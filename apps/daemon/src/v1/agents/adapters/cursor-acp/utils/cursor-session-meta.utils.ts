import { readFileSync, statSync } from 'node:fs';

/**
 * How much of that header this will read before giving up.
 *
 * Generous for a three-key JSON object and small enough that a corrupt or
 * vendor-grown file cannot be pulled into memory whole on the daemon's event
 * loop. The claude session reader bounds its own vendor-file read for the same
 * reason, at its own budget.
 */
const META_MAX_BYTES = 256 * 1024;

/**
 * The title this CLI gave one of its own ACP conversations, read off the session
 * store it keeps on disk.
 *
 * `<sessionId>/meta.json` is a flat JSON header the agent rewrites as the
 * conversation goes — `{"schemaVersion":1,"cwd":"…","title":"Fix Conflicts
 * Worktree"}` — and the title in it is GENERATED by the agent, which is the one
 * thing no scan of the transcript could produce. Observed 2026-08-22 on
 * 2026.08.11-e8db854 across geniro's own store: three of four sessions carried
 * one, the fourth (a one-word exchange) did not, so absence is ordinary and not
 * an error.
 *
 * Read in preference to ACP `session/list`, which returns the same field: that
 * is a two-frame handshake against a spawned `cursor-agent acp` process, and the
 * caller here already knows exactly which session it is asking about. Spawning a
 * CLI to re-read a file geniro's own turns just wrote is seconds spent for a
 * string sitting on disk.
 *
 * Synchronous, like `readCursorContextUsage` beside it and for the same reason:
 * it is a single small file, and the callers are already inside an async hop.
 * Read-only and failure-swallowing by construction — geniro owns this directory
 * but not the format, so a missing file, a schema that has moved and unreadable
 * bytes are all one answer: null.
 */
export function readCursorSessionTitle(
  path: string,
  warn?: (message: string) => void,
): string | null {
  let parsed: unknown;
  try {
    const info = statSync(path);
    // TYPE as well as size. `readFileSync` is synchronous on the daemon's one
    // event loop, so a FIFO here does not cost a title — it wedges every route,
    // turn and WS frame for good, which is the opposite of what the ceiling was
    // added for. A named pipe reports `size: 0` and sails past a size check.
    // Reachable without any privilege gain: `prepareSessionImport` copies the
    // user's own cursor store with `cp`, which preserves symlinks by default.
    if (!info.isFile() || info.size > META_MAX_BYTES) {
      warn?.(
        `cursor session meta at ${path} is not a readable header — skipping it`,
      );
      return null;
    }
    parsed = JSON.parse(readFileSync(path, 'utf8'));
  } catch (err) {
    // The ERROR CLASS, never its message: V8's parse errors quote the first
    // bytes of the file back, and this line reaches the debug log and its WS
    // room — where redaction covers registered secrets and not a stranger's
    // file contents.
    warn?.(
      `could not read cursor session meta at ${path}: ${
        err instanceof Error ? err.name : 'unknown error'
      }`,
    );
    return null;
  }
  if (typeof parsed !== 'object' || parsed === null) {
    return null;
  }
  const { title } = parsed as Record<string, unknown>;
  if (typeof title !== 'string') {
    return null;
  }
  const trimmed = title.trim();
  return trimmed === '' ? null : trimmed;
}
