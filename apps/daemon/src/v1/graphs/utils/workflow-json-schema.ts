import { z } from 'zod';

import { WorkflowSchema } from '../graphs.types';

/**
 * The file name the workflow library's JSON Schema is written under, beside
 * the `*.geniro.yaml` files it describes. A dotfile, so it stays out of a
 * Finder window and out of the store's own listing (which reads only the
 * workflow suffix).
 */
export const WORKFLOW_SCHEMA_FILE_NAME = '.workflow.schema.json';

/**
 * The workflow document's structure as JSON Schema — every field, its type,
 * its bounds and its one-line description — GENERATED from `WorkflowSchema`,
 * the schema the daemon itself validates and writes through.
 *
 * This is the reference the builder's chat agent is pointed at instead of a
 * field list restated in prose: a prose list drifts the first time a field is
 * added (the brief this replaced never learned about `pool` or
 * `mcpDisabled`), while a document produced from the validator cannot say
 * anything the validator does not.
 *
 * The STRICT schema rather than `WorkflowYamlSchema`: a file satisfying it is
 * always accepted by the lenient one, and it is the shape the builder writes,
 * so an agent following it never leans on a default the canvas would then
 * spell out on its next save. What JSON Schema cannot carry — the graph rules
 * over the edge list — the brief renders from `NODE_CONNECTION_RULES` instead.
 */
export function workflowJsonSchema(): string {
  const schema = z.toJSONSchema(WorkflowSchema, { io: 'input' });
  return `${JSON.stringify(
    {
      ...schema,
      title: 'geniro workflow (*.geniro.yaml)',
      $comment:
        'Generated by the geniro daemon from the schema it validates workflows with; rewritten whenever a workflow chat opens. Do not edit.',
    },
    null,
    2,
  )}\n`;
}
