import { z } from 'zod';

import { TeamSchema } from '../teams.types';

/**
 * The file name the team library's JSON Schema is written under, beside
 * the `*.team.yaml` files it describes. A dotfile, so it stays out of a
 * Finder window and out of the store's own listing (which reads only the
 * team suffix).
 */
export const TEAM_SCHEMA_FILE_NAME = '.team.schema.json';

/**
 * The team document's structure as JSON Schema — every field, its type,
 * its bounds and its one-line description — GENERATED from `TeamSchema`,
 * the schema the daemon itself validates and writes through.
 *
 * This is the reference the builder's chat agent is pointed at instead of a
 * field list restated in prose: a prose list drifts the first time a field is
 * added (the brief this replaced never learned about `pool` or
 * `mcpDisabled`), while a document produced from the validator cannot say
 * anything the validator does not.
 *
 * The STRICT schema rather than `TeamYamlSchema`: a file satisfying it is
 * always accepted by the lenient one, and it is the shape the builder writes,
 * so an agent following it never leans on a default the team editor would then
 * spell out on its next save. What JSON Schema cannot carry — the ids one
 * part names in another (a trigger's member, a block's audience, a stage's
 * responsible members) — `validateTeam` checks, and the brief states.
 */
export function teamJsonSchema(): string {
  const schema = z.toJSONSchema(TeamSchema, { io: 'input' });
  return `${JSON.stringify(
    {
      ...schema,
      title: 'geniro team (*.team.yaml)',
      $comment:
        'Generated by the geniro daemon from the schema it validates teams with; rewritten whenever a team chat opens. Do not edit.',
    },
    null,
    2,
  )}\n`;
}
