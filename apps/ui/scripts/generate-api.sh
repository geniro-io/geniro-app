#!/usr/bin/env bash
# Regenerate the renderer's daemon client from the daemon's OpenAPI document.
#
# The sibling Geniro web app runs the same two steps against a fixed swagger
# URL; here step 1 resolves the spec from a running daemon (or boots a
# throwaway one) because the loopback daemon negotiates its port and token.
# See scripts/openapi-spec.mjs.
#
# The output is COMMITTED — builds and CI never run this; a developer runs it
# after changing a daemon route or wire schema, and the diff is reviewed.
set -euo pipefail

cd "$(dirname "$0")/.."

SPEC="$(mktemp -t geniro-openapi)"
trap 'rm -f "$SPEC"' EXIT

node ./scripts/openapi-spec.mjs "$SPEC"

rm -rf ./src/renderer/autogenerated

pnpm openapi-generator-cli generate \
  -i "$SPEC" \
  -g typescript-fetch \
  -o ./src/renderer/autogenerated \
  --additional-properties=supportsES6=true,withoutRuntimeChecks=true,prefixParameterInterfaces=true \
  --global-property=models,apis,supportingFiles,modelDocs=false,apiDocs=false
