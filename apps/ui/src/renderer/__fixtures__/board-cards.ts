import type { CommandCenterCard } from '../autogenerated';

/** A board card for specs and stories: a plain finished-or-not chat thread, overridable. */
export function boardCard(
  runId: string,
  {
    column = 'idle',
    status = 'completed',
    lastActivityAt = '2026-11-27T10:00:00.000Z',
    finishKey = column === 'done' ? `fk-${runId}` : null,
    title = `Thread ${runId}`,
    report = column === 'done' ? `${title} shipped its change.` : null,
  }: {
    column?: CommandCenterCard['column'];
    status?: string;
    lastActivityAt?: string;
    finishKey?: string | null;
    title?: string;
    report?: string | null;
  } = {},
): CommandCenterCard {
  return {
    run: {
      id: runId,
      title,
      createdAt: '2026-11-27T09:00:00.000Z',
      lastActivityAt,
      status,
      awaiting: null,
      teamId: null,
      agentKind: 'claude',
      project: null,
      pullRequests: [],
    },
    column,
    contact: { lastAt: null, awaitingReply: false },
    task: null,
    handle: null,
    note: null,
    activity: null,
    report,
    finishKey,
  } as unknown as CommandCenterCard;
}
