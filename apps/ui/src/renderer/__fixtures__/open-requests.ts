import type { ItemDto } from '../autogenerated';
import type { OpenRequest } from '../command-center/use-open-requests';

/** An open question or approval card as a thread's run state holds it. */
export function openRequest(
  runId: string,
  requestId: string,
  payload: Record<string, unknown>,
  { title = `Thread ${runId}`, createdAt = '2026-11-27T10:00:00.000Z' } = {},
): OpenRequest {
  return {
    runId,
    title,
    isTeam: false,
    requestId,
    item: {
      id: `item-${requestId}`,
      runId,
      kind: 'approval_request',
      createdAt,
      payload: { id: requestId, ...payload },
    } as unknown as ItemDto,
  };
}

const COLOUR_QUESTIONS = [
  {
    question: 'Which colour do you want?',
    header: 'Colour',
    options: [
      { label: 'Red', description: 'Warm and loud' },
      { label: 'Blue', description: 'Calm and quiet' },
    ],
  },
];

/** A thread asking the user to pick one of two options. */
export function questionRequest(
  runId: string,
  requestId: string,
  options?: Parameters<typeof openRequest>[3],
): OpenRequest {
  return openRequest(
    runId,
    requestId,
    {
      toolName: 'AskUserQuestion',
      input: { questions: COLOUR_QUESTIONS },
      questions: COLOUR_QUESTIONS,
    },
    options,
  );
}

/** A thread holding a shell command for a yes or a no. */
export function approvalRequest(
  runId: string,
  requestId: string,
  options?: Parameters<typeof openRequest>[3],
): OpenRequest {
  return openRequest(
    runId,
    requestId,
    { toolName: 'Bash', input: { command: 'ls' } },
    options,
  );
}
