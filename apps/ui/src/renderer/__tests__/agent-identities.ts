import type {
  AgentIconName,
  AgentIdentityCapability,
  AgentKind,
} from '../autogenerated';

/**
 * One published identity. `displayName` differs from `shortName` on purpose, so
 * code that read the wrong field would not pass by coincidence — and neither
 * equals the agent's kind (the binary name).
 */
export function identity(
  agent: AgentKind,
  shortName: string,
  icon: AgentIconName,
): AgentIdentityCapability {
  return {
    agent,
    displayName: `${shortName} (long name)`,
    shortName,
    summary: '',
    details: [],
    icon,
    callerEscalatesQuestions: false,
  };
}

/**
 * The three shipped CLIs, shaped as `GET /v1/capabilities` shapes them but
 * named and drawn so that no field can stand in for another: the short names
 * are capitalised — as published, `claude` and `codex` equal their kinds, which
 * would let a label read from the wrong field pass — and each glyph differs.
 */
export const PUBLISHED_IDENTITIES: readonly AgentIdentityCapability[] = [
  identity('claude', 'Claude', 'bot'),
  identity('cursor-agent', 'Cursor', 'terminal'),
  identity('codex', 'Codex', 'code'),
];
