import { vi } from 'vitest';

import type {
  AgentContextWindowListing,
  AgentEffortListing,
  AgentModel,
  AgentModelParameterListing,
  AgentsApiListAgentVocabularyRequest,
  AgentVocabularyDto,
} from '../autogenerated';

type Question = AgentsApiListAgentVocabularyRequest;

/**
 * A spec's answer to each PART of the vocabulary, under the name of the route
 * that part used to have — what a spec actually varies and asserts on.
 */
export interface VocabularyParts {
  listAgentModels?: (
    question: Omit<Question, 'model'>,
  ) => Promise<AgentModel[]>;
  listAgentEfforts?: (question: Question) => Promise<AgentEffortListing>;
  listAgentContextWindows?: (
    question: Question,
  ) => Promise<AgentContextWindowListing>;
  listAgentModelParameters?: (
    question: Question,
  ) => Promise<AgentModelParameterListing>;
}

/**
 * `listAgentVocabulary` built out of a spec's per-part answers, the way the
 * daemon builds it out of its four services (`AgentVocabularyService`).
 *
 * `parts` is read AT CALL TIME, so a spec that swaps one with
 * `mockImplementation` after setup is answered by the swap. Each part is asked
 * the question the request carries — the model list without the model, which
 * it never depended on. A part that rejects answers `null`, and the whole
 * request rejects when every part did, exactly as the daemon does; a part the
 * spec does not supply answers an empty listing.
 */
export function vocabularyFrom(parts: VocabularyParts) {
  return vi.fn(async (question: Question): Promise<AgentVocabularyDto> => {
    const { model: _model, ...withoutModel } = question;
    const settled = await Promise.allSettled([
      parts.listAgentModels?.(withoutModel) ?? Promise.resolve([]),
      parts.listAgentEfforts?.(question) ??
        Promise.resolve({ efforts: [], unavailableReason: null }),
      parts.listAgentContextWindows?.(question) ??
        Promise.resolve({
          windows: [],
          unavailableReason: null,
          unavailableKind: null,
        }),
      parts.listAgentModelParameters?.(question) ??
        Promise.resolve({ parameters: [], unavailableReason: null }),
    ]);
    if (settled.every((part) => part.status === 'rejected')) {
      throw (settled[0] as PromiseRejectedResult).reason;
    }
    const value = <T>(part: PromiseSettledResult<T>): T | null =>
      part.status === 'fulfilled' ? part.value : null;
    return {
      models: value(settled[0]),
      efforts: value(settled[1]),
      contextWindows: value(settled[2]),
      modelParameters: value(settled[3]),
    };
  });
}

/**
 * `api` with a `listAgentVocabulary` answered from its own per-part members —
 * the SAME object, so a spec relying on the client's identity keeps it.
 */
export function withVocabulary<T extends object>(
  api: T & VocabularyParts,
): T & { listAgentVocabulary: ReturnType<typeof vocabularyFrom> } {
  return Object.assign(api, { listAgentVocabulary: vocabularyFrom(api) });
}
