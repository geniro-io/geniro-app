import type { ChatTotals } from '../autogenerated';

/**
 * A `ChatTotals` in which no turn reported anything — the daemon's own "not
 * measured" shape, for fixtures whose subject is not the spend.
 */
export const NO_TOTALS: ChatTotals = {
  turns: 0,
  costedTurns: 0,
  costUsd: null,
  inputTokens: null,
  outputTokens: null,
  cacheReadTokens: null,
  cacheCreationTokens: null,
  thinkingTokens: null,
  workedMs: null,
};

/** Totals over `turns` turns, carrying only the figures a fixture names. */
export function totals(
  figures: Partial<ChatTotals> & { turns: number },
): ChatTotals {
  return { ...NO_TOTALS, ...figures };
}
