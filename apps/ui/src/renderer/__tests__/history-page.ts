import type { ChatHistoryDto, ItemDto } from '../autogenerated';

/**
 * A `listRunItems` reply as the route answers it — `{ items, anchors }`. A spec
 * that wrote the page as a bare array of rows meant a page with no anchors, so
 * that is what an array becomes; a spec exercising anchors returns the object.
 */
export function asHistoryPage(value: unknown): ChatHistoryDto {
  if (Array.isArray(value)) {
    return { items: value as ItemDto[], anchors: [] };
  }
  return value as ChatHistoryDto;
}

/**
 * `api` with its `listRunItems` answering pages, while the spy a spec
 * configures and asserts on stays the one it holds. The spy is read at CALL
 * time, so a `mockResolvedValue` set after this wraps still applies.
 */
export function withHistoryPages<T extends { listRunItems: unknown }>(
  api: T,
): T {
  const rows = api.listRunItems as (...args: unknown[]) => unknown;
  return {
    ...api,
    listRunItems: (...args: unknown[]) =>
      Promise.resolve(rows(...args)).then(asHistoryPage),
  };
}
