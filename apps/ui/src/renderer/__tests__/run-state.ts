import type { RunStateDto } from '../autogenerated';

/** A run that holds nothing as a whole — for an api double a surface reads run state from. */
export function emptyRunState(): RunStateDto {
  return {
    openRequests: [],
    calls: [],
    delegates: [],
    workflowRows: [],
    artifactRows: [],
    shells: [],
    monitors: [],
    actions: [],
    openToolCalls: [],
    throughSeq: -1,
    turnStartedAt: null,
  };
}
