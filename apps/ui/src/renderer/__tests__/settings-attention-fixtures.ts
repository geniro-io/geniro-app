import type {
  CliDetection,
  CliKind,
  UpdateState,
} from '../../shared/contracts';
import type { Share } from '../autogenerated';

export function detection(
  kind: CliKind,
  overrides: Partial<CliDetection> = {},
): CliDetection {
  return {
    kind,
    found: true,
    path: `/bin/${kind}`,
    version: '1.0.0',
    loggedIn: true,
    update: {
      available: null,
      latestVersion: null,
      checkUnavailableReason: null,
    },
    ...overrides,
  };
}

export function updateAvailable(latestVersion: string): CliDetection['update'] {
  return { available: true, latestVersion, checkUnavailableReason: null };
}

export function waitingShare(
  id: string,
  destinationId: string,
  label: string,
  status: Share['status'] = 'awaiting-sign-in',
): Share {
  return {
    id,
    destinationId,
    destinationName: label,
    status,
    signIn: { cli: 'gcloud', label },
  } as Share;
}

export function updateState(overrides: Partial<UpdateState>): UpdateState {
  return {
    phase: 'idle',
    version: '2.0.0',
    progress: null,
    message: null,
    failedPhase: null,
    currentVersion: '1.0.0',
    canInstall: true,
    ...overrides,
  };
}
