import type {
  RunWaterfallCall,
  RunWaterfallDto,
  RunWaterfallLane,
  RunWaterfallTurn,
  RunWaterfallWait,
} from '../autogenerated';

/**
 * Builders for the waterfall wire, shared by the specs of its pure folds
 * (breakdown, insights). Every time is in SECONDS after `WATERFALL_FROM`, so a
 * spec reads as a timeline rather than as ISO strings.
 */

export const WATERFALL_FROM = Date.parse('2026-09-07T12:00:00.000Z');

export function atSecond(seconds: number): string {
  return new Date(WATERFALL_FROM + seconds * 1000).toISOString();
}

export function wfLane(
  nodeId: string | null,
  over: Partial<RunWaterfallLane> = {},
): RunWaterfallLane {
  return {
    nodeId,
    agentKind: 'claude',
    costUsd: null,
    estimatedCostUsd: null,
    turns: 1,
    toolCalls: 0,
    delegateToolCalls: 0,
    workedMs: null,
    ...over,
  };
}

export function wfTurn(
  nodeId: string | null,
  start: number,
  end: number,
  over: Partial<RunWaterfallTurn> = {},
): RunWaterfallTurn {
  return {
    nodeId,
    startedAt: atSecond(start),
    seq: 1,
    timingSource: 'cli',
    outcome: 'completed',
    toolCalls: 0,
    delegateToolCalls: 0,
    durationMs: (end - start) * 1000,
    apiMs: null,
    ttftMs: null,
    timeToRequestMs: null,
    numTurns: null,
    costUsd: null,
    estimatedCostUsd: null,
    model: null,
    member: null,
    inputTokens: null,
    outputTokens: null,
    cacheReadTokens: null,
    contextTokens: null,
    contextWindowTokens: null,
    modelCosts: null,
    ...over,
  };
}

export function wfCall(
  callerNodeId: string,
  calleeNodeId: string,
  start: number,
  end: number,
  over: Partial<RunWaterfallCall> = {},
): RunWaterfallCall {
  return {
    callerNodeId,
    calleeNodeId,
    mode: 'async',
    status: 'ok',
    running: false,
    startedAt: atSecond(start),
    seq: 1,
    durationMs: (end - start) * 1000,
    ...over,
  };
}

export function wfWait(
  nodeId: string | null,
  start: number,
  end: number,
): RunWaterfallWait {
  return {
    nodeId,
    question: false,
    toolName: 'Bash',
    allowed: true,
    startedAt: atSecond(start),
    seq: 1,
    durationMs: (end - start) * 1000,
  };
}

export function wfDto(
  seconds: number,
  over: Partial<RunWaterfallDto> = {},
): RunWaterfallDto {
  return {
    from: atSecond(0),
    to: atSecond(seconds),
    lanes: [],
    toolUse: [],
    turns: [],
    calls: [],
    waits: [],
    delegates: [],
    criticalPath: [],
    totals: {
      turns: 0,
      costedTurns: 0,
      costUsd: null,
      estimatedCostUsd: null,
      inputTokens: null,
      outputTokens: null,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      thinkingTokens: null,
      workedMs: null,
    },
    waitedOnUserMs: null,
    partialReason: null,
    ...over,
  };
}
