import { createContext } from 'react';

import type {
  AgentIconName,
  AgentIdentityCapability,
  AgentKind,
} from './autogenerated';

/**
 * Every registered CLI's identity, exactly as `GET /v1/capabilities` reports
 * it — display name, one-word short name, icon, summary. This is the ONE
 * place the renderer learns which agents exist and what to call them; nothing
 * downstream hardcodes a CLI name or a per-agent glyph.
 *
 * Defaults to an empty list, which every reader must treat as "not answered
 * yet" rather than "no agents exist" — the same fail-open reading
 * `useCapabilities` itself takes on a failed or not-yet-landed read. Provided
 * by `App` around the shell, and by `Onboarding` from the `identities` it is
 * handed, since that screen renders in the shell's place; a spec rendering a
 * reader on its own provides it itself.
 */
export const AgentIdentityContext = createContext<
  readonly AgentIdentityCapability[]
>([]);

/**
 * The one-word label a CLI is called by, wherever a row of chrome has room
 * for a single word — a sidebar row's labels, a call block's name line.
 *
 * Falls back to the kind string itself — the daemon's own wire name for it —
 * before capabilities have loaded or for a kind the daemon did not report,
 * rather than guessing at a shortening a future CLI might want.
 */
export function agentShortName(
  identities: readonly AgentIdentityCapability[],
  kind: AgentKind | string,
): string {
  return (
    identities.find((identity) => identity.agent === kind)?.shortName ?? kind
  );
}

/**
 * The glyph a CLI is drawn with. The generic `bot` before capabilities have
 * loaded or for a kind the daemon did not report — the same not-a-guess
 * reading {@link agentShortName} takes for the name.
 */
export function agentIconName(
  identities: readonly AgentIdentityCapability[],
  kind: AgentKind | string,
): AgentIconName {
  return identities.find((identity) => identity.agent === kind)?.icon ?? 'bot';
}
