// A fake DaemonClient whose item/reconnect listeners the test can fire.
function makeClient(): {
  client: DaemonClient;
  emitItem: (item: ChatItem) => void;
  fireDisconnect: () => void;
  fireReconnect: () => void;
  fireVerdictAck: (ack: VerdictAck) => void;
  emitLiveText: (event: LiveTextEvent) => void;
  joinRun: ReturnType<typeof vi.fn>;
} {
  let itemListener: ((item: ChatItem) => void) | null = null;
  let reconnectListener: ((error?: Error) => void) | null = null;
  let disconnectListener: (() => void) | null = null;
  let verdictAckListener: ((ack: VerdictAck) => void) | null = null;
  let liveTextListener: ((event: LiveTextEvent) => void) | null = null;
  const joinRun = vi.fn(async () => {});
  const client = {
    onItem: (l: (item: ChatItem) => void) => {
      itemListener = l;
      return () => {
        itemListener = null;
      };
    },
    onReconnect: (l: (error?: Error) => void) => {
      reconnectListener = l;
      return () => {
        reconnectListener = null;
      };
    },
    onDisconnect: (l: () => void) => {
      disconnectListener = l;
      return () => {
        disconnectListener = null;
      };
    },
    onLiveText: (l: (event: LiveTextEvent) => void) => {
      liveTextListener = l;
      return () => {
        liveTextListener = null;
      };
    },
    onVerdictAck: (l: (ack: VerdictAck) => void) => {
      verdictAckListener = l;
      return () => {
        verdictAckListener = null;
      };
    },
    joinRun,
    leaveRun: vi.fn(),
    sendVerdict: vi.fn(),
  } as unknown as DaemonClient;
  return {
    client,
    emitItem: (item) => itemListener?.(item),
    fireDisconnect: () => disconnectListener?.(),
    fireReconnect: () => reconnectListener?.(),
    fireVerdictAck: (ack) => verdictAckListener?.(ack),
    emitLiveText: (event) => liveTextListener?.(event),
    joinRun,
  };
}

const roots: Root[] = [];

async function mount(client: DaemonClient): Promise<HTMLElement> {
  const container = document.createElement('div');
  document.body.appendChild(container);
  const root = createRoot(container);
  roots.push(root);
  await act(async () => {
    root.render(<Chats client={client} handle={handle} />);
  });
  return container;
}

async function clickRun(container: HTMLElement, title: string): Promise<void> {
  const li = [...container.querySelectorAll('li')].find((el) =>
    el.textContent?.includes(title),
  );
  // The row's activation surface is its overlay button (the li's first child).
  const activate = li?.querySelector<HTMLButtonElement>('button');
  await act(async () => {
    activate?.click();
  });
}

/** The composer's round icon actions, looked up by their accessible name. */
/** An element's class list as exact tokens (substring checks lie about `shrink-0`). */
function classesOf(el: Element): string[] {
  return (el.getAttribute('class') ?? '').split(/\s+/).filter(Boolean);
}

function composerButton(
  container: HTMLElement,
  label: 'Send' | 'Stop' | 'Queue',
): HTMLButtonElement | null {
  return container.querySelector<HTMLButtonElement>(
    `button[aria-label="${label}"]`,
  );
}

/** The composer's target picker. The menu is OURS, so its rows are real DOM. */
function targetTrigger(container: HTMLElement): HTMLButtonElement {
  return container.querySelector<HTMLButtonElement>(
    '[data-menu-trigger][aria-label="Agent or workflow for new runs"]',
  )!;
}

/** Open a composer menu and click the row with this exact label. */
async function pickMenuRow(
  container: HTMLElement,
  trigger: HTMLButtonElement,
  rowText: string,
): Promise<void> {
  await act(async () => {
    trigger.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
  const row = [
    ...container.querySelectorAll<HTMLElement>('[role="option"]'),
  ].find((o) => o.textContent === rowText);
  if (!row) {
    throw new Error(`no menu row labelled "${rowText}"`);
  }
  await act(async () => {
    row.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

/** Read a menu's rows without committing to one (open, read, close). */
async function menuRows(
  container: HTMLElement,
  trigger: HTMLButtonElement,
): Promise<string[]> {
  const toggle = async (): Promise<void> => {
    await act(async () => {
      trigger.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
  };
  await toggle();
  const rows = [...container.querySelectorAll('[role="option"]')].map(
    (o) => o.textContent ?? '',
  );
  await toggle();
  return rows;
}

