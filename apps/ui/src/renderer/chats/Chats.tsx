  // the shared attachment reader, then that composer's own git read — and the
  // strip is rendered from exactly this value, so a lone attachment failure
  // cannot be computed into the text of a strip whose visibility never
  // considered it (it was, and stayed invisible).
  const composerError = error ?? attachments.error ?? git.error;
  const transcriptError = error ?? attachments.error;
  /**
   * Close the strip. Every source is cleared, not just the one on top: they are
   * layered, so clearing only `error` would swap one stale failure for an older
   * one and read as a close button that does not close.
   */
  const dismissError = (): void => {
    setError(null);
    attachments.clearError();
    git.clearError();
  };
  const skillQuery = slashQuery(input);
  const skillMatches = useMemo(
    () => (skillQuery === null ? [] : filterSkills(skills, skillQuery)),
    [skills, skillQuery],
  );
  const [skillHighlight, setSkillHighlight] = useState(0);
  // The one query string Escape dismissed — editing the token re-opens.
  const [dismissedQuery, setDismissedQuery] = useState<string | null>(null);
  useEffect(() => setSkillHighlight(0), [skillQuery]);
  const skillMenuOpen =
    skillQuery !== null &&
    skillQuery !== dismissedQuery &&
    skillMatches.length > 0;
  // Narrowing the query can shrink the list under the highlight — clamp.
  const highlightedIndex = Math.min(skillHighlight, skillMatches.length - 1);
  const pickSkill = useCallback((skill: AgentSkill): void => {
    // `/name ` no longer parses as a bare slash token, so picking closes
    // the menu by construction; the caret lands ready for arguments.
    setInput(applySkill(skill));
  }, []);
  /** Menu-first key protocol for both composer textareas; true = consumed. */
  const handleSkillMenuKeys = (
    event: React.KeyboardEvent<HTMLTextAreaElement>,
  ): boolean => {
    if (!skillMenuOpen) {
      return false;
    }
    if (event.key === 'ArrowDown' || event.key === 'ArrowUp') {
      event.preventDefault();
      const delta = event.key === 'ArrowDown' ? 1 : -1;
      setSkillHighlight(
        (highlightedIndex + delta + skillMatches.length) % skillMatches.length,
      );
      return true;
    }
    if (
      event.key === 'Tab' ||
      (event.key === 'Enter' &&
        !event.metaKey &&
        !event.ctrlKey &&
        !event.shiftKey)
    ) {
      event.preventDefault();
      const highlighted = skillMatches[highlightedIndex];
      if (highlighted) {
        pickSkill(highlighted);
      }
      return true;
    }
    if (event.key === 'Escape') {
      event.preventDefault();
      setDismissedQuery(skillQuery);
      return true;
    }
    return false;
  };

  // The active workflow's node inventory: its agent nodes (the agents panel),
  // its triggers (the run composer's inactive info chips), and every node id
  // it knows (so trigger status items are never mistaken for an unknown
  // agent's).
  const [wfNodes, setWfNodes] = useState<{
    agents: WorkflowAgentNode[];
    triggers: WorkflowTriggerNode[];
    allIds: Set<string>;
  }>({ agents: [], triggers: [], allIds: new Set() });
  /**
   * Set when the active run's workflow is GONE from the library (a 404, not a
   * failed request) — the run's own history survives it, so the transcript
   * stays readable, but nothing about it can be recovered and every panel that
   * reads the graph stays empty. The banner turns that dead end into the one
   * action that resolves it: delete the run.
   */
  const [missingWorkflow, setMissingWorkflow] = useState<string | null>(null);
  useEffect(() => {
    let cancelled = false;
    const workflowId = activeRun?.workflowId;
    setMissingWorkflow(null);
    if (!workflowId) {
      setWfNodes({ agents: [], triggers: [], allIds: new Set() });
      return;
    }
    void workflowApi
      .getWorkflow({ slug: workflowId })
      .then(({ workflow }) => {
        if (cancelled) {
          return;
        }
        setWfNodes({
          agents: workflow.nodes.filter(
            (node): node is WorkflowAgentNode => node.kind === 'agent',
          ),
          triggers: workflow.nodes.filter(
            (node): node is WorkflowTriggerNode => node.kind === 'trigger',
          ),
          allIds: new Set(workflow.nodes.map((node) => node.id)),
        });
      })
      .catch((err: unknown) => {
        if (cancelled) {
          return;
        }
        setWfNodes({ agents: [], triggers: [], allIds: new Set() });
        // A deleted workflow is not a failure to report as one: the request
        // worked, the graph is simply gone. Say that in the user's terms and
        // let the banner offer the way out, instead of pasting a 404 body
        // under a caption about "terminal targets".
        if (daemonErrorStatus(err) === 404) {
          setMissingWorkflow(workflowId);
          setError(
            `The workflow “${workflowId}” is no longer in your library, so this run's agents and terminals cannot be loaded. Its transcript above is all that is left of it.`,
          );
          return;
        }
        setError(
          `Could not load workflow terminal targets: ${err instanceof Error ? err.message : String(err)}`,
        );
      });
    return () => {
      cancelled = true;
    };
  }, [activeRun?.workflowId, workflowApi]);
  // Node display metadata for the transcript (names + kinds), and the
  // transcript folded into render entries — consecutive tool calls collapse
  // into expandable groups.
  const nodeMeta = useMemo(() => {
    const map = new Map<string, TranscriptNodeMeta>();
    for (const node of wfNodes.agents) {
      map.set(node.id, { name: node.name ?? node.id, kind: 'agent' });
    }
    for (const node of wfNodes.triggers) {
      map.set(node.id, { name: node.name ?? node.id, kind: 'trigger' });
    }
    return map;
  }, [wfNodes]);
  // Live per-agent state for the agents panel, derived purely from the
  // transcript (status items count parallel turns; call items list threads;
  // turn_complete usage carries context/spend).
  const activity = useMemo(() => computeAgentActivity(items), [items]);
  /**
   * Each agent's OWN task list as it stands now, for the side panel.
   *
   * The panel and not the composer: it is the same kind of derived, per-agent
   * state as the delegate list beside it, and it belongs where a reader already
   * looks for "what is this agent doing". The transcript cards stay as the
   * history of the list moving, exactly as a sub-agent has both a block in the
   * flow and a row in the panel.
   *
   * Keyed by node id (`null` for a 1:1 chat), and a delegate's rows are excluded
   * — its list lives in its own block, whose header carries its count.
   */
  const tasksByAgent = useMemo(() => {
    // Re-keyed to the PANEL's agent ids here rather than in the fold: a 1:1
    // chat's rows carry `nodeId: null` while its agent card is keyed by
    // `CHAT_AGENT_KEY`, and that mapping is this screen's own — the fold has no
    // business knowing it.
    const byAgent = new Map<string, AgentTaskRow[]>();
    for (const [nodeId, tasks] of taskListsByAgent(items, subagentIdOf)) {
      byAgent.set(nodeId ?? CHAT_AGENT_KEY, tasks);
    }
    return byAgent;
  }, [items]);
  /**
   * The agents whose turn is in flight — the transcript draws each of them a
   * row even when they have nothing to say yet, so the flow never goes silent
   * between a tool batch and the next words.
   *
   * A chat's one agent is running when the run is; a workflow node is running
   * when it has an unsettled turn. Both are read from state the transcript
   * already derives, so nothing new has to be tracked to answer it.
   */
  const workingAgents = useMemo(() => {
    const keys = new Set<string>();
    if (!activeRun) {
      return keys;
    }
    if (!activeRun.workflowId) {
      if (streaming || activeRun.status === 'running') {
        keys.add(CHAT_LIVE_KEY);
      }
    } else {
      for (const [nodeId, nodeActivity] of activity) {
        if (nodeId !== CHAT_AGENT_KEY && nodeActivity.activeTurns > 0) {
          keys.add(nodeId);
        }
      }
    }
    // An agent parked on a question is NOT working — it is waiting on the
    // person reading the card. Its turn is genuinely still in flight, so every
    // signal above says "running", and the fallback drew a spinning
    // "Working… 4m 12s" directly under the question it was waiting for an
    // answer to. Removing it leaves the card as the only thing on screen,
    // which is the truth: nothing moves until it is answered.
    for (const key of awaitingAnswer) {
      keys.delete(key);
    }
    return keys;
  }, [activeRun, activity, awaitingAnswer, streaming]);
  /**
   * The badge for the run currently on screen.
   *
   * Only the ACTIVE run gets this treatment, and that is a limit of what is
   * knowable rather than an oversight: `streaming` and `awaitingAnswer` are both
   * derived from the open transcript's items, and the renderer holds no items
   * for a chat it is not looking at. A background row keeps the daemon's own
   * status, which the client-wide `run_status` broadcast already keeps honest.
   */
  /**
   * The DURABLE fold, memoized on the items alone.
   *
   * Kept separate from the live overlay below on purpose. Folding both in one
   * memo rebuilt every block, tool group and call block object on each delta —
   * several times a second while streaming — so every memoized child got fresh
   * prop identity and the whole transcript re-rendered, which is the visible
   * blink. `withLiveText` copies only the ONE block it appends to, so with the
   * fold held stable here every other block keeps its identity and its memo.
   *
   * Ordered before the badge below because the badge READS it: whether a
   * background sub-agent is still working is a fact about the folded
   * transcript, not one the run row carries.
   */
  const durableEntries = useMemo(
    () => buildTurnBlocks(buildSubagentBlocks(groupTranscript(items), items)),
    [items],
  );
  /**
   * The run STOPPED for a reason that outranks a delegate still being out.
   *
   * Only `failed` and `cancelled` — deliberately NOT every settled status, and
   * not `isSettledRunStatus`. A `completed` row is exactly the stale value
   * this whole signal exists to override (`displayRunStatus` documents the
   * three writers that produce it), so treating it as a stop would let the
   * badge suppress itself and the feature would do nothing. The two kept here
   * are the same two `displayRunStatus` refuses to override for `streaming`,
   * for the same reason: both are genuine settle paths, and a cancelled run is
   * precisely where a delegate's last rows are still landing with no turn-end
   * item to close it.
   */
  const runRowStopped =
    activeRun?.status === 'failed' || activeRun?.status === 'cancelled';
  /**
   * WHEN it stopped, which is what a delegate's status is actually read
   * against — see {@link subagentBlockStatus}. The run row's own `updatedAt` is
   * the settle moment and not merely the newest thing about the run: items do
   * not touch that row, so it stands still while a delegate keeps writing
   * (measured — run `d8cb70c0` carries an `updatedAt` 149s BEFORE its own last
   * item), which is exactly the gap that makes "has this delegate spoken
   * since?" answerable.
   */
  /**
   * WHEN a run that HAS stopped stopped — the later of its own terminal item and
   * the row's timestamp, or `'unknown'` when neither can be read.
   *
   * The two together, never the row alone: items do not touch `updatedAt`, so a
   * row can be older than the stop it describes and a row written in that gap
   * then reads as "produced after the run settled" — see
   * {@link lastTerminalItemAt} for the measurement. And never the item alone: a
   * settle path that writes none still has to answer.
   */
  const settleMomentOf = useCallback(
    (run: ChatRun | null, rows: readonly ChatItem[]): RunSettleAt => {
      const rowAt = run ? Date.parse(run.updatedAt) : Number.NaN;
      const itemAt = lastTerminalItemAt(rows);
      const known = [rowAt, itemAt].filter(
        (at): at is number => at !== null && Number.isFinite(at),
      );
      // `'unknown'` and not null when nothing is readable: the run DID stop, and
      // losing that fact would put every spinner back — see {@link RunSettleAt}.
      return known.length === 0 ? 'unknown' : Math.max(...known);
    },
    [],
  );
  const runStoppedAt = useMemo(
    () => (runRowStopped ? settleMomentOf(activeRun, items) : null),
    [runRowStopped, activeRun, items],
  );
  const subagentRunning = useMemo(
    () =>
      collectSubagentBlocks(durableEntries).some(
        (block) => subagentBlockStatus(block, runStoppedAt) === 'running',
      ),
    [durableEntries, runStoppedAt],
  );
  const activeRunStatus = useMemo(
    () =>
      activeRun
        ? displayRunStatus({
            status: activeRun.status,
            streaming,
            awaitingAnswer: awaitingAnswer.size > 0,
            subagentRunning,
          })
        : 'idle',
    [activeRun, streaming, awaitingAnswer, subagentRunning],
  );
  /**
   * The settle moment the transcript reads — WHEN this run stopped, or null
   * while it has not.
   *
   * Broader than {@link runStoppedAt} on purpose, and the two must not be
   * merged: that one answers "did the run stop for a reason that outranks a
   * delegate still being out", so it deliberately excludes `completed`; this
   * one drives the blocks themselves, where a completed run genuinely does end
   * a tool call that never returned. What both now share is that a settle is a
   * MOMENT — a delegate that has produced rows since is working, whichever
   * predicate said the run was over.
   */
  const activeRunSettledAt = useMemo(
    () =>
      isSettledRunStatus(activeRunStatus)
        ? settleMomentOf(activeRun, items)
        : null,
    [activeRun, activeRunStatus, items],
  );
  const transcriptEntries = useMemo(
    () => withLiveText(durableEntries, liveText, workingAgents),
    [durableEntries, liveText, workingAgents],
  );
