// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { SurfaceDto } from '../autogenerated';
import { SurfaceBody } from './a2ui-components';
import {
  BrowserPaneContext,
  type BrowserPaneControls,
} from './browser/browser-pane-context';
import type { SurfaceState } from './use-surface';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const TEXT = (id: string, text: string) => ({ id, component: 'Text', text });

const LINKS = [
  { id: 'root', component: 'Column', children: ['refused', 'accepted'] },
  {
    id: 'refused',
    component: 'Button',
    child: 'refused_label',
    action: {
      functionCall: {
        '@call': 'openUrl',
        args: { url: 'https://refused.example/report' },
      },
    },
  },
  TEXT('refused_label', 'Open refused'),
  {
    id: 'accepted',
    component: 'Button',
    child: 'accepted_label',
    action: {
      functionCall: {
        '@call': 'openUrl',
        args: { url: 'https://example.com/docs' },
      },
    },
  },
  TEXT('accepted_label', 'Open accepted'),
];

function surface(): SurfaceDto {
  return {
    surfaceId: 'links',
    version: 1,
    title: 'Links',
    components: LINKS,
    dataModel: {},
    drafts: {},
    agentWrites: [],
    overriddenDrafts: [],
    oneShotPressed: [],
    removed: false,
    publisher: { memberId: 'a', agentLabel: 'Alice' },
    media: {},
  };
}

const STATE: SurfaceState = {
  surface: null,
  error: null,
  model: {},
  highlighted: new Set<string>(),
  phase: { kind: 'idle' },
  setValue: vi.fn(),
  press: vi.fn(),
  readMedia: vi.fn(),
};

let root: Root;
let container: HTMLDivElement;
let pane: BrowserPaneControls;

beforeEach(() => {
  window.geniro = createPreloadStub();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  pane = { openPane: vi.fn(), openUrl: vi.fn(), isOpen: () => true };
});

afterEach(() => {
  act(() => {
    root.unmount();
  });
  container.remove();
  vi.restoreAllMocks();
});

function draw(opensLink: (url: string) => boolean): void {
  act(() => {
    root.render(
      <BrowserPaneContext.Provider value={pane}>
        <SurfaceBody
          surface={surface()}
          state={STATE}
          inert={false}
          opensLink={opensLink}
        />
      </BrowserPaneContext.Provider>,
    );
  });
}

function buttonNamed(label: string): HTMLButtonElement {
  const found = Array.from(container.querySelectorAll('button')).find(
    (button) => button.textContent?.trim() === label,
  );
  if (found === undefined) {
    throw new Error(`no button drawn for "${label}"`);
  }
  return found;
}

function linkTo(href: string): HTMLAnchorElement {
  const found = container.querySelector<HTMLAnchorElement>(`a[href="${href}"]`);
  if (found === null) {
    throw new Error(`no link drawn to ${href}`);
  }
  return found;
}

describe('SurfaceBody link buttons', () => {
  it('draws a link the card may not open disabled, and a press opens nothing', () => {
    const opensLink = vi.fn((url: string) =>
      url.startsWith('https://example.com/'),
    );
    draw(opensLink);
    expect(opensLink).toHaveBeenCalledWith('https://refused.example/report');
    expect(
      container.querySelector('a[href="https://refused.example/report"]'),
    ).toBeNull();
    const refused = buttonNamed('Open refused');
    expect(refused.disabled).toBe(true);
    refused.click();
    expect(pane.openUrl).not.toHaveBeenCalled();
  });

  it('keeps a link the card may open enabled, and a press opens it in the chat browser', () => {
    const opensLink = vi.fn((url: string) =>
      url.startsWith('https://example.com/'),
    );
    draw(opensLink);
    expect(opensLink).toHaveBeenCalledWith('https://example.com/docs');
    const accepted = linkTo('https://example.com/docs');
    act(() => {
      accepted.dispatchEvent(
        new MouseEvent('click', { bubbles: true, cancelable: true, button: 0 }),
      );
    });
    expect(pane.openUrl).toHaveBeenCalledExactlyOnceWith(
      'https://example.com/docs',
    );
  });
});
