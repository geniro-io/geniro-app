function ChoicePickerView({
  component,
  scope,
}: {
  component: A2uiComponent;
  scope: Scope;
}): React.JSX.Element {
  const { render, pointer, value, write, highlighted } = useBinding(
    component,
    scope,
  );
  const [filter, setFilter] = useState('');
  const options = (
    Array.isArray(component.options) ? component.options : []
  ).flatMap((option: unknown) => {
    if (typeof option !== 'object' || option === null) {
      return [];
    }
    const record = option as { label?: unknown; value?: unknown };
    return typeof record.value === 'string'
      ? [{ label: resolveText(record.label, scope), value: record.value }]
      : [];
  });
  const shown = options.filter((option) =>
    option.label.toLowerCase().includes(filter.trim().toLowerCase()),
  );
  const chosen = Array.isArray(value)
    ? value.filter((entry): entry is string => typeof entry === 'string')
    : [];
  const single = component.variant !== 'multipleSelection';
  const pick = (picked: string): void => {
    write(
      single
        ? [picked]
        : chosen.includes(picked)
          ? chosen.filter((entry) => entry !== picked)
          : [...chosen, picked],
    );
  };
  return (
    <FieldFrame
      label={
        component.label === undefined ? '' : resolveText(component.label, scope)
      }
      messages={inputChecks(render, component, scope, pointer)}
      highlighted={highlighted}>
      {component.filterable === true ? (
        <Input
          value={filter}
          placeholder="Filter"
          onChange={(event) => setFilter(event.currentTarget.value)}
        />
      ) : null}
      {component.displayStyle === 'chips' ? (
        <div className="flex flex-wrap gap-1.5">
          {shown.map((option) => (
            <Chip
              key={option.value}
              asChild
              interactive
              tone={chosen.includes(option.value) ? 'active' : 'muted'}>
              <button
                type="button"
                aria-pressed={chosen.includes(option.value)}
                disabled={render.inert}
                className={cn(chosen.includes(option.value) && 'bg-accent')}
                onClick={() => pick(option.value)}>
                {option.label}
              </button>
            </Chip>
          ))}
        </div>
      ) : (
        <OptionList
          options={shown.map((option) => option.label)}
          selected={shown
            .filter((option) => chosen.includes(option.value))
            .map((option) => option.label)}
          arity={single ? 'one' : 'many'}
          disabled={render.inert}
          onPick={(label) => {
            const option = shown.find((entry) => entry.label === label);
            if (option !== undefined) {
              pick(option.value);
            }
          }}
        />
      )}
    </FieldFrame>
  );
}

function SliderView({
  component,
  scope,
}: {
  component: A2uiComponent;
  scope: Scope;
}): React.JSX.Element {
  const { render, pointer, value, write, highlighted } = useBinding(
    component,
    scope,
  );
  const min = typeof component.min === 'number' ? component.min : 0;
  const max = typeof component.max === 'number' ? component.max : 100;
  const steps =
    typeof component.steps === 'number' && component.steps > 0
      ? component.steps
      : null;
  const label =
    component.label === undefined ? '' : resolveText(component.label, scope);
  return (
    <FieldFrame
      label={label}
      messages={inputChecks(render, component, scope, pointer)}
      highlighted={highlighted}>
      <Slider
        value={typeof value === 'number' ? value : min}
        min={min}
        max={max}
        step={steps === null ? 1 : (max - min) / steps}
        label={label}
        disabled={render.inert}
        onValueChange={(next) => write(next)}
      />
    </FieldFrame>
  );
}

function DateTimeView({
  component,
  scope,
}: {
  component: A2uiComponent;
  scope: Scope;
}): React.JSX.Element {
  const { render, pointer, value, write, highlighted } = useBinding(
    component,
    scope,
  );
  const date = component.enableDate !== false;
  const time = component.enableTime === true;
  const type = date && time ? 'datetime-local' : time ? 'time' : 'date';
  return (
    <FieldFrame
      label={
        component.label === undefined ? '' : resolveText(component.label, scope)
      }
      messages={inputChecks(render, component, scope, pointer)}
      highlighted={highlighted}>
      <Input
        type={type}
        value={typeof value === 'string' ? value : ''}
        min={
          component.min === undefined
            ? undefined
            : resolveText(component.min, scope)
        }
        max={
          component.max === undefined
            ? undefined
            : resolveText(component.max, scope)
        }
        disabled={render.inert}
        onChange={(event) => write(event.currentTarget.value)}
      />
    </FieldFrame>
  );
}

function boundPointers(render: SurfaceRender, scope: Scope): string[] {
  return [...render.byId.values()].flatMap((component) => {
    const pointer = boundPointer(component.value, scope);
    return pointer === null ? [] : [pointer];
  });
}

function ButtonView({
  component,
  scope,
}: {
  component: A2uiComponent;
  scope: Scope;
}): React.JSX.Element {
  const render = useContext(RenderContext);
  const inTrigger = useContext(TriggerContext);
  if (render === null) {
    throw new Error('a card button outside its card');
  }
  const variant =
    BUTTON_VARIANT[
      str(component.variant, 'default') as keyof typeof BUTTON_VARIANT
    ] ?? 'outline';
  const label = <Node id={str(component.child, '')} scope={scope} />;
  const action =
    typeof component.action === 'object' && component.action !== null
      ? (component.action as Record<string, unknown>)
      : {};
  if (inTrigger) {
    return (
      <span className={buttonVariants({ variant, size: 'sm' })}>{label}</span>
    );
  }
  const call = action.functionCall;
  if (typeof call === 'object' && call !== null) {
    const opened = resolveValue(call, scope);
    const url =
      typeof opened === 'object' && opened !== null && 'url' in opened
        ? String(opened.url)
        : null;
    return url === null ? (
      <Button variant={variant} size="sm" disabled>
        {label}
      </Button>
    ) : (
      <ChatLink
        href={url}
        title={url}
        className={buttonVariants({ variant, size: 'sm' })}>
        {label}
      </ChatLink>
    );
  }
  const event =
    typeof action.event === 'object' && action.event !== null
      ? (action.event as Record<string, unknown>)
      : null;
  const checks = checkMessages(component, scope);
  const once = isOneShot(component);
  const spent = once && render.surface.oneShotPressed.includes(component.id);
  const phase = render.state.phase;
  const mine = phase.kind !== 'idle' && phase.componentId === component.id;
  const busy = mine && (phase.kind === 'pressing' || phase.kind === 'waiting');
  const blocked =
    render.inert ||
    spent ||
    busy ||
    event === null ||
    (checks.length > 0 && render.touched.size > 0);
  return (
    <div className="flex flex-col gap-1">
      <Button
        data-slot="a2ui-button"
        variant={variant}
        size="sm"
        disabled={blocked}
        onClick={() => {
          render.touch(boundPointers(render, scope));
          if (event === null || checks.length > 0) {
            return;
          }
          const context =
            typeof event.context === 'object' && event.context !== null
              ? (event.context as Record<string, unknown>)
              : {};
          render.state.press(
            component.id,
            event.userMessage === undefined
              ? null
              : resolveText(event.userMessage, scope),
            Object.fromEntries(
              Object.entries(context).map(([key, entry]) => [
                key,
                resolveValue(entry, scope),
              ]),
            ),
          );
        }}>
        {busy ? <Loader2 className="size-3.5 animate-spin" /> : null}
        {label}
      </Button>
      {spent ? (
        <span className="text-xs text-muted-foreground">
          Sent · this button works once
        </span>
      ) : null}
      {mine && phase.kind === 'waiting' ? (
        <span className="text-xs text-muted-foreground">
          Waiting — goes to the agent when its turn ends
        </span>
      ) : null}
      {mine && phase.kind === 'sent' && !spent ? (
        <span className="text-xs text-muted-foreground">✓ Sent</span>
      ) : null}
      {mine && phase.kind === 'error' ? (
        <span className="text-xs text-destructive">{phase.message}</span>
      ) : null}
      {checks.length > 0 && render.touched.size > 0
        ? checks.map((message) => (
            <span key={message} className="text-xs text-destructive">
              {message}
            </span>
          ))
        : null}
    </div>
  );
}
