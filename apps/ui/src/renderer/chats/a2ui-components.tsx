/** Links, pictures and raw HTML stay out of a card's text: an agent's link is a button the user presses. */
export function cardMarkdown(text: string): string {
  return text
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/<[^>]+>/g, '');
}

interface SurfaceRender {
  surface: SurfaceDto;
  state: SurfaceState;
  byId: ReadonlyMap<string, A2uiComponent>;
  touched: ReadonlySet<string>;
  touch: (pointers: readonly string[]) => void;
  inert: boolean;
}

const RenderContext = createContext<SurfaceRender | null>(null);

export function SurfaceBody({
  surface,
  state,
  inert,
}: {
  surface: SurfaceDto;
  state: SurfaceState;
  inert: boolean;
}): React.JSX.Element {
  const [touched, setTouched] = useState<ReadonlySet<string>>(new Set());
  const byId = new Map(
    (surface.components as A2uiComponent[]).map((component) => [
      component.id,
      component,
    ]),
  );
  const render: SurfaceRender = {
    surface,
    state,
    byId,
    touched,
    inert,
    touch: (pointers) =>
      setTouched((current) => new Set([...current, ...pointers])),
  };
  return (
    <RenderContext.Provider value={render}>
      <Node id="root" scope={{ model: state.model, base: '' }} />
    </RenderContext.Provider>
  );
}

function Node({
  id,
  scope,
}: {
  id: string;
  scope: Scope;
}): React.JSX.Element | null {
  const render = useContext(RenderContext);
  const component = render?.byId.get(id);
  if (render === null || component === undefined) {
    return null;
  }
  const accessibility = component['@accessibility'];
  const a11y =
    typeof accessibility === 'object' && accessibility !== null
      ? (accessibility as Record<string, unknown>)
      : {};
  if (a11y.hidden !== undefined && resolveValue(a11y.hidden, scope) === true) {
    return null;
  }
  const weight = typeof component.weight === 'number' ? component.weight : null;
  const label =
    a11y.label === undefined ? undefined : resolveText(a11y.label, scope);
  const body = <ComponentView component={component} scope={scope} />;
  return weight === null && label === undefined ? (
    body
  ) : (
    <div
      aria-label={label}
      className="min-w-0"
      style={weight === null ? undefined : { flexGrow: weight, flexBasis: 0 }}>
      {body}
    </div>
  );
}

function Children({
  children,
  scope,
}: {
  children: unknown;
  scope: Scope;
}): React.JSX.Element {
  return (
    <>
      {templateChildren(children, scope).map((child, index) => (
        <Node
          key={`${child.componentId}:${child.scope.base}:${index}`}
          id={child.componentId}
          scope={child.scope}
        />
      ))}
    </>
  );
}

function str(value: unknown, fallback: string): string {
  return typeof value === 'string' ? value : fallback;
}

function ComponentView({
  component,
  scope,
}: {
  component: A2uiComponent;
  scope: Scope;
}): React.JSX.Element | null {
  switch (component.component) {
    case 'Text':
      return <TextView component={component} scope={scope} />;
    case 'Image':
      return <ImageView component={component} scope={scope} />;
    case 'Icon':
      return <IconView component={component} scope={scope} />;
    case 'Video':
    case 'AudioPlayer':
      return <MediaView component={component} />;
    case 'Row':
    case 'Column':
      return (
        <div
          data-slot={`a2ui-${component.component.toLowerCase()}`}
          className={cn(
            'flex min-w-0 gap-2',
            component.component === 'Row' ? 'flex-row flex-wrap' : 'flex-col',
            JUSTIFY[str(component.justify, 'start')],
            ALIGN[str(component.align, 'stretch')],
          )}>
          <Children children={component.children} scope={scope} />
        </div>
      );
    case 'List':
      return (
        <div
          data-slot="a2ui-list"
          className={cn(
            'flex min-w-0 gap-2',
            component.direction === 'horizontal'
              ? 'flex-row overflow-x-auto'
              : 'flex-col',
            ALIGN[str(component.align, 'stretch')],
          )}>
          <Children children={component.children} scope={scope} />
        </div>
      );
    case 'Card':
      return (
        <Card className="gap-0 p-3">
          <Node id={str(component.child, '')} scope={scope} />
        </Card>
      );
    case 'Tabs':
      return <TabsView component={component} scope={scope} />;
    case 'Modal':
      return <ModalView component={component} scope={scope} />;
    case 'Divider':
      return component.axis === 'vertical' ? (
        <div className="w-px self-stretch bg-border" />
      ) : (
        <hr className="my-1 border-border" />
      );
    case 'Button':
      return <ButtonView component={component} scope={scope} />;
    case 'TextField':
      return <TextFieldView component={component} scope={scope} />;
    case 'CheckBox':
      return <CheckBoxView component={component} scope={scope} />;
    case 'ChoicePicker':
      return <ChoicePickerView component={component} scope={scope} />;
    case 'Slider':
      return <SliderView component={component} scope={scope} />;
    case 'DateTimeInput':
      return <DateTimeView component={component} scope={scope} />;
    default:
      return null;
  }
}

