import { describe, expect, it } from 'vitest';

import type { ItemDto } from '../autogenerated';
import { readSurfaceRow } from './a2ui-payload';

function row(payload: unknown): ItemDto {
  return { payload } as ItemDto;
}

describe('readSurfaceRow', () => {
  it('reads the row the daemon writes', () => {
    expect(
      readSurfaceRow(
        row({ surfaceId: 'form', version: 2, op: 'update', title: 'Release' }),
      ),
    ).toEqual({
      surfaceId: 'form',
      version: 2,
      op: 'update',
      title: 'Release',
    });
  });

  it('reads a missing title as none', () => {
    expect(
      readSurfaceRow(row({ surfaceId: 'form', version: 1, op: 'create' }))
        ?.title,
    ).toBeNull();
  });

  it.each([
    null,
    { version: 1, op: 'create' },
    { surfaceId: 'form', op: 'create' },
    { surfaceId: 'form', version: 1, op: 'replace' },
  ])('refuses %j', (payload) => {
    expect(readSurfaceRow(row(payload))).toBeNull();
  });
});
