import type { ItemDto as ChatItem } from '../autogenerated';

/**
 * TWIN PARSER: `apps/daemon/src/v1/agents/chat.types.ts` (`SurfaceRowPayload`)
 * is what the daemon writes for a `show_ui` row.
 */
export interface SurfaceRow {
  surfaceId: string;
  version: number;
  op: 'create' | 'update' | 'remove';
  title: string | null;
}

const OPS: readonly SurfaceRow['op'][] = ['create', 'update', 'remove'];

export function readSurfaceRow(item: ChatItem): SurfaceRow | null {
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const record = payload as Record<string, unknown>;
  const op = OPS.find((candidate) => candidate === record.op);
  if (
    typeof record.surfaceId !== 'string' ||
    record.surfaceId.length === 0 ||
    typeof record.version !== 'number' ||
    op === undefined
  ) {
    return null;
  }
  return {
    surfaceId: record.surfaceId,
    version: record.version,
    op,
    title: typeof record.title === 'string' ? record.title : null,
  };
}
