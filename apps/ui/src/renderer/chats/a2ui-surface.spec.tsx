async function renderCard(
  host: SurfaceHost | null,
  row: SurfaceRow = CREATE_ROW,
): Promise<void> {
  await act(async () => {
    root.render(
      <SurfaceHostContext.Provider value={host}>
        <SurfaceCard row={row} />
      </SurfaceHostContext.Provider>,
    );
  });
  await act(async () => {});
}

function fieldFrame(label: string): HTMLLabelElement {
  const frame = [
    ...container.querySelectorAll<HTMLLabelElement>('[data-slot="a2ui-field"]'),
  ].find((element) => element.textContent.includes(label));
  if (frame === undefined) {
    throw new Error('no field labelled ' + label);
  }
  return frame;
}

function fieldInput(label: string): HTMLInputElement | HTMLTextAreaElement {
  const input = fieldFrame(label).querySelector<
    HTMLInputElement | HTMLTextAreaElement
  >('input, textarea');
  if (input === null) {
    throw new Error('no input in field ' + label);
  }
  return input;
}

function typeInto(
  input: HTMLInputElement | HTMLTextAreaElement,
  value: string,
) {
  const prototype =
    input instanceof HTMLTextAreaElement
      ? HTMLTextAreaElement.prototype
      : HTMLInputElement.prototype;
  const setter = Object.getOwnPropertyDescriptor(prototype, 'value')?.set;
  act(() => {
    setter?.call(input, value);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

function buttonNamed(text: string): HTMLButtonElement {
  const button = [
    ...container.querySelectorAll<HTMLButtonElement>(
      '[data-slot="a2ui-button"]',
    ),
  ].find((element) => element.textContent.includes(text));
  if (button === undefined) {
    throw new Error('no button ' + text);
  }
  return button;
}

describe('SurfaceCard', () => {
  it('draws the text, labelled field and button of a surface read from the daemon', async () => {
    const surface = surfaceOf();
    const api = fakeApi(surface);
    await renderCard(hostOf(surface, api));

    expect(api.readSurface).toHaveBeenCalledWith({
      runId: 'run-1',
      surfaceId: 'form',
    });
    expect(container.textContent).toContain('Fill in the order');
    expect(fieldFrame('Name').textContent).toContain('Name');
    expect(fieldInput('Name')).toBeInstanceOf(HTMLInputElement);
    expect(buttonNamed('Save').textContent).toContain('Save');
  });

  it('saves a typed short field as a draft once typing pauses', async () => {
    const surface = surfaceOf({ components: TWO_FIELDS });
    const api = fakeApi(surface);
    await renderCard(hostOf(surface, api));

    typeInto(fieldInput('Name'), 'x');

    await vi.waitFor(() =>
      expect(api.saveSurfaceDrafts).toHaveBeenCalledWith({
        runId: 'run-1',
        surfaceId: 'form',
        saveSurfaceDraftsDto: { version: 1, changes: { '/name': 'x' } },
      }),
    );
  });

  it('never sends the pointer of an obscured field in any draft save', async () => {
    const surface = surfaceOf({ components: TWO_FIELDS });
    const api = fakeApi(surface);
    await renderCard(hostOf(surface, api));

    typeInto(fieldInput('Password'), 'hunter2-secret');
    typeInto(fieldInput('Name'), 'x');

    await vi.waitFor(() =>
      expect(api.saveSurfaceDrafts).toHaveBeenCalledWith({
        runId: 'run-1',
        surfaceId: 'form',
        saveSurfaceDraftsDto: { version: 1, changes: { '/name': 'x' } },
      }),
    );
    for (const [args] of api.saveSurfaceDrafts.mock.calls) {
      expect(Object.keys(args.saveSurfaceDraftsDto.changes)).not.toContain(
        '/password',
      );
      expect(JSON.stringify(args)).not.toContain('hunter2-secret');
    }
  });

  it('presses a button with the value its context binds, and the message it names', async () => {
    const surface = surfaceOf({ components: GREET });
    const api = fakeApi(surface);
    await renderCard(hostOf(surface, api));

    typeInto(fieldInput('Who'), 'Ann');
    act(() => buttonNamed('Greet').click());

    await vi.waitFor(() =>
      expect(api.pressChatSurface).toHaveBeenCalledWith({
        runId: 'run-1',
        surfaceId: 'form',
        pressSurfaceDto: {
          sourceComponentId: 'send',
          changes: { '/who': 'Ann' },
          userMessage: 'Greet them',
          context: { who: 'Ann' },
          clientMessageId: expect.any(String),
        },
      }),
    );
  });

  it('sends a press through the team route when the card belongs to a team run', async () => {
    const surface = surfaceOf({ components: GREET });
    const api = fakeApi(surface);
    const teamPress = {
      pressTeamSurface: vi.fn(async (_args: PressArgs) => surface),
    } as unknown as Pick<TeamsApi, 'pressTeamSurface'>;
    await renderCard(hostOf(surface, api, { teamPress }));

    typeInto(fieldInput('Who'), 'Ann');
    act(() => buttonNamed('Greet').click());

    await vi.waitFor(() =>
      expect(teamPress.pressTeamSurface).toHaveBeenCalled(),
    );
    expect(api.pressChatSurface).not.toHaveBeenCalled();
  });

  it('shows a press refused as busy as waiting, and sends it again with the same id once the turn ends', async () => {
    const surface = surfaceOf();
    const api = fakeApi(surface);
    api.pressChatSurface.mockImplementationOnce(async () => {
      throw daemonError(409, 'RUN_BUSY');
    });
    await renderCard(hostOf(surface, api, { turnOpen: true }));

    act(() => buttonNamed('Save').click());

    await vi.waitFor(() =>
      expect(container.textContent).toContain(
        'Waiting — goes to the agent when its turn ends',
      ),
    );
    expect(api.pressChatSurface).toHaveBeenCalledTimes(1);

    await renderCard(hostOf(surface, api, { turnOpen: false }));

    await vi.waitFor(() =>
      expect(api.pressChatSurface).toHaveBeenCalledTimes(2),
    );
    const ids = api.pressChatSurface.mock.calls.map(
      ([args]) => args.pressSurfaceDto.clientMessageId,
    );
    expect(ids[1]).toBe(ids[0]);
  });

  it('marks a field the agent overwrote with its own draft', async () => {
    const surface = surfaceOf({
      components: TWO_FIELDS,
      overriddenDrafts: ['/name'],
    });
    await renderCard(hostOf(surface, fakeApi(surface)));

    expect(fieldFrame('Name').dataset.highlighted).toBe('true');
    expect(fieldFrame('Name').textContent).toContain('Changed by the agent');
  });

  it('says a removed card was removed and leaves its fields disabled', async () => {
    const surface = surfaceOf({ components: TWO_FIELDS, removed: true });
    await renderCard(hostOf(surface, fakeApi(surface)));

    expect(container.textContent).toContain('Card removed by the agent');
    expect(fieldInput('Name').disabled).toBe(true);
  });

  it('disables a one-shot button the user has already pressed', async () => {
    const surface = surfaceOf({
      components: ONE_SHOT,
      oneShotPressed: ['approve'],
    });
    await renderCard(hostOf(surface, fakeApi(surface)));

    expect(buttonNamed('Approve').disabled).toBe(true);
    expect(container.textContent).toContain('Sent · this button works once');
  });

  it('opens a card that has no chat to draw it in with a line saying so', async () => {
    await renderCard(null);

    expect(container.textContent).toContain('This card opens in its chat.');
  });

  it('loads a stored picture as a data URL', async () => {
    const surface = surfaceOf({ components: PICTURE });
    const api = fakeApi(surface, 'image/png');
    await renderCard(hostOf(surface, api));

    await vi.waitFor(() => {
      const img = container.querySelector('img');
      expect(img?.getAttribute('src')).toMatch(/^data:image\/png;base64,/);
    });
    expect(api.readSurfaceMedia).toHaveBeenCalledWith({
      runId: 'run-1',
      file: IMAGE_FILE,
    });
  });

  it('loads a stored video only once its play button is pressed', async () => {
    const created = vi.fn((_blob: Blob) => 'blob:geniro-test');
    Object.defineProperty(URL, 'createObjectURL', {
      value: created,
      configurable: true,
    });
    Object.defineProperty(URL, 'revokeObjectURL', {
      value: vi.fn(),
      configurable: true,
    });
    const surface = surfaceOf({ components: CLIP });
    const api = fakeApi(surface, 'video/mp4');
    await renderCard(hostOf(surface, api));

    expect(api.readSurfaceMedia).not.toHaveBeenCalled();

    act(() => {
      container
        .querySelector<HTMLButtonElement>('[data-slot="a2ui-media-play"]')
        ?.click();
    });

    await vi.waitFor(() =>
      expect(container.querySelector('video')?.getAttribute('src')).toBe(
        'blob:geniro-test',
      ),
    );
    expect(api.readSurfaceMedia).toHaveBeenCalledWith({
      runId: 'run-1',
      file: VIDEO_FILE,
    });
    expect(created).toHaveBeenCalledTimes(1);
  });
});

