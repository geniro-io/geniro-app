type ReadArgs = { runId: string; surfaceId: string };
type SaveArgs = {
  runId: string;
  surfaceId: string;
  saveSurfaceDraftsDto: { version: number; changes: Record<string, unknown> };
};
type PressArgs = {
  runId: string;
  surfaceId: string;
  pressSurfaceDto: {
    sourceComponentId: string;
    changes: Record<string, unknown>;
    userMessage: string | null;
    context: Record<string, unknown>;
    clientMessageId: string;
  };
};

function fakeApi(surface: SurfaceDto, mediaType = 'image/png') {
  return {
    readSurface: vi.fn(async (_args: ReadArgs) => surface),
    saveSurfaceDrafts: vi.fn(async (args: SaveArgs) => ({
      ...surface,
      drafts: args.saveSurfaceDraftsDto.changes,
    })),
    readSurfaceMedia: vi.fn(async (args: { runId: string; file: string }) => ({
      file: args.file,
      mediaType,
      data: 'AAAA',
    })),
    pressChatSurface: vi.fn(async (_args: PressArgs) => surface),
  };
}

function hostOf(
  surface: SurfaceDto,
  api: ReturnType<typeof fakeApi>,
  extra: Partial<SurfaceHost> = {},
): SurfaceHost {
  return {
    runId: 'run-1',
    api,
    teamPress: null,
    versions: new Map([[surface.surfaceId, surface.version]]),
    turnOpen: false,
    beforePress: null,
    pressSettled: null,
    ...extra,
  };
}

function daemonError(status: number, code: string): Error {
  return new Error(
    'daemon POST /v1/chats/run-1/surfaces/form/press failed (' +
      status +
      '): ' +
      JSON.stringify({ code, message: code }),
  );
}

let container: HTMLDivElement;
let root: Root;

