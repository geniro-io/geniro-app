// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { LiveAction } from '../autogenerated';
import { ActionCard } from './action-card';
import type { ActionEntry } from './transcript-groups';
import { type ChatActions, ChatActionsContext } from './use-chat-actions';

(
  globalThis as unknown as { IS_REACT_ACT_ENVIRONMENT: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const entry = (
  seq: number,
  outcome: ActionEntry['outcome'] = null,
  extra: {
    once?: boolean;
    text?: string;
    agentLabel?: string;
    callId?: string;
    kind?: 'message' | 'stop' | 'command';
    targets?: { pid: number; command: string }[];
    argv?: string[];
    cwd?: string;
  } = {},
): ActionEntry => ({
  type: 'action',
  id: `i-${seq}`,
  createdAt: 'now',
  seq,
  memberId: null,
  parentToolUseId: null,
  action: {
    actionId: 'merged',
    label: 'Merged',
    description: null,
    kind: extra.kind ?? 'message',
    text:
      extra.kind === 'stop' || extra.kind === 'command'
        ? null
        : (extra.text ?? 'continue'),
    targets: extra.targets ?? [],
    argv: extra.argv ?? [],
    cwd: extra.cwd ?? null,
    once: extra.once ?? true,
    nodeId: 'agent',
    conversationId: '',
    agentLabel: extra.agentLabel ?? null,
    callId: extra.callId ?? null,
  },
  outcome,
});

const live = (seq: number): LiveAction => ({
  seq,
  actionId: 'merged',
  memberId: 'agent',
  conversationId: '',
  label: 'Merged',
  once: true,
  spec: { kind: 'message', text: 'go' },
  publisher: { nodeId: 'agent', conversationId: '' },
  pending: false,
});

let root: Root | null = null;
afterEach(() => {
  act(() => root?.unmount());
  root = null;
});

function render(card: ActionEntry, chat: Partial<ChatActions>): HTMLElement {
  const container = document.createElement('div');
  root = createRoot(container);
  const value: ChatActions = {
    actions: [],
    throughSeq: 100,
    phases: new Map(),
    press: vi.fn(),
    dismiss: vi.fn(),
    confirming: null,
    confirmCommand: vi.fn(),
    cancelCommand: vi.fn(),
    ...chat,
  };
  act(() =>
    root!.render(
      <ChatActionsContext.Provider value={value}>
        <ActionCard entry={card} />
      </ChatActionsContext.Provider>,
    ),
  );
  return container;
}

const status = (container: HTMLElement): string | null =>
  container.querySelector('[data-slot="action-status"]')?.textContent ?? null;

describe('ActionCard', () => {
  it('draws the live button while the daemon lists the publish, and presses it', () => {
    const press = vi.fn();
    const container = render(entry(5), { actions: [live(5)], press });

    const button = container.querySelector<HTMLButtonElement>(
      '[data-slot="action-chip"]',
    );
    act(() => button!.click());

    expect(press).toHaveBeenCalledWith(live(5));
    expect(status(container)).toBeNull();
  });

  it('says what became of a publish that is no longer live', () => {
    const at = '2026-10-18T14:32:00Z';
    const local = new Date(at);
    const clock = `${String(local.getHours()).padStart(2, '0')}:${String(local.getMinutes()).padStart(2, '0')}`;
    expect(
      status(
        render(
          entry(5, {
            actionSeq: 5,
            state: 'succeeded',
            exitCode: null,
            error: null,
            outputTail: null,
            alreadyStopped: false,
            at,
          }),
          {},
        ),
      ),
    ).toBe(`Pressed ${clock} · message sent`);
  });

  it.each([
    ['removed', 'Removed by agent'],
    ['dismissed', 'Dismissed'],
    ['interrupted', 'Interrupted'],
    ['failed', 'Failed 00:00 · boom'],
  ] as const)('reads %s as %s', (state, line) => {
    const at = new Date(2026, 9, 18, 0, 0).toISOString();
    expect(
      status(
        render(
          entry(5, {
            actionSeq: 5,
            state,
            exitCode: null,
            error: 'boom',
            outputTail: null,
            alreadyStopped: false,
            at,
          }),
          {},
        ),
      ),
    ).toBe(line);
  });

  it('reads No longer available when nothing in the window says why', () => {
    expect(status(render(entry(5), {}))).toBe('No longer available');
  });

  it('keeps what ended a publish over a newer one, and calls a replaced reusable press Updated', () => {
    const at = new Date(2026, 9, 18, 0, 0).toISOString();
    const outcome = (state: 'removed' | 'succeeded') => ({
      actionSeq: 5,
      state,
      exitCode: null,
      error: null,
      outputTail: null,
      alreadyStopped: false,
      at,
    });
    expect(
      status(render(entry(5, outcome('removed')), { actions: [live(9)] })),
    ).toBe('Removed by agent');
    const clock = `${String(new Date(at).getHours()).padStart(2, '0')}:00`;
    expect(
      status(render(entry(5, outcome('succeeded')), { actions: [live(9)] })),
    ).toBe(`Pressed ${clock} · message sent`);
    expect(
      status(
        render(entry(5, outcome('succeeded'), { once: false }), {
          actions: [live(9)],
        }),
      ),
    ).toBe('Updated');
  });

  it('clamps a long message until the reader asks for all of it', () => {
    const text = ['first line', 'second', 'third', 'hidden fourth'].join('\n');
    const container = render(entry(5, null, { text }), { actions: [live(5)] });
    const message = container.querySelector('[data-slot="action-message"]');
    expect(message?.className).toContain('line-clamp-3');

    const toggle = [...container.querySelectorAll('button')].find(
      (button) => button.textContent === 'Show all',
    );
    act(() => toggle!.click());

    expect(message?.className).not.toContain('line-clamp-3');
    expect(toggle?.getAttribute('aria-expanded')).toBe('true');
  });

  it('lists the processes a stop press ends, and says when they had already stopped', () => {
    const targets = [
      { pid: 48211, command: 'python3 -m http.server 8765' },
      { pid: 48212, command: 'node watcher.js' },
    ];
    const container = render(entry(5, null, { kind: 'stop', targets }), {
      actions: [live(5)],
    });
    expect(
      container.querySelector('[data-slot="action-targets"]')?.textContent,
    ).toBe(
      'Stops, with what these start:python3 -m http.server 8765 · pid 48211node watcher.js · pid 48212',
    );
    expect(container.querySelector('[data-slot="action-message"]')).toBeNull();

    const at = new Date(2026, 9, 18, 0, 0).toISOString();
    const stopped = (alreadyStopped: boolean) =>
      entry(
        5,
        {
          actionSeq: 5,
          state: 'stopped',
          exitCode: null,
          error: null,
          outputTail: null,
          alreadyStopped,
          at,
        },
        { kind: 'stop', targets },
      );
    expect(status(render(stopped(false), {}))).toBe('Pressed 00:00 · stopped');
    expect(status(render(stopped(true), {}))).toBe(
      'Pressed 00:00 · already stopped',
    );
  });

  it('shows the command a press runs, in full, before and after the press', () => {
    const argv = ['pnpm', 'test', '--grep', 'checkout flow'];
    const cwd = '/Users/dev/projects/geniro-app';
    const block = (container: HTMLElement): string | null =>
      container.querySelector('[data-slot="action-command"]')?.textContent ??
      null;

    const before = render(entry(5, null, { kind: 'command', argv, cwd }), {
      actions: [live(5)],
    });
    expect(block(before)).toBe(
      `Runs:pnpm test --grep 'checkout flow'in ${cwd}`,
    );
    expect(before.querySelector('[data-slot="action-message"]')).toBeNull();

    const after = render(
      entry(
        5,
        {
          actionSeq: 5,
          state: 'succeeded',
          exitCode: 0,
          error: null,
          outputTail: null,
          alreadyStopped: false,
          at: new Date(2026, 9, 18, 0, 0).toISOString(),
        },
        { kind: 'command', argv, cwd },
      ),
      {},
    );
    expect(block(after)).toBe(`Runs:pnpm test --grep 'checkout flow'in ${cwd}`);
    expect(status(after)).toBe('Pressed 00:00 · ran, exit 0');
  });

  it('keeps a command output tail folded until the reader opens it', () => {
    const outcome = (outputTail: string | null): ActionEntry['outcome'] => ({
      actionSeq: 5,
      state: 'failed',
      exitCode: 1,
      error: 'exit 1',
      outputTail,
      alreadyStopped: false,
      at: new Date(2026, 9, 18, 0, 0).toISOString(),
    });
    const card = (tail: string | null): ActionEntry =>
      entry(5, outcome(tail), {
        kind: 'command',
        argv: ['make'],
        cwd: '/repo',
      });

    const container = render(card('1 failed\nboom'), {});
    const toggle = [...container.querySelectorAll('button')].find(
      (button) => button.textContent === 'Output',
    );
    expect(toggle?.getAttribute('aria-expanded')).toBe('false');
    expect(container.querySelector('[data-slot="action-output"]')).toBeNull();

    act(() => toggle!.click());

    expect(toggle?.getAttribute('aria-expanded')).toBe('true');
    expect(
      container.querySelector('[data-slot="action-output"]')?.textContent,
    ).toBe('1 failed\nboom');
    expect(status(container)).toBe('Failed 00:00 · exit 1');

    expect(
      [...render(card(null), {}).querySelectorAll('button')].some(
        (button) => button.textContent === 'Output',
      ),
    ).toBe(false);
  });

  it('reports a command’s exit code even after the agent republished its button', () => {
    const card = entry(
      5,
      {
        actionSeq: 5,
        state: 'failed',
        exitCode: 2,
        error: 'exit 2',
        outputTail: null,
        alreadyStopped: false,
        at: new Date(2026, 9, 18, 0, 0).toISOString(),
      },
      { kind: 'command', argv: ['make'], cwd: '/repo' },
    );

    expect(status(render(card, { actions: [live(9)] }))).toBe(
      'Failed 00:00 · exit 2',
    );
  });

  it('reports a command’s last run while its button stays, and nothing while it runs', () => {
    const failed: ActionEntry['outcome'] = {
      actionSeq: 5,
      state: 'failed',
      exitCode: 3,
      error: 'exit 3',
      outputTail: null,
      alreadyStopped: false,
      at: new Date(2026, 9, 18, 0, 0).toISOString(),
    };
    const command = (pending: boolean): LiveAction => ({
      ...live(5),
      spec: { kind: 'command', argv: ['make'], cwd: '/repo' },
      pending,
    });
    const card = entry(5, failed, {
      kind: 'command',
      argv: ['make'],
      cwd: '/repo',
    });

    const idle = render(card, { actions: [command(false)] });
    expect(idle.querySelector('[data-slot="action-chip"]')).not.toBeNull();
    expect(status(idle)).toBe('Failed 00:00 · exit 3');

    expect(status(render(card, { actions: [command(true)] }))).toBeNull();
    expect(status(render(entry(5, failed), { actions: [live(5)] }))).toBeNull();
  });

  it('shows the exact text a press sends', () => {
    const container = render(entry(5), { actions: [live(5)] });

    expect(
      container.querySelector('[data-slot="action-message"]')?.textContent,
    ).toBe('Sends: continue');
  });

  it('draws the record alone where no live set is provided', () => {
    const container = document.createElement('div');
    root = createRoot(container);
    act(() => root!.render(<ActionCard entry={entry(5)} />));

    expect(status(container)).toBeNull();
    expect(container.querySelector('[data-slot="action-chip"]')).toBeNull();

    act(() =>
      root!.render(
        <ActionCard
          entry={entry(5, {
            actionSeq: 5,
            state: 'dismissed',
            exitCode: null,
            error: null,
            outputTail: null,
            alreadyStopped: false,
            at: 'now',
          })}
        />,
      ),
    );
    expect(status(container)).toBe('Dismissed');
  });

  it('reads Updated when a newer publish of the same id is live', () => {
    expect(status(render(entry(5), { actions: [live(9)] }))).toBe('Updated');
  });

  it('callee action card renders with from <agent>, linking to its call', () => {
    const openCall = vi.fn();
    const container = render(
      entry(5, null, { agentLabel: 'Engineer', callId: 'call-1' }),
      { actions: [live(5)], openCall },
    );

    expect(
      container.querySelector('[data-slot="action-publisher"]')?.textContent,
    ).toBe('from Engineer');
    const link = container.querySelector<HTMLButtonElement>(
      '[aria-label="Open Engineer\'s thread"]',
    );
    act(() => link!.click());
    expect(openCall).toHaveBeenCalledWith('call-1');
  });

  it('names the publisher without a link where no call can be opened, and nobody for the run’s own agent', () => {
    const named = render(entry(5, null, { agentLabel: 'Engineer' }), {});
    expect(
      named.querySelector('[data-slot="action-publisher"]')?.textContent,
    ).toBe('from Engineer');
    expect(named.querySelector('[aria-label="Open Engineer\'s thread"]')).toBe(
      null,
    );

    expect(
      render(entry(5), {}).querySelector('[data-slot="action-publisher"]'),
    ).toBeNull();
  });

  it('says nothing about a publish the live set has not been read through yet', () => {
    const container = render(entry(5), { throughSeq: 3 });

    expect(status(container)).toBeNull();
    expect(container.querySelector('[data-slot="action-chip"]')).toBeNull();
  });
});
