// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { LiveAction } from '../autogenerated';
import { ActionCard } from './action-card';
import type { ActionEntry } from './transcript-groups';
import { type ChatActions, ChatActionsContext } from './use-chat-actions';

(
  globalThis as unknown as { IS_REACT_ACT_ENVIRONMENT: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const entry = (
  seq: number,
  outcome: ActionEntry['outcome'] = null,
  extra: { once?: boolean; text?: string } = {},
): ActionEntry => ({
  type: 'action',
  id: `i-${seq}`,
  createdAt: 'now',
  seq,
  nodeId: null,
  parentToolUseId: null,
  action: {
    actionId: 'merged',
    label: 'Merged',
    description: null,
    kind: 'message',
    text: extra.text ?? 'continue',
    once: extra.once ?? true,
    nodeId: 'agent',
    conversationId: '',
  },
  outcome,
});

const live = (seq: number): LiveAction => ({
  seq,
  actionId: 'merged',
  nodeId: 'agent',
  conversationId: '',
  label: 'Merged',
  once: true,
  spec: { kind: 'message', text: 'go' },
  publisher: { nodeId: 'agent', conversationId: '' },
  pending: false,
});

let root: Root | null = null;
afterEach(() => {
  act(() => root?.unmount());
  root = null;
});

function render(card: ActionEntry, chat: Partial<ChatActions>): HTMLElement {
  const container = document.createElement('div');
  root = createRoot(container);
  const value: ChatActions = {
    actions: [],
    throughSeq: 100,
    phases: new Map(),
    press: vi.fn(),
    dismiss: vi.fn(),
    ...chat,
  };
  act(() =>
    root!.render(
      <ChatActionsContext.Provider value={value}>
        <ActionCard entry={card} />
      </ChatActionsContext.Provider>,
    ),
  );
  return container;
}

const status = (container: HTMLElement): string | null =>
  container.querySelector('[data-slot="action-status"]')?.textContent ?? null;

describe('ActionCard', () => {
  it('draws the live button while the daemon lists the publish, and presses it', () => {
    const press = vi.fn();
    const container = render(entry(5), { actions: [live(5)], press });

    const button = container.querySelector<HTMLButtonElement>(
      '[data-slot="action-chip"]',
    );
    act(() => button!.click());

    expect(press).toHaveBeenCalledWith(live(5));
    expect(status(container)).toBeNull();
  });

  it('says what became of a publish that is no longer live', () => {
    const at = '2026-10-18T14:32:00Z';
    const local = new Date(at);
    const clock = `${String(local.getHours()).padStart(2, '0')}:${String(local.getMinutes()).padStart(2, '0')}`;
    expect(
      status(
        render(
          entry(5, {
            actionSeq: 5,
            state: 'succeeded',
            exitCode: null,
            error: null,
            at,
          }),
          {},
        ),
      ),
    ).toBe(`Pressed ${clock} · message sent`);
  });

  it.each([
    ['removed', 'Removed by agent'],
    ['dismissed', 'Dismissed'],
    ['interrupted', 'Interrupted'],
    ['failed', 'Failed 00:00 · boom'],
  ] as const)('reads %s as %s', (state, line) => {
    const at = new Date(2026, 9, 18, 0, 0).toISOString();
    expect(
      status(
        render(
          entry(5, { actionSeq: 5, state, exitCode: null, error: 'boom', at }),
          {},
        ),
      ),
    ).toBe(line);
  });

  it('reads No longer available when nothing in the window says why', () => {
    expect(status(render(entry(5), {}))).toBe('No longer available');
  });

  it('keeps what ended a publish over a newer one, and calls a replaced reusable press Updated', () => {
    const at = new Date(2026, 9, 18, 0, 0).toISOString();
    const outcome = (state: 'removed' | 'succeeded') => ({
      actionSeq: 5,
      state,
      exitCode: null,
      error: null,
      at,
    });
    expect(
      status(render(entry(5, outcome('removed')), { actions: [live(9)] })),
    ).toBe('Removed by agent');
    const clock = `${String(new Date(at).getHours()).padStart(2, '0')}:00`;
    expect(
      status(render(entry(5, outcome('succeeded')), { actions: [live(9)] })),
    ).toBe(`Pressed ${clock} · message sent`);
    expect(
      status(
        render(entry(5, outcome('succeeded'), { once: false }), {
          actions: [live(9)],
        }),
      ),
    ).toBe('Updated');
  });

  it('clamps a long message until the reader asks for all of it', () => {
    const text = ['first line', 'second', 'third', 'hidden fourth'].join('\n');
    const container = render(entry(5, null, { text }), { actions: [live(5)] });
    const message = container.querySelector('[data-slot="action-message"]');
    expect(message?.className).toContain('line-clamp-3');

    const toggle = [...container.querySelectorAll('button')].find(
      (button) => button.textContent === 'Show all',
    );
    act(() => toggle!.click());

    expect(message?.className).not.toContain('line-clamp-3');
    expect(toggle?.getAttribute('aria-expanded')).toBe('true');
  });

  it('shows the exact text a press sends', () => {
    const container = render(entry(5), { actions: [live(5)] });

    expect(
      container.querySelector('[data-slot="action-message"]')?.textContent,
    ).toBe('Sends: continue');
  });

  it('draws the record alone where no live set is provided', () => {
    const container = document.createElement('div');
    root = createRoot(container);
    act(() => root!.render(<ActionCard entry={entry(5)} />));

    expect(status(container)).toBeNull();
    expect(container.querySelector('[data-slot="action-chip"]')).toBeNull();

    act(() =>
      root!.render(
        <ActionCard
          entry={entry(5, {
            actionSeq: 5,
            state: 'dismissed',
            exitCode: null,
            error: null,
            at: 'now',
          })}
        />,
      ),
    );
    expect(status(container)).toBe('Dismissed');
  });

  it('reads Updated when a newer publish of the same id is live', () => {
    expect(status(render(entry(5), { actions: [live(9)] }))).toBe('Updated');
  });

  it('says nothing about a publish the live set has not been read through yet', () => {
    const container = render(entry(5), { throughSeq: 3 });

    expect(status(container)).toBeNull();
    expect(container.querySelector('[data-slot="action-chip"]')).toBeNull();
  });
});
