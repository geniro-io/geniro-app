function liveCommand(seq: number, label: string): LiveAction {
  return {
    seq,
    actionId: label.toLowerCase(),
    nodeId: 'agent',
    conversationId: '',
    label,
    once: false,
    spec: { kind: 'command', ...E2E, timeoutMs: 600_000, notifyAgent: true },
    publisher: { nodeId: 'agent', conversationId: '' },
    pending: false,
  };
}

function live(seq: number, label: string, agentLabel?: string): LiveAction {
  return {
    seq,
    actionId: label.toLowerCase(),
    nodeId: 'agent',
    conversationId: '',
    label,
    once: true,
    spec:
      agentLabel === undefined
        ? { kind: 'message', text: 'continue' }
        : {
            kind: 'stop',
            targets: PREVIEW.map((target) => ({
              ...target,
              startedAt: '2026-10-18T14:20:00Z',
            })),
          },
    publisher: {
      nodeId: 'agent',
      conversationId: '',
      ...(agentLabel === undefined ? {} : { callId: 'call-1', agentLabel }),
    },
    pending: false,
  };
}

