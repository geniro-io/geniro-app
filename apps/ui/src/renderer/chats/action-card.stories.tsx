import type { Meta, StoryObj } from '@storybook/react-vite';

import type { LiveAction } from '../autogenerated';
import { ActionCard } from './action-card';
import type { ActionEntry } from './transcript-groups';
import { type ChatActions, ChatActionsContext } from './use-chat-actions';

function entry(
  seq: number,
  label: string,
  outcome: ActionEntry['outcome'] = null,
  description: string | null = 'Tell the agent the pull request landed',
): ActionEntry {
  return {
    type: 'action',
    id: `i-${seq}`,
    createdAt: '2026-10-18T14:30:00Z',
    seq,
    nodeId: null,
    parentToolUseId: null,
    action: {
      actionId: label.toLowerCase(),
      label,
      description,
      kind: 'message',
      text: 'PR merged — continue',
      once: true,
      nodeId: 'agent',
      conversationId: '',
    },
    outcome,
  };
}

function live(seq: number, label: string): LiveAction {
  return {
    seq,
    actionId: label.toLowerCase(),
    nodeId: 'agent',
    conversationId: '',
    label,
    once: true,
    spec: { kind: 'message', text: 'continue' },
    publisher: { nodeId: 'agent', conversationId: '' },
    pending: false,
  };
}

const chat: ChatActions = {
  actions: [live(10, 'PR merged')],
  throughSeq: 50,
  phases: new Map(),
  press: () => undefined,
  dismiss: () => undefined,
};

function Cards(): React.JSX.Element {
  return (
    <ChatActionsContext.Provider value={chat}>
      <div className="flex w-[28rem] flex-col gap-3">
        <ActionCard entry={entry(10, 'PR merged')} />
        <ActionCard
          entry={entry(4, 'Deploy approved', {
            actionSeq: 4,
            state: 'succeeded',
            exitCode: null,
            error: null,
            at: '2026-10-18T14:32:00Z',
          })}
        />
        <ActionCard
          entry={entry(3, 'Ship it', {
            actionSeq: 3,
            state: 'removed',
            exitCode: null,
            error: null,
            at: '2026-10-18T14:33:00Z',
          })}
        />
        <ActionCard entry={entry(2, 'Retry build', null, null)} />
      </div>
    </ChatActionsContext.Provider>
  );
}

const meta = {
  title: 'Chats/ActionCard',
  component: Cards,
  decorators: [
    (story) => (
      <div className="h-[420px] bg-background p-3 text-foreground">
        {story()}
      </div>
    ),
  ],
} satisfies Meta<typeof Cards>;

export default meta;
type Story = StoryObj<typeof meta>;

/** Live (with its button and Dismiss), pressed, removed by the agent, gone. */
export const States: Story = {};
