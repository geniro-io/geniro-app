import { type ChatActions, ChatActionsContext } from './use-chat-actions';

const RESULT_OF_SUCCESS: Record<ActionCardView['kind'], string> = {
  message: 'message sent',
  stop: 'stopped',
  command: 'ran',
};

/** The line a card shows once its button is gone, or after a command's last run. */
function actionStatusLine(
  action: ActionCardView,
  outcome: ActionOutcomeView | null,
  replaced: boolean,
): string {
  // What ended this publish outranks a newer publish of its id; only a
  // reusable button the agent replaced while it was still live reads Updated.
  const retired =
    outcome !== null &&
    (RETIRING_STATES.has(outcome.state) ||
      (action.once && ONE_SHOT_END_STATES.has(outcome.state)));
  // A command's finished run is reported over a newer publish of its id: the
  // exit code is the one record of what the user ran.
  const ranCommand =
    action.kind === 'command' &&
    outcome !== null &&
    outcome.state !== 'running' &&
    outcome.state !== 'pressed';
  if (replaced && !retired && !ranCommand) {
    return 'Updated';
  }
  if (outcome !== null) {
    const at = formatClockTime(outcome.at);
    switch (outcome.state) {
      case 'succeeded':
      case 'stopped': {
        const result =
          action.kind === 'command' && outcome.exitCode !== null
            ? `ran, exit ${outcome.exitCode}`
            : outcome.alreadyStopped
              ? 'already stopped'
              : RESULT_OF_SUCCESS[action.kind];
        return `Pressed ${at} · ${result}`;
      }
      case 'failed':
        return outcome.error === null
          ? `Failed ${at}`
          : `Failed ${at} · ${outcome.error}`;
      case 'removed':
        return 'Removed by agent';
      case 'dismissed':
        return 'Dismissed';
      case 'interrupted':
        return 'Interrupted';
      case 'pressed':
      case 'running':
        return `Pressed ${at} · running`;
    }
  }
  return 'No longer available';
}

/**
 * TWIN PARSER: apps/daemon/src/v1/agents/utils/action-fold.ts (`RETIRING_STATES` /
 * `ONE_SHOT_END_STATES`), the fold that decides what is still live.
 */
const RETIRING_STATES: ReadonlySet<ActionOutcomeView['state']> = new Set([
  'removed',
  'dismissed',
]);
const ONE_SHOT_END_STATES: ReadonlySet<ActionOutcomeView['state']> = new Set([
  'succeeded',
  'stopped',
  'interrupted',
]);

/** Past this, the message is clamped until the reader asks for all of it. */
const MESSAGE_PREVIEW_CHARS = 240;
// Must match the `line-clamp-3` the message is drawn with.
const MESSAGE_PREVIEW_LINES = 3;

function liveOf(
  chat: ChatActions | null,
  entry: ActionEntry,
): LiveAction | null {
  return chat?.actions.find((action) => action.seq === entry.seq) ?? null;
}

function isReplaced(chat: ChatActions | null, entry: ActionEntry): boolean {
  return (
    chat?.actions.some(
      (action) =>
        action.seq > entry.seq &&
        action.actionId === entry.action.actionId &&
        action.memberId === entry.action.nodeId &&
        action.conversationId === entry.action.conversationId,
    ) ?? false
  );
}

/**
 * An agent's button where it was published: what it is, and — while it is
 * live — the same button the shelf draws, with Dismiss beside it. Once it is
 * not, or once a command it runs has ended, a status line says what became
 * of it.
 */
export function ActionCard({
  entry,
}: {
  entry: ActionEntry;
}): React.JSX.Element {
  const chat = useContext(ChatActionsContext);
  const live = liveOf(chat, entry);
  const Icon = ACTION_KIND_ICON[entry.action.kind];
  // A publish the live set has not been read through yet is undecided, not
  // gone; a surface with no live set at all can only report what it holds.
  const undecided =
    live === null && chat !== null && chat.throughSeq < entry.seq;
  // A command's last run is reported even while its button stays — a failed
  // one stays pressable, and its exit code is what the user presses again on.
  const reportsLastRun =
    live !== null &&
    entry.action.kind === 'command' &&
    entry.outcome !== null &&
    !live.pending;
  const status =
    (live !== null && !reportsLastRun) || undecided
      ? null
      : chat === null
        ? entry.outcome === null
          ? null
          : actionStatusLine(entry.action, entry.outcome, false)
        : actionStatusLine(
            entry.action,
            entry.outcome,
            isReplaced(chat, entry),
          );
  const outputTail = entry.outcome?.outputTail ?? null;
  return (
    <div
      data-slot="action-card"
      data-action-seq={entry.seq}
      className="flex flex-col gap-1.5 rounded-lg border border-border bg-card px-3 py-2 text-sm shadow-panel-sm">
      <div className="flex min-w-0 items-center gap-2">
        <Icon
          aria-hidden="true"
          className="size-3.5 shrink-0 text-muted-foreground"
        />
        <span className="truncate">
          <span className="text-muted-foreground">Action · </span>
          <span className="font-medium">{entry.action.label}</span>
        </span>
      </div>
      {entry.action.agentLabel !== null ? (
        <ActionPublisher
          agent={entry.action.agentLabel}
          callId={entry.action.callId}
          openCall={chat?.openCall}
        />
      ) : null}
      {entry.action.description !== null ? (
        <p className="truncate text-xs text-muted-foreground">
          {entry.action.description}
        </p>
      ) : null}
      {entry.action.text !== null ? (
        <ActionMessage
          text={entry.action.text}
          memoryKey={`action:${entry.id}`}
        />
      ) : null}
      {entry.action.targets.length > 0 ? (
        <ActionStopTargets targets={entry.action.targets} />
      ) : null}
      {entry.action.kind === 'command' ? (
        <ActionCommand argv={entry.action.argv} cwd={entry.action.cwd} />
      ) : null}
      {live !== null && chat !== null ? (
        <div className="flex items-center gap-1">
          <ActionChip
            action={live}
            phase={chat.phases.get(live.seq)}
            onPress={chat.press}
          />
          <ActionMoreMenu action={live} onDismiss={chat.dismiss} />
        </div>
      ) : null}
      {status !== null ? (
        <p
          data-slot="action-status"
          className={cn(
            'text-xs text-muted-foreground',
            entry.outcome?.state === 'failed' && 'text-destructive',
          )}>
          {status}
        </p>
      ) : null}
      {outputTail === null ? null : (
        <ActionOutput
          tail={outputTail}
          memoryKey={`action-output:${entry.id}:${entry.outcome?.at ?? ''}`}
        />
      )}
    </div>
  );
}

/**
 * Which agent published a button that is not the run's own — a link to the
 * call it was answering where that call can be opened.
 */
function ActionPublisher({
  agent,
  callId,
  openCall,
}: {
  agent: string;
  callId: string | null;
  openCall: ((callId: string) => void) | undefined;
}): React.JSX.Element {
  return (
    <p data-slot="action-publisher" className="text-xs text-muted-foreground">
      from{' '}
      {callId !== null && openCall !== undefined ? (
        <Button
          type="button"
          variant="link"
          className="h-auto p-0 text-xs max-sm:min-h-11"
          aria-label={`Open ${agent}'s thread`}
          onClick={() => openCall(callId)}>
          {agent}
        </Button>
      ) : (
        <span className="font-medium">{agent}</span>
      )}
    </p>
  );
}

/**
 * What a stop press ends, process by process, and with them what they have
 * started by then — the user decides on these, not on the agent's label.
 */
function ActionStopTargets({
  targets,
}: {
  targets: readonly StopTargetView[];
}): React.JSX.Element {
  return (
    <div
      data-slot="action-targets"
      className="flex flex-col gap-0.5 border-l-2 border-border pl-2 text-xs text-muted-foreground">
      <span className="font-medium">Stops, with what these start:</span>
      {targets.map((target) => (
        <span key={target.pid} className="break-all">
          <code className="font-mono">{target.command}</code>
          <span className="whitespace-nowrap"> · pid {target.pid}</span>
        </span>
      ))}
    </div>
  );
}

/**
 * What a command press runs, in full and word by word — the user decides on
 * this, not on the agent's label.
 */
function ActionCommand({
  argv,
  cwd,
}: {
  argv: readonly string[];
  cwd: string | null;
}): React.JSX.Element {
  return (
    <div
      data-slot="action-command"
      className="flex flex-col gap-0.5 border-l-2 border-border pl-2 text-xs text-muted-foreground">
      <span className="font-medium">Runs:</span>
      <code className="font-mono break-all whitespace-pre-wrap">
        {quotedArgv(argv).join(' ')}
      </code>
      {cwd === null ? null : (
        <span className="break-all">
          in <code className="font-mono">{cwd}</code>
        </span>
      )}
    </div>
  );
}

/** The end of a command's output, folded until the reader asks for it. */
function ActionOutput({
  tail,
  memoryKey,
}: {
  tail: string;
  memoryKey: string;
}): React.JSX.Element {
  const [open, setOpen] = useThreadFlag(memoryKey, false);
  return (
    <div className="flex flex-col items-start gap-1">
      <Button
        type="button"
        variant="link"
        className="h-auto p-0 text-xs max-sm:min-h-11"
        aria-expanded={open}
        onClick={() => setOpen((current) => !current)}>
        Output
      </Button>
      {open ? (
        <pre
          data-slot="action-output"
          className="max-h-60 w-full overflow-auto rounded-md bg-muted px-2 py-1.5 font-mono text-xs whitespace-pre-wrap text-foreground">
          <AnsiText text={tail} />
        </pre>
      ) : null}
    </div>
  );
}

/**
 * What a press sends, in full on request: it goes into the chat as the user's
 * own words, so nothing in it may stay out of view — on a phone too, where a
 * tooltip never opens.
 */
function ActionMessage({
  text,
  memoryKey,
}: {
  text: string;
  memoryKey: string;
}): React.JSX.Element {
  const [expanded, setExpanded] = useThreadFlag(memoryKey, false);
  const long =
    text.length > MESSAGE_PREVIEW_CHARS ||
    text.split('\n').length > MESSAGE_PREVIEW_LINES;
  return (
    <div className="flex flex-col items-start gap-0.5">
      <p
        data-slot="action-message"
        className={cn(
          'border-l-2 border-border pl-2 text-xs whitespace-pre-wrap text-muted-foreground',
          long && !expanded && 'line-clamp-3',
        )}>
        <span className="font-medium">Sends: </span>
        {text}
      </p>
      {long ? (
        <Button
          type="button"
          variant="link"
          className="ml-2 h-auto p-0 text-xs max-sm:min-h-11"
          aria-expanded={expanded}
          onClick={() => setExpanded((current) => !current)}>
          {expanded ? 'Show less' : 'Show all'}
        </Button>
      ) : null}
    </div>
  );
}
