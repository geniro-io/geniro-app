describe('ActionChip attribution', () => {
  it('says which agent published a button that is not the run’s own', async () => {
    const callee: LiveAction = {
      ...action(2, 'Merged'),
      publisher: {
        nodeId: 'engineer',
        conversationId: 'call-1',
        callId: 'call-1',
        agentLabel: 'Engineer',
      },
    };
    const container = document.createElement('div');
    root = createRoot(container);
    await act(async () =>
      root!.render(
        <ChatActionChips
          actions={[callee, action(1, 'Ping')]}
          phases={new Map()}
          onPress={() => {}}
          onDismiss={() => {}}
        />,
      ),
    );

    const [chip, own] = [
      ...container.querySelectorAll('[data-slot="action-chip"]'),
    ];
    expect(chip?.textContent).toBe('Merged· Engineer');
    expect(chip?.getAttribute('aria-label')).toBe(
      'Merged, from Engineer, sends a message',
    );
    expect(chip?.getAttribute('title')).toContain('From Engineer');
    expect(own?.querySelector('[data-slot="action-agent"]')).toBeNull();

    // The list behind `All N` names it too.
    await act(async () =>
      root!.render(
        <ActionRow
          action={callee}
          phase={undefined}
          onPress={() => {}}
          onDismiss={() => {}}
        />,
      ),
    );
    expect(
      container.querySelector('[data-slot="action-row"]')?.textContent,
    ).toContain('From Engineer');
  });
});

describe('useChatActions on a workflow run', () => {
  it('presses and dismisses through the workflow route, re-pressing a busy refusal on the timer', async () => {
    const outcome = (seq: number) =>
      Promise.resolve({
        outcome: {
          actionSeq: seq,
          actionId: 'merged',
          nodeId: 'agent',
          conversationId: '',
          state: 'succeeded' as const,
        },
      });
    const api = {
      pressWorkflowAction: vi
        .fn((args: { seq: number }) => outcome(args.seq))
        .mockImplementationOnce(() =>
          Promise.reject(daemonError(409, 'RUN_BUSY')),
        ),
      dismissWorkflowAction: vi.fn((args: { seq: number }) =>
        outcome(args.seq),
      ),
    };
    // A workflow run's state never opens a turn: the busy press is asked again.
    const state = {
      actions: [action(2, 'Merged'), action(1, 'Ping')],
      turnStartedAt: null,
      throughSeq: 100,
    };
    let chat: ReturnType<typeof useChatActions> | null = null;
    function Probe(): null {
      chat = useChatActions(api, 'run', state, () => {});
      return null;
    }
    const container = document.createElement('div');
    root = createRoot(container);
    await act(async () => root!.render(<Probe />));

    await act(async () => chat!.press(action(2, 'Merged')));
    expect(api.pressWorkflowAction).toHaveBeenCalledTimes(1);
    const first = api.pressWorkflowAction.mock.calls[0]![0];
    await act(async () => vi.advanceTimersByTime(ACTION_RETRY_MS));
    expect(api.pressWorkflowAction).toHaveBeenCalledTimes(2);
    expect(api.pressWorkflowAction.mock.calls[1]![0]).toEqual(first);
    expect(first).toEqual({
      runId: 'run',
      seq: 2,
      pressActionDto: { clientMessageId: expect.any(String) as string },
    });

    await act(async () => chat!.dismiss(action(1, 'Ping')));
    expect(api.dismissWorkflowAction).toHaveBeenCalledWith({
      runId: 'run',
      seq: 1,
    });
  });

  it('counts only a message press as starting a turn', () => {
    const of = (kind: 'message' | 'stop' | 'command'): LiveAction => ({
      ...action(1, 'X'),
      spec: { kind },
    });

    expect(pressStartsTurn(of('message'))).toBe(true);
    expect(pressStartsTurn(of('stop'))).toBe(false);
    expect(pressStartsTurn(of('command'))).toBe(false);
  });
});
