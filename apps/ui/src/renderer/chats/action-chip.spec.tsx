import { act, useState } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { LiveAction } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { ActionRow, ChatActionChips } from './action-chip';
import {
  ACTION_DONE_MS,
  ACTION_RETRY_MS,
  pressStartsTurn,
  useChatActions,
} from './use-chat-actions';

(
  globalThis as unknown as { IS_REACT_ACT_ENVIRONMENT: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function action(seq: number, label: string, once = true): LiveAction {
  return {
    seq,
    actionId: label.toLowerCase(),
    nodeId: 'agent',
    conversationId: '',
    label,
    once,
    spec: { kind: 'message', text: `${label} pressed` },
    publisher: { nodeId: 'agent', conversationId: '' },
    pending: false,
  };
}

/** The daemon's error shape, as `createDaemonApis` throws it. */
function daemonError(status: number, code: string): Error {
  return new Error(
    `daemon POST /v1/chats/run/actions/1/press failed (${status}): ${JSON.stringify({ code, message: code })}`,
  );
}

let root: Root | null = null;
beforeEach(() => {
  vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] });
});
afterEach(() => {
  act(() => root?.unmount());
  root = null;
  vi.useRealTimers();
});

/**
 * The shelf over the real hook, with run state held here the way `useRunState`
 * holds it: `refresh` re-reads `server`, which the fake press route edits.
 */
function harness(
  initial: LiveAction[],
  beforePress?: (action: LiveAction) => Promise<unknown>,
) {
  const hooks = beforePress === undefined ? undefined : { beforePress };
  const server = {
    actions: initial,
    turnStartedAt: null as string | null,
    throughSeq: 100,
  };
  const api = {
    pressChatAction: vi.fn(
      (args: { seq: number; pressActionDto: { clientMessageId: string } }) => {
        const pressed = server.actions.find((a) => a.seq === args.seq);
        if (pressed?.once) {
          server.actions = server.actions.filter((a) => a.seq !== args.seq);
        }
        return Promise.resolve({
          outcome: {
            actionSeq: args.seq,
            actionId: pressed?.actionId ?? '',
            nodeId: 'agent',
            conversationId: '',
            state: 'succeeded' as const,
          },
        });
      },
    ),
    dismissChatAction: vi.fn((args: { seq: number }) => {
      server.actions = server.actions.filter((a) => a.seq !== args.seq);
      return Promise.resolve({
        outcome: {
          actionSeq: args.seq,
          actionId: '',
          nodeId: 'agent',
          conversationId: '',
          state: 'dismissed' as const,
        },
      });
    }),
  };
  let setState: ((next: typeof server) => void) | null = null;
  function Shelf(): React.JSX.Element {
    const [state, set] = useState({ ...server });
    setState = set;
    const refresh = useLatestCallback(() => set({ ...server }), []);
    const chat = useChatActions(api, 'run', state, refresh, hooks);
    return (
      <ChatActionChips
        actions={chat.actions}
        phases={chat.phases}
        onPress={chat.press}
        onDismiss={chat.dismiss}
      />
    );
  }
  const container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  return {
    api,
    server,
    container,
    render: async () => {
      await act(async () => root!.render(<Shelf />));
    },
    /** The daemon's run state changes and the client re-reads it. */
    reread: async () => {
      await act(async () => setState!({ ...server }));
    },
    chips: () =>
      [...container.querySelectorAll('[data-slot="action-chip"]')].map(
        (chip) => chip.textContent,
      ),
    press: async (label: string) => {
      const chip = [
        ...container.querySelectorAll<HTMLButtonElement>(
          '[data-slot="action-chip"]',
        ),
      ].find((node) => node.textContent === label);
      await act(async () => chip!.click());
    },
  };
}

describe('ChatActionChips', () => {
  it('one-shot chip leaves the shelf after press; overflow collapses past the fit', async () => {
    const shelf = harness([
      action(3, 'Deploy'),
      action(2, 'Merged'),
      action(1, 'Ping', false),
    ]);
    await shelf.render();

    // Newest first, two in the row, the rest behind `All 3`.
    expect(shelf.chips()).toEqual(['Deploy', 'Merged']);
    const overflow = shelf.container.querySelector(
      '[data-slot="action-overflow"]',
    );
    expect(overflow?.textContent).toContain('All3');
    expect(overflow?.className).not.toContain('sm:hidden');

    await shelf.press('Merged');

    expect(shelf.api.pressChatAction).toHaveBeenCalledWith({
      runId: 'run',
      seq: 2,
      pressActionDto: { clientMessageId: expect.any(String) as string },
    });
    expect(shelf.chips()).toEqual(['Deploy', 'Ping']);
    // Two left fit the row, so the list is for the phone alone.
    expect(
      shelf.container.querySelector('[data-slot="action-overflow"]')?.className,
    ).toContain('sm:hidden');
  });

  it('a reusable chip shows a brief check after a press, then returns', async () => {
    const shelf = harness([action(1, 'Ping', false)]);
    await shelf.render();

    await shelf.press('Ping');
    const glyph = (): string | null | undefined =>
      shelf.container
        .querySelector('[data-slot="action-chip"] svg')
        ?.getAttribute('class');
    expect(glyph()).toContain('lucide-check');

    await act(async () => vi.advanceTimersByTime(ACTION_DONE_MS));
    expect(glyph()).not.toContain('lucide-check');
    expect(shelf.chips()).toEqual(['Ping']);
  });

  it('keeps the shelf chip height on a phone, for the chips and their `All N`', async () => {
    const shelf = harness([action(2, 'Deploy'), action(1, 'Merged')]);
    await shelf.render();

    const buttons = [
      ...shelf.container.querySelectorAll<HTMLElement>(
        '[data-slot="action-chip"], [data-slot="action-overflow"] button',
      ),
    ];
    expect(buttons).toHaveLength(3);
    for (const button of buttons) {
      expect(button.className).toContain('h-[22px]');
      expect(button.className).not.toMatch(/max-sm:h-/);
    }
  });

  it('draws nothing when no action is live', async () => {
    const shelf = harness([]);
    await shelf.render();

    expect(
      shelf.container.querySelector('[data-slot="chat-actions"]'),
    ).toBeNull();
  });

  it('a press the chat refuses as busy waits for the turn to settle and goes again with the same id', async () => {
    const shelf = harness([action(1, 'Merged')]);
    shelf.server.turnStartedAt = '2026-10-18T10:00:00Z';
    await shelf.render();
    shelf.api.pressChatAction.mockImplementationOnce(() =>
      Promise.reject(daemonError(409, 'RUN_BUSY')),
    );

    await shelf.press('Merged');
    const first = shelf.api.pressChatAction.mock.calls[0]![0];
    const chip = shelf.container.querySelector('[data-slot="action-chip"]');
    expect(chip?.getAttribute('aria-busy')).toBe('true');

    // Still running: nothing is re-sent, however long it takes.
    await act(async () => vi.advanceTimersByTime(ACTION_RETRY_MS * 3));
    expect(shelf.api.pressChatAction).toHaveBeenCalledTimes(1);

    shelf.server.turnStartedAt = null;
    await shelf.reread();
    await act(async () => vi.advanceTimersByTime(ACTION_RETRY_MS));

    expect(shelf.api.pressChatAction).toHaveBeenCalledTimes(2);
    expect(shelf.api.pressChatAction.mock.calls[1]![0]).toEqual(first);
    expect(shelf.chips()).toEqual([]);
  });

  it('dismisses from the overflow list and the button leaves', async () => {
    const shelf = harness([
      action(3, 'Deploy'),
      action(2, 'Merged'),
      action(1, 'Ping'),
    ]);
    await shelf.render();

    const trigger = shelf.container.querySelector<HTMLButtonElement>(
      '[data-slot="action-overflow"] button',
    );
    await act(async () => trigger!.click());
    const more = document.querySelector<HTMLButtonElement>(
      '[aria-label="More for Ping"]',
    );
    await act(async () => more!.click());
    const dismiss = [
      ...document.querySelectorAll<HTMLElement>('[role="option"]'),
    ].find((option) => option.textContent?.includes('Dismiss'));
    await act(async () => dismiss!.click());

    expect(shelf.api.dismissChatAction).toHaveBeenCalledWith({
      runId: 'run',
      seq: 1,
    });
    expect(shelf.api.pressChatAction).not.toHaveBeenCalled();
    expect(
      shelf.container.querySelector('[data-slot="action-overflow"]')?.className,
    ).toContain('sm:hidden');
  });

  it('re-reads the live set when the press finds the button gone', async () => {
    const shelf = harness([action(1, 'Merged')]);
    await shelf.render();
    shelf.api.pressChatAction.mockImplementationOnce(() => {
      // Pressed on another device a moment ago.
      shelf.server.actions = [];
      return Promise.reject(daemonError(409, 'ACTION_GONE'));
    });

    await shelf.press('Merged');

    expect(shelf.chips()).toEqual([]);
  });

  it('runs the surface flush before the press reaches the daemon', async () => {
    let flushed: () => void = () => undefined;
    const flush = vi.fn(
      () =>
        new Promise<void>((resolve) => {
          flushed = resolve;
        }),
    );
    const shelf = harness([action(1, 'Merged')], flush);
    await shelf.render();

    await shelf.press('Merged');
    expect(flush).toHaveBeenCalledTimes(1);
    expect(flush).toHaveBeenCalledWith(
      expect.objectContaining({ seq: 1, label: 'Merged' }),
    );
    expect(shelf.api.pressChatAction).not.toHaveBeenCalled();

    await act(async () => flushed());
    expect(shelf.api.pressChatAction).toHaveBeenCalledTimes(1);
  });

  it('shows a refusal on the chip and keeps it for a retry', async () => {
    const shelf = harness([action(1, 'Merged')]);
    await shelf.render();
    shelf.api.pressChatAction.mockImplementationOnce(() =>
      Promise.reject(daemonError(500, 'INTERNAL')),
    );

    await shelf.press('Merged');

    const chip = shelf.container.querySelector('[data-slot="action-chip"]');
    expect(chip?.getAttribute('aria-label')).toBe(
      'Merged, sends a message — failed: INTERNAL',
    );
    expect(chip?.getAttribute('aria-busy')).toBeNull();
    await shelf.press('Merged');
    expect(shelf.api.pressChatAction).toHaveBeenCalledTimes(2);
  });
});

