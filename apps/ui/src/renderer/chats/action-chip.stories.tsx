import type { Meta, StoryObj } from '@storybook/react-vite';
import { useState } from 'react';

import type { LiveAction } from '../autogenerated';
import { ChatActionChips } from './action-chip';
import type { ActionPressPhase } from './use-chat-actions';

function action(
  seq: number,
  label: string,
  kind: LiveAction['spec']['kind'] = 'message',
  description?: string,
): LiveAction {
  return {
    seq,
    actionId: label.toLowerCase().replace(/\s+/g, '-'),
    nodeId: 'agent',
    conversationId: '',
    label,
    ...(description === undefined ? {} : { description }),
    once: true,
    spec:
      kind === 'command'
        ? {
            kind,
            argv: ['pnpm', 'test:e2e', '--grep', 'checkout flow'],
            cwd: '/Users/dev/projects/geniro-app',
            timeoutMs: 600_000,
          }
        : { kind, text: `${label} — continue` },
    publisher: { nodeId: 'agent', conversationId: '' },
    pending: false,
  };
}

const LIVE: LiveAction[] = [
  action(5, 'PR merged', 'message', 'Tell the agent the pull request landed'),
  action(4, 'Stop preview', 'stop', 'Stops the preview server on :3000'),
  action(3, 'Run e2e', 'command'),
  action(2, 'Deploy approved'),
];

/** Drives presses locally: a press spins, then the one-shot leaves. */
function Shelf({
  initial,
  initialPhases = new Map(),
}: {
  initial: LiveAction[];
  initialPhases?: ReadonlyMap<number, ActionPressPhase>;
}): React.JSX.Element {
  const [actions, setActions] = useState(initial);
  const [phases, setPhases] = useState(initialPhases);
  return (
    <div className="flex min-h-7 items-center gap-1.5 px-1">
      <ChatActionChips
        actions={actions}
        phases={phases}
        onPress={(pressed) => {
          setPhases(new Map([[pressed.seq, { kind: 'pressing' }]]));
          setTimeout(() => {
            setActions((current) =>
              current.filter((entry) => entry.seq !== pressed.seq),
            );
            setPhases(new Map());
          }, 800);
        }}
        onDismiss={(dismissed) =>
          setActions((current) =>
            current.filter((entry) => entry.seq !== dismissed.seq),
          )
        }
      />
    </div>
  );
}

const meta = {
  title: 'Chats/ChatActionChips',
  component: Shelf,
  args: { initial: LIVE },
  decorators: [
    (story) => (
      <div className="flex h-[360px] w-[36rem] items-end bg-background p-3 text-foreground">
        {story()}
      </div>
    ),
  ],
} satisfies Meta<typeof Shelf>;

export default meta;
type Story = StoryObj<typeof meta>;

