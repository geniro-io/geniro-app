import {
  ActionOutcomeState,
  ActionSpecKindEnum,
  type ItemDto as ChatItem,
} from '../autogenerated';

/**
 * TWIN PARSER: `ActionPayloadSchema` / `ActionOutcomePayloadSchema` in
 * `apps/daemon/src/v1/agents/chat.types.ts`, which writes these rows. An item's
 * payload is `unknown` on the wire, so each field is read defensively and a
 * row that does not parse draws nothing.
 */

/** One publish of an agent's button, as its transcript card draws it. */
export interface ActionCardView {
  actionId: string;
  label: string;
  description: string | null;
  kind: ActionSpecKindEnum;
  /** What a message press sends — shown so the user sees it before pressing. */
  text: string | null;
  /** What a stop press stops — shown, like `text`, before it is pressed. */
  targets: StopTargetView[];
  once: boolean;
  nodeId: string;
  conversationId: string;
  /** Who published it, when a press must say so — another agent of a workflow. */
  agentLabel: string | null;
  /** The call its publisher was answering, which the card links to. */
  callId: string | null;
}

/** One process a stop action stops. */
export interface StopTargetView {
  pid: number;
  command: string;
}

/** What happened to a publish, as the card's status line reads it. */
export interface ActionOutcomeView {
  actionSeq: number;
  state: ActionOutcomeState;
  exitCode: number | null;
  error: string | null;
  /** A stop whose processes had all exited before the press. */
  alreadyStopped: boolean;
  at: string;
}

const KINDS: ReadonlySet<string> = new Set(Object.values(ActionSpecKindEnum));
const STATES: ReadonlySet<string> = new Set(Object.values(ActionOutcomeState));

function record(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

function text(value: unknown): string | null {
  return typeof value === 'string' && value !== '' ? value : null;
}

export function readActionPayload(item: ChatItem): ActionCardView | null {
  if (item.kind !== 'action') {
    return null;
  }
  const payload = record(item.payload);
  const spec = record(payload?.spec);
  const publisher = record(payload?.publisher);
  const actionId = text(payload?.actionId);
  const label = text(payload?.label);
  const kind = spec?.kind;
  const nodeId = text(publisher?.nodeId);
  const conversationId = publisher?.conversationId;
  if (
    actionId === null ||
    label === null ||
    typeof kind !== 'string' ||
    !KINDS.has(kind) ||
    nodeId === null ||
    typeof conversationId !== 'string'
  ) {
    return null;
  }
  return {
    actionId,
    label,
    description: text(payload?.description),
    kind: kind as ActionSpecKindEnum,
    text: text(spec?.text),
    targets: Array.isArray(spec?.targets)
      ? spec.targets.flatMap((value: unknown) => {
          const target = record(value);
          const pid = target?.pid;
          const command = text(target?.command);
          return typeof pid === 'number' && command !== null
            ? [{ pid, command }]
            : [];
        })
      : [],
    once: payload?.once !== false,
    nodeId,
    conversationId,
    agentLabel: text(publisher?.agentLabel),
    callId: text(publisher?.callId),
  };
}

export function readActionOutcome(item: ChatItem): ActionOutcomeView | null {
  if (item.kind !== 'action_outcome') {
    return null;
  }
  const payload = record(item.payload);
  const actionSeq = payload?.actionSeq;
  const state = payload?.state;
  if (
    typeof actionSeq !== 'number' ||
    !Number.isInteger(actionSeq) ||
    typeof state !== 'string' ||
    !STATES.has(state)
  ) {
    return null;
  }
  const exitCode = payload?.exitCode;
  return {
    actionSeq,
    state: state as ActionOutcomeState,
    exitCode: typeof exitCode === 'number' ? exitCode : null,
    error: text(payload?.error),
    alreadyStopped: payload?.alreadyStopped === true,
    at: item.createdAt,
  };
}
