/**
 * Live per-agent execution state, derived purely from a run's transcript
 * items. Every turn an agent node runs — DAG-scheduled or a callee sub-turn
 * started by `call_agent` — emits a `status` item `{nodeId, status:'running'}`
 * on spawn and a terminal one on settle, so the number of currently-live
 * parallel turns is the running count minus the settled count. `turn_complete`
 * items carry the CLI's usage, giving the agent's current context footprint
 * and its cumulative spend.
 */
export interface AgentActivity {
  /** Turns of this agent live RIGHT NOW (an orchestrator can run several). */
  activeTurns: number;
  /** How many turns of this agent have STARTED over the run's lifetime. */
  turnStarts: number;
  /** The node's most recent status transition; null before its first one. */
  lastStatus: NodeRunStatus | null;
  /** Prompt-side tokens of the agent's LATEST settled turn (its context). */
  contextTokens: number | null;
  /** That turn's model window as the CLI reported it; null if it reported none. */
  contextWindowTokens: number | null;
  /** Cumulative cost across all of the agent's settled turns. */
  spentUsd: number | null;
  /**
   * The agent's call threads — one per `call_agent` conversation targeting it,
   * derived from the caller's call_started/call_result items (which carry the
   * callee node id and, on settle, the thread's CLI session id).
   */
  callThreads: AgentCallThread[];
}

/** One `call_agent` conversation of an agent, as the transcript records it. */
export interface AgentCallThread {
  callId: string;
  /** The first message of the thread — its display label. */
  message: string | null;
  status: 'running' | 'completed' | 'failed';
  /** The thread's CLI session id once settled — its terminal/resume handle. */
  sessionId: string | null;
}

/**
 * The activity-map key for single-agent chat items (their nodeId is null).
 *
 * NUL-prefixed so it cannot collide with a real node id. A workflow node id is
 * any non-empty string, so `agent` is a legal — and obvious — node name; while
 * the sentinel was that same word, such a node was read as "the chat's agent"
 * and every site that excludes the sentinel (`nodeId !== CHAT_AGENT_KEY`)
 * silently excluded the node too, dropping it from the working-agents set and
 * from the panel's extras list. Same defect, and same fix, as
 * `CHAT_LIVE_KEY` on the live plane (`live-text.ts`).
 */
export const CHAT_AGENT_KEY = '\u0000chat';

/**
 * One agent as the agents panel displays it — workflow node metadata merged
 * with its live {@link AgentActivity}.
 */
export interface AgentDisplay {
  /** Node id ({@link CHAT_AGENT_KEY} for a single-agent chat). */
  id: string;
  name: string;
  /** The CLI driving it; null for a node no longer in the workflow. */
  agent: CliKind | null;
  /**
   * The agent config directory this node's turns run under, or null.
   *
   * Carried on the DISPLAY row because a profile carries its own MCP servers:
   * two nodes on the same CLI with different config directories genuinely load
   * different sets, so the panel cannot ask one question per CLI and paint the
   * answer on both.
   */
  configDir: string | null;
  status: RunStatusKind;
  activeTurns: number;
  contextTokens: number | null;
  /**
   * The window {@link contextTokens} is measured against, as the CLI reported
   * it for the model it ran. Null means UNREPORTED, and is rendered as such —
   * the meter shows the count without a denominator rather than measuring
   * against a window nobody named.
   */
  contextWindowTokens: number | null;
  spentUsd: number | null;
  /** Every conversation the agent has run — the panel's expandable list. */
  threads: AgentThread[];
}

/** One conversation of an agent, as the agents panel lists it. */
export interface AgentThread {
  /**
   * 'main' for the node's own DAG/chat conversation, the call id for a call
   * thread, and for a sub-agent the id of the tool call that launched it.
   */
  id: string;
  /**
   * Which KIND of conversation this is, and the three are genuinely different
   * things rather than three labels: a `main` thread is the node's own, a
   * `call` thread is a sub-session with ANOTHER node over the geniro call
   * runtime, and a `subagent` is one CLI's own in-process delegate — which
   * exists only inside its parent's turn and has no CLI session of its own.
   * That last distinction is load-bearing: it is why a sub-agent row offers no
   * terminal handoff, since there is no session for `--resume` to target.
   */
  kind: 'main' | 'call' | 'subagent';
  label: string;
  status: RunStatusKind;
  /**
   * Resume handle for a call thread's terminal (from its call_result item);
   * null for main threads — the daemon resolves those from node_state — and
   * always null for a sub-agent, which never had one.
   */
  sessionId: string | null;
}

/**
 * The display threads an agent's activity implies: its main conversation
 * (when the node ran a DAG turn — detected as more turn starts than call
 * threads) followed by each call thread.
 */
export function threadsOf(activity: AgentActivity | undefined): AgentThread[] {
  if (!activity) {
    return [];
  }
  const calls = activity.callThreads.map((thread): AgentThread => ({
    id: thread.callId,
    kind: 'call',
    label: thread.message
      ? `${thread.callId} · ${thread.message}`
      : thread.callId,
    status: thread.status,
    sessionId: thread.sessionId,
  }));
  if (activity.turnStarts <= activity.callThreads.length) {
    return calls; // a call-only node never ran a main DAG turn
  }
  const runningCalls = calls.filter((t) => t.status === 'running').length;
  const main: AgentThread = {
    id: 'main',
    kind: 'main',
    label: 'Main conversation',
    // The node's live turns beyond its live calls ARE the main turn; once
    // settled, the node's last transition is the best record of how it ended.
    status:
      activity.activeTurns > runningCalls
        ? 'running'
        : activity.lastStatus && activity.lastStatus !== 'running'
          ? activity.lastStatus
          : 'completed',
    sessionId: null,
  };
  return [main, ...calls];
}

/**
 * The sub-agent threads a folded transcript implies, grouped by the agent that
 * launched each one.
 *
 * Lives here rather than inline in `Chats.tsx` because this module owns the
 * {@link AgentThread} shape and its only other builder ({@link threadsOf}) —
 * and because the status translation below is a real decision that deserves to
 * be reachable without mounting a 3.5k-line component.
 *
 * `stopped` becomes `cancelled`: a delegate whose run or turn ended before it
 * reported back did stop without completing, and `cancelled` is the only word
 * in {@link RunStatusKind} that says that. It is the nearest true term, not a
 * claim that the user cancelled anything.
 */
export function subagentThreadsByAgent(
  blocks: readonly SubagentBlockEntry[],
  chatAgentKey: string,
  runSettledAt: RunSettleAt = null,
): Map<string, AgentThread[]> {
  const byAgent = new Map<string, AgentThread[]>();
  for (const block of blocks) {
    const status = subagentBlockStatus(block, runSettledAt);
    const key = block.nodeId ?? chatAgentKey;
    const threads = byAgent.get(key) ?? [];
    threads.push({
      id: block.id,
      kind: 'subagent',
      label: subagentTitle(block),
      status:
        status === 'completed'
          ? 'completed'
          : status === 'failed'
            ? 'failed'
            : status === 'stopped'
              ? 'cancelled'
              : 'running',
      sessionId: null,
    });
    byAgent.set(key, threads);
  }
  return byAgent;
}

/**
 * The display status an agent's activity implies (any live turn = running).
 *
 * A node with NO activity is `pending`, the same word its own `node_state` row
 * carries — never a second one for the same fact. It used to answer `idle`
 * here and `pending` the moment any status item existed, so one unchanged node
 * changed word on the strength of a row nobody had looked at.
 */
export function displayStatus(
  activity: AgentActivity | undefined,
): RunStatusKind {
  if (!activity) {
    return 'pending';
  }
  if (activity.activeTurns > 0) {
    return 'running';
  }
  return activity.lastStatus ?? 'pending';
}

const NODE_STATUSES: ReadonlySet<string> = new Set([
  'pending',
  'running',
  'completed',
  'failed',
  'cancelled',
  'skipped',
]);

function asRecord(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null
    ? (value as Record<string, unknown>)
    : null;
}

/** Derive each agent's live state from a run's items (seq-ordered). */
export function computeAgentActivity(
  items: ChatItem[],
): Map<string, AgentActivity> {
  const byAgent = new Map<string, AgentActivity>();
  const entry = (key: string): AgentActivity => {
    let existing = byAgent.get(key);
    if (!existing) {
      existing = {
        activeTurns: 0,
        turnStarts: 0,
        lastStatus: null,
        contextTokens: null,
        contextWindowTokens: null,
        spentUsd: null,
        callThreads: [],
      };
      byAgent.set(key, existing);
    }
    return existing;
  };
  for (const item of items) {
    const key = item.nodeId ?? CHAT_AGENT_KEY;
    if (endsContextHistory(item)) {
      // A compaction empties the window, so every reading above this row was
      // taken on a conversation that is over — carrying one past it is what
      // left the ring full directly after a `/compact`. The WINDOW is kept: it
      // is a property of the model, which a compaction does not change, and
      // dropping it would leave the next count with nothing to divide by.
      //
      // A reading the compaction itself reported lands BELOW this row and
      // overwrites the null, which is why this is a reset rather than a stop.
      entry(key).contextTokens = null;
      continue;
    }
    if (item.kind === 'status') {
      const status = asRecord(item.payload)?.status;
      if (typeof status !== 'string' || !NODE_STATUSES.has(status)) {
        continue;
      }
      const agent = entry(key);
      agent.lastStatus = status as NodeRunStatus;
      if (status === 'running') {
        agent.activeTurns += 1;
        agent.turnStarts += 1;
      } else if (status !== 'pending') {
        // A terminal transition settles ONE live turn. `skipped` (and a
        // defensive clamp) can arrive without a matching start — never
        // go negative.
        agent.activeTurns = Math.max(0, agent.activeTurns - 1);
      }
      continue;
    }
    // Call items are persisted under the CALLER's node — the thread belongs
    // to the CALLEE named in the payload.
    if (item.kind === 'call_started') {
      const payload = asRecord(item.payload);
      const callId = payload?.callId;
      const calleeNodeId = payload?.calleeNodeId;
      if (typeof callId !== 'string' || typeof calleeNodeId !== 'string') {
        continue;
      }
      const message = payload?.message;
      entry(calleeNodeId).callThreads.push({
        callId,
        message: typeof message === 'string' ? message : null,
        status: 'running',
        sessionId: null,
      });
      continue;
    }
    if (item.kind === 'call_result') {
      const payload = asRecord(item.payload);
      const callId = payload?.callId;
      const calleeNodeId = payload?.calleeNodeId;
      if (typeof callId !== 'string' || typeof calleeNodeId !== 'string') {
        continue;
      }
      const thread = entry(calleeNodeId).callThreads.find(
        (t) => t.callId === callId,
      );
      if (!thread) {
        continue;
      }
      thread.status = payload?.status === 'ok' ? 'completed' : 'failed';
      const sessionId = payload?.sessionId;
      if (typeof sessionId === 'string') {
        thread.sessionId = sessionId;
      }
      continue;
    }
    if (item.kind === 'turn_complete') {
      const usage = asRecord(asRecord(item.payload)?.usage);
      if (!usage) {
        continue;
      }
      const agent = entry(key);
      // A reported 0 is rejected for the same reason as the window below: it
      // is not a measurement, it is a turn that reported nothing. Overwriting
      // a real figure with it made the meter read `0 of 200k` mid-conversation
      // — and the live plane already treats a non-positive count as absent
      // (`live-text.ts`), so accepting it only here was the odd one out.
      const context = usage.contextTokens ?? usage.inputTokens;
      if (typeof context === 'number' && context > 0) {
        agent.contextTokens = context;
      }
      // REMEMBERED, on exactly the rule the count above follows — and it did
      // not used to be, which is the `ctx 357.2k` with no ring beside it.
      //
      // A turn that reports no window has said NOTHING about the model's
      // window; it is not a measurement of one. Overwriting with its silence
      // wiped a window the previous turn had reported, and since the count IS
      // guarded, what was left was a bare number where the ring had been —
      // for the rest of the chat, until some later turn reported a window
      // again. Measured in the author's own `geniro.db`: five `turn_complete`
      // rows across three runs carry `{inputTokens:0, outputTokens:0,
      // contextTokens:null, contextWindowTokens:null, costUsd:0}` — a turn
      // that ended having reported no accounting at all (one of them followed
      // three seconds later by `Tool permission request failed: AbortError:
      // Stream closed`). That is also why it read as intermittent.
      //
      // The reason recorded for the old wipe was a MODEL CHANGE — a stale 1M
      // window keeping a 200k model at 3% full. It could never have served
      // that: the window and the model are read from the same `modelUsage`
      // entry (`claude-usage.utils.ts` → `readContextWindow`), so a turn that
      // switched model reports the NEW window and overwrites correctly, and a
      // null window comes with a null `contextModel` — an absence of
      // information, never the name of a smaller model. The turns the wipe
      // actually fired on were the ones that measured nothing.
      //
      // A 0 is rejected for the same reason it is on the count: consumers read
      // this as a denominator, and `ContextMeter` would render 0 as "no window
      // reported" anyway.
      const window = usage.contextWindowTokens;
      if (typeof window === 'number' && window > 0) {
        agent.contextWindowTokens = window;
      }
      if (typeof usage.costUsd === 'number') {
        agent.spentUsd = (agent.spentUsd ?? 0) + usage.costUsd;
      }
    }
  }
  return byAgent;
}

/**
 * Compact token count: 950 → "950", 12_400 → "12.4k", 1_200_000 → "1.2M",
 * 16_603_400_000 → "16.6B".
 *
 * The BILLION step is not hypothetical padding. A month of cache reads reaches
 * it easily — measured on a real 26-day ledger, `cacheReadTokens` was 16.6e9,
 * which without this step rendered as `16603.4M`: five significant digits under
 * a suffix that no longer compacts anything, printed as the largest figure on
 * the Stats page. Anything past a trillion keeps growing the `B` figure rather
 * than gaining another suffix — a `T` of tokens is not a scale this app has a
 * reason to be ready for, and an unfamiliar suffix costs more than a long number.
 */
export function formatTokens(count: number): string {
  if (count >= 1_000_000_000) {
    return `${(count / 1_000_000_000).toFixed(1).replace(/\.0$/, '')}B`;
  }
  if (count >= 1_000_000) {
    return `${(count / 1_000_000).toFixed(1).replace(/\.0$/, '')}M`;
  }
  if (count >= 1_000) {
    return `${(count / 1_000).toFixed(1).replace(/\.0$/, '')}k`;
  }
  return String(count);
}

/**
 * Money — the app's TWO formats, and every dollar on screen comes from one of
 * them. They agree everywhere above a cent (`$0.24`, `$21,547.80`) and differ
 * only below it, where a bare 2-decimal rounding would print `$0.00` and claim
 * a turn cost nothing. Neither is willing to say that; they refuse it
 * differently, and which refusal is right depends on the surface.
 *
 * Both are GROUPED, because these render a lifetime total as well as a single
 * turn's cost. Ungrouped, that total was `$21547.80` — seven digits the reader
 * has to count in threes to know whether it is twenty-one thousand or two
 * hundred and fifteen.
 *
 * Both are pinned to `en-US` rather than the machine's locale, unlike the day
 * labels beside them, and that is deliberate: the `$` is hardcoded because the
 * daemon records USD and nothing else, so a machine-locale number would pair a
 * dollar sign with `21.547,80` — a figure that reads as twenty-one dollars to
 * half of Europe. One currency, one notation.
 */
const USD_DIGITS = new Intl.NumberFormat('en-US', {
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
});

const USD_SUBCENT = new Intl.NumberFormat('en-US', {
  minimumFractionDigits: 4,
  maximumFractionDigits: 4,
});

/**
 * A BOUND: sub-cent spend reads `<$0.01`.
 *
 * For aggregates in a column — the Stats breakdowns, the context meter's
 * run total — where every figure is the same width and the reader is comparing
 * rows, not pricing one of them. `$0.0034` in a `tabular-nums` column of
 * two-decimal figures is four characters nothing else has.
 */
export function formatUsd(amount: number): string {
  if (amount > 0 && amount < 0.01) {
    return '<$0.01';
  }
  return `$${USD_DIGITS.format(amount)}`;
}

/**
 * A VALUE: sub-cent spend reads `$0.0034`.
 *
 * For a figure that stands alone and IS the point — the thread header's cost,
 * the `✓ done · 21s · $0.42` note under a finished turn. Cheap turns are most
 * of them, and `<$0.01` on every one of them tells the reader nothing they
 * could compare.
 *
 * Note what it is NOT: four decimals ALWAYS. The transcript note used a bare
 * `toFixed(4)`, so a 42-cent turn read `$0.4200` two hundred pixels under a
 * header saying `$0.42` — the same number, in two notations, on one screen.
 */
export function formatExactUsd(amount: number): string {
  if (amount > 0 && amount < 0.01) {
    return `$${USD_SUBCENT.format(amount)}`;
  }
  return `$${USD_DIGITS.format(amount)}`;
}
