describe('AgentEventStack', () => {
  it('stacks its events one under the other, in the order given', () => {
    const el = render(
      <AgentEventStack>
        <MemberEventCard
          kind="finished"
          name="Researcher"
          memberId="m-r"
          callId="call-1"
        />
        <MemberEventCard
          kind="failed"
          name="Backend"
          memberId="m-b"
          callId="call-2"
        />
      </AgentEventStack>,
    );
    expect(el.querySelector('[data-slot="agent-event-stack"]')).not.toBeNull();
    const kinds = [
      ...el.querySelectorAll<HTMLElement>('[data-slot="agent-event-card"]'),
    ].map((article) => article.dataset.kind);
    expect(kinds).toEqual(['finished', 'failed']);
  });
});

describe('MemberEventCard', () => {
  it.each([
    ['finished', 'Done'],
    ['failed', 'Failed'],
    ['cancelled', 'Cancelled'],
    ['skipped', 'Skipped'],
    ['asked', 'Question from'],
    ['answered', 'Answered question from'],
    ['no-answer', 'Question from · no answer'],
    ['message', 'Message to'],
    ['answer', 'Answer to'],
  ] as const)('draws a %s event under the label "%s"', (kind, label) => {
    const el = render(
      <MemberEventCard
        kind={kind}
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
      />,
    );
    expect(card(el).dataset.kind).toBe(kind);
    expect(
      el.querySelector('[data-slot="agent-event-label"]')?.textContent,
    ).toBe(label);
  });

  it('heads the event with the member it is about, its face and the call it belongs to', () => {
    const el = render(
      <MemberEventCard
        kind="finished"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
      />,
    );
    expect(
      el.querySelector('[data-slot="agent-event-title"]')?.textContent,
    ).toBe('Researcher');
    expect(
      el.querySelector<HTMLElement>('[data-slot="agent-event-face"]')?.dataset
        .face,
    ).toBe('member');
    expect(
      el.querySelector('[data-slot="agent-event-handle"]')?.textContent,
    ).toBe('call-7');
  });

  it('names the agent the event was reported to beside its label', () => {
    const el = render(
      <MemberEventCard
        kind="message"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        agent="Manager"
      />,
    );
    expect(
      el.querySelector('[data-slot="agent-event-member"]')?.textContent,
    ).toBe('· Manager');
  });

  it('draws the answer a finished call gave, its markdown rendered', () => {
    const el = render(
      <MemberEventCard
        kind="finished"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        text="Found two stale **fixtures**."
      />,
    );
    const body = el.querySelector<HTMLElement>(
      '[data-slot="agent-event-text"]',
    );
    expect(body?.textContent).toContain('Found two stale fixtures.');
    expect(body?.querySelector('strong')?.textContent).toBe('fixtures');
    expect(body?.dataset.clamped).toBeUndefined();
    expect(
      el.querySelector('[data-slot="agent-event-text-toggle"]'),
    ).toBeNull();
  });

  it('folds an answer longer than eight lines behind Show more, and Show more unfolds it', () => {
    const el = render(
      <MemberEventCard
        kind="finished"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        text={stepLines(12)}
      />,
    );
    const body = el.querySelector<HTMLElement>(
      '[data-slot="agent-event-text"]',
    )!;
    expect(body.dataset.clamped).toBe('true');
    const toggle = el.querySelector<HTMLButtonElement>(
      '[data-slot="agent-event-text-toggle"]',
    )!;
    expect(toggle.textContent).toContain('Show more');

    act(() => toggle.click());

    expect(body.dataset.clamped).toBeUndefined();
    expect(body.textContent).toContain('step 12');
  });

  it('leaves an answer of exactly eight lines whole', () => {
    const el = render(
      <MemberEventCard
        kind="finished"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        text={stepLines(8)}
      />,
    );
    expect(
      el.querySelector<HTMLElement>('[data-slot="agent-event-text"]')?.dataset
        .clamped,
    ).toBeUndefined();
    expect(
      el.querySelector('[data-slot="agent-event-text-toggle"]'),
    ).toBeNull();
  });

  it('offers the options of a question inert: each one drawn, none pressable', () => {
    const el = render(
      <MemberEventCard
        kind="asked"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        text="Which branch should I keep?"
        options={['Keep the branch', 'Delete it']}
      />,
    );
    const buttons = [...card(el).querySelectorAll<HTMLButtonElement>('button')];
    expect(buttons.map((button) => button.textContent)).toEqual([
      'Keep the branch',
      'Delete it',
    ]);
    expect(buttons.every((button) => button.disabled)).toBe(true);
  });

  it('marks a question as waiting on the reader only when it is waiting', () => {
    const waiting = render(
      <MemberEventCard
        kind="asked"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        waiting
      />,
    );
    expect(
      waiting.querySelector('[data-slot="agent-event-waiting"]')?.textContent,
    ).toBe('Waiting on you');

    const answered = render(
      <MemberEventCard
        kind="asked"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        waiting={false}
      />,
    );
    expect(
      answered.querySelector('[data-slot="agent-event-waiting"]'),
    ).toBeNull();
  });

  it('draws what became of the event in red for a failure and muted otherwise, and nothing when there is no outcome', () => {
    const failed = render(
      <MemberEventCard
        kind="failed"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        outcome={{
          text: 'Stopped after the second retry',
          tone: 'destructive',
        }}
      />,
    );
    const red = failed.querySelector<HTMLElement>(
      '[data-slot="agent-event-outcome"]',
    );
    expect(red?.textContent).toBe('Stopped after the second retry');
    expect(red?.className).toContain('text-destructive');

    const done = render(
      <MemberEventCard
        kind="finished"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        outcome={{ text: 'Merged into the branch' }}
      />,
    );
    const muted = done.querySelector<HTMLElement>(
      '[data-slot="agent-event-outcome"]',
    );
    expect(muted?.textContent).toBe('Merged into the branch');
    expect(muted?.className).toContain('text-muted-foreground');
    expect(muted?.className).not.toContain('text-destructive');

    const bare = render(
      <MemberEventCard
        kind="finished"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
      />,
    );
    expect(bare.querySelector('[data-slot="agent-event-outcome"]')).toBeNull();
  });

  it('opens its call from the card when the view can show that call', () => {
    const open = vi.fn();
    const el = render(
      <RevealCallContext.Provider
        value={(callId) => (callId === 'call-7' ? open : null)}>
        <MemberEventCard
          kind="finished"
          name="Researcher"
          memberId="m-researcher"
          callId="call-7"
        />
      </RevealCallContext.Provider>,
    );
    const button = el.querySelector<HTMLButtonElement>(
      '[data-slot="agent-event-open-call"]',
    );
    expect(button?.textContent).toBe('Open call');

    act(() => button!.click());

    expect(open).toHaveBeenCalledTimes(1);
  });

  it('draws no open button for an event that belongs to no call', () => {
    const el = render(
      <RevealCallContext.Provider value={() => vi.fn()}>
        <MemberEventCard
          kind="finished"
          name="Researcher"
          memberId="m-researcher"
          callId={null}
        />
      </RevealCallContext.Provider>,
    );
    expect(el.querySelector('[data-slot="agent-event-open-call"]')).toBeNull();
  });

  it('draws no open button where no call can be shown', () => {
    const noProvider = render(
      <MemberEventCard
        kind="finished"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
      />,
    );
    expect(
      noProvider.querySelector('[data-slot="agent-event-open-call"]'),
    ).toBeNull();

    const declined = render(
      <RevealCallContext.Provider value={() => null}>
        <MemberEventCard
          kind="finished"
          name="Researcher"
          memberId="m-researcher"
          callId="call-7"
        />
      </RevealCallContext.Provider>,
    );
    expect(
      declined.querySelector('[data-slot="agent-event-open-call"]'),
    ).toBeNull();
  });

  it('labels the member’s CLI by its short name, from the capabilities it reports', () => {
    const el = render(
      <AgentIdentityContext.Provider value={[CLAUDE]}>
        <MemberEventCard
          kind="finished"
          name="Researcher"
          memberId="m-researcher"
          callId="call-7"
          meta={{ name: 'Researcher', kind: 'agent', agent: 'claude' }}
        />
      </AgentIdentityContext.Provider>,
    );
    expect(
      el.querySelector('[data-slot="agent-event-agent"]')?.textContent,
    ).toBe('Claude');
  });

  it('falls back to the CLI’s own name before capabilities have loaded', () => {
    const el = render(
      <MemberEventCard
        kind="finished"
        name="Researcher"
        memberId="m-researcher"
        callId="call-7"
        meta={{ name: 'Researcher', kind: 'agent', agent: 'claude' }}
      />,
    );
    expect(
      el.querySelector('[data-slot="agent-event-agent"]')?.textContent,
    ).toBe('claude');
  });
});

describe('MonitorEventCard', () => {
  it('draws a batch that woke the agent as a reported monitor, headed by the monitor', () => {
    const el = render(
      <MonitorEventCard
        entry={monitor()}
        woke
        agent="Manager"
        memoryKey="monitor-test"
      />,
    );
    const article = card(el, 'monitor-event');
    expect(article.dataset.kind).toBe('monitor-reported');
    expect(article.dataset.monitor).toBe('m1');
    expect(
      el.querySelector<HTMLElement>('[data-slot="monitor-event-face"]')?.dataset
        .face,
    ).toBe('monitor');
    expect(
      el.querySelector('[data-slot="monitor-event-title"]')?.textContent,
    ).toBe('dev server log');
    expect(
      el.querySelector('[data-slot="monitor-event-handle"]')?.textContent,
    ).toBe('m1');
    expect(
      el.querySelector('[data-slot="monitor-event-label"]')?.textContent,
    ).toBe('Monitor reported');
  });

  it('folds the delivered output behind Output, and names the lines cut before delivery', () => {
    const el = render(
      <MonitorEventCard
        entry={monitor({ omitted: 3 })}
        woke
        agent={null}
        memoryKey="monitor-test"
      />,
    );
    expect(el.querySelector('[data-slot="monitor-output"]')).toBeNull();
    const toggle = outputButton(el);

    act(() => toggle.click());

    const output = el.querySelector('[data-slot="monitor-output"]');
    expect(output?.textContent).toContain('compiled');
    expect(output?.textContent).toContain('ready');
    expect(output?.textContent).toContain('… 3 more lines not delivered');
    expect(toggle.getAttribute('aria-expanded')).toBe('true');

    act(() => toggle.click());

    expect(el.querySelector('[data-slot="monitor-output"]')).toBeNull();
  });

  it('says a single cut line in the singular', () => {
    const el = render(
      <MonitorEventCard
        entry={monitor({ lines: [], omitted: 1 })}
        woke
        agent={null}
        memoryKey="monitor-test"
      />,
    );
    act(() => outputButton(el).click());
    expect(
      el.querySelector('[data-slot="monitor-output"]')?.textContent,
    ).toContain('… 1 more line not delivered');
  });

  it('draws no Output fold when nothing was delivered or cut', () => {
    const el = render(
      <MonitorEventCard
        entry={monitor({ lines: [], omitted: 0 })}
        woke
        agent={null}
        memoryKey="monitor-test"
      />,
    );
    expect(el.querySelector('button')).toBeNull();
  });

  it('draws an ending that was only a stop as a stopped monitor, with no outcome line', () => {
    const el = render(
      <MonitorEventCard
        entry={monitor({ event: 'end', end: { kind: 'stopped' } })}
        woke={false}
        agent={null}
        memoryKey="monitor-test"
      />,
    );
    expect(card(el, 'monitor-event').dataset.kind).toBe('monitor-stopped');
    expect(el.querySelector('[data-slot="monitor-event-outcome"]')).toBeNull();
  });

  it('draws a batch delivered without a turn of its own as a report, never as a stop', () => {
    const el = render(
      <MonitorEventCard
        entry={monitor()}
        woke={false}
        agent={null}
        memoryKey="monitor-test"
      />,
    );
    expect(card(el, 'monitor-event').dataset.kind).toBe('monitor-reported');
  });

  it('draws a monitor that exited with an error as ended, its exit code in red', () => {
    const el = render(
      <MonitorEventCard
        entry={monitor({ event: 'end', end: { kind: 'exit', code: 1 } })}
        woke={false}
        agent={null}
        memoryKey="monitor-test"
      />,
    );
    expect(card(el, 'monitor-event').dataset.kind).toBe('monitor-ended');
    const outcome = el.querySelector<HTMLElement>(
      '[data-slot="monitor-event-outcome"]',
    );
    expect(outcome?.textContent).toBe('exit code 1');
    expect(outcome?.className).toContain('text-destructive');
  });

  it('draws a monitor that exited cleanly as stopped, its exit code muted', () => {
    const el = render(
      <MonitorEventCard
        entry={monitor({ event: 'end', end: { kind: 'exit', code: 0 } })}
        woke={false}
        agent={null}
        memoryKey="monitor-test"
      />,
    );
    expect(card(el, 'monitor-event').dataset.kind).toBe('monitor-stopped');
    const outcome = el.querySelector<HTMLElement>(
      '[data-slot="monitor-event-outcome"]',
    );
    expect(outcome?.textContent).toBe('exit code 0');
    expect(outcome?.className).toContain('text-muted-foreground');
    expect(outcome?.className).not.toContain('text-destructive');
  });

  it('colours a bad ending red on a batch that woke the agent too', () => {
    const el = render(
      <MonitorEventCard
        entry={monitor({ event: 'end', end: { kind: 'exit', code: 2 } })}
        woke
        agent={null}
        memoryKey="monitor-test"
      />,
    );
    expect(card(el, 'monitor-event').dataset.kind).toBe('monitor-reported');
    const outcome = el.querySelector<HTMLElement>(
      '[data-slot="monitor-event-outcome"]',
    );
    expect(outcome?.textContent).toBe('exit code 2');
    expect(outcome?.className).toContain('text-destructive');
  });
});

describe('monitorEndText', () => {
  it.each<[MonitorEnd, string]>([
    [{ kind: 'exit', code: 3 }, 'exit code 3'],
    [{ kind: 'exit' }, 'exited'],
    [{ kind: 'signal', signal: 'SIGKILL' }, 'killed by SIGKILL'],
    [{ kind: 'signal' }, 'killed by a signal'],
    [{ kind: 'timeout' }, 'timed out'],
    [{ kind: 'stopped' }, 'stopped'],
    [{ kind: 'flooded' }, 'flooded'],
    [{ kind: 'interrupted' }, 'interrupted'],
  ])('words the ending %j as "%s"', (end, text) => {
    expect(monitorEndText(end)).toBe(text);
  });
});
