const stepLines = (count: number): string =>
  Array.from({ length: count }, (_, i) => `- step ${i + 1}`).join('\n');

function card(el: HTMLElement, slot = 'agent-event'): HTMLElement {
  const found = el.querySelector<HTMLElement>(`[data-slot="${slot}-card"]`);
  if (found === null) {
    throw new Error(`no ${slot} card`);
  }
  return found;
}

function monitor(over: Partial<MonitorEntry> = {}): MonitorEntry {
  return {
    id: 'm1',
    description: 'dev server log',
    event: 'batch',
    end: null,
    lines: ['compiled', 'ready'],
    omitted: 0,
    command: null,
    startedAt: null,
    timeoutMs: null,
    ...over,
  };
}

function slotText(el: HTMLElement, slot: string): string | null | undefined {
  return el.querySelector(`[data-slot="${slot}"]`)?.textContent;
}

