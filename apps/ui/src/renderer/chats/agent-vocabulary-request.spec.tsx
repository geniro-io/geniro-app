// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { AgentVocabularyDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { useAgentContextWindows } from './use-agent-context-windows';
import { useAgentEfforts } from './use-agent-efforts';
import { useAgentModelParameters } from './use-agent-model-parameters';
import { useAgentModels } from './use-agent-models';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

const ANSWER: AgentVocabularyDto = {
  models: [{ id: 'opus', label: 'Opus', source: 'cli' }],
  efforts: {
    efforts: [{ id: 'high', label: 'High' }],
    unavailableReason: null,
  },
  contextWindows: {
    windows: [{ id: '1m', label: '1M' }],
    unavailableReason: null,
    unavailableKind: null,
  },
  modelParameters: { parameters: [], unavailableReason: 'none' },
};

type Picker = {
  models: string[];
  efforts: string[];
  windows: string[];
  parametersReason: string | null;
};

/** One picker, the way every screen mounts it: all four hooks, one question. */
function mountPicker(agentsApi: DaemonApis['agents']): () => Picker {
  let latest: Picker = {
    models: [],
    efforts: [],
    windows: [],
    parametersReason: null,
  };
  function Probe(): null {
    const models = useAgentModels(
      agentsApi,
      'claude',
      '/profiles/work',
      'opus',
    );
    const efforts = useAgentEfforts(
      agentsApi,
      'claude',
      'opus',
      '/profiles/work',
    );
    const windows = useAgentContextWindows(
      agentsApi,
      'claude',
      'opus',
      '/profiles/work',
    );
    const parameters = useAgentModelParameters(
      agentsApi,
      'claude',
      'opus',
      '/profiles/work',
    );
    latest = {
      models: models.models.map((model) => model.id),
      efforts: efforts.efforts.map((effort) => effort.id),
      windows: windows.windows.map((window) => window.id),
      parametersReason: parameters.unavailableReason,
    };
    return null;
  }
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root?.render(<Probe />);
  });
  return () => latest;
}

const settle = (): Promise<void> =>
  act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });

describe('a picker’s vocabulary', () => {
  it('is ONE request for all four listings, answered to each hook', async () => {
    // Four requests per picker was the cost over a LAN gateway or a tunnel:
    // each a real round trip, queued behind six connections per host.
    const listAgentVocabulary = vi.fn(async () => ANSWER);
    const picker = mountPicker({
      listAgentVocabulary,
    } as unknown as DaemonApis['agents']);

    await settle();

    expect(listAgentVocabulary).toHaveBeenCalledTimes(1);
    expect(listAgentVocabulary).toHaveBeenCalledWith({
      agent: 'claude',
      model: 'opus',
      configDir: '/profiles/work',
    });
    expect(picker()).toEqual({
      models: ['opus'],
      efforts: ['high'],
      windows: ['1m'],
      parametersReason: 'none',
    });
  });

  it('asks again for the one part the daemon could not read, and keeps the rest', async () => {
    vi.useFakeTimers();
    // `null` is "could not ask", which must be retried — not cached as "this
    // CLI offers no levels", which is what an empty listing means.
    const listAgentVocabulary = vi
      .fn(async () => ANSWER)
      .mockImplementationOnce(async () => ({ ...ANSWER, efforts: null }));
    const picker = mountPicker({
      listAgentVocabulary,
    } as unknown as DaemonApis['agents']);

    await act(async () => {
      await vi.advanceTimersByTimeAsync(0);
    });
    expect(picker().efforts).toEqual([]);
    expect(picker().windows).toEqual(['1m']);

    // The vocabulary hook's own retry delay.
    await act(async () => {
      await vi.advanceTimersByTimeAsync(4_000);
    });

    expect(listAgentVocabulary).toHaveBeenCalledTimes(2);
    expect(picker().efforts).toEqual(['high']);
  });
});
