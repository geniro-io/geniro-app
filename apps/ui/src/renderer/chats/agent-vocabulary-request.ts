import type { CliKind } from '../../shared/contracts';
import type { AgentVocabularyDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { vocabularyVariant } from './use-agent-vocabulary';

/**
 * The requests in flight, per client and question. Per CLIENT because a daemon
 * restart rotates the handle and so builds a new one, and an answer the old
 * daemon is still composing belongs to nobody.
 */
const inFlight = new WeakMap<
  DaemonApis['agents'],
  Map<string, Promise<AgentVocabularyDto>>
>();

/**
 * One CLI's vocabulary for one model and one account — `GET /v1/agents/vocabulary`
 * — shared by every hook that asks the same question at the same moment.
 *
 * A picker's four hooks (`useAgentModels`, `useAgentEfforts`,
 * `useAgentContextWindows`, `useAgentModelParameters`) each ask on their own,
 * in the same commit, and used to be four requests; asking through here they
 * are one, because the second to ask finds the first's request still running.
 * Only a request IN FLIGHT is shared: each hook keeps its own cache, retry and
 * refresh exactly as before, so a later ask is a fresh request.
 */
export function requestAgentVocabulary(
  agentsApi: DaemonApis['agents'],
  agent: CliKind,
  model: string | null,
  configDir: string | null,
): Promise<AgentVocabularyDto> {
  let byQuestion = inFlight.get(agentsApi);
  if (byQuestion === undefined) {
    byQuestion = new Map();
    inFlight.set(agentsApi, byQuestion);
  }
  // `\u0000` because neither a CLI name, a model id nor a path can contain it.
  const key = `${agent}\u0000${vocabularyVariant(model, configDir)}`;
  const running = byQuestion.get(key);
  if (running !== undefined) {
    return running;
  }
  const request = agentsApi.listAgentVocabulary({
    agent,
    // Omitted rather than sent empty: an absent model is "nothing chosen yet",
    // and an absent directory is "the CLI's own profile" — `''` is neither.
    ...(model ? { model } : {}),
    ...(configDir ? { configDir } : {}),
  });
  byQuestion.set(key, request);
  const forget = (): void => {
    if (byQuestion.get(key) === request) {
      byQuestion.delete(key);
    }
  };
  request.then(forget, forget);
  return request;
}

/**
 * A part the daemon answered, or a throw when it could not read that part
 * (`null` on the wire). A throw is what makes the hook asking for it treat it
 * as a failed fetch and ask again, rather than caching "the CLI offers none".
 */
export function vocabularyPart<T>(part: T | null, name: string): T {
  if (part === null) {
    throw new Error(`the daemon could not read this CLI's ${name}`);
  }
  return part;
}
