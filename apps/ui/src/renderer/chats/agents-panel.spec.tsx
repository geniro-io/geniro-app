describe('AgentsPanel', () => {
  it('lists EVERY agent with status, active/total thread counts, context + ring, and spend', () => {
    const el = render(
      <AgentsPanel agents={agents} onOpenThread={vi.fn()} onClose={vi.fn()} />,
    );
    const rows = [...el.querySelectorAll('ul > li')];
    expect(rows).toHaveLength(3);

    const worker = rows.find((row) => row.textContent?.includes('Worker'))!;
    expect(worker.textContent).toContain('3 active · 2 threads');
    expect(worker.textContent).toContain('ctx 12k / 200k');
    expect(worker.textContent).toContain('<$0.01');
    expect(worker.querySelector('svg.animate-spin')).not.toBeNull();
    expect(
      worker.querySelector('svg[aria-label="Context 6% full"]'),
    ).not.toBeNull();

    // One main thread and nothing else: the card IS that conversation, so it
    // shows no chevron, no thread list and no "1 thread" count to expand into.
    const orchestrator = rows.find((row) =>
      row.textContent?.includes('Orchestrator'),
    )!;
    expect(orchestrator.textContent).not.toContain('1 thread');
    // The live-turn count survives the collapse — only the thread COUNT goes.
    expect(orchestrator.textContent).toContain('1 active');
    expect(orchestrator.querySelector('button[aria-expanded]')).toBeNull();
    // The CLI's own window, not the 200k default the sibling card falls to.
    expect(orchestrator.textContent).toContain('ctx 45.2k / 1M');
    expect(orchestrator.textContent).not.toContain('/ 200k');
    // …and the ring is scaled by it: 45.2k of 1M is 5% full, of 200k is 23%.
    expect(
      orchestrator.querySelector('svg[aria-label="Context 5% full"]'),
    ).not.toBeNull();
    expect(orchestrator.textContent).toContain('$0.24');

    const reviewer = rows.find((row) => row.textContent?.includes('Reviewer'))!;
    expect(reviewer.textContent).toContain('idle');
    expect(reviewer.textContent).toContain('cursor-agent');
    expect(reviewer.textContent).not.toContain('ctx');
  });

  it('expanding an agent lists its threads; per-thread terminals need claude + a session', () => {
    const onOpenThread = vi.fn();
    const el = render(
      <AgentsPanel
        agents={agents}
        onOpenThread={onOpenThread}
        onClose={vi.fn()}
      />,
    );
    // Collapsed: no thread labels yet.
    expect(el.textContent).not.toContain('Write a haiku about rivers.');

    click(el.querySelector('button[aria-label="Worker threads"]'));
    expect(el.textContent).toContain('call-1 · Write a haiku about rivers.');
    expect(el.textContent).toContain('call-2 · Write a haiku about mountains.');

    // call-1 settled with a session id → openable; call-2 still running → not.
    const openCall1 = el.querySelector(
      'button[aria-label="Open terminal for Worker — call-1"]',
    );
    expect(openCall1).not.toBeNull();
    expect(
      el.querySelector(
        'button[aria-label="Open terminal for Worker — call-2"]',
      ),
    ).toBeNull();

    click(openCall1);
    expect(onOpenThread).toHaveBeenCalledWith(agents[1], agents[1]!.threads[0]);

    // A sole-thread claude agent needs no expanding: its terminal sits right
    // on the card and opens without an explicit session id.
    const openMain = el.querySelector(
      'button[aria-label="Open terminal for Orchestrator"]',
    );
    expect(openMain).not.toBeNull();
    click(openMain);
    expect(onOpenThread).toHaveBeenCalledWith(agents[0], agents[0]!.threads[0]);

    // Cursor has no interactive mirror — no terminal anywhere on its card.
    expect(
      el.querySelector('button[aria-label="Open terminal for Reviewer"]'),
    ).toBeNull();
  });

  it('still expands an agent that genuinely has several threads', () => {
    // The collapse is for a SOLE main thread only — a fan-out agent's call
    // threads must stay reachable.
    const el = render(
      <AgentsPanel agents={agents} onOpenThread={vi.fn()} onClose={vi.fn()} />,
    );
    const worker = [...el.querySelectorAll('ul > li')].find((row) =>
      row.textContent?.includes('Worker'),
    )!;

    expect(worker.querySelector('button[aria-expanded]')).not.toBeNull();
    expect(worker.textContent).not.toContain('Write a haiku about rivers.');
    click(worker.querySelector('button[aria-expanded]'));
    expect(worker.textContent).toContain('Write a haiku about rivers.');
  });

  it('the fill ring escalates its tone as the context window fills', () => {
    const withContext = (id: string, contextTokens: number): AgentDisplay => ({
      id,
      name: id,
      agent: 'claude',
      status: 'completed',
      activeTurns: 0,
      contextTokens,
      contextWindowTokens: null,
      spentUsd: null,
      threads: [],
    });
    const el = render(
      <AgentsPanel
        agents={[
          withContext('calm', 45_200), // 23% → success
          withContext('hot', 150_000), // 75% → warning
          withContext('critical', 185_000), // 92.5% → destructive
        ]}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );
    const ring = (label: string): SVGElement =>
      el.querySelector<SVGElement>(`svg[aria-label="${label}"]`)!;
    expect(ring('Context 23% full').classList.contains('text-success')).toBe(
      true,
    );
    expect(ring('Context 75% full').classList.contains('text-warning')).toBe(
      true,
    );
    expect(
      ring('Context 93% full').classList.contains('text-destructive'),
    ).toBe(true);
  });

  it('closes via the ✕ and offers the resize handle', () => {
    const onClose = vi.fn();
    const el = render(
      <AgentsPanel agents={agents} onOpenThread={vi.fn()} onClose={onClose} />,
    );
    expect(
      el.querySelector('[role="separator"][aria-label="Resize agents panel"]'),
    ).not.toBeNull();
    click(el.querySelector('button[aria-label="Close agents panel"]'));
    expect(onClose).toHaveBeenCalledOnce();
  });

  it('shows an empty state when the run has no agents', () => {
    const el = render(
      <AgentsPanel agents={[]} onOpenThread={vi.fn()} onClose={vi.fn()} />,
    );
    expect(el.textContent).toContain('No agents in this run');
  });
});

/** The card of the agent whose name is given. */
function cardFor(el: HTMLDivElement, name: string): Element {
  return [...el.querySelectorAll('ul > li')].find((row) =>
    row.querySelector('span')?.textContent?.includes(name),
  )!;
}

describe('AgentsPanel — MCP servers', () => {
  const claudeListing: AgentMcpListing = {
    unavailableReason: null,
    servers: [
      {
        name: 'sentry',
        target: 'node sentry.js',
        transport: 'stdio' as const,
        status: 'connected' as const,
        detail: null,
        scope: 'project' as const,
        disabled: false,
        toggleUnavailableReason: null,
      },
      {
        name: 'linear',
        target: 'https://linear.app/mcp',
        transport: 'http' as const,
        status: 'failed' as const,
        detail: 'HTTP 502: upstream dial failed',
        scope: 'project' as const,
        disabled: false,
        toggleUnavailableReason: null,
      },
      {
        name: 'unapproved',
        target: '/bin/echo hi',
        transport: 'stdio' as const,
        status: 'pending' as const,
        detail: '(run `claude` to approve)',
        scope: 'other' as const,
        disabled: false,
        toggleUnavailableReason:
          'only servers defined in this folder\u2019s .mcp.json can be switched off',
      },
    ],
  };

  it('lists one agent’s servers with the health the CLI reported', () => {
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={new Map([['claude', claudeListing]])}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    const orchestrator = cardFor(el, 'Orchestrator');
    expect(orchestrator.textContent).toContain('sentry');
    expect(orchestrator.textContent).toContain('connected');
    expect(orchestrator.textContent).toContain('linear');
    expect(orchestrator.textContent).toContain('failed');
    expect(orchestrator.textContent).toContain('pending');
  });

  it('puts the failure reason where the user can read it', () => {
    // The reason is the only actionable part of a failure and is far too long
    // for the row, so it must survive somewhere — not be dropped for fitting.
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={new Map([['claude', claudeListing]])}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    const failing = [
      ...cardFor(el, 'Orchestrator').querySelectorAll('li[title]'),
    ].find((row) => row.textContent?.includes('linear'));
    expect(failing?.getAttribute('title')).toBe(
      'HTTP 502: upstream dial failed',
    );
  });

  it('shows a CLI’s own reason instead of pretending the folder is empty', () => {
    // The distinction this whole shape exists for: one agent gets the daemon's
    // sentence, and the claude agent in the SAME run still gets rows. The
    // sentence here is a REAL one the daemon can send — cursor's listing is
    // implemented since milestone 4, so what it now fails with is a CLI that
    // did not answer, not an unimplemented feature.
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={
          new Map<CliKind, AgentMcpListing>([
            ['claude', claudeListing],
            [
              'cursor-agent',
              {
                servers: [],
                unavailableReason:
                  'could not read MCP servers — cursor-agent did not answer',
              },
            ],
          ])
        }
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    const reviewer = cardFor(el, 'Reviewer');
    expect(reviewer.textContent).toContain(
      'could not read MCP servers — cursor-agent did not answer',
    );
    expect(reviewer.textContent).not.toContain('No servers');
    expect(cardFor(el, 'Orchestrator').textContent).toContain('sentry');
  });

  it('says "No servers" when the CLI could be asked and had none', () => {
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={
          new Map<CliKind, AgentMcpListing>([
            ['claude', { servers: [], unavailableReason: null }],
          ])
        }
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    expect(cardFor(el, 'Orchestrator').textContent).toContain('No servers');
  });

  it('does not claim "No servers" for an agent nothing has answered for', () => {
    // A run can carry no folder at all, so nothing is ever asked. Saying "No
    // servers" there is a claim about the user's configuration made without
    // looking — the same class of untruth `unavailableReason` exists to stop.
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={new Map<CliKind, AgentMcpListing>()}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    const orchestrator = cardFor(el, 'Orchestrator');
    expect(orchestrator.textContent).toContain('Not checked');
    expect(orchestrator.textContent).not.toContain('No servers');
  });

  it('refreshes on demand, and blocks a second click while one is running', () => {
    const onRefreshMcp = vi.fn();
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={new Map([['claude', claudeListing]])}
        mcpLoading={false}
        onRefreshMcp={onRefreshMcp}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );
    click(el.querySelector('button[aria-label="Refresh MCP servers"]'));
    expect(onRefreshMcp).toHaveBeenCalledOnce();

    // A read in flight already health-checks the user's servers; a second
    // concurrent one buys nothing and doubles that cost.
    act(() => {
      root!.render(
        <AgentsPanel
          agents={agents}
          mcpByKind={new Map([['claude', claudeListing]])}
          mcpLoading
          onRefreshMcp={onRefreshMcp}
          onOpenThread={vi.fn()}
          onClose={vi.fn()}
        />,
      );
    });
    const refresh = el.querySelector<HTMLButtonElement>(
      'button[aria-label="Refresh MCP servers"]',
    );
    // A real disabled <button>, not an aria-disabled div — that is what makes
    // the browser suppress the click, so it is the part worth asserting.
    expect(refresh?.tagName).toBe('BUTTON');
    expect(refresh?.disabled).toBe(true);
  });

  it('offers no refresh control when the owner supplies no handler', () => {
    // A control that cannot do anything is worse than no control.
    const el = render(
      <AgentsPanel agents={agents} onOpenThread={vi.fn()} onClose={vi.fn()} />,
    );
    expect(
      el.querySelector('button[aria-label="Refresh MCP servers"]'),
    ).toBeNull();
  });

  it('renders no MCP section at all when the owner passes no listings', () => {
    // The panel predates this feature and must still render standalone.
    const el = render(
      <AgentsPanel agents={agents} onOpenThread={vi.fn()} onClose={vi.fn()} />,
    );
    expect(el.textContent).not.toContain('MCP');
  });
});

describe('AgentsPanel — MCP toggle', () => {
  /** One row, shaped by whatever the daemon said about togglability. */
  function listingOf(
    server: Partial<AgentMcpListing['servers'][number]> & { name: string },
  ): AgentMcpListing {
    return {
      unavailableReason: null,
      servers: [
        {
          target: 'node x.js',
          transport: 'stdio' as const,
          status: 'connected' as const,
          detail: null,
          scope: 'project' as const,
          disabled: false,
          toggleUnavailableReason: null,
          ...server,
        },
      ],
    };
  }

  /** The switches inside one agent's card. */
  function switchesIn(el: Element): HTMLButtonElement[] {
    return [...el.querySelectorAll('[role="switch"]')] as HTMLButtonElement[];
  }

  it('renders a switch for a project-scope server', () => {
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={new Map([['claude', listingOf({ name: 'sentry' })]])}
        onSetMcpEnabled={vi.fn()}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    expect(switchesIn(cardFor(el, 'Orchestrator'))).toHaveLength(1);
  });

  it('renders NO switch for a row the daemon says cannot be toggled', () => {
    // The forbidden action of this milestone: a switch that moves and changes
    // nothing. Probe-verified that no settings key disables a user- or
    // local-scope server.
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={
          new Map([
            [
              'claude',
              listingOf({
                name: 'global-one',
                scope: 'other',
                toggleUnavailableReason: 'only project servers can be switched',
              }),
            ],
          ])
        }
        onSetMcpEnabled={vi.fn()}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    expect(switchesIn(cardFor(el, 'Orchestrator'))).toHaveLength(0);
  });

  it('shows the daemon’s reason on a row that cannot be toggled', () => {
    // Reading "no switch here" is not enough — the user needs to know why, and
    // the daemon's sentence is the only thing that knows.
    const reason = 'switched off in your own claude settings';
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={
          new Map([
            [
              'claude',
              listingOf({
                name: 'sentry',
                disabled: true,
                toggleUnavailableReason: reason,
              }),
            ],
          ])
        }
        onSetMcpEnabled={vi.fn()}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    expect(
      cardFor(el, 'Orchestrator').querySelector(`[aria-label="${reason}"]`),
    ).not.toBeNull();
  });

  it('reflects a disabled server as off, not on', () => {
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={
          new Map([['claude', listingOf({ name: 'sentry', disabled: true })]])
        }
        onSetMcpEnabled={vi.fn()}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    expect(
      switchesIn(cardFor(el, 'Orchestrator'))[0]?.getAttribute('aria-checked'),
    ).toBe('false');
  });

  it('asks to ENABLE a server that is currently off', () => {
    // The click carries the state the user wants, not the one on screen.
    // Inverting this makes the switch a no-op that looks like it worked.
    const onSetMcpEnabled = vi.fn();
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={
          new Map([['claude', listingOf({ name: 'sentry', disabled: true })]])
        }
        onSetMcpEnabled={onSetMcpEnabled}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    act(() => {
      switchesIn(cardFor(el, 'Orchestrator'))[0]?.click();
    });

    expect(onSetMcpEnabled).toHaveBeenCalledWith('claude', 'sentry', true);
  });

  it('asks to DISABLE a server that is currently on', () => {
    const onSetMcpEnabled = vi.fn();
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={new Map([['claude', listingOf({ name: 'sentry' })]])}
        onSetMcpEnabled={onSetMcpEnabled}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    act(() => {
      switchesIn(cardFor(el, 'Orchestrator'))[0]?.click();
    });

    expect(onSetMcpEnabled).toHaveBeenCalledWith('claude', 'sentry', false);
  });

  it('renders every row read-only when no write path was given', () => {
    // The panel never invents a control its owner did not offer.
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={new Map([['claude', listingOf({ name: 'sentry' })]])}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    expect(switchesIn(cardFor(el, 'Orchestrator'))).toHaveLength(0);
  });

  it('shows a failed toggle instead of letting the switch snap back silently', () => {
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={new Map([['claude', listingOf({ name: 'sentry' })]])}
        mcpToggleError="daemon PUT /v1/agents/mcp failed (400): not project scope"
        onDismissMcpToggleError={vi.fn()}
        onSetMcpEnabled={vi.fn()}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    expect(el.textContent).toContain('not project scope');
  });

  it('disables the switch while a read or write is in flight', () => {
    // Two clicks in a row would race two writes whose answers arrive in any
    // order, and the loser would be rendered as the truth.
    const el = render(
      <AgentsPanel
        agents={agents}
        mcpByKind={new Map([['claude', listingOf({ name: 'sentry' })]])}
        mcpLoading
        onSetMcpEnabled={vi.fn()}
        onOpenThread={vi.fn()}
        onClose={vi.fn()}
      />,
    );

    expect(switchesIn(cardFor(el, 'Orchestrator'))[0]?.disabled).toBe(true);
  });
});
