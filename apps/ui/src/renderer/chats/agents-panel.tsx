/**
 * One agent's MCP servers, behind a button rather than always on screen.
 *
 * Two reasons it is not a band of the card any more. The listing was rendered
 * inline and read on mount, and that read HEALTH-CHECKS each server — it
 * launches the user's own MCP processes — so simply opening a chat greeted
 * them with a column of connection failures from servers they had not asked to
 * start. And the list is long (ten rows is ordinary) with a paragraph of
 * failure text under the broken ones, which pushed the thing the panel is
 * actually for — the agents and their threads — off the bottom.
 *
 * The trigger is the label alone: the count and the re-dial control belong to
 * the panel it opens, which already heads its rows with both.
 */
/**
 * The MCP control: an icon button beside the terminal one, opening the server
 * list in a MODAL DIALOG.
 *
 * A dialog and not a popover, which is the third placement this list has had
 * and the first one sized for what it actually holds. It was a full-width band
 * across the card, which pushed the agents themselves off the bottom whenever
 * it was open; then a popover anchored to this button, which is a tooltip-sized
 * surface hung off a 24px trigger inside a 280px panel — ten server rows, each
 * able to carry a paragraph of connection-failure text, do not fit in one, and
 * it closed on the first pointer press that landed anywhere else. Toggling a
 * server on and off is deliberate work, so it gets the surface deliberate work
 * gets: a centered card with room, a backdrop, Escape, and focus that stays put
 * until it is dismissed.
 */
function McpDisclosure({
  agentName,
  open,
  onOpenChange,
  listing,
  loading,
  onRefresh,
  onSetEnabled,
  onSignIn,
}: {
  /** Names the dialog, so several open one at a time stay tellable apart. */
  agentName: string;
  open: boolean;
  onOpenChange: (open: boolean) => void;
  listing: AgentMcpListing | undefined;
  loading: boolean;
  onRefresh?: () => void;
  onSetEnabled?: (server: string, enabled: boolean) => void;
  onSignIn?: (server: string) => void;
}): React.JSX.Element {
  const count = listing?.servers?.length ?? 0;
  return (
    <>
      <Button
        type="button"
        variant="ghost"
        size="icon"
        aria-expanded={open}
        aria-label="MCP servers"
        title="MCP servers this agent loads here"
        className="size-6 shrink-0 text-muted-foreground"
        onClick={(event) => {
          // The card header is a plain row now, so nothing above this would
          // act on the press — but the control row sits inside a list item
          // that a later change could make activatable, and a stray toggle of
          // the thread list is not something a reader would trace back here.
          event.stopPropagation();
          onOpenChange(!open);
        }}>
        <Plug aria-hidden="true" className="size-3.5 shrink-0" />
        {count > 0 ? <span className="sr-only">{count} servers</span> : null}
      </Button>
      <Dialog
        open={open}
        onClose={() => onOpenChange(false)}
        title={`MCP servers — ${agentName}`}
        className="max-w-lg">
        <McpSection
          listing={listing}
          loading={loading}
          onRefresh={onRefresh}
          onSetEnabled={onSetEnabled}
          onSignIn={onSignIn}
          // The dialog IS the section's chrome here, so the card-band edges
          // (a top rule, the card's own padding) would draw a stray line
          // across a panel that is already bounded.
          className="border-t-0"
        />
      </Dialog>
    </>
  );
}

/**
 * The right side panel (opened from the transcript header): every agent of
 * the active run with its live status, active/total thread counts, context
 * fill, and spend. The chevron button in each card's control row opens its
 * thread list — the main conversation, every `call_agent` thread, and every
 * sub-agent still WORKING, with the finished delegates counted behind their
 * own disclosure. A conversation carries the "open it in a terminal" control —
 * live where the CLI can resume one, inert with the daemon's reason where it
 * cannot; a call thread needs its recorded session id, so it opens once
 * settled — while a sub-agent opens its own timeline and thread instead, having
 * no CLI session to resume. Resizable like the builder's side panels.
 */
/**
 * "Carry this conversation on yourself": opens the agent's own CLI on this
 * thread, in the user's terminal.
 *
 * There is no embedded terminal any more. A mirror was a SECOND process
 * rendering the same transcript, and it could not follow a running turn without
 * being re-spawned on a timer — probe-measured, an open CLI never re-reads its
 * session, and even two interactive CLIs on one session do not see each other.
 * Handing over needs none of that: the CLI starts when the button is pressed
 * and renders the conversation as it stands then.
 *
 * Hovering (or focusing) resolves the invocation and shows it, selectable, with
 * a copy control — the way out for anyone whose terminal geniro cannot launch:
 * a remote host, a tmux pane already open. It resolves at most once per thread
 * and only on demand, so a panel of ten agents costs ten nothing.
 */
function OpenInCliButton({
  agent,
  thread,
  label,
  unavailableReason = null,
  onOpen,
  onResolve,
}: {
  agent: AgentDisplay;
  thread: AgentThread;
  label: string;
  /**
   * Why this CLI can never reopen a conversation, or null when it can.
   *
   * Set means the control is PRESENT AND INERT rather than absent — the panel
   * used to hide it for such a CLI, which left a cursor card showing one
   * unlabelled glyph where a claude card shows two and no way to find out why.
   * The daemon has always had a sentence for it; nothing rendered it.
   */
  unavailableReason?: string | null;
  onOpen: (agent: AgentDisplay, thread: AgentThread) => void;
  onResolve?: (
    agent: AgentDisplay,
    thread: AgentThread,
  ) => Promise<HandoffTargetDto>;
}): React.JSX.Element {
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const [hint, setHint] = useState<HandoffTargetDto | null>(null);
  const [showHint, setShowHint] = useState(false);
  const inert = unavailableReason !== null;
  const reveal = (): void => {
    setShowHint(true);
    // Nothing to resolve when the CLI has already answered for every thread it
    // will ever have: the reason is in hand, and asking would spend a request
    // to be told the same thing a beat later.
    if (inert || hint || !onResolve) {
      return;
    }
    void onResolve(agent, thread)
      .then(setHint)
      // A failed lookup must not surface as an error banner: nothing was asked
      // for yet. The button still works; the hint just stays quiet.
      .catch(() => undefined);
  };
  return (
    <span
      className="relative flex shrink-0 items-center"
      onMouseEnter={reveal}
      onMouseLeave={() => setShowHint(false)}>
      <Button
        ref={triggerRef}
        type="button"
        variant="ghost"
        size="icon"
        className={cn(
          'size-6 shrink-0 text-muted-foreground',
          inert && 'opacity-50',
        )}
        aria-label={label}
        // `aria-disabled`, never `disabled`: a disabled button leaves the tab
        // order, and the reason is only reachable by hovering it. The whole
        // point of rendering it is that the explanation can be reached, so it
        // stays focusable and the click simply does nothing.
        aria-disabled={inert || undefined}
        title={
          unavailableReason ?? 'Continue this conversation in your terminal'
        }
        onFocus={reveal}
        onBlur={() => setShowHint(false)}
        onClick={(event) => {
          event.stopPropagation();
          if (inert) {
            return;
          }
          onOpen(agent, thread);
        }}>
        <TerminalIcon className="size-3.5 shrink-0" />
      </Button>
      <Popover
        open={showHint && (inert || hint !== null)}
        onClose={() => setShowHint(false)}
        triggerRef={triggerRef}
        side="bottom"
        align="end"
        // The trigger lives inside the thread list, which SCROLLS — so an
        // ancestor-positioned panel is cut at that list's left edge, and a
        // 26rem one inside a 280px panel loses most of its text. Measured: 233
        // of 390px clipped, which hid the first half of every sentence and of
        // claude's copyable `--resume` line.
        anchor="viewport"
        label="Command to continue in a terminal"
        className="w-[26rem] p-2">
        {!inert && hint?.kind === 'command' && hint.display ? (
          <div className="flex items-start gap-2">
            <code className="min-w-0 flex-1 break-all font-mono text-[11px] text-foreground">
              {hint.display}
            </code>
            <CopyButton text={hint.display} label="Copy the command" />
          </div>
        ) : (
          <p className="text-[11px] text-muted-foreground">
            {unavailableReason ??
              hint?.unavailableReason ??
              'this conversation cannot be opened in a terminal'}
          </p>
        )}
      </Popover>
    </span>
  );
}

/**
 * One conversation of one agent, as a row of the card's thread list.
 *
 * Extracted because the list now renders threads from three places — the
 * agent's own conversations, its running delegates, and the settled delegates
 * behind their own disclosure — and three copies of this row is how one of them
 * comes to lose the terminal button or the sub-agent affordance without anyone
 * noticing.
 */
function ThreadRow({
  agent,
  thread,
  terminal,
  onOpenThread,
  onOpenSubagent,
  onResolveHandoff,
}: {
  agent: AgentDisplay;
  thread: AgentThread;
  /**
   * This CLI's handoff answer, or null when there is none to render — an agent
   * whose kind the panel does not know, or a capability report that has not
   * landed yet. `reason` non-null means the control is shown inert.
   */
  terminal: { reason: string | null } | null;
  onOpenThread: (agent: AgentDisplay, thread: AgentThread) => void;
  onOpenSubagent?: (subagentId: string) => void;
  onResolveHandoff?: (
    agent: AgentDisplay,
    thread: AgentThread,
  ) => Promise<HandoffTargetDto>;
}): React.JSX.Element {
  // A MAIN thread needs nothing else — the daemon resolves its session from
  // `node_state`. A CALL thread is a sub-session, which can only be targeted
  // once its own session id has been recorded (present after the call settles).
  // A SUB-AGENT has no session at all — it lives inside its parent's turn — so
  // it is excluded outright rather than left to fail the sessionId test by
  // accident.
  //
  // Note what is NOT in this test any more: whether the CLI can resume at all.
  // That is `terminal.reason`, and it makes the control INERT rather than
  // absent — the row still carries the explanation, where before it carried
  // nothing.
  const canOpen =
    terminal !== null &&
    thread.kind !== 'subagent' &&
    (thread.kind === 'main' || thread.sessionId !== null);
  // What a sub-agent row offers INSTEAD: its own timeline and conversation, in
  // a panel. Absent the callback the row is inert rather than falsely clickable.
  const openSubagent =
    thread.kind === 'subagent' && onOpenSubagent ? onOpenSubagent : null;
  return (
    <li className="flex items-center gap-1.5 rounded-md px-1 py-0.5 text-xs">
      <RunStatusIcon status={thread.status} />
      {openSubagent ? (
        <button
          type="button"
          // `text-xs font-normal` is not decoration — it is an OVERRIDE.
          // `styles/global.css` gives every bare `button` the base 15px at
          // medium weight, so without it this row rendered half again the size
          // of its `Main conversation` sibling, which is a span. Screenshotted
          // against the real stylesheet; jsdom loads no CSS, so no component
          // test could ever have caught it.
          className="min-w-0 flex-1 truncate rounded px-0.5 text-left text-xs font-normal transition-colors hover:text-foreground hover:underline"
          title={`Open ${thread.label}'s timeline and conversation`}
          onClick={() => openSubagent(thread.id)}>
          {thread.label}
        </button>
      ) : (
        <span className="min-w-0 flex-1 truncate" title={thread.label}>
          {thread.label}
        </span>
      )}
      {canOpen ? (
        <OpenInCliButton
          agent={agent}
          thread={thread}
          label={`Open terminal for ${agent.name} — ${thread.id}`}
          unavailableReason={terminal?.reason ?? null}
          onOpen={onOpenThread}
          onResolve={onResolveHandoff}
        />
      ) : null}
    </li>
  );
}

export function AgentsPanel({
  agents,
  mcpByScope,
  mcpLoading = false,
  onRefreshMcp,
  onSetMcpEnabled,
  onSignInMcp,
  mcpToggleError = null,
  onDismissMcpToggleError,
  onMcpOpenChange,
  onOpenThread,
  onOpenSubagent,
  onResolveHandoff,
  terminalReasons,
  usageReasons,
  onClose,
}: {
  agents: AgentDisplay[];
  /**
   * MCP servers per {@link mcpScopeKey}, fetched by the owner.
   *
   * Keyed by (CLI, config directory) rather than by node: several nodes
   * routinely share one pair and would get identical answers, but two nodes on
   * the same CLI with DIFFERENT config directories do not — a profile carries its
   * own MCP servers. Keyed by CLI alone (as it was) the panel painted one
   * node's servers onto every card of that CLI, including nodes that load a
   * different set. Absent while the panel's owner has nothing to show.
   */
  mcpByScope?: ReadonlyMap<string, AgentMcpListing>;
  mcpLoading?: boolean;
  /** Re-read health from the CLIs; absent hides the control entirely. */
  onRefreshMcp?: () => void;
  /**
   * Switch one server on or off for one CLI kind. Absent renders every row
   * read-only — the panel never invents a write path it was not given.
   */
  onSetMcpEnabled?: (kind: CliKind, server: string, enabled: boolean) => void;
  /**
   * Sign one CLI in to one MCP server. Absent hides the action, on the same
   * rule as {@link onSetMcpEnabled}.
   *
   * It ends in the user's own terminal rather than in the daemon, and that is
   * forced: `mcp login` refuses a non-TTY stdin outright (probe-verified), so
   * there is no headless path being passed over. Nothing in this panel knows
   * that — it hands over a CLI kind and a server name.
   */
  onSignInMcp?: (kind: CliKind, server: string) => void;
  /**
   * Why the last toggle did not land. Shown as a strip rather than swallowed:
   * the daemon refuses a toggle it cannot honour, and its sentence explains
   * WHY — silence would leave the switch snapping back for no stated reason.
   */
  mcpToggleError?: string | null;
  onDismissMcpToggleError?: () => void;
  /**
   * Told whenever an MCP list is opened or closed, so the owner can hold the
   * READ until then. The panel cannot gate the fetch itself — it does not own
   * the hook — and the fetch is what launches the user's own MCP servers.
   */
  onMcpOpenChange?: (open: boolean) => void;
  /** Open a terminal mirroring one thread of one agent. */
  onOpenThread: (agent: AgentDisplay, thread: AgentThread) => void;
  /**
   * Show one sub-agent's timeline and conversation, by the id of the tool call
   * that launched it. Absent leaves sub-agent rows listed but inert — the
   * panel never invents a surface it was not given, on the same rule as
   * {@link onSetMcpEnabled}.
   */
  onOpenSubagent?: (subagentId: string) => void;
  /*
   * There was a `subagentUnavailableReason` here — a panel-level paragraph
   * saying why a CLI lists no delegates. It has been removed: on cursor it was
   * three lines of protocol detail ("no session/update variant this client reads
   * carries a parent, task or sub-session id") standing permanently above every
   * agent card, on EVERY cursor chat, explaining the absence of something most
   * readers were not looking for. A caveat that never goes away stops being a
   * caveat and becomes chrome.
   *
   * The daemon still reports the fact (`GET /v1/capabilities` → `subagents[]`,
   * from each adapter's own config) and the reason is still the adapter's to
   * own — so if a place is ever found where a reader is actually asking the
   * question, it can be answered there without re-deriving anything.
   */
  /**
   * Resolve the invocation that opens one thread in a terminal — used for the
   * hover hint only. Optional: without it the button still opens, it just has
   * nothing to show beforehand.
   */
  onResolveHandoff?: (
    agent: AgentDisplay,
    thread: AgentThread,
  ) => Promise<HandoffTargetDto>;
  /**
   * Per CLI kind: `null` if it can reopen a conversation INTERACTIVELY
   * (`--resume`), else the daemon's own sentence for why it cannot.
   *
   * Read rather than hardcoded, because "which CLI can" is the adapter layer's
   * fact (`AdapterConfig.handoff`), and a list written here is how a second CLI
   * gaining the ability silently keeps its threads unopenable.
   *
   * A kind that is ABSENT from the map is unknown — the report has not landed —
   * and gets no control, which errs toward not showing one that would fail. A
   * kind present with a reason gets the control INERT, carrying that sentence.
   * The distinction matters: this replaced a set of capable kinds, under which
   * "we have not been told" and "this CLI never can" were the same thing, and
   * both rendered as silence.
   */
  terminalReasons?: ReadonlyMap<string, string | null>;
  /**
   * Per CLI kind: `null` if it reports what a turn cost, else the daemon's own
   * sentence for why the card's context meter is empty.
   *
   * Same three-state reading as {@link terminalReasons}: absent from the map is
   * "we have not been told", which must render as silence rather than as a
   * refusal — a turn mid-flight has no figures either.
   */
  usageReasons?: ReadonlyMap<string, string | null>;
  onClose: () => void;
}): React.JSX.Element {
  const { width, minWidth, maxWidth, startResize, resizeTo } = usePanelWidth({
    storageKey: 'chats.agentsPanelWidth',
    defaultWidth: 280,
    minWidth: 220,
    maxWidth: 420,
    handleEdge: 'left',
  });
  // ONE at a time, and that is a statement of fact rather than a policy:
  // `Popover` closes on any pointer press outside its own trigger, so pressing
  // a second card's trigger closes the first before it opens. A set of open
  // ids modelled a side-by-side comparison the pointer cannot actually reach.
  const [openMcp, setOpenMcp] = useState<string | null>(null);
  // Telling the owner is a SIDE EFFECT and so cannot live in the updater,
  // which React may run more than once — it hangs off the derived flag below.
  const openMcpFor = (agentId: string, open: boolean): void => {
    setOpenMcp((prev) => (open ? agentId : prev === agentId ? null : prev));
  };
  // Held in a ref so the effects below key on the OPEN STATE alone. Keyed on
  // the callback's identity instead, an inline arrow from a caller would run
  // the unmount cleanup on every re-render and slam the read gate shut
  // mid-open; that it works today rests on `Chats` passing a stable setter.
  const notifyMcpOpen = useRef(onMcpOpenChange);
  notifyMcpOpen.current = onMcpOpenChange;
  const anyMcpOpen = openMcp !== null;
  useEffect(() => {
    notifyMcpOpen.current?.(anyMcpOpen);
  }, [anyMcpOpen]);
  // Closing the PANEL closes every list in it — the state lives here and is
  // discarded on unmount, while the gate it drives lives in the owner. Without
  // this the owner is never told, so its gate stays open for the rest of the
  // session and the read it exists to withhold — the one that launches the
  // user's MCP servers — returns permanently after one open/close cycle.
  useEffect(
    () => () => {
      notifyMcpOpen.current?.(false);
    },
    [],
  );
  const [expanded, setExpanded] = useState<Set<string>>(new Set());
  const toggleExpanded = (agentId: string): void => {
    setExpanded((prev) => {
      const next = new Set(prev);
      if (!next.delete(agentId)) {
        next.add(agentId);
      }
      return next;
    });
  };
  // Which cards are also showing their FINISHED delegates. Separate state from
  // `expanded`, and per agent: a run that spawned forty delegates and finished
  // thirty-nine of them buried its one live thread under them, which is the
  // whole reason the list is split.
  const [showSettled, setShowSettled] = useState<Set<string>>(new Set());
  const toggleSettled = (agentId: string): void => {
    setShowSettled((prev) => {
      const next = new Set(prev);
      if (!next.delete(agentId)) {
        next.add(agentId);
      }
      return next;
    });
  };
  return (
    <aside
      className="relative flex min-h-0 flex-col border-l border-border bg-sidebar"
      style={{ width }}
      aria-label="Run agents">
      <PanelResizeHandle
        edge="left"
        label="Resize agents panel"
        onMouseDown={startResize}
        value={width}
        min={minWidth}
        max={maxWidth}
        onResize={resizeTo}
      />
      <div className="flex items-center justify-between py-1.5 pr-2 pl-3">
        <span className="text-xs font-medium tracking-wide text-muted-foreground uppercase">
          Agents
        </span>
        <span className="flex items-center gap-0.5">
          <Button
            type="button"
            variant="ghost"
            size="icon"
            className="size-7"
            aria-label="Close agents panel"
            title="Close"
            onClick={onClose}>
            <X className="size-4 shrink-0" />
          </Button>
        </span>
      </div>
      {mcpToggleError !== null && onDismissMcpToggleError ? (
        <ErrorBanner
          className="px-3 pb-1"
          message={mcpToggleError}
          onDismiss={onDismissMcpToggleError}
        />
      ) : null}
      <ul className="m-0 flex min-h-0 flex-1 list-none flex-col gap-1.5 overflow-y-auto p-3 pt-1">
        {agents.length === 0 ? (
          <li className="px-2 py-1.5 text-sm text-muted-foreground">
            No agents in this run
          </li>
        ) : (
          agents.map((agent) => {
            const isExpanded = expanded.has(agent.id);
            // Bound here so the toggle closure below carries a NARROWED kind
            // rather than a non-null assertion on a field re-read at call time.
            const mcpKind = agent.agent;
            const mcpScope =
              mcpKind === null
                ? null
                : mcpScopeKey({ agent: mcpKind, configDir: agent.configDir });
            // This CLI's handoff answer, resolved once for the card and its
            // thread rows. Null only when there is nothing to say — a workflow
            // agent whose kind is unknown, or a capability report still in
            // flight; a CLI that simply CANNOT resume is present here with its
            // reason and gets an inert control, not silence.
            const terminal =
              agent.agent !== null && terminalReasons?.has(agent.agent) === true
                ? { reason: terminalReasons.get(agent.agent) ?? null }
                : null;
            // The agent's OWN conversation. Its terminal control lives in the
            // card's header — always, not only when it is the agent's one thread
            // as before. It was a row in the list captioned `Conversation`, which
            // is the one thread every card has and the one the card itself
            // already names: a row for it was a heading repeated as a list item,
            // and it put the most-used control in the panel one disclosure away.
            const mainThread =
              agent.threads.find((thread) => thread.kind === 'main') ?? null;
            const mainTerminal =
              mainThread !== null && terminal !== null ? mainThread : null;
            // Delegates split by whether they are still WORKING. Only the live
            // ones belong in the list: a run that spawns twenty read-only
            // analysts leaves twenty rows behind it, and the one thread the
            // reader opened the panel to watch was somewhere in the middle of
            // them.
            const subagents = agent.threads.filter(
              (thread) => thread.kind === 'subagent',
            );
            const liveSubagents = subagents.filter(
              (thread) => thread.status === 'running',
            );
            const settledSubagents = subagents.filter(
              (thread) => thread.status !== 'running',
            );
            // What the list HOLDS: the calls this agent made, and the delegates
            // it is running. Not its own conversation (above), which is why an
            // agent with neither gets no list and no control to open one — the
            // 1:1 chat's whole shape, where a disclosure over an empty box is
            // pure nesting.
            const listedThreads = [
              ...agent.threads.filter((thread) => thread.kind === 'call'),
              ...liveSubagents,
            ];
            const hasList =
              listedThreads.length > 0 || settledSubagents.length > 0;
            const settledOpen = showSettled.has(agent.id);
            return (
              <li
                key={agent.id}
                className="flex flex-col rounded-lg border border-border bg-card shadow-panel-sm">
                {/* Line 1 — WHO this is: the name, and which CLI drives it.
                    A plain row, not a control: the thread list opens from the
                    button in the control row below, beside the MCP one, so
                    every affordance this card has sits in one place instead of
                    the whole header doubling as a hit target. */}
                <div className="flex flex-col rounded-lg px-2.5 pt-1.5 text-left">
                  <span className="flex items-center gap-1.5">
                    <span className="min-w-0 flex-1 truncate text-sm font-medium">
                      {agent.name}
                    </span>
                    {agent.agent ? (
                      <Badge variant="muted">{agent.agent}</Badge>
                    ) : null}
                  </span>
                </div>
                {/* Line 2 — WHAT it is doing, and what you can do about it:
                    status, how full its context is, and its two controls.
                    Everything that used to take three lines (status; a context
                    meter alone on the next; controls up beside the name) reads
                    as one row, which is what makes the card compact. */}
                <div className="flex items-center gap-1 px-2.5 pt-0.5 pb-1.5 text-xs">
                  <RunStatusIcon status={agent.status} />
                  {/* `needs-input` is a slug, not a sentence — hence `.label`. */}
                  <span className={RUN_STATUS_META[agent.status].className}>
                    {RUN_STATUS_META[agent.status].label}
                  </span>
                  {/*
                    The counts used to sit here, and they are now the thread
                    list's own header. On this line they were a running tally
                    nobody had asked for: every card carried "N active · M
                    threads" whether or not the reader had opened the list they
                    describe, and on a narrow panel they crowded out the one
                    thing this line is for — what the agent is DOING. Inside the
                    list they are a caption over the rows they count.
                  */}
                  <span className="ml-auto flex shrink-0 items-center gap-0.5">
                    <ContextMeter
                      contextTokens={agent.contextTokens}
                      contextWindowTokens={agent.contextWindowTokens}
                      spentUsd={agent.spentUsd}
                      // Why this card's meter is empty, when it always will be.
                      // Null for an agent whose kind the panel does not know, and
                      // for one whose report has not landed — both are "we have
                      // not been told", which must not print as a refusal.
                      unavailableReason={
                        agent.agent === null
                          ? null
                          : (usageReasons?.get(agent.agent) ?? null)
                      }
                      // The same box as the two icon buttons beside it, so the
                      // one `gap-0.5` produces one gap. The ring is 14px and
                      // their glyphs are 14px inside a 24px button, so left as
                      // content-width it sat 5px tighter against the terminal
                      // control than that control sits against the plug.
                      className="size-6 justify-center"
                    />
                    {mainTerminal ? (
                      <OpenInCliButton
                        agent={agent}
                        thread={mainTerminal}
                        label={`Open terminal for ${agent.name}`}
                        unavailableReason={terminal?.reason ?? null}
                        onOpen={onOpenThread}
                        onResolve={onResolveHandoff}
                      />
                    ) : null}
                    {mcpByScope && mcpKind !== null && mcpScope !== null ? (
                      <McpDisclosure
                        agentName={agent.name}
                        open={openMcp === agent.id}
                        onOpenChange={(next) => openMcpFor(agent.id, next)}
                        listing={mcpByScope.get(mcpScope)}
                        loading={mcpLoading}
                        onRefresh={onRefreshMcp}
                        onSetEnabled={
                          onSetMcpEnabled
                            ? (server, enabled) =>
                                onSetMcpEnabled(mcpKind, server, enabled)
                            : undefined
                        }
                        onSignIn={
                          onSignInMcp
                            ? (server) => onSignInMcp(mcpKind, server)
                            : undefined
                        }
                      />
                    ) : null}
                    {hasList ? (
                      // The thread list's own control, sitting with the rest of
                      // the card's buttons rather than as a chevron up on the
                      // name line. The header is then a plain row: nothing about
                      // an agent's NAME suggests pressing it, and while it was a
                      // button every control in this row had to stop the press
                      // from bubbling into it.
                      <Button
                        type="button"
                        variant="ghost"
                        size="icon"
                        aria-expanded={isExpanded}
                        aria-label={`${agent.name} threads`}
                        title={
                          isExpanded
                            ? 'Hide this agent’s threads'
                            : 'Show this agent’s threads'
                        }
                        className={cn(
                          'size-6 shrink-0',
                          // A chevron says WHICH WAY it opens and nothing about
                          // what is inside; this icon says what is inside, so the
                          // open state has to be carried some other way. Tone,
                          // like the other two controls in this row: the button
                          // reads as lit while its list is showing.
                          isExpanded
                            ? 'text-foreground'
                            : 'text-muted-foreground',
                        )}
                        onClick={() => toggleExpanded(agent.id)}>
                        {/*
                          What this opens is the agent's THREADS — its own
                          conversation, plus a row per delegate it is running —
                          so a nested list is what the glyph should be. It also
                          has to stay legible beside its two neighbours (a
                          context ring and the MCP plug) at 14px, which is why
                          this is `ListTree` rather than `Users` or `Network`:
                          a two-level list at that size still reads as a list,
                          while a cluster of figures or nodes turns to mush.
                        */}
                        <ListTree
                          aria-hidden="true"
                          className="size-3.5 shrink-0"
                        />
                      </Button>
                    ) : null}
                  </span>
                </div>
                {isExpanded && hasList ? (
                  <div className="flex flex-col border-t border-border px-2 py-1.5">
                    {/* The counts, in the one place they describe something: a
                        caption over the rows below. Both are the AGENT's own
                        figures rather than the list's — turns live anywhere on
                        it, and every thread it holds including the conversation
                        whose control sits in the header — so the number can
                        exceed the rows, and saying "threads" rather than naming
                        the rows is what keeps that honest. */}
                    <p className="m-0 px-1 pb-1 text-[11px] text-muted-foreground">
                      {agent.activeTurns} active · {agent.threads.length}{' '}
                      {agent.threads.length === 1 ? 'thread' : 'threads'}
                    </p>
                    <ul className="m-0 flex list-none flex-col gap-0.5">
                      {listedThreads.map((thread) => (
                        <ThreadRow
                          key={thread.id}
                          agent={agent}
                          thread={thread}
                          terminal={terminal}
                          onOpenThread={onOpenThread}
                          onOpenSubagent={onOpenSubagent}
                          onResolveHandoff={onResolveHandoff}
                        />
                      ))}
                      {settledSubagents.length > 0 ? (
                        <li className="flex flex-col">
                          <button
                            type="button"
                            aria-expanded={settledOpen}
                            onClick={() => toggleSettled(agent.id)}
                            // `font-normal` for the same reason the row label
                            // carries it: global.css's base `button` rule would
                            // otherwise weight this heavier than the threads it
                            // is counting.
                            className="flex items-center gap-1.5 rounded-md px-1 py-0.5 text-left text-xs font-normal text-muted-foreground transition-colors hover:text-foreground">
                            <ChevronRight
                              aria-hidden="true"
                              className={cn(
                                'size-3 shrink-0 transition-transform',
                                settledOpen && 'rotate-90',
                              )}
                            />
                            {/* Counted, not listed: the number is the only thing
                                a reader wants from work that is over, and it is
                                what says the rows above are the LIVE ones rather
                                than all there ever were. */}
                            <span>
                              {settledSubagents.length} finished sub-agent
                              {settledSubagents.length === 1 ? '' : 's'}
                            </span>
                          </button>
                          {settledOpen ? (
                            <ul className="m-0 flex list-none flex-col gap-0.5 pl-4">
                              {settledSubagents.map((thread) => (
                                <ThreadRow
                                  key={thread.id}
                                  agent={agent}
                                  thread={thread}
                                  terminal={terminal}
                                  onOpenThread={onOpenThread}
                                  onOpenSubagent={onOpenSubagent}
                                  onResolveHandoff={onResolveHandoff}
                                />
                              ))}
                            </ul>
                          ) : null}
                        </li>
                      ) : null}
                    </ul>
                  </div>
                ) : null}
              </li>
            );
          })
        )}
      </ul>
    </aside>
  );
}
