// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { createPreloadStub } from '../__fixtures__/preload-stub';
import { withVocabulary } from '../__tests__/agent-vocabulary-api';
import { emptyRunState } from '../__tests__/run-state';
import { stubResizeObserver } from '../__tests__/stub-resize-observer';
import type { ItemDto as ChatItem, RunDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { AnalysisDialog } from './analysis-dialog';
import type { HostedChatState } from './use-hosted-chat';

// The conversation hook has its own spec (through `useTeamChat`); this one
// is about what the popup opens and what its card's Apply reaches.
const { hosted } = vi.hoisted(() => ({
  hosted: {
    state: null as HostedChatState | null,
    args: null as null | {
      subject: string | null;
      open: () => Promise<RunDto>;
    },
  },
}));
vi.mock('./use-hosted-chat', () => ({
  useHostedChat: (args: {
    subject: string | null;
    open: () => Promise<RunDto>;
  }) => {
    hosted.args = args;
    return hosted.state;
  },
}));

const CARD = {
  sourceRunId: 'source',
  sourceKind: 'chat',
  summary: 'the reply named no pull request',
  timing: null,
  items: [
    {
      id: 'R-1',
      target: 'repo',
      territory: 'process',
      kind: 'ADD',
      location: 'AGENTS.md',
      title: 'Report every opened PR by URL',
      change: 'WHEN a PR is opened → name its URL',
      evidence: [{ seq: 2, quote: 'Done.' }],
      rootCause: 'termination',
      impact: { minutesSaved: 1, basis: 'one follow-up turn', confidence: 2 },
      risk: { level: 'low', note: 'longer replies' },
    },
  ],
};

function cardRow(): ChatItem {
  return {
    id: 'i7',
    runId: 'analysis-1',
    seq: 7,
    kind: 'recommendations',
    role: null,
    nodeId: null,
    payload: CARD,
    createdAt: '2026-10-15T00:00:07.000Z',
  } as unknown as ChatItem;
}

function chatState(overrides: Partial<HostedChatState>): HostedChatState {
  return {
    liveUnsent: [],
    run: {
      id: 'analysis-1',
      status: 'completed',
      agentKind: 'claude',
      model: 'opus',
      holdingFor: 0,
      shellsOpen: 0,
      subagentsOut: 0,
      monitorsOpen: 0,
    } as HostedChatState['run'],
    items: [],
    anchors: [],
    client: null,
    reconnectNonce: 0,
    markWorking: vi.fn(),
    liveText: new Map(),
    loading: false,
    error: null,
    working: false,
    activity: null,
    settledTurns: 0,
    settledAs: null,
    send: vi.fn(async () => true),
    post: vi.fn(async () => {}),
    patchSettings: vi.fn(async () => true),
    rememberContext: vi.fn(),
    deadRequestIds: new Set<string>(),
    respond: vi.fn(),
    cancel: vi.fn(async () => {}),
    discard: vi.fn(async () => {}),
    ...overrides,
  };
}

const getThreadAnalysis = vi.fn();
const getTeamAnalysis = vi.fn();
const APIS = {
  teams: { getTeamAnalysis },
  chats: {
    readRunState: vi.fn(async () => emptyRunState()),
    getThreadAnalysis,
    readChatMetrics: vi.fn(async () => ({})),
  },
  agents: withVocabulary({
    listAgentModels: vi.fn(async () => []),
    listAgentEfforts: vi.fn(async () => ({
      efforts: [],
      unavailableReason: null,
    })),
    listAgentContextWindows: vi.fn(async () => ({
      windows: [],
      unavailableReason: null,
      unavailableKind: null,
    })),
    listAgentModelParameters: vi.fn(async () => ({
      parameters: [],
      unavailableReason: null,
    })),
  }),
} as unknown as DaemonApis;

describe('AnalysisDialog', () => {
  let container: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    stubResizeObserver();
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    window.geniro = createPreloadStub();
    hosted.state = chatState({});
    hosted.args = null;
    getThreadAnalysis.mockReset();
    getTeamAnalysis.mockReset();
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    vi.restoreAllMocks();
  });

  async function paint(
    source: RunDto | null,
    props: {
      apply?: (runId: string, cardSeq: number, ids: string[]) => Promise<void>;
      onNewAnalysis?: () => void;
    } = {},
  ): Promise<void> {
    await act(async () => {
      root.render(
        <AnalysisDialog
          subject={source === null ? null : { kind: 'thread', run: source }}
          sourceLabel="Shelf — three open pull requests"
          apis={APIS}
          handle={null}
          client={null as unknown as DaemonClient}
          capabilities={null}
          capabilitiesLoading={false}
          recentConfigDirs={{}}
          configProfiles={[]}
          applyRecommendations={props.apply ?? vi.fn(async () => {})}
          onNewAnalysis={props.onNewAnalysis ?? vi.fn()}
          onClose={vi.fn()}
        />,
      );
    });
  }

  const SOURCE = { id: 'source' } as RunDto;

  it("opens the source thread's analysis, and refuses a thread with none", async () => {
    await paint(SOURCE);

    expect(hosted.args?.subject).toBe('source');
    getThreadAnalysis.mockResolvedValueOnce({
      analysis: { id: 'analysis-1', status: 'running' },
    });
    await expect(hosted.args!.open()).resolves.toMatchObject({
      id: 'analysis-1',
    });
    expect(getThreadAnalysis).toHaveBeenCalledWith({ runId: 'source' });

    getThreadAnalysis.mockResolvedValueOnce({ analysis: null });
    await expect(hosted.args!.open()).rejects.toThrow('no analysis');
  });

  it("opens a team's analysis by its slug, and refuses a team with none", async () => {
    await act(async () => {
      root.render(
        <AnalysisDialog
          subject={{ kind: 'team', slug: 'dev-team', name: 'Dev Team' }}
          sourceLabel="Dev Team"
          apis={APIS}
          handle={null}
          client={null as unknown as DaemonClient}
          capabilities={null}
          capabilitiesLoading={false}
          recentConfigDirs={{}}
          configProfiles={[]}
          applyRecommendations={vi.fn(async () => {})}
          onNewAnalysis={vi.fn()}
          onClose={vi.fn()}
        />,
      );
    });

    // Its own subject: never the builder chat's conversation about the slug.
    expect(hosted.args?.subject).toBe('team-analysis:dev-team');
    getTeamAnalysis.mockResolvedValueOnce({
      analysis: { id: 'analysis-1', status: 'running' },
    });
    await expect(hosted.args!.open()).resolves.toMatchObject({
      id: 'analysis-1',
    });
    expect(getTeamAnalysis).toHaveBeenCalledWith({ slug: 'dev-team' });
    expect(getThreadAnalysis).not.toHaveBeenCalled();

    getTeamAnalysis.mockResolvedValueOnce({ analysis: null });
    await expect(hosted.args!.open()).rejects.toThrow(
      'This team has no analysis yet.',
    );
  });

  describe('a message a Stop dropped', () => {
    const userRow = {
      id: 'i5',
      runId: 'analysis-1',
      seq: 5,
      kind: 'message',
      role: 'user',
      nodeId: null,
      payload: { text: 'look again', deliveryId: 'd-1' },
      createdAt: '2026-10-15T00:00:05.000Z',
    } as unknown as ChatItem;
    const marker = {
      id: 'i6',
      runId: 'analysis-1',
      seq: 6,
      kind: 'system',
      role: null,
      nodeId: null,
      payload: {
        message: 'Your message was not sent',
        severity: 'warning',
        caption: 'Not sent',
        unsentMessages: ['d-1'],
      },
      createdAt: '2026-10-15T00:00:06.000Z',
    } as unknown as ChatItem;
    const doc = (): Document => container.ownerDocument;

    it('resends it through the queue when the run can take it', async () => {
      hosted.state = chatState({ items: [userRow, marker] });
      await paint(SOURCE);

      const resend = [...doc().querySelectorAll('button')].find(
        (button) => button.textContent === 'Resend',
      );
      await act(async () => {
        resend!.click();
      });
      await act(async () => {
        await new Promise((resolve) => setTimeout(resolve, 0));
      });

      expect(hosted.state.post).toHaveBeenCalledWith(
        'look again',
        [],
        expect.any(String),
      );
    });

    it('puts it back in the empty composer when it was dropped just now', async () => {
      hosted.state = chatState({
        items: [userRow, marker],
        liveUnsent: [{ rowId: 'i6', deliveryIds: ['d-1'] }],
      });
      await paint(SOURCE);
      await act(async () => {
        await new Promise((resolve) => setTimeout(resolve, 0));
      });

      expect(doc().querySelector('textarea')?.value).toBe('look again');
    });

    it('waits for the message row when the marker lands first', async () => {
      hosted.state = chatState({
        items: [marker],
        liveUnsent: [{ rowId: 'i6', deliveryIds: ['d-1'] }],
      });
      await paint(SOURCE);
      expect(doc().querySelector('textarea')?.value).toBe('');

      hosted.state = { ...hosted.state, items: [userRow, marker] };
      await paint(SOURCE);
      await act(async () => {
        await new Promise((resolve) => setTimeout(resolve, 0));
      });

      expect(doc().querySelector('textarea')?.value).toBe('look again');
    });
  });

  it('draws nothing while no thread is chosen', async () => {
    await paint(null);

    expect(container.ownerDocument.querySelector('[role="dialog"]')).toBeNull();
    expect(hosted.args?.subject).toBeNull();
  });

  it("applies the card's selection for the analysis run", async () => {
    hosted.state = chatState({ items: [cardRow()] });
    const apply = vi.fn(async () => {});
    await paint(SOURCE, { apply });

    const buttons = (): HTMLButtonElement[] => [
      ...document.querySelectorAll<HTMLButtonElement>(
        '[data-slot="analysis-transcript"] button',
      ),
    ];
    await act(async () => {
      buttons()
        .find((b) => b.textContent?.includes('R-1'))!
        .click();
    });
    await act(async () => {
      buttons()
        .find((b) => b.textContent?.includes('Apply selected'))!
        .click();
    });

    expect(apply).toHaveBeenCalledWith('analysis-1', 7, ['R-1']);
  });

  it("presses an agent's button from its card in the popup", async () => {
    const live = {
      seq: 9,
      actionId: 'go',
      nodeId: 'agent',
      conversationId: '',
      label: 'Go on',
      once: true,
      spec: { kind: 'message' as const, text: 'continue' },
      publisher: { nodeId: 'agent', conversationId: '' },
      pending: false,
    };
    const chats = APIS.chats as unknown as {
      readRunState: ReturnType<typeof vi.fn>;
      pressChatAction?: ReturnType<typeof vi.fn>;
    };
    chats.readRunState.mockResolvedValueOnce({
      ...emptyRunState(),
      actions: [live],
      throughSeq: 9,
    });
    const pressChatAction = vi.fn(async () => ({
      outcome: {
        actionSeq: 9,
        actionId: 'go',
        nodeId: 'agent',
        conversationId: '',
        state: 'succeeded',
      },
    }));
    chats.pressChatAction = pressChatAction;
    hosted.state = chatState({
      items: [
        {
          id: 'i9',
          runId: 'analysis-1',
          seq: 9,
          kind: 'action',
          role: null,
          nodeId: null,
          payload: {
            actionId: 'go',
            label: 'Go on',
            once: true,
            spec: { kind: 'message', text: 'continue' },
            publisher: { nodeId: 'agent', conversationId: '' },
          },
          createdAt: '2026-10-15T00:00:09.000Z',
        } as unknown as ChatItem,
      ],
    });
    await paint(SOURCE);

    const chip = document.querySelector<HTMLButtonElement>(
      '[data-slot="analysis-transcript"] [data-slot="action-chip"]',
    );
    await act(async () => chip!.click());

    expect(pressChatAction).toHaveBeenCalledWith({
      runId: 'analysis-1',
      seq: 9,
      pressActionDto: { clientMessageId: expect.any(String) as string },
    });
    delete chats.pressChatAction;
  });

  it('re-reads the live buttons after the socket reconnects', async () => {
    const readRunState = (
      APIS.chats as unknown as { readRunState: ReturnType<typeof vi.fn> }
    ).readRunState;
    readRunState.mockClear();
    await paint(SOURCE);
    // Re-painting with nothing changed reads nothing more.
    await paint(SOURCE);
    const settled = readRunState.mock.calls.length;

    hosted.state = chatState({ reconnectNonce: 1 });
    await paint(SOURCE);

    expect(readRunState).toHaveBeenCalledTimes(settled + 1);
  });

  it('offers a new analysis from its header', async () => {
    const onNewAnalysis = vi.fn();
    await paint(SOURCE, { onNewAnalysis });

    await act(async () => {
      [...document.querySelectorAll<HTMLButtonElement>('button')]
        .find((b) => b.textContent?.includes('New analysis'))!
        .click();
    });

    expect(onNewAnalysis).toHaveBeenCalledTimes(1);
    expect(
      document.querySelector('[data-slot="analysis-status"]'),
    ).not.toBeNull();
  });
});
