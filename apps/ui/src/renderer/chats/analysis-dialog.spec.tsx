// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { RunDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { AnalysisDialog } from './analysis-dialog';
import type { HostedThread } from './hosted-thread';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

// The chat screen draws the analysis and has its own spec for a hosted thread;
// this one is about what the POPUP hands it.
const drawn = { hosted: null as HostedThread | null };
function renderThread(hosted: HostedThread): React.ReactNode {
  drawn.hosted = hosted;
  return hosted.headerActions?.({ discard: null });
}

const SOURCE = { id: 'r1', title: 'My chat' } as RunDto;
const ANALYSIS = { id: 'a1', status: 'running' } as RunDto;

const getThreadAnalysis = vi.fn();
const getTeamAnalysis = vi.fn();
const APIS = {
  chats: { getThreadAnalysis },
  teams: { getTeamAnalysis },
} as unknown as DaemonApis;

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  window.geniro = createPreloadStub();
  drawn.hosted = null;
  getThreadAnalysis
    .mockReset()
    .mockImplementation(async () => ({ analysis: ANALYSIS }));
  getTeamAnalysis
    .mockReset()
    .mockImplementation(async () => ({ analysis: ANALYSIS }));
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => {
    root.unmount();
  });
  container.remove();
});

const onNewAnalysis = vi.fn();
const onTurnSettled = vi.fn();

async function paint(
  subject: Parameters<typeof AnalysisDialog>[0]['subject'],
  render: typeof renderThread | null = renderThread,
): Promise<void> {
  await act(async () => {
    root.render(
      <AnalysisDialog
        subject={subject}
        sourceLabel="My chat"
        apis={APIS}
        renderThread={render}
        onNewAnalysis={onNewAnalysis}
        onTurnSettled={onTurnSettled}
        onClose={() => undefined}
      />,
    );
  });
}

function thread(): HostedThread {
  if (drawn.hosted === null) {
    throw new Error('the popup drew no chat');
  }
  return drawn.hosted;
}

describe('AnalysisDialog', () => {
  it('remembers a setup changed in the analysis’s chat for the next one', async () => {
    const updateSettings = vi.fn().mockResolvedValue({});
    window.geniro = createPreloadStub({ updateSettings });
    await paint({ kind: 'thread', run: SOURCE });

    await thread().onRunSettingsChanged!({
      id: 'a1',
      agentKind: 'claude',
      configDir: null,
      model: 'opus',
      effort: 'xhigh',
      contextWindow: null,
      autoCompactPercent: null,
      modelParameters: {},
      approval: 'auto',
    } as RunDto);

    expect(updateSettings).toHaveBeenCalledWith({
      lastAnalysisConfig: expect.objectContaining({
        agent: 'claude',
        model: 'opus',
        effort: 'xhigh',
        approval: 'auto',
      }),
    });
  });

  it('opens a thread’s analysis by the thread it reads', async () => {
    await paint({ kind: 'thread', run: SOURCE });

    await expect(thread().open()).resolves.toBe(ANALYSIS);
    expect(getThreadAnalysis).toHaveBeenCalledWith({ runId: 'r1' });
    expect(getTeamAnalysis).not.toHaveBeenCalled();
  });

  it('opens a team’s analysis by the team', async () => {
    await paint({ kind: 'team', slug: 'dev-team', name: 'Dev Team' });

    await expect(thread().open()).resolves.toBe(ANALYSIS);
    expect(getTeamAnalysis).toHaveBeenCalledWith({ slug: 'dev-team' });
    expect(getThreadAnalysis).not.toHaveBeenCalled();
  });

  it('says so when the subject has no analysis to open', async () => {
    getThreadAnalysis.mockImplementation(async () => ({ analysis: null }));
    await paint({ kind: 'thread', run: SOURCE });

    await expect(thread().open()).rejects.toThrow(
      'This thread has no analysis yet.',
    );
  });

  it('offers a new analysis from the thread’s header', async () => {
    await paint({ kind: 'thread', run: SOURCE });

    const button = [...document.body.querySelectorAll('button')].find(
      (candidate) => candidate.textContent?.includes('New analysis'),
    );
    await act(async () => {
      button?.click();
    });

    expect(onNewAnalysis).toHaveBeenCalledTimes(1);
  });

  it('re-reads after each turn through the host, and creates nothing', async () => {
    await paint({ kind: 'team', slug: 'dev-team', name: 'Dev Team' });

    expect(thread().onTurnSettled).toBe(onTurnSettled);
    expect(thread().discard).toBeUndefined();
    expect(thread().queueScope).toBe('analysis:team-analysis:dev-team');
  });

  it('draws no conversation while closed, or before the daemon is reached', async () => {
    await paint(null);
    expect(drawn.hosted).toBeNull();

    await paint({ kind: 'thread', run: SOURCE }, null);
    expect(drawn.hosted).toBeNull();
  });
});
