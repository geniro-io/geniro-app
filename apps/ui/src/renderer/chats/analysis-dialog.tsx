import { RotateCcw } from 'lucide-react';
import { Fragment } from 'react';

import type { RunDto } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { AnalysedTeamSubject } from './analyze-thread-dialog';
import type { HostedThread } from './hosted-thread';
import { rememberAnalysisSetup } from './improvement-chat-setup';

/**
 * A thread's analysis, in a popup over the thread it reads.
 *
 * The analysis is an ordinary chat the sidebar never lists — REPORTED as "I
 * should not see this thread in shared list - same as for thread with
 * changing team. It should be just in different popup" — so this is the
 * only place it is read, answered, applied and replaced. One per thread
 * (`GET /v1/chats/:runId/analysis`): New analysis opens the setup dialog
 * again, and starting there replaces this one. The popup draws it with the
 * chat screen itself, which the caller hands in as `renderThread` (`Chats`
 * with `hosted`) — the chat screen draws this popup too.
 *
 * Closing it stops nothing: the analysis runs in the daemon, and the thread's
 * Analyze button says when it is working or waiting on you.
 *
 * A team's subject is that team's analysis across its recent runs
 * ("Analyze & improve", `GET /v1/teams/:slug/analysis`), hosted over the
 * builder the same way.
 */
export function AnalysisDialog({
  subject,
  sourceLabel,
  apis,
  renderThread,
  onNewAnalysis,
  onTurnSettled,
  onClose,
}: {
  /** Whose analysis this is; the popup is open while it is non-null. */
  subject:
    | { kind: 'thread'; run: RunDto }
    | ({ kind: 'team' } & AnalysedTeamSubject)
    | null;
  sourceLabel: string;
  apis: DaemonApis;
  /** Draws the conversation; null until the daemon is reached. */
  renderThread: ((thread: HostedThread) => React.ReactNode) | null;
  /** Open the setup dialog to start a new analysis, which replaces this one. */
  onNewAnalysis: () => void;
  /** A turn of the analysis ended — it may have changed the team. */
  onTurnSettled?: () => void | Promise<void>;
  onClose: () => void;
}): React.JSX.Element {
  const slug = subject?.kind === 'team' ? subject.slug : null;
  const sourceId =
    subject === null
      ? null
      : subject.kind === 'thread'
        ? subject.run.id
        : `team-analysis:${subject.slug}`;
  const open = useLatestCallback(async (): Promise<RunDto> => {
    if (sourceId === null) {
      throw new Error('This analysis is closed.');
    }
    const { analysis } =
      slug === null
        ? await apis.chats.getThreadAnalysis({ runId: sourceId })
        : await apis.teams.getTeamAnalysis({ slug });
    if (analysis == null) {
      throw new Error(
        slug === null
          ? 'This thread has no analysis yet.'
          : 'This team has no analysis yet.',
      );
    }
    return analysis;
  }, [apis, sourceId, slug]);
  const subjectWord = slug === null ? 'thread' : 'team';
  const headerActions = useLatestCallback(
    () => (
      <Button
        type="button"
        variant="ghost"
        size="sm"
        className="shrink-0"
        title={`Set up a new analysis of this ${subjectWord} — starting it replaces this one`}
        onClick={onNewAnalysis}>
        <RotateCcw className="size-3.5" />
        New analysis
      </Button>
    ),
    [subjectWord, onNewAnalysis],
  );

  return (
    <Dialog
      open={sourceId !== null}
      onClose={onClose}
      className="h-full max-w-5xl"
      flush
      title={
        <span className="flex min-w-0 items-center gap-2">
          <span className="shrink-0">Analysis</span>
          <span className="min-w-0 truncate font-normal text-muted-foreground">
            {sourceLabel}
          </span>
        </span>
      }>
      <div data-slot="analysis-dialog" className="flex h-full min-h-0 flex-col">
        {sourceId === null || renderThread === null ? null : (
          <Fragment key={sourceId}>
            {renderThread({
              open,
              queueScope: `analysis:${sourceId}`,
              emptyText:
                slug === null
                  ? 'The analysis is starting — it reads the thread, then posts what it found and a card of changes to pick from.'
                  : 'The analysis is starting — it reads the team’s latest runs, then posts what it found and a card of changes to pick from.',
              composerLabel: 'Message the analysis',
              composerPlaceholder:
                'Ask about a finding, or what to change instead…',
              onTurnSettled,
              onRunSettingsChanged: rememberAnalysisSetup,
              headerActions,
            })}
          </Fragment>
        )}
      </div>
    </Dialog>
  );
}
