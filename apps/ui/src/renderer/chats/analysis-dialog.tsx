import { RotateCcw } from 'lucide-react';
import { useCallback } from 'react';

import type {
  CliKind,
  ConfigProfile,
  DaemonHandle,
} from '../../shared/contracts';
import type { CapabilitiesDto, RunDto } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { HostedChat } from './hosted-chat';
import type { RecommendationsApplier } from './recommendations-apply-context';
import { RunStatusBadge } from './run-status';
import { useHostedChat } from './use-hosted-chat';

/**
 * A thread's analysis, in a popup over the thread it reads.
 *
 * The analysis is an ordinary chat the sidebar never lists — REPORTED as "I
 * should not see this thread in shared list - same as for thread with
 * changing workflow. It should be just in different popup" — so this is the
 * only place it is read, answered, applied and replaced. One per thread
 * (`GET /v1/chats/:runId/analysis`): New analysis opens the setup dialog
 * again, and starting there replaces this one.
 *
 * Closing it stops nothing: the analysis runs in the daemon, and the thread's
 * Analyze button says when it is working or waiting on you.
 */
export function AnalysisDialog({
  source,
  sourceLabel,
  apis,
  handle,
  client,
  capabilities,
  capabilitiesLoading,
  recentConfigDirs,
  configProfiles,
  applyRecommendations,
  onNewAnalysis,
  onClose,
}: {
  /** The thread whose analysis this is; the popup is open while it is non-null. */
  source: RunDto | null;
  sourceLabel: string;
  apis: DaemonApis | null;
  /** This launch's daemon — what a published page's URL is built from. */
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  recentConfigDirs: Partial<Record<CliKind, readonly string[]>>;
  configProfiles: readonly ConfigProfile[];
  applyRecommendations: RecommendationsApplier;
  /** Open the setup dialog to start a new analysis, which replaces this one. */
  onNewAnalysis: () => void;
  onClose: () => void;
}): React.JSX.Element {
  const sourceId = source?.id ?? null;
  const open = useCallback(async (): Promise<RunDto> => {
    if (apis === null || sourceId === null) {
      throw new Error('daemon unavailable');
    }
    const { analysis } = await apis.chats.getThreadAnalysis({
      runId: sourceId,
    });
    if (analysis == null) {
      throw new Error('This thread has no analysis yet.');
    }
    return analysis;
  }, [apis, sourceId]);
  const chat = useHostedChat({ subject: sourceId, apis, client, open });

  return (
    <Dialog
      open={source !== null}
      onClose={onClose}
      className="h-full max-w-5xl"
      flush
      title={
        <span className="flex min-w-0 items-center gap-2">
          <span className="shrink-0">Analysis</span>
          <span className="min-w-0 truncate font-normal text-muted-foreground">
            {sourceLabel}
          </span>
        </span>
      }>
      <div data-slot="analysis-dialog" className="flex h-full min-h-0 flex-col">
        {sourceId === null ? null : (
          <HostedChat
            chat={chat}
            ownerKey={sourceId}
            apis={apis}
            handle={handle}
            capabilities={capabilities}
            capabilitiesLoading={capabilitiesLoading}
            recentConfigDirs={recentConfigDirs}
            configProfiles={configProfiles}
            applyRecommendations={applyRecommendations}
            transcriptSlot="analysis-transcript"
            emptyText="The analysis is starting — it reads the thread, then posts what it found and a card of changes to pick from."
            composerLabel="Message the analysis"
            composerPlaceholder="Ask about a finding, or what to change instead…"
            header={({ run, status }) => (
              <div className="flex items-center gap-2 border-b border-border px-5 py-2">
                {run === null ? null : (
                  <RunStatusBadge data-slot="analysis-status" status={status} />
                )}
                <span className="min-w-0 truncate text-xs text-muted-foreground">
                  {run === null
                    ? null
                    : [run.agentKind, run.model].filter(Boolean).join(' · ')}
                </span>
                <Button
                  type="button"
                  variant="ghost"
                  size="sm"
                  className="ml-auto shrink-0"
                  title="Set up a new analysis of this thread — starting it replaces this one"
                  onClick={onNewAnalysis}>
                  <RotateCcw className="size-3.5" />
                  New analysis
                </Button>
              </div>
            )}
          />
        )}
      </div>
    </Dialog>
  );
}
