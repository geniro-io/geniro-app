// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  type AnalysisConfig,
  DEFAULT_SETTINGS,
  type Settings,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type {
  AgentApprovalCapability,
  ChatsApi,
  RunDto,
  WorkflowsApi,
} from '../autogenerated';
import { AnalyzeThreadDialog } from './analyze-thread-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const COMPOSER: AnalysisConfig = {
  agent: 'claude',
  configDir: null,
  model: 'opus',
  effort: null,
  approval: null,
};

const CLAUDE_APPROVALS: AgentApprovalCapability = {
  agent: 'claude',
  modes: ['auto', 'ask', 'acceptEdits', 'plan'],
  probe: null,
};

function source(over: Partial<RunDto> = {}): RunDto {
  return {
    id: 'source',
    title: 'Dev Team run',
    workflowId: null,
    cwd: '/tmp/project',
    workedMs: 3_600_000,
    toolCalls: 412,
    ...over,
  } as RunDto;
}

let settings: Partial<Settings>;
let updates: Partial<Settings>[];

beforeEach(() => {
  settings = {};
  updates = [];
  window.geniro = createPreloadStub({
    getSettings: () => Promise.resolve({ ...DEFAULT_SETTINGS, ...settings }),
    updateSettings: (patch) => {
      updates.push(patch);
      return Promise.resolve({ ...DEFAULT_SETTINGS, ...settings });
    },
    pickProjectFolder: () => Promise.resolve('/tmp/elsewhere'),
  });
});

async function render(
  run: RunDto,
  analyzeThread: ReturnType<typeof vi.fn>,
  onStarted = vi.fn(),
): Promise<void> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(
      <AnalyzeThreadDialog
        subject={{ kind: 'thread', run }}
        sourceLabel={run.title ?? 'thread'}
        chatApi={{ analyzeThread } as unknown as ChatsApi}
        agentsApi={null}
        cliDetections={null}
        composerSetup={COMPOSER}
        recentConfigDirsFor={() => []}
        configProfilesFor={() => []}
        configDirReasonFor={() => null}
        approvalCapabilityFor={() => CLAUDE_APPROVALS}
        runSettings={() => Promise.resolve({ customInstructions: 'be brief' })}
        onClose={() => undefined}
        onStarted={onStarted}
      />,
    );
  });
}

function button(name: string): HTMLButtonElement {
  const found = [...document.querySelectorAll('button')].find((el) =>
    el.textContent?.includes(name),
  );
  if (!found) {
    throw new Error(`no button "${name}"`);
  }
  return found as HTMLButtonElement;
}

async function press(name: string): Promise<void> {
  await act(async () => {
    button(name).click();
  });
}

describe('AnalyzeThreadDialog', () => {
  it("starts from the composer's setup the first time, and remembers the choice", async () => {
    const analyzeThread = vi.fn().mockResolvedValue({ id: 'analysis' });
    const onStarted = vi.fn();
    await render(source(), analyzeThread, onStarted);

    await press('Start analysis');

    expect(analyzeThread).toHaveBeenCalledWith({
      runId: 'source',
      analyzeThreadDto: {
        agentKind: 'claude',
        approval: 'auto',
        model: 'opus',
        customInstructions: 'be brief',
      },
    });
    expect(onStarted).toHaveBeenCalledWith({ id: 'analysis' });
    expect(updates).toEqual([
      { lastAnalysisConfig: { ...COMPOSER, approval: 'auto' } },
    ]);
  });

  it('offers the approval mode, opening on auto-approve and never on plan', async () => {
    const analyzeThread = vi.fn().mockResolvedValue({ id: 'analysis' });
    await render(source(), analyzeThread);

    const trigger = document.querySelector<HTMLButtonElement>(
      '[aria-label="Tool-approval mode of the analysis"]',
    )!;
    expect(trigger.textContent).toContain('auto-approve');
    act(() => {
      trigger.click();
    });
    const options = [
      ...document.querySelectorAll<HTMLElement>('[role="option"]'),
    ];
    expect(options.map((option) => option.textContent)).toEqual([
      'ask',
      'accept edits',
      'auto-approve',
    ]);
    await act(async () => {
      options[0]!.click();
    });
    await press('Start analysis');

    expect(analyzeThread.mock.calls[0]![0].analyzeThreadDto.approval).toBe(
      'ask',
    );
    expect(updates[0]!.lastAnalysisConfig?.approval).toBe('ask');
  });

  it('opens on the last analysis choice when there is one', async () => {
    settings = {
      lastAnalysisConfig: {
        agent: 'codex',
        configDir: null,
        model: 'gpt-5.5',
        effort: 'high',
        approval: 'acceptEdits',
      },
    };
    const analyzeThread = vi.fn().mockResolvedValue({ id: 'analysis' });
    await render(source(), analyzeThread);

    await press('Start analysis');

    expect(analyzeThread.mock.calls[0]![0].analyzeThreadDto).toMatchObject({
      agentKind: 'codex',
      model: 'gpt-5.5',
      effort: 'high',
      approval: 'acceptEdits',
    });
  });

  it('says what will be suggested by the kind of thread', async () => {
    await render(source({ workflowId: 'dev-team' }), vi.fn());
    expect(
      document.querySelector('[data-slot="scope-note"]')?.textContent,
    ).toContain('workflow changes');

    act(() => root?.unmount());
    container?.remove();
    await render(source(), vi.fn());
    expect(
      document.querySelector('[data-slot="scope-note"]')?.textContent,
    ).not.toContain('workflow changes');
  });

  it('asks for a folder when the thread’s folder is gone, then runs there', async () => {
    const analyzeThread = vi
      .fn()
      .mockRejectedValueOnce(
        new Error(
          'daemon POST /v1/chats/source/analyses failed (409): {"code":"ANALYSIS_FOLDER_GONE","message":"the thread\'s folder no longer exists"}',
        ),
      )
      .mockResolvedValueOnce({ id: 'analysis' });
    const onStarted = vi.fn();
    await render(source(), analyzeThread, onStarted);

    await press('Start analysis');

    expect(onStarted).not.toHaveBeenCalled();
    expect(document.querySelector('[role="alert"]')?.textContent).toContain(
      'no longer exists',
    );
    expect(button('Start analysis').disabled).toBe(true);

    await press('Choose a folder');
    await press('Start analysis');

    expect(analyzeThread.mock.calls[1]![0].analyzeThreadDto.cwd).toBe(
      '/tmp/elsewhere',
    );
    expect(onStarted).toHaveBeenCalledTimes(1);
  });

  it('keeps the dialog open with the daemon’s sentence on any other refusal', async () => {
    const analyzeThread = vi
      .fn()
      .mockRejectedValue(
        new Error(
          'daemon POST /v1/chats/source/analyses failed (409): {"code":"ANALYSIS_SOURCE_ARCHIVED","message":"an archived thread cannot be analysed"}',
        ),
      );
    const onStarted = vi.fn();
    await render(source(), analyzeThread, onStarted);

    await press('Start analysis');

    expect(onStarted).not.toHaveBeenCalled();
    expect(document.querySelector('[role="alert"]')?.textContent).toContain(
      'an archived thread cannot be analysed',
    );
    expect(button('Start analysis').disabled).toBe(false);
  });

  describe('on a workflow', () => {
    async function renderWorkflow(
      analyzeWorkflow: ReturnType<typeof vi.fn>,
      onStarted = vi.fn(),
    ): Promise<void> {
      container = document.createElement('div');
      document.body.appendChild(container);
      root = createRoot(container);
      await act(async () => {
        root!.render(
          <AnalyzeThreadDialog
            subject={{
              kind: 'workflow',
              slug: 'dev-team',
              name: 'Dev Team',
              api: { analyzeWorkflow } as unknown as WorkflowsApi,
            }}
            sourceLabel="Dev Team"
            chatApi={{} as ChatsApi}
            agentsApi={null}
            cliDetections={null}
            composerSetup={COMPOSER}
            recentConfigDirsFor={() => []}
            configProfilesFor={() => []}
            configDirReasonFor={() => null}
            approvalCapabilityFor={() => CLAUDE_APPROVALS}
            runSettings={() => Promise.resolve({})}
            onClose={() => undefined}
            onStarted={onStarted}
          />,
        );
      });
    }

    it('starts a workflow analysis over the number of latest runs picked', async () => {
      const analyzeWorkflow = vi.fn().mockResolvedValue({ id: 'analysis' });
      const onStarted = vi.fn();
      await renderWorkflow(analyzeWorkflow, onStarted);

      expect(document.body.textContent).toContain('Analyze workflow');
      expect(document.body.textContent).toContain(
        'compares how its agents and their models did',
      );
      expect(
        document
          .querySelector('[aria-label="Latest runs to analyse"]')
          ?.textContent?.trim(),
      ).toBe('10');
      await act(async () => {
        (
          document.querySelector(
            '[aria-label="Decrease Latest runs to analyse"]',
          ) as HTMLButtonElement
        ).click();
      });
      await press('Start analysis');

      expect(analyzeWorkflow).toHaveBeenCalledWith({
        slug: 'dev-team',
        analyzeWorkflowDto: {
          agentKind: 'claude',
          approval: 'auto',
          model: 'opus',
          runs: 9,
        },
      });
      expect(onStarted).toHaveBeenCalledWith({ id: 'analysis' });
    });

    it('keeps the dialog open on a workflow never run', async () => {
      const analyzeWorkflow = vi
        .fn()
        .mockRejectedValue(
          new Error(
            'daemon POST /v1/workflows/dev-team/analyses failed (409): {"code":"ANALYSIS_NO_RUNS","message":"the workflow has no runs to analyse yet — run it first"}',
          ),
        );
      const onStarted = vi.fn();
      await renderWorkflow(analyzeWorkflow, onStarted);

      await press('Start analysis');

      expect(onStarted).not.toHaveBeenCalled();
      expect(document.querySelector('[role="alert"]')?.textContent).toContain(
        'the workflow has no runs to analyse yet',
      );
    });
  });
});
