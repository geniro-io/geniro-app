// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  type AnalysisConfig,
  DEFAULT_SETTINGS,
  type Settings,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type {
  AgentApprovalCapability,
  ChatsApi,
  RunDto,
  TeamsApi,
} from '../autogenerated';
import { AnalyzeThreadDialog } from './analyze-thread-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const COMPOSER: AnalysisConfig = {
  agent: 'claude',
  configDir: null,
  model: 'opus',
  effort: null,
  contextWindow: null,
  autoCompactPercent: null,
  modelParameters: {},
  approval: null,
};

const CLAUDE_APPROVALS: AgentApprovalCapability = {
  agent: 'claude',
  modes: ['auto', 'ask', 'acceptEdits', 'plan'],
  probe: null,
};

function source(over: Partial<RunDto> = {}): RunDto {
  return {
    id: 'source',
    title: 'Dev Team run',
    teamId: null,
    cwd: '/tmp/project',
    workedMs: 3_600_000,
    toolCalls: 412,
    ...over,
  } as RunDto;
}

let settings: Partial<Settings>;
let updates: Partial<Settings>[];

beforeEach(() => {
  settings = {};
  updates = [];
  window.geniro = createPreloadStub({
    getSettings: () => Promise.resolve({ ...DEFAULT_SETTINGS, ...settings }),
    updateSettings: (patch) => {
      updates.push(patch);
      return Promise.resolve({ ...DEFAULT_SETTINGS, ...settings });
    },
    pickProjectFolder: () => Promise.resolve('/tmp/elsewhere'),
  });
});

async function render(
  run: RunDto,
  analyzeThread: ReturnType<typeof vi.fn>,
  onStarted = vi.fn(),
): Promise<void> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(
      <AnalyzeThreadDialog
        subject={{ kind: 'thread', run }}
        sourceLabel={run.title ?? 'thread'}
        chatApi={{ analyzeThread } as unknown as ChatsApi}
        agentsApi={null}
        cliDetections={null}
        composerSetup={COMPOSER}
        recentConfigDirsFor={() => []}
        configProfilesFor={() => []}
        configDirReasonFor={() => null}
        approvalCapabilityFor={() => CLAUDE_APPROVALS}
        runSettings={() => Promise.resolve({ customInstructions: 'be brief' })}
        onClose={() => undefined}
        onStarted={onStarted}
      />,
    );
  });
}

function button(name: string): HTMLButtonElement {
  const found = [...document.querySelectorAll('button')].find((el) =>
    el.textContent?.includes(name),
  );
  if (!found) {
    throw new Error(`no button "${name}"`);
  }
  return found as HTMLButtonElement;
}

async function press(name: string): Promise<void> {
  await act(async () => {
    button(name).click();
  });
}

describe('AnalyzeThreadDialog', () => {
  it("starts from the composer's setup the first time, and remembers the choice", async () => {
    const analyzeThread = vi.fn().mockResolvedValue({ id: 'analysis' });
    const onStarted = vi.fn();
    await render(source(), analyzeThread, onStarted);

    await press('Start analysis');

    expect(analyzeThread).toHaveBeenCalledWith({
      runId: 'source',
      analyzeThreadDto: {
        agentKind: 'claude',
        approval: 'auto',
        model: 'opus',
        customInstructions: 'be brief',
      },
    });
    expect(onStarted).toHaveBeenCalledWith({ id: 'analysis' });
    expect(updates).toEqual([
      { lastAnalysisConfig: { ...COMPOSER, approval: 'auto' } },
    ]);
  });

  it('offers the approval mode, opening on auto-approve and never on plan', async () => {
    const analyzeThread = vi.fn().mockResolvedValue({ id: 'analysis' });
    await render(source(), analyzeThread);

    const trigger = document.querySelector<HTMLButtonElement>(
      '[aria-label="Tool-approval mode of the analysis"]',
    )!;
    expect(trigger.textContent).toContain('auto-approve');
    act(() => {
      trigger.click();
    });
    const options = [
      ...document.querySelectorAll<HTMLElement>('[role="option"]'),
    ];
    expect(options.map((option) => option.textContent)).toEqual([
      'ask',
      'accept edits',
      'auto-approve',
    ]);
    await act(async () => {
      options[0]!.click();
    });
    await press('Start analysis');

    expect(analyzeThread.mock.calls[0]![0].analyzeThreadDto.approval).toBe(
      'ask',
    );
    expect(updates[0]!.lastAnalysisConfig?.approval).toBe('ask');
  });

  it('opens on the last analysis choice when there is one', async () => {
    settings = {
      lastAnalysisConfig: {
        agent: 'codex',
        configDir: null,
        model: 'gpt-5.5',
        effort: 'high',
        contextWindow: '1m',
        autoCompactPercent: 80,
        modelParameters: { fast: 'on' },
        approval: 'acceptEdits',
      },
    };
    const analyzeThread = vi.fn().mockResolvedValue({ id: 'analysis' });
    await render(source(), analyzeThread);

    await press('Start analysis');

    expect(analyzeThread.mock.calls[0]![0].analyzeThreadDto).toMatchObject({
      agentKind: 'codex',
      model: 'gpt-5.5',
      effort: 'high',
      contextWindow: '1m',
      autoCompactPercent: 80,
      modelParameters: { fast: 'on' },
      approval: 'acceptEdits',
    });
    expect(updates[0]!.lastAnalysisConfig).toMatchObject({
      contextWindow: '1m',
      autoCompactPercent: 80,
      modelParameters: { fast: 'on' },
    });
  });

  it('shows the remembered auto-compact threshold and changes it', async () => {
    settings = {
      lastAnalysisConfig: { ...COMPOSER, autoCompactPercent: 80 },
    };
    const analyzeThread = vi.fn().mockResolvedValue({ id: 'analysis' });
    await render(source(), analyzeThread);

    const trigger = document.querySelector<HTMLButtonElement>(
      '[aria-label="Auto-compact of the analysis"]',
    )!;
    expect(trigger.textContent).toContain('80');
    act(() => {
      trigger.click();
    });
    const never = [
      ...document.querySelectorAll<HTMLElement>('[role="option"]'),
    ].find((option) => !/\d/.test(option.textContent ?? ''))!;
    await act(async () => {
      never.click();
    });
    await press('Start analysis');

    expect(analyzeThread.mock.calls[0]![0].analyzeThreadDto).not.toHaveProperty(
      'autoCompactPercent',
    );
    expect(updates[0]!.lastAnalysisConfig?.autoCompactPercent).toBeNull();
  });

  it('says what will be suggested by the kind of thread', async () => {
    await render(source({ teamId: 'dev-team' }), vi.fn());
    expect(
      document.querySelector('[data-slot="scope-note"]')?.textContent,
    ).toContain('team changes');

    act(() => root?.unmount());
    container?.remove();
    await render(source(), vi.fn());
    expect(
      document.querySelector('[data-slot="scope-note"]')?.textContent,
    ).not.toContain('team changes');
  });

  it('asks for a folder when the thread’s folder is gone, then runs there', async () => {
    const analyzeThread = vi
      .fn()
      .mockRejectedValueOnce(
        new Error(
          'daemon POST /v1/chats/source/analyses failed (409): {"code":"ANALYSIS_FOLDER_GONE","message":"the thread\'s folder no longer exists"}',
        ),
      )
      .mockResolvedValueOnce({ id: 'analysis' });
    const onStarted = vi.fn();
    await render(source(), analyzeThread, onStarted);

    await press('Start analysis');

    expect(onStarted).not.toHaveBeenCalled();
    expect(document.querySelector('[role="alert"]')?.textContent).toContain(
      'no longer exists',
    );
    expect(button('Start analysis').disabled).toBe(true);

    await press('Choose a folder');
    await press('Start analysis');

    expect(analyzeThread.mock.calls[1]![0].analyzeThreadDto.cwd).toBe(
      '/tmp/elsewhere',
    );
    expect(onStarted).toHaveBeenCalledTimes(1);
  });

  it('keeps the dialog open with the daemon’s sentence on any other refusal', async () => {
    const analyzeThread = vi
      .fn()
      .mockRejectedValue(
        new Error(
          'daemon POST /v1/chats/source/analyses failed (409): {"code":"ANALYSIS_SOURCE_EMPTY","message":"the thread has nothing in it to analyse yet"}',
        ),
      );
    const onStarted = vi.fn();
    await render(source(), analyzeThread, onStarted);

    await press('Start analysis');

    expect(onStarted).not.toHaveBeenCalled();
    expect(document.querySelector('[role="alert"]')?.textContent).toContain(
      'the thread has nothing in it to analyse yet',
    );
    expect(button('Start analysis').disabled).toBe(false);
  });

  describe('on a team', () => {
    async function renderTeam(
      analyzeTeam: ReturnType<typeof vi.fn>,
      onStarted = vi.fn(),
      checkTeamAnalysisJudge: ReturnType<typeof vi.fn> = vi
        .fn()
        .mockResolvedValue({
          judgeVendor: null,
          members: 2,
          sameVendor: [],
          alternatives: [],
        }),
      countTeamAnalysisRuns: ReturnType<typeof vi.fn> = vi
        .fn()
        .mockResolvedValue({ inPeriod: 12, analysed: 12 }),
    ): Promise<void> {
      container = document.createElement('div');
      document.body.appendChild(container);
      root = createRoot(container);
      await act(async () => {
        root!.render(
          <AnalyzeThreadDialog
            subject={{
              kind: 'team',
              slug: 'dev-team',
              name: 'Dev Team',
              api: {
                analyzeTeam,
                checkTeamAnalysisJudge,
                countTeamAnalysisRuns,
              } as unknown as TeamsApi,
            }}
            sourceLabel="Dev Team"
            chatApi={{} as ChatsApi}
            agentsApi={null}
            cliDetections={null}
            composerSetup={COMPOSER}
            recentConfigDirsFor={() => []}
            configProfilesFor={() => []}
            configDirReasonFor={() => null}
            approvalCapabilityFor={() => CLAUDE_APPROVALS}
            agentLabelOf={(kind) => (kind === 'codex' ? 'Codex' : kind)}
            runSettings={() => Promise.resolve({})}
            onClose={() => undefined}
            onStarted={onStarted}
          />,
        );
      });
    }

    it('warns when most members run the judge’s own vendor, and switches to another agent on a press', async () => {
      const check = vi.fn().mockImplementation(async ({ agent }) => ({
        judgeVendor: agent === 'claude' ? 'anthropic' : 'openai',
        members: 2,
        sameVendor: agent === 'claude' ? ['lead', 'reviewer'] : [],
        alternatives: agent === 'claude' ? ['codex'] : ['claude'],
      }));
      await renderTeam(vi.fn(), vi.fn(), check);

      const hint = document.querySelector('[data-slot="analysis-judge-hint"]');
      expect(check).toHaveBeenCalledWith({
        slug: 'dev-team',
        agent: 'claude',
        model: 'opus',
      });
      expect(hint?.textContent).toContain(
        'Every member of this team runs models of the same vendor',
      );

      await act(async () => {
        button('Use Codex').click();
      });

      expect(check).toHaveBeenLastCalledWith({
        slug: 'dev-team',
        agent: 'codex',
      });
      expect(
        document.querySelector('[data-slot="analysis-judge-hint"]'),
      ).toBeNull();
    });

    function periodTrigger(): HTMLElement {
      return document.querySelector<HTMLElement>(
        '[aria-label="Period of the runs to analyse"]',
      )!;
    }

    function countLine(): HTMLElement {
      return document.querySelector<HTMLElement>(
        '[data-slot="analysis-period-count"]',
      )!;
    }

    async function pickPeriod(label: string): Promise<void> {
      act(() => {
        periodTrigger().click();
      });
      const option = [
        ...document.querySelectorAll<HTMLElement>('[role="option"]'),
      ].find((el) => el.textContent === label);
      await act(async () => {
        option!.click();
      });
    }

    it('offers the period of runs to analyse, opening on the last 7 days', async () => {
      const countTeamAnalysisRuns = vi
        .fn()
        .mockResolvedValue({ inPeriod: 12, analysed: 12 });
      await renderTeam(vi.fn(), vi.fn(), undefined, countTeamAnalysisRuns);

      expect(document.body.textContent).toContain('Analyze team');
      expect(document.body.textContent).toContain(
        'compares how its agents and their models did',
      );
      expect(
        document.querySelector('[aria-label="Latest runs to analyse"]'),
      ).toBeNull();
      expect(periodTrigger().textContent).toContain('Last 7 days');
      expect(countTeamAnalysisRuns).toHaveBeenCalledWith({
        slug: 'dev-team',
        days: 7,
      });
      expect(countLine().textContent).toBe('12 runs will be analysed');
    });

    it('says how many runs the period holds, and that the cap leaves some out', async () => {
      const counts: Record<number, { inPeriod: number; analysed: number }> = {
        1: { inPeriod: 1, analysed: 1 },
        7: { inPeriod: 12, analysed: 12 },
        30: { inPeriod: 45, analysed: 30 },
      };
      await renderTeam(
        vi.fn(),
        vi.fn(),
        undefined,
        vi.fn(async ({ days }: { days: number }) => counts[days]),
      );

      expect(countLine().textContent).toBe('12 runs will be analysed');
      await pickPeriod('Last day');
      expect(countLine().textContent).toBe('1 run will be analysed');
      await pickPeriod('Last 30 days');
      expect(countLine().textContent).toBe(
        '45 runs in this period — the newest 30 will be analysed',
      );
    });

    it('says there are no runs in the period, and does not start the analysis', async () => {
      const analyzeTeam = vi.fn();
      await renderTeam(
        analyzeTeam,
        vi.fn(),
        undefined,
        vi.fn(async ({ days }: { days: number }) =>
          days === 3
            ? { inPeriod: 0, analysed: 0 }
            : { inPeriod: 12, analysed: 12 },
        ),
      );

      await pickPeriod('Last 3 days');

      expect(countLine().textContent).toBe('No runs in this period');
      expect(button('Start analysis').disabled).toBe(true);
      expect(analyzeTeam).not.toHaveBeenCalled();
    });

    it('counts again on each period, and never lets an earlier period’s answer land', async () => {
      const answers = new Map<
        number,
        (answer: { inPeriod: number; analysed: number }) => void
      >();
      const countTeamAnalysisRuns = vi.fn(
        ({ days }: { days: number }) =>
          new Promise((resolve) => answers.set(days, resolve)),
      );
      await renderTeam(vi.fn(), vi.fn(), undefined, countTeamAnalysisRuns);
      expect(countLine().textContent).toBe('Counting…');

      await pickPeriod('Last 30 days');
      expect(countTeamAnalysisRuns).toHaveBeenLastCalledWith({
        slug: 'dev-team',
        days: 30,
      });
      await act(async () => {
        answers.get(30)!({ inPeriod: 45, analysed: 30 });
      });
      expect(countLine().textContent).toBe(
        '45 runs in this period — the newest 30 will be analysed',
      );

      await act(async () => {
        answers.get(7)!({ inPeriod: 12, analysed: 12 });
      });
      expect(countLine().textContent).toBe(
        '45 runs in this period — the newest 30 will be analysed',
      );
    });

    it('starts a team analysis over the period picked', async () => {
      const analyzeTeam = vi.fn().mockResolvedValue({ id: 'analysis' });
      const onStarted = vi.fn();
      await renderTeam(analyzeTeam, onStarted);

      await pickPeriod('Last 14 days');
      await press('Start analysis');

      expect(analyzeTeam).toHaveBeenCalledWith({
        slug: 'dev-team',
        analyzeTeamDto: {
          agentKind: 'claude',
          approval: 'auto',
          model: 'opus',
          days: 14,
        },
      });
      expect(onStarted).toHaveBeenCalledWith({ id: 'analysis' });
    });

    it('keeps the dialog open on a team never run', async () => {
      const analyzeTeam = vi
        .fn()
        .mockRejectedValue(
          new Error(
            'daemon POST /v1/teams/dev-team/analyses failed (409): {"code":"ANALYSIS_NO_RUNS","message":"the team has no runs to analyse yet — run it first"}',
          ),
        );
      const onStarted = vi.fn();
      await renderTeam(analyzeTeam, onStarted);

      await press('Start analysis');

      expect(onStarted).not.toHaveBeenCalled();
      expect(document.querySelector('[role="alert"]')?.textContent).toContain(
        'the team has no runs to analyse yet',
      );
    });
  });
});
