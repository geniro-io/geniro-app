import { FolderOpen, Sparkles, Workflow as TeamIcon } from 'lucide-react';
import { useEffect, useState } from 'react';

import type {
  AnalysisConfig,
  CliDetection,
  CliKind,
  ConfigProfile,
  RunSettings,
} from '../../shared/contracts';
import type {
  AgentApprovalCapability,
  ChatApprovalMode,
  RunDto,
} from '../autogenerated';
