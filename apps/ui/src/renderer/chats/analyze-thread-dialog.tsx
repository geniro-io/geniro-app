/**
 * The mode an analysis starts in until the user picks another. Twin of the
 * daemon's `ANALYSIS_DEFAULT_APPROVAL` (`v1/agents/chat.types.ts`), which
 * applies when the dialog sends none; this side always sends one.
 */
const ANALYSIS_DEFAULT_APPROVAL: ChatApprovalMode = 'auto';

/** How many of a team's newest runs an analysis reads unless changed. */
export const DEFAULT_ANALYSED_RUNS = 10;

/**
 * The most runs one team analysis reads. Twin of the daemon's
 * `MAX_ANALYSED_TEAM_RUNS` (`v1/agents/dto/chat.dto.ts`).
 */
export const MAX_ANALYSED_RUNS = 30;

/** A library team "Analyze & improve" is set up for. */
export interface AnalysedTeamSubject {
  slug: string;
  name: string;
}

/** What an analysis reads: one thread, or a team across its runs. */
export type AnalysisSubject =
  | { kind: 'thread'; run: RunDto }
  | ({
      kind: 'team';
      api: DaemonApis['teams'];
    } & AnalysedTeamSubject);

/**
 * "Analyze thread": who analyses the subject, and what to look at — for a
 * team ("Analyze & improve"), how many of its newest runs to read too.
 *
 * Starts a NEW chat linked to its subject (`POST /v1/chats/:runId/analyses`,
 * `POST /v1/teams/:slug/analyses`); the analysis itself happens there.
 * Opens on the last analysis choice
 * (`Settings.lastAnalysisConfig`), else the composer's own setup — except the
 * approval mode, which starts on auto-approve rather than the composer's: the
 * analysis works unwatched in its popup, where a card per read stalls it.
 *
 * Refusals keep the dialog open with the daemon's sentence. One of them is a
 * question rather than an error: `ANALYSIS_FOLDER_GONE` — the thread's (or
 * the newest run's) folder no longer exists — and the dialog then asks for
 * one, since repo recommendations are edits in that folder.
 */
export function AnalyzeThreadDialog({
  subject,
  replaces = false,
  sourceLabel,
  chatApi,
  agentsApi,
  cliDetections,
  composerSetup,
  recentConfigDirsFor,
  configProfilesFor,
  configDirReasonFor,
  approvalCapabilityFor,
  runSettings,
  onClose,
  onStarted,
}: {
  /** What to analyse; the dialog is open while it is non-null. */
  subject: AnalysisSubject | null;
  /** The subject already has an analysis, which starting this one replaces. */
  replaces?: boolean;
  sourceLabel: string;
  chatApi: DaemonApis['chats'];
  agentsApi: DaemonApis['agents'] | null;
  cliDetections: readonly CliDetection[] | null;
  /** The composer's setup — the first analysis's starting point. */
  composerSetup: AnalysisConfig;
  recentConfigDirsFor: (kind: CliKind) => readonly string[];
  configProfilesFor: (kind: CliKind) => readonly ConfigProfile[];
  configDirReasonFor: (kind: CliKind) => string | null | undefined;
  /** The CLI's approval modes, or `undefined` while capabilities load. */
  approvalCapabilityFor: (kind: CliKind) => AgentApprovalCapability | undefined;
  runSettings: () => Promise<RunSettings>;
  onClose: () => void;
  onStarted: (run: RunDto) => void;
}): React.JSX.Element {
  const open = subject !== null;
  const source = subject?.kind === 'thread' ? subject.run : null;
  const team = subject?.kind === 'team' ? subject : null;
  const [config, setConfig] = useState<AnalysisConfig>(composerSetup);
  const [focus, setFocus] = useState('');
  const [runs, setRuns] = useState(DEFAULT_ANALYSED_RUNS);
  const [folder, setFolder] = useState<string | null>(null);
  const [folderGone, setFolderGone] = useState(false);
  const [starting, setStarting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Reset on OPEN, the new-task dialog's rule: every exit (✕, Escape, the
  // backdrop) leaves state behind that must not greet the next thread.
  useEffect(() => {
    if (!open) {
      return;
    }
    setConfig(composerSetup);
    setFocus('');
    setRuns(DEFAULT_ANALYSED_RUNS);
    setFolder(null);
    setFolderGone(false);
    setError(null);
    let live = true;
    void window.geniro
      .getSettings()
      .then((settings) => {
        if (live && settings.lastAnalysisConfig) {
          setConfig(settings.lastAnalysisConfig);
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
    // Only on open and a change of subject: the composer moving under an open
    // dialog must not overwrite a choice the user is making.
  }, [open, source?.id, team?.slug]);

  const kind = config.agent;
  const profileless = configDirReasonFor(kind) !== null;
  const configDir = profileless ? null : config.configDir;
  const { models, loading: modelsLoading } = useAgentModels(
    agentsApi,
    open ? kind : null,
    configDir,
    config.model,
  );
  const efforts = useAgentEfforts(
    agentsApi,
    open ? kind : null,
    config.model,
    configDir,
  );
  const isTeam = team !== null || source?.teamId != null;
  const approval: ChatApprovalMode = isChatApprovalMode(config.approval)
    ? config.approval
    : ANALYSIS_DEFAULT_APPROVAL;
  const approvalCapability = approvalCapabilityFor(kind);
  // `plan` is withheld: an analysis that writes a plan and stops never reads.
  const approvalPickable =
    approvalOptions(approvalCapability, approval, PLAN_WITHHELD).length > 0;

  const set = (patch: Partial<AnalysisConfig>): void =>
    setConfig((current) => ({ ...current, ...patch }));

  const browse = (then: (chosen: string) => void): void => {
    void window.geniro
      .pickProjectFolder()
      .then((chosen) => {
        if (chosen) {
          then(chosen);
        }
      })
      .catch((err: unknown) => setError(describeDaemonError(err)));
  };

  const start = async (): Promise<void> => {
    if (subject === null || starting) {
      return;
    }
    setStarting(true);
    setError(null);
    try {
      const dto = {
        agentKind: kind,
        approval,
        ...(config.model === null ? {} : { model: config.model }),
        ...(config.effort === null ? {} : { effort: config.effort }),
        ...(configDir === null ? {} : { configDir }),
        ...(folder === null ? {} : { cwd: folder }),
        ...(focus.trim() === '' ? {} : { focus: focus.trim() }),
        ...(await runSettings()),
      };
      const run =
        subject.kind === 'team'
          ? await subject.api.analyzeTeam({
              slug: subject.slug,
              analyzeTeamDto: { ...dto, runs },
            })
          : await chatApi.analyzeThread({
              runId: subject.run.id,
              analyzeThreadDto: dto,
            });
      void window.geniro
        .updateSettings({
          lastAnalysisConfig: { ...config, configDir, approval },
        })
        .catch(() => undefined);
      onStarted(run);
    } catch (err) {
      if (daemonErrorCode(err) === 'ANALYSIS_FOLDER_GONE') {
        setFolderGone(true);
      }
      setError(describeDaemonError(err));
    } finally {
      setStarting(false);
    }
  };

  const facts = [
    source?.workedMs == null ? null : formatDuration(source.workedMs),
    source?.toolCalls == null ? null : `${source.toolCalls} tool calls`,
  ].filter((fact): fact is string => fact !== null);

  return (
    <Dialog
      open={open}
      // Escape and the backdrop cancel — except while the analysis is being
      // started, when closing would hide whether it started at all.
      onClose={() => {
        if (!starting) {
          onClose();
        }
      }}
      title={team === null ? 'Analyze thread' : 'Analyze team'}>
      <div data-slot="analyze-thread" className="flex flex-col gap-4">
        <div className="flex flex-col gap-1">
          <p className="flex items-center gap-2 text-sm font-medium">
            <span className="min-w-0 truncate">{sourceLabel}</span>
            <Badge variant="secondary" className="shrink-0">
              {isTeam ? <TeamIcon className="size-3" aria-hidden /> : null}
              {isTeam ? 'Team' : 'Chat'}
            </Badge>
          </p>
          {facts.length === 0 ? null : (
            <p className="text-xs text-muted-foreground">{facts.join(' · ')}</p>
          )}
          <p className="text-xs text-muted-foreground" data-slot="scope-note">
            {team !== null
              ? 'Reads the team’s latest runs, compares how its agents and their models did, and suggests team changes (models, roles, the graph’s structure, when to stop) and repository changes (AGENTS.md, rules, checks). You choose which to apply.'
              : isTeam
                ? 'Finds where the time went and suggests team changes (roles, models, parallel calls, when to stop) and repository changes (AGENTS.md, rules, checks). You choose which to apply.'
                : 'Finds where the time went and suggests repository changes (AGENTS.md, rules, checks). You choose which to apply.'}
          </p>
          {replaces ? (
            <p className="text-xs text-warning" data-slot="replaces-note">
              {`Starting replaces this ${team === null ? 'thread' : 'team'}'s current analysis — its conversation and card are deleted.`}
            </p>
          ) : null}
        </div>

        <div className="flex flex-col divide-y divide-border rounded-md border border-border">
          {team === null ? null : (
            <SettingRow label="Runs">
              <span className="flex items-center gap-2">
                <Stepper
                  value={runs}
                  min={1}
                  max={MAX_ANALYSED_RUNS}
                  aria-label="Latest runs to analyse"
                  onChange={setRuns}
                />
                <span className="text-xs text-muted-foreground">
                  latest runs
                </span>
              </span>
            </SettingRow>
          )}
          <SettingRow label="Agent">
            <TargetSelect
              value={kind}
              // Only CLIs: an analysis is one agent reading one thread.
              teams={[]}
              cliDetections={cliDetections}
              aria-label="Agent that runs the analysis"
              onChange={(target) =>
                set({
                  agent: targetAgentKind(target),
                  model: null,
                  effort: null,
                  configDir: null,
                  // Another CLI need not honour the mode picked for this one.
                  approval: null,
                })
              }
            />
          </SettingRow>
          {profileless ? null : (
            <SettingRow label="Profile">
              <ConfigDirSelect
                configDir={config.configDir}
                recentConfigDirs={[...recentConfigDirsFor(kind)]}
                configProfiles={configProfilesFor(kind)}
                unavailableReason={configDirReasonFor(kind)}
                ariaLabel="Profile the analysis runs as"
                onChange={(next) => set({ configDir: next, model: null })}
                onBrowse={() => browse((chosen) => set({ configDir: chosen }))}
              />
            </SettingRow>
          )}
          <SettingRow label="Model">
            <ModelSelect
              agentKind={kind}
              models={models}
              loading={modelsLoading}
              value={config.model}
              onChange={(model) => set({ model, effort: null })}
            />
          </SettingRow>
          {efforts.loading ? (
            <ModelSettingsPendingRow />
          ) : efforts.efforts.length === 0 ? null : (
            <SettingRow label="Effort">
              <EffortSelect
                efforts={efforts.efforts}
                value={config.effort}
                onChange={(effort) => set({ effort })}
              />
            </SettingRow>
          )}
          {approvalPickable ? (
            <SettingRow label="Approval">
              <ApprovalModeSelect
                capability={approvalCapability}
                value={approval}
                withheld={PLAN_WITHHELD}
                ariaLabel="Tool-approval mode of the analysis"
                onChange={(mode) => set({ approval: mode })}
              />
            </SettingRow>
          ) : null}
        </div>

        <p
          className="text-xs text-muted-foreground"
          data-slot="analysis-folder">
          Runs in{' '}
          {folder === null && team !== null ? (
            'the newest run’s folder'
          ) : (
            <span className="font-mono">
              {shortenPath(folder ?? source?.cwd ?? '')}
            </span>
          )}
          {folderGone ? null : ' — repository changes are made there.'}
        </p>
        {folderGone ? (
          <div className="flex items-center gap-2">
            <Button
              type="button"
              variant="outline"
              size="sm"
              disabled={starting}
              onClick={() =>
                browse((chosen) => {
                  setFolder(chosen);
                  setError(null);
                })
              }>
              <FolderOpen className="size-3.5" aria-hidden />
              Choose a folder…
            </Button>
            <span className="text-xs text-muted-foreground">
              {team === null
                ? 'The thread’s folder no longer exists.'
                : 'The newest run’s folder no longer exists.'}
            </span>
          </div>
        ) : null}

        <div className="flex flex-col gap-1.5">
          <Label htmlFor="analyze-thread-focus">
            Focus / extra instructions (optional)
          </Label>
          <ExpandableTextarea
            id="analyze-thread-focus"
            value={focus}
            title="Focus for this analysis"
            rows={3}
            maxRows={12}
            placeholder="e.g. why did the review loop run three times?"
            onChange={setFocus}
          />
        </div>

        {error === null ? null : (
          <ErrorBanner message={error} onDismiss={() => setError(null)} />
        )}

        <div className="flex justify-end gap-2">
          <Button variant="ghost" disabled={starting} onClick={onClose}>
            Cancel
          </Button>
          <Button
            disabled={!open || starting || (folderGone && folder === null)}
            onClick={() => void start()}>
            <Sparkles className="size-3.5" aria-hidden />
            {starting ? 'Starting…' : 'Start analysis'}
          </Button>
        </div>
      </div>
    </Dialog>
  );
}
