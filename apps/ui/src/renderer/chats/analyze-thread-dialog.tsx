import { FolderOpen, Sparkles, Workflow as WorkflowIcon } from 'lucide-react';
import { useEffect, useState } from 'react';

import type {
  AnalysisConfig,
  CliDetection,
  CliKind,
  ConfigProfile,
  RunSettings,
} from '../../shared/contracts';
import type { RunDto } from '../autogenerated';
import { ErrorBanner } from '../components/error-banner';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { SettingRow } from '../components/setting-row';
import { Badge } from '../components/ui/badge';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Label } from '../components/ui/label';
import {
  type DaemonApis,
  daemonErrorCode,
  describeDaemonError,
} from '../daemon-api';
import { targetAgentKind } from './composer-values';
import { ConfigDirSelect } from './config-dir-select';
import { shortenPath } from './directory-select';
import { EffortSelect } from './effort-select';
import { ModelSelect } from './model-select';
import { ModelSettingsPendingRow } from './model-settings-pending-row';
import { TargetSelect } from './target-select';
import { formatDuration } from './turn-duration';
import { useAgentEfforts } from './use-agent-efforts';
import { useAgentModels } from './use-agent-models';

/**
 * "Analyze thread": who analyses the thread, and what to look at.
 *
 * Starts a NEW chat linked to the clicked one (`POST /v1/chats/:runId/analyses`);
 * the analysis itself happens there. Opens on the last analysis choice
 * (`Settings.lastAnalysisConfig`), else the composer's own setup.
 *
 * Refusals keep the dialog open with the daemon's sentence. One of them is a
 * question rather than an error: `ANALYSIS_FOLDER_GONE` — the thread's folder
 * no longer exists — and the dialog then asks for one, since repo
 * recommendations are edits in that folder.
 */
export function AnalyzeThreadDialog({
  source,
  replaces = false,
  sourceLabel,
  chatApi,
  agentsApi,
  cliDetections,
  composerSetup,
  recentConfigDirsFor,
  configProfilesFor,
  configDirReasonFor,
  runSettings,
  onClose,
  onStarted,
}: {
  /** The thread to analyse; the dialog is open while it is non-null. */
  source: RunDto | null;
  /** The thread already has an analysis, which starting this one replaces. */
  replaces?: boolean;
  sourceLabel: string;
  chatApi: DaemonApis['chats'];
  agentsApi: DaemonApis['agents'] | null;
  cliDetections: readonly CliDetection[] | null;
  /** The composer's setup — the first analysis's starting point. */
  composerSetup: AnalysisConfig;
  recentConfigDirsFor: (kind: CliKind) => readonly string[];
  configProfilesFor: (kind: CliKind) => readonly ConfigProfile[];
  configDirReasonFor: (kind: CliKind) => string | null | undefined;
  runSettings: () => Promise<RunSettings>;
  onClose: () => void;
  onStarted: (run: RunDto) => void;
}): React.JSX.Element {
  const open = source !== null;
  const [config, setConfig] = useState<AnalysisConfig>(composerSetup);
  const [focus, setFocus] = useState('');
  const [folder, setFolder] = useState<string | null>(null);
  const [folderGone, setFolderGone] = useState(false);
  const [starting, setStarting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Reset on OPEN, the new-task dialog's rule: every exit (✕, Escape, the
  // backdrop) leaves state behind that must not greet the next thread.
  useEffect(() => {
    if (!open) {
      return;
    }
    setConfig(composerSetup);
    setFocus('');
    setFolder(null);
    setFolderGone(false);
    setError(null);
    let live = true;
    void window.geniro
      .getSettings()
      .then((settings) => {
        if (live && settings.lastAnalysisConfig) {
          setConfig(settings.lastAnalysisConfig);
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
    // Only on open and a change of thread: the composer moving under an open
    // dialog must not overwrite a choice the user is making.
  }, [open, source?.id]);

  const kind = config.agent;
  const profileless = configDirReasonFor(kind) !== null;
  const configDir = profileless ? null : config.configDir;
  const { models, loading: modelsLoading } = useAgentModels(
    agentsApi,
    open ? kind : null,
    configDir,
    config.model,
  );
  const efforts = useAgentEfforts(
    agentsApi,
    open ? kind : null,
    config.model,
    configDir,
  );
  const workflow = source?.workflowId != null;

  const set = (patch: Partial<AnalysisConfig>): void =>
    setConfig((current) => ({ ...current, ...patch }));

  const browse = (then: (chosen: string) => void): void => {
    void window.geniro
      .pickProjectFolder()
      .then((chosen) => {
        if (chosen) {
          then(chosen);
        }
      })
      .catch((err: unknown) => setError(describeDaemonError(err)));
  };

  const start = async (): Promise<void> => {
    if (source === null || starting) {
      return;
    }
    setStarting(true);
    setError(null);
    try {
      const run = await chatApi.analyzeThread({
        runId: source.id,
        analyzeThreadDto: {
          agentKind: kind,
          ...(config.model === null ? {} : { model: config.model }),
          ...(config.effort === null ? {} : { effort: config.effort }),
          ...(configDir === null ? {} : { configDir }),
          ...(folder === null ? {} : { cwd: folder }),
          ...(focus.trim() === '' ? {} : { focus: focus.trim() }),
          ...(await runSettings()),
        },
      });
      void window.geniro
        .updateSettings({
          lastAnalysisConfig: { ...config, configDir },
        })
        .catch(() => undefined);
      onStarted(run);
    } catch (err) {
      if (daemonErrorCode(err) === 'ANALYSIS_FOLDER_GONE') {
        setFolderGone(true);
      }
      setError(describeDaemonError(err));
    } finally {
      setStarting(false);
    }
  };

  const facts = [
    source?.workedMs == null ? null : formatDuration(source.workedMs),
    source?.toolCalls == null ? null : `${source.toolCalls} tool calls`,
  ].filter((fact): fact is string => fact !== null);

  return (
    <Dialog
      open={open}
      // Escape and the backdrop cancel — except while the analysis is being
      // started, when closing would hide whether it started at all.
      onClose={() => {
        if (!starting) {
          onClose();
        }
      }}
      title="Analyze thread">
      <div data-slot="analyze-thread" className="flex flex-col gap-4">
        <div className="flex flex-col gap-1">
          <p className="flex items-center gap-2 text-sm font-medium">
            <span className="min-w-0 truncate">{sourceLabel}</span>
            <Badge variant="secondary" className="shrink-0">
              {workflow ? (
                <WorkflowIcon className="size-3" aria-hidden />
              ) : null}
              {workflow ? 'Workflow' : 'Chat'}
            </Badge>
          </p>
          {facts.length === 0 ? null : (
            <p className="text-xs text-muted-foreground">{facts.join(' · ')}</p>
          )}
          <p className="text-xs text-muted-foreground" data-slot="scope-note">
            {workflow
              ? 'Finds where the time went and suggests workflow changes (roles, models, parallel calls, when to stop) and repository changes (AGENTS.md, rules, checks). You choose which to apply.'
              : 'Finds where the time went and suggests repository changes (AGENTS.md, rules, checks). You choose which to apply.'}
          </p>
          {replaces ? (
            <p className="text-xs text-warning" data-slot="replaces-note">
              Starting replaces this thread&apos;s current analysis — its
              conversation and card are deleted.
            </p>
          ) : null}
        </div>

        <div className="flex flex-col divide-y divide-border rounded-md border border-border">
          <SettingRow label="Agent">
            <TargetSelect
              value={kind}
              // Only CLIs: an analysis is one agent reading one thread.
              workflows={[]}
              cliDetections={cliDetections}
              aria-label="Agent that runs the analysis"
              onChange={(target) =>
                set({
                  agent: targetAgentKind(target),
                  model: null,
                  effort: null,
                  configDir: null,
                })
              }
            />
          </SettingRow>
          {profileless ? null : (
            <SettingRow label="Profile">
              <ConfigDirSelect
                configDir={config.configDir}
                recentConfigDirs={[...recentConfigDirsFor(kind)]}
                configProfiles={configProfilesFor(kind)}
                unavailableReason={configDirReasonFor(kind)}
                ariaLabel="Profile the analysis runs as"
                onChange={(next) => set({ configDir: next, model: null })}
                onBrowse={() => browse((chosen) => set({ configDir: chosen }))}
              />
            </SettingRow>
          )}
          <SettingRow label="Model">
            <ModelSelect
              agentKind={kind}
              models={models}
              loading={modelsLoading}
              value={config.model}
              onChange={(model) => set({ model, effort: null })}
            />
          </SettingRow>
          {efforts.loading ? (
            <ModelSettingsPendingRow />
          ) : efforts.efforts.length === 0 ? null : (
            <SettingRow label="Effort">
              <EffortSelect
                efforts={efforts.efforts}
                value={config.effort}
                onChange={(effort) => set({ effort })}
              />
            </SettingRow>
          )}
        </div>

        <p
          className="text-xs text-muted-foreground"
          data-slot="analysis-folder">
          Runs in{' '}
          <span className="font-mono">
            {shortenPath(folder ?? source?.cwd ?? '')}
          </span>
          {folderGone ? null : ' — repository changes are made there.'}
        </p>
        {folderGone ? (
          <div className="flex items-center gap-2">
            <Button
              type="button"
              variant="outline"
              size="sm"
              disabled={starting}
              onClick={() =>
                browse((chosen) => {
                  setFolder(chosen);
                  setError(null);
                })
              }>
              <FolderOpen className="size-3.5" aria-hidden />
              Choose a folder…
            </Button>
            <span className="text-xs text-muted-foreground">
              The thread’s folder no longer exists.
            </span>
          </div>
        ) : null}

        <div className="flex flex-col gap-1.5">
          <Label htmlFor="analyze-thread-focus">
            Focus / extra instructions (optional)
          </Label>
          <ExpandableTextarea
            id="analyze-thread-focus"
            value={focus}
            title="Focus for this analysis"
            rows={3}
            maxRows={12}
            placeholder="e.g. why did the review loop run three times?"
            onChange={setFocus}
          />
        </div>

        {error === null ? null : (
          <ErrorBanner message={error} onDismiss={() => setError(null)} />
        )}

        <div className="flex justify-end gap-2">
          <Button variant="ghost" disabled={starting} onClick={onClose}>
            Cancel
          </Button>
          <Button
            disabled={
              source === null || starting || (folderGone && folder === null)
            }
            onClick={() => void start()}>
            <Sparkles className="size-3.5" aria-hidden />
            {starting ? 'Starting…' : 'Start analysis'}
          </Button>
        </div>
      </div>
    </Dialog>
  );
}
