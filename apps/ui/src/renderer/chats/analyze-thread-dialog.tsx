/** What a model, profile or agent change clears: these belong to the model that offered them. */
const MODEL_BOUND_BLANK = {
  contextWindow: null,
  modelParameters: {},
} satisfies Partial<AnalysisConfig>;

/** A new CLI starts blank; it need not honour the mode picked for the last one. */
const AGENT_BLANK = {
  ...MODEL_BOUND_BLANK,
  model: null,
  effort: null,
  configDir: null,
  approval: null,
} satisfies Partial<AnalysisConfig>;

/**
 * The mode an analysis starts in until the user picks another. Twin of the
 * daemon's `ANALYSIS_DEFAULT_APPROVAL` (`v1/agents/chat.types.ts`), which
 * applies when the dialog sends none; this side always sends one.
 */
const ANALYSIS_DEFAULT_APPROVAL: ChatApprovalMode = 'auto';

/** The period a team analysis reads unless changed, in days. */
const DEFAULT_ANALYSED_DAYS = 7;

/** The periods a team analysis can read, in days, shortest first. */
const ANALYSED_PERIODS = [1, 3, 7, 14, 30, 90];

export function periodLabel(days: number): string {
  return days === 1 ? 'Last day' : `Last ${days} days`;
}

/** What a period's count means for the analysis: what it holds and what it reads. */
function countSentence(answer: AnalysisRunsCountDto): string {
  if (answer.analysed === 0) {
    return 'No runs in this period';
  }
  if (answer.inPeriod > answer.analysed) {
    const newest =
      answer.analysed === 1
        ? 'the newest run'
        : `the newest ${answer.analysed}`;
    return `${answer.inPeriod} runs in this period — ${newest} will be analysed`;
  }
  return `${answer.analysed} ${answer.analysed === 1 ? 'run' : 'runs'} will be analysed`;
}

/** A library team "Analyze & improve" is set up for. */
export interface AnalysedTeamSubject {
  slug: string;
  name: string;
}

/** What an analysis reads: one thread, or a team across its runs. */
export type AnalysisSubject =
  | { kind: 'thread'; run: RunDto }
  | ({
      kind: 'team';
      api: DaemonApis['teams'];
    } & AnalysedTeamSubject);

/**
 * "Analyze thread": who analyses the subject, and what to look at — for a
 * team ("Analyze & improve"), how many past days of its runs to read too.
 *
 * Starts a NEW chat linked to its subject (`POST /v1/chats/:runId/analyses`,
 * `POST /v1/teams/:slug/analyses`); the analysis itself happens there.
 * Opens on the setup last used in an analysis or a team's or project's chat
 * (`Settings.lastAnalysisConfig`), else the composer's own setup — except the
 * approval mode, which starts on auto-approve rather than the composer's: the
 * analysis works unwatched in its popup, where a card per read stalls it.
 *
 * Refusals keep the dialog open with the daemon's sentence. One of them is a
 * question rather than an error: `ANALYSIS_FOLDER_GONE` — the thread's (or
 * the newest run's) folder no longer exists — and the dialog then asks for
 * one, since repo recommendations are edits in that folder.
 */
export function AnalyzeThreadDialog({
  subject,
  replaces = false,
  sourceLabel,
  chatApi,
  agentsApi,
  cliDetections,
  composerSetup,
  recentConfigDirsFor,
  configProfilesFor,
  configDirReasonFor,
  approvalCapabilityFor,
  agentLabelOf,
  runSettings,
  onClose,
  onStarted,
}: {
  /** What to analyse; the dialog is open while it is non-null. */
  subject: AnalysisSubject | null;
  /** The subject already has an analysis, which starting this one replaces. */
  replaces?: boolean;
  sourceLabel: string;
  chatApi: DaemonApis['chats'];
  agentsApi: DaemonApis['agents'] | null;
  cliDetections: readonly CliDetection[] | null;
  /** The composer's setup — the first analysis's starting point. */
  composerSetup: AnalysisConfig;
  recentConfigDirsFor: (kind: CliKind) => readonly string[];
  configProfilesFor: (kind: CliKind) => readonly ConfigProfile[];
  configDirReasonFor: (kind: CliKind) => string | null | undefined;
  /** The CLI's approval modes, or `undefined` while capabilities load. */
  approvalCapabilityFor: (kind: CliKind) => AgentApprovalCapability | undefined;
  /** The name a CLI is shown by — the judge hint names the agents it suggests. */
  agentLabelOf?: (kind: string) => string;
  runSettings: () => Promise<RunSettings>;
  onClose: () => void;
  onStarted: (run: RunDto) => void;
}): React.JSX.Element {
  const open = subject !== null;
  const source = subject?.kind === 'thread' ? subject.run : null;
  const team = subject?.kind === 'team' ? subject : null;
  const [config, setConfig] = useState<AnalysisConfig>(composerSetup);
  const [focus, setFocus] = useState('');
  const [days, setDays] = useState(DEFAULT_ANALYSED_DAYS);
  const [count, setCount] = useState<{
    days: number;
    answer: AnalysisRunsCountDto | null;
  } | null>(null);
  const [folder, setFolder] = useState<string | null>(null);
  const [folderGone, setFolderGone] = useState(false);
  const [starting, setStarting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [judge, setJudge] = useState<AnalysisJudgeCheckDto | null>(null);
  const attachments = useAttachments();
  const [refusedFiles, setRefusedFiles] = useState<string | null>(null);

  // Reset on OPEN, the new-task dialog's rule: every exit (✕, Escape, the
  // backdrop) leaves state behind that must not greet the next thread.
  useEffect(() => {
    if (!open) {
      return;
    }
    setConfig(composerSetup);
    setFocus('');
    setDays(DEFAULT_ANALYSED_DAYS);
    setFolder(null);
    setFolderGone(false);
    setError(null);
    attachments.clear();
    setRefusedFiles(null);
    let live = true;
    void window.geniro
      .getSettings()
      .then((settings) => {
        if (live && settings.lastAnalysisConfig) {
          setConfig(settings.lastAnalysisConfig);
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
    // Only on open and a change of subject: the composer moving under an open
    // dialog must not overwrite a choice the user is making.
  }, [open, source?.id, team?.slug]);

  const kind = config.agent;
  const profileless = configDirReasonFor(kind) !== null;
  const configDir = profileless ? null : config.configDir;
  const { models, loading: modelsLoading } = useAgentModels(
    agentsApi,
    open ? kind : null,
    configDir,
    config.model,
  );
  const efforts = useAgentEfforts(
    agentsApi,
    open ? kind : null,
    config.model,
    configDir,
  );
  const windows = useAgentContextWindows(
    agentsApi,
    open ? kind : null,
    config.model,
    configDir,
  );
  const parameters = useAgentModelParameters(
    agentsApi,
    open ? kind : null,
    config.model,
    configDir,
  );
  const isTeam = team !== null || source?.teamId != null;
  const approval: ChatApprovalMode = isChatApprovalMode(config.approval)
    ? config.approval
    : ANALYSIS_DEFAULT_APPROVAL;
  const approvalCapability = approvalCapabilityFor(kind);
  // `plan` is withheld: an analysis that writes a plan and stops never reads.
  const approvalPickable =
    approvalOptions(approvalCapability, approval, PLAN_WITHHELD).length > 0;

  const set = (patch: Partial<AnalysisConfig>): void =>
    setConfig((current) => ({ ...current, ...patch }));

  const teamSlug = team?.slug ?? null;
  const teamApi = team?.api ?? null;
  useEffect(() => {
    setJudge(null);
    if (teamSlug === null || teamApi === null) {
      return;
    }
    let live = true;
    teamApi
      .checkTeamAnalysisJudge({
        slug: teamSlug,
        agent: kind,
        ...(config.model === null ? {} : { model: config.model }),
      })
      .then((answer) => {
        if (live) {
          setJudge(answer);
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, [teamSlug, teamApi, kind, config.model]);
  const sameVendorJudge =
    judge !== null &&
    judge.judgeVendor !== null &&
    judge.sameVendor.length * 2 > judge.members;

  useEffect(() => {
    setCount(null);
    if (teamSlug === null || teamApi === null) {
      return;
    }
    let live = true;
    teamApi
      .countTeamAnalysisRuns({ slug: teamSlug, days })
      .then((answer) => {
        if (live) {
          setCount({ days, answer });
        }
      })
      .catch(() => {
        if (live) {
          setCount({ days, answer: null });
        }
      });
    return () => {
      live = false;
    };
  }, [open, teamSlug, teamApi, days]);
  const counted = count?.days === days ? count : null;
  const countText =
    counted === null
      ? 'Counting…'
      : counted.answer === null
        ? 'Could not count the runs'
        : countSentence(counted.answer);
  const noRunsInPeriod = counted?.answer?.analysed === 0;

  const browse = (then: (chosen: string) => void): void => {
    void window.geniro
      .pickProjectFolder()
      .then((chosen) => {
        if (chosen) {
          then(chosen);
        }
      })
      .catch((err: unknown) => setError(describeDaemonError(err)));
  };

  const start = async (): Promise<void> => {
    if (subject === null || starting) {
      return;
    }
    setStarting(true);
    setError(null);
    try {
      const dto = {
        agentKind: kind,
        approval,
        ...setupFieldsOf({ ...config, configDir }),
        ...(folder === null ? {} : { cwd: folder }),
        ...(focus.trim() === '' ? {} : { focus: focus.trim() }),
        ...(attachments.attachments.length === 0
          ? {}
          : { images: attachments.toWire() }),
        ...(await runSettings()),
      };
      const run =
        subject.kind === 'team'
          ? await subject.api.analyzeTeam({
              slug: subject.slug,
              analyzeTeamDto: { ...dto, days },
            })
          : await chatApi.analyzeThread({
              runId: subject.run.id,
              analyzeThreadDto: dto,
            });
      void window.geniro
        .updateSettings({
          lastAnalysisConfig: { ...config, configDir, approval },
        })
        .catch(() => undefined);
      onStarted(run);
    } catch (err) {
      if (daemonErrorCode(err) === 'ANALYSIS_FOLDER_GONE') {
        setFolderGone(true);
      }
      setError(describeDaemonError(err));
    } finally {
      setStarting(false);
    }
  };

  const facts = [
    source?.workedMs == null ? null : formatDuration(source.workedMs),
    source?.toolCalls == null ? null : `${source.toolCalls} tool calls`,
  ].filter((fact): fact is string => fact !== null);

  return (
    <Dialog
      open={open}
      // Escape and the backdrop cancel — except while the analysis is being
      // started, when closing would hide whether it started at all.
      onClose={() => {
        if (!starting) {
          onClose();
        }
      }}
      title={team === null ? 'Analyze thread' : 'Analyze team'}
      className="max-w-2xl">
      <div data-slot="analyze-thread" className="flex flex-col gap-4">
        <div className="flex flex-col gap-1">
          <p className="flex items-center gap-2 text-sm font-medium">
            <span className="min-w-0 truncate">{sourceLabel}</span>
            <Badge variant="secondary" className="shrink-0">
              {isTeam ? <TeamIcon className="size-3" aria-hidden /> : null}
              {isTeam ? 'Team' : 'Chat'}
            </Badge>
          </p>
          {facts.length === 0 ? null : (
            <p className="text-xs text-muted-foreground">{facts.join(' · ')}</p>
          )}
          <p className="text-xs text-muted-foreground" data-slot="scope-note">
            {team !== null
              ? 'Reads the team’s runs from the period picked, archived ones included, compares how its agents and their models did, and suggests team changes (models, roles, the graph’s structure, when to stop) and repository changes (AGENTS.md, rules, checks). You choose which to apply.'
              : isTeam
                ? 'Finds where the time went and suggests team changes (roles, models, parallel calls, when to stop) and repository changes (AGENTS.md, rules, checks). You choose which to apply.'
                : 'Finds where the time went and suggests repository changes (AGENTS.md, rules, checks). You choose which to apply.'}
          </p>
          {replaces ? (
            <p className="text-xs text-warning" data-slot="replaces-note">
              {`Starting replaces this ${team === null ? 'thread' : 'team'}'s current analysis — its conversation and card are deleted.`}
            </p>
          ) : null}
        </div>

        <div className="flex flex-col divide-y divide-border rounded-md border border-border">
          {team === null ? null : (
            <SettingRow label="Period">
              <span className="flex flex-wrap items-center">
                <Select
                  variant="ghost"
                  aria-label="Period of the runs to analyse"
                  leadingIcon={<CalendarDays />}
                  value={String(days)}
                  groups={[
                    {
                      items: ANALYSED_PERIODS.map((period) => ({
                        value: String(period),
                        label: periodLabel(period),
                      })),
                    },
                  ]}
                  onValueChange={(next) => setDays(Number(next))}
                />
                <span
                  className="px-2 text-xs text-muted-foreground"
                  data-slot="analysis-period-count">
                  {countText}
                </span>
              </span>
            </SettingRow>
          )}
          <SettingRow label="Agent">
            <TargetSelect
              value={kind}
              // Only CLIs: an analysis is one agent reading one thread.
              teams={[]}
              cliDetections={cliDetections}
              aria-label="Agent that runs the analysis"
              onChange={(target) =>
                set({ ...AGENT_BLANK, agent: targetAgentKind(target) })
              }
            />
          </SettingRow>
          {profileless ? null : (
            <SettingRow label="Profile">
              <ConfigDirSelect
                configDir={config.configDir}
                recentConfigDirs={[...recentConfigDirsFor(kind)]}
                configProfiles={configProfilesFor(kind)}
                unavailableReason={configDirReasonFor(kind)}
                ariaLabel="Profile the analysis runs as"
                onChange={(next) =>
                  set({ ...MODEL_BOUND_BLANK, configDir: next, model: null })
                }
                onBrowse={() => browse((chosen) => set({ configDir: chosen }))}
              />
            </SettingRow>
          )}
          <SettingRow label="Model">
            <ModelSelect
              agentKind={kind}
              models={models}
              loading={modelsLoading}
              value={config.model}
              onChange={(model) =>
                set({ ...MODEL_BOUND_BLANK, model, effort: null })
              }
            />
          </SettingRow>
          {!sameVendorJudge ? null : (
            <div
              data-slot="analysis-judge-hint"
              role="status"
              className="flex flex-col gap-2 px-3 py-2.5">
              <p className="m-0 text-xs text-warning">
                {judge.sameVendor.length === judge.members
                  ? 'Every member of this team runs'
                  : `${judge.sameVendor.length} of its ${judge.members} members run`}{' '}
                models of the same vendor as this analysis. A judge tends to
                mark its own vendor’s work high — for the members’ marks, pick
                another agent.
              </p>
              {judge.alternatives.length === 0 ? null : (
                <span className="flex flex-wrap gap-1.5">
                  {judge.alternatives.map((alternative) => (
                    <Button
                      key={alternative}
                      type="button"
                      size="sm"
                      variant="outline"
                      disabled={starting}
                      onClick={() =>
                        set({ ...AGENT_BLANK, agent: alternative })
                      }>
                      Use {agentLabelOf?.(alternative) ?? alternative}
                    </Button>
                  ))}
                </span>
              )}
            </div>
          )}
          {efforts.loading || windows.loading || parameters.loading ? (
            <ModelSettingsPendingRow />
          ) : (
            <>
              {efforts.efforts.length === 0 ? null : (
                <SettingRow label="Effort">
                  <EffortSelect
                    efforts={efforts.efforts}
                    value={config.effort}
                    onChange={(effort) => set({ effort })}
                  />
                </SettingRow>
              )}
              {windows.windows.length === 0 ? null : (
                <SettingRow label="Context window">
                  <ContextWindowSelect
                    windows={windows.windows}
                    value={config.contextWindow}
                    onChange={(contextWindow) => set({ contextWindow })}
                  />
                </SettingRow>
              )}
              {parameters.parameters.map((parameter) =>
                parameter.values.length === 0 ? null : (
                  <SettingRow key={parameter.id} label={parameter.label}>
                    <ModelParameterSelect
                      parameter={parameter}
                      value={config.modelParameters[parameter.id] ?? null}
                      showAxisName={false}
                      onChange={(value) =>
                        set({
                          modelParameters: withModelParameter(
                            config.modelParameters,
                            parameter.id,
                            value,
                          ),
                        })
                      }
                    />
                  </SettingRow>
                ),
              )}
            </>
          )}
          <SettingRow label="Auto-compact">
            <AutoCompactSelect
              value={config.autoCompactPercent}
              ariaLabel="Auto-compact of the analysis"
              onChange={(autoCompactPercent) => set({ autoCompactPercent })}
            />
          </SettingRow>
          {approvalPickable ? (
            <SettingRow label="Approval">
              <ApprovalModeSelect
                capability={approvalCapability}
                value={approval}
                withheld={PLAN_WITHHELD}
                ariaLabel="Tool-approval mode of the analysis"
                onChange={(mode) => set({ approval: mode })}
              />
            </SettingRow>
          ) : null}
        </div>

        <p
          className="text-xs text-muted-foreground"
          data-slot="analysis-folder">
          Runs in{' '}
          {folder === null && team !== null ? (
            'the newest run’s folder'
          ) : (
            <span className="font-mono">
              {shortenPath(folder ?? source?.cwd ?? '')}
            </span>
          )}
          {folderGone ? null : ' — repository changes are made there.'}
        </p>
        {folderGone ? (
          <div className="flex items-center gap-2">
            <Button
              type="button"
              variant="outline"
              size="sm"
              disabled={starting}
              onClick={() =>
                browse((chosen) => {
                  setFolder(chosen);
                  setError(null);
                })
              }>
              <FolderOpen className="size-3.5" aria-hidden />
              Choose a folder…
            </Button>
            <span className="text-xs text-muted-foreground">
              {team === null
                ? 'The thread’s folder no longer exists.'
                : 'The newest run’s folder no longer exists.'}
            </span>
          </div>
        ) : null}

        <div className="flex flex-col gap-1.5">
          <Label htmlFor="analyze-thread-focus">
            Focus / extra instructions (optional)
          </Label>
          <AttachmentStrip
            attachments={attachments.attachments}
            onRemove={attachments.remove}
            className="px-0 pt-0"
          />
          <div className="flex items-start gap-1.5">
            <div className="min-w-0 flex-1">
              <ExpandableTextarea
                id="analyze-thread-focus"
                value={focus}
                title="Focus for this analysis"
                rows={3}
                maxRows={12}
                placeholder="e.g. why did the review loop run three times? Paste a screenshot to attach it."
                onChange={setFocus}
                onPaste={(event) => {
                  if (attachments.addFromClipboard(event.clipboardData)) {
                    setRefusedFiles(null);
                    event.preventDefault();
                  }
                }}
              />
            </div>
            <AttachFilesButton
              accept={ACCEPTED_IMAGE_TYPES}
              label="Attach images"
              disabled={starting}
              onFiles={(files) => {
                const refused = attachments.addFiles(files);
                setRefusedFiles(
                  refused.length === 0
                    ? null
                    : `${refused.map((file) => file.name).join(', ')} — only PNG, JPEG, GIF or WebP images up to ${Math.floor(MAX_ATTACHMENT_BYTES / 1024 / 1024)}MB can be attached`,
                );
              }}
            />
          </div>
          {(refusedFiles ?? attachments.error) === null ? null : (
            <ErrorText className="text-xs">
              {refusedFiles ?? attachments.error}
            </ErrorText>
          )}
        </div>

        {error === null ? null : (
          <ErrorBanner message={error} onDismiss={() => setError(null)} />
        )}

        <div className="flex justify-end gap-2">
          <Button variant="ghost" disabled={starting} onClick={onClose}>
            Cancel
          </Button>
          <Button
            disabled={
              !open ||
              starting ||
              attachments.reading ||
              (folderGone && folder === null) ||
              noRunsInPeriod
            }
            onClick={() => void start()}>
            <Sparkles className="size-3.5" aria-hidden />
            {starting ? 'Starting…' : 'Start analysis'}
          </Button>
        </div>
      </div>
    </Dialog>
  );
}
