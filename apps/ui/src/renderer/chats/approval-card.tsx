/** One parsed AskUserQuestion entry (defensive — bad shapes are dropped). */
interface ParsedQuestion {
  question: string;
  /** The CLI's short tab title for this question; null when it sent none. */
  header: string | null;
  options: string[];
  multiSelect: boolean;
}

/** TWIN LIMIT: apps/daemon/src/v1/agents/chat.types.ts MAX_ANSWER_LENGTH. */
const MAX_ANSWER_LENGTH = 32_768;

/**
 * TWIN LIMIT: apps/daemon/src/v1/agents/chat.types.ts
 * MAX_QUESTION_HEADER_LENGTH. A header is rendered as a tab title, and the tab
 * strip has no truncation of its own.
 */
const MAX_QUESTION_HEADER_LENGTH = 64;

/** How long "Sending…" holds before the one-shot freeze re-arms for a retry. */
const RESPONDED_RETRY_MS = 10_000;

/**
 * The sentence under a question saying how many of its options may be picked.
 *
 * Worded from the arity rather than from `multiSelect`, so the `none` case gets
 * a line of its own: there, a click IS the submission, and the card's one-shot
 * verdict means a mis-click cannot be taken back — which is worth a warning
 * before the press, not a discovery after it.
 */
function arityHint(arity: OptionArity): string {
  return arity === 'many'
    ? 'Pick as many as apply.'
    : arity === 'one'
      ? 'Pick one.'
      : 'Picking an option answers straight away.';
}

/** The tab title for one question — its header, or its position as a fallback. */
function tabLabel(question: ParsedQuestion, index: number): string {
  return question.header ?? `Question ${index + 1}`;
}

/**
 * How much of a question's own text may prefix its answer in the submission.
 * The question is AGENT-written and unbounded, while the submission it rides in
 * is capped at MAX_ANSWER_LENGTH — so without this an over-long question would
 * spend the budget the user's answer needs and kill Submit before a character
 * was typed. It only shortens the LABEL; the question renders in full above.
 */
const MAX_ANSWER_LABEL_LENGTH = 80;

function answerLabel(question: ParsedQuestion): string {
  return question.question.length <= MAX_ANSWER_LABEL_LENGTH
    ? question.question
    : `${question.question.slice(0, MAX_ANSWER_LABEL_LENGTH - 1)}…`;
}

/**
 * Join one tab's answer parts. The ONE rule for it, shared by the staged path
 * and the answer-on-click path — which disagreed until an adversarial test
 * caught the click path silently dropping a typed qualifier.
 */
function joinParts(parts: string[]): string {
  return parts.filter((part) => part.length > 0).join(', ');
}

/**
 * The multi-question submission: one labelled line per question, so the single
 * `response` wire channel stays unambiguous about which answer belongs where.
 */
function combinedAnswer(
  questions: ParsedQuestion[],
  answerAt: (index: number) => string,
): string {
  return questions
    .map((question, index) => `${answerLabel(question)}: ${answerAt(index)}`)
    .join('\n');
}

/**
 * Parse a `cursor/ask_question` params object (`{ questions: [{ id, prompt,
 * options: [{ id, label }], allowMultiple }] }`) into the same renderable
 * entries. Empty for anything else, including claude's shape — the two share
 * only the word `questions`.
 *
 * TWIN PARSER: the daemon parses the same wire shape in
 * apps/daemon/src/v1/agents/adapters/cursor-acp/utils/cursor-question.utils.ts
 * — a shape drift fixed there must be mirrored here, and vice versa. Mirrored
 * rules: an option is kept only when its `id` is non-empty, and its LABEL
 * falls back to that id (the daemon answers with the id, so a row whose label
 * this side dropped would be unpickable while the daemon still had a value
 * for it); a question with no options is dropped whole, because the vendor's
 * only answer channel is `selectedOptionIds`.
 *
 * `header` is null: the request has no per-question title. Its request-level
 * `title` is deliberately not used as one — it names the whole ask, and
 * repeating it on every tab would label them identically.
 */
function readCursorQuestions(input: unknown): ParsedQuestion[] {
  if (!input || typeof input !== 'object' || Array.isArray(input)) {
    return [];
  }
  const questions = (input as { questions?: unknown }).questions;
  if (!Array.isArray(questions)) {
    return [];
  }
  const parsed: ParsedQuestion[] = [];
  for (const entry of questions) {
    if (!entry || typeof entry !== 'object') {
      continue;
    }
    const q = entry as {
      id?: unknown;
      prompt?: unknown;
      options?: unknown;
      allowMultiple?: unknown;
    };
    if (
      typeof q.id !== 'string' ||
      q.id.length === 0 ||
      typeof q.prompt !== 'string' ||
      q.prompt.length === 0
    ) {
      continue;
    }
    const options = (Array.isArray(q.options) ? q.options : [])
      .map((o) => {
        if (!o || typeof o !== 'object') {
          return null;
        }
        const option = o as { id?: unknown; label?: unknown };
        if (typeof option.id !== 'string' || option.id.length === 0) {
          return null;
        }
        return typeof option.label === 'string' && option.label.length > 0
          ? option.label
          : option.id;
      })
      .filter(
        (label): label is string =>
          label !== null && label.length <= MAX_ANSWER_LENGTH,
      );
    if (options.length === 0) {
      continue;
    }
    parsed.push({
      question: q.prompt,
      header: null,
      options,
      multiSelect: q.allowMultiple === true,
    });
  }
  return parsed;
}

/**
 * Parse an AskUserQuestion tool input (`{ questions: [{ question, options:
 * [{ label }] }] }`) into renderable entries. Empty for any other tool's
 * input — the card then falls back to the plain approve/deny body.
 *
 * TWIN PARSER: the daemon parses the same wire shape in
 * apps/daemon/src/v1/agents/adapters/claude/utils/claude-question.utils.ts (no
 * daemon↔renderer shared package exists) — a shape drift fixed there must be
 * mirrored here, and vice versa. Mirrored rules: option labels are kept only
 * when non-empty and ≤ MAX_ANSWER_LENGTH; `header` only when non-empty and
 * ≤ MAX_QUESTION_HEADER_LENGTH; `multiSelect` only when the payload says so
 * literally (a truthy string would let one side offer multi-pick while the
 * other offers one).
 */
function readQuestions(input: unknown): ParsedQuestion[] {
  if (!input || typeof input !== 'object' || Array.isArray(input)) {
    return [];
  }
  const questions = (input as { questions?: unknown }).questions;
  if (!Array.isArray(questions)) {
    return [];
  }
  const parsed: ParsedQuestion[] = [];
  for (const entry of questions) {
    if (!entry || typeof entry !== 'object') {
      continue;
    }
    const q = entry as {
      question?: unknown;
      header?: unknown;
      options?: unknown;
      multiSelect?: unknown;
    };
    if (typeof q.question !== 'string' || q.question.length === 0) {
      continue;
    }
    const options = Array.isArray(q.options)
      ? q.options
          .map((o) =>
            o && typeof o === 'object'
              ? (o as { label?: unknown }).label
              : null,
          )
          .filter(
            (label): label is string =>
              typeof label === 'string' &&
              label.length > 0 &&
              label.length <= MAX_ANSWER_LENGTH,
          )
      : [];
    parsed.push({
      question: q.question,
      header:
        typeof q.header === 'string' &&
        q.header.length > 0 &&
        q.header.length <= MAX_QUESTION_HEADER_LENGTH
          ? q.header
          : null,
      options,
      multiSelect: q.multiSelect === true,
    });
  }
  return parsed;
}

/**
 * The one-shot verdict channel both card bodies share.
 *
 * Freeze the card the moment an answer is sent, until the persisted verdict
 * item (or expiry) round-trips — a double-click, or Approve-then-Deny, would
 * emit a conflicting verdict the daemon silently drops. The freeze must not be
 * forever though: if the verdict item never arrives (its write failed, or the
 * ack was 'invalid') the controls re-arm, because the daemon settles a request
 * exactly once and a retry is therefore safe.
 *
 * Shared rather than written twice: the question card and the permission card
 * are separate components with the same contract, and a fix to this timing on
 * one of them has to reach both.
 */
function useOneShotVerdict(
  verdict: boolean | null,
  expired: boolean,
  onRespond: (
    allow: boolean,
    answer?: string,
    images?: SendMessageDtoImagesInner[],
  ) => void,
): {
  responded: boolean;
  sending: boolean;
  respond: (
    allow: boolean,
    answer?: string,
    images?: SendMessageDtoImagesInner[],
  ) => void;
} {
  const [responded, setResponded] = useState(false);
  useEffect(() => {
    if (!responded || verdict !== null || expired) {
      return;
    }
    const timer = setTimeout(() => setResponded(false), RESPONDED_RETRY_MS);
    return () => clearTimeout(timer);
  }, [responded, verdict, expired]);
  const respond = (
    allow: boolean,
    answer?: string,
    images?: SendMessageDtoImagesInner[],
  ): void => {
    if (responded) {
      return;
    }
    setResponded(true);
    // Preserve the caller-visible arity: a plain approve/deny stays a
    // one-argument call, and an answer with no attachment a two-argument one.
    if (answer === undefined) {
      onRespond(allow);
    } else if (images === undefined || images.length === 0) {
      onRespond(allow, answer);
    } else {
      onRespond(allow, answer, images);
    }
  };
  return {
    responded,
    sending: responded && verdict === null && !expired,
    respond,
  };
}

/**
 * An AskUserQuestion request: one TAB per question, each returnable and
 * re-answerable, with the picked answer riding the verdict (`answer`) to reach
 * the agent as "The user responded: …" (the M4 escalation leg).
 *
 * Rendered only for a payload that actually parsed into questions — the router
 * below falls back to the plain permission body otherwise.
 */
function QuestionCard({
  questions,
  verdict,
  answer,
  expired,
  onRespond,
}: {
  /** Already parsed and non-empty. */
  questions: ParsedQuestion[];
  verdict: boolean | null;
  /** What the user answered, once the transcript recorded it. */
  answer: string | null;
  expired: boolean;
  /**
   * `images` are NOT part of the answer string — they cannot be. The answer
   * reaches the model as a plain string inside the CLI's own tool input
   * (`updatedInput.answers` for a lone question, `updatedInput.response` for
   * several), so there is nowhere in it for bytes to go. The
   * caller delivers them as their own user message into the same running turn
   * (the channel the composer already uses), and the answer text says one is
   * coming so the model knows to expect it.
   */
  onRespond: (
    allow: boolean,
    answer?: string,
    images?: SendMessageDtoImagesInner[],
  ) => void;
}): React.JSX.Element {
  // Per question, kept independently so every tab stays returnable: switching
  // away and back must show the same picks and the same typed text, and both
  // must remain changeable until the one submission is sent.
  const [activeTab, setActiveTab] = useState(0);
  const [picked, setPicked] = useState<Record<number, string[]>>({});
  const [texts, setTexts] = useState<Record<number, string>>({});
  const cardId = useId();
  const tabRefs = useRef<(HTMLButtonElement | null)[]>([]);
  // Screenshots pasted into the answer. Staged here and delivered by the
  // caller as a separate message — see `onRespond`'s note for why they cannot
  // ride the answer string itself.
  const attachments = useAttachments();
  /**
   * The images pasted into ONE tab.
   *
   * Per tab, and that is the fix: one hook stages every screenshot on the card,
   * so before the owner tag every tab drew every thumbnail and the answer could
   * only say that a picture was coming — never which question it answered. A
   * user pasting a screenshot under the second question saw it appear under the
   * first and the third as well ("it should be attached to tab where i inserted
   * it, not to all").
   *
   * The BYTES are still one delivery: they leave as a single follow-up message,
   * because that is what the send path does. What is per-tab is which
   * thumbnails a tab shows and which answer line announces them.
   */
  const imagesAt = (index: number): StagedAttachment[] =>
    attachments.attachments.filter(
      (image) => (image.owner ?? 0) === (questions.length > 1 ? index : 0),
    );
  /**
   * The line appended to a tab's answer when screenshots ride along with it.
   *
   * A factual description of the DELIVERY, not words put in the user's mouth:
   * the bytes go out as their own message, and without this the model reads the
   * answer, acts on it, and only meets the screenshot afterwards with no idea
   * it was meant as part of the reply.
   *
   * Shared by BOTH submit paths, so neither can describe the delivery
   * differently from the other.
   */
  const imageNoteFor = (count: number): string =>
    count === 0
      ? ''
      : `\n(${count === 1 ? '1 image' : `${count} images`} attached — sent as the next message)`;
  const { responded, sending, respond } = useOneShotVerdict(
    verdict,
    expired,
    onRespond,
  );
  const pending = verdict === null && !expired;
  // One tab per question, and only while the card can still be answered —
  // a settled card is a transcript row, so it lists every question instead.
  const showTabs = pending && questions.length > 1;
  const activeIndex = Math.min(activeTab, questions.length - 1);
  const active = questions[activeIndex]!;
  // A click can only BE the whole answer when there is exactly one question
  // and it takes exactly one pick; otherwise picks stage until Submit —
  // which is also what makes each of them re-answerable.
  const staged = questions.length > 1 || questions[0]!.multiSelect;
  // What the ACTIVE tab's options are drawn as. Read off the tab rather than
  // off the card, because a multi-question ask mixes the two freely: tab one
  // may take several answers and tab two exactly one, and a card-wide shape
  // would misdescribe whichever of them it was not built for.
  const optionArity: OptionArity = !staged
    ? 'none'
    : active.multiSelect
      ? 'many'
      : 'one';
  // Each tab's answer: the labels it picked, plus whatever was typed there.
  // Both, so "Red, but a lighter shade" survives as one answer.
  const typedAt = (index: number): string =>
    joinParts([...(picked[index] ?? []), (texts[index] ?? '').trim()]);
  // …and the tab's OWN image note, so a card of three questions announces the
  // screenshot on the line of the question it belongs to rather than once at
  // the end for the whole card.
  //
  // This is also what makes an image-only tab count as ANSWERED below: the note
  // is non-empty, so `unanswered` no longer lists a tab the user answered with
  // a picture. The old code had to special-case a lone question for that, on
  // the stated grounds that "one image cannot say which tab it belongs to" —
  // which stopped being true the moment images carried an owner.
  const answerAt = (index: number): string =>
    `${typedAt(index)}${imageNoteFor(imagesAt(index).length)}`;
  const submission =
    questions.length > 1 ? combinedAnswer(questions, answerAt) : answerAt(0);
  // The per-tab budget: the daemon drops an oversized verdict on the floor
  // (notifications.gateway `readVerdict`), so the tabs share the one wire
  // limit rather than letting any single tab spend all of it. The labelled
  // prefixes are reserved out of it first, so filling every tab to its own
  // maxLength always yields a submission the daemon will accept.
  const prefixCost =
    questions.length > 1
      ? questions.reduce(
          // `: ` after the label, `\n` between lines.
          (total, question) => total + answerLabel(question).length + 3,
          0,
        )
      : 0;
  const perTabBudget = Math.max(
    1,
    Math.floor((MAX_ANSWER_LENGTH - prefixCost) / questions.length),
  );
  // What is left of THIS tab's share once its picked labels are counted. The
  // answer that travels is picks + typed text joined, so bounding only the
  // typed half would let a pick push the tab past its budget — and the user
  // would hit the refusal by typing inside a limit the field itself allowed.
  const chosen = picked[activeIndex] ?? [];
  // On the staged path the picks are already made, so charge exactly them.
  // On the answer-on-click path NOTHING is picked yet and a click is the
  // submit — so reserve room for the WIDEST label this tab could add, or a
  // full-length typed answer plus a click would exceed the wire limit on a
  // path that has no Submit button to disable.
  const pendingPickCost = staged
    ? chosen.length === 0
      ? 0
      : joinParts(chosen).length + 2
    : active.options.reduce(
        (widest, label) => Math.max(widest, label.length),
        0,
      ) + 2;
  // Everything that will ride along with the typed text is reserved out of it
  // first — the widest label a click could add, and the image note — because
  // the answer-on-click path is the one submit path with no button to disable.
  // Anything left unreserved there puts the verdict past the wire limit, and
  // the daemon drops it with no on-card explanation.
  //
  // Floored at 0, not 1: a label wide enough to consume the whole budget must
  // leave NO room to type.
  const typedBudget = Math.max(
    0,
    perTabBudget -
      pendingPickCost -
      imageNoteFor(imagesAt(activeIndex).length).length,
  );
  const unanswered = questions
    .map((q, index) =>
      answerAt(index).length === 0 ? tabLabel(q, index) : null,
    )
    .filter((label): label is string => label !== null);
  const tooLong = submission.length > MAX_ANSWER_LENGTH;
  // ONE gate, shared by the Submit button and the Enter key — two conditions
  // would drift, and an Enter that outran the button's guard would send an
  // answer the daemon drops on the floor with no on-card explanation.
  //
  // A pasted screenshot ANSWERS the tab it was pasted into ("which of these
  // looks right?" is answered by the picture), on every card rather than only a
  // lone question — `answerAt` carries the note, so such a tab is not in
  // `unanswered` in the first place.
  const canSubmit = unanswered.length === 0 && !tooLong;
  // Submit is disabled for exactly two reasons, and both are SAID: a
  // disabled button with no explanation is the defect this card had.
  const blockedReason = tooLong
    ? `That answer is ${submission.length.toLocaleString()} characters — ${MAX_ANSWER_LENGTH.toLocaleString()} is the most the agent can receive. Shorten one of the answers.`
    : unanswered.length === 0
      ? null
      : questions.length > 1
        ? `Answer every tab to submit — still empty: ${unanswered.join(', ')}.`
        : 'Pick an option or type an answer to submit.';
  /**
   * The next tab still holding nothing, searching forward from `from` and
   * wrapping. Null when every other tab is already answered.
   *
   * `step < questions.length` stops one short of a full lap, so `from` itself
   * is never a candidate — landing back on the tab just answered would read as
   * the control doing nothing.
   */
  const nextUnansweredFrom = (from: number): number | null => {
    for (let step = 1; step < questions.length; step++) {
      const candidate = (from + step) % questions.length;
      if (answerAt(candidate).length === 0) {
        return candidate;
      }
    }
    return null;
  };
  const nextTab = nextUnansweredFrom(activeIndex);
  const pickOption = (index: number, label: string): void => {
    if (!staged) {
      // The click IS the whole answer here — but it is not the whole answer
      // TEXT: a qualifier already typed beside the options rides with it,
      // through the same join the staged path uses. Dropping it would spend
      // the one-shot verdict on a partial answer the user can't resend.
      //
      // The staged attachments ride too. `canSubmit` already treats a pasted
      // screenshot as a valid answer to a lone question, and Submit sends it —
      // so this path silently discarding it made the ONE case where the image
      // was lost the same case the card said was answerable, with the card then
      // settled and no way to resend.
      respond(
        true,
        `${joinParts([label, (texts[index] ?? '').trim()])}${imageNoteFor(imagesAt(index).length)}`,
        attachments.toWire(),
      );
      return;
    }
    const wasChosen = (picked[index] ?? [])[0] === label;
    setPicked((previous) => {
      const current = previous[index] ?? [];
      if (!questions[index]!.multiSelect) {
        // Single-pick: clicking the chosen label again clears it, so a
        // mis-tap is recoverable without spending the one-shot verdict.
        return { ...previous, [index]: current[0] === label ? [] : [label] };
      }
      return {
        ...previous,
        [index]: current.includes(label)
          ? current.filter((chosen) => chosen !== label)
          : [...current, label],
      };
    });
    // Move to the next unfilled tab once this one is settled.
    //
    // Only for a SINGLE-pick question: a multi-select is not finished after
    // one click, and jumping away would take the remaining options off screen
    // mid-answer. And not when the click CLEARED the pick — that leaves the
    // tab empty, so advancing would abandon a tab the user just emptied.
    //
    // This is the actual defect behind "Submit is disabled": the button
    // correctly waits for every tab, but nothing told the user other tabs
    // existed, so a card whose first tab was answered looked stuck.
    if (!questions[index]!.multiSelect && !wasChosen) {
      const next = nextUnansweredFrom(index);
      if (next !== null) {
        // `focusTab`, not `setActiveTab`: the option buttons are keyed
        // `${li}-${label}`, so switching tabs unmounts the button that was just
        // activated and focus falls to `document.body`. A keyboard user would
        // have to tab back in from the top of the document on EVERY question.
        focusTab(next);
      }
    }
  };
  const focusTab = (index: number): void => {
    const next = (index + questions.length) % questions.length;
    setActiveTab(next);
    tabRefs.current[next]?.focus();
  };
  return (
    <Card className="flex flex-col gap-2 border-primary/40 p-3">
      <div className="flex items-center gap-2">
        <MessageCircleQuestion
          aria-hidden="true"
          className="size-4 shrink-0 text-primary"
        />
        <span className="text-sm font-medium">Agent asks a question</span>
        {questions.length === 1 && active.header ? (
          <Badge variant="secondary">{active.header}</Badge>
        ) : null}
      </div>
      {showTabs ? (
        <div
          role="tablist"
          aria-label="Questions"
          className="flex flex-wrap gap-1 border-b border-border pb-1.5">
          {questions.map((q, qi) => {
            const selected = qi === activeIndex;
            const answered = answerAt(qi).length > 0;
            return (
              // Index-composite keys: one payload may repeat a question.
              <button
                key={`${qi}-${q.question}`}
                ref={(node) => {
                  tabRefs.current[qi] = node;
                }}
                type="button"
                role="tab"
                id={`${cardId}-tab-${qi}`}
                aria-selected={selected}
                aria-controls={`${cardId}-panel-${qi}`}
                // Roving tabindex: the strip is ONE tab stop, arrows move
                // within it — the pattern `role="tab"` promises.
                tabIndex={selected ? 0 : -1}
                data-answered={answered}
                onKeyDown={(e) => {
                  if (e.key === 'ArrowRight') {
                    focusTab(activeIndex + 1);
                  } else if (e.key === 'ArrowLeft') {
                    focusTab(activeIndex - 1);
                  } else if (e.key === 'Home') {
                    focusTab(0);
                  } else if (e.key === 'End') {
                    focusTab(questions.length - 1);
                  } else {
                    return;
                  }
                  e.preventDefault();
                }}
                onClick={() => setActiveTab(qi)}
                className={cn(
                  'inline-flex cursor-pointer items-center gap-1.5 rounded-md px-2.5 py-1 text-xs font-medium transition-colors outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50',
                  selected
                    ? 'bg-secondary text-secondary-foreground'
                    : 'text-muted-foreground hover:bg-accent hover:text-accent-foreground',
                )}>
                <span
                  aria-hidden="true"
                  className={cn(
                    'size-1.5 rounded-full',
                    answered ? 'bg-primary' : 'bg-border',
                  )}
                />
                {tabLabel(q, qi)}
              </button>
            );
          })}
        </div>
      ) : null}
      {pending ? (
        <div
          role={showTabs ? 'tabpanel' : undefined}
          id={showTabs ? `${cardId}-panel-${activeIndex}` : undefined}
          aria-labelledby={
            showTabs ? `${cardId}-tab-${activeIndex}` : undefined
          }
          className="flex flex-col gap-1.5">
          <p className="m-0 text-sm whitespace-pre-wrap">{active.question}</p>
          {active.options.length > 0 ? (
            <>
              {/* The arity in words, under the question and above the options
                  it describes — and it is said for EVERY arity, not only for
                  multi-select. A single-pick tab used to carry no line at all,
                  so "pick as many as apply" read as a property of that one
                  question rather than as one of two possible answers to "how
                  many may I choose", and its absence said nothing.

                  The count rides the same line, and only where counting is a
                  question: it is the running feedback a user two picks into a
                  list of ten wants without counting the ticks themselves, and
                  on a pick-one tab it is a line that can only ever say "1". */}
              <p className="m-0 text-xs text-muted-foreground">
                {arityHint(optionArity)}
                {optionArity === 'many' && chosen.length > 0
                  ? ` · ${chosen.length} selected`
                  : ''}
              </p>
              <OptionList
                options={active.options}
                selected={chosen}
                arity={optionArity}
                disabled={responded}
                label={
                  questions.length > 1
                    ? `Options: ${tabLabel(active, activeIndex)}`
                    : 'Options'
                }
                onPick={(label) => pickOption(activeIndex, label)}
              />
            </>
          ) : null}
          {/* On EVERY tab, not just a lone question: it is the only way to
              answer one the agent offered no options for, and the only way
              to qualify a pick. */}
          {/* Above the field, exactly as the composer stages its own pastes —
              the same component, so a thumbnail and its remove control cannot
              come to look different in the two places a screenshot is
              attached. */}
          <AttachmentStrip
            attachments={imagesAt(activeIndex)}
            onRemove={attachments.remove}
          />
          {attachments.error ? (
            /* `ErrorText`, not a hand-rolled <p>: it supplies role="alert", so
               a failed paste is ANNOUNCED rather than only drawn. The className
               keeps this instance at the card's own text size. */
            <ErrorText className="m-0 text-xs">{attachments.error}</ErrorText>
          ) : null}
          <Input
            value={texts[activeIndex] ?? ''}
            maxLength={typedBudget}
            disabled={responded}
            // Sized to the options above it rather than to a form field: at the
            // default height it was the tallest thing on the card and read as
            // the primary way to answer, when for a card that offers options it
            // is the qualifier beside them.
            className="h-8"
            onPaste={(event) => {
              // A paste carrying FILES is intercepted — images stage as
              // attachments, anything else becomes its absolute path, exactly
              // as in the composer. Plain text keeps the field's own
              // behaviour, which is what typing an answer is.
              //
              // The images are tagged with the tab they landed in — see
              // `imagesAt`. Read HERE rather than inside the hook's async
              // read, which the user is free to change tabs during.
              const staged = attachments.addFromClipboard(
                event.clipboardData,
                activeIndex,
              );
              const pathed = insertPastedFilePaths(event.clipboardData);
              if (staged || pathed) {
                event.preventDefault();
              }
            }}
            aria-label={
              questions.length > 1
                ? `Answer: ${tabLabel(active, activeIndex)}`
                : "Answer the agent's question"
            }
            placeholder={
              active.options.length > 0
                ? 'Or type your own answer…'
                : 'Type your answer…'
            }
            onChange={(e) =>
              setTexts((previous) => ({
                ...previous,
                [activeIndex]: e.target.value,
              }))
            }
            onKeyDown={(e) => {
              // The verdict is one-shot — an Enter that merely confirms an
              // IME composition must not submit a half-composed answer.
              if (e.nativeEvent.isComposing) {
                return;
              }
              if (e.key !== 'Enter') {
                return;
              }
              /*
                Enter ADVANCES before it submits, which is the second half of
                the report ("when i press enter - it should go to next tab
                automatically").

                Picking an option has moved to the next unfilled tab since the
                tabs were introduced; typing an answer did not, so a card of
                three free-text questions was answered by typing, reaching for
                the mouse, typing, reaching for the mouse again — and Enter,
                the key every one of those fields invites, did nothing at all.

                The order is what keeps it safe. `nextTab` is the next tab still
                EMPTY, so it is null exactly when nothing is left to fill in —
                which is when Enter submits, under the same `canSubmit` gate the
                button uses. From an empty tab, `nextTab` skips over nothing:
                the current tab is never its own candidate, so Enter on an
                unanswered tab moves on rather than submitting it blank, and the
                Submit button (which lists what is still empty) stays the way to
                finish.
              */
              if (nextTab !== null) {
                e.preventDefault();
                focusTab(nextTab);
                return;
              }
              if (canSubmit) {
                respond(true, submission, attachments.toWire());
              }
            }}
          />
        </div>
      ) : (
        questions.map((q, qi) => (
          <p
            key={`${qi}-${q.question}`}
            className="m-0 text-sm whitespace-pre-wrap">
            {q.question}
          </p>
        ))
      )}
      {expired && verdict === null ? (
        <p className="text-xs text-muted-foreground">
          ⏱ expired — the turn ended before an answer
        </p>
      ) : sending ? (
        <p className="text-xs text-muted-foreground">Sending…</p>
      ) : verdict === null ? (
        <>
          {blockedReason ? (
            <p className="m-0 text-xs text-warning">{blockedReason}</p>
          ) : null}
          {/* `sm` throughout: this is a row inside a transcript card, not a
              form's own footer, and three default-height buttons under a
              two-line question made the card's chrome taller than the question
              it was asking. Decline is `ghost` for the same reason it is last —
              it is the way out, not one of three equal choices. */}
          <div className="flex items-center gap-1.5">
            <Button
              type="button"
              size="sm"
              disabled={!canSubmit}
              onClick={() => respond(true, submission, attachments.toWire())}>
              {staged ? 'Submit answers' : 'Answer'}
            </Button>
            {/* The mouse counterpart to Enter's auto-advance — kept once Enter
                gained it, because the strip is small and this button is what
                names the move for anyone who never presses Enter in a field. */}
            {showTabs && nextTab !== null ? (
              <Button
                type="button"
                size="sm"
                variant="outline"
                disabled={responded}
                onClick={() => focusTab(nextTab)}>
                Next question
              </Button>
            ) : null}
            <Button
              type="button"
              size="sm"
              variant="ghost"
              className="ml-auto text-muted-foreground"
              onClick={() => respond(false)}>
              Decline
            </Button>
          </div>
        </>
      ) : (
        <div className="flex flex-col gap-1.5">
          <p
            className={cn(
              'm-0 text-xs',
              verdict ? 'text-success' : 'text-destructive',
            )}>
            {verdict ? '✓ answered' : '✗ declined'}
          </p>
          {/* The words the user actually sent, which the card used to swallow:
              a question was asked, answered, and the answer then existed
              nowhere on screen — while the AGENT's every sentence stays in the
              transcript forever. It carries the user bubble's own language
              (`bg-primary/10` over `border-primary/20`, straight from
              `message-bubble`'s `user` variant) rather than the muted grey of
              card chrome, because that is whose sentence it is.

              A multi-question card sends one labelled line per question, so
              `whitespace-pre-wrap` is what keeps that shape; the height is
              capped because the answer shares the wire budget with a 32k
              limit and a settled card must never push the live one off
              screen. */}
          {verdict && answer !== null && answer.trim() !== '' ? (
            <p className="m-0 max-h-40 overflow-auto rounded-md border border-primary/20 bg-primary/10 px-2.5 py-1.5 text-sm break-words whitespace-pre-wrap">
              {answer}
            </p>
          ) : null}
        </div>
      )}
    </Card>
  );
}

/**
 * A paused tool call under review: Approve/Deny over the tool's input, with a
 * file edit rendered as the same red/green diff the tool-group rows use.
 */
function PermissionCard({
  toolName,
  input,
  verdict,
  expired,
  onRespond,
}: {
  toolName: string;
  input: unknown;
  verdict: boolean | null;
  expired: boolean;
  onRespond: (allow: boolean, answer?: string) => void;
}): React.JSX.Element {
  const { sending, respond } = useOneShotVerdict(verdict, expired, onRespond);
  // A file edit under review reads as a diff, not as raw JSON — the same
  // red/green view the tool-group rows use once the call has run.
  const diff = editDiffOf(toolName, input);
  const filePath =
    input && typeof input === 'object' && 'file_path' in input
      ? String((input as { file_path: unknown }).file_path)
      : null;
  // An agent may name a tool call and withhold its arguments — an ACP `read` or
  // `edit` call does exactly that, and the daemon normalizes the empty bag it
  // sends to null (`disclosedInput`). Rendering that as JSON printed the literal
  // word `null` in the card, which reads as a value the agent supplied. The
  // predicate is shared with the transcript row so the two surfaces cannot give
  // different answers about whether arguments exist.
  // geniro's own patch proposal says what it DOES, and the card leads with it.
  // Scoped to that tool rather than to any input carrying a `summary` key: the
  // word is generic enough that another tool's arguments could hold one meaning
  // something else entirely, and this line replaces the card's whole heading.
  const proposal =
    toolName === PROPOSE_PATCH &&
    input &&
    typeof input === 'object' &&
    typeof (input as { summary?: unknown }).summary === 'string'
      ? (input as { summary: string }).summary
      : null;
  const showsInput = disclosesInput(input);
  let inputPreview: string;
  try {
    inputPreview = JSON.stringify(input, null, 2);
  } catch {
    inputPreview = String(input);
  }
  return (
    <Card className="flex flex-col gap-2.5 border-primary/40 p-3">
      <div className="flex items-center gap-2">
        <ShieldQuestion
          aria-hidden="true"
          className="size-4 shrink-0 text-primary"
        />
        {/* A proposal is not a request to RUN something — approving it applies
            a change — so it leads with what the change does, and falls back to
            saying that much when the agent named no summary. Every other tool
            keeps the wording it has always had. */}
        <span className="min-w-0 flex-1 truncate text-sm font-medium">
          {toolName === PROPOSE_PATCH
            ? (proposal ?? 'Agent proposes a change')
            : 'Agent asks to run a tool'}
        </span>
        <Badge variant="secondary" className="shrink-0">
          {toolName}
        </Badge>
      </div>
      {diff ? (
        <div className="flex flex-col gap-1.5">
          {filePath ? (
            <div className="font-mono text-xs text-muted-foreground">
              {filePath}
            </div>
          ) : null}
          <div className="max-h-48 overflow-auto">
            <DiffView oldText={diff.oldText} newText={diff.newText} />
          </div>
        </div>
      ) : showsInput ? (
        <pre className="m-0 max-h-48 overflow-auto rounded-md bg-muted p-2 font-mono text-xs whitespace-pre-wrap">
          {inputPreview}
        </pre>
      ) : null}
      {expired && verdict === null ? (
        <p className="text-xs text-muted-foreground">
          ⏱ expired — the turn ended before an answer
        </p>
      ) : sending ? (
        <p className="text-xs text-muted-foreground">Sending…</p>
      ) : verdict === null ? (
        <div className="flex gap-2">
          <Button type="button" onClick={() => respond(true)}>
            Approve
          </Button>
          <Button
            type="button"
            variant="outline"
            onClick={() => respond(false)}>
            Deny
          </Button>
        </div>
      ) : (
        <p
          className={cn(
            'text-xs',
            verdict ? 'text-success' : 'text-destructive',
          )}>
          {verdict ? '✓ approved' : '✗ denied'}
        </p>
      )}
    </Card>
  );
}

/**
 * Elicitation card for an `ask`-node's paused tool call — a two-line router.
 *
 * Once the persisted `approval_verdict` item arrives (or replays after a
 * reconnect) each body renders its settled state; the verdict item is the
 * durable acknowledgment, so neither needs local optimistic state.
 *
 * The AskUserQuestion split is NAME-ONLY, matching the daemon's answer-fold
 * gate exactly: a card must never collect an answer the daemon would refuse to
 * deliver, so a flag-only interactive tool renders the permission body — as
 * does an AskUserQuestion whose payload parses to nothing.
 */
export function ApprovalCard({
  toolName,
  input,
  verdict,
  answer = null,
  expired = false,
  onRespond,
}: {
  toolName: string;
  input: unknown;
  /** null while pending; the user's answer once the verdict item arrived. */
  verdict: boolean | null;
  /**
   * The words that answer carried, read back from the same verdict item.
   *
   * Only the QUESTION body can show one, and only that body can produce one:
   * the daemon records an answer solely where it folded it into the CLI's own
   * question tool, and a permission card's verdict is a yes or a no with
   * nothing said. Defaulted so a caller with nothing to read back — a card
   * still pending — need not pass it.
   */
  answer?: string | null;
  /** The turn ended before an answer — no verdict can apply anymore. */
  expired?: boolean;
  /**
   * `images` arrive only from the QUESTION body, and only as a SEPARATE
   * delivery — see its `onRespond` note. A permission card never sends any:
   * approving a tool call is a yes or a no, with nothing to attach to it.
   */
  onRespond: (
    allow: boolean,
    answer?: string,
    images?: SendMessageDtoImagesInner[],
  ) => void;
}): React.JSX.Element {
  // One parser per CLI's question shape, chosen by the name the DAEMON put on
  // the request — each adapter's own `questionToolName`. Gated on the name
  // rather than on "did it parse", because both shapes are just `questions:
  // [...]`: an ordinary tool call carrying a field of that name would
  // otherwise be rendered as a question and answered as one.
  //
  // Two entries, not a lookup: this is the twin-parser carve-out (the item
  // payload is untyped on the wire by design, so no generated type reaches
  // here), and a name spelled on both sides is what the doc blocks above
  // cross-reference.
  // `ask_user_question` is geniro's OWN tool, registered for a CLI whose model
  // has none (the daemon's `HOST_QUESTION_TOOL`), and it deliberately takes the
  // AskUserQuestion shape so it reads through this same parser — a host-asked
  // question and a claude-asked one are the same card, not two that could
  // drift.
  const questions =
    toolName === 'AskUserQuestion' || toolName === 'ask_user_question'
      ? readQuestions(input)
      : toolName === 'cursor/ask_question'
        ? readCursorQuestions(input)
        : [];
  return questions.length > 0 ? (
    <QuestionCard
      questions={questions}
      verdict={verdict}
      answer={answer}
      expired={expired}
      onRespond={onRespond}
    />
  ) : (
    <PermissionCard
      toolName={toolName}
      input={input}
      verdict={verdict}
      expired={expired}
      onRespond={onRespond}
    />
  );
}
