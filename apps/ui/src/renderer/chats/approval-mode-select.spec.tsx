// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type {
  AgentApprovalCapability,
  ChatApprovalMode,
} from '../autogenerated';
import { ApprovalModeSelect, approvalOptions } from './approval-mode-select';

/** What the daemon reports for claude — every mode the CLI honours. */
const CLAUDE_MODES: readonly ChatApprovalMode[] = [
  'auto',
  'ask',
  'acceptEdits',
  'plan',
];

function claudeCapability(
  over: Partial<AgentApprovalCapability> = {},
): AgentApprovalCapability {
  return {
    agent: 'claude',
    modes: [...CLAUDE_MODES],
    probe: null,
    ...over,
  };
}

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function render(element: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(element);
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const trigger = (el: HTMLElement): HTMLButtonElement =>
  el.querySelector<HTMLButtonElement>('[data-menu-trigger]')!;

/** The menu's rows — the picker is ours, so they are real DOM, not an OS menu. */
function optionValues(el: HTMLElement): string[] {
  act(() => {
    trigger(el).click();
  });
  return [...el.querySelectorAll('[role="option"]')].map(
    (o) => o.textContent ?? '',
  );
}

describe('approvalOptions', () => {
  const REQUIRES_PASS = 'plan' as const;

  it('withholds a requiresPass mode whose probe is UNKNOWN', () => {
    const options = approvalOptions(
      claudeCapability({
        probe: {
          modes: [
            { mode: REQUIRES_PASS, status: 'unknown', requiresPass: true },
          ],
          version: null,
          probedAt: null,
          reason: null,
        },
      }),
      'ask',
    );
    expect(options.map((o) => o.value)).not.toContain('plan');
  });

  it('offers a requiresPass mode once its probe PASSES', () => {
    const options = approvalOptions(
      claudeCapability({
        probe: {
          modes: [{ mode: REQUIRES_PASS, status: 'pass', requiresPass: true }],
          version: null,
          probedAt: null,
          reason: null,
        },
      }),
      'ask',
    );
    expect(options.map((o) => o.value)).toContain('plan');
  });

  it('offers a requiresPass:false mode even while its probe is UNKNOWN — the daemon degrades it', () => {
    const options = approvalOptions(
      claudeCapability({
        probe: {
          modes: [
            { mode: 'acceptEdits', status: 'unknown', requiresPass: false },
          ],
          version: null,
          probedAt: null,
          reason: null,
        },
      }),
      'ask',
    );
    expect(options.map((o) => o.value)).toContain('acceptEdits');
  });

  it('drops a mode this surface withholds', () => {
    const options = approvalOptions(claudeCapability(), 'ask', ['plan']);
    expect(options.map((o) => o.value)).not.toContain('plan');
  });

  it('keeps the CURRENT value even when it is withheld, unsupported by no probe pass, or otherwise refused', () => {
    // Never refuse to show what a run already holds.
    const options = approvalOptions(claudeCapability(), 'plan', ['plan']);
    expect(options.map((o) => o.value)).toContain('plan');
  });

  it('answers empty while the capability has not loaded', () => {
    expect(approvalOptions(undefined, 'ask')).toEqual([]);
  });
});

describe('ApprovalModeSelect', () => {
  it('offers ask / accept edits / auto and hides plan whose probe has not passed', () => {
    const el = render(
      <ApprovalModeSelect
        capability={claudeCapability({
          probe: {
            modes: [{ mode: 'plan', status: 'unknown', requiresPass: true }],
            version: null,
            probedAt: null,
            reason: null,
          },
        })}
        value="ask"
        onChange={() => {}}
      />,
    );
    expect(optionValues(el)).toEqual(['ask', 'accept edits', 'auto-approve']);
  });

  it('offers plan once its probe passes, and fires onChange with the picked mode', () => {
    const onChange = vi.fn();
    const el = render(
      <ApprovalModeSelect
        capability={claudeCapability({
          probe: {
            modes: [{ mode: 'plan', status: 'pass', requiresPass: true }],
            version: null,
            probedAt: null,
            reason: null,
          },
        })}
        value="ask"
        onChange={onChange}
      />,
    );
    expect(optionValues(el)).toEqual([
      'ask',
      'accept edits',
      'plan',
      'auto-approve',
    ]);
    act(() => {
      el.querySelectorAll<HTMLElement>('[role="option"]')[1]!.click();
    });
    expect(onChange).toHaveBeenCalledWith('acceptEdits');
  });

  it('keeps a stored plan value visible even when the probe says unsupported — the select never lies', () => {
    const el = render(
      <ApprovalModeSelect
        capability={claudeCapability({
          probe: {
            modes: [{ mode: 'plan', status: 'fail', requiresPass: true }],
            version: null,
            probedAt: null,
            reason: null,
          },
        })}
        value="plan"
        onChange={() => {}}
      />,
    );
    expect(optionValues(el)).toContain('plan');
  });

  it('renders a legacy null value as a one-way "cli default" placeholder', () => {
    const el = render(
      <ApprovalModeSelect
        capability={claudeCapability()}
        value={null}
        onChange={() => {}}
      />,
    );
    expect(trigger(el).textContent).toContain('cli default');
  });

  it('renders nothing when the CLI honours no modes at all', () => {
    // A CLI with no approval channel has nothing to present, so the row omits
    // the chip rather than showing a control over nothing. The emptiness is
    // the DAEMON's answer, though — never inferred from the agent's name.
    // `value` is null (not one of the four modes) so this cannot be confused
    // with the separate "current value always kept" rule tested above, which
    // only rescues a mode the run is ALREADY on.
    const el = render(
      <ApprovalModeSelect
        capability={claudeCapability({ modes: [] })}
        value={null}
        onChange={() => {}}
      />,
    );

    expect(el.querySelector('[data-menu-trigger]')).toBeNull();
    expect(el.textContent).toBe('');
    expect(el.children).toHaveLength(0);
  });

  it('renders nothing until the capability is known, rather than guessing', () => {
    const el = render(
      <ApprovalModeSelect
        capability={undefined}
        value="ask"
        onChange={() => {}}
      />,
    );
    expect(el.children).toHaveLength(0);
  });

  it('offers exactly the modes the CLI reports — the cursor regression', () => {
    // cursor-agent over ACP honours auto and ask, and NOT plan. The chip
    // used to render nothing for it purely because of its name, which hid a
    // control the user really had: every cursor chat sat in `ask` and raised a
    // permission card per tool with no way to change it.
    const el = render(
      <ApprovalModeSelect
        capability={{
          agent: 'cursor-agent',
          modes: ['auto', 'ask'],
          probe: null,
        }}
        value="ask"
        onChange={() => {}}
      />,
    );
    expect(optionValues(el)).toEqual(['ask', 'auto-approve']);
  });

  it('withholds a mode this surface passed in `withheld`, even though the CLI honours it', () => {
    const el = render(
      <ApprovalModeSelect
        capability={claudeCapability({
          probe: {
            modes: [{ mode: 'plan', status: 'pass', requiresPass: true }],
            version: null,
            probedAt: null,
            reason: null,
          },
        })}
        value="ask"
        withheld={['plan']}
        onChange={() => {}}
      />,
    );
    expect(optionValues(el)).not.toContain('plan');
  });

  it('stays usable while a turn is running, like every other composer chip', () => {
    // It used to lock, because the daemon 409'd a mid-turn approval change.
    // The CLI accepts `set_permission_mode` on a turn already in flight and
    // re-reads it in milliseconds, so the daemon now hands the change to the
    // running turn — and a chip disabled in advance would hide a control the
    // user really has. The one case that still cannot be honoured (a turn
    // spawned with no permission gate) is refused by the daemon and surfaces
    // as an error, which is the only place that fact is actually known.
    const el = render(
      <ApprovalModeSelect
        capability={claudeCapability()}
        value="ask"
        onChange={() => {}}
      />,
    );
    expect(trigger(el).disabled).toBe(false);
  });
});
