// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ChatApprovalMode } from '../autogenerated';
import { ApprovalModeSelect } from './approval-mode-select';

/** What the daemon reports for claude — every mode the CLI honours. */
const CLAUDE_MODES: readonly ChatApprovalMode[] = [
  'auto',
  'ask',
  'acceptEdits',
  'plan',
];

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function render(element: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(element);
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const trigger = (el: HTMLElement): HTMLButtonElement =>
  el.querySelector<HTMLButtonElement>('[data-menu-trigger]')!;

/** The menu's rows — the picker is ours, so they are real DOM, not an OS menu. */
function optionValues(el: HTMLElement): string[] {
  act(() => {
    trigger(el).click();
  });
  return [...el.querySelectorAll('[role="option"]')].map(
    (o) => o.textContent ?? '',
  );
}

describe('ApprovalModeSelect', () => {
  it('offers ask / accept edits / auto and hides plan when the probe did not pass', () => {
    const el = render(
      <ApprovalModeSelect
        supportedModes={CLAUDE_MODES}
        value="ask"
        planSupported={false}
        onChange={() => {}}
      />,
    );
    expect(optionValues(el)).toEqual(['ask', 'accept edits', 'auto-approve']);
  });

  it('offers plan when the installed CLI probed pass, and fires onChange with the picked mode', () => {
    const onChange = vi.fn();
    const el = render(
      <ApprovalModeSelect
        supportedModes={CLAUDE_MODES}
        value="ask"
        planSupported
        onChange={onChange}
      />,
    );
    expect(optionValues(el)).toEqual([
      'ask',
      'accept edits',
      'plan',
      'auto-approve',
    ]);
    act(() => {
      el.querySelectorAll<HTMLElement>('[role="option"]')[1]!.click();
    });
    expect(onChange).toHaveBeenCalledWith('acceptEdits');
  });

  it('keeps a stored plan value visible even when the probe says unsupported — the select never lies', () => {
    const el = render(
      <ApprovalModeSelect
        supportedModes={CLAUDE_MODES}
        value="plan"
        planSupported={false}
        onChange={() => {}}
      />,
    );
    expect(optionValues(el)).toContain('plan');
  });

  it('renders a legacy null value as a one-way "cli default" placeholder', () => {
    const el = render(
      <ApprovalModeSelect
        supportedModes={CLAUDE_MODES}
        value={null}
        planSupported={false}
        onChange={() => {}}
      />,
    );
    expect(trigger(el).textContent).toContain('cli default');
  });

  it('renders nothing when the CLI honours no modes at all', () => {
    // A CLI with no approval channel has nothing to present, so the row omits
    // the chip rather than showing a control over nothing. The emptiness is
    // the DAEMON's answer, though — never inferred from the agent's name.
    const el = render(
      <ApprovalModeSelect
        supportedModes={[]}
        value="auto"
        planSupported
        onChange={() => {}}
      />,
    );

    expect(el.querySelector('[data-menu-trigger]')).toBeNull();
    expect(el.textContent).toBe('');
    expect(el.children).toHaveLength(0);
  });

  it('renders nothing until the capability is known, rather than guessing', () => {
    const el = render(
      <ApprovalModeSelect
        supportedModes={null}
        value="ask"
        planSupported
        onChange={() => {}}
      />,
    );
    expect(el.children).toHaveLength(0);
  });

  it('offers exactly the modes the CLI reports — the cursor regression', () => {
    // cursor-agent over ACP honours auto/ask/acceptEdits and NOT plan. The chip
    // used to render nothing for it purely because of its name, which hid a
    // control the user really had: every cursor chat sat in `ask` and raised a
    // permission card per tool with no way to change it.
    const el = render(
      <ApprovalModeSelect
        supportedModes={['auto', 'ask', 'acceptEdits']}
        value="ask"
        planSupported
        onChange={() => {}}
      />,
    );
    expect(optionValues(el)).toEqual(['ask', 'accept edits', 'auto-approve']);
  });

  it('stays usable while a turn is running, like every other composer chip', () => {
    // It used to lock, because the daemon 409'd a mid-turn approval change.
    // The CLI accepts `set_permission_mode` on a turn already in flight and
    // re-reads it in milliseconds, so the daemon now hands the change to the
    // running turn — and a chip disabled in advance would hide a control the
    // user really has. The one case that still cannot be honoured (a turn
    // spawned with no permission gate) is refused by the daemon and surfaces
    // as an error, which is the only place that fact is actually known.
    const el = render(
      <ApprovalModeSelect
        supportedModes={CLAUDE_MODES}
        value="ask"
        planSupported={false}
        onChange={() => {}}
      />,
    );
    expect(trigger(el).disabled).toBe(false);
  });
});
