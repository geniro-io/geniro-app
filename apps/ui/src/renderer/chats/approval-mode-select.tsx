import type { CliKind } from '../../shared/contracts';
import type { ChatApprovalMode } from '../autogenerated';
import { Select } from '../components/ui/select';

/** Display labels for the chat approval modes (order = menu order). */
const MODE_LABELS: readonly { value: ChatApprovalMode; label: string }[] = [
  { value: 'ask', label: 'ask' },
  { value: 'acceptEdits', label: 'accept edits' },
  { value: 'plan', label: 'plan' },
  { value: 'auto', label: 'auto-approve' },
];

/**
 * The composer's tool-approval chip — claude only.
 *
 * A cursor chat renders NOTHING here. cursor-agent has no per-turn approval
 * channel to drive: its whole per-run permission surface is the `--force`
 * boolean, and everything else comes from the static allow/deny list the CLI
 * reads itself from `~/.cursor/cli-config.json`. There is no moment at which
 * this app could raise a card, so a mode picker would be a control over
 * nothing. It previously stated the pinned mode as a static badge; that is
 * chrome on a choice the user does not have, so the row simply omits it.
 *
 * Claude chats offer ask / accept edits / plan / auto-approve, with `plan`
 * hidden unless the installed CLI probed pass (no dead UI) — a run already
 * stored on `plan` keeps its option visible so the select never lies. A legacy
 * run whose approval is null shows a one-way "cli default" placeholder until a
 * mode is picked.
 */
export function ApprovalModeSelect({
  agentKind,
  value,
  planSupported,
  lockedMidTurn = false,
  onChange,
  className,
}: {
  agentKind: CliKind;
  /** Current mode; null = legacy run created before the selector existed. */
  value: ChatApprovalMode | null;
  planSupported: boolean;
  /**
   * A turn is running, so this chip is LOCKED.
   *
   * The odd one out among the composer chips, and deliberately: the daemon
   * 409s an approval change mid-turn because this is the permission control,
   * and an ACK that the running turn will not honour would state a safety
   * posture the user does not have. Model and effort carry no such risk and
   * stay editable, applying to the next turn.
   */
  lockedMidTurn?: boolean;
  onChange: (mode: ChatApprovalMode) => void;
  className?: string;
}): React.JSX.Element | null {
  if (agentKind === 'cursor-agent') {
    return null;
  }
  const options = MODE_LABELS.filter(
    (mode) => mode.value !== 'plan' || planSupported || value === 'plan',
  );
  return (
    <Select
      variant="ghost"
      value={value}
      placeholder="cli default"
      aria-label="Tool-approval mode"
      disabled={lockedMidTurn}
      title={
        lockedMidTurn
          ? 'The approval mode is locked while a turn is running'
          : 'Tool-approval mode'
      }
      className={className}
      groups={[{ items: [...options] }]}
      onValueChange={(mode) => onChange(mode as ChatApprovalMode)}
    />
  );
}
