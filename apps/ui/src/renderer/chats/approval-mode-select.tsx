import type {
  AgentApprovalCapability,
  ChatApprovalMode,
} from '../autogenerated';
import { Select } from '../components/ui/select';

/**
 * Display labels for the chat approval modes (order = menu order).
 *
 * EXPORTED because the composer now offers this axis inside the model-settings
 * popover (`ModelSettingsSelect`) while this chip still serves the surface that
 * is not a chip row — the graph node inspector. One list, so the two renderings
 * cannot come to spell `auto` two different ways.
 */
export const MODE_LABELS: readonly {
  value: ChatApprovalMode;
  label: string;
}[] = [
  { value: 'ask', label: 'ask' },
  { value: 'acceptEdits', label: 'accept edits' },
  { value: 'plan', label: 'plan' },
  { value: 'auto', label: 'auto-approve' },
];

/**
 * No mode withheld — the default for callers that do not need one, and a
 * stable reference so passing nothing never churns a memo keyed on it.
 */
const NO_WITHHELD: readonly ChatApprovalMode[] = [];

/**
 * Withholds `plan` — the posture for a surface that runs unattended (a task,
 * a project default, a workflow node): `plan` makes an agent write a plan and
 * stop, which is not a thing to pin on a run nobody is watching to act on it.
 * A run already stored on it keeps the option regardless — see
 * {@link approvalOptions}'s current-value rule.
 */
export const PLAN_WITHHELD: readonly ChatApprovalMode[] = ['plan'];

/**
 * The composer's tool-approval chip, offering exactly the modes the run's CLI
 * says it honours.
 *
 * Which modes those are is the DAEMON's answer (`GET /v1/capabilities`
 * `approvals[]`, composed from each adapter's own `AdapterConfig.approval`),
 * never a judgement made here. This used to branch on the agent name —
 * `agentKind === 'cursor-agent'` rendered nothing, on the once-true grounds
 * that the CLI had no per-turn approval channel. ACP gave it one, so the chip
 * was hiding a control the user really had: every cursor chat sat in the
 * daemon's default `ask`, raised a permission card for every tool, and offered
 * no way to switch. A name-based branch cannot notice a CLI gaining a
 * capability; a capability list can.
 *
 * Renders nothing when the CLI honours no modes at all, and nothing while the
 * capability is still unknown — a picker that guesses its own options would be
 * stating a safety posture nobody verified.
 *
 * A mode whose probe row says `requiresPass` carries one extra narrowing: it
 * is hidden until that probe passes (no dead UI), while a run already stored
 * on it keeps the option visible so the select never lies.
 *
 * Editable MID-TURN, like every other composer chip. It used to lock, on the
 * once-true grounds that the daemon 409'd an approval change while a turn ran —
 * but the CLI accepts a `set_permission_mode` on a turn already in flight and
 * re-reads it in milliseconds, so that refusal was a limitation of the daemon
 * rather than of the agent. The daemon now hands the change to the running turn
 * and still refuses the one case it genuinely cannot honour (a turn spawned
 * with no permission gate at all), which surfaces as an ordinary error rather
 * than as a control greyed out in advance.
 */
export function ApprovalModeSelect({
  capability,
  value,
  withheld = NO_WITHHELD,
  onChange,
  className,
}: {
  /**
   * This agent's approval capability (its modes plus any probe), or
   * `undefined` while capabilities have not loaded. A capability with an
   * empty `modes` list means the CLI has no approval channel — the chip is
   * then absent because there is genuinely nothing to choose, not because of
   * its name.
   */
  capability: AgentApprovalCapability | undefined;
  /** Current mode; null = legacy run created before the selector existed. */
  value: ChatApprovalMode | null;
  /**
   * Modes this surface never offers regardless of what the CLI honours — a
   * run that starts unattended withholds `plan` this way. The current value
   * is offered even so; see {@link approvalOptions}.
   */
  withheld?: readonly ChatApprovalMode[];
  onChange: (mode: ChatApprovalMode) => void;
  className?: string;
}): React.JSX.Element | null {
  const options = approvalOptions(capability, value, withheld);
  if (options.length === 0) {
    return null;
  }
  return (
    <Select
      variant="ghost"
      value={value}
      placeholder="cli default"
      aria-label="Tool-approval mode"
      title="Tool-approval mode"
      className={className}
      groups={[{ items: [...options] }]}
      onValueChange={(mode) => onChange(mode as ChatApprovalMode)}
    />
  );
}

/**
 * Which modes to offer, given what the CLI honours, this surface's own
 * withheld set, and what each mode's probe says.
 *
 * Its own function because two surfaces ask it — this chip and the composer's
 * model-settings popover — and the probe/withheld narrowing is the kind of
 * rule that silently diverges when it is written twice.
 *
 * A mode is offered when it is in the capability's `modes`, is not in
 * `withheld`, and — if its probe row has `requiresPass: true` — that row's
 * status is `pass` (a row with `requiresPass: false`, or no row at all, is
 * offered whatever its status). The CURRENT value is always offered on top of
 * all three checks: a picker must never refuse to show what a run already
 * holds, however it got there.
 */
export function approvalOptions(
  capability: AgentApprovalCapability | undefined,
  value: ChatApprovalMode | null,
  withheld: readonly ChatApprovalMode[] = NO_WITHHELD,
): { value: ChatApprovalMode; label: string }[] {
  if (capability === undefined) {
    return [];
  }
  return MODE_LABELS.filter((mode) => {
    if (mode.value === value) {
      return true;
    }
    if (
      !capability.modes.includes(mode.value) ||
      withheld.includes(mode.value)
    ) {
      return false;
    }
    const probeRow = capability.probe?.modes.find(
      (row) => row.mode === mode.value,
    );
    return probeRow?.requiresPass !== true || probeRow.status === 'pass';
  });
}
