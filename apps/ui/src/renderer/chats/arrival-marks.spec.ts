import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem, ItemKind } from '../autogenerated';
import { arrivalMarks, NO_ARRIVAL_MARKS } from './arrival-marks';

function row(
  seq: number,
  kind: ItemKind,
  fields: Partial<Pick<ChatItem, 'role' | 'payload'>> = {},
): ChatItem {
  return {
    id: `r1-${seq}`,
    runId: 'r1',
    memberId: null,
    seq,
    kind,
    role: null,
    payload: {},
    createdAt: 'now',
    ...fields,
  };
}

describe('arrivalMarks', () => {
  it('answers the shared empty marks when nothing arrived', () => {
    expect(arrivalMarks([])).toBe(NO_ARRIVAL_MARKS);
    expect(NO_ARRIVAL_MARKS).toEqual({
      ids: new Set(),
      turnEnds: 0,
      pausedSpanRows: 0,
      userSeq: 0,
      agentSeq: 0,
      artifactSeq: 0,
      teamNoteSeq: 0,
      eventSeq: 0,
    });
  });

  it('counts the turn ends and the rows that move a team’s paused spans', () => {
    const marks = arrivalMarks([
      row(1, 'turn_complete'),
      row(2, 'turn_cancelled'),
      row(3, 'error'),
      row(4, 'approval_request'),
      row(5, 'shell_open'),
      row(6, 'subagent_info'),
      row(7, 'status', { payload: { status: 'running' } }),
      row(8, 'status', { payload: { status: 'completed' } }),
      row(9, 'message', { role: 'assistant' }),
    ]);

    expect(marks.turnEnds).toBe(3);
    expect(marks.pausedSpanRows).toBe(4);
  });

  it('takes the newest seq of each refresh kind, and the agent’s side excludes the user’s messages', () => {
    const marks = arrivalMarks([
      row(2, 'message', { role: 'user' }),
      row(7, 'message', { role: 'user' }),
      row(9, 'message', { role: 'assistant' }),
      row(11, 'reasoning'),
      row(12, 'tool_result'),
      row(20, 'message', { role: 'user' }),
      row(3, 'team_note'),
      row(5, 'team_note'),
      row(4, 'show_artifact'),
      row(6, 'show_artifact'),
    ]);

    expect(marks.userSeq).toBe(20);
    expect(marks.agentSeq).toBe(11);
    expect(marks.artifactSeq).toBe(6);
    expect(marks.teamNoteSeq).toBe(5);
  });

  it('takes the newest row the thread timeline draws an event from, and no other', () => {
    const marks = arrivalMarks([
      row(3, 'milestone'),
      row(8, 'stage_change'),
      row(9, 'message', { role: 'assistant' }),
      row(10, 'tool_result'),
      row(6, 'error'),
    ]);

    expect(marks.eventSeq).toBe(8);
  });

  it('holds the id of every row that arrived, whatever its kind', () => {
    const marks = arrivalMarks([
      row(1, 'message', { role: 'user' }),
      row(2, 'tool_call'),
      row(3, 'team_note'),
    ]);

    expect(marks.ids).toEqual(new Set(['r1-1', 'r1-2', 'r1-3']));
  });
});
