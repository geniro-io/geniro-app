import type { ItemDto as ChatItem } from '../autogenerated';
import { TERMINAL_KINDS } from './settled-status';
import { movesPausedSpans } from './turn-duration';

/**
 * The refresh triggers of the open thread's whole-run reads, taken over the
 * rows that ARRIVED after it opened (live, or replayed after a reconnect) —
 * never over the window, whose first page would move every one of them and
 * re-read what the open just read.
 */
export interface ArrivalMarks {
  ids: ReadonlySet<string>;
  turnEnds: number;
  pausedSpanRows: number;
  userSeq: number;
  agentSeq: number;
  artifactSeq: number;
  teamNoteSeq: number;
}

export const NO_ARRIVAL_MARKS: ArrivalMarks = {
  ids: new Set(),
  turnEnds: 0,
  pausedSpanRows: 0,
  userSeq: 0,
  agentSeq: 0,
  artifactSeq: 0,
  teamNoteSeq: 0,
};

export function arrivalMarks(arrivals: readonly ChatItem[]): ArrivalMarks {
  if (arrivals.length === 0) {
    return NO_ARRIVAL_MARKS;
  }
  const ids = new Set<string>();
  const marks = { ...NO_ARRIVAL_MARKS, ids };
  for (const row of arrivals) {
    ids.add(row.id);
    if (TERMINAL_KINDS.has(row.kind)) {
      marks.turnEnds += 1;
    }
    if (movesPausedSpans(row)) {
      marks.pausedSpanRows += 1;
    }
    if (row.kind === 'message' && row.role === 'user') {
      marks.userSeq = Math.max(marks.userSeq, row.seq);
    } else if (row.kind === 'message' || row.kind === 'reasoning') {
      marks.agentSeq = Math.max(marks.agentSeq, row.seq);
    } else if (row.kind === 'show_artifact') {
      marks.artifactSeq = Math.max(marks.artifactSeq, row.seq);
    } else if (row.kind === 'team_note') {
      marks.teamNoteSeq = Math.max(marks.teamNoteSeq, row.seq);
    }
  }
  return marks;
}
