import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { artifactsFrom } from './artifact-payload';

const URL_A =
  'https://claude.ai/code/artifact/5f197e53-a2f2-492c-b199-601853f4823f';
const URL_B =
  'https://claude.ai/code/artifact/02ef45f2-f4bd-4ab7-8bf6-d6a32048776e';

function call(
  seq: number,
  id: string,
  input: Record<string, unknown>,
  name = 'Artifact',
): ChatItem {
  return {
    id: `c${seq}`,
    runId: 'r1',
    nodeId: null,
    seq,
    kind: 'tool_call',
    role: null,
    payload: { id, name, input },
    createdAt: `2026-08-18T10:0${seq}:00.000Z`,
  };
}

function result(seq: number, id: string, text: string): ChatItem {
  return {
    id: `r${seq}`,
    runId: 'r1',
    nodeId: null,
    seq,
    kind: 'tool_result',
    role: null,
    payload: { id, result: text },
    createdAt: `2026-08-18T10:0${seq}:00.000Z`,
  };
}

describe('artifactsFrom', () => {
  it('reads the page a publish reported, with the name the tool gave it', () => {
    const items = [
      call(1, 'toolu_1', { action: 'publish', title: 'Coverage Audit' }),
      result(2, 'toolu_1', `Published — ${URL_A}`),
    ];
    expect(artifactsFrom(items)).toEqual([
      {
        id: '5f197e53-a2f2-492c-b199-601853f4823f',
        url: URL_A,
        title: 'Coverage Audit',
        at: '2026-08-18T10:02:00.000Z',
        seq: 2,
      },
    ]);
  });

  it('takes the title out of the tool’s own line when the call named none', () => {
    // The shape a live 2.1.234 result actually carries.
    const items = [
      call(1, 'toolu_1', { action: 'status' }),
      result(
        2,
        'toolu_1',
        `- Coverage Audit — Kenya, UAE, Italy — ${URL_A} — updated 2026-08-11`,
      ),
    ];
    expect(artifactsFrom(items)[0]?.title).toBe('Coverage Audit');
  });

  it('keeps ONE row per artifact — the newest republish wins', () => {
    const items = [
      call(1, 'toolu_1', { action: 'publish', title: 'Draft' }),
      result(2, 'toolu_1', `Published — ${URL_A}`),
      call(3, 'toolu_2', { action: 'publish', title: 'Final' }),
      result(4, 'toolu_2', `Published — ${URL_A}`),
    ];
    const artifacts = artifactsFrom(items);
    expect(artifacts).toHaveLength(1);
    expect(artifacts[0]?.title).toBe('Final');
  });

  it('orders newest first, so the head is the CURRENT one', () => {
    const items = [
      call(1, 'toolu_1', { action: 'publish', title: 'Older' }),
      result(2, 'toolu_1', `Published — ${URL_A}`),
      call(3, 'toolu_2', { action: 'publish', title: 'Newer' }),
      result(4, 'toolu_2', `Published — ${URL_B}`),
    ];
    expect(artifactsFrom(items).map((a) => a.title)).toEqual([
      'Newer',
      'Older',
    ]);
  });

  it('ignores a LISTING, which describes the account and not this thread', () => {
    // Probe-verified on 2.1.234: `action: "list"` answers with every artifact
    // the user has ever published — five, on the account it was run against —
    // so folding it in would fill a chat's panel with pages it never touched.
    const items = [
      call(1, 'toolu_1', { action: 'list' }),
      result(
        2,
        'toolu_1',
        `5 published artifacts (most recent first):\n- One — ${URL_A} — updated 2026-08-11\n- Two — ${URL_B} — updated 2026-08-09`,
      ),
    ];
    expect(artifactsFrom(items)).toEqual([]);
  });

  it('ignores another tool that merely mentions an artifact URL', () => {
    const items = [
      call(1, 'toolu_1', { command: `curl ${URL_A}` }, 'Bash'),
      result(2, 'toolu_1', `fetched ${URL_A}`),
    ];
    expect(artifactsFrom(items)).toEqual([]);
  });
});
