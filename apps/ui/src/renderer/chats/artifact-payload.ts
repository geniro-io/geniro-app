import type { ItemDto as ChatItem } from '../autogenerated';
import { toolResultText } from './tool-render';
import { payloadString } from './transcript-payload';

/**
 * TWIN PARSER: apps/daemon/src/v1/agents/adapters/claude/claude.const.ts
 * (`CLAUDE_ARTIFACT_ENV`) is the daemon half — it is what makes a headless turn
 * hold the `Artifact` tool at all. This file reads what that tool then says.
 *
 * There is no generated type for either side: the tool is claude's own, its
 * result is PROSE, and the only contract is the URL shape below. A change on
 * one side has to be mirrored here by hand, which is what this block is for.
 */

/** One page this thread published to claude.ai. */
export interface RunArtifact {
  /** The artifact's id — the uuid in its URL, and its identity across turns. */
  id: string;
  url: string;
  /** Whatever the tool called it; the id when it named nothing. */
  title: string;
  /** ISO time of the row that reported it. */
  at: string;
  /** The reporting row's seq — how "the current one" is decided. */
  seq: number;
}

/**
 * The artifact URL, which is the whole wire contract.
 *
 * Read off a live tool result on 2.1.234:
 * `- Coverage Audit — Kenya, UAE, Italy — https://claude.ai/code/artifact/<uuid> — updated 2026-08-11`.
 * Matching the URL rather than the sentence around it is deliberate: the prose
 * is the CLI's to reword, the URL is what a viewer needs.
 */
const ARTIFACT_URL =
  /https:\/\/claude\.ai\/code\/artifact\/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})/gi;

/**
 * Actions that report on the ACCOUNT rather than on this thread's work.
 *
 * `list` answers with every artifact the user has ever published — five of them
 * on the account this was probed against — so folding its result in would fill
 * a chat's panel with pages that chat never touched. Probe-verified for `list`;
 * an unknown read-only action would at worst add a row that opens something
 * real, which is why this is a small deny-list rather than a guessed allow-list
 * over a vocabulary that belongs to the CLI.
 */
const ACCOUNT_WIDE_ACTIONS = new Set(['list', 'gallery']);

/** The `Artifact` tool, as its `tool_call` rows name it. */
const ARTIFACT_TOOL = 'artifact';

const titleFrom = (line: string, id: string): string => {
  // `- <title> — <url> — updated <date>`: the em-dash separators are the CLI's
  // own, and anything before the first one is the name it gave the page.
  const before = line.split('—')[0] ?? '';
  const cleaned = before.replace(/^[\s*-]+/, '').trim();
  return cleaned.length > 0 ? cleaned : id;
};

/**
 * The pages this thread published, newest first.
 *
 * Folded from the transcript rather than tracked as it streams, for the same
 * reason the task list is: a reopened chat replays its rows and has to arrive
 * at the same answer. One artifact republished across several turns collapses
 * to its NEWEST row, so "the current one" is the head of this list.
 */
export function artifactsFrom(items: readonly ChatItem[]): RunArtifact[] {
  const byToolUse = new Map<string, { action: string; title: string | null }>();
  const found = new Map<string, RunArtifact>();

  for (const item of items) {
    if (item.kind === 'tool_call') {
      const name = payloadString(item.payload, 'name') ?? '';
      if (name.toLowerCase() !== ARTIFACT_TOOL) {
        continue;
      }
      const id = payloadString(item.payload, 'id');
      if (id === null) {
        continue;
      }
      const input = (item.payload as { input?: unknown }).input;
      const bag = (input ?? {}) as Record<string, unknown>;
      byToolUse.set(id, {
        action: String(bag.action ?? '').toLowerCase(),
        title: typeof bag.title === 'string' ? bag.title : null,
      });
      continue;
    }
    if (item.kind !== 'tool_result') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    const call = id === null ? undefined : byToolUse.get(id);
    if (call === undefined || ACCOUNT_WIDE_ACTIONS.has(call.action)) {
      continue;
    }
    const text = toolResultText((item.payload as { result?: unknown }).result);
    for (const line of text.split('\n')) {
      ARTIFACT_URL.lastIndex = 0;
      let match = ARTIFACT_URL.exec(line);
      while (match !== null) {
        const artifactId = match[1]!.toLowerCase();
        const previous = found.get(artifactId);
        // Newest row wins, and the title with it: a republish renames as
        // readily as it rewrites.
        if (previous === undefined || item.seq >= previous.seq) {
          found.set(artifactId, {
            id: artifactId,
            url: match[0],
            title: call.title ?? titleFrom(line, artifactId),
            at: item.createdAt,
            seq: item.seq,
          });
        }
        match = ARTIFACT_URL.exec(line);
      }
    }
  }

  return [...found.values()].sort((a, b) => b.seq - a.seq);
}
