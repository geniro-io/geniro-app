(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const RUN = '11111111-2222-4333-8444-555555555555';
const ARTIFACT: PublishedArtifact = {
  artifactId: 'report',
  version: 2,
  title: 'Report',
  summary: null,
  key: 'k'.repeat(64),
};
const URL_WITH_KEY = 'https://pages.example.com/abc/index.html#k=KEY';

function share(partial: Partial<Share> = {}): Share {
  return {
    id: 'share-1',
    runId: RUN,
    artifactId: 'report',
    title: 'Report',
    destinationId: 'company',
    destinationName: 'Company',
    sharedVersion: 2,
    sharedBy: 'user',
    status: 'live',
    lastError: null,
    signIn: { cli: 'gcloud', label: 'Google Cloud' },
    askedByAgent: false,
    createdAt: '2026-10-15T00:00:00.000Z',
    updatedAt: '2026-10-15T00:00:00.000Z',
    ...partial,
  };
}

const AWAITING = share({
  status: 'awaiting-sign-in',
  sharedVersion: 0,
  sharedBy: 'agent',
  askedByAgent: true,
  lastError:
    'ERROR: (gcloud.storage.cp) Your current active account [me@example.com] does not have any valid credentials',
});

function signInSession(
  partial: Partial<ShareSignInSessionDto> = {},
): ShareSignInSessionDto {
  return {
    id: 'sign-in-1',
    destinationId: 'company',
    label: 'Google Cloud',
    cli: 'gcloud',
    status: 'waiting',
    lines: [],
    url: 'https://accounts.google.com/o/oauth2/auth?x=1',
    message: null,
    retried: [],
    ...partial,
  };
}

/** A fake shares client over an in-memory list, recording what it was asked. */
function fakeApi(initial: Share[] = []) {
  let shares = [...initial];
  const created: unknown[] = [];
  const api = {
    startShareSignIn: vi.fn(() => Promise.resolve(signInSession())),
    readShareSignIn: vi.fn(() => Promise.resolve(signInSession())),
    cancelShareSignIn: vi.fn(() =>
      Promise.resolve(signInSession({ status: 'cancelled' })),
    ),
    setShares: (next: Share[]) => {
      shares = next;
    },
    listShares: vi.fn(() =>
      Promise.resolve({ shares, configReceivedAt: '2026-10-15T00:00:00Z' }),
    ),
    shareArtifact: vi.fn(({ createShareDto }: { createShareDto: unknown }) => {
      created.push(createShareDto);
      shares = [share()];
      return Promise.resolve({ share: share(), url: URL_WITH_KEY });
    }),
    readShareLink: vi.fn(() => Promise.resolve({ url: URL_WITH_KEY })),
    revokeShare: vi.fn(() => {
      shares = [];
      return Promise.resolve({ status: 'revoked' as const });
    }),
  };
  return {
    api: api as unknown as Parameters<typeof useArtifactSharing>[0],
    calls: api,
    created,
  };
}

/** A socket client the spec announces share changes through. */
const announced = new Set<(event: SharesChangedEvent) => void>();
const socket = {
  onSharesChanged: (listener: (event: SharesChangedEvent) => void) => {
    announced.add(listener);
    return () => announced.delete(listener);
  },
};

function Harness({
  api,
  refreshKey = 1,
}: {
  api: ReturnType<typeof fakeApi>['api'] | null;
  refreshKey?: number;
}): React.JSX.Element {
  const sharing = useArtifactSharing(api, RUN, refreshKey, socket);
  return (
    <ArtifactShareContext.Provider value={sharing}>
      <ArtifactShareStrip artifact={ARTIFACT} />
      <ArtifactShareButton artifact={ARTIFACT} />
    </ArtifactShareContext.Provider>
  );
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

async function render(
  api: ReturnType<typeof fakeApi>['api'] | null,
  refreshKey = 1,
) {
  await act(async () => {
    root.render(<Harness api={api} refreshKey={refreshKey} />);
  });
}

const trigger = (): HTMLButtonElement | null =>
  document.querySelector('button[aria-haspopup="dialog"]');

function button(text: string): HTMLButtonElement {
  const found = [...document.querySelectorAll('button')].find(
    (b) => b.textContent?.trim() === text,
  );
  if (!found) {
    throw new Error(`no button "${text}"`);
  }
  return found;
}

async function press(element: HTMLElement): Promise<void> {
  await act(async () => {
    element.click();
  });
}

const linkField = (): HTMLInputElement | null =>
  document.querySelector('input[aria-label="Share link"]');

describe('ArtifactShareButton', () => {
  it('draws nothing where pages cannot be shared from (a phone)', async () => {
    await render(null);
    expect(trigger()).toBeNull();
  });

  it('creates a link with the current theme baked in, and shows it to copy', async () => {
    document.documentElement.style.setProperty(
      '--font-family-sans',
      'Probe Sans',
    );
    const fake = fakeApi();
    await render(fake.api);
    expect(trigger()?.getAttribute('aria-label')).toBe(
      'Share Report as a link',
    );

    await press(trigger()!);
    await press(button('Create link'));

    expect(fake.created).toEqual([
      expect.objectContaining({
        runId: RUN,
        artifactId: 'report',
        title: 'Report',
        themeVars: expect.objectContaining({ '--geniro-font': 'Probe Sans' }),
      }),
    ]);
    expect(linkField()?.value).toBe(URL_WITH_KEY);
    expect(
      document.querySelector('button[aria-label="Copy link"]'),
    ).not.toBeNull();
    // The list was re-read, so the control now reads as shared.
    expect(trigger()?.getAttribute('aria-label')).toContain('is shared');
  });

  it('re-reads the run’s shares when its refresh key changes', async () => {
    const fake = fakeApi();
    await render(fake.api, 1);
    await render(fake.api, 2);

    expect(fake.calls.listShares).toHaveBeenCalledTimes(2);
  });

  it('reads an existing link from the daemon when opened, and offers an update for a newer version', async () => {
    const fake = fakeApi([share({ sharedVersion: 1 })]);
    await render(fake.api);

    await press(trigger()!);

    expect(fake.calls.readShareLink).toHaveBeenCalledWith({
      shareId: 'share-1',
    });
    expect(linkField()?.value).toBe(URL_WITH_KEY);
    expect(button('Update link to v2')).toBeTruthy();
  });

  it('reads the Keychain once per opening, not again on every list refresh', async () => {
    const fake = fakeApi([share()]);
    await render(fake.api, 1);
    await press(trigger()!);

    await render(fake.api, 2);

    expect(fake.calls.listShares).toHaveBeenCalledTimes(2);
    expect(fake.calls.readShareLink).toHaveBeenCalledTimes(1);
  });

  it('revokes after the confirming second press', async () => {
    const fake = fakeApi([share()]);
    await render(fake.api);
    await press(trigger()!);

    await press(button('Revoke'));
    expect(fake.calls.revokeShare).not.toHaveBeenCalled();
    await press(button('Revoke link?'));

    expect(fake.calls.revokeShare).toHaveBeenCalledWith({ shareId: 'share-1' });
    expect(button('Create link')).toBeTruthy();
  });

  it('says a failed revoke may have left the link working', async () => {
    const fake = fakeApi([share()]);
    fake.calls.revokeShare.mockImplementation(() =>
      Promise.resolve({
        status: 'revoke-failed',
        detail: 'network unreachable',
      } as never),
    );
    await render(fake.api);
    await press(trigger()!);

    await press(button('Revoke'));
    await press(button('Revoke link?'));

    expect(document.body.textContent).toContain(
      'The link could not be removed: network unreachable. It may still work',
    );
  });
});

describe('a share waiting on sign-in', () => {
  it('shows the sign-in strip and button only for awaiting-sign-in, with the warning tint', async () => {
    const fake = fakeApi([AWAITING]);
    await render(fake.api);

    expect(trigger()?.getAttribute('aria-label')).toBe(
      'Report — sharing needs sign-in',
    );
    expect(trigger()?.className).toContain('text-warning');
    expect(document.body.textContent).toContain(
      'Sign-in required (gcloud) — this page is not shared yet.',
    );

    await press(trigger()!);

    const panel = document.querySelector('[data-slot="artifact-share"]');
    expect(panel?.textContent).toContain('An agent tried to share this page');
    expect(panel?.textContent).toContain('Sign-in required (gcloud)');
    // Nothing was uploaded, so there is no link to read.
    expect(fake.calls.readShareLink).not.toHaveBeenCalled();
    expect(
      panel?.querySelector('[data-slot="artifact-share-sign-in"] button')
        ?.textContent,
    ).toBe('Sign in to Google Cloud');
  });

  it('starts the destination’s sign-in from the button and shows its progress with Cancel', async () => {
    const fake = fakeApi([AWAITING]);
    await render(fake.api);
    await press(trigger()!);

    const panel = document.querySelector('[data-slot="artifact-share"]');
    const signIn = [...(panel?.querySelectorAll('button') ?? [])].find(
      (b) => b.textContent === 'Sign in to Google Cloud',
    );
    await press(signIn!);

    expect(fake.calls.startShareSignIn).toHaveBeenCalledWith({
      startShareSignInDto: { destinationId: 'company' },
    });
    expect(panel?.textContent).toContain(
      'Waiting for you to finish in the browser',
    );
    expect(document.activeElement?.textContent).toBe('Cancel');
  });

  it('keeps showing the working link when an update of a shared page has to wait on sign-in', async () => {
    const fake = fakeApi([share({ sharedVersion: 1 })]);
    fake.calls.shareArtifact.mockImplementation(() => {
      const waiting = share({ sharedVersion: 1, status: 'awaiting-sign-in' });
      fake.calls.setShares([waiting]);
      return Promise.resolve({ share: waiting, url: null } as never);
    });
    await render(fake.api);
    await press(trigger()!);
    expect(linkField()?.value).toBe(URL_WITH_KEY);

    await press(button('Update link to v2'));

    expect(linkField()?.value).toBe(URL_WITH_KEY);
    expect(document.body.textContent).toContain('Sign-in required (gcloud)');
  });

  it('a cancelled sign-in says the page was not shared and offers the button again', async () => {
    const fake = fakeApi([AWAITING]);
    await render(fake.api);
    await press(trigger()!);
    await press(button('Sign in to Google Cloud'));

    await press(button('Cancel'));
    expect(document.body.textContent).toContain(
      'Not shared — sign-in cancelled',
    );
    expect(fake.calls.shareArtifact).not.toHaveBeenCalled();

    await press(button('Dismiss'));
    expect(button('Sign in to Google Cloud')).toBeTruthy();
  });

  it('ends a sign-in the daemon forgot across a restart instead of polling it forever', async () => {
    vi.useFakeTimers();
    try {
      const fake = fakeApi([AWAITING]);
      fake.calls.readShareSignIn.mockRejectedValue(
        new Error(
          'daemon GET /v1/shares/sign-in/sign-in-1 failed (404): no sign-in',
        ),
      );
      await render(fake.api);
      await press(trigger()!);
      await press(button('Sign in to Google Cloud'));

      await act(async () => {
        await vi.advanceTimersByTimeAsync(1300);
      });
      const polls = fake.calls.readShareSignIn.mock.calls.length;
      expect(document.body.textContent).toContain(
        'Geniro restarted before this sign-in finished',
      );
      await act(async () => {
        await vi.advanceTimersByTimeAsync(5000);
      });
      expect(fake.calls.readShareSignIn).toHaveBeenCalledTimes(polls);
    } finally {
      vi.useRealTimers();
    }
  });

  it('offers no sign-in for a share that failed for another reason', async () => {
    const fake = fakeApi([
      share({
        status: 'failed',
        sharedVersion: 0,
        lastError: 'gs://company-share not found: 404.',
      }),
    ]);
    await render(fake.api);
    await press(trigger()!);

    expect(document.body.textContent).toContain(
      'Not shared: gs://company-share not found: 404.',
    );
    expect(document.body.textContent).not.toContain('Sign in to');
    expect(button('Create link')).toBeTruthy();
  });

  it('re-reads when the daemon says one of this run’s shares changed — the link appears without a press', async () => {
    const fake = fakeApi([AWAITING]);
    await render(fake.api);
    fake.calls.setShares([share()]);

    await act(async () => {
      for (const listener of announced) {
        listener({
          runId: RUN,
          shareId: 'share-1',
          status: 'live',
          title: 'Report',
          destinationName: 'Company',
          askedByAgent: true,
          signInRequested: false,
        });
      }
    });

    expect(trigger()?.getAttribute('aria-label')).toContain('is shared');
    expect(document.body.textContent).not.toContain('Sign-in required');
  });

  it('ignores another run’s share changes', async () => {
    const fake = fakeApi([AWAITING]);
    await render(fake.api);
    const before = fake.calls.listShares.mock.calls.length;

    await act(async () => {
      for (const listener of announced) {
        listener({
          runId: 'another-run',
          shareId: 'x',
          status: 'live',
          title: 'Other',
          destinationName: 'Company',
          askedByAgent: false,
          signInRequested: false,
        });
      }
    });

    expect(fake.calls.listShares).toHaveBeenCalledTimes(before);
  });
});

describe('latestShowArtifactResultSeq', () => {
  const server = `mcp__geniro-${RUN.slice(0, 8)}__`;
  const row = (seq: number, kind: string, payload: object): ItemDto =>
    ({ seq, kind, payload }) as unknown as ItemDto;

  it('rises with the result of a show_artifact call, paired by call id even when the result carries no name', () => {
    const rows = [
      row(5, 'show_artifact', {}),
      row(6, 'tool_call', { id: 'c1', name: `${server}show_artifact` }),
      // claude writes `name: null` on every result row.
      row(9, 'tool_result', { id: 'c1', name: null }),
    ];
    expect(latestShowArtifactResultSeq(rows, RUN, 5)).toBe(9);
  });

  it('ignores another tool’s result and keeps the floor', () => {
    const rows = [
      row(6, 'tool_call', { id: 'c2', name: `${server}show_chart` }),
      row(9, 'tool_result', { id: 'c2', name: null }),
    ];
    expect(latestShowArtifactResultSeq(rows, RUN, 5)).toBe(5);
  });
});
