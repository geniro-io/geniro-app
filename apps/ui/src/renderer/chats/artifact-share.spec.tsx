// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { ItemDto, Share, SharesApi } from '../autogenerated';
import { ArtifactShareButton, ArtifactShareContext } from './artifact-share';
import type { PublishedArtifact } from './published-artifact';
import {
  latestShowArtifactResultSeq,
  useArtifactSharing,
} from './use-artifact-sharing';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const RUN = '11111111-2222-4333-8444-555555555555';
const ARTIFACT: PublishedArtifact = {
  artifactId: 'report',
  version: 2,
  title: 'Report',
  summary: null,
  key: 'k'.repeat(64),
};
const URL_WITH_KEY = 'https://pages.example.com/abc/index.html#k=KEY';

function share(partial: Partial<Share> = {}): Share {
  return {
    id: 'share-1',
    runId: RUN,
    artifactId: 'report',
    title: 'Report',
    destinationId: 'company',
    destinationName: 'Company',
    sharedVersion: 2,
    sharedBy: 'user',
    status: 'live',
    lastError: null,
    createdAt: '2026-10-15T00:00:00.000Z',
    updatedAt: '2026-10-15T00:00:00.000Z',
    ...partial,
  };
}

/** A fake shares client over an in-memory list, recording what it was asked. */
function fakeApi(initial: Share[] = []) {
  let shares = [...initial];
  const created: unknown[] = [];
  const api = {
    listShares: vi.fn(() =>
      Promise.resolve({ shares, configReceivedAt: '2026-10-15T00:00:00Z' }),
    ),
    shareArtifact: vi.fn(({ createShareDto }: { createShareDto: unknown }) => {
      created.push(createShareDto);
      shares = [share()];
      return Promise.resolve({ share: share(), url: URL_WITH_KEY });
    }),
    readShareLink: vi.fn(() => Promise.resolve({ url: URL_WITH_KEY })),
    revokeShare: vi.fn(() => {
      shares = [];
      return Promise.resolve({ status: 'revoked' as const });
    }),
  };
  return {
    api: api as unknown as Pick<
      SharesApi,
      'listShares' | 'shareArtifact' | 'readShareLink' | 'revokeShare'
    >,
    calls: api,
    created,
  };
}

function Harness({
  api,
  refreshKey = 1,
}: {
  api: ReturnType<typeof fakeApi>['api'] | null;
  refreshKey?: number;
}): React.JSX.Element {
  const sharing = useArtifactSharing(api, RUN, refreshKey);
  return (
    <ArtifactShareContext.Provider value={sharing}>
      <ArtifactShareButton artifact={ARTIFACT} />
    </ArtifactShareContext.Provider>
  );
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

async function render(
  api: ReturnType<typeof fakeApi>['api'] | null,
  refreshKey = 1,
) {
  await act(async () => {
    root.render(<Harness api={api} refreshKey={refreshKey} />);
  });
}

const trigger = (): HTMLButtonElement | null =>
  document.querySelector('button[aria-haspopup="dialog"]');

function button(text: string): HTMLButtonElement {
  const found = [...document.querySelectorAll('button')].find(
    (b) => b.textContent?.trim() === text,
  );
  if (!found) {
    throw new Error(`no button "${text}"`);
  }
  return found;
}

async function press(element: HTMLElement): Promise<void> {
  await act(async () => {
    element.click();
  });
}

const linkField = (): HTMLInputElement | null =>
  document.querySelector('input[aria-label="Share link"]');

describe('ArtifactShareButton', () => {
  it('draws nothing where pages cannot be shared from (a phone)', async () => {
    await render(null);
    expect(trigger()).toBeNull();
  });

  it('creates a link with the current theme baked in, and shows it to copy', async () => {
    document.documentElement.style.setProperty(
      '--font-family-sans',
      'Probe Sans',
    );
    const fake = fakeApi();
    await render(fake.api);
    expect(trigger()?.getAttribute('aria-label')).toBe(
      'Share Report as a link',
    );

    await press(trigger()!);
    await press(button('Create link'));

    expect(fake.created).toEqual([
      expect.objectContaining({
        runId: RUN,
        artifactId: 'report',
        title: 'Report',
        themeVars: expect.objectContaining({ '--geniro-font': 'Probe Sans' }),
      }),
    ]);
    expect(linkField()?.value).toBe(URL_WITH_KEY);
    expect(
      document.querySelector('button[aria-label="Copy link"]'),
    ).not.toBeNull();
    // The list was re-read, so the control now reads as shared.
    expect(trigger()?.getAttribute('aria-label')).toContain('is shared');
  });

  it('re-reads the run’s shares when its refresh key changes', async () => {
    const fake = fakeApi();
    await render(fake.api, 1);
    await render(fake.api, 2);

    expect(fake.calls.listShares).toHaveBeenCalledTimes(2);
  });

  it('reads an existing link from the daemon when opened, and offers an update for a newer version', async () => {
    const fake = fakeApi([share({ sharedVersion: 1 })]);
    await render(fake.api);

    await press(trigger()!);

    expect(fake.calls.readShareLink).toHaveBeenCalledWith({
      shareId: 'share-1',
    });
    expect(linkField()?.value).toBe(URL_WITH_KEY);
    expect(button('Update link to v2')).toBeTruthy();
  });

  it('reads the Keychain once per opening, not again on every list refresh', async () => {
    const fake = fakeApi([share()]);
    await render(fake.api, 1);
    await press(trigger()!);

    await render(fake.api, 2);

    expect(fake.calls.listShares).toHaveBeenCalledTimes(2);
    expect(fake.calls.readShareLink).toHaveBeenCalledTimes(1);
  });

  it('revokes after the confirming second press', async () => {
    const fake = fakeApi([share()]);
    await render(fake.api);
    await press(trigger()!);

    await press(button('Revoke'));
    expect(fake.calls.revokeShare).not.toHaveBeenCalled();
    await press(button('Revoke link?'));

    expect(fake.calls.revokeShare).toHaveBeenCalledWith({ shareId: 'share-1' });
    expect(button('Create link')).toBeTruthy();
  });

  it('says a failed revoke may have left the link working', async () => {
    const fake = fakeApi([share()]);
    fake.calls.revokeShare.mockImplementation(() =>
      Promise.resolve({
        status: 'revoke-failed',
        detail: 'network unreachable',
      } as never),
    );
    await render(fake.api);
    await press(trigger()!);

    await press(button('Revoke'));
    await press(button('Revoke link?'));

    expect(document.body.textContent).toContain(
      'The link could not be removed: network unreachable. It may still work',
    );
  });
});

describe('latestShowArtifactResultSeq', () => {
  const server = `mcp__geniro-${RUN.slice(0, 8)}__`;
  const row = (seq: number, kind: string, payload: object): ItemDto =>
    ({ seq, kind, payload }) as unknown as ItemDto;

  it('rises with the result of a show_artifact call, paired by call id even when the result carries no name', () => {
    const rows = [
      row(5, 'show_artifact', {}),
      row(6, 'tool_call', { id: 'c1', name: `${server}show_artifact` }),
      // claude writes `name: null` on every result row.
      row(9, 'tool_result', { id: 'c1', name: null }),
    ];
    expect(latestShowArtifactResultSeq(rows, RUN, 5)).toBe(9);
  });

  it('ignores another tool’s result and keeps the floor', () => {
    const rows = [
      row(6, 'tool_call', { id: 'c2', name: `${server}show_chart` }),
      row(9, 'tool_result', { id: 'c2', name: null }),
    ];
    expect(latestShowArtifactResultSeq(rows, RUN, 5)).toBe(5);
  });
});
