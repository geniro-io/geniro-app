import { AttachmentMediaType } from '../autogenerated';

/**
 * One image attached to a user message, as read back out of the item payload.
 */
export interface MessageAttachment {
  id: string;
  mediaType: AttachmentMediaType;
}

const MEDIA_TYPES: string[] = Object.values(AttachmentMediaType);

/**
 * TWIN PARSER: apps/daemon/src/v1/agents/chat.types.ts `AttachmentWireSchema`
 * (the shape) and `ChatService.sendMessage` (which writes it into the payload).
 *
 * A message item's `payload` is `z.unknown()` on the wire — deliberately, since
 * every item kind carries a different shape — so the generated client types it
 * as `any` and no schema check reaches this side. Attachments are therefore
 * projected defensively here, exactly as the approval card projects its own
 * payload. A change to the daemon's attachment row MUST be mirrored here.
 *
 * Anything malformed is dropped rather than rendered: a bad row would otherwise
 * become a broken-image box in the transcript.
 */
export function messageAttachments(payload: unknown): MessageAttachment[] {
  if (!payload || typeof payload !== 'object' || !('images' in payload)) {
    return [];
  }
  const images = (payload as { images?: unknown }).images;
  if (!Array.isArray(images)) {
    return [];
  }
  return images.flatMap((image): MessageAttachment[] => {
    if (!image || typeof image !== 'object') {
      return [];
    }
    const { id, mediaType } = image as { id?: unknown; mediaType?: unknown };
    if (typeof id !== 'string' || typeof mediaType !== 'string') {
      return [];
    }
    return MEDIA_TYPES.includes(mediaType)
      ? [{ id, mediaType: mediaType as AttachmentMediaType }]
      : [];
  });
}
