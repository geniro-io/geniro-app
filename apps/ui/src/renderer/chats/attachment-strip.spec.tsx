// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { AttachmentMediaType } from '../autogenerated';
import { AttachmentStrip } from './attachment-strip';
import type { StagedAttachment } from './use-attachments';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

const staged = (name: string): StagedAttachment => ({
  key: `k-${name}`,
  mediaType: AttachmentMediaType.ImagePng,
  data: 'AAA',
  preview: `data:image/png;base64,${name}`,
  name,
  owner: null,
});

function render(onRemove = vi.fn()): ReturnType<typeof vi.fn> {
  act(() => {
    root.render(
      <AttachmentStrip attachments={[staged('one.png')]} onRemove={onRemove} />,
    );
  });
  return onRemove;
}

describe('the images staged on the composer', () => {
  it('opens the one being sent, at a size that can be checked', () => {
    // The strip's squares are 64px `object-cover`, and two screenshots pasted
    // in a row can look identical in it — so "which of these am I about to
    // send" is unanswerable without opening one.
    render();

    act(() => {
      container
        .querySelector('[data-slot="zoomable-image"]')!
        .dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });

    expect(
      document.body
        .querySelector('[data-slot="image-viewer-image"]')
        ?.getAttribute('src'),
    ).toBe('data:image/png;base64,one.png');
  });

  it('still removes on the ✕, which now sits over a pressable image', () => {
    // The ✕ is absolutely positioned over the thumbnail, which is now a button
    // of its own. The two must stay SIBLINGS: nested, the ✕ would sit inside
    // the opener and every attempt to take an image back would open it
    // full-screen instead — and a nested button is invalid markup besides.
    const onRemove = render();

    act(() => {
      container
        .querySelector<HTMLElement>('[aria-label="Remove one.png"]')!
        .dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });

    expect(onRemove).toHaveBeenCalledWith('k-one.png');
    expect(
      document.body.querySelector('[data-slot="image-viewer-image"]'),
    ).toBeNull();
  });
});
