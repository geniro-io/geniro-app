import { Globe } from 'lucide-react';

import type { SendMessageDtoImagesInner } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Card } from '../components/ui/card';
import { cn } from '../components/ui/utils';
import { HazardAck, HazardWarning, useHazardGate } from './text-hazard-gate';
import { recordOf } from './tool-result-text';
import { useOneShotVerdict } from './use-one-shot-verdict';

/** The `optionId` the middle button sends: every host for this chat until Geniro quits. */
const SESSION_OPTION_ID = 'session';

/** What the new-host card asks: which agent wants which address. */
export interface BrowserHostRequest {
  host: string;
  url: string;
  memberName: string;
}

function readString(value: unknown): string | null {
  return typeof value === 'string' && value.trim() !== '' ? value : null;
}

/**
 * The request on a `browser_host` row's `input`, or null when any of the three
 * is missing — the caller then draws the permission body, which is still
 * answerable.
 *
 * TWIN PARSER: `BrowserHostCardInput` in `apps/daemon/src/v1/agents/chat.types.ts`,
 * filled by `BrowserBroker` (`services/browser.broker.ts`) when it asks. A key
 * renamed on either side must be renamed on both.
 */
export function readBrowserHostRequest(
  input: unknown,
): BrowserHostRequest | null {
  const record = recordOf(input);
  const host = readString(record?.host);
  const url = readString(record?.url);
  const memberName = readString(record?.memberName);
  return host === null || url === null || memberName === null
    ? null
    : { host, url, memberName };
}

/**
 * An agent's first open of a host in this chat, under review: Approve allows
 * that host for the chat, Allow for this session every host until Geniro quits,
 * Deny refuses. The agent was told to wait and is woken by the answer, so the
 * card stands across turns.
 */
export function BrowserHostCard({
  request,
  verdict,
  verdictOption = null,
  expired = false,
  onRespond,
}: {
  request: BrowserHostRequest;
  /** null while pending; the user's answer once the verdict item arrived. */
  verdict: boolean | null;
  /** The label of the option the settled verdict picked, or null. */
  verdictOption?: string | null;
  /** The turn ended before an answer — no verdict can apply anymore. */
  expired?: boolean;
  onRespond: (
    allow: boolean,
    answer?: string,
    images?: SendMessageDtoImagesInner[],
    optionId?: string,
  ) => void;
}): React.JSX.Element {
  const { sending, respond } = useOneShotVerdict(verdict, expired, onRespond);
  const gate = useHazardGate(
    `${request.memberName} ${request.host} ${request.url}`,
  );
  return (
    <Card
      data-slot="browser-host-card"
      className="flex min-w-0 flex-col gap-2.5 border-primary/40 p-3">
      <div className="flex min-w-0 items-center gap-2">
        <Globe aria-hidden="true" className="size-4 shrink-0 text-primary" />
        <span className="min-w-0 flex-1 text-sm font-medium break-words">
          {request.memberName} wants to open {request.host} in the browser
        </span>
      </div>
      <HazardWarning hazards={gate.hazards} subject="this address" />
      <p className="m-0 min-w-0 font-mono text-xs break-all text-muted-foreground">
        {request.url}
      </p>
      {expired && verdict === null ? (
        <p className="text-xs text-muted-foreground">
          ⏱ expired — the turn ended before an answer
        </p>
      ) : sending ? (
        <p className="text-xs text-muted-foreground">Sending…</p>
      ) : verdict !== null ? (
        <p
          className={cn(
            'text-xs',
            verdict ? 'text-success' : 'text-destructive',
          )}>
          {verdict ? '✓ approved' : '✗ denied'}
          {verdictOption === null ? null : ` — ${verdictOption}`}
        </p>
      ) : (
        <div className="flex flex-col gap-2">
          {gate.hazards.gates ? (
            <HazardAck
              id={gate.ackId}
              checked={gate.acknowledged}
              onCheckedChange={gate.setAcknowledged}
            />
          ) : null}
          <div className="flex flex-wrap gap-2">
            <Button
              type="button"
              disabled={gate.blocksApprove}
              onClick={() => respond(true)}>
              Approve
            </Button>
            <Button
              type="button"
              variant="outline"
              title="Lets this agent open any address in this chat until Geniro quits"
              disabled={gate.blocksApprove}
              onClick={() =>
                respond(true, undefined, undefined, SESSION_OPTION_ID)
              }>
              Allow for this session
            </Button>
            <Button
              type="button"
              variant="outline"
              onClick={() => respond(false)}>
              Deny
            </Button>
          </div>
        </div>
      )}
    </Card>
  );
}
