// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { stubResizeObserver } from '../__tests__/stub-resize-observer';
import type { ItemDto as ChatItem } from '../autogenerated';
import { BrowserPaneContext } from './browser/browser-pane-context';
import { BrowserScreenshotCard } from './browser-screenshot-card';
import { LocalImageLoaderContext } from './local-image-loader';
import type { ToolPair } from './transcript-groups';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

stubResizeObserver();

const RUN_ID = 'abc12345-0000-0000-0000-000000000000';

function item(kind: 'tool_call' | 'tool_result', payload: unknown): ChatItem {
  return {
    id: `i-${Math.random()}`,
    runId: RUN_ID,
    memberId: 'orch',
    seq: 1,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function pair(result?: { text: string; isError?: boolean }): ToolPair {
  return {
    call: item('tool_call', {
      id: 'c1',
      name: 'mcp__geniro-abc12345__browser_screenshot',
      input: { tab: 't2' },
    }),
    result:
      result === undefined
        ? null
        : item('tool_result', {
            id: 'c1',
            result: [{ type: 'text', text: result.text }],
            isError: result.isError ?? false,
          }),
  };
}

const SAVED =
  'Screenshot taken.\nSaved screenshot: /data/attachments/r1/shot.png';

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

async function draw(
  source: ToolPair,
  options: {
    load?: (path: string) => Promise<string>;
    pane?: { openPane: (tab: string | null) => void } | null;
  } = {},
): Promise<void> {
  await act(async () => {
    root.render(
      <LocalImageLoaderContext.Provider value={options.load ?? null}>
        <BrowserPaneContext.Provider
          value={
            options.pane == null
              ? null
              : {
                  openPane: options.pane.openPane,
                  openUrl: vi.fn(),
                  isOpen: () => false,
                }
          }>
          <BrowserScreenshotCard pair={source} />
        </BrowserPaneContext.Provider>
      </LocalImageLoaderContext.Provider>,
    );
  });
  await act(async () => {});
}

describe('a browser screenshot card', () => {
  it('draws the saved screenshot through the local image loader', async () => {
    const asked: string[] = [];
    await draw(pair({ text: SAVED }), {
      load: async (path) => {
        asked.push(path);
        return 'data:image/png;base64,AAAA';
      },
    });
    expect(asked).toEqual(['/data/attachments/r1/shot.png']);
    const image = container.querySelector<HTMLImageElement>(
      '[data-slot="browser-screenshot-image"]',
    );
    expect(image?.getAttribute('src')).toBe('data:image/png;base64,AAAA');
    expect(container.textContent).toContain('Screenshot of t2');
  });

  it('releases the picture when the card folds', async () => {
    await draw(pair({ text: SAVED }), {
      load: async () => 'data:image/png;base64,AAAA',
    });
    const fold = container.querySelector<HTMLButtonElement>(
      'button[aria-expanded]',
    )!;
    await act(async () => fold.click());
    expect(
      container.querySelector('[data-slot="browser-screenshot-image"]'),
    ).toBeNull();
  });

  it('offers Show in browser on its tab, and nothing without a pane', async () => {
    const openPane = vi.fn();
    await draw(pair({ text: SAVED }), {
      load: async () => 'data:image/png;base64,AAAA',
      pane: { openPane },
    });
    const show = [...container.querySelectorAll('button')].find(
      (button) => button.textContent === 'Show in browser',
    );
    act(() => show!.click());
    expect(openPane).toHaveBeenCalledWith('t2');

    await draw(pair({ text: SAVED }), {
      load: async () => 'data:image/png;base64,AAAA',
    });
    expect(container.textContent).not.toContain('Show in browser');
  });

  it('says it is taking the screenshot while the call has no result', async () => {
    await draw(pair(), { load: vi.fn() });
    expect(container.textContent).toContain('Taking a screenshot');
  });

  it('shows the reason a screenshot failed and loads nothing', async () => {
    const load = vi.fn();
    await draw(
      pair({ text: 'The browser did not answer within 20 s.', isError: true }),
      { load },
    );
    expect(container.textContent).toContain(
      'Screenshot failed: The browser did not answer within 20 s.',
    );
    expect(load).not.toHaveBeenCalled();
  });

  it('shows a broken tile when the file cannot be read', async () => {
    await draw(pair({ text: SAVED }), {
      load: async () => {
        throw new Error('gone');
      },
    });
    expect(container.textContent).toContain('could not be read');
  });
});
