import type { Meta, StoryObj } from '@storybook/react-vite';

import type { ItemDto as ChatItem } from '../autogenerated';
import { BrowserPaneContext } from './browser/browser-pane-context';
import { BrowserScreenshotCard } from './browser-screenshot-card';
import { LocalImageLoaderContext } from './local-image-loader';
import type { ToolPair } from './transcript-groups';

const PICTURE =
  'data:image/svg+xml;utf8,' +
  encodeURIComponent(
    '<svg xmlns="http://www.w3.org/2000/svg" width="640" height="400"><rect width="640" height="400" fill="#888"/></svg>',
  );

function row(kind: 'tool_call' | 'tool_result', payload: unknown): ChatItem {
  return {
    id: `${kind}-${Math.random()}`,
    runId: 'abc12345-0000-0000-0000-000000000000',
    memberId: null,
    seq: 1,
    kind,
    role: null,
    payload,
    createdAt: '2026-11-11T10:00:00.000Z',
  };
}

function pair(text: string | null, isError = false): ToolPair {
  return {
    call: row('tool_call', {
      id: 'c1',
      name: 'mcp__geniro-abc12345__browser_screenshot',
      input: { tab: 't2' },
    }),
    result:
      text === null
        ? null
        : row('tool_result', {
            id: 'c1',
            result: [{ type: 'text', text }],
            isError,
          }),
  };
}

const meta = {
  title: 'Chats/BrowserScreenshotCard',
  component: BrowserScreenshotCard,
  args: {
    pair: pair(
      'Screenshot taken.\nSaved screenshot: /data/attachments/shot.png',
    ),
  },
  decorators: [
    (story) => (
      <LocalImageLoaderContext.Provider value={() => Promise.resolve(PICTURE)}>
        <BrowserPaneContext.Provider
          value={{ openPane: () => {}, openUrl: () => {} }}>
          <div className="w-[560px] bg-background p-4">{story()}</div>
        </BrowserPaneContext.Provider>
      </LocalImageLoaderContext.Provider>
    ),
  ],
} satisfies Meta<typeof BrowserScreenshotCard>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Saved: Story = {};

export const Taking: Story = { args: { pair: pair(null) } };

export const Failed: Story = {
  args: { pair: pair('The browser did not answer within 20 s.', true) },
};
