// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import type { BlockStatus } from './block-shell';
import { BrowserPaneContext } from './browser/browser-pane-context';
import { browserToolEntryOf, BrowserToolRow } from './browser-tool-row';
import type { ToolPair } from './transcript-groups';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const RUN_ID = 'abc12345-0000-0000-0000-000000000000';
const SERVER = 'geniro-abc12345';

function item(kind: 'tool_call' | 'tool_result', payload: unknown): ChatItem {
  return {
    id: `i-${Math.random()}`,
    runId: RUN_ID,
    memberId: 'orch',
    seq: 1,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function pair(
  tool: string,
  input: unknown,
  result?: { text: string; isError?: boolean },
): ToolPair {
  return {
    call: item('tool_call', {
      id: 'c1',
      name: `mcp__${SERVER}__${tool}`,
      input,
    }),
    result:
      result === undefined
        ? null
        : item('tool_result', {
            id: 'c1',
            result: result.text,
            isError: result.isError ?? false,
          }),
  };
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

const openPane = vi.fn();

function draw(
  source: ToolPair,
  options: { status?: BlockStatus; pane?: boolean } = {},
): void {
  const entry = browserToolEntryOf(source);
  if (entry === null) {
    throw new Error('expected a browser entry');
  }
  act(() =>
    root.render(
      <BrowserPaneContext.Provider
        value={
          options.pane === false
            ? null
            : { openPane, openUrl: vi.fn(), isOpen: () => false }
        }>
        <BrowserToolRow entry={entry} status={options.status ?? 'done'} />
      </BrowserPaneContext.Provider>,
    ),
  );
}

function line(): string {
  return (container.textContent ?? '').replace(/\s+/g, ' ').trim();
}

const showButton = (): HTMLButtonElement | undefined =>
  [...container.querySelectorAll('button')].find(
    (button) => button.textContent === 'Show in browser',
  );

describe('a browser tool row', () => {
  it('names the host it opened and hides Show in browser without a pane', () => {
    const opened = pair(
      'browser_open',
      { url: 'https://staging.acme.dev/login?x=1' },
      { text: 'Opened.\nTab: t1' },
    );
    draw(opened);
    expect(line()).toContain('Opened staging.acme.dev');
    expect(showButton()).toBeDefined();

    draw(opened, { pane: false });
    expect(line()).toContain('Opened staging.acme.dev');
    expect(showButton()).toBeUndefined();
  });

  it('opens the pane on the tab the result named', () => {
    openPane.mockClear();
    draw(
      pair(
        'browser_open',
        { url: 'http://localhost:5173' },
        { text: 'Opened.\nTab: t3' },
      ),
    );
    act(() => showButton()!.click());
    expect(openPane).toHaveBeenCalledWith('t3');
  });

  it('offers no Show in browser on a close, whether it worked or not', () => {
    draw(pair('browser_close', { tab: 't2' }, { text: 'Closed.' }));
    expect(line()).toContain('Closed tab t2');
    expect(showButton()).toBeUndefined();

    draw(
      pair(
        'browser_close',
        { tab: 't2' },
        { text: 'no such tab', isError: true },
      ),
      {
        status: 'error',
      },
    );
    expect(showButton()).toBeUndefined();

    draw(
      pair(
        'browser_navigate',
        { tab: 't1', url: 'https://acme.dev/a' },
        { text: 'ok' },
      ),
    );
    expect(showButton()).toBeDefined();
  });

  it.each([
    [
      'browser_navigate',
      { tab: 't1', url: 'https://acme.dev/a' },
      'Navigated to acme.dev',
    ],
    ['browser_snapshot', { tab: 't1' }, 'Read the page'],
    ['browser_click', { tab: 't1', ref: 'e12' }, 'Clicked e12'],
    [
      'browser_type',
      { tab: 't1', ref: 'e7', text: 'hunter2' },
      'Typed into e7',
    ],
    ['browser_press', { tab: 't1', key: 'Enter' }, 'Pressed Enter'],
    ['browser_tabs', {}, 'Listed tabs'],
    ['browser_close', { tab: 't2' }, 'Closed tab t2'],
    [
      'browser_label_tab',
      { tab: 't2', name: 'API docs', color: 'teal' },
      'Labelled tab t2',
    ],
    ['browser_get_cookies', {}, 'Read cookies'],
    ['browser_clear_cookies', {}, 'Cleared cookies'],
  ])('words %s as a short sentence', (tool, input, words) => {
    draw(pair(tool, input, { text: 'ok' }));
    expect(line()).toContain(words);
  });

  it('counts the cookies set and never shows a value or the typed text', () => {
    draw(
      pair(
        'browser_set_cookies',
        {
          cookies: [
            { name: 'a', value: '‹cookie›', domain: 'acme.dev' },
            { name: 'b', value: '‹cookie›', domain: 'acme.dev' },
            { name: 'c', value: '‹cookie›', domain: 'acme.dev' },
          ],
        },
        { text: 'Set.' },
      ),
    );
    expect(line()).toContain('Set 3 cookies (‹cookie› values hidden)');

    draw(
      pair(
        'browser_type',
        { tab: 't1', ref: 'e7', text: 'hunter2' },
        { text: 'ok' },
      ),
    );
    expect(line()).not.toContain('hunter2');
  });

  it('says a call waits for the user’s approval instead of claiming it opened', () => {
    draw(
      pair(
        'browser_open',
        { url: 'https://new.example/x' },
        {
          text: 'Waiting for the user to approve new.example; you will be woken with the result. Do not retry this call.',
        },
      ),
    );
    expect(line()).toContain('Asked to open new.example');
    expect(line()).toContain('waiting for approval');
    expect(line()).not.toContain('Opened');
  });

  it('shows a refusal’s reason on a failed call and a spinner on a running one', () => {
    draw(
      pair(
        'browser_click',
        { tab: 't1', ref: 'e12' },
        { text: 'ref e12 is gone — take a new snapshot', isError: true },
      ),
      { status: 'error' },
    );
    expect(line()).toContain('Clicked e12');
    expect(line()).toContain('ref e12 is gone — take a new snapshot');

    draw(pair('browser_click', { tab: 't1', ref: 'e12' }), {
      status: 'running',
    });
    expect(line()).toContain('Clicking e12');
    expect(showButton()).toBeUndefined();
  });

  it('is not a row for a tool of another server or a name it does not know', () => {
    expect(
      browserToolEntryOf({
        call: item('tool_call', {
          id: 'c1',
          name: 'mcp__geniro-feedbeef__browser_open',
          input: { url: 'https://a.b' },
        }),
        result: null,
      }),
    ).toBeNull();
    expect(
      browserToolEntryOf(pair('browser_screenshot', { tab: 't1' })),
    ).toBeNull();
  });
});
