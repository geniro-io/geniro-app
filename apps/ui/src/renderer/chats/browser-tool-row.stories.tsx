import type { Meta, StoryObj } from '@storybook/react-vite';

import type { ItemDto as ChatItem } from '../autogenerated';
import { BrowserPaneContext } from './browser/browser-pane-context';
import { browserToolEntryOf, BrowserToolRow } from './browser-tool-row';

const RUN_ID = 'abc12345-0000-0000-0000-000000000000';

function row(kind: 'tool_call' | 'tool_result', payload: unknown): ChatItem {
  return {
    id: `${kind}-${Math.random()}`,
    runId: RUN_ID,
    memberId: null,
    seq: 1,
    kind,
    role: null,
    payload,
    createdAt: '2026-11-11T10:00:00.000Z',
  };
}

function entryOf(
  tool: string,
  input: unknown,
  text = 'Done.\nTab: t1',
): NonNullable<ReturnType<typeof browserToolEntryOf>> {
  const entry = browserToolEntryOf({
    call: row('tool_call', {
      id: 'c1',
      name: `mcp__geniro-abc12345__${tool}`,
      input,
    }),
    result: row('tool_result', { id: 'c1', result: text, isError: false }),
  });
  if (entry === null) {
    throw new Error(`${tool} is not a browser tool`);
  }
  return entry;
}

const meta = {
  title: 'Chats/BrowserToolRow',
  component: BrowserToolRow,
  args: {
    status: 'done',
    entry: entryOf('browser_open', { url: 'https://staging.acme.dev/login' }),
  },
  decorators: [
    (story) => (
      <BrowserPaneContext.Provider
        value={{ openPane: () => {}, openUrl: () => {}, isOpen: () => false }}>
        <div className="w-[560px] bg-background p-4">{story()}</div>
      </BrowserPaneContext.Provider>
    ),
  ],
} satisfies Meta<typeof BrowserToolRow>;

export default meta;
type Story = StoryObj<typeof meta>;

