import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem, ItemKind } from '../autogenerated';
import { NO_CALL_ANSWER_PAIRS, pairCallAnswers } from './call-answers';

function row(
  id: string,
  seq: number,
  kind: ItemKind,
  payload: Record<string, unknown>,
): ChatItem {
  return {
    id,
    runId: 'run-1',
    memberId: 'orch',
    seq,
    kind,
    role: null,
    payload,
    createdAt: new Date(0).toISOString(),
  };
}

describe('pairCallAnswers', () => {
  it('pairs each question of one call with the answer written after it, in order', () => {
    const pairs = pairCallAnswers([
      row('a2', 4, 'call_answer', {
        callId: 'call-1',
        outcome: 'answered',
        answer: 'Blue',
      }),
      row('q1', 1, 'call_question', { callId: 'call-1' }),
      row('a1', 2, 'call_answer', {
        callId: 'call-1',
        outcome: 'answered',
        answer: 'Red',
      }),
      row('q2', 3, 'call_question', { callId: 'call-1' }),
    ]);
    expect(pairs.byQuestion.get('q1')).toEqual({
      outcome: 'answered',
      answer: 'Red',
      noAnswer: null,
    });
    expect(pairs.byQuestion.get('q2')).toEqual({
      outcome: 'answered',
      answer: 'Blue',
      noAnswer: null,
    });
    expect([...pairs.shownOnQuestion].sort()).toEqual(['a1', 'a2']);
  });

  it('never takes a message_agent message, delivered or held, as an answer', () => {
    const pairs = pairCallAnswers([
      row('q1', 1, 'call_question', { callId: 'call-1' }),
      row('m1', 2, 'call_answer', {
        callId: 'call-1',
        outcome: 'message',
        message: 'faster',
      }),
      row('m2', 3, 'call_answer', {
        callId: 'call-1',
        outcome: 'undelivered',
        message: 'stop',
      }),
    ]);
    expect(pairs).toBe(NO_CALL_ANSWER_PAIRS);
  });

  it('pairs an unanswered question with the row that said why', () => {
    const pairs = pairCallAnswers([
      row('q1', 1, 'call_question', { callId: 'call-1' }),
      row('t1', 2, 'call_answer', { callId: 'call-1', outcome: 'timeout' }),
    ]);
    expect(pairs.byQuestion.get('q1')).toEqual({
      outcome: 'timeout',
      answer: null,
      noAnswer: null,
    });
  });

  it('leaves an answer whose question is not loaded unpaired', () => {
    expect(
      pairCallAnswers([
        row('a1', 2, 'call_answer', {
          callId: 'call-1',
          outcome: 'answered',
          answer: 'Red',
        }),
      ]),
    ).toBe(NO_CALL_ANSWER_PAIRS);
  });

  it('puts the row saying no turn was left to answer on its question, with the answer row', () => {
    const pairs = pairCallAnswers([
      row('q1', 1, 'call_question', { callId: 'call-8' }),
      row('o1', 2, 'system', {
        severity: 'info',
        callId: 'call-2',
        message:
          'Epilogue asked a question in call-8 and no turn of this agent was left to answer it, so it goes on without an answer.',
        orphanQuestion: {
          callId: 'call-8',
          callee: 'Epilogue',
          calleeNodeId: 'epilogue',
          outcome: 'continues',
        },
      }),
      row('a1', 3, 'call_answer', { callId: 'call-8', outcome: 'orphaned' }),
    ]);
    expect(pairs.byQuestion.get('q1')).toEqual({
      outcome: 'orphaned',
      answer: null,
      noAnswer: 'continues',
    });
    expect([...pairs.shownOnQuestion].sort()).toEqual(['a1', 'o1']);
  });

  it('puts the row saying no turn was left to answer on its question when the answer row came first', () => {
    const pairs = pairCallAnswers([
      row('q1', 1, 'call_question', { callId: 'call-8' }),
      row('a1', 2, 'call_answer', { callId: 'call-8', outcome: 'orphaned' }),
      row('o1', 3, 'system', {
        severity: 'info',
        orphanQuestion: {
          callId: 'call-8',
          callee: 'Epilogue',
          calleeNodeId: 'epilogue',
          outcome: 'stopped',
        },
      }),
    ]);
    expect(pairs.byQuestion.get('q1')).toEqual({
      outcome: 'orphaned',
      answer: null,
      noAnswer: 'stopped',
    });
    expect([...pairs.shownOnQuestion].sort()).toEqual(['a1', 'o1']);
  });

  it('never puts the row saying no turn was left to answer on a question that was answered', () => {
    const pairs = pairCallAnswers([
      row('q1', 1, 'call_question', { callId: 'call-8' }),
      row('a1', 2, 'call_answer', {
        callId: 'call-8',
        outcome: 'answered',
        answer: 'Red',
      }),
      row('o1', 3, 'system', {
        severity: 'info',
        orphanQuestion: {
          callId: 'call-8',
          callee: 'Epilogue',
          calleeNodeId: 'epilogue',
          outcome: 'stopped',
        },
      }),
    ]);
    expect(pairs.byQuestion.get('q1')?.outcome).toBe('answered');
    expect(pairs.shownOnQuestion.has('o1')).toBe(false);
  });

  it('reads a stopped callee from a row written before the orphan keys', () => {
    const pairs = pairCallAnswers([
      row('q1', 1, 'call_question', { callId: 'call-8' }),
      row('o1', 2, 'system', {
        severity: 'info',
        message:
          'Epilogue was stopped: it asked a question in call-8 and no turn of this agent was left to answer it.',
      }),
    ]);
    expect(pairs.byQuestion.get('q1')?.noAnswer).toBe('stopped');
    expect(pairs.shownOnQuestion.has('o1')).toBe(true);
  });

  it('leaves the row saying no turn was left to answer on its own when its question is not loaded', () => {
    expect(
      pairCallAnswers([
        row('o1', 2, 'system', {
          severity: 'info',
          orphanQuestion: {
            callId: 'call-8',
            callee: 'Epilogue',
            calleeNodeId: 'epilogue',
            outcome: 'continues',
          },
        }),
        row('a1', 3, 'call_answer', { callId: 'call-8', outcome: 'orphaned' }),
      ]),
    ).toBe(NO_CALL_ANSWER_PAIRS);
  });
});
