import { createContext } from 'react';

import type { ItemDto as ChatItem } from '../autogenerated';
import { payloadString } from './transcript-payload';

/** What became of a question a callee put to its caller. */
export interface PairedCallAnswer {
  outcome: 'answered' | 'timeout' | 'orphaned' | 'undelivered';
  answer: string | null;
}

/** Each loaded question's answer row, and the answer rows a question card now shows. */
export interface CallAnswerPairs {
  /** By the `call_question` row's id. */
  byQuestion: ReadonlyMap<string, PairedCallAnswer>;
  /** The `call_answer` rows drawn on their question's card instead of on their own. */
  shownOnQuestion: ReadonlySet<string>;
}

export const NO_CALL_ANSWER_PAIRS: CallAnswerPairs = {
  byQuestion: new Map(),
  shownOnQuestion: new Set(),
};

function answerOutcomeOf(item: ChatItem): PairedCallAnswer['outcome'] | null {
  const outcome = payloadString(item.payload, 'outcome');
  if (
    outcome === 'answered' ||
    outcome === 'timeout' ||
    outcome === 'orphaned'
  ) {
    return outcome;
  }
  return outcome === 'undelivered' &&
    payloadString(item.payload, 'message') === null
    ? 'undelivered'
    : null;
}

/**
 * Pairs every loaded `call_question` with the answer row that settled it: the
 * first answer of the same call written after it and before the call's next
 * question. A `message_agent` message is never an answer.
 */
export function pairCallAnswers(rows: readonly ChatItem[]): CallAnswerPairs {
  const open = new Map<string, string>();
  const byQuestion = new Map<string, PairedCallAnswer>();
  const shownOnQuestion = new Set<string>();
  for (const item of [...rows].sort((a, b) => a.seq - b.seq)) {
    const callId = payloadString(item.payload, 'callId');
    if (callId === null) {
      continue;
    }
    if (item.kind === 'call_question') {
      open.set(callId, item.id);
      continue;
    }
    if (item.kind !== 'call_answer') {
      continue;
    }
    const outcome = answerOutcomeOf(item);
    const questionId = open.get(callId);
    if (outcome === null || questionId === undefined) {
      continue;
    }
    open.delete(callId);
    byQuestion.set(questionId, {
      outcome,
      answer: payloadString(item.payload, 'answer'),
    });
    shownOnQuestion.add(item.id);
  }
  return byQuestion.size === 0
    ? NO_CALL_ANSWER_PAIRS
    : { byQuestion, shownOnQuestion };
}

export const CallAnswerPairsContext =
  createContext<CallAnswerPairs>(NO_CALL_ANSWER_PAIRS);
