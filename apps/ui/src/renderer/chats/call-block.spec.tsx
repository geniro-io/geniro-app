describe('an earlier call of a continued conversation', () => {
  /** A Poet conversation continued once: [pointer, card]. */
  function continued(): ReturnType<typeof groupTranscript> {
    return groupTranscript([
      item(
        'call_started',
        {
          callId: 'call-1',
          calleeNodeId: 'poet',
          mode: 'sync',
          message: 'Write a haiku about the sea.',
          title: 'Sea haiku',
        },
        'orch',
      ),
      item(
        'status',
        { status: 'completed', nodeId: 'poet', callId: 'call-1' },
        'poet',
      ),
      item(
        'call_started',
        {
          callId: 'call-2',
          calleeNodeId: 'poet',
          mode: 'sync',
          message: 'Now one about mountains.',
          thread: 'call-1',
        },
        'orch',
      ),
      item(
        'status',
        { status: 'running', nodeId: 'poet', callId: 'call-2' },
        'poet',
      ),
    ]);
  }

  it('names the call where it was made and takes the reader to the card', () => {
    // REPORTED: keep writing to the same agent and the card moves to the newest
    // call, leaving an empty place in the history where it had been.
    const [pointer, card] = continued();
    if (card?.type !== 'call-block') {
      throw new Error('expected the card second');
    }
    const revealed: string[] = [];
    act(() =>
      root.render(
        <RevealCallBlockContext.Provider value={(id) => revealed.push(id)}>
          <TranscriptEntryView entry={pointer!} nodes={NODES} />
          <TranscriptEntryView entry={card} nodes={NODES} />
        </RevealCallBlockContext.Provider>,
      ),
    );
    const row = container.querySelector('[data-role="call-continued"]');
    expect(row?.textContent).toContain('Sea haiku');
    expect(row?.textContent).toContain('Orchestrator → Poet');
    expect(row?.textContent).toContain('continued below');
    // The brief is the card's to show, not the pointer's.
    expect(row?.textContent).not.toContain('Write a haiku');

    act(() => row!.querySelector('button')!.click());

    expect(revealed).toEqual([card.id]);
    // …and the id it hands over is the one the card can be found by.
    expect(
      container.querySelector(
        `[data-role="call-block"][data-call-block="${card.id}"]`,
      ),
    ).not.toBeNull();
  });

  it('is a plain line, not a dead control, where nothing can reveal the card', () => {
    const [pointer] = continued();
    act(() =>
      root.render(<TranscriptEntryView entry={pointer!} nodes={NODES} />),
    );
    const row = container.querySelector('[data-role="call-continued"]');
    expect(row?.textContent).toContain('continued below');
    expect(row?.querySelector('button')).toBeNull();
  });
});

