  describe('the callee’s context ring', () => {
    /**
     * The ring's reading, off its accessible NAME — which is where the figures
     * are (the arc itself frames no glyphs, deliberately), so it is also the
     * only place a spec can read them.
     */
    function ringLabel(): string | null {
      return (
        container
          .querySelector('[data-slot="call-summary-context"]')
          ?.querySelector('[aria-label]')
          ?.getAttribute('aria-label') ?? null
      );
    }

    /** Render the block with a resolver standing in for `Chats`'s own. */
    function renderWith(reading: CalleeContext | null): void {
      act(() =>
        root.render(
          <CalleeContextResolverContext.Provider
            value={reading === null ? null : () => reading}>
            <CallBlock block={makeBlock()} nodes={NODES} />
          </CalleeContextResolverContext.Provider>,
        ),
      );
    }

    it('draws while the call is STILL RUNNING, with no settled turn to fold', () => {
      // THE REPORTED DEFECT. `makeBlock` is a call in flight: a `call_started`,
      // a running status and one streamed message, and no `turn_complete` —
      // which is the only row `callBlockContext` can read. So the band drew no
      // ring for the whole of every call and drew one the instant it settled,
      // measured on a live cursor call at 46 seconds of nothing.
      renderWith({ contextTokens: 80_414, contextWindowTokens: 200_000 });

      expect(
        container.querySelector('[data-slot="call-summary-context"]'),
      ).not.toBeNull();
    });

    it('draws NOTHING with no resolver — the block folds only settled turns', () => {
      // The control case, and what the two above would look like if the
      // provider were dropped: outside `ChatProviders` there is no source, and
      // a running call's own rows carry no reading yet.
      renderWith(null);

      expect(
        container.querySelector('[data-slot="call-summary-context"]'),
      ).toBeNull();
    });

    it('OUTRANKS the block’s own settled reading', () => {
      // A callee that finished one turn under this call and is working on the
      // next: the block holds the first turn's figure and the resolver holds
      // the request in flight. The newer one is the one a reader is watching.
      const entries = groupTranscript([
        item(
          'call_started',
          { callId: 'call-1', calleeNodeId: 'poet', message: 'Write.' },
          'orch',
        ),
        item(
          'status',
          { status: 'running', nodeId: 'poet', callId: 'call-1' },
          'poet',
        ),
        item(
          'turn_complete',
          {
            callId: 'call-1',
            usage: { contextTokens: 12_000, contextWindowTokens: 200_000 },
          },
          'poet',
        ),
      ]);
      const block = entries[0];
      if (block?.type !== 'call-block') {
        throw new Error('expected a call block');
      }

      // Folded alone, the settled turn is what shows.
      act(() => root.render(<CallBlock block={block} nodes={NODES} />));
      expect(ringLabel()).toContain('6% full');

      // With a resolver, the live figure wins.
      act(() =>
        root.render(
          <CalleeContextResolverContext.Provider
            value={() => ({
              contextTokens: 160_000,
              contextWindowTokens: 200_000,
            })}>
            <CallBlock block={block} nodes={NODES} />
          </CalleeContextResolverContext.Provider>,
        ),
      );
      expect(ringLabel()).toContain('80% full');
    });

    it('keeps the block’s WINDOW when the resolver reports only a count', () => {
      // Per-figure fallback, at the render seam rather than only inside
      // `resolveCalleeContext`: without the window there is no denominator, so
      // the gauge would lose the ring it is drawn as.
      const entries = groupTranscript([
        item(
          'call_started',
          { callId: 'call-1', calleeNodeId: 'poet', message: 'Write.' },
          'orch',
        ),
        item(
          'status',
          { status: 'running', nodeId: 'poet', callId: 'call-1' },
          'poet',
        ),
        item(
          'turn_complete',
          {
            callId: 'call-1',
            usage: { contextTokens: 12_000, contextWindowTokens: 200_000 },
          },
          'poet',
        ),
      ]);
      const block = entries[0];
      if (block?.type !== 'call-block') {
        throw new Error('expected a call block');
      }
      act(() =>
        root.render(
          <CalleeContextResolverContext.Provider
            value={() => ({
              contextTokens: 100_000,
              contextWindowTokens: null,
            })}>
            <CallBlock block={block} nodes={NODES} />
          </CalleeContextResolverContext.Provider>,
        ),
      );

      expect(ringLabel()).toContain('50% full');
      // The denominator survived — the block's own settled turn supplied it.
      expect(ringLabel()).toContain('of 200k');
    });
  });
