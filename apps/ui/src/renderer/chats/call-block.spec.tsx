let seq = 0;
function item(
  kind: ChatItem['kind'],
  payload: unknown,
  nodeId: string,
): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    nodeId,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function makeBlock(title?: string): CallBlockEntry {
  const entries = groupTranscript([
    item(
      'call_started',
      {
        callId: 'call-1',
        calleeNodeId: 'poet',
        mode: 'async',
        message: 'Write a haiku about the sea.',
        ...(title !== undefined ? { title } : {}),
      },
      'orch',
    ),
    item(
      'status',
      { status: 'running', nodeId: 'poet', callId: 'call-1' },
      'poet',
    ),
    item(
      'message',
      { text: 'Waves rise and retreat', callId: 'call-1' },
      'poet',
    ),
  ]);
  const block = entries[0];
  if (block?.type !== 'call-block') {
    throw new Error('expected a call block');
  }
  return block;
}

