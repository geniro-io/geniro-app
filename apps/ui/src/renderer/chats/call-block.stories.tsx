import type { Meta, StoryObj } from '@storybook/react-vite';
import { userEvent, within } from 'storybook/test';

import type { ItemDto } from '../autogenerated';
import { CallBlock } from './call-block';
import { type CallBlockEntry, groupTranscript } from './transcript-groups';
import type { TranscriptNodeMeta } from './transcript-item';

const nodes: ReadonlyMap<string, TranscriptNodeMeta> = new Map([
  ['manager', { name: 'Manager', kind: 'agent', agent: 'claude' }],
  [
    'engineer',
    {
      name: 'Engineer',
      kind: 'agent',
      agent: 'claude',
      pool: ['claude', 'claude'],
    },
  ],
]);

function row(
  seq: number,
  kind: ItemDto['kind'],
  payload: unknown,
  nodeId = 'engineer',
): ItemDto {
  return {
    id: `pool-story-${seq}`,
    runId: 'pool-preview',
    nodeId,
    seq,
    kind,
    role: null,
    createdAt: '2026-10-20T10:00:00.000Z',
    payload,
  };
}

function pooledBlock(completed = false): CallBlockEntry {
  const rows: ItemDto[] = [
    row(
      1,
      'call_started',
      {
        callId: 'call-1',
        calleeNodeId: 'engineer',
        title: 'Review the changes',
        message: 'Review the changes and report any problems.',
        member: 1,
      },
      'manager',
    ),
    row(2, 'status', { callId: 'call-1', status: 'running' }),
    row(3, 'message', { callId: 'call-1', text: 'Checking the changes.' }),
    row(4, 'system', {
      callId: 'call-1',
      member: 2,
      message:
        'Engineer: pool member 1 hit a usage limit — handing the call to member 2.',
    }),
  ];
  if (completed) {
    rows.push(
      row(5, 'message', {
        callId: 'call-1',
        text: 'The review is complete. The changes are ready for review.',
      }),
      row(6, 'status', { callId: 'call-1', status: 'completed' }),
    );
  }
  const [block] = groupTranscript(rows, { anchorIds: new Set([rows[3]!.id]) });
  if (block?.type !== 'call-block') {
    throw new Error('Missing story call');
  }
  return block;
}

const meta = {
  title: 'Chats/CallBlock',
  component: CallBlock,
  args: { block: pooledBlock(), nodes },
  decorators: [(story) => <div className="max-w-3xl p-4">{story()}</div>],
} satisfies Meta<typeof CallBlock>;
export default meta;

type Story = StoryObj<typeof meta>;

export const PoolSwitch: Story = {};

export const BackupCompleted: Story = {
  args: { block: pooledBlock(true) },
};

export const PoolSwitchOpened: Story = {
  play: async ({ canvasElement }) => {
    await userEvent.click(
      within(canvasElement).getByRole('button', {
        name: /review the changes.*Manager → Engineer call/i,
      }),
    );
  },
};
