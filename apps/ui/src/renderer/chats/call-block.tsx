function blockStatusOf(
  status: CallBlockEntry['status'],
  queued: boolean,
): BlockStatus {
  switch (status) {
    case 'completed':
      return 'done';
    case 'failed':
      return 'error';
    case 'cancelled':
      return 'stopped';
    case 'pending':
      return queued ? 'queued' : 'running';
    default:
      return 'running';
  }
}

function containsRow(entry: TranscriptEntry, seq: number): boolean {
  if (entry.type === 'item') {
    return entry.item.seq === seq;
  }
  if (entry.type === 'tools' || isCardEntry(entry)) {
    return false;
  }
  return entry.entries.some((child) => containsRow(child, seq));
}

