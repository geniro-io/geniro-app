/**
 * Where an EARLIER call of a continued conversation was made — a pointer to the
 * card, which is drawn at the conversation's newest call.
 *
 * REPORTED as "if we keep writing to the same agent thread in a workflow, the
 * call card moves and disappears from where it was — the history becomes
 * unclear, there is just an empty space". The card moving is deliberate (one
 * card per conversation, with the work in flight at the tail); the empty slot
 * was not. So the slot names the call the way the card's header does — the
 * caller → callee pair and that call's own reason — and says where it went.
 *
 * One line and no disclosure: what the call did is inside the card, and a
 * second copy of it here would be the stacked cards the merge removed.
 */
export function CallContinuedRow({
  item,
  cardId,
  nodes,
}: {
  item: ChatItem;
  cardId: string;
  nodes?: ReadonlyMap<string, TranscriptNodeMeta>;
}): React.JSX.Element {
  const reveal = useContext(RevealCallBlockContext);
  const nameOf = (id: string | null): string | null =>
    id === null ? null : (nodes?.get(id)?.name ?? id);
  const calleeNodeId = payloadString(item.payload, 'calleeNodeId');
  const callee = nameOf(calleeNodeId) ?? 'agent';
  const caller = nameOf(item.nodeId);
  const identityText = caller ? `${caller} → ${callee}` : callee;
  const title = payloadString(item.payload, 'title');
  const body = (
    <>
      <span className="flex shrink-0 items-center text-muted-foreground">
        <ArrowRightLeft aria-hidden="true" className="size-3" />
        <span className="sr-only">Agent communication</span>
      </span>
      {caller ? (
        <AvatarPair
          caller={caller}
          callerKey={item.nodeId ?? caller}
          callee={callee}
          calleeKey={calleeNodeId ?? callee}
        />
      ) : null}
      <span className="min-w-0 flex-1 truncate text-left">
        {title ? (
          <>
            <span className="text-foreground">{title}</span>
            <span className="text-muted-foreground"> · {identityText}</span>
          </>
        ) : (
          <span className="text-foreground">{identityText}</span>
        )}
      </span>
      <span
        data-slot="call-continued-where"
        className="flex shrink-0 items-center gap-1 text-muted-foreground">
        continued below
        <ArrowDown aria-hidden="true" className="size-3" />
      </span>
    </>
  );
  const rowClass =
    'flex w-full min-w-0 items-center gap-2 rounded-xl border border-dashed border-border px-3 py-1.5 text-xs';
  return (
    <div data-role="call-continued" className="w-full">
      {reveal ? (
        <button
          type="button"
          onClick={() => reveal(cardId)}
          title="Show where this conversation continues"
          className={cn(
            rowClass,
            'transition-colors hover:bg-muted/40 focus-visible:ring-[3px] focus-visible:ring-ring/50 focus-visible:outline-none',
          )}>
          {body}
        </button>
      ) : (
        <div className={rowClass}>{body}</div>
      )}
    </div>
  );
}

/**
 * The callee's task list behind a glyph and its `done/total` — on the SHUT
 * card, where the list itself is folded away.
 *
 * ASKED FOR as "also current tasks icon with popover", beside the figures. A
 * checklist is the one thing in a call block that answers "how far through is
 * it" without reading anything, and folding the card had put it two clicks
 * away.
 *
 * Drawn only when the callee keeps a list — a chip reading `0/0` states that
 * this agent has no plan, which is not a fact about its progress. The popover
 * is the SAME {@link TaskScrollRows} the composer shelf and the agents panel
 * draw, bounded and following the running row, so three surfaces cannot
 * disagree about one list.
 *
 * It opens UPWARD only if it must: a call block sits anywhere in a scrolling
 * transcript, so `bottom` is right for the common case and `Popover`'s own
 * clamping keeps it on screen at the edges.
 */
function CallTaskChip({
  tasks,
  live,
  callee,
}: {
  tasks: readonly AgentTaskRow[];
  live: boolean;
  callee: string;
}): React.JSX.Element | null {
  if (tasks.length === 0) {
    return null;
  }
  const { done, total } = taskProgress(tasks);
  return (
    <HoverPopover
      slot="call-tasks"
      label={`${done} of ${total} ${total === 1 ? 'task' : 'tasks'} done \u2014 ${callee}`}
      panelLabel={`${callee}'s task list`}
      panelClassName="w-[20rem]"
      className="shrink-0"
      triggerClassName="flex items-center gap-1 rounded px-1 py-0.5 text-[11px] font-normal text-muted-foreground transition-colors hover:bg-muted"
      trigger={
        <>
          <TaskIcon className="size-3 text-muted-foreground" />
          <span className="tabular-nums">
            <TaskCount done={done} total={total} />
          </span>
        </>
      }>
      <TaskScrollRows tasks={tasks} live={live} />
    </HoverPopover>
  );
}

/**
 * The callee's figures — its task chip, how full its window is, and what it
 * spent — drawn ONE way whether the card is shut or open.
 *
 * REPORTED as "i wanna have same design of elements for footer when
 * uncollapsing agent conversation as in collapsed - with circle and so on": the
 * shut band drew the task chip and the context RING, while opening the card
 * swapped them for a plain-text footer reading `96 tools 233k ctx`, so opening
 * a card changed how its numbers looked rather than only what else was shown.
 * One component for both is what keeps the two states from drifting apart
 * again. `slot` only names the hooks, since the two are never on screen at once.
 */
function CallFigures({
  slot,
  tasks,
  live,
  callee,
  runId,
  callId,
  contextTokens,
  contextWindowTokens,
  contextEstimated,
  costUsd,
  estimatedCostUsd,
  workedMs,
}: {
  slot: 'call-summary' | 'call-footer';
  tasks: readonly AgentTaskRow[];
  live: boolean;
  callee: string;
  /** The open run, or null where the block is drawn outside one. */
  runId: string | null;
  /** The call whose conversation the ring's readout reports on. */
  callId: string;
  contextTokens: number | null;
  contextWindowTokens: number | null;
  /** Whether {@link contextTokens} is geniro's stand-in for a reading. */
  contextEstimated: boolean;
  costUsd: number | null;
  /** Of {@link costUsd}, the part geniro priced itself; null when none. */
  estimatedCostUsd: number | null;
  /** How long the callee has worked in this conversation, its open turn included. */
  workedMs: number | null;
}): React.JSX.Element {
  return (
    <>
      {workedMs === null ? null : (
        <span
          data-slot={`${slot}-worked`}
          title={
            live
              ? `${callee} has worked ${formatDuration(workedMs)} in this conversation so far`
              : `${callee} worked ${formatDuration(workedMs)} in this conversation`
          }
          className="flex shrink-0 items-center gap-1 tabular-nums">
          <Timer aria-hidden="true" className="size-3" />
          {live ? formatElapsed(workedMs) : formatDuration(workedMs)}
        </span>
      )}
      {/* WHAT IT IS ON, without opening the card — asked for beside the
          figures ("also current tasks icon with popover"). The list is the
          callee's own, folded out of this block. */}
      <CallTaskChip tasks={tasks} live={live} callee={callee} />
      {/* HOW FULL the callee's own window is — the one figure about this call
          that the caller's ring cannot state, each side of a call holding a
          window of its own. Its readout is that CONVERSATION's full breakdown,
          plan limits and totals, asked by call id: it could only restate the
          ring's own figure while the run was the one thing the daemon could be
          asked about — REPORTED as "when hovering to context in footer - i
          wanna see full details with subscription and so on, same as in main
          chat". */}
      {contextTokens === null ? null : (
        <span data-slot={`${slot}-context`} className="shrink-0">
          <ContextMeter
            runId={runId}
            callId={callId}
            contextTokens={contextTokens}
            contextWindowTokens={contextWindowTokens}
            contextEstimated={contextEstimated}
            live={live}
          />
        </span>
      )}
      {/* The ring's own figure, in words. This slot used to print the callee's
          input + output as "N tokens" right beside the ring, and it was read as
          the context — REPORTED as wrong numbers over a call reading "838
          tokens" whose window held 843k. It then rode the HOVER, said for what
          it is, and that is gone too: REPORTED as "я не понимаю, что такое
          in/out", and on a cached conversation the pair is a fraction of what
          actually moved — 8.7k over a call that read 4.26M tokens out of cache.
          What a call holds is this figure; what it SPENT is the cost beside. */}
      {contextTokens === null ? null : (
        <span
          data-slot={`${slot}-tokens`}
          className="shrink-0 tabular-nums"
          title={contextEstimated ? CONTEXT_ESTIMATE_NOTE : undefined}>
          {markContextEstimate(
            contextWindowTokens === null
              ? `${formatTokens(contextTokens)} context`
              : `${formatTokens(contextTokens)} / ${formatTokens(contextWindowTokens)}`,
            contextEstimated,
          )}
        </span>
      )}
      {costUsd === null ? null : (
        <span
          data-slot={`${slot}-cost`}
          className="shrink-0 tabular-nums"
          title={costEstimateTitle(costUsd, estimatedCostUsd)}>
          {markEstimate(formatExactUsd(costUsd), estimatedCostUsd)}
        </span>
      )}
    </>
  );
}

/**
 * One agent-to-agent call — geniro web's CommunicationBlock, always
 * expanded: an "Agent communication" eyebrow, a neutral card whose header
 * carries the caller→callee avatar pair, the name line, a live spinner and
 * the status chip; the body holds the clamped "Instructions for X" section,
 * the callee's streamed work (each entry in its own sender frame), the
 * clamped "Result from X" (or error) section, and an "N tools" footer.
 *
 * The card chrome itself lives in {@link BlockShell}, shared with the
 * sub-agent block.
 *
 * It is COLLAPSIBLE and shut to start, which REVERSES what shipped first. The
 * old reasoning — "a call is the point of the row it sits on, so it stays
 * open" — is true of one call and false of the conversation a workflow
 * actually produces: a manager routing work to three agents draws three cards
 * each holding a clamped brief, the callee's whole sub-turn and a clamped
 * result, so the caller's own sentences are pages apart and the transcript
 * reads as somebody else's inbox. REPORTED as "those blocks should be
 * collapsable. By default it should be collapsed."
 *
 * What a shut card still says is the point of the rest of that report — "we
 * always should see last message there, like its current state": the header
 * carries the pair, the CLI and the live spinner, and {@link callBlockSummary}
 * puts the callee's newest words under it. So the fold costs the reader
 * nothing they were scanning for; opening one is for the work behind it.
 */
export const CallBlock = memo(function CallBlock({
  block,
  nodes,
  chatAgentName,
}: {
  block: CallBlockEntry;
  nodes?: ReadonlyMap<string, TranscriptNodeMeta>;
  chatAgentName?: string | null;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  const nameOf = (id: string | null): string | null =>
    id === null ? null : (nodes?.get(id)?.name ?? id);
  const callee = nameOf(block.calleeNodeId) ?? 'agent';
  const caller = nameOf(block.callerNodeId);
  const calleeKind = calleeAgentOf(block, nodes);
  const calleeAgent =
    calleeKind === null ? null : agentShortName(identities, calleeKind);
  const poolTotal =
    (block.calleeNodeId === null
      ? undefined
      : nodes?.get(block.calleeNodeId)?.pool?.length) ?? 0;
  const poolMember = poolTotal > 1 ? (block.member ?? null) : null;
  const poolTitle =
    poolMember === null
      ? undefined
      : `Pool member ${poolMember} of ${poolTotal}`;
  const agentBadge =
    poolMember !== null
      ? `${calleeAgent ?? 'agent'} · ${poolMember}/${poolTotal}`
      : calleeAgent === callee
        ? null
        : calleeAgent;
  // A callee carrying on by itself after the call settled is working IN this
  // card — its live row is drawn inside it — so the card's mark spins with it.
  // The call itself stays settled: `callRunning` below still reads the call.
  const status = blockStatusOf(
    block.calleeWorking ? 'running' : block.status,
    block.queued === true,
  );
  const foldedUsage = callBlockUsage(block);
  /**
   * The callee's window, live first and the block's own settled rows last.
   *
   * The fold alone could only ever answer AFTER the call — a `turn_complete` is
   * the one row it reads and the callee has not written one yet — so the ring
   * was blank for the whole of every call and appeared at the moment it stopped
   * being worth watching. REPORTED against a running cursor call, and measured
   * on that same run: no ring for 46 seconds, then `80.4k / 200k` at the settle.
   *
   * Each figure falls back on its own, the rule `resolveCalleeContext` states in
   * full: a source that reports one half says nothing about the other, so a
   * live delta carrying only a count must not erase a window the settled turn
   * already had.
   *
   * The resolver is handed every call of the conversation, so a continuation
   * that has not reported yet reads on the same rule the agents panel's instance
   * ring does (`CalleeContextResolver`).
   */
  const folded = callBlockContext(block);
  const resolveCallReading = useContext(CalleeContextResolverContext);
  const callChannel = useContext(CallMessageChannelContext);
  // The open run — the one this block's transcript belongs to.
  const runId = useContext(ThreadUiMemoryContext);
  const [messageOpen, setMessageOpen] = useState(false);
  const calleeNodeAgent = calleeAgentOf(block, nodes);
  // The block's own status, not the card's: a call still pending — queued
  // under the run's cap, or not yet started — has no turn to join yet.
  const callRunning = block.status === 'running';
  const live =
    resolveCallReading !== null && block.calleeNodeId !== null
      ? // The WHOLE conversation rather than the calls this window drew: both
        // figures the resolver answers are about the callee's SESSION, which
        // outlives the window. The ring only gains older fallbacks; the SPEND
        // was silently short by every call that had paged out — see
        // `CallBlockEntry.conversationCallIds` for what that cost.
        resolveCallReading(block.calleeNodeId, block.conversationCallIds)
      : null;
  // The daemon's whole-run spend for this conversation, over the window's
  // fold — a call that started above the loaded window, or was continued many
  // times, otherwise states only the part of its cost on screen. The running
  // turn's unrecorded dollars go on top of whichever of the two is drawn: a
  // call hours into its turn otherwise states its FINISHED turns as the bill.
  const usage = withLiveCost(
    live?.spend ?? foldedUsage,
    live?.liveCost ?? null,
  );
  /**
   * Every tool the callee ran in this CONVERSATION, on the same rule — the
   * daemon's per-call counts over the fold, which holds only the loaded window.
   */
  const toolCount = live?.toolCalls ?? countTools(block.entries);
  const context = {
    contextTokens: live?.contextTokens ?? folded.contextTokens,
    contextEstimated:
      live?.contextTokens != null
        ? live.contextEstimated === true
        : folded.contextEstimated === true,
    contextWindowTokens:
      live?.contextWindowTokens ?? folded.contextWindowTokens,
  };
  const tasks = callBlockTasks(block);
  /**
   * The callee's working time in this conversation: the settled turns, plus
   * the turn in flight while the card is working — never while it is settled,
   * when an open turn is one a dead process left without an ending.
   */
  const workingTurns = status === 'running' ? (live?.openTurns ?? []) : [];
  useSecondTick(workingTurns.length > 0);
  const settledWorkedMs = live?.workedMs ?? null;
  const liveWorkedMs =
    workingTurns.length > 0 ? openTurnWorkedMs(workingTurns, Date.now()) : 0;
  const workedMs =
    settledWorkedMs === null && liveWorkedMs <= 0
      ? null
      : (settledWorkedMs ?? 0) + liveWorkedMs;
  const failed = block.status === 'failed';
  const identityText = caller ? `${caller} → ${callee}` : callee;
  const baseToggleLabel = caller ? `${identityText} call` : `Call to ${callee}`;
  /**
   * The accessible name for the disclosure button says WHY the call was made
   * before it says WHO it was to, matching what a sighted reader sees on the
   * header; with no reason on record it names the call by its pair alone.
   */
  const toggleLabel = block.title
    ? `${block.title} — ${baseToggleLabel}`
    : baseToggleLabel;
  const requestLabel = `Providing instructions for ${callee}`;
  // The callee's live row draws its own spinner and its own clock, so the
  // static hint below it would be the second line in a row saying the same
  // agent is still going.
  const tail = block.entries[block.entries.length - 1];
  const liveTail =
    tail?.type === 'item' && liveRowKind(tail.item.payload) !== null;
  const summaryText = callBlockSummary(block);
  /**
   * A shut card must still say its state, and between `call_started` and the
   * callee's first non-status row there are no words, no tasks and no figures
   * to say it with.
   */
  const pending = status === 'running' && summaryText === null;
  /**
   * What to say while the callee has produced no words yet — composed ONCE,
   * because the shut band and the open card both show it.
   *
   * Not gated on {@link pending}: the open card draws this line under a
   * different condition (running, with no live row of its own), so a lookup
   * tied to the shut card's state would leave that one saying `is thinking...`
   * about a callee three tools deep.
   */
  const activity = callBlockActivity(block);
  /**
   * The word for a callee that has shown nothing yet — see `live-words.ts`.
   *
   * Called unconditionally, above the branch that may not use it: it is a hook,
   * and the branch above it depends on data that changes between renders.
   */
  const calleeWord = useLiveWord(THINKING_WORDS);
  /**
   * A STALLED call outranks both — naming the tool it was last on would report
   * work that is no longer happening, and `is thinking...` would be the same
   * claim in softer words. The call is still open; only its silence is
   * reported. A later callee row clears `stalled` upstream, so this cannot
   * outlive the silence it describes.
   */
  /**
   * The callee ended its turn waiting for calls of its own — the call is open
   * because of THEM, so neither "thinking" nor "gone quiet" is true of it.
   */
  const heldOn = status === 'running' ? (block.heldOn ?? null) : null;
  const heldCalls =
    heldOn === null
      ? null
      : `${heldOn} call${heldOn === 1 ? '' : 's'} it started`;
  const heldText = heldCalls === null ? null : `waiting for ${heldCalls}`;
  const pendingLine =
    heldText !== null
      ? `${callee} is ${heldText}`
      : block.stalled
        ? `${callee} has gone quiet — the call is still open`
        : activity === null
          ? // The rotating vocabulary, lower-cased to sit inside the sentence. It
            // opens on the plain `thinking`, so a card glanced at in the first
            // seconds reads exactly as it always has — the word only wanders once
            // the callee has been quiet long enough for a still line to read as a
            // frozen one, which on a called agent is routinely minutes.
            `${callee} is ${calleeWord.toLowerCase()}...`
          : `${callee} is running ${activity}`;
  /**
   * Whether there is anything to put in the band at all — `BlockShell` renders
   * it on `summary ?`, and an element is always truthy, so the caller has to
   * pass `undefined` to say it has nothing to show.
   */
  const hasFigures =
    workedMs !== null ||
    tasks.length > 0 ||
    usage.costUsd !== null ||
    context.contextTokens !== null;
  const figures = (slot: 'call-summary' | 'call-footer'): React.JSX.Element => (
    <CallFigures
      slot={slot}
      tasks={tasks}
      live={status === 'running'}
      callee={callee}
      runId={runId}
      callId={block.callId}
      contextTokens={context.contextTokens}
      contextWindowTokens={context.contextWindowTokens}
      contextEstimated={context.contextEstimated}
      costUsd={usage.costUsd}
      estimatedCostUsd={usage.estimatedCostUsd ?? null}
      workedMs={workedMs}
    />
  );
  /**
   * Where the conversation's read pages begin, while older ones are still
   * unread — the rows a page of the run's own flow anchored for the folded
   * readings lie above it, scattered, and are not drawn as if they joined it.
   */
  const conversation = block.conversationCallIds[0] ?? block.callId;
  const pages = useContext(CallConversationContext)?.stateOf(conversation);
  const drawnFrom = pages?.hasOlder === true ? (pages.oldestSeq ?? null) : null;
  const handOff = block.poolHandOff;
  const handOffRowDrawn =
    handOff !== undefined &&
    block.entries.some((entry) => {
      const endSeq = entryEndSeq(entry);
      return (
        !(drawnFrom !== null && endSeq !== null && endSeq < drawnFrom) &&
        containsRow(entry, handOff.seq)
      );
    });
  const mark = useContext(JumpMarkContext);
  const hasSummary =
    summaryText !== null ||
    pending ||
    // A call that has gone quiet with nothing else to show still owes the
    // reader that one fact, so it earns the band on its own — on the same
    // terms the marker itself is drawn, or the band could open empty.
    (block.stalled && status === 'running') ||
    heldText !== null ||
    hasFigures;
  return (
    <div
      data-role="call-block"
      data-call-block={block.id}
      className={REVEALABLE_CARD_CLASS}>
      <BlockShell
        eyebrow="Agent communication"
        eyebrowIcon={<ArrowRightLeft aria-hidden="true" className="size-3" />}
        status={status}
        collapsible
        memoryKey={`call:${block.id}`}
        toggleLabel={toggleLabel}
        summary={
          hasSummary ? (
            <>
              {pending ? (
                // The same sentence the OPEN card shows in this state, so the
                // fold changes what is on screen and not what is true. ONE
                // line here, which is this band's own rule — its other arm has
                // always truncated, and this arm grew the shut card for the
                // same reason it grew the open one: an ACP tool name is
                // routinely a whole shell command.
                <BlockPendingLine clamp="one">{pendingLine}</BlockPendingLine>
              ) : (
                /* The words give way — the figures and the chip beside them are a
                 fixed handful of characters, while a callee's last message is a
                 paragraph. */
                <span className="flex min-w-0 flex-1 flex-col">
                  <span className="truncate">{summaryText ?? ''}</span>
                  {block.poolHandOff !== undefined &&
                  block.poolHandOff.message !== summaryText ? (
                    <span
                      data-slot="call-pool-handoff"
                      title={block.poolHandOff.message}
                      className="truncate text-xs text-muted-foreground">
                      {block.poolHandOff.message}
                    </span>
                  ) : null}
                </span>
              )}
              {/* GONE QUIET — its own marker rather than a variation on the
                pending line, because that line is drawn only while there are
                no words yet: a callee that spoke and THEN stopped is exactly
                the case worth reporting, and it would have had none. Muted
                rather than destructive: nothing has failed and nothing has
                been cancelled, so the loudest tone on the page would be a
                claim this row is careful not to make. */}
              {heldText !== null ? (
                <span
                  data-slot="call-summary-held"
                  title={`${callee} ended its turn with ${heldCalls} still running. This call stays open until they finish, and ${callee} is continued in it to finish its answer.`}
                  className="shrink-0 text-xs text-muted-foreground">
                  {heldText}
                </span>
              ) : null}
              {block.stalled && status === 'running' ? (
                <span
                  data-slot="call-summary-stalled"
                  title={`${callee} has produced nothing for a while. The call is still open — nothing has been cancelled.`}
                  className="shrink-0 text-xs text-muted-foreground">
                  quiet
                </span>
              ) : null}
              {figures('call-summary')}
            </>
          ) : undefined
        }
        header={
          <>
            {caller ? (
              <AvatarPair
                caller={caller}
                callerKey={block.callerNodeId ?? caller}
                callee={callee}
                calleeKey={block.calleeNodeId ?? callee}
              />
            ) : null}
            {/* TWO LINES when the caller named a reason: the `title` it passed
                on `call_agent` first, the caller→callee pair under it — ASKED
                FOR as "на первой строке тайтл, на второй «Менеджер инженер»",
                since the pair says WHO is talking and the title says what this
                particular call is for. Without a title the pair IS the title,
                on one line, exactly as the header read before the field
                existed. */}
            {block.title ? (
              <span className="flex min-w-0 flex-1 flex-col leading-tight">
                <BlockTitle>{block.title}</BlockTitle>
                <span
                  data-slot="call-identity"
                  className="truncate text-[11px] text-muted-foreground">
                  {identityText}
                </span>
              </span>
            ) : (
              <BlockTitle>{identityText}</BlockTitle>
            )}
            {/* WHICH CLI answered. The card is the callee's work, so it is the
                callee's binary that is named — a graph routinely mixes the two,
                and a node's name is the user's word for a persona rather than a
                statement about what is under it. Dropped when it would repeat
                the name beside it (a node called `claude` on claude), the same
                rule the agents panel's card badge follows, and drawn as nothing
                at all when the graph does not say — an unstated agent is not a
                fact about the agent. */}
            {agentBadge ? (
              <Badge
                variant="muted"
                className="shrink-0"
                title={poolTitle}
                aria-label={poolTitle}>
                {agentBadge}
              </Badge>
            ) : null}
          </>
        }>
        {block.message ? (
          <BlockRequest
            label={requestLabel}
            text={block.message}
            memoryKey={`call:${block.id}:request`}
          />
        ) : null}
        <CallConversationPager conversation={conversation} />
        {handOff !== undefined && !handOffRowDrawn ? (
          <MessageBubble variant="note">{handOff.message}</MessageBubble>
        ) : null}
        {/*
          The card's header IS the callee's identity, so its rows carry none of
          their own — the same rule, and the same context, the sub-agent block
          applies to a delegate's thread. Without it every message the callee
          streamed wore an avatar and a `<callee> · 14:51` line of its own, so a
          six-message sub-turn drew the same face six times inside a card whose
          header had just named it. Reported as "иконка инженера просто
          дублируется — она должна быть просто один раз в хедере блока".
        */}
        <NestedThreadContext.Provider value={true}>
          {block.entries.map((entry) => {
            const startSeq = entryStartSeq(entry);
            const endSeq = entryEndSeq(entry);
            // Wholly above the pages read: a scattered card row, not one of them.
            if (drawnFrom !== null && endSeq !== null && endSeq < drawnFrom) {
              return null;
            }
            // A CONTINUED call's ask, at the point it was sent — drawn exactly
            // as the first ask is, since the card is one conversation and each
            // ask is a brief to the same callee.
            if (isCallContinuation(entry)) {
              const ask = payloadString(entry.item.payload, 'message');
              return ask ? (
                <BlockRequest
                  key={entry.item.id}
                  label={requestLabel}
                  text={ask}
                />
              ) : null;
            }
            // Each row is a place a jump can land (`data-call-seq`), marked
            // the way the transcript marks its own rows.
            return (
              <TranscriptRow
                key={entry.type === 'item' ? entry.item.id : entry.id}
                className={cn(
                  mark?.key === `card-row:${startSeq}` && JUMP_MARK_CLASS,
                )}
                {...jumpAnchorProps('call', startSeq, `card-row:${startSeq}`)}>
                <TranscriptEntryView
                  entry={entry}
                  nodes={nodes}
                  chatAgentName={chatAgentName}
                />
              </TranscriptRow>
            );
          })}
        </NestedThreadContext.Provider>
        {block.result ? (
          <BlockResult
            label={`Result from ${callee}`}
            text={block.result}
            memoryKey={`call:${block.id}:result`}
          />
        ) : null}
        {status === 'running' && !liveTail ? (
          <BlockPendingLine clamp="one">{pendingLine}</BlockPendingLine>
        ) : null}
        {block.calleeNodeId !== null ? (
          <CallMessagePanel
            blockId={block.id}
            callId={block.callId}
            calleeNodeId={block.calleeNodeId}
            callee={callee}
            calleeAgent={calleeNodeAgent}
            caller={caller}
            running={callRunning}
            open={messageOpen}
            onClose={() => setMessageOpen(false)}
          />
        ) : null}
        <BlockToolFooter
          count={toolCount}
          {...(live?.toolCalls == null
            ? {}
            : {
                countTitle: `Every tool ${callee} has run in this conversation, its sub-agents' not included`,
              })}
          action={
            // Only when there is a button to draw: an element the button
            // renders as null still makes the footer think it has content.
            callChannel === null ||
            block.calleeNodeId === null ||
            !callRunning ||
            messageOpen ? undefined : (
              <CallMessageButton
                callee={callee}
                calleeAgent={calleeNodeAgent}
                running={callRunning}
                open={messageOpen}
                onOpen={() => setMessageOpen(true)}
              />
            )
          }
          // The SAME figures the shut band draws — task chip, ring and cost,
          // in the band's own size — pushed to the right as they sit
          // there, so opening the card never changes how its numbers look.
          note={
            failed || hasFigures ? (
              <>
                {failed ? <span>finished with an error</span> : null}
                {hasFigures ? (
                  <span
                    data-slot="call-footer-figures"
                    className="ml-auto flex items-center gap-2 whitespace-nowrap text-xs">
                    {figures('call-footer')}
                  </span>
                ) : null}
              </>
            ) : undefined
          }
        />
      </BlockShell>
    </div>
  );
});

/**
 * The CLI that answers this call: the pool member it ran on, else the callee
 * node's own. A pooled node's member 2 is routinely another CLI, and naming
 * the node's would credit the reply to an agent that never saw it.
 */
function calleeAgentOf(
  block: CallBlockEntry,
  nodes: ReadonlyMap<string, TranscriptNodeMeta> | undefined,
): string | null {
  if (block.calleeNodeId === null) {
    return null;
  }
  const meta = nodes?.get(block.calleeNodeId);
  const member =
    block.member !== undefined ? meta?.pool?.[block.member - 1] : undefined;
  return member ?? meta?.agent ?? null;
}
