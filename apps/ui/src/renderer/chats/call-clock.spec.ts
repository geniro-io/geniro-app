import { describe, expect, it } from 'vitest';

import type { CallClock, ItemDto as ChatItem } from '../autogenerated';
import { callClocksMs, continueCallClocks } from './call-clock';

function row(
  seq: number,
  kind: string,
  atMs: number,
  payload: Record<string, unknown>,
  memberId = 'engineer',
): ChatItem {
  return {
    id: `i${seq}`,
    runId: 'r1',
    seq,
    kind,
    role: null,
    payload,
    memberId,
    createdAt: new Date(atMs).toISOString(),
  } as ChatItem;
}

const status = (
  seq: number,
  callId: string,
  value: string,
  atMs: number,
): ChatItem =>
  row(seq, 'status', atMs, { nodeId: 'engineer', status: value, callId });

const clock = (fields: Partial<CallClock> = {}): CallClock => ({
  closedMs: 0,
  runningSince: null,
  parkedMs: 0,
  parkedSince: null,
  openCards: [],
  throughSeq: 10,
  ...fields,
});

describe('continueCallClocks', () => {
  it('continues the daemon’s reading over the rows after it, never the rows it counted', () => {
    const clocks = continueCallClocks(
      [
        {
          callId: 'call-1',
          memberId: 'engineer',
          clock: clock({ closedMs: 5_000, runningSince: 0 }),
        },
      ],
      [
        status(9, 'call-1', 'completed', 1_000),
        status(11, 'call-1', 'completed', 60_000),
      ],
    );

    expect(clocks.get('call-1')).toEqual(
      clock({ closedMs: 65_000, throughSeq: 11 }),
    );
  });

  it('keeps a stretch running through a monitor wake that writes no status row', () => {
    const clocks = continueCallClocks(
      [],
      [
        status(1, 'call-1', 'running', 0),
        row(2, 'turn_complete', 10_000, { callId: 'call-1', usage: {} }),
        row(3, 'system', 50_000, {
          woke: true,
          monitors: [],
          callId: 'call-1',
        }),
      ],
    );

    expect(callClocksMs([...clocks.values()], 80_000, true)).toBe(80_000);
  });

  it('closes a card the daemon left open with a verdict after its reading', () => {
    const clocks = continueCallClocks(
      [
        {
          callId: 'call-1',
          memberId: 'engineer',
          clock: clock({
            runningSince: 0,
            parkedSince: 10_000,
            openCards: ['q1'],
          }),
        },
      ],
      [row(11, 'approval_verdict', 40_000, { id: 'q1' })],
    );

    expect(clocks.get('call-1')).toMatchObject({
      parkedMs: 30_000,
      parkedSince: null,
      openCards: [],
    });
    expect(callClocksMs([...clocks.values()], 100_000, true)).toBe(70_000);
  });

  it('folds a call the daemon had not seen from its rows alone', () => {
    const clocks = continueCallClocks(
      [],
      [
        status(20, 'call-2', 'running', 1_000),
        row(21, 'approval_request', 2_000, { id: 'q1', callId: 'call-2' }),
        row(22, 'unanswerable', 5_000, { id: 'q1' }),
        status(23, 'call-2', 'completed', 11_000),
      ],
    );

    expect(clocks.get('call-2')).toEqual(
      clock({ closedMs: 7_000, throughSeq: 23 }),
    );
  });
});

describe('callClocksMs', () => {
  it('sums every call and stops at an open card', () => {
    const clocks = [
      clock({ closedMs: 3_000 }),
      clock({ runningSince: 0, parkedMs: 1_000, parkedSince: 8_000 }),
    ];

    expect(callClocksMs(clocks, 20_000, true)).toBe(10_000);
  });

  it('leaves out an open stretch once the card has settled', () => {
    expect(
      callClocksMs(
        [clock({ closedMs: 3_000, runningSince: 0 })],
        20_000,
        false,
      ),
    ).toBe(3_000);
  });
});
