import type { CallClock, ItemDto as ChatItem } from '../autogenerated';
import { useSecondTick } from '../components/use-second-tick';
import { payloadString } from './transcript-payload';
import { formatDuration } from './turn-duration';

/** A call's clock as the daemon read it, beside the member that answers the call. */
export interface DurableCallClock {
  callId: string;
  memberId: string;
  clock: CallClock;
}

const ENDING_STATUSES: ReadonlySet<string> = new Set([
  'completed',
  'failed',
  'cancelled',
  'skipped',
]);

const CARD_CLOSING_KINDS: ReadonlySet<string> = new Set([
  'approval_verdict',
  'unanswerable',
]);

/**
 * Every call's clock: the daemon's reading of each, continued over the rows
 * this client holds past that reading's `throughSeq`, and a call the daemon
 * had not seen yet folded from its rows alone.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/utils/call-clock.ts` →
 * `callClocksFrom`, which folds the same rows by the same rule over the whole
 * run.
 */
export function continueCallClocks(
  durable: Iterable<DurableCallClock>,
  rows: readonly ChatItem[],
): ReadonlyMap<string, CallClock> {
  const clocks = new Map<string, CallClock>();
  const cardCalls = new Map<string, string>();
  for (const { callId, memberId, clock } of durable) {
    clocks.set(callId, { ...clock, openCards: [...clock.openCards] });
    for (const id of clock.openCards) {
      cardCalls.set(`${memberId}\u0000${id}`, callId);
    }
  }
  for (const row of rows) {
    const at = Date.parse(row.createdAt);
    if (row.memberId === null || !Number.isFinite(at)) {
      continue;
    }
    if (CARD_CLOSING_KINDS.has(row.kind)) {
      const id = payloadString(row.payload, 'id');
      const cardKey = `${row.memberId}\u0000${id ?? ''}`;
      const callId = id === null ? undefined : cardCalls.get(cardKey);
      const clock = callId === undefined ? undefined : clocks.get(callId);
      if (clock !== undefined && id !== null && row.seq > clock.throughSeq) {
        cardCalls.delete(cardKey);
        closeCard(clock, id, at);
        clock.throughSeq = row.seq;
      }
      continue;
    }
    const callId = payloadString(row.payload, 'callId');
    if (
      callId === null ||
      (row.kind !== 'status' && row.kind !== 'approval_request')
    ) {
      continue;
    }
    const clock = clocks.get(callId) ?? emptyCallClock();
    clocks.set(callId, clock);
    if (row.seq <= clock.throughSeq) {
      continue;
    }
    clock.throughSeq = row.seq;
    if (row.kind === 'status') {
      const status = payloadString(row.payload, 'status');
      if (status === 'running') {
        startStretch(clock, at);
      } else if (status !== null && ENDING_STATUSES.has(status)) {
        for (const id of clock.openCards) {
          cardCalls.delete(`${row.memberId}\u0000${id}`);
        }
        endStretch(clock, at);
      }
    } else {
      const id = payloadString(row.payload, 'id');
      if (id !== null && clock.runningSince !== null) {
        cardCalls.set(`${row.memberId}\u0000${id}`, callId);
        openCard(clock, id, at);
      }
    }
  }
  return clocks;
}

/**
 * What these clocks read at `now`. A stretch still open counts only while
 * `running`: a settled card's open stretch is one a dead process left without
 * its ending, and counting it would run the clock forever.
 */
export function callClocksMs(
  clocks: readonly CallClock[],
  now: number,
  running: boolean,
): number {
  return clocks.reduce((total, clock) => {
    if (!running || clock.runningSince === null) {
      return total + clock.closedMs;
    }
    const parked =
      clock.parkedMs +
      (clock.parkedSince === null ? 0 : Math.max(0, now - clock.parkedSince));
    return (
      total + clock.closedMs + Math.max(0, now - clock.runningSince - parked)
    );
  }, 0);
}

/**
 * A conversation's clock as a card draws it, ticking while it runs; null when
 * no call of it has a clock.
 */
export function useCallClockMs(
  clocks: readonly CallClock[] | undefined,
  running: boolean,
): number | null {
  const ticking =
    running &&
    (clocks ?? []).some(
      (clock) => clock.runningSince !== null && clock.parkedSince === null,
    );
  useSecondTick(ticking);
  if (clocks === undefined || clocks.length === 0) {
    return null;
  }
  return callClocksMs(clocks, Date.now(), running);
}

/** What a conversation's clock counts, said where its figure is drawn. */
export function callClockTitle(ms: number, running: boolean): string {
  return `${running ? 'On this conversation for' : 'Was on this conversation for'} ${formatDuration(ms)}${running ? ' so far' : ''}: its waits on its own monitors and calls count, its waits on you do not`;
}

function emptyCallClock(): CallClock {
  return {
    closedMs: 0,
    runningSince: null,
    parkedMs: 0,
    parkedSince: null,
    openCards: [],
    throughSeq: -1,
  };
}

function startStretch(clock: CallClock, at: number): void {
  if (clock.runningSince === null) {
    clock.runningSince = at;
    clock.parkedMs = 0;
  }
}

function endStretch(clock: CallClock, at: number): void {
  if (clock.runningSince !== null) {
    const parked =
      clock.parkedMs +
      (clock.parkedSince === null ? 0 : Math.max(0, at - clock.parkedSince));
    clock.closedMs += Math.max(0, at - clock.runningSince - parked);
  }
  clock.runningSince = null;
  clock.parkedMs = 0;
  clock.parkedSince = null;
  clock.openCards = [];
}

function openCard(clock: CallClock, id: string, at: number): void {
  if (clock.openCards.includes(id)) {
    return;
  }
  clock.openCards.push(id);
  clock.parkedSince ??= at;
}

function closeCard(clock: CallClock, id: string, at: number): void {
  clock.openCards = clock.openCards.filter((open) => open !== id);
  if (clock.openCards.length === 0 && clock.parkedSince !== null) {
    clock.parkedMs += Math.max(0, at - clock.parkedSince);
    clock.parkedSince = null;
  }
}
