function live(
  contextTokens: number | null,
  contextWindowTokens: number | null,
): LiveState {
  return {
    text: '',
    thinkingTokens: null,
    thinkingText: null,
    thinkingSince: null,
    thinkingStretch: null,
    composingTool: null,
    composingBytes: null,
    contextTokens,
    contextWindowTokens,
    spentInputTokens: null,
    spentOutputTokens: null,
    spentCacheReadTokens: null,
    spentCostUsd: null,
  };
}

/** One call as a spec states it: its listing entry and its figures together. */
type CallEntry = NodeDurableReading['calls'][number] &
  Partial<Omit<NodeDurableReading['callFigures'][number], 'callId'>>;

/** The node reading the route would send for these calls, split as it does. */
function reading(
  entries: readonly CallEntry[],
): ReadonlyMap<string, NodeDurableReading> {
  return new Map([
    [
      'callee',
      {
        contextTokens: null,
        contextEstimated: false,
        contextWindowTokens: null,
        model: null,
        calls: entries.map(
          ({
            totals: _totals,
            toolCalls: _toolCalls,
            toolCallsThroughSeq: _through,
            promptCacheExpiresAt: _expiry,
            workedMs: _worked,
            workedThroughSeq: _workedThrough,
            ...heavy
          }) => heavy,
        ),
        callFigures: entries.map((entry) => ({
          callId: entry.callId,
          totals: entry.totals ?? NO_TOTALS,
          toolCalls: entry.toolCalls ?? 0,
          toolCallsThroughSeq: entry.toolCallsThroughSeq ?? null,
          promptCacheExpiresAt: entry.promptCacheExpiresAt ?? null,
          workedMs: entry.workedMs ?? null,
          workedThroughSeq: entry.workedThroughSeq ?? null,
        })),
        totals: NO_TOTALS,
        mainTotals: NO_TOTALS,
        workedMs: null,
        toolCalls: null,
        status: 'running',
        startedAt: null,
        promptCacheExpiresAt: null,
      },
    ],
  ]);
}

const NO_LIVE: ReadonlyMap<string, LiveState> = new Map();
const NO_ROWS: ReadonlyMap<string, NodeDurableReading> = new Map();

describe('resolveCalleeContext', () => {
  it('reads the live plane under the per-CALL owner key', () => {
    // The key is the whole point: a node serving two calls at once holds two
    // windows, and keyed by node alone they would share one entry with the
    // last writer winning — which is the defect `liveTextKey` records.
    const liveText = new Map([
      [partialOwnerKey('callee', 'call-1'), live(80_414, 200_000)],
      [partialOwnerKey('callee', 'call-2'), live(12_000, 200_000)],
    ]);

    expect(resolveCalleeContext(liveText, NO_ROWS, 'callee', 'call-1')).toEqual(
      {
        contextTokens: 80_414,
        contextWindowTokens: 200_000,
      },
    );
    expect(resolveCalleeContext(liveText, NO_ROWS, 'callee', 'call-2')).toEqual(
      {
        contextTokens: 12_000,
        contextWindowTokens: 200_000,
      },
    );
  });

  it('falls back to the daemon’s durable row for the call', () => {
    // What a reloaded window has and the live plane does not: the plane is
    // throwaway state, so on a first open there is nothing in it at all.
    const rows = reading([
      {
        promptCacheExpiresAt: null,
        callId: 'call-1',
        contextTokens: 64_500,
        contextEstimated: false,
        contextWindowTokens: 200_000,
        totals: NO_TOTALS,
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
    ]);

    expect(resolveCalleeContext(NO_LIVE, rows, 'callee', 'call-1')).toEqual({
      contextTokens: 64_500,
      contextWindowTokens: 200_000,
    });
  });

  it('prefers LIVE over the durable row', () => {
    // The row moves on the daemon's own write schedule and is fetched on run
    // open and reconnect only; a delta is this turn's latest request.
    const rows = reading([
      {
        promptCacheExpiresAt: null,
        callId: 'call-1',
        contextTokens: 64_500,
        contextEstimated: false,
        contextWindowTokens: 200_000,
        totals: NO_TOTALS,
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
    ]);
    const liveText = new Map([
      [partialOwnerKey('callee', 'call-1'), live(80_414, 200_000)],
    ]);

    expect(resolveCalleeContext(liveText, rows, 'callee', 'call-1')).toEqual({
      contextTokens: 80_414,
      contextWindowTokens: 200_000,
    });
  });

  it('falls back PER FIGURE — a live count does not erase a durable window', () => {
    // The daemon's own rule: a reading that omits one half says nothing about
    // it. A delta carrying a count and no window would otherwise take the
    // gauge's denominator away and leave a ring that cannot be drawn.
    const rows = reading([
      {
        promptCacheExpiresAt: null,
        callId: 'call-1',
        contextTokens: 64_500,
        contextEstimated: false,
        contextWindowTokens: 200_000,
        totals: NO_TOTALS,
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
    ]);
    const liveText = new Map([
      [partialOwnerKey('callee', 'call-1'), live(80_414, null)],
    ]);

    expect(resolveCalleeContext(liveText, rows, 'callee', 'call-1')).toEqual({
      contextTokens: 80_414,
      contextWindowTokens: 200_000,
    });
  });

  it('answers UNMEASURED when neither source knows this call', () => {
    const rows = reading([
      {
        promptCacheExpiresAt: null,
        callId: 'call-2',
        contextTokens: 64_500,
        contextEstimated: false,
        contextWindowTokens: 200_000,
        totals: NO_TOTALS,
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
    ]);

    expect(resolveCalleeContext(NO_LIVE, rows, 'callee', 'call-1')).toEqual({
      contextTokens: null,
      contextWindowTokens: null,
    });
    expect(resolveCalleeContext(NO_LIVE, NO_ROWS, 'nobody', 'call-1')).toEqual({
      contextTokens: null,
      contextWindowTokens: null,
    });
  });
});

describe('resolveConversationContext', () => {
  it('takes the conversation’s LATEST call’s reading over an earlier call’s', () => {
    // A continued conversation is one session: its newest call is where the
    // window stands now, and the first call's row is an older level of it.
    const rows = reading([
      {
        promptCacheExpiresAt: null,
        callId: 'call-22',
        contextTokens: 40_000,
        contextEstimated: false,
        contextWindowTokens: 200_000,
        totals: NO_TOTALS,
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
      {
        promptCacheExpiresAt: null,
        callId: 'call-24',
        contextTokens: 90_000,
        contextEstimated: false,
        contextWindowTokens: 200_000,
        totals: NO_TOTALS,
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
    ]);
    expect(
      resolveConversationContext(NO_LIVE, rows, 'callee', [
        'call-22',
        'call-23',
        'call-24',
      ]),
    ).toEqual({ contextTokens: 90_000, contextWindowTokens: 200_000 });
  });

  it('falls back to an earlier call while the latest has reported nothing yet', () => {
    const rows = reading([
      {
        promptCacheExpiresAt: null,
        callId: 'call-22',
        contextTokens: 40_000,
        contextEstimated: false,
        contextWindowTokens: null,
        totals: NO_TOTALS,
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
      {
        promptCacheExpiresAt: null,
        callId: 'call-23',
        contextTokens: 55_000,
        contextEstimated: false,
        contextWindowTokens: 200_000,
        totals: NO_TOTALS,
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
    ]);
    const liveText = new Map([
      [partialOwnerKey('callee', 'call-24'), live(null, 1_000_000)],
    ]);
    expect(
      resolveConversationContext(liveText, rows, 'callee', [
        'call-22',
        'call-23',
        'call-24',
      ]),
    ).toEqual({ contextTokens: 55_000, contextWindowTokens: 1_000_000 });
  });
});

describe('resolveConversationSpend', () => {
  it('sums the WHOLE run’s spend across every call of the conversation', () => {
    // The daemon's per-call totals, not the window's fold: a conversation
    // continued three times, its first call far above the loaded page, costs
    // what all three cost.
    const rows = reading([
      {
        promptCacheExpiresAt: null,
        callId: 'call-10',
        contextTokens: null,
        contextEstimated: false,
        contextWindowTokens: null,
        totals: totals({
          turns: 4,
          costUsd: 40,
          inputTokens: 1_000,
          outputTokens: 500,
        }),
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
      {
        promptCacheExpiresAt: null,
        callId: 'call-12',
        contextTokens: null,
        contextEstimated: false,
        contextWindowTokens: null,
        totals: totals({ turns: 1, costUsd: 12.38, outputTokens: 250 }),
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
    ]);
    expect(
      resolveConversationSpend(rows, 'callee', [
        'call-10',
        'call-11',
        'call-12',
      ]),
    ).toEqual({ tokens: 1_750, costUsd: 52.38 });
  });

  it('answers null when no call has a durable figure, so the caller folds instead', () => {
    const rows = reading([
      {
        promptCacheExpiresAt: null,
        callId: 'call-1',
        contextTokens: 5,
        contextEstimated: false,
        contextWindowTokens: 10,
        totals: NO_TOTALS,
        toolCalls: 0,
        toolCallsThroughSeq: null,
        start: null,
      },
    ]);
    expect(resolveConversationSpend(rows, 'callee', ['call-1'])).toBeNull();
    expect(resolveConversationSpend(rows, 'nobody', ['call-1'])).toBeNull();
  });

  it('keeps an unpriced turn’s cost NOT MEASURED rather than zero', () => {
    // cursor reports tokens and no cost: a `$0.00` would be a claim nobody made.
    expect(
      spendOfTotals(totals({ turns: 2, inputTokens: 10, outputTokens: 5 })),
    ).toEqual({ tokens: 15, costUsd: null });
  });
});

describe('a call past the listing cap', () => {
  it('still states its spend, tools and cache expiry from the uncapped figures', () => {
    // The listing (`calls`) keeps only the newest calls; call-1 has aged out
    // of it, and its figures must not age out with it.
    const readings: ReadonlyMap<string, NodeDurableReading> = new Map([
      [
        'callee',
        {
          ...reading([]).get('callee')!,
          calls: [],
          callFigures: [
            {
              callId: 'call-1',
              totals: totals({ turns: 2, costUsd: 9.5, outputTokens: 40 }),
              toolCalls: 230,
              toolCallsThroughSeq: 900,
              promptCacheExpiresAt: '2026-10-25T12:00:00.000Z',
              workedMs: 61_000,
              workedThroughSeq: 880,
            },
          ],
        },
      ],
    ]);
    expect(resolveConversationSpend(readings, 'callee', ['call-1'])).toEqual({
      tokens: 40,
      costUsd: 9.5,
    });
    expect(
      resolveConversationToolCalls(readings, 'callee', ['call-1'], new Map()),
    ).toBe(230);
    expect(resolveConversationCacheExpiry(readings, 'callee', ['call-1'])).toBe(
      '2026-10-25T12:00:00.000Z',
    );
    expect(
      resolveConversationWorked(readings, 'callee', ['call-1'], NO_CALL_TURNS)
        .workedMs,
    ).toBe(61_000);
  });
});

const NO_CALL_TURNS = { durations: new Map(), open: new Map() };

describe('resolveConversationWorked', () => {
  const callReading = (
    callId: string,
    workedMs: number | null,
    workedThroughSeq: number | null,
  ): CallEntry => ({
    promptCacheExpiresAt: null,
    callId,
    contextTokens: null,
    contextEstimated: false,
    contextWindowTokens: null,
    start: null,
    workedMs,
    workedThroughSeq,
  });
  const openTurn = (startedAt: number): OpenTurn => ({
    agentKey: 'callee',
    startedAt,
    parkedMs: 0,
    openSince: [],
  });

  it('sums every call of the conversation, adding only the turns settled after the read', () => {
    const readings = reading([
      callReading('call-1', 30_000, 40),
      callReading('call-2', 5_000, 90),
    ]);
    const turns = {
      durations: new Map([
        [
          'call-1',
          [
            { seq: 40, ms: 30_000 },
            { seq: 120, ms: 2_000 },
          ],
        ],
        ['call-2', [{ seq: 90, ms: 5_000 }]],
      ]),
      open: new Map([['call-2', openTurn(1_000)]]),
    };

    expect(
      resolveConversationWorked(
        readings,
        'callee',
        ['call-1', 'call-2'],
        turns,
      ),
    ).toEqual({ workedMs: 37_000, openTurns: [openTurn(1_000)] });
  });

  it('counts every held turn of a call the daemon has not measured', () => {
    const turns = {
      durations: new Map([['call-3', [{ seq: 7, ms: 4_000 }]]]),
      open: new Map(),
    };

    expect(
      resolveConversationWorked(NO_ROWS, 'callee', ['call-3'], turns),
    ).toEqual({ workedMs: 4_000, openTurns: [] });
  });

  it('is unmeasured when nothing has measured a turn', () => {
    expect(
      resolveConversationWorked(
        reading([callReading('call-1', null, null)]),
        'callee',
        ['call-1'],
        NO_CALL_TURNS,
      ).workedMs,
    ).toBeNull();
  });
});

describe('resolveConversationToolCalls', () => {
  const callReading = (
    callId: string,
    toolCalls: number,
    toolCallsThroughSeq: number | null,
  ): CallEntry => ({
    promptCacheExpiresAt: null,
    callId,
    contextTokens: null,
    contextEstimated: false,
    contextWindowTokens: null,
    totals: NO_TOTALS,
    toolCalls,
    toolCallsThroughSeq,
    start: null,
  });
  const toolRow = (
    seq: number,
    inCall: string,
    nodeId = 'callee',
    parentToolUseId?: string,
  ): ChatItem => ({
    id: `i${seq}`,
    runId: 'w1',
    nodeId,
    seq,
    kind: 'tool_call',
    role: null,
    inCall,
    payload: {
      id: `t${seq}`,
      name: 'Bash',
      ...(parentToolUseId === undefined ? {} : { parentToolUseId }),
    },
    createdAt: 'now',
  });

  it('sums the conversation’s own calls, never another conversation of the same agent', () => {
    // The agent answered three conversations; the card is for call-10 and its
    // continuation call-12. call-20 is a separate conversation.
    const readings = reading([
      callReading('call-10', 120, 500),
      callReading('call-12', 21, 640),
      callReading('call-20', 1_073, 900),
    ]);
    expect(
      resolveConversationToolCalls(
        readings,
        'callee',
        ['call-10', 'call-12'],
        new Map(),
      ),
    ).toBe(141);
  });

  it('adds only the rows the daemon counted before, and only the agent’s own', () => {
    const readings = reading([callReading('call-12', 21, 640)]);
    const seqs = ownToolCallSeqsByCall([
      // Already in the daemon's 21.
      toolRow(630, 'call-12'),
      toolRow(640, 'call-12'),
      // Written after the read: the turn in flight.
      toolRow(650, 'call-12'),
      toolRow(660, 'call-12'),
      // A sub-agent's, another agent's, and the run's own flow.
      toolRow(670, 'call-12', 'callee', 'toolu_sub'),
      toolRow(680, 'call-12', 'other'),
      toolRow(690, '', 'callee'),
    ]);
    expect(
      resolveConversationToolCalls(readings, 'callee', ['call-12'], seqs),
    ).toBe(23);
  });

  it('counts a call the daemon has not read yet from its rows alone', () => {
    const readings = reading([callReading('call-10', 120, 500)]);
    const seqs = ownToolCallSeqsByCall([
      toolRow(700, 'call-12'),
      toolRow(710, 'call-12'),
    ]);
    expect(
      resolveConversationToolCalls(
        readings,
        'callee',
        ['call-10', 'call-12'],
        seqs,
      ),
    ).toBe(122);
  });

  it('adds every own row of a call read before its first tool', () => {
    const readings = reading([callReading('call-12', 0, null)]);
    const seqs = ownToolCallSeqsByCall([
      toolRow(700, 'call-12'),
      toolRow(710, 'call-12'),
    ]);
    expect(
      resolveConversationToolCalls(readings, 'callee', ['call-12'], seqs),
    ).toBe(2);
  });

  it('counts own rows by the same rule before the daemon has read the conversation at all', () => {
    // No reading yet: a sub-agent's row must not be counted now and dropped
    // once the daemon's own-tools figure arrives.
    const seqs = ownToolCallSeqsByCall([
      toolRow(700, 'call-12'),
      toolRow(710, 'call-12', 'callee', 'toolu_sub'),
    ]);
    expect(
      resolveConversationToolCalls(NO_ROWS, 'callee', ['call-12'], seqs),
    ).toBe(1);
  });

  it('answers null when the conversation has neither a reading nor a row, so the card folds instead', () => {
    expect(
      resolveConversationToolCalls(
        reading([callReading('call-10', 120, 500)]),
        'callee',
        ['call-12'],
        ownToolCallSeqsByCall([toolRow(700, 'call-10')]),
      ),
    ).toBeNull();
  });
});

describe('the running part of a conversation’s cost', () => {
  const costing = (spentCostUsd: number | null): LiveState => ({
    ...live(null, null),
    spentCostUsd,
  });
  const plane: ReadonlyMap<string, LiveState> = new Map([
    [partialOwnerKey('callee', 'call-1'), costing(1.25)],
    [partialOwnerKey('callee', 'call-2'), costing(0.5)],
    ['callee', costing(2)],
    [partialOwnerKey('other', 'call-3'), costing(9)],
    [partialOwnerKey('callee', 'call-4'), costing(null)],
  ]);

  it('sums the calls a conversation names, under their per-call keys', () => {
    expect(liveConversationCost(plane, 'callee', ['call-1', 'call-2'])).toEqual(
      { costUsd: 1.75, estimatedCostUsd: null },
    );
  });

  it('sums the part of the running cost geniro priced itself', () => {
    const priced: ReadonlyMap<string, LiveState> = new Map([
      [
        partialOwnerKey('callee', 'call-1'),
        { ...costing(1), spentEstimatedCostUsd: 1 },
      ],
      [partialOwnerKey('callee', 'call-2'), costing(0.5)],
    ]);
    expect(
      liveConversationCost(priced, 'callee', ['call-1', 'call-2']),
    ).toEqual({ costUsd: 1.5, estimatedCostUsd: 1 });
  });

  it('answers null — not 0 — when nothing running has reported', () => {
    expect(liveConversationCost(plane, 'callee', ['call-4'])).toBeNull();
    expect(liveConversationCost(NO_LIVE, 'callee', ['call-1'])).toBeNull();
  });

  it('sums EVERY conversation of one node for its card, and no other node’s', () => {
    expect(liveNodeCost(plane, 'callee')?.costUsd).toBe(3.75);
  });

  it('sums the whole open run for the thread’s header', () => {
    expect(liveRunCost(plane)?.costUsd).toBe(12.75);
  });

  it('adds the running part to a recorded spend', () => {
    // The reported undercount: a call hours into its turn stated the turns
    // that had FINISHED as the bill.
    expect(
      withLiveCost(
        { tokens: 900, costUsd: 1.25 },
        { costUsd: 3, estimatedCostUsd: null },
      ),
    ).toEqual({ tokens: 900, costUsd: 4.25 });
  });

  it('takes the running part as the whole cost of a first turn still going', () => {
    const running = { costUsd: 0.4, estimatedCostUsd: null };
    expect(withLiveCost(null, running)).toEqual({
      tokens: null,
      costUsd: 0.4,
    });
    expect(withLiveCost({ tokens: 10, costUsd: null }, running)).toEqual({
      tokens: 10,
      costUsd: 0.4,
    });
  });

  it('leaves a spend alone when nothing is running, or nothing is unrecorded', () => {
    const spend = { tokens: 5, costUsd: 1 };
    expect(withLiveCost(spend, null)).toBe(spend);
    expect(withLiveCost(spend, { costUsd: 0, estimatedCostUsd: null })).toBe(
      spend,
    );
    expect(withLiveCost(null, null)).toBeNull();
  });

  it('adds the running part geniro priced itself to the recorded estimate', () => {
    expect(
      withLiveCost(
        { tokens: 5, costUsd: 1, estimatedCostUsd: 0.25 },
        { costUsd: 2, estimatedCostUsd: 2 },
      ),
    ).toEqual({ tokens: 5, costUsd: 3, estimatedCostUsd: 2.25 });
    // A running part that is the CLI's own bill leaves the estimate as it was.
    expect(
      withLiveCost(
        { tokens: 5, costUsd: 1, estimatedCostUsd: 0.25 },
        { costUsd: 2, estimatedCostUsd: null },
      ).estimatedCostUsd,
    ).toBe(0.25);
  });
});

describe('resolveConversationCacheExpiry', () => {
  const call = (
    callId: string,
    promptCacheExpiresAt: string | null,
  ): CallEntry => ({
    callId,
    contextTokens: null,
    contextEstimated: false,
    contextWindowTokens: null,
    totals: NO_TOTALS,
    toolCalls: 0,
    toolCallsThroughSeq: null,
    start: null,
    promptCacheExpiresAt,
  });

  it('takes the newest call of the conversation that states an expiry', () => {
    const rows = reading([
      call('call-1', '2026-10-11T10:00:00.000Z'),
      call('call-4', '2026-10-11T11:00:00.000Z'),
      call('call-9', null),
    ]);
    expect(
      resolveConversationCacheExpiry(rows, 'callee', [
        'call-1',
        'call-4',
        'call-9',
      ]),
    ).toBe('2026-10-11T11:00:00.000Z');
  });

  it('answers null when no call of the conversation states one', () => {
    const rows = reading([call('call-1', null)]);
    expect(resolveConversationCacheExpiry(rows, 'callee', ['call-1'])).toBe(
      null,
    );
    expect(resolveConversationCacheExpiry(rows, 'other', ['call-1'])).toBe(
      null,
    );
  });
});
