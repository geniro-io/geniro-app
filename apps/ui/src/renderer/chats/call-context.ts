import type {
  CallContextReading,
  ChatTotals,
  ItemDto as ChatItem,
} from '../autogenerated';
import { type LiveState, ownerOfKey, partialOwnerKey } from './live-text';
import { subagentIdOf } from './subagent-payload';
import type { CallTurnDuration, OpenTurn } from './turn-duration';
import type { NodeDurableReading } from './use-node-context';

/**
 * How full ONE call thread's own context window is.
 *
 * DERIVED from the daemon's own row rather than restated — the wire type minus
 * the id, which every caller here already holds. A hand-written pair would be a
 * second definition of the same two figures, free to drift from the row it is
 * resolved out of.
 */
export type CalleeContext = Pick<
  CallContextReading,
  'contextTokens' | 'contextWindowTokens'
> &
  Partial<Pick<CallContextReading, 'contextEstimated'>>;

/**
 * What one conversation has SPENT — tokens in and out, and money — in the
 * shape a call block's own fold answers (`callBlockUsage`).
 */
export interface CallSpend {
  tokens: number | null;
  costUsd: number | null;
  /** Of {@link costUsd}, the part geniro priced itself; absent when none. */
  estimatedCostUsd?: number | null;
}

/**
 * Dollars a RUNNING turn has spent that no durable row carries yet, and the
 * part of them geniro priced itself — the live plane's `spentCostUsd` pair.
 */
export interface LiveCost {
  costUsd: number;
  estimatedCostUsd: number | null;
}

/** A call conversation's reading: its window, plus its whole-run spend. */
export type CalleeReading = CalleeContext & {
  /** Null when the daemon has no figure for it yet — fall back to the fold. */
  spend?: CallSpend | null;
  /**
   * Dollars the conversation's RUNNING turn has spent that {@link spend} does
   * not include yet — added on top of whichever of spend or fold is drawn
   * ({@link withLiveCost}). Null when nothing running has reported one.
   */
  liveCost?: LiveCost | null;
  /**
   * How many tools the callee ran in this CONVERSATION — every call that
   * continued it, its CLI sub-agents' excluded. Never the agent's run-wide
   * total: an agent answers many separate conversations in one run.
   *
   * Null when the daemon has no count — the fold is the fallback, on the same
   * rule {@link spend} follows.
   */
  toolCalls?: number | null;
  /**
   * How long the callee has worked in this CONVERSATION over its settled
   * turns — the daemon's per-call figure plus the turns it was read before.
   * Null when no turn of it was measured.
   */
  workedMs?: number | null;
  /** The conversation's turn in flight, which a clock adds to {@link workedMs}. */
  openTurns?: readonly OpenTurn[];
};

type CallFigures = NodeDurableReading['callFigures'][number];

/**
 * A node's call figures by call id, built once per reading: the list is every
 * call of the run, and each card and panel row looks several of them up.
 */
const figuresIndex = new WeakMap<
  readonly CallFigures[],
  ReadonlyMap<string, CallFigures>
>();

const EMPTY_FIGURES: ReadonlyMap<string, CallFigures> = new Map();

function figuresOf(
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  nodeId: string,
): ReadonlyMap<string, CallFigures> {
  const list = nodeReadings.get(nodeId)?.callFigures;
  if (list === undefined) {
    return EMPTY_FIGURES;
  }
  let index = figuresIndex.get(list);
  if (index === undefined) {
    index = new Map(list.map((figures) => [figures.callId, figures]));
    figuresIndex.set(list, index);
  }
  return index;
}

/**
 * The seqs of each call's own tool calls among `rows` — rows filed under a
 * call (`inCall`), sub-agents' excluded — keyed by {@link callToolKey}.
 *
 * TWIN PARSER: `ItemDao.ownToolCallsByCall` in
 * apps/daemon/src/v1/agents/dao/item.dao.ts counts the rows up to its seq by
 * the same rule; the two must agree on which rows count.
 */
export function ownToolCallSeqsByCall(
  rows: readonly ChatItem[],
): ReadonlyMap<string, readonly number[]> {
  const seqs = new Map<string, number[]>();
  for (const row of rows) {
    if (
      row.kind !== 'tool_call' ||
      row.nodeId == null ||
      typeof row.inCall !== 'string' ||
      row.inCall === '' ||
      subagentIdOf(row) !== null
    ) {
      continue;
    }
    const key = callToolKey(row.nodeId, row.inCall);
    const forCall = seqs.get(key);
    if (forCall === undefined) {
      seqs.set(key, [row.seq]);
    } else {
      forCall.push(row.seq);
    }
  }
  return seqs;
}

function callToolKey(nodeId: string, callId: string): string {
  return `${nodeId}\u0000${callId}`;
}

/**
 * The tools one CONVERSATION has run: each call's daemon count, plus the rows
 * the client holds that the count was read before (seq above its
 * `toolCallsThroughSeq`) — a turn in flight, or one settled since the read.
 *
 * A call the daemon has not read yet (it started since the last read) counts
 * the rows the client holds of it.
 *
 * Null when the conversation has neither a reading nor a row of its own, the
 * caller's cue to use its fold.
 */
export function resolveConversationToolCalls(
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callIds: readonly string[],
  ownToolSeqs: ReadonlyMap<string, readonly number[]>,
): number | null {
  const figures = figuresOf(nodeReadings, calleeNodeId);
  let total: number | null = null;
  for (const callId of callIds) {
    const call = figures.get(callId);
    const seqs = ownToolSeqs.get(callToolKey(calleeNodeId, callId)) ?? [];
    if (call === undefined) {
      if (seqs.length > 0) {
        total = (total ?? 0) + seqs.length;
      }
      continue;
    }
    const through = call.toolCallsThroughSeq;
    total =
      (total ?? 0) +
      call.toolCalls +
      (through === null
        ? seqs.length
        : seqs.filter((seq) => seq > through).length);
  }
  return total;
}

/**
 * What one CONVERSATION has worked: each call's daemon figure, plus the turns
 * the client holds that the figure was read before (seq above its
 * `workedThroughSeq`); and the turn still open, for a clock to add as it runs.
 *
 * A call the daemon has no figure for counts every settled turn the client
 * holds of it. `workedMs` is null when nothing was measured at all.
 */
export function resolveConversationWorked(
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callIds: readonly string[],
  turns: {
    durations: ReadonlyMap<string, readonly CallTurnDuration[]>;
    open: ReadonlyMap<string, OpenTurn>;
  },
): { workedMs: number | null; openTurns: readonly OpenTurn[] } {
  const figures = figuresOf(nodeReadings, calleeNodeId);
  let workedMs: number | null = null;
  const openTurns: OpenTurn[] = [];
  for (const callId of callIds) {
    const call = figures.get(callId);
    const through = call?.workedThroughSeq ?? null;
    workedMs = addFigure(workedMs, call?.workedMs ?? null);
    for (const turn of turns.durations.get(callId) ?? []) {
      if (through === null || turn.seq > through) {
        workedMs = (workedMs ?? 0) + turn.ms;
      }
    }
    const open = turns.open.get(callId);
    if (open !== undefined) {
      openTurns.push(open);
    }
  }
  return { workedMs, openTurns };
}

/**
 * The daemon's totals as a spend, or null when no turn reported any — so a
 * caller falls back to its own fold rather than drawing a zero nobody measured.
 */
export function spendOfTotals(
  totals: ChatTotals | undefined,
): CallSpend | null {
  if (totals === undefined || totals.turns === 0) {
    return null;
  }
  const tokens =
    totals.inputTokens === null && totals.outputTokens === null
      ? null
      : (totals.inputTokens ?? 0) + (totals.outputTokens ?? 0);
  return withEstimate(
    { tokens, costUsd: totals.costUsd },
    totals.estimatedCostUsd,
  );
}

/** A spend carrying its estimated part only when it has one. */
function withEstimate<T extends CallSpend>(
  spend: T,
  estimatedCostUsd: number | null | undefined,
): T {
  const { estimatedCostUsd: _previous, ...rest } = spend;
  return estimatedCostUsd === null || estimatedCostUsd === undefined
    ? (rest as T)
    : ({ ...rest, estimatedCostUsd } as T);
}

/**
 * A CONVERSATION's spend over the WHOLE run — every call that continued it,
 * summed from the daemon's per-call totals.
 *
 * The transcript fold can only sum the turns the loaded window holds, so a
 * call that started above it — or a long conversation continued many times —
 * read a fraction of what it cost. Null when no call of the conversation has a
 * durable figure yet (a reading not fetched, a turn not yet settled), which is
 * the caller's cue to use its fold.
 */
export function resolveConversationSpend(
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callIds: readonly string[],
): CallSpend | null {
  const figures = figuresOf(nodeReadings, calleeNodeId);
  const found: CallSpend = { tokens: null, costUsd: null };
  let estimated: number | null = null;
  let measured = false;
  for (const callId of callIds) {
    const spend = spendOfTotals(figures.get(callId)?.totals);
    if (spend === null) {
      continue;
    }
    measured = true;
    found.tokens = addFigure(found.tokens, spend.tokens);
    found.costUsd = addFigure(found.costUsd, spend.costUsd);
    estimated = addFigure(estimated, spend.estimatedCostUsd ?? null);
  }
  return measured ? withEstimate(found, estimated) : null;
}

function addFigure(a: number | null, b: number | null): number | null {
  return a === null && b === null ? null : (a ?? 0) + (b ?? 0);
}

/**
 * What the RUNNING part of a conversation has cost — dollars no durable row
 * carries yet, summed over the calls it names — or null when nothing running
 * has reported one.
 *
 * The daemon publishes it per call key and drops it to zero as the turn's own
 * row records the same money, so it is ADDED to a recorded spend
 * ({@link withLiveCost}), never chosen over one. Without it a running call's
 * card states only its finished turns, as if that were the bill.
 */
export function liveConversationCost(
  liveText: ReadonlyMap<string, LiveState>,
  calleeNodeId: string,
  callIds: readonly string[],
): LiveCost | null {
  let total: LiveCost | null = null;
  for (const callId of callIds) {
    total = addLive(total, liveText.get(partialOwnerKey(calleeNodeId, callId)));
  }
  return total;
}

/**
 * The same figure over EVERY conversation of one node — its own turn's key and
 * each call's — for a card that states the agent's whole spend.
 */
export function liveNodeCost(
  liveText: ReadonlyMap<string, LiveState>,
  nodeId: string,
): LiveCost | null {
  let total: LiveCost | null = null;
  for (const [key, state] of liveText) {
    if (ownerOfKey(key) === nodeId) {
      total = addLive(total, state);
    }
  }
  return total;
}

/**
 * The same figure over the WHOLE open run — every key the live plane holds,
 * since that plane is dropped on a run switch — for the header's thread total.
 */
export function liveRunCost(
  liveText: ReadonlyMap<string, LiveState>,
): LiveCost | null {
  let total: LiveCost | null = null;
  for (const state of liveText.values()) {
    total = addLive(total, state);
  }
  return total;
}

/** A spend as the agents panel's two money fields. */
export function spentOf(spend: CallSpend | null): {
  spentUsd: number | null;
  spentEstimatedUsd: number | null;
} {
  return {
    spentUsd: spend?.costUsd ?? null,
    spentEstimatedUsd: spend?.estimatedCostUsd ?? null,
  };
}

/** One live state's running spend, or null when it has reported none. */
export function liveCostOf(state: LiveState | undefined): LiveCost | null {
  return addLive(null, state);
}

/**
 * A recorded spend with the running part added, or the spend unchanged when
 * nothing is running. A spend with no recorded money yet (a first turn still
 * going) takes the running figure as its whole cost rather than staying blank.
 */
export function withLiveCost<T extends CallSpend>(
  spend: T,
  live: LiveCost | null,
): T;
export function withLiveCost<T extends CallSpend>(
  spend: T | null,
  live: LiveCost | null,
): T | CallSpend | null;
export function withLiveCost<T extends CallSpend>(
  spend: T | null,
  live: LiveCost | null,
): T | CallSpend | null {
  if (live === null || live.costUsd <= 0) {
    return spend;
  }
  if (spend === null) {
    return withEstimate(
      { tokens: null, costUsd: live.costUsd },
      live.estimatedCostUsd,
    );
  }
  return withEstimate(
    { ...spend, costUsd: (spend.costUsd ?? 0) + live.costUsd },
    addFigure(spend.estimatedCostUsd ?? null, live.estimatedCostUsd),
  );
}

function addLive(
  total: LiveCost | null,
  state: LiveState | undefined,
): LiveCost | null {
  const part = state?.spentCostUsd;
  if (part === null || part === undefined) {
    return total;
  }
  return {
    costUsd: (total?.costUsd ?? 0) + part,
    estimatedCostUsd: addFigure(
      total?.estimatedCostUsd ?? null,
      state?.spentEstimatedCostUsd ?? null,
    ),
  };
}

/**
 * One call thread's context reading, live first.
 *
 * The TWO ranks a call block cannot fold for itself. A callee's `turn_complete`
 * rows are the only source inside the block, and they do not exist until the
 * callee finishes — so a ring folded from them alone is empty for the whole of
 * a call and fills at the moment there is nothing left to watch. REPORTED
 * against a running cursor call, and MEASURED on that same run: no ring for 46
 * seconds, then `80.4k / 200k` the instant the call settled.
 *
 * Both ranks are per CALL rather than per node, which is what makes them usable
 * here at all: the daemon publishes a callee's deltas under
 * {@link partialOwnerKey} and files its durable row on `call_context` keyed
 * `(runId, callId)`, so a node serving several calls at once has one reading
 * each rather than one flickering between windows.
 *
 * Each figure falls back on its OWN — the daemon's rule that a reading omitting
 * one half says nothing about it, so a delta carrying only a count must not
 * erase the window a durable row already had. Safe across the ranks for the
 * reason `callThreadsOf` gives about its own pair: a window is a property of
 * the model and does not move between one call's turns.
 *
 * EXTRACTED rather than written twice. The sidebar's per-call thread rings
 * resolve the identical pair, and `Chats.tsx` says at `cardContextOf` why that
 * matters — two copies of this order is how a card and its own thread rows come
 * to disagree about one window. A call block is the third surface drawing this
 * figure, so the order now lives in one place for all three.
 */
export function resolveCalleeContext(
  liveText: ReadonlyMap<string, LiveState>,
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callId: string,
): CalleeContext {
  const live = liveText.get(partialOwnerKey(calleeNodeId, callId));
  const row = nodeReadings
    .get(calleeNodeId)
    ?.calls.find((call) => call.callId === callId);
  // A live count is the CLI's own; only the durable row can be a stand-in.
  const estimated =
    live?.contextTokens == null && row?.contextEstimated === true;
  return {
    contextTokens: live?.contextTokens ?? row?.contextTokens ?? null,
    contextWindowTokens:
      live?.contextWindowTokens ?? row?.contextWindowTokens ?? null,
    ...(estimated ? { contextEstimated: true } : {}),
  };
}

/**
 * A CONVERSATION's context reading, across the calls that continued it — the
 * newest call carrying each figure.
 *
 * One continued conversation is one callee session, so its latest call's
 * reading is the one to draw; but a continuation that has only just started
 * has reported nothing yet, and the session it resumed still holds the window
 * the previous call left, so each figure falls back through the earlier calls
 * rather than blanking the ring between two asks.
 */
export function resolveConversationContext(
  liveText: ReadonlyMap<string, LiveState>,
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callIds: readonly string[],
): CalleeContext {
  const found: CalleeContext = {
    contextTokens: null,
    contextWindowTokens: null,
  };
  for (let i = callIds.length - 1; i >= 0; i -= 1) {
    const reading = resolveCalleeContext(
      liveText,
      nodeReadings,
      calleeNodeId,
      callIds[i]!,
    );
    if (found.contextTokens === null && reading.contextTokens !== null) {
      found.contextTokens = reading.contextTokens;
      if (reading.contextEstimated === true) {
        found.contextEstimated = true;
      }
    }
    found.contextWindowTokens ??= reading.contextWindowTokens;
  }
  return found;
}

/**
 * When a CONVERSATION's prompt cache lapses (ISO), from the newest of its calls
 * the daemon stated one for — or null when none did (no call has settled, or
 * its CLI reports no cache lifetime).
 */
export function resolveConversationCacheExpiry(
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callIds: readonly string[],
): string | null {
  const figures = figuresOf(nodeReadings, calleeNodeId);
  for (let i = callIds.length - 1; i >= 0; i -= 1) {
    const expiresAt = figures.get(callIds[i]!)?.promptCacheExpiresAt;
    if (typeof expiresAt === 'string') {
      return expiresAt;
    }
  }
  return null;
}

/**
 * Answers {@link resolveConversationContext} for one conversation, bound to the
 * open run — the ONE rule a call card's ring and the agents panel's instance
 * ring both read, so a continuation that has not reported yet cannot draw two
 * different rings for one conversation.
 */
export type CalleeContextResolver = (
  calleeNodeId: string,
  callIds: readonly string[],
) => CalleeReading;

/**
 * Where a call block's ring gets a reading from while the call is still open.
 *
 * A CONTEXT rather than a prop, on the rule `AttachmentLoaderContext` already
 * follows: every row shell between `Chats` and a call block is memoized, and a
 * block nests inside another block's entries, so threading this down would mean
 * a new prop on each of them and one more place to forget it. It is also the
 * only shape that reaches the sub-agent detail dialog and the workflow card,
 * each of which renders a transcript as a sibling subtree of the main one.
 *
 * Null means NO source — a spec rendering the block bare, and any surface
 * mounted outside the provider. The block then falls back to what it can fold
 * out of its own rows.
 */
export const CalleeContextResolverContext =
  createContext<CalleeContextResolver | null>(null);
