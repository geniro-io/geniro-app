import { createContext } from 'react';

import type { CallContextReading } from '../autogenerated';
import { type LiveState, partialOwnerKey } from './live-text';
import type { NodeDurableReading } from './use-node-context';

/**
 * How full ONE call thread's own context window is.
 *
 * DERIVED from the daemon's own row rather than restated — the wire type minus
 * the id, which every caller here already holds. A hand-written pair would be a
 * second definition of the same two figures, free to drift from the row it is
 * resolved out of.
 */
export type CalleeContext = Omit<CallContextReading, 'callId'>;

/**
 * One call thread's context reading, live first.
 *
 * The TWO ranks a call block cannot fold for itself. A callee's `turn_complete`
 * rows are the only source inside the block, and they do not exist until the
 * callee finishes — so a ring folded from them alone is empty for the whole of
 * a call and fills at the moment there is nothing left to watch. REPORTED
 * against a running cursor call, and MEASURED on that same run: no ring for 46
 * seconds, then `80.4k / 200k` the instant the call settled.
 *
 * Both ranks are per CALL rather than per node, which is what makes them usable
 * here at all: the daemon publishes a callee's deltas under
 * {@link partialOwnerKey} and files its durable row on `call_context` keyed
 * `(runId, callId)`, so a node serving several calls at once has one reading
 * each rather than one flickering between windows.
 *
 * Each figure falls back on its OWN — the daemon's rule that a reading omitting
 * one half says nothing about it, so a delta carrying only a count must not
 * erase the window a durable row already had. Safe across the ranks for the
 * reason `callThreadsOf` gives about its own pair: a window is a property of
 * the model and does not move between one call's turns.
 *
 * EXTRACTED rather than written twice. The sidebar's per-call thread rings
 * resolve the identical pair, and `Chats.tsx` says at `cardContextOf` why that
 * matters — two copies of this order is how a card and its own thread rows come
 * to disagree about one window. A call block is the third surface drawing this
 * figure, so the order now lives in one place for all three.
 */
export function resolveCalleeContext(
  liveText: ReadonlyMap<string, LiveState>,
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callId: string,
): CalleeContext {
  const live = liveText.get(partialOwnerKey(calleeNodeId, callId));
  const row = nodeReadings
    .get(calleeNodeId)
    ?.calls.find((call) => call.callId === callId);
  return {
    contextTokens: live?.contextTokens ?? row?.contextTokens ?? null,
    contextWindowTokens:
      live?.contextWindowTokens ?? row?.contextWindowTokens ?? null,
  };
}

/** Answers {@link resolveCalleeContext} for one call, bound to the open run. */
export type CalleeContextResolver = (
  calleeNodeId: string,
  callId: string,
) => CalleeContext;

/**
 * Where a call block's ring gets a reading from while the call is still open.
 *
 * A CONTEXT rather than a prop, on the rule `AttachmentLoaderContext` already
 * follows: every row shell between `Chats` and a call block is memoized, and a
 * block nests inside another block's entries, so threading this down would mean
 * a new prop on each of them and one more place to forget it. It is also the
 * only shape that reaches the sub-agent detail dialog and the workflow card,
 * each of which renders a transcript as a sibling subtree of the main one.
 *
 * Null means NO source — a spec rendering the block bare, and any surface
 * mounted outside the provider. The block then falls back to what it can fold
 * out of its own rows, which is exactly what it did before this existed.
 */
export const CalleeContextResolverContext =
  createContext<CalleeContextResolver | null>(null);
