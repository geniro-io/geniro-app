import { createContext } from 'react';

import type { CallContextReading, ChatTotals } from '../autogenerated';
import { type LiveState, partialOwnerKey } from './live-text';
import type { NodeDurableReading } from './use-node-context';

/**
 * How full ONE call thread's own context window is.
 *
 * DERIVED from the daemon's own row rather than restated — the wire type minus
 * the id, which every caller here already holds. A hand-written pair would be a
 * second definition of the same two figures, free to drift from the row it is
 * resolved out of.
 */
export type CalleeContext = Pick<
  CallContextReading,
  'contextTokens' | 'contextWindowTokens'
>;

/**
 * What one conversation has SPENT — tokens in and out, and money — in the
 * shape a call block's own fold answers (`callBlockUsage`).
 */
export interface CallSpend {
  tokens: number | null;
  costUsd: number | null;
}

/** A call conversation's reading: its window, plus its whole-run spend. */
export type CalleeReading = CalleeContext & {
  /** Null when the daemon has no figure for it yet — fall back to the fold. */
  spend?: CallSpend | null;
  /**
   * How many tools this AGENT has run in the whole workflow — the daemon's own
   * running count (`node_state.tool_calls`), not a fold of what is on screen.
   *
   * Per agent rather than per call, and that is the point: one agent is asked
   * again and again on the same conversation, so "what has it done" is the sum
   * over every one of those calls. The fold could only ever answer for the
   * LATEST call, and only for the part of it inside the loaded window —
   * REPORTED as `36 tools` on a card whose agent had by then run 2,543, with
   * 45 of them in the call the card was drawn for.
   *
   * Null when the daemon has no count — the fold is the fallback, on the same
   * rule {@link spend} follows.
   */
  toolCalls?: number | null;
};

/**
 * Every tool one agent has run in this workflow, or null when the daemon has
 * no count for it — see {@link CalleeReading.toolCalls}.
 *
 * Keyed by the NODE and not by its calls, because the count is the node's: the
 * daemon accumulates it per node as each turn settles, calls and DAG turns
 * alike, so there is nothing per call to sum.
 */
export function resolveNodeToolCalls(
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
): number | null {
  return nodeReadings.get(calleeNodeId)?.toolCalls ?? null;
}

/**
 * The daemon's totals as a spend, or null when no turn reported any — so a
 * caller falls back to its own fold rather than drawing a zero nobody measured.
 */
export function spendOfTotals(
  totals: ChatTotals | undefined,
): CallSpend | null {
  if (totals === undefined || totals.turns === 0) {
    return null;
  }
  const tokens =
    totals.inputTokens === null && totals.outputTokens === null
      ? null
      : (totals.inputTokens ?? 0) + (totals.outputTokens ?? 0);
  return { tokens, costUsd: totals.costUsd };
}

/**
 * A CONVERSATION's spend over the WHOLE run — every call that continued it,
 * summed from the daemon's per-call totals.
 *
 * The transcript fold can only sum the turns the loaded window holds, so a
 * call that started above it — or a long conversation continued many times —
 * read a fraction of what it cost. Null when no call of the conversation has a
 * durable figure yet (a reading not fetched, a turn not yet settled), which is
 * the caller's cue to use its fold.
 */
export function resolveConversationSpend(
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callIds: readonly string[],
): CallSpend | null {
  const calls = nodeReadings.get(calleeNodeId)?.calls ?? [];
  const found: CallSpend = { tokens: null, costUsd: null };
  let measured = false;
  for (const callId of callIds) {
    const spend = spendOfTotals(
      calls.find((call) => call.callId === callId)?.totals,
    );
    if (spend === null) {
      continue;
    }
    measured = true;
    found.tokens = addFigure(found.tokens, spend.tokens);
    found.costUsd = addFigure(found.costUsd, spend.costUsd);
  }
  return measured ? found : null;
}

function addFigure(a: number | null, b: number | null): number | null {
  return a === null && b === null ? null : (a ?? 0) + (b ?? 0);
}

/**
 * One call thread's context reading, live first.
 *
 * The TWO ranks a call block cannot fold for itself. A callee's `turn_complete`
 * rows are the only source inside the block, and they do not exist until the
 * callee finishes — so a ring folded from them alone is empty for the whole of
 * a call and fills at the moment there is nothing left to watch. REPORTED
 * against a running cursor call, and MEASURED on that same run: no ring for 46
 * seconds, then `80.4k / 200k` the instant the call settled.
 *
 * Both ranks are per CALL rather than per node, which is what makes them usable
 * here at all: the daemon publishes a callee's deltas under
 * {@link partialOwnerKey} and files its durable row on `call_context` keyed
 * `(runId, callId)`, so a node serving several calls at once has one reading
 * each rather than one flickering between windows.
 *
 * Each figure falls back on its OWN — the daemon's rule that a reading omitting
 * one half says nothing about it, so a delta carrying only a count must not
 * erase the window a durable row already had. Safe across the ranks for the
 * reason `callThreadsOf` gives about its own pair: a window is a property of
 * the model and does not move between one call's turns.
 *
 * EXTRACTED rather than written twice. The sidebar's per-call thread rings
 * resolve the identical pair, and `Chats.tsx` says at `cardContextOf` why that
 * matters — two copies of this order is how a card and its own thread rows come
 * to disagree about one window. A call block is the third surface drawing this
 * figure, so the order now lives in one place for all three.
 */
export function resolveCalleeContext(
  liveText: ReadonlyMap<string, LiveState>,
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callId: string,
): CalleeContext {
  const live = liveText.get(partialOwnerKey(calleeNodeId, callId));
  const row = nodeReadings
    .get(calleeNodeId)
    ?.calls.find((call) => call.callId === callId);
  return {
    contextTokens: live?.contextTokens ?? row?.contextTokens ?? null,
    contextWindowTokens:
      live?.contextWindowTokens ?? row?.contextWindowTokens ?? null,
  };
}

/**
 * A CONVERSATION's context reading, across the calls that continued it — the
 * newest call carrying each figure.
 *
 * One continued conversation is one callee session, so its latest call's
 * reading is the one to draw; but a continuation that has only just started
 * has reported nothing yet, and the session it resumed still holds the window
 * the previous call left, so each figure falls back through the earlier calls
 * rather than blanking the ring between two asks.
 */
export function resolveConversationContext(
  liveText: ReadonlyMap<string, LiveState>,
  nodeReadings: ReadonlyMap<string, NodeDurableReading>,
  calleeNodeId: string,
  callIds: readonly string[],
): CalleeContext {
  const found: CalleeContext = {
    contextTokens: null,
    contextWindowTokens: null,
  };
  for (let i = callIds.length - 1; i >= 0; i -= 1) {
    const reading = resolveCalleeContext(
      liveText,
      nodeReadings,
      calleeNodeId,
      callIds[i]!,
    );
    found.contextTokens ??= reading.contextTokens;
    found.contextWindowTokens ??= reading.contextWindowTokens;
  }
  return found;
}

/**
 * Answers {@link resolveConversationContext} for one conversation, bound to the
 * open run — the ONE rule a call card's ring and the agents panel's instance
 * ring both read, so a continuation that has not reported yet cannot draw two
 * different rings for one conversation.
 */
export type CalleeContextResolver = (
  calleeNodeId: string,
  callIds: readonly string[],
) => CalleeReading;

/**
 * Where a call block's ring gets a reading from while the call is still open.
 *
 * A CONTEXT rather than a prop, on the rule `AttachmentLoaderContext` already
 * follows: every row shell between `Chats` and a call block is memoized, and a
 * block nests inside another block's entries, so threading this down would mean
 * a new prop on each of them and one more place to forget it. It is also the
 * only shape that reaches the sub-agent detail dialog and the workflow card,
 * each of which renders a transcript as a sibling subtree of the main one.
 *
 * Null means NO source — a spec rendering the block bare, and any surface
 * mounted outside the provider. The block then falls back to what it can fold
 * out of its own rows.
 */
export const CalleeContextResolverContext =
  createContext<CalleeContextResolver | null>(null);
