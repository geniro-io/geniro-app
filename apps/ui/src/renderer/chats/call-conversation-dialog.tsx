import { useEffect, useMemo, useRef, useState } from 'react';

import type {
  ChatsApi,
  ItemDto as ChatItem,
  RunStateDto,
} from '../autogenerated';
import { Dialog } from '../components/ui/dialog';
import type { DaemonClient } from '../daemon-client';
import { CallConversationBody } from './call-block';
import {
  CallConversationContext,
  CallConversationPager,
} from './call-conversation';
import { useDurableTranscript } from './durable-transcript';
import { mergeAnchorRows } from './history-anchors';
import { callBlockOfConversation, indexCallBlocks } from './transcript-groups';
import type { TranscriptNodeMeta } from './transcript-item';
import { payloadString } from './transcript-payload';
import { useCallPages } from './use-call-pages';
import { WorkingAgentHead, WorkingAgentTitle } from './working-agent-row';
import type { WorkingAgentRow } from './working-agents';

/** How many rows one page of the popup asks for. */
const CONVERSATION_PAGE = 200;

/**
 * The conversation's calls, and every call the rows name as continuing one of
 * them: a continuation the popup sees start is on nobody's list yet. Read in seq
 * order, so a continuation of a continuation counts too.
 */
function callsInside(
  rows: readonly ChatItem[],
  chain: readonly string[],
): ReadonlySet<string> {
  const inside = new Set(chain);
  for (const row of rows) {
    const callId = payloadString(row.payload, 'callId');
    const thread = payloadString(row.payload, 'thread');
    if (
      row.kind === 'call_started' &&
      callId !== null &&
      thread !== null &&
      inside.has(thread)
    ) {
      inside.add(callId);
    }
  }
  return inside;
}

/**
 * A call's start and settle are filed in its caller's flow, so they are matched
 * on the call they name, and a continuation's start on the call it continues.
 */
function belongsInside(
  item: ChatItem,
  runId: string,
  inside: ReadonlySet<string>,
): boolean {
  if (item.runId !== runId) {
    return false;
  }
  if (typeof item.inCall === 'string' && inside.has(item.inCall)) {
    return true;
  }
  if (item.kind !== 'call_started' && item.kind !== 'call_result') {
    return false;
  }
  return [
    payloadString(item.payload, 'callId'),
    payloadString(item.payload, 'thread'),
  ].some((callId) => callId !== null && inside.has(callId));
}

function ConversationBody({
  row,
  runId,
  api,
  client,
  nodes,
  chatAgentName,
  delegateState,
  collapseToolSteps,
}: {
  row: WorkingAgentRow;
  runId: string;
  api: Pick<ChatsApi, 'listRunItems'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
  nodes?: ReadonlyMap<string, TranscriptNodeMeta>;
  chatAgentName?: string | null;
  delegateState?: Pick<RunStateDto, 'throughSeq' | 'delegates' | 'calls'>;
  collapseToolSteps: boolean;
}): React.JSX.Element {
  const [rows, setRows] = useState<ChatItem[]>([]);
  const runIdRef = useRef<string | null>(runId);
  const pageSizeRef = useRef(CONVERSATION_PAGE);
  const { callConversations } = useCallPages({
    runIdRef,
    api,
    pageSizeRef,
    commitRows: setRows,
  });
  const insideRef = useRef<ReadonlySet<string>>(new Set(row.callIds));
  insideRef.current = useMemo(
    () => callsInside(rows, row.callIds),
    [rows, row.callIds],
  );
  const { retry } = callConversations;
  useEffect(() => {
    const offItem = client.onItem((item) => {
      if (belongsInside(item, runId, insideRef.current)) {
        setRows((prev) => mergeAnchorRows(prev, [item]));
      }
    });
    const offReconnect = client.onReconnect(() => retry(row.conversationId));
    return () => {
      offItem();
      offReconnect();
    };
  }, [client, runId, retry, row.conversationId]);

  const { entries } = useDurableTranscript({
    items: rows,
    anchors: [],
    runId,
    taskList: undefined,
    collapseToolSteps,
    delegateState,
  });
  const block = useMemo(
    () => callBlockOfConversation(indexCallBlocks(entries), row.callIds),
    [entries, row.callIds],
  );
  const pages = callConversations.stateOf(row.conversationId);
  const settled = pages?.loading === false;

  // An empty page anchors nothing, so a conversation that had no row of its own
  // when the popup opened has no card to fold its live rows into until a page
  // holding one brings the call's start.
  const startAskedAtRef = useRef(0);
  useEffect(() => {
    if (
      block === undefined &&
      settled &&
      rows.length > startAskedAtRef.current
    ) {
      startAskedAtRef.current = rows.length;
      retry(row.conversationId);
    }
  }, [block, settled, rows.length, retry, row.conversationId]);

  const scrollerRef = useRef<HTMLDivElement | null>(null);
  const landedRef = useRef(false);
  useEffect(() => {
    const scroller = scrollerRef.current;
    if (
      !landedRef.current &&
      settled &&
      block !== undefined &&
      scroller !== null
    ) {
      landedRef.current = true;
      scroller.scrollTop = scroller.scrollHeight;
    }
  }, [settled, block]);

  return (
    <div
      data-slot="call-conversation-dialog"
      className="flex h-full min-h-0 flex-col">
      <div className="flex min-w-0 shrink-0 flex-col gap-2 border-b border-border/60 px-5 py-3">
        <WorkingAgentHead row={row} />
        <WorkingAgentTitle row={row} />
      </div>
      <div
        ref={scrollerRef}
        className="flex min-h-0 flex-1 flex-col gap-3 overflow-y-auto px-5 py-4">
        <CallConversationContext.Provider value={callConversations}>
          {block === undefined ? (
            <>
              <CallConversationPager conversation={row.conversationId} />
              {settled && pages?.failed !== true ? (
                <p className="m-0 text-xs text-muted-foreground">
                  No messages yet.
                </p>
              ) : null}
            </>
          ) : (
            <CallConversationBody
              block={block}
              callee={row.callee}
              nodes={nodes}
              chatAgentName={chatAgentName}
            />
          )}
        </CallConversationContext.Provider>
      </div>
    </div>
  );
}

/**
 * One call's whole conversation in a popup, read page by page into its own
 * rows: reaching a call the transcript's window does not hold must not move the
 * window the reader is on.
 */
export function CallConversationDialog({
  row,
  onClose,
  ...body
}: {
  row: WorkingAgentRow | null;
  onClose: () => void;
  runId: string;
  api: Pick<ChatsApi, 'listRunItems'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
  nodes?: ReadonlyMap<string, TranscriptNodeMeta>;
  chatAgentName?: string | null;
  delegateState?: Pick<RunStateDto, 'throughSeq' | 'delegates' | 'calls'>;
  collapseToolSteps: boolean;
}): React.JSX.Element {
  return (
    <Dialog
      open={row !== null}
      onClose={onClose}
      title={row?.callee ?? 'Agent'}
      flush
      className="h-[min(48rem,100%)] max-w-3xl">
      {row === null ? null : (
        <ConversationBody key={row.conversationId} row={row} {...body} />
      )}
    </Dialog>
  );
}
