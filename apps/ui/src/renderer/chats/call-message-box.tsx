import { MessageSquarePlus, SendHorizontal } from 'lucide-react';
import {
  createContext,
  useContext,
  useEffect,
  useMemo,
  useRef,
  useState,
} from 'react';

import type { AgentFollowUpCapability } from '../autogenerated';
import { ErrorText } from '../components/error-text';
import { Button } from '../components/ui/button';
import { Textarea } from '../components/ui/textarea';
import { AttachmentStrip } from './attachment-strip';
import { isComposerSendKey } from './composer-keys';
import { insertPastedFilePaths } from './paste-file-paths';
import { QueuedStrip } from './queued-strip';
import { useAttachments } from './use-attachments';
import type { CallMessageQueues, CallTarget } from './use-call-message-queues';

/** What a CLI does with a message handed to it mid-turn, from the daemon. */
export type CallFollowUp = Pick<
  AgentFollowUpCapability,
  'unavailableReason' | 'interrupts'
>;

/** The direct line to the running calls of the open workflow run. */
export interface CallMessageChannel {
  runId: string;
  queues: CallMessageQueues;
  /** Null while the daemon has not answered for this agent. */
  followUpOf: (agent: string | null) => CallFollowUp | null;
}

/**
 * A context rather than a prop because memoized row shells, and other blocks,
 * sit between `Chats` and a call block. Null means no channel — a 1:1 chat, a
 * spec rendering the block bare — and nothing is drawn.
 */
export const CallMessageChannelContext =
  createContext<CallMessageChannel | null>(null);

/** Why the callee cannot be written to right now, or null when it can. */
function refusalOf(
  channel: CallMessageChannel,
  callee: string,
  calleeAgent: string | null,
): string | null {
  const followUp = channel.followUpOf(calleeAgent);
  return followUp === null
    ? `Checking whether ${callee} can take a message while it works…`
    : followUp.unavailableReason;
}

/** The footer control that opens the composer for a running call's callee. */
export function CallMessageButton({
  callee,
  calleeAgent,
  running,
  open,
  onOpen,
}: {
  callee: string;
  calleeAgent: string | null;
  running: boolean;
  open: boolean;
  onOpen: () => void;
}): React.JSX.Element | null {
  const channel = useContext(CallMessageChannelContext);
  if (channel === null || !running || open) {
    return null;
  }
  const refusal = refusalOf(channel, callee, calleeAgent);
  return (
    <Button
      type="button"
      variant="ghost"
      size="sm"
      data-slot="call-message-open"
      className="h-6 gap-1 px-1.5 text-[11px] text-muted-foreground has-[>svg]:px-1.5"
      disabled={refusal !== null}
      title={refusal ?? undefined}
      onClick={onOpen}>
      <MessageSquarePlus aria-hidden="true" className="size-3.5" />
      Message {callee}
    </Button>
  );
}

/**
 * What the user is sending a running call's callee: the messages still
 * waiting to go out, and — while open — a composer that takes pasted images.
 *
 * The callee answers inside the work it was briefed for, so its answer still
 * goes back to the caller; the hint says so, and says BEFORE the press when
 * the callee's CLI interrupts its current step to take a message.
 *
 * An OPEN composer outlives the call: the callee routinely finishes while the
 * user is still typing, and unmounting then would throw the draft away.
 */
export function CallMessagePanel({
  blockId,
  callId,
  calleeNodeId,
  callee,
  calleeAgent,
  caller,
  running,
  open,
  onClose,
}: {
  blockId: string;
  callId: string;
  calleeNodeId: string;
  callee: string;
  calleeAgent: string | null;
  caller: string | null;
  running: boolean;
  open: boolean;
  onClose: () => void;
}): React.JSX.Element | null {
  const channel = useContext(CallMessageChannelContext);
  const [text, setText] = useState('');
  const attachments = useAttachments();
  const field = useRef<HTMLTextAreaElement>(null);
  const runId = channel?.runId ?? null;
  const target = useMemo(
    (): CallTarget | null =>
      runId === null ? null : { runId, nodeId: calleeNodeId, callId, blockId },
    [runId, calleeNodeId, callId, blockId],
  );
  const queue =
    channel !== null && target !== null ? channel.queues.queueOf(target) : null;
  const waiting = queue?.messages.length ?? 0;
  const stopped = (queue?.error ?? null) !== null;

  useEffect(() => {
    if (open) {
      field.current?.focus();
    }
  }, [open]);

  // What is waiting goes out as soon as the call can take it and nothing is
  // holding the queue. A queue a refusal STOPPED is left for the user — Send
  // now, or remove — because re-driving it on every render would re-POST a
  // message the daemon has already said it will not take.
  useEffect(() => {
    if (
      channel !== null &&
      target !== null &&
      running &&
      waiting > 0 &&
      !stopped
    ) {
      void channel.queues.drain(target);
    }
  }, [channel, target, running, waiting, stopped, queue?.paused]);

  if (channel === null || target === null || queue === null) {
    return null;
  }
  if (
    !open &&
    waiting === 0 &&
    queue.inFlight === null &&
    queue.error === null
  ) {
    return null;
  }

  const followUp = channel.followUpOf(calleeAgent);
  const canSend =
    running &&
    refusalOf(channel, callee, calleeAgent) === null &&
    (text.trim() !== '' || attachments.attachments.length > 0);

  const close = (): void => {
    setText('');
    attachments.clear();
    onClose();
  };

  const submit = (): void => {
    if (!canSend) {
      return;
    }
    channel.queues.enqueue(target, text.trim(), attachments.toWire());
    close();
  };

  return (
    <div data-slot="call-message-panel" className="flex flex-col gap-1.5">
      {waiting > 0 ? (
        <QueuedStrip
          messages={queue.messages}
          paused={queue.paused}
          turnInFlight={running}
          steerUnavailableReason={
            running
              ? (followUp?.unavailableReason ?? null)
              : `${callee}’s call has ended`
          }
          steerInterrupts={followUp?.interrupts ?? false}
          steerStatus={null}
          onEdit={(id, next) => channel.queues.edit(target, id, next)}
          onRemove={(id) => channel.queues.remove(target, id)}
          onReorder={(id, overId) => channel.queues.reorder(target, id, overId)}
          onSteer={(id) => void channel.queues.sendNow(target, id)}
          onTogglePause={() => channel.queues.togglePause(target)}
          flowingNote={`the next goes out as soon as ${callee} can take it`}
        />
      ) : null}
      {queue.inFlight === null ? null : (
        <span
          data-slot="call-message-sending"
          className="px-2 text-xs text-muted-foreground">
          Sending to {callee}…
        </span>
      )}
      {queue.error === null ? null : (
        <ErrorText className="text-xs">{queue.error}</ErrorText>
      )}
      {open ? (
        <div data-slot="call-message-box" className="flex flex-col gap-1.5">
          <AttachmentStrip
            attachments={attachments.attachments}
            onRemove={attachments.remove}
          />
          {attachments.error === null ? null : (
            <ErrorText className="text-xs">{attachments.error}</ErrorText>
          )}
          <Textarea
            ref={field}
            aria-label={`Message ${callee}`}
            placeholder={`Message ${callee} directly…`}
            value={text}
            className="min-h-14"
            onChange={(event) => setText(event.target.value)}
            onPaste={(event) => {
              // Files are intercepted as in the composer: images stage as
              // attachments, anything else becomes its absolute path.
              const staged = attachments.addFromClipboard(event.clipboardData);
              const pathed = insertPastedFilePaths(event.clipboardData);
              if (staged || pathed) {
                event.preventDefault();
              }
            }}
            onKeyDown={(event) => {
              if (event.key === 'Escape') {
                event.preventDefault();
                close();
              } else if (isComposerSendKey(event)) {
                event.preventDefault();
                submit();
              }
            }}
          />
          <div className="flex items-center gap-2">
            <span className="min-w-0 flex-1 text-xs text-muted-foreground">
              {!running
                ? `${callee}’s call has ended — nothing more reaches it here`
                : `${
                    followUp?.interrupts === true
                      ? `Interrupts ${callee}’s current step`
                      : `Joins ${callee}’s current turn`
                  }${caller === null ? '' : ` — its answer still goes to ${caller}`}`}
            </span>
            <Button type="button" variant="ghost" size="sm" onClick={close}>
              Cancel
            </Button>
            <Button
              type="button"
              size="sm"
              data-slot="call-message-send"
              disabled={!canSend}
              onClick={submit}>
              <SendHorizontal aria-hidden="true" />
              Send
            </Button>
          </div>
        </div>
      ) : null}
    </div>
  );
}
