import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem, RunCallState } from '../autogenerated';
import { memberCallWaits } from './call-waits';

const AWAIT = 'mcp__geniro-run-1__await_agent';
const CALL = 'mcp__geniro-run-1__call_agent';

let seq = 0;
function item(
  kind: ChatItem['kind'],
  payload: unknown,
  memberId: string | null = 'manager',
): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    memberId,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

const toolCall = (
  id: string,
  name: string,
  input: unknown,
  memberId: string | null = 'manager',
): ChatItem => item('tool_call', { id, name, input }, memberId);

const toolResult = (
  id: string,
  memberId: string | null = 'manager',
): ChatItem => item('tool_result', { id, name: null, result: 'ok' }, memberId);

const call = (over: Partial<RunCallState>): RunCallState => ({
  callId: 'call-1',
  callerMemberId: 'manager',
  calleeMemberId: 'engineer',
  title: null,
  brief: null,
  mode: 'async',
  thread: null,
  callerConversationId: null,
  startSeq: 1,
  startedAt: '2026-11-23T12:00:00.000Z',
  endedAt: null,
  status: 'running',
  queued: false,
  member: null,
  ...over,
});

describe('memberCallWaits', () => {
  it('names the call an await_agent waits on by its call id', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { call_id: 'call-3', timeout_ms: 58000 })],
      [call({ callId: 'call-3', calleeMemberId: 'engineer' })],
    );

    expect(waits.get('manager')).toEqual({
      callId: 'call-3',
      calleeMemberId: 'engineer',
      more: 0,
    });
  });

  it('leaves the callee unknown when the awaited call is not in the run state', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { call_id: 'call-3' })],
      [],
    );

    expect(waits.get('manager')).toEqual({
      callId: 'call-3',
      calleeMemberId: null,
      more: 0,
    });
  });

  it('leaves the callee unknown when the awaited call has no callee', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { call_id: 'call-3' })],
      [call({ callId: 'call-3', calleeMemberId: null })],
    );

    expect(waits.get('manager')).toEqual({
      callId: 'call-3',
      calleeMemberId: null,
      more: 0,
    });
  });

  it('with no call id, names the oldest running call the member made and counts the rest', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { timeout_ms: 58000 })],
      [
        call({ callId: 'call-2', startSeq: 9, calleeMemberId: 'qa' }),
        call({ callId: 'call-1', startSeq: 5, calleeMemberId: 'engineer' }),
      ],
    );

    expect(waits.get('manager')).toEqual({
      callId: 'call-1',
      calleeMemberId: 'engineer',
      more: 1,
    });
  });

  it('leaves out the calls another member made and the ones already settled', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { timeout_ms: 58000 })],
      [
        call({ callId: 'call-1', callerMemberId: 'poet' }),
        call({
          callId: 'call-2',
          status: 'completed',
          endedAt: '2026-11-23T12:01:00.000Z',
        }),
      ],
    );

    expect(waits.has('manager')).toBe(false);
  });

  it('counts a queued call as running', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { timeout_ms: 58000 })],
      [call({ callId: 'call-1', queued: true })],
    );

    expect(waits.get('manager')).toEqual({
      callId: 'call-1',
      calleeMemberId: 'engineer',
      more: 0,
    });
  });

  it('names the running sync calls for an open sync call_agent', () => {
    const waits = memberCallWaits(
      [toolCall('t1', CALL, { agent: 'poet' })],
      [
        call({
          callId: 'call-1',
          mode: 'sync',
          calleeMemberId: 'poet',
          startSeq: 3,
        }),
        call({ callId: 'call-2', mode: 'async', startSeq: 1 }),
      ],
    );

    expect(waits.get('manager')).toEqual({
      callId: 'call-1',
      calleeMemberId: 'poet',
      more: 0,
    });
  });

  it('names nothing for an open call_agent whose only call in flight is async', () => {
    const waits = memberCallWaits(
      [toolCall('t1', CALL, { agent: 'poet' })],
      [call({ callId: 'call-1', mode: 'async' })],
    );

    expect(waits.has('manager')).toBe(false);
  });

  it('stops naming the wait once its own result lands', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { call_id: 'call-3' }), toolResult('t1')],
      [call({ callId: 'call-3' })],
    );

    expect(waits.has('manager')).toBe(false);
  });

  it('keeps the wait open through the result of another tool call', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { call_id: 'call-3' }), toolResult('t9')],
      [call({ callId: 'call-3' })],
    );

    expect(waits.get('manager')?.callId).toBe('call-3');
  });

  it.each([
    ['a message', item('message', { text: 'Still here.' })],
    ['a reasoning row', item('reasoning', { text: 'Weighing it.' })],
    ['another tool call', toolCall('t2', 'Bash', { command: 'ls' })],
  ])('stops naming the wait at the member’s next %s', (_label, next) => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { call_id: 'call-3' }), next],
      [call({ callId: 'call-3' })],
    );

    expect(waits.has('manager')).toBe(false);
  });

  it('names the newer wait when the member opens a second one', () => {
    const waits = memberCallWaits(
      [
        toolCall('t1', AWAIT, { call_id: 'call-1' }),
        toolCall('t2', AWAIT, { call_id: 'call-2' }),
      ],
      [call({ callId: 'call-1' }), call({ callId: 'call-2', startSeq: 4 })],
    );

    expect(waits.get('manager')?.callId).toBe('call-2');
  });

  it('ignores another member’s wait', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { call_id: 'call-3' }, 'poet')],
      [call({ callId: 'call-3' })],
    );

    expect(waits.has('manager')).toBe(false);
    expect(waits.get('poet')?.callId).toBe('call-3');
  });

  it('ignores a wait made inside a sub-agent', () => {
    const waits = memberCallWaits(
      [
        item(
          'tool_call',
          {
            id: 't1',
            name: AWAIT,
            input: { call_id: 'call-3' },
            parentToolUseId: 'toolu_1',
          },
          'manager',
        ),
      ],
      [call({ callId: 'call-3' })],
    );

    expect(waits.has('manager')).toBe(false);
  });

  it('ignores a tool named await_agent on another server', () => {
    const waits = memberCallWaits(
      [toolCall('t1', 'mcp__other-server__await_agent', { call_id: 'call-3' })],
      [call({ callId: 'call-3' })],
    );

    expect(waits.has('manager')).toBe(false);
  });

  it('ignores rows with no member', () => {
    const waits = memberCallWaits(
      [toolCall('t1', AWAIT, { call_id: 'call-3' }, null)],
      [call({ callId: 'call-3' })],
    );

    expect(waits.size).toBe(0);
  });
});
