import type { ItemDto as ChatItem, RunCallState } from '../autogenerated';
import { geniroToolOf } from './geniro-tool';
import { subagentIdOf } from './subagent-payload';
import { payloadString } from './transcript-payload';

export interface MemberCallWait {
  callId: string;
  calleeMemberId: string | null;
  more: number;
}

interface OpenWait {
  tool: 'await_agent' | 'call_agent';
  toolId: string | null;
  awaitedCallId: string | null;
}

export function memberCallWaits(
  items: readonly ChatItem[],
  calls: readonly RunCallState[],
): Map<string, MemberCallWait> {
  const open = new Map<string, OpenWait>();
  for (const row of items) {
    const memberId = row.memberId;
    if (memberId === null || subagentIdOf(row) !== null) {
      continue;
    }
    if (row.kind === 'tool_call') {
      open.delete(memberId);
      const wait = waitOpenedBy(row);
      if (wait !== null) {
        open.set(memberId, wait);
      }
    } else if (row.kind === 'tool_result') {
      const current = open.get(memberId);
      if (current !== undefined && answers(current, row)) {
        open.delete(memberId);
      }
    } else if (row.kind === 'message' || row.kind === 'reasoning') {
      open.delete(memberId);
    }
  }
  const waits = new Map<string, MemberCallWait>();
  for (const [memberId, wait] of open) {
    const named = nameWait(wait, memberId, calls);
    if (named !== null) {
      waits.set(memberId, named);
    }
  }
  return waits;
}

function waitOpenedBy(row: ChatItem): OpenWait | null {
  const payload: unknown = row.payload;
  const name = payloadString(payload, 'name');
  const tool = name === null ? null : geniroToolOf(name, row.runId);
  if (tool !== 'await_agent' && tool !== 'call_agent') {
    return null;
  }
  return {
    tool,
    toolId: payloadString(payload, 'id'),
    awaitedCallId: payloadString(inputOf(payload), 'call_id'),
  };
}

function inputOf(payload: unknown): unknown {
  return typeof payload === 'object' && payload !== null && 'input' in payload
    ? payload.input
    : null;
}

function answers(wait: OpenWait, row: ChatItem): boolean {
  return (
    wait.toolId !== null && wait.toolId === payloadString(row.payload, 'id')
  );
}

function nameWait(
  wait: OpenWait,
  memberId: string,
  calls: readonly RunCallState[],
): MemberCallWait | null {
  if (wait.tool === 'await_agent' && wait.awaitedCallId !== null) {
    const awaited = calls.find((call) => call.callId === wait.awaitedCallId);
    return {
      callId: wait.awaitedCallId,
      calleeMemberId: awaited?.calleeMemberId ?? null,
      more: 0,
    };
  }
  const running = calls
    .filter(
      (call) =>
        call.callerMemberId === memberId &&
        call.status === 'running' &&
        (wait.tool === 'await_agent' || call.mode === 'sync'),
    )
    .sort((a, b) => a.startSeq - b.startSeq);
  const [oldest, ...others] = running;
  if (oldest === undefined) {
    return null;
  }
  return {
    callId: oldest.callId,
    calleeMemberId: oldest.calleeMemberId,
    more: others.length,
  };
}
