import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { chartRows, readChart, seriesKey, X_KEY } from './chart-payload';

function item(payload: unknown): ChatItem {
  return {
    id: 'i1',
    runId: 'r1',
    nodeId: null,
    seq: 1,
    kind: 'show_chart',
    createdAt: '2026-08-29T00:00:00.000Z',
    payload,
  } as unknown as ChatItem;
}

const CHART = {
  title: 'Test suite duration',
  kind: 'line',
  xLabel: 'commit',
  yLabel: 'seconds',
  labels: ['a1b2', 'c3d4', 'e5f6'],
  series: [{ name: 'unit', values: [12.1, null, 11.9] }],
};

describe('readChart', () => {
  it('reads a well-formed payload, gaps included', () => {
    expect(readChart(item(CHART))).toEqual({
      title: 'Test suite duration',
      kind: 'line',
      xLabel: 'commit',
      yLabel: 'seconds',
      labels: ['a1b2', 'c3d4', 'e5f6'],
      series: [{ name: 'unit', values: [12.1, null, 11.9] }],
    });
  });

  it.each([
    ['not an object', 'a chart'],
    ['null', null],
    ['no labels', { ...CHART, labels: [] }],
    ['labels not an array', { ...CHART, labels: 'three' }],
    ['no series', { ...CHART, series: [] }],
    ['series not an array', { ...CHART, series: 'unit' }],
    ['a nameless series', { ...CHART, series: [{ values: [1, 2, 3] }] }],
  ])('answers null for %s', (_name, payload) => {
    expect(readChart(item(payload))).toBeNull();
  });

  it('keeps a chart with no title — the card supplies its own heading', () => {
    expect(readChart(item({ ...CHART, title: undefined }))?.title).toBeNull();
  });

  it('falls back to a line for a kind it does not know', () => {
    expect(readChart(item({ ...CHART, kind: 'sunburst' }))?.kind).toBe('line');
  });

  it('RE-ALIGNS a short series rather than pairing it with the wrong labels', () => {
    // This reader also runs over rows written by older builds, whose alignment
    // was whatever that build's rules were — so the guarantee is re-established
    // here rather than assumed from the daemon.
    const read = readChart(
      item({ ...CHART, series: [{ name: 'unit', values: [12.1] }] }),
    );
    expect(read?.series[0]?.values).toEqual([12.1, null, null]);
  });

  it('cuts a series longer than the labels', () => {
    const read = readChart(
      item({ ...CHART, series: [{ name: 'unit', values: [1, 2, 3, 4, 5] }] }),
    );
    expect(read?.series[0]?.values).toEqual([1, 2, 3]);
  });

  it('BLANKS an unreadable label instead of removing it', () => {
    // Removing one would shift every later point a place left and silently
    // re-attribute the measurements — a wrong chart that still looks right.
    const read = readChart(item({ ...CHART, labels: ['a1b2', 7, 'e5f6'] }));
    expect(read?.labels).toEqual(['a1b2', '', 'e5f6']);
    expect(read?.series[0]?.values).toEqual([12.1, null, 11.9]);
  });

  it('reads a non-finite stored number as a gap', () => {
    const read = readChart(
      item({ ...CHART, series: [{ name: 'unit', values: [1, 'nope', 3] }] }),
    );
    expect(read?.series[0]?.values).toEqual([1, null, 3]);
  });

  it('keeps a real zero, which is a measurement and not a gap', () => {
    const read = readChart(
      item({ ...CHART, series: [{ name: 'unit', values: [0, 1, 2] }] }),
    );
    expect(read?.series[0]?.values).toEqual([0, 1, 2]);
  });
});

describe('chartRows', () => {
  it('transposes the positional payload into one row per x', () => {
    const chart = readChart(item(CHART))!;
    expect(chartRows(chart)).toEqual([
      { [X_KEY]: 'a1b2', s0: 12.1 },
      { [X_KEY]: 'c3d4', s0: null },
      { [X_KEY]: 'e5f6', s0: 11.9 },
    ]);
  });

  it('keys series BY POSITION, so one named "x" cannot eat the axis column', () => {
    // The reason `seriesKey` exists at all: keyed by name, this series would
    // overwrite the x column and the chart would plot against its own values.
    const chart = readChart(
      item({
        ...CHART,
        labels: ['a', 'b'],
        series: [{ name: 'x', values: [1, 2] }],
      }),
    )!;
    expect(chartRows(chart)).toEqual([
      { [X_KEY]: 'a', s0: 1 },
      { [X_KEY]: 'b', s0: 2 },
    ]);
  });

  it('keeps two series that share a name as two columns', () => {
    // A model legitimately sends "p95" twice for two runs; keyed by name they
    // would collapse into one curve and the second would silently win.
    const chart = readChart(
      item({
        ...CHART,
        labels: ['a', 'b'],
        series: [
          { name: 'p95', values: [1, 2] },
          { name: 'p95', values: [3, 4] },
        ],
      }),
    )!;
    expect(chartRows(chart)).toEqual([
      { [X_KEY]: 'a', s0: 1, s1: 3 },
      { [X_KEY]: 'b', s0: 2, s1: 4 },
    ]);
    expect(seriesKey(0)).not.toBe(seriesKey(1));
  });
});
