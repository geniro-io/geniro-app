import type { ItemDto as ChatItem } from '../autogenerated';

/**
 * A chart an agent handed the app to plot, read off the transcript.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/chat.types.ts` declares the shape
 * (`HostChart`) and `apps/daemon/src/v1/agents/utils/host-chart.ts` writes these
 * keys for the `show_chart` item kind. An item payload is `z.unknown()` on the
 * wire BY DESIGN — every kind carries a different shape — so no generated type
 * reaches here and this is an independent reading of one shape. A key renamed on
 * either side must be renamed on both.
 *
 * The naming seam is already crossed upstream: the daemon takes the tool's
 * snake_case argument names at its edge and stores camelCase, so what arrives
 * here is camelCase.
 *
 * The one invariant this file exists to preserve: the payload is POSITIONAL.
 * Every series holds one value per entry of `labels`, aligned by index. Nothing
 * here may drop, reorder or compact either list independently of the other —
 * that would not fail, it would silently re-attribute every measurement after
 * the edit and still look like a chart.
 */

export type ChartKind = 'line' | 'bar' | 'area';

const KINDS: readonly ChartKind[] = ['line', 'bar', 'area'];

/** One plotted series: a name for the legend, one value per x label. */
export interface ChartSeries {
  name: string;
  /** Null is a GAP — a point that was not measured, drawn as a break. */
  values: (number | null)[];
}

/** One `show_chart` row, as the card plots it. */
export interface ChartSpec {
  /** Null when the agent named none; the card supplies its own heading. */
  title: string | null;
  kind: ChartKind;
  labels: string[];
  series: ChartSeries[];
  xLabel: string | null;
  yLabel: string | null;
}

function readString(value: unknown): string | null {
  return typeof value === 'string' && value.length > 0 ? value : null;
}

function readValue(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

/**
 * Read one `show_chart` row, or null when the payload does not read as a chart.
 *
 * Null where the findings reader would return an empty report, and the
 * difference is real: an empty review IS a result worth a card saying so, while
 * a chart with no labels or no series has nothing to draw and no sentence to
 * put in its place. The daemon already refuses that call at the tool edge, so
 * reaching it here means a row written by an older build.
 */
export function readChart(item: ChatItem): ChartSpec | null {
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const row = payload as {
    title?: unknown;
    kind?: unknown;
    labels?: unknown;
    series?: unknown;
    xLabel?: unknown;
    yLabel?: unknown;
  };
  if (!Array.isArray(row.labels) || row.labels.length === 0) {
    return null;
  }
  // Every entry kept, blanks included: an index here is a position a series
  // value is matched against, so removing one would shift the whole axis.
  const labels = row.labels.map((label) =>
    typeof label === 'string' ? label : '',
  );
  if (!Array.isArray(row.series)) {
    return null;
  }
  const series = row.series
    .map((entry): ChartSeries | null => {
      if (typeof entry !== 'object' || entry === null) {
        return null;
      }
      const s = entry as { name?: unknown; values?: unknown };
      const name = readString(s.name);
      const values = s.values;
      if (name === null || !Array.isArray(values)) {
        return null;
      }
      // Re-aligned here as well as at the daemon edge. Not defensive
      // duplication: this reader also runs over rows written by OLDER builds,
      // whose alignment was whatever that build's rules were, and a short array
      // reaching the plot would pair values with the wrong labels.
      return {
        name,
        values: labels.map((_, index) => readValue(values[index])),
      };
    })
    .filter((entry): entry is ChartSeries => entry !== null);
  if (series.length === 0) {
    return null;
  }
  return {
    title: readString(row.title),
    kind:
      typeof row.kind === 'string' &&
      (KINDS as readonly string[]).includes(row.kind)
        ? (row.kind as ChartKind)
        : 'line',
    labels,
    series,
    xLabel: readString(row.xLabel),
    yLabel: readString(row.yLabel),
  };
}

/** The x-axis key in a plotted row. */
export const X_KEY = 'x';

/**
 * The data key for the series at `index`.
 *
 * Positional rather than the series' own name, and both halves matter: a series
 * legitimately named "x" would otherwise overwrite the axis column, and two
 * series sharing a name — which the daemon permits, because a model may well
 * send "p95" twice for two runs — would collapse into one curve.
 */
export function seriesKey(index: number): string {
  return `s${index}`;
}

/** One row of the plot: the x label plus one column per series. */
export type ChartRow = Record<string, string | number | null>;

/**
 * Transpose the positional payload into the row-per-x shape recharts reads.
 *
 * The one place the positional contract is spent, and the last place it can go
 * wrong: the index driving this is the LABEL's, so a series shorter than the
 * labels contributes nulls at the end rather than shifting everything left.
 */
export function chartRows(chart: ChartSpec): ChartRow[] {
  return chart.labels.map((label, index) => {
    const row: ChartRow = { [X_KEY]: label };
    chart.series.forEach((series, seriesIndex) => {
      row[seriesKey(seriesIndex)] = series.values[index] ?? null;
    });
    return row;
  });
}
