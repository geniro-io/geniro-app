import { useEffect, useMemo } from 'react';

import type { ItemDto as ChatItem } from '../autogenerated';
import { endsContextHistory } from './compaction-payload';
import type { ContextReading } from './context-reading';

/** How full a context window is, and how big it is. Either may be unmeasured. */
export interface ContextFigures {
  tokens: number | null;
  window: number | null;
}

/** One place a reading can come from, with the window it was taken against. */
interface ReadingSource {
  contextTokens: number | null;
  contextWindowTokens: number | null;
}

export interface ChatContextSources {
  /** The live plane's reading for the turn in flight. */
  live: ReadingSource | undefined;
  /** The run row, where the daemon files every reading the CLI reports. */
  run: ReadingSource | null;
  /** The last settled turn of the loaded transcript. */
  transcript: ReadingSource | undefined;
  /** Whether the transcript holds any rows yet. */
  itemsLoaded: boolean;
  /** What this surface remembered for the run. Read only while nothing is loaded. */
  recall: () => ContextReading | null;
}

/**
 * The ring's figures for a 1:1 chat, read in recency order: the live delta,
 * then the run row, then the transcript's last settled turn.
 *
 * Nothing compares the sources. Each measures a later moment than the one after
 * it, so `??` is the whole rule. The live plane is read directly rather than
 * through the transcript's agent entry, because that entry already collapses the
 * live plane onto the transcript and would put the oldest source first.
 *
 * A loaded transcript that yields no reading is an answer, not a gap. A
 * compaction has just discarded every figure above it, and a remembered one
 * would hand the old ring straight back. Recall covers only the refetch mid-switch,
 * when nothing is loaded yet.
 */
export function chatContextFigures(
  sources: ChatContextSources,
): ContextFigures {
  const { live, run, transcript } = sources;
  const tokens =
    live?.contextTokens ??
    run?.contextTokens ??
    transcript?.contextTokens ??
    null;
  // The window is read whether or not there is a count. A compaction clears
  // every count and keeps the window, which belongs to the model, and the empty
  // ring drawn afterwards needs that denominator to be a gauge at all.
  const windowTokens =
    live?.contextWindowTokens ??
    run?.contextWindowTokens ??
    transcript?.contextWindowTokens ??
    null;
  if (tokens !== null) {
    return { tokens, window: windowTokens };
  }
  const recalled = sources.itemsLoaded ? null : sources.recall();
  return recalled === null
    ? { tokens: null, window: windowTokens }
    : { tokens: recalled.tokens, window: recalled.window };
}

/**
 * The reason the ring draws when it has no count, or null when there is nothing
 * worth saying.
 *
 * One case: a compaction discarded the conversation the last reading described,
 * and nothing measures the replacement until the next message goes out. The
 * transcript is where that is knowable, because the row saying so is in it.
 */
export function chatContextAwaitingReading(
  tokens: number | null,
  items: readonly ChatItem[],
): string | null {
  return tokens === null && items.some(endsContextHistory)
    ? 'Conversation compacted — its new size is measured on the next message'
    : null;
}

/**
 * The ring's bookkeeping, shared by the chat screen and the workflow dock: files
 * the reading on screen for its run, and answers why the ring has no count when
 * that is worth drawing (see {@link chatContextAwaitingReading}).
 *
 * Filing keeps a thread switch from taking the ring down with the transcript. A
 * reading is filed only for the run it was measured on, and an unmeasured figure
 * never overwrites one that is filed. A loaded transcript that yields no figure
 * forgets the one filed for its run, the rule {@link chatContextFigures} applies
 * too: the transcript is the newer account, and a figure filed before a
 * compaction must not outlive it.
 */
export function useContextRing({
  runId,
  figures,
  items,
  remember,
  forget,
}: {
  runId: string | null;
  figures: ContextFigures;
  items: readonly ChatItem[];
  remember: (runId: string, reading: ContextReading | null) => void;
  forget: (runId: string) => void;
}): string | null {
  const { tokens, window: windowTokens } = figures;
  const itemsLoaded = items.length > 0;
  useEffect(() => {
    if (runId === null) {
      return;
    }
    if (tokens !== null) {
      remember(runId, { tokens, window: windowTokens });
      return;
    }
    // Forgetting only over a loaded transcript. An empty one is the refetch
    // mid-switch, where forgetting is exactly the flicker this exists to stop.
    if (itemsLoaded) {
      forget(runId);
    }
  }, [runId, tokens, windowTokens, itemsLoaded, remember, forget]);
  return useMemo(
    () => chatContextAwaitingReading(tokens, items),
    [tokens, items],
  );
}
