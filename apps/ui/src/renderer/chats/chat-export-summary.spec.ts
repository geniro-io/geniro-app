import { describe, expect, it } from 'vitest';

import type { ChatExportDtoItemsInner } from '../autogenerated';
import { chatExportSummary } from './chat-export-summary';

let seq = 0;
function row(
  kind: ChatExportDtoItemsInner['kind'],
  payload: unknown,
  extra: { nodeId?: string | null; createdAt?: string } = {},
): ChatExportDtoItemsInner {
  seq += 1;
  return {
    id: `i${seq}`,
    runId: 'r1',
    nodeId: extra.nodeId ?? null,
    seq,
    kind,
    role: null,
    payload,
    createdAt: extra.createdAt ?? '2026-09-18T06:00:00.000Z',
  };
}

const turn = (
  usage: Record<string, unknown>,
  extra: { nodeId?: string | null; callId?: string } = {},
): ChatExportDtoItemsInner =>
  row(
    'turn_complete',
    { usage, ...(extra.callId ? { callId: extra.callId } : {}) },
    { nodeId: extra.nodeId },
  );

describe('chatExportSummary — spend per agent', () => {
  it('sums each agent’s own turns, cost and worked time', () => {
    const summary = chatExportSummary([
      turn({ costUsd: 1.5, durationMs: 2000 }, { nodeId: 'manager' }),
      turn({ costUsd: 0.5, durationMs: 1000 }, { nodeId: 'manager' }),
      turn({ costUsd: 9, durationMs: 60000 }, { nodeId: 'engineer' }),
    ]);

    expect(summary.agents).toEqual([
      { agent: 'manager', turns: 2, costUsd: 2, workedMs: 3000 },
      { agent: 'engineer', turns: 1, costUsd: 9, workedMs: 60000 },
    ]);
  });

  it('files a 1:1 chat’s turns under one label rather than the run id', () => {
    // Every row of a chat carries `nodeId: null`, and naming the bucket after the
    // run would say nothing the facts above the table do not already say.
    expect(
      chatExportSummary([turn({ costUsd: 0.2, durationMs: 500 })]).agents,
    ).toEqual([{ agent: 'agent', turns: 1, costUsd: 0.2, workedMs: 500 }]);
  });

  it('keeps a figure nothing measured ABSENT rather than zero', () => {
    // The daemon's own null-means-not-measured rule reaching a document: cursor
    // reports no cost unless its currency is USD, and a `$0.00` in this table
    // would claim a turn that ran free.
    expect(
      chatExportSummary([
        turn({ costUsd: null, durationMs: null }),
        turn({ costUsd: null, durationMs: 400 }),
      ]).agents,
    ).toEqual([{ agent: 'agent', turns: 2, costUsd: null, workedMs: 400 }]);
  });
});

describe('chatExportSummary — agent calls', () => {
  it('pairs a start with its result, timing and costing the call', () => {
    const summary = chatExportSummary([
      row(
        'call_started',
        {
          callId: 'call-1',
          callerNodeId: 'manager',
          calleeNodeId: 'engineer',
          title: 'Build the counter fix',
          message: 'a much longer brief nobody wants in a table',
        },
        { createdAt: '2026-09-18T06:00:00.000Z' },
      ),
      turn(
        { costUsd: 4.25, durationMs: 90000 },
        {
          nodeId: 'engineer',
          callId: 'call-1',
        },
      ),
      row(
        'call_result',
        { callId: 'call-1', status: 'ok', result: { text: 'done' } },
        { createdAt: '2026-09-18T06:02:30.000Z' },
      ),
    ]);

    expect(summary.calls).toEqual([
      {
        callId: 'call-1',
        title: 'Build the counter fix',
        callerNodeId: 'manager',
        calleeNodeId: 'engineer',
        durationMs: 150_000,
        costUsd: 4.25,
        outcome: 'ok',
      },
    ]);
  });

  it('carries a failure’s WHOLE one-liner, prefix included', () => {
    // The prefix IS the diagnosis. A table of eleven rows each reading `error`
    // answers nothing, and finding which calls failed the same way is usually the
    // reason the export is open at all.
    const summary = chatExportSummary([
      row('call_started', {
        callId: 'call-2',
        callerNodeId: 'manager',
        calleeNodeId: 'engineer',
      }),
      row('call_result', {
        callId: 'call-2',
        status: 'error',
        error: "CALLEE_FAILED[rate_limited]: You've hit your session limit",
      }),
    ]);

    expect(summary.calls[0]?.outcome).toBe(
      "CALLEE_FAILED[rate_limited]: You've hit your session limit",
    );
  });

  it('reports a call with no result as unsettled, with no invented duration', () => {
    const summary = chatExportSummary([
      row('call_started', { callId: 'call-3', calleeNodeId: 'qa' }),
    ]);

    expect(summary.calls[0]).toMatchObject({
      outcome: 'unsettled',
      durationMs: null,
      costUsd: null,
    });
  });

  it('does not count a callee’s turn twice — once for the call, once for the agent', () => {
    // The agent total and the call total are two different questions about the
    // same turn, so both hold; what must not happen is either being doubled.
    const summary = chatExportSummary([
      row('call_started', { callId: 'call-4', calleeNodeId: 'engineer' }),
      turn(
        { costUsd: 3, durationMs: 1000 },
        {
          nodeId: 'engineer',
          callId: 'call-4',
        },
      ),
    ]);

    expect(summary.agents[0]?.costUsd).toBe(3);
    expect(summary.calls[0]?.costUsd).toBe(3);
  });
});

describe('chatExportSummary — errors and compactions', () => {
  it('lists each failure with when it happened and who reported it', () => {
    const summary = chatExportSummary([
      row(
        'error',
        { message: "You've hit your session limit · resets 7:30pm" },
        { nodeId: 'engineer', createdAt: '2026-09-18T07:30:00.000Z' },
      ),
    ]);

    expect(summary.errors).toEqual([
      {
        at: '2026-09-18T07:30:00.000Z',
        agent: 'engineer',
        message: "You've hit your session limit · resets 7:30pm",
      },
    ]);
  });

  it('recognises a compaction by its MARKER, not by the message text', () => {
    // The same rule the transcript's own reader follows, and the reason this
    // shares that reader: a CLI that reworded its "This session is being
    // continued…" preamble would silently stop being counted.
    const summary = chatExportSummary([
      row('system', {
        message: 'anything at all',
        compaction: { preTokens: 856_000, postTokens: 29_000, trigger: 'auto' },
      }),
      row('system', { message: 'an ordinary relayed notice' }),
    ]);

    expect(summary.compactions).toEqual([
      {
        at: '2026-09-18T06:00:00.000Z',
        agent: null,
        preTokens: 856_000,
        postTokens: 29_000,
        trigger: 'auto',
      },
    ]);
  });
});
