import type { ChatExportDtoItemsInner } from '../autogenerated';
import { compactionFacts } from './compaction-payload';
import { payloadNumber, payloadString } from './transcript-payload';

/**
 * The SUMMARY an exported conversation opens with — what it cost, where, and what
 * went wrong — folded from the rows the transcript already holds.
 *
 * It exists because reading a long run's export means answering the same four
 * questions first, and every one of them currently requires a script. MEASURED on
 * one real workflow export: 28.9 MB, 14,086 rows, 81 turns, $985.87 — and none of
 * those figures is stated anywhere in the file. Which agent spent the money, how
 * long each of 57 agent calls took, which of them failed and why, and how many
 * times a context window was compacted are all in there, one row at a time.
 *
 * It stores and computes NOTHING new: every figure is folded from a
 * `turn_complete`, a `call_started`/`call_result` pair, an `error` or a `system`
 * row. A figure nothing measured is left OUT rather than drawn as a zero — the
 * daemon's own null-means-not-measured rule reaching a document, where a `$0.00`
 * would claim a turn that ran free.
 *
 * Pure, and its own module rather than more of `chat-markdown.ts`: the fold is
 * the part worth testing directly, and the renderer is one `join`.
 */

/** Per-agent spend and worked time, summed over that agent's own turns. */
export interface ExportAgentTotals {
  /** The node id, or `agent` for a 1:1 chat's single conversation. */
  agent: string;
  turns: number;
  costUsd: number | null;
  workedMs: number | null;
}

/** One agent-to-agent call, as its start and result rows recorded it. */
export interface ExportCall {
  callId: string;
  /** WHY the caller made it — the `title` argument, never the brief. */
  title: string | null;
  callerNodeId: string | null;
  calleeNodeId: string | null;
  /** Wall clock from the start row to the result row; null while unsettled. */
  durationMs: number | null;
  /** Summed from the `turn_complete` rows carrying this call's id. */
  costUsd: number | null;
  /** `ok`, or the error envelope's own machine-prefixed one-liner. */
  outcome: string;
}

/** One failure, with when it happened and which agent reported it. */
export interface ExportError {
  at: string;
  agent: string | null;
  message: string;
}

/** One context compaction, with the figures the CLI reported about it. */
export interface ExportCompaction {
  at: string;
  agent: string | null;
  preTokens: number | null;
  postTokens: number | null;
  trigger: 'auto' | 'manual' | null;
}

export interface ChatExportSummary {
  agents: ExportAgentTotals[];
  calls: ExportCall[];
  errors: ExportError[];
  compactions: ExportCompaction[];
}

/**
 * The bucket a row's figures belong to.
 *
 * `nodeId` is null for every row of a 1:1 chat, where there is one conversation
 * and naming it after the run would say nothing — so those fold under one label
 * the reader already understands from the run facts above the table.
 */
const MAIN_AGENT = 'agent';

const agentOf = (item: ChatExportDtoItemsInner): string =>
  item.nodeId ?? MAIN_AGENT;

/** Add two figures either of which may be absent, keeping absence absent. */
function addFigure(total: number | null, next: number | null): number | null {
  if (next === null) {
    return total;
  }
  return (total ?? 0) + next;
}

const usageNumber = (
  item: ChatExportDtoItemsInner,
  key: string,
): number | null =>
  payloadNumber((item.payload as { usage?: unknown } | null)?.usage, key);

/**
 * What a `call_result` row's envelope says happened — `ok`, or the error's own
 * one-liner (`CALLEE_FAILED[rate_limited]: …`, `QUESTION_TIMEOUT: …`).
 *
 * The prefixed string rather than the bare word, because the prefix IS the
 * diagnosis: a table of eleven rows reading `error` answers nothing, and the
 * whole reason to read an export is usually to find out which of them failed the
 * same way.
 */
function outcomeOf(payload: unknown): string {
  const status = payloadString(payload, 'status');
  if (status === 'error') {
    return payloadString(payload, 'error') ?? 'error';
  }
  return status ?? 'unsettled';
}

/**
 * Fold one conversation's rows into its summary.
 *
 * ONE pass, because the transcript is the largest thing in the document and the
 * whole point of the summary is that reading it should be cheaper than reading
 * the rows.
 */
export function chatExportSummary(
  items: readonly ChatExportDtoItemsInner[],
): ChatExportSummary {
  const agents = new Map<string, ExportAgentTotals>();
  const calls = new Map<string, ExportCall>();
  const startedAt = new Map<string, number>();
  const errors: ExportError[] = [];
  const compactions: ExportCompaction[] = [];

  const agentTotals = (agent: string): ExportAgentTotals => {
    const found = agents.get(agent);
    if (found !== undefined) {
      return found;
    }
    const fresh: ExportAgentTotals = {
      agent,
      turns: 0,
      costUsd: null,
      workedMs: null,
    };
    agents.set(agent, fresh);
    return fresh;
  };

  for (const item of items) {
    if (item.kind === 'turn_complete') {
      const totals = agentTotals(agentOf(item));
      totals.turns += 1;
      totals.costUsd = addFigure(totals.costUsd, usageNumber(item, 'costUsd'));
      totals.workedMs = addFigure(
        totals.workedMs,
        usageNumber(item, 'durationMs'),
      );
      // A callee's turn also belongs to its CALL, which is what makes a per-call
      // cost answerable at all — the executor stamps the id on the row.
      const callId = payloadString(item.payload, 'callId');
      const call = callId === null ? undefined : calls.get(callId);
      if (call !== undefined) {
        call.costUsd = addFigure(call.costUsd, usageNumber(item, 'costUsd'));
      }
      continue;
    }
    if (item.kind === 'call_started') {
      const callId = payloadString(item.payload, 'callId');
      if (callId === null || calls.has(callId)) {
        continue;
      }
      calls.set(callId, {
        callId,
        title: payloadString(item.payload, 'title'),
        callerNodeId: payloadString(item.payload, 'callerNodeId'),
        calleeNodeId: payloadString(item.payload, 'calleeNodeId'),
        durationMs: null,
        costUsd: null,
        outcome: 'unsettled',
      });
      const began = Date.parse(item.createdAt);
      if (Number.isFinite(began)) {
        startedAt.set(callId, began);
      }
      continue;
    }
    if (item.kind === 'call_result') {
      const callId = payloadString(item.payload, 'callId');
      const call = callId === null ? undefined : calls.get(callId);
      if (call === undefined) {
        continue;
      }
      call.outcome = outcomeOf(item.payload);
      const began = startedAt.get(call.callId);
      const ended = Date.parse(item.createdAt);
      if (began !== undefined && Number.isFinite(ended) && ended >= began) {
        call.durationMs = ended - began;
      }
      continue;
    }
    if (item.kind === 'error') {
      const message = payloadString(item.payload, 'message');
      if (message !== null) {
        errors.push({ at: item.createdAt, agent: item.nodeId, message });
      }
      continue;
    }
    if (item.kind === 'system') {
      // The MARKER decides it, never the message text — the same rule the
      // transcript's own reader follows, and the reason this shares that reader
      // rather than matching on a CLI's "This session is being continued…".
      const facts = compactionFacts(item.payload);
      if (facts !== null) {
        compactions.push({
          at: item.createdAt,
          agent: item.nodeId,
          ...facts,
        });
      }
    }
  }

  return {
    agents: [...agents.values()],
    calls: [...calls.values()],
    errors,
    compactions,
  };
}
