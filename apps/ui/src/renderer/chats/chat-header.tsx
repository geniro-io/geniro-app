/**
 * One re-render a second, for as long as `active`.
 *
 * The two live readouts in this header own their own ticking rather than the
 * header being repainted from above once a second — the same reason the
 * transcript's live rows own theirs.
 */
function useSecondTick(active: boolean): void {
  const [, tick] = useState(0);
  useEffect(() => {
    if (!active) {
      return;
    }
    const id = window.setInterval(() => tick((n) => n + 1), 1_000);
    return () => window.clearInterval(id);
  }, [active]);
}

/**
 * The counters' trigger — one constant, because there are three of them.
 *
 * The TYPE SIZE is on the button and has to be: `global.css`'s base rule sets
 * `button { font-size: var(--text-base) }`, which DEFEATS an inherited size,
 * so the row's own `text-xs` reached the icons and not the numbers beside
 * them. Measured on the reported screenshot — the digits were 15px medium
 * against 14px glyphs, taller and heavier than the icon they belong to and
 * than every other word on the header line. REPORTED as "давай сделаем меньше
 * вот эти циферки… значки оставь одного размера, а вот циферки уменьшим": the
 * icons are untouched at `size-3.5`, and the numbers come back to the 12px the
 * row asked for in the first place. `font-normal` for the same reason — the
 * same base rule also makes them medium, so a count read as emphasis.
 */
const COUNT_TRIGGER_CLASS =
  'gap-1 rounded-md px-1 py-0.5 text-xs font-normal hover:bg-accent';

/**
 * What this thread has WORKED and what it has SPENT — ONE readout, on the
 * right, beside the counters.
 *
 * It used to be two spans in the middle of the identity line, each with its own
 * leading middot, spelling `· worked 4m 13s / 5 turns · $1.11` — six words and
 * two figures for two numbers. REPORTED as "we have soo much information here.
 * I wanna redesign it, minimize", against a header carrying nine things on one
 * line. What went is the PROSE, not a figure: the word `worked` is a glyph now,
 * the turn count moved onto the hover, and the pair reads `4m 13s · $1.11`.
 *
 * It also crossed the row. The left side truncates the TITLE when it runs short
 * (the whole reason `min-w-0` is on it), so every character of prose there was
 * paid for by the thread's own name; the right side is a fixed handful of
 * characters already. Beside the counters these are what they are — the numbers
 * about this thread, in one place, rather than two of them wedged between the
 * folder and the sub-agent count.
 *
 * The whole worked figure MOVES while a turn is in flight, rather than the
 * running turn being stated separately: "how much work is in here" is one
 * number, and a thread mid-turn had it standing still for the entire turn — a
 * header reading `running · 18s · worked 64m 34s` where the 64m had not moved
 * in an hour of watching.
 *
 * A null spend renders NOTHING rather than `$0.00`, and the distinction is the
 * whole rule the figures obey end to end: cursor-agent reports no cost unless
 * its currency is USD, so a thread on it has not spent nothing — it has not
 * been measured. Writing `$0.00` there would be the app inventing a number the
 * CLI refused to give.
 */
function ThreadMetrics({
  settledMs,
  turnCount,
  openTurn,
  costUsd,
}: {
  settledMs: number;
  turnCount: number;
  openTurn: OpenTurn | null;
  costUsd: number | null;
}): React.JSX.Element | null {
  useSecondTick(openTurn !== null);
  const liveMs = openTurnWorkedMs(openTurn, Date.now());
  const totalMs = settledMs + liveMs;
  // The running turn counts toward the tally because its time counts toward
  // the total — a sum over fifteen turns labelled "14 turns" is the kind of
  // small lie a reader has no way to catch.
  const turns = turnCount + (openTurn === null ? 0 : 1);
  const worked = totalMs > 0 ? formatDuration(totalMs) : null;
  const spend = costUsd === null ? null : formatUsd(costUsd);
  if (worked === null && spend === null) {
    return null;
  }
  return (
    <span
      data-slot="thread-metrics"
      className="flex shrink-0 items-center gap-1 text-xs tabular-nums text-muted-foreground"
      title={threadMetricsTitle(worked, turns, openTurn !== null, spend)}>
      {worked === null ? null : (
        <>
          {/* The word `worked` was three of the line's characters and is the
              one thing here a glyph can say as well. It is NOT decoration: a
              bare `4m 13s` beside a price reads as "4m 13s ago", which is a
              different fact and one the header used to state a few pixels to
              the left. */}
          <Timer aria-hidden="true" className="size-3.5 shrink-0" />
          {worked}
        </>
      )}
      {worked !== null && spend !== null ? (
        <span aria-hidden="true">·</span>
      ) : null}
      {spend}
    </span>
  );
}

/**
 * The sentence behind {@link ThreadMetrics} — everything the row stopped
 * spelling out.
 *
 * Kept as a `title` rather than a hover panel: it is two clauses of prose, and
 * the panels in this header exist for LISTS (the delegates, the shells, the
 * tasks) where a count alone cannot say what it counts.
 */
function threadMetricsTitle(
  worked: string | null,
  turns: number,
  running: boolean,
  spend: string | null,
): string {
  const parts: string[] = [];
  if (worked !== null) {
    parts.push(
      running
        ? `Worked ${worked} across ${turns} ${turns === 1 ? 'turn' : 'turns'} — the turn in flight included, paused while it waits on you`
        : `Worked ${worked} across ${turns} ${turns === 1 ? 'turn' : 'turns'} — not the span since the thread started`,
    );
  }
  if (spend !== null) {
    parts.push(`Cost ${spend}, summed over every turn that reported one`);
  }
  return parts.join('. ');
}

/**
 * The three facts fixed for this run's whole life — the agent, the folder and
 * the profile — behind ONE chip.
 *
 * They were three chips in a row, and on the reported header they read
 * `claude  ManifestOS  .claude-manifest-lab` before the status word had even
 * been reached. Each is true and each is the same KIND of fact, which is what
 * makes one chip the right shape: the folder is the one a reader checks at a
 * glance ("which repo is this thread in"), and the other two are qualifiers on
 * it that are consulted, not scanned.
 *
 * So the leaf stays on the trigger and the rest is one hover away, with every
 * value in full — which the chips could not do anyway, since all three
 * truncated a deep path down to its last component.
 */
function ThreadIdentity({
  agentKind,
  cwd,
  configDir,
}: {
  agentKind: string | null;
  cwd: string | null;
  configDir: string | null;
  // Still on the props, still unread: `Chats` passes it and the daemon still
  // sends it, and both go when `ConfigDirPin` is deleted end to end.
  configDirPin?: ConfigDirPin | null;
}): React.JSX.Element | null {
  // The folder leads, and the agent stands in for it on a run that has none —
  // a workflow, whose agents are per node, has neither and draws nothing.
  const leaf = cwd === null ? agentKind : folderName(cwd);
  if (leaf === null) {
    return null;
  }
  return (
    <HoverPopover
      slot="thread-identity"
      label={`Thread identity: ${[agentKind, cwd, configDir].filter((part) => part !== null).join(', ')}`}
      panelLabel="Thread identity"
      side="bottom"
      align="start"
      // The chip's own look, spelled here rather than nested: `HoverPopover`
      // renders the trigger BUTTON, and a `Chip` inside it would be an element
      // with a control's styling wrapped in a control.
      triggerClassName="h-6 min-w-0 gap-1.5 rounded-lg px-1.5 text-xs font-medium text-muted-foreground transition-colors hover:bg-accent hover:text-accent-foreground"
      panelClassName="w-[24rem]"
      trigger={
        <>
          {cwd === null ? (
            <Bot aria-hidden="true" className="size-3.5 shrink-0" />
          ) : (
            <FolderOpen aria-hidden="true" className="size-3.5 shrink-0" />
          )}
          <span className="max-w-40 truncate">{leaf}</span>
        </>
      }>
      <ul className="m-0 flex list-none flex-col gap-1.5 p-0">
        <IdentityRow
          icon={<Bot aria-hidden="true" className="size-3.5 shrink-0" />}
          name="Agent"
          value={agentKind}
          fallback="One per node"
        />
        <IdentityRow
          icon={<FolderOpen aria-hidden="true" className="size-3.5 shrink-0" />}
          name="Folder"
          value={cwd}
          fallback={null}
        />
        <IdentityRow
          icon={<IdCard aria-hidden="true" className="size-3.5 shrink-0" />}
          name="Profile"
          // The chat's OWN profile, which is what the turn runs as — MEASURED,
          // after this row spent a release claiming otherwise. A folder's
          // `.claude/settings.local.json` `env.CLAUDE_CONFIG_DIR` does NOT
          // outrank it, and does not apply in its absence either: in the
          // reporter's own pinned folder on 2.1.247, `CLAUDE_CONFIG_DIR=…
          // -personal` loaded the personal profile's 17 servers, `…-lab` the
          // team profile's 51, and NO variable loaded the default `~/.claude`'s
          // 12 — the pinned profile never once won. It cannot: that variable
          // decides where the CLI reads its config FROM, and a project settings
          // file is read after that decision is made, so its `env` block
          // reaches the tools the agent runs and not the CLI's own resolution.
          value={configDir}
          // A run on the CLI's own profile is not a run with no profile, and
          // the chips said nothing at all about it — the row that vanished was
          // the commonest case.
          fallback="The CLI’s default"
        />
        {/* The `Pinned by` row is GONE with the override it described. It
            reported a folder file as having decided this chat's account, and
            the measurement above says no such thing happens — so it named a
            real file next to a claim that was never true, which is worse than
            saying nothing. `configDirPin` is still on the wire and is now read
            by nothing; see the daemon's `ConfigDirPinService` for the removal
            that belongs with this. */}
      </ul>
    </HoverPopover>
  );
}

/**
 * One fact in {@link ThreadIdentity}'s panel. `fallback` is what a null MEANS
 * where it means something; a null with none is simply not a row.
 */
function IdentityRow({
  icon,
  name,
  value,
  fallback,
}: {
  icon: React.ReactNode;
  name: string;
  value: string | null;
  fallback: string | null;
}): React.JSX.Element | null {
  const shown = value ?? fallback;
  if (shown === null) {
    return null;
  }
  return (
    <li className="flex items-start gap-1.5 text-xs text-muted-foreground">
      {icon}
      {/* Wide enough for the longest label and `nowrap` besides: at `w-14` the
          two-word `Pinned by` broke over two lines and pushed its own value's
          first line up against the row above it. */}
      <span className="w-[4.75rem] shrink-0 whitespace-nowrap">{name}</span>
      {/* `break-all`, not truncation: the panel exists BECAUSE the chips could
          only ever show a path's last component. Bounded at three lines all the
          same — the pin row states two full paths and ran to five, which made
          one row taller than the other three together — with the whole value on
          the row's own `title`, so nothing is lost by the clamp. */}
      <span
        className="line-clamp-3 min-w-0 flex-1 break-all text-foreground"
        title={shown}>
        {shown}
      </span>
    </li>
  );
}

/**
 * A spend, in the smallest number of digits that still distinguishes two turns.
 *
 * Cents for anything a user would recognise as an amount, and four decimals
 * below one cent — a thread that has cost $0.0003 must not round to `$0.00`,
 * which is the same "we measured nothing" claim the null case is careful to
 * avoid making.
 */
function formatUsd(costUsd: number): string {
  return costUsd > 0 && costUsd < 0.01
    ? `$${costUsd.toFixed(4)}`
    : `$${costUsd.toFixed(2)}`;
}

/**
 * What the sub-agent count is a count OF — the delegates themselves, behind the
 * number.
 *
 * The count alone was the whole readout, and a number is not an answer to "what
 * is it doing": REPORTED as "при наведении на поп-овер эйджентов: список
 * текущих эйджентов". Each row states its own status through the app's one
 * status vocabulary ({@link RunStatusIcon}), so a delegate that finished, one
 * that failed and one still working are told apart here exactly as they are in
 * the panel below.
 *
 * The empty case is a SENTENCE rather than an empty box, because the counter is
 * now drawn at zero: "0" with nothing behind it reads as a readout that failed
 * to load.
 */
function SubagentList({
  threads,
}: {
  threads: readonly AgentThread[];
}): React.JSX.Element {
  if (threads.length === 0) {
    return (
      <p className="text-[11px] text-muted-foreground">
        No sub-agents yet — this thread’s agent has delegated nothing.
      </p>
    );
  }
  return (
    <ul className="m-0 flex list-none flex-col gap-1 p-0">
      {threads.map((thread) => (
        <li
          key={thread.id}
          className="flex items-center gap-1.5 text-xs text-muted-foreground">
          <RunStatusIcon status={thread.status} />
          <span className="min-w-0 flex-1 truncate text-foreground">
            {thread.label}
          </span>
          <span
            className={cn(
              'shrink-0',
              RUN_STATUS_META[thread.status].className,
            )}>
            {RUN_STATUS_META[thread.status].label}
          </span>
        </li>
      ))}
    </ul>
  );
}

/**
 * The open transcript's header, in two halves: on the LEFT what this thread IS
 * — its name, the three facts fixed for the run's whole life behind one chip
 * ({@link ThreadIdentity}: the agent, the folder it runs in, the profile it
 * runs as), then the live status and, once it settles, when it last spoke. On
 * the RIGHT the NUMBERS about it — what it worked and what it cost
 * ({@link ThreadMetrics}), then what the agents panel is holding.
 *
 * That split is the answer to "we have soo much information here. I wanna
 * redesign it, minimize", reported against a line carrying nine things:
 * `Смотри, у меня… claude  ManifestOS  .claude-manifest-lab  running · worked
 * 4m 13s / 5 turns · $1.11` plus two counters. Nothing was DELETED — every
 * figure is still on the header or one hover into it — and nothing new was
 * invented; three chips became one and two prose readouts became one pair of
 * figures. What the arrangement buys is the title: the left side is what
 * truncates when the row runs short, so every character of prose there was
 * paid for out of the thread's own name.
 *
 * The counters used to BE the agents panel's toggle; the panel is always on
 * screen now, so there is nothing left to open. The context meter used to sit
 * here too and has moved into the composer, beside Send — the question it
 * answers ("how much room is left") is asked while composing the next message,
 * not while reading the header. Everything per-agent (threads, per-node
 * context) stays in the panel.
 */
export function ChatHeader({
  label,
  isWorkflow,
  agentKind = null,
  cwd = null,
  configDir = null,
  configDirPin = null,
  status,
  lastActivityAt,
  workedMs = 0,
  turnCount = 0,
  costUsd = null,
  openTurn = null,
  runningSubagents = 0,
  shells = [],
  onOpenShell,
  tasks = null,
  subagents = [],
  taskRows = [],
}: {
  label: string;
  isWorkflow: boolean;
  /**
   * The CLI driving a single-agent chat. It lives HERE rather than in the
   * composer below: it is fixed for the life of the run, and a chip stating an
   * unchangeable fact sat among five that change things. Null for a workflow
   * run, whose agents are per node — the panel lists those.
   */
  agentKind?: string | null;
  /**
   * The folder this run's turns happen in.
   *
   * HERE, on the same rule the agent and the profile beside it already follow:
   * it is fixed for the life of the run and it changes what the conversation IS
   * — the same question asked in two repositories is two conversations. That
   * rule was already written down one field below, for the config directory,
   * and the cwd is the plainer case of it; what kept the cwd out of the header
   * was a separate reading, that a folder is a caption on the MESSAGE.
   *
   * It comes here after three positions in the composer — beside Send, then a
   * row above the card, then inside the card's top right — each of which the
   * user rejected on how it looked, the last one flatly ("мне все еще не
   * нравится, как это выглядит… может, в шапку?"). The composer is where the
   * run's LIVE choices are, and the folder is not one: every arrangement that
   * put an unchangeable fact among the pickers had to earn its own band, and
   * the band was the thing that looked wrong. Here it costs no layout at all —
   * the identity line already exists and already truncates.
   */
  cwd?: string | null;
  /**
   * The agent config directory this run's turns use — which account/profile
   * the CLI runs as — or null for the CLI's own default.
   *
   * HERE, beside the agent, for the same reason the agent is: it is fixed for
   * the life of the run and it changes what the conversation IS — a different
   * profile is a different subscription, different plugins, different history.
   * A run on the default profile shows nothing, because "the usual one" is not
   * news; only a run that departs from it earns a chip.
   */
  configDir?: string | null;
  /**
   * What this run's FOLDER pins for its CLI, overriding the profile above.
   *
   * The daemon reads it per run, because the CLI applies a project settings
   * `env` block over the environment geniro hands it — so the profile a chat
   * was pointed at is a REQUEST, and this is what came of it.
   */
  configDirPin?: ConfigDirPin | null;
  /**
   * The DISPLAY status, not the daemon's row value — wider than `RunStatus`
   * because `needs-input` is derived in the renderer (`displayRunStatus`) and
   * no daemon row ever carries it.
   */
  status: RunStatusKind;
  lastActivityAt: string;
  /**
   * What this thread has WORKED in total — the sum of its turns, not the span
   * from its first message to its last.
   *
   * The two differ enormously and only one answers the question: a chat left
   * open across three days with five minutes of work in it spans `3d` and
   * worked `5m`. Zero (a thread whose turns reported nothing, or that has none
   * yet) renders nothing rather than `0s`.
   */
  workedMs?: number;
  /** How many settled turns {@link workedMs} is the sum of. */
  turnCount?: number;
  /**
   * What this thread has spent in USD, or null when nothing measured it.
   *
   * Summed by the DAEMON over the run's own turns rather than folded from the
   * transcript on screen — see `use-chat-totals.ts`. Null is a real answer and
   * renders nothing: a CLI that reports no cost has not made this thread free.
   */
  costUsd?: number | null;
  /**
   * The turn still in flight, so the total keeps MOVING while one is — null
   * when nothing is running.
   *
   * {@link workedMs} alone is the settled sum, which is a figure that stands
   * still for the whole of a turn: the reported defect was a header sitting on
   * `worked 64m 34s` while the agent visibly worked. Handed over as the turn's
   * pieces rather than as a number, because a number would freeze the instant
   * it was computed — a timestamp rather than an elapsed count, for the same
   * reason `turn-duration.ts` records against its own.
   */
  openTurn?: OpenTurn | null;
  /** Delegates working right now. */
  runningSubagents?: number;
  /**
   * The shells this run's agents have RUNNING right now — the commands, not a
   * count, since the counter holds the list behind it exactly as the sub-agent
   * one does.
   *
   * Asked for beside that count, and it belongs beside it: both say how much
   * work is in flight that the transcript alone would make you hunt for. The
   * rows come from the same map the panel's sections render — liveness rule
   * and all — so a `2` here and two cards below cannot disagree.
   */
  shells?: readonly ShellRun[];
  /** Show one command's own output, from the counter's own list. */
  onOpenShell?: (shell: ShellRun) => void;
  /**
   * The agents' own task lists, as DONE OUT OF TOTAL — null when no agent here
   * keeps one.
   *
   * A bare count of what is left was what got reported: `6` alone says nothing
   * about whether that is six of seven or six of sixty, and it only ever
   * shrinks, so it reads as a countdown out of an unstated number. The pair is
   * also the one form the rest of the app already uses for a list's progress
   * ({@link TaskCount}, in the transcript cards, the panel and the sub-agent
   * headers), so the header now agrees with every other place the same lists
   * are summarized instead of speaking its own dialect.
   */
  tasks?: { done: number; total: number } | null;
  /**
   * Every delegate this run has launched, for the list behind the count —
   * running ones and the ones that have finished, in the order the agents panel
   * holds them.
   *
   * The COUNT still comes from {@link runningSubagents}: it is a reading over
   * every agent of the run, taken where the agents are, and re-deriving it here
   * from a list assembled for a popover would be a second answer to a question
   * the sidebar and the panel already answer once.
   */
  subagents?: readonly AgentThread[];
  /**
   * The task rows behind {@link tasks}' count — the agents' own lists, merged
   * in the order the panel shows them.
   */
  taskRows?: readonly AgentTaskRow[];
}): React.JSX.Element {
  return (
    // A header for the TRANSCRIPT, not for the window: the shell's title bar is
    // one band above every column (`components/title-bar.tsx`), and this row no
    // longer moves the window — dragging a row full of chips was surprising
    // once a real title bar existed.
    // ONE LINE, and nothing in it wraps. The row used to be `flex-wrap`, where
    // wrapping is all-or-nothing: the identity group grows with the thread
    // (agent, profile, status, elapsed, worked, spend) until it fills the row,
    // and the whole right-hand group then drops to a SECOND LINE — the reported
    // "subagent icon не должен переноситься на новую строку".
    //
    // Wrapping INSIDE the identity was tried next and is not the answer either:
    // it kept the counters in place while orphaning "· worked 2.7s · $0.20" on
    // a line of its own, leading middot and all. What gives instead is the
    // TITLE, which is the one thing here that can be shortened and still read —
    // it already truncates, and `min-w-0` is what lets it.
    <div className="flex items-center gap-x-4 border-b border-border bg-card/60 px-4 py-2.5">
      <div className="flex min-w-0 flex-1 items-center gap-2">
        {isWorkflow ? (
          <WorkflowIcon
            aria-hidden="true"
            className="size-4 shrink-0 text-muted-foreground"
          />
        ) : null}
        <h2 className="min-w-0 truncate text-sm font-semibold tracking-tight">
          {label}
        </h2>
        <ThreadIdentity
          agentKind={agentKind}
          cwd={cwd}
          configDir={configDir}
          configDirPin={configDirPin}
        />
        <span className="flex shrink-0 items-center gap-1 text-xs">
          <RunStatusIcon status={status} />
          <span className={RUN_STATUS_META[status].className}>
            {RUN_STATUS_META[status].label}
          </span>
        </span>
        {/* NOTHING while it runs — {@link ThreadMetrics} is the clock then, and
            it ticks. There used to be a second one here, this turn's raw wall
            clock, and on a thread's first turn the two are the same number
            twice: REPORTED against `running · 21s · worked 21s` as "у нас
            сейчас два раза показывается таймер… нам нужен только таймер,
            сколько он в целом работал".

            Only the RUNNING half goes. Settled, this slot says when the thread
            last spoke, which is a different question from how much work is in
            it — the pair `completed · 4m · worked 1h 41m 5s` is two answers,
            not one twice. And the reason the wall clock was here at all is
            answered by what replaces it: the relative time reads "just now"
            for a whole turn, which is why it cannot be shown while running,
            and `worked` moves every second, which is what the relative time
            could not do.

            What is genuinely lost is the wait on an APPROVAL card: `worked`
            pauses there by design, so a thread parked for ten minutes now
            shows the seconds it worked rather than the minutes it waited. The
            card is on screen saying so. */}
        {isWorkingRunStatus(status) ? null : (
          <span className="shrink-0 text-xs text-muted-foreground">
            · {formatRelativeTime(lastActivityAt)}
          </span>
        )}
      </div>
      {/* `shrink-0` beside the identity's `flex-1 min-w-0`: the figures and the
          counters are a fixed handful of characters, so the row gives up width
          on the side that has a truncating title rather than squeezing a
          number. */}
      <div className="ml-auto flex shrink-0 items-center gap-3">
        {/* The reported ask: what the thread COST, next to what it worked. The
            pair is the point — a price with no sense of the work behind it is
            the same half-answer the duration was on its own. */}
        <ThreadMetrics
          settledMs={workedMs}
          turnCount={turnCount}
          openTurn={openTurn}
          costUsd={costUsd}
        />
        {/* What the agents panel is holding, at a glance. It used to BE that
            panel's toggle — "how much work is in here" was the one thing a bare
            chevron could not say, so the counts and the control were one
            button. The panel is always on screen now, so there is nothing left
            to OPEN; what a press does here is pin the readout each count holds
            behind it.

            The sub-agent counter is drawn WHATEVER the count — the reported
            "здесь должна быть всегда иконка саб-эйджентов, даже если их ноль".
            A counter that appears only once something is running answers "are
            any working" with the same blank space as a header that never had
            one, and the reader cannot tell which of the two they are looking
            at. The task counter still comes and goes: a thread whose agent
            keeps no list has no list to report on, where every thread has
            delegates it could have launched and did not. */}
        <span
          data-slot="side-panel-counts"
          className="flex shrink-0 items-center gap-2 text-xs tabular-nums text-muted-foreground">
          <HoverPopover
            slot="running-subagents"
            label={`${runningSubagents} sub-${runningSubagents === 1 ? 'agent' : 'agents'} working`}
            panelLabel="Sub-agents"
            side="bottom"
            triggerClassName={COUNT_TRIGGER_CLASS}
            // Bounded and scrolling, like every other list this app hangs off a
            // count: a delegating turn can hold a dozen, and a panel that grows
            // with them runs off the bottom of the window.
            panelClassName="max-h-64 w-[18rem] overflow-y-auto"
            trigger={
              <>
                <Bot aria-hidden="true" className="size-3.5 shrink-0" />
                {runningSubagents}
              </>
            }>
            <SubagentList threads={subagents} />
          </HoverPopover>
          {/* Beside the delegates, and drawn at zero for the same reason they
              are: "is anything running on my machine" is a question with an
              answer either way, and a counter that appears only once something
              is gives the same blank space for "nothing" as for "this header
              has no such readout". The two are the pair a reader scans — how
              many agents are working, and how many commands they have open. */}
          <HoverPopover
            slot="running-shells"
            label={`${shells.length} shell${shells.length === 1 ? '' : 's'} running`}
            panelLabel="Shells"
            side="bottom"
            triggerClassName={COUNT_TRIGGER_CLASS}
            // Bounded and scrolling, like the delegates' — a fan-out can hold a
            // dozen, and the rows are long (a command, not a name).
            panelClassName="max-h-64 w-[22rem] overflow-y-auto"
            trigger={
              <>
                <ShellIcon className="size-3.5" />
                {shells.length}
              </>
            }>
            <ShellRows shells={shells} onOpen={onOpenShell} />
          </HoverPopover>
          {tasks !== null && tasks.total > 0 ? (
            <HoverPopover
              slot="open-tasks"
              label={`${tasks.done} of ${tasks.total} ${tasks.total === 1 ? 'task' : 'tasks'} done`}
              panelLabel="Task list"
              side="bottom"
              triggerClassName={COUNT_TRIGGER_CLASS}
              panelClassName="w-[20rem]"
              trigger={
                <>
                  <TaskIcon className="size-3.5" />
                  <TaskCount done={tasks.done} total={tasks.total} />
                </>
              }>
              {/* The panel's own bounded list — it already scrolls itself and
                  follows the task that is running, so a thirteen-row list opens
                  on the row that matters rather than on five finished ones. */}
              <TaskScrollRows tasks={taskRows} live={status === 'running'} />
            </HoverPopover>
          ) : null}
        </span>
      </div>
    </div>
  );
}
