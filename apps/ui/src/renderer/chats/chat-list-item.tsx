import { Pencil, Trash2, Workflow as WorkflowIcon } from 'lucide-react';
import { memo, useEffect, useRef, useState } from 'react';

import type { RunAwaiting } from '../autogenerated';
import { NavListItem } from '../components/nav-list-item';
import { Button } from '../components/ui/button';
import { Input } from '../components/ui/input';
import { cn } from '../components/ui/utils';
import { formatRelativeTime } from './relative-time';
import {
  awaitingPhrase,
  RUN_STATUS_META,
  RunStatusIcon,
  type RunStatusKind,
} from './run-status';

/**
 * One chat-list row: the run's label (custom title, else its workflow's name,
 * else the agent), hover-revealed rename/delete controls, the latest message
 * as a one-line preview, and a status line — icon + tone per state, spinning
 * while running — with the last-activity time on the right (hidden while
 * running: the spinner IS the live signal). A running row additionally names
 * what the agent is doing, so the badge distinguishes work from a turn parked
 * waiting on the user.
 *
 * Filing it into a group is a DRAG, not a control on this row: a chat is moved
 * by dragging it into the group, which is one gesture where a menu was a click,
 * a read and a second click. Nothing here knows about groups any more.
 *
 * Renaming happens IN the row: the label becomes a text field in place, so the
 * name is edited where it is read instead of in a popup that hides the list it
 * came from. Enter commits, Escape reverts, blur commits. The edit state is
 * local to the row — the parent only supplies the commit, which throws to
 * report a failure, keeping the row in edit mode with the reason shown.
 *
 * Memoized (the sidebar renders one per run on every composer keystroke) —
 * callbacks take the row's `runId` so the parent can pass stable functions.
 */
export const ChatListItem = memo(function ChatListItem({
  runId,
  label,
  isWorkflow,
  status,
  lastMessage,
  lastActivityAt,
  activity = null,
  awaiting = null,
  active,
  onActivate,
  onRename,
  onDelete,
  dragging = false,
  onDragStartRun,
  onDragEndRun,
}: {
  runId: string;
  label: string;
  /** Show the workflow glyph before the label (a team run, not a 1:1 chat). */
  isWorkflow: boolean;
  /**
   * The DISPLAY status, not the daemon's row value — wider than `RunStatus`
   * because `needs-input` is derived in the renderer (`displayRunStatus`) and
   * no daemon row ever carries it.
   */
  status: RunStatusKind;
  lastMessage: string | null;
  /** ISO time of the run's last activity (its `updatedAt`). */
  lastActivityAt: string;
  /**
   * What this run is doing right now ("running Bash"), or null. Shown BESIDE
   * the status word while running: "running" alone cannot tell one piece of
   * work from another.
   */
  activity?: string | null;
  /**
   * What the run is parked on waiting for the user, straight from the daemon's
   * approval registry — null when it is not parked.
   *
   * Separate from `activity` because it comes from a different place and
   * outlives it: `activity` rides events only, so it is empty in a window that
   * connected after the turn parked, whereas this is on the run row itself.
   * That gap is why the phrase used to disappear on a reload while the badge
   * stayed correct.
   */
  awaiting?: RunAwaiting | null;
  active: boolean;
  onActivate: (runId: string) => void;
  /** Commit a new title. Rejects to report the failure back into the row. */
  onRename: (runId: string, title: string) => Promise<void>;
  onDelete: (runId: string) => void;
  /** This is the row being dragged — dimmed while it travels. */
  dragging?: boolean;
  /**
   * Picked up, and put down. Where it LANDS is the section's business
   * (`Chats.tsx`): a drop zone has to cover a whole group, including the space
   * between its rows, and `dragover` bubbles there from here anyway.
   */
  onDragStartRun?: (runId: string) => void;
  onDragEndRun?: () => void;
}): React.JSX.Element {
  const meta = RUN_STATUS_META[status];
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(label);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  useEffect(() => {
    if (editing) {
      inputRef.current?.focus();
      inputRef.current?.select();
    }
  }, [editing]);

  const startEditing = (): void => {
    setDraft(label);
    setError(null);
    setEditing(true);
  };
  const commit = async (): Promise<void> => {
    const title = draft.trim();
    // Nothing to save — an empty name would leave the row unidentifiable, and
    // an unchanged one is not worth a request.
    if (title.length === 0 || title === label) {
      setEditing(false);
      return;
    }
    setBusy(true);
    setError(null);
    try {
      await onRename(runId, title);
      setEditing(false);
    } catch (err) {
      // Stay open carrying the reason: closing would discard the typed name
      // and leave the failure invisible.
      setError(String(err));
    } finally {
      setBusy(false);
    }
  };

  return (
    <NavListItem
      active={active}
      // `select-none`: without it a press-and-drag on the row starts a TEXT
      // selection instead of the drag, which is what "выделяется, но не
      // перетаскивается" looks like from the other side of the screen.
      className={cn('group select-none', dragging && 'opacity-40')}
      activateLabel={label}
      suspendActivation={editing}
      // Not while renaming: a text field inside a draggable element cannot be
      // selected with the mouse, because the drag starts instead.
      draggable={onDragStartRun !== undefined && !editing}
      onDragStart={(event) => {
        // Firefox refuses to start a drag with no payload; the value is never
        // read back, since the parent already knows what it picked up.
        event.dataTransfer.setData('text/plain', runId);
        event.dataTransfer.effectAllowed = 'move';
        onDragStartRun?.(runId);
      }}
      onDragEnd={() => onDragEndRun?.()}
      onActivate={() => onActivate(runId)}>
      <span className="flex items-center gap-1.5">
        {isWorkflow ? (
          <WorkflowIcon
            aria-hidden="true"
            className="size-3.5 shrink-0 text-muted-foreground"
          />
        ) : null}
        {editing ? (
          <Input
            ref={inputRef}
            value={draft}
            disabled={busy}
            aria-label={`Rename ${label}`}
            aria-invalid={error !== null || undefined}
            className="h-6 min-w-0 flex-1 px-1.5 py-0 text-sm"
            onChange={(event) => setDraft(event.target.value)}
            onKeyDown={(event) => {
              // The commit is one request — an Enter confirming an IME
              // composition must not fire it on a half-composed name.
              if (event.nativeEvent.isComposing) {
                return;
              }
              if (event.key === 'Enter') {
                void commit();
              } else if (event.key === 'Escape') {
                // Closing unmounts the field, and removing a focused element
                // fires no blur — so the abandoned draft cannot leak through
                // the commit-on-blur path below. The error goes with it: it
                // describes an attempt the user just abandoned, and the row
                // renders it from state, so leaving it would strand a red
                // failure line under a name that is no longer being edited.
                setError(null);
                setEditing(false);
              }
            }}
            onBlur={() => {
              if (!busy) {
                void commit();
              }
            }}
          />
        ) : (
          <>
            <span className="min-w-0 flex-1 truncate text-sm font-medium">
              {label}
            </span>
            {/* Chats only: a workflow run's name comes from the workflow it
                ran, so renaming it here would read as editing the library
                entry from another view. */}
            {isWorkflow ? null : (
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-5 shrink-0 text-muted-foreground opacity-0 group-hover:opacity-100 focus-visible:opacity-100"
                aria-label={`Rename ${label}`}
                title="Rename"
                onClick={(event) => {
                  event.stopPropagation();
                  startEditing();
                }}>
                <Pencil className="size-3 shrink-0" />
              </Button>
            )}
            {/* BOTH kinds. A workflow ROW is one run's history, not the
                workflow — deleting it leaves the library entry untouched. It
                was gated with rename before, which is why the sidebar's
                workflow rows could not be removed at all. */}
            <Button
              type="button"
              variant="ghost"
              size="icon"
              className="size-5 shrink-0 text-muted-foreground opacity-0 group-hover:opacity-100 hover:text-destructive focus-visible:opacity-100"
              aria-label={`Delete ${label}`}
              title="Delete"
              onClick={(event) => {
                event.stopPropagation();
                onDelete(runId);
              }}>
              <Trash2 className="size-3 shrink-0" />
            </Button>
          </>
        )}
      </span>
      {error ? (
        <span className="truncate text-xs text-destructive">{error}</span>
      ) : null}
      {lastMessage ? (
        <span className="truncate text-xs text-muted-foreground">
          {lastMessage}
        </span>
      ) : null}
      <span className="flex items-center gap-1 text-xs">
        {/* Every glyph but the SPINNER leads its label. A spinner is the one
            that draws the eye on its own, and a moving thing in front of the
            word it belongs to pushed the whole line about; it goes to the far
            right instead — the slot a running row leaves empty (the relative
            time below is for stopped runs only), and where the group header
            above already puts its own. */}
        {status === 'running' ? null : <RunStatusIcon status={status} />}
        {/* Never wrapped: the status word is the shortest thing on the line and
            the one that must stay readable, so the activity phrase beside it
            (which already truncates) is what gives up room. Before this,
            `needs more info` broke across two lines and made the row taller
            than its neighbours. */}
        <span className={cn('shrink-0 whitespace-nowrap', meta.className)}>
          {meta.label}
        </span>
        {/* A parked row gets a phrase too, and it is worded from the KIND
            rather than taken from the activity plane: the label says the run is
            blocked on the user, this says on WHAT — the difference between
            going to read a question and going to press a button. */}
        {status === 'needs-input' && awaiting ? (
          <span className="min-w-0 truncate text-muted-foreground">
            · {awaitingPhrase(awaiting)}
          </span>
        ) : status === 'running' && activity ? (
          <span className="min-w-0 truncate text-muted-foreground">
            · {activity}
          </span>
        ) : null}
        {/* The time is for runs that have STOPPED — "when did this last do
            anything" is only a question about a run that is no longer doing
            it. A parked run is as live as a running one (its turn is open, its
            process is up), so it is excluded for the same reason `running` is
            — and on a 260px sidebar it was the third thing competing for the
            line, which is what made the status label wrap onto two rows. */}
        {status !== 'running' && status !== 'needs-input' ? (
          <span className="ml-auto pl-2 text-muted-foreground">
            {formatRelativeTime(lastActivityAt)}
          </span>
        ) : null}
        {status === 'running' ? (
          // `ml-auto` and no padding: the glyph is a border-box `size-3`, so a
          // `pl-*` here would eat its own drawn area rather than space it.
          <RunStatusIcon status={status} className="ml-auto" />
        ) : null}
      </span>
    </NavListItem>
  );
});
