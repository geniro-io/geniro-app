/**
 * What the agent label SAYS — `claude`, `cursor`, `graph`.
 *
 * Three shortenings, and each earns itself. A workflow run has no single CLI
 * (its agents are per node), so the honest word is what it IS: a graph. The
 * daemon spells the second CLI `cursor-agent`, which is the BINARY's name — the
 * user's own word for it is `cursor`, and this label has room for one word.
 * And a run whose kind was never recorded says nothing rather than guessing,
 * which is the same three-state reading the rest of the app takes: an absent
 * fact is not a fact about absence.
 *
 * Deliberately NOT shared with the agents panel, which renders `agent.agent`
 * raw in its own badge — that panel is about one run's agents and has room for
 * the exact kind, where this is a 260px rail on which every row carries the
 * label. The SHORTENING is shared, though: the call block's header became the
 * third surface wanting a display name, which is the condition this note used
 * to name for promoting it, so `cursor-agent → cursor` now lives in
 * `agent-label.ts` and the two arms below are what stays local to a row whose
 * label slot is always filled.
 */
function agentLabel(
  agentKind: string | null,
  isWorkflow: boolean,
  workflowName: string | null,
): string {
  if (isWorkflow) {
    // The WORKFLOW's own name when this client knows it, and `graph` only when
    // it does not (a run of a workflow since deleted from the library).
    //
    // It said `graph` on every workflow row, which is the same word for every
    // run of every workflow — true, and the least useful true thing available:
    // the label slot is the one part of the row that says what KIND of thing it
    // is, and the row's title now says what the run is DOING rather than which
    // workflow it is (see the daemon's `ChatTitleService`). Asked for as the
    // other half of that change — "name of workflow should be as chip".
    return workflowName ?? 'graph';
  }
  return shortAgentLabel(agentKind) ?? 'agent';
}

/**
 * One chat-list row: the run's label (custom title, else its workflow's name,
 * else the agent), hover-revealed rename/delete controls, the latest message
 * as a one-line preview, and a status line — icon + tone per state, always
 * LEADING the status word, spinning while running — with the last-activity time
 * on the right (hidden while running: the spinner IS the live signal). A
 * running row additionally names what the agent is doing, so the badge
 * distinguishes work from a turn parked waiting on the user.
 *
 * Filing it into a group is a DRAG, not a control on this row: a chat is moved
 * by dragging it into the group, which is one gesture where a menu was a click,
 * a read and a second click. Nothing here knows about groups any more.
 *
 * Renaming happens IN the row: the label becomes a text field in place, so the
 * name is edited where it is read instead of in a popup that hides the list it
 * came from. Enter commits, Escape reverts, blur commits. The edit state is
 * local to the row — the parent only supplies the commit, which throws to
 * report a failure, keeping the row in edit mode with the reason shown.
 *
 * Memoized (the sidebar renders one per run on every composer keystroke) —
 * callbacks take the row's `runId` so the parent can pass stable functions.
 */
export const ChatListItem = memo(function ChatListItem({
  runId,
  label,
  isWorkflow,
  workflowName = null,
  status,
  lastMessage,
  lastActivityAt,
  activity = null,
  awaiting = null,
  agentKind = null,
  taskIdentifier = null,
  pullRequest = null,
  active,
  unseen = false,
  naming = false,
  onActivate,
  onRename,
  onDelete,
  onArchive,
  onUnarchive,
  archived = false,
  pinned = false,
  onSetPinned,
  dragging = false,
  onDragStartRun,
  onDragOverRun,
  onDragEndRun,
}: {
  runId: string;
  label: string;
  /** Show the workflow glyph before the label (a team run, not a 1:1 chat). */
  isWorkflow: boolean;
  /**
   * The workflow's own name, for the label chip — see {@link agentLabel}. Null
   * for a 1:1 chat, and for a run whose workflow this client cannot name.
   */
  workflowName?: string | null;
  /**
   * The DISPLAY status, not the daemon's row value — wider than `RunStatus`
   * because `needs-input` is derived in the renderer (`displayRunStatus`) and
   * no daemon row ever carries it.
   */
  status: RunStatusKind;
  lastMessage: string | null;
  /** ISO time of the run's last activity (its `updatedAt`). */
  lastActivityAt: string;
  /**
   * What this run is doing right now ("running Bash"), or null. Shown BESIDE
   * the status word while running: "running" alone cannot tell one piece of
   * work from another.
   */
  activity?: string | null;
  /**
   * What the run is parked on waiting for the user, straight from the daemon's
   * approval registry — null when it is not parked.
   *
   * Separate from `activity` because it comes from a different place and
   * outlives it: `activity` rides events only, so it is empty in a window that
   * connected after the turn parked, whereas this is on the run row itself.
   * That gap is why the phrase used to disappear on a reload while the badge
   * stayed correct.
   */
  awaiting?: RunAwaiting | null;
  /**
   * Which CLI drives this thread — the daemon's own spelling, or null for a run
   * that recorded none. Ignored for a workflow, whose agents are per node; see
   * {@link agentLabel}.
   */
  agentKind?: string | null;
  /**
   * The board card this thread is the work for — `GEN-12` — or null for a
   * conversation nobody started from one.
   *
   * Read off the RUN row, which carries it denormalized: the sidebar holds
   * runs and no board, and the identifier is two rows away on the daemon side
   * (see `Run.taskIdentifier`).
   */
  taskIdentifier?: string | null;
  /**
   * The pull request this thread's folder is on, or null when there is none.
   *
   * Resolved by the owner rather than here: it is a match between the folder's
   * checked-out branch and a list read once per folder, and a row that fetched
   * its own would spawn one `gh` process per thread in the list.
   */
  pullRequest?: PullRequestInfo | null;
  active: boolean;
  /**
   * This thread finished, failed or asked something and the user has not
   * opened it since — see {@link import('./use-unseen-runs')}. Drawn as the
   * unread mark it is: a dot on the row and its name in the heavier weight,
   * the pairing a mail client uses, so the row reads as new at a glance and
   * nothing else about it moves.
   */
  unseen?: boolean;
  /**
   * The daemon is working out a NAME for this run right now, so the label on
   * screen is the placeholder it is about to replace.
   *
   * Drawn as a pulse on the label alone. Naming a claude chat costs a whole
   * extra CLI turn, and until this the row simply sat on the raw opening line
   * with nothing saying a better name was on its way — reported as exactly
   * that once the wait was measured.
   */
  naming?: boolean;
  onActivate: (runId: string) => void;
  /** Commit a new title. Rejects to report the failure back into the row. */
  onRename: (runId: string, title: string) => Promise<void>;
  onDelete: (runId: string) => void;
  /**
   * Shelve this run — a chat or a workflow run alike; the archive is a
   * property of the row, not a chat feature. Optional only so a harness can
   * render a row with no shelving at all.
   */
  onArchive?: (runId: string) => void;
  /** Put an archived chat back. Only ever passed in the archived view. */
  onUnarchive?: (runId: string) => void;
  /**
   * This row is being drawn in the ARCHIVE, which decides which pair of
   * actions it offers: Archive on the desk, Unarchive + Delete on the shelf.
   */
  archived?: boolean;
  /**
   * This thread is pinned to the top of its own group (or of the loose list).
   *
   * Read off the ROW rather than from where the section drew it, on the same
   * rule {@link archived} follows: the band and the rest are one list of rows,
   * so a position-derived flag would offer Unpin to whatever happened to be
   * drawn first.
   */
  pinned?: boolean;
  /**
   * Pin this thread, or unpin it. Absent on a row that cannot be pinned — an
   * archived one — which is what withholds the control rather than disabling
   * it: the daemon refuses the write, so a live button would be a press with
   * nothing behind it.
   */
  onSetPinned?: (runId: string, pinned: boolean) => void;
  /** This is the row being dragged — dimmed while it travels. */
  dragging?: boolean;
  /**
   * Picked up, and put down. Where it LANDS is the section's business
   * (`Chats.tsx`): a drop zone has to cover a whole group, including the space
   * between its rows, and `dragover` bubbles there from here anyway.
   */
  onDragStartRun?: (runId: string) => void;
  /**
   * The pointer is over THIS row while something is being dragged.
   *
   * What that means is the section's business, not the row's: within one
   * pinned band it rearranges the band under the cursor, and anywhere else it
   * does nothing at all. The row reports the position and knows neither what
   * is being carried nor what happens to it — the same split
   * {@link onDragStartRun} already documents for where a chat LANDS.
   */
  onDragOverRun?: (runId: string) => void;
  onDragEndRun?: () => void;
}): React.JSX.Element {
  const meta = RUN_STATUS_META[status];
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(label);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  const rowMenu = useContextMenu();

  useEffect(() => {
    if (editing) {
      inputRef.current?.focus();
      inputRef.current?.select();
    }
  }, [editing]);

  /**
   * Everything the row can do, for the right-click.
   *
   * It DUPLICATES the two controls the row still draws rather than holding
   * only the overflow, which is the whole point of the arrangement: the row
   * keeps the two actions worth a permanent target and the menu is the
   * complete list, so a user who has learned to right-click never has to
   * remember which half lives where. Asked for in those words — "всё остальное
   * на правый клик. И там тоже должны дублироваться архивирование или
   * нейминг".
   *
   * Two groups, and the split is by REVERSIBILITY: what the row is called and
   * where it sits, then what happens to the thread. It puts the menu's one
   * hairline between the destructive end and everything else, which is the only
   * place on this menu a reader benefits from a pause.
   */
  const menuGroups = useMemo<MenuGroup[]>(() => {
    const groups: MenuGroup[] = [];
    const naming: MenuItem[] = [];
    // A workflow run's name comes from the workflow it ran, so renaming it
    // here would read as editing the library entry from another view — the
    // same reason the row draws no pencil for one.
    if (!isWorkflow) {
      naming.push({
        value: 'rename',
        label: 'Rename',
        icon: <Pencil className="size-3.5 shrink-0" />,
      });
    }
    if (!archived && onSetPinned) {
      naming.push({
        value: 'pin',
        // Shorter than the row control's old tooltip ("Pin to the top of its
        // group"), which truncated in the panel — and the panel is where the
        // words have to survive, a menu row being the one place this action is
        // named at all now.
        label: pinned ? 'Unpin' : 'Pin to top of group',
        icon: pinned ? (
          <PinOff className="size-3.5 shrink-0" />
        ) : (
          <Pin className="size-3.5 shrink-0" />
        ),
      });
    }
    if (naming.length > 0) {
      groups.push({ items: naming });
    }
    const shelf: MenuItem[] = [];
    if (!archived && onArchive) {
      shelf.push({
        value: 'archive',
        label: 'Archive',
        icon: <Archive className="size-3.5 shrink-0" />,
      });
    }
    if (archived && onUnarchive) {
      shelf.push({
        value: 'unarchive',
        label: 'Unarchive',
        icon: <ArchiveRestore className="size-3.5 shrink-0" />,
      });
    }
    // The one-way door, and the menu is now the ONLY way to it. It was a hover
    // button on the archived row, which put the gesture that destroys a run's
    // history one click from the pointer's resting place; behind a right-click
    // it is still two presses from the archive and no longer one from a hover.
    if (archived) {
      shelf.push({
        value: 'delete',
        label: 'Delete permanently',
        tone: 'destructive',
        icon: <Trash2 className="size-3.5 shrink-0" />,
      });
    }
    if (shelf.length > 0) {
      groups.push({ items: shelf });
    }
    return groups;
  }, [isWorkflow, archived, pinned, onSetPinned, onArchive, onUnarchive]);

  const startEditing = (): void => {
    setDraft(label);
    setError(null);
    setEditing(true);
  };
  /**
   * Declared BELOW {@link startEditing} because it calls it — a `const` arrow
   * is in its temporal dead zone until its own line, and naming it in a hook's
   * dependency array (which evaluates on every render) throws rather than
   * merely re-creating the callback. Plain rather than memoized for the same
   * reason: `startEditing` is re-made each render, so a `useCallback` over it
   * would be re-made each render too, and the menu it feeds exists only while
   * it is open.
   */
  const onMenuSelect = (value: string): void => {
    rowMenu.close();
    if (value === 'rename') {
      startEditing();
    } else if (value === 'pin') {
      onSetPinned?.(runId, !pinned);
    } else if (value === 'archive') {
      onArchive?.(runId);
    } else if (value === 'unarchive') {
      onUnarchive?.(runId);
    } else if (value === 'delete') {
      onDelete(runId);
    }
  };
  const commit = async (): Promise<void> => {
    const title = draft.trim();
    // Nothing to save — an empty name would leave the row unidentifiable, and
    // an unchanged one is not worth a request.
    if (title.length === 0 || title === label) {
      setEditing(false);
      return;
    }
    setBusy(true);
    setError(null);
    try {
      await onRename(runId, title);
      setEditing(false);
    } catch (err) {
      // Stay open carrying the reason: closing would discard the typed name
      // and leave the failure invisible.
      setError(String(err));
    } finally {
      setBusy(false);
    }
  };

  return (
    <NavListItem
      active={active}
      // `select-none`: without it a press-and-drag on the row starts a TEXT
      // selection instead of the drag, which is what "gets selected, but
      // doesn't drag" looks like from the other side of the screen.
      className={cn(
        'group select-none',
        // An unseen row is marked on the ROW, not only in front of its name.
        // Reported twice: a 6px dot was missed, a 10px one still was — "точку
        // не видно… давай что-то более заметное, дополнительная линия или
        // выделение". A mark the width of a glyph competes with every other
        // glyph on a 260px rail; a bar down the row's own edge and a wash
        // behind it are read by shape and area instead, which is what a mail
        // client uses for the same job.
        //
        // The bar is a pseudo-element on the row's own box (`NavListItem` is
        // `relative`), so it costs no layout and cannot push the title the way
        // a leading element does — and it sits INSIDE the row, clear of the
        // group's colour rail, which is the section's mark rather than this
        // row's.
        unseen &&
          'before:absolute before:top-1.5 before:bottom-1.5 before:left-0 before:w-[3px] before:rounded-full before:bg-primary',
        // The wash yields to the ACTIVE row: an open chat has its own
        // highlight, and two backgrounds on one row would read as a third
        // state. Moot in practice — opening a thread is what marks it seen —
        // but the frame in between is exactly when the eye is on it.
        unseen && !active && 'bg-primary/10',
        dragging && 'opacity-40',
      )}
      activateLabel={label}
      suspendActivation={editing}
      // Not while renaming: a text field inside a draggable element cannot be
      // selected with the mouse, because the drag starts instead.
      draggable={onDragStartRun !== undefined && !editing}
      onDragStart={(event) => {
        // Firefox refuses to start a drag with no payload; the value is never
        // read back, since the parent already knows what it picked up.
        event.dataTransfer.setData('text/plain', runId);
        event.dataTransfer.effectAllowed = 'move';
        onDragStartRun?.(runId);
      }}
      onDragOver={(event) => {
        // Prevent FIRST, decide second. A dragover the row does not act on
        // must still accept the drop, or the browser calls the gesture
        // unsuccessful and flies the carried row home — the snap-back the
        // queued strip already records. This list rearranges live under the
        // pointer, so the row beneath the cursor when the button comes up is
        // routinely the dragged one itself.
        event.preventDefault();
        onDragOverRun?.(runId);
      }}
      onDragEnd={() => onDragEndRun?.()}
      // Nothing to offer while the name is being edited: the row's actions all
      // act on a row the field currently owns, and the platform's own
      // cut/copy/paste is what a right-click in a text field should raise —
      // which it does, since this handler is what would have suppressed it.
      onContextMenu={editing ? undefined : rowMenu.onContextMenu}
      onActivate={() => onActivate(runId)}>
      <span className="flex items-center gap-1.5">
        {/* Leads the row, ahead of the workflow glyph: it is about the row as a
            whole rather than about what kind of run it is, and the left edge is
            where an eye scanning a list for "what is new" already goes. */}
        {unseen ? (
          // 6px of caramel on a cream rail was the thing being scanned for and
          // the easiest thing on the row to miss — at that size it reads as
          // punctuation in front of the name rather than as a mark on the row.
          // 10px is the fix, and the plain disc is deliberate: a haloed variant
          // was tried at three ring weights and each read as a target or a
          // donut, which is a different symbol, while none of them was more
          // legible than simply making the dot big enough to see.
          <span
            data-slot="unseen-dot"
            title="Not opened since it last reported"
            aria-label="not seen yet"
            role="img"
            className="size-2.5 shrink-0 rounded-full bg-primary"
          />
        ) : null}
        {isWorkflow ? (
          <WorkflowIcon
            aria-hidden="true"
            className="size-3.5 shrink-0 text-muted-foreground"
          />
        ) : null}
        {/* What makes `Show all` legible: with both kinds of row in one list,
            a shelved thread is otherwise identical to a live one until it is
            hovered, and its row actions are the only difference. Under the
            other two scopes every row is the same kind and the glyph simply
            says which list this is. */}
        {archived ? (
          // The accessible name is on a WRAPPER, like the unseen dot's: lucide
          // narrows its own props and refuses `role`, so a bare icon here would
          // be decorative markup carrying a label nothing announces.
          <span role="img" aria-label="archived" title="Archived">
            <Archive
              aria-hidden="true"
              className="size-3.5 shrink-0 text-muted-foreground"
            />
          </span>
        ) : null}
        {/* At REST, not on hover: the band's rows sit against the ordinary
            ones in the same list under the same rail, so with the mark behind
            a hover the only thing saying which rows are pinned would be their
            position — and position is exactly what a reader cannot check,
            since the newest thread legitimately sits at the top of the rest.
            The accessible name is on a wrapper for the archived glyph's own
            reason. */}
        {pinned ? (
          <span role="img" aria-label="pinned" title="Pinned">
            <Pin
              aria-hidden="true"
              className="size-3.5 shrink-0 text-muted-foreground"
            />
          </span>
        ) : null}
        {editing ? (
          <Input
            ref={inputRef}
            value={draft}
            disabled={busy}
            aria-label={`Rename ${label}`}
            aria-invalid={error !== null || undefined}
            className="h-6 min-w-0 flex-1 px-1.5 py-0 text-sm"
            onChange={(event) => setDraft(event.target.value)}
            onKeyDown={(event) => {
              // The commit is one request — an Enter confirming an IME
              // composition must not fire it on a half-composed name.
              if (event.nativeEvent.isComposing) {
                return;
              }
              if (event.key === 'Enter') {
                void commit();
              } else if (event.key === 'Escape') {
                // Closing unmounts the field, and removing a focused element
                // fires no blur — so the abandoned draft cannot leak through
                // the commit-on-blur path below. The error goes with it: it
                // describes an attempt the user just abandoned, and the row
                // renders it from state, so leaving it would strand a red
                // failure line under a name that is no longer being edited.
                setError(null);
                setEditing(false);
              }
            }}
            onBlur={() => {
              if (!busy) {
                void commit();
              }
            }}
          />
        ) : (
          <>
            <span
              data-slot="chat-row-label"
              // The pulse marks the LABEL and nothing else on the row: it is
              // the one thing about to change, and animating the row would
              // read as the chat itself doing something.
              className={cn(
                'min-w-0 flex-1 truncate text-sm font-medium',
                unseen && 'font-semibold text-foreground',
                naming && 'title-naming',
              )}
              title={naming ? 'Naming this chat…' : undefined}>
              {label}
            </span>
            {/* Chats only: a workflow run's name comes from the workflow it
                ran, so renaming it here would read as editing the library
                entry from another view. */}
            {isWorkflow ? null : (
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-5 shrink-0 text-muted-foreground opacity-0 group-hover:opacity-100 focus-visible:opacity-100"
                aria-label={`Rename ${label}`}
                title="Rename"
                onClick={(event) => {
                  event.stopPropagation();
                  startEditing();
                }}>
                <Pencil className="size-3 shrink-0" />
              </Button>
            )}
            {/* The desk's destructive-looking action is ARCHIVE, and it is
                reversible: nothing is destroyed, the thread moves to the
                shelf. Both kinds of row. */}
            {!archived && onArchive ? (
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-5 shrink-0 text-muted-foreground opacity-0 group-hover:opacity-100 focus-visible:opacity-100"
                aria-label={`Archive ${label}`}
                title="Archive"
                onClick={(event) => {
                  event.stopPropagation();
                  onArchive(runId);
                }}>
                <Archive className="size-3 shrink-0" />
              </Button>
            ) : null}
            {archived && onUnarchive ? (
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-5 shrink-0 text-muted-foreground opacity-0 group-hover:opacity-100 focus-visible:opacity-100"
                aria-label={`Unarchive ${label}`}
                title="Unarchive"
                onClick={(event) => {
                  event.stopPropagation();
                  onUnarchive(runId);
                }}>
                <ArchiveRestore className="size-3 shrink-0" />
              </Button>
            ) : null}
          </>
        )}
      </span>
      {error ? (
        <span className="truncate text-xs text-destructive">{error}</span>
      ) : null}
      {lastMessage ? (
        <span className="truncate text-xs text-muted-foreground">
          {lastMessage}
        </span>
      ) : null}
      {/* The row's LABELS — what this thread is, in the smallest form each fact
          has. They replace a full pull-request line that spent the row's whole
          width restating a title ("make chip with current pr in threads list
          smaller - just icon and pr number. And make it as label. also add
          second label there - agent type").

          Labels rather than chips, because nothing on this row is pressable:
          the row is one activatable element and everything inside it describes
          the thread. The pull request leads, since it is the fact that comes
          and goes; the agent is on every row, so it reads as the column it is
          rather than as news. */}
      <span data-slot="chat-row-labels" className="flex items-center gap-1">
        {/* The card LEADS, unlike the volatile-first order the other two
            follow, and its own job is what decides that: it is an IDENTIFIER —
            asked for as "to make those threads identifiable in the list" — so
            it is scanned down a column, which only works while it sits at the
            same x on every row that has one. It can afford to: unlike the pull
            request, it never appears or disappears mid-session, so leading
            with it shifts nothing. Monospaced for the reason the card and the
            panel set it that way: it is a key, not a word. */}
        {taskIdentifier === null ? null : (
          <Badge
            data-slot="task-identifier"
            variant="muted"
            title={`Working the board card ${taskIdentifier}`}
            className="px-1.5 py-0 font-mono font-normal">
            {taskIdentifier}
          </Badge>
        )}
        {pullRequest ? <PullRequestBadge pullRequest={pullRequest} /> : null}
        <Badge
          data-slot="agent-kind"
          variant="muted"
          title={
            isWorkflow
              ? 'A team of agents running as a graph'
              : `Driven by ${agentKind ?? 'an unrecorded CLI'}`
          }
          className="gap-1 px-1.5 py-0 font-normal">
          {agentLabel(agentKind, isWorkflow, workflowName)}
        </Badge>
      </span>
      <span className="flex items-center gap-1 text-xs">
        {/* EVERY glyph leads its label, the spinner included. It was parked at
            the far right for a while, on the theory that a moving thing in
            front of its word would push the line about — it does not (both
            glyphs are the same `size-3 shrink-0` box), and what it did instead
            was give a running row a different shape from every other row in the
            list, so the eye had to look in two places to read one column. */}
        <RunStatusIcon status={status} />
        {/* Never wrapped: the status word is the shortest thing on the line and
            the one that must stay readable, so the activity phrase beside it
            (which already truncates) is what gives up room. Before this,
            `needs more info` broke across two lines and made the row taller
            than its neighbours. */}
        <span className={cn('shrink-0 whitespace-nowrap', meta.className)}>
          {meta.label}
        </span>
        {/* A parked row gets a phrase too, and it is worded from the KIND
            rather than taken from the activity plane: the label says the run is
            blocked on the user, this says on WHAT — the difference between
            going to read a question and going to press a button. */}
        {status === 'needs-input' && awaiting ? (
          <span className="min-w-0 truncate text-muted-foreground">
            · {awaitingPhrase(awaiting)}
          </span>
        ) : isWorkingRunStatus(status) ? (
          /* Never conditional on there BEING a phrase: a null activity means
             "working, nothing named", not "say nothing", and treating the two
             the same is what made this row flicker once per tool call. See
             {@link STANDING_ACTIVITY} — and {@link HELD_ACTIVITY}, which is the
             same fallback for a turn that is held rather than thinking. */
          <span className="min-w-0 truncate text-muted-foreground">
            ·{' '}
            {activity ??
              (status === 'held' ? HELD_ACTIVITY : STANDING_ACTIVITY)}
          </span>
        ) : null}
        {/* The time is for runs that have STOPPED — "when did this last do
            anything" is only a question about a run that is no longer doing
            it. A parked run is as live as a running one (its turn is open, its
            process is up), so it is excluded for the same reason `running` is
            — and on a 260px sidebar it was the third thing competing for the
            line, which is what made the status label wrap onto two rows. A HELD
            run is live on both of those counts too, so it is excluded with
            them: `waiting · 24m` was the reported row, and the `24m` is exactly
            the half of it that reads as a thread nobody has touched since. */}
        {!isWorkingRunStatus(status) && status !== 'needs-input' ? (
          <span className="ml-auto pl-2 text-muted-foreground">
            {formatRelativeTime(lastActivityAt)}
          </span>
        ) : null}
      </span>
      {/* Rendered INSIDE the row so the menu unmounts with it — a row dropped
          by a scope switch or a delete must not leave a panel behind. Its own
          box is `fixed`, so being a descendant of a scrolling list costs it no
          clipping. */}
      <ContextMenu
        point={rowMenu.point}
        groups={menuGroups}
        onSelect={onMenuSelect}
        onClose={rowMenu.close}
        // Sized to the longest row rather than left to the default: the panel
        // opens beside a 260px rail but is `fixed`, so it has the window to
        // grow into and nothing is gained by clipping `Delete permanently`.
        className="min-w-0 w-60"
      />
    </NavListItem>
  );
});
