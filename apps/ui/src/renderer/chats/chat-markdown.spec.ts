import { describe, expect, it } from 'vitest';

import {
  type ChatExportDto,
  type ChatExportDtoItemsInner,
  ItemKind,
} from '../autogenerated';
import { chatToMarkdown } from './chat-markdown';

let seq = 0;
function row(
  kind: ChatExportDtoItemsInner['kind'],
  payload: unknown = null,
  role: string | null = null,
): ChatExportDtoItemsInner {
  seq += 1;
  return {
    id: `i${seq}`,
    runId: 'r1',
    nodeId: null,
    seq,
    kind,
    role,
    payload,
    createdAt: '2026-09-05T10:00:00.000Z',
  };
}

function doc(items: ChatExportDtoItemsInner[]): ChatExportDto {
  return {
    formatVersion: 1,
    exportedAt: '2026-09-05T11:00:00.000Z',
    daemonVersion: '1.2.3',
    run: {
      id: 'r1',
      workflowId: null,
      status: 'completed',
      title: 'Sizing the bloom filter',
      agentKind: 'claude',
      cwd: '/work/app',
      startSha: 'a'.repeat(40),
      startDirty: false,
      model: 'opus',
      approval: null,
      effort: null,
      contextWindow: null,
      autoCompactPercent: null,
      modelParameters: {},
      contextTokens: null,
      contextWindowTokens: null,
      configDir: null,
      groupId: null,
      customInstructions: null,
      workflowInstructions: null,
      taskInstructions: null,
      cursorMaxMode: null,
      lastMetricsReading: null,
      pendingContext: null,
      createdAt: '2026-09-05T09:00:00.000Z',
      updatedAt: '2026-09-05T10:30:00.000Z',
    },
    totals: {
      turns: 2,
      costedTurns: 1,
      costUsd: 0.42,
      inputTokens: null,
      outputTokens: null,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      thinkingTokens: null,
      workedMs: null,
    },
    nodes: [],
    items,
  };
}

describe('chatToMarkdown', () => {
  it('gives EVERY kind a section, including the ones with no prose form', () => {
    // The milestone's own criterion, and the reason the fallback exists: a
    // serializer that quietly dropped what it did not recognise produces a
    // document that reads as complete while missing whole turns. Driven off the
    // generated vocabulary rather than a list written here, so a kind added to
    // the daemon joins this assertion on the next `generate:api`.
    const kinds = Object.values(ItemKind);
    const out = chatToMarkdown(doc(kinds.map((kind) => row(kind, { a: 1 }))));

    for (const kind of kinds) {
      expect(out).toContain(`#### ${kind} ·`);
    }
    expect(kinds.length).toBeGreaterThan(25);
  });

  it('renders a message as its own words, not as a JSON blob', () => {
    const out = chatToMarkdown(
      doc([
        row(
          'message',
          { text: '# A heading\n\nand a paragraph.' },
          'assistant',
        ),
      ]),
    );

    // Verbatim: the text IS markdown — it is what the app renders as markdown on
    // screen — so escaping it would turn the agent's own headings into
    // punctuation.
    expect(out).toContain('# A heading\n\nand a paragraph.');
    expect(out).not.toContain('"text"');
  });

  it('names the speaker from the ROLE, so a reader can tell the two apart', () => {
    const out = chatToMarkdown(
      doc([
        row('message', { text: 'what does this do?' }, 'user'),
        row('message', { text: 'it sizes the filter' }, 'assistant'),
      ]),
    );

    expect(out).toContain('**You**');
    expect(out).toContain('**claude**');
  });

  it('opens a fence longer than any backtick run inside it', () => {
    // The one real escaping problem: agent output routinely CONTAINS fenced
    // code, so a fixed three-backtick fence is closed by the content's own and
    // everything after it lands outside the block — silently, mid-document.
    const out = chatToMarkdown(
      doc([row('tool_result', { result: '```js\nconst x = 1;\n```' })]),
    );

    expect(out).toContain('````');
    // The inner fence survives as content rather than ending the block.
    expect(out).toContain('```js\nconst x = 1;\n```');
  });

  it('never SUBSTITUTES characters in the text it exports', () => {
    // An export claims to be the conversation. A short tool result carrying a
    // backtick was rendered inline with the backtick swapped for a curly quote,
    // which is a silent edit to the agent's own words in the one artifact whose
    // whole purpose is fidelity — worse than an ugly fence, because nothing on
    // the page says it happened.
    const out = chatToMarkdown(
      doc([row('tool_result', { result: 'run `pnpm test` first' })]),
    );

    // The RENDERING, not the absence of a curly quote: a bare `toContain` of the
    // text passes under the inline form too, so it would go green with the
    // backtick branch deleted — the one thing this case exists for. Asserting
    // the fence is what fails on that revert.
    expect(out).toContain('```\nrun `pnpm test` first\n```');
  });

  it('keeps a multi-line title from breaking the document’s heading', () => {
    // A chat's title is generated from its opening line and is routinely whatever
    // the user pasted. A newline in it turns `# <title>` into a heading plus a
    // stray paragraph, and everything after reads as part of the conversation.
    const empty = doc([]);
    const out = chatToMarkdown({
      ...empty,
      run: { ...empty.run, title: 'Fix the parser\nand then the tests' },
    });

    const heading = out.split('\n')[0]!;
    expect(heading).toContain('Fix the parser');
    expect(heading).toContain('and then the tests');
  });

  it('states the commit the conversation started at', () => {
    // What the git view measures against — an export that omits it cannot be
    // read back against the tree it describes.
    const out = chatToMarkdown(doc([]));

    expect(out).toContain(`**Started at commit:** ${'a'.repeat(40)}`);
  });

  it('leaves out a fact the run does not have, rather than printing null', () => {
    const empty = doc([]);
    const out = chatToMarkdown({
      ...empty,
      run: { ...empty.run, model: null, cwd: null },
    });

    expect(out).not.toContain('**Model:**');
    expect(out).not.toContain('**Folder:**');
    // The ones it DOES have are still there — the filter is per fact.
    expect(out).toContain('**Agent:** claude');
  });

  it('says a cost was never measured rather than printing $0.00', () => {
    // cursor reports no cost at all unless its currency is USD, and a zero would
    // claim a thread that ran free.
    const empty = doc([]);
    const out = chatToMarkdown({
      ...empty,
      totals: { ...empty.totals, costUsd: null },
    });

    expect(out).toContain('**Cost:** not measured');
  });

  it('COLLAPSES a base64 image block instead of writing the bytes out', () => {
    // 13.8 MB of one real 28.9 MB export was 81 of these, none of which a reader
    // can do anything with — and no editor opens a file with megabyte-long lines,
    // so analysing that export meant writing a parser first.
    const data = 'A'.repeat(300_000);
    const out = chatToMarkdown(
      doc([
        row('tool_result', {
          result: [
            {
              type: 'image',
              source: { type: 'base64', data, media_type: 'image/png' },
            },
          ],
        }),
      ]),
    );

    expect(out).not.toContain(data);
    expect(out).toContain('[image: image/png, 220 KB]');
  });

  it('summarizes spend per agent, each call, errors and compactions', () => {
    const out = chatToMarkdown(
      doc([
        row('call_started', {
          callId: 'call-1',
          callerNodeId: 'manager',
          calleeNodeId: 'engineer',
          title: 'Build the counter fix',
        }),
        row('turn_complete', {
          usage: { costUsd: 4.25, durationMs: 90_000 },
          callId: 'call-1',
        }),
        row('call_result', {
          callId: 'call-1',
          status: 'error',
          error: 'CALLEE_FAILED[rate_limited]: session limit',
        }),
        row('error', { message: 'the turn failed' }),
        row('system', {
          message: 'compacted',
          compaction: {
            preTokens: 856_000,
            postTokens: 29_000,
            trigger: 'auto',
          },
        }),
      ]),
    );

    expect(out).toContain('## Summary');
    expect(out).toContain('### Spend per agent');
    expect(out).toContain('### Agent calls');
    expect(out).toContain(
      '| call-1 | manager → engineer | Build the counter fix |',
    );
    expect(out).toContain('CALLEE_FAILED[rate_limited]: session limit');
    expect(out).toContain('### Errors');
    expect(out).toContain('### Context compactions');
    // …and the summary comes BEFORE the rows it is a summary of.
    expect(out.indexOf('## Summary')).toBeLessThan(
      out.indexOf('## Transcript'),
    );
  });

  it('omits a summary section that would have no rows, and the heading with them', () => {
    // An `### Errors` heading over nothing reads as a rendering failure, and
    // every one of the four is legitimately empty on an ordinary chat.
    const out = chatToMarkdown(doc([row('message', { text: 'hi' }, 'user')]));

    expect(out).not.toContain('## Summary');
    expect(out).not.toContain('### Errors');
  });

  it('keeps a call TITLE on one table row, whatever the agent wrote in it', () => {
    // A markdown cell cannot hold a newline or a bare pipe — either would break
    // the row and take the rest of the table with it.
    const out = chatToMarkdown(
      doc([
        row('call_started', {
          callId: 'call-1',
          calleeNodeId: 'engineer',
          title: 'Fix a | b\nand c',
        }),
      ]),
    );

    expect(out).toContain('Fix a \\| b and c');
  });
});
