import type { ChatExportDto, ChatExportDtoItemsInner } from '../autogenerated';
import { formatUsd } from './agent-activity';
import {
  type ChatExportSummary,
  chatExportSummary,
} from './chat-export-summary';
import { collapseImageBlocks } from './export-image-blocks';
import { payloadNumber, payloadString } from './transcript-payload';
import { formatDuration } from './turn-duration';

/**
 * One conversation as READABLE markdown — the second thing an export can be.
 *
 * The JSON export is for a machine: every column, every payload, nothing
 * interpreted. This is for a person — a bug report, a code review, a note to a
 * colleague — so it renders what each row MEANS wherever the row has a meaning
 * in words, and falls back to the payload itself where it does not.
 *
 * The fallback is the load-bearing half. Every kind present in a thread gets a
 * section, including the ones with no prose form: a serializer that quietly
 * dropped what it did not recognise would produce a document that reads as
 * complete and is missing whole turns, which is worse than a fenced blob nobody
 * enjoys. `RENDERERS` is therefore consulted per kind and `fallbackSection` is
 * what answers for the rest — a kind added to the daemon needs no edit here to
 * keep the export honest, only to make it prettier.
 *
 * Modelled on `debug-panel.tsx`'s `formatReport` for the SHELL alone — a pure
 * function, a line array, one `join`. Everything below the shell is this file's
 * own.
 */

/** How long an inline fragment (a tool input, a result) may run before it folds. */
const INLINE_MAX = 400;

/**
 * A fenced block whose fence is longer than any backtick run inside it.
 *
 * The one real escaping problem here: agent output routinely CONTAINS fenced
 * code, so a fixed three-backtick fence is closed by the content's own fence and
 * everything after it lands outside the block — silently, and in the middle of
 * the document.
 */
function fence(content: string, lang = ''): string[] {
  const longest = [...content.matchAll(/`+/g)].reduce(
    (max, run) => Math.max(max, run[0].length),
    0,
  );
  const ticks = '`'.repeat(Math.max(3, longest + 1));
  return [`${ticks}${lang}`, content, ticks];
}

/**
 * The payload as pretty JSON, for a row with nothing better to show.
 *
 * Base64 image blocks are COLLAPSED on the way through (see
 * `export-image-blocks.ts`): this is the one door every dumped payload passes,
 * so a screenshot cannot reach the file whichever row was carrying it — a tool
 * result, a message, or a kind added later that falls through to
 * {@link fallbackSection}. Measured on one real export, that is 13.8 MB of 28.9.
 */
function json(value: unknown): string[] {
  return fence(
    JSON.stringify(collapseImageBlocks(value) ?? null, null, 2),
    'json',
  );
}

/**
 * Verbatim text — inline where a short single line can carry it, fenced
 * otherwise.
 *
 * A value holding a BACKTICK is fenced too, and that is the point: inline code
 * has no escape for its own delimiter, so the only ways to render one inline are
 * to substitute the character or to drop it. Both are silent edits to the
 * agent's own words, in the one artifact whose whole purpose is being a faithful
 * record — {@link fence} already sizes its delimiter to whatever is inside.
 */
function text(value: string): string[] {
  return value.includes('\n') ||
    value.includes('`') ||
    value.length > INLINE_MAX
    ? fence(value)
    : [`\`${value}\``];
}

/**
 * One line of it, for a heading.
 *
 * A chat's title is generated from its opening line and is routinely whatever
 * the user pasted, so a newline in it would end the `#` heading and leave the
 * rest as a stray paragraph the reader takes for the conversation's own.
 */
function oneLine(value: string): string {
  return value.replace(/\s+/g, ' ').trim();
}

/** Who a row is FROM, in the words the transcript uses. */
function speaker(item: ChatExportDtoItemsInner, agent: string): string {
  if (item.role === 'user') {
    return 'You';
  }
  return item.nodeId ?? agent;
}

type Renderer = (
  item: ChatExportDtoItemsInner,
  agent: string,
) => string[] | null;

/**
 * Per-kind prose. A renderer answering null means "nothing worth saying in
 * words" and hands the row to the fenced fallback, which is how a payload that
 * turned out not to hold what its kind implies still reaches the document.
 */
const RENDERERS: Partial<Record<string, Renderer>> = {
  message: (item, agent) => {
    const body = payloadString(item.payload, 'text');
    if (body === null) {
      return null;
    }
    // Verbatim, NOT escaped: this text is markdown already — it is what the app
    // renders as markdown on screen — so escaping it would turn the agent's own
    // headings, lists and code into literal punctuation.
    return [`**${speaker(item, agent)}**`, '', body];
  },
  reasoning: (item) => {
    const body = payloadString(item.payload, 'text');
    return body === null
      ? null
      : // Quoted rather than plain, so a page of chain-of-thought is visibly
        // aside from the answer it led to.
        ['**Reasoning**', '', ...body.split('\n').map((line) => `> ${line}`)];
  },
  tool_call: (item) => {
    const name = payloadString(item.payload, 'name') ?? 'tool';
    const input = (item.payload as { input?: unknown } | null)?.input;
    const head = `**🔧 ${name}**`;
    if (input === undefined || input === null) {
      return [head];
    }
    return [head, '', ...json(input)];
  },
  tool_result: (item) => {
    const result = (item.payload as { result?: unknown } | null)?.result;
    if (result === undefined) {
      return null;
    }
    return [
      '**⮑ result**',
      '',
      ...(typeof result === 'string' ? text(result) : json(result)),
    ];
  },
  system: (item) => {
    const body = payloadString(item.payload, 'message');
    return body === null ? null : [`_${body}_`];
  },
  error: (item) => {
    const body = payloadString(item.payload, 'message');
    return body === null ? null : [`**✗ error** — ${body}`];
  },
  turn_complete: (item) => {
    const cost = payloadNumber(
      (item.payload as { usage?: unknown } | null)?.usage,
      'costUsd',
    );
    const ms = payloadNumber(
      (item.payload as { usage?: unknown } | null)?.usage,
      'durationMs',
    );
    const parts = ['**✓ turn complete**'];
    if (ms !== null) {
      parts.push(`worked ${Math.round(ms / 1000)}s`);
    }
    if (cost !== null) {
      parts.push(`$${cost.toFixed(4)}`);
    }
    return [parts.join(' — ')];
  },
  turn_cancelled: () => ['**⊘ turn cancelled**'],
  call_question: (item) => {
    const question = payloadString(item.payload, 'question');
    return question === null ? null : [`**❓ asks**`, '', question];
  },
  call_answer: (item) => {
    const answer = payloadString(item.payload, 'answer');
    return answer === null ? null : [`**↩ answered**`, '', answer];
  },
};

/**
 * A section for a kind nothing knows how to say in words — the payload itself,
 * under a heading naming what it is.
 *
 * Deliberately not silent, and not merely a line saying the kind exists: an
 * export is read by somebody trying to work out what happened, and the payload
 * is the only record of the kinds the transcript itself draws as cards.
 */
function fallbackSection(item: ChatExportDtoItemsInner): string[] {
  return [`**${item.kind}**`, '', ...json(item.payload)];
}

function itemSection(item: ChatExportDtoItemsInner, agent: string): string[] {
  const body = RENDERERS[item.kind]?.(item, agent) ?? fallbackSection(item);
  // The seq is in the heading rather than a bare timestamp, because it is what
  // the app's own search and jump address a row by — so a line quoted out of
  // this file can be found again in the conversation it came from.
  return [
    `#### ${item.kind} · seq ${item.seq} · ${item.createdAt}`,
    '',
    ...body,
  ];
}

/** `key: value` lines for the run's own facts, skipping the ones it has none of. */
function runFacts(doc: ChatExportDto): string[] {
  const run = doc.run;
  const facts: [string, string | null][] = [
    ['Agent', run.agentKind],
    ['Model', run.model],
    ['Folder', run.cwd],
    ['Profile', run.configDir],
    ['Approval', run.approval],
    ['Effort', run.effort],
    ['Context window', run.contextWindow],
    ['Status', run.status],
    ['Started', run.createdAt],
    ['Last activity', run.updatedAt],
    ['Started at commit', run.startSha],
    [
      'Folder was dirty at the start',
      run.startDirty === null ? null : String(run.startDirty),
    ],
    ['Workflow', run.workflowId],
  ];
  return facts
    .filter(([, value]) => value !== null && value !== '')
    .map(([label, value]) => `- **${label}:** ${value!}`);
}

/** A table cell's value, or an em dash for a figure nothing measured. */
function cell(value: string | null): string {
  return value === null || value === '' ? '—' : value;
}

/** A markdown cell cannot hold a `|` or a newline — both would break the row. */
function inlineCell(value: string | null): string {
  return value === null
    ? '—'
    : cell(value.replace(/\s+/g, ' ').replaceAll('|', '\\|').trim());
}

/** One markdown table, or nothing at all when it would have no rows. */
function table(
  heading: string,
  columns: readonly string[],
  rows: readonly string[][],
): string[] {
  if (rows.length === 0) {
    return [];
  }
  return [
    `### ${heading}`,
    '',
    `| ${columns.join(' | ')} |`,
    `|${columns.map(() => '---').join('|')}|`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
    '',
  ];
}

const money = (amount: number | null): string | null =>
  amount === null ? null : formatUsd(amount);

const worked = (ms: number | null): string | null =>
  ms === null ? null : formatDuration(ms);

/**
 * The summary tables between the run facts and the transcript.
 *
 * Deliberately BELOW the facts and ABOVE the rows: a reader opening a long export
 * wants the shape of the run before the rows, and the facts are what tell them
 * which run they have. A section with nothing to say is omitted entirely rather
 * than drawn empty — an `## Errors` heading over no rows reads as a rendering
 * failure, and every one of these four is legitimately empty on an ordinary chat.
 */
function summarySections(summary: ChatExportSummary): string[] {
  const lines = [
    ...table(
      'Spend per agent',
      ['Agent', 'Turns', 'Cost', 'Worked'],
      summary.agents.map((agent) => [
        agent.agent,
        String(agent.turns),
        cell(money(agent.costUsd)),
        cell(worked(agent.workedMs)),
      ]),
    ),
    ...table(
      'Agent calls',
      ['Call', 'Caller → Callee', 'Why', 'Duration', 'Cost', 'Outcome'],
      summary.calls.map((call) => [
        call.callId,
        `${cell(call.callerNodeId)} → ${cell(call.calleeNodeId)}`,
        inlineCell(call.title),
        cell(worked(call.durationMs)),
        cell(money(call.costUsd)),
        inlineCell(call.outcome),
      ]),
    ),
    ...table(
      'Errors',
      ['When', 'Agent', 'Error'],
      summary.errors.map((error) => [
        error.at,
        cell(error.agent),
        inlineCell(error.message),
      ]),
    ),
    ...table(
      'Context compactions',
      ['When', 'Agent', 'Trigger', 'Before', 'After'],
      summary.compactions.map((compaction) => [
        compaction.at,
        cell(compaction.agent),
        cell(compaction.trigger),
        cell(
          compaction.preTokens === null ? null : String(compaction.preTokens),
        ),
        cell(
          compaction.postTokens === null ? null : String(compaction.postTokens),
        ),
      ]),
    ),
  ];
  return lines.length === 0 ? [] : ['## Summary', '', ...lines];
}

/**
 * Render one exported conversation as markdown.
 *
 * Takes the DAEMON's export document rather than the rows on screen, for the
 * reason the JSON export does: a chat's history is paged, so a file built from
 * what the client happened to have loaded would be a fragment with nothing in it
 * saying so.
 */
export function chatToMarkdown(doc: ChatExportDto): string {
  const agent = doc.run.agentKind ?? 'agent';
  const lines = [
    `# ${oneLine(doc.run.title ?? 'Untitled conversation')}`,
    '',
    ...runFacts(doc),
    '',
    `- **Exported:** ${doc.exportedAt} (geniro daemon ${doc.daemonVersion}, format ${doc.formatVersion})`,
    // `not measured` rather than a zero: cursor reports no cost at all unless
    // its currency is USD, and a `$0.00` would claim a thread that ran free.
    `- **Turns:** ${doc.totals.turns} · **Cost:** ${
      doc.totals.costUsd === null
        ? 'not measured'
        : `$${doc.totals.costUsd.toFixed(4)}`
    }`,
    '',
    '---',
    '',
    ...summarySections(chatExportSummary(doc.items)),
    '## Transcript',
    '',
  ];
  for (const item of doc.items) {
    lines.push(...itemSection(item, agent), '');
  }
  return lines.join('\n');
}
