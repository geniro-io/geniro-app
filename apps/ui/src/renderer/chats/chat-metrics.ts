import { createContext } from 'react';

import type { ChatMetricsDto } from '../autogenerated';

/**
 * How a meter fetches one chat's metrics — the context breakdown and the
 * thread's spend.
 *
 * A context rather than a prop, for the reason `AttachmentLoaderContext` is
 * one: the meter is rendered from two places that are several memoized shells
 * away from the component holding the daemon client, and threading a loader
 * through each of them would give every shell in between a prop it does not
 * use. Null when nothing has provided one — the meter then keeps its summary
 * and offers no readout to expand, which is the honest shape for a caller with
 * no run to ask about.
 */
export type ChatMetricsLoader = (runId: string) => Promise<ChatMetricsDto>;

export const ChatMetricsLoaderContext = createContext<ChatMetricsLoader | null>(
  null,
);

/**
 * The hues a category is drawn in, by its position in the CLI's own list.
 *
 * By POSITION and not by name: the names belong to the CLI and it is free to
 * invent one — a colour map keyed by name would leave the new category
 * uncoloured, or worse, silently borrow the colour of a neighbour. The CLI's
 * order is stable within a session, so the same category keeps its colour for
 * as long as anyone is looking at it.
 *
 * The avatar palette rather than a set of its own, for the reason the sidebar
 * groups alias it too: these are the app's distinguishable hues, and a second
 * eight-colour set would drift from them.
 */
export const CONTEXT_CATEGORY_COLORS = [
  'bg-avatar-1',
  'bg-avatar-2',
  'bg-avatar-3',
  'bg-avatar-4',
  'bg-avatar-5',
  'bg-avatar-6',
  'bg-avatar-7',
  'bg-avatar-8',
] as const;

export function contextCategoryColor(index: number): string {
  // The modulo cannot land outside the array, but the index signature does not
  // know that — and `bg-muted` is the right thing to be wrong with anyway: a
  // segment nobody can name reads as unattributed rather than as a colour
  // borrowed from a category above it.
  return (
    CONTEXT_CATEGORY_COLORS[Math.abs(index) % CONTEXT_CATEGORY_COLORS.length] ??
    'bg-muted'
  );
}

/**
 * The last path segment, for a memory file whose full path is far too long for
 * a 22rem panel.
 *
 * Basename alone would render three `CLAUDE.md` rows with nothing to tell them
 * apart — which is the ordinary case, since a project's own file, the user's
 * and a rules directory's all share the name — so the PARENT comes with it.
 */
export function shortenPath(path: string): string {
  const parts = path.split('/').filter((part) => part.length > 0);
  return parts.slice(-2).join('/') || path;
}
