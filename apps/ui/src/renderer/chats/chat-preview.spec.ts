import { describe, expect, it } from 'vitest';

import type { ItemDto } from '../autogenerated';
import { previewMessageOf } from './chat-preview';

/** The shape the rule reads — the two fields, plus a tag to assert identity. */
function row(
  tag: string,
  kind: ItemDto['kind'],
  role: string | null,
): { tag: string } & Pick<ItemDto, 'kind' | 'role'> {
  return { tag, kind, role };
}

describe('previewMessageOf', () => {
  it('picks the NEWEST message even when the user said it last', () => {
    // REPORTED as "In thread i cant see last user message. I should see there
    // last AI or USER message". The rule used to prefer the agent's latest, so
    // a thread showed the previous answer for the whole time it was working on
    // what the user had just asked. Restore that preference and this is
    // `agent-new`.
    const picked = previewMessageOf([
      row('agent-old', 'message', 'assistant'),
      row('agent-new', 'message', 'assistant'),
      row('user-newest', 'message', 'user'),
    ]);
    expect(picked?.tag).toBe('user-newest');
  });

  it('picks the agent’s reply once it is the newest', () => {
    // The other half of the same rule: the line follows the conversation
    // rather than one side of it, so the agent takes it back by answering.
    const picked = previewMessageOf([
      row('user-asked', 'message', 'user'),
      row('agent-answered', 'message', 'assistant'),
    ]);
    expect(picked?.tag).toBe('agent-answered');
  });

  it('previews the opening question of a chat whose agent has not spoken', () => {
    expect(previewMessageOf([row('u', 'message', 'user')])?.tag).toBe('u');
  });

  it('ignores non-message rows when picking the newest', () => {
    // The batch a live turn hands over routinely ENDS on a tool row or a
    // terminal item; taking its literal tail would preview nothing.
    const picked = previewMessageOf([
      row('m', 'message', 'assistant'),
      row('t', 'tool_call', 'assistant'),
      row('c', 'turn_complete', null),
    ]);
    expect(picked?.tag).toBe('m');
  });

  it('returns undefined for a batch with no message rows at all', () => {
    expect(
      previewMessageOf([
        row('t', 'tool_call', null),
        row('c', 'turn_complete', null),
      ]),
    ).toBeUndefined();
  });
});
