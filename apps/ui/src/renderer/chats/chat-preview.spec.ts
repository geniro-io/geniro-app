import { describe, expect, it } from 'vitest';

import type { ItemDto } from '../autogenerated';
import { isAgentMessage, previewMessageOf } from './chat-preview';

/** The shape the rule reads — the two fields, plus a tag to assert identity. */
function row(
  tag: string,
  kind: ItemDto['kind'],
  role: string | null,
): { tag: string } & Pick<ItemDto, 'kind' | 'role'> {
  return { tag, kind, role };
}

describe('isAgentMessage', () => {
  it('is true for an assistant message and false for the user’s', () => {
    expect(isAgentMessage(row('a', 'message', 'assistant'))).toBe(true);
    expect(isAgentMessage(row('u', 'message', 'user'))).toBe(false);
  });

  it('is false for a non-message row whatever its role', () => {
    expect(isAgentMessage(row('t', 'tool_call', 'assistant'))).toBe(false);
    expect(isAgentMessage(row('c', 'turn_complete', null))).toBe(false);
  });

  it('reads an UNKNOWN role as the agent, not as the user', () => {
    // A CLI is free to spell its own role; only `user` is geniro's own word,
    // so an allowlist of agent names would silently demote a new spelling to
    // "the user is talking" and echo the user's message back as the preview.
    expect(isAgentMessage(row('x', 'message', 'model'))).toBe(true);
    expect(isAgentMessage(row('y', 'message', null))).toBe(true);
  });
});

describe('previewMessageOf', () => {
  it('picks the agent’s latest message over a NEWER user message', () => {
    // The defect this rule exists for: with "newest message wins", sending a
    // message takes the preview line away from the agent's reply until the
    // agent answers, so the line alternates owner every turn.
    const picked = previewMessageOf(
      [
        row('agent-old', 'message', 'assistant'),
        row('agent-new', 'message', 'assistant'),
        row('user-newest', 'message', 'user'),
      ],
      true,
    );
    expect(picked?.tag).toBe('agent-new');
  });

  it('falls back to the user’s message while the agent has not spoken', () => {
    const picked = previewMessageOf([row('u', 'message', 'user')], false);
    expect(picked?.tag).toBe('u');
  });

  it('withholds a user message once the agent HAS spoken earlier', () => {
    // The batch alone cannot see the earlier reply — this is what
    // `agentHasSpoken` carries — so without it a reconnect delta holding only
    // the user's newest message would put the fallback back into effect and
    // hand the line back to the user.
    expect(
      previewMessageOf([row('u', 'message', 'user')], true),
    ).toBeUndefined();
  });

  it('returns undefined for a batch with no message rows at all', () => {
    expect(
      previewMessageOf(
        [row('t', 'tool_call', null), row('c', 'turn_complete', null)],
        false,
      ),
    ).toBeUndefined();
  });
});
