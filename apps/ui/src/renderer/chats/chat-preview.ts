import type { ItemDto } from '../autogenerated';
import { payloadString } from './transcript-payload';

/**
 * Which message a chat row previews.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/dao/item.dao.ts`
 * `latestMessageTextPerRun` decides the same thing for the run LIST, off the
 * database. The two must agree, because they take turns writing the same line —
 * the list value arrives on a refetch, this one on a live turn — and a rule
 * held on only one side is a preview that changes owner depending on which
 * source spoke last, which is the defect both exist to end.
 *
 * The rule: the NEWEST message, whoever said it.
 *
 * It used to be the agent's latest, falling back to any role while the agent
 * had not spoken — deliberately, to stop the line alternating owner at every
 * turn boundary. REPORTED as "In thread i cant see last user message. I should
 * see there last AI or USER message": the cost of that rule is that a thread
 * shows the agent's previous answer for the whole time it is working on what
 * you just asked, so the row is stalest at exactly the moment you go looking
 * for the chat you were last in. Alternation is the price and it is now the
 * asked-for behaviour — a preview tracks where a conversation has got to, and
 * where it has got to is the last thing said.
 */

/**
 * The message a batch of transcript rows should preview, or undefined when it
 * holds none.
 *
 * A batch, because the two callers hand it different amounts: the history
 * replay passes the whole loaded window, a live turn passes the one row that
 * just arrived. Taking the LAST message of whatever it is given is correct for
 * both, and is why this no longer needs to be told whether the agent has
 * spoken — that question only existed to serve the agent-preferring rule.
 */
export function previewMessageOf<
  T extends Pick<ItemDto, 'kind' | 'role'> & { payload?: unknown },
>(items: readonly T[]): T | undefined {
  return items.findLast(previewsThread);
}

/**
 * Whether one row may be a thread's preview: a message, and not one written
 * inside an agent-to-agent call or by a delegate — those are other
 * conversations the sidebar row cannot open. REPORTED as a team row
 * previewing its Engineer's words instead of its Manager's. The daemon's
 * `NOT_IN_A_CALL` / `NOT_A_DELEGATE` (the list) and `threadPreviewOf` (the
 * live `run_status.preview` push, `v1/agents/utils/message-preview.ts`) are
 * the twins.
 */
export function previewsThread(
  item: Pick<ItemDto, 'kind'> & { payload?: unknown },
): boolean {
  if (item.kind !== 'message') {
    return false;
  }
  const payload =
    typeof item.payload === 'object' && item.payload !== null
      ? (item.payload as Record<string, unknown>)
      : {};
  return payload.callId === undefined && payload.parentToolUseId === undefined;
}

/**
 * The line a previewed message writes: its text, or — for a message that says
 * nothing in words, such as a screenshot sent alone — a label naming its
 * pictures. Null for neither, so the caller leaves the line as it was.
 *
 * TWIN PARSER: the daemon's `messagePreviewOf`
 * (`apps/daemon/src/v1/agents/utils/message-preview.ts`) writes the same line
 * for the list and the live push; the label must be spelled identically.
 */
export function previewTextOf(payload: unknown): string | null {
  const text = payloadString(payload, 'text');
  if (text !== null && text.trim() !== '') {
    return previewCut(text);
  }
  const images =
    typeof payload === 'object' &&
    payload !== null &&
    'images' in payload &&
    Array.isArray(payload.images)
      ? payload.images.length
      : 0;
  if (images === 0) {
    return null;
  }
  return images === 1 ? '🖼 Image' : `🖼 ${images} images`;
}

/**
 * The most of a message's text the preview line carries.
 *
 * The row draws ONE truncated line, yet the list used to ship each thread's
 * whole last message: 73% of a 1.5 MB archive listing on a real profile was
 * these lines. Generous beyond the row's width, so that markdown stripped off
 * the front (a link's URL, a heading's marks) still leaves words to show.
 *
 * TWIN: `PREVIEW_MAX_CHARS` in `apps/daemon/src/v1/agents/utils/message-preview.ts`
 * — both sides write the same line, so they cut at the same place.
 */
export const PREVIEW_MAX_CHARS = 400;

/** `text` cut to {@link PREVIEW_MAX_CHARS} code points, never inside a surrogate pair. */
function previewCut(text: string): string {
  if (text.length <= PREVIEW_MAX_CHARS) {
    return text;
  }
  return Array.from(text.slice(0, PREVIEW_MAX_CHARS * 2))
    .slice(0, PREVIEW_MAX_CHARS)
    .join('');
}
