import type { ItemDto } from '../autogenerated';

/**
 * Which message a chat row previews.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/dao/item.dao.ts`
 * `latestMessageTextPerRun` decides the same thing for the run LIST, off the
 * database. The two must agree, because they take turns writing the same line —
 * the list value arrives on a refetch, this one on a live turn — and a rule
 * held on only one side is a preview that changes owner depending on which
 * source spoke last, which is the defect both exist to end.
 *
 * The rule: the AGENT's latest message, falling back to the newest message of
 * any role while the agent has not spoken yet. Not "the newest message", which
 * alternates owner at every turn boundary — the user's own sentence echoed back
 * for as long as the agent is working, then the agent's reply, then the user's
 * again.
 */

/** True for a message this thread said BACK to the user. */
export function isAgentMessage(item: Pick<ItemDto, 'kind' | 'role'>): boolean {
  // Read as "not the user" rather than as an allowlist of agent role names, so
  // a CLI that spells its own role differently still previews instead of
  // falling silently back to echoing the user.
  return item.kind === 'message' && item.role !== 'user';
}

/**
 * The message a batch of transcript rows should preview, or undefined when it
 * holds none. `agentHasSpoken` carries what the batch alone cannot know — that
 * an EARLIER part of the conversation already had an agent reply — so a delta
 * carrying only the user's newest message does not put the fallback back into
 * effect on a thread that has long since left it.
 */
export function previewMessageOf<T extends Pick<ItemDto, 'kind' | 'role'>>(
  items: readonly T[],
  agentHasSpoken: boolean,
): T | undefined {
  const agent = items.findLast(isAgentMessage);
  if (agent !== undefined) {
    return agent;
  }
  return agentHasSpoken
    ? undefined
    : items.findLast((item) => item.kind === 'message');
}
