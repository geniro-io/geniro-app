import type * as React from 'react';

import type { ChatSearchHit } from '../autogenerated';
import { EmptyState } from '../components/empty-state';
import { ErrorText } from '../components/error-text';
import {
  SearchField,
  SearchResultList,
  SearchSnippet,
} from '../components/search-panel';
import { Dialog } from '../components/ui/dialog';
import { formatClockTime } from './relative-time';
import type { ChatSearchState } from './use-chat-search';

/**
 * What a hit's row is CALLED — the kind, in the words the transcript itself
 * uses.
 *
 * Only the kinds a search can actually return need an entry: a hit exists
 * because `searchableText` found words in the payload, so kinds carrying none
 * (`usage`, `attachment`) never reach here. Anything unlisted falls back to its
 * own kind with the underscores opened out, which is a worse label than a
 * written one and a far better one than nothing.
 */
const KIND_LABELS: Record<string, string> = {
  message: 'Message',
  reasoning: 'Reasoning',
  tool_call: 'Tool call',
  tool_result: 'Tool result',
  system: 'Note',
  error: 'Error',
  task_list: 'Task list',
  findings: 'Findings',
  call_question: 'Question',
  call_answer: 'Answer',
  approval_request: 'Approval request',
};

function hitLabel(hit: ChatSearchHit): string {
  // The ROLE outranks the kind for a message, because "You" and "Message" are
  // the difference between the reader's own words and the agent's — which is
  // most of what a list of hits is scanned for.
  if (hit.kind === 'message') {
    return hit.role === 'user' ? 'You' : 'Message';
  }
  return KIND_LABELS[hit.kind] ?? hit.kind.replaceAll('_', ' ');
}

/**
 * Search what was said in the OPEN conversation, and jump to it.
 *
 * A dialog rather than a strip in the transcript, on the session picker's own
 * reasoning: a list of hits needs room to scroll and its own place to say why it
 * is short, and a chat pane that is already two columns wide has neither. It
 * closes on a pick, because the answer to a search is a place in the
 * conversation rather than a list to keep beside it.
 *
 * The rows are drawn from the SHARED search panel, so this and the session
 * picker cannot grow different ideas of what "searching" looks like — see
 * `components/search-panel.tsx` for which states that covers.
 */
export function ChatSearchDialog({
  open,
  search,
  onClose,
  onJump,
}: {
  open: boolean;
  search: ChatSearchState;
  onClose: () => void;
  /** Take the reader to this row — see `Chats.tsx`'s `jumpToSeq`. */
  onJump: (seq: number) => void;
}): React.JSX.Element {
  const { query, setQuery, hits, partialReason, loading, error, tooShort } =
    search;

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Search this conversation"
      // Tall and wide for the reason the session picker is: a hit is a quoted
      // sentence, and a narrow card would clip every one of them to a few words.
      // `max-w-none` beats Dialog's own 28rem cap, which a width alone does not.
      className="h-[min(48rem,100%)] w-[min(48rem,calc(100vw-3rem))] max-w-none">
      <div className="flex h-full min-h-0 flex-col gap-3">
        <p className="shrink-0 text-sm text-muted-foreground">
          Searched on the daemon, over the whole conversation — including the
          part this window has not loaded.
        </p>

        <SearchField
          className="shrink-0"
          label="Search this conversation"
          placeholder="Search by what was said…"
          value={query}
          onValueChange={setQuery}
          autoFocus
        />

        {error ? <ErrorText className="shrink-0">{error}</ErrorText> : null}

        <SearchResultList
          loading={loading}
          loadingLabel="Searching this conversation…"
          partialReason={partialReason}
          isEmpty={hits.length === 0}
          empty={
            <EmptyState>
              {query.trim() === ''
                ? 'Type to search what was said in this conversation.'
                : tooShort
                  ? 'Two characters or more — one matches almost every message.'
                  : 'Nothing in this conversation matches that.'}
            </EmptyState>
          }>
          <ul className="m-0 flex list-none flex-col p-1">
            {hits.map((hit) => (
              // Keyed on the pair, not the seq alone: transcripts written before
              // the daemon's seq allocator hold two rows sharing one seq — the
              // transcript itself de-dupes by `id` for that reason — and two such
              // hits would collide here.
              <li key={`${hit.seq}:${hit.createdAt}`}>
                <button
                  type="button"
                  className="flex w-full cursor-pointer flex-col items-start gap-0.5 rounded-md px-3 py-2 text-left hover:bg-sidebar-accent"
                  onClick={() => onJump(hit.seq)}>
                  <span className="flex w-full items-baseline gap-2 text-sm text-foreground">
                    {hitLabel(hit)}
                    <span className="ml-auto shrink-0 text-xs text-muted-foreground">
                      {formatClockTime(hit.createdAt)}
                    </span>
                  </span>
                  <SearchSnippet>{hit.snippet}</SearchSnippet>
                </button>
              </li>
            ))}
          </ul>
        </SearchResultList>
      </div>
    </Dialog>
  );
}
