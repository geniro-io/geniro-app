// @vitest-environment jsdom
import { act, useState } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { LiveAction } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { ChatActionChips } from './action-chip';
import { ChatProviders } from './chat-providers';
import { quotedArgv } from './command-confirm-dialog';
import { useChatActions } from './use-chat-actions';

(
  globalThis as unknown as { IS_REACT_ACT_ENVIRONMENT: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const CWD = '/Users/dev/Library/Application Support/Geniro/repo';
const ARGV = ['node', 'scripts/build report.mjs', '--title', "it's", ''];

function command(seq: number, label: string): LiveAction {
  return {
    seq,
    actionId: label.toLowerCase(),
    memberId: 'agent',
    conversationId: '',
    label,
    once: false,
    spec: {
      kind: 'command',
      argv: ARGV,
      cwd: CWD,
      timeoutMs: 600_000,
      notifyAgent: true,
    },
    publisher: { nodeId: 'agent', conversationId: '', agentLabel: 'Engineer' },
    pending: false,
  };
}

function message(seq: number, label: string): LiveAction {
  return {
    seq,
    actionId: label.toLowerCase(),
    memberId: 'agent',
    conversationId: '',
    label,
    once: false,
    spec: { kind: 'message', text: 'go' },
    publisher: { nodeId: 'agent', conversationId: '' },
    pending: false,
  };
}

let root: Root | null = null;
afterEach(() => {
  act(() => root?.unmount());
  root = null;
  document.body.replaceChildren();
});

/** The shelf and the dialog over the real hook, wired the way `ChatProviders` wires them. */
function harness(initial: LiveAction[]) {
  const api = {
    pressChatAction: vi.fn(() =>
      Promise.resolve({
        outcome: {
          actionSeq: 0,
          actionId: '',
          nodeId: 'agent',
          conversationId: '',
          state: 'running' as const,
        },
      }),
    ),
    dismissChatAction: vi.fn(() =>
      Promise.resolve({
        outcome: {
          actionSeq: 0,
          actionId: '',
          nodeId: 'agent',
          conversationId: '',
          state: 'dismissed' as const,
        },
      }),
    ),
  };
  let setActions: ((next: LiveAction[]) => void) | null = null;
  function Surface(): React.JSX.Element {
    const [actions, set] = useState(initial);
    setActions = set;
    const refresh = useLatestCallback(() => undefined, []);
    const chat = useChatActions(
      api,
      'run',
      { actions, turnStartedAt: null, throughSeq: 100 },
      refresh,
    );
    // Through the real providers, which mount the one dialog per surface.
    return (
      <ChatProviders
        threadId="run"
        runSettledAt={null}
        signIn={null}
        retry={null}
        callContext={null}
        callChannel={null}
        artifactUrl={null}
        chatActions={chat}>
        <ChatActionChips
          actions={chat.actions}
          phases={chat.phases}
          onPress={chat.press}
          onDismiss={chat.dismiss}
        />
      </ChatProviders>
    );
  }
  const container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  return {
    api,
    container,
    render: async () => {
      await act(async () => root!.render(<Surface />));
    },
    replaceActions: async (next: LiveAction[]) => {
      await act(async () => setActions!(next));
    },
    click: async (element: Element | null | undefined) => {
      await act(async () => (element as HTMLElement).click());
    },
    chip: (label: string) =>
      [
        ...container.querySelectorAll<HTMLButtonElement>(
          '[data-slot="action-chip"]',
        ),
      ].find((node) => node.textContent?.startsWith(label)),
    dialog: () => document.querySelector('[aria-modal="true"]'),
    button: (name: string) =>
      [
        ...document.querySelectorAll<HTMLButtonElement>(
          '[aria-modal="true"] button',
        ),
      ].find((node) => node.textContent === name),
  };
}

describe('CommandConfirmDialog', () => {
  it('command chip opens the dialog with exact argv and cwd and presses only on Run command', async () => {
    const shelf = harness([command(5, 'Build report')]);
    await shelf.render();
    expect(shelf.dialog()).toBeNull();

    await shelf.click(shelf.chip('Build report'));

    const dialog = shelf.dialog();
    expect(
      dialog?.querySelector('[data-slot="dialog-title"]')?.textContent,
    ).toBe('Run "Build report"?');
    expect(dialog?.textContent).toContain('Engineer wants to run:');
    expect(
      [...dialog!.querySelectorAll('[data-slot="command-token"]')].map(
        (token) => token.textContent,
      ),
    ).toEqual([
      'node',
      "'scripts/build report.mjs'",
      '--title',
      `'it'\\''s'`,
      "''",
    ]);
    expect(
      dialog?.querySelector('[data-slot="command-cwd"]')?.textContent,
    ).toBe(CWD);
    expect(dialog?.textContent).toContain('Stops after 10 min');
    expect(dialog?.textContent).toContain('The agent is told how it ended.');
    expect(shelf.api.pressChatAction).not.toHaveBeenCalled();

    await shelf.click(shelf.button('Cancel'));
    expect(shelf.dialog()).toBeNull();
    expect(shelf.api.pressChatAction).not.toHaveBeenCalled();

    await shelf.click(shelf.chip('Build report'));
    await shelf.click(shelf.button('Run command'));

    expect(shelf.dialog()).toBeNull();
    expect(shelf.api.pressChatAction).toHaveBeenCalledTimes(1);
    expect(shelf.api.pressChatAction).toHaveBeenCalledWith({
      runId: 'run',
      seq: 5,
      pressActionDto: { clientMessageId: expect.any(String) as string },
    });
  });

  it('opens from the overflow list too, and a message button still presses at once', async () => {
    const shelf = harness([
      message(3, 'Ping'),
      message(2, 'Merged'),
      command(1, 'Build report'),
    ]);
    await shelf.render();

    await shelf.click(
      shelf.container.querySelector('[data-slot="action-overflow"] button'),
    );
    const rows = [
      ...document.querySelectorAll<HTMLButtonElement>(
        '[data-slot="action-row"] > button',
      ),
    ];
    await shelf.click(
      rows.find((row) => row.textContent?.includes('Build report')),
    );

    expect(shelf.dialog()).not.toBeNull();
    expect(shelf.api.pressChatAction).not.toHaveBeenCalled();

    await shelf.click(shelf.button('Cancel'));
    await shelf.click(shelf.chip('Ping'));

    expect(shelf.api.pressChatAction).toHaveBeenCalledTimes(1);
    expect(shelf.dialog()).toBeNull();
  });

  it('focuses Cancel when it opens', async () => {
    const shelf = harness([command(5, 'Build report')]);
    await shelf.render();

    await shelf.click(shelf.chip('Build report'));

    expect(document.activeElement).toBe(shelf.button('Cancel'));
  });

  it('refuses Run command once the agent changed or removed the action, and presses nothing', async () => {
    const shelf = harness([command(5, 'Build report')]);
    await shelf.render();
    await shelf.click(shelf.chip('Build report'));
    expect(shelf.button('Run command')?.disabled).toBe(false);
    expect(shelf.dialog()?.textContent).not.toContain('changed or removed');

    await shelf.replaceActions([command(6, 'Build report')]);

    expect(shelf.dialog()?.textContent).toContain(
      'The agent changed or removed this action since it was shown.',
    );
    expect(shelf.button('Run command')?.disabled).toBe(true);
    expect(shelf.button('Cancel')?.disabled).toBe(false);
    await shelf.click(shelf.button('Run command'));
    expect(shelf.api.pressChatAction).not.toHaveBeenCalled();
  });

  it('says The agent when the publisher is the run’s own', async () => {
    const own: LiveAction = {
      ...command(5, 'Build report'),
      publisher: { nodeId: 'agent', conversationId: '' },
    };
    const shelf = harness([own]);
    await shelf.render();

    await shelf.click(shelf.chip('Build report'));

    expect(shelf.dialog()?.textContent).toContain('The agent wants to run:');
  });
});

describe('quotedArgv', () => {
  it.each([
    [
      ['pnpm', 'test:e2e', '--grep=a-b', './x/y.ts'],
      ['pnpm', 'test:e2e', '--grep=a-b', './x/y.ts'],
    ],
    [['a b'], [`'a b'`]],
    [[''], [`''`]],
    [
      ['^x', '%1'],
      [`'^x'`, '%1'],
    ],
    [["it's"], [`'it'\\''s'`]],
    [
      ['tab\there', 'new\nline'],
      [`'tab\there'`, `'new\nline'`],
    ],
    [
      ['$HOME', '`id`', '!x', '*.ts', '?', '[a]', '(a)', '{a}'],
      [`'$HOME'`, "'`id`'", `'!x'`, `'*.ts'`, `'?'`, `'[a]'`, `'(a)'`, `'{a}'`],
    ],
    [
      ['a>b', 'a<b', 'a|b', 'a&b', 'a;b', '#c', '~', 'a"b', 'a\\b'],
      [
        `'a>b'`,
        `'a<b'`,
        `'a|b'`,
        `'a&b'`,
        `'a;b'`,
        `'#c'`,
        `'~'`,
        `'a"b'`,
        `'a\\b'`,
      ],
    ],
  ])('quotes %j as %j', (argv, expected) => {
    expect(quotedArgv(argv)).toEqual(expected);
  });
});
