import type { Meta, StoryObj } from '@storybook/react-vite';
import { useState } from 'react';

import type { LiveAction } from '../autogenerated';
import { CommandConfirmDialog } from './command-confirm-dialog';

function command(
  argv: string[],
  cwd: string,
  extra: Partial<LiveAction['spec']> = {},
  agentLabel?: string,
): LiveAction {
  return {
    seq: 7,
    actionId: 'run-e2e',
    nodeId: 'agent',
    conversationId: '',
    label: 'Run e2e',
    once: false,
    spec: { kind: 'command', argv, cwd, timeoutMs: 600_000, ...extra },
    publisher: {
      nodeId: 'agent',
      conversationId: '',
      ...(agentLabel === undefined ? {} : { agentLabel }),
    },
    pending: false,
  };
}

/** Opens by default; Cancel and Run command both close it, and Reopen brings it back. */
function Harness({
  action,
  changed = false,
}: {
  action: LiveAction;
  changed?: boolean;
}): React.JSX.Element {
  const [shown, setShown] = useState<LiveAction | null>(action);
  return (
    <>
      <button
        type="button"
        className="text-sm text-primary hover:underline"
        onClick={() => setShown(action)}>
        Reopen
      </button>
      <CommandConfirmDialog
        action={shown}
        changed={changed}
        onCancel={() => setShown(null)}
        onConfirm={() => setShown(null)}
      />
    </>
  );
}

const meta = {
  title: 'Chats/CommandConfirmDialog',
  component: Harness,
  decorators: [
    (story) => (
      <div className="h-[420px] bg-background p-3 text-foreground">
        {story()}
      </div>
    ),
  ],
} satisfies Meta<typeof Harness>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Default: Story = {
  args: {
    action: command(
      ['pnpm', 'test:e2e'],
      '/Users/dev/projects/geniro-app',
      { notifyAgent: true },
      'Engineer',
    ),
  },
};

