import { shellQuote } from '../../shared/shell-quote';
import type { LiveAction } from '../autogenerated';
import { ConfirmDialog } from '../components/confirm-dialog';

/**
 * Each argument as a shell would need it written to be the same single
 * argument, so the user reads exactly where one ends and the next begins —
 * an empty or spaced argument is not mistaken for two.
 */
export function quotedArgv(argv: readonly string[]): string[] {
  return argv.map(shellQuote);
}

const MS_PER_MINUTE = 60_000;

/**
 * The confirmation in front of every command an agent publishes: the exact
 * argv and folder, in full, before anything runs. Open while `action` is set;
 * `changed` means the agent replaced or removed it since it was shown, and
 * what is on screen is no longer what would run.
 */
export function CommandConfirmDialog({
  action,
  changed,
  onCancel,
  onConfirm,
}: {
  action: LiveAction | null;
  changed: boolean;
  onCancel: () => void;
  onConfirm: () => void;
}): React.JSX.Element {
  const { spec, publisher } = action ?? {};
  const tokens = quotedArgv(spec?.argv ?? []);
  const minutes =
    spec?.timeoutMs === undefined
      ? null
      : Math.max(1, Math.round(spec.timeoutMs / MS_PER_MINUTE));
  return (
    <ConfirmDialog
      open={action !== null}
      title={`Run "${action?.label ?? ''}"?`}
      confirmLabel="Run command"
      confirmVariant="default"
      busyLabel="Running…"
      error={
        changed
          ? 'The agent changed or removed this action since it was shown.'
          : null
      }
      confirmDisabled={changed}
      onCancel={onCancel}
      onConfirm={onConfirm}>
      <div className="flex flex-col gap-2">
        <p>{publisher?.agentLabel ?? 'The agent'} wants to run:</p>
        <div
          data-slot="command-argv"
          className="flex flex-wrap gap-x-2 gap-y-1 rounded-md bg-muted px-2 py-1.5 font-mono text-xs text-foreground">
          {tokens.map((token, index) => (
            <code
              // Position is the identity: the same word may repeat.
              key={index}
              data-slot="command-token"
              className="break-all whitespace-pre-wrap">
              {token}
            </code>
          ))}
        </div>
        <p>in</p>
        <code
          data-slot="command-cwd"
          className="rounded-md bg-muted px-2 py-1.5 font-mono text-xs break-all whitespace-pre-wrap text-foreground">
          {spec?.cwd ?? ''}
        </code>
        {minutes === null ? null : (
          <p className="text-xs text-muted-foreground">
            Stops after {minutes} min
          </p>
        )}
        {spec?.notifyAgent ? (
          <p className="text-xs text-muted-foreground">
            The agent is told how it ended.
          </p>
        ) : null}
      </div>
    </ConfirmDialog>
  );
}
