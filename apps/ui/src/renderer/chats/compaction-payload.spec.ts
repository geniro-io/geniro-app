import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  compactionDetail,
  compactionFacts,
  compactionOnlyTurnEnds,
} from './compaction-payload';

describe('compactionFacts', () => {
  it('reads the figures the daemon stamped', () => {
    expect(
      compactionFacts({
        message: 'This session is being continued…',
        origin: 'cli',
        compaction: { preTokens: 200_167, postTokens: 34_120 },
      }),
    ).toEqual({ preTokens: 200_167, postTokens: 34_120 });
  });

  it('is the MARKER, so a summary reported with no figures is still one', () => {
    // The boundary is optional metadata on the wire. Reading "no numbers" as
    // "not a compaction" would put the wall of prose back in the transcript.
    expect(
      compactionFacts({
        message: 'summary',
        origin: 'cli',
        compaction: { preTokens: null, postTokens: null },
      }),
    ).toEqual({ preTokens: null, postTokens: null });
  });

  it('is null for a relayed notice that is not a compaction summary', () => {
    expect(compactionFacts({ message: 'notice', origin: 'cli' })).toBeNull();
    expect(compactionFacts(null)).toBeNull();
    expect(compactionFacts({ compaction: 'yes' })).toBeNull();
  });

  it('rejects a non-positive count rather than showing "0 tokens"', () => {
    expect(
      compactionFacts({ compaction: { preTokens: 0, postTokens: -5 } }),
    ).toEqual({ preTokens: null, postTokens: null });
  });
});

describe('compactionDetail', () => {
  it('states the drop when both halves are known', () => {
    expect(compactionDetail({ preTokens: 200_167, postTokens: 34_120 })).toBe(
      '200.2k → 34.1k tokens',
    );
  });

  it('never subtracts across a missing operand', () => {
    // claude 2.1.228 sends pre_tokens on every boundary and post_tokens only
    // sometimes. An invented "after" figure is the one number a reader would act
    // on, so each of these says only what the CLI actually reported.
    expect(compactionDetail({ preTokens: 200_167, postTokens: null })).toBe(
      '200.2k tokens summarised',
    );
    expect(compactionDetail({ preTokens: null, postTokens: 34_120 })).toBe(
      '34.1k tokens after compacting',
    );
  });

  it('is undefined when the CLI reported nothing, so the row shows no figures', () => {
    expect(
      compactionDetail({ preTokens: null, postTokens: null }),
    ).toBeUndefined();
  });
});

describe('compactionOnlyTurnEnds', () => {
  let seq = 0;
  const item = (
    kind: ChatItem['kind'],
    payload: unknown,
    role: ChatItem['role'] = null,
  ): ChatItem => {
    seq += 1;
    return {
      id: `i${seq}`,
      runId: 'r1',
      nodeId: null,
      seq,
      kind,
      role,
      payload,
      createdAt: 'now',
    };
  };
  const compacted = (): ChatItem =>
    item('system', {
      message: 'This session is being continued…',
      origin: 'cli',
      compaction: { preTokens: 539_800, postTokens: 16_500 },
    });
  const done = (): ChatItem => item('turn_complete', { usage: null });

  it('names the ending of a turn that did nothing but compact', () => {
    const asked = item('message', { text: '/compact' }, 'user');
    const summary = compacted();
    const end = done();
    expect([...compactionOnlyTurnEnds([asked, summary, end])]).toEqual([
      end.id,
    ]);
  });

  it('leaves the ending of a turn that also DID something', () => {
    // An automatic compaction happens in the middle of real work, and that
    // turn's `✓ done` is reporting on the work — the figure the user reads to
    // see what the turn cost and how long it took.
    const asked = item('message', { text: 'refactor this' }, 'user');
    const summary = compacted();
    const answered = item(
      'message',
      { text: 'done — three files' },
      'assistant',
    );
    expect(
      compactionOnlyTurnEnds([asked, summary, answered, done()]).size,
    ).toBe(0);
  });

  it('does not carry a compaction across the turn that follows it', () => {
    // Counters reset at every turn end, so the NEXT turn's ending — which had
    // no compaction of its own — keeps its row.
    const first = [item('message', { text: '/compact' }, 'user'), compacted()];
    const firstEnd = done();
    const second = [
      item('message', { text: 'carry on' }, 'user'),
      item('message', { text: 'carrying on' }, 'assistant'),
    ];
    const secondEnd = done();
    expect([
      ...compactionOnlyTurnEnds([...first, firstEnd, ...second, secondEnd]),
    ]).toEqual([firstEnd.id]);
  });

  it('says nothing about a turn with no compaction at all', () => {
    const items = [
      item('message', { text: 'hello' }, 'user'),
      item('message', { text: 'hi' }, 'assistant'),
      done(),
    ];
    expect(compactionOnlyTurnEnds(items).size).toBe(0);
  });

  it('keeps a STOPPED compaction’s own row — cancelled is not "done"', () => {
    const items = [
      item('message', { text: '/compact' }, 'user'),
      compacted(),
      item('turn_cancelled', {}),
    ];
    expect(compactionOnlyTurnEnds(items).size).toBe(0);
  });
});
