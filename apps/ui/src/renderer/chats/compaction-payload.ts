/**
 * What a `system` row's `compaction` key says about the compaction whose summary
 * the row carries.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/services/chat.service.ts` stamps this
 * key onto a CLI-authored notice when the compaction boundary that preceded it
 * reported token figures. An item payload is `z.unknown()` on the wire BY DESIGN
 * — every item kind carries a different shape — so no generated type reaches the
 * renderer and the two sides are independent readings of one shape. Rename the
 * key there and this file must change with it.
 *
 * A plain `.ts` module rather than a helper inside the row component, for the
 * reason `system-payload.ts` is one: a pure payload reader parked in a `.tsx`
 * previously closed a real value-import cycle in this directory.
 *
 * It does pair with `agent-activity.ts` in both directions (`formatTokens` out,
 * `endsContextHistory` in), and that pair is safe only because neither side
 * touches the other at MODULE level — both are called from inside functions.
 * Keep it that way: a top-level use here would resolve to `undefined`.
 */

import type { ItemDto as ChatItem } from '../autogenerated';
import { formatTokens } from './agent-activity';
import { TERMINAL_KINDS } from './settled-status';

/** Presence of this marker is what says the row IS a compaction summary. */
export interface CompactionFacts {
  /** Context tokens before the compaction, or null if the CLI did not say. */
  preTokens: number | null;
  /** Context tokens after it, or null. Claude reports this less often than pre. */
  postTokens: number | null;
}

/**
 * Read the compaction marker off a `system` item's payload, or null when the row
 * is an ordinary relayed notice.
 *
 * The marker — not the message TEXT — is what identifies a compaction summary. A
 * CLI that reworded its "This session is being continued…" preamble would
 * silently stop being recognised by a pattern match, and the daemon refuses to
 * pattern-match it for exactly that reason.
 */
export function compactionFacts(payload: unknown): CompactionFacts | null {
  if (payload === null || typeof payload !== 'object') {
    return null;
  }
  const value = (payload as { compaction?: unknown }).compaction;
  if (value === null || typeof value !== 'object') {
    return null;
  }
  const record = value as { preTokens?: unknown; postTokens?: unknown };
  return {
    preTokens: positive(record.preTokens),
    postTokens: positive(record.postTokens),
  };
}

/**
 * Whether this `system` row records that the CLI's conversation was REPLACED —
 * geniro's own compaction, performed for a CLI that has none of its own.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/services/chat.service.ts` stamps
 * `conversationReplaced` in `commitCarriedCompaction`. A separate key from
 * {@link compactionFacts}, because they answer different questions: that one
 * identifies a relayed wall of prose to collapse, this one says the readings
 * above it stopped describing this conversation.
 */
export function conversationReplaced(payload: unknown): boolean {
  return (
    payload !== null &&
    typeof payload === 'object' &&
    (payload as { conversationReplaced?: unknown }).conversationReplaced ===
      true
  );
}

/**
 * Does this row end the stretch of transcript a context reading may be taken
 * from? True for either kind of compaction — the CLI's own and geniro's.
 *
 * A compaction empties the window, so every figure ABOVE it describes a
 * conversation that is over. The CLI's own compaction usually reports what it
 * left behind and that figure lands below this row, which is why this is a
 * reset and not a refusal.
 */
export function endsContextHistory(item: ChatItem): boolean {
  return (
    item.kind === 'system' &&
    (compactionFacts(item.payload) !== null ||
      conversationReplaced(item.payload))
  );
}

/** A positive token count, else null — a zero window is nothing worth showing. */
function positive(value: unknown): number | null {
  return typeof value === 'number' && value > 0 ? value : null;
}

/**
 * The one line the collapsed row shows about what the compaction did, or
 * undefined when the CLI reported no figures at all.
 *
 * Three readings, because the CLI does not always report both halves — claude
 * 2.1.228 sends `pre_tokens` on every boundary and `post_tokens` only sometimes.
 * Each says only what is known: never a subtraction across a missing operand, and
 * never a fabricated "after" figure, which would be the one number a reader would
 * actually act on.
 */
export function compactionDetail(facts: CompactionFacts): string | undefined {
  const { preTokens, postTokens } = facts;
  if (preTokens !== null && postTokens !== null) {
    return `${formatTokens(preTokens)} → ${formatTokens(postTokens)} tokens`;
  }
  if (preTokens !== null) {
    return `${formatTokens(preTokens)} tokens summarised`;
  }
  if (postTokens !== null) {
    return `${formatTokens(postTokens)} tokens after compacting`;
  }
  return undefined;
}

/**
 * The `turn_complete` rows whose turn did nothing but compact the conversation
 * — the ones the transcript should not print a second ending for.
 *
 * `/compact` is a turn like any other on the wire: the user's command, the
 * CLI's summary row, and a terminal item. On screen that reads
 * `conversation compacted · 539.8k → 16.5k tokens` immediately followed by
 * `✓ done · 2m 15s`, and the second line says nothing the first did not —
 * reported as "after conversation compacted we dont need to duplicate done
 * message".
 *
 * Decided STRUCTURALLY, from what the turn actually produced, rather than by
 * matching the text `/compact`: a user is free to type that string as prose,
 * and — the case that matters — an AUTOMATIC compaction happens in the middle
 * of a turn that is doing real work. Anything at all besides the compaction
 * summary (an assistant message, a tool call, a reasoning row) keeps the
 * ending, because then it is reporting on work rather than on housekeeping.
 * The user's own message is not work: it is the instruction that asked for it.
 *
 * Only the ROW goes. The item is untouched, so the turn still counts toward
 * the header's worked/turns totals and its usage still reaches the ledger.
 *
 * Run-level rows only (`nodeId === null`) — a workflow node's own turn end is
 * a different statement, and its rows are not this turn's content.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/services/chat.service.ts` decides the
 * same thing LIVE, from the events of the turn it is running, as its
 * `compactionRows`/`workRows` tally behind `RunStatusEvent.housekeeping` — which
 * is what suppresses the system notification for the same turn. This side reads
 * the persisted items instead, because a reopened chat has only those. The two
 * readings must agree: a turn the transcript treats as pure housekeeping while
 * the sidebar marks it unseen is the app contradicting itself about one turn, so
 * a change to what counts as work belongs on both sides or neither.
 */
export function compactionOnlyTurnEnds(
  items: readonly ChatItem[],
): ReadonlySet<string> {
  const ends = new Set<string>();
  let compactions = 0;
  let work = 0;
  for (const item of items) {
    if (item.nodeId !== null) {
      continue;
    }
    if (TERMINAL_KINDS.has(item.kind)) {
      if (item.kind === 'turn_complete' && compactions > 0 && work === 0) {
        ends.add(item.id);
      }
      compactions = 0;
      work = 0;
      continue;
    }
    if (item.kind === 'system' && compactionFacts(item.payload) !== null) {
      compactions += 1;
      continue;
    }
    // The prompt that ASKED for the compaction — including a follow-up steered
    // into the same turn, which is still the user talking rather than the
    // agent producing anything.
    if (item.kind === 'message' && item.role === 'user') {
      continue;
    }
    work += 1;
  }
  return ends;
}
