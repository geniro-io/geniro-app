import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { readComparison } from './comparison-payload';

const row = (payload: unknown): ChatItem =>
  ({
    id: 'i1',
    runId: 'r1',
    nodeId: null,
    seq: 1,
    kind: 'show_comparison',
    role: null,
    payload,
    createdAt: '2026-08-29T10:00:00.000Z',
  }) as unknown as ChatItem;

const OPTIONS = [{ name: 'SQLite' }, { name: 'Postgres' }];
const CRITERIA = [
  { label: 'Setup cost', cells: [{ value: 'none' }, { value: 'a server' }] },
];

describe('readComparison', () => {
  it('reads the daemon’s own literal, every field surviving', () => {
    // The twin of `chat.service.spec.ts`'s worked example — the payload is
    // `z.unknown()` on the wire, so this is the only thing keeping the two
    // readings of one shape together.
    expect(
      readComparison(
        row({
          title: 'Local store for the daemon',
          options: [{ name: 'SQLite', note: 'one file' }, { name: 'Postgres' }],
          criteria: [
            {
              label: 'Setup cost',
              cells: [
                { value: 'none', verdict: 'good' },
                { value: 'a server', verdict: 'bad' },
              ],
            },
          ],
          recommendation: { option: 'SQLite', reason: 'local-first by rule' },
        }),
      ),
    ).toEqual({
      title: 'Local store for the daemon',
      options: [
        { name: 'SQLite', note: 'one file' },
        { name: 'Postgres', note: null },
      ],
      criteria: [
        {
          label: 'Setup cost',
          cells: [
            { value: 'none', verdict: 'good' },
            { value: 'a server', verdict: 'bad' },
          ],
        },
      ],
      recommendation: { option: 'SQLite', reason: 'local-first by rule' },
      recommendedIndex: 0,
    });
  });

  it('RE-ALIGNS every row to the option count', () => {
    // Runs over rows written by OLDER builds, whose alignment was whatever
    // that build's rules were — a short row reaching the table would leave the
    // last option looking un-assessed.
    const read = readComparison(
      row({
        title: 'T',
        options: [{ name: 'A' }, { name: 'B' }, { name: 'C' }],
        criteria: [
          { label: 'short', cells: [{ value: 'a' }] },
          {
            label: 'long',
            cells: [
              { value: 'a' },
              { value: 'b' },
              { value: 'c' },
              { value: 'd' },
            ],
          },
        ],
      }),
    );
    expect(read?.criteria[0]?.cells.map((c) => c.value)).toEqual(['a', '', '']);
    expect(read?.criteria[1]?.cells.map((c) => c.value)).toEqual([
      'a',
      'b',
      'c',
    ]);
  });

  it('BLANKS an unreadable cell rather than dropping it', () => {
    // Dropping would file each option's answer under its neighbour's name — a
    // failure that does not throw and still looks like a comparison.
    const read = readComparison(
      row({
        title: 'T',
        options: [{ name: 'A' }, { name: 'B' }, { name: 'C' }],
        criteria: [
          { label: 'row', cells: [{ value: 'a' }, 42, { value: 'c' }] },
        ],
      }),
    );
    expect(read?.criteria[0]?.cells.map((c) => c.value)).toEqual([
      'a',
      '',
      'c',
    ]);
  });

  it('resolves an absent or unknown verdict to neutral', () => {
    const read = readComparison(
      row({
        title: 'T',
        options: OPTIONS,
        criteria: [
          {
            label: 'row',
            cells: [{ value: 'a', verdict: 'gooood' }, { value: 'b' }],
          },
        ],
      }),
    );
    expect(read?.criteria[0]?.cells.map((c) => c.verdict)).toEqual([
      'neutral',
      'neutral',
    ]);
  });

  it('matches the recommendation to its column, case-insensitively', () => {
    // A model that writes "sqlite" in the recommendation and "SQLite" in the
    // options is agreeing with itself; an exact match would silently drop the
    // highlight.
    const read = readComparison(
      row({
        title: 'T',
        options: OPTIONS,
        criteria: CRITERIA,
        recommendation: { option: '  postgres ', reason: 'concurrency' },
      }),
    );
    expect(read?.recommendedIndex).toBe(1);
  });

  it('keeps a recommendation naming NO column, with no highlight', () => {
    // A real answer: the agent may recommend something that is not on the
    // table, and the reason still reads.
    const read = readComparison(
      row({
        title: 'T',
        options: OPTIONS,
        criteria: CRITERIA,
        recommendation: { option: 'DuckDB', reason: 'neither, actually' },
      }),
    );
    expect(read?.recommendedIndex).toBeNull();
    expect(read?.recommendation?.reason).toBe('neither, actually');
  });

  it('drops a HALF recommendation rather than half-drawing it', () => {
    for (const recommendation of [
      { option: 'SQLite' },
      { reason: 'because' },
      'SQLite',
      null,
    ]) {
      const read = readComparison(
        row({
          title: 'T',
          options: OPTIONS,
          criteria: CRITERIA,
          recommendation,
        }),
      );
      expect(read?.recommendation).toBeNull();
      expect(read?.recommendedIndex).toBeNull();
    }
  });

  it('answers a payload that is not a comparison with null', () => {
    for (const payload of [
      null,
      'SQLite vs Postgres',
      42,
      {},
      { title: 'T' },
      { title: 'T', options: OPTIONS },
      { title: 'T', options: OPTIONS, criteria: [] },
      { title: 'T', options: OPTIONS, criteria: [{ cells: [] }] },
      // One column is not a comparison — the floor is enforced here too, not
      // only at the daemon edge, because this reader also runs over old rows.
      { title: 'T', options: [{ name: 'only' }], criteria: CRITERIA },
    ]) {
      expect(readComparison(row(payload))).toBeNull();
    }
  });
});
