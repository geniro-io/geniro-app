import type { ItemDto as ChatItem } from '../autogenerated';
import type { Sentiment } from './metrics-payload';

/**
 * A comparison an agent handed the app to draw, read off the transcript.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/chat.types.ts` declares the shape
 * (`HostComparison`) and `apps/daemon/src/v1/agents/utils/host-comparison.ts`
 * writes these keys for the `show_comparison` item kind. An item payload is
 * `z.unknown()` on the wire BY DESIGN — every kind carries a different shape —
 * so no generated type reaches here and this is an independent reading of one
 * shape. A key renamed on either side must be renamed on both.
 *
 * The invariant this file exists to preserve is POSITIONAL, the chart's again:
 * a criterion's cells are matched to `options` BY INDEX. Nothing here may drop
 * or reorder one list independently of the other — that failure does not throw,
 * it files each option's answer under its neighbour's name and still looks like
 * a comparison. So this reader re-aligns every row to the option count, exactly
 * as the daemon's does, because it also runs over rows written by OLDER builds
 * whose alignment was whatever that build's rules were.
 *
 * `Sentiment` is imported from `metrics-payload` rather than re-declared: it is
 * the same good/bad/neutral question, and the daemon shares one vocabulary
 * across both tools for that reason.
 */

const SENTIMENTS: readonly Sentiment[] = ['good', 'bad', 'neutral'];

/** One option — a column of the table. */
export interface ComparisonOption {
  name: string;
  note: string | null;
}

/** One option's answer for one criterion. */
export interface ComparisonCell {
  /** Empty when the agent said nothing here — drawn as a dash, not as a gap. */
  value: string;
  verdict: Sentiment;
}

/** One criterion — a row, holding exactly one cell per option. */
export interface ComparisonCriterion {
  label: string;
  cells: ComparisonCell[];
}

/** One `show_comparison` row, as the card draws it. */
export interface ComparisonSpec {
  title: string;
  options: ComparisonOption[];
  criteria: ComparisonCriterion[];
  /** Null when the agent named none; the card then draws no answer line. */
  recommendation: { option: string; reason: string } | null;
  /**
   * Which COLUMN the recommendation points at, or null when it points at none.
   *
   * Resolved here rather than in the card, and by NAME because that is what the
   * wire carries: matched case- and whitespace-insensitively, since a model
   * that writes "sqlite" in the recommendation and "SQLite" in the options is
   * agreeing with itself and an exact match would silently drop the highlight.
   * Null is a real answer — a recommendation may name something that is not on
   * the table, and the reason still reads.
   */
  recommendedIndex: number | null;
}

function readString(value: unknown): string | null {
  return typeof value === 'string' && value.length > 0 ? value : null;
}

function readCell(entry: unknown): ComparisonCell {
  // A blank, never a drop: an index here is which option the cell answers for.
  if (typeof entry === 'string') {
    return { value: entry, verdict: 'neutral' };
  }
  if (typeof entry !== 'object' || entry === null || Array.isArray(entry)) {
    return { value: '', verdict: 'neutral' };
  }
  const raw = entry as { value?: unknown; verdict?: unknown };
  return {
    value: readString(raw.value) ?? '',
    verdict:
      typeof raw.verdict === 'string' &&
      (SENTIMENTS as readonly string[]).includes(raw.verdict)
        ? (raw.verdict as Sentiment)
        : 'neutral',
  };
}

/** Fold a name to what a case-insensitive match compares. */
function key(name: string): string {
  return name.trim().toLowerCase();
}

/**
 * Read one `show_comparison` row, or null when the payload is not one.
 *
 * Two options is the floor here as it is at the daemon edge — a one-column
 * comparison is not one — so a row that has lost an option on the way is
 * dropped rather than drawn as an analysis of nothing.
 */
export function readComparison(item: ChatItem): ComparisonSpec | null {
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const row = payload as {
    title?: unknown;
    options?: unknown;
    criteria?: unknown;
    recommendation?: unknown;
  };
  const title = readString(row.title);
  if (title === null || !Array.isArray(row.options)) {
    return null;
  }
  const options: ComparisonOption[] = [];
  for (const entry of row.options) {
    if (typeof entry !== 'object' || entry === null || Array.isArray(entry)) {
      continue;
    }
    const raw = entry as { name?: unknown; note?: unknown };
    const name = readString(raw.name);
    if (name !== null) {
      options.push({ name, note: readString(raw.note) });
    }
  }
  if (options.length < 2 || !Array.isArray(row.criteria)) {
    return null;
  }
  const criteria: ComparisonCriterion[] = [];
  for (const entry of row.criteria) {
    if (typeof entry !== 'object' || entry === null || Array.isArray(entry)) {
      continue;
    }
    const raw = entry as { label?: unknown; cells?: unknown };
    const label = readString(raw.label);
    if (label === null) {
      continue;
    }
    const cells = Array.isArray(raw.cells) ? raw.cells : [];
    criteria.push({
      label,
      cells: options.map((_, index) => readCell(cells[index])),
    });
  }
  if (criteria.length === 0) {
    return null;
  }
  const suggested =
    row.recommendation &&
    typeof row.recommendation === 'object' &&
    !Array.isArray(row.recommendation)
      ? (row.recommendation as { option?: unknown; reason?: unknown })
      : null;
  const option = suggested === null ? null : readString(suggested.option);
  const reason = suggested === null ? null : readString(suggested.reason);
  const recommendation =
    option === null || reason === null ? null : { option, reason };
  const index =
    recommendation === null
      ? -1
      : options.findIndex((o) => key(o.name) === key(recommendation.option));
  return {
    title,
    options,
    criteria,
    recommendation,
    recommendedIndex: index === -1 ? null : index,
  };
}
