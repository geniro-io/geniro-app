import type { Meta, StoryObj } from '@storybook/react-vite';

import type { TeamNote } from '../autogenerated';
import { TeamNotesChip } from './composer-shelf';

function note(seq: number, over: Partial<TeamNote>): TeamNote {
  return {
    seq,
    kind: 'fact',
    text: '',
    nodeId: 'backend',
    conversationId: null,
    callId: null,
    createdAt: new Date(Date.now() - (300 - seq) * 60_000).toISOString(),
    supersedes: null,
    supersededBy: null,
    ...over,
  };
}

const NAMES: Record<string, string> = {
  manager: 'Manager',
  backend: 'Backend Engineer',
};

const meta = {
  title: 'Chats/TeamNotesChip',
  component: TeamNotesChip,
  args: {
    notes: [
      note(214, {
        kind: 'pitfall',
        text: '`npm ci` fails in this repo (pnpm workspace). Use `pnpm install --frozen-lockfile`.',
        callId: 'call-3',
      }),
      note(190, {
        kind: 'decision',
        text: 'Orders are paged by cursor, not offset.',
        nodeId: 'manager',
      }),
      note(150, {
        kind: 'contract',
        text: '`POST /orders` returns `{ id, status }`.',
      }),
    ],
    agentName: (nodeId: string) => NAMES[nodeId] ?? nodeId,
    onJump: () => {},
  },
  decorators: [
    (story) => (
      <div className="flex h-[360px] items-end bg-background p-4">
        {story()}
      </div>
    ),
  ],
} satisfies Meta<typeof TeamNotesChip>;

export default meta;
type Story = StoryObj<typeof meta>;

export const ThreeNotes: Story = {};

export const NoNotesDrawsNothing: Story = {
  args: { notes: [] },
};
