/**
 * The row of small cards directly above the composer.
 *
 * ONE LINE, always. What sits here is whatever the thread has produced that the
 * user might want to reach without scrolling the transcript — pull requests are
 * the first of those rather than the only one, and anything added later is
 * another chip in this row, not another line above the composer, which is how
 * the area became a stack of one-item rows in the first place. A row that
 * wrapped would push the textarea down by however much the thread happened to
 * produce, so each KIND of thing is one short chip — one pull request shows
 * itself, several are one chip with the list behind it, and the agent's
 * buttons likewise. On a phone the row scrolls sideways instead.
 *
 * The chips stay SEPARATE, with gaps — a row of distinct readings, each its own
 * object; the whole row joined into one segmented bar was rejected.
 *
 * Its height is RESERVED even when it holds nothing. The transcript above is
 * pinned to its tail, so a row appearing or vanishing resized the transcript
 * and moved every line in it — and the Terminals chip comes and goes with
 * nearly every command an agent runs. `min-h-7` is the tallest thing the row
 * can hold (the Unarchive button; chips are 22px), so no chip changes it.
 *
 * `inline` is the same row placed at the head of the queued strip's header
 * line, whose own height is held at the shelf's instead. Standing on its own
 * under a queue, the empty reservation was a blank band between the queue and
 * the composer — REPORTED as a gap that should never be there. Inline, an empty
 * shelf therefore draws nothing (the header line already keeps the height), and
 * it hangs into the header's left padding so a chip sits at the same x as it
 * does in its own row.
 *
 * `status` is the compact counter cluster pushed to the row's right end. It is
 * right-anchored, so it runs VOLATILE → DURABLE left to right: the chip that
 * comes and goes most sits furthest from the edge and shifts nothing.
 */
export function ComposerShelf({
  children,
  trailing,
  status,
  inline = false,
}: {
  children: React.ReactNode;
  /** Drawn after the content chips, before the right-anchored counters. */
  trailing?: React.ReactNode;
  status?: React.ReactNode;
  inline?: boolean;
}): React.JSX.Element {
  return (
    <div
      data-slot="composer-shelf"
      className={cn(
        'flex min-h-7 items-center gap-1.5 overflow-clip px-1 max-sm:overflow-x-auto max-sm:overscroll-x-contain max-sm:[scrollbar-width:none] max-sm:*:shrink-0',
        inline && '-mx-2 min-w-0 flex-1 [&:not(:has(>:not(:empty)))]:hidden',
      )}>
      {children}
      {trailing}
      {status === undefined ? null : (
        <div data-slot="shelf-status" className={SHELF_STATUS_GROUP_CLASS}>
          {status}
        </div>
      )}
    </div>
  );
}

