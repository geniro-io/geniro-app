/**
 * When geniro continues calls a usage limit stopped — `today` at a clock time,
 * and the weekday in front of it when the continue is on another day (a limit
 * can reset tomorrow; the daemon waits at most two days).
 */
export function formatContinueTime(at: number, now: number): string {
  const clock = formatClockTime(new Date(at).toISOString());
  const day = new Date(at);
  const today = new Date(now);
  return day.toDateString() === today.toDateString()
    ? clock
    : `${day.toLocaleDateString(undefined, { weekday: 'short' })} ${clock}`;
}

/**
 * A continue geniro has PROMISED this run and not yet made: calls a usage limit
 * stopped, which it starts again when the window reopens.
 *
 * The promise is made to the AGENT — it is told "geniro starts you again when
 * it resets" and waits — so without this the user sees a team go idle with
 * nothing on screen saying why or until when. So the promise is a chip with
 * the time it will be kept, and the way to call it off is behind it: a user
 * who would rather pick the team up themselves should not have it started
 * under them hours later.
 *
 * Read off the RUN (`RunDto.resetWakes`), which the daemon keeps and announces
 * whenever a promise is made, kept or called off — so the chip goes away the
 * moment the continue happens, and survives a reload and a daemon restart.
 */
export function ResetWakeChip({
  wakes,
  onCancel,
  cancelling = false,
  now = Date.now(),
}: {
  wakes: readonly RunResetWake[];
  onCancel: () => void;
  cancelling?: boolean;
  now?: number;
}): React.JSX.Element | null {
  if (wakes.length === 0) {
    return null;
  }
  const next = Math.min(...wakes.map((wake) => wake.continuesAt));
  const at = formatContinueTime(next, now);
  const callIds = wakes.flatMap((wake) => wake.callIds);
  return (
    <HoverPopover
      slot="reset-wake"
      openOn="click"
      label={`geniro continues ${callIds.join(', ')} at ${at}, when the usage limit resets`}
      panelLabel="Continue after the usage limit"
      side="top"
      align="start"
      className={SHELF_CHIP_WRAPPER_CLASS}
      triggerClassName={SHELF_CHIP_TRIGGER_CLASS}
      panelClassName="w-[20rem]"
      trigger={
        <>
          <AlarmClock className="size-3.5 text-muted-foreground" />
          <span className="font-medium">Continues at {at}</span>
        </>
      }>
      {(close) => (
        <div className="flex flex-col gap-2 p-3 text-xs">
          {wakes.map((wake) => (
            <p key={wake.instant} className="text-foreground">
              {wake.callIds.join(', ')} stopped at the usage limit (resets{' '}
              {wake.resetsAt}). geniro continues{' '}
              {wake.callIds.length === 1 ? 'it' : 'them'} at{' '}
              {formatContinueTime(wake.continuesAt, now)}.
            </p>
          ))}
          <Button
            type="button"
            size="sm"
            variant="outline"
            className="self-start"
            disabled={cancelling}
            onClick={() => {
              onCancel();
              close();
            }}>
            Don’t continue
          </Button>
        </div>
      )}
    </HoverPopover>
  );
}

/**
 * What the run's FOLDER holds that it did not when the chat started — the
 * leftmost chip on the shelf, and the way into the file list behind it.
 *
 * It was in the chat header first, beside search and export, and moved here on
 * report: the shelf is the row of what this thread has produced, and a folder an
 * agent has been writing to is the most literal case of that. It also stops the
 * header's chip competing with the thread TITLE for width, which is the one
 * element there that has to stay readable.
 *
 * LEFTMOST, ahead of the pull requests, by the shelf's own DURABLE → VOLATILE
 * rule: a working tree outlives every pull request opened from it, so nothing
 * here can shift it.
 *
 * Two states draw NOTHING at all, and they differ. A summary of `null` has not
 * been read yet, so there is no figure to state and a chip would have to invent
 * one. `files === 0` is a real reading of a folder nothing has touched — and on
 * the SHELF that draws nothing either, unlike the header where the control had
 * to stay reachable: this row is a row of what EXISTS, so an empty folder is
 * said by the chip's absence, exactly as a thread with no pull requests is.
 */
export function FolderChangesChip({
  summary,
  onOpen,
}: {
  summary: ChangesSummary | null;
  onOpen: () => void;
}): React.JSX.Element | null {
  if (summary === null || summary.files === 0) {
    return null;
  }
  const label = `${summary.files} ${summary.files === 1 ? 'file' : 'files'} changed since this chat started — open the list`;
  return (
    <button
      type="button"
      data-slot="folder-changes-chip"
      aria-label={label}
      title={label}
      onClick={onOpen}
      className={cn(SHELF_CHIP_CLASS, 'shrink-0')}>
      <GitCompare aria-hidden="true" className="size-3.5 shrink-0" />
      <span className="tabular-nums">
        {summary.files} {summary.files === 1 ? 'file' : 'files'}
      </span>
      <DiffFigures
        added={summary.added}
        removed={summary.removed}
        className="text-[11px]"
      />
    </button>
  );
}

/**
 * The thread's pull requests as ONE shelf chip.
 *
 * A thread with a single pull request shows it: its state, number and
 * acceptance, a press away from GitHub. With several, the chip is the glyph and
 * how many there are, and the list behind it holds every one — open first —
 * with its title, size and acceptance, and the way to the panel. Drawn while
 * the thread has a pull request worth naming (`shelfThreadPullRequests`).
 */
export function ThreadPullRequestChips({
  results,
  outcomes = new Map(),
}: {
  results: readonly PullRequestRefResult[];
  /** The thread's newest recorded outcome per pull request, as the daemon states it. */
  outcomes?: ReadonlyMap<string, PullRequestOutcome>;
}): React.JSX.Element | null {
  const runId = useContext(ThreadUiMemoryContext);
  const [newest] = shelfThreadPullRequests(results);
  if (newest === undefined) {
    return null;
  }
  const outcomeOf = (result: PullRequestRefResult): PullRequestOutcome | null =>
    outcomes.get(pullRequestOutcomeKey(result.ref)) ?? null;
  if (results.length === 1) {
    return (
      <ThreadPullRequestChip
        result={newest}
        showRepo={false}
        outcome={outcomeOf(newest)}
      />
    );
  }
  const showRepo =
    new Set(results.map((row) => `${row.ref.owner}/${row.ref.repo}`)).size > 1;
  const isOpen = (row: PullRequestRefResult): boolean =>
    row.pullRequest?.state === 'open';
  const open = results.filter(isOpen);
  const ordered = [...open, ...results.filter((row) => !isOpen(row))];
  const summary =
    open.length === 0
      ? `${results.length} pull requests`
      : `${results.length} pull requests · ${open.length} open`;
  return (
    <HoverPopover
      slot="thread-pull-requests"
      openOn="click"
      label={`${summary} — show the list`}
      title={`Pull requests · ${open.length} open of ${results.length}`}
      panelLabel="Pull requests"
      side="top"
      align="start"
      className={SHELF_CHIP_WRAPPER_CLASS}
      triggerClassName={SHELF_CHIP_TRIGGER_CLASS}
      panelClassName="w-[24rem] p-1.5"
      trigger={
        <>
          <GitPullRequest
            aria-hidden="true"
            className={cn(
              'size-3.5 shrink-0',
              open.length > 0 ? 'text-warning' : 'text-muted-foreground',
            )}
          />
          <span className="font-medium">PR</span>
          <span className="text-muted-foreground tabular-nums">
            {results.length}
          </span>
        </>
      }>
      {(close) => (
        <div data-slot="thread-pull-request-list" className="flex flex-col">
          <p className="m-0 px-2 pt-0.5 pb-1 text-[11px] text-muted-foreground">
            {summary}
          </p>
          <div className="flex max-h-80 flex-col gap-0.5 overflow-y-auto overscroll-contain">
            {ordered.map((result) => (
              <PullRequestListRow
                key={result.ref.url}
                result={result}
                showRepo={showRepo}
                outcome={outcomeOf(result)}
              />
            ))}
          </div>
          <div className="mt-1 border-t border-border/60 pt-1">
            <Button
              type="button"
              variant="ghost"
              size="sm"
              className="w-full justify-start px-2 font-normal text-muted-foreground hover:text-foreground"
              onClick={() => {
                close();
                revealThreadPullRequests(runId);
              }}>
              Show in the panel
            </Button>
          </div>
        </div>
      )}
    </HoverPopover>
  );
}

