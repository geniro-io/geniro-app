const CALL_STATE = {
  working: { word: 'working', dot: 'bg-success' },
  queued: {
    word: 'queued',
    dot: 'border border-muted-foreground bg-transparent',
  },
  quiet: { word: 'gone quiet', dot: 'bg-warning' },
} as const;

function callStateOf(call: OpenCallChipRow): keyof typeof CALL_STATE {
  if (call.queued) {
    return 'queued';
  }
  return call.stalled ? 'quiet' : 'working';
}

