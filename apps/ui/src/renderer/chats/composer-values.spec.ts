import { describe, expect, it } from 'vitest';

import { ChatApprovalMode } from '../autogenerated';
import {
  isChatApprovalMode,
  targetAgentKind,
  teamSlugOf,
} from './composer-values';

describe('teamSlugOf / targetAgentKind', () => {
  it('reads the slug out of a team: target and nothing out of a CLI one', () => {
    expect(teamSlugOf('team:ship-it')).toBe('ship-it');
    expect(teamSlugOf('claude')).toBeNull();
    // A bare `team:` names no team.
    expect(teamSlugOf('team:')).toBeNull();
  });

  it('keys a team under claude', () => {
    // The composer derives `agentKind` as `teamSlug ? 'claude' : target`.
    // If these two disagree, a remembered model is stored under a key the
    // composer never reads back.
    expect(targetAgentKind('team:ship-it')).toBe('claude');
    expect(targetAgentKind('cursor-agent')).toBe('cursor-agent');
  });
});

describe('isChatApprovalMode', () => {
  it('accepts the daemon’s own words and refuses anything else', () => {
    // The whole reason this exists: settings.json is a file the user can edit
    // and an older build can write, so a stored mode is FOREIGN input — sent
    // unchecked, it reaches a run the daemon then rejects.
    expect(isChatApprovalMode(ChatApprovalMode.Ask)).toBe(true);
    expect(isChatApprovalMode('yolo-mode')).toBe(false);
    expect(isChatApprovalMode(null)).toBe(false);
    expect(isChatApprovalMode(3)).toBe(false);
  });
});
