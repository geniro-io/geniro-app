import { useCallback, useContext, useEffect, useRef, useState } from 'react';

import type { ChatMetricsDto } from '../autogenerated';
import { HoverPopover } from '../components/hover-popover';
import { ProgressRing } from '../components/ui/progress-ring';
import { cn } from '../components/ui/utils';
import { formatTokens, formatUsd } from './agent-activity';
import { ChatMetricsLoaderContext } from './chat-metrics';
import { ContextPanel } from './context-panel';

/**
 * Fraction above which the ring warns, then alarms. Below `WARN_AT` it is
 * GREEN — a traffic light, not a brand accent: the ring exists to say how much
 * room is left, and `text-primary` (the app's caramel) reads as decoration
 * beside every other primary-toned control rather than as "you are fine".
 */
const WARN_AT = 0.6;
const ALARM_AT = 0.9;

/**
 * How often an OPEN readout re-reads while the agent is working.
 *
 * The readout used to be taken once per open and never again, and its own copy
 * said so — "send a message in this chat to take a fresh reading" — while every
 * figure in it moved underneath: measured across one turn, the thread went from
 * 0 turns to 1, its cost from nothing to $0.03, and the window from 32,560 to
 * 32,105 tokens. Somebody watching an agent work was reading the moment they
 * opened the panel.
 *
 * Ten seconds and not one, because this is not a cheap read: for claude it is a
 * control request onto the live agent's stdin, measured at 1.1s on a 411k-token
 * session, and the CLI serialises them. It runs only while the panel is OPEN
 * and only while the agent is actually working — a settled chat's figures
 * cannot change on their own, so polling one would be a question with a known
 * answer.
 */
const LIVE_REREAD_MS = 10_000;

/**
 * A ring with a readout behind it: the shell BOTH ring branches are drawn on —
 * the one showing how full the window is, and the one saying the CLI never
 * reports it.
 *
 * Extracted rather than copied, and it owns the open state because that is the
 * fiddly part: the pin/hover pair below took two attempts to get right, and a
 * second copy of it would be a second chance to get it wrong. The `data-slot`
 * is the same either way, so "where is the meter" stays one query whichever
 * shape it has taken.
 */
function MeterReadout({
  ring,
  label,
  side,
  className,
  runId,
  live = false,
  children,
}: {
  ring: React.ReactNode;
  /** The whole reading, as the button's accessible name. */
  label: string;
  side: 'top' | 'bottom';
  className?: string;
  /** Which chat to fetch the full readout for, or null for none. */
  runId?: string | null;
  /** Whether this chat's agent is working right now — see {@link LIVE_REREAD_MS}. */
  live?: boolean;
  children: React.ReactNode;
}): React.JSX.Element {
  // Mirrors `HoverPopover`'s own open state, which this needs and cannot see:
  // the breakdown is fetched when the panel OPENS and never polled, so the
  // fetch has to be told. `useState`'s setter is stable, so it can be the
  // callback directly.
  const [open, setOpen] = useState(false);
  const metrics = useChatMetrics(runId ?? null, open, live);
  return (
    <HoverPopover
      // Unchanged whichever shape the meter has taken, so "where is the meter"
      // stays one query.
      slot="context-meter"
      className={className}
      // `size-full justify-center` so a caller can give the OUTER span a box
      // and have the ring centre in it. The agents panel does, because the row
      // it sits in is a strip of `size-6` icon buttons at `gap-0.5`: a bare
      // 14px ring in that row is 5px closer to its neighbour than the
      // neighbours are to each other, since their glyphs carry that padding
      // inside the button and the ring carried none. Equal BOXES is what makes
      // the gaps equal — a nudge margin would have to be re-tuned the moment
      // either size changes.
      triggerClassName="size-full justify-center"
      // The ring is the whole control, so the button carries the reading as its
      // accessible name — a screen reader gets it without having to open
      // anything, which a hover-only readout could never provide.
      label={label}
      panelLabel="Context usage"
      side={side}
      onOpenChange={setOpen}
      // `w-max` so the figures keep their one-line shape, `max-w` so a
      // sentence wraps instead of running off the screen. With a full
      // readout the panel takes a fixed width and a scroll of its own — the
      // breakdown is a dozen rows plus three lists, and a `w-max` panel over
      // those would be as wide as the longest MCP server name.
      panelClassName={
        metrics === null
          ? 'w-max max-w-[20rem]'
          : 'max-h-[26rem] w-[22rem] overflow-y-auto'
      }
      trigger={ring}>
      {/* The summary steps aside as soon as a breakdown is COMING, not once
          it has landed — and the difference is a reported bug.

          These are two different measurements of one window: the summary is
          the prompt side of the LAST REQUEST, the panel's header is the
          agent's own `/context` reply. Showing the first for the 1–3s the
          second takes, and then swapping it out in the same spot, reads as
          one figure correcting itself — measured on a real chat as `340.3k
          of 1M · 34%` becoming `487.5k of 1M · 49%` a beat later, with
          nothing in between to say the question had changed. "Agent context
          is jumping — first I see one number, and then when it loads full
          stats, another number."

          So the popover states ONE reading or none. While the first one is
          in flight it carries the loading line alone; a re-read keeps the
          previous BREAKDOWN on screen (`ContextPanel`), which is the same
          measurement and therefore moves rather than jumps. The summary is
          still the whole content where no breakdown is coming — no loader,
          no run, a CLI that has none to give, or a fetch that failed — since
          there it is not a placeholder for a different figure, it is the
          only figure there is. */}
      {metrics === null || (!metrics.loading && !metrics.data?.context)
        ? children
        : null}
      {metrics ? (
        <ContextPanel
          metrics={metrics.data}
          loading={metrics.loading}
          error={metrics.error}
          live={live}
        />
      ) : null}
    </HoverPopover>
  );
}

/** What one open readout knows about the chat it is reporting on. */
interface MetricsState {
  /**
   * Which chat this reading was taken from.
   *
   * Carried WITH the reading rather than assumed from the current props: the
   * component is not unmounted across a chat switch (the composer keeps one
   * meter and `activateRun` only swaps the run beneath it), so without this the
   * state that survives the switch is indistinguishable from a fresh one.
   */
  runId: string | null;
  data: ChatMetricsDto | null;
  loading: boolean;
  error: string | null;
}

/** A readout that knows nothing yet — the shape a chat starts on. */
const NO_READING: Omit<MetricsState, 'runId'> = {
  data: null,
  loading: false,
  error: null,
};

/**
 * Fetch a chat's metrics while the readout is OPEN, and never otherwise.
 *
 * On demand rather than polled, because the breakdown is a round trip to the
 * live CLI measured at 1.2–3.3s and it launches nothing — the daemon asks the
 * process the run already holds. Polling it would put a multi-second question
 * to the user's agent every few seconds for a panel nobody has opened.
 *
 * Re-fetched on every open rather than cached: a conversation's window is what
 * changes between two glances at it, so a remembered reading would answer the
 * question the user is asking now with the state it was in last time. The
 * previous reading STAYS on screen while the new one lands (see
 * {@link ContextPanel}), so the re-fetch costs no blank panel.
 *
 * Returns null when there is nothing to fetch — no loader in the tree, or a
 * meter with no run — so the caller keeps its summary and shows no panel at
 * all, rather than an empty one under a heading.
 */
function useChatMetrics(
  runId: string | null,
  open: boolean,
  live: boolean,
): MetricsState | null {
  const load = useContext(ChatMetricsLoaderContext);
  const [state, setState] = useState<MetricsState>({
    runId: null,
    ...NO_READING,
  });
  // Bumped by the live re-read timer below. A nonce rather than calling the
  // fetch from two places: one effect owns the request, so a re-read cannot
  // race the open-fetch or duplicate its cancellation.
  const [nonce, setNonce] = useState(0);
  useEffect(() => {
    // `live` is in the deps, so this ALSO fires the moment the turn settles —
    // which is exactly when the last turn's cost and token counts land, and it
    // costs no timer of its own.
    if (!open || !live || load === null || runId === null) {
      return;
    }
    const timer = setInterval(
      () => setNonce((value) => value + 1),
      LIVE_REREAD_MS,
    );
    return () => clearInterval(timer);
  }, [open, live, load, runId]);
  useEffect(() => {
    if (!open || load === null || runId === null) {
      return;
    }
    // The reply of a fetch whose panel has closed — or whose run has changed
    // under it — must not land in the new state. Without this, closing the
    // readout mid-request and reopening it on another chat showed the first
    // chat's window under the second chat's name. Named `current` rather than
    // `live`, which is now the working-agent PROP this effect also depends on.
    let current = true;
    setState((previous) =>
      // Re-reading the SAME chat keeps what is already on screen, so a refetch
      // costs no blank panel. A DIFFERENT chat keeps nothing: those figures
      // describe a conversation the user has left.
      previous.runId === runId
        ? { ...previous, loading: true, error: null }
        : { runId, ...NO_READING, loading: true },
    );
    void load(runId)
      .then((data) => {
        if (current) {
          setState({ runId, data, loading: false, error: null });
        }
      })
      .catch((err: unknown) => {
        if (current) {
          setState((previous) => ({
            ...previous,
            runId,
            loading: false,
            error: err instanceof Error ? err.message : String(err),
          }));
        }
      });
    return () => {
      current = false;
    };
    // `live` rides the deps so a settle takes one final reading; `nonce` is the
    // live re-read.
  }, [load, runId, open, live, nonce]);
  if (load === null || runId === null) {
    return null;
  }
  // The effect covers the switch it can SEE; this covers the one it cannot. It
  // is skipped entirely while the readout is closed, so a chat switched in the
  // meantime leaves the previous chat's reading in state until the next open —
  // and an effect runs after that open has painted, so without this the first
  // frame of the new chat's panel is the old chat's window, totals and spend,
  // with the summary suppressed alongside it. One frame rather than forever,
  // and the same wrong figures under the same wrong name.
  return state.runId === runId ? state : { runId, ...NO_READING };
}

/**
 * How full one agent's context window is, plus what the run has cost.
 *
 * EXTRACTED from the agents panel rather than written fresh: the panel already
 * rendered exactly this, and the header needed the same thing. One component
 * serving both is what makes them structurally incapable of disagreeing — the
 * defect was a header with no readout at all beside a panel that had one.
 *
 * The figures are DELIBERATELY not on screen while the window is known. A
 * header carrying `ctx 91.6k / 1M · 9%` next to a ring says the same thing
 * three times and crowds the row it sits in; the ring alone answers the only
 * question asked at a glance ("how much room is left"), and the numbers are one
 * hover — or one click, which pins the panel for a keyboard user — away.
 *
 * Renders nothing when there is nothing to say, so callers can place it
 * unconditionally.
 */
export function ContextMeter({
  contextTokens,
  contextWindowTokens,
  spentUsd = null,
  runId = null,
  side = 'bottom',
  live = false,
  awaitingReading = null,
  className,
}: {
  /** Prompt-side tokens of the latest request, or null when unknown. */
  contextTokens: number | null;
  /** The model's own window, or null when the CLI has not reported one. */
  contextWindowTokens: number | null;
  /** Total spend across the run's turns, or null to omit. */
  spentUsd?: number | null;
  /**
   * Which chat the expanded readout reports on, or null for a meter that has
   * only the summary to show.
   *
   * Optional because the summary stands alone and always has: a caller with no
   * run — or one rendered outside the loader's provider — gets exactly the
   * meter it got before.
   */
  runId?: string | null;
  /**
   * Which way the readout opens. `Popover` does no collision detection — its
   * placement is two static ternaries — so a caller near an edge has to say.
   *
   * The ring shows no figures by design, which makes this panel the only
   * readout a sighted pointer or keyboard user gets: clipped, there is nothing
   * left to read. (Screen-reader users are unaffected — the trigger carries the
   * whole reading in its `aria-label`.)
   *
   * Defaults to `bottom` so the agents-panel call site, which has room below,
   * is unchanged.
   */
  side?: 'top' | 'bottom';
  /**
   * Whether this chat's agent is working RIGHT NOW.
   *
   * What it buys is the readout following the turn instead of freezing on the
   * moment it was opened — see {@link LIVE_REREAD_MS} — and the thread line
   * saying that a turn is in flight rather than counting it as nothing.
   * Defaults false, so a caller that cannot know (the agents panel's per-node
   * meters) gets exactly the readout it had.
   */
  live?: boolean;
  /**
   * Why there is no reading, when the reason is worth drawing rather than
   * hiding: a compaction has just discarded the conversation the last figure
   * described, and nothing measures the replacement until the next message.
   *
   * REPORTED against the first cut of that fix, which simply withheld the
   * meter: "я на втором скриншоте у тебя сейчас вообще кружочку не вижу!". A
   * control that vanishes is indistinguishable from a broken one — the same
   * reading the effort and context-window chips are drawn by — and here it is
   * worse, because the ring is the one thing on the row a user watches climb.
   * So the ring is drawn EMPTY and says why.
   *
   * Null everywhere else: a chat that has simply not run a turn yet keeps the
   * absent meter, since "not measured" there is a moment rather than an event
   * anybody needs explained.
   */
  awaitingReading?: string | null;
  className?: string;
}): React.JSX.Element | null {
  // The model's OWN window, or NOTHING. A window of 0 is rejected here, not
  // just upstream: this is the ONE place that divides by it, and the result
  // ("Context Infinity% full") would land in the accessible name.
  //
  // There is deliberately no assumed fallback. Substituting a flat 200k made
  // the meter state a denominator nobody had reported — so a 1M-window model
  // read as a fifth full before it had said anything. When the window is
  // unknown the count is shown bare and the ring is withheld: "26k used" is
  // true, "26k / 200k · 13%" was not.
  const windowTokens =
    contextWindowTokens !== null && contextWindowTokens > 0
      ? contextWindowTokens
      : null;
  // An EMPTY ring rather than no ring — see {@link awaitingReading}. It needs
  // the window: with no denominator there is no gauge to draw, and the branch
  // below already has the right answer for that (the figures, bare).
  if (
    contextTokens === null &&
    awaitingReading !== null &&
    windowTokens !== null
  ) {
    return (
      <MeterReadout
        side={side}
        className={className}
        runId={runId}
        live={live}
        label={awaitingReading}
        ring={
          <ProgressRing
            fraction={0}
            size={14}
            // Muted, unlike every filled state: this is the absence of a
            // reading, and a green nought would read as an empty window —
            // which is a claim, and one nobody has measured.
            className="text-muted-foreground/60"
          />
        }>
        {/* WRAPS, unlike the reading below it: those are figures and this is a
            sentence, and held on one line it ran off the panel's edge. */}
        <span className="flex max-w-64 flex-col gap-0.5 text-xs text-muted-foreground">
          <span className="font-medium text-foreground">
            {formatTokens(windowTokens)} window
          </span>
          <span>{awaitingReading}</span>
          {spentUsd !== null ? (
            <span>{formatUsd(spentUsd)} spent across this run</span>
          ) : null}
        </span>
      </MeterReadout>
    );
  }
  if (contextTokens === null && spentUsd === null) {
    // Nothing to say: a turn that has yet to report anything, which is a
    // moment rather than a fact. The meter stays absent until it does.
    //
    // A second arm used to live here — a hollow ring carrying a sentence for
    // "a CLI that NEVER reports usage", fed from the daemon's per-adapter
    // usage capability. Its premise stopped being true of either shipped CLI:
    // claude answers over its control channel and cursor-agent's reading is
    // read out of that CLI's own session store, so both meters fill as soon as
    // a turn lands. What the sentence actually described was the absence of a
    // COST, so a cursor chat with no turns yet explained itself with "no cost
    // can be shown" while the context reading it was waiting for was simply on
    // its way — and the panel's own breakdown reason was already saying the
    // useful half ("send a message to take a fresh reading"). The daemon
    // capability is still published, so an agent that genuinely reports
    // neither can have this rebuilt against a true premise.
    return null;
  }

  // A reading with no window to scale it against. It keeps the RING — muted,
  // and at nought, exactly like the compaction branch above — rather than
  // collapsing to a line of text.
  //
  // REPORTED as "sometimes context circle is disappearing and instead i just
  // see something like ctx. 167k". Reproduced by clearing this machine's
  // remembered windows and opening a chat: claude reports the used side on
  // every `assistant` line and the WINDOW only on `result`, so until some turn
  // of that model has completed once, the first request has a numerator and no
  // denominator — measured live as `ctx 63.6k` for the whole of a first turn.
  // The old shape swapped one control for another mid-turn, which is what reads
  // as the meter breaking; a muted ring holds the composer's layout still and
  // says the same thing, and the figures are one hover away like every other
  // state's.
  //
  // Muted rather than filled for the compaction branch's own reason: a green
  // arc is a claim about how full the window is, and nobody has measured one
  // here. The count itself is not withheld — it is in the readout, where the
  // ring's figures always are.
  //
  // Testing the two INPUTS rather than a derived fraction is what narrows them
  // to numbers for the ring branch below; deriving first and testing that left
  // both operands nullable everywhere they are actually used.
  if (contextTokens === null || windowTokens === null) {
    const unscaled =
      contextTokens === null
        ? null
        : `${formatTokens(contextTokens)} used — this model's window has not been reported yet`;
    return (
      <MeterReadout
        side={side}
        className={className}
        runId={runId}
        live={live}
        label={unscaled ?? 'No context reading yet'}
        ring={
          <ProgressRing
            fraction={0}
            size={14}
            className="text-muted-foreground/60"
          />
        }>
        <span className="flex max-w-64 flex-col gap-0.5 text-xs text-muted-foreground">
          {contextTokens !== null ? (
            <span className="font-medium text-foreground">
              ctx {formatTokens(contextTokens)}
            </span>
          ) : null}
          {unscaled !== null ? (
            <span>
              The window arrives with this model’s first completed turn.
            </span>
          ) : null}
          {spentUsd !== null ? (
            <span>{formatUsd(spentUsd)} spent across this run</span>
          ) : null}
        </span>
      </MeterReadout>
    );
  }

  const fraction = contextTokens / windowTokens;
  const percent = Math.round(fraction * 100);
  return (
    <MeterReadout
      side={side}
      className={className}
      runId={runId}
      live={live}
      // Deliberately still the bare reading, with no "which measurement"
      // qualifier: this is the control's accessible NAME, and a name that
      // explains itself stops being one — it is announced on every focus, and
      // it is what a screen-reader user navigates by. The distinction between
      // this fraction (the prompt side of the last request) and the panel's
      // (the agent's own `/context` reply) is stated in the panel, as TEXT, so
      // it reaches that user through the same route as the figures it explains.
      label={
        `Context ${percent}% full — ${formatTokens(contextTokens)} of ${formatTokens(windowTokens)}` +
        (spentUsd === null ? '' : `, ${formatUsd(spentUsd)} spent`)
      }
      ring={
        <ProgressRing
          fraction={fraction}
          // Sized to sit INSIDE a line of 12px text rather than beside it.
          // With the percentage gone from the middle the arc frames no glyphs,
          // so it can read as a gauge; at 18px it was still setting the height
          // of every row it shared — which is what pushed the agent card's
          // context readout onto a line of its own.
          size={14}
          // No `label`, unlike every other use: the button around it already
          // carries the reading as its accessible name, and labelling both makes
          // a screen reader announce the figure twice.
          className={cn(
            fraction >= ALARM_AT
              ? 'text-destructive'
              : fraction >= WARN_AT
                ? 'text-warning'
                : 'text-success',
          )}
        />
      }>
      <span className="flex flex-col gap-0.5 text-xs whitespace-nowrap text-muted-foreground">
        <span className="font-medium text-foreground">
          {formatTokens(contextTokens)} / {formatTokens(windowTokens)}
        </span>
        <span>{percent}% of the model&rsquo;s context window</span>
        {spentUsd !== null ? (
          <span>{formatUsd(spentUsd)} spent across this run</span>
        ) : null}
      </span>
    </MeterReadout>
  );
}
