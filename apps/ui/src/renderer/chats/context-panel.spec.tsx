// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import type { ChatMetricsDto } from '../autogenerated';
import { ContextPanel } from './context-panel';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root;
let container: HTMLDivElement;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function render(el: React.JSX.Element): void {
  act(() => root.render(el));
}

/** Metrics holding all three foldable groups, which is what this file is about. */
function metrics(): ChatMetricsDto {
  return {
    context: {
      categories: [
        { name: 'System prompt', tokens: 5_700, deferred: false },
        { name: 'Skills', tokens: 6_500, deferred: true },
      ],
      totalTokens: 196_700,
      maxTokens: 1_000_000,
      model: 'claude-opus-5',
      autoCompactAtTokens: 967_000,
      autoCompactEnabled: true,
      memoryFiles: [{ path: 'CLAUDE.md', kind: 'project', tokens: 12_600 }],
      servers: [
        {
          name: 'codegraph',
          tokens: 123_200,
          toolCount: 12,
          loadedToolCount: 12,
        },
      ],
    },
    breakdownReason: null,
    plan: null,
    planReason: null,
    takenAt: new Date().toISOString(),
    planTakenAt: null,
    totals: {
      turns: 3,
      costedTurns: 3,
      costUsd: 1.5,
      inputTokens: 100,
      outputTokens: 200,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      thinkingTokens: null,
      workedMs: 1_000,
    },
  };
}

describe('the folded group headers', () => {
  it('sets its own type, because a button does not inherit the panel’s', () => {
    // REPORTED as "we should reduce font size for groups and their counts in
    // bottom". Measured in the running app before the fix: 15px on these three
    // headings against 11.25px on every row under them, because a `<button>`
    // takes the app's base size rather than the container's `text-xs`.
    //
    // Asserted on the CLASS rather than a computed size: jsdom applies no
    // stylesheet, so `getComputedStyle` would report the same thing with the
    // fix reverted. The class is what carries the size here, and its absence
    // IS the defect.
    render(<ContextPanel metrics={metrics()} loading={false} error={null} />);

    const headers = [
      ...container.querySelectorAll<HTMLElement>('button[aria-expanded]'),
    ];

    // All three groups are present, so this cannot pass by finding none.
    expect(headers).toHaveLength(3);
    for (const header of headers) {
      expect(header.className).toContain('text-xs');
      // Still a HEADING — by weight and colour, which is what the size was
      // doing badly.
      expect(header.querySelector('span')?.className).toContain('font-medium');
    }
  });
});

describe('the plan limits', () => {
  const PLAN = {
    plan: 'team',
    windows: [
      {
        key: 'session',
        label: 'Current session',
        percent: 96,
        resetsAt: null,
      },
    ],
    estimated: false,
  };

  it('holds the section with a loader while the first reading is on its way', () => {
    // REPORTED as "if they are not loaded yet, there should be some loader".
    // Nothing had arrived, so the panel had no plan section at all until the
    // answer landed — then one appeared and shoved the rest down.
    render(<ContextPanel metrics={null} loading={true} error={null} />);

    const holder = container.querySelector('[data-slot="plan-limits-loading"]');
    expect(holder?.textContent).toContain('Plan limits');
    expect(holder?.getAttribute('aria-busy')).toBe('true');
    // The breakdown's own wait is said too, at the top.
    expect(
      container.querySelector('[data-slot="context-loading"]'),
    ).not.toBeNull();
  });

  it('keeps the limits on screen during a re-read, marked as refreshing', () => {
    render(
      <ContextPanel
        metrics={{ ...metrics(), plan: PLAN, planTakenAt: null }}
        loading={true}
        error={null}
      />,
    );

    const section = container.querySelector('[data-slot="plan-limits"]');
    expect(section?.textContent).toContain('96%');
    expect(section?.getAttribute('aria-busy')).toBe('true');
    expect(
      container.querySelector('[data-slot="plan-limits-loading"]'),
    ).toBeNull();
  });

  it('dates a reading another chat took minutes ago, and not one taken now', () => {
    const old = new Date(Date.now() - 5 * 60_000).toISOString();
    render(
      <ContextPanel
        metrics={{ ...metrics(), plan: PLAN, planTakenAt: old }}
        loading={false}
        error={null}
      />,
    );
    expect(
      container.querySelector('[data-slot="plan-limits"]')?.textContent,
    ).toContain('Updated 5m ago');

    render(
      <ContextPanel
        metrics={{
          ...metrics(),
          plan: PLAN,
          planTakenAt: new Date().toISOString(),
        }}
        loading={false}
        error={null}
      />,
    );
    expect(
      container.querySelector('[data-slot="plan-limits"]')?.textContent,
    ).not.toContain('Updated');
  });

  it('says when the figures are only the CLI’s estimate', () => {
    render(
      <ContextPanel
        metrics={{
          ...metrics(),
          plan: { ...PLAN, estimated: true },
          planTakenAt: null,
        }}
        loading={false}
        error={null}
      />,
    );
    expect(
      container.querySelector('[data-slot="plan-limits-estimated"]'),
    ).not.toBeNull();
  });
});
