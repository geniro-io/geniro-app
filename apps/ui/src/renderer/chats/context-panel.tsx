import type {
  ChatMetricsDto,
  ContextBreakdown,
  PlanLimits,
} from '../autogenerated';
import { ErrorText } from '../components/error-text';
import { cn } from '../components/ui/utils';
import { formatTokens, formatUsd } from './agent-activity';
import { contextCategoryColor, formatTimeUntil } from './chat-metrics';
import { shortenPath } from './directory-select';
import { formatDuration } from './turn-duration';

/**
 * The readout behind the context ring: what this chat's window HOLDS, and what
 * the thread has cost.
 *
 * The ring answers "how much room is left" at a glance and nothing about what
 * filled it, which is the whole of the report this replaces — a user looking at
 * `9%` and asking for the statistics their CLI's own `/context` prints. The
 * two facts people actually act on are invisible without it: a CLAUDE.md
 * costing 46k tokens, and one MCP server holding 109k of the 274k tool surface.
 *
 * Presentational and pure. Every figure is the daemon's — nothing is derived
 * here beyond bar widths, because a percentage this component computed could
 * disagree with the one the CLI reported.
 */
export function ContextPanel({
  metrics,
  loading,
  error,
  live = false,
}: {
  /** Null until the first fetch lands. */
  metrics: ChatMetricsDto | null;
  loading: boolean;
  /** Why the fetch failed, or null. */
  error: string | null;
  /**
   * Whether the agent is working right now.
   *
   * The thread's figures are summed from turns that have FINISHED, so a turn in
   * flight contributes nothing to them — which read as `0 turns` under a live
   * context reading while the agent was visibly working, and as an unchanged
   * cost for as long as the turn lasted. The count is not faked here (a running
   * turn's cost is genuinely unknown until the CLI reports it); it is NAMED.
   */
  live?: boolean;
}): React.JSX.Element {
  return (
    // Ordered by what a reader came for, not by where the figures came from.
    // The two HEADLINE readings lead — how full this window is, and how much of
    // the account's allowance is left — and the itemization that explains the
    // first comes after both.
    //
    // The reported bug is what the old order did to the second one. The panel
    // is a 26rem scroll box, and the plan limits sat under every drill-down
    // section: the deferred rows, one row per instruction file, and one row per
    // MCP SERVER. On a machine with twelve servers that is a screen and a half
    // above them, and the popover's own bottom edge reads as the end of the
    // content — so "the weekly-limits feature — I open it on claude and see
    // nothing" was a section that had been pushed off the visible panel. The
    // limits are also the item with the shortest shelf life on here: a window
    // breakdown keeps until the next turn, an allowance is the thing about to
    // stop the conversation.
    <div className="flex flex-col gap-3 text-xs">
      {metrics?.context ? <Breakdown context={metrics.context} /> : null}
      {metrics && !metrics.context && metrics.breakdownReason ? (
        <p className="text-muted-foreground">{metrics.breakdownReason}</p>
      ) : null}
      {metrics?.plan ? <Plan plan={metrics.plan} /> : null}
      {/* The reason is shown only where the limits would have been: a workflow
          run and a CLI with no such channel both get a sentence rather than a
          missing section, which is the rule the breakdown above follows. */}
      {metrics && !metrics.plan && metrics.planReason ? (
        <div className="flex flex-col gap-0.5 border-t border-border pt-2">
          <span className="font-medium text-foreground">Plan limits</span>
          <span className="text-muted-foreground">{metrics.planReason}</span>
        </div>
      ) : null}
      {metrics ? <Totals totals={metrics.totals} live={live} /> : null}
      {metrics?.context ? <ContextDetail context={metrics.context} /> : null}
      {/* Kept BELOW whatever has already arrived rather than replacing it: a
          refetch on a panel the user is reading must not blank the figures
          they are mid-sentence about. */}
      {loading ? (
        <p className="text-muted-foreground">
          Reading the agent&rsquo;s context…
        </p>
      ) : null}
      {/* `ErrorText`, not a hand-rolled `<p>`: it carries `role="alert"`, and
          this error is set ASYNCHRONOUSLY on a panel the user already has open.
          The only role anywhere above it is the popover's own `dialog`, so
          without a live region a failed fetch is announced to nobody — silence
          where the sighted user gets a red line. `text-xs` keeps the panel's
          scale, which the component forwards. */}
      {error ? <ErrorText className="text-xs">{error}</ErrorText> : null}
    </div>
  );
}

function Breakdown({
  context,
}: {
  context: ContextBreakdown;
}): React.JSX.Element {
  // Deferred rows are OUTSIDE the CLI's own total (its tool surface is
  // available, not loaded), so they are drawn in their own section rather than
  // in the bar — one live reading had 274k deferred against a 98k total, which
  // in one bar would report a window nearly four times fuller than it is.
  const loaded = context.categories.filter((row) => !row.deferred);
  const used =
    context.totalTokens ?? loaded.reduce((sum, row) => sum + row.tokens, 0);
  const window = context.maxTokens;
  const free = window === null ? null : Math.max(0, window - used);
  // Rounded the way the ring's label rounds it — which is as close as the two
  // readings get, because they are not the same measurement. This one is the
  // agent's own `/context` reply; the ring's fraction is the prompt side of the
  // LAST REQUEST (`promptSideTokens`, via `agents[0].contextTokens`). They can
  // legitimately disagree by more than a point, so the ring can sit green while
  // this reads past the warn mark.
  //
  // Not unified, and not by oversight: the ring has to render while the panel
  // is CLOSED, and the `/context` reply is a multi-second question put to the
  // live agent only on open. There is no reading available to the ring that the
  // panel could share. What is fixable is saying which is which, hence the
  // labels below.
  const percent =
    window === null || window <= 0 ? null : Math.round((used / window) * 100);
  return (
    <div className="flex flex-col gap-2">
      <div className="flex items-baseline gap-1.5">
        <span className="text-sm font-medium text-foreground">
          {formatTokens(used)}
        </span>
        {window === null ? null : (
          <span className="text-muted-foreground">
            of {formatTokens(window)}
            {percent === null ? null : ` · ${percent}%`}
          </span>
        )}
        {context.model ? (
          <span className="ml-auto truncate text-muted-foreground">
            {context.model}
          </span>
        ) : null}
      </div>
      {/* The reading is NAMED, in TEXT rather than a `title`: the ring above it
          is a different measurement, so a user comparing the two figures needs
          to know which is which — and a tooltip says that to a pointer alone,
          which is the same gap `ErrorText` was brought in to close two blocks
          down. The ring's own `aria-label` carries the reciprocal sentence.

          WORDED FOR EVERY CLI, which it was not: it said "/context" and "the
          ring measures the last request", both of which describe claude alone.
          An ACP agent has no such command — cursor's figures are read out of
          its own session store — and since that reading now rides the turn it
          IS what the ring draws, so the old sentence told a cursor user the two
          measured different things when they measure the same one. What is
          still true of both, and is the whole reason the note exists, is WHEN
          each was taken. */}
      <p className="text-[11px] text-muted-foreground">
        Reported by the agent&rsquo;s own accounting, re-read each time this
        opens. The ring carries the last turn&rsquo;s reading, so the two can
        differ.
      </p>
      {/* One bar, segments proportional to the WINDOW where there is one — so
          the empty tail is the room left, which is the thing being asked
          about. Without a window there is no denominator, and the segments are
          proportional to what is used instead. */}
      <div className="flex h-1.5 w-full overflow-hidden rounded-full bg-muted">
        {loaded.map((row, index) => (
          <span
            key={row.name}
            className={cn('h-full', contextCategoryColor(index))}
            style={{ width: `${share(row.tokens, window ?? used)}%` }}
          />
        ))}
      </div>
      <ul className="flex flex-col gap-0.5">
        {loaded.map((row, index) => (
          <li key={row.name} className="flex items-center gap-1.5">
            <span
              className={cn(
                'size-2 shrink-0 rounded-full',
                contextCategoryColor(index),
              )}
            />
            <span className="truncate text-foreground">{row.name}</span>
            <span className="ml-auto shrink-0 tabular-nums text-muted-foreground">
              {formatTokens(row.tokens)}
            </span>
          </li>
        ))}
        {free === null ? null : (
          <li className="flex items-center gap-1.5">
            <span className="size-2 shrink-0 rounded-full bg-muted" />
            <span className="truncate text-muted-foreground">Free space</span>
            <span className="ml-auto shrink-0 tabular-nums text-muted-foreground">
              {formatTokens(free)}
            </span>
          </li>
        )}
      </ul>
      {context.autoCompactEnabled && context.autoCompactAtTokens !== null ? (
        <p className="text-muted-foreground">
          Auto-compacts at {formatTokens(context.autoCompactAtTokens)}
        </p>
      ) : null}
    </div>
  );
}

/**
 * What is IN the window, itemized — the drill-down behind {@link Breakdown}'s
 * bar.
 *
 * Split out of it so the panel can put the two headline readings first and this
 * after them: these three sections are open-ended (one row per instruction
 * file, one per MCP server) and on a well-equipped machine they are longer than
 * the popover, which is what buried the plan limits under them. See the comment
 * on {@link ContextPanel}'s container.
 */
function ContextDetail({
  context,
}: {
  context: ContextBreakdown;
}): React.JSX.Element | null {
  const deferred = context.categories.filter((row) => row.deferred);
  if (
    deferred.length === 0 &&
    context.memoryFiles.length === 0 &&
    context.servers.length === 0
  ) {
    return null;
  }
  return (
    <>
      {deferred.length > 0 ? (
        <Section
          title="Available, not loaded"
          // Said out loud because the figures are large and would otherwise
          // read as part of the window: this is what the agent COULD pull in.
          caption="costs nothing until the agent searches for one"
          rows={deferred.map((row) => ({
            key: row.name,
            label: row.name,
            value: formatTokens(row.tokens),
          }))}
        />
      ) : null}
      {context.memoryFiles.length > 0 ? (
        <Section
          title="Instructions"
          rows={context.memoryFiles.map((file) => ({
            key: file.path,
            // Two segments, not the menu rows' three: three `CLAUDE.md` files
            // are told apart by their parent directory, and this panel is
            // 22rem.
            label: shortenPath(file.path, 2),
            // The full path on hover: the panel is 22rem and these are long,
            // but which of three CLAUDE.md files this is matters.
            title: file.path,
            value: formatTokens(file.tokens),
          }))}
        />
      ) : null}
      {context.servers.length > 0 ? (
        <Section
          title="MCP servers"
          rows={context.servers.map((server) => ({
            key: server.name,
            label: server.name,
            title: `${server.toolCount} tools, ${server.loadedToolCount} loaded`,
            value: formatTokens(server.tokens),
          }))}
        />
      ) : null}
    </>
  );
}

/**
 * What the ACCOUNT behind this chat is allowed, and how much is left.
 *
 * The thing that actually stops a conversation, and the one figure the app
 * could not previously say anything about — a user hitting a limit mid-turn
 * learned it from the CLI's own refusal. It belongs in THIS panel because it is
 * the same question the ring asks one scale up: the window bounds a
 * conversation, the plan bounds the day.
 *
 * Per chat, and that is not a technicality — a run carries its own config
 * directory, so the thread beside this one can be a different account on a
 * different plan. One figure in the app header would be describing whichever
 * was asked last.
 *
 * Every window the CLI reported is drawn, not just the shortest: a five-hour
 * window refills over lunch while a seven-day one does not, so showing only the
 * first tells a user they have room on the day they are about to be cut off.
 */
function Plan({ plan }: { plan: PlanLimits }): React.JSX.Element {
  // Read ONCE for the whole block rather than per row, so three windows cannot
  // be counted down from three different moments. The panel is fetched on open
  // and never polled, so this is the moment the reading itself describes.
  const now = Date.now();
  return (
    <div className="flex flex-col gap-1.5 border-t border-border pt-2">
      <div className="flex items-baseline gap-1.5">
        <span className="font-medium text-foreground">Plan limits</span>
        {plan.plan === null ? null : (
          // The CLI's own word for the subscription, cased as a plan name
          // rather than reworded into one: 'max' is what it said.
          <span className="ml-auto shrink-0 uppercase text-muted-foreground">
            {plan.plan}
          </span>
        )}
      </div>
      <ul className="flex flex-col gap-1.5">
        {plan.windows.map((row) => {
          const until = formatTimeUntil(row.resetsAt, now);
          return (
            <li
              key={row.key}
              data-plan-window={row.key}
              className="flex flex-col gap-1">
              <div className="flex items-baseline gap-1.5">
                <span className="truncate text-foreground">{row.label}</span>
                <span className="ml-auto shrink-0 tabular-nums text-muted-foreground">
                  {row.percent}%{until === null ? '' : ` · resets in ${until}`}
                </span>
              </div>
              {/* The same 1.5px track the window breakdown uses, so the two
                  readings on one panel read as the same kind of measurement.
                  One segment, because a plan window has no parts. */}
              <div className="h-1.5 w-full overflow-hidden rounded-full bg-muted">
                <span
                  className="block h-full bg-primary"
                  style={{ width: `${row.percent}%` }}
                />
              </div>
            </li>
          );
        })}
      </ul>
    </div>
  );
}

function Totals({
  totals,
  live,
}: {
  totals: ChatMetricsDto['totals'];
  live: boolean;
}): React.JSX.Element {
  const parts = [
    totals.costUsd === null ? null : formatUsd(totals.costUsd),
    // A turn in flight is STATED rather than counted, and it replaces the count
    // outright while there is nothing to count — `0 turns` is the one reading
    // that is both technically true and read by everyone as "this is broken",
    // since it appears under a live window on a thread that is plainly working.
    // Once a turn has finished the count leads and the running one trails it,
    // so no figure is ever lost to the phrase.
    totals.turns === 0
      ? live
        ? 'turn in progress'
        : '0 turns'
      : `${totals.turns} ${totals.turns === 1 ? 'turn' : 'turns'}${
          live ? ' · 1 in progress' : ''
        }`,
    totals.workedMs === null
      ? null
      : `worked ${formatDuration(totals.workedMs)}`,
  ].filter((part): part is string => part !== null);
  const tokens = [
    totals.inputTokens === null
      ? null
      : `in ${formatTokens(totals.inputTokens)}`,
    totals.outputTokens === null
      ? null
      : `out ${formatTokens(totals.outputTokens)}`,
    totals.thinkingTokens === null
      ? null
      : `thinking ${formatTokens(totals.thinkingTokens)}`,
    totals.cacheReadTokens === null
      ? null
      : `cache read ${formatTokens(totals.cacheReadTokens)}`,
    totals.cacheCreationTokens === null
      ? null
      : `cached ${formatTokens(totals.cacheCreationTokens)}`,
  ].filter((part): part is string => part !== null);
  return (
    <div className="flex flex-col gap-0.5 border-t border-border pt-2">
      <span className="font-medium text-foreground">This thread</span>
      <span className="text-muted-foreground">{parts.join(' · ')}</span>
      {tokens.length > 0 ? (
        <span className="text-muted-foreground">{tokens.join(' · ')}</span>
      ) : null}
    </div>
  );
}

/** A titled list of label/value rows — the panel's three secondary blocks. */
function Section({
  title,
  caption,
  rows,
}: {
  title: string;
  caption?: string;
  rows: { key: string; label: string; title?: string; value: string }[];
}): React.JSX.Element {
  return (
    <div className="flex flex-col gap-0.5 border-t border-border pt-2">
      <span className="font-medium text-foreground">{title}</span>
      {caption ? (
        <span className="text-[11px] text-muted-foreground">{caption}</span>
      ) : null}
      <ul className="flex flex-col gap-0.5">
        {rows.map((row) => (
          <li key={row.key} className="flex items-center gap-1.5">
            <span className="truncate text-muted-foreground" title={row.title}>
              {row.label}
            </span>
            <span className="ml-auto shrink-0 tabular-nums text-muted-foreground">
              {row.value}
            </span>
          </li>
        ))}
      </ul>
    </div>
  );
}

/**
 * One segment's width as a percentage.
 *
 * Clamped at both ends: a zero denominator would produce `Infinity%`, and a
 * category the CLI reports as larger than the window (which the arithmetic
 * allows — deferred rows are excluded from the total, not from reality) would
 * push every other segment off the bar.
 */
function share(tokens: number, of: number): number {
  if (of <= 0) {
    return 0;
  }
  return Math.min(100, Math.max(0, (tokens / of) * 100));
}
