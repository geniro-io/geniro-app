import { Maximize2 } from 'lucide-react';

import type {
  AgentContextWindow,
  AgentContextWindowUnavailableKind,
} from '../autogenerated';
import { Chip } from '../components/ui/chip';
import { Select } from '../components/ui/select';
import { formatTokens } from './agent-activity';

/**
 * Sentinel for "ask for no particular size" — a distinct value rather than
 * `''`, for the same reason {@link CLI_DEFAULT_EFFORT} is: the menu needs a row
 * it can check, and an empty option value reads as "nothing selected".
 */
export const MODEL_DEFAULT_CONTEXT_WINDOW = '__default__';

/**
 * The MENU row's label for {@link MODEL_DEFAULT_CONTEXT_WINDOW} — "let the
 * model decide", which is a choice and has to read as one beside the sizes.
 *
 * The CHIP does not show this. See {@link ContextWindowSelect}'s `windowTokens`.
 */
const DEFAULT_ROW_LABEL = 'model default';

/**
 * What the CHIP says when nothing is picked and nothing has been measured.
 *
 * REPORTED as "вместо Default Window, потому что это слишком длинно, может
 * быть, сразу значение дефолтное туда поставим". Two words became one, and the
 * one that went is the one the leading icon already draws.
 */
const DEFAULT_CHIP_LABEL = 'default';

/** The inert-chip label for `unavailableKind: 'no-model'`. */
const NO_MODEL_LABEL = 'pick a model';

/**
 * The context-window chip: which of the model's window sizes a turn runs at.
 *
 * REPORTED as "cursor also has a model size, that is 1 million, 300k … I
 * should be able to select it everywhere". It is the same shape as the effort
 * chip because it is the same kind of thing — a per-MODEL parameter whose
 * vocabulary belongs to the CLI — and it is deliberately ONE component for
 * every surface (the composer, a saved run configuration, a graph node), so
 * the rows, the default sentinel and the add-back row below cannot drift
 * between three copies.
 *
 * THE NUMBERS ARE THE CLI's OWN. Nothing here maps `1m` to a token count: the
 * count that matters is the one the agent then reports about its own window,
 * which the context meter already draws from the CLI's accounting — a table
 * here would be a second answer to that question with nothing keeping the two
 * in step. (Measured end to end: `1m` makes cursor report a 1,000,000-token
 * window, `300k` a 300,000-token one, on the same model and the same prompt.)
 *
 * WITH NO SIZES IT IS STILL THE PICKER, reading the window the turn does in
 * fact run at — {@link windowTokens} when the CLI has reported one, else the
 * bare word `default`. It was an INERT chip labelled `one window`,
 * and that is the shape this rewrite exists to remove: on claude, which has no
 * such axis at all, every model shows it, so the commonest rendering of this
 * control was a dead grey word that answers nothing and cannot be pressed
 * ("we need to keep it as default then if there is no other options … it
 * shouldn't be just inactive button like that"). One rendering for every
 * model is also what stops the row rearranging itself as the model changes:
 * the chip keeps its shape and its vocabulary, and only the rows behind it
 * differ. The daemon's sentence is not dropped with the label — it is the
 * chip's hover title AND the open menu's own note, which is where the four
 * cases (no model yet, no such axis, one fixed size, the CLI could not be
 * asked) are told apart in words. Both, because they answer for different
 * readers: the title serves someone who never opens the control, and the note
 * serves someone who did — reported as "it didnt load contexts for cursor",
 * where the panel offered its single `model default` row and said nothing, and
 * the model in question (`kimi-k3`) does in fact have one fixed window.
 *
 * The ONE case that is still inert is `no-model`, and it says `pick a model`:
 * nothing has been asked yet, so there is no default window to report either —
 * a picker there would offer the user a row standing for a model nobody has
 * chosen. Which case it is comes from `unavailableKind`, never from reading
 * the sentence: the prose is what a USER reads, so recognising a case by
 * matching those words means improving the wording silently changes what the
 * control says.
 */
export function ContextWindowSelect({
  windows,
  value,
  nextTurnOnly = false,
  unavailableReason,
  unavailableKind,
  windowTokens = null,
  onChange,
  className,
  variant = 'ghost',
  id,
}: {
  windows: AgentContextWindow[];
  /** The chosen size, or null for the model's own default. */
  value: string | null;
  /** A turn is running — this pick lands on the NEXT one. */
  nextTurnOnly?: boolean;
  /**
   * Why there are no sizes to choose from, from the daemon. Becomes the chip's
   * hover title when {@link windows} is empty; `null` means there IS a picker
   * (so this is never read) and `undefined` means the answer has not landed.
   */
  unavailableReason?: string | null;
  /**
   * WHICH case {@link unavailableReason} describes. Only `no-model` renders
   * differently — as the one inert chip; everything else keeps the picker at
   * the model's own default.
   */
  unavailableKind?: AgentContextWindowUnavailableKind | null;
  /**
   * The window the CLI itself reported for the model this run is on, in tokens
   * — what the context meter's own denominator is drawn from.
   *
   * Shown on the CHIP in place of the word `default`, which is the reported
   * "вместо Default Window … может быть, сразу значение дефолтное туда
   * поставим": the chip's job is to say what this turn runs at, and a measured
   * `1M` says it in two characters where `default window` took fourteen.
   *
   * It is read from the SAME reading the ring draws (the agent's own
   * accounting) rather than from a table mapping `1m` to a number — this file's
   * standing rule, and the reason the two can never disagree about one model.
   *
   * Null wherever nothing has measured it: a thread with no turn yet, the
   * builder's node inspector, a saved configuration. Those keep the word.
   */
  windowTokens?: number | null;
  onChange: (contextWindow: string | null) => void;
  className?: string;
  /**
   * `ghost` is the composer's flat chip, `default` the bordered form field the
   * graph builder's node inspector and the run-configuration editor use.
   */
  variant?: 'ghost' | 'default';
  /** Ties the form-field variant to its `Field` label. */
  id?: string;
}): React.JSX.Element | null {
  if (windows.length === 0) {
    // No report yet: a chip whose only explanation is still in flight would
    // read as a control that is simply broken.
    if (!unavailableReason) {
      return null;
    }
    if (unavailableKind === 'no-model') {
      return (
        <Chip tone="muted" className={className} title={unavailableReason}>
          <Maximize2 aria-hidden="true" />
          {NO_MODEL_LABEL}
        </Chip>
      );
    }
  }
  /**
   * The daemon's sentence when there is nothing to choose from — the chip's
   * hover title in place of the plain name, since "why can I not pick a size
   * here" is the only question left once the rows are gone. Null whenever
   * there ARE rows, where it is not read at all.
   */
  const fixedReason = windows.length === 0 ? unavailableReason : null;
  const known = windows.some((window) => window.id === value);
  // A size the CURRENT model does not offer — a chat carried over to another
  // model, or a workflow node whose model changed under it. Always model-
  // specific here (there is no CLI-wide union of window sizes), so the row is
  // added back DISABLED rather than dropped: the value is still stored, and
  // hiding it would leave nothing on screen naming what the chip's silent
  // "default window" fallback is covering for.
  const refused = value !== null && !known;
  const rows = [
    ...windows.map((window) => ({ value: window.id, label: window.label })),
    ...(refused
      ? [{ value, label: value, disabled: true, hint: 'unavailable' }]
      : []),
  ];
  return (
    <Select
      variant={variant}
      id={id}
      aria-label="Context window"
      title={
        fixedReason ??
        (nextTurnOnly
          ? 'Context window — applies to your next message'
          : 'Context window')
      }
      className={className}
      leadingIcon={<Maximize2 />}
      // The chip states the window; the MENU states the choice. They are
      // different sentences and this is where they part: with nothing picked
      // the chip reads `1M` — what the turn runs at — while the menu's own row
      // still reads `model default`, which is what you would be choosing. A
      // single label cannot be both, and `triggerLabel` exists for exactly this
      // kind of split.
      triggerLabel={
        (refused ? null : value) === null
          ? windowTokens !== null && windowTokens > 0
            ? formatTokens(windowTokens)
            : DEFAULT_CHIP_LABEL
          : undefined
      }
      // What the chip SHOWS when the model does not take the stored size: the
      // default, which is what the turn will actually run at. Showing the
      // stored word would claim a window the agent cannot reach.
      value={(refused ? null : value) ?? MODEL_DEFAULT_CONTEXT_WINDOW}
      groups={[
        { items: rows },
        {
          // The daemon's sentence, IN the menu — not only on the trigger's
          // hover title, which is where it used to live alone. With no sizes to
          // offer, the panel is one `model default` row and nothing else, and a
          // one-row picker that says nothing about why reads as a control that
          // failed to fetch: reported as "it didnt load contexts for cursor"
          // against `kimi-k3`, a model that genuinely runs at one fixed window
          // (measured — its own handshake enumerates `reasoning` and no
          // `context` parameter, while `claude-opus-5` on the same account and
          // build enumerates `context = 300k|1m`). The answer was right and
          // only the rendering was silent.
          //
          // The title stays too: the reason belongs to the CHIP as much as to
          // the open panel, and a reader who never opens it is owed it.
          note: fixedReason ?? undefined,
          items: [
            { value: MODEL_DEFAULT_CONTEXT_WINDOW, label: DEFAULT_ROW_LABEL },
          ],
        },
      ]}
      onValueChange={(next) =>
        onChange(next === MODEL_DEFAULT_CONTEXT_WINDOW ? null : next)
      }
    />
  );
}
