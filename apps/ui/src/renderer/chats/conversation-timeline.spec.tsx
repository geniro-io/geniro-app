// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ChatTimelineMarker, ChatTotals } from '../autogenerated';
import { ConversationTimeline } from './conversation-timeline';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const NOTHING_MEASURED: ChatTotals = {
  turns: 0,
  costedTurns: 0,
  costUsd: null,
  inputTokens: null,
  outputTokens: null,
  cacheReadTokens: null,
  cacheCreationTokens: null,
  thinkingTokens: null,
  workedMs: null,
};

function marker(
  seq: number,
  preview: string,
  segment: Partial<ChatTimelineMarker['segment']> = {},
): ChatTimelineMarker {
  return {
    seq,
    createdAt: '2026-09-07T12:00:00.000Z',
    preview,
    segment: {
      aiMessages: 0,
      elapsedMs: null,
      totals: NOTHING_MEASURED,
      ...segment,
    },
  };
}

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function render(
  markers: readonly ChatTimelineMarker[],
  onJump = vi.fn(),
  partialReason: string | null = null,
): { onJump: ReturnType<typeof vi.fn> } {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <ConversationTimeline
        markers={markers}
        partialReason={partialReason}
        onJump={onJump}
      />,
    );
  });
  return { onJump };
}

/** The header icon that opens the panel. */
const trigger = (): HTMLButtonElement | null =>
  document.body.querySelector<HTMLButtonElement>(
    '[aria-label="Conversation timeline"]',
  );

function open(): void {
  act(() => {
    trigger()!.click();
  });
}

// The panel is portalled out of `container`, so every read is against the
// document rather than the mount point.
const panel = (): HTMLElement | null =>
  document.body.querySelector<HTMLElement>(
    '[data-slot="conversation-timeline"]',
  );

const markerButtons = (): HTMLButtonElement[] =>
  Array.from(
    document.body.querySelectorAll<HTMLButtonElement>(
      '[data-slot="timeline-marker"]',
    ),
  );

const segmentText = (): string[] =>
  Array.from(
    document.body.querySelectorAll<HTMLElement>(
      '[data-slot="timeline-segment"]',
    ),
  ).map((el) => el.textContent ?? '');

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

describe('ConversationTimeline', () => {
  it('offers no control at all for a conversation with no user messages', () => {
    // Omitted, never disabled — the rule the header's other actions follow. A
    // greyed control says the feature is broken; the truth is this thread has
    // nothing to navigate yet.
    render([]);

    expect(trigger()).toBe(null);
  });

  it('keeps the timeline behind the icon until it is asked for', () => {
    // The whole reason it is a panel: it costs nothing until opened, where the
    // strip it replaced took height off every transcript whether or not anyone
    // was navigating.
    render([marker(1, 'first ask')]);

    expect(trigger()).not.toBe(null);
    expect(panel()).toBe(null);
  });

  it('draws one node per user message, in the transcript order', () => {
    // Oldest at the top, like the conversation itself — so the timeline maps
    // onto what is on screen rather than asking the reader to invert it.
    render([marker(1, 'first ask'), marker(4, 'second ask')]);
    open();

    expect(markerButtons().map((b) => b.textContent)).toEqual([
      'first ask',
      'second ask',
    ]);
  });

  it('hands the message SEQ to the jump, which is what addresses a row', () => {
    // The seq is the anchor `useTranscriptJump.jumpToSeq` resolves — an index
    // would address the wrong row on any thread whose timeline is not the whole
    // transcript.
    const { onJump } = render([marker(1, 'first'), marker(42, 'second')]);
    open();

    act(() => {
      markerButtons()[1]!.click();
    });

    expect(onJump).toHaveBeenCalledWith(42);
  });

  it('closes the panel on a jump, since it stands in front of the answer', () => {
    const { onJump } = render([marker(1, 'first')]);
    open();
    expect(panel()).not.toBe(null);

    act(() => {
      markerButtons()[0]!.click();
    });

    expect(panel()).toBe(null);
    expect(onJump).toHaveBeenCalledWith(1);
  });

  it('labels a message that carried no text by its POSITION', () => {
    // A paste or an image-only message has no words. An unlabelled node is one
    // the reader cannot aim at, which is the whole point of the timeline.
    render([marker(1, '   '), marker(2, 'has words')]);
    open();

    expect(markerButtons().map((b) => b.textContent)).toEqual([
      'Message 1',
      'has words',
    ]);
  });

  it('writes a stretch of figures under its own message', () => {
    render([
      marker(1, 'ask', {
        aiMessages: 3,
        elapsedMs: 80_000,
        totals: {
          ...NOTHING_MEASURED,
          costUsd: 0.42,
          inputTokens: 10_000,
          outputTokens: 2_000,
        },
      }),
    ]);
    open();

    expect(segmentText()[0]).toBe('3 messages · 1m 20s · 12k · $0.42');
  });

  it('OMITS an unmeasured cost rather than drawing it as zero', () => {
    // cursor turns are genuinely unpriced. A `$0.00` here would be a claim
    // about money no CLI ever made.
    render([marker(1, 'ask', { aiMessages: 2, elapsedMs: 5_000 })]);
    open();

    const text = segmentText()[0]!;
    expect(text).toBe('2 messages · 5s');
    expect(text).not.toContain('$');
  });

  it('says so in the detail when a figure was never measured', () => {
    render([marker(1, 'ask', { aiMessages: 1 })]);
    open();

    const detail =
      document.body
        .querySelector('[data-slot="timeline-segment"]')
        ?.getAttribute('title') ?? '';
    expect(detail).toContain('cost not measured');
    expect(detail).toContain('tokens not measured');
    expect(detail).toContain('agent time not measured');
  });

  it('counts a single message in the singular', () => {
    render([marker(1, 'ask', { aiMessages: 1 })]);
    open();

    expect(segmentText()[0]).toContain('1 message');
  });

  it('leaves thinking tokens OUT of the segment total', () => {
    // Some providers count reasoning inside the output figure, so adding it
    // would double some stretches and not others — and a timeline is read by
    // comparing its stretches against each other.
    render([
      marker(1, 'ask', {
        aiMessages: 1,
        totals: {
          ...NOTHING_MEASURED,
          inputTokens: 1_000,
          outputTokens: 500,
          thinkingTokens: 9_000,
        },
      }),
    ]);
    open();

    expect(segmentText()[0]).toContain('1.5k');
  });

  it('draws a node for every message, each with its own dot', () => {
    // The dot IS the timeline's node — a list that drew the line and left one
    // message without a mark on it would be read as that message missing.
    render([marker(1, 'a'), marker(2, 'b'), marker(3, 'c')]);
    open();

    expect(
      document.body.querySelectorAll('[data-slot="timeline-dot"]'),
    ).toHaveLength(3);
  });

  it('says on the timeline when the conversation starts earlier than it does', () => {
    // A capped list that stayed silent would be indistinguishable from a
    // shorter conversation, which is why the daemon sends a sentence rather
    // than just a shorter list.
    render([marker(61, 'ask 61')], vi.fn(), 'showing the newest 200 messages');
    open();

    expect(
      document.body.querySelector('[data-slot="timeline-partial"]')
        ?.textContent,
    ).toBe('showing the newest 200 messages');
  });

  it('draws no partial note on a timeline that is whole', () => {
    render([marker(1, 'only ask')]);
    open();

    expect(document.body.querySelector('[data-slot="timeline-partial"]')).toBe(
      null,
    );
  });
});
