import { GitCommitVertical } from 'lucide-react';
import { memo, useEffect, useRef, useState } from 'react';

import type { ChatTimelineMarker, ChatTimelineSegment } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Popover } from '../components/ui/popover';
import { cn } from '../components/ui/utils';
import { formatTokens, formatUsd } from './agent-activity';
import { formatDuration } from './turn-duration';

/**
 * What a marker says when its message carried no text of its own — a paste, an
 * image with no words. Its POSITION is the only thing left to name it by, and
 * an unlabelled dot is one the reader cannot aim at.
 */
function fallbackLabel(index: number): string {
  return `Message ${index + 1}`;
}

/**
 * The tokens one stretch moved: what went in, plus what came back.
 *
 * The two that every CLI reports and that cannot overlap. `thinkingTokens` is
 * deliberately left out of this sum — some providers count reasoning inside the
 * output figure, so adding it would double some segments and not others, and a
 * timeline is read by comparing its stretches against each other.
 *
 * Null contributes nothing rather than zero, so a stretch nothing reported
 * stays null: `0` here would claim a turn that moved no tokens at all.
 */
function segmentTokens(segment: ChatTimelineSegment): number | null {
  const { inputTokens, outputTokens } = segment.totals;
  if (inputTokens === null && outputTokens === null) {
    return null;
  }
  return (inputTokens ?? 0) + (outputTokens ?? 0);
}

/**
 * The stretch's figures, in the order they answer "what happened here": how
 * much was said, how long it took, what it moved, what it cost.
 *
 * A figure nothing measured is OMITTED rather than drawn as a zero — cursor
 * turns are genuinely unpriced, so a `$0.00` here would be a claim about money
 * no CLI ever made.
 */
function segmentFigures(segment: ChatTimelineSegment): string[] {
  // `messages` rather than `replies`: the count includes a delegate's output,
  // which rides the same kind and role, so the narrower word would claim these
  // were all the agent's own answers to the reader.
  const parts: string[] = [
    `${segment.aiMessages} ${segment.aiMessages === 1 ? 'message' : 'messages'}`,
  ];
  if (segment.elapsedMs !== null) {
    parts.push(formatDuration(segment.elapsedMs));
  }
  const tokens = segmentTokens(segment);
  if (tokens !== null) {
    parts.push(formatTokens(tokens));
  }
  if (segment.totals.costUsd !== null) {
    parts.push(formatUsd(segment.totals.costUsd));
  }
  return parts;
}

/** The same figures spelled out, for the hover title. */
function segmentDetail(segment: ChatTimelineSegment): string {
  const lines = [
    `${segment.aiMessages} agent message${segment.aiMessages === 1 ? '' : 's'}, sub-agents included`,
  ];
  lines.push(
    segment.elapsedMs === null
      ? 'no time elapsed yet'
      : `${formatDuration(segment.elapsedMs)} elapsed`,
  );
  lines.push(
    segment.totals.workedMs === null
      ? 'agent time not measured'
      : `${formatDuration(segment.totals.workedMs)} of agent time`,
  );
  const tokens = segmentTokens(segment);
  lines.push(
    tokens === null ? 'tokens not measured' : `${formatTokens(tokens)} tokens`,
  );
  lines.push(
    segment.totals.costUsd === null
      ? 'cost not measured'
      : `${formatUsd(segment.totals.costUsd)} spent`,
  );
  return lines.join('\n');
}

interface ConversationTimelineProps {
  markers: readonly ChatTimelineMarker[];
  /** Why the timeline is real but incomplete — the daemon's own sentence. */
  partialReason?: string | null;
  /** Take the reader to this message — `useTranscriptJump.jumpToSeq`. */
  onJump: (seq: number) => void;
  /**
   * The agent is still working on the NEWEST message.
   *
   * Asked for as "for current step (last message) color/dot should be
   * different, because its on progress": every node wore the same dot, so the
   * stretch still being written read exactly like one that was over. That node
   * now carries a live dot and a clock that runs.
   */
  inProgress?: boolean;
  className?: string;
}

/**
 * The conversation as a vertical timeline, behind an icon in the chat header.
 *
 * One node per user message, top to bottom in the order they were sent — the
 * transcript's own order, so the timeline maps onto what is on screen rather
 * than asking the reader to invert it. Beside each node is that message; under
 * it, along the line running down to the next node, is what happened in
 * between: the agent messages, the elapsed time, the tokens, the cost. Clicking
 * a node takes the reader there and closes the panel, the answer being the
 * place rather than the list.
 *
 * BEHIND AN ICON rather than always on screen. It first shipped as a strip
 * pinned above the transcript and that was the wrong shape twice over: a
 * horizontal rail has one line of room, so a message's own words — the only
 * thing that makes a node aimable — had to be truncated to a chip, and the band
 * took its height off the transcript on every thread whether or not anybody was
 * navigating. A panel costs nothing until it is opened, and vertical space is
 * what a list of sentences actually needs.
 *
 * It is OMITTED, never disabled, when the thread has no user messages — the
 * rule the header's own actions follow, and the same one the effort and
 * context-window chips follow elsewhere: a greyed control states that a feature
 * exists and is broken, where the truth is that this thread has nothing to
 * navigate yet.
 */
export const ConversationTimeline = memo(function ConversationTimeline({
  markers,
  partialReason = null,
  onJump,
  inProgress = false,
  className,
}: ConversationTimelineProps): React.JSX.Element | null {
  const [open, setOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement>(null);

  if (markers.length === 0) {
    return null;
  }

  const jump = (seq: number): void => {
    // Closed FIRST: the panel covers the transcript it is about, so leaving it
    // open would land the reader on a row it is standing in front of.
    setOpen(false);
    onJump(seq);
  };

  return (
    <>
      <Button
        ref={triggerRef}
        variant="ghost"
        size="icon"
        aria-label="Conversation timeline"
        aria-expanded={open}
        title={`Conversation timeline — jump to any of your ${markers.length} messages`}
        className={className}
        onClick={() => setOpen((was) => !was)}>
        <GitCommitVertical aria-hidden="true" />
      </Button>
      <Popover
        open={open}
        onClose={() => setOpen(false)}
        triggerRef={triggerRef}
        side="bottom"
        align="end"
        // The trigger sits at the right edge of the header, so an
        // ancestor-positioned panel opening rightward is clipped by the window;
        // viewport anchoring is what lets it flip and clamp.
        anchor="viewport"
        label="Conversation timeline"
        className="w-96 max-w-[min(24rem,90vw)] p-0">
        <div
          data-slot="conversation-timeline"
          className="max-h-[60vh] overflow-y-auto p-3">
          {/* A capped timeline SAYS so, at the end the conversation continues
              from — the daemon's own sentence rather than a second wording
              here. Without it a list that starts part-way through the thread is
              indistinguishable from a shorter thread. */}
          {partialReason === null ? null : (
            <p
              data-slot="timeline-partial"
              className="mb-2 text-[11px] text-muted-foreground/80">
              {partialReason}
            </p>
          )}
          {/* NEWEST FIRST.
              REPORTED as "нам нужно изменить timeline, чтобы он изначально
              начинался сверху… Сейчас, чтобы увидеть последнее сообщение
              пользователя, мне нужно каждый раз листать до самого низа" — the
              list was chronological, so the message a reader is most likely
              looking for, the one they just sent, was the one furthest from the
              top of a panel capped at 60vh.

              The daemon still sends seq order and still keeps the NEWEST
              markers when it caps, so the reversal is presentation only: it
              cannot turn a truncated head into a truncated tail, and the
              partial-reason line above still sits at the end the conversation
              continues from.

              The ORDINAL is taken before the reversal, so `Message 3` is the
              third message of the conversation rather than the third row of the
              panel — a number that counted rows would relabel every earlier
              message each time a new one arrived. */}
          <ol>
            {markers
              .map((marker, index) => ({ marker, ordinal: index + 1 }))
              .reverse()
              .map(({ marker, ordinal }, row, rows) => (
                <TimelineNode
                  key={marker.seq}
                  marker={marker}
                  label={marker.preview.trim() || fallbackLabel(ordinal - 1)}
                  last={row === rows.length - 1}
                  // Row 0 is the NEWEST message, the list being reversed.
                  current={inProgress && row === 0}
                  onJump={jump}
                />
              ))}
          </ol>
        </div>
      </Popover>
    </>
  );
});

/**
 * One node: the dot, the line running down from it, the message beside it, and
 * that stretch's figures along the line.
 *
 * The line is drawn under EVERY node including the last, because every marker
 * opens a stretch of work — the last one's is whatever the agent is doing now.
 * What the last node drops is the extra spacing, so the list ends at its
 * figures rather than trailing off into empty panel.
 *
 * THE WHOLE NODE ANSWERS THE POINTER, and it does so in `--accent` — the two
 * halves of a hover that could not be seen. The fill was `bg-sidebar-accent`,
 * a token tuned for the sidebar's own ground: over this floating panel it is
 * `#282624` on `#262422`, two units per channel, so on the dark theme the
 * effect existed and was invisible — the same trap the connector line below
 * fell into. `--accent` is what the app's own menu rows highlight with on this
 * exact surface, so a timeline node and a menu row now react alike. And it
 * moved off the message BUTTON onto the node's body, because a reader aiming
 * at a node aims at all of it: with the fill on the label alone, crossing the
 * figures — which are half the node's height — put the highlight out again.
 * The click target stays the message line, since the figures carry a tooltip
 * of their own that an overlaid button would swallow.
 */
function TimelineNode({
  marker,
  label,
  last,
  current,
  onJump,
}: {
  marker: ChatTimelineMarker;
  label: string;
  last: boolean;
  /** The agent is still working on this message — see `inProgress`. */
  current: boolean;
  onJump: (seq: number) => void;
}): React.JSX.Element {
  const now = useNowWhile(current);
  // The daemon's elapsed figure runs to the last row it READ, so for a stretch
  // still being worked it is as old as the last fetch. The clock is taken from
  // the message itself instead, and never runs backwards past that figure.
  const segment: ChatTimelineSegment = current
    ? {
        ...marker.segment,
        elapsedMs: Math.max(
          marker.segment.elapsedMs ?? 0,
          now - Date.parse(marker.createdAt),
        ),
      }
    : marker.segment;
  return (
    <li
      className="group flex gap-3"
      aria-current={current ? 'step' : undefined}>
      <div className="flex w-2 flex-none flex-col items-center">
        {/* The dot answers the same hover, in a ring rather than a size: it
            sits in a fixed-width column beside a line, so anything that grows
            it moves both. A FINISHED stretch's dot is muted and the one still
            being worked is the accent with a pulse behind it — the list's one
            live element, told apart by colour AND motion. */}
        <span
          aria-hidden
          data-slot="timeline-dot"
          data-state={current ? 'in-progress' : 'done'}
          className={cn(
            'relative mt-2 size-2 flex-none rounded-full ring-2 ring-transparent transition-[box-shadow] group-hover:ring-primary/30',
            current ? 'bg-primary' : 'bg-muted-foreground/60',
          )}>
          {current ? (
            <span className="absolute inset-0 animate-ping rounded-full bg-primary/60" />
          ) : null}
        </span>
        {/* `--border` is tuned for an edge BETWEEN two surfaces and is far too
            faint to read as a line drawn ON one: measured at rgb(59,56,53) over
            the dark popover, about 1.5:1, so the line existed at its full 39px
            and simply could not be seen — and the line is what makes this a
            timeline rather than a list. A muted-foreground tint is the same
            token family the figures beside it use. */}
        <span aria-hidden className="w-px flex-1 bg-muted-foreground/40" />
      </div>
      {/* The gap to the next node is a MARGIN, not padding: it is what gives
          the connector its length, and inside the box it would tint a
          centimetre of empty panel under every node's figures. */}
      <div
        data-slot="timeline-node"
        className={cn(
          'min-w-0 flex-1 rounded-md px-1.5 py-1 transition-colors group-hover:bg-accent group-focus-within:bg-accent',
          last ? null : 'mb-3',
        )}>
        <button
          type="button"
          onClick={() => onJump(marker.seq)}
          title={`${label}\n${new Date(marker.createdAt).toLocaleString()}`}
          aria-label={`Jump to: ${label}`}
          data-slot="timeline-marker"
          className="block w-full cursor-pointer rounded-sm text-left text-xs text-foreground focus-visible:ring-[3px] focus-visible:ring-ring/50 focus-visible:outline-none">
          {label}
        </button>
        <p
          data-slot="timeline-segment"
          title={segmentDetail(segment)}
          className="mt-0.5 text-[11px] tabular-nums text-muted-foreground/80">
          {segmentFigures(segment).join(' · ')}
        </p>
      </div>
    </li>
  );
}

/**
 * The wall clock, re-read every second while `active`, for the elapsed time of
 * the stretch still being worked. Schedules nothing otherwise, so a timeline
 * of finished messages costs no timer.
 */
function useNowWhile(active: boolean): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    if (!active) {
      return;
    }
    const timer = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(timer);
  }, [active]);
  return now;
}
