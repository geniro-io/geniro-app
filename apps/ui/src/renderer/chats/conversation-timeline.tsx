import { memo } from 'react';

import type { ChatTimelineMarker, ChatTimelineSegment } from '../autogenerated';
import { cn } from '../components/ui/utils';
import { formatTokens, formatUsd } from './agent-activity';
import { formatDuration } from './turn-duration';

/**
 * What a marker says when its message carried no text of its own — a paste, an
 * image with no words. Its POSITION is the only thing left to name it by, and
 * an unlabelled dot is one the reader cannot aim at.
 */
function fallbackLabel(index: number): string {
  return `Message ${index + 1}`;
}

/**
 * The tokens one stretch moved: what went in, plus what came back.
 *
 * The two that every CLI reports and that cannot overlap. `thinkingTokens` is
 * deliberately left out of this sum — some providers count reasoning inside the
 * output figure, so adding it would double some segments and not others, and a
 * rail is read by comparing its stretches against each other.
 *
 * Null contributes nothing rather than zero, so a stretch nothing reported
 * stays null: `0` here would claim a turn that moved no tokens at all.
 */
function segmentTokens(segment: ChatTimelineSegment): number | null {
  const { inputTokens, outputTokens } = segment.totals;
  if (inputTokens === null && outputTokens === null) {
    return null;
  }
  return (inputTokens ?? 0) + (outputTokens ?? 0);
}

/**
 * The stretch's figures, in the order they answer "what happened here": how
 * much was said, how long it took, what it moved, what it cost.
 *
 * A figure nothing measured is OMITTED rather than drawn as a zero — cursor
 * turns are genuinely unpriced, so a `$0.00` on the rail would be a claim about
 * money no CLI ever made.
 */
function segmentFigures(segment: ChatTimelineSegment): string[] {
  // `messages` rather than `replies`: the count includes a delegate's output,
  // which rides the same kind and role, so the narrower word would claim these
  // were all the agent's own answers to the reader.
  const parts: string[] = [
    `${segment.aiMessages} ${segment.aiMessages === 1 ? 'message' : 'messages'}`,
  ];
  if (segment.elapsedMs !== null) {
    parts.push(formatDuration(segment.elapsedMs));
  }
  const tokens = segmentTokens(segment);
  if (tokens !== null) {
    parts.push(formatTokens(tokens));
  }
  if (segment.totals.costUsd !== null) {
    parts.push(formatUsd(segment.totals.costUsd));
  }
  return parts;
}

/** The same figures spelled out, for the hover title. */
function segmentDetail(segment: ChatTimelineSegment): string {
  const lines = [
    `${segment.aiMessages} agent message${segment.aiMessages === 1 ? '' : 's'}, sub-agents included`,
  ];
  lines.push(
    segment.elapsedMs === null
      ? 'no time elapsed yet'
      : `${formatDuration(segment.elapsedMs)} elapsed`,
  );
  lines.push(
    segment.totals.workedMs === null
      ? 'agent time not measured'
      : `${formatDuration(segment.totals.workedMs)} of agent time`,
  );
  const tokens = segmentTokens(segment);
  lines.push(
    tokens === null ? 'tokens not measured' : `${formatTokens(tokens)} tokens`,
  );
  lines.push(
    segment.totals.costUsd === null
      ? 'cost not measured'
      : `${formatUsd(segment.totals.costUsd)} spent`,
  );
  return lines.join('\n');
}

interface ConversationTimelineProps {
  markers: readonly ChatTimelineMarker[];
  /** Why the rail is real but incomplete — the daemon's own sentence. */
  partialReason?: string | null;
  /** Take the reader to this message — `useTranscriptJump.jumpToSeq`. */
  onJump: (seq: number) => void;
  className?: string;
}

/**
 * The conversation as a horizontal rail: one node per user message, with what
 * followed each written on the line between it and the next.
 *
 * It is a NAVIGATION strip and deliberately not a restatement of the rows below
 * it — a vertical timeline that repeated the entries directly beneath itself
 * was built once and removed on the report that the transcript already said all
 * of it (`subagent-block.tsx`). What this carries that scrolling cannot is the
 * whole thread at once, and per-stretch figures that exist nowhere else on
 * screen.
 *
 * It scrolls sideways rather than compressing: a node's LABEL is what makes the
 * rail aimable, so squeezing forty messages into the pane's width would leave
 * forty unlabelled dots — which is the vertical version's failure in a new
 * shape.
 *
 * MEMOIZED, like every other many-row component on this surface. `Chats`
 * re-renders on every streamed token, and this list is whole-thread by design —
 * so without it a long conversation reformats hundreds of markers several times
 * a second while the agent is producing. Both props are already referentially
 * stable: `markers` is hook state and `onJump` is a `useCallback`.
 */
export const ConversationTimeline = memo(function ConversationTimeline({
  markers,
  partialReason = null,
  onJump,
  className,
}: ConversationTimelineProps): React.JSX.Element | null {
  if (markers.length === 0) {
    return null;
  }
  return (
    <nav
      aria-label="Conversation timeline"
      data-slot="conversation-timeline"
      className={cn(
        'shrink-0 overflow-x-auto border-b border-border bg-card',
        className,
      )}>
      <ol className="flex w-max items-center px-3 py-1.5">
        {/* A capped rail SAYS so, at the end the conversation continues from —
        the daemon's own sentence rather than a second wording here. Without it
        a rail that starts part-way through the thread is indistinguishable from
        a shorter thread. */}
        {partialReason === null ? null : (
          <li
            data-slot="timeline-partial"
            title={partialReason}
            className="flex shrink-0 items-center gap-1.5 pr-1.5 text-[11px] text-muted-foreground/80">
            <span className="max-w-44 truncate">{partialReason}</span>
            <span aria-hidden className="h-px w-3 bg-border" />
          </li>
        )}
        {markers.map((marker, index) => {
          const label = marker.preview.trim() || fallbackLabel(index);
          return (
            <li key={marker.seq} className="flex shrink-0 items-center">
              <button
                type="button"
                onClick={() => onJump(marker.seq)}
                title={`${label}\n${new Date(marker.createdAt).toLocaleString()}`}
                aria-label={`Jump to: ${label}`}
                data-slot="timeline-marker"
                className="group flex max-w-44 shrink-0 items-center gap-1.5 rounded-md px-1.5 py-1 text-xs text-muted-foreground transition-colors hover:bg-sidebar-accent hover:text-foreground focus-visible:ring-[3px] focus-visible:ring-ring/50 focus-visible:outline-none">
                <span
                  aria-hidden
                  className="size-2 shrink-0 rounded-full bg-muted-foreground/60 transition-colors group-hover:bg-primary"
                />
                <span className="truncate">{label}</span>
              </button>
              <Connector
                segment={marker.segment}
                last={index === markers.length - 1}
              />
            </li>
          );
        })}
      </ol>
    </nav>
  );
});

/**
 * The line between two nodes, carrying that stretch's figures.
 *
 * The LAST stretch is drawn shorter and without a trailing rule: there is no
 * node after it, so a full-length connector would run off into nothing and read
 * as a message the rail had failed to draw.
 */
function Connector({
  segment,
  last,
}: {
  segment: ChatTimelineSegment;
  last: boolean;
}): React.JSX.Element {
  return (
    <div
      data-slot="timeline-segment"
      title={segmentDetail(segment)}
      className={cn(
        'flex shrink-0 items-center gap-1.5',
        last ? 'min-w-24 pl-1.5' : 'min-w-32 px-1.5',
      )}>
      <span aria-hidden className="h-px min-w-3 flex-1 bg-border" />
      <span className="whitespace-nowrap text-[11px] text-muted-foreground/80 tabular-nums">
        {segmentFigures(segment).join(' · ')}
      </span>
      {last ? null : (
        <span aria-hidden className="h-px min-w-3 flex-1 bg-border" />
      )}
    </div>
  );
}
