import { describe, expect, it } from 'vitest';

import type { OpenMonitor } from '../autogenerated';
import type { AgentThread } from './agent-activity';
import {
  conversationWorkByCall,
  conversationWorkOf,
  NO_CONVERSATION_WORK,
} from './conversation-work';
import type { ShellRun } from './shell-activity';
import type { AgentTaskRow } from './task-payload';

const shell = (id: string, callId: string | null): ShellRun => ({
  id,
  command: `cmd ${id}`,
  description: null,
  background: true,
  handle: null,
  status: 'running',
  exitCode: null,
  startedAt: '2026-11-11T10:00:00.000Z',
  launchSeq: 1,
  trackedSeq: null,
  agentId: 'engineer',
  callId,
});

const monitor = (id: string, callId: string | null): OpenMonitor => ({
  id,
  description: `watch ${id}`,
  command: 'tail -f log',
  memberId: 'engineer',
  callId,
  startedAt: '2026-11-11T10:00:00.000Z',
  endsAt: '2026-11-11T11:00:00.000Z',
});

const delegate = (id: string, callId: string | null): AgentThread => ({
  id,
  kind: 'subagent',
  label: id,
  status: 'running',
  sessionId: null,
  callId,
});

const task = (id: string): AgentTaskRow => ({
  id,
  title: `task ${id}`,
  status: 'pending',
  activeForm: null,
});

describe('conversationWorkOf', () => {
  const byCall = conversationWorkByCall({
    agents: [
      {
        threads: [
          delegate('sub-a', 'call-1'),
          delegate('sub-b', 'call-2'),
          delegate('sub-main', null),
        ],
      },
    ],
    shellsByAgent: new Map([
      ['engineer', [shell('sh-1', 'call-1'), shell('sh-3', 'call-3')]],
      ['qa', [shell('sh-2', 'call-2'), shell('sh-main', null)]],
    ]),
    monitors: [monitor('m1', 'call-2'), monitor('m-main', null)],
    tasksByAgent: new Map([
      [
        'engineer',
        [
          { threadId: 'call-3', tasks: [task('1'), task('2')] },
          { threadId: 'main', tasks: [task('9')] },
        ],
      ],
    ]),
  });

  it('keeps only what the conversation’s own calls started', () => {
    const work = conversationWorkOf(byCall, ['call-2']);

    expect(work.shells.map((each) => each.id)).toEqual(['sh-2']);
    expect(work.monitors.map((each) => each.id)).toEqual(['m1']);
    expect(work.subagents.map((each) => each.id)).toEqual(['sub-b']);
    expect(work.tasks).toEqual([]);
  });

  it('gathers a continued conversation over every call of its chain', () => {
    const work = conversationWorkOf(byCall, ['call-1', 'call-3']);

    expect(work.shells.map((each) => each.id)).toEqual(['sh-1', 'sh-3']);
    expect(work.subagents.map((each) => each.id)).toEqual(['sub-a']);
    expect(work.tasks.map((each) => each.id)).toEqual(['1', '2']);
  });

  it('answers the empty reading for a conversation with nothing of its own', () => {
    expect(conversationWorkOf(byCall, ['call-9'])).toBe(NO_CONVERSATION_WORK);
  });
});
