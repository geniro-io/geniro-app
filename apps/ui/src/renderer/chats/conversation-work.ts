import type { OpenMonitor } from '../autogenerated';
import { type AgentDisplay, type AgentThread } from './agent-activity';
import type { InstanceTaskList } from './agent-instances';
import type { ShellRun } from './shell-activity';
import type { AgentTaskRow } from './task-payload';

/** What one call conversation has running and keeps: its own share of the shelf's counters. */
export interface ConversationWork {
  shells: readonly ShellRun[];
  monitors: readonly OpenMonitor[];
  subagents: readonly AgentThread[];
  tasks: readonly AgentTaskRow[];
}

interface CallWork {
  shells: ShellRun[];
  monitors: OpenMonitor[];
  subagents: AgentThread[];
  tasks: readonly AgentTaskRow[] | null;
}

export const NO_CONVERSATION_WORK: ConversationWork = {
  shells: [],
  monitors: [],
  subagents: [],
  tasks: [],
};

/** Every call's own commands, monitors, delegates and task list, keyed by call id. */
export function conversationWorkByCall({
  agents,
  shellsByAgent,
  monitors,
  tasksByAgent,
}: {
  agents: readonly Pick<AgentDisplay, 'threads'>[];
  shellsByAgent: ReadonlyMap<string, readonly ShellRun[]>;
  monitors: readonly OpenMonitor[];
  tasksByAgent: ReadonlyMap<string, readonly InstanceTaskList[]>;
}): ReadonlyMap<string, CallWork> {
  const byCall = new Map<string, CallWork>();
  const entry = (callId: string): CallWork => {
    let found = byCall.get(callId);
    if (found === undefined) {
      found = { shells: [], monitors: [], subagents: [], tasks: null };
      byCall.set(callId, found);
    }
    return found;
  };
  for (const shells of shellsByAgent.values()) {
    for (const shell of shells) {
      if (shell.callId !== null) {
        entry(shell.callId).shells.push(shell);
      }
    }
  }
  for (const monitor of monitors) {
    if (monitor.callId !== null) {
      entry(monitor.callId).monitors.push(monitor);
    }
  }
  for (const agent of agents) {
    for (const thread of agent.threads) {
      if (thread.kind === 'subagent' && thread.callId != null) {
        entry(thread.callId).subagents.push(thread);
      }
    }
  }
  for (const lists of tasksByAgent.values()) {
    for (const list of lists) {
      if (list.tasks.length > 0) {
        entry(list.threadId).tasks = list.tasks;
      }
    }
  }
  return byCall;
}

/** One conversation's work, gathered over every call of its chain. */
export function conversationWorkOf(
  byCall: ReadonlyMap<string, CallWork>,
  callIds: readonly string[],
): ConversationWork {
  const shells: ShellRun[] = [];
  const monitors: OpenMonitor[] = [];
  const subagents: AgentThread[] = [];
  let tasks: readonly AgentTaskRow[] = [];
  for (const callId of callIds) {
    const found = byCall.get(callId);
    if (found === undefined) {
      continue;
    }
    shells.push(...found.shells);
    monitors.push(...found.monitors);
    subagents.push(...found.subagents);
    if (found.tasks !== null) {
      tasks = found.tasks;
    }
  }
  if (
    shells.length === 0 &&
    monitors.length === 0 &&
    subagents.length === 0 &&
    tasks.length === 0
  ) {
    return NO_CONVERSATION_WORK;
  }
  return { shells, monitors, subagents, tasks };
}
