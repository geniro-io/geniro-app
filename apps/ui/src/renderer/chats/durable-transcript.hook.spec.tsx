// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem, RunStateDto } from '../autogenerated';
import { useDurableTranscript } from './durable-transcript';
import type { TranscriptEntry } from './transcript-groups';

(
  globalThis as unknown as { IS_REACT_ACT_ENVIRONMENT: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const launch: ChatItem = {
  id: 'launch',
  runId: 'run-1',
  nodeId: null,
  seq: 1,
  kind: 'tool_call',
  role: null,
  payload: { id: 'delegate', name: 'Task', input: { description: 'Review' } },
  createdAt: '2026-09-14T10:00:00.000Z',
};
const items: ChatItem[] = [launch];
const anchors: ChatItem[] = [];

function stateOf(
  throughSeq: number,
  status: 'running' | 'completed',
): Pick<RunStateDto, 'throughSeq' | 'delegates'> {
  return {
    throughSeq,
    delegates: [
      {
        id: 'delegate',
        nodeId: null,
        callId: null,
        label: 'Review',
        kind: null,
        status,
        processEnded: false,
        launchSeq: 1,
        startedAt: launch.createdAt,
      },
    ],
  };
}

describe('useDurableTranscript', () => {
  let container: HTMLDivElement;
  let root: Root;
  let seen: TranscriptEntry[][];

  function Probe({
    state,
  }: {
    state: Pick<RunStateDto, 'throughSeq' | 'delegates'>;
  }): null {
    seen.push(
      useDurableTranscript({
        items,
        anchors,
        runId: 'run-1',
        taskList: undefined,
        collapseToolSteps: true,
        delegateState: state,
      }).entries,
    );
    return null;
  }

  beforeEach(() => {
    seen = [];
    container = document.createElement('div');
    root = createRoot(container);
  });
  afterEach(() => {
    act(() => root.unmount());
  });

  it('keeps the same entries across a run-state read that says nothing new', () => {
    act(() => root.render(<Probe state={stateOf(1, 'running')} />));
    // A later read — a new object, a moved `throughSeq` — with the same news.
    act(() => root.render(<Probe state={stateOf(5, 'running')} />));
    expect(seen.at(-1)).toBe(seen[0]);

    act(() => root.render(<Probe state={stateOf(6, 'completed')} />));
    expect(seen.at(-1)).not.toBe(seen[0]);
  });
});
