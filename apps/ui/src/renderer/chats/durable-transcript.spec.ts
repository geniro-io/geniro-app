import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem, RunDto } from '../autogenerated';
import {
  anySubagentRunning,
  foldDurableTranscript,
} from './durable-transcript';
import type { TranscriptEntry } from './transcript-groups';

function row(
  id: string,
  kind: string,
  payload: unknown,
  seq: number,
  runId = 'run-1',
): ChatItem {
  return {
    id,
    runId,
    nodeId: null,
    seq,
    kind: kind as ChatItem['kind'],
    role: null,
    payload,
    createdAt: '2026-09-14T10:00:00.000Z',
  };
}

function foldOf(
  items: readonly ChatItem[],
  collapseToolSteps: boolean,
  run: { runId?: string; taskList?: RunDto['taskList'] } = {},
): TranscriptEntry[] {
  return foldDurableTranscript({
    items,
    foldItems: items,
    anchorIds: new Set(),
    runId: run.runId ?? 'run-1',
    taskList: run.taskList,
    collapseToolSteps,
  });
}

/** Every entry the fold drew, nested ones included, depth first. */
function flattenEntries(
  entries: readonly TranscriptEntry[],
): TranscriptEntry[] {
  return entries.flatMap((entry) => [
    entry,
    ...('entries' in entry && Array.isArray(entry.entries)
      ? flattenEntries(entry.entries)
      : []),
  ]);
}

/** The ids of the rows the fold draws as items, wherever they sit. */
function drawnIds(entries: readonly TranscriptEntry[]): string[] {
  return flattenEntries(entries).flatMap((entry) =>
    entry.type === 'item' ? [entry.item.id] : [],
  );
}

describe('foldDurableTranscript', () => {
  it('drops a turn that only compacted the conversation from the fold, and leaves the window as it was', () => {
    // The `✓ done` under a compaction says what the compaction row already says.
    // The turn is still in `items`, so it still counts toward the totals.
    const compaction = row(
      'c1',
      'system',
      { compaction: { preTokens: 100000, postTokens: 9000 } },
      1,
    );
    const turnEnd = row('t1', 'turn_complete', {}, 2);
    const items = [compaction, turnEnd];

    expect(drawnIds(foldOf(items, true))).not.toContain('t1');
    expect(drawnIds(foldOf([turnEnd], true))).toContain('t1');
    // The fold reads the window and never edits it.
    expect(items.map((item) => item.id)).toEqual(['c1', 't1']);
  });

  it('pulls a file change out of its tool group only while tool steps are not collapsed', () => {
    // A file change is pulled out of a group of several calls, so the group has
    // to hold a read before the edit.
    const group = [
      row(
        'q1',
        'tool_call',
        { id: 'q1', name: 'Read', input: { file_path: '/a.ts' } },
        1,
      ),
      row('q2', 'tool_result', { id: 'q1', output: 'a' }, 2),
      row(
        'e1',
        'tool_call',
        {
          id: 'e1',
          name: 'Edit',
          input: { file_path: '/a.ts', old_string: 'a', new_string: 'b' },
        },
        3,
      ),
      row('e2', 'tool_result', { id: 'e1', output: 'ok' }, 4),
    ];
    // A pulled-out change is a `tools` entry marked `standalone`.
    const hasStandalone = (entries: readonly TranscriptEntry[]): boolean =>
      flattenEntries(entries).some(
        (entry) => entry.type === 'tools' && entry.standalone === true,
      );

    expect(hasStandalone(foldOf(group, false))).toBe(true);
    expect(hasStandalone(foldOf(group, true))).toBe(false);
  });

  it("titles a task card from the run's own task list only while the rows belong to that run", () => {
    // The window cannot name a task whose announcement it does not hold, so the
    // daemon's list titles it. A switch can leave one run's rows under another
    // run's id for a render, and the guard keeps that run's list out of it.
    const announced = row(
      'k1',
      'task_list',
      {
        mode: 'patch',
        tasks: [{ id: '1', status: 'completed' }],
        toolCallId: null,
      },
      1,
    );
    const runTasks: RunDto['taskList'] = [
      {
        nodeId: null,
        callId: null,
        snapshot: true,
        tasks: [
          {
            id: '1',
            title: 'Write the plan',
            status: 'completed',
            activeForm: null,
          },
        ],
      },
    ];
    const titleFor = (runId: string): string | null | undefined =>
      flattenEntries(foldOf([announced], false, { runId, taskList: runTasks }))
        .flatMap((entry) => (entry.type === 'task-list' ? entry.tasks : []))
        .map((task) => task.title)[0];

    expect(titleFor('run-1')).toBe('Write the plan');
    expect(titleFor('run-2')).toBeNull();
  });
});

describe('anySubagentRunning', () => {
  // A `Task` call nothing has returned: the delegate was launched and has not
  // reported back.
  const launched = row(
    'task-1',
    'tool_call',
    {
      id: 'task-1',
      name: 'Task',
      input: { description: 'Review', prompt: 'Look at the diff' },
    },
    1,
  );
  const entries = foldOf([launched], false);

  it('reports a delegate working while the run has not settled', () => {
    expect(anySubagentRunning(entries, null, 1)).toBe(true);
  });

  it('does not report it once the run settled after the delegate last wrote a row', () => {
    expect(
      anySubagentRunning(entries, Date.parse('2026-09-14T11:00:00.000Z'), 1),
    ).toBe(false);
  });

  it('does not report a delegate working on a settle nobody can date', () => {
    // A settle whose moment cannot be read makes nothing audible, so no delegate
    // is reported working on a stop it cannot place.
    expect(anySubagentRunning(entries, 'unknown', 1)).toBe(false);
  });
});
