import { useMemo } from 'react';

import type { ItemDto as ChatItem, RunDto } from '../autogenerated';
import { compactionOnlyTurnEnds } from './compaction-payload';
import { anchorOnlyIds, withAnchors } from './history-anchors';
import {
  buildSubagentBlocks,
  buildTurnBlocks,
  buildWorkflowCards,
  collectSubagentBlocks,
  groupTranscript,
  pullFileChangesOutOfGroups,
  type RunSettleAt,
  subagentBlockStatus,
  subagentSpokeSince,
  type TranscriptEntry,
  withDurableTaskLists,
} from './transcript-groups';

/**
 * The durable transcript of one run: its rows folded into the blocks a thread
 * draws, WITHOUT the live plane (`withLiveText` lays that over the top).
 *
 * The chat screen and the workflow dock both call this, so the two cannot fold
 * the same rows differently. A row that looks wrong in the dock looks wrong in
 * the chat screen for the same reason.
 */
export function foldDurableTranscript({
  items,
  foldItems,
  anchorIds,
  runId,
  taskList,
  collapseToolSteps,
}: {
  /** The loaded window's rows. */
  items: readonly ChatItem[];
  /** The window with its anchors folded in — see `withAnchors`. */
  foldItems: readonly ChatItem[];
  /** The anchors that are structure only — see `anchorOnlyIds`. */
  anchorIds: ReadonlySet<string>;
  runId: string | null;
  /** The run's task list as the daemon folded the whole run. */
  taskList: RunDto['taskList'] | undefined;
  /** Whether tool steps start folded — `Settings.collapseToolSteps`. */
  collapseToolSteps: boolean;
}): TranscriptEntry[] {
  // A turn that did nothing but compact the conversation ends on the compaction
  // row itself, so its `✓ done` line repeats what the row already says. Only the
  // ROW goes: the item stays in `items`, so the turn still counts toward the
  // totals and its usage still reaches the ledger. Applied to the fold's output
  // rather than inside `groupTranscript`, which cannot import the reader —
  // `compaction-payload` reaches `agent-activity`, which imports `transcript-groups`
  // back.
  const redundant = compactionOnlyTurnEnds(items);
  // A task's words are stated only in the announcement that created it, so the
  // window alone cannot title every card. The daemon's fold of the whole run
  // can. It is used only while `items` belong to that run: a switch replaces the
  // two a render apart, and two runs of one workflow share node ids.
  const durableTasks = items[0]?.runId === runId ? (taskList ?? []) : [];
  const folded = withDurableTaskLists(
    redundant.size === 0
      ? groupTranscript(foldItems, { anchorIds })
      : groupTranscript(foldItems, { anchorIds }).filter(
          (entry) => entry.type !== 'item' || !redundant.has(entry.item.id),
        ),
    durableTasks,
  );
  // File changes come OUT of their group after the fold. An ACP agent reports
  // its change on the RESULT, which is attached after the call was grouped, so
  // a decision taken inside the fold would miss every one of them.
  const flow = collapseToolSteps ? folded : pullFileChangesOutOfGroups(folded);
  return buildTurnBlocks(
    buildWorkflowCards(buildSubagentBlocks(flow, foldItems), foldItems),
  );
}

/**
 * {@link foldDurableTranscript} over a loaded window and its anchors, memoized,
 * with the two inputs every other structural fold reads beside it: the window
 * with its anchors laid in, and which of those rows are anchors only.
 *
 * Held apart from the live overlay on purpose. Folding both in one memo rebuilt
 * every block on each delta, so every memoized row re-rendered several times a
 * second while streaming, which is the visible blink. `withLiveText` copies only
 * the one block it appends to.
 */
export function useDurableTranscript({
  items,
  anchors,
  runId,
  taskList,
  collapseToolSteps,
}: {
  items: readonly ChatItem[];
  /** Rows outside the window that rows inside it belong to — see `history-anchors.ts`. */
  anchors: readonly ChatItem[];
  runId: string | null;
  taskList: RunDto['taskList'] | undefined;
  collapseToolSteps: boolean;
}): {
  foldItems: readonly ChatItem[];
  anchorIds: ReadonlySet<string>;
  entries: TranscriptEntry[];
} {
  const foldItems = useMemo(
    () => withAnchors(items, anchors),
    [items, anchors],
  );
  const anchorIds = useMemo(
    () => anchorOnlyIds(items, anchors),
    [items, anchors],
  );
  const entries = useMemo(
    () =>
      foldDurableTranscript({
        items,
        foldItems,
        anchorIds,
        runId,
        taskList,
        collapseToolSteps,
      }),
    [items, foldItems, anchorIds, runId, taskList, collapseToolSteps],
  );
  return { foldItems, anchorIds, entries };
}

/**
 * Whether a sub-agent in the folded transcript is still working: its block reads
 * `running` against the run's settle moment and its delegate count, and it has
 * spoken since the run settled. The chat screen and the workflow dock both ask
 * this, so a delegate cannot read settled on one surface and working on the
 * other.
 */
export function anySubagentRunning(
  entries: readonly TranscriptEntry[],
  runStoppedAt: RunSettleAt | null,
  delegatesOut: number | null,
): boolean {
  return collectSubagentBlocks(entries).some(
    (block) =>
      subagentBlockStatus(block, runStoppedAt, delegatesOut) === 'running' &&
      subagentSpokeSince(block, runStoppedAt),
  );
}
