/**
 * The durable transcript of one run: its rows folded into the blocks a thread
 * draws, WITHOUT the live plane (`withLiveText` lays that over the top).
 *
 * The chat screen and the workflow dock both call this, so the two cannot fold
 * the same rows differently. A row that looks wrong in the dock looks wrong in
 * the chat screen for the same reason.
 */
export function foldDurableTranscript({
  items,
  foldItems,
  anchorIds,
  runId,
  taskList,
  collapseToolSteps,
}: {
  /** The loaded window's rows. */
  items: readonly ChatItem[];
  /** The window with its anchors folded in — see `withAnchors`. */
  foldItems: readonly ChatItem[];
  /** The anchors that are structure only — see `anchorOnlyIds`. */
  anchorIds: ReadonlySet<string>;
  runId: string | null;
  /** The run's task list as the daemon folded the whole run. */
  taskList: RunDto['taskList'] | undefined;
  /** Whether tool steps start folded — `Settings.collapseToolSteps`. */
  collapseToolSteps: boolean;
}): TranscriptEntry[] {
  // A turn that did nothing but compact the conversation ends on the compaction
  // row itself, so its `✓ done` line repeats what the row already says. Only the
  // ROW goes: the item stays in `items`, so the turn still counts toward the
  // totals and its usage still reaches the ledger. Applied to the fold's output
  // rather than inside `groupTranscript`, which cannot import the reader —
  // `compaction-payload` reaches `agent-activity`, which imports `transcript-groups`
  // back.
  const redundant = compactionOnlyTurnEnds(items);
  // A task's words are stated only in the announcement that created it, so the
  // window alone cannot title every card. The daemon's fold of the whole run
  // can. It is used only while `items` belong to that run: a switch replaces the
  // two a render apart, and two runs of one workflow share node ids.
  const durableTasks = items[0]?.runId === runId ? (taskList ?? []) : [];
  const folded = withDurableTaskLists(
    redundant.size === 0
      ? groupTranscript(foldItems, { anchorIds })
      : groupTranscript(foldItems, { anchorIds }).filter(
          (entry) => entry.type !== 'item' || !redundant.has(entry.item.id),
        ),
    durableTasks,
  );
  // File changes come OUT of their group after the fold. An ACP agent reports
  // its change on the RESULT, which is attached after the call was grouped, so
  // a decision taken inside the fold would miss every one of them.
  const flow = collapseToolSteps ? folded : pullFileChangesOutOfGroups(folded);
  return buildTurnBlocks(
    buildWorkflowCards(buildSubagentBlocks(flow, foldItems), foldItems),
  );
}

/**
 * {@link foldDurableTranscript} over a loaded window and its anchors, memoized,
 * with the two inputs every other structural fold reads beside it: the window
 * with its anchors laid in, and which of those rows are anchors only.
 *
 * Held apart from the live overlay on purpose. Folding both in one memo rebuilt
 * every block on each delta, so every memoized row re-rendered several times a
 * second while streaming, which is the visible blink. `withLiveText` copies only
 * the one block it appends to.
 */
export function useDurableTranscript({
  items,
  anchors,
  runId,
  taskList,
  collapseToolSteps,
  delegateState,
}: {
  items: readonly ChatItem[];
  /** Rows outside the window that rows inside it belong to — see `history-anchors.ts`. */
  anchors: readonly ChatItem[];
  runId: string | null;
  taskList: RunDto['taskList'] | undefined;
  collapseToolSteps: boolean;
  delegateState?: Pick<RunStateDto, 'throughSeq' | 'delegates'> &
    Partial<Pick<RunStateDto, 'calls'>>;
}): {
  foldItems: readonly ChatItem[];
  anchorIds: ReadonlySet<string>;
  entries: TranscriptEntry[];
} {
  const foldItems = useMemo(
    () => withAnchors(items, anchors),
    [items, anchors],
  );
  const anchorIds = useMemo(
    () => anchorOnlyIds(items, anchors),
    [items, anchors],
  );
  // The rows alone, so a run-state read — every structural row and status
  // announce brings one — never refolds the transcript.
  const base = useMemo(
    () =>
      foldDurableTranscript({
        items,
        foldItems,
        anchorIds,
        runId,
        taskList,
        collapseToolSteps,
      }),
    [items, foldItems, anchorIds, runId, taskList, collapseToolSteps],
  );
  // Keyed by what the readings SAY, so a read that changed nothing about any
  // delegate leaves the transcript's objects alone.
  const readingsKey = useMemo(
    () =>
      delegateState === undefined
        ? ''
        : readingsKeyOf(daemonSubagentReadings(delegateState, foldItems)),
    [delegateState, foldItems],
  );
  const readings = useMemo(() => readingsOfKey(readingsKey), [readingsKey]);
  const read = useMemo(
    () => applyDaemonReadings(base, readings),
    [base, readings],
  );
  // Keyed like the readings: which calls the daemon says have started, and
  // through which row it read.
  const startedKey =
    delegateState?.calls === undefined
      ? ''
      : startedCallsKeyOf(delegateState.calls, delegateState.throughSeq);
  const entries = useMemo(
    () => withDaemonStartedCalls(read, startedCallsOfKey(startedKey)),
    [read, startedKey],
  );
  return { foldItems, anchorIds, entries };
}

/** The calls the daemon reads as started — out and no longer queued. */
function startedCallsKeyOf(
  calls: RunStateDto['calls'],
  throughSeq: RunStateDto['throughSeq'],
): string {
  return JSON.stringify([
    throughSeq,
    calls
      .filter((call) => call.endedAt === null && !call.queued)
      .map((call) => call.callId),
  ]);
}

function startedCallsOfKey(key: string): StartedCalls | null {
  if (key === '') {
    return null;
  }
  const [throughSeq, ids] = JSON.parse(key) as [number | null, string[]];
  return throughSeq === null ? null : { throughSeq, ids: new Set(ids) };
}

interface StartedCalls {
  throughSeq: number;
  ids: ReadonlySet<string>;
}

/**
 * A card the window still reads as QUEUED whose call the daemon says has
 * started — off the tail the window never takes the call's first status row.
 * Only a read that covered the queued row counts: an older one knew nothing of
 * the wait, so its "not queued" says nothing.
 */
export function withDaemonStartedCalls(
  entries: TranscriptEntry[],
  started: StartedCalls | null,
): TranscriptEntry[] {
  if (started === null || started.ids.size === 0) {
    return entries;
  }
  const applyAll = (list: TranscriptEntry[]): TranscriptEntry[] => {
    let changed = false;
    const next = list.map((entry) => {
      const applied = apply(entry);
      changed ||= applied !== entry;
      return applied;
    });
    return changed ? next : list;
  };
  const apply = (entry: TranscriptEntry): TranscriptEntry => {
    if (
      entry.type !== 'call-block' &&
      entry.type !== 'turn-block' &&
      entry.type !== 'subagent-block'
    ) {
      return entry;
    }
    const inner = applyAll(entry.entries);
    if (
      entry.type === 'call-block' &&
      entry.queuedSeq !== undefined &&
      entry.queuedSeq <= started.throughSeq &&
      started.ids.has(entry.callId)
    ) {
      const { queued: _queued, queuedSeq: _queuedSeq, ...rest } = entry;
      return { ...rest, entries: inner };
    }
    return inner === entry.entries ? entry : { ...entry, entries: inner };
  };
  return applyAll(entries);
}

/**
 * Whether a sub-agent in the folded transcript is still working: its block reads
 * `running`, and it has spoken since the run settled. The chat screen and the
 * workflow dock both ask this, so a delegate cannot read settled on one surface
 * and working on the other.
 */
export function anySubagentRunning(
  entries: readonly TranscriptEntry[],
  runStoppedAt: RunSettleAt | null,
): boolean {
  return collectSubagentBlocks(entries).some(
    (block) =>
      subagentBlockStatus(block) === 'running' &&
      subagentSpokeSince(block, runStoppedAt),
  );
}

/** What the daemon says of one delegate. */
interface DaemonReading {
  /** Its lifecycle — only while the read covers every row the window holds. */
  lifecycle: {
    status: 'running' | BackgroundOutcome;
    processEnded: boolean;
  } | null;
  /** Its tool calls over the whole run, plus its rows written since the read. */
  toolCalls: number;
}

type DaemonReadings = ReadonlyMap<string, DaemonReading>;

const EMPTY_READINGS: DaemonReadings = new Map();

/**
 * The daemon's reading of each delegate. Its lifecycle is kept only while it
 * covers every row of that delegate the window holds — a newer row says more.
 * Its tool count is the daemon's, over every row through the read, plus the
 * delegate's own tool calls the window holds above it.
 *
 * TWIN PARSER: `ItemDao.delegateToolCallCounts` in
 * apps/daemon/src/v1/agents/dao/item.dao.ts counts the rows up to the read by
 * the same rule (`subagentIdOf`).
 */
export function daemonSubagentReadings(
  state: Pick<RunStateDto, 'throughSeq' | 'delegates'>,
  rows: readonly ChatItem[],
): DaemonReadings {
  if (state.delegates.length === 0) {
    return EMPTY_READINGS;
  }
  const newest = new Map<string, number>();
  const toolsSinceRead = new Map<string, number>();
  for (const row of rows) {
    const parent = subagentIdOf(row);
    for (const id of [payloadString(row.payload, 'id'), parent]) {
      if (id !== null) {
        newest.set(id, Math.max(newest.get(id) ?? -1, row.seq));
      }
    }
    if (
      parent !== null &&
      row.kind === 'tool_call' &&
      row.seq > state.throughSeq
    ) {
      toolsSinceRead.set(parent, (toolsSinceRead.get(parent) ?? 0) + 1);
    }
  }
  const readings = new Map<string, DaemonReading>();
  for (const delegate of state.delegates) {
    const covered =
      (newest.get(delegate.id) ?? delegate.launchSeq) <= state.throughSeq;
    readings.set(delegate.id, {
      lifecycle: covered
        ? {
            status:
              delegate.status === 'cancelled' ? 'stopped' : delegate.status,
            processEnded: delegate.processEnded,
          }
        : null,
      toolCalls: delegate.toolCalls + (toolsSinceRead.get(delegate.id) ?? 0),
    });
  }
  return readings;
}

/** Readings as a string that is equal exactly when they say the same. */
function readingsKeyOf(readings: DaemonReadings): string {
  return readings.size === 0
    ? ''
    : JSON.stringify(
        [...readings].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
      );
}

function readingsOfKey(key: string): DaemonReadings {
  return key === ''
    ? EMPTY_READINGS
    : new Map(JSON.parse(key) as [string, DaemonReading][]);
}

/**
 * Lay the daemon's readings over the folded blocks. A subtree nothing changes
 * in is returned as the same object, so memoized rows below it do not render.
 */
export function applyDaemonReadings(
  entries: TranscriptEntry[],
  readings: DaemonReadings,
): TranscriptEntry[] {
  if (readings.size === 0) {
    return entries;
  }
  const applyAll = (list: TranscriptEntry[]): TranscriptEntry[] => {
    let changed = false;
    const next = list.map((entry) => {
      const applied = apply(entry);
      changed ||= applied !== entry;
      return applied;
    });
    return changed ? next : list;
  };
  const apply = (entry: TranscriptEntry): TranscriptEntry => {
    if (
      entry.type !== 'call-block' &&
      entry.type !== 'turn-block' &&
      entry.type !== 'subagent-block'
    ) {
      return entry;
    }
    const inner = applyAll(entry.entries);
    const reading =
      entry.type === 'subagent-block' ? readings.get(entry.id) : undefined;
    if (entry.type === 'subagent-block' && reading !== undefined) {
      const { lifecycle } = reading;
      if (
        inner === entry.entries &&
        entry.durableToolCalls === reading.toolCalls &&
        (lifecycle === null ||
          (entry.daemonStatus === lifecycle.status &&
            entry.processEnded === lifecycle.processEnded))
      ) {
        return entry;
      }
      return {
        ...entry,
        ...(lifecycle === null
          ? {}
          : {
              daemonStatus: lifecycle.status,
              processEnded: lifecycle.processEnded,
            }),
        durableToolCalls: reading.toolCalls,
        entries: inner,
      };
    }
    return inner === entry.entries ? entry : { ...entry, entries: inner };
  };
  return applyAll(entries);
}
