import { Gauge } from 'lucide-react';

import type { AgentEffort } from '../autogenerated';
import { Select } from '../components/ui/select';

/**
 * Sentinel for "send no `--effort` flag at all" — a distinct value rather than
 * `''`, for the same reason as {@link CLI_DEFAULT_MODEL}: the menu needs a row
 * it can check, and an empty option value reads as "nothing selected".
 */
export const CLI_DEFAULT_EFFORT = '__default__';

/** The label shown for {@link CLI_DEFAULT_EFFORT} on the chip and in the menu. */
const DEFAULT_LABEL = 'default effort';

/**
 * The composer's reasoning-effort chip: how hard the model thinks next turn.
 *
 * The rows come from the CLI's own vocabulary (fetched by the caller through
 * `useAgentEfforts`), never a list baked into this app — claude accepts a
 * level its `--help` does not even name, so a copy here would be wrong the day
 * it was written.
 *
 * WITH NO LEVELS THERE IS NOTHING AT ALL — no chip, no explanation. It used to
 * draw an inert `no effort control` word carrying the daemon's sentence on
 * hover, on the reasoning that a control which vanishes is indistinguishable
 * from one that is broken. That reasoning came from a report about an effort
 * that SHOULD have existed and did not (cursor's, before the ACP handshake
 * declared its parameterized model picker) — and the fix for that was making
 * the axis reachable, not explaining its absence. What the word does now is put
 * a dead grey control in the composer of every model that genuinely has no
 * effort axis, which is most of cursor's: REPORTED as "мы не должны показывать
 * No Effort Control — мы полностью должны удалить, если у нас нет эффорта".
 * The daemon still SAYS why (`GET /v1/capabilities` `modelEfforts[]`, the
 * listing's own `unavailableReason`); nothing here renders it.
 *
 * A level the CLI no longer lists but the run still carries is added back as
 * its own row, so it is named on screen rather than vanishing silently —
 * SELECTABLE when the CLI's own vocabulary moved, DISABLED when it is the
 * current model refusing it. See {@link levelsAreModelSpecific}.
 */
export function EffortSelect({
  efforts,
  value,
  nextTurnOnly = false,
  levelsAreModelSpecific = false,
  onChange,
  className,
  variant = 'ghost',
  id,
}: {
  efforts: AgentEffort[];
  /** The chosen level, or null for the CLI's default. */
  value: string | null;
  /** A turn is running — this pick lands on the NEXT one. */
  nextTurnOnly?: boolean;
  /**
   * Whether {@link efforts} is ONE MODEL's list rather than the CLI's union.
   *
   * It decides what happens to a stored level the list does not contain, and
   * the two answers differ. For a CLI-wide list, a missing level means the
   * vocabulary moved under a run that still carries the old word, so it is
   * added back as a SELECTABLE row — the chip must name what will actually be
   * passed. For a MODEL's list it means this model refuses that level, which
   * is the case this control was rebuilt for: re-offering it as choosable
   * would put `max` back on a Grok chat, which is the reported defect
   * exactly. So the row is added back DISABLED instead of dropped — the run
   * still carries the level (nothing here clears it, and the daemon keeps
   * sending it every turn), so hiding the row entirely left nothing on screen
   * naming what the chip's silent "default effort" fallback was covering for.
   */
  levelsAreModelSpecific?: boolean;
  onChange: (effort: string | null) => void;
  className?: string;
  /**
   * `ghost` is the composer's flat chip, `default` the bordered form field the
   * graph builder's node inspector uses. One component for both rather than a
   * second picker in `graphs/`: the rows, the default sentinel and the
   * add-back row for a level the CLI no longer lists are the parts worth
   * getting right once, and they are identical wherever the control appears.
   */
  variant?: 'ghost' | 'default';
  /** Ties the form-field variant to its `Field` label. */
  id?: string;
}): React.JSX.Element | null {
  if (efforts.length === 0) {
    return null;
  }
  const known = efforts.some((effort) => effort.id === value);
  // See `levelsAreModelSpecific`: the model-refused case still gets its own
  // row, DISABLED rather than dropped, so the level the chip is silently
  // falling back from is named on screen instead of vanishing without a
  // trace.
  const refused = value !== null && !known && levelsAreModelSpecific;
  const rows = [
    ...efforts.map((effort) => ({ value: effort.id, label: effort.label })),
    ...(value !== null && !known
      ? [
          {
            value,
            label: value,
            disabled: levelsAreModelSpecific,
            hint: refused ? 'unavailable' : undefined,
          },
        ]
      : []),
  ];
  // What the chip SHOWS when the model does not take the stored level: the
  // CLI's default, which is what the turn will run at. Showing the stored word
  // would say the run is thinking at a level it cannot reach — the same lie in
  // a quieter place than the red row that got reported.
  const shown = refused ? null : value;
  return (
    <Select
      variant={variant}
      id={id}
      aria-label="Reasoning effort"
      title={
        nextTurnOnly
          ? 'Reasoning effort — applies to your next message'
          : 'Reasoning effort'
      }
      className={className}
      leadingIcon={<Gauge />}
      value={shown ?? CLI_DEFAULT_EFFORT}
      groups={[
        { items: rows },
        { items: [{ value: CLI_DEFAULT_EFFORT, label: DEFAULT_LABEL }] },
      ]}
      onValueChange={(next) =>
        onChange(next === CLI_DEFAULT_EFFORT ? null : next)
      }
    />
  );
}
