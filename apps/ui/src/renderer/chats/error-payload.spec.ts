import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  errorFactsOf,
  errorRecoveryOf,
  errorReportText,
} from './error-payload';

function errorItem(payload: unknown): ChatItem {
  return { kind: 'error', payload } as unknown as ChatItem;
}

describe('errorRecoveryOf', () => {
  it('reads the cure the daemon stamped', () => {
    expect(
      errorRecoveryOf(
        errorItem({ message: 'Failed to authenticate', recovery: 'cli-login' }),
      ),
    ).toBe('cli-login');
  });

  it('reads an ordinary failure as having no cure', () => {
    // The common case by far — the daemon stamps the key only for a failure
    // whose cure its adapter actually recognised.
    expect(errorRecoveryOf(errorItem({ message: 'spawn ENOENT' }))).toBeNull();
  });

  it('refuses a value it does not model, rather than passing it through', () => {
    // A future recovery kind the renderer has no button for must render as an
    // ordinary error row, not as a mislabelled Sign in.
    expect(
      errorRecoveryOf(errorItem({ recovery: 'restart-daemon' })),
    ).toBeNull();
  });

  it('survives a payload that is not a record', () => {
    expect(errorRecoveryOf(errorItem(null))).toBeNull();
    expect(errorRecoveryOf(errorItem('boom'))).toBeNull();
    expect(errorRecoveryOf(errorItem(undefined))).toBeNull();
  });
});

describe('errorFactsOf', () => {
  /** The shape the daemon stamps for a live API failure (probed 2.1.234). */
  const apiFailure = {
    message: 'API Error: Connection lost mid-response.',
    detail: {
      code: 'api_error',
      httpStatus: 404,
      requestId: 'req_011CeAL4KP2RkG9YEPGrdi2n',
      sessionId: '99691942-8ca6-415d-a4c5-975ed3aa4b73',
      durationMs: 986,
    },
  };

  it('reads the facts in the order a reader needs them', () => {
    // Most actionable first: what the provider calls it, what it answered, and
    // the id they can look up. The ORDER is asserted rather than the set,
    // because it is what puts the request id above a session id nobody outside
    // this machine can use.
    expect(errorFactsOf(errorItem(apiFailure))).toEqual([
      { label: 'code', value: 'api_error' },
      { label: 'http status', value: '404' },
      { label: 'request id', value: 'req_011CeAL4KP2RkG9YEPGrdi2n' },
      { label: 'failed after', value: '986ms' },
      { label: 'session', value: '99691942-8ca6-415d-a4c5-975ed3aa4b73' },
    ]);
  });

  it('reads a process that died rather than answered', () => {
    expect(
      errorFactsOf(
        errorItem({
          message: 'claude was terminated by SIGKILL',
          detail: { signal: 'SIGKILL' },
        }),
      ),
    ).toEqual([{ label: 'signal', value: 'SIGKILL' }]);
    // Zero is a real exit code, and truthiness would drop it.
    expect(
      errorFactsOf(errorItem({ message: 'x', detail: { exitCode: 0 } })),
    ).toEqual([{ label: 'exit code', value: '0' }]);
  });

  it('says nothing for a failure that reported nothing', () => {
    expect(errorFactsOf(errorItem({ message: 'it broke' }))).toEqual([]);
    expect(errorFactsOf(errorItem({ message: 'x', detail: 'nope' }))).toEqual(
      [],
    );
    expect(errorFactsOf(errorItem(null))).toEqual([]);
  });
});

describe('errorReportText', () => {
  it('is the sentence, when it happened, and every fact — one per line', () => {
    // The whole feature in one string: what a user hands to whoever runs the
    // model. Its shape is deliberately the plainest thing every tracker and
    // chat window renders unharmed.
    const item = {
      ...errorItem({
        message: 'API Error: Connection lost mid-response.',
        detail: { code: 'api_error', requestId: 'req_011Ce' },
      }),
      createdAt: '2026-08-18T13:56:13.063Z',
    } as ChatItem;

    expect(errorReportText(item)).toBe(
      [
        'API Error: Connection lost mid-response.',
        'when: 2026-08-18T13:56:13.063Z',
        'code: api_error',
        'request id: req_011Ce',
      ].join('\n'),
    );
  });
});
