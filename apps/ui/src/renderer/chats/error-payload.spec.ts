import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { errorRecoveryOf } from './error-payload';

function errorItem(payload: unknown): ChatItem {
  return { kind: 'error', payload } as unknown as ChatItem;
}

describe('errorRecoveryOf', () => {
  it('reads the cure the daemon stamped', () => {
    expect(
      errorRecoveryOf(
        errorItem({ message: 'Failed to authenticate', recovery: 'cli-login' }),
      ),
    ).toBe('cli-login');
  });

  it('reads an ordinary failure as having no cure', () => {
    // The common case by far — the daemon stamps the key only for a failure
    // whose cure its adapter actually recognised.
    expect(errorRecoveryOf(errorItem({ message: 'spawn ENOENT' }))).toBeNull();
  });

  it('refuses a value it does not model, rather than passing it through', () => {
    // A future recovery kind the renderer has no button for must render as an
    // ordinary error row, not as a mislabelled Sign in.
    expect(
      errorRecoveryOf(errorItem({ recovery: 'restart-daemon' })),
    ).toBeNull();
  });

  it('survives a payload that is not a record', () => {
    expect(errorRecoveryOf(errorItem(null))).toBeNull();
    expect(errorRecoveryOf(errorItem('boom'))).toBeNull();
    expect(errorRecoveryOf(errorItem(undefined))).toBeNull();
  });
});
