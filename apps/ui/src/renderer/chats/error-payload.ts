import type { ItemDto as ChatItem } from '../autogenerated';

/**
 * The cures this side knows how to render.
 *
 * Named rather than spelled at each comparison because the VALUE is as much of
 * the twin-parser contract as the key is — a daemon-side rename would otherwise
 * leave several bare literals with nothing pointing at them.
 */
export type ErrorRecovery = 'cli-login';

/**
 * What the user can do about a failed turn, or null when nothing is offered.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/utils/event-to-item.ts` stamps this
 * key onto an `error` item's payload, from the verdict the ADAPTER reached
 * about its own CLI's wording. An item payload is `z.unknown()` on the wire BY
 * DESIGN — every item kind carries a different shape — so no generated type
 * carries it here and this is an independent reading of the same shape. BOTH
 * the key (`recovery`) and its values ({@link ErrorRecovery}) are the contract:
 * renaming either on that side must be mirrored here, and vice versa.
 *
 * Only `cli-login` exists today: the CLI's account session lapsed, and signing
 * it back in is the cure. Anything else reads as null, so an unrecognised
 * future value renders an ordinary error row rather than a mislabelled button.
 *
 * Absent on the overwhelming majority of error rows — the daemon stamps it only
 * for a failure whose cure it actually recognised.
 */
export function errorRecoveryOf(item: ChatItem): ErrorRecovery | null {
  // `unknown`, not the generated field's own type: the payload is untyped on
  // the wire, so the generator gives it `any` and every read would be
  // unchecked.
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const value = (payload as { recovery?: unknown }).recovery;
  return value === 'cli-login' ? 'cli-login' : null;
}
