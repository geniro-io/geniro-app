import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  type FindingRow,
  findingsSummary,
  groupFindingsByFile,
  readFindingsReport,
} from './findings-payload';

let seq = 0;
function findingsItem(payload: unknown): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    nodeId: null,
    seq,
    kind: 'report_findings',
    role: null,
    payload,
    createdAt: 'now',
  };
}

const wire = (overrides: Record<string, unknown> = {}) => ({
  file: 'src/queue/processor.ts',
  line: 402,
  summary: 'finalizeCompleted no longer checks generation',
  shortSummary: 'CAS guard weakened',
  failureScenario: 'A superseded worker finishes late and wins the write.',
  category: 'correctness',
  verdict: 'CONFIRMED',
  ...overrides,
});

const row = (overrides: Partial<FindingRow> = {}): FindingRow => ({
  file: 'src/a.ts',
  line: null,
  summary: 'A defect',
  shortSummary: null,
  failureScenario: null,
  category: null,
  verdict: null,
  outcome: null,
  ...overrides,
});

describe('readFindingsReport', () => {
  it('reads a well-formed report', () => {
    expect(
      readFindingsReport(findingsItem({ level: 'high', findings: [wire()] })),
    ).toEqual({
      level: 'high',
      findings: [
        {
          file: 'src/queue/processor.ts',
          line: 402,
          summary: 'finalizeCompleted no longer checks generation',
          shortSummary: 'CAS guard weakened',
          failureScenario:
            'A superseded worker finishes late and wins the write.',
          category: 'correctness',
          verdict: 'CONFIRMED',
          outcome: null,
        },
      ],
    });
  });

  it('reads back every key the daemon writes — the twin-parser contract', () => {
    // This literal is byte-for-byte the payload asserted daemon-side in
    // `apps/daemon/src/v1/agents/services/chat.service.spec.ts` ("records a
    // findings report as one transcript row"). The payload is `z.unknown()` on
    // the wire, so nothing but these two assertions stops a key renamed on one
    // side from silently dropping the field from the card.
    const report = readFindingsReport(
      findingsItem({
        level: 'high',
        findings: [
          {
            file: 'src/a.ts',
            line: 12,
            summary: 'A guard was weakened',
            shortSummary: 'guard weakened',
            failureScenario: 'A late writer wins the race.',
            category: 'correctness',
            verdict: 'CONFIRMED',
            outcome: 'fixed',
          },
        ],
      }),
    );
    expect(report).toEqual({
      level: 'high',
      findings: [
        {
          file: 'src/a.ts',
          line: 12,
          summary: 'A guard was weakened',
          shortSummary: 'guard weakened',
          failureScenario: 'A late writer wins the race.',
          category: 'correctness',
          verdict: 'CONFIRMED',
          outcome: 'fixed',
        },
      ],
    });
  });

  it('reads an EMPTY report — nothing survived verification is still a report', () => {
    expect(readFindingsReport(findingsItem({ findings: [] }))).toEqual({
      level: null,
      findings: [],
    });
  });

  it('answers null for a payload that is not a report at all', () => {
    expect(readFindingsReport(findingsItem('a report'))).toBeNull();
    expect(readFindingsReport(findingsItem(null))).toBeNull();
    expect(readFindingsReport(findingsItem({ findings: 'three' }))).toBeNull();
  });

  it('renders a finding that carries only the two fields a row IS', () => {
    const report = readFindingsReport(
      findingsItem({ findings: [{ file: 'src/a.ts', summary: 'A defect' }] }),
    );
    expect(report?.findings).toEqual([row()]);
  });

  it('drops a finding with no file, keeping its neighbours', () => {
    const report = readFindingsReport(
      findingsItem({
        findings: [wire({ file: undefined }), wire(), null, 'nope'],
      }),
    );
    expect(report?.findings).toHaveLength(1);
  });

  it('degrades an unknown verdict, outcome or level rather than throwing', () => {
    const report = readFindingsReport(
      findingsItem({
        level: 'extreme',
        findings: [wire({ verdict: 'PROBABLY', outcome: 'half-fixed' })],
      }),
    );
    expect(report?.level).toBeNull();
    expect(report?.findings[0]?.verdict).toBeNull();
    expect(report?.findings[0]?.outcome).toBeNull();
    // The finding itself survives — an unrecognised badge costs it a badge.
    expect(report?.findings[0]?.summary).toBe(
      'finalizeCompleted no longer checks generation',
    );
  });

  it('keeps an outcome, which is what a re-report after fixes carries', () => {
    const report = readFindingsReport(
      findingsItem({ findings: [wire({ outcome: 'fixed' })] }),
    );
    expect(report?.findings[0]?.outcome).toBe('fixed');
  });

  it.each([[0], [-1], [2.5], ['402'], [null]])(
    'reads the line %p as absent rather than pointing at the wrong place',
    (line) => {
      const report = readFindingsReport(
        findingsItem({ findings: [wire({ line })] }),
      );
      expect(report?.findings[0]?.line).toBeNull();
    },
  );
});

describe('groupFindingsByFile', () => {
  it('groups by file, keeping the agent’s own order', () => {
    // The agent was told to send most-severe first, so the wire order is the
    // only ranking anybody has — re-sorting here would throw it away.
    const groups = groupFindingsByFile([
      row({ file: 'b.ts', summary: 'first' }),
      row({ file: 'a.ts', summary: 'second' }),
      row({ file: 'b.ts', summary: 'third' }),
    ]);
    expect(groups.map((g) => g.file)).toEqual(['b.ts', 'a.ts']);
    expect(groups[0]?.findings.map((f) => f.summary)).toEqual([
      'first',
      'third',
    ]);
  });

  it('returns nothing for an empty report', () => {
    expect(groupFindingsByFile([])).toEqual([]);
  });
});

describe('findingsSummary', () => {
  it('counts the total, the confirmed, and how many carry an outcome', () => {
    expect(
      findingsSummary({
        level: 'high',
        findings: [
          row({ verdict: 'CONFIRMED' }),
          row({ verdict: 'PLAUSIBLE' }),
          row({ verdict: 'CONFIRMED', outcome: 'fixed' }),
        ],
      }),
    ).toEqual({ total: 3, confirmed: 2, resolved: 1 });
  });
});
