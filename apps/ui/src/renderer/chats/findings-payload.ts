import type { ItemDto as ChatItem } from '../autogenerated';

/**
 * A code-review findings report an agent handed the app to draw, read off the
 * transcript.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/chat.types.ts` declares the shape
 * (`HostFindingsReport`) and `apps/daemon/src/v1/agents/utils/host-findings.ts`
 * writes these keys for the `report_findings` item kind. An item payload is
 * `z.unknown()` on the wire BY DESIGN — every kind carries a different shape —
 * so no generated type reaches here and this is an independent reading of one
 * shape. A key renamed on either side must be renamed on both.
 *
 * Note the naming seam this side does NOT cross: the daemon takes claude's
 * snake_case argument names at the tool edge and stores camelCase, so what
 * arrives here is already camelCase.
 *
 * Why NO fold, where `task-payload.ts` has one: a task list arrives as patches
 * naming only the rows that moved, so no single row is ever "the list". A
 * findings report arrives whole. Each row is therefore its own card, and an
 * agent that re-reports after fixing its findings produces a second card
 * carrying `outcome` — chronological, rather than a card that rewrites itself
 * under a reader who has already scrolled past it.
 */

export type FindingLevel = 'low' | 'medium' | 'high' | 'xhigh' | 'max';
export type FindingVerdict = 'CONFIRMED' | 'PLAUSIBLE';
export type FindingOutcome = 'fixed' | 'skipped' | 'no_change_needed';

const LEVELS: readonly FindingLevel[] = [
  'low',
  'medium',
  'high',
  'xhigh',
  'max',
];
const VERDICTS: readonly FindingVerdict[] = ['CONFIRMED', 'PLAUSIBLE'];
const OUTCOMES: readonly FindingOutcome[] = [
  'fixed',
  'skipped',
  'no_change_needed',
];

/** One finding, as one row of the card. */
export interface FindingRow {
  file: string;
  /** Null when the agent named no line, or named one that did not read as one. */
  line: number | null;
  summary: string;
  /** The collapsed label. Null falls back to {@link summary}. */
  shortSummary: string | null;
  failureScenario: string | null;
  category: string | null;
  /** Null unless a verification pass actually ran over this finding. */
  verdict: FindingVerdict | null;
  /** Null unless this is a RE-report, after the agent acted on its findings. */
  outcome: FindingOutcome | null;
}

/** One `report_findings` row, as the card draws it. */
export interface FindingsReport {
  level: FindingLevel | null;
  findings: FindingRow[];
}

function readString(value: unknown): string | null {
  return typeof value === 'string' && value.length > 0 ? value : null;
}

function readLine(value: unknown): number | null {
  return typeof value === 'number' && Number.isInteger(value) && value >= 1
    ? value
    : null;
}

function readOneOf<T extends string>(
  value: unknown,
  allowed: readonly T[],
): T | null {
  return typeof value === 'string' &&
    (allowed as readonly string[]).includes(value)
    ? (value as T)
    : null;
}

/**
 * Read one `report_findings` row, or null when the payload does not read as one.
 *
 * An empty findings list is a REPORT, not a non-report: the agent reviewed and
 * nothing survived its verification, which is worth a card saying so. Only a
 * payload that is not a report at all answers null.
 */
export function readFindingsReport(item: ChatItem): FindingsReport | null {
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const row = payload as { level?: unknown; findings?: unknown };
  if (!Array.isArray(row.findings)) {
    return null;
  }
  const findings = row.findings
    .map((entry): FindingRow | null => {
      if (typeof entry !== 'object' || entry === null) {
        return null;
      }
      const f = entry as Record<string, unknown>;
      const file = readString(f.file);
      const summary = readString(f.summary);
      // The two the row IS: a location and a claim. Anything else missing only
      // costs this finding a detail.
      if (file === null || summary === null) {
        return null;
      }
      return {
        file,
        summary,
        line: readLine(f.line),
        shortSummary: readString(f.shortSummary),
        failureScenario: readString(f.failureScenario),
        category: readString(f.category),
        verdict: readOneOf(f.verdict, VERDICTS),
        outcome: readOneOf(f.outcome, OUTCOMES),
      };
    })
    .filter((finding): finding is FindingRow => finding !== null);
  return { level: readOneOf(row.level, LEVELS), findings };
}

/** One file's findings, for the card's per-file headings. */
export interface FindingFileGroup {
  file: string;
  findings: FindingRow[];
}

/**
 * Group findings by file, keeping the agent's own order.
 *
 * A file's group sits where its FIRST finding did, and findings keep their
 * order within it. The agent was told to send them most-severe first, so any
 * re-sorting here would throw away the one ranking anybody has.
 */
export function groupFindingsByFile(
  findings: readonly FindingRow[],
): FindingFileGroup[] {
  const groups: FindingFileGroup[] = [];
  const byFile = new Map<string, FindingFileGroup>();
  for (const finding of findings) {
    const known = byFile.get(finding.file);
    if (known) {
      known.findings.push(finding);
      continue;
    }
    const group: FindingFileGroup = { file: finding.file, findings: [finding] };
    byFile.set(finding.file, group);
    groups.push(group);
  }
  return groups;
}

/** The card's one-line summary — what the header says beside the level. */
export function findingsSummary(report: FindingsReport): {
  total: number;
  confirmed: number;
  /** How many carry an outcome, i.e. this is a re-report after fixes. */
  resolved: number;
} {
  return {
    total: report.findings.length,
    confirmed: report.findings.filter((f) => f.verdict === 'CONFIRMED').length,
    resolved: report.findings.filter((f) => f.outcome !== null).length,
  };
}
