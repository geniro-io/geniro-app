// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import type { BlockStatus } from './block-shell';
import { flagToolEntryOf, FlagToolRow } from './flag-tool-row';
import type { ToolPair } from './transcript-groups';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const RUN_ID = 'abc12345-0000-0000-0000-000000000000';
const SERVER = 'geniro-abc12345';

const WORK_INPUT = {
  cost: 'work',
  category: 'geniro_tool',
  summary: 'The stage tool returned an empty stage list',
  detail: 'Re-ran move_stage three times before it accepted the handoff.',
  minutesLost: 15,
};

function item(kind: 'tool_call' | 'tool_result', payload: unknown): ChatItem {
  return {
    id: `i-${Math.random()}`,
    runId: RUN_ID,
    memberId: 'orch',
    seq: 1,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function pair(
  input: unknown,
  result?: { text: unknown; isError?: boolean },
): ToolPair {
  return {
    call: item('tool_call', {
      id: 'c1',
      name: `mcp__${SERVER}__flag_issue`,
      input,
    }),
    result:
      result === undefined
        ? null
        : item('tool_result', {
            id: 'c1',
            result: result.text,
            isError: result.isError ?? false,
          }),
  };
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function draw(source: ToolPair, status: BlockStatus = 'done'): void {
  const entry = flagToolEntryOf(source);
  if (entry === null) {
    throw new Error('expected a flag entry');
  }
  act(() => root.render(<FlagToolRow entry={entry} status={status} />));
}

function line(): string {
  return (container.textContent ?? '').replace(/\s+/g, ' ').trim();
}

function trigger(): HTMLButtonElement | null {
  return container.querySelector<HTMLButtonElement>(
    '[data-role="flag-tool"] > button',
  );
}

describe('a recorded flag', () => {
  it('shows the cost with its minutes, the category, the summary and the handle the result gave', () => {
    draw(
      pair(WORK_INPUT, {
        text: 'Flag F-3fa9c1 recorded. Every analysis of this thread reads it first. This conversation may raise 2 more.',
      }),
    );
    expect(line()).toBe(
      'Flagged a problem · cost work · ~15 min · Geniro tool · The stage tool returned an empty stage list F-3fa9c1',
    );
  });

  it('names a disagreement without minutes', () => {
    draw(
      pair(
        {
          cost: 'disagreement',
          category: 'user_instructions',
          summary: 'Used npm after I said pnpm',
        },
        {
          text: 'Flag F-0a1b2c recorded. Every analysis of this thread reads it first. This conversation may raise 4 more.',
        },
      ),
    );
    expect(line()).toBe(
      'Flagged a problem · user disagreed · Your agent instructions · Used npm after I said pnpm F-0a1b2c',
    );
  });

  it('shows the pending state while the call still runs, with no handle yet', () => {
    draw(pair(WORK_INPUT), 'running');
    expect(line()).toBe(
      'Flagging a problem · cost work · ~15 min · Geniro tool · The stage tool returned an empty stage list',
    );
  });
});

describe('a refused flag', () => {
  it('says the flag was not recorded and quotes the reason', () => {
    draw(
      pair(WORK_INPUT, {
        text: 'FLAG_LIMIT: this conversation has used its flags.',
        isError: true,
      }),
      'error',
    );
    expect(line()).toBe(
      'Flag not recorded · cost work · ~15 min · Geniro tool · The stage tool returned an empty stage list · this conversation has used its flags.',
    );
  });

  it('strips the Not recorded prefix from the reason', () => {
    draw(
      pair(WORK_INPUT, {
        text: 'Not recorded: the summary repeats an earlier flag.',
        isError: true,
      }),
      'error',
    );
    expect(line()).toContain('Flag not recorded');
    expect(line()).toContain('· the summary repeats an earlier flag.');
    expect(line()).not.toContain('Not recorded:');
  });
});

describe('the detail of a flag', () => {
  it('stays folded until the row is clicked', () => {
    draw(
      pair(WORK_INPUT, {
        text: 'Flag F-3fa9c1 recorded. Every analysis of this thread reads it first. This conversation may raise 2 more.',
      }),
    );
    expect(trigger()?.getAttribute('aria-expanded')).toBe('false');
    expect(container.textContent).not.toContain('Re-ran move_stage');
    act(() => trigger()?.click());
    expect(trigger()?.getAttribute('aria-expanded')).toBe('true');
    expect(container.textContent).toContain(
      'Re-ran move_stage three times before it accepted the handoff.',
    );
  });

  it('offers no toggle where the call carried no detail', () => {
    draw(
      pair(
        { cost: 'work', category: 'other', summary: 'A short note' },
        {
          text: 'Flag F-123abc recorded. Every analysis of this thread reads it first. This conversation may raise 4 more.',
        },
      ),
    );
    expect(trigger()).toBeNull();
    expect(line()).toBe(
      'Flagged a problem · cost work · Other · A short note F-123abc',
    );
  });
});

describe('flagToolEntryOf', () => {
  it.each([
    ['another server’s flag_issue', 'mcp__geniro-mine__flag_issue'],
    [
      'a tool of the run’s server that is not flag_issue',
      `mcp__${SERVER}__flag_issued`,
    ],
  ])('does not claim %s', (_, name) => {
    const foreign = pair(WORK_INPUT);
    foreign.call.payload = { id: 'c1', name, input: WORK_INPUT };
    expect(flagToolEntryOf(foreign)).toBeNull();
  });

  it('still draws a refused call whose input cannot be read', () => {
    expect(
      flagToolEntryOf(
        pair('not an object', {
          text: 'INVALID_ARGS: input must be an object.',
          isError: true,
        }),
      ),
    ).toEqual({
      cost: null,
      category: null,
      summary: null,
      detail: null,
      minutesLost: null,
      handle: null,
      refusal: 'input must be an object.',
    });
  });
});
