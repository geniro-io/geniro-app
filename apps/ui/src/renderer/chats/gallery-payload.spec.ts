import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { readGallery } from './gallery-payload';

function item(payload: unknown): ChatItem {
  return {
    id: 'i1',
    runId: 'r1',
    nodeId: null,
    seq: 1,
    kind: 'show_gallery',
    createdAt: '2026-08-30T00:00:00.000Z',
    payload,
  } as unknown as ChatItem;
}

describe('readGallery', () => {
  it('reads a well-formed payload, captions and all', () => {
    expect(
      readGallery(
        item({
          title: 'Before and after',
          images: [
            { path: '/tmp/shots/before.png', caption: 'the old header' },
            { path: '/tmp/shots/after.png' },
          ],
        }),
      ),
    ).toEqual({
      title: 'Before and after',
      images: [
        {
          path: '/tmp/shots/before.png',
          caption: 'the old header',
          description: null,
          source: null,
        },
        {
          path: '/tmp/shots/after.png',
          caption: null,
          description: null,
          source: null,
        },
      ],
    });
  });

  it('reads the bare-string entry, matching what its daemon twin accepts', () => {
    // Twin PARITY, not back-compatibility: nothing persisted arrives in this
    // shape (the daemon normalizes before writing the row), but a twin that
    // accepts less than its writer can produce is a twin that disagrees, and
    // the two readers are only checkable against each other while they agree.
    expect(readGallery(item({ images: ['a.png'] }))).toEqual({
      title: null,
      images: [
        { path: 'a.png', caption: null, description: null, source: null },
      ],
    });
  });

  it('accepts `src` as a synonym for `path`, like its twin', () => {
    expect(readGallery(item({ images: [{ src: 'a.png' }] }))).toEqual({
      title: null,
      images: [
        { path: 'a.png', caption: null, description: null, source: null },
      ],
    });
  });

  it('accepts `url` as a synonym for `path`, like its twin', () => {
    expect(
      readGallery(item({ images: [{ url: 'https://cdn.example/a.png' }] })),
    ).toEqual({
      title: null,
      images: [
        {
          path: 'https://cdn.example/a.png',
          caption: null,
          description: null,
          source: null,
        },
      ],
    });
  });

  it('reads a description and the URL a downloaded picture came from', () => {
    expect(
      readGallery(
        item({
          images: [
            {
              path: '/u/attachments/r1/x.png',
              caption: 'Khinkali',
              description: '5 pcs\n2 400 ₸',
              source: 'https://cdn.example/khinkali.png',
            },
          ],
        }),
      ),
    ).toEqual({
      title: null,
      images: [
        {
          path: '/u/attachments/r1/x.png',
          caption: 'Khinkali',
          description: '5 pcs\n2 400 ₸',
          source: 'https://cdn.example/khinkali.png',
        },
      ],
    });
  });

  it('drops an entry naming no file and keeps the rest', () => {
    // DROPPED rather than blanked, unlike `readChart`'s labels: a gallery is a
    // SET, so no tile is read by its index and removing one re-attributes
    // nothing. A blank tile would be a picture-shaped hole instead.
    expect(
      readGallery(
        item({
          images: [{ path: 'a.png' }, { caption: 'orphan' }, 7, 'b.png'],
        }),
      ),
    ).toEqual({
      title: null,
      images: [
        { path: 'a.png', caption: null, description: null, source: null },
        { path: 'b.png', caption: null, description: null, source: null },
      ],
    });
  });

  it('answers null when the row names no picture at all', () => {
    expect(readGallery(item({ images: [] }))).toBeNull();
    expect(
      readGallery(item({ images: [{ caption: 'only a caption' }] })),
    ).toBeNull();
    expect(readGallery(item({ images: 'a.png' }))).toBeNull();
    expect(readGallery(item({}))).toBeNull();
    expect(readGallery(item(null))).toBeNull();
    expect(readGallery(item('a.png'))).toBeNull();
  });

  it('treats a blank title and a blank caption as absent', () => {
    // `null` and not `''`: the card branches on the title being present, and an
    // empty string is a heading that renders as a gap above the grid.
    expect(
      readGallery(
        item({ title: '  ', images: [{ path: 'a.png', caption: '' }] }),
      ),
    ).toEqual({
      title: null,
      images: [
        { path: 'a.png', caption: null, description: null, source: null },
      ],
    });
  });
});
