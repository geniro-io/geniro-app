import type { ItemDto as ChatItem } from '../autogenerated';

/**
 * A set of pictures an agent handed the app to show, read off the transcript.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/chat.types.ts` declares the shape
 * (`HostGallery`) and `apps/daemon/src/v1/agents/utils/host-gallery.ts` writes
 * these keys for the `show_gallery` item kind. An item payload is `z.unknown()`
 * on the wire BY DESIGN — every kind carries a different shape — so no generated
 * type reaches here and this is an independent reading of one shape. A key
 * renamed on either side must be renamed on both.
 *
 * What this payload holds that no other card's does is PATHS rather than
 * content: nothing here is the picture, only where it is. Resolving one is the
 * card's job, through the same loader a markdown image already uses, so this
 * file neither reads nor validates a file — a path that names nothing costs one
 * broken tile, which is the loader's failure to draw and not this reader's to
 * catch.
 */

/** One picture in the gallery. */
export interface GalleryImage {
  path: string;
  /** Null when the agent named none; the tile then shows the picture alone. */
  caption: string | null;
}

/** One `show_gallery` row, as the card draws it. */
export interface GallerySpec {
  /** Null when the agent named none; the card supplies its own heading. */
  title: string | null;
  images: GalleryImage[];
}

function readString(value: unknown): string | null {
  if (typeof value !== 'string') {
    return null;
  }
  const trimmed = value.trim();
  return trimmed.length === 0 ? null : trimmed;
}

/**
 * One entry, or null when it names no file.
 *
 * Accepts the bare-string and `src` forms as well as the documented object,
 * which is twin-PARITY rather than leniency this side needs: the daemon's
 * reader accepts them from the model, and a twin that accepts less than its
 * writer can produce is a twin that disagrees. Nothing persisted reaches here
 * in those shapes today — `readHostGallery` normalizes every entry before the
 * row is written — so the parity is what keeps the two readers checkable
 * against each other, not a back-compatibility allowance.
 */
function readImage(value: unknown): GalleryImage | null {
  const bare = readString(value);
  if (bare !== null) {
    return { path: bare, caption: null };
  }
  if (typeof value !== 'object' || value === null) {
    return null;
  }
  const entry = value as { path?: unknown; src?: unknown; caption?: unknown };
  const path = readString(entry.path) ?? readString(entry.src);
  if (path === null) {
    return null;
  }
  return { path, caption: readString(entry.caption) };
}

/**
 * Read one `show_gallery` row, or null when the payload names no picture.
 *
 * Null on the chart reader's rule rather than the findings reader's: an empty
 * review IS a result worth a card saying so, while a gallery with no pictures
 * has nothing to draw and no sentence to put in its place. The daemon already
 * refuses that call at the tool edge, so reaching it here means a row written by
 * an older build.
 *
 * Entries that name no file are DROPPED rather than blanked — a gallery is a
 * SET, not the chart's positional axis, so nothing downstream reads a tile by
 * its index and removing one re-attributes nothing.
 */
export function readGallery(item: ChatItem): GallerySpec | null {
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const row = payload as { title?: unknown; images?: unknown };
  if (!Array.isArray(row.images)) {
    return null;
  }
  const images = row.images
    .map(readImage)
    .filter((image): image is GalleryImage => image !== null);
  if (images.length === 0) {
    return null;
  }
  return { title: readString(row.title), images };
}
