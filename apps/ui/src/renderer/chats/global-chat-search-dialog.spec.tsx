// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type {
  ChatsApi,
  GlobalChatSearchHit,
  GlobalChatSearchResultDto,
} from '../autogenerated';
import { GlobalChatSearchDialog } from './global-chat-search-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const HIT: GlobalChatSearchHit = {
  runId: 'run-1',
  itemId: 'item-1',
  memberId: null,
  seq: 12,
  kind: 'message',
  role: 'assistant',
  snippet: 'проверка платежей прошла',
  createdAt: '2026-01-01T00:00:00.000Z',
  title: 'Billing',
  cwd: '/shop',
  archived: true,
  score: 3,
};

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function mount(
  searchAllChats: ReturnType<typeof vi.fn>,
  onJump = vi.fn(),
): void {
  const chatApi = { searchAllChats } as unknown as ChatsApi;
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <GlobalChatSearchDialog
        open
        chatApi={chatApi}
        onClose={() => undefined}
        onJump={onJump}
      />,
    );
  });
}

async function type(value: string): Promise<void> {
  const input = document.querySelector('input')!;
  act(() => {
    Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )!.set!.call(input, value);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
  await act(async () => {
    await vi.advanceTimersByTimeAsync(400);
  });
}

beforeEach(() => {
  vi.useFakeTimers({ shouldAdvanceTime: true });
});

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

describe('GlobalChatSearchDialog', () => {
  it('asks for the words alone once two characters are typed, and draws the hits', async () => {
    const result: GlobalChatSearchResultDto = {
      hits: [HIT],
      partialReason: 'Showing the best 30 matches — add a word to narrow it.',
    };
    const searchAllChats = vi.fn().mockResolvedValue(result);
    mount(searchAllChats);

    await type('п');
    expect(searchAllChats).not.toHaveBeenCalled();

    await type('платеж');
    expect(searchAllChats).toHaveBeenCalledTimes(1);
    expect(searchAllChats.mock.calls[0]![0]).toEqual({ query: 'платеж' });
    const text = document.body.textContent ?? '';
    expect(text).toContain('Billing');
    expect(text).toContain('проверка платежей прошла');
    expect(text).toContain('Archived');
    expect(text).toContain('1 match');
    expect(text).toContain('add a word to narrow it');
  });

  it('jumps to the hit that is pressed', async () => {
    const onJump = vi.fn();
    mount(
      vi.fn().mockResolvedValue({ hits: [HIT], partialReason: null }),
      onJump,
    );
    await type('платеж');
    const row = [...document.querySelectorAll('button')].find((button) =>
      button.textContent?.includes('Billing'),
    );
    act(() => {
      row!.click();
    });
    expect(onJump).toHaveBeenCalledWith(HIT);
  });

  it('shows why a search failed', async () => {
    mount(vi.fn().mockRejectedValue(new Error('daemon is down')));
    await type('платеж');
    expect(document.body.textContent).toContain('Could not search chats');
  });
});
