import { useMemo } from 'react';

import type { ChatsApi, GlobalChatSearchHit } from '../autogenerated';
import { EmptyState } from '../components/empty-state';
import { ErrorText } from '../components/error-text';
import {
  SearchField,
  SearchResultList,
  SearchSnippet,
} from '../components/search-panel';
import { Dialog } from '../components/ui/dialog';
import { useDaemonSearch } from './use-chat-search';

export function GlobalChatSearchDialog({
  open,
  chatApi,
  onClose,
  onJump,
}: {
  open: boolean;
  chatApi: ChatsApi;
  onClose: () => void;
  onJump: (hit: GlobalChatSearchHit) => void;
}): React.JSX.Element {
  // Asked only while the dialog is open; a closed one holds no answer.
  const ask = useMemo(
    () =>
      open ? (term: string) => chatApi.searchAllChats({ query: term }) : null,
    [open, chatApi],
  );
  const { query, setQuery, hits, partialReason, loading, error, tooShort } =
    useDaemonSearch(ask, 'Could not search chats. Try again.');
  const term = query.trim();
  const answered = term.length > 0 && !tooShort && !loading && !error;

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Search all chats"
      className="h-[min(48rem,100%)] w-[min(48rem,calc(100vw-2rem))] max-w-none">
      <div className="flex h-full min-h-0 flex-col gap-3">
        <p className="shrink-0 text-sm text-muted-foreground">
          Every word must appear, and each word also finds longer ones it begins
          — <span className="text-foreground">платеж</span> finds платежей.
          Searches every project, archived chats included.
        </p>
        <SearchField
          label="Search all chats"
          placeholder="Words you remember"
          value={query}
          onValueChange={setQuery}
          autoFocus
          className="shrink-0"
        />
        {error ? <ErrorText>{error}</ErrorText> : null}
        {answered ? (
          <p role="status" className="shrink-0 text-xs text-muted-foreground">
            {hits.length} {hits.length === 1 ? 'match' : 'matches'}
          </p>
        ) : null}
        <SearchResultList
          loading={loading}
          loadingLabel="Searching all chats…"
          partialReason={partialReason}
          isEmpty={hits.length === 0}
          empty={
            <EmptyState>
              {term.length === 0
                ? 'Type words from the conversation you are looking for.'
                : tooShort
                  ? 'Type at least two characters.'
                  : 'No matching messages.'}
            </EmptyState>
          }>
          <ul className="m-0 flex list-none flex-col p-1">
            {hits.map((hit) => (
              <li key={hit.itemId}>
                <button
                  type="button"
                  onClick={() => onJump(hit)}
                  className="flex w-full cursor-pointer flex-col items-start gap-1 rounded-md px-3 py-3 text-left hover:bg-sidebar-accent">
                  <span className="flex w-full items-baseline gap-2 text-sm text-foreground">
                    <span className="min-w-0 flex-1 truncate font-medium">
                      {hit.title ?? 'Untitled chat'}
                    </span>
                    {hit.archived ? (
                      <span className="shrink-0 text-xs text-muted-foreground">
                        Archived
                      </span>
                    ) : null}
                  </span>
                  <SearchSnippet>{hit.snippet}</SearchSnippet>
                  <span className="flex w-full flex-wrap gap-x-2 text-xs text-muted-foreground">
                    <span>
                      {hit.role === 'user'
                        ? 'You'
                        : hit.kind === 'reasoning'
                          ? 'Reasoning'
                          : 'Assistant'}
                    </span>
                    <span>{new Date(hit.createdAt).toLocaleString()}</span>
                    {hit.cwd ? (
                      <span className="min-w-0 truncate" title={hit.cwd}>
                        {hit.cwd}
                      </span>
                    ) : null}
                  </span>
                </button>
              </li>
            ))}
          </ul>
        </SearchResultList>
      </div>
    </Dialog>
  );
}
