import { useEffect, useState } from 'react';

import type {
  ChatsApi,
  GlobalChatSearchHit,
  GlobalChatSearchResultDto,
} from '../autogenerated';
import { EmptyState } from '../components/empty-state';
import { ErrorText } from '../components/error-text';
import {
  SearchField,
  SearchResultList,
  SearchSnippet,
} from '../components/search-panel';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { SegmentedControl } from '../components/ui/segmented-control';
import { daemonErrorDetail } from '../daemon-api';

type SearchMode = GlobalChatSearchResultDto['mode'];
const MODES: readonly { id: SearchMode; label: string }[] = [
  { id: 'hybrid', label: 'Meaning + text' },
  { id: 'semantic', label: 'Meaning' },
  { id: 'keyword', label: 'Text' },
];

export function GlobalChatSearchDialog({
  open,
  chatApi,
  onClose,
  onJump,
}: {
  open: boolean;
  chatApi: ChatsApi;
  onClose: () => void;
  onJump: (hit: GlobalChatSearchHit) => void;
}): React.JSX.Element {
  const [query, setQuery] = useState('');
  const [mode, setMode] = useState<SearchMode>('hybrid');
  const [result, setResult] = useState<GlobalChatSearchResultDto | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [refresh, setRefresh] = useState(0);
  const term = query.trim();

  useEffect(() => {
    setResult(null);
    setError(null);
    if (!open || term.length < 2) {
      setLoading(false);
      return;
    }
    let disposed = false;
    const controller = new AbortController();
    let timer: ReturnType<typeof setTimeout>;
    const search = async (): Promise<void> => {
      try {
        const found = await chatApi.searchAllChats(
          { query: term, mode },
          { signal: controller.signal },
        );
        if (disposed) {
          return;
        }
        setResult(found);
        setLoading(false);
        if (found.indexing) {
          timer = setTimeout(() => void search(), 2_000);
        }
      } catch (err) {
        if (disposed) {
          return;
        }
        setLoading(false);
        setError(
          daemonErrorDetail(err) ?? 'Could not search chats. Try again.',
        );
      }
    };
    setLoading(true);
    timer = setTimeout(() => void search(), 300);
    return () => {
      disposed = true;
      controller.abort();
      clearTimeout(timer);
    };
  }, [open, chatApi, term, mode, refresh]);

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Search all chats"
      className="h-[min(48rem,100%)] w-[min(48rem,calc(100vw-2rem))] max-w-none">
      <div className="flex h-full min-h-0 flex-col gap-3">
        <p className="shrink-0 text-sm text-muted-foreground">
          Find earlier decisions and conversations across every project,
          including archived chats.
        </p>
        <SearchField
          label="Search all chats"
          placeholder="What do you want to recall?"
          value={query}
          onValueChange={setQuery}
          autoFocus
          className="shrink-0"
        />
        <div className="flex shrink-0 flex-wrap items-center justify-between gap-2">
          <SegmentedControl
            ariaLabel="Search mode"
            options={MODES}
            value={mode}
            onSelect={setMode}
            size="sm"
          />
          <Button
            type="button"
            variant="ghost"
            size="sm"
            disabled={loading || term.length < 2}
            onClick={() => setRefresh((value) => value + 1)}>
            Refresh results
          </Button>
        </div>
        {error ? <ErrorText>{error}</ErrorText> : null}
        {result ? (
          <p role="status" className="shrink-0 text-xs text-muted-foreground">
            {result.mode === 'keyword'
              ? 'Text search'
              : result.mode === 'semantic'
                ? 'Search by meaning'
                : 'Meaning + text'}
            {' · '}
            {result.hits.length}{' '}
            {result.hits.length === 1 ? 'match' : 'matches'}
            {result.indexing ? ' · Indexing history…' : ''}
          </p>
        ) : null}
        <SearchResultList
          loading={loading}
          loadingLabel="Searching all chats…"
          partialReason={result?.partialReason}
          isEmpty={!result?.hits.length}
          empty={
            <EmptyState>
              {term.length === 0
                ? 'Describe what you remember, or type exact words.'
                : term.length < 2
                  ? 'Type at least two characters.'
                  : result?.indexing
                    ? 'Building the local search index…'
                    : 'No matching messages.'}
            </EmptyState>
          }>
          <ul className="m-0 flex list-none flex-col p-1">
            {result?.hits.map((hit) => (
              <li key={`${hit.runId}:${hit.seq}:${hit.createdAt}`}>
                <button
                  type="button"
                  onClick={() => onJump(hit)}
                  className="flex w-full cursor-pointer flex-col items-start gap-1 rounded-md px-3 py-3 text-left hover:bg-sidebar-accent">
                  <span className="flex w-full items-baseline gap-2 text-sm text-foreground">
                    <span className="min-w-0 flex-1 truncate font-medium">
                      {hit.title ?? 'Untitled chat'}
                    </span>
                    {hit.archived ? (
                      <span className="shrink-0 text-xs text-muted-foreground">
                        Archived
                      </span>
                    ) : null}
                  </span>
                  <SearchSnippet>{hit.snippet}</SearchSnippet>
                  <span className="flex w-full flex-wrap gap-x-2 text-xs text-muted-foreground">
                    <span>
                      {hit.role === 'user'
                        ? 'You'
                        : hit.kind === 'message'
                          ? 'Assistant'
                          : hit.kind.replaceAll('_', ' ')}
                    </span>
                    <span>{new Date(hit.createdAt).toLocaleString()}</span>
                    {hit.cwd ? (
                      <span className="min-w-0 truncate" title={hit.cwd}>
                        {hit.cwd}
                      </span>
                    ) : null}
                  </span>
                </button>
              </li>
            ))}
          </ul>
        </SearchResultList>
      </div>
    </Dialog>
  );
}
