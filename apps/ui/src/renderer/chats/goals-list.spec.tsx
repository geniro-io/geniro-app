// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { RunGoal } from '../autogenerated';
import { type GoalsActions, goalsFigure, GoalsList } from './goals-list';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const goal = (patch: Partial<RunGoal>): RunGoal => ({
  id: 'g1',
  text: 'the export saves a csv',
  source: 'agent',
  status: 'open',
  evidence: null,
  memberId: null,
  createdAt: '2026-11-01T00:00:00.000Z',
  closedAt: null,
  ...patch,
});

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  document.body.innerHTML = '';
});

function actions(): GoalsActions &
  Record<keyof GoalsActions, ReturnType<typeof vi.fn>> {
  return {
    add: vi.fn(async () => ({})),
    edit: vi.fn(async () => ({})),
    close: vi.fn(async () => ({})),
    reopen: vi.fn(async () => ({})),
  };
}

function typeInto(
  input: HTMLInputElement | HTMLTextAreaElement,
  value: string,
): void {
  const setter = Object.getOwnPropertyDescriptor(
    Object.getPrototypeOf(input) as object,
    'value',
  )?.set;
  setter?.call(input, value);
  input.dispatchEvent(new Event('input', { bubbles: true }));
}

describe('GoalsList', () => {
  it('draws each goal with how it closed and its evidence, and who set it', () => {
    act(() =>
      root.render(
        <GoalsList
          goals={[
            goal({
              status: 'achieved',
              evidence: 'saved report.csv',
              memberId: 'dev',
            }),
            goal({
              id: 'g2',
              text: 'the readme names it',
              status: 'dropped',
              evidence: 'user said skip',
            }),
          ]}
          nameOf={(id) => (id === 'dev' ? 'Developer' : id)}
        />,
      ),
    );
    const rows = [...container.querySelectorAll('[data-goal-id]')];
    expect(rows).toHaveLength(2);
    expect(rows[0]?.textContent).toContain('Achieved: saved report.csv');
    expect(rows[0]?.textContent).toContain('closed by Developer');
    expect(rows[1]?.textContent).toContain('Dropped: user said skip');
    expect(container.querySelector('input[aria-label="New goal"]')).toBeNull();
  });

  it('adds a goal through the daemon and clears the field once it answered', async () => {
    const hand = actions();
    act(() => root.render(<GoalsList goals={[]} actions={hand} />));
    const field = container.querySelector<HTMLInputElement>(
      'input[aria-label="New goal"]',
    )!;
    act(() => typeInto(field, '  ship the button '));
    await act(async () => {
      container
        .querySelector('form')!
        .dispatchEvent(
          new Event('submit', { bubbles: true, cancelable: true }),
        );
    });
    expect(hand.add).toHaveBeenCalledWith('ship the button');
    expect(field.value).toBe('');
  });

  it('closes a goal only with evidence, and reopens a closed one', async () => {
    const hand = actions();
    act(() =>
      root.render(
        <GoalsList
          goals={[
            goal({}),
            goal({ id: 'g2', status: 'not_achieved', evidence: 'red' }),
          ]}
          actions={hand}
        />,
      ),
    );
    act(() =>
      container
        .querySelector<HTMLButtonElement>('button[aria-label="Close g1…"]')!
        .click(),
    );
    const submit = [
      ...document.querySelectorAll<HTMLButtonElement>('button'),
    ].find((button) => button.textContent === 'Close goal')!;
    expect(submit.disabled).toBe(true);
    act(() =>
      typeInto(
        document.querySelector<HTMLTextAreaElement>(
          'textarea[aria-label="Evidence"]',
        )!,
        'the spec passes',
      ),
    );
    expect(submit.disabled).toBe(false);
    await act(async () => submit.click());
    expect(hand.close).toHaveBeenCalledWith(
      'g1',
      'achieved',
      'the spec passes',
    );

    await act(async () =>
      container
        .querySelector<HTMLButtonElement>('button[aria-label="Reopen g2"]')!
        .click(),
    );
    expect(hand.reopen).toHaveBeenCalledWith('g2');
  });

  it('shows the daemon’s refusal', async () => {
    const hand = actions();
    hand.add.mockRejectedValueOnce(new Error('a run holds at most 40 goals'));
    act(() => root.render(<GoalsList goals={[]} actions={hand} />));
    act(() =>
      typeInto(
        container.querySelector<HTMLInputElement>(
          'input[aria-label="New goal"]',
        )!,
        'one more',
      ),
    );
    await act(async () => {
      container
        .querySelector('form')!
        .dispatchEvent(
          new Event('submit', { bubbles: true, cancelable: true }),
        );
    });
    expect(container.querySelector('[role="alert"]')).not.toBeNull();
  });
});

describe('goalsFigure', () => {
  it('counts achieved over the goals not dropped', () => {
    expect(
      goalsFigure([
        goal({ status: 'achieved' }),
        goal({ status: 'open' }),
        goal({ status: 'dropped' }),
      ]),
    ).toBe('1/2');
    expect(goalsFigure([goal({ status: 'dropped' })])).toBeNull();
  });
});
