import { Check, CircleSlash, Pencil, Plus, RotateCcw, X } from 'lucide-react';
import { useState } from 'react';

import type {
  CloseRunGoalDtoGoalClosingStatus,
  RunGoal,
  ThreadOutcome,
} from '../autogenerated';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { SegmentedControl } from '../components/ui/segmented-control';
import { Textarea } from '../components/ui/textarea';
import { cn } from '../components/ui/utils';
import { daemonErrorDetail } from '../daemon-api';

/** The user's hand on a run's goals — each a daemon route; the list comes back on `run_status`. */
export interface GoalsActions {
  add: (text: string) => Promise<unknown>;
  edit: (goalId: string, text: string) => Promise<unknown>;
  close: (
    goalId: string,
    status: CloseRunGoalDtoGoalClosingStatus,
    evidence: string,
  ) => Promise<unknown>;
  reopen: (goalId: string) => Promise<unknown>;
}

export const GOAL_STATUS_LABEL: Record<RunGoal['status'], string> = {
  open: 'Open',
  achieved: 'Achieved',
  not_achieved: 'Not achieved',
  dropped: 'Dropped',
};

export const OUTCOME_LABEL: Record<ThreadOutcome['kind'], string> = {
  success: 'Success',
  partial: 'Partial',
  failed: 'Failed',
  abandoned: 'Abandoned',
};

const SOURCE_LABEL: Record<RunGoal['source'], string> = {
  user: 'Requested',
  agent: 'Inferred',
};

const statusChip = cva(
  'mt-px flex size-6 shrink-0 items-center justify-center rounded-full [&_svg]:size-3.5',
  {
    variants: {
      status: {
        open: 'border-[1.5px] border-dashed border-border-strong',
        achieved: 'bg-success/10 text-success',
        not_achieved: 'bg-destructive/10 text-destructive',
        dropped: 'bg-muted/60 text-muted-foreground',
      },
    },
  },
);

const goalRow = cva(
  'group flex items-start gap-3 rounded-lg border px-3 py-2.5 transition-colors',
  {
    variants: {
      status: {
        open: 'border-border bg-card shadow-panel-sm',
        achieved: 'border-border bg-card shadow-panel-sm',
        not_achieved: 'border-border bg-card shadow-panel-sm',
        dropped: 'border-dashed border-border bg-transparent',
      },
    },
  },
);

const evidenceBlock = cva(
  'mt-2 rounded-md border-l-2 bg-muted/40 px-2.5 py-1.5 text-xs leading-relaxed break-words text-muted-foreground',
  {
    variants: {
      status: {
        open: 'border-l-border',
        achieved: 'border-l-success/60',
        not_achieved: 'border-l-destructive/60',
        dropped: 'border-l-border',
      },
    },
  },
);

const STATUS_ICON = {
  open: null,
  achieved: Check,
  not_achieved: X,
  dropped: CircleSlash,
} as const;

type GoalClosingStatus = CloseRunGoalDtoGoalClosingStatus;

const CLOSING_OPTIONS: { id: GoalClosingStatus; label: string }[] = [
  { id: 'achieved', label: 'Achieved' },
  { id: 'not_achieved', label: 'Not achieved' },
  { id: 'dropped', label: 'Dropped' },
];

/** How many of the goals not dropped were achieved, as `2/3`; null with none counted. */
export function goalsFigure(goals: readonly RunGoal[]): string | null {
  const counted = goals.filter((goal) => goal.status !== 'dropped');
  if (counted.length === 0) {
    return null;
  }
  const achieved = counted.filter((goal) => goal.status === 'achieved').length;
  return `${achieved}/${counted.length}`;
}

const SUMMARY_ORDER: readonly RunGoal['status'][] = [
  'open',
  'achieved',
  'not_achieved',
  'dropped',
];

/** The goals as one line of counts by status, `1 open · 2 achieved`. */
export function goalsSummary(goals: readonly RunGoal[]): string {
  if (goals.length === 0) {
    return 'No goals yet';
  }
  return SUMMARY_ORDER.flatMap((status) => {
    const count = goals.filter((goal) => goal.status === status).length;
    return count === 0
      ? []
      : [`${count} ${GOAL_STATUS_LABEL[status].toLowerCase()}`];
  }).join(' · ');
}

/**
 * A run's goals as the goals tool and the user left them: each with how it closed and
 * its evidence, the user's add, edit, close and reopen beside it. Nothing is changed
 * here until the daemon answers; its `run_status` announce brings the new list.
 */
export function GoalsList({
  goals,
  actions,
  nameOf,
}: {
  goals: readonly RunGoal[];
  /** Absent on an archived run, which is read only. */
  actions?: GoalsActions;
  /** The team member a goal was recorded by; absent in a chat. */
  nameOf?: (memberId: string) => string;
}): React.JSX.Element {
  const [draft, setDraft] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [editing, setEditing] = useState<{ id: string; text: string } | null>(
    null,
  );
  const [closing, setClosing] = useState<RunGoal | null>(null);

  const run = async (work: () => Promise<unknown>): Promise<boolean> => {
    setBusy(true);
    setError(null);
    try {
      await work();
      return true;
    } catch (err) {
      setError(daemonErrorDetail(err) ?? 'The goals could not be saved.');
      return false;
    } finally {
      setBusy(false);
    }
  };

  return (
    <div data-slot="goals-list" className="flex flex-col gap-2">
      {goals.length === 0 ? null : (
        <ul className="m-0 flex list-none flex-col gap-1.5 p-0">
          {goals.map((goal) => {
            const Icon = STATUS_ICON[goal.status];
            return (
              <li
                key={goal.id}
                data-goal-id={goal.id}
                data-status={goal.status}
                className={goalRow({ status: goal.status })}>
                <span
                  role="img"
                  aria-label={GOAL_STATUS_LABEL[goal.status]}
                  className={statusChip({ status: goal.status })}>
                  {Icon === null ? null : <Icon aria-hidden="true" />}
                </span>
                <div className="flex min-w-0 flex-1 flex-col">
                  {editing?.id === goal.id ? (
                    <form
                      className="flex gap-1.5"
                      onSubmit={(event) => {
                        event.preventDefault();
                        const text = editing.text.trim();
                        if (text.length === 0 || actions === undefined) {
                          return;
                        }
                        void run(() => actions.edit(goal.id, text)).then(
                          (saved) => {
                            if (saved) {
                              setEditing(null);
                            }
                          },
                        );
                      }}>
                      <Input
                        aria-label={`Edit ${goal.id}`}
                        value={editing.text}
                        autoFocus
                        className="h-8"
                        onChange={(event) =>
                          setEditing({ id: goal.id, text: event.target.value })
                        }
                      />
                      <Button type="submit" size="sm" disabled={busy}>
                        Save
                      </Button>
                      <Button
                        type="button"
                        size="sm"
                        variant="ghost"
                        onClick={() => setEditing(null)}>
                        Cancel
                      </Button>
                    </form>
                  ) : (
                    <span
                      data-slot="goal-text"
                      className={cn(
                        'text-sm leading-snug break-words text-foreground',
                        goal.status === 'dropped' &&
                          'text-muted-foreground line-through',
                      )}>
                      {goal.text}
                    </span>
                  )}
                  <span
                    data-slot="goal-meta"
                    className="mt-1 flex flex-wrap items-center gap-x-1.5 text-[11px] text-muted-foreground">
                    <span>{GOAL_STATUS_LABEL[goal.status]}</span>
                    <span aria-hidden="true">·</span>
                    <span
                      title={
                        goal.source === 'user'
                          ? 'The user asked for it in so many words'
                          : 'The agent read it from the task'
                      }>
                      {SOURCE_LABEL[goal.source]}
                    </span>
                    {goal.memberId !== null && nameOf !== undefined ? (
                      <>
                        <span aria-hidden="true">·</span>
                        <span>
                          {goal.status === 'open' ? 'set' : 'closed'} by{' '}
                          {nameOf(goal.memberId)}
                        </span>
                      </>
                    ) : null}
                  </span>
                  {goal.evidence === null ? null : (
                    <p
                      data-slot="goal-evidence"
                      className={evidenceBlock({ status: goal.status })}>
                      {goal.evidence}
                    </p>
                  )}
                </div>
                {actions === undefined || editing?.id === goal.id ? null : (
                  <span className="-mt-0.5 -mr-1 flex shrink-0 gap-0.5 opacity-50 transition-opacity group-hover:opacity-100 focus-within:opacity-100">
                    <Button
                      type="button"
                      variant="ghost"
                      size="icon"
                      className="size-7"
                      aria-label={`Edit ${goal.id}`}
                      title="Edit"
                      disabled={busy}
                      onClick={() =>
                        setEditing({ id: goal.id, text: goal.text })
                      }>
                      <Pencil aria-hidden="true" className="size-3.5" />
                    </Button>
                    {goal.status === 'open' ? (
                      <Button
                        type="button"
                        variant="ghost"
                        size="icon"
                        className="size-7"
                        aria-label={`Close ${goal.id}…`}
                        title="Close with evidence…"
                        disabled={busy}
                        onClick={() => setClosing(goal)}>
                        <Check aria-hidden="true" className="size-3.5" />
                      </Button>
                    ) : (
                      <Button
                        type="button"
                        variant="ghost"
                        size="icon"
                        className="size-7"
                        aria-label={`Reopen ${goal.id}`}
                        title="Reopen"
                        disabled={busy}
                        onClick={() => void run(() => actions.reopen(goal.id))}>
                        <RotateCcw aria-hidden="true" className="size-3.5" />
                      </Button>
                    )}
                  </span>
                )}
              </li>
            );
          })}
        </ul>
      )}
      {actions === undefined ? null : (
        <form
          data-slot="goal-add"
          className="flex items-center gap-2 rounded-lg border border-dashed border-border-strong py-1 pr-1 pl-3 transition-[color,box-shadow,border-color] focus-within:border-solid focus-within:border-ring focus-within:ring-[3px] focus-within:ring-ring/50"
          onSubmit={(event) => {
            event.preventDefault();
            const text = draft.trim();
            if (text.length === 0) {
              return;
            }
            void run(() => actions.add(text)).then((saved) => {
              if (saved) {
                setDraft('');
              }
            });
          }}>
          <Plus
            aria-hidden="true"
            className="size-4 shrink-0 text-muted-foreground"
          />
          <Input
            aria-label="New goal"
            placeholder="Add a goal — one outcome you can check"
            value={draft}
            className="h-8 border-0 bg-transparent px-0 shadow-none focus-visible:ring-0"
            onChange={(event) => setDraft(event.target.value)}
          />
          <Button
            type="submit"
            size="sm"
            variant={draft.trim().length === 0 ? 'ghost' : 'default'}
            disabled={busy || draft.trim().length === 0}>
            Add
          </Button>
        </form>
      )}
      {error === null ? null : (
        <p role="alert" className="text-xs text-destructive">
          {error}
        </p>
      )}
      {actions === undefined ? null : (
        <CloseGoalDialog
          goal={closing}
          busy={busy}
          onClose={() => setClosing(null)}
          onSubmit={(status, evidence) => {
            if (closing === null) {
              return;
            }
            void run(() => actions.close(closing.id, status, evidence)).then(
              (saved) => {
                if (saved) {
                  setClosing(null);
                }
              },
            );
          }}
        />
      )}
    </div>
  );
}

function CloseGoalDialog({
  goal,
  busy,
  onClose,
  onSubmit,
}: {
  goal: RunGoal | null;
  busy: boolean;
  onClose: () => void;
  onSubmit: (status: GoalClosingStatus, evidence: string) => void;
}): React.JSX.Element {
  const [status, setStatus] = useState<GoalClosingStatus>('achieved');
  const [evidence, setEvidence] = useState('');
  return (
    <Dialog
      open={goal !== null}
      onClose={onClose}
      title={goal === null ? 'Close goal' : `Close ${goal.id}`}
      className="max-w-md">
      <form
        className="flex flex-col gap-3"
        onSubmit={(event) => {
          event.preventDefault();
          if (evidence.trim().length > 0) {
            onSubmit(status, evidence.trim());
          }
        }}>
        <p className="rounded-md bg-muted/40 px-3 py-2 text-sm">{goal?.text}</p>
        <SegmentedControl
          ariaLabel="How the goal ended"
          options={CLOSING_OPTIONS}
          value={status}
          onSelect={setStatus}
        />
        <Textarea
          aria-label="Evidence"
          placeholder="What shows it — a test run, a link, a file, or why it was dropped"
          value={evidence}
          rows={3}
          onChange={(event) => setEvidence(event.target.value)}
        />
        <div className="flex justify-end gap-2">
          <Button type="button" variant="ghost" onClick={onClose}>
            Cancel
          </Button>
          <Button type="submit" disabled={busy || evidence.trim().length === 0}>
            Close goal
          </Button>
        </div>
      </form>
    </Dialog>
  );
}
