import { cva } from 'class-variance-authority';
import { Check, Circle, CircleSlash, Pencil, RotateCcw, X } from 'lucide-react';
import { useState } from 'react';

import type {
  CloseRunGoalDtoGoalClosingStatus,
  RunGoal,
  ThreadOutcome,
} from '../autogenerated';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { SegmentedControl } from '../components/ui/segmented-control';
import { Textarea } from '../components/ui/textarea';
import { cn } from '../components/ui/utils';
import { daemonErrorDetail } from '../daemon-api';

/** The user's hand on a run's goals — each a daemon route; the list comes back on `run_status`. */
export interface GoalsActions {
  add: (text: string) => Promise<unknown>;
  edit: (goalId: string, text: string) => Promise<unknown>;
  close: (
    goalId: string,
    status: CloseRunGoalDtoGoalClosingStatus,
    evidence: string,
  ) => Promise<unknown>;
  reopen: (goalId: string) => Promise<unknown>;
}

export const GOAL_STATUS_LABEL: Record<RunGoal['status'], string> = {
  open: 'Open',
  achieved: 'Achieved',
  not_achieved: 'Not achieved',
  dropped: 'Dropped',
};

export const OUTCOME_LABEL: Record<ThreadOutcome['kind'], string> = {
  success: 'Success',
  partial: 'Partial',
  failed: 'Failed',
  abandoned: 'Abandoned',
};

const statusMark = cva('mt-0.5 size-3.5 shrink-0', {
  variants: {
    status: {
      open: 'text-muted-foreground',
      achieved: 'text-success',
      not_achieved: 'text-destructive',
      dropped: 'text-muted-foreground',
    },
  },
});

const STATUS_ICON = {
  open: Circle,
  achieved: Check,
  not_achieved: X,
  dropped: CircleSlash,
} as const;

type GoalClosingStatus = CloseRunGoalDtoGoalClosingStatus;

const CLOSING_OPTIONS: { id: GoalClosingStatus; label: string }[] = [
  { id: 'achieved', label: 'Achieved' },
  { id: 'not_achieved', label: 'Not achieved' },
  { id: 'dropped', label: 'Dropped' },
];

/** How many of the goals not dropped were achieved, as `2/3`; null with none counted. */
export function goalsFigure(goals: readonly RunGoal[]): string | null {
  const counted = goals.filter((goal) => goal.status !== 'dropped');
  if (counted.length === 0) {
    return null;
  }
  const achieved = counted.filter((goal) => goal.status === 'achieved').length;
  return `${achieved}/${counted.length}`;
}

/**
 * A run's goals as the goals tool and the user left them: each with how it closed and
 * its evidence, the user's add, edit, close and reopen beside it. Nothing is changed
 * here until the daemon answers; its `run_status` announce brings the new list.
 */
export function GoalsList({
  goals,
  actions,
  nameOf,
}: {
  goals: readonly RunGoal[];
  /** Absent on an archived run, which is read only. */
  actions?: GoalsActions;
  /** The team member a goal was recorded by; absent in a chat. */
  nameOf?: (memberId: string) => string;
}): React.JSX.Element {
  const [draft, setDraft] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [editing, setEditing] = useState<{ id: string; text: string } | null>(
    null,
  );
  const [closing, setClosing] = useState<RunGoal | null>(null);

  const run = async (work: () => Promise<unknown>): Promise<boolean> => {
    setBusy(true);
    setError(null);
    try {
      await work();
      return true;
    } catch (err) {
      setError(daemonErrorDetail(err) ?? 'The goals could not be saved.');
      return false;
    } finally {
      setBusy(false);
    }
  };

  return (
    <div data-slot="goals-list" className="flex flex-col gap-2">
      {goals.length === 0 ? (
        <p className="text-xs text-muted-foreground">
          No goals yet. The agent records them at the start of a task, or add
          one here.
        </p>
      ) : (
        <ul className="m-0 flex list-none flex-col gap-1.5 p-0">
          {goals.map((goal) => {
            const Icon = STATUS_ICON[goal.status];
            return (
              <li
                key={goal.id}
                data-goal-id={goal.id}
                className="group flex items-start gap-2 text-sm">
                <Icon
                  aria-label={GOAL_STATUS_LABEL[goal.status]}
                  className={statusMark({ status: goal.status })}
                />
                <div className="flex min-w-0 flex-1 flex-col gap-0.5">
                  {editing?.id === goal.id ? (
                    <form
                      className="flex gap-1"
                      onSubmit={(event) => {
                        event.preventDefault();
                        const text = editing.text.trim();
                        if (text.length === 0 || actions === undefined) {
                          return;
                        }
                        void run(() => actions.edit(goal.id, text)).then(
                          (saved) => {
                            if (saved) {
                              setEditing(null);
                            }
                          },
                        );
                      }}>
                      <Input
                        aria-label={`Edit ${goal.id}`}
                        value={editing.text}
                        autoFocus
                        className="h-7"
                        onChange={(event) =>
                          setEditing({ id: goal.id, text: event.target.value })
                        }
                      />
                      <Button type="submit" size="sm" disabled={busy}>
                        Save
                      </Button>
                    </form>
                  ) : (
                    <span
                      className={cn(
                        'break-words',
                        goal.status === 'dropped' &&
                          'text-muted-foreground line-through',
                      )}>
                      {goal.text}
                    </span>
                  )}
                  {goal.evidence === null ? null : (
                    <span className="break-words text-xs text-muted-foreground">
                      {GOAL_STATUS_LABEL[goal.status]}: {goal.evidence}
                    </span>
                  )}
                  {goal.memberId !== null && nameOf !== undefined ? (
                    <span className="text-[11px] text-muted-foreground">
                      {goal.status === 'open' ? 'set' : 'closed'} by{' '}
                      {nameOf(goal.memberId)}
                    </span>
                  ) : null}
                </div>
                {actions === undefined || editing?.id === goal.id ? null : (
                  <span className="flex shrink-0 gap-0.5 opacity-60 group-hover:opacity-100 focus-within:opacity-100">
                    <Button
                      type="button"
                      variant="ghost"
                      size="icon"
                      className="size-6"
                      aria-label={`Edit ${goal.id}`}
                      title="Edit"
                      disabled={busy}
                      onClick={() =>
                        setEditing({ id: goal.id, text: goal.text })
                      }>
                      <Pencil aria-hidden="true" className="size-3" />
                    </Button>
                    {goal.status === 'open' ? (
                      <Button
                        type="button"
                        variant="ghost"
                        size="icon"
                        className="size-6"
                        aria-label={`Close ${goal.id}…`}
                        title="Close with evidence…"
                        disabled={busy}
                        onClick={() => setClosing(goal)}>
                        <Check aria-hidden="true" className="size-3" />
                      </Button>
                    ) : (
                      <Button
                        type="button"
                        variant="ghost"
                        size="icon"
                        className="size-6"
                        aria-label={`Reopen ${goal.id}`}
                        title="Reopen"
                        disabled={busy}
                        onClick={() => void run(() => actions.reopen(goal.id))}>
                        <RotateCcw aria-hidden="true" className="size-3" />
                      </Button>
                    )}
                  </span>
                )}
              </li>
            );
          })}
        </ul>
      )}
      {actions === undefined ? null : (
        <form
          className="flex gap-1"
          onSubmit={(event) => {
            event.preventDefault();
            const text = draft.trim();
            if (text.length === 0) {
              return;
            }
            void run(() => actions.add(text)).then((saved) => {
              if (saved) {
                setDraft('');
              }
            });
          }}>
          <Input
            aria-label="New goal"
            placeholder="Add a goal…"
            value={draft}
            className="h-7"
            onChange={(event) => setDraft(event.target.value)}
          />
          <Button
            type="submit"
            size="sm"
            variant="outline"
            disabled={busy || draft.trim().length === 0}>
            Add
          </Button>
        </form>
      )}
      {error === null ? null : (
        <p role="alert" className="text-xs text-destructive">
          {error}
        </p>
      )}
      {actions === undefined ? null : (
        <CloseGoalDialog
          goal={closing}
          busy={busy}
          onClose={() => setClosing(null)}
          onSubmit={(status, evidence) => {
            if (closing === null) {
              return;
            }
            void run(() => actions.close(closing.id, status, evidence)).then(
              (saved) => {
                if (saved) {
                  setClosing(null);
                }
              },
            );
          }}
        />
      )}
    </div>
  );
}

function CloseGoalDialog({
  goal,
  busy,
  onClose,
  onSubmit,
}: {
  goal: RunGoal | null;
  busy: boolean;
  onClose: () => void;
  onSubmit: (status: GoalClosingStatus, evidence: string) => void;
}): React.JSX.Element {
  const [status, setStatus] = useState<GoalClosingStatus>('achieved');
  const [evidence, setEvidence] = useState('');
  return (
    <Dialog
      open={goal !== null}
      onClose={onClose}
      title={goal === null ? 'Close goal' : `Close ${goal.id}`}
      className="max-w-md">
      <form
        className="flex flex-col gap-3"
        onSubmit={(event) => {
          event.preventDefault();
          if (evidence.trim().length > 0) {
            onSubmit(status, evidence.trim());
          }
        }}>
        <p className="text-sm">{goal?.text}</p>
        <SegmentedControl
          ariaLabel="How the goal ended"
          options={CLOSING_OPTIONS}
          value={status}
          onSelect={setStatus}
        />
        <Textarea
          aria-label="Evidence"
          placeholder="What shows it — a test run, a link, a file, or why it was dropped"
          value={evidence}
          rows={3}
          onChange={(event) => setEvidence(event.target.value)}
        />
        <div className="flex justify-end gap-2">
          <Button type="button" variant="ghost" onClick={onClose}>
            Cancel
          </Button>
          <Button type="submit" disabled={busy || evidence.trim().length === 0}>
            Close goal
          </Button>
        </div>
      </form>
    </Dialog>
  );
}
