// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { RunGoal } from '../autogenerated';
import { goalsSummary } from './goals-list';
import { GoalsSection, type RunGoals } from './goals-section';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLElement;
let root: Root;

const goal = (over: Partial<RunGoal>): RunGoal => ({
  id: 'g1',
  text: 'the export saves a csv',
  source: 'agent',
  status: 'open',
  evidence: null,
  memberId: null,
  createdAt: '2026-11-01T00:00:00.000Z',
  closedAt: null,
  ...over,
});

function mount(goals: RunGoals, onOpen: () => void = () => {}): void {
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  act(() => root.render(<GoalsSection goals={goals} onOpen={onOpen} />));
}

describe('goalsSummary', () => {
  it('counts the goals by status, open first, and says when there are none', () => {
    expect(goalsSummary([])).toBe('No goals yet');
    expect(
      goalsSummary([
        goal({ status: 'achieved' }),
        goal({ id: 'g2' }),
        goal({ id: 'g3', status: 'achieved' }),
        goal({ id: 'g4', status: 'dropped' }),
      ]),
    ).toBe('1 open · 2 achieved · 1 dropped');
  });
});

describe('GoalsSection', () => {
  afterEach(() => {
    act(() => root.unmount());
    container.remove();
  });

  it('is one row saying where the goals stand, which opens the progress popup', () => {
    const onOpen = vi.fn();
    mount(
      {
        goals: [goal({ status: 'achieved' }), goal({ id: 'g2' })],
        outcome: null,
      },
      onOpen,
    );
    const row = container.querySelector<HTMLButtonElement>(
      'section[aria-label="Goals"] button',
    )!;
    expect(row.textContent).toBe('1 open · 1 achieved');
    expect(
      container.querySelector('[data-slot="goals-figure"]')?.textContent,
    ).toBe('1/2 achieved');
    expect(container.querySelector('input')).toBeNull();
    act(() => row.click());
    expect(onOpen).toHaveBeenCalledTimes(1);
  });

  it('names the outcome beside the counts', () => {
    mount({
      goals: [goal({ status: 'achieved' })],
      outcome: { kind: 'success', source: 'goals', summary: null, seq: null },
    });
    expect(
      container.querySelector('[data-slot="panel-link-meta"]')?.textContent,
    ).toBe('Outcome: Success');
  });

  it('still offers the popup to a thread with no goals yet', () => {
    mount({ goals: [], outcome: null });
    expect(
      container.querySelector('section[aria-label="Goals"] button')
        ?.textContent,
    ).toBe('No goals yet');
  });
});
