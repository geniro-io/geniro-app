import type { RunGoal, ThreadOutcome } from '../autogenerated';
import { PanelSection } from '../components/panel-section';
import {
  type GoalsActions,
  goalsFigure,
  GoalsList,
  OUTCOME_LABEL,
} from './goals-list';

/** What the panel's Goals section draws: the run's goals, its outcome, and the user's hand on them. */
export interface RunGoals {
  goals: readonly RunGoal[];
  outcome: ThreadOutcome | null;
  actions?: GoalsActions;
}

/**
 * The agents panel's Goals section: what the thread set out to achieve, each goal's
 * evidence, and how the thread ended — the outcome an agent recorded, else the one its
 * goals give.
 */
export function GoalsSection({
  goals,
  nameOf,
}: {
  goals: RunGoals;
  nameOf?: (memberId: string) => string;
}): React.JSX.Element {
  const figure = goalsFigure(goals.goals);
  return (
    <PanelSection
      label="Goals"
      action={
        figure === null ? null : (
          <span
            data-slot="goals-figure"
            title="Achieved of the goals not dropped"
            className="text-[11px] text-muted-foreground tabular-nums">
            {figure} achieved
          </span>
        )
      }>
      {goals.outcome === null ? null : (
        <p data-slot="thread-outcome" className="text-xs">
          <span className="font-medium">
            Outcome: {OUTCOME_LABEL[goals.outcome.kind]}
          </span>
          <span className="text-muted-foreground">
            {goals.outcome.source === 'goals'
              ? ' · from the goals'
              : goals.outcome.summary === null
                ? ''
                : ` · ${goals.outcome.summary}`}
          </span>
        </p>
      )}
      <GoalsList goals={goals.goals} actions={goals.actions} nameOf={nameOf} />
    </PanelSection>
  );
}
