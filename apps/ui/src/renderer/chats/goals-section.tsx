import { Target } from 'lucide-react';

import type { RunGoal, ThreadOutcome } from '../autogenerated';
import { PanelActionRow } from '../components/panel-link-row';
import { PanelSection } from '../components/panel-section';
import {
  type GoalsActions,
  goalsFigure,
  goalsSummary,
  OUTCOME_LABEL,
} from './goals-list';

/** A run's goals, its outcome, and the user's hand on them — what the progress popup draws. */
export interface RunGoals {
  goals: readonly RunGoal[];
  outcome: ThreadOutcome | null;
  actions?: GoalsActions;
}

/**
 * The agents panel's Goals section: one row saying where the goals stand, which
 * opens the thread's progress popup, where they are read and changed.
 */
export function GoalsSection({
  goals,
  onOpen,
}: {
  goals: RunGoals;
  onOpen: () => void;
}): React.JSX.Element {
  const figure = goalsFigure(goals.goals);
  return (
    <PanelSection
      label="Goals"
      action={
        figure === null ? null : (
          <span
            data-slot="goals-figure"
            title="Achieved of the goals not dropped"
            className="text-[11px] text-muted-foreground tabular-nums">
            {figure} achieved
          </span>
        )
      }>
      <PanelActionRow
        onClick={onOpen}
        title={goalsSummary(goals.goals)}
        tooltip="Open the thread's progress"
        icon={
          <Target
            aria-hidden="true"
            className="size-3.5 shrink-0 text-muted-foreground"
          />
        }
        meta={
          goals.outcome === null
            ? undefined
            : `Outcome: ${OUTCOME_LABEL[goals.outcome.kind]}`
        }
      />
    </PanelSection>
  );
}
