// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import {
  RunGroupColor,
  type RunGroupDto,
  type WorkflowSummaryDto as WorkflowSummary,
} from '../autogenerated';
import { GroupHeader } from './group-header';
import type { RunGroupSummary } from './run-group';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function render(element: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(element);
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const GROUP: RunGroupDto = {
  id: 'g1',
  name: 'Work',
  color: RunGroupColor.Blue,
  position: 0,
  collapsed: false,
  autoCwd: null,
  autoWorkflowId: null,
};

const SUMMARY: RunGroupSummary = { count: 3, busy: false, needsInput: false };

const buttonNamed = (el: HTMLElement, text: string): HTMLButtonElement =>
  [...el.querySelectorAll('button')].find((b) => b.textContent === text)!;

describe('GroupHeader options menu', () => {
  it('sizes its raw <button> rows explicitly, never leaving them to the base rule', () => {
    // `OPTION_ROW` (the shared class string behind "Rename group" and "Delete
    // group") is a genuine ancestor of a plain `<button>` — but it carries its
    // own `text-sm` directly, so it is self-sized rather than leaning on
    // inheritance. `styles/global.css`'s base `button { font-size: … }` rule
    // would otherwise win, exactly as it did for the task list's heading
    // before `SectionLabel` gained its `[&_button]` override — see
    // `type-setting-wrappers.spec.ts`. This pins the OBSERVABLE proof: if a
    // future edit ever drops that token from `OPTION_ROW`, this fails instead
    // of the row quietly rendering oversized.
    const el = render(
      <GroupHeader
        group={GROUP}
        summary={SUMMARY}
        onToggle={() => {}}
        onRename={() => Promise.resolve()}
        onCommand={() => {}}
        workflows={[]}
      />,
    );

    const trigger = el.querySelector<HTMLButtonElement>(
      `[aria-label="Group options for ${GROUP.name}"]`,
    )!;
    act(() => {
      trigger.click();
    });

    const rename = buttonNamed(el, 'Rename group');
    const del = buttonNamed(el, 'Delete group');
    for (const button of [rename, del]) {
      expect(button.className.split(/\s+/)).toContain('text-sm');
    }
  });

  it('files every run of a workflow into the group, by picking it', () => {
    // The second auto-file rule, and the one a folder cannot express: a team
    // graph runs over many repositories, so nothing about WHERE it started
    // identifies its runs.
    const onCommand = vi.fn();
    const el = render(
      <GroupHeader
        group={GROUP}
        summary={SUMMARY}
        onToggle={() => {}}
        onRename={() => Promise.resolve()}
        onCommand={onCommand}
        workflows={[{ slug: 'dev-team', name: 'Dev Team' } as WorkflowSummary]}
      />,
    );
    act(() => {
      el.querySelector<HTMLButtonElement>(
        `[aria-label="Group options for ${GROUP.name}"]`,
      )!.click();
    });
    act(() => {
      // The WORKFLOW picker by its own name — `[data-menu-trigger]` alone
      // finds the colour menu's dot, which opens first in the DOM.
      el.querySelector<HTMLElement>(
        `[aria-label="Auto-file a workflow into ${GROUP.name}"]`,
      )!.click();
    });
    const row = [...document.querySelectorAll('[role="option"]')].find(
      (option) => option.textContent === 'Dev Team',
    )!;
    act(() => {
      (row as HTMLElement).click();
    });

    expect(onCommand).toHaveBeenCalledWith(GROUP.id, {
      kind: 'auto-workflow',
      slug: 'dev-team',
    });
  });

  it('says when the rule names a workflow the library no longer holds', () => {
    // The rule is still stored and simply never matches, so showing it as
    // unset would have the user set it again over the top of a live rule.
    const el = render(
      <GroupHeader
        group={{ ...GROUP, autoWorkflowId: 'deleted-graph' }}
        summary={SUMMARY}
        onToggle={() => {}}
        onRename={() => Promise.resolve()}
        onCommand={() => {}}
        workflows={[]}
      />,
    );
    act(() => {
      el.querySelector<HTMLButtonElement>(
        `[aria-label="Group options for ${GROUP.name}"]`,
      )!.click();
    });
    act(() => {
      // The WORKFLOW picker by its own name — `[data-menu-trigger]` alone
      // finds the colour menu's dot, which opens first in the DOM.
      el.querySelector<HTMLElement>(
        `[aria-label="Auto-file a workflow into ${GROUP.name}"]`,
      )!.click();
    });

    expect(document.body.textContent).toContain('deleted-graph');
    expect(document.body.textContent).toContain('not in the library any more');
  });

  it('names the group and reports its live count', () => {
    const el = render(
      <GroupHeader
        group={GROUP}
        summary={SUMMARY}
        onToggle={() => {}}
        onRename={() => Promise.resolve()}
        onCommand={() => {}}
        workflows={[]}
      />,
    );
    expect(el.textContent).toContain('Work');
    // Read off its own node — `toContain('3')` on the whole subtree would
    // also match a stray '3' anywhere else on the row (a position, an id).
    expect(el.querySelector('[data-slot="group-count"]')!.textContent).toBe(
      '3',
    );
  });

  it('draws the busy spinner when a thread in the group is running', () => {
    const el = render(
      <GroupHeader
        group={GROUP}
        summary={{ count: 3, busy: true, needsInput: false }}
        onToggle={() => {}}
        onRename={() => Promise.resolve()}
        onCommand={() => {}}
        workflows={[]}
      />,
    );
    expect(el.querySelector('[data-slot="group-busy"]')).not.toBeNull();
    expect(el.querySelector('[data-slot="group-needs-input"]')).toBeNull();
  });

  it('draws the needs-input glyph ahead of the busy spinner when both are true', () => {
    // `needsInput` outranks `busy` in the header's own ternary (both live on
    // the summary independently — see `runGroupSummary`), so a group with a
    // parked question AND a running thread must read as "needs you" rather
    // than merely "working".
    const el = render(
      <GroupHeader
        group={GROUP}
        summary={{ count: 3, busy: true, needsInput: true }}
        onToggle={() => {}}
        onRename={() => Promise.resolve()}
        onCommand={() => {}}
        workflows={[]}
      />,
    );
    expect(el.querySelector('[data-slot="group-needs-input"]')).not.toBeNull();
    expect(el.querySelector('[data-slot="group-busy"]')).toBeNull();
  });

  it('toggles the fold on a press of the row', () => {
    const onToggle = vi.fn();
    const el = render(
      <GroupHeader
        group={GROUP}
        summary={SUMMARY}
        onToggle={onToggle}
        onRename={() => Promise.resolve()}
        onCommand={() => {}}
        workflows={[]}
      />,
    );
    const row = el.querySelector<HTMLElement>('[data-slot="group-header"]')!;
    act(() => {
      row.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    expect(onToggle).toHaveBeenCalledWith(GROUP.id, true);
  });
});
