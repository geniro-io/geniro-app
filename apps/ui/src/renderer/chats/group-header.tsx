import {
  ChevronDown,
  ChevronRight,
  FolderOpen,
  Loader2,
  MessageCircleQuestion,
  MoreHorizontal,
  Pencil,
  Trash2,
  X,
} from 'lucide-react';
import { memo, useEffect, useRef, useState } from 'react';

import type { RunGroupColor, RunGroupDto } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Input } from '../components/ui/input';
import { Menu } from '../components/ui/menu';
import { Popover } from '../components/ui/popover';
import { cn } from '../components/ui/utils';
import { shortenPath } from './directory-select';
import {
  GROUP_COLOR_LABEL,
  GROUP_DOT_CLASS,
  type RunGroupSummary,
} from './run-group';

/**
 * How wide a menu may be inside the 260px chat sidebar.
 *
 * Sized by its container rather than by its longest row: left to grow, the
 * colour menu measured 257px in a 235px slot and was clipped by the list's own
 * scroll container. `min-w-0` is what defeats the primitive's default floor.
 */
export const SIDEBAR_MENU_WIDTH = 'min-w-0 w-56';

/** A row in the options panel — the look shared by its two action rows. */
const OPTION_ROW =
  'flex w-full cursor-pointer items-center gap-2.5 rounded-md px-2 py-1.5 text-left text-sm transition-colors [&>svg]:size-4 [&>svg]:shrink-0';

/** What the header's options panel asks the sidebar to do. */
export type GroupCommand =
  | { kind: 'color'; color: RunGroupColor }
  | { kind: 'auto-folder' }
  | { kind: 'auto-clear' }
  | { kind: 'delete' };

/**
 * One group's header in the chat sidebar: a fold control, the group's colour, its
 * name, how many threads are in it, whether any of them is working, and an
 * overflow menu for everything else.
 *
 * The WHOLE row toggles the fold. A group header has one obvious action and
 * confining it to the chevron makes a 200px-wide target into a 14px one; the
 * rename field and the menu button stop their own clicks, so neither folds the
 * group out from under the user.
 *
 * Renaming happens IN the row, the same way a chat's does (`chat-list-item`) and
 * for the same reason: the name is edited where it is read. The edit state is
 * local — the parent supplies a commit that throws to report a failure, which
 * keeps the row open carrying the reason.
 *
 * Memoized like the chat rows beside it: the sidebar re-renders on every
 * composer keystroke, and each header would otherwise re-render with it.
 */
export const GroupHeader = memo(function GroupHeader({
  group,
  summary,
  unseen = false,
  dragging = false,
  autoFocusName = false,
  onNameFocused,
  onToggle,
  onRename,
  onCommand,
  onDragStart,
  onDragEnd,
}: {
  group: RunGroupDto;
  summary: RunGroupSummary;
  /**
   * At least one thread in this group has reported something the user has not
   * opened since — see {@link import('./use-unseen-runs')}. Kept OFF
   * {@link RunGroupSummary}, which is derived from the rows' display statuses
   * alone: this is about what the user has looked at, which no status carries.
   */
  unseen?: boolean;
  /** This is the group currently being dragged — dimmed while it travels. */
  dragging?: boolean;
  /**
   * Open with the name selected — a group the user just created, so naming it
   * is typing rather than a second trip through the menu.
   *
   * A flag the parent CLEARS through {@link onNameFocused} rather than a
   * one-shot mount effect: this row is memoized and long-lived, and a flag left
   * standing would drop it back into edit mode on any later re-mount, out of
   * nowhere.
   */
  autoFocusName?: boolean;
  /** Reported once the field has taken focus, so the parent can clear it. */
  onNameFocused?: () => void;
  onToggle: (groupId: string, collapsed: boolean) => void;
  /** Commit a new name. Rejects to report the failure back into the row. */
  onRename: (groupId: string, name: string) => Promise<void>;
  onCommand: (groupId: string, command: GroupCommand) => void;
  /**
   * Reordering, by dragging this header onto another group.
   *
   * Only the two ENDS of the gesture live here. What the pointer passes over is
   * the SECTION's business (`Chats.tsx`), because a section is header + rail +
   * rows and a drag has to be answerable anywhere inside it — `dragover`
   * bubbles, so a handler here would only ever cover the 26px strip.
   */
  onDragStart?: (groupId: string) => void;
  onDragEnd?: () => void;
}): React.JSX.Element {
  const [editing, setEditing] = useState(false);
  const [draft, setDraft] = useState(group.name);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [menuOpen, setMenuOpen] = useState(false);
  const [colorMenuOpen, setColorMenuOpen] = useState(false);
  const inputRef = useRef<HTMLInputElement>(null);
  const menuTriggerRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    if (editing) {
      inputRef.current?.focus();
      inputRef.current?.select();
    }
  }, [editing]);

  useEffect(() => {
    if (autoFocusName && !editing) {
      setDraft(group.name);
      setError(null);
      setEditing(true);
      onNameFocused?.();
    }
    // `editing` is deliberately absent from the deps: this must fire when the
    // PARENT names this group, not every time the row's own edit state changes
    // — re-running on the commit that turns editing off would put the field
    // straight back up.
  }, [autoFocusName, group.name, onNameFocused]);

  const startEditing = (): void => {
    setDraft(group.name);
    setError(null);
    setEditing(true);
  };
  const commit = async (): Promise<void> => {
    const name = draft.trim();
    // Nothing to save — an empty name would leave the group unidentifiable,
    // and an unchanged one is not worth a request.
    if (name.length === 0 || name === group.name) {
      setEditing(false);
      return;
    }
    setBusy(true);
    setError(null);
    try {
      await onRename(group.id, name);
      setEditing(false);
    } catch (err) {
      setError(String(err));
    } finally {
      setBusy(false);
    }
  };

  return (
    // A DIV, not an `li`: the section around it is the list item (`Chats.tsx`
    // renders one per group, and it is what carries the drop zone), so a
    // second `li` here would nest one list item directly inside another.
    <div className="group/header">
      <div
        role="button"
        tabIndex={0}
        aria-expanded={!group.collapsed}
        aria-label={`${group.collapsed ? 'Expand' : 'Collapse'} ${group.name}`}
        // Draggable EXCEPT while the name is being edited: a text field inside
        // a draggable element cannot be selected with the mouse, because the
        // drag starts instead of the selection.
        draggable={!editing}
        data-slot="group-header"
        data-group-id={group.id}
        className={cn(
          'flex w-full cursor-pointer select-none items-center gap-1.5 rounded-md px-2 py-1 text-left hover:bg-sidebar-accent',
          dragging && 'opacity-40',
        )}
        onDragStart={(event) => {
          // Firefox refuses to start a drag with no payload, and the data is
          // never read back: the parent already knows which group started.
          event.dataTransfer.setData('text/plain', group.id);
          event.dataTransfer.effectAllowed = 'move';
          onDragStart?.(group.id);
        }}
        onDragEnd={() => onDragEnd?.()}
        onClick={() => onToggle(group.id, !group.collapsed)}
        onKeyDown={(event) => {
          if (event.key === 'Enter' || event.key === ' ') {
            event.preventDefault();
            onToggle(group.id, !group.collapsed);
          }
        }}>
        {group.collapsed ? (
          <ChevronRight
            aria-hidden="true"
            className="size-3.5 shrink-0 text-muted-foreground"
          />
        ) : (
          <ChevronDown
            aria-hidden="true"
            className="size-3.5 shrink-0 text-muted-foreground"
          />
        )}
        {/* The dot IS the colour, so the dot is what changes it — which also
            keeps the options menu short enough to show every row at once. It
            was one menu of fourteen rows, and measured in the real sidebar
            that panel was 257px wide in a 235px slot and scrolled its last
            four rows (the delete among them) out of sight. */}
        <span
          className="relative inline-flex shrink-0"
          onClick={(event) => event.stopPropagation()}>
          <button
            type="button"
            data-menu-trigger
            aria-haspopup="listbox"
            aria-expanded={colorMenuOpen}
            aria-label={`Colour of ${group.name}`}
            title="Group colour"
            className="flex size-4 cursor-pointer items-center justify-center rounded-full outline-none focus-visible:ring-2 focus-visible:ring-ring/50"
            onClick={() => setColorMenuOpen((open) => !open)}>
            <span
              data-slot="group-dot"
              data-color={group.color}
              className={cn(
                'size-2 shrink-0 rounded-full',
                GROUP_DOT_CLASS[group.color],
              )}
            />
          </button>
          <Menu
            open={colorMenuOpen}
            side="bottom"
            align="start"
            className={SIDEBAR_MENU_WIDTH}
            value={group.color}
            groups={[
              {
                label: 'Colour',
                items: Object.entries(GROUP_COLOR_LABEL).map(
                  ([color, label]) => ({
                    value: color,
                    label,
                    icon: (
                      <span
                        className={cn(
                          'size-2.5 rounded-full',
                          GROUP_DOT_CLASS[color as RunGroupColor],
                        )}
                      />
                    ),
                  }),
                ),
              },
            ]}
            onSelect={(color) =>
              onCommand(group.id, {
                kind: 'color',
                color: color as RunGroupColor,
              })
            }
            onClose={() => setColorMenuOpen(false)}
          />
        </span>
        {editing ? (
          <Input
            ref={inputRef}
            value={draft}
            disabled={busy}
            aria-label={`Rename ${group.name}`}
            aria-invalid={error !== null || undefined}
            className="h-6 min-w-0 flex-1 px-1.5 py-0 text-sm"
            // The field owns its clicks and its keys: without this every
            // keystroke bubbles to the row above and folds the group shut.
            onClick={(event) => event.stopPropagation()}
            onChange={(event) => setDraft(event.target.value)}
            onKeyDown={(event) => {
              event.stopPropagation();
              // One request per commit — an Enter confirming an IME
              // composition must not fire it on a half-composed name.
              if (event.nativeEvent.isComposing) {
                return;
              }
              if (event.key === 'Enter') {
                void commit();
              } else if (event.key === 'Escape') {
                // Unmounting a focused field fires no blur, so the abandoned
                // draft cannot leak through the commit-on-blur path below.
                setError(null);
                setEditing(false);
              }
            }}
            onBlur={() => {
              if (!busy) {
                void commit();
              }
            }}
          />
        ) : (
          // Name and count are ONE unit, so the number sits against the name
          // it counts. Pushed to the far right by `flex-1` on the name it read
          // as a second, unrelated column — and on a short name it sat a long
          // way from anything it was about.
          <span className="flex min-w-0 flex-1 items-center gap-1.5">
            <span className="min-w-0 truncate text-xs font-semibold tracking-wide text-muted-foreground uppercase">
              {group.name}
            </span>
            {/* Always shown, including zero: an empty group the user just made
                has to look like an empty group rather than a bug. */}
            <span
              data-slot="group-count"
              className="shrink-0 rounded-full bg-muted px-1.5 text-[11px] leading-[18px] tabular-nums text-muted-foreground">
              {summary.count}
            </span>
          </span>
        )}
        {/* `relative` so the menu panel hangs off this wrapper — see menu.tsx,
            which positions against the trigger's parent rather than a portal. */}
        <span
          className="relative inline-flex shrink-0"
          onClick={(event) => event.stopPropagation()}>
          <Button
            ref={menuTriggerRef}
            type="button"
            variant="ghost"
            size="icon"
            aria-haspopup="dialog"
            aria-expanded={menuOpen}
            className="size-5 text-muted-foreground opacity-0 group-hover/header:opacity-100 focus-visible:opacity-100 aria-expanded:opacity-100"
            aria-label={`Group options for ${group.name}`}
            title="Group options"
            onClick={() => setMenuOpen((open) => !open)}>
            <MoreHorizontal className="size-3.5 shrink-0" />
          </Button>
          <Popover
            open={menuOpen}
            onClose={() => setMenuOpen(false)}
            triggerRef={menuTriggerRef}
            side="bottom"
            align="end"
            // The trigger lives inside the chat list, which SCROLLS — an
            // ancestor-positioned panel is cut at that list's edge, which is
            // what capped the old menu at a width its own rows did not fit in.
            // Measuring the trigger and placing the panel `fixed` is the only
            // way out of a clipping ancestor.
            anchor="viewport"
            label={`Options for ${group.name}`}
            className="w-64 p-1">
            <button
              type="button"
              className={cn(OPTION_ROW, 'text-foreground hover:bg-accent')}
              onClick={() => {
                setMenuOpen(false);
                startEditing();
              }}>
              <Pencil />
              <span className="min-w-0 flex-1 truncate">Rename group</span>
            </button>

            <div className="mt-1 border-t border-border/70 px-2 pt-2 pb-1">
              <p className="m-0 text-[11px] font-medium tracking-wide text-muted-foreground uppercase">
                Auto-file
              </p>
              {/* The rule STATED, not implied by a row that happens to hold a
                  path: what it does was the one thing the old menu never said,
                  and a folder path on its own does not say it. */}
              <p className="m-0 pt-0.5 text-xs leading-snug text-muted-foreground">
                {group.autoCwd === null
                  ? 'Pick a folder and every new chat you start in it lands in this group.'
                  : 'New chats started in this folder land here.'}
              </p>
              {group.autoCwd === null ? (
                <Button
                  type="button"
                  variant="outline"
                  className="mt-2 h-7 w-full justify-start gap-2 px-2 text-xs"
                  onClick={() => onCommand(group.id, { kind: 'auto-folder' })}>
                  <FolderOpen className="size-3.5 shrink-0" />
                  Choose folder…
                </Button>
              ) : (
                <div className="mt-2 flex items-center gap-1">
                  {/* The path is a LABEL, not a control: clicking it used to
                      open the folder picker, which is why picking the same
                      folder again read as "nothing happened". The two things
                      it can do are now two buttons that say what they do. */}
                  <span
                    className="min-w-0 flex-1 truncate rounded-md bg-muted px-2 py-1 font-mono text-[11px] text-muted-foreground"
                    title={group.autoCwd}>
                    {shortenPath(group.autoCwd)}
                  </span>
                  <Button
                    type="button"
                    variant="ghost"
                    size="icon"
                    className="size-6 shrink-0 text-muted-foreground"
                    aria-label={`Choose another folder for ${group.name}`}
                    title="Choose another folder"
                    onClick={() =>
                      onCommand(group.id, { kind: 'auto-folder' })
                    }>
                    <FolderOpen className="size-3.5 shrink-0" />
                  </Button>
                  <Button
                    type="button"
                    variant="ghost"
                    size="icon"
                    className="size-6 shrink-0 text-muted-foreground hover:text-destructive"
                    aria-label={`Stop filing new chats into ${group.name}`}
                    title="Remove the rule"
                    onClick={() => onCommand(group.id, { kind: 'auto-clear' })}>
                    <X className="size-3.5 shrink-0" />
                  </Button>
                </div>
              )}
            </div>

            <button
              type="button"
              className={cn(
                OPTION_ROW,
                'mt-1 border-t border-border/70 pt-2 text-destructive hover:bg-destructive/10 [&>svg]:text-destructive',
              )}
              onClick={() => {
                setMenuOpen(false);
                onCommand(group.id, { kind: 'delete' });
              }}>
              <Trash2 />
              <span className="min-w-0 flex-1 truncate">Delete group</span>
            </button>
          </Popover>
        </span>
        {/* LAST in the row, after the options button, so the glyph sits flush
            with the right edge. Before this it came BEFORE that button, which
            is `opacity-0` until the row is hovered but still occupies its 20px
            box, so the header's glyph floated ~23px short of the edge and read
            as a stray mark in the middle of the row. It is a SUMMARY of the
            rows below rather than one row's own status — which is why it stays
            here while the rows lead with theirs.
            A parked thread outranks a working one, and both survive a fold —
            which is the whole point of putting them here. A collapsed group
            that hid an unanswered question would be a worse sidebar than no
            groups at all. */}
        {/* The same unread mark the rows carry, summarised — a group folded
            over a thread that just finished would otherwise hide the very
            signal the highlight exists to give, exactly as it would for a
            parked question. Its own axis rather than a third arm of the
            ternary below: "something in here is new" and "something in here is
            working" are both true of a group that has one of each. */}
        {unseen ? (
          <span
            data-slot="group-unseen"
            role="img"
            aria-label={`${group.name} has a thread you have not opened`}
            className="size-1.5 shrink-0 rounded-full bg-primary"
          />
        ) : null}
        {summary.needsInput ? (
          <MessageCircleQuestion
            data-slot="group-needs-input"
            aria-label={`${group.name} has a thread waiting for you`}
            className="size-3 shrink-0 text-warning"
          />
        ) : summary.busy ? (
          <Loader2
            data-slot="group-busy"
            aria-label={`${group.name} has a thread running`}
            className="size-3 shrink-0 animate-spin text-primary"
          />
        ) : null}
      </div>
      {error ? (
        <p className="truncate px-2 text-xs text-destructive">{error}</p>
      ) : null}
    </div>
  );
});
