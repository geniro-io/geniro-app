import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  anchorOnlyIds,
  mergeAnchorRows,
  structureIndexOf,
  unplacedStructureOf,
  withAnchors,
} from './history-anchors';

function row(
  seq: number,
  kind: ChatItem['kind'],
  payload: Record<string, unknown> = {},
): ChatItem {
  return {
    id: `i${seq}`,
    runId: 'r1',
    nodeId: null,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

describe('withAnchors', () => {
  it('lays the anchors in by seq and hands the window back untouched when there is nothing to add', () => {
    const items = [row(10, 'message'), row(11, 'message')];
    expect(withAnchors(items, [])).toBe(items);
    expect(withAnchors(items, [row(11, 'message')])).toBe(items);
    expect(
      withAnchors(items, [row(2, 'call_started')]).map((item) => item.seq),
    ).toEqual([2, 10, 11]);
  });

  it('never doubles a row an older page has since brought into the window', () => {
    const anchor = row(5, 'call_started', { callId: 'call-1' });
    const items = [anchor, row(10, 'message')];
    expect(withAnchors(items, [anchor]).map((item) => item.seq)).toEqual([
      5, 10,
    ]);
  });
});

describe('anchorOnlyIds', () => {
  it('names only the anchors the window does not hold — a held row is drawn', () => {
    const paged = row(5, 'call_started', { callId: 'call-1' });
    const above = row(2, 'call_started', { callId: 'call-0' });
    expect([
      ...anchorOnlyIds([paged, row(10, 'message')], [above, paged]),
    ]).toEqual(['i2']);
  });
});

describe('mergeAnchorRows', () => {
  it('keeps one row per id, in seq order', () => {
    const merged = mergeAnchorRows(
      [row(3, 'call_started'), row(1, 'call_started')],
      [row(3, 'call_started'), row(2, 'tool_call')],
    );
    expect(merged.map((item) => item.seq)).toEqual([1, 2, 3]);
  });
});

describe('unplacedStructureOf — what a live row needs anchors for', () => {
  const index = structureIndexOf([
    row(1, 'call_started', { callId: 'call-1' }),
    row(2, 'tool_call', { id: 'toolu_held' }),
  ]);

  it('asks for a call nothing in the window opened', () => {
    expect(
      unplacedStructureOf(row(10, 'message', { callId: 'call-9' }), index),
    ).toEqual(['call:call-9']);
    expect(
      unplacedStructureOf(row(11, 'message', { callId: 'call-1' }), index),
    ).toEqual([]);
  });

  it('asks for the conversation a continuation names when its calls are above the window', () => {
    expect(
      unplacedStructureOf(
        row(12, 'call_started', { callId: 'call-20', thread: 'call-7' }),
        index,
      ),
    ).toEqual(['call:call-7']);
    expect(
      unplacedStructureOf(
        row(13, 'call_started', { callId: 'call-21', thread: 'call-1' }),
        index,
      ),
    ).toEqual([]);
  });

  it("asks for a delegate's launch and for an orphan reply's call", () => {
    expect(
      unplacedStructureOf(
        row(14, 'message', { parentToolUseId: 'toolu_task' }),
        index,
      ),
    ).toEqual(['tool:toolu_task']);
    expect(
      unplacedStructureOf(row(15, 'tool_result', { id: 'toolu_gone' }), index),
    ).toEqual(['tool:toolu_gone']);
    expect(
      unplacedStructureOf(row(16, 'tool_result', { id: 'toolu_held' }), index),
    ).toEqual([]);
  });

  it('asks for the launch a delegate’s or a workflow’s own announcement names', () => {
    expect(
      unplacedStructureOf(
        row(17, 'subagent_info', {
          id: 'cursor-1',
          backgroundOutcome: 'completed',
        }),
        index,
      ),
    ).toEqual(['tool:cursor-1']);
    expect(
      unplacedStructureOf(row(18, 'workflow_info', { id: 'wf-1' }), index),
    ).toEqual(['tool:wf-1']);
  });
});
