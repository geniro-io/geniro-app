import type { ItemDto as ChatItem } from '../autogenerated';
import { subagentIdOf } from './subagent-payload';
import { payloadString } from './transcript-payload';

/**
 * The ANCHORS of a transcript window: rows outside the window that rows inside
 * it belong to — a call's start and settle, a delegate's launch, a tool
 * result's call — as the daemon picks them for each page it serves
 * (`GET /v1/chats/:runId/items`, `utils/history-anchors.ts` there).
 *
 * They are kept APART from the window, never in it. Everything that pages reads
 * the window's first and last row and decides whether older history exists from
 * how many rows a page returned, and an anchor among them would move both. They
 * join the window only where the transcript is FOLDED into structure, and even
 * there no anchor is drawn as a row of its own: it is what a card is built
 * from, not something the reader scrolled to.
 */

/** Two anchor sets as one, by id, in seq order. */
export function mergeAnchorRows(
  held: readonly ChatItem[],
  more: readonly ChatItem[],
): ChatItem[] {
  if (more.length === 0) {
    return [...held];
  }
  const byId = new Map(held.map((item) => [item.id, item] as const));
  for (const item of more) {
    byId.set(item.id, item);
  }
  return [...byId.values()].sort((a, b) => a.seq - b.seq);
}

/**
 * The window with its anchors laid in, in seq order — what the transcript's
 * structure is folded from. An anchor the window has since paged in is the
 * window's own row and is not added twice. Answers `items` itself when there is
 * nothing to add, so a memo keyed on it keeps its identity.
 */
export function withAnchors(
  items: readonly ChatItem[],
  anchors: readonly ChatItem[],
): readonly ChatItem[] {
  if (anchors.length === 0) {
    return items;
  }
  const held = new Set(items.map((item) => item.id));
  const extra = anchors.filter((item) => !held.has(item.id));
  if (extra.length === 0) {
    return items;
  }
  return [...items, ...extra].sort((a, b) => a.seq - b.seq);
}

/**
 * The ids of the anchors that are NOT the window's own rows — the ones a fold
 * must never draw as a row of their own.
 */
export function anchorOnlyIds(
  items: readonly ChatItem[],
  anchors: readonly ChatItem[],
): ReadonlySet<string> {
  const held = new Set(items.map((item) => item.id));
  return new Set(
    anchors.filter((item) => !held.has(item.id)).map((item) => item.id),
  );
}

/** Which calls and tool calls a set of rows can already place. */
export interface StructureIndex {
  callStarts: Set<string>;
  toolCalls: Set<string>;
}

export function structureIndexOf(
  ...lists: readonly (readonly ChatItem[])[]
): StructureIndex {
  const index: StructureIndex = { callStarts: new Set(), toolCalls: new Set() };
  for (const list of lists) {
    for (const item of list) {
      if (item.kind === 'call_started') {
        const callId = payloadString(item.payload, 'callId');
        if (callId !== null) {
          index.callStarts.add(callId);
        }
      } else if (item.kind === 'tool_call') {
        const id = payloadString(item.payload, 'id');
        if (id !== null) {
          index.toolCalls.add(id);
        }
      }
    }
  }
  return index;
}

/**
 * The structure a LIVE row refers to that nothing held can place, as keys
 * (`call:<id>`, `tool:<id>`) — a call that started above the window and has
 * just spoken again, a delegate launched above it. Its anchors are then asked
 * of the daemon for that row alone.
 *
 * TWIN PARSER: `anchorNeedsOf` in
 * apps/daemon/src/v1/agents/utils/history-anchors.ts — what a live row needs
 * is what the same row needs when a page brings it.
 */
export function unplacedStructureOf(
  item: ChatItem,
  index: StructureIndex,
): string[] {
  const keys: string[] = [];
  const callId = payloadString(item.payload, 'callId');
  if (
    callId !== null &&
    item.kind !== 'call_started' &&
    !index.callStarts.has(callId)
  ) {
    keys.push(`call:${callId}`);
  }
  // A continuation joins the conversation it names, whose calls may all be
  // above the window.
  const thread =
    item.kind === 'call_started' ? payloadString(item.payload, 'thread') : null;
  if (thread !== null && !index.callStarts.has(thread)) {
    keys.push(`call:${thread}`);
  }
  const delegate = subagentIdOf(item);
  if (delegate !== null && !index.toolCalls.has(delegate)) {
    keys.push(`tool:${delegate}`);
  }
  // A reply names its call, and a delegate's or a workflow's own announcement
  // names the call that launched it.
  if (
    item.kind === 'tool_result' ||
    item.kind === 'subagent_info' ||
    item.kind === 'workflow_info'
  ) {
    const id = payloadString(item.payload, 'id');
    if (id !== null && !index.toolCalls.has(id)) {
      keys.push(`tool:${id}`);
    }
  }
  return keys;
}
