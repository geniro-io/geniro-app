/** No workflow is ever a target here: a hosted chat is one agent's. */
const NO_WORKFLOW_TARGETS = [] as const;

/**
 * One frozen empty list for a CLI that has stored no recent config
 * directories. A `?? []` at the settings panel would be a new array on every
 * render, and a hosted chat re-renders on each streamed delta.
 */
const EMPTY_RECENT_CONFIG_DIRS: readonly string[] = [];

/**
 * One frozen empty map for a run that has stored no parameter picks. A
 * `?? {}` inside `chipsOfRun` would be a new object on every render and
 * defeat the settings panel's memo on exactly those runs.
 */
const NO_MODEL_PARAMETERS: Record<string, string> = {};

/** What the composer's chips name: a run's settings, or the create's draft. */
export interface ChipValues {
  agentKind: AgentKind;
  approval: ChatApprovalMode;
  model: string | null;
  effort: string | null;
  contextWindow: string | null;
  modelParameters: Record<string, string>;
  configDir: string | null;
}

/**
 * The draft chips of a frame that creates nothing (the analysis popup opens a
 * conversation that already exists): never drawn, since its run's own row is.
 */
const UNSET_CHIPS: ChipValues = {
  agentKind: CLI_KINDS[0]!,
  approval: 'ask',
  model: null,
  effort: null,
  contextWindow: null,
  modelParameters: {},
  configDir: null,
};

/** What a hosted chat's frame draws its header from. */
export interface HostedChatHeaderView {
  run: RunDto | null;
  /** The run's status as every surface reads it (`displayRunStatus`). */
  status: RunStatusKind;
}

/** The chips an open run shows: its own row, an absent field reading as unset. */
function chipsOfRun(run: RunDto, draft: ChipValues): ChipValues {
  return {
    agentKind: run.agentKind ?? draft.agentKind,
    approval: run.approval ?? draft.approval,
    model: run.model ?? null,
    effort: run.effort ?? null,
    contextWindow: run.contextWindow ?? null,
    modelParameters: run.modelParameters ?? NO_MODEL_PARAMETERS,
    configDir: run.configDir ?? null,
  };
}

/**
 * One conversation drawn outside the chat screen, with the chat screen's own
 * parts: the transcript rows, the approval card, the composer shell, its
 * queue and its chips. Nothing here re-draws a message or an option list; if a
 * row looks wrong, it looks wrong in the chat screen too.
 *
 * The caller owns the conversation (`useHostedChat`) and the frame: the
 * builder's dock (`WorkflowChatPanel`) and a thread's analysis popup
 * (`AnalysisDialog`). This renders the header the frame hands it, the
 * transcript and the composer, as siblings for the frame's own column.
 */
export function HostedChat({
  chat,
  ownerKey,
  apis,
  handle,
  capabilities,
  capabilitiesLoading,
  recentConfigDirs,
  configProfiles,
  draftChips: draftChipsProp,
  onDraftChipsChange,
  initialDraft = '',
  active = true,
  header,
  emptyText,
  composerLabel,
  composerPlaceholder,
  transcriptSlot,
  applyRecommendations = null,
  onBeforeSend,
  onWorkingChange,
  onAwaitingChange,
  onTurnSettled,
}: {
  chat: HostedChatState;
  /**
   * What the composer's draft and attachments belong to before a run exists —
   * the frame's subject. A run takes over once there is one.
   */
  ownerKey: string;
  apis: DaemonApis | null;
  /** This launch's daemon — what a published page's URL is built from. */
  handle: DaemonHandle | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  /** PER CLI: each keeps a different layout in its directory. */
  recentConfigDirs: Partial<Record<CliKind, readonly string[]>>;
  /** The user's named config directories — the WHOLE list; filtered to this chat's own agent below. */
  configProfiles: readonly ConfigProfile[];
  /**
   * The chips before a conversation exists, for a frame that CREATES one (the
   * builder's dock), with its agent picker. A frame that only opens an
   * existing conversation leaves both out.
   */
  draftChips?: ChipValues;
  onDraftChipsChange?: Dispatch<SetStateAction<ChipValues>>;
  initialDraft?: string;
  /** Whether the frame is on screen. Its settings are read again when it is. */
  active?: boolean;
  /** The frame's header, drawn from what this reads of the run. */
  header: (view: HostedChatHeaderView) => ReactNode;
  /** What an empty conversation invites the user to do. */
  emptyText: string;
  composerLabel: string;
  composerPlaceholder: string;
  /** The transcript box's `data-slot`, kept per frame for its specs. */
  transcriptSlot: string;
  /** A recommendations card's Apply — given by the analysis popup only. */
  applyRecommendations?: RecommendationsApplier | null;
  /**
   * Run before a message is handed to the daemon — the builder writes any
   * pending canvas edit first, so the agent reads the graph the user is
   * looking at rather than the one last autosaved.
   */
  onBeforeSend?: () => Promise<unknown>;
  /**
   * A turn started or ended. The builder suspends its autosave while one runs,
   * so the agent's write and the canvas cannot overwrite each other.
   */
  onWorkingChange?: (working: boolean) => void;
  /**
   * The agent is waiting on the user — a question or an approval card — or no
   * longer is. A frame that can be HIDDEN while its turn waits marks its
   * toggle from this; nothing else on screen would say so.
   */
  onAwaitingChange?: (awaiting: RunAwaiting | null) => void;
  /** A turn ended — the builder re-reads the workflow the agent may have edited. */
  onTurnSettled?: () => void | Promise<void>;
}): React.JSX.Element {
  // The chips' values before a conversation exists: what the create starts with.
  // Once one does, the chips show the run's own row and a change is saved onto
  // the run — see `applySettings`. A frame that creates nothing holds them here.
  const [localChips, setLocalChips] = useState<ChipValues>(UNSET_CHIPS);
  const draftChips = draftChipsProp ?? localChips;
  const setDraftChips = onDraftChipsChange ?? setLocalChips;
  const [collapseToolSteps, setCollapseToolSteps] = useState(false);
  const [draft, setDraft] = useState(initialDraft);
  const previousRunId = useRef<string | null>(null);
  const [composeError, setComposeError] = useState<string | null>(null);
  const sendingRef = useRef(false);

  const runId = chat.run?.id ?? null;
  const ownerRef = useRef(runId ?? ownerKey);
  ownerRef.current = runId ?? ownerKey;
  const attachments = useAttachments(undefined, {
    current: () => ownerRef.current,
    // A discarded conversation cannot receive an image whose read finishes later.
    elsewhere: () => {},
  });
  const fileAttach = useFileAttach({
    remote: isRemoteRuntime(),
    stageImages: attachments.addFiles,
    resolvePath: (file) => window.geniro.filePath(file),
    upload: async (file) => {
      if (apis === null) {
        throw new Error('daemon unavailable');
      }
      return (
        await apis.chats.uploadChatFile(
          {
            uploadChatFileDto: {
              name: file.name,
              data: await readAsBase64(file),
            },
          },
          { signal: AbortSignal.timeout(CHAT_UPLOAD_TIMEOUT_MS) },
        )
      ).path;
    },
    currentOwner: () => ownerRef.current,
    deliver: (owner, paths) => {
      if (owner === ownerRef.current) {
        setDraft((text) => appendPaths(text, paths));
      }
    },
  });
  const clearAttachments = attachments.clear;
  useEffect(() => {
    if (!(initialDraft && runId !== null && previousRunId.current === null)) {
      setDraft(runId === null ? initialDraft : '');
    }
    previousRunId.current = runId;
    setComposeError(null);
    clearAttachments();
  }, [ownerKey, runId, clearAttachments, initialDraft]);
  const attachBusy = attachments.reading || fileAttach.uploading;
  const attachBusyTitle = attachments.reading
    ? 'Reading the image…'
    : 'Uploading the file…';
  const hasContent = draft.trim() !== '' || attachments.attachments.length > 0;
  const loadAttachment = useCallback(
    async (attachmentRunId: string, attachmentId: string): Promise<string> => {
      if (apis === null) {
        throw new Error('daemon unavailable');
      }
      return (
        await apis.chats.readChatAttachment({
          runId: attachmentRunId,
          attachmentId,
        })
      ).data;
    },
    [apis],
  );

  // A picture the agent referenced, read from this run's own folder: the route
  // the chat screen takes (`loadMarkdownImage` in Chats.tsx).
  const loadMarkdownImage = useCallback(
    async (path: string): Promise<string> => {
      if (apis === null || runId === null) {
        throw new Error('no run to resolve this image against');
      }
      return readLocalImageDataUrl(apis.chats, runId, path);
    },
    [apis, runId],
  );

  // The approvals the transcript already draws as cards, which its verdict rows
  // must not repeat — the chat screen computes the same set.
  const cardBacked = useMemo(
    () => cardBackedRequestIds(chat.items),
    [chat.items],
  );
  /** How a page this chat's agent published is addressed — see `Chats.tsx`. */
  const artifactUrl = useMemo<ArtifactUrlBuilder | null>(() => {
    if (handle === null || runId === null) {
      return null;
    }
    return artifactUrlBuilder(handle, runId);
  }, [handle, runId]);
  const { run, working, settledTurns, patchSettings, rememberContext } = chat;
  // What the chips show: the open run's row once there is one — a save the daemon
  // answers is what the row then says — and the create's draft before that.
  const {
    agentKind,
    model,
    effort,
    contextWindow,
    approval,
    modelParameters,
    configDir,
  } = run === null ? draftChips : chipsOfRun(run, draftChips);
  const loadMetrics = useChatMetricsLoader(
    apis?.chats ?? null,
    rememberContext,
  );
  // From here on the run is read through the chat screen's own functions, so
  // the transcript, the status and the ring cannot read the same rows two ways.
  const { foldItems, entries: durableEntries } = useDurableTranscript({
    items: chat.items,
    anchors: chat.anchors,
    runId,
    taskList: run?.taskList,
    collapseToolSteps,
  });
  const verdicts = useMemo(() => collectVerdicts(chat.items), [chat.items]);
  const unanswerable = useMemo(
    () => unanswerableRequestIds(chat.items),
    [chat.items],
  );
  // A card nobody has answered: no verdict, not taken down with its turn, and
  // not refused as expired. The run row's `awaiting` is OR'd in below.
  const openRequestOnScreen = useMemo(
    () =>
      foldItems.some((item) => {
        const id =
          item.kind === 'approval_request'
            ? payloadString(item.payload, 'id')
            : null;
        return (
          id !== null &&
          !verdicts.has(id) &&
          !unanswerable.has(id) &&
          !chat.deadRequestIds.has(id)
        );
      }),
    [foldItems, verdicts, unanswerable, chat.deadRequestIds],
  );
  const runStoppedAt =
    run !== null && isSettledRunStatus(run.status)
      ? settleMomentOf(run, chat.items)
      : null;
  const subagentRunning = useMemo(
    () =>
      anySubagentRunning(
        durableEntries,
        runStoppedAt,
        run?.subagentsOut ?? null,
      ),
    [durableEntries, runStoppedAt, run?.subagentsOut],
  );
  const status =
    run === null
      ? 'pending'
      : displayRunStatus({
          status: run.status,
          streaming: working,
          awaitingAnswer: run.awaiting != null || openRequestOnScreen,
          subagentRunning,
          heldForBackgroundWork: run.holdingFor > 0,
          shellsRunning: run.shellsOpen > 0,
          subagentsOut: run.subagentsOut > 0,
        });
  const runSettledAt =
    run !== null && isSettledRunStatus(status)
      ? settleMomentOf(run, chat.items)
      : null;
  const turnDurations = useMemo(
    () => scanTurns(chat.items).durations,
    [chat.items],
  );
  const { remember, recall, forget } = useContextReadings();
  const transcriptFigures = useMemo(
    () => computeAgentActivity(foldItems).get(CHAT_AGENT_KEY),
    [foldItems],
  );
  const ring = useMemo(
    () =>
      chatContextFigures({
        live: chat.liveText.get(CHAT_LIVE_KEY),
        run,
        transcript: transcriptFigures,
        itemsLoaded: chat.items.length > 0,
        recall: () => recall(runId),
      }),
    [chat.liveText, chat.items.length, recall, run, transcriptFigures, runId],
  );
  const awaitingReading = useContextRing({
    runId,
    figures: ring,
    items: chat.items,
    remember,
    forget,
  });

  // The chat screen's message queue: written while the agent works, sent one
  // per settled turn. Not kept across a reload — that store is the chat
  // screen's, and two surfaces restoring it would each drain the other's runs.
  const messageQueue = useMessageQueue({ persist: false });
  const runIdRef = useRef(runId);
  runIdRef.current = runId;
  const workingRef = useRef(working);
  workingRef.current = working;
  /**
   * Every send — typed or drained — flushes the canvas first and is awaited:
   * the agent reads the file, so a canvas edit still in the autosave debounce
   * would be invisible to the turn and then written on top of what it produced.
   */
  const sendQueued = useCallback(
    async (
      sendRunId: string,
      text: string,
      images: SendMessageDtoImagesInner[],
      clientMessageId = randomId(),
    ): Promise<void> => {
      await onBeforeSend?.();
      if (sendRunId !== runIdRef.current) {
        throw new Error(
          'This conversation was replaced before the message went out',
        );
      }
      await chat.post(text, images, clientMessageId);
    },
    [onBeforeSend, chat],
  );
  useEffect(() => {
    messageQueue.handlersRef.current = {
      activeRunId: () => runIdRef.current,
      send: sendQueued,
      isWorking: () => workingRef.current,
      onFailed: (failedRunId, err) => {
        if (failedRunId === runIdRef.current) {
          setComposeError(describeDaemonError(err));
        }
      },
    };
  });
  const { resetSteerStatus, drain: drainQueue } = messageQueue;
  useEffect(() => {
    resetSteerStatus();
  }, [runId, resetSteerStatus]);
  const queued = runId === null ? [] : (messageQueue.queues[runId] ?? []);
  const deliveryFacts = {
    streaming: working,
    queued: queued.length > 0,
    held: (run?.holdingFor ?? 0) > 0,
    awaitingCalls: false,
    rootsIdle: false,
    subagentsOut: (run?.subagentsOut ?? 0) > 0,
    shellsOut: (run?.shellsOpen ?? 0) > 0,
  };
  const paused = runId !== null && messageQueue.pausedQueues.has(runId);
  const composerButton = followUpButton(
    followUpDelivery(deliveryFacts),
    working ? parkedReason(deliveryFacts) : null,
    paused,
  );
  const steer = useMemo(
    () =>
      steerReadiness(
        capabilities?.followUps ?? [],
        run?.agentKind ? [run.agentKind] : [],
      ),
    [capabilities, run?.agentKind],
  );

  useEffect(() => {
    onWorkingChange?.(working);
  }, [working, onWorkingChange]);

  // The same setting the chat screen reads, so a tool step folds here as it does
  // in a thread. Read again on activation: the builder stays mounted while it is
  // not on screen, so a change made in Settings reaches the surface only this way.
  useEffect(() => {
    if (!active) {
      return;
    }
    void window.geniro.getSettings().then((s) => {
      setCollapseToolSteps(s.collapseToolSteps ?? false);
    });
  }, [active]);

  const awaiting = run?.awaiting ?? null;
  useEffect(() => {
    onAwaitingChange?.(awaiting);
  }, [awaiting, onAwaitingChange]);

  // Keyed on the COUNT rather than on a boolean: two turns in a row must reload
  // the canvas twice, and an effect on `working` going false cannot tell the
  // second settle from the first.
  //
  // The queue's next message goes out only once the canvas has re-read what the
  // turn wrote: its send flushes the canvas first, and a flush before the reload
  // would write the pre-turn graph over the agent's edit.
  const settledSeen = useRef(settledTurns);
  useEffect(() => {
    if (settledTurns !== settledSeen.current) {
      settledSeen.current = settledTurns;
      void Promise.resolve(onTurnSettled?.()).finally(() => {
        if (runId !== null) {
          void drainQueue(runId);
        }
      });
    }
  }, [settledTurns, onTurnSettled, runId, drainQueue]);
  // A HELD turn has finished its reply and waits only for background
  // sub-agents, so it takes the queue's next message at once — as on the chat
  // screen, once per hold.
  const held = (run?.holdingFor ?? 0) > 0;
  useEffect(() => {
    if (held && runId !== null) {
      void drainQueue(runId);
    }
  }, [held, runId, drainQueue]);

  const agentApi = apis?.agents ?? null;
  const models = useAgentModels(agentApi, agentKind, configDir, model);
  const efforts = useAgentEfforts(agentApi, agentKind, model, configDir);
  const windows = useAgentContextWindows(agentApi, agentKind, model, configDir);
  const parameters = useAgentModelParameters(
    agentApi,
    agentKind,
    model,
    configDir,
  );
  const configDirCapability = configDirCapabilityFrom(
    capabilities,
    capabilitiesLoading,
  );
  const approvalCapability = useMemo(
    () => capabilities?.approvals.find((entry) => entry.agent === agentKind),
    [capabilities, agentKind],
  );

  /**
   * Save one chip. Before a conversation exists it only sets the create's draft.
   * Once one does, the save goes to the run and the chip shows what the daemon
   * answers with — the row — exactly as the chat screen's chips do. A save the
   * daemon refuses changes nothing, so there is nothing to put back. The draft
   * follows an accepted save, so the next conversation starts on the same choice.
   */
  const applySettings = useCallback(
    (
      draft: Partial<ChipValues>,
      patch: Parameters<typeof patchSettings>[0],
    ) => {
      const apply = (): void =>
        setDraftChips((current) => ({ ...current, ...draft }));
      if (run === null) {
        apply();
        return;
      }
      void patchSettings(patch).then((saved) => {
        if (saved) {
          apply();
        }
      });
    },
    [run, patchSettings],
  );
  const pickConfigDir = useCallback(async (): Promise<void> => {
    const chosen = await window.geniro.pickProjectFolder();
    if (chosen) {
      applySettings({ configDir: chosen }, { configDir: chosen });
    }
  }, [applySettings]);

  /**
   * The transcript, folded EXACTLY as the chat screen folds it — tool groups,
   * turn blocks, sub-agent enclosures and call cards — with the live plane laid
   * over the top.
   *
   * It used to map `chat.items` one row per item, which is why this surface
   * looked nothing like the chat: every tool call was its own bare row, nothing
   * folded, and a running turn showed no streaming text and no spinner at all
   * (REPORTED as "сейчас там нет ни иконки загрузки, ничего"). Reusing the fold
   * rather than re-deriving one is also what keeps the two surfaces honest — a
   * row that looks wrong here looks wrong in the chat screen too.
   */
  const entries = useMemo<TranscriptEntry[]>(() => {
    // ONE agent, so the fallback that draws `Working… 12s` under a turn nobody
    // has streamed a word for is keyed by the chat sentinel — the same key the
    // daemon files a chat's own deltas under. An agent parked on an approval
    // card is waiting on the person, so no working row is drawn for it.
    const workingAgents =
      working && awaiting === null
        ? new Set([CHAT_LIVE_KEY])
        : new Set<string>();
    return withLiveText(durableEntries, chat.liveText, workingAgents, runId);
  }, [durableEntries, chat.liveText, working, awaiting, runId]);

  const transcriptRef = useRef<HTMLDivElement | null>(null);
  useEffect(() => {
    const box = transcriptRef.current;
    if (box !== null) {
      box.scrollTop = box.scrollHeight;
    }
    // The LIVE plane too, not only the durable rows: a streaming answer grows
    // the box without adding an item, and following only items left the tail
    // of what the agent was writing off the bottom of a 320px dock (or a popup).
  }, [chat.items, chat.liveText]);

  const send = useCallback(async (): Promise<void> => {
    const text = draft.trim();
    const images = attachments.toWire();
    if (
      (text === '' && images.length === 0) ||
      attachBusy ||
      runId === null ||
      sendingRef.current
    ) {
      return;
    }
    setComposeError(null);
    const sentKeys = attachments.attachments.map(
      (attachment) => attachment.key,
    );
    // Queued or sent straight in by the chat screen's own rule — see
    // `followUpDelivery` and the table in apps/ui/AGENTS.md.
    const decision = followUpDelivery(deliveryFacts);
    if (decision.action === 'queue') {
      messageQueue.enqueue(runId, { text, images });
      setDraft('');
      attachments.clear(sentKeys);
      if (decision.kickDrain) {
        void messageQueue.drain(runId);
      }
      return;
    }
    sendingRef.current = true;
    const owner = ownerRef.current;
    try {
      await sendQueued(runId, text, images);
      if (owner === ownerRef.current) {
        setDraft((current) => (current === draft ? '' : current));
        attachments.clear(sentKeys);
      }
    } catch (err) {
      if (owner !== ownerRef.current) {
        return;
      }
      if (isRunBusyError(err)) {
        // The daemon is still finishing a turn this chat already believed over:
        // the queue sends it the moment the run can take it.
        messageQueue.enqueue(runId, { text, images });
        setDraft((current) => (current === draft ? '' : current));
        attachments.clear(sentKeys);
        void messageQueue.drain(runId);
        return;
      }
      setComposeError(describeDaemonError(err));
    } finally {
      sendingRef.current = false;
    }
  }, [
    draft,
    attachments,
    attachBusy,
    runId,
    deliveryFacts,
    messageQueue,
    sendQueued,
  ]);
  const error =
    composeError ?? chat.error ?? attachments.error ?? fileAttach.error;

  return (
    /* What a transcript row reaches for without being handed it — the SAME
       set the chat screen provides, so a row folded here reads and remembers
       exactly as it does there. `threadId` is answerable from this surface only
       for this conversation: a fold the reader presses here must not follow
       them into another conversation's. The sign-in, the retry and the direct
       line to a running call's callee have no meaning in a surface that runs
       one agent, so they stay null. The sub-agent detail dialog and the call
       jumps need the chat screen's own transcript scroller and dialog, so they
       stay null here too.

       `artifactUrl` IS answerable, and has to be: this runs an ordinary chat,
       so the daemon offers its agent `show_artifact` like any other. A null
       here would let the agent spend a turn writing a page and hand the user a
       card saying it cannot be opened. */
    <ChatProviders
      threadId={runId}
      signIn={null}
      retry={null}
      callContext={null}
      callChannel={null}
      artifactUrl={artifactUrl}
      runSettledAt={runSettledAt}
      delegatesOut={run?.subagentsOut ?? null}
      transcript={{
        collapseToolSteps,
        runActivity: chat.activity,
        turnDurations,
        revealCallBlock: null,
        revealCall: null,
        openSubagentDetail: null,
        cardBacked,
        loadImage: loadMarkdownImage,
        loadMetrics,
      }}
      loadAttachment={loadAttachment}
      applyRecommendations={applyRecommendations}>
      {header({ run, status })}

      <div
        ref={transcriptRef}
        data-slot={transcriptSlot}
        className="min-h-0 flex-1 space-y-2 overflow-y-auto px-3 py-2">
        {chat.loading && chat.items.length === 0 ? (
          <p className="text-xs text-muted-foreground">Opening the chat…</p>
        ) : null}
        {/* Gated on the ENTRIES, not on the items: a turn that has started
              and streamed nothing durable yet still puts a working row on
              screen, and the invitation to ask for a change printed under it
              would be describing a conversation already in progress. */}
        {!chat.loading && entries.length === 0 ? (
          <p className="text-xs text-muted-foreground">{emptyText}</p>
        ) : null}
        {/* An `approval_request` is intercepted here rather than left to the
            entry view, exactly as the chat screen intercepts it: the fold
            deliberately keeps that kind in the MAIN flow (a card folded into a
            collapsed block is a card nobody can see they must answer), and the
            row it draws is a CARD this chat has to wire its verdict channel
            into. Everything else goes through the shared renderer. */}
        {entries.map((entry) => (
          <TranscriptRow key={transcriptEntryKey(entry)}>
            {entry.type === 'item' && entry.item.kind === 'approval_request' ? (
              <ApprovalRow
                item={entry.item}
                verdicts={verdicts}
                unanswerable={unanswerable}
                onRespond={chat.respond}
              />
            ) : (
              <TranscriptEntryView
                entry={entry}
                // ONE agent and no nodes, so its rows need no identity frame —
                // the same exemption a 1:1 chat gets. The user's own messages
                // keep theirs; the conversation still has two sides.
                soloAgent
                chatAgentName={chat.run?.agentKind ?? agentKind}
              />
            )}
          </TranscriptRow>
        ))}
      </div>

      <div className="space-y-1 px-3 pt-1 pb-2">
        {error === null ? null : <ErrorText>{error}</ErrorText>}
        {queued.length === 0 ? null : (
          <QueuedStrip
            messages={queued}
            paused={paused}
            turnInFlight={working}
            advancing={working}
            postingIds={messageQueue.postingIds}
            steerUnavailableReason={steer.reason}
            steerInterrupts={steer.interrupts}
            steerStatus={messageQueue.steerStatus}
            onEdit={messageQueue.edit}
            onRemove={messageQueue.remove}
            onReorder={messageQueue.reorder}
            onSteer={(id) => void messageQueue.steer(id)}
            onTogglePause={messageQueue.togglePause}
          />
        )}
        <MessageComposer
          attachments={attachments.attachments}
          onRemoveAttachment={attachments.remove}
          onAttachFiles={fileAttach.attach}
          onPasteImages={attachments.addFromClipboard}
          textareaProps={{
            value: draft,
            rows: 2,
            disabled: chat.run === null,
            onChange: (event) => setDraft(event.target.value),
            onKeyDown: (event) => {
              if (isComposerSendKey(event)) {
                event.preventDefault();
                void send();
              }
            },
            'aria-label': composerLabel,
            placeholder: composerPlaceholder,
          }}
          actions={
            <>
              {/* While a turn runs it QUEUES, and says so — the chat
                  screen's own button, read off the same decision. */}
              {!working || hasContent || attachBusy ? (
                <Button
                  type="button"
                  size="icon"
                  className="size-8 rounded-full"
                  aria-label={composerButton.label}
                  title={attachBusy ? attachBusyTitle : composerButton.title}
                  disabled={!hasContent || chat.run === null || attachBusy}
                  onClick={() => void send()}>
                  {composerButton.label === 'Queue' ? (
                    <Clock className="size-3.5 shrink-0" />
                  ) : (
                    <ArrowUp className="size-3.5 shrink-0" />
                  )}
                </Button>
              ) : null}
              {working ? (
                <Button
                  type="button"
                  variant="destructive"
                  size="icon"
                  className="size-8 rounded-full"
                  aria-label="Stop"
                  title="Stop the current turn"
                  onClick={() => void chat.cancel()}>
                  <Square className="size-3 shrink-0" />
                </Button>
              ) : null}
            </>
          }>
          {chat.run === null && onDraftChipsChange !== undefined ? (
            <TargetSelect
              value={agentKind}
              workflows={NO_WORKFLOW_TARGETS}
              cliDetections={null}
              aria-label="Agent for this chat"
              onChange={(target) =>
                setDraftChips((current) => ({
                  ...current,
                  agentKind: target as AgentKind,
                }))
              }
            />
          ) : null}
          <ModelSettingsSelect
            agentKind={agentKind}
            models={models.models}
            model={model}
            onModelChange={(next) =>
              // A window and the model's other parameters belong to the model
              // that offered them, so they go with it.
              applySettings(
                { model: next, contextWindow: null, modelParameters: {} },
                { model: next, contextWindow: null, modelParameters: null },
              )
            }
            efforts={efforts.efforts}
            effort={effort}
            onEffortChange={(next) =>
              applySettings({ effort: next }, { effort: next })
            }
            approvalCapability={approvalCapability}
            approval={approval}
            withheld={PLAN_WITHHELD}
            onApprovalChange={(next) =>
              applySettings({ approval: next }, { approval: next })
            }
            windows={windows.windows}
            contextWindow={contextWindow}
            onContextWindowChange={(next) =>
              applySettings({ contextWindow: next }, { contextWindow: next })
            }
            parameters={parameters.parameters}
            parameterValues={modelParameters}
            onParameterChange={(parameterId, value) => {
              const next = withModelParameter(
                modelParameters,
                parameterId,
                value,
              );
              applySettings(
                { modelParameters: next },
                { modelParameters: next },
              );
            }}
            configDir={configDir}
            recentConfigDirs={
              recentConfigDirs[agentKind] ?? EMPTY_RECENT_CONFIG_DIRS
            }
            configProfiles={configProfiles.filter(
              (profile) => profile.agent === agentKind,
            )}
            configDirUnavailableReason={configDirCapability.unavailableReasonFor(
              agentKind,
            )}
            onConfigDirChange={(next) =>
              applySettings({ configDir: next }, { configDir: next })
            }
            settingsLoading={
              efforts.loading || windows.loading || parameters.loading
            }
            loading={models.loading}
            nextTurnOnly={working}
            windowTokens={ring.window}
            autoCompactPercent={run?.autoCompactPercent ?? null}
            onAutoCompactChange={
              run === null
                ? undefined
                : (percent) =>
                    void patchSettings({ autoCompactPercent: percent })
            }
            onBrowseConfigDir={() => void pickConfigDir()}
          />
          {run === null ? null : (
            <ContextMeter
              className="ml-1.5"
              runId={run.id}
              contextTokens={ring.tokens}
              contextWindowTokens={ring.window}
              contextEstimated={ring.estimated}
              awaitingReading={awaitingReading}
              live={isWorkingRunStatus(status)}
              side="top"
            />
          )}
        </MessageComposer>
      </div>
    </ChatProviders>
  );
}

/**
 * One approval or question card in a hosted chat.
 *
 * The chat screen composes exactly this, and the three exclusions are read from
 * the same helpers it reads them from — a card that shows as answered must not
 * still be answerable, on either surface.
 */
function ApprovalRow({
  item,
  verdicts,
  unanswerable,
  onRespond,
}: {
  item: ChatItem;
  verdicts: ReturnType<typeof collectVerdicts>;
  unanswerable: ReadonlySet<string>;
  onRespond: (requestId: string, allow: boolean, answer?: string) => void;
}): React.JSX.Element | null {
  const requestId = payloadString(item.payload, 'id');
  if (requestId === null) {
    return null;
  }
  const settled = verdicts.get(requestId) ?? null;
  return (
    <ApprovalCard
      toolName={payloadString(item.payload, 'toolName') ?? 'tool'}
      input={(item.payload as { input?: unknown } | null)?.input ?? null}
      questions={(item.payload as { questions?: unknown } | null)?.questions}
      requestId={requestId}
      verdict={settled?.allow ?? null}
      answer={settled?.answer ?? null}
      expired={unanswerable.has(requestId)}
      onRespond={(allow, answer) => onRespond(requestId, allow, answer)}
    />
  );
}
