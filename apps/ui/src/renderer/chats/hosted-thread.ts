import type { ReactNode } from 'react';

import type { RunAwaiting, RunDto } from '../autogenerated';

/**
 * A conversation the chat screen draws on its own, in another surface — the
 * team builder's chat dock, a thread's or a team's analysis popup. The run is
 * an ordinary chat the sidebar never lists, so the surface says how to open it
 * and the chat screen does everything else exactly as it does for a thread.
 */
export interface HostedThread {
  /** The conversation as it reads now, created where the surface does that. */
  open: () => Promise<RunDto>;
  /** Throw the conversation away; the next `open` starts a new one. */
  discard?: () => Promise<void>;
  /**
   * Which stored queue is this surface's, stable across closing and reopening
   * it, so a message queued before it closed goes out once it is back.
   */
  queueScope: string;
  /** The surface's own controls, drawn at the end of the thread's header. */
  headerActions?: (controls: { discard: (() => void) | null }) => ReactNode;
  /** What an empty conversation says it is for. */
  emptyText: string;
  composerLabel: string;
  composerPlaceholder: string;
  /** Put in the composer once, when the conversation first opens. */
  initialDraft?: string;
  /** Run before a message, a button press, an Apply or a Retry reaches the daemon. */
  onBeforeSend?: () => Promise<unknown>;
  onWorkingChange?: (working: boolean) => void;
  /** The agent is waiting on the user — a question or an approval — or no longer is. */
  onAwaitingChange?: (awaiting: RunAwaiting | null) => void;
  /**
   * Called as a turn's ending arrives, before a queued message goes out
   * behind it, so `onBeforeSend` can wait on what this starts.
   */
  onTurnSettled?: () => void | Promise<void>;
  /** The user changed the conversation's settings; `run` reads as they now stand. */
  onRunSettingsChanged?: (run: RunDto) => void | Promise<void>;
}
