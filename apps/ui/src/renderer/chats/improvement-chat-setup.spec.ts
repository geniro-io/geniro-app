// @vitest-environment jsdom
import { beforeEach, describe, expect, it, vi } from 'vitest';

import {
  type AnalysisConfig,
  DEFAULT_SETTINGS,
  type Settings,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { RunDto } from '../autogenerated';
import {
  openChangeChat,
  rememberAnalysisSetup,
  rememberChangeChatSetup,
} from './improvement-chat-setup';

const REMEMBERED: AnalysisConfig = {
  agent: 'codex',
  configDir: '/profiles/work',
  model: 'gpt-5.5',
  effort: 'high',
  contextWindow: '1m',
  autoCompactPercent: 80,
  modelParameters: { fast: 'on' },
  approval: 'auto',
};

const RUN = {
  id: 'r1',
  agentKind: 'codex',
  configDir: '/profiles/work',
  model: 'gpt-5.5',
  effort: 'xhigh',
  contextWindow: '1m',
  autoCompactPercent: 70,
  modelParameters: { fast: 'on' },
  approval: 'ask',
} as unknown as RunDto;

const OPENED = { id: 'opened' } as RunDto;

let settings: Partial<Settings>;
let updates: Partial<Settings>[];

beforeEach(() => {
  settings = {};
  updates = [];
  window.geniro = createPreloadStub({
    getSettings: () => Promise.resolve({ ...DEFAULT_SETTINGS, ...settings }),
    updateSettings: (patch) => {
      updates.push(patch);
      return Promise.resolve({ ...DEFAULT_SETTINGS, ...settings });
    },
  });
});

describe('openChangeChat', () => {
  it('opens on the CLI’s defaults while nothing is remembered', async () => {
    const start = vi.fn().mockResolvedValue(OPENED);

    await expect(openChangeChat(start)).resolves.toBe(OPENED);

    expect(start).toHaveBeenCalledWith({
      agentKind: 'claude',
      approval: 'acceptEdits',
      agentOptions: {},
    });
  });

  it('opens on the whole remembered setup, without the analysis’s auto-approve', async () => {
    settings = { lastAnalysisConfig: REMEMBERED };
    const start = vi.fn().mockResolvedValue(OPENED);

    await openChangeChat(start);

    expect(start).toHaveBeenCalledWith({
      agentKind: 'codex',
      approval: 'acceptEdits',
      agentOptions: {},
      configDir: '/profiles/work',
      model: 'gpt-5.5',
      effort: 'high',
      contextWindow: '1m',
      autoCompactPercent: 80,
      modelParameters: { fast: 'on' },
    });
  });

  it('opens on the approval mode last chosen in these chats', async () => {
    settings = { lastChangeChatApproval: 'ask' };
    const start = vi.fn().mockResolvedValue(OPENED);

    await openChangeChat(start);

    expect(start.mock.calls[0]![0].approval).toBe('ask');
  });

  it('keeps an agent picked for this chat, leaving out another CLI’s setup', async () => {
    settings = { lastAnalysisConfig: REMEMBERED };
    const start = vi.fn().mockResolvedValue(OPENED);

    await openChangeChat(start, 'claude');

    expect(start).toHaveBeenCalledWith({
      agentKind: 'claude',
      approval: 'acceptEdits',
      agentOptions: {},
    });
  });

  it('applies the setup to a picked agent it describes', async () => {
    settings = { lastAnalysisConfig: REMEMBERED };
    const start = vi.fn().mockResolvedValue(OPENED);

    await openChangeChat(start, 'codex');

    expect(start.mock.calls[0]![0].model).toBe('gpt-5.5');
  });

  it('opens on defaults when the daemon refuses a stale setup', async () => {
    settings = { lastAnalysisConfig: REMEMBERED };
    const start = vi
      .fn()
      .mockRejectedValueOnce(new Error('EFFORT_UNSUPPORTED'))
      .mockResolvedValueOnce(OPENED);

    await expect(openChangeChat(start)).resolves.toBe(OPENED);

    expect(start).toHaveBeenCalledTimes(2);
    expect(start.mock.calls[1]![0]).toEqual({
      agentKind: 'codex',
      approval: 'acceptEdits',
      agentOptions: {},
    });
  });

  it('reports a refusal of the defaults themselves, asking once', async () => {
    const start = vi.fn().mockRejectedValue(new Error('PROJECT_NOT_FOUND'));

    await expect(openChangeChat(start)).rejects.toThrow('PROJECT_NOT_FOUND');

    expect(start).toHaveBeenCalledTimes(1);
  });
});

describe('rememberAnalysisSetup', () => {
  it('records the run’s whole setup, approval included', async () => {
    await rememberAnalysisSetup(RUN);

    expect(updates).toEqual([
      {
        lastAnalysisConfig: {
          agent: 'codex',
          configDir: '/profiles/work',
          model: 'gpt-5.5',
          effort: 'xhigh',
          contextWindow: '1m',
          autoCompactPercent: 70,
          modelParameters: { fast: 'on' },
          approval: 'ask',
        },
      },
    ]);
  });

  it('keeps the mode it had when the chat moves to plan', async () => {
    settings = { lastAnalysisConfig: REMEMBERED };

    await rememberAnalysisSetup({ ...RUN, approval: 'plan' });

    expect(updates[0]!.lastAnalysisConfig?.approval).toBe('auto');
  });
});

describe('rememberChangeChatSetup', () => {
  it('records the setup, its approval apart from the analysis’s', async () => {
    settings = { lastAnalysisConfig: REMEMBERED };

    await rememberChangeChatSetup(RUN);

    expect(updates[0]!.lastChangeChatApproval).toBe('ask');
    expect(updates[0]!.lastAnalysisConfig).toEqual({
      agent: 'codex',
      configDir: '/profiles/work',
      model: 'gpt-5.5',
      effort: 'xhigh',
      contextWindow: '1m',
      autoCompactPercent: 70,
      modelParameters: { fast: 'on' },
      approval: 'auto',
    });
  });

  it('drops the analysis’s mode when the chat runs another CLI', async () => {
    settings = { lastAnalysisConfig: REMEMBERED };

    await rememberChangeChatSetup({ ...RUN, agentKind: 'claude' });

    expect(updates[0]!.lastAnalysisConfig?.agent).toBe('claude');
    expect(updates[0]!.lastAnalysisConfig?.approval).toBeNull();
  });

  it('keeps the mode it had when the chat moves to plan', async () => {
    settings = { lastChangeChatApproval: 'ask' };

    await rememberChangeChatSetup({ ...RUN, approval: 'plan' });

    expect(updates[0]!.lastChangeChatApproval).toBe('ask');
  });

  it('writes nothing for a run with no agent of its own', async () => {
    await rememberChangeChatSetup({ ...RUN, agentKind: null });

    expect(updates).toEqual([]);
  });

  it('survives a memory that cannot be written', async () => {
    window.geniro = createPreloadStub({
      getSettings: () => Promise.resolve(DEFAULT_SETTINGS),
      updateSettings: () => Promise.reject(new Error('refused')),
    });

    await expect(rememberChangeChatSetup(RUN)).resolves.toBeUndefined();
  });
});
