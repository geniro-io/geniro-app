import {
  type AnalysisConfig,
  CLI_KINDS,
  type CliKind,
} from '../../shared/contracts';
import type {
  ChatApprovalMode,
  RunDto,
  StartProjectChatDto,
} from '../autogenerated';
import { currentRunSettings } from '../run-settings';
import { PLAN_WITHHELD } from './approval-mode-select';
import { isChatApprovalMode } from './composer-values';

/**
 * A team's or a project's chat saves through the daemon as a file edit, and
 * `ask` would put a card in front of every save. A CLI without the mode opens
 * on its own default: the daemon narrows it.
 */
const CHANGE_CHAT_DEFAULT_APPROVAL: ChatApprovalMode = 'acceptEdits';

/** A config's model settings as a create payload names them: unset is absent. */
export function setupFieldsOf(
  config: Omit<AnalysisConfig, 'agent' | 'approval'>,
): Pick<
  StartProjectChatDto,
  | 'configDir'
  | 'model'
  | 'effort'
  | 'contextWindow'
  | 'autoCompactPercent'
  | 'modelParameters'
> {
  return {
    ...(config.configDir === null ? {} : { configDir: config.configDir }),
    ...(config.model === null ? {} : { model: config.model }),
    ...(config.effort === null ? {} : { effort: config.effort }),
    ...(config.contextWindow === null
      ? {}
      : { contextWindow: config.contextWindow }),
    ...(config.autoCompactPercent === null
      ? {}
      : { autoCompactPercent: config.autoCompactPercent }),
    ...(Object.keys(config.modelParameters).length === 0
      ? {}
      : { modelParameters: config.modelParameters }),
  };
}

/**
 * Open a team's or a project's chat. A chat that already exists keeps its own
 * settings (the daemon ignores these); a new one starts on the last setup used
 * in these chats, unless `pickedAgent` names another CLI, whose models and
 * profiles the setup does not describe. These docks have no setup to fix a
 * refusal in, so a stale setup (an effort or a profile gone) opens on defaults.
 */
export async function openChangeChat(
  start: (dto: StartProjectChatDto) => Promise<RunDto>,
  pickedAgent?: CliKind,
): Promise<RunDto> {
  const settings = await window.geniro.getSettings();
  const remembered = settings.lastAnalysisConfig;
  const agentKind = pickedAgent ?? remembered?.agent ?? CLI_KINDS[0]!;
  const bare: StartProjectChatDto = {
    agentKind,
    approval: isChatApprovalMode(settings.lastChangeChatApproval)
      ? settings.lastChangeChatApproval
      : CHANGE_CHAT_DEFAULT_APPROVAL,
    ...(await currentRunSettings()),
  };
  const setup =
    remembered?.agent === agentKind ? setupFieldsOf(remembered) : {};
  if (Object.keys(setup).length === 0) {
    return start(bare);
  }
  return start({ ...bare, ...setup }).catch(() => start(bare));
}

function configOfRun(
  run: RunDto,
  agent: CliKind,
): Omit<AnalysisConfig, 'approval'> {
  return {
    agent,
    configDir: run.configDir,
    model: run.model,
    effort: run.effort,
    contextWindow: run.contextWindow,
    autoCompactPercent: run.autoCompactPercent,
    modelParameters: run.modelParameters,
  };
}

/** `plan` is a move within one conversation, never how the next one starts. */
function approvalToKeep(
  run: RunDto,
  earlier: string | null | undefined,
): string | null {
  return run.approval === null || PLAN_WITHHELD.includes(run.approval)
    ? (earlier ?? null)
    : run.approval;
}

/** The user changed the setup of a thread's or a team's analysis in its chat. */
export function rememberAnalysisSetup(run: RunDto): Promise<void> {
  return remember(run, (agent, earlier) => ({
    lastAnalysisConfig: {
      ...configOfRun(run, agent),
      approval: approvalToKeep(run, earlier?.approval),
    },
  }));
}

/**
 * The user changed the setup of a team's or a project's chat. Its approval
 * mode is kept apart: an analysis's auto-approve must not reach these chats.
 */
export function rememberChangeChatSetup(run: RunDto): Promise<void> {
  return remember(run, (agent, earlier, approval) => ({
    lastAnalysisConfig: {
      ...configOfRun(run, agent),
      approval: earlier?.agent === agent ? earlier.approval : null,
    },
    lastChangeChatApproval: approvalToKeep(run, approval),
  }));
}

async function remember(
  run: RunDto,
  patchFor: (
    agent: CliKind,
    earlier: AnalysisConfig | null | undefined,
    changeChatApproval: string | null | undefined,
  ) => Parameters<typeof window.geniro.updateSettings>[0],
): Promise<void> {
  const agent = run.agentKind;
  if (agent === null) {
    return;
  }
  // The choice was made in the run; a memory that cannot be written costs only the next default.
  await window.geniro
    .getSettings()
    .then((settings) =>
      window.geniro.updateSettings(
        patchFor(
          agent,
          settings.lastAnalysisConfig,
          settings.lastChangeChatApproval,
        ),
      ),
    )
    .catch(() => undefined);
}
