import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { foldsHolding } from './jump-folds';
import { groupTranscript, type TranscriptEntry } from './transcript-groups';

function row(
  seq: number,
  kind: ChatItem['kind'],
  payload: unknown,
  id = `i${seq}`,
): ChatItem {
  return {
    id,
    runId: 'run-12345678',
    nodeId: null,
    seq,
    kind,
    role: kind === 'message' ? 'assistant' : null,
    payload,
    createdAt: 'now',
  };
}

/** Only the shape the walk reads; the rest of a block is irrelevant here. */
const block = (
  type: 'subagent-block' | 'call-block',
  id: string,
  entries: TranscriptEntry[],
): TranscriptEntry => ({ type, id, entries }) as unknown as TranscriptEntry;

describe('foldsHolding', () => {
  it("opens a command's group and its row for a hit in the command's result", () => {
    const entries = groupTranscript([
      row(1, 'tool_call', { id: 't1', name: 'Bash', input: { command: 'ls' } }),
      row(2, 'tool_result', { id: 't1', result: 'a' }),
      row(3, 'tool_call', { id: 't2', name: 'Bash', input: { command: 'df' } }),
      row(4, 'tool_result', { id: 't2', result: 'the needle' }),
    ]);

    expect(foldsHolding(entries, 4)).toEqual(['tools:i1', 'tool:i3']);
  });

  it('keys the run of plain calls an agent action splits a group into, as the group draws it', () => {
    const entries = groupTranscript([
      row(1, 'tool_call', { id: 't1', name: 'Bash', input: { command: 'ls' } }),
      row(2, 'tool_result', { id: 't1', result: 'a' }),
      row(3, 'tool_call', {
        id: 't2',
        name: 'mcp__geniro-run-1234__message_agent',
        input: {},
      }),
      row(4, 'tool_result', { id: 't2', result: 'sent' }),
      row(5, 'tool_call', { id: 't3', name: 'Bash', input: { command: 'df' } }),
      row(6, 'tool_result', { id: 't3', result: 'b' }),
    ]);

    expect(foldsHolding(entries, 6)).toEqual(['tools:i5', 'tool:i5']);
    // The action itself is drawn in no fold.
    expect(foldsHolding(entries, 4)).toEqual([]);
  });

  it('opens a long reasoning a hit is in, and nothing for a message', () => {
    const entries = groupTranscript([
      row(1, 'reasoning', { text: 'thinking hard' }),
      row(2, 'message', { text: 'done' }),
    ]);

    expect(foldsHolding(entries, 1)).toEqual(['thinking:i1']);
    expect(foldsHolding(entries, 2)).toEqual([]);
  });

  it('opens the delegate a row IS in, never another whose seqs span it', () => {
    // Two delegates of one fan-out interleave: B starts nearer the hit and
    // its seqs span it, but the row is A's.
    const [a] = groupTranscript([
      row(58, 'tool_call', { id: 'ta', name: 'Bash', input: { command: 'x' } }),
      row(60, 'tool_result', { id: 'ta', result: 'hit' }),
    ]);
    const [b] = groupTranscript([row(59, 'message', { text: 'B speaks' })]);
    const entries = [
      block('subagent-block', 'A', [a!]),
      block('subagent-block', 'B', [
        b!,
        ...groupTranscript([row(95, 'message', { text: 'B ends' })]),
      ]),
    ];

    expect(foldsHolding(entries, 60)).toEqual([
      'subagent:A',
      'tools:i58',
      'tool:i58',
    ]);
    expect(foldsHolding(entries, 59)).toEqual(['subagent:B']);
  });

  it('names the card a row is in, and answers nothing for a row the transcript does not hold', () => {
    const entries = [
      block(
        'call-block',
        'card-1',
        groupTranscript([row(7, 'message', { text: 'x' })]),
      ),
    ];

    expect(foldsHolding(entries, 7)).toEqual(['call:card-1']);
    expect(foldsHolding(entries, 8)).toEqual([]);
  });
});
