describe('the documents a panel reads as they stand now', () => {
  const search = (): ToolPair =>
    pair(
      'knowledge_search',
      { query: 'release' },
      {
        text: [TWO_DOCUMENTS, COMMIT_FORMAT, RELEASE_CHECKLIST_UNREVIEWED].join(
          '\n',
        ),
      },
    );

  function drawWith(
    loader: KnowledgeLoader | null,
    open: (target: KnowledgeOpenTarget) => void = () => undefined,
  ): void {
    const entry = knowledgeToolEntryOf(search());
    if (entry === null) {
      throw new Error('expected a knowledge entry');
    }
    act(() =>
      root.render(
        <KnowledgeLoaderContext.Provider value={loader}>
          <KnowledgeOpenContext.Provider value={open}>
            <KnowledgeToolRow entry={entry} status="done" />
          </KnowledgeOpenContext.Provider>
        </KnowledgeLoaderContext.Provider>,
      ),
    );
  }

  function bareSuccess(tool: string, input: unknown): KnowledgeToolEntry {
    const entry = knowledgeToolEntryOf(
      pair(tool, input, { text: { success: true } }),
    );
    if (entry === null) {
      throw new Error('expected a knowledge entry');
    }
    return entry;
  }

  async function settle(): Promise<void> {
    await act(async () => {
      await new Promise((resolve) => setTimeout(resolve, 0));
    });
  }

  const docOf = (handle: string): string =>
    container.querySelector(`[data-knowledge-doc="${handle}"]`)?.textContent ??
    '';

  it('asks the loader for each handle the call named, once the panel opens', async () => {
    const loader = vi.fn().mockResolvedValue([]);
    drawWith(loader);
    expect(loader).not.toHaveBeenCalled();

    await press();

    expect(loader.mock.calls).toEqual([
      ['commit-format'],
      ['release-checklist'],
    ]);
  });

  it('shows the title, when to read it and the flags of the document as it stands now', async () => {
    drawWith(async (handle) =>
      handle === 'release-checklist'
        ? [
            aKnowledgeHead({
              id: 'd9',
              title: 'Release checklist v2',
              whenToRead: 'Before a release cut.',
              approvedAt: null,
              status: 'archived',
            }),
          ]
        : [],
    );
    await press();
    await settle();

    const checklist = docOf('release-checklist');
    expect(checklist).toContain('Release checklist v2');
    expect(checklist).toContain('Before a release cut.');
    expect(checklist).not.toContain('Cutting a release.');
    expect(checklist).toContain('unreviewed');
    expect(checklist).toContain('archived');
  });

  it('prefers the document at the level the call named over one at another level', async () => {
    const open = vi.fn();
    drawWith(
      async (handle) =>
        handle === 'release-checklist'
          ? [
              aKnowledgeHead({
                id: 'd-global',
                title: 'Global one',
                place: 'global',
                projectId: null,
              }),
              aKnowledgeHead({ id: 'd-project', title: 'Project one' }),
            ]
          : [],
      open,
    );
    await press();
    await settle();

    expect(docOf('release-checklist')).toContain('Project one');
    expect(docOf('release-checklist')).not.toContain('Global one');
    linksToKnowledge()[0]?.click();
    expect(open).toHaveBeenCalledExactlyOnceWith({ documentId: 'd-project' });
  });

  it('says a document is no longer in Knowledge, with no link, when nothing is filed under its handle', async () => {
    drawWith(async () => []);
    await press();
    await settle();

    expect(container.textContent).toContain('No longer in Knowledge.');
    expect(linksToKnowledge()).toHaveLength(0);
  });

  it('says a document is gone when only another level still holds its handle', async () => {
    drawWith(async () => [
      aKnowledgeHead({ place: 'team:dev', title: 'Team one' }),
    ]);
    await press();
    await settle();

    expect(container.textContent).toContain('No longer in Knowledge.');
    expect(container.textContent).not.toContain('Team one');
  });

  it('prefers a live document over a nearer archived one when the call named no level', async () => {
    const entry = knowledgeToolEntryOf(
      pair(
        'knowledge_save',
        { handle: 'release-checklist', reason: 'r' },
        { text: 'Saved `release-checklist` at rev 2.' },
      ),
    );
    if (entry === null) {
      throw new Error('expected a knowledge entry');
    }
    const loader: KnowledgeLoader = async () => [
      aKnowledgeHead({ status: 'archived', title: 'Old project one' }),
      aKnowledgeHead({ place: 'global', title: 'Live global one' }),
    ];
    act(() =>
      root.render(
        <KnowledgeLoaderContext.Provider value={loader}>
          <KnowledgeToolRow entry={entry} status="done" />
        </KnowledgeLoaderContext.Provider>,
      ),
    );
    await press();
    await settle();

    expect(container.textContent).toContain('Live global one');
    expect(container.textContent).not.toContain('Old project one');
  });

  it('searches for itself when the CLI reported the result as a bare success', async () => {
    const entry = bareSuccess('knowledge_search', { query: 'release' });
    const search = vi.fn(async () => [
      aKnowledgeHead({ title: 'Nearest one' }),
      aKnowledgeHead({ place: 'global', title: 'Shadowed one' }),
    ]);
    const open = vi.fn();
    act(() =>
      root.render(
        <KnowledgeSearcherContext.Provider value={search}>
          <KnowledgeOpenContext.Provider value={open}>
            <KnowledgeToolRow entry={entry} status="done" />
          </KnowledgeOpenContext.Provider>
        </KnowledgeSearcherContext.Provider>,
      ),
    );
    await press();
    await settle();

    expect(search).toHaveBeenCalledExactlyOnceWith('release');
    expect(container.textContent).toContain('Nearest one');
    expect(container.textContent).not.toContain('Shadowed one');
    act(() => linksToKnowledge()[0]?.click());
    expect(open).toHaveBeenCalledExactlyOnceWith({ documentId: 'd1' });
  });

  it('says nothing matches now when its own search comes back empty', async () => {
    const entry = bareSuccess('knowledge_search', { query: 'release' });
    act(() =>
      root.render(
        <KnowledgeSearcherContext.Provider value={async () => []}>
          <KnowledgeToolRow entry={entry} status="done" />
        </KnowledgeSearcherContext.Provider>,
      ),
    );
    await press();
    await settle();

    expect(container.textContent).toContain(
      'Nothing in Knowledge matches this search now.',
    );
  });

  it('reads the arguments a CLI keeps one level down', async () => {
    const entry = knowledgeToolEntryOf({
      ...pair('knowledge_search', {}, { text: { success: true } }),
      call: item('tool_call', {
        id: 'c1',
        name: `${SERVER}: knowledge_search`,
        input: {
          providerIdentifier: SERVER,
          toolName: 'knowledge_search',
          args: { query: 'release' },
        },
      }),
    });
    expect(entry).toMatchObject({ tool: 'knowledge_search', query: 'release' });
  });

  it('offers a read’s document from its arguments when the result has no text', async () => {
    const entry = bareSuccess('knowledge_read', {
      handle: 'release-checklist',
    });
    act(() =>
      root.render(
        <KnowledgeLoaderContext.Provider
          value={async () => [aKnowledgeHead({ title: 'Fresh title' })]}>
          <KnowledgeToolRow entry={entry} status="done" />
        </KnowledgeLoaderContext.Provider>,
      ),
    );
    await press();
    await settle();

    expect(container.textContent).toContain('Fresh title');
  });

  it('opens a document whose handle is an inherited object key', async () => {
    const entry = knowledgeToolEntryOf(
      pair(
        'knowledge_search',
        { query: 'constructor' },
        {
          text: [
            '1 document.',
            '- constructor (rev 1, global, 1.0 KB) — Constructor. When: Building.',
          ].join('\n'),
        },
      ),
    );
    if (entry === null) {
      throw new Error('expected a knowledge entry');
    }
    act(() =>
      root.render(
        <KnowledgeLoaderContext.Provider value={async () => []}>
          <KnowledgeToolRow entry={entry} status="done" />
        </KnowledgeLoaderContext.Provider>,
      ),
    );
    await press();

    expect(
      container.querySelector('[data-knowledge-doc="constructor"]'),
    ).not.toBeNull();
    await settle();
    expect(container.textContent).toContain('No longer in Knowledge.');
  });

  it('keeps what the call said when the loader fails', async () => {
    drawWith(async () => {
      throw new Error('daemon GET /v1/knowledge failed (500): boom');
    });
    await press();
    await settle();

    const checklist = docOf('release-checklist');
    expect(checklist).toContain('Release checklist');
    expect(checklist).toContain('Cutting a release.');
    expect(checklist).toContain('unreviewed');
    expect(linksToKnowledge()).toHaveLength(2);
  });

  it('opens a document by its handle while no fresh read has found it', async () => {
    const open = vi.fn();
    drawWith(() => new Promise(() => undefined), open);
    await press();

    linksToKnowledge()[1]?.click();

    expect(open).toHaveBeenCalledExactlyOnceWith({
      handle: 'release-checklist',
    });
  });

  it('opens a document by its id once a fresh read has found it', async () => {
    const open = vi.fn();
    drawWith(
      async (handle) =>
        handle === 'release-checklist'
          ? [aKnowledgeHead({ id: 'd-fresh' })]
          : [],
      open,
    );
    await press();
    await settle();

    expect(linksToKnowledge()).toHaveLength(1);
    linksToKnowledge()[0]?.click();

    expect(open).toHaveBeenCalledExactlyOnceWith({ documentId: 'd-fresh' });
  });
});

