const RUN_ID = 'abc12345-0000-0000-0000-000000000000';
const SERVER = 'geniro-abc12345';

function item(kind: 'tool_call' | 'tool_result', payload: unknown): ChatItem {
  return {
    id: `i-${Math.random()}`,
    runId: RUN_ID,
    memberId: 'orch',
    seq: 1,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function pair(
  tool: string,
  input: unknown,
  result?: { text: unknown; isError?: boolean },
): ToolPair {
  return {
    call: item('tool_call', {
      id: 'c1',
      name: `mcp__${SERVER}__${tool}`,
      input,
    }),
    result:
      result === undefined
        ? null
        : item('tool_result', {
            id: 'c1',
            result: result.text,
            isError: result.isError ?? false,
          }),
  };
}

const COMMIT_FORMAT =
  '- commit-format (rev 2, global, 0.7 KB) — Commit format. When: Writing a commit.';
const RELEASE_CHECKLIST_UNREVIEWED =
  '- release-checklist (rev 7, project, 2.0 KB, unreviewed) — Release checklist. When: Cutting a release.';
const RELEASE_CHECKLIST =
  '- release-checklist (rev 7, project, 2.0 KB) — Release checklist. When: Cutting a release.';
const TWO_DOCUMENTS =
  'Knowledge documents this run sees — 2 documents. Unmarked ones were written or approved by the user:';

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function draw(
  source: ToolPair,
  options: {
    status?: BlockStatus;
    open?: ((target: KnowledgeOpenTarget) => void) | null;
  } = {},
): void {
  const entry = knowledgeToolEntryOf(source);
  if (entry === null) {
    throw new Error('expected a knowledge entry');
  }
  act(() =>
    root.render(
      <KnowledgeOpenContext.Provider value={options.open ?? null}>
        <KnowledgeToolRow entry={entry} status={options.status ?? 'done'} />
      </KnowledgeOpenContext.Provider>,
    ),
  );
}

function line(): string {
  return (container.textContent ?? '').replace(/\s+/g, ' ').trim();
}

describe('knowledge_search', () => {
  it('counts the documents the result lists and shows the query', () => {
    draw(
      pair(
        'knowledge_search',
        { query: 'release' },
        {
          text: [
            TWO_DOCUMENTS,
            COMMIT_FORMAT,
            RELEASE_CHECKLIST_UNREVIEWED,
          ].join('\n'),
        },
      ),
    );
    expect(line()).toBe('Searched knowledge · “release” · 2 documents');
  });

  it('counts every document a search matched, not only the ones it showed', () => {
    draw(
      pair(
        'knowledge_search',
        { query: 'release' },
        {
          text: [
            'Knowledge documents this run sees — Showing 1 of 9. Unmarked ones were written or approved by the user:',
            COMMIT_FORMAT,
          ].join('\n'),
        },
      ),
    );
    expect(line()).toBe('Searched knowledge · “release” · 9 documents');
  });

  it('says 0 documents for a search that matched nothing, and 1 document in the singular', () => {
    draw(
      pair(
        'knowledge_search',
        { query: 'zebra' },
        { text: 'No knowledge document this run sees matches "zebra".' },
      ),
    );
    expect(line()).toBe('Searched knowledge · “zebra” · 0 documents');
    draw(
      pair(
        'knowledge_search',
        { query: 'commit' },
        {
          text: [
            'Knowledge documents this run sees — 1 document. Unmarked ones were written or approved by the user:',
            COMMIT_FORMAT,
          ].join('\n'),
        },
      ),
    );
    expect(line()).toBe('Searched knowledge · “commit” · 1 document');
  });

  it('lists what the run sees when the search named no words', () => {
    draw(
      pair(
        'knowledge_search',
        {},
        { text: 'This run sees no knowledge documents.' },
      ),
    );
    expect(line()).toBe('Searched knowledge · 0 documents');
  });

  it('reads a result delivered as MCP content blocks', () => {
    draw(
      pair(
        'knowledge_search',
        { query: 'commit' },
        {
          text: [
            {
              type: 'text',
              text: [
                'Knowledge documents this run sees — 1 document. Unmarked ones were written or approved by the user:',
                COMMIT_FORMAT,
              ].join('\n'),
            },
          ],
        },
      ),
    );
    expect(line()).toBe('Searched knowledge · “commit” · 1 document');
  });

  it('names no count for a refused search, reads the refusal as the row’s reason, and says it is running while it is', () => {
    draw(
      pair(
        'knowledge_search',
        { query: 'release' },
        {
          text: 'KNOWLEDGE_DISABLED: the user has turned knowledge off; work without it.',
          isError: true,
        },
      ),
      { status: 'error' },
    );
    expect(line()).toBe(
      'Searched knowledge · “release” · the user has turned knowledge off; work without it.',
    );
    expect(
      container.querySelector('[data-role="knowledge-tool"] .font-medium')
        ?.className,
    ).toContain('text-destructive');
    draw(pair('knowledge_search', { query: 'release' }), { status: 'running' });
    expect(line()).toBe('Searching knowledge · “release”');
  });
});

