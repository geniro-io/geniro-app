/** A document to open: its row when the panel read one, else its handle. */
export type KnowledgeOpenTarget =
  { documentId: string } | { handle: string; runId?: string };

/**
 * Open the Knowledge page on one document; null where nothing can take the
 * reader there, which leaves the panel without its link.
 */
export const KnowledgeOpenContext = createContext<
  ((target: KnowledgeOpenTarget) => void) | null
>(null);

/** The documents the run's places file under a handle now, nearest first. */
export type KnowledgeLoader = (handle: string) => Promise<KnowledgeHead[]>;

/** How a row reads its documents when it opens; null leaves what the call said. */
export const KnowledgeLoaderContext = createContext<KnowledgeLoader | null>(
  null,
);

/**
 * TWIN PARSER: `KNOWLEDGE_PLACE_LEVELS` in
 * `apps/daemon/src/v1/knowledge/knowledge.types.ts`.
 */
const PLACE_LEVELS = ['project', 'team', 'global'] as const;
type KnowledgePlaceLevel = (typeof PLACE_LEVELS)[number];

function levelOfPlace(place: string): KnowledgePlaceLevel {
  return PLACE_LEVELS.find((level) => place.startsWith(level)) ?? 'global';
}

/** What a row's opening found of one document; `gone` is no such document now. */
type KnowledgeFresh = KnowledgeHead | 'gone';

/** One document a call named, read off its line of the result or off its arguments. */
export interface KnowledgeDocLine {
  handle: string;
  title: string | null;
  whenToRead: string | null;
  level: KnowledgePlaceLevel | null;
  /** Null where the call does not say, as a save's result does not. */
  reviewed: boolean | null;
}

type SaveOutcome = 'saved' | 'proposed' | 'stale' | 'refused';

/** What a knowledge tool call said and got back, read off its untyped payloads. */
export type KnowledgeToolEntry =
  | {
      tool: 'knowledge_search';
      query: string | null;
      count: number | null;
      documents: KnowledgeDocLine[];
      failure: string | null;
    }
  | {
      tool: 'knowledge_read';
      handle: string;
      documents: KnowledgeDocLine[];
      changed: boolean;
      failure: string | null;
    }
  | {
      tool: 'knowledge_save';
      handle: string | null;
      title: string | null;
      whenToRead: string | null;
      outcome: SaveOutcome | null;
      created: boolean;
      note: string | null;
      documents: KnowledgeDocLine[];
    };

type SaveEntry = Extract<KnowledgeToolEntry, { tool: 'knowledge_save' }>;

/** One document line: `- <handle> (rev <n>, <level>, <x.y> KB[, unreviewed]) — <title>. When: <when>`. */
const DOCUMENT_LINE =
  /^- (?<handle>\S+) \(rev \d+, (?<level>project|team|global), [\d.]+ KB(?<unreviewed>, unreviewed)?\) — (?<title>.+?)\. When: (?<when>.*)$/;
const SEARCH_TOTAL =
  /^Knowledge documents this run sees — (?:Showing \d+ of (\d+)|(\d+) documents?)\./;
const SEARCH_NONE =
  /^(?:No knowledge document this run sees matches|This run sees no knowledge documents)/;
const READ_CHANGED = /^The document `[^`]+` changed:/;
const SAVED = /^Saved `([^`]+)` at rev \d+\./;
const PROPOSED = /^Proposed (a new document|a change to) `([^`]+)`:/;
const SAVE_STALE = /^Not saved: `([^`]+)` is at rev \d+ now\./;

/** A string argument, trimmed; null when it is absent or blank. */
function textArg(args: Record<string, unknown>, key: string): string | null {
  const value = args[key];
  if (typeof value !== 'string') {
    return null;
  }
  const trimmed = value.trim();
  return trimmed === '' ? null : trimmed;
}

/** The text before its first blank line: a read's header, never its body. */
function headerOf(text: string): string {
  return text.split('\n\n', 1)[0] ?? '';
}

/**
 * The document lines a result names, in the order it names them.
 *
 * TWIN PARSER: `knowledgeHitLine` in `apps/daemon/src/v1/mcp/tools/knowledge-mcp-tool.ts`
 * writes each line this reads; reword it there too.
 */
export function knowledgeToolDocsOf(text: string | null): KnowledgeDocLine[] {
  return (text ?? '').split('\n').flatMap((line) => {
    const groups = DOCUMENT_LINE.exec(line)?.groups;
    if (groups === undefined) {
      return [];
    }
    const { handle = '', level, unreviewed, title = '', when = '' } = groups;
    return [
      {
        handle,
        title,
        whenToRead: when === '' ? null : when,
        level: PLACE_LEVELS.find((candidate) => candidate === level) ?? null,
        reviewed: unreviewed === undefined,
      },
    ];
  });
}

function searchCount(text: string, shown: number): number | null {
  if (SEARCH_NONE.test(text)) {
    return 0;
  }
  const total = SEARCH_TOTAL.exec(text);
  if (total !== null) {
    return Number(total[1] ?? total[2]);
  }
  return shown > 0 ? shown : null;
}

function searchEntry(
  args: Record<string, unknown>,
  text: string | null,
  failed: boolean,
): KnowledgeToolEntry {
  const query = textArg(args, 'query');
  if (failed) {
    return {
      tool: 'knowledge_search',
      query,
      count: null,
      documents: [],
      failure: text === null ? null : refusalReason(text),
    };
  }
  const documents = knowledgeToolDocsOf(text);
  return {
    tool: 'knowledge_search',
    query,
    count: text === null ? null : searchCount(text, documents.length),
    documents,
    failure: null,
  };
}

function readEntry(
  args: Record<string, unknown>,
  text: string | null,
  failed: boolean,
): KnowledgeToolEntry | null {
  const handle = textArg(args, 'handle');
  if (handle === null) {
    return null;
  }
  if (failed) {
    return {
      tool: 'knowledge_read',
      handle,
      documents: [],
      changed: false,
      failure: text === null ? null : refusalReason(text),
    };
  }
  const changed = text !== null && READ_CHANGED.test(text);
  return {
    tool: 'knowledge_read',
    handle,
    documents:
      text === null || changed ? [] : knowledgeToolDocsOf(headerOf(text)),
    changed,
    failure: null,
  };
}

interface SaveReading {
  outcome: SaveOutcome | null;
  named: string | null;
  created: boolean;
  note: string | null;
}

function saveReadingOf(text: string | null, failed: boolean): SaveReading {
  const none: SaveReading = {
    outcome: null,
    named: null,
    created: false,
    note: null,
  };
  if (text === null) {
    return none;
  }
  if (!failed) {
    const saved = SAVED.exec(text);
    if (saved !== null) {
      return { ...none, outcome: 'saved', named: saved[1] ?? null };
    }
    const proposed = PROPOSED.exec(text);
    if (proposed !== null) {
      return {
        ...none,
        outcome: 'proposed',
        named: proposed[2] ?? null,
        created: proposed[1] === 'a new document',
      };
    }
  }
  const stale = SAVE_STALE.exec(text);
  if (stale !== null) {
    return { ...none, outcome: 'stale', named: stale[1] ?? null };
  }
  if (failed) {
    return { ...none, outcome: 'refused', note: refusalReason(text) };
  }
  return none;
}

function saveEntry(
  args: Record<string, unknown>,
  text: string | null,
  failed: boolean,
): KnowledgeToolEntry | null {
  const argHandle = textArg(args, 'handle');
  const title = textArg(args, 'title');
  if (argHandle === null && title === null) {
    return null;
  }
  const whenToRead = textArg(args, 'whenToRead');
  const reading = saveReadingOf(text, failed);
  const handle = reading.named ?? argHandle;
  const filed = reading.outcome === 'saved' || reading.outcome === 'proposed';
  return {
    tool: 'knowledge_save',
    handle,
    title,
    whenToRead,
    outcome: reading.outcome,
    created: reading.created,
    note: reading.note,
    documents:
      filed && handle !== null
        ? [{ handle, title, whenToRead, level: null, reviewed: null }]
        : [],
  };
}

function entryOf(
  tool: GeniroKnowledgeTool,
  args: Record<string, unknown>,
  text: string | null,
  failed: boolean,
): KnowledgeToolEntry | null {
  switch (tool) {
    case 'knowledge_search':
      return searchEntry(args, text, failed);
    case 'knowledge_read':
      return readEntry(args, text, failed);
    case 'knowledge_save':
      return saveEntry(args, text, failed);
  }
}

/**
 * The knowledge row a tool pair draws, or null when the pair is not one of the
 * knowledge tools of this run's own server or its arguments cannot be read — the
 * caller then draws the ordinary tool row.
 *
 * TWIN PARSER: the result texts of `knowledgeSearchResultText`,
 * `knowledgeReadResultText` and `knowledgeSaveResultText` (each in
 * `apps/daemon/src/v1/mcp/tools/knowledge-<tool>/knowledge-<tool>.reader.ts`),
 * read through {@link knowledgeToolDocsOf}.
 */
export function knowledgeToolEntryOf(
  pair: ToolPair,
): KnowledgeToolEntry | null {
  const name = payloadString(pair.call.payload, 'name') ?? '';
  const tool = geniroKnowledgeToolOf(name, pair.call.runId);
  if (tool === null) {
    return null;
  }
  const args = recordOf(recordOf(pair.call.payload)?.input);
  if (args === null) {
    return null;
  }
  const resultPayload = recordOf(pair.result?.payload);
  return entryOf(
    tool,
    args,
    resultTextOf(resultPayload?.result),
    resultPayload?.isError === true,
  );
}

const TOOL_ICON = {
  knowledge_search: Search,
  knowledge_read: BookOpen,
  knowledge_save: FilePlus,
} as const;

function saveLabel(entry: SaveEntry, running: boolean): string {
  if (running) {
    return entry.handle === null ? 'Saving knowledge' : 'Updating knowledge';
  }
  if (entry.outcome === 'proposed' && entry.handle !== null) {
    return entry.created
      ? `Proposed ${entry.handle}`
      : `Proposed a change to ${entry.handle}`;
  }
  if (entry.outcome === 'stale' || entry.outcome === 'refused') {
    return 'Knowledge not saved';
  }
  if (entry.outcome === 'saved') {
    return entry.handle === null ? 'Saved knowledge' : `Saved ${entry.handle}`;
  }
  return 'Save knowledge';
}

function labelOf(entry: KnowledgeToolEntry, running: boolean): string {
  switch (entry.tool) {
    case 'knowledge_search':
      return running ? 'Searching knowledge' : 'Searched knowledge';
    case 'knowledge_read':
      return `${running ? 'Reading' : 'Read'} ${entry.handle}`;
    case 'knowledge_save':
      return saveLabel(entry, running);
  }
}

function SaveOutcomeTag({
  entry,
}: {
  entry: SaveEntry;
}): React.JSX.Element | null {
  const text =
    entry.outcome === 'stale'
      ? 'changed since it was read'
      : entry.outcome === 'refused'
        ? (entry.note ?? 'refused')
        : entry.outcome === 'proposed'
          ? 'waits for review'
          : null;
  if (text === null) {
    return null;
  }
  const refused = entry.outcome === 'stale' || entry.outcome === 'refused';
  return (
    <>
      <Dot />
      <span className={cn(refused ? 'text-destructive' : 'text-warning')}>
        {text}
      </span>
    </>
  );
}

function Detail({
  entry,
}: {
  entry: KnowledgeToolEntry;
}): React.JSX.Element | null {
  switch (entry.tool) {
    case 'knowledge_search':
      return (
        <>
          {entry.count === null ? null : (
            <>
              <Dot />
              <span>{plural(entry.count, 'document')}</span>
            </>
          )}
          {entry.query === null ? null : (
            <>
              {' '}
              <span className="min-w-0 truncate text-muted-foreground/70">
                “{entry.query}”
              </span>
            </>
          )}
          {entry.failure === null ? null : (
            <>
              <Dot />
              <span className="text-destructive">{entry.failure}</span>
            </>
          )}
        </>
      );
    case 'knowledge_read': {
      if (entry.failure !== null) {
        return (
          <>
            <Dot />
            <span className="text-destructive">{entry.failure}</span>
          </>
        );
      }
      if (entry.changed) {
        return (
          <>
            <Dot />
            <span className="text-warning">changed since it was read</span>
          </>
        );
      }
      const title = entry.documents[0]?.title ?? null;
      return title === null ? null : (
        <>
          <Dot />
          <span className="min-w-0 truncate text-foreground">{title}</span>
        </>
      );
    }
    case 'knowledge_save':
      return (
        <>
          {entry.title === null ? null : (
            <>
              <Dot />
              <span className="min-w-0 truncate text-foreground">
                {entry.title}
              </span>
            </>
          )}
          <SaveOutcomeTag entry={entry} />
        </>
      );
  }
}

function KnowledgePeekPanel({
  documents,
  fresh,
  close,
}: {
  documents: readonly KnowledgeDocLine[];
  fresh: ReadonlyMap<string, KnowledgeFresh>;
  close: () => void;
}): React.JSX.Element {
  const openKnowledge = useContext(KnowledgeOpenContext);
  return (
    <div
      data-slot="knowledge-peek"
      className="flex max-h-[min(24rem,60vh)] w-[min(28rem,calc(100vw-2rem))] flex-col divide-y divide-border/60 overflow-y-auto">
      {documents.map((doc) => {
        const read = fresh.get(doc.handle);
        const head = read === undefined || read === 'gone' ? null : read;
        const whenToRead = head?.whenToRead ?? doc.whenToRead;
        const level = head ? levelOfPlace(head.place) : doc.level;
        const reviewed = head ? head.approvedAt !== null : doc.reviewed;
        return (
          <div
            key={doc.handle}
            data-knowledge-doc={doc.handle}
            className="flex min-w-0 flex-col gap-1 py-1 first:pt-0 last:pb-0">
            <div className="flex min-w-0 flex-wrap items-center gap-2 px-2 pt-1">
              <span className="min-w-0 text-sm font-medium break-words">
                {head?.title ?? doc.title ?? doc.handle}
              </span>
              {level === null ? null : <Badge variant="muted">{level}</Badge>}
              {reviewed === false ? (
                <Badge variant="warning">unreviewed</Badge>
              ) : null}
              {head?.status === 'archived' ? (
                <Badge variant="muted">archived</Badge>
              ) : null}
            </div>
            <p className="m-0 px-2 text-xs text-muted-foreground">
              <span className="font-mono text-primary">{doc.handle}</span>
              {whenToRead === null ? null : (
                <>
                  {' · '}
                  {whenToRead}
                </>
              )}
            </p>
            {read === 'gone' ? (
              <p className="m-0 px-2 text-xs text-muted-foreground">
                No longer in Knowledge.
              </p>
            ) : openKnowledge === null ? null : (
              <Button
                type="button"
                variant="link"
                onClick={() => {
                  close();
                  openKnowledge(
                    head ? { documentId: head.id } : { handle: doc.handle },
                  );
                }}
                className="h-auto self-start px-2 py-0 text-xs">
                Open in Knowledge
              </Button>
            )}
          </div>
        );
      })}
    </div>
  );
}

/**
 * One knowledge tool call as a single compact line inside the transcript's tool
 * run: what was searched, read or saved. Where the call named documents, the line
 * opens a panel on hover or press with each one's title, when to read it, handle
 * and place as they stand now, and an Open in Knowledge link. No body is drawn.
 */
export function KnowledgeToolRow({
  entry,
  status,
}: {
  entry: KnowledgeToolEntry;
  status: BlockStatus;
}): React.JSX.Element {
  const running = status === 'running';
  const Icon = TOOL_ICON[entry.tool];
  const failed = status === 'error' && entry.tool !== 'knowledge_save';
  const loadKnowledge = useContext(KnowledgeLoaderContext);
  const [fresh, setFresh] = useState<ReadonlyMap<string, KnowledgeFresh>>(
    () => new Map(),
  );
  const onOpenChange = useLatestCallback(
    (open: boolean) => {
      if (!open || loadKnowledge === null) {
        return;
      }
      for (const doc of entry.documents) {
        loadKnowledge(doc.handle).then(
          (heads) =>
            setFresh((current) =>
              new Map(current).set(
                doc.handle,
                (doc.level === null
                  ? currentOf(heads)
                  : heads.find(
                      (head) => levelOfPlace(head.place) === doc.level,
                    )) ?? 'gone',
              ),
            ),
          () => undefined,
        );
      }
    },
    [entry, loadKnowledge],
  );
  const line = (
    <>
      <Icon aria-hidden="true" className="size-3.5 shrink-0" />
      <span
        className={cn('font-medium', failed ? 'text-destructive' : undefined)}>
        {labelOf(entry, running)}
      </span>{' '}
      <Detail entry={entry} />
      {running ? <Spinner /> : null}
      {status === 'stopped' ? (
        <>
          <Dot />
          <span className="text-muted-foreground/70">no result</span>
        </>
      ) : null}
    </>
  );
  const lineClass =
    'flex min-w-0 flex-wrap items-center gap-x-1.5 gap-y-0.5 py-0.5 text-xs text-muted-foreground';
  if (entry.documents.length === 0) {
    return (
      <div
        data-role="knowledge-tool"
        data-knowledge-tool={entry.tool}
        className={lineClass}>
        {line}
      </div>
    );
  }
  const handles = entry.documents.map((doc) => doc.handle).join(', ');
  return (
    <div
      data-role="knowledge-tool"
      data-knowledge-tool={entry.tool}
      className="flex">
      <HoverPopover
        slot="knowledge-tool-peek"
        trigger={line}
        label={`${labelOf(entry, running)}: ${handles}`}
        panelLabel={`Knowledge documents: ${handles}`}
        align="start"
        className="min-w-0 max-w-full"
        triggerClassName={cn(
          lineClass,
          '-mx-1 rounded-md px-1 text-left hover:bg-accent/50 hover:text-foreground',
        )}
        panelClassName="p-1.5"
        onOpenChange={onOpenChange}>
        {(close) => (
          <KnowledgePeekPanel
            documents={entry.documents}
            fresh={fresh}
            close={close}
          />
        )}
      </HoverPopover>
    </div>
  );
}
