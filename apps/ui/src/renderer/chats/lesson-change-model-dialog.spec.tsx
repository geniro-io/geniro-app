// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { LessonEstimate, LessonSegment } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { LessonChangeModelDialog } from './lesson-change-model-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

const SEGMENT = {
  id: 'seg-1',
  runId: 'run-1',
  sourceTitle: 'Refactor the parser',
  archived: true,
  fromSeq: 1,
  toSeq: 40,
  closedBy: 'archive',
  closedAt: '2026-11-13T10:00:00.000Z',
  signals: [{ kind: 'user_correction', seq: 12 }],
  status: 'offered',
  reflectionRunId: null,
  estimate: {
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    tokens: 1200,
    usd: 0.5,
  },
} as unknown as LessonSegment;

const DEFAULT_MODEL_ESTIMATE: LessonEstimate = {
  agentKind: 'claude',
  model: null,
  tokens: 1500,
  usd: null,
};

function fakeLessons() {
  return {
    estimateLessons: vi.fn(() =>
      Promise.resolve({
        estimate: DEFAULT_MODEL_ESTIMATE,
        signals: 1,
        fromSeq: 1,
        toSeq: 40,
      }),
    ),
    reflectLessons: vi.fn(() => Promise.resolve({})),
  };
}

async function render(lessons: ReturnType<typeof fakeLessons>): Promise<void> {
  await act(async () => {
    root.render(
      <LessonChangeModelDialog
        segment={SEGMENT}
        lessonsApi={lessons as unknown as DaemonApis['lessons']}
        agentsApi={null}
        capabilities={null}
        onClose={vi.fn()}
        onStarted={vi.fn()}
      />,
    );
  });
}

function buttonNamed(label: string): HTMLButtonElement {
  return [...document.querySelectorAll<HTMLButtonElement>('button')].find(
    (button) => button.textContent?.trim() === label,
  )!;
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('LessonChangeModelDialog', () => {
  it('starts with the stretch’s own agent and model, and their estimate', async () => {
    await render(fakeLessons());

    expect(document.body.textContent).toContain('claude-haiku-5-5');
    expect(document.body.textContent).toContain('≈$0.50 (≈1.2k tokens)');
  });

  it('shows the daemon’s own sentence when it refuses the start, not the error’s class', async () => {
    const lessons = fakeLessons();
    lessons.reflectLessons.mockRejectedValueOnce(
      new Error('a reflection on this thread is still working'),
    );
    await render(lessons);

    await press(buttonNamed('Extract lessons'));

    expect(document.body.textContent).toContain(
      'a reflection on this thread is still working',
    );
    expect(document.body.textContent).not.toContain('Error: ');
  });

  it('re-reads the estimate for a picked model, and starts the reflection with that choice', async () => {
    const lessons = fakeLessons();
    await render(lessons);

    await press(
      document.querySelector<HTMLElement>('[aria-label="Reflection model"]')!,
    );
    await press(
      [...document.querySelectorAll<HTMLElement>('[role="option"]')].find(
        (node) => node.textContent?.trim() === "The CLI's default model",
      )!,
    );

    expect(lessons.estimateLessons).toHaveBeenLastCalledWith({
      runId: 'run-1',
      agentKind: 'claude',
    });
    expect(document.body.textContent).toContain('≈1.5k tokens');

    await press(buttonNamed('Extract lessons'));
    expect(lessons.reflectLessons).toHaveBeenCalledWith({
      runId: 'run-1',
      reflectLessonsDto: { segmentId: 'seg-1', agentKind: 'claude' },
    });
  });
});
