import { useContext, useRef, useState } from 'react';

import { AgentIdentityContext } from '../agent-identity';
import type {
  CapabilitiesDto,
  LessonEstimate,
  LessonSegment,
} from '../autogenerated';
import { ErrorText } from '../components/error-text';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import type { DaemonApis } from '../daemon-api';
import {
  type LessonModelChoice,
  LessonModelPicker,
  lessonRunLabel,
} from './lesson-model-picker';

export function LessonChangeModelDialog({
  segment,
  lessonsApi,
  agentsApi,
  capabilities,
  onClose,
  onStarted,
}: {
  segment: LessonSegment;
  lessonsApi: DaemonApis['lessons'];
  agentsApi: DaemonApis['agents'] | null;
  capabilities: CapabilitiesDto | null;
  onClose: () => void;
  onStarted: () => void;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  const [choice, setChoice] = useState<LessonModelChoice>({
    agentKind: segment.estimate.agentKind,
    model: segment.estimate.model,
  });
  const [estimate, setEstimate] = useState<LessonEstimate>(segment.estimate);
  const [estimating, setEstimating] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const reading = useRef(0);
  const title = segment.sourceTitle?.trim() || 'Untitled thread';

  const pick = (next: LessonModelChoice): void => {
    const read = reading.current + 1;
    reading.current = read;
    setChoice(next);
    setError(null);
    setEstimating(true);
    lessonsApi
      .estimateLessons({
        runId: segment.runId,
        ...(next.agentKind === null ? {} : { agentKind: next.agentKind }),
        ...(next.model === null ? {} : { model: next.model }),
      })
      .then((answer) => {
        if (reading.current === read) {
          setEstimate(answer.estimate);
        }
      })
      .catch((err: unknown) => {
        if (reading.current === read) {
          setError(String(err));
        }
      })
      .finally(() => {
        if (reading.current === read) {
          setEstimating(false);
        }
      });
  };

  const start = (): void => {
    setBusy(true);
    setError(null);
    lessonsApi
      .reflectLessons({
        runId: segment.runId,
        reflectLessonsDto: {
          segmentId: segment.id,
          ...(choice.agentKind === null ? {} : { agentKind: choice.agentKind }),
          ...(choice.model === null ? {} : { model: choice.model }),
        },
      })
      .then(() => onStarted())
      .catch((err: unknown) => {
        setError(String(err));
        setBusy(false);
      });
  };

  return (
    <Dialog
      open
      onClose={busy ? () => undefined : onClose}
      title="Change model">
      <div className="flex flex-col gap-4">
        <p className="text-sm text-muted-foreground">
          Reflect on “{title}” with the agent and model picked here.
        </p>
        <div className="flex flex-wrap items-center gap-1">
          <LessonModelPicker
            value={choice}
            onChange={pick}
            agentsApi={agentsApi}
            capabilities={capabilities}
            disabled={busy}
          />
        </div>
        <p className="text-sm">
          {estimating ? 'Estimating…' : lessonRunLabel(identities, estimate)}
        </p>
        {error === null ? null : <ErrorText>{error}</ErrorText>}
        <div className="flex justify-end gap-2">
          <Button
            type="button"
            variant="outline"
            disabled={busy}
            onClick={onClose}>
            Cancel
          </Button>
          <Button type="button" disabled={busy || estimating} onClick={start}>
            Extract lessons
          </Button>
        </div>
      </div>
    </Dialog>
  );
}
