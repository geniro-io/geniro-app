import { describe, expect, it } from 'vitest';

import type { LessonEstimate } from '../autogenerated';
import {
  lessonPriceLabel,
  lessonTypicalLabel,
  segmentTitle,
} from './lesson-labels';

function estimate(patch: Partial<LessonEstimate> = {}): LessonEstimate {
  return {
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    tokens: 1200,
    usd: 0.5,
    ...patch,
  };
}

describe('lessonPriceLabel', () => {
  it('reads the price in dollars, approximately', () => {
    expect(lessonPriceLabel(estimate({ usd: 0.02 }))).toBe('≈$0.02');
  });

  it('keeps the < guard for a sub-cent price and never prefixes it with ≈', () => {
    const label = lessonPriceLabel(estimate({ usd: 0.0034 }));

    expect(label).toBe('<$0.01');
    expect(label).not.toContain('≈<');
  });

  it('shows tokens alone for a model with no list price, never $0', () => {
    const label = lessonPriceLabel(estimate({ usd: null, tokens: 4200 }));

    expect(label).toBe('≈4.2k tokens');
    expect(label).not.toContain('$');
  });
});

describe('lessonTypicalLabel', () => {
  const typical = {
    runs: 7,
    usd: 0.28,
    durationMs: 34_000,
    model: 'claude-sonnet-5-5',
    sameModel: true,
  };

  it('reads the median spend and time and the runs it is taken over, on the model named', () => {
    expect(lessonTypicalLabel(typical, 'Sonnet 5.5')).toBe(
      'Usually ~$0.28 and ~34s — median of the last 7 runs on Sonnet 5.5',
    );
  });

  it('names no model when runs on every model were counted', () => {
    expect(
      lessonTypicalLabel({ ...typical, sameModel: false, model: null }, null),
    ).toBe('Usually ~$0.28 and ~34s — median of the last 7 runs');
  });

  it('never shows $0 for a cost no run reported', () => {
    const label = lessonTypicalLabel({ ...typical, usd: null }, 'Sonnet 5.5');

    expect(label).toBe(
      'Usually ~34s — median of the last 7 runs on Sonnet 5.5; cost not reported',
    );
    expect(label).not.toContain('$');
  });

  it('says one run in the singular, and that no run reported either figure when none did', () => {
    expect(lessonTypicalLabel({ ...typical, runs: 1 }, 'Sonnet 5.5')).toBe(
      'Usually ~$0.28 and ~34s — median of the last run on Sonnet 5.5',
    );
    expect(
      lessonTypicalLabel({ ...typical, usd: null, durationMs: null }, null),
    ).toBe('Cost not reported by the last 7 runs');
  });

  it('says the cost is not measured before any run finished', () => {
    expect(lessonTypicalLabel(null, 'Sonnet 5.5')).toBe(
      'Cost not measured yet — no extraction has finished so far',
    );
  });
});

describe('segmentTitle', () => {
  it('reads the trimmed title of the thread', () => {
    expect(segmentTitle({ sourceTitle: '  My chat ' })).toBe('My chat');
  });

  it('names an untitled thread for a missing or blank title', () => {
    expect(segmentTitle({ sourceTitle: null })).toBe('Untitled thread');
    expect(segmentTitle({ sourceTitle: '' })).toBe('Untitled thread');
    expect(segmentTitle({ sourceTitle: '   ' })).toBe('Untitled thread');
  });
});
