import { describe, expect, it } from 'vitest';

import { PUBLISHED_IDENTITIES } from '../__tests__/agent-identities';
import type { LessonEstimate } from '../autogenerated';
import {
  choiceToDto,
  lessonPriceLabel,
  lessonRunLabel,
  segmentTitle,
} from './lesson-labels';

function estimate(patch: Partial<LessonEstimate> = {}): LessonEstimate {
  return {
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    tokens: 1200,
    usd: 0.5,
    ...patch,
  };
}

describe('lessonPriceLabel', () => {
  it('reads the price and the tokens, the tokens in thousands', () => {
    expect(lessonPriceLabel(estimate({ usd: 0.02, tokens: 4200 }))).toBe(
      '≈$0.02 (≈4.2k tokens)',
    );
  });

  it('keeps the < guard for a sub-cent price and never prefixes it with ≈', () => {
    const label = lessonPriceLabel(estimate({ usd: 0.0034, tokens: 900 }));

    expect(label).toBe('<$0.01 (≈900 tokens)');
    expect(label).not.toContain('≈<');
  });

  it('shows tokens alone for a model with no list price, never $0', () => {
    const label = lessonPriceLabel(estimate({ usd: null, tokens: 4200 }));

    expect(label).toBe('≈4.2k tokens');
    expect(label).not.toContain('$');
  });
});

describe('lessonRunLabel', () => {
  it('names the agent, the model and the price', () => {
    expect(lessonRunLabel(PUBLISHED_IDENTITIES, estimate())).toBe(
      'Claude · claude-haiku-5-5 · ≈$0.50 (≈1.2k tokens)',
    );
  });

  it('says the default model when the estimate names none', () => {
    expect(
      lessonRunLabel(PUBLISHED_IDENTITIES, estimate({ model: null })),
    ).toBe('Claude · default model · ≈$0.50 (≈1.2k tokens)');
  });
});

describe('segmentTitle', () => {
  it('reads the trimmed title of the thread', () => {
    expect(segmentTitle({ sourceTitle: '  My chat ' })).toBe('My chat');
  });

  it('names an untitled thread for a missing or blank title', () => {
    expect(segmentTitle({ sourceTitle: null })).toBe('Untitled thread');
    expect(segmentTitle({ sourceTitle: '' })).toBe('Untitled thread');
    expect(segmentTitle({ sourceTitle: '   ' })).toBe('Untitled thread');
  });
});

describe('choiceToDto', () => {
  it('sends neither field for the thread’s own CLI and its default model', () => {
    expect(choiceToDto({ agentKind: null, model: null })).toStrictEqual({});
  });

  it('sends only the agent when no model is picked', () => {
    expect(choiceToDto({ agentKind: 'codex', model: null })).toStrictEqual({
      agentKind: 'codex',
    });
  });

  it('sends the agent and the model when both are picked', () => {
    expect(choiceToDto({ agentKind: 'claude', model: 'opus' })).toStrictEqual({
      agentKind: 'claude',
      model: 'opus',
    });
  });
});
