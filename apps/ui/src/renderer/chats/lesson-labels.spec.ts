import { describe, expect, it } from 'vitest';

import type { LessonEstimate } from '../autogenerated';
import {
  lessonCostLabel,
  lessonPriceLabel,
  segmentTitle,
} from './lesson-labels';

function estimate(patch: Partial<LessonEstimate> = {}): LessonEstimate {
  return {
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    tokens: 1200,
    usd: 0.5,
    ...patch,
  };
}

describe('lessonPriceLabel', () => {
  it('reads the price in dollars, approximately', () => {
    expect(lessonPriceLabel(estimate({ usd: 0.02 }))).toBe('≈$0.02');
  });

  it('keeps the < guard for a sub-cent price and never prefixes it with ≈', () => {
    const label = lessonPriceLabel(estimate({ usd: 0.0034 }));

    expect(label).toBe('<$0.01');
    expect(label).not.toContain('≈<');
  });

  it('shows tokens alone for a model with no list price, never $0', () => {
    const label = lessonPriceLabel(estimate({ usd: null, tokens: 4200 }));

    expect(label).toBe('≈4.2k tokens');
    expect(label).not.toContain('$');
  });
});

describe('lessonCostLabel', () => {
  it('names the model by the name it is given, then the price', () => {
    expect(lessonCostLabel(estimate(), null, 'Haiku 5.5')).toBe(
      'Haiku 5.5 · ≈$0.50',
    );
  });

  it('says the default model when no model is named', () => {
    expect(lessonCostLabel(estimate({ model: null }), null, null)).toBe(
      'default model · ≈$0.50',
    );
  });

  it('adds the check’s price, marked as only if a lesson is found', () => {
    expect(
      lessonCostLabel(
        estimate(),
        estimate({ model: 'opus', usd: 0.27 }),
        'Haiku 5.5',
      ),
    ).toBe('Haiku 5.5 · ≈$0.50 · check ≈$0.27 if a lesson is found');
  });
});

describe('segmentTitle', () => {
  it('reads the trimmed title of the thread', () => {
    expect(segmentTitle({ sourceTitle: '  My chat ' })).toBe('My chat');
  });

  it('names an untitled thread for a missing or blank title', () => {
    expect(segmentTitle({ sourceTitle: null })).toBe('Untitled thread');
    expect(segmentTitle({ sourceTitle: '' })).toBe('Untitled thread');
    expect(segmentTitle({ sourceTitle: '   ' })).toBe('Untitled thread');
  });
});
