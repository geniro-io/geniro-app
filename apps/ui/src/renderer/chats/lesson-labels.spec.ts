import { describe, expect, it } from 'vitest';

import type { LessonEstimate } from '../autogenerated';
import {
  lessonExtractionTitle,
  lessonPriceLabel,
  lessonTypicalDetail,
  lessonTypicalLabel,
  segmentTitle,
} from './lesson-labels';

function estimate(patch: Partial<LessonEstimate> = {}): LessonEstimate {
  return {
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    tokens: 1200,
    usd: 0.5,
    ...patch,
  };
}

describe('lessonPriceLabel', () => {
  it('reads the price in dollars, approximately', () => {
    expect(lessonPriceLabel(estimate({ usd: 0.02 }))).toBe('≈$0.02');
  });

  it('keeps the < guard for a sub-cent price and never prefixes it with ≈', () => {
    const label = lessonPriceLabel(estimate({ usd: 0.0034 }));

    expect(label).toBe('<$0.01');
    expect(label).not.toContain('≈<');
  });

  it('shows tokens alone for a model with no list price, never $0', () => {
    const label = lessonPriceLabel(estimate({ usd: null, tokens: 4200 }));

    expect(label).toBe('≈4.2k tokens');
    expect(label).not.toContain('$');
  });
});

const TYPICAL = {
  runs: 7,
  usd: 0.28,
  durationMs: 34_000,
  model: 'claude-sonnet-5-5',
  sameModel: true,
};

describe('lessonTypicalLabel', () => {
  it('reads the median spend and time on one short line, on the model named', () => {
    expect(lessonTypicalLabel(TYPICAL, 'Sonnet 5.5')).toBe(
      'Usually ~$0.28 and ~34s on Sonnet 5.5',
    );
  });

  it('names no model when runs on every model were counted', () => {
    expect(
      lessonTypicalLabel(
        { ...TYPICAL, sameModel: false, model: null },
        'Sonnet 5.5',
      ),
    ).toBe('Usually ~$0.28 and ~34s');
  });

  it('never shows $0 for a cost no run reported', () => {
    const label = lessonTypicalLabel({ ...TYPICAL, usd: null }, 'Sonnet 5.5');

    expect(label).toBe('Usually ~34s on Sonnet 5.5; cost not reported');
    expect(label).not.toContain('$');
  });

  it('says no run reported either figure when none did', () => {
    expect(
      lessonTypicalLabel({ ...TYPICAL, usd: null, durationMs: null }, null),
    ).toBe('Cost not reported by the last 7 runs');
  });

  it('says the cost is not measured before any run finished', () => {
    expect(lessonTypicalLabel(null, 'Sonnet 5.5')).toBe(
      'Cost not measured yet',
    );
  });
});

describe('lessonTypicalDetail', () => {
  it('names the runs the figures are the median of, on the model named', () => {
    expect(lessonTypicalDetail(TYPICAL, 'Sonnet 5.5')).toBe(
      'Usually ~$0.28 and ~34s — median of the last 7 runs on Sonnet 5.5',
    );
  });

  it('names no model when runs on every model were counted', () => {
    expect(
      lessonTypicalDetail({ ...TYPICAL, sameModel: false, model: null }, null),
    ).toBe('Usually ~$0.28 and ~34s — median of the last 7 runs');
  });

  it('says one run in the singular, and keeps the cost note', () => {
    expect(lessonTypicalDetail({ ...TYPICAL, runs: 1 }, 'Sonnet 5.5')).toBe(
      'Usually ~$0.28 and ~34s — median of the last run on Sonnet 5.5',
    );
    expect(lessonTypicalDetail({ ...TYPICAL, usd: null }, 'Sonnet 5.5')).toBe(
      'Usually ~34s — median of the last 7 runs on Sonnet 5.5; cost not reported',
    );
  });

  it('says no run reported either figure when none did', () => {
    expect(
      lessonTypicalDetail({ ...TYPICAL, usd: null, durationMs: null }, null),
    ).toBe('Cost not reported by the last 7 runs');
  });

  it('says why nothing is measured before any run finished', () => {
    expect(lessonTypicalDetail(null, 'Sonnet 5.5')).toBe(
      'Cost not measured yet — no extraction has finished so far',
    );
  });
});

describe('lessonExtractionTitle', () => {
  it('says what extracting does, what it typically costs and where progress shows', () => {
    expect(
      lessonExtractionTitle({ check: null, typical: TYPICAL }, 'Sonnet 5.5'),
    ).toBe(
      'After archiving, a background agent (Sonnet 5.5) reads the thread and saves up to 3 lessons to memory for future agents. Progress shows in the top bar. Usually ~$0.28 and ~34s — median of the last 7 runs on Sonnet 5.5.',
    );
  });

  it('says a second model checks each lesson only when the daemon will check', () => {
    expect(
      lessonExtractionTitle(
        {
          check: {
            agentKind: 'claude',
            model: 'claude-opus-5-5',
            tokens: 9000,
            usd: 0.27,
          },
          typical: null,
        },
        null,
      ),
    ).toBe(
      'After archiving, a background agent (the default model) reads the thread and saves up to 3 lessons to memory for future agents. A second model checks each lesson it finds. Progress shows in the top bar. Cost not measured yet — no extraction has finished so far.',
    );
  });
});

describe('segmentTitle', () => {
  it('reads the trimmed title of the thread', () => {
    expect(segmentTitle({ sourceTitle: '  My chat ' })).toBe('My chat');
  });

  it('names an untitled thread for a missing or blank title', () => {
    expect(segmentTitle({ sourceTitle: null })).toBe('Untitled thread');
    expect(segmentTitle({ sourceTitle: '' })).toBe('Untitled thread');
    expect(segmentTitle({ sourceTitle: '   ' })).toBe('Untitled thread');
  });
});
