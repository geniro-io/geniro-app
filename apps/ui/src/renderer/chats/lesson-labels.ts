import type {
  LessonEstimate,
  LessonSegment,
  LessonTypicalSpend,
  ThreadLessonEstimateDto,
} from '../autogenerated';
import { formatDuration } from '../stats/stats-format';
import { formatTokens, formatUsd } from './agent-activity';

/** A lesson run's price: a model with no list price shows its tokens alone, never $0. */
export function lessonPriceLabel(estimate: LessonEstimate): string {
  if (estimate.usd === null) {
    return `≈${formatTokens(estimate.tokens)} tokens`;
  }
  const usd = formatUsd(estimate.usd);
  return usd.startsWith('<') ? usd : `≈${usd}`;
}

const NOT_MEASURED = 'Cost not measured yet';

/**
 * What finished lessons runs typically cost and took, as one short line for
 * the archive dialog: "Usually ~$0.28 and ~34s on Sonnet 5.5". A figure no run
 * reported is left out, never shown as $0.
 */
export function lessonTypicalLabel(
  typical: LessonTypicalSpend | null,
  modelName: string | null,
): string {
  return typicalSentence(typical, modelName, (model) =>
    model === null ? '' : ` on ${model}`,
  );
}

/**
 * The same figures with the runs they are the median of: "Usually ~$0.28 and
 * ~34s — median of the last 7 runs on Sonnet 5.5".
 */
export function lessonTypicalDetail(
  typical: LessonTypicalSpend | null,
  modelName: string | null,
): string {
  if (typical === null) {
    return `${NOT_MEASURED} — no extraction has finished so far`;
  }
  const runs = runsLabel(typical);
  return typicalSentence(typical, modelName, (model) =>
    model === null
      ? ` — median of ${runs}`
      : ` — median of ${runs} on ${model}`,
  );
}

/** Everything the archive dialog's lessons box does, for its tooltip. */
export function lessonExtractionTitle(
  lessons: Pick<ThreadLessonEstimateDto, 'check' | 'typical'>,
  modelName: string | null,
): string {
  return [
    `After archiving, a background agent (${modelName ?? 'the default model'}) reads the thread and saves up to 3 lessons to memory for future agents.`,
    lessons.check === null
      ? null
      : 'A second model checks each lesson it finds.',
    'Progress shows in the top bar.',
    `${lessonTypicalDetail(lessons.typical, modelName)}.`,
  ]
    .filter((sentence): sentence is string => sentence !== null)
    .join(' ');
}

function runsLabel(typical: LessonTypicalSpend): string {
  return `the last ${typical.runs === 1 ? 'run' : `${typical.runs} runs`}`;
}

function typicalSentence(
  typical: LessonTypicalSpend | null,
  modelName: string | null,
  tail: (model: string | null) => string,
): string {
  if (typical === null) {
    return NOT_MEASURED;
  }
  const figures = [
    typical.usd === null ? null : `~${formatUsd(typical.usd)}`,
    typical.durationMs === null
      ? null
      : `~${formatDuration(typical.durationMs)}`,
  ].filter((figure): figure is string => figure !== null);
  if (figures.length === 0) {
    return `Cost not reported by ${runsLabel(typical)}`;
  }
  const model = typical.sameModel ? modelName : null;
  const said = `Usually ${figures.join(' and ')}${tail(model)}`;
  return typical.usd === null ? `${said}; cost not reported` : said;
}

export function segmentTitle(
  segment: Pick<LessonSegment, 'sourceTitle'>,
): string {
  return segment.sourceTitle?.trim() || 'Untitled thread';
}
