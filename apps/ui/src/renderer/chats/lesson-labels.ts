import type { LessonEstimate, LessonSegment } from '../autogenerated';
import { formatTokens, formatUsd } from './agent-activity';

/** A lesson run's price: a model with no list price shows its tokens alone, never $0. */
export function lessonPriceLabel(estimate: LessonEstimate): string {
  if (estimate.usd === null) {
    return `≈${formatTokens(estimate.tokens)} tokens`;
  }
  const usd = formatUsd(estimate.usd);
  return usd.startsWith('<') ? usd : `≈${usd}`;
}

/** "Haiku 5.5 · ≈$0.02", with " · check … if a lesson is found" when a check runs. */
export function lessonCostLabel(
  estimate: LessonEstimate,
  check: LessonEstimate | null,
  modelName: string | null,
): string {
  const parts = [modelName ?? 'default model', lessonPriceLabel(estimate)];
  if (check !== null) {
    parts.push(`check ${lessonPriceLabel(check)} if a lesson is found`);
  }
  return parts.join(' · ');
}

export function segmentTitle(
  segment: Pick<LessonSegment, 'sourceTitle'>,
): string {
  return segment.sourceTitle?.trim() || 'Untitled thread';
}
