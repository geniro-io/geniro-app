import { agentShortName } from '../agent-identity';
import type {
  AgentIdentityCapability,
  LessonEstimate,
  LessonSegment,
  ReflectLessonsDto,
} from '../autogenerated';
import { formatTokens, formatUsd } from './agent-activity';
import type { LessonModelChoice } from './lesson-model-picker';

export function lessonPriceLabel(estimate: LessonEstimate): string {
  const tokens = `${formatTokens(estimate.tokens)} tokens`;
  if (estimate.usd === null) {
    return `≈${tokens}`;
  }
  const usd = formatUsd(estimate.usd);
  const approx = usd.startsWith('<') ? usd : `≈${usd}`;
  return `${approx} (≈${tokens})`;
}

export function lessonRunLabel(
  identities: readonly AgentIdentityCapability[],
  estimate: LessonEstimate,
): string {
  return `${agentShortName(identities, estimate.agentKind)} · ${estimate.model ?? 'default model'} · ${lessonPriceLabel(estimate)}`;
}

export function segmentTitle(
  segment: Pick<LessonSegment, 'sourceTitle'>,
): string {
  return segment.sourceTitle?.trim() || 'Untitled thread';
}

export function choiceToDto(
  choice: LessonModelChoice,
): Pick<ReflectLessonsDto, 'agentKind' | 'model'> {
  return {
    ...(choice.agentKind === null ? {} : { agentKind: choice.agentKind }),
    ...(choice.model === null ? {} : { model: choice.model }),
  };
}
