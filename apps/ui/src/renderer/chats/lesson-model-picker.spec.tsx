// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { CapabilitiesDto } from '../autogenerated';
import {
  type LessonModelChoice,
  LessonModelPicker,
} from './lesson-model-picker';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

const CAPABILITIES = {
  agents: [
    { agent: 'claude', displayName: 'Claude Code', shortName: 'Claude' },
    { agent: 'codex', displayName: 'Codex', shortName: 'Codex' },
  ],
} as unknown as CapabilitiesDto;

async function render(
  value: LessonModelChoice,
  onChange: (next: LessonModelChoice) => void,
): Promise<void> {
  await act(async () => {
    root.render(
      <LessonModelPicker
        value={value}
        onChange={onChange}
        agentsApi={null}
        capabilities={CAPABILITIES}
      />,
    );
  });
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
}

function selectOf(label: string): HTMLButtonElement | null {
  return container.querySelector<HTMLButtonElement>(`[aria-label="${label}"]`);
}

function option(label: string): HTMLElement {
  return [...document.querySelectorAll<HTMLElement>('[role="option"]')].find(
    (node) => node.textContent?.trim() === label,
  )!;
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('LessonModelPicker', () => {
  it('offers the thread’s own CLI first, then every agent the daemon reports', async () => {
    await render({ agentKind: null, model: null }, vi.fn());

    await press(selectOf('Reflection agent')!);

    expect(
      [...document.querySelectorAll<HTMLElement>('[role="option"]')].map(
        (node) => node.textContent?.trim(),
      ),
    ).toEqual(['Same CLI as the thread', 'claude', 'codex']);
  });

  it('shows no model select while the thread’s own CLI is picked', async () => {
    await render({ agentKind: null, model: null }, vi.fn());

    expect(selectOf('Reflection agent')!.textContent).toContain(
      'Same CLI as the thread',
    );
    expect(selectOf('Reflection model')).toBeNull();
  });

  it('a new agent pick reports that agent and clears the model of the last one', async () => {
    const onChange = vi.fn();
    await render({ agentKind: 'claude', model: 'opus' }, onChange);

    await press(selectOf('Reflection agent')!);
    await press(option('codex'));

    expect(onChange).toHaveBeenCalledWith({ agentKind: 'codex', model: null });
  });

  it('picking the thread’s own CLI reports no agent', async () => {
    const onChange = vi.fn();
    await render({ agentKind: 'codex', model: null }, onChange);

    await press(selectOf('Reflection agent')!);
    await press(option('Same CLI as the thread'));

    expect(onChange).toHaveBeenCalledWith({ agentKind: null, model: null });
  });

  it('picking the CLI’s default model reports no model, keeping the agent', async () => {
    const onChange = vi.fn();
    await render({ agentKind: 'claude', model: 'opus' }, onChange);

    await press(selectOf('Reflection model')!);
    await press(option("The CLI's default model"));

    expect(onChange).toHaveBeenCalledWith({ agentKind: 'claude', model: null });
  });
});
