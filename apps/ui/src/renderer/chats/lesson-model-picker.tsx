import { useContext } from 'react';

import { AgentIdentityContext, agentShortName } from '../agent-identity';
import type {
  AgentKind,
  CapabilitiesDto,
  LessonEstimate,
} from '../autogenerated';
import { Select } from '../components/ui/select';
import type { DaemonApis } from '../daemon-api';
import { formatUsd } from './agent-activity';
import { useAgentModels } from './use-agent-models';

export const THREAD_CLI_VALUE = '__thread__';
export const CLI_DEFAULT_VALUE = '__default__';

export interface LessonModelChoice {
  agentKind: AgentKind | null;
  model: string | null;
}

export function lessonPriceLabel(estimate: LessonEstimate): string {
  if (estimate.usd === null) {
    return `≈${estimate.tokens} tokens`;
  }
  const usd = formatUsd(estimate.usd);
  const approx = usd.startsWith('<') ? usd : `≈${usd}`;
  return `${approx} (≈${estimate.tokens} tokens)`;
}

export function lessonRunLabel(
  identities: Parameters<typeof agentShortName>[0],
  estimate: LessonEstimate,
): string {
  return `${agentShortName(identities, estimate.agentKind)} · ${estimate.model ?? 'default model'} · ${lessonPriceLabel(estimate)}`;
}

export function LessonModelPicker({
  value,
  onChange,
  agentsApi,
  capabilities,
  disabled = false,
  idPrefix,
}: {
  value: LessonModelChoice;
  onChange: (next: LessonModelChoice) => void;
  agentsApi: DaemonApis['agents'] | null;
  capabilities: CapabilitiesDto | null;
  disabled?: boolean;
  idPrefix?: string;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  const models = useAgentModels(agentsApi, value.agentKind, null, value.model);
  const agents = capabilities?.agents ?? [];

  return (
    <>
      <Select
        id={idPrefix === undefined ? undefined : `${idPrefix}-agent`}
        aria-label="Reflection agent"
        className="w-48"
        value={value.agentKind ?? THREAD_CLI_VALUE}
        disabled={disabled}
        groups={[
          {
            items: [
              { value: THREAD_CLI_VALUE, label: 'Same CLI as the thread' },
              ...agents.map((agent) => ({
                value: agent.agent,
                label: agentShortName(identities, agent.agent),
              })),
            ],
          },
        ]}
        onValueChange={(next) =>
          onChange({
            agentKind:
              agents.find((agent) => agent.agent === next)?.agent ?? null,
            model: null,
          })
        }
      />
      {value.agentKind === null ? null : (
        <Select
          id={idPrefix === undefined ? undefined : `${idPrefix}-model`}
          aria-label="Reflection model"
          className="w-48"
          value={value.model ?? CLI_DEFAULT_VALUE}
          disabled={disabled || models.loading}
          groups={[
            {
              items: [
                { value: CLI_DEFAULT_VALUE, label: "The CLI's default model" },
                ...models.models.map((model) => ({
                  value: model.id,
                  label: model.label,
                })),
              ],
            },
          ]}
          onValueChange={(next) =>
            onChange({
              agentKind: value.agentKind,
              model: next === CLI_DEFAULT_VALUE ? null : next,
            })
          }
        />
      )}
    </>
  );
}
