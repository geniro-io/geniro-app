// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { LessonSegment } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { LessonOfferRow } from './lesson-offer-row';
import { LessonsApiContext } from './lessons-api-context';
import {
  type LessonModelPickerRender as LessonModelPicker,
  LessonsClientContext,
} from './lessons-client-context';
import type { LessonOfferView } from './lessons-payload';
import type { LessonOfferEntry } from './transcript-groups';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

const OFFER: LessonOfferView = {
  segmentId: 'seg-1',
  fromSeq: 4,
  toSeq: 40,
  closedBy: 'idle',
  signals: [{ kind: 'user_correction', seq: 31 }],
  estimate: {
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    tokens: 4200,
    usd: 0.02,
  },
};

const ENTRY: LessonOfferEntry = {
  type: 'lesson-offer',
  id: 'i-70',
  createdAt: '2026-11-12T10:00:00.000Z',
  seq: 70,
  memberId: null,
  parentToolUseId: null,
  runId: 'run-1',
  offer: OFFER,
  latest: true,
};

function segment(
  status: LessonSegment['status'],
  overrides: Partial<LessonSegment> = {},
): LessonSegment {
  return {
    id: 'seg-1',
    runId: 'run-1',
    sourceTitle: 'Synthetic thread',
    archived: false,
    fromSeq: 4,
    toSeq: 40,
    closedBy: 'idle',
    closedAt: '2026-11-12T10:00:00.000Z',
    signals: [{ kind: 'user_correction', seq: 31 }],
    status,
    reflectionRunId: status === 'reflected' ? 'refl-1' : null,
    estimate: OFFER.estimate,
    ...overrides,
  };
}

function lessonsApi(
  overrides: Partial<Record<keyof DaemonApis['lessons'], unknown>> = {},
): DaemonApis['lessons'] {
  return {
    listLessonSegments: vi.fn(async () => ({
      segments: [segment('offered')],
    })),
    reflectLessons: vi.fn(async () => ({})),
    dismissLessonSegment: vi.fn(async () => ({})),
    estimateLessons: vi.fn(async () => ({
      estimate: OFFER.estimate,
      signals: 1,
      fromSeq: 4,
      toSeq: 40,
    })),
    ...overrides,
  } as unknown as DaemonApis['lessons'];
}

async function render(
  api: DaemonApis['lessons'] | null,
  options: {
    entry?: LessonOfferEntry;
    client?: DaemonClient | null;
    renderModelPicker?: LessonModelPicker;
  } = {},
): Promise<HTMLDivElement> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(
      <LessonsApiContext.Provider value={api}>
        <LessonsClientContext.Provider value={options.client ?? null}>
          <LessonOfferRow
            entry={options.entry ?? ENTRY}
            renderModelPicker={options.renderModelPicker}
          />
        </LessonsClientContext.Provider>
      </LessonsApiContext.Provider>,
    );
  });
  return container;
}

function buttonNamed(el: HTMLElement, name: string): HTMLButtonElement {
  const found = [...el.querySelectorAll('button')].find(
    (button) => button.textContent?.trim() === name,
  );
  if (!found) {
    throw new Error(`no button named ${name}`);
  }
  return found;
}

function buttonNames(el: HTMLElement): string[] {
  return [...el.querySelectorAll('button')].map((button) =>
    (button.textContent ?? '').trim(),
  );
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
}

describe('LessonOfferRow', () => {
  it('asks the question with the stretch, the model and the price', async () => {
    const el = await render(lessonsApi());

    expect(el.textContent).toContain(
      '1 learning signal here was never reflected on',
    );
    expect(el.textContent).toContain('Extract lessons from messages 5–40?');
    expect(el.textContent).toContain('claude-haiku-5-5');
    expect(el.textContent).toContain('$0.02');
    expect(el.textContent).toContain('4.2k tokens');
  });

  it('counts plural signals in the plural', async () => {
    const el = await render(lessonsApi(), {
      entry: {
        ...ENTRY,
        offer: {
          ...OFFER,
          signals: [
            { kind: 'user_correction', seq: 31 },
            { kind: 'user_correction', seq: 33 },
          ],
        },
      },
    });

    expect(el.textContent).toContain(
      '2 learning signals here were never reflected on',
    );
  });

  it('shows tokens alone for a model with no list price, never $0', async () => {
    const el = await render(
      lessonsApi({
        listLessonSegments: vi.fn(async () => ({
          segments: [
            segment('offered', {
              estimate: { ...OFFER.estimate, model: null, usd: null },
            }),
          ],
        })),
      }),
    );

    expect(el.textContent).toContain('≈4.2k tokens');
    expect(el.textContent).toContain('default model');
    expect(el.textContent).not.toContain('$0');
  });

  it('extracts lessons from the stretch on the default model', async () => {
    const api = lessonsApi();
    const el = await render(api);

    await press(buttonNamed(el, 'Extract lessons'));

    expect(api.reflectLessons).toHaveBeenCalledWith({
      runId: 'run-1',
      reflectLessonsDto: { segmentId: 'seg-1' },
    });
  });

  it('puts the stretch aside with Not now', async () => {
    const api = lessonsApi();
    const el = await render(api);

    await press(buttonNamed(el, 'Not now'));

    expect(api.dismissLessonSegment).toHaveBeenCalledWith({
      segmentId: 'seg-1',
    });
  });

  it('holds its buttons until the state moves, then draws the new state', async () => {
    let finish!: () => void;
    const api = lessonsApi({
      reflectLessons: vi.fn(
        () => new Promise<object>((resolve) => (finish = () => resolve({}))),
      ),
      listLessonSegments: vi
        .fn()
        .mockResolvedValueOnce({ segments: [segment('offered')] })
        .mockResolvedValue({ segments: [segment('reflecting')] }),
    });
    const el = await render(api);

    await press(buttonNamed(el, 'Extract lessons'));

    expect(buttonNamed(el, 'Extracting…').disabled).toBe(true);
    expect(buttonNamed(el, 'Not now').disabled).toBe(true);

    await act(async () => {
      finish();
    });

    expect(el.textContent).toContain('Reflecting…');
    expect(buttonNames(el)).toEqual([]);
  });

  it('shows the daemon message and enables the buttons again when a press is refused', async () => {
    const api = lessonsApi({
      reflectLessons: vi.fn(() =>
        Promise.reject(new Error('LESSONS_REFLECTING')),
      ),
    });
    const el = await render(api);

    await press(buttonNamed(el, 'Extract lessons'));

    expect(el.textContent).toContain('LESSONS_REFLECTING');
    expect(buttonNamed(el, 'Extract lessons').disabled).toBe(false);
    expect(buttonNamed(el, 'Not now').disabled).toBe(false);
  });

  it('says where a put-aside stretch waits and still offers Extract', async () => {
    const el = await render(
      lessonsApi({
        listLessonSegments: vi.fn(async () => ({
          segments: [segment('dismissed')],
        })),
      }),
    );

    expect(el.textContent).toContain(
      'Not now — waiting in Settings → Memory → Not reflected yet',
    );
    expect(buttonNames(el)).toEqual(['Extract lessons']);
  });

  it('says a failed reflection failed and still offers Extract', async () => {
    const el = await render(
      lessonsApi({
        listLessonSegments: vi.fn(async () => ({
          segments: [segment('failed')],
        })),
      }),
    );

    expect(el.textContent).toContain('Reflection failed');
    expect(buttonNames(el)).toEqual(['Extract lessons']);
  });

  it('shows a running reflection with no buttons', async () => {
    const el = await render(
      lessonsApi({
        listLessonSegments: vi.fn(async () => ({
          segments: [segment('reflecting')],
        })),
      }),
    );

    expect(el.textContent).toContain('Reflecting…');
    expect(buttonNames(el)).toEqual([]);
  });

  it('collapses a reflected stretch to a pointer at its lessons', async () => {
    const el = await render(
      lessonsApi({
        listLessonSegments: vi.fn(async () => ({
          segments: [segment('reflected')],
        })),
      }),
    );

    expect(el.textContent).toBe('Lessons extracted ↓');
    expect(buttonNames(el)).toEqual([]);
  });

  it('draws a stretch the list does not hold as offered', async () => {
    const el = await render(
      lessonsApi({
        listLessonSegments: vi.fn(async () => ({ segments: [] })),
      }),
    );

    expect(buttonNames(el)).toEqual(['Extract lessons', 'Not now']);
  });

  it('reads an offer re-offered later as updated below, and acts on nothing', async () => {
    const api = lessonsApi();
    const el = await render(api, { entry: { ...ENTRY, latest: false } });

    expect(el.textContent).toBe('Offer updated below');
    expect(buttonNames(el)).toEqual([]);
    expect(api.listLessonSegments).not.toHaveBeenCalled();
  });

  it('disables every action without a lessons API', async () => {
    const el = await render(null);

    expect(buttonNamed(el, 'Extract lessons').disabled).toBe(true);
    expect(buttonNamed(el, 'Not now').disabled).toBe(true);
  });

  it('draws no model choice without a picker to draw it', async () => {
    const el = await render(lessonsApi());

    expect(buttonNames(el)).not.toContain('Change model…');
  });

  it('re-prices through the picker and extracts on the chosen model', async () => {
    const api = lessonsApi({
      estimateLessons: vi.fn(async () => ({
        estimate: {
          agentKind: 'claude',
          model: 'claude-sonnet-5-5',
          tokens: 9000,
          usd: 0.19,
        },
        signals: 1,
        fromSeq: 4,
        toSeq: 40,
      })),
    });
    const picker: LessonModelPicker = (_value, onChange) => (
      <button
        type="button"
        onClick={() =>
          onChange({ agentKind: 'claude', model: 'claude-sonnet-5-5' })
        }>
        Pick sonnet
      </button>
    );
    const el = await render(api, { renderModelPicker: picker });

    await press(buttonNamed(el, 'Change model…'));
    await press(buttonNamed(el, 'Pick sonnet'));

    expect(api.estimateLessons).toHaveBeenCalledWith({
      runId: 'run-1',
      agentKind: 'claude',
      model: 'claude-sonnet-5-5',
    });
    expect(el.textContent).toContain('$0.19');

    await press(buttonNamed(el, 'Extract lessons'));

    expect(api.reflectLessons).toHaveBeenCalledWith({
      runId: 'run-1',
      reflectLessonsDto: {
        segmentId: 'seg-1',
        agentKind: 'claude',
        model: 'claude-sonnet-5-5',
      },
    });
  });

  it('re-reads a running reflection every 5 s until it ends', async () => {
    vi.useFakeTimers();
    const listLessonSegments = vi
      .fn()
      .mockResolvedValueOnce({ segments: [segment('reflecting')] })
      .mockResolvedValueOnce({ segments: [segment('reflected')] });
    const el = await render(lessonsApi({ listLessonSegments }));

    expect(el.textContent).toContain('Reflecting…');

    await act(async () => {
      await vi.advanceTimersByTimeAsync(5_000);
    });

    expect(listLessonSegments).toHaveBeenCalledTimes(2);
    expect(el.textContent).toBe('Lessons extracted ↓');
  });

  it('re-reads its stretch when the daemon says a lesson changed', async () => {
    const listeners: ((event: { runId: string | null }) => void)[] = [];
    const client = {
      onLessonsChanged: vi.fn(
        (listener: (event: { runId: string | null }) => void) => {
          listeners.push(listener);
          return () => undefined;
        },
      ),
    } as unknown as DaemonClient;
    const api = lessonsApi({
      listLessonSegments: vi
        .fn()
        .mockResolvedValueOnce({ segments: [segment('offered')] })
        .mockResolvedValue({ segments: [segment('dismissed')] }),
    });
    const el = await render(api, { client });

    await act(async () => {
      listeners[0]?.({ runId: 'run-1' });
    });

    expect(api.listLessonSegments).toHaveBeenCalledTimes(2);
    expect(el.textContent).toContain('Not now — waiting in Settings');
  });
});
