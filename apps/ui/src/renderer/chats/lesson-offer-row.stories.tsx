import type { Meta, StoryObj } from '@storybook/react-vite';

import type { LessonSegment } from '../autogenerated';
import { Button } from '../components/ui/button';
import type { DaemonApis } from '../daemon-api';
import { LessonOfferRow } from './lesson-offer-row';
import { LessonsApiContext } from './lessons-api-context';
import type { LessonOfferView } from './lessons-payload';
import type { LessonOfferEntry } from './transcript-groups';

const OFFER: LessonOfferView = {
  segmentId: 'seg-1',
  fromSeq: 4,
  toSeq: 40,
  closedBy: 'idle',
  signals: [
    { kind: 'user_correction', seq: 31 },
    { kind: 'user_correction', seq: 36 },
  ],
  estimate: {
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    tokens: 4200,
    usd: 0.02,
  },
};

const ENTRY: LessonOfferEntry = {
  type: 'lesson-offer',
  id: 'i-70',
  createdAt: '2026-11-12T10:00:00.000Z',
  seq: 70,
  memberId: null,
  parentToolUseId: null,
  runId: 'run-1',
  offer: OFFER,
  latest: true,
};

function segmentIn(status: LessonSegment['status']): LessonSegment {
  return {
    id: 'seg-1',
    runId: 'run-1',
    sourceTitle: 'Synthetic thread',
    archived: false,
    fromSeq: 4,
    toSeq: 40,
    closedBy: 'idle',
    closedAt: '2026-11-12T10:00:00.000Z',
    signals: OFFER.signals,
    status,
    reflectionRunId: status === 'reflected' ? 'refl-1' : null,
    estimate: OFFER.estimate,
  };
}

function apiIn(status: LessonSegment['status']): DaemonApis['lessons'] {
  return {
    listLessonSegments: async () => ({ segments: [segmentIn(status)] }),
    reflectLessons: async () => ({}),
    dismissLessonSegment: async () => ({}),
    estimateLessons: async () => ({
      estimate: OFFER.estimate,
      signals: OFFER.signals.length,
      fromSeq: OFFER.fromSeq,
      toSeq: OFFER.toSeq,
    }),
  } as unknown as DaemonApis['lessons'];
}

function withApi(api: DaemonApis['lessons']) {
  return (story: () => React.ReactNode) => (
    <LessonsApiContext.Provider value={api}>
      {story()}
    </LessonsApiContext.Provider>
  );
}

const meta = {
  title: 'Chats/LessonOfferRow',
  component: LessonOfferRow,
  args: { entry: ENTRY },
  decorators: [
    (story) => (
      <div className="w-[36rem] bg-background p-3 text-foreground">
        {story()}
      </div>
    ),
  ],
} satisfies Meta<typeof LessonOfferRow>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Offered: Story = {
  decorators: [withApi(apiIn('offered'))],
};

export const OfferedWithModelChoice: Story = {
  decorators: [withApi(apiIn('offered'))],
  args: {
    renderModelPicker: (_value, onChange) => (
      <div className="flex flex-wrap gap-2">
        <Button
          size="sm"
          variant="outline"
          onClick={() =>
            onChange({ agentKind: 'claude', model: 'claude-sonnet-5-5' })
          }>
          Sonnet 5.5
        </Button>
      </div>
    ),
  },
};

