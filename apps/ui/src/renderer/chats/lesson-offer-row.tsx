import { useContext, useEffect, useState } from 'react';

import { AgentIdentityContext } from '../agent-identity';
import type { LessonEstimate, LessonSegment } from '../autogenerated';
import { ErrorBanner } from '../components/error-banner';
import { Button } from '../components/ui/button';
import { describeDaemonError } from '../daemon-api';
import { choiceToDto, lessonRunLabel } from './lesson-labels';
import type { LessonModelChoice } from './lesson-model-picker';
import { LessonsApiContext } from './lessons-api-context';
import {
  type LessonModelPickerRender,
  LessonsClientContext,
  LessonsModelPickerContext,
} from './lessons-client-context';
import type { LessonOfferEntry } from './transcript-groups';
import { ALL_SEGMENT_STATUSES, useLessonSegments } from './use-lesson-segments';

const NO_CHOICE: LessonModelChoice = { agentKind: null, model: null };
const REFLECTION_POLL_MS = 5_000;

const STATE_TEXT: Partial<Record<LessonSegment['status'], string>> = {
  reflecting: 'Reflecting…',
  reflected: 'Lessons extracted ↓',
  empty: 'No lessons from this stretch — nothing passed the bar.',
};

const WAITING_TEXT: Partial<Record<LessonSegment['status'], string>> = {
  dismissed: 'Not now — waiting in Settings → Memory → Not reflected yet',
  failed: 'Reflection failed',
};

/**
 * A `lesson_offer` row: the offer to reflect on a closed stretch, with its
 * live state. Only the newest offer of a stretch acts; an older one reads as
 * updated below.
 */
export function LessonOfferRow({
  entry,
  renderModelPicker,
}: {
  entry: LessonOfferEntry;
  renderModelPicker?: LessonModelPickerRender;
}): React.JSX.Element {
  const pickerFromContext = useContext(LessonsModelPickerContext);
  if (!entry.latest) {
    return (
      <p data-slot="lesson-offer" className="m-0 text-xs text-muted-foreground">
        Offer updated below
      </p>
    );
  }
  return (
    <OpenLessonOffer
      entry={entry}
      renderModelPicker={renderModelPicker ?? pickerFromContext ?? undefined}
    />
  );
}

function OpenLessonOffer({
  entry,
  renderModelPicker,
}: {
  entry: LessonOfferEntry;
  renderModelPicker?: LessonModelPickerRender;
}): React.JSX.Element {
  const api = useContext(LessonsApiContext);
  const client = useContext(LessonsClientContext);
  const identities = useContext(AgentIdentityContext);
  const { offer, runId } = entry;
  const { segments, reload } = useLessonSegments({
    lessonsApi: api,
    client,
    runId,
    statuses: ALL_SEGMENT_STATUSES,
  });
  const segment =
    segments?.find((candidate) => candidate.id === offer.segmentId) ?? null;
  const status: LessonSegment['status'] = segment?.status ?? 'offered';

  const [choice, setChoice] = useState<LessonModelChoice | null>(null);
  const [priced, setPriced] = useState<LessonEstimate | null>(null);
  const [picking, setPicking] = useState(false);
  const [pending, setPending] = useState<{
    action: 'extract' | 'dismiss';
    from: LessonSegment['status'];
  } | null>(null);
  const [error, setError] = useState<string | null>(null);

  const choiceDto = choice ?? NO_CHOICE;
  const busy = pending !== null && pending.from === status;

  useEffect(() => {
    if (choice === null || api === null) {
      return;
    }
    let live = true;
    api
      .estimateLessons({ runId, ...choiceToDto(choice) })
      .then((answer) => {
        if (live) {
          setPriced(answer.estimate);
        }
      })
      .catch((err: unknown) => {
        if (live) {
          setError(describeDaemonError(err));
        }
      });
    return () => {
      live = false;
    };
  }, [api, choice, runId]);

  useEffect(() => {
    if (status !== 'reflecting') {
      return;
    }
    const timer = setTimeout(reload, REFLECTION_POLL_MS);
    return () => clearTimeout(timer);
  }, [status, reload]);

  const press = (action: 'extract' | 'dismiss', request: Promise<unknown>) => {
    setPending({ action, from: status });
    setError(null);
    request
      .then(() => reload())
      .catch((err: unknown) => {
        setPending(null);
        setError(describeDaemonError(err));
        reload();
      });
  };

  const extract = (): void => {
    if (api === null) {
      return;
    }
    press(
      'extract',
      api.reflectLessons({
        runId,
        reflectLessonsDto: {
          segmentId: offer.segmentId,
          ...choiceToDto(choiceDto),
        },
      }),
    );
  };

  const dismiss = (): void => {
    if (api === null) {
      return;
    }
    press('dismiss', api.dismissLessonSegment({ segmentId: offer.segmentId }));
  };

  const stateText = STATE_TEXT[status];
  if (stateText !== undefined) {
    return (
      <p data-slot="lesson-offer" className="m-0 text-xs text-muted-foreground">
        {stateText}
      </p>
    );
  }

  const estimate = priced ?? segment?.estimate ?? offer.estimate;
  const signalCount = offer.signals.length;
  const question = `💡 ${signalCount} learning ${signalCount === 1 ? 'signal' : 'signals'} here ${signalCount === 1 ? 'was' : 'were'} never reflected on`;
  const offered = status === 'offered';
  const pressDisabled = api === null || busy;

  return (
    <div
      data-slot="lesson-offer"
      className="flex min-w-0 flex-col gap-2 rounded-lg border border-border p-3">
      <p className="m-0 text-sm font-medium">{question}</p>
      <p className="m-0 text-xs text-muted-foreground">
        {offered
          ? `Extract lessons from messages ${offer.fromSeq + 1}–${offer.toSeq}? · ${lessonRunLabel(identities, estimate)}`
          : WAITING_TEXT[status]}
      </p>
      <div className="flex flex-wrap gap-2">
        <Button size="sm" disabled={pressDisabled} onClick={extract}>
          {busy && pending?.action === 'extract'
            ? 'Extracting…'
            : 'Extract lessons'}
        </Button>
        {offered && renderModelPicker !== undefined ? (
          <Button
            size="sm"
            variant="outline"
            disabled={busy}
            aria-expanded={picking}
            onClick={() => setPicking((open) => !open)}>
            Change model…
          </Button>
        ) : null}
        {offered ? (
          <Button
            size="sm"
            variant="ghost"
            disabled={pressDisabled}
            onClick={dismiss}>
            Not now
          </Button>
        ) : null}
      </div>
      {offered && picking && renderModelPicker !== undefined
        ? renderModelPicker(choiceDto, (next) => setChoice(next))
        : null}
      {error === null ? null : (
        <ErrorBanner
          message={error}
          size="sm"
          onDismiss={() => setError(null)}
        />
      )}
    </div>
  );
}
