// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { LESSON_CORRECTION } from '../__fixtures__/lessons';
import type { LessonReflectionFactsDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { LessonsApiContext } from './lessons-api-context';
import { LessonsBlock } from './lessons-block';
import type { LessonsEntry } from './transcript-groups';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

const ENTRY: LessonsEntry = {
  type: 'lessons',
  id: 'i-50',
  createdAt: '2026-11-12T10:00:00.000Z',
  seq: 50,
  memberId: null,
  parentToolUseId: null,
  card: {
    reflectionRunId: 'refl-1',
    segmentId: 'seg-1',
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    proposals: [LESSON_CORRECTION],
    places: { project: true, team: true },
  },
  outcomes: {},
};

const FACTS_DONE: LessonReflectionFactsDto = {
  reflectionRunId: 'refl-1',
  agentKind: 'claude',
  model: 'claude-haiku-5-5',
  working: false,
  startedAt: '2026-11-12T10:00:00.000Z',
  durationMs: 38_000,
  costUsd: 0.02,
  tokens: 4200,
};

function lessonsApi(
  overrides: Partial<DaemonApis['lessons']> = {},
): DaemonApis['lessons'] {
  return {
    getLessonReflection: vi.fn(async () => FACTS_DONE),
    saveLesson: vi.fn(async () => ({})),
    rejectLesson: vi.fn(async () => ({})),
    ...overrides,
  } as unknown as DaemonApis['lessons'];
}

async function render(
  api: DaemonApis['lessons'] | null,
  entry: LessonsEntry = ENTRY,
): Promise<HTMLDivElement> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(
      <LessonsApiContext.Provider value={api}>
        <LessonsBlock entry={entry} />
      </LessonsApiContext.Provider>,
    );
  });
  return container;
}

function buttonNamed(el: HTMLElement, name: string): HTMLButtonElement {
  const found = [...el.querySelectorAll('button')].find(
    (button) => button.textContent?.trim() === name,
  );
  if (!found) {
    throw new Error(`no button named ${name}`);
  }
  return found;
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
}

describe('LessonsBlock', () => {
  it('names in its footer the model the reflection was billed for', async () => {
    const el = await render(
      lessonsApi({
        getLessonReflection: vi.fn(async () => ({
          ...FACTS_DONE,
          model: 'claude-sonnet-5-5',
        })) as never,
      }),
      { ...ENTRY, card: { ...ENTRY.card, model: 'haiku' } },
    );

    expect(el.textContent).toContain('claude-sonnet-5-5');
    expect(el.textContent).not.toContain('· haiku ·');
  });

  it('disables the actions when no lessons API is provided', async () => {
    const el = await render(null);

    expect(buttonNamed(el, 'Save').disabled).toBe(true);
    expect(buttonNamed(el, 'Edit').disabled).toBe(true);
    expect(buttonNamed(el, 'Reject').disabled).toBe(true);
  });

  it('saves the proposal to its scope through the API', async () => {
    const api = lessonsApi();
    const el = await render(api);

    await press(buttonNamed(el, 'Save'));

    expect(api.saveLesson).toHaveBeenCalledWith({
      proposalId: 'p-correction',
      saveLessonDto: {
        target: { kind: 'memory', scope: 'project', type: 'feedback' },
      },
    });
  });

  it('rejects the proposal with the reason it was given', async () => {
    const api = lessonsApi();
    const el = await render(api);

    await press(buttonNamed(el, 'Reject'));
    const reason = el.querySelector<HTMLInputElement>(
      'input[aria-label="Reject reason"]',
    )!;
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )!.set!;
    act(() => {
      setter.call(reason, 'already covered');
      reason.dispatchEvent(new Event('input', { bubbles: true }));
    });
    await press(buttonNamed(el, 'Reject'));

    expect(api.rejectLesson).toHaveBeenCalledWith({
      proposalId: 'p-correction',
      rejectLessonDto: { reason: 'already covered' },
    });
  });

  it('shows the daemon message when a save is refused', async () => {
    const api = lessonsApi({
      saveLesson: vi.fn(() =>
        Promise.reject(new Error('no project to save to')),
      ),
    });
    const el = await render(api);

    await press(buttonNamed(el, 'Save'));

    expect(el.textContent).toContain('no project to save to');
  });

  it('re-reads a working reflection every 5 s and stops once it is done', async () => {
    vi.useFakeTimers();
    const getLessonReflection = vi
      .fn<() => Promise<LessonReflectionFactsDto>>()
      .mockResolvedValueOnce({ ...FACTS_DONE, working: true, costUsd: null })
      .mockResolvedValueOnce(FACTS_DONE);
    const api = lessonsApi({
      getLessonReflection: getLessonReflection as never,
    });
    const el = await render(api);

    expect(el.textContent).toContain('working…');

    await act(async () => {
      await vi.advanceTimersByTimeAsync(5_000);
    });

    expect(getLessonReflection).toHaveBeenCalledTimes(2);
    expect(el.textContent).toContain('$0.02');
    expect(el.textContent).not.toContain('working…');

    await act(async () => {
      await vi.advanceTimersByTimeAsync(20_000);
    });

    expect(getLessonReflection).toHaveBeenCalledTimes(2);
  });

  it('stops re-reading a working reflection when it unmounts', async () => {
    vi.useFakeTimers();
    const getLessonReflection = vi.fn(async () => ({
      ...FACTS_DONE,
      working: true,
      costUsd: null,
    }));
    const api = lessonsApi({
      getLessonReflection: getLessonReflection as never,
    });
    await render(api);

    act(() => {
      root?.unmount();
    });
    root = null;
    await act(async () => {
      await vi.advanceTimersByTimeAsync(20_000);
    });

    expect(getLessonReflection).toHaveBeenCalledTimes(1);
  });
});
