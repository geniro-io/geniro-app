import { useContext, useEffect, useState } from 'react';

import { agentDisplayName, AgentIdentityContext } from '../agent-identity';
import type { LessonReflectionFactsDto } from '../autogenerated';
import {
  type LessonSaveRequest,
  LessonsCard,
  type LessonsLook,
  type LessonsReflectionView,
} from '../components/lessons-card';
import { describeDaemonError } from '../daemon-api';
import { formatDuration } from '../stats/stats-format';
import { formatUsd } from './agent-activity';
import { LessonsApiContext } from './lessons-api-context';
import type { LessonsEntry } from './transcript-groups';

const LOOK: LessonsLook = {
  formatDuration,
  formatUsd,
};

const REFLECTION_POLL_MS = 5_000;

/**
 * A `lessons` row as its card. The lessons row carries the proposals and the
 * outcomes the user has set on them; the reflection's footer is read from the
 * daemon while it is still working.
 */
export function LessonsBlock({
  entry,
}: {
  entry: LessonsEntry;
}): React.JSX.Element {
  const api = useContext(LessonsApiContext);
  const identities = useContext(AgentIdentityContext);
  const reflectionRunId = entry.card.reflectionRunId;
  const [facts, setFacts] = useState<LessonReflectionFactsDto | null>(null);

  useEffect(() => {
    if (api === null) {
      return;
    }
    let live = true;
    let timer: ReturnType<typeof setTimeout> | undefined;
    const read = (): void => {
      api
        .getLessonReflection({ reflectionRunId })
        .then((next) => {
          if (!live) {
            return;
          }
          setFacts(next);
          if (next.working) {
            timer = setTimeout(read, REFLECTION_POLL_MS);
          }
        })
        .catch(() => undefined);
    };
    read();
    return () => {
      live = false;
      clearTimeout(timer);
    };
  }, [api, reflectionRunId]);

  const reflection: LessonsReflectionView = {
    agent: agentDisplayName(identities, entry.card.agentKind),
    model: entry.card.model,
    working: facts?.working ?? false,
    durationMs: facts?.durationMs ?? null,
    costUsd: facts?.costUsd ?? null,
    tokens: facts?.tokens ?? null,
  };

  return (
    <LessonsCard
      look={LOOK}
      lessons={entry.card.proposals}
      outcomes={entry.outcomes}
      reflection={reflection}
      onSave={
        api === null
          ? undefined
          : (proposalId: string, request: LessonSaveRequest) =>
              api
                .saveLesson({ proposalId, saveLessonDto: request })
                .then(() => undefined)
                .catch((err: unknown) => {
                  throw new Error(describeDaemonError(err));
                })
      }
      onReject={
        api === null
          ? undefined
          : (proposalId: string, reason: string | null) =>
              api
                .rejectLesson({
                  proposalId,
                  rejectLessonDto: reason === null ? {} : { reason },
                })
                .then(() => undefined)
                .catch((err: unknown) => {
                  throw new Error(describeDaemonError(err));
                })
      }
    />
  );
}
