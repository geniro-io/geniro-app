import { describe, expect, it } from 'vitest';

import { LESSON_CORRECTION } from '../__fixtures__/lessons';
import type { ItemDto as ChatItem } from '../autogenerated';
import {
  foldLessonOutcomes,
  readLessonOutcome,
  readLessons,
} from './lessons-payload';

function row(seq: number, kind: ChatItem['kind'], payload: unknown): ChatItem {
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    memberId: null,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

const PROPOSAL = {
  id: 'p-correction',
  title: LESSON_CORRECTION.title,
  rule: LESSON_CORRECTION.rule,
  why: LESSON_CORRECTION.why,
  signalKind: 'user_correction',
  evidence: { seq: 31, quote: 'не запускай vitest напрямую' },
  target: { kind: 'memory', scope: 'project', type: 'feedback' },
  dedup: { verdict: 'refines', handle: 'm12' },
};

const LESSONS_PAYLOAD = {
  reflectionRunId: 'refl-1',
  segmentId: 'seg-1',
  fromSeq: 1,
  toSeq: 40,
  agentKind: 'claude',
  model: 'claude-haiku-5-5',
  proposals: [PROPOSAL],
  places: { project: true, team: false },
};

describe('readLessons', () => {
  it('reads a reflection with its proposals as the card draws them', () => {
    expect(readLessons(row(50, 'lessons', LESSONS_PAYLOAD))).toEqual({
      reflectionRunId: 'refl-1',
      segmentId: 'seg-1',
      agentKind: 'claude',
      model: 'claude-haiku-5-5',
      proposals: [
        {
          id: 'p-correction',
          title: LESSON_CORRECTION.title,
          rule: LESSON_CORRECTION.rule,
          why: LESSON_CORRECTION.why,
          signalKind: 'user_correction',
          evidence: { seq: 31, quote: 'не запускай vitest напрямую' },
          target: { kind: 'memory', scope: 'project', type: 'feedback' },
          dedup: { verdict: 'refines', handle: 'm12' },
        },
      ],
      places: { project: true, team: false },
    });
  });

  it('reads the places the thread has as the daemon wrote them', () => {
    expect(
      readLessons(
        row(50, 'lessons', {
          ...LESSONS_PAYLOAD,
          places: { project: false, team: true },
        }),
      )?.places,
    ).toEqual({ project: false, team: true });
  });

  it('offers every place a row written before the places were named', () => {
    expect(
      readLessons(row(50, 'lessons', { ...LESSONS_PAYLOAD, places: undefined }))
        ?.places,
    ).toEqual({
      project: true,
      team: true,
    });
  });

  it('offers a place whose flag does not read as a boolean', () => {
    expect(
      readLessons(
        row(50, 'lessons', {
          ...LESSONS_PAYLOAD,
          places: { project: 'no', team: false },
        }),
      )?.places,
    ).toEqual({ project: true, team: false });
  });

  it('reads an empty proposal list as a reflection that proposed nothing', () => {
    const card = readLessons(
      row(50, 'lessons', { ...LESSONS_PAYLOAD, proposals: [] }),
    );

    expect(card).not.toBeNull();
    expect(card!.proposals).toEqual([]);
  });

  it('drops a proposal that does not read and keeps the ones that do', () => {
    const card = readLessons(
      row(50, 'lessons', {
        ...LESSONS_PAYLOAD,
        proposals: [{ id: 'broken' }, PROPOSAL],
      }),
    );

    expect(card!.proposals.map((proposal) => proposal.id)).toEqual([
      'p-correction',
    ]);
  });

  it.each([
    ['a payload that is not an object', 'junk'],
    [
      'a payload with no reflection',
      { ...LESSONS_PAYLOAD, reflectionRunId: '' },
    ],
    [
      'a proposals field that is not a list',
      { ...LESSONS_PAYLOAD, proposals: 'x' },
    ],
    ['an unknown agent kind', { ...LESSONS_PAYLOAD, agentKind: 'mystery-cli' }],
    [
      'proposals that all fail to read',
      { ...LESSONS_PAYLOAD, proposals: [{ id: 'broken' }] },
    ],
  ])('answers null for %s', (_label, payload) => {
    expect(readLessons(row(50, 'lessons', payload))).toBeNull();
  });
});

describe('readLessonOutcome', () => {
  it('reads a saved and a rejected outcome', () => {
    expect(
      readLessonOutcome(
        row(60, 'lesson_outcome', {
          proposalId: 'p-correction',
          status: 'saved',
          title: LESSON_CORRECTION.title,
          rule: LESSON_CORRECTION.rule,
          target: { kind: 'memory', scope: 'team', type: 'feedback' },
          memoryHandle: 'm40',
          reason: null,
        }),
      ),
    ).toEqual({
      proposalId: 'p-correction',
      status: 'saved',
      title: LESSON_CORRECTION.title,
      target: { kind: 'memory', scope: 'team', type: 'feedback' },
      memoryHandle: 'm40',
      reason: null,
    });
    expect(
      readLessonOutcome(
        row(61, 'lesson_outcome', {
          proposalId: 'p-correction',
          status: 'rejected',
          title: LESSON_CORRECTION.title,
          rule: LESSON_CORRECTION.rule,
          target: { kind: 'memory', scope: 'team', type: 'feedback' },
          memoryHandle: null,
          reason: 'too narrow',
        }),
      )?.reason,
    ).toBe('too narrow');
  });

  it('answers null for a status it does not know', () => {
    expect(
      readLessonOutcome(
        row(60, 'lesson_outcome', {
          proposalId: 'p-correction',
          status: 'maybe',
          title: LESSON_CORRECTION.title,
          target: { kind: 'memory', scope: 'team', type: 'feedback' },
        }),
      ),
    ).toBeNull();
  });

  it('answers null for an outcome that names no lesson', () => {
    expect(
      readLessonOutcome(
        row(60, 'lesson_outcome', {
          proposalId: 'p-correction',
          status: 'saved',
          target: { kind: 'memory', scope: 'team', type: 'feedback' },
          memoryHandle: 'm40',
          reason: null,
        }),
      ),
    ).toBeNull();
  });
});

describe('foldLessonOutcomes', () => {
  const outcome = (seq: number, status: 'saved' | 'rejected'): ChatItem =>
    row(seq, 'lesson_outcome', {
      proposalId: 'p-correction',
      status,
      title: LESSON_CORRECTION.title,
      target: { kind: 'memory', scope: 'project', type: 'feedback' },
      memoryHandle: status === 'saved' ? 'm40' : null,
      reason: null,
    });

  it('keeps the newest outcome per proposal, whatever order the rows come in', () => {
    const folded = foldLessonOutcomes([
      outcome(62, 'rejected'),
      outcome(60, 'saved'),
    ]);

    expect(folded['p-correction']?.status).toBe('rejected');
  });

  it('keeps the newest of several outcomes in row order too', () => {
    const folded = foldLessonOutcomes([
      outcome(60, 'saved'),
      outcome(62, 'rejected'),
    ]);

    expect(folded['p-correction']?.status).toBe('rejected');
  });

  it('ignores rows that are not outcomes', () => {
    expect(foldLessonOutcomes([row(50, 'lessons', LESSONS_PAYLOAD)])).toEqual(
      {},
    );
  });
});
