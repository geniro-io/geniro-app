import {
  type AgentKind,
  AgentKind as AgentKinds,
  type ItemDto as ChatItem,
  LessonDedupVerdictEnum,
  type LessonEstimate,
  type LessonMemoryTarget,
  LessonMemoryTargetScopeEnum,
  LessonMemoryTargetTypeEnum,
  LessonSegmentCloser,
  type LessonSignalKind,
  LessonSignalKind as LessonSignalKinds,
} from '../autogenerated';
import type {
  LessonDedupVerdict,
  LessonOutcomeView,
  LessonPlaces,
  LessonView,
} from '../components/lessons-card';

/**
 * Readers over a reflection's rows: the `lessons` card a reflection writes
 * into the thread it read, the `lesson_outcome` row each Save or Reject
 * leaves beside it, and the `lesson_offer` row a closed stretch with a learning
 * signal writes.
 *
 * TWIN PARSER: apps/daemon/src/v1/lessons/lessons.types.ts —
 * `LessonsPayloadSchema`, `LessonProposalCardSchema`,
 * `LessonOutcomePayloadSchema` and `LessonOfferPayloadSchema`. The daemon
 * validates before it writes, so these are defensive rather than strict: a
 * proposal that does not read is dropped, and a row that does not read as its
 * kind at all answers null.
 */

export interface LessonsCardData {
  reflectionRunId: string;
  segmentId: string;
  agentKind: AgentKind;
  model: string | null;
  proposals: LessonView[];
  places: LessonPlaces;
}

function record(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

function text(value: unknown): string | null {
  return typeof value === 'string' && value.trim() !== '' ? value : null;
}

function count(value: unknown): number | null {
  return typeof value === 'number' && Number.isInteger(value) && value >= 0
    ? value
    : null;
}

function oneOf<T extends string>(
  value: unknown,
  allowed: readonly T[],
): T | null {
  return typeof value === 'string' &&
    (allowed as readonly string[]).includes(value)
    ? (value as T)
    : null;
}

const SIGNAL_KINDS = Object.values(LessonSignalKinds);
const SCOPES = Object.values(LessonMemoryTargetScopeEnum);
const MEMORY_TYPES = Object.values(LessonMemoryTargetTypeEnum);
const VERDICTS = Object.values(LessonDedupVerdictEnum);
const AGENT_KINDS = Object.values(AgentKinds);

function readTarget(value: unknown): LessonMemoryTarget | null {
  const row = record(value);
  if (row?.kind !== 'memory') {
    return null;
  }
  const scope = oneOf(row.scope, SCOPES);
  const type = oneOf(row.type, MEMORY_TYPES);
  return scope === null || type === null
    ? null
    : { kind: 'memory', scope, type };
}

function readProposal(value: unknown): LessonView | null {
  const row = record(value);
  const id = text(row?.id);
  const title = text(row?.title);
  const rule = text(row?.rule);
  const why = text(row?.why);
  const signalKind = oneOf<LessonSignalKind>(row?.signalKind, SIGNAL_KINDS);
  const evidence = record(row?.evidence);
  const seq = count(evidence?.seq);
  const quote = typeof evidence?.quote === 'string' ? evidence.quote : null;
  const target = readTarget(row?.target);
  const dedup = record(row?.dedup);
  const verdict = oneOf<LessonDedupVerdict>(dedup?.verdict, VERDICTS);
  if (
    id === null ||
    title === null ||
    rule === null ||
    why === null ||
    signalKind === null ||
    seq === null ||
    quote === null ||
    target === null ||
    verdict === null
  ) {
    return null;
  }
  return {
    id,
    title,
    rule,
    why,
    signalKind,
    evidence: { seq, quote },
    target,
    dedup: { verdict, handle: text(dedup?.handle) },
  };
}

function readPlaces(value: unknown): LessonPlaces {
  const row = record(value);
  return {
    project: typeof row?.project === 'boolean' ? row.project : true,
    team: typeof row?.team === 'boolean' ? row.team : true,
  };
}

/** One `lessons` row, or null. Zero proposals is a valid reading: nothing passed the bar. */
export function readLessons(item: ChatItem): LessonsCardData | null {
  const row = record(item.payload);
  const reflectionRunId = text(row?.reflectionRunId);
  const segmentId = text(row?.segmentId);
  const agentKind = oneOf<AgentKind>(row?.agentKind, AGENT_KINDS);
  if (
    row === null ||
    reflectionRunId === null ||
    segmentId === null ||
    agentKind === null ||
    !Array.isArray(row.proposals)
  ) {
    return null;
  }
  const proposals = row.proposals
    .map(readProposal)
    .filter((entry): entry is LessonView => entry !== null);
  // All unreadable is not a zero: drawn as zero, the card would say nothing passed.
  if (proposals.length === 0 && row.proposals.length > 0) {
    return null;
  }
  return {
    reflectionRunId,
    segmentId,
    agentKind,
    model: text(row.model),
    proposals,
    places: readPlaces(row.places),
  };
}

/** One `lesson_outcome` row, or null. */
export function readLessonOutcome(item: ChatItem): LessonOutcomeView | null {
  const row = record(item.payload);
  const proposalId = text(row?.proposalId);
  const status = oneOf(row?.status, ['saved', 'rejected'] as const);
  const title = text(row?.title);
  const target = readTarget(row?.target);
  if (
    proposalId === null ||
    status === null ||
    title === null ||
    target === null
  ) {
    return null;
  }
  return {
    proposalId,
    status,
    title,
    target,
    memoryHandle: text(row?.memoryHandle),
    reason: text(row?.reason),
  };
}

/**
 * Every lesson's decision in a stretch of rows, keyed by proposal. Where a
 * proposal has more than one outcome, the newest by `seq` wins.
 */
export function foldLessonOutcomes(
  items: readonly ChatItem[],
): Record<string, LessonOutcomeView> {
  const outcomes: Record<string, LessonOutcomeView> = {};
  const newest = new Map<string, number>();
  for (const item of items) {
    if (item.kind !== 'lesson_outcome') {
      continue;
    }
    const outcome = readLessonOutcome(item);
    if (outcome === null || (newest.get(outcome.proposalId) ?? -1) > item.seq) {
      continue;
    }
    newest.set(outcome.proposalId, item.seq);
    outcomes[outcome.proposalId] = outcome;
  }
  return outcomes;
}

export interface LessonOfferSignal {
  kind: LessonSignalKind;
  seq: number;
}

export interface LessonOfferView {
  segmentId: string;
  fromSeq: number;
  toSeq: number;
  closedBy: LessonSegmentCloser;
  signals: LessonOfferSignal[];
  estimate: LessonEstimate;
}

const CLOSERS = Object.values(LessonSegmentCloser);

function integer(value: unknown): number | null {
  return typeof value === 'number' && Number.isInteger(value) ? value : null;
}

function readSignalRef(value: unknown): LessonOfferSignal | null {
  const row = record(value);
  const kind = oneOf<LessonSignalKind>(row?.kind, SIGNAL_KINDS);
  const seq = count(row?.seq);
  return kind === null || seq === null ? null : { kind, seq };
}

function readSignalRefs(value: unknown): LessonOfferSignal[] | null {
  if (!Array.isArray(value)) {
    return null;
  }
  const signals = value
    .map(readSignalRef)
    .filter((signal): signal is LessonOfferSignal => signal !== null);
  return signals.length === value.length ? signals : null;
}

/** A price that does not read is no price: the row then shows tokens alone, never $0. */
function readUsd(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) && value >= 0
    ? value
    : null;
}

function readEstimate(value: unknown): LessonEstimate | null {
  const row = record(value);
  const agentKind = oneOf<AgentKind>(row?.agentKind, AGENT_KINDS);
  const tokens = count(row?.tokens);
  if (agentKind === null || tokens === null) {
    return null;
  }
  return {
    agentKind,
    model: text(row?.model),
    tokens,
    usd: readUsd(row?.usd),
  };
}

/** One `lesson_offer` row, or null. */
export function readLessonOffer(item: ChatItem): LessonOfferView | null {
  const row = record(item.payload);
  const segmentId = text(row?.segmentId);
  const fromSeq = integer(row?.fromSeq);
  const toSeq = integer(row?.toSeq);
  const closedBy = oneOf<LessonSegmentCloser>(row?.closedBy, CLOSERS);
  const signals = readSignalRefs(row?.signals);
  const estimate = readEstimate(row?.estimate);
  if (
    row === null ||
    segmentId === null ||
    fromSeq === null ||
    toSeq === null ||
    closedBy === null ||
    signals === null ||
    estimate === null
  ) {
    return null;
  }
  return { segmentId, fromSeq, toSeq, closedBy, signals, estimate };
}

/**
 * The `seq` of each stretch's newest offer: a stretch re-offered after more
 * work carries several rows, and the one reaching furthest (then the latest
 * written) is the only one that still acts.
 */
export function newestLessonOfferSeqs(
  items: readonly ChatItem[],
): ReadonlyMap<string, number> {
  const newest = new Map<string, { toSeq: number; seq: number }>();
  for (const item of items) {
    if (item.kind !== 'lesson_offer') {
      continue;
    }
    const offer = readLessonOffer(item);
    if (offer === null) {
      continue;
    }
    const held = newest.get(offer.segmentId);
    if (
      held !== undefined &&
      (held.toSeq > offer.toSeq ||
        (held.toSeq === offer.toSeq && held.seq > item.seq))
    ) {
      continue;
    }
    newest.set(offer.segmentId, { toSeq: offer.toSeq, seq: item.seq });
  }
  return new Map([...newest].map(([segmentId, held]) => [segmentId, held.seq]));
}
