import type { AgentKind } from '../autogenerated';
import type { McpConfigActions } from '../components/mcp-add-dialog';
import {
  type DaemonApis,
  describeDaemonError,
  MCP_ROUTE_TIMEOUT_MS,
} from '../daemon-api';
import type { AgentMcpScope } from './use-agent-mcp';

/**
 * The "Add MCP server" dialog's three daemon calls, bound to ONE agent scope —
 * a CLI and the config directory its listing was taken under — so every
 * surface that draws an MCP listing (the chat's agents panel, a workflow node,
 * a pool member) offers the same writes to the same profile its rows came
 * from. A plain factory, not a hook: the agents panel binds one per card, in a
 * loop.
 *
 * The profile is OMITTED for the CLI's own default rather than sent as null,
 * on the read path's own rule. Each call rejects with the daemon's own
 * sentence where it gave one, which the dialog shows as is.
 */
export function mcpConfigActions(
  agentsApi: DaemonApis['agents'],
  scope: AgentMcpScope,
): McpConfigActions {
  const agent = scope.agent as AgentKind;
  const profile =
    scope.configDir === null ? {} : { configDir: scope.configDir };
  const said = (err: unknown): never => {
    throw new Error(describeDaemonError(err));
  };
  return {
    read: () =>
      agentsApi
        .readAgentMcpConfig(
          { agent, ...profile },
          { signal: AbortSignal.timeout(MCP_ROUTE_TIMEOUT_MS) },
        )
        .catch(said),
    write: (servers, version) =>
      agentsApi
        .writeAgentMcpConfig(
          { writeMcpConfigDto: { agent, ...profile, servers, version } },
          { signal: AbortSignal.timeout(MCP_ROUTE_TIMEOUT_MS) },
        )
        .catch(said),
    add: (server) =>
      agentsApi
        .addAgentMcpServer(
          { addMcpServerDto: { agent, ...profile, ...server } },
          { signal: AbortSignal.timeout(MCP_ROUTE_TIMEOUT_MS) },
        )
        .catch(said),
  };
}
