import { createContext } from 'react';

import type {
  CardAssessmentVerdictsDto,
  MemberAssessmentVerdictDto,
} from '../autogenerated';

/**
 * Reads and sets the user's verdicts on a recommendations card's member
 * assessments (`GET /v1/stats/assessments/:chatRunId/:cardSeq`, `POST
 * /v1/stats/assessments/verdict`). Provided by `Chats`, which holds the API
 * client; a card drawn without it shows no verdict control.
 */
export interface MemberVerdicts {
  read: (
    chatRunId: string,
    cardSeq: number,
  ) => Promise<CardAssessmentVerdictsDto>;
  set: (
    request: MemberAssessmentVerdictDto,
  ) => Promise<CardAssessmentVerdictsDto>;
}

export const MemberVerdictsContext = createContext<MemberVerdicts | null>(null);
