// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { AttachmentMediaType } from '../autogenerated';
import {
  type AttachmentLoader,
  AttachmentLoaderContext,
  MessageAttachments,
} from './message-attachments';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

const ATTACHMENT = {
  id: 'att-1',
  mediaType: AttachmentMediaType.ImagePng,
};

async function render(load: AttachmentLoader | null): Promise<void> {
  await act(async () => {
    root.render(
      <AttachmentLoaderContext.Provider value={load}>
        <MessageAttachments runId="run-1" attachments={[ATTACHMENT]} />
      </AttachmentLoaderContext.Provider>,
    );
  });
}

describe('the images on a user’s own message', () => {
  it('renders nothing at all with no attachments', () => {
    act(() => {
      root.render(<MessageAttachments runId="run-1" attachments={[]} />);
    });

    expect(container.textContent).toBe('');
  });

  it('opens the whole screenshot, which the row itself only ever crops', async () => {
    // REPORTED as "all images should be clickable", and this is the case it
    // costs the most: the row draws 128px `object-cover` squares, so a pasted
    // screenshot shows its middle third — and the transcript holds the only
    // copy of those bytes in the app.
    const load = vi.fn(async () => 'AAA');

    await render(load);

    const thumb = container.querySelector('[data-slot="zoomable-image"]');
    expect(thumb).not.toBeNull();

    act(() => {
      thumb!.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });

    const full = document.body.querySelector(
      '[data-slot="image-viewer-image"]',
    );
    expect(full?.getAttribute('src')).toBe('data:image/png;base64,AAA');
  });

  it('offers nothing to press when the bytes could not be read', async () => {
    // There is no picture to open, and a control that opens an empty window is
    // worse than the sentence saying why.
    const load = vi.fn(async () => {
      throw new Error('gone');
    });

    await render(load);

    expect(container.querySelector('[data-slot="zoomable-image"]')).toBeNull();
    expect(container.textContent).toContain('image unavailable');
  });
});
