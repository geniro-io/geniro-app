import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { readMetrics } from './metrics-payload';

const row = (payload: unknown): ChatItem =>
  ({
    id: 'i1',
    runId: 'r1',
    nodeId: null,
    seq: 1,
    kind: 'show_metrics',
    role: null,
    payload,
    createdAt: '2026-08-29T10:00:00.000Z',
  }) as unknown as ChatItem;

describe('readMetrics', () => {
  it('reads the daemon’s own literal, every field surviving', () => {
    // The twin of `chat.service.spec.ts`'s worked example — the payload is
    // `z.unknown()` on the wire, so this is the only thing keeping the two
    // readings of one shape together.
    expect(
      readMetrics(
        row({
          title: 'After the caching change',
          metrics: [
            {
              label: 'Coverage',
              value: '82%',
              delta: '+4 pts',
              sentiment: 'good',
              note: 'lines, not branches',
            },
            { label: 'Flaky tests', value: '0' },
          ],
        }),
      ),
    ).toEqual({
      title: 'After the caching change',
      metrics: [
        {
          label: 'Coverage',
          value: '82%',
          delta: '+4 pts',
          sentiment: 'good',
          note: 'lines, not branches',
        },
        {
          label: 'Flaky tests',
          value: '0',
          delta: null,
          sentiment: 'neutral',
          note: null,
        },
      ],
    });
  });

  it('NEVER coerces a number into a value', () => {
    // The invariant this file exists for: 0.82 drawn as "0.82" where the agent
    // meant "82%" would look like the model's mistake and be the renderer's.
    expect(
      readMetrics(row({ metrics: [{ label: 'Coverage', value: 0.82 }] })),
    ).toBeNull();
  });

  it('resolves an absent or unknown sentiment to neutral', () => {
    // Absence is meaningful on the WIRE and not here: the card colours by this,
    // and neutral is what an absent one draws — so nothing downstream has to
    // spell the fallback again. An unknown word must never paint a good result
    // red.
    const read = readMetrics(
      row({
        metrics: [
          { label: 'A', value: '1', delta: '+1' },
          { label: 'B', value: '2', delta: '-1', sentiment: 'gooood' },
        ],
      }),
    );
    expect(read?.metrics.map((m) => m.sentiment)).toEqual([
      'neutral',
      'neutral',
    ]);
  });

  it('drops a row missing either half and keeps the rest', () => {
    const read = readMetrics(
      row({
        metrics: [
          { label: 'Kept', value: '1' },
          { label: 'no value' },
          { value: '7' },
          null,
          'Coverage: 82%',
          { label: 'Also kept', value: '2' },
        ],
      }),
    );
    expect(read?.metrics.map((m) => m.label)).toEqual(['Kept', 'Also kept']);
  });

  it('answers a payload that is not a scorecard with null', () => {
    // Null where the findings reader returns an empty report: an empty review
    // is a result worth a card, a scorecard with no figures is not.
    for (const payload of [
      null,
      'metrics',
      42,
      {},
      { metrics: [] },
      { metrics: 'coverage' },
      { title: 'Results', metrics: [{ label: 'nothing' }] },
    ]) {
      expect(readMetrics(row(payload))).toBeNull();
    }
  });
});
