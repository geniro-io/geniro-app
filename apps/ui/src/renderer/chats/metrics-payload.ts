import type { ItemDto as ChatItem } from '../autogenerated';

/**
 * A scorecard an agent handed the app to draw, read off the transcript.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/chat.types.ts` declares the shape
 * (`HostMetrics`) and `apps/daemon/src/v1/agents/utils/host-metrics.ts` writes
 * these keys for the `show_metrics` item kind. An item payload is `z.unknown()`
 * on the wire BY DESIGN — every kind carries a different shape — so no
 * generated type reaches here and this is an independent reading of one shape.
 * A key renamed on either side must be renamed on both.
 *
 * The invariant this file exists to preserve is the one the daemon's own doc
 * block states: a value is a STRING the agent already formatted, and this
 * reader must never help by coercing a number into one. `0.82` reaching a card
 * as `0.82` where the agent meant `82%` would look like the model's mistake and
 * be the renderer's.
 */

export type Sentiment = 'good' | 'bad' | 'neutral';

const SENTIMENTS: readonly Sentiment[] = ['good', 'bad', 'neutral'];

/** One figure on the scorecard. */
export interface MetricSpec {
  label: string;
  /** Already formatted by the agent — displayed verbatim, never parsed. */
  value: string;
  /** The change, also pre-formatted. Null when there was nothing to compare. */
  delta: string | null;
  /**
   * What that change means. Always resolved to a value here, unlike the wire
   * shape where absence is meaningful: the card colours by it, and `neutral`
   * is exactly what an absent one draws — so a reader downstream of this never
   * has to spell the fallback again.
   */
  sentiment: Sentiment;
  note: string | null;
}

/** One `show_metrics` row, as the card draws it. */
export interface MetricsSpec {
  /** Null when the agent named none; the card supplies its own heading. */
  title: string | null;
  metrics: MetricSpec[];
}

function readString(value: unknown): string | null {
  return typeof value === 'string' && value.length > 0 ? value : null;
}

/**
 * Read one `show_metrics` row, or null when the payload does not read as one.
 *
 * Null where the findings reader would return an empty report, and the
 * difference is the one the daemon draws at its own edge: an empty review IS a
 * result worth a card saying so, while a scorecard with no figures has nothing
 * to draw and no sentence to put in its place. The daemon already refuses that
 * call, so reaching it here means a row written by an older build.
 */
export function readMetrics(item: ChatItem): MetricsSpec | null {
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const row = payload as { title?: unknown; metrics?: unknown };
  if (!Array.isArray(row.metrics)) {
    return null;
  }
  const metrics: MetricSpec[] = [];
  for (const entry of row.metrics) {
    if (typeof entry !== 'object' || entry === null || Array.isArray(entry)) {
      continue;
    }
    const m = entry as {
      label?: unknown;
      value?: unknown;
      delta?: unknown;
      sentiment?: unknown;
      note?: unknown;
    };
    const label = readString(m.label);
    // Read as a STRING and never coerced — see the doc block above. A row that
    // carries a number here is dropped rather than formatted by guesswork.
    const value = readString(m.value);
    if (label === null || value === null) {
      continue;
    }
    metrics.push({
      label,
      value,
      delta: readString(m.delta),
      sentiment:
        typeof m.sentiment === 'string' &&
        (SENTIMENTS as readonly string[]).includes(m.sentiment)
          ? (m.sentiment as Sentiment)
          : 'neutral',
      note: readString(m.note),
    });
  }
  if (metrics.length === 0) {
    return null;
  }
  return { title: readString(row.title), metrics };
}
