import type { AgentModelDto } from '../autogenerated';

export function withSelectedModel(
  models: AgentModelDto[],
  selected: string | null,
): AgentModelDto[] {
  if (selected === null || models.some((entry) => entry.id === selected)) {
    return models;
  }
  const local = selected.startsWith('ollama/');
  return [
    ...models,
    {
      id: selected,
      label: local ? selected.slice('ollama/'.length) : selected,
      source: local ? 'ollama' : 'cli',
      ...(local
        ? {
            unavailableReason:
              models.find((entry) => entry.id === 'ollama/')
                ?.unavailableReason ??
              'Ollama does not currently report this model. Start Ollama or install the model.',
          }
        : {}),
    },
  ];
}
