// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type { AgentModelParameter } from '../autogenerated';
import {
  ModelParameterSelect,
  withModelParameter,
} from './model-parameter-select';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function render(element: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(element);
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const trigger = (el: HTMLElement): HTMLButtonElement | null =>
  el.querySelector<HTMLButtonElement>('[data-menu-trigger]');

function optionLabels(el: HTMLElement): string[] {
  act(() => {
    trigger(el)!.click();
  });
  return [...el.querySelectorAll('[role="option"]')].map(
    (o) => o.textContent ?? '',
  );
}

/**
 * `auto-smart`'s only parameter, exactly as cursor-agent 2026.08.11-e8db854
 * enumerates it — the axis this control was reported for.
 */
const OPTIMIZE_FOR: AgentModelParameter = {
  id: 'optimize_for',
  label: 'Optimize For',
  values: [
    { id: 'intelligence', label: 'Intelligence' },
    { id: 'balanced', label: 'Balance' },
    { id: 'cost', label: 'Cost' },
  ],
  current: 'balanced',
};

describe('ModelParameterSelect', () => {
  it('names itself and its rows in the CLI’s own words', () => {
    // Nothing is baked in here — not the label, not the values, not their
    // labels. `Optimize For` and `Balance` are cursor's spellings, and a table
    // on this side would be this app naming another product's setting.
    const el = render(
      <ModelParameterSelect
        parameter={OPTIMIZE_FOR}
        value={null}
        onChange={() => {}}
      />,
    );

    expect(trigger(el)?.getAttribute('aria-label')).toBe('Optimize For');
    expect(optionLabels(el)).toEqual([
      'Intelligence',
      'Balance',
      'Cost',
      'model default',
    ]);
  });

  it('shows what the model is ALREADY on when nothing is picked', () => {
    // The chip states the outcome, the menu states the choice: with no pick
    // the trigger reads `Balance` (what the turn runs at) while `model default`
    // stays the checked row. A chip reading `model default` would answer "what
    // does this run do" with a word about the picker instead.
    const el = render(
      <ModelParameterSelect
        parameter={OPTIMIZE_FOR}
        value={null}
        onChange={() => {}}
      />,
    );

    expect(trigger(el)?.textContent).toContain('Optimize For · Balance');
  });

  it('names the PARAMETER as well as the value — the half that says nothing alone', () => {
    // REPORTED as "кнопку Cost нужно переименовать, потому что по сути это не
    // Cost". `1M` and `high` name themselves; `Cost` is one option of an axis
    // this app has never heard of, and on its own it reads as a figure. Worse
    // on a boolean axis, where the bare value is the word `true`.
    const el = render(
      <ModelParameterSelect
        parameter={OPTIMIZE_FOR}
        value="cost"
        onChange={() => {}}
      />,
    );

    expect(trigger(el)?.textContent).toContain('Optimize For · Cost');
  });

  it('drops the axis name where a label column already carries it', () => {
    // The run-configuration editor lays its settings out as labelled rows, so
    // naming the axis on the chip too is one name rendered twice inches apart.
    const el = render(
      <ModelParameterSelect
        parameter={OPTIMIZE_FOR}
        value="cost"
        showAxisName={false}
        onChange={() => {}}
      />,
    );

    expect(trigger(el)?.textContent).toContain('Cost');
    expect(trigger(el)?.textContent).not.toContain('Optimize For');
  });

  it('says `default` when the CLI reports no current value and nothing is picked', () => {
    const el = render(
      <ModelParameterSelect
        parameter={{ ...OPTIMIZE_FOR, current: null }}
        value={null}
        onChange={() => {}}
      />,
    );

    expect(trigger(el)?.textContent).toContain('Optimize For · default');
  });

  it('sends the value back verbatim, and null for the default row', () => {
    const picked: (string | null)[] = [];
    const el = render(
      <ModelParameterSelect
        parameter={OPTIMIZE_FOR}
        value={null}
        onChange={(next) => picked.push(next)}
      />,
    );

    act(() => {
      trigger(el)!.click();
    });
    const rows = [...el.querySelectorAll('[role="option"]')];
    act(() => {
      (rows[2] as HTMLElement).click();
    });
    act(() => {
      trigger(el)!.click();
    });
    act(() => {
      (
        [...el.querySelectorAll('[role="option"]')].at(-1) as HTMLElement
      ).click();
    });

    // The id, not the label — `cost`, never `Cost`.
    expect(picked).toEqual(['cost', null]);
  });

  it('names a stored value this model does not offer, DISABLED rather than dropped', () => {
    // A chat carried to another model, or a node whose model changed under it.
    // The value is still stored and still sent, so hiding the row would leave
    // nothing on screen naming what the chip is falling back from.
    const el = render(
      <ModelParameterSelect
        parameter={OPTIMIZE_FOR}
        value="frugal"
        onChange={() => {}}
      />,
    );

    expect(optionLabels(el).some((label) => label.includes('frugal'))).toBe(
      true,
    );
    // …and the chip reports what the turn will ACTUALLY run at, not the stored
    // word, which would claim a setting the model cannot reach.
    expect(trigger(el)?.textContent).toContain('Optimize For · Balance');
  });

  it('renders nothing for a parameter the CLI named without enumerating', () => {
    // A picker with nothing to pick is the dead control this app keeps
    // removing. The adapter already drops these; this is the other half.
    const el = render(
      <ModelParameterSelect
        parameter={{ ...OPTIMIZE_FOR, values: [] }}
        value={null}
        onChange={() => {}}
      />,
    );

    expect(el.textContent).toBe('');
  });
});

describe('withModelParameter', () => {
  it('DELETES the key rather than writing undefined', () => {
    // Absent is the only spelling of "leave this at whatever the model is on":
    // the wire schema is `record(string, string)`, so `{id: undefined}` is not
    // the same thing and does not validate.
    const cleared = withModelParameter(
      { optimize_for: 'cost', fast: 'true' },
      'optimize_for',
      null,
    );

    expect(cleared).toEqual({ fast: 'true' });
    expect('optimize_for' in cleared).toBe(false);
  });

  it('changes one parameter without disturbing its neighbours', () => {
    expect(
      withModelParameter({ fast: 'true' }, 'optimize_for', 'intelligence'),
    ).toEqual({ fast: 'true', optimize_for: 'intelligence' });
  });
});
