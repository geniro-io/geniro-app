import { SlidersHorizontal } from 'lucide-react';

import type { AgentModelParameter } from '../autogenerated';
import { Select } from '../components/ui/select';

/**
 * Sentinel for "send this parameter no value at all" — a distinct value rather
 * than `''`, for the same reason {@link CLI_DEFAULT_EFFORT} is: the menu needs
 * a row it can check, and an empty option value reads as "nothing selected".
 */
export const MODEL_PARAMETER_DEFAULT = '__default__';

/** The MENU row's label for {@link MODEL_PARAMETER_DEFAULT}. */
const DEFAULT_ROW_LABEL = 'model default';

/**
 * One parameter changed in a map of them, as a NEW map.
 *
 * Exists because a chip press is about one parameter while the run stores all
 * of them, and the obvious inline spread writes `{id: undefined}` — which is
 * not the same as an absent key on a wire whose schema is `record(string,
 * string)`. Absent is the only spelling of "leave this at whatever the model is
 * on", so the delete has to be a real delete.
 */
export function withModelParameter(
  parameters: Record<string, string>,
  id: string,
  value: string | null,
): Record<string, string> {
  const next = { ...parameters };
  if (value === null) {
    delete next[id];
  } else {
    next[id] = value;
  }
  return next;
}

/**
 * One chip for one model setting geniro has NO control of its own for — the
 * generic twin of the effort and context-window chips.
 *
 * Those two exist because their axes mean something in every CLI's vocabulary,
 * so this app can name them, explain them and store them in a column each. Most
 * of what a CLI offers is not like that. Measured 2026-08-26 on cursor-agent
 * 2026.08.11-e8db854, one handshake per model: `optimize_for`
 * (intelligence | balanced | cost, on `auto-smart` alone), `thinking` and
 * `fast` were all enumerated by the CLI and invisible in the app — and
 * `optimize_for` is the one REPORTED ("у курсора есть дефолтный модуль, и мы
 * можем выбрать тип этого дефолтного модуля"). A third dedicated stack would
 * have covered one of the three and needed a fourth for the next.
 *
 * So this component knows NOTHING about any of them. The id, the label, the
 * values and their labels all come from the CLI through
 * `GET /v1/agents/model-parameters`, and the chosen value goes back verbatim.
 * That is also why the chip carries no explanation of its own: geniro cannot
 * say what `Fast` does, and inventing a sentence about another product's
 * setting is worse than the CLI's own word for it standing alone.
 *
 * WITH NO VALUES THERE IS NO CHIP — the caller is handed only parameters that
 * enumerated some (the adapter drops the rest), so this is the defensive half
 * of that rule rather than a case anything produces today.
 */
export function ModelParameterSelect({
  parameter,
  value,
  nextTurnOnly = false,
  showAxisName = true,
  onChange,
  className,
  variant = 'ghost',
  id,
}: {
  parameter: AgentModelParameter;
  /** The chosen value, or null for whatever the model is already on. */
  value: string | null;
  /** A turn is running — this pick lands on the NEXT one. */
  nextTurnOnly?: boolean;
  /**
   * Whether the chip states the PARAMETER as well as its value.
   *
   * True everywhere the chip stands in a row of its own, and false only where a
   * label column already names it (the graph node inspector), because two
   * renderings of one name inches apart is the redundancy this app keeps
   * removing.
   */
  showAxisName?: boolean;
  onChange: (value: string | null) => void;
  className?: string;
  /**
   * `ghost` is the composer's flat chip, `default` the bordered form field the
   * graph builder's node inspector uses.
   */
  variant?: 'ghost' | 'default';
  /** Ties the form-field variant to its `Field` label. */
  id?: string;
}): React.JSX.Element | null {
  if (parameter.values.length === 0) {
    return null;
  }
  const known = parameter.values.some((option) => option.id === value);
  // A value the current model does not offer — a chat carried over to another
  // model, or a workflow node whose model changed under it. Added back
  // DISABLED rather than dropped, on the context chip's own rule: the value is
  // still stored and still sent, so hiding the row would leave nothing on
  // screen naming what the chip is silently falling back from.
  const refused = value !== null && !known;
  const rows = [
    ...parameter.values.map((option) => ({
      value: option.id,
      label: option.label,
    })),
    ...(refused
      ? [{ value, label: value, disabled: true, hint: 'unavailable' }]
      : []),
  ];
  /**
   * What the CHIP says: the parameter and the value it is on.
   *
   * BOTH halves, unlike its two neighbours, and that is the whole difference
   * between a setting this app knows and one it does not. `1M` and `high` name
   * themselves — nobody reads a context size as an effort. `Cost` names
   * nothing: it is one option of one axis whose id this app has never heard of,
   * and on its own it reads as a figure. REPORTED exactly that way ("кнопку
   * Cost нужно переименовать, потому что по сути это не Cost"). It matters more
   * on a boolean axis, where the bare value would be the word `true`.
   *
   * The value half is the pick, else what the CLI reports the model is ALREADY
   * on — the same split the context chip documents, so the trigger reads
   * `Optimize For · Balance` while the `model default` row stays checked. It
   * falls back to `default` where the CLI named no current value, which is the
   * only other true thing to say.
   */
  const valueLabel =
    parameter.values.find(
      (option) =>
        option.id ===
        (refused ? parameter.current : (value ?? parameter.current)),
    )?.label ?? 'default';
  const shownLabel = showAxisName
    ? `${parameter.label} · ${valueLabel}`
    : valueLabel;
  return (
    <Select
      variant={variant}
      id={id}
      aria-label={parameter.label}
      title={
        nextTurnOnly
          ? `${parameter.label} — applies to your next message`
          : parameter.label
      }
      className={className}
      leadingIcon={<SlidersHorizontal />}
      // ALWAYS set, where the two neighbouring chips set it only for their
      // default state: the Select would otherwise render the chosen row's bare
      // label, which is the half that says nothing.
      triggerLabel={shownLabel}
      value={(refused ? null : value) ?? MODEL_PARAMETER_DEFAULT}
      groups={[
        { items: rows },
        {
          items: [{ value: MODEL_PARAMETER_DEFAULT, label: DEFAULT_ROW_LABEL }],
        },
      ]}
      onValueChange={(next) =>
        onChange(next === MODEL_PARAMETER_DEFAULT ? null : next)
      }
    />
  );
}
