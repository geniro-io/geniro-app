// @vitest-environment jsdom
import { act, useState } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { AgentModelDto as AgentModel } from '../autogenerated';
import { ModelSelect } from './model-select';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function render(element: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(element);
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

/** One model row as the daemon reports it. */
const model = (id: string, label: string): AgentModel => ({
  id,
  label,
  source: 'cli',
});

/** The rows of an OPEN menu, as `[label, hint]` pairs. */
function openRows(el: HTMLDivElement): [string, string][] {
  act(() => {
    el.querySelector<HTMLElement>('[data-menu-trigger]')?.click();
  });
  return [...el.querySelectorAll('[role="option"]')].map((option) => {
    const spans = [...option.querySelectorAll('span')];
    return [
      spans[0]?.textContent ?? '',
      spans[1]?.textContent ?? '',
    ] satisfies [string, string];
  });
}

describe('ModelSelect', () => {
  it('shows a loader instead of the default row while models are still fetching', () => {
    const el = render(
      <ModelSelect
        agentKind="cursor-agent"
        models={[]}
        loading
        value={null}
        onChange={() => {}}
      />,
    );
    expect(el.textContent).toContain('Loading models…');
    expect(el.querySelector('[data-menu-trigger]')).toBeNull();
    expect(el.querySelector('.animate-spin')).not.toBeNull();
  });

  it('lists what it is given, with no CLI syntax read out of an id', () => {
    // The rows are label-only on purpose. An earlier revision put each model's
    // effort here as a hint, parsed out of a cursor model id — which is dead now
    // that the ids are bare and the effort is its own picker, and which put one
    // CLI's syntax in the composer while it lasted.
    const el = render(
      <ModelSelect
        agentKind="cursor-agent"
        models={[model('claude-opus-5', 'Opus 5'), model('gpt-5.5', 'GPT-5.5')]}
        value={null}
        onChange={() => {}}
      />,
    );

    expect(openRows(el)).toEqual([
      ['Opus 5', ''],
      ['GPT-5.5', ''],
      ['default model', ''],
    ]);
  });

  it('offers no free-text row unless the caller asked for one', () => {
    // The composer's half: a chat runs on what the CLI offers today, so there
    // is no text field and no row promising one.
    const el = render(
      <ModelSelect
        agentKind="claude"
        models={[model('opus', 'opus')]}
        value={null}
        onChange={() => {}}
      />,
    );

    expect(openRows(el).map(([label]) => label)).toEqual([
      'opus',
      'default model',
    ]);
    expect(el.querySelector('input')).toBeNull();
  });
});

/**
 * The graph builder's half of the same chip. It used to be a second component
 * in `workflows/` — a bordered select over a text input, which is what the reported
 * "model should be the same design as when we create chat" was about.
 */
describe('ModelSelect — allowCustom (the node inspector)', () => {
  const CLAUDE = [
    model('opus', 'opus'),
    model('sonnet', 'sonnet'),
    model('haiku', 'haiku'),
  ];
  const spy = vi.fn();

  /** Stateful parent mirroring the inspector: onChange feeds back into value. */
  function Harness({
    initial,
    models = CLAUDE,
  }: {
    initial?: string;
    models?: AgentModel[];
  }): React.JSX.Element {
    const [chosen, setChosen] = useState<string | null>(initial ?? null);
    return (
      <ModelSelect
        agentKind="claude"
        allowCustom
        models={models}
        value={chosen}
        onChange={(next) => {
          spy(next);
          setChosen(next);
        }}
      />
    );
  }

  const trigger = (el: HTMLDivElement): HTMLButtonElement =>
    el.querySelector<HTMLButtonElement>('[data-menu-trigger]')!;

  /** Open the menu and click the row with this label. */
  function pick(el: HTMLDivElement, label: string): void {
    act(() => trigger(el).click());
    const row = [...el.querySelectorAll<HTMLElement>('[role="option"]')].find(
      (option) => option.textContent === label,
    );
    if (!row) {
      throw new Error(`no menu row labelled ${label}`);
    }
    act(() => row.click());
  }

  /** Type into the custom-model input through the prototype setter, so React's
   *  value tracking sees the change (the repo-wide idiom — see Chats.spec.tsx). */
  function typeCustom(el: HTMLDivElement, value: string): void {
    const input = el.querySelector('input')!;
    Object.getOwnPropertyDescriptor(
      Object.getPrototypeOf(input) as object,
      'value',
    )!.set!.call(input, value);
    act(() => {
      input.dispatchEvent(new Event('input', { bubbles: true }));
    });
  }

  it('adds Custom… beside the default row, and keeps both', () => {
    const el = render(<Harness initial="opus" />);

    expect(openRows(el).map(([label]) => label)).toEqual([
      'opus',
      'sonnet',
      'haiku',
      'default model',
      'Custom…',
    ]);
  });

  it('leaves a model-less node on the CLI default rather than adopting one', () => {
    // The builder's picker used to force the first alias onto any node without
    // a model, because it had no row meaning "let the CLI decide". It has one
    // now — and an adopt would fight it, setting `opus` back the instant the
    // user picked the default.
    spy.mockClear();
    const el = render(<Harness />);

    expect(spy).not.toHaveBeenCalled();
    expect(trigger(el).textContent).toContain('default model');
  });

  it('an off-list stored model opens free-text entry showing the exact value', () => {
    const el = render(
      <ModelSelect
        agentKind="claude"
        allowCustom
        models={CLAUDE}
        value="claude-fable-5"
        onChange={() => {}}
      />,
    );

    expect(trigger(el).textContent).toContain('Custom…');
    expect(el.querySelector('input')?.value).toBe('claude-fable-5');
  });

  it('waits for the CLI list before calling a stored model off-list', () => {
    // A node's list is fetched when the node is SELECTED, so the chip routinely
    // mounts with none. Deciding then made every stored model look like free
    // text: re-opening any node showed "Custom…" over a text input, permanently.
    const el = render(
      <ModelSelect
        agentKind="claude"
        allowCustom
        models={[]}
        value="sonnet"
        onChange={() => {}}
      />,
    );

    expect(trigger(el).textContent).toContain('sonnet');
    expect(el.querySelector('input')).toBeNull();
  });

  it('Custom… opens the field without erasing the stored model', () => {
    spy.mockClear();
    const el = render(<Harness initial="opus" />);
    pick(el, 'Custom…');

    // Switching modes alone must not touch the node — only typing does.
    expect(spy).not.toHaveBeenCalled();
    expect(el.querySelector('input')?.value).toBe('opus');

    typeCustom(el, 'claude-fable-5');
    expect(spy).toHaveBeenLastCalledWith('claude-fable-5');
  });

  it('clearing the custom field keeps custom mode — no snap back to an alias', () => {
    spy.mockClear();
    const el = render(<Harness initial="my-own-model" />);
    expect(trigger(el).textContent).toContain('Custom…');

    typeCustom(el, '');

    expect(spy).toHaveBeenLastCalledWith(null);
    expect(trigger(el).textContent).toContain('Custom…');
    expect(el.querySelector('input')).not.toBeNull();
  });

  it('leaving custom mode via an alias emits it and hides the field', () => {
    spy.mockClear();
    const el = render(<Harness initial="my-own-model" />);
    pick(el, 'sonnet');

    expect(spy).toHaveBeenLastCalledWith('sonnet');
    expect(el.querySelector('input')).toBeNull();
  });
});
