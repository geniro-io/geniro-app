// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type { AgentModelDto as AgentModel } from '../autogenerated';
import { ModelEffortReadout } from './model-effort-readout';
import { ModelSelect } from './model-select';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function render(element: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(element);
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

/** One model row as the daemon reports it. */
const model = (
  id: string,
  label: string,
  effort: string | null,
): AgentModel => ({ id, label, source: 'cli', effort });

/** The rows of an OPEN menu, as `[label, hint]` pairs. */
function openRows(el: HTMLDivElement): [string, string][] {
  act(() => {
    el.querySelector<HTMLElement>('[data-menu-trigger]')?.click();
  });
  return [...el.querySelectorAll('[role="option"]')].map((option) => {
    const spans = [...option.querySelectorAll('span')];
    return [
      spans[0]?.textContent ?? '',
      spans[1]?.textContent ?? '',
    ] satisfies [string, string];
  });
}

describe('ModelSelect', () => {
  it('shows a loader instead of the default row while models are still fetching', () => {
    const el = render(
      <ModelSelect
        agentKind="cursor-agent"
        models={[]}
        loading
        value={null}
        onChange={() => {}}
      />,
    );
    expect(el.textContent).toContain('Loading models…');
    expect(el.querySelector('[data-menu-trigger]')).toBeNull();
    expect(el.querySelector('.animate-spin')).not.toBeNull();
  });

  it('shows each row’s effort, which the CLI’s own label leaves out', () => {
    // The whole fix for "I cannot change the effort of a Cursor model". These
    // two rows differ ONLY in effort — cursor folds it into the id and names
    // both models "Opus …" — so a list of labels alone offers the choice while
    // hiding what is being chosen. Drop the hint and the item comes back.
    const el = render(
      <ModelSelect
        agentKind="cursor-agent"
        models={[
          model(
            'claude-opus-5[thinking=true,context=300k,effort=high,fast=false]',
            'Opus 5',
            'high',
          ),
          model(
            'claude-opus-4-7[thinking=true,context=300k,effort=xhigh,fast=false]',
            'Opus 4.7',
            'xhigh',
          ),
        ]}
        value={null}
        onChange={() => {}}
      />,
    );

    expect(openRows(el)).toEqual([
      ['Opus 5', 'high'],
      ['Opus 4.7', 'xhigh'],
      // The default row, which names no model and so states no effort.
      ['default model', ''],
    ]);
  });

  it('leaves the row bare for a CLI whose models state no effort', () => {
    // claude takes effort as its own flag and has a real picker for it, so a
    // hint here would restate a value the chip beside this one owns.
    const el = render(
      <ModelSelect
        agentKind="claude"
        models={[model('opus', 'opus', null)]}
        value={null}
        onChange={() => {}}
      />,
    );

    expect(openRows(el)).toEqual([
      ['opus', ''],
      ['default model', ''],
    ]);
  });
});

describe('ModelEffortReadout', () => {
  const CURSOR_REASON =
    'cursor-agent builds the reasoning effort into the model itself — change it in Cursor’s own model picker';

  it('states the effort the chosen model carries', () => {
    const el = render(
      <ModelEffortReadout effort="high" unavailableReason={CURSOR_REASON} />,
    );
    expect(el.textContent).toContain('high');
  });

  it('carries the daemon’s reason verbatim, so the chip is not merely inert', () => {
    // The item was "cursor's effort isn't changeable". It genuinely is not — the
    // agent rejects every recomposed model id on both ACP carriers (see the
    // adapter's `efforts` field for the probe) — so the fix available to the chip
    // is to name where it DOES change. Stating the value alone is what made this
    // read as a broken control, and composing the sentence here instead of
    // showing the adapter's is how it came to say something the daemon did not.
    const el = render(
      <ModelEffortReadout effort="high" unavailableReason={CURSOR_REASON} />,
    );

    const title = el.querySelector('[title]')?.getAttribute('title') ?? '';
    expect(title).toContain('high');
    expect(title).toContain(CURSOR_REASON);
  });

  it('renders nothing for a CLI that HAS an effort picker', () => {
    // A null reason is the affirmative answer, and `EffortSelect` is then on
    // screen: two controls for one value is worse than the readout being absent.
    const el = render(
      <ModelEffortReadout effort="high" unavailableReason={null} />,
    );
    expect(el.textContent).toBe('');
  });

  it('renders nothing before the capability report lands', () => {
    // Undefined, not null — the agent is simply not in the map yet. Rendering
    // would show a chip whose only explanation is still in flight.
    const el = render(
      <ModelEffortReadout effort="high" unavailableReason={undefined} />,
    );
    expect(el.textContent).toBe('');
  });

  it('renders nothing on the CLI default, where no model is chosen yet', () => {
    const el = render(
      <ModelEffortReadout effort={null} unavailableReason={CURSOR_REASON} />,
    );
    expect(el.textContent).toBe('');
  });
});
