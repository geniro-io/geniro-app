import { Sparkles } from 'lucide-react';
import { useEffect, useState } from 'react';

import type { CliKind } from '../../shared/contracts';
import type { AgentModelDto as AgentModel } from '../autogenerated';
import { Input } from '../components/ui/input';
import { LoadingChip } from '../components/ui/loading-chip';
import { Select } from '../components/ui/select';

/**
 * Sentinel for "send no `--model` flag at all". A distinct value rather than
 * `''` because the menu needs a row it can check, and an empty option value
 * would be indistinguishable from "nothing selected".
 */
export const CLI_DEFAULT_MODEL = '__default__';

/** The label shown for {@link CLI_DEFAULT_MODEL} on the chip and in the menu. */
const DEFAULT_LABEL = 'default model';

/**
 * Sentinel for the row that switches the chip to free-text entry — offered only
 * under {@link ModelSelect}'s `allowCustom`.
 *
 * NOT an action row: custom is a MODE the chip stays in, so it has to be able
 * to carry the checkmark and name itself on the trigger.
 */
const CUSTOM_MODEL = '__custom__';

/**
 * The composer's model chip: which model the next chat's CLI runs.
 *
 * The rows are whatever the CLI itself reports (fetched by the caller through
 * `useAgentModels`), never a list baked into this app — so a model the CLI
 * gains is offered without a release. A `default model` row always closes the
 * list: sending no `--model` is a real choice, and it is the one that still
 * works when a CLI cannot be asked.
 *
 * A model the CLI no longer reports but the run still carries (a remembered
 * pick, an older CLI) is added back as its own row, so the chip names what
 * will actually be passed instead of silently showing the default.
 *
 * The same chip serves an OPEN chat, where it switches the model the next turn
 * runs as — including while a turn is in flight, which {@link nextTurnOnly}
 * says out loud.
 *
 * …and the graph builder's node inspector, under {@link allowCustom}. ONE chip
 * for all three rather than a second picker in `workflows/`, on the rule the
 * effort chip beside it already follows: which rows the CLI reports, that a
 * stored model outside them still has to be named on screen, and what the
 * default row means are the parts worth getting right once.
 */
export function ModelSelect({
  agentKind,
  models,
  value,
  loading = false,
  nextTurnOnly = false,
  allowCustom = false,
  onChange,
  showIcon = true,
  className,
}: {
  agentKind: CliKind;
  models: AgentModel[];
  /** The chosen model id, or null for the CLI's default. */
  value: string | null;
  /** The CLI's model list is still being fetched — show a loader, not a default. */
  loading?: boolean;
  /** A turn is running — this pick lands on the NEXT one. */
  nextTurnOnly?: boolean;
  /**
   * Offer a `Custom…` row that opens free-text entry for a full model id.
   *
   * The builder's case, not the composer's, and the asymmetry is deliberate: a
   * workflow is written once and run for months, so naming a model the CLI does
   * not enumerate (`claude-fable-5`) is worth a text field there — while a chat
   * is started from whatever the CLI offers today.
   *
   * Mount the chip with `key={nodeId}`: the mode belongs to ONE node and must
   * not leak across selections.
   */
  allowCustom?: boolean;
  onChange: (model: string | null) => void;
  /**
   * The leading glyph, on by default.
   *
   * It IDENTIFIES the chip in a row of chips that carry no labels — the
   * composer's footer, where `opus` beside `high` beside `auto-approve` is
   * three words with nothing saying which axis each belongs to. In a LABEL
   * COLUMN there is already a word for that, and the glyph then costs
   * alignment instead: it pushes this value's text right by its own width, so
   * a column mixing chips that have one with chips and plain text that do not
   * has three different left edges. REPORTED as exactly that — "параметр
   * как-то криво выглядит — может быть за счёт иконок, может быть за счёт
   * выравнивания" — and it was both, which is one cause.
   *
   * The same trade `model-parameter-select`'s `showAxisName` already makes.
   */
  showIcon?: boolean;
  className?: string;
}): React.JSX.Element {
  // Whether free-text entry is open, or null while nothing has decided yet.
  //
  // Decided ONCE, and only once the CLI's list has actually arrived. The
  // inspector fetches per selected node, so the chip routinely mounts with an
  // empty list: deciding then made every stored model look like free text, and
  // every node re-opened showed `Custom…` over a text input, permanently.
  const [custom, setCustom] = useState<boolean | null>(null);
  useEffect(() => {
    if (allowCustom && custom === null && models.length > 0) {
      setCustom(value !== null && !models.some((model) => model.id === value));
    }
  }, [allowCustom, custom, models, value]);
  // Undecided reads as list mode: the alternative opens a text input over a
  // model the list is about to recognise.
  const customMode = allowCustom && (custom ?? false);

  if (loading) {
    return (
      <LoadingChip
        noun="models"
        title={`Loading models for ${agentKind}…`}
        visibleText="Loading models…"
        className={className}
      />
    );
  }
  const known = models.some((model) => model.id === value);
  const rows = [
    ...models.map((model) => ({ value: model.id, label: model.label })),
    // A stored model the CLI no longer reports is added back so the chip names
    // what will actually be passed — except under `allowCustom`, where the same
    // value opens the text field instead and a row for it would be a second
    // place to edit one thing.
    ...(value !== null && !known && !allowCustom
      ? [{ value, label: value }]
      : []),
  ];
  const select = (
    <Select
      variant="ghost"
      aria-label="Model"
      title={
        nextTurnOnly
          ? `Model for ${agentKind} — applies to your next message`
          : `Model for ${agentKind}`
      }
      className={className}
      searchPlaceholder={rows.length > 8 ? 'Search models…' : undefined}
      {...(showIcon ? { leadingIcon: <Sparkles /> } : {})}
      value={customMode ? CUSTOM_MODEL : (value ?? CLI_DEFAULT_MODEL)}
      // While the list is still on its way the stored id IS the honest label:
      // with no matching row the trigger would otherwise fall back to the
      // default and read as though nothing had been chosen. Only reachable
      // under `allowCustom` — the add-back row above covers the composer.
      triggerLabel={
        allowCustom && !customMode && value !== null && !known
          ? value
          : undefined
      }
      groups={[
        ...(rows.length > 0 ? [{ items: rows }] : []),
        {
          items: [
            { value: CLI_DEFAULT_MODEL, label: DEFAULT_LABEL },
            ...(allowCustom ? [{ value: CUSTOM_MODEL, label: 'Custom…' }] : []),
          ],
        },
      ]}
      onValueChange={(next) => {
        if (next === CUSTOM_MODEL) {
          // Keep the stored model — the field below takes over editing it, so
          // switching modes alone never changes what the run will use.
          setCustom(true);
          return;
        }
        setCustom(false);
        onChange(next === CLI_DEFAULT_MODEL ? null : next);
      }}
    />
  );
  if (!allowCustom) {
    return select;
  }
  return (
    <>
      {select}
      {customMode ? (
        <Input
          aria-label="Custom model id"
          // `w-full` in the chip row that holds it: the field is a line of its
          // own under the chips, not a sixth chip beside them.
          className="w-full"
          value={value ?? ''}
          placeholder="full model id, e.g. claude-fable-5"
          onChange={(event) => onChange(event.target.value || null)}
        />
      ) : null}
    </>
  );
}
