// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type { AgentModelDto, AgentModelParameter } from '../autogenerated';
import { AgentModelDtoSourceEnum } from '../autogenerated';
import { ModelSettingsSelect } from './model-settings-select';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const MODELS: AgentModelDto[] = [
  { id: 'auto-smart', label: 'Auto', source: AgentModelDtoSourceEnum.Cli },
  {
    id: 'claude-opus-5',
    label: 'Claude Opus 5',
    source: AgentModelDtoSourceEnum.Cli,
  },
];
const OPTIMIZE_FOR: AgentModelParameter = {
  id: 'optimize_for',
  label: 'Optimize For',
  values: [
    { id: 'intelligence', label: 'Intelligence' },
    { id: 'balanced', label: 'Balance' },
    { id: 'cost', label: 'Cost' },
  ],
  current: 'balanced',
};

/**
 * Stable empties for the defaults below. `useAgentVocabulary` hands out one
 * shared `NOTHING_YET` for the same reason: a fresh `[]` per render changes
 * identity every time, which would silently defeat the panel's own row memo
 * here and make the dependency-list test below pin nothing.
 */
const NO_ITEMS: never[] = [];
const NO_VALUES: Record<string, string> = {};

/** Every prop defaulted to "this model offers nothing", overridden per case. */
function render(
  over: Partial<React.ComponentProps<typeof ModelSettingsSelect>> = {},
): {
  el: HTMLDivElement;
  picked: [string, string | null][];
  rerender: (
    next: Partial<React.ComponentProps<typeof ModelSettingsSelect>>,
  ) => void;
} {
  const picked: [string, string | null][] = [];
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  const paint = (
    extra: Partial<React.ComponentProps<typeof ModelSettingsSelect>>,
  ): void => {
    act(() => {
      root!.render(
        <ModelSettingsSelect
          agentKind="cursor-agent"
          models={MODELS}
          model={null}
          onModelChange={(m) => picked.push(['model', m])}
          efforts={NO_ITEMS}
          effort={null}
          onEffortChange={(e) => picked.push(['effort', e])}
          windows={NO_ITEMS}
          contextWindow={null}
          onContextWindowChange={(w) => picked.push(['context', w])}
          parameters={NO_ITEMS}
          parameterValues={NO_VALUES}
          onParameterChange={(id, v) => picked.push([id, v])}
          {...over}
          {...extra}
        />,
      );
    });
  };
  paint({});
  // ACCUMULATES rather than replaces. With replace-semantics every rerender
  // silently reverted the props an earlier one had set, so a second dependency
  // always moved alongside the one under test — which is exactly what a
  // dependency-list test must not allow.
  let applied = { ...over };
  const rerender = (
    next: Partial<React.ComponentProps<typeof ModelSettingsSelect>>,
  ): void => {
    applied = { ...applied, ...next };
    paint(applied);
  };
  return { el: container, picked, rerender };
}

const trigger = (el: HTMLElement): HTMLButtonElement =>
  el.querySelector<HTMLButtonElement>('[data-menu-trigger]')!;

function open(el: HTMLElement): void {
  act(() => {
    trigger(el).click();
  });
}

/** The FIRST level's rows: one per axis, plus Model. */
function axisRows(el: HTMLElement): string[] {
  const panel = el.querySelector<HTMLElement>('[role="listbox"]');
  return panel
    ? [...panel.querySelectorAll('[role="option"]')].map(
        (o) => o.querySelector('span')?.textContent ?? '',
      )
    : [];
}

function axisRow(el: HTMLElement, label: string): HTMLElement | undefined {
  const panel = el.querySelector<HTMLElement>('[role="listbox"]');
  return panel
    ? [...panel.querySelectorAll<HTMLElement>('[role="option"]')].find(
        (o) => o.querySelector('span')?.textContent === label,
      )
    : undefined;
}

/** The SECOND level — the panel an axis row opened. */
function submenuRows(el: HTMLElement): HTMLElement[] {
  const panels = [...el.querySelectorAll<HTMLElement>('[role="listbox"]')];
  const child = panels[1];
  return child
    ? [...child.querySelectorAll<HTMLElement>('[role="option"]')]
    : [];
}

function openAxis(el: HTMLElement, label: string): void {
  act(() => {
    axisRow(el, label)!.click();
  });
}

/** The second level's blocks — the hairline between them is drawn per group. */
function submenuGroups(el: HTMLElement): HTMLElement[] {
  const child = [...el.querySelectorAll<HTMLElement>('[role="listbox"]')][1];
  return child
    ? [...child.querySelectorAll<HTMLElement>('[data-slot="menu-group"]')]
    : [];
}

/** The second-level row whose label matches, or undefined. */
function submenuRow(el: HTMLElement, label: string): HTMLElement | undefined {
  return submenuRows(el).find(
    (r) => r.querySelector('span')?.textContent === label,
  );
}

describe('ModelSettingsSelect', () => {
  it('draws ONE chip naming the model, over a first level of AXES', () => {
    // The report, twice over. First: five pickers across the composer row on
    // `claude-opus-5` through cursor. Then, when that became one flat panel:
    // "сейчас у нас один огромный большой список. У нас должно быть
    // двух-уровневое меню", with Cursor's own picker as the reference. So the
    // first level is one row per axis — its name and where it stands — and the
    // values live behind it.
    const { el } = render({
      model: 'claude-opus-5',
      efforts: [{ id: 'high', label: 'high' }],
      windows: [{ id: '1m', label: '1m' }],
      parameters: [OPTIMIZE_FOR],
    });

    expect(el.querySelectorAll('[data-menu-trigger]')).toHaveLength(1);
    expect(trigger(el).textContent).toContain('Claude Opus 5');
    open(el);
    expect(axisRows(el)).toEqual([
      'Effort',
      'Context window',
      'Optimize For',
      'Model',
    ]);
  });

  it('states where each axis STANDS on its own row', () => {
    // The reason a level beats a heading: five current values readable at a
    // glance. A chosen value wins; with nothing chosen the row reports what the
    // CLI says the model is already on, which is what the turn will run at.
    const { el } = render({
      efforts: [
        { id: 'low', label: 'low' },
        { id: 'high', label: 'high' },
      ],
      effort: 'high',
      parameters: [OPTIMIZE_FOR],
    });

    open(el);
    expect(axisRow(el, 'Effort')?.textContent).toContain('high');
    // `optimize_for` is unset, and cursor reports the model is on `balanced`.
    expect(axisRow(el, 'Optimize For')?.textContent).toContain('Balance');
  });

  it('puts the MODEL row last, with the only search field behind it', () => {
    // Thirty-four rows is where typing beats scrolling; five is not, and a
    // filter over the first level would hide the axes it exists to show.
    const { el } = render({ parameters: [OPTIMIZE_FOR] });

    open(el);
    expect(axisRows(el).at(-1)).toBe('Model');
    expect(el.querySelector('input')).toBeNull();
    openAxis(el, 'Model');
    expect(
      [...el.querySelectorAll('input')].some(
        (i) => i.getAttribute('placeholder') === 'Search models…',
      ),
    ).toBe(true);
  });

  it('checks each axis’s own value, which one menu value cannot', () => {
    // `MenuItem.checked` exists for exactly this: a single `value` marks one
    // row, and this control holds a choice per submenu.
    const { el } = render({
      efforts: [
        { id: 'low', label: 'low' },
        { id: 'high', label: 'high' },
      ],
      effort: 'high',
      parameters: [OPTIMIZE_FOR],
      parameterValues: { optimize_for: 'cost' },
    });

    const checkedUnder = (axisLabel: string): string[] => {
      open(el);
      openAxis(el, axisLabel);
      const marked = submenuRows(el)
        .filter((r) => r.getAttribute('aria-selected') === 'true')
        .map((r) => r.querySelector('span')?.textContent ?? '');
      open(el);
      return marked;
    };

    expect(checkedUnder('Effort')).toEqual(['high']);
    expect(checkedUnder('Optimize For')).toEqual(['Cost']);
  });

  it('routes a pick to the axis it came from, and null for the default row', () => {
    const { el, picked } = render({
      efforts: [{ id: 'high', label: 'high' }],
      parameters: [OPTIMIZE_FOR],
    });

    open(el);
    openAxis(el, 'Optimize For');
    act(() => {
      submenuRows(el)[0]!.click();
    });
    open(el);
    openAxis(el, 'Effort');
    act(() => {
      submenuRows(el).at(-1)!.click();
    });
    open(el);
    openAxis(el, 'Model');
    act(() => {
      submenuRows(el)[1]!.click();
    });

    // The ids, never the labels — `intelligence`, not `Intelligence`.
    expect(picked).toEqual([
      ['optimize_for', 'intelligence'],
      ['effort', null],
      ['model', 'claude-opus-5'],
    ]);
  });

  it('drops an axis entirely when the model offers nothing in it', () => {
    // The standing rule: a picker with nothing to pick is not drawn. With a
    // model that has no axes at all this is one row long — the old model chip.
    const { el } = render({ model: 'auto-smart' });

    open(el);
    expect(axisRows(el)).toEqual(['Model']);
  });

  it('names a stored value the model refuses, DISABLED, beside the default', () => {
    // The run still carries it and the daemon still sends it, so hiding the row
    // would leave nothing on screen naming what the default is standing in for.
    const { el } = render({
      parameters: [OPTIMIZE_FOR],
      parameterValues: { optimize_for: 'frugal' },
    });

    open(el);
    openAxis(el, 'Optimize For');
    const rows = submenuRows(el);
    const stored = rows.find(
      (r) => r.querySelector('span')?.textContent === 'frugal',
    );
    expect(stored).toBeDefined();
    expect(stored?.hasAttribute('disabled')).toBe(true);
    // …and the default row is the one marked, since that is what will run.
    expect(rows.at(-1)?.getAttribute('aria-selected')).toBe('true');
  });

  it('keeps a stored effort OUTSIDE the CLI-wide union selectable, and says so', () => {
    // With no model chosen the daemon answers with the union, and the union is
    // not a superset by construction — cursor declares `effortsAreExhaustive:
    // false` because gpt-5.2 enumerates a level no other model has. So a stored
    // level the union omits still RUNS, and printing `unavailable` beside it
    // would name the wrong outcome and leave no way to re-select it.
    const { el } = render({
      model: null,
      efforts: [
        { id: 'low', label: 'low' },
        { id: 'high', label: 'high' },
      ],
      effort: 'xhigh',
    });

    open(el);
    // The axis stands where the STORED level says, not at the default.
    expect(axisRow(el, 'Effort')?.textContent).toContain('xhigh');
    openAxis(el, 'Effort');
    const stored = submenuRow(el, 'xhigh');
    expect(stored).toBeDefined();
    expect(stored?.hasAttribute('disabled')).toBe(false);
    expect(stored?.textContent).not.toContain('unavailable');
    expect(stored?.getAttribute('aria-selected')).toBe('true');
  });

  it('refuses a stored effort outside ONE MODEL’s own list', () => {
    // The other half of the same rule, and the case the single-axis chip was
    // rebuilt for: with a model chosen the list is that model's, so a level it
    // omits is that model refusing it — re-offering it would put `xhigh` back
    // on a model that declines it every turn.
    const { el } = render({
      model: 'claude-opus-5',
      efforts: [
        { id: 'low', label: 'low' },
        { id: 'high', label: 'high' },
      ],
      effort: 'xhigh',
    });

    open(el);
    // The axis falls back to what will actually run.
    expect(axisRow(el, 'Effort')?.textContent).not.toContain('xhigh');
    openAxis(el, 'Effort');
    const stored = submenuRow(el, 'xhigh');
    expect(stored?.hasAttribute('disabled')).toBe(true);
    expect(stored?.textContent).toContain('unavailable');
    // …and the default row is the one marked, since that is what will run.
    expect(submenuRows(el).at(-1)?.getAttribute('aria-selected')).toBe('true');
  });

  it('gives the default row a block of its own, so the hairline is drawn', () => {
    // The three single-axis chips each put it in its own menu group; pushed
    // into the values array it reads as one more value here and as a distinct
    // escape hatch there, for one row that means the same thing in both.
    const { el } = render({
      efforts: [
        { id: 'low', label: 'low' },
        { id: 'high', label: 'high' },
      ],
    });

    open(el);
    openAxis(el, 'Effort');
    const groups = submenuGroups(el);
    expect(groups).toHaveLength(2);
    expect(
      [...groups[1]!.querySelectorAll('[role="option"]')].map(
        (o) => o.querySelector('span')?.textContent,
      ),
    ).toEqual(['default effort']);
  });

  it('gives a recognised parameter its own glyph, and everything else the generic one', () => {
    // The named exception. `fast` earns a bolt because it was asked for by name;
    // every other id keeps the sliders, which is what lets a parameter the
    // vendor ships next month render correctly with no change here. Asserted on
    // the two rows TOGETHER — either alone passes with the map deleted or with
    // it applied to everything.
    const { el } = render({
      parameters: [
        {
          id: 'fast',
          label: 'Fast',
          values: [{ id: 'true', label: 'On' }],
          current: null,
        },
        OPTIMIZE_FOR,
        {
          id: 'thinking',
          label: 'Thinking',
          values: [{ id: 'true', label: 'On' }],
          current: null,
        },
      ],
    });

    open(el);
    const glyph = (label: string): string => {
      const svg = axisRow(el, label)?.querySelector('svg');
      if (!svg) {
        throw new Error(`no glyph on the "${label}" row`);
      }
      return svg.getAttribute('class') ?? '';
    };

    // Two UNRECOGNISED parameters share one glyph…
    expect(glyph('Optimize For')).toBe(glyph('Thinking'));
    // …and the recognised one differs from it. Neither half alone would fail
    // the two ways this can break: delete the map and the first still passes,
    // apply it to everything and the second does.
    expect(glyph('Fast')).not.toBe(glyph('Optimize For'));
  });

  it('says the axes are STILL BEING FETCHED rather than dropping them', () => {
    // The report: "я выбрал GPT 5.5… и он мне вообще не пишет никаких
    // дополнительных параметров к этой модели, хотя должен". GPT-5.5 offers
    // three, and each is answered by a real `cursor-agent acp` handshake — so
    // for twenty-odd seconds an empty listing was drawn exactly like a model
    // that has none, which is the one thing this control must not confuse.
    const { el } = render({ model: 'claude-opus-5', settingsLoading: true });

    open(el);
    expect(axisRows(el)).toEqual(['Reading what this model offers…', 'Model']);
    // …and it is a statement, not a picker: there is nothing behind it yet.
    expect(
      axisRow(el, 'Reading what this model offers…')?.hasAttribute('disabled'),
    ).toBe(true);
  });

  it('drops the pending row the moment an axis answers', () => {
    // The other half: the row stands in for the axes, so it must not outlive
    // them. Same props as above with the answer in — one row, not two.
    const { el } = render({
      model: 'claude-opus-5',
      efforts: [{ id: 'high', label: 'high' }],
      settingsLoading: false,
    });

    open(el);
    expect(axisRows(el)).toEqual(['Effort', 'Model']);
  });

  it('rebuilds the rows when any input the panel reads changes', () => {
    // The rows are memoized, and `react-hooks/exhaustive-deps` is not enabled
    // in this repo — nothing mechanically checks that dependency list. A
    // forgotten entry serves a stale panel, which this drives one input at a
    // time: change it, and the second level must state the new answer.
    const { el, rerender } = render({
      efforts: [
        { id: 'low', label: 'low' },
        { id: 'high', label: 'high' },
      ],
      effort: 'low',
      parameters: [OPTIMIZE_FOR],
      parameterValues: { optimize_for: 'cost' },
    });

    const checkedUnder = (axisLabel: string): string[] => {
      open(el);
      openAxis(el, axisLabel);
      const marked = submenuRows(el)
        .filter((r) => r.getAttribute('aria-selected') === 'true')
        .map((r) => r.querySelector('span')?.textContent ?? '');
      open(el);
      return marked;
    };

    expect(checkedUnder('Effort')).toEqual(['low']);
    rerender({ effort: 'high' });
    expect(checkedUnder('Effort')).toEqual(['high']);

    expect(checkedUnder('Optimize For')).toEqual(['Cost']);
    rerender({ parameterValues: { optimize_for: 'intelligence' } });
    expect(checkedUnder('Optimize For')).toEqual(['Intelligence']);

    // The vocabulary itself, not only the selection — a model answering with a
    // level it did not have before must reach the list.
    rerender({
      efforts: [
        { id: 'low', label: 'low' },
        { id: 'high', label: 'high' },
        { id: 'max', label: 'max' },
      ],
    });
    open(el);
    openAxis(el, 'Effort');
    expect(
      submenuRows(el).map((r) => r.querySelector('span')?.textContent),
    ).toContain('max');
  });

  it('rebuilds on EVERY remaining memo input, one at a time', () => {
    // The companion to the case above, and between them they drive all ten
    // entries of the dependency list. Each step changes exactly one prop and
    // asserts an observable that only that prop can move, so dropping any single
    // entry from the list turns one of these red — which is the whole reason
    // the test exists, `react-hooks/exhaustive-deps` being off in this repo.
    const { el, rerender } = render();
    const axisNames = (): string[] => {
      open(el);
      const names = axisRows(el);
      open(el);
      return names;
    };
    const hintOf = (label: string): string => {
      open(el);
      const text = axisRow(el, label)?.textContent ?? '';
      open(el);
      return text;
    };

    // `model` and `models` are asserted on the MODEL AXIS ROW, never the
    // trigger: the trigger's label is composed in the JSX, outside the memo, so
    // it moves whether or not either is in the dependency list and would pass
    // with both dropped.
    expect(hintOf('Model')).toContain('default');
    rerender({ model: 'claude-opus-5' });
    expect(hintOf('Model')).toContain('Claude Opus 5');
    rerender({ models: [{ ...MODELS[1]!, label: 'Opus (renamed)' }] });
    expect(hintOf('Model')).toContain('Opus (renamed)');

    // `windows` — an axis that did not exist appears.
    expect(axisNames()).not.toContain('Context window');
    rerender({ windows: [{ id: '1m', label: '1m' }] });
    expect(axisNames()).toContain('Context window');

    // `contextWindow` — where that axis STANDS. The row's hint is the
    // EFFECTIVE label ('default'), not the submenu's `model default` row.
    expect(hintOf('Context window')).toContain('default');
    rerender({ contextWindow: '1m' });
    expect(hintOf('Context window')).toContain('1m');

    // `windowTokens` — the fallback shown with nothing chosen. Cleared FIRST as
    // its own step, so the step that follows moves this prop alone; changing
    // both at once would let `contextWindow` account for the rebuild.
    rerender({ contextWindow: null });
    expect(hintOf('Context window')).toContain('default');
    rerender({ windowTokens: 200_000 });
    expect(hintOf('Context window')).toContain('200k');

    // `parameters` — another axis appearing.
    expect(axisNames()).not.toContain('Optimize For');
    rerender({ parameters: [OPTIMIZE_FOR] });
    expect(axisNames()).toContain('Optimize For');

    // `settingsLoading` — the pending row standing in for the axes.
    expect(axisNames()).not.toContain('Reading what this model offers…');
    rerender({ settingsLoading: true });
    expect(axisNames()).toContain('Reading what this model offers…');
  });

  it('is a READOUT while the model list is still being fetched', () => {
    // Kept from the model chip this replaced: there is nothing to open yet, and
    // a pressable-but-empty picker is what that behaviour exists to avoid.
    const { el } = render({ models: [], loading: true });

    expect(el.querySelector('[data-menu-trigger]')).toBeNull();
    expect(el.textContent).toContain('Loading models…');
  });
});
