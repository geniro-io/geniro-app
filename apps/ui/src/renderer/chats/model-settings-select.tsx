import {
  FolderOpen,
  Gauge,
  IdCard,
  Maximize2,
  ShieldCheck,
  SlidersHorizontal,
  Sparkles,
  Zap,
} from 'lucide-react';
import { useMemo } from 'react';

import type { CliKind, ConfigProfile } from '../../shared/contracts';
import type {
  AgentContextWindow,
  AgentEffort,
  AgentModelDto as AgentModel,
  AgentModelParameter,
  ChatApprovalMode,
} from '../autogenerated';
import { chipVariants } from '../components/ui/chip';
import type { MenuItem } from '../components/ui/menu';
import { Select } from '../components/ui/select';
import { Spinner } from '../components/ui/spinner';
import { cn } from '../components/ui/utils';
import { formatTokens } from './agent-activity';
import { approvalOptions } from './approval-mode-select';
import { folderName, shortenPath } from './directory-select';

/**
 * The one row that means "send this axis no value at all" — a distinct token
 * rather than `''`, for the reason every sentinel in this directory is one: the
 * menu needs a row it can check.
 */
const DEFAULT = '__default__';

/** Value prefixes, so one menu's `onValueChange` can tell its blocks apart. */
const MODEL = 'model';
const EFFORT = 'effort';
const CONTEXT = 'context';
const PARAMETER = 'parameter';
const APPROVAL = 'approval';
const PROFILE = 'profile';

/**
 * The profile submenu's two ACTION rows — a path is never one of these, since
 * both are bare words and every real value is absolute.
 */
const PROFILE_DEFAULT = '__default_profile__';
const PROFILE_BROWSE = '__browse_profile__';

/** Stable, so a caller with no recents does not re-key the memo each render. */
const EMPTY_RECENTS: readonly string[] = [];
/**
 * A stable empty default, like {@link EMPTY_RECENTS} beside it: a fresh `[]` in
 * the parameter list is a new reference on every render, which would defeat the
 * memo the whole panel is built inside.
 */
const EMPTY_PROFILES: readonly ConfigProfile[] = [];

/** `<kind>:<id>` — and for a parameter, `parameter:<parameterId>:<value>`. */
const encode = (...parts: string[]): string => parts.join(':');

/**
 * Glyphs for the model parameters this app recognises BY NAME, keyed by the
 * CLI's own id.
 *
 * A deliberate, named exception to the rule the rest of this file follows — the
 * CLI's word, never ours. Everything else about a parameter is a pass-through
 * precisely because geniro cannot know what another product's setting means,
 * and an icon is a claim about meaning like any other. It exists because it was
 * asked for by name ("для Fast Mode нам нужна молния"), and a bolt on Fast is a
 * claim that is plainly true.
 *
 * Kept as ONE list rather than a branch at the call site so the exception stays
 * countable: anything not on it keeps the generic sliders, which is what makes
 * a parameter the vendor ships next month render correctly with no change here.
 */
const PARAMETER_ICONS: Record<string, React.ReactNode> = {
  fast: <Zap />,
};

/**
 * The row that stands where the axes will be, while the CLI is still being
 * asked what this model offers.
 *
 * Without it "not asked yet" and "this model has none" are the same picture,
 * because an empty axis is DROPPED — and the wait is not a frame: the three
 * listings are answered by ONE real `cursor-agent acp` handshake, measured at
 * 6.1–6.8s on a cold model (6.2s wall for all three, so the single-flight is
 * working) against 0.0s warm, so picking a model the daemon has not probed
 * leaves the panel holding its Model row alone. Reported exactly that way
 * ("я выбрал GPT 5.5…
 * и он мне вообще не пишет никаких дополнительных параметров к этой модели,
 * хотя должен") — GPT-5.5 offers effort, a context window and Fast, and all
 * three were on their way.
 *
 * ONE row rather than a skeleton per axis, because which axes exist is itself
 * the answer being waited for: only the model knows whether it has an effort
 * level, and `optimize_for` exists on one model of the thirty-four.
 */
const PENDING_AXES: MenuItem = {
  value: 'axis:pending:',
  icon: <Spinner />,
  label: 'Reading what this model offers…',
  disabled: true,
};

/**
 * ONE control for a model AND everything that model can be run with.
 *
 * It replaces a row of separate chips — model, effort, context window, and one
 * per parameter the CLI enumerates. That row was correct and it grew: on
 * `claude-opus-5` through cursor it was five pickers wide, each an icon and a
 * word, and REPORTED as such ("сейчас очень много опций… в курсоре фактически
 * не на каждую опцию отдельный select, а поповер, когда мы выбираем модель,
 * уже там все эти опции"). Cursor's own picker is the shape being described,
 * and the second half of the report is the other reason for it: inside one
 * panel each block carries a LABEL, so a setting says what it is in words
 * rather than only through an icon the composer had no room to explain.
 *
 * It is a `Select` and not a bespoke popover, which is what keeps it honest:
 * the search box, the keyboard highlight, the escape from a clipping ancestor
 * and the panel's own placement are the primitive's, and a hand-built panel
 * here would be a second answer to all four. What it needed from the primitive
 * was ONE addition — `MenuItem.checked`, because a menu holding several
 * independent choices cannot mark them from a single `value`.
 *
 * IT IS TWO LEVELS, which is the shape being copied rather than a flourish.
 * The first is one compact row per axis — its name, where it currently stands,
 * and a chevron; the second is that axis's values. A single flat panel was
 * built first and REPORTED ("сейчас у нас один огромный большой список. У нас
 * должно быть двух-уровневое меню"), with Cursor's own picker as the reference:
 * on `claude-opus-5` the flat form was five blocks of values followed by
 * thirty-four model rows, so the thing the panel is named after sat at the
 * bottom of a scroller. Two levels make the whole set of axes readable at once,
 * with the current value of each on its own row.
 *
 * The MODEL is one of those rows, last, and the only one whose second level
 * carries a search field — thirty-four rows is where typing beats scrolling and
 * five is not.
 *
 * The glyphs are the ones these settings already wore as separate chips —
 * a gauge for effort, arrows for the context window, sliders for a parameter
 * this app has no name for, a spark for the model — so the control reads as the
 * row it replaced rather than as a new vocabulary. {@link PARAMETER_ICONS} is
 * the one place a parameter earns a glyph of its own.
 *
 * Every row is DROPPED when the model offers nothing to choose in it, on the
 * standing rule that a picker with nothing to pick is not drawn. With a CLI
 * that has no axes at all this is one row long, which is the old model chip.
 * Not before the CLI has answered, though — see {@link PENDING_AXES}.
 */
export function ModelSettingsSelect({
  agentKind,
  models,
  model,
  onModelChange,
  efforts,
  effort,
  onEffortChange,
  approvalModes,
  approval,
  planSupported,
  onApprovalChange,
  windows,
  contextWindow,
  windowTokens = null,
  onContextWindowChange,
  parameters,
  parameterValues,
  onParameterChange,
  configDir = null,
  recentConfigDirs = EMPTY_RECENTS,
  configProfiles = EMPTY_PROFILES,
  configDirUnavailableReason,
  onConfigDirChange,
  onBrowseConfigDir,
  loading = false,
  settingsLoading = false,
  nextTurnOnly = false,
  className,
}: {
  /** Which CLI is being asked — named in the loading chip and nowhere else. */
  agentKind: CliKind;
  models: AgentModel[];
  /** The chosen model, or null for the CLI's own default. */
  model: string | null;
  onModelChange: (model: string | null) => void;
  efforts: AgentEffort[];
  effort: string | null;
  onEffortChange: (effort: string | null) => void;
  /**
   * Tool-approval modes this run's CLI honours, or null while capabilities have
   * not loaded. Empty means it has no approval channel, and the axis is absent —
   * the same "a picker with nothing to pick is not drawn" rule the effort and
   * window axes follow.
   */
  approvalModes: readonly ChatApprovalMode[] | null;
  /** Current mode; null = a legacy run created before the selector existed. */
  approval: ChatApprovalMode | null;
  /** Whether the installed claude probed `--permission-mode plan` as passing. */
  planSupported: boolean;
  onApprovalChange: (approval: ChatApprovalMode) => void;
  windows: AgentContextWindow[];
  contextWindow: string | null;
  /** The window the agent reported for this thread, when one has been measured. */
  windowTokens?: number | null;
  onContextWindowChange: (contextWindow: string | null) => void;
  parameters: AgentModelParameter[];
  /** The run's own picks, keyed by the CLI's parameter id. */
  parameterValues: Record<string, string>;
  onParameterChange: (parameterId: string, value: string | null) => void;
  /** The chosen profile, or null for the CLI's own — the normal state. */
  configDir?: string | null;
  recentConfigDirs?: readonly string[];
  /**
   * The user's NAMED configurations (Settings → the claude card), so a
   * directory they have named wears its colour in the Profile list.
   *
   * Defaulted to empty rather than required: every other caller of this control
   * renders the same panel without one, and an empty list simply leaves every
   * row uncoloured — which is also what an install that has named nothing sees.
   */
  configProfiles?: readonly ConfigProfile[];
  /**
   * Why this CLI cannot be pointed at a config directory (`null` = it can),
   * `undefined` while the capability read is in flight — and `undefined` also
   * for a caller that does not offer the axis at all. All three draw no row,
   * which is why one field carries them: the honest rendering before the daemon
   * has spoken is nothing rather than a guess, and so is the rendering for a
   * surface that never asked.
   */
  configDirUnavailableReason?: string | null;
  /** A pick, or null from the "Default profile" row. Absent hides the axis. */
  onConfigDirChange?: (configDir: string | null) => void;
  /** Open the native directory dialog. Absent hides the axis. */
  onBrowseConfigDir?: () => void;
  /** The model list is still being fetched — the trigger says so. */
  loading?: boolean;
  /**
   * The axes below are still being fetched — see {@link PENDING_AXES}. Separate
   * from `loading` because they are separate questions: the model list is one
   * per CLI and already answered, while what THIS model offers is asked again
   * on every pick.
   */
  settingsLoading?: boolean;
  /** A turn is running — these picks land on the NEXT one. */
  nextTurnOnly?: boolean;
  className?: string;
}): React.JSX.Element {
  // Memoized, and ABOVE the readout return below rather than beside the render
  // it feeds: a hook cannot sit after a conditional return. The rows are ~40
  // objects plus a JSX icon per axis, rebuilt on every render of a component
  // the transcript re-renders on each streamed delta, for a list that only
  // changes when the vocabulary or a selection does.
  const rows = useMemo(() => {
    /**
     * One AXIS as a first-level row: its name, where it stands, and its values
     * behind it. Null when the model offers nothing to choose in it.
     *
     * `checked` is set per value row rather than left to the menu's own value
     * rule — one `value` cannot mark a choice in each of five submenus. The
     * default row closes every axis for the reason it closes the model list:
     * sending nothing is a real choice, and the one that still works when a model
     * refuses everything else.
     */
    const axis = (
      icon: React.ReactNode,
      label: string,
      prefix: string,
      options: { id: string; label: string }[],
      chosen: string | null,
      defaultLabel: string,
      /** What runs when nothing is chosen, for the row's own hint. */
      effectiveLabel: string,
      /**
       * Whether {@link options} is ONE MODEL's list rather than the CLI's union —
       * the same distinction {@link EffortSelect.levelsAreModelSpecific} carries,
       * and it decides what a stored value the list does not contain MEANS. For a
       * model's list it means this model refuses that value, so the row is
       * disabled and the axis falls back to its default. For a CLI-wide union it
       * means the vocabulary moved under a run that still carries the old word —
       * the daemon honours it and the turn will run at it, so the row stays
       * selectable and the axis states it.
       */
      valuesAreModelSpecific: boolean,
      parameterId?: string,
    ): MenuItem | null => {
      if (options.length === 0) {
        return null;
      }
      const key = (value: string): string =>
        parameterId === undefined
          ? encode(prefix, value)
          : encode(prefix, parameterId, value);
      const known = options.some((option) => option.id === chosen);
      const refused = chosen !== null && !known && valuesAreModelSpecific;
      const items: MenuItem[] = options.map((option) => ({
        value: key(option.id),
        label: option.label,
        checked: option.id === chosen,
      }));
      // A stored value the list does not contain, added back rather than dropped:
      // the run still carries it, so hiding the row would leave nothing on screen
      // naming what the default is standing in for.
      if (chosen !== null && !known) {
        items.push({
          value: key(chosen),
          label: chosen,
          hint: refused ? 'unavailable' : undefined,
          disabled: valuesAreModelSpecific,
          checked: !refused,
        });
      }
      return {
        value: `axis:${prefix}:${parameterId ?? ''}`,
        icon,
        label,
        // The first level states where each axis STANDS, which is the whole
        // reason it is worth a level of its own: five values readable at a glance
        // where five chips could only be read one hover at a time.
        hint:
          chosen === null || refused
            ? effectiveLabel
            : (options.find((option) => option.id === chosen)?.label ?? chosen),
        // The default row gets a GROUP of its own, which is what draws the
        // hairline above it — the three single-axis chips each separate it that
        // way, and pushed into the values array it reads as one more value here
        // and as a distinct escape hatch there.
        submenu: [
          { items },
          {
            items: [
              {
                value: key(DEFAULT),
                label: defaultLabel,
                checked: chosen === null || refused,
              },
            ],
          },
        ],
      };
    };

    /**
     * WHICH PROFILE the chat runs as — the account, and the toolbelt with it.
     *
     * ASKED FOR as "давай еще Default profile тоже засунем в Opus Submenu": it
     * was a chip beside this one, and it belongs here for the reason approval
     * did — the composer row was a queue of pickers, and this panel is where a
     * setting gets a name and a stated value instead of a bare word.
     *
     * It LEADS, ahead of approval, which is the order the graph node inspector
     * teaches: profile, approval, then the model and everything the model
     * offers. Two surfaces with a label column should not teach two orders.
     *
     * ABSENT — not disabled — for a CLI that reads no config directory, and
     * absent while the daemon has not said either way: the standing "a picker
     * with nothing to pick is not drawn" rule, which the chip decided for
     * itself and the row now decides the same way.
     */
    const profileRow = ((): MenuItem | null => {
      if (
        configDirUnavailableReason !== null ||
        onConfigDirChange === undefined ||
        onBrowseConfigDir === undefined
      ) {
        return null;
      }
      // The current one leads even before it is among the persisted recents,
      // so the panel always has a row to put the checkmark on.
      const paths =
        configDir !== null && !recentConfigDirs.includes(configDir)
          ? [configDir, ...recentConfigDirs]
          : recentConfigDirs;
      return {
        value: 'axis:profile:',
        icon: <IdCard />,
        label: 'Profile',
        // The LEAF, like the chip it replaced: a full path is a paragraph in a
        // row that has to state four other settings beside it, and the whole
        // of it is one row down.
        hint: configDir === null ? 'default' : folderName(configDir),
        submenu: [
          ...(paths.length > 0
            ? [
                {
                  label: 'Recents',
                  items: paths.map((path) => {
                    // The colour of the user's NAMED configuration for this
                    // directory, drawn by `Menu` as the row's left border —
                    // asked for as "просто левый бордер вот этого же цвета".
                    // Only that: the row still says the PATH, because a colour
                    // is a way to recognise a directory at a glance rather than
                    // a replacement for knowing which one it is, and a list
                    // where some rows said a name and others a path would read
                    // as two kinds of thing.
                    const accent = configProfiles.find(
                      (profile) => profile.dir === path,
                    )?.color;
                    return {
                      value: encode(PROFILE, path),
                      // More than the leaf here: two checkouts of one repo are
                      // both `geniro-app` and would be the same row.
                      label: shortenPath(path),
                      title: path,
                      icon: <IdCard />,
                      checked: path === configDir,
                      // Spread rather than a possibly-`undefined` key: an
                      // explicit undefined is still a key, and `MenuItem`
                      // distinguishes "no colour" from "a colour".
                      ...(accent === undefined ? {} : { accent }),
                    };
                  }),
                },
              ]
            : []),
          {
            items: [
              {
                value: encode(PROFILE, PROFILE_DEFAULT),
                label: 'Default profile',
                checked: configDir === null,
              },
              {
                value: encode(PROFILE, PROFILE_BROWSE),
                label: 'Choose config directory…',
                icon: <FolderOpen />,
                action: true,
              },
            ],
          },
        ],
      };
    })();

    /**
     * The tool-approval posture, as the FIRST row.
     *
     * ASKED FOR as "add auto-approve option to model settings popover instead"
     * — it was a chip of its own beside this one, and on `claude-opus-5` the
     * row was already five pickers wide. It is not a model setting, which is
     * exactly why it leads rather than being interleaved among the axes the
     * model derives: those come and go as the vocabulary lands, and a row that
     * is always there should not move when they do.
     *
     * Built by hand rather than through {@link axis}: that helper's shape is a
     * nullable value with a default arm, and there is no "default approval" to
     * send — a null here is a legacy run whose mode was never recorded, not a
     * choice anyone can make.
     */
    const approvalRow = ((): MenuItem | null => {
      const options = approvalOptions(approvalModes, planSupported, approval);
      if (options.length === 0) {
        return null;
      }
      return {
        value: 'axis:approval:',
        icon: <ShieldCheck />,
        label: 'Approval',
        // The placeholder the chip used, for the same reason: a run created
        // before the selector existed runs on whatever the CLI defaults to, and
        // naming one of the modes would state a posture nobody chose.
        hint:
          options.find((option) => option.value === approval)?.label ??
          'cli default',
        submenu: [
          {
            items: options.map((option) => ({
              value: encode(APPROVAL, option.value),
              label: option.label,
              checked: option.value === approval,
            })),
          },
        ],
      };
    })();

    const modelKnown = models.some((entry) => entry.id === model);
    const modelRow: MenuItem = {
      value: 'axis:model:',
      icon: <Sparkles />,
      label: 'Model',
      hint:
        model === null
          ? 'default'
          : (models.find((entry) => entry.id === model)?.label ?? model),
      submenuSearchPlaceholder: 'Search models…',
      submenu: [
        {
          items: [
            ...models.map((entry) => ({
              value: encode(MODEL, entry.id),
              label: entry.label,
              checked: entry.id === model,
            })),
            // A model the CLI no longer reports but the run still carries stays
            // SELECTABLE, unlike a refused axis value: the CLI's own list moving
            // is not the same as this model refusing a setting.
            ...(model !== null && !modelKnown
              ? [{ value: encode(MODEL, model), label: model, checked: true }]
              : []),
            {
              value: encode(MODEL, DEFAULT),
              label: 'default model',
              checked: model === null,
            },
          ],
        },
      ],
    };

    return [
      profileRow,
      approvalRow,
      axis(
        <Gauge />,
        'Effort',
        EFFORT,
        efforts,
        effort,
        'default effort',
        'default',
        // The one axis with a CLI-wide union to fall back on: with no model
        // chosen the daemon answers with it AND still honours a stored level
        // outside it, since the union is not a superset by construction (cursor
        // declares `effortsAreExhaustive: false` — gpt-5.2 enumerates a level no
        // other model has).
        model !== null,
      ),
      axis(
        <Maximize2 />,
        'Context window',
        CONTEXT,
        windows,
        contextWindow,
        'model default',
        windowTokens !== null && windowTokens > 0
          ? formatTokens(windowTokens)
          : 'default',
        // Always one model's list: there is no union of window sizes to fall
        // back on, so a size outside the list is this model refusing it.
        true,
      ),
      ...parameters.map((parameter) =>
        axis(
          // A recognised id gets its own glyph; everything else keeps the
          // generic sliders — see {@link PARAMETER_ICONS} for why that asymmetry
          // is the point rather than an omission.
          PARAMETER_ICONS[parameter.id.toLowerCase()] ?? <SlidersHorizontal />,
          parameter.label,
          PARAMETER,
          parameter.values,
          parameterValues[parameter.id] ?? null,
          'model default',
          parameter.values.find((v) => v.id === parameter.current)?.label ??
            'default',
          // Which ids exist at all is this model's answer, so a stored value
          // outside its list is refused rather than merely unlisted.
          true,
          parameter.id,
        ),
      ),
      // Last of the axes and above the model, which is where the rows it stands
      // in for will appear — so an axis arriving does not move the Model row out
      // from under the pointer.
      settingsLoading ? PENDING_AXES : null,
      modelRow,
    ].filter((row): row is MenuItem => row !== null);
  }, [
    configDir,
    recentConfigDirs,
    configDirUnavailableReason,
    onConfigDirChange,
    onBrowseConfigDir,
    models,
    model,
    efforts,
    effort,
    windows,
    contextWindow,
    windowTokens,
    parameters,
    parameterValues,
    settingsLoading,
    approvalModes,
    approval,
    planSupported,
  ]);

  // While the list is still being fetched there is nothing to open, so the chip
  // is a READOUT rather than a picker — kept from the model chip this control
  // replaced, where a pressable-but-empty picker was the thing being avoided.
  if (loading && models.length === 0) {
    return (
      <span
        data-slot="select-chip"
        aria-busy="true"
        aria-label="Loading models"
        title={`Loading models for ${agentKind}…`}
        className={cn(
          chipVariants({ interactive: false, tone: 'active' }),
          className,
        )}>
        <Spinner className="size-3.5" />
        <span className="truncate">Loading models…</span>
      </span>
    );
  }

  return (
    <Select
      variant="ghost"
      aria-label="Model and its settings"
      title={
        nextTurnOnly
          ? 'Model and its settings — apply to your next message'
          : 'Model and its settings'
      }
      className={className}
      leadingIcon={<Sparkles />}
      // NO search at the FIRST level: it holds five rows at most, and a filter
      // over them would hide the axes it exists to make visible. The model's
      // own level carries one.
      // The chip names the MODEL and nothing else. Every other setting is one
      // press away and would not fit here — the row this control replaced was
      // reported for being too wide.
      triggerLabel={
        model === null
          ? 'default model'
          : (models.find((entry) => entry.id === model)?.label ?? model)
      }
      value={null}
      groups={[{ items: rows }]}
      onValueChange={(next) => {
        const [kind, ...rest] = next.split(':');
        const tail = rest.join(':');
        if (kind === MODEL) {
          onModelChange(tail === DEFAULT ? null : tail);
          return;
        }
        if (kind === PROFILE) {
          if (tail === PROFILE_BROWSE) {
            onBrowseConfigDir?.();
            return;
          }
          onConfigDirChange?.(tail === PROFILE_DEFAULT ? null : tail);
          return;
        }
        if (kind === APPROVAL) {
          onApprovalChange(tail as ChatApprovalMode);
          return;
        }
        if (kind === EFFORT) {
          onEffortChange(tail === DEFAULT ? null : tail);
          return;
        }
        if (kind === CONTEXT) {
          onContextWindowChange(tail === DEFAULT ? null : tail);
          return;
        }
        // `parameter:<id>:<value>`, and the id is split off rather than the
        // value: a CLI's value can carry a colon far more plausibly than its
        // parameter id can.
        const [parameterId, ...valueParts] = rest;
        const value = valueParts.join(':');
        if (parameterId !== undefined) {
          onParameterChange(parameterId, value === DEFAULT ? null : value);
        }
      }}
    />
  );
}
