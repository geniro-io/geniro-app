// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { TranscriptItem } from './transcript-item';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;

afterEach(() => {
  act(() => root?.unmount());
  root = null;
  document.body.innerHTML = '';
});

function mount(item: ChatItem): HTMLElement {
  const container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <TranscriptItem
        item={item}
        nodes={new Map([['manager', { name: 'Manager', kind: 'agent' }]])}
      />,
    );
  });
  return container;
}

const row = (payload: Record<string, unknown>): ChatItem => ({
  id: 'i1',
  runId: 'r1',
  nodeId: 'manager',
  seq: 1,
  kind: 'system',
  role: null,
  payload,
  createdAt: '2026-10-21T12:00:00Z',
});

const monitor = (
  over: Record<string, unknown> = {},
): Record<string, unknown> => ({
  id: 'm1',
  description: 'dev server log',
  event: 'batch',
  lines: [],
  omitted: 0,
  ...over,
});

const notice = (monitors: Record<string, unknown>[], woke: boolean): ChatItem =>
  row({ severity: 'info', message: 'monitor m1', monitors, woke });

describe('the monitor divider', () => {
  it('says which agent picked back up, for which monitor', () => {
    const el = mount(notice([monitor({ lines: ['ready'] })], true));
    expect(el.querySelector('[data-slot="monitor-divider"]')?.textContent).toBe(
      'Manager picked back up — dev server log · monitor m1',
    );
    // The divider, not the daemon's message drawn as a note.
    expect(el.textContent).not.toContain('monitor m1 stopped');
  });

  it('adds the exit code of a monitor that ended', () => {
    const el = mount(
      notice([monitor({ event: 'end', end: { kind: 'exit', code: 0 } })], true),
    );
    expect(el.querySelector('[data-slot="monitor-divider"]')?.textContent).toBe(
      'Manager picked back up — dev server log · monitor m1 · exit code 0',
    );
    expect(
      el.querySelector('[data-slot="monitor-end"]')?.className,
    ).not.toContain('font-semibold');
  });

  it.each([
    [{ kind: 'exit', code: 3 }, 'exit code 3'],
    [{ kind: 'signal', signal: 'SIGKILL' }, 'killed by SIGKILL'],
    [{ kind: 'timeout' }, 'timed out'],
    [{ kind: 'flooded' }, 'flooded'],
    [{ kind: 'interrupted' }, 'interrupted'],
  ])('draws the bad ending %j heavier', (end, text) => {
    const el = mount(notice([monitor({ event: 'end', end })], true));
    const suffix = el.querySelector('[data-slot="monitor-end"]');
    expect(suffix?.textContent).toBe(text);
    expect(suffix?.className).toContain('font-semibold');
  });

  it('draws a stopped ending at normal weight', () => {
    const el = mount(
      notice([monitor({ event: 'end', end: { kind: 'stopped' } })], true),
    );
    const suffix = el.querySelector('[data-slot="monitor-end"]');
    expect(suffix?.textContent).toBe('stopped');
    expect(suffix?.className).not.toContain('font-semibold');
  });

  it('draws one divider for each monitor in the row', () => {
    const el = mount(
      notice(
        [monitor(), monitor({ id: 'm2', description: 'build watch' })],
        true,
      ),
    );
    expect(
      [...el.querySelectorAll('[data-slot="monitor-divider"]')].map(
        (divider) => divider.textContent,
      ),
    ).toEqual([
      'Manager picked back up — dev server log · monitor m1',
      'Manager picked back up — build watch · monitor m2',
    ]);
  });

  it('folds the delivered output away until it is asked for', () => {
    const el = mount(
      notice([monitor({ lines: ['compiled', 'ready'], omitted: 3 })], true),
    );
    expect(el.querySelector('[data-slot="monitor-output"]')).toBeNull();
    const toggle = [...el.querySelectorAll('button')].find(
      (button) => button.textContent === 'Output',
    ) as HTMLButtonElement;
    act(() => toggle.click());
    const output = el.querySelector('[data-slot="monitor-output"]');
    expect(output?.textContent).toContain('compiled');
    expect(output?.textContent).toContain('ready');
    expect(output?.textContent).toContain('… 3 more lines not delivered');
  });

  it('has no output block when nothing was delivered or cut', () => {
    const el = mount(notice([monitor()], true));
    expect(el.querySelector('button')).toBeNull();
  });

  it('says how many lines were cut when none were delivered', () => {
    const el = mount(notice([monitor({ omitted: 1 })], true));
    act(() => el.querySelector('button')!.click());
    expect(el.querySelector('[data-slot="monitor-output"]')?.textContent).toBe(
      '… 1 more line not delivered',
    );
  });
});

describe('a monitor notice that did not wake the agent', () => {
  it('is a quiet note, not a divider', () => {
    const el = mount(
      notice([monitor({ event: 'end', end: { kind: 'stopped' } })], false),
    );
    expect(el.querySelector('[data-slot="monitor-divider"]')).toBeNull();
    expect(el.querySelector('[data-slot="monitor-note"]')?.textContent).toBe(
      'dev server log · monitor m1 stopped',
    );
  });

  it('names how it ended when that was not a stop', () => {
    const el = mount(
      notice(
        [monitor({ event: 'end', end: { kind: 'exit', code: 1 } })],
        false,
      ),
    );
    expect(el.querySelector('[data-slot="monitor-note"]')?.textContent).toBe(
      'dev server log · monitor m1 · exit code 1',
    );
  });
});

describe('a monitor notice for a monitor that only started', () => {
  it.each([true, false])('draws nothing (woke=%s)', (woke) => {
    const el = mount(notice([monitor({ event: 'start' })], woke));
    expect(el.textContent).toBe('');
  });
});
