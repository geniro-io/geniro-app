import type { Meta, StoryObj } from '@storybook/react-vite';

import type { OpenMonitor } from '../autogenerated';
import { MonitorRows } from './monitor-list';

function monitor(over: Partial<OpenMonitor>): OpenMonitor {
  return {
    id: 'm1',
    description: 'CI on #42',
    command: 'gh pr checks 42 --watch',
    nodeId: null,
    callId: null,
    startedAt: new Date(Date.now() - 95_000).toISOString(),
    endsAt: new Date(Date.now() + 505_000).toISOString(),
    ...over,
  };
}

const NAMES: Record<string, string> = {
  reviewer: 'Reviewer',
  ops: 'Release Engineer',
};

const meta = {
  title: 'Chats/MonitorRows',
  component: MonitorRows,
  args: {
    monitors: [
      monitor({ nodeId: 'reviewer' }),
      monitor({
        id: 'm2',
        description: 'Preview sandbox deploy',
        command:
          'until curl -fsS https://preview.example.test/health; do sleep 10; done',
        nodeId: 'ops',
        startedAt: new Date(Date.now() - 12_000).toISOString(),
        endsAt: new Date(Date.now() + 1_788_000).toISOString(),
      }),
    ],
    agentNameOf: (nodeId: string) => NAMES[nodeId] ?? nodeId,
    onStop: () => {},
  },
  decorators: [
    (story) => (
      <div className="w-[22rem] rounded-md border border-border bg-popover">
        {story()}
      </div>
    ),
  ],
} satisfies Meta<typeof MonitorRows>;

export default meta;
type Story = StoryObj<typeof meta>;

export const TwoInAWorkflow: Story = {};

export const OneInAChat: Story = {
  args: { monitors: [monitor({})], agentNameOf: undefined },
};
