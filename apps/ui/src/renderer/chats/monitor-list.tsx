import { CircleStop, Radar } from 'lucide-react';

import type { OpenMonitor } from '../autogenerated';
import { ConfirmButton } from '../components/confirm-button';
import { formatElapsed, useSecondsTick } from './live-row';

/**
 * One running monitor: what it watches, its id, how long it has run, and its
 * command with the time its timeout stops it. Owns its clock, as `ShellRow`
 * does, so a tick re-renders the row and not the panel.
 */
function MonitorRow({
  monitor,
  agentName,
  onStop,
}: {
  monitor: OpenMonitor;
  /** Whose monitor this is, where the list mixes several agents' — a workflow's. */
  agentName: string | null;
  onStop?: (monitor: OpenMonitor) => void | Promise<void>;
}): React.JSX.Element {
  useSecondsTick();
  const now = Date.now();
  const started = Date.parse(monitor.startedAt);
  const ends = Date.parse(monitor.endsAt);
  return (
    <li data-slot="monitor-row" className="flex flex-col gap-0.5 text-xs">
      <div className="flex items-center gap-1.5">
        <Radar
          aria-hidden="true"
          className="size-3 shrink-0 -translate-y-px text-muted-foreground"
        />
        {agentName === null ? null : (
          <span
            data-slot="monitor-agent"
            className="shrink-0 text-[11px] text-muted-foreground"
            title={`Started by ${agentName}`}>
            {agentName}
          </span>
        )}
        <span className="min-w-0 flex-1 truncate" title={monitor.description}>
          {monitor.description}
        </span>
        <span className="shrink-0 text-[11px] text-muted-foreground">
          {monitor.id}
        </span>
        {Number.isNaN(started) ? null : (
          <span className="min-w-[3.25rem] shrink-0 text-right tabular-nums text-muted-foreground">
            {formatElapsed(now - started)}
          </span>
        )}
        {onStop === undefined ? null : (
          <ConfirmButton
            data-slot="monitor-stop"
            size="icon"
            variant="ghost"
            className="size-5 shrink-0 rounded-full text-muted-foreground hover:bg-destructive/10 hover:text-destructive data-[armed]:text-destructive-foreground data-[armed]:hover:bg-destructive/90 data-[armed]:hover:text-destructive-foreground"
            title={`Stop this monitor — press twice to confirm. The agent is told it was stopped (${monitor.description})`}
            aria-label={`Stop monitor ${monitor.id}`}
            confirmLabel={<CircleStop className="size-3.5" />}
            onConfirm={() => onStop(monitor)}>
            <CircleStop className="size-3.5" />
          </ConfirmButton>
        )}
      </div>
      <div
        data-slot="monitor-detail"
        className="flex min-w-0 items-center gap-1.5 pl-[18px] text-[11px] text-muted-foreground">
        <span
          className="min-w-0 flex-1 truncate font-mono"
          title={monitor.command}>
          {monitor.command}
        </span>
        {Number.isNaN(ends) ? null : (
          <span
            className="shrink-0 tabular-nums"
            title="When its timeout stops it">
            stops in {formatElapsed(ends - now)}
          </span>
        )}
      </div>
    </li>
  );
}

/** The monitors a thread's agents have running, each a row with its own Stop. */
export function MonitorRows({
  monitors,
  agentNameOf,
  onStop,
}: {
  monitors: readonly OpenMonitor[];
  /** Names the agent a row belongs to; absent in a 1:1 chat, which has one. */
  agentNameOf?: (nodeId: string) => string;
  onStop?: (monitor: OpenMonitor) => void | Promise<void>;
}): React.JSX.Element {
  return (
    <ul
      data-slot="monitor-rows"
      className="m-0 flex list-none flex-col gap-2 p-1.5">
      {monitors.map((monitor) => (
        <MonitorRow
          key={monitor.id}
          monitor={monitor}
          agentName={
            agentNameOf === undefined || monitor.nodeId === null
              ? null
              : agentNameOf(monitor.nodeId)
          }
          onStop={onStop}
        />
      ))}
    </ul>
  );
}
