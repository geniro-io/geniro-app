import { describe, expect, it, vi } from 'vitest';

import { AttachmentMediaType } from '../autogenerated';
import {
  type DecodedImage,
  type ImageCodec,
  MAX_ATTACHMENT_PIXELS,
  normalizeImage,
  scaleToFit,
} from './normalize-image';

/** A blob of a stated size — only `size` and the type are ever read here. */
function blobOf(bytes: number, type: string): Blob {
  return new Blob([new Uint8Array(bytes)], { type });
}

/**
 * A codec that decodes to a stated size and encodes to a stated one.
 *
 * `sizes` maps `<mediaType>@<quality>` to the byte count that rendering
 * produces, which is what lets a spec put the ladder in any state it likes —
 * PNG small enough, PNG too big, every JPEG rung too big — without an image
 * codec in the runtime.
 */
function fakeCodec(
  width: number,
  height: number,
  sizes: Record<string, number>,
): ImageCodec & { calls: string[]; closed: () => number } {
  const calls: string[] = [];
  let closes = 0;
  const decoded: DecodedImage = {
    width,
    height,
    source: 'bitmap',
    close: () => {
      closes += 1;
    },
  };
  return {
    calls,
    closed: () => closes,
    decode: () => Promise.resolve(decoded),
    encode: (image, w, h, mediaType, quality) => {
      const key = `${mediaType}@${quality ?? ''}`;
      calls.push(`${key} ${w}x${h}`);
      // The encoder is always handed the SAME decoded image back; a codec that
      // received someone else's handle would silently draw the wrong picture.
      expect(image).toBe(decoded);
      return Promise.resolve(blobOf(sizes[key] ?? 1, mediaType));
    },
  };
}

const MAX_BYTES = 5 * 1024 * 1024;

describe('scaleToFit', () => {
  it('answers null for an image already inside the ceiling', () => {
    // Null is the instruction to leave the ORIGINAL BYTES alone — a re-encode
    // of an image that needed none is pure loss, so this is not merely an
    // optimisation and the null has to be distinguishable from a same-size box.
    expect(scaleToFit(1900, 1200, 2000)).toBeNull();
    expect(scaleToFit(2000, 2000, 2000)).toBeNull();
  });

  it('scales the LONGER edge to the ceiling and keeps the ratio', () => {
    // The exact shot from the reported run: 2160x1886, the widest of the seven
    // that were over the line.
    expect(scaleToFit(2160, 1886, 2000)).toEqual({ width: 2000, height: 1746 });
    // Landscape, where the width is the offender and the height is already far
    // inside — the commonest shape of a pasted screenshot.
    expect(scaleToFit(2094, 968, 2000)).toEqual({ width: 2000, height: 925 });
  });

  it('never produces a zero edge', () => {
    // A 6000x1 strip scales to 0.33px tall, and a zero-width canvas throws
    // rather than degrading — so the whole paste would fail on an image the
    // provider would have taken.
    expect(scaleToFit(6000, 1, 2000)).toEqual({ width: 2000, height: 1 });
  });
});

describe('normalizeImage', () => {
  it('leaves an image inside the ceiling BYTE-IDENTICAL', async () => {
    const original = blobOf(400, 'image/jpeg');
    const codec = fakeCodec(1200, 900, {});
    const result = await normalizeImage(
      original,
      AttachmentMediaType.ImageJpeg,
      MAX_BYTES,
      codec,
    );

    expect(result.blob).toBe(original);
    expect(result.mediaType).toBe(AttachmentMediaType.ImageJpeg);
    // Not merely "the same size" — nothing was ENCODED at all.
    expect(codec.calls).toEqual([]);
  });

  it('resizes an over-2000px screenshot to PNG at the fitted size', async () => {
    // THE reported case. The provider serves a many-image conversation at a
    // 2000px per-image ceiling and states so in the refusal; the CLI caps its
    // own images there and geniro's attachments did not go through that code,
    // so a 2094px paste sat in the history failing every later turn.
    const codec = fakeCodec(2094, 968, { 'image/png@': 900_000 });
    const result = await normalizeImage(
      blobOf(300_000, 'image/png'),
      AttachmentMediaType.ImagePng,
      MAX_BYTES,
      codec,
    );

    expect(codec.calls).toEqual(['image/png@ 2000x925']);
    expect(result.mediaType).toBe(AttachmentMediaType.ImagePng);
    expect(result.blob.size).toBe(900_000);
  });

  it('falls back through the JPEG ladder when the PNG is still too heavy', async () => {
    const codec = fakeCodec(4000, 4000, {
      'image/png@': MAX_BYTES + 1,
      'image/jpeg@0.8': MAX_BYTES + 1,
      'image/jpeg@0.6': 2_000_000,
    });
    const result = await normalizeImage(
      blobOf(MAX_BYTES, 'image/png'),
      AttachmentMediaType.ImagePng,
      MAX_BYTES,
      codec,
    );

    // Stops at the first rung that fits — 0.4 is never asked for.
    expect(codec.calls).toEqual([
      'image/png@ 2000x2000',
      'image/jpeg@0.8 2000x2000',
      'image/jpeg@0.6 2000x2000',
    ]);
    expect(result.mediaType).toBe(AttachmentMediaType.ImageJpeg);
    expect(result.blob.size).toBe(2_000_000);
  });

  it('returns the SMALLEST rendering when nothing fits, rather than the first', async () => {
    // The caller's byte check is what refuses the paste, and its message names
    // the limit — so refusing with the biggest attempt would report a limit the
    // image had not actually failed at its best.
    const codec = fakeCodec(9000, 9000, {
      'image/png@': 40_000_000,
      'image/jpeg@0.8': 20_000_000,
      'image/jpeg@0.6': 12_000_000,
      'image/jpeg@0.4': 9_000_000,
    });
    const result = await normalizeImage(
      blobOf(MAX_BYTES, 'image/png'),
      AttachmentMediaType.ImagePng,
      MAX_BYTES,
      codec,
    );

    expect(result.mediaType).toBe(AttachmentMediaType.ImageJpeg);
    expect(result.blob.size).toBe(9_000_000);
  });

  it('closes the decoded image on every path, including a failing encode', async () => {
    // `createImageBitmap` holds decoded pixels off the JS heap; a paste loop
    // that never closes them leaks the whole screenshot per image.
    const ok = fakeCodec(3000, 3000, { 'image/png@': 10 });
    await normalizeImage(
      blobOf(10, 'image/png'),
      AttachmentMediaType.ImagePng,
      MAX_BYTES,
      ok,
    );
    expect(ok.closed()).toBe(1);

    const small = fakeCodec(100, 100, {});
    await normalizeImage(
      blobOf(10, 'image/png'),
      AttachmentMediaType.ImagePng,
      MAX_BYTES,
      small,
    );
    expect(small.closed()).toBe(1);

    const broken = fakeCodec(3000, 3000, {});
    broken.encode = vi.fn(() => Promise.reject(new Error('no canvas')));
    await expect(
      normalizeImage(
        blobOf(10, 'image/png'),
        AttachmentMediaType.ImagePng,
        MAX_BYTES,
        broken,
      ),
    ).rejects.toThrow('no canvas');
    expect(broken.closed()).toBe(1);
  });

  it('pins the ceiling to the number the provider stated', () => {
    // Read out of the CLI's own session record for the reported run:
    // "…exceed max allowed size for many-image requests: 2000 pixels". Not a
    // taste value — moving it up puts the failure back.
    expect(MAX_ATTACHMENT_PIXELS).toBe(2000);
  });
});
