import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  callTargetOf,
  notSentDeliveryIds,
  restoreIntoEmpty,
} from './not-sent-messages';

function row(
  kind: ChatItem['kind'],
  role: string | null,
  payload: unknown,
  seq = 1,
): ChatItem {
  return {
    id: `${kind}-${seq}-${JSON.stringify(payload)}`,
    runId: 'run-1',
    memberId: null,
    seq,
    kind,
    role,
    payload,
    createdAt: new Date(0).toISOString(),
  };
}

describe('notSentDeliveryIds', () => {
  it('pairs a "not sent" row with the user messages it names, and only those loaded', () => {
    const ids = notSentDeliveryIds([
      row('message', 'user', { text: 'a', deliveryId: 'd-1' }),
      row('message', 'user', { text: 'b', deliveryId: 'd-2' }),
      row('system', null, { message: 'x', unsentMessages: ['d-1', 'd-9'] }),
    ]);

    expect([...ids.keys()]).toEqual(['d-1']);
  });

  it('carries what the CLI said refusing a message, and null for a turn that ended first', () => {
    const ids = notSentDeliveryIds([
      row('message', 'user', { text: 'a', deliveryId: 'd-1' }),
      row('message', 'user', { text: 'b', deliveryId: 'd-2' }),
      row('system', null, { message: 'x', unsentMessages: ['d-1'] }),
      row('system', null, {
        message: 'y',
        unsentMessages: ['d-2'],
        unsentReason: 'turn already finishing',
      }),
    ]);

    expect([...ids]).toEqual([
      ['d-1', null],
      ['d-2', 'turn already finishing'],
    ]);
  });

  it('ignores an id relayed from the CLI and one an agent row carries', () => {
    const ids = notSentDeliveryIds([
      row('message', 'assistant', { text: 'a', deliveryId: 'd-1' }),
      row('message', 'user', { text: 'b', deliveryId: 'd-2' }),
      row('system', null, { message: 'x', unsentMessages: ['d-1'] }),
      row('system', null, {
        message: 'y',
        origin: 'cli',
        unsentMessages: ['d-2'],
      }),
    ]);

    expect(ids.size).toBe(0);
  });
});

describe('notSentDeliveryIds for call messages', () => {
  it('pairs a delivered message_agent row with the not-delivered row that retracts it', () => {
    const ids = notSentDeliveryIds([
      row('call_answer', null, {
        message: 'a',
        outcome: 'message',
        followUpId: 'f-1',
      }),
      row('call_answer', null, {
        message: 'b',
        outcome: 'message',
        followUpId: 'f-2',
      }),
      row('call_answer', null, {
        message: 'a',
        outcome: 'undelivered',
        followUpId: 'f-1',
      }),
    ]);

    expect([...ids.keys()]).toEqual(['f-1']);
  });
});

describe('callTargetOf', () => {
  it('answers the run itself for a message with no call', () => {
    expect(callTargetOf(row('message', 'user', { text: 'a' }, 5), [])).toBe(
      'run',
    );
  });

  it('addresses a callee message to the newest block of its call at or before it', () => {
    const earlierPass = row('call_started', null, { callId: 'call-1' }, 2);
    const thisPass = row('call_started', null, { callId: 'call-1' }, 8);
    const later = row('call_started', null, { callId: 'call-1' }, 20);
    const message = row(
      'message',
      'user',
      { text: 'use v2', callId: 'call-1', nodeId: 'helper' },
      9,
    );

    expect(callTargetOf(message, [earlierPass, thisPass, later])).toEqual({
      runId: 'run-1',
      memberId: 'helper',
      callId: 'call-1',
      blockId: thisPass.id,
    });
  });

  it('answers null for a callee message whose call is not loaded', () => {
    const message = row(
      'message',
      'user',
      { text: 'use v2', callId: 'call-1', nodeId: 'helper' },
      9,
    );

    expect(callTargetOf(message, [])).toBeNull();
  });
});

describe('restoreIntoEmpty', () => {
  it('fills an empty box and an empty stage, each on its own', () => {
    const restored = { text: 'do X instead', staged: ['pic'] };

    expect(restoreIntoEmpty({ text: '', staged: [] }, restored)).toEqual(
      restored,
    );
    expect(restoreIntoEmpty({ text: 'newer', staged: [] }, restored)).toEqual({
      text: 'newer',
      staged: ['pic'],
    });
    expect(restoreIntoEmpty({ text: '', staged: ['mine'] }, restored)).toEqual({
      text: 'do X instead',
      staged: ['mine'],
    });
  });
});
