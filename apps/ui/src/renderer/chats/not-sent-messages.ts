import { createContext } from 'react';

import type {
  ItemDto as ChatItem,
  SendMessageDtoImagesInner,
} from '../autogenerated';
import { randomId } from '../random-id';
import { messageAttachments } from './attachment-payload';
import { unsentMessageIds, unsentReason } from './system-payload';
import { payloadString } from './transcript-payload';
import type { StagedAttachment } from './use-attachments';
import type { CallTarget } from './use-call-message-queues';

/**
 * The user messages a turn accepted and then dropped before its agent took
 * them, as the transcript row that draws each one reads it.
 */
export interface NotSentMessages {
  /**
   * `deliveryId`s of the loaded user rows a "not sent" row names, each with
   * what the CLI said refusing it — null when its turn simply ended first.
   * Also the `followUpId`s of a caller's `message_agent` rows a later "not
   * delivered" row retracts (`callFollowUpId`).
   */
  unsent: ReadonlyMap<string, string | null>;
  /** Send one of those messages again, or null where this surface cannot. */
  resend: ((item: ChatItem) => void) | null;
}

/**
 * A context for `CardBackedRequestsContext`'s reason: the shells between the
 * screen and a message row are memoized on stable props.
 *
 * Null outside a provider, which is the safe default — no user row is marked,
 * and the "not sent" row itself stays on screen as the only record.
 */
export const NotSentMessagesContext = createContext<NotSentMessages | null>(
  null,
);

/**
 * The id a user message row was delivered under, or null for any other row.
 *
 * TWIN PARSER: the daemon stamps `deliveryId` on a mid-turn user message's
 * row — `ChatService.deliverIntoRunningTurn` and the graph executor's
 * `deliverFollowUp` / `deliverToCall` — and names the same id in a "not sent"
 * row's `unsentMessages` (`system-payload.ts`). Rename it there and here.
 */
export function userDeliveryId(item: ChatItem): string | null {
  return item.kind === 'message' && item.role === 'user'
    ? payloadString(item.payload, 'deliveryId')
    : null;
}

/**
 * The id a caller's `message_agent` row rode into the callee's turn with, on
 * the "delivered" row (`outcome: 'message'`) or on the "not delivered" row a
 * later drop wrote for it (`outcome: 'undelivered'`); null for any other row.
 *
 * TWIN PARSER: the daemon's `CallBroker.recordDeliveredMessage` and
 * `markMessageDropped` write `followUpId` on both rows. Rename it there too.
 */
export function callFollowUpId(
  item: ChatItem,
  outcome: 'message' | 'undelivered',
): string | null {
  return item.kind === 'call_answer' &&
    payloadString(item.payload, 'outcome') === outcome
    ? payloadString(item.payload, 'followUpId')
    : null;
}

/**
 * The delivery ids that pair a "not sent" row with a user message row in
 * `items`, each with the reason that row gives — and the call messages a "not
 * delivered" row retracts. Only paired ids count: a marker whose message is
 * outside the loaded window keeps drawing itself.
 */
export function notSentDeliveryIds(
  items: readonly ChatItem[],
): ReadonlyMap<string, string | null> {
  const named = new Map<string, string | null>();
  for (const item of items) {
    const retracted = callFollowUpId(item, 'undelivered');
    if (retracted !== null) {
      named.set(retracted, null);
    }
    if (item.kind === 'system') {
      const reason = unsentReason(item.payload);
      for (const id of unsentMessageIds(item.payload)) {
        named.set(id, reason);
      }
    }
  }
  const paired = new Map<string, string | null>();
  if (named.size === 0) {
    return paired;
  }
  for (const item of items) {
    const id = userDeliveryId(item) ?? callFollowUpId(item, 'message');
    if (id !== null && named.has(id)) {
      paired.set(id, named.get(id) ?? null);
    }
  }
  return paired;
}

/** A dropped message's words and pictures, read back from its own row. */
export async function unsentMessageContent(
  item: ChatItem,
  loadAttachment: (runId: string, attachmentId: string) => Promise<string>,
): Promise<{ text: string; images: SendMessageDtoImagesInner[] }> {
  const images = await Promise.all(
    messageAttachments(item.payload).map(async (attachment) => ({
      mediaType: attachment.mediaType,
      data: await loadAttachment(item.runId, attachment.id),
    })),
  );
  return { text: payloadString(item.payload, 'text') ?? '', images };
}

/** One of those pictures as a composer stages it, for `owner`'s draft. */
export function stagedFrom(
  image: SendMessageDtoImagesInner,
  owner: string | null,
): StagedAttachment {
  return {
    key: randomId(),
    mediaType: image.mediaType,
    data: image.data,
    preview: `data:${image.mediaType};base64,${image.data}`,
    name: 'image',
    owner,
  };
}

/**
 * The call a user message was addressed to: `'run'` for one to the run
 * itself, null for a call whose block is not loaded. Its block is the newest
 * `call_started` row for that call id at or before the message, since call ids
 * restart every pass of a run.
 */
export function callTargetOf(
  item: ChatItem,
  rows: readonly ChatItem[],
): CallTarget | 'run' | null {
  const callId = payloadString(item.payload, 'callId');
  if (callId === null) {
    return 'run';
  }
  const nodeId = payloadString(item.payload, 'nodeId') ?? item.nodeId;
  if (nodeId === null) {
    return null;
  }
  let blockId: string | null = null;
  for (const row of rows) {
    if (
      row.kind === 'call_started' &&
      row.seq <= item.seq &&
      payloadString(row.payload, 'callId') === callId
    ) {
      blockId = row.id;
    }
  }
  return blockId === null
    ? null
    : { runId: item.runId, nodeId, callId, blockId };
}

/**
 * What a composer holds after a message that did not go out is put back:
 * never over what was written since — text comes back only into an empty box,
 * images only onto an empty stage, each decided on its own.
 */
export function restoreIntoEmpty<Staged>(
  current: { text: string; staged: readonly Staged[] },
  restored: { text: string; staged: readonly Staged[] },
): { text: string; staged: readonly Staged[] } {
  return {
    text: current.text.length === 0 ? restored.text : current.text,
    staged: current.staged.length === 0 ? restored.staged : current.staged,
  };
}
