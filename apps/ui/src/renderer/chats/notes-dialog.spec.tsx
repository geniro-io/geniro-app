// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { TeamNote } from '../autogenerated';
import { NotesDialog, type ThreadNotesHandle } from './notes-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function note(seq: number, over: Partial<TeamNote> = {}): TeamNote {
  return {
    seq,
    kind: 'fact',
    text: `note ${seq}`,
    memberId: 'backend',
    conversationId: null,
    callId: null,
    createdAt: '2026-10-26T09:00:00.000Z',
    supersedes: null,
    supersededBy: null,
    ...over,
  };
}

const NAMES: Record<string, string> = {
  backend: 'Backend',
  manager: 'Manager',
};
const agentName = (memberId: string): string => NAMES[memberId] ?? memberId;

const LONG = Array.from({ length: 12 }, (_, i) => `line ${i + 1}`).join('\n');
const NOTES = [
  note(9, { kind: 'pitfall', text: LONG }),
  note(7, {
    kind: 'decision',
    memberId: 'manager',
    text: 'page by cursor',
    supersedes: 4,
  }),
  note(4, {
    kind: 'contract',
    callId: 'call-3',
    text: 'POST /orders',
    supersededBy: 7,
  }),
];

let root: Root | null = null;
let host: HTMLDivElement | null = null;

function draw({
  open = true,
  onClose = vi.fn(),
  onJump = vi.fn(),
  initialSelected = null,
  threadNotes = {
    runId: 'run-1',
    value: 'mine',
    onSave: vi.fn(async () => {}),
  },
  teamNotes = NOTES,
}: {
  open?: boolean;
  onClose?: () => void;
  onJump?: (seq: number) => void;
  initialSelected?: number | null;
  threadNotes?: ThreadNotesHandle | null;
  teamNotes?: TeamNote[];
} = {}): void {
  if (root === null) {
    host = document.createElement('div');
    document.body.appendChild(host);
    root = createRoot(host);
  }
  act(() => {
    root!.render(
      <NotesDialog
        open={open}
        onClose={onClose}
        threadNotes={threadNotes}
        teamNotes={teamNotes}
        agentName={agentName}
        initialSelected={initialSelected}
        onJump={onJump}
      />,
    );
  });
}

function mount(
  onClose = vi.fn(),
  onJump = vi.fn(),
  initialSelected: number | null = null,
) {
  draw({ onClose, onJump, initialSelected });
  return { onClose, onJump };
}

const dialog = (): HTMLElement => document.querySelector('[role="dialog"]')!;
const notesField = (): HTMLTextAreaElement | null =>
  document.querySelector<HTMLTextAreaElement>(
    'textarea[aria-label="Thread notes"]',
  );
const type = (text: string): void => {
  act(() => {
    const field = notesField()!;
    Object.getOwnPropertyDescriptor(
      HTMLTextAreaElement.prototype,
      'value',
    )!.set!.call(field, text);
    field.dispatchEvent(new Event('input', { bubbles: true }));
  });
};
const rows = (): string[] =>
  [...dialog().querySelectorAll('li')].map((li) => li.textContent ?? '');
const card = (seq: number): HTMLElement =>
  dialog().querySelector<HTMLElement>(`li[data-note-seq="${seq}"]`)!;
const body = (seq: number): HTMLElement =>
  card(seq).querySelector<HTMLElement>('[class*="break-words"]')!;
const heading = (seq: number): HTMLButtonElement =>
  card(seq).querySelector<HTMLButtonElement>('li > button')!;
const buttonIn = (
  element: HTMLElement,
  label: string,
): HTMLButtonElement | undefined =>
  [...element.querySelectorAll<HTMLButtonElement>('button')].find(
    (button) => button.textContent === label,
  );
const search = (text: string): void => {
  const input = dialog().querySelector<HTMLInputElement>(
    'input[aria-label="Search team notes"]',
  )!;
  act(() => {
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )!.set!;
    setter.call(input, text);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
};

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
});

describe('NotesDialog — team notes', () => {
  it('lists every note by its first three lines, with its author and call, and no Show more', () => {
    mount();
    expect(rows()).toHaveLength(3);
    expect(body(9).className).toContain('line-clamp-3');
    expect(heading(9).getAttribute('aria-expanded')).toBe('false');
    expect(dialog().textContent).not.toContain('Show more');
    expect(rows()[2]).toContain('Backend · Call 3');
    expect(dialog().textContent).toContain('3 notes');
  });

  it('shows a note whole on a press anywhere on it, and folds it back on a second press', () => {
    mount();
    act(() => body(9).click());
    expect(body(9).className).not.toContain('line-clamp');
    expect(heading(9).getAttribute('aria-expanded')).toBe('true');
    expect(card(9).dataset.selected).toBe('true');
    expect(buttonIn(card(9), 'Open in chat')).toBeDefined();

    act(() => heading(7).click());
    expect(body(9).className).toContain('line-clamp-3');
    expect(card(7).dataset.selected).toBe('true');

    act(() => heading(7).click());
    expect(body(7).className).toContain('line-clamp-3');
    expect(card(7).dataset.selected).toBeUndefined();
  });

  it('opens on the note it was opened for, whole', () => {
    mount(vi.fn(), vi.fn(), 7);
    expect(card(7).dataset.selected).toBe('true');
    expect(body(7).className).not.toContain('line-clamp');
    expect(body(9).className).toContain('line-clamp-3');
  });

  it('marks a superseded note as such in its heading', () => {
    mount();
    expect(heading(4).textContent).toContain('superseded');
    expect(heading(7).textContent).not.toContain('superseded');
  });

  it('moves from a superseded note to the one replacing it, and back, clearing a search that hides it', () => {
    mount(vi.fn(), vi.fn(), 4);
    act(() => buttonIn(card(4), 'Show the newer note')!.click());
    expect(card(7).dataset.selected).toBe('true');
    expect(card(4).dataset.selected).toBeUndefined();

    search('page by cursor');
    expect(rows()).toHaveLength(1);
    act(() => buttonIn(card(7), 'Show the note it replaces')!.click());
    expect(rows()).toHaveLength(3);
    expect(card(4).dataset.selected).toBe('true');
  });

  it('narrows by words in the text or the author, and says how many of all match', () => {
    mount();
    search('cursor');
    expect(rows()).toHaveLength(1);
    expect(rows()[0]).toContain('page by cursor');
    expect(dialog().textContent).toContain('1 of 3');

    search('backend');
    expect(rows()).toHaveLength(2);
  });

  it('says when nothing matches, and Clear filters brings every note back', () => {
    mount();
    search('nothing like this');
    expect(rows()).toHaveLength(0);
    expect(dialog().textContent).toContain('No notes match');
    act(() => {
      [...dialog().querySelectorAll<HTMLButtonElement>('button')]
        .find((button) => button.textContent === 'Clear filters')
        ?.click();
    });
    expect(rows()).toHaveLength(3);
  });

  it('closes itself and opens a picked note in the transcript from Open in chat', () => {
    const { onClose, onJump } = mount();
    act(() => heading(7).click());
    expect(onJump).not.toHaveBeenCalled();
    act(() => buttonIn(card(7), 'Open in chat')!.click());
    expect(onClose).toHaveBeenCalled();
    expect(onJump).toHaveBeenCalledExactlyOnceWith(7);
  });
});

describe('NotesDialog — the user’s own notes', () => {
  it('shows the user’s notes above the team notes, focused, and says the agent never sees them', () => {
    mount();
    expect(notesField()?.value).toBe('mine');
    expect(document.activeElement).toBe(notesField());
    const mine = dialog().querySelector('section[aria-label="Your notes"]')!;
    const team = dialog().querySelector('section[aria-label="Team notes"]')!;
    expect(
      mine.compareDocumentPosition(team) & Node.DOCUMENT_POSITION_FOLLOWING,
    ).toBeTruthy();
    expect(
      mine.querySelector('[data-slot="thread-notes-hint"]')?.textContent,
    ).toContain('never sent to the agent');
  });

  it('puts the focus on the team note it was opened on, not the field', () => {
    mount(vi.fn(), vi.fn(), 7);
    expect(notesField()).not.toBeNull();
    expect(document.activeElement).toBe(heading(7));
  });

  it('draws only the field, in a small popup, for a thread whose agents wrote no team notes', () => {
    draw({ teamNotes: [] });
    expect(notesField()?.value).toBe('mine');
    expect(
      dialog().querySelector('section[aria-label="Team notes"]'),
    ).toBeNull();
    expect(
      dialog().querySelector<HTMLElement>('[tabindex="-1"]')!.className,
    ).toContain('max-w-lg');
  });

  it('draws no field when it is not handed a way to save', () => {
    draw({ threadNotes: null });
    expect(notesField()).toBeNull();
    expect(rows()).toHaveLength(3);
  });

  it('saves the owed text when the popup is closed before the pause ends', () => {
    vi.useFakeTimers();
    try {
      const onSave = vi.fn(async () => {});
      const threadNotes = { runId: 'run-1', value: null, onSave };
      draw({ threadNotes });
      type('typed then closed');
      expect(onSave).not.toHaveBeenCalled();

      draw({ threadNotes, open: false });

      expect(notesField()).toBeNull();
      expect(onSave).toHaveBeenCalledWith('typed then closed');
    } finally {
      vi.useRealTimers();
    }
  });

  it('saves a pending draft to the run it was typed in when the popup moves to another', async () => {
    vi.useFakeTimers();
    try {
      const saveA = vi.fn(async () => {});
      const saveB = vi.fn(async () => {});
      draw({ threadNotes: { runId: 'a', value: null, onSave: saveA } });
      type('typed in a');

      draw({ threadNotes: { runId: 'b', value: null, onSave: saveB } });
      await act(async () => {
        await vi.advanceTimersByTimeAsync(700);
      });

      expect(saveA).toHaveBeenCalledWith('typed in a');
      expect(saveB).not.toHaveBeenCalled();
      expect(notesField()?.value).toBe('');
    } finally {
      vi.useRealTimers();
    }
  });
});
