import { NotebookPen, Search } from 'lucide-react';
import { useEffect, useRef, useState } from 'react';

import type { TeamNote } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { cn } from '../components/ui/utils';
import { teamNoteAuthor } from './team-note-author';
import { TeamNoteEntry } from './team-note-entry';
import { TeamNotesFilter, useTeamNoteFilters } from './team-note-filters';
import { ThreadNotes } from './thread-notes';

/** The user's own notes on the thread, and how to store a new text. */
export interface ThreadNotesHandle {
  /** The run they belong to — keys the field, so a draft never outlives it. */
  runId: string;
  value: string | null;
  onSave: (text: string) => Promise<void>;
}

/**
 * Every note of the thread in one popup: the user's own notes, then the
 * agents' team notes of a team run. Each team note shows its first lines;
 * a press picks it and shows it whole, with the way to its row in the
 * transcript. The kind and author filters, plus a search over the words.
 */
export function NotesDialog({
  open,
  onClose,
  threadNotes,
  teamNotes,
  agentName,
  initialSelected = null,
  onJump,
}: {
  open: boolean;
  onClose: () => void;
  /** Absent draws no field — the popup never invents a write path. */
  threadNotes: ThreadNotesHandle | null;
  /** Newest first, as the daemon lists them. */
  teamNotes: readonly TeamNote[];
  agentName: (memberId: string) => string;
  /** The team note picked on open — the one pressed in the transcript. */
  initialSelected?: number | null;
  /** Open a team note's row in the transcript; the popup closes first. */
  onJump?: (seq: number) => void;
}): React.JSX.Element {
  const filters = useTeamNoteFilters(teamNotes, agentName);
  const [query, setQuery] = useState('');
  const [selected, setSelected] = useState<number | null>(initialSelected);
  const listRef = useRef<HTMLUListElement | null>(null);
  const openedOn = useRef<HTMLElement | null>(null);
  const attachList = (element: HTMLUListElement | null): void => {
    listRef.current = element;
    if (
      openedOn.current === null &&
      element !== null &&
      initialSelected !== null
    ) {
      openedOn.current = element.querySelector<HTMLElement>(
        `[data-note-seq="${initialSelected}"] > button`,
      );
    }
  };
  const words = query.trim().toLowerCase();
  const matching = teamNotes.filter(
    (note) =>
      filters.passes(note) &&
      (words === '' ||
        `${note.text}\n${teamNoteAuthor(note, agentName)}\n${note.kind}`
          .toLowerCase()
          .includes(words)),
  );
  const clear = (): void => {
    filters.clear();
    setQuery('');
  };
  const select = (seq: number): void => {
    if (seq === selected) {
      setSelected(null);
      return;
    }
    if (!matching.some((note) => note.seq === seq)) {
      clear();
    }
    setSelected(seq);
  };
  const jump =
    onJump === undefined
      ? undefined
      : (seq: number): void => {
          onClose();
          onJump(seq);
        };
  const selectedListed = teamNotes.some((note) => note.seq === selected);
  useEffect(() => {
    if (selected === null || !selectedListed) {
      return;
    }
    listRef.current
      ?.querySelector(`[data-note-seq="${selected}"]`)
      ?.scrollIntoView?.({ block: 'nearest' });
  }, [selected, selectedListed]);
  const hasTeamNotes = teamNotes.length > 0;

  return (
    <Dialog
      open={open}
      onClose={onClose}
      initialFocus={initialSelected === null ? undefined : openedOn}
      title={
        <span className="flex items-center gap-2">
          <NotebookPen
            aria-hidden
            className="size-4 shrink-0 text-muted-foreground"
          />
          Notes
        </span>
      }
      className={cn(
        hasTeamNotes ? 'h-[92vh] w-[min(96vw,56rem)] max-w-none' : 'max-w-lg',
      )}>
      <div className="flex h-full min-h-0 flex-col gap-4">
        {threadNotes === null ? null : (
          <section
            aria-label="Your notes"
            className="flex shrink-0 flex-col gap-2">
            {hasTeamNotes ? (
              <h3 className="m-0 text-xs font-medium text-muted-foreground">
                Your notes
              </h3>
            ) : null}
            {/* Mounted only while open, so closing the popup is the field's
                way out: its owed text is saved then. */}
            <ThreadNotes
              key={threadNotes.runId}
              notes={threadNotes.value}
              onSave={threadNotes.onSave}
              autoFocus={initialSelected === null}
            />
            <p
              data-slot="thread-notes-hint"
              className="m-0 text-xs text-muted-foreground">
              Only you see these — they are never sent to the agent. Saved as
              you type.
            </p>
          </section>
        )}
        {hasTeamNotes ? (
          <section
            aria-label="Team notes"
            className="flex min-h-0 flex-1 flex-col gap-2">
            <h3 className="m-0 text-xs font-medium text-muted-foreground">
              Team notes
            </h3>
            <div className="flex min-w-0 items-center gap-2">
              <div className="relative min-w-0 flex-1">
                <Search
                  className="pointer-events-none absolute top-1/2 left-2.5 size-4 -translate-y-1/2 text-muted-foreground"
                  aria-hidden
                />
                <Input
                  type="search"
                  value={query}
                  onChange={(event) => setQuery(event.target.value)}
                  placeholder="Search team notes"
                  aria-label="Search team notes"
                  className="pl-8"
                />
              </div>
              <TeamNotesFilter filters={filters} className="size-9" />
              <span className="shrink-0 text-xs whitespace-nowrap text-muted-foreground tabular-nums">
                {matching.length === teamNotes.length
                  ? `${teamNotes.length} ${teamNotes.length === 1 ? 'note' : 'notes'}`
                  : `${matching.length} of ${teamNotes.length}`}
              </span>
            </div>
            {matching.length === 0 ? (
              <div className="flex flex-col items-center gap-2 py-12 text-sm text-muted-foreground">
                <span>No notes match</span>
                <Button type="button" variant="ghost" size="sm" onClick={clear}>
                  Clear filters
                </Button>
              </div>
            ) : (
              <ul
                ref={attachList}
                className="m-0 flex min-h-0 flex-1 list-none flex-col gap-2 overflow-y-auto p-0">
                {matching.map((note) => (
                  <TeamNoteEntry
                    key={note.seq}
                    note={note}
                    author={teamNoteAuthor(note, agentName)}
                    selected={note.seq === selected}
                    onSelect={select}
                    onJump={jump}
                  />
                ))}
              </ul>
            )}
          </section>
        ) : null}
      </div>
    </Dialog>
  );
}
