// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import {
  afterEach,
  beforeEach,
  describe,
  expect,
  it,
  type Mock,
  vi,
} from 'vitest';

import type {
  PluginBlock,
  PluginDetailDto,
  PluginRunResult,
  PluginSummary,
} from '../autogenerated';
import { type PluginBlocksApi, PluginBlockSection } from './plugin-blocks';
import { ThreadUiMemoryContext } from './thread-ui-memory';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const AT = '2026-11-25T10:00:00.000Z';

/** The generated type narrows `data` to null; the wire carries any JSON. */
function resultOf(
  data: unknown,
  overrides: Partial<PluginRunResult> = {},
): PluginRunResult {
  return {
    at: AT,
    data,
    error: null,
    exitCode: 0,
    stderrTail: '',
    ...overrides,
  } as PluginRunResult;
}

const RESULT = resultOf({ title: 'Rain at noon' });

const FAILED = resultOf(null, {
  error: 'exit 2: boom',
  exitCode: 2,
  stderrTail: 'trace line',
});

const DETAIL: PluginDetailDto = {
  slug: 'weather',
  text: 'name: Weather v2',
  approvedText: 'name: Weather',
  hash: 'h2',
  state: 'changed',
  error: null,
  path: '/Users/me/plugins/weather.plugin.yaml',
};

const SUMMARY: PluginSummary = {
  slug: 'weather',
  name: 'Weather',
  enabled: true,
  folders: [],
  refreshMinutes: 5,
  command: 'node weather.js',
  buttons: [],
  state: 'approved',
  error: null,
  hash: 'h2',
  path: '/Users/me/plugins/weather.plugin.yaml',
  lastRunAt: AT,
};

const TITLE_VIEW = [
  { id: 'root', component: 'Column', children: ['title'] },
  { id: 'title', component: 'Text', text: { '@path': '/data/title' } },
];

const BUTTON_VIEW = [
  {
    id: 'root',
    component: 'Column',
    children: ['title', 'publish', 'restart'],
  },
  { id: 'title', component: 'Text', text: { '@path': '/data/title' } },
  {
    id: 'publish',
    component: 'Button',
    child: 'publish_label',
    action: { event: { name: 'publish', context: {} } },
  },
  { id: 'publish_label', component: 'Text', text: 'Publish' },
  {
    id: 'restart',
    component: 'Button',
    child: 'restart_label',
    action: { event: { name: 'restart', context: {} } },
  },
  { id: 'restart_label', component: 'Text', text: 'Restart' },
];

const PUBLISH = { id: 'publish', command: 'make publish', confirm: true };
const RESTART = { id: 'restart', command: 'make restart', confirm: false };

function blockOf(overrides: Partial<PluginBlock> = {}): PluginBlock {
  return {
    slug: 'weather',
    name: 'Weather',
    state: 'approved',
    folder: '/Users/me/proj',
    view: TITLE_VIEW,
    refreshMinutes: 5,
    buttons: [],
    result: null,
    ...overrides,
  };
}

interface FakeApi {
  runPlugin: Mock<PluginBlocksApi['runPlugin']>;
  pressPluginButton: Mock<PluginBlocksApi['pressPluginButton']>;
  readPlugin: Mock<PluginBlocksApi['readPlugin']>;
  approvePlugin: Mock<PluginBlocksApi['approvePlugin']>;
}

function fakeApi(
  run: PluginBlocksApi['runPlugin'] = async () => RESULT,
): FakeApi {
  return {
    runPlugin: vi.fn<PluginBlocksApi['runPlugin']>(run),
    pressPluginButton: vi.fn<PluginBlocksApi['pressPluginButton']>(
      async () => ({
        exitCode: 0,
        outputTail: '',
        error: null,
      }),
    ),
    readPlugin: vi.fn<PluginBlocksApi['readPlugin']>(async () => DETAIL),
    approvePlugin: vi.fn<PluginBlocksApi['approvePlugin']>(async () => SUMMARY),
  };
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  localStorage.clear();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function renderBlock(
  block: PluginBlock,
  api: FakeApi,
  onAsk: (text: string) => void = vi.fn(),
): void {
  act(() => {
    root.render(
      <ThreadUiMemoryContext.Provider value="run-1">
        <PluginBlockSection
          block={block}
          api={api}
          runId="run-1"
          onAsk={onAsk}
        />
      </ThreadUiMemoryContext.Provider>,
    );
  });
}

const flush = (): Promise<void> =>
  act(async () => {
    await new Promise((resolve) => {
      setTimeout(resolve, 0);
    });
  });

function click(element: HTMLElement): void {
  act(() => {
    element.click();
  });
}

function buttonNamed(text: string): HTMLButtonElement {
  const found = [
    ...document.querySelectorAll<HTMLButtonElement>('button'),
  ].find((button) => button.textContent?.trim() === text);
  if (found === undefined) {
    throw new Error(`no "${text}" button`);
  }
  return found;
}

function buttonLabelled(label: string): HTMLButtonElement {
  const found = document.querySelector<HTMLButtonElement>(
    `[aria-label="${label}"]`,
  );
  if (found === null) {
    throw new Error(`no button labelled "${label}"`);
  }
  return found;
}

function toggle(): HTMLButtonElement {
  const found = container.querySelector<HTMLButtonElement>(
    '[data-slot="panel-section-toggle"]',
  );
  if (found === null) {
    throw new Error('no fold toggle');
  }
  return found;
}

describe('PluginBlockSection', () => {
  it('runs an approved block on mount and draws its data through the view', async () => {
    const api = fakeApi();
    renderBlock(blockOf({ view: TITLE_VIEW }), api);
    await flush();

    expect(api.runPlugin).toHaveBeenCalledTimes(1);
    expect(api.runPlugin).toHaveBeenCalledWith({
      slug: 'weather',
      pluginRunRequestDto: { runId: 'run-1', force: false },
    });
    expect(container.textContent).toContain('Rain at noon');
  });

  it('shows the loading state until the run answers', async () => {
    const api = fakeApi(() => new Promise<PluginRunResult>(() => {}));
    renderBlock(blockOf({ view: TITLE_VIEW }), api);
    await flush();

    expect(
      container.querySelector('[data-slot="plugin-loading"]')?.textContent,
    ).toContain('Loading…');
  });

  it('draws a failed run as "The command failed", its error, and Try again forces a run', async () => {
    const api = fakeApi();
    api.runPlugin.mockResolvedValueOnce(FAILED);
    renderBlock(blockOf({ view: TITLE_VIEW }), api);
    await flush();

    expect(container.textContent).toContain('The command failed');
    expect(container.textContent).toContain('exit 2: boom');
    expect(container.textContent).toContain('trace line');

    click(buttonNamed('Try again'));
    await flush();

    expect(api.runPlugin).toHaveBeenLastCalledWith({
      slug: 'weather',
      pluginRunRequestDto: { runId: 'run-1', force: true },
    });
    expect(container.textContent).toContain('Rain at noon');
  });

  it('draws "Nothing to show" for a command whose list is empty', async () => {
    const api = fakeApi();
    api.runPlugin.mockResolvedValueOnce(resultOf([]));
    renderBlock(blockOf({ view: TITLE_VIEW }), api);
    await flush();

    expect(container.textContent).toContain('Nothing to show');
  });

  it('does not run a changed block, says so, and Review reads the file', async () => {
    const api = fakeApi();
    renderBlock(blockOf({ state: 'changed' }), api);
    await flush();

    expect(api.runPlugin).not.toHaveBeenCalled();
    expect(container.textContent).toContain(
      'Plugin file changed · not run since',
    );

    click(buttonNamed('Review'));
    await flush();

    expect(api.readPlugin).toHaveBeenCalledWith({ slug: 'weather' });
    expect(document.body.textContent).toContain('Review plugin Weather');
  });

  it('refreshes forced from the refresh button', async () => {
    const api = fakeApi();
    renderBlock(blockOf({ view: TITLE_VIEW }), api);
    await flush();

    click(buttonLabelled('Refresh Weather'));
    await flush();

    expect(api.runPlugin).toHaveBeenLastCalledWith({
      slug: 'weather',
      pluginRunRequestDto: { runId: 'run-1', force: true },
    });
  });

  it('asks before a confirm button runs, then presses with the data time the user saw', async () => {
    const api = fakeApi();
    renderBlock(
      blockOf({ view: BUTTON_VIEW, buttons: [PUBLISH, RESTART] }),
      api,
    );
    await flush();

    click(buttonNamed('Publish'));
    expect(api.pressPluginButton).not.toHaveBeenCalled();
    expect(document.body.textContent).toContain('Run this command?');
    expect(document.body.textContent).toContain('make publish');

    click(buttonNamed('Run'));
    await flush();

    expect(api.pressPluginButton).toHaveBeenCalledTimes(1);
    expect(api.pressPluginButton).toHaveBeenCalledWith({
      slug: 'weather',
      buttonId: 'publish',
      pluginPressRequestDto: { runId: 'run-1', dataAt: AT },
    });
  });

  it('presses an unmarked button at once, with no confirmation', async () => {
    const api = fakeApi();
    renderBlock(
      blockOf({ view: BUTTON_VIEW, buttons: [PUBLISH, RESTART] }),
      api,
    );
    await flush();

    click(buttonNamed('Restart'));
    await flush();

    expect(document.querySelector('[role="dialog"]')).toBeNull();
    expect(api.pressPluginButton).toHaveBeenCalledWith({
      slug: 'weather',
      buttonId: 'restart',
      pluginPressRequestDto: { runId: 'run-1', dataAt: AT },
    });
  });

  it('puts its name, folder and data into the message box with Ask', async () => {
    const onAsk = vi.fn<(text: string) => void>();
    const api = fakeApi();
    renderBlock(blockOf({ view: TITLE_VIEW }), api, onAsk);
    await flush();

    click(buttonLabelled('Ask about Weather'));

    expect(onAsk).toHaveBeenCalledTimes(1);
    const text = onAsk.mock.calls[0]?.[0] ?? '';
    expect(text).toContain('Plugin "Weather" in /Users/me/proj');
    expect(text).toContain('"title": "Rain at noon"');
  });

  it('folds the body and remembers the fold for this thread only', async () => {
    const api = fakeApi();
    renderBlock(blockOf({ view: TITLE_VIEW }), api);
    await flush();
    expect(
      container.querySelector('[data-slot="plugin-block"]'),
    ).not.toBeNull();

    click(toggle());

    expect(container.querySelector('[data-slot="plugin-block"]')).toBeNull();
    expect(toggle().getAttribute('aria-expanded')).toBe('false');
    expect(
      JSON.parse(localStorage.getItem('geniro.threadUi.run-1') ?? '{}'),
    ).toEqual({ 'plugin:weather:open': false });
  });
});
