import { useEffect, useState } from 'react';

import type { PluginDetailDto, PluginsApi } from '../autogenerated';
import { ErrorText } from '../components/error-text';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { describeDaemonError } from '../daemon-api';
import { DiffView } from './diff-view';

/**
 * A plugin file changed since it was approved: the approved text against
 * the current one, and Approve, which approves exactly the text shown — a
 * file that moves on meanwhile is refused and read again.
 */
export function PluginReviewDialog({
  open,
  slug,
  name,
  api,
  onClose,
}: {
  open: boolean;
  slug: string;
  name: string;
  api: Pick<PluginsApi, 'readPlugin' | 'approvePlugin'>;
  onClose: () => void;
}): React.JSX.Element {
  const [detail, setDetail] = useState<PluginDetailDto | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [reads, setReads] = useState(0);

  useEffect(() => {
    if (!open) {
      return;
    }
    let cancelled = false;
    setDetail(null);
    api
      .readPlugin({ slug })
      .then((read) => {
        if (!cancelled) {
          setDetail(read);
        }
      })
      .catch((err: unknown) => {
        if (!cancelled) {
          setError(describeDaemonError(err));
        }
      });
    return () => {
      cancelled = true;
    };
  }, [open, slug, api, reads]);

  const approve = async (): Promise<void> => {
    if (detail === null) {
      return;
    }
    setBusy(true);
    setError(null);
    try {
      await api.approvePlugin({
        slug,
        pluginApproveRequestDto: { hash: detail.hash },
      });
      onClose();
    } catch (err) {
      setError(describeDaemonError(err));
      setReads((count) => count + 1);
    } finally {
      setBusy(false);
    }
  };

  return (
    <Dialog
      open={open}
      onClose={busy ? () => undefined : onClose}
      title={`Review plugin ${name}`}>
      <div className="flex flex-col gap-3">
        <p className="text-sm text-muted-foreground">
          The plugin file changed since you approved it, so nothing of it runs.
          {detail?.approvedText === null
            ? ' It was never approved.'
            : ' Red is what you approved, green is the file now.'}
        </p>
        {detail === null ? (
          error === null ? (
            <p className="text-xs text-muted-foreground">Reading the file…</p>
          ) : null
        ) : (
          <div className="max-h-[50vh] overflow-auto">
            <DiffView oldText={detail.approvedText} newText={detail.text} />
          </div>
        )}
        {detail?.error ? <ErrorText>{detail.error}</ErrorText> : null}
        {error === null ? null : <ErrorText>{error}</ErrorText>}
        <div className="flex justify-end gap-2">
          <Button
            type="button"
            variant="outline"
            disabled={busy}
            onClick={onClose}>
            Cancel
          </Button>
          <Button
            type="button"
            disabled={busy || detail === null || detail.state === 'invalid'}
            onClick={() => void approve()}>
            {busy ? 'Approving…' : 'Approve'}
          </Button>
        </div>
      </div>
    </Dialog>
  );
}
