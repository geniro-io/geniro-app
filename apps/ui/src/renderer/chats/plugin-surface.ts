import type { SurfaceDto } from '../autogenerated';
import type { SurfacePressPhase, SurfaceState } from './use-surface';

/** One component of a plugin view, as its file holds it. */
type ViewComponent = Record<string, unknown>;

/**
 * A plugin's view and the command's data as the card renderer reads a
 * surface: the view is the components, the data model is `{data}`, and
 * nothing the user types or an agent writes exists. Every field is filled so
 * a field `show_ui` adds to `SurfaceDto` fails type-checking here.
 */
export function pluginSurfaceOf(
  slug: string,
  view: readonly ViewComponent[],
  data: unknown,
): SurfaceDto {
  return {
    surfaceId: `plugin:${slug}`,
    version: 1,
    title: null,
    components: [...view],
    dataModel: { data },
    drafts: {},
    agentWrites: [],
    overriddenDrafts: [],
    oneShotPressed: [],
    removed: false,
    publisher: { memberId: null, agentLabel: null },
    media: {},
  };
}

/** The plugin button a view Button presses: the name of its event, or null. */
export function pluginButtonOf(
  view: readonly ViewComponent[],
  componentId: string,
): string | null {
  const component = view.find((entry) => entry.id === componentId);
  const action = component?.action;
  if (typeof action !== 'object' || action === null) {
    return null;
  }
  const event = (action as { event?: unknown }).event;
  if (typeof event !== 'object' || event === null) {
    return null;
  }
  const name = (event as { name?: unknown }).name;
  return typeof name === 'string' ? name : null;
}

/** Whether a link from command output may open: the web only, never a local path. */
export function opensPluginLink(url: string): boolean {
  return /^https?:\/\//i.test(url.trim());
}

/**
 * The surface state a plugin block draws with: its data, the press phase of
 * the button running, and a press that maps a view Button to its plugin
 * button. No values are ever set and no media read.
 */
export function pluginSurfaceState(
  surface: SurfaceDto,
  data: unknown,
  phase: SurfacePressPhase,
  onPress: (componentId: string) => void,
): SurfaceState {
  return {
    surface,
    error: null,
    model: { data },
    highlighted: new Set(),
    phase,
    setValue: () => undefined,
    press: (componentId) => onPress(componentId),
    readMedia: () =>
      Promise.reject(new Error('a plugin block shows no stored media')),
  };
}
