import { describe, expect, it } from 'vitest';

import type { RunMonitor, RunProcess, RunProcessTree } from '../autogenerated';
import { groupDetached, groupMonitors, groupProcesses } from './process-groups';

function proc(
  pid: number,
  depth: number,
  name: string,
  over: Partial<RunProcess> = {},
): RunProcess {
  return {
    pid,
    ppid: 1,
    depth,
    link: depth === 0 ? 'root' : 'child',
    name,
    args: name,
    cpuPercent: 1,
    rssBytes: 100,
    elapsedSeconds: 30,
    ...over,
  };
}

function tree(processes: RunProcess[]): RunProcessTree {
  return {
    sessionKey: 'run-1',
    nodeId: null,
    conversationId: null,
    agentKind: 'claude',
    cwd: '/p',
    rootPid: 100,
    processes,
    cpuPercent: 0,
    rssBytes: 0,
  };
}

describe('groupProcesses', () => {
  it('splits a CLI into itself, the servers it launched, and the commands it ran', () => {
    const groups = groupProcesses(
      tree([
        proc(100, 0, 'claude'),
        proc(101, 1, 'codegraph'),
        proc(102, 2, 'node'),
        proc(103, 1, 'zsh', {
          args: "/bin/zsh -c source snap.sh && eval 'sleep 900' < /dev/null",
        }),
        proc(104, 2, 'sleep', { args: 'sleep 900' }),
        proc(105, 1, 'npm', { args: 'npm exec @playwright/mcp@latest' }),
        proc(106, 2, 'playwright-mcp'),
      ]),
    );
    expect(groups.map((g) => [g.role, g.label, g.size, g.rssBytes])).toEqual([
      ['cli', 'claude', 1, 100],
      ['server', 'codegraph', 2, 200],
      // A package runner is named by the binary it runs.
      ['server', 'playwright-mcp', 2, 200],
      // A shell is named by the command under it, not by itself, and its
      // wrapper is not counted — but its memory still is.
      ['command', 'sleep 900', 1, 200],
    ]);
  });

  it('names a shell running only builtins by what it was told to eval', () => {
    const [, command] = groupProcesses(
      tree([
        proc(100, 0, 'claude'),
        proc(103, 1, 'zsh', { args: "zsh -c eval 'while true; do :; done'" }),
      ]),
    );
    expect(command?.label).toBe('while true; do :; done');
  });

  it('counts a process that outlived its shell as a detached command', () => {
    const [, orphan] = groupProcesses(
      tree([
        proc(100, 0, 'claude'),
        proc(150, 1, 'next', { link: 'group', args: 'next dev --turbo' }),
      ]),
    );
    expect([orphan?.role, orphan?.detached, orphan?.label]).toEqual([
      'command',
      true,
      'next dev --turbo',
    ]);
  });
});

describe('groupDetached', () => {
  it('makes each top process one command of its own, and keeps what is under it with it', () => {
    const groups = groupDetached([
      proc(500, 0, 'node', { args: 'node web.js' }),
      proc(501, 1, 'next-server', { ppid: 500 }),
      proc(600, 0, 'node', { args: 'node api.js' }),
    ]);
    expect(
      groups.map((group) => [group.key, group.label, group.processes.length]),
    ).toEqual([
      ['detached:500', 'node web.js', 2],
      ['detached:600', 'node api.js', 1],
    ]);
    expect(
      groups.every((group) => group.detached && group.role === 'command'),
    ).toBe(true);
  });
});

describe('groupMonitors', () => {
  const monitor: RunMonitor = {
    id: 'm1',
    description: 'dev server log',
    command: 'tail -f /tmp/dev.log',
    startedAt: '2026-10-04T11:58:00.000Z',
    endsAt: '2026-10-04T12:08:00.000Z',
    pid: 700,
    processes: [proc(700, 0, 'zsh'), proc(701, 1, 'tail')],
    cpuPercent: 7.5,
    rssBytes: 9_000,
  };

  it('makes one row of a monitor, carrying its own totals and its clock', () => {
    const [group] = groupMonitors([monitor], '2026-10-04T12:00:00.000Z');
    expect(group).toMatchObject({
      key: 'monitor:m1',
      role: 'command',
      label: 'tail -f /tmp/dev.log',
      size: 1,
      cpuPercent: 7.5,
      rssBytes: 9_000,
      elapsedSeconds: 120,
      detached: false,
      monitor: {
        id: 'm1',
        description: 'dev server log',
        remainingSeconds: 480,
      },
    });
    expect(group?.processes.map((p) => p.pid)).toEqual([700, 701]);
  });

  it('reports no clock when a time will not parse, rather than inventing one', () => {
    const [group] = groupMonitors(
      [{ ...monitor, startedAt: 'soon', endsAt: 'later' }],
      '2026-10-04T12:00:00.000Z',
    );
    expect(group?.elapsedSeconds).toBeNull();
    expect(group?.monitor?.remainingSeconds).toBeNull();
  });

  it('gives a process group no monitor', () => {
    expect(groupDetached([proc(500, 0, 'node')])[0]?.monitor).toBeNull();
  });
});
