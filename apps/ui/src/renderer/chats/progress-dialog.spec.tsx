describe('stageTimeAgo', () => {
  const now = Date.parse('2026-10-27T12:00:00Z');
  it('says how long ago, and leaves "just now" as it is', () => {
    expect(stageTimeAgo('2026-10-27T11:55:00Z', now)).toBe('5m ago');
    expect(stageTimeAgo('2026-10-27T09:00:00Z', now)).toBe('3h ago');
    expect(stageTimeAgo('2026-10-27T11:59:50Z', now)).toBe('just now');
  });
});

describe('ProgressChip', () => {
  const chip = (): HTMLButtonElement | null =>
    container.querySelector<HTMLButtonElement>('[data-slot="progress-chip"]');
  const figure = (slot: string): string | null =>
    chip()?.querySelector(`[data-slot="${slot}"]`)?.textContent ?? null;

  it('draws nothing for a read-only thread with no stages, goals or outcome', () => {
    render(<ProgressChip goals={noGoals()} stages={null} onOpen={() => {}} />);
    expect(chip()).toBeNull();
  });

  it('stands on a chat with no goals yet, so the user can set them', () => {
    render(
      <ProgressChip
        goals={noGoals({ actions: actions() })}
        stages={undefined}
        onOpen={() => {}}
      />,
    );
    expect(chip()?.getAttribute('aria-label')).toBe('Progress · No goals yet');
    expect(chip()?.textContent).toBe('Set goals');
    expect(chip()?.querySelector('svg')).not.toBeNull();
  });

  it('invites goals beside a team run’s stage, and never on a read-only thread', () => {
    render(
      <ProgressChip
        goals={noGoals({ actions: actions() })}
        stages={progress()}
        onOpen={() => {}}
      />,
    );
    expect(chip()?.textContent).toBe('2/4Set goals');
    act(() =>
      root?.render(
        <ProgressChip
          goals={noGoals()}
          stages={progress()}
          onOpen={() => {}}
        />,
      ),
    );
    expect(chip()?.textContent).toBe('2/4');
  });

  it('shows the stage position and, once there are goals, how many were achieved', () => {
    render(
      <ProgressChip
        goals={someGoals()}
        stages={progress()}
        onOpen={() => {}}
      />,
    );
    expect(figure('progress-stage-figure')).toBe('2/4');
    expect(figure('progress-goals-figure')).toBe('1/2');
    expect(chip()?.getAttribute('aria-label')).toBe(
      'Progress · Stage 2 of 4: Review · Goals 1/2 achieved',
    );
    expect(chip()?.getAttribute('title')).toBe(
      chip()?.getAttribute('aria-label'),
    );
  });

  it('takes the stage figure from the position, not from the stages it lists', () => {
    render(
      <ProgressChip
        goals={noGoals()}
        stages={progress({ position: { index: 3, total: 9 } })}
        onOpen={() => {}}
      />,
    );
    expect(figure('progress-stage-figure')).toBe('3/9');
    expect(figure('progress-goals-figure')).toBeNull();
  });

  it('says a finished run is done', () => {
    render(
      <ProgressChip
        goals={noGoals()}
        stages={progress({ current: null, position: { index: 4, total: 4 } })}
        onOpen={() => {}}
      />,
    );
    expect(chip()?.getAttribute('aria-label')).toBe(
      'Progress · All 4 stages done · No goals yet',
    );
  });

  it('opens the popup on a press', () => {
    const onOpen = vi.fn();
    render(<ProgressChip goals={someGoals()} stages={null} onOpen={onOpen} />);
    act(() => chip()?.click());
    expect(onOpen).toHaveBeenCalledTimes(1);
  });
});

describe('ProgressDialog', () => {
  const entries = (): HTMLElement[] => [
    ...document.querySelectorAll<HTMLElement>(
      '[data-slot="stage-entries"] [data-slot="stage-entry"]',
    ),
  ];
  const pills = (): HTMLElement[] => [
    ...document.querySelectorAll<HTMLElement>(
      '[data-slot="stage-graph"] [data-slot="stage-pill"]',
    ),
  ];
  const open = (
    stages: StageProgress | null,
    goals: RunGoals = noGoals(),
    onClose: () => void = () => {},
  ): void =>
    render(
      <ProgressDialog open onClose={onClose} goals={goals} stages={stages} />,
    );
  const button = (name: string): HTMLButtonElement | undefined =>
    [...document.querySelectorAll<HTMLButtonElement>('button')].find(
      (candidate) => candidate.textContent === name,
    );
  const openDetails = (): void => act(() => button('Stage details')?.click());

  it('leaves the stages out of a chat, which has none', () => {
    open(null, someGoals());
    expect(document.querySelector('[data-slot="progress-stages"]')).toBeNull();
    expect(
      document.querySelector('[data-slot="progress-goals"]'),
    ).not.toBeNull();
  });

  it('heads the stages with the position, and a finished run with all done', () => {
    open(progress());
    expect(
      document.querySelector('[data-slot="stage-position"]')?.textContent,
    ).toBe('2 of 4');
    act(() => root?.unmount());
    root = null;
    container.remove();
    open(progress({ current: null, position: { index: 4, total: 4 } }));
    expect(
      document.querySelector('[data-slot="stage-position"]')?.textContent,
    ).toBe('All 4 done');
  });

  it('draws the run’s graph with each stage’s status, a fork split into rows', async () => {
    stubResizeObserver();
    open(forked());
    await settleStageGraphs();
    expect(
      pills().map((pill) => [
        pill.dataset.stageId,
        pill.dataset.column,
        pill.dataset.status,
      ]),
    ).toEqual([
      ['investigate', '0', 'done'],
      ['implement', '1', 'not_taken'],
      ['fix', '1', 'current'],
      ['review', '2', 'pending'],
    ]);
    expect(pills().some((pill) => pill.getAttribute('role') === 'button')).toBe(
      false,
    );
  });

  it('shows what may follow the current stage: both branches of a fork ahead', async () => {
    stubResizeObserver();
    open(undecided());
    await settleStageGraphs();
    const ahead = [
      ...document.querySelectorAll<SVGPathElement>(
        '[data-slot="stage-graph"] [data-slot="stage-edge"]',
      ),
    ]
      .filter((edge) => edge.dataset.edge!.startsWith('investigate>'))
      .map((edge) => [edge.dataset.edge, edge.dataset.tone]);
    expect(ahead).toEqual([
      ['investigate>implement', 'plain'],
      ['investigate>fix', 'plain'],
    ]);
  });

  it('folds the stage details away until they are asked for', () => {
    open(progress());
    expect(entries()).toEqual([]);
    expect(button('Stage details')?.getAttribute('aria-expanded')).toBe(
      'false',
    );
    openDetails();
    expect(entries()).toHaveLength(4);
    expect(button('Stage details')?.getAttribute('aria-expanded')).toBe('true');
  });

  it('lists every stage with its status in a word, the current one as the step', () => {
    open(progress());
    openDetails();
    expect(
      entries().map((row) => [
        row.querySelector('[data-slot="stage-entry-title"]')?.textContent,
        row.querySelector('[data-slot="stage-status"]')?.textContent,
      ]),
    ).toEqual([
      ['Build', 'done'],
      ['Review', 'current'],
      ['Ship', 'pending'],
      ['Docs', 'not taken'],
    ]);
    expect(entries().map((row) => row.getAttribute('aria-current'))).toEqual([
      null,
      'step',
      null,
      null,
    ]);
  });

  it('names the branch a fork took by its title', () => {
    open(forked());
    openDetails();
    const [investigation] = entries();
    expect(
      investigation!.querySelector('[data-slot="stage-branch"]')?.textContent,
    ).toBe('took→Fix');
  });

  it('names who finished a stage and when, and their summary', () => {
    open(
      progress({
        stages: progress().stages.map((stage) =>
          stage.id === 'build'
            ? { ...stage, at: new Date(Date.now() - 5 * 60_000).toISOString() }
            : stage,
        ),
      }),
    );
    openDetails();
    const [build, review] = entries();
    expect(build!.querySelector('[data-slot="stage-actor"]')?.textContent).toBe(
      'lead',
    );
    expect(build!.querySelector('time')?.textContent).toBe('5m ago');
    expect(
      build!.querySelector('[data-slot="stage-entry-summary"]')?.textContent,
    ).toBe('compiled clean');
    expect(review!.querySelector('[data-slot="stage-actor"]')).toBeNull();
  });

  it('closes and opens the agents panel for its thread, where stages are moved', () => {
    writeThreadFlag('run-1', AGENTS_PANEL_COLLAPSED_FLAG, true);
    const onClose = vi.fn();
    open(progress(), noGoals(), onClose);
    act(() => button('Open in agents panel')?.click());
    expect(onClose).toHaveBeenCalledTimes(1);
    expect(readThreadFlag('run-1', AGENTS_PANEL_COLLAPSED_FLAG)).toBe(false);
  });

  it('counts the goals achieved and says how the thread ended', () => {
    open(
      null,
      someGoals({
        outcome: {
          kind: 'partial',
          source: 'recorded',
          summary: 'one goal left',
          seq: 9,
        },
      }),
    );
    expect(
      document.querySelector('[data-slot="goals-count"]')?.textContent,
    ).toBe('2');
    expect(
      document.querySelector('[data-slot="progress-headline"]')?.textContent,
    ).toBe('1 of 2 goals achieved');
    expect(
      document.querySelector('[data-slot="thread-outcome"]')?.textContent,
    ).toBe('Partial');
    expect(
      document.querySelector('[data-slot="thread-outcome-summary"]')
        ?.textContent,
    ).toBe('one goal left');
    expect(
      [...document.querySelectorAll('[data-goal-id]')].map(
        (row) => (row as HTMLElement).dataset.goalId,
      ),
    ).toEqual(['g1', 'g2']);
  });

  it('says an outcome came from the goals, and where a team run stands', () => {
    open(
      progress(),
      someGoals({
        outcome: { kind: 'success', source: 'goals', summary: null, seq: null },
      }),
    );
    expect(
      document.querySelector('[data-slot="thread-outcome"]')?.textContent,
    ).toBe('Success · from the goals');
    expect(
      document.querySelector('[data-slot="thread-outcome-summary"]'),
    ).toBeNull();
    expect(
      document.querySelector('[data-slot="progress-stage-badge"]')?.textContent,
    ).toBe('Stage 2 of 4: Review');
  });

  it('greets a thread with no goals by offering the first one', () => {
    open(null, noGoals({ actions: actions() }));
    expect(
      document.querySelector('[data-slot="progress-headline"]')?.textContent,
    ).toBe('No goals yet');
    expect(
      document.querySelector('input[aria-label="New goal"]'),
    ).not.toBeNull();
    act(() => root?.unmount());
    root = null;
    open(null, noGoals());
    expect(
      document.querySelector('[data-slot="progress-dialog"]')?.textContent,
    ).toContain('This thread recorded no goals.');
    expect(document.querySelector('[data-slot="progress-goals"]')).toBeNull();
  });

  it('adds a goal through the user’s own route', async () => {
    const hand = actions();
    open(null, noGoals({ actions: hand }));
    const input = document.querySelector<HTMLInputElement>(
      'input[aria-label="New goal"]',
    )!;
    act(() => {
      Object.getOwnPropertyDescriptor(
        HTMLInputElement.prototype,
        'value',
      )!.set!.call(input, 'the csv has a header row');
      input.dispatchEvent(new Event('input', { bubbles: true }));
    });
    await act(async () => {
      input.form!.requestSubmit();
    });
    expect(hand.add).toHaveBeenCalledWith('the csv has a header row');
  });
});
