function stagePhrase(progress: StageProgress): string {
  const { index, total } = progress.position;
  if (progress.current === null) {
    return `All ${total} ${total === 1 ? 'stage' : 'stages'} done`;
  }
  const current = progress.stages.find(
    (stage) => stage.id === progress.current,
  );
  return `Stage ${index} of ${total}${current === undefined ? '' : `: ${current.title}`}`;
}

function goalsPhrase(goals: readonly RunGoal[]): string {
  if (goals.length === 0) {
    return 'No goals yet';
  }
  const figure = goalsFigure(goals);
  return figure === null ? 'Every goal dropped' : `Goals ${figure} achieved`;
}

/** What the progress chip says it holds: the stage the run is on, then its goals. */
export function progressLabel(
  goals: readonly RunGoal[],
  stages: StageProgress | null,
): string {
  return [
    'Progress',
    ...(stages === null ? [] : [stagePhrase(stages)]),
    goalsPhrase(goals),
  ].join(' · ');
}

/**
 * The thread's progress as one shelf counter: the stage a team run is on and how
 * many goals were achieved, opening the progress popup. Shown whenever there is
 * something to read or the user can add a goal, so a thread with none still
 * offers the way to set them.
 */
export function ProgressChip({
  goals,
  stages,
  onOpen,
}: {
  goals: RunGoals;
  stages: StageProgress | null | undefined;
  onOpen: () => void;
}): React.JSX.Element | null {
  const progress = stages ?? null;
  if (
    progress === null &&
    goals.goals.length === 0 &&
    goals.outcome === null &&
    goals.actions === undefined
  ) {
    return null;
  }
  const figure = goalsFigure(goals.goals);
  const label = progressLabel(goals.goals, progress);
  const invitesGoals = goals.goals.length === 0 && goals.actions !== undefined;
  return (
    <button
      type="button"
      data-slot="progress-chip"
      aria-haspopup="dialog"
      aria-label={label}
      title={label}
      onClick={onOpen}
      className={SHELF_STATUS_TRIGGER_CLASS}>
      {progress === null ? null : (
        <>
          {progress.current === null ? (
            <CircleCheck
              aria-hidden="true"
              className="size-3.5 shrink-0 text-success"
            />
          ) : (
            <CircleDot
              aria-hidden="true"
              className="size-3.5 shrink-0 text-muted-foreground"
            />
          )}
          <span
            data-slot="progress-stage-figure"
            className="text-muted-foreground tabular-nums">
            {progress.position.index}/{progress.position.total}
          </span>
        </>
      )}
      {progress !== null && figure === null && !invitesGoals ? null : (
        <Target aria-hidden="true" className="size-3.5 shrink-0" />
      )}
      {figure === null ? null : (
        <span
          data-slot="progress-goals-figure"
          className="text-muted-foreground tabular-nums">
          {figure}
        </span>
      )}
      {invitesGoals ? (
        <span data-slot="progress-set-goals" className="text-muted-foreground">
          Set goals
        </span>
      ) : null}
    </button>
  );
}

const outcomeTone = cva('', {
  variants: {
    kind: {
      success: 'bg-success/10 text-success',
      partial: 'bg-warning/10 text-warning',
      failed: 'bg-destructive/10 text-destructive',
      abandoned: 'bg-muted text-muted-foreground',
    },
  },
});

function ProgressSummary({
  goals,
  stages,
}: {
  goals: RunGoals;
  stages: StageProgress | null;
}): React.JSX.Element {
  const counted = goals.goals.filter((goal) => goal.status !== 'dropped');
  const achieved = counted.filter((goal) => goal.status === 'achieved').length;
  const fraction = counted.length === 0 ? 0 : achieved / counted.length;
  const headline =
    goals.goals.length === 0
      ? 'No goals yet'
      : counted.length === 0
        ? 'Every goal dropped'
        : `${achieved} of ${counted.length} ${counted.length === 1 ? 'goal' : 'goals'} achieved`;
  const detail =
    goals.goals.length > 0
      ? goals.goals.every((goal) => goal.status === 'achieved')
        ? null
        : goalsSummary(goals.goals)
      : goals.actions === undefined
        ? 'This thread recorded no goals.'
        : 'The outcomes this thread must reach, each one you can check. The agent sets them as a task starts — or add the first one below.';
  const outcome: ThreadOutcome | null = goals.outcome;
  return (
    <div
      data-slot="progress-summary"
      className="flex items-center gap-4 rounded-xl border border-border bg-muted/30 p-4">
      <div className="relative flex size-16 shrink-0 items-center justify-center">
        <ProgressRing
          fraction={fraction}
          size={64}
          strokeWidth={5}
          label={headline}
          className={fraction === 1 ? 'text-success' : 'text-primary'}
        />
        <span className="absolute inset-0 flex items-center justify-center text-sm font-semibold tabular-nums">
          {counted.length === 0 ? (
            <Target
              aria-hidden="true"
              className="size-6 text-muted-foreground"
            />
          ) : (
            `${achieved}/${counted.length}`
          )}
        </span>
      </div>
      <div className="flex min-w-0 flex-1 flex-col gap-1">
        <p
          data-slot="progress-headline"
          className="m-0 text-base leading-tight font-semibold">
          {headline}
        </p>
        {detail === null ? null : (
          <p
            data-slot="progress-detail"
            className="m-0 text-xs leading-relaxed text-muted-foreground">
            {detail}
          </p>
        )}
        {outcome === null && stages === null ? null : (
          <div className="mt-1 flex flex-wrap items-center gap-1.5">
            {outcome === null ? null : (
              <Badge
                data-slot="thread-outcome"
                variant="muted"
                title={
                  outcome.source === 'goals'
                    ? 'How the thread ended, from its goals'
                    : 'How the thread ended, as its agent recorded it'
                }
                className={outcomeTone({ kind: outcome.kind })}>
                {OUTCOME_LABEL[outcome.kind]}
                {outcome.source === 'goals' ? ' · from the goals' : ''}
              </Badge>
            )}
            {stages === null ? null : (
              <Badge
                data-slot="progress-stage-badge"
                variant="muted"
                className={cn(
                  stages.current === null && 'bg-success/10 text-success',
                )}>
                {stages.current === null ? <CircleCheck /> : <CircleDot />}
                {stagePhrase(stages)}
              </Badge>
            )}
          </div>
        )}
        {outcome === null || outcome.summary === null ? null : (
          <p
            data-slot="thread-outcome-summary"
            className="m-0 mt-1 text-xs leading-relaxed text-foreground/80">
            {outcome.summary}
          </p>
        )}
      </div>
    </div>
  );
}

function ProgressHeading({
  title,
  aside,
}: {
  title: string;
  aside?: ReactNode;
}): React.JSX.Element {
  return (
    <header className="flex items-baseline gap-1.5">
      <h3 className="m-0 text-[11px] font-semibold tracking-wide text-muted-foreground uppercase">
        {title}
      </h3>
      {aside === undefined || aside === null ? null : (
        <span className="ml-auto text-xs text-muted-foreground tabular-nums">
          {aside}
        </span>
      )}
    </header>
  );
}

function ProgressStages({
  progress,
  nameOf,
  onRevealPanel,
}: {
  progress: StageProgress;
  nameOf?: (memberId: string) => string;
  onRevealPanel: () => void;
}): React.JSX.Element {
  const [detailsOpen, setDetailsOpen] = useState(false);
  return (
    <section
      aria-label="Stages"
      data-slot="progress-stages"
      className="flex flex-col gap-2 text-xs">
      <ProgressHeading
        title="Stages"
        aside={
          <span data-slot="stage-position">
            {progress.current === null
              ? `All ${progress.position.total} done`
              : `${progress.position.index} of ${progress.position.total}`}
          </span>
        }
      />
      <div className="rounded-lg border border-border bg-muted/20 px-2 py-3">
        <StageGraph stages={progress.stages} />
      </div>
      <div className="flex items-center justify-between gap-2">
        <Button
          type="button"
          variant="ghost"
          size="sm"
          aria-expanded={detailsOpen}
          className="-ml-2 text-muted-foreground"
          onClick={() => setDetailsOpen((open) => !open)}>
          <ChevronRight
            aria-hidden="true"
            className={cn('transition-transform', detailsOpen && 'rotate-90')}
          />
          Stage details
        </Button>
        <Button
          type="button"
          variant="ghost"
          size="sm"
          className="-mr-2 text-muted-foreground"
          onClick={onRevealPanel}>
          <PanelRight aria-hidden="true" />
          Open in agents panel
        </Button>
      </div>
      {detailsOpen ? (
        <ol
          aria-label="Stages"
          data-slot="stage-entries"
          className="m-0 flex max-h-[14rem] list-none flex-col divide-y divide-border overflow-y-auto rounded-lg border border-border bg-card px-3">
          {progress.stages.map((stage) => (
            <StageEntry
              key={stage.id}
              stage={stage}
              progress={progress}
              agentName={nameOf}
            />
          ))}
        </ol>
      ) : null}
    </section>
  );
}

/**
 * The thread's progress popup: a summary of where its goals stand and how it
 * ended, the goals with the user's add, edit, close and reopen, and a team run's
 * stages. Opened from the shelf's progress chip and the agents panel's Goals row.
 */
export function ProgressDialog({
  open,
  onClose,
  goals,
  stages,
  nameOf,
}: {
  open: boolean;
  onClose: () => void;
  goals: RunGoals;
  stages: StageProgress | null | undefined;
  /** A team member's name; absent in a chat. */
  nameOf?: (memberId: string) => string;
}): React.JSX.Element {
  const runId = useContext(ThreadUiMemoryContext);
  const bodyRef = useRef<HTMLDivElement | null>(null);
  const progress = stages ?? null;
  return (
    <Dialog
      open={open}
      onClose={onClose}
      initialFocus={bodyRef}
      className="max-w-lg"
      title={
        <span className="flex items-center gap-2">
          <Target
            aria-hidden="true"
            className="size-4 shrink-0 text-muted-foreground"
          />
          Progress
        </span>
      }>
      <div
        ref={bodyRef}
        tabIndex={-1}
        data-slot="progress-dialog"
        className="flex flex-col gap-5 outline-none">
        <ProgressSummary goals={goals} stages={progress} />
        {goals.goals.length === 0 && goals.actions === undefined ? null : (
          <section
            aria-label="Goals"
            data-slot="progress-goals"
            className="flex flex-col gap-2">
            {goals.goals.length === 0 ? null : (
              <ProgressHeading
                title="Goals"
                aside={
                  <span data-slot="goals-count">{goals.goals.length}</span>
                }
              />
            )}
            <GoalsList
              goals={goals.goals}
              actions={goals.actions}
              nameOf={nameOf}
            />
          </section>
        )}
        {progress === null ? null : (
          <ProgressStages
            progress={progress}
            nameOf={nameOf}
            onRevealPanel={() => {
              onClose();
              revealAgentsPanel(runId);
            }}
          />
        )}
      </div>
    </Dialog>
  );
}
