import { FolderGit2 } from 'lucide-react';

import type { ProjectDto } from '../autogenerated';
import { Select } from '../components/ui/select';

const NONE = '__none__';

/** From this many projects the menu gets a filter field. */
export const PROJECT_SEARCH_FROM = 8;

/**
 * A project to bind a run to, or none: the run configuration editor's row and
 * the composer's chip. A `value` naming no listed project reads as none.
 */
export function ProjectSelect({
  projects,
  value,
  onChange,
  noneLabel = 'None',
  variant = 'default',
  disabled = false,
  'aria-label': ariaLabel,
  title,
}: {
  projects: readonly Pick<ProjectDto, 'id' | 'name' | 'folder'>[];
  value: string | null;
  onChange: (projectId: string | null) => void;
  noneLabel?: string;
  variant?: 'default' | 'ghost';
  disabled?: boolean;
  'aria-label': string;
  title?: string;
}): React.JSX.Element {
  const known = projects.some((project) => project.id === value);
  return (
    <Select
      variant={variant}
      flexible={variant === 'ghost'}
      aria-label={ariaLabel}
      title={title}
      disabled={disabled}
      leadingIcon={variant === 'ghost' ? <FolderGit2 /> : undefined}
      value={known ? value : NONE}
      searchPlaceholder={
        projects.length >= PROJECT_SEARCH_FROM ? 'Find a project…' : undefined
      }
      groups={[
        {
          items: [
            { value: NONE, label: noneLabel },
            ...projects.map((project) => ({
              value: project.id,
              label: project.name,
              icon: <FolderGit2 />,
            })),
          ],
        },
      ]}
      onValueChange={(next) => onChange(next === NONE ? null : next)}
    />
  );
}
