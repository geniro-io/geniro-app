import { Hourglass, TriangleAlert } from 'lucide-react';
import { useEffect, useState } from 'react';

import type { PromptCacheTtlReason } from '../autogenerated';
import { ErrorBanner } from '../components/error-banner';
import { formatTokens } from './agent-activity';
import { formatElapsed } from './live-row';
import {
  formatCacheSpan,
  msUntilPromptCacheNotice,
  promptCacheReasonText,
  promptCacheState,
} from './prompt-cache';

/**
 * How often the line re-reads the clock once it is showing: every second while
 * it counts down, every half minute once the cache has lapsed and the only
 * figure left is "how long ago", stated in whole minutes.
 */
const COUNTDOWN_TICK_MS = 1_000;
const EXPIRED_TICK_MS = 30_000;

/**
 * The expiries the user closed the notice for, for this window's life.
 *
 * Keyed by the EXPIRY rather than held in component state: the composer is
 * re-used across chats, so state would forget a dismissal the moment the user
 * looked at another thread and came back. A new turn moves the expiry, which
 * is a new cache to warn about — so closing it is never a permanent mute.
 */
const dismissedExpiries = new Set<string>();

/**
 * The strip at the bottom of the message box saying the prompt cache is about
 * to lapse, or has — because the next message is then a full re-write of the
 * conversation to the cache, which on a long thread is the most expensive turn
 * in it. See `prompt-cache.ts` for where the expiry comes from.
 *
 * It is the app's warning strip (`ErrorBanner`'s `warning` tone) so it can be
 * closed, and it says WHY a cache is short when the CLI said so — without that
 * a five-minute cache on a subscription read as an expiry geniro got wrong.
 *
 * It owns its clock, so the composer around it does not re-render with it, and
 * it SLEEPS until the countdown is due: an hour-long cache costs one timer, not
 * 3,600 renders of nothing.
 */
export function PromptCacheNotice({
  expiresAt,
  ttlMs,
  ttlReason,
  contextTokens,
}: {
  /** `RunDto.promptCacheExpiresAt`. */
  expiresAt: string | null | undefined;
  /** `RunDto.promptCacheTtlMs` — the lifetime that expiry was measured with. */
  ttlMs?: number | null;
  /** `RunDto.promptCacheTtlReason` — why the lifetime is what it is. */
  ttlReason?: PromptCacheTtlReason | null;
  /** How much the next message would re-cache, when known. */
  contextTokens: number | null | undefined;
}): React.JSX.Element | null {
  const [now, setNow] = useState(() => Date.now());
  // Bumped by a close, so the strip re-renders without it; the set is the
  // record, this is only the nudge.
  const [, setDismissals] = useState(0);
  const state = promptCacheState(expiresAt, now);
  useEffect(() => {
    // A FRESH clock, not the rendered one: while nothing shows, `now` can be a
    // whole sleep old, and a new expiry (the next turn settling) measured
    // against it would wake the line late.
    const current = Date.now();
    const fresh = promptCacheState(expiresAt, current);
    if (fresh?.kind !== promptCacheState(expiresAt, now)?.kind) {
      setNow(current);
      return;
    }
    const delay =
      fresh === null
        ? msUntilPromptCacheNotice(expiresAt, current)
        : fresh.kind === 'expiring'
          ? COUNTDOWN_TICK_MS
          : EXPIRED_TICK_MS;
    if (delay === null) {
      return;
    }
    // Capped: a timer past 2^31-1 ms fires at once, which would turn a long
    // sleep into a tight loop.
    const id = window.setTimeout(
      () => setNow(Date.now()),
      Math.min(delay, 2_147_483_647),
    );
    return () => window.clearTimeout(id);
  }, [expiresAt, now]);

  if (
    state === null ||
    typeof expiresAt !== 'string' ||
    dismissedExpiries.has(expiresAt)
  ) {
    return null;
  }
  const size =
    typeof contextTokens === 'number' && contextTokens > 0
      ? `~${formatTokens(contextTokens)} tokens`
      : 'the whole conversation';
  const expired = state.kind === 'expired';
  const headline = expired
    ? `Prompt cache expired ${formatCacheSpan(state.sinceMs)} ago — the next message re-caches ${size} at full price.`
    : `Prompt cache expires in ${formatElapsed(state.remainingMs)} — send now to keep the next message cheap.`;
  const reason = promptCacheReasonText(ttlReason, ttlMs);
  return (
    <ErrorBanner
      data-slot="prompt-cache-notice"
      data-state={state.kind}
      tone="warning"
      size="sm"
      // The countdown re-renders every second; as an alert it would be read
      // out on every tick.
      announce="status"
      icon={expired ? <TriangleAlert /> : <Hourglass />}
      message={reason === null ? headline : `${headline} ${reason}`}
      onDismiss={() => {
        dismissedExpiries.add(expiresAt);
        setDismissals((count) => count + 1);
      }}
      className="mx-3 mb-1.5"
    />
  );
}
