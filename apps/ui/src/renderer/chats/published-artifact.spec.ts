import { describe, expect, it } from 'vitest';

import type { DaemonHandle } from '../../shared/contracts';
import type { ItemDto as ChatItem } from '../autogenerated';
import {
  artifactPageUrl,
  artifactUrlBuilder,
  type PublishedArtifact,
  readPublishedArtifact,
} from './published-artifact';

const row = (
  payload: unknown,
  seq = 1,
  kind: ChatItem['kind'] = 'show_artifact',
): ChatItem =>
  ({
    id: `item-${seq}`,
    runId: 'run-1',
    seq,
    kind,
    role: null,
    nodeId: null,
    payload,
    createdAt: new Date(seq * 1000).toISOString(),
  }) as unknown as ChatItem;

const PAYLOAD = {
  artifactId: 'plan',
  version: 1,
  title: 'Migration plan',
  summary: 'three phases',
  key: 'a'.repeat(64),
};

describe('readPublishedArtifact', () => {
  it('reads the descriptor the daemon writes', () => {
    expect(readPublishedArtifact(row(PAYLOAD))).toEqual({
      artifactId: 'plan',
      version: 1,
      title: 'Migration plan',
      summary: 'three phases',
      key: 'a'.repeat(64),
    });
  });

  it('leaves an absent summary null rather than inventing one', () => {
    const { summary, ...rest } = PAYLOAD;
    expect(summary).toBeTruthy();
    expect(readPublishedArtifact(row(rest))?.summary).toBeNull();
  });

  it.each([
    ['no id', { ...PAYLOAD, artifactId: undefined }],
    ['no key', { ...PAYLOAD, key: undefined }],
    ['no title', { ...PAYLOAD, title: undefined }],
    ['no version', { ...PAYLOAD, version: undefined }],
    ['a version that is not a whole number', { ...PAYLOAD, version: 1.5 }],
    ['a version below one', { ...PAYLOAD, version: 0 }],
  ])(
    'draws nothing for a row with %s — it could not be opened',
    (_why, payload) => {
      // A card that cannot open its own artifact is worse than no card: every
      // one of these leaves no URL to frame.
      expect(readPublishedArtifact(row(payload))).toBeNull();
    },
  );

  it('does not throw on a payload of any shape', () => {
    for (const payload of [null, 'text', 42, [], { artifactId: 5, key: {} }]) {
      expect(() => readPublishedArtifact(row(payload))).not.toThrow();
      expect(readPublishedArtifact(row(payload))).toBeNull();
    }
  });
});

describe('artifactPageUrl', () => {
  const handle: DaemonHandle = {
    host: '127.0.0.1',
    port: 47615,
    token: 'launch-token',
    version: '1.0.0',
    startedAt: '2026-09-20T00:00:00.000Z',
  };
  const artifact: PublishedArtifact = {
    artifactId: 'roll out/plan',
    version: 3,
    title: 'Plan',
    summary: null,
    key: 'k'.repeat(64),
  };

  it('addresses the version the row announced, with its own key', () => {
    const url = artifactPageUrl(handle, 'run-1', artifact);

    expect(url).toBe(
      'http://127.0.0.1:47615/v1/artifacts/run-1/roll%20out%2Fplan' +
        `?key=${'k'.repeat(64)}&v=3`,
    );
  });

  it('carries the LAUNCH token nowhere near the URL', () => {
    // The per-artifact key is what this route authenticates on precisely so
    // the master credential of the whole daemon never travels in a frame's
    // address.
    expect(artifactPageUrl(handle, 'run-1', artifact)).not.toContain(
      'launch-token',
    );
  });

  it('asks for the raw document only when told to', () => {
    // `raw=1` is the one literal the route turns the unwrapped reading on for,
    // and the save path is its only caller.
    expect(artifactPageUrl(handle, 'run-1', artifact)).not.toContain('raw');
    expect(artifactPageUrl(handle, 'run-1', artifact, {})).not.toContain('raw');
    expect(
      artifactPageUrl(handle, 'run-1', artifact, { raw: false }),
    ).not.toContain('raw');
    expect(artifactPageUrl(handle, 'run-1', artifact, { raw: true })).toContain(
      '&raw=1',
    );
  });
});

describe('artifactUrlBuilder', () => {
  const handle: DaemonHandle = {
    host: '127.0.0.1',
    port: 47615,
    token: 'launch-token',
    version: '1.0.0',
    startedAt: '2026-09-20T00:00:00.000Z',
  };
  const artifact: PublishedArtifact = {
    artifactId: 'plan',
    version: 1,
    title: 'Plan',
    summary: null,
    key: 'k'.repeat(64),
  };

  it('FORWARDS the options a caller passes', () => {
    // The whole reason the factory exists. A provider written by hand as
    // `(artifact) => artifactPageUrl(handle, runId, artifact)` type-checks and
    // drops these silently, which hands the save path the framed page — it
    // shipped once and was found by opening the saved file, because every spec
    // in front of it used a stub provider and was only testing the stub.
    const build = artifactUrlBuilder(handle, 'run-1');

    expect(build(artifact, { raw: true })).toContain('&raw=1');
    expect(build(artifact)).not.toContain('raw');
  });

  it('binds the run it was made for', () => {
    expect(artifactUrlBuilder(handle, 'run-7')(artifact)).toContain(
      '/v1/artifacts/run-7/plan',
    );
  });
});
