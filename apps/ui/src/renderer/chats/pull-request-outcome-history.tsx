import { ChevronRight } from 'lucide-react';

import type { RunPullRequestOutcomes } from '../autogenerated';
import { cn } from '../components/ui/utils';
import { formatDuration } from '../stats/stats-format';
import { formatDateTime } from './relative-time';
import {
  AcceptanceBadge,
  outcomeSegments,
  plural,
  pullRequestOutcomeKey,
} from './run-outcome';
import { useThreadFlag } from './thread-ui-memory';

/** What a pull request's outcomes add up to, as the fold's one line. */
export function outcomeHistoryLine(history: RunPullRequestOutcomes): string {
  return [
    plural(history.outcomes.length, 'outcome', 'outcomes'),
    ...(history.changesRequestedRounds === 0
      ? []
      : [
          `sent back ${plural(history.changesRequestedRounds, 'time', 'times')}`,
        ]),
    ...(history.msToAccepted === null
      ? []
      : [`accepted after ${formatDuration(history.msToAccepted)}`]),
  ].join(' · ');
}

/**
 * Every outcome the run's agents recorded for one pull request, under its row
 * in the agents panel: folded to the newest verdict and what the history adds
 * up to, and opened on a press into each record, newest first, with the
 * agent's summary.
 */
export function PullRequestOutcomeHistory({
  history,
}: {
  history: RunPullRequestOutcomes;
}): React.JSX.Element | null {
  const [open, setOpen] = useThreadFlag(
    `pr-outcomes:${pullRequestOutcomeKey(history)}`,
    false,
  );
  const newest = history.outcomes[0];
  if (newest === undefined) {
    return null;
  }
  return (
    <div data-slot="pr-outcome-history" className="flex min-w-0 flex-col gap-1">
      <button
        type="button"
        aria-expanded={open}
        title={open ? 'Hide the outcomes' : 'Show every recorded outcome'}
        onClick={() => setOpen((wasOpen) => !wasOpen)}
        className="flex w-full min-w-0 items-center gap-1.5 px-1 text-left text-xs text-muted-foreground hover:text-foreground">
        <ChevronRight
          aria-hidden="true"
          className={cn(
            'size-3 shrink-0 transition-transform',
            open && 'rotate-90',
          )}
        />
        <AcceptanceBadge acceptance={newest.acceptance} />
        <span className="min-w-0">{outcomeHistoryLine(history)}</span>
      </button>
      {open ? (
        <ol className="m-0 ml-2.5 flex list-none flex-col gap-2 border-l border-border p-0 pl-2.5">
          {history.outcomes.map((entry) => {
            const words = outcomeSegments(entry);
            return (
              <li
                key={entry.seq}
                data-slot="pr-outcome-entry"
                className="flex min-w-0 flex-col gap-0.5 text-xs">
                <span className="flex min-w-0 items-center gap-1.5">
                  <AcceptanceBadge
                    acceptance={entry.acceptance}
                    muted={entry !== newest}
                  />
                  <span className="truncate tabular-nums text-muted-foreground">
                    {formatDateTime(entry.at)}
                  </span>
                </span>
                <span className="text-muted-foreground">
                  {[words.draft, words.rounds, words.questions].join(' · ')}
                </span>
                {entry.summary === null ? null : (
                  <span className="whitespace-pre-wrap break-words text-foreground/90">
                    {entry.summary}
                  </span>
                )}
              </li>
            );
          })}
        </ol>
      ) : null}
    </div>
  );
}
