/**
 * How one state is drawn — the single mapping, so the panel's list, the sidebar
 * row and the composer band cannot end up calling the same pull request three
 * different things.
 *
 * A DRAFT is a state of its own here rather than a flag on `open`: that is how
 * it reads on screen and how GitHub itself labels it, and a draft listed as
 * plain `open` would say a pull request is asking for review when it is not.
 */
interface PullRequestLook {
  word: string;
  icon: LucideIcon;
  className: string;
}

function lookOf(pullRequest: PullRequestInfo): PullRequestLook {
  if (pullRequest.state === 'merged') {
    return { word: 'merged', icon: GitMerge, className: 'text-success' };
  }
  if (pullRequest.state === 'closed') {
    return {
      word: 'closed',
      icon: GitPullRequestClosed,
      className: 'text-destructive',
    };
  }
  if (pullRequest.isDraft) {
    return {
      word: 'draft',
      icon: GitPullRequestDraft,
      className: 'text-muted-foreground',
    };
  }
  return { word: 'open', icon: GitPullRequest, className: 'text-warning' };
}

/**
 * The state as a glyph, and the ONLY place a row states it: green merged,
 * yellow open, grey draft, red closed. It carries its word for a reader who
 * cannot see the colour, since colour and shape are the whole visible signal —
 * every list here draws one row per pull request, so the state repeated as text
 * beside every number was a column of words that said what the icon already
 * said.
 */
export function PullRequestStateIcon({
  pullRequest,
}: {
  pullRequest: PullRequestInfo;
}): React.JSX.Element {
  const look = lookOf(pullRequest);
  const Icon = look.icon;
  return (
    <>
      <Icon
        aria-hidden="true"
        className={cn('size-3.5 shrink-0', look.className)}
      />
      <span className="sr-only">{look.word}</span>
    </>
  );
}

/**
 * How big a pull request is, said in words — for a tooltip, where there is room
 * for the units the row itself has to leave off.
 *
 * Empty when GitHub reported nothing, which a caller appends rather than
 * branches on.
 */
function sizeSentence(pullRequest: PullRequestInfo): string {
  const parts: string[] = [];
  if (pullRequest.changedFiles !== null) {
    parts.push(
      `${pullRequest.changedFiles} ${pullRequest.changedFiles === 1 ? 'file' : 'files'}`,
    );
  }
  if (pullRequest.added !== null || pullRequest.removed !== null) {
    parts.push(
      [
        pullRequest.added === null ? null : `+${pullRequest.added}`,
        pullRequest.removed === null ? null : `−${pullRequest.removed}`,
      ]
        .filter((part) => part !== null)
        .join(' '),
    );
  }
  return parts.length === 0 ? '' : ` · ${parts.join(' ')}`;
}

/**
 * The second line of a pull request's PANEL row: its name, then its size.
 *
 * Under the title rather than beside it: beside it, these figures left the
 * title a couple of words in a 280px panel. The file count still gets its own
 * word rather than being folded into a tooltip.
 */
function PullRequestMeta({
  name,
  pullRequest,
  outcome,
}: {
  name: string;
  pullRequest: PullRequestInfo;
  outcome: PullRequestOutcome | null;
}): React.JSX.Element {
  return (
    <span className="flex items-baseline gap-2">
      <span className="tabular-nums text-foreground/80">{name}</span>
      {outcome === null ? null : (
        <span className="self-center">
          <AcceptanceIcon acceptance={outcome.acceptance} />
        </span>
      )}
      {pullRequest.changedFiles === null ? null : (
        <span className="tabular-nums">
          {pullRequest.changedFiles}{' '}
          {pullRequest.changedFiles === 1 ? 'file' : 'files'}
        </span>
      )}
      <DiffFigures added={pullRequest.added} removed={pullRequest.removed} />
    </span>
  );
}

/**
 * THIS thread's pull request as a LABEL — a state glyph and the number, and
 * nothing else.
 *
 * It was a full line on the sidebar row: the glyph, the number and the TITLE,
 * spending the row's whole width on text the row already spends two lines on
 * (the chat's own name, and the last message). REPORTED as "make chip with
 * current pr in threads list smaller - just icon and pr number. And make it as
 * label", and the title is the part that had to go — the number is what
 * identifies a pull request, and the state is what a glance is asking about.
 *
 * A `Badge` rather than a bordered chip, because the sidebar row is not a place
 * for controls: it is one activatable element, and everything drawn inside it is
 * a description of the thread. A chip's affordance would promise a press this
 * cannot honour — an anchor nested inside an activatable row is invalid markup
 * that also steals the row's own click, which is why nothing here is a link. The
 * whole sentence stays on `title`, so the title is one hover away rather than
 * gone.
 */
export function PullRequestBadge({
  pullRequest,
  className,
}: {
  pullRequest: PullRequestInfo;
  className?: string;
}): React.JSX.Element {
  const look = lookOf(pullRequest);
  return (
    <Badge
      data-slot="current-pull-request"
      variant="muted"
      title={`#${pullRequest.number} ${pullRequest.title} · ${look.word}`}
      className={cn('gap-1 px-1.5 py-0 font-normal', className)}>
      <PullRequestStateIcon pullRequest={pullRequest} />
      <span className="tabular-nums">#{pullRequest.number}</span>
    </Badge>
  );
}

/**
 * How a pull request the THREAD opened is named when the thread spans several
 * repositories.
 *
 * `#87` is unambiguous inside one repository and meaningless across six — the
 * measured case here opened `#3` in two different ones. So the repository is
 * part of the name exactly when there is more than one on screen, and never
 * otherwise: prefixing every row in a single-repository thread is noise that
 * pushes the title out.
 */
function pullRequestLabel(
  ref: { repo: string; number: number },
  showRepo: boolean,
): string {
  return showRepo ? `${ref.repo}#${ref.number}` : `#${ref.number}`;
}

/**
 * One pull request THIS THREAD opened or touched, in the right-hand panel.
 *
 * The state is the ICON's — its colour and its shape — never a word beside the
 * number: within the settled group a merged pull request and an abandoned one
 * are the same row shape, and green-versus-red separates them at a glance where
 * a trailing `· merged` had to be read. The word survives in the row's tooltip
 * and in the icon's own screen-reader text.
 *
 * Draws from whatever is known: a resolved row gets the title and the state,
 * and an unresolved one still gets a row.
 * That fallback is the point rather than a nicety — the thread demonstrably
 * opened this pull request, so "GitHub could not be asked" must not make it
 * disappear, which is exactly what a list built only from `gh` answers would do
 * on a logged-out machine.
 */
export function ThreadPullRequestRow({
  result,
  showRepo,
  outcome = null,
}: {
  result: PullRequestRefResult;
  showRepo: boolean;
  /** Its newest recorded outcome, drawn beside the number; null when none. */
  outcome?: PullRequestOutcome | null;
}): React.JSX.Element {
  const { ref, pullRequest } = result;
  const name = pullRequestLabel(ref, showRepo);
  if (pullRequest === null) {
    return (
      <PanelLinkRow
        href={ref.url}
        title={name}
        tooltip={`${ref.owner}/${ref.repo}#${ref.number}`}
        icon={
          <GitPullRequest
            aria-hidden="true"
            className="size-3.5 shrink-0 text-muted-foreground"
          />
        }
      />
    );
  }
  return (
    <PanelLinkRow
      href={pullRequest.url}
      title={pullRequest.title}
      tooltip={`${ref.owner}/${ref.repo}#${ref.number} ${pullRequest.title} · ${lookOf(pullRequest).word}${sizeSentence(pullRequest)}`}
      icon={<PullRequestStateIcon pullRequest={pullRequest} />}
      detail={
        <PullRequestMeta
          name={name}
          pullRequest={pullRequest}
          outcome={outcome}
        />
      }
    />
  );
}

/**
 * One pull request in the shelf's list: a flat row like every other row of a
 * shelf popover, the title over two lines at most, and under it the number, the
 * recorded acceptance in words and the size in right-aligned columns, so the
 * figures of every row line up.
 */
export function PullRequestListRow({
  result,
  showRepo,
  outcome = null,
}: {
  result: PullRequestRefResult;
  showRepo: boolean;
  outcome?: PullRequestOutcome | null;
}): React.JSX.Element {
  const { ref, pullRequest } = result;
  const name = pullRequestLabel(ref, showRepo);
  const identity =
    pullRequest === null
      ? `${ref.owner}/${ref.repo}#${ref.number}`
      : `${ref.owner}/${ref.repo}#${ref.number} ${pullRequest.title} · ${lookOf(pullRequest).word}${sizeSentence(pullRequest)}`;
  return (
    <a
      data-slot="pull-request-list-row"
      href={pullRequest?.url ?? ref.url}
      target="_blank"
      rel="noreferrer"
      title={
        outcome === null ? identity : `${identity}\n${outcomeSentence(outcome)}`
      }
      className="group flex items-start gap-2 rounded-md px-2 py-1.5 text-left transition-colors hover:bg-muted">
      <span className="flex h-5 shrink-0 items-center">
        {pullRequest === null ? (
          <GitPullRequest
            aria-hidden="true"
            className="size-3.5 shrink-0 text-muted-foreground"
          />
        ) : (
          <PullRequestStateIcon pullRequest={pullRequest} />
        )}
      </span>
      <span className="flex min-w-0 flex-1 flex-col gap-0.5">
        <span className="flex items-start gap-2">
          <span className="line-clamp-2 min-w-0 flex-1 text-sm leading-5 text-foreground">
            {pullRequest?.title ?? name}
          </span>
          <ExternalLink
            aria-hidden="true"
            className="mt-1 size-3 shrink-0 text-muted-foreground opacity-0 transition-opacity group-hover:opacity-100 group-focus-visible:opacity-100"
          />
        </span>
        <span
          data-slot="pull-request-list-detail"
          className="flex items-center gap-2 text-xs text-muted-foreground">
          <span className="shrink-0 tabular-nums">{name}</span>
          {outcome === null ? null : (
            <AcceptanceLabel acceptance={outcome.acceptance} />
          )}
          {pullRequest === null ? null : (
            <span className="ml-auto flex shrink-0 items-center gap-2">
              {pullRequest.changedFiles === null ? null : (
                <span className="tabular-nums">
                  {pullRequest.changedFiles}{' '}
                  {pullRequest.changedFiles === 1 ? 'file' : 'files'}
                </span>
              )}
              <DiffFigures
                added={pullRequest.added}
                removed={pullRequest.removed}
                layout="columns"
                className="gap-1"
              />
            </span>
          )}
        </span>
      </span>
    </a>
  );
}

/**
 * The thread's one pull request as a shelf chip: the state glyph, the number
 * and the recorded acceptance. The title and the size are on the tooltip, so
 * the chip stays as short as the counters beside it.
 */
export function ThreadPullRequestChip({
  result,
  showRepo,
  outcome = null,
}: {
  result: PullRequestRefResult;
  showRepo: boolean;
  /**
   * Its newest recorded outcome on this thread (`record_outcome`), drawn as an
   * acceptance mark beside the number; null when none was recorded.
   */
  outcome?: PullRequestOutcome | null;
}): React.JSX.Element {
  const { ref, pullRequest } = result;
  const name = pullRequestLabel(ref, showRepo);
  const identity =
    pullRequest === null
      ? `${ref.owner}/${ref.repo}#${ref.number}`
      : `${name} ${pullRequest.title} · ${lookOf(pullRequest).word}${sizeSentence(pullRequest)}`;
  const label =
    outcome === null ? identity : `${identity}\n${outcomeSentence(outcome)}`;
  return (
    <a
      data-slot="pull-request-chip"
      href={ref.url}
      target="_blank"
      rel="noreferrer"
      title={label}
      className={cn(SHELF_CHIP_CLASS, 'shrink-0')}>
      {pullRequest === null ? (
        <GitPullRequest
          aria-hidden="true"
          className="size-3.5 shrink-0 text-muted-foreground"
        />
      ) : (
        <PullRequestStateIcon pullRequest={pullRequest} />
      )}
      <span className="font-medium tabular-nums">{name}</span>
      {outcome === null ? null : (
        <AcceptanceIcon acceptance={outcome.acceptance} />
      )}
    </a>
  );
}
