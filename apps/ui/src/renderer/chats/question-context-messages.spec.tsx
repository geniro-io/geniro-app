const MESSAGES: ThreadContextMessage[] = [
  { seq: 4, role: 'user', text: 'Clear the cache' },
  { seq: 5, role: 'assistant', text: 'Two caches could be meant' },
];

const NO_ANSWERS = {
  readArtifactAnswers: vi.fn(),
  saveArtifactAnswers: vi.fn(),
};

const HANDLE: DaemonHandle = {
  host: '127.0.0.1',
  port: 47615,
  token: 'launch-token',
  version: '1.0.0',
  startedAt: '2026-09-20T00:00:00.000Z',
};

const itemRow = (
  seq: number,
  kind: string,
  role: string | null,
  payload: Record<string, unknown>,
): ItemDto =>
  ({
    id: `item-${seq}`,
    runId: 'thread-1',
    memberId: null,
    seq,
    kind,
    role,
    payload,
    createdAt: new Date(seq * 1000).toISOString(),
  }) as ItemDto;

let root: Root;
let container: HTMLDivElement;

beforeEach(() => {
  localStorage.clear();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function drawWith(
  reader: ThreadContextReader | null,
  requestId = 'req-1',
): void {
  act(() => {
    root.render(
      <ThreadContextReaderContext.Provider value={reader}>
        <QuestionContextMessages
          threadRunId="thread-1"
          threadRequestId={requestId}
        />
      </ThreadContextReaderContext.Provider>,
    );
  });
}

function draw(
  read: ThreadContextReader['read'] | null,
  requestId = 'req-1',
): void {
  drawWith(read === null ? null : stubThreadContextReader(read), requestId);
}

const FIVE_LINES = (name: string): string =>
  [1, 2, 3, 4, 5].map((line) => `${name}, line ${line}.`).join('\n');

const LONG_MESSAGES: ThreadContextMessage[] = [
  { seq: 1, role: 'user', text: FIVE_LINES('Clear the shared cache') },
  { seq: 2, role: 'assistant', text: FIVE_LINES('Two caches could be meant') },
  { seq: 3, role: 'user', text: FIVE_LINES('The shared one') },
];

function drawInThread(
  read: ThreadContextReader['read'],
  requestId: string,
): void {
  act(() => {
    root.render(
      <ThreadUiMemoryContext.Provider value="manager-run">
        <ThreadContextReaderContext.Provider
          value={stubThreadContextReader(read)}>
          <QuestionContextMessages
            threadRunId="thread-1"
            threadRequestId={requestId}
          />
        </ThreadContextReaderContext.Provider>
      </ThreadUiMemoryContext.Provider>,
    );
  });
}

const messagesBlock = (): HTMLElement | null =>
  container.querySelector<HTMLElement>(
    '[data-slot="thread-question-context-messages"]',
  );

const messagesToggle = (): HTMLButtonElement =>
  container.querySelector<HTMLButtonElement>(
    '[data-slot="thread-question-context-messages-toggle"]',
  )!;

const settle = (): Promise<void> =>
  act(async () => {
    await Promise.resolve();
  });

const flush = async (): Promise<void> => {
  for (let i = 0; i < 4; i += 1) {
    await settle();
  }
};

const toggle = (): HTMLButtonElement =>
  container.querySelector<HTMLButtonElement>(
    '[data-slot="thread-question-show-context"]',
  )!;

const context = (): HTMLElement | null =>
  container.querySelector<HTMLElement>('[data-slot="thread-question-context"]');

describe('QuestionContextMessages', () => {
  it('reads the messages before the question and draws them expanded, without a press', async () => {
    const reader = vi.fn().mockResolvedValue(MESSAGES);
    draw(reader);

    expect(reader).toHaveBeenCalledWith('thread-1', 'req-1');
    expect(context()?.dataset.state).toBe('loading');
    await settle();

    expect(context()?.dataset.state).toBe('shown');
    expect(
      [
        ...container.querySelectorAll<HTMLElement>(
          '[data-slot="thread-question-context-message"]',
        ),
      ].map((message) => message.dataset.role),
    ).toEqual(['user', 'assistant']);
    expect(toggle().textContent).toBe('Hide messages');
  });

  it('folds the messages on Hide messages, and reads them again on Show a few messages', async () => {
    const reader = vi.fn().mockResolvedValue(MESSAGES);
    draw(reader);
    await settle();

    act(() => toggle().click());
    expect(context()).toBeNull();
    expect(toggle().textContent).toBe('Show a few messages');

    act(() => toggle().click());
    expect(reader).toHaveBeenCalledTimes(2);
    await settle();
    expect(context()?.dataset.state).toBe('shown');
  });

  it('reads the messages of the question it is given', async () => {
    const reader = vi.fn().mockResolvedValue(MESSAGES);
    draw(reader, 'req-1');
    draw(reader, 'req-2');

    expect(reader).toHaveBeenLastCalledWith('thread-1', 'req-2');
  });

  it('says the thread said nothing when no message came before the question', async () => {
    draw(vi.fn().mockResolvedValue([]));
    await settle();

    expect(context()?.textContent).toContain(
      'The thread said nothing before this question.',
    );
  });

  it('says so when the messages cannot be read', async () => {
    draw(() => Promise.reject(new Error('daemon down')));
    await settle();

    expect(context()?.dataset.state).toBe('failed');
  });

  it('draws one Show more for the whole list of messages, and none on a message inside it', async () => {
    draw(vi.fn().mockResolvedValue(LONG_MESSAGES));
    await settle();

    expect(messagesBlock()?.dataset.clamped).toBe('true');
    expect(messagesToggle().textContent).toContain('Show more');
    expect(
      messagesBlock()!.querySelectorAll('[data-slot$="-toggle"]'),
    ).toHaveLength(1);
  });

  it('unfolds every message at once on Show more, and folds the list again on Show less', async () => {
    draw(vi.fn().mockResolvedValue(LONG_MESSAGES));
    await settle();

    act(() => messagesToggle().click());
    expect(messagesBlock()!.dataset.clamped).toBeUndefined();
    expect(container.querySelector('[data-clamped]')).toBeNull();
    expect(
      (messagesBlock()!.firstElementChild as HTMLElement).style.maxHeight,
    ).toBe('');
    expect(messagesToggle().textContent).toContain('Show less');

    act(() => messagesToggle().click());
    expect(messagesBlock()!.dataset.clamped).toBe('true');
    expect(
      (messagesBlock()!.firstElementChild as HTMLElement).style.maxHeight,
    ).toBe('14.4em');
    expect(messagesToggle().textContent).toContain('Show more');
  });

  it('draws no toggle and no clamp when the messages together are short', async () => {
    draw(vi.fn().mockResolvedValue(MESSAGES));
    await settle();

    expect(messagesBlock()).not.toBeNull();
    expect(messagesBlock()!.dataset.clamped).toBeUndefined();
    expect(messagesBlock()!.querySelector('[data-slot$="-toggle"]')).toBeNull();
  });

  it('remembers an expanded list within the thread across a remount, and per question', async () => {
    const reader = vi.fn().mockResolvedValue(LONG_MESSAGES);
    drawInThread(reader, 'req-1');
    await settle();
    act(() => messagesToggle().click());

    act(() => root.render(null));
    drawInThread(reader, 'req-1');
    await settle();
    expect(messagesBlock()!.dataset.clamped).toBeUndefined();
    expect(messagesToggle().textContent).toContain('Show less');

    act(() => root.render(null));
    drawInThread(reader, 'req-2');
    await settle();
    expect(messagesBlock()!.dataset.clamped).toBe('true');
  });

  it('draws the pages and pictures beside the folded messages, never under the fold', async () => {
    draw(
      vi.fn().mockResolvedValue([
        ...LONG_MESSAGES,
        {
          seq: 4,
          artifact: {
            artifactId: 'pr-673-acceptance',
            version: 1,
            title: 'PR #673 — acceptance',
            summary: null,
            key: 'a'.repeat(64),
          },
        },
      ]),
    );
    await settle();

    expect(messagesBlock()?.dataset.clamped).toBe('true');
    const visual = container.querySelector<HTMLElement>(
      '[data-slot="thread-question-context-visual"]',
    );
    expect(visual).not.toBeNull();
    expect(messagesBlock()!.contains(visual)).toBe(false);
    expect(container.querySelector('[data-clamped] iframe')).toBeNull();
    expect(container.querySelector('iframe')).not.toBeNull();
  });

  it('draws a page with no messages before it, and no fold around it', async () => {
    draw(
      vi.fn().mockResolvedValue([
        {
          seq: 4,
          gallery: {
            title: 'Strip screenshots',
            images: [
              {
                path: 'shots/strip.png',
                caption: null,
                description: null,
                source: null,
              },
            ],
          },
        },
      ]),
    );
    await settle();

    expect(messagesBlock()).toBeNull();
    expect(
      container.querySelector('[data-slot="gallery-card"]'),
    ).not.toBeNull();
    expect(context()?.textContent).not.toContain('The thread said nothing');
  });

  it('draws nothing where no reader is provided', () => {
    draw(null);

    expect(container.childElementCount).toBe(0);
  });
});

describe('QuestionContextMessages with the pages and pictures its thread showed', () => {
  const ASKED = itemRow(3, 'approval_request', null, {
    id: 'req-1',
    toolName: 'AskUserQuestion',
  });

  it('frames a page the thread published, at the thread’s own run', async () => {
    drawWith(
      threadContextReaderOf(
        {
          readRunArtifacts: vi.fn(),
          listRunItems: vi.fn().mockResolvedValue({
            items: [
              itemRow(2, 'show_artifact', 'assistant', {
                artifactId: 'pr-673-acceptance',
                version: 1,
                title: 'PR #673 — acceptance',
                key: 'a'.repeat(64),
              }),
              ASKED,
            ],
            anchors: [],
          }),
          listCallMessages: vi.fn(),
          readLocalImage: vi.fn(),
          ...NO_ANSWERS,
        },
        HANDLE,
      ),
    );
    await flush();

    expect(container.querySelector('iframe')?.getAttribute('src')).toContain(
      '/v1/artifacts/thread-1/pr-673-acceptance',
    );
  });

  it('asks the thread’s run for each picture of a gallery the thread showed', async () => {
    const readLocalImage = vi
      .fn()
      .mockResolvedValue({ mediaType: 'image/png', data: 'AAAA' });
    drawWith(
      threadContextReaderOf(
        {
          readRunArtifacts: vi.fn(),
          listRunItems: vi.fn().mockResolvedValue({
            items: [
              itemRow(2, 'show_gallery', 'assistant', {
                title: 'Strip screenshots',
                images: [{ path: 'shots/strip.png' }],
              }),
              ASKED,
            ],
            anchors: [],
          }),
          listCallMessages: vi.fn(),
          readLocalImage,
          ...NO_ANSWERS,
        },
        HANDLE,
      ),
    );
    await flush();

    expect(readLocalImage).toHaveBeenCalledWith({
      runId: 'thread-1',
      path: 'shots/strip.png',
    });
  });

  it('keeps what the user picks on a page the thread showed in the thread’s run, not the run drawing the question', async () => {
    const outer: ArtifactAnswersStore = {
      read: vi.fn().mockResolvedValue({}),
      save: vi.fn(),
      subscribe: vi.fn(() => () => undefined),
    };
    const readArtifactAnswers = vi
      .fn()
      .mockResolvedValue({ values: { choice: 'a' }, updatedAt: null });
    const saveArtifactAnswers = vi
      .fn()
      .mockResolvedValue({ values: { choice: 'b' }, updatedAt: 'now' });
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems: vi.fn().mockResolvedValue({
          items: [
            itemRow(2, 'show_artifact', 'assistant', {
              artifactId: 'pr-673-acceptance',
              version: 1,
              title: 'PR #673 — acceptance',
              key: 'a'.repeat(64),
            }),
            ASKED,
          ],
          anchors: [],
        }),
        listCallMessages: vi.fn(),
        readLocalImage: vi.fn(),
        readArtifactAnswers,
        saveArtifactAnswers,
      },
      HANDLE,
    );
    act(() => {
      root.render(
        <ArtifactAnswersContext.Provider value={outer}>
          <ThreadContextReaderContext.Provider value={reader}>
            <QuestionContextMessages
              threadRunId="thread-1"
              threadRequestId="req-1"
            />
          </ThreadContextReaderContext.Provider>
        </ArtifactAnswersContext.Provider>,
      );
    });
    await flush();
    const frame = container.querySelector('iframe')!;
    const fromPage = async (data: Record<string, unknown>): Promise<void> => {
      await act(async () => {
        window.dispatchEvent(
          new MessageEvent('message', {
            data: { source: 'geniro-artifact', ...data },
            source: frame.contentWindow,
          }),
        );
      });
    };

    await fromPage({ type: 'ready' });
    await flush();
    act(() => frame.focus());
    await fromPage({ type: 'answer', name: 'choice', value: 'b', seq: 1 });
    await act(async () => {
      await new Promise((resolve) => {
        setTimeout(resolve, ANSWERS_SAVE_DELAY_MS + 50);
      });
    });

    expect(readArtifactAnswers).toHaveBeenCalledWith({
      runId: 'thread-1',
      artifactId: 'pr-673-acceptance',
    });
    expect(saveArtifactAnswers).toHaveBeenCalledWith({
      runId: 'thread-1',
      artifactId: 'pr-673-acceptance',
      saveArtifactAnswersDto: { changes: { choice: 'b' } },
    });
    expect(outer.read).not.toHaveBeenCalled();
    expect(outer.save).not.toHaveBeenCalled();
  });

  it('loads a picture a message of the thread names through the thread’s run, not the run drawing the question', async () => {
    const threadLoader = vi.fn().mockResolvedValue(STUB_PICTURE_DATA_URL);
    const loaderFor = vi.fn(() => threadLoader);
    const outerLoader = vi.fn().mockResolvedValue(STUB_PICTURE_DATA_URL);
    act(() => {
      root.render(
        <LocalImageLoaderContext.Provider value={outerLoader}>
          <ThreadContextReaderContext.Provider
            value={stubThreadContextReader(
              () =>
                Promise.resolve([
                  {
                    seq: 2,
                    role: 'assistant',
                    text: 'The strip now ![shot](/tmp/shot.png)',
                  },
                ]),
              { loadImage: loaderFor },
            )}>
            <QuestionContextMessages
              threadRunId="thread-1"
              threadRequestId="req-1"
            />
          </ThreadContextReaderContext.Provider>
        </LocalImageLoaderContext.Provider>,
      );
    });
    await flush();

    expect(loaderFor).toHaveBeenCalledWith('thread-1');
    expect(threadLoader).toHaveBeenCalledWith('/tmp/shot.png');
    expect(outerLoader).not.toHaveBeenCalled();
  });

  it('offers no share control for a page the thread showed, even under a run that shares its own', async () => {
    const sharing: ArtifactSharing = {
      shareOf: () => null,
      share: vi.fn(),
      link: vi.fn(),
      revoke: vi.fn(),
      signIn: {
        startShareSignIn: vi.fn(),
        readShareSignIn: vi.fn(),
        cancelShareSignIn: vi.fn(),
      },
    };
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems: vi.fn().mockResolvedValue({
          items: [
            itemRow(2, 'show_artifact', 'assistant', {
              artifactId: 'pr-673-acceptance',
              version: 1,
              title: 'PR #673 — acceptance',
              key: 'a'.repeat(64),
            }),
            ASKED,
          ],
          anchors: [],
        }),
        listCallMessages: vi.fn(),
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    );
    act(() => {
      root.render(
        <ArtifactShareContext.Provider value={sharing}>
          <ThreadContextReaderContext.Provider value={reader}>
            <QuestionContextMessages
              threadRunId="thread-1"
              threadRequestId="req-1"
            />
          </ThreadContextReaderContext.Provider>
        </ArtifactShareContext.Provider>,
      );
    });
    await flush();

    expect(container.querySelector('iframe')).not.toBeNull();
    expect(container.querySelector('button[aria-label^="Share "]')).toBeNull();
  });
});

describe('a question row that carries its attachments', () => {
  const PLAN = {
    artifactId: 'plan',
    version: 1,
    title: 'Plan',
    summary: null,
    key: 'a'.repeat(64),
  };
  const OTHER = { ...PLAN, artifactId: 'other', title: 'Other page' };

  function drawAttached(
    read: ThreadContextReader['read'],
    attachments: QuestionAttachmentSet | undefined,
  ): void {
    act(() => {
      root.render(
        <ThreadContextReaderContext.Provider
          value={stubThreadContextReader(read, {
            artifacts: () => Promise.resolve([PLAN]),
          })}>
          <QuestionContextMessages
            threadRunId="thread-1"
            threadRequestId="req-1"
            attachments={attachments}
          />
        </ThreadContextReaderContext.Provider>,
      );
    });
  }

  it('draws exactly the attached pages, in place of the pages the asking turn showed', async () => {
    drawAttached(vi.fn().mockResolvedValue([{ seq: 4, artifact: OTHER }]), {
      attachments: [
        { kind: 'artifact', artifactId: 'plan', title: 'Plan', version: 1 },
      ],
      moreAttachments: 0,
    });
    await settle();

    const visuals = container.querySelectorAll('[data-slot="artifact-card"]');
    expect(visuals).toHaveLength(1);
    expect(visuals[0]?.textContent).toContain('Plan');
    expect(container.textContent).not.toContain('Other page');
  });

  it('keeps the pages the asking turn showed for a question written before attachments', async () => {
    drawAttached(
      vi.fn().mockResolvedValue([{ seq: 4, artifact: OTHER }]),
      undefined,
    );
    await settle();

    expect(container.textContent).toContain('Other page');
    expect(
      container.querySelector('[data-slot="thread-question-context-visual"]'),
    ).not.toBeNull();
  });
});
