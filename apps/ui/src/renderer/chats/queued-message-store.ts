import type { SendMessageDtoImagesInner } from '../autogenerated';

/** One message waiting in a run's queue, with the images it carries. */
export interface QueuedMessage {
  id: string;
  text: string;
  images: SendMessageDtoImagesInner[];
}

/** What a reload hands back: the queues, and which of them must not drain. */
export interface RestoredQueueState {
  queues: Record<string, QueuedMessage[]>;
  /**
   * Runs whose queue comes back PAUSED — the ones the user paused, and any
   * whose head was mid-send when the page went away. That message may or may
   * not have reached the daemon (the reply is what was lost), so re-sending it
   * unasked risks the agent being told twice; held, the user can see it in the
   * strip beside the transcript that says whether it landed, and release it.
   */
  paused: ReadonlySet<string>;
}

/** Everything a write needs to say about the composer's queues. */
export interface QueueStateToStore {
  queues: Readonly<Record<string, readonly QueuedMessage[]>>;
  paused: ReadonlySet<string>;
  /** The message each run's drain has in flight, by run id. */
  sending: Readonly<Record<string, string>>;
}

const STORAGE_KEY = 'geniro.queuedMessages';

/**
 * The composer's queues, kept in the browser's storage as well as in memory.
 *
 * The composer is CLEARED the moment a message is queued, so with the queues
 * in component state alone anything that reloads the page between the queue
 * and its drain loses the message outright, with nothing on screen saying it
 * had ever existed. On a phone that is routine rather than rare: the app runs
 * in a browser tab there, and iOS discards a background tab whenever the user
 * switches apps or locks the screen.
 *
 * The PAUSE and the in-flight head are stored beside the messages, for the
 * reason {@link RestoredQueueState.paused} gives: without them a reload would
 * turn a held queue into one that drains by itself, and re-send a head whose
 * send had already reached the agent.
 *
 * Every read and write is guarded: storage can be absent, full, or refuse
 * outright (a private window), and a queue that could not be saved must still
 * WORK — it simply stops surviving a reload.
 */
export function readStoredQueueState(): RestoredQueueState {
  const empty: RestoredQueueState = { queues: {}, paused: new Set() };
  let raw: string | null;
  try {
    raw = localStorage.getItem(STORAGE_KEY);
  } catch {
    return empty;
  }
  if (raw === null) {
    return empty;
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch {
    return empty;
  }
  if (typeof parsed !== 'object' || parsed === null) {
    return empty;
  }
  const stored = parsed as {
    queues?: unknown;
    paused?: unknown;
    sending?: unknown;
  };
  const queues: Record<string, QueuedMessage[]> = {};
  if (typeof stored.queues === 'object' && stored.queues !== null) {
    for (const [runId, list] of Object.entries(stored.queues)) {
      if (!Array.isArray(list)) {
        continue;
      }
      const messages = list.filter(isQueuedMessage);
      if (messages.length > 0) {
        queues[runId] = messages;
      }
    }
  }
  const paused = new Set<string>();
  if (Array.isArray(stored.paused)) {
    for (const runId of stored.paused) {
      if (typeof runId === 'string' && queues[runId] !== undefined) {
        paused.add(runId);
      }
    }
  }
  if (typeof stored.sending === 'object' && stored.sending !== null) {
    for (const [runId, id] of Object.entries(stored.sending)) {
      if (queues[runId]?.some((message) => message.id === id)) {
        paused.add(runId);
      }
    }
  }
  return { queues, paused };
}

/**
 * Save the queues. Images are base64 and can overrun the storage quota, so a
 * write that is refused is retried with the TEXT alone — the words are most of
 * a message, and keeping them beats keeping nothing. A pause is only stored for
 * a run that still has a queue, so it can never outlive the messages it held.
 */
export function writeStoredQueueState(state: QueueStateToStore): void {
  const queues = Object.fromEntries(
    Object.entries(state.queues).filter(([, list]) => list.length > 0),
  );
  const paused = [...state.paused].filter((runId) => runId in queues);
  const sending = Object.fromEntries(
    Object.entries(state.sending).filter(([runId]) => runId in queues),
  );
  try {
    if (Object.keys(queues).length === 0) {
      localStorage.removeItem(STORAGE_KEY);
      return;
    }
    localStorage.setItem(
      STORAGE_KEY,
      JSON.stringify({ queues, paused, sending }),
    );
  } catch {
    try {
      const textOnly = Object.fromEntries(
        Object.entries(queues).map(([runId, list]) => [
          runId,
          list.map((message) => ({ ...message, images: [] })),
        ]),
      );
      localStorage.setItem(
        STORAGE_KEY,
        JSON.stringify({ queues: textOnly, paused, sending }),
      );
    } catch {
      // Storage is unavailable: the in-memory queue still works.
    }
  }
}

function isQueuedMessage(value: unknown): value is QueuedMessage {
  if (typeof value !== 'object' || value === null) {
    return false;
  }
  const candidate = value as Partial<QueuedMessage>;
  return (
    typeof candidate.id === 'string' &&
    typeof candidate.text === 'string' &&
    Array.isArray(candidate.images)
  );
}
