import type { ChatsApi, RunDto, TeamsApi } from '../autogenerated';

/**
 * One run by id, chat or team run alike, asked of both listings so it is
 * projected exactly as a listing projects it; undefined when neither has it.
 */
export async function readRunById(
  chatApi: Pick<ChatsApi, 'listChats'>,
  teamApi: Pick<TeamsApi, 'listTeamRuns'>,
  runId: string,
): Promise<RunDto | undefined> {
  const [chats, teamRuns] = await Promise.all([
    chatApi.listChats({ scope: 'all', runId }),
    teamApi.listTeamRuns({ scope: 'all', runId }),
  ]);
  return [...chats, ...teamRuns].find((run) => run.id === runId);
}
