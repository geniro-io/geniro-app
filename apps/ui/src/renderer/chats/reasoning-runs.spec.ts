import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { withReasoningRuns } from './reasoning-runs';
import type { TranscriptEntry } from './transcript-groups';

function entry(
  seq: number,
  kind: ChatItem['kind'],
  payload: unknown,
  memberId: string | null = 'engineer',
): TranscriptEntry {
  return {
    type: 'item',
    item: {
      id: `i${seq}`,
      runId: 'run-1',
      memberId,
      seq,
      kind,
      role: kind === 'message' ? 'assistant' : null,
      payload,
      createdAt: '2026-11-03T22:10:00.000Z',
    },
  };
}

const heading = (seq: number, ...titles: string[]): TranscriptEntry =>
  entry(seq, 'reasoning', {
    text: titles.map((title) => `**${title}**`).join('\n\n'),
  });

function shape(pieces: ReturnType<typeof withReasoningRuns>): unknown[] {
  return pieces.map((piece) =>
    piece.type === 'reasoning-run'
      ? { run: piece.id, headings: piece.headings }
      : piece.type === 'item'
        ? piece.item.id
        : piece.type,
  );
}

describe('withReasoningRuns', () => {
  it('folds back-to-back heading-only rows into one run of every heading', () => {
    const pieces = withReasoningRuns([
      entry(1, 'message', { text: 'Stand is up.' }),
      heading(2, 'Updating handoff pointer'),
      heading(3, 'Reviewing test logs', 'Recording keeper need'),
      heading(4, 'Listing changed files'),
      entry(5, 'message', { text: 'Done.' }),
    ]);

    expect(shape(pieces)).toEqual([
      'i1',
      {
        run: 'i2',
        headings: [
          'Updating handoff pointer',
          'Reviewing test logs',
          'Recording keeper need',
          'Listing changed files',
        ],
      },
      'i5',
    ]);
  });

  it('leaves a lone heading row where it is', () => {
    const pieces = withReasoningRuns([
      heading(1, 'Checking notes', 'Summarizing limits'),
      entry(2, 'message', { text: 'Stand is up.' }),
      heading(3, 'Revising the note format'),
    ]);

    expect(shape(pieces)).toEqual(['i1', 'i2', 'i3']);
  });

  it('never folds reasoning written as prose, nor the live thinking row', () => {
    const pieces = withReasoningRuns([
      entry(1, 'reasoning', { text: 'I need to check the stand first.' }),
      heading(2, 'Checking the stand'),
      entry(3, 'reasoning', { live: 'thinking', thinkingSince: 1 }),
      heading(4, 'Listing files'),
      entry(5, 'reasoning', { text: 'Then report.' }),
    ]);

    expect(shape(pieces)).toEqual(['i1', 'i2', 'i3', 'i4', 'i5']);
  });

  it('splits a run where the thread changes', () => {
    const pieces = withReasoningRuns([
      heading(1, 'One'),
      heading(2, 'Two'),
      entry(3, 'reasoning', { text: '**Three**' }, 'qa'),
      entry(4, 'reasoning', { text: '**Four**' }, 'qa'),
    ]);

    expect(shape(pieces)).toEqual([
      { run: 'i1', headings: ['One', 'Two'] },
      { run: 'i3', headings: ['Three', 'Four'] },
    ]);
  });

  it('ends a run at a tool group between two thoughts', () => {
    const pieces = withReasoningRuns([
      heading(1, 'One'),
      heading(2, 'Two'),
      { type: 'tools', id: 'g', pairs: [] } as unknown as TranscriptEntry,
      heading(4, 'Four'),
    ]);

    expect(shape(pieces)).toEqual([
      { run: 'i1', headings: ['One', 'Two'] },
      'tools',
      'i4',
    ]);
  });
});
