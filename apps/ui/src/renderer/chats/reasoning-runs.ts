import type { ItemDto as ChatItem } from '../autogenerated';
import { liveRowKind } from './live-row';
import { subagentIdOf } from './subagent-payload';
import { reasoningHeadings } from './thinking-block';
import type { ItemEntry, TranscriptEntry } from './transcript-groups';

export const REASONING_RUN_MIN_ROWS = 2;

export interface ReasoningRun {
  type: 'reasoning-run';
  id: string;
  entries: ItemEntry[];
  headings: string[];
}

export type ReasoningRunPiece = TranscriptEntry | ReasoningRun;

export function reasoningRunFoldKey(run: ReasoningRun): string {
  return `thinking-run:${run.id}`;
}

function headingsOf(entry: TranscriptEntry): string[] | null {
  if (entry.type !== 'item' || entry.continuedIn !== undefined) {
    return null;
  }
  const item = entry.item;
  if (item.kind !== 'reasoning' || liveRowKind(item.payload) !== null) {
    return null;
  }
  const text = (item.payload as { text?: unknown } | null)?.text;
  return typeof text === 'string' ? reasoningHeadings(text) : null;
}

function sameThread(a: ChatItem, b: ChatItem): boolean {
  return a.memberId === b.memberId && subagentIdOf(a) === subagentIdOf(b);
}

export function withReasoningRuns(
  entries: readonly TranscriptEntry[],
): ReasoningRunPiece[] {
  const out: ReasoningRunPiece[] = [];
  let run: { entries: ItemEntry[]; headings: string[] } | null = null;
  const close = (): void => {
    if (run === null) {
      return;
    }
    if (run.entries.length >= REASONING_RUN_MIN_ROWS) {
      out.push({
        type: 'reasoning-run',
        id: run.entries[0]!.item.id,
        entries: run.entries,
        headings: run.headings,
      });
    } else {
      out.push(...run.entries);
    }
    run = null;
  };
  for (const entry of entries) {
    const headings = headingsOf(entry);
    if (headings === null || entry.type !== 'item') {
      close();
      out.push(entry);
      continue;
    }
    const last = run?.entries[run.entries.length - 1];
    if (
      run !== null &&
      last !== undefined &&
      !sameThread(last.item, entry.item)
    ) {
      close();
    }
    run ??= { entries: [], headings: [] };
    run.entries.push(entry);
    run.headings.push(...headings);
  }
  close();
  return out;
}
