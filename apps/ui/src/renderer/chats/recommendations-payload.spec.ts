import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  readApply,
  readRecommendationOutcomes,
  readRecommendations,
} from './recommendations-payload';
import { groupTranscript } from './transcript-groups';

function item(
  seq: number,
  kind: string,
  payload: unknown,
  role: string | null = null,
): ChatItem {
  return {
    id: `i${seq}`,
    runId: 'analysis',
    seq,
    kind,
    role,
    nodeId: null,
    payload,
    createdAt: new Date(Date.UTC(2026, 9, 14, 10, 0, seq)).toISOString(),
  } as unknown as ChatItem;
}

const CARD = {
  sourceRunId: 'source',
  sourceKind: 'workflow',
  summary: 'reviewers ran serially',
  timing: {
    wallMs: 1000,
    activeMs: 800,
    waitingMs: 100,
    criticalPathMs: 900,
    sinks: [{ label: 'reviewer', ms: 600 }],
  },
  items: [
    {
      id: 'W-1',
      target: 'workflow',
      territory: 'process',
      kind: 'parallelize',
      location: 'reviewer',
      title: 'Parallel reviewers',
      change: 'edges: …',
      evidence: [{ seq: 4, quote: 'waiting' }],
      rootCause: 'serial',
      impact: { minutesSaved: 12, basis: 'critical path', confidence: 4 },
      risk: { level: 'low', note: 'none' },
    },
    {
      id: 'U-1',
      target: 'user',
      territory: 'domain',
      kind: 'pointer',
      location: '~/.claude/CLAUDE.md',
      title: 'Name the check command',
      change: 'WHEN … → …',
      evidence: [{ runId: 'run-older', seq: 4, quote: 'waiting' }],
      rootCause: 'guessed',
      impact: { minutesSaved: 2, basis: 'one retry', confidence: 3 },
      risk: { level: 'low', note: 'none' },
    },
    { id: 'W-2' },
  ],
};

describe('recommendations payload readers', () => {
  it('reads a card and drops an item that does not read', () => {
    const card = readRecommendations(item(5, 'recommendations', CARD));

    expect(card?.sourceKind).toBe('workflow');
    expect(card?.timing?.sinks).toEqual([{ label: 'reviewer', ms: 600 }]);
    expect(card?.items.map((entry) => entry.id)).toEqual(['W-1', 'U-1']);
    expect(card?.items[1]?.target).toBe('user');
    expect(card?.items[0]).toMatchObject({ minutesSaved: 12, risk: 'low' });
    // A workflow analysis names the run each quote is from.
    expect(card?.items[1]?.evidence[0]?.runId).toBe('run-older');
    expect(card?.items[0]?.evidence[0]?.runId).toBeNull();
  });

  it('reads a memory item, and still drops an item whose target is unknown', () => {
    const [w1] = CARD.items as Record<string, unknown>[];
    const card = readRecommendations(
      item(5, 'recommendations', {
        ...CARD,
        items: [
          {
            ...w1,
            id: 'M-1',
            target: 'memory',
            kind: 'update',
            location: 'm12',
          },
          { ...w1, id: 'W-2', target: 'skill' },
        ],
      }),
    );

    expect(card?.items.map((entry) => [entry.id, entry.target])).toEqual([
      ['M-1', 'memory'],
    ]);
    expect(card?.items[0]).toMatchObject({ kind: 'update', location: 'm12' });
  });

  it("reads the workflow's measured figures, the hotspots and each item's estimates, an older card's missing ones as absent", () => {
    const filed = readRecommendations(
      item(6, 'recommendations', {
        ...CARD,
        timing: null,
        hotspots: [
          {
            title: 'Serial reviews',
            node: 'reviewer',
            why: 'waits on itself',
            items: ['W-1', 7],
          },
          { title: 'no why' },
        ],
        items: [
          {
            ...CARD.items[0],
            impact: {
              minutesSaved: -3,
              costSavedUsd: -0.2,
              basis: 'one more pass',
              confidence: 3,
              outcome: 'bugs caught before review',
            },
          },
        ],
        workflowStats: {
          runs: 2,
          perRun: {
            wallMs: 60_000,
            activeMs: 50_000,
            waitingOnUserMs: 0,
            criticalPathMs: 40_000,
            turns: 4.5,
            calls: 1,
            costUsd: null,
            pricedRuns: 0,
          },
          totals: {
            wallMs: 120_000,
            activeMs: 100_000,
            turns: 9,
            failedTurns: 1,
            cancelledTurns: 0,
            toolCalls: 30,
            failedToolCalls: 2,
            calls: 2,
            costUsd: null,
          },
          runList: [
            {
              runId: 'r1',
              title: null,
              createdAt: '2026-10-14T10:00:00.000Z',
              version: 3,
              current: true,
              wallMs: 60_000,
              activeMs: 50_000,
              waitingOnUserMs: 0,
              turns: 5,
              failedTurns: 1,
              costUsd: null,
            },
            { runId: 'broken' },
          ],
          agents: [
            {
              node: 'reviewer',
              agent: 'claude',
              runs: 2,
              turns: 9,
              failedTurns: 1,
              cancelledTurns: 0,
              workedMs: 90_000,
              workedPerRunMs: 45_000,
              waitingOnCalleePerRunMs: null,
              criticalPathPerRunMs: 20_000,
              toolCalls: 30,
              failedToolCalls: 2,
              costUsd: null,
              costPerRunUsd: null,
              models: [
                {
                  agent: 'claude',
                  model: null,
                  modelSource: 'configured',
                  turns: 9,
                  failedTurns: 1,
                  cancelledTurns: 0,
                  avgTurnMs: null,
                  costUsd: null,
                  costPerTurnUsd: null,
                },
              ],
            },
          ],
          calls: [],
        },
      }),
    );
    const older = readRecommendations(item(5, 'recommendations', CARD));

    expect(filed?.hotspots).toEqual([
      {
        title: 'Serial reviews',
        node: 'reviewer',
        why: 'waits on itself',
        items: ['W-1'],
      },
    ]);
    expect(filed?.items[0]).toMatchObject({
      minutesSaved: -3,
      costSavedUsd: -0.2,
      outcome: 'bugs caught before review',
    });
    expect(filed?.workflowStats).toMatchObject({
      runs: 2,
      perRun: { wallMs: 60_000, costUsd: null, pricedRuns: 0 },
      totals: { failedTurns: 1, costUsd: null },
      runList: [{ runId: 'r1', version: 3, current: true, costUsd: null }],
      callEdges: 0,
      agents: [
        {
          node: 'reviewer',
          workedMs: 90_000,
          workedPerRunMs: 45_000,
          waitingOnCalleePerRunMs: null,
          models: [{ model: null, modelSource: 'configured' }],
        },
      ],
    });
    expect(older?.workflowStats).toBeNull();
    expect(older?.hotspots).toEqual([]);
    expect(older?.items[0]).toMatchObject({
      minutesSaved: 12,
      costSavedUsd: null,
      outcome: null,
    });
  });

  it('reads figures that do not read as no figures, never as zeros', () => {
    const card = readRecommendations(
      item(6, 'recommendations', {
        ...CARD,
        workflowStats: { runs: 2, perRun: { wallMs: 'slow' }, totals: {} },
      }),
    );

    expect(card?.workflowStats).toBeNull();
  });

  it("reads each item's territory, and drops an item that names none or another", () => {
    const [w1, u1] = CARD.items as Record<string, unknown>[];
    const { territory: _omitted, ...untagged } = w1!;
    const card = readRecommendations(
      item(5, 'recommendations', {
        ...CARD,
        items: [
          { ...untagged, id: 'W-1' },
          { ...w1, id: 'W-2', territory: 'both' },
          u1,
        ],
      }),
    );

    expect(card?.items.map((entry) => [entry.id, entry.territory])).toEqual([
      ['U-1', 'domain'],
    ]);
  });

  it('reads a card none of whose items read as no card, never as an empty one', () => {
    const untagged = (CARD.items as Record<string, unknown>[]).map(
      ({ territory: _omitted, ...rest }) => rest,
    );

    expect(
      readRecommendations(
        item(5, 'recommendations', { ...CARD, items: untagged }),
      ),
    ).toBeNull();
    expect(
      readRecommendations(item(5, 'recommendations', { ...CARD, items: [] }))
        ?.items,
    ).toEqual([]);
  });

  it('reads an Apply only off a user message', () => {
    const apply = { cardSeq: 5, ids: ['W-1'] };
    expect(
      readApply(item(6, 'message', { text: 'apply', apply }, 'user')),
    ).toEqual(apply);
    expect(
      readApply(item(6, 'message', { text: 'apply', apply }, 'assistant')),
    ).toBeNull();
  });

  it('reads outcomes keyed by id', () => {
    expect(
      readRecommendationOutcomes(
        item(9, 'recommendation_outcome', {
          cardSeq: 5,
          outcomes: [
            { id: 'W-1', status: 'applied', backup: '.backups/x.yaml' },
          ],
        }),
      ),
    ).toEqual({
      cardSeq: 5,
      outcomes: {
        'W-1': { status: 'applied', note: null, backup: '.backups/x.yaml' },
      },
    });
  });
});

describe('groupTranscript with an analysis card', () => {
  it('folds the Apply and the outcomes into the card, and draws no outcome row', () => {
    const entries = groupTranscript([
      item(5, 'recommendations', CARD),
      item(
        6,
        'message',
        { text: 'apply', apply: { cardSeq: 5, ids: ['W-1'] } },
        'user',
      ),
      item(9, 'recommendation_outcome', {
        cardSeq: 5,
        outcomes: [{ id: 'W-1', status: 'failed', note: 'hash drift' }],
      }),
    ]);

    const card = entries.find((entry) => entry.type === 'recommendations');
    expect(card).toMatchObject({
      seq: 5,
      runId: 'analysis',
      applied: ['W-1'],
      outcomes: {
        'W-1': { status: 'failed', note: 'hash drift', backup: null },
      },
    });
    expect(
      entries.some(
        (entry) =>
          entry.type === 'item' && entry.item.kind === 'recommendation_outcome',
      ),
    ).toBe(false);
  });
});
