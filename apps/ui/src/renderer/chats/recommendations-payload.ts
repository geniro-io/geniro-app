import type { ItemDto as ChatItem } from '../autogenerated';
import type {
  RecommendationHotspotView,
  RecommendationOutcomeStatus,
  RecommendationOutcomeView,
  RecommendationRisk,
  RecommendationsTimingView,
  RecommendationTerritory,
  RecommendationView,
} from '../components/recommendations-card';
import type {
  WorkflowAgentStatsView,
  WorkflowCallStatsView,
  WorkflowModelStatsView,
  WorkflowRunStatsView,
  WorkflowStatsView,
} from '../components/recommendations-figures';

/**
 * Readers over the analysis rows: a `recommendations` card, its
 * `recommendation_outcome` marks, and the `apply` selection a user message
 * carries.
 *
 * TWIN PARSER: apps/daemon/src/v1/agents/chat.types.ts —
 * `RecommendationsPayloadSchema` (with `RecommendationsWorkflowStatsSchema`),
 * `RecommendationMarksSchema` (the outcome rows) and
 * `RecommendationApplySchema`. The daemon validates before it writes, so these
 * are defensive rather than strict: an entry that does not read is dropped, and
 * a row that does not read as its kind at all answers null.
 */

export interface RecommendationsCardData {
  summary: string | null;
  timing: RecommendationsTimingView | null;
  workflowStats: WorkflowStatsView | null;
  hotspots: RecommendationHotspotView[];
  sourceKind: 'workflow' | 'chat';
  items: RecommendationView[];
}

export interface RecommendationOutcomes {
  cardSeq: number;
  outcomes: Record<string, RecommendationOutcomeView>;
}

export interface RecommendationApplyData {
  cardSeq: number;
  ids: string[];
}

const RISKS: readonly RecommendationRisk[] = ['low', 'medium', 'high'];
const TERRITORIES: readonly RecommendationTerritory[] = ['process', 'domain'];
const STATUSES: readonly RecommendationOutcomeStatus[] = [
  'applied',
  'skipped',
  'failed',
];

function record(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

function text(value: unknown): string | null {
  return typeof value === 'string' && value.trim() !== '' ? value : null;
}

function count(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) && value >= 0
    ? value
    : null;
}

function signed(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

function counts<K extends string>(
  row: Record<string, unknown> | null,
  keys: readonly K[],
): Record<K, number> | null {
  if (row === null) {
    return null;
  }
  const out = {} as Record<K, number>;
  for (const key of keys) {
    const value = count(row[key]);
    if (value === null) {
      return null;
    }
    out[key] = value;
  }
  return out;
}

function list<T>(value: unknown, read: (entry: unknown) => T | null): T[] {
  return Array.isArray(value)
    ? value.flatMap((entry) => {
        const parsed = read(entry);
        return parsed === null ? [] : [parsed];
      })
    : [];
}

function oneOf<T extends string>(
  value: unknown,
  allowed: readonly T[],
): T | null {
  return typeof value === 'string' &&
    (allowed as readonly string[]).includes(value)
    ? (value as T)
    : null;
}

function readTiming(value: unknown): RecommendationsTimingView | null {
  const row = record(value);
  if (row === null) {
    return null;
  }
  const wallMs = count(row.wallMs);
  const activeMs = count(row.activeMs);
  const waitingMs = count(row.waitingMs);
  const criticalPathMs = count(row.criticalPathMs);
  if (
    wallMs === null ||
    activeMs === null ||
    waitingMs === null ||
    criticalPathMs === null
  ) {
    return null;
  }
  const sinks = Array.isArray(row.sinks)
    ? row.sinks.flatMap((entry) => {
        const sink = record(entry);
        const label = text(sink?.label);
        const ms = count(sink?.ms);
        return label === null || ms === null ? [] : [{ label, ms }];
      })
    : [];
  return { wallMs, activeMs, waitingMs, criticalPathMs, sinks };
}

function readRun(value: unknown): WorkflowRunStatsView | null {
  const row = record(value);
  const runId = text(row?.runId);
  const createdAt = text(row?.createdAt);
  const figures = counts(row, [
    'wallMs',
    'activeMs',
    'waitingOnUserMs',
    'turns',
    'failedTurns',
  ] as const);
  if (row === null || runId === null || createdAt === null || !figures) {
    return null;
  }
  return {
    runId,
    title: text(row.title),
    createdAt,
    version: count(row.version),
    current: row.current === true,
    ...figures,
    costUsd: count(row.costUsd),
  };
}

function readModel(value: unknown): WorkflowModelStatsView | null {
  const row = record(value);
  const figures = counts(row, [
    'turns',
    'failedTurns',
    'cancelledTurns',
  ] as const);
  if (row === null || !figures) {
    return null;
  }
  return {
    agent: text(row.agent),
    model: text(row.model),
    modelSource:
      oneOf(row.modelSource, ['reported', 'configured', 'unreported']) ??
      'reported',
    ...figures,
    avgTurnMs: count(row.avgTurnMs),
    costUsd: count(row.costUsd),
    costPerTurnUsd: count(row.costPerTurnUsd),
  };
}

function readAgent(value: unknown): WorkflowAgentStatsView | null {
  const row = record(value);
  const node = text(row?.node);
  const figures = counts(row, [
    'runs',
    'turns',
    'failedTurns',
    'cancelledTurns',
    'toolCalls',
    'failedToolCalls',
  ] as const);
  if (row === null || node === null || !figures) {
    return null;
  }
  return {
    node,
    agent: text(row.agent),
    ...figures,
    workedMs: count(row.workedMs),
    workedPerRunMs: count(row.workedPerRunMs),
    waitingOnCalleePerRunMs: count(row.waitingOnCalleePerRunMs),
    criticalPathPerRunMs: count(row.criticalPathPerRunMs),
    costUsd: count(row.costUsd),
    costPerRunUsd: count(row.costPerRunUsd),
    models: list(row.models, readModel),
  };
}

function readCall(value: unknown): WorkflowCallStatsView | null {
  const row = record(value);
  const caller = text(row?.caller);
  const callee = text(row?.callee);
  const figures = counts(row, [
    'calls',
    'failedCalls',
    'totalMs',
    'avgMs',
    'maxMs',
  ] as const);
  return caller === null || callee === null || !figures
    ? null
    : { caller, callee, ...figures, workedMs: count(row?.workedMs) };
}

function readWorkflowStats(value: unknown): WorkflowStatsView | null {
  const row = record(value);
  const runs = count(row?.runs);
  const perRunRow = record(row?.perRun);
  const perRun = counts(perRunRow, [
    'wallMs',
    'activeMs',
    'waitingOnUserMs',
    'criticalPathMs',
    'turns',
    'calls',
    'pricedRuns',
  ] as const);
  const totalsRow = record(row?.totals);
  const totals = counts(totalsRow, [
    'wallMs',
    'activeMs',
    'turns',
    'failedTurns',
    'cancelledTurns',
    'toolCalls',
    'failedToolCalls',
    'calls',
  ] as const);
  if (row === null || runs === null || !perRun || !totals) {
    return null;
  }
  const calls = list(row.calls, readCall);
  return {
    runs,
    perRun: { ...perRun, costUsd: count(perRunRow?.costUsd) },
    totals: { ...totals, costUsd: count(totalsRow?.costUsd) },
    runList: list(row.runList, readRun),
    agents: list(row.agents, readAgent),
    callEdges: count(row.callEdges) ?? calls.length,
    calls,
  };
}

function readHotspot(value: unknown): RecommendationHotspotView | null {
  const row = record(value);
  const title = text(row?.title);
  const why = text(row?.why);
  if (row === null || title === null || why === null) {
    return null;
  }
  return {
    title,
    node: text(row.node),
    why,
    items: Array.isArray(row.items)
      ? row.items.filter((id): id is string => typeof id === 'string')
      : [],
  };
}

function readItem(value: unknown): RecommendationView | null {
  const row = record(value);
  const id = text(row?.id);
  const target = oneOf(row?.target, [
    'workflow',
    'repo',
    'user',
    'memory',
  ] as const);
  const territory = oneOf(row?.territory, TERRITORIES);
  const title = text(row?.title);
  const change = text(row?.change);
  if (
    row === null ||
    id === null ||
    target === null ||
    territory === null ||
    title === null ||
    change === null
  ) {
    return null;
  }
  const impact = record(row.impact);
  const risk = record(row.risk);
  const evidence = Array.isArray(row.evidence)
    ? row.evidence.flatMap((entry) => {
        const ev = record(entry);
        const seq = count(ev?.seq);
        const quote = text(ev?.quote);
        return seq === null || quote === null
          ? []
          : [
              {
                runId: text(ev?.runId),
                seq,
                quote,
                ts: text(ev?.ts),
                nodeId: text(ev?.nodeId),
              },
            ];
      })
    : [];
  return {
    id,
    target,
    territory,
    title,
    change,
    kind: text(row.kind) ?? '',
    location: text(row.location) ?? '',
    evidence,
    rootCause: text(row.rootCause) ?? '',
    minutesSaved: signed(impact?.minutesSaved) ?? 0,
    costSavedUsd: signed(impact?.costSavedUsd),
    outcome: text(impact?.outcome),
    basis: text(impact?.basis) ?? '',
    confidence: count(impact?.confidence) ?? 0,
    risk: oneOf(risk?.level, RISKS) ?? 'medium',
    riskNote: text(risk?.note) ?? '',
  };
}

/** One `recommendations` row, or null when it does not read as one. */
export function readRecommendations(
  item: ChatItem,
): RecommendationsCardData | null {
  const row = record(item.payload);
  if (row === null || !Array.isArray(row.items)) {
    return null;
  }
  const items = row.items
    .map(readItem)
    .filter((entry): entry is RecommendationView => entry !== null);
  // Items that all fail to read are not "no recommendations": drawn, the card
  // would claim nothing was found worth changing.
  if (items.length === 0 && row.items.length > 0) {
    return null;
  }
  return {
    summary: text(row.summary),
    timing: readTiming(row.timing),
    workflowStats: readWorkflowStats(row.workflowStats),
    hotspots: list(row.hotspots, readHotspot),
    sourceKind: row.sourceKind === 'workflow' ? 'workflow' : 'chat',
    items,
  };
}

/** One `recommendation_outcome` row, or null. */
export function readRecommendationOutcomes(
  item: ChatItem,
): RecommendationOutcomes | null {
  const row = record(item.payload);
  const cardSeq = count(row?.cardSeq);
  if (row === null || cardSeq === null || !Array.isArray(row.outcomes)) {
    return null;
  }
  const outcomes: Record<string, RecommendationOutcomeView> = {};
  for (const entry of row.outcomes) {
    const mark = record(entry);
    const id = text(mark?.id);
    const status = oneOf(mark?.status, STATUSES);
    if (id !== null && status !== null) {
      outcomes[id] = {
        status,
        note: text(mark?.note),
        backup: text(mark?.backup),
      };
    }
  }
  return { cardSeq, outcomes };
}

/** The `apply` selection a user message carries, or null. */
export function readApply(item: ChatItem): RecommendationApplyData | null {
  if (item.kind !== 'message' || item.role !== 'user') {
    return null;
  }
  const apply = record(record(item.payload)?.apply);
  const cardSeq = count(apply?.cardSeq);
  if (apply === null || cardSeq === null || !Array.isArray(apply.ids)) {
    return null;
  }
  const ids = apply.ids.filter((id): id is string => typeof id === 'string');
  return ids.length === 0 ? null : { cardSeq, ids };
}
