import type { ItemDto as ChatItem } from '../autogenerated';
import type {
  RecommendationOutcomeStatus,
  RecommendationOutcomeView,
  RecommendationRisk,
  RecommendationsTimingView,
  RecommendationTerritory,
  RecommendationView,
} from '../components/recommendations-card';

/**
 * Readers over the analysis rows: a `recommendations` card, its
 * `recommendation_outcome` marks, and the `apply` selection a user message
 * carries.
 *
 * TWIN PARSER: apps/daemon/src/v1/agents/chat.types.ts —
 * `RecommendationsPayloadSchema`, `RecommendationMarksSchema` (the outcome
 * rows) and `RecommendationApplySchema`. The daemon validates before it writes, so these
 * are defensive rather than strict: an entry that does not read is dropped, and
 * a row that does not read as its kind at all answers null.
 */

export interface RecommendationsCardData {
  summary: string | null;
  timing: RecommendationsTimingView | null;
  sourceKind: 'workflow' | 'chat';
  items: RecommendationView[];
}

export interface RecommendationOutcomes {
  cardSeq: number;
  outcomes: Record<string, RecommendationOutcomeView>;
}

export interface RecommendationApplyData {
  cardSeq: number;
  ids: string[];
}

const RISKS: readonly RecommendationRisk[] = ['low', 'medium', 'high'];
const TERRITORIES: readonly RecommendationTerritory[] = ['process', 'domain'];
const STATUSES: readonly RecommendationOutcomeStatus[] = [
  'applied',
  'skipped',
  'failed',
];

function record(value: unknown): Record<string, unknown> | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

function text(value: unknown): string | null {
  return typeof value === 'string' && value.trim() !== '' ? value : null;
}

function count(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) && value >= 0
    ? value
    : null;
}

function oneOf<T extends string>(
  value: unknown,
  allowed: readonly T[],
): T | null {
  return typeof value === 'string' &&
    (allowed as readonly string[]).includes(value)
    ? (value as T)
    : null;
}

function readTiming(value: unknown): RecommendationsTimingView | null {
  const row = record(value);
  if (row === null) {
    return null;
  }
  const wallMs = count(row.wallMs);
  const activeMs = count(row.activeMs);
  const waitingMs = count(row.waitingMs);
  const criticalPathMs = count(row.criticalPathMs);
  if (
    wallMs === null ||
    activeMs === null ||
    waitingMs === null ||
    criticalPathMs === null
  ) {
    return null;
  }
  const sinks = Array.isArray(row.sinks)
    ? row.sinks.flatMap((entry) => {
        const sink = record(entry);
        const label = text(sink?.label);
        const ms = count(sink?.ms);
        return label === null || ms === null ? [] : [{ label, ms }];
      })
    : [];
  return { wallMs, activeMs, waitingMs, criticalPathMs, sinks };
}

function readItem(value: unknown): RecommendationView | null {
  const row = record(value);
  const id = text(row?.id);
  const target = oneOf(row?.target, ['workflow', 'repo', 'user'] as const);
  const territory = oneOf(row?.territory, TERRITORIES);
  const title = text(row?.title);
  const change = text(row?.change);
  if (
    row === null ||
    id === null ||
    target === null ||
    territory === null ||
    title === null ||
    change === null
  ) {
    return null;
  }
  const impact = record(row.impact);
  const risk = record(row.risk);
  const evidence = Array.isArray(row.evidence)
    ? row.evidence.flatMap((entry) => {
        const ev = record(entry);
        const seq = count(ev?.seq);
        const quote = text(ev?.quote);
        return seq === null || quote === null
          ? []
          : [
              {
                runId: text(ev?.runId),
                seq,
                quote,
                ts: text(ev?.ts),
                nodeId: text(ev?.nodeId),
              },
            ];
      })
    : [];
  return {
    id,
    target,
    territory,
    title,
    change,
    kind: text(row.kind) ?? '',
    location: text(row.location) ?? '',
    evidence,
    rootCause: text(row.rootCause) ?? '',
    minutesSaved: count(impact?.minutesSaved) ?? 0,
    basis: text(impact?.basis) ?? '',
    confidence: count(impact?.confidence) ?? 0,
    risk: oneOf(risk?.level, RISKS) ?? 'medium',
    riskNote: text(risk?.note) ?? '',
  };
}

/** One `recommendations` row, or null when it does not read as one. */
export function readRecommendations(
  item: ChatItem,
): RecommendationsCardData | null {
  const row = record(item.payload);
  if (row === null || !Array.isArray(row.items)) {
    return null;
  }
  const items = row.items
    .map(readItem)
    .filter((entry): entry is RecommendationView => entry !== null);
  // Items that all fail to read are not "no recommendations": drawn, the card
  // would claim the thread ran efficiently.
  if (items.length === 0 && row.items.length > 0) {
    return null;
  }
  return {
    summary: text(row.summary),
    timing: readTiming(row.timing),
    sourceKind: row.sourceKind === 'workflow' ? 'workflow' : 'chat',
    items,
  };
}

/** One `recommendation_outcome` row, or null. */
export function readRecommendationOutcomes(
  item: ChatItem,
): RecommendationOutcomes | null {
  const row = record(item.payload);
  const cardSeq = count(row?.cardSeq);
  if (row === null || cardSeq === null || !Array.isArray(row.outcomes)) {
    return null;
  }
  const outcomes: Record<string, RecommendationOutcomeView> = {};
  for (const entry of row.outcomes) {
    const mark = record(entry);
    const id = text(mark?.id);
    const status = oneOf(mark?.status, STATUSES);
    if (id !== null && status !== null) {
      outcomes[id] = {
        status,
        note: text(mark?.note),
        backup: text(mark?.backup),
      };
    }
  }
  return { cardSeq, outcomes };
}

/** The `apply` selection a user message carries, or null. */
export function readApply(item: ChatItem): RecommendationApplyData | null {
  if (item.kind !== 'message' || item.role !== 'user') {
    return null;
  }
  const apply = record(record(item.payload)?.apply);
  const cardSeq = count(apply?.cardSeq);
  if (apply === null || cardSeq === null || !Array.isArray(apply.ids)) {
    return null;
  }
  const ids = apply.ids.filter((id): id is string => typeof id === 'string');
  return ids.length === 0 ? null : { cardSeq, ids };
}
