import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { rowsShownOnCards } from './rows-shown-on-cards';

const RUN = 'run-0da49d12-6d80';
const TOOL = 'mcp__geniro-run-0da4__start_thread';

let seq = 0;
function row(kind: string, payload: unknown, id = `row-${++seq}`): ChatItem {
  return { id, runId: RUN, seq: ++seq, kind, payload } as unknown as ChatItem;
}

function startCall(callId: string, title: string, answer: object): ChatItem[] {
  return [
    row('tool_call', {
      id: callId,
      name: TOOL,
      input: { project: 'Geniro', title, brief: 'Check it' },
    }),
    row('tool_result', {
      id: callId,
      result: [{ type: 'text', text: JSON.stringify(answer) }],
      isError: false,
    }),
  ];
}

function quiet(message: string, id: string): ChatItem {
  return row('system', { severity: 'info', message, woke: false }, id);
}

function wake(message: string, id: string): ChatItem {
  return row(
    'system',
    { severity: 'info', message, shares: [], woke: true },
    id,
  );
}

function doneCard(handle: string): ChatItem {
  return row('system', {
    severity: 'info',
    message: `${handle} is done`,
    woke: false,
    threadDone: [{ runId: 'thread-1', title: 'Billing cache', handle }],
  });
}

describe('rowsShownOnCards', () => {
  it('hides a Started row under the start card of the same title', () => {
    const rows = [
      ...startCall('c1', 'Billing cache', {
        status: 'card_shown',
        startId: 'start-1',
      }),
      quiet('Started "Billing cache"', 'started'),
    ];

    expect([...rowsShownOnCards(rows)]).toEqual(['started']);
  });

  it('hides it under a card filed on the board too', () => {
    const rows = [
      ...startCall('c1', 'Billing cache', {
        status: 'starting',
        taskId: 'task-1',
        identifier: 'GEN-4',
      }),
      quiet('Started "Billing cache"', 'started'),
    ];

    expect(rowsShownOnCards(rows).has('started')).toBe(true);
  });

  it('keeps a Started row whose card is not loaded or names another title', () => {
    const rows = [
      ...startCall('c1', 'Cache warmup', {
        status: 'card_shown',
        startId: 'start-1',
      }),
      quiet('Started "Billing cache"', 'started'),
    ];

    expect(rowsShownOnCards(rows).size).toBe(0);
    expect(
      rowsShownOnCards([quiet('Started "Billing cache"', 'started')]).size,
    ).toBe(0);
  });

  it('keeps a row that carries more than the sentence', () => {
    const rows = [
      ...startCall('c1', 'Billing cache', {
        status: 'card_shown',
        startId: 'start-1',
      }),
      row(
        'system',
        {
          severity: 'info',
          message: 'Started "Billing cache"',
          woke: false,
          waitingItems: { kind: 'memory', items: [{ id: 'm1', title: 'x' }] },
        },
        'extra',
      ),
      row(
        'system',
        { severity: 'warning', message: 'Started "Billing cache"' },
        'warning',
      ),
    ];

    expect(rowsShownOnCards(rows).size).toBe(0);
  });

  it('hides a failed start of a thread filed with no card, whose card reads Could not start', () => {
    const rows = [
      ...startCall('c1', 'Billing cache', {
        status: 'card_shown',
        startId: 'start-1',
      }),
      wake('Could not start "Billing cache"', 'failed'),
    ];

    expect(rowsShownOnCards(rows).has('failed')).toBe(true);
  });

  it('keeps a failed start of a board card, whose card does not say it failed', () => {
    const rows = [
      ...startCall('c1', 'Billing cache', {
        status: 'card_shown',
        taskId: 'task-1',
        identifier: 'GEN-4',
      }),
      wake('Could not start "Billing cache"', 'failed'),
    ];

    expect(rowsShownOnCards(rows).size).toBe(0);
  });

  it('hides a watched finish under the Done card of the same thread, and keeps one joined with another wake', () => {
    const rows = [
      doneCard('t86'),
      wake('t86 is done', 'done-wake'),
      wake('t86 is done Could not start "Billing cache"', 'joined'),
      wake('t87 is done', 'other'),
    ];

    expect([...rowsShownOnCards(rows)]).toEqual(['done-wake']);
  });
});
