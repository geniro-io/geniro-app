import { createContext } from 'react';

import type { ItemDto as ChatItem } from '../autogenerated';
import { geniroToolOf, START_THREAD } from './geniro-tool';
import { readThreadMessageRow } from './thread-message-payload';
import { readThreadStart } from './thread-start-payload';
import type { ToolPair } from './transcript-groups';
import { payloadString } from './transcript-payload';

const STARTED = /^Started "([\s\S]+)"$/;
const NOT_STARTED = /^Could not start "([\s\S]+)"$/;
const DONE = /^(\S+) is done$/;

const QUIET_ROW_KEYS: ReadonlySet<string> = new Set([
  'severity',
  'message',
  'woke',
]);
const WAKE_ROW_KEYS: ReadonlySet<string> = new Set([
  'severity',
  'message',
  'woke',
  'shares',
]);

function hostRowOf(
  payload: unknown,
): { message: string; woke: boolean } | null {
  if (payload === null || typeof payload !== 'object') {
    return null;
  }
  const row = payload as Record<string, unknown>;
  if (
    row.severity !== 'info' ||
    typeof row.message !== 'string' ||
    typeof row.woke !== 'boolean'
  ) {
    return null;
  }
  const keys = row.woke ? WAKE_ROW_KEYS : QUIET_ROW_KEYS;
  if (!Object.keys(row).every((key) => keys.has(key))) {
    return null;
  }
  if (
    row.shares !== undefined &&
    !(Array.isArray(row.shares) && row.shares.length === 0)
  ) {
    return null;
  }
  return { message: row.message, woke: row.woke };
}

function startPairs(rows: readonly ChatItem[]): ToolPair[] {
  const calls = new Map<string, ChatItem>();
  const results = new Map<string, ChatItem>();
  for (const row of rows) {
    const id = payloadString(row.payload, 'id');
    if (id === null) {
      continue;
    }
    if (
      row.kind === 'tool_call' &&
      geniroToolOf(payloadString(row.payload, 'name') ?? '', row.runId) ===
        START_THREAD
    ) {
      calls.set(id, row);
    } else if (row.kind === 'tool_result') {
      results.set(id, row);
    }
  }
  return [...calls].map(([id, call]) => ({
    call,
    result: results.get(id) ?? null,
  }));
}

/**
 * The ids of the manager chat's host rows whose whole sentence a loaded card
 * already says: a thread's start under its `start_thread` card (rows written
 * before the daemon stopped writing them), a failed start under the card of a
 * thread filed with no board card, which reads Could not start, and a watched
 * thread's finish under its Done card. Matched on the exact sentence and title
 * or handle; a row carrying anything more, or whose card is not loaded, stays.
 *
 * TWIN PARSER: the sentences `CommandCenterStartsService` and
 * `CommandCenterNotifyService` write as `HostRowWire` rows, and
 * `joinHostWakes`' row shape, in `apps/daemon/src/v1/command-center/` and
 * `apps/daemon/src/v1/agents/services/host-wake.bus.ts`.
 */
export function rowsShownOnCards(
  rows: readonly ChatItem[],
): ReadonlySet<string> {
  const started = new Set<string>();
  const filedWithoutCard = new Set<string>();
  for (const start of startPairs(rows).map(readThreadStart)) {
    if (start.title === null || start.answer === null) {
      continue;
    }
    if (start.answer !== 'refused') {
      started.add(start.title);
    }
    if (start.startId !== null) {
      filedWithoutCard.add(start.title);
    }
  }
  const done = new Set<string>();
  for (const row of rows) {
    const read =
      row.kind === 'system' ? readThreadMessageRow(row.payload) : null;
    if (read?.kind === 'done') {
      for (const entry of read.done) {
        done.add(entry.handle);
      }
    }
  }
  const shown = new Set<string>();
  if (started.size === 0 && done.size === 0) {
    return shown;
  }
  for (const row of rows) {
    const host = row.kind === 'system' ? hostRowOf(row.payload) : null;
    if (host === null) {
      continue;
    }
    const title = (host.woke ? null : STARTED.exec(host.message))?.[1];
    const failed = (host.woke ? NOT_STARTED.exec(host.message) : null)?.[1];
    const handle = (host.woke ? DONE.exec(host.message) : null)?.[1];
    if (
      (title !== undefined && started.has(title.trim())) ||
      (failed !== undefined && filedWithoutCard.has(failed.trim())) ||
      (handle !== undefined && done.has(handle))
    ) {
      shown.add(row.id);
    }
  }
  return shown;
}

/** Empty outside a provider, which hides nothing. */
export const RowsShownOnCardsContext = createContext<ReadonlySet<string>>(
  new Set<string>(),
);
