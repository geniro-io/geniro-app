import { describe, expect, it } from 'vitest';

import type { RunConfig } from '../../shared/contracts';
import { ChatApprovalMode } from '../autogenerated';
import {
  applyRunConfig,
  captureRunConfig,
  replaceRunConfig,
  targetAgentKind,
  workflowSlugOf,
} from './run-config';

function config(over: Partial<RunConfig> = {}): RunConfig {
  return {
    id: 'rc-1',
    name: 'Geniro app',
    cwd: '/Users/dev/geniro-app',
    branch: null,
    target: 'claude',
    model: null,
    effort: null,
    approval: null,
    configDir: null,
    ...over,
  };
}

describe('workflowSlugOf / targetAgentKind', () => {
  it('reads the slug out of a wf: target and nothing out of a CLI one', () => {
    expect(workflowSlugOf('wf:ship-it')).toBe('ship-it');
    expect(workflowSlugOf('claude')).toBeNull();
  });

  it('keys a workflow under claude', () => {
    // The composer derives `agentKind` as `workflowSlug ? 'claude' : target`.
    // If these two disagree, a configuration stores its model under a key the
    // composer never reads back.
    expect(targetAgentKind('wf:ship-it')).toBe('claude');
    expect(targetAgentKind('cursor-agent')).toBe('cursor-agent');
  });
});

describe('which targets are honoured', () => {
  it('accepts a real CLI and a workflow reference, rejects anything else', () => {
    // Asserted through `applyRunConfig`, the only consumer of the underlying
    // check — a null return IS "this build cannot point a run at that".
    expect(applyRunConfig(config({ target: 'claude' }))).not.toBeNull();
    expect(applyRunConfig(config({ target: 'cursor-agent' }))).not.toBeNull();
    expect(applyRunConfig(config({ target: 'wf:ship-it' }))).not.toBeNull();
    expect(
      applyRunConfig(config({ target: 'some-agent-we-dropped' })),
    ).toBeNull();
    // A bare `wf:` names no workflow.
    expect(applyRunConfig(config({ target: 'wf:' }))).toBeNull();
  });
});

describe('captureRunConfig', () => {
  it('stores the model and effort of the TARGET’s own CLI, not the other one', () => {
    // Saving while pointed at cursor must not capture the claude alias sitting
    // in the same per-CLI map — that alias reaches `--model` on the next run.
    const draft = captureRunConfig({
      name: 'Work',
      target: 'cursor-agent',
      cwd: '/Users/dev/app',
      branch: 'main',
      configDir: '/Users/dev/.config/work',
      models: { claude: 'claude-opus-5', 'cursor-agent': 'auto-smart' },
      efforts: { claude: 'high', 'cursor-agent': 'low' },
      approval: 'acceptEdits',
    });

    expect(draft.model).toBe('auto-smart');
    expect(draft.effort).toBe('low');
  });

  it('trims the name', () => {
    expect(
      captureRunConfig({
        name: '  Padded  ',
        target: 'claude',
        cwd: '/Users/dev/app',
        branch: null,
        configDir: null,
        models: {},
        efforts: {},
        approval: null,
      }).name,
    ).toBe('Padded');
  });

  it('a workflow target stores none of the three per-CLI choices', () => {
    // The composer hides the model / effort / approval / config-dir chips for a
    // workflow (its nodes name their own in the YAML), so capturing whatever
    // they last showed would save choices the user could not see or edit.
    const draft = captureRunConfig({
      name: 'Team',
      target: 'wf:ship-it',
      cwd: '/Users/dev/app',
      branch: null,
      configDir: '/Users/dev/.config/work',
      models: { claude: 'claude-opus-5' },
      efforts: { claude: 'high' },
      approval: 'acceptEdits',
    });

    expect(draft).toMatchObject({
      model: null,
      effort: null,
      approval: null,
      configDir: null,
    });
  });
});

describe('applyRunConfig', () => {
  it('passes a fully-specified configuration through', () => {
    const applied = applyRunConfig(
      config({
        target: 'cursor-agent',
        model: 'auto-smart',
        effort: 'low',
        approval: ChatApprovalMode.AcceptEdits,
        configDir: '/Users/dev/.config/work',
        branch: 'feat/x',
      }),
    );

    expect(applied).toEqual({
      target: 'cursor-agent',
      agentKind: 'cursor-agent',
      isWorkflow: false,
      cwd: '/Users/dev/geniro-app',
      configDir: '/Users/dev/.config/work',
      model: 'auto-smart',
      effort: 'low',
      approval: ChatApprovalMode.AcceptEdits,
      branch: 'feat/x',
    });
  });

  it('refuses a target this build cannot point a run at', () => {
    // settings.json is user-editable and can be written by another build. With
    // no valid target there is no CLI to key the other choices under, so the
    // configuration cannot be applied at all.
    expect(
      applyRunConfig(config({ target: 'agent-from-the-future' })),
    ).toBeNull();
  });

  it('drops an approval mode this build does not know, keeping the rest', () => {
    // The mode vocabulary is the DAEMON's. A stored value it would reject must
    // not become composer state — but it must not cost the whole configuration
    // either, so the folder and model still apply and the composer keeps the
    // mode it already had.
    const applied = applyRunConfig(
      config({ approval: 'yolo-mode', model: 'claude-opus-5' }),
    );

    expect(applied?.approval).toBeNull();
    expect(applied?.model).toBe('claude-opus-5');
    expect(applied?.cwd).toBe('/Users/dev/geniro-app');
  });

  it('a workflow configuration resolves without the CLI-only choices', () => {
    const applied = applyRunConfig(
      config({
        target: 'wf:ship-it',
        model: 'claude-opus-5',
        effort: 'high',
        approval: ChatApprovalMode.AcceptEdits,
        configDir: '/Users/dev/.config/work',
      }),
    );

    expect(applied).toMatchObject({
      target: 'wf:ship-it',
      agentKind: 'claude',
      model: null,
      effort: null,
      approval: null,
      configDir: null,
    });
  });

  it('flags a workflow so the caller does not write the per-CLI choices', () => {
    // The flag is the whole guard against a real data loss: `agentKind` is
    // `claude` for a workflow, and the composer's model/effort setters PERSIST,
    // so writing the nulls below through them deletes the user's own remembered
    // claude model. A CLI configuration that merely names no model is the
    // opposite case and must stay writable.
    expect(applyRunConfig(config({ target: 'wf:ship-it' }))?.isWorkflow).toBe(
      true,
    );
    expect(applyRunConfig(config({ target: 'claude' }))?.isWorkflow).toBe(
      false,
    );
  });

  it('carries the branch through so the caller can attempt the switch', () => {
    expect(applyRunConfig(config({ branch: 'feat/x' }))?.branch).toBe('feat/x');
  });
});

describe('replaceRunConfig', () => {
  it('replaces in place — the user’s ordering is not an MRU', () => {
    const list = [
      config({ id: 'a' }),
      config({ id: 'b' }),
      config({ id: 'c' }),
    ];
    const next = replaceRunConfig(list, config({ id: 'b', name: 'Renamed' }));

    expect(next.map((c) => c.id)).toEqual(['a', 'b', 'c']);
    expect(next[1]?.name).toBe('Renamed');
  });

  it('leaves the list alone when no entry matches', () => {
    const list = [config({ id: 'a' })];
    expect(replaceRunConfig(list, config({ id: 'gone' }))).toEqual(list);
  });
});
