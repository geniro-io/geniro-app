import type { CliKind, RunConfig } from '../../shared/contracts';
import { CLI_KINDS } from '../../shared/contracts';
import { ChatApprovalMode } from '../autogenerated';

/**
 * Reading and writing the user's saved new-chat setups.
 *
 * It imports NO component module — only `shared/contracts` and the generated
 * client — which keeps it out of the renderer's component cycles.
 *
 * The values a configuration holds are OPAQUE strings on the Electron side, so
 * this is where a stored one is checked against the generated enum before it
 * becomes composer state: settings.json is a file the user can edit and an
 * older build can write, so "it came from our own settings" is not the same as
 * "it is a value this build understands".
 */

/** Is this stored/foreign string one of the daemon's approval modes? */
export const isChatApprovalMode = (value: unknown): value is ChatApprovalMode =>
  typeof value === 'string' &&
  (Object.values(ChatApprovalMode) as string[]).includes(value);

/** A composer target naming a library workflow rather than a CLI. */
const WORKFLOW_TARGET = /^wf:(.+)$/;

/** The workflow slug a target names, or null when it names a CLI. */
export function workflowSlugOf(target: string): string | null {
  return WORKFLOW_TARGET.exec(target)?.[1] ?? null;
}

/**
 * Which CLI's model/effort a target keys under.
 *
 * A workflow's nodes each name their own in the YAML, so there is no CLI to ask
 * about — it reports `claude` because the composer's own `agentKind` does, and
 * the two must agree or a configuration would store its model under a key the
 * composer never reads back.
 */
export function targetAgentKind(target: string): CliKind {
  return workflowSlugOf(target) !== null ? 'claude' : (target as CliKind);
}

/** Is this target one this build can actually point a run at? */
function isKnownTarget(target: string): boolean {
  return (
    workflowSlugOf(target) !== null ||
    (CLI_KINDS as readonly string[]).includes(target)
  );
}

/** Everything about a configuration except its identity. */
export type RunConfigDraft = Omit<RunConfig, 'id'>;

/**
 * A fresh configuration id — random rather than name-derived, since the name is
 * the field the user is most likely to change and two setups may share one.
 */
export function newRunConfigId(): string {
  return crypto.randomUUID();
}

/**
 * The configuration the composer's CURRENT state describes. `model` and
 * `effort` are read out of the per-CLI maps under the target's own agent, so
 * saving while pointed at cursor cannot store a claude alias.
 */
export function captureRunConfig(input: {
  name: string;
  firstMessage: string | null;
  target: string;
  cwd: string;
  branch: string | null;
  configDir: string | null;
  models: Partial<Record<CliKind, string>>;
  efforts: Partial<Record<CliKind, string>>;
  contextWindows: Partial<Record<CliKind, string>>;
  modelParameters: Partial<Record<CliKind, Record<string, string>>>;
  approval: string | null;
}): RunConfigDraft {
  const kind = targetAgentKind(input.target);
  const workflow = workflowSlugOf(input.target) !== null;
  return {
    name: input.name.trim(),
    // Trimmed to null rather than kept as whitespace: an action whose message
    // is three spaces would create a chat and send nothing, which is neither of
    // the two things this field means.
    firstMessage: input.firstMessage?.trim() || null,
    target: input.target,
    cwd: input.cwd,
    branch: input.branch,
    // A workflow carries none of the per-CLI choices — its nodes each name
    // their own — so they are stored absent rather than as whatever the
    // composer happened to be showing before the target was switched.
    configDir: workflow ? null : input.configDir,
    model: workflow ? null : (input.models[kind] ?? null),
    effort: workflow ? null : (input.efforts[kind] ?? null),
    contextWindow: workflow ? null : (input.contextWindows[kind] ?? null),
    modelParameters: workflow ? {} : (input.modelParameters[kind] ?? {}),
    approval: workflow ? null : input.approval,
  };
}

/** Composer state a configuration resolves to, once its stored values are re-checked. */
export interface AppliedRunConfig {
  target: string;
  agentKind: CliKind;
  /** The message to send once the run exists, or null to seed and stop. */
  firstMessage: string | null;
  /**
   * This configuration starts a workflow, so it says NOTHING about any CLI's
   * model or effort — as distinct from a CLI configuration that names none,
   * which says "use that CLI's default".
   *
   * The caller must NOT write the per-CLI choices when this is true: they are
   * remembered per CLI and shared with the composer, so writing `null` through
   * the ordinary chip callback deletes the user's remembered model for
   * `agentKind` — which is `claude` here only because a workflow has no CLI of
   * its own to name.
   */
  isWorkflow: boolean;
  cwd: string;
  configDir: string | null;
  /** Null means "leave the CLI's default" — the composer omits the field. */
  model: string | null;
  effort: string | null;
  /**
   * The window size, on the same terms as `effort` — null means the model's
   * own. A size the configuration's model no longer offers is not filtered
   * here: the chip re-fetches that model's list and draws it as unavailable,
   * which is the one place that can know.
   */
  contextWindow: string | null;
  /**
   * The other model settings, on the same terms again — a value the
   * configuration's model no longer offers is drawn as unavailable by its own
   * chip rather than filtered here.
   */
  modelParameters: Record<string, string>;
  /**
   * A mode this build recognises, or null when the stored one is not — in which
   * case the composer keeps the mode it already had rather than being set to a
   * value the daemon would reject.
   */
  approval: ChatApprovalMode | null;
  /** The branch to switch the folder to, or null to take what is checked out. */
  branch: string | null;
}

/**
 * Resolve a stored configuration into composer state, or null when this build
 * cannot honour it at all.
 *
 * Only the TARGET can make a configuration unusable: without a valid one there
 * is nothing to start and no CLI to key the other choices under. Every other
 * stored value degrades to the CLI's own default instead, which is a working
 * chat rather than a refusal.
 *
 * A `wf:` target for a workflow that has since been deleted is NOT rejected
 * here: the composer already resets an unknown workflow target to `claude` once
 * its list has loaded, and a second check against a list this module cannot see
 * would be free to disagree with it.
 */
export function applyRunConfig(config: RunConfig): AppliedRunConfig | null {
  if (!isKnownTarget(config.target)) {
    return null;
  }
  const workflow = workflowSlugOf(config.target) !== null;
  return {
    target: config.target,
    agentKind: targetAgentKind(config.target),
    firstMessage: config.firstMessage,
    isWorkflow: workflow,
    cwd: config.cwd,
    configDir: workflow ? null : config.configDir,
    model: workflow ? null : config.model,
    effort: workflow ? null : config.effort,
    contextWindow: workflow ? null : config.contextWindow,
    modelParameters: workflow ? {} : config.modelParameters,
    approval:
      !workflow && isChatApprovalMode(config.approval) ? config.approval : null,
    branch: config.branch,
  };
}

/**
 * Replace one configuration in the list, preserving order — the arrangement is
 * the user's, so an edit must not float the entry to the front.
 */
export function replaceRunConfig(
  configs: readonly RunConfig[],
  next: RunConfig,
): RunConfig[] {
  return configs.map((c) => (c.id === next.id ? next : c));
}
