import type { CliKind, RunConfig } from '../../shared/contracts';
import {
  CLI_KINDS,
  MAX_RUN_CONFIG_NAME,
  MAX_RUN_CONFIGS,
} from '../../shared/contracts';
import type { ChatApprovalMode } from '../autogenerated';
import { randomId } from '../random-id';
import {
  isChatApprovalMode,
  targetAgentKind,
  teamSlugOf,
} from './composer-values';

/**
 * Reading and writing the user's saved new-chat setups.
 *
 * It imports NO component module — only `shared/contracts`, the generated
 * client and `composer-values` beside it — which keeps it out of the renderer's
 * component cycles.
 *
 * The three foreign-string readers it needs (`isChatApprovalMode`,
 * `teamSlugOf`, `targetAgentKind`) live in `composer-values.ts` and are
 * imported rather than restated: they were carved OUT of this file when the
 * configurations were removed, and re-inlining them here would leave the
 * composer and a saved configuration free to disagree about what `team:` means.
 *
 * The values a configuration holds are OPAQUE strings on the Electron side, so
 * this is where a stored one is checked against the generated enum before it
 * becomes composer state: settings.json is a file the user can edit and an
 * older build can write, so "it came from our own settings" is not the same as
 * "it is a value this build understands".
 */

/** Is this target one this build can actually point a run at? */
function isKnownTarget(target: string): boolean {
  return (
    teamSlugOf(target) !== null ||
    (CLI_KINDS as readonly string[]).includes(target)
  );
}

/** Everything about a configuration except its identity. */
export type RunConfigDraft = Omit<RunConfig, 'id'>;

/** A draft with nothing chosen yet, bar what `over` sets. */
export function blankRunConfigDraft(
  over: Partial<RunConfigDraft> = {},
): RunConfigDraft {
  return {
    name: '',
    cwd: '',
    branch: null,
    target: CLI_KINDS[0]!,
    model: null,
    effort: null,
    contextWindow: null,
    modelParameters: {},
    approval: null,
    configDir: null,
    projectId: null,
    ...over,
  };
}

/**
 * Why saving a draft is refused, or null. The name and count limits are the
 * IPC schema's, refused here first because that boundary rejects the WHOLE
 * settings patch by throwing — an editor that closed on it would show a row
 * that was never written.
 */
export function runConfigRefusal(
  draft: RunConfigDraft,
  isNew: boolean,
  count: number,
  projects: readonly { id: string }[],
): string | null {
  const name = draft.name.trim();
  if (name === '') {
    return 'Give the configuration a name.';
  }
  if (draft.cwd === '') {
    return 'Choose the folder this configuration opens in.';
  }
  if (!projects.some((project) => project.id === draft.projectId)) {
    return 'Choose the project this configuration belongs to.';
  }
  if (name.length > MAX_RUN_CONFIG_NAME) {
    return `That name is ${name.length} characters — keep it to ${MAX_RUN_CONFIG_NAME}.`;
  }
  if (isNew && count >= MAX_RUN_CONFIGS) {
    return `You already have ${MAX_RUN_CONFIGS} configurations — delete one before adding another.`;
  }
  return null;
}

/**
 * A fresh configuration id — random rather than name-derived, since the name is
 * the field the user is most likely to change and two setups may share one.
 */
export function newRunConfigId(): string {
  return randomId();
}

/**
 * The configuration the composer's CURRENT state describes. `model` and
 * `effort` are read out of the per-CLI maps under the target's own agent, so
 * saving while pointed at cursor cannot store a claude alias.
 */
export function captureRunConfig(input: {
  name: string;
  target: string;
  cwd: string;
  branch: string | null;
  configDir: string | null;
  models: Partial<Record<CliKind, string>>;
  efforts: Partial<Record<CliKind, string>>;
  contextWindows: Partial<Record<CliKind, string>>;
  modelParameters: Partial<Record<CliKind, Record<string, string>>>;
  approval: string | null;
  /** The project the composer's run would be bound to by choice, or null. */
  projectId: string | null;
}): RunConfigDraft {
  const kind = targetAgentKind(input.target);
  const team = teamSlugOf(input.target) !== null;
  return {
    name: input.name.trim(),
    target: input.target,
    cwd: input.cwd,
    branch: input.branch,
    // A team carries none of the per-CLI choices — its nodes each name
    // their own — so they are stored absent rather than as whatever the
    // composer happened to be showing before the target was switched.
    configDir: team ? null : input.configDir,
    model: team ? null : (input.models[kind] ?? null),
    effort: team ? null : (input.efforts[kind] ?? null),
    contextWindow: team ? null : (input.contextWindows[kind] ?? null),
    modelParameters: team ? {} : (input.modelParameters[kind] ?? {}),
    approval: team ? null : input.approval,
    // A team binds a project as a chat does: it reaches every member.
    projectId: input.projectId,
  };
}

/** Composer state a configuration resolves to, once its stored values are re-checked. */
export interface AppliedRunConfig {
  target: string;
  agentKind: CliKind;
  /**
   * This configuration starts a team, so it says NOTHING about any CLI's
   * model or effort — as distinct from a CLI configuration that names none,
   * which says "use that CLI's default".
   *
   * The caller must NOT write the per-CLI choices when this is true: they are
   * remembered per CLI and shared with the composer, so writing `null` through
   * the ordinary chip callback deletes the user's remembered model for
   * `agentKind` — which is `claude` here only because a team has no CLI of
   * its own to name.
   */
  isTeam: boolean;
  cwd: string;
  configDir: string | null;
  /** Null means "leave the CLI's default" — the composer omits the field. */
  model: string | null;
  effort: string | null;
  /**
   * The window size, on the same terms as `effort` — null means the model's
   * own. A size the configuration's model no longer offers is not filtered
   * here: the chip re-fetches that model's list and draws it as unavailable,
   * which is the one place that can know.
   */
  contextWindow: string | null;
  /**
   * The other model settings, on the same terms again — a value the
   * configuration's model no longer offers is drawn as unavailable by its own
   * chip rather than filtered here.
   */
  modelParameters: Record<string, string>;
  /**
   * A mode this build recognises, or null when the stored one is not — in which
   * case the composer keeps the mode it already had rather than being set to a
   * value the daemon would reject.
   */
  approval: ChatApprovalMode | null;
  /** The branch to switch the folder to, or null to take what is checked out. */
  branch: string | null;
  /**
   * The project the configuration binds its runs to, or null when it leaves
   * that to the folder. Not checked against the live projects here: the
   * composer falls back to the folder's own once the list no longer holds it.
   */
  projectId: string | null;
}

/**
 * Resolve a stored configuration into composer state, or null when this build
 * cannot honour it at all.
 *
 * Only the TARGET can make a configuration unusable: without a valid one there
 * is nothing to start and no CLI to key the other choices under. Every other
 * stored value degrades to the CLI's own default instead, which is a working
 * chat rather than a refusal.
 *
 * A `team:` target for a team that has since been deleted is NOT rejected
 * here: the composer already resets an unknown team target to `claude` once
 * its list has loaded, and a second check against a list this module cannot see
 * would be free to disagree with it.
 */
export function applyRunConfig(config: RunConfig): AppliedRunConfig | null {
  if (!isKnownTarget(config.target)) {
    return null;
  }
  const team = teamSlugOf(config.target) !== null;
  return {
    target: config.target,
    agentKind: targetAgentKind(config.target),
    isTeam: team,
    cwd: config.cwd,
    configDir: team ? null : config.configDir,
    model: team ? null : config.model,
    effort: team ? null : config.effort,
    contextWindow: team ? null : config.contextWindow,
    modelParameters: team ? {} : config.modelParameters,
    approval:
      !team && isChatApprovalMode(config.approval) ? config.approval : null,
    branch: config.branch,
    projectId: config.projectId ?? null,
  };
}

/**
 * The list with `draft` saved: replacing the entry `id` names in place, or
 * appended under a new id when `id` is null. The name is stored trimmed.
 */
export function upsertRunConfig(
  configs: readonly RunConfig[],
  draft: RunConfigDraft,
  id: string | null,
): RunConfig[] {
  const named = { ...draft, name: draft.name.trim() };
  return id === null
    ? [...configs, { ...named, id: newRunConfigId() }]
    : replaceRunConfig(configs, { ...named, id });
}

/**
 * Replace one configuration in the list, preserving order — the arrangement is
 * the user's, so an edit must not float the entry to the front.
 */
export function replaceRunConfig(
  configs: readonly RunConfig[],
  next: RunConfig,
): RunConfig[] {
  return configs.map((c) => (c.id === next.id ? next : c));
}

/**
 * Move `id` to where `overId` currently sits — the one reorder both the drag
 * and the grip's arrow keys perform. By ID on both sides, never by index, so a
 * list that changed under the gesture cannot move the wrong entry. Returns the
 * list unchanged (a copy) when either id is missing or the two are the same.
 */
export function moveRunConfig(
  configs: readonly RunConfig[],
  id: string,
  overId: string,
): RunConfig[] {
  const from = configs.findIndex((c) => c.id === id);
  const to = configs.findIndex((c) => c.id === overId);
  if (from === -1 || to === -1 || from === to) {
    return [...configs];
  }
  const next = [...configs];
  const [moved] = next.splice(from, 1);
  next.splice(to, 0, moved!);
  return next;
}

/** A configuration whose project is unset or no longer listed. */
export function isUnboundRunConfig(
  config: RunConfig,
  projects: readonly { id: string }[],
): boolean {
  return !projects.some((project) => project.id === config.projectId);
}

export interface RunConfigGroup<P extends { id: string }> {
  /** Null for the configurations bound to no listed project. */
  project: P | null;
  configs: RunConfig[];
}

/**
 * The configurations under their projects, each project where its first
 * configuration stands in the user's order, the unbound ones last.
 */
export function groupRunConfigsByProject<P extends { id: string }>(
  configs: readonly RunConfig[],
  projects: readonly P[],
): RunConfigGroup<P>[] {
  const groups = new Map<string, RunConfigGroup<P>>();
  const unbound: RunConfig[] = [];
  for (const config of configs) {
    const project = projects.find((entry) => entry.id === config.projectId);
    if (project === undefined) {
      unbound.push(config);
      continue;
    }
    const group = groups.get(project.id);
    if (group === undefined) {
      groups.set(project.id, { project, configs: [config] });
    } else {
      group.configs.push(config);
    }
  }
  const grouped = [...groups.values()];
  return unbound.length === 0
    ? grouped
    : [...grouped, { project: null, configs: unbound }];
}

/**
 * The whole list with the entries of `reordered` laid back into the places
 * those entries held, in their new order; every other entry stays put.
 */
export function withSubsetOrder(
  configs: readonly RunConfig[],
  reordered: readonly RunConfig[],
): RunConfig[] {
  const ids = new Set(reordered.map((config) => config.id));
  const queue = [...reordered];
  return configs.map((config) =>
    ids.has(config.id) ? (queue.shift() ?? config) : config,
  );
}
