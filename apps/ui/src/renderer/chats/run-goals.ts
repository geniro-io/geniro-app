/**
 * A run's goals and its outcome, as a `run_status` announce carries them.
 *
 * TWIN PARSER: `RunGoalSchema` and `ThreadOutcomeSchema` in
 * `apps/daemon/src/v1/agents/chat.types.ts`, sent as `RunStatusEvent.goals`
 * and `RunStatusEvent.outcome`. The socket is outside the generated contract,
 * so the two sides read one shape independently; a field renamed there must
 * change here.
 */

import {
  GoalSource,
  GoalStatus,
  type RunGoal,
  type ThreadOutcome,
  ThreadOutcomeKind,
} from '../autogenerated';

const STATUSES: ReadonlySet<string> = new Set(Object.values(GoalStatus));
const SOURCES: ReadonlySet<string> = new Set(Object.values(GoalSource));
const KINDS: ReadonlySet<string> = new Set(Object.values(ThreadOutcomeKind));

function readGoal(raw: unknown): RunGoal | null {
  if (raw === null || typeof raw !== 'object') {
    return null;
  }
  const bag = raw as Record<string, unknown>;
  if (
    typeof bag.id !== 'string' ||
    typeof bag.text !== 'string' ||
    typeof bag.source !== 'string' ||
    !SOURCES.has(bag.source) ||
    typeof bag.status !== 'string' ||
    !STATUSES.has(bag.status) ||
    (bag.evidence !== null && typeof bag.evidence !== 'string') ||
    (bag.memberId !== null && typeof bag.memberId !== 'string') ||
    typeof bag.createdAt !== 'string' ||
    (bag.closedAt !== null && typeof bag.closedAt !== 'string')
  ) {
    return null;
  }
  return {
    id: bag.id,
    text: bag.text,
    source: bag.source as RunGoal['source'],
    status: bag.status as RunGoal['status'],
    evidence: bag.evidence,
    memberId: bag.memberId,
    createdAt: bag.createdAt,
    closedAt: bag.closedAt,
  };
}

/** The whole goal list, or undefined when the announce carries none or one entry is unreadable. */
export function readRunGoals(raw: unknown): RunGoal[] | undefined {
  if (!Array.isArray(raw)) {
    return undefined;
  }
  const goals: RunGoal[] = [];
  for (const entry of raw) {
    const goal = readGoal(entry);
    if (goal === null) {
      return undefined;
    }
    goals.push(goal);
  }
  return goals;
}

/**
 * The outcome: null says the run has none, undefined that the announce says
 * nothing about it or carried a shape this build cannot read.
 */
export function readThreadOutcome(
  raw: unknown,
): ThreadOutcome | null | undefined {
  if (raw === null) {
    return null;
  }
  if (typeof raw !== 'object' || raw === undefined) {
    return undefined;
  }
  const bag = raw as Record<string, unknown>;
  if (
    typeof bag.kind !== 'string' ||
    !KINDS.has(bag.kind) ||
    (bag.summary !== null && typeof bag.summary !== 'string') ||
    (bag.source !== 'recorded' && bag.source !== 'goals') ||
    (bag.seq !== null && typeof bag.seq !== 'number')
  ) {
    return undefined;
  }
  return {
    kind: bag.kind as ThreadOutcome['kind'],
    summary: bag.summary,
    source: bag.source,
    seq: bag.seq,
  };
}
