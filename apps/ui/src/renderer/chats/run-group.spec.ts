import { describe, expect, it } from 'vitest';

import type { RunGroupColor, RunGroupDto } from '../autogenerated';
import {
  GROUP_DOT_CLASS,
  GROUP_RAIL_CLASS,
  previewSectionRuns,
  runGroupSections,
  runGroupSummary,
  SECTION_PREVIEW_LIMIT,
} from './run-group';

const group = (id: string, position: number): RunGroupDto => ({
  id,
  name: id,
  color: 'blue',
  position,
  collapsed: false,
  autoCwd: null,
});
const run = (
  id: string,
  groupId: string | null,
): { id: string; groupId: string | null } => ({
  id,
  groupId,
});

describe('runGroupSections', () => {
  it('orders sections by position and puts the loose runs last', () => {
    const sections = runGroupSections(
      // Supplied out of order on purpose: the daemon answers ordered, but the
      // sidebar patches one group's row in place after a rename, and nothing
      // re-sorts that array.
      [group('b', 1), group('a', 0)],
      [run('r1', 'b'), run('r2', null), run('r3', 'a')],
    );
    expect(sections.map((section) => section.group?.id ?? null)).toEqual([
      'a',
      'b',
      null,
    ]);
    expect(sections.map((section) => section.runs.map((r) => r.id))).toEqual([
      ['r3'],
      ['r1'],
      ['r2'],
    ]);
  });

  it('keeps an empty group, and the loose section even when nothing is loose', () => {
    // A group the user just made and has not filled is the ONLY way they can
    // see it exists; dropping empty sections would make creating one look like
    // it did nothing.
    const sections = runGroupSections([group('a', 0)], [run('r1', 'a')]);
    expect(sections).toHaveLength(2);
    expect(sections[1]).toEqual({ group: null, runs: [] });
  });

  it('files a run whose group no longer exists into the loose list', () => {
    // Deleting a group releases its runs, so this should not arise — but "we
    // lost your chat" is the one outcome a grouping bug must not have.
    const sections = runGroupSections([group('a', 0)], [run('r1', 'ghost')]);
    expect(sections[0]!.runs).toEqual([]);
    expect(sections[1]!.runs.map((r) => r.id)).toEqual(['r1']);
  });

  it('preserves the incoming run order inside a section', () => {
    // The list arrives newest-first and the grouping must not reshuffle it.
    const sections = runGroupSections(
      [group('a', 0)],
      [run('r1', 'a'), run('r2', 'a'), run('r3', 'a')],
    );
    expect(sections[0]!.runs.map((r) => r.id)).toEqual(['r1', 'r2', 'r3']);
  });
});

describe('previewSectionRuns', () => {
  /** `n` chats named r0…r(n-1), none of them working. */
  const idle = (n: number): { id: string }[] =>
    Array.from({ length: n }, (_, i) => ({ id: `r${i}` }));
  const keepNone = (): boolean => false;

  it('draws a short section in full and reports nothing hidden', () => {
    const runs = idle(SECTION_PREVIEW_LIMIT);
    const preview = previewSectionRuns(runs, { keep: keepNone });
    expect(preview.visible).toEqual(runs);
    expect(preview.hidden).toBe(0);
  });

  it('folds a long section down to the limit', () => {
    const preview = previewSectionRuns(idle(100), { keep: keepNone });
    expect(preview.visible).toHaveLength(SECTION_PREVIEW_LIMIT);
    expect(preview.hidden).toBe(100 - SECTION_PREVIEW_LIMIT);
    // The first rows, in the caller's order: the list arrives
    // newest-activity-first, so a folded group opens on what someone was last
    // in.
    expect(preview.visible.map((r) => r.id)).toEqual(
      idle(SECTION_PREVIEW_LIMIT).map((r) => r.id),
    );
  });

  it('always draws a kept run, however far down the list it sits', () => {
    // The whole point of the fold: a working thread must never be the thing
    // behind "Show all".
    const preview = previewSectionRuns(idle(100), {
      keep: (run) => run.id === 'r90',
    });
    expect(preview.visible.map((r) => r.id)).toContain('r90');
    expect(preview.visible).toHaveLength(SECTION_PREVIEW_LIMIT);
    expect(preview.hidden).toBe(100 - SECTION_PREVIEW_LIMIT);
  });

  it('hides nothing when more runs are kept than the limit allows', () => {
    // Thirty live chats are thirty rows. Capping them would hide exactly the
    // work the user is waiting on.
    const preview = previewSectionRuns(idle(30), { keep: () => true });
    expect(preview.visible).toHaveLength(30);
    expect(preview.hidden).toBe(0);
  });

  it('keeps the list order rather than floating kept runs to the top', () => {
    // Reordering on status would make rows jump under the cursor exactly when
    // a turn starts or ends.
    const preview = previewSectionRuns(idle(40), {
      keep: (run) => run.id === 'r39',
    });
    expect(preview.visible.map((r) => r.id).at(-1)).toBe('r39');
  });

  it('draws the section in full rather than folding one or two rows away', () => {
    // The toggle is itself a row, so hiding two saves exactly one — a fold
    // that coy reads as the sidebar withholding nothing.
    const preview = previewSectionRuns(idle(SECTION_PREVIEW_LIMIT + 2), {
      keep: keepNone,
    });
    expect(preview.visible).toHaveLength(SECTION_PREVIEW_LIMIT + 2);
    expect(preview.hidden).toBe(0);
  });
});

describe('runGroupSummary', () => {
  it('counts the threads and reports whether any is working', () => {
    expect(runGroupSummary(['completed', 'running', 'failed'])).toEqual({
      count: 3,
      busy: true,
      needsInput: false,
    });
    expect(runGroupSummary(['completed'])).toEqual({
      count: 1,
      busy: false,
      needsInput: false,
    });
    expect(runGroupSummary([])).toEqual({
      count: 0,
      busy: false,
      needsInput: false,
    });
  });

  it('reports a parked thread separately from a working one', () => {
    // Folded into `busy` it would be invisible in a COLLAPSED group — the one
    // state that cannot advance without the user, hidden behind a fold.
    expect(runGroupSummary(['completed', 'needs-input'])).toMatchObject({
      busy: false,
      needsInput: true,
    });
  });
});

describe('the colour maps', () => {
  it('spell every class in full, so Tailwind emits it', () => {
    // An interpolated `bg-group-${color}` is never seen by Tailwind's source
    // scan and every dot would render transparent — this is the pin on the
    // reason the maps exist at all.
    for (const [color, cls] of Object.entries(GROUP_DOT_CLASS)) {
      expect(cls).toBe(`bg-group-${color as RunGroupColor}`);
    }
    for (const [color, cls] of Object.entries(GROUP_RAIL_CLASS)) {
      expect(cls).toBe(`border-group-${color as RunGroupColor}/40`);
    }
  });

  it('covers the same colours in both, so no group can lose its rail', () => {
    expect(Object.keys(GROUP_RAIL_CLASS)).toEqual(Object.keys(GROUP_DOT_CLASS));
  });
});
