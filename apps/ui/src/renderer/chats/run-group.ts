/**
 * The sidebar's groups: how a list of runs is folded into the sections the
 * chat list draws, and what a section's header says about what is inside it.
 *
 * Pure and separate from the components for the usual reason — the bucketing
 * and the "is anything in here working" reading are the parts worth pinning,
 * and neither needs a DOM.
 */

