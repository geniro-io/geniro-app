/** One rendered section of the chat list. */
export interface RunGroupSection<TRun> {
  /** The group, or null for the loose runs that belong to none. */
  group: RunGroupDto | null;
  runs: TRun[];
}

/**
 * Fold a run list into sections: every group in sidebar order, then the runs
 * belonging to none.
 *
 * The loose section is LAST and always present, even when empty — it is where a
 * run lands when it leaves a group, so a sidebar whose every chat is filed
 * still has to show somewhere to drop the next one. An EMPTY GROUP is kept for
 * the same reason: a user who just made one and has not filled it yet must be
 * able to see that it exists.
 *
 * A run whose `groupId` names no group falls into the loose section rather than
 * vanishing. That should not happen — deleting a group releases its runs — but
 * "we lost your chat" is the one outcome a grouping bug must not have.
 */
export function runGroupSections<TRun extends { groupId: string | null }>(
  groups: readonly RunGroupDto[],
  runs: readonly TRun[],
): RunGroupSection<TRun>[] {
  const ordered = [...groups].sort((a, b) => a.position - b.position);
  const byGroup = new Map<string, TRun[]>(
    ordered.map((group) => [group.id, [] as TRun[]]),
  );
  const loose: TRun[] = [];
  for (const run of runs) {
    const bucket = run.groupId === null ? undefined : byGroup.get(run.groupId);
    (bucket ?? loose).push(run);
  }
  return [
    ...ordered.map((group) => ({ group, runs: byGroup.get(group.id) ?? [] })),
    { group: null, runs: loose },
  ];
}

/** What a group header reports about the threads inside it. */
export interface RunGroupSummary {
  count: number;
  /** At least one thread in here is working. */
  busy: boolean;
  /** At least one thread in here is parked waiting on the user. */
  needsInput: boolean;
}

/**
 * Summarize a section from the statuses its rows are ALREADY showing.
 *
 * It takes the display statuses rather than the run rows deliberately: the
 * badge a row draws is `displayRunStatus`'s answer, not the daemon column, and
 * a header computed from the raw column would contradict the rows beneath it in
 * exactly the cases that matter (a live turn under a stale `completed` row, a
 * parked question the row already paints as `needs-input`).
 *
 * `needsInput` is reported alongside `busy` rather than folded into it because
 * a COLLAPSED group would otherwise hide the one state that cannot advance
 * without the user — which is the failure this whole feature would introduce if
 * a header only ever said "something is running".
 */
export function runGroupSummary(
  statuses: readonly RunStatusKind[],
): RunGroupSummary {
  return {
    count: statuses.length,
    busy: statuses.includes('running'),
    needsInput: statuses.includes('needs-input'),
  };
}
