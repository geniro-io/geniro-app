import { describe, expect, it } from 'vitest';

import type { RunDto as ChatRun } from '../autogenerated';
import { reconcileListing } from './run-list-pages';

/** A run created `day` days into 2026; `archived` puts it on the shelf. */
function run(id: string, day: number, archived = true): ChatRun {
  return {
    id,
    createdAt: new Date(Date.UTC(2026, 0, day)).toISOString(),
    archivedAt: archived ? '2026-12-31T00:00:00.000Z' : null,
  } as ChatRun;
}

const horizon = run('edge', 50).createdAt;
const none = new Set<string>();
const never = (): boolean => false;

describe('reconcileListing', () => {
  it('shows the listing down to the horizon and holds what lies below it', () => {
    const { shown, held } = reconcileListing({
      all: [run('a', 60), run('b', 40)],
      known: [],
      heldBefore: [],
      horizon,
      scope: 'archived',
      deleted: none,
      takenInSince: never,
    });

    expect(shown.map((row) => row.id)).toEqual(['a']);
    expect(held.map((row) => row.id)).toEqual(['b']);
  });

  it('keeps a known row below the horizon on screen, and one above it off scope', () => {
    const { shown, kept } = reconcileListing({
      all: [run('a', 60)],
      known: [run('deep', 10), run('gone', 70)],
      heldBefore: [],
      horizon,
      scope: 'archived',
      deleted: none,
      takenInSince: never,
    });

    expect(shown.map((row) => row.id)).toEqual(['a', 'deep']);
    expect(kept.map((row) => row.id)).toEqual(['gone']);
  });

  it('keeps a row taken in after the listing was asked for, wherever it lies', () => {
    const { shown } = reconcileListing({
      all: [run('a', 60)],
      known: [run('new', 80, false)],
      heldBefore: [],
      horizon: null,
      scope: 'active',
      deleted: none,
      takenInSince: (id) => id === 'new',
    });

    expect(shown.map((row) => row.id)).toEqual(['new', 'a']);
  });

  it('carries held rows the listing does not reach, and never a deleted one', () => {
    const { held } = reconcileListing({
      all: [run('a', 60)],
      known: [],
      heldBefore: [run('older', 20), run('dropped', 15), run('covered', 55)],
      horizon,
      scope: 'archived',
      deleted: new Set(['dropped']),
      takenInSince: never,
    });

    expect(held.map((row) => row.id)).toEqual(['older']);
  });

  it('never keeps a known row of another scope on screen', () => {
    const { shown, kept } = reconcileListing({
      all: [run('a', 60)],
      known: [run('desk', 10, false)],
      heldBefore: [],
      horizon,
      scope: 'archived',
      deleted: none,
      takenInSince: never,
    });

    expect(shown.map((row) => row.id)).toEqual(['a']);
    expect(kept.map((row) => row.id)).toEqual(['desk']);
  });
});
