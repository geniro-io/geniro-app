import type {
  ChatsApiListChatsRequest,
  RunDto as ChatRun,
  TeamsApiListTeamRunsRequest,
} from '../autogenerated';

/**
 * How many rows one page of a paged listing asks each half (chats, team
 * runs) for. The archive grows without bound, and every listed run costs the
 * daemon its own reads; the desk (`active`) is never paged, because the
 * notification rules and the composer read it whole.
 */
export const RUN_LIST_PAGE = 50;

/**
 * The most rows one listing request may ask for, probe row included, so a
 * re-list asks for at most one fewer.
 * TWIN: `limit` in the daemon's `listChatsQuerySchema` (`max(1000)`).
 */
export const RUN_LIST_MAX = 1000;

/**
 * The `limit` to send for `wanted` rows: one more, so a page that comes back
 * longer than `wanted` says there is more below without a further request. A
 * page exactly as long as the rows that remain would otherwise read as full.
 */
export function probeLimit(wanted: number): number {
  return wanted + 1;
}

type ListScope = NonNullable<ChatsApiListChatsRequest['scope']>;

/** A page query both list routes take — a rename on either is a type error here. */
export type ListPageQuery = ChatsApiListChatsRequest &
  TeamsApiListTeamRunsRequest;

/** How far one half of a paged listing has read. */
export interface ListingDepth {
  /** Rows it has handed over across every page — what a re-list asks for again. */
  loaded: number;
  /** Its last page came back full, so there may be more below. */
  hasMore: boolean;
  /** The oldest row it has handed over: the cursor of its next page. */
  oldest: ChatRun | null;
}

/** Where a paged listing stands, and the rows it fetched but does not show yet. */
export interface ListingPages {
  scope: ListScope;
  chats: ListingDepth;
  runs: ListingDepth;
  /**
   * Rows older than the {@link horizonOf} the two halves reach together. One
   * half can page far deeper than the other — fifty team runs may span two
   * months where fifty chats span two days — and showing its old rows would put
   * them beside a gap where the other half's rows of that time belong.
   */
  held: readonly ChatRun[];
}

export function isPagedScope(scope: ListScope): boolean {
  return scope !== 'active';
}

/** The depth a page asked for `wanted` rows (and its probe) leaves a listing at. */
export function depthOf(
  rows: readonly ChatRun[],
  wanted: number,
): ListingDepth {
  const page = rows.slice(0, wanted);
  return {
    loaded: page.length,
    hasMore: rows.length > wanted,
    oldest: page.at(-1) ?? null,
  };
}

/** The rows of one {@link RUN_LIST_PAGE} page, its probe row dropped. */
export function pageRows(rows: readonly ChatRun[]): readonly ChatRun[] {
  return rows.slice(0, RUN_LIST_PAGE);
}

/** `depth` after one more page of {@link RUN_LIST_PAGE} rows and its probe. */
export function deeper(
  depth: ListingDepth,
  rows: readonly ChatRun[],
): ListingDepth {
  const next = depthOf(rows, RUN_LIST_PAGE);
  return {
    loaded: depth.loaded + next.loaded,
    hasMore: next.hasMore,
    oldest: next.oldest ?? depth.oldest,
  };
}

/**
 * The depth a re-list leaves a half at: its own, unless it was cut short by
 * its limit and the depth already read reaches further.
 */
export function deepest(
  listed: ListingDepth,
  held: ListingDepth | undefined,
): ListingDepth {
  return listed.hasMore && held !== undefined && held.loaded > listed.loaded
    ? held
    : listed;
}

/**
 * The `createdAt` below which the listing is incomplete: the newer of the two
 * halves' oldest rows, among halves with more to give. Null when both halves
 * are read to the end, so nothing is held back.
 *
 * Times compare as strings here and below: the daemon writes every one with
 * `toISOString()`, whose fixed width orders lexically as it does in time.
 */
export function horizonOf(
  pages: Pick<ListingPages, 'chats' | 'runs'>,
): string | null {
  let horizon: string | null = null;
  for (const depth of [pages.chats, pages.runs]) {
    if (!depth.hasMore || depth.oldest === null) {
      continue;
    }
    const edge = depth.oldest.createdAt;
    if (horizon === null || edge > horizon) {
      horizon = edge;
    }
  }
  return horizon;
}

export function belowHorizon(run: ChatRun, horizon: string | null): boolean {
  return horizon !== null && run.createdAt < horizon;
}

/**
 * Newest first. Stable, so rows created in the same instant keep the order
 * they came in — the daemon's own, within a page and across pages.
 */
export function newestFirst(rows: readonly ChatRun[]): ChatRun[] {
  return [...rows].sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}

/** The query of the page after `oldest`. */
export function olderPageQuery(
  scope: ListScope,
  oldest: ChatRun,
): ListPageQuery {
  return {
    scope,
    limit: probeLimit(RUN_LIST_PAGE),
    beforeCreatedAt: oldest.createdAt,
    beforeId: oldest.id,
  };
}

/** Whether a listing of `scope` holds this run. */
export function inScope(run: ChatRun, scope: ListScope): boolean {
  return scope === 'all' || (run.archivedAt != null) === (scope === 'archived');
}

/** What a landing listing makes of the rows a window already holds. */
export interface ReconciledListing {
  /** The list on screen, newest first. */
  shown: ChatRun[];
  /** Fetched rows below the horizon, waiting for the page that reaches them. */
  held: ChatRun[];
  /** Known rows this scope does not show, still followed off scope. */
  kept: ChatRun[];
  /** The rows whose snapshot facts the listing states. */
  seeded: ChatRun[];
}

/**
 * Fold a landing listing into what the window holds.
 *
 * `all` is the listing (deleted rows out, fresher copies in). A row of this
 * scope it is silent about stays on screen when the listing does not reach it
 * (below `horizon`) or when it was taken in by itself after the listing was
 * asked for (`takenInSince`); any other known row is kept off scope, never
 * dropped. Held rows of an older page below `horizon` stay held.
 */
export function reconcileListing({
  all,
  known,
  heldBefore,
  horizon,
  scope,
  deleted,
  takenInSince,
}: {
  all: readonly ChatRun[];
  known: readonly ChatRun[];
  heldBefore: readonly ChatRun[];
  horizon: string | null;
  scope: ListScope;
  deleted: ReadonlySet<string>;
  takenInSince: (runId: string) => boolean;
}): ReconciledListing {
  const listed = new Set(all.map((row) => row.id));
  const knownIds = new Set(known.map((row) => row.id));
  const unlisted = known.filter(
    (row) =>
      !listed.has(row.id) &&
      !deleted.has(row.id) &&
      inScope(row, scope) &&
      (belowHorizon(row, horizon) || takenInSince(row.id)),
  );
  const shown = newestFirst([
    ...all.filter((row) => !belowHorizon(row, horizon) || knownIds.has(row.id)),
    ...unlisted,
  ]);
  const onScreen = new Set(shown.map((row) => row.id));
  const carried = heldBefore.filter(
    (row) =>
      !listed.has(row.id) &&
      !onScreen.has(row.id) &&
      !deleted.has(row.id) &&
      belowHorizon(row, horizon),
  );
  return {
    shown,
    held: newestFirst([
      ...all.filter((row) => !onScreen.has(row.id)),
      ...carried,
    ]),
    kept: known.filter(
      (row) =>
        !listed.has(row.id) && !onScreen.has(row.id) && !deleted.has(row.id),
    ),
    seeded: [...all, ...unlisted],
  };
}
