/**
 * What a `run_outcome` row's payload says: one pull request's delivery outcome,
 * as a team node recorded it with `record_outcome`.
 *
 * TWIN PARSER: `RunOutcomePayloadSchema` in
 * `apps/daemon/src/v1/agents/chat.types.ts`, which writes these rows. An item
 * payload is `z.unknown()` on the wire, so the two sides read one shape
 * independently; a field renamed there must change here.
 */

import { RunOutcomeAcceptance } from '../autogenerated';

export interface RunOutcomePayload {
  prOwner: string;
  prRepo: string;
  prNumber: number;
  prUrl: string;
  draft: boolean;
  reviewRounds: number;
  acceptance: RunOutcomeAcceptance;
  questionsAsked: number;
  /** What the recording agent said about it, or null when it said nothing. */
  summary: string | null;
  nodeId: string;
}

const ACCEPTANCES: ReadonlySet<string> = new Set(
  Object.values(RunOutcomeAcceptance),
);

/** Whether a value is one of the daemon's acceptance words — shared by the readers of untyped outcome payloads. */
export function isRunOutcomeAcceptance(
  value: unknown,
): value is RunOutcomeAcceptance {
  return typeof value === 'string' && ACCEPTANCES.has(value);
}

/** A whole, non-negative figure — a count or a seq — on an untyped outcome payload. */
export function isOutcomeCount(value: unknown): value is number {
  return typeof value === 'number' && Number.isInteger(value) && value >= 0;
}

/** The outcome a row carries, or null when its payload is not one. */
export function readRunOutcomePayload(
  payload: unknown,
): RunOutcomePayload | null {
  if (payload === null || typeof payload !== 'object') {
    return null;
  }
  const bag = payload as Record<string, unknown>;
  if (
    typeof bag.prOwner !== 'string' ||
    typeof bag.prRepo !== 'string' ||
    !isOutcomeCount(bag.prNumber) ||
    typeof bag.prUrl !== 'string' ||
    typeof bag.draft !== 'boolean' ||
    !isOutcomeCount(bag.reviewRounds) ||
    !isRunOutcomeAcceptance(bag.acceptance) ||
    !isOutcomeCount(bag.questionsAsked) ||
    typeof bag.nodeId !== 'string'
  ) {
    return null;
  }
  return {
    prOwner: bag.prOwner,
    prRepo: bag.prRepo,
    prNumber: bag.prNumber,
    prUrl: bag.prUrl,
    draft: bag.draft,
    reviewRounds: bag.reviewRounds,
    acceptance: bag.acceptance,
    questionsAsked: bag.questionsAsked,
    summary:
      typeof bag.summary === 'string' && bag.summary.trim() !== ''
        ? bag.summary
        : null,
    nodeId: bag.nodeId,
  };
}
