// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { RunOutcomeAcceptance } from '../autogenerated';
import { outcomeSegments, outcomeSentence } from './run-outcome';
import type { RunOutcomePayload } from './run-outcome-payload';
import { RunOutcomeRow } from './run-outcome-row';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const OUTCOME: RunOutcomePayload = {
  prOwner: 'acme',
  prRepo: 'platform',
  prNumber: 87,
  prUrl: 'https://github.com/acme/platform/pull/87',
  draft: true,
  reviewRounds: 2,
  acceptance: RunOutcomeAcceptance.Accepted,
  questionsAsked: 3,
  summary: null,
  nodeId: 'manager',
};

describe('outcomeSegments', () => {
  it.each([
    [0, 'no review rounds', 'no questions'],
    [1, '1 review round', '1 question'],
    [2, '2 review rounds', '2 questions'],
  ])('words %i rounds and questions exactly', (count, rounds, questions) => {
    const words = outcomeSegments({
      ...OUTCOME,
      reviewRounds: count,
      questionsAsked: count,
    });
    expect(words.rounds).toBe(rounds);
    expect(words.questions).toBe(questions);
  });

  it.each([
    [RunOutcomeAcceptance.Accepted, 'accepted'],
    [RunOutcomeAcceptance.ChangesRequested, 'changes requested'],
    [RunOutcomeAcceptance.NotYet, 'not yet'],
    [RunOutcomeAcceptance.NotNeeded, 'not needed'],
  ])('words the acceptance %s as "%s"', (acceptance, word) => {
    expect(outcomeSegments({ ...OUTCOME, acceptance }).acceptance).toBe(word);
  });

  it('says draft or ready', () => {
    expect(outcomeSegments(OUTCOME).draft).toBe('draft');
    expect(outcomeSegments({ ...OUTCOME, draft: false }).draft).toBe('ready');
  });

  it('joins the figures into the tooltip line', () => {
    expect(outcomeSentence({ ...OUTCOME, seq: 4 })).toBe(
      'Outcome: draft · 2 review rounds · accepted · 3 questions',
    );
  });
});

describe('RunOutcomeRow', () => {
  let container: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
  });

  function render(props: Partial<Parameters<typeof RunOutcomeRow>[0]>): void {
    act(() =>
      root.render(
        <RunOutcomeRow
          outcome={OUTCOME}
          author="Manager"
          superseded={false}
          showRepo={false}
          {...props}
        />,
      ),
    );
  }

  it('dims a superseded row, says so in words, and keeps the badge word', () => {
    render({ superseded: true });
    const row = container.querySelector('[data-slot="run-outcome"]');
    expect(row?.className).toContain('opacity-70');
    expect(row?.textContent).toContain('superseded');
    expect(row?.textContent).toContain('accepted');
  });

  it("shows the agent's summary under the verdict, and the figures when it gave none", () => {
    render({ outcome: { ...OUTCOME, summary: 'Retry moved behind a flag.' } });
    expect(
      container.querySelector('[data-slot="run-outcome-preview"]')?.textContent,
    ).toBe('Retry moved behind a flag.');

    render({});
    expect(
      container.querySelector('[data-slot="run-outcome-preview"]')?.textContent,
    ).toBe('draft · 2 review rounds · 3 questions');
  });

  it('opens into the summary and every figure, with when it was recorded', () => {
    render({
      outcome: { ...OUTCOME, summary: 'Retry moved behind a flag.' },
      recordedAt: '2026-10-27T09:31:00',
    });
    act(() =>
      container
        .querySelector<HTMLButtonElement>('button[aria-expanded]')
        ?.click(),
    );
    const detail =
      container.querySelector('[data-slot="run-outcome-detail"]')
        ?.textContent ?? '';
    expect(detail).toContain('Retry moved behind a flag.');
    expect(detail).toContain('Review rounds2');
    expect(detail).toContain('Questions asked3');
    expect(detail).toContain('Oct 27, 2026');
    expect(
      container.querySelector('[data-slot="run-outcome-preview"]'),
    ).toBeNull();
  });

  it('draws a current row at full strength with no superseded tag', () => {
    render({});
    const row = container.querySelector('[data-slot="run-outcome"]');
    expect(row?.className).not.toContain('opacity-70');
    expect(row?.textContent).not.toContain('superseded');
  });
});
