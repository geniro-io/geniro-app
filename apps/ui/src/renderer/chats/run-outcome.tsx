import { Check, Clock, type LucideIcon, Minus, RefreshCw } from 'lucide-react';
import { createContext } from 'react';

import {
  type DisplayedPullRequest,
  type PullRequestOutcome,
  RunOutcomeAcceptance,
} from '../autogenerated';
import { Badge } from '../components/ui/badge';
import { cn } from '../components/ui/utils';

type BadgeVariant = 'success' | 'warning' | 'muted' | 'outline';

interface AcceptanceLook {
  word: string;
  variant: BadgeVariant;
  icon: LucideIcon;
  /** The icon's colour on the shelf chip, where it stands without its badge. */
  iconClassName: string;
}

/** Each acceptance's look, in one place for the transcript row and the shelf chip. */
const ACCEPTANCE_LOOK: Readonly<Record<RunOutcomeAcceptance, AcceptanceLook>> =
  {
    [RunOutcomeAcceptance.Accepted]: {
      word: 'accepted',
      variant: 'success',
      icon: Check,
      iconClassName: 'text-success',
    },
    [RunOutcomeAcceptance.ChangesRequested]: {
      word: 'changes requested',
      variant: 'warning',
      icon: RefreshCw,
      iconClassName: 'text-warning',
    },
    [RunOutcomeAcceptance.NotYet]: {
      word: 'not yet',
      variant: 'muted',
      icon: Clock,
      iconClassName: 'text-muted-foreground',
    },
    [RunOutcomeAcceptance.NotNeeded]: {
      word: 'not needed',
      variant: 'outline',
      icon: Minus,
      iconClassName: 'text-muted-foreground',
    },
  };

/**
 * How a pull request is keyed between the run's list and its outcome rows:
 * owner and repo case-folded, as the daemon files outcomes and as GitHub
 * resolves them.
 */
export function pullRequestOutcomeKey(ref: {
  owner: string;
  repo: string;
  number: number;
}): string {
  return `${ref.owner}/${ref.repo}#${ref.number}`.toLowerCase();
}

/** What an outcome row reads off its run. */
export interface RunOutcomes {
  /**
   * Each pull request's newest recorded outcome, as the DAEMON states it on the
   * run's list — never folded from the loaded rows, which are a window.
   */
  newest: ReadonlyMap<string, PullRequestOutcome>;
  /** The run's pull requests span several repositories, so a number needs its repo. */
  showRepo: boolean;
}

export function runOutcomesOf(
  pullRequests: readonly DisplayedPullRequest[] | undefined,
): RunOutcomes {
  const newest = new Map<string, PullRequestOutcome>();
  const repos = new Set<string>();
  for (const row of pullRequests ?? []) {
    repos.add(`${row.owner}/${row.repo}`);
    if (row.outcome != null) {
      newest.set(pullRequestOutcomeKey(row), row.outcome);
    }
  }
  return { newest, showRepo: repos.size > 1 };
}

/**
 * The open run's outcomes, for the rows that draw one: a row whose seq is older
 * than its pull request's newest outcome is drawn as superseded. Empty outside a
 * provider, which draws every row as current.
 */
export const RunOutcomesContext = createContext<RunOutcomes>({
  newest: new Map(),
  showRepo: false,
});

function plural(count: number, one: string, many: string): string {
  return `${count} ${count === 1 ? one : many}`;
}

/** The outcome's figures in words, in the order the row draws them. */
export function outcomeSegments(outcome: {
  draft: boolean;
  reviewRounds: number;
  acceptance: RunOutcomeAcceptance;
  questionsAsked: number;
}): { draft: string; rounds: string; acceptance: string; questions: string } {
  return {
    draft: outcome.draft ? 'draft' : 'ready',
    rounds:
      outcome.reviewRounds === 0
        ? 'no review rounds'
        : plural(outcome.reviewRounds, 'review round', 'review rounds'),
    acceptance: ACCEPTANCE_LOOK[outcome.acceptance].word,
    questions:
      outcome.questionsAsked === 0
        ? 'no questions'
        : plural(outcome.questionsAsked, 'question', 'questions'),
  };
}

/** The outcome as one tooltip line: `Outcome: draft · 2 review rounds · accepted · 3 questions`. */
export function outcomeSentence(outcome: PullRequestOutcome): string {
  const words = outcomeSegments(outcome);
  return `Outcome: ${words.draft} · ${words.rounds} · ${words.acceptance} · ${words.questions}`;
}

/** The acceptance as a badge — the word always shown, never colour alone. */
export function AcceptanceBadge({
  acceptance,
  muted = false,
}: {
  acceptance: RunOutcomeAcceptance;
  /** A superseded row's badge, drawn without its colour. */
  muted?: boolean;
}): React.JSX.Element {
  const look = ACCEPTANCE_LOOK[acceptance];
  return <Badge variant={muted ? 'muted' : look.variant}>{look.word}</Badge>;
}

/**
 * The acceptance as a glyph for the shelf chip, which has no room for the word;
 * the word rides along for a reader who cannot see the icon.
 */
export function AcceptanceIcon({
  acceptance,
}: {
  acceptance: RunOutcomeAcceptance;
}): React.JSX.Element {
  const look = ACCEPTANCE_LOOK[acceptance];
  const Icon = look.icon;
  return (
    <>
      <Icon
        aria-hidden="true"
        data-slot="pull-request-outcome"
        className={cn('size-3.5 shrink-0', look.iconClassName)}
      />
      <span className="sr-only">{look.word}</span>
    </>
  );
}
