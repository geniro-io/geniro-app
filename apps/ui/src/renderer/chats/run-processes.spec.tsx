// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type {
  RunProcess,
  RunProcessesDto,
  RunProcessTree,
} from '../autogenerated';
import { RunProcesses, treeLabel } from './run-processes';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function proc(over: Partial<RunProcess> = {}): RunProcess {
  return {
    pid: 100,
    ppid: 1,
    depth: 0,
    link: 'root',
    name: 'claude',
    args: 'claude -p --output-format stream-json',
    cpuPercent: 12.3,
    rssBytes: 300 * 1024 * 1024,
    elapsedSeconds: 90,
    ...over,
  };
}

function tree(over: Partial<RunProcessTree> = {}): RunProcessTree {
  return {
    sessionKey: 'run-1',
    nodeId: null,
    conversationId: null,
    agentKind: 'claude',
    cwd: '/proj',
    rootPid: 100,
    processes: [
      proc(),
      proc({
        pid: 101,
        ppid: 100,
        depth: 1,
        link: 'child',
        name: 'codegraph',
        args: 'node /usr/local/bin/codegraph serve --mcp',
        cpuPercent: 0.5,
        rssBytes: 80 * 1024 * 1024,
      }),
      proc({
        pid: 150,
        ppid: 1,
        depth: 1,
        link: 'group',
        name: 'next',
        args: 'node next dev',
        cpuPercent: 4,
        rssBytes: 512 * 1024,
      }),
    ],
    cpuPercent: 16.8,
    rssBytes: 380 * 1024 * 1024 + 512 * 1024,
    ...over,
  };
}

function reading(over: Partial<RunProcessesDto> = {}): RunProcessesDto {
  return {
    sampledAt: '2026-10-04T12:00:00.000Z',
    trees: [tree()],
    detached: [],
    processes: 3,
    cpuPercent: 16.8,
    rssBytes: 380 * 1024 * 1024 + 512 * 1024,
    unavailableReason: null,
    ...over,
  };
}

let root: Root | null = null;
let host: HTMLDivElement | null = null;

function mount(props: Parameters<typeof RunProcesses>[0]): HTMLDivElement {
  host = document.createElement('div');
  document.body.append(host);
  root = createRoot(host);
  act(() => root?.render(<RunProcesses {...props} />));
  return host;
}

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
});

describe('RunProcesses', () => {
  it('groups one agent’s processes by role, each with its CPU and memory', () => {
    const el = mount({ data: reading(), loading: false, error: null });
    const groups = [
      ...el.querySelectorAll<HTMLElement>('[data-slot="process-group"]'),
    ].map((group) => [group.dataset.role, group.textContent]);
    expect(groups).toEqual([
      ['cli', 'claudepid 10012.3%300.0 MB'],
      ['server', 'codegraph0.5%80.0 MB'],
      ['command', 'node next dev4.0%512 KBup 1mdetached'],
    ]);
    expect(
      [...el.querySelectorAll('section[aria-label]')].map((section) =>
        section.getAttribute('aria-label'),
      ),
    ).toEqual(['Agent', 'Servers & tools', 'Commands']);
    expect(
      el.querySelector('[data-slot="processes-summary"]')?.textContent,
    ).toContain('380.5 MB');
  });

  it('divides the thread’s memory between those groups in ONE bar', () => {
    const el = mount({ data: reading(), loading: false, error: null });
    expect(
      el.querySelector('[data-slot="share-stack"]')?.getAttribute('aria-label'),
    ).toBe(
      'Memory by process group: claude 79%, codegraph 21%, node next dev <1%',
    );
    // Each row wears the dot of its stretch.
    expect(el.querySelectorAll('[data-slot="share-dot"]')).toHaveLength(3);
  });

  it('opens a group of several processes onto each of them', () => {
    const el = mount({
      data: reading({
        trees: [
          tree({
            processes: [
              proc(),
              proc({ pid: 101, depth: 1, link: 'child', name: 'npm' }),
              proc({
                pid: 102,
                depth: 2,
                link: 'child',
                name: 'playwright-mcp',
              }),
            ],
          }),
        ],
      }),
      loading: false,
      error: null,
    });
    const toggle = el.querySelector<HTMLButtonElement>(
      '[data-role="server"] button[aria-expanded]',
    );
    expect(toggle?.textContent).toContain('playwright-mcp');
    // The count is a badge, so the name keeps the width.
    expect(
      toggle?.querySelector('[data-slot="process-count"]')?.textContent,
    ).toBe('2');
    expect(
      el.querySelector('ul[aria-label="Processes of playwright-mcp"]'),
    ).toBeNull();
    act(() => toggle?.click());
    expect(
      [
        ...el.querySelectorAll(
          'ul[aria-label="Processes of playwright-mcp"] > li',
        ),
      ].map((li) => li.textContent?.split(/\d/)[0]),
    ).toEqual(['npm', 'playwright-mcp']);
  });

  it('carries every full command line on hover', () => {
    const el = mount({ data: reading(), loading: false, error: null });
    const command = el.querySelector('[data-role="command"] [title]');
    expect(command?.getAttribute('title')).toContain('node next dev');
    expect(command?.getAttribute('title')).toContain('process group');
  });

  it('says when the thread has nothing running', () => {
    const el = mount({
      data: reading({ trees: [], processes: 0 }),
      loading: false,
      error: null,
    });
    expect(el.textContent).toBe('no agent process is running for this thread');
  });

  it('says why when the process table could not be read, instead of claiming nothing runs', () => {
    const el = mount({
      data: reading({ trees: [], unavailableReason: 'ps failed' }),
      loading: false,
      error: null,
    });
    expect(el.textContent).toBe('ps failed');
  });
});

describe('RunProcesses — what the agents left detached', () => {
  const DEV = [
    proc({
      pid: 500,
      ppid: 1,
      depth: 0,
      link: 'root',
      name: 'pnpm',
      args: 'node /usr/local/bin/pnpm dev',
      rssBytes: 100 * 1024 * 1024,
    }),
    proc({
      pid: 501,
      ppid: 500,
      depth: 1,
      link: 'child',
      name: 'next-server',
      args: 'next-server (v16)',
      rssBytes: 900 * 1024 * 1024,
    }),
  ];

  it('lists them with no agent running, each command with its figures', () => {
    const el = mount({
      data: reading({ trees: [], detached: DEV, processes: 2 }),
      loading: false,
      error: null,
    });
    const section = el.querySelector('[data-slot="processes-detached"]');
    expect(section?.textContent).toContain('Detached');
    expect(section?.textContent).toContain('node /usr/local/bin/pnpm dev');
    expect(section?.textContent).toContain('1000.0 MB');
    expect(
      el.querySelector('[data-slot="processes-summary"]')?.textContent,
    ).toContain('2 processes · 2 detached');
    expect(
      section
        ?.querySelector('[data-slot="process-group"] [title]')
        ?.getAttribute('title'),
    ).toContain('no agent CLI holds it');
  });

  it('gives them their own stretch of the bar beside the agent’s groups', () => {
    const el = mount({
      data: reading({ detached: DEV, processes: 5 }),
      loading: false,
      error: null,
    });
    expect(
      el.querySelector('[data-slot="share-stack"]')?.getAttribute('aria-label'),
    ).toContain('node /usr/local/bin/pnpm dev');
    expect(el.querySelector('[data-slot="processes-detached"]')).not.toBeNull();
  });
});

describe('RunProcesses — several agents', () => {
  function several(): HTMLDivElement {
    return mount({
      data: reading({
        trees: [
          tree({ sessionKey: 'run-1::node:qa', nodeId: 'qa', rssBytes: 300 }),
          tree({
            sessionKey: 'run-1::call:call-2',
            conversationId: 'call-2',
            rssBytes: 100,
          }),
        ],
        rssBytes: 400,
      }),
      loading: false,
      error: null,
    });
  }

  it('divides the thread’s memory by AGENT, one block each', () => {
    const el = several();
    expect(
      el.querySelector('[data-slot="share-stack"]')?.getAttribute('aria-label'),
    ).toBe('Memory by agent: qa 75%, call call-2 25%');
    expect(
      el.querySelector('[data-slot="processes-summary"]')?.textContent,
    ).toContain('2 agents');
  });

  it('gives what the agents left detached its own colour after theirs', () => {
    const el = mount({
      data: reading({
        trees: [
          tree({ sessionKey: 'run-1::node:qa', nodeId: 'qa', rssBytes: 300 }),
          tree({
            sessionKey: 'run-1::call:call-2',
            conversationId: 'call-2',
            rssBytes: 100,
          }),
        ],
        detached: [
          proc({ pid: 500, ppid: 1, depth: 0, name: 'pnpm', args: 'pnpm dev' }),
        ],
        rssBytes: 700,
      }),
      loading: false,
      error: null,
    });
    const swatches = [
      ...el.querySelectorAll('[data-slot="share-segment"]'),
    ].map((segment) => segment.className);
    expect(swatches).toHaveLength(3);
    // The detached group's stretch and its row's dot are one colour, and no
    // agent's.
    const detachedDot = el
      .querySelector('[data-slot="processes-detached"] [data-slot="share-dot"]')
      ?.className.split(' ')
      .find((name) => name.startsWith('bg-'));
    expect(detachedDot).toBeDefined();
    expect(swatches[2]).toContain(detachedDot as string);
    expect(swatches[0]).not.toContain(detachedDot as string);
    expect(swatches[1]).not.toContain(detachedDot as string);
  });

  it('folds an agent away on its header', () => {
    const el = several();
    const header = el.querySelector<HTMLButtonElement>(
      'li > button[aria-expanded]',
    );
    expect(el.querySelectorAll('[data-role="cli"]')).toHaveLength(2);
    act(() => header?.click());
    expect(header?.getAttribute('aria-expanded')).toBe('false');
    expect(el.querySelectorAll('[data-role="cli"]')).toHaveLength(1);
  });
});

describe('treeLabel', () => {
  it('names a node, then a callee conversation, then the chat’s CLI', () => {
    expect(treeLabel(tree({ nodeId: 'qa' }), 'claude')).toBe('qa');
    expect(treeLabel(tree({ conversationId: 'call-3' }), 'claude')).toBe(
      'call call-3',
    );
    expect(treeLabel(tree(), 'claude')).toBe('claude');
  });
});
