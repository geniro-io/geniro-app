// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type {
  RunProcess,
  RunProcessesDto,
  RunProcessTree,
} from '../autogenerated';
import { formatMemory, RunProcesses, treeLabel } from './run-processes';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function proc(over: Partial<RunProcess> = {}): RunProcess {
  return {
    pid: 100,
    ppid: 1,
    depth: 0,
    link: 'root',
    name: 'claude',
    args: 'claude -p --output-format stream-json',
    cpuPercent: 12.3,
    rssBytes: 300 * 1024 * 1024,
    elapsedSeconds: 90,
    ...over,
  };
}

function tree(over: Partial<RunProcessTree> = {}): RunProcessTree {
  return {
    sessionKey: 'run-1',
    nodeId: null,
    conversationId: null,
    agentKind: 'claude',
    cwd: '/proj',
    rootPid: 100,
    processes: [
      proc(),
      proc({
        pid: 101,
        ppid: 100,
        depth: 1,
        link: 'child',
        name: 'codegraph',
        args: 'node /usr/local/bin/codegraph serve --mcp',
        cpuPercent: 0.5,
        rssBytes: 80 * 1024 * 1024,
      }),
      proc({
        pid: 150,
        ppid: 1,
        depth: 1,
        link: 'group',
        name: 'next',
        args: 'node next dev',
        cpuPercent: 4,
        rssBytes: 512 * 1024,
      }),
    ],
    cpuPercent: 16.8,
    rssBytes: 380 * 1024 * 1024 + 512 * 1024,
    ...over,
  };
}

function reading(over: Partial<RunProcessesDto> = {}): RunProcessesDto {
  return {
    sampledAt: '2026-10-04T12:00:00.000Z',
    trees: [tree()],
    processes: 3,
    cpuPercent: 16.8,
    rssBytes: 380 * 1024 * 1024 + 512 * 1024,
    unavailableReason: null,
    ...over,
  };
}

let root: Root | null = null;
let host: HTMLDivElement | null = null;

function mount(props: Parameters<typeof RunProcesses>[0]): HTMLDivElement {
  host = document.createElement('div');
  document.body.append(host);
  root = createRoot(host);
  act(() => root?.render(<RunProcesses {...props} />));
  return host;
}

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
});

describe('RunProcesses', () => {
  it('lists every process of every agent tree, with its CPU and memory', () => {
    const el = mount({ data: reading(), loading: false, error: null });
    const rows = [...el.querySelectorAll('ul[aria-label] > li')].map(
      (li) => li.textContent,
    );
    expect(rows).toEqual([
      'claude10012.3%300.0 MB',
      'codegraph1010.5%80.0 MB',
      'next150detached4.0%512 KB',
    ]);
    expect(el.textContent).toContain('380.5 MB');
  });

  it('carries the full command line and how it was attributed on hover', () => {
    const el = mount({ data: reading(), loading: false, error: null });
    const detached = [...el.querySelectorAll('li[title]')].find((li) =>
      li.textContent?.startsWith('next'),
    );
    expect(detached?.getAttribute('title')).toContain('node next dev');
    expect(detached?.getAttribute('title')).toContain('process group');
  });

  it('says when the thread has nothing running', () => {
    const el = mount({
      data: reading({ trees: [], processes: 0 }),
      loading: false,
      error: null,
    });
    expect(el.textContent).toBe('no agent process is running for this thread');
  });

  it('says why when the process table could not be read, instead of claiming nothing runs', () => {
    const el = mount({
      data: reading({ trees: [], unavailableReason: 'ps failed' }),
      loading: false,
      error: null,
    });
    expect(el.textContent).toBe('ps failed');
  });
});

describe('treeLabel', () => {
  it('names a node, then a callee conversation, then the chat’s one agent', () => {
    expect(treeLabel(tree({ nodeId: 'qa' }))).toBe('qa');
    expect(treeLabel(tree({ conversationId: 'call-3' }))).toBe('call call-3');
    expect(treeLabel(tree())).toBe('agent');
  });
});

describe('formatMemory', () => {
  it.each([
    [512 * 1024, '512 KB'],
    [5 * 1024 * 1024, '5.0 MB'],
    [3 * 1024 * 1024 * 1024, '3.00 GB'],
  ])('%d bytes reads %s', (bytes, text) => {
    expect(formatMemory(bytes)).toBe(text);
  });
});
