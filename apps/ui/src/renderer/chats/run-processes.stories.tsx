import type { Meta, StoryObj } from '@storybook/react-vite';
import { useState } from 'react';

import type { RunProcess } from '../autogenerated';
import { RunProcesses } from './run-processes';

const detached: RunProcess[] = [
  {
    pid: 500,
    ppid: 1,
    depth: 0,
    link: 'root',
    name: 'node',
    args: 'node preview-server.js --port 3000',
    cpuPercent: 1.2,
    rssBytes: 128 * 1024 * 1024,
    elapsedSeconds: 300,
  },
  {
    pid: 501,
    ppid: 500,
    depth: 1,
    link: 'child',
    name: 'watcher',
    args: 'node watcher.js',
    cpuPercent: 0.1,
    rssBytes: 32 * 1024 * 1024,
    elapsedSeconds: 299,
  },
  {
    pid: 600,
    ppid: 1,
    depth: 0,
    link: 'root',
    name: 'sleep',
    args: 'sleep 600',
    cpuPercent: 0,
    rssBytes: 1024 * 1024,
    elapsedSeconds: 60,
  },
];

const meta = {
  title: 'Chats/RunProcesses',
  component: RunProcesses,
  args: { data: null, loading: false, error: null },
  decorators: [
    (story) => (
      <div className="h-[480px] w-80 bg-background p-3 text-foreground">
        {story()}
      </div>
    ),
  ],
} satisfies Meta<typeof RunProcesses>;

export default meta;
type Story = StoryObj<typeof meta>;

function DetachedProcesses({
  fail = false,
}: {
  fail?: boolean;
}): React.JSX.Element {
  const [processes, setProcesses] = useState(detached);
  return (
    <RunProcesses
      data={{
        sampledAt: '2026-10-16T12:00:00.000Z',
        trees: [],
        detached: processes,
        processes: processes.length,
        cpuPercent: processes.reduce(
          (sum, process) => sum + process.cpuPercent,
          0,
        ),
        rssBytes: processes.reduce((sum, process) => sum + process.rssBytes, 0),
        unavailableReason: null,
      }}
      loading={false}
      error={null}
      onStopDetached={async (pids) => {
        if (fail) {
          throw new Error(
            'A selected process is no longer detached. Refresh and try again.',
          );
        }
        setProcesses((current) =>
          current.filter((process) => !pids.includes(process.pid)),
        );
      }}
    />
  );
}

export const Detached: Story = { render: () => <DetachedProcesses /> };
export const StopFailed: Story = { render: () => <DetachedProcesses fail /> };
