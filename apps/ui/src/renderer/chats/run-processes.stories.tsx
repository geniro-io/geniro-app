type Story = StoryObj<typeof meta>;

function DetachedProcesses({
  fail = false,
  withMonitor = false,
}: {
  fail?: boolean;
  withMonitor?: boolean;
}): React.JSX.Element {
  const [processes, setProcesses] = useState(detached);
  const [monitors, setMonitors] = useState(withMonitor ? [monitor] : []);
  return (
    <RunProcesses
      data={{
        sampledAt: '2026-10-16T12:00:00.000Z',
        trees: [],
        detached: processes,
        monitors,
        processes:
          processes.length +
          monitors.reduce((sum, m) => sum + m.processes.length, 0),
        cpuPercent:
          processes.reduce((sum, process) => sum + process.cpuPercent, 0) +
          monitors.reduce((sum, m) => sum + m.cpuPercent, 0),
        rssBytes:
          processes.reduce((sum, process) => sum + process.rssBytes, 0) +
          monitors.reduce((sum, m) => sum + m.rssBytes, 0),
        unavailableReason: null,
      }}
      loading={false}
      error={null}
      onStopDetached={async (pids, monitorIds) => {
        if (fail) {
          throw new Error(
            'A selected process is no longer detached. Refresh and try again.',
          );
        }
        setProcesses((current) =>
          current.filter((process) => !pids.includes(process.pid)),
        );
        setMonitors((current) =>
          current.filter((m) => !monitorIds.includes(m.id)),
        );
      }}
    />
  );
}

export const Detached: Story = { render: () => <DetachedProcesses /> };
export const StopFailed: Story = { render: () => <DetachedProcesses fail /> };
export const WithMonitor: Story = {
  render: () => <DetachedProcesses withMonitor />,
};
