/** Deeper than this, a nested row stops indenting — the column is narrow. */
const MAX_INDENT_DEPTH = 3;

function formatUptime(seconds: number | null): string | null {
  if (seconds === null) {
    return null;
  }
  if (seconds < 60) {
    return `${seconds}s`;
  }
  if (seconds < 3_600) {
    return `${Math.floor(seconds / 60)}m`;
  }
  if (seconds < 86_400) {
    return `${Math.floor(seconds / 3_600)}h ${Math.floor((seconds % 3_600) / 60)}m`;
  }
  return `${Math.floor(seconds / 86_400)}d ${Math.floor((seconds % 86_400) / 3_600)}h`;
}

/**
 * Whose process this is: the workflow node, the callee conversation, or — for
 * a chat, whose one agent has no name of its own — its CLI.
 */
export function treeLabel(tree: RunProcessTree, agentName: string): string {
  if (tree.nodeId !== null) {
    return tree.nodeId;
  }
  if (tree.conversationId !== null) {
    return `call ${tree.conversationId}`;
  }
  return agentName;
}

function processTitle(process: RunProcess): string {
  const uptime = formatUptime(process.elapsedSeconds);
  const how =
    process.link === 'root'
      ? 'the agent CLI geniro started'
      : process.link === 'group'
        ? 'outlived the shell that started it — kept by the CLI’s process group'
        : `started under pid ${process.ppid}`;
  return [
    `pid ${process.pid}${uptime === null ? '' : ` · up ${uptime}`} · ${how}`,
    process.args,
  ].join('\n');
}

/** The muted half of a group's row: what kind of thing it is, briefly. */
function groupDetail(group: ProcessGroup): string | null {
  if (group.role === 'cli') {
    return `pid ${group.processes[0]?.pid ?? '?'}`;
  }
  const uptime = formatUptime(group.elapsedSeconds);
  return group.role === 'command' && uptime !== null ? `up ${uptime}` : null;
}

function NestedProcess({
  process,
  baseDepth,
}: {
  process: RunProcess;
  baseDepth: number;
}): React.JSX.Element {
  return (
    <li
      className="flex items-baseline gap-1.5 text-[11px]"
      title={processTitle(process)}
      style={{
        paddingLeft: `${Math.min(process.depth - baseDepth, MAX_INDENT_DEPTH) * 10}px`,
      }}>
      <span className="flex min-w-0 flex-1 items-baseline gap-1.5">
        <span className="min-w-0 truncate text-foreground">{process.name}</span>
        <span className="shrink-0 font-mono text-[10px] text-muted-foreground tabular-nums">
          {process.pid}
        </span>
      </span>
      <ProcessFigureCells
        cpuPercent={process.cpuPercent}
        rssBytes={process.rssBytes}
      />
    </li>
  );
}

function GroupRow({
  group,
  memoryKey,
  colorClass,
}: {
  group: ProcessGroup;
  memoryKey: string;
  colorClass: string | null;
}): React.JSX.Element {
  const expandable = group.processes.length > 1;
  const [open, setOpen] = useThreadFlag(memoryKey, false);
  const detail = groupDetail(group);
  const title = group.processes.map(processTitle).join('\n\n');
  // A command gets the whole first line for itself — it is the most telling
  // text in the section and the longest — and states how long it has run, and
  // whether it outlived its shell, on a second line under it.
  const isCommand = group.role === 'command';
  const line = (
    <>
      <span className="flex w-full items-center gap-1.5">
        <span className="flex min-w-0 flex-1 items-center gap-1.5">
          {expandable ? (
            <ChevronRight
              aria-hidden="true"
              className={cn(
                'size-3 shrink-0 text-muted-foreground transition-transform',
                open && 'rotate-90',
              )}
            />
          ) : (
            <span aria-hidden="true" className="size-3 shrink-0" />
          )}
          {colorClass === null ? null : <ShareDot colorClass={colorClass} />}
          {/* The NAME is what a reader scans for, so it is the last thing to
              give up width: everything after it shrinks first. */}
          <span
            className={cn(
              'min-w-[2.5rem] truncate',
              isCommand ? 'font-mono text-[11px]' : '',
              group.role === 'cli'
                ? 'font-medium text-foreground'
                : 'text-foreground',
            )}>
            {group.label}
          </span>
          {group.size > 1 ? (
            <span
              data-slot="process-count"
              title={`${group.size} processes`}
              className="shrink-0 rounded-full bg-muted px-1.5 text-[10px] text-muted-foreground tabular-nums">
              {group.size}
            </span>
          ) : null}
          {detail !== null && !isCommand ? (
            <span className="min-w-0 shrink-[4] truncate text-[11px] text-muted-foreground tabular-nums">
              {detail}
            </span>
          ) : null}
        </span>
        <ProcessFigureCells
          cpuPercent={group.cpuPercent}
          rssBytes={group.rssBytes}
        />
      </span>
      {isCommand && (detail !== null || group.detached) ? (
        <span
          data-slot="process-command-detail"
          className={cn(
            'flex items-center gap-1.5 text-[11px] text-muted-foreground tabular-nums',
            colorClass === null ? 'pl-[18px]' : 'pl-[32px]',
          )}>
          {detail}
          {group.detached ? (
            <span className="rounded border border-border px-1 py-px text-[10px]">
              detached
            </span>
          ) : null}
        </span>
      ) : null}
    </>
  );
  return (
    <li
      data-slot="process-group"
      data-role={group.role}
      className="flex flex-col">
      {expandable ? (
        <button
          type="button"
          aria-expanded={open}
          onClick={() => setOpen((value) => !value)}
          title={title}
          className="-mx-1 flex flex-col gap-0.5 rounded-md px-1 py-1 text-left text-xs outline-none hover:bg-muted focus-visible:ring-2 focus-visible:ring-ring/50">
          {line}
        </button>
      ) : (
        <div
          title={title}
          className="-mx-1 flex flex-col gap-0.5 px-1 py-1 text-xs">
          {line}
        </div>
      )}
      {expandable && open ? (
        <ul
          aria-label={`Processes of ${group.label}`}
          className="m-0 mb-1 ml-[5px] flex list-none flex-col gap-0.5 border-l border-border p-0 py-0.5 pl-3">
          {group.processes.map((process) => (
            <NestedProcess
              key={process.pid}
              process={process}
              baseDepth={group.processes[0]?.depth ?? 0}
            />
          ))}
        </ul>
      ) : null}
    </li>
  );
}

/**
 * One agent's processes, as the groups a reader thinks in — the CLI, its
 * servers and tools, its commands — each a captioned section.
 */
function AgentGroups({
  tree,
  groups,
  colorOf,
  columns,
}: {
  tree: RunProcessTree;
  groups: readonly ProcessGroup[];
  /** The dot each group wears, or null when the division is by AGENT. */
  colorOf: ((group: ProcessGroup) => string) | null;
  /** Whether the first caption names the CPU / memory columns. */
  columns: boolean;
}): React.JSX.Element {
  const roles = ROLE_ORDER.filter((role) =>
    groups.some((group) => group.role === role),
  );
  return (
    <div className="flex flex-col gap-1.5">
      {roles.map((role, index) => {
        const ofRole = groups.filter((group) => group.role === role);
        return (
          <section key={role} aria-label={ROLE_CAPTION[role]}>
            <ProcessFigureHeader
              className="mb-0.5"
              columns={columns && index === 0}
              label={
                <>
                  {ROLE_CAPTION[role]}
                  {role === 'cli' ? null : (
                    <span className="ml-1 tabular-nums">{ofRole.length}</span>
                  )}
                </>
              }
            />
            <ul className="m-0 flex list-none flex-col p-0">
              {ofRole.map((group) => (
                <GroupRow
                  key={group.key}
                  group={group}
                  memoryKey={`processes:${tree.sessionKey}:${group.key}`}
                  colorClass={colorOf === null ? null : colorOf(group)}
                />
              ))}
            </ul>
          </section>
        );
      })}
    </div>
  );
}

/** One agent among several — its own block, folded on its header. */
function AgentBlock({
  tree,
  colorClass,
}: {
  tree: RunProcessTree;
  colorClass: string;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  const agentName =
    tree.agentKind === null
      ? 'agent'
      : agentShortName(identities, tree.agentKind);
  const label = treeLabel(tree, agentName);
  const [open, setOpen] = useThreadFlag(`processes:${tree.sessionKey}`, true);
  return (
    <li className="flex flex-col gap-1.5">
      <button
        type="button"
        aria-expanded={open}
        onClick={() => setOpen((value) => !value)}
        title={tree.cwd}
        className="-mx-1 flex items-center gap-1.5 rounded-md px-1 py-1 text-xs outline-none hover:bg-muted focus-visible:ring-2 focus-visible:ring-ring/50">
        <span className="flex min-w-0 flex-1 items-center gap-1.5">
          <ChevronRight
            aria-hidden="true"
            className={cn(
              'size-3 shrink-0 text-muted-foreground transition-transform',
              open && 'rotate-90',
            )}
          />
          <ShareDot colorClass={colorClass} />
          <AgentGlyph
            icon={agentIconName(identities, tree.agentKind ?? '')}
            className="size-3.5 shrink-0 text-muted-foreground"
          />
          <span className="min-w-0 truncate font-medium text-foreground">
            {label}
          </span>
          {label !== agentName ? (
            <span className="shrink-0 text-muted-foreground">{agentName}</span>
          ) : null}
        </span>
        <ProcessFigureCells
          cpuPercent={tree.cpuPercent}
          rssBytes={tree.rssBytes}
          strong
        />
      </button>
      {open ? (
        <div className="ml-[5px] border-l border-border pl-3">
          <AgentGroups
            tree={tree}
            groups={groupProcesses(tree)}
            colorOf={null}
            columns={false}
          />
        </div>
      ) : null}
    </li>
  );
}

/**
 * Every process this thread has running — each agent CLI geniro started for
 * it, and what that CLI runs: its servers and tools, and the commands it
 * started — with CPU and resident memory, and ONE bar showing how the
 * thread's memory divides between them.
 *
 * A LIVE reading, not a history: a process that has ended is simply gone from
 * the next poll.
 */
export function RunProcesses({
  data,
  loading,
  error,
}: {
  data: RunProcessesDto | null;
  loading: boolean;
  error: string | null;
}): React.JSX.Element | null {
  const identities = useContext(AgentIdentityContext);
  if (data === null) {
    if (error !== null) {
      return <p className="text-xs text-muted-foreground">{error}</p>;
    }
    return loading ? (
      <p className="text-xs text-muted-foreground">reading processes…</p>
    ) : null;
  }
  if (data.trees.length === 0) {
    return (
      <div className="flex flex-col gap-1">
        <p className="text-xs text-muted-foreground">
          {data.unavailableReason ??
            'no agent process is running for this thread'}
        </p>
        {error === null ? null : (
          <p className="text-[11px] text-muted-foreground">{error}</p>
        )}
      </div>
    );
  }

  const several = data.trees.length > 1;
  const single = several ? null : (data.trees[0] as RunProcessTree);
  const singleGroups = single === null ? [] : groupProcesses(single);
  // One colour per part of the division, in the order the bar draws them.
  const groupColor = new Map(
    singleGroups.map((group, index) => [group.key, segmentColorClass(index)]),
  );
  const segments: ShareSegment[] = several
    ? data.trees.map((tree, index) => ({
        key: tree.sessionKey,
        label: treeLabel(
          tree,
          tree.agentKind === null
            ? 'agent'
            : agentShortName(identities, tree.agentKind),
        ),
        value: tree.rssBytes,
        colorClass: segmentColorClass(index),
      }))
    : singleGroups.map((group) => ({
        key: group.key,
        label: group.label,
        value: group.rssBytes,
        colorClass: groupColor.get(group.key) ?? '',
      }));

  return (
    <div className="flex flex-col gap-2">
      <div
        data-slot="processes-summary"
        className="flex items-baseline gap-1.5 text-xs">
        <span className="min-w-0 flex-1 truncate text-muted-foreground">
          {data.processes} process{data.processes === 1 ? '' : 'es'}
          {several ? ` · ${data.trees.length} agents` : ''}
        </span>
        <span className="shrink-0 text-muted-foreground tabular-nums">
          {formatCpu(data.cpuPercent)} CPU
        </span>
        <span className="shrink-0 font-medium text-foreground tabular-nums">
          {formatMemory(data.rssBytes)}
        </span>
      </div>
      <ShareStack
        segments={segments}
        label={several ? 'Memory by agent' : 'Memory by process group'}
      />
      {several ? <ProcessFigureHeader label="agents" className="mt-1" /> : null}
      {single === null ? (
        <ul className="m-0 flex list-none flex-col gap-2 p-0">
          {data.trees.map((tree, index) => (
            <AgentBlock
              key={tree.sessionKey}
              tree={tree}
              colorClass={segmentColorClass(index)}
            />
          ))}
        </ul>
      ) : (
        <AgentGroups
          tree={single}
          groups={singleGroups}
          colorOf={(group) => groupColor.get(group.key) ?? ''}
          columns
        />
      )}
      {error === null ? null : (
        <p className="text-[11px] text-muted-foreground">{error}</p>
      )}
    </div>
  );
}
