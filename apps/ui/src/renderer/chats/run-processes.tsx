import type {
  RunProcess,
  RunProcessesDto,
  RunProcessTree,
} from '../autogenerated';

/** Deeper than this, a row stops indenting — the column is ~280px wide. */
const MAX_INDENT_DEPTH = 4;

const KIB = 1024;

/** Resident memory in the unit a reader expects from Activity Monitor. */
export function formatMemory(bytes: number): string {
  if (bytes < KIB * KIB) {
    return `${Math.max(0, Math.round(bytes / KIB))} KB`;
  }
  if (bytes < KIB * KIB * KIB) {
    return `${(bytes / (KIB * KIB)).toFixed(1)} MB`;
  }
  return `${(bytes / (KIB * KIB * KIB)).toFixed(2)} GB`;
}

/** Percent of one core, as `ps` and Activity Monitor both state it. */
export function formatCpu(percent: number): string {
  return `${percent.toFixed(1)}%`;
}

function formatUptime(seconds: number | null): string | null {
  if (seconds === null) {
    return null;
  }
  if (seconds < 60) {
    return `${seconds}s`;
  }
  if (seconds < 3_600) {
    return `${Math.floor(seconds / 60)}m`;
  }
  if (seconds < 86_400) {
    return `${Math.floor(seconds / 3_600)}h ${Math.floor((seconds % 3_600) / 60)}m`;
  }
  return `${Math.floor(seconds / 86_400)}d ${Math.floor((seconds % 86_400) / 3_600)}h`;
}

/** Whose process this is: the node, the callee conversation, or the chat. */
export function treeLabel(tree: RunProcessTree): string {
  if (tree.nodeId !== null) {
    return tree.nodeId;
  }
  if (tree.conversationId !== null) {
    return `call ${tree.conversationId}`;
  }
  return 'agent';
}

function processTitle(process: RunProcess): string {
  const uptime = formatUptime(process.elapsedSeconds);
  const how =
    process.link === 'root'
      ? 'the agent CLI geniro started'
      : process.link === 'group'
        ? 'outlived the shell that started it — kept by the CLI’s process group'
        : `started under pid ${process.ppid}`;
  return [
    `pid ${process.pid}${uptime === null ? '' : ` · up ${uptime}`} · ${how}`,
    process.args,
  ].join('\n');
}

function ProcessRow({ process }: { process: RunProcess }): React.JSX.Element {
  return (
    <li
      className="flex items-baseline gap-1.5 text-xs"
      title={processTitle(process)}
      style={{
        paddingLeft: `${Math.min(process.depth, MAX_INDENT_DEPTH) * 10}px`,
      }}>
      <span
        className={
          process.link === 'root'
            ? 'min-w-0 truncate font-medium text-foreground'
            : 'min-w-0 truncate text-foreground'
        }>
        {process.name}
      </span>
      <span className="shrink-0 text-[11px] text-muted-foreground tabular-nums">
        {process.pid}
      </span>
      {process.link === 'group' ? (
        <span className="shrink-0 text-[11px] text-muted-foreground">
          detached
        </span>
      ) : null}
      <span className="ml-auto shrink-0 text-muted-foreground tabular-nums">
        {formatCpu(process.cpuPercent)}
      </span>
      <span className="w-16 shrink-0 text-right text-foreground tabular-nums">
        {formatMemory(process.rssBytes)}
      </span>
    </li>
  );
}

function ProcessTree({ tree }: { tree: RunProcessTree }): React.JSX.Element {
  return (
    <li className="flex flex-col gap-1">
      <div className="flex items-baseline gap-1.5 text-xs" title={tree.cwd}>
        <span className="truncate font-medium text-foreground">
          {treeLabel(tree)}
        </span>
        {tree.agentKind === null ? null : (
          <span className="truncate text-muted-foreground">
            {tree.agentKind}
          </span>
        )}
        <span className="ml-auto shrink-0 text-muted-foreground tabular-nums">
          {formatCpu(tree.cpuPercent)}
        </span>
        <span className="w-16 shrink-0 text-right font-medium text-foreground tabular-nums">
          {formatMemory(tree.rssBytes)}
        </span>
      </div>
      <ul
        aria-label={`Processes of ${treeLabel(tree)}`}
        className="m-0 flex list-none flex-col gap-0.5 border-l border-border p-0 pl-2">
        {tree.processes.map((process) => (
          <ProcessRow key={process.pid} process={process} />
        ))}
      </ul>
    </li>
  );
}

/**
 * Every process this thread has running — each agent CLI geniro started for
 * it and the whole tree under it (MCP servers, shells, dev servers,
 * sub-agents' tools) — with CPU and resident memory per process.
 *
 * A LIVE reading, not a history: a process that has ended is simply gone from
 * the next poll.
 */
export function RunProcesses({
  data,
  loading,
  error,
}: {
  data: RunProcessesDto | null;
  loading: boolean;
  error: string | null;
}): React.JSX.Element | null {
  if (data === null) {
    if (error !== null) {
      return <p className="text-xs text-muted-foreground">{error}</p>;
    }
    return loading ? (
      <p className="text-xs text-muted-foreground">reading processes…</p>
    ) : null;
  }
  return (
    <div className="flex flex-col gap-2">
      {data.unavailableReason === null ? null : (
        <p className="text-xs text-muted-foreground">
          {data.unavailableReason}
        </p>
      )}
      {data.trees.length === 0 ? (
        data.unavailableReason === null ? (
          <p className="text-xs text-muted-foreground">
            no agent process is running for this thread
          </p>
        ) : null
      ) : (
        <>
          <dl className="grid grid-cols-3 gap-1 text-xs">
            <Figure label="processes" value={String(data.processes)} />
            <Figure label="cpu" value={formatCpu(data.cpuPercent)} />
            <Figure label="memory" value={formatMemory(data.rssBytes)} />
          </dl>
          <ul className="m-0 flex list-none flex-col gap-2 p-0">
            {data.trees.map((tree) => (
              <ProcessTree key={tree.sessionKey} tree={tree} />
            ))}
          </ul>
        </>
      )}
      {error === null ? null : (
        <p className="text-[11px] text-muted-foreground">{error}</p>
      )}
    </div>
  );
}

function Figure({
  label,
  value,
}: {
  label: string;
  value: string;
}): React.JSX.Element {
  return (
    <div className="flex min-w-0 flex-col">
      <dt className="text-[11px] text-muted-foreground">{label}</dt>
      <dd className="m-0 truncate font-medium text-foreground tabular-nums">
        {value}
      </dd>
    </div>
  );
}
