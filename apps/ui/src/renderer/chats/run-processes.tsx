/** Deeper than this, a nested row stops indenting — the column is narrow. */
const MAX_INDENT_DEPTH = 3;

function formatUptime(seconds: number | null): string | null {
  if (seconds === null) {
    return null;
  }
  if (seconds < 60) {
    return `${seconds}s`;
  }
  if (seconds < 3_600) {
    return `${Math.floor(seconds / 60)}m`;
  }
  if (seconds < 86_400) {
    return `${Math.floor(seconds / 3_600)}h ${Math.floor((seconds % 3_600) / 60)}m`;
  }
  return `${Math.floor(seconds / 86_400)}d ${Math.floor((seconds % 86_400) / 3_600)}h`;
}

/**
 * Whose process this is: the workflow node, the callee conversation, or — for
 * a chat, whose one agent has no name of its own — its CLI.
 */
export function treeLabel(tree: RunProcessTree, agentName: string): string {
  if (tree.nodeId !== null) {
    return tree.nodeId;
  }
  if (tree.conversationId !== null) {
    return `call ${tree.conversationId}`;
  }
  return agentName;
}

/**
 * A process's hover text. `detached` marks a process from the thread's
 * detached set, whose top was left running by an agent rather than started
 * by geniro; `monitor` one that belongs to an agent's monitor.
 */
function processTitle(
  process: RunProcess,
  detached = false,
  monitor = false,
): string {
  const uptime = formatUptime(process.elapsedSeconds);
  const how =
    process.link === 'root'
      ? monitor
        ? 'the shell of an agent’s monitor'
        : detached
          ? 'left running by this thread’s agents — no agent CLI holds it; stop it here or archive the thread'
          : 'the agent CLI geniro started'
      : process.link === 'group'
        ? 'outlived the shell that started it — kept by the CLI’s process group'
        : `started under pid ${process.ppid}`;
  return [
    `pid ${process.pid}${uptime === null ? '' : ` · up ${uptime}`} · ${how}`,
    process.args,
  ].join('\n');
}

/** What a monitor's row hover says first: its id and how long it has left. */
function monitorTitle(monitor: MonitorFacts): string {
  const left = monitor.remainingSeconds;
  const timeout =
    left === null
      ? null
      : left <= 0
        ? 'past its timeout'
        : `${formatUptime(left)} left`;
  return `monitor ${monitor.id}${timeout === null ? '' : ` · ${timeout}`}`;
}

/** The muted half of a group's row: what kind of thing it is, briefly. */
function groupDetail(group: ProcessGroup): string | null {
  if (group.monitor !== null) {
    const uptime = formatUptime(group.elapsedSeconds);
    return [uptime === null ? null : `up ${uptime}`, group.monitor.description]
      .filter((part) => part !== null)
      .join(' · ');
  }
  if (group.role === 'cli') {
    return `pid ${group.processes[0]?.pid ?? '?'}`;
  }
  const uptime = formatUptime(group.elapsedSeconds);
  return group.role === 'command' && uptime !== null ? `up ${uptime}` : null;
}

function NestedProcess({
  process,
  baseDepth,
  detached,
  monitor,
}: {
  process: RunProcess;
  baseDepth: number;
  detached: boolean;
  monitor: boolean;
}): React.JSX.Element {
  return (
    <li
      className="flex items-baseline gap-1.5 text-[11px]"
      title={processTitle(process, detached, monitor)}
      style={{
        paddingLeft: `${Math.min(process.depth - baseDepth, MAX_INDENT_DEPTH) * 10}px`,
      }}>
      <span className="flex min-w-0 flex-1 items-baseline gap-1.5">
        <span className="min-w-0 truncate text-foreground">{process.name}</span>
        <span className="shrink-0 font-mono text-[10px] text-muted-foreground tabular-nums">
          {process.pid}
        </span>
      </span>
      <ProcessFigureCells
        cpuPercent={process.cpuPercent}
        rssBytes={process.rssBytes}
      />
    </li>
  );
}

function GroupRow({
  group,
  memoryKey,
  colorClass,
  action,
}: {
  group: ProcessGroup;
  memoryKey: string;
  colorClass: string | null;
  action?: React.ReactNode;
}): React.JSX.Element {
  const expandable = group.processes.length > 1;
  const [open, setOpen] = useThreadFlag(memoryKey, false);
  const detail = groupDetail(group);
  const title = [
    ...(group.monitor === null ? [] : [monitorTitle(group.monitor)]),
    ...group.processes.map((process) =>
      processTitle(process, group.detached, group.monitor !== null),
    ),
  ].join('\n\n');
  const badge =
    group.monitor !== null ? 'monitor' : group.detached ? 'detached' : null;
  // A command gets the whole first line for itself — it is the most telling
  // text in the section and the longest — and states how long it has run, and
  // whether it outlived its shell, on a second line under it.
  const isCommand = group.role === 'command';
  const line = (
    <>
      <span className="flex w-full items-center gap-1.5">
        <span className="flex min-w-0 flex-1 items-center gap-1.5">
          {expandable ? (
            <ChevronRight
              aria-hidden="true"
              className={cn(
                'size-3 shrink-0 text-muted-foreground transition-transform',
                open && 'rotate-90',
              )}
            />
          ) : (
            <span aria-hidden="true" className="size-3 shrink-0" />
          )}
          {colorClass === null ? null : <ShareDot colorClass={colorClass} />}
          {/* The NAME is what a reader scans for, so it is the last thing to
              give up width: everything after it shrinks first. */}
          <span
            className={cn(
              'min-w-[2.5rem] truncate',
              isCommand ? 'font-mono text-[11px]' : '',
              group.role === 'cli'
                ? 'font-medium text-foreground'
                : 'text-foreground',
            )}>
            {group.label}
          </span>
          {group.size > 1 ? (
            <span
              data-slot="process-count"
              title={`${group.size} processes`}
              className="shrink-0 rounded-full bg-muted px-1.5 text-[10px] text-muted-foreground tabular-nums">
              {group.size}
            </span>
          ) : null}
          {detail !== null && !isCommand ? (
            <span className="min-w-0 shrink-[4] truncate text-[11px] text-muted-foreground tabular-nums">
              {detail}
            </span>
          ) : null}
        </span>
        <ProcessFigureCells
          cpuPercent={group.cpuPercent}
          rssBytes={group.rssBytes}
        />
      </span>
      {isCommand && (detail !== null || badge !== null) ? (
        <span
          data-slot="process-command-detail"
          className={cn(
            'flex items-center gap-1.5 text-[11px] text-muted-foreground tabular-nums',
            colorClass === null ? 'pl-[18px]' : 'pl-[32px]',
          )}>
          {detail === null ? null : (
            <span className="min-w-0 truncate">{detail}</span>
          )}
          {badge === null ? null : (
            <span className="shrink-0 rounded border border-border px-1 py-px text-[10px]">
              {badge}
            </span>
          )}
        </span>
      ) : null}
    </>
  );
  return (
    <li
      data-slot="process-group"
      data-role={group.role}
      className="flex flex-col">
      <div className="flex items-start gap-1">
        {expandable ? (
          <button
            type="button"
            aria-expanded={open}
            onClick={() => setOpen((value) => !value)}
            title={title}
            className="-mx-1 flex min-w-0 flex-1 flex-col gap-0.5 rounded-md px-1 py-1 text-left text-xs outline-none hover:bg-muted focus-visible:ring-2 focus-visible:ring-ring/50">
            {line}
          </button>
        ) : (
          <div
            title={title}
            className="-mx-1 flex min-w-0 flex-1 flex-col gap-0.5 px-1 py-1 text-xs">
            {line}
          </div>
        )}
        {action}
      </div>
      {expandable && open ? (
        <ul
          aria-label={`Processes of ${group.label}`}
          className="m-0 mb-1 ml-[5px] flex list-none flex-col gap-0.5 border-l border-border p-0 py-0.5 pl-3">
          {group.processes.map((process) => (
            <NestedProcess
              key={process.pid}
              process={process}
              baseDepth={group.processes[0]?.depth ?? 0}
              detached={group.detached}
              monitor={group.monitor !== null}
            />
          ))}
        </ul>
      ) : null}
    </li>
  );
}

/**
 * One agent's processes, as the groups a reader thinks in — the CLI, its
 * servers and tools, its commands — each a captioned section.
 */
function AgentGroups({
  tree,
  groups,
  colorOf,
  columns,
}: {
  tree: RunProcessTree;
  groups: readonly ProcessGroup[];
  /** The dot each group wears, or null when the division is by AGENT. */
  colorOf: ((group: ProcessGroup) => string) | null;
  /** Whether the first caption names the CPU / memory columns. */
  columns: boolean;
}): React.JSX.Element {
  const roles = ROLE_ORDER.filter((role) =>
    groups.some((group) => group.role === role),
  );
  return (
    <div className="flex flex-col gap-1.5">
      {roles.map((role, index) => {
        const ofRole = groups.filter((group) => group.role === role);
        return (
          <section key={role} aria-label={ROLE_CAPTION[role]}>
            <ProcessFigureHeader
              className="mb-0.5"
              columns={columns && index === 0}
              label={
                <>
                  {ROLE_CAPTION[role]}
                  {role === 'cli' ? null : (
                    <span className="ml-1 tabular-nums">{ofRole.length}</span>
                  )}
                </>
              }
            />
            <ul className="m-0 flex list-none flex-col p-0">
              {ofRole.map((group) => (
                <GroupRow
                  key={group.key}
                  group={group}
                  memoryKey={`processes:${tree.sessionKey}:${group.key}`}
                  colorClass={colorOf === null ? null : colorOf(group)}
                />
              ))}
            </ul>
          </section>
        );
      })}
    </div>
  );
}

/** One agent among several — its own block, folded on its header. */
function AgentBlock({
  tree,
  colorClass,
}: {
  tree: RunProcessTree;
  colorClass: string;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  const agentName =
    tree.agentKind === null
      ? 'agent'
      : agentShortName(identities, tree.agentKind);
  const label = treeLabel(tree, agentName);
  const [open, setOpen] = useThreadFlag(`processes:${tree.sessionKey}`, true);
  return (
    <li className="flex flex-col gap-1.5">
      <button
        type="button"
        aria-expanded={open}
        onClick={() => setOpen((value) => !value)}
        title={tree.cwd}
        className="-mx-1 flex items-center gap-1.5 rounded-md px-1 py-1 text-xs outline-none hover:bg-muted focus-visible:ring-2 focus-visible:ring-ring/50">
        <span className="flex min-w-0 flex-1 items-center gap-1.5">
          <ChevronRight
            aria-hidden="true"
            className={cn(
              'size-3 shrink-0 text-muted-foreground transition-transform',
              open && 'rotate-90',
            )}
          />
          <ShareDot colorClass={colorClass} />
          <AgentGlyph
            icon={agentIconName(identities, tree.agentKind ?? '')}
            className="size-3.5 shrink-0 text-muted-foreground"
          />
          <span className="min-w-0 truncate font-medium text-foreground">
            {label}
          </span>
          {label !== agentName ? (
            <span className="shrink-0 text-muted-foreground">{agentName}</span>
          ) : null}
        </span>
        <ProcessFigureCells
          cpuPercent={tree.cpuPercent}
          rssBytes={tree.rssBytes}
          strong
        />
      </button>
      {open ? (
        <div className="ml-[5px] border-l border-border pl-3">
          <AgentGroups
            tree={tree}
            groups={groupProcesses(tree)}
            colorOf={null}
            columns={false}
          />
        </div>
      ) : null}
    </li>
  );
}

/**
 * What the thread's agents left running with no CLI of theirs above it — the
 * same set archiving the thread stops, so nothing it will end is hidden here —
 * and the monitors they started, each one row.
 */
function DetachedSection({
  groups,
  colorOf,
  columns,
  onStop,
}: {
  groups: readonly ProcessGroup[];
  colorOf: (group: ProcessGroup) => string;
  /** Whether the caption names the CPU / memory columns. */
  columns: boolean;
  onStop?: (groups: readonly ProcessGroup[], all: boolean) => void;
}): React.JSX.Element {
  return (
    <section data-slot="processes-detached" aria-label="Detached">
      <ProcessFigureHeader
        className="mb-0.5"
        columns={columns}
        label={
          <span
            className="flex items-center gap-1"
            title="Started by this thread’s agents and left running — no agent CLI holds them. Stop them here, or archive or delete the thread.">
            Detached
            <span className="ml-1 tabular-nums">{groups.length}</span>
            {onStop === undefined ? null : (
              <Button
                type="button"
                variant="ghost"
                size="sm"
                className="h-6 px-1.5 text-[11px]"
                onClick={() => onStop(groups, true)}>
                Stop all
              </Button>
            )}
          </span>
        }
      />
      <ul className="m-0 flex list-none flex-col p-0">
        {groups.map((group) => (
          <GroupRow
            key={group.key}
            group={group}
            memoryKey={`processes:${group.key}`}
            colorClass={colorOf(group)}
            action={
              onStop === undefined ? undefined : (
                <Button
                  type="button"
                  variant="ghost"
                  size="sm"
                  className="h-6 px-1.5 text-[11px]"
                  aria-label={`Stop ${group.monitor?.description ?? group.label}`}
                  onClick={() => onStop([group], false)}>
                  Stop
                </Button>
              )
            }
          />
        ))}
      </ul>
    </section>
  );
}

function stopTitle(all: boolean, processes: number, monitors: number): string {
  if (!all) {
    return monitors > 0 ? 'Stop this monitor?' : 'Stop this process group?';
  }
  if (monitors === 0) {
    return 'Stop all detached processes?';
  }
  return processes === 0
    ? 'Stop all monitors?'
    : 'Stop all detached processes and monitors?';
}

/**
 * Every process this thread has running — each agent CLI geniro started for
 * it, and what that CLI runs: its servers and tools, and the commands it
 * started; then what its agents left running detached — with CPU and resident
 * memory, and ONE bar showing how the thread's memory divides between them.
 *
 * A LIVE reading, not a history: a process that has ended is simply gone from
 * the next poll.
 */
export function RunProcesses({
  data,
  loading,
  error,
  onStopDetached,
}: {
  data: RunProcessesDto | null;
  loading: boolean;
  error: string | null;
  /** Stops these detached pids and these monitors, by the id the agent knows them by. */
  onStopDetached?: (pids: number[], monitorIds: string[]) => Promise<void>;
}): React.JSX.Element | null {
  const identities = useContext(AgentIdentityContext);
  const [selection, setSelection] = useState<{
    groups: readonly ProcessGroup[];
    all: boolean;
  } | null>(null);
  const [stopping, setStopping] = useState(false);
  const [stopError, setStopError] = useState<string | null>(null);
  const confirmStop = async (): Promise<void> => {
    if (selection === null || onStopDetached === undefined || stopping) {
      return;
    }
    setStopping(true);
    setStopError(null);
    try {
      await onStopDetached(
        selection.groups.flatMap((group) =>
          group.monitor === null
            ? group.processes.map((process) => process.pid)
            : [],
        ),
        selection.groups.flatMap((group) =>
          group.monitor === null ? [] : [group.monitor.id],
        ),
      );
      setSelection(null);
    } catch (err: unknown) {
      setStopError(describeDaemonError(err));
    } finally {
      setStopping(false);
    }
  };
  const picked = selection?.groups ?? [];
  const monitors = picked.filter((group) => group.monitor !== null);
  const plain = picked.filter((group) => group.monitor === null);
  if (data === null) {
    if (error !== null) {
      return <p className="text-xs text-muted-foreground">{error}</p>;
    }
    return loading ? (
      <p className="text-xs text-muted-foreground">reading processes…</p>
    ) : null;
  }
  if (
    data.trees.length === 0 &&
    data.detached.length === 0 &&
    data.monitors.length === 0
  ) {
    return (
      <div className="flex flex-col gap-1">
        <p className="text-xs text-muted-foreground">
          {data.unavailableReason ??
            'no agent process is running for this thread'}
        </p>
        {error === null ? null : (
          <p className="text-[11px] text-muted-foreground">{error}</p>
        )}
      </div>
    );
  }

  const several = data.trees.length > 1;
  const single =
    data.trees.length === 1 ? (data.trees[0] as RunProcessTree) : null;
  const singleGroups = single === null ? [] : groupProcesses(single);
  // A monitor stands in the detached section with what was left running: the
  // agent started it, and no agent CLI holds it.
  const detachedGroups = [
    ...groupDetached(data.detached),
    ...groupMonitors(data.monitors, data.sampledAt),
  ];
  // One colour per part of the division, in the order the bar draws them:
  // the agents (or the one agent's groups), then what was left detached.
  const leading: ShareSegment[] = several
    ? data.trees.map((tree, index) => ({
        key: tree.sessionKey,
        label: treeLabel(
          tree,
          tree.agentKind === null
            ? 'agent'
            : agentShortName(identities, tree.agentKind),
        ),
        value: tree.rssBytes,
        colorClass: segmentColorClass(index),
      }))
    : singleGroups.map((group, index) => ({
        key: group.key,
        label: group.label,
        value: group.rssBytes,
        colorClass: segmentColorClass(index),
      }));
  const groupColor = new Map(
    [...singleGroups, ...detachedGroups].map((group, index) => [
      group.key,
      segmentColorClass(several ? data.trees.length + index : index),
    ]),
  );
  const segments: ShareSegment[] = [
    ...leading,
    ...detachedGroups.map((group) => ({
      key: group.key,
      label: group.label,
      value: group.rssBytes,
      colorClass: groupColor.get(group.key) ?? '',
    })),
  ];
  const colorOf = (group: ProcessGroup): string =>
    groupColor.get(group.key) ?? '';

  return (
    <div className="flex flex-col gap-2">
      <div
        data-slot="processes-summary"
        className="flex items-baseline gap-1.5 text-xs">
        <span className="min-w-0 flex-1 truncate text-muted-foreground">
          {data.processes} process{data.processes === 1 ? '' : 'es'}
          {several ? ` · ${data.trees.length} agents` : ''}
          {data.detached.length > 0
            ? ` · ${data.detached.length} detached`
            : ''}
          {data.monitors.length > 0
            ? ` · ${data.monitors.length} monitor${data.monitors.length === 1 ? '' : 's'}`
            : ''}
        </span>
        <span className="shrink-0 text-muted-foreground tabular-nums">
          {formatCpu(data.cpuPercent)} CPU
        </span>
        <span className="shrink-0 font-medium text-foreground tabular-nums">
          {formatMemory(data.rssBytes)}
        </span>
      </div>
      <ShareStack
        segments={segments}
        label={several ? 'Memory by agent' : 'Memory by process group'}
      />
      {several ? <ProcessFigureHeader label="agents" className="mt-1" /> : null}
      {several ? (
        <ul className="m-0 flex list-none flex-col gap-2 p-0">
          {data.trees.map((tree, index) => (
            <AgentBlock
              key={tree.sessionKey}
              tree={tree}
              colorClass={segmentColorClass(index)}
            />
          ))}
        </ul>
      ) : single !== null ? (
        <AgentGroups
          tree={single}
          groups={singleGroups}
          colorOf={colorOf}
          columns
        />
      ) : null}
      {detachedGroups.length > 0 ? (
        <DetachedSection
          groups={detachedGroups}
          colorOf={colorOf}
          columns={data.trees.length === 0}
          onStop={
            onStopDetached === undefined
              ? undefined
              : (groups, all) => {
                  setStopError(null);
                  setSelection({ groups, all });
                }
          }
        />
      ) : null}
      {error === null ? null : (
        <p className="text-[11px] text-muted-foreground">{error}</p>
      )}
      <ConfirmDialog
        open={selection !== null}
        busy={stopping}
        error={stopError}
        title={stopTitle(
          selection?.all ?? false,
          plain.length,
          monitors.length,
        )}
        confirmLabel={
          selection?.all
            ? 'Stop all'
            : monitors.length > 0
              ? 'Stop monitor'
              : 'Stop group'
        }
        busyLabel="Stopping…"
        onCancel={() => setSelection(null)}
        onConfirm={() => void confirmStop()}>
        {plain.length > 0 ? (
          <p>
            This stops{' '}
            {plain.reduce((sum, group) => sum + group.processes.length, 0)}{' '}
            detached processes. Any dev server or preview they serve will become
            unavailable. You can ask the agent to start them again.
          </p>
        ) : null}
        {monitors.length === 1 ? (
          <p>This stops the monitor. The agent will be told it was stopped.</p>
        ) : monitors.length > 1 ? (
          <p>
            This stops {monitors.length} monitors. The agent will be told they
            were stopped.
          </p>
        ) : null}
        <ul className="mt-2 list-disc pl-4">
          {selection?.groups.map((group) => (
            <li key={group.key} className="break-all font-mono text-xs">
              {group.label}
            </li>
          ))}
        </ul>
      </ConfirmDialog>
    </div>
  );
}
