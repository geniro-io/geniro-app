import { describe, expect, it } from 'vitest';

import type { OpenShell, RunDelegateState } from '../autogenerated';
import type { AgentThread } from './agent-activity';
import { withDurableDelegates, withDurableShells } from './run-state-readouts';
import type { ShellRun } from './shell-activity';

const delegate = (
  id: string,
  extra: Partial<RunDelegateState> = {},
): RunDelegateState => ({
  id,
  nodeId: null,
  callId: null,
  label: null,
  kind: null,
  status: 'running',
  launchSeq: 1,
  startedAt: '2026-10-01T00:00:00.000Z',
  ...extra,
});

const thread = (id: string): AgentThread => ({
  id,
  kind: 'subagent',
  label: id,
  status: 'completed',
  sessionId: null,
  callId: null,
});

describe('withDurableDelegates', () => {
  it('adds the daemon’s delegates the window holds no block for, ahead of the window’s', () => {
    const merged = withDurableDelegates(
      new Map([['chat', [thread('toolu_seen')]]]),
      [delegate('toolu_seen'), delegate('toolu_early', { label: 'Reviewer' })],
      'chat',
    );
    expect(merged.get('chat')!.map((t) => [t.id, t.label])).toEqual([
      ['toolu_early', 'Reviewer'],
      ['toolu_seen', 'toolu_seen'],
    ]);
  });

  it('names an unnamed delegate by its identity, and files it under its node', () => {
    const merged = withDurableDelegates(
      new Map(),
      [delegate('toolu_01AD1kjdJCqfkzGRTjn5M6mo', { nodeId: 'qa' })],
      'chat',
    );
    expect(merged.get('qa')![0]!.label).toBe('Sub-agent n5M6mo');
  });
});

describe('withDurableShells', () => {
  const open = (id: string, nodeId: string | null): OpenShell => ({
    id,
    command: `cmd ${id}`,
    nodeId,
    callId: 'call-3',
    startedAt: 0,
  });

  it('adds what the daemon says is still running and the window knows nothing of', () => {
    const merged = withDurableShells(new Map(), [], [open('s1', 'engineer')]);
    expect(merged.get('engineer')).toMatchObject([
      { id: 's1', background: true, status: 'running', callId: 'call-3' },
    ]);
  });

  it('never brings back a command the window saw end', () => {
    const finished = { id: 's1' } as ShellRun;
    const merged = withDurableShells(
      new Map(),
      [finished],
      [open('s1', 'engineer')],
    );
    expect(merged.get('engineer')).toBeUndefined();
  });
});
