import { describe, expect, it } from 'vitest';

import type {
  ItemDto,
  OpenShell,
  RunCallState,
  RunDelegateState,
} from '../autogenerated';
import type { AgentThread } from './agent-activity';
import {
  callEndedPerDaemon,
  withDurableDelegates,
  withDurableShells,
  withoutDaemonEndedShells,
} from './run-state-readouts';
import type { ShellRun } from './shell-activity';

const delegate = (
  id: string,
  extra: Partial<RunDelegateState> = {},
): RunDelegateState => ({
  id,
  nodeId: null,
  callId: null,
  label: null,
  kind: null,
  status: 'running',
  processEnded: false,
  launchSeq: 1,
  toolCalls: 0,
  startedAt: '2026-10-01T00:00:00.000Z',
  ...extra,
});

const thread = (id: string): AgentThread => ({
  id,
  kind: 'subagent',
  label: id,
  status: 'completed',
  sessionId: null,
  callId: null,
});

describe('withDurableDelegates', () => {
  it('carries the daemon’s word that a delegate’s process ended onto its thread', () => {
    const merged = withDurableDelegates(
      new Map(),
      [
        delegate('ended', { status: 'untracked', processEnded: true }),
        delegate('lost', { status: 'untracked' }),
      ],
      'chat',
    );
    expect(
      merged.get('chat')!.map((t) => [t.id, t.processEnded ?? false]),
    ).toEqual([
      ['ended', true],
      ['lost', false],
    ]);
  });

  it('adds the daemon’s delegates the window holds no block for, ahead of the window’s', () => {
    const merged = withDurableDelegates(
      new Map([['chat', [thread('toolu_seen')]]]),
      [delegate('toolu_seen'), delegate('toolu_early', { label: 'Reviewer' })],
      'chat',
    );
    expect(merged.get('chat')!.map((t) => [t.id, t.label])).toEqual([
      ['toolu_early', 'Reviewer'],
      ['toolu_seen', 'toolu_seen'],
    ]);
  });

  it('names an unnamed delegate by its identity, and files it under its node', () => {
    const merged = withDurableDelegates(
      new Map(),
      [delegate('toolu_01AD1kjdJCqfkzGRTjn5M6mo', { nodeId: 'qa' })],
      'chat',
    );
    expect(merged.get('qa')![0]!.label).toBe('Sub-agent n5M6mo');
  });
});

describe('withDurableShells', () => {
  const open = (id: string, nodeId: string | null): OpenShell => ({
    id,
    command: `cmd ${id}`,
    nodeId,
    callId: 'call-3',
    startedAt: 0,
  });

  it('adds what the daemon says is still running and the window knows nothing of', () => {
    const merged = withDurableShells(new Map(), [], [open('s1', 'engineer')]);
    expect(merged.get('engineer')).toMatchObject([
      { id: 's1', background: true, status: 'running', callId: 'call-3' },
    ]);
  });

  it('never brings back a command the window saw end', () => {
    const finished = { id: 's1' } as ShellRun;
    const merged = withDurableShells(
      new Map(),
      [finished],
      [open('s1', 'engineer')],
    );
    expect(merged.get('engineer')).toBeUndefined();
  });
});

describe('withoutDaemonEndedShells', () => {
  const shell = (
    id: string,
    launchSeq: number | null,
    detached: { trackedSeq: number | null } | null = null,
  ): ShellRun => ({
    id,
    command: id,
    description: null,
    background: detached !== null,
    handle: null,
    status: 'running',
    exitCode: null,
    startedAt: '2026-10-01T00:00:00.000Z',
    launchSeq,
    trackedSeq: detached?.trackedSeq ?? null,
    agentId: null,
    callId: null,
  });
  const call = (id: string): ItemDto => ({
    id: `row-${id}`,
    runId: 'r1',
    nodeId: null,
    seq: 1,
    kind: 'tool_call',
    role: null,
    payload: { id },
    createdAt: 'now',
  });
  const open = (id: string): OpenShell => ({
    id,
    command: 'x',
    nodeId: null,
    callId: null,
    startedAt: 0,
  });

  it("drops a foreground command the read covers that is no open turn's unanswered call", () => {
    const kept = withoutDaemonEndedShells(
      [
        shell('ended', 10),
        shell('foreground', 10),
        shell('newer', 60),
        shell('daemon-only', null),
      ],
      {
        throughSeq: 50,
        shells: [],
        openToolCalls: [call('foreground')],
      },
    );
    expect(kept.map((s) => s.id)).toEqual([
      'foreground',
      'newer',
      'daemon-only',
    ]);
  });

  it('drops a detached command once a read covering its shell_open no longer lists it — and leaves one the daemon never bracketed to the page', () => {
    const kept = withoutDaemonEndedShells(
      [
        shell('closed', 10, { trackedSeq: 20 }),
        shell('still-out', 10, { trackedSeq: 20 }),
        // Launched before the read, bracketed after it.
        shell('bracketed-later', 10, { trackedSeq: 60 }),
        shell('never-bracketed', 10, { trackedSeq: null }),
      ],
      { throughSeq: 50, shells: [open('still-out')], openToolCalls: [] },
    );
    expect(kept.map((s) => s.id)).toEqual([
      'still-out',
      'bracketed-later',
      'never-bracketed',
    ]);
  });

  it('keeps a finished command, which says how it ended', () => {
    const done = { ...shell('done', 10), status: 'completed' as const };
    expect(
      withoutDaemonEndedShells([done], {
        throughSeq: 50,
        shells: [],
        openToolCalls: [],
      }),
    ).toEqual([done]);
  });
});

describe('callEndedPerDaemon', () => {
  const state = (status: RunCallState['status'], startSeq: number) =>
    new Map([
      [
        'call-1',
        {
          callId: 'call-1',
          callerNodeId: 'manager',
          calleeNodeId: 'engineer',
          title: null,
          brief: null,
          mode: null,
          thread: null,
          startSeq,
          startedAt: 'now',
          endedAt: null,
          status,
          queued: false,
          member: null,
        },
      ],
    ]);

  it('says how a call the read covers ended, and nothing for one still out, begun after it, or unknown', () => {
    expect(
      callEndedPerDaemon(state('failed', 10), { throughSeq: 50 }, 'call-1'),
    ).toBe('failed');
    expect(
      callEndedPerDaemon(state('running', 10), { throughSeq: 50 }, 'call-1'),
    ).toBeNull();
    expect(
      callEndedPerDaemon(state('completed', 60), { throughSeq: 50 }, 'call-1'),
    ).toBeNull();
    expect(
      callEndedPerDaemon(state('completed', 10), { throughSeq: 50 }, 'call-9'),
    ).toBeNull();
  });
});
