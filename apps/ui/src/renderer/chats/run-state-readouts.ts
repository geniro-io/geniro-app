import type {
  OpenShell,
  RunCallState,
  RunDelegateState,
  RunStateDto,
  RunWorkStatus,
} from '../autogenerated';
import type { AgentThread } from './agent-activity';
import type { ShellRun } from './shell-activity';
import { subagentRef } from './subagent-payload';

/**
 * The readouts' half of the run-state merge (`use-run-state.ts`): what the
 * window's own fold found, with everything the daemon holds that the window
 * does not added beside it. The window supplies what the daemon's summary has
 * no notion of (a delegate's conversation, a command's exit code); the daemon
 * decides what has ENDED.
 *
 * A window is a page of the run, so it can hold a thing's start without its
 * end — after a jump, or on an older page of a card — and its fold then reads
 * a finished command, delegate or call as running for good. The daemon's read
 * covers the whole run up to `throughSeq`: anything that began at or before it
 * and that the read says is over, is over, whatever the page says. A thing
 * begun after the read is the page's alone until the next read.
 */

/**
 * The Agents chip's id for a call whose card the window does not draw — a
 * press on it jumps to the call's own start row instead of revealing a card.
 */
export const OFF_WINDOW_CALL_PREFIX = 'off-window-call:';

/**
 * Each agent's sub-agent threads, with every delegate the run launched that the
 * window holds no block for added FIRST — those were launched before the
 * loaded page, so they come earlier in the conversation.
 */
export function withDurableDelegates(
  byAgent: ReadonlyMap<string, AgentThread[]>,
  delegates: readonly RunDelegateState[],
  chatAgentKey: string,
): Map<string, AgentThread[]> {
  const held = new Set([...byAgent.values()].flat().map((thread) => thread.id));
  const added = new Map<string, AgentThread[]>();
  for (const delegate of delegates) {
    if (held.has(delegate.id)) {
      continue;
    }
    const key = delegate.nodeId ?? chatAgentKey;
    const threads = added.get(key) ?? [];
    threads.push({
      id: delegate.id,
      kind: 'subagent',
      // `subagentTitle`'s reading, from what the daemon could read off the
      // launch — the delegate's own block is not in the window to ask.
      label:
        delegate.label ??
        delegate.kind ??
        `Sub-agent ${subagentRef(delegate.id)}`,
      status: delegate.status,
      sessionId: null,
      callId: delegate.callId,
    });
    added.set(key, threads);
  }
  if (added.size === 0) {
    return new Map(byAgent);
  }
  const merged = new Map<string, AgentThread[]>();
  for (const key of new Set([...added.keys(), ...byAgent.keys()])) {
    merged.set(key, [...(added.get(key) ?? []), ...(byAgent.get(key) ?? [])]);
  }
  return merged;
}

/**
 * Each agent's running commands, with every command the daemon says is still
 * running that the window knows nothing of — finished ones included, since a
 * command that ended in the window must not come back from an older read.
 */
export function withDurableShells(
  byAgent: ReadonlyMap<string | null, ShellRun[]>,
  windowShells: readonly ShellRun[],
  running: readonly OpenShell[],
): Map<string | null, ShellRun[]> {
  const known = new Set(windowShells.map((shell) => shell.id));
  const merged = new Map<string | null, ShellRun[]>();
  // Oldest first, like the transcript: a command the window has not loaded was
  // started before everything it holds.
  for (const shell of running) {
    if (known.has(shell.id)) {
      continue;
    }
    const list = merged.get(shell.nodeId) ?? [];
    list.push({
      id: shell.id,
      command: shell.command,
      description: null,
      // Detached by construction: a command still open whose transcript the
      // window does not hold is one the daemon bracketed (`shell_open`).
      background: true,
      handle: null,
      status: 'running',
      exitCode: null,
      startedAt: new Date(shell.startedAt).toISOString(),
      launchSeq: null,
      trackedSeq: null,
      agentId: shell.nodeId,
      callId: shell.callId,
    });
    merged.set(shell.nodeId, list);
  }
  for (const [key, shells] of byAgent) {
    merged.set(key, [...(merged.get(key) ?? []), ...shells]);
  }
  return merged;
}

/**
 * How the daemon says a thing that began at `startSeq` ended, or null while it
 * runs or began after the read — the one test every readout below applies.
 */
function endedPerDaemon(
  state: Pick<RunStateDto, 'throughSeq'>,
  startSeq: number,
  status: RunWorkStatus,
): RunWorkStatus | null {
  return status !== 'running' && startSeq <= state.throughSeq ? status : null;
}

/**
 * The window's sub-agent threads with the daemon's ending laid over each it
 * still reads as running — see the doc block above.
 */
export function withDaemonDelegateEndings(
  byAgent: ReadonlyMap<string, AgentThread[]>,
  state: Pick<RunStateDto, 'throughSeq' | 'delegates'>,
): Map<string, AgentThread[]> {
  const delegates = new Map(
    state.delegates.map((delegate) => [delegate.id, delegate] as const),
  );
  const out = new Map<string, AgentThread[]>();
  for (const [key, threads] of byAgent) {
    out.set(
      key,
      threads.map((thread) => {
        const delegate = delegates.get(thread.id);
        const ended =
          thread.status === 'running' && delegate !== undefined
            ? endedPerDaemon(state, delegate.launchSeq, delegate.status)
            : null;
        return ended === null ? thread : { ...thread, status: ended };
      }),
    );
  }
  return out;
}

/**
 * The window's commands without those the daemon says are no longer running.
 * A detached command the daemon brackets (`shell_open`) has ended once a read
 * that covers its `shell_open` no longer lists it (`shells`); a foreground one
 * once a read that covers its launch has it neither detached nor among the open
 * turns' unanswered calls (`openToolCalls`). A detached command the daemon
 * never bracketed is the page's alone to end.
 */
export function withoutDaemonEndedShells(
  shells: readonly ShellRun[],
  state: Pick<RunStateDto, 'throughSeq' | 'shells' | 'openToolCalls'>,
): ShellRun[] {
  const running = new Set([
    ...state.shells.map((shell) => shell.id),
    ...state.openToolCalls
      .map((row) => (row.payload as { id?: unknown } | null)?.id)
      .filter((id): id is string => typeof id === 'string'),
  ]);
  const detached = new Set(state.shells.map((shell) => shell.id));
  return shells.filter((shell) => {
    if (shell.status !== 'running') {
      return true;
    }
    if (shell.background) {
      return (
        shell.trackedSeq === null ||
        shell.trackedSeq > state.throughSeq ||
        detached.has(shell.id)
      );
    }
    return (
      shell.launchSeq === null ||
      shell.launchSeq > state.throughSeq ||
      running.has(shell.id)
    );
  });
}

/**
 * How the daemon says a call ended, for a call the read covers that is no
 * longer out; null while it is, or when the read does not know it yet.
 */
export function callEndedPerDaemon(
  calls: ReadonlyMap<string, RunCallState>,
  state: Pick<RunStateDto, 'throughSeq'>,
  callId: string,
): RunWorkStatus | null {
  const call = calls.get(callId);
  return call === undefined
    ? null
    : endedPerDaemon(state, call.startSeq, call.status);
}
