import type { OpenShell, RunDelegateState } from '../autogenerated';
import type { AgentThread } from './agent-activity';
import type { ShellRun } from './shell-activity';
import { subagentRef } from './subagent-payload';

/**
 * The readouts' half of the run-state merge (`use-run-state.ts`): what the
 * window's own fold found, with everything the daemon holds that the window
 * does not added beside it. The window's reading WINS wherever both hold a
 * thing — it carries what the daemon's summary has no notion of (a delegate's
 * conversation, a command's exit code) — so the daemon's rows only ever ADD.
 */

/**
 * The Agents chip's id for a call whose card the window does not draw — a
 * press on it jumps to the call's own start row instead of revealing a card.
 */
export const OFF_WINDOW_CALL_PREFIX = 'off-window-call:';

/**
 * Each agent's sub-agent threads, with every delegate the run launched that the
 * window holds no block for added FIRST — those were launched before the
 * loaded page, so they come earlier in the conversation.
 */
export function withDurableDelegates(
  byAgent: ReadonlyMap<string, AgentThread[]>,
  delegates: readonly RunDelegateState[],
  chatAgentKey: string,
): Map<string, AgentThread[]> {
  const held = new Set([...byAgent.values()].flat().map((thread) => thread.id));
  const added = new Map<string, AgentThread[]>();
  for (const delegate of delegates) {
    if (held.has(delegate.id)) {
      continue;
    }
    const key = delegate.nodeId ?? chatAgentKey;
    const threads = added.get(key) ?? [];
    threads.push({
      id: delegate.id,
      kind: 'subagent',
      // `subagentTitle`'s reading, from what the daemon could read off the
      // launch — the delegate's own block is not in the window to ask.
      label:
        delegate.label ??
        delegate.kind ??
        `Sub-agent ${subagentRef(delegate.id)}`,
      status: delegate.status,
      sessionId: null,
      callId: delegate.callId,
    });
    added.set(key, threads);
  }
  if (added.size === 0) {
    return new Map(byAgent);
  }
  const merged = new Map<string, AgentThread[]>();
  for (const key of new Set([...added.keys(), ...byAgent.keys()])) {
    merged.set(key, [...(added.get(key) ?? []), ...(byAgent.get(key) ?? [])]);
  }
  return merged;
}

/**
 * Each agent's running commands, with every command the daemon says is still
 * running that the window knows nothing of — finished ones included, since a
 * command that ended in the window must not come back from an older read.
 */
export function withDurableShells(
  byAgent: ReadonlyMap<string | null, ShellRun[]>,
  windowShells: readonly ShellRun[],
  running: readonly OpenShell[],
): Map<string | null, ShellRun[]> {
  const known = new Set(windowShells.map((shell) => shell.id));
  const merged = new Map<string | null, ShellRun[]>();
  // Oldest first, like the transcript: a command the window has not loaded was
  // started before everything it holds.
  for (const shell of running) {
    if (known.has(shell.id)) {
      continue;
    }
    const list = merged.get(shell.nodeId) ?? [];
    list.push({
      id: shell.id,
      command: shell.command,
      description: null,
      // Detached by construction: a command still open whose transcript the
      // window does not hold is one the daemon bracketed (`shell_open`).
      background: true,
      handle: null,
      status: 'running',
      exitCode: null,
      startedAt: new Date(shell.startedAt).toISOString(),
      agentId: shell.nodeId,
      callId: shell.callId,
    });
    merged.set(shell.nodeId, list);
  }
  for (const [key, shells] of byAgent) {
    merged.set(key, [...(merged.get(key) ?? []), ...shells]);
  }
  return merged;
}
