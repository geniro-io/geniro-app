import type { RunDto } from '../autogenerated';
import type { RunStatusEvent } from '../daemon-client';

/**
 * The run-row fields one `run_status` announce sets, the same way wherever the
 * row is held: the chat screen's sidebar patch (`patchRow` in use-chat-run.ts)
 * and the workflow dock's copy of its run (`runRowPatch` in
 * use-workflow-chat.ts). Each used to carry its own reading of these rules, and
 * nothing checked that the two agreed.
 *
 * ABSENT asserts nothing, so an activity announce cannot lower a value it never
 * meant to touch: each field is set only when the event carries it. `status` is
 * the one whose `null` also means "nothing to say" — a count-only or
 * preview-only announce carries it, and the row keeps its status.
 *
 * The shell and sub-agent counts and the context reading are NOT here. The chat
 * screen applies those through handlers of their own, which skip a value that
 * did not move so the sidebar does not re-render per event; the dock applies its
 * copies beside this set in `runRowPatch`.
 */
export function runStatusRowFields(event: RunStatusEvent): Partial<RunDto> {
  const fields: Partial<RunDto> = {};
  if (event.status !== null) {
    fields.status = event.status;
  }
  // `awaiting` is three-state: absent asserts nothing, `null` clears. It is on
  // the row because the builder marks its chat toggle from it — a card raised
  // while the dock is hidden is otherwise a turn waiting on an answer nobody can
  // see is being asked.
  if (event.awaiting !== undefined) {
    fields.awaiting = event.awaiting;
  }
  // The row's copy too, not only the holding map: the queue's replay decision
  // (`queueMayDrainAfterReplay`) reads the row, and a copy frozen at the
  // load-time listing drained a queued message into a turn that had since
  // started, or held one back behind a hold that had since ended. A zero says
  // the hold is over, so it is written rather than skipped.
  if (event.holdingFor !== undefined) {
    fields.holdingFor = event.holdingFor;
  }
  // BOTH clocks: an announce carrying `at` wrote the row because the run did
  // something, which is exactly what `lastActivityAt` answers — and the sidebar
  // reads that one.
  if (event.at !== undefined) {
    fields.updatedAt = event.at;
    fields.lastActivityAt = event.at;
  }
  // Replaced wholesale, never merged: the daemon folds the whole transcript, so
  // the list it sends IS the current list. Merging it with what the row held
  // would put back the window-bound partial fold this field exists to replace.
  if (event.taskList !== undefined) {
    fields.taskList = event.taskList;
  }
  return fields;
}
