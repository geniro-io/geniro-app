/**
 * Everything a run or a node can be, display-wise: the run statuses, the
 * node-only `skipped`, and the three no daemon row ever carries —
 * `needs-input`, `held` and the sub-agent-only `unknown`. See
 * {@link displayRunStatus}.
 *
 * There is no `idle`. It was a NINTH member meaning "has not started yet",
 * which is what `pending` already means and what the daemon's own `node_state`
 * row literally says while it holds — so an agent card said `idle` for exactly
 * as long as no item had been written for that node and `pending` the moment
 * one was, for one unchanged fact.
 *
 * ONE vocabulary for the whole app. Anything drawn in a different one — a
 * transcript block's `done`/`error`/`stopped` lifecycle — is TRANSLATED into
 * these before it reaches a glyph or a word (`block-shell.tsx`), because a
 * screen that spells one state two ways is what "давай стандартизируем
 * статусы" was reported against: a cancelled turn's delegate wore a red
 * `error` pill three lines under a header reading `cancelled`.
 */
export type RunStatusKind =
  | 'pending'
  | 'running'
  | 'held'
  | 'needs-input'
  | 'completed'
  | 'failed'
  | 'cancelled'
  | 'skipped';

/**
 * The one status → icon/tone/label mapping, so a run's or agent's state reads
 * the same everywhere (sidebar rows, the transcript header, the agents panel):
 * running spins in the accent tone, terminal states are
 * success/destructive/muted.
 *
 * `label` exists because the call sites were printing the raw key, and
 * `needs-input` is a slug rather than a sentence.
 */
export const RUN_STATUS_META: Record<
  RunStatusKind,
  { icon: typeof Clock; className: string; label: string }
> = {
  pending: {
    icon: Clock,
    className: 'text-muted-foreground',
    label: 'pending',
  },
  running: { icon: Loader2, className: 'text-primary', label: 'running' },
  // Accent-toned like `running`, because that is what it IS — work is going on
  // and nobody is being waited for. What it must NOT do is spin: the state
  // routinely lasts twenty minutes (a background task with no end holds the
  // turn until the silence deadline), and a spinner running that long over an
  // answer the agent finished writing is the defect this state was carved out
  // of `running` to fix.
  //
  // The label says `working` rather than `waiting` for the same reason it is
  // no longer `idle`: the row already carries `· waiting on 6 background
  // tasks` beside it ({@link HELD_ACTIVITY}), so the badge's job is to say the
  // thread is not finished, and the phrase's is to say what it is on.
  //
  // The KIND is `held` rather than `waiting` for the other half of that: the
  // word `waiting` was doing three jobs at once — this key, the phrase under a
  // `needs-input` badge (`waiting for your answer`), and the sign-in flow's own
  // `CliLoginStatus`. `held` is the daemon's own name for the fact
  // (`turn_held` → `holdingFor`), so the key now names what produced it.
  held: { icon: Hourglass, className: 'text-primary', label: 'working' },
  // Warning-toned, not accent: it is the one state that will not advance on
  // its own, so it must read as "you are the blocker" rather than as another
  // shade of busy — and the icon is deliberately not a spinner, for the same
  // reason.
  'needs-input': {
    icon: MessageCircleQuestion,
    className: 'text-warning',
    label: 'needs more info',
  },
  completed: {
    icon: CircleCheck,
    className: 'text-success',
    label: 'completed',
  },
  failed: { icon: CircleX, className: 'text-destructive', label: 'failed' },
  cancelled: {
    icon: Ban,
    className: 'text-muted-foreground',
    label: 'cancelled',
  },
  skipped: {
    icon: MinusCircle,
    className: 'text-muted-foreground',
    label: 'skipped',
  },
};

/**
 * What a run's badge should SAY, as opposed to what its row happens to hold.
 *
 * Three independent writers touch `run.status` — the terminal-item handler, the
 * client-wide `run_status` broadcast, and the snapshot refetch — so a snapshot
 * taken mid-turn can land after a fresher event and re-assert a stale
 * `completed`. That is the reported flicker: a chat reading "completed" while
 * its agent is visibly still thinking. The row is not the authority on whether
 * work is in flight; the live plane is.
 *
 * The order is the contract:
 *
 * 1. An unanswered question outranks everything. The turn IS still open at the
 *    daemon, so every other signal says `running` — but nothing will move until
 *    a human answers, and calling that "running" is what left the user watching
 *    a spinner that was in fact waiting on them.
 * 2. Work in flight outranks a terminal row — a live turn (`streaming`) or a
 *    background sub-agent that has not reported back. `streaming` is cleared on
 *    activate and re-derived from the replayed transcript on reconnect, so it
 *    cannot go stale-true across a chat switch — which is what makes it safe to
 *    let it veto a `completed` that only a racing refetch asserted.
 * 3. Otherwise the row is right.
 *
 * Pure and exported, so the badge rule is testable without mounting a chat.
 */
export function displayRunStatus({
  status,
  streaming,
  awaitingAnswer,
  subagentRunning = false,
  heldForBackgroundWork = false,
  shellsRunning = false,
  subagentsOut = false,
}: {
  /** The status on the run row, as the daemon last reported it. */
  status: RunStatusKind;
  /** A turn's live plane is active for this run. */
  streaming: boolean;
  /** This run has an approval or question card still open. */
  awaitingAnswer: boolean;
  /**
   * At least one background sub-agent of this run is still working.
   *
   * Ranked with {@link streaming} rather than under it, because the two go out
   * of step in exactly the case this exists for: the daemon deliberately drops
   * a sub-agent's deltas from the live tail, so a delegating turn can have
   * nothing streaming while several delegates are mid-flight. The run then read
   * as its stale row — the reported "thread says completed while sub-agents are
   * visibly working".
   *
   * Defaulted, so the many call sites that know nothing about sub-agents (a
   * background row, a workflow node) are unaffected.
   */
  subagentRunning?: boolean;
  /**
   * At least one background COMMAND this run started is still running.
   *
   * REPORTED against a thread reading `completed` beside a header counting two
   * running shells, with the agent's own last words being "the orphan branch
   * and the PR-body patch both wait on that" — "there is something in
   * progress, but it shows completed status".
   *
   * It is a DISPLAY reading and deliberately not a hold on the turn. The turn
   * settling is correct and load-bearing: the agent has finished speaking, the
   * composer must accept the next message, and holding for a command that
   * never ends (`pnpm dev`, a tailed log) is the previous defect this codebase
   * carved shells out of `openWork` to fix — a thread that read `running ·
   * 20m 18s` over an answer written twenty minutes earlier. So the run stays
   * SETTLED underneath; only the word on the badge changes, and it names the
   * commands rather than claiming the agent is busy.
   *
   * Answers `held` for that reason — the vocabulary's existing "the agent has
   * said its piece and something it started is still out" — never `running`,
   * which would put a spinner over an agent that has stopped.
   *
   * Ranked BELOW `heldForBackgroundWork` (a delegate hold is the stronger fact
   * and already says `waiting on N sub-agents`) and below a live turn, which
   * is the agent genuinely working. Defaulted, so every call site that knows
   * nothing about shells — a background row, a workflow node — is unaffected.
   */
  shellsRunning?: boolean;
  /**
   * This run's turn is merely HELD: the agent has said its piece and stopped,
   * and the process is alive only until background work it launched reports
   * back (the daemon's `turn_held` → `holdingFor` on the run row).
   *
   * Ranked ABOVE every other live reading — see the ordering comment in the
   * body, which is where the reason lives.
   *
   * The reported "done but showing like it's working", and it is a different
   * defect from the one that phrase last named: the sentence under the badge
   * was fixed to say `waiting on 2 sub-agents`, and the BADGE went on
   * spinning `running` above it. A background task with no end — a dev server,
   * a tailed log — holds the turn until the 30-minute silence deadline, so the
   * screenshot that came back showed `running · 20m 18s` under an answer the
   * agent had finished writing twenty minutes earlier.
   *
   * It answers `held`, which was `idle` for one release and should not have
   * been. `idle` is the word the COMPOSER uses to the user ("the agent is idle,
   * waiting on its sub-agents"), where a whole sentence carries it; on a
   * badge the word stands alone, and it came straight back reported twice over
   * — `i still see it seems like it finished but not`, over a header reading
   * `idle · 1h` above a live Stop button and a `waiting on 1 sub-agent`
   * line. Neither status is SETTLED, so nothing downstream reads the run as
   * finished either way: what changed is that the badge no longer says the
   * opposite of what the row beneath it says.
   */
  heldForBackgroundWork?: boolean;
  /**
   * At least one sub-agent of this run is DECLARED still out while producing
   * nothing — the CLI said it was working in the background and has not said
   * another word about it.
   *
   * The same kind of fact as {@link shellsRunning} and ranked with it, which is
   * why it is a separate input from {@link subagentRunning} rather than more of
   * it: the agent has stopped speaking, so a spinner over the run would claim
   * work IT is doing, while `held` says exactly what is true — something it
   * started is still out. A delegate that is producing rows stays
   * `subagentRunning` and outranks this.
   *
   * Like `shellsRunning`, it is deliberately withheld from the reading the
   * turn-end notification and the unseen mark are fired on: the banner reports
   * the TURN ending, which a delegate running on does not undo. Without that
   * split a cursor fan-out — nine reviewers left out by design — would silence
   * the notification for the whole of the chat's remaining session.
   */
  subagentsOut?: boolean;
}): RunStatusKind {
  if (awaitingAnswer) {
    return 'needs-input';
  }
  // failed/cancelled are deliberately NOT overridden: both are settle paths
  // that can arrive while the live plane has yet to be torn down, and painting
  // a cancelled run as running would hide the very thing the user just asked
  // for. A still-running sub-agent does not earn an exception — a cancelled run
  // is precisely where a delegate's last rows are still landing. Nor does a
  // hold: a run that failed is not idle, it is failed.
  if (status === 'failed' || status === 'cancelled') {
    return status;
  }
  // Held: the agent has stopped and only its background work keeps the turn
  // open.
  //
  // It leads both of the readings below, and that ORDER is the fix for the
  // reported "I see the chat is idle, and the moment I click it that changes
  // to another status". `subagentRunning` is derived from the LOADED
  // transcript, so it is knowable for the focused run and never for any other
  // — a held run therefore read `running` in the header and `idle` in its own
  // sidebar row, and clicking it swapped one for the other in front of the
  // user. Deciding the hold first makes the two readings identical, because a
  // hold is a fact the run row carries about every run alike.
  //
  // Nothing is lost by ranking a live delegate under it: the case that rule
  // was written for — a delegating turn with nothing streaming, reading as its
  // stale `completed` row — is a turn that is NOT held, so it still falls
  // through to `subagentRunning` below.
  if (heldForBackgroundWork) {
    return 'held';
  }
  // A delegate still producing rows is WORK, whatever the run row says.
  if (subagentRunning) {
    return 'running';
  }
  if (streaming) {
    return 'running';
  }
  // LAST of the live readings, and only over a run the daemon calls finished:
  // a command outliving its turn is the weakest evidence here, so anything the
  // agent is doing itself outranks it, and a run still `pending` has not
  // started. See the field for why this is a display reading rather than a
  // hold on the turn.
  // `completed` ALONE, spelled out rather than asked of `isSettledRunStatus`:
  // failed and cancelled already returned above, and `skipped` is a workflow
  // node nothing ever ran, which has no commands of its own to be waiting on.
  if ((shellsRunning || subagentsOut) && status === 'completed') {
    return 'held';
  }
  return status;
}

/**
 * The sentence under a `needs-input` badge: which kind of answer the run is
 * waiting for.
 *
 * Worded HERE rather than sent by the daemon, which is what keeps the two
 * surfaces from disagreeing. The daemon used to publish this as an activity
 * phrase, and the activity plane is events-only — so the phrase appeared while
 * the window was connected and vanished on a reload, when the badge itself
 * (which rides the run row) was still correct. The daemon owns the FACT (which
 * kind is open); the wording is presentation.
 */
export function awaitingPhrase(kind: RunAwaiting): string {
  return kind === 'question'
    ? 'waiting for your answer'
    : 'waiting for approval';
}

/**
 * What a RUNNING run is doing when the daemon has named nothing.
 *
 * A null activity does not mean "nothing is happening" — the daemon says so at
 * its own `idleActivity`, "null leaves the run's own Working… standing, which
 * is the honest phrase for an agent that is simply thinking". That was only
 * ever true of ONE of the two consumers: the transcript's live row carried this
 * fallback and the sidebar row carried none, so the sidebar ERASED the phrase
 * every time a tool returned and drew it again on the next call.
 *
 * REPORTED as "the fanin status on the thread keeps jumping around… now it
 * shows, now it's gone. Blinking… there should always be its last status
 * there". A turn is a run of tool calls, so that is a flicker per tool, and
 * it is entirely the missing fallback — the daemon was announcing exactly
 * what it meant.
 *
 * ONE constant, read by both surfaces, because that is the actual fix: the
 * blink was two renderings of one null disagreeing about what it meant, and a
 * second literal is how they would come to disagree again.
 */
export const STANDING_ACTIVITY = 'Working…';

/**
 * The same fallback for a run whose turn is HELD — see `heldForBackgroundWork`.
 *
 * A second constant rather than a reuse of {@link STANDING_ACTIVITY}, because
 * the two nulls do not mean the same thing. A running run with no named
 * activity is thinking; a held one is not doing anything at all, and its whole
 * state is what it is outstanding on. `Working…` there would also read as a
 * stutter under a badge that already says `working`.
 *
 * The daemon names the count while the window is connected (`waiting on 6
 * sub-agents`); this is what a window that reconnected mid-hold shows,
 * the activity plane being events-only.
 *
 * "background work" rather than "sub-agents", which it said until a SECOND
 * thing could hold a run: a detached command outliving its turn now reads
 * `held` too (see `shellsRunning`), and the daemon names no activity for that
 * case at all — so the sub-agent wording was the sentence a shell-held run
 * would always have shown, and it would have been false every time. The
 * daemon's own phrase still wins wherever it has one, so nothing that could
 * name the count stops naming it.
 */
export const HELD_ACTIVITY = 'waiting on background work';

/**
 * Something is working on this run RIGHT NOW, with nobody being waited for.
 *
 * The one predicate for "this thread is live", so the three places that ask —
 * the sidebar row's phrase, the same row's relative time, the header's elapsed
 * clock — cannot answer it differently. `needs-input` is deliberately not here:
 * that turn is open too, but it is open on the USER, which every call site
 * already handles separately.
 */
export function isWorkingRunStatus(status: RunStatusKind): boolean {
  return status === 'running' || status === 'held';
}

/**
 * This run has stopped for good — nothing further will arrive for it.
 *
 * Deliberately takes the status {@link displayRunStatus} produced rather than
 * the raw row, so "has it stopped" is answered by the same authority the badge
 * shows. Reading the row directly is how a transcript came to contradict its
 * own header.
 *
 * `pending` is NOT settled: it is a state a run has yet to leave, not one it
 * has finished in. Neither are `needs-input` and `held` — both
 * are open turns, one blocked on a human and the other on background work the
 * run itself launched.
 */
export function isSettledRunStatus(status: RunStatusKind): boolean {
  return (
    status === 'completed' ||
    status === 'failed' ||
    status === 'cancelled' ||
    status === 'skipped'
  );
}

/** The status glyph alone — spinning while running. */
export function RunStatusIcon({
  status,
  className,
}: {
  status: RunStatusKind;
  className?: string;
}): React.JSX.Element {
  const meta = RUN_STATUS_META[status];
  const Icon = meta.icon;
  return (
    <Icon
      aria-hidden="true"
      // The glyph and its tone ARE the status here — nothing beside a tool row
      // or a panel thread row spells it in words — so the status is also stated
      // in the DOM. Otherwise the only thing a test (or anyone inspecting the
      // page) can read it off is a lucide class name, which changes with the
      // icon rather than with the meaning.
      data-status={status}
      className={cn(
        'size-3 shrink-0',
        meta.className,
        status === 'running' && 'animate-spin',
        className,
      )}
    />
  );
}
