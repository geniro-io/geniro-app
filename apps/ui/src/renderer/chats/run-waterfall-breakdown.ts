import type { RunWaterfallDto, RunWaterfallTurn } from '../autogenerated';
import { cacheHitRate } from '../stats/stats-format';
import {
  type ClockWindow,
  endOf,
  overlapMs,
  turnContextFill,
} from './run-waterfall-geometry';

/**
 * The waterfall's table: the same run, folded by agent, by model or by tool,
 * over whatever stretch of the clock the view is showing.
 *
 * Pure, and kept out of the dialog, because every figure here is a claim about
 * money or time that the gantt beside it must agree with — and that agreement
 * is only checkable where it can be run without a DOM.
 *
 * Two rules decide what a zoomed-in table counts, and both look arbitrary
 * until they are broken:
 * - A turn is IN the window when it overlaps it, and its time is the part that
 *   overlaps. A turn that began before the window still worked inside it.
 * - A turn's MONEY is counted where the turn ENDED, because that is when a CLI
 *   prices it — the same rule the spend curve draws. Splitting a turn's price
 *   by the share of its time in the window would state a figure no CLI ever
 *   reported.
 */

export type BreakdownBy = 'agent' | 'model';

export interface BreakdownRow {
  key: string;
  /** The lane a row is about — set on agent rows only, for focus and colour. */
  nodeId?: string | null;
  turns: number;
  /** Time inside turns, clipped to the window. */
  workedMs: number;
  /** What its own turns cost; null when none of them priced anything. */
  costUsd: number | null;
  /**
   * Its own cost plus what the agents it CALLED priced while answering it —
   * agent rows on a run with calls only, null otherwise.
   */
  withCalleesUsd: number | null;
  /** Share of prompt tokens served from cache, as a percentage. */
  cacheShare: number | null;
  /** The fullest context reading among its turns, 0 to 1. */
  peakContext: number | null;
  failed: number;
}

/** Whether the window is the whole run — the case where lanes' own figures apply. */
function isWhole(data: RunWaterfallDto, window: ClockWindow): boolean {
  return (
    window.from <= Date.parse(data.from) && window.to >= Date.parse(data.to)
  );
}

/** A lane's key in a map — the chat's own lane is keyed null, which a string key cannot hold. */
function laneKey(nodeId: string | null): string {
  return nodeId ?? '\u0000';
}

function sumPriced(turns: readonly RunWaterfallTurn[]): number | null {
  const priced = turns.filter((turn) => turn.costUsd !== null);
  return priced.length === 0
    ? null
    : priced.reduce((sum, turn) => sum + (turn.costUsd ?? 0), 0);
}

function cacheShareOf(turns: readonly RunWaterfallTurn[]): number | null {
  // Summed over the turns that reported BOTH figures. A turn that reported
  // only one would otherwise pull the share toward 0% or 100% on a figure
  // nobody measured — `cacheHitRate`'s own rule, applied across turns.
  const both = turns.filter(
    (turn) => turn.cacheReadTokens !== null && turn.inputTokens !== null,
  );
  if (both.length === 0) {
    return null;
  }
  return cacheHitRate(
    both.reduce((sum, turn) => sum + (turn.cacheReadTokens ?? 0), 0),
    both.reduce((sum, turn) => sum + (turn.inputTokens ?? 0), 0),
  );
}

function peakOf(turns: readonly RunWaterfallTurn[]): number | null {
  const fills = turns
    .map(turnContextFill)
    .filter((fill): fill is number => fill !== null);
  return fills.length === 0 ? null : Math.max(...fills);
}

function endsIn(turn: RunWaterfallTurn, window: ClockWindow): boolean {
  const end = endOf(turn);
  return end >= window.from && end <= window.to;
}

/**
 * What the agents a lane CALLED priced while answering it: each callee turn
 * that ended inside a call this lane made, counted once however many of its
 * calls overlap. One level deep — a callee's own callees are that callee's row.
 */
function calleeCost(
  data: RunWaterfallDto,
  nodeId: string | null,
  window: ClockWindow,
): number | null {
  const calls = data.calls.filter((call) => call.callerNodeId === nodeId);
  const answered = new Set<RunWaterfallTurn>();
  for (const call of calls) {
    const from = Date.parse(call.startedAt);
    const to = from + call.durationMs;
    for (const turn of data.turns) {
      const end = endOf(turn);
      if (
        turn.nodeId === call.calleeNodeId &&
        turn.nodeId !== nodeId &&
        end >= from &&
        end <= to &&
        endsIn(turn, window)
      ) {
        answered.add(turn);
      }
    }
  }
  return sumPriced([...answered]);
}

export function breakdownRows(
  data: RunWaterfallDto,
  window: ClockWindow,
  by: BreakdownBy,
  /** Only this lane's turns; undefined for every lane. */
  focus: string | null | undefined,
): BreakdownRow[] {
  const whole = isWhole(data, window);
  const inWindow = data.turns.filter(
    (turn) =>
      (focus === undefined || turn.nodeId === focus) &&
      overlapMs(Date.parse(turn.startedAt), endOf(turn), window) > 0,
  );
  const groups = new Map<string, RunWaterfallTurn[]>();
  const keyOf = (turn: RunWaterfallTurn): string =>
    by === 'agent' ? laneKey(turn.nodeId) : (turn.model ?? '');
  for (const turn of inWindow) {
    const key = keyOf(turn);
    groups.set(key, [...(groups.get(key) ?? []), turn]);
  }

  if (by === 'agent') {
    return data.lanes
      .filter(
        (lane) =>
          (focus === undefined || lane.nodeId === focus) &&
          // On the whole run a lane with no drawable turn (a CLI that timed
          // nothing) still has a price and a turn count worth a row.
          (whole || groups.has(laneKey(lane.nodeId))),
      )
      .map((lane) => {
        const turns = groups.get(laneKey(lane.nodeId)) ?? [];
        const priced = turns.filter((turn) => endsIn(turn, window));
        const own = whole ? lane.costUsd : sumPriced(priced);
        const callees =
          data.calls.length === 0
            ? null
            : calleeCost(data, lane.nodeId, window);
        return {
          key: lane.nodeId ?? 'agent',
          nodeId: lane.nodeId,
          // The lane's own count on the whole run: it is the daemon's
          // reconciled figure, and a turn its CLI never timed has no span.
          turns: whole ? lane.turns : turns.length,
          workedMs: turns.reduce(
            (sum, turn) =>
              sum + overlapMs(Date.parse(turn.startedAt), endOf(turn), window),
            0,
          ),
          costUsd: own,
          withCalleesUsd:
            data.calls.length === 0
              ? null
              : own === null && callees === null
                ? null
                : (own ?? 0) + (callees ?? 0),
          cacheShare: cacheShareOf(turns),
          peakContext: peakOf(turns),
          failed: turns.filter((turn) => turn.outcome === 'failed').length,
        };
      });
  }

  return [...groups.entries()].map(([key, turns]) => ({
    key: key === '' ? 'unknown model' : key,
    turns: turns.length,
    workedMs: turns.reduce(
      (sum, turn) =>
        sum + overlapMs(Date.parse(turn.startedAt), endOf(turn), window),
      0,
    ),
    costUsd: sumPriced(turns.filter((turn) => endsIn(turn, window))),
    withCalleesUsd: null,
    cacheShare: cacheShareOf(turns),
    peakContext: peakOf(turns),
    failed: turns.filter((turn) => turn.outcome === 'failed').length,
  }));
}

export interface ToolRow {
  name: string;
  calls: number;
}

/**
 * Which tools the run reached for, busiest first, folded by NAME — otherwise
 * `Bash` appears once per agent and the table stops answering "what did this
 * run do". The daemon counts tools per run, not per moment, so a zoomed view
 * still reads the whole run here and says so.
 */
export function toolRows(
  data: RunWaterfallDto,
  focus: string | null | undefined,
): ToolRow[] {
  const byName = new Map<string, number>();
  for (const use of data.toolUse) {
    if (focus !== undefined && use.nodeId !== focus) {
      continue;
    }
    byName.set(use.name, (byName.get(use.name) ?? 0) + use.calls);
  }
  return [...byName.entries()]
    .map(([name, calls]) => ({ name, calls }))
    .sort((a, b) => b.calls - a.calls);
}
