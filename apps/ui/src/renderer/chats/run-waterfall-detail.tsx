/**
 * What the selected mark is, in full — the panel that stays put.
 *
 * A hover panel follows the pointer and is gone the moment it moves, so it can
 * be read but not used: nothing in it can be copied, compared with the next
 * mark, or acted on. This holds the selection until another one replaces it,
 * and carries the two things a reader does next — open that moment in the
 * transcript, or zoom the view to it.
 *
 * With nothing selected it states the run's critical path by agent, which is
 * the answer to "what made this take as long as it did" before any click.
 */

interface Row {
  label: string;
  value: React.ReactNode;
  tone?: 'warning' | 'danger';
  /** A line under the value, for what the figure cannot say about itself. */
  note?: string;
}

function Rows({ rows }: { rows: readonly (Row | null)[] }): React.JSX.Element {
  return (
    <dl className="grid grid-cols-[auto_1fr] gap-x-3 gap-y-1.5 text-xs">
      {rows.map((row) =>
        row === null ? null : (
          <div key={row.label} className="contents">
            <dt className="text-muted-foreground">{row.label}</dt>
            <dd
              className={cn(
                'm-0 min-w-0 text-right break-words tabular-nums text-foreground',
                row.tone === 'warning' && 'text-warning',
                row.tone === 'danger' && 'text-destructive',
              )}>
              {row.value}
              {row.note === undefined ? null : (
                <span className="block text-muted-foreground">{row.note}</span>
              )}
            </dd>
          </div>
        ),
      )}
    </dl>
  );
}

const laneName = (memberId: string | null): string => memberId ?? 'agent';

function Swatch({
  data,
  memberId,
}: {
  data: RunWaterfallDto;
  memberId: string | null;
}): React.JSX.Element {
  return (
    <span
      aria-hidden="true"
      className="size-2 shrink-0 rounded-[2px]"
      style={{ backgroundColor: categoryToken(laneIndexOf(data, memberId)) }}
    />
  );
}

/** A span's stretch on the clock, padded so it does not sit on the view's edge. */
function around(startedAt: string, durationMs: number): ClockWindow {
  const from = Date.parse(startedAt);
  const pad = Math.max(5_000, durationMs * 0.15);
  return { from: from - pad, to: from + durationMs + pad };
}

export function WaterfallDetail({
  data,
  runFrom,
  selected,
  onJump,
  onZoom,
}: {
  data: RunWaterfallDto;
  runFrom: number;
  selected: WaterfallMark | null;
  /** Open this seq in the transcript; absent where no transcript is on screen. */
  onJump?: (seq: number) => void;
  onZoom: (window: ClockWindow) => void;
}): React.JSX.Element {
  const view = describe(data, runFrom, selected);
  if (view === null) {
    return <RunSummary data={data} />;
  }
  return (
    <div data-slot="waterfall-detail" className="flex flex-col gap-3">
      <div className="flex flex-col gap-0.5">
        <span className="flex items-center gap-1.5 text-[11px] text-muted-foreground">
          {view.memberId === undefined ? null : (
            <Swatch data={data} memberId={view.memberId} />
          )}
          {view.eyebrow}
        </span>
        <h4 className="text-sm font-semibold text-foreground">{view.title}</h4>
        {view.note === undefined ? null : (
          <p className="text-xs leading-relaxed text-muted-foreground">
            {view.note}
          </p>
        )}
      </div>
      <Rows rows={view.rows} />
      {view.extra}
      <div className="flex flex-col gap-1.5">
        {onJump === undefined ? null : (
          <Button
            size="sm"
            variant="secondary"
            className="justify-start"
            onClick={() => onJump(view.seq)}>
            <ArrowUpRight aria-hidden="true" className="size-3.5" />
            Open in chat
          </Button>
        )}
        <Button
          size="sm"
          variant="ghost"
          className="justify-start"
          onClick={() => onZoom(view.zoom)}>
          <ZoomIn aria-hidden="true" className="size-3.5" />
          Zoom to this
        </Button>
      </div>
    </div>
  );
}

interface Described {
  memberId?: string | null;
  eyebrow: string;
  title: string;
  note?: string;
  rows: (Row | null)[];
  extra?: React.ReactNode;
  seq: number;
  zoom: ClockWindow;
}

function describe(
  data: RunWaterfallDto,
  runFrom: number,
  selected: WaterfallMark | null,
): Described | null {
  if (selected === null) {
    return null;
  }
  const at = (startedAt: string): string =>
    `at ${formatTurnDuration(Date.parse(startedAt) - runFrom)}`;
  switch (selected.kind) {
    case 'turn': {
      const turn = data.turns[selected.index];
      return turn === undefined ? null : describeTurn(data, turn, at);
    }
    case 'call':
    case 'blocked': {
      const call = data.calls[selected.index];
      if (call === undefined) {
        return null;
      }
      const from = Date.parse(call.startedAt);
      const to = from + call.durationMs;
      const answering = data.turns.filter(
        (turn) =>
          turn.memberId === call.calleeMemberId &&
          overlapMs(Date.parse(turn.startedAt), endOf(turn), { from, to }) > 0,
      );
      const worked = answering.reduce(
        (sum, turn) =>
          sum +
          overlapMs(Date.parse(turn.startedAt), endOf(turn), { from, to }),
        0,
      );
      const priced = answering.filter((turn) => turn.costUsd !== null);
      const calleeCost = priced.reduce(
        (sum, turn) => sum + (turn.costUsd ?? 0),
        0,
      );
      const calleeEstimated = priced.reduce(
        (sum, turn) => sum + (turn.estimatedCostUsd ?? 0),
        0,
      );
      const callee = laneName(call.calleeMemberId);
      const caller = laneName(call.callerMemberId);
      const wall = Math.max(1, Date.parse(data.to) - Date.parse(data.from));
      const blocked = selected.kind === 'blocked';
      return {
        memberId: blocked ? call.callerMemberId : call.calleeMemberId,
        eyebrow: `${caller} · ${at(call.startedAt)}`,
        title: blocked ? `${caller} waited on ${callee}` : `→ ${callee}`,
        note: blocked
          ? `A call that held ${caller} still until ${callee} answered. The arrows show the work that answered it.`
          : undefined,
        rows: [
          {
            label: 'mode',
            value: blocksCaller(call)
              ? `${call.mode ?? 'sync'} · caller waits`
              : 'async · caller carries on',
          },
          {
            label: 'outcome',
            value: call.running ? 'still running' : (call.status ?? '—'),
            tone: callFailed(call) ? 'danger' : undefined,
          },
          {
            label: call.running ? 'so far' : 'took',
            value: formatTurnDuration(call.durationMs),
          },
          blocked
            ? {
                label: 'of the wall clock',
                value: formatPercent((call.durationMs / wall) * 100),
              }
            : null,
          {
            label: `${callee} worked`,
            value: `${formatTurnDuration(worked)} in ${answering.length} ${answering.length === 1 ? 'turn' : 'turns'}`,
          },
          {
            label: `${callee} spent`,
            value:
              priced.length === 0
                ? NOT_MEASURED
                : markEstimate(formatUsd(calleeCost), calleeEstimated),
            note: costEstimateTitle(calleeCost, calleeEstimated),
          },
          {
            // The part of the call nobody on the far side was working — a
            // callee queued behind its own calls, or waiting on a card.
            label: 'idle inside the call',
            value: formatTurnDuration(Math.max(0, call.durationMs - worked)),
          },
        ],
        seq: call.seq,
        zoom: around(call.startedAt, call.durationMs),
      };
    }
    case 'wait': {
      const wait = data.waits[selected.index];
      if (wait === undefined) {
        return null;
      }
      const start = Date.parse(wait.startedAt);
      const lit = onCriticalPath(
        data.criticalPath,
        'waiting_on_user',
        null,
        start,
        start + wait.durationMs,
      );
      return {
        memberId: wait.memberId,
        eyebrow: `${laneName(wait.memberId)} · ${at(wait.startedAt)}`,
        title: wait.question ? 'A question for you' : 'A permission request',
        rows: [
          { label: 'tool', value: wait.toolName ?? '—' },
          { label: 'you took', value: formatTurnDuration(wait.durationMs) },
          {
            label: 'answered',
            value:
              wait.allowed === null
                ? '—'
                : wait.allowed
                  ? 'allowed'
                  : 'refused',
          },
          {
            label: 'on the critical path',
            value: lit ? 'yes — the run stood still' : 'no',
            tone: lit ? 'warning' : undefined,
          },
        ],
        seq: wait.seq,
        zoom: around(wait.startedAt, wait.durationMs),
      };
    }
    case 'delegate': {
      const delegate = data.delegates[selected.index];
      return delegate === undefined
        ? null
        : {
            memberId: delegate.memberId,
            eyebrow: `${laneName(delegate.memberId)} · ${at(delegate.startedAt)}`,
            title: 'A sub-agent',
            rows: [
              { label: 'launched by', value: laneName(delegate.memberId) },
              {
                label: 'ran for',
                value: formatTurnDuration(delegate.durationMs),
              },
            ],
            seq: delegate.seq,
            zoom: around(delegate.startedAt, delegate.durationMs),
          };
    }
  }
}

function describeTurn(
  data: RunWaterfallDto,
  turn: RunWaterfallTurn,
  at: (startedAt: string) => string,
): Described {
  const total = data.totals.costUsd;
  const turnCost =
    turn.costUsd === null
      ? NOT_MEASURED
      : markEstimate(formatUsd(turn.costUsd), turn.estimatedCostUsd);
  const share = turnCacheShare(turn);
  const fill = turnContextFill(turn);
  const outcome =
    turn.outcome === 'failed'
      ? ' · failed'
      : turn.outcome === 'cancelled'
        ? ' · stopped'
        : turn.outcome === 'running'
          ? ' · working now'
          : '';
  return {
    memberId: turn.memberId,
    eyebrow: `${laneName(turn.memberId)} · ${at(turn.startedAt)}`,
    title: `A turn${outcome}`,
    note:
      turn.timingSource === 'derived'
        ? 'This CLI reports no timing, so the stretch is measured from the rows it wrote.'
        : undefined,
    rows: [
      {
        label: 'cost',
        value:
          turn.costUsd === null
            ? NOT_MEASURED
            : total === null || total <= 0
              ? turnCost
              : `${turnCost} · ${formatPercent((turn.costUsd / total) * 100)} of the run`,
        note: costEstimateTitle(turn.costUsd, turn.estimatedCostUsd),
      },
      // Which models that cost went to — the sub-agents' included, which the
      // token rows below may not count.
      ...(splitParts(turn) ?? []).map((part) => ({
        label: part.model,
        value: markEstimate(formatUsd(part.costUsd), turn.estimatedCostUsd),
      })),
      {
        label: turn.outcome === 'running' ? 'so far' : 'worked',
        value: formatTurnDuration(turn.durationMs),
      },
      turn.apiMs === null
        ? null
        : { label: 'of that, API', value: formatTurnDuration(turn.apiMs) },
      turn.ttftMs === null
        ? null
        : { label: 'to first token', value: formatTurnDuration(turn.ttftMs) },
      turn.timeToRequestMs === null
        ? null
        : {
            label: 'before asking',
            value: formatTurnDuration(turn.timeToRequestMs),
          },
      { label: 'model', value: turn.model ?? '—' },
      turn.numTurns === null
        ? null
        : { label: 'model calls', value: formatCount(turn.numTurns) },
      { label: 'tools', value: formatCount(turn.toolCalls) },
      turn.delegateToolCalls === 0
        ? null
        : {
            label: BY_SUB_AGENTS,
            value: formatCount(turn.delegateToolCalls),
          },
      turn.inputTokens === null
        ? null
        : { label: 'fresh input', value: formatTokens(turn.inputTokens) },
      turn.cacheReadTokens === null
        ? null
        : {
            label: 'cache read',
            value:
              share === null
                ? formatTokens(turn.cacheReadTokens)
                : `${formatTokens(turn.cacheReadTokens)} · ${formatPercent(share)}`,
            tone: share !== null && share < 50 ? 'warning' : undefined,
          },
      turn.outputTokens === null
        ? null
        : { label: 'output', value: formatTokens(turn.outputTokens) },
      fill === null
        ? null
        : {
            label: 'context after',
            value: `${formatTokens(turn.contextTokens ?? 0)} of ${formatTokens(turn.contextWindowTokens ?? 0)}`,
            tone: fill >= CONTEXT_PRESSURE ? 'warning' : undefined,
          },
    ],
    extra:
      fill === null ? null : (
        <ProgressBar
          fraction={fill}
          label="How full the context was after the turn"
          tone={fill >= CONTEXT_PRESSURE ? 'danger' : 'default'}
          className="h-1.5 bg-muted"
        />
      ),
    seq: turn.seq,
    zoom: around(turn.startedAt, turn.durationMs),
  };
}

/** The resting state: what set the wall clock, by agent, before any click. */
function RunSummary({ data }: { data: RunWaterfallDto }): React.JSX.Element {
  const byNode = new Map<string | null, number>();
  let waited = 0;
  let idle = 0;
  for (const segment of data.criticalPath) {
    if (segment.kind === 'work') {
      byNode.set(
        segment.memberId,
        (byNode.get(segment.memberId) ?? 0) + segment.durationMs,
      );
    } else if (segment.kind === 'waiting_on_user') {
      waited += segment.durationMs;
    } else {
      idle += segment.durationMs;
    }
  }
  const holders = [...byNode.entries()].sort((a, b) => b[1] - a[1]);
  const wall = Math.max(1, Date.parse(data.to) - Date.parse(data.from));
  const share = (ms: number): string => formatPercent((ms / wall) * 100);
  return (
    <div data-slot="waterfall-detail" className="flex flex-col gap-3">
      <div className="flex flex-col gap-0.5">
        <h4 className="text-sm font-semibold text-foreground">
          Nothing selected
        </h4>
        <p className="text-xs leading-relaxed text-muted-foreground">
          Click a bar or one of the notes above to read it here and open it in
          the chat.
        </p>
      </div>
      {data.criticalPath.length === 0 ? null : (
        <div className="flex flex-col gap-2">
          <p className="text-xs leading-relaxed text-muted-foreground">
            What set the wall clock — the critical path, by who held it:
          </p>
          <Rows
            rows={[
              ...holders.map(([memberId, ms]) => ({
                label: laneName(memberId),
                value: `${formatDuration(ms)} · ${share(ms)}`,
              })),
              waited === 0
                ? null
                : {
                    label: 'waiting on you',
                    value: `${formatDuration(waited)} · ${share(waited)}`,
                    tone: 'warning' as const,
                  },
              idle === 0
                ? null
                : {
                    label: 'nobody working',
                    value: `${formatDuration(idle)} · ${share(idle)}`,
                  },
            ]}
          />
        </div>
      )}
    </div>
  );
}
