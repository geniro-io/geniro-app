// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import { stubResizeObserver } from '../__tests__/stub-resize-observer';
import type {
  RunWaterfallDto,
  RunWaterfallLane,
  RunWaterfallTurn,
} from '../autogenerated';
import { RunWaterfallDialog } from './run-waterfall-dialog';

stubResizeObserver();

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const FROM = '2026-09-07T12:00:00.000Z';
const TO = '2026-09-07T13:00:00.000Z';

function lane(over: Partial<RunWaterfallLane> = {}): RunWaterfallLane {
  return {
    nodeId: 'engineer',
    agentKind: 'claude',
    costUsd: 12.5,
    turns: 2,
    toolCalls: 40,
    workedMs: 600_000,
    toolBuckets: [0, 3, 0],
    ...over,
  };
}

function turn(over: Partial<RunWaterfallTurn> = {}): RunWaterfallTurn {
  return {
    nodeId: 'engineer',
    startedAt: FROM,
    timingSource: 'cli',
    durationMs: 60_000,
    apiMs: null,
    ttftMs: null,
    timeToRequestMs: null,
    numTurns: null,
    costUsd: 3,
    model: 'opus-5',
    inputTokens: null,
    outputTokens: null,
    cacheReadTokens: null,
    contextTokens: null,
    contextWindowTokens: null,
    ...over,
  };
}

function dto(over: Partial<RunWaterfallDto> = {}): RunWaterfallDto {
  return {
    from: FROM,
    to: TO,
    lanes: [lane()],
    toolUse: [],
    turns: [],
    calls: [],
    waits: [],
    delegates: [],
    totals: {
      turns: 2,
      costedTurns: 2,
      costUsd: 12.5,
      inputTokens: null,
      outputTokens: null,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      thinkingTokens: null,
      workedMs: 600_000,
    },
    waitedOnUserMs: null,
    partialReason: null,
    ...over,
  };
}

let root: Root | null = null;
let host: HTMLDivElement | null = null;

function show(data: RunWaterfallDto): HTMLElement {
  host = document.createElement('div');
  document.body.append(host);
  root = createRoot(host);
  act(() => {
    root?.render(<RunWaterfallDialog open onClose={() => {}} data={data} />);
  });
  // The dialog renders into the document, not into `host` — read the body.
  return document.body;
}

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
});

describe('RunWaterfallDialog', () => {
  it('states the wall clock and the agent time as two separate figures', () => {
    // The GAP between them is the answer to "why did this take all afternoon",
    // and collapsing them into one figure is what hides it. 1h against 10m.
    const view = show(dto());

    expect(view.textContent).toContain('wall clock');
    expect(view.textContent).toContain('agent time');
    expect(view.textContent).toContain('1h');
    expect(view.textContent).toContain('10m');
  });

  it('says a run priced nothing instead of drawing it as free', () => {
    // The render half of the money rule, at the headline figure this time.
    const view = show(
      dto({
        totals: { ...dto().totals, costUsd: null, costedTurns: 0 },
      }),
    );

    expect(view.textContent).not.toContain('$0.00');
    expect(view.textContent).toContain('—');
  });

  it('replaces the curve with a sentence when no turn reported a price', () => {
    // A cursor-only run prices nothing on the wire, and an axis pair with a
    // flat line at zero would claim the run was free rather than unmeasured.
    const view = show(dto({ turns: [turn({ costUsd: null })] }));

    expect(view.textContent).toContain('no turn on this run reported a price');
  });

  it('draws the money curve once a turn carries a price', () => {
    const view = show(dto({ turns: [turn({ costUsd: 3 })] }));

    expect(view.textContent).not.toContain(
      'no turn on this run reported a price',
    );
    expect(view.textContent).toContain('How the money added up');
  });

  it('draws the waiting-on-you lane only when somebody was actually asked', () => {
    // Asserted on the LANE rather than on the words: the legend carries the
    // same phrase permanently, so a text search here passes whatever the lane
    // does. That is exactly how this test failed when it was written.
    const view = show(dto());

    expect(view.querySelector('[data-slot="waterfall-wait-lane"]')).toBeNull();
    expect(view.textContent).toContain('waiting on you');
  });

  it('draws that lane once a card was raised', () => {
    const view = show(
      dto({
        waits: [
          {
            nodeId: null,
            question: true,
            toolName: 'AskUserQuestion',
            allowed: true,
            startedAt: FROM,
            durationMs: 120_000,
          },
        ],
        waitedOnUserMs: 120_000,
      }),
    );

    expect(
      view.querySelector('[data-slot="waterfall-wait-lane"]'),
    ).not.toBeNull();
    expect(view.textContent).toContain('2m');
  });

  it('lists the most expensive turns, biggest first', () => {
    const view = show(
      dto({
        turns: [
          turn({ costUsd: 1, model: 'haiku' }),
          turn({ costUsd: 40, model: 'opus-5' }),
        ],
      }),
    );

    const rows = [...view.querySelectorAll('tbody tr')];
    expect(rows).toHaveLength(2);
    expect(rows[0]?.textContent).toContain('opus-5');
    expect(rows[1]?.textContent).toContain('haiku');
  });

  it("repeats the daemon's own sentence when the picture is capped", () => {
    // Same rule as the card: a thinner picture is otherwise indistinguishable
    // from a quieter run, and the big view is where somebody counts the bars.
    const view = show(
      dto({ partialReason: "showing the newest 500 of this run's turns" }),
    );

    expect(view.textContent).toContain('showing the newest 500');
  });

  it('answers a hover on the tool-density strip, which had no hover at all', () => {
    // The strip is the widest band in every lane and carried no `title`, so on
    // a lane whose turns all ran inside agent calls (`0 turns`, density only)
    // hovering anywhere produced NOTHING. REPORTED as "непонятно, что за
    // полоски такие". Driven through a real mouse event rather than asserted
    // on markup: the reading is produced by the handler, not by the DOM.
    const view = show(
      dto({ lanes: [lane({ nodeId: 'qa', turns: 0, toolBuckets: [7, 0] })] }),
    );

    const bucket = view.querySelectorAll('[data-lane-track] span span')[0];
    expect(bucket).not.toBeUndefined();
    act(() => {
      bucket?.dispatchEvent(
        new MouseEvent('mousemove', {
          bubbles: true,
          clientX: 10,
          clientY: 10,
        }),
      );
    });

    expect(view.textContent).toContain('tool calls');
    expect(view.textContent).toContain('sub-agents included');
  });

  it('answers a hover anywhere in a lane, not only on a mark', () => {
    // A lane holding nothing but density has no mark to aim at, so the TRACK
    // itself has to say which agent the row is and where on the clock the
    // pointer sits — otherwise most of a lane is dead space that explains
    // nothing.
    const view = show(dto({ lanes: [lane({ nodeId: 'engineer' })] }));

    const track = view.querySelector('[data-lane-track]');
    expect(track).not.toBeNull();
    // The panel is the observable, and it must not already be there — the lane
    // LABEL also says `engineer`, so a bare text search would pass with the
    // handler deleted.
    const panelTitles = (): string[] =>
      [...view.querySelectorAll('p')].map((node) => node.textContent ?? '');
    expect(panelTitles()).not.toContain('engineer');

    act(() => {
      track?.dispatchEvent(
        new MouseEvent('mousemove', {
          bubbles: true,
          clientX: 10,
          clientY: 10,
        }),
      );
    });

    expect(panelTitles()).toContain('engineer');
  });

  it('gives a workflow run one lane per node', () => {
    // The whole reason the fold keys on `nodeId`: a five-node Dev Team run has
    // to read as five agents on one clock, not as one merged row.
    const view = show(
      dto({
        lanes: [
          lane({ nodeId: 'manager' }),
          lane({ nodeId: 'engineer' }),
          lane({ nodeId: 'qa', agentKind: 'cursor-agent', costUsd: null }),
        ],
      }),
    );

    expect(view.textContent).toContain('manager');
    expect(view.textContent).toContain('engineer');
    expect(view.textContent).toContain('qa');
    expect(view.textContent).toContain('cursor-agent');
  });

  it("counts the headline's turns from the lanes, not from finished turns alone", () => {
    // MEASURED in the running app: a run stopped mid-turn writes no
    // `turn_complete`, so `totals.turns` was 0 while the lanes directly under
    // the tile read `1 turn` and `3 turns`. One screen, two answers, and the
    // tile is the half a reader takes first.
    const view = show(
      dto({
        lanes: [
          lane({ nodeId: 'manager', turns: 1 }),
          lane({ nodeId: 'engineer', turns: 3 }),
        ],
        totals: { ...dto().totals, turns: 0, costedTurns: 0 },
      }),
    );

    const tile = [...view.querySelectorAll('div')].find(
      (node) => node.textContent?.trim().startsWith('turns') === true,
    );
    expect(tile?.textContent).toContain('4');
  });

  it('states a tool’s share as a share, not as a rounding error', () => {
    // `formatPercent` takes a PERCENT and was handed the rate, so the busiest
    // tool on a real run — 352 calls of 520 — was reported as `1%`.
    const view = show(
      dto({
        lanes: [lane({ nodeId: 'eng', toolCalls: 520 })],
        toolUse: [
          { nodeId: 'eng', name: 'Bash', calls: 352 },
          { nodeId: 'eng', name: 'Read', calls: 168 },
        ],
      }),
    );

    const table = view.querySelector('table');
    expect(table?.textContent).toContain('68%');
    expect(table?.textContent).not.toContain('1%');
  });
});
