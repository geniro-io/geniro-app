const FROM = Date.parse('2026-09-07T12:00:00.000Z');
const SECOND = 1000;

function at(seconds: number): string {
  return new Date(FROM + seconds * SECOND).toISOString();
}

function lane(
  nodeId: string,
  agentKind: RunWaterfallLane['agentKind'],
  costUsd: number | null,
  turns: number,
  toolCalls: number,
): RunWaterfallLane {
  return {
    nodeId,
    agentKind,
    costUsd,
    estimatedCostUsd: null,
    turns,
    toolCalls,
    delegateToolCalls: 0,
    workedMs: null,
  };
}

let nextSeq = 1;

function turn(
  nodeId: string,
  start: number,
  end: number,
  over: Partial<RunWaterfallTurn> = {},
): RunWaterfallTurn {
  return {
    nodeId,
    startedAt: at(start),
    seq: nextSeq++,
    timingSource: 'cli',
    outcome: 'completed',
    toolCalls: 12,
    delegateToolCalls: 0,
    durationMs: (end - start) * SECOND,
    apiMs: null,
    ttftMs: null,
    timeToRequestMs: null,
    numTurns: null,
    costUsd: null,
    estimatedCostUsd: null,
    model: 'opus-5',
    member: null,
    inputTokens: null,
    outputTokens: null,
    cacheReadTokens: null,
    contextTokens: null,
    contextWindowTokens: null,
    modelCosts: null,
    ...over,
  };
}

function call(
  calleeNodeId: string,
  start: number,
  end: number,
  over: Partial<RunWaterfallCall> = {},
): RunWaterfallCall {
  return {
    callerNodeId: 'manager',
    calleeNodeId,
    mode: 'async',
    status: 'ok',
    running: false,
    startedAt: at(start),
    seq: nextSeq++,
    durationMs: (end - start) * SECOND,
    ...over,
  };
}

function segment(
  kind: RunWaterfallCriticalSegment['kind'],
  nodeId: string | null,
  start: number,
  end: number,
): RunWaterfallCriticalSegment {
  return {
    kind,
    nodeId,
    startedAt: at(start),
    durationMs: (end - start) * SECOND,
  };
}

