const FROM = Date.parse('2026-09-07T12:00:00.000Z');
const MINUTE = 60_000;

function at(minutes: number): string {
  return new Date(FROM + minutes * MINUTE).toISOString();
}

function lane(nodeId: string, costUsd: number | null): RunWaterfallLane {
  return {
    nodeId,
    agentKind: 'claude',
    costUsd,
    turns: 2,
    toolCalls: 40,
    workedMs: 10 * MINUTE,
  };
}

function turn(
  nodeId: string,
  startMinutes: number,
  minutes: number,
  costUsd: number | null,
): RunWaterfallTurn {
  return {
    nodeId,
    startedAt: at(startMinutes),
    timingSource: 'cli',
    outcome: 'completed',
    toolCalls: 12,
    durationMs: minutes * MINUTE,
    apiMs: null,
    ttftMs: null,
    timeToRequestMs: null,
    numTurns: null,
    costUsd,
    model: 'opus-5',
    inputTokens: null,
    outputTokens: null,
    cacheReadTokens: null,
    contextTokens: null,
    contextWindowTokens: null,
  };
}

function call(
  calleeNodeId: string,
  startMinutes: number,
  minutes: number,
): RunWaterfallCall {
  return {
    callerNodeId: 'manager',
    calleeNodeId,
    mode: 'async',
    status: 'ok',
    running: false,
    startedAt: at(startMinutes),
    durationMs: minutes * MINUTE,
  };
}

