type BreakdownTab = BreakdownBy | 'tool';

/**
 * The same run, folded by agent, by model or by tool — over the stretch in
 * view and the agent in focus.
 *
 * ASKED FOR, for the tools half, as "для Tools мне тоже нужна статистика:
 * сколько и каких". The agent and model halves answer "who spent it" and "on
 * which model", with the cache share and the fullest context beside the money,
 * because those two are what make one agent expensive and another cheap.
 */
function Breakdown({
  data,
  view,
  zoomed,
  focus,
  onFocus,
}: {
  data: RunWaterfallDto;
  view: ClockWindow;
  zoomed: boolean;
  focus: string | null | undefined;
  onFocus: (nodeId: string | null | undefined) => void;
}): React.JSX.Element {
  const [tab, setTab] = useState<BreakdownTab>('agent');
  const scope = [
    zoomed ? 'the stretch in view' : 'the whole run',
    focus === undefined ? null : `only ${focus ?? 'agent'}`,
  ]
    .filter(Boolean)
    .join(' · ');
  return (
    <div className="flex flex-col gap-2">
      <div className="flex flex-wrap items-center gap-2">
        <SegmentedControl
          ariaLabel="Fold the run by"
          size="sm"
          options={[
            { id: 'agent', label: 'By agent' },
            { id: 'model', label: 'By model' },
            { id: 'tool', label: 'By tool' },
          ]}
          value={tab}
          onSelect={setTab}
        />
        <span className="ml-auto text-[11px] text-muted-foreground">
          {tab === 'tool' && zoomed
            ? `${focus === undefined ? '' : `only ${focus ?? 'agent'} · `}tool counts always cover the whole run`
            : scope}
        </span>
      </div>
      {tab === 'tool' ? (
        <ToolTable data={data} focus={focus} />
      ) : (
        <FoldTable
          data={data}
          rows={breakdownRows(data, view, tab, focus)}
          by={tab}
          focus={focus}
          onFocus={onFocus}
        />
      )}
      {tab === 'tool' || !zoomed ? null : (
        <p className="text-[11px] text-muted-foreground">
          A turn's money is counted where it ended, which is when its CLI priced
          it.
        </p>
      )}
    </div>
  );
}

function FoldTable({
  data,
  rows,
  by,
  focus,
  onFocus,
}: {
  data: RunWaterfallDto;
  rows: readonly BreakdownRow[];
  by: BreakdownBy;
  focus: string | null | undefined;
  onFocus: (nodeId: string | null | undefined) => void;
}): React.JSX.Element {
  const showCallees = by === 'agent' && data.calls.length > 0;
  const sorted = [...rows].sort(
    (a, b) => (b.costUsd ?? -1) - (a.costUsd ?? -1) || b.workedMs - a.workedMs,
  );
  const peak = Math.max(...sorted.map((row) => row.costUsd ?? 0), 0.0001);
  if (sorted.length === 0) {
    return (
      <p className="text-xs text-muted-foreground">
        no turn ran in what is shown
      </p>
    );
  }
  return (
    <div className="overflow-x-auto rounded-xl border border-border bg-card">
      <table className="w-full min-w-[40rem] table-fixed border-collapse text-xs">
        <colgroup>
          <col className="w-[22%]" />
          <col className="w-[8%]" />
          <col className="w-[11%]" />
          <col className="w-[19%]" />
          {showCallees ? <col className="w-[12%]" /> : null}
          <col className="w-[10%]" />
          <col className="w-[10%]" />
          <col className="w-[8%]" />
        </colgroup>
        <thead>
          <tr className="border-b border-border bg-muted/30 text-[10px] tracking-wide whitespace-nowrap text-muted-foreground uppercase">
            <th className="h-8 px-3 text-left font-medium">{by}</th>
            <th className="h-8 px-3 text-right font-medium">turns</th>
            <th className="h-8 px-3 text-right font-medium">in turns</th>
            <th className="h-8 px-3 text-right font-medium">own cost</th>
            {showCallees ? (
              <th
                className="h-8 px-3 text-right font-medium"
                title="Its own cost plus what the agents it called priced while answering it">
                with callees
              </th>
            ) : null}
            <th className="h-8 px-3 text-right font-medium">cache read</th>
            <th
              className="h-8 px-3 text-right font-medium whitespace-nowrap"
              title="The fullest the context window got after any of its turns">
              context
            </th>
            <th className="h-8 px-3 text-right font-medium">failed</th>
          </tr>
        </thead>
        <tbody>
          {sorted.map((row) => {
            const nodeId = row.nodeId;
            const focusable = by === 'agent' && nodeId !== undefined;
            const colour =
              nodeId === undefined
                ? undefined
                : categoryToken(laneIndexOf(data, nodeId));
            return (
              <tr
                key={row.key}
                data-slot="waterfall-fold-row"
                className={cn(
                  'border-t border-border/60',
                  focusable && 'cursor-pointer hover:bg-muted/40',
                  focusable && focus === nodeId && 'bg-muted/50',
                )}
                onClick={
                  focusable
                    ? () => onFocus(focus === nodeId ? undefined : nodeId)
                    : undefined
                }>
                <td className="h-9 px-3">
                  <span className="flex min-w-0 items-center gap-1.5">
                    {colour === undefined ? null : (
                      <span
                        aria-hidden="true"
                        className="size-2 shrink-0 rounded-[2px]"
                        style={{ backgroundColor: colour }}
                      />
                    )}
                    {focusable ? (
                      <button
                        type="button"
                        aria-pressed={focus === nodeId}
                        className="cursor-pointer truncate text-left text-xs text-foreground hover:underline"
                        onClick={(event) => {
                          event.stopPropagation();
                          onFocus(focus === nodeId ? undefined : nodeId);
                        }}>
                        {row.key}
                      </button>
                    ) : (
                      <span className="truncate text-foreground">
                        {row.key}
                      </span>
                    )}
                  </span>
                </td>
                <td className="h-9 px-3 text-right tabular-nums text-muted-foreground">
                  {formatCount(row.turns)}
                </td>
                <td className="h-9 px-3 text-right tabular-nums text-muted-foreground">
                  {row.workedMs === 0
                    ? NOT_MEASURED
                    : formatTurnDuration(row.workedMs)}
                </td>
                <td className="h-9 px-3">
                  <span className="flex items-center justify-end gap-2">
                    <ShareBar
                      fraction={(row.costUsd ?? 0) / peak}
                      className="w-12"
                    />
                    <span
                      className="font-medium tabular-nums text-foreground"
                      title={costEstimateTitle(
                        row.costUsd,
                        row.estimatedCostUsd,
                      )}>
                      {row.costUsd === null
                        ? NOT_MEASURED
                        : markEstimate(
                            formatUsd(row.costUsd),
                            row.estimatedCostUsd,
                          )}
                    </span>
                  </span>
                </td>
                {showCallees ? (
                  <td
                    className="h-9 px-3 text-right tabular-nums text-muted-foreground"
                    title={costEstimateTitle(
                      row.withCalleesUsd,
                      row.withCalleesEstimatedUsd,
                    )}>
                    {row.withCalleesUsd === null
                      ? NOT_MEASURED
                      : markEstimate(
                          formatUsd(row.withCalleesUsd),
                          row.withCalleesEstimatedUsd,
                        )}
                  </td>
                ) : null}
                <td
                  className={cn(
                    'h-9 px-3 text-right tabular-nums text-muted-foreground',
                    row.cacheShare !== null &&
                      row.cacheShare < 50 &&
                      'text-warning',
                  )}>
                  {row.cacheShare === null
                    ? NOT_MEASURED
                    : formatPercent(row.cacheShare)}
                </td>
                <td
                  className={cn(
                    'h-9 px-3 text-right tabular-nums text-muted-foreground',
                    row.peakContext !== null &&
                      row.peakContext >= CONTEXT_PRESSURE &&
                      'text-warning',
                  )}>
                  {row.peakContext === null
                    ? NOT_MEASURED
                    : formatPercent(row.peakContext * 100)}
                </td>
                <td
                  className={cn(
                    'h-9 px-3 text-right tabular-nums text-muted-foreground',
                    row.failed > 0 && 'text-destructive',
                  )}>
                  {row.failed === 0 ? NOT_MEASURED : formatCount(row.failed)}
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}

/** WHICH tools the run reached for, and how often. */
function ToolTable({
  data,
  focus,
}: {
  data: RunWaterfallDto;
  focus: string | null | undefined;
}): React.JSX.Element {
  const rows = toolRows(data, focus);
  const own = rows.reduce((sum, row) => sum + row.calls, 0);
  const delegated = rows.reduce((sum, row) => sum + row.delegateCalls, 0);
  const total = own + delegated;
  // A run whose agents launched no sub-agent keeps the table it had: a column
  // of zeros says nothing.
  const split = delegated > 0;
  if (rows.length === 0) {
    return (
      <p className="text-xs text-muted-foreground">
        {focus === undefined
          ? 'this run recorded no tool call'
          : 'this agent recorded no tool call'}
      </p>
    );
  }
  return (
    <div className="flex flex-col gap-2">
      <div className="overflow-x-auto rounded-xl border border-border bg-card">
        <table className="w-full table-fixed border-collapse text-xs">
          <colgroup>
            <col className={cn(split ? 'w-[32%]' : 'w-[38%]')} />
            <col className={cn(split ? 'w-[32%]' : 'w-[38%]')} />
            <col className="w-[12%]" />
            {split ? <col className="w-[12%]" /> : null}
            <col className="w-[12%]" />
          </colgroup>
          <thead>
            <tr className="border-b border-border bg-muted/30 text-[10px] tracking-wide text-muted-foreground uppercase">
              <th className="h-8 px-3 text-left font-medium">tool</th>
              <th className="h-8 px-3 text-left font-medium">share</th>
              <th className="h-8 px-3 text-right font-medium">
                {split ? 'own' : 'calls'}
              </th>
              {split ? (
                <th className="h-8 px-3 text-right font-medium">sub-agents</th>
              ) : null}
              <th className="h-8 px-3 text-right font-medium">of total</th>
            </tr>
          </thead>
          <tbody>
            {rows.map((row, index) => (
              <tr key={row.name} className="border-t border-border/60">
                <td className="h-9 px-3">
                  <span className="block truncate text-foreground">
                    {row.name}
                  </span>
                </td>
                <td className="h-9 px-3">
                  <ShareBar
                    fraction={row.all / (rows[0]?.all ?? 1)}
                    colour={categoryToken(index)}
                  />
                </td>
                <td className="h-9 px-3 text-right font-medium tabular-nums text-foreground">
                  {formatCount(row.calls)}
                </td>
                {split ? (
                  <td className="h-9 px-3 text-right tabular-nums text-foreground">
                    {formatCount(row.delegateCalls)}
                  </td>
                ) : null}
                <td className="h-9 px-3 text-right tabular-nums text-muted-foreground">
                  {/*
                    `formatPercent` takes a PERCENT, not a rate — handed the
                    fraction it rounded 352-of-520 to `1%`, the busiest tool on
                    the run reported as a rounding error.
                  */}
                  {total === 0
                    ? NOT_MEASURED
                    : formatPercent((row.all / total) * 100)}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p className="text-[11px] text-muted-foreground">
        {toolsTitle(own, delegated)}
      </p>
    </div>
  );
}

/**
 * The money, accumulating over the SAME x axis the lanes use.
 *
 * Two charts rather than one with two y scales: a dual axis lets a reader take
 * any crossing point as meaningful when it is an artefact of two arbitrary
 * scalings, which is the single most common chart mistake and is forbidden
 * outright here. The stretch zoomed into above is shaded, so the curve says
 * how much of the money fell inside it.
 */
function SpendCurve({
  points,
  span,
  highlight,
}: {
  points: readonly { atMs: number; spentUsd: number }[];
  span: number;
  /** The stretch in view, in milliseconds since the run's first row. */
  highlight: { from: number; to: number } | null;
}): React.JSX.Element {
  return (
    <div className="rounded-xl border border-border bg-card p-3">
      <ResponsiveContainer width="100%" height={CURVE_HEIGHT}>
        <AreaChart data={[...points]} margin={CHART_MARGIN}>
          <defs>
            <linearGradient id="waterfall-spend" x1="0" y1="0" x2="0" y2="1">
              <stop offset="0%" stopColor={SERIES.spend} stopOpacity={0.35} />
              <stop offset="100%" stopColor={SERIES.spend} stopOpacity={0.02} />
            </linearGradient>
          </defs>
          <CartesianGrid stroke={AXIS.stroke} vertical={false} />
          <XAxis
            dataKey="atMs"
            type="number"
            domain={[0, span]}
            tickFormatter={(value: number) => formatDuration(value)}
            stroke={AXIS.stroke}
            tick={AXIS.tick}
          />
          <YAxis
            tickFormatter={formatUsdAxis}
            stroke={AXIS.stroke}
            tick={AXIS.tick}
            width={56}
          />
          {highlight === null ? null : (
            <ReferenceArea
              x1={highlight.from}
              x2={highlight.to}
              fill={AXIS.stroke}
              fillOpacity={0.35}
              ifOverflow="hidden"
            />
          )}
          <Tooltip
            cursor={{ stroke: AXIS.stroke }}
            content={(props: SpendTooltipProps) => {
              const point = hoveredPoint(props);
              return point === null ? null : (
                <ChartTooltip
                  title={`${formatDuration(point.atMs)} in`}
                  rows={[
                    {
                      label: 'spent so far',
                      value: markEstimate(
                        formatUsd(point.spentUsd),
                        point.spentEstimatedUsd,
                      ),
                      color: SERIES.spend,
                      note: costEstimateTitle(
                        point.spentUsd,
                        point.spentEstimatedUsd,
                      ),
                    },
                  ]}
                />
              );
            }}
          />
          {/*
            A STEP, never a smoothed curve. Money is charged when a turn ENDS,
            so the total is flat between turns and jumps at each one — and
            `monotone` drew a run whose single priced turn landed 50 minutes in
            as a straight diagonal from zero, which says the money was spent
            evenly across the whole hour. The step says when it was actually
            spent, and on a long run it also reads as the shape of the work.
          */}
          <Area
            type="stepAfter"
            dataKey="spentUsd"
            stroke={SERIES.spend}
            strokeWidth={2}
            fill="url(#waterfall-spend)"
            isAnimationActive={false}
          />
        </AreaChart>
      </ResponsiveContainer>
    </div>
  );
}

/**
 * Which models a turn's cost went to, under its model's name — absent for a
 * turn one model paid for whole.
 */
function TurnCostSplit({
  turn,
}: {
  turn: RunWaterfallTurn;
}): React.JSX.Element | null {
  const split = costSplit(turn);
  if (split === null) {
    return null;
  }
  return (
    <span
      className="block truncate text-[10px] tabular-nums text-muted-foreground"
      title={split}>
      {split}
    </span>
  );
}

/**
 * Where the money went, turn by turn — the rows a reader acts on. A row
 * selects its turn on the gantt, so the detail panel can say the rest.
 */
function TopTurns({
  data,
  turns,
  selected,
  onSelect,
}: {
  data: RunWaterfallDto;
  turns: readonly RunWaterfallTurn[];
  selected: WaterfallMark | null;
  onSelect: (mark: WaterfallMark | null) => void;
}): React.JSX.Element {
  const peak = Math.max(...turns.map((turn) => turn.costUsd ?? 0), 0.0001);
  return (
    <div className="overflow-x-auto rounded-xl border border-border bg-card">
      {/*
        `table-fixed` with a declared colgroup, which is the whole of what made
        this read as crooked: on `auto` every column is sized by its own widest
        cell, so the bar column swelled or collapsed with whatever model names
        the run happened to hold and the numeric columns landed at a different
        x on every render. REPORTED as "таблица выглядит как-то кривой".
      */}
      <table className="w-full table-fixed border-collapse text-xs">
        <colgroup>
          <col className="w-[22%]" />
          <col className="w-[26%]" />
          <col className="w-[20%]" />
          <col className="w-[12%]" />
          <col className="w-[10%]" />
          <col className="w-[10%]" />
        </colgroup>
        <thead>
          {/*
            A real header BAND — its own ground and one hairline under it —
            rather than a row wearing the same padding as the data, which is
            what had it reading as a first row set in small caps.
          */}
          <tr className="border-b border-border bg-muted/30 text-[10px] tracking-wide text-muted-foreground uppercase">
            <th className="h-8 px-3 text-left font-medium">agent</th>
            <th className="h-8 px-3 text-left font-medium">model</th>
            <th className="h-8 px-3 text-left font-medium">share</th>
            <th className="h-8 px-3 text-right font-medium">cost</th>
            <th className="h-8 px-3 text-right font-medium">took</th>
            <th className="h-8 px-3 text-right font-medium">cache read</th>
          </tr>
        </thead>
        <tbody>
          {turns.map((turn) => {
            const colour = categoryToken(laneIndexOf(data, turn.nodeId));
            const index = data.turns.indexOf(turn);
            const mark: WaterfallMark = { kind: 'turn', index };
            const share = turnCacheShare(turn);
            return (
              <tr
                key={index}
                data-slot="waterfall-top-turn"
                className={cn(
                  'cursor-pointer border-t border-border/60 hover:bg-muted/40',
                  sameMark(selected, mark) && 'bg-muted/50',
                )}
                onClick={() =>
                  onSelect(sameMark(selected, mark) ? null : mark)
                }>
                <td className="h-9 px-3">
                  <span className="flex min-w-0 items-center gap-1.5">
                    <span
                      aria-hidden="true"
                      className="size-2 shrink-0 rounded-[2px]"
                      style={{ backgroundColor: colour }}
                    />
                    {/*
                      A BUTTON, so the row is reachable from the keyboard: the
                      row's own click is the pointer's shortcut to the same.
                    */}
                    <button
                      type="button"
                      aria-pressed={sameMark(selected, mark)}
                      className="cursor-pointer truncate text-left text-xs text-foreground hover:underline"
                      onClick={(event) => {
                        event.stopPropagation();
                        onSelect(sameMark(selected, mark) ? null : mark);
                      }}>
                      {turn.nodeId ?? 'agent'}
                    </button>
                  </span>
                </td>
                <td className="h-9 px-3 text-muted-foreground">
                  <span className="block truncate">
                    {turn.model ?? NOT_MEASURED}
                  </span>
                  <TurnCostSplit turn={turn} />
                </td>
                <td className="h-9 px-3">
                  <ShareBar
                    fraction={(turn.costUsd ?? 0) / peak}
                    colour={colour}
                  />
                </td>
                <td
                  className="h-9 px-3 text-right font-medium tabular-nums text-foreground"
                  title={costEstimateTitle(
                    turn.costUsd,
                    turn.estimatedCostUsd,
                  )}>
                  {turn.costUsd === null
                    ? NOT_MEASURED
                    : markEstimate(
                        formatUsd(turn.costUsd),
                        turn.estimatedCostUsd,
                      )}
                </td>
                <td className="h-9 px-3 text-right tabular-nums text-muted-foreground">
                  {formatTurnDuration(turn.durationMs)}
                </td>
                <td className="h-9 px-3 text-right tabular-nums text-muted-foreground">
                  {turn.cacheReadTokens === null
                    ? NOT_MEASURED
                    : share === null
                      ? formatTokens(turn.cacheReadTokens)
                      : formatPercent(share)}
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}
