/**
 * The money, accumulating over the SAME x axis the lanes use.
 *
 * Two charts rather than one with two y scales: a dual axis lets a reader take
 * any crossing point as meaningful when it is an artefact of two arbitrary
 * scalings, which is the single most common chart mistake and is forbidden
 * outright here.
 */
function SpendCurve({
  points,
  span,
}: {
  points: readonly { atMs: number; spentUsd: number }[];
  span: number;
}): React.JSX.Element {
  return (
    <div className="rounded-xl border border-border bg-card p-3">
      <ResponsiveContainer width="100%" height={CURVE_HEIGHT}>
        <AreaChart data={[...points]} margin={CHART_MARGIN}>
          <defs>
            <linearGradient id="waterfall-spend" x1="0" y1="0" x2="0" y2="1">
              <stop offset="0%" stopColor={SERIES.spend} stopOpacity={0.35} />
              <stop offset="100%" stopColor={SERIES.spend} stopOpacity={0.02} />
            </linearGradient>
          </defs>
          <CartesianGrid stroke={AXIS.stroke} vertical={false} />
          <XAxis
            dataKey="atMs"
            type="number"
            domain={[0, span]}
            tickFormatter={(value: number) => formatDuration(value)}
            stroke={AXIS.stroke}
            tick={AXIS.tick}
          />
          <YAxis
            tickFormatter={formatUsdAxis}
            stroke={AXIS.stroke}
            tick={AXIS.tick}
            width={56}
          />
          <Tooltip
            cursor={{ stroke: AXIS.stroke }}
            content={(props: SpendTooltipProps) => {
              const point = hoveredPoint(props);
              return point === null ? null : (
                <ChartTooltip
                  title={`${formatDuration(point.atMs)} in`}
                  rows={[
                    {
                      label: 'spent so far',
                      value: formatUsd(point.spentUsd),
                      color: SERIES.spend,
                    },
                  ]}
                />
              );
            }}
          />
          <Area
            type="monotone"
            dataKey="spentUsd"
            stroke={SERIES.spend}
            strokeWidth={2}
            fill="url(#waterfall-spend)"
            isAnimationActive={false}
          />
        </AreaChart>
      </ResponsiveContainer>
    </div>
  );
}

/** Where the money went, turn by turn — the rows a reader acts on. */
function TopTurns({
  data,
  turns,
}: {
  data: RunWaterfallDto;
  turns: readonly RunWaterfallTurn[];
}): React.JSX.Element {
  const peak = Math.max(...turns.map((turn) => turn.costUsd ?? 0), 0.0001);
  return (
    <div className="overflow-x-auto rounded-xl border border-border bg-card">
      <table className="w-full border-collapse text-xs">
        <thead>
          <tr className="text-[10px] tracking-wide text-muted-foreground uppercase">
            <th className="px-3 py-2 text-left font-medium">agent</th>
            <th className="px-3 py-2 text-left font-medium">model</th>
            <th className="w-1/4 px-3 py-2 text-left font-medium" />
            <th className="px-3 py-2 text-right font-medium">cost</th>
            <th className="px-3 py-2 text-right font-medium">took</th>
            <th className="px-3 py-2 text-right font-medium">cache read</th>
          </tr>
        </thead>
        <tbody>
          {turns.map((turn) => (
            <tr
              key={`${turn.startedAt}-${turn.durationMs}-${turn.costUsd ?? 0}`}
              className="border-t border-border">
              <td className="max-w-40 truncate px-3 py-1.5">
                <span className="flex min-w-0 items-center gap-1.5">
                  <span
                    aria-hidden="true"
                    className="size-2 shrink-0 rounded-[2px]"
                    style={{
                      backgroundColor: categoryToken(
                        laneIndexOf(data, turn.nodeId),
                      ),
                    }}
                  />
                  <span className="truncate">{turn.nodeId ?? 'agent'}</span>
                </span>
              </td>
              <td className="max-w-40 truncate px-3 py-1.5 text-muted-foreground">
                {turn.model ?? NOT_MEASURED}
              </td>
              <td className="px-3 py-1.5">
                <span
                  aria-hidden="true"
                  className="block h-1.5 rounded-[3px]"
                  style={{
                    width: `${Math.max(2, ((turn.costUsd ?? 0) / peak) * 100)}%`,
                    backgroundColor: categoryToken(
                      laneIndexOf(data, turn.nodeId),
                    ),
                  }}
                />
              </td>
              <td className="px-3 py-1.5 text-right tabular-nums">
                {turn.costUsd === null ? NOT_MEASURED : formatUsd(turn.costUsd)}
              </td>
              <td className="px-3 py-1.5 text-right tabular-nums text-muted-foreground">
                {formatTurnDuration(turn.durationMs)}
              </td>
              <td className="px-3 py-1.5 text-right tabular-nums text-muted-foreground">
                {turn.cacheReadTokens === null
                  ? NOT_MEASURED
                  : formatTokens(turn.cacheReadTokens)}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
