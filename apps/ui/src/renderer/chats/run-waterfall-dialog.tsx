/**
 * The run under a magnifying glass — the FULL view the sidebar card opens.
 *
 * The card in the panel answers "did this run go the way I think it did" at a
 * glance, in 280px. This answers the next question, which needs room: WHERE the
 * money went, in what order, and how long each piece actually took. Both read
 * the same fold from the same route (the daemon's, for the reason that route
 * exists at all — the renderer holds at most `HISTORY_PAGE` items) and share
 * their placement maths (`run-waterfall-geometry.ts`), so they cannot draw one
 * run two ways.
 *
 * A full-screen DIALOG rather than a nav destination, which is the house
 * pattern for exactly this shape: `artifact-dialog.tsx` opens a transcript card
 * into the same thing. A page of its own would need a run picker to be reachable
 * at all, and the run is already the one the sidebar has open.
 */

/** The label column's width — wide enough for a node name plus its CLI. */
const LABEL_WIDTH = 168;

/** How many marks the time axis carries. Six is readable at every width. */
const AXIS_TICKS = 6;

/** A bar narrower than this has no room for its own price, so it carries none. */
const LABEL_MIN_PCT = 5;

/** Rows in the most-expensive-turns table. */
const TOP_TURNS = 12;

/** Plot height for the cumulative-cost curve. */
const CURVE_HEIGHT = 200;

/**
 * What Recharts hands the curve's tooltip.
 *
 * Typed here rather than imported, for `time-charts.tsx`'s stated reason: the
 * library's own generic is loose enough that it would not catch a renamed data
 * key, which is the mistake this shape exists to make impossible. `readonly`
 * because the content prop is checked contravariantly.
 */
interface SpendTooltipProps {
  active?: boolean;
  payload?: readonly { payload?: SpendPoint }[];
}

/** The point the curve's tooltip is over, or null when it is not showing. */
function hoveredPoint(props: SpendTooltipProps): SpendPoint | null {
  return props.active && props.payload?.length
    ? (props.payload[0]?.payload ?? null)
    : null;
}

export function RunWaterfallDialog({
  open,
  onClose,
  data,
}: {
  open: boolean;
  onClose: () => void;
  data: RunWaterfallDto;
}): React.JSX.Element {
  const clock = useMemo(() => {
    const from = Date.parse(data.from);
    const to = Date.parse(data.to);
    return { from, span: Math.max(1, to - from) };
  }, [data]);

  const spend = useMemo(
    () => cumulativeSpend(data.turns, clock.from),
    [data, clock.from],
  );
  const expensive = useMemo(() => topTurns(data.turns, TOP_TURNS), [data]);

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Where the run went"
      className="h-[92vh] w-[min(96vw,80rem)] max-w-none">
      <div className="flex flex-col gap-6">
        <Tiles data={data} span={clock.span} />

        <Section title="Who worked when, and what it cost">
          <Gantt data={data} from={clock.from} span={clock.span} />
          <Legend />
        </Section>

        <Section title="How the money added up">
          {spend.length === 0 ? (
            <p className="text-xs text-muted-foreground">
              no turn on this run reported a price
            </p>
          ) : (
            <SpendCurve points={spend} span={clock.span} />
          )}
        </Section>

        <Section title="Where the money went — the most expensive turns">
          {expensive.length === 0 ? (
            <p className="text-xs text-muted-foreground">
              no turn on this run reported a price
            </p>
          ) : (
            <TopTurns data={data} turns={expensive} />
          )}
        </Section>

        {data.partialReason === null ? null : (
          <p className="text-xs text-muted-foreground">{data.partialReason}</p>
        )}
      </div>
    </Dialog>
  );
}

function Section({
  title,
  children,
}: {
  title: string;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <section className="flex flex-col gap-2">
      <h3 className="text-xs font-semibold tracking-wide text-muted-foreground uppercase">
        {title}
      </h3>
      {children}
    </section>
  );
}

/**
 * The run's headline figures.
 *
 * `wall clock` and `agent time` sit beside each other on purpose: the gap
 * between them IS the answer to "why did this take all afternoon", and it is
 * invisible while either is shown alone.
 */
function Tiles({
  data,
  span,
}: {
  data: RunWaterfallDto;
  span: number;
}): React.JSX.Element {
  const tools = data.lanes.reduce((sum, lane) => sum + lane.toolCalls, 0);
  const failed = data.calls.filter((call) => call.status !== 'ok').length;
  return (
    <StatGrid className="grid-cols-2 sm:grid-cols-3 lg:grid-cols-6">
      <StatCell
        label="spent"
        size="lead"
        value={
          data.totals.costUsd === null
            ? NOT_MEASURED
            : formatUsd(data.totals.costUsd)
        }
        footnote={
          data.totals.costedTurns === data.totals.turns
            ? undefined
            : `${data.totals.costedTurns} of ${data.totals.turns} turns priced`
        }
      />
      <StatCell label="wall clock" value={formatDuration(span)} />
      <StatCell
        label="agent time"
        value={
          data.totals.workedMs === null
            ? NOT_MEASURED
            : formatDuration(data.totals.workedMs)
        }
      />
      <StatCell
        label="waited on you"
        value={
          data.waitedOnUserMs === null
            ? NOT_MEASURED
            : formatDuration(data.waitedOnUserMs)
        }
        footnote={
          data.waits.length === 0
            ? undefined
            : `${data.waits.length} ${data.waits.length === 1 ? 'card' : 'cards'}`
        }
      />
      <StatCell label="turns" value={formatCount(data.totals.turns)} />
      <StatCell
        label="tools"
        value={formatCount(tools)}
        hint={toolsTitle(tools)}
        footnote={
          data.calls.length === 0
            ? undefined
            : `${data.calls.length} agent calls${failed === 0 ? '' : `, ${failed} failed`}`
        }
      />
    </StatGrid>
  );
}

/** One lane per node, plus the waiting-on-you lane, on one shared clock. */
function Gantt({
  data,
  from,
  span,
}: {
  data: RunWaterfallDto;
  from: number;
  span: number;
}): React.JSX.Element {
  const ticks = useMemo(
    () =>
      Array.from({ length: AXIS_TICKS }, (_, index) => ({
        pct: (index / (AXIS_TICKS - 1)) * 100,
        label: formatDuration((span * index) / (AXIS_TICKS - 1)),
      })),
    [span],
  );
  const turnsByLane = useMemo(() => {
    const byLane = new Map<string | null, RunWaterfallTurn[]>();
    for (const turn of data.turns) {
      const own = byLane.get(turn.nodeId);
      if (own === undefined) {
        byLane.set(turn.nodeId, [turn]);
      } else {
        own.push(turn);
      }
    }
    return byLane;
  }, [data]);

  return (
    <div className="overflow-hidden rounded-xl border border-border bg-card">
      <div
        className="grid"
        style={{ gridTemplateColumns: `${LABEL_WIDTH}px 1fr` }}>
        {/* The axis: elapsed time, so a reader never has to subtract two clocks. */}
        <div className="border-b border-border" />
        <div className="relative h-6 border-b border-l border-border">
          {ticks.map((tick) => (
            <span
              key={tick.pct}
              className="absolute top-1 -translate-x-1/2 text-[10px] tabular-nums text-muted-foreground"
              style={{ left: `${tick.pct}%` }}>
              {tick.label}
            </span>
          ))}
        </div>

        {data.lanes.map((lane, index) => (
          <Fragment key={lane.nodeId ?? 'chat'}>
            <LaneLabel lane={lane} index={index} />
            <LaneTrack
              data={data}
              lane={lane}
              index={index}
              turns={turnsByLane.get(lane.nodeId) ?? []}
              from={from}
              span={span}
            />
          </Fragment>
        ))}

        {data.waits.length === 0 ? null : (
          <Fragment>
            {/*
              Named, because the LEGEND below also carries the words "waiting
              on you" — so a text search cannot tell the lane from the key that
              explains it, and a spec written that way pins nothing.
            */}
            <div
              data-slot="waterfall-wait-lane"
              className="flex flex-col justify-center border-t border-border px-3 py-2">
              <span className="truncate text-sm font-medium text-foreground">
                waiting on you
              </span>
              <span className="text-[11px] tabular-nums text-muted-foreground">
                {data.waits.length} {data.waits.length === 1 ? 'card' : 'cards'}
              </span>
            </div>
            <div className="relative min-h-12 border-t border-l border-border">
              {data.waits.map((wait) => {
                const spot = place(wait.startedAt, wait.durationMs, from, span);
                return spot === null ? null : (
                  <span
                    key={`${wait.startedAt}-${wait.durationMs}`}
                    className="absolute top-1/2 h-3 -translate-y-1/2 rounded-[3px] border border-muted-foreground/70 bg-muted-foreground/25"
                    style={{
                      left: `${spot.leftPct}%`,
                      width: `${spot.widthPct}%`,
                    }}
                    title={`${wait.question ? 'question' : 'permission'}${
                      wait.toolName === null ? '' : ` · ${wait.toolName}`
                    } · ${formatTurnDuration(wait.durationMs)}`}
                  />
                );
              })}
            </div>
          </Fragment>
        )}
      </div>
    </div>
  );
}

function LaneLabel({
  lane,
  index,
}: {
  lane: RunWaterfallLane;
  index: number;
}): React.JSX.Element {
  return (
    <div className="flex flex-col justify-center gap-0.5 border-t border-border px-3 py-2">
      <span className="flex min-w-0 items-center gap-1.5">
        <span
          aria-hidden="true"
          className="size-2 shrink-0 rounded-[2px]"
          style={{ backgroundColor: categoryToken(index) }}
        />
        <span className="truncate text-sm font-medium text-foreground">
          {lane.nodeId ?? 'agent'}
        </span>
      </span>
      <span className="truncate pl-3.5 text-[11px] text-muted-foreground">
        {lane.agentKind ?? NOT_MEASURED}
      </span>
      <span className="flex gap-2 pl-3.5 text-[11px] tabular-nums text-muted-foreground">
        <span>
          {lane.costUsd === null ? NOT_MEASURED : formatUsd(lane.costUsd)}
        </span>
        <span>
          {lane.turns} {lane.turns === 1 ? 'turn' : 'turns'}
        </span>
        <span title={toolsTitle(lane.toolCalls)}>{lane.toolCalls} tools</span>
      </span>
    </div>
  );
}

/**
 * One lane's spans, stacked by what they mean rather than overlaid.
 *
 * Turns sit on top because they are the work; the calls this node MADE and the
 * delegates it launched are thinner rows under them, and the tool density runs
 * along the floor. Overlaying them was tried on the prototype and made a busy
 * lane unreadable — a call and the turn that made it are the same stretch of
 * time, so drawn on one line the wider one simply hides the other.
 */
function LaneTrack({
  data,
  lane,
  index,
  turns,
  from,
  span,
}: {
  data: RunWaterfallDto;
  lane: RunWaterfallLane;
  index: number;
  turns: readonly RunWaterfallTurn[];
  from: number;
  span: number;
}): React.JSX.Element {
  const colour = categoryToken(index);
  const peak = Math.max(1, ...lane.toolBuckets);
  const calls = data.calls.filter((call) => call.callerNodeId === lane.nodeId);
  const delegates = data.delegates.filter(
    (delegate) => delegate.nodeId === lane.nodeId,
  );
  return (
    <div className="relative min-h-16 border-t border-l border-border">
      {/* Tool density along the floor — how busy this lane was, minute to minute. */}
      <div
        aria-hidden="true"
        className="absolute inset-x-0 bottom-0 flex h-1.5">
        {lane.toolBuckets.map((count, bucket) => (
          <span
            key={bucket}
            className="h-full flex-1"
            style={{
              backgroundColor: colour,
              opacity: count === 0 ? 0 : 0.2 + 0.5 * (count / peak),
            }}
          />
        ))}
      </div>

      {turns.map((turn) => {
        const spot = place(turn.startedAt, turn.durationMs, from, span);
        if (spot === null) {
          return null;
        }
        return (
          <span
            key={`t-${turn.startedAt}-${turn.durationMs}`}
            className="absolute top-2 flex h-5 items-center overflow-hidden rounded-[4px] px-1"
            style={{
              left: `${spot.leftPct}%`,
              width: `${spot.widthPct}%`,
              backgroundColor: colour,
            }}
            title={turnTitle(turn)}>
            {spot.widthPct >= LABEL_MIN_PCT && turn.costUsd !== null ? (
              <span className="truncate text-[10px] font-medium tabular-nums text-background">
                {formatUsd(turn.costUsd)}
              </span>
            ) : null}
          </span>
        );
      })}

      {calls.map((call) => {
        const spot = place(call.startedAt, call.durationMs, from, span);
        if (spot === null) {
          return null;
        }
        // Coloured by the CALLEE, which is what the row is about: this lane's
        // own colour would say only "this node made a call", where the point is
        // which agent it handed the work to.
        const calleeColour = categoryToken(
          laneIndexOf(data, call.calleeNodeId),
        );
        const failed = call.status !== 'ok';
        return (
          <span
            key={`c-${call.startedAt}-${call.calleeNodeId ?? ''}-${call.durationMs}`}
            className={`absolute top-8 h-2.5 rounded-[3px] ${failed ? 'ring-1 ring-destructive' : ''}`}
            style={{
              left: `${spot.leftPct}%`,
              width: `${spot.widthPct}%`,
              backgroundColor: calleeColour,
              opacity: 0.85,
            }}
            title={`→ ${call.calleeNodeId ?? 'agent'} · ${call.mode} · ${call.status} · ${formatTurnDuration(call.durationMs)}`}
          />
        );
      })}

      {delegates.map((delegate) => {
        const spot = place(delegate.startedAt, delegate.durationMs, from, span);
        return spot === null ? null : (
          <span
            key={`d-${delegate.startedAt}-${delegate.durationMs}`}
            className="absolute top-12 h-1.5 rounded-[2px] bg-muted-foreground/50"
            style={{
              left: `${spot.leftPct}%`,
              width: `${spot.widthPct}%`,
            }}
            title={`sub-agent · ${formatTurnDuration(delegate.durationMs)}`}
          />
        );
      })}
    </div>
  );
}

