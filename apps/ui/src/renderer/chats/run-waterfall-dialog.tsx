/**
 * The run under a magnifying glass — the FULL view the sidebar card opens.
 *
 * The card in the panel answers "did this run go the way I think it did" at a
 * glance, in 280px. This answers the next question, which needs room: WHERE the
 * money went, in what order, how long each piece actually took — and what made
 * the run take as long as it did. Both read the same fold from the same route
 * (the daemon's, for the reason that route exists at all — the renderer holds
 * at most `HISTORY_PAGE` items) and share their placement maths
 * (`run-waterfall-geometry.ts`), so they cannot draw one run two ways.
 *
 * Everything on it reads ONE state — the stretch of the clock in view, the mark
 * selected, the agent in focus — so the gantt, the tables and the curve can
 * never describe three different slices of the run at once. The layout follows
 * what the trace tools converged on (Chrome's performance panel, Honeycomb,
 * Datadog, Jaeger): an overview to zoom with, lanes to select in, a panel that
 * keeps the selection, and tables that follow the zoom.
 *
 * A full-screen DIALOG rather than a nav destination, which is the house
 * pattern for exactly this shape: `artifact-dialog.tsx` opens a transcript card
 * into the same thing. A page of its own would need a run picker to be reachable
 * at all, and the run is already the one the sidebar has open.
 */

/** Rows in the most-expensive-turns table. */
const TOP_TURNS = 12;

/** Plot height for the cumulative-cost curve. */
const CURVE_HEIGHT = 200;

/** Where the critical-path switch remembers itself. */
const CRITICAL_PATH_KEY = 'geniro.waterfall.criticalPath';

/**
 * What Recharts hands the curve's tooltip.
 *
 * Typed here rather than imported, for `time-charts.tsx`'s stated reason: the
 * library's own generic is loose enough that it would not catch a renamed data
 * key, which is the mistake this shape exists to make impossible. `readonly`
 * because the content prop is checked contravariantly.
 */
interface SpendTooltipProps {
  active?: boolean;
  payload?: readonly { payload?: SpendPoint }[];
}

/** The point the curve's tooltip is over, or null when it is not showing. */
function hoveredPoint(props: SpendTooltipProps): SpendPoint | null {
  return props.active && props.payload?.length
    ? (props.payload[0]?.payload ?? null)
    : null;
}

/**
 * What each headline figure MEANS, with a worked example.
 *
 * REPORTED as "я не понимаю, что такое волклок… не понимаю Agent time и Waited
 * on you". A label names a figure; it does not explain one, and three of these
 * six are terms this app invented. The example is the load-bearing half — the
 * definitions are all one sentence, and it is the arithmetic between them that
 * a reader is actually asking about.
 */
const FIGURE_HELP: Record<string, { what: string; example: string }> = {
  'wall clock': {
    what: 'End to end, from the first thing this run recorded to the last. It keeps running while nobody is working — overnight, over lunch, and while the run waits on you.',
    example:
      'Started at 9:00, last row at 17:00 → 8h, even if the agents only worked forty minutes of it.',
  },
  'agent time': {
    what: 'How long the CLIs say they were actually working, summed over every turn. It does NOT count time parked on a question, and a CLI that reports no timing contributes nothing to it.',
    example:
      '27h 33m of work inside a 41h wall clock means about 13h went somewhere that was not an agent — mostly waiting on you.',
  },
  parallel: {
    what: 'Agent time divided by the wall clock: how many agents were working at once, on average. Above 1× the run was doing several things at the same time.',
    example:
      '21m of agent time inside a 9m wall clock → 2.3× — on average two or three agents were busy at any moment.',
  },
  'waited on you': {
    what: 'Time this run sat on a question or a permission card with nobody answering. It is the gap between wall clock and agent time that is yours rather than the machine’s.',
    example: 'An agent asked at 14:02 and you answered at 14:41 → 39m here.',
  },
  spent: {
    what: 'What the CLIs reported this run cost. A turn that reported no price is not counted rather than counted as free — cursor-agent prices nothing on its wire, so its work is billed through the polled account figure instead.',
    example:
      '“28 of 30 turns priced” under the figure means two turns did the work and never said what it cost.',
  },
  turns: {
    what: 'How many turns the agents took. One turn is one round of the agent working until it stops and hands back — it can hold hundreds of tool calls.',
    example:
      'You send one message, the agent reads twelve files, edits three and answers → 1 turn, 15 tools.',
  },
  tools: {
    what: 'How many tool calls the agents themselves made — reads, edits, shell commands, MCP calls. What their sub-agents called is counted apart, under the figure.',
    example:
      'An agent that greps a repo, opens nine files and runs the tests has already spent a dozen of these inside a single turn.',
  },
};

/** The `?` beside a figure's label, opening that figure's explanation. */
function FigureHelp({ label }: { label: string }): React.JSX.Element | null {
  const help = FIGURE_HELP[label];
  if (help === undefined) {
    return null;
  }
  return (
    <HoverPopover
      label={`What ${label} means`}
      panelLabel={`What ${label} means`}
      side="bottom"
      align="start"
      triggerClassName="rounded-full"
      panelClassName="w-80 p-3"
      trigger={
        <HelpCircle
          aria-hidden="true"
          className="size-3.5 shrink-0 opacity-60"
        />
      }>
      <p className="text-xs leading-relaxed text-popover-foreground">
        {help.what}
      </p>
      <p className="mt-2 text-xs leading-relaxed text-muted-foreground">
        <span className="font-medium text-foreground">For example: </span>
        {help.example}
      </p>
    </HoverPopover>
  );
}

export function RunWaterfallDialog({
  open,
  onClose,
  data,
  onJump,
}: {
  open: boolean;
  onClose: () => void;
  data: RunWaterfallDto;
  /**
   * Open a transcript row by seq — the detail panel's "Open in chat". The
   * dialog closes first, so the row lands in front of the reader.
   */
  onJump?: (seq: number) => void;
}): React.JSX.Element {
  const full = useMemo<ClockWindow>(() => {
    const from = Date.parse(data.from);
    const to = Date.parse(data.to);
    return { from, to: Math.max(from + 1, to) };
  }, [data]);
  const span = full.to - full.from;

  const [zoom, setZoom] = useState<ClockWindow | null>(null);
  const [selected, setSelected] = useState<WaterfallMark | null>(null);
  const [focus, setFocus] = useState<string | null | undefined>(undefined);
  const [critical, setCritical] = usePersistedFlag(CRITICAL_PATH_KEY, false);
  // Where focus lands as the view opens. Its first control is the `?` beside
  // `spent`, and focusing that opened its explanation over the insights before
  // anyone had read them; the gantt's toolbar is where a reader starts.
  const startRef = useRef<HTMLButtonElement>(null);

  // A fresh look every time it opens: a zoom or a selection left over from the
  // last visit would describe a moment the reader is no longer asking about.
  useEffect(() => {
    if (open) {
      setZoom(null);
      setSelected(null);
      setFocus(undefined);
    }
  }, [open]);

  // The run keeps growing while the dialog is open, so a zoom is held as the
  // stretch it named and clipped to the run each render, never stored clipped.
  const view = useMemo<ClockWindow>(() => {
    if (zoom === null) {
      return full;
    }
    const from = Math.max(full.from, zoom.from);
    const to = Math.min(full.to, zoom.to);
    return to - from < 1 ? full : { from, to };
  }, [zoom, full]);
  const zoomed = view.from > full.from || view.to < full.to;
  const zoomTo = useCallback((window: ClockWindow) => setZoom(window), []);

  // Escape lets go of a selection or a focus before it closes the dialog: the
  // dialog's own Escape handler stands down for a key already handled. On the
  // WINDOW's capture phase, which runs before the dialog's `document` listener
  // wherever the key lands — on `document` itself included.
  useEffect(() => {
    if (!open || (selected === null && focus === undefined)) {
      return;
    }
    const onKey = (event: KeyboardEvent): void => {
      if (event.key !== 'Escape' || event.defaultPrevented) {
        return;
      }
      event.preventDefault();
      if (selected !== null) {
        setSelected(null);
      } else {
        setFocus(undefined);
      }
    };
    window.addEventListener('keydown', onKey, true);
    return () => window.removeEventListener('keydown', onKey, true);
  }, [open, selected, focus]);

  const insights = useMemo(() => waterfallInsights(data), [data]);
  const spend = useMemo(
    () => cumulativeSpend(data.turns, full.from),
    [data, full.from],
  );
  const expensive = useMemo(
    () =>
      topTurns(
        data.turns.filter(
          (turn) =>
            (focus === undefined || turn.nodeId === focus) &&
            endOf(turn) >= view.from &&
            endOf(turn) <= view.to,
        ),
        TOP_TURNS,
      ),
    [data, focus, view],
  );

  const pick = (insight: Insight): void => {
    if (insight.target === null) {
      setCritical(!critical);
      setSelected(null);
      return;
    }
    setSelected(sameMark(selected, insight.target) ? null : insight.target);
  };

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Where the run went"
      initialFocus={startRef}
      className="h-[92vh] w-[min(96vw,84rem)] max-w-none">
      <div className="flex flex-col gap-5">
        <Headline data={data} span={span} />

        {insights.length === 0 ? null : (
          <Insights
            insights={insights}
            selected={selected}
            critical={critical}
            onPick={pick}
          />
        )}

        <div className="grid gap-5 lg:grid-cols-[minmax(0,1fr)_17rem]">
          <div className="flex min-w-0 flex-col gap-6">
            <Section title="Who worked when, and what it cost">
              <div className="flex flex-wrap items-center gap-2">
                <Button
                  ref={startRef}
                  size="sm"
                  variant={critical ? 'secondary' : 'ghost'}
                  aria-pressed={critical}
                  onClick={() => setCritical(!critical)}>
                  <Route aria-hidden="true" className="size-3.5" />
                  Critical path
                </Button>
                <Button
                  size="sm"
                  variant="ghost"
                  disabled={!zoomed}
                  onClick={() => setZoom(null)}>
                  Show the whole run
                </Button>
                {focus === undefined ? null : (
                  <Button
                    size="sm"
                    variant="ghost"
                    onClick={() => setFocus(undefined)}>
                    Every agent
                  </Button>
                )}
                <span className="ml-auto text-xs tabular-nums text-muted-foreground">
                  {zoomed
                    ? `${formatDuration(view.from - full.from)} – ${formatDuration(view.to - full.from)} of ${formatDuration(span)}`
                    : 'the whole run'}
                </span>
              </div>
              <WaterfallOverview
                data={data}
                full={full}
                window={view}
                onWindow={zoomTo}
              />
              <Gantt
                data={data}
                runFrom={full.from}
                window={view}
                selected={selected}
                onSelect={setSelected}
                focus={focus}
                onFocus={setFocus}
                critical={critical}
              />
              <Legend critical={critical} />
            </Section>

            <Section title="Where the time and money went">
              <Breakdown
                data={data}
                view={view}
                zoomed={zoomed}
                focus={focus}
                onFocus={setFocus}
              />
            </Section>

            <Section title="How the money added up">
              {spend.length === 0 ? (
                <p className="text-xs text-muted-foreground">
                  no turn on this run reported a price
                </p>
              ) : (
                <SpendCurve
                  points={spend}
                  span={span}
                  highlight={
                    zoomed
                      ? { from: view.from - full.from, to: view.to - full.from }
                      : null
                  }
                />
              )}
            </Section>

            <Section title="The most expensive turns">
              {expensive.length === 0 ? (
                <p className="text-xs text-muted-foreground">
                  {zoomed || focus !== undefined
                    ? 'no priced turn ended in what is shown'
                    : 'no turn on this run reported a price'}
                </p>
              ) : (
                <TopTurns
                  data={data}
                  turns={expensive}
                  selected={selected}
                  onSelect={setSelected}
                />
              )}
            </Section>

            {data.partialReason === null ? null : (
              <p className="text-xs text-muted-foreground">
                {data.partialReason}
              </p>
            )}
          </div>

          <aside className="min-w-0 rounded-xl border border-border bg-card p-4 lg:sticky lg:top-0 lg:self-start">
            <WaterfallDetail
              data={data}
              runFrom={full.from}
              selected={selected}
              onJump={
                onJump === undefined
                  ? undefined
                  : (seq) => {
                      onClose();
                      onJump(seq);
                    }
              }
              onZoom={zoomTo}
            />
          </aside>
        </div>
      </div>
    </Dialog>
  );
}

function Section({
  title,
  children,
}: {
  title: string;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <section className="flex flex-col gap-2">
      <h3 className="text-xs font-semibold tracking-wide text-muted-foreground uppercase">
        {title}
      </h3>
      {children}
    </section>
  );
}

/**
 * The run's headline figures, one ruled surface a person reads across.
 *
 * `wall clock`, `agent time` and `parallel` sit beside each other on purpose:
 * the gap between the first two IS the answer to "why did this take all
 * afternoon", and the third says it as a single number. Every figure is one
 * size — REPORTED as "сверху цифры разного размера" — and keeps its `?`,
 * because three of them are terms this app invented.
 */
function Headline({
  data,
  span,
}: {
  data: RunWaterfallDto;
  span: number;
}): React.JSX.Element {
  const tools = data.lanes.reduce((sum, lane) => sum + lane.toolCalls, 0);
  const delegateTools = data.lanes.reduce(
    (sum, lane) => sum + lane.delegateToolCalls,
    0,
  );
  // The LANES' own counts, summed — never `totals.turns`, which counts
  // `turn_complete` rows alone. A run the user stopped mid-turn writes none,
  // so the figure read `turns 0` directly above lanes saying `1 turn` and
  // `3 turns`: one screen, two answers. The lane figure is the daemon's
  // reconciled one (a turn that OPENED counts), so this is the same quantity
  // at run level rather than a second opinion.
  const turnsTaken = data.lanes.reduce((sum, lane) => sum + lane.turns, 0);
  const failed = data.calls.filter(callFailed).length;
  const parallel =
    data.totals.workedMs === null ? null : data.totals.workedMs / span;
  return (
    <StatGrid className="grid-cols-2 sm:grid-cols-4 xl:grid-cols-7">
      <StatCell
        label="spent"
        help={<FigureHelp label="spent" />}
        value={
          data.totals.costUsd === null
            ? NOT_MEASURED
            : markEstimate(
                formatUsd(data.totals.costUsd),
                data.totals.estimatedCostUsd,
              )
        }
        hint={costEstimateTitle(
          data.totals.costUsd,
          data.totals.estimatedCostUsd,
        )}
        footnote={
          data.totals.costedTurns === data.totals.turns
            ? undefined
            : `${data.totals.costedTurns} of ${data.totals.turns} turns priced`
        }
      />
      <StatCell
        label="wall clock"
        help={<FigureHelp label="wall clock" />}
        value={formatDuration(span)}
      />
      <StatCell
        label="agent time"
        help={<FigureHelp label="agent time" />}
        value={
          data.totals.workedMs === null
            ? NOT_MEASURED
            : formatDuration(data.totals.workedMs)
        }
      />
      <StatCell
        label="parallel"
        help={<FigureHelp label="parallel" />}
        value={parallel === null ? NOT_MEASURED : `${parallel.toFixed(1)}×`}
      />
      <StatCell
        label="waited on you"
        help={<FigureHelp label="waited on you" />}
        value={
          data.waitedOnUserMs === null
            ? NOT_MEASURED
            : formatDuration(data.waitedOnUserMs)
        }
        footnote={
          data.waits.length === 0
            ? undefined
            : `${data.waits.length} ${data.waits.length === 1 ? 'card' : 'cards'}`
        }
      />
      <StatCell
        label="turns"
        help={<FigureHelp label="turns" />}
        value={formatCount(turnsTaken)}
      />
      <StatCell
        label="tools"
        help={<FigureHelp label="tools" />}
        value={formatCount(tools)}
        hint={toolsTitle(tools, delegateTools)}
        footnote={
          [
            delegateTools === 0
              ? null
              : `+ ${formatCount(delegateTools)} ${BY_SUB_AGENTS}`,
            data.calls.length === 0
              ? null
              : `${data.calls.length} agent calls${failed === 0 ? '' : `, ${failed} failed`}`,
          ]
            .filter((part) => part !== null)
            .join(' · ') || undefined
        }
      />
    </StatGrid>
  );
}

/**
 * A share drawn as a bar in a TRACK rather than floating: without one a
 * 2%-wide stripe and a full-width one share no left edge to read against, so a
 * column of them looks ragged instead of ranked. The track is the rail; the bar
 * is the reading. One shape for every table on the view.
 */
function ShareBar({
  fraction,
  colour,
  className,
}: {
  fraction: number;
  /** A lane's or a series' colour; the primary when absent. */
  colour?: string;
  className?: string;
}): React.JSX.Element {
  return (
    <span
      aria-hidden="true"
      className={cn(
        'block h-1.5 w-full overflow-hidden rounded-full bg-muted',
        className,
      )}>
      <span
        className={cn(
          'block h-full rounded-full',
          colour === undefined && 'bg-primary',
        )}
        style={{
          width: `${Math.max(2, Math.min(1, fraction) * 100)}%`,
          backgroundColor: colour,
        }}
      />
    </span>
  );
}

/**
 * What stands out, as notes a reader can press — each lands on the mark that
 * shows it. A gantt shows everything at once and so says nothing first; these
 * say the few things a person opened the view to find.
 */
function Insights({
  insights,
  selected,
  critical,
  onPick,
}: {
  insights: readonly Insight[];
  selected: WaterfallMark | null;
  critical: boolean;
  onPick: (insight: Insight) => void;
}): React.JSX.Element {
  return (
    <ul
      aria-label="What stands out"
      data-slot="waterfall-insights"
      className="m-0 grid list-none gap-2 p-0 sm:grid-cols-2 xl:grid-cols-3">
      {insights.map((insight) => {
        const active =
          insight.target === null
            ? critical
            : sameMark(selected, insight.target);
        return (
          <li key={insight.id} className="min-w-0">
            <button
              type="button"
              aria-pressed={active}
              onClick={() => onPick(insight)}
              className={cn(
                'flex h-full w-full cursor-pointer items-start gap-2 rounded-lg border border-border bg-card px-3 py-2 text-left transition-colors hover:border-ring focus-visible:outline-2 focus-visible:outline-ring',
                active && 'border-ring bg-muted/40',
              )}>
              <span
                aria-hidden="true"
                className={cn(
                  'mt-1 size-2 shrink-0 rounded-[2px]',
                  insight.tone === 'danger' && 'bg-destructive',
                  insight.tone === 'warning' && 'bg-warning',
                  insight.tone === 'neutral' && 'bg-muted-foreground',
                )}
              />
              <span className="flex min-w-0 flex-col gap-0.5">
                <span className="text-xs font-medium text-foreground">
                  {insight.title}
                </span>
                <span className="text-[11px] leading-snug text-muted-foreground">
                  {insight.detail}
                </span>
              </span>
            </button>
          </li>
        );
      })}
    </ul>
  );
}

