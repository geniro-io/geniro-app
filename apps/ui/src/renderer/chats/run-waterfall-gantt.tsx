/**
 * The waterfall's lanes: one per agent, plus the waiting-on-you lane, on one
 * shared clock — and everything a reader can do to them.
 *
 * It answers the pointer three ways, each for a different question:
 * - HOVER reads a mark in passing (the panel follows the pointer).
 * - CLICK selects it, and the detail panel beside the gantt keeps it — a hover
 *   cannot be copied, pinned or compared. A selected call also draws arrows to
 *   the work that answered it, which is the "who waited on whom" no colour can
 *   say on its own.
 * - Clicking a lane's NAME focuses that agent: the others fade and the tables
 *   below follow.
 *
 * It draws whatever WINDOW of the run's clock the view is zoomed to; the
 * overview strip above it is how a reader picks one.
 */

/**
 * The label column's width.
 *
 * Wide enough for a node name AND its price on one row, which is what the
 * column is sized by: the name truncates, the money never does, and the line
 * under them has to fit without wrapping.
 *
 * Sized against the LONGEST real meta line rather than a round number:
 * `cursor-agent · 0 turns · 130 tools` is 34 characters at 11px, and at 208px
 * it truncated to `130 to…` on a real run.
 */
const LABEL_WIDTH = 236;

/** How many marks the time axis carries. Six is readable at every width. */
const AXIS_TICKS = 6;

/** A bar narrower than this has no room for its own price, so it carries none. */
const LABEL_MIN_PCT = 5;

/** A turn costing this share of the run says so on its own bar. */
const HOT_SHARE = 0.2;

/**
 * A lane track's vertical anatomy, in pixels: the turns' row on top, then one
 * row per set of calls that overlap in time, then the sub-agents' rows. Each is
 * a number rather than a class because how many call and sub-agent rows a lane
 * needs is only known from its data.
 */
const CALL_TOP = 32;
const CALL_HEIGHT = 16;
const CALL_STEP = 20;
const DELEGATE_GAP = 2;
const DELEGATE_HEIGHT = 12;
const DELEGATE_STEP = 10;
const TRACK_MIN_HEIGHT = 64;
const TRACK_PAD_BOTTOM = 4;

/**
 * What the pointer is currently over on the waterfall, and where.
 *
 * The marks used to carry a native `title`, and that failed twice over: the
 * browser shows one only after about a second and draws it as an OS tooltip
 * nothing here can style — and the tool-density strip that then ran along each
 * lane's floor carried none at all. REPORTED as "сейчас ничего не показывается,
 * непонятно, что за полоски такие".
 */
interface MarkTip {
  clientX: number;
  clientY: number;
  title: string;
  rows: TooltipRow[];
}

/** How far the panel sits from the pointer, and off the viewport's edges. */
const TIP_OFFSET = 16;

/** Assumed panel box, used to keep it on screen without measuring it. */
const TIP_BOX = { width: 280, height: 160 };

/**
 * The hover panel, following the pointer.
 *
 * `fixed` and `pointer-events-none`: it has to escape the gantt's own
 * `overflow-hidden`, and a panel that could take the pointer would flicker
 * against the mark it is describing. It flips to the other side of the cursor
 * near an edge rather than being clamped, so it never covers what is hovered.
 */
function HoverTip({ tip }: { tip: MarkTip }): React.JSX.Element {
  const flipX = tip.clientX + TIP_OFFSET + TIP_BOX.width > window.innerWidth;
  const flipY = tip.clientY + TIP_OFFSET + TIP_BOX.height > window.innerHeight;
  return (
    <div
      className="pointer-events-none fixed z-50"
      style={{
        left: flipX ? undefined : tip.clientX + TIP_OFFSET,
        right: flipX ? window.innerWidth - tip.clientX + TIP_OFFSET : undefined,
        top: flipY ? undefined : tip.clientY + TIP_OFFSET,
        bottom: flipY
          ? window.innerHeight - tip.clientY + TIP_OFFSET
          : undefined,
      }}>
      <ChartTooltip title={tip.title} rows={tip.rows} />
    </div>
  );
}

/** A figure that was never measured, said as such rather than shown as zero. */
export function measuredRow(label: string, value: string | null): TooltipRow {
  return { label, value: value ?? '', unmeasured: value === null };
}

/**
 * A cost row: the figure with its `≈` when geniro priced any of it, and the
 * note saying which part, or not-measured when no cost was reported.
 */
function costRow(
  label: string,
  costUsd: number | null,
  estimatedUsd: number | null,
): TooltipRow {
  return {
    ...measuredRow(
      label,
      costUsd === null ? null : markEstimate(formatUsd(costUsd), estimatedUsd),
    ),
    note: costEstimateTitle(costUsd, estimatedUsd),
  };
}

/**
 * A lane's React key. The chat's own lane is keyed null, and spelling that as
 * a word collided with a node of the same name.
 */
function laneKey(nodeId: string | null): string {
  return nodeId === null ? '\u0000chat' : `node:${nodeId}`;
}

/** The DOM key of a mark, which the arrows find their ends by. */
function markKey(mark: WaterfallMark): string {
  return `${mark.kind}-${mark.index}`;
}

/** A list's entries with their index in the wire, so a click can name them. */
interface Indexed<T> {
  item: T;
  index: number;
}

function byLane<T>(
  list: readonly T[],
  laneOf: (item: T) => string | null,
): Map<string | null, Indexed<T>[]> {
  const out = new Map<string | null, Indexed<T>[]>();
  list.forEach((item, index) => {
    const key = laneOf(item);
    const own = out.get(key);
    if (own === undefined) {
      out.set(key, [{ item, index }]);
    } else {
      own.push({ item, index });
    }
  });
  return out;
}

export interface GanttProps {
  data: RunWaterfallDto;
  /** The run's first row — what every "at" on the gantt is measured from. */
  runFrom: number;
  window: ClockWindow;
  selected: WaterfallMark | null;
  onSelect: (mark: WaterfallMark | null) => void;
  focus: string | null | undefined;
  onFocus: (nodeId: string | null | undefined) => void;
  /** Light the critical path and fade everything off it. */
  critical: boolean;
}

export function Gantt({
  data,
  runFrom,
  window: view,
  selected,
  onSelect,
  focus,
  onFocus,
  critical,
}: GanttProps): React.JSX.Element {
  const span = Math.max(1, view.to - view.from);
  const ticks = useMemo(
    () =>
      Array.from({ length: AXIS_TICKS }, (_, index) => ({
        pct: (index / (AXIS_TICKS - 1)) * 100,
        // The precise clock, not the rounded one: zoomed into four minutes
        // the ticks sit 48 seconds apart, and whole minutes printed `4m`
        // twice in a row.
        label: formatTurnDuration(
          view.from - runFrom + (span * index) / (AXIS_TICKS - 1),
        ),
      })),
    [view.from, runFrom, span],
  );
  const lanes = useMemo(
    () => ({
      turns: byLane(data.turns, (turn) => turn.nodeId),
      calls: byLane(data.calls, (call) => call.callerNodeId),
      served: byLane(data.calls, (call) => call.calleeNodeId),
      delegates: byLane(data.delegates, (delegate) => delegate.nodeId),
    }),
    [data],
  );

  // What the pointer is over, and where it sits across every lane. The second
  // is what makes a gantt readable at all: a mark 40cm to the right of its own
  // lane label is otherwise read against nothing.
  const [tip, setTip] = useState<MarkTip | null>(null);
  const [cursorPct, setCursorPct] = useState<number | null>(null);
  const clearHover = useCallback(() => {
    setTip(null);
    setCursorPct(null);
  }, []);
  const gridRef = useRef<HTMLDivElement>(null);
  const atOf = (pct: number | null): string =>
    formatTurnDuration(view.from - runFrom + ((pct ?? 0) / 100) * span);

  return (
    <div
      className="relative overflow-hidden rounded-xl border border-border bg-card"
      onMouseLeave={clearHover}>
      {tip === null ? null : <HoverTip tip={tip} />}
      <div
        ref={gridRef}
        className="relative grid"
        style={{ gridTemplateColumns: `${LABEL_WIDTH}px 1fr` }}>
        {/*
          The axis: elapsed time, so a reader never has to subtract two clocks.

          The END ticks are anchored rather than centred. A centred label at
          100% hangs half its width past the card, and `overflow-hidden` then
          wraps it — which is what put a stray "41" over "18" in the corner of
          a real run. The first tick has the mirror problem at 0%.
        */}
        <div className="border-b border-border" />
        <div className="relative h-6 overflow-hidden border-b border-l border-border">
          {ticks.map((tick, index) => (
            <span
              key={tick.pct}
              className={cn(
                'absolute top-1 text-[10px] whitespace-nowrap tabular-nums text-muted-foreground',
                index === 0 && 'translate-x-1',
                index === ticks.length - 1 &&
                  '-translate-x-[calc(100%+0.25rem)]',
                index > 0 && index < ticks.length - 1 && '-translate-x-1/2',
              )}
              style={{ left: `${tick.pct}%` }}>
              {tick.label}
            </span>
          ))}
        </div>

        {data.lanes.map((lane, index) => {
          const faded = focus !== undefined && focus !== lane.nodeId;
          return (
            <Fragment key={laneKey(lane.nodeId)}>
              <LaneLabel
                lane={lane}
                index={index}
                focused={focus === lane.nodeId}
                faded={faded}
                onFocus={() =>
                  onFocus(focus === lane.nodeId ? undefined : lane.nodeId)
                }
              />
              <LaneTrack
                data={data}
                lane={lane}
                index={index}
                turns={lanes.turns.get(lane.nodeId) ?? []}
                calls={lanes.calls.get(lane.nodeId) ?? []}
                served={lanes.served.get(lane.nodeId) ?? []}
                delegates={lanes.delegates.get(lane.nodeId) ?? []}
                runFrom={runFrom}
                view={view}
                faded={faded}
                critical={critical}
                selected={selected}
                onSelect={onSelect}
                cursorPct={cursorPct}
                onHover={setTip}
                onMove={setCursorPct}
                atOf={atOf}
              />
            </Fragment>
          );
        })}

        {data.waits.length === 0 ? null : (
          <WaitLane
            data={data}
            runFrom={runFrom}
            view={view}
            critical={critical}
            faded={focus !== undefined}
            selected={selected}
            onSelect={onSelect}
            cursorPct={cursorPct}
            onHover={setTip}
            onMove={setCursorPct}
          />
        )}
        <CallArrows
          data={data}
          gridRef={gridRef}
          selected={selected}
          view={view}
        />
      </div>
    </div>
  );
}

function LaneLabel({
  lane,
  index,
  focused,
  faded,
  onFocus,
}: {
  lane: RunWaterfallLane;
  index: number;
  focused: boolean;
  faded: boolean;
  onFocus: () => void;
}): React.JSX.Element {
  // Name, then kind and turns, then the tools — one job per line. At this
  // width a wrapped figure stacks above its unit, so every line truncates
  // instead: a shortened node name is readable where a reflowed figure is not.
  // The money ends the name row, a right-aligned column across lanes.
  //
  // A BUTTON, because pressing it focuses the agent: the other lanes fade and
  // the tables under the gantt narrow to this one.
  return (
    <button
      type="button"
      data-slot="waterfall-lane-label"
      aria-pressed={focused}
      title={focused ? 'Show every agent' : 'Focus this agent'}
      onClick={onFocus}
      className={cn(
        'flex min-w-0 cursor-pointer flex-col justify-center gap-1 border-t border-border px-3 py-2 text-left transition-opacity hover:bg-muted/40 focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-ring',
        focused && 'bg-muted/50',
        faded && 'opacity-40',
      )}>
      <span className="flex min-w-0 items-baseline gap-1.5">
        <span
          aria-hidden="true"
          className="size-2 shrink-0 translate-y-px rounded-[2px]"
          style={{ backgroundColor: categoryToken(index) }}
        />
        <span className="truncate text-sm font-medium text-foreground">
          {lane.nodeId ?? 'agent'}
        </span>
        <span
          className="ml-auto shrink-0 text-sm tabular-nums text-foreground"
          title={costEstimateTitle(lane.costUsd, lane.estimatedCostUsd)}>
          {lane.costUsd === null
            ? NOT_MEASURED
            : markEstimate(formatUsd(lane.costUsd), lane.estimatedCostUsd)}
        </span>
      </span>
      <span className="truncate pl-3.5 text-[11px] whitespace-nowrap text-muted-foreground">
        {lane.agentKind ?? NOT_MEASURED} · {lane.turns}{' '}
        {lane.turns === 1 ? 'turn' : 'turns'}
      </span>
      {/* Its own line, so the label width never cuts the tool split. */}
      <span
        className="truncate pl-3.5 text-[11px] whitespace-nowrap text-muted-foreground"
        title={toolsTitle(lane.toolCalls, lane.delegateToolCalls)}>
        {toolsCaption(lane.toolCalls, lane.delegateToolCalls)}
      </span>
    </button>
  );
}

/** Where the pointer is inside `box`, as a percentage of its width. */
function pctWithin(box: Element | null, clientX: number): number | null {
  if (box === null) {
    return null;
  }
  const rect = box.getBoundingClientRect();
  if (rect.width === 0) {
    return null;
  }
  return Math.max(0, Math.min(100, ((clientX - rect.left) / rect.width) * 100));
}

/**
 * The one vertical line every lane draws at the pointer's x.
 *
 * This is what makes the gantt readable rather than decorative: a mark half a
 * metre right of its own lane label is otherwise read against nothing, and
 * "was the engineer working while the manager waited" is exactly the question
 * the picture exists to answer.
 */
function Crosshair({ pct }: { pct: number | null }): React.JSX.Element | null {
  return pct === null ? null : (
    <span
      aria-hidden="true"
      className="pointer-events-none absolute inset-y-0 z-10 w-px bg-foreground/25"
      style={{ left: `${pct}%` }}
    />
  );
}

/** A mark's left and width, as the inline style every mark takes. */
function spot(placed: Placed): React.CSSProperties {
  return { left: `${placed.leftPct}%`, width: `${placed.widthPct}%` };
}

/**
 * The classes a selectable mark takes on top of its own: a ring while it is
 * selected, and faded while the critical path is lit and it is off it.
 */
function markState(selected: boolean, offPath: boolean): string {
  return cn(
    'cursor-pointer transition-opacity',
    selected && 'z-20 ring-2 ring-foreground ring-offset-1 ring-offset-card',
    offPath && 'opacity-25',
  );
}

/**
 * One lane's spans, stacked by what they mean rather than overlaid.
 *
 * Turns sit on top because they are the work; the calls this node MADE and the
 * delegates it launched are rows under them. Overlaying them was tried on the
 * prototype and made a busy lane unreadable — a call and the turn that made it
 * are the same stretch of time, so drawn on one line the wider one simply hides
 * the other.
 *
 * A call is drawn OUTLINED and NAMED (`→ researcher`), where it used to be a
 * filled bar in the callee's colour: under a manager's own turns that read as
 * a second, unexplained turn row — REPORTED as "вторая маленькая находится
 * снизу. Я не понимаю, для чего она нужна". The tool-density strip that ran
 * along the floor went for the same reason; each turn's hover carries its own
 * tool count instead.
 *
 * A call that HELD its caller still is also drawn on the caller's own turn row,
 * hatched: the part of the turn that was waiting rather than working. Without
 * it a manager's turn read as twenty minutes of work when nineteen of them
 * were spent waiting on an engineer.
 */
function LaneTrack({
  data,
  lane,
  index,
  turns,
  calls,
  served,
  delegates,
  runFrom,
  view,
  faded,
  critical,
  selected,
  onSelect,
  cursorPct,
  onHover,
  onMove,
  atOf,
}: {
  data: RunWaterfallDto;
  lane: RunWaterfallLane;
  index: number;
  turns: readonly Indexed<RunWaterfallTurn>[];
  calls: readonly Indexed<RunWaterfallCall>[];
  served: readonly Indexed<RunWaterfallCall>[];
  delegates: readonly Indexed<RunWaterfallDelegate>[];
  runFrom: number;
  view: ClockWindow;
  faded: boolean;
  critical: boolean;
  selected: WaterfallMark | null;
  onSelect: (mark: WaterfallMark | null) => void;
  cursorPct: number | null;
  onHover: (tip: MarkTip | null) => void;
  onMove: (pct: number | null) => void;
  atOf: (pct: number | null) => string;
}): React.JSX.Element {
  const colour = categoryToken(index);
  const laneName = lane.nodeId ?? 'agent';
  const path = data.criticalPath;
  const total = data.totals.costUsd;

  // Calls that share time get a row each, and the sub-agents' rows start under
  // the last of them. A manager fanning out to three agents at once otherwise
  // drew three outlines and three names over one another on a single line.
  const callSpots = calls.map(({ item }) =>
    placeIn(item.startedAt, item.durationMs, view),
  );
  const callRows = stackRows(callSpots);
  const delegateSpots = delegates.map(({ item }) =>
    placeIn(item.startedAt, item.durationMs, view),
  );
  const delegateRows = stackRows(delegateSpots);
  const delegateTop =
    CALL_TOP + Math.max(1, callRows.count) * CALL_STEP - DELEGATE_GAP;
  const lowestMark =
    delegateRows.count > 0
      ? delegateTop + (delegateRows.count - 1) * DELEGATE_STEP + DELEGATE_HEIGHT
      : CALL_TOP + (callRows.count - 1) * CALL_STEP + CALL_HEIGHT;
  const trackHeight = Math.max(TRACK_MIN_HEIGHT, lowestMark + TRACK_PAD_BOTTOM);
  const onPath = (start: number, end: number): boolean =>
    onCriticalPath(path, 'work', lane.nodeId, start, end);

  /**
   * Every mark answers the pointer the same way.
   *
   * `stopPropagation` is what makes the layering work: the track itself sets a
   * fallback tip on move, and without it that fallback would overwrite the
   * mark's own on the very next event, since `mousemove` bubbles.
   */
  const marked =
    (tip: Omit<MarkTip, 'clientX' | 'clientY'>) =>
    (event: React.MouseEvent<HTMLElement>): void => {
      event.stopPropagation();
      onMove(
        pctWithin(
          event.currentTarget.closest('[data-lane-track]'),
          event.clientX,
        ),
      );
      onHover({ ...tip, clientX: event.clientX, clientY: event.clientY });
    };
  /** A click selects the mark, and a second click on it lets it go. */
  const select =
    (mark: WaterfallMark) =>
    (event: React.MouseEvent<HTMLElement>): void => {
      event.stopPropagation();
      onSelect(sameMark(selected, mark) ? null : mark);
    };

  return (
    <div
      data-lane-track=""
      className={cn(
        'relative border-t border-l border-border transition-opacity',
        faded && 'opacity-40',
      )}
      style={{ minHeight: trackHeight }}
      onClick={() => onSelect(null)}
      onMouseMove={(event) => {
        const pct = pctWithin(event.currentTarget, event.clientX);
        onMove(pct);
        // The FALLBACK reading: hovering anywhere between the marks says which
        // agent this row is and where on the run's clock the pointer sits.
        onHover({
          clientX: event.clientX,
          clientY: event.clientY,
          title: laneName,
          rows: [
            { label: 'agent', value: lane.agentKind ?? '—' },
            { label: 'at', value: atOf(pct) },
            costRow('spent', lane.costUsd, lane.estimatedCostUsd),
          ],
        });
      }}>
      <Crosshair pct={cursorPct} />

      {delegates.map(({ item: delegate, index: at }, row) => {
        const placed = delegateSpots[row] ?? null;
        const mark: WaterfallMark = { kind: 'delegate', index: at };
        return placed === null ? null : (
          <button
            type="button"
            key={`d-${at}`}
            data-slot="waterfall-delegate"
            data-mark={markKey(mark)}
            aria-label={`a sub-agent ${laneName} launched`}
            className={cn(
              'absolute flex items-center rounded-[2px]',
              markState(sameMark(selected, mark), critical),
            )}
            style={{
              ...spot(placed),
              top: delegateTop + (delegateRows.rows[row] ?? 0) * DELEGATE_STEP,
              height: DELEGATE_HEIGHT,
            }}
            onClick={select(mark)}
            onMouseMove={marked({
              title: 'a sub-agent',
              rows: [
                { label: 'launched by', value: laneName },
                {
                  label: 'ran for',
                  value: formatTurnDuration(delegate.durationMs),
                },
                {
                  label: 'at',
                  value: formatTurnDuration(
                    Date.parse(delegate.startedAt) - runFrom,
                  ),
                },
              ],
            })}>
            <span
              aria-hidden="true"
              className="h-1.5 w-full rounded-[2px] bg-muted-foreground/50"
            />
          </button>
        );
      })}

      {calls.map(({ item: call, index: at }, row) => {
        const placed = callSpots[row] ?? null;
        if (placed === null) {
          return null;
        }
        const mark: WaterfallMark = { kind: 'call', index: at };
        // Coloured by the CALLEE, which is what the row is about: this lane's
        // own colour would say only "this node made a call", where the point is
        // which agent it handed the work to.
        const calleeColour = categoryToken(
          laneIndexOf(data, call.calleeNodeId),
        );
        const callee = call.calleeNodeId ?? 'agent';
        const failed = callFailed(call);
        return (
          <button
            type="button"
            key={`c-${at}`}
            data-slot="waterfall-call"
            data-mark={markKey(mark)}
            aria-label={`${laneName} called ${callee}`}
            className={cn(
              'absolute flex items-center rounded-[3px]',
              markState(sameMark(selected, mark), critical),
            )}
            style={{
              ...spot(placed),
              top: CALL_TOP + (callRows.rows[row] ?? 0) * CALL_STEP,
              height: CALL_HEIGHT,
            }}
            onClick={select(mark)}
            onMouseMove={marked({
              title: `${laneName} called ${callee}`,
              rows: [
                // Both are nullable on the wire — a call recorded by an older
                // build names neither — so neither is asserted as a word here.
                { label: 'mode', value: call.mode ?? '—', color: calleeColour },
                {
                  label: 'outcome',
                  value: call.running ? 'still running' : (call.status ?? '—'),
                },
                {
                  label: call.running ? 'so far' : 'took',
                  value: formatTurnDuration(call.durationMs),
                },
                {
                  label: 'at',
                  value: formatTurnDuration(
                    Date.parse(call.startedAt) - runFrom,
                  ),
                },
              ],
            })}>
            {/*
              Outlined with a faint wash in the CALLEE's colour, never filled:
              a filled bar under this lane's turns reads as a turn of its own.
              The name inside says the rest, wherever the bar has room for it.
            */}
            <span
              className={cn(
                'relative flex h-full w-full items-center overflow-hidden rounded-[3px] border px-1',
                failed && 'border-destructive',
                call.running && TURN_OUTCOME_CLASS.running,
              )}
              style={failed ? undefined : { borderColor: calleeColour }}>
              <span
                aria-hidden="true"
                className="absolute inset-0 opacity-20"
                style={{ backgroundColor: calleeColour }}
              />
              {placed.widthPct >= LABEL_MIN_PCT ? (
                <span className="relative truncate text-[10px] leading-none font-medium text-foreground">
                  → {callee}
                </span>
              ) : null}
            </span>
          </button>
        );
      })}

      {served.map(({ item: call, index: at }) => {
        const placed = placeIn(call.startedAt, call.durationMs, view);
        if (placed === null) {
          return null;
        }
        const callerColour = categoryToken(
          laneIndexOf(data, call.callerNodeId),
        );
        return (
          <span
            key={`s-${at}`}
            // Drawn OUTLINED where a turn is filled: this lane did the work,
            // but the stretch is its caller's account of it, not its own
            // reported turn. Same row as the turns, so on a callee whose CLI
            // reports no timing the two coincide and the lane reads as one
            // span rather than two.
            className={cn(
              'absolute top-2 flex h-5 items-center transition-opacity',
              critical && 'opacity-25',
            )}
            style={spot(placed)}
            onMouseMove={marked({
              title: `${laneName} · working for ${call.callerNodeId ?? 'agent'}`,
              rows: [
                { label: 'mode', value: call.mode ?? '—', color: callerColour },
                { label: 'outcome', value: call.status ?? '—' },
                { label: 'took', value: formatTurnDuration(call.durationMs) },
                {
                  label: 'at',
                  value: formatTurnDuration(
                    Date.parse(call.startedAt) - runFrom,
                  ),
                },
              ],
            })}>
            <span
              aria-hidden="true"
              className="h-full w-full rounded-[4px] border border-dashed"
              style={{ borderColor: colour }}
            />
          </span>
        );
      })}

      {turns.map(({ item: turn, index: at }) => {
        const placed = placeIn(turn.startedAt, turn.durationMs, view);
        if (placed === null) {
          return null;
        }
        const mark: WaterfallMark = { kind: 'turn', index: at };
        const start = Date.parse(turn.startedAt);
        const fill = turnContextFill(turn);
        const share =
          total === null || total <= 0 || turn.costUsd === null
            ? null
            : turn.costUsd / total;
        const wide = placed.widthPct >= LABEL_MIN_PCT;
        return (
          <button
            type="button"
            key={`t-${at}`}
            data-slot="waterfall-turn"
            data-mark={markKey(mark)}
            data-outcome={turn.outcome}
            aria-label={turnLabel(laneName, turn)}
            className={cn(
              'absolute top-2 flex h-5 items-center overflow-hidden rounded-[4px] px-1',
              TURN_OUTCOME_CLASS[turn.outcome],
              markState(
                sameMark(selected, mark),
                critical && !onPath(start, start + turn.durationMs),
              ),
            )}
            style={{ ...spot(placed), backgroundColor: colour }}
            onClick={select(mark)}
            onMouseMove={marked({
              title: turnTipTitle(laneName, turn),
              rows: turnRows(turn, runFrom),
            })}>
            {wide && turn.costUsd !== null ? (
              <span className="truncate text-[10px] font-medium tabular-nums text-background">
                {markEstimate(formatUsd(turn.costUsd), turn.estimatedCostUsd)}
                {share !== null && share >= HOT_SHARE
                  ? ` · ${Math.round(share * 100)}%`
                  : ''}
              </span>
            ) : null}
            {/*
              How full the context was after the turn, as a stripe along the
              bar's floor — red once it is close to the window. A reader can
              see a lane filling up without opening a single turn.
            */}
            {fill === null ? null : (
              <span
                aria-hidden="true"
                data-slot="waterfall-context"
                className={cn(
                  'absolute bottom-0 left-0 h-[3px]',
                  fill >= CONTEXT_PRESSURE
                    ? 'bg-destructive'
                    : 'bg-background/50',
                )}
                style={{ width: `${fill * 100}%` }}
              />
            )}
          </button>
        );
      })}

      {calls.map(({ item: call, index: at }) => {
        if (!blocksCaller(call)) {
          return null;
        }
        const placed = placeIn(call.startedAt, call.durationMs, view);
        if (placed === null) {
          return null;
        }
        const mark: WaterfallMark = { kind: 'blocked', index: at };
        const callee = call.calleeNodeId ?? 'agent';
        return (
          <button
            type="button"
            key={`b-${at}`}
            data-slot="waterfall-blocked"
            data-mark={markKey(mark)}
            aria-label={`${laneName} waiting on ${callee}`}
            className={cn(
              // Stripes over whatever is beneath: on the caller's turn the
              // turn's colour shows through them, so the stretch reads as
              // part of the turn that was spent waiting rather than working.
              'absolute top-2 flex h-5 items-center overflow-hidden rounded-[4px] bg-[repeating-linear-gradient(135deg,var(--color-card)_0_3px,transparent_3px_7px)] px-1 text-[10px] font-medium text-foreground ring-1 ring-muted-foreground/60 ring-inset',
              markState(sameMark(selected, mark), critical),
            )}
            style={spot(placed)}
            onClick={select(mark)}
            onMouseMove={marked({
              title: `${laneName} · waiting on ${callee}`,
              rows: [
                {
                  label: call.running ? 'so far' : 'held still for',
                  value: formatTurnDuration(call.durationMs),
                },
                {
                  label: 'at',
                  value: formatTurnDuration(
                    Date.parse(call.startedAt) - runFrom,
                  ),
                },
              ],
            })}>
            {placed.widthPct >= LABEL_MIN_PCT * 2 ? (
              <span className="truncate rounded-[3px] bg-card/80 px-1 leading-4">
                waiting on {callee}
              </span>
            ) : null}
          </button>
        );
      })}

      {critical ? (
        <PathUnderline
          path={path}
          kind="work"
          nodeId={lane.nodeId}
          view={view}
        />
      ) : null}
    </div>
  );
}

/**
 * The critical path, drawn as a line under each stretch of it on this lane.
 *
 * Under the turn row rather than as a ring around the turn: a stretch of the
 * path is often only PART of a turn (the work after a call returned), and a
 * ring around the whole bar would claim the rest of it too.
 */
function PathUnderline({
  path,
  kind,
  nodeId,
  view,
}: {
  path: RunWaterfallDto['criticalPath'];
  kind: 'work' | 'waiting_on_user';
  nodeId: string | null;
  view: ClockWindow;
}): React.JSX.Element {
  return (
    <>
      {path.map((segment, index) => {
        if (
          segment.kind !== kind ||
          (kind === 'work' && segment.nodeId !== nodeId)
        ) {
          return null;
        }
        const placed = placeIn(segment.startedAt, segment.durationMs, view);
        return placed === null ? null : (
          <span
            key={index}
            aria-hidden="true"
            data-slot="waterfall-critical"
            className="pointer-events-none absolute top-[30px] h-[3px] rounded-full bg-primary"
            style={spot(placed)}
          />
        );
      })}
    </>
  );
}

