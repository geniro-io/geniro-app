/**
 * Two arrows for the selected call: from the call to the first turn that
 * answered it, and back from the last one to the moment the call returned.
 *
 * Measured off the DOM after layout rather than computed from percentages,
 * because the lanes' heights depend on how many call rows each one stacks —
 * which only the browser knows once it has laid them out.
 */
function CallArrows({
  data,
  gridRef,
  selected,
  view,
}: {
  data: RunWaterfallDto;
  gridRef: React.RefObject<HTMLDivElement | null>;
  selected: WaterfallMark | null;
  view: ClockWindow;
}): React.JSX.Element | null {
  // Bumped whenever the grid changes size: the arrows are pixels measured
  // off bars placed in percentages, so a window resize moves the bars and
  // leaves the arrows pointing at where they used to be.
  const [measure, setMeasure] = useState(0);
  useLayoutEffect(() => {
    const grid = gridRef.current;
    if (grid === null || typeof ResizeObserver === 'undefined') {
      return;
    }
    const observer = new ResizeObserver(() => setMeasure((n) => n + 1));
    observer.observe(grid);
    return () => observer.disconnect();
  }, [gridRef]);
  const [paths, setPaths] = useState<{
    out: string;
    back: string;
    colour: string;
  } | null>(null);
  useLayoutEffect(() => {
    const grid = gridRef.current;
    const call =
      selected !== null &&
      (selected.kind === 'call' || selected.kind === 'blocked')
        ? data.calls[selected.index]
        : undefined;
    if (grid === null || call === undefined) {
      setPaths(null);
      return;
    }
    const from = Date.parse(call.startedAt);
    const to = from + call.durationMs;
    const answering = data.turns
      .map((turn, index) => ({ turn, index }))
      .filter(
        ({ turn }) =>
          turn.nodeId === call.calleeNodeId &&
          Date.parse(turn.startedAt) < to &&
          endOf(turn) > from,
      );
    const callMark = grid.querySelector(
      `[data-mark="${selected?.kind}-${selected?.index}"]`,
    );
    const first = answering[0];
    const last = answering[answering.length - 1];
    const firstMark =
      first === undefined
        ? null
        : grid.querySelector(`[data-mark="turn-${first.index}"]`);
    const lastMark =
      last === undefined
        ? null
        : grid.querySelector(`[data-mark="turn-${last.index}"]`);
    if (callMark === null || firstMark === null || lastMark === null) {
      setPaths(null);
      return;
    }
    const box = grid.getBoundingClientRect();
    const a = callMark.getBoundingClientRect();
    const f = firstMark.getBoundingClientRect();
    const z = lastMark.getBoundingClientRect();
    const curve = (x1: number, y1: number, x2: number, y2: number): string => {
      const mid = (y1 + y2) / 2;
      return `M${x1},${y1} C${x1},${mid} ${x2},${mid} ${x2},${y2}`;
    };
    const down = f.top > a.bottom;
    setPaths({
      out: curve(
        a.left - box.left + 4,
        (down ? a.bottom : a.top) - box.top,
        f.left - box.left + 4,
        (down ? f.top : f.bottom) - box.top,
      ),
      back: curve(
        z.right - box.left - 4,
        (down ? z.top : z.bottom) - box.top,
        a.right - box.left - 4,
        (down ? a.bottom : a.top) - box.top,
      ),
      colour: categoryToken(laneIndexOf(data, call.calleeNodeId)),
    });
  }, [data, gridRef, selected, view, measure]);

  if (paths === null) {
    return null;
  }
  return (
    <svg
      aria-hidden="true"
      data-slot="waterfall-arrows"
      className="pointer-events-none absolute inset-0 z-30 size-full overflow-visible">
      <defs>
        <marker
          id="waterfall-arrow-head"
          viewBox="0 0 8 8"
          refX="7"
          refY="4"
          markerWidth="7"
          markerHeight="7"
          orient="auto">
          <path d="M0,0 L8,4 L0,8 z" fill={paths.colour} />
        </marker>
      </defs>
      <path
        d={paths.out}
        fill="none"
        stroke={paths.colour}
        strokeWidth={1.5}
        markerEnd="url(#waterfall-arrow-head)"
      />
      <path
        d={paths.back}
        fill="none"
        stroke={paths.colour}
        strokeWidth={1.5}
        strokeDasharray="4 3"
        markerEnd="url(#waterfall-arrow-head)"
      />
    </svg>
  );
}

/** A turn mark's accessible name: its lane, its cost, and whose price that is. */
function turnLabel(laneName: string, turn: RunWaterfallTurn): string {
  if (turn.costUsd === null) {
    return `${laneName} turn`;
  }
  const note = costEstimateNote(turn.costUsd, turn.estimatedCostUsd);
  return `${laneName} turn, ${markEstimate(formatUsd(turn.costUsd), turn.estimatedCostUsd)}${note === null ? '' : ` (${note})`}`;
}

/**
 * Everything the CLI said about one turn, as rows rather than one long line.
 *
 * `turnTitle` still composes the SENTENCE the 280px sidebar card hovers with —
 * one line is all that fits there. Here there is room for a panel, and the
 * figures the daemon now lifts off claude's result line (`ttft`, the wait
 * before the first request, how many model calls a turn took) are the ones a
 * reader opened this view for.
 */
export function turnRows(
  turn: RunWaterfallTurn,
  runFrom: number,
): TooltipRow[] {
  const rows: TooltipRow[] = [
    costRow('cost', turn.costUsd, turn.estimatedCostUsd),
    // Which models that cost went to — the sub-agents' included, which the
    // token rows below may not count.
    ...(splitParts(turn) ?? []).map((part) => ({
      label: part.model,
      value: markEstimate(formatUsd(part.costUsd), turn.estimatedCostUsd),
    })),
    {
      label: turn.outcome === 'running' ? 'so far' : 'worked',
      value: formatTurnDuration(turn.durationMs),
    },
    {
      label: 'at',
      value: formatTurnDuration(Date.parse(turn.startedAt) - runFrom),
    },
    { label: 'tools', value: formatCount(turn.toolCalls) },
    ...(turn.delegateToolCalls === 0
      ? []
      : [
          {
            label: BY_SUB_AGENTS,
            value: formatCount(turn.delegateToolCalls),
          },
        ]),
    { label: 'model', value: turn.model ?? '—' },
  ];
  if (turn.apiMs !== null) {
    rows.push({ label: 'of that, API', value: formatTurnDuration(turn.apiMs) });
  }
  if (turn.ttftMs !== null) {
    rows.push({
      label: 'to first token',
      value: formatTurnDuration(turn.ttftMs),
    });
  }
  if (turn.timeToRequestMs !== null) {
    rows.push({
      label: 'before asking',
      value: formatTurnDuration(turn.timeToRequestMs),
    });
  }
  if (turn.numTurns !== null) {
    rows.push({ label: 'model calls', value: formatCount(turn.numTurns) });
  }
  if (turn.cacheReadTokens !== null) {
    const share = turnCacheShare(turn);
    rows.push({
      label: 'cache read',
      value:
        share === null
          ? formatTokens(turn.cacheReadTokens)
          : `${formatTokens(turn.cacheReadTokens)} · ${Math.round(share)}%`,
    });
  }
  if (turn.contextTokens !== null && turn.contextWindowTokens !== null) {
    rows.push({
      label: 'context after',
      value: `${formatTokens(turn.contextTokens)} of ${formatTokens(turn.contextWindowTokens)}`,
    });
  }
  return rows;
}

/**
 * What a turn's hover is headed with. A turn that did not simply finish says
 * so FIRST — a stretch still running or one that died is the thing a reader
 * hovering it wants confirmed — and a finished turn measured from the rows
 * rather than by its CLI says that instead.
 */
export function turnTipTitle(laneName: string, turn: RunWaterfallTurn): string {
  switch (turn.outcome) {
    case 'running':
      return `${laneName} · working now`;
    case 'failed':
      return `${laneName} · a turn that failed`;
    case 'cancelled':
      return `${laneName} · a turn that was stopped`;
    case 'completed':
      return turn.timingSource === 'derived'
        ? `${laneName} · one turn (timing measured here)`
        : `${laneName} · one turn`;
  }
}

/**
 * The whole run in one strip, and the way to zoom into part of it: drag across
 * it to pick a stretch, which every lane and table below then shows.
 *
 * One thin row per agent plus one for the cards, so the strip is a map of the
 * run's shape rather than a decoration — a reader can see WHERE the dense
 * stretch is before deciding to zoom into it.
 */
export function WaterfallOverview({
  data,
  full,
  window: view,
  onWindow,
}: {
  data: RunWaterfallDto;
  full: ClockWindow;
  window: ClockWindow;
  onWindow: (window: ClockWindow) => void;
}): React.JSX.Element {
  const [drag, setDrag] = useState<{ from: number; to: number } | null>(null);
  const span = Math.max(1, full.to - full.from);
  const rows = data.lanes.length + (data.waits.length > 0 ? 1 : 0);
  const rowHeight = Math.max(
    3,
    Math.min(6, Math.floor(30 / Math.max(1, rows))),
  );
  // The strip GROWS for a run with many agents rather than clipping its last
  // rows — the waits row is drawn last, and on a nine-agent run with cards it
  // fell off the bottom of a fixed 40px.
  const stripHeight = Math.max(40, 8 + rows * (rowHeight + 1) + 2);
  const zoomed = view.from > full.from || view.to < full.to;
  const atX = (element: HTMLElement, clientX: number): number => {
    const rect = element.getBoundingClientRect();
    const pct =
      rect.width === 0
        ? 0
        : Math.max(0, Math.min(1, (clientX - rect.left) / rect.width));
    return full.from + pct * span;
  };
  const pctOf = (at: number): number => ((at - full.from) / span) * 100;
  const shown = drag ?? (zoomed ? view : null);
  const left = shown === null ? 0 : pctOf(Math.min(shown.from, shown.to));
  const width =
    shown === null ? 0 : Math.abs(pctOf(shown.to) - pctOf(shown.from));

  return (
    <div
      data-slot="waterfall-overview"
      role="group"
      aria-label="The whole run — drag across it to zoom in"
      className="relative cursor-crosshair touch-none overflow-hidden rounded-lg border border-border bg-background select-none"
      style={{ height: stripHeight }}
      onPointerDown={(event) => {
        // The primary button only: a right-click opening a menu is not the
        // start of a drag.
        if (event.button !== 0) {
          return;
        }
        const at = atX(event.currentTarget, event.clientX);
        event.currentTarget.setPointerCapture?.(event.pointerId);
        setDrag({ from: at, to: at });
      }}
      onPointerMove={(event) => {
        if (drag === null) {
          return;
        }
        setDrag({ ...drag, to: atX(event.currentTarget, event.clientX) });
      }}
      onPointerUp={(event) => {
        if (drag === null) {
          return;
        }
        // The END is read off this event, not off the last move the state has
        // caught up with: a quick flick can lift before its moves render.
        const end = atX(event.currentTarget, event.clientX);
        const from = Math.min(drag.from, end);
        const to = Math.max(drag.from, end);
        setDrag(null);
        // A click, or a drag too short to mean a stretch, is not a zoom.
        if (to - from >= span * 0.02) {
          onWindow({ from, to });
        }
      }}
      // A drag the system took away — a gesture, a lost capture — ends with
      // no zoom. Left standing, the brush followed a pointer with no button
      // held and the next click zoomed to a stretch nobody chose.
      onPointerCancel={() => setDrag(null)}
      onLostPointerCapture={() => setDrag(null)}
      onDoubleClick={() => onWindow(full)}>
      {data.lanes.map((lane, row) => (
        <span
          key={laneKey(lane.nodeId)}
          aria-hidden="true"
          className="absolute inset-x-0"
          style={{ top: 4 + row * (rowHeight + 1), height: rowHeight }}>
          {data.turns.map((turn, index) => {
            if (turn.nodeId !== lane.nodeId) {
              return null;
            }
            const placed = placeIn(turn.startedAt, turn.durationMs, full);
            return placed === null ? null : (
              <span
                key={index}
                className={cn(
                  'absolute inset-y-0 rounded-[1px]',
                  turn.outcome === 'failed' && 'bg-destructive',
                )}
                style={{
                  ...spot(placed),
                  backgroundColor:
                    turn.outcome === 'failed'
                      ? undefined
                      : categoryToken(laneIndexOf(data, lane.nodeId)),
                }}
              />
            );
          })}
        </span>
      ))}
      {data.waits.length === 0 ? null : (
        <span
          aria-hidden="true"
          className="absolute inset-x-0"
          style={{
            top: 4 + data.lanes.length * (rowHeight + 1),
            height: rowHeight,
          }}>
          {data.waits.map((wait, index) => {
            const placed = placeIn(wait.startedAt, wait.durationMs, full);
            return placed === null ? null : (
              <span
                key={index}
                className="absolute inset-y-0 rounded-[1px] bg-warning"
                style={spot(placed)}
              />
            );
          })}
        </span>
      )}
      {shown === null ? null : (
        <span
          aria-hidden="true"
          data-slot="waterfall-brush"
          className="pointer-events-none absolute inset-y-0 rounded-md border border-primary bg-primary/15"
          style={{ left: `${left}%`, width: `${width}%` }}
        />
      )}
      {zoomed || drag !== null ? null : (
        <span className="pointer-events-none absolute right-2 bottom-0.5 text-[10px] text-muted-foreground">
          drag to zoom
        </span>
      )}
    </div>
  );
}
