import { describe, expect, it } from 'vitest';

import type {
  RunWaterfallDto,
  RunWaterfallLane,
  RunWaterfallTurn,
} from '../autogenerated';
import {
  cumulativeSpend,
  laneIndexOf,
  place,
  toolsTitle,
  topTurns,
} from './run-waterfall-geometry';

const FROM = Date.parse('2026-09-07T12:00:00.000Z');
const SPAN_MS = 60 * 60 * 1000;

function turn(over: Partial<RunWaterfallTurn> = {}): RunWaterfallTurn {
  return {
    nodeId: 'engineer',
    startedAt: new Date(FROM).toISOString(),
    timingSource: 'cli',
    durationMs: 60_000,
    apiMs: null,
    ttftMs: null,
    timeToRequestMs: null,
    numTurns: null,
    costUsd: 1,
    model: 'opus-5',
    inputTokens: null,
    outputTokens: null,
    cacheReadTokens: null,
    contextTokens: null,
    contextWindowTokens: null,
    ...over,
  };
}

function lane(nodeId: string | null): RunWaterfallLane {
  return {
    nodeId,
    agentKind: 'claude',
    costUsd: 1,
    turns: 1,
    toolCalls: 1,
    workedMs: 1,
    toolBuckets: [],
  };
}

function dto(nodeIds: (string | null)[]): RunWaterfallDto {
  return {
    from: new Date(FROM).toISOString(),
    to: new Date(FROM + SPAN_MS).toISOString(),
    lanes: nodeIds.map(lane),
    toolUse: [],
    turns: [],
    calls: [],
    waits: [],
    delegates: [],
    totals: {
      turns: 0,
      costedTurns: 0,
      costUsd: null,
      inputTokens: null,
      outputTokens: null,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      thinkingTokens: null,
      workedMs: null,
    },
    waitedOnUserMs: null,
    partialReason: null,
  };
}

describe('place', () => {
  it('refuses a span it cannot put on the clock', () => {
    // A `turn_complete` whose derived start will not parse reaches here, and
    // the caller draws nothing rather than a bar at NaN% — which React renders
    // as a full-width element, i.e. a turn claiming the whole run.
    expect(place('not a date', 1000, FROM, SPAN_MS)).toBeNull();
  });

  it('never lets a span run past the end of its lane', () => {
    // The visible-width floor is itself bounded by the room left; applied after
    // the clamp it pushed a late span out of the lane entirely.
    const spot = place(
      new Date(FROM + SPAN_MS - 100).toISOString(),
      SPAN_MS,
      FROM,
      SPAN_MS,
    );
    expect(spot).not.toBeNull();
    expect((spot?.leftPct ?? 0) + (spot?.widthPct ?? 0)).toBeLessThanOrEqual(
      100,
    );
  });
});

describe('cumulativeSpend', () => {
  it('only ever climbs, and opens at zero', () => {
    // The curve's whole claim is "this is what had been spent by then". A
    // series that dipped would be reporting money coming back.
    const points = cumulativeSpend(
      [
        turn({ costUsd: 2, startedAt: new Date(FROM + 30_000).toISOString() }),
        turn({ costUsd: 1, startedAt: new Date(FROM).toISOString() }),
      ],
      FROM,
    );

    expect(points[0]).toEqual({ atMs: 0, spentUsd: 0 });
    const spends = points.map((point) => point.spentUsd);
    expect(spends).toEqual([...spends].sort((a, b) => a - b));
    expect(spends.at(-1)).toBe(3);
  });

  it('leaves out a turn that priced nothing rather than adding a zero', () => {
    // cursor-agent prices no turn on the wire. Counted as 0 it would flatten
    // the curve across real work, which reads as an agent that did nothing.
    const points = cumulativeSpend(
      [turn({ costUsd: null }), turn({ costUsd: 4 })],
      FROM,
    );

    // The opening zero plus the ONE priced turn — never a third point.
    expect(points).toHaveLength(2);
    expect(points.at(-1)?.spentUsd).toBe(4);
  });

  it('answers empty when nothing on the run was priced', () => {
    // The caller draws a sentence instead of a chart; a lone `{0, 0}` point
    // would render as an axis pair claiming the run cost nothing.
    expect(cumulativeSpend([turn({ costUsd: null })], FROM)).toEqual([]);
  });
});

describe('topTurns', () => {
  it('ranks by cost and drops the turns that reported none', () => {
    const rows = topTurns(
      [turn({ costUsd: 1 }), turn({ costUsd: null }), turn({ costUsd: 9 })],
      10,
    );

    expect(rows.map((row) => row.costUsd)).toEqual([9, 1]);
  });
});

describe('laneIndexOf', () => {
  it('gives each lane its own colour index', () => {
    const data = dto(['manager', 'engineer']);
    expect(laneIndexOf(data, 'manager')).toBe(0);
    expect(laneIndexOf(data, 'engineer')).toBe(1);
  });

  it('places a span whose lane was dropped rather than losing it', () => {
    // A node that only ever waited earns no lane, and a call naming it still
    // has to be drawn on its caller's row.
    expect(laneIndexOf(dto(['manager']), 'ghost')).toBe(0);
  });
});

describe('toolsTitle', () => {
  it('says whose tools were counted', () => {
    // The fold reads the payload-free spine, so a delegate's calls land in its
    // launcher's lane while the agent card beside it counts the agent's own.
    expect(toolsTitle(636)).toContain('sub-agents included');
  });
});
