const FROM = Date.parse('2026-09-07T12:00:00.000Z');
const SPAN_MS = 60 * 60 * 1000;

function turn(over: Partial<RunWaterfallTurn> = {}): RunWaterfallTurn {
  return {
    nodeId: 'engineer',
    startedAt: new Date(FROM).toISOString(),
    seq: 1,
    timingSource: 'cli',
    outcome: 'completed',
    toolCalls: 0,
    delegateToolCalls: 0,
    durationMs: 60_000,
    apiMs: null,
    ttftMs: null,
    timeToRequestMs: null,
    numTurns: null,
    costUsd: 1,
    estimatedCostUsd: null,
    modelCosts: null,
    model: 'opus-5',
    inputTokens: null,
    outputTokens: null,
    cacheReadTokens: null,
    contextTokens: null,
    contextWindowTokens: null,
    ...over,
  };
}

function lane(nodeId: string | null): RunWaterfallLane {
  return {
    nodeId,
    agentKind: 'claude',
    costUsd: 1,
    estimatedCostUsd: null,
    turns: 1,
    toolCalls: 1,
    delegateToolCalls: 0,
    workedMs: 1,
  };
}

function dto(nodeIds: (string | null)[]): RunWaterfallDto {
  return {
    from: new Date(FROM).toISOString(),
    to: new Date(FROM + SPAN_MS).toISOString(),
    lanes: nodeIds.map(lane),
    toolUse: [],
    turns: [],
    calls: [],
    waits: [],
    delegates: [],
    criticalPath: [],
    totals: {
      turns: 0,
      costedTurns: 0,
      costUsd: null,
      estimatedCostUsd: null,
      inputTokens: null,
      outputTokens: null,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      thinkingTokens: null,
      workedMs: null,
    },
    waitedOnUserMs: null,
    partialReason: null,
  };
}

describe('place', () => {
  it('refuses a span it cannot put on the clock', () => {
    // A `turn_complete` whose derived start will not parse reaches here, and
    // the caller draws nothing rather than a bar at NaN% — which React renders
    // as a full-width element, i.e. a turn claiming the whole run.
    expect(place('not a date', 1000, FROM, SPAN_MS)).toBeNull();
  });

  it('never lets a span run past the end of its lane', () => {
    // The visible-width floor is itself bounded by the room left; applied after
    // the clamp it pushed a late span out of the lane entirely.
    const spot = place(
      new Date(FROM + SPAN_MS - 100).toISOString(),
      SPAN_MS,
      FROM,
      SPAN_MS,
    );
    expect(spot).not.toBeNull();
    expect((spot?.leftPct ?? 0) + (spot?.widthPct ?? 0)).toBeLessThanOrEqual(
      100,
    );
  });
});

describe('cumulativeSpend', () => {
  it('only ever climbs, and opens at zero', () => {
    // The curve's whole claim is "this is what had been spent by then". A
    // series that dipped would be reporting money coming back.
    const points = cumulativeSpend(
      [
        turn({ costUsd: 2, startedAt: new Date(FROM + 30_000).toISOString() }),
        turn({ costUsd: 1, startedAt: new Date(FROM).toISOString() }),
      ],
      FROM,
    );

    expect(points[0]).toEqual({
      atMs: 0,
      spentUsd: 0,
      spentEstimatedUsd: null,
    });
    const spends = points.map((point) => point.spentUsd);
    expect(spends).toEqual([...spends].sort((a, b) => a - b));
    expect(spends.at(-1)).toBe(3);
  });

  it('accumulates the estimated part alongside, null until a turn carries one', () => {
    const points = cumulativeSpend(
      [
        turn({ costUsd: 2, startedAt: new Date(FROM).toISOString() }),
        turn({
          costUsd: 1,
          estimatedCostUsd: 1,
          startedAt: new Date(FROM + 30_000).toISOString(),
        }),
      ],
      FROM,
    );

    expect(points.map((point) => point.spentEstimatedUsd)).toEqual([
      null,
      null,
      1,
    ]);
  });

  it('leaves out a turn that priced nothing rather than adding a zero', () => {
    // cursor-agent prices no turn on the wire. Counted as 0 it would flatten
    // the curve across real work, which reads as an agent that did nothing.
    const points = cumulativeSpend(
      [turn({ costUsd: null }), turn({ costUsd: 4 })],
      FROM,
    );

    // The opening zero plus the ONE priced turn — never a third point.
    expect(points).toHaveLength(2);
    expect(points.at(-1)?.spentUsd).toBe(4);
  });

  it('answers empty when nothing on the run was priced', () => {
    // The caller draws a sentence instead of a chart; a lone `{0, 0}` point
    // would render as an axis pair claiming the run cost nothing.
    expect(cumulativeSpend([turn({ costUsd: null })], FROM)).toEqual([]);
  });
});

describe('topTurns', () => {
  it('ranks by cost and drops the turns that reported none', () => {
    const rows = topTurns(
      [turn({ costUsd: 1 }), turn({ costUsd: null }), turn({ costUsd: 9 })],
      10,
    );

    expect(rows.map((row) => row.costUsd)).toEqual([9, 1]);
  });
});

describe('laneIndexOf', () => {
  it('gives each lane its own colour index', () => {
    const data = dto(['manager', 'engineer']);
    expect(laneIndexOf(data, 'manager')).toBe(0);
    expect(laneIndexOf(data, 'engineer')).toBe(1);
  });

  it('places a span whose lane was dropped rather than losing it', () => {
    // A node that only ever waited earns no lane, and a call naming it still
    // has to be drawn on its caller's row.
    expect(laneIndexOf(dto(['manager']), 'ghost')).toBe(0);
  });
});

describe('toolsCaption / toolsTitle', () => {
  it('puts the sub-agents’ calls beside the agent’s own, never inside them', () => {
    expect(toolsCaption(845, 1_041)).toBe('845 own + 1,041 by sub-agents');
    expect(toolsTitle(845, 1_041)).toBe(
      '845 tool calls made by the agents themselves, 1,041 by their sub-agents',
    );
  });

  it('says only the agent’s own count when no sub-agent called a tool', () => {
    expect(toolsCaption(1, 0)).toBe('1 tool');
    expect(toolsCaption(2_672, 0)).toBe('2,672 tools');
    expect(toolsTitle(636, 0)).toBe(
      '636 tool calls made by the agents themselves',
    );
  });
});

describe('costSplit', () => {
  const SPLIT = [
    { model: 'claude-haiku-5-5', costUsd: 39.03 },
    { model: 'claude-sonnet-5-5', costUsd: 1.65 },
  ];

  it('says which models a turn’s cost went to', () => {
    expect(costSplit(turn({ modelCosts: SPLIT }))).toBe(
      'claude-haiku-5-5 $39.03 · claude-sonnet-5-5 $1.65',
    );
  });

  it('says nothing for one model or no stated split', () => {
    expect(costSplit(turn({ modelCosts: [SPLIT[0]!] }))).toBeNull();
    expect(costSplit(turn({ modelCosts: null }))).toBeNull();
  });

  it('marks every model’s share with the turn’s own provenance', () => {
    expect(
      costSplit(turn({ modelCosts: SPLIT, estimatedCostUsd: 40.68 })),
    ).toBe('claude-haiku-5-5 ≈$39.03 · claude-sonnet-5-5 ≈$1.65');
  });

  it('marks an estimated turn’s hover cost and says whose price it is', () => {
    const estimated = turnTitle(turn({ costUsd: 3, estimatedCostUsd: 3 }));
    const billed = turnTitle(turn({ costUsd: 3, estimatedCostUsd: null }));

    expect(estimated).toContain('≈$3.00');
    expect(estimated).toContain("geniro's estimate");
    expect(billed).toContain('$3.00');
    expect(billed).not.toContain('≈');
    expect(billed).not.toContain('estimate');
  });

  it('rides the turn’s hover sentence after its cost, with the split tools', () => {
    const title = turnTitle(
      turn({
        costUsd: 40.68,
        modelCosts: SPLIT,
        toolCalls: 12,
        delegateToolCalls: 30,
      }),
    );
    expect(title).toContain(
      '$40.68 = claude-haiku-5-5 $39.03 · claude-sonnet-5-5 $1.65',
    );
    expect(title).toContain('12 own + 30 by sub-agents');
  });
});

describe('stackRows', () => {
  it('gives spans that share time a row each and reuses a row once it is free', () => {
    // Three calls out at once, then a fourth after the first has come back:
    // the fourth goes back to row 0 rather than opening a fourth row.
    const { rows, count } = stackRows([
      { leftPct: 10, widthPct: 40 },
      { leftPct: 12, widthPct: 30 },
      { leftPct: 15, widthPct: 50 },
      { leftPct: 50, widthPct: 10 },
    ]);

    expect(rows).toEqual([0, 1, 2, 0]);
    expect(count).toBe(3);
  });

  it('keeps input order in its answer whatever order the spans start in', () => {
    const { rows } = stackRows([
      { leftPct: 30, widthPct: 10 },
      { leftPct: 0, widthPct: 35 },
    ]);

    expect(rows).toEqual([1, 0]);
  });

  it('takes no row for a span that could not be placed', () => {
    const { rows, count } = stackRows([null, { leftPct: 0, widthPct: 5 }]);

    expect(rows).toEqual([0, 0]);
    expect(count).toBe(1);
  });
});

describe('placeIn', () => {
  const window = { from: FROM + 10 * 60_000, to: FROM + 20 * 60_000 };
  const iso = (minutes: number): string =>
    new Date(FROM + minutes * 60_000).toISOString();

  it('draws a span that began before the window from its left edge, for the part inside', () => {
    // 5m–15m against a 10m–20m window: half the window, from 0%. Measured
    // from its true start it would claim the whole first 100%.
    expect(placeIn(iso(5), 10 * 60_000, window)).toEqual({
      leftPct: 0,
      widthPct: 50,
    });
  });

  it('refuses a span wholly outside the window', () => {
    expect(placeIn(iso(0), 60_000, window)).toBeNull();
    expect(placeIn(iso(25), 60_000, window)).toBeNull();
  });

  it('cuts a span that runs past the window at its right edge', () => {
    expect(placeIn(iso(15), 30 * 60_000, window)).toEqual({
      leftPct: 50,
      widthPct: 50,
    });
  });
});

describe('blocksCaller', () => {
  it("holds a caller for anything not explicitly async, as the daemon's path does", () => {
    const call = (mode: string | null) => ({
      callerNodeId: 'a',
      calleeNodeId: 'b',
      mode,
      status: 'ok',
      running: false,
      startedAt: new Date(FROM).toISOString(),
      seq: 1,
      durationMs: 1,
    });
    expect(blocksCaller(call('sync'))).toBe(true);
    expect(blocksCaller(call(null))).toBe(true);
    expect(blocksCaller(call('async'))).toBe(false);
  });
});

describe('turnContextFill', () => {
  it('reads a fill only when both figures were reported, capped at full', () => {
    expect(
      turnContextFill(turn({ contextTokens: 50, contextWindowTokens: 200 })),
    ).toBe(0.25);
    expect(
      turnContextFill(turn({ contextTokens: 300, contextWindowTokens: 200 })),
    ).toBe(1);
    expect(
      turnContextFill(turn({ contextTokens: 50, contextWindowTokens: null })),
    ).toBeNull();
    expect(
      turnContextFill(turn({ contextTokens: 50, contextWindowTokens: 0 })),
    ).toBeNull();
  });
});

describe('onCriticalPath', () => {
  const path = [
    {
      kind: 'work' as const,
      nodeId: 'eng',
      startedAt: new Date(FROM).toISOString(),
      durationMs: 60_000,
    },
  ];

  it('lights work only on the node whose stretch it is', () => {
    expect(
      onCriticalPath(path, 'work', 'eng', FROM + 10_000, FROM + 20_000),
    ).toBe(true);
    expect(
      onCriticalPath(path, 'work', 'mgr', FROM + 10_000, FROM + 20_000),
    ).toBe(false);
  });

  it('lights nothing that only touches the stretch at its end', () => {
    expect(
      onCriticalPath(path, 'work', 'eng', FROM + 60_000, FROM + 90_000),
    ).toBe(false);
  });
});
