import type {
  RunWaterfallCall,
  RunWaterfallDto,
  RunWaterfallTurn,
} from '../autogenerated';
import { formatCount, NOT_MEASURED } from '../stats/stats-format';
import { formatUsd } from './agent-activity';
import { formatDuration as formatTurnDuration } from './turn-duration';

/**
 * The placement maths BOTH waterfall surfaces share.
 *
 * There are two of them on purpose — a 280px sidebar card and a full-screen
 * view — because one reads at a glance and the other is read closely, and no
 * single density serves both. What must NOT be two is where a span LANDS: two
 * copies of this arithmetic is how the card and the big view come to draw the
 * same run differently, which is the one failure that makes both untrustworthy.
 */

/** A lane's own spans, already placed as percentages of the run's wall clock. */
export interface Placed {
  leftPct: number;
  widthPct: number;
}

/**
 * The narrowest bar still visible: a 20-second turn inside a 40-hour run is
 * 0.014% wide and would otherwise render as nothing at all, and a lane showing
 * no work for a turn that happened is worse than a slightly generous bar.
 */
export const MIN_SPAN_PCT = 0.7;

/**
 * Where a span sits on the run's clock, or null when it cannot be placed.
 *
 * ORDER is load-bearing twice over, and both orderings look arbitrary until
 * they are wrong. The width is measured against the CLAMPED left edge — a turn
 * whose derived start precedes the run's first row has a negative one, and
 * measuring against that lets the bar claim more of the lane than the span
 * covers. And the visible-minimum floor is itself capped by the room left, so a
 * span starting at the very end of the run is widened into what remains rather
 * than past it.
 */
export function place(
  startedAt: string,
  durationMs: number,
  from: number,
  span: number,
): Placed | null {
  const start = Date.parse(startedAt);
  if (!Number.isFinite(start) || !Number.isFinite(durationMs)) {
    return null;
  }
  const leftPct = Math.max(0, Math.min(100, ((start - from) / span) * 100));
  const room = 100 - leftPct;
  return {
    leftPct,
    widthPct: Math.min(
      room,
      Math.max(Math.min(MIN_SPAN_PCT, room), (durationMs / span) * 100),
    ),
  };
}

/**
 * How a turn bar says the turn did not simply finish — the ONE spelling both
 * surfaces draw, so a failed turn cannot read as failed in one and as done in
 * the other.
 *
 * A running turn pulses (and holds still for a reader who asked for less
 * motion), a failed one is outlined red, a stopped one fades. A finished turn
 * adds nothing: it is the ordinary case, and the bar's colour already says whose.
 */
export const TURN_OUTCOME_CLASS: Record<RunWaterfallTurn['outcome'], string> = {
  completed: '',
  running: 'animate-pulse motion-reduce:animate-none',
  failed: 'opacity-60 ring-1 ring-inset ring-destructive',
  cancelled: 'opacity-40',
};

/** The outcome in words, for a hover — null for the ordinary finished turn. */
export function turnOutcomeWord(
  outcome: RunWaterfallTurn['outcome'],
): string | null {
  switch (outcome) {
    case 'running':
      return 'still running';
    case 'failed':
      return 'failed';
    case 'cancelled':
      return 'stopped';
    case 'completed':
      return null;
  }
}

/**
 * Whether a call ended badly. A call still RUNNING has no status yet, and
 * reading that absence as "not ok" counted every call in progress as a failure.
 */
export function callFailed(call: RunWaterfallCall): boolean {
  return !call.running && call.status !== 'ok';
}

/**
 * What one turn says about itself on hover.
 *
 * A figure the CLI never reported is LEFT OUT rather than drawn as a dash: this
 * is a hover line rather than a column, so an absent part costs a reader
 * nothing, where an em dash in a sentence reads as a broken figure.
 */
export function turnTitle(turn: RunWaterfallTurn): string {
  const outcome = turnOutcomeWord(turn.outcome);
  const parts = [
    ...(outcome === null ? [] : [outcome]),
    formatTurnDuration(turn.durationMs),
    turn.costUsd === null
      ? NOT_MEASURED
      : withCostSplit(formatUsd(turn.costUsd), turn),
    toolsCaption(turn.toolCalls, turn.delegateToolCalls),
  ];
  if (turn.model !== null) {
    parts.push(turn.model);
  }
  if (turn.ttftMs !== null) {
    parts.push(`${formatTurnDuration(turn.ttftMs)} to first token`);
  }
  if (turn.timeToRequestMs !== null) {
    parts.push(`${formatTurnDuration(turn.timeToRequestMs)} before asking`);
  }
  if (turn.numTurns !== null) {
    parts.push(
      `${turn.numTurns} model ${turn.numTurns === 1 ? 'call' : 'calls'}`,
    );
  }
  return parts.join(' · ');
}

/**
 * A lane's or a turn's tool calls as a caption: the agent's own, and its CLI
 * sub-agents' beside them rather than inside them — `800 own + 1,041 by
 * sub-agents`. The daemon files a delegate's calls under the agent that
 * launched it, and summed they read as the agent's own work.
 *
 * Shared by every surface drawing the count, so none of them words it
 * differently.
 */
export function toolsCaption(own: number, delegates: number): string {
  if (delegates === 0) {
    return `${formatCount(own)} ${own === 1 ? 'tool' : 'tools'}`;
  }
  return `${formatCount(own)} own + ${formatCount(delegates)} ${BY_SUB_AGENTS}`;
}

/** The words every surface names the sub-agents' share of a tool count with. */
export const BY_SUB_AGENTS = 'by sub-agents';

/**
 * The hover sentence behind {@link toolsCaption} — worded for one lane and for
 * the run's total alike.
 */
export function toolsTitle(own: number, delegates: number): string {
  const mine = `${formatCount(own)} tool ${own === 1 ? 'call' : 'calls'} made by the agents themselves`;
  return delegates === 0
    ? mine
    : `${mine}, ${formatCount(delegates)} by their sub-agents`;
}

/**
 * Where a turn's cost went by model — `claude-haiku-5-5 $39.03 · claude-sonnet-5-5
 * $1.65` — or null when the CLI stated no split, or one model spent it all.
 *
 * The split is the daemon's, kept only when it adds up to the cost: a turn's
 * token figures can be its main thread's alone while its cost covers every
 * sub-agent, so tokens times a price will not reproduce the figure without it.
 */
export function costSplit(
  turn: Pick<RunWaterfallTurn, 'modelCosts'>,
): string | null {
  return (
    splitParts(turn)
      ?.map((part) => `${part.model} ${formatUsd(part.costUsd)}`)
      .join(' · ') ?? null
  );
}

/** The parts {@link costSplit} draws, or null when it draws none. */
export function splitParts(
  turn: Pick<RunWaterfallTurn, 'modelCosts'>,
): RunWaterfallTurn['modelCosts'] {
  const parts = turn.modelCosts;
  return parts !== null && parts.length >= 2 ? parts : null;
}

/** `$40.68 = <split>` when the turn has a split, else the figure alone. */
function withCostSplit(
  cost: string,
  turn: Pick<RunWaterfallTurn, 'modelCosts'>,
): string {
  const split = costSplit(turn);
  return split === null ? cost : `${cost} = ${split}`;
}

/** The lane a span belongs to, by node id — which is also its colour index. */
export function laneIndexOf(
  data: RunWaterfallDto,
  nodeId: string | null,
): number {
  const index = data.lanes.findIndex((lane) => lane.nodeId === nodeId);
  // A span whose lane was dropped (a node that only ever waited) still has to
  // be drawn somewhere; the first colour is a better answer than not drawing it.
  return index < 0 ? 0 : index;
}

/** One point of the cumulative-spend curve. */
export interface SpendPoint {
  /** Milliseconds since the run's first row — the shared X axis. */
  atMs: number;
  /** Everything the run had spent by then, in dollars. */
  spentUsd: number;
}

/**
 * How the money added up, over the run's own clock.
 *
 * Only turns that REPORTED a cost contribute: a cursor turn carries none on the
 * wire, and treating that as a zero would draw a flat stretch through work that
 * was in fact billed elsewhere (the polled figure the totals carry). So the
 * curve is explicitly about what the TURNS priced, and the tile above it is
 * what states the run's whole bill.
 *
 * Returns an empty list when nothing priced anything, so the caller draws no
 * chart rather than a flat line at zero.
 */
export function cumulativeSpend(
  turns: readonly RunWaterfallTurn[],
  from: number,
): SpendPoint[] {
  const priced = turns
    .filter((turn) => turn.costUsd !== null)
    .map((turn) => ({
      at: Date.parse(turn.startedAt) + turn.durationMs,
      cost: turn.costUsd ?? 0,
    }))
    .filter((entry) => Number.isFinite(entry.at))
    .sort((a, b) => a.at - b.at);
  if (priced.length === 0) {
    return [];
  }
  let running = 0;
  const points: SpendPoint[] = [{ atMs: 0, spentUsd: 0 }];
  for (const entry of priced) {
    running += entry.cost;
    points.push({ atMs: Math.max(0, entry.at - from), spentUsd: running });
  }
  return points;
}

/**
 * The turns that cost the most, biggest first.
 *
 * A turn that priced nothing is left out rather than sorted to the bottom: this
 * table answers "where did the money go", and a row reading `—` in its only
 * numeric column is not an answer to that question.
 */
export function topTurns(
  turns: readonly RunWaterfallTurn[],
  limit: number,
): RunWaterfallTurn[] {
  return turns
    .filter((turn) => turn.costUsd !== null)
    .sort((a, b) => (b.costUsd ?? 0) - (a.costUsd ?? 0))
    .slice(0, limit);
}
