import type { RunWaterfallDto } from '../autogenerated';
import { formatDuration, formatPercent } from '../stats/stats-format';
import { formatTokens, formatUsd, markEstimate } from './agent-activity';
import {
  blocksCaller,
  callFailed,
  CONTEXT_PRESSURE,
  turnCacheShare,
  turnContextFill,
  type WaterfallMark,
} from './run-waterfall-geometry';

/**
 * What stands out on a run, said in a sentence — and the mark that shows it.
 *
 * A gantt shows everything at once and so says nothing first. These are the
 * few readings a person opened the view to find, worked out of the same wire
 * the gantt draws and never estimated: a sync call that held its caller still,
 * the run standing still on a card, a turn that failed or cost a large share,
 * the cache collapsing, a context near its window. Each names the mark that
 * shows it, so a click lands on the evidence rather than on a paraphrase of it.
 */

export type InsightTone = 'warning' | 'danger' | 'neutral';

export interface Insight {
  /** Stable within one reading — the list's key. */
  id: string;
  tone: InsightTone;
  title: string;
  detail: string;
  /** The mark that shows it; null for one about the run as a whole. */
  target: WaterfallMark | null;
}

/** A blocking call worth naming: at least this long, or this share of the run. */
const BLOCKED_MIN_MS = 60_000;
const BLOCKED_MIN_SHARE = 0.15;
/** The run standing still on the user, on the critical path, from here on. */
const WAITED_MIN_MS = 30_000;
/** One turn costing this share of the run's priced total. */
const EXPENSIVE_SHARE = 0.25;
/** A cache share falling from at least `CACHE_WAS` to under `CACHE_NOW`. */
const CACHE_WAS = 70;
const CACHE_NOW = 50;
/** Idle time on the critical path from this share of the wall clock on. */
const IDLE_SHARE = 0.25;
/** How many a reader is shown — past this they stop being "what stands out". */
const MAX_INSIGHTS = 6;

const laneName = (nodeId: string | null): string => nodeId ?? 'agent';

export function waterfallInsights(data: RunWaterfallDto): Insight[] {
  const wallMs = Math.max(1, Date.parse(data.to) - Date.parse(data.from));
  const out: Insight[] = [];

  // The run standing still on the user — on the PATH, so it is time the run
  // actually lost rather than a card answered while other agents worked.
  const waitedOnPath = data.criticalPath
    .filter((segment) => segment.kind === 'waiting_on_user')
    .reduce((sum, segment) => sum + segment.durationMs, 0);
  if (waitedOnPath >= WAITED_MIN_MS && data.waits.length > 0) {
    const longest = data.waits.reduce(
      (best, wait, index) =>
        wait.durationMs > (data.waits[best]?.durationMs ?? -1) ? index : best,
      0,
    );
    out.push({
      id: 'waited',
      tone: 'warning',
      title: `the run stood still ${formatDuration(waitedOnPath)} waiting on you`,
      detail: `${data.waits.length} ${data.waits.length === 1 ? 'card' : 'cards'} — the longest took ${formatDuration(data.waits[longest]?.durationMs ?? 0)}`,
      target: { kind: 'wait', index: longest },
    });
  }

  // The longest blocking call per caller, named when it held a real share.
  const longestBlock = new Map<string | null, number>();
  data.calls.forEach((call, index) => {
    if (!blocksCaller(call)) {
      return;
    }
    const best = longestBlock.get(call.callerNodeId);
    if (
      best === undefined ||
      call.durationMs > (data.calls[best]?.durationMs ?? 0)
    ) {
      longestBlock.set(call.callerNodeId, index);
    }
  });
  for (const [caller, index] of longestBlock) {
    const call = data.calls[index];
    if (
      call === undefined ||
      (call.durationMs < BLOCKED_MIN_MS &&
        call.durationMs / wallMs < BLOCKED_MIN_SHARE)
    ) {
      continue;
    }
    out.push({
      id: `blocked-${index}`,
      tone: 'neutral',
      title: `${laneName(caller)} waited ${formatDuration(call.durationMs)} on ${laneName(call.calleeNodeId)}`,
      detail: `a call that held it still — ${formatPercent((call.durationMs / wallMs) * 100)} of the wall clock`,
      target: { kind: 'blocked', index },
    });
  }

  data.turns.forEach((turn, index) => {
    if (turn.outcome !== 'failed') {
      return;
    }
    out.push({
      id: `failed-turn-${index}`,
      tone: 'danger',
      title: `${laneName(turn.nodeId)}: a turn failed`,
      detail:
        turn.costUsd === null
          ? `${formatDuration(turn.durationMs)} of work with no result`
          : `${markEstimate(formatUsd(turn.costUsd), turn.estimatedCostUsd)} and ${formatDuration(turn.durationMs)} with no result`,
      target: { kind: 'turn', index },
    });
  });

  data.calls.forEach((call, index) => {
    if (!callFailed(call)) {
      return;
    }
    out.push({
      id: `failed-call-${index}`,
      tone: 'danger',
      title: `a call to ${laneName(call.calleeNodeId)} failed`,
      detail: `${laneName(call.callerNodeId)} asked, and it came back ${call.status ?? 'without a status'}`,
      target: { kind: 'call', index },
    });
  });

  // The ONE most expensive turn, once it holds a real share of the run. Every
  // turn past the threshold would name the same agent two or three times and
  // crowd out the readings that are actually different.
  const total = data.totals.costUsd;
  if (total !== null && total > 0) {
    const priciest = data.turns.reduce<number | null>((best, turn, index) => {
      const bestCost =
        best === null ? null : (data.turns[best]?.costUsd ?? null);
      return turn.costUsd !== null &&
        (bestCost === null || turn.costUsd > bestCost)
        ? index
        : best;
    }, null);
    const turn = priciest === null ? undefined : data.turns[priciest];
    if (
      priciest !== null &&
      turn !== undefined &&
      turn.costUsd !== null &&
      turn.costUsd / total >= EXPENSIVE_SHARE &&
      turn.costUsd < total
    ) {
      out.push({
        id: `expensive-${priciest}`,
        tone: 'warning',
        title: `${laneName(turn.nodeId)}: one turn cost ${formatPercent((turn.costUsd / total) * 100)} of the run`,
        detail: `${markEstimate(formatUsd(turn.costUsd), turn.estimatedCostUsd)} of ${markEstimate(formatUsd(total), data.totals.estimatedCostUsd)}`,
        target: { kind: 'turn', index: priciest },
      });
    }
  }

  // The cache collapsing between two turns of one lane — the reading that says
  // a session was respawned or its instructions changed under it.
  const lastShare = new Map<string | null, number>();
  data.turns.forEach((turn, index) => {
    const share = turnCacheShare(turn);
    if (share === null) {
      return;
    }
    const was = lastShare.get(turn.nodeId);
    lastShare.set(turn.nodeId, share);
    if (was === undefined || was < CACHE_WAS || share >= CACHE_NOW) {
      return;
    }
    out.push({
      id: `cache-${index}`,
      tone: 'danger',
      title: `${laneName(turn.nodeId)}: cache fell to ${formatPercent(share)}`,
      detail: `it was ${formatPercent(was)} the turn before`,
      target: { kind: 'turn', index },
    });
  });

  // The fullest context per lane, once it is close to the window.
  const fullest = new Map<string | null, number>();
  data.turns.forEach((turn, index) => {
    const fill = turnContextFill(turn);
    if (fill === null || fill < CONTEXT_PRESSURE) {
      return;
    }
    const best = fullest.get(turn.nodeId);
    const bestTurn = best === undefined ? undefined : data.turns[best];
    if (bestTurn === undefined || fill > (turnContextFill(bestTurn) ?? 0)) {
      fullest.set(turn.nodeId, index);
    }
  });
  for (const [nodeId, index] of fullest) {
    const turn = data.turns[index];
    const fill = turn === undefined ? null : turnContextFill(turn);
    if (turn === undefined || fill === null) {
      continue;
    }
    out.push({
      id: `context-${index}`,
      tone: 'warning',
      title: `${laneName(nodeId)}: context at ${formatPercent(fill * 100)}`,
      detail: `${formatTokens(turn.contextTokens ?? 0)} of a ${formatTokens(turn.contextWindowTokens ?? 0)} window`,
      target: { kind: 'turn', index },
    });
  }

  const idle = data.criticalPath
    .filter((segment) => segment.kind === 'idle')
    .reduce((sum, segment) => sum + segment.durationMs, 0);
  if (idle / wallMs >= IDLE_SHARE) {
    out.push({
      id: 'idle',
      tone: 'neutral',
      title: `nobody was working for ${formatPercent((idle / wallMs) * 100)} of the wall clock`,
      detail: `${formatDuration(idle)} on the critical path with no agent running and no card open`,
      target: null,
    });
  }

  return out.slice(0, MAX_INSIGHTS);
}
