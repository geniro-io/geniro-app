import type { RunWaterfallDto } from '../autogenerated';
import {
  blocksCaller,
  type ClockWindow,
  endOf,
} from './run-waterfall-geometry';

/** The least room, in pixels, between two rows that each carry an arrow. */
export const SEQUENCE_ROW_MIN = 26;

/** An event-free stretch longer than this is drawn as a break. */
export const SEQUENCE_BREAK_MS = 30 * 60_000;

/** How tall a break is drawn, in pixels. */
export const SEQUENCE_BREAK_PX = 44;

/** Pixels per minute of the run's clock at scale 1. */
export const SEQUENCE_PX_PER_MIN = 1.2;

/** Room above the first event, in pixels. */
const TOP_PAD = 20;

/** Calls one agent made this close together, with no other arrow between, are drawn as one parallel group. */
export const SEQUENCE_PARALLEL_MS = 90_000;

/** Extra room above and below a parallel group, for its frame and tag. */
const GROUP_PAD_TOP = 18;
const GROUP_PAD_BOTTOM = 10;

/** One call as the diagram draws it. */
export interface SequenceCall {
  index: number;
  /** Its number in the run, by when it was made — the same at any zoom. */
  number: number;
  from: number;
  to: number;
  /** The slot of the caller's turn the call left from, and of the callee's turn that answered. */
  fromSlot: number;
  toSlot: number;
  /** The slot of the callee's last answering turn, where its answer leaves from. */
  backSlot: number;
  y: number;
  /** Where its answer comes back, for a call its caller waited on; else null. */
  backY: number | null;
}

/** One turn as the diagram draws it: its column, its slot beside overlapping turns, and its span. */
export interface SequenceTurn {
  index: number;
  column: number;
  slot: number;
  y0: number;
  y1: number;
  /** The breaks it runs through, which it is drawn notched across. */
  broken: boolean;
}

/** One wait on the user, on the column of the agent that raised it. */
export interface SequenceWait {
  index: number;
  column: number;
  y0: number;
  y1: number;
}

/** A stretch of the clock with no event in it, drawn short. */
export interface SequenceBreak {
  y0: number;
  y1: number;
  ms: number;
}

/** Calls one agent made at once, framed together. */
export interface SequenceGroup {
  calls: number[];
  from: number;
  /** The columns its arrows reach, leftmost and rightmost. */
  minColumn: number;
  maxColumn: number;
  y0: number;
  y1: number;
}

export interface SequenceLayout {
  columns: (string | null)[];
  calls: SequenceCall[];
  groups: SequenceGroup[];
  turns: SequenceTurn[];
  waits: SequenceWait[];
  breaks: SequenceBreak[];
  /** How many turns of one agent overlap at most — the slots its column needs. */
  slots: number[];
  height: number;
  /** The run's clock at a height, for the axis. */
  timeAt: (y: number) => number;
  /** A height on the clock. */
  yAt: (t: number) => number;
}

interface Point {
  t: number;
  /** A row that carries an arrow, and so needs room of its own. */
  row: boolean;
  key: string;
}

/**
 * Where everything on the sequence diagram sits.
 *
 * Time runs down in proportion to the clock, with two exceptions that keep the
 * picture readable: every arrow gets a row of its own at least
 * {@link SEQUENCE_ROW_MIN} below the last, so two calls made in the same
 * second never print over each other; and a stretch with no event in it longer
 * than {@link SEQUENCE_BREAK_MS} is drawn {@link SEQUENCE_BREAK_PX} tall and
 * marked as a break, so a night between two bursts of work does not push the
 * second one off the screen. Turns follow the same clock, so a turn and the
 * arrow that started it begin on one row.
 */
export function sequenceLayout(
  data: RunWaterfallDto,
  view: ClockWindow,
  scale: number,
): SequenceLayout {
  const columns = data.lanes.map((lane) => lane.memberId);
  const columnOf = (memberId: string | null): number => {
    const at = columns.indexOf(memberId);
    return at < 0 ? 0 : at;
  };
  const inView = (start: number, end: number): boolean =>
    end >= view.from && start <= view.to;
  const clip = (t: number): number => Math.min(view.to, Math.max(view.from, t));

  const points: Point[] = [];
  data.turns.forEach((turn, index) => {
    const start = Date.parse(turn.startedAt);
    const end = endOf(turn);
    if (Number.isFinite(start) && inView(start, end)) {
      points.push({ t: clip(start), row: false, key: `t${index}s` });
      points.push({ t: clip(end), row: false, key: `t${index}e` });
    }
  });
  data.waits.forEach((wait, index) => {
    const start = Date.parse(wait.startedAt);
    const end = start + wait.durationMs;
    if (Number.isFinite(start) && inView(start, end)) {
      points.push({ t: clip(start), row: false, key: `w${index}s` });
      points.push({ t: clip(end), row: false, key: `w${index}e` });
    }
  });
  data.calls.forEach((call, index) => {
    const start = Date.parse(call.startedAt);
    const end = start + call.durationMs;
    if (!Number.isFinite(start)) {
      return;
    }
    if (start >= view.from && start <= view.to) {
      points.push({ t: start, row: true, key: `c${index}` });
    }
    if (
      blocksCaller(call) &&
      !call.running &&
      end >= view.from &&
      end <= view.to
    ) {
      points.push({ t: end, row: true, key: `b${index}` });
    }
  });
  points.sort((a, b) => a.t - b.t || Number(a.row) - Number(b.row));

  // Parallel groups: calls one agent made within SEQUENCE_PARALLEL_MS of the
  // group's first, with no other arrow's row between them.
  const groupOf = new Map<number, number>();
  const members: number[][] = [];
  let open: { caller: string | null; at: number; calls: number[] } | null =
    null;
  const close = (): void => {
    if (open !== null && open.calls.length > 1) {
      const id = members.length;
      members.push(open.calls);
      open.calls.forEach((index) => groupOf.set(index, id));
    }
    open = null;
  };
  for (const point of points) {
    if (!point.row) {
      continue;
    }
    if (!point.key.startsWith('c')) {
      close();
      continue;
    }
    const index = Number(point.key.slice(1));
    const caller = data.calls[index]!.callerMemberId;
    if (
      open !== null &&
      open.caller === caller &&
      point.t - open.at <= SEQUENCE_PARALLEL_MS
    ) {
      open.calls.push(index);
    } else {
      close();
      open = { caller, at: point.t, calls: [index] };
    }
  }
  close();
  const firstOfGroup = new Set(members.map((calls) => `c${calls[0]}`));
  const lastOfGroup = new Set(
    members.map((calls) => `c${calls[calls.length - 1]}`),
  );

  const pxPerMs = (SEQUENCE_PX_PER_MIN * scale) / 60_000;
  const times: number[] = [];
  const ys: number[] = [];
  const rowY = new Map<string, number>();
  const breaks: SequenceBreak[] = [];
  let y = TOP_PAD;
  let floor = TOP_PAD;
  let lastRow = -Infinity;
  let lastRowKey = '';
  let previous: number | null = null;
  for (const point of points) {
    if (previous !== null) {
      const gap = point.t - previous;
      if (gap > SEQUENCE_BREAK_MS) {
        breaks.push({ y0: y, y1: y + SEQUENCE_BREAK_PX, ms: gap });
        y += SEQUENCE_BREAK_PX;
        floor = y;
      } else {
        y += gap * pxPerMs;
      }
    }
    if (point.row) {
      const pad =
        (firstOfGroup.has(point.key) ? GROUP_PAD_TOP : 0) +
        (lastOfGroup.has(lastRowKey) ? GROUP_PAD_BOTTOM : 0);
      y = Math.max(
        y,
        lastRow + SEQUENCE_ROW_MIN + pad,
        firstOfGroup.has(point.key) ? floor + GROUP_PAD_TOP + 14 : 0,
      );
      lastRow = y;
      lastRowKey = point.key;
      rowY.set(point.key, y);
    }
    times.push(point.t);
    ys.push(y);
    previous = point.t;
  }

  const yAt = (t: number): number => {
    if (times.length === 0) {
      return TOP_PAD;
    }
    let lo = 0;
    let hi = times.length - 1;
    if (t <= times[0]!) {
      return ys[0]!;
    }
    if (t >= times[hi]!) {
      return ys[hi]!;
    }
    while (hi - lo > 1) {
      const mid = (lo + hi) >> 1;
      if (times[mid]! <= t) {
        lo = mid;
      } else {
        hi = mid;
      }
    }
    const span = times[hi]! - times[lo]!;
    return span <= 0
      ? ys[lo]!
      : ys[lo]! + ((t - times[lo]!) / span) * (ys[hi]! - ys[lo]!);
  };
  const timeAt = (at: number): number => {
    if (ys.length === 0) {
      return view.from;
    }
    let lo = 0;
    let hi = ys.length - 1;
    if (at <= ys[0]!) {
      return times[0]!;
    }
    if (at >= ys[hi]!) {
      return times[hi]!;
    }
    while (hi - lo > 1) {
      const mid = (lo + hi) >> 1;
      if (ys[mid]! <= at) {
        lo = mid;
      } else {
        hi = mid;
      }
    }
    const span = ys[hi]! - ys[lo]!;
    return span <= 0
      ? times[lo]!
      : times[lo]! + ((at - ys[lo]!) / span) * (times[hi]! - times[lo]!);
  };

  // Slots are decided on the CLOCK, not on the drawn height: a run of short
  // turns one after another is one slot, however small each is drawn.
  const slotEnds = columns.map(() => [] as number[]);
  const turns: SequenceTurn[] = [];
  data.turns
    .map((turn, index) => ({ turn, index }))
    .filter(({ turn }) => {
      const start = Date.parse(turn.startedAt);
      return Number.isFinite(start) && inView(start, endOf(turn));
    })
    .sort((a, b) => Date.parse(a.turn.startedAt) - Date.parse(b.turn.startedAt))
    .forEach(({ turn, index }) => {
      const column = columnOf(turn.memberId);
      const start = Date.parse(turn.startedAt);
      const end = endOf(turn);
      const y0 = yAt(clip(start));
      const y1 = Math.max(y0 + 3, yAt(clip(end)));
      const ends = slotEnds[column]!;
      const free = ends.findIndex((ended) => ended <= start);
      const slot = free < 0 ? ends.length : free;
      ends[slot] = end;
      turns.push({
        index,
        column,
        slot,
        y0,
        y1,
        broken: breaks.some((cut) => cut.y0 >= y0 && cut.y1 <= y1),
      });
    });

  const slotOf = new Map(turns.map((turn) => [turn.index, turn.slot]));
  const turnAt = (memberId: string | null, at: number): number | undefined => {
    let found: number | undefined;
    data.turns.forEach((turn, index) => {
      const start = Date.parse(turn.startedAt);
      if (
        turn.memberId === memberId &&
        start <= at + 1000 &&
        endOf(turn) >= at - 1000 &&
        slotOf.has(index)
      ) {
        found = index;
      }
    });
    return found;
  };
  const numberOf = new Map(
    data.calls
      .map((call, index) => ({ at: Date.parse(call.startedAt), index }))
      .sort((a, b) => a.at - b.at || a.index - b.index)
      .map(({ index }, order) => [index, order + 1]),
  );
  const calls: SequenceCall[] = [];
  data.calls.forEach((call, index) => {
    const at = rowY.get(`c${index}`);
    if (at === undefined) {
      return;
    }
    const answering = data.turns
      .map((turn, turnIndex) => ({ turn, turnIndex }))
      .filter(
        ({ turn, turnIndex }) =>
          turn.callId !== null &&
          turn.callId === call.callId &&
          slotOf.has(turnIndex),
      );
    const first = answering[0]?.turnIndex;
    const last = answering[answering.length - 1]?.turnIndex;
    const caller = turnAt(call.callerMemberId, Date.parse(call.startedAt));
    calls.push({
      index,
      number: numberOf.get(index) ?? index + 1,
      from: columnOf(call.callerMemberId),
      to: columnOf(call.calleeMemberId),
      fromSlot: caller === undefined ? 0 : (slotOf.get(caller) ?? 0),
      toSlot: first === undefined ? 0 : (slotOf.get(first) ?? 0),
      backSlot: last === undefined ? 0 : (slotOf.get(last) ?? 0),
      y: at,
      backY: rowY.get(`b${index}`) ?? null,
    });
  });

  const waits: SequenceWait[] = [];
  data.waits.forEach((wait, index) => {
    const start = Date.parse(wait.startedAt);
    const end = start + wait.durationMs;
    if (!Number.isFinite(start) || !inView(start, end)) {
      return;
    }
    const y0 = yAt(clip(start));
    waits.push({
      index,
      column: columnOf(wait.memberId),
      y0,
      y1: Math.max(y0 + 3, yAt(clip(end))),
    });
  });

  const placedCall = new Map(calls.map((call) => [call.index, call]));
  const groups: SequenceGroup[] = members.flatMap((indices) => {
    const placed = indices
      .map((index) => placedCall.get(index))
      .filter((call): call is SequenceCall => call !== undefined);
    const first = placed[0];
    const last = placed[placed.length - 1];
    if (first === undefined || last === undefined) {
      return [];
    }
    const reach = placed.flatMap((call) => [call.from, call.to]);
    return [
      {
        calls: indices,
        from: first.from,
        minColumn: Math.min(...reach),
        maxColumn: Math.max(...reach),
        y0: first.y - GROUP_PAD_TOP - 4,
        y1: last.y + GROUP_PAD_BOTTOM - 2,
      },
    ];
  });

  return {
    columns,
    calls,
    groups,
    turns,
    waits,
    breaks,
    slots: slotEnds.map((ends) => Math.max(1, ends.length)),
    height: (ys[ys.length - 1] ?? TOP_PAD) + TOP_PAD * 2,
    timeAt,
    yAt,
  };
}
