import { useId, useLayoutEffect, useMemo, useRef, useState } from 'react';

import type { RunWaterfallDto } from '../autogenerated';
import { cn } from '../components/ui/utils';
import { categoryToken } from '../stats/charts/chart-theme';
import { formatDuration, NOT_MEASURED } from '../stats/stats-format';
import { costEstimateTitle, formatUsd, markEstimate } from './agent-activity';
import {
  HoverTip,
  type MarkTip,
  turnRows,
  turnTipTitle,
} from './run-waterfall-gantt';
import {
  callFailed,
  type ClockWindow,
  endOf,
  onCriticalPath,
  sameMark,
  type WaterfallMark,
} from './run-waterfall-geometry';
import {
  type SequenceLayout,
  sequenceLayout,
} from './run-waterfall-sequence-layout';
import { formatDuration as formatTurnDuration } from './turn-duration';

/** The time axis' width on the left, in pixels. */
const GUTTER = 76;

/** A turn bar's width, and how far a turn of one agent running beside another is set off it. */
const BAR = 10;
const NEST = 4;

/** A call number's badge radius, and where the call's words start past it. */
const BADGE = 7;
const WORDS_FROM = 2 * BADGE + 6;

const ARROW_TONES = ['quiet', 'strong', 'failed'] as const;
const ARROW_STROKE: Record<(typeof ARROW_TONES)[number], string> = {
  quiet: 'var(--color-muted-foreground)',
  strong: 'var(--color-foreground)',
  failed: 'var(--color-destructive)',
};

/** How often the axis carries a time, in pixels. */
const TICK_EVERY = 96;

/** The narrowest column, in pixels; past it the diagram scrolls sideways. */
const COLUMN_MIN = 132;

/**
 * The run as a sequence diagram: one column per agent, time running down.
 *
 * A call is a numbered horizontal arrow from the caller's turn to the callee's
 * at the moment it was made, named and timed at its tail; a call its caller
 * waited on comes back as a dashed arrow under the same number when it was
 * answered. Arrows are one quiet colour, so the agents' colours stay on their
 * columns. Each arrow has a row of its own (`sequenceLayout`), so arrows and
 * their words never overlap, calls one agent made at once are framed together,
 * and a long stretch with no event in it is drawn as a short break. The bars on
 * a column are that agent's turns, stacked a few pixels apart when it ran
 * several at once; amber marks are the cards it waited on the user for.
 *
 * Pointing at an arrow or a turn lights it and what it is tied to — the turns
 * that answered a call (`RunWaterfallTurn.callId`), the calls a turn made —
 * and a click selects it for the detail panel.
 */
export function SequenceDiagram({
  data,
  runFrom,
  window: view,
  selected,
  onSelect,
  focus,
  onFocus,
  critical,
  scale = 1,
}: {
  data: RunWaterfallDto;
  runFrom: number;
  window: ClockWindow;
  selected: WaterfallMark | null;
  onSelect: (mark: WaterfallMark | null) => void;
  focus: string | null | undefined;
  onFocus: (memberId: string | null | undefined) => void;
  critical: boolean;
  scale?: number;
}): React.JSX.Element {
  const layout = useMemo(
    () => sequenceLayout(data, view, scale),
    [data, view, scale],
  );
  const boxRef = useRef<HTMLDivElement>(null);
  const [width, setWidth] = useState(0);
  useLayoutEffect(() => {
    const box = boxRef.current;
    if (box === null) {
      return;
    }
    setWidth(box.clientWidth);
    if (typeof ResizeObserver === 'undefined') {
      return;
    }
    const observer = new ResizeObserver(() => setWidth(box.clientWidth));
    observer.observe(box);
    return () => observer.disconnect();
  }, []);
  const [hovered, setHovered] = useState<WaterfallMark | null>(null);
  const [tip, setTip] = useState<MarkTip | null>(null);
  const markerId = useId();

  const count = Math.max(1, layout.columns.length);
  const columnWidth = Math.max(COLUMN_MIN, (width - GUTTER) / count);
  const totalWidth = GUTTER + columnWidth * count;
  const centre = (column: number): number =>
    GUTTER + columnWidth * (column + 0.5);
  const barX = (column: number, slot: number): number =>
    centre(column) - BAR / 2 + slot * NEST;
  const stackReach = (column: number): number =>
    BAR / 2 + ((layout.slots[column] ?? 1) - 1) * NEST;

  const active = selected ?? hovered;
  const lit = useMemo(
    () => litOf(data, layout, active),
    [data, layout, active],
  );
  const faded = (memberIds: (string | null)[]): boolean =>
    focus !== undefined && !memberIds.includes(focus);

  const ticks: { y: number; label: string }[] = [];
  for (let at = 16; at < layout.height - 16; at += TICK_EVERY) {
    if (layout.breaks.some((cut) => at >= cut.y0 - 8 && at <= cut.y1 + 8)) {
      continue;
    }
    const label = formatDuration(layout.timeAt(at) - runFrom);
    if (ticks[ticks.length - 1]?.label !== label) {
      ticks.push({ y: at, label });
    }
  }

  const hover =
    (mark: WaterfallMark, title: string, rows: MarkTip['rows']) =>
    (event: React.MouseEvent): void => {
      setHovered(mark);
      setTip({ clientX: event.clientX, clientY: event.clientY, title, rows });
    };
  const leave = (): void => {
    setHovered(null);
    setTip(null);
  };
  const select =
    (mark: WaterfallMark) =>
    (event: React.MouseEvent): void => {
      event.stopPropagation();
      onSelect(sameMark(selected, mark) ? null : mark);
    };

  const edge = (column: number, slot: number, side: 1 | -1): number =>
    side === 1 ? barX(column, slot) + BAR : barX(column, slot);
  const arrowOf = (placed: SequenceLayout['calls'][number]) => {
    const call = data.calls[placed.index]!;
    const mark: WaterfallMark = { kind: 'call', index: placed.index };
    const active =
      selected !== null || hovered !== null
        ? (() => {
            const on = selected ?? hovered;
            return (
              on !== null &&
              (on.kind === 'call' || on.kind === 'blocked') &&
              on.index === placed.index
            );
          })()
        : false;
    const isLit = lit === null || lit.calls.has(placed.index);
    const strong = active || (lit !== null && lit.calls.has(placed.index));
    const failed = callFailed(call);
    const dir: 1 | -1 = placed.to >= placed.from ? 1 : -1;
    const callee = call.calleeMemberId ?? 'agent';
    const took = formatTurnDuration(call.durationMs);
    const tone = failed ? 'failed' : strong ? 'strong' : 'quiet';
    return {
      mark,
      active,
      strong,
      failed,
      dir,
      running: call.running,
      dim: faded([call.callerMemberId, call.calleeMemberId]) || !isLit,
      stroke: ARROW_STROKE[tone],
      head: `${markerId}-${tone}`,
      tail: edge(placed.from, placed.fromSlot, dir) + dir * 2,
      tip: edge(placed.to, placed.toSlot, dir === 1 ? -1 : 1) - dir,
      backFrom: edge(placed.to, placed.backSlot, dir === 1 ? -1 : 1) - dir * 2,
      backTo: edge(placed.from, placed.fromSlot, dir) + dir,
      title: `${call.callerMemberId ?? 'agent'} called ${callee}`,
      words: [
        callee,
        call.running ? 'running' : formatDuration(call.durationMs),
        ...(call.mode === 'async' ? [] : ['waits']),
        ...(failed ? [call.status ?? 'failed'] : []),
      ].join(' · '),
      rows: [
        { label: 'mode', value: call.mode ?? '—' },
        {
          label: 'outcome',
          value: call.running ? 'still running' : (call.status ?? '—'),
        },
        { label: call.running ? 'so far' : 'took', value: took },
        {
          label: 'at',
          value: formatTurnDuration(Date.parse(call.startedAt) - runFrom),
        },
      ] satisfies MarkTip['rows'],
    };
  };

  return (
    <div
      ref={boxRef}
      data-slot="waterfall-sequence"
      className="relative max-h-[72vh] overflow-auto rounded-xl border border-border bg-card"
      onMouseLeave={leave}>
      {tip === null ? null : <HoverTip tip={tip} />}
      <div
        className="sticky top-0 z-20 grid border-b border-border bg-card"
        style={{
          width: totalWidth,
          gridTemplateColumns: `${GUTTER}px repeat(${count}, ${columnWidth}px)`,
        }}>
        <div />
        {data.lanes.map((lane, index) => (
          <button
            key={lane.memberId ?? '\u0000chat'}
            type="button"
            data-slot="waterfall-sequence-head"
            aria-pressed={focus === lane.memberId}
            title={
              focus === lane.memberId ? 'Show every agent' : 'Focus this agent'
            }
            onClick={() =>
              onFocus(focus === lane.memberId ? undefined : lane.memberId)
            }
            className={cn(
              'flex min-w-0 flex-col items-center gap-0.5 px-2 py-2.5 transition-opacity hover:bg-muted',
              focus === lane.memberId && 'bg-muted',
              faded([lane.memberId]) && 'opacity-40',
            )}>
            <span className="flex min-w-0 items-center gap-1.5">
              <span
                aria-hidden="true"
                className="size-2 shrink-0 rounded-[2px]"
                style={{ backgroundColor: categoryToken(index) }}
              />
              <span className="truncate text-sm font-medium text-foreground">
                {lane.memberId ?? 'agent'}
              </span>
            </span>
            <span
              className="text-[11px] tabular-nums text-muted-foreground"
              title={costEstimateTitle(lane.costUsd, lane.estimatedCostUsd)}>
              {lane.costUsd === null
                ? NOT_MEASURED
                : markEstimate(
                    formatUsd(lane.costUsd),
                    lane.estimatedCostUsd,
                  )}{' '}
              · {lane.turns} {lane.turns === 1 ? 'turn' : 'turns'}
            </span>
          </button>
        ))}
      </div>

      <svg
        width={totalWidth}
        height={layout.height}
        className="block"
        onClick={() => onSelect(null)}>
        <defs>
          {ARROW_TONES.map((tone) => (
            <marker
              key={tone}
              id={`${markerId}-${tone}`}
              viewBox="0 0 10 10"
              refX="9"
              refY="5"
              markerWidth="8"
              markerHeight="8"
              markerUnits="userSpaceOnUse"
              orient="auto">
              <path
                d="M1,1 L9,5 L1,9"
                fill="none"
                stroke={ARROW_STROKE[tone]}
                strokeWidth="1.8"
                strokeLinecap="round"
                strokeLinejoin="round"
              />
            </marker>
          ))}
        </defs>

        {layout.columns.map((memberId, column) => (
          <line
            key={memberId ?? '\u0000chat'}
            x1={centre(column)}
            x2={centre(column)}
            y1={0}
            y2={layout.height}
            stroke="var(--color-border)"
            strokeDasharray="3 4"
            opacity={faded([memberId]) ? 0.4 : 1}
          />
        ))}

        {ticks.map((tick) => (
          <text
            key={tick.y}
            x={GUTTER - 10}
            y={tick.y + 4}
            textAnchor="end"
            fontSize={10.5}
            className="fill-muted-foreground tabular-nums">
            {tick.label}
          </text>
        ))}

        {layout.breaks.map((cut) => (
          <g key={cut.y0} data-slot="waterfall-sequence-break">
            <rect
              x={0}
              y={cut.y0 + 6}
              width={totalWidth}
              height={cut.y1 - cut.y0 - 12}
              className="fill-muted/60"
            />
            <text
              x={GUTTER - 10}
              y={(cut.y0 + cut.y1) / 2 + 4}
              textAnchor="end"
              fontSize={10.5}
              className="fill-muted-foreground tabular-nums">
              ⋯ {formatDuration(cut.ms)}
            </text>
          </g>
        ))}

        {layout.groups.map((group) => {
          const left =
            centre(group.minColumn) - stackReach(group.minColumn) - 24;
          const right =
            centre(group.maxColumn) + stackReach(group.maxColumn) + 24;
          const words = `${group.calls.length} at once`;
          const tagWidth = words.length * 5.6 + 12;
          const tagX =
            (centre(group.minColumn) +
              centre(Math.min(group.maxColumn, group.minColumn + 1))) /
              2 -
            tagWidth / 2;
          return (
            <g key={`g-${group.calls[0]}`} data-slot="waterfall-sequence-group">
              <rect
                x={left}
                y={group.y0}
                width={right - left}
                height={group.y1 - group.y0}
                rx={6}
                strokeDasharray="4 3"
                className="fill-muted/30 stroke-border"
              />
              <rect
                x={tagX}
                y={group.y0 - 7}
                width={tagWidth}
                height={14}
                rx={7}
                className="fill-card stroke-border"
              />
              <text
                x={tagX + tagWidth / 2}
                y={group.y0 + 3.5}
                textAnchor="middle"
                fontSize={10}
                className="fill-muted-foreground tabular-nums">
                {words}
              </text>
            </g>
          );
        })}

        {layout.waits.map((wait) => {
          const mark: WaterfallMark = { kind: 'wait', index: wait.index };
          const item = data.waits[wait.index];
          return (
            <rect
              key={`w-${wait.index}`}
              data-slot="waterfall-sequence-wait"
              x={barX(wait.column, 0) - 12}
              y={wait.y0}
              width={8}
              height={Math.max(8, wait.y1 - wait.y0)}
              rx={4}
              strokeWidth={1.5}
              className={cn(
                'cursor-pointer fill-warning/25 stroke-warning transition-opacity',
                lit !== null && !sameMark(active, mark) && 'opacity-25',
              )}
              onClick={select(mark)}
              onMouseMove={hover(mark, 'waiting on you', [
                {
                  label: 'card',
                  value: item?.question
                    ? 'a question'
                    : (item?.toolName ?? '—'),
                },
                {
                  label: 'took',
                  value: formatTurnDuration(item?.durationMs ?? 0),
                },
              ])}
            />
          );
        })}

        {layout.turns.map((placed) => {
          const turn = data.turns[placed.index]!;
          const mark: WaterfallMark = { kind: 'turn', index: placed.index };
          const name = turn.memberId ?? 'agent';
          const offPath =
            critical &&
            !onCriticalPath(
              data.criticalPath,
              'work',
              turn.memberId,
              Date.parse(turn.startedAt),
              endOf(turn),
            );
          const dim =
            faded([turn.memberId]) ||
            offPath ||
            (lit !== null && !lit.turns.has(placed.index));
          const x = barX(placed.column, placed.slot);
          const pieces = placed.broken
            ? splitByBreaks(placed.y0, placed.y1, layout)
            : [[placed.y0, placed.y1] as const];
          return (
            <g
              key={`t-${placed.index}`}
              data-slot="waterfall-turn"
              data-mark={`turn-${placed.index}`}
              className={cn(
                'cursor-pointer transition-opacity',
                dim && 'opacity-25',
              )}
              onClick={select(mark)}
              onMouseMove={hover(
                mark,
                turnTipTitle(name, turn),
                turnRows(turn, runFrom),
              )}>
              {pieces.map(([y0, y1]) => (
                <rect
                  key={y0}
                  x={x}
                  y={y0}
                  width={BAR}
                  height={Math.max(3, y1 - y0)}
                  rx={2}
                  fill={categoryToken(placed.column)}
                  className={cn(
                    turn.outcome === 'failed'
                      ? 'stroke-destructive'
                      : 'stroke-card',
                    turn.outcome === 'running' &&
                      'animate-pulse motion-reduce:animate-none',
                  )}
                  strokeWidth={
                    turn.outcome === 'failed' ? 1.5 : placed.slot > 0 ? 1.5 : 0
                  }
                  opacity={turn.outcome === 'cancelled' ? 0.45 : 1}
                />
              ))}
              {sameMark(selected, mark) ? (
                <rect
                  x={x - 3}
                  y={placed.y0 - 3}
                  width={BAR + 6}
                  height={Math.max(3, placed.y1 - placed.y0) + 6}
                  rx={5}
                  fill="none"
                  className="stroke-foreground"
                  strokeWidth={1.5}
                />
              ) : null}
            </g>
          );
        })}

        {layout.calls.map((placed) => {
          const arrow = arrowOf(placed);
          return (
            <g
              key={`l-${placed.index}`}
              data-slot="waterfall-call-line"
              data-call={placed.index}
              className={cn('transition-opacity', arrow.dim && 'opacity-20')}>
              <line
                x1={arrow.tail}
                x2={arrow.tip}
                y1={placed.y}
                y2={placed.y}
                stroke={arrow.stroke}
                strokeWidth={arrow.strong ? 2 : 1.5}
                strokeLinecap="round"
                markerEnd={`url(#${arrow.head})`}
                className={cn(
                  arrow.running && 'animate-pulse motion-reduce:animate-none',
                )}
              />
              {placed.backY === null ? null : (
                <line
                  x1={arrow.backFrom}
                  x2={arrow.backTo}
                  y1={placed.backY}
                  y2={placed.backY}
                  stroke={arrow.stroke}
                  strokeWidth={arrow.strong ? 1.75 : 1.25}
                  strokeDasharray="4 4"
                  strokeLinecap="round"
                  markerEnd={`url(#${arrow.head})`}
                />
              )}
            </g>
          );
        })}

        {layout.calls.map((placed) => {
          const arrow = arrowOf(placed);
          const badge = (x: number, y: number) => (
            <g data-slot="waterfall-call-number">
              <circle
                cx={x}
                cy={y}
                r={BADGE}
                strokeWidth={arrow.strong ? 1.5 : 1}
                className="fill-card"
                stroke={arrow.stroke}
              />
              <text
                x={x}
                y={y + 3.25}
                textAnchor="middle"
                fontSize={9}
                fontWeight={600}
                className={cn(
                  'tabular-nums',
                  arrow.failed
                    ? 'fill-destructive'
                    : arrow.strong
                      ? 'fill-foreground'
                      : 'fill-muted-foreground',
                )}>
                {placed.number}
              </text>
            </g>
          );
          return (
            <g
              key={`c-${placed.index}`}
              data-slot="waterfall-call"
              data-mark={`call-${placed.index}`}
              data-y={placed.y}
              className={cn(
                'cursor-pointer transition-opacity',
                arrow.dim && 'opacity-20',
              )}
              onClick={select(arrow.mark)}
              onMouseMove={hover(arrow.mark, arrow.title, arrow.rows)}>
              <line
                x1={Math.min(arrow.tail, arrow.tip) - 4}
                x2={Math.max(arrow.tail, arrow.tip) + 4}
                y1={placed.y}
                y2={placed.y}
                stroke="transparent"
                strokeWidth={14}
              />
              {placed.backY === null ? null : (
                <line
                  x1={Math.min(arrow.backFrom, arrow.backTo) - 4}
                  x2={Math.max(arrow.backFrom, arrow.backTo) + 4}
                  y1={placed.backY}
                  y2={placed.backY}
                  stroke="transparent"
                  strokeWidth={14}
                />
              )}
              {badge(arrow.tail + arrow.dir * BADGE, placed.y)}
              {placed.backY === null
                ? null
                : badge(arrow.backFrom - arrow.dir * BADGE, placed.backY)}
              <text
                data-slot="waterfall-call-words"
                x={arrow.tail + arrow.dir * WORDS_FROM}
                y={placed.y - 6}
                textAnchor={arrow.dir === 1 ? 'start' : 'end'}
                fontSize={11}
                className={cn(
                  'tabular-nums',
                  arrow.failed ? 'fill-destructive' : 'fill-foreground',
                )}
                style={{
                  paintOrder: 'stroke',
                  stroke: 'var(--color-card)',
                  strokeWidth: 4,
                  strokeLinejoin: 'round',
                }}>
                {arrow.words}
              </text>
            </g>
          );
        })}
      </svg>
    </div>
  );
}

/** A turn's span with the breaks it runs through cut out of it. */
function splitByBreaks(
  y0: number,
  y1: number,
  layout: SequenceLayout,
): (readonly [number, number])[] {
  const pieces: [number, number][] = [];
  let from = y0;
  for (const cut of layout.breaks) {
    if (cut.y0 >= from && cut.y1 <= y1) {
      pieces.push([from, cut.y0 + 4]);
      from = cut.y1 - 4;
    }
  }
  pieces.push([from, y1]);
  return pieces;
}

/**
 * What a mark lights: a call lights itself and the turns that answered it; a
 * turn lights itself, the call it answered and every call it made. Null when
 * nothing is pointed at or selected.
 */
function litOf(
  data: RunWaterfallDto,
  layout: SequenceLayout,
  mark: WaterfallMark | null,
): { calls: Set<number>; turns: Set<number> } | null {
  if (mark === null || mark.kind === 'wait' || mark.kind === 'delegate') {
    return null;
  }
  const calls = new Set<number>();
  const turns = new Set<number>();
  const answering = (callIndex: number): void => {
    const call = data.calls[callIndex];
    if (call === undefined) {
      return;
    }
    calls.add(callIndex);
    data.turns.forEach((turn, index) => {
      if (turn.callId !== null && turn.callId === call.callId) {
        turns.add(index);
      }
    });
  };
  if (mark.kind === 'call' || mark.kind === 'blocked') {
    answering(mark.index);
    const call = data.calls[mark.index];
    const at = call === undefined ? NaN : Date.parse(call.startedAt);
    data.turns.forEach((turn, index) => {
      if (
        call !== undefined &&
        turn.memberId === call.callerMemberId &&
        Date.parse(turn.startedAt) <= at + 1000 &&
        endOf(turn) >= at - 1000
      ) {
        turns.add(index);
      }
    });
    return { calls, turns };
  }
  const turn = data.turns[mark.index];
  if (turn === undefined) {
    return null;
  }
  turns.add(mark.index);
  const start = Date.parse(turn.startedAt);
  const end = endOf(turn);
  data.calls.forEach((call, index) => {
    const at = Date.parse(call.startedAt);
    if (call.callId === turn.callId) {
      calls.add(index);
    }
    if (
      call.callerMemberId === turn.memberId &&
      at >= start - 1000 &&
      at <= end + 1000
    ) {
      answering(index);
    }
  });
  return layout.turns.length === 0 ? null : { calls, turns };
}
