// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { stubResizeObserver } from '../__tests__/stub-resize-observer';
import type { RunWaterfallDto, RunWaterfallLane } from '../autogenerated';
import { RunWaterfallPopup } from './run-waterfall';

stubResizeObserver();

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const FROM = '2026-09-07T12:00:00.000Z';
const TO = '2026-09-07T13:00:00.000Z';
/** A section heading only the FULL view draws. */
const FULL_VIEW_HEADING = 'Who worked when, and what it cost';

function lane(over: Partial<RunWaterfallLane> = {}): RunWaterfallLane {
  return {
    nodeId: 'engineer',
    agentKind: 'claude',
    costUsd: 12.5,
    estimatedCostUsd: null,
    turns: 2,
    toolCalls: 40,
    delegateToolCalls: 0,
    workedMs: 600_000,
    ...over,
  };
}

function dto(over: Partial<RunWaterfallDto> = {}): RunWaterfallDto {
  return {
    from: FROM,
    to: TO,
    lanes: [lane()],
    toolUse: [],
    turns: [],
    calls: [],
    waits: [],
    delegates: [],
    criticalPath: [],
    totals: {
      turns: 2,
      costedTurns: 2,
      costUsd: 12.5,
      estimatedCostUsd: null,
      inputTokens: null,
      outputTokens: null,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      thinkingTokens: null,
      workedMs: 600_000,
    },
    waitedOnUserMs: null,
    partialReason: null,
    ...over,
  };
}

let root: Root | null = null;
let host: HTMLDivElement | null = null;

function show(
  data: RunWaterfallDto | null,
  state: { loading?: boolean; error?: string | null; open?: boolean } = {},
  onClose: () => void = () => {},
): HTMLElement {
  const { loading = false, error = null, open = true } = state;
  host = document.createElement('div');
  document.body.append(host);
  root = createRoot(host);
  act(() => {
    root?.render(
      <RunWaterfallPopup
        open={open}
        onClose={onClose}
        state={{ data, loading, error }}
      />,
    );
  });
  return document.body;
}

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
  localStorage.clear();
});

describe('RunWaterfallPopup', () => {
  it('opens straight into the full view once the run has something to draw', () => {
    const view = show(dto());

    expect(view.querySelector('[role="dialog"]')).not.toBeNull();
    expect(view.textContent).toContain(FULL_VIEW_HEADING);
  });

  it('draws nothing while it is closed', () => {
    const view = show(dto(), { open: false });

    expect(view.querySelector('[role="dialog"]')).toBeNull();
  });

  it('says it is reading while the first read is still out', () => {
    const view = show(null, { loading: true });

    expect(view.textContent).toContain('reading the run…');
    expect(view.textContent).not.toContain(FULL_VIEW_HEADING);
  });

  it('says it is reading on the frame before the read has started', () => {
    // The owner raises `loading` from an effect, so the popup's first frame
    // has neither data nor a read in flight — that is not "nothing has run".
    const view = show(null);

    expect(view.textContent).toContain('reading the run…');
    expect(view.textContent).not.toContain('nothing has run');
  });

  it('shows the failure instead of an empty view, even over an older read', () => {
    const view = show(dto(), { error: 'could not read this run — timed out' });

    expect(view.textContent).toContain('could not read this run — timed out');
    expect(view.textContent).not.toContain(FULL_VIEW_HEADING);
  });

  it('says a thread has not run rather than opening an empty clock', () => {
    const view = show(dto({ lanes: [] }));

    expect(view.textContent).toContain('nothing has run in this thread yet');
    expect(view.textContent).not.toContain(FULL_VIEW_HEADING);
  });

  it('closes from its own ✕ in the small popup too', () => {
    const onClose = vi.fn();
    const view = show(null, { loading: true }, onClose);

    act(() => {
      view
        .querySelector<HTMLButtonElement>('button[aria-label="Close"]')!
        .click();
    });

    expect(onClose).toHaveBeenCalledTimes(1);
  });
});
