// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type {
  RunWaterfallCall,
  RunWaterfallDto,
  RunWaterfallLane,
  RunWaterfallTurn,
} from '../autogenerated';
import { RunWaterfall } from './run-waterfall';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const FROM = '2026-09-07T12:00:00.000Z';
const TO = '2026-09-07T13:00:00.000Z';
const SPAN_MS = 60 * 60 * 1000;

function lane(over: Partial<RunWaterfallLane> = {}): RunWaterfallLane {
  return {
    nodeId: 'engineer',
    agentKind: 'claude',
    costUsd: 12.5,
    turns: 2,
    toolCalls: 40,
    workedMs: 600_000,
    toolBuckets: [0, 3, 0],
    ...over,
  };
}

function turn(over: Partial<RunWaterfallTurn> = {}): RunWaterfallTurn {
  return {
    nodeId: 'engineer',
    startedAt: FROM,
    durationMs: 60_000,
    apiMs: null,
    ttftMs: null,
    timeToRequestMs: null,
    numTurns: null,
    costUsd: 1,
    model: 'opus-5',
    inputTokens: null,
    outputTokens: null,
    cacheReadTokens: null,
    contextTokens: null,
    contextWindowTokens: null,
    ...over,
  };
}

function call(status: string): RunWaterfallCall {
  return {
    callerNodeId: 'manager',
    calleeNodeId: 'qa',
    mode: 'async',
    status,
    startedAt: FROM,
    durationMs: 1_000,
  };
}

function dto(over: Partial<RunWaterfallDto> = {}): RunWaterfallDto {
  return {
    from: FROM,
    to: TO,
    lanes: [lane()],
    turns: [],
    calls: [],
    waits: [],
    delegates: [],
    totals: {
      turns: 2,
      costedTurns: 2,
      costUsd: 12.5,
      inputTokens: null,
      outputTokens: null,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      thinkingTokens: null,
      workedMs: 600_000,
    },
    waitedOnUserMs: null,
    partialReason: null,
    ...over,
  };
}

let root: Root | null = null;
let host: HTMLDivElement | null = null;

function show(
  data: RunWaterfallDto | null,
  state: { loading?: boolean; error?: string | null } = {},
): HTMLDivElement {
  const { loading = false, error = null } = state;
  host = document.createElement('div');
  document.body.append(host);
  root = createRoot(host);
  act(() => {
    root?.render(<RunWaterfall data={data} loading={loading} error={error} />);
  });
  return host;
}

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
});

describe('RunWaterfall', () => {
  it('says a lane priced nothing instead of drawing it as free', () => {
    // The RENDER half of the money rule. The fold already answers null for a
    // cursor-agent lane, and a component that ran that null through a currency
    // formatter would print "$0.00" — a claim about money nothing measured,
    // with a green fold test either way.
    // `waitedOnUserMs` is given a figure on purpose: it renders an em dash of
    // its own when null, which would satisfy the assertion below from a row
    // that has nothing to do with the lane under test.
    const view = show(
      dto({
        lanes: [lane({ nodeId: 'qa', costUsd: null })],
        waitedOnUserMs: 60_000,
      }),
    );

    expect(view.querySelector('li')?.textContent).toContain('—');
    expect(view.textContent).not.toContain('$0.00');
  });

  it("places a turn span on the run's own clock, not on its own length", () => {
    // A span half an hour into a one-hour run belongs at the halfway mark. Get
    // the arithmetic wrong and every bar still renders, just in the wrong
    // place — which looks like a plausible picture of a different run.
    const view = show(
      dto({
        turns: [
          turn({
            startedAt: new Date(Date.parse(FROM) + SPAN_MS / 2).toISOString(),
            durationMs: SPAN_MS / 4,
          }),
        ],
      }),
    );

    const span = view.querySelector<HTMLElement>('[title*="opus-5"]');
    expect(span?.style.left).toBe('50%');
    expect(span?.style.width).toBe('25%');
  });

  it('gives a sub-second turn a visible bar rather than nothing at all', () => {
    // A one-second turn inside an hour is 0.03% wide: rendering it truthfully
    // renders it invisibly, and a lane showing no work for a turn that happened
    // is the worse lie.
    const view = show(
      dto({ turns: [turn({ model: 'haiku', durationMs: 1_000 })] }),
    );

    const span = view.querySelector<HTMLElement>('[title*="haiku"]');
    expect(
      Number.parseFloat(span?.style.width.replace('%', '') ?? '0'),
    ).toBeGreaterThan(0.5);
  });

  it('keeps a span inside the lane when it would overflow the right edge', () => {
    // A turn still running at the last recorded row would otherwise be drawn
    // past 100% and spill out of its own row.
    const view = show(
      dto({
        turns: [
          turn({
            startedAt: new Date(Date.parse(TO) - 60_000).toISOString(),
            durationMs: SPAN_MS,
          }),
        ],
      }),
    );

    const span = view.querySelector<HTMLElement>('[title*="opus-5"]');
    const left = Number.parseFloat(span?.style.left.replace('%', '') ?? '0');
    const width = Number.parseFloat(span?.style.width.replace('%', '') ?? '0');
    expect(left + width).toBeLessThanOrEqual(100);
  });

  it('draws the waiting-on-you lane only when somebody was actually asked', () => {
    expect(show(dto()).textContent).not.toContain('waiting on you');
  });

  it('draws it, and its total, once a card was raised', () => {
    const view = show(
      dto({
        waits: [
          {
            nodeId: null,
            question: true,
            toolName: 'AskUserQuestion',
            allowed: true,
            startedAt: FROM,
            durationMs: 120_000,
          },
        ],
        waitedOnUserMs: 120_000,
      }),
    );

    expect(view.textContent).toContain('waiting on you');
    expect(view.textContent).toContain('2m');
  });

  it('stays quiet when every agent-to-agent call succeeded', () => {
    expect(
      show(dto({ calls: [call('ok'), call('ok')] })).textContent,
    ).not.toContain('failed');
  });

  it('counts the calls that failed', () => {
    const view = show(
      dto({ calls: [call('ok'), call('error'), call('error')] }),
    );
    expect(view.textContent).toContain('2 of 3 agent-to-agent calls failed');
  });

  it("repeats the daemon's own sentence when the picture is capped", () => {
    // The cap has to be SAID: a thinner waterfall is otherwise indistinguishable
    // from a quieter run.
    const view = show(
      dto({ partialReason: "showing the newest 500 of this run's turns" }),
    );
    expect(view.textContent).toContain('showing the newest 500');
  });

  it('says a thread has not run rather than drawing an empty clock', () => {
    expect(show(dto({ lanes: [] })).textContent).toContain(
      'nothing has run in this thread yet',
    );
  });

  it('reads back the figures claude reports and nothing else does', () => {
    // These three ride claude's result line and were dropped for releases. The
    // card's hover is their reader: without one they would be captured into an
    // append-only ledger and validated by nothing.
    const view = show(
      dto({
        turns: [turn({ ttftMs: 1_400, timeToRequestMs: 300, numTurns: 4 })],
      }),
    );

    const title = view
      .querySelector<HTMLElement>('[title*="opus-5"]')
      ?.getAttribute('title');
    expect(title).toContain('to first token');
    expect(title).toContain('before asking');
    expect(title).toContain('4 model calls');
  });

  it('leaves out a figure the CLI never reported rather than dashing it', () => {
    // Every ACP agent reports none of the three. A hover sentence carrying
    // three em dashes reads as broken rather than as unmeasured.
    const view = show(dto({ turns: [turn()] }));

    const title = view
      .querySelector<HTMLElement>('[title*="opus-5"]')
      ?.getAttribute('title');
    expect(title).not.toContain('first token');
    expect(title).not.toContain('model call');
  });

  it('renders nothing once a read settled with no data', () => {
    expect(show(null).textContent).toBe('');
  });

  it('says it is reading while the first read is still out', () => {
    // The state the card is actually in when a panel is first unfolded — which
    // the case above does NOT arrange, whatever its old title claimed.
    expect(show(null, { loading: true }).textContent).toContain(
      'reading the run',
    );
  });

  it('shows the failure instead of an empty card', () => {
    const view = show(null, { error: 'could not read this run — timed out' });

    expect(view.textContent).toContain('could not read this run — timed out');
    expect(view.querySelector('li')).toBeNull();
  });

  it('says whose tools it counted, because the card above counts fewer', () => {
    // The fold reads the payload-free spine, so a delegate's calls land in its
    // launcher's lane — while the agent card directly above this one states
    // `Run.toolCalls`, the agent's own toolbelt. Measured on a real fan-out
    // thread: 237 there against 636 here. Unqualified, the larger figure reads
    // as one of the two being wrong.
    const view = show(dto({ lanes: [lane({ toolCalls: 636 })] }));

    const tools = [...view.querySelectorAll('span')].find((node) =>
      node.textContent?.includes('636 tools'),
    );
    expect(tools?.getAttribute('title')).toContain('sub-agents included');
  });

  it('keeps a span that starts at the very end inside its lane', () => {
    // The visible-width floor is itself bounded by the room left; applied after
    // the clamp it pushed a late span past the lane's right edge.
    const view = show(
      dto({
        turns: [
          turn({
            model: 'sonnet',
            startedAt: new Date(Date.parse(TO) - 100).toISOString(),
            durationMs: 100,
          }),
        ],
      }),
    );

    const span = view.querySelector<HTMLElement>('[title*="sonnet"]');
    const left = Number.parseFloat(span?.style.left.replace('%', '') ?? '0');
    const width = Number.parseFloat(span?.style.width.replace('%', '') ?? '0');
    expect(left).toBeGreaterThan(99);
    expect(left + width).toBeLessThanOrEqual(100);
  });
});
