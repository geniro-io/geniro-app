import { memo, useMemo } from 'react';

import type {
  RunWaterfallDto,
  RunWaterfallLane,
  RunWaterfallTurn,
  RunWaterfallWait,
} from '../autogenerated';
import { categoryToken } from '../stats/charts/chart-theme';
import { formatDuration, NOT_MEASURED } from '../stats/stats-format';
import { formatUsd } from './agent-activity';
// The chats-side formatter, for a SINGLE turn: it keeps sub-minute precision
// (`0.4s`, `1m 5s`) where its stats-side namesake rounds to the minute, which is
// right for the aggregate figures above and wrong for a turn that took nine
// seconds.
import { formatDuration as formatTurnDuration } from './turn-duration';

/** A lane's own spans, already placed as percentages of the run's wall clock. */
interface Placed {
  leftPct: number;
  widthPct: number;
}

/**
 * The narrowest bar still visible: a 20-second turn inside a 40-hour run is
 * 0.014% wide and would otherwise render as nothing at all, and a lane showing
 * no work for a turn that happened is worse than a slightly generous bar.
 */
const MIN_SPAN_PCT = 0.7;

/**
 * Where a span sits on the run's clock, or null when it cannot be placed.
 *
 * ORDER is load-bearing twice over, and both orderings look arbitrary until
 * they are wrong. The width is measured against the CLAMPED left edge — a turn
 * whose derived start precedes the run's first row has a negative one, and
 * measuring against that lets the bar claim more of the lane than the span
 * covers. And the visible-minimum floor is itself capped by the room left, so a
 * span starting at the very end of the run is widened into what remains rather
 * than past it.
 */
function place(
  startedAt: string,
  durationMs: number,
  from: number,
  span: number,
): Placed | null {
  const start = Date.parse(startedAt);
  if (!Number.isFinite(start) || !Number.isFinite(durationMs)) {
    return null;
  }
  const leftPct = Math.max(0, Math.min(100, ((start - from) / span) * 100));
  const room = 100 - leftPct;
  return {
    leftPct,
    widthPct: Math.min(
      room,
      Math.max(Math.min(MIN_SPAN_PCT, room), (durationMs / span) * 100),
    ),
  };
}

/** A lane with no turns of its own, with one identity so `memo` can hold. */
const NO_TURNS: readonly RunWaterfallTurn[] = [];

/**
 * What one turn says about itself on hover.
 *
 * A figure the CLI never reported is LEFT OUT rather than drawn as a dash: this
 * is a hover line rather than a column, so an absent part costs a reader
 * nothing, where an em dash in a sentence reads as a broken figure.
 */
function turnTitle(turn: RunWaterfallTurn): string {
  const parts = [
    formatTurnDuration(turn.durationMs),
    turn.costUsd === null ? NOT_MEASURED : formatUsd(turn.costUsd),
  ];
  if (turn.model !== null) {
    parts.push(turn.model);
  }
  if (turn.ttftMs !== null) {
    parts.push(`${formatTurnDuration(turn.ttftMs)} to first token`);
  }
  if (turn.timeToRequestMs !== null) {
    parts.push(`${formatTurnDuration(turn.timeToRequestMs)} before asking`);
  }
  if (turn.numTurns !== null) {
    parts.push(
      `${turn.numTurns} model ${turn.numTurns === 1 ? 'call' : 'calls'}`,
    );
  }
  return parts.join(' · ');
}

/**
 * One agent's row: what it did, when, and what that cost.
 *
 * `memo` over a lane's own grouped turns, which is what makes it hold: the
 * props are then the same objects until the fold itself is re-read.
 */
const WaterfallLane = memo(function WaterfallLane({
  lane,
  turns,
  index,
  from,
  span,
}: {
  lane: RunWaterfallLane;
  turns: readonly RunWaterfallTurn[];
  index: number;
  from: number;
  span: number;
}): React.JSX.Element {
  const colour = categoryToken(index);
  const peak = Math.max(1, ...lane.toolBuckets);
  return (
    <li className="flex flex-col gap-1">
      <div className="flex items-baseline gap-1.5 text-xs">
        <span
          aria-hidden="true"
          className="size-2 shrink-0 rounded-[2px]"
          style={{ backgroundColor: colour }}
        />
        <span className="truncate font-medium text-foreground">
          {lane.nodeId ?? 'agent'}
        </span>
        <span className="truncate text-muted-foreground">{lane.agentKind}</span>
        <span className="ml-auto shrink-0 tabular-nums text-foreground">
          {lane.costUsd === null ? NOT_MEASURED : formatUsd(lane.costUsd)}
        </span>
      </div>
      <div className="relative h-4 w-full overflow-hidden rounded-[3px] bg-muted/40">
        {/* Tool density underneath — how busy this lane was, minute to minute. */}
        <div aria-hidden="true" className="absolute inset-0 flex">
          {lane.toolBuckets.map((count, bucket) => (
            <span
              key={bucket}
              className="h-full flex-1"
              style={{
                backgroundColor: colour,
                opacity: count === 0 ? 0 : 0.14 + 0.36 * (count / peak),
              }}
            />
          ))}
        </div>
        {/* Turn spans on top — the stretches the CLI itself calls work. */}
        {turns.map((turn) => {
          const spot = place(turn.startedAt, turn.durationMs, from, span);
          if (spot === null) {
            return null;
          }
          return (
            <span
              key={`${turn.startedAt}-${turn.durationMs}`}
              className="absolute inset-y-[3px] rounded-[2px]"
              style={{
                left: `${spot.leftPct}%`,
                width: `${spot.widthPct}%`,
                backgroundColor: colour,
              }}
              title={turnTitle(turn)}
            />
          );
        })}
      </div>
      <div className="flex gap-2 text-[11px] tabular-nums text-muted-foreground">
        <span>
          {lane.turns} {lane.turns === 1 ? 'turn' : 'turns'}
        </span>
        {/*
          The daemon folds this off the payload-free spine, so a delegate's
          tool calls land in the lane of the agent that launched it — and the
          agent card directly above states `Run.toolCalls`, the agent's OWN
          toolbelt, which on a fan-out thread is a fraction of this figure
          (measured: 237 against 636). Two figures about one lane, differing
          nearly threefold, with nothing saying why — so this says why, the
          same answer `conversation-timeline.tsx` gives for its message count.
        */}
        <span title={`${lane.toolCalls} tool calls, sub-agents included`}>
          {lane.toolCalls} tools
        </span>
        <span className="ml-auto">
          {lane.workedMs === null
            ? NOT_MEASURED
            : formatDuration(lane.workedMs)}
        </span>
      </div>
    </li>
  );
});

/** The stretches the run spent waiting on a person, on the same clock. */
const WaitLane = memo(function WaitLane({
  waits,
  from,
  span,
}: {
  waits: readonly RunWaterfallWait[];
  from: number;
  span: number;
}): React.JSX.Element {
  return (
    <li className="flex flex-col gap-1">
      <div className="flex items-baseline gap-1.5 text-xs">
        <span className="font-medium text-foreground">waiting on you</span>
        <span className="ml-auto shrink-0 tabular-nums text-muted-foreground">
          {waits.length} {waits.length === 1 ? 'card' : 'cards'}
        </span>
      </div>
      <div className="relative h-2.5 w-full overflow-hidden rounded-[3px] bg-muted/40">
        {waits.map((wait) => {
          const spot = place(wait.startedAt, wait.durationMs, from, span);
          if (spot === null) {
            return null;
          }
          return (
            <span
              key={`${wait.startedAt}-${wait.durationMs}`}
              className="absolute inset-y-0 rounded-[2px] border border-muted-foreground/70 bg-muted-foreground/25"
              style={{ left: `${spot.leftPct}%`, width: `${spot.widthPct}%` }}
              title={`${wait.question ? 'question' : 'permission'}${
                wait.toolName === null ? '' : ` · ${wait.toolName}`
              } · ${formatTurnDuration(wait.durationMs)}`}
            />
          );
        })}
      </div>
    </li>
  );
});

/**
 * One run as money, order and timing on a single wall clock.
 *
 * Props-only, like `conversation-timeline.tsx`: the panel owns the read, so this
 * component cannot fetch a second, differently-timed copy of the same run.
 *
 * Every figure here is folded by the DAEMON. Folding in the renderer would
 * describe the transcript window the client happens to hold and present it as
 * the whole run.
 */
export const RunWaterfall = memo(function RunWaterfall({
  data,
  loading,
  error,
}: {
  data: RunWaterfallDto | null;
  loading: boolean;
  error: string | null;
}): React.JSX.Element | null {
  const clock = useMemo(() => {
    if (data === null) {
      return null;
    }
    const from = Date.parse(data.from);
    const to = Date.parse(data.to);
    return { from, span: Math.max(1, to - from) };
  }, [data]);
  // Grouped ONCE, so each lane keeps the same array identity between renders.
  // Filtering per lane at the call site rebuilt every array on every render,
  // which is what made `memo` on the row below inert.
  const turnsByLane = useMemo(() => {
    const byLane = new Map<string | null, RunWaterfallTurn[]>();
    for (const turn of data?.turns ?? []) {
      const own = byLane.get(turn.nodeId);
      if (own === undefined) {
        byLane.set(turn.nodeId, [turn]);
      } else {
        own.push(turn);
      }
    }
    return byLane;
  }, [data]);

  if (error !== null) {
    return <p className="text-xs text-muted-foreground">{error}</p>;
  }
  if (loading && data === null) {
    return <p className="text-xs text-muted-foreground">reading the run…</p>;
  }
  if (data === null || clock === null) {
    return null;
  }
  if (data.lanes.length === 0) {
    return (
      <p className="text-xs text-muted-foreground">
        nothing has run in this thread yet
      </p>
    );
  }

  const failedCalls = data.calls.filter((call) => call.status !== 'ok').length;
  return (
    <div className="flex flex-col gap-2">
      <dl className="grid grid-cols-3 gap-1 text-xs">
        <Figure
          label="spent"
          value={
            data.totals.costUsd === null
              ? NOT_MEASURED
              : formatUsd(data.totals.costUsd)
          }
        />
        <Figure label="wall clock" value={formatDuration(clock.span)} />
        <Figure
          label="waited on you"
          value={
            data.waitedOnUserMs === null
              ? NOT_MEASURED
              : formatDuration(data.waitedOnUserMs)
          }
        />
      </dl>
      <ul className="flex flex-col gap-2">
        {data.lanes.map((lane, index) => (
          <WaterfallLane
            key={lane.nodeId ?? 'chat'}
            lane={lane}
            index={index}
            from={clock.from}
            span={clock.span}
            turns={turnsByLane.get(lane.nodeId) ?? NO_TURNS}
          />
        ))}
        {data.waits.length > 0 ? (
          <WaitLane waits={data.waits} from={clock.from} span={clock.span} />
        ) : null}
      </ul>
      {failedCalls > 0 ? (
        <p className="text-[11px] text-muted-foreground">
          {failedCalls} of {data.calls.length} agent-to-agent{' '}
          {data.calls.length === 1 ? 'call' : 'calls'} failed
        </p>
      ) : null}
      {data.partialReason === null ? null : (
        <p className="text-[11px] text-muted-foreground">
          {data.partialReason}
        </p>
      )}
    </div>
  );
});

function Figure({
  label,
  value,
}: {
  label: string;
  value: string;
}): React.JSX.Element {
  return (
    <div className="flex flex-col">
      <dt className="text-[11px] text-muted-foreground">{label}</dt>
      <dd className="tabular-nums text-foreground">{value}</dd>
    </div>
  );
}
