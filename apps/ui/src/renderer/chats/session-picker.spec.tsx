// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { AgentSession } from '../autogenerated';
import { SessionPicker } from './session-picker';
import type { MergedSessions, ProfiledSession } from './session-search';

const session = (over: Partial<AgentSession> = {}): AgentSession => ({
  id: 's1',
  cwd: '/work/app',
  title: 'Fix the auth redirect loop',
  updatedAt: Date.parse('2026-08-16T00:00:00.000Z'),
  snippet: null,
  ...over,
});

const row = (
  over: Partial<AgentSession> = {},
  configDir: string | null = null,
): ProfiledSession => ({ session: session(over), configDir });

const listing = (over: Partial<MergedSessions> = {}): MergedSessions => ({
  sessions: [row()],
  unavailableReason: null,
  partialReason: null,
  ...over,
});

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

function mount(over: Partial<Parameters<typeof SessionPicker>[0]> = {}): {
  container: HTMLDivElement;
  onResume: ReturnType<typeof vi.fn>;
} {
  const onResume = vi.fn();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  const element = (
    <SessionPicker
      open
      agent="claude"
      onAgentChange={vi.fn()}
      profiles={[null]}
      query=""
      onQueryChange={vi.fn()}
      listing={listing()}
      loading={false}
      error={null}
      busyId={null}
      onClose={vi.fn()}
      onResume={onResume}
      {...over}
    />
  );
  act(() => {
    root!.render(element);
  });
  return { container, onResume };
}

describe('SessionPicker', () => {
  it('refuses a session with no folder rather than resuming it somewhere else', () => {
    // A resumed conversation is about the tree it was reasoning over; opening
    // it in an unrelated folder is how an agent starts confidently answering
    // about the wrong project.
    const { container, onResume } = mount({
      listing: listing({ sessions: [row({ cwd: null })] }),
    });
    const button = container.querySelector('li button') as HTMLButtonElement;
    expect(button.disabled).toBe(true);
    act(() => {
      button.click();
    });
    expect(onResume).not.toHaveBeenCalled();
  });

  it('resumes the row that was clicked', () => {
    const { container, onResume } = mount();
    act(() => {
      (container.querySelector('li button') as HTMLButtonElement).click();
    });
    expect(onResume).toHaveBeenCalledWith(
      expect.objectContaining({
        session: expect.objectContaining({ id: 's1' }),
      }),
    );
  });

  it('tells two same-named folders apart, which a leaf name cannot', () => {
    // With the folder-scope control gone, this line is the only thing on the
    // row that says WHICH project — and a machine holding `~/a/work/app` and
    // `~/b/work/app` gets two identical rows from a bare basename.
    const { container } = mount({
      listing: listing({
        sessions: [
          row({ id: 'a', cwd: '/a/work/app' }),
          row({ id: 'b', cwd: '/b/work/app' }),
        ],
      }),
    });
    const folders = [...container.querySelectorAll('li button')].map(
      (row) => row.querySelectorAll('span')[2]?.textContent,
    );
    expect(folders[0]).not.toEqual(folders[1]);
    expect(folders[0]).toContain('/a/');
  });

  it('opens the agent menu BELOW its trigger, not over the dialog title', () => {
    // The picker sits at the top of a dialog; `Menu`'s default side is upward,
    // which is the composer's geometry and covered this dialog's own header.
    const { container } = mount();
    const trigger = container.querySelector(
      '[data-menu-trigger]',
    ) as HTMLButtonElement;
    act(() => {
      trigger.click();
    });
    const panel = container.querySelector(
      '[data-slot="menu-panel"]',
    ) as HTMLElement;
    // Asked in whichever way this menu is placed, since that is a separate
    // decision from the side: a viewport-anchored panel carries a measured
    // `top`, an ancestor-anchored one the `top-full` offset. Either way the
    // downward side is what must be set and the upward one empty.
    const downward =
      panel.style.top !== '' || panel.className.includes('top-full');
    const upward =
      panel.style.bottom !== '' || panel.className.includes('bottom-full');
    expect(downward).toBe(true);
    expect(upward).toBe(false);
  });

  it("shows the CLI's own reason instead of an empty list that explains nothing", () => {
    const { container } = mount({
      listing: listing({ sessions: [], unavailableReason: 'cannot be asked' }),
    });
    expect(container.textContent).toContain('cannot be asked');
  });

  it('says what the listing does NOT reach, even when it found rows', () => {
    // The half a user with terminal history would otherwise read as broken.
    const { container } = mount({
      listing: listing({ partialReason: 'only ACP sessions are listed' }),
    });
    expect(container.textContent).toContain('only ACP sessions are listed');
    expect(container.textContent).toContain('Fix the auth redirect loop');
  });

  it('locks the OTHER rows while one is being imported', () => {
    const { container } = mount({
      listing: listing({
        sessions: [row({ id: 'a' }), row({ id: 'b' })],
      }),
      busyId: 'a',
    });
    const rows = [...container.querySelectorAll('li button')];
    expect((rows[0] as HTMLButtonElement).disabled).toBe(true);
    expect((rows[1] as HTMLButtonElement).disabled).toBe(true);
  });

  it('quotes the line that answered a content search', () => {
    // REPORTED as "improve search bu threads - by content as well". A row's
    // title is the conversation's opening prompt, so a match found in the
    // middle of it has nothing on screen explaining why the row is there.
    const { container } = mount({
      query: 'asar',
      listing: listing({
        sessions: [row({ snippet: 'The app.asar archive is never deleted.' })],
      }),
    });

    expect(
      container.querySelector('[data-slot="session-snippet"]')?.textContent,
    ).toContain('app.asar archive');
    // Beside the title, never instead of it — a search result still has to name
    // the conversation.
    expect(container.textContent).toContain('Fix the auth redirect loop');
  });

  it('says WHICH account a row is from, but only once there are several', () => {
    // With one profile it is the same word on every row, and the row already
    // carries a path and a time.
    const rows = { sessions: [row({}, '/work/second')] };
    expect(
      mount({
        profiles: [null],
        listing: listing(rows),
      }).container.querySelector('[data-slot="session-profile"]'),
    ).toBeNull();

    act(() => {
      root?.unmount();
    });
    container?.remove();

    const many = mount({
      profiles: [null, '/work/second'],
      listing: listing(rows),
    });
    expect(
      many.container.querySelector('[data-slot="session-profile"]')
        ?.textContent,
    ).toContain('second');
  });

  it('names the stores it searched when there is more than one', () => {
    // The picker used to name the ONE profile it had asked, which told the user
    // nothing about the accounts it had not.
    const { container } = mount({ profiles: [null, '/work/second'] });

    expect(container.textContent).toContain('Across 2 profiles');
  });

  it('reports typing UP rather than filtering the rows it holds', () => {
    // The search is a question for the daemon — only it can read what was said
    // inside a conversation — so this component must not narrow the answer.
    const onQueryChange = vi.fn();
    const { container } = mount({
      onQueryChange,
      listing: listing({ sessions: [row({ title: 'billing' })] }),
    });

    const input = container.querySelector(
      'input[aria-label="Search sessions"]',
    ) as HTMLInputElement;
    act(() => {
      // Through the NATIVE setter: React installs its own `value` property on
      // the element, and assigning to it leaves React's tracker believing the
      // value never changed — so the synthetic `onChange` never fires.
      Object.getOwnPropertyDescriptor(
        window.HTMLInputElement.prototype,
        'value',
      )!.set!.call(input, 'asar');
      input.dispatchEvent(new Event('input', { bubbles: true }));
    });

    expect(onQueryChange).toHaveBeenCalledWith('asar');
    // Still on screen: nothing here decides what matches.
    expect(container.textContent).toContain('billing');
  });
});
