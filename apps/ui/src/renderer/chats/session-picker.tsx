import { Folder, History, Search } from 'lucide-react';
import * as React from 'react';

import type { CliKind } from '../../shared/contracts';
import { CLI_KINDS } from '../../shared/contracts';
import type { AgentSession, AgentSessionListingDto } from '../autogenerated';
import { EmptyState } from '../components/empty-state';
import { ErrorText } from '../components/error-text';
import { NoteBox } from '../components/note-box';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { Select } from '../components/ui/select';
import { Spinner } from '../components/ui/spinner';
import { cn } from '../components/ui/utils';
import { formatRelativeTime } from './relative-time';

/**
 * Pick a conversation the user already had in their terminal, and carry it on
 * here.
 *
 * Deliberately a separate control from the sidebar's `+`, which stays a
 * one-click new thread: this one has a question to ask (which conversation?)
 * and the other must never grow one.
 *
 * The three controls across the top are the three ways a list of hundreds
 * becomes the one row somebody is looking for — which CLI, which folder, and
 * free text. Folder scope defaults to the folder the composer is already
 * pointed at, because "carry on what I was doing here" is the common case and
 * "everything I have ever worked on" is the fallback, not the other way round.
 */
export function SessionPicker({
  open,
  agent,
  onAgentChange,
  folder,
  folderOnly,
  onFolderOnlyChange,
  configDir,
  listing,
  loading,
  error,
  busyId,
  onClose,
  onResume,
}: {
  open: boolean;
  agent: CliKind;
  onAgentChange: (agent: CliKind) => void;
  /** The composer's current folder, or null when none is chosen yet. */
  folder: string | null;
  /** Whether the listing is narrowed to {@link folder}. */
  folderOnly: boolean;
  onFolderOnlyChange: (folderOnly: boolean) => void;
  /** Shown so the user can see which profile the list came from. */
  configDir: string | null;
  listing: AgentSessionListingDto | null;
  loading: boolean;
  error: string | null;
  /** The row being imported right now — the dialog stays up while it runs. */
  busyId: string | null;
  onClose: () => void;
  onResume: (session: AgentSession) => void;
}): React.JSX.Element {
  const [query, setQuery] = React.useState('');
  // Cleared on every open rather than kept: a filter left over from last time
  // is an empty list whose reason is off screen.
  React.useEffect(() => {
    if (open) {
      setQuery('');
    }
  }, [open]);

  const rows = React.useMemo(
    () => filterSessions(listing?.sessions ?? [], query),
    [listing, query],
  );

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Continue a session"
      className="w-[min(44rem,calc(100vw-2rem))]">
      <div className="flex min-h-0 flex-col gap-3">
        <p className="text-sm text-muted-foreground">
          Threads you already have with these CLIs on this machine. Picking one
          opens it here and carries on where it left off.
        </p>

        <div className="flex flex-wrap items-center gap-2">
          <Select
            aria-label="Agent"
            value={agent}
            onValueChange={(value: string) => onAgentChange(value as CliKind)}
            groups={[
              {
                items: CLI_KINDS.map((kind) => ({ value: kind, label: kind })),
              },
            ]}
          />
          {/*
            Scope, not a filter over what already arrived: a narrowed listing is
            a narrower QUESTION put to the CLI, which for cursor is a process
            spawn — so the choice belongs here, before the fetch, rather than in
            the search box below.
          */}
          <Select
            aria-label="Folder scope"
            value={folderOnly ? 'folder' : 'all'}
            onValueChange={(value: string) =>
              onFolderOnlyChange(value === 'folder')
            }
            groups={[
              {
                items: [
                  {
                    value: 'folder',
                    label:
                      folder === null
                        ? 'This folder'
                        : `In ${basename(folder)}`,
                    icon: <Folder />,
                    // Nothing to narrow to. Refused rather than hidden, so the
                    // control does not appear and disappear as the composer's
                    // folder is chosen.
                    ...(folder === null
                      ? { disabled: true, hint: 'no folder chosen yet' }
                      : {}),
                  },
                  { value: 'all', label: 'All folders', icon: <History /> },
                ],
              },
            ]}
          />
          <label className="relative flex min-w-[12rem] flex-1 items-center">
            <Search
              className="pointer-events-none absolute left-2 size-4 text-muted-foreground"
              aria-hidden="true"
            />
            <Input
              aria-label="Search sessions"
              className="pl-8"
              placeholder="Search by what was said or by folder…"
              value={query}
              onChange={(event) => setQuery(event.target.value)}
            />
          </label>
        </div>

        {configDir === null ? null : (
          // `break-all` on the path: it is one unbroken token with no spaces to
          // wrap at, so without it a real profile path runs straight out
          // through the side of the dialog.
          <p className="text-xs text-muted-foreground">
            From the profile at <code className="break-all">{configDir}</code>.
          </p>
        )}

        {error ? <ErrorText>{error}</ErrorText> : null}

        <div className="min-h-[16rem] overflow-y-auto rounded-md border border-border">
          {loading ? (
            <div className="flex items-center gap-2 p-4 text-sm text-muted-foreground">
              <Spinner /> Asking {agent} what it has…
            </div>
          ) : listing?.unavailableReason ? (
            <EmptyState>{listing.unavailableReason}</EmptyState>
          ) : rows.length === 0 ? (
            <EmptyState className="flex-col gap-1">
              <span className="text-foreground">
                {query === ''
                  ? `No ${agent} sessions${
                      folderOnly && folder !== null ? ' in this folder' : ''
                    }`
                  : 'Nothing matches that search'}
              </span>
              <span>
                {query === ''
                  ? 'Sessions you start in your terminal show up here.'
                  : 'Try fewer words, or clear the search.'}
              </span>
            </EmptyState>
          ) : (
            <ul className="m-0 flex list-none flex-col p-1">
              {rows.map((session) => (
                <SessionRow
                  key={session.id}
                  session={session}
                  busy={busyId === session.id}
                  disabled={busyId !== null && busyId !== session.id}
                  onResume={onResume}
                />
              ))}
            </ul>
          )}
        </div>

        {/*
          The listing is complete for the store it reached and this CLI may keep
          another. Said UNDER the rows rather than in place of them, because it
          is true whether the list is full or empty — and a user whose terminal
          history is all in that other store would otherwise read a short,
          correct list as a broken feature.
        */}
        {listing?.partialReason ? (
          <NoteBox>{listing.partialReason}</NoteBox>
        ) : null}
      </div>
    </Dialog>
  );
}

/** One conversation, as a row that says what it was about and where. */
function SessionRow({
  session,
  busy,
  disabled,
  onResume,
}: {
  session: AgentSession;
  busy: boolean;
  disabled: boolean;
  onResume: (session: AgentSession) => void;
}): React.JSX.Element {
  // A session the CLI recorded no folder for cannot be resumed anywhere
  // sensible, so the row says so instead of offering a button that would open a
  // conversation about one project inside another.
  const resumable = session.cwd !== null;
  return (
    <li>
      <button
        type="button"
        disabled={disabled || busy || !resumable}
        title={resumable ? undefined : 'This CLI recorded no folder for it'}
        onClick={() => onResume(session)}
        className={cn(
          'flex w-full flex-col items-start gap-0.5 rounded-md px-3 py-2 text-left',
          'hover:bg-sidebar-accent focus-visible:bg-sidebar-accent',
          'disabled:pointer-events-none disabled:opacity-50',
        )}>
        <span className="line-clamp-2 w-full text-sm text-foreground">
          {session.title ?? 'Untitled conversation'}
        </span>
        <span className="flex w-full items-center gap-1.5 text-xs text-muted-foreground">
          {busy ? <Spinner /> : <Folder className="size-3 shrink-0" />}
          <span className="truncate">
            {session.cwd === null
              ? 'folder not recorded'
              : basename(session.cwd)}
          </span>
          {session.updatedAt === null ? null : (
            <>
              <span aria-hidden="true">·</span>
              <span className="shrink-0">
                {formatRelativeTime(new Date(session.updatedAt).toISOString())}
              </span>
            </>
          )}
        </span>
      </button>
    </li>
  );
}

/**
 * Rows matching every whitespace-separated term, against the title AND the
 * folder.
 *
 * Every term rather than the whole string, so "auth geniro" finds the auth
 * conversation in the geniro folder — which is how somebody actually remembers
 * a thread they had last week, in fragments from both halves of the row.
 */
export function filterSessions(
  sessions: readonly AgentSession[],
  query: string,
): AgentSession[] {
  const terms = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (terms.length === 0) {
    return [...sessions];
  }
  return sessions.filter((session) => {
    const haystack =
      `${session.title ?? ''} ${session.cwd ?? ''}`.toLowerCase();
    return terms.every((term) => haystack.includes(term));
  });
}

/** Last path segment, which is what identifies a project at a glance. */
function basename(path: string): string {
  const trimmed = path.replace(/\/+$/, '');
  return trimmed.slice(trimmed.lastIndexOf('/') + 1) || trimmed;
}
