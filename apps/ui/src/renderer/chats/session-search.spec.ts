import { describe, expect, it } from 'vitest';

import type { AgentSession, AgentSessionListingDto } from '../autogenerated';
import {
  mergeSessionListings,
  type ProfileAnswer,
  sessionProfiles,
} from './session-search';

const session = (over: Partial<AgentSession> = {}): AgentSession => ({
  id: 's1',
  cwd: '/work/app',
  title: 'Fix the auth redirect loop',
  updatedAt: 1_000,
  snippet: null,
  ...over,
});

const listing = (
  over: Partial<AgentSessionListingDto> = {},
): AgentSessionListingDto => ({
  sessions: [session()],
  unavailableReason: null,
  partialReason: null,
  ...over,
});

const answer = (
  configDir: string | null,
  over: Partial<ProfileAnswer> = {},
): ProfileAnswer => ({
  configDir,
  listing: listing(),
  error: null,
  ...over,
});

describe('sessionProfiles', () => {
  it('always asks the CLI’s own default, chosen or not', () => {
    // The account a user has without ever picking one, and where most of their
    // history is. A list built from their choices alone omits it.
    expect(sessionProfiles(null, [], true)).toEqual([null]);
    expect(sessionProfiles('/a', ['/b'], true)).toEqual([null, '/a', '/b']);
  });

  it('does not repeat a directory that is both current and recent', () => {
    expect(sessionProfiles('/a', ['/a', '/b'], true)).toEqual([
      null,
      '/a',
      '/b',
    ]);
  });

  it('asks ONE profile for a CLI that reads no config directory', () => {
    // Listing under a directory the CLI does not read is a listing about
    // nothing — and on the import route, a 400.
    expect(sessionProfiles('/a', ['/b'], false)).toEqual([null]);
  });
});

describe('mergeSessionListings', () => {
  it('tags every row with the profile it came from', () => {
    // REPORTED as "i can see only one claude profile there". The tag is not a
    // label: an id listed under one profile is not resumable under another, so
    // this is what the import is told.
    const merged = mergeSessionListings(
      [
        answer(null, {
          listing: listing({ sessions: [session({ id: 'a' })] }),
        }),
        answer('/work/second', {
          listing: listing({ sessions: [session({ id: 'b' })] }),
        }),
      ],
      400,
    );

    expect(
      merged.sessions.map((row) => [row.session.id, row.configDir]),
    ).toEqual([
      ['a', null],
      ['b', '/work/second'],
    ]);
  });

  it('interleaves the accounts by WHEN, never grouping them', () => {
    // Somebody looking for a thread does not remember which subscription they
    // were signed into at the time.
    const merged = mergeSessionListings(
      [
        answer(null, {
          listing: listing({
            sessions: [
              session({ id: 'old-default', updatedAt: 1 }),
              session({ id: 'new-default', updatedAt: 4 }),
            ],
          }),
        }),
        answer('/second', {
          listing: listing({
            sessions: [session({ id: 'mid-second', updatedAt: 2 })],
          }),
        }),
      ],
      400,
    );

    expect(merged.sessions.map((row) => row.session.id)).toEqual([
      'new-default',
      'mid-second',
      'old-default',
    ]);
  });

  it('names a profile it could NOT read instead of quietly dropping it', () => {
    // A user who moved a profile away sees a shorter list; without a sentence
    // the missing half is indistinguishable from history they never had.
    const merged = mergeSessionListings(
      [answer(null), answer('/gone', { listing: null, error: 'ENOENT' })],
      400,
    );

    expect(merged.sessions).toHaveLength(1);
    expect(merged.partialReason).toContain('Could not read');
    expect(merged.partialReason).toContain('gone');
  });

  it('keeps “this CLI cannot be asked” only when NOTHING answered', () => {
    // Stated over a list that is on screen and full of rows, it is simply
    // false — and it is the message the picker renders INSTEAD of the rows.
    const partly = mergeSessionListings(
      [
        answer(null),
        answer('/second', {
          listing: listing({ sessions: [], unavailableReason: 'no' }),
        }),
      ],
      400,
    );
    expect(partly.unavailableReason).toBeNull();

    const none = mergeSessionListings(
      [
        answer(null, {
          listing: listing({ sessions: [], unavailableReason: 'no' }),
        }),
      ],
      400,
    );
    expect(none.unavailableReason).toBe('no');
  });

  it('states each partial reason once, however many profiles said it', () => {
    // Every claude profile answers with the same sentence about its own search
    // bound, and three copies of it under the rows is noise the user has to
    // read past to find the one that is different.
    const merged = mergeSessionListings(
      [
        answer(null, { listing: listing({ partialReason: 'bounded' }) }),
        answer('/b', { listing: listing({ partialReason: 'bounded' }) }),
      ],
      400,
    );

    expect(merged.partialReason).toBe('bounded');
  });

  it('drops a session id a second profile repeats', () => {
    // Two stores cannot normally hold one id, but the profile list is built
    // from paths the user typed and the same directory can be spelled twice.
    const merged = mergeSessionListings([answer(null), answer('/second')], 400);

    expect(merged.sessions).toHaveLength(1);
    expect(merged.sessions[0]?.configDir).toBeNull();
  });
});
