function finding(id: string): MemoryFinding {
  return { id } as MemoryFinding;
}

function notice(
  kind: SettingsNoticeKind,
  key: string = kind,
  overrides: Partial<SettingsNotice> = {},
): SettingsNotice {
  return {
    id: `notice:${key}`,
    kind,
    key,
    items: [],
    openedAt: '2026-11-27T10:00:00.000Z',
    resolvedAt: null,
    dismissedAt: null,
    ...overrides,
  };
}

/** One open notice per card a test may draw, each standing at its own row. */
function everyNotice(): SettingsNotice[] {
  return [
    notice('app-update'),
    notice('agent-updates', 'agent-updates:claude'),
    notice('agent-updates', 'agent-updates:codex'),
    notice('agent-sign-in', 'agent-sign-in:claude:'),
    notice('agent-sign-in', 'agent-sign-in:claude:/cfg/work'),
    notice('agent-sign-in', 'agent-sign-in:codex:'),
    notice('share-sign-in', 'share-sign-in:aws'),
    notice('share-sign-in', 'share-sign-in:gcs'),
    notice('share-sign-in', 'share-sign-in:long'),
    notice('memory-conflicts'),
  ];
}

