// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type {
  CliDetection,
  CliUpdates,
  UpdateState,
} from '../../shared/contracts';
import {
  detection as det,
  updateAvailable as withUpdate,
  updateState,
  waitingShare as share,
} from '../__tests__/settings-attention-fixtures';
import type { MemoryFinding, Share } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { SettingsAttentionCards } from './settings-attention-cards';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function finding(id: string): MemoryFinding {
  return { id } as MemoryFinding;
}

let container: HTMLDivElement;
let root: Root;
let detections: CliDetection[];
let detectClis: ReturnType<typeof vi.fn>;
let updateCli: ReturnType<typeof vi.fn>;
let installUpdate: ReturnType<typeof vi.fn>;
let relaunchForUpdate: ReturnType<typeof vi.fn>;
let pushCliUpdates: (state: CliUpdates) => void;
let appUpdate: UpdateState;
let shares: Share[];
let findings: MemoryFinding[];
let listShares: ReturnType<typeof vi.fn>;
let listMemoryFindings: ReturnType<typeof vi.fn>;
let startCliLogin: ReturnType<typeof vi.fn>;
let startShareSignIn: ReturnType<typeof vi.fn>;
let memoryChanged: () => void;
let sharesChanged: () => void;
let reconnected: () => void;

function apis(): DaemonApis {
  return {
    shares: {
      listShares,
      startShareSignIn,
      readShareSignIn: vi.fn(),
      cancelShareSignIn: vi.fn(),
    },
    memories: { listMemoryFindings },
    cliAuth: {
      startCliLogin,
      submitCliLoginCode: vi.fn(),
      cancelCliLogin: vi.fn(),
    },
  } as unknown as DaemonApis;
}

const client = {
  onMemoryChanged: (listener: () => void) => {
    memoryChanged = listener;
    return () => undefined;
  },
  onSharesChanged: (listener: () => void) => {
    sharesChanged = listener;
    return () => undefined;
  },
  onReconnect: (listener: () => void) => {
    reconnected = listener;
    return () => undefined;
  },
} as unknown as DaemonClient;

const theApis = { current: null as DaemonApis | null };

async function draw(
  props: Partial<{
    active: boolean;
    remote: boolean;
    onOpenMemoryConflicts: (() => void) | null;
  }> = {},
): Promise<void> {
  theApis.current ??= apis();
  await act(async () => {
    root.render(
      <SettingsAttentionCards
        apis={theApis.current as DaemonApis}
        client={client}
        active={props.active ?? true}
        remote={props.remote ?? false}
        onOpenMemoryConflicts={props.onOpenMemoryConflicts ?? null}
      />,
    );
  });
}

const cards = (kind?: string): HTMLElement[] => [
  ...container.querySelectorAll<HTMLElement>(
    kind === undefined
      ? '[data-slot="settings-attention-card"]'
      : `[data-slot="settings-attention-card"][data-kind="${kind}"]`,
  ),
];

const button = (card: HTMLElement, label: string): HTMLButtonElement | null =>
  [...card.querySelectorAll('button')].find(
    (candidate) => candidate.textContent === label,
  ) ?? null;

beforeEach(() => {
  detections = [];
  appUpdate = updateState({});
  shares = [];
  findings = [];
  theApis.current = null;
  detectClis = vi.fn(() => Promise.resolve(detections));
  updateCli = vi.fn(() => Promise.resolve({ kind: 'claude', ok: true }));
  installUpdate = vi.fn(() =>
    Promise.resolve(updateState({ phase: 'downloading' })),
  );
  relaunchForUpdate = vi.fn(() => Promise.resolve(appUpdate));
  listShares = vi.fn(() => Promise.resolve({ shares, configReceivedAt: null }));
  listMemoryFindings = vi.fn(() => Promise.resolve({ findings }));
  startShareSignIn = vi.fn(() =>
    Promise.resolve({
      id: 'share-sign-in-1',
      destinationId: 'gcs',
      label: 'Google Cloud',
      cli: 'gcloud',
      status: 'waiting',
      lines: [],
      url: null,
      message: null,
    }),
  );
  startCliLogin = vi.fn(() =>
    Promise.resolve({
      id: 'login-1',
      status: 'waiting',
      url: null,
      message: null,
    }),
  );
  Object.assign(window, {
    geniro: {
      detectClis,
      updateCli,
      getCliUpdates: () => Promise.resolve({ updating: [], results: {} }),
      forgetCliUpdateResults: () =>
        Promise.resolve({ updating: [], results: {} }),
      onCliUpdates: (listener: (state: CliUpdates) => void) => {
        pushCliUpdates = listener;
        return () => undefined;
      },
      getUpdateState: () => Promise.resolve(appUpdate),
      onUpdateState: () => () => undefined,
      checkForUpdates: vi.fn(),
      installUpdate,
      relaunchForUpdate,
      getSettings: () => Promise.resolve({ configProfiles: [] }),
      onSettingsChanged: () => () => undefined,
    },
  });
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('SettingsAttentionCards', () => {
  it('draws nothing while nothing waits in Settings', async () => {
    await draw();

    expect(
      container.querySelector('[data-slot="settings-attention"]'),
    ).toBeNull();
  });

  it('lists every CLI with an update in one card, each with its own Update that runs the Settings update', async () => {
    detections = [
      det('claude', { update: withUpdate('2.0.0') }),
      det('codex', { update: withUpdate('0.9.0') }),
      det('cursor-agent'),
    ];
    await draw();

    const [card] = cards('agent-updates');
    expect(cards('agent-updates')).toHaveLength(1);
    const rows = card?.querySelectorAll(
      '[data-slot="settings-attention-update"]',
    );
    expect([...(rows ?? [])].map((row) => row.textContent)).toEqual([
      'claude 1.0.0 → 2.0.0Update',
      'codex 1.0.0 → 0.9.0Update',
    ]);

    await act(async () => {
      button(rows?.[0] as HTMLElement, 'Update')?.click();
    });
    expect(updateCli).toHaveBeenCalledWith('claude');
  });

  it('drops a CLI once its update finished and the CLIs read again say it is current', async () => {
    detections = [det('claude', { update: withUpdate('2.0.0') })];
    await draw();
    expect(cards('agent-updates')).toHaveLength(1);

    detections = [det('claude', { version: '2.0.0' })];
    await act(async () => {
      pushCliUpdates({ updating: ['claude'], results: {} });
    });
    await act(async () => {
      pushCliUpdates({ updating: [], results: {} });
    });

    expect(cards('agent-updates')).toHaveLength(0);
  });

  it('lists each signed-out account and signs the pressed one in through the Settings sign-in', async () => {
    detections = [
      det('claude', { loggedIn: false, profileLogins: { '/cfg/work': false } }),
    ];
    await draw();

    const card = cards('agent-sign-in')[0] as HTMLElement;
    const rows = [
      ...card.querySelectorAll<HTMLElement>(
        '[data-slot="settings-attention-sign-in"]',
      ),
    ];
    expect(rows.map((row) => row.textContent)).toEqual([
      'claudeSign in',
      'claude · workSign in',
    ]);

    await act(async () => {
      button(rows[1] as HTMLElement, 'Sign in')?.click();
    });
    expect(startCliLogin).toHaveBeenCalledWith({
      agent: 'claude',
      configDir: '/cfg/work',
    });
  });

  it('offers Update now for an available Geniro update and Restart now once it is installed', async () => {
    appUpdate = updateState({ phase: 'available' });
    await draw();
    let card = cards('app-update')[0] as HTMLElement;
    expect(button(card, 'Restart now')).toBeNull();
    await act(async () => {
      button(card, 'Update now')?.click();
    });
    expect(installUpdate).toHaveBeenCalledTimes(1);

    act(() => root.unmount());
    root = createRoot(container);
    appUpdate = updateState({ phase: 'ready' });
    await draw();
    card = cards('app-update')[0] as HTMLElement;
    expect(button(card, 'Update now')).toBeNull();
    await act(async () => {
      button(card, 'Restart now')?.click();
    });
    expect(relaunchForUpdate).toHaveBeenCalledTimes(1);
  });

  it('draws the Geniro update without its Mac-only buttons on a paired device', async () => {
    appUpdate = updateState({ phase: 'ready' });
    await draw({ remote: true });

    const card = cards('app-update')[0] as HTMLElement;
    expect(card.querySelectorAll('button')).toHaveLength(0);
    expect(card.textContent).toContain('Install it on the Mac.');
  });

  it('draws one card per place whose shares wait on a sign-in, with how many wait', async () => {
    shares = [
      share('s1', 'gcs', 'Google Cloud'),
      share('s2', 'gcs', 'Google Cloud'),
      share('s3', 'aws', 'Amazon'),
    ];
    await draw();

    const placed = cards('share-sign-in');
    expect(
      placed.map(
        (card) =>
          card.querySelector('[data-slot="settings-attention-share-count"]')
            ?.textContent,
      ),
    ).toEqual([
      '1 shared link waits to be uploaded. Sign-in required (gcloud).',
      '2 shared links wait to be uploaded. Sign-in required (gcloud).',
    ]);
    expect(
      button(placed[1] as HTMLElement, 'Sign in to Google Cloud'),
    ).not.toBeNull();
  });

  it("reads no shares on a paired device, whose share routes are the Mac's", async () => {
    shares = [share('s1', 'gcs', 'Google Cloud')];
    await draw({ remote: true });

    expect(listShares).not.toHaveBeenCalled();
    expect(cards('share-sign-in')).toHaveLength(0);
  });

  it("drops a place's card once a share announce says nothing waits there any more", async () => {
    shares = [share('s1', 'gcs', 'Google Cloud')];
    await draw();
    expect(cards('share-sign-in')).toHaveLength(1);

    shares = [];
    await act(async () => {
      sharesChanged();
    });

    expect(cards('share-sign-in')).toHaveLength(0);
  });

  it('sums every undecided memory conflict in one card whose button opens Clean up', async () => {
    findings = [finding('f1'), finding('f2')];
    const onOpen = vi.fn();
    await draw({ onOpenMemoryConflicts: onOpen });

    const [card] = cards('memory-conflicts');
    expect(cards('memory-conflicts')).toHaveLength(1);
    expect(
      card?.querySelector('[data-slot="settings-attention-conflicts"]')
        ?.textContent,
    ).toBe('2 pairs of memory entries repeat or contradict each other.');
    await act(async () => {
      button(card as HTMLElement, 'Review conflicts')?.click();
    });
    expect(onOpen).toHaveBeenCalledTimes(1);
  });

  it('follows the conflicts on a memory change and keeps one card across a reconnect', async () => {
    findings = [finding('f1'), finding('f2')];
    await draw();

    findings = [finding('f2')];
    await act(async () => {
      memoryChanged();
    });
    expect(cards('memory-conflicts')).toHaveLength(1);
    expect(cards('memory-conflicts')[0]?.textContent).toContain(
      '1 pair of memory entries repeats or contradicts itself.',
    );

    await act(async () => {
      reconnected();
    });
    expect(cards('memory-conflicts')).toHaveLength(1);

    findings = [];
    await act(async () => {
      memoryChanged();
    });
    expect(cards('memory-conflicts')).toHaveLength(0);
  });

  it("reads the daemon's lists only while the chat is on screen, and again when it comes back", async () => {
    findings = [finding('f1')];
    await draw({ active: false });
    expect(listMemoryFindings).not.toHaveBeenCalled();
    expect(cards('memory-conflicts')).toHaveLength(0);

    await draw({ active: true });
    expect(listMemoryFindings).toHaveBeenCalledTimes(1);
    expect(cards('memory-conflicts')).toHaveLength(1);

    findings = [];
    await draw({ active: false });
    await draw({ active: true });
    expect(listMemoryFindings).toHaveBeenCalledTimes(2);
    expect(cards('memory-conflicts')).toHaveLength(0);
  });

  it('signs in to the place whose card was pressed, as Settings → Sharing does', async () => {
    shares = [share('s1', 'gcs', 'Google Cloud'), share('s2', 'aws', 'Amazon')];
    await draw();

    const google = cards('share-sign-in').find((card) =>
      card.textContent?.includes('Google Cloud'),
    ) as HTMLElement;
    await act(async () => {
      button(google, 'Sign in to Google Cloud')?.click();
    });

    expect(startShareSignIn).toHaveBeenCalledWith({
      startShareSignInDto: { destinationId: 'gcs' },
    });
  });
});
