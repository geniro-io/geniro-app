import { useEffect, useState } from 'react';

import type { ConfigProfile, UpdateState } from '../../shared/contracts';
import type { MemoryFinding, Share } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { signInLabel, signInReason } from './artifact-share';
import type { Subscribe } from './use-waiting-items';

export interface ShareWait {
  destinationId: string;
  /** What the Sign in button names: "Google Cloud". */
  label: string;
  /** "Sign-in required (gcloud)". */
  reason: string;
  count: number;
}

/** The shares waiting on a sign-in, one entry per place they wait to be uploaded to. */
export function shareWaitsByPlace(shares: Iterable<Share>): ShareWait[] {
  const byPlace = new Map<string, ShareWait>();
  for (const share of shares) {
    if (share.status !== 'awaiting-sign-in') {
      continue;
    }
    const known = byPlace.get(share.destinationId);
    if (known === undefined) {
      byPlace.set(share.destinationId, {
        destinationId: share.destinationId,
        label: signInLabel(share),
        reason: signInReason(share),
        count: 1,
      });
    } else {
      known.count += 1;
    }
  }
  return [...byPlace.values()].sort(
    (a, b) =>
      a.label.localeCompare(b.label) ||
      a.destinationId.localeCompare(b.destinationId),
  );
}

/** Whether a Geniro update waits on the user here: one this install can apply, one under way, or one installed. */
export function appUpdateWaits(state: UpdateState | null): boolean {
  if (state === null) {
    return false;
  }
  switch (state.phase) {
    case 'available':
      return state.canInstall;
    case 'downloading':
    case 'installing':
    case 'ready':
      return true;
    default:
      return false;
  }
}

/** What a configuration directory is called: its saved name, else its folder's name. */
export function configDirName(
  configDir: string,
  profiles: readonly ConfigProfile[],
): string {
  return (
    profiles.find((profile) => profile.dir === configDir)?.name ??
    configDir.replace(/\/+$/, '').split('/').pop() ??
    configDir
  );
}

export const readWaitingShares = async ({
  shares,
}: DaemonApis): Promise<Share[]> => (await shares.listShares({})).shares;

export const readMemoryFindings = async ({
  memories,
}: DaemonApis): Promise<MemoryFinding[]> =>
  (await memories.listMemoryFindings()).findings;

export const ON_SHARES: Subscribe = (client, reload) =>
  client.onSharesChanged(reload);

/** The named configurations from settings.json, re-read whenever settings are written. */
export function useConfigProfiles(): readonly ConfigProfile[] {
  const [profiles, setProfiles] = useState<readonly ConfigProfile[]>([]);
  useEffect(() => {
    let live = true;
    const read = (): void => {
      void window.geniro
        .getSettings()
        .then((settings) => {
          if (live) {
            setProfiles(settings.configProfiles);
          }
        })
        .catch(() => undefined);
    };
    read();
    const off = window.geniro.onSettingsChanged(read);
    return () => {
      live = false;
      off();
    };
  }, []);
  return profiles;
}
