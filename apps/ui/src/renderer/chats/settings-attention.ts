export interface ShareWait {
  destinationId: string;
  /** What the Sign in button names: "Google Cloud". */
  label: string;
  /** "Sign-in required (gcloud)"; null where only the notice is known. */
  reason: string | null;
  count: number;
  shareIds: string[];
}

/** The shares waiting on a sign-in, one entry per place they wait to be uploaded to. */
export function shareWaitsByPlace(shares: Iterable<Share>): ShareWait[] {
  const byPlace = new Map<string, ShareWait>();
  for (const share of shares) {
    if (share.status !== 'awaiting-sign-in') {
      continue;
    }
    const known = byPlace.get(share.destinationId);
    if (known === undefined) {
      byPlace.set(share.destinationId, {
        destinationId: share.destinationId,
        label: signInLabel(share),
        reason: signInReason(share),
        count: 1,
        shareIds: [share.id],
      });
    } else {
      known.count += 1;
      known.shareIds.push(share.id);
    }
  }
  return [...byPlace.values()].sort(
    (a, b) =>
      a.label.localeCompare(b.label) ||
      a.destinationId.localeCompare(b.destinationId),
  );
}

/** Whether a Geniro update waits on the user here: one this install can apply, one under way, or one installed. */
export function appUpdateWaits(state: UpdateState | null): boolean {
  if (state === null) {
    return false;
  }
  switch (state.phase) {
    case 'available':
      return state.canInstall;
    case 'downloading':
    case 'installing':
    case 'ready':
      return true;
    default:
      return false;
  }
}

/** What a configuration directory is called: its saved name, else its folder's name. */
export function configDirName(
  configDir: string,
  profiles: readonly ConfigProfile[],
): string {
  return (
    profiles.find((profile) => profile.dir === configDir)?.name ??
    configDir.replace(/\/+$/, '').split('/').pop() ??
    configDir
  );
}

/** Whether fetching or installing a Geniro update the user pressed for failed: what the card then says, rather than the offer. */
export function appInstallFailed(state: UpdateState | null): boolean {
  return (
    state?.phase === 'error' &&
    (state.failedPhase === 'available' ||
      state.failedPhase === 'downloading' ||
      state.failedPhase === 'installing')
  );
}

/** Whether nobody knows right now if a Geniro update waits: nothing checked yet this launch, a check under way, or one that failed. */
export function appUpdateUnsettled(state: UpdateState | null): boolean {
  return (
    state === null ||
    state.phase === 'idle' ||
    state.phase === 'checking' ||
    state.phase === 'error'
  );
}

/**
 * TWIN PARSER: the `agent-sign-in` key of `readingsByKey` in
 * `apps/daemon/src/v1/command-center/utils/notice-plan.ts`.
 */
export function signInNoticeKey(account: SignedOutAccount): string {
  return `agent-sign-in:${signInItemOf(account)}`;
}

function signInItemOf(account: SignedOutAccount): string {
  return `${account.kind}:${account.configDir ?? ''}`;
}

/** The newest version a notice's items name: `2.4.0`, or `2.4.0` of `claude@2.4.0`. */
export function newestNoticeVersion(items: readonly string[]): string | null {
  const item = items.at(-1);
  if (item === undefined) {
    return null;
  }
  const version = item.slice(item.lastIndexOf('@') + 1);
  return version === '' ? null : version;
}

/**
 * What the desktop window reports of the readings Electron main holds; a kind
 * not read yet is left out, and an answer not known right now is unsettled, so
 * a check under way or a probe that failed never closes a notice.
 */
export function reportedNoticeReadings(
  detections: readonly CliDetection[] | null,
  update: UpdateState | null,
): SettingsNoticeReadingsDtoReadingsInner[] {
  const readings: SettingsNoticeReadingsDtoReadingsInner[] = [];
  if (update !== null) {
    const item = update.version ?? 'unknown';
    readings.push({
      kind: 'app-update',
      items: appUpdateWaits(update) ? [item] : [],
      unsettled: appUpdateUnsettled(update) ? [item] : [],
    });
  }
  if (detections !== null) {
    const found = detections.filter((detection) => detection.found);
    const accounts = found.flatMap(accountLogins);
    readings.push(
      {
        kind: 'agent-updates',
        items: cliUpdatesAvailable(detections).map(
          (detection) =>
            `${detection.kind}@${detection.update.latestVersion ?? ''}`,
        ),
        unsettled: found
          .filter((detection) => detection.update.available === null)
          .map((detection) => `${detection.kind}@`),
      },
      {
        kind: 'agent-sign-in',
        items: accounts
          .filter(({ loggedIn }) => loggedIn === false)
          .map(signInItemOf),
        unsettled: accounts
          .filter(({ loggedIn }) => loggedIn === null)
          .map(signInItemOf),
      },
    );
  }
  return readings;
}

const SHARE_SIGN_IN_PREFIX = 'share-sign-in:';

/** The storage a `share-sign-in` notice is about, as the daemon stored it: what a device that reads no shares draws. */
export function storedShareWait(notice: SettingsNotice): ShareWait {
  const destinationId = notice.key.startsWith(SHARE_SIGN_IN_PREFIX)
    ? notice.key.slice(SHARE_SIGN_IN_PREFIX.length)
    : notice.key;
  return {
    destinationId,
    label: notice.label ?? destinationId,
    reason: null,
    count: notice.items.length,
    shareIds: [...notice.items],
  };
}

/** The storage a `share-sign-in:<destination id>` notice is about, as Settings reads it now. */
export function shareWaitOf(
  waits: readonly ShareWait[],
  key: string,
): ShareWait | null {
  return (
    waits.find(
      (wait) => key === `${SHARE_SIGN_IN_PREFIX}${wait.destinationId}`,
    ) ?? null
  );
}

