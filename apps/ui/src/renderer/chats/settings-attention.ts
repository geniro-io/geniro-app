/** The named configurations from settings.json, re-read whenever settings are written. */
export function useConfigProfiles(): readonly ConfigProfile[] {
  const [profiles, setProfiles] = useState<readonly ConfigProfile[]>([]);
  useEffect(() => {
    let live = true;
    const read = (): void => {
      void window.geniro
        .getSettings()
        .then((settings) => {
          if (live) {
            setProfiles(settings.configProfiles);
          }
        })
        .catch(() => undefined);
    };
    read();
    const off = window.geniro.onSettingsChanged(read);
    return () => {
      live = false;
      off();
    };
  }, []);
  return profiles;
}
