import { SettingsNoticeKind } from '../autogenerated';

export interface SettingsNoticeRowView {
  noticeId: string;
  kind: SettingsNoticeKind;
  key: string;
}

const KINDS: ReadonlySet<string> = new Set(Object.values(SettingsNoticeKind));

/**
 * The Settings notice a manager-chat row stands for, or null when it is none.
 *
 * TWIN PARSER: the `settingsNotice` field of `HostRowWire` in
 * `apps/daemon/src/v1/agents/chat.types.ts`.
 */
export function readSettingsNoticeRow(
  payload: unknown,
): SettingsNoticeRowView | null {
  if (payload === null || typeof payload !== 'object') {
    return null;
  }
  const notice = (payload as Record<string, unknown>).settingsNotice;
  if (notice === null || typeof notice !== 'object') {
    return null;
  }
  const { noticeId, kind, key } = notice as Record<string, unknown>;
  if (
    typeof noticeId !== 'string' ||
    typeof key !== 'string' ||
    typeof kind !== 'string' ||
    !KINDS.has(kind)
  ) {
    return null;
  }
  return { noticeId, kind: kind as SettingsNoticeKind, key };
}
