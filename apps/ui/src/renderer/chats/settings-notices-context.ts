import { createContext } from 'react';

import type { CliDetection, ConfigProfile } from '../../shared/contracts';
import type { SettingsNotice } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { CliUpdatesController } from '../settings/use-cli-updates';
import type { UpdateController } from '../updates/use-update-state';
import type { CliLoginController } from '../use-cli-login';
import type { ShareWait } from './settings-attention';

export interface SettingsNoticesStore {
  apis: DaemonApis;
  /** The manager's notices by id; null until the first read answers. */
  notices: ReadonlyMap<string, SettingsNotice> | null;
  dismiss: (noticeId: string) => void;
  /** Null until Electron main's first reading lands. */
  detections: readonly CliDetection[] | null;
  cliUpdates: CliUpdatesController;
  login: CliLoginController;
  update: UpdateController;
  profiles: readonly ConfigProfile[];
  shareWaits: readonly ShareWait[];
  conflictIds: readonly string[];
  onOpenMemoryConflicts: (() => void) | null;
  remote: boolean;
}

/** Null outside the command center manager's chat, where a notice row draws nothing. */
export const SettingsNoticesContext =
  createContext<SettingsNoticesStore | null>(null);
