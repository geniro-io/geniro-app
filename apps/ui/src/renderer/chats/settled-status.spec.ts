import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  lastTerminalItemAt,
  settledRunStatus,
  TERMINAL_KINDS,
} from './settled-status';

function item(
  kind: string,
  payload: unknown = {},
  nodeId: string | null = null,
): ChatItem {
  return {
    id: 'i1',
    runId: 'r1',
    nodeId,
    seq: 1,
    kind: kind as ChatItem['kind'],
    role: null,
    payload,
    createdAt: 'now',
  };
}

describe('settledRunStatus', () => {
  it('reads each terminal kind as the status it implies', () => {
    expect(settledRunStatus(item('turn_complete'))).toBe('completed');
    expect(settledRunStatus(item('turn_cancelled'))).toBe('cancelled');
    expect(settledRunStatus(item('error'))).toBe('failed');
  });

  it('takes a workflow run’s roll-up from the stopReason, not the kind', () => {
    // Every workflow run ends in a run-level `turn_complete` whose stopReason
    // carries the verdict, so reading the kind alone reported a failed workflow
    // as completed.
    expect(
      settledRunStatus(
        item('turn_complete', { stopReason: 'workflow_failed' }),
      ),
    ).toBe('failed');
    expect(
      settledRunStatus(
        item('turn_complete', { stopReason: 'workflow_cancelled' }),
      ),
    ).toBe('cancelled');
    expect(
      settledRunStatus(
        item('turn_complete', { stopReason: 'workflow_completed' }),
      ),
    ).toBe('completed');
  });

  it('refuses a NODE’s own turn end', () => {
    // A workflow node settling says nothing about the run — sibling branches may
    // still be running, and reading one as the run's end re-enabled the composer
    // underneath them.
    expect(settledRunStatus(item('turn_complete', {}, 'coder'))).toBeNull();
    expect(settledRunStatus(item('error', {}, 'coder'))).toBeNull();
  });

  it('answers null for anything that is not a turn end', () => {
    expect(settledRunStatus(item('message', { text: 'hi' }))).toBeNull();
    expect(settledRunStatus(item('tool_call'))).toBeNull();
    // `unanswerable` and `system` rows are written AFTER a settle by the same
    // sweep, and reading either as terminal would settle a run twice.
    expect(settledRunStatus(item('unanswerable'))).toBeNull();
    expect(settledRunStatus(item('system'))).toBeNull();
  });

  it('exports the kinds as one set, so no caller can spell its own', () => {
    expect([...TERMINAL_KINDS].sort()).toEqual([
      'error',
      'turn_cancelled',
      'turn_complete',
    ]);
  });
});

describe('lastTerminalItemAt', () => {
  const at = (
    kind: ChatItem['kind'],
    createdAt: string,
    nodeId: string | null = null,
  ): ChatItem => ({
    id: `i-${createdAt}`,
    runId: 'r',
    nodeId,
    seq: 1,
    kind,
    role: null,
    payload: {},
    createdAt,
  });

  it('answers with the run’s own record of when it stopped', () => {
    // The defect this closes, with the measured numbers: the row the renderer
    // held said the run stopped at 07:24:48.881 while the daemon had recorded
    // the cancel at 07:24:50.870, and a task announcement written at
    // 07:24:49.462 — inside that gap — read as "produced after the settle", so
    // its in-progress row went on spinning on a run the user had stopped.
    expect(
      lastTerminalItemAt([
        at('task_list', '2026-08-14T07:24:49.462Z'),
        at('turn_cancelled', '2026-08-14T07:24:50.870Z'),
      ]),
    ).toBe(Date.parse('2026-08-14T07:24:50.870Z'));
  });

  it('takes the NEWEST terminal item, so a later turn wins', () => {
    expect(
      lastTerminalItemAt([
        at('turn_complete', '2026-08-14T07:00:00.000Z'),
        at('turn_complete', '2026-08-14T08:00:00.000Z'),
      ]),
    ).toBe(Date.parse('2026-08-14T08:00:00.000Z'));
  });

  it('ignores a workflow NODE’s own turn end', () => {
    // Same rule `settledRunStatus` enforces: a node's `turn_complete` says
    // nothing about the run, and reading one as the run's stop would close every
    // sibling branch's spinners while they were still working.
    expect(
      lastTerminalItemAt([
        at('turn_complete', '2026-08-14T07:00:00Z', 'writer'),
      ]),
    ).toBeNull();
  });

  it('answers null for a run whose transcript holds no terminal item', () => {
    // Which is what leaves the row's own timestamp as the fallback, rather than
    // claiming the run never stopped.
    expect(
      lastTerminalItemAt([at('message', '2026-08-14T07:00:00.000Z')]),
    ).toBeNull();
    expect(lastTerminalItemAt([])).toBeNull();
  });
});
