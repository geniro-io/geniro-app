import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { settledRunStatus, TERMINAL_KINDS } from './settled-status';

function item(
  kind: string,
  payload: unknown = {},
  nodeId: string | null = null,
): ChatItem {
  return {
    id: 'i1',
    runId: 'r1',
    nodeId,
    seq: 1,
    kind: kind as ChatItem['kind'],
    role: null,
    payload,
    createdAt: 'now',
  };
}

describe('settledRunStatus', () => {
  it('reads each terminal kind as the status it implies', () => {
    expect(settledRunStatus(item('turn_complete'))).toBe('completed');
    expect(settledRunStatus(item('turn_cancelled'))).toBe('cancelled');
    expect(settledRunStatus(item('error'))).toBe('failed');
  });

  it('takes a workflow run’s roll-up from the stopReason, not the kind', () => {
    // Every workflow run ends in a run-level `turn_complete` whose stopReason
    // carries the verdict, so reading the kind alone reported a failed workflow
    // as completed.
    expect(
      settledRunStatus(
        item('turn_complete', { stopReason: 'workflow_failed' }),
      ),
    ).toBe('failed');
    expect(
      settledRunStatus(
        item('turn_complete', { stopReason: 'workflow_cancelled' }),
      ),
    ).toBe('cancelled');
    expect(
      settledRunStatus(
        item('turn_complete', { stopReason: 'workflow_completed' }),
      ),
    ).toBe('completed');
  });

  it('refuses a NODE’s own turn end', () => {
    // A workflow node settling says nothing about the run — sibling branches may
    // still be running, and reading one as the run's end re-enabled the composer
    // underneath them.
    expect(settledRunStatus(item('turn_complete', {}, 'coder'))).toBeNull();
    expect(settledRunStatus(item('error', {}, 'coder'))).toBeNull();
  });

  it('answers null for anything that is not a turn end', () => {
    expect(settledRunStatus(item('message', { text: 'hi' }))).toBeNull();
    expect(settledRunStatus(item('tool_call'))).toBeNull();
    // `unanswerable` and `system` rows are written AFTER a settle by the same
    // sweep, and reading either as terminal would settle a run twice.
    expect(settledRunStatus(item('unanswerable'))).toBeNull();
    expect(settledRunStatus(item('system'))).toBeNull();
  });

  it('exports the kinds as one set, so no caller can spell its own', () => {
    expect([...TERMINAL_KINDS].sort()).toEqual([
      'error',
      'turn_cancelled',
      'turn_complete',
    ]);
  });
});
