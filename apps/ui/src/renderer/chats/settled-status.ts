import type { ItemDto as ChatItem, RunDto } from '../autogenerated';
import type { RunSettleAt } from './transcript-groups';
import { payloadBoolean, payloadString } from './transcript-payload';

/** Item kinds that end a RUN-level turn — after one, that turn is over. */
export const TERMINAL_KINDS: ReadonlySet<string> = new Set([
  'turn_complete',
  'turn_cancelled',
  'error',
]);

/**
 * Whether this row ENDED a run-level turn — a terminal kind, not a workflow
 * node's own, and not a continuation result that arrived inside a turn.
 *
 * TWIN PARSER: `insideTurn` is written by the daemon's `mapEventToItem`
 * (apps/daemon/src/v1/agents/utils/event-to-item.ts).
 */
function endsRunTurn(item: ChatItem): boolean {
  return (
    item.nodeId === null &&
    TERMINAL_KINDS.has(item.kind) &&
    payloadBoolean(item.payload, 'insideTurn') !== true
  );
}

/**
 * Whether this `turn_complete` is the settle of a turn whose prompt the CLI
 * answered INSIDE a continuation. It still ENDS the turn — the run settles on
 * it — but it is not the turn's visible ending: the continuation's own
 * `insideTurn` row, written a moment earlier, already carries the turn's
 * duration and cost. Drawn as well, it put `✓ done · 0s` directly under
 * `✓ done · 9m 44s · $5.08` — reported as a doubled system message.
 *
 * TWIN PARSER: `answeredByContinuation` is written by the daemon's
 * `mapEventToItem` (apps/daemon/src/v1/agents/utils/event-to-item.ts), from
 * `spawn-cli`'s `answeredByContinuation`.
 */
export function settlesOnContinuation(
  item: Pick<ChatItem, 'kind' | 'payload'>,
): boolean {
  return (
    item.kind === 'turn_complete' &&
    payloadBoolean(item.payload, 'answeredByContinuation') === true
  );
}

/**
 * The run status a terminal transcript item implies, or null when the item is
 * not one — a run-level turn end, and never a workflow node's own.
 *
 * `nodeId !== null` is refused here rather than at the call sites: a workflow's
 * per-node `turn_complete` says nothing about the RUN, and letting one through
 * re-enabled the composer while sibling branches were still running.
 *
 * A workflow run's roll-up rides the terminal item's `stopReason`, so a failed
 * or cancelled workflow is not read as `completed` just because its last item's
 * kind says so.
 *
 * Extracted because three sites need it and they must not drift: the live
 * stream mirrors it as it happens, while the two REPLAY paths (activating a run,
 * and the post-reconnect delta) may only apply it for the item that is actually
 * LAST. That distinction is the whole reason this is a function rather than an
 * inline branch — see its callers in `Chats.tsx`.
 *
 * A row the daemon stamped `insideTurn` ends nothing: it is a background task's
 * continuation finishing while the user's own turn was still owed its answer.
 * REPORTED as a sidebar reading `completed · 32m` over a thread still visibly
 * working — the live mirror had settled the row on exactly such a result, and
 * the daemon, whose status never moved, had no reason to announce again.
 */
export function settledRunStatus(item: ChatItem): RunDto['status'] | null {
  if (!endsRunTurn(item)) {
    return null;
  }
  const stopReason = payloadString(item.payload, 'stopReason');
  if (stopReason === 'workflow_failed') {
    return 'failed';
  }
  if (stopReason === 'workflow_cancelled') {
    return 'cancelled';
  }
  if (item.kind === 'turn_complete') {
    return 'completed';
  }
  return item.kind === 'turn_cancelled' ? 'cancelled' : 'failed';
}

/**
 * WHEN this run last stopped, as its own transcript records it — the newest
 * terminal item's timestamp, or null when it holds none.
 *
 * The run ROW cannot answer this alone, which is what this exists for. Items
 * never touch `updatedAt`, so that field is only as fresh as the last thing that
 * DID write the row, and it can therefore sit BEFORE the moment the run actually
 * stopped. Measured on a cancelled cursor turn: the daemon recorded the cancel at
 * 07:24:50.871 while the row the renderer held said 07:24:48.881, and a task
 * announcement written at 07:24:49.462 — squarely inside that 2-second gap — read
 * as "produced after the run settled", so its in-progress row went on spinning on
 * a run the user had just stopped.
 *
 * Readers take THIS moment first, and the row's own timestamp only when there is
 * no terminal item at all (a settle that wrote none, such as a cancel) — see
 * {@link settleMomentOf}. The later of the two was the earlier design, and it made
 * "has this delegate spoken since the run settled?" unanswerable, because a
 * delegate's own row pushes the stamp past itself. The rows that arrive after a
 * CLI's own turn-end line are after this moment too, which is what makes them
 * evidence of work carrying on.
 */
export function lastTerminalItemAt(items: readonly ChatItem[]): number | null {
  let latest: number | null = null;
  for (const item of items) {
    if (!endsRunTurn(item)) {
      continue;
    }
    const at = Date.parse(item.createdAt);
    if (Number.isFinite(at) && (latest === null || at > latest)) {
      latest = at;
    }
  }
  return latest;
}

/**
 * WHEN a run that HAS stopped stopped — its own terminal ITEM, falling back to
 * the row's timestamp, or `'unknown'` when neither can be read.
 *
 * The item FIRST, and never the later of the two. The row's `updatedAt` is not
 * bumped by items, so it can sit before the stop it describes; taking the later
 * of the two made "has this delegate spoken since the run settled?" unanswerable,
 * because a delegate's own row would push the stamp past itself. The fallback
 * still matters: a settle path that writes no terminal item (a cancel) has
 * nothing else to answer with.
 */
export function settleMomentOf(
  run: RunDto | null,
  rows: readonly ChatItem[],
): RunSettleAt {
  const itemAt = lastTerminalItemAt(rows);
  if (itemAt !== null && Number.isFinite(itemAt)) {
    return itemAt;
  }
  const rowAt = run ? Date.parse(run.updatedAt) : Number.NaN;
  // `'unknown'` and not null when nothing is readable: the run DID stop, and
  // losing that fact would put every spinner back — see {@link RunSettleAt}.
  return Number.isFinite(rowAt) ? rowAt : 'unknown';
}

/**
 * Rows the daemon writes about work that OUTLIVES a turn: a background command
 * ending (`shell_info`), one being noticed (`shell_open`), a delegate's close
 * (`subagent_info`). They land AFTER the turn's own terminal row and say
 * nothing about the turn, so they cannot be what a replay reads the run's
 * state from.
 */
const AFTER_TURN_BOOKKEEPING: ReadonlySet<string> = new Set([
  'shell_info',
  'shell_open',
  'subagent_info',
]);

/**
 * The row a REPLAY reads the run's present state from: the last row that is
 * not {@link AFTER_TURN_BOOKKEEPING}.
 *
 * The plain last row was right until the daemon began writing those rows on
 * its own — a `sleep` started in the background and finishing after the turn
 * put a `shell_info` at the tail, so a replay that ended the turn offline read
 * "not ended", and Stop with the working row stayed up over a finished run.
 */
export function replayTail(items: readonly ChatItem[]): ChatItem | undefined {
  for (let index = items.length - 1; index >= 0; index -= 1) {
    const item = items[index];
    if (item !== undefined && !AFTER_TURN_BOOKKEEPING.has(item.kind)) {
      return item;
    }
  }
  return undefined;
}
