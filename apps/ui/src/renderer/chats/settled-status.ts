import type { ItemDto as ChatItem, RunDto } from '../autogenerated';
import { payloadString } from './transcript-payload';

/** Item kinds that end a RUN-level turn — after one, that turn is over. */
export const TERMINAL_KINDS: ReadonlySet<string> = new Set([
  'turn_complete',
  'turn_cancelled',
  'error',
]);

/**
 * The run status a terminal transcript item implies, or null when the item is
 * not one — a run-level turn end, and never a workflow node's own.
 *
 * `nodeId !== null` is refused here rather than at the call sites: a workflow's
 * per-node `turn_complete` says nothing about the RUN, and letting one through
 * re-enabled the composer while sibling branches were still running.
 *
 * A workflow run's roll-up rides the terminal item's `stopReason`, so a failed
 * or cancelled workflow is not read as `completed` just because its last item's
 * kind says so.
 *
 * Extracted because three sites need it and they must not drift: the live
 * stream mirrors it as it happens, while the two REPLAY paths (activating a run,
 * and the post-reconnect delta) may only apply it for the item that is actually
 * LAST. That distinction is the whole reason this is a function rather than an
 * inline branch — see its callers in `Chats.tsx`.
 */
export function settledRunStatus(item: ChatItem): RunDto['status'] | null {
  if (item.nodeId !== null || !TERMINAL_KINDS.has(item.kind)) {
    return null;
  }
  const stopReason = payloadString(item.payload, 'stopReason');
  if (stopReason === 'workflow_failed') {
    return 'failed';
  }
  if (stopReason === 'workflow_cancelled') {
    return 'cancelled';
  }
  if (item.kind === 'turn_complete') {
    return 'completed';
  }
  return item.kind === 'turn_cancelled' ? 'cancelled' : 'failed';
}
