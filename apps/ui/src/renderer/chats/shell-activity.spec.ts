import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { runningShellsByAgent, shellRuns } from './shell-activity';

let seq = 0;
function item(
  kind: ChatItem['kind'],
  payload: unknown,
  nodeId: string | null = null,
): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    nodeId,
    seq,
    kind,
    role: null,
    payload,
    createdAt: '2026-08-24T10:00:00.000Z',
  };
}

/** A claude `Bash` call, as `event-to-item.ts` persists one. */
const bash = (
  id: string,
  command: string,
  extra: Record<string, unknown> = {},
  nodeId: string | null = null,
) =>
  item('tool_call', { id, name: 'Bash', input: { command, ...extra } }, nodeId);

const reply = (id: string, result: unknown, isError = false) =>
  item('tool_result', { id, name: 'Bash', result, isError });

const namedCall = (id: string, name: string, input: unknown) =>
  item('tool_call', { id, name, input });

const namedReply = (
  id: string,
  name: string,
  result: unknown,
  isError = false,
) => item('tool_result', { id, name, result, isError });

/**
 * The launch reply as the CLI actually writes it, transcribed from the shipped
 * 2.1.237 binary — one ternary with three arms, every one of them ending
 * `Output is being written to: <path>.`
 *
 * The fixtures here used to stop at `ID: bash_3.`, a shape the CLI never
 * sends, which is exactly the trap `testing.md` warns about: a spec asserting
 * against a string it invented itself passes whatever the reader does. The
 * reader now requires the whole announcement, and it has to be given the whole
 * announcement to be tested at all.
 */
const LAUNCHED = (id: string): string =>
  `Command running in background with ID: ${id}. Output is being written to: /tmp/${id}.log.`;

/** The second arm: a command that outran its own timeout. Note the PARENS. */
const TIMED_OUT_INTO_BACKGROUND = (id: string): string =>
  `Command did not complete within its 120s timeout and was moved to the background (ID: ${id}). Output is being written to: /tmp/${id}.log.`;

/** The third: the user pushed it there by hand. */
const BACKGROUNDED_BY_USER = (id: string): string =>
  `Command was manually backgrounded by user with ID: ${id}. Output is being written to: /tmp/${id}.log.`;

describe('shellRuns', () => {
  it('reads a foreground command as running until its reply lands', () => {
    expect(shellRuns([bash('c1', 'pnpm build')])).toEqual([
      expect.objectContaining({
        id: 'c1',
        command: 'pnpm build',
        background: false,
        status: 'running',
      }),
    ]);
    expect(
      shellRuns([bash('c1', 'pnpm build'), reply('c1', 'done')])[0]?.status,
    ).toBe('completed');
  });

  it('reads a reply the CLI marked as an error as a failure', () => {
    expect(
      shellRuns([bash('c1', 'pnpm build'), reply('c1', 'boom', true)])[0]
        ?.status,
    ).toBe('failed');
  });

  it('keeps a BACKGROUND command running after its launch replies', () => {
    // The whole point of the background arm: the reply arrives within the
    // second and the command runs on. Read like a foreground one it would be
    // retired the moment it started.
    const shells = shellRuns([
      bash('c1', 'pnpm dev', { run_in_background: true }),
      reply('c1', LAUNCHED('bash_3')),
    ]);
    expect(shells[0]).toEqual(
      expect.objectContaining({
        background: true,
        handle: 'bash_3',
        status: 'running',
      }),
    );
  });

  it('does not read `ID:` in a command OUTPUT as a background launch', () => {
    // THE reported defect, and the exact output that caused it. A foreground
    // command's reply is its own output, so any command printing the
    // characters `ID:` — Go source with a struct field, a JSON blob, a doc —
    // was promoted to a detached shell and then never settled, because a
    // detached shell only ends on a probe, a kill or the daemon's `shell_info`
    // and none is ever coming for a command that already exited. Measured on
    // the reporter's own `geniro.db`, run `d64593d0`: 11 phantoms out of 690
    // shells, with handles like `row`, `spec` and `"foryou",`, the oldest
    // listed as running for a day and a half — the "три терминала" under a
    // thread that had finished, and the "эти шелл команды вообще стейлд".
    const shells = shellRuns([
      bash('c1', 'git show origin/main:feed.go'),
      reply(
        'c1',
        'type Row struct {\n\tID: row\n\tBucketForYou, spec string\n}\n',
      ),
    ]);
    expect(shells[0]).toEqual(
      expect.objectContaining({
        background: false,
        handle: null,
        status: 'completed',
      }),
    );
  });

  it('does not read an announcement BURIED in output as a launch either', () => {
    // The anchor, which earned itself within a day of the fix above: a
    // `sqlite3` query printing past launch replies, and a `grep` over the CLI
    // binary, each produced a phantom shell in this very conversation — one of
    // them carrying the literal handle `${e}`. The announcement is the whole
    // of what the CLI answers a detached launch with, never something quoted
    // in the middle of output.
    const shells = shellRuns([
      bash('c1', 'sqlite3 geniro.db "select result from items"'),
      reply('c1', `some earlier output\n${LAUNCHED('bash_9')}\nmore output\n`),
    ]);
    expect(shells[0]).toEqual(
      expect.objectContaining({ background: false, status: 'completed' }),
    );
  });

  it('recognises all three of the CLI’s own launch wordings', () => {
    // One ternary in the shipped binary, three arms — a plain launch, one the
    // user backgrounded by hand, and one that outran its timeout. The middle
    // one wraps its id in PARENTHESES, which the old reader captured into the
    // handle (`bash_7)`), so no later probe could ever match it.
    for (const [announcement, id] of [
      [LAUNCHED('bash_1'), 'bash_1'],
      [BACKGROUNDED_BY_USER('bash_2'), 'bash_2'],
      [TIMED_OUT_INTO_BACKGROUND('bash_3'), 'bash_3'],
    ] as const) {
      const shells = shellRuns([
        bash('c1', 'pnpm dev'),
        reply('c1', announcement),
      ]);
      expect(shells[0]).toEqual(
        expect.objectContaining({
          background: true,
          handle: id,
          status: 'running',
        }),
      );
    }
  });

  it('closes a command that ASKED for the background and came back with output', () => {
    // The reply decides BOTH ways, which is what was missing: a call carrying
    // `run_in_background` whose reply is plain output was never detached, so
    // leaving it `running` stranded a row no probe could ever match — it has
    // no handle to be matched BY. Two such rows on the reporter's own ledger,
    // from the day this was written.
    const shells = shellRuns([
      bash('c1', 'echo hi', { run_in_background: true }),
      reply('c1', 'hi\n'),
    ]);
    expect(shells[0]).toEqual(
      expect.objectContaining({
        background: false,
        handle: null,
        status: 'completed',
      }),
    );
  });

  it('settles a background command from the probe that reports it done', () => {
    const shells = shellRuns([
      bash('c1', 'pnpm dev', { run_in_background: true }),
      reply('c1', LAUNCHED('bash_3')),
      namedCall('c2', 'BashOutput', { bash_id: 'bash_3' }),
      namedReply(
        'c2',
        'BashOutput',
        '<status>failed</status>\n<exit_code>1</exit_code>',
      ),
    ]);
    expect(shells[0]).toEqual(
      expect.objectContaining({ status: 'failed', exitCode: 1 }),
    );
  });

  it('leaves a background command running while its probe says so', () => {
    const shells = shellRuns([
      bash('c1', 'pnpm dev', { run_in_background: true }),
      reply('c1', LAUNCHED('bash_3')),
      namedCall('c2', 'BashOutput', { bash_id: 'bash_3' }),
      namedReply('c2', 'BashOutput', '<status>running</status>\nReady in 1s'),
    ]);
    expect(shells[0]?.status).toBe('running');
  });

  it('reads a kill as one, and a FAILED kill as no kill at all', () => {
    const kill = (resultIsError: boolean) =>
      shellRuns([
        bash('c1', 'pnpm dev', { run_in_background: true }),
        reply('c1', LAUNCHED('bash_3')),
        namedCall('c2', 'KillShell', { shell_id: 'bash_3' }),
        namedReply('c2', 'KillShell', 'x', resultIsError),
      ])[0]?.status;
    expect(kill(false)).toBe('killed');
    // A handle the CLI cannot find answers with an error — retiring the row off
    // that would report a shell nothing stopped as stopped.
    expect(kill(true)).toBe('running');
  });

  it('reads a command the CLI detached ITSELF as detached', () => {
    // The agent asked for a foreground command and the CLI backgrounded it —
    // measured wordings: one the user pushed to the background, and one that
    // outran its own timeout. Read off the input flag alone, such a command is
    // retired the instant it is detached, which is the opposite of the truth.
    const shells = shellRuns([
      bash('c1', 'pnpm dev'),
      reply('c1', TIMED_OUT_INTO_BACKGROUND('bash_7')),
    ]);
    expect(shells[0]).toEqual(
      expect.objectContaining({
        background: true,
        handle: 'bash_7',
        status: 'running',
      }),
    );
    // …and it is then closed by the same settle any other detached command is.
    expect(
      shellRuns([
        bash('c1', 'pnpm dev'),
        reply('c1', LAUNCHED('bash_7')),
        item('shell_info', { id: null, workId: 'bash_7' }),
      ])[0]?.status,
    ).toBe('completed');
  });

  it('retires a background shell when the DAEMON says it finished', () => {
    // The one ending no tool call reports. Without this row the command is
    // listed for as long as the turn lasts, and a long turn accumulates every
    // one it ever launched.
    const shells = shellRuns([
      bash('c1', 'pnpm dev', { run_in_background: true }),
      reply('c1', LAUNCHED('bash_3')),
      item('shell_info', { id: 'c1', workId: 'bash_3' }),
    ]);
    expect(shells[0]?.status).toBe('completed');
  });

  it('matches a settle that names only the CLI’s own work id', () => {
    // One of the two settle channels carries no tool call at all, and a session
    // that resumed after the launch never saw the line that would have paired
    // them — so the handle parsed out of the launch reply is the match.
    const shells = shellRuns([
      bash('c1', 'pnpm dev', { run_in_background: true }),
      reply('c1', LAUNCHED('bash_3')),
      item('shell_info', { id: null, workId: 'bash_3' }),
    ]);
    expect(shells[0]?.status).toBe('completed');
  });

  it('does not coarsen an outcome a probe already reported', () => {
    // The settle says only that the unit is no longer open. A probe said HOW it
    // ended, with an exit code, and that is the better answer.
    const shells = shellRuns([
      bash('c1', 'pnpm dev', { run_in_background: true }),
      reply('c1', LAUNCHED('bash_3')),
      namedCall('c2', 'BashOutput', { bash_id: 'bash_3' }),
      namedReply(
        'c2',
        'BashOutput',
        '<status>failed</status>\n<exit_code>1</exit_code>',
      ),
      item('shell_info', { id: 'c1', workId: 'bash_3' }),
    ]);
    expect(shells[0]).toEqual(
      expect.objectContaining({ status: 'failed', exitCode: 1 }),
    );
  });

  it('ignores a settle for a command it has never seen', () => {
    // A transcript paged from the middle: the settle is in the window and the
    // launch is not. Nothing to retire, and nothing to invent either.
    expect(
      shellRuns([item('shell_info', { id: 'gone', workId: 'bash_9' })]),
    ).toEqual([]);
  });

  it('never lists the tools that READ a shell as shells of their own', () => {
    expect(
      shellRuns([
        namedCall('c2', 'BashOutput', { bash_id: 'bash_3' }),
        namedCall('c3', 'KillShell', { shell_id: 'bash_3' }),
      ]),
    ).toEqual([]);
  });

  it("takes an ACP agent's own classification, and its title when it discloses nothing", () => {
    // cursor sends `toolKind` and routinely withholds the arguments; a row
    // named by the call is the honest answer, and dropping it would answer
    // "what is running" with silence on that CLI.
    const shells = shellRuns([
      item('tool_call', {
        id: 'c1',
        name: 'Run terminal command',
        input: {},
        toolKind: 'execute',
      }),
    ]);
    expect(shells).toEqual([
      expect.objectContaining({
        command: 'Run terminal command',
        status: 'running',
      }),
    ]);
  });

  it('ignores tool calls that are not shells', () => {
    expect(
      shellRuns([
        item('tool_call', {
          id: 'c1',
          name: 'Read',
          input: { file_path: '/tmp/x' },
        }),
        item('message', { text: 'hello' }),
      ]),
    ).toEqual([]);
  });

  it("keeps a command the DAEMON detached, whatever the CLI's prose says", () => {
    // THE REPORTED DEFECT, in its own words: a sidebar row reading `working ·
    // waiting on background work` beside a header counting zero shells. The
    // sidebar reads `Run.shellsOpen`, which the daemon counts off the CLI's
    // structured frames; this fold could only recognise a detachment by
    // matching the CLI's ENGLISH, and that match is deliberately strict, so it
    // misses — here the reply is the CLI's own announcement with the trailing
    // output path absent, which `readLaunchHandle` refuses. Before the
    // `shell_open` row the reply then read as the command's OUTPUT and the
    // shell was marked finished, so one question had two answers.
    const shells = shellRuns([
      bash('c1', 'sleep 240', { run_in_background: true }),
      item('shell_open', { id: 'c1', workId: 'bash_1' }),
      reply('c1', 'Command running in background with ID: bash_1.'),
    ]);
    expect(shells).toHaveLength(1);
    expect(shells[0]?.status).toBe('running');
    expect(shells[0]?.background).toBe(true);
    // The open's work id stands in for the handle the prose did not yield, so
    // the `shell_info` that ends this command can still find the row.
    expect(shells[0]?.handle).toBe('bash_1');
    expect(
      shellRuns([
        bash('c1', 'sleep 240', { run_in_background: true }),
        item('shell_open', { id: 'c1', workId: 'bash_1' }),
        reply('c1', 'Command running in background with ID: bash_1.'),
        item('shell_info', { id: 'c1', workId: 'bash_1' }),
      ])[0]?.status,
    ).toBe('completed');
  });

  it('detaches a command whose open lands AFTER its reply closed it', () => {
    // Nothing orders the daemon's row against the CLI's own reply, so the fold
    // has to undo that close rather than merely decline to make it. Same
    // transcript as above with the two rows swapped: without the reopen this
    // reads `completed` and the count and the list disagree again.
    const shells = shellRuns([
      bash('c1', 'sleep 240', { run_in_background: true }),
      reply('c1', 'Command running in background with ID: bash_1.'),
      item('shell_open', { id: 'c1', workId: 'bash_1' }),
    ]);
    expect(shells[0]?.status).toBe('running');
    expect(shells[0]?.background).toBe(true);
  });

  it('lets the PROSE handle win, since only a probe can be addressed to it', () => {
    // The two ids are different namespaces: `shell_info` names the CLI's work
    // id, while a `BashOutput` probe names the handle the launch announced. The
    // open only fills a handle nothing else supplied.
    const shells = shellRuns([
      bash('c1', 'sleep 240', { run_in_background: true }),
      item('shell_open', { id: 'c1', workId: 'task-77' }),
      reply('c1', LAUNCHED('bash_9')),
    ]);
    expect(shells[0]?.handle).toBe('bash_9');
  });

  it('marks and never CREATES: an open for a call below the window adds nothing', () => {
    // A launch outside the loaded transcript would otherwise become a command
    // with no name to draw. It is also not an ending, so a foreground command
    // running beside it is untouched.
    const shells = shellRuns([
      item('shell_open', { id: 'c-unknown', workId: 'bash_1' }),
      bash('c1', 'pnpm build'),
    ]);
    expect(shells).toHaveLength(1);
    expect(shells[0]?.id).toBe('c1');
    expect(shells[0]?.background).toBe(false);
  });

  it('still closes a plain foreground command on its own output', () => {
    // The reply's "no announcement means this is the output" arm is untouched
    // for a command the daemon never opened — which is what keeps a foreground
    // command from being listed for ever.
    const shells = shellRuns([
      bash('c1', 'pnpm build'),
      reply('c1', 'built in 3s'),
    ]);
    expect(shells[0]?.status).toBe('completed');
    expect(shells[0]?.background).toBe(false);
  });
});

describe('runningShellsByAgent', () => {
  it('groups the LIVE shells by the node that started them', () => {
    const byAgent = runningShellsByAgent([
      bash('c1', 'sleep 30', {}, 'node-a'),
      bash('c2', 'echo hi', {}, 'node-b'),
      reply('c2', 'hi'),
      bash('c3', 'sleep 60'),
    ]);
    expect([...byAgent.keys()]).toEqual(['node-a', null]);
    expect(byAgent.get('node-a')?.map((s) => s.command)).toEqual(['sleep 30']);
    expect(byAgent.get(null)?.map((s) => s.command)).toEqual(['sleep 60']);
  });

  it("keeps a DELEGATE's shell, which the task-list fold drops", () => {
    // A delegate's task list is its own bookkeeping; a delegate's `pnpm build`
    // is a process on the user's machine, which is the question this answers.
    const call = bash('c1', 'pnpm build');
    (call.payload as Record<string, unknown>).parentToolUseId = 'sub-1';
    expect(runningShellsByAgent([call]).get(null)?.length).toBe(1);
  });
});
