/**
 * What the agents are RUNNING on this machine right now — the shells behind
 * their `execute` tool calls, read off the transcript.
 *
 * The ask was for the thing every coding CLI puts on its own screen: the
 * commands currently in flight, somewhere a reader can see them without
 * scrolling the conversation for the last tool row and guessing whether it has
 * come back. The transcript is where that lives, because a shell is only ever
 * started by a tool call and only ever ends by one coming back — geniro spawns
 * none of these itself. The daemon declines ACP's `terminal/*` capability
 * (`acp/acp.types.ts`), so an ACP agent runs its own commands too and there is
 * no process on this side to enumerate.
 *
 * TWIN PARSER, twice over. The item payloads are the ones
 * `apps/daemon/src/v1/agents/utils/event-to-item.ts` writes (`id` / `name` /
 * `input` / `toolKind` for a call, `id` / `result` / `isError` for its reply) —
 * a payload is `z.unknown()` on the wire BY DESIGN, so no generated type spans
 * the two sides. And the BACKGROUND half reads one CLI's own prose: claude
 * answers a detached launch with `Command running in background with ID: <id>.`
 * and a `BashOutput` probe with `<status>…</status>` / `<exit_code>…</exit_code>`
 * (read out of the installed 2.1.237 binary's string table). Both are matched
 * narrowly and both are OPTIONAL — a launch nobody could parse an id out of
 * stays a running background shell, it just cannot be told apart from its
 * siblings by a later probe.
 *
 * A detached command finishing is the one ending no tool call reports — the
 * CLI announces it to the MODEL out of band and to the conversation as a
 * sentence the agent writes (measured 2026-08-24 on claude 2.1.237: a 45-second
 * `sleep` whose transcript holds no probe at all). That is what the daemon's
 * `shell_info` row exists to carry, and reading it here is what keeps this list
 * from accumulating: without it every background command a session ever
 * launched stays listed until its turn ends, and on a long turn they pile up.
 */

/**
 * How a shell ended, or that it has not.
 *
 * `killed` is separate from `completed` because it is the one ending the USER's
 * agent chose rather than the command reaching its own end, and `failed` covers
 * both a non-zero exit and a tool reply the CLI marked as an error.
 */
export type ShellStatus = 'running' | 'completed' | 'failed' | 'killed';

/**
 * A shell's state said in the RUN vocabulary's words — the same translation
 * `block-shell.tsx` makes for its own block lifecycle, and for the same reason:
 * these vocabularies are MODELS, and the app spells one state one way.
 *
 * `killed → cancelled` is the pair that matters: the block beside a shell
 * already translates, so an untranslated dialog spells one event two ways on
 * one screen.
 */
export const RUN_STATUS_OF_SHELL: Record<ShellStatus, RunStatusKind> = {
  running: 'running',
  completed: 'completed',
  failed: 'failed',
  killed: 'cancelled',
};

/** One shell an agent started, as the panel lists it. */
export interface ShellRun {
  /** The launching tool call's id — unique within the run, and the row's key. */
  id: string;
  /**
   * What is running: the command the agent wrote, or — for a CLI that names a
   * call and withholds its arguments — the call's own title.
   *
   * Never empty, and never dropped for want of a command: a cursor `execute`
   * call routinely discloses nothing (see `disclosesInput` in `tool-render.ts`),
   * and hiding those rows would answer "what is running" with silence on one of
   * the two CLIs the app ships.
   */
  command: string;
  /** The agent's own one-line note about what the command is for. */
  description: string | null;
  /** Whether it was launched detached (claude's `run_in_background`). */
  background: boolean;
  /**
   * The CLI's own handle for a background shell, once its launch has replied.
   *
   * Null while the launch is still in flight, and null for good when the reply
   * carried no id — which costs only the ability to match a later probe to this
   * row, never the row itself.
   */
  handle: string | null;
  status: ShellStatus;
  /** The exit code a probe reported, when one did. */
  exitCode: number | null;
  /** When the call streamed in — what the row's clock counts from. */
  startedAt: string;
  /** Which agent card this belongs to: the item's node id (null in a chat). */
  agentId: string | null;
}

/** claude's readers over a background shell it already started. */
const OUTPUT_TOOLS: ReadonlySet<string> = new Set([
  'BashOutput',
  'BashOutputTool',
]);
/** …and the two names it has used for stopping one. */
const KILL_TOOLS: ReadonlySet<string> = new Set(['KillShell', 'KillBash']);

/**
 * The handle keys a background-shell tool accepts, in the CLI's own precedence
 * (`task_id ?? shell_id`, with `bash_id` the older spelling its own reader still
 * falls back to).
 */
const HANDLE_KEYS = ['task_id', 'bash_id', 'shell_id'] as const;

function asRecord(value: unknown): Record<string, unknown> | null {
  return value && typeof value === 'object' && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

/** The tool call's arguments, whatever shape they arrived in. */
function inputOf(payload: unknown): unknown {
  const record = asRecord(payload);
  return record ? record.input : undefined;
}

/** Which background shell a probe or a kill is aimed at. */
function readHandle(input: unknown): string | null {
  const record = asRecord(input);
  if (!record) {
    return null;
  }
  for (const key of HANDLE_KEYS) {
    const value = record[key];
    if (typeof value === 'string' && value !== '') {
      return value;
    }
  }
  return null;
}

/**
 * The id claude hands back when it detaches a command — matched on the whole
 * ANNOUNCEMENT, never on `ID:` alone.
 *
 * There are three wordings and they are one ternary in the shipped binary
 * (read out of 2.1.237): a plain launch, one the user backgrounded by hand,
 * and one that outran its own timeout —
 *
 * ```
 * Command running in background with ID: <id>. Output is being written to: <path>.
 * Command was manually backgrounded by user with ID: <id>. Output is being written to: <path>.
 * Command did not complete within its <N>s timeout and was moved to the background (ID: <id>). Output is being written to: <path>.
 * ```
 *
 * — so all three put the id directly before `Output is being written to:`,
 * with either a `.` or a `).` between. Matching that whole shape is what makes
 * this a recogniser rather than a guess.
 *
 * **It used to match `\bID:\s*([^\s.]+)` anywhere in the reply, and that is the
 * defect this rewrite exists to remove.** A foreground command's reply is its
 * OUTPUT, so any command whose output happened to contain the characters `ID:`
 * — a `git show` of Go source with a struct field, a JSON blob, a doc listing
 * — was read as having been detached: promoted to a background shell, never
 * settled (a detached shell only ends on a probe, a kill or the daemon's
 * `shell_info`, and none is ever coming for a command that already exited),
 * and therefore listed as running for ever. Measured on the reporter's own
 * `geniro.db`, run `d64593d0`: 690 shells, **11 of them phantoms**, with
 * handles like `row`, `spec`, `resp` and `"foryou",` — the oldest running for
 * a day and a half. That is the reported "три терминала" under a thread that
 * had finished, and the "эти шелл команды вообще стейлд" beside it.
 *
 * The old doc justified the loose match by saying a MISS is survivable. It is
 * — a genuinely detached command that this fails to recognise is marked
 * finished when its immediate reply lands, so it simply drops out of the
 * running list — and that is precisely the argument for tightening rather than
 * loosening: the two failures are not comparable. A miss costs one row that
 * should have been listed; a false positive costs a row that can never be
 * unlisted, and poisons the header count for the life of the conversation.
 *
 * It is anchored at the START of the reply for the same reason, and that guard
 * earned itself within a day: the announcement is the whole of what the CLI
 * answers a detached launch with, never something buried in output — so a
 * command whose OUTPUT quotes the sentence is not a launch. Measured on this
 * very conversation, where a `sqlite3` query printing past launch replies and
 * a `grep` over the CLI binary each produced a phantom shell, one of them
 * carrying the literal handle `${e}`.
 */
function readLaunchHandle(text: string): string | null {
  const match =
    /^\s*\S[^\n]*?\bID:\s*([^\s).]+)\)?\.\s*Output is being written to:/.exec(
      text,
    );
  return match?.[1] ?? null;
}

/** What a `BashOutput` probe says about the shell it read. */
function readProbedStatus(
  text: string,
): { status: ShellStatus; exitCode: number | null } | null {
  const status = /<status>\s*(\w+)\s*<\/status>/.exec(text)?.[1];
  if (status === undefined) {
    return null;
  }
  const code = /<exit_code>\s*(-?\d+)\s*<\/exit_code>/.exec(text)?.[1];
  const exitCode = code === undefined ? null : Number.parseInt(code, 10);
  if (status === 'running') {
    return { status: 'running', exitCode: null };
  }
  if (status === 'completed' || status === 'failed' || status === 'killed') {
    return { status, exitCode };
  }
  // A word this does not know is not an ending: reporting it as one would
  // retire a row for a shell that is still going.
  return null;
}

/**
 * Retire the shell a `shell_info` row names — the daemon saying a DETACHED
 * command has really finished.
 *
 * This is the ONE ending the transcript otherwise has no record of: the
 * launching call was answered the moment the CLI accepted the command, and the
 * completion is reported to the model out of band. Without it every background
 * command a session launched stays listed until its turn ends.
 *
 * Matched by the LAUNCHING CALL where the CLI tied one to the unit, else by its
 * own work id — the handle the launch reply named. Both, because the settle
 * carries the call on one of its two channels and not the other.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/utils/event-to-item.ts` writes the
 * two keys read here (`id` = the launching tool call, `workId` = the CLI's own
 * id). An item payload is `z.unknown()` on the wire BY DESIGN — every kind
 * carries a different shape — so no generated type spans the two sides, and a
 * key renamed there must be renamed here.
 */
function settleFromShellInfo(
  callId: string | null,
  workId: string | null,
  index: {
    byCall: Map<string, ShellRun>;
    byHandle: Map<string, ShellRun>;
  },
): void {
  const target =
    (callId === null ? undefined : index.byCall.get(callId)) ??
    (workId === null ? undefined : index.byHandle.get(workId));
  // Only a shell still believed to be RUNNING. One a probe has already settled
  // knows HOW it ended (`failed`, `killed`, with an exit code); this channel
  // reports only that the unit is no longer open, so letting it through would
  // coarsen a finer answer that is already correct.
  if (target !== undefined && target.status === 'running') {
    target.status = 'completed';
  }
}

/**
 * Mark the shell a `shell_open` row names as DETACHED — the daemon saying which
 * tool calls this CLI actually put in the background.
 *
 * The AUTHORITY on that question, ranked above {@link readLaunchHandle}, and the
 * fix for two surfaces answering it differently. The daemon reads it off the
 * CLI's own structured frames; this reader could only recover it by matching the
 * CLI's English, which is deliberately strict (a loose match promotes a
 * foreground command whose OUTPUT quotes the announcement into a shell nothing
 * can ever close) and therefore misses. Every miss put the run row's own
 * `shellsOpen` — which counts exactly these events — over a transcript naming
 * fewer commands than the count, and the two are read by different surfaces:
 * REPORTED as a sidebar row saying `working · waiting on background work` beside
 * a header counting zero shells.
 *
 * It marks and never CREATES: a row naming a call this transcript has not seen
 * is a launch below the loaded window, and inventing a shell for it would put a
 * command on screen with no name to draw. It also never closes one — the open
 * and the close are two rows, and this is the open.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/utils/event-to-item.ts` writes the two
 * keys read here (`id` = the launching tool call, `workId` = the CLI's own id).
 * An item payload is `z.unknown()` on the wire BY DESIGN — every kind carries a
 * different shape — so no generated type spans the two sides, and a key renamed
 * there must be renamed here.
 */
function detachFromShellOpen(
  callId: string | null,
  workId: string | null,
  index: {
    byCall: Map<string, ShellRun>;
    byHandle: Map<string, ShellRun>;
  },
): void {
  if (callId === null) {
    return;
  }
  const target = index.byCall.get(callId);
  if (target === undefined) {
    return;
  }
  target.background = true;
  // Nothing orders this row against the launch's own REPLY, so the case where
  // the reply landed first has to be undone here: with no announcement in its
  // prose that arm reads the reply as the command's output and marks the shell
  // finished. `completed` is the only status reachable by then — a probe or a
  // kill is addressed to a handle, which does not exist until one of the two
  // channels has named it — so this cannot coarsen a finer ending.
  if (target.status === 'completed') {
    target.status = 'running';
  }
  // The CLI's own id for the unit, so a later `shell_info` naming only the work
  // id still finds this row — the settle carries the call on one of its two
  // channels and not the other. The prose handle wins where it landed first: it
  // is the id a `BashOutput` PROBE is addressed to, and this one is not.
  if (workId !== null && target.handle === null) {
    target.handle = workId;
    index.byHandle.set(workId, target);
  }
}

/** What a probe/kill call is FOR, so its reply can be read the right way. */
interface ShellProbe {
  handle: string;
  kind: 'read' | 'kill';
}

/**
 * Every shell the transcript records, oldest first, folded to how it stands
 * now.
 *
 * Delegates' shells are IN here, unlike the task list's fold, which drops them.
 * A task list is a delegate's own bookkeeping and belongs in its own block; a
 * delegate's `pnpm build` is a process running on the user's machine, which is
 * the whole question this answers.
 */
export function shellRuns(items: readonly ChatItem[]): ShellRun[] {
  const shells: ShellRun[] = [];
  /** Launching call id → the shell it started. */
  const byCall = new Map<string, ShellRun>();
  /** Probe/kill call id → what it was aimed at, until its reply lands. */
  const probes = new Map<string, ShellProbe>();
  /** Background handle → the shell carrying it, for those probes to find. */
  const byHandle = new Map<string, ShellRun>();
  /**
   * The launching calls the DAEMON said were detached — see
   * {@link detachFromShellOpen}.
   *
   * Kept as well as applied, because nothing orders a `shell_open` against the
   * launch's own reply: arriving first, it must survive that reply's "no
   * announcement in the prose means the command has exited" arm, which is
   * otherwise the correct reading and would close the shell a moment after the
   * daemon opened it.
   */
  const detached = new Set<string>();
  for (const item of items) {
    const payload: unknown = item.payload;
    const callId = payloadString(payload, 'id');
    if (item.kind === 'shell_open') {
      // Before the id guard, on `shell_info`'s reasoning: the row is read for
      // both of its keys, and only one of them is the launching call.
      if (callId !== null) {
        detached.add(callId);
      }
      detachFromShellOpen(callId, payloadString(payload, 'workId'), {
        byCall,
        byHandle,
      });
      continue;
    }
    if (item.kind === 'shell_info') {
      // BEFORE the id guard below, because this row's `id` is legitimately null
      // — a settle channel that names no launching call still names the unit,
      // and that is the whole point of carrying both.
      settleFromShellInfo(callId, payloadString(payload, 'workId'), {
        byCall,
        byHandle,
      });
      continue;
    }
    if (callId === null) {
      continue;
    }
    if (item.kind === 'tool_call') {
      const name = payloadString(payload, 'name') ?? '';
      const input = inputOf(payload);
      if (OUTPUT_TOOLS.has(name) || KILL_TOOLS.has(name)) {
        const handle = readHandle(input);
        if (handle !== null) {
          probes.set(callId, {
            handle,
            kind: KILL_TOOLS.has(name) ? 'kill' : 'read',
          });
        }
        continue;
      }
      // The agent's OWN classification first, the tool name second — the one
      // shared reading, so a CLI that calls its shell tool anything at all is
      // still recognised (see `tool-kind.ts`).
      if (toolOperationOf(payload) !== 'execute') {
        continue;
      }
      const record = asRecord(input);
      const shell: ShellRun = {
        id: callId,
        command: commandOf(input) ?? name,
        description:
          record && typeof record.description === 'string'
            ? record.description
            : null,
        background: record?.run_in_background === true,
        handle: null,
        status: 'running',
        exitCode: null,
        startedAt: item.createdAt,
        agentId: item.nodeId,
      };
      if (shell.command === '') {
        continue;
      }
      shells.push(shell);
      byCall.set(callId, shell);
      continue;
    }
    if (item.kind !== 'tool_result') {
      continue;
    }
    const probe = probes.get(callId);
    if (probe !== undefined) {
      probes.delete(callId);
      const target = byHandle.get(probe.handle);
      if (target === undefined) {
        continue;
      }
      if (probe.kind === 'kill') {
        // A kill that FAILED is not a kill: the CLI answers a handle it cannot
        // find with an error, and marking the row killed off that would retire
        // a shell nothing stopped.
        if (payloadBoolean(payload, 'isError') !== true) {
          target.status = 'killed';
        }
        continue;
      }
      const probed = readProbedStatus(
        toolResultText(asRecord(payload)?.result),
      );
      if (probed !== null) {
        target.status = probed.status;
        target.exitCode = probed.exitCode;
      }
      continue;
    }
    const shell = byCall.get(callId);
    if (shell === undefined) {
      continue;
    }
    const failed = payloadBoolean(payload, 'isError') === true;
    const replyText = failed ? '' : toolResultText(asRecord(payload)?.result);
    if (failed) {
      shell.status = 'failed';
      continue;
    }
    // The REPLY is the authority on whether the command was detached, not the
    // argument the agent wrote — and it decides BOTH ways, which is the part
    // that was missing. claude backgrounds a command nobody asked to
    // background in two measured cases (the user pushed it there; it outran
    // its own timeout), so an input-only reading retires a command the instant
    // it is detached. And the reverse is just as real: a call that ASKED for
    // the background and came back with plain output was never detached at
    // all, so an input-only reading leaves it listed for ever with no handle
    // any probe could match. Measured on the reporter's own `geniro.db` — two
    // such rows, from today.
    //
    // What OUTRANKS the reply is the daemon's own `shell_open`: this reading is
    // a match on the CLI's English, that one is a reading of the CLI's frames,
    // and the two disagreeing is what put a header counting zero shells beside
    // a sidebar row saying background work was still out. The prose stays the
    // only source of the PROBE HANDLE, which is why it is still read here.
    const handle = readLaunchHandle(replyText);
    if (handle === null) {
      if (detached.has(callId)) {
        // The daemon says this command was detached, so the reply is the
        // launch's acknowledgement rather than its output — it settles nothing.
        // What is lost by the prose not matching is only the probe handle: a
        // later `BashOutput` cannot be tied to this row, while the `shell_info`
        // that ends it still can, by the work id the open carried.
        shell.background = true;
        continue;
      }
      // No announcement means the reply IS the command's output, whichever
      // way the call was written: the shell has exited.
      shell.background = false;
      shell.status = 'completed';
      continue;
    }
    // A detached launch replies immediately and the command runs on, so this
    // reply settles nothing — it only names the handle a later probe will use.
    shell.background = true;
    shell.handle = handle;
    byHandle.set(handle, shell);
  }
  return shells;
}

/**
 * The shells still going, by the agent that started them — the panel's own
 * question.
 *
 * Keyed by node id (`null` for a 1:1 chat), the same shape `taskListsByAgent`
 * returns, so the screen re-keys both to its card ids in one place.
 *
 * Only the RUNNING ones. The transcript is where a finished command and its
 * output already live, in full and in order; repeating the last forty of them
 * in a 280px column would bury the one row this exists to show.
 */
export function runningShellsByAgent(
  items: readonly ChatItem[],
): Map<string | null, ShellRun[]> {
  const byAgent = new Map<string | null, ShellRun[]>();
  for (const shell of shellRuns(items)) {
    if (shell.status !== 'running') {
      continue;
    }
    const list = byAgent.get(shell.agentId);
    if (list) {
      list.push(shell);
    } else {
      byAgent.set(shell.agentId, [shell]);
    }
  }
  return byAgent;
}
