import { describe, expect, it } from 'vitest';

import type { CliKind } from '../../shared/contracts';
import type { WorkflowAgentNode } from '../autogenerated';
import { signInResolverFor } from './sign-in-resolver';

const node = (
  over: Partial<WorkflowAgentNode> & Pick<WorkflowAgentNode, 'id'>,
): WorkflowAgentNode => ({
  kind: 'agent',
  agent: 'claude',
  approval: 'auto',
  ...over,
});

/** Records what a sign-in press would start, so the assertion reads the real call. */
function recorder(): {
  calls: [CliKind, string | null][];
  signIn: (kind: CliKind, configDir: string | null) => void;
} {
  const calls: [CliKind, string | null][] = [];
  return { calls, signIn: (kind, configDir) => calls.push([kind, configDir]) };
}

describe('signInResolverFor — a workflow run', () => {
  const manager = node({ id: 'manager', configDir: '/Users/x/.claude-lab' });
  const engineer = node({ id: 'engineer', configDir: '/Users/x/.claude-work' });

  it('signs in the profile of the node that FAILED, not one for the whole run', () => {
    // The reported case: a Manager and an Engineer run as two accounts, and
    // a lapsed session is per account. Resolving BOTH rows — and getting two
    // different directories — is what tells "the failing node's profile" apart
    // from a single run-wide answer, which would sign one of them in wrongly.
    const { calls, signIn } = recorder();
    const resolve = signInResolverFor({
      workflowId: 'dev-team',
      agentKind: null,
      configDir: null,
      workflowAgents: [manager, engineer],
      signIn,
    });
    resolve!('engineer')!();
    resolve!('manager')!();
    expect(calls).toEqual([
      ['claude', '/Users/x/.claude-work'],
      ['claude', '/Users/x/.claude-lab'],
    ]);
  });

  it('signs in the CLI the node runs, not the run’s', () => {
    const { calls, signIn } = recorder();
    const resolve = signInResolverFor({
      workflowId: 'dev-team',
      agentKind: null,
      configDir: null,
      workflowAgents: [node({ id: 'qa', agent: 'cursor-agent' })],
      signIn,
    });
    resolve!('qa')!();
    expect(calls).toEqual([['cursor-agent', null]]);
  });

  it('signs a node naming no config directory into the CLI’s own default profile', () => {
    // `configDir` is optional on a node; absent must reach the daemon as
    // "default", never as a blank directory it would have to reject.
    const { calls, signIn } = recorder();
    const resolve = signInResolverFor({
      workflowId: 'dev-team',
      agentKind: null,
      configDir: null,
      workflowAgents: [node({ id: 'solo' })],
      signIn,
    });
    resolve!('solo')!();
    expect(calls).toEqual([['claude', null]]);
  });

  it('offers nothing for a row it cannot place — an unknown node, or none', () => {
    const resolve = signInResolverFor({
      workflowId: 'dev-team',
      agentKind: null,
      configDir: null,
      workflowAgents: [manager],
      signIn: () => undefined,
    });
    expect(resolve!('gone')).toBeNull();
    expect(resolve!(null)).toBeNull();
  });

  it('offers nothing while the run’s snapshot has not loaded', () => {
    // Guessing would sign in whichever account the run happens to carry,
    // which on a workflow run is no node's account at all.
    const resolve = signInResolverFor({
      workflowId: 'dev-team',
      agentKind: null,
      configDir: null,
      workflowAgents: [],
      signIn: () => undefined,
    });
    expect(resolve!('manager')).toBeNull();
  });
});

describe('signInResolverFor — a chat', () => {
  it('signs in the run’s own agent and profile, whichever row asks', () => {
    const { calls, signIn } = recorder();
    const resolve = signInResolverFor({
      workflowId: null,
      agentKind: 'claude',
      configDir: '/Users/x/.claude-lab',
      workflowAgents: [],
      signIn,
    });
    resolve!(null)!();
    resolve!('agent')!();
    expect(calls).toEqual([
      ['claude', '/Users/x/.claude-lab'],
      ['claude', '/Users/x/.claude-lab'],
    ]);
  });

  it('has no resolver at all for a chat that names no agent', () => {
    expect(
      signInResolverFor({
        workflowId: null,
        agentKind: null,
        configDir: null,
        workflowAgents: [],
        signIn: () => undefined,
      }),
    ).toBeNull();
  });
});
