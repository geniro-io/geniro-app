import type { CliKind } from '../../shared/contracts';
import type { TeamMember } from '../autogenerated';
import type { SignInResolver } from './cli-login-context';

/**
 * Build the transcript's sign-in resolver for the open run — see
 * `SignInResolver` for why it is keyed by member.
 *
 * A pure function of the run's own fields rather than logic inside `Chats`,
 * because the one decision worth pinning — that a team row signs in the
 * profile of the MEMBER that failed, not the run's — is otherwise reachable only
 * by mounting a nine-thousand-line screen.
 *
 * Returns null where nothing can be answered for ANY row (a chat naming no
 * agent), and a resolver answering null for a single row it cannot place.
 */
export function signInResolverFor(run: {
  teamId: string | null | undefined;
  agentKind: CliKind | null | undefined;
  configDir: string | null | undefined;
  /**
   * The members of the run's OWN snapshot — never the library's current
   * team, which a user may have edited since, re-pointing a member at another
   * profile. The account that failed is the one the run started under.
   */
  teamAgents: readonly TeamMember[];
  signIn: (kind: CliKind, configDir: string | null) => void;
}): SignInResolver | null {
  if (run.teamId) {
    // Built once per resolver rather than searched per row: a long run's
    // transcript can hold many error rows, and the snapshot is fixed for it.
    const byId = new Map(run.teamAgents.map((member) => [member.id, member]));
    return (memberId) => {
      const member = memberId === null ? undefined : byId.get(memberId);
      return member
        ? () => run.signIn(member.agent, member.configDir ?? null)
        : null;
    };
  }
  const kind = run.agentKind;
  if (!kind) {
    return null;
  }
  const configDir = run.configDir ?? null;
  // A chat has one agent and one profile, so no member is consulted.
  return () => () => run.signIn(kind, configDir);
}
