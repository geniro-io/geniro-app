import { describe, expect, it } from 'vitest';

import type { AgentSkillDto as AgentSkill } from '../autogenerated';
import {
  applySkill,
  filterSkills,
  mergeSkills,
  slashQuery,
  unknownSlashCommand,
} from './skill-autocomplete';

function skill(name: string, overrides: Partial<AgentSkill> = {}): AgentSkill {
  return {
    name,
    description: null,
    kind: 'command',
    source: 'project',
    ...overrides,
  };
}

describe('slashQuery', () => {
  it('parses the query of an input that is one slash token being typed', () => {
    expect(slashQuery('/')).toBe('');
    expect(slashQuery('/de')).toBe('de');
  });

  it('is closed for arguments, leading text, or a non-slash input', () => {
    expect(slashQuery('/deploy now')).toBeNull();
    expect(slashQuery('hey /deploy')).toBeNull();
    expect(slashQuery('')).toBeNull();
    // The applySkill contract: the inserted trailing space closes the menu.
    expect(slashQuery('/deploy ')).toBeNull();
  });
});

describe('filterSkills', () => {
  it('ranks prefix matches before substring matches, case-insensitively', () => {
    const skills = [skill('code-review'), skill('review'), skill('Deploy')];
    expect(filterSkills(skills, 'rev').map((s) => s.name)).toEqual([
      'review',
      'code-review',
    ]);
    expect(filterSkills(skills, 'dep').map((s) => s.name)).toEqual(['Deploy']);
    expect(filterSkills(skills, 'zzz')).toEqual([]);
  });

  it('matches everything on the empty query (a bare "/")', () => {
    const skills = [skill('b'), skill('a')];
    expect(filterSkills(skills, '')).toEqual(skills);
  });
});

describe('applySkill', () => {
  it('yields the token plus a trailing space, ready for arguments', () => {
    expect(applySkill(skill('deploy'))).toBe('/deploy ');
  });
});

describe('mergeSkills', () => {
  it('unions lists preserving order; the first list wins a name clash', () => {
    // Order is the daemon's ranking (project → user → cli) — merging must
    // keep it, never re-sort alphabetically.
    const claude = [
      skill('zeta', { description: 'ranked first by the daemon' }),
      skill('deploy', { description: 'from claude' }),
    ];
    const cursor = [
      skill('deploy', { description: 'from cursor' }),
      skill('audit'),
    ];
    expect(mergeSkills([claude, cursor])).toEqual([
      skill('zeta', { description: 'ranked first by the daemon' }),
      skill('deploy', { description: 'from claude' }),
      skill('audit'),
    ]);
  });
});

describe('unknownSlashCommand', () => {
  const known = [skill('compact', { source: 'geniro' }), skill('review')];

  it('names a slash command this agent does not have', () => {
    // The reported case: `/summarize` is a cursor TUI command, absent from that
    // CLI's ACP server, so both transports hand it to the model as prose.
    expect(unknownSlashCommand('/summarize', known)).toBe('summarize');
  });

  it('passes a command the popup offers, arguments and all', () => {
    expect(unknownSlashCommand('/compact', known)).toBeNull();
    expect(unknownSlashCommand('/review the diff', known)).toBeNull();
  });

  it('passes an absolute path, which is not an invocation', () => {
    // A path is an ordinary thing to paste into a composer; refusing it as "a
    // command nobody has" would be the guard breaking normal use.
    expect(unknownSlashCommand('/Users/me/app/src/main.ts', known)).toBeNull();
    expect(unknownSlashCommand('/etc/hosts is wrong', known)).toBeNull();
  });

  it('passes everything while the list is still empty', () => {
    // A folder whose skills are still loading looks exactly like this, and
    // blocking there refuses every command for the first seconds of a chat.
    expect(unknownSlashCommand('/summarize', [])).toBeNull();
  });

  it('passes ordinary prose that merely contains a slash', () => {
    expect(unknownSlashCommand('use a/b testing', known)).toBeNull();
    expect(unknownSlashCommand('', known)).toBeNull();
  });

  it('reads multi-line arguments as arguments, both ways', () => {
    // A real invocation's arguments routinely run over several lines
    // (`/geniro:implement` followed by a pasted spec), so the newline must not
    // end the command — in EITHER direction, or `/summarize` with a sentence
    // under it would slip past the guard.
    expect(unknownSlashCommand('/review\nthe pasted diff', known)).toBeNull();
    expect(unknownSlashCommand('/summarize\nplease', known)).toBe('summarize');
  });
});
