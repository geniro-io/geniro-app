import type { AgentSkillDto as AgentSkill } from '../autogenerated';

/**
 * Pure logic behind the composer's `/` skill autocomplete (the Claude
 * Code / Cursor pattern): the menu is open exactly while the WHOLE input is
 * one slash token still being typed (`/`, `/de`, …). The first space (the
 * arguments) or any other leading text closes it — matching when the CLIs'
 * own pickers show and hide theirs.
 */

/** The skill-name query of an input that is one slash token, else null. */
export function slashQuery(input: string): string | null {
  const match = /^\/(\S*)$/.exec(input);
  return match ? match[1]! : null;
}

/**
 * The name of a slash command this agent does not have, or null when the
 * message is safe to send.
 *
 * This exists because of what the transports do with an unknown command:
 * nothing. The Agent Client Protocol says a client sends a command as an
 * ordinary prompt and leaves recognising it to the agent, and specifies nothing
 * at all about one the agent never advertised — so a name that is not in
 * `available_commands_update` reaches the model as prose and is answered as
 * prose. Reported against a cursor chat: `/summarize` (a command of that CLI's
 * interactive shell, absent from its ACP server) produced a paragraph of the
 * agent reasoning about what the user might have meant. The same holds for
 * claude's stream-json stdin. So the check has to live on the client, and this
 * is the client.
 *
 * The list it checks against is the list the `/` popup shows, which is what
 * makes the refusal explainable — whatever the popup offers, sends.
 *
 * Three things deliberately pass through:
 *
 * - an EMPTY list, which is what a folder whose skills are still loading looks
 *   like. Blocking there would refuse every command for the first seconds of a
 *   chat, and the failure it prevents is a wasted turn rather than a lost one.
 * - anything that is not command-SHAPED, most of all an absolute path
 *   (`/Users/…/file.ts`), which is an ordinary thing to paste into a composer
 *   and would otherwise be refused as a command nobody has. The name may not
 *   contain a second `/`, which is the whole of that rule.
 *
 * Arguments are allowed to run over several lines, because a real invocation's
 * routinely do (`/geniro:implement` followed by a pasted spec).
 */
export function unknownSlashCommand(
  input: string,
  skills: readonly AgentSkill[],
): string | null {
  if (skills.length === 0) {
    return null;
  }
  const name = slashCommandName(input);
  if (name === undefined) {
    return null;
  }
  return resolveSkillName(name, skills) === null ? name : null;
}

/**
 * The command name a message opens with, or undefined when it opens with none.
 *
 * A name, then either end-of-message or the arguments. The name character class
 * excludes `/`, which is the whole of what keeps an absolute path out of this.
 */
function slashCommandName(input: string): string | undefined {
  return /^\/([A-Za-z0-9][\w:.-]*)(?:\s[\s\S]*)?$/.exec(input.trim())?.[1];
}

/**
 * One name with `:` and `-` made equivalent, for {@link resolveSkillName}.
 *
 * The two separators are the two CLIs' own conventions for the SAME plugin
 * skill, and neither is anyone's choice to change: claude composes
 * `<plugin>:<skill>` itself and reports the name it accepts, while cursor
 * resolves a directory name, and a directory literally called `geniro:review`
 * is not a thing to ship on macOS.
 */
function separatorInsensitive(name: string): string {
  return name.replace(/:/g, '-');
}

/**
 * The name THIS agent answers to for a typed command, or null when it has no
 * such command.
 *
 * Exact match first, always — the alias below may only ever rescue a name that
 * matches nothing, never overrule one that matches something.
 *
 * REPORTED as "я всё ещё вижу, что я не могу использовать Geniro команды в
 * курсорах", against a composer refusing `/geniro:review` on cursor-agent. It
 * was not missing: the CLI has it as `geniro-review`, and the refusal named the
 * command without saying that. Since the spelling belongs to the CLI rather
 * than to the user, both are accepted and the send is given the one the agent
 * resolves.
 *
 * An ambiguous alias resolves to NOTHING rather than to a guess: two skills
 * whose names differ only by that separator are two commands, and picking
 * either would run something the user did not ask for. Exact matching is
 * unaffected, so the only cost is that the refusal stands where it would have.
 */
export function resolveSkillName(
  name: string,
  skills: readonly AgentSkill[],
): string | null {
  if (skills.some((skill) => skill.name === name)) {
    return name;
  }
  const wanted = separatorInsensitive(name);
  const aliases = skills.filter(
    (skill) => separatorInsensitive(skill.name) === wanted,
  );
  return aliases.length === 1 ? aliases[0]!.name : null;
}

/**
 * The message to actually send: the same text, with a command the user spelled
 * in the OTHER CLI's convention rewritten to the one this agent answers to.
 *
 * Everything else is returned untouched, including a name that already matches
 * and one that matches nothing — the latter is `unknownSlashCommand`'s to
 * refuse, and rewriting is not a way to smuggle a command past that check.
 */
export function withAgentSlashSpelling(
  input: string,
  skills: readonly AgentSkill[],
): string {
  const name = slashCommandName(input);
  if (name === undefined) {
    return input;
  }
  const resolved = resolveSkillName(name, skills);
  if (resolved === null || resolved === name) {
    return input;
  }
  // Only the NAME, and only its first occurrence: the arguments are the user's
  // own words and routinely hold the same characters (a path, a URL, a branch).
  return input.replace(`/${name}`, `/${resolved}`);
}

/** Prefix matches first (the common case), then substring matches; stable. */
export function filterSkills(
  skills: readonly AgentSkill[],
  query: string,
): AgentSkill[] {
  const lower = query.toLowerCase();
  const prefixed: AgentSkill[] = [];
  const infixed: AgentSkill[] = [];
  for (const skill of skills) {
    const name = skill.name.toLowerCase();
    if (name.startsWith(lower)) {
      prefixed.push(skill);
    } else if (name.includes(lower)) {
      infixed.push(skill);
    }
  }
  return [...prefixed, ...infixed];
}

/** The composer text after picking a skill — trailing space, ready for args. */
export function applySkill(skill: AgentSkill): string {
  return `/${skill.name} `;
}

/**
 * Union the per-agent-kind lists (a workflow trigger can fan out to mixed
 * agents), de-duped by name — first list wins, mirroring the daemon's own
 * first-occurrence-wins collision rule. Order is PRESERVED, not re-sorted:
 * the daemon ranks each list (project → user → cli-reported) so the user's
 * own skills lead the popup; later lists' new names append in their order.
 */
export function mergeSkills(
  lists: readonly (readonly AgentSkill[])[],
): AgentSkill[] {
  const byName = new Map<string, AgentSkill>();
  for (const list of lists) {
    for (const skill of list) {
      if (!byName.has(skill.name)) {
        byName.set(skill.name, skill);
      }
    }
  }
  return [...byName.values()];
}
