// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type {
  MoveTeamRunStageDto,
  StageMoveResultDto,
  StageProgress,
} from '../autogenerated';
import {
  StageActionDialog,
  type StageActionRequest,
  STAGES_MOVED_MESSAGE,
} from './stage-action-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const FORK: StageProgress = {
  rev: 4,
  current: 'investigate',
  position: { index: 1, total: 3 },
  stages: [
    {
      id: 'investigate',
      title: 'Investigation',
      status: 'current',
      next: ['implement', 'fix'],
    },
    {
      id: 'implement',
      title: 'Implementation',
      status: 'pending',
      next: ['review'],
    },
    { id: 'fix', title: 'Fix', status: 'pending', next: ['review'] },
    { id: 'review', title: 'Review', status: 'pending', next: [] },
  ],
};

const WALKED: StageProgress = {
  rev: 7,
  current: 'review',
  position: { index: 3, total: 3 },
  stages: [
    { id: 'plan', title: 'Plan', status: 'done', next: ['build', 'docs'] },
    { id: 'build', title: 'Build', status: 'skipped', next: ['review'] },
    { id: 'review', title: 'Review', status: 'current', next: [] },
    { id: 'docs', title: 'Docs', status: 'not_taken', next: [] },
  ],
};

function mount({
  request,
  progress,
  onMove = vi.fn(),
  onMoved = vi.fn(),
  onClose = vi.fn(),
}: {
  request: StageActionRequest | null;
  progress: StageProgress;
  onMove?: (dto: MoveTeamRunStageDto) => Promise<StageMoveResultDto>;
  onMoved?: (result: StageMoveResultDto) => void;
  onClose?: () => void;
}): { el: HTMLDivElement; rerender: (progress: StageProgress) => void } {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  const draw = (next: StageProgress): void => {
    act(() => {
      root!.render(
        <StageActionDialog
          request={request}
          progress={next}
          onMove={onMove}
          onClose={onClose}
          onMoved={onMoved}
        />,
      );
    });
  };
  draw(progress);
  return { el: container, rerender: draw };
}

function type(el: HTMLElement, text: string): void {
  const field = el.querySelector('textarea')!;
  const setValue = Object.getOwnPropertyDescriptor(
    HTMLTextAreaElement.prototype,
    'value',
  )!.set!;
  act(() => {
    setValue.call(field, text);
    field.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

const submitButton = (el: HTMLElement): HTMLButtonElement =>
  el.querySelector<HTMLButtonElement>('button[type="submit"]')!;

async function submit(el: HTMLElement): Promise<void> {
  await act(async () => {
    submitButton(el).click();
  });
}

function pick(el: HTMLElement, title: string): void {
  const option = [
    ...el.querySelectorAll<HTMLButtonElement>('[role="group"] button'),
  ].find((button) => button.textContent === title);
  act(() => {
    option!.click();
  });
}

const daemonError = (status: number, code: string, message: string): Error =>
  new Error(
    `daemon POST /v1/teams/runs/r1/stages failed (${status}): ${JSON.stringify({
      code,
      message,
    })}`,
  );

describe('StageActionDialog', () => {
  it('names the field by what the move asks for', () => {
    const labels = (['complete', 'skip', 'reopen'] as const).map((action) => {
      const { el } = mount({
        request: { action, stageId: 'plan', rev: 7 },
        progress: WALKED,
      });
      const label = el.querySelector('label')?.textContent;
      act(() => root!.unmount());
      container!.remove();
      root = null;
      return label;
    });
    expect(labels).toEqual([
      'What was done',
      'Why skip it',
      'What still needs doing',
    ]);
  });

  it('will not mark a fork done until the branch is picked, then sends the move', async () => {
    const onMove = vi
      .fn()
      .mockResolvedValue({ progress: FORK, woke: true, hasLead: true });
    const onMoved = vi.fn();
    const { el } = mount({
      request: { action: 'complete', stageId: 'investigate', rev: 4 },
      progress: FORK,
      onMove,
      onMoved,
    });

    type(el, '  The cause is a sign error.  ');
    expect(submitButton(el).disabled).toBe(true);

    pick(el, 'Fix');
    expect(submitButton(el).disabled).toBe(false);
    await submit(el);

    expect(onMove).toHaveBeenCalledWith({
      action: 'complete',
      stage: 'investigate',
      next: 'fix',
      text: 'The cause is a sign error.',
      expectedRev: 4,
    });
    expect(onMoved).toHaveBeenCalledWith({
      progress: FORK,
      woke: true,
      hasLead: true,
    });
  });

  it('offers two branches with the same title as separate choices and sends the picked id', async () => {
    const twins: StageProgress = {
      ...FORK,
      stages: [
        { ...FORK.stages[0]!, next: ['fix-a', 'fix-b', 'review'] },
        { id: 'fix-a', title: 'Fix', status: 'pending', next: ['review'] },
        { id: 'fix-b', title: 'Fix', status: 'pending', next: ['review'] },
        { id: 'review', title: 'Review', status: 'pending', next: [] },
      ],
    };
    const onMove = vi
      .fn()
      .mockResolvedValue({ progress: twins, woke: true, hasLead: true });
    const { el } = mount({
      request: { action: 'complete', stageId: 'investigate', rev: 4 },
      progress: twins,
      onMove,
    });
    const labels = [
      ...el.querySelectorAll<HTMLButtonElement>('[role="group"] button'),
    ].map((button) => button.textContent);
    expect(labels).toEqual(['Fix (fix-a)', 'Fix (fix-b)', 'Review']);

    type(el, 'Both are plausible');
    pick(el, 'Fix (fix-b)');
    const pressed = [
      ...el.querySelectorAll<HTMLButtonElement>('[role="group"] button'),
    ].map((button) => button.getAttribute('aria-pressed'));
    expect(pressed).toEqual(['false', 'true', 'false']);
    await submit(el);
    expect(onMove).toHaveBeenCalledWith(
      expect.objectContaining({ next: 'fix-b' }),
    );
  });

  it('needs a reason before anything is sent', () => {
    const { el } = mount({
      request: { action: 'skip', stageId: 'review', rev: 7 },
      progress: WALKED,
    });
    expect(submitButton(el).disabled).toBe(true);
    type(el, '   ');
    expect(submitButton(el).disabled).toBe(true);
    type(el, 'Covered by CI');
    expect(submitButton(el).disabled).toBe(false);
  });

  it('sends no branch for a stage that does not fork', async () => {
    const onMove = vi
      .fn()
      .mockResolvedValue({ progress: WALKED, woke: false, hasLead: true });
    const { el } = mount({
      request: { action: 'skip', stageId: 'review', rev: 7 },
      progress: WALKED,
      onMove,
    });
    expect(el.querySelector('[role="group"]')).toBeNull();
    type(el, 'Covered by CI');
    await submit(el);
    expect(onMove).toHaveBeenCalledWith({
      action: 'skip',
      stage: 'review',
      text: 'Covered by CI',
      expectedRev: 7,
    });
  });

  it('keeps the dialog open when the stages moved meanwhile, and the retry quotes what is shown now', async () => {
    const onMove = vi
      .fn()
      .mockRejectedValueOnce(
        daemonError(409, 'STAGE_PROGRESS_CHANGED', 'stages moved since rev 7'),
      )
      .mockResolvedValueOnce({ progress: WALKED, woke: false, hasLead: true });
    const onMoved = vi.fn();
    const { el, rerender } = mount({
      request: { action: 'skip', stageId: 'review', rev: 7 },
      progress: WALKED,
      onMove,
      onMoved,
    });
    type(el, 'Covered by CI');
    await submit(el);

    expect(el.querySelector('[role="alert"]')?.textContent).toBe(
      STAGES_MOVED_MESSAGE,
    );
    expect(onMoved).not.toHaveBeenCalled();
    expect(el.querySelector('[role="dialog"]')).not.toBeNull();
    expect(el.querySelector('textarea')?.value).toBe('Covered by CI');

    rerender({ ...WALKED, rev: 8 });
    await submit(el);
    expect(onMove).toHaveBeenLastCalledWith(
      expect.objectContaining({ expectedRev: 8 }),
    );
  });

  it('shows the daemon’s own sentence for any other refusal', async () => {
    const onMove = vi
      .fn()
      .mockRejectedValue(
        daemonError(
          400,
          'STAGE_NOT_CURRENT',
          "'review' is not the current stage — the current stage is Plan (plan).",
        ),
      );
    const { el } = mount({
      request: { action: 'complete', stageId: 'review', rev: 7 },
      progress: WALKED,
      onMove,
    });
    type(el, 'done');
    await submit(el);
    expect(el.querySelector('[role="alert"]')?.textContent).toBe(
      "'review' is not the current stage — the current stage is Plan (plan).",
    );
    expect(el.querySelector('[role="dialog"]')).not.toBeNull();
  });

  it('names the stages a reopen sends back to pending', () => {
    const { el } = mount({
      request: { action: 'reopen', stageId: 'plan', rev: 7 },
      progress: WALKED,
    });
    expect(
      el.querySelector('[data-slot="stage-reopen-resets"]')?.textContent,
    ).toBe('Sends back to pending: Build, Review');
    expect(el.querySelector('[role="group"]')).toBeNull();
  });

  it('draws nothing while closed', () => {
    const { el } = mount({ request: null, progress: WALKED });
    expect(el.querySelector('[role="dialog"]')).toBeNull();
  });
});
