import type { Meta, StoryObj } from '@storybook/react-vite';
import { useState } from 'react';

import type {
  MoveTeamRunStageDto,
  StageMoveResultDto,
  StageProgress,
} from '../autogenerated';
import {
  StageActionDialog,
  type StageActionRequest,
} from './stage-action-dialog';

