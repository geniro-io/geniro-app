const MOVED_MEANWHILE = new Error(
  `daemon POST /v1/teams/runs/r1/stages failed (409): ${JSON.stringify({
    code: 'STAGE_PROGRESS_CHANGED',
    message: 'The stages moved since revision 2.',
  })}`,
);

function Harness({
  request,
  progress,
  refuse = false,
}: {
  request: StageActionRequest;
  progress: StageProgress;
  refuse?: boolean;
}): React.JSX.Element {
  const [shown, setShown] = useState<StageActionRequest | null>(request);
  const onMove = (dto: MoveTeamRunStageDto): Promise<StageMoveResultDto> =>
    refuse
      ? Promise.reject(MOVED_MEANWHILE)
      : Promise.resolve({
          progress: { ...progress, rev: dto.expectedRev + 1 },
          woke: true,
          hasLead: true,
        });
  return (
    <>
      <button
        type="button"
        className="text-sm text-primary hover:underline"
        onClick={() => setShown(request)}>
        Reopen
      </button>
      <StageActionDialog
        request={shown}
        progress={progress}
        onMove={onMove}
        onClose={() => setShown(null)}
        onMoved={() => setShown(null)}
      />
    </>
  );
}

const meta = {
  title: 'Chats/StageActionDialog',
  component: Harness,
  args: {
    request: { action: 'complete', stageId: 'investigation', rev: 0 },
    progress: FORK,
  },
  decorators: [(story) => <div className="h-[520px]">{story()}</div>],
} satisfies Meta<typeof Harness>;

export default meta;
type Story = StoryObj<typeof meta>;

