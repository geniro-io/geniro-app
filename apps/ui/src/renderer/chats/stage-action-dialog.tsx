import { useId, useState } from 'react';

import type {
  MoveWorkflowRunStageDto,
  MoveWorkflowRunStageDtoStageMoveAction,
  StageMoveResultDto,
  StageProgress,
} from '../autogenerated';
import { ErrorText } from '../components/error-text';
import { Field } from '../components/field';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { OptionList } from '../components/ui/option-list';
import { Textarea } from '../components/ui/textarea';
import {
  daemonErrorCode,
  daemonErrorStatus,
  describeDaemonError,
} from '../daemon-api';
import { distinctStageLabels, stagesReopenResets } from './stage-progress';

export type StageMoveAction = MoveWorkflowRunStageDtoStageMoveAction;

export interface StageActionRequest {
  action: StageMoveAction;
  stageId: string;
  rev: number;
}

const ACTION_VIEW: Record<
  StageMoveAction,
  { title: (stage: string) => string; field: string; submit: string }
> = {
  complete: {
    title: (stage) => `Mark ${stage} done`,
    field: 'What was done',
    submit: 'Mark done',
  },
  skip: {
    title: (stage) => `Skip ${stage}`,
    field: 'Why skip it',
    submit: 'Skip stage',
  },
  reopen: {
    title: (stage) => `Reopen ${stage}`,
    field: 'What still needs doing',
    submit: 'Reopen',
  },
};

export const STAGES_MOVED_MESSAGE =
  'The stages moved meanwhile — check them and try again';

export function StageActionDialog({
  request,
  progress,
  onMove,
  onClose,
  onMoved,
}: {
  request: StageActionRequest | null;
  progress: StageProgress;
  onMove: (dto: MoveWorkflowRunStageDto) => Promise<StageMoveResultDto>;
  onClose: () => void;
  onMoved: (result: StageMoveResultDto) => void;
}): React.JSX.Element {
  const stage =
    request === null
      ? undefined
      : progress.stages.find((entry) => entry.id === request.stageId);
  return (
    <Dialog
      open={request !== null && stage !== undefined}
      onClose={onClose}
      title={
        request === null || stage === undefined
          ? undefined
          : ACTION_VIEW[request.action].title(stage.title)
      }
      className="max-w-md">
      {request === null || stage === undefined ? null : (
        <StageActionForm
          key={`${request.action}:${request.stageId}:${request.rev}`}
          request={request}
          progress={progress}
          onMove={onMove}
          onClose={onClose}
          onMoved={onMoved}
        />
      )}
    </Dialog>
  );
}

function branchChoices(
  progress: StageProgress,
  ids: readonly string[],
): { id: string; label: string }[] {
  const labels = distinctStageLabels(
    ids.map((id) => ({
      id,
      title: progress.stages.find((entry) => entry.id === id)?.title ?? id,
    })),
  );
  return ids.map((id) => ({ id, label: labels.get(id)! }));
}

function StageActionForm({
  request,
  progress,
  onMove,
  onClose,
  onMoved,
}: {
  request: StageActionRequest;
  progress: StageProgress;
  onMove: (dto: MoveWorkflowRunStageDto) => Promise<StageMoveResultDto>;
  onClose: () => void;
  onMoved: (result: StageMoveResultDto) => void;
}): React.JSX.Element {
  const fieldId = useId();
  const [text, setText] = useState('');
  const [next, setNext] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [told, setTold] = useState(false);
  const view = ACTION_VIEW[request.action];
  const stage = progress.stages.find((entry) => entry.id === request.stageId)!;
  const branches =
    request.action !== 'reopen' && stage.next.length > 1
      ? branchChoices(progress, stage.next)
      : [];
  const resets =
    request.action === 'reopen'
      ? stagesReopenResets(progress, stage.id).map(
          (id) => progress.stages.find((entry) => entry.id === id)?.title ?? id,
        )
      : [];
  const ready =
    text.trim() !== '' && (branches.length === 0 || next !== null) && !busy;

  const submit = async (): Promise<void> => {
    if (!ready) {
      return;
    }
    setBusy(true);
    setError(null);
    try {
      const result = await onMove({
        action: request.action,
        stage: stage.id,
        ...(next === null ? {} : { next }),
        text: text.trim(),
        expectedRev: told ? progress.rev : request.rev,
      });
      onMoved(result);
    } catch (err: unknown) {
      if (
        daemonErrorStatus(err) === 409 &&
        daemonErrorCode(err) === 'STAGE_PROGRESS_CHANGED'
      ) {
        setTold(true);
        setError(STAGES_MOVED_MESSAGE);
      } else {
        setError(describeDaemonError(err));
      }
      setBusy(false);
    }
  };

  return (
    <form
      className="flex flex-col gap-4"
      onSubmit={(event) => {
        event.preventDefault();
        void submit();
      }}>
      {branches.length === 0 ? null : (
        <div className="flex flex-col gap-1.5">
          <span className="text-sm font-medium">Where the run goes next</span>
          <OptionList
            label="Next stage"
            arity="one"
            options={branches.map((branch) => branch.label)}
            selected={branches
              .filter((branch) => branch.id === next)
              .map((branch) => branch.label)}
            onPick={(label) =>
              setNext(
                branches.find((branch) => branch.label === label)?.id ?? null,
              )
            }
            disabled={busy}
          />
        </div>
      )}
      <Field label={view.field} htmlFor={fieldId}>
        <Textarea
          id={fieldId}
          value={text}
          required
          disabled={busy}
          onChange={(event) => setText(event.target.value)}
          onKeyDown={(event) => {
            if (event.key === 'Enter' && (event.metaKey || event.ctrlKey)) {
              event.preventDefault();
              void submit();
            }
          }}
        />
      </Field>
      {resets.length === 0 ? null : (
        <p
          data-slot="stage-reopen-resets"
          className="m-0 text-xs text-muted-foreground">
          Sends back to pending: {resets.join(', ')}
        </p>
      )}
      {error === null ? null : <ErrorText>{error}</ErrorText>}
      <div className="flex justify-end gap-2">
        <Button type="button" variant="outline" onClick={onClose}>
          Cancel
        </Button>
        <Button type="submit" disabled={!ready}>
          {view.submit}
        </Button>
      </div>
    </form>
  );
}
