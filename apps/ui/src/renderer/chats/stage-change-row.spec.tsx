const CHANGE: StageChangePayload = {
  action: 'complete',
  stageId: 'review',
  stageTitle: 'Review',
  text: 'two rounds',
  rev: 3,
  by: { kind: 'agent', nodeId: 'manager' },
};

describe('stageChangeVerb (the markdown export’s wording)', () => {
  it.each<[Partial<StageChangePayload>, string]>([
    [{ action: 'complete' }, 'completed'],
    [{ action: 'complete', next: 'ship' }, 'completed — took ship'],
    [{ action: 'skip' }, 'skipped'],
    [{ action: 'skip', next: 'ship' }, 'skipped — took ship'],
    [{ action: 'reopen' }, 'reopened'],
    [{ action: 'nudge' }, 'still open — woke the lead'],
    [{ action: 'stalled' }, 'stalled — you were notified'],
  ])('words %j as "%s"', (over, verb) => {
    expect(stageChangeVerb({ ...CHANGE, ...over })).toBe(verb);
  });
});

describe('stageChangeHeadline', () => {
  it.each<[StageChangePayload['action'], string]>([
    ['complete', 'completed'],
    ['skip', 'skipped'],
    ['reopen', 'reopened'],
    ['nudge', 'still open — woke the lead'],
    ['stalled', 'stalled — you were notified'],
  ])('words %s as "%s"', (action, verb) => {
    expect(stageChangeHeadline(action)).toBe(verb);
  });
});

describe('stageActorLabel', () => {
  it('names an agent by its node, the user as You and geniro itself', () => {
    const name = (id: string): string => `agent ${id}`;
    expect(stageActorLabel({ kind: 'agent', nodeId: 'm' }, name)).toBe(
      'agent m',
    );
    expect(stageActorLabel({ kind: 'user', via: 'remote' }, name)).toBe('You');
    expect(stageActorLabel({ kind: 'system' }, name)).toBe('geniro');
  });
});

describe('stageTitleOf', () => {
  it('reads a stage’s title off the run’s list, and falls back to its id', () => {
    const stages = {
      rev: 1,
      current: null,
      position: { index: 1, total: 1 },
      stages: [
        { id: 'fix', title: 'Fix it', status: 'done' as const, next: [] },
      ],
    };
    expect(stageTitleOf(stages, 'fix')).toBe('Fix it');
    expect(stageTitleOf(stages, 'ship')).toBe('ship');
    expect(stageTitleOf(null, 'ship')).toBe('ship');
  });
});

describe('stageChangeSuperseded', () => {
  const progress = (
    rev: number,
    stageRev: number | undefined,
  ): StageProgress => ({
    rev,
    current: null,
    position: { index: 1, total: 1 },
    stages: [
      {
        id: 'review',
        title: 'Review',
        status: 'done',
        next: [],
        ...(stageRev === undefined ? {} : { rev: stageRev }),
      },
    ],
  });

  it('keeps a finish standing while it is the move that resolved its stage', () => {
    expect(
      stageChangeSuperseded(
        { ...CHANGE, action: 'complete', rev: 3 },
        progress(5, 3),
      ),
    ).toBe(false);
  });

  it('supersedes a finish or skip once the stage was resolved again by a later move', () => {
    expect(
      stageChangeSuperseded(
        { ...CHANGE, action: 'complete', rev: 3 },
        progress(5, 5),
      ),
    ).toBe(true);
    expect(
      stageChangeSuperseded(
        { ...CHANGE, action: 'skip', rev: 3 },
        progress(5, 5),
      ),
    ).toBe(true);
  });

  it('keeps a reopen standing while it is the move that set its stage, and supersedes it once a later one did', () => {
    const reopen: StageChangePayload = { ...CHANGE, action: 'reopen', rev: 4 };
    expect(stageChangeSuperseded(reopen, progress(6, 4))).toBe(false);
    expect(stageChangeSuperseded(reopen, progress(6, 5))).toBe(true);
  });

  it('judges no row by progress older than it — the row is written before its progress is announced', () => {
    for (const action of ['complete', 'skip', 'reopen'] as const) {
      expect(
        stageChangeSuperseded({ ...CHANGE, action, rev: 4 }, progress(3, 2)),
      ).toBe(false);
      expect(
        stageChangeSuperseded(
          { ...CHANGE, action, rev: 4 },
          progress(3, undefined),
        ),
      ).toBe(false);
    }
  });

  it('supersedes a nudge or a stall once the run’s progress moved on', () => {
    for (const action of ['nudge', 'stalled'] as const) {
      const change: StageChangePayload = { ...CHANGE, action, rev: 3 };
      expect(stageChangeSuperseded(change, progress(3, 3))).toBe(false);
      expect(stageChangeSuperseded(change, progress(4, 3))).toBe(true);
    }
  });

  it('never supersedes a hand-off: it records who led from then on', () => {
    const handoff: StageChangePayload = {
      ...CHANGE,
      action: 'handoff',
      rev: 1,
      by: { kind: 'system' },
      lead: 'ada',
    };
    expect(
      stageChangeSuperseded(handoff, {
        rev: 5,
        current: null,
        position: { index: 3, total: 3 },
        stages: [],
      }),
    ).toBe(false);
  });

  it('supersedes nothing while the run’s progress is unknown', () => {
    for (const action of [
      'complete',
      'skip',
      'reopen',
      'nudge',
      'stalled',
    ] as const) {
      expect(stageChangeSuperseded({ ...CHANGE, action }, null)).toBe(false);
    }
  });
});

describe('StageChangeRow', () => {
  let container: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    localStorage.clear();
  });

  function render(
    change: Partial<StageChangePayload>,
    props: {
      actor?: string;
      nextTitle?: string;
      time?: string;
      superseded?: boolean;
      leadName?: string;
    } = {},
    runId: string | null = null,
  ): HTMLElement {
    act(() =>
      root.render(
        <ThreadUiMemoryContext.Provider value={runId}>
          <StageChangeRow
            change={{ ...CHANGE, ...change }}
            actor={props.actor ?? 'Manager'}
            {...(props.nextTitle === undefined
              ? {}
              : { nextTitle: props.nextTitle })}
            {...(props.time === undefined ? {} : { time: props.time })}
            {...(props.superseded === undefined
              ? {}
              : { superseded: props.superseded })}
            {...(props.leadName === undefined
              ? {}
              : { leadName: props.leadName })}
          />
        </ThreadUiMemoryContext.Provider>,
      ),
    );
    return container.querySelector<HTMLElement>('[data-slot="stage-change"]')!;
  }

  const part = (slot: string): string | null =>
    container.querySelector(`[data-slot="${slot}"]`)?.textContent ?? null;

  it('heads the row with the stage and what happened, then who and when', () => {
    render({}, { time: '14:07' });
    expect(part('stage-headline')).toBe('Review completed');
    expect(part('stage-actor')).toBe('Manager');
    expect(
      container
        .querySelector('[data-slot="stage-actor"]')
        ?.getAttribute('data-actor'),
    ).toBe('agent');
    expect(container.querySelector('time')?.textContent).toBe('14:07');
  });

  it('names the member a hand-off gives the run to, falling back to its id', () => {
    const handoff = {
      action: 'handoff' as const,
      stageTitle: 'Build',
      text: 'Ada leads Build now.',
      by: { kind: 'system' as const },
      lead: 'ada',
    };
    render(handoff, { actor: 'geniro', leadName: 'Ada' });
    expect(part('stage-headline')).toBe('Build handed to Ada');
    render(handoff, { actor: 'geniro' });
    expect(part('stage-lead')).toBe('ada');
  });

  it('quotes the summary under the headline, and draws none when it is empty', () => {
    render({});
    expect(part('stage-summary')).toBe('two rounds');
    render({ action: 'nudge', text: '', by: { kind: 'system' } });
    expect(container.querySelector('[data-slot="stage-summary"]')).toBeNull();
  });

  it('names the branch a fork took by the stage’s title, falling back to its id', () => {
    render({ action: 'skip', next: 'ship' }, { nextTitle: 'Ship it' });
    expect(part('stage-headline')).toBe('Review skipped');
    expect(part('stage-branch')).toBe('took→Ship it');
    render({ action: 'skip', next: 'ship' });
    expect(part('stage-branch')).toBe('took→ship');
    render({});
    expect(container.querySelector('[data-slot="stage-branch"]')).toBeNull();
  });

  it('words a nudge and a stall for the user, and names geniro and You by kind', () => {
    render({ action: 'nudge', by: { kind: 'system' } }, { actor: 'geniro' });
    expect(part('stage-headline')).toBe('Review still open — woke the lead');
    expect(
      container
        .querySelector('[data-slot="stage-actor"]')
        ?.getAttribute('data-actor'),
    ).toBe('system');
    render({ action: 'stalled' });
    expect(part('stage-headline')).toBe('Review stalled — you were notified');
    render(
      { action: 'reopen', by: { kind: 'user', via: 'desktop' } },
      {
        actor: 'You',
      },
    );
    expect(part('stage-headline')).toBe('Review reopened');
    expect(
      container
        .querySelector('[data-slot="stage-actor"]')
        ?.getAttribute('data-actor'),
    ).toBe('user');
  });

  it('tones only the glyph and, for a nudge or a stall, the verb — never the row', () => {
    const verbClass = (): string =>
      container.querySelector('[data-slot="stage-verb"]')!.className;
    const row = render({ action: 'nudge' });
    expect(row.dataset.tone).toBe('warning');
    expect(verbClass()).toContain('text-warning');
    expect(row.querySelector('svg')!.getAttribute('class')).toContain(
      'text-warning',
    );
    expect(render({ action: 'stalled' }).dataset.tone).toBe('destructive');
    expect(verbClass()).toContain('text-destructive');
    const done = render({});
    expect(done.dataset.tone).toBe('success');
    expect(verbClass()).toContain('text-muted-foreground');
    expect(done.querySelector('svg')!.getAttribute('class')).toContain(
      'text-success',
    );
    for (const action of ['nudge', 'stalled', 'complete'] as const) {
      expect(render({ action }).className).not.toMatch(
        /\bbg-(warning|destructive|success|primary)/,
      );
    }
  });

  it('tags the row with its action', () => {
    expect(render({ action: 'reopen' }).getAttribute('data-action')).toBe(
      'reopen',
    );
  });

  it('opens the agents panel for its thread when the row is pressed', () => {
    writeThreadFlag('run-1', AGENTS_PANEL_COLLAPSED_FLAG, true);
    render({}, {}, 'run-1');
    const reveal = container.querySelector<HTMLButtonElement>(
      '[data-slot="stage-reveal"]',
    )!;
    expect(reveal.getAttribute('aria-label')).toBe(
      'Show stage Review in the agents panel',
    );
    act(() => reveal.click());
    expect(readThreadFlag('run-1', AGENTS_PANEL_COLLAPSED_FLAG)).toBe(false);
  });

  it('marks, dims and says "superseded" only when a later move superseded it', () => {
    const word = (row: HTMLElement) =>
      row.querySelector('[data-slot="stage-superseded"]')?.textContent ?? null;
    const dimmed = (row: HTMLElement): (string | null)[] =>
      [
        row.querySelector('svg'),
        row.querySelector('[data-slot="stage-verb"]'),
      ].map((el) =>
        (el?.getAttribute('class') ?? '').includes('opacity-60') ? 'dim' : null,
      );
    const live = render({});
    expect(live.hasAttribute('data-superseded')).toBe(false);
    expect(dimmed(live)).toEqual([null, null]);
    expect(word(live)).toBeNull();
    const stale = render({}, { superseded: true });
    expect(stale.hasAttribute('data-superseded')).toBe(true);
    expect(dimmed(stale)).toEqual(['dim', 'dim']);
    expect(word(stale)).toBe('superseded');
    const explicit = render({}, { superseded: false });
    expect(explicit.hasAttribute('data-superseded')).toBe(false);
    expect(dimmed(explicit)).toEqual([null, null]);
    expect(word(explicit)).toBeNull();
  });

  it('keeps the whole row and its text at full strength when superseded', () => {
    const stale = render({ text: 'two rounds' }, { superseded: true });
    expect(stale.className).not.toContain('opacity');
    const summary = stale.querySelector('[data-slot="stage-summary"] p')!;
    expect(summary.className).toContain('text-muted-foreground');
    expect(summary.className).not.toContain('opacity');
    expect(
      stale.querySelector('[data-slot="stage-headline"] .text-foreground')!
        .className,
    ).not.toContain('opacity');
  });

  it('is no control outside a thread', () => {
    render({});
    expect(container.querySelector('[data-slot="stage-reveal"]')).toBeNull();
  });
});

describe('ClampedText', () => {
  let container: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    vi.restoreAllMocks();
  });

  function overflow(scroll: number, client: number): void {
    vi.spyOn(HTMLElement.prototype, 'scrollHeight', 'get').mockReturnValue(
      scroll,
    );
    vi.spyOn(HTMLElement.prototype, 'clientHeight', 'get').mockReturnValue(
      client,
    );
  }

  it('offers no toggle when the text fits its one line', () => {
    overflow(16, 16);
    act(() => root.render(<ClampedText text="short" />));
    expect(container.querySelector('button')).toBeNull();
    expect(container.querySelector('p')?.className).toContain('line-clamp-1');
  });

  it('unclamps on "more" and clamps again on "less" when the text overflows', () => {
    overflow(48, 16);
    act(() => root.render(<ClampedText text="a long summary" />));
    const toggle = container.querySelector('button')!;
    expect(toggle.textContent).toBe('more');
    expect(toggle.getAttribute('aria-expanded')).toBe('false');
    act(() => toggle.click());
    expect(container.querySelector('p')?.className).not.toContain(
      'line-clamp-1',
    );
    expect(toggle.textContent).toBe('less');
    act(() => toggle.click());
    expect(container.querySelector('p')?.className).toContain('line-clamp-1');
  });

  it('keeps its press from reaching a row around it', () => {
    overflow(48, 16);
    const outer = vi.fn();
    act(() =>
      root.render(
        <div onClick={outer}>
          <ClampedText text="a long summary" />
        </div>,
      ),
    );
    act(() => container.querySelector('button')!.click());
    expect(outer).not.toHaveBeenCalled();
  });
});

describe('ClampedText memory', () => {
  let container: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
    vi.spyOn(HTMLElement.prototype, 'scrollHeight', 'get').mockReturnValue(48);
    vi.spyOn(HTMLElement.prototype, 'clientHeight', 'get').mockReturnValue(16);
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    vi.restoreAllMocks();
    localStorage.clear();
  });

  const draw = (memoryKey: string | undefined): void =>
    act(() =>
      root.render(
        <ThreadUiMemoryContext.Provider value="run-1">
          <ClampedText
            text="a long summary"
            {...(memoryKey === undefined ? {} : { memoryKey })}
          />
        </ThreadUiMemoryContext.Provider>,
      ),
    );

  it('keeps "more" open across a remount of the same row in the thread', () => {
    draw('stage:i1');
    act(() => container.querySelector('button')!.click());
    expect(readThreadFlag('run-1', 'stage:i1')).toBe(true);
    act(() => root.render(null));
    draw('stage:i1');
    expect(container.querySelector('p')?.className).not.toContain(
      'line-clamp-1',
    );
    expect(container.querySelector('button')?.textContent).toBe('less');
  });

  it('does not open a row whose key was never pressed', () => {
    draw('stage:i1');
    act(() => container.querySelector('button')!.click());
    act(() => root.render(null));
    draw('stage:i2');
    expect(container.querySelector('p')?.className).toContain('line-clamp-1');
  });
});
