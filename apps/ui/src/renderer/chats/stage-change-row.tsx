export const RunStagesContext = createContext<StageProgress | null>(null);

export function stageTitleOf(
  stages: StageProgress | null | undefined,
  id: string,
): string {
  return stages?.stages.find((stage) => stage.id === id)?.title ?? id;
}

export function stageActorLabel(
  by: StageActor,
  agentName: (memberId: string) => string,
): string {
  switch (by.kind) {
    case 'agent':
      return agentName(by.nodeId);
    case 'user':
      return 'You';
    case 'system':
      return 'geniro';
  }
}

type Tone = 'success' | 'primary' | 'muted' | 'warning' | 'destructive';

const STAGE_ACTION_VIEW: Record<
  StageChangeAction,
  { verb: string; Icon: LucideIcon; tone: Tone }
> = {
  complete: {
    verb: 'completed',
    Icon: STAGE_STATUS_VIEW.done.Icon,
    tone: 'success',
  },
  skip: {
    verb: 'skipped',
    Icon: STAGE_STATUS_VIEW.skipped.Icon,
    tone: 'muted',
  },
  reopen: { verb: 'reopened', Icon: RotateCcw, tone: 'primary' },
  nudge: {
    verb: 'still open — woke the lead',
    Icon: BellRing,
    tone: 'warning',
  },
  stalled: {
    verb: 'stalled — you were notified',
    Icon: TriangleAlert,
    tone: 'destructive',
  },
  handoff: { verb: 'handed to', Icon: UserRoundCheck, tone: 'primary' },
};

export function stageChangeHeadline(action: StageChangeAction): string {
  return STAGE_ACTION_VIEW[action].verb;
}

export function stageChangeVerb(change: StageChangePayload): string {
  const { verb } = STAGE_ACTION_VIEW[change.action];
  return change.next === undefined ? verb : `${verb} — took ${change.next}`;
}

export function ClampedText({
  text,
  className,
  memoryKey,
}: {
  text: string;
  className?: string;
  memoryKey?: string;
}): React.JSX.Element {
  const ref = useRef<HTMLParagraphElement>(null);
  const [expanded, setExpanded] = useThreadFlag(memoryKey, false);
  const [overflows, setOverflows] = useState(expanded);
  useLayoutEffect(() => {
    const element = ref.current;
    if (element === null || expanded) {
      return;
    }
    setOverflows(element.scrollHeight > element.clientHeight + 1);
  }, [text, expanded]);
  return (
    <div
      data-slot="clamped-text"
      className="flex min-w-0 items-baseline gap-1.5">
      <p
        ref={ref}
        className={cn(
          'm-0 min-w-0 flex-1 break-words whitespace-pre-wrap',
          !expanded && 'line-clamp-1',
          className,
        )}>
        {text}
      </p>
      {overflows ? (
        <button
          type="button"
          aria-expanded={expanded}
          className="pointer-events-auto relative shrink-0 cursor-pointer rounded-sm text-[11px] font-medium text-primary outline-none hover:underline focus-visible:ring-[3px] focus-visible:ring-ring/50"
          onClick={(event) => {
            event.stopPropagation();
            setExpanded((value) => !value);
          }}>
          {expanded ? 'less' : 'more'}
        </button>
      ) : null}
    </div>
  );
}

export function StageBranch({ title }: { title: string }): React.JSX.Element {
  return (
    <span
      data-slot="stage-branch"
      className="min-w-0 shrink truncate text-muted-foreground">
      <span className="sr-only">took</span>
      <span aria-hidden="true" className="mr-1">
        →
      </span>
      <span className="text-foreground">{title}</span>
    </span>
  );
}

const iconVariants = cva('mt-[3px] size-3.5 shrink-0', {
  variants: {
    tone: {
      success: 'text-success',
      primary: 'text-primary',
      muted: 'text-muted-foreground',
      warning: 'text-warning',
      destructive: 'text-destructive',
    },
    superseded: { true: 'opacity-60', false: '' },
  },
});

const verbVariants = cva('', {
  variants: {
    tone: {
      success: 'text-muted-foreground',
      primary: 'text-muted-foreground',
      muted: 'text-muted-foreground',
      warning: 'text-warning',
      destructive: 'text-destructive',
    },
    superseded: { true: 'opacity-60', false: '' },
  },
});

// A move's row is written before the progress it produced is announced.
export function stageChangeSuperseded(
  change: StageChangePayload,
  progress: StageProgress | null,
): boolean {
  if (progress === null || change.rev > progress.rev) {
    return false;
  }
  switch (change.action) {
    case 'complete':
    case 'skip':
    case 'reopen':
      return (
        progress.stages.find((s) => s.id === change.stageId)?.rev !== change.rev
      );
    case 'handoff':
      return false;
    default:
      return progress.rev > change.rev;
  }
}

export function StageChangeRow({
  change,
  actor,
  nextTitle,
  leadName,
  time,
  superseded = false,
  memoryKey,
}: {
  change: StageChangePayload;
  actor: string;
  nextTitle?: string;
  /** A hand-off's new lead, by name. */
  leadName?: string;
  time?: string;
  superseded?: boolean;
  memoryKey?: string;
}): React.JSX.Element {
  const runId = useContext(ThreadUiMemoryContext);
  const { verb, Icon, tone } = STAGE_ACTION_VIEW[change.action];
  return (
    <div
      data-slot="stage-change"
      data-action={change.action}
      data-tone={tone}
      data-superseded={superseded || undefined}
      className="relative flex w-full min-w-0 items-start gap-2 rounded-md px-2 py-1 text-xs transition-colors hover:bg-accent/50 has-[[data-slot=stage-reveal]:focus-visible]:ring-[3px] has-[[data-slot=stage-reveal]:focus-visible]:ring-ring/50">
      {runId === null ? null : (
        <button
          type="button"
          data-slot="stage-reveal"
          aria-label={`Show stage ${change.stageTitle} in the agents panel`}
          className="absolute inset-0 cursor-pointer rounded-md text-xs outline-none"
          onClick={() => revealAgentsPanel(runId)}
        />
      )}
      <Icon aria-hidden="true" className={iconVariants({ tone, superseded })} />
      <div className="pointer-events-none relative flex min-w-0 flex-1 flex-col gap-0.5">
        <div className="flex min-w-0 items-baseline gap-1.5 text-sm">
          <p data-slot="stage-headline" className="m-0 shrink-0">
            <span className="font-semibold text-foreground">
              {change.stageTitle}
            </span>{' '}
            <span
              data-slot="stage-verb"
              className={verbVariants({ tone, superseded })}>
              {verb}
            </span>
            {change.action === 'handoff' && change.lead !== undefined ? (
              <>
                {' '}
                <span
                  data-slot="stage-lead"
                  className="font-semibold text-foreground">
                  {leadName ?? change.lead}
                </span>
              </>
            ) : null}
          </p>
          {change.next === undefined ? null : (
            <StageBranch title={nextTitle ?? change.next} />
          )}
          <span className="ml-auto flex shrink-0 items-baseline gap-1 pl-2 text-[11px] text-muted-foreground">
            {superseded ? (
              <>
                <span data-slot="stage-superseded" className="italic">
                  superseded
                </span>
                <span aria-hidden="true">·</span>
              </>
            ) : null}
            <span
              data-slot="stage-actor"
              data-actor={change.by.kind}
              className="max-w-[12rem] truncate">
              {actor}
            </span>
            {time === undefined || time === '' ? null : (
              <>
                <span aria-hidden="true">·</span>
                <time className="tabular-nums">{time}</time>
              </>
            )}
          </span>
        </div>
        {change.text === '' ? null : (
          <div data-slot="stage-summary">
            <ClampedText
              text={change.text}
              className="text-muted-foreground"
              {...(memoryKey === undefined ? {} : { memoryKey })}
            />
          </div>
        )}
      </div>
    </div>
  );
}
