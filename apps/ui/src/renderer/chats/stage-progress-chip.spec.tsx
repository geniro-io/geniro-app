// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import { settleStageGraphs } from '../__tests__/settle-stage-graphs';
import { stubResizeObserver } from '../__tests__/stub-resize-observer';
import type { StageProgress } from '../autogenerated';
import { AGENTS_PANEL_COLLAPSED_FLAG } from './panel-flags';
import { StageProgressChip, stageTimeAgo } from './stage-progress-chip';
import {
  readThreadFlag,
  ThreadUiMemoryContext,
  writeThreadFlag,
} from './thread-ui-memory';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLElement;
let root: Root;

const progress = (over: Partial<StageProgress> = {}): StageProgress => ({
  rev: 3,
  current: 'review',
  position: { index: 2, total: 4 },
  stages: [
    {
      id: 'build',
      title: 'Build',
      status: 'done',
      next: ['review'],
      by: { kind: 'agent', nodeId: 'lead' },
      text: 'compiled clean',
    },
    { id: 'review', title: 'Review', status: 'current', next: ['ship'] },
    { id: 'ship', title: 'Ship', status: 'pending', next: [] },
    { id: 'docs', title: 'Docs', status: 'not_taken', next: [] },
  ],
  ...over,
});

const forked = (over: Partial<StageProgress> = {}): StageProgress => ({
  rev: 2,
  current: 'fix',
  position: { index: 2, total: 3 },
  stages: [
    {
      id: 'investigate',
      title: 'Investigation',
      status: 'done',
      next: ['implement', 'fix'],
      chosen: 'fix',
    },
    {
      id: 'implement',
      title: 'Implementation',
      status: 'not_taken',
      next: ['review'],
    },
    { id: 'fix', title: 'Fix', status: 'current', next: ['review'] },
    { id: 'review', title: 'Review', status: 'pending', next: [] },
  ],
  ...over,
});

const undecided = (): StageProgress => ({
  rev: 0,
  current: 'investigate',
  position: { index: 1, total: 3 },
  stages: [
    {
      id: 'investigate',
      title: 'Investigation',
      status: 'current',
      next: ['implement', 'fix'],
    },
    {
      id: 'implement',
      title: 'Implementation',
      status: 'pending',
      next: ['review'],
    },
    { id: 'fix', title: 'Fix', status: 'pending', next: ['review'] },
    { id: 'review', title: 'Review', status: 'pending', next: [] },
  ],
});

describe('stageTimeAgo', () => {
  const now = Date.parse('2026-10-27T12:00:00Z');
  it('says how long ago, and leaves "just now" as it is', () => {
    expect(stageTimeAgo('2026-10-27T11:55:00Z', now)).toBe('5m ago');
    expect(stageTimeAgo('2026-10-27T09:00:00Z', now)).toBe('3h ago');
    expect(stageTimeAgo('2026-10-27T11:59:50Z', now)).toBe('just now');
  });
});

describe('StageProgressChip', () => {
  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    localStorage.clear();
  });

  function mount(value: StageProgress | null | undefined, runId = 'run-1') {
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
    act(() => {
      root.render(
        <ThreadUiMemoryContext.Provider value={runId}>
          <StageProgressChip progress={value} />
        </ThreadUiMemoryContext.Provider>,
      );
    });
  }

  const trigger = (): HTMLButtonElement =>
    container.querySelector<HTMLButtonElement>('button')!;

  const open = (): void => act(() => trigger().click());

  it.each([null, undefined])(
    'draws nothing when the run has %s stages',
    (value) => {
      mount(value);
      expect(container.textContent).toBe('');
    },
  );

  it('shows only the position on the chip, the current stage’s title in its label', () => {
    mount(progress());
    expect(trigger().textContent).toBe('2/4');
    expect(trigger().getAttribute('aria-label')).toBe('Stage 2 of 4: Review');
    expect(trigger().getAttribute('title')).toBe('Stages · 2 of 4 · Review');
  });

  it('takes the figure from the position, not from the stages it lists', () => {
    mount(progress({ position: { index: 3, total: 9 } }));
    expect(trigger().textContent).toContain('3/9');
  });

  it('marks a finished run done, with no title', () => {
    mount(
      progress({
        current: null,
        position: { index: 4, total: 4 },
        stages: progress().stages.map((stage) => ({
          ...stage,
          status: 'done' as const,
        })),
      }),
    );
    expect(trigger().textContent).toBe('4/4');
    expect(trigger().getAttribute('aria-label')).toBe('All 4 stages done');
  });

  const entries = (): HTMLElement[] => [
    ...document.querySelectorAll<HTMLElement>(
      '[data-slot="stage-entries"] [data-slot="stage-entry"]',
    ),
  ];
  const pills = (): HTMLElement[] => [
    ...document.querySelectorAll<HTMLElement>(
      '[data-slot="stage-graph"] [data-slot="stage-pill"]',
    ),
  ];

  it('heads the popover with the position, and the finished run with all done', () => {
    mount(progress());
    open();
    expect(
      document.querySelector('[data-slot="stage-position"]')?.textContent,
    ).toBe('2 of 4');
    act(() => root.unmount());
    container.remove();
    mount(progress({ current: null, position: { index: 4, total: 4 } }));
    open();
    expect(
      document.querySelector('[data-slot="stage-position"]')?.textContent,
    ).toBe('All 4 done');
  });

  it('draws the run’s graph with each stage’s status, a fork split into rows', async () => {
    stubResizeObserver();
    mount(forked());
    open();
    await settleStageGraphs();
    expect(
      pills().map((pill) => [
        pill.dataset.stageId,
        pill.dataset.column,
        pill.dataset.status,
      ]),
    ).toEqual([
      ['investigate', '0', 'done'],
      ['implement', '1', 'not_taken'],
      ['fix', '1', 'current'],
      ['review', '2', 'pending'],
    ]);
    expect(pills().some((pill) => pill.getAttribute('role') === 'button')).toBe(
      false,
    );
  });

  it('shows what may follow the current stage: both branches of a fork ahead', async () => {
    stubResizeObserver();
    mount(undecided());
    open();
    await settleStageGraphs();
    const ahead = [
      ...document.querySelectorAll<SVGPathElement>(
        '[data-slot="stage-graph"] [data-slot="stage-edge"]',
      ),
    ]
      .filter((edge) => edge.dataset.edge!.startsWith('investigate>'))
      .map((edge) => [edge.dataset.edge, edge.dataset.tone]);
    expect(ahead).toEqual([
      ['investigate>implement', 'plain'],
      ['investigate>fix', 'plain'],
    ]);
    expect(
      pills()
        .filter((pill) => pill.dataset.column === '1')
        .map((pill) => pill.dataset.status),
    ).toEqual(['pending', 'pending']);
  });

  it('lists every stage with its status in a word, the current one as the step', () => {
    mount(progress());
    open();
    expect(
      entries().map((row) => [
        row.querySelector('[data-slot="stage-entry-title"]')?.textContent,
        row.querySelector('[data-slot="stage-status"]')?.textContent,
      ]),
    ).toEqual([
      ['Build', 'done'],
      ['Review', 'current'],
      ['Ship', 'pending'],
      ['Docs', 'not taken'],
    ]);
    expect(entries().map((row) => row.getAttribute('aria-current'))).toEqual([
      null,
      'step',
      null,
      null,
    ]);
  });

  it('names the branch a fork took by its title', () => {
    mount(forked());
    open();
    const [investigation] = entries();
    expect(
      investigation!.querySelector('[data-slot="stage-branch"]')?.textContent,
    ).toBe('took→Fix');
  });

  it('names who finished a stage and when, and their summary', () => {
    mount(
      progress({
        stages: progress().stages.map((stage) =>
          stage.id === 'build'
            ? { ...stage, at: new Date(Date.now() - 5 * 60_000).toISOString() }
            : stage,
        ),
      }),
    );
    open();
    const [build, review] = entries();
    expect(build!.querySelector('[data-slot="stage-actor"]')?.textContent).toBe(
      'lead',
    );
    expect(build!.querySelector('time')?.textContent).toBe('5m ago');
    expect(
      build!.querySelector('[data-slot="stage-entry-summary"]')?.textContent,
    ).toBe('compiled clean');
    expect(review!.querySelector('[data-slot="stage-actor"]')).toBeNull();
    expect(
      review!.querySelector('[data-slot="stage-entry-summary"]'),
    ).toBeNull();
  });

  it('opens the agents panel for its thread from the popover', () => {
    writeThreadFlag('run-1', AGENTS_PANEL_COLLAPSED_FLAG, true);
    mount(progress());
    open();
    const reveal = [
      ...document.querySelectorAll<HTMLButtonElement>('button'),
    ].find((button) => button.textContent === 'Open in agents panel');
    act(() => reveal?.click());
    expect(readThreadFlag('run-1', AGENTS_PANEL_COLLAPSED_FLAG)).toBe(false);
  });
});
