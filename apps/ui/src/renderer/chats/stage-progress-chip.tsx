import { cva } from 'class-variance-authority';
import { CircleCheck, CircleDot, PanelRight } from 'lucide-react';
import { type ReactNode, useContext } from 'react';

import type { StageProgress, StageProgressEntry } from '../autogenerated';
import { HoverPopover } from '../components/hover-popover';
import { STAGE_STATUS_VIEW, StageGraph } from '../components/stage-graph';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import { revealAgentsPanel } from './panel-flags';
import { formatRelativeTime } from './relative-time';
import { SHELF_CHIP_CLASS, SHELF_YIELD_CLASS } from './shelf-chip';
import {
  ClampedText,
  stageActorLabel,
  StageBranch,
  stageTitleOf,
} from './stage-change-row';
import { ThreadUiMemoryContext } from './thread-ui-memory';

export function stageTimeAgo(at: string, now: number = Date.now()): string {
  const relative = formatRelativeTime(at, now);
  return /^\d+[mhd]$/.test(relative) ? `${relative} ago` : relative;
}

const statusIconVariants = cva('size-3.5 shrink-0', {
  variants: {
    status: {
      done: 'text-success',
      current: 'text-primary',
      pending: 'text-muted-foreground/70',
      skipped: 'text-muted-foreground',
      not_taken: 'text-muted-foreground/70',
    },
  },
});

const entryTitleVariants = cva('min-w-0 truncate', {
  variants: {
    status: {
      done: 'text-foreground',
      current: 'font-semibold text-foreground',
      pending: 'text-foreground',
      skipped: 'text-muted-foreground',
      not_taken: 'text-muted-foreground',
    },
  },
});

const entryMetaVariants = cva(
  'flex items-baseline gap-1 text-[11px] text-muted-foreground',
  {
    variants: {
      withAction: {
        true: '[grid-area:1/1] transition-opacity group-focus-within/stage:opacity-0 group-hover/stage:opacity-0',
        false: '',
      },
    },
  },
);

export function StageEntry({
  stage,
  progress,
  agentName = (nodeId) => nodeId,
  action,
  children,
}: {
  stage: StageProgressEntry;
  progress: StageProgress;
  agentName?: (nodeId: string) => string;
  action?: ReactNode;
  children?: ReactNode;
}): React.JSX.Element {
  const { word, Icon } = STAGE_STATUS_VIEW[stage.status];
  const withAction = action !== undefined && action !== null;
  const meta = (
    <span className={entryMetaVariants({ withAction })}>
      <span data-slot="stage-status">{word}</span>
      {stage.by === undefined ? null : (
        <>
          <span aria-hidden="true">·</span>
          <span
            data-slot="stage-actor"
            data-actor={stage.by.kind}
            className="max-w-[7rem] truncate">
            {stageActorLabel(stage.by, agentName)}
          </span>
        </>
      )}
      {stage.at === undefined ? null : (
        <>
          <span aria-hidden="true">·</span>
          <time dateTime={stage.at}>{stageTimeAgo(stage.at)}</time>
        </>
      )}
    </span>
  );
  return (
    <li
      data-slot="stage-entry"
      data-status={stage.status}
      aria-current={stage.status === 'current' ? 'step' : undefined}
      className="group/stage flex min-w-0 flex-col gap-0.5 py-1.5">
      <div className="flex min-w-0 items-center gap-2">
        <Icon
          aria-hidden="true"
          className={statusIconVariants({ status: stage.status })}
        />
        <span
          data-slot="stage-entry-title"
          className={entryTitleVariants({ status: stage.status })}>
          {stage.title}
        </span>
        {stage.chosen === undefined ? null : (
          <StageBranch title={stageTitleOf(progress, stage.chosen)} />
        )}
        <span className="ml-auto grid shrink-0 justify-items-end pl-2">
          {meta}
          {withAction ? (
            <span className="flex items-center opacity-0 transition-opacity [grid-area:1/1] group-focus-within/stage:opacity-100 group-hover/stage:opacity-100">
              {action}
            </span>
          ) : null}
        </span>
      </div>
      {stage.text === undefined || stage.text === '' ? null : (
        <div data-slot="stage-entry-summary" className="pl-5.5">
          <ClampedText text={stage.text} className="text-muted-foreground" />
        </div>
      )}
      {children === undefined || children === null ? null : (
        <div data-slot="stage-entry-details" className="pl-5.5">
          {children}
        </div>
      )}
    </li>
  );
}

export function StageProgressChip({
  progress,
}: {
  progress: StageProgress | null | undefined;
}): React.JSX.Element | null {
  const runId = useContext(ThreadUiMemoryContext);
  if (progress === null || progress === undefined) {
    return null;
  }
  const { index, total } = progress.position;
  const finished = progress.current === null;
  const current =
    progress.stages.find((stage) => stage.id === progress.current) ?? null;
  return (
    <HoverPopover
      slot="stage-progress"
      openOn="click"
      label={
        finished
          ? `All ${total} ${total === 1 ? 'stage' : 'stages'} done`
          : `Stage ${index} of ${total}${current === null ? '' : `: ${current.title}`}`
      }
      panelLabel="Stages"
      side="top"
      align="start"
      className="min-w-min"
      triggerClassName={cn(SHELF_CHIP_CLASS, 'min-w-min')}
      panelClassName="w-[24rem]"
      trigger={
        <>
          {finished ? (
            <CircleCheck
              aria-hidden="true"
              className="size-3.5 shrink-0 text-success"
            />
          ) : (
            <CircleDot
              aria-hidden="true"
              className="size-3.5 shrink-0 text-muted-foreground"
            />
          )}
          <span className="shrink-0 font-medium tabular-nums">
            {index}/{total}
          </span>
          {current === null ? null : (
            <span className={SHELF_YIELD_CLASS}>
              <span className="min-w-0 truncate text-muted-foreground">
                · {current.title}
              </span>
            </span>
          )}
        </>
      }>
      {(close) => (
        <div className="flex flex-col gap-3 p-1 text-xs">
          <header className="flex items-baseline gap-1.5 px-1">
            <span className="text-sm font-semibold">Stages</span>
            <span
              data-slot="stage-position"
              className="ml-auto text-muted-foreground tabular-nums">
              {finished ? `All ${total} done` : `${index} of ${total}`}
            </span>
          </header>
          <StageGraph stages={progress.stages} className="px-1" />
          <ol
            aria-label="Stages"
            data-slot="stage-entries"
            className="m-0 flex max-h-[16rem] list-none flex-col divide-y divide-border overflow-y-auto border-y border-border px-1">
            {progress.stages.map((stage) => (
              <StageEntry key={stage.id} stage={stage} progress={progress} />
            ))}
          </ol>
          <Button
            type="button"
            variant="ghost"
            size="sm"
            className="self-start"
            onClick={() => {
              close();
              revealAgentsPanel(runId);
            }}>
            <PanelRight aria-hidden="true" />
            Open in agents panel
          </Button>
        </div>
      )}
    </HoverPopover>
  );
}
