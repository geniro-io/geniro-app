import { describe, expect, it } from 'vitest';

import type { StageProgress } from '../autogenerated';
import { distinctStageLabels, stagesReopenResets } from './stage-progress';

const WALKED: StageProgress = {
  rev: 7,
  current: 'review',
  position: { index: 3, total: 3 },
  stages: [
    { id: 'plan', title: 'Plan', status: 'done', next: ['build', 'docs'] },
    { id: 'build', title: 'Build', status: 'skipped', next: ['review'] },
    { id: 'review', title: 'Review', status: 'current', next: [] },
    { id: 'docs', title: 'Docs', status: 'not_taken', next: [] },
  ],
};

describe('stagesReopenResets', () => {
  it('takes every finished or current stage reachable from the reopened one', () => {
    expect(stagesReopenResets(WALKED, 'plan')).toEqual(['build', 'review']);
    expect(stagesReopenResets(WALKED, 'build')).toEqual(['review']);
  });

  it('leaves out the reopened stage itself on a loop back to it', () => {
    const looping: StageProgress = {
      rev: 3,
      current: 'review',
      position: { index: 2, total: 2 },
      stages: [
        { id: 'fix', title: 'Fix', status: 'done', next: ['review'] },
        { id: 'review', title: 'Review', status: 'current', next: ['fix'] },
      ],
    };
    expect(stagesReopenResets(looping, 'fix')).toEqual(['review']);
  });
});

describe('distinctStageLabels', () => {
  it('labels a stage by its title, adding the id only where titles repeat', () => {
    expect(
      distinctStageLabels([
        { id: 'fix', title: 'Fix' },
        { id: 'fix-ui', title: 'Fix' },
        { id: 'review', title: 'Review' },
      ]),
    ).toEqual(
      new Map([
        ['fix', 'Fix (fix)'],
        ['fix-ui', 'Fix (fix-ui)'],
        ['review', 'Review'],
      ]),
    );
  });

  it('keeps labels apart when a title reads like another stage’s labelled one', () => {
    const labels = distinctStageLabels([
      { id: 'x', title: 'A' },
      { id: 'z', title: 'A' },
      { id: 'y', title: 'A (x)' },
    ]);
    expect(new Set(labels.values()).size).toBe(3);
    expect(labels.get('y')).toBe('A (x) (y)');
  });
});
