import type { StageProgress } from '../autogenerated';

/** TWIN: stagesReopenResets in apps/daemon/src/v1/teams/utils/stage-fold.ts. */
export function stagesReopenResets(
  progress: StageProgress,
  id: string,
): string[] {
  const byId = new Map(progress.stages.map((stage) => [stage.id, stage]));
  const seen = new Set<string>();
  const queue = [id];
  while (queue.length > 0) {
    const at = queue.shift()!;
    if (seen.has(at)) {
      continue;
    }
    seen.add(at);
    queue.push(...(byId.get(at)?.next ?? []));
  }
  seen.delete(id);
  return progress.stages
    .filter(
      (stage) =>
        seen.has(stage.id) &&
        (stage.status === 'done' ||
          stage.status === 'skipped' ||
          stage.status === 'current'),
    )
    .map((stage) => stage.id);
}

/** An option label per stage id, its title made unique by the id when titles repeat. */
export function distinctStageLabels(
  stages: readonly { id: string; title: string }[],
): Map<string, string> {
  const counts = new Map<string, number>();
  for (const { title } of stages) {
    counts.set(title, (counts.get(title) ?? 0) + 1);
  }
  const labels = stages.map(({ id, title }) =>
    counts.get(title)! > 1 ? `${title} (${id})` : title,
  );
  return new Map(
    stages.map(({ id, title }, index) => {
      const label = labels[index]!;
      const taken = labels.filter((other) => other === label).length > 1;
      return [id, taken && label === title ? `${title} (${id})` : label];
    }),
  );
}
