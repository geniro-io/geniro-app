// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type {
  StageMoveResultDto,
  StageProgress,
  WorkflowStage,
} from '../autogenerated';
import { type RunStages, StagesSection } from './stages-section';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const PROGRESS: StageProgress = {
  rev: 2,
  current: 'review',
  position: { index: 3, total: 4 },
  stages: [
    {
      id: 'plan',
      title: 'Plan',
      status: 'done',
      next: ['build'],
      by: { kind: 'agent', nodeId: 'lead' },
      text: 'Scoped to calc.py.',
    },
    {
      id: 'build',
      title: 'Build',
      status: 'skipped',
      next: ['review', 'docs'],
      chosen: 'review',
      by: { kind: 'user', via: 'desktop' },
      text: 'Already built.',
    },
    { id: 'review', title: 'Review', status: 'current', next: ['ship'] },
    { id: 'docs', title: 'Docs', status: 'not_taken', next: [] },
    { id: 'ship', title: 'Ship', status: 'pending', next: [] },
  ],
};

const DEFINITIONS: WorkflowStage[] = [
  { id: 'plan', title: 'Plan', doneWhen: 'A plan exists.', next: ['build'] },
  {
    id: 'build',
    title: 'Build',
    doneWhen: 'It compiles.',
    next: ['review', 'docs'],
  },
  {
    id: 'review',
    title: 'Review',
    instructions: 'Read the diff against the README.',
    doneWhen: 'Every finding is answered.',
    ownerHint: 'reviewer',
    next: ['ship'],
  },
  { id: 'docs', title: 'Docs', doneWhen: 'Docs updated.' },
  { id: 'ship', title: 'Ship', doneWhen: 'Merged.' },
];

const NAMES: Record<string, string> = { lead: 'Lead', reviewer: 'Reviewer' };
const agentName = (nodeId: string): string => NAMES[nodeId] ?? nodeId;

function mount(over: Partial<RunStages> = {}): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <StagesSection
        stages={{
          progress: PROGRESS,
          definitions: DEFINITIONS,
          archived: false,
          onMove: vi.fn(),
          ...over,
        }}
        agentName={agentName}
      />,
    );
  });
  return container;
}

const row = (el: HTMLElement, id: string): HTMLElement =>
  [...el.querySelectorAll<HTMLElement>('[data-slot="stage-entry"]')].find(
    (entry) =>
      entry.querySelector('[data-slot="stage-entry-title"]')?.textContent ===
      PROGRESS.stages.find((stage) => stage.id === id)?.title,
  )!;

const buttonNamed = (
  el: HTMLElement,
  name: string,
): HTMLButtonElement | undefined =>
  [...el.querySelectorAll<HTMLButtonElement>('button')].find(
    (button) =>
      (button.getAttribute('aria-label') ?? button.textContent) === name,
  );

function type(el: HTMLElement, text: string): void {
  const field = el.querySelector('textarea')!;
  const setValue = Object.getOwnPropertyDescriptor(
    HTMLTextAreaElement.prototype,
    'value',
  )!.set!;
  act(() => {
    setValue.call(field, text);
    field.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

describe('StagesSection', () => {
  it('draws the graph and lists every stage with its status word', () => {
    const el = mount();
    expect(el.querySelector('section[aria-label="Stages"] svg')).not.toBeNull();
    expect(
      [...el.querySelectorAll('[data-slot="stage-status"]')].map(
        (word) => word.textContent,
      ),
    ).toEqual(['done', 'skipped', 'current', 'not taken', 'pending']);
    expect(el.querySelector('[data-slot="stage-position"]')?.textContent).toBe(
      '3 of 4',
    );
  });

  it('unfolds the current stage with what the run’s workflow says of it', () => {
    const el = mount();
    const current = row(el, 'review');
    expect(
      current.querySelector('[data-slot="stage-instructions"]')?.textContent,
    ).toBe('Read the diff against the README.');
    expect(
      current.querySelector('[data-slot="stage-done-when"]')?.textContent,
    ).toBe('Done when Every finding is answered.');
    expect(
      current.querySelector('[data-slot="stage-owner"]')?.textContent,
    ).toBe('Usually done by Reviewer');
    expect(buttonNamed(current, 'Mark done…')).toBeDefined();
    expect(buttonNamed(current, 'Skip…')).toBeDefined();
    expect(
      el.querySelectorAll('[data-slot="stage-entry-details"]'),
    ).toHaveLength(1);
  });

  it('offers Reopen on a finished or skipped stage only', () => {
    const el = mount();
    expect(buttonNamed(row(el, 'plan'), 'Reopen Plan…')).toBeDefined();
    expect(buttonNamed(row(el, 'build'), 'Reopen Build…')).toBeDefined();
    for (const id of ['review', 'docs', 'ship']) {
      expect(
        [...row(el, id).querySelectorAll('button')].filter((button) =>
          button.getAttribute('aria-label')?.startsWith('Reopen'),
        ),
      ).toHaveLength(0);
    }
  });

  it('keeps Reopen visible on touch and narrow screens, beside the meta instead of over it', () => {
    const plan = row(mount(), 'plan');
    const classes = (el: Element | null): string => el?.className ?? '';
    const aside = plan.querySelector('[data-slot="stage-entry-aside"]');
    const action = buttonNamed(plan, 'Reopen Plan…')!.parentElement;
    const meta = plan.querySelector(
      '[data-slot="stage-status"]',
    )!.parentElement;
    expect(classes(action)).toContain('pointer-coarse:opacity-100');
    expect(classes(action)).toContain('max-sm:opacity-100');
    expect(classes(aside)).toContain('pointer-coarse:flex');
    expect(classes(aside)).toContain('max-sm:flex');
    expect(classes(meta)).not.toMatch(
      /(^|\s)(group-hover|group-focus-within)\//,
    );
    expect(classes(meta)).toContain(
      'sm:pointer-fine:group-hover/stage:opacity-0',
    );
  });

  it('lets the meta give way before the entry title does', () => {
    const plan = row(mount(), 'plan');
    const aside = plan.querySelector('[data-slot="stage-entry-aside"]');
    const title = plan.querySelector('[data-slot="stage-entry-title"]');
    expect(aside?.className).toContain('min-w-0');
    expect(aside?.className).not.toMatch(/(^|\s)shrink-0(\s|$)/);
    expect(aside?.className).toMatch(/(^|\s)shrink-\d{2,}(\s|$)/);
    expect(title?.className).toContain('truncate');
    const actor = plan.querySelector('[data-slot="stage-actor"]');
    expect(actor?.className).toContain('truncate');
    expect(actor?.className).toContain('min-w-0');
  });

  it('draws an archived run’s stages without a single action', () => {
    const el = mount({ archived: true });
    expect(el.querySelector('[data-slot="stage-done-when"]')?.textContent).toBe(
      'Done when Every finding is answered.',
    );
    expect(el.querySelectorAll('section button')).toHaveLength(0);
  });

  it('names the agent who moved a stage', () => {
    const el = mount();
    expect(
      row(el, 'plan').querySelector('[data-slot="stage-actor"]')?.textContent,
    ).toBe('Lead');
    expect(
      row(el, 'build').querySelector('[data-slot="stage-actor"]')?.textContent,
    ).toBe('You');
  });

  it('opens the move on the revision on screen, and draws the answer at once', async () => {
    const after: StageProgress = {
      ...PROGRESS,
      rev: 3,
      current: 'ship',
      position: { index: 4, total: 4 },
      stages: PROGRESS.stages.map((stage) =>
        stage.id === 'review'
          ? { ...stage, status: 'done', text: 'All answered.' }
          : stage.id === 'ship'
            ? { ...stage, status: 'current' }
            : stage,
      ),
    };
    const onMove = vi
      .fn<(dto: unknown) => Promise<StageMoveResultDto>>()
      .mockResolvedValue({ progress: after, woke: true, hasLead: true });
    const el = mount({ onMove });

    act(() => buttonNamed(row(el, 'review'), 'Mark done…')!.click());
    type(el, 'All answered.');
    await act(async () => {
      el.querySelector<HTMLButtonElement>('button[type="submit"]')!.click();
    });

    expect(onMove).toHaveBeenCalledWith({
      action: 'complete',
      stage: 'review',
      text: 'All answered.',
      expectedRev: 2,
    });
    expect(el.querySelector('[role="dialog"]')).toBeNull();
    expect(
      row(el, 'review').querySelector('[data-slot="stage-status"]')
        ?.textContent,
    ).toBe('done');
    expect(el.querySelector('[data-slot="stage-position"]')?.textContent).toBe(
      '4 of 4',
    );
    expect(el.querySelector('[role="status"]')?.textContent).toBe(
      'The lead agent will pick this up.',
    );
  });

  it('tells the user to send a message when the move woke no lead agent', async () => {
    const onMove = vi
      .fn<(dto: unknown) => Promise<StageMoveResultDto>>()
      .mockResolvedValue({
        progress: { ...PROGRESS, rev: 3 },
        woke: false,
        hasLead: true,
      });
    const el = mount({ onMove });
    act(() => buttonNamed(row(el, 'plan'), 'Reopen Plan…')!.click());
    expect(el.querySelector('[role="status"]')).toBeNull();
    type(el, 'The plan missed the README.');
    await act(async () => {
      el.querySelector<HTMLButtonElement>('button[type="submit"]')!.click();
    });
    expect(onMove).toHaveBeenCalledWith(
      expect.objectContaining({ action: 'reopen', stage: 'plan' }),
    );
    expect(el.querySelector('[role="dialog"]')).toBeNull();
    expect(el.querySelector('[role="status"]')?.textContent).toBe(
      'The lead agent sees this on its next turn — send it a message to continue.',
    );
  });

  it('says no agent was told when the workflow has no lead to wake', async () => {
    const onMove = vi
      .fn<(dto: unknown) => Promise<StageMoveResultDto>>()
      .mockResolvedValue({
        progress: { ...PROGRESS, rev: 3 },
        woke: false,
        hasLead: false,
      });
    const el = mount({ onMove });
    act(() => buttonNamed(row(el, 'plan'), 'Reopen Plan…')!.click());
    type(el, 'The plan missed the README.');
    await act(async () => {
      el.querySelector<HTMLButtonElement>('button[type="submit"]')!.click();
    });
    expect(el.querySelector('[role="status"]')?.textContent).toBe(
      'No agent was told: this workflow’s trigger starts none.',
    );
  });
});
