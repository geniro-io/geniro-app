const agentName = (nodeId: string): string =>
  nodeId === 'lead' ? 'lead' : nodeId;

const accept =
  (progress: StageProgress) =>
  (dto: MoveTeamRunStageDto): Promise<StageMoveResultDto> =>
    Promise.resolve({
      progress: {
        ...progress,
        rev: Math.max(progress.rev, dto.expectedRev) + 1,
      },
      woke: true,
      hasLead: true,
    });

