import { Check, RotateCcw, SkipForward } from 'lucide-react';
import { useState } from 'react';

import type {
  MoveWorkflowRunStageDto,
  StageMoveResultDto,
  StageProgress,
  StageProgressEntry,
  WorkflowStage,
} from '../autogenerated';
import { PanelSection } from '../components/panel-section';
import { StageGraph } from '../components/stage-graph';
import { Button } from '../components/ui/button';
import {
  StageActionDialog,
  type StageActionRequest,
  type StageMoveAction,
} from './stage-action-dialog';
import { StageEntry } from './stage-progress-chip';

export interface RunStages {
  progress: StageProgress;
  definitions: readonly WorkflowStage[] | null;
  archived: boolean;
  onMove?: (dto: MoveWorkflowRunStageDto) => Promise<StageMoveResultDto>;
}

export function StagesSection({
  stages,
  agentName,
}: {
  stages: RunStages;
  agentName: (nodeId: string) => string;
}): React.JSX.Element {
  const { definitions, archived, onMove } = stages;
  // The run_status announce after a move carries the same rev; the newer one wins.
  const [moved, setMoved] = useState<StageProgress | null>(null);
  const progress =
    moved !== null && moved.rev > stages.progress.rev ? moved : stages.progress;
  const [request, setRequest] = useState<StageActionRequest | null>(null);
  const [told, setTold] = useState<StageMoveResultDto | null>(null);
  const canAct = !archived && onMove !== undefined;
  const { index, total } = progress.position;

  const open = (action: StageMoveAction, stageId: string): void => {
    setTold(null);
    setRequest({ action, stageId, rev: progress.rev });
  };

  const actionOf = (stage: StageProgressEntry): React.ReactNode => {
    if (!canAct || (stage.status !== 'done' && stage.status !== 'skipped')) {
      return null;
    }
    return (
      <Button
        type="button"
        variant="ghost"
        size="sm"
        aria-label={`Reopen ${stage.title}…`}
        className="h-5 gap-1 px-1 text-[11px] font-normal text-muted-foreground hover:text-foreground has-[>svg]:px-1"
        onClick={() => open('reopen', stage.id)}>
        <RotateCcw aria-hidden="true" className="size-3" />
        Reopen…
      </Button>
    );
  };

  return (
    <PanelSection
      label="Stages"
      action={
        <span
          data-slot="stage-position"
          className="text-[11px] text-muted-foreground tabular-nums">
          {progress.current === null
            ? `All ${total} done`
            : `${index} of ${total}`}
        </span>
      }>
      <StageGraph stages={progress.stages} />
      <ol
        aria-label="Stages"
        data-slot="stage-entries"
        className="m-0 flex list-none flex-col divide-y divide-border border-y border-border p-0 text-xs">
        {progress.stages.map((stage) => (
          <StageEntry
            key={stage.id}
            stage={stage}
            progress={progress}
            agentName={agentName}
            action={actionOf(stage)}>
            {stage.status === 'current' ? (
              <CurrentStageDetails
                definition={
                  definitions?.find((entry) => entry.id === stage.id) ?? null
                }
                agentName={agentName}
                onComplete={
                  canAct ? () => open('complete', stage.id) : undefined
                }
                onSkip={canAct ? () => open('skip', stage.id) : undefined}
              />
            ) : null}
          </StageEntry>
        ))}
      </ol>
      {told === null ? null : (
        <p role="status" className="m-0 text-[11px] text-muted-foreground">
          {toldLine(told)}
        </p>
      )}
      {onMove === undefined ? null : (
        <StageActionDialog
          request={canAct ? request : null}
          progress={progress}
          onMove={onMove}
          onClose={() => setRequest(null)}
          onMoved={(result) => {
            setMoved(result.progress);
            setTold(result);
            setRequest(null);
          }}
        />
      )}
    </PanelSection>
  );
}

function CurrentStageDetails({
  definition,
  agentName,
  onComplete,
  onSkip,
}: {
  definition: WorkflowStage | null;
  agentName: (nodeId: string) => string;
  onComplete?: () => void;
  onSkip?: () => void;
}): React.JSX.Element | null {
  const instructions = definition?.instructions?.trim() ?? '';
  const doneWhen = definition?.doneWhen.trim() ?? '';
  const owner = definition?.ownerHint;
  const actions = onComplete !== undefined || onSkip !== undefined;
  if (
    instructions === '' &&
    doneWhen === '' &&
    owner === undefined &&
    !actions
  ) {
    return null;
  }
  return (
    <div className="flex flex-col gap-1.5 pt-1 pb-0.5">
      {instructions === '' ? null : (
        <p
          data-slot="stage-instructions"
          className="m-0 break-words whitespace-pre-wrap text-muted-foreground">
          {instructions}
        </p>
      )}
      {doneWhen === '' ? null : (
        <p data-slot="stage-done-when" className="m-0 break-words">
          <span className="font-medium text-foreground">Done when</span>{' '}
          <span className="text-muted-foreground">{doneWhen}</span>
        </p>
      )}
      {owner === undefined ? null : (
        <p data-slot="stage-owner" className="m-0 text-muted-foreground">
          Usually done by{' '}
          <span className="text-foreground">{agentName(owner)}</span>
        </p>
      )}
      {actions ? (
        <div className="flex flex-wrap gap-1.5 pt-0.5">
          {onComplete === undefined ? null : (
            <Button
              type="button"
              variant="outline"
              size="sm"
              className="h-7 gap-1 px-2 text-xs font-normal has-[>svg]:px-2"
              onClick={onComplete}>
              <Check aria-hidden="true" className="size-3.5 text-success" />
              Mark done…
            </Button>
          )}
          {onSkip === undefined ? null : (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              className="h-7 gap-1 px-2 text-xs font-normal text-muted-foreground has-[>svg]:px-2"
              onClick={onSkip}>
              <SkipForward aria-hidden="true" className="size-3.5" />
              Skip…
            </Button>
          )}
        </div>
      ) : null}
    </div>
  );
}

function toldLine({ woke, hasLead }: StageMoveResultDto): string {
  if (!hasLead) {
    return 'No agent was told: this workflow’s trigger starts none.';
  }
  return woke
    ? 'The lead agent will pick this up.'
    : 'The lead agent sees this on its next turn — send it a message to continue.';
}
