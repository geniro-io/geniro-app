let seq = 0;
function item(kind: ChatItem['kind'], payload: unknown): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    nodeId: null,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function makeBlock({
  withResult = true,
  stopped = false,
  failed = false,
}: {
  /** The launching Task tool returned. */
  withResult?: boolean;
  /** Its turn ended without the Task tool ever returning. */
  stopped?: boolean;
  /** It returned, but with `isError`. */
  failed?: boolean;
} = {}): SubagentBlockEntry {
  const items: ChatItem[] = [
    item('tool_call', {
      id: 'task-1',
      name: 'Task',
      input: {
        subagent_type: 'code-reviewer',
        description: 'Review the diff',
        prompt: 'Look for off-by-one errors.',
      },
    }),
    item('message', {
      text: 'reading the diff now',
      parentToolUseId: 'task-1',
    }),
    // A reasoning row, so the FOURTH caption surface (`TranscriptItem`'s
    // 'sub-agent thinking') and `subagentSteps`' `thought` arm are both
    // reachable from this fixture.
    item('reasoning', {
      text: 'the loop bound looks suspect',
      parentToolUseId: 'task-1',
    }),
    item('tool_call', {
      id: 'g1',
      name: 'Grep',
      input: { pattern: 'idx <=' },
      parentToolUseId: 'task-1',
    }),
    item('tool_result', {
      id: 'g1',
      name: null,
      result: 'two hits',
      parentToolUseId: 'task-1',
    }),
  ];
  if (stopped) {
    // The turn ends with the delegate's tool never having returned.
    items.push(item('turn_complete', {}));
  } else if (withResult) {
    items.push(
      item('tool_result', {
        id: 'task-1',
        name: null,
        result: failed
          ? 'the delegate could not finish'
          : 'Found one off-by-one in parse().',
        isError: failed,
      }),
      item('turn_complete', {}),
    );
  }
  const blocks = collectSubagentBlocks(
    buildTurnBlocks(buildSubagentBlocks(groupTranscript(items), items)),
  );
  const block = blocks[0];
  if (!block) {
    throw new Error('expected a sub-agent block');
  }
  return block;
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function disclosure(): HTMLButtonElement | null {
  return container.querySelector(
    '[data-role="subagent-block"] button[aria-expanded]',
  );
}

/**
 * The block's status PILL — which only two statuses get. `running` and `done`
 * are a spinner and a check now (the pill on every settled delegate was the
 * loudest thing in a run of them), so this returning null is itself a fact
 * some tests assert.
 */
function badge(): Element | null {
  return container.querySelector(
    '[data-role="block-shell"] [data-slot="block-status-badge"]',
  );
}

describe('SubagentBlock', () => {
  it('renders the delegate as a block that is COLLAPSED by default', () => {
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={makeBlock()}
          soloAgent
          chatAgentName="claude"
        />,
      ),
    );

    // The enclosure and its identity read without opening anything.
    expect(
      container.querySelector('[data-role="subagent-block"]'),
    ).not.toBeNull();
    expect(container.textContent).toContain('Sub-agent');
    expect(container.textContent).toContain('Review the diff');
    expect(disclosure()?.getAttribute('aria-expanded')).toBe('false');
    // The delegate's conversation is NOT in the flow until asked for — the
    // requirement this block exists to satisfy.
    expect(container.textContent).not.toContain('reading the diff now');
    expect(container.textContent).not.toContain('Look for off-by-one errors.');
  });

  it('expands into the delegate own thread — its ask, its work, its result', () => {
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={makeBlock()}
          soloAgent
          chatAgentName="claude"
        />,
      ),
    );
    act(() =>
      disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true })),
    );

    expect(container.textContent).toContain('Task for Review the diff');
    expect(container.textContent).toContain('Look for off-by-one errors.');
    expect(container.textContent).toContain('reading the diff now');
    expect(container.textContent).toContain('Result from Review the diff');
    expect(container.textContent).toContain('Found one off-by-one in parse().');
  });

  it('does not repeat the "sub-agent" caption on ANY of the four surfaces inside its enclosure', () => {
    // Four sites used to say it independently — TurnBlock's block caption,
    // ToolGroup's row caption, and TranscriptItem's two (a message row's
    // `sub-agent` and a reasoning row's `sub-agent thinking`). Inside a block
    // whose header already names the delegate they are the same fact over and
    // over, so all four stand down via NestedThreadContext. Asserted across
    // surfaces, because a single `data-role` query passes while three still
    // fire — the fixture carries a message, a reasoning row and a tool group
    // precisely so every one of them is reachable here.
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={makeBlock()}
          soloAgent
          chatAgentName="claude"
        />,
      ),
    );
    act(() =>
      disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true })),
    );

    // TurnBlock's caption.
    expect(container.querySelector('[data-role="subagent-label"]')).toBeNull();
    // ToolGroup's and TranscriptItem's read as literal lower-case text; the
    // eyebrow reads "Sub-agent", so case is what discriminates them.
    expect(container.textContent).toContain('Sub-agent');
    expect(container.textContent).not.toContain('sub-agent');
  });

  it('still captions a delegate rendered OUTSIDE an enclosure', () => {
    // The other half of the promise above: the captions stand down because of
    // the enclosure, not because they were deleted. Without this, removing the
    // captions outright would leave the suite green.
    const block = makeBlock();
    const inner = block.entries[0];
    if (!inner) {
      throw new Error('expected the block to hold the delegate thread');
    }
    act(() => root.render(<TranscriptEntryView entry={inner} soloAgent />));

    expect(
      container.querySelector('[data-role="subagent-label"]'),
    ).not.toBeNull();
  });

  it('spins while the delegate is still out, and stops once it reports back', () => {
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={makeBlock({ withResult: false })}
          soloAgent
        />,
      ),
    );
    expect(container.querySelector('svg.animate-spin')).not.toBeNull();
    expect(container.textContent).toContain('running');

    act(() =>
      root.render(<TranscriptEntryView entry={makeBlock()} soloAgent />),
    );
    expect(container.querySelector('svg.animate-spin')).toBeNull();
    expect(container.textContent).toContain('completed');
  });

  it('stops spinning once the run itself has stopped, not only once its turn ended', () => {
    // `closed` alone cannot answer this. It asks whether a turn-ending row
    // arrived AFTER the delegate's last row, and a cancelled run is exactly
    // where that ordering breaks: the CLI's trailing sub-agent lines land after
    // the `turn_cancelled` row, so nothing in the item stream is ever "after"
    // them and the enclosure pulses on a run that has stopped for good. The
    // tool rows nested inside it already take the run-settled signal
    // (`ToolGroup`); the enclosure drawn around them does not read it at all.
    const block = makeBlock({ withResult: false });

    act(() =>
      root.render(
        <RunSettledContext.Provider value={null}>
          <TranscriptEntryView entry={block} soloAgent />
        </RunSettledContext.Provider>,
      ),
    );
    expect(container.querySelector('svg.animate-spin')).not.toBeNull();
    expect(container.textContent).toContain('running');

    act(() =>
      root.render(
        <RunSettledContext.Provider value={1_000}>
          <TranscriptEntryView entry={block} soloAgent />
        </RunSettledContext.Provider>,
      ),
    );
    expect(container.querySelector('svg.animate-spin')).toBeNull();
    expect(container.textContent).not.toContain('running');
  });

  it('keeps spinning for a delegate whose rows are NEWER than the settle', () => {
    // The reported defect: "I can see stopped status - but it's incorrect, in
    // fact they continue working." The run row settling painted every
    // unreturned delegate in the chat `stopped` at once, regardless of whether
    // that delegate was still writing. It routinely was — measured on the
    // author's own `geniro.db`, run `f42bfe2d` took 1346 further delegate rows
    // after the item that settled it, and every block whose Task call had not
    // yet returned read `stopped` for as long as that lasted.
    //
    // The transcript is the evidence and the status is the claim, so where they
    // disagree the evidence wins.
    const block = { ...makeBlock({ withResult: false }), lastRowAt: 2_000 };

    act(() =>
      root.render(
        <RunSettledContext.Provider value={1_000}>
          <TranscriptEntryView entry={block} soloAgent />
        </RunSettledContext.Provider>,
      ),
    );

    expect(container.querySelector('svg.animate-spin')).not.toBeNull();
    expect(container.textContent).toContain('running');
    expect(container.textContent).not.toContain('stopped before');
  });

  it('ends a WORKING delegate’s thread with the same live row the main flow uses', () => {
    // The reported ask: "for subagent popup i wanna have same thinking system
    // message". A delegate's thread stopped at whatever it last said, so one
    // that was thinking looked exactly like one that had wedged — while the
    // main conversation has had a live row for that stretch all along.
    act(() =>
      root.render(
        <RunSettledContext.Provider value={null}>
          <TranscriptEntryView
            entry={makeBlock({ withResult: false })}
            soloAgent
          />
        </RunSettledContext.Provider>,
      ),
    );
    // Open the block — the row lives in the thread, which is what the popup
    // renders too.
    act(() => {
      disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });

    expect(container.textContent).toContain('Working…');
  });

  it('shows NO live row once the delegate has returned', () => {
    // A finished thread ending in a spinner claims work that is over — the same
    // defect the header's own status rules exist to prevent.
    act(() =>
      root.render(<TranscriptEntryView entry={makeBlock()} soloAgent />),
    );
    act(() => {
      disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });

    expect(container.textContent).toContain('Found one off-by-one');
    expect(container.textContent).not.toContain('Working…');
  });

  it('does NOT print the run’s activity phrase inside a delegate’s thread', () => {
    // The run's phrase belongs to the PARENT — while a delegate runs it reads
    // "running Agent", which is the very delegation this block IS. Printed
    // here it would have the sub-agent report its own launch as its work.
    act(() =>
      root.render(
        <RunActivityContext.Provider value="running Agent">
          <RunSettledContext.Provider value={null}>
            <TranscriptEntryView
              entry={makeBlock({ withResult: false })}
              soloAgent
            />
          </RunSettledContext.Provider>
        </RunActivityContext.Provider>,
      ),
    );
    act(() => {
      disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });

    expect(container.textContent).toContain('Working…');
    expect(container.textContent).not.toContain('running Agent');
  });

  it('reports a delegate whose turn ended without it reporting back as stopped', () => {
    // The `stopped` arm end-to-end: `subagentBlockStatus` → `shellStatusOf` →
    // the badge. Dropping `case 'stopped'` falls through to `running` — the
    // stale spinner `closed` exists to end. Read off the badge and the ABSENT
    // spinner rather than a sentence in the body, which is where the status
    // used to be stated a second time.
    act(() =>
      root.render(
        <TranscriptEntryView entry={makeBlock({ stopped: true })} soloAgent />,
      ),
    );

    expect(badge()?.textContent).toBe('cancelled');
    expect(container.querySelector('svg.animate-spin')).toBeNull();

    act(() =>
      disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true })),
    );
    // Opening the thread neither adds a second reading of the status nor
    // changes the one on the header.
    expect(badge()?.textContent).toBe('cancelled');
    expect(container.textContent).not.toContain('is working...');
  });

  it('states a delegate’s tokens and duration on the CLOSED header', () => {
    // REPORTED as "in front of each agent i wanna see amount of
    // tokens/costs/time", against rows reading only `general-purpose · 49
    // tools`. The header is where it has to land: a block is collapsed by
    // default, so a figure that needs a click answers nothing for someone
    // scanning a column of delegates.
    const block: SubagentBlockEntry = {
      ...makeBlock(),
      tokens: 26124,
      durationMs: 2029,
    };
    act(() => root.render(<TranscriptEntryView entry={block} soloAgent />));

    // The disclosure BUTTON specifically — it is the header row, and asserting
    // on it rather than on the block is what makes this a test about the
    // CLOSED state: the same strings under the facts line inside would satisfy
    // a container-wide assertion the moment anything opened the block.
    const header = container.querySelector(
      '[data-role="subagent-block"] button[aria-label^="Show"]',
    );
    expect(header?.textContent).toContain('26.1k tokens');
    expect(header?.textContent).toContain('took 2s');
  });

  it('states a delegate’s COST on the closed header, marked approximate', () => {
    // The third of the three the report asked for, and the only one no CLI
    // states: the daemon derives it from the delegate's own token breakdown at
    // its model's list rate, calibrated against what the CLI charged for that
    // turn. The `≈` is what separates it from the exact per-turn figures this
    // app shows elsewhere, so it is asserted with the number and not beside it.
    const block: SubagentBlockEntry = {
      ...makeBlock(),
      tokens: 29_388,
      durationMs: 1761,
      costUsd: 0.2262808,
    };
    act(() => root.render(<TranscriptEntryView entry={block} soloAgent />));

    const header = container.querySelector(
      '[data-role="subagent-block"] button[aria-label^="Show"]',
    );
    expect(header?.textContent).toContain('≈$0.23');
  });

  it('shows tokens but NO dollars when the cost could not be derived', () => {
    // The required reading of a null cost: a delegate on a model this build
    // has no price for, or one whose turn reported no roll-up to calibrate
    // against, has an UNKNOWN cost — never a zero one. A `$0.00` beside 29k
    // tokens would be the one wrong number this feature could produce.
    const block: SubagentBlockEntry = {
      ...makeBlock(),
      tokens: 29_388,
      costUsd: null,
    };
    act(() => root.render(<TranscriptEntryView entry={block} soloAgent />));

    expect(container.textContent).toContain('29.4k tokens');
    expect(container.textContent).not.toContain('$');
  });

  it('shows no spend at all for a delegate whose CLI measured none', () => {
    // Every CLI but claude reports none of this, and a `— tokens` placeholder
    // on each of twenty delegate rows is noise about a blind spot the reader
    // can do nothing with. `tokens`/`durationMs` are null on `makeBlock`.
    act(() =>
      root.render(<TranscriptEntryView entry={makeBlock()} soloAgent />),
    );

    expect(container.textContent).not.toContain('tokens');
    expect(container.textContent).not.toContain('took ');
  });

  it('reports a delegate whose tool returned an error as failed, not done', () => {
    // `isError` IS on the tool_result payload (event-to-item.ts persists it),
    // so reading the mere presence of a result would paint a failed delegate
    // with the green "done" chip and a success-toned result panel.
    act(() =>
      root.render(
        <TranscriptEntryView entry={makeBlock({ failed: true })} soloAgent />,
      ),
    );

    expect(container.textContent).toContain('failed');
    expect(container.textContent).not.toContain('completed');
  });

  it('offers the detail control only where something can host the dialog', () => {
    // Null context is the honest default: a surface with no provider renders
    // no control rather than one that silently does nothing.
    act(() =>
      root.render(<TranscriptEntryView entry={makeBlock()} soloAgent />),
    );
    expect(
      container.querySelector('[aria-label="Open Review the diff in a panel"]'),
    ).toBeNull();

    const opened: SubagentBlockEntry[] = [];
    act(() =>
      root.render(
        <SubagentDetailContext.Provider value={(b) => opened.push(b)}>
          <TranscriptEntryView entry={makeBlock()} soloAgent />
        </SubagentDetailContext.Provider>,
      ),
    );
    const control = container.querySelector(
      '[aria-label="Open Review the diff in a panel"]',
    );
    expect(control).not.toBeNull();
    // The button IS the hit target — it sits beside the disclosure with no gap,
    // so nothing around it enlarges the target. It carries the `size-6` box
    // rather than the `size-5` one, which is the 24px minimum WCAG 2.5.8 asks
    // for. jsdom loads no stylesheet, so what is asserted is the class the
    // component emits, not a measured box: an equivalent spelling (`h-6 w-6`)
    // would fail this while satisfying the guideline.
    expect(control?.className).toContain('size-6');

    act(() =>
      control?.dispatchEvent(new MouseEvent('click', { bubbles: true })),
    );
    expect(opened).toHaveLength(1);
    expect(opened[0]?.id).toBe('task-1');
    // Pressing it must not also toggle the disclosure it sits inside.
    expect(disclosure()?.getAttribute('aria-expanded')).toBe('false');
  });
});

describe('a delegate whose CLI streams none of its work', () => {
  const REASON =
    'cursor-agent reports the delegation but not the work inside it';

  /**
   * The cursor shape end to end: a `task` tool call the daemon DECLARED as a
   * launch (its title is prose and its input names only the CLI's own tool), a
   * `subagent_info` row carrying the brief, and a result with no text in it.
   */
  function declaredBlock(
    over: Record<string, unknown> = {},
    /**
     * What the launching call was answered WITH.
     *
     * The default is the pre-fix shape, still sitting in transcripts written
     * before the adapter declared `resultIsBookkeeping`: the CLI's
     * `{durationMs, isBackground}` reaching the block as a result. `null` is
     * what the daemon writes today — verified in the running app, where a real
     * cursor delegate's `tool_result` row carries `"result":null`.
     */
    resultBody: unknown = { durationMs: 13075, isBackground: false },
  ): SubagentBlockEntry {
    const items: ChatItem[] = [
      item('tool_call', {
        id: 'toolu_1',
        name: 'Task: Subagent task',
        input: { _toolName: 'task' },
      }),
      item('subagent_info', {
        id: 'toolu_1',
        label: 'List files in directory',
        kind: null,
        prompt: 'list every file in the workspace root',
        model: 'claude-opus-5-thinking-high',
        durationMs: 13075,
        stepsUnavailableReason: REASON,
        ...over,
      }),
      item('tool_result', {
        id: 'toolu_1',
        name: null,
        result: resultBody,
      }),
    ];
    const block = collectSubagentBlocks(
      buildTurnBlocks(buildSubagentBlocks(groupTranscript(items), items)),
    )[0];
    if (!block) {
      throw new Error('expected a sub-agent block');
    }
    return block;
  }

  it('says WHY its thread is empty, instead of that it did nothing', () => {
    // The line this replaces — "This sub-agent has not done anything yet" — was
    // a claim about the delegate, printed for one that had just spent thirteen
    // seconds working. Reverting the reason to a generic empty state fails here.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={declaredBlock()} chatAgentName="cursor" />
        </Dialog>,
      ),
    );

    expect(container.textContent).toContain(REASON);
    expect(container.textContent).not.toContain('has not done anything yet');
    // Stated ONCE. It used to be printed under both a `Timeline` heading and a
    // `Conversation` one; neither heading exists any more.
    expect(container.textContent).not.toContain('Timeline');
    expect(
      container.querySelectorAll('[data-role="subagent-steps-missing"]'),
    ).toHaveLength(1);
  });

  it('says the sub-agent ENDED, which nothing else in its body does', () => {
    // REPORTED as "cursor agent doesn't seem to have success message". Its
    // body is the brief, the model and the steps-unavailable sentence — none
    // of which changes when the work finishes — so a delegate that ran for a
    // minute read exactly like one that did nothing. Deleting the line puts
    // the ending back on a 14px header glyph alone and fails here.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail
            block={declaredBlock({}, null)}
            chatAgentName="cursor"
          />
        </Dialog>,
      ),
    );

    const ended = container.querySelector('[data-role="subagent-ended"]');
    expect(ended).not.toBeNull();
    // The block vocabulary's own word, so this line, the header glyph and the
    // panel row cannot spell one ending three ways.
    expect(ended?.textContent).toContain('completed');
  });

  it('withholds the ending line while the delegate is still working', () => {
    // A launch with no result yet: the live row above it is what says what is
    // happening, and an "ended" line beside a spinner is the card
    // contradicting itself.
    const RUNNING_ITEMS: ChatItem[] = [
      item('tool_call', {
        id: 'toolu_2',
        name: 'Task: Subagent task',
        input: { _toolName: 'task' },
      }),
      item('subagent_info', {
        id: 'toolu_2',
        label: 'Still going',
        kind: null,
        prompt: 'take your time',
        model: null,
        durationMs: null,
        stepsUnavailableReason: REASON,
      }),
    ];
    const running = collectSubagentBlocks(
      buildTurnBlocks(
        buildSubagentBlocks(groupTranscript(RUNNING_ITEMS), RUNNING_ITEMS),
      ),
    )[0];
    if (!running) {
      throw new Error('expected a sub-agent block');
    }

    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={running} chatAgentName="cursor" />
        </Dialog>,
      ),
    );

    expect(container.querySelector('[data-role="subagent-ended"]')).toBeNull();
  });

  it('withholds it from a delegate whose own work already shows the ending', () => {
    // The footer this thread removed once, for repeating what the header says
    // better — a delegate that streamed its steps ends on those steps, and one
    // whose answer is printed ends on the answer.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={makeBlock()} chatAgentName="claude" />
        </Dialog>,
      ),
    );

    expect(container.querySelector('[data-role="subagent-ended"]')).toBeNull();
  });

  it('states the model and the duration, the only substance the CLI gives', () => {
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={declaredBlock()} chatAgentName="cursor" />
        </Dialog>,
      ),
    );

    const facts = container.querySelector('[data-role="subagent-facts"]');
    expect(facts?.textContent).toContain('claude-opus-5-thinking-high');
    expect(facts?.textContent).toContain('took 13s');
    // And the brief it was given, which is the other thing only this channel
    // carries — the launching tool call's own arguments never held it.
    expect(container.textContent).toContain(
      'list every file in the workspace root',
    );
  });

  it('keeps the generic empty state for a delegate that simply has not spoken YET', () => {
    // The distinction the reason exists for: a CLI that streams its delegates
    // (claude) sends no reason, so an empty thread there means "not yet" and
    // must keep saying so. It survived the timeline's removal by moving into
    // the same line the reason uses.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail
            block={{
              ...makeBlock({ withResult: false }),
              entries: [],
              returned: false,
            }}
            chatAgentName="claude"
          />
        </Dialog>,
      ),
    );

    expect(container.textContent).toContain('has not done anything yet');
  });

  /**
   * A BACKGROUNDED delegate, as claude really launches one: the `Agent` call is
   * answered within the second with a launch acknowledgement, the daemon
   * announces the open background unit, and the delegate's own rows arrive
   * afterwards — or, at the moment of the report, not yet.
   *
   * The acknowledgement text is the one measured on the user's own ledger,
   * where all 23 of them carry it verbatim.
   */
  function backgroundBlock({
    withRows = false,
    open = true,
  }: { withRows?: boolean; open?: boolean } = {}): SubagentBlockEntry {
    const items: ChatItem[] = [
      item('tool_call', {
        id: 'task-bg',
        name: 'Agent',
        input: { description: 'Review: optimizations', prompt: 'Look.' },
      }),
      item('tool_result', {
        id: 'task-bg',
        name: null,
        result:
          'Async agent launched successfully. (This tool result is internal metadata — never quote or paste any part of it, including the agentId below, into a user-facing reply.)',
      }),
      item('subagent_info', {
        id: 'task-bg',
        label: null,
        kind: null,
        prompt: null,
        model: null,
        durationMs: null,
        stepsUnavailableReason: null,
        backgroundOpen: open,
      }),
    ];
    if (withRows) {
      items.push(
        item('message', { text: 'looking now', parentToolUseId: 'task-bg' }),
      );
    }
    const block = collectSubagentBlocks(
      buildTurnBlocks(buildSubagentBlocks(groupTranscript(items), items)),
    )[0];
    if (!block) {
      throw new Error('expected a sub-agent block');
    }
    return block;
  }

  it('does not pass a launch acknowledgement off as the delegate’s result', () => {
    // REPORTED as "wrong ... popup", over a card reading "Working… 2m 29s" with
    // "RESULT FROM SUB-AGENT" printed above the launch ack directly beneath it.
    // Worse than merely mislabelled: the text the card was showing is the CLI's
    // own internal metadata, and it says in so many words that it must never be
    // put in front of the user.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={backgroundBlock()} chatAgentName="claude" />
        </Dialog>,
      ),
    );

    expect(container.textContent).not.toContain('Result from');
    expect(container.textContent).toContain('Reply to the launching call');
    // …and the line explaining the empty thread is BACK. It was suppressed by
    // `returned`, which an acknowledgement sets a second after the launch — so
    // it went missing on exactly the delegates whose thread is empty for that
    // reason.
    expect(container.textContent).toContain('has not done anything yet');
  });

  it('still calls it an acknowledgement once the delegate has spoken', () => {
    // The seq test rather than the status one: this delegate's background unit
    // has CLOSED, so it no longer reads as running — but its rows arrived after
    // its call was answered, which is what proves the answer was not its
    // report. Without this arm the falsehood simply moves to the end state,
    // where it is the ordinary one: every finished background delegate.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail
            block={backgroundBlock({ withRows: true, open: false })}
            chatAgentName="claude"
          />
        </Dialog>,
      ),
    );

    expect(container.textContent).toContain('looking now');
    expect(container.textContent).toContain('Reply to the launching call');
    expect(container.textContent).not.toContain('Result from');
  });

  it('does not pass a RESUME receipt off as a delegate’s result either', () => {
    // Transcribed from the user's own ledger, and the exact card in the report:
    // a `SendMessage` to an already-running agent, which the daemon declares
    // background work against — so the fold adopts it as a delegate launch —
    // and whose reply is a routing receipt. It arrives with no description, no
    // prompt, no rows and a settled background unit, so every "did it speak
    // afterwards" test says yes-this-is-its-report. What actually settles it is
    // that the call was never a DELEGATION: `SendMessage` resumes an agent, it
    // does not launch one.
    const items: ChatItem[] = [
      item('tool_call', {
        id: 'toolu_send',
        name: 'SendMessage',
        input: { to: 'a3249b7c8f0b195f8', summary: 'Write the mockup' },
      }),
      item('tool_result', {
        id: 'toolu_send',
        name: null,
        result:
          '{"success":true,"message":"Resuming agent a3249b7","resumedAgentId":"a3249b7c8f0b195f8"}',
      }),
      item('subagent_info', {
        id: 'toolu_send',
        label: null,
        kind: null,
        prompt: null,
        model: null,
        durationMs: null,
        stepsUnavailableReason: null,
        backgroundOpen: false,
      }),
    ];
    const block = collectSubagentBlocks(
      buildTurnBlocks(buildSubagentBlocks(groupTranscript(items), items)),
    )[0]!;

    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={block} chatAgentName="claude" />
        </Dialog>,
      ),
    );

    expect(container.textContent).not.toContain('Result from');
    expect(container.textContent).toContain('Reply to the launching call');
  });

  it('withholds the generic line from a delegate that RETURNED with no thread', () => {
    // Beside a result, "has not done anything yet" is simply false — it was
    // legible only under the `Timeline` heading it used to sit below, where it
    // meant "no steps recorded", and that heading is gone.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail
            block={{ ...makeBlock(), entries: [] }}
            chatAgentName="claude"
          />
        </Dialog>,
      ),
    );

    expect(container.textContent).toContain('Found one off-by-one in parse().');
    expect(container.textContent).not.toContain('has not done anything yet');
  });

  it('renders no facts line at all when the CLI named neither', () => {
    // Every claude delegate: its work IS the thread, so a metadata line would
    // only repeat the header.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={makeBlock()} chatAgentName="claude" />
        </Dialog>,
      ),
    );

    expect(container.querySelector('[data-role="subagent-facts"]')).toBeNull();
  });

  it('shows the reason inline too, without opening the dialog', () => {
    // The block is collapsed by default, so the reason lives inside it — what
    // must NOT happen is the card claiming a conversation that opens onto
    // nothing at all.
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={declaredBlock()}
          soloAgent
          chatAgentName="cursor"
        />,
      ),
    );
    const toggle = disclosure();
    expect(toggle).not.toBeNull();
    act(() => toggle?.click());

    expect(
      container.querySelector('[data-role="subagent-steps-missing"]')
        ?.textContent,
    ).toContain(REASON);
  });
});

describe('SubagentDetail', () => {
  function openDetail(): void {
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={makeBlock()} chatAgentName="claude" />
        </Dialog>,
      ),
    );
  }

  it('is the conversation, open — and needs no expanding', () => {
    // The dialog was opened to READ the thread, unlike the inline block.
    openDetail();
    expect(container.textContent).toContain('reading the diff now');
    expect(container.textContent).toContain('Found one off-by-one in parse().');
  });

  it('carries no timeline — the messages ARE the record of what it did', () => {
    // It was a second reading of the very entries below it, one line per tool
    // call and message, sitting between the reader and the conversation they
    // opened the dialog for.
    openDetail();
    expect(
      container.querySelector('[data-role="subagent-timeline"]'),
    ).toBeNull();
    expect(container.textContent).not.toContain('Timeline');
  });

  it('heads its one section with nothing — the dialog title already names it', () => {
    openDetail();
    expect(container.textContent).not.toContain('Conversation');
  });
});
