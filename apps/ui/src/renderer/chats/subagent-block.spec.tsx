import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { Dialog } from '../components/ui/dialog';
import { RunSettledContext } from './live-row';
import { SubagentDetail, subagentSteps } from './subagent-block';
import { SubagentDetailContext } from './subagent-context';
import { TranscriptEntryView } from './transcript-entry';
import {
  buildSubagentBlocks,
  buildTurnBlocks,
  collectSubagentBlocks,
  groupTranscript,
  type SubagentBlockEntry,
} from './transcript-groups';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let seq = 0;
function item(kind: ChatItem['kind'], payload: unknown): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    nodeId: null,
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function makeBlock({
  withResult = true,
  stopped = false,
  failed = false,
}: {
  /** The launching Task tool returned. */
  withResult?: boolean;
  /** Its turn ended without the Task tool ever returning. */
  stopped?: boolean;
  /** It returned, but with `isError`. */
  failed?: boolean;
} = {}): SubagentBlockEntry {
  const items: ChatItem[] = [
    item('tool_call', {
      id: 'task-1',
      name: 'Task',
      input: {
        subagent_type: 'code-reviewer',
        description: 'Review the diff',
        prompt: 'Look for off-by-one errors.',
      },
    }),
    item('message', {
      text: 'reading the diff now',
      parentToolUseId: 'task-1',
    }),
    // A reasoning row, so the FOURTH caption surface (`TranscriptItem`'s
    // 'sub-agent thinking') and `subagentSteps`' `thought` arm are both
    // reachable from this fixture.
    item('reasoning', {
      text: 'the loop bound looks suspect',
      parentToolUseId: 'task-1',
    }),
    item('tool_call', {
      id: 'g1',
      name: 'Grep',
      input: { pattern: 'idx <=' },
      parentToolUseId: 'task-1',
    }),
    item('tool_result', {
      id: 'g1',
      name: null,
      result: 'two hits',
      parentToolUseId: 'task-1',
    }),
  ];
  if (stopped) {
    // The turn ends with the delegate's tool never having returned.
    items.push(item('turn_complete', {}));
  } else if (withResult) {
    items.push(
      item('tool_result', {
        id: 'task-1',
        name: null,
        result: failed
          ? 'the delegate could not finish'
          : 'Found one off-by-one in parse().',
        isError: failed,
      }),
      item('turn_complete', {}),
    );
  }
  const blocks = collectSubagentBlocks(
    buildTurnBlocks(buildSubagentBlocks(groupTranscript(items), items)),
  );
  const block = blocks[0];
  if (!block) {
    throw new Error('expected a sub-agent block');
  }
  return block;
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function disclosure(): HTMLButtonElement | null {
  return container.querySelector(
    '[data-role="subagent-block"] button[aria-expanded]',
  );
}

describe('SubagentBlock', () => {
  it('renders the delegate as a block that is COLLAPSED by default', () => {
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={makeBlock()}
          soloAgent
          chatAgentName="claude"
        />,
      ),
    );

    // The enclosure and its identity read without opening anything.
    expect(
      container.querySelector('[data-role="subagent-block"]'),
    ).not.toBeNull();
    expect(container.textContent).toContain('Sub-agent');
    expect(container.textContent).toContain('Review the diff');
    expect(disclosure()?.getAttribute('aria-expanded')).toBe('false');
    // The delegate's conversation is NOT in the flow until asked for — the
    // requirement this block exists to satisfy.
    expect(container.textContent).not.toContain('reading the diff now');
    expect(container.textContent).not.toContain('Look for off-by-one errors.');
  });

  it('expands into the delegate own thread — its ask, its work, its result', () => {
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={makeBlock()}
          soloAgent
          chatAgentName="claude"
        />,
      ),
    );
    act(() =>
      disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true })),
    );

    expect(container.textContent).toContain('Task for Review the diff');
    expect(container.textContent).toContain('Look for off-by-one errors.');
    expect(container.textContent).toContain('reading the diff now');
    expect(container.textContent).toContain('Result from Review the diff');
    expect(container.textContent).toContain('Found one off-by-one in parse().');
  });

  it('does not repeat the "sub-agent" caption on ANY of the four surfaces inside its enclosure', () => {
    // Four sites used to say it independently — TurnBlock's block caption,
    // ToolGroup's row caption, and TranscriptItem's two (a message row's
    // `sub-agent` and a reasoning row's `sub-agent thinking`). Inside a block
    // whose header already names the delegate they are the same fact over and
    // over, so all four stand down via NestedThreadContext. Asserted across
    // surfaces, because a single `data-role` query passes while three still
    // fire — the fixture carries a message, a reasoning row and a tool group
    // precisely so every one of them is reachable here.
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={makeBlock()}
          soloAgent
          chatAgentName="claude"
        />,
      ),
    );
    act(() =>
      disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true })),
    );

    // TurnBlock's caption.
    expect(container.querySelector('[data-role="subagent-label"]')).toBeNull();
    // ToolGroup's and TranscriptItem's read as literal lower-case text; the
    // eyebrow reads "Sub-agent", so case is what discriminates them.
    expect(container.textContent).toContain('Sub-agent');
    expect(container.textContent).not.toContain('sub-agent');
  });

  it('still captions a delegate rendered OUTSIDE an enclosure', () => {
    // The other half of the promise above: the captions stand down because of
    // the enclosure, not because they were deleted. Without this, removing the
    // captions outright would leave the suite green.
    const block = makeBlock();
    const inner = block.entries[0];
    if (!inner) {
      throw new Error('expected the block to hold the delegate thread');
    }
    act(() => root.render(<TranscriptEntryView entry={inner} soloAgent />));

    expect(
      container.querySelector('[data-role="subagent-label"]'),
    ).not.toBeNull();
  });

  it('spins while the delegate is still out, and stops once it reports back', () => {
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={makeBlock({ withResult: false })}
          soloAgent
        />,
      ),
    );
    expect(container.querySelector('svg.animate-spin')).not.toBeNull();
    expect(container.textContent).toContain('running');

    act(() =>
      root.render(<TranscriptEntryView entry={makeBlock()} soloAgent />),
    );
    expect(container.querySelector('svg.animate-spin')).toBeNull();
    expect(container.textContent).toContain('done');
  });

  it('stops spinning once the run itself has stopped, not only once its turn ended', () => {
    // `closed` alone cannot answer this. It asks whether a turn-ending row
    // arrived AFTER the delegate's last row, and a cancelled run is exactly
    // where that ordering breaks: the CLI's trailing sub-agent lines land after
    // the `turn_cancelled` row, so nothing in the item stream is ever "after"
    // them and the enclosure pulses on a run that has stopped for good. The
    // tool rows nested inside it already take the run-settled signal
    // (`ToolGroup`); the enclosure drawn around them does not read it at all.
    const block = makeBlock({ withResult: false });

    act(() =>
      root.render(
        <RunSettledContext.Provider value={null}>
          <TranscriptEntryView entry={block} soloAgent />
        </RunSettledContext.Provider>,
      ),
    );
    expect(container.querySelector('svg.animate-spin')).not.toBeNull();
    expect(container.textContent).toContain('running');

    act(() =>
      root.render(
        <RunSettledContext.Provider value={1_000}>
          <TranscriptEntryView entry={block} soloAgent />
        </RunSettledContext.Provider>,
      ),
    );
    expect(container.querySelector('svg.animate-spin')).toBeNull();
    expect(container.textContent).not.toContain('running');
  });

  it('keeps spinning for a delegate whose rows are NEWER than the settle', () => {
    // The reported defect: "I can see stopped status - but it's incorrect, in
    // fact they continue working." The run row settling painted every
    // unreturned delegate in the chat `stopped` at once, regardless of whether
    // that delegate was still writing. It routinely was — measured on the
    // author's own `geniro.db`, run `f42bfe2d` took 1346 further delegate rows
    // after the item that settled it, and every block whose Task call had not
    // yet returned read `stopped` for as long as that lasted.
    //
    // The transcript is the evidence and the status is the claim, so where they
    // disagree the evidence wins.
    const block = { ...makeBlock({ withResult: false }), lastRowAt: 2_000 };

    act(() =>
      root.render(
        <RunSettledContext.Provider value={1_000}>
          <TranscriptEntryView entry={block} soloAgent />
        </RunSettledContext.Provider>,
      ),
    );

    expect(container.querySelector('svg.animate-spin')).not.toBeNull();
    expect(container.textContent).toContain('running');
    expect(container.textContent).not.toContain('stopped before');
  });

  it('reports a delegate whose turn ended without it reporting back as stopped', () => {
    // The `stopped` arm end-to-end: `subagentBlockStatus` → `shellStatusOf` →
    // the badge and the in-body line. Dropping `case 'stopped'` falls through
    // to `running` — the stale spinner `closed` exists to end.
    act(() =>
      root.render(
        <TranscriptEntryView entry={makeBlock({ stopped: true })} soloAgent />,
      ),
    );

    expect(container.textContent).toContain('stopped');
    expect(container.querySelector('svg.animate-spin')).toBeNull();

    act(() =>
      disclosure()?.dispatchEvent(new MouseEvent('click', { bubbles: true })),
    );
    expect(container.textContent).toContain('stopped before');
    expect(container.textContent).not.toContain('is working...');
  });

  it('reports a delegate whose tool returned an error as failed, not done', () => {
    // `isError` IS on the tool_result payload (event-to-item.ts persists it),
    // so reading the mere presence of a result would paint a failed delegate
    // with the green "done" chip and a success-toned result panel.
    act(() =>
      root.render(
        <TranscriptEntryView entry={makeBlock({ failed: true })} soloAgent />,
      ),
    );

    expect(container.textContent).toContain('error');
    expect(container.textContent).not.toContain('done');
  });

  it('offers the detail control only where something can host the dialog', () => {
    // Null context is the honest default: a surface with no provider renders
    // no control rather than one that silently does nothing.
    act(() =>
      root.render(<TranscriptEntryView entry={makeBlock()} soloAgent />),
    );
    expect(
      container.querySelector('[aria-label="Open Review the diff in a panel"]'),
    ).toBeNull();

    const opened: SubagentBlockEntry[] = [];
    act(() =>
      root.render(
        <SubagentDetailContext.Provider value={(b) => opened.push(b)}>
          <TranscriptEntryView entry={makeBlock()} soloAgent />
        </SubagentDetailContext.Provider>,
      ),
    );
    const control = container.querySelector(
      '[aria-label="Open Review the diff in a panel"]',
    );
    expect(control).not.toBeNull();

    act(() =>
      control?.dispatchEvent(new MouseEvent('click', { bubbles: true })),
    );
    expect(opened).toHaveLength(1);
    expect(opened[0]?.id).toBe('task-1');
    // Pressing it must not also toggle the disclosure it sits inside.
    expect(disclosure()?.getAttribute('aria-expanded')).toBe('false');
  });
});

describe('subagentSteps', () => {
  it('lists what the delegate DID, in order, from its own entries', () => {
    const steps = subagentSteps(makeBlock());
    expect(steps.map((step) => step.what)).toEqual(['said', 'thought', 'Grep']);
    expect(steps[0]?.detail).toBe('reading the diff now');
    expect(steps[1]?.detail).toBe('the loop bound looks suspect');
    expect(steps[2]?.detail).toContain('idx <=');
  });

  it('reads an error step off the payload key the daemon actually writes', () => {
    // `message` is an unverified payload key on a new exported function: if it
    // is wrong the timeline renders a blank error step and nothing moves.
    const block = makeBlock();
    const steps = subagentSteps({
      ...block,
      entries: [
        {
          type: 'item',
          item: item('error', {
            message: 'the delegate hit a wall',
            parentToolUseId: 'task-1',
          }),
        },
      ],
    });
    expect(steps).toHaveLength(1);
    expect(steps[0]?.what).toBe('error');
    expect(steps[0]?.detail).toBe('the delegate hit a wall');
  });

  it('describes no work for a delegate that has not produced any', () => {
    const empty = { ...makeBlock(), entries: [] };
    expect(subagentSteps(empty)).toEqual([]);
  });
});

describe('a delegate whose CLI streams none of its work', () => {
  const REASON =
    'cursor-agent reports the delegation but not the work inside it';

  /**
   * The cursor shape end to end: a `task` tool call the daemon DECLARED as a
   * launch (its title is prose and its input names only the CLI's own tool), a
   * `subagent_info` row carrying the brief, and a result with no text in it.
   */
  function declaredBlock(
    over: Record<string, unknown> = {},
  ): SubagentBlockEntry {
    const items: ChatItem[] = [
      item('tool_call', {
        id: 'toolu_1',
        name: 'Task: Subagent task',
        input: { _toolName: 'task' },
      }),
      item('subagent_info', {
        id: 'toolu_1',
        label: 'List files in directory',
        kind: null,
        prompt: 'list every file in the workspace root',
        model: 'claude-opus-5-thinking-high',
        durationMs: 13075,
        stepsUnavailableReason: REASON,
        ...over,
      }),
      item('tool_result', {
        id: 'toolu_1',
        name: null,
        result: { durationMs: 13075, isBackground: false },
      }),
    ];
    const block = collectSubagentBlocks(
      buildTurnBlocks(buildSubagentBlocks(groupTranscript(items), items)),
    )[0];
    if (!block) {
      throw new Error('expected a sub-agent block');
    }
    return block;
  }

  it('says WHY its thread is empty, instead of that it did nothing', () => {
    // The line this replaces — "This sub-agent has not done anything yet" — was
    // a claim about the delegate, printed for one that had just spent thirteen
    // seconds working. Reverting the reason to a generic empty state fails here.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={declaredBlock()} chatAgentName="cursor" />
        </Dialog>,
      ),
    );

    expect(container.textContent).toContain(REASON);
    expect(container.textContent).not.toContain('has not done anything yet');
    // No Timeline heading either: there is nothing to sequence, so the split
    // would be two headings over one sentence — printed twice.
    expect(container.textContent).not.toContain('Timeline');
    expect(container.textContent).toContain('Conversation');
  });

  it('states the model and the duration, the only substance the CLI gives', () => {
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={declaredBlock()} chatAgentName="cursor" />
        </Dialog>,
      ),
    );

    const facts = container.querySelector('[data-role="subagent-facts"]');
    expect(facts?.textContent).toContain('claude-opus-5-thinking-high');
    expect(facts?.textContent).toContain('took 13s');
    // And the brief it was given, which is the other thing only this channel
    // carries — the launching tool call's own arguments never held it.
    expect(container.textContent).toContain(
      'list every file in the workspace root',
    );
  });

  it('keeps the generic empty state for a delegate that simply has not spoken YET', () => {
    // The distinction the reason exists for: a CLI that streams its delegates
    // (claude) sends no reason, so an empty thread there means "not yet" and
    // must keep saying so.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail
            block={{ ...makeBlock(), entries: [] }}
            chatAgentName="claude"
          />
        </Dialog>,
      ),
    );

    expect(container.textContent).toContain('has not done anything yet');
    expect(container.textContent).toContain('Timeline');
  });

  it('renders no facts line at all when the CLI named neither', () => {
    // Every claude delegate: its work IS the thread, so a metadata line would
    // only repeat the header.
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={makeBlock()} chatAgentName="claude" />
        </Dialog>,
      ),
    );

    expect(container.querySelector('[data-role="subagent-facts"]')).toBeNull();
  });

  it('shows the reason inline too, without opening the dialog', () => {
    // The block is collapsed by default, so the reason lives inside it — what
    // must NOT happen is the card claiming a conversation that opens onto
    // nothing at all.
    act(() =>
      root.render(
        <TranscriptEntryView
          entry={declaredBlock()}
          soloAgent
          chatAgentName="cursor"
        />,
      ),
    );
    const toggle = disclosure();
    expect(toggle).not.toBeNull();
    act(() => toggle?.click());

    expect(
      container.querySelector('[data-role="subagent-steps-missing"]')
        ?.textContent,
    ).toContain(REASON);
  });
});

describe('SubagentDetail', () => {
  it('shows the timeline AND the conversation, both open', () => {
    act(() =>
      root.render(
        <Dialog open onClose={() => undefined} title="Sub-agent">
          <SubagentDetail block={makeBlock()} chatAgentName="claude" />
        </Dialog>,
      ),
    );

    expect(container.textContent).toContain('Timeline');
    expect(
      container.querySelector('[data-role="subagent-timeline"]'),
    ).not.toBeNull();
    expect(container.textContent).toContain('Grep');

    // The conversation is the SAME thread the inline block shows — and unlike
    // there, it needs no expanding: the dialog was opened to read it.
    expect(container.textContent).toContain('Conversation');
    expect(container.textContent).toContain('reading the diff now');
    expect(container.textContent).toContain('Found one off-by-one in parse().');
  });
});
