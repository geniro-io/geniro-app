import type { Meta, StoryObj } from '@storybook/react-vite';
import { userEvent, within } from 'storybook/test';

import type { ItemDto } from '../autogenerated';
import { SubagentBlock } from './subagent-block';
import {
  buildSubagentBlocks,
  collectSubagentBlocks,
  groupTranscript,
  type SubagentBlockEntry,
} from './transcript-groups';

function untrackedBlock(lost: Record<string, unknown>): SubagentBlockEntry {
  const rows: ItemDto[] = [
    {
      id: 'launch',
      runId: 'story',
      memberId: null,
      seq: 1,
      kind: 'tool_call',
      role: null,
      createdAt: '2026-10-18T10:00:00.000Z',
      payload: {
        id: 'review',
        name: 'Task',
        input: {
          description: 'Review the changes',
          prompt: 'Check the changes for bugs.',
        },
      },
    },
    {
      id: 'lost',
      runId: 'story',
      memberId: null,
      seq: 2,
      kind: 'subagent_info',
      role: null,
      createdAt: '2026-10-18T10:01:00.000Z',
      payload: {
        id: 'review',
        backgroundOpen: false,
        backgroundOutcome: 'untracked',
        ...lost,
      },
    },
  ];
  const [block] = collectSubagentBlocks(
    buildSubagentBlocks(groupTranscript(rows), rows),
  );
  if (block === undefined) {
    throw new Error('Missing story subagent');
  }
  return block;
}

const meta = {
  title: 'Chats/SubagentBlock',
  component: SubagentBlock,
  args: { block: untrackedBlock({}) },
  decorators: [(story) => <div className="max-w-2xl p-4">{story()}</div>],
} satisfies Meta<typeof SubagentBlock>;
export default meta;

type Story = StoryObj<typeof meta>;

const open: Story['play'] = async ({ canvasElement }) => {
  await userEvent.click(
    within(canvasElement).getByRole('button', {
      name: /review the changes's conversation/i,
    }),
  );
};

/** Shut: the pill and the one-line summary say what `untracked` means. */
export const Untracked: Story = {};

/** Opened: the warning line under the thread. */
export const UntrackedOpened: Story = { play: open };

/** Its process ended, so the work is over and only the outcome is unknown. */
export const ProcessEnded: Story = {
  args: { block: untrackedBlock({ trackingLost: 'process-ended' }) },
  play: open,
};
