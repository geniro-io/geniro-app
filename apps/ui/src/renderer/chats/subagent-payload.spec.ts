import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  mergeSubagentDeclarations,
  readSubagentDeclaration,
  subagentIdOf,
} from './subagent-payload';

function item(payload: unknown): ChatItem {
  return {
    id: 'i-1',
    runId: 'run-1',
    nodeId: null,
    seq: 1,
    kind: 'tool_call',
    role: 'assistant',
    payload,
    createdAt: 'now',
  };
}

describe('subagentIdOf', () => {
  it('reads the id a sub-agent row was stamped with', () => {
    expect(subagentIdOf(item({ id: 't1', parentToolUseId: 'toulu_abc' }))).toBe(
      'toulu_abc',
    );
  });

  it('reports the main thread when the key is absent', () => {
    expect(subagentIdOf(item({ id: 't1', name: 'Bash' }))).toBeNull();
  });

  // The guards below exist because the payload is `z.unknown()` on the wire:
  // nothing upstream constrains its shape, so each of these is a value that can
  // genuinely arrive. Without a test they read as dead code and get "cleaned up".
  it('reports the main thread for a payload that is not an object', () => {
    expect(subagentIdOf(item(null))).toBeNull();
    expect(subagentIdOf(item('a string payload'))).toBeNull();
    expect(subagentIdOf(item(42))).toBeNull();
  });

  it('reports the main thread for an array payload', () => {
    // `typeof [] === 'object'`, so the object guard alone lets this through.
    expect(subagentIdOf(item([{ parentToolUseId: 'x' }]))).toBeNull();
  });

  it('rejects a non-string id rather than coercing it', () => {
    expect(subagentIdOf(item({ parentToolUseId: 42 }))).toBeNull();
    expect(subagentIdOf(item({ parentToolUseId: true }))).toBeNull();
    expect(subagentIdOf(item({ parentToolUseId: { id: 'x' } }))).toBeNull();
  });

  it('treats an empty id as the main thread', () => {
    // The daemon normalizes `''` to absent at its own read site; this is the
    // reader half of that agreement. Both halves are needed — they are separate
    // implementations of one shape and a disagreement here means one row is
    // attributed to two different threads.
    expect(subagentIdOf(item({ parentToolUseId: '' }))).toBeNull();
  });
});

describe('readSubagentDeclaration — backgroundOutcome', () => {
  const declared = (payload: Record<string, unknown>) =>
    readSubagentDeclaration(item({ id: 'toolu_a', ...payload }));

  it('keeps a word the daemon actually sends', () => {
    // The reader half of the outcome path. Without this the whole renderer end
    // is revertible with a green suite: nothing else exercises it, so the field
    // could be hard-wired to null and a killed delegate would go back to
    // wearing a green check.
    expect(declared({ backgroundOutcome: 'failed' })?.backgroundOutcome).toBe(
      'failed',
    );
    expect(declared({ backgroundOutcome: 'stopped' })?.backgroundOutcome).toBe(
      'stopped',
    );
  });

  it('refuses a word outside the vocabulary rather than passing it through', () => {
    // The payload is `z.unknown()` on the wire, so this is the only thing
    // standing between a daemon that grows a fourth word and a block state the
    // renderer has no rendering for. A defensive branch worth writing is worth
    // a test that enters it.
    expect(declared({ backgroundOutcome: 'killed' })?.backgroundOutcome).toBe(
      null,
    );
    expect(declared({ backgroundOutcome: 7 })?.backgroundOutcome).toBe(null);
    expect(declared({})?.backgroundOutcome).toBe(null);
  });

  it('merges on the same last-non-null rule as its neighbours', () => {
    // A delegate is announced twice — an anchor, then the settle — so an
    // anchor-only row arriving between them must not blank an outcome already
    // reported.
    const anchor = declared({ backgroundOpen: true })!;
    const settle = declared({
      backgroundOpen: false,
      backgroundOutcome: 'stopped',
    })!;

    expect(mergeSubagentDeclarations(anchor, settle).backgroundOutcome).toBe(
      'stopped',
    );
    expect(mergeSubagentDeclarations(settle, anchor).backgroundOutcome).toBe(
      'stopped',
    );
  });
});
