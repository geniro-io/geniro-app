import type { ItemDto as ChatItem } from '../autogenerated';

/**
 * Which sub-agent produced a transcript row, or null for the main thread.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/utils/event-to-item.ts` stamps this
 * key onto the payload, from the `parent_tool_use_id` its claude mapper reads
 * off the stream-json line. An item payload is `z.unknown()` on the wire BY
 * DESIGN — every item kind carries a different shape — so no generated type
 * carries it here and this is an independent reading of the same shape. If the
 * key is renamed on that side it must be renamed here, and vice versa.
 *
 * The value is the id of the tool call that started the sub-agent, which is
 * also the id of the parent row in this very transcript — so it joins a
 * sub-agent's work to the row that launched it, not merely to "some sub-agent".
 *
 * Absent on the overwhelming majority of rows: only a CLI that runs sub-agents
 * on the same stream ever sets it, and only for the lines they produced.
 */
export function subagentIdOf(item: ChatItem): string | null {
  // `unknown`, not the generated field's own type: the payload is untyped on
  // the wire, so the generator gives it `any` and every read off it would
  // otherwise be unchecked.
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const value = (payload as { parentToolUseId?: unknown }).parentToolUseId;
  return typeof value === 'string' && value !== '' ? value : null;
}

/**
 * What a `subagent_info` row says about one delegate.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/utils/event-to-item.ts` writes these
 * keys, on the same footing as `parentToolUseId` above — the payload is
 * `z.unknown()` on the wire BY DESIGN, so this is an independent reading of one
 * shape and a rename on either side must be a rename on both.
 *
 * `id` is the LAUNCHING TOOL CALL's id, not the delegate's own: it is what joins
 * this declaration to the row that started the work. Note it is deliberately NOT
 * `parentToolUseId` — that key means "the delegate produced this row", and this
 * row is one the MAIN thread produced about the delegate.
 */
export interface SubagentDeclaration {
  id: string;
  label: string | null;
  kind: string | null;
  prompt: string | null;
  model: string | null;
  durationMs: number | null;
  /**
   * What the delegate SPENT — every token it used, and how many tools it
   * called — when its CLI reports them.
   *
   * There is no cost beside them, and that is a measurement rather than an
   * omission: the daemon's `subagent_info` doc block records every channel that
   * was probed for one. A price cannot be derived from the turn's own total
   * either, which covers the main thread and all of its delegates at once.
   */
  tokens: number | null;
  toolUses: number | null;
  /**
   * The four token kinds BILLING distinguishes, when the CLI broke the
   * delegate's spend down that far.
   *
   * Separate from {@link tokens} rather than replacing it: the roll-up and the
   * breakdown arrive on different channels at different moments, so a delegate
   * can be described by one, the other, or both.
   */
  inputTokens: number | null;
  outputTokens: number | null;
  cacheReadTokens: number | null;
  cacheCreationTokens: number | null;
  /**
   * What it cost, in dollars — the one figure here that no CLI stated.
   *
   * The daemon derives it from the breakdown above at its model's list rate,
   * calibrated against what the CLI charged for the turn that ran the delegate;
   * `apps/daemon/src/v1/agents/adapters/claude/utils/claude-delegate-cost.utils.ts`
   * holds the measurements. Null whenever any leg of that was missing, which
   * must render as "not shown" and never as a delegate that cost nothing.
   */
  costUsd: number | null;
  stepsUnavailableReason: string | null;
  /**
   * Whether the CLI says this delegate is still working in the BACKGROUND —
   * `null` when it has said nothing, which is every announcement but claude's
   * task lifecycle.
   *
   * It exists because the transcript's own end-of-delegate signal is the
   * launching tool call returning, and a delegate the agent does not wait for
   * returns at once while it runs on. Null therefore has to mean "no claim":
   * treating it as "not running" would be the old reading with extra steps.
   */
  backgroundOpen: boolean | null;
  /**
   * HOW it ended, when the CLI said so — `null` while it is still out, and null
   * for a CLI that reports only THAT the work is over.
   *
   * The companion to {@link backgroundOpen}, and needed for the same reason
   * that field has three states: absent must read as "nothing was said", never
   * as success.
   */
  backgroundOutcome: BackgroundOutcome | null;
}

/**
 * How a delegate ENDED, in the app's own words.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/adapters/adapter.types.ts` declares
 * the same three as `BackgroundUnitOutcome` and each CLI's adapter translates
 * its own vocabulary into them. An item payload is `z.unknown()` on the wire BY
 * DESIGN, so no generated type carries this across and the two sides are
 * independent readings of one shape — add a word there and it must be added
 * here, or the new word reads as {@link isBackgroundOutcome} rejecting it.
 */
export type BackgroundOutcome = 'completed' | 'failed' | 'stopped';

const OUTCOMES: ReadonlySet<string> = new Set<BackgroundOutcome>([
  'completed',
  'failed',
  'stopped',
]);

/** Narrows an unknown payload word to the vocabulary, so no caller casts. */
function isBackgroundOutcome(value: unknown): value is BackgroundOutcome {
  return typeof value === 'string' && OUTCOMES.has(value);
}

/**
 * Read one `subagent_info` row, or null when it names no tool call to anchor to.
 *
 * A CLI may announce the same delegate more than once — an anchor as soon as the
 * launch is recognised, then its brief when that arrives — so a reader must MERGE
 * these rather than take one, preferring the last non-null value per field.
 * {@link mergeSubagentDeclarations} is that rule, in one place, so no caller
 * re-implements it and lets a later anchor-only row blank out a brief.
 */
export function readSubagentDeclaration(
  item: ChatItem,
): SubagentDeclaration | null {
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const record = payload as Record<string, unknown>;
  const id = str(record.id);
  if (id === null) {
    return null;
  }
  return {
    id,
    label: str(record.label),
    kind: str(record.kind),
    prompt: str(record.prompt),
    model: str(record.model),
    durationMs: num(record.durationMs),
    tokens: num(record.tokens),
    inputTokens: num(record.inputTokens),
    outputTokens: num(record.outputTokens),
    cacheReadTokens: num(record.cacheReadTokens),
    cacheCreationTokens: num(record.cacheCreationTokens),
    costUsd: num(record.costUsd),
    toolUses: num(record.toolUses),
    stepsUnavailableReason: str(record.stepsUnavailableReason),
    backgroundOpen:
      typeof record.backgroundOpen === 'boolean' ? record.backgroundOpen : null,
    // Narrowed against the vocabulary, never cast: this is another process's
    // payload, typed `z.unknown()` on the wire, and a word this renderer does
    // not know would otherwise reach the status derivation as a block state
    // that renders nothing.
    backgroundOutcome: isBackgroundOutcome(record.backgroundOutcome)
      ? record.backgroundOutcome
      : null,
  };
}

/** Later non-null fields win; the id is the same by construction. */
export function mergeSubagentDeclarations(
  base: SubagentDeclaration,
  next: SubagentDeclaration,
): SubagentDeclaration {
  return {
    id: base.id,
    label: next.label ?? base.label,
    kind: next.kind ?? base.kind,
    prompt: next.prompt ?? base.prompt,
    model: next.model ?? base.model,
    durationMs: next.durationMs ?? base.durationMs,
    tokens: next.tokens ?? base.tokens,
    toolUses: next.toolUses ?? base.toolUses,
    inputTokens: next.inputTokens ?? base.inputTokens,
    outputTokens: next.outputTokens ?? base.outputTokens,
    cacheReadTokens: next.cacheReadTokens ?? base.cacheReadTokens,
    cacheCreationTokens: next.cacheCreationTokens ?? base.cacheCreationTokens,
    // Same last-non-null rule, and it is what carries the price across the two
    // lines that produce it: the breakdown arrives when the delegate returns,
    // the dollars only when the turn ends and the CLI says what it charged.
    costUsd: next.costUsd ?? base.costUsd,
    stepsUnavailableReason:
      next.stepsUnavailableReason ?? base.stepsUnavailableReason,
    // Same last-non-null rule, and it is what carries the pair: the `started`
    // announcement says `true`, the settle says `false`, and an anchor-only row
    // arriving between them (null) leaves whichever stands.
    backgroundOpen: next.backgroundOpen ?? base.backgroundOpen,
    backgroundOutcome: next.backgroundOutcome ?? base.backgroundOutcome,
  };
}

function str(value: unknown): string | null {
  return typeof value === 'string' && value !== '' ? value : null;
}

/**
 * A figure, or null for anything that is not one.
 *
 * `Number.isFinite` and not a bare `typeof`: the payload crosses JSON, where a
 * `NaN` or an `Infinity` that got in would otherwise render as `NaN tokens` on
 * the block header. Zero IS kept — `0 tool uses` is a real reading about a
 * delegate that called none, and is exactly what the probe measured.
 */
function num(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}
