// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { CliDetection } from '../../shared/contracts';
import { PUBLISHED_IDENTITIES } from '../__tests__/agent-identities';
import { AgentIdentityContext } from '../agent-identity';
import type { AgentIdentityCapability } from '../autogenerated';
import { TargetSelect, type TargetWorkflow } from './target-select';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const WORKFLOWS: TargetWorkflow[] = [{ slug: 'dev-team', name: 'Dev team' }];

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function render(
  props: Partial<React.ComponentProps<typeof TargetSelect>> = {},
  /** Default [] mirrors `AgentIdentityContext`'s own default — no Provider. */
  identities: readonly AgentIdentityCapability[] = [],
): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <AgentIdentityContext.Provider value={identities}>
        <TargetSelect
          value="claude"
          workflows={[]}
          cliDetections={null}
          onChange={() => {}}
          {...props}
        />
      </AgentIdentityContext.Provider>,
    );
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const trigger = (el: HTMLElement): HTMLButtonElement =>
  el.querySelector<HTMLButtonElement>('[data-menu-trigger]')!;

const rowsOf = (el: HTMLElement): HTMLElement[] => [
  ...el.querySelectorAll<HTMLElement>('[role="option"]'),
];

/** The menu's rows — the picker is ours, so they are real DOM, not an OS menu. */
function options(el: HTMLElement): HTMLElement[] {
  act(() => {
    trigger(el).click();
  });
  return rowsOf(el);
}

function typeInSearch(el: HTMLElement, text: string): void {
  const input = el.querySelector<HTMLInputElement>('input')!;
  act(() => {
    // React tracks the DOM value to dedupe change events, so the native setter
    // is what makes `onChange` fire here — taken off the element's own
    // prototype, since the element and the test run in different realms.
    Object.getOwnPropertyDescriptor(
      Object.getPrototypeOf(input) as object,
      'value',
    )!.set!.call(input, text);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

const labelOf = (row: HTMLElement): string | null | undefined =>
  row.querySelector('[data-slot="menu-item-label"]')?.textContent;

function rowLabelled(rows: HTMLElement[], label: string): HTMLElement {
  const row = rows.find((candidate) => labelOf(candidate) === label);
  if (!row) {
    throw new Error(
      `no row labelled "${label}" — the rows read ${JSON.stringify(rows.map(labelOf))}`,
    );
  }
  return row;
}

describe('TargetSelect', () => {
  it('names each agent by the identity the daemon published, not by its binary', () => {
    const rows = options(render({}, PUBLISHED_IDENTITIES));

    expect(rows.map(labelOf)).toEqual(['Claude', 'Cursor', 'Codex']);
  });

  it('draws the published glyph beside each agent', () => {
    const rows = options(render({}, PUBLISHED_IDENTITIES));

    expect(
      rowLabelled(rows, 'Claude').querySelector('svg.lucide-bot'),
    ).not.toBeNull();
    expect(
      rowLabelled(rows, 'Cursor').querySelector('svg.lucide-square-terminal'),
    ).not.toBeNull();
    expect(
      rowLabelled(rows, 'Codex').querySelector('svg.lucide-code'),
    ).not.toBeNull();
  });

  it('reads the same name on the closed chip as on its menu row', () => {
    const el = render({ value: 'cursor-agent' }, PUBLISHED_IDENTITIES);
    const chip = trigger(el).textContent;

    expect(chip).toBe('Cursor');
    expect(options(el).map(labelOf)).toContain(chip);
  });

  it('still finds an agent by its binary name, which its label no longer says', () => {
    const el = render({}, PUBLISHED_IDENTITIES);
    options(el);

    typeInSearch(el, 'cursor-agent');

    expect(rowsOf(el).map(labelOf)).toEqual(['Cursor']);
  });

  it('carries each agent’s binary name on its row, for the hover', () => {
    const rows = options(render({}, PUBLISHED_IDENTITIES));

    expect(rows.map((row) => row.getAttribute('title'))).toEqual([
      'claude',
      'cursor-agent',
      'codex',
    ]);
  });

  it('still reports the KIND when a row is chosen — only what is drawn is renamed', () => {
    const onChange = vi.fn();
    const rows = options(render({ onChange }, PUBLISHED_IDENTITIES));

    act(() => {
      rowLabelled(rows, 'Cursor').click();
    });

    expect(onChange).toHaveBeenCalledWith('cursor-agent');
  });

  it('falls back to the kind and the generic glyph before identities have loaded', () => {
    const el = render({ value: 'cursor-agent' });
    const rows = options(el);

    expect(trigger(el).textContent).toBe('cursor-agent');
    expect(rows.map(labelOf)).toEqual(['claude', 'cursor-agent', 'codex']);
    for (const row of rows) {
      expect(row.querySelector('svg.lucide-bot')).not.toBeNull();
    }
  });

  it('keeps an agent the machine cannot run shown and refused, under its published name', () => {
    const missing: CliDetection = {
      kind: 'codex',
      found: false,
      path: null,
      version: null,
      loggedIn: null,
      update: {
        available: null,
        latestVersion: null,
        checkUnavailableReason: null,
      },
    };
    const rows = options(
      render({ cliDetections: [missing] }, PUBLISHED_IDENTITIES),
    );
    const codex = rowLabelled(rows, 'Codex') as HTMLButtonElement;

    expect(codex.disabled).toBe(true);
    expect(
      codex.querySelector('[data-slot="menu-item-hint"]')?.textContent,
    ).toBe('not installed');
  });

  it('leaves the workflows in the same picker as they were', () => {
    const onChange = vi.fn();
    const rows = options(
      render({ workflows: WORKFLOWS, onChange }, PUBLISHED_IDENTITIES),
    );
    const workflow = rowLabelled(rows, 'Dev team');

    expect(rows.map(labelOf)).toEqual([
      'Claude',
      'Cursor',
      'Codex',
      'Dev team',
    ]);
    expect(workflow.querySelector('svg.lucide-workflow')).not.toBeNull();

    act(() => {
      workflow.click();
    });
    expect(onChange).toHaveBeenCalledWith('wf:dev-team');
  });
});
