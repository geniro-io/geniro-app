import type { ItemDto as ChatItem } from '../autogenerated';

/**
 * The agent's OWN task list — the todo list a coding CLI keeps for itself while
 * it works through a multi-step job — read off the transcript.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/utils/event-to-item.ts` writes these
 * keys for the `task_list` item kind, from whatever its adapters read off each
 * CLI. An item payload is `z.unknown()` on the wire BY DESIGN — every kind
 * carries a different shape — so no generated type reaches here and this is an
 * independent reading of one shape. A key renamed on either side must be
 * renamed on both.
 *
 * Why a FOLD and not just a render: two of the three shapes the daemon maps are
 * PATCHES that name only the rows that moved (claude's `TaskUpdate`, cursor's
 * `merge:true`), so no single row is ever "the list". The list is the fold of
 * every announcement in order, which is also why the rows are persisted rather
 * than streamed live — a reopened chat replays them and arrives at the same
 * place.
 */

export type TaskStatus = 'pending' | 'in_progress' | 'completed';

/** One task, as it stands after folding every announcement about it. */
export interface AgentTaskRow {
  id: string;
  /** Null only for a task first seen in a patch that carried no text. */
  title: string | null;
  /** Null when the CLI named a status the daemon does not recognise. */
  status: TaskStatus | null;
  /** The present-continuous label, for a CLI that sends one. */
  activeForm: string | null;
}

/** One announcement, exactly as one `task_list` row carries it. */
export interface TaskAnnouncement {
  /** `snapshot` replaces the list; `patch` moves only the rows it names. */
  mode: 'snapshot' | 'patch';
  tasks: AgentTaskRow[];
  /**
   * The tool call that produced it, when the CLI ties one to it — which is what
   * lets the transcript render the list INSTEAD of the opaque tool row (claude's
   * `TaskUpdate`, cursor's argument-free `Update TODOs`) rather than beside it.
   */
  toolCallId: string | null;
}

function readStatus(value: unknown): TaskStatus | null {
  return value === 'pending' || value === 'in_progress' || value === 'completed'
    ? value
    : null;
}

function readString(value: unknown): string | null {
  return typeof value === 'string' && value.length > 0 ? value : null;
}

/** Read one `task_list` row, or null when the payload does not read as one. */
export function readTaskAnnouncement(item: ChatItem): TaskAnnouncement | null {
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const row = payload as {
    mode?: unknown;
    tasks?: unknown;
    toolCallId?: unknown;
  };
  if (!Array.isArray(row.tasks)) {
    return null;
  }
  const tasks = row.tasks
    .map((entry): AgentTaskRow | null => {
      if (typeof entry !== 'object' || entry === null) {
        return null;
      }
      const task = entry as {
        id?: unknown;
        title?: unknown;
        status?: unknown;
        activeForm?: unknown;
      };
      const id = readString(task.id);
      return id === null
        ? null
        : {
            id,
            title: readString(task.title),
            status: readStatus(task.status),
            activeForm: readString(task.activeForm),
          };
    })
    .filter((task): task is AgentTaskRow => task !== null);
  return {
    // A payload whose mode is missing or unrecognised reads as a PATCH, the
    // direction that fails safely: a snapshot mistaken for a patch leaves a
    // deleted task on screen, while a patch mistaken for a snapshot deletes
    // every task it did not name — turning a list of seven into the two that
    // just moved.
    mode: row.mode === 'snapshot' ? 'snapshot' : 'patch',
    tasks,
    toolCallId: readString(row.toolCallId),
  };
}

/**
 * Apply one announcement to the list so far, in place, and return it.
 *
 * A patch MERGES per field rather than replacing the row: claude's `TaskUpdate`
 * sends `{taskId, status}` and no text at all, so a replacing merge would blank
 * the title of every task the moment it started running.
 */
function applyAnnouncement(
  list: AgentTaskRow[],
  announcement: TaskAnnouncement,
): AgentTaskRow[] {
  if (announcement.mode === 'snapshot') {
    // The CLI has stated the list; anything absent from it is gone. Titles are
    // still carried over for a row the snapshot named without one, so a terse
    // snapshot cannot lose text an earlier announcement gave.
    return announcement.tasks.map((task) => {
      const known = list.find((row) => row.id === task.id);
      return {
        ...task,
        title: task.title ?? known?.title ?? null,
        activeForm: task.activeForm ?? known?.activeForm ?? null,
      };
    });
  }
  const merged = [...list];
  for (const task of announcement.tasks) {
    const at = merged.findIndex((row) => row.id === task.id);
    if (at === -1) {
      merged.push(task);
      continue;
    }
    const known = merged[at]!;
    merged[at] = {
      id: known.id,
      title: task.title ?? known.title,
      // The status IS what a patch is for, so a patch that named the task takes
      // it even when it is null — the CLI moved this row somewhere we could not
      // name, which is not the same as it standing still.
      status: task.status,
      activeForm: task.activeForm ?? known.activeForm,
    };
  }
  return merged;
}

/**
 * The task list of ONE thread — the fold of the announcements given, in order.
 *
 * Threads are kept apart by the caller, not here: a delegate's list is its own,
 * and both CLIs number tasks from 1, so folding a sub-agent's rows in with the
 * main agent's would have task `1` mean two different things.
 */
export function foldTaskList(
  announcements: readonly TaskAnnouncement[],
): AgentTaskRow[] {
  let list: AgentTaskRow[] = [];
  for (const announcement of announcements) {
    list = applyAnnouncement(list, announcement);
  }
  return list;
}

/** How far along a list is — for the one-line summary a collapsed view shows. */
export function taskProgress(tasks: readonly AgentTaskRow[]): {
  done: number;
  total: number;
  /** The task being worked on now, when exactly one is; else null. */
  current: AgentTaskRow | null;
} {
  const running = tasks.filter((task) => task.status === 'in_progress');
  return {
    done: tasks.filter((task) => task.status === 'completed').length,
    total: tasks.length,
    // Only when unambiguous. Naming the first of several as "the current one"
    // would state a sequence the CLI never gave.
    current: running.length === 1 ? running[0]! : null,
  };
}

/**
 * Every task list in a transcript, keyed by the thread that owns it: `null` for
 * the agent's own, else the id of the tool call that launched the sub-agent.
 *
 * One pass over the items, because both consumers need it — the pinned strip
 * (the agent's current list) and each sub-agent block (the delegate's own).
 */
export function taskListsByThread(
  items: readonly ChatItem[],
  subagentIdOf: (item: ChatItem) => string | null,
): Map<string | null, AgentTaskRow[]> {
  const perThread = new Map<string | null, TaskAnnouncement[]>();
  for (const item of items) {
    if (item.kind !== 'task_list') {
      continue;
    }
    const announcement = readTaskAnnouncement(item);
    if (announcement === null) {
      continue;
    }
    const thread = subagentIdOf(item);
    const list = perThread.get(thread);
    if (list) {
      list.push(announcement);
    } else {
      perThread.set(thread, [announcement]);
    }
  }
  const out = new Map<string | null, AgentTaskRow[]>();
  for (const [thread, announcements] of perThread) {
    out.set(thread, foldTaskList(announcements));
  }
  return out;
}
