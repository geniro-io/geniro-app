import { ArrowUpRight } from 'lucide-react';

import type { TeamNote } from '../autogenerated';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import { MarkdownContent } from './markdown-content';
import { formatDateTime, formatRelativeTime } from './relative-time';
import { TeamNoteKindBadge } from './team-note-kind';

/**
 * One team note as a row of a pickable list: who, what kind, when, and its
 * first three lines until it is picked, then every word and the ways on from
 * it.
 */
export function TeamNoteEntry({
  note,
  author,
  selected,
  onSelect,
  onJump,
}: {
  note: TeamNote;
  author: string;
  selected: boolean;
  /** Pick this note, or another one it names (the newer or the earlier note). */
  onSelect: (seq: number) => void;
  onJump?: (seq: number) => void;
}): React.JSX.Element {
  const newer = note.supersededBy;
  const earlier = note.supersedes;
  const superseded = newer !== null;
  return (
    <li
      data-slot="team-note"
      data-note-seq={note.seq}
      data-selected={selected ? 'true' : undefined}
      onClick={(event) => {
        if ((event.target as Element).closest('a, button') !== null) {
          return;
        }
        if ((window.getSelection()?.toString() ?? '') !== '') {
          return;
        }
        onSelect(note.seq);
      }}
      className={cn(
        'group flex flex-col gap-1.5 rounded-lg border border-border/60 bg-muted/30 px-3 py-2 motion-safe:transition-colors',
        selected
          ? 'border-primary/60 bg-accent'
          : 'cursor-pointer hover:border-primary/40 hover:bg-accent',
        superseded && !selected && 'opacity-60',
      )}>
      <button
        type="button"
        onClick={() => onSelect(note.seq)}
        aria-expanded={selected}
        aria-label={`${note.kind} note by ${author}`}
        className="-mx-1 flex min-w-0 items-center justify-between gap-2 rounded px-1 text-left text-xs focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none">
        <span className="flex min-w-0 items-center gap-1.5">
          <span className="truncate text-xs font-medium text-foreground">
            {author}
          </span>
          <TeamNoteKindBadge kind={note.kind} />
          {superseded ? (
            <span
              title="A newer note replaces this one"
              className="shrink-0 text-[11px] text-muted-foreground">
              superseded
            </span>
          ) : null}
        </span>
        <time
          dateTime={note.createdAt}
          title={formatDateTime(note.createdAt)}
          className="shrink-0 text-[11px] whitespace-nowrap text-muted-foreground tabular-nums">
          {formatRelativeTime(note.createdAt)}
        </time>
      </button>
      <MarkdownContent
        content={note.text}
        className={cn(
          'text-xs leading-relaxed',
          !selected && 'line-clamp-3',
          superseded && 'line-through decoration-muted-foreground/50',
        )}
      />
      {selected ? (
        <div
          data-slot="team-note-actions"
          className="flex flex-wrap items-center gap-1">
          {onJump === undefined ? null : (
            <Button
              type="button"
              variant="outline"
              size="sm"
              onClick={() => onJump(note.seq)}>
              <ArrowUpRight />
              Open in chat
            </Button>
          )}
          {newer === null ? null : (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => onSelect(newer)}>
              Show the newer note
            </Button>
          )}
          {earlier === null ? null : (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => onSelect(earlier)}>
              Show the note it replaces
            </Button>
          )}
        </div>
      ) : null}
    </li>
  );
}
