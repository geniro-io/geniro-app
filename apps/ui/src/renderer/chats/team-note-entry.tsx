import { NotebookPen } from 'lucide-react';
import { useState } from 'react';

import type { TeamNote } from '../autogenerated';
import { cn } from '../components/ui/utils';
import { MarkdownContent } from './markdown-content';
import { formatDateTime, formatRelativeTime } from './relative-time';
import { TeamNoteKindBadge } from './team-note-kind';

/** A body longer than this is clamped until "Show more". */
const CLAMP_CHARS = 280;
const CLAMP_LINES = 4;

function isLong(text: string): boolean {
  return text.length > CLAMP_CHARS || text.split('\n').length > CLAMP_LINES;
}

/** One team note as a list row: who, what kind, when, and the note itself. */
export function TeamNoteEntry({
  note,
  author,
  arrived = false,
  clamp = true,
  onJump,
}: {
  note: TeamNote;
  author: string;
  /** Just arrived — drawn marked for a moment. */
  arrived?: boolean;
  /** Clamp a long body behind "Show more"; the full view shows every word. */
  clamp?: boolean;
  onJump?: (seq: number) => void;
}): React.JSX.Element {
  const [expanded, setExpanded] = useState(false);
  const long = clamp && isLong(note.text);
  const superseded = note.supersededBy !== null;
  const header = (
    <>
      <span className="flex min-w-0 items-center gap-1.5">
        <NotebookPen
          className="size-3.5 shrink-0 text-muted-foreground"
          aria-hidden
        />
        <span className="truncate text-xs font-medium">{author}</span>
        <TeamNoteKindBadge kind={note.kind} />
      </span>
      <time
        dateTime={note.createdAt}
        title={formatDateTime(note.createdAt)}
        className="shrink-0 text-[11px] whitespace-nowrap text-muted-foreground tabular-nums">
        {formatRelativeTime(note.createdAt)}
      </time>
    </>
  );
  return (
    <li
      className={cn(
        'flex flex-col gap-1 rounded-md px-2 py-1.5 motion-safe:transition-colors',
        superseded && 'opacity-60',
        // No flash under reduced motion; the polite announcement still says it.
        arrived && 'motion-safe:bg-primary/10',
      )}>
      {onJump === undefined ? (
        <div className="flex min-w-0 items-center justify-between gap-2">
          {header}
        </div>
      ) : (
        <button
          type="button"
          onClick={() => onJump(note.seq)}
          aria-label={`${note.kind} note ${note.seq} by ${author} — open it in the transcript`}
          className="-mx-1 flex min-w-0 items-center justify-between gap-2 rounded px-1 text-left text-xs hover:bg-accent focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none">
          {header}
        </button>
      )}
      <MarkdownContent
        content={note.text}
        className={cn(
          'text-xs',
          long && !expanded && 'line-clamp-4',
          superseded && 'line-through decoration-muted-foreground/50',
        )}
      />
      {long ? (
        <button
          type="button"
          onClick={() => setExpanded((was) => !was)}
          aria-expanded={expanded}
          className="self-start text-[11px] text-muted-foreground hover:text-foreground">
          {expanded ? 'Show less' : 'Show more'}
        </button>
      ) : null}
      {superseded ? (
        <span className="text-[11px] text-muted-foreground">
          superseded by note {note.supersededBy}
        </span>
      ) : null}
    </li>
  );
}
