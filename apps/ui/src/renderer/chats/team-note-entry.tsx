import { ArrowUpRight } from 'lucide-react';
import { useState } from 'react';

import type { TeamNote } from '../autogenerated';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import { MarkdownContent } from './markdown-content';
import { formatDateTime, formatRelativeTime } from './relative-time';
import { TeamNoteKindBadge } from './team-note-kind';

/** A body longer than this is clamped until "Show more". */
const CLAMP_CHARS = 280;
const CLAMP_LINES = 4;

function isLong(text: string): boolean {
  return text.length > CLAMP_CHARS || text.split('\n').length > CLAMP_LINES;
}

/**
 * One team note as a card: who, what kind, when, and the note itself.
 *
 * Given `onSelect` it is a row of a pickable list: its first three lines until
 * it is picked, then every word and the ways on from it. Without it a press
 * opens the note in the transcript and a long body folds behind "Show more".
 */
export function TeamNoteEntry({
  note,
  author,
  arrived = false,
  selected = false,
  onSelect,
  onJump,
}: {
  note: TeamNote;
  author: string;
  /** Just arrived — drawn marked for a moment. */
  arrived?: boolean;
  selected?: boolean;
  /** Pick this note, or another one it names (the newer or the earlier note). */
  onSelect?: (seq: number) => void;
  onJump?: (seq: number) => void;
}): React.JSX.Element {
  const [expanded, setExpanded] = useState(false);
  const pickable = onSelect !== undefined;
  const long = !pickable && isLong(note.text);
  const newer = note.supersededBy;
  const earlier = note.supersedes;
  const superseded = newer !== null;
  const press = pickable ? onSelect : onJump;
  const header = (
    <>
      <span className="flex min-w-0 items-center gap-1.5">
        <span className="truncate text-xs font-medium text-foreground">
          {author}
        </span>
        <TeamNoteKindBadge kind={note.kind} />
        {superseded ? (
          <span
            title="A newer note replaces this one"
            className="shrink-0 text-[11px] text-muted-foreground">
            superseded
          </span>
        ) : null}
      </span>
      <span className="flex shrink-0 items-center gap-1 text-muted-foreground">
        <time
          dateTime={note.createdAt}
          title={formatDateTime(note.createdAt)}
          className="text-[11px] whitespace-nowrap tabular-nums">
          {formatRelativeTime(note.createdAt)}
        </time>
        {pickable || onJump === undefined ? null : (
          <ArrowUpRight
            aria-hidden
            className="size-3.5 opacity-0 group-focus-within:opacity-100 group-hover:opacity-100 motion-safe:transition-opacity"
          />
        )}
      </span>
    </>
  );
  const openFromCard =
    press === undefined
      ? undefined
      : (event: React.MouseEvent<HTMLLIElement>): void => {
          const target = event.target as Element;
          if (target.closest('a, button') !== null) {
            return;
          }
          if ((window.getSelection()?.toString() ?? '') !== '') {
            return;
          }
          press(note.seq);
        };
  return (
    <li
      data-slot="team-note"
      data-note-seq={note.seq}
      data-selected={selected ? 'true' : undefined}
      onClick={openFromCard}
      className={cn(
        'group flex flex-col gap-1.5 rounded-lg border border-border/60 bg-muted/30 px-3 py-2 motion-safe:transition-colors',
        press !== undefined &&
          'cursor-pointer hover:border-primary/40 hover:bg-accent',
        superseded && !selected && 'opacity-60',
        selected && 'cursor-auto border-primary/60 bg-accent hover:bg-accent',
        // No flash under reduced motion; the polite announcement still says it.
        arrived && 'border-primary/40 motion-safe:bg-primary/10',
      )}>
      {press === undefined ? (
        <div className="flex min-w-0 items-center justify-between gap-2">
          {header}
        </div>
      ) : (
        <button
          type="button"
          onClick={() => press(note.seq)}
          aria-expanded={pickable ? selected : undefined}
          aria-label={
            pickable
              ? `${note.kind} note by ${author}`
              : `${note.kind} note by ${author} — open it in the transcript`
          }
          className="-mx-1 flex min-w-0 items-center justify-between gap-2 rounded px-1 text-left text-xs focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none">
          {header}
        </button>
      )}
      <MarkdownContent
        content={note.text}
        className={cn(
          'text-xs leading-relaxed',
          pickable && !selected && 'line-clamp-3',
          long && !expanded && 'line-clamp-4',
          superseded && 'line-through decoration-muted-foreground/50',
        )}
      />
      {long ? (
        <div className="flex items-center gap-2 text-[11px] text-muted-foreground">
          <button
            type="button"
            onClick={() => setExpanded((was) => !was)}
            aria-expanded={expanded}
            className="text-[11px] hover:text-foreground">
            {expanded ? 'Show less' : 'Show more'}
          </button>
        </div>
      ) : null}
      {pickable && selected ? (
        <div
          data-slot="team-note-actions"
          className="flex flex-wrap items-center gap-1">
          {onJump === undefined ? null : (
            <Button
              type="button"
              variant="outline"
              size="sm"
              onClick={() => onJump(note.seq)}>
              <ArrowUpRight />
              Open in chat
            </Button>
          )}
          {newer === null ? null : (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => onSelect(newer)}>
              Show the newer note
            </Button>
          )}
          {earlier === null ? null : (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => onSelect(earlier)}>
              Show the note it replaces
            </Button>
          )}
        </div>
      ) : null}
    </li>
  );
}
