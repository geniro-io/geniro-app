import { Filter } from 'lucide-react';
import { useMemo, useRef, useState } from 'react';

import type { TeamNote, TeamNoteKind } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Menu, type MenuItem } from '../components/ui/menu';
import { cn } from '../components/ui/utils';
import { TEAM_NOTE_KINDS } from './team-note-kind';

const CLEAR = 'clear';
const kindValue = (kind: TeamNoteKind): string => `kind:${kind}`;
const authorValue = (name: string): string => `author:${name}`;

/** The kind and author filters over a set of team notes. */
export interface TeamNoteFilters {
  kinds: readonly TeamNoteKind[];
  authors: readonly string[];
  pickedKinds: ReadonlySet<TeamNoteKind>;
  pickedAuthors: ReadonlySet<string>;
  narrowed: boolean;
  passes: (note: TeamNote) => boolean;
  toggle: (value: string) => void;
  clear: () => void;
}

export function useTeamNoteFilters(
  notes: readonly TeamNote[],
  agentName: (nodeId: string) => string,
): TeamNoteFilters {
  const [pickedKinds, setPickedKinds] = useState<ReadonlySet<TeamNoteKind>>(
    () => new Set(),
  );
  const [pickedAuthors, setPickedAuthors] = useState<ReadonlySet<string>>(
    () => new Set(),
  );
  const authors = useMemo(
    () => [...new Set(notes.map((note) => agentName(note.nodeId)))].sort(),
    [notes, agentName],
  );
  const kinds = useMemo(
    () => TEAM_NOTE_KINDS.filter((kind) => notes.some((n) => n.kind === kind)),
    [notes],
  );
  const flip = <T,>(was: ReadonlySet<T>, value: T): ReadonlySet<T> => {
    const next = new Set(was);
    if (!next.delete(value)) {
      next.add(value);
    }
    return next;
  };
  return {
    kinds,
    authors,
    pickedKinds,
    pickedAuthors,
    narrowed: pickedKinds.size > 0 || pickedAuthors.size > 0,
    passes: (note) =>
      (pickedKinds.size === 0 || pickedKinds.has(note.kind)) &&
      (pickedAuthors.size === 0 || pickedAuthors.has(agentName(note.nodeId))),
    toggle: (value) => {
      if (value.startsWith('kind:')) {
        const kind = value.slice('kind:'.length) as TeamNoteKind;
        setPickedKinds((was) => flip(was, kind));
      } else if (value.startsWith('author:')) {
        const name = value.slice('author:'.length);
        setPickedAuthors((was) => flip(was, name));
      }
    },
    clear: () => {
      setPickedKinds(new Set());
      setPickedAuthors(new Set());
    },
  };
}

/**
 * Narrow the notes by kind and by author — an icon trigger opening checked
 * rows, on `ChatScopeFilter`'s pattern, toned while anything is narrowed.
 */
export function TeamNotesFilter({
  filters,
  className,
}: {
  filters: TeamNoteFilters;
  /** The trigger's size. */
  className?: string;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const { kinds, authors, pickedKinds, pickedAuthors, narrowed } = filters;
  const onToggle = filters.toggle;
  const onClear = filters.clear;
  const groups: { label?: string; items: MenuItem[] }[] = [
    {
      label: 'Kind',
      items: kinds.map((kind) => ({
        value: kindValue(kind),
        label: kind,
        checked: pickedKinds.has(kind),
      })),
    },
    {
      label: 'Author',
      items: authors.map((name) => ({
        value: authorValue(name),
        label: name,
        checked: pickedAuthors.has(name),
      })),
    },
  ];
  if (narrowed) {
    groups.push({ items: [{ value: CLEAR, label: 'Clear filters' }] });
  }
  return (
    <span className="relative inline-flex">
      <Button
        ref={triggerRef}
        type="button"
        variant="ghost"
        size="icon"
        data-menu-trigger
        aria-haspopup="listbox"
        aria-expanded={open}
        aria-label="Filter team notes"
        title={narrowed ? 'Filter team notes · narrowed' : 'Filter team notes'}
        className={cn(
          'size-6',
          className,
          narrowed && 'text-primary hover:text-primary',
        )}
        onClick={() => setOpen((wasOpen) => !wasOpen)}>
        <Filter className="shrink-0" />
      </Button>
      <Menu
        open={open}
        side="bottom"
        align="end"
        anchor="viewport"
        triggerRef={triggerRef}
        groups={groups}
        onSelect={(value) => {
          if (value === CLEAR) {
            onClear();
          } else {
            onToggle(value);
          }
        }}
        onClose={() => setOpen(false)}
      />
    </span>
  );
}
