import { TeamNoteKind } from '../autogenerated';
import { Badge } from '../components/ui/badge';

type BadgeVariant = 'default' | 'secondary' | 'muted' | 'warning' | 'outline';

/** Each kind's look, in one place for the transcript row and the panel. */
const KIND_VARIANT: Readonly<Record<TeamNoteKind, BadgeVariant>> = {
  [TeamNoteKind.Contract]: 'default',
  [TeamNoteKind.Decision]: 'secondary',
  [TeamNoteKind.Fact]: 'muted',
  [TeamNoteKind.Pitfall]: 'warning',
  [TeamNoteKind.Pointer]: 'outline',
};

/** The kinds in the order the filter lists them. */
export const TEAM_NOTE_KINDS: readonly TeamNoteKind[] =
  Object.values(TeamNoteKind);

/** A team note's kind as a badge — the word always shown, never colour alone. */
export function TeamNoteKindBadge({
  kind,
}: {
  kind: TeamNoteKind;
}): React.JSX.Element {
  return <Badge variant={KIND_VARIANT[kind]}>{kind}</Badge>;
}
