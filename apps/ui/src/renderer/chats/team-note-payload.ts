/**
 * What a `team_note` row's payload says: one note an agent of a team run
 * wrote to the run's shared team notes.
 *
 * TWIN PARSER: `TeamNotePayloadSchema` in
 * `apps/daemon/src/v1/agents/chat.types.ts`, which writes these rows. An item
 * payload is `z.unknown()` on the wire, so the two sides read one shape
 * independently; a field renamed there must change here.
 */

import { TeamNoteKind } from '../autogenerated';

export interface TeamNotePayload {
  kind: TeamNoteKind;
  text: string;
  /** The earlier note this one replaces, or null. */
  supersedes: number | null;
  nodeId: string;
  /** The writing conversation; null for the node's own. */
  conversationId: string | null;
  /** The call that conversation was answering, or null. */
  callId: string | null;
}

const KINDS: ReadonlySet<string> = new Set(Object.values(TeamNoteKind));

function isTeamNoteKind(value: unknown): value is TeamNoteKind {
  return typeof value === 'string' && KINDS.has(value);
}

/** The note a row carries, or null when its payload is not one. */
export function readTeamNotePayload(payload: unknown): TeamNotePayload | null {
  if (payload === null || typeof payload !== 'object') {
    return null;
  }
  const bag = payload as Record<string, unknown>;
  if (
    !isTeamNoteKind(bag.kind) ||
    typeof bag.text !== 'string' ||
    typeof bag.nodeId !== 'string'
  ) {
    return null;
  }
  return {
    kind: bag.kind,
    text: bag.text,
    supersedes:
      typeof bag.supersedes === 'number' && Number.isInteger(bag.supersedes)
        ? bag.supersedes
        : null,
    nodeId: bag.nodeId,
    conversationId:
      typeof bag.conversationId === 'string' ? bag.conversationId : null,
    callId: typeof bag.callId === 'string' ? bag.callId : null,
  };
}
