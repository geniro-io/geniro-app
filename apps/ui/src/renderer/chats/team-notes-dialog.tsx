import { Search } from 'lucide-react';
import { useState } from 'react';

import type { TeamNote } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { teamNoteAuthor } from './team-note-author';
import { TeamNoteEntry } from './team-note-entry';
import { TeamNotesFilter, useTeamNoteFilters } from './team-note-filters';

/**
 * Every team note of the run, whole, in a window of its own — what the agents
 * panel's 280px column and the shelf chip's preview cannot hold. The same
 * kind and author filters as the panel, plus a search over the words, and a
 * press on a note's heading closes this and opens the note in the transcript.
 */
export function TeamNotesDialog({
  open,
  onClose,
  notes,
  agentName,
  onJump,
}: {
  open: boolean;
  onClose: () => void;
  /** Newest first, as the daemon lists them. */
  notes: readonly TeamNote[];
  agentName: (nodeId: string) => string;
  /** Open a note's row in the transcript; the dialog closes first. */
  onJump?: (seq: number) => void;
}): React.JSX.Element {
  const filters = useTeamNoteFilters(notes, agentName);
  const [query, setQuery] = useState('');
  const words = query.trim().toLowerCase();
  const matching = notes.filter(
    (note) =>
      filters.passes(note) &&
      (words === '' ||
        `${note.text}\n${teamNoteAuthor(note, agentName)}\n${note.kind}`
          .toLowerCase()
          .includes(words)),
  );
  const clear = (): void => {
    filters.clear();
    setQuery('');
  };
  const jump =
    onJump === undefined
      ? undefined
      : (seq: number): void => {
          onClose();
          onJump(seq);
        };

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Team notes"
      className="h-[92vh] w-[min(96vw,56rem)] max-w-none">
      <div className="flex h-full min-h-0 flex-col gap-3">
        <div className="flex min-w-0 items-center gap-2">
          <div className="relative min-w-0 flex-1">
            <Search
              className="pointer-events-none absolute top-1/2 left-2.5 size-4 -translate-y-1/2 text-muted-foreground"
              aria-hidden
            />
            <Input
              type="search"
              value={query}
              onChange={(event) => setQuery(event.target.value)}
              placeholder="Search notes"
              aria-label="Search team notes"
              className="pl-8"
            />
          </div>
          <TeamNotesFilter filters={filters} className="size-9" />
          <span className="shrink-0 text-xs whitespace-nowrap text-muted-foreground tabular-nums">
            {matching.length === notes.length
              ? `${notes.length} ${notes.length === 1 ? 'note' : 'notes'}`
              : `${matching.length} of ${notes.length}`}
          </span>
        </div>
        {matching.length === 0 ? (
          <div className="flex flex-col items-center gap-2 py-12 text-sm text-muted-foreground">
            <span>
              {notes.length === 0 ? 'No team notes yet' : 'No notes match'}
            </span>
            {notes.length === 0 ? null : (
              <Button type="button" variant="ghost" size="sm" onClick={clear}>
                Clear filters
              </Button>
            )}
          </div>
        ) : (
          <ul className="m-0 flex min-h-0 flex-1 list-none flex-col gap-2 overflow-y-auto p-0">
            {matching.map((note) => (
              <TeamNoteEntry
                key={note.seq}
                note={note}
                author={teamNoteAuthor(note, agentName)}
                clamp={false}
                onJump={jump}
              />
            ))}
          </ul>
        )}
      </div>
    </Dialog>
  );
}
