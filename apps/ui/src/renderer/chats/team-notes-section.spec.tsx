// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { TeamNote } from '../autogenerated';
import { TeamNotesSection } from './team-notes-section';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function note(seq: number): TeamNote {
  return {
    seq,
    kind: 'fact',
    text: `note ${seq}`,
    nodeId: 'worker',
    conversationId: null,
    callId: null,
    createdAt: '2026-10-26T09:00:00.000Z',
    supersedes: null,
    supersededBy: null,
  };
}

const agentName = (nodeId: string): string => nodeId;

let root: Root | null = null;
let host: HTMLDivElement | null = null;

function show(notes: TeamNote[], loaded = true): void {
  if (root === null) {
    host = document.createElement('div');
    document.body.appendChild(host);
    root = createRoot(host);
  }
  act(() => {
    root!.render(
      <TeamNotesSection notes={notes} loaded={loaded} agentName={agentName} />,
    );
  });
}

const announced = (): string =>
  host?.querySelector('[aria-live="polite"]')?.textContent ?? '';

afterEach(() => {
  vi.useRealTimers();
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
});

describe('TeamNotesSection — notes arriving while the thread is open', () => {
  it('announces the first note of a thread that opened with none', () => {
    show([]);
    show([note(5)]);
    expect(announced()).toBe('1 new team note');
  });

  it('announces notes newer than the ones the thread opened with, and not the opening set', () => {
    show([note(5)]);
    expect(announced()).toBe('');
    show([note(9), note(7), note(5)]);
    expect(announced()).toBe('2 new team notes');
  });
});

describe('TeamNotesSection — what is marked as new', () => {
  const marked = (): number =>
    host?.querySelectorAll('li[class*="bg-primary/10"]').length ?? 0;

  it('marks nothing for the notes a thread opened with, read after mount', () => {
    show([], false);
    show([note(9), note(7)], true);
    expect(announced()).toBe('');
    expect(marked()).toBe(0);
  });

  it('clears the mark of an arrival, also when the list is re-read meanwhile', () => {
    vi.useFakeTimers();
    show([note(5)]);
    show([note(9), note(5)]);
    expect(marked()).toBe(1);
    // A re-read with nothing new inside the mark's window.
    show([note(9), note(5)]);
    act(() => {
      vi.advanceTimersByTime(2_000);
    });
    expect(marked()).toBe(0);
  });

  it('shows a New notes pill while scrolled, past the mark, until the list is back at its top', () => {
    vi.useFakeTimers();
    show([note(5)]);
    const list = host!.querySelector<HTMLDivElement>('.overflow-y-auto')!;
    list.scrollTo = vi.fn();
    act(() => {
      list.scrollTop = 120;
      list.dispatchEvent(new Event('scroll'));
    });
    const pill = (): HTMLButtonElement | undefined =>
      [...host!.querySelectorAll<HTMLButtonElement>('button')].find(
        (button) => button.textContent === 'New notes',
      );
    expect(pill()).toBeUndefined();

    show([note(9), note(5)]);
    act(() => {
      vi.advanceTimersByTime(2_000);
    });
    // The mark is gone; a reader scrolled away has not seen the note yet.
    expect(pill()).toBeDefined();
    act(() => pill()?.click());
    expect(list.scrollTo).toHaveBeenCalledWith({ top: 0 });
    expect(pill()).toBeUndefined();

    show([note(12), note(9), note(5)]);
    expect(pill()).toBeDefined();
    act(() => {
      list.scrollTop = 0;
      list.dispatchEvent(new Event('scroll'));
    });
    expect(pill()).toBeUndefined();
  });

  it('announces a second arrival of the same size again, the first one having cleared', () => {
    vi.useFakeTimers();
    show([note(5)]);
    show([note(7), note(5)]);
    expect(announced()).toBe('1 new team note');
    act(() => {
      vi.advanceTimersByTime(2_000);
    });
    expect(announced()).toBe('');
    show([note(9), note(7), note(5)]);
    expect(announced()).toBe('1 new team note');
  });

  it('clears the mark even when a failed re-read empties the list meanwhile', () => {
    vi.useFakeTimers();
    show([note(5)]);
    show([note(9), note(5)]);
    show([]);
    show([note(9), note(5)]);
    act(() => {
      vi.advanceTimersByTime(2_000);
    });
    expect(marked()).toBe(0);
  });
});

describe('TeamNotesSection — paging', () => {
  it('lists the newest 50 and pages the rest in behind Show older', () => {
    const notes = Array.from({ length: 51 }, (_, i) => note(100 - i));
    show(notes);
    expect(host!.querySelectorAll('li')).toHaveLength(50);
    const older = [...host!.querySelectorAll<HTMLButtonElement>('button')].find(
      (button) => button.textContent === 'Show older (1)',
    );
    act(() => older?.click());
    expect(host!.querySelectorAll('li')).toHaveLength(51);
  });
});

describe('TeamNotesSection — arrivals and the reader’s place', () => {
  const pill = (): HTMLButtonElement | undefined =>
    [...host!.querySelectorAll<HTMLButtonElement>('button')].find(
      (button) => button.textContent === 'New notes',
    );
  const scrollTo = (top: number): void => {
    const list = host!.querySelector<HTMLDivElement>('.overflow-y-auto')!;
    act(() => {
      list.scrollTop = top;
      list.dispatchEvent(new Event('scroll'));
    });
  };

  it('raises no pill for a note that arrived while the list was at its top', () => {
    show([note(5)]);
    show([note(9), note(5)]);
    scrollTo(120);
    expect(pill()).toBeUndefined();
  });

  it('announces a burst as one growing batch, so each arrival changes the text', () => {
    vi.useFakeTimers();
    show([note(5)]);
    show([note(7), note(5)]);
    expect(announced()).toBe('1 new team note');
    act(() => {
      vi.advanceTimersByTime(1_000);
    });
    show([note(9), note(7), note(5)]);
    expect(announced()).toBe('2 new team notes');
  });

  it('forgets the scroll position when the list goes away and comes back at its top', () => {
    show([note(5)]);
    scrollTo(120);
    show([note(9), note(5)]);
    expect(pill()).toBeDefined();
    // A failed re-read empties the list; the next read draws it afresh.
    show([]);
    show([note(9), note(5)]);
    expect(pill()).toBeUndefined();
  });
});

describe('TeamNotesSection — a press anywhere on a note opens it', () => {
  const longNote = (seq: number): TeamNote => ({
    ...note(seq),
    text: 'a long note '.repeat(40),
  });

  function showJumpable(notes: TeamNote[]): ReturnType<typeof vi.fn> {
    const onJump = vi.fn();
    host = document.createElement('div');
    document.body.appendChild(host);
    root = createRoot(host);
    act(() => {
      root!.render(
        <TeamNotesSection
          notes={notes}
          agentName={agentName}
          onJump={onJump}
        />,
      );
    });
    return onJump;
  }

  const card = (seq: number): HTMLElement =>
    [...host!.querySelectorAll<HTMLElement>('[data-slot="team-note"]')].find(
      (li) =>
        li
          .querySelector('li > button')
          ?.getAttribute('aria-label')
          ?.includes(` note ${seq} `) === true,
    )!;

  it('opens the note from its words, not only from its heading', () => {
    const onJump = showJumpable([note(9), note(4)]);
    const words = card(4).querySelector<HTMLElement>('[class*="break-words"]');
    act(() => {
      words!.click();
    });
    expect(onJump).toHaveBeenCalledExactlyOnceWith(4);
  });

  it('opens the note once from its heading', () => {
    const onJump = showJumpable([note(9)]);
    act(() => {
      card(9).querySelector<HTMLButtonElement>('li > button')!.click();
    });
    expect(onJump).toHaveBeenCalledExactlyOnceWith(9);
  });

  it('leaves Show more to unfold the note rather than open it', () => {
    const onJump = showJumpable([longNote(9)]);
    const more = [...card(9).querySelectorAll('button')].find(
      (button) => button.textContent === 'Show more',
    );
    act(() => {
      more!.click();
    });
    expect(onJump).not.toHaveBeenCalled();
    expect(more!.textContent).toBe('Show less');
  });

  it('does not open the note when the press ends a text selection', () => {
    const onJump = showJumpable([note(9)]);
    const words = card(9).querySelector<HTMLElement>('[class*="break-words"]')!;
    const range = document.createRange();
    range.selectNodeContents(words);
    window.getSelection()!.addRange(range);
    try {
      act(() => {
        words.click();
      });
    } finally {
      window.getSelection()!.removeAllRanges();
    }
    expect(onJump).not.toHaveBeenCalled();
  });
});
