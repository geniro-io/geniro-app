function note(seq: number, over: Partial<TeamNote>): TeamNote {
  return {
    seq,
    kind: 'fact',
    text: '',
    nodeId: 'backend',
    conversationId: null,
    callId: null,
    createdAt: new Date(Date.now() - (300 - seq) * 60_000).toISOString(),
    supersedes: null,
    supersededBy: null,
    ...over,
  };
}

