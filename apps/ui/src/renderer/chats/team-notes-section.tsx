import { Maximize2 } from 'lucide-react';
import { useCallback, useEffect, useRef, useState } from 'react';

import type { TeamNote } from '../autogenerated';
import { PanelSection } from '../components/panel-section';
import { Button } from '../components/ui/button';
import { teamNoteAuthor } from './team-note-author';
import { TeamNoteEntry } from './team-note-entry';
import { TeamNotesFilter, useTeamNoteFilters } from './team-note-filters';

/** How many notes the section lists before "Show older". */
export const TEAM_NOTES_PAGE = 50;

/** How long a note that just arrived stays marked. */
const ARRIVAL_MARK_MS = 2_000;

/**
 * Every team note of the open workflow run — the agents' shared contracts,
 * decisions, facts, pitfalls and pointers — newest first, in the notes popup.
 * A press on a note's heading opens its row in the transcript (inside its
 * call's card when a callee wrote it). Draws nothing at zero notes.
 */
export function TeamNotesSection({
  notes,
  loaded = true,
  agentName,
  onJump,
  onOpenAll,
}: {
  /** Newest first, as the daemon lists them. */
  notes: readonly TeamNote[];
  /**
   * Whether the run's notes have been read at all. The first read is the set
   * the thread opened with; only notes after it are marked as arriving.
   */
  loaded?: boolean;
  agentName: (nodeId: string) => string;
  onJump?: (seq: number) => void;
  /**
   * Open every note in the full view, for a reader who wants the notes
   * whole. Absent draws no button.
   */
  onOpenAll?: () => void;
}): React.JSX.Element | null {
  const filters = useTeamNoteFilters(notes, agentName);
  const [shown, setShown] = useState(TEAM_NOTES_PAGE);
  const [arrived, setArrived] = useState<ReadonlySet<number>>(() => new Set());
  const [announcement, setAnnouncement] = useState('');
  const [scrolled, setScrolled] = useState(false);
  // Set by an arrival the reader can see, cleared once the list is back at
  // its top — not by the mark's timer, which a scrolled reader would miss.
  const [newAbove, setNewAbove] = useState(false);
  const listRef = useRef<HTMLDivElement | null>(null);
  // A list that unmounts (every note filtered out, a failed re-read) comes
  // back at its top, so what it knew about scrolling goes with it.
  const attachList = useCallback((element: HTMLDivElement | null) => {
    listRef.current = element;
    if (element === null) {
      setScrolled(false);
      setNewAbove(false);
    }
  }, []);
  const arrivedRef = useRef(arrived);
  arrivedRef.current = arrived;
  // `undefined` until the first read answers; then the newest seq seen, or
  // null for a run that had none.
  const newestSeen = useRef<number | null | undefined>(undefined);
  const notesRef = useRef(notes);
  notesRef.current = notes;
  // What the list shows now, read by the arrival effect without re-running it.
  const shownRef = useRef<(note: TeamNote) => boolean>(() => true);

  const newest = notes[0]?.seq ?? null;
  // Keyed on the newest seq alone: a re-read that changes nothing must not
  // restart the effect, whose cleanup would cancel the mark's timer for good.
  useEffect(() => {
    if (!loaded) {
      return;
    }
    const before = newestSeen.current;
    if (before === undefined) {
      newestSeen.current = newest;
      return;
    }
    if (newest === null || (before !== null && newest <= before)) {
      return;
    }
    newestSeen.current = newest;
    const fresh = notesRef.current
      .filter((note) => before === null || note.seq > before)
      .map((note) => note.seq);
    // One batch while the mark is up: a second arrival joins the first, so
    // its count — and the announced text — changes and is heard.
    const batch = new Set([...arrivedRef.current, ...fresh]);
    setArrived(batch);
    // Only a reader scrolled away has not seen an arrival at the top.
    const away = (listRef.current?.scrollTop ?? 0) > 0;
    if (
      away &&
      notesRef.current.some(
        (note) => fresh.includes(note.seq) && shownRef.current(note),
      )
    ) {
      setNewAbove(true);
    }
    setAnnouncement(
      `${batch.size} new team ${batch.size === 1 ? 'note' : 'notes'}`,
    );
  }, [loaded, newest]);

  // Its own effect, so nothing but a newer arrival can cancel the clearing:
  // the announcement goes with the mark, so the next identical one is heard.
  useEffect(() => {
    if (arrived.size === 0) {
      return;
    }
    const timer = setTimeout(() => {
      setArrived(new Set());
      setAnnouncement('');
    }, ARRIVAL_MARK_MS);
    return () => clearTimeout(timer);
  }, [arrived]);
  if (notes.length === 0) {
    return null;
  }

  const passes = filters.passes;
  shownRef.current = passes;
  const matching = notes.filter(passes);
  const clear = filters.clear;

  return (
    <PanelSection
      label="Team notes"
      action={<TeamNotesFilter filters={filters} />}>
      <span aria-live="polite" className="sr-only">
        {announcement}
      </span>
      {matching.length === 0 ? (
        <div className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
          <span>No notes match</span>
          <Button type="button" variant="ghost" size="sm" onClick={clear}>
            Clear filters
          </Button>
        </div>
      ) : (
        <div className="relative">
          {scrolled && newAbove ? (
            <Button
              type="button"
              size="sm"
              className="absolute top-1 left-1/2 z-10 -translate-x-1/2 shadow-panel-sm"
              onClick={() => {
                setNewAbove(false);
                listRef.current?.scrollTo({ top: 0 });
              }}>
              New notes
            </Button>
          ) : null}
          <div
            ref={attachList}
            className="max-h-80 overflow-y-auto"
            onScroll={(event) => {
              const away = event.currentTarget.scrollTop > 0;
              setScrolled(away);
              if (!away) {
                setNewAbove(false);
              }
            }}>
            <ul className="m-0 flex list-none flex-col gap-1.5 p-0">
              {matching.slice(0, shown).map((note) => (
                <TeamNoteEntry
                  key={note.seq}
                  note={note}
                  author={teamNoteAuthor(note, agentName)}
                  arrived={arrived.has(note.seq)}
                  onJump={onJump}
                />
              ))}
            </ul>
            {matching.length > shown ? (
              <Button
                type="button"
                variant="ghost"
                size="sm"
                className="w-full"
                onClick={() => setShown((was) => was + TEAM_NOTES_PAGE)}>
                Show older ({matching.length - shown})
              </Button>
            ) : null}
          </div>
        </div>
      )}
      {onOpenAll === undefined ? null : (
        <Button
          type="button"
          variant="outline"
          size="sm"
          className="w-full"
          onClick={onOpenAll}>
          <Maximize2 />
          Open the full view
        </Button>
      )}
    </PanelSection>
  );
}
