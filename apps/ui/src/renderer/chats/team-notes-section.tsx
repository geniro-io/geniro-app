import { Filter, NotebookPen } from 'lucide-react';
import { useCallback, useEffect, useMemo, useRef, useState } from 'react';

import type { TeamNote, TeamNoteKind } from '../autogenerated';
import { PanelSection } from '../components/panel-section';
import { Button } from '../components/ui/button';
import { Menu, type MenuItem } from '../components/ui/menu';
import { cn } from '../components/ui/utils';
import { MarkdownContent } from './markdown-content';
import { formatDateTime, formatRelativeTime } from './relative-time';
import { teamNoteAuthor } from './team-note-author';
import { TEAM_NOTE_KINDS, TeamNoteKindBadge } from './team-note-kind';

/** How many notes the section lists before "Show older". */
export const TEAM_NOTES_PAGE = 50;

/** A body longer than this is clamped until "Show more". */
const CLAMP_CHARS = 280;
const CLAMP_LINES = 4;

/** How long a note that just arrived stays marked. */
const ARRIVAL_MARK_MS = 2_000;

const CLEAR = 'clear';
const kindValue = (kind: TeamNoteKind): string => `kind:${kind}`;
const authorValue = (name: string): string => `author:${name}`;

function isLong(text: string): boolean {
  return text.length > CLAMP_CHARS || text.split('\n').length > CLAMP_LINES;
}

/**
 * Narrow the notes by kind and by author — an icon trigger opening checked
 * rows, on `ChatScopeFilter`'s pattern, toned while anything is narrowed.
 */
function TeamNotesFilter({
  kinds,
  authors,
  pickedKinds,
  pickedAuthors,
  onToggle,
  onClear,
}: {
  kinds: readonly TeamNoteKind[];
  authors: readonly string[];
  pickedKinds: ReadonlySet<TeamNoteKind>;
  pickedAuthors: ReadonlySet<string>;
  onToggle: (value: string) => void;
  onClear: () => void;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const narrowed = pickedKinds.size > 0 || pickedAuthors.size > 0;
  const groups: { label?: string; items: MenuItem[] }[] = [
    {
      label: 'Kind',
      items: kinds.map((kind) => ({
        value: kindValue(kind),
        label: kind,
        checked: pickedKinds.has(kind),
      })),
    },
    {
      label: 'Author',
      items: authors.map((name) => ({
        value: authorValue(name),
        label: name,
        checked: pickedAuthors.has(name),
      })),
    },
  ];
  if (narrowed) {
    groups.push({ items: [{ value: CLEAR, label: 'Clear filters' }] });
  }
  return (
    <span className="relative inline-flex">
      <Button
        ref={triggerRef}
        type="button"
        variant="ghost"
        size="icon"
        data-menu-trigger
        aria-haspopup="listbox"
        aria-expanded={open}
        aria-label="Filter team notes"
        title={narrowed ? 'Filter team notes · narrowed' : 'Filter team notes'}
        className={cn('size-6', narrowed && 'text-primary hover:text-primary')}
        onClick={() => setOpen((wasOpen) => !wasOpen)}>
        <Filter className="shrink-0" />
      </Button>
      <Menu
        open={open}
        side="bottom"
        align="end"
        anchor="viewport"
        triggerRef={triggerRef}
        groups={groups}
        onSelect={(value) => {
          if (value === CLEAR) {
            onClear();
          } else {
            onToggle(value);
          }
        }}
        onClose={() => setOpen(false)}
      />
    </span>
  );
}

function TeamNoteEntry({
  note,
  author,
  arrived,
  onJump,
}: {
  note: TeamNote;
  author: string;
  arrived: boolean;
  onJump?: (seq: number) => void;
}): React.JSX.Element {
  const [expanded, setExpanded] = useState(false);
  const long = isLong(note.text);
  const superseded = note.supersededBy !== null;
  const header = (
    <>
      <span className="flex min-w-0 items-center gap-1.5">
        <NotebookPen
          className="size-3.5 shrink-0 text-muted-foreground"
          aria-hidden
        />
        <span className="truncate text-xs font-medium">{author}</span>
        <TeamNoteKindBadge kind={note.kind} />
      </span>
      <time
        dateTime={note.createdAt}
        title={formatDateTime(note.createdAt)}
        className="shrink-0 text-[11px] whitespace-nowrap text-muted-foreground tabular-nums">
        {formatRelativeTime(note.createdAt)}
      </time>
    </>
  );
  return (
    <li
      className={cn(
        'flex flex-col gap-1 rounded-md px-2 py-1.5 motion-safe:transition-colors',
        superseded && 'opacity-60',
        // No flash under reduced motion; the polite announcement still says it.
        arrived && 'motion-safe:bg-primary/10',
      )}>
      {onJump === undefined ? (
        <div className="flex min-w-0 items-center justify-between gap-2">
          {header}
        </div>
      ) : (
        <button
          type="button"
          onClick={() => onJump(note.seq)}
          aria-label={`${note.kind} note ${note.seq} by ${author} — open it in the transcript`}
          className="-mx-1 flex min-w-0 items-center justify-between gap-2 rounded px-1 text-left text-xs hover:bg-accent focus-visible:ring-2 focus-visible:ring-ring focus-visible:outline-none">
          {header}
        </button>
      )}
      <MarkdownContent
        content={note.text}
        className={cn(
          'text-xs',
          long && !expanded && 'line-clamp-4',
          superseded && 'line-through decoration-muted-foreground/50',
        )}
      />
      {long ? (
        <button
          type="button"
          onClick={() => setExpanded((was) => !was)}
          aria-expanded={expanded}
          className="self-start text-[11px] text-muted-foreground hover:text-foreground">
          {expanded ? 'Show less' : 'Show more'}
        </button>
      ) : null}
      {superseded ? (
        <span className="text-[11px] text-muted-foreground">
          superseded by note {note.supersededBy}
        </span>
      ) : null}
    </li>
  );
}

/**
 * Every team note of the open workflow run — the agents' shared contracts,
 * decisions, facts, pitfalls and pointers — newest first, under the agents.
 * A press on a note's heading opens its row in the transcript (inside its
 * call's card when a callee wrote it). Draws nothing at zero notes.
 */
export function TeamNotesSection({
  notes,
  loaded = true,
  agentName,
  onJump,
}: {
  /** Newest first, as the daemon lists them. */
  notes: readonly TeamNote[];
  /**
   * Whether the run's notes have been read at all. The first read is the set
   * the thread opened with; only notes after it are marked as arriving.
   */
  loaded?: boolean;
  agentName: (nodeId: string) => string;
  onJump?: (seq: number) => void;
}): React.JSX.Element | null {
  const [pickedKinds, setPickedKinds] = useState<ReadonlySet<TeamNoteKind>>(
    () => new Set(),
  );
  const [pickedAuthors, setPickedAuthors] = useState<ReadonlySet<string>>(
    () => new Set(),
  );
  const [shown, setShown] = useState(TEAM_NOTES_PAGE);
  const [arrived, setArrived] = useState<ReadonlySet<number>>(() => new Set());
  const [announcement, setAnnouncement] = useState('');
  const [scrolled, setScrolled] = useState(false);
  // Set by an arrival the reader can see, cleared once the list is back at
  // its top — not by the mark's timer, which a scrolled reader would miss.
  const [newAbove, setNewAbove] = useState(false);
  const listRef = useRef<HTMLDivElement | null>(null);
  // A list that unmounts (every note filtered out, a failed re-read) comes
  // back at its top, so what it knew about scrolling goes with it.
  const attachList = useCallback((element: HTMLDivElement | null) => {
    listRef.current = element;
    if (element === null) {
      setScrolled(false);
      setNewAbove(false);
    }
  }, []);
  const arrivedRef = useRef(arrived);
  arrivedRef.current = arrived;
  // `undefined` until the first read answers; then the newest seq seen, or
  // null for a run that had none.
  const newestSeen = useRef<number | null | undefined>(undefined);
  const notesRef = useRef(notes);
  notesRef.current = notes;
  // What the list shows now, read by the arrival effect without re-running it.
  const shownRef = useRef<(note: TeamNote) => boolean>(() => true);

  const newest = notes[0]?.seq ?? null;
  // Keyed on the newest seq alone: a re-read that changes nothing must not
  // restart the effect, whose cleanup would cancel the mark's timer for good.
  useEffect(() => {
    if (!loaded) {
      return;
    }
    const before = newestSeen.current;
    if (before === undefined) {
      newestSeen.current = newest;
      return;
    }
    if (newest === null || (before !== null && newest <= before)) {
      return;
    }
    newestSeen.current = newest;
    const fresh = notesRef.current
      .filter((note) => before === null || note.seq > before)
      .map((note) => note.seq);
    // One batch while the mark is up: a second arrival joins the first, so
    // its count — and the announced text — changes and is heard.
    const batch = new Set([...arrivedRef.current, ...fresh]);
    setArrived(batch);
    // Only a reader scrolled away has not seen an arrival at the top.
    const away = (listRef.current?.scrollTop ?? 0) > 0;
    if (
      away &&
      notesRef.current.some(
        (note) => fresh.includes(note.seq) && shownRef.current(note),
      )
    ) {
      setNewAbove(true);
    }
    setAnnouncement(
      `${batch.size} new team ${batch.size === 1 ? 'note' : 'notes'}`,
    );
  }, [loaded, newest]);

  // Its own effect, so nothing but a newer arrival can cancel the clearing:
  // the announcement goes with the mark, so the next identical one is heard.
  useEffect(() => {
    if (arrived.size === 0) {
      return;
    }
    const timer = setTimeout(() => {
      setArrived(new Set());
      setAnnouncement('');
    }, ARRIVAL_MARK_MS);
    return () => clearTimeout(timer);
  }, [arrived]);
  const authors = useMemo(
    () => [...new Set(notes.map((note) => agentName(note.nodeId)))].sort(),
    [notes, agentName],
  );
  const kinds = useMemo(
    () => TEAM_NOTE_KINDS.filter((kind) => notes.some((n) => n.kind === kind)),
    [notes],
  );

  if (notes.length === 0) {
    return null;
  }

  const passes = (note: TeamNote): boolean =>
    (pickedKinds.size === 0 || pickedKinds.has(note.kind)) &&
    (pickedAuthors.size === 0 || pickedAuthors.has(agentName(note.nodeId)));
  shownRef.current = passes;
  const matching = notes.filter(passes);
  const clear = (): void => {
    setPickedKinds(new Set());
    setPickedAuthors(new Set());
  };
  const toggle = (value: string): void => {
    if (value.startsWith('kind:')) {
      const kind = value.slice('kind:'.length) as TeamNoteKind;
      setPickedKinds((was) => {
        const next = new Set(was);
        if (!next.delete(kind)) {
          next.add(kind);
        }
        return next;
      });
    } else if (value.startsWith('author:')) {
      const name = value.slice('author:'.length);
      setPickedAuthors((was) => {
        const next = new Set(was);
        if (!next.delete(name)) {
          next.add(name);
        }
        return next;
      });
    }
  };

  return (
    <PanelSection
      label="Team notes"
      action={
        <TeamNotesFilter
          kinds={kinds}
          authors={authors}
          pickedKinds={pickedKinds}
          pickedAuthors={pickedAuthors}
          onToggle={toggle}
          onClear={clear}
        />
      }>
      <span aria-live="polite" className="sr-only">
        {announcement}
      </span>
      {matching.length === 0 ? (
        <div className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
          <span>No notes match</span>
          <Button type="button" variant="ghost" size="sm" onClick={clear}>
            Clear filters
          </Button>
        </div>
      ) : (
        <div className="relative">
          {scrolled && newAbove ? (
            <Button
              type="button"
              size="sm"
              className="absolute top-1 left-1/2 z-10 -translate-x-1/2 shadow-panel-sm"
              onClick={() => {
                setNewAbove(false);
                listRef.current?.scrollTo({ top: 0 });
              }}>
              New notes
            </Button>
          ) : null}
          <div
            ref={attachList}
            className="max-h-80 overflow-y-auto"
            onScroll={(event) => {
              const away = event.currentTarget.scrollTop > 0;
              setScrolled(away);
              if (!away) {
                setNewAbove(false);
              }
            }}>
            <ul className="m-0 flex list-none flex-col gap-1 p-0">
              {matching.slice(0, shown).map((note) => (
                <TeamNoteEntry
                  key={note.seq}
                  note={note}
                  author={teamNoteAuthor(note, agentName)}
                  arrived={arrived.has(note.seq)}
                  onJump={onJump}
                />
              ))}
            </ul>
            {matching.length > shown ? (
              <Button
                type="button"
                variant="ghost"
                size="sm"
                className="w-full"
                onClick={() => setShown((was) => was + TEAM_NOTES_PAGE)}>
                Show older ({matching.length - shown})
              </Button>
            ) : null}
          </div>
        </div>
      )}
    </PanelSection>
  );
}
