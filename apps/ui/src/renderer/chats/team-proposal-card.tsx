/** What one Approve writes, said under a replacement: every file it changes and what is kept. */
function approvalNote(proposal: ParsedLibraryProposal): string {
  const { overlay, project, replacesName } = proposal;
  const teamChanges = proposal.diff?.identical !== true;
  const changes = [
    teamChanges ? `overwrites ${replacesName}` : null,
    overlay === null
      ? null
      : `changes ${overlay.projectName}’s overlay of ${teamChanges ? 'it' : replacesName}`,
    project === null
      ? null
      : `changes the instructions of ${project.projectName}`,
  ].filter((change): change is string => change !== null);
  const kept = teamChanges
    ? [
        overlay === null
          ? 'the current file is backed up first'
          : 'the current files are backed up first',
        project === null
          ? null
          : `${project.projectName}’s instructions are put back if the team cannot be written`,
      ].filter((part): part is string => part !== null)
    : ['the shared team stays as it is'];
  return `Approving ${joinedChanges(changes)}; ${kept.join(', and ')}.`;
}

function joinedChanges(changes: readonly string[]): string {
  return changes.length <= 2
    ? changes.join(' and ')
    : `${changes.slice(0, -1).join(', ')} and ${changes.at(-1)}`;
}

/** What an approval saved, naming the team file only when it wrote one. */
function savedText(proposal: ParsedLibraryProposal, slug: string): string {
  const { diff, overlay, project } = proposal;
  const saved = [
    overlay === null ? null : `${overlay.projectName}’s overlay`,
    project === null ? null : `${project.projectName}’s instructions`,
  ].filter((part): part is string => part !== null);
  return diff?.identical === true && saved.length > 0
    ? `✓ Saved ${joinedChanges(saved)}`
    : `✓ Saved as “${slug}”`;
}

/** The props every team card takes, whatever its mode. */
interface TeamProposalCardProps {
  proposal: ParsedTeamProposal;
  /** null while pending; the user's decision once the verdict item arrived. */
  verdict: boolean | null;
  /** The note that decision carried, read back from the same verdict item. */
  note?: string | null;
  /** What the daemon did with an approval, from the same verdict item. */
  outcome?: ProposalOutcome | null;
  /** A newer proposal or the chat's archiving took the card down. */
  expired: boolean;
  /** The approval request's id: folds are remembered per thread under it. */
  memoryKey?: string;
  onRespond: (allow: boolean, answer?: string) => void;
  /** Open the saved team in the editor; absent, nothing offers to. */
  onOpenTeam?: (slug: string) => void;
  /** Open the project a card saved without touching the team; absent, nothing offers to. */
  onOpenProject?: (projectId: string) => void;
}

/**
 * A team an agent proposes: propose_team's card for the library, or the
 * run_team card that starts a team in this chat or changes a running one.
 * Approve writes it (the daemon does, never the agent); Decline writes
 * nothing; a note typed beside either reaches the agent with the verdict.
 */
export function TeamProposalCard({
  proposal,
  ...rest
}: TeamProposalCardProps): React.JSX.Element {
  return isRunProposal(proposal) ? (
    <RunTeamCard proposal={proposal} {...rest} />
  ) : (
    <LibraryTeamCard proposal={proposal} {...rest} />
  );
}

/**
 * A library card. It shows what an approval commits to: every member and
 * whether it asks before running tools — any that would not are named in a
 * strip above all else — and, for a replacement, what changes against the
 * saved file. Once answered it keeps the roster and the changes, and says what
 * became of an approval: saved (with a way to open it) or not.
 */
function LibraryTeamCard({
  proposal,
  verdict,
  note = null,
  outcome = null,
  expired,
  memoryKey,
  onRespond,
  onOpenTeam,
  onOpenProject,
}: Omit<TeamProposalCardProps, 'proposal'> & {
  proposal: ParsedLibraryProposal;
}): React.JSX.Element {
  const { team, diff, overlay, project } = proposal;
  const savedProject = diff?.identical === true ? (overlay ?? project) : null;
  const stages = team.stages ?? [];
  const { sending, respond } = useOneShotVerdict(verdict, expired, onRespond);
  const remembered = (name: string) =>
    memoryKey === undefined ? undefined : `${name}:${memoryKey}`;
  const [stageTextShown, setStageTextShown] = useThreadFlag(
    remembered('team-stage-text'),
    false,
  );
  const [rosterShown, setRosterShown] = useThreadFlag(
    remembered('team-roster'),
    false,
  );
  const verdictNote = useVerdictNote(respond);
  const titleId = useId();

  const roster = useMemo(() => rosterOf(team), [team]);
  const marks = useMemo(() => previewMarks(diff), [diff]);
  const stageMarks = useMemo(() => stageMarksOf(diff), [diff]);
  const changedAgents = roster.filter((row) => marks.has(row.member.id));
  const changedStages = stages.filter((stage) => stageMarks.has(stage.id));
  const changes = useMemo(
    () => (diff === null ? null : diffRows(diff, team)),
    [diff, team],
  );
  const scanText = useMemo(() => proposalScanText(proposal), [proposal]);
  const gate = useHazardGate(scanText);
  const firstMessage = team.members.find(
    (member) => member.id === team.triggers[0]?.member,
  );

  const teamBody = (
    <>
      {changes !== null ? (
        <TeamDiffList rows={changes} memoryKey={remembered('team-diff')} />
      ) : null}
      {stages.length > 0 ? (
        <div
          data-slot="team-proposal-stages"
          className="flex flex-col gap-1.5 rounded-md border border-border p-2">
          <span className="text-xs font-medium">Stages every run walks</span>
          <StageGraph stages={stages} />
          <Fold
            slot="team-proposal-stage-fold"
            noun={['stage', 'stages']}
            total={stages.length}
            replacing={proposal.mode === 'replace'}
            open={stageTextShown}
            onToggle={() => setStageTextShown((current) => !current)}
            changed={{
              count: changedStages.length,
              content: <StageList stages={changedStages} marks={stageMarks} />,
            }}
            all={<StageList stages={stages} marks={stageMarks} />}
          />
        </div>
      ) : null}
      <Fold
        slot="team-proposal-agents"
        noun={['agent', 'agents']}
        total={roster.length}
        replacing={proposal.mode === 'replace'}
        open={rosterShown}
        onToggle={() => setRosterShown((current) => !current)}
        changed={{
          count: changedAgents.length,
          content: <Roster rows={changedAgents} marks={marks} />,
        }}
        all={<Roster rows={roster} marks={marks} />}
      />
    </>
  );

  return (
    <Card
      role="group"
      aria-labelledby={titleId}
      data-slot="team-proposal-card"
      className="flex min-w-0 flex-col gap-3 border-primary/40 p-3">
      <div className="flex flex-wrap items-center gap-x-2 gap-y-1">
        <TeamIcon aria-hidden="true" className="size-4 shrink-0 text-primary" />
        <span id={titleId} className="min-w-0 text-sm font-medium break-words">
          {team.name}
        </span>
        {proposal.mode === 'create' ? (
          <Badge variant="outline">New</Badge>
        ) : (
          <Badge variant="secondary" className="max-w-full truncate">
            {diff?.identical === true
              ? `${proposal.replacesName} stays as it is`
              : `Replaces ${proposal.replacesName}`}
          </Badge>
        )}
        <span className="text-xs text-muted-foreground">
          {plural(roster.length, 'member', 'members')}
          {firstMessage === undefined
            ? null
            : ` · first message to ${firstMessage.name}`}
          {stages.length > 0
            ? ` · ${plural(stages.length, 'stage', 'stages')}`
            : null}
        </span>
      </div>
      <ProposalWords proposal={proposal} />
      <HazardWarning hazards={gate.hazards} subject="this proposal" />
      {overlay === null && project === null ? (
        teamBody
      ) : (
        <>
          {diff?.identical === true ? null : (
            <ProposalSection title="Shared team" slot="team-proposal-shared">
              {teamBody}
            </ProposalSection>
          )}
          {overlay === null ? null : (
            <ProposalSection
              title={`${overlay.projectName} overlay`}
              slot="team-proposal-overlay">
              <UnifiedDiff diff={overlay.diffText} />
            </ProposalSection>
          )}
          {project === null ? null : (
            <ProposalSection
              title={`${project.projectName} instructions`}
              slot="team-proposal-project">
              <UnifiedDiff diff={project.diffText} />
            </ProposalSection>
          )}
        </>
      )}
      {expired && verdict === null ? (
        <p className="m-0 text-xs text-muted-foreground">
          ⏱ expired — a newer proposal replaced it, or the chat was archived
        </p>
      ) : sending ? (
        <p className="m-0 text-xs text-muted-foreground">Sending…</p>
      ) : verdict === null ? (
        <VerdictForm
          above={
            proposal.mode === 'replace' ? (
              <p className="m-0 text-xs text-muted-foreground">
                {approvalNote(proposal)}
              </p>
            ) : null
          }
          note={verdictNote}
          gate={gate}
          approveLabel="Approve"
        />
      ) : (
        <div aria-live="polite" className="flex flex-col gap-1.5">
          {!verdict ? (
            <p className="m-0 text-xs text-destructive">✗ Declined</p>
          ) : outcome?.kind === 'saved' ? (
            <div className="flex flex-wrap items-center gap-2">
              <p className="m-0 text-xs text-success">
                {savedText(proposal, outcome.slug)}
              </p>
              {savedProject !== null ? (
                onOpenProject ? (
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    className="max-sm:min-h-11"
                    onClick={() => onOpenProject(savedProject.projectId)}>
                    Open project
                  </Button>
                ) : null
              ) : onOpenTeam ? (
                <Button
                  type="button"
                  variant="outline"
                  size="sm"
                  className="max-sm:min-h-11"
                  onClick={() => onOpenTeam(outcome.slug)}>
                  Open team
                </Button>
              ) : null}
            </div>
          ) : outcome?.kind === 'not-saved' ? (
            <>
              <p className="m-0 text-xs text-destructive">✗ Not saved</p>
              <p
                data-slot="team-not-saved"
                className="m-0 rounded-md border border-destructive/30 bg-destructive/10 px-2.5 py-1.5 text-xs text-destructive">
                {notSavedText(outcome.cause, proposal)}
              </p>
            </>
          ) : (
            <p className="m-0 text-xs text-success">✓ Approved</p>
          )}
          <VerdictNoteEcho note={note} />
        </div>
      )}
    </Card>
  );
}

/** The agent's own summary and why, as a card shows them: neither is trusted. */
function ProposalWords({
  proposal,
}: {
  proposal: Pick<ParsedTeamProposal, 'summary' | 'reason'>;
}): React.JSX.Element | null {
  const { summary, reason } = proposal;
  if (summary === null && reason === null) {
    return null;
  }
  return (
    <div className="flex flex-col gap-1.5">
      {summary === null ? null : (
        <ClampedText
          text={summary}
          lines={3}
          slot="team-proposal-summary"
          className="text-sm"
        />
      )}
      {reason === null ? null : (
        <div className="flex min-w-0 flex-col gap-0.5">
          <span className="text-xs font-medium">Why</span>
          <ClampedText
            text={reason}
            lines={3}
            slot="team-proposal-reason"
            className="text-xs text-muted-foreground"
          />
        </div>
      )}
    </div>
  );
}

type VerdictNote = ReturnType<typeof useVerdictNote>;
type HazardGate = ReturnType<typeof useHazardGate>;

/**
 * The note box and the two verdict buttons every team card ends with. Approve
 * is held by an unacknowledged hazard, a note too long to send, or
 * `approveHeld`; `approveHint` says why, in one line under the buttons.
 */
function VerdictForm({
  note,
  gate,
  approveLabel,
  above = null,
  approveHeld = false,
  approveHint = null,
}: {
  note: VerdictNote;
  gate: HazardGate;
  approveLabel: string;
  above?: React.ReactNode;
  approveHeld?: boolean;
  approveHint?: string | null;
}): React.JSX.Element {
  return (
    <div className="flex flex-col gap-2">
      {above}
      <VerdictNoteField
        draft={note.draft}
        onChange={note.setDraft}
        tooLong={note.tooLong}
        placeholder="Optional — what to change, or why not"
      />
      {gate.hazards.gates ? (
        <HazardAck
          id={gate.ackId}
          checked={gate.acknowledged}
          onCheckedChange={gate.setAcknowledged}
        />
      ) : null}
      <div className="flex gap-2">
        <Button
          type="button"
          className="max-sm:min-h-11"
          onClick={() => note.send(true)}
          disabled={note.tooLong || gate.blocksApprove || approveHeld}>
          {approveLabel}
        </Button>
        <Button
          type="button"
          variant="outline"
          className="max-sm:min-h-11"
          onClick={() => note.send(false)}
          disabled={note.tooLong}>
          Decline
        </Button>
      </div>
      {approveHint === null ? null : (
        <p className="m-0 text-xs text-muted-foreground">{approveHint}</p>
      )}
    </div>
  );
}

