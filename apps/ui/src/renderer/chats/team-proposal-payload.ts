/**
 * The `propose_team` and `run_team` cards' payload: the `input` of their
 * `approval_request` row, and the `outcome` their verdict row carries once
 * answered.
 *
 * TWIN PARSER: `TeamProposalSchema` (`apps/daemon/src/v1/teams/teams.types.ts`),
 * with its run arms `RunStartProposalSchema`, `RunChangeProposalSchema` and
 * `RunTeamChangeSchema`, `TeamDiff` (`apps/daemon/src/v1/teams/utils/team-diff.ts`)
 * and `TeamProposalOutcome` (`apps/daemon/src/v1/agents/chat.types.ts`); the
 * replace arm's optional `overlay` and `project` are read tolerantly, each
 * dropped whole when any part of it does not read, and never make the card
 * unreadable. The
 * daemon checked the team strictly before raising the card, so anything
 * here that does not read is version skew — the card then falls back to the
 * permission body rather than drawing half a proposal. A card raised while
 * teams were node graphs is read through `teamFromLegacyGraph`, the twin of
 * the daemon's `teamFromWorkflow` (`apps/daemon/src/v1/teams/utils/team-from-workflow.ts`).
 */

export interface ProposalDiffField {
  field: string;
  /** JSON of the old value, quoted and capped by the daemon. */
  before: string;
  after: string;
}

export interface ProposalDiffEntry {
  id: string;
  fields: ProposalDiffField[];
}

/** A team field a replacement changes; `values` is null on a card raised before they were quoted. */
export interface ProposalTeamField {
  field: string;
  values: Omit<ProposalDiffField, 'field'> | null;
}

/**
 * A removed entry quotes what it held; on a card raised before that, it is
 * its id with no fields. An added entry is an id, read whole from the team.
 */
export interface ProposalDiff {
  identical: boolean;
  teamFields: ProposalTeamField[];
  addedMembers: string[];
  removedMembers: ProposalDiffEntry[];
  changedMembers: ProposalDiffEntry[];
  addedBlocks: string[];
  removedBlocks: ProposalDiffEntry[];
  changedBlocks: ProposalDiffEntry[];
  addedStages: string[];
  removedStages: ProposalDiffEntry[];
  changedStages: ProposalDiffEntry[];
}

/** A replacement's change to one project's overlay of the team. */
export interface ProposalOverlay {
  projectId: string;
  projectName: string;
  /** The whole new overlay document. */
  overlay: TeamOverlay;
  /** The overlay file's hash when the card was raised; null: no file. */
  baseHash: string | null;
  /** Unified diff of the overlay's YAML, before then after. */
  diffText: string;
}

/** A replacement's change to the instructions of a project that runs the team. */
export interface ProposalProject {
  projectId: string;
  projectName: string;
  /** The instructions revision the change was read at. */
  baseRevision: number;
  /** Unified diff of the blocks under their titles, before then after. */
  diffText: string;
}

const RUN_CHANGE_FIELDS = ['role', 'instructions', 'model', 'effort'] as const;

/** What every card carries, whatever its mode. */
interface ProposalCommon {
  /** A library card's team, or a run's team as the run would have it. */
  team: Team;
  /** The library file an approval writes, fixed when the card was raised; empty on a run card. */
  slug: string;
  /** The agent's own line, never trusted as a description of the change. */
  summary: string | null;
  /** The agent's own account of why, never trusted either. */
  reason: string | null;
  /** Every agent that runs tools without asking, as the daemon names them. */
  autoAgents: string[];
}

/** A propose_team card: a new library team, or a replacement of a saved one. */
export interface ParsedLibraryProposal extends ProposalCommon {
  mode: 'create' | 'replace';
  /** Replace only: the name of the team being overwritten. */
  replacesName: string | null;
  /** Replace only; null on a new team. */
  diff: ProposalDiff | null;
  /** Replace only; null when the card leaves every overlay alone. */
  overlay: ProposalOverlay | null;
  /** Replace only; null when the card leaves every project's instructions alone. */
  project: ProposalProject | null;
}

/** One agent a run_team card names: the daemon's own row for it. */
export interface RunCardMember {
  memberId: string;
  name: string;
  role: string;
  agent: AgentKind;
  /** null: the CLI's default model. */
  model: string | null;
  approval: ApprovalMode;
}

export type RunChangeField = (typeof RUN_CHANGE_FIELDS)[number];

/** One field of a running agent a change sets: what it reads now and what it would read. */
export interface RunChangeValue {
  field: RunChangeField;
  /** null: the field was unset. */
  before: string | null;
  after: string | null;
}

/** One line of a run_team change card. */
export type RunChange =
  | { op: 'add'; member: RunCardMember; task: string | null }
  | { op: 'remove'; memberId: string; name: string }
  | {
      op: 'update';
      memberId: string;
      name: string;
      fields: RunChangeValue[];
      task: string | null;
    };

/** A run_team start card: this chat becomes the team, led by its own agent. */
export interface ParsedRunStart extends ProposalCommon {
  mode: 'run-start';
  plan: string[];
  lead: RunCardMember;
  members: { member: RunCardMember; task: string }[];
}

/** A run_team change card: the running team's roster or instructions, for this run only. */
export interface ParsedRunChange extends ProposalCommon {
  mode: 'run-change';
  changes: RunChange[];
}

export type ParsedRunProposal = ParsedRunStart | ParsedRunChange;

export type ParsedTeamProposal = ParsedLibraryProposal | ParsedRunProposal;

export function isRunProposal(
  proposal: ParsedTeamProposal,
): proposal is ParsedRunProposal {
  return proposal.mode === 'run-start' || proposal.mode === 'run-change';
}

const NOT_SAVED_CAUSES = [
  'changed',
  'exists',
  'gone',
  'not-closed',
  'write-failed',
] as const;

export type NotSavedCause = (typeof NOT_SAVED_CAUSES)[number];

export type ProposalOutcome =
  | { kind: 'saved'; slug: string }
  /** `cause` null: a cause this build does not know. */
  | { kind: 'not-saved'; cause: NotSavedCause | null }
  | { kind: 'started' }
  | { kind: 'not-started'; causes: string[] }
  | { kind: 'changed' }
  | { kind: 'not-changed'; reason: string };

function isNotSavedCause(value: unknown): value is NotSavedCause {
  return (NOT_SAVED_CAUSES as readonly unknown[]).includes(value);
}

type Fields = Record<string, unknown>;

function record(value: unknown): Fields | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Fields)
    : null;
}

function isString(value: unknown): value is string {
  return typeof value === 'string';
}

function stringList(value: unknown): string[] | null {
  return Array.isArray(value) && value.every(isString) ? value : null;
}

function oneOf<T extends string>(
  values: Readonly<Record<string, T>>,
  value: unknown,
): value is T {
  return (Object.values(values) as unknown[]).includes(value);
}

function optionalString(value: unknown): boolean {
  return value === undefined || isString(value);
}

function readAgentFields(fields: Fields): boolean {
  return (
    oneOf(AgentKind, fields.agent) &&
    optionalString(fields.model) &&
    optionalString(fields.effort)
  );
}

function readPool(pool: unknown): boolean {
  return (
    pool === undefined ||
    (Array.isArray(pool) &&
      pool.every((entry) => {
        const member = record(entry);
        return (
          member !== null &&
          readAgentFields(member) &&
          (member.approval === undefined ||
            oneOf(ApprovalMode, member.approval))
        );
      }))
  );
}

function isMember(value: unknown): boolean {
  const member = record(value);
  return (
    member !== null &&
    isString(member.id) &&
    isString(member.name) &&
    readAgentFields(member) &&
    oneOf(ApprovalMode, member.approval) &&
    optionalString(member.role) &&
    optionalString(member.instructions) &&
    optionalString(member.character) &&
    readPool(member.pool)
  );
}

function isBlock(value: unknown): boolean {
  const block = record(value);
  return (
    block !== null &&
    isString(block.id) &&
    isString(block.title) &&
    isString(block.text) &&
    (block.audience === 'everyone' || stringList(block.audience) !== null)
  );
}

function isTrigger(value: unknown): boolean {
  const trigger = record(value);
  return (
    trigger !== null &&
    trigger.kind === 'first-message' &&
    isString(trigger.member)
  );
}

function isStage(value: unknown): boolean {
  const stage = record(value);
  return (
    stage !== null &&
    isString(stage.id) &&
    isString(stage.title) &&
    isString(stage.goal) &&
    optionalString(stage.howToWork) &&
    (stage.responsible === undefined ||
      stringList(stage.responsible) !== null) &&
    (stage.next === undefined || stringList(stage.next) !== null)
  );
}

function readMemberTeam(team: Fields): Team | null {
  if (
    !isString(team.name) ||
    !optionalString(team.description) ||
    !oneOf(TeamMode, team.mode) ||
    !Array.isArray(team.members) ||
    !team.members.every(isMember) ||
    !Array.isArray(team.triggers) ||
    !team.triggers.every(isTrigger) ||
    !Array.isArray(team.instructionBlocks) ||
    !team.instructionBlocks.every(isBlock) ||
    !(
      team.stages === undefined ||
      (Array.isArray(team.stages) && team.stages.every(isStage))
    )
  ) {
    return null;
  }
  return team as unknown as Team;
}

/**
 * A team proposed while teams were node graphs, as members: agent nodes
 * become members (the public `description` their role, the private `role`
 * their instructions), the trigger's data edge names the member that handles
 * the first message, instruction nodes become blocks for the agents their
 * edges reached (all of them: everyone), and a stage's usual owner its one
 * responsible member. Null when the graph does not read.
 */
export function teamFromLegacyGraph(value: Fields): Team | null {
  const nodes = Array.isArray(value.nodes) ? value.nodes.map(record) : null;
  const edges = Array.isArray(value.edges ?? [])
    ? ((value.edges ?? []) as unknown[]).map(record)
    : null;
  if (
    !isString(value.name) ||
    nodes === null ||
    edges === null ||
    nodes.some((node) => node === null || !isString(node.id)) ||
    edges.some(
      (edge) => edge === null || !isString(edge.from) || !isString(edge.to),
    )
  ) {
    return null;
  }
  const graphNodes = nodes as Fields[];
  const graphEdges = edges as Fields[];
  const agents = graphNodes.filter((node) => node.kind === 'agent');
  if (
    !agents.every(
      (node) =>
        readAgentFields(node) &&
        (node.approval === undefined || oneOf(ApprovalMode, node.approval)) &&
        readPool(node.pool),
    )
  ) {
    return null;
  }
  const agentIds = agents.map((node) => node.id as string);
  const fed = graphNodes
    .filter((node) => node.kind === 'trigger')
    .flatMap((trigger) =>
      graphEdges.filter(
        (edge) =>
          (edge.kind ?? 'data') === 'data' &&
          edge.from === trigger.id &&
          agentIds.includes(edge.to as string),
      ),
    )
    .map((edge) => edge.to as string)[0];
  const lead = fed ?? agentIds[0];
  const members: TeamMember[] = agents.map((node) => {
    const {
      kind: _kind,
      description,
      role,
      name,
      approval,
      ...settings
    } = node;
    void _kind;
    return {
      ...(settings as Omit<TeamMember, 'name' | 'approval'>),
      name: isString(name) ? name : (node.id as string),
      approval: (approval ?? 'auto') as TeamMember['approval'],
      ...(isString(description) ? { role: description } : {}),
      ...(isString(role) ? { instructions: role } : {}),
    };
  });
  const instructionBlocks: InstructionBlock[] = graphNodes
    .filter((node) => node.kind === 'instruction')
    .map((node) => {
      const reached = new Set(
        graphEdges
          .filter(
            (edge) =>
              edge.kind === 'instruction' &&
              edge.from === node.id &&
              agentIds.includes(edge.to as string),
          )
          .map((edge) => edge.to as string),
      );
      const everyone =
        agentIds.length > 0 && agentIds.every((id) => reached.has(id));
      return {
        id: node.id as string,
        title: isString(node.name) ? node.name : (node.id as string),
        text: isString(node.instructions) ? node.instructions : '',
        audience: everyone
          ? 'everyone'
          : agentIds.filter((id) => reached.has(id)),
      };
    });
  const stages = Array.isArray(value.stages)
    ? value.stages.map(record).map((stage) =>
        stage === null
          ? null
          : {
              id: stage.id,
              title: stage.title,
              ...(isString(stage.instructions)
                ? { howToWork: stage.instructions }
                : {}),
              goal: stage.doneWhen,
              ...(isString(stage.ownerHint)
                ? { responsible: [stage.ownerHint] }
                : {}),
              ...(stage.next === undefined ? {} : { next: stage.next }),
            },
      )
    : undefined;
  if (stages !== undefined && !stages.every(isStage)) {
    return null;
  }
  return {
    name: value.name,
    ...(isString(value.description) ? { description: value.description } : {}),
    ...(typeof value.maxActiveTurns === 'number'
      ? { maxActiveTurns: value.maxActiveTurns }
      : {}),
    mode: TeamMode.Lead,
    members,
    triggers:
      lead === undefined ? [] : [{ kind: 'first-message', member: lead }],
    instructionBlocks,
    ...(stages === undefined ? {} : { stages: stages as Team['stages'] }),
  };
}

function readTeam(value: unknown): Team | null {
  const team = record(value);
  if (team === null) {
    return null;
  }
  return Array.isArray(team.members)
    ? readMemberTeam(team)
    : teamFromLegacyGraph(team);
}

function readDiffField(raw: unknown): ProposalDiffField | null {
  const field = record(raw);
  return field !== null &&
    isString(field.field) &&
    isString(field.before) &&
    isString(field.after)
    ? { field: field.field, before: field.before, after: field.after }
    : null;
}

function readDiffEntry(raw: unknown): ProposalDiffEntry | null {
  const entry = record(raw);
  if (entry === null || !isString(entry.id) || !Array.isArray(entry.fields)) {
    return null;
  }
  const fields = entry.fields.map(readDiffField);
  return fields.every((field) => field !== null)
    ? { id: entry.id, fields: fields }
    : null;
}

function readList<T>(
  value: unknown,
  read: (raw: unknown) => T | null,
): T[] | null {
  if (!Array.isArray(value)) {
    return null;
  }
  const items = value.map(read);
  return items.every((item) => item !== null) ? items : null;
}

const readChangedEntries = (value: unknown): ProposalDiffEntry[] | null =>
  readList(value, readDiffEntry);

const readRemovedEntries = (value: unknown): ProposalDiffEntry[] | null =>
  readList(value, (raw) =>
    isString(raw) ? { id: raw, fields: [] } : readDiffEntry(raw),
  );

const readTeamFields = (value: unknown): ProposalTeamField[] | null =>
  readList(value, (raw): ProposalTeamField | null => {
    if (isString(raw)) {
      return { field: raw, values: null };
    }
    const quoted = readDiffField(raw);
    return quoted === null
      ? null
      : {
          field: quoted.field,
          values: { before: quoted.before, after: quoted.after },
        };
  });

function readDiff(value: unknown): ProposalDiff | null {
  const diff = record(value);
  if (diff === null || typeof diff.identical !== 'boolean') {
    return null;
  }
  const teamFields = readTeamFields(diff.teamFields ?? diff.workflowFields);
  const addedMembers = stringList(diff.addedMembers ?? diff.addedNodes);
  const removedMembers = readRemovedEntries(
    diff.removedMembers ?? diff.removedNodes,
  );
  const changedMembers = readChangedEntries(
    diff.changedMembers ?? diff.changedNodes,
  );
  const addedBlocks = stringList(diff.addedBlocks ?? []);
  const removedBlocks = readRemovedEntries(diff.removedBlocks ?? []);
  const changedBlocks = readChangedEntries(diff.changedBlocks ?? []);
  const addedStages = stringList(diff.addedStages);
  const removedStages = readRemovedEntries(diff.removedStages);
  const changedStages = readChangedEntries(diff.changedStages);
  if (
    teamFields === null ||
    addedMembers === null ||
    removedMembers === null ||
    changedMembers === null ||
    addedBlocks === null ||
    removedBlocks === null ||
    changedBlocks === null ||
    addedStages === null ||
    removedStages === null ||
    changedStages === null
  ) {
    return null;
  }
  return {
    identical: diff.identical,
    teamFields,
    addedMembers,
    removedMembers,
    changedMembers,
    addedBlocks,
    removedBlocks,
    changedBlocks,
    addedStages,
    removedStages,
    changedStages,
  };
}

function readOverlay(value: unknown): ProposalOverlay | null {
  const raw = record(value);
  const document = record(raw?.overlay);
  if (
    raw === null ||
    document === null ||
    !isString(raw.projectId) ||
    !isString(raw.projectName) ||
    !isString(raw.diffText) ||
    !(raw.baseHash === null || isString(raw.baseHash))
  ) {
    return null;
  }
  return {
    projectId: raw.projectId,
    projectName: raw.projectName,
    overlay: document,
    baseHash: raw.baseHash,
    diffText: raw.diffText,
  };
}

function readProject(value: unknown): ProposalProject | null {
  const raw = record(value);
  if (
    raw === null ||
    !isString(raw.projectId) ||
    !isString(raw.projectName) ||
    !isString(raw.diffText) ||
    typeof raw.baseRevision !== 'number' ||
    !Number.isInteger(raw.baseRevision)
  ) {
    return null;
  }
  return {
    projectId: raw.projectId,
    projectName: raw.projectName,
    baseRevision: raw.baseRevision,
    diffText: raw.diffText,
  };
}

function nullableString(value: unknown): value is string | null {
  return value === null || isString(value);
}

function isRunChangeField(value: unknown): value is RunChangeField {
  return (RUN_CHANGE_FIELDS as readonly unknown[]).includes(value);
}

function readRunMember(raw: unknown): RunCardMember | null {
  const member = record(raw);
  if (member === null) {
    return null;
  }
  const { agent, approval, model } = member;
  if (
    !isString(member.memberId) ||
    !isString(member.name) ||
    !isString(member.role) ||
    !oneOf(AgentKind, agent) ||
    !nullableString(model) ||
    !oneOf(ApprovalMode, approval)
  ) {
    return null;
  }
  return {
    memberId: member.memberId,
    name: member.name,
    role: member.role,
    agent,
    model,
    approval,
  };
}

function readRunStartMember(
  raw: unknown,
): { member: RunCardMember; task: string } | null {
  const entry = record(raw);
  if (entry === null || !isString(entry.task)) {
    return null;
  }
  const member = readRunMember(entry.member);
  return member === null ? null : { member, task: entry.task };
}

function readRunChangeValue(raw: unknown): RunChangeValue | null {
  const value = record(raw);
  if (
    value === null ||
    !isRunChangeField(value.field) ||
    !nullableString(value.before) ||
    !nullableString(value.after)
  ) {
    return null;
  }
  return {
    field: value.field,
    before: value.before,
    after: value.after,
  };
}

function readRunChange(raw: unknown): RunChange | null {
  const change = record(raw);
  if (change === null) {
    return null;
  }
  if (change.op === 'add') {
    const member = readRunMember(change.member);
    return member === null || !nullableString(change.task)
      ? null
      : { op: 'add', member, task: change.task };
  }
  if (change.op === 'remove') {
    return isString(change.memberId) && isString(change.name)
      ? { op: 'remove', memberId: change.memberId, name: change.name }
      : null;
  }
  if (
    change.op !== 'update' ||
    !isString(change.memberId) ||
    !isString(change.name) ||
    !nullableString(change.task)
  ) {
    return null;
  }
  const fields = readList(change.fields, readRunChangeValue);
  return fields === null
    ? null
    : {
        op: 'update',
        memberId: change.memberId,
        name: change.name,
        fields,
        task: change.task,
      };
}

function readRunProposal(
  proposal: Fields,
  common: ProposalCommon,
): ParsedRunProposal | null {
  if (proposal.mode === 'run-start') {
    const plan = stringList(proposal.plan);
    const lead = readRunMember(proposal.lead);
    const members = readList(proposal.members, readRunStartMember);
    return plan === null || lead === null || members === null
      ? null
      : { ...common, mode: 'run-start', plan, lead, members };
  }
  const changes = readList(proposal.changes, readRunChange);
  return changes === null ? null : { ...common, mode: 'run-change', changes };
}

function trimmedText(value: unknown): string | null {
  return isString(value) && value.trim() !== '' ? value.trim() : null;
}

/**
 * The proposal on a card, or null to draw the permission body instead. A card
 * raised before the rename holds its team under `workflow` and its diff's own
 * field list under `workflowFields`.
 */
export function readTeamProposal(input: unknown): ParsedTeamProposal | null {
  const proposal = record(input);
  if (proposal === null || !isString(proposal.slug)) {
    return null;
  }
  const team = readTeam(proposal.team ?? proposal.workflow);
  const autoAgents = stringList(proposal.autoAgents);
  if (team === null || autoAgents === null) {
    return null;
  }
  const common: ProposalCommon = {
    team,
    slug: proposal.slug,
    summary: trimmedText(proposal.summary),
    reason: trimmedText(proposal.reason),
    autoAgents,
  };
  if (proposal.mode === 'run-start' || proposal.mode === 'run-change') {
    return readRunProposal(proposal, common);
  }
  if (proposal.mode === 'create') {
    return {
      ...common,
      mode: 'create',
      replacesName: null,
      diff: null,
      overlay: null,
      project: null,
    };
  }
  if (proposal.mode !== 'replace' || !isString(proposal.replacesName)) {
    return null;
  }
  const diff = readDiff(proposal.diff);
  if (diff === null) {
    return null;
  }
  return {
    ...common,
    mode: 'replace',
    replacesName: proposal.replacesName,
    diff,
    overlay: readOverlay(proposal.overlay),
    project: readProject(proposal.project),
  };
}

/** What became of an approval, or null when the verdict row carries none. */
export function readProposalOutcome(raw: unknown): ProposalOutcome | null {
  const outcome = record(raw);
  if (outcome === null) {
    return null;
  }
  if (outcome.kind === 'saved' && isString(outcome.slug)) {
    return { kind: 'saved', slug: outcome.slug };
  }
  if (outcome.kind === 'not-saved') {
    return {
      kind: 'not-saved',
      cause: isNotSavedCause(outcome.cause) ? outcome.cause : null,
    };
  }
  if (outcome.kind === 'started') {
    return { kind: 'started' };
  }
  if (outcome.kind === 'not-started') {
    const causes = stringList(outcome.causes);
    return causes === null ? null : { kind: 'not-started', causes };
  }
  if (outcome.kind === 'changed') {
    return { kind: 'changed' };
  }
  if (outcome.kind === 'not-changed' && isString(outcome.reason)) {
    return { kind: 'not-changed', reason: outcome.reason };
  }
  return null;
}

function collectStrings(value: unknown, into: string[]): void {
  if (typeof value === 'string') {
    into.push(value);
  } else if (Array.isArray(value)) {
    for (const entry of value) {
      collectStrings(entry, into);
    }
  } else if (typeof value === 'object' && value !== null) {
    for (const [key, entry] of Object.entries(value)) {
      into.push(key);
      collectStrings(entry, into);
    }
  }
}

/** The strings only one mode's card draws: a run's plan, lead, members or changes; a library card's diff and overlays. */
function scanPartsOf(proposal: ParsedTeamProposal): unknown[] {
  switch (proposal.mode) {
    case 'run-start':
      return [proposal.plan, proposal.lead, proposal.members];
    case 'run-change':
      return [proposal.changes];
    case 'create':
    case 'replace':
      return [
        proposal.diff,
        proposal.replacesName,
        proposal.overlay,
        proposal.project,
      ];
  }
}

/**
 * Every string the card can draw, for the Approve gate's hazard scan: the
 * team, the diff — its old side and removed ids included, which the
 * proposed team does not carry — and the agent's own lines. Object keys
 * too: an agent writes those (`modelParameters`), and the scan is cheaper
 * whole than proven narrower.
 *
 * Raw, not JSON: `JSON.stringify` escapes the C0 controls the card draws
 * verbatim. Joined by spaces, with line breaks and tabs turned to spaces,
 * because each is itself `\p{Cc}` and would gate every multi-line role.
 */
export function proposalScanText(proposal: ParsedTeamProposal): string {
  const strings: string[] = [];
  collectStrings(
    [
      proposal.team,
      proposal.summary,
      proposal.reason,
      proposal.autoAgents,
      scanPartsOf(proposal),
    ],
    strings,
  );
  // A quoted value arrives JSON-quoted and is drawn decoded (`shown`), so the
  // decoded form is scanned too: the quoted form hides a control character
  // behind its `\u` escape.
  const diff = isRunProposal(proposal) ? null : proposal.diff;
  const quoted = [
    ...(diff?.teamFields ?? []).flatMap(({ values }) =>
      values === null ? [] : [values],
    ),
    ...[
      ...(diff?.changedMembers ?? []),
      ...(diff?.removedMembers ?? []),
      ...(diff?.changedBlocks ?? []),
      ...(diff?.removedBlocks ?? []),
      ...(diff?.changedStages ?? []),
      ...(diff?.removedStages ?? []),
    ].flatMap(({ fields }) => fields),
  ];
  for (const { before, after } of quoted) {
    strings.push(shown(before), shown(after));
  }
  return strings.join(' ').replace(/[\n\t\r]/g, ' ');
}

/** Each member a replacement adds or changes, for the preview to mark. */
export function previewMarks(
  diff: ProposalDiff | null,
): ReadonlyMap<string, PreviewMark> {
  const marks = new Map<string, PreviewMark>();
  for (const { id } of diff?.changedMembers ?? []) {
    marks.set(id, 'changed');
  }
  for (const id of diff?.addedMembers ?? []) {
    marks.set(id, 'added');
  }
  return marks;
}

/** Each stage a replacement adds or changes; nothing on a new team. */
export function stageMarksOf(
  diff: ProposalDiff | null,
): ReadonlyMap<string, PreviewMark> {
  const marks = new Map<string, PreviewMark>();
  for (const { id } of diff?.changedStages ?? []) {
    marks.set(id, 'changed');
  }
  for (const id of diff?.addedStages ?? []) {
    marks.set(id, 'added');
  }
  return marks;
}

/** One member of the proposal, as a roster row. */
export interface RosterRow {
  member: TeamMember;
  /** The title of every instruction block addressed to this member. */
  instructions: string[];
}

/** The proposal's members in team order, each with the blocks it is in the audience of. */
export function rosterOf(team: Team): RosterRow[] {
  return team.members.map((member) => ({
    member,
    instructions: team.instructionBlocks
      .filter((block) => audienceReaches(block, member.id))
      .map((block) => block.title.trim() || block.id),
  }));
}

export type DiffMarker = 'changed' | 'added' | 'removed';

/** One line of the change list. */
export interface DiffRow {
  key: string;
  marker: DiffMarker;
  /** What the subject names: the team's own field, a member, a block, a stage. */
  scope: 'team' | 'member' | 'block' | 'stage';
  /** A team field's name, a member id, a block id or a stage id. */
  subject: string;
  /** For a changed field: which one, and from what to what. */
  detail: { field: string; before: string; after: string } | null;
  /** For an added or removed entry: each field it holds or held. */
  entry: DiffEntryField[];
  /** The whole line, when the generic wording does not fit a run's roster change. */
  label?: string;
  /** The change makes an agent run tools without asking. */
  toAuto: boolean;
}

export interface DiffEntryField {
  field: string;
  value: string;
}

/** How the daemon quotes a field one side of the diff does not have. */
const UNSET = '(unset)';

/** A diff value as a reader sees it: a quoted string loses its quotes. */
function shown(json: string): string {
  try {
    const value: unknown = JSON.parse(json);
    return typeof value === 'string' ? value : json;
  } catch {
    return json;
  }
}

/** Each field an entry of the proposed team sets, drawn as the quoted diff values are. */
function entryFields(entry: object | undefined): DiffEntryField[] {
  return Object.entries(entry ?? {})
    .filter(([field, value]) => field !== 'id' && value !== undefined)
    .map(([field, value]) => ({
      field,
      value: typeof value === 'string' ? value : JSON.stringify(value),
    }));
}

/**
 * Whether a member's OLD pool ran an entry unasked under `approval` — the
 * member's new approval, so that only the pool edit is judged. Null when the old pool's
 * quote was cut short and cannot be read.
 */
function oldPoolRunsUnasked(approval: unknown, before: string): boolean | null {
  let pool: unknown;
  try {
    pool = before === UNSET ? [] : JSON.parse(before);
  } catch {
    return null;
  }
  if (!Array.isArray(pool)) {
    return null;
  }
  return pool.some((member) =>
    memberRunsUnasked(record(member)?.approval, approval),
  );
}

/**
 * The diff as rows, every change that makes an agent run unasked first — the
 * change a reader must not skim past — then the rest in the daemon's order.
 */
export function diffRows(diff: ProposalDiff, team: Team): DiffRow[] {
  const members = new Map(team.members.map((member) => [member.id, member]));
  const unasked = new Set(
    [...members.values()].filter(runsUnasked).map((member) => member.id),
  );
  // A pool row is flagged only when the POOL edit makes an entry run unasked:
  // the old pool judged under the member's new approval, never the quoted new
  // pool, which the daemon cuts at 400 characters and in which an entry that
  // inherits the member's `auto` never spells it. An old pool cut short counts
  // as "did not", so a real switch is never missed.
  const poolToAuto = (id: string, before: string) => {
    const member = members.get(id);
    return (
      member !== undefined &&
      member.approval !== 'auto' &&
      unasked.has(id) &&
      oldPoolRunsUnasked(member.approval, before) !== true
    );
  };
  const proposed = {
    member: members,
    block: new Map(team.instructionBlocks.map((block) => [block.id, block])),
    stage: new Map((team.stages ?? []).map((stage) => [stage.id, stage])),
  } satisfies Record<Exclude<DiffRow['scope'], 'team'>, Map<string, object>>;
  const listed = (
    scope: Exclude<DiffRow['scope'], 'team'>,
    marker: 'added' | 'removed',
    entries: readonly { id: string; entry: DiffEntryField[] }[],
  ): DiffRow[] =>
    entries.map(({ id, entry }) => ({
      key: `${marker}-${scope}:${id}`,
      marker,
      scope,
      subject: id,
      detail: null,
      entry,
      toAuto: scope === 'member' && marker === 'added' && unasked.has(id),
    }));
  const added = (
    scope: Exclude<DiffRow['scope'], 'team'>,
    ids: readonly string[],
  ): DiffRow[] =>
    listed(
      scope,
      'added',
      ids.map((id) => ({
        id,
        entry: entryFields(proposed[scope].get(id)),
      })),
    );
  const removed = (
    scope: Exclude<DiffRow['scope'], 'team'>,
    entries: readonly ProposalDiffEntry[],
  ): DiffRow[] =>
    listed(
      scope,
      'removed',
      entries.map(({ id, fields }) => ({
        id,
        entry: fields.map(({ field, before }) => ({
          field,
          value: shown(before),
        })),
      })),
    );
  const changed = (
    scope: DiffRow['scope'],
    entries: readonly ProposalDiffEntry[],
  ): DiffRow[] =>
    entries.flatMap(({ id, fields }) =>
      fields.map(({ field, before, after }): DiffRow => ({
        key: `changed-${scope}:${id}:${field}`,
        marker: 'changed',
        scope,
        subject: id,
        detail: { field, before: shown(before), after: shown(after) },
        entry: [],
        toAuto:
          scope === 'member' &&
          (field === 'approval'
            ? shown(after) === 'auto'
            : field === 'pool' && poolToAuto(id, before)),
      })),
    );
  const rows: DiffRow[] = [
    ...diff.teamFields.map(({ field, values }): DiffRow => ({
      key: `team:${field}`,
      marker: 'changed',
      scope: 'team',
      subject: field,
      detail:
        values === null
          ? null
          : {
              field,
              before: shown(values.before),
              after: shown(values.after),
            },
      entry: [],
      toAuto: false,
    })),
    ...added('member', diff.addedMembers),
    ...changed('member', diff.changedMembers),
    ...removed('member', diff.removedMembers),
    ...added('block', diff.addedBlocks),
    ...changed('block', diff.changedBlocks),
    ...removed('block', diff.removedBlocks),
    ...added('stage', diff.addedStages),
    ...changed('stage', diff.changedStages),
    ...removed('stage', diff.removedStages),
  ];
  return [
    ...rows.filter((row) => row.toAuto),
    ...rows.filter((row) => !row.toAuto),
  ];
}

/**
 * A run's change as the change list draws it: each agent it adds with its
 * task, each field of each agent it updates, each task it sets, and each agent
 * it removes. Those that run tools unasked come first, as {@link diffRows} orders them.
 */
export function runChangeRows(
  changes: readonly RunChange[],
  agentName: (agent: AgentKind) => string,
): DiffRow[] {
  const rows = changes.flatMap((change): DiffRow[] => {
    switch (change.op) {
      case 'add': {
        const { member, task } = change;
        const who = [
          member.role,
          `${agentName(member.agent)} · ${member.model ?? 'default'}`,
        ]
          .filter((part) => part !== '')
          .join(' · ');
        return [
          {
            key: `add:${member.memberId}`,
            marker: 'added',
            scope: 'member',
            subject: member.name,
            detail: null,
            label: `${member.name} — ${who}`,
            entry: task === null ? [] : [{ field: 'task', value: task }],
            toAuto: member.approval === 'auto',
          },
        ];
      }
      case 'remove':
        return [
          {
            key: `remove:${change.memberId}`,
            marker: 'removed',
            scope: 'member',
            subject: change.name,
            detail: null,
            label: `${change.name} — finishes its current call, then leaves`,
            entry: [],
            toAuto: false,
          },
        ];
      case 'update': {
        const { memberId, name, fields, task } = change;
        const fieldRows = fields.map(({ field, before, after }): DiffRow => ({
          key: `update:${memberId}:${field}`,
          marker: 'changed',
          scope: 'member',
          subject: name,
          detail: { field, before: before ?? UNSET, after: after ?? UNSET },
          entry: [],
          toAuto: false,
        }));
        return task === null
          ? fieldRows
          : [
              ...fieldRows,
              {
                key: `task:${memberId}`,
                marker: 'changed',
                scope: 'member',
                subject: name,
                detail: null,
                label: `${name} — new task`,
                entry: [{ field: 'task', value: task }],
                toAuto: false,
              },
            ];
      }
    }
  });
  return [
    ...rows.filter((row) => row.toAuto),
    ...rows.filter((row) => !row.toAuto),
  ];
}
