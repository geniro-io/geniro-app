import {
  AgentKind,
  ApprovalMode,
  type InstructionBlock,
  type Team,
  type TeamMember,
  TeamMode,
} from '../autogenerated';
import {
  audienceReaches,
  memberRunsUnasked,
  type PreviewMark,
  runsUnasked,
} from '../teams/member-schema';

/**
 * The `propose_team` card's payload: the `input` of its `approval_request`
 * row, and the `outcome` its verdict row carries once approved.
 *
 * TWIN PARSER: `TeamProposalSchema` (`apps/daemon/src/v1/teams/teams.types.ts`),
 * `TeamDiff` (`apps/daemon/src/v1/teams/utils/team-diff.ts`) and
 * `TeamProposalOutcome` (`apps/daemon/src/v1/agents/chat.types.ts`). The
 * daemon checked the team strictly before raising the card, so anything
 * here that does not read is version skew — the card then falls back to the
 * permission body rather than drawing half a proposal. A card raised while
 * teams were node graphs is read through `teamFromLegacyGraph`, the twin of
 * the daemon's `teamFromWorkflow` (`apps/daemon/src/v1/teams/utils/team-from-workflow.ts`).
 */

export interface ProposalDiffField {
  field: string;
  /** JSON of the old value, quoted and capped by the daemon. */
  before: string;
  after: string;
}

export interface ProposalDiffEntry {
  id: string;
  fields: ProposalDiffField[];
}

export interface ProposalDiff {
  identical: boolean;
  teamFields: string[];
  addedMembers: string[];
  removedMembers: string[];
  changedMembers: ProposalDiffEntry[];
  addedBlocks: string[];
  removedBlocks: string[];
  changedBlocks: ProposalDiffEntry[];
  addedStages: string[];
  removedStages: string[];
  changedStages: ProposalDiffEntry[];
}

export interface ParsedTeamProposal {
  mode: 'create' | 'replace';
  team: Team;
  /** The library file an approval writes, fixed when the card was raised. */
  slug: string;
  /** The agent's own line, never trusted as a description of the change. */
  summary: string | null;
  /** The agent's own account of why, never trusted either. */
  reason: string | null;
  /** Every agent that runs tools without asking, as the daemon names them. */
  autoAgents: string[];
  /** Replace only: the name of the team being overwritten. */
  replacesName: string | null;
  /** Replace only; null on a new team. */
  diff: ProposalDiff | null;
}

const NOT_SAVED_CAUSES = [
  'changed',
  'exists',
  'gone',
  'not-closed',
  'write-failed',
] as const;

export type NotSavedCause = (typeof NOT_SAVED_CAUSES)[number];

export type ProposalOutcome =
  | { kind: 'saved'; slug: string }
  /** `cause` null: a cause this build does not know. */
  | { kind: 'not-saved'; cause: NotSavedCause | null };

function isNotSavedCause(value: unknown): value is NotSavedCause {
  return (NOT_SAVED_CAUSES as readonly unknown[]).includes(value);
}

type Fields = Record<string, unknown>;

function record(value: unknown): Fields | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Fields)
    : null;
}

function isString(value: unknown): value is string {
  return typeof value === 'string';
}

function stringList(value: unknown): string[] | null {
  return Array.isArray(value) && value.every(isString) ? value : null;
}

function oneOf<T extends string>(
  values: Readonly<Record<string, T>>,
  value: unknown,
): value is T {
  return (Object.values(values) as unknown[]).includes(value);
}

function optionalString(value: unknown): boolean {
  return value === undefined || isString(value);
}

function readAgentFields(fields: Fields): boolean {
  return (
    oneOf(AgentKind, fields.agent) &&
    optionalString(fields.model) &&
    optionalString(fields.effort)
  );
}

function readPool(pool: unknown): boolean {
  return (
    pool === undefined ||
    (Array.isArray(pool) &&
      pool.every((entry) => {
        const member = record(entry);
        return (
          member !== null &&
          readAgentFields(member) &&
          (member.approval === undefined ||
            oneOf(ApprovalMode, member.approval))
        );
      }))
  );
}

function isMember(value: unknown): boolean {
  const member = record(value);
  return (
    member !== null &&
    isString(member.id) &&
    isString(member.name) &&
    readAgentFields(member) &&
    oneOf(ApprovalMode, member.approval) &&
    optionalString(member.role) &&
    optionalString(member.instructions) &&
    optionalString(member.character) &&
    readPool(member.pool)
  );
}

function isBlock(value: unknown): boolean {
  const block = record(value);
  return (
    block !== null &&
    isString(block.id) &&
    isString(block.title) &&
    isString(block.text) &&
    (block.audience === 'everyone' || stringList(block.audience) !== null)
  );
}

function isTrigger(value: unknown): boolean {
  const trigger = record(value);
  return (
    trigger !== null &&
    trigger.kind === 'first-message' &&
    isString(trigger.member)
  );
}

function isStage(value: unknown): boolean {
  const stage = record(value);
  return (
    stage !== null &&
    isString(stage.id) &&
    isString(stage.title) &&
    isString(stage.goal) &&
    optionalString(stage.howToWork) &&
    (stage.responsible === undefined ||
      stringList(stage.responsible) !== null) &&
    (stage.next === undefined || stringList(stage.next) !== null)
  );
}

function readMemberTeam(team: Fields): Team | null {
  if (
    !isString(team.name) ||
    !optionalString(team.description) ||
    !oneOf(TeamMode, team.mode) ||
    !Array.isArray(team.members) ||
    !team.members.every(isMember) ||
    !Array.isArray(team.triggers) ||
    !team.triggers.every(isTrigger) ||
    !Array.isArray(team.instructionBlocks) ||
    !team.instructionBlocks.every(isBlock) ||
    !(
      team.stages === undefined ||
      (Array.isArray(team.stages) && team.stages.every(isStage))
    )
  ) {
    return null;
  }
  return team as unknown as Team;
}

/**
 * A team proposed while teams were node graphs, as members: agent nodes
 * become members (the public `description` their role, the private `role`
 * their instructions), the trigger's data edge names the member that handles
 * the first message, instruction nodes become blocks for the agents their
 * edges reached (all of them: everyone), and a stage's usual owner its one
 * responsible member. Null when the graph does not read.
 */
export function teamFromLegacyGraph(value: Fields): Team | null {
  const nodes = Array.isArray(value.nodes) ? value.nodes.map(record) : null;
  const edges = Array.isArray(value.edges ?? [])
    ? ((value.edges ?? []) as unknown[]).map(record)
    : null;
  if (
    !isString(value.name) ||
    nodes === null ||
    edges === null ||
    nodes.some((node) => node === null || !isString(node.id)) ||
    edges.some(
      (edge) => edge === null || !isString(edge.from) || !isString(edge.to),
    )
  ) {
    return null;
  }
  const graphNodes = nodes as Fields[];
  const graphEdges = edges as Fields[];
  const agents = graphNodes.filter((node) => node.kind === 'agent');
  if (
    !agents.every(
      (node) =>
        readAgentFields(node) &&
        (node.approval === undefined || oneOf(ApprovalMode, node.approval)) &&
        readPool(node.pool),
    )
  ) {
    return null;
  }
  const agentIds = agents.map((node) => node.id as string);
  const fed = graphNodes
    .filter((node) => node.kind === 'trigger')
    .flatMap((trigger) =>
      graphEdges.filter(
        (edge) =>
          (edge.kind ?? 'data') === 'data' &&
          edge.from === trigger.id &&
          agentIds.includes(edge.to as string),
      ),
    )
    .map((edge) => edge.to as string)[0];
  const lead = fed ?? agentIds[0];
  const members: TeamMember[] = agents.map((node) => {
    const {
      kind: _kind,
      description,
      role,
      name,
      approval,
      ...settings
    } = node;
    void _kind;
    return {
      ...(settings as Omit<TeamMember, 'name' | 'approval'>),
      name: isString(name) ? name : (node.id as string),
      approval: (approval ?? 'auto') as TeamMember['approval'],
      ...(isString(description) ? { role: description } : {}),
      ...(isString(role) ? { instructions: role } : {}),
    };
  });
  const instructionBlocks: InstructionBlock[] = graphNodes
    .filter((node) => node.kind === 'instruction')
    .map((node) => {
      const reached = new Set(
        graphEdges
          .filter(
            (edge) =>
              edge.kind === 'instruction' &&
              edge.from === node.id &&
              agentIds.includes(edge.to as string),
          )
          .map((edge) => edge.to as string),
      );
      const everyone =
        agentIds.length > 0 && agentIds.every((id) => reached.has(id));
      return {
        id: node.id as string,
        title: isString(node.name) ? node.name : (node.id as string),
        text: isString(node.instructions) ? node.instructions : '',
        audience: everyone
          ? 'everyone'
          : agentIds.filter((id) => reached.has(id)),
      };
    });
  const stages = Array.isArray(value.stages)
    ? value.stages.map(record).map((stage) =>
        stage === null
          ? null
          : {
              id: stage.id,
              title: stage.title,
              ...(isString(stage.instructions)
                ? { howToWork: stage.instructions }
                : {}),
              goal: stage.doneWhen,
              ...(isString(stage.ownerHint)
                ? { responsible: [stage.ownerHint] }
                : {}),
              ...(stage.next === undefined ? {} : { next: stage.next }),
            },
      )
    : undefined;
  if (stages !== undefined && !stages.every(isStage)) {
    return null;
  }
  return {
    name: value.name,
    ...(isString(value.description) ? { description: value.description } : {}),
    ...(typeof value.maxActiveTurns === 'number'
      ? { maxActiveTurns: value.maxActiveTurns }
      : {}),
    mode: TeamMode.Lead,
    members,
    triggers:
      lead === undefined ? [] : [{ kind: 'first-message', member: lead }],
    instructionBlocks,
    ...(stages === undefined ? {} : { stages: stages as Team['stages'] }),
  } as Team;
}

function readTeam(value: unknown): Team | null {
  const team = record(value);
  if (team === null) {
    return null;
  }
  return Array.isArray(team.members)
    ? readMemberTeam(team)
    : teamFromLegacyGraph(team);
}

function readChangedEntries(value: unknown): ProposalDiffEntry[] | null {
  if (!Array.isArray(value)) {
    return null;
  }
  const entries: ProposalDiffEntry[] = [];
  for (const raw of value) {
    const entry = record(raw);
    if (entry === null || !isString(entry.id) || !Array.isArray(entry.fields)) {
      return null;
    }
    const fields: ProposalDiffField[] = [];
    for (const rawField of entry.fields) {
      const field = record(rawField);
      if (
        field === null ||
        !isString(field.field) ||
        !isString(field.before) ||
        !isString(field.after)
      ) {
        return null;
      }
      fields.push({
        field: field.field,
        before: field.before,
        after: field.after,
      });
    }
    entries.push({ id: entry.id, fields });
  }
  return entries;
}

function readDiff(value: unknown): ProposalDiff | null {
  const diff = record(value);
  if (diff === null || typeof diff.identical !== 'boolean') {
    return null;
  }
  const teamFields = stringList(diff.teamFields ?? diff.workflowFields);
  const addedMembers = stringList(diff.addedMembers ?? diff.addedNodes);
  const removedMembers = stringList(diff.removedMembers ?? diff.removedNodes);
  const changedMembers = readChangedEntries(
    diff.changedMembers ?? diff.changedNodes,
  );
  const addedBlocks = stringList(diff.addedBlocks ?? []);
  const removedBlocks = stringList(diff.removedBlocks ?? []);
  const changedBlocks = readChangedEntries(diff.changedBlocks ?? []);
  const addedStages = stringList(diff.addedStages);
  const removedStages = stringList(diff.removedStages);
  const changedStages = readChangedEntries(diff.changedStages);
  if (
    teamFields === null ||
    addedMembers === null ||
    removedMembers === null ||
    changedMembers === null ||
    addedBlocks === null ||
    removedBlocks === null ||
    changedBlocks === null ||
    addedStages === null ||
    removedStages === null ||
    changedStages === null
  ) {
    return null;
  }
  return {
    identical: diff.identical,
    teamFields,
    addedMembers,
    removedMembers,
    changedMembers,
    addedBlocks,
    removedBlocks,
    changedBlocks,
    addedStages,
    removedStages,
    changedStages,
  };
}

function trimmedText(value: unknown): string | null {
  return isString(value) && value.trim() !== '' ? value.trim() : null;
}

/**
 * The proposal on a card, or null to draw the permission body instead. A card
 * raised before the rename holds its team under `workflow` and its diff's own
 * field list under `workflowFields`.
 */
export function readTeamProposal(input: unknown): ParsedTeamProposal | null {
  const proposal = record(input);
  if (proposal === null || !isString(proposal.slug)) {
    return null;
  }
  const team = readTeam(proposal.team ?? proposal.workflow);
  const autoAgents = stringList(proposal.autoAgents);
  if (team === null || autoAgents === null) {
    return null;
  }
  const summary = trimmedText(proposal.summary);
  const reason = trimmedText(proposal.reason);
  if (proposal.mode === 'create') {
    return {
      mode: 'create',
      team,
      slug: proposal.slug,
      summary,
      reason,
      autoAgents,
      replacesName: null,
      diff: null,
    };
  }
  if (proposal.mode !== 'replace' || !isString(proposal.replacesName)) {
    return null;
  }
  const diff = readDiff(proposal.diff);
  if (diff === null) {
    return null;
  }
  return {
    mode: 'replace',
    team,
    slug: proposal.slug,
    summary,
    reason,
    autoAgents,
    replacesName: proposal.replacesName,
    diff,
  };
}

/** What became of an approval, or null when the verdict row carries none. */
export function readProposalOutcome(raw: unknown): ProposalOutcome | null {
  const outcome = record(raw);
  if (outcome === null) {
    return null;
  }
  if (outcome.kind === 'saved' && isString(outcome.slug)) {
    return { kind: 'saved', slug: outcome.slug };
  }
  if (outcome.kind === 'not-saved') {
    return {
      kind: 'not-saved',
      cause: isNotSavedCause(outcome.cause) ? outcome.cause : null,
    };
  }
  return null;
}

function collectStrings(value: unknown, into: string[]): void {
  if (typeof value === 'string') {
    into.push(value);
  } else if (Array.isArray(value)) {
    for (const entry of value) {
      collectStrings(entry, into);
    }
  } else if (typeof value === 'object' && value !== null) {
    for (const [key, entry] of Object.entries(value)) {
      into.push(key);
      collectStrings(entry, into);
    }
  }
}

/**
 * Every string the card can draw, for the Approve gate's hazard scan: the
 * team, the diff — its old side and removed ids included, which the
 * proposed team does not carry — and the agent's own lines. Object keys
 * too: an agent writes those (`modelParameters`), and the scan is cheaper
 * whole than proven narrower.
 *
 * Raw, not JSON: `JSON.stringify` escapes the C0 controls the card draws
 * verbatim. Joined by spaces, with line breaks and tabs turned to spaces,
 * because each is itself `\p{Cc}` and would gate every multi-line role.
 */
export function proposalScanText(proposal: ParsedTeamProposal): string {
  const strings: string[] = [];
  collectStrings(
    [
      proposal.team,
      proposal.diff,
      proposal.summary,
      proposal.reason,
      proposal.replacesName,
      proposal.autoAgents,
    ],
    strings,
  );
  // A changed field's values arrive JSON-quoted and are drawn decoded
  // (`shown`), so the decoded form is scanned too: the quoted form hides a
  // control character behind its `\u` escape.
  for (const { fields } of [
    ...(proposal.diff?.changedMembers ?? []),
    ...(proposal.diff?.changedBlocks ?? []),
    ...(proposal.diff?.changedStages ?? []),
  ]) {
    for (const { before, after } of fields) {
      strings.push(shown(before), shown(after));
    }
  }
  return strings.join(' ').replace(/[\n\t\r]/g, ' ');
}

/** Each member a replacement adds or changes, for the preview to mark. */
export function previewMarks(
  diff: ProposalDiff | null,
): ReadonlyMap<string, PreviewMark> {
  const marks = new Map<string, PreviewMark>();
  for (const { id } of diff?.changedMembers ?? []) {
    marks.set(id, 'changed');
  }
  for (const id of diff?.addedMembers ?? []) {
    marks.set(id, 'added');
  }
  return marks;
}

/** Each stage a replacement adds or changes; nothing on a new team. */
export function stageMarksOf(
  diff: ProposalDiff | null,
): ReadonlyMap<string, PreviewMark> {
  const marks = new Map<string, PreviewMark>();
  for (const { id } of diff?.changedStages ?? []) {
    marks.set(id, 'changed');
  }
  for (const id of diff?.addedStages ?? []) {
    marks.set(id, 'added');
  }
  return marks;
}

/** One member of the proposal, as a roster row. */
export interface RosterRow {
  member: TeamMember;
  /** The title of every instruction block addressed to this member. */
  instructions: string[];
}

/** The proposal's members in team order, each with the blocks it is in the audience of. */
export function rosterOf(team: Team): RosterRow[] {
  return team.members.map((member) => ({
    member,
    instructions: team.instructionBlocks
      .filter((block) => audienceReaches(block, member.id))
      .map((block) => block.title.trim() || block.id),
  }));
}

export type DiffMarker = 'changed' | 'added' | 'removed';

/** One line of the change list. */
export interface DiffRow {
  key: string;
  marker: DiffMarker;
  /** What the subject names: the team's own field, a member, a block, a stage. */
  scope: 'team' | 'member' | 'block' | 'stage';
  /** A team field's name, a member id, a block id or a stage id. */
  subject: string;
  /** For a changed field: which one, and from what to what. */
  detail: { field: string; before: string; after: string } | null;
  /** The change makes an agent run tools without asking. */
  toAuto: boolean;
}

/** How the daemon quotes a field one side of the diff does not have. */
const UNSET = '(unset)';

/** A diff value as a reader sees it: a quoted string loses its quotes. */
function shown(json: string): string {
  try {
    const value: unknown = JSON.parse(json);
    return typeof value === 'string' ? value : json;
  } catch {
    return json;
  }
}

/**
 * Whether a member's OLD pool ran an entry unasked under `approval` — the
 * member's new approval, so that only the pool edit is judged. Null when the old pool's
 * quote was cut short and cannot be read.
 */
function oldPoolRunsUnasked(approval: unknown, before: string): boolean | null {
  let pool: unknown;
  try {
    pool = before === UNSET ? [] : JSON.parse(before);
  } catch {
    return null;
  }
  if (!Array.isArray(pool)) {
    return null;
  }
  return pool.some((member) =>
    memberRunsUnasked(record(member)?.approval, approval),
  );
}

/**
 * The diff as rows, every change that makes an agent run unasked first — the
 * change a reader must not skim past — then the rest in the daemon's order.
 */
export function diffRows(diff: ProposalDiff, team: Team): DiffRow[] {
  const members = new Map(team.members.map((member) => [member.id, member]));
  const unasked = new Set(
    [...members.values()].filter(runsUnasked).map((member) => member.id),
  );
  // A pool row is flagged only when the POOL edit makes an entry run unasked:
  // the old pool judged under the member's new approval, never the quoted new
  // pool, which the daemon cuts at 400 characters and in which an entry that
  // inherits the member's `auto` never spells it. An old pool cut short counts
  // as "did not", so a real switch is never missed.
  const poolToAuto = (id: string, before: string) => {
    const member = members.get(id);
    return (
      member !== undefined &&
      member.approval !== 'auto' &&
      unasked.has(id) &&
      oldPoolRunsUnasked(member.approval, before) !== true
    );
  };
  const listed = (
    scope: DiffRow['scope'],
    marker: 'added' | 'removed',
    ids: readonly string[],
  ): DiffRow[] =>
    ids.map((id) => ({
      key: `${marker}-${scope}:${id}`,
      marker,
      scope,
      subject: id,
      detail: null,
      toAuto: scope === 'member' && marker === 'added' && unasked.has(id),
    }));
  const changed = (
    scope: DiffRow['scope'],
    entries: readonly ProposalDiffEntry[],
  ): DiffRow[] =>
    entries.flatMap(({ id, fields }) =>
      fields.map(({ field, before, after }): DiffRow => ({
        key: `changed-${scope}:${id}:${field}`,
        marker: 'changed',
        scope,
        subject: id,
        detail: { field, before: shown(before), after: shown(after) },
        toAuto:
          scope === 'member' &&
          (field === 'approval'
            ? shown(after) === 'auto'
            : field === 'pool' && poolToAuto(id, before)),
      })),
    );
  const rows: DiffRow[] = [
    ...diff.teamFields.map((field): DiffRow => ({
      key: `team:${field}`,
      marker: 'changed',
      scope: 'team',
      subject: field,
      detail: null,
      toAuto: false,
    })),
    ...listed('member', 'added', diff.addedMembers),
    ...changed('member', diff.changedMembers),
    ...listed('member', 'removed', diff.removedMembers),
    ...listed('block', 'added', diff.addedBlocks),
    ...changed('block', diff.changedBlocks),
    ...listed('block', 'removed', diff.removedBlocks),
    ...listed('stage', 'added', diff.addedStages),
    ...changed('stage', diff.changedStages),
    ...listed('stage', 'removed', diff.removedStages),
  ];
  return [
    ...rows.filter((row) => row.toAuto),
    ...rows.filter((row) => !row.toAuto),
  ];
}
