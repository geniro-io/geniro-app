import { describe, expect, it } from 'vitest';

import type { Team, TeamMember } from '../autogenerated';
import { rootAgentOf, triggerFedAgentIds } from './team-root';

const member = (id: string): TeamMember => ({
  id,
  name: id,
  agent: 'claude',
  approval: 'auto',
});

const team = (members: string[], triggerMember?: string): Team => ({
  name: 'Team',
  mode: 'lead',
  members: members.map(member),
  triggers:
    triggerMember === undefined
      ? []
      : [{ kind: 'first-message', member: triggerMember }],
  instructionBlocks: [],
});

describe('rootAgentOf', () => {
  it('names the member the trigger names', () => {
    expect(rootAgentOf(team(['manager', 'eng'], 'manager'))).toBe('manager');
    expect(rootAgentOf(team(['manager', 'eng'], 'eng'))).toBe('eng');
  });

  it('answers null for a team with no trigger', () => {
    expect(rootAgentOf(team(['a', 'b']))).toBeNull();
  });

  it('answers null when the trigger names no member of the team', () => {
    expect(rootAgentOf(team(['a', 'b'], 'gone'))).toBeNull();
  });
});

describe('triggerFedAgentIds', () => {
  it('lists the trigger member alone, however many members the team has', () => {
    expect(triggerFedAgentIds(team(['a', 'b', 'c'], 'b'))).toEqual(['b']);
  });

  it('lists nobody when the trigger names no member', () => {
    expect(triggerFedAgentIds(team(['a'], 'gone'))).toEqual([]);
    expect(triggerFedAgentIds(team(['a']))).toEqual([]);
  });
});
