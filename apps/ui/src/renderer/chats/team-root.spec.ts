import { describe, expect, it } from 'vitest';

import type { Team, TeamMember } from '../autogenerated';
import {
  firstMessageMemberOf,
  rootAgentOf,
  runLeadOf,
  triggerFedAgentIds,
} from './team-root';

const member = (id: string): TeamMember => ({
  id,
  name: id,
  agent: 'claude',
  approval: 'auto',
});

const team = (members: string[], triggerMember?: string): Team => ({
  name: 'Team',
  mode: 'lead',
  members: members.map(member),
  triggers:
    triggerMember === undefined
      ? []
      : [{ kind: 'first-message', member: triggerMember }],
  instructionBlocks: [],
});

describe('rootAgentOf', () => {
  it('names the member the trigger names', () => {
    expect(rootAgentOf(team(['manager', 'eng'], 'manager'))).toBe('manager');
    expect(rootAgentOf(team(['manager', 'eng'], 'eng'))).toBe('eng');
  });

  it('answers null for a team with no trigger', () => {
    expect(rootAgentOf(team(['a', 'b']))).toBeNull();
  });

  it('answers null when the trigger names no member of the team', () => {
    expect(rootAgentOf(team(['a', 'b'], 'gone'))).toBeNull();
  });
});

describe('triggerFedAgentIds', () => {
  it('lists the trigger member alone, however many members the team has', () => {
    expect(triggerFedAgentIds(team(['a', 'b', 'c'], 'b'))).toEqual(['b']);
  });

  it('lists nobody when the trigger names no member', () => {
    expect(triggerFedAgentIds(team(['a'], 'gone'))).toEqual([]);
    expect(triggerFedAgentIds(team(['a']))).toEqual([]);
  });
});

describe('runLeadOf', () => {
  const ids = new Set(['ada', 'bob']);

  it('is the daemon’s lead when it names a member of the run', () => {
    expect(runLeadOf('bob', ids, 'ada')).toBe('bob');
  });

  it('falls back to the trigger’s member for a run with no lead recorded, or one naming no member', () => {
    expect(runLeadOf(null, ids, 'ada')).toBe('ada');
    expect(runLeadOf(undefined, ids, 'ada')).toBe('ada');
    expect(runLeadOf('gone', ids, 'ada')).toBe('ada');
  });
});

describe('firstMessageMemberOf', () => {
  const relay = (responsible: string[]): Team => ({
    ...team(['manager', 'qa'], 'manager'),
    mode: 'relay',
    stages: [
      {
        id: 'test',
        title: 'Test',
        goal: 'tested',
        responsible,
        next: ['ship'],
      },
      { id: 'ship', title: 'Ship', goal: 'shipped' },
    ],
  });

  it('is the first stage’s lead in a relay team', () => {
    expect(firstMessageMemberOf(relay(['qa', 'manager']))).toBe('qa');
  });

  it('is the trigger’s member in a one-lead team, or when the first stage names no member', () => {
    expect(firstMessageMemberOf({ ...relay(['qa']), mode: 'lead' })).toBe(
      'manager',
    );
    expect(firstMessageMemberOf(relay([]))).toBe('manager');
    expect(firstMessageMemberOf(relay(['gone', 'qa']))).toBe('manager');
  });
});
