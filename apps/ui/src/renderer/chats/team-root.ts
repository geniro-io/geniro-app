import type { Team } from '../autogenerated';
import { validateStages } from '../teams/stage-validate';

/**
 * The member the team's trigger names — the one the run is a conversation
 * WITH, rather than one the conversation is about.
 *
 * The transcript draws every agent in an avatar-framed block, which earns its
 * space the moment two of them share a flow. The root agent is the exception,
 * and it is the same exception a 1:1 chat already makes: the user writes to it,
 * it answers, and everything else in the run reaches the screen inside a card
 * that names its own agent (a call block, a sub-agent block).
 *
 * Null when the trigger names no member of the team. Purely presentational:
 * a disagreement with the daemon costs a frame, never a routing decision.
 */
export function rootAgentOf(team: Team): string | null {
  return triggerFedAgentIds(team)[0] ?? null;
}

/**
 * The members a message written to an open team run reaches — the one the
 * trigger names (the daemon's `deliverFollowUp` hands it to exactly that one).
 *
 * TWIN PARSER: `triggerMemberId` in apps/daemon/src/v1/teams/utils/team-roster.ts.
 */
export function triggerFedAgentIds(team: Team): string[] {
  const id = team.triggers[0]?.member;
  return id !== undefined && team.members.some((member) => member.id === id)
    ? [id]
    : [];
}

/**
 * The member an open team run's messages go to now: the daemon's
 * `RunDto.currentLead` when it names one of the run's members, else the
 * trigger's member (a run started before the lead was recorded).
 */
export function runLeadOf(
  currentLead: string | null | undefined,
  memberIds: ReadonlySet<string>,
  triggerMember: string | null,
): string | null {
  return currentLead != null && memberIds.has(currentLead)
    ? currentLead
    : triggerMember;
}

/**
 * The member a new run's first message goes to: in `relay` mode the first
 * stage's lead (its first responsible member) when the stages are walkable
 * and it names one of the team, else the trigger's member.
 *
 * TWIN PARSER: `startingLeadOf` in apps/daemon/src/v1/teams/utils/team-roster.ts; its
 * start-stage rule is `startStageId` in apps/daemon/src/v1/teams/utils/stage-validate.ts.
 */
export function firstMessageMemberOf(team: Team): string | null {
  const trigger = triggerFedAgentIds(team)[0] ?? null;
  const stages = team.stages ?? [];
  if (
    team.mode !== 'relay' ||
    stages.length === 0 ||
    validateStages(team).errors.length > 0
  ) {
    return trigger;
  }
  const named = new Set(stages.flatMap((stage) => stage.next ?? []));
  const lead = stages.find((stage) => !named.has(stage.id))?.responsible?.[0];
  return lead !== undefined && team.members.some((m) => m.id === lead)
    ? lead
    : trigger;
}
