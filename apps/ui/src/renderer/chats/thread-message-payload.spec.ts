import { describe, expect, it } from 'vitest';

import { WaitingMessageDtoReasonEnum } from '../autogenerated';
import {
  firstLineOf,
  readThreadMessageRow,
  threadMessageReasonWords,
} from './thread-message-payload';

const RECEIVED = {
  severity: 'info',
  message: 'Message from Pelican: hi',
  threadMessages: [
    {
      id: 'm1',
      fromRunId: 'r-pelican',
      fromTitle: 'Pelican',
      fromMember: null,
      text: 'hi',
    },
    {
      id: 'm2',
      fromRunId: 'r-otter',
      fromTitle: 'Otter',
      fromMember: 'Backend Engineer',
      text: 'line one\nline two',
    },
  ],
  woke: false,
};

const SENT = (sent: Record<string, unknown>) => ({
  severity: 'info',
  message: 'Message to Otter waits.',
  threadMessageSent: sent,
  woke: false,
});

describe('readThreadMessageRow', () => {
  it('reads every message a turn took, keeping each sender and its whole text', () => {
    expect(readThreadMessageRow(RECEIVED)).toEqual({
      kind: 'received',
      messages: [
        {
          id: 'm1',
          fromRunId: 'r-pelican',
          fromTitle: 'Pelican',
          fromMember: null,
          text: 'hi',
        },
        {
          id: 'm2',
          fromRunId: 'r-otter',
          fromTitle: 'Otter',
          fromMember: 'Backend Engineer',
          text: 'line one\nline two',
        },
      ],
    });
  });

  it('reads the thread that woke a turn', () => {
    expect(
      readThreadMessageRow({
        severity: 'info',
        message: 'Woken by a message from Pelican.',
        threadWake: { fromRunId: 'r-pelican', fromTitle: 'Pelican' },
        woke: true,
      }),
    ).toEqual({ kind: 'woken', fromRunId: 'r-pelican', fromTitle: 'Pelican' });
  });

  it('reads a send with its outcome, and its reason when it waits', () => {
    expect(
      readThreadMessageRow(
        SENT({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome: 'waiting',
          reason: 'stopped',
        }),
      ),
    ).toEqual({
      kind: 'sent',
      sent: {
        toRunId: 'r-otter',
        title: 'Otter',
        outcome: 'waiting',
        reason: 'stopped',
      },
    });
    expect(
      readThreadMessageRow(
        SENT({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome: 'joined',
          reason: null,
        }),
      ),
    ).toEqual({
      kind: 'sent',
      sent: {
        toRunId: 'r-otter',
        title: 'Otter',
        outcome: 'joined',
        reason: null,
      },
    });
  });

  it('reads nothing from a row that carries none of the three fields', () => {
    expect(
      readThreadMessageRow({ severity: 'info', message: 'plain', woke: false }),
    ).toBeNull();
    expect(readThreadMessageRow(null)).toBeNull();
    expect(readThreadMessageRow('threadWake')).toBeNull();
  });

  it('reads nothing from a send with an outcome or reason it does not know', () => {
    expect(
      readThreadMessageRow(
        SENT({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome: 'sent',
          reason: null,
        }),
      ),
    ).toBeNull();
    expect(
      readThreadMessageRow(
        SENT({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome: 'waiting',
          reason: 'bored',
        }),
      ),
    ).toBeNull();
    expect(
      readThreadMessageRow({ threadWake: { fromRunId: 'r-pelican' } }),
    ).toBeNull();
  });

  it('skips a message missing a field and keeps the valid ones', () => {
    const row = readThreadMessageRow({
      threadMessages: [
        { id: 'm0', fromRunId: 'r-x', fromTitle: 'X', fromMember: null },
        RECEIVED.threadMessages[0],
      ],
    });
    expect(row).toEqual({
      kind: 'received',
      messages: [RECEIVED.threadMessages[0]],
    });
  });
});

describe('threadMessageReasonWords', () => {
  it('words each reason the daemon can name in a sentence of its own', () => {
    const reasons = Object.values(WaitingMessageDtoReasonEnum);
    const words = reasons.map((reason) => threadMessageReasonWords(reason));
    expect(new Set(words).size).toBe(reasons.length);
    expect(words.every((text) => text.length > 0)).toBe(true);
    expect(threadMessageReasonWords('stopped')).toBe(
      'waits, because the user stopped that thread',
    );
  });
});

describe('firstLineOf', () => {
  it('returns the first line that has text on it, trimmed', () => {
    expect(firstLineOf('\n  \n  Hello there \nsecond line')).toBe(
      'Hello there',
    );
  });

  it('returns nothing for a text with no words on any line', () => {
    expect(firstLineOf('   \n\t')).toBe('');
  });
});
