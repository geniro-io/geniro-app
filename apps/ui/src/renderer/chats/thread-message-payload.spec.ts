import { describe, expect, it } from 'vitest';

import { WaitingMessageDtoReasonEnum } from '../autogenerated';
import {
  readThreadMessageRow,
  sentOutcomeWords,
  threadMessageReasonWords,
  waitingMessageReasonWords,
} from './thread-message-payload';

const RECEIVED = {
  severity: 'info',
  message: 'Message from Pelican: hi',
  threadMessages: [
    {
      id: 'm1',
      fromRunId: 'r-pelican',
      fromTitle: 'Pelican',
      fromMember: null,
      text: 'hi',
    },
    {
      id: 'm2',
      fromRunId: 'r-otter',
      fromTitle: 'Otter',
      fromMember: 'Backend Engineer',
      text: 'line one\nline two',
    },
  ],
  woke: false,
};

const SENT = (sent: Record<string, unknown>) => ({
  severity: 'info',
  message: 'Message to Otter waits.',
  threadMessageSent: sent,
  woke: false,
});

describe('readThreadMessageRow', () => {
  it('reads every message a turn took, keeping each sender and its whole text', () => {
    expect(readThreadMessageRow(RECEIVED)).toEqual({
      kind: 'received',
      messages: [
        {
          id: 'm1',
          fromRunId: 'r-pelican',
          fromTitle: 'Pelican',
          fromMember: null,
          text: 'hi',
          inReplyTo: null,
        },
        {
          id: 'm2',
          fromRunId: 'r-otter',
          fromTitle: 'Otter',
          fromMember: 'Backend Engineer',
          text: 'line one\nline two',
          inReplyTo: null,
        },
      ],
    });
  });

  it('reads the reply a message answers, and null for a message that answers none', () => {
    const row = readThreadMessageRow({
      ...RECEIVED,
      threadMessages: [
        {
          ...RECEIVED.threadMessages[1],
          inReplyTo: { text: 'which build?', at: '2026-11-06T10:00:00.000Z' },
        },
        { ...RECEIVED.threadMessages[0], inReplyTo: null },
        { ...RECEIVED.threadMessages[0], id: 'm3', inReplyTo: 'a reply' },
      ],
    });
    expect(row).toEqual({
      kind: 'received',
      messages: [
        {
          id: 'm2',
          fromRunId: 'r-otter',
          fromTitle: 'Otter',
          fromMember: 'Backend Engineer',
          text: 'line one\nline two',
          inReplyTo: { text: 'which build?', at: '2026-11-06T10:00:00.000Z' },
        },
        {
          id: 'm1',
          fromRunId: 'r-pelican',
          fromTitle: 'Pelican',
          fromMember: null,
          text: 'hi',
          inReplyTo: null,
        },
        {
          id: 'm3',
          fromRunId: 'r-pelican',
          fromTitle: 'Pelican',
          fromMember: null,
          text: 'hi',
          inReplyTo: null,
        },
      ],
    });
  });

  it('reads the thread that woke a turn', () => {
    expect(
      readThreadMessageRow({
        severity: 'info',
        message: 'Woken by a message from Pelican.',
        threadWake: { fromRunId: 'r-pelican', fromTitle: 'Pelican' },
        woke: true,
      }),
    ).toEqual({ kind: 'woken', fromRunId: 'r-pelican', fromTitle: 'Pelican' });
  });

  it('reads a send with its outcome, and its reason when it waits', () => {
    expect(
      readThreadMessageRow(
        SENT({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome: 'waiting',
          reason: 'stopped',
        }),
      ),
    ).toEqual({
      kind: 'sent',
      sent: {
        toRunId: 'r-otter',
        title: 'Otter',
        outcome: 'waiting',
        reason: 'stopped',
        text: null,
      },
    });
    expect(
      readThreadMessageRow(
        SENT({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome: 'joined',
          reason: null,
        }),
      ),
    ).toEqual({
      kind: 'sent',
      sent: {
        toRunId: 'r-otter',
        title: 'Otter',
        outcome: 'joined',
        reason: null,
        text: null,
      },
    });
  });

  it('reads the text a send carries', () => {
    expect(
      readThreadMessageRow(
        SENT({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome: 'woken',
          reason: null,
          text: 'Please rebase on main.',
        }),
      ),
    ).toEqual({
      kind: 'sent',
      sent: {
        toRunId: 'r-otter',
        title: 'Otter',
        outcome: 'woken',
        reason: null,
        text: 'Please rebase on main.',
      },
    });
  });

  it('reads every finished thread a row carries, each summary and pull request optional', () => {
    expect(
      readThreadMessageRow({
        severity: 'info',
        message: 't22 is done',
        threadDone: [
          {
            runId: 'r-otter',
            title: 'Otter',
            handle: 't22',
            summary: 'PRI-10 cancelled.',
            pullRequest: 146,
          },
          { runId: 'r-elves', title: 'Elves', handle: 't23' },
        ],
        woke: true,
      }),
    ).toEqual({
      kind: 'done',
      done: [
        {
          runId: 'r-otter',
          title: 'Otter',
          handle: 't22',
          summary: 'PRI-10 cancelled.',
          pullRequest: 146,
        },
        {
          runId: 'r-elves',
          title: 'Elves',
          handle: 't23',
          summary: null,
          pullRequest: null,
        },
      ],
    });
  });

  it('reads nothing from a done row missing its thread or handle, as rows before it was written', () => {
    expect(
      readThreadMessageRow({
        severity: 'info',
        message: 't22 is done',
        woke: true,
      }),
    ).toBeNull();
    expect(
      readThreadMessageRow({
        threadDone: [{ runId: 'r-otter', title: 'Otter' }],
      }),
    ).toBeNull();
  });

  it('reads nothing from a row that carries none of the four fields', () => {
    expect(
      readThreadMessageRow({ severity: 'info', message: 'plain', woke: false }),
    ).toBeNull();
    expect(readThreadMessageRow(null)).toBeNull();
    expect(readThreadMessageRow('threadWake')).toBeNull();
  });

  it('reads nothing from a send with an outcome or reason it does not know', () => {
    expect(
      readThreadMessageRow(
        SENT({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome: 'sent',
          reason: null,
        }),
      ),
    ).toBeNull();
    expect(
      readThreadMessageRow(
        SENT({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome: 'waiting',
          reason: 'bored',
        }),
      ),
    ).toBeNull();
    expect(
      readThreadMessageRow({ threadWake: { fromRunId: 'r-pelican' } }),
    ).toBeNull();
  });

  it('skips a message missing a field and keeps the valid ones', () => {
    const row = readThreadMessageRow({
      threadMessages: [
        { id: 'm0', fromRunId: 'r-x', fromTitle: 'X', fromMember: null },
        RECEIVED.threadMessages[0],
      ],
    });
    expect(row).toEqual({
      kind: 'received',
      messages: [{ ...RECEIVED.threadMessages[0], inReplyTo: null }],
    });
  });
});

describe('readThreadMessageRow waiting items', () => {
  it('reads a kind with its items', () => {
    expect(
      readThreadMessageRow({
        waitingItems: {
          kind: 'lesson',
          items: [
            { id: 'l1', title: 'Run lint first' },
            { id: 'l2', title: 'Pin the node version' },
          ],
        },
      }),
    ).toEqual({
      kind: 'waiting',
      waiting: {
        kind: 'lesson',
        items: [
          { id: 'l1', title: 'Run lint first' },
          { id: 'l2', title: 'Pin the node version' },
        ],
      },
    });
  });

  it.each([
    ['an unknown kind', { kind: 'note', items: [{ id: 'a', title: 'b' }] }],
    ['no items', { kind: 'memory', items: [] }],
    ['items that are not a list', { kind: 'memory', items: 'a' }],
    ['an item without a title', { kind: 'memory', items: [{ id: 'a' }] }],
    ['an item without an id', { kind: 'knowledge', items: [{ title: 'a' }] }],
    ['a value that is not an object', 'memory'],
  ])('reads %s as no row', (_name, waitingItems) => {
    expect(readThreadMessageRow({ waitingItems })).toBeNull();
  });
});

describe('sentOutcomeWords', () => {
  it.each([
    ['joined', null, 'Joined the running turn'],
    ['woken', null, 'Started a turn there'],
    ['waiting', 'stopped', 'Waits, because the user stopped that thread'],
    ['waiting', null, 'Waiting'],
  ] as const)(
    'says what became of a %s send (reason %s)',
    (outcome, reason, words) => {
      expect(
        sentOutcomeWords({
          toRunId: 'r-otter',
          title: 'Otter',
          outcome,
          reason,
          text: null,
        }),
      ).toBe(words);
    },
  );
});

describe('waitingMessageReasonWords', () => {
  it('says a message held by a question goes out once it is answered', () => {
    expect(waitingMessageReasonWords('question')).toBe(
      'Goes out once you have answered: a question waits for you here',
    );
  });

  it('speaks from the thread holding the message, never to the sender', () => {
    expect(waitingMessageReasonWords('sender_opted_out')).toBe(
      'Goes out with the next turn: the sender did not wake this thread',
    );
    expect(waitingMessageReasonWords('running_turn')).toBe(
      'Goes out when this turn ends',
    );
  });
});

describe('threadMessageReasonWords', () => {
  it('words each reason the daemon can name in a sentence of its own', () => {
    const reasons = Object.values(WaitingMessageDtoReasonEnum);
    const words = reasons.map((reason) => threadMessageReasonWords(reason));
    expect(new Set(words).size).toBe(reasons.length);
    expect(words.every((text) => text.length > 0)).toBe(true);
    expect(threadMessageReasonWords('stopped')).toBe(
      'waits, because the user stopped that thread',
    );
  });
});
