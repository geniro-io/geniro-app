import { WaitingMessageDtoReasonEnum } from '../autogenerated';

/** Why a message still waits instead of having reached its thread. */
export type ThreadMessageReason = WaitingMessageDtoReasonEnum;

/** `joined` a running turn, `woken` a turn of its own, or left `waiting`. */
export type ThreadMessageOutcome = 'joined' | 'woken' | 'waiting';

/**
 * A message from another thread, as the turn that took it carries it.
 *
 * TWIN PARSER: `ThreadMessageRowEntry` in `apps/daemon/src/v1/agents/chat.types.ts`,
 * written by `threadMessagesRow` in `apps/daemon/src/v1/agents/utils/thread-message-text.ts`.
 */
export interface ReceivedThreadMessage {
  id: string;
  fromRunId: string;
  fromTitle: string;
  fromMember: string | null;
  text: string;
}

/** A message this thread sent, and what became of it. */
export interface ThreadMessageSent {
  toRunId: string;
  title: string;
  outcome: ThreadMessageOutcome;
  reason: ThreadMessageReason | null;
}

/** The one shape a thread-message row carries. */
export type ThreadMessageRow =
  | { kind: 'received'; messages: ReceivedThreadMessage[] }
  | { kind: 'woken'; fromRunId: string; fromTitle: string }
  | { kind: 'sent'; sent: ThreadMessageSent };

const REASONS: ReadonlySet<string> = new Set(
  Object.values(WaitingMessageDtoReasonEnum),
);
const OUTCOMES: ReadonlySet<string> = new Set<ThreadMessageOutcome>([
  'joined',
  'woken',
  'waiting',
]);

/**
 * The thread-message row a system item carries, or null when it carries none.
 *
 * TWIN PARSER: the `threadMessages`, `threadWake` and `threadMessageSent`
 * fields of `HostRowWire` in `apps/daemon/src/v1/agents/chat.types.ts`.
 */
export function readThreadMessageRow(
  payload: unknown,
): ThreadMessageRow | null {
  if (payload === null || typeof payload !== 'object') {
    return null;
  }
  const bag = payload as Record<string, unknown>;
  const messages = readReceived(bag.threadMessages);
  if (messages !== null) {
    return { kind: 'received', messages };
  }
  const wake = readWake(bag.threadWake);
  if (wake !== null) {
    return { kind: 'woken', ...wake };
  }
  const sent = readSent(bag.threadMessageSent);
  return sent === null ? null : { kind: 'sent', sent };
}

function readReceived(value: unknown): ReceivedThreadMessage[] | null {
  if (!Array.isArray(value)) {
    return null;
  }
  const messages: ReceivedThreadMessage[] = [];
  for (const entry of value) {
    if (entry === null || typeof entry !== 'object') {
      continue;
    }
    const { id, fromRunId, fromTitle, fromMember, text } = entry as Record<
      string,
      unknown
    >;
    if (
      typeof id === 'string' &&
      typeof fromRunId === 'string' &&
      typeof fromTitle === 'string' &&
      (fromMember === null || typeof fromMember === 'string') &&
      typeof text === 'string'
    ) {
      messages.push({ id, fromRunId, fromTitle, fromMember, text });
    }
  }
  return messages.length === 0 ? null : messages;
}

function readWake(
  value: unknown,
): { fromRunId: string; fromTitle: string } | null {
  if (value === null || typeof value !== 'object') {
    return null;
  }
  const { fromRunId, fromTitle } = value as Record<string, unknown>;
  return typeof fromRunId === 'string' && typeof fromTitle === 'string'
    ? { fromRunId, fromTitle }
    : null;
}

function readSent(value: unknown): ThreadMessageSent | null {
  if (value === null || typeof value !== 'object') {
    return null;
  }
  const { toRunId, title, outcome, reason } = value as Record<string, unknown>;
  const reasonValue = reason ?? null;
  if (
    typeof toRunId !== 'string' ||
    typeof title !== 'string' ||
    typeof outcome !== 'string' ||
    !OUTCOMES.has(outcome) ||
    !(
      reasonValue === null ||
      (typeof reasonValue === 'string' && REASONS.has(reasonValue))
    )
  ) {
    return null;
  }
  return {
    toRunId,
    title,
    outcome: outcome as ThreadMessageOutcome,
    reason: reasonValue as ThreadMessageReason | null,
  };
}

/**
 * Why a message waits, in the words the sender and the user both read. The
 * same sentences the daemon writes into the sender's row.
 *
 * TWIN: `REASON_WORDS` in `apps/daemon/src/v1/agents/utils/thread-message-text.ts`.
 */
const REASON_WORDS: Record<ThreadMessageReason, string> = {
  running_turn: 'waits for the turn running there to end',
  stopped: 'waits, because the user stopped that thread',
  failed: 'waits, because the last turn there failed',
  not_started: 'waits, because that thread has not started',
  question: 'waits, because that thread has a question for the user',
  sender_opted_out: 'waits for its next turn, as you asked',
  cold_and_large:
    'waits for its next turn, because waking that large idle thread would be costly',
  wake_limit:
    'waits for its next turn, because that thread was woken too often this hour',
};

export function threadMessageReasonWords(reason: ThreadMessageReason): string {
  return REASON_WORDS[reason];
}

/** The same reasons as the thread holding the message reads them. */
const WAITING_WORDS: Record<ThreadMessageReason, string> = {
  running_turn: 'Goes out when this turn ends',
  stopped: 'Goes out with the next turn: this thread was stopped',
  failed: 'Goes out with the next turn: the last turn failed',
  not_started: 'Goes out with the first turn',
  question: 'Goes out with the next turn: a question waits for you here',
  sender_opted_out:
    'Goes out with the next turn: the sender did not wake this thread',
  cold_and_large:
    'Goes out with the next turn: waking this large idle thread would be costly',
  wake_limit:
    'Goes out with the next turn: this thread was woken too often this hour',
};

export function waitingMessageReasonWords(reason: ThreadMessageReason): string {
  return WAITING_WORDS[reason];
}

/** The first line of a message that has text on it — all a waiting list previews. */
export function firstLineOf(text: string): string {
  return (
    text
      .split('\n')
      .map((line) => line.trim())
      .find((line) => line !== '') ?? ''
  );
}
