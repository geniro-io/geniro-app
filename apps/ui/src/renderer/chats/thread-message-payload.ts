import { WaitingMessageDtoReasonEnum } from '../autogenerated';

/** Why a message still waits instead of having reached its thread. */
export type ThreadMessageReason = WaitingMessageDtoReasonEnum;

/** `joined` a running turn, `woken` a turn of its own, or left `waiting`. */
export type ThreadMessageOutcome = 'joined' | 'woken' | 'waiting';

/**
 * A message from another thread, as the turn that took it carries it.
 *
 * TWIN PARSER: `ThreadMessageRowEntry` in `apps/daemon/src/v1/agents/chat.types.ts`,
 * written by `threadMessagesRow` in `apps/daemon/src/v1/agents/utils/thread-message-text.ts`.
 */
export interface ThreadMessageReply {
  text: string;
  at: string;
}

export interface ReceivedThreadMessage {
  id: string;
  fromRunId: string;
  fromTitle: string;
  fromMember: string | null;
  text: string;
  inReplyTo: ThreadMessageReply | null;
}

/** A message this thread sent, and what became of it. */
export interface ThreadMessageSent {
  toRunId: string;
  title: string;
  outcome: ThreadMessageOutcome;
  reason: ThreadMessageReason | null;
  /** Null on a row written before the daemon kept the text. */
  text: string | null;
}

/** A thread on the command center's roster that finished. */
export interface ThreadDone {
  runId: string;
  title: string;
  handle: string;
  summary: string | null;
  pullRequest: number | null;
}

/** Review items of one kind the manager announced: one id is one item's card, more are a summary. */
export interface WaitingItemsRowView {
  kind: 'memory' | 'lesson' | 'knowledge';
  items: { id: string; title: string }[];
}

/** The one shape a thread-message row carries. */
export type ThreadMessageRow =
  | { kind: 'received'; messages: ReceivedThreadMessage[] }
  | { kind: 'woken'; fromRunId: string; fromTitle: string }
  | { kind: 'sent'; sent: ThreadMessageSent }
  | { kind: 'done'; done: ThreadDone[] }
  | { kind: 'waiting'; waiting: WaitingItemsRowView };

const REASONS: ReadonlySet<string> = new Set(
  Object.values(WaitingMessageDtoReasonEnum),
);
const OUTCOMES: ReadonlySet<string> = new Set<ThreadMessageOutcome>([
  'joined',
  'woken',
  'waiting',
]);

/**
 * The thread-message row a system item carries, or null when it carries none.
 *
 * TWIN PARSER: the `threadMessages`, `threadWake`, `threadMessageSent` and
 * `threadDone` and `waitingItems` fields of `HostRowWire` in `apps/daemon/src/v1/agents/chat.types.ts`.
 */
export function readThreadMessageRow(
  payload: unknown,
): ThreadMessageRow | null {
  if (payload === null || typeof payload !== 'object') {
    return null;
  }
  const bag = payload as Record<string, unknown>;
  const messages = readReceived(bag.threadMessages);
  if (messages !== null) {
    return { kind: 'received', messages };
  }
  const wake = readWake(bag.threadWake);
  if (wake !== null) {
    return { kind: 'woken', ...wake };
  }
  const sent = readSent(bag.threadMessageSent);
  if (sent !== null) {
    return { kind: 'sent', sent };
  }
  const done = Array.isArray(bag.threadDone)
    ? bag.threadDone.flatMap((entry) => {
        const read = readDone(entry);
        return read === null ? [] : [read];
      })
    : [];
  if (done.length > 0) {
    return { kind: 'done', done };
  }
  const waiting = readWaiting(bag.waitingItems);
  return waiting === null ? null : { kind: 'waiting', waiting };
}

const WAITING_KINDS: ReadonlySet<string> = new Set<WaitingItemsRowView['kind']>(
  ['memory', 'lesson', 'knowledge'],
);

function readWaiting(value: unknown): WaitingItemsRowView | null {
  if (value === null || typeof value !== 'object') {
    return null;
  }
  const { kind, items } = value as Record<string, unknown>;
  if (
    typeof kind !== 'string' ||
    !WAITING_KINDS.has(kind) ||
    !Array.isArray(items)
  ) {
    return null;
  }
  const read: WaitingItemsRowView['items'] = [];
  for (const entry of items) {
    if (entry === null || typeof entry !== 'object') {
      return null;
    }
    const { id, title } = entry as Record<string, unknown>;
    if (typeof id !== 'string' || typeof title !== 'string') {
      return null;
    }
    read.push({ id, title });
  }
  return read.length === 0
    ? null
    : { kind: kind as WaitingItemsRowView['kind'], items: read };
}

function readDone(value: unknown): ThreadDone | null {
  if (value === null || typeof value !== 'object') {
    return null;
  }
  const { runId, title, handle, summary, pullRequest } = value as Record<
    string,
    unknown
  >;
  if (
    typeof runId !== 'string' ||
    typeof title !== 'string' ||
    typeof handle !== 'string'
  ) {
    return null;
  }
  return {
    runId,
    title,
    handle,
    summary: typeof summary === 'string' && summary !== '' ? summary : null,
    pullRequest:
      typeof pullRequest === 'number' && Number.isInteger(pullRequest)
        ? pullRequest
        : null,
  };
}

function readReceived(value: unknown): ReceivedThreadMessage[] | null {
  if (!Array.isArray(value)) {
    return null;
  }
  const messages: ReceivedThreadMessage[] = [];
  for (const entry of value) {
    if (entry === null || typeof entry !== 'object') {
      continue;
    }
    const { id, fromRunId, fromTitle, fromMember, text, inReplyTo } =
      entry as Record<string, unknown>;
    if (
      typeof id === 'string' &&
      typeof fromRunId === 'string' &&
      typeof fromTitle === 'string' &&
      (fromMember === null || typeof fromMember === 'string') &&
      typeof text === 'string'
    ) {
      messages.push({
        id,
        fromRunId,
        fromTitle,
        fromMember,
        text,
        inReplyTo: readReply(inReplyTo),
      });
    }
  }
  return messages.length === 0 ? null : messages;
}

function readReply(value: unknown): ThreadMessageReply | null {
  if (value === null || typeof value !== 'object') {
    return null;
  }
  const { text, at } = value as Record<string, unknown>;
  return typeof text === 'string' && typeof at === 'string'
    ? { text, at }
    : null;
}

function readWake(
  value: unknown,
): { fromRunId: string; fromTitle: string } | null {
  if (value === null || typeof value !== 'object') {
    return null;
  }
  const { fromRunId, fromTitle } = value as Record<string, unknown>;
  return typeof fromRunId === 'string' && typeof fromTitle === 'string'
    ? { fromRunId, fromTitle }
    : null;
}

function readSent(value: unknown): ThreadMessageSent | null {
  if (value === null || typeof value !== 'object') {
    return null;
  }
  const { toRunId, title, outcome, reason, text } = value as Record<
    string,
    unknown
  >;
  const reasonValue = reason ?? null;
  if (
    typeof toRunId !== 'string' ||
    typeof title !== 'string' ||
    typeof outcome !== 'string' ||
    !OUTCOMES.has(outcome) ||
    !(
      reasonValue === null ||
      (typeof reasonValue === 'string' && REASONS.has(reasonValue))
    )
  ) {
    return null;
  }
  return {
    toRunId,
    title,
    outcome: outcome as ThreadMessageOutcome,
    reason: reasonValue as ThreadMessageReason | null,
    text: typeof text === 'string' && text !== '' ? text : null,
  };
}

/**
 * Why a message waits, in the words the sender and the user both read. The
 * same sentences the daemon writes into the sender's row.
 *
 * TWIN PARSER: `REASON_WORDS` in `apps/daemon/src/v1/agents/utils/thread-message-text.ts`
 * writes these sentences — a wording changed there must be mirrored here, and vice versa.
 */
const REASON_WORDS: Record<ThreadMessageReason, string> = {
  running_turn: 'waits for the turn running there to end',
  stopped: 'waits, because the user stopped that thread',
  failed: 'waits, because the last turn there failed',
  not_started: 'waits, because that thread has not started',
  question: 'waits, because that thread has a question for the user',
  sender_opted_out:
    'waits for its next turn: it was sent without waking that thread',
  cold_and_large:
    'waits for its next turn, because waking that large idle thread would be costly',
  wake_limit:
    'waits for its next turn, because other threads reached that thread too often this hour',
};

export function threadMessageReasonWords(reason: ThreadMessageReason): string {
  return REASON_WORDS[reason];
}

/** What became of a sent message, as a sentence under it. */
export function sentOutcomeWords(sent: ThreadMessageSent): string {
  if (sent.outcome === 'joined') {
    return 'Joined the running turn';
  }
  if (sent.outcome === 'woken') {
    return 'Started a turn there';
  }
  if (sent.reason === null) {
    return 'Waiting';
  }
  const words = REASON_WORDS[sent.reason];
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/** The same reasons as the thread holding the message reads them. */
const WAITING_WORDS: Record<ThreadMessageReason, string> = {
  running_turn: 'Goes out when this turn ends',
  stopped: 'Goes out with the next turn: this thread was stopped',
  failed: 'Goes out with the next turn: the last turn failed',
  not_started: 'Goes out with the first turn',
  question: 'Goes out once you have answered: a question waits for you here',
  sender_opted_out:
    'Goes out with the next turn: the sender did not wake this thread',
  cold_and_large:
    'Goes out with the next turn: waking this large idle thread would be costly',
  wake_limit:
    'Goes out with the next turn: other threads reached this one too often this hour',
};

export function waitingMessageReasonWords(reason: ThreadMessageReason): string {
  return WAITING_WORDS[reason];
}
