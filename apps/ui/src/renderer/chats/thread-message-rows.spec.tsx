// @vitest-environment jsdom
import { describe, expect, it } from 'vitest';

import { mountIntoDocument } from '../__tests__/mount-into-document';
import type { ItemDto as ChatItem } from '../autogenerated';
import { TranscriptContexts } from './chat-providers';
import { TranscriptItem } from './transcript-item';
import type { TranscriptNodeMeta } from './transcript-payload';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const render = mountIntoDocument();

const systemRow = (payload: Record<string, unknown>): ChatItem => ({
  id: 'i1',
  runId: 'r1',
  memberId: 'manager',
  seq: 1,
  kind: 'system',
  role: null,
  payload,
  createdAt: '2026-11-06T12:00:00Z',
});

const NODES: ReadonlyMap<string, TranscriptNodeMeta> = new Map([
  ['manager', { name: 'Manager', kind: 'agent' }],
]);

describe('thread message rows in the transcript', () => {
  it('draws a message from another thread as its card, not as the daemon’s sentence', () => {
    const el = render(
      <TranscriptItem
        item={systemRow({
          severity: 'info',
          message: 'Message from Pelican: hi',
          threadMessages: [
            {
              id: 'm1',
              fromRunId: 'r-pelican',
              fromTitle: 'Pelican',
              fromMember: null,
              text: 'hi',
            },
          ],
          woke: false,
        })}
      />,
    );
    const card = el.querySelector<HTMLElement>(
      '[data-slot="thread-event-card"]',
    );
    expect(card?.dataset.kind).toBe('received');
    expect(card?.dataset.run).toBe('r-pelican');
    expect(el.textContent).not.toContain('Message from Pelican: hi');
  });

  it('draws the turn a message woke as the card naming that thread', () => {
    const el = render(
      <TranscriptItem
        nodes={NODES}
        item={systemRow({
          severity: 'info',
          message: 'Woken by a message from Pelican.',
          threadWake: { fromRunId: 'r-pelican', fromTitle: 'Pelican' },
          woke: true,
        })}
      />,
    );
    const card = el.querySelector<HTMLElement>(
      '[data-slot="thread-event-card"]',
    );
    expect(card?.dataset.kind).toBe('woken');
    expect(card?.textContent).toContain('Woken by a message from');
    expect(card?.textContent).toContain('Pelican');
    expect(el.textContent).not.toContain('Woken by a message from Pelican.');
  });

  it('draws a send this thread made as its card, with what became of it', () => {
    const el = render(
      <TranscriptItem
        item={systemRow({
          severity: 'info',
          message:
            'Message to "Otter" waits, because the user stopped that thread.',
          threadMessageSent: {
            toRunId: 'r-otter',
            title: 'Otter',
            outcome: 'waiting',
            reason: 'stopped',
          },
          woke: false,
        })}
      />,
    );
    const sent = el.querySelector<HTMLElement>(
      '[data-slot="thread-event-card"]',
    );
    expect(sent?.dataset.kind).toBe('sent');
    expect(
      sent?.querySelector('[data-slot="thread-event-outcome"]')?.textContent,
    ).toBe('Waits, because the user stopped that thread');
  });

  it('draws a finished thread as its card, not as the bare done line', () => {
    const el = render(
      <TranscriptItem
        item={systemRow({
          severity: 'info',
          message: 't22 is done',
          threadDone: [
            {
              runId: 'r-otter',
              title: 'Otter',
              handle: 't22',
              summary: 'PRI-10 cancelled.',
              pullRequest: 146,
            },
          ],
          woke: true,
        })}
      />,
    );
    const card = el.querySelector<HTMLElement>(
      '[data-slot="thread-event-card"]',
    );
    expect(card?.dataset.kind).toBe('done');
    expect(card?.textContent).toContain('PRI-10 cancelled.');
    expect(el.textContent).not.toContain('t22 is done');
  });

  it('heads the card with the thread as the view names it, through the transcript contexts', () => {
    const el = render(
      <TranscriptContexts
        collapseToolSteps={false}
        runActivity={null}
        turnDurations={new Map()}
        revealCallBlock={null}
        revealCall={null}
        openSubagentDetail={null}
        runOutcomes={{
          newest: new Map(),
          showRepo: false,
          resolved: new Map(),
        }}
        runStages={null}
        openTeamNote={null}
        openThread={null}
        threadIdentities={
          new Map([
            [
              'r-pelican',
              {
                title: 'Pelican — fix the login redirect',
                project: 'Web',
                projectColor: 'teal',
                agentLabel: 'claude',
                isTeam: false,
              },
            ],
          ])
        }>
        <TranscriptItem
          item={systemRow({
            severity: 'info',
            message: 'Woken by a message from Pelican.',
            threadWake: { fromRunId: 'r-pelican', fromTitle: 'Pelican' },
            woke: true,
          })}
        />
      </TranscriptContexts>,
    );
    const card = el.querySelector<HTMLElement>(
      '[data-slot="thread-event-card"]',
    );
    expect(card?.dataset.color).toBe('teal');
    expect(card?.textContent).toContain('Pelican — fix the login redirect');
    expect(
      el.querySelector('[data-slot="thread-event-project"]')?.textContent,
    ).toBe('Web');
  });

  it('leaves an ordinary system row to the rows it always drew', () => {
    const el = render(
      <TranscriptItem
        item={systemRow({
          severity: 'info',
          message: 'Plain notice.',
          woke: false,
        })}
      />,
    );
    expect(el.querySelector('[data-slot="thread-event-card"]')).toBeNull();
    expect(el.textContent).toContain('Plain notice.');
  });
});
