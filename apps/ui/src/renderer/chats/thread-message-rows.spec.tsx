// @vitest-environment jsdom
import { describe, expect, it } from 'vitest';

import { mountIntoDocument } from '../__tests__/mount-into-document';
import type { ItemDto as ChatItem } from '../autogenerated';
import { TranscriptItem } from './transcript-item';
import type { TranscriptNodeMeta } from './transcript-payload';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const render = mountIntoDocument();

const systemRow = (payload: Record<string, unknown>): ChatItem => ({
  id: 'i1',
  runId: 'r1',
  memberId: 'manager',
  seq: 1,
  kind: 'system',
  role: null,
  payload,
  createdAt: '2026-11-06T12:00:00Z',
});

const NODES: ReadonlyMap<string, TranscriptNodeMeta> = new Map([
  ['manager', { name: 'Manager', kind: 'agent' }],
]);

describe('thread message rows in the transcript', () => {
  it('draws a message from another thread as its card, not as the daemon’s sentence', () => {
    const el = render(
      <TranscriptItem
        item={systemRow({
          severity: 'info',
          message: 'Message from Pelican: hi',
          threadMessages: [
            {
              id: 'm1',
              fromRunId: 'r-pelican',
              fromTitle: 'Pelican',
              fromMember: null,
              text: 'hi',
            },
          ],
          woke: false,
        })}
      />,
    );
    expect(
      el.querySelector('[data-slot="thread-message-card"]'),
    ).not.toBeNull();
    expect(el.textContent).not.toContain('Message from Pelican: hi');
  });

  it('draws the turn a message woke as the divider naming that thread', () => {
    const el = render(
      <TranscriptItem
        nodes={NODES}
        item={systemRow({
          severity: 'info',
          message: 'Woken by a message from Pelican.',
          threadWake: { fromRunId: 'r-pelican', fromTitle: 'Pelican' },
          woke: true,
        })}
      />,
    );
    expect(
      el.querySelector('[data-slot="thread-wake-divider"]')?.textContent,
    ).toContain('Manager picked back up — a message from Pelican');
  });

  it('draws a send this thread made as its row, with what became of it', () => {
    const el = render(
      <TranscriptItem
        item={systemRow({
          severity: 'info',
          message:
            'Message to "Otter" waits, because the user stopped that thread.',
          threadMessageSent: {
            toRunId: 'r-otter',
            title: 'Otter',
            outcome: 'waiting',
            reason: 'stopped',
          },
          woke: false,
        })}
      />,
    );
    const sent = el.querySelector('[data-slot="thread-message-sent"]');
    expect(sent?.getAttribute('data-outcome')).toBe('waiting');
    expect(sent?.textContent).toContain(
      'waits, because the user stopped that thread',
    );
  });

  it('leaves an ordinary system row to the rows it always drew', () => {
    const el = render(
      <TranscriptItem
        item={systemRow({
          severity: 'info',
          message: 'Plain notice.',
          woke: false,
        })}
      />,
    );
    expect(el.querySelector('[data-slot="thread-message-card"]')).toBeNull();
    expect(el.querySelector('[data-slot="thread-message-sent"]')).toBeNull();
    expect(el.textContent).toContain('Plain notice.');
  });
});
