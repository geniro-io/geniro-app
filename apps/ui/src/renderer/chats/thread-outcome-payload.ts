/**
 * What a `thread_outcome` row's payload says: how the whole thread ended, as one
 * of its agents recorded it with `record_outcome`.
 *
 * TWIN PARSER: `ThreadOutcomePayloadSchema` in
 * `apps/daemon/src/v1/agents/chat.types.ts`, which writes these rows. An item
 * payload is `z.unknown()` on the wire, so the two sides read one shape
 * independently; a field renamed there must change here.
 */

import { ThreadOutcomeKind } from '../autogenerated';

export interface ThreadOutcomePayload {
  kind: ThreadOutcomeKind;
  summary: string;
  nodeId: string;
}

const KINDS: ReadonlySet<string> = new Set(Object.values(ThreadOutcomeKind));

export function readThreadOutcomePayload(
  payload: unknown,
): ThreadOutcomePayload | null {
  if (payload === null || typeof payload !== 'object') {
    return null;
  }
  const bag = payload as Record<string, unknown>;
  if (
    typeof bag.kind !== 'string' ||
    !KINDS.has(bag.kind) ||
    typeof bag.summary !== 'string' ||
    typeof bag.nodeId !== 'string'
  ) {
    return null;
  }
  return {
    kind: bag.kind as ThreadOutcomeKind,
    summary: bag.summary,
    nodeId: bag.nodeId,
  };
}
