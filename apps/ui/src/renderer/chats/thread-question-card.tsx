/** How many times the pictures of one relayed answer are offered to its thread. */
export const RELAYED_IMAGES_SEND_ATTEMPTS = 5;

/** A managed thread's open request, as the manager chat's relayed card carries it. */
export interface ThreadQuestionRelay {
  threadRunId: string;
  threadIsTeam: boolean;
  /** The thread's own request this relay answers; absent on a row that never named it. */
  threadRequestId?: string;
  handle: string;
  threadTitle: string;
  toolName: string;
  input: unknown;
  questions?: unknown;
  options?: unknown;
}

function readString(value: unknown): string | null {
  return typeof value === 'string' && value.trim() !== '' ? value : null;
}

/**
 * The relayed request on a `thread_question` row's `input`, or null when its
 * thread, handle, title or tool is missing — the caller then draws the permission
 * body, which is still answerable.
 *
 * TWIN PARSER: `ThreadQuestionCardInput` in `apps/daemon/src/v1/agents/chat.types.ts`,
 * filled by `CommandCenterNotifyService`. A key renamed on either side must be
 * renamed on both.
 */
export function readThreadQuestionRelay(
  input: unknown,
): ThreadQuestionRelay | null {
  const record = recordOf(input);
  const threadRunId = readString(record?.threadRunId);
  const handle = readString(record?.handle);
  const threadTitle = readString(record?.threadTitle);
  const toolName = readString(record?.toolName);
  if (
    record === null ||
    threadRunId === null ||
    handle === null ||
    threadTitle === null ||
    toolName === null
  ) {
    return null;
  }
  const threadRequestId = readString(record.threadRequestId);
  return {
    threadRunId,
    threadIsTeam: record.threadIsTeam === true,
    ...(threadRequestId === null ? {} : { threadRequestId }),
    handle,
    threadTitle,
    toolName,
    input: record.input,
    ...(record.questions === undefined ? {} : { questions: record.questions }),
    ...(record.options === undefined ? {} : { options: record.options }),
  };
}

/** The relayed request of an `approval_request` row, or null when the row is not a readable relay. */
export function threadQuestionRelayOfRow(
  payload: unknown,
): ThreadQuestionRelay | null {
  const record = recordOf(payload);
  return record?.toolName === THREAD_QUESTION_CARD
    ? readThreadQuestionRelay(record.input)
    : null;
}

/**
 * Send the pictures pasted into a relayed answer to the thread it answers, as
 * their own message. The answer itself starts the thread's turn, so the thread
 * refuses them RUN_BUSY while that turn runs: they are offered again each time
 * the thread's run settles, as a queued message would be.
 */
export function deliverRelayedImages(
  relay: ThreadQuestionRelay,
  images: SendMessageDtoImagesInner[],
  apis: Pick<DaemonApis, 'chats' | 'teams'>,
  client: Pick<DaemonClient, 'onRunStatus'>,
  onError: (err: unknown) => void,
): void {
  const message = {
    runId: relay.threadRunId,
    sendMessageDto: { text: '', images },
  };
  let attempts = 0;
  let sending = false;
  let stopWatching: (() => void) | null = null;
  const finish = (): void => {
    stopWatching?.();
    stopWatching = null;
  };
  const attempt = (): void => {
    sending = true;
    attempts += 1;
    (relay.threadIsTeam
      ? apis.teams.sendTeamRunMessage(message)
      : apis.chats.sendChatMessage(message)
    ).then(
      () => {
        sending = false;
        finish();
      },
      (err: unknown) => {
        sending = false;
        if (!isRunBusyError(err) || attempts >= RELAYED_IMAGES_SEND_ATTEMPTS) {
          finish();
          onError(err);
          return;
        }
        stopWatching ??= client.onRunStatus((event) => {
          if (
            !sending &&
            event.runId === relay.threadRunId &&
            event.status !== null &&
            isSettledRunStatus(event.status) &&
            settleReleasesQueue(event.status)
          ) {
            attempt();
          }
        });
      },
    );
  };
  attempt();
}

/** What became of an answer pressed on the card, as its verdict row's `outcome` says. */
function deliveryNote(outcome: unknown): string | null {
  return outcome === 'not-delivered'
    ? 'Not delivered — the thread no longer waited on this.'
    : null;
}

type QuestionState = 'waiting' | 'answered' | 'declined' | 'closed';

const STATE_META: Record<
  QuestionState,
  { icon: LucideIcon; label: string; tone: EventTone }
> = {
  waiting: {
    icon: MessageCircleQuestion,
    label: 'Question for you',
    tone: 'warning',
  },
  answered: { icon: CircleCheck, label: 'Answered', tone: 'success' },
  declined: { icon: CircleX, label: 'Declined', tone: 'muted' },
  closed: { icon: CircleSlash, label: 'No longer open', tone: 'muted' },
};

function stateOf(verdict: boolean | null, expired: boolean): QuestionState {
  if (verdict !== null) {
    return verdict ? 'answered' : 'declined';
  }
  return expired ? 'closed' : 'waiting';
}

/**
 * A managed thread's question or approval, drawn in the command center
 * manager's chat: headed by the thread as its node on the graph shows it,
 * with the thread's own card under it — answering that answers the thread.
 * Closed with no answer, it says so in place of the card. Folded, it is the
 * thread's card alone, which names the thread itself.
 */
export function ThreadQuestionCard({
  relay,
  verdict,
  outcome = null,
  expired = false,
  folded = false,
  children,
}: {
  relay: ThreadQuestionRelay;
  /** null while pending; the user's answer once the verdict item arrived. */
  verdict: boolean | null;
  /** The verdict row's `outcome`: whether the answer reached the thread. */
  outcome?: unknown;
  /** Closed with no answer — answered in the thread, or its turn ended. */
  expired?: boolean;
  folded?: boolean;
  children: React.ReactNode;
}): React.JSX.Element {
  const known = useThreadIdentity(relay.threadRunId);
  const open = useContext(ThreadOpenContext);
  const identity = known ?? bareThreadIdentity(relay.threadTitle);
  const state = stateOf(verdict, expired);
  const meta = STATE_META[state];
  const note = verdict === null ? null : deliveryNote(outcome);
  const noteLine =
    note === null ? null : <p className="text-xs text-destructive">{note}</p>;
  if (folded && state !== 'closed') {
    return (
      <article
        data-slot="thread-question-card"
        data-state={state}
        data-run={relay.threadRunId}
        data-folded={true}
        className="flex w-full min-w-0 flex-col gap-1.5">
        {children}
        {noteLine}
      </article>
    );
  }
  return (
    <article
      data-slot="thread-question-card"
      data-state={state}
      data-run={relay.threadRunId}
      className="flex w-full min-w-0 flex-col gap-2.5 rounded-lg border border-border/70 bg-card px-3 py-2.5 text-sm">
      <EventLine
        icon={meta.icon}
        tone={meta.tone}
        label={meta.label}
        slot="thread-question"
        handle={relay.handle}
        waiting={state === 'waiting'}
      />
      {open === null ? null : (
        <div
          data-slot="thread-question-actions"
          className="-mx-1 flex flex-wrap items-center gap-1">
          <ThreadActionButton
            slot="thread-question-open-chat"
            label={`Open the chat of ${identity.title}`}
            title="Show this thread and open its chat"
            icon={<MessageSquareText aria-hidden="true" />}
            onClick={() => open(relay.threadRunId)}>
            Open chat
          </ThreadActionButton>
        </div>
      )}
      <ThreadHead
        identity={identity}
        slot="thread-question"
        onOpen={open === null ? undefined : () => open(relay.threadRunId)}
      />
      <QuestionContextMessages
        threadRunId={relay.threadRunId}
        threadRequestId={relay.threadRequestId ?? null}
      />
      {state === 'closed' ? (
        <p className="text-xs text-muted-foreground">
          No longer open — answered in the thread, or its turn ended.
        </p>
      ) : (
        children
      )}
      {noteLine}
    </article>
  );
}
