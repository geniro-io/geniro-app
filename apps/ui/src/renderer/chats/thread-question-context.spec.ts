import { describe, expect, it, type Mock, vi } from 'vitest';

import type { DaemonHandle } from '../../shared/contracts';
import type { ItemDto } from '../autogenerated';
import type { PublishedArtifact } from './published-artifact';
import {
  messagesBefore,
  QUESTION_CONTEXT_MESSAGES,
  threadContextReaderOf,
} from './thread-question-context';

function row(
  seq: number,
  kind: string,
  role: string | null,
  payload: Record<string, unknown>,
): ItemDto {
  return {
    id: `item-${seq}`,
    runId: 'thread-1',
    memberId: null,
    seq,
    kind,
    role,
    payload,
    createdAt: new Date(seq * 1000).toISOString(),
  } as ItemDto;
}

const HANDLE: DaemonHandle = {
  host: '127.0.0.1',
  port: 47615,
  token: 'launch-token',
  version: '1.0.0',
  startedAt: '2026-09-20T00:00:00.000Z',
};

const NO_ANSWERS = {
  readArtifactAnswers: vi.fn(),
  saveArtifactAnswers: vi.fn(),
};

const ROWS: ItemDto[] = [
  row(1, 'message', 'user', { text: 'Fix the cache' }),
  row(2, 'message', 'assistant', { text: 'Looking at it' }),
  row(3, 'tool_call', null, { name: 'Bash' }),
  row(4, 'message', 'assistant', { text: '   ' }),
  row(5, 'message', 'assistant', { text: 'Two caches could be meant' }),
  row(6, 'message', 'user', { text: 'The shared one' }),
  row(7, 'approval_request', null, {
    id: 'req-1',
    toolName: 'AskUserQuestion',
  }),
  row(8, 'message', 'assistant', { text: 'Thanks, clearing it' }),
];

describe('messagesBefore', () => {
  it('takes the last messages the thread exchanged before its question, oldest first, skipping tool rows and empty text', () => {
    expect(messagesBefore(ROWS, 'req-1')).toEqual([
      { seq: 2, role: 'assistant', text: 'Looking at it' },
      { seq: 5, role: 'assistant', text: 'Two caches could be meant' },
      { seq: 6, role: 'user', text: 'The shared one' },
    ]);
    expect(messagesBefore(ROWS, 'req-1')).toHaveLength(
      QUESTION_CONTEXT_MESSAGES,
    );
  });

  it('leaves out every page and picture the asking turn showed', () => {
    const shown = [
      ...ROWS.slice(0, 6),
      row(61, 'show_artifact', null, {
        artifactId: 'plan-page',
        version: 1,
        title: 'Launch plan',
        key: 'k'.repeat(64),
      }),
      row(62, 'show_gallery', null, { images: [{ path: '/tmp/a.png' }] }),
      ...ROWS.slice(6),
    ];
    expect(messagesBefore(shown, 'req-1')).toEqual([
      { seq: 2, role: 'assistant', text: 'Looking at it' },
      { seq: 5, role: 'assistant', text: 'Two caches could be meant' },
      { seq: 6, role: 'user', text: 'The shared one' },
    ]);
  });

  it('reads rows in seq order whatever order the page came in', () => {
    expect(messagesBefore([...ROWS].reverse(), 'req-1').at(-1)?.seq).toBe(6);
  });

  it('takes the newest messages on the page when the question is not on it', () => {
    expect(
      messagesBefore(ROWS, 'req-elsewhere').map((message) => message.seq),
    ).toEqual([5, 6, 8]);
    expect(messagesBefore(ROWS, null).map((message) => message.seq)).toEqual([
      5, 6, 8,
    ]);
  });
});

describe('threadContextReaderOf', () => {
  it('reads the root conversation once and answers what led up to a question raised there', async () => {
    const listRunItems = vi
      .fn()
      .mockResolvedValue({ items: ROWS, anchors: [] });
    const listCallMessages = vi.fn();
    const read = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems,
        listCallMessages,
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    ).read;

    const messages = await read('thread-1', 'req-1');

    expect(listRunItems).toHaveBeenCalledTimes(1);
    expect(listRunItems).toHaveBeenCalledWith(
      expect.objectContaining({ runId: 'thread-1', conversation: 'root' }),
    );
    expect(listCallMessages).not.toHaveBeenCalled();
    expect(messages.map((message) => message.seq)).toEqual([2, 5, 6]);
  });

  it('reads the messages of the member call a question was raised inside, before the question', async () => {
    const callRow = (seq: number, role: string, text: string): ItemDto => ({
      ...row(seq, 'message', role, { text }),
      inCall: 'call-1',
    });
    const asked = {
      ...row(9, 'approval_request', null, {
        id: 'req-2',
        toolName: 'AskUserQuestion',
      }),
      inCall: 'call-1',
    };
    const listRunItems = vi.fn(async (request: { conversation?: string }) => ({
      items: request.conversation === 'root' ? ROWS : [...ROWS, asked],
      anchors: [],
    }));
    const listCallMessages = vi.fn().mockResolvedValue({
      messages: [
        callRow(7, 'assistant', 'Two caches in the call'),
        callRow(10, 'assistant', 'Sent after the question'),
      ],
      hasOlder: false,
    });
    const read = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems,
        listCallMessages,
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    ).read;

    const messages = await read('thread-1', 'req-2');

    expect(listCallMessages).toHaveBeenCalledWith({
      runId: 'thread-1',
      callId: 'call-1',
      limit: 20,
    });
    expect(messages).toEqual([
      { seq: 7, role: 'assistant', text: 'Two caches in the call' },
    ]);
  });

  it('reads the brief and the member’s words of the call a card was raised in, though the card stands in the run’s own flow', async () => {
    const rootRows: ItemDto[] = [
      row(0, 'message', 'user', { text: 'Call the helper now' }),
      row(4, 'call_started', null, {
        callId: 'call-1',
        message: 'Run your command',
      }),
      row(9, 'approval_request', null, {
        id: 'thread-1::call:call-1#approval',
        toolName: 'Bash',
        callId: 'call-1',
      }),
    ];
    const listRunItems = vi
      .fn()
      .mockResolvedValue({ items: rootRows, anchors: [] });
    const listCallMessages = vi.fn().mockResolvedValue({
      messages: [
        {
          ...row(7, 'message', 'assistant', { text: 'Helper context' }),
          inCall: 'call-1',
        },
        {
          ...row(13, 'message', 'assistant', { text: 'Said after the card' }),
          inCall: 'call-1',
        },
      ],
      hasOlder: false,
    });
    const read = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems,
        listCallMessages,
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    ).read;

    const messages = await read('thread-1', 'thread-1::call:call-1#approval');

    expect(listRunItems).toHaveBeenCalledTimes(1);
    expect(listCallMessages).toHaveBeenCalledWith({
      runId: 'thread-1',
      callId: 'call-1',
      limit: 20,
    });
    expect(messages).toEqual([
      { seq: 4, role: 'user', text: 'Run your command' },
      { seq: 7, role: 'assistant', text: 'Helper context' },
    ]);
  });

  it('keeps the root messages when the question is found neither on the root page nor inside a call', async () => {
    const listRunItems = vi
      .fn()
      .mockResolvedValue({ items: ROWS.slice(0, 6), anchors: [] });
    const listCallMessages = vi.fn();
    const read = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems,
        listCallMessages,
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    ).read;

    const messages = await read('thread-1', 'req-elsewhere');

    expect(listCallMessages).not.toHaveBeenCalled();
    expect(messages.map((message) => message.seq)).toEqual([2, 5, 6]);
  });
});

const PAGE = (artifactId: string, version: number): PublishedArtifact => ({
  artifactId,
  version,
  title: artifactId,
  summary: null,
  key: 'a'.repeat(64),
});

describe('threadContextReaderOf over a member call', () => {
  const callRow = (
    seq: number,
    kind: string,
    role: string | null,
    payload: Record<string, unknown>,
    inCall: string,
  ): ItemDto => ({ ...row(seq, kind, role, payload), inCall });

  const memberRow = (
    seq: number,
    kind: string,
    payload: Record<string, unknown>,
    memberId: string,
  ): ItemDto => ({ ...row(seq, kind, 'assistant', payload), memberId });

  const CALL_ROOT: ItemDto[] = [
    row(4, 'call_started', null, {
      callId: 'call-1',
      message: 'Run your command',
    }),
    {
      ...row(9, 'approval_request', null, {
        id: 'thread-1::call:call-1#approval',
        toolName: 'Bash',
        callId: 'call-1',
      }),
      memberId: 'helper',
    },
  ];

  const CALL_MESSAGES = {
    messages: [
      callRow(5, 'message', 'assistant', { text: 'Helper context' }, 'call-1'),
    ],
    hasOlder: false,
  };

  it('keeps a call’s brief from the root page though the whole run’s newest rows no longer hold it', async () => {
    const listRunItems = vi.fn(async (request: { conversation?: string }) => ({
      items:
        request.conversation === 'root'
          ? CALL_ROOT
          : CALL_ROOT.filter((item) => item.kind !== 'call_started'),
      anchors: [],
    }));
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems,
        listCallMessages: vi.fn().mockResolvedValue(CALL_MESSAGES),
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    );

    const messages = await reader.read(
      'thread-1',
      'thread-1::call:call-1#approval',
    );

    expect(messages[0]).toEqual({
      seq: 4,
      role: 'user',
      text: 'Run your command',
    });
  });

  it('keeps a call’s brief that the root page carries as an anchor, however many rows of the run’s own flow stand between it and the question', async () => {
    const brief = row(4, 'call_started', null, {
      callId: 'call-1',
      message: 'Run your command',
    });
    const busy = Array.from({ length: 450 }, (_, index) =>
      memberRow(
        100 + index,
        'approval_request',
        { id: `other-${index}`, toolName: 'Bash', callId: 'call-2' },
        'reviewer',
      ),
    );
    const asked: ItemDto = {
      ...row(900, 'approval_request', null, {
        id: 'thread-1::call:call-1#approval',
        toolName: 'Bash',
        callId: 'call-1',
      }),
      memberId: 'helper',
    };
    const listRunItems = vi.fn(
      async (request: { conversation?: string; limit?: number }) => {
        const limit = request.limit ?? busy.length;
        return request.conversation === 'root'
          ? { items: busy.slice(-limit), anchors: [brief] }
          : { items: [...busy, asked].slice(-limit), anchors: [] };
      },
    );
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems,
        listCallMessages: vi.fn().mockResolvedValue(CALL_MESSAGES),
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    );

    const messages = await reader.read(
      'thread-1',
      'thread-1::call:call-1#approval',
    );

    expect(messages).toEqual([
      { seq: 4, role: 'user', text: 'Run your command' },
      { seq: 5, role: 'assistant', text: 'Helper context' },
    ]);
  });

  it('keeps a call’s brief beside the member’s last three messages, never in place of one', async () => {
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems: vi.fn().mockResolvedValue({
          items: [
            row(1, 'call_started', null, {
              callId: 'call-1',
              message: 'Run your command',
            }),
            {
              ...row(6, 'approval_request', null, {
                id: 'thread-1::call:call-1#approval',
                toolName: 'Bash',
                callId: 'call-1',
              }),
              memberId: 'helper',
            },
          ],
          anchors: [],
        }),
        listCallMessages: vi.fn().mockResolvedValue({
          messages: [
            callRow(2, 'message', 'assistant', { text: 'First' }, 'call-1'),
            callRow(3, 'message', 'assistant', { text: 'Second' }, 'call-1'),
            callRow(4, 'message', 'assistant', { text: 'Third' }, 'call-1'),
            callRow(5, 'message', 'assistant', { text: 'Fourth' }, 'call-1'),
          ],
          hasOlder: false,
        }),
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    );

    const messages = await reader.read(
      'thread-1',
      'thread-1::call:call-1#approval',
    );

    expect(
      messages.flatMap((entry) => ('text' in entry ? [entry.text] : [])),
    ).toEqual(['Run your command', 'Second', 'Third', 'Fourth']);
  });
});

describe('threadContextReaderOf binds its thread’s run', () => {
  it('binds the picture loader, the page URL and the answers store to the thread’s run', async () => {
    const readLocalImage = vi
      .fn()
      .mockResolvedValue({ mediaType: 'image/png', data: 'AAAA' });
    const readArtifactAnswers = vi
      .fn()
      .mockResolvedValue({ values: { pick: 'a' }, updatedAt: null });
    const saveArtifactAnswers = vi
      .fn()
      .mockResolvedValue({ values: { pick: 'b' }, updatedAt: 'now' });
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems: vi.fn(),
        listCallMessages: vi.fn(),
        readLocalImage,
        readArtifactAnswers,
        saveArtifactAnswers,
      },
      HANDLE,
    );

    await expect(reader.loadImage('thread-1')('/tmp/a.png')).resolves.toBe(
      'data:image/png;base64,AAAA',
    );
    expect(readLocalImage).toHaveBeenCalledWith({
      runId: 'thread-1',
      path: '/tmp/a.png',
    });
    expect(
      reader.artifactUrl('thread-1')(PAGE('pr-673-acceptance', 1)),
    ).toContain('/v1/artifacts/thread-1/pr-673-acceptance');
    const answers = reader.answers('thread-1');
    await expect(answers.read('pr-673-acceptance')).resolves.toEqual({
      pick: 'a',
    });
    await answers.save('pr-673-acceptance', { pick: 'b' }, Symbol('frame'));
    expect(readArtifactAnswers).toHaveBeenCalledWith({
      runId: 'thread-1',
      artifactId: 'pr-673-acceptance',
    });
    expect(saveArtifactAnswers).toHaveBeenCalledWith({
      runId: 'thread-1',
      artifactId: 'pr-673-acceptance',
      saveArtifactAnswersDto: { changes: { pick: 'b' } },
    });
  });
});

describe('the listing of a thread run a reader keeps', () => {
  const HANDLE: DaemonHandle = {
    host: '127.0.0.1',
    port: 47615,
    token: 'launch-token',
    version: '1.0.0',
    startedAt: '2026-09-20T00:00:00.000Z',
  };

  function chatsWith(readRunArtifacts: Mock) {
    return {
      listRunItems: vi.fn(),
      listCallMessages: vi.fn(),
      readLocalImage: vi.fn(),
      readArtifactAnswers: vi.fn(),
      saveArtifactAnswers: vi.fn(),
      readRunArtifacts,
    };
  }

  it('reads a run listing once and names each page as the attachment reader needs it', async () => {
    const readRunArtifacts = vi.fn().mockResolvedValue({
      artifacts: [
        {
          artifactId: 'plan',
          version: 2,
          title: 'Plan',
          summary: null,
          key: 'k',
          at: '2026-09-20T00:00:00.000Z',
          seq: 3,
        },
      ],
    });
    const reader = threadContextReaderOf(chatsWith(readRunArtifacts), HANDLE);

    const first = await reader.artifacts('thread-1');
    const second = await reader.artifacts('thread-1');

    expect(readRunArtifacts).toHaveBeenCalledTimes(1);
    expect(readRunArtifacts).toHaveBeenCalledWith({ runId: 'thread-1' });
    expect(first).toEqual([
      {
        artifactId: 'plan',
        version: 2,
        title: 'Plan',
        summary: null,
        key: 'k',
      },
    ]);
    expect(second).toEqual(first);
  });

  it('reads the listing again after a read fails, rather than keeping the failure', async () => {
    const readRunArtifacts = vi
      .fn()
      .mockRejectedValueOnce(new Error('daemon down'))
      .mockResolvedValueOnce({ artifacts: [] });
    const reader = threadContextReaderOf(chatsWith(readRunArtifacts), HANDLE);

    await expect(reader.artifacts('thread-1')).rejects.toThrow('daemon down');
    await expect(reader.artifacts('thread-1')).resolves.toEqual([]);
    expect(readRunArtifacts).toHaveBeenCalledTimes(2);
  });

  it('reads the listing again when a kept one lacks a wanted page or holds an older version', async () => {
    const row = (artifactId: string, version: number) => ({
      artifactId,
      version,
      title: artifactId,
      summary: null,
      key: 'k',
      at: '2026-09-20T00:00:00.000Z',
      seq: 3,
    });
    const readRunArtifacts = vi
      .fn()
      .mockResolvedValueOnce({ artifacts: [row('plan', 1)] })
      .mockResolvedValueOnce({ artifacts: [row('plan', 1), row('voices', 1)] })
      .mockResolvedValueOnce({ artifacts: [row('plan', 2), row('voices', 1)] });
    const reader = threadContextReaderOf(chatsWith(readRunArtifacts), HANDLE);

    await reader.artifacts('thread-1');
    const withNew = await reader.artifacts('thread-1', [
      { artifactId: 'voices', version: 1 },
    ]);
    const withNewer = await reader.artifacts('thread-1', [
      { artifactId: 'plan', version: 2 },
    ]);
    await reader.artifacts('thread-1', [{ artifactId: 'plan', version: 2 }]);

    expect(withNew.map((page) => page.artifactId)).toContain('voices');
    expect(withNewer.find((page) => page.artifactId === 'plan')?.version).toBe(
      2,
    );
    expect(readRunArtifacts).toHaveBeenCalledTimes(3);
  });

  it('reads the listing again for a finish it was not read for, once per finish', async () => {
    const readRunArtifacts = vi.fn().mockResolvedValue({ artifacts: [] });
    const reader = threadContextReaderOf(chatsWith(readRunArtifacts), HANDLE);

    await reader.artifacts('thread-1');
    await reader.artifacts('thread-1', [], 'finish-1');
    await reader.artifacts('thread-1', [], 'finish-1');
    await reader.artifacts('thread-1');
    await reader.artifacts('thread-1', [], 'finish-2');
    await reader.artifacts('thread-1', [], 'finish-1');

    expect(readRunArtifacts).toHaveBeenCalledTimes(3);
  });
});
