describe('threadContextReaderOf and the pages and pictures', () => {
  const callRow = (
    seq: number,
    kind: string,
    role: string | null,
    payload: Record<string, unknown>,
    inCall: string,
  ): ItemDto => ({ ...row(seq, kind, role, payload), inCall });

  const memberRow = (
    seq: number,
    kind: string,
    payload: Record<string, unknown>,
    memberId: string,
  ): ItemDto => ({ ...row(seq, kind, 'assistant', payload), memberId });

  const CALL_ROOT: ItemDto[] = [
    row(1, 'show_artifact', 'assistant', PAGE_PAYLOAD('root-page', 1)),
    memberRow(
      2,
      'show_artifact',
      PAGE_PAYLOAD('earlier-call-page', 1),
      'helper',
    ),
    row(4, 'call_started', null, {
      callId: 'call-1',
      message: 'Run your command',
    }),
    memberRow(6, 'show_artifact', PAGE_PAYLOAD('call-page', 1), 'helper'),
    memberRow(
      7,
      'show_gallery',
      { title: 'Call shots', images: [{ path: '/tmp/call.png' }] },
      'helper',
    ),
    memberRow(8, 'show_artifact', PAGE_PAYLOAD('lead-page', 1), 'manager'),
    {
      ...row(9, 'approval_request', null, {
        id: 'thread-1::call:call-1#approval',
        toolName: 'Bash',
        callId: 'call-1',
      }),
      memberId: 'helper',
    },
  ];

  const CALL_MESSAGES = {
    messages: [
      callRow(5, 'message', 'assistant', { text: 'Helper context' }, 'call-1'),
    ],
    hasOlder: false,
  };

  it('takes a call’s pages and pictures from the root page, by the member that asked, after the call’s brief', async () => {
    const listRunItems = vi
      .fn()
      .mockResolvedValue({ items: CALL_ROOT, anchors: [] });
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems,
        listCallMessages: vi.fn().mockResolvedValue(CALL_MESSAGES),
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    );

    const entries = await reader.read(
      'thread-1',
      'thread-1::call:call-1#approval',
    );

    expect(listRunItems).toHaveBeenCalledTimes(1);
    expect(entries).toEqual([
      { seq: 4, role: 'user', text: 'Run your command' },
      { seq: 5, role: 'assistant', text: 'Helper context' },
      expect.objectContaining({
        seq: 6,
        artifact: expect.objectContaining({ artifactId: 'call-page' }),
      }),
      expect.objectContaining({
        seq: 7,
        gallery: expect.objectContaining({ title: 'Call shots' }),
      }),
    ]);
  });

  it('keeps a call’s brief from the root page though the whole run’s newest rows no longer hold it', async () => {
    const listRunItems = vi.fn(async (request: { conversation?: string }) => ({
      items:
        request.conversation === 'root'
          ? CALL_ROOT
          : CALL_ROOT.filter((item) => item.kind !== 'call_started'),
      anchors: [],
    }));
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems,
        listCallMessages: vi.fn().mockResolvedValue(CALL_MESSAGES),
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    );

    const entries = await reader.read(
      'thread-1',
      'thread-1::call:call-1#approval',
    );

    expect(entries[0]).toEqual({
      seq: 4,
      role: 'user',
      text: 'Run your command',
    });
  });

  it('keeps a call’s brief and its member’s pages however many rows of the run’s own flow stand between them and the question', async () => {
    const brief = row(4, 'call_started', null, {
      callId: 'call-1',
      message: 'Run your command',
    });
    const busy = Array.from({ length: 450 }, (_, index) =>
      memberRow(
        100 + index,
        'approval_request',
        { id: `other-${index}`, toolName: 'Bash', callId: 'call-2' },
        'reviewer',
      ),
    );
    const flow: ItemDto[] = [
      memberRow(2, 'show_artifact', PAGE_PAYLOAD('earlier-page', 1), 'helper'),
      brief,
      memberRow(6, 'show_artifact', PAGE_PAYLOAD('call-page', 1), 'helper'),
      ...busy,
      {
        ...row(900, 'approval_request', null, {
          id: 'thread-1::call:call-1#approval',
          toolName: 'Bash',
          callId: 'call-1',
        }),
        memberId: 'helper',
      },
    ];
    const listRunItems = vi.fn(
      async (request: {
        conversation?: string;
        limit?: number;
        beforeSeq?: number;
      }) => {
        if (request.conversation !== 'root') {
          return { items: busy.slice(-(request.limit ?? 0)), anchors: [] };
        }
        const items = flow
          .filter(
            (item) =>
              request.beforeSeq === undefined || item.seq < request.beforeSeq,
          )
          .slice(-(request.limit ?? flow.length));
        const firstSeq = items[0]?.seq ?? Infinity;
        return {
          items,
          anchors: brief.seq < firstSeq ? [brief] : [],
        };
      },
    );
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems,
        listCallMessages: vi.fn().mockResolvedValue(CALL_MESSAGES),
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    );

    const entries = await reader.read(
      'thread-1',
      'thread-1::call:call-1#approval',
    );

    expect(entries).toEqual([
      { seq: 4, role: 'user', text: 'Run your command' },
      { seq: 5, role: 'assistant', text: 'Helper context' },
      expect.objectContaining({
        seq: 6,
        artifact: expect.objectContaining({ artifactId: 'call-page' }),
      }),
    ]);
    expect(listRunItems).toHaveBeenCalledTimes(3);
    expect(listRunItems).toHaveBeenLastCalledWith(
      expect.objectContaining({ conversation: 'root', beforeSeq: 151 }),
    );
  });

  it('keeps a call’s brief beside the member’s last three messages, never in place of one', async () => {
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems: vi.fn().mockResolvedValue({
          items: [
            row(1, 'call_started', null, {
              callId: 'call-1',
              message: 'Run your command',
            }),
            {
              ...row(6, 'approval_request', null, {
                id: 'thread-1::call:call-1#approval',
                toolName: 'Bash',
                callId: 'call-1',
              }),
              memberId: 'helper',
            },
          ],
          anchors: [],
        }),
        listCallMessages: vi.fn().mockResolvedValue({
          messages: [
            callRow(2, 'message', 'assistant', { text: 'First' }, 'call-1'),
            callRow(3, 'message', 'assistant', { text: 'Second' }, 'call-1'),
            callRow(4, 'message', 'assistant', { text: 'Third' }, 'call-1'),
            callRow(5, 'message', 'assistant', { text: 'Fourth' }, 'call-1'),
          ],
          hasOlder: false,
        }),
        readLocalImage: vi.fn(),
        ...NO_ANSWERS,
      },
      HANDLE,
    );

    const entries = await reader.read(
      'thread-1',
      'thread-1::call:call-1#approval',
    );

    expect(
      entries.flatMap((entry) => ('text' in entry ? [entry.text] : [])),
    ).toEqual(['Run your command', 'Second', 'Third', 'Fourth']);
  });

  it('binds the picture loader, the page URL and the answers store to the thread’s run', async () => {
    const readLocalImage = vi
      .fn()
      .mockResolvedValue({ mediaType: 'image/png', data: 'AAAA' });
    const readArtifactAnswers = vi
      .fn()
      .mockResolvedValue({ values: { pick: 'a' }, updatedAt: null });
    const saveArtifactAnswers = vi
      .fn()
      .mockResolvedValue({ values: { pick: 'b' }, updatedAt: 'now' });
    const reader = threadContextReaderOf(
      {
        readRunArtifacts: vi.fn(),
        listRunItems: vi.fn(),
        listCallMessages: vi.fn(),
        readLocalImage,
        readArtifactAnswers,
        saveArtifactAnswers,
      },
      HANDLE,
    );

    await expect(reader.loadImage('thread-1')('/tmp/a.png')).resolves.toBe(
      'data:image/png;base64,AAAA',
    );
    expect(readLocalImage).toHaveBeenCalledWith({
      runId: 'thread-1',
      path: '/tmp/a.png',
    });
    expect(
      reader.artifactUrl('thread-1')(PAGE('pr-673-acceptance', 1)),
    ).toContain('/v1/artifacts/thread-1/pr-673-acceptance');
    const answers = reader.answers('thread-1');
    await expect(answers.read('pr-673-acceptance')).resolves.toEqual({
      pick: 'a',
    });
    await answers.save('pr-673-acceptance', { pick: 'b' }, Symbol('frame'));
    expect(readArtifactAnswers).toHaveBeenCalledWith({
      runId: 'thread-1',
      artifactId: 'pr-673-acceptance',
    });
    expect(saveArtifactAnswers).toHaveBeenCalledWith({
      runId: 'thread-1',
      artifactId: 'pr-673-acceptance',
      saveArtifactAnswersDto: { changes: { pick: 'b' } },
    });
  });
});

describe('the listing of a thread run a reader keeps', () => {
  const HANDLE: DaemonHandle = {
    host: '127.0.0.1',
    port: 47615,
    token: 'launch-token',
    version: '1.0.0',
    startedAt: '2026-09-20T00:00:00.000Z',
  };

  function chatsWith(readRunArtifacts: Mock) {
    return {
      listRunItems: vi.fn(),
      listCallMessages: vi.fn(),
      readLocalImage: vi.fn(),
      readArtifactAnswers: vi.fn(),
      saveArtifactAnswers: vi.fn(),
      readRunArtifacts,
    };
  }

  it('reads a run listing once and names each page as the attachment reader needs it', async () => {
    const readRunArtifacts = vi.fn().mockResolvedValue({
      artifacts: [
        {
          artifactId: 'plan',
          version: 2,
          title: 'Plan',
          summary: null,
          key: 'k',
          at: '2026-09-20T00:00:00.000Z',
          seq: 3,
        },
      ],
    });
    const reader = threadContextReaderOf(chatsWith(readRunArtifacts), HANDLE);

    const first = await reader.artifacts('thread-1');
    const second = await reader.artifacts('thread-1');

    expect(readRunArtifacts).toHaveBeenCalledTimes(1);
    expect(readRunArtifacts).toHaveBeenCalledWith({ runId: 'thread-1' });
    expect(first).toEqual([
      {
        artifactId: 'plan',
        version: 2,
        title: 'Plan',
        summary: null,
        key: 'k',
      },
    ]);
    expect(second).toEqual(first);
  });

  it('reads the listing again after a read fails, rather than keeping the failure', async () => {
    const readRunArtifacts = vi
      .fn()
      .mockRejectedValueOnce(new Error('daemon down'))
      .mockResolvedValueOnce({ artifacts: [] });
    const reader = threadContextReaderOf(chatsWith(readRunArtifacts), HANDLE);

    await expect(reader.artifacts('thread-1')).rejects.toThrow('daemon down');
    await expect(reader.artifacts('thread-1')).resolves.toEqual([]);
    expect(readRunArtifacts).toHaveBeenCalledTimes(2);
  });
});
