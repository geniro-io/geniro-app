/** How many of a thread's messages a relayed question shows for its context. */
export const QUESTION_CONTEXT_MESSAGES = 3;

/** How many of the pages and pictures the asking turn showed a relayed question shows, newest first. */
export const QUESTION_CONTEXT_VISUALS = 3;

/** How many of the thread's rows one read takes to find what led up to its question. */
const CONTEXT_PAGE = 200;

/** The most pages of the run's own flow read back from a call's question towards its brief. */
const CALL_CONTEXT_PAGES = 10;

/** The most of a call's words one read may ask for (the daemon's `CALL_MESSAGES_MAX`). */
const CALL_MESSAGES_PAGE = 20;

/** One message of the thread a relayed question came from. */
export interface ThreadContextMessage {
  seq: number;
  role: 'user' | 'assistant';
  text: string;
}

/** A page the thread published with `show_artifact`, or pictures it handed over with `show_gallery`. */
export type ThreadContextVisual =
  | { seq: number; artifact: PublishedArtifact }
  | { seq: number; gallery: GallerySpec };

export type ThreadContextEntry = ThreadContextMessage | ThreadContextVisual;

export function isThreadContextVisual(
  entry: ThreadContextEntry,
): entry is ThreadContextVisual {
  return 'artifact' in entry || 'gallery' in entry;
}

/**
 * How a relayed question reads what its thread showed right before asking, and
 * how the pages and pictures it showed reach the screen. Provided by `Chats` and
 * by the command center, which hold the daemon handle; null offers no context.
 *
 * The URL builder, the picture loader and the answers store are bound to the
 * THREAD's run, not to the run the question is drawn in: a page is served from
 * the thread's folder, a relative picture path resolves against the thread's
 * working directory, and what the user picks on a page is kept for the thread.
 */
export interface ThreadContextReader {
  read(
    threadRunId: string,
    threadRequestId: string | null,
  ): Promise<ThreadContextEntry[]>;
  /**
   * The thread run's pages at their newest version, as its listing names them.
   * Read again when a kept listing lacks a `wanted` page or holds it at an
   * older version. Rejects when the listing cannot be read; a page missing from
   * it is gone.
   */
  artifacts(
    threadRunId: string,
    wanted?: readonly { artifactId: string; version: number }[],
  ): Promise<PublishedArtifact[]>;
  artifactUrl(threadRunId: string): ArtifactUrlBuilder;
  loadImage(threadRunId: string): LocalImageLoader;
  answers(threadRunId: string): ArtifactAnswersStore;
}

export const ThreadContextReaderContext =
  createContext<ThreadContextReader | null>(null);

function isAskedBy(row: ItemDto, requestId: string): boolean {
  return (
    row.kind === 'approval_request' &&
    payloadString(row.payload, 'id') === requestId
  );
}

/** The member call a question was raised inside: its row stands in the run's own flow, so the call is named by its payload. */
function callOf(asked: ItemDto): string | null {
  return asked.inCall ?? payloadString(asked.payload, 'callId') ?? null;
}

/** The newest `call_started` row of call `callId` before `beforeSeq`: the brief that opened it. */
function briefRowOf(
  rows: readonly ItemDto[],
  callId: string,
  beforeSeq: number,
): ItemDto | undefined {
  return rows
    .filter(
      (row) =>
        row.kind === 'call_started' &&
        row.seq < beforeSeq &&
        payloadString(row.payload, 'callId') === callId,
    )
    .reduce<ItemDto | undefined>(
      (newest, row) =>
        newest === undefined || row.seq > newest.seq ? row : newest,
      undefined,
    );
}

/** The brief that opened call `callId` before `beforeSeq`, as the message sent to the member. */
function briefOf(
  rows: readonly ItemDto[],
  callId: string,
  beforeSeq: number,
): ThreadContextMessage[] {
  const started = briefRowOf(rows, callId, beforeSeq);
  const text = started && payloadString(started.payload, 'message')?.trim();
  return started === undefined || !text
    ? []
    : [{ seq: started.seq, role: 'user', text }];
}

/**
 * The last `count` messages of `rows` sent before `beforeSeq`, oldest first;
 * of all of them when `beforeSeq` is undefined.
 */
function messagesUpTo(
  rows: readonly ItemDto[],
  beforeSeq: number | undefined,
  count = QUESTION_CONTEXT_MESSAGES,
): ThreadContextMessage[] {
  const messages: ThreadContextMessage[] = [];
  for (const row of [...rows].sort((a, b) => a.seq - b.seq)) {
    if (beforeSeq !== undefined && row.seq >= beforeSeq) {
      break;
    }
    const text = payloadString(row.payload, 'text')?.trim() ?? '';
    if (
      row.kind === 'message' &&
      (row.role === 'user' || row.role === 'assistant') &&
      text !== ''
    ) {
      messages.push({ seq: row.seq, role: row.role, text });
    }
  }
  return messages.slice(-count);
}

function visualOf(row: ItemDto): ThreadContextVisual | null {
  if (row.kind === 'show_artifact') {
    const artifact = readPublishedArtifact(row);
    return artifact === null ? null : { seq: row.seq, artifact };
  }
  if (row.kind === 'show_gallery') {
    const gallery = readGallery(row);
    return gallery === null ? null : { seq: row.seq, gallery };
  }
  return null;
}

/** The seq of the newest message the user sent before `beforeSeq`: the asking turn began after it. */
function turnStartOf(
  rows: readonly ItemDto[],
  beforeSeq: number | undefined,
): number {
  let start = -Infinity;
  for (const row of rows) {
    if (
      row.kind === 'message' &&
      row.role === 'user' &&
      row.seq > start &&
      (beforeSeq === undefined || row.seq < beforeSeq)
    ) {
      start = row.seq;
    }
  }
  return start;
}

/**
 * The pages and pictures the asking turn showed: the visual rows after
 * `turnStart` and before `beforeSeq`, the newest few, one per page at its
 * newest version.
 */
function visualsOf(
  rows: readonly ItemDto[],
  beforeSeq: number | undefined,
  turnStart: number,
): ThreadContextVisual[] {
  const shown: ThreadContextVisual[] = [];
  const pages = new Set<string>();
  for (const row of [...rows].sort((a, b) => b.seq - a.seq)) {
    if (
      row.seq <= turnStart ||
      (beforeSeq !== undefined && row.seq >= beforeSeq)
    ) {
      continue;
    }
    const visual = visualOf(row);
    if (visual === null) {
      continue;
    }
    if ('artifact' in visual) {
      if (pages.has(visual.artifact.artifactId)) {
        continue;
      }
      pages.add(visual.artifact.artifactId);
    }
    shown.push(visual);
    if (shown.length === QUESTION_CONTEXT_VISUALS) {
      break;
    }
  }
  return shown.reverse();
}

function contextOf(
  messages: ThreadContextMessage[],
  visuals: ThreadContextVisual[],
): ThreadContextEntry[] {
  return [...messages, ...visuals].sort((a, b) => a.seq - b.seq);
}

/**
 * What a question shows of its thread before it asked, oldest first: the last
 * `count` messages, and the pages and pictures its asking turn published. The
 * question is cut at its own seq; before the end of the page when it is not on it.
 */
export function messagesBefore(
  rows: readonly ItemDto[],
  requestId: string | null,
  count = QUESTION_CONTEXT_MESSAGES,
): ThreadContextEntry[] {
  const asked =
    requestId === null
      ? undefined
      : rows.find((row) => isAskedBy(row, requestId));
  return contextOf(
    messagesUpTo(rows, asked?.seq, count),
    visualsOf(rows, asked?.seq, turnStartOf(rows, asked?.seq)),
  );
}

function publishedOf(artifact: RunArtifact): PublishedArtifact {
  return {
    artifactId: artifact.artifactId,
    version: artifact.version,
    title: artifact.title,
    summary: artifact.summary,
    key: artifact.key,
  };
}

/**
 * The reader over the daemon's pages of a run. A question raised inside a
 * member call is answered from the call's brief and its last messages, cut at
 * the question, and the pages and pictures its member published after the
 * brief; any other from the root conversation's page. A member's pages stand in the run's
 * own flow, so they are found on the root page by the member that asked, read
 * back towards the brief, which a root page carries as an anchor of the call
 * still open across it.
 */
export function threadContextReaderOf(
  chats: Pick<
    DaemonApis['chats'],
    | 'listRunItems'
    | 'listCallMessages'
    | 'readRunArtifacts'
    | 'readLocalImage'
    | 'readArtifactAnswers'
    | 'saveArtifactAnswers'
  >,
  handle: DaemonHandle,
): ThreadContextReader {
  const listings = new Map<string, Promise<PublishedArtifact[]>>();
  const holds = (
    pages: readonly PublishedArtifact[],
    wanted: readonly { artifactId: string; version: number }[],
  ): boolean =>
    wanted.every((want) =>
      pages.some(
        (page) =>
          page.artifactId === want.artifactId && page.version >= want.version,
      ),
    );
  const listed = async (
    threadRunId: string,
    wanted: readonly { artifactId: string; version: number }[] = [],
  ): Promise<PublishedArtifact[]> => {
    const known = await listings.get(threadRunId)?.catch(() => null);
    if (known !== undefined && known !== null && holds(known, wanted)) {
      return known;
    }
    const listing = chats
      .readRunArtifacts({ runId: threadRunId })
      .then(({ artifacts }) => artifacts.map(publishedOf));
    listings.set(threadRunId, listing);
    listing.catch(() => {
      listings.delete(threadRunId);
    });
    return listing;
  };
  return {
    read: async (threadRunId, threadRequestId) => {
      const rootPage = (beforeSeq?: number) =>
        chats.listRunItems({
          runId: threadRunId,
          limit: CONTEXT_PAGE,
          beforeSeq,
          conversation: ListRunItemsConversationEnum.Root,
        });
      const { items: root, anchors } = await rootPage();
      if (threadRequestId === null) {
        return messagesBefore(root, null);
      }
      const onRoot = root.find((row) => isAskedBy(row, threadRequestId));
      const elsewhere =
        onRoot === undefined
          ? (
              await chats.listRunItems({
                runId: threadRunId,
                limit: CONTEXT_PAGE,
              })
            ).items
          : [];
      const asked =
        onRoot ?? elsewhere.find((row) => isAskedBy(row, threadRequestId));
      const callId = asked === undefined ? null : callOf(asked);
      if (asked === undefined || callId === null) {
        return messagesBefore(root, threadRequestId);
      }
      const { messages } = await chats.listCallMessages({
        runId: threadRunId,
        callId,
        limit: CALL_MESSAGES_PAGE,
      });
      const brief = briefRowOf(
        [...root, ...elsewhere, ...anchors],
        callId,
        asked.seq,
      );
      const askedBy = (rows: readonly ItemDto[]): ItemDto[] =>
        rows.filter((row) => row.memberId === asked.memberId);
      const flow = [...root];
      let page = root;
      for (let read = 1; read < CALL_CONTEXT_PAGES; read += 1) {
        const oldest = Math.min(...flow.map((row) => row.seq));
        if (
          brief === undefined ||
          page.length < CONTEXT_PAGE ||
          oldest <= brief.seq ||
          visualsOf(askedBy(flow), asked.seq, brief.seq).length ===
            QUESTION_CONTEXT_VISUALS
        ) {
          break;
        }
        page = (await rootPage(oldest)).items;
        flow.push(...page);
      }
      const rows = [
        ...new Map(
          [...flow, ...elsewhere].map((row) => [row.id, row]),
        ).values(),
      ];
      return contextOf(
        [
          ...briefOf(brief === undefined ? [] : [brief], callId, asked.seq),
          ...messagesUpTo(messages, asked.seq),
        ],
        visualsOf(askedBy(rows), asked.seq, brief?.seq ?? -Infinity),
      );
    },
    artifacts: listed,
    artifactUrl: (threadRunId) => artifactUrlBuilder(handle, threadRunId),
    loadImage: (threadRunId) => (path) =>
      readLocalImageDataUrl(chats, threadRunId, path),
    answers: (threadRunId) => artifactAnswersStore(chats, threadRunId),
  };
}
