const RUN_ID = 'abc12345-0000-0000-0000-000000000000';
const TOOL = 'mcp__geniro-abc12345__start_thread';

function item(
  kind: 'tool_call' | 'tool_result',
  payload: unknown,
  seq: number,
): ChatItem {
  return {
    id: `i-${seq}`,
    runId: RUN_ID,
    memberId: null,
    seq,
    kind,
    role: null,
    payload,
    createdAt: '2026-11-18T10:00:00.000Z',
  };
}

const ARGS = {
  project: 'ManifestOS',
  title: 'CI-1233: Case page slow',
  brief: 'Find why the case page is slow',
};

function pair(
  result?: { text: string; isError?: boolean },
  input: unknown = ARGS,
): ToolPair {
  return {
    call: item('tool_call', { id: 'c1', name: TOOL, input }, 1),
    result:
      result === undefined
        ? null
        : item(
            'tool_result',
            {
              id: 'c1',
              result: [{ type: 'text', text: result.text }],
              isError: result.isError ?? false,
            },
            2,
          ),
  };
}

const FILED = {
  text: '{"status":"card_shown","taskId":"task-1","identifier":"MAN-16"}\nCard MAN-16 is filed.',
};

function fakeReader(answer: () => Promise<TaskDto>): {
  reader: TaskReader;
  read: ReturnType<typeof vi.fn<(taskId: string) => Promise<TaskDto>>>;
  change: (taskId: string) => void;
  reconnect: () => void;
} {
  const listeners = new Set<(taskId: string) => void>();
  const reconnects = new Set<() => void>();
  const read = vi.fn<(taskId: string) => Promise<TaskDto>>(() => answer());
  return {
    reader: {
      read,
      onChanged: (listener) => {
        listeners.add(listener);
        return () => listeners.delete(listener);
      },
      onReconnect: (listener) => {
        reconnects.add(listener);
        return () => reconnects.delete(listener);
      },
    },
    read,
    change: (taskId) => {
      for (const listener of listeners) {
        listener(taskId);
      }
    },
    reconnect: () => {
      for (const listener of reconnects) {
        listener();
      }
    },
  };
}

function card(overrides: Partial<TaskDto>): TaskDto {
  return aTask({
    id: 'task-1',
    title: 'CI-1233: Case page slow',
    status: TaskStatus.Backlog,
    ...overrides,
  });
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

async function render(
  node: React.ReactNode,
  reader: TaskReader | null,
  open: ((runId: string) => void) | null = null,
): Promise<void> {
  await act(async () => {
    root.render(
      <TaskReaderContext.Provider value={reader}>
        <ThreadOpenContext.Provider value={open}>
          {node}
        </ThreadOpenContext.Provider>
      </TaskReaderContext.Provider>,
    );
  });
}

function stateText(): string | null {
  return (
    container.querySelector('[data-slot="thread-start-state"]')?.textContent ??
    null
  );
}

describe('ThreadStartCard', () => {
  it('shows the thread, its project, agent and card while its start waits for the user', async () => {
    const { reader, read } = fakeReader(() =>
      Promise.resolve(
        card({
          startRequest: {
            requestedAt: '2026-11-18T10:00:00.000Z',
            approvedAt: null,
          },
        }),
      ),
    );
    await render(
      <ThreadStartCard pair={pair(FILED, { ...ARGS, agent: 'claude' })} />,
      reader,
    );

    expect(read).toHaveBeenCalledWith('task-1');
    expect(
      container.querySelector('[data-slot="thread-start-title"]')?.textContent,
    ).toBe('CI-1233: Case page slow');
    const chips = [
      ...container.querySelectorAll(
        '[data-slot="thread-start-labels"] > [data-slot]',
      ),
    ].map((chip) => [chip.getAttribute('data-slot'), chip.textContent]);
    expect(chips).toEqual([
      ['thread-card-board-card', 'MAN-16'],
      ['thread-start-agent', 'claude'],
      ['thread-start-project', 'ManifestOS'],
    ]);
    expect(stateText()).toBe('Waiting for your Start');
    expect(container.textContent).toContain('Answer the Start card to run it.');
  });

  it('names the team, or the project default when the call named neither', async () => {
    await render(
      <ThreadStartCard pair={pair(FILED, { ...ARGS, team: 'dev-team' })} />,
      null,
    );
    expect(container.textContent).toContain('dev-team');
    await render(<ThreadStartCard pair={pair(FILED)} />, null);
    expect(container.textContent).toContain('Project default');
  });

  it('lets the agent chip take its whole width in the wrapping labels row, as the project chip does', async () => {
    await render(<ThreadStartCard pair={pair(FILED)} />, null);
    const agent = container.querySelector('[data-slot="thread-start-agent"]');
    const project = container.querySelector(
      '[data-slot="thread-start-project"]',
    );
    expect(
      container.querySelector('[data-slot="thread-start-labels"]')?.classList,
    ).toContain('flex-wrap');
    expect(agent?.classList).not.toContain('max-w-28');
    expect(agent?.className).toBe(project?.className);
  });

  it('moves from Starting to Started on the card’s own change, and opens the started thread', async () => {
    let current = card({
      startRequest: {
        requestedAt: '2026-11-18T10:00:00.000Z',
        approvedAt: '2026-11-18T10:00:05.000Z',
      },
    });
    const { reader, change } = fakeReader(() => Promise.resolve(current));
    const open = vi.fn<(runId: string) => void>();
    await render(<ThreadStartCard pair={pair(FILED)} />, reader, open);
    expect(stateText()).toBe('Starting…');
    expect(container.querySelector('[data-slot="thread-card-go"]')).toBeNull();

    current = card({
      runId: 'run-new',
      status: TaskStatus.InProgress,
      startRequest: {
        requestedAt: '2026-11-18T10:00:00.000Z',
        approvedAt: '2026-11-18T10:00:05.000Z',
      },
    });
    await act(async () => {
      change('another-task');
    });
    expect(stateText()).toBe('Starting…');
    await act(async () => {
      change('task-1');
    });

    expect(stateText()).toBe('Started');
    expect(
      container
        .querySelector('[data-slot="thread-card-board-card"]')
        ?.getAttribute('title'),
    ).toContain('In progress');
    const button = container.querySelector<HTMLButtonElement>(
      '[data-slot="thread-card-go"]',
    );
    expect(button).not.toBeNull();
    expect(
      container.querySelector('[data-slot="thread-start-note"]'),
    ).toBeNull();
    act(() => button!.click());
    expect(open).toHaveBeenCalledWith('run-new');
  });

  it('reads the card again after a reconnect, and keeps the newer of two answers', async () => {
    const answers: ((task: TaskDto) => void)[] = [];
    const { reader, read, reconnect } = fakeReader(
      () =>
        new Promise<TaskDto>((resolve) => {
          answers.push(resolve);
        }),
    );
    await render(<ThreadStartCard pair={pair(FILED)} />, reader);
    await act(async () => {
      reconnect();
    });
    expect(read).toHaveBeenCalledTimes(2);

    await act(async () => {
      answers[1]!(card({ runId: 'run-new' }));
    });
    expect(stateText()).toBe('Started');
    await act(async () => {
      answers[0]!(
        card({
          startRequest: {
            requestedAt: '2026-11-18T10:00:00.000Z',
            approvedAt: null,
          },
        }),
      );
    });
    expect(stateText()).toBe('Started');
  });

  it('stays Filed, not Card removed, when the read fails for another reason', async () => {
    const { reader } = fakeReader(() =>
      Promise.reject(
        new Error('daemon GET /v1/tasks/task-1 failed (500): boom'),
      ),
    );
    await render(<ThreadStartCard pair={pair(FILED)} />, reader);
    expect(stateText()).toBe('Filed');
  });

  it('reads Not started once the request ended with no run', async () => {
    const { reader } = fakeReader(() => Promise.resolve(card({})));
    await render(<ThreadStartCard pair={pair(FILED)} />, reader);
    expect(stateText()).toBe('Not started');
    expect(container.textContent).toContain('The card stays in backlog.');
  });

  it('reads Card removed when the board no longer has the card', async () => {
    const { reader } = fakeReader(() =>
      Promise.reject(
        new Error('daemon GET /v1/tasks/task-1 failed (404): TASK_NOT_FOUND'),
      ),
    );
    await render(<ThreadStartCard pair={pair(FILED)} />, reader);
    expect(stateText()).toBe('Card removed');
    expect(
      container.querySelector('[data-slot="thread-card-board-card"]'),
    ).toBeNull();
    expect(
      container.querySelector('[data-slot="thread-start-card-id"]')
        ?.textContent,
    ).toBe('MAN-16');
  });

  it('shows a refusal with its reason and reads no card', async () => {
    const { reader, read } = fakeReader(() => Promise.resolve(card({})));
    await render(
      <ThreadStartCard
        pair={pair({
          text: 'PROJECT_NOT_FOUND: no project has the id or name "Manifest"',
        })}
      />,
      reader,
    );
    expect(stateText()).toBe('Refused');
    expect(container.textContent).toContain(
      'no project has the id or name "Manifest"',
    );
    expect(read).not.toHaveBeenCalled();
  });

  it('reads Filing while the call is out, and No result once the run settled without one', async () => {
    await render(<ThreadStartCard pair={pair()} />, null);
    expect(stateText()).toBe('Filing…');
    await act(async () => {
      root.render(
        <RunSettledContext.Provider value={Date.now()}>
          <ThreadStartCard pair={pair()} />
        </RunSettledContext.Provider>,
      );
    });
    expect(stateText()).toBe('No result');
  });

  it('is what the transcript draws for a start_thread call, in place of its tool row', async () => {
    const [entry] = groupTranscript([pair(FILED).call, pair(FILED).result!]);
    expect(entry !== undefined && isCardEntry(entry)).toBe(true);
    if (entry === undefined || !isCardEntry(entry)) {
      return;
    }
    await render(<EntryCard entry={entry} />, null);
    expect(
      container.querySelector('[data-slot="thread-start-card"]'),
    ).not.toBeNull();
    expect(container.textContent).toContain('MAN-16');
  });
});

describe('ThreadStartCard — a thread filed with no board card', () => {
  const STARTED_ANSWER = {
    text: '{"status":"card_shown","startId":"start-1"}\nA Start card is on screen for the user; no board card was filed.',
  };

  function fakeThreadReader(
    answer: () => Promise<CommandCenterThreadStartState>,
  ): {
    reader: ThreadStartReader;
    read: ReturnType<
      typeof vi.fn<(startId: string) => Promise<CommandCenterThreadStartState>>
    >;
    changed: (runIds: string[]) => void;
    reconnect: () => void;
  } {
    const starts = new Set<(runIds: string[]) => void>();
    const reconnects = new Set<() => void>();
    const read = vi.fn<
      (startId: string) => Promise<CommandCenterThreadStartState>
    >(() => answer());
    return {
      reader: {
        read,
        onStartChanged: (listener) => {
          starts.add(listener);
          return () => starts.delete(listener);
        },
        onReconnect: (listener) => {
          reconnects.add(listener);
          return () => reconnects.delete(listener);
        },
      },
      read,
      changed: (runIds) => {
        for (const listener of starts) {
          listener(runIds);
        }
      },
      reconnect: () => {
        for (const listener of reconnects) {
          listener();
        }
      },
    };
  }

  function start(
    state: CommandCenterThreadStartState['state'],
    over: Partial<CommandCenterThreadStartState> = {},
  ): CommandCenterThreadStartState {
    return { startId: 'start-1', state, runId: null, failure: null, ...over };
  }

  async function renderThread(
    reader: ThreadStartReader | null,
    open: ((runId: string) => void) | null = null,
  ): Promise<void> {
    await act(async () => {
      root.render(
        <ThreadStartReaderContext.Provider value={reader}>
          <ThreadOpenContext.Provider value={open}>
            <ThreadStartCard pair={pair(STARTED_ANSWER, ARGS)} />
          </ThreadOpenContext.Provider>
        </ThreadStartReaderContext.Provider>,
      );
    });
  }

  it('shows its title, brief and project, with no board card', async () => {
    const { reader, read } = fakeThreadReader(() =>
      Promise.resolve(start('waiting')),
    );
    await renderThread(reader);

    expect(read).toHaveBeenCalledWith('start-1');
    expect(
      container.querySelector('[data-slot="thread-start-title"]')?.textContent,
    ).toBe('CI-1233: Case page slow');
    expect(
      container.querySelector('[data-slot="thread-start-brief"]')?.textContent,
    ).toBe('Find why the case page is slow');
    expect(
      container.querySelector('[data-slot="thread-card-board-card"]'),
    ).toBeNull();
    expect(
      container.querySelector('[data-slot="thread-start-card-id"]'),
    ).toBeNull();
    expect(
      container.querySelector('[data-slot="thread-start-project"]')
        ?.textContent,
    ).toBe('ManifestOS');
    expect(stateText()).toBe('Waiting for your Start');
  });

  it('draws no Show more under a brief that fits its three lines', async () => {
    const { reader } = fakeThreadReader(() =>
      Promise.resolve(start('started', { runId: 'thread-1' })),
    );
    await renderThread(reader);

    const brief = container.querySelector('[data-slot="thread-start-brief"]');
    expect(brief?.classList.contains('line-clamp-3')).toBe(true);
    expect(container.textContent).not.toContain('Show more');
  });

  it('holds a longer brief to three lines with a Show more that unfolds it, remembered in the thread', async () => {
    const heights = (element: HTMLElement): boolean =>
      element.dataset.slot === 'thread-start-brief' &&
      element.classList.contains('line-clamp-3');
    Object.defineProperty(HTMLElement.prototype, 'scrollHeight', {
      configurable: true,
      get(this: HTMLElement) {
        return heights(this) ? 120 : 0;
      },
    });
    Object.defineProperty(HTMLElement.prototype, 'clientHeight', {
      configurable: true,
      get(this: HTMLElement) {
        return heights(this) ? 48 : 0;
      },
    });
    try {
      const { reader } = fakeThreadReader(() =>
        Promise.resolve(start('started', { runId: 'thread-1' })),
      );
      const draw = (): Promise<void> =>
        act(async () => {
          root.render(
            <ThreadUiMemoryContext.Provider value="brief-run">
              <ThreadStartReaderContext.Provider value={reader}>
                <ThreadStartCard pair={pair(STARTED_ANSWER, ARGS)} />
              </ThreadStartReaderContext.Provider>
            </ThreadUiMemoryContext.Provider>,
          );
        });
      const brief = (): Element | null =>
        container.querySelector('[data-slot="thread-start-brief"]');
      const toggle = (): HTMLButtonElement | undefined =>
        [...container.querySelectorAll('button')].find((button) =>
          /Show (more|less)/.test(button.textContent ?? ''),
        );
      await draw();

      expect(brief()?.classList.contains('line-clamp-3')).toBe(true);
      expect(toggle()?.textContent).toBe(' Show more');
      expect(toggle()?.querySelector('svg')).not.toBeNull();

      await act(async () => {
        toggle()?.click();
      });
      expect(brief()?.classList.contains('line-clamp-3')).toBe(false);
      expect(toggle()?.textContent).toBe(' Show less');

      await act(async () => {
        root.render(null);
      });
      await draw();
      expect(brief()?.classList.contains('line-clamp-3')).toBe(false);
      expect(toggle()?.textContent).toBe(' Show less');
    } finally {
      delete (HTMLElement.prototype as { scrollHeight?: number }).scrollHeight;
      delete (HTMLElement.prototype as { clientHeight?: number }).clientHeight;
    }
  });

  it('reads an approved start as Starting and a declined one as Declined', async () => {
    const approved = fakeThreadReader(() => Promise.resolve(start('approved')));
    await renderThread(approved.reader);
    expect(stateText()).toBe('Starting…');

    const declined = fakeThreadReader(() => Promise.resolve(start('declined')));
    await renderThread(declined.reader);
    expect(stateText()).toBe('Declined');
    expect(container.textContent).toContain('No thread was started.');
  });

  it('shows Could not start with the reason it failed', async () => {
    const { reader } = fakeThreadReader(() =>
      Promise.resolve(
        start('failed', { failure: 'The project has no agent configured' }),
      ),
    );
    await renderThread(reader);

    expect(stateText()).toBe('Could not start');
    expect(
      container.querySelector('[data-slot="thread-start-note"]')?.textContent,
    ).toBe('The project has no agent configured');
  });

  it('shows Started, and opens the thread that started', async () => {
    const { reader } = fakeThreadReader(() =>
      Promise.resolve(start('started', { runId: 'run-7' })),
    );
    const open = vi.fn<(runId: string) => void>();
    await renderThread(reader, open);

    expect(stateText()).toBe('Started');
    const button = container.querySelector<HTMLButtonElement>(
      '[data-slot="thread-card-go"]',
    );
    expect(button).not.toBeNull();
    act(() => button!.click());
    expect(open).toHaveBeenCalledWith('run-7');
  });

  it('reads the start again when a start change names its manager run, and not another', async () => {
    let current = start('waiting');
    const { reader, read, changed } = fakeThreadReader(() =>
      Promise.resolve(current),
    );
    await renderThread(reader);
    expect(read).toHaveBeenCalledTimes(1);

    await act(async () => {
      changed(['another-run']);
    });
    expect(read).toHaveBeenCalledTimes(1);

    current = start('started', { runId: 'run-7' });
    await act(async () => {
      changed([RUN_ID]);
    });
    expect(read).toHaveBeenCalledTimes(2);
    expect(stateText()).toBe('Started');
  });

  it('reads the start again after a reconnect', async () => {
    const { reader, read, reconnect } = fakeThreadReader(() =>
      Promise.resolve(start('waiting')),
    );
    await renderThread(reader);
    await act(async () => {
      reconnect();
    });
    expect(read).toHaveBeenCalledTimes(2);
  });

  it('shows Filed while there is no reader to read the start with', async () => {
    await renderThread(null);
    expect(stateText()).toBe('Filed');
  });
});
