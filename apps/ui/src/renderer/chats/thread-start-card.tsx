function stateOf(
  start: ThreadStart,
  task: LiveTask,
  settled: boolean,
): StartState {
  if (start.answer === null) {
    return settled ? 'stopped' : 'filing';
  }
  if (start.answer === 'refused') {
    return 'refused';
  }
  switch (task.kind) {
    case 'unread':
    case 'loading':
    case 'unreadable':
      return 'filed';
    case 'gone':
      return 'removed';
    case 'found':
      if (task.task.runId !== null) {
        return 'started';
      }
      if (task.task.startRequest === null) {
        return 'not-started';
      }
      return task.task.startRequest.approvedAt === null
        ? 'awaiting-start'
        : 'starting';
  }
}

/**
 * How a Start card reads a thread filed with no board card, and hears it
 * change. Provided by the chat that holds the daemon; null reads nothing, so
 * such a card stays at Filed.
 */
export interface ThreadStartReader {
  read: (startId: string) => Promise<CommandCenterThreadStartState>;
  /** Calls `listener` with the runs each start change named; answers the unsubscribe. */
  onStartChanged: (listener: (runIds: string[]) => void) => () => void;
  onReconnect: (listener: () => void) => () => void;
}

export const ThreadStartReaderContext = createContext<ThreadStartReader | null>(
  null,
);

/**
 * One cardless start as the daemon has it now: read on mount, again on each
 * start change naming the manager run that filed it, and after a reconnect.
 * Null until the first answer, and after a read that failed.
 */
function useLiveThreadStart(
  startId: string | null,
  managerRunId: string | null,
): CommandCenterThreadStartState | null {
  const reader = useContext(ThreadStartReaderContext);
  const [live, setLive] = useState<CommandCenterThreadStartState | null>(null);
  useEffect(() => {
    if (reader === null || startId === null) {
      setLive(null);
      return;
    }
    let current = true;
    let latest = 0;
    const load = (): void => {
      const ask = ++latest;
      reader.read(startId).then(
        (start) => {
          if (current && ask === latest) {
            setLive(start);
          }
        },
        () => {
          if (current && ask === latest) {
            setLive(null);
          }
        },
      );
    };
    load();
    const offChanged = reader.onStartChanged((runIds) => {
      if (managerRunId !== null && runIds.includes(managerRunId)) {
        load();
      }
    });
    const offReconnect = reader.onReconnect(load);
    return () => {
      current = false;
      offChanged();
      offReconnect();
    };
  }, [reader, startId, managerRunId]);
  return live;
}

function threadStateOf(
  start: ThreadStart,
  live: CommandCenterThreadStartState | null,
  settled: boolean,
): StartState {
  if (start.answer === null) {
    return settled ? 'stopped' : 'filing';
  }
  if (start.answer === 'refused') {
    return 'refused';
  }
  if (live === null) {
    return 'filed';
  }
  switch (live.state) {
    case 'waiting':
      return 'awaiting-start';
    case 'approved':
      return 'starting';
    case 'started':
      return 'started';
    case 'declined':
      return 'declined';
    case 'failed':
      return 'failed';
  }
}

const noteVariants = cva('m-0 min-w-0 text-xs break-words', {
  variants: {
    attention: {
      blocked: 'text-destructive',
      question: 'text-warning',
      working: 'text-muted-foreground',
      quiet: 'text-muted-foreground',
      inactive: 'text-muted-foreground',
      done: 'text-muted-foreground',
    } satisfies Record<ThreadAttention, string>,
  },
});

function StateChip({ state }: { state: StartState }): React.JSX.Element {
  const meta = STATE_META[state];
  const Icon = meta.icon;
  return (
    <ThreadStatusChip
      attention={meta.attention}
      slot="thread-start-state"
      className="gap-1">
      {Icon === 'spinner' ? (
        <Spinner />
      ) : Icon === null ? null : (
        <Icon aria-hidden="true" className="size-3 shrink-0" />
      )}
      {meta.label}
    </ThreadStatusChip>
  );
}

/**
 * The thread the command center's manager started with `start_thread`, drawn
 * from its call and its result: what it is called, where and as whom it runs,
 * the board card it filed, and where that card stands now — read live from the
 * board, since the start happens after the call (the user's Start, then
 * Electron main's drain).
 */
export function ThreadStartCard({
  pair,
}: {
  pair: ToolPair;
}): React.JSX.Element {
  const settled = useContext(RunSettledContext) !== null;
  const open = useContext(ThreadOpenContext);
  const start = readThreadStart(pair);
  const task = useLiveTask(start.taskId);
  const live = useLiveThreadStart(start.startId, pair.call.runId);
  const [briefOpen, setBriefOpen] = useThreadFlag(
    `thread-start-brief:${pair.call.id}`,
    false,
  );
  const state =
    start.startId === null
      ? stateOf(start, task, settled)
      : threadStateOf(start, live, settled);
  const found = task.kind === 'found' ? task.task : null;
  const startedRunId = live?.state === 'started' ? live.runId : null;
  const runId = found?.runId ?? startedRunId;
  const title = found?.title ?? start.title ?? 'New thread';
  const note =
    state === 'refused'
      ? start.reason
      : state === 'failed'
        ? (live?.failure ?? null)
        : STATE_META[state].note;
  const runsAs = start.team ?? start.agent;
  const canGo = runId !== null && open !== null;
  return (
    <div
      data-slot="thread-start-card"
      data-state={state}
      className="flex min-w-0 gap-3 rounded-card border border-border bg-card p-3 text-sm shadow-panel-sm">
      <span
        aria-hidden="true"
        data-slot="thread-start-icon"
        className={cn(
          'flex size-8 shrink-0 items-center justify-center rounded-lg',
          state === 'refused'
            ? 'bg-destructive/10 text-destructive'
            : 'bg-primary/10 text-primary',
        )}>
        <MessageSquarePlus className="size-4" />
      </span>
      <div className="flex min-w-0 flex-1 flex-col gap-1">
        <div className="flex min-w-0 items-center gap-2">
          <span className="min-w-0 flex-1 truncate text-[11px] tracking-wide text-muted-foreground uppercase">
            New thread
          </span>
          <StateChip state={state} />
        </div>
        <p
          data-slot="thread-start-title"
          className="m-0 min-w-0 text-sm leading-5 font-semibold break-words text-foreground">
          {title}
        </p>
        {start.startId === null || start.brief === null ? null : (
          <ClampedText
            text={start.brief}
            lines={3}
            slot="thread-start-brief"
            className="min-w-0 text-xs text-muted-foreground"
            toggleClassName={cn(SHOW_MORE_TOGGLE_CLASS, 'font-normal')}
            toggleLabel={(open) => <ShowMoreLabel expanded={open} />}
            expanded={briefOpen}
            onExpandedChange={setBriefOpen}
          />
        )}
        {note === null ? null : (
          <p
            data-slot="thread-start-note"
            className={noteVariants({
              attention: STATE_META[state].attention,
            })}>
            {note}
          </p>
        )}
        <div
          data-slot="thread-start-labels"
          className="flex min-w-0 flex-wrap items-center gap-1">
          {start.identifier === null ? null : found === null ? (
            <ThreadLabelChip
              slot="thread-start-card-id"
              icon={CircleDashed}
              text={start.identifier}
              title={`Board card ${start.identifier}`}
              yields={false}
            />
          ) : (
            <BoardCardLabel
              card={{
                identifier: start.identifier,
                title,
                status: found.status,
              }}
            />
          )}
          <ThreadLabelChip
            slot="thread-start-agent"
            icon={start.team === null ? Bot : Users}
            text={runsAs ?? 'Project default'}
            title={
              start.team !== null
                ? `Team ${start.team}`
                : runsAs === null
                  ? "The project's default agent or team"
                  : `Agent ${runsAs}`
            }
            yields
          />
          {start.project === null ? null : (
            <ThreadLabelChip
              slot="thread-start-project"
              icon={Folder}
              text={start.project}
              title={`Project ${start.project}`}
              yields
            />
          )}
          {canGo ? (
            <span className="-mr-1.5 ml-auto flex shrink-0 pl-1">
              <ThreadActionButton
                slot="thread-start-go"
                label={`Go to ${title}`}
                title="Open this thread's chat"
                icon={<MessageSquareText aria-hidden="true" />}
                onClick={() => open(runId)}>
                Go to thread
                <ArrowRight aria-hidden="true" />
              </ThreadActionButton>
            </span>
          ) : null}
        </div>
      </div>
    </div>
  );
}
