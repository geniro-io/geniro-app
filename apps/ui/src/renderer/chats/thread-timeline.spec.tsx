// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ChatTimelineEvent, ChatTimelineMarker } from '../autogenerated';
import { ThreadTimeline, type ThreadTimelineProps } from './thread-timeline';
import { readThreadFlag, ThreadUiMemoryContext } from './thread-ui-memory';
import type { ChatTimelineState } from './use-chat-timeline';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;

afterEach(() => {
  const mounted = root;
  root = null;
  if (mounted !== null) {
    act(() => mounted.unmount());
  }
  document.body.innerHTML = '';
  localStorage.clear();
});

const PR_NUMBER = 612;
const NOW = Date.now();
const ago = (minutes: number): string =>
  new Date(NOW - minutes * 60_000).toISOString();

function marker(
  seq: number,
  preview: string,
  minutesAgo: number,
): ChatTimelineMarker {
  return {
    seq,
    createdAt: ago(minutesAgo),
    preview,
    segment: {
      aiMessages: 3,
      elapsedMs: 60_000,
      totals: {
        turns: 1,
        costedTurns: 1,
        costUsd: 0.5,
        estimatedCostUsd: null,
        inputTokens: 1000,
        outputTokens: 200,
        cacheReadTokens: null,
        cacheCreationTokens: null,
        thinkingTokens: null,
        workedMs: 50_000,
      },
    },
  };
}

function event(
  over: Partial<ChatTimelineEvent> & Pick<ChatTimelineEvent, 'kind'>,
): ChatTimelineEvent {
  return {
    id: `${over.kind}:${over.seq ?? 'x'}`,
    seq: 1,
    at: ago(1),
    memberId: null,
    text: null,
    detail: null,
    url: null,
    open: null,
    ...over,
  };
}

function state(over: Partial<ChatTimelineState> = {}): ChatTimelineState {
  return {
    runId: 'run-1',
    status: 'ready',
    markers: [],
    partialReason: null,
    events: [],
    eventsPartialReason: null,
    ...over,
  };
}

function render(props: Partial<ThreadTimelineProps> = {}): void {
  const container = document.createElement('div');
  document.body.append(container);
  const created = createRoot(container);
  root = created;
  act(() => {
    created.render(
      <ThreadUiMemoryContext.Provider value="run-1">
        <ThreadTimeline
          timeline={state()}
          inProgress={false}
          onJump={() => {}}
          onShowGoals={() => {}}
          {...props}
        />
      </ThreadUiMemoryContext.Provider>,
    );
  });
}

const rows = (): HTMLElement[] => [
  ...document.querySelectorAll<HTMLElement>('[data-slot="timeline-row"]'),
];
const kinds = (): (string | undefined)[] =>
  rows().map((row) => row.dataset.kind);
const press = (label: string): void =>
  act(() =>
    [...document.querySelectorAll<HTMLButtonElement>('button')]
      .find((button) => button.textContent === label)
      ?.click(),
  );

describe('ThreadTimeline', () => {
  it('lists the user’s messages and the key events newest first, in their own words', () => {
    render({
      nameOf: (id) => (id === 'senior' ? 'Tony Stark' : id),
      timeline: state({
        markers: [marker(10, 'fix the export', 30)],
        events: [
          event({ kind: 'started', seq: 11, at: ago(29) }),
          event({
            kind: 'failure',
            seq: 20,
            at: ago(20),
            text: 'test run timed out',
          }),
          event({
            kind: 'step',
            seq: 25,
            at: ago(10),
            memberId: 'senior',
            text: 'Found the cause',
            detail: 'problem',
          }),
          event({
            kind: 'finished',
            seq: 30,
            at: ago(2),
            detail: 'success',
            text: 'Shipped',
          }),
        ],
      }),
    });

    expect(kinds()).toEqual([
      'finished',
      'step',
      'failure',
      'started',
      'message',
    ]);
    const [finished, step, failure, , message] = rows();
    expect(finished!.textContent).toContain('Thread finished · Success');
    expect(step!.textContent).toContain('Tony Stark');
    expect(step!.textContent).toContain('Found the cause');
    expect(failure!.textContent).toContain('test run timed out');
    expect(message!.textContent).toContain('You wrote');
    expect(message!.textContent).toContain('fix the export');
    expect(message!.textContent).toContain('3 messages');
  });

  it('colours a failure red and a found problem yellow, each with its own icon', () => {
    render({
      timeline: state({
        events: [
          event({ kind: 'failure', seq: 2, text: 'boom' }),
          event({ kind: 'problems', seq: 3, detail: '2', text: 'race' }),
          event({ kind: 'step', seq: 4, detail: 'problem', text: 'flaky' }),
        ],
      }),
    });
    const dot = (kind: string): string =>
      document.querySelector(`[data-kind="${kind}"] [aria-hidden="true"]`)
        ?.className ?? '';
    expect(dot('failure')).toContain('text-destructive');
    expect(dot('problems')).toContain('text-warning');
    expect(dot('step')).toContain('text-warning');
    expect(
      rows().find((r) => r.dataset.kind === 'problems')!.textContent,
    ).toContain('found 2 problems');
  });

  it('shows calls, notes, pages, goals and plain approvals only with Everything, remembered for the thread', () => {
    render({
      timeline: state({
        events: [
          event({ kind: 'stage', seq: 2, detail: 'complete', text: 'Build' }),
          event({ kind: 'call', seq: 3, detail: 'qa', text: 'Review it' }),
          event({ kind: 'note', seq: 4, detail: 'decision', text: 'one PR' }),
          event({ kind: 'page', seq: 5, text: 'Plan page' }),
          event({ kind: 'approval', seq: 6, text: 'Bash', open: false }),
          event({ kind: 'goal', seq: null, text: 'ship' }),
        ],
      }),
    });
    expect(kinds()).toEqual(['stage']);

    press('Everything');

    expect(new Set(kinds())).toEqual(
      new Set(['stage', 'call', 'note', 'page', 'approval', 'goal']),
    );
    expect(readThreadFlag('run-1', 'timeline:everything')).toBe(true);
  });

  it('jumps to a row’s transcript seq, and an achieved goal opens the Goals tab instead', () => {
    const onJump = vi.fn();
    const onShowGoals = vi.fn();
    render({
      onJump,
      onShowGoals,
      timeline: state({
        markers: [marker(10, 'the ask', 5)],
        events: [event({ kind: 'goal', seq: null, text: 'ship', at: ago(1) })],
      }),
    });
    press('Everything');

    act(() =>
      document
        .querySelector<HTMLButtonElement>('[data-kind="message"] > button')
        ?.click(),
    );
    expect(onJump).toHaveBeenCalledWith(10);

    act(() =>
      document
        .querySelector<HTMLButtonElement>('[data-kind="goal"] > button')
        ?.click(),
    );
    expect(onShowGoals).toHaveBeenCalledTimes(1);
    expect(onJump).toHaveBeenCalledTimes(1);
  });

  it('opens a pull request from its own link, never from the row’s jump', () => {
    const onJump = vi.fn();
    render({
      onJump,
      timeline: state({
        events: [
          event({
            kind: 'pull_request',
            seq: 40,
            text: `#${PR_NUMBER}`,
            detail: 'acme/app',
            url: 'https://github.com/acme/app/pull/612',
          }),
        ],
      }),
    });
    const link = document.querySelector<HTMLAnchorElement>(
      '[data-slot="timeline-link"]',
    )!;
    expect(link.getAttribute('href')).toBe(
      'https://github.com/acme/app/pull/612',
    );
    expect(link.closest('button')).toBeNull();
    expect(rows()[0]!.textContent).toContain('Pull request #612 opened');
  });

  it('marks a question still waiting on the user', () => {
    render({
      timeline: state({
        events: [
          event({ kind: 'asked', seq: 3, text: 'Ship it?', open: true }),
        ],
      }),
    });
    expect(
      document.querySelector('[data-slot="timeline-waiting"]'),
    ).not.toBeNull();
  });

  it('runs the clock of the stretch still being worked', () => {
    render({
      inProgress: true,
      timeline: state({ markers: [marker(1, 'old', 60), marker(9, 'new', 3)] }),
    });
    const live = document.querySelectorAll('[data-slot="timeline-live-dot"]');
    expect(live).toHaveLength(1);
    expect(live[0]!.closest('[data-kind="message"]')!.textContent).toContain(
      'new',
    );
  });

  it('says why the list is shorter than the thread, in the daemon’s words', () => {
    render({
      timeline: state({
        events: [event({ kind: 'started', seq: 2 })],
        eventsPartialReason:
          'showing the newest 200 events — the thread starts earlier',
      }),
    });
    expect(
      document.querySelector('[data-slot="timeline-partial"]')?.textContent,
    ).toBe('showing the newest 200 events — the thread starts earlier');
  });

  it('draws loading, error and empty states', () => {
    render({ timeline: state({ status: 'loading' }) });
    expect(
      document.querySelector('[data-slot="timeline-loading"]'),
    ).not.toBeNull();
    act(() => root?.unmount());
    root = null;

    render({ timeline: state({ status: 'error' }) });
    expect(
      document.querySelector('[data-slot="timeline-error"]')?.textContent,
    ).toBe('Could not read the timeline.');
    act(() => root?.unmount());
    root = null;

    render({ timeline: state() });
    expect(
      document.querySelector('[data-slot="timeline-empty"]')?.textContent,
    ).toContain('Nothing has happened yet');
  });
});
