function event(
  over: Partial<ChatTimelineEvent> & Pick<ChatTimelineEvent, 'kind'>,
): ChatTimelineEvent {
  return {
    id: `${over.kind}:${over.seq ?? over.at ?? 'x'}`,
    seq: 1,
    at: ago(1),
    memberId: null,
    text: null,
    detail: null,
    url: null,
    open: null,
    ...over,
  };
}

