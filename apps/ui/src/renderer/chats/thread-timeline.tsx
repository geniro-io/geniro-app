import { Clock, ExternalLink } from 'lucide-react';
import { useMemo } from 'react';

import type { ChatTimelineEvent, ChatTimelineMarker } from '../autogenerated';
import { RunOutcomeAcceptance } from '../autogenerated';
import { EmptyState } from '../components/empty-state';
import { ErrorText } from '../components/error-text';
import { groupTimelineDays } from '../components/timeline-days';
import { TimelineEventRow } from '../components/timeline-event-row';
import { Badge } from '../components/ui/badge';
import { SegmentedControl } from '../components/ui/segmented-control';
import { Spinner } from '../components/ui/spinner';
import { ChatLink } from './browser/chat-link';
import { AcceptanceBadge } from './run-outcome';
import { useThreadFlag } from './thread-ui-memory';
import {
  eventDetail,
  eventLook,
  eventSentence,
  isKeyEvent,
  MESSAGE_LOOK,
} from './timeline-event-meta';
import {
  liveSegment,
  segmentDetail,
  segmentFigures,
  useNowWhile,
} from './timeline-figures';
import type { ChatTimelineState } from './use-chat-timeline';

type Density = 'key' | 'everything';

type TimelineEntry =
  | { kind: 'message'; at: string; seq: number; marker: ChatTimelineMarker }
  | { kind: 'event'; at: string; seq: number | null; event: ChatTimelineEvent };

export interface ThreadTimelineProps {
  timeline: ChatTimelineState;
  /** The agent is still working on the newest message. */
  inProgress: boolean;
  nameOf?: (memberId: string) => string;
  /** Take the reader to this transcript row. */
  onJump: (seq: number) => void;
  /** An event no row carries (an achieved goal) shows its tab instead. */
  onShowGoals: () => void;
  /** Drawn at the start of the control row — the window's tabs. */
  leading?: React.ReactNode;
}

function defaultName(): string {
  return 'Agent';
}

function isAcceptance(value: string | null): value is RunOutcomeAcceptance {
  return (
    value !== null &&
    (Object.values(RunOutcomeAcceptance) as string[]).includes(value)
  );
}

/** Newest first; a same-instant pair keeps the transcript's order reversed. */
function newestFirst(a: TimelineEntry, b: TimelineEntry): number {
  return (
    Date.parse(b.at) - Date.parse(a.at) ||
    (b.seq ?? Number.MAX_SAFE_INTEGER) - (a.seq ?? Number.MAX_SAFE_INTEGER)
  );
}

/**
 * The Progress window's Timeline: the user's messages and what happened on
 * the thread, newest first, by day. Key steps by default; Everything adds the
 * calls, notes, pages, goals and plain approvals, remembered per thread.
 */
export function ThreadTimeline({
  timeline,
  inProgress,
  nameOf = defaultName,
  onJump,
  onShowGoals,
  leading,
}: ThreadTimelineProps): React.JSX.Element {
  const [everything, setEverything] = useThreadFlag(
    'timeline:everything',
    false,
  );
  const newestMarkerSeq = timeline.markers.at(-1)?.seq ?? null;
  const now = useNowWhile(inProgress && newestMarkerSeq !== null);
  const entries = useMemo<TimelineEntry[]>(
    () =>
      [
        ...timeline.markers.map((marker): TimelineEntry => ({
          kind: 'message',
          at: marker.createdAt,
          seq: marker.seq,
          marker,
        })),
        ...timeline.events
          .filter((event) => everything || isKeyEvent(event))
          .map((event): TimelineEntry => ({
            kind: 'event',
            at: event.at,
            seq: event.seq,
            event,
          })),
      ].sort(newestFirst),
    [timeline.markers, timeline.events, everything],
  );
  const days = groupTimelineDays(entries, Date.now());
  const partial = [timeline.eventsPartialReason, timeline.partialReason].filter(
    (reason): reason is string => reason !== null,
  );

  return (
    <section
      aria-label="Timeline"
      data-slot="thread-timeline"
      className="flex flex-col gap-3">
      <div className="flex flex-wrap items-center justify-between gap-2">
        {leading}
        <SegmentedControl<Density>
          ariaLabel="Which events to show"
          size="sm"
          options={[
            { id: 'key', label: 'Key steps' },
            { id: 'everything', label: 'Everything' },
          ]}
          value={everything ? 'everything' : 'key'}
          onSelect={(id) => setEverything(id === 'everything')}
        />
      </div>
      {timeline.status === 'error' ? (
        <ErrorText data-slot="timeline-error">
          Could not read the timeline.
        </ErrorText>
      ) : timeline.status !== 'ready' ? (
        <div
          data-slot="timeline-loading"
          className="flex justify-center py-8 text-muted-foreground">
          <Spinner />
        </div>
      ) : entries.length === 0 ? (
        <EmptyState
          data-slot="timeline-empty"
          icon={<Clock aria-hidden="true" />}>
          Nothing has happened yet
        </EmptyState>
      ) : (
        <div className="flex flex-col gap-2">
          {days.map((day) => (
            <section key={day.key} aria-label={day.label}>
              <h4 className="sticky top-0 z-[2] m-0 bg-card py-1 text-[11px] font-semibold tracking-wide text-muted-foreground uppercase">
                {day.label}
              </h4>
              <ol className="m-0 list-none p-0">
                {day.events.map((entry) =>
                  entry.kind === 'message' ? (
                    <MessageRow
                      key={`message:${entry.marker.seq}`}
                      marker={entry.marker}
                      live={inProgress && entry.marker.seq === newestMarkerSeq}
                      now={now}
                      onJump={onJump}
                    />
                  ) : (
                    <EventRow
                      key={entry.event.id}
                      event={entry.event}
                      nameOf={nameOf}
                      onJump={onJump}
                      onShowGoals={onShowGoals}
                    />
                  ),
                )}
              </ol>
            </section>
          ))}
          {partial.map((reason) => (
            <p
              key={reason}
              data-slot="timeline-partial"
              className="m-0 text-xs text-muted-foreground">
              {reason}
            </p>
          ))}
        </div>
      )}
    </section>
  );
}

function MessageRow({
  marker,
  live,
  now,
  onJump,
}: {
  marker: ChatTimelineMarker;
  live: boolean;
  now: number;
  onJump: (seq: number) => void;
}): React.JSX.Element {
  const segment = liveSegment(marker.segment, marker.createdAt, live, now);
  const words = marker.preview.trim();
  return (
    <TimelineEventRow
      icon={MESSAGE_LOOK.icon}
      tone={MESSAGE_LOOK.tone}
      at={marker.createdAt}
      live={live}
      sentence={<span className="shrink-0 font-medium">You wrote</span>}
      detail={
        <>
          {words === '' ? null : (
            <span className="block truncate text-foreground/80">{words}</span>
          )}
          <span
            data-slot="timeline-segment"
            title={segmentDetail(segment)}
            className="block text-xs tabular-nums">
            {segmentFigures(segment).join(' · ')}
          </span>
        </>
      }
      onActivate={() => onJump(marker.seq)}
      activateLabel={`Go to your message${words === '' ? '' : `: ${words}`}`}
      data={{ 'data-slot': 'timeline-row', 'data-kind': 'message' }}
    />
  );
}

function EventRow({
  event,
  nameOf,
  onJump,
  onShowGoals,
}: {
  event: ChatTimelineEvent;
  nameOf: (memberId: string) => string;
  onJump: (seq: number) => void;
  onShowGoals: () => void;
}): React.JSX.Element {
  const look = eventLook(event);
  const sentence = eventSentence(event, nameOf);
  const detail = eventDetail(event);
  const label = [sentence.name, sentence.words].filter(Boolean).join(' ');
  const seq = event.seq;
  return (
    <TimelineEventRow
      icon={look.icon}
      tone={look.tone}
      at={event.at}
      sentence={
        <>
          {sentence.name === null ? null : (
            <span className="shrink-0 font-medium">{sentence.name}</span>
          )}
          <span
            className={
              sentence.name === null
                ? 'min-w-0 truncate font-medium'
                : 'min-w-0 truncate text-muted-foreground'
            }>
            {sentence.words}
          </span>
        </>
      }
      badge={<EventBadge event={event} />}
      detail={detail}
      actions={
        event.url === null ? undefined : (
          <ChatLink
            href={event.url}
            data-slot="timeline-link"
            className="mt-0.5 inline-flex items-center gap-1 text-xs text-primary hover:underline">
            <ExternalLink aria-hidden="true" className="size-3" />
            Open {event.text ?? 'pull request'}
          </ChatLink>
        )
      }
      onActivate={seq === null ? onShowGoals : () => onJump(seq)}
      activateLabel={seq === null ? `${label} — show goals` : `Go to: ${label}`}
      data={{ 'data-slot': 'timeline-row', 'data-kind': event.kind }}
    />
  );
}

function EventBadge({
  event,
}: {
  event: ChatTimelineEvent;
}): React.JSX.Element | null {
  if (event.kind === 'review' && isAcceptance(event.detail)) {
    return <AcceptanceBadge acceptance={event.detail} />;
  }
  if ((event.kind === 'asked' || event.kind === 'approval') && event.open) {
    return (
      <Badge
        variant="warning"
        data-slot="timeline-waiting"
        className="shrink-0 px-1.5 py-0 text-[11px] font-normal">
        waiting on you
      </Badge>
    );
  }
  return null;
}
