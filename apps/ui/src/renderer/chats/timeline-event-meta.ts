interface KindMeta {
  icon: LucideIcon;
  tone: TimelineTone;
  /** Shown under Key steps; the rest only under Everything. */
  key: boolean;
}

const KIND_META: Readonly<Record<ChatTimelineEventKind, KindMeta>> = {
  [ChatTimelineEventKind.Started]: { icon: Play, tone: 'success', key: true },
  [ChatTimelineEventKind.Stage]: { icon: Milestone, tone: 'muted', key: true },
  [ChatTimelineEventKind.PullRequest]: {
    icon: GitPullRequest,
    tone: 'success',
    key: true,
  },
  [ChatTimelineEventKind.Review]: {
    icon: ClipboardCheck,
    tone: 'success',
    key: true,
  },
  [ChatTimelineEventKind.Failure]: {
    icon: CircleX,
    tone: 'destructive',
    key: true,
  },
  [ChatTimelineEventKind.Problems]: { icon: Bug, tone: 'warning', key: true },
  [ChatTimelineEventKind.Asked]: {
    icon: CircleHelp,
    tone: 'warning',
    key: true,
  },
  [ChatTimelineEventKind.Approval]: {
    icon: ShieldAlert,
    tone: 'warning',
    key: false,
  },
  [ChatTimelineEventKind.Finished]: { icon: Flag, tone: 'success', key: true },
  [ChatTimelineEventKind.Step]: { icon: Sparkles, tone: 'accent', key: true },
  [ChatTimelineEventKind.Call]: {
    icon: ArrowRightLeft,
    tone: 'muted',
    key: false,
  },
  [ChatTimelineEventKind.Note]: {
    icon: NotebookPen,
    tone: 'muted',
    key: false,
  },
  [ChatTimelineEventKind.Page]: { icon: FileText, tone: 'muted', key: false },
  [ChatTimelineEventKind.Goal]: { icon: Target, tone: 'success', key: false },
};

const STEP_LOOK: Readonly<
  Record<string, { icon: LucideIcon; tone: TimelineTone }>
> = {
  progress: { icon: Sparkles, tone: 'accent' },
  problem: { icon: TriangleAlert, tone: 'warning' },
  done: { icon: CircleCheckBig, tone: 'success' },
};

const FINISHED_TONE: Readonly<Record<ThreadOutcomeKind, TimelineTone>> = {
  [ThreadOutcomeKind.Success]: 'success',
  [ThreadOutcomeKind.Partial]: 'warning',
  [ThreadOutcomeKind.Failed]: 'destructive',
  [ThreadOutcomeKind.Abandoned]: 'muted',
};

const STAGE_VERB: Readonly<Record<string, string>> = {
  complete: 'finished',
  skip: 'skipped',
  reopen: 'reopened',
  handoff: 'handed on',
};

/**
 * The transcript kinds the daemon reads an event from, a structural trigger
 * for re-reading the timeline while it shows — never a fold of the events.
 */
export const TIMELINE_EVENT_KINDS: ReadonlySet<ItemKind> = new Set<ItemKind>([
  ItemKind.StageChange,
  ItemKind.RunOutcome,
  ItemKind.ThreadOutcome,
  ItemKind.Error,
  ItemKind.CallStarted,
  ItemKind.CallResult,
  ItemKind.ApprovalRequest,
  ItemKind.ApprovalVerdict,
  ItemKind.Unanswerable,
  ItemKind.ReportFindings,
  ItemKind.TeamNote,
  ItemKind.ShowArtifact,
  ItemKind.Milestone,
]);

/** What a user message's row is drawn with. */
export const MESSAGE_LOOK = { icon: MessageSquare, tone: 'primary' } as const;

function isOutcomeKind(value: string | null): value is ThreadOutcomeKind {
  return value !== null && value in FINISHED_TONE;
}

export function eventLook(event: ChatTimelineEvent): {
  icon: LucideIcon;
  tone: TimelineTone;
} {
  if (event.kind === ChatTimelineEventKind.Step) {
    return STEP_LOOK[event.detail ?? ''] ?? STEP_LOOK.progress!;
  }
  if (event.kind === ChatTimelineEventKind.Finished) {
    return {
      icon: Flag,
      tone: isOutcomeKind(event.detail)
        ? FINISHED_TONE[event.detail]
        : 'success',
    };
  }
  return KIND_META[event.kind];
}

/** Whether an event is shown with Key steps, not only with Everything. */
export function isKeyEvent(event: ChatTimelineEvent): boolean {
  return KIND_META[event.kind].key;
}

/** A row's one line: who, when there is someone to name, and what happened. */
export interface EventSentence {
  name: string | null;
  words: string;
}

export function eventSentence(
  event: ChatTimelineEvent,
  nameOf: (memberId: string) => string,
): EventSentence {
  const name = event.memberId === null ? null : nameOf(event.memberId);
  switch (event.kind) {
    case ChatTimelineEventKind.Started:
      return {
        name: null,
        words:
          name === null
            ? 'Work started'
            : `Work started · ${name} took the request`,
      };
    case ChatTimelineEventKind.Stage: {
      const verb = STAGE_VERB[event.detail ?? ''] ?? 'moved';
      const stage = event.text ?? 'a stage';
      return name === null
        ? { name: null, words: `Stage ${verb}: ${stage}` }
        : { name, words: `${verb} stage: ${stage}` };
    }
    case ChatTimelineEventKind.PullRequest:
      return {
        name: null,
        words:
          event.text === null
            ? 'Pull request opened'
            : `Pull request ${event.text} opened`,
      };
    case ChatTimelineEventKind.Review:
      return {
        name: null,
        words: `Review recorded${event.text === null ? '' : ` on ${event.text}`}`,
      };
    case ChatTimelineEventKind.Failure:
      return {
        name: null,
        words: name === null ? 'Failed' : `Failed · ${name}`,
      };
    case ChatTimelineEventKind.Problems: {
      const count = Number(event.detail ?? '0');
      return {
        name: name ?? 'Review',
        words: `found ${plural(count, 'problem', 'problems')}`,
      };
    }
    case ChatTimelineEventKind.Asked:
      return { name: name ?? 'Agent', words: 'asked you' };
    case ChatTimelineEventKind.Approval:
      return {
        name: name ?? 'Agent',
        words: `asked to run ${event.text ?? 'a tool'}`,
      };
    case ChatTimelineEventKind.Finished:
      return {
        name: null,
        words: isOutcomeKind(event.detail)
          ? `Thread finished · ${OUTCOME_LABEL[event.detail]}`
          : 'Thread finished',
      };
    case ChatTimelineEventKind.Step:
      return { name: name ?? 'Agent', words: event.text ?? '' };
    case ChatTimelineEventKind.Call: {
      const callee =
        event.detail === null ? 'another agent' : nameOf(event.detail);
      return {
        name: name ?? 'Agent',
        words: `→ ${callee}${event.text === null ? '' : ` · ${event.text}`}`,
      };
    }
    case ChatTimelineEventKind.Note:
      return {
        name: name ?? 'Agent',
        words:
          event.detail === null ? 'wrote a team note' : `· ${event.detail}`,
      };
    case ChatTimelineEventKind.Page:
      return {
        name: null,
        words: `Page published${event.text === null ? '' : ` · ${event.text}`}`,
      };
    case ChatTimelineEventKind.Goal:
      return { name: null, words: 'Goal achieved' };
  }
}

/** The muted second line an event carries, or null. */
export function eventDetail(event: ChatTimelineEvent): string | null {
  switch (event.kind) {
    case ChatTimelineEventKind.Failure:
    case ChatTimelineEventKind.Problems:
    case ChatTimelineEventKind.Asked:
    case ChatTimelineEventKind.Finished:
    case ChatTimelineEventKind.Note:
    case ChatTimelineEventKind.Goal:
      return event.text;
    case ChatTimelineEventKind.PullRequest:
      return event.detail;
    default:
      return null;
  }
}
