import { describe, expect, it } from 'vitest';

import type { ChatTimelineSegment, ChatTotals } from '../autogenerated';
import { liveSegment, segmentDetail, segmentFigures } from './timeline-figures';

const NOTHING_MEASURED: ChatTotals = {
  turns: 0,
  costedTurns: 0,
  costUsd: null,
  estimatedCostUsd: null,
  inputTokens: null,
  outputTokens: null,
  cacheReadTokens: null,
  cacheCreationTokens: null,
  thinkingTokens: null,
  workedMs: null,
};

function segment(
  fields: Partial<Omit<ChatTimelineSegment, 'totals'>> & {
    totals?: Partial<ChatTotals>;
  } = {},
): ChatTimelineSegment {
  return {
    aiMessages: fields.aiMessages ?? 1,
    elapsedMs: fields.elapsedMs ?? null,
    totals: { ...NOTHING_MEASURED, ...fields.totals },
  };
}

describe('segmentFigures', () => {
  it.each([
    [
      'omits an unmeasured cost rather than drawing it as zero',
      segment({ aiMessages: 2, elapsedMs: 5_000 }),
      ['2 messages', '5s'],
    ],
    [
      'counts a single message in the singular',
      segment({ aiMessages: 1 }),
      ['1 message'],
    ],
    [
      'leaves thinking tokens out of the total',
      segment({
        totals: {
          inputTokens: 1_000,
          outputTokens: 500,
          thinkingTokens: 9_000,
        },
      }),
      ['1 message', '1.5k tokens'],
    ],
    [
      'marks a cost geniro priced itself',
      segment({ totals: { costUsd: 0.42, estimatedCostUsd: 0.42 } }),
      ['1 message', '≈$0.42'],
    ],
    [
      'draws a measured cost as it is',
      segment({ totals: { costUsd: 0.5 } }),
      ['1 message', '$0.50'],
    ],
  ])('%s', (_title, input, expected) => {
    expect(segmentFigures(input)).toEqual(expected);
  });
});

describe('segmentDetail', () => {
  it('says which figures were never measured', () => {
    const detail = segmentDetail(segment());

    expect(detail).toContain('no time elapsed yet');
    expect(detail).toContain('agent time not measured');
    expect(detail).toContain('tokens not measured');
    expect(detail).toContain('cost not measured');
  });

  it('says when a cost is geniro’s own estimate', () => {
    const detail = segmentDetail(
      segment({ totals: { costUsd: 0.42, estimatedCostUsd: 0.42 } }),
    );

    expect(detail).toContain('≈$0.42 spent');
    expect(detail).toContain("geniro's estimate");
  });
});

describe('liveSegment', () => {
  const createdAt = '2026-11-20T10:00:00.000Z';
  const now = Date.parse(createdAt) + 90_000;

  it('runs a live stretch’s clock from its message', () => {
    expect(
      liveSegment(segment({ elapsedMs: 30_000 }), createdAt, true, now)
        .elapsedMs,
    ).toBe(90_000);
  });

  it('never runs it backwards past the daemon’s reading', () => {
    expect(
      liveSegment(segment({ elapsedMs: 120_000 }), createdAt, true, now)
        .elapsedMs,
    ).toBe(120_000);
  });

  it('leaves a settled stretch as the daemon read it', () => {
    expect(
      liveSegment(segment({ elapsedMs: 30_000 }), createdAt, false, now)
        .elapsedMs,
    ).toBe(30_000);
  });
});
