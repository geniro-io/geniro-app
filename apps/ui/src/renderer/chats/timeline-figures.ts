import { useEffect, useState } from 'react';

import type { ChatTimelineSegment } from '../autogenerated';
import {
  costEstimateNote,
  formatTokens,
  formatUsd,
  markEstimate,
} from './agent-activity';
import { formatDuration } from './turn-duration';

/**
 * The tokens one stretch moved: what went in, plus what came back.
 *
 * `thinkingTokens` is left out: some providers count reasoning inside the
 * output figure, so adding it would double some stretches and not others.
 * Null stays null, since `0` would claim a turn that moved no tokens at all.
 */
export function segmentTokens(segment: ChatTimelineSegment): number | null {
  const { inputTokens, outputTokens } = segment.totals;
  if (inputTokens === null && outputTokens === null) {
    return null;
  }
  return (inputTokens ?? 0) + (outputTokens ?? 0);
}

/**
 * The stretch's figures: how much was said, how long it took, what it moved,
 * what it cost. A figure nothing measured is omitted, never drawn as a zero.
 */
export function segmentFigures(segment: ChatTimelineSegment): string[] {
  const parts: string[] = [
    `${segment.aiMessages} ${segment.aiMessages === 1 ? 'message' : 'messages'}`,
  ];
  if (segment.elapsedMs !== null) {
    parts.push(formatDuration(segment.elapsedMs));
  }
  const tokens = segmentTokens(segment);
  if (tokens !== null) {
    parts.push(`${formatTokens(tokens)} tokens`);
  }
  if (segment.totals.costUsd !== null) {
    parts.push(
      markEstimate(
        formatUsd(segment.totals.costUsd),
        segment.totals.estimatedCostUsd,
      ),
    );
  }
  return parts;
}

/** The same figures spelled out, for the hover title. */
export function segmentDetail(segment: ChatTimelineSegment): string {
  const lines = [
    `${segment.aiMessages} agent message${segment.aiMessages === 1 ? '' : 's'}, sub-agents included`,
  ];
  lines.push(
    segment.elapsedMs === null
      ? 'no time elapsed yet'
      : `${formatDuration(segment.elapsedMs)} elapsed`,
  );
  lines.push(
    segment.totals.workedMs === null
      ? 'agent time not measured'
      : `${formatDuration(segment.totals.workedMs)} of agent time`,
  );
  const tokens = segmentTokens(segment);
  lines.push(
    tokens === null ? 'tokens not measured' : `${formatTokens(tokens)} tokens`,
  );
  lines.push(
    segment.totals.costUsd === null
      ? 'cost not measured'
      : `${markEstimate(formatUsd(segment.totals.costUsd), segment.totals.estimatedCostUsd)} spent`,
  );
  const estimate = costEstimateNote(
    segment.totals.costUsd,
    segment.totals.estimatedCostUsd,
  );
  if (estimate !== null) {
    lines.push(estimate);
  }
  return lines.join('\n');
}

/**
 * The wall clock, re-read every second while `active`, for the elapsed time of
 * the stretch still being worked. Schedules nothing otherwise.
 */
export function useNowWhile(active: boolean): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    if (!active) {
      return;
    }
    const timer = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(timer);
  }, [active]);
  return now;
}

/**
 * A stretch as it stands now: one still being worked runs its clock from the
 * message itself, never backwards past the daemon's last reading.
 */
export function liveSegment(
  segment: ChatTimelineSegment,
  createdAt: string,
  live: boolean,
  now: number,
): ChatTimelineSegment {
  return live
    ? {
        ...segment,
        elapsedMs: Math.max(
          segment.elapsedMs ?? 0,
          now - Date.parse(createdAt),
        ),
      }
    : segment;
}
