import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { RunSettledContext } from './live-row';
import { CollapseToolStepsContext, ToolGroup } from './tool-group';
import { groupTranscript, type ToolGroupEntry } from './transcript-groups';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let seq = 0;
function toolItem(
  kind: 'tool_call' | 'tool_result',
  payload: unknown,
): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    nodeId: 'orch',
    seq,
    kind,
    role: null,
    payload,
    createdAt: 'now',
  };
}

function makeGroup(items: ChatItem[]): ToolGroupEntry {
  const group = groupTranscript(items)[0];
  if (group?.type !== 'tools') {
    throw new Error('expected a tool group');
  }
  return group;
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function render(
  group: ToolGroupEntry,
  runSettled = false,
  collapseSteps = false,
): void {
  act(() =>
    root.render(
      // The context carries WHEN the run settled; a tool group only ever asks
      // WHETHER, so any moment stands for "settled" here.
      <RunSettledContext.Provider value={runSettled ? 1_000 : null}>
        <CollapseToolStepsContext.Provider value={collapseSteps}>
          <ToolGroup group={group} />
        </CollapseToolStepsContext.Provider>
      </RunSettledContext.Provider>,
    ),
  );
}

/** The header spinner — shown only while a call is believed to be in flight. */
function spinning(): boolean {
  return container.querySelector('.animate-spin') !== null;
}

/** Each expanded tool row's status, in row order, off its own status glyph. */
function rowStatuses(): (string | null)[] {
  return [
    ...container.querySelectorAll('button[aria-expanded] [data-status]'),
  ].map((icon) => icon.getAttribute('data-status'));
}

/**
 * The OPERATION glyphs on screen — what each settled row says it did.
 *
 * A settled row spends its leading glyph on the operation rather than on a
 * status, so `rowStatuses` above deliberately returns nothing for one: the two
 * helpers read two different marks, and a row carries exactly one of them.
 */
function rowOperations(): (string | null)[] {
  return (
    [...container.querySelectorAll('button[aria-expanded] [data-operation]')]
      // The group HEADER is an `aria-expanded` button too, and it now carries
      // operation glyphs of its own — so this helper has to say which of the two
      // marks it is reading, or a header strip would be reported as row icons.
      .filter((icon) => icon.closest(HEADER_OPERATIONS) === null)
      .map((icon) => icon.getAttribute('data-operation'))
  );
}

/** The strip on the COLLAPSED header — what the group says it did, as glyphs. */
const HEADER_OPERATIONS = '[data-slot="tool-group-operations"]';

function headerOperations(): (string | null)[] {
  return [
    ...container.querySelectorAll(`${HEADER_OPERATIONS} [data-operation]`),
  ].map((icon) => icon.getAttribute('data-operation'));
}

function click(el: Element | null): void {
  act(() => {
    el?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

describe('ToolGroup', () => {
  const bashGroup = (): ToolGroupEntry =>
    makeGroup([
      toolItem('tool_call', {
        id: 't1',
        name: 'Bash',
        input: { command: 'ls -la' },
      }),
      toolItem('tool_result', { id: 't1', name: null, result: 'file-list' }),
      toolItem('tool_call', {
        id: 't2',
        name: 'Read',
        input: { file_path: '/proj/a.ts' },
      }),
      toolItem('tool_result', { id: 't2', name: null, result: 'contents' }),
    ]);

  it('is COLLAPSED by default: the summary line shows, the tool rows and payloads do not', () => {
    render(bashGroup());

    // The sender frame around the group names the agent — the summary line
    // itself stays name-free.
    expect(container.textContent).toContain('Read 1 file · ran 1 command');
    expect(container.textContent).not.toContain('ls -la');
    expect(container.textContent).not.toContain('file-list');
    const header = container.querySelector('button[aria-expanded]');
    expect(header?.getAttribute('aria-expanded')).toBe('false');
  });

  it('shows what it did as glyphs WHILE COLLAPSED, matching its own summary', () => {
    // The reported gap: the operation icons existed only once a group was
    // expanded, so the state a reader spends most of their time in — a column
    // of collapsed rows — was identical grey text they had to read word by word.
    render(bashGroup());

    const header = container.querySelector('button[aria-expanded]');
    expect(header?.getAttribute('aria-expanded')).toBe('false');
    // Collapsed, and the glyphs are already there — in the summary's own order.
    expect(container.textContent).toContain('Read 1 file · ran 1 command');
    expect(headerOperations()).toEqual(['read', 'execute']);
    // …and no ROW has rendered, so these are the header's own.
    expect(rowOperations()).toEqual([]);
  });

  it('caps the collapsed glyphs at three', () => {
    render(
      makeGroup([
        toolItem('tool_call', {
          id: 't1',
          name: 'Read',
          input: { file_path: '/a' },
        }),
        toolItem('tool_result', { id: 't1', name: null, result: 'x' }),
        toolItem('tool_call', {
          id: 't2',
          name: 'Grep',
          input: { pattern: 'x' },
        }),
        toolItem('tool_result', { id: 't2', name: null, result: 'x' }),
        toolItem('tool_call', {
          id: 't3',
          name: 'Bash',
          input: { command: 'ls' },
        }),
        toolItem('tool_result', { id: 't3', name: null, result: 'x' }),
        toolItem('tool_call', {
          id: 't4',
          name: 'Edit',
          input: { file_path: '/b', old_string: 'a', new_string: 'b' },
        }),
        toolItem('tool_result', { id: 't4', name: null, result: 'x' }),
      ]),
    );

    // The sentence names four things; the strip shows three. A row of glyphs
    // long enough to need counting has stopped being a glance.
    expect(container.textContent).toContain('edited 1 file');
    expect(headerOperations()).toEqual(['read', 'search', 'execute']);
  });

  it('expands to one row per tool, and a row expands to the full input + result', () => {
    render(bashGroup());

    click(container.querySelector('button[aria-expanded]'));
    // Row headers now visible: name + one-line arg preview, details still not.
    expect(container.textContent).toContain('Bash');
    expect(container.textContent).toContain('ls -la');
    expect(container.textContent).not.toContain('file-list');

    const rows = [...container.querySelectorAll('button[aria-expanded]')];
    click(rows[1] ?? null); // first tool row (index 0 is the group header)
    // The command is shown AS a shell command, not as the raw JSON envelope
    // it arrived in — the input keys must not be on screen at all.
    const blocks = [...container.querySelectorAll('[data-slot="code-block"]')];
    expect(blocks.length).toBeGreaterThan(0);
    expect(blocks[0]?.getAttribute('data-language')).toBe('bash');
    expect(blocks[0]?.textContent).toBe('ls -la');
    expect(container.textContent).not.toContain('"command"');
    expect(container.textContent).toContain('file-list');
    expect(container.textContent).toContain('result');
  });

  it('renders Edit inputs as a red/green diff instead of raw JSON', () => {
    render(
      makeGroup([
        toolItem('tool_call', {
          id: 't1',
          name: 'Edit',
          input: {
            file_path: '/proj/a.ts',
            old_string: 'const a = 1;',
            new_string: 'const a = 2;',
          },
        }),
      ]),
    );

    // No presses: an edit shows its diff on arrival — see the auto-open tests
    // below for why.
    const diff = container.querySelector('[data-slot="diff"]');
    expect(diff).not.toBeNull();
    expect(diff?.textContent).toContain('-');
    expect(diff?.textContent).toContain('const a = 1;');
    expect(diff?.textContent).toContain('+');
    expect(diff?.textContent).toContain('const a = 2;');
    // The raw JSON body is replaced by the diff for edits.
    expect(container.textContent).not.toContain('"old_string"');
  });

  it('spends a finished row’s glyph on WHAT it did, and keeps the error mark', () => {
    render(
      makeGroup([
        toolItem('tool_call', { id: 't1', name: 'Bash', input: {} }),
        toolItem('tool_result', { id: 't1', name: null, result: 'ok' }),
        toolItem('tool_call', { id: 't2', name: 'Read', input: {} }),
        toolItem('tool_result', {
          id: 't2',
          name: null,
          result: 'ENOENT',
          isError: true,
        }),
      ]),
    );

    click(container.querySelector('button[aria-expanded]'));
    // Every settled row used to wear the same green check — a column of
    // identical ticks saying only "these happened", which the reader could see
    // already. The done row now names its operation instead.
    expect(rowOperations()).toEqual(['execute']);
    // And the failure keeps its own mark: a failed read must not be able to look
    // like a successful one.
    expect(rowStatuses()).toEqual(['failed']);
  });

  it('leaves a row still in flight on its status glyph, not on an operation', () => {
    // The operation is not the news while the call is running — whether it has
    // come back is. Classify unconditionally and a running Bash row would show a
    // terminal glyph, indistinguishable from one that had finished.
    render(
      makeGroup([
        toolItem('tool_call', {
          id: 't1',
          name: 'Bash',
          input: { command: 'sleep 5' },
        }),
      ]),
    );

    click(container.querySelector('button[aria-expanded]'));
    expect(rowStatuses()).toEqual(['running']);
    expect(rowOperations()).toEqual([]);
  });

  it('falls back to the status glyph for a tool it cannot classify', () => {
    // An unknown tool would otherwise lose its only leading mark, and a blank is
    // a worse answer than a check.
    render(
      makeGroup([
        toolItem('tool_call', { id: 't1', name: 'Telepathy', input: {} }),
        toolItem('tool_result', { id: 't1', name: null, result: 'ok' }),
      ]),
    );

    click(container.querySelector('button[aria-expanded]'));
    expect(rowOperations()).toEqual([]);
    expect(rowStatuses()).toEqual(['completed']);
  });

  it('reads the AGENT’s own classification, so a cursor row is not "unknown"', () => {
    // cursor titles its calls "Read File" / "Edit File" and matches no name
    // bucket, so without `toolKind` every one of its rows would fall back to the
    // check this change exists to replace.
    render(
      makeGroup([
        toolItem('tool_call', {
          id: 't1',
          name: 'Edit File',
          input: {},
          toolKind: 'edit',
        }),
        toolItem('tool_result', { id: 't1', name: null, result: 'ok' }),
      ]),
    );

    click(container.querySelector('button[aria-expanded]'));
    expect(rowOperations()).toEqual(['edit']);
  });

  it('shows an MCP tool under its readable name, not its wire identifier', () => {
    render(
      makeGroup([
        toolItem('tool_call', {
          id: 't1',
          name: 'mcp__linear__get_issue',
          input: {},
        }),
      ]),
    );

    click(container.querySelector('button[aria-expanded]'));
    expect(container.textContent).toContain('Linear: Get issue');
    expect(container.textContent).not.toContain('mcp__linear__get_issue');
  });
});

