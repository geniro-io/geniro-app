let seq = 0;
function item(
  kind: ChatItem['kind'],
  payload: unknown,
  nodeId: string | null = 'orch',
  role: string | null = null,
): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    nodeId,
    seq,
    kind,
    role,
    payload,
    createdAt: 'now',
  };
}

const call = (
  name: string,
  id: string,
  input: unknown = {},
  nodeId: string | null = 'orch',
): ChatItem => item('tool_call', { id, name, input }, nodeId);
const result = (
  id: string,
  value: unknown = 'ok',
  nodeId: string | null = 'orch',
): ChatItem => item('tool_result', { id, name: null, result: value }, nodeId);

describe('groupTranscript', () => {
  it('collapses consecutive same-node tool calls into ONE group and pairs results by id', () => {
    const entries = groupTranscript([
      item('message', { text: 'hi' }, null),
      call('Bash', 't1'),
      result('t1', 'out-1'),
      call('Read', 't2'),
      result('t2', 'out-2'),
    ]);

    expect(entries.map((e) => e.type)).toEqual(['item', 'tools']);
    const group = entries[1] as ToolGroupEntry;
    expect(group.pairs).toHaveLength(2);
    expect(group.pairs[0]?.result).not.toBeNull();
    expect(group.pairs[1]?.result).not.toBeNull();
  });

  it('a same-node non-tool item closes the group; the next call opens a NEW one', () => {
    const entries = groupTranscript([
      call('Bash', 't1'),
      item('message', { text: 'thinking aloud' }),
      call('Bash', 't2'),
    ]);

    expect(entries.map((e) => e.type)).toEqual(['tools', 'item', 'tools']);
    expect((entries[0] as ToolGroupEntry).pairs).toHaveLength(1);
    expect((entries[2] as ToolGroupEntry).pairs).toHaveLength(1);
  });

  it("another node's interleaved rows do NOT shred a node's tool run", () => {
    // A parallel branch (a callee's status/message) lands between the
    // caller's tool calls — the caller's group must keep accumulating.
    const entries = groupTranscript([
      call('Bash', 't1'),
      item('status', { status: 'running' }, 'poet'),
      item('message', { text: 'haiku' }, 'poet'),
      call('Grep', 't2'),
      result('t1'),
      result('t2'),
    ]);

    const groups = entries.filter(
      (e): e is ToolGroupEntry => e.type === 'tools',
    );
    expect(groups).toHaveLength(1);
    expect(groups[0]?.pairs).toHaveLength(2);
    expect(groups[0]?.pairs.every((p) => p.result !== null)).toBe(true);
  });

  it('a result pairs with its call even after the group closed', () => {
    const entries = groupTranscript([
      call('Bash', 't1'),
      item('message', { text: 'meanwhile…' }),
      result('t1', 'late result'),
    ]);

    expect(entries.map((e) => e.type)).toEqual(['tools', 'item']);
    expect((entries[0] as ToolGroupEntry).pairs[0]?.result).not.toBeNull();
  });

  it('drops mcp__geniro__* tool calls AND their results entirely', () => {
    // The dedicated call_* kinds already narrate agent calls — the raw
    // envelope JSON rows are duplication.
    const entries = groupTranscript([
      call('mcp__geniro__call_agent', 't1', { agent: 'poet' }),
      item('call_started', { callId: 'call-1', calleeNodeId: 'poet' }),
      result('t1', '{"status":"ok"}'),
    ]);

    expect(entries.map((e) => e.type)).toEqual(['item']);
    expect((entries[0] as { item: ChatItem }).item.kind).toBe('call_started');
  });

  it('an orphan tool_result (no known call) stays a plain item entry', () => {
    const entries = groupTranscript([result('mystery', 'out')]);
    expect(entries.map((e) => e.type)).toEqual(['item']);
  });
});

describe('groupTranscript — sub-agent work', () => {
  const SUB_A = 'toolu_agent_a';
  const SUB_B = 'toolu_agent_b';

  /** A tool call the CLI attributed to a sub-agent rather than the main thread. */
  const subCall = (name: string, id: string, parent: string): ChatItem =>
    item('tool_call', { id, name, input: {}, parentToolUseId: parent }, 'orch');
  const subSays = (text: string, parent: string): ChatItem =>
    item('message', { text, parentToolUseId: parent }, 'orch', 'assistant');

  it('does NOT let a sub-agent’s chatter split the main thread’s group', () => {
    // THE FLOOD. Sub-agent output arrives on the same stream interleaved with
    // the main thread's, so keying groups by node alone let every sub-agent
    // message close the main group — which is how eleven consecutive Bash
    // calls came to render as eleven separate flat rows.
    const entries = groupTranscript([
      call('Bash', 'm1'),
      subSays('working on it', SUB_A),
      call('Bash', 'm2'),
      subSays('still working', SUB_A),
      call('Bash', 'm3'),
    ]);

    const groups = entries.filter(
      (entry): entry is ToolGroupEntry => entry.type === 'tools',
    );
    const main = groups.filter((group) => group.parentToolUseId === null);
    expect(main).toHaveLength(1);
    // By tool-call id from the payload, not the item id: the item counter is
    // module-global, so absolute ids depend on which tests ran before this one.
    expect(
      main[0]?.pairs.map((pair) => payloadString(pair.call.payload, 'id')),
    ).toEqual(['m1', 'm2', 'm3']);
  });

  it('keeps two concurrent sub-agents in separate groups, and out of the main one', () => {
    const entries = groupTranscript([
      call('Bash', 'm1'),
      subCall('Bash', 'a1', SUB_A),
      subCall('Bash', 'b1', SUB_B),
      subCall('Read', 'a2', SUB_A),
      call('Read', 'm2'),
    ]);

    const groups = entries.filter(
      (entry): entry is ToolGroupEntry => entry.type === 'tools',
    );
    const byOrigin = new Map(
      groups.map((group) => [group.parentToolUseId, group]),
    );
    // Three origins, three groups — never one interleaved run.
    expect(groups).toHaveLength(3);
    expect(byOrigin.get(null)?.pairs).toHaveLength(2);
    expect(byOrigin.get(SUB_A)?.pairs).toHaveLength(2);
    expect(byOrigin.get(SUB_B)?.pairs).toHaveLength(1);
  });

  it('pairs a sub-agent’s result with its call across a main-thread line', () => {
    // Pairing goes through the payload's tool id, not the group key — so a
    // result must still find its call after the main thread has spoken in
    // between, which is the ordinary case once two threads interleave.
    const entries = groupTranscript([
      subCall('Bash', 'a1', SUB_A),
      item('message', { text: 'meanwhile' }, 'orch', 'assistant'),
      item('tool_result', { id: 'a1', name: null, result: 'ok' }, 'orch'),
    ]);
    const group = entries.find(
      (entry): entry is ToolGroupEntry => entry.type === 'tools',
    );
    expect(group?.parentToolUseId).toBe(SUB_A);
    expect(group?.pairs[0]?.result).not.toBeNull();
  });

  it('leaves an ordinary transcript with no sub-agents unchanged', () => {
    const entries = groupTranscript([
      call('Bash', 't1'),
      result('t1'),
      call('Read', 't2'),
    ]);
    expect(entries.map((entry) => entry.type)).toEqual(['tools']);
    expect((entries[0] as ToolGroupEntry).parentToolUseId).toBeNull();
  });
});

describe('groupTranscript — call blocks', () => {
  const startCall = (
    callId: string,
    callee: string,
    message = 'do the thing',
    mode = 'async',
  ): ChatItem =>
    item(
      'call_started',
      { callId, calleeNodeId: callee, mode, message },
      'orch',
    );
  const tagged = (
    kind: ChatItem['kind'],
    payload: Record<string, unknown>,
    nodeId: string,
    callId: string,
  ): ChatItem => item(kind, { ...payload, callId, nodeId }, nodeId);
  const isBlock = (e: { type: string }): e is CallBlockEntry =>
    e.type === 'call-block';

  it('folds a tagged callee sub-turn into ONE block — status rows become the header status, not rows', () => {
    const entries = groupTranscript([
      startCall('call-1', 'poet', 'Write a haiku.'),
      tagged('status', { status: 'running' }, 'poet', 'call-1'),
      tagged('message', { text: 'Waves rise…' }, 'poet', 'call-1'),
      tagged('status', { status: 'completed' }, 'poet', 'call-1'),
    ]);

    expect(entries).toHaveLength(1);
    const block = entries[0] as CallBlockEntry;
    expect(block.type).toBe('call-block');
    expect(block.callId).toBe('call-1');
    expect(block.calleeNodeId).toBe('poet');
    expect(block.callerNodeId).toBe('orch');
    expect(block.mode).toBe('async');
    // Request → result framing: the ask is the request, and the COMPLETED
    // sub-turn's final message is pulled out of the flow as the RESULT. The
    // old "▸ started"/"✓ finished" pair is the header status now.
    expect(block.message).toBe('Write a haiku.');
    expect(block.status).toBe('completed');
    expect(block.result).toBe('Waves rise…');
    expect(block.entries).toHaveLength(0);
  });

  it('a RUNNING sub-turn has no result yet — the tail message stays in the flow', () => {
    const entries = groupTranscript([
      startCall('call-1', 'poet', 'Write a haiku.'),
      tagged('status', { status: 'running' }, 'poet', 'call-1'),
      tagged('message', { text: 'draft so far…' }, 'poet', 'call-1'),
    ]);

    const block = entries[0] as CallBlockEntry;
    expect(block.status).toBe('running');
    expect(block.result).toBeNull();
    expect(block.entries).toHaveLength(1);
  });

  it('two parallel calls to the SAME callee node keep their items apart by callId', () => {
    const entries = groupTranscript([
      startCall('call-1', 'worker', 'rivers'),
      startCall('call-2', 'worker', 'mountains'),
      tagged('status', { status: 'running' }, 'worker', 'call-1'),
      tagged('status', { status: 'running' }, 'worker', 'call-2'),
      // Deliberately interleaved: call-2's text arrives first.
      tagged('message', { text: 'about mountains' }, 'worker', 'call-2'),
      tagged('message', { text: 'about rivers' }, 'worker', 'call-1'),
    ]);

    const blocks = entries.filter(isBlock);
    expect(blocks).toHaveLength(2);
    const texts = (block: CallBlockEntry): string =>
      JSON.stringify(block.entries);
    expect(texts(blocks[0]!)).toContain('about rivers');
    expect(texts(blocks[0]!)).not.toContain('about mountains');
    expect(texts(blocks[1]!)).toContain('about mountains');
    expect(blocks[0]!.status).toBe('running');
  });

  it('tool calls inside a sub-turn still group Claude-style within the block', () => {
    const entries = groupTranscript([
      startCall('call-1', 'researcher'),
      tagged('status', { status: 'running' }, 'researcher', 'call-1'),
      tagged(
        'tool_call',
        { id: 't1', name: 'Bash', input: { command: 'pwd' } },
        'researcher',
        'call-1',
      ),
      tagged(
        'tool_result',
        { id: 't1', name: null, result: '/proj' },
        'researcher',
        'call-1',
      ),
    ]);

    const block = entries[0] as CallBlockEntry;
    expect(block.entries).toHaveLength(1);
    expect(block.entries[0]?.type).toBe('tools');
  });

  it('UNTAGGED (legacy) callee items stay in the main flow with the flat call row', () => {
    const entries = groupTranscript([
      startCall('call-1', 'poet'),
      item('status', { status: 'running' }, 'poet'),
      item('message', { text: 'legacy haiku' }, 'poet'),
    ]);

    expect(entries.filter(isBlock)).toHaveLength(0);
    expect(entries.map((e) => e.type)).toEqual(['item', 'item', 'item']);
  });

  it('a tagged approval_request is NEVER claimed — a pending card must stay answerable in the main flow', () => {
    const entries = groupTranscript([
      startCall('call-1', 'poet'),
      tagged('status', { status: 'running' }, 'poet', 'call-1'),
      tagged(
        'approval_request',
        { id: 'req-1', toolName: 'Bash', input: {} },
        'poet',
        'call-1',
      ),
    ]);

    const block = entries.find(isBlock)!;
    expect(JSON.stringify(block.entries)).not.toContain('req-1');
    expect(
      entries.some(
        (e) => e.type === 'item' && e.item.kind === 'approval_request',
      ),
    ).toBe(true);
  });

  it('the WHOLE exchange claims into the block: question/answer nest, the ok settle drops', () => {
    const entries = groupTranscript([
      startCall('call-1', 'poet'),
      tagged('status', { status: 'running' }, 'poet', 'call-1'),
      item(
        'call_question',
        { callId: 'call-1', calleeNodeId: 'poet', question: 'Which sea?' },
        'orch',
      ),
      item(
        'call_answer',
        {
          callId: 'call-1',
          calleeNodeId: 'poet',
          outcome: 'answered',
          answer: 'Baltic',
        },
        'orch',
      ),
      tagged('message', { text: 'haiku!' }, 'poet', 'call-1'),
      tagged('status', { status: 'completed' }, 'poet', 'call-1'),
      item(
        'call_result',
        { callId: 'call-1', calleeNodeId: 'poet', status: 'ok', result: {} },
        'orch',
      ),
    ]);

    // Nothing about the call remains in the main flow.
    expect(entries.map((e) => e.type)).toEqual(['call-block']);
    const block = entries[0] as CallBlockEntry;
    const innerJson = JSON.stringify(block.entries);
    expect(innerJson).toContain('Which sea?');
    expect(innerJson).toContain('Baltic');
    // The ok settle envelope is bookkeeping — the done chip + result own it.
    expect(innerJson).not.toContain('call_result');
  });

  it('an ERROR settle keeps its row inside the block', () => {
    const entries = groupTranscript([
      startCall('call-1', 'poet'),
      tagged('status', { status: 'running' }, 'poet', 'call-1'),
      tagged('status', { status: 'failed' }, 'poet', 'call-1'),
      item(
        'call_result',
        {
          callId: 'call-1',
          calleeNodeId: 'poet',
          status: 'error',
          error: 'CALLEE_FAILED: exit 1',
        },
        'orch',
      ),
    ]);

    expect(entries.map((e) => e.type)).toEqual(['call-block']);
    expect(JSON.stringify((entries[0] as CallBlockEntry).entries)).toContain(
      'CALLEE_FAILED',
    );
  });
});

describe('toolGroupSummary', () => {
  it('counts reads, commands, edited and created files', () => {
    const pairs = groupTranscript([
      call('Bash', 't1', { command: 'ls' }),
      call('Bash', 't2', { command: 'pwd' }),
      call('Edit', 't3', {
        file_path: '/a.ts',
        old_string: 'x',
        new_string: 'y',
      }),
      call('Write', 't4', { file_path: '/b.ts', content: 'hello' }),
      call('Read', 't5', { file_path: '/c.ts' }),
    ])[0] as ToolGroupEntry;

    // Every call now has a named bucket, so the bare total goes away entirely —
    // which is the point: "Used 5 tools" said nothing about what the five were.
    expect(toolGroupSummary(pairs.pairs)).toBe(
      'Read 1 file · ran 2 commands · edited 1 file · created 1 file',
    );
  });

  it('reports a group of file reads as reads, not as a bare tool count', () => {
    // The line the user photographed read "Used 7 tools · ran 3 commands" for
    // four Reads and three Bashes — the reads were invisible.
    const group = groupTranscript([
      call('Read', 't1', { file_path: '/a.ts' }),
      call('Read', 't2', { file_path: '/b.ts' }),
      call('Read', 't3', { file_path: '/c.ts' }),
      call('Read', 't4', { file_path: '/d.ts' }),
      call('Bash', 't5', { command: 'ls' }),
      call('Bash', 't6', { command: 'pwd' }),
      call('Bash', 't7', { command: 'rg x' }),
    ])[0] as ToolGroupEntry;

    expect(toolGroupSummary(group.pairs)).toBe('Read 4 files · ran 3 commands');
  });

  it('counts reads by DISTINCT path, like the edits', () => {
    const group = groupTranscript([
      call('Read', 't1', { file_path: '/a.ts' }),
      call('Read', 't2', { file_path: '/a.ts' }),
    ])[0] as ToolGroupEntry;

    expect(toolGroupSummary(group.pairs)).toBe('Read 1 file');
  });

  it('names searches, web fetches, subagents and MCP calls', () => {
    const group = groupTranscript([
      call('Grep', 't1', { pattern: 'x' }),
      call('Glob', 't2', { pattern: '*.ts' }),
      call('WebFetch', 't3', { url: 'https://example.com' }),
      call('Task', 't4', { prompt: 'go' }),
      call('mcp__codegraph__codegraph_explore', 't5', { query: 'x' }),
      call('mcp__telegram__send_message', 't6', { text: 'hi' }),
    ])[0] as ToolGroupEntry;

    expect(toolGroupSummary(group.pairs)).toBe(
      'Searched 2 times · fetched 1 page · delegated to 1 subagent · called 2 MCP tools',
    );
  });

  it('does not count the same action twice when the breakdown covers it all', () => {
    // "Used 1 tool · ran 1 command" reported one action as two figures. The
    // total is dropped exactly when every call already has a named bucket.
    const group = groupTranscript([
      call('Bash', 't1', { command: 'ls' }),
    ])[0] as ToolGroupEntry;

    expect(toolGroupSummary(group.pairs)).toBe('Ran 1 command');
  });

  it('keeps the total as soon as one call falls outside the breakdown', () => {
    // TodoWrite is in no bucket, so dropping the total would hide it entirely.
    const group = groupTranscript([
      call('Bash', 't1', { command: 'ls' }),
      call('TodoWrite', 't2', { todos: [] }),
    ])[0] as ToolGroupEntry;

    expect(toolGroupSummary(group.pairs)).toBe('Used 2 tools · ran 1 command');
  });

  it('leaves a file-shaped call with no path unaccounted rather than miscounting it', () => {
    // Reporting it as "read 0 files" would be a figure for something that never
    // happened; the total is the honest answer for a call we cannot describe.
    const group = groupTranscript([
      call('Read', 't1', { notAPath: true }),
    ])[0] as ToolGroupEntry;

    expect(toolGroupSummary(group.pairs)).toBe('Used 1 tool');
  });

  it('counts CALLS, not distinct files, when deciding the total is redundant', () => {
    // Three edits to one file are three accounted calls and one edited file.
    // Comparing the DISPLAYED figures instead would have kept "Used 3 tools ·
    // edited 1 file" — the very line the drop exists to avoid.
    const group = groupTranscript([
      call('Edit', 't1', {
        file_path: '/a.ts',
        old_string: 'a',
        new_string: 'b',
      }),
      call('Edit', 't2', {
        file_path: '/a.ts',
        old_string: 'b',
        new_string: 'c',
      }),
      call('Edit', 't3', {
        file_path: '/a.ts',
        old_string: 'c',
        new_string: 'd',
      }),
    ])[0] as ToolGroupEntry;

    expect(toolGroupSummary(group.pairs)).toBe('Edited 1 file');
  });
});

