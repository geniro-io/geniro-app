  function callBlockOf(items: ChatItem[]): CallBlockEntry {
    const found = groupTranscript(items).find(
      (entry) => entry.type === 'call-block',
    );
    if (found?.type !== 'call-block') {
      throw new Error('expected a call block');
    }
    return found;
  }

  /** The role of the row carrying `text`, wherever the fold nested it. */
  function roleOfText(
    entries: readonly TranscriptEntry[],
    text: string,
  ): string | null | undefined {
    for (const entry of entries) {
      if (entry.type === 'item') {
        if (payloadString(entry.item.payload, 'text') === text) {
          return entry.item.role;
        }
      } else if ('entries' in entry) {
        const nested = roleOfText(entry.entries, text);
        if (nested !== undefined) {
          return nested;
        }
      }
    }
    return undefined;
  }

