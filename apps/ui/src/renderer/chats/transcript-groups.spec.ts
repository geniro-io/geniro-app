describe('pullFileChangesOutOfGroups', () => {
  /** An `Edit` as claude discloses it — the change is in the ARGUMENTS. */
  const edit = (
    id: string,
    path: string,
    nodeId: string | null = 'orch',
  ): ChatItem =>
    call(
      'Edit',
      id,
      { file_path: path, old_string: 'before', new_string: 'after' },
      nodeId,
    );

  const shapeOf = (entries: readonly TranscriptEntry[]): string[] =>
    entries.map((entry) =>
      entry.type !== 'tools'
        ? entry.type
        : `${entry.standalone === true ? 'edit' : 'group'}:${entry.pairs
            .map((pair) => payloadString(pair.call.payload, 'name'))
            .join('+')}`,
    );

  it('splits a run at each file change, leaving the calls around it grouped', () => {
    // REPORTED: "у нас все еще должны быть группы, сколлапсированные с другими
    // экшенами, но редактирование файлов должно быть вне этой группы … если
    // агент сделал несколько shell-tool колов, у нас должна быть еще одна
    // группа «collapse» … а отдельно блок с редактированием файла".
    const folded = groupTranscript([
      call('Bash', 'c1', { command: 'ls' }),
      call('Bash', 'c2', { command: 'grep x' }),
      edit('c3', 'src/a.ts'),
      call('Read', 'c4', { file_path: 'src/b.ts' }),
      edit('c5', 'src/b.ts'),
    ]);
    // The whole run is ONE group before the split — which is the shape being
    // fixed, not a detail of the fixture.
    expect(shapeOf(folded)).toEqual(['group:Bash+Bash+Edit+Read+Edit']);

    expect(shapeOf(pullFileChangesOutOfGroups(folded))).toEqual([
      'group:Bash+Bash',
      'edit:Edit',
      'group:Read',
      'edit:Edit',
    ]);
  });

  it('leaves a group with no file change exactly as it was', () => {
    // Identity, not equality: an untouched run must not be rebuilt, or every
    // group in a long transcript remounts on a setting nobody changed.
    const folded = groupTranscript([
      call('Bash', 'c1', { command: 'ls' }),
      call('Read', 'c2', { file_path: 'src/b.ts' }),
    ]);
    const split = pullFileChangesOutOfGroups(folded);
    expect(split).toHaveLength(1);
    expect(split[0]).toBe(folded[0]);
  });

  it('lifts a change an ACP agent reports on its RESULT, not its arguments', () => {
    // The two shipped transports disclose a change at opposite ends of one
    // call, and the result arrives AFTER the call was grouped — which is the
    // whole reason this runs on the fold's output rather than inside it. Taken
    // during the fold, every cursor edit would read as "not an edit".
    const folded = groupTranscript([
      call('Bash', 'c1', { command: 'ls' }),
      call('write', 'c2', {}),
      result('c2', {
        diffs: [{ path: 'src/a.ts', oldText: 'before', newText: 'after' }],
      }),
    ]);
    expect(shapeOf(folded)).toEqual(['group:Bash+write']);

    expect(shapeOf(pullFileChangesOutOfGroups(folded))).toEqual([
      'group:Bash',
      'edit:write',
    ]);
  });

  it('gives every piece of a split run its own identity', () => {
    // The pieces are React keys AND the handle each row's expansion state hangs
    // off. Reusing the run's id would give three siblings one key.
    const folded = groupTranscript([
      call('Bash', 'c1', { command: 'ls' }),
      edit('c2', 'src/a.ts'),
      call('Bash', 'c3', { command: 'ls' }),
    ]);
    const ids = pullFileChangesOutOfGroups(folded).map((entry) =>
      entry.type === 'tools' ? entry.id : '',
    );
    expect(new Set(ids).size).toBe(3);
  });

  it('carries the group’s own facts onto every piece', () => {
    // `closed`, the node and the sub-agent thread all decide whether a piece
    // spins and where it is filed. A split that dropped them would put a
    // delegate's edit in the main flow with a spinner that never stops.
    const folded = groupTranscript([
      call('Bash', 'c1', { command: 'ls' }, 'node-a'),
      edit('c2', 'src/a.ts', 'node-a'),
    ]);
    const group = folded[0] as ToolGroupEntry;
    group.closed = true;
    const split = pullFileChangesOutOfGroups([group]) as ToolGroupEntry[];
    expect(split).toHaveLength(2);
    for (const piece of split) {
      expect(piece.closed).toBe(true);
      expect(piece.nodeId).toBe(group.nodeId);
      expect(piece.parentToolUseId).toBe(group.parentToolUseId);
    }
  });
});

/**
 * A conversation is the calls that CONTINUE one another, and its parent link
 * has to survive the transcript window — which is where it used to be read
 * from, and only from.
 */
describe('resolveCallChains — a conversation outlives the loaded window', () => {
  const started = (callId: string, thread: string | null) =>
    item('call_started', {
      callId,
      calleeNodeId: 'engineer',
      ...(thread === null ? {} : { thread }),
    });

  it('joins a continuation to a parent only the DAEMON still knows', () => {
    // The shape measured on a real run: `call-8` had paged out past
    // HISTORY_PAGE while `call-9` and `call-10` were still loaded, so the
    // panel drew `call-8` as its own instance with its own spend.
    const chains = resolveCallChains(
      [started('call-9', 'call-8'), started('call-10', 'call-9')],
      new Map([
        ['call-8', { thread: null }],
        ['call-9', { thread: 'call-8' }],
        ['call-10', { thread: 'call-9' }],
      ]),
    );
    expect(chains.get('call-10')).toEqual(['call-8', 'call-9', 'call-10']);
    // Every member names the same conversation, so a spend folded over
    // `callIds` covers all three however the reader reached it.
    expect(chains.get('call-8')).toBe(chains.get('call-10'));
  });

  it('orders a chain by the daemon’s numbering, not by where each call was found', () => {
    // `callIds.at(-1)` is the LATEST call on every surface, so a parent
    // arriving from the readings after its child arrived from the window must
    // not end up last.
    const chains = resolveCallChains(
      [started('call-9', 'call-8')],
      new Map([['call-8', { thread: null }]]),
    );
    expect(chains.get('call-9')).toEqual(['call-8', 'call-9']);
  });

  it('keeps the window’s own reading when both sources know a call', () => {
    const chains = resolveCallChains(
      [started('call-2', 'call-1'), started('call-1', null)],
      new Map([['call-2', { thread: null }]]),
    );
    expect(chains.get('call-2')).toEqual(['call-1', 'call-2']);
  });

  it('merges a BRANCH, two calls continuing one settled thread', () => {
    const chains = resolveCallChains([
      started('call-1', null),
      started('call-2', 'call-1'),
      started('call-3', 'call-1'),
    ]);
    expect(chains.get('call-3')).toEqual(['call-1', 'call-2', 'call-3']);
  });

  it('refuses a parent the daemon minted LATER, so a cycle cannot form', () => {
    // The guarantee used to come from array position, which a durable map does
    // not have; it comes from the numbering now, and holds for a parent the
    // window never loaded.
    const chains = resolveCallChains(
      [],
      new Map([
        ['call-1', { thread: 'call-2' }],
        ['call-2', { thread: 'call-1' }],
      ]),
    );
    // call-1 naming call-2 is refused (later), call-2 naming call-1 joins.
    expect(chains.get('call-2')).toEqual(['call-1', 'call-2']);
  });

  it('refuses a thread that names the call itself', () => {
    const chains = resolveCallChains(
      [],
      new Map([['call-5', { thread: 'call-5' }]]),
    );
    expect(chains.get('call-5')).toEqual(['call-5']);
  });

  it('leaves a call whose parent nothing knows as its own conversation', () => {
    const chains = resolveCallChains([started('call-9', 'call-8')]);
    expect(chains.get('call-9')).toEqual(['call-9']);
  });
});

describe('withLiveText — a card being WRITTEN', () => {
  const RUN = 'abc12345-0000-0000-0000-000000000000';
  const ARTIFACT_TOOL = 'mcp__geniro-abc12345__show_artifact';

  const live = (over: Partial<LiveState> = {}): LiveState => ({
    text: '',
    thinkingTokens: null,
    thinkingText: null,
    thinkingSince: null,
    thinkingStretch: null,
    composingTool: null,
    composingBytes: null,
    contextTokens: null,
    contextWindowTokens: null,
    spentInputTokens: null,
    spentOutputTokens: null,
    spentCacheReadTokens: null,
    ...over,
  });

  /** Every synthetic live row a fold produced, in order. */
  function liveRows(entries: readonly TranscriptEntry[]): unknown[] {
    const out: unknown[] = [];
    const walk = (list: readonly TranscriptEntry[]): void => {
      for (const entry of list) {
        if (entry.type === 'item') {
          if (liveRowKind(entry.item.payload) !== null) {
            out.push(entry.item.payload);
          }
          continue;
        }
        if ('entries' in entry) {
          walk(entry.entries as readonly TranscriptEntry[]);
        }
      }
    };
    walk(entries);
    return out;
  }

  it('draws a placeholder for the card the model is writing', () => {
    // The wait this exists for: a host tool's argument IS its deliverable, and
    // the raw call row is hidden by design, so the transcript stayed on the
    // generic working row for the whole of it.
    const entries = withLiveText(
      [],
      new Map([
        [
          CHAT_LIVE_KEY,
          live({ composingTool: ARTIFACT_TOOL, composingBytes: 4096 }),
        ],
      ]),
      new Set(),
      RUN,
    );
    expect(liveRows(entries)).toEqual([
      { live: 'composing', composingKind: 'artifact', composingBytes: 4096 },
    ]);
  });

  it('leaves the words that introduced it ON SCREEN', () => {
    // The sentence that announces a card ("I'll put this in an artifact") is
    // routinely still live when the call starts; replacing it would take it off
    // the screen until its durable item landed. Two rows, words first, because
    // that is the order they happened in.
    const entries = withLiveText(
      [],
      new Map([
        [
          CHAT_LIVE_KEY,
          live({
            text: 'Putting this in a page',
            composingTool: ARTIFACT_TOOL,
          }),
        ],
      ]),
      new Set(),
      RUN,
    );
    const block = entries[entries.length - 1] as TurnBlockEntry;
    const kinds = block.entries.map((entry) =>
      entry.type === 'item' ? liveRowKind(entry.item.payload) : null,
    );
    expect(kinds).toEqual([null, 'composing']);
    expect(block.entries[0]).toMatchObject({
      item: { payload: { text: 'Putting this in a page' } },
    });
  });

  it('draws NOTHING for a tool that produces no card', () => {
    // A call tool's story is told by the dedicated call rows, so a placeholder
    // would resolve into nothing at all — and every ordinary tool is answered
    // within milliseconds of being written, so a loader for one would flicker.
    for (const tool of ['mcp__geniro-abc12345__call_agent', 'Bash']) {
      const entries = withLiveText(
        [],
        new Map([[CHAT_LIVE_KEY, live({ composingTool: tool })]]),
        new Set(),
        RUN,
      );
      expect(liveRows(entries)).toEqual([]);
    }
  });

  it('draws nothing without a run to check the server name against', () => {
    // geniro's MCP server is named per run, and that id is what makes the name
    // unforgeable. Withheld rather than matched loosely: a card-shaped loader
    // drawn for a user's own tool is worse than no loader at all.
    const entries = withLiveText(
      [],
      new Map([[CHAT_LIVE_KEY, live({ composingTool: ARTIFACT_TOOL })]]),
      new Set(),
      null,
    );
    expect(liveRows(entries)).toEqual([]);
  });

  it('omits the byte count when nothing measured it', () => {
    const entries = withLiveText(
      [],
      new Map([[CHAT_LIVE_KEY, live({ composingTool: ARTIFACT_TOOL })]]),
      new Set(),
      RUN,
    );
    expect(liveRows(entries)).toEqual([
      { live: 'composing', composingKind: 'artifact' },
    ]);
  });

  it('suppresses the working fallback for an agent that is composing', () => {
    // The agent has been spoken for — a `Working…` row beside the skeleton
    // would be two rows narrating one wait, which is the defect the live plane
    // was reworked to fix.
    const entries = withLiveText(
      [],
      new Map([[CHAT_LIVE_KEY, live({ composingTool: ARTIFACT_TOOL })]]),
      new Set([CHAT_LIVE_KEY]),
      RUN,
    );
    expect(liveRows(entries).map((payload) => liveRowKind(payload))).toEqual([
      'composing',
    ]);
  });
});
