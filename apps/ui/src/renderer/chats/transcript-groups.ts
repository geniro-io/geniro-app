/**
 * The open-group bucket an item belongs to: its node AND its originating
 * thread.
 *
 * A node id and a sub-agent id are opaque strings from different namespaces —
 * a node id is authored by hand in a workflow YAML — so they are joined by NUL
 * rather than concatenated. Without a separator, node `a` with sub-agent `b`
 * and node `ab` with none would share a bucket, and any PRINTABLE separator is
 * one a hand-written node id could itself contain.
 */
function groupKey(item: ChatItem): string {
  return `${item.nodeId ?? ''}\u0000${subagentIdOf(item) ?? ''}`;
}

/**
 * The renderer's own agent-call tools ride the transcript as raw
 * tool_call/tool_result items too, but the dedicated call kinds
 * (call_started/call_result/call_question/call_answer/await_collected)
 * already tell that story in a readable form — the raw envelope JSON rows
 * are pure duplication, so they are hidden from the transcript. Every host tool
 * rides it for the same reason: each draws its own card — a findings table, a
 * chart, a scorecard, a decision table, a diff with Apply, a plan with Approve
 * — and the raw call beside it is the same row twice.
 *
 * A row STORED before geniro's server was renamed per run — claude published it
 * under this fixed key then, so old transcripts carry `mcp__geniro__<tool>` and
 * would otherwise start showing raw envelope rows on replay. Live turns are
 * matched by the run-scoped rule in {@link isGeniroToolName} instead.
 *
 * Paired with the TOOL NAMES rather than used as a bare prefix, because
 * `geniro` is a name a user's own MCP server may legitimately carry: matching
 * the prefix alone hid every call to THEIR server as well, so an agent would
 * work through it while the transcript showed nothing.
 */
const GENIRO_TOOL_PREFIX = 'mcp__geniro__';

/** Every tool geniro publishes on its own server. */
const GENIRO_TOOL_NAMES = [
  'call_agent',
  'await_agent',
  'answer_agent',
  'ask_user_question',
  'report_findings',
  // None of these five was ever published under the legacy fixed key — the
  // per-run rename shipped first — but they are listed with their siblings so
  // this list and the daemon's cannot drift, and so a transcript exported from
  // a build in between still hides them.
  'show_chart',
  'show_metrics',
  'show_comparison',
  'show_gallery',
  'propose_patch',
  'propose_plan',
] as const;

/**
 * Whether a tool call names geniro's own server — under EITHER of that server's
 * two names.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/utils/host-tool.ts` decides the same
 * question daemon-side, for the permission gate, and its doc block carries the
 * two-names contract both sides read from.
 *
 * The per-run half is what covers cursor, whose tool rows carry no `mcp__` name
 * at all — the CLI reports the pair as one prose label around the server name
 * geniro minted. The run id in that name is what makes it unforgeable, which is
 * why containment is enough here and no tool-name list is kept.
 */
function isGeniroToolName(name: string, runId: string): boolean {
  if (name.includes(`geniro-${runId.slice(0, 8)}`)) {
    return true;
  }
  return GENIRO_TOOL_NAMES.some(
    (tool) => name === `${GENIRO_TOOL_PREFIX}${tool}`,
  );
}

/**
 * Whether a tool RESULT is one of geniro's own call envelopes.
 *
 * TWIN PARSER: `CallEnvelope` in
 * `apps/daemon/src/v1/graphs/graphs.types.ts` is what produces this shape, and
 * `McpServerService` is what serializes it into the tool result. There is no
 * generated type spanning the seam — an item payload is `z.unknown()` on the
 * wire by design — so a field renamed there must be renamed here.
 *
 * It exists for the ORPHAN case alone: a result whose own call is inside the
 * loaded window is already hidden by id, which is both cheaper and exact. This
 * is the fallback for the window boundary, and it matches on the envelope's
 * OWN discriminators — a `status` this app defines plus a `call_id` — rather
 * than on any prose, so an agent that merely writes about a call cannot trip
 * it: a tool result is a payload we serialized, not something a model wrote.
 */
function isCallEnvelopeResult(payload: unknown): boolean {
  // The SHARED reader, so this and the row that would have drawn the result
  // are looking at the same string.
  const text = toolResultText(recordOf(payload)?.result).trim();
  if (!text.startsWith('{')) {
    return false;
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    return false;
  }
  const envelope = recordOf(parsed);
  const status = envelope?.status;
  if (typeof status !== 'string') {
    return false;
  }
  // Every arm of the union carries a call id — at the root (`pending`,
  // `question`) or inside `result` (`ok`), which is why both are read.
  return (
    typeof envelope?.call_id === 'string' ||
    typeof recordOf(envelope?.result)?.call_id === 'string'
  );
}

