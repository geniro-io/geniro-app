/**
 * Where a workflow stands — the ONE derivation, so the card and anything else
 * that reports on a workflow cannot disagree about whether it is still out.
 *
 * The ROSTER outranks the launching call's return, and that ordering was
 * measured rather than reasoned: a workflow can be BACKGROUNDED, and then its
 * call is answered in seconds with "The workflow is running in the background —
 * I'll report when it completes" while the fleet works on. Observed live on
 * 2.1.251 through this very card, which read `completed` beside its own header
 * saying `3 agents · 1 running`. An agent the newest roster still lists as out
 * is evidence; the return is only a claim about the tool call.
 *
 * A run that has settled outranks the roster in turn, on
 * `subagentBlockStatus`'s reasoning: with the CLI gone, an agent left `running`
 * on the last roster is UNREPORTED work rather than running work, and reading
 * it as running latches the spinner on for good.
 */
export function workflowCardStatus(
  entry: WorkflowEntry,
  runSettledAt: RunSettleAt = null,
): 'running' | BackgroundOutcome {
  if (entry.failed) {
    return 'failed';
  }
  // The run settling ends a workflow that has said nothing SINCE — the same
  // reading, and the same measured defect, as `subagentBlockStatus`'s.
  const endedByRun =
    runSettledAt !== null &&
    (runSettledAt === 'unknown' ||
      entry.lastRowAt === null ||
      entry.lastRowAt <= runSettledAt);
  if (workflowTally(entry.workflow.agents).running > 0 && !endedByRun) {
    return 'running';
  }
  if (entry.returned) {
    return 'completed';
  }
  return endedByRun ? 'stopped' : 'running';
}

export type TranscriptEntry =
  | ItemEntry
  | ToolGroupEntry
  | CallBlockEntry
  | TurnBlockEntry
  | SubagentBlockEntry
  | TaskListEntry
  | FindingsEntry
  | ChartEntry
  | MetricsEntry
  | ComparisonEntry
  | GalleryEntry
  | WorkflowEntry;

/**
 * A CARD entry: a folded row that stands on its own — not a raw item, not a
 * block enclosing other rows.
 *
 * The four share one shape (`id`/`createdAt`/`seq`/`nodeId`/`parentToolUseId`)
 * and, more to the point, share how six separate readers below have to treat
 * them: who owns it, which thread it belongs to, its `seq` for ordering nested
 * work, its `createdAt` for "has anything spoken since", and the fact that it
 * holds no tool invocations to count.
 *
 * Extracted at the fourth one. Each of those six readers spelled the same
 * three-arm `entry.type === …` chain, so a new card kind was six edits, every
 * one of them silent when missed — a card left out of the `lastRowAt` fold does
 * not fail, it just stops a spinner from noticing that work has happened. One
 * predicate made the fifth card a single line.
 *
 * The union and the predicate must list the SAME kinds, and the COMPILER is
 * what enforces it: adding `comparison` to the predicate alone — which is how
 * the fifth card actually went in — narrowed nothing, and five call sites
 * stopped compiling because a `ComparisonEntry` reached a branch expecting
 * `.entries`. That is the trade this abstraction makes, and it is the whole
 * point of it: six silent misses became one loud one.
 */
export type CardEntry =
  | TaskListEntry
  | FindingsEntry
  | ChartEntry
  | MetricsEntry
  | ComparisonEntry
  | GalleryEntry
  | WorkflowEntry;

export function isCardEntry(entry: TranscriptEntry): entry is CardEntry {
  return (
    entry.type === 'task-list' ||
    entry.type === 'findings' ||
    entry.type === 'chart' ||
    entry.type === 'metrics' ||
    entry.type === 'comparison' ||
    entry.type === 'gallery' ||
    entry.type === 'workflow'
  );
}

/** Sentinel: entry has no agent owner and breaks a turn block. */
const NO_OWNER = Symbol('no-owner');

/**
 * The node AND originating thread an entry belongs to — the same pairing
 * {@link groupKey} folds tool groups by. `nodeId` alone is not enough: a
 * sub-agent's rows carry the MAIN agent's nodeId, so keying on it alone
 * folded a delegate's words into the main agent's block under its own
 * SenderRow.
 */
interface EntryOwner {
  nodeId: string | null;
  subagentId: string | null;
}

function sameOwner(a: EntryOwner, b: EntryOwner): boolean {
  return a.nodeId === b.nodeId && a.subagentId === b.subagentId;
}

/** The agent a top-level entry belongs to (NO_OWNER breaks the block). */
function ownerOf(entry: TranscriptEntry): EntryOwner | typeof NO_OWNER {
  if (entry.type === 'tools') {
    return { nodeId: entry.nodeId, subagentId: entry.parentToolUseId };
  }
  if (entry.type === 'call-block') {
    return { nodeId: entry.callerNodeId, subagentId: null };
  }
  if (entry.type === 'subagent-block') {
    // The DELEGATING agent's, not the delegate's — the block belongs in the
    // turn where the delegation happened, which is what puts it beside the
    // tool row that launched it. Its own rows are already inside it.
    return { nodeId: entry.nodeId, subagentId: null };
  }
  if (entry.type === 'turn-block') {
    return { nodeId: entry.nodeId, subagentId: null };
  }
  if (isCardEntry(entry)) {
    return { nodeId: entry.nodeId, subagentId: entry.parentToolUseId };
  }
  const item = entry.item;
  if (item.kind === 'message' && item.role !== 'user') {
    return { nodeId: item.nodeId, subagentId: subagentIdOf(item) };
  }
  if (
    item.kind === 'reasoning' ||
    item.kind === 'error' ||
    item.kind === 'system'
  ) {
    return { nodeId: item.nodeId, subagentId: subagentIdOf(item) };
  }
  return NO_OWNER;
}

function entryId(entry: TranscriptEntry): string {
  return entry.type === 'item' ? entry.item.id : entry.id;
}

function entryCreatedAt(entry: TranscriptEntry): string {
  if (entry.type === 'item') {
    return entry.item.createdAt;
  }
  if (entry.type === 'tools') {
    return entry.pairs[0]?.call.createdAt ?? '';
  }
  return entry.createdAt;
}

/**
 * Fold consecutive same-agent entries into turn blocks. Applied by the
 * MAIN flow only (a communication card's inner content is already one
 * story); user messages, notes and approval cards break a block.
 */
export function buildTurnBlocks(
  entries: readonly TranscriptEntry[],
): TranscriptEntry[] {
  const out: TranscriptEntry[] = [];
  let open: TurnBlockEntry | null = null;
  let openOwner: EntryOwner | null = null;
  for (const entry of entries) {
    const owner = ownerOf(entry);
    if (owner === NO_OWNER) {
      open = null;
      openOwner = null;
      out.push(entry);
      continue;
    }
    if (open && openOwner && sameOwner(openOwner, owner)) {
      open.entries.push(entry);
      continue;
    }
    open = {
      type: 'turn-block',
      id: entryId(entry),
      createdAt: entryCreatedAt(entry),
      nodeId: owner.nodeId,
      subagentId: owner.subagentId,
      entries: [entry],
    };
    openOwner = owner;
    out.push(open);
  }
  return out;
}

/**
 * Kinds that stay in the MAIN flow even when a delegate produced them — the
 * same carve-out {@link UNCLAIMABLE_KINDS} makes for call blocks, and for the
 * same reason: a permission card folded into a collapsed block is a card
 * nobody can see they have to answer.
 */
const SUBAGENT_UNCLAIMABLE_KINDS = new Set<ChatItem['kind']>([
  'approval_request',
  'approval_verdict',
]);

/** The sub-agent an already-folded entry belongs to, or null for the main thread. */
function subagentOwnerOf(entry: TranscriptEntry): string | null {
  if (entry.type === 'tools') {
    return entry.parentToolUseId;
  }
  if (entry.type === 'item') {
    return SUBAGENT_UNCLAIMABLE_KINDS.has(entry.item.kind)
      ? null
      : subagentIdOf(entry.item);
  }
  if (entry.type === 'turn-block') {
    return entry.subagentId;
  }
  if (isCardEntry(entry)) {
    return entry.parentToolUseId;
  }
  // A call block is a NODE-to-node call and a sub-agent block is already an
  // enclosure — neither is a delegate's row needing one.
  return null;
}

/** The node an already-folded entry belongs to. */
function entryNodeId(entry: TranscriptEntry): string | null {
  if (entry.type === 'item') {
    return entry.item.nodeId;
  }
  if (entry.type === 'call-block') {
    return entry.callerNodeId;
  }
  return entry.nodeId;
}

/** The highest `seq` any row inside these entries carries (0 when empty). */
function maxSeqOf(list: readonly TranscriptEntry[]): number {
  let max = 0;
  for (const entry of list) {
    if (entry.type === 'item') {
      max = Math.max(max, entry.item.seq);
      continue;
    }
    if (entry.type === 'tools') {
      for (const pair of entry.pairs) {
        max = Math.max(max, pair.result?.seq ?? pair.call.seq);
      }
      continue;
    }
    if (isCardEntry(entry)) {
      max = Math.max(max, entry.seq);
      continue;
    }
    max = Math.max(max, maxSeqOf(entry.entries));
  }
  return max;
}

/**
 * When a run stopped, for the readers that must ask whether a piece of nested
 * work has spoken SINCE.
 *
 * Three states, not two, because a settle with no readable moment is not the
 * same as no settle. Folding them lost the FACT the moment was meant to refine:
 * an unparseable `updatedAt` silently re-enabled every spinner on a cancelled
 * run. `'unknown'` keeps the old, conservative reading — the run is over and
 * everything unreturned is stopped — while a number allows the exception.
 */
export type RunSettleAt = number | 'unknown' | null;

/** The newest `createdAt` (ms) any row inside these entries carries. */
function lastRowAtOf(list: readonly TranscriptEntry[]): number | null {
  let latest: number | null = null;
  const consider = (createdAt: string): void => {
    const at = Date.parse(createdAt);
    if (Number.isFinite(at) && (latest === null || at > latest)) {
      latest = at;
    }
  };
  for (const entry of list) {
    if (entry.type === 'item') {
      consider(entry.item.createdAt);
      continue;
    }
    if (entry.type === 'tools') {
      for (const pair of entry.pairs) {
        consider(pair.result?.createdAt ?? pair.call.createdAt);
      }
      continue;
    }
    if (isCardEntry(entry)) {
      consider(entry.createdAt);
      continue;
    }
    const nested = lastRowAtOf(entry.entries);
    if (nested !== null && (latest === null || nested > latest)) {
      latest = nested;
    }
  }
  return latest;
}

/**
 * Where a sub-agent's work stands — the ONE derivation, shared by the block
 * that renders it, the panel that lists it, and the run badge that reports it,
 * so the three can never disagree about whether a delegate is still working.
 *
 * `stopped` is the honest reading of a delegate whose turn ended without its
 * tool ever returning: it is not running (nothing more is coming) and it did
 * not complete (there is no result), and calling it either would be a claim
 * the transcript does not support.
 *
 * `runSettledAt` is WHEN the run settled — see {@link RunSettleAt}, and
 * {@link RunSettledContext} for why the moment and not merely the fact. It
 * decides the fate of a delegate NOTHING was ever declared about; a delegate
 * the CLI declared BACKGROUND is decided by what was declared, and the run's
 * own ending says nothing about it.
 */
/**
 * Whether a delegate has produced a row SINCE the run settled — "is it
 * audible", not "is it over".
 *
 * The two questions were one predicate until the daemon took over stating a
 * delegate's ending: silence past the settle used to mean the work was
 * unreportable and the block was downgraded for it. It no longer decides
 * anything about the WORK — a declared-open delegate is working until an
 * outcome says otherwise ({@link subagentBlockStatus}) — and what it decides
 * instead is the BADGE's wording: a delegate writing rows is the run `running`,
 * while one merely declared out is `held`, the same reading a background
 * command gets. A run that has not settled is all live, so everything is
 * audible; a settle nobody can place makes nothing audible, which is the
 * conservative half of {@link RunSettleAt} in its new job.
 */
export function subagentSpokeSince(
  block: SubagentBlockEntry,
  runSettledAt: RunSettleAt = null,
): boolean {
  if (runSettledAt === null) {
    return true;
  }
  if (runSettledAt === 'unknown') {
    return false;
  }
  return block.lastRowAt !== null && block.lastRowAt > runSettledAt;
}

export function subagentBlockStatus(
  block: SubagentBlockEntry,
  runSettledAt: RunSettleAt = null,
): 'running' | BackgroundOutcome {
  if (block.failed) {
    return 'failed';
  }
  // Two independent things end a delegate that never returned, and neither
  // subsumes the other — the same pairing `ToolGroupEntry.closed` documents.
  // `closed` is its own turn ending; the run settling is the whole run
  // stopping, which on the cancel path writes no turn-end item at all. Reading
  // `closed` alone left a cancelled run's delegate spinning "is working…"
  // forever.
  //
  // But a run settling only ends a delegate that has said nothing SINCE. The
  // reported defect: a delegate rendered `stopped` while its rows were still
  // landing, because the run row had settled and that alone painted every
  // unreturned block in the chat at once. Measured on the author's own
  // `geniro.db` — 1346 delegate rows arrived in run `f42bfe2d` after the item
  // that settled it. Whatever the row says, a delegate that has spoken since is
  // working: the transcript is the evidence and the status is the claim, so
  // where they disagree the evidence wins.
  const endedByRun =
    runSettledAt !== null &&
    (runSettledAt === 'unknown' ||
      block.lastRowAt === null ||
      block.lastRowAt <= runSettledAt);
  // The CLOSING half of that same channel, and reading only the opening half is
  // what made a long conversation sprout delegates that run forever. A block is
  // admitted by the delegate's OWN rows, while `returned` comes from the
  // launching call — so once a thread grows past `HISTORY_PAGE` and that call
  // falls out of the loaded window, the block arrives unnamed with `returned`
  // false and nothing below can end it: no launch to answer it, and no turn-end
  // after its last row while the agent is still working. Measured on the
  // reporter's own `geniro.db`, run `d64593d0` at the moment of the report: the
  // window held seq ~2570–3570, delegates `…27pzci` and `…L6pqka` were launched
  // at 2537/2551 — just below it — and the daemon's own `backgroundOpen: false`
  // for them sat at 3213 and 3364, INSIDE the window and discarded. The header
  // read 4 running delegates over a run whose hold tally said 2, which was the
  // report.
  //
  // WHAT the settle said, ahead of both readings below — and above `returned`
  // as well as above the settle itself, which is the half that is easy to miss:
  // a backgrounded delegate's launching call is answered within the second, so
  // `returned` is already true by the time the CLI reports how the work ended.
  if (block.backgroundOutcome !== null) {
    return block.backgroundOutcome;
  }
  // A settled unit is a delegate that REPORTED, so it completes rather than
  // stopping — the daemon writes this the moment the work comes back. Reached
  // only when the CLI named no outcome: "it is over" is all that was said, and
  // inventing a failure from silence would be the same error mirrored.
  if (block.backgroundOpen === false) {
    return 'completed';
  }
  // DECLARED STILL OUT, and nothing has said otherwise — so it is working, and
  // the run settling is not evidence against that.
  //
  // This used to read the turn's own ending: `endedByRun`/`closed` downgraded
  // such a delegate to `unknown` the instant its turn settled, which dropped it
  // out of every "what is working" surface — the composer shelf's `Sub-agents`
  // chip counts `running` alone. REPORTED against a cursor fan-out of nine
  // reviewers that vanished from the shelf the second the agent stopped
  // speaking, with all nine still at work. The turn ending is a fact about the
  // AGENT, never about the delegates it left running; the doc block below the
  // old arm said as much in its own last sentence and then acted on the turn
  // anyway.
  //
  // What makes the plain reading safe now is that the DAEMON always states the
  // ending. A cursor delegate lives inside the ACP process that launched it, so
  // when that session closes the delegate has demonstrably stopped, and
  // `ChatService.closeStrandedDelegates` writes `backgroundOutcome: 'stopped'`
  // for each one still out — at the close, and once more at boot for the closes
  // a SIGKILLed daemon never wrote. So "declared out" can no longer outlive the
  // work: it is answered above, by a stated outcome, rather than guessed at
  // here. That is also what retires the old `unknown` arm, and with it the
  // reported oscillation it was written for — a delegate's status no longer
  // moves when a turn opens or closes, because it no longer reads the turn.
  if (block.backgroundOpen === true) {
    return 'running';
  }
  // `returned` is the launching call coming back, which for a delegate the CLI
  // declared still out means nothing — hence the arm above, which takes those
  // before this one is reached.
  if (block.returned) {
    return 'completed';
  }
  return block.closed || endedByRun ? 'stopped' : 'running';
}

/**
 * What to call a delegate: its own description, else its type, else generic.
 *
 * One derivation, beside the status one and for the same reason — the block
 * header, the panel row and the dialog title must never disagree about a
 * delegate's name.
 */
export function subagentTitle(block: SubagentBlockEntry): string {
  return (
    block.label ??
    block.kind ??
    // NOT the bare word. Nothing here is guessing at a name — the point is that
    // an unnamed delegate is still a DISTINCT delegate, and a constant made
    // every one of them the same row: reported against a panel listing one
    // "Review: optimizations" over seven identical `sub-agent`s, where the only
    // question a reader has ("which spinner is which piece of work") had no
    // answer on screen and no way to get one.
    //
    // Both fields being null is ordinary rather than exotic. The launching call
    // is the only thing that ever carries a description, so any delegate whose
    // launch is outside the loaded window — a transcript opened mid-run, or a
    // backgrounded agent later RESUMED by a different call — arrives with
    // neither. The daemon's own `subagent_info` cannot cover for it: measured
    // across all 76 declarations on the user's ledger, every one carries
    // `label: null, kind: null` and speaks only about `backgroundOpen`.
    //
    // So the identity is what is shown, because it is what is known. Its tail
    // rather than the whole: `toolu_01AD1kjdJCqfkzGRTjn5M6mo` is twenty-odd
    // characters of prefix shared by every row, and it is the end that differs.
    `Sub-agent ${subagentRef(block.id)}`
  );
}

/**
 * Whether a delegate carries a name of its OWN, or only the identity
 * {@link subagentTitle} falls back to.
 *
 * Exists so a surface that prefixes the title with its category — the detail
 * dialog's `Sub-agent · …` — can drop the prefix rather than stutter it, which
 * is what produced the reported `Sub-agent · sub-agent`.
 */
export function subagentNamed(block: SubagentBlockEntry): boolean {
  return block.label !== null || block.kind !== null;
}

/** How many trailing characters of an id identify a delegate on screen. */
const SUBAGENT_REF_LENGTH = 6;

/** The short form of a delegate's id — its last few characters. */
function subagentRef(id: string): string {
  return id.length <= SUBAGENT_REF_LENGTH ? id : id.slice(-SUBAGENT_REF_LENGTH);
}

/**
 * How many tool invocations these entries hold, at any depth.
 *
 * One recursion, shared by both block kinds: a shallow count and a deep count
 * of the same "N tools" label meant different things per card.
 */
/**
 * The last thing the CALLEE said in a call block — what a COLLAPSED one shows
 * as its current state.
 *
 * ASKED FOR alongside the fold: "we always should see last message there, like
 * its current state". A shut card whose header names only `Manager → QA` says
 * that a call happened and nothing about where it has got to, which for a call
 * still running is the one thing a reader wants without opening it.
 *
 * The RESULT wins when there is one, because it lands after every row in
 * {@link CallBlockEntry.entries} and is the callee's final answer — the block
 * pulls it out of those entries for exactly that reason. Otherwise the newest
 * assistant message, found by walking backwards and descending into nested
 * entries the way {@link countTools} does, since a callee's rows are routinely
 * folded into a turn block.
 *
 * Null when the callee has not spoken yet, and never the caller's own ask: that
 * is what the block was ASKED, not where it has got to, and the header already
 * names both ends of the call. A block with no summary is one whose header's
 * spinner is the whole of the answer.
 */
export function callBlockSummary(block: CallBlockEntry): string | null {
  return block.result ?? lastSpokenIn(block.entries);
}

function lastSpokenIn(entries: readonly TranscriptEntry[]): string | null {
  for (let i = entries.length - 1; i >= 0; i -= 1) {
    const entry = entries[i]!;
    if (entry.type === 'item') {
      // `kind` alone, exactly as the block's own result extraction reads it: a
      // call block holds the CALLEE's rows, and the caller's ask is pulled out
      // to `message` before any of this — so there is no user turn in here for
      // a role check to exclude, and requiring one would drop every row on a
      // transport that leaves the column null.
      if (entry.item.kind === 'message') {
        const text = payloadString(entry.item.payload, 'text');
        if (text !== null && text.trim().length > 0) {
          return text;
        }
      }
      continue;
    }
    if (entry.type === 'tools' || isCardEntry(entry)) {
      continue;
    }
    const nested = lastSpokenIn(entry.entries);
    if (nested !== null) {
      return nested;
    }
  }
  return null;
}

/** What one call block's own turns have spent — the footer's two figures. */
export interface CallBlockUsage {
  /** Input + output, on the agent card's own rule — never the cache reads. */
  tokens: number | null;
  costUsd: number | null;
}

/**
 * What the callee has SPENT inside this block, summed from its own
 * `turn_complete` rows.
 *
 * ASKED FOR on the block footer beside the tool count: "for footer lets write
 * also tokens and money". The figures were in the block already — every
 * `turn_complete` carries them — and were readable only by opening that row.
 *
 * The token figure is INPUT + OUTPUT, the same reading the agents panel's own
 * spend line takes, so the two surfaces cannot state different numbers about
 * one agent's work. Cache reads are left out there for a measured reason and
 * the same one holds here.
 *
 * Null means UNMEASURED, never zero: a call whose turn has not ended yet has
 * reported nothing — there is no live token or cost channel on either CLI, so
 * the figures appear when the turn lands — and cursor-agent reports no cost at
 * all, which is why the two halves are independent.
 */
export function callBlockUsage(block: CallBlockEntry): CallBlockUsage {
  const usage: CallBlockUsage = { tokens: null, costUsd: null };
  addCallUsage(block.entries, usage);
  return usage;
}

function addCallUsage(
  entries: readonly TranscriptEntry[],
  into: CallBlockUsage,
): void {
  for (const entry of entries) {
    if (entry.type === 'item') {
      if (entry.item.kind !== 'turn_complete') {
        continue;
      }
      const usage = recordOf(recordOf(entry.item.payload)?.usage);
      if (usage === undefined) {
        continue;
      }
      const tokens = addFigure(
        addFigure(into.tokens, usage.inputTokens),
        usage.outputTokens,
      );
      into.tokens = tokens;
      into.costUsd = addFigure(into.costUsd, usage.costUsd);
      continue;
    }
    if (entry.type === 'tools' || isCardEntry(entry)) {
      continue;
    }
    addCallUsage(entry.entries, into);
  }
}

function recordOf(value: unknown): Record<string, unknown> | undefined {
  return typeof value === 'object' && value !== null
    ? (value as Record<string, unknown>)
    : undefined;
}

/** Add a reported figure to a running total, where null means UNMEASURED. */
function addFigure(total: number | null, next: unknown): number | null {
  if (typeof next !== 'number' || !Number.isFinite(next) || next < 0) {
    return total;
  }
  return (total ?? 0) + next;
}

/**
 * The callee's task list as it stands INSIDE this call block — what the shut
 * card's own tasks chip lists.
 *
 * The LAST card wins, on `TaskListCard`'s own rule: a list is announced many
 * times over a turn and every card but the newest is a step on the way there.
 * Empty when the callee keeps none, which is what withholds the chip.
 */
export function callBlockTasks(block: CallBlockEntry): AgentTaskRow[] {
  return lastTaskListIn(block.entries) ?? [];
}

function lastTaskListIn(
  entries: readonly TranscriptEntry[],
): AgentTaskRow[] | null {
  for (let i = entries.length - 1; i >= 0; i -= 1) {
    const entry = entries[i]!;
    if (entry.type === 'task-list') {
      return entry.tasks;
    }
    if (entry.type === 'item' || entry.type === 'tools' || isCardEntry(entry)) {
      continue;
    }
    const nested = lastTaskListIn(entry.entries);
    if (nested !== null) {
      return nested;
    }
  }
  return null;
}

export function countTools(entries: readonly TranscriptEntry[]): number {
  return entries.reduce((sum, entry) => {
    if (entry.type === 'tools') {
      return sum + entry.pairs.length;
    }
    if (entry.type === 'item' || isCardEntry(entry)) {
      // None of these cards holds tool invocations: the calls that produced
      // them are hidden BY them, and counting those would report work with no
      // row to open.
      return sum;
    }
    return sum + countTools(entry.entries);
  }, 0);
}

/** Every sub-agent block in a folded transcript, at any depth. */
export function collectSubagentBlocks(
  entries: readonly TranscriptEntry[],
): SubagentBlockEntry[] {
  const out: SubagentBlockEntry[] = [];
  const walk = (list: readonly TranscriptEntry[]): void => {
    for (const entry of list) {
      if (entry.type === 'subagent-block') {
        out.push(entry);
        continue;
      }
      if (entry.type === 'turn-block' || entry.type === 'call-block') {
        walk(entry.entries);
      }
    }
  };
  walk(entries);
  return out;
}

