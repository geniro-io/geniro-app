/** A run of tool calls collapsed into one expandable transcript row. */
export interface ToolGroupEntry {
  type: 'tools';
  /** Stable identity for React keys and expansion state: the first call's id. */
  id: string;
  nodeId: string | null;
  /**
   * The sub-agent whose work this is — the id of the tool call that started
   * it — or null for the agent's own thread.
   *
   * A group never mixes the two. A CLI running sub-agents emits their tool
   * calls on the SAME stream as its own, so folding by node alone produced one
   * interleaved sequence in which each thread's chatter closed the other's
   * group: several sub-agents working at once turned into a long flat run of
   * single-call rows with nothing saying where any of them came from.
   */
  parentToolUseId: string | null;
  /**
   * A turn ended after this group — so whatever result was coming has come.
   *
   * An unpaired call means "still running" only while its turn is open. Once
   * the turn is over, a missing `tool_result` is a result that never arrived,
   * and a spinner over it claims work that stopped long ago. (A result that
   * lands between turns IS persisted now, along with its call — but it takes a
   * fresh seq, so it appears later in the transcript rather than inside this
   * closed group.) That is the reported bug: a chat whose
   * header read `completed` with a sub-agent row working forever.
   *
   * Per-GROUP rather than per-run, and that distinction is the point: the run
   * reads `running` again the moment the user sends another message, so a
   * run-level flag let the same stale group start spinning through every
   * later turn.
   */
  closed: boolean;
  pairs: ToolPair[];
  /**
   * This entry is ONE file change lifted out of a run of tool calls — draw the
   * row alone, with no summary line of its own.
   *
   * See {@link pullFileChangesOutOfGroups}. Absent on every group the fold
   * produces, so a transcript with the setting off is byte-identical to what it
   * was.
   */
  standalone?: boolean;
}

