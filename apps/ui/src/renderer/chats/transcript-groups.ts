/**
 * Read one string field off a tool call's `input` object.
 *
 * TWIN PARSER: the keys read through this — `subagent_type`, `description`,
 * `prompt`, `model` — are claude's own Task-tool argument schema, which reaches the
 * renderer inside a `tool_call` payload's `input` and so carries no generated
 * type (`apps/daemon/src/v1/agents/utils/event-to-item.ts` forwards
 * `event.input` verbatim; the shape originates in
 * `apps/daemon/src/v1/agents/adapters/claude/`). If that CLI renames one of
 * them, it must be renamed here, and vice versa — nothing type-checks the two
 * against each other. Every key is read defensively, so a rename degrades to
 * an unlabelled block rather than a crash.
 */
function inputString(call: ChatItem | undefined, key: string): string | null {
  const input = (call?.payload as { input?: unknown } | null)?.input;
  if (typeof input !== 'object' || input === null) {
    return null;
  }
  const value = (input as Record<string, unknown>)[key];
  return typeof value === 'string' && value !== '' ? value : null;
}

/**
 * What model the LAUNCHING call asked this delegate to run on — the stand-in
 * until its CLI says which one actually did.
 *
 * The declaration OUTRANKS this, which inverts the rule its three neighbours
 * follow (`kind`, `label` and `prompt` all prefer the call). The two sources
 * are not the same fact here: the call carries the caller's own word for a
 * model — an ALIAS like `sonnet` — while the declaration carries what the CLI
 * resolved it to (`claude-sonnet-5`), which is the one a reader can look up.
 * That declaration only arrives when the launching call RETURNS, so a delegate
 * is otherwise unattributed for the whole time it runs, which is precisely
 * when a column of a dozen of them is being read.
 *
 * `inherit` is dropped rather than shown: it is the schema's way of naming no
 * model at all, and printing it would answer "which model" with a word about
 * where the answer comes from.
 */
function requestedModel(call: ChatItem | undefined): string | null {
  const model = inputString(call, 'model');
  return model === 'inherit' ? null : model;
}

/**
 * Fold every background sub-agent's rows into one {@link SubagentBlockEntry},
 * placed where that delegate's FIRST row appeared — which is directly after
 * the tool call that launched it.
 *
 * Runs BETWEEN {@link groupTranscript} and {@link buildTurnBlocks}: the former
 * has already split each delegate's tool runs onto their own groups, and the
 * latter must see the finished block as a single entry of the DELEGATING
 * agent's turn rather than fold the delegate's loose rows into it.
 *
 * The launching `tool_call` supplies the block's identity and its request; its
 * paired `tool_result` supplies the result and is the only "the delegate
 * finished" signal on the wire. Rows whose launcher is missing entirely (a
 * transcript replayed from mid-run, a `Task` call the fold dropped) still get
 * a block — an unlabelled enclosure beats spilling a delegate's work back into
 * the main conversation, which is the defect this whole fold exists to fix.
 *
 * A launch is recognised TWO ways, because CLIs disclose a delegation
 * differently and neither reading covers the other:
 * - by the tool's NAME ({@link AGENT_TOOLS}), whose own arguments carry the
 *   description, the prompt and the type — claude's `Task`;
 * - by a `subagent_info` row the DAEMON wrote, which names the launching tool
 *   call explicitly — for a CLI whose delegation frame carries no usable name
 *   and whose brief arrives later on its own channel (cursor over ACP, where the
 *   call is titled `Task: Subagent task` and its input holds only `_toolName`).
 *
 * The second is why nothing here needs a second CLI's tool-name spellings: which
 * calls launched delegates is the adapter layer's fact, and it is stated on the
 * wire rather than pattern-matched at this end.
 *
 * One level deep, like the other blocks: a claude sub-agent is a leaf and
 * cannot itself delegate, so no block nests inside another.
 */
export function buildSubagentBlocks(
  entries: readonly TranscriptEntry[],
  items: readonly ChatItem[],
): TranscriptEntry[] {
  // Merged rather than taken: a CLI announces the same delegate once at launch
  // (anchor only) and again with its brief, so the last non-null field wins.
  const declarations = new Map<string, SubagentDeclaration>();
  for (const item of items) {
    if (item.kind !== 'subagent_info') {
      continue;
    }
    const declaration = readSubagentDeclaration(item);
    if (declaration === null) {
      continue;
    }
    const previous = declarations.get(declaration.id);
    declarations.set(
      declaration.id,
      previous === undefined
        ? declaration
        : mergeSubagentDeclarations(previous, declaration),
    );
  }
  const launches = new Map<string, SubagentLaunch>();
  /**
   * Of those launches, the ones whose tool is a DELEGATION by name.
   *
   * The two admission routes are not equally strong and only this one is
   * self-evidencing. A call admitted by its name launched a delegate and its
   * reply is that delegate's report; a call admitted only because the daemon
   * declared background work against it may be anything the CLI ran an agent
   * FOR — measured on the user's own ledger, a `SendMessage` resuming an
   * already-running agent, whose reply is the receipt `{"success":true,
   * "message":"Resuming agent a3249b7"…}` and whose block therefore had no
   * name, no prompt, no conversation, and that receipt where its result
   * should be.
   */
  const byDelegationTool = new Set<string>();
  for (const item of items) {
    if (item.kind !== 'tool_call') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    const name = payloadString(item.payload, 'name') ?? '';
    if (id && (AGENT_TOOLS.has(name) || declarations.has(id))) {
      launches.set(id, { call: item, result: null });
      if (AGENT_TOOLS.has(name)) {
        byDelegationTool.add(id);
      }
    }
  }
  for (const item of items) {
    if (item.kind !== 'tool_result') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    const launch = id ? launches.get(id) : undefined;
    if (launch) {
      launch.result = item;
    }
  }

  const out: TranscriptEntry[] = [];
  const blocks = new Map<string, SubagentBlockEntry>();
  /**
   * The `seq` the delegation was ISSUED at, per block.
   *
   * Only load-bearing while a block has no rows of its own: `maxSeqOf([])` is
   * 0, so without an anchor ANY earlier turn-end of the delegating node reads
   * as "this delegate's turn is over" and a Task call the CLI has not yet
   * produced a single row for renders `stopped` the instant it appears.
   */
  const anchorSeq = new Map<string, number>();
  /**
   * The `seq` at which each block's launching call was ANSWERED, for the blocks
   * that have an answer. Kept apart from {@link anchorSeq}, which coalesces to
   * the call when there is no result — this must stay undefined there, since
   * "never answered" and "answered at the launch" are different facts and only
   * the second can make a result the delegate's own.
   */
  const answeredSeq = new Map<string, number>();
  const openBlock = (
    subagentId: string,
    /** Where to read identity from when the launching call is missing. */
    fallback: TranscriptEntry,
  ): SubagentBlockEntry => {
    const existing = blocks.get(subagentId);
    if (existing) {
      return existing;
    }
    const launch = launches.get(subagentId);
    const payload = launch?.result?.payload as {
      result?: unknown;
      isError?: unknown;
    } | null;
    const body = payload?.result;
    // What the DAEMON said about this delegate, when its CLI announces one apart
    // from the launching call. Read as a FALLBACK per field rather than as an
    // alternative source: claude's Task arguments are richer and already carry
    // three of these, so the declaration fills only what the call did not say.
    const declared = declarations.get(subagentId) ?? null;
    const block: SubagentBlockEntry = {
      type: 'subagent-block',
      id: subagentId,
      // A ternary, not `??`: every 1:1 chat row carries `nodeId: null`
      // legitimately, so coalescing would fall through to the first row's
      // node whenever the launcher IS the chat agent.
      createdAt: launch ? launch.call.createdAt : entryCreatedAt(fallback),
      nodeId: launch ? launch.call.nodeId : entryNodeId(fallback),
      kind:
        inputString(launch?.call, 'subagent_type') ?? declared?.kind ?? null,
      label:
        inputString(launch?.call, 'description') ?? declared?.label ?? null,
      prompt: inputString(launch?.call, 'prompt') ?? declared?.prompt ?? null,
      // The one field where the DECLARATION wins — see {@link requestedModel}.
      model: declared?.model ?? requestedModel(launch?.call),
      durationMs: declared?.durationMs ?? null,
      tokens: declared?.tokens ?? null,
      toolUses: declared?.toolUses ?? null,
      costUsd: declared?.costUsd ?? null,
      stepsUnavailableReason: declared?.stepsUnavailableReason ?? null,
      backgroundOpen: declared?.backgroundOpen ?? null,
      backgroundOutcome: declared?.backgroundOutcome ?? null,
      returned: launch?.result != null,
      failed: payload?.isError === true,
      // Only stringify a body that EXISTS. `toolResultText(null)` returns
      // the four characters `null`, which the result panel then framed as
      // the delegate's own answer.
      result: body == null ? null : toolResultText(body),
      // Decided in the pass below, once the delegate's rows are known.
      resultIsOwn: false,
      closed: false,
      lastRowAt: null,
      entries: [],
    };
    if (launch) {
      anchorSeq.set(subagentId, launch.result?.seq ?? launch.call.seq);
      // Only a call that was a DELEGATION can have been answered WITH a
      // delegate's report — see {@link byDelegationTool}. A declaration that
      // describes the delegate is the other CLI's way of saying the same thing
      // (cursor's ACP frame carries no usable tool name, so its brief is the
      // evidence), while a declaration that describes nothing is only the
      // daemon noticing background work against some call.
      const describes =
        declared !== null &&
        (declared.label !== null ||
          declared.kind !== null ||
          declared.prompt !== null);
      if (launch.result && (byDelegationTool.has(subagentId) || describes)) {
        answeredSeq.set(subagentId, launch.result.seq);
      }
    }
    blocks.set(subagentId, block);
    out.push(block);
    return block;
  };

  for (const entry of entries) {
    const subagentId = subagentOwnerOf(entry);
    if (subagentId !== null) {
      openBlock(subagentId, entry).entries.push(entry);
      continue;
    }
    // A MAIN-thread tool group is where the delegations were issued. The
    // launching `Task` pair is pulled OUT of it and rendered as the block it
    // opened: the block already says a delegate was started, who it is and
    // how it ended, so leaving the pair in the group produced a second,
    // poorer telling of it directly above ("Delegated to 5 subagents").
    if (entry.type === 'tools') {
      const kept: ToolPair[] = [];
      const launched: string[] = [];
      for (const pair of entry.pairs) {
        const id = payloadString(pair.call.payload, 'id');
        if (id !== null && launches.has(id)) {
          launched.push(id);
          continue;
        }
        kept.push(pair);
      }
      if (kept.length > 0) {
        // `id` is carried over UNCHANGED even when the pair it names was the
        // one just stripped. It is a React key, and re-deriving it from the
        // first surviving pair would change it the moment a delegation is
        // followed by real work in the same group — remounting the row and
        // discarding whatever the reader had expanded.
        out.push({ ...entry, pairs: kept });
      }
      // AFTER the group, so a turn that both worked and delegated still reads
      // in the order it happened.
      for (const id of launched) {
        openBlock(id, entry);
      }
      continue;
    }
    out.push(entry);
  }
  if (blocks.size === 0) {
    return out;
  }

  const turnEnds = items.filter((item) => TURN_END_KINDS.has(item.kind));
  for (const block of blocks.values()) {
    // Scoped to the delegating NODE, not the whole run. Under graph fan-out
    // several nodes settle independently, so an unscoped read let node A's
    // `turn_complete` mark node B's still-working delegate `stopped` — the
    // failure showing up exactly when several agents run at once, which is
    // when this feature matters most.
    const lastSeq = Math.max(
      maxSeqOf(block.entries),
      anchorSeq.get(block.id) ?? 0,
    );
    block.closed = turnEnds.some(
      (item) => item.nodeId === block.nodeId && item.seq > lastSeq,
    );
    // Whose answer the result is — see {@link SubagentBlockEntry.resultIsOwn}.
    // `lastSeq` already folds in `anchorSeq`, which for an answered block IS
    // that answer's seq, so `lastSeq > answered` says exactly "a row of this
    // delegate's arrived afterwards" — and a delegate that spoke after its call
    // was answered was plainly not reporting through it.
    //
    // The open-background test is what covers the same delegate BEFORE it has
    // spoken at all: an acknowledgement and no rows leaves the seqs equal, and
    // an open background unit is the CLI saying the work is still to come.
    const answered = answeredSeq.get(block.id);
    block.resultIsOwn =
      block.result !== null &&
      answered !== undefined &&
      block.backgroundOpen !== true &&
      lastSeq <= answered;
    // Taken BEFORE the fold, while the rows are still flat. Falls back to the
    // LAUNCH when the delegate has produced nothing yet: a delegation issued
    // after the run settled is itself evidence of life, and reading null there
    // would call a delegate that started one second ago `stopped`.
    const launchedAt = Date.parse(block.createdAt);
    block.lastRowAt =
      lastRowAtOf(block.entries) ??
      (Number.isFinite(launchedAt) ? launchedAt : null);
    // Folded so the nested thread reads exactly like the main flow does.
    block.entries = buildTurnBlocks(block.entries);
  }
  return out;
}

/**
 * Every dynamic workflow this transcript records, in launch order.
 *
 * The ONE reading, and it is exported because there are now three views of it:
 * the transcript's card, the chip above the composer while one is running, and
 * the panel's list. Folded twice they would disagree about how many agents are
 * still out — which is exactly the kind of drift `isCardEntry` exists to
 * prevent one entry-kind lower down.
 *
 * A launch is recognised ONE way — by a `workflow_info` row naming the call —
 * and never by the tool's NAME. Which calls launched a workflow is the adapter
 * layer's fact and it is stated on the wire, so nothing here has to learn that
 * claude spells its orchestrator `Workflow`; a second CLI that grows one is a
 * daemon change alone. That is the stronger of the two admission routes
 * {@link buildSubagentBlocks} documents, and here it is the only one available:
 * a workflow emits no rows of its own, so there is no second reading to fall
 * back on.
 */
export function workflowCardsOf(items: readonly ChatItem[]): WorkflowEntry[] {
  // Merged rather than taken: a workflow announces itself at launch (the name,
  // nothing else) and again on every roster change, so the last non-null field
  // wins — and the roster itself is taken WHOLESALE, per
  // `mergeWorkflowDeclarations`.
  const declarations = new Map<string, WorkflowDeclaration>();
  // The FIRST row about each workflow, which is where a card that has lost its
  // launching call takes its place in the conversation from.
  const anchors = new Map<string, ChatItem>();
  /** The newest row about each workflow — see {@link WorkflowEntry.lastRowAt}. */
  const lastRowAt = new Map<string, number>();
  /** Its `seq`, which is what decides whether a result is the workflow's own. */
  const lastRowSeq = new Map<string, number>();
  for (const item of items) {
    if (item.kind !== 'workflow_info') {
      continue;
    }
    const declaration = readWorkflowDeclaration(item);
    if (declaration === null) {
      continue;
    }
    const previous = declarations.get(declaration.id);
    declarations.set(
      declaration.id,
      previous === undefined
        ? declaration
        : mergeWorkflowDeclarations(previous, declaration),
    );
    if (!anchors.has(declaration.id)) {
      anchors.set(declaration.id, item);
    }
    const at = Date.parse(item.createdAt);
    if (Number.isFinite(at) && at > (lastRowAt.get(declaration.id) ?? 0)) {
      lastRowAt.set(declaration.id, at);
    }
    lastRowSeq.set(
      declaration.id,
      Math.max(lastRowSeq.get(declaration.id) ?? 0, item.seq),
    );
  }
  const launches = new Map<string, SubagentLaunch>();
  for (const item of items) {
    if (item.kind !== 'tool_call') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    if (id !== null && declarations.has(id)) {
      launches.set(id, { call: item, result: null });
    }
  }
  for (const item of items) {
    if (item.kind !== 'tool_result') {
      continue;
    }
    const id = payloadString(item.payload, 'id');
    const launch = id ? launches.get(id) : undefined;
    if (launch) {
      launch.result = item;
    }
  }

  const cardFor = (
    id: string,
    workflow: WorkflowDeclaration,
  ): WorkflowEntry => {
    const launch = launches.get(id);
    const payload = launch?.result?.payload as {
      result?: unknown;
      isError?: unknown;
    } | null;
    const body = payload?.result;
    // The launching call when there is one, else the first row the daemon wrote
    // about this workflow — which is a row of the same turn, so the card lands
    // where the work happened either way.
    const anchor = launch?.call ?? anchors.get(id) ?? null;
    return {
      type: 'workflow',
      id,
      createdAt: anchor?.createdAt ?? '',
      seq: anchor?.seq ?? 0,
      nodeId: anchor?.nodeId ?? null,
      // The launching call's own thread: a workflow started by a delegate is
      // the delegate's, and its card belongs inside that block's flow.
      parentToolUseId: anchor === null ? null : subagentIdOf(anchor),
      workflow,
      script: inputString(launch?.call, 'script'),
      returned: launch?.result != null,
      failed: payload?.isError === true,
      // Only stringify a body that EXISTS. `toolResultText(null)` returns the
      // four characters `null`, which the result panel would then frame as the
      // workflow's own answer.
      result: body == null ? null : toolResultText(body),
      // A roster that arrived AFTER the answer says the workflow was plainly
      // not reporting through it — see {@link WorkflowEntry.resultIsOwn}.
      resultIsOwn:
        launch?.result != null &&
        (lastRowSeq.get(id) ?? 0) <= launch.result.seq,
      lastRowAt: lastRowAt.get(id) ?? null,
    };
  };

  return [...declarations].map(([id, workflow]) => cardFor(id, workflow));
}

/**
 * Replace every dynamic-workflow tool call with the {@link WorkflowEntry} card
 * describing what it actually did.
 *
 * The PLACEMENT half of {@link workflowCardsOf}, which is where the reading
 * itself lives. Runs AFTER {@link buildSubagentBlocks} and before
 * {@link buildTurnBlocks}, for the same reason that one does: the groups are
 * already folded, and the turn fold must see one finished card rather than a
 * tool pair plus a run of invisible rows.
 *
 * The launching pair is pulled OUT of its tool group, exactly as a `Task` pair
 * is: the card already says a workflow ran, what it spawned and how it ended,
 * so leaving the pair in the group would print a poorer telling of it directly
 * above ("Used 1 tool").
 */
export function buildWorkflowCards(
  entries: readonly TranscriptEntry[],
  items: readonly ChatItem[],
): TranscriptEntry[] {
  const cards = new Map(
    workflowCardsOf(items).map((card) => [card.id, card] as const),
  );
  if (cards.size === 0) {
    return [...entries];
  }
  const out: TranscriptEntry[] = [];
  const placed = new Set<string>();
  for (const entry of entries) {
    if (entry.type === 'tools') {
      const kept: ToolPair[] = [];
      const launched: string[] = [];
      for (const pair of entry.pairs) {
        const id = payloadString(pair.call.payload, 'id');
        if (id !== null && cards.has(id)) {
          launched.push(id);
          continue;
        }
        kept.push(pair);
      }
      if (kept.length > 0) {
        // `id` carried over UNCHANGED even when the pair it names was the one
        // stripped — it is a React key, and re-deriving it would remount the
        // row and discard whatever the reader had expanded.
        out.push({ ...entry, pairs: kept });
      }
      // AFTER the group, so a turn that both worked and launched a workflow
      // still reads in the order it happened.
      for (const id of launched) {
        const card = cards.get(id);
        if (card === undefined) {
          continue;
        }
        placed.add(id);
        out.push(card);
      }
      continue;
    }
    out.push(entry);
  }
  // A workflow whose launching call never reached this fold still gets a card:
  // the daemon's rows are the evidence it ran, and a transcript replayed from
  // mid-run — or one whose tool pair the group fold consumed — would otherwise
  // drop the most expensive thing in the conversation entirely.
  for (const card of cards.values()) {
    if (!placed.has(card.id)) {
      out.push(card);
    }
  }
  return out;
}

/**
 * Caller-attributed rows of the SAME call (the parked question, its answer,
 * the settle envelope) — everything about a sub-agent call belongs inside
 * its block, so these claim into the bucket by callId alone (their nodeId
 * is the CALLER's).
 */
const CALL_FOLLOWUP_KINDS = new Set<ChatItem['kind']>([
  'call_question',
  'call_answer',
  'call_result',
]);

/**
 * Kinds that must stay in the MAIN flow even when callId-tagged: the block
 * anchor itself, the broker's pickup note (renders as nothing), and
 * approval requests/verdicts — a pending card hidden inside a block's flow
 * could never be answered.
 */
const UNCLAIMABLE_KINDS = new Set<ChatItem['kind']>([
  'call_started',
  'await_collected',
  'approval_request',
  'approval_verdict',
]);

const BLOCK_STATUSES = new Set(['running', 'completed', 'failed', 'cancelled']);

/** A pending agent-call block under assembly (one per call_started). */
interface CallShell {
  started: ChatItem;
  calleeNodeId: string | null;
  bucket: ChatItem[];
}

/**
 * Fold a transcript into render entries: agent calls collapse into nested
 * call blocks, tool calls collapse into per-node groups (Claude/Cursor-style
 * "used N tools" rows), everything else stays a plain item entry.
 *
 * Call-block rules:
 * - a `call_started` opens a block; every item TAGGED with that callId and
 *   attributed to the callee node folds inside it (its status items drive
 *   the block's live status instead of rendering as rows — merging the old
 *   redundant "call → B" + "B started" pair into one block header).
 * - the caller-attributed rows about the call (question/answer/settle)
 *   claim in too — the WHOLE exchange lives in the block; only the anchor
 *   and approval requests/verdicts stay out (see {@link UNCLAIMABLE_KINDS}),
 *   and untagged items (legacy transcripts) keep the flat flow.
 *
 * Tool-grouping rules:
 * - a `tool_call` joins its node's OPEN group (or opens one); any other
 *   rendered kind from the SAME node closes that node's group — another
 *   node's interleaved rows do not, so a parallel branch doesn't shred the
 *   caller's tool run into fragments.
 * - a `tool_result` attaches to its call by payload id wherever that call
 *   lives (the pairing survives a closed group); an orphan result (no known
 *   call) stays a plain item entry.
 * - `mcp__geniro__*` tool calls and their results are dropped entirely (see
 *   {@link GENIRO_TOOL_PREFIX}).
 */
export function groupTranscript(items: readonly ChatItem[]): TranscriptEntry[] {
  // Pass 1 — collect the call shells and claim each callee sub-turn's items.
  const shells = new Map<string, CallShell>();
  for (const item of items) {
    if (item.kind !== 'call_started') {
      continue;
    }
    const callId = payloadString(item.payload, 'callId');
    if (callId && !shells.has(callId)) {
      shells.set(callId, {
        started: item,
        calleeNodeId: payloadString(item.payload, 'calleeNodeId'),
        bucket: [],
      });
    }
  }
  const claimed = new Set<string>();
  if (shells.size > 0) {
    for (const item of items) {
      if (UNCLAIMABLE_KINDS.has(item.kind)) {
        continue;
      }
      const callId = payloadString(item.payload, 'callId');
      const shell = callId ? shells.get(callId) : undefined;
      if (!shell) {
        continue;
      }
      // The callee's own streamed items claim by callId + callee nodeId; the
      // caller-attributed rows ABOUT this call (question/answer/settle)
      // claim by callId alone — the whole exchange lives in the block.
      if (
        CALL_FOLLOWUP_KINDS.has(item.kind) ||
        (item.nodeId !== null && item.nodeId === shell.calleeNodeId)
      ) {
        shell.bucket.push(item);
        claimed.add(item.id);
      }
    }
  }

  // Pass 2 — which tool calls a task announcement SPEAKS FOR.
  //
  // The list is rendered INSTEAD of the row that produced it, not beside it,
  // because that row is the whole complaint: claude's `TaskUpdate` collapses to
  // `TaskUpdate` in a tool group, and cursor's discloses no arguments at all
  // (`rawInput:{_toolName:"updateTodos"}`), so the reader learns that a tool
  // ran and nothing about the work. Both halves of the pair go, which is why
  // this has to be known BEFORE the fold: the result arrives later in the
  // stream than the announcement that claims it.
  const taskToolCallIds = new Set<string>();
  for (const item of items) {
    if (item.kind !== 'task_list') {
      continue;
    }
    const toolCallId = readTaskAnnouncement(item)?.toolCallId;
    if (toolCallId) {
      taskToolCallIds.add(toolCallId);
    }
  }

  // Pass 3 — the main fold over everything not claimed into a block.
  const entries: TranscriptEntry[] = [];
  const hiddenCallIds = new Set<string>();
  // The running fold per thread, and the card currently open for it. Kept per
  // thread because both CLIs number tasks from 1, so a delegate's task `1` and
  // the main agent's are different tasks.
  const taskLists = new Map<string | null, TaskAnnouncement[]>();
  const openTaskCards = new Map<string, TaskListEntry>();
  const pairsByCallId = new Map<string, ToolPair>();
  // Keyed by node AND by originating thread, so a sub-agent's calls collapse
  // into their own row and neither thread's narrative closes the other's group.
  const openGroups = new Map<string, ToolGroupEntry>();

  for (const item of items) {
    if (claimed.has(item.id)) {
      continue;
    }
    if (item.kind === 'call_started') {
      const callId = payloadString(item.payload, 'callId');
      const shell = callId ? shells.get(callId) : undefined;
      openGroups.delete(groupKey(item));
      if (
        callId &&
        shell &&
        shell.started.id === item.id &&
        shell.bucket.length > 0
      ) {
        entries.push(buildCallBlock(callId, shell));
      } else {
        // No tagged sub-turn yet (a legacy transcript, a call rejected
        // before any turn started, or the spawn racing this render) — keep
        // the flat call row; it upgrades to a block once tagged items land.
        entries.push({ type: 'item', item });
      }
      continue;
    }
    if (
      item.kind === 'shell_open' ||
      item.kind === 'shell_info' ||
      item.kind === 'workflow_info'
    ) {
      // Bookkeeping, not narrative: the first two are the open and the close of
      // a detached command (`shell-activity.ts` is their only reader), the third
      // describes a running workflow and is folded into that workflow's own card
      // by `buildWorkflowCards`. None renders anything here. Skipped OUTRIGHT
      // rather than left to the fall-through below, which treats any other kind
      // as the node having "said something" and closes its open tool group — so
      // a burst of them would chop one turn's tools into a run of one-call rows
      // for rows nobody can see. A workflow announces itself once per roster
      // change, dozens of times over its run, so it is precisely such a burst.
      continue;
    }
    if (item.kind === 'tool_call') {
      const name = payloadString(item.payload, 'name') ?? '';
      const callId = payloadString(item.payload, 'id');
      if (
        isGeniroToolName(name, item.runId) ||
        (callId !== null && taskToolCallIds.has(callId))
      ) {
        if (callId) {
          hiddenCallIds.add(callId);
        }
        continue;
      }
      const pair: ToolPair = { call: item, result: null };
      if (callId) {
        pairsByCallId.set(callId, pair);
      }
      const key = groupKey(item);
      // A VISIBLE tool call closes this thread's open task card, so the next
      // announcement starts a fresh one. Without it a card floated above the
      // work done after it while showing the list as it stood afterwards. A
      // HIDDEN call never reaches here, which is what keeps a burst of task
      // tools — every one of them hidden — collapsed into the single card.
      openTaskCards.delete(key);
      const open = openGroups.get(key);
      if (open) {
        open.pairs.push(pair);
      } else {
        const group: ToolGroupEntry = {
          type: 'tools',
          id: item.id,
          nodeId: item.nodeId,
          parentToolUseId: subagentIdOf(item),
          // Filled by the closing sweep below, once the whole stream is known.
          closed: false,
          pairs: [pair],
        };
        openGroups.set(key, group);
        entries.push(group);
      }
      continue;
    }
    if (item.kind === 'tool_result') {
      const callId = payloadString(item.payload, 'id');
      if (callId && hiddenCallIds.has(callId)) {
        continue;
      }
      const pair = callId ? pairsByCallId.get(callId) : undefined;
      if (pair) {
        pair.result = item;
        continue;
      }
      // An ORPHAN — its `tool_call` is not in this window — and if that call was
      // one of GENIRO'S OWN, hiding it is still owed. `hiddenCallIds` is filled
      // as the calls go past, so it can only ever know about calls the window
      // holds: measured on a real run, the `await_agent` sat at seq 899 and its
      // result at 1099, with the window starting near 926, so the result
      // arrived with nothing to suppress it and the raw envelope was printed
      // into the transcript under a `RESULT` caption. REPORTED as "I see raw
      // tool result", over `{"status":"ok","result":{"call_id":"call-3",…}}`.
      //
      // The result row cannot be matched by NAME — the CLI writes `name: null`
      // on it (verified on that row) — so the envelope itself is the only
      // signal present, and it is geniro's OWN shape rather than any CLI's
      // prose: see {@link isCallEnvelopeResult}.
      if (isCallEnvelopeResult(item.payload)) {
        continue;
      }
      entries.push({ type: 'item', item });
      continue;
    }
    if (item.kind === 'report_findings') {
      const report = readFindingsReport(item);
      if (report === null) {
        continue;
      }
      // A card is a narrative row of its own, so it closes BOTH of the thread's
      // open runs — the tool group and the task card — exactly as every other
      // rendered row does. Leaving the task card open lets a later announcement
      // rewrite the card ABOVE this one in place, so it ends up showing state
      // from after the findings it sits over.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'findings',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        nodeId: item.nodeId,
        parentToolUseId: subagentIdOf(item),
        report,
      });
      continue;
    }
    if (item.kind === 'show_chart') {
      const chart = readChart(item);
      if (chart === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'chart',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        nodeId: item.nodeId,
        parentToolUseId: subagentIdOf(item),
        chart,
      });
      continue;
    }
    if (item.kind === 'show_metrics') {
      const metrics = readMetrics(item);
      if (metrics === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'metrics',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        nodeId: item.nodeId,
        parentToolUseId: subagentIdOf(item),
        metrics,
      });
      continue;
    }
    if (item.kind === 'show_comparison') {
      const comparison = readComparison(item);
      if (comparison === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'comparison',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        nodeId: item.nodeId,
        parentToolUseId: subagentIdOf(item),
        comparison,
      });
      continue;
    }
    if (item.kind === 'show_gallery') {
      const gallery = readGallery(item);
      if (gallery === null) {
        continue;
      }
      // Closes both open runs, for the reason the findings card does.
      openGroups.delete(groupKey(item));
      openTaskCards.delete(groupKey(item));
      entries.push({
        type: 'gallery',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        nodeId: item.nodeId,
        parentToolUseId: subagentIdOf(item),
        gallery,
      });
      continue;
    }
    if (item.kind === 'task_list') {
      const announcement = readTaskAnnouncement(item);
      if (announcement === null) {
        continue;
      }
      const thread = subagentIdOf(item);
      const history = taskLists.get(thread) ?? [];
      history.push(announcement);
      taskLists.set(thread, history);
      // Folded from the thread's WHOLE history rather than this run's rows: a
      // run holding one `TaskUpdate` knows about one task, and the list is only
      // ever the fold of everything before it.
      const tasks = foldTaskList(history);
      const key = groupKey(item);
      const open = openTaskCards.get(key);
      if (open) {
        open.tasks = tasks;
        open.seq = Math.max(open.seq, item.seq);
        continue;
      }
      // A card is a narrative row of its own, so it closes the tool group of the
      // thread that produced it — the same boundary any other rendered row is.
      openGroups.delete(key);
      const card: TaskListEntry = {
        type: 'task-list',
        id: item.id,
        createdAt: item.createdAt,
        seq: item.seq,
        nodeId: item.nodeId,
        parentToolUseId: thread,
        tasks,
        // Decided by the sweep below, once the whole stream is known — the same
        // shape `closed` on a tool group takes, and for the same reason: a card
        // cannot know whether a later one exists while it is being built.
        latest: false,
      };
      openTaskCards.set(key, card);
      entries.push(card);
      continue;
    }
    // Any other rendered kind from this node is a narrative boundary — the
    // node "said something", so its next tool call starts a fresh group. Only
    // for the thread that said it: a sub-agent reporting mid-way must not
    // split the main thread's group, which is what produced runs of one-call
    // rows while several sub-agents were talking at once.
    openGroups.delete(groupKey(item));
    openTaskCards.delete(groupKey(item));
    entries.push({ type: 'item', item });
  }
  closeGroupsBeforeTurnEnds(entries, items);
  // The last card of each thread is the current list. Keyed by the same
  // (node, thread) pair the cards were folded on, so a delegate's last card and
  // the agent's own are both current — they are different lists.
  const lastCard = new Map<string, TaskListEntry>();
  for (const entry of entries) {
    if (entry.type === 'task-list') {
      lastCard.set(
        `${entry.nodeId ?? ''}\u0000${entry.parentToolUseId ?? ''}`,
        entry,
      );
    }
  }
  for (const card of lastCard.values()) {
    card.latest = true;
  }
  return entries;
}

/**
 * Whether anything is still working through the list this card shows.
 *
 * Two conditions, and both are needed. An earlier card is a SNAPSHOT of a list
 * that has since moved on, so its in-progress row is history however live the
 * run is. And the latest card is only live while the run is: a turn that ended
 * with a task still in progress leaves a row that will never advance, and a
 * spinner on it claims work that stopped — the reported "finished one task,
 * still in progress for some reason".
 *
 * `runSettledAt` is read exactly as {@link subagentBlockStatus} reads it: a
 * MOMENT rather than a flag, so a card written AFTER the settle (the CLI
 * carrying on by itself past its own turn-end line) is still live, and an
 * unparseable settle keeps the conservative reading rather than putting every
 * spinner back.
 */
export function taskCardIsLive(
  entry: TaskListEntry,
  runSettledAt: RunSettleAt,
): boolean {
  if (!entry.latest) {
    return false;
  }
  if (runSettledAt === null) {
    return true;
  }
  if (runSettledAt === 'unknown') {
    return false;
  }
  const at = Date.parse(entry.createdAt);
  return Number.isFinite(at) && at > runSettledAt;
}

/** Item kinds that end a turn — after one, nothing more is coming for it. */
const TURN_END_KINDS = new Set(['turn_complete', 'turn_cancelled', 'error']);

/**
 * Mark every tool group that a turn ended after.
 *
 * Answered against the ITEM stream rather than the run's status, because the
 * question is per-turn: the run goes back to `running` on the user's next
 * message, and a group left open by turn 1 must stay closed through turn 5
 * rather than start spinning again with it.
 *
 * Recursive over blocks, since the fold nests groups inside turn- and
 * call-blocks and a nested group is exactly the sub-agent case that was
 * reported spinning.
 *
 * Scoped to the group's own NODE, for the same reason {@link
 * buildSubagentBlocks} scopes its own turn-end read: under graph fan-out each
 * node settles independently, so an unscoped comparison let node A's
 * `turn_complete` close node B's still-open group and drop the spinner off a
 * tool call genuinely in flight. In a 1:1 chat every `nodeId` is null, so the
 * scoping is a no-op there — which is why it went unnoticed.
 */
function closeGroupsBeforeTurnEnds(
  entries: readonly TranscriptEntry[],
  items: readonly ChatItem[],
): void {
  const turnEnds = items.filter((item) => TURN_END_KINDS.has(item.kind));
  if (turnEnds.length === 0) {
    return;
  }
  const walk = (list: readonly TranscriptEntry[]): void => {
    for (const entry of list) {
      if (entry.type === 'tools') {
        const lastSeq = entry.pairs.reduce(
          (max, pair) => Math.max(max, pair.result?.seq ?? pair.call.seq),
          0,
        );
        // A turn of THIS node ended after this group's last row, so this
        // group's turn is among the ones that finished.
        entry.closed = turnEnds.some(
          (item) => item.nodeId === entry.nodeId && item.seq > lastSeq,
        );
        continue;
      }
      if (entry.type === 'turn-block' || entry.type === 'call-block') {
        walk(entry.entries);
      }
    }
  };
  walk(entries);
}

/**
 * Assemble one call's block: status items drive the header's live status
 * (they never render as rows — the old "▸ B started"/"✓ B finished" pair
 * folds into the header icon), everything else re-folds recursively (tool
 * groups work inside a block; the bucket holds no call rows, so no blocks
 * nest from here).
 */
function buildCallBlock(callId: string, shell: CallShell): CallBlockEntry {
  let status: CallBlockEntry['status'] = 'pending';
  const inner: ChatItem[] = [];
  for (const item of shell.bucket) {
    if (item.kind === 'status') {
      const value = payloadString(item.payload, 'status');
      if (value && BLOCK_STATUSES.has(value)) {
        status = value as CallBlockEntry['status'];
      }
      continue;
    }
    inner.push(item);
  }
  // A COMPLETED sub-turn's last message is the call's RESULT — pull it out
  // of the flow so the block can frame it (request at the top, result at
  // the bottom). While running the tail message is just the latest stream.
  let result: string | null = null;
  if (status === 'completed') {
    for (let i = inner.length - 1; i >= 0; i--) {
      if (inner[i]!.kind === 'message') {
        result = payloadString(inner[i]!.payload, 'text');
        if (result !== null) {
          inner.splice(i, 1);
        }
        break;
      }
    }
  }
  // The ok settle envelope is pure bookkeeping once the block shows the
  // result and the done chip; only the error arm keeps a row (in-block).
  const visibleInner = inner.filter(
    (item) =>
      !(
        item.kind === 'call_result' &&
        payloadString(item.payload, 'status') === 'ok'
      ),
  );
  return {
    type: 'call-block',
    id: shell.started.id,
    createdAt: shell.started.createdAt,
    callId,
    calleeNodeId: shell.calleeNodeId,
    callerNodeId: shell.started.nodeId,
    mode: payloadString(shell.started.payload, 'mode'),
    message: payloadString(shell.started.payload, 'message'),
    status,
    result,
    // A callee runs its own delegates, so its sub-turn gets the same fold the
    // main flow gets. Without this a workflow callee's `Task` work spilled
    // loose into the call block, invisible to the panel and to the run badge —
    // and `collectSubagentBlocks`' recursion into call blocks could never find
    // anything, making its "at any depth" claim false.
    //
    // `buildTurnBlocks` LAST, exactly as `Chats.tsx` ends the main flow with
    // it, and its absence here is why a callee's prose read differently from
    // every other agent's: a message that folds into a turn block is drawn as
    // markdown in the flow, and one that does not goes through
    // `MessageBubble` and wears a bordered card of its own. So the callee's
    // sentences sat in grey boxes inside a card that already frames them,
    // where the same agent's words in a 1:1 chat sit bare — reported as
    // "каждое его сообщение все еще в каком-то странном сером блоке… дизайн
    // должен быть такой же, как у обычного треда". Under the block's
    // `NestedThreadContext` those turn blocks render frameless, so what comes
    // out is the ordinary thread's own shape.
    entries: buildTurnBlocks(
      buildWorkflowCards(
        buildSubagentBlocks(groupTranscript(visibleInner), visibleInner),
        visibleInner,
      ),
    ),
  };
}

/**
 * The file a tool RESULT names, when the call itself named none.
 *
 * An agent may disclose nothing about an edit up front and then report the whole
 * diff, path included, on completion (measured on cursor-agent — see
 * `resultDiffsOf`). That path is the only way to tell two edits of the same file
 * from edits of two files, which is the difference between "edited 1 file" and
 * "edited 2 files".
 */
function diffPathOf(result: ChatItem | null): string | null {
  if (result === null) {
    return null;
  }
  const payload = result.payload as { result?: unknown } | null;
  const [first] = resultDiffsOf(payload?.result ?? null);
  return first?.path ?? null;
}

/**
 * The collapsed group's one-line summary, Claude/Cursor-style:
 * "Read 4 files · ran 3 commands · edited 1 file".
 *
 * Every bucket names what the agent DID, because a bare "Used 7 tools" is the
 * one thing a reader cannot act on — seven reads and seven edits are the same
 * number and completely different turns. The buckets cover the tools a coding
 * agent actually spends its calls on: opening files, searching, running
 * commands, editing, writing, fetching, delegating, and calling MCP servers.
 *
 * The tool TOTAL is dropped when the breakdown already accounts for every call
 * in the group, because otherwise the same work is counted twice in one line:
 * a group holding one `Bash` read "Used 1 tool · ran 1 command", two figures
 * for a single action. Once some call falls outside the named buckets the total
 * is the only thing that reports it, so it comes back.
 *
 * `accounted` counts CALLS, while the file figures count DISTINCT paths — three
 * edits to one file are three accounted tools and one edited file, and comparing
 * the displayed numbers instead would have kept the total on exactly the groups
 * that need it least.
 *
 * A file-shaped tool with no `file_path` stays unaccounted ON PURPOSE: it would
 * otherwise be reported as an edit of nothing, and the total is the honest
 * answer for a call this cannot describe.
 */
/**
 * Does this call have a CHANGE TO A FILE to show?
 *
 * REPORTED as "I wanna see all file edits, so it should be automatically open,
 * like claude cli" — the transcript folded every edit behind two presses (the
 * group's chevron, then the row's), so the one part of a turn a reader has to
 * check by eye was the part hidden hardest. It decides what is OPEN, and — since
 * {@link pullFileChangesOutOfGroups} — which rows are lifted out of a group.
 *
 * Only file changes, and deliberately not "everything". A turn's reads, greps
 * and command output are the material an agent worked FROM; unfolding those
 * too would bury the diff in the wall of text this fold exists to prevent.
 *
 * Asked of BOTH directions, because the two shipped transports report a change
 * at opposite ends of one call: claude discloses it in the arguments
 * (`Edit`'s `old_string`/`new_string`, `Write`'s `content`), while an ACP agent
 * discloses no arguments at all and returns `diffs` on the result. Keying on
 * either alone would open the diffs of one CLI and none of the other's — and it
 * is also why the split above runs on the FOLD'S OUTPUT rather than inside it:
 * a result arrives after its call, so a decision taken while grouping would
 * read as "not an edit" for every ACP agent.
 *
 * The last clause is the guard rather than the rule: a tool this classifies as
 * an edit but nothing renders as a diff (`MultiEdit`, whose arguments are a
 * list) still has arguments worth reading, but a row with NO body opens onto
 * blank space and would read as a broken disclosure.
 *
 * Lives here rather than beside its renderer because it is a fact about a
 * {@link ToolPair}, and because the splitter is in this module: `tool-group.tsx`
 * imports from here, so the reverse would close a value cycle.
 */
export function showsFileChange(pair: ToolPair): boolean {
  const payload: unknown = pair.call.payload;
  const name = payloadString(payload, 'name') ?? 'tool';
  const input = (payload as { input?: unknown } | null)?.input;
  const body = toolInputBody(name, input);
  if (body?.kind === 'diff') {
    return true;
  }
  if (pair.result !== null) {
    const result =
      (pair.result.payload as { result?: unknown } | null)?.result ?? null;
    if (toolResultBody(input, result).kind === 'diff') {
      return true;
    }
  }
  const operation = toolOperationOf(payload);
  return (operation === 'edit' || operation === 'create') && body !== null;
}

/**
 * Lift every FILE CHANGE out of its tool group, leaving the calls around it
 * grouped as before.
 *
 * REPORTED: "у нас все еще должны быть группы, сколлапсированные с другими
 * экшенами, но редактирование файлов должно быть вне этой группы … если агент
 * сделал несколько shell-tool колов, у нас должна быть еще одна группа
 * «collapse» … а отдельно блок с редактированием файла". The group already
 * OPENED itself when it held an edit, and that is the shape being fixed: it
 * opened the reads, greps and commands with it, so the diff a reader came for
 * arrived at the bottom of everything the agent had done to find it.
 *
 * So `[bash, bash, edit, read, write]` becomes a collapsed `bash, bash`, the
 * edit on its own, a collapsed `read`, and the write on its own. The
 * surrounding runs keep the fold they always had — they are the material, not
 * the result — and a group holding no change is untouched.
 *
 * Only when the user has left file edits expanded, which is the same condition
 * the auto-open follows: someone who has asked for every step folded is asking
 * for less on screen, and lifting the edits out would put more there.
 *
 * Identity is the segment's OWN first call, exactly as the fold names a group,
 * so the pieces of a split run carry distinct React keys and each keeps its own
 * expansion state instead of inheriting the run's.
 */
export function pullFileChangesOutOfGroups(
  entries: readonly TranscriptEntry[],
): TranscriptEntry[] {
  return entries.flatMap((entry): TranscriptEntry[] => {
    if (entry.type !== 'tools' || !entry.pairs.some(showsFileChange)) {
      return [entry];
    }
    const out: TranscriptEntry[] = [];
    let run: ToolPair[] = [];
    const flushRun = (): void => {
      if (run.length > 0) {
        out.push({ ...entry, id: run[0]!.call.id, pairs: run });
        run = [];
      }
    };
    for (const pair of entry.pairs) {
      if (showsFileChange(pair)) {
        flushRun();
        out.push({
          ...entry,
          id: pair.call.id,
          pairs: [pair],
          standalone: true,
        });
        continue;
      }
      run.push(pair);
    }
    flushRun();
    return out;
  });
}

export function toolGroupSummary(pairs: readonly ToolPair[]): string {
  const { spoken, accounted } = foldToolGroup(pairs);
  const parts = spoken.map((phrase) => phrase.text);
  if (parts.length === 0 || accounted < pairs.length) {
    parts.unshift(`Used ${countOf(pairs.length, 'tool')}`);
    return parts.join(' · ');
  }
  // The breakdown is now the whole line, so it opens the sentence.
  const [first, ...rest] = parts;
  return [first!.charAt(0).toUpperCase() + first!.slice(1), ...rest].join(
    ' · ',
  );
}

/**
 * How many operation glyphs a collapsed group's header carries.
 *
 * Three because the header is a one-line summary sitting in a narrow column and
 * a strip of glyphs long enough to need counting has stopped being a glance —
 * and because the phrases behind them are already spelled out in the sentence
 * beside it, so the icons are an index into that sentence rather than a
 * replacement for it.
 */
const MAX_GROUP_OPERATION_ICONS = 3;

/**
 * The operations a collapsed group's header should draw glyphs for — the same
 * ones {@link toolGroupSummary} SPEAKS, in the same order, capped.
 *
 * Off the same fold as the sentence, deliberately: a second pass over the pairs
 * is how an icon strip comes to disagree with the words next to it (a group
 * reading "read 2 files" under a terminal glyph). It also means the strip
 * inherits the summary's own honesty rules for free — an operation the sentence
 * cannot account for gets no glyph either, rather than a picture asserting
 * something the text declined to.
 *
 * `delegate`, `delete` and `move` are counted by the fold and never spoken, so
 * they draw nothing here either — see the note beside their phrases.
 */
export function toolGroupOperations(
  pairs: readonly ToolPair[],
): ToolOperation[] {
  return foldToolGroup(pairs)
    .spoken.map((phrase) => phrase.operation)
    .slice(0, MAX_GROUP_OPERATION_ICONS);
}

/** `1 file` / `3 files` — the shared pluralizer for the phrases below. */
function countOf(n: number, noun: string): string {
  return `${n} ${noun}${n === 1 ? '' : 's'}`;
}

/** One thing a group is reported to have done: the operation, and its wording. */
interface ToolGroupPhrase {
  operation: ToolOperation;
  text: string;
}

/**
 * The ONE pass over a group's pairs, feeding both the header's sentence and its
 * glyphs.
 *
 * Split out of {@link toolGroupSummary} rather than copied so the two readings
 * cannot drift — the same reason `toolOperationOf` is one classifier serving
 * both the summary and the per-row icon.
 */
function foldToolGroup(pairs: readonly ToolPair[]): {
  spoken: ToolGroupPhrase[];
  accounted: number;
} {
  let commands = 0;
  let searches = 0;
  let fetches = 0;
  let mcpCalls = 0;
  let accounted = 0;
  const opened = new Set<string>();
  const edited = new Set<string>();
  const created = new Set<string>();
  for (const { call, result } of pairs) {
    const input = (call.payload as { input?: unknown } | null)?.input;
    const file =
      input && typeof input === 'object' && 'file_path' in input
        ? String((input as { file_path: unknown }).file_path)
        : null;
    // What the call DID, from the ONE classifier — the agent's own answer when it
    // made one, else its tool name. The name buckets are one CLI's vocabulary:
    // cursor titles its calls "Read File", "Edit File", "grep" and discloses no
    // arguments at all, so before the agent's own answer was consulted a turn
    // that read, edited and ran a command summarised as "Used 2 tools" and named
    // nothing it had done.
    const operation = toolOperationOf(call.payload);
    // Whether the AGENT classified this call itself, which is a different
    // question and decides how a call with no path is counted. An agent-declared
    // kind is trusted with no target (cursor discloses none, so every one of its
    // calls would otherwise go unaccounted); a name-matched file tool is not —
    // it would be reported as an edit of nothing, and the "Used N tools" total is
    // the honest answer for a call this cannot describe.
    const selfDeclared = toolKindOf(call.payload) !== null;
    // A path when one is known — an edit's diff reports it even when the call did
    // not. Counting DISTINCT paths is what makes three edits of one file read as
    // one edited file.
    const path = file ?? diffPathOf(result);
    /** Count this call against a file bucket, or leave it unaccounted. */
    const addPath = (bucket: Set<string>): void => {
      if (path !== null) {
        bucket.add(path);
        accounted += 1;
      } else if (selfDeclared) {
        // No path to tell it apart, so the CALL is the unit. Keyed off the count
        // so two such calls never collapse into one.
        accounted += 1;
        bucket.add(`#${accounted}`);
      }
    };
    switch (operation) {
      case 'read':
        addPath(opened);
        break;
      case 'edit':
        addPath(edited);
        break;
      case 'create':
        addPath(created);
        break;
      case 'search':
        searches += 1;
        accounted += 1;
        break;
      case 'execute':
        commands += 1;
        accounted += 1;
        break;
      case 'fetch':
        fetches += 1;
        accounted += 1;
        break;
      case 'mcp':
        mcpCalls += 1;
        accounted += 1;
        break;
      case 'delegate':
        // Accounted but never SPOKEN — see the note where the other phrases are
        // assembled below.
        accounted += 1;
        break;
      case 'delete':
      case 'move':
        // Accounted but not SPOKEN either: neither has a phrase here, and
        // inventing one ("moved 1 file") for a kind never yet seen on the wire
        // would be guessing at wording no measurement supports.
        accounted += 1;
        break;
      case null:
        break;
    }
  }
  const count = countOf;
  const spoken: ToolGroupPhrase[] = [];
  if (opened.size > 0) {
    spoken.push({
      operation: 'read',
      text: `read ${count(opened.size, 'file')}`,
    });
  }
  if (searches > 0) {
    spoken.push({
      operation: 'search',
      text: `searched ${count(searches, 'time')}`,
    });
  }
  if (commands > 0) {
    spoken.push({
      operation: 'execute',
      text: `ran ${count(commands, 'command')}`,
    });
  }
  if (edited.size > 0) {
    spoken.push({
      operation: 'edit',
      text: `edited ${count(edited.size, 'file')}`,
    });
  }
  if (created.size > 0) {
    spoken.push({
      operation: 'create',
      text: `created ${count(created.size, 'file')}`,
    });
  }
  if (fetches > 0) {
    spoken.push({
      operation: 'fetch',
      text: `fetched ${count(fetches, 'page')}`,
    });
  }
  // `delegations` is counted into `accounted` and then deliberately NOT
  // spoken: a delegation already renders as its own sub-agent block directly
  // below this row, so naming it here says the same thing twice — which is
  // what "Delegated to 5 subagents" sitting over five sub-agent cards actually
  // looked like. It stays ACCOUNTED for so a group that MIXES delegations with
  // real work still reads as its breakdown ("Read 3 files") rather than
  // falling through to the "Used N tools" catch-all. A group of nothing BUT
  // delegations never reaches a reader at all: `buildSubagentBlocks` strips
  // those pairs out and drops the emptied group.
  if (mcpCalls > 0) {
    spoken.push({
      operation: 'mcp',
      text: `called ${count(mcpCalls, 'MCP tool')}`,
    });
  }
  return { spoken, accounted };
}

/** One-line argument preview for a tool row (the command, the path, …). */
export function toolCallSummary(call: ChatItem): string {
  const input = (call.payload as { input?: unknown } | null)?.input;
  if (!input || typeof input !== 'object') {
    return '';
  }
  const record = input as Record<string, unknown>;
  // An agent that named a call and disclosed no arguments has nothing to preview,
  // and `compactJson({})` below would render the literal `{}` — the reported
  // defect, on the line that is visible while the row is COLLAPSED. This is the
  // sibling of the same guard in `tool-render.ts`; it is a separate check rather
  // than a shared call because this function summarizes, it does not decide
  // whether to draw a body. It also covers rows persisted BEFORE the daemon
  // started normalizing the empty bag, which is why replaying an old cursor chat
  // still needs it.
  if (Object.keys(record).length === 0) {
    return '';
  }
  const first = (...keys: string[]): string | null => {
    for (const key of keys) {
      const value = record[key];
      if (typeof value === 'string' && value.length > 0) {
        return value;
      }
    }
    return null;
  };
  const questions = record.questions;
  if (Array.isArray(questions) && questions.length > 0) {
    const q = questions[0] as { question?: unknown };
    if (typeof q?.question === 'string') {
      return q.question;
    }
  }
  return (
    first(
      'command',
      'file_path',
      'pattern',
      'description',
      'query',
      'prompt',
      'path',
      'url',
    ) ?? compactJson(record)
  );
}

function compactJson(value: unknown): string {
  try {
    return JSON.stringify(value) ?? '';
  } catch {
    return String(value);
  }
}

