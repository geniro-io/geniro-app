describe('approval_verdict row — suppressed only when its card is on screen', () => {
  /** The verdict row as the transcript renders it, under a given id set. */
  function renderVerdict(
    payload: unknown,
    cardBacked: ReadonlySet<string>,
  ): string {
    render(
      <CardBackedRequestsContext.Provider value={cardBacked}>
        <TranscriptItem
          item={item('approval_verdict', payload)}
          nodes={NODES}
        />
      </CardBackedRequestsContext.Provider>,
    );
    return container.textContent ?? '';
  }

  it('renders exactly once — the row is dropped while the QUESTION card is loaded', () => {
    // The card's own settled line ("✓ answered — Blue") is the one the user
    // reads; this row would print the same answer directly beneath it.
    expect(
      renderVerdict(
        { id: 'req-1', allow: true, answer: 'Blue' },
        new Set(['req-1']),
      ),
    ).toBe('');
  });

  it('renders exactly once — the row is dropped while the PERMISSION card is loaded', () => {
    // The card's other branch ("✓ approved") duplicates just as hard. Pinned
    // separately because the two settled blocks live at different places in
    // approval-card.tsx and a presence check that missed one would pass the
    // question case while still doubling every permission.
    expect(
      renderVerdict({ id: 'req-2', allow: true }, new Set(['req-2'])),
    ).toBe('');
    expect(
      renderVerdict({ id: 'req-3', allow: false }, new Set(['req-3'])),
    ).toBe('');
  });

  it('KEEPS the row when the card scrolled out of the loaded window', () => {
    // Without the card there is no other record of the answer — dropping the
    // row unconditionally would erase it from the history.
    expect(renderVerdict({ id: 'req-4', allow: true }, new Set())).toContain(
      '✓ tool approved',
    );
    expect(renderVerdict({ id: 'req-5', allow: false }, new Set())).toContain(
      '✗ tool denied',
    );
    expect(
      renderVerdict({ id: 'req-6', allow: true, answer: 'Blue' }, new Set()),
    ).toContain('✓ answered — Blue');
  });

  it('keeps a verdict that carries no request id — nothing can vouch for it', () => {
    expect(renderVerdict({ allow: true }, new Set(['req-1']))).toContain(
      '✓ tool approved',
    );
  });

  it('defaults to showing the row when no provider is present', () => {
    // The context default must be the SAFE one: a row rendered outside Chats
    // (a nested flow, a spec) records its verdict rather than vanishing.
    render(
      <TranscriptItem
        item={item('approval_verdict', { id: 'req-1', allow: true })}
        nodes={NODES}
      />,
    );
    expect(container.textContent).toContain('✓ tool approved');
  });
});

describe('cardBackedRequestIds', () => {
  it('collects the ids of the approval REQUESTS in the window, nothing else', () => {
    const items = [
      item('approval_request', { id: 'req-1', toolName: 'Write' }),
      { ...item('approval_verdict', { id: 'req-9', allow: true }), id: 'v-1' },
      { ...item('message', { text: 'hi' }), id: 'm-1' },
    ];
    expect([...cardBackedRequestIds(items)]).toEqual(['req-1']);
  });

  it('ignores a request whose payload carries no id', () => {
    expect([...cardBackedRequestIds([item('approval_request', {})])]).toEqual(
      [],
    );
  });
});

describe('unanswerable — the daemon says a card is dead', () => {
  it('RENDERS a note when the card it closes is not in the loaded window', () => {
    // The kind must not fall through to `default: return null` — an item the
    // daemon wrote to explain a dead request would then be pure silence, and
    // a history window that scrolled past the card would explain nothing.
    render(
      <CardBackedRequestsContext.Provider value={new Set()}>
        <TranscriptItem
          item={item('unanswerable', { id: 'req-1', toolName: 'Bash' })}
          nodes={NODES}
        />
      </CardBackedRequestsContext.Provider>,
    );
    expect(container.textContent).toContain('⊘ Bash');
    expect(container.textContent).toContain(
      'the turn ended before this was answered',
    );
  });

  it('renders NOTHING when its card is on screen — the card shows its own expired state', () => {
    render(
      <CardBackedRequestsContext.Provider value={new Set(['req-1'])}>
        <TranscriptItem
          item={item('unanswerable', { id: 'req-1', toolName: 'Bash' })}
          nodes={NODES}
        />
      </CardBackedRequestsContext.Provider>,
    );
    expect(container.textContent).toBe('');
  });

  it('collects the request ids the daemon declared dead, ignoring malformed rows', () => {
    const items = [
      item('unanswerable', { id: 'req-1', toolName: 'Bash' }),
      { ...item('unanswerable', { toolName: 'Write' }), id: 'u-2', seq: 2 },
      { ...item('approval_request', { id: 'req-9' }), id: 'a-3', seq: 3 },
    ];
    expect(unanswerableRequestIds(items)).toEqual(new Set(['req-1']));
  });
});

