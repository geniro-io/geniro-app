import { createContext, memo, useContext } from 'react';

import type { ItemDto as ChatItem } from '../autogenerated';
import { CodeBlock } from '../components/ui/code-block';
import { AlertRow } from './alert-row';
import { messageAttachments } from './attachment-payload';
import { DiffView } from './diff-view';
import { liveRowKind, ThinkingRow, WorkingRow } from './live-row';
import { MarkdownContent } from './markdown-content';
import { MessageAttachments } from './message-attachments';
import { MessageBubble } from './message-bubble';
import { toolInputBody, toolResultBody } from './tool-render';

/** What the transcript knows about a workflow node (for display only). */
export interface TranscriptNodeMeta {
  name: string;
  kind: 'agent' | 'trigger';
}

/** Read a string field out of an item's payload, defensively. */
export function payloadString(payload: unknown, key: string): string | null {
  if (payload && typeof payload === 'object' && key in payload) {
    const value = (payload as Record<string, unknown>)[key];
    if (typeof value === 'string') {
      return value;
    }
  }
  return null;
}

/** Read a numeric field out of an item's payload, defensively. */
function payloadNumber(payload: unknown, key: string): number | null {
  if (payload && typeof payload === 'object' && key in payload) {
    const value = (payload as Record<string, unknown>)[key];
    if (typeof value === 'number' && Number.isFinite(value)) {
      return value;
    }
  }
  return null;
}

/**
 * One transcript row, rendered by item kind. Memoized: items are immutable
 * (keyed by id), and a streaming workflow run re-renders the whole list per
 * event — without the memo every tool row re-stringifies its payload on each
 * incoming item.
 */
export const TranscriptItem = memo(function TranscriptItem({
  item,
  nodes,
}: {
  item: ChatItem;
  /** Workflow node display metadata, keyed by node id (names + kinds). */
  nodes?: ReadonlyMap<string, TranscriptNodeMeta>;
}): React.JSX.Element | null {
  const cardBacked = useContext(CardBackedRequestsContext);
  const nodeName = (id: string | null): string | null =>
    id === null ? null : (nodes?.get(id)?.name ?? id);
  // Workflow-run items carry the node that produced them; tag each row so
  // parallel branches stay readable in the interleaved transcript.
  const tag = (label: string): string => {
    const name = nodeName(item.nodeId);
    return name ? `${name} · ${label}` : label;
  };
  switch (item.kind) {
    case 'message': {
      // The SenderRow frame (avatar + name + time) identifies the speaker —
      // the bubble carries only the markdown-rendered text.
      const text = payloadString(item.payload, 'text') ?? '';
      const attachments = messageAttachments(item.payload);
      return (
        <MessageBubble variant={item.role === 'user' ? 'user' : 'assistant'}>
          <MessageAttachments runId={item.runId} attachments={attachments} />
          {/* An image alone is a complete message — don't render an empty
              markdown block under it. */}
          {text ? <MarkdownContent content={text} /> : null}
        </MessageBubble>
      );
    }
    case 'reasoning': {
      // A LIVE row describes what is happening right now and owns its own
      // clock; a durable one is text the daemon persisted. Only the synthetic
      // rows carry the marker, so a persisted reasoning item can never be
      // mistaken for one.
      const live = liveRowKind(item.payload);
      if (live === 'working') {
        return <WorkingRow />;
      }
      if (live === 'thinking') {
        return (
          <ThinkingRow
            since={payloadNumber(item.payload, 'thinkingSince') ?? Date.now()}
            tokens={payloadNumber(item.payload, 'thinkingTokens') ?? 0}
          />
        );
      }
      return (
        <MessageBubble variant="reasoning" role="thinking">
          <div className="whitespace-pre-wrap italic break-words">
            {payloadString(item.payload, 'text') ?? ''}
          </div>
        </MessageBubble>
      );
    }
    case 'tool_call': {
      // The UNGROUPED path — an orphan call whose pair never formed still
      // lands here, and must not read worse than a grouped row.
      const name = payloadString(item.payload, 'name') ?? 'tool';
      const body = toolInputBody(
        name,
        (item.payload as { input?: unknown } | null)?.input,
      );
      return (
        <MessageBubble variant="tool" role={tag(`🔧 ${name}`)}>
          {body.kind === 'diff' ? (
            <DiffView oldText={body.oldText} newText={body.newText} />
          ) : (
            <CodeBlock
              code={body.code}
              language={body.language}
              caption={body.caption}
            />
          )}
        </MessageBubble>
      );
    }
    case 'tool_result': {
      // No paired call here, so there is no input to infer a language from.
      const body = toolResultBody(
        null,
        (item.payload as { result?: unknown } | null)?.result ?? null,
      );
      return (
        <MessageBubble variant="tool" role={tag('⮑ result')}>
          <CodeBlock code={body.code} language={body.language} />
        </MessageBubble>
      );
    }
    case 'error':
      return (
        <AlertRow
          caption="error"
          message={payloadString(item.payload, 'message') ?? 'unknown error'}
        />
      );
    case 'turn_cancelled':
      // A node's cancel already lands as its "<Name> cancelled" status row —
      // only the run-level cancel note remains.
      return item.nodeId !== null ? null : (
        <MessageBubble variant="note">⊘ cancelled</MessageBubble>
      );
    case 'turn_complete': {
      // A node's finished turn already lands as its "<Name> finished" status
      // row (its cost/context live in the agents panel) — only the run-level
      // note renders. That note carries the workflow roll-up in stopReason:
      // a failed/cancelled workflow must not read "✓ done".
      if (item.nodeId !== null) {
        return null;
      }
      const stop = payloadString(item.payload, 'stopReason');
      if (stop === 'workflow_failed') {
        return <MessageBubble variant="note">✗ failed</MessageBubble>;
      }
      if (stop === 'workflow_cancelled') {
        return <MessageBubble variant="note">⊘ cancelled</MessageBubble>;
      }
      const usage = (item.payload as { usage?: unknown } | null)?.usage;
      const cost =
        usage && typeof usage === 'object' && 'costUsd' in usage
          ? (usage as { costUsd: unknown }).costUsd
          : null;
      return (
        <MessageBubble variant="note">
          {`✓ done${typeof cost === 'number' ? ` · $${cost.toFixed(4)}` : ''}`}
        </MessageBubble>
      );
    }
    case 'status': {
      const status = payloadString(item.payload, 'status');
      if (!status) {
        return null;
      }
      // A trigger firing is not news — the user's own message sits right
      // above it. Only agent nodes narrate their lifecycle.
      if (item.nodeId !== null && nodes?.get(item.nodeId)?.kind === 'trigger') {
        return null;
      }
      // Starts and clean finishes are not news — the blocks, spinners and
      // status chips already narrate them; only the EXCEPTIONAL settles
      // (failed / cancelled / skipped) keep a note.
      if (status === 'running' || status === 'completed') {
        return null;
      }
      const name = nodeName(item.nodeId) ?? 'run';
      const reason = payloadString(item.payload, 'reason');
      const line =
        status === 'failed'
          ? `✗ ${name} failed`
          : status === 'cancelled'
            ? `⊘ ${name} cancelled`
            : status === 'skipped'
              ? `− ${name} skipped${reason ? ` — ${reason}` : ''}`
              : `${name} · ${status}`;
      return <MessageBubble variant="note">{line}</MessageBubble>;
    }
    case 'system': {
      const message = payloadString(item.payload, 'message');
      // The daemon's system items are failure advisories (a degraded caller,
      // a persistence problem) — surface them like errors: red, expandable.
      return message ? <AlertRow caption="system" message={message} /> : null;
    }
    case 'approval_verdict': {
      const allow = (item.payload as { allow?: unknown } | null)?.allow;
      const answer = payloadString(item.payload, 'answer');
      const requestId = payloadString(item.payload, 'id');
      if (requestId !== null && cardBacked.has(requestId)) {
        // The card that asked is on screen and renders its own settled line
        // (both its branches do, and it shows the free-text answer too), so
        // this row would only repeat it.
        return null;
      }
      return (
        <MessageBubble variant="note">
          {tag(
            allow === true
              ? answer
                ? `✓ answered — ${answer}`
                : '✓ tool approved'
              : '✗ tool denied',
          )}
        </MessageBubble>
      );
    }
    case 'unanswerable': {
      const requestId = payloadString(item.payload, 'id');
      if (requestId !== null && cardBacked.has(requestId)) {
        // The card that asked is on screen; it renders its own expired state
        // (this item is what puts it there — see `unanswerableRequestIds`), so
        // a row beside it would only repeat what the card already says.
        return null;
      }
      const toolName = payloadString(item.payload, 'toolName') ?? 'tool';
      return (
        <MessageBubble variant="note">
          {tag(`⊘ ${toolName} — the turn ended before this was answered`)}
        </MessageBubble>
      );
    }
    case 'call_started': {
      const callee =
        nodeName(payloadString(item.payload, 'calleeNodeId')) ?? 'agent';
      return (
        <MessageBubble variant="call" role={tag(`📞 call → ${callee}`)}>
          <div className="whitespace-pre-wrap break-words">
            {payloadString(item.payload, 'message') ?? ''}
          </div>
        </MessageBubble>
      );
    }
    case 'call_result': {
      // Payload spreads the call ENVELOPE: status 'ok' carries
      // result.{call_id,agent,text}; 'error' carries the prefixed error line.
      const callee =
        nodeName(payloadString(item.payload, 'calleeNodeId')) ?? 'agent';
      if (payloadString(item.payload, 'status') === 'ok') {
        // A compact receipt only: the result TEXT lives in the call block's
        // RESULT card (or, in legacy flat transcripts, in the callee's own
        // final bubble right above) — repeating it here doubled the payoff.
        return (
          <MessageBubble variant="note">
            {tag(`✓ result from ${callee}`)}
          </MessageBubble>
        );
      }
      return (
        <MessageBubble variant="error" role={tag(`✗ call failed ← ${callee}`)}>
          <div className="whitespace-pre-wrap break-words">
            {payloadString(item.payload, 'error') ?? 'call failed'}
          </div>
        </MessageBubble>
      );
    }
    case 'await_collected':
      // Pure plumbing (the broker's pickup bookkeeping) — the ✓ result
      // receipt right beside it says everything the user needs.
      return null;
    case 'call_question': {
      // A call-initiated callee parked on a question — the CALLER (not the
      // user) is expected to answer it via answer_agent. The SenderRow frame
      // names the asking callee; the bubble keeps only the question marker.
      const options = (item.payload as { options?: unknown } | null)?.options;
      const optionLine = Array.isArray(options)
        ? options.filter((o) => typeof o === 'string').join(' / ')
        : '';
      return (
        <MessageBubble variant="call" role="❓ question">
          <div className="whitespace-pre-wrap break-words">
            {payloadString(item.payload, 'question') ?? ''}
            {optionLine ? (
              <span className="text-muted-foreground">{`\n(${optionLine})`}</span>
            ) : null}
          </div>
        </MessageBubble>
      );
    }
    case 'call_answer': {
      const callee =
        nodeName(payloadString(item.payload, 'calleeNodeId')) ?? 'agent';
      const outcome = payloadString(item.payload, 'outcome');
      if (outcome === 'answered') {
        return (
          <MessageBubble variant="call" role={tag(`💬 answered → ${callee}`)}>
            <div className="whitespace-pre-wrap break-words">
              {payloadString(item.payload, 'answer') ?? ''}
            </div>
          </MessageBubble>
        );
      }
      return (
        <MessageBubble variant="error" role={tag('✗ question')}>
          <div className="whitespace-pre-wrap break-words">
            {outcome === 'timeout'
              ? 'timed out — the caller never answered'
              : outcome === 'undelivered'
                ? 'undelivered — the callee ended before the answer arrived'
                : 'orphaned — the caller ended before answering'}
          </div>
        </MessageBubble>
      );
    }
    default:
      return null; // usage / attachment / approval_request (rendered as a card)
  }
});

/**
 * Requests the DAEMON declared unanswerable — its turn settled with the
 * request still pending, so no verdict can ever reach it.
 *
 * Read, not inferred: the daemon knows which turns are live and which requests
 * it actually dropped, while this side could only guess from the order of
 * items. The inference this replaces reconstructed turn scoping from callIds
 * in the transcript, which mistook a callee sub-turn settling for the node's
 * own turn ending and saw nothing at all for a turn that failed to start.
 *
 * TWIN PARSER: the payload is written by
 * `apps/daemon/src/v1/agents/utils/unanswerable.ts` (`UnanswerableWire`). Item
 * payloads are untyped on the wire by design, so a shape change there MUST be
 * mirrored here.
 */
export function unanswerableRequestIds(
  items: readonly ChatItem[],
): Set<string> {
  const dead = new Set<string>();
  for (const item of items) {
    if (item.kind !== 'unanswerable') {
      continue;
    }
    const requestId = payloadString(item.payload, 'id');
    if (requestId) {
      dead.add(requestId);
    }
  }
  return dead;
}

/**
 * Request ids that have an `approval_request` item in the loaded window.
 *
 * Once a verdict lands, {@link ApprovalCard} renders its own settled line —
 * `✓ answered / ✗ declined` on the question branch, `✓ approved / ✗ denied` on
 * the permission branch — so an `approval_verdict` row beside it repeats what
 * the card already says. The row still earns its place when the card is
 * ABSENT: an older turn scrolled out of the loaded window leaves the row as
 * the only surviving record of the answer.
 */
export function cardBackedRequestIds(
  items: readonly ChatItem[],
): ReadonlySet<string> {
  const ids = new Set<string>();
  for (const item of items) {
    if (item.kind === 'approval_request') {
      const id = payloadString(item.payload, 'id');
      if (id) {
        ids.add(id);
      }
    }
  }
  return ids;
}

/**
 * How a verdict row learns whether its card is on screen.
 *
 * A context rather than a prop, for the same reason as
 * `AttachmentLoaderContext`: the shells between `Chats` and a verdict row
 * (`TranscriptEntryView`, `TurnBlock`, `CallBlock`) are memoized on
 * referentially stable props, and threading a set through all three would
 * bloat their signatures and defeat that memoization.
 *
 * Empty outside a provider, which is the SAFE default — an empty set
 * suppresses nothing, so a row rendered without one still records its verdict
 * rather than silently vanishing.
 */
export const CardBackedRequestsContext = createContext<ReadonlySet<string>>(
  new Set<string>(),
);

/** All persisted verdicts of a transcript, keyed by approval request id. */
export function collectVerdicts(
  items: readonly ChatItem[],
): Map<string, boolean> {
  const verdicts = new Map<string, boolean>();
  for (const item of items) {
    if (item.kind === 'approval_verdict') {
      const id = payloadString(item.payload, 'id');
      if (id) {
        const allow = (item.payload as { allow?: unknown }).allow;
        verdicts.set(id, allow === true);
      }
    }
  }
  return verdicts;
}
