/**
 * The API/own-work split, for the tooltip — only when the CLI reported both and
 * the subtraction is meaningful. The remainder is the CLI running tools and
 * reading files, which is what separates "the model was slow" from "the agent
 * did a lot".
 *
 * `api > total` is a REAL reading, not a defensive guess, which is why it
 * returns nothing rather than clamping: measured 2026-08-14 across two turns of
 * one kept claude session, turn 2 reported `durationMs` 2562 against `apiMs`
 * 4633. Clamping would print `0s its own work` about a turn that ran tools;
 * withholding the split leaves the duration itself — which is sound — and says
 * nothing it cannot support.
 */
function apiSuffix(payload: unknown): string {
  const total = cliTurnDurationMs(payload);
  const api = cliTurnApiMs(payload);
  if (total === null || api === null || total <= 0 || api > total) {
    return '';
  }
  return ` — ${formatDuration(api)} of it waiting on the model, ${formatDuration(total - api)} its own work`;
}

/**
 * Re-exported from the pure {@link ./transcript-payload} module, which is
 * where they now live: `transcript-groups.ts` needs `payloadString`, and
 * importing it from THIS component module closed a real import cycle
 * (`agent-activity → transcript-groups → transcript-item → live-row →
 * agent-activity`). Kept re-exported here so the dozen call sites that read
 * them off the row module do not all have to churn.
 */
export { payloadString, type TranscriptNodeMeta } from './transcript-payload';

/**
 * One transcript row, rendered by item kind. Memoized: items are immutable
 * (keyed by id), and a streaming workflow run re-renders the whole list per
 * event — without the memo every tool row re-stringifies its payload on each
 * incoming item.
 */
export const TranscriptItem = memo(function TranscriptItem({
  item,
  nodes,
}: {
  item: ChatItem;
  /** Workflow node display metadata, keyed by node id (names + kinds). */
  nodes?: ReadonlyMap<string, TranscriptNodeMeta>;
}): React.JSX.Element | null {
  const cardBacked = useContext(CardBackedRequestsContext);
  const signIn = useContext(CliLoginContext);
  const nested = useContext(NestedThreadContext);
  const durations = useContext(TurnDurationContext);
  const nodeName = (id: string | null): string | null =>
    id === null ? null : (nodes?.get(id)?.name ?? id);
  // Workflow-run items carry the node that produced them; tag each row so
  // parallel branches stay readable in the interleaved transcript.
  const tag = (label: string): string => {
    const name = nodeName(item.nodeId);
    return name ? `${name} · ${label}` : label;
  };
  switch (item.kind) {
    case 'message': {
      // The SenderRow frame (avatar + name + time) identifies the speaker —
      // the bubble carries only the markdown-rendered text.
      const text = payloadString(item.payload, 'text') ?? '';
      const attachments = messageAttachments(item.payload);
      return (
        <MessageBubble
          variant={item.role === 'user' ? 'user' : 'assistant'}
          // The SenderRow frame names the AGENT, which is the same agent for a
          // sub-agent's prose as for its own — so without this a delegate's
          // report reads as the words of the agent the user is talking to.
          // Withheld inside a sub-agent ENCLOSURE, whose header already names
          // the delegate: the third of the three surfaces that used to say it
          // independently, and the last one to stand down.
          role={
            subagentIdOf(item) === null || nested ? undefined : tag('sub-agent')
          }>
          <MessageAttachments runId={item.runId} attachments={attachments} />
          {/* An image alone is a complete message — don't render an empty
              markdown block under it. */}
          {text ? <MarkdownContent content={text} /> : null}
        </MessageBubble>
      );
    }
    case 'reasoning': {
      // A LIVE row describes what is happening right now and owns its own
      // clock; a durable one is text the daemon persisted. Only the synthetic
      // rows carry the marker, so a persisted reasoning item can never be
      // mistaken for one.
      const live = liveRowKind(item.payload);
      if (live === 'working') {
        return (
          <WorkingRow since={payloadNumber(item.payload, 'workingSince')} />
        );
      }
      if (live === 'thinking') {
        return (
          <ThinkingRow
            since={payloadNumber(item.payload, 'thinkingSince') ?? Date.now()}
            tokens={payloadNumber(item.payload, 'thinkingTokens') ?? 0}
            text={payloadString(item.payload, 'thinkingText')}
          />
        );
      }
      // FOLDED once the stretch is finished — the words stop being something
      // to watch and become something to be able to check. See
      // `ThinkingDisclosure`; a short stretch is left alone.
      const reasoning = payloadString(item.payload, 'text') ?? '';
      return (
        <MessageBubble
          variant="reasoning"
          role={
            subagentIdOf(item) === null || nested
              ? 'thinking'
              : tag('sub-agent thinking')
          }>
          <ThinkingDisclosure text={reasoning}>
            <div className="whitespace-pre-wrap italic break-words">
              {reasoning}
            </div>
          </ThinkingDisclosure>
        </MessageBubble>
      );
    }
    case 'tool_call': {
      // The UNGROUPED path — an orphan call whose pair never formed still
      // lands here, and must not read worse than a grouped row.
      const name = payloadString(item.payload, 'name') ?? 'tool';
      const body = toolInputBody(
        name,
        (item.payload as { input?: unknown } | null)?.input,
      );
      return (
        <MessageBubble variant="tool" role={tag(`🔧 ${name}`)}>
          {body === null ? null : <ToolBodyView body={body} />}
        </MessageBubble>
      );
    }
    case 'tool_result': {
      // No paired call here, so there is no input to infer a language from.
      const body = toolResultBody(
        null,
        (item.payload as { result?: unknown } | null)?.result ?? null,
      );
      return (
        <MessageBubble variant="tool" role={tag('⮑ result')}>
          <ToolBodyView body={body} />
        </MessageBubble>
      );
    }
    case 'error':
      return (
        <DisclosureRow
          caption="error"
          message={payloadString(item.payload, 'message') ?? 'unknown error'}
          // What the failure said about itself, and the whole thing as one
          // block of text — a failure is something the user has to hand to
          // somebody, and a screenshot of a sentence is not a report.
          facts={errorFactsOf(item)}
          copyText={errorReportText(item)}
          // Offered only when the DAEMON recognised this failure as a lapsed
          // account session — the renderer never reads a CLI's wording itself,
          // so it cannot offer sign-in for a failure sign-in would not fix.
          onSignIn={
            errorRecoveryOf(item) === 'cli-login' && signIn ? signIn : undefined
          }
        />
      );
    case 'turn_cancelled':
      // A node's cancel already lands as its "<Name> cancelled" status row —
      // only the run-level cancel note remains.
      return item.nodeId !== null ? null : (
        <MessageBubble variant="note">⊘ cancelled</MessageBubble>
      );
    case 'turn_complete': {
      // A node's finished turn already lands as its "<Name> finished" status
      // row (its cost/context live in the agents panel) — only the run-level
      // note renders. That note carries the workflow roll-up in stopReason:
      // a failed/cancelled workflow must not read "✓ done".
      if (item.nodeId !== null) {
        return null;
      }
      const stop = payloadString(item.payload, 'stopReason');
      if (stop === 'workflow_failed') {
        return <MessageBubble variant="note">✗ failed</MessageBubble>;
      }
      if (stop === 'workflow_cancelled') {
        return <MessageBubble variant="note">⊘ cancelled</MessageBubble>;
      }
      const usage = (item.payload as { usage?: unknown } | null)?.usage;
      const cost =
        usage && typeof usage === 'object' && 'costUsd' in usage
          ? (usage as { costUsd: unknown }).costUsd
          : null;
      // How long this turn worked, beside the cost that was already here. The
      // pair is the whole point: a turn's price meant little with no sense of
      // what it bought, and the time was on screen only while the turn ran.
      const worked = durations.get(item.id);
      return (
        <MessageBubble variant="note">
          {/* ONE child, because the note bubble is a `flex-col`: a second
              sibling here does not sit beside the first, it stacks under it —
              which put the cost on its own line the moment the duration gained
              a span of its own. */}
          <span>
            <span
              title={
                worked === undefined
                  ? undefined
                  : worked.source === 'cli'
                    ? `How long the agent worked, as the CLI itself measured it${apiSuffix(item.payload)}`
                    : 'How long this turn worked — measured from the transcript, minus any time waiting on you'
              }>
              {`✓ done${worked === undefined ? '' : ` · ${formatDuration(worked.ms)}`}`}
            </span>
            {typeof cost === 'number' ? ` · $${cost.toFixed(4)}` : ''}
          </span>
        </MessageBubble>
      );
    }
    case 'status': {
      const status = payloadString(item.payload, 'status');
      if (!status) {
        return null;
      }
      // A trigger firing is not news — the user's own message sits right
      // above it. Only agent nodes narrate their lifecycle.
      if (item.nodeId !== null && nodes?.get(item.nodeId)?.kind === 'trigger') {
        return null;
      }
      // Starts and clean finishes are not news — the blocks, spinners and
      // status chips already narrate them; only the EXCEPTIONAL settles
      // (failed / cancelled / skipped) keep a note.
      if (status === 'running' || status === 'completed') {
        return null;
      }
      const name = nodeName(item.nodeId) ?? 'run';
      const reason = payloadString(item.payload, 'reason');
      const line =
        status === 'failed'
          ? `✗ ${name} failed`
          : status === 'cancelled'
            ? `⊘ ${name} cancelled`
            : status === 'skipped'
              ? `− ${name} skipped${reason ? ` — ${reason}` : ''}`
              : `${name} · ${status}`;
      return <MessageBubble variant="note">{line}</MessageBubble>;
    }
    case 'system': {
      const message = payloadString(item.payload, 'message');
      if (message === null) {
        return null;
      }
      // Text the CLI wrote, which geniro is only relaying — its own compaction
      // summary is the case this exists for. It is informational prose, so it
      // gets the neutral tone rather than the failure chrome below; dressing
      // a relayed summary in red told the user geniro was reporting a problem,
      // and it would also let agent-authored text impersonate an app-level
      // advisory beside the real ones.
      if (isCliAuthored(item.payload)) {
        const compaction = compactionFacts(item.payload);
        // A compaction summary is ~10 000 characters of the CLI describing a
        // conversation the user just had, and it used to land in the transcript
        // in full — several screens of prose between two of their own messages,
        // with no heading to say what it even was. COLLAPSED, with the one fact
        // that explains why it appeared at all on its line: the row states what
        // the compaction did, and the summary is one click away for the rare
        // moment someone wants to read it.
        if (compaction !== null) {
          return (
            <DisclosureRow
              tone="muted"
              caption="conversation compacted"
              detail={compactionDetail(compaction)}
              message={message}
            />
          );
        }
        // A relayed notice with no compaction marker: not a summary, and short
        // enough to read where it stands. Unchanged.
        return <MessageBubble variant="note">{message}</MessageBubble>;
      }
      // The daemon speaking, but not about a failure: it said so itself
      // (`severity: 'info'`). The between-turn hand-over is the case — a request
      // the CLI raised while no turn was open, kept for the user instead of
      // answered for them. Neutral tone, same as relayed prose: the row exists
      // so the odd timing is not silent, and it sits directly above the card it
      // points at, where red chrome read as "something is wrong with this card".
      if (isInfoNotice(item.payload)) {
        return <MessageBubble variant="note">{message}</MessageBubble>;
      }
      // A DEGRADE: a setting the user chose that the agent could not apply. It
      // has to be seen — the turn is not doing what they asked — and it must not
      // be red, because nothing failed and the turn carried on. Captioned for
      // what it is rather than as `system`, which named the WRITER and left the
      // reader to infer the severity from the colour.
      if (isWarningNotice(item.payload)) {
        return (
          <DisclosureRow
            tone="warning"
            // `not applied` is the DEGRADE's caption, not the level's: it is
            // true of a setting the agent could not honour and false of the
            // other loud-but-not-fatal thing, a request that failed and was
            // retried. A producer that names its own kind gets that word.
            caption={noticeCaption(item.payload) ?? 'not applied'}
            message={message}
          />
        );
      }
      // The DAEMON's own system items are failure advisories (a degraded caller,
      // a persistence problem) — surface them like errors: red, expandable.
      return <DisclosureRow caption="system" message={message} />;
    }
    case 'approval_verdict': {
      const allow = (item.payload as { allow?: unknown } | null)?.allow;
      const answer = payloadString(item.payload, 'answer');
      const requestId = payloadString(item.payload, 'id');
      if (requestId !== null && cardBacked.has(requestId)) {
        // The card that asked is on screen and renders its own settled line —
        // including the answer, which is what this suppression assumed all
        // along and what the card only started doing once the answer was
        // threaded to it. So this row would only repeat it.
        return null;
      }
      return (
        <MessageBubble variant="note">
          {tag(
            allow === true
              ? answer
                ? `✓ answered — ${answer}`
                : '✓ tool approved'
              : '✗ tool denied',
          )}
        </MessageBubble>
      );
    }
    case 'unanswerable': {
      const requestId = payloadString(item.payload, 'id');
      if (requestId !== null && cardBacked.has(requestId)) {
        // The card that asked is on screen; it renders its own expired state
        // (this item is what puts it there — see `unanswerableRequestIds`), so
        // a row beside it would only repeat what the card already says.
        return null;
      }
      const toolName = payloadString(item.payload, 'toolName') ?? 'tool';
      return (
        <MessageBubble variant="note">
          {tag(`⊘ ${toolName} — the turn ended before this was answered`)}
        </MessageBubble>
      );
    }
    case 'call_started': {
      const callee =
        nodeName(payloadString(item.payload, 'calleeNodeId')) ?? 'agent';
      return (
        <MessageBubble variant="call" role={tag(`📞 call → ${callee}`)}>
          <div className="whitespace-pre-wrap break-words">
            {payloadString(item.payload, 'message') ?? ''}
          </div>
        </MessageBubble>
      );
    }
    case 'call_result': {
      // Payload spreads the call ENVELOPE: status 'ok' carries
      // result.{call_id,agent,text}; 'error' carries the prefixed error line.
      const callee =
        nodeName(payloadString(item.payload, 'calleeNodeId')) ?? 'agent';
      if (payloadString(item.payload, 'status') === 'ok') {
        // A compact receipt only: the result TEXT lives in the call block's
        // RESULT card (or, in legacy flat transcripts, in the callee's own
        // final bubble right above) — repeating it here doubled the payoff.
        return (
          <MessageBubble variant="note">
            {tag(`✓ result from ${callee}`)}
          </MessageBubble>
        );
      }
      return (
        <MessageBubble variant="error" role={tag(`✗ call failed ← ${callee}`)}>
          <div className="whitespace-pre-wrap break-words">
            {payloadString(item.payload, 'error') ?? 'call failed'}
          </div>
        </MessageBubble>
      );
    }
    case 'await_collected':
      // Pure plumbing (the broker's pickup bookkeeping) — the ✓ result
      // receipt right beside it says everything the user needs.
      return null;
    case 'call_question': {
      // A call-initiated callee parked on a question — the CALLER (not the
      // user) is expected to answer it via answer_agent. The SenderRow frame
      // names the asking callee; the bubble keeps only the question marker.
      const options = (item.payload as { options?: unknown } | null)?.options;
      const optionLine = Array.isArray(options)
        ? options.filter((o) => typeof o === 'string').join(' / ')
        : '';
      return (
        <MessageBubble variant="call" role="❓ question">
          <div className="whitespace-pre-wrap break-words">
            {payloadString(item.payload, 'question') ?? ''}
            {optionLine ? (
              <span className="text-muted-foreground">{`\n(${optionLine})`}</span>
            ) : null}
          </div>
        </MessageBubble>
      );
    }
    case 'call_answer': {
      const callee =
        nodeName(payloadString(item.payload, 'calleeNodeId')) ?? 'agent';
      const outcome = payloadString(item.payload, 'outcome');
      if (outcome === 'answered') {
        return (
          <MessageBubble variant="call" role={tag(`💬 answered → ${callee}`)}>
            <div className="whitespace-pre-wrap break-words">
              {payloadString(item.payload, 'answer') ?? ''}
            </div>
          </MessageBubble>
        );
      }
      return (
        <MessageBubble variant="error" role={tag('✗ question')}>
          <div className="whitespace-pre-wrap break-words">
            {outcome === 'timeout'
              ? 'timed out — the caller never answered'
              : outcome === 'undelivered'
                ? 'undelivered — the callee ended before the answer arrived'
                : 'orphaned — the caller ended before answering'}
          </div>
        </MessageBubble>
      );
    }
    default:
      return null; // usage / attachment / approval_request (rendered as a card)
  }
});

/**
 * Requests the DAEMON declared unanswerable — its turn settled with the
 * request still pending, so no verdict can ever reach it.
 *
 * Read, not inferred: the daemon knows which turns are live and which requests
 * it actually dropped, while this side could only guess from the order of
 * items. The inference this replaces reconstructed turn scoping from callIds
 * in the transcript, which mistook a callee sub-turn settling for the node's
 * own turn ending and saw nothing at all for a turn that failed to start.
 *
 * TWIN PARSER: the payload is written by
 * `apps/daemon/src/v1/agents/utils/unanswerable.ts` (`UnanswerableWire`). Item
 * payloads are untyped on the wire by design, so a shape change there MUST be
 * mirrored here.
 */
export function unanswerableRequestIds(
  items: readonly ChatItem[],
): Set<string> {
  const dead = new Set<string>();
  for (const item of items) {
    if (item.kind !== 'unanswerable') {
      continue;
    }
    const requestId = payloadString(item.payload, 'id');
    if (requestId) {
      dead.add(requestId);
    }
  }
  return dead;
}

/**
 * Request ids that have an `approval_request` item in the loaded window.
 *
 * Once a verdict lands, {@link ApprovalCard} renders its own settled line —
 * `✓ answered / ✗ declined` on the question branch, `✓ approved / ✗ denied` on
 * the permission branch — so an `approval_verdict` row beside it repeats what
 * the card already says. The row still earns its place when the card is
 * ABSENT: an older turn scrolled out of the loaded window leaves the row as
 * the only surviving record of the answer.
 */
export function cardBackedRequestIds(
  items: readonly ChatItem[],
): ReadonlySet<string> {
  const ids = new Set<string>();
  for (const item of items) {
    if (item.kind === 'approval_request') {
      const id = payloadString(item.payload, 'id');
      if (id) {
        ids.add(id);
      }
    }
  }
  return ids;
}

/**
 * How a verdict row learns whether its card is on screen.
 *
 * A context rather than a prop, for the same reason as
 * `AttachmentLoaderContext`: the shells between `Chats` and a verdict row
 * (`TranscriptEntryView`, `TurnBlock`, `CallBlock`) are memoized on
 * referentially stable props, and threading a set through all three would
 * bloat their signatures and defeat that memoization.
 *
 * Empty outside a provider, which is the SAFE default — an empty set
 * suppresses nothing, so a row rendered without one still records its verdict
 * rather than silently vanishing.
 */
export const CardBackedRequestsContext = createContext<ReadonlySet<string>>(
  new Set<string>(),
);

/**
 * One settled approval, as the transcript recorded it.
 *
 * The ANSWER rides along with the allow/deny because the card that asked the
 * question is the natural place to read it back, and it had nowhere to read it
 * from: a card whose question was answered said `✓ answered` and nothing else,
 * so the user's own words vanished the moment they were sent — "hehe i should
 * also see my answer". The daemon has always written them here (`answer` on the
 * `approval_verdict` payload, recorded only when it was actually folded into
 * the tool input), so this is a value that already existed and was being
 * dropped one map entry short of the screen.
 */
export interface RecordedVerdict {
  allow: boolean;
  /**
   * What the user said, or null — never an answer the daemon withheld, since
   * it only records one it actually delivered.
   *
   * Null is the common case rather than the meaningful one: a plain tool
   * approval carries no words at all, and neither does a question that was
   * declined. A REJECTED card can still carry them, though — `propose_plan`
   * sends the user's note on either verdict, and that note is the most useful
   * thing on a rejection.
   */
  answer: string | null;
}

/** All persisted verdicts of a transcript, keyed by approval request id. */
export function collectVerdicts(
  items: readonly ChatItem[],
): Map<string, RecordedVerdict> {
  const verdicts = new Map<string, RecordedVerdict>();
  for (const item of items) {
    if (item.kind === 'approval_verdict') {
      const id = payloadString(item.payload, 'id');
      if (id) {
        const allow = (item.payload as { allow?: unknown }).allow;
        verdicts.set(id, {
          allow: allow === true,
          answer: payloadString(item.payload, 'answer'),
        });
      }
    }
  }
  return verdicts;
}
