// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { TranscriptEntryView } from './transcript-entry';
import { buildTurnBlocks, groupTranscript } from './transcript-groups';
import type { TranscriptNodeMeta } from './transcript-item';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const NODES: ReadonlyMap<string, TranscriptNodeMeta> = new Map([
  ['writer', { name: 'Writer', kind: 'agent' }],
]);

let seq = 0;
function item(
  kind: ChatItem['kind'],
  payload: unknown,
  nodeId: string | null,
  role: string | null = null,
): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    nodeId,
    seq,
    kind,
    role,
    payload,
    createdAt: '2026-07-28T18:43:00.000Z',
  };
}

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

/** Render one agent turn — an assistant message plus a tool call. */
function renderTurn(soloAgent: boolean, nodeId: string | null): void {
  const entries = buildTurnBlocks(
    groupTranscript([
      item('message', { text: 'Working on it.' }, nodeId, 'assistant'),
      item(
        'tool_call',
        { id: 't1', name: 'Bash', input: { command: 'ls' } },
        nodeId,
      ),
    ]),
  );
  act(() => {
    root.render(
      <>
        {entries.map((entry, index) => (
          <TranscriptEntryView
            key={index}
            entry={entry}
            nodes={NODES}
            chatAgentName="claude"
            soloAgent={soloAgent}
          />
        ))}
      </>,
    );
  });
}

describe('TurnBlock identity frame', () => {
  it('drops the avatar, the card and the sender line for a solo agent', () => {
    // A 1:1 chat has one participant on the agent side — repeating its name
    // and avatar over every turn is noise, so the words sit bare in the flow.
    renderTurn(true, null);

    const block = container.querySelector('[data-role="turn-block"]');
    expect(block).not.toBeNull();
    expect(block?.getAttribute('data-solo')).toBe('true');
    expect(container.querySelector('[data-slot="avatar"]')).toBeNull();
    expect(container.textContent).not.toContain('claude');
    // The agent's actual words still render.
    expect(container.textContent).toContain('Working on it.');
  });

  it('keeps the avatar and the sender line when several agents can speak', () => {
    // A workflow run needs identity: two nodes' turns are otherwise
    // indistinguishable in one flow.
    renderTurn(false, 'writer');

    expect(container.querySelector('[data-slot="avatar"]')).not.toBeNull();
    expect(container.textContent).toContain('Writer');
    expect(container.textContent).toContain('Working on it.');
  });
});

describe('standalone transcript rows', () => {
  it('renders a solo agent’s message without a sender row', () => {
    const entry = groupTranscript([
      item('error', { message: 'it broke' }, null),
    ])[0]!;
    act(() => {
      root.render(
        <TranscriptEntryView
          entry={entry}
          nodes={NODES}
          chatAgentName="claude"
          soloAgent
        />,
      );
    });

    expect(container.querySelector('[data-slot="sender-row"]')).toBeNull();
    expect(container.textContent).toContain('it broke');
  });

  it('keeps the user’s own bubble in a solo chat — the chat still has two sides', () => {
    const entry = groupTranscript([
      item('message', { text: 'do the thing' }, null, 'user'),
    ])[0]!;
    act(() => {
      root.render(
        <TranscriptEntryView
          entry={entry}
          nodes={NODES}
          chatAgentName="claude"
          soloAgent
        />,
      );
    });

    expect(container.querySelector('[data-slot="sender-row"]')).not.toBeNull();
    expect(container.textContent).toContain('You');
  });

  it.each([true, false])(
    'says a delegate’s words are a sub-agent’s (soloAgent=%s)',
    (solo) => {
      // Reproduced in the real UI before this existed: five near-identical
      // reviewer openers rendered as flat main-thread prose, indistinguishable
      // from the agent the user is talking to. `TranscriptItem`'s own
      // `sub-agent` caption cannot cover it — `TurnBlock` draws message rows
      // itself and never reaches that path, and every assistant message is
      // inside a block.
      const entries = buildTurnBlocks(
        groupTranscript([
          item('message', { text: 'Spawning reviewers.' }, null, 'assistant'),
          item(
            'message',
            {
              text: "I'll start by loading criteria.",
              parentToolUseId: 'toolu_1',
            },
            null,
            'assistant',
          ),
        ]),
      );
      act(() => {
        root.render(
          <>
            {entries.map((entry, index) => (
              <TranscriptEntryView
                key={index}
                entry={entry}
                nodes={NODES}
                chatAgentName="claude"
                soloAgent={solo}
              />
            ))}
          </>,
        );
      });

      const blocks = [
        ...container.querySelectorAll('[data-role="turn-block"]'),
      ];
      const main = blocks.find((b) =>
        b.textContent?.includes('Spawning reviewers.'),
      )!;
      const delegate = blocks.find((b) =>
        b.textContent?.includes('loading criteria'),
      )!;

      // Two blocks, not one — a delegate's words are not the agent's own.
      expect(main).not.toBe(delegate);
      expect(delegate.getAttribute('data-subagent')).toBe('toolu_1');
      expect(
        delegate.querySelector('[data-role="subagent-label"]'),
      ).not.toBeNull();
      expect(delegate.textContent).toContain('sub-agent');

      // …and the main thread is NOT labelled, or the marker would mean nothing.
      expect(main.getAttribute('data-subagent')).toBeNull();
      expect(main.querySelector('[data-role="subagent-label"]')).toBeNull();
    },
  );
});
