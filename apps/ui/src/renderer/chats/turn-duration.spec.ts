import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  cliTurnApiMs,
  cliTurnDurationMs,
  formatDuration,
  openTurnWorkedMs,
  scanTurns,
  threadWorkedMs,
  turnDurations,
} from './turn-duration';

let seq = 0;
function item(
  kind: string,
  at: string,
  extra: Partial<ChatItem> = {},
): ChatItem {
  seq += 1;
  return {
    id: `i${seq}`,
    runId: 'r1',
    seq,
    kind,
    role: null,
    payload: null,
    nodeId: null,
    createdAt: at,
    ...extra,
  } as ChatItem;
}

const userAt = (at: string): ChatItem =>
  item('message', at, { role: 'user', payload: { text: 'go' } });

/** A `turn_complete` the CLI timed itself. */
const cliDone = (at: string, durationMs: number, apiMs?: number): ChatItem =>
  item('turn_complete', at, {
    payload: {
      usage: { durationMs, ...(apiMs === undefined ? {} : { apiMs }) },
    },
  });

/** A `turn_complete` from a CLI that reports no timing (every ACP agent). */
const untimedDone = (at: string): ChatItem =>
  item('turn_complete', at, { payload: { usage: { costUsd: 0.1 } } });

describe('cliTurnDurationMs', () => {
  it("reads the CLI's own figure off the payload", () => {
    expect(cliTurnDurationMs({ usage: { durationMs: 7618 } })).toBe(7618);
    expect(cliTurnApiMs({ usage: { apiMs: 7176 } })).toBe(7176);
  });

  it('rejects a figure that is present but unusable, so the fallback is reached', () => {
    // The whole point of returning null rather than the number: a garbage value
    // that is merely PRESENT would suppress the wall-clock measurement and put
    // nonsense on screen in its place.
    expect(cliTurnDurationMs({ usage: { durationMs: -5 } })).toBeNull();
    expect(cliTurnDurationMs({ usage: { durationMs: Number.NaN } })).toBeNull();
    expect(cliTurnDurationMs({ usage: { durationMs: '7618' } })).toBeNull();
    expect(cliTurnDurationMs({ usage: null })).toBeNull();
    expect(cliTurnDurationMs(null)).toBeNull();
  });
});

describe('turnDurations', () => {
  it("prefers the CLI's own clock over the wall clock", () => {
    // The wall span here is 60s; the CLI says it worked 7.618s. The CLI's figure
    // wins because it excludes the waits geniro puts around a turn (the
    // MCP-readiness hold), which the wall clock cannot see.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      cliDone('2026-08-14T10:01:00.000Z', 7618),
    ];
    const durations = turnDurations(items);
    expect(durations.get(items[1]!.id)).toEqual({ ms: 7618, source: 'cli' });
  });

  it('measures the wall clock for a CLI that reports no timing', () => {
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      untimedDone('2026-08-14T10:00:09.100Z'),
    ];
    expect(turnDurations(items).get(items[1]!.id)).toEqual({
      ms: 9_100,
      source: 'wall',
    });
  });

  it('subtracts time parked on an approval card from the wall clock', () => {
    // The reason the fallback is not a plain end-minus-start: a turn blocked on
    // a question card is timing a HUMAN. Without this the two clocks would mean
    // different things — claude's figure excludes the wait, so a cursor turn
    // would report the half hour its user spent at lunch as work.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      item('approval_request', '2026-08-14T10:00:05.000Z', {
        payload: { id: 'req-1', toolName: 'AskUserQuestion' },
      }),
      item('approval_verdict', '2026-08-14T10:30:05.000Z', {
        payload: { id: 'req-1', verdict: 'allow' },
      }),
      untimedDone('2026-08-14T10:30:12.000Z'),
    ];
    // 30m12s elapsed, 30m of it parked → 12s of work.
    expect(turnDurations(items).get(items[3]!.id)).toEqual({
      ms: 12_000,
      source: 'wall',
    });
  });

  it('counts a card still open at the settle as parked right up to it', () => {
    // An `unanswerable` close is one path here; a turn that simply ended with
    // the card open is the other, and it must not read as work either.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      item('approval_request', '2026-08-14T10:00:04.000Z', {
        payload: { id: 'req-1' },
      }),
      untimedDone('2026-08-14T10:20:00.000Z'),
    ];
    expect(turnDurations(items).get(items[2]!.id)?.ms).toBe(4_000);
  });

  it('does not restart the clock for a follow-up sent INTO a running turn', () => {
    // A second user message can be delivered mid-turn (claude's stream-json
    // stdin accepts one). The turn being measured began at the FIRST message —
    // taking the later one would report a long turn as a short one.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      userAt('2026-08-14T10:00:50.000Z'),
      untimedDone('2026-08-14T10:01:00.000Z'),
    ];
    expect(turnDurations(items).get(items[2]!.id)?.ms).toBe(60_000);
  });

  it('measures each turn separately across a multi-turn thread', () => {
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      untimedDone('2026-08-14T10:00:10.000Z'),
      userAt('2026-08-14T11:00:00.000Z'),
      untimedDone('2026-08-14T11:00:20.000Z'),
    ];
    const durations = turnDurations(items);
    expect(durations.get(items[1]!.id)?.ms).toBe(10_000);
    // Crucially NOT 1h20s: the hour between turns is the user reading, and the
    // second turn's clock starts at its own message.
    expect(durations.get(items[3]!.id)?.ms).toBe(20_000);
  });

  it("ignores a workflow node's own turn end", () => {
    // A node's `turn_complete` ends that node's work, not a turn of the
    // conversation — its cost and context live in the agents panel.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      item('turn_complete', '2026-08-14T10:00:05.000Z', {
        nodeId: 'node-a',
        payload: { usage: { durationMs: 5000 } },
      }),
    ];
    expect(turnDurations(items).size).toBe(0);
  });

  it('yields nothing for a turn whose start is not in the transcript', () => {
    // An `afterSeq` replay can begin mid-turn. Measuring from the epoch would
    // report 56 years; showing nothing is the honest answer.
    const items = [untimedDone('2026-08-14T10:00:10.000Z')];
    expect(turnDurations(items).size).toBe(0);
  });

  it('measures a cancelled and a failed turn too', () => {
    // Both are turns that WORKED — a Stop after four minutes spent four
    // minutes, and hiding that would make an expensive abandoned turn look free.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      item('turn_cancelled', '2026-08-14T10:04:00.000Z', { payload: {} }),
      userAt('2026-08-14T10:05:00.000Z'),
      item('error', '2026-08-14T10:05:30.000Z', {
        payload: { message: 'boom' },
      }),
    ];
    const durations = turnDurations(items);
    expect(durations.get(items[1]!.id)?.ms).toBe(240_000);
    expect(durations.get(items[3]!.id)?.ms).toBe(30_000);
  });
});

describe('threadWorkedMs', () => {
  it('sums the turns rather than spanning first to last', () => {
    // The distinction the feature exists for: this thread spans 1h0m20s and
    // worked 30s.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      untimedDone('2026-08-14T10:00:10.000Z'),
      userAt('2026-08-14T11:00:00.000Z'),
      untimedDone('2026-08-14T11:00:20.000Z'),
    ];
    expect(threadWorkedMs(turnDurations(items))).toEqual({
      ms: 30_000,
      turns: 2,
    });
  });

  it('reports zero for a thread with no settled turn', () => {
    expect(threadWorkedMs(turnDurations([]))).toEqual({ ms: 0, turns: 0 });
  });
});

describe('scanTurns + openTurnWorkedMs', () => {
  const at = (iso: string): number => Date.parse(iso);

  it('reports no open turn once the last one settled', () => {
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      untimedDone('2026-08-14T10:00:10.000Z'),
    ];
    expect(scanTurns(items).open).toBeNull();
    expect(openTurnWorkedMs(null, at('2026-08-14T11:00:00.000Z'))).toBe(0);
  });

  it('measures the turn in flight from its own start, not from now', () => {
    // The defect this exists for: the header's total stood still for the whole
    // of a turn. A figure measured from the reader's mount would restart at
    // zero on every reload instead.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      untimedDone('2026-08-14T10:00:10.000Z'),
      userAt('2026-08-14T10:05:00.000Z'),
    ];
    const { durations, open } = scanTurns(items);
    expect(threadWorkedMs(durations).ms).toBe(10_000);
    expect(openTurnWorkedMs(open, at('2026-08-14T10:06:30.000Z'))).toBe(90_000);
  });

  it('stops counting while the turn sits on an unanswered card', () => {
    // Ticking here would report the user's own thinking time as the agent's
    // work — the very thing the wall-clock fallback subtracts for a settled
    // turn, so the live reading has to do it too or the two mean different
    // things.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      item('approval_request', '2026-08-14T10:00:20.000Z', {
        payload: { id: 'req-1' },
      }),
    ];
    const { open } = scanTurns(items);
    expect(openTurnWorkedMs(open, at('2026-08-14T10:00:30.000Z'))).toBe(20_000);
    // Ten minutes later, still unanswered: the same 20s of work.
    expect(openTurnWorkedMs(open, at('2026-08-14T10:10:30.000Z'))).toBe(20_000);
  });

  it('resumes counting once the card is answered', () => {
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      item('approval_request', '2026-08-14T10:00:20.000Z', {
        payload: { id: 'req-1' },
      }),
      item('approval_verdict', '2026-08-14T10:10:20.000Z', {
        payload: { id: 'req-1', verdict: 'allow' },
      }),
    ];
    const { open } = scanTurns(items);
    // 10m25s elapsed, 10m of it parked → 25s worked.
    expect(openTurnWorkedMs(open, at('2026-08-14T10:10:25.000Z'))).toBe(25_000);
  });

  it('never reports a negative figure from a clock that moved backwards', () => {
    const { open } = scanTurns([userAt('2026-08-14T10:00:00.000Z')]);
    expect(openTurnWorkedMs(open, at('2026-08-14T09:59:00.000Z'))).toBe(0);
  });

  it('still answers the settled durations exactly as turnDurations does', () => {
    // The two share one scan; a divergence would mean the transcript rows and
    // the header disagreed about the same turn.
    const items = [
      userAt('2026-08-14T10:00:00.000Z'),
      cliDone('2026-08-14T10:00:10.000Z', 7618),
      userAt('2026-08-14T10:05:00.000Z'),
    ];
    expect(scanTurns(items).durations).toEqual(turnDurations(items));
  });
});

describe('formatDuration', () => {
  it('keeps one decimal below ten seconds and drops it above', () => {
    // Most turns land in the seconds, where rounding 7.6 and 7.4 both to `7s`
    // throws away the only digit that separates them.
    expect(formatDuration(7618)).toBe('7.6s');
    expect(formatDuration(400)).toBe('0.4s');
    // A whole second keeps no pointless `.0`.
    expect(formatDuration(8000)).toBe('8s');
    expect(formatDuration(12_400)).toBe('12s');
    expect(formatDuration(65_000)).toBe('1m 5s');
  });

  it('never renders a negative duration', () => {
    expect(formatDuration(-5)).toBe('0s');
  });
});
