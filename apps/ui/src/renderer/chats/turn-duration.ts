import { createContext } from 'react';

import type { ItemDto as ChatItem } from '../autogenerated';
import { formatElapsed } from './live-row';
import { TERMINAL_KINDS } from './settled-status';

/**
 * How long each turn actually WORKED, and the thread's total.
 *
 * The question this answers is not "when did this chat last speak" — the
 * sidebar's relative time already says that — but "how much work happened
 * here", which nothing showed. A live clock ran in the header while a turn was
 * in flight and vanished the moment it settled, so a finished turn reported its
 * cost and never its time; meanwhile a sub-agent block has said `took 13s` for
 * two milestones, which left a delegate better instrumented than the agent that
 * launched it.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/adapters/claude/utils/claude-usage.utils.ts`
 * writes the `usage.durationMs` / `usage.apiMs` this reads, and
 * `apps/daemon/src/v1/agents/utils/event-to-item.ts` carries them into the
 * `turn_complete` row. An item payload is `z.unknown()` on the wire BY DESIGN —
 * every kind carries a different shape — so no generated type spans the two
 * sides. Renaming a key there means renaming it here.
 *
 * **Two clocks, and they disagree on purpose.** A CLI that times its own turn
 * (claude) reports the stretch it was WORKING, which excludes both waits geniro
 * puts around a turn: the first-prompt MCP-readiness hold, and any time parked
 * on an approval card. Where no CLI figure exists (every ACP agent) the wall
 * clock is all there is — so this measures it from the turn's own durable rows
 * and then SUBTRACTS the parked stretches, because a turn blocked half an hour
 * on a question card did not work for half an hour, and reporting that it did
 * would make the fallback mean something different from the primary. The parked
 * intervals are readable because both halves are durable rows: an
 * `approval_request` and the `approval_verdict` (or `unanswerable`) that closes
 * it.
 */

/**
 * A SETTLED duration: `0.4s`, `7.6s`, `12s`, `1m 5s`.
 *
 * One decimal below ten seconds and none above, which is the difference between
 * this and {@link formatElapsed}: that one drives a clock that reticks every
 * second, where a jittering tenth is noise. A settled figure is read once and
 * never moves, and most turns land in the seconds — rounding 7.6s and 7.4s both
 * to `7s` throws away the only digit that distinguishes them.
 *
 * Delegates above the threshold rather than restating the minutes form, so the
 * two cannot drift into spelling `1m 5s` differently.
 */
export function formatDuration(ms: number): string {
  const safe = Math.max(0, ms);
  if (safe >= 10_000) {
    return formatElapsed(safe);
  }
  // `toFixed(1)` then strip a trailing `.0`, so a whole second reads `8s` and
  // not `8.0s` — the decimal is there to separate close values, not decoration.
  return `${(safe / 1000).toFixed(1).replace(/\.0$/, '')}s`;
}

/** Which clock produced a figure — so a reader can be told what it means. */
export type TurnDurationSource = 'cli' | 'wall';

export interface TurnDuration {
  ms: number;
  source: TurnDurationSource;
}

/**
 * How long each of this run's turns worked, keyed by the terminal item that
 * ends it.
 *
 * A context and not a prop, for the reason `RunActivityContext` and
 * `RunSettledContext` are: the `turn_complete` row that shows the figure sits
 * inside shells memoized on referentially stable props, and threading a map
 * that grows with every turn through all of them would defeat that memoization
 * for every row in the transcript. It lives here rather than beside those two
 * so the module holding `formatElapsed` need not import back from this one —
 * the same reason `subagent-context.ts` stands alone.
 *
 * Empty outside a provider, which reads as "no figure for this turn": the row
 * then shows exactly what it showed before.
 */
export const TurnDurationContext = createContext<
  ReadonlyMap<string, TurnDuration>
>(new Map());

/** Kinds that close an open approval card, ending a parked stretch. */
const APPROVAL_CLOSING_KINDS: ReadonlySet<string> = new Set([
  'approval_verdict',
  'unanswerable',
]);

/**
 * Read the CLI's own turn duration off a `turn_complete` payload.
 *
 * Rejects a non-finite or negative number rather than passing it through: the
 * consumer's whole fallback exists for "the CLI said nothing", and a garbage
 * figure that is merely present would suppress it.
 */
export function cliTurnDurationMs(payload: unknown): number | null {
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const usage = (payload as { usage?: unknown }).usage;
  if (typeof usage !== 'object' || usage === null) {
    return null;
  }
  const ms = (usage as { durationMs?: unknown }).durationMs;
  return typeof ms === 'number' && Number.isFinite(ms) && ms >= 0 ? ms : null;
}

/** The API half of the split, on the same terms as {@link cliTurnDurationMs}. */
export function cliTurnApiMs(payload: unknown): number | null {
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const usage = (payload as { usage?: unknown }).usage;
  if (typeof usage !== 'object' || usage === null) {
    return null;
  }
  const ms = (usage as { apiMs?: unknown }).apiMs;
  return typeof ms === 'number' && Number.isFinite(ms) && ms >= 0 ? ms : null;
}

function parsedAt(iso: string): number | null {
  const at = Date.parse(iso);
  return Number.isFinite(at) ? at : null;
}

/**
 * Per-turn durations for a run's transcript, keyed by the id of the terminal
 * item that ENDS each turn.
 *
 * Keyed by that item and not by an index, because the consumer is the row
 * renderer: a `turn_complete` row has to look up its own figure, and it knows
 * only its own id. RUN-level turns only — a workflow node's own `turn_complete`
 * ends that node's work, not a turn of the conversation, and its cost and
 * context already live in the agents panel.
 *
 * A turn with no start (a transcript whose history begins mid-turn, which a
 * `afterSeq` replay can produce) yields nothing rather than measuring from the
 * epoch.
 */
export function turnDurations(
  items: readonly ChatItem[],
): ReadonlyMap<string, TurnDuration> {
  return scanTurns(items).durations;
}

/**
 * The turn still IN FLIGHT at the end of the transcript, if there is one —
 * everything needed to keep measuring it as the clock moves.
 *
 * A settled turn's figure is a number; a running one cannot be, for the reason
 * `turnStartedAt` is a timestamp rather than an elapsed count: a duration
 * computed by the owner freezes the moment it is handed over. So the pieces
 * travel and the consumer does the subtraction, once a second, against its own
 * `Date.now()`.
 */
export interface OpenTurn {
  /** When this turn began. */
  startedAt: number;
  /** Parked stretches inside it that have already CLOSED. */
  parkedMs: number;
  /**
   * Approval cards still open, by when each opened.
   *
   * Their wait is parked right up to `now` — which is what makes the live total
   * STOP while the run sits on a question. That is not a nicety: a turn parked
   * overnight would otherwise report eight hours of work nobody did, and this
   * figure exists precisely to not be the wall clock.
   */
  openSince: readonly number[];
}

/**
 * The open turn with a HOLD counted as a parked stretch — the turn as it should
 * be MEASURED once the agent has stopped talking.
 *
 * A hold is the daemon keeping the turn open for background work the agent
 * launched: it has said its piece, and the process is alive only for its
 * listeners. That is the same non-work as a turn parked on an approval card,
 * and `openSince` is already how such a stretch stops the live total — so this
 * adds the hold to it rather than inventing a second mechanism.
 *
 * A separate function rather than a branch inside {@link scanTurns}, because a
 * hold leaves NO transcript row to scan for: `turn_held` maps to no item, on
 * purpose. It is a live fact about the run, and it arrives from the run-status
 * channel.
 *
 * `heldSince` undefined means not held, and the turn passes through untouched.
 */
export function parkWhileHeld(
  open: OpenTurn | null,
  heldSince: number | undefined,
): OpenTurn | null {
  if (open === null || heldSince === undefined) {
    return open;
  }
  return { ...open, openSince: [...open.openSince, heldSince] };
}

/**
 * What the in-flight turn has worked as of `now` — 0 when nothing is running.
 *
 * Measured the same way the wall-clock fallback measures a settled turn, so the
 * live figure and the one that replaces it at the settle mean the same thing.
 * A CLI that times its own turn (claude) reports a slightly SMALLER number than
 * the wall clock, so the total can tick back a second or two as a turn lands;
 * that is the price of the primary clock being the honest one, and it is
 * smaller than the error of showing a frozen total for the whole turn.
 */
export function openTurnWorkedMs(open: OpenTurn | null, now: number): number {
  if (open === null) {
    return 0;
  }
  let parked = open.parkedMs;
  // The UNION of the open stretches, not their sum — and they all end at `now`,
  // so the union is simply the earliest of them to here.
  //
  // Summing was wrong the moment two of them overlapped, which they routinely
  // do: a turn can hold several approval cards at once (`openSince` is a list
  // for that reason), and a hold sits on top of whatever is already open. Two
  // stretches of ten minutes inside a ten-minute turn subtracted twenty and the
  // figure pinned itself at 0 — a turn that had worked reporting that it had
  // not. Found by a test written for the hold; it was reachable before that.
  if (open.openSince.length > 0) {
    parked += Math.max(0, now - Math.min(...open.openSince));
  }
  return Math.max(0, now - open.startedAt - parked);
}

/** Both readings off ONE pass: the settled turns, and the one still running. */
export function scanTurns(items: readonly ChatItem[]): {
  durations: ReadonlyMap<string, TurnDuration>;
  open: OpenTurn | null;
} {
  const durations = new Map<string, TurnDuration>();
  let startedAt: number | null = null;
  /** Open approval cards, by request id — a turn can have several at once. */
  const parkedSince = new Map<string, number>();
  let parkedMs = 0;

  for (const item of items) {
    if (item.nodeId !== null) {
      continue;
    }
    const at = parsedAt(item.createdAt);
    if (item.kind === 'message' && item.role === 'user') {
      // A follow-up delivered INTO a running turn must not restart the clock:
      // the turn it joined began earlier and is still the one being measured.
      startedAt ??= at;
      continue;
    }
    if (item.kind === 'approval_request' && at !== null) {
      const id = approvalId(item.payload);
      // Keyed by the request id so two cards open at once are two intervals;
      // an id-less request is ignored rather than guessed at, which costs the
      // subtraction and never invents one.
      if (id !== null) {
        parkedSince.set(id, at);
      }
      continue;
    }
    if (APPROVAL_CLOSING_KINDS.has(item.kind) && at !== null) {
      const id = approvalId(item.payload);
      const since = id === null ? undefined : parkedSince.get(id);
      if (since !== undefined && id !== null) {
        parkedSince.delete(id);
        parkedMs += Math.max(0, at - since);
      }
      continue;
    }
    if (!TERMINAL_KINDS.has(item.kind)) {
      continue;
    }
    // The turn ended. A card still open when it did was never answered — the
    // wait it caused is real elapsed time nobody worked through, so it counts
    // as parked right up to the settle.
    for (const since of parkedSince.values()) {
      if (at !== null) {
        parkedMs += Math.max(0, at - since);
      }
    }
    parkedSince.clear();

    const cli = cliTurnDurationMs(item.payload);
    if (cli !== null) {
      durations.set(item.id, { ms: cli, source: 'cli' });
    } else if (startedAt !== null && at !== null) {
      durations.set(item.id, {
        ms: Math.max(0, at - startedAt - parkedMs),
        source: 'wall',
      });
    }
    startedAt = null;
    parkedMs = 0;
  }
  return {
    durations,
    // A turn with a start and no terminal row yet is the one in flight. The
    // scan already carries its parked stretches, so nothing is re-derived.
    open:
      startedAt === null
        ? null
        : {
            startedAt,
            parkedMs,
            openSince: [...parkedSince.values()],
          },
  };
}

/** The `id` an approval row pairs on — both halves carry it. */
function approvalId(payload: unknown): string | null {
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const id = (payload as { id?: unknown }).id;
  return typeof id === 'string' && id.length > 0 ? id : null;
}

/**
 * What a whole thread worked: the sum of its turns.
 *
 * The sum and NOT `updatedAt − createdAt`, which is the number that looks
 * plausible and is wrong — a chat left open for three days with five minutes of
 * work in it would read `3d`. Turns are what the agent actually spent, so
 * summing them is the only figure that answers "how long did this work take".
 */
export function threadWorkedMs(durations: ReadonlyMap<string, TurnDuration>): {
  ms: number;
  turns: number;
} {
  let ms = 0;
  for (const duration of durations.values()) {
    ms += duration.ms;
  }
  return { ms, turns: durations.size };
}
