import { useCallback, useMemo } from 'react';

import type { CliKind } from '../../shared/contracts';
import type { AgentContextWindowListingDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { useAgentVocabulary, vocabularyVariant } from './use-agent-vocabulary';

/** The listing plus whether it is still being fetched — see `AgentEffortsState`. */
export type AgentContextWindowsState = AgentContextWindowListingDto & {
  loading: boolean;
};

/** Nothing known yet — one frozen value, so an effect keyed on it is stable. */
const NOTHING_YET: AgentContextWindowListingDto = {
  windows: [],
  unavailableReason: null,
  unavailableKind: null,
};

/**
 * The context-window sizes one agent CLI can run ONE MODEL at, as its adapter
 * reports them.
 *
 * The twin of {@link useAgentEfforts}, and per model even more strictly: swept
 * on the daemon side across a cursor account's thirty-four models, twelve carry
 * the setting at all and the vocabularies differ between them (`300k|1m`,
 * `272k|1m`, `200k|1m`). Nothing is hardcoded here — the sizes are the CLI's
 * own words, and the number they actually produce is what the agent then
 * reports about its own window, which the context meter already draws.
 *
 * A null model answers with the sentence saying a model has to be picked first:
 * unlike the effort chip there is no CLI-wide union to stand in, because a
 * window size means nothing apart from the model that offered it.
 *
 * An EMPTY list always arrives with its reason — this CLI has no such control,
 * this model runs at one fixed window, or the CLI could not be asked — so the
 * chip can say so rather than vanish. Caching (keyed by kind AND model), the
 * stale-response guard and the failure fallback are
 * {@link useAgentVocabulary}'s, shared with the model and effort pickers.
 */
export function useAgentContextWindows(
  agentsApi: DaemonApis['agents'] | null,
  kind: CliKind | null,
  model: string | null = null,
  /**
   * The ACCOUNT this question is about — the run's config directory, or null
   * for the CLI's own. It is part of the QUESTION, not a refinement: a
   * subscription decides this vocabulary, so two profiles genuinely have two
   * answers (measured — one login's two profiles report `max` and `team` from
   * the same binary).
   */
  configDir: string | null = null,
): AgentContextWindowsState {
  const fetchFor = useCallback(
    async (agent: CliKind) => [
      await agentsApi!.listAgentContextWindows({
        agent,
        // Omitted rather than sent empty — `''` is not the question the daemon
        // reads an absent model as.
        ...(model ? { model } : {}),
        ...(configDir ? { configDir } : {}),
      }),
    ],
    [agentsApi, model, configDir],
  );
  const { items, loading } = useAgentVocabulary<AgentContextWindowListingDto>(
    kind,
    agentsApi && fetchFor,
    // The cache key's second half: without it a model switch serves the
    // previous model's sizes, which is the defect this whole shape prevents.
    vocabularyVariant(model, configDir),
  );
  const listing = items[0] ?? NOTHING_YET;
  return useMemo(() => ({ ...listing, loading }), [listing, loading]);
}
