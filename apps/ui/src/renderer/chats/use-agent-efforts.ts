import { useCallback } from 'react';

import type { CliKind } from '../../shared/contracts';
import type { AgentEffortDto as AgentEffort } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { useAgentVocabulary } from './use-agent-vocabulary';

/**
 * The reasoning-effort levels one agent CLI accepts, as its adapter reports
 * them.
 *
 * Nothing is hardcoded on this side — the levels are a CLI's own vocabulary
 * (`claude --effort`, whose accepted set is wider than its `--help` admits), so
 * the daemon owns the list and this hook only fetches it.
 *
 * An EMPTY list is the meaningful answer for a CLI with no effort control at
 * all, and it is also what a failed fetch yields: in both cases the composer
 * omits the chip rather than offering a control over nothing. Caching, the
 * stale-response guard and that fallback are {@link useAgentVocabulary}'s —
 * shared with the model picker so a fix to either cannot reach only one.
 */
export function useAgentEfforts(
  agentsApi: DaemonApis['agents'] | null,
  kind: CliKind | null,
): AgentEffort[] {
  const fetchFor = useCallback(
    (agent: CliKind) => agentsApi!.listAgentEfforts({ agent }),
    [agentsApi],
  );
  return useAgentVocabulary<AgentEffort>(kind, agentsApi && fetchFor);
}
