import { useCallback, useMemo } from 'react';

import type { CliKind } from '../../shared/contracts';
import type { AgentModelParameterListingDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { useAgentVocabulary, vocabularyVariant } from './use-agent-vocabulary';

/** The listing plus whether it is still being fetched — see `AgentEffortsState`. */
export type AgentModelParametersState = AgentModelParameterListingDto & {
  loading: boolean;
};

/** Nothing known yet — one frozen value, so an effect keyed on it is stable. */
const NOTHING_YET: AgentModelParameterListingDto = {
  parameters: [],
  unavailableReason: null,
};

/**
 * Every OTHER setting ONE MODEL of a CLI offers — whatever it enumerates beyond
 * the model, its effort and its context window, each of which has a control and
 * a hook of its own.
 *
 * The third of three vocabulary hooks over one question, and the only one whose
 * answer this app cannot name in advance: the ids and their values are the
 * CLI's, so a setting the vendor adds reaches the composer without a change
 * here. `model` is part of the QUESTION for the same measured reason it is in
 * `useAgentEfforts`, only more sharply — probed 2026-08-26 on cursor-agent
 * 2026.08.11-e8db854, `optimize_for` exists on `auto-smart` alone, `thinking`
 * and `fast` on other models, and `gemini-3.1-pro` offers none at all. With no
 * model named the daemon answers empty, since there is no union worth serving.
 *
 * Caching (keyed by kind AND model), the stale-response guard and the failure
 * fallback are {@link useAgentVocabulary}'s, shared with its two siblings.
 */
export function useAgentModelParameters(
  agentsApi: DaemonApis['agents'] | null,
  kind: CliKind | null,
  model: string | null = null,
  /**
   * The ACCOUNT this question is about — the run's config directory, or null
   * for the CLI's own. It is part of the QUESTION, not a refinement: a
   * subscription decides this vocabulary, so two profiles genuinely have two
   * answers (measured — one login's two profiles report `max` and `team` from
   * the same binary).
   */
  configDir: string | null = null,
): AgentModelParametersState {
  const fetchFor = useCallback(
    async (agent: CliKind) => [
      await agentsApi!.listAgentModelParameters({
        agent,
        // Omitted rather than sent empty, exactly as the effort hook does: the
        // daemon reads an absent model as "no model named", and `''` is not
        // that question.
        ...(model ? { model } : {}),
        ...(configDir ? { configDir } : {}),
      }),
    ],
    [agentsApi, model, configDir],
  );
  const { items, loading } = useAgentVocabulary<AgentModelParameterListingDto>(
    kind,
    agentsApi && fetchFor,
    // The cache key's second half. Without it a model switch serves the
    // previous model's parameters from cache — which for this listing is not a
    // stale vocabulary but a different SET of chips.
    vocabularyVariant(model, configDir),
  );
  const listing = items[0] ?? NOTHING_YET;
  return useMemo(() => ({ ...listing, loading }), [listing, loading]);
}
