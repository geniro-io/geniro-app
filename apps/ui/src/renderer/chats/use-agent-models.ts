import { useCallback } from 'react';

import type { CliKind } from '../../shared/contracts';
import type { AgentModel } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import {
  requestAgentVocabulary,
  vocabularyPart,
} from './agent-vocabulary-request';
import { useAgentVocabulary, vocabularyVariant } from './use-agent-vocabulary';

export type AgentModelsState = {
  models: AgentModel[];
  /** True while this CLI's model list is still being fetched. */
  loading: boolean;
};

/**
 * The models one agent CLI accepts, as that CLI reports them.
 *
 * Nothing is hardcoded on this side: the daemon asks the CLI itself
 * (`cursor-agent models`, and for claude the account models it caches for its
 * own picker) and falls back to the documented aliases when the CLI cannot be
 * asked, so the picker tracks whatever is installed without an app release.
 *
 * A fetch failure yields an empty list; the picker then shows only its
 * "default model" row, which still starts a run. Caching, the stale-response
 * guard and that fallback are {@link useAgentVocabulary}'s — shared with the
 * effort picker so a fix to either cannot reach only one of them.
 */
export function useAgentModels(
  agentsApi: DaemonApis['agents'] | null,
  kind: CliKind | null,
  /**
   * The ACCOUNT this question is about — the run's config directory, or null
   * for the CLI's own. It is part of the QUESTION, not a refinement: a
   * subscription decides this vocabulary, so two profiles genuinely have two
   * answers (measured — one login's two profiles report `max` and `team` from
   * the same binary).
   */
  configDir: string | null = null,
  /**
   * The model the picker's OTHER hooks are asking about, or null.
   *
   * Not part of this question — the model list does not depend on it, and the
   * cache key below leaves it out — but the vocabulary is ONE answer, and asking
   * with the model the effort, window and parameter hooks name is what lets all
   * four share one request (`requestAgentVocabulary`). Leave it out and the
   * picker sends two.
   */
  model: string | null = null,
): AgentModelsState {
  // `model` in the deps re-runs nothing that is cached: the vocabulary hook
  // fetches only for a key it has no answer for, and the key leaves the model
  // out. It only decides which request a fetch still to come shares.
  const fetchFor = useCallback(
    async (agent: CliKind) =>
      vocabularyPart(
        (await requestAgentVocabulary(agentsApi!, agent, model, configDir))
          .models,
        'models',
      ),
    [agentsApi, configDir, model],
  );
  const { items, loading } = useAgentVocabulary<AgentModel>(
    kind,
    agentsApi && fetchFor,
    // The cache key's second half. Without it the first profile to ask has its
    // account's models served to every other — which is the daemon-side defect
    // this mirrors, moved one layer up.
    vocabularyVariant(null, configDir),
    30_000,
  );
  return { models: items, loading };
}
