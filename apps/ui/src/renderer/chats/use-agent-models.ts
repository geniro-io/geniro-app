import { useEffect, useRef, useState } from 'react';

import type { CliKind } from '../../shared/contracts';
import type { AgentModelDto as AgentModel } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';

/**
 * The models one agent CLI accepts, as that CLI reports them.
 *
 * Nothing is hardcoded on this side: the daemon asks the CLI itself
 * (`cursor-agent models`, and for claude the account models it caches for its
 * own picker) and falls back to the documented aliases when the CLI cannot be
 * asked, so the picker tracks whatever is installed without an app release.
 * Cached per kind for the session — the daemon re-asks on a CLI upgrade.
 *
 * A fetch failure yields an empty list; the picker then shows only its
 * "default model" row, which still starts a run.
 */
export function useAgentModels(
  agentsApi: DaemonApis['agents'] | null,
  kind: CliKind | null,
): AgentModel[] {
  const cacheRef = useRef(new Map<CliKind, AgentModel[]>());
  const [models, setModels] = useState<AgentModel[]>([]);

  useEffect(() => {
    if (kind === null || agentsApi === null) {
      setModels([]);
      return;
    }
    const cached = cacheRef.current.get(kind);
    if (cached) {
      setModels(cached);
      return;
    }
    let stale = false;
    void agentsApi
      .listAgentModels({ agent: kind })
      .then((list) => {
        cacheRef.current.set(kind, list);
        if (!stale) {
          setModels(list);
        }
      })
      .catch(() => {
        if (!stale) {
          setModels([]);
        }
      });
    return () => {
      // The user switched agents mid-flight — a late answer for the previous
      // kind must not land in the picker for the current one.
      stale = true;
    };
  }, [agentsApi, kind]);

  return models;
}
