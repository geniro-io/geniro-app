// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { AgentSkillDto as AgentSkill } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { useAgentSkills } from './use-agent-skills';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const skill = (name: string): AgentSkill => ({
  name,
  description: null,
  kind: 'command',
  source: 'cli',
});

type ListSkills = DaemonApis['agents']['listAgentSkills'];

function api(listAgentSkills: ReturnType<typeof vi.fn>): DaemonApis['agents'] {
  return {
    listAgentSkills: listAgentSkills as unknown as ListSkills,
  } as unknown as DaemonApis['agents'];
}

/** Mount the hook; `render(typing)` re-renders it with that flag. */
async function mount(agentsApi: DaemonApis['agents']): Promise<{
  latest: () => string[];
  render: (typingCommand: boolean) => Promise<void>;
}> {
  let latest: AgentSkill[] = [];
  function Probe({ typingCommand }: { typingCommand: boolean }): null {
    latest = useAgentSkills(
      agentsApi,
      [{ kind: 'claude', configDir: null }],
      '/repo',
      typingCommand,
    );
    return null;
  }
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  const render = async (typingCommand: boolean): Promise<void> => {
    await act(async () => {
      root!.render(<Probe typingCommand={typingCommand} />);
    });
  };
  await render(false);
  return { latest: () => latest.map((entry) => entry.name), render };
}

describe('useAgentSkills', () => {
  it('refreshes a stale first answer when the user starts typing a command', async () => {
    // The reported case: the first read came back without the plugin's
    // commands, and the popup went on offering that read for the whole session.
    const listAgentSkills = vi
      .fn()
      .mockResolvedValueOnce([skill('compact')])
      .mockResolvedValueOnce([skill('compact'), skill('geniro:resolve')]);
    const { latest, render } = await mount(api(listAgentSkills));
    expect(latest()).toEqual(['compact']);

    await render(true);

    expect(listAgentSkills).toHaveBeenCalledTimes(2);
    expect(latest()).toEqual(['compact', 'geniro:resolve']);
  });

  it('recovers from a failed first read on the next command', async () => {
    const listAgentSkills = vi
      .fn()
      .mockRejectedValueOnce(new Error('timeout'))
      .mockResolvedValueOnce([skill('geniro:resolve')]);
    const { latest, render } = await mount(api(listAgentSkills));
    expect(latest()).toEqual([]);

    await render(true);

    expect(latest()).toEqual(['geniro:resolve']);
  });

  it('keeps the answer on screen when a refresh fails', async () => {
    const listAgentSkills = vi
      .fn()
      .mockResolvedValueOnce([skill('geniro:resolve')])
      .mockRejectedValueOnce(new Error('daemon restarting'));
    const { latest, render } = await mount(api(listAgentSkills));

    await render(true);

    expect(listAgentSkills).toHaveBeenCalledTimes(2);
    expect(latest()).toEqual(['geniro:resolve']);
  });

  it('asks each target under its OWN profile and unions the answers', async () => {
    // Two agents of one CLI on two accounts have two lists — one directory for
    // the whole set would read one account's list twice.
    const listAgentSkills = vi.fn(({ configDir }: { configDir?: string }) =>
      Promise.resolve(
        configDir === '/lab' ? [skill('geniro:resolve')] : [skill('compact')],
      ),
    );
    let latest: AgentSkill[] = [];
    // Built once: a client rebuilt per render is a new effect dependency each
    // time, and the hook would refetch forever.
    const agentsApi = api(listAgentSkills);
    function Probe(): null {
      latest = useAgentSkills(
        agentsApi,
        [
          { kind: 'claude', configDir: '/lab' },
          { kind: 'claude', configDir: null },
        ],
        '/repo',
      );
      return null;
    }
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
    await act(async () => {
      root!.render(<Probe />);
    });

    expect(listAgentSkills).toHaveBeenCalledWith({
      agent: 'claude',
      cwd: '/repo',
      configDir: '/lab',
    });
    expect(listAgentSkills).toHaveBeenCalledWith({
      agent: 'claude',
      cwd: '/repo',
    });
    expect(latest.map((entry) => entry.name).sort()).toEqual([
      'compact',
      'geniro:resolve',
    ]);
  });

  it('serves the cache, without asking, when no command is being typed', async () => {
    const listAgentSkills = vi.fn().mockResolvedValue([skill('compact')]);
    const { latest, render } = await mount(api(listAgentSkills));

    await render(true);
    await render(false);

    expect(listAgentSkills).toHaveBeenCalledTimes(2);
    expect(latest()).toEqual(['compact']);
  });
});
