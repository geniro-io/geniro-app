import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { latestShowArtifactResultSeq } from './use-artifact-sharing';

const SHOW_ARTIFACT = 'mcp__geniro-r1__show_artifact';

function showCall(seq: number, id: string): ChatItem {
  return {
    id: `r1-${seq}`,
    runId: 'r1',
    memberId: null,
    seq,
    kind: 'tool_call',
    role: null,
    payload: { id, name: SHOW_ARTIFACT },
    createdAt: 'now',
  };
}

function showResult(seq: number, id: string): ChatItem {
  return {
    id: `r1-${seq}`,
    runId: 'r1',
    memberId: null,
    seq,
    kind: 'tool_result',
    role: null,
    payload: { id, name: null },
    createdAt: 'now',
  };
}

const rows: ChatItem[] = [
  showCall(1, 'a'),
  showResult(2, 'a'),
  showCall(3, 'b'),
  showResult(4, 'b'),
  showCall(5, 'c'),
  showResult(6, 'c'),
];

describe('latestShowArtifactResultSeq', () => {
  it('answers the newest paired result when every result counts', () => {
    expect(latestShowArtifactResultSeq(rows, 'r1', 0)).toBe(6);
  });

  it('skips a paired result the predicate does not admit and answers the newest admitted one', () => {
    const counts = (result: ChatItem) => result.seq !== 6;

    expect(latestShowArtifactResultSeq(rows, 'r1', 0, counts)).toBe(4);
  });

  it('answers the floor when the predicate admits no result above it', () => {
    expect(latestShowArtifactResultSeq(rows, 'r1', 3, () => false)).toBe(3);
  });
});
