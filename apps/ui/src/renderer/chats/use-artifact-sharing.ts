import { useCallback, useEffect, useMemo, useState } from 'react';

import type {
  ItemDto as ChatItem,
  RevokeShareDto,
  Share,
  SharesApi,
} from '../autogenerated';
import { themeVars } from './artifact-theme';
import { geniroToolOf } from './geniro-tool';
import type { PublishedArtifact } from './published-artifact';
import { payloadString } from './transcript-payload';

/**
 * The newest `show_artifact` tool RESULT among `rows`, or `floor` — the share
 * list's refresh trigger. An agent's share finishes after its page row was
 * written (the upload can take a while), and its receipt is the first row that
 * lands once it has. Results are paired to their call by id, because claude
 * writes `name: null` on a result row.
 */
export function latestShowArtifactResultSeq(
  rows: readonly ChatItem[],
  runId: string,
  floor: number,
): number {
  const calls = new Set<string>();
  let newest = floor;
  for (const item of rows) {
    const id = payloadString(item.payload, 'id');
    if (id === null) {
      continue;
    }
    if (item.kind === 'tool_call') {
      const name = payloadString(item.payload, 'name');
      if (name !== null && geniroToolOf(name, runId) === 'show_artifact') {
        calls.add(id);
      }
    } else if (
      item.kind === 'tool_result' &&
      calls.has(id) &&
      item.seq > newest
    ) {
      newest = item.seq;
    }
  }
  return newest;
}

/** What the user is told when a revoke left the uploaded page in place. */
export function revokeFailedMessage(detail: string | undefined): string {
  return `The link could not be removed: ${detail ?? 'unknown error'}. It may still work — try again.`;
}

/** {@link revokeFailedMessage} for a revoke of many pages, `detail` being the first failure's. */
export function revokeManyFailedMessage(
  failed: number,
  total: number,
  detail: string | null,
): string {
  return `${failed} of ${total} links could not be removed: ${detail ?? 'unknown error'}. They may still work — try again.`;
}

/** What a page's Share control can do, for the run on screen. */
export interface ArtifactSharing {
  /** This page's live share, or null when it has none. */
  shareOf: (artifactId: string) => Share | null;
  /** Share the page's newest version; resolves to the link (key in its fragment). */
  share: (artifact: PublishedArtifact) => Promise<string>;
  link: (shareId: string) => Promise<string>;
  revoke: (shareId: string) => Promise<RevokeShareDto>;
}

type SharesClient = Pick<
  SharesApi,
  'listShares' | 'shareArtifact' | 'readShareLink' | 'revokeShare'
>;

/**
 * The run's shared pages, read from the daemon and re-read whenever a page is
 * published (`refreshKey`) or a share changes here.
 *
 * Null without a client — a paired phone, which the daemon refuses anyway —
 * so the control renders nothing rather than a press that cannot work.
 */
export function useArtifactSharing(
  api: SharesClient | null,
  runId: string | null,
  refreshKey: number,
): ArtifactSharing | null {
  const [shares, setShares] = useState<{
    runId: string | null;
    list: Share[];
  }>({ runId, list: [] });
  const [bump, setBump] = useState(0);

  useEffect(() => {
    if (api === null || runId === null) {
      setShares({ runId, list: [] });
      return;
    }
    let cancelled = false;
    void api
      .listShares({ runId })
      .then((answer) => {
        if (!cancelled) {
          setShares({ runId, list: answer.shares });
        }
      })
      // A list that could not be read shows every page as not shared; the
      // press itself still reports what went wrong.
      .catch(() => {
        if (!cancelled) {
          setShares({ runId, list: [] });
        }
      });
    return () => {
      cancelled = true;
    };
  }, [api, runId, refreshKey, bump]);

  const list = shares.runId === runId ? shares.list : [];

  const shareOf = useCallback(
    (artifactId: string) =>
      list.find((entry) => entry.artifactId === artifactId) ?? null,
    [list],
  );

  const share = useCallback(
    async (artifact: PublishedArtifact) => {
      if (api === null || runId === null) {
        throw new Error('sharing is not available here');
      }
      const created = await api.shareArtifact({
        createShareDto: {
          runId,
          artifactId: artifact.artifactId,
          title: artifact.title,
          // The theme the user is looking at, baked into the shared page.
          themeVars: themeVars(),
        },
      });
      setBump((n) => n + 1);
      return created.url;
    },
    [api, runId],
  );

  const link = useCallback(
    async (shareId: string) => {
      if (api === null) {
        throw new Error('sharing is not available here');
      }
      return (await api.readShareLink({ shareId })).url;
    },
    [api],
  );

  const revoke = useCallback(
    async (shareId: string) => {
      if (api === null) {
        throw new Error('sharing is not available here');
      }
      const outcome = await api.revokeShare({ shareId });
      setBump((n) => n + 1);
      return outcome;
    },
    [api],
  );

  return useMemo(
    () => (api === null ? null : { shareOf, share, link, revoke }),
    [api, shareOf, share, link, revoke],
  );
}
