// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import { AttachmentMediaType } from '../autogenerated';
import type { DecodedImage, ImageCodec } from './normalize-image';
import {
  type AttachmentRouting,
  type StagedAttachment,
  useAttachments,
} from './use-attachments';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

interface Harness {
  paste: (files: File[]) => void;
  staged: () => StagedAttachment[];
}

/**
 * Mount the hook behind a probe component and hand the spec its two verbs.
 *
 * `addFromClipboard` reads exactly one thing off the event — `data.files` — so
 * a plain object stands in for the `DataTransfer` jsdom does not implement.
 */
function mount(codec: ImageCodec): Harness {
  let latest: StagedAttachment[] = [];
  let add: (data: DataTransfer | null) => boolean = () => false;
  function Probe(): null {
    const { attachments, addFromClipboard } = useAttachments(codec);
    latest = attachments;
    add = addFromClipboard;
    return null;
  }
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(<Probe />);
  });
  return {
    paste: (files) => {
      act(() => {
        add({ files } as unknown as DataTransfer);
      });
    },
    staged: () => latest,
  };
}

/** A codec that reports a decoded size and renders to a stated media type. */
function codecOf(
  width: number,
  height: number,
  rendered: 'image/png' | 'image/jpeg',
): ImageCodec & { encodes: number } {
  const state = { encodes: 0 };
  const decoded: DecodedImage = {
    width,
    height,
    source: 'bitmap',
    close: () => {},
  };
  return {
    get encodes() {
      return state.encodes;
    },
    decode: () => Promise.resolve(decoded),
    encode: (_image, _w, _h, mediaType) => {
      state.encodes += 1;
      // Only the rung this codec is standing in for comes back small enough;
      // everything else is oversize, so the ladder walks on.
      return Promise.resolve(
        new Blob([new Uint8Array(mediaType === rendered ? 8 : 99_999_999)], {
          type: mediaType,
        }),
      );
    },
  };
}

const png = (name: string): File =>
  new File([new Uint8Array(64)], name, { type: 'image/png' });

/**
 * Let the staging finish. `FileReader.readAsDataURL` resolves on a TASK, not a
 * microtask, so draining the microtask queue alone leaves the list empty.
 */
async function settle(): Promise<void> {
  for (let tick = 0; tick < 8; tick += 1) {
    await act(async () => {
      await new Promise((resolve) => setTimeout(resolve, 0));
    });
  }
}

describe('useAttachments', () => {
  it('SHRINKS a paste the provider would refuse, and stages the shrunk bytes', async () => {
    // The reported defect: a 2094px retina screenshot went to the model at its
    // native size, over the 2000px ceiling a many-image conversation is served
    // under, and then failed every turn for as long as it stayed in history.
    // The hook is the one door images come through, so this is where it has to
    // be caught — pinning `normalizeImage` alone would stay green with the call
    // deleted from here.
    const codec = codecOf(2094, 968, 'image/png');
    const harness = mount(codec);

    harness.paste([png('shot.png')]);
    await settle();

    expect(codec.encodes).toBe(1);
    expect(harness.staged()).toHaveLength(1);
    // 8 bytes is the fake's rendering; the source file is 64. Asserting the
    // STAGED bytes rather than the call is what makes this fail if the hook
    // encodes and then sends the original anyway.
    expect(atob(harness.staged()[0]!.data)).toHaveLength(8);
  });

  it('leaves an in-bounds paste alone', async () => {
    const codec = codecOf(1200, 800, 'image/png');
    const harness = mount(codec);

    harness.paste([png('small.png')]);
    await settle();

    expect(codec.encodes).toBe(0);
    expect(atob(harness.staged()[0]!.data)).toHaveLength(64);
  });

  it('records the media type the RESIZE produced, not the file’s', async () => {
    // A PNG too heavy even at 2000px comes back as JPEG. The thumbnail's data
    // URL and the daemon's stored extension are both read off this field, so a
    // stale `image/png` writes JPEG bytes to a `.png` and mislabels the block
    // the model is handed.
    const codec = codecOf(3000, 3000, 'image/jpeg');
    const harness = mount(codec);

    harness.paste([png('huge.png')]);
    await settle();

    const staged = harness.staged()[0]!;
    expect(staged.mediaType).toBe(AttachmentMediaType.ImageJpeg);
    expect(staged.preview.startsWith('data:image/jpeg;base64,')).toBe(true);
  });

  it('still stages the image when the codec is unusable', async () => {
    // A runtime with no image codec must not lose the ability to paste at all:
    // the fallback is the behaviour that shipped before any of this existed.
    const broken: ImageCodec = {
      decode: () => Promise.reject(new Error('no createImageBitmap here')),
      encode: () => Promise.reject(new Error('unreachable')),
    };
    const harness = mount(broken);

    harness.paste([png('shot.png')]);
    await settle();

    expect(harness.staged()).toHaveLength(1);
    expect(atob(harness.staged()[0]!.data)).toHaveLength(64);
  });
});

/**
 * A codec whose decode waits until the spec releases it, so a paste stays IN
 * FLIGHT for exactly as long as the case needs. Decodes to a size inside the
 * ceiling, so a released read goes straight on to `FileReader`.
 */
function gatedCodec(): ImageCodec & { release: () => void } {
  const waiting: (() => void)[] = [];
  const decoded: DecodedImage = {
    width: 10,
    height: 10,
    source: 'bitmap',
    close: () => {},
  };
  return {
    decode: () =>
      new Promise<DecodedImage>((resolve) => {
        waiting.push(() => resolve(decoded));
      }),
    encode: () => Promise.reject(new Error('unreachable: in bounds')),
    release: () => {
      for (const resolve of waiting.splice(0)) {
        resolve();
      }
    },
  };
}

interface RoutedHarness extends Harness {
  reading: () => boolean;
  clear: (keys?: readonly string[]) => void;
  /** Re-render, the way the composer's parent does on a thread switch. */
  rerender: () => void;
}

function mountRouted(
  codec: ImageCodec,
  routing?: AttachmentRouting,
): RoutedHarness {
  const state = {
    staged: [] as StagedAttachment[],
    reading: false,
    add: (() => false) as (data: DataTransfer | null) => boolean,
    clear: (() => {}) as (keys?: readonly string[]) => void,
  };
  function Probe(): null {
    const hook = useAttachments(codec, routing);
    state.staged = hook.attachments;
    state.reading = hook.reading;
    state.add = hook.addFromClipboard;
    state.clear = hook.clear;
    return null;
  }
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  const paint = (): void => {
    act(() => {
      root!.render(<Probe />);
    });
  };
  paint();
  return {
    paste: (files) => {
      act(() => {
        state.add({ files } as unknown as DataTransfer);
      });
    },
    staged: () => state.staged,
    reading: () => state.reading,
    clear: (keys) => {
      act(() => {
        state.clear(keys);
      });
    },
    rerender: paint,
  };
}

describe('useAttachments — a paste still being read', () => {
  it('is READING until the image lands, so a send can refuse to go without it', async () => {
    // Enter pressed straight after a paste sent the message WITHOUT the
    // screenshot: `toWire` returns what has landed, and nothing said a read
    // was still running.
    const codec = gatedCodec();
    const harness = mountRouted(codec);

    harness.paste([png('shot.png')]);
    expect(harness.reading()).toBe(true);
    expect(harness.staged()).toHaveLength(0);

    codec.release();
    await settle();

    expect(harness.reading()).toBe(false);
    expect(harness.staged()).toHaveLength(1);
  });

  it('sends a read that lands after its thread LEFT the screen to that thread’s draft', async () => {
    // One stage serves every thread's draft in turn, and a read outlives a
    // switch. Appended to the live stage regardless, the screenshot turned up
    // staged in the thread the user had moved to — the one it could then be
    // sent from.
    const codec = gatedCodec();
    let onScreen = 'thread-a';
    const parked: [string, StagedAttachment][] = [];
    const harness = mountRouted(codec, {
      current: () => onScreen,
      elsewhere: (owner, attachment) => parked.push([owner, attachment]),
    });

    harness.paste([png('shot.png')]);
    onScreen = 'thread-b';
    harness.rerender();
    // The read belongs to A: B's Send is not held for it.
    expect(harness.reading()).toBe(false);

    codec.release();
    await settle();

    expect(harness.staged()).toHaveLength(0);
    expect(parked).toHaveLength(1);
    expect(parked[0]![0]).toBe('thread-a');
    expect(parked[0]![1].owner).toBe('thread-a');
  });

  it('lands on the stage when its thread is still the one on screen', async () => {
    // The other half, so the routing above cannot pass by sending EVERY read
    // away.
    const codec = gatedCodec();
    const parked: string[] = [];
    const harness = mountRouted(codec, {
      current: () => 'thread-a',
      elsewhere: (owner) => parked.push(owner),
    });

    harness.paste([png('shot.png')]);
    expect(harness.reading()).toBe(true);
    codec.release();
    await settle();

    expect(parked).toEqual([]);
    expect(harness.staged()).toHaveLength(1);
    expect(harness.staged()[0]!.owner).toBe('thread-a');
  });
});

describe('useAttachments — clear', () => {
  it('takes only the images it is handed the keys of', async () => {
    // A send gives up the images it SENT. A bare clear took one that landed
    // while the send was being made along with them.
    const harness = mountRouted(codecOf(1200, 800, 'image/png'));
    harness.paste([png('sent.png')]);
    await settle();
    harness.paste([png('pasted-since.png')]);
    await settle();
    const [sent, since] = harness.staged();

    harness.clear([sent!.key]);

    expect(harness.staged().map((image) => image.key)).toEqual([since!.key]);

    // And with no keys, everything — the call a surface closing its box makes.
    harness.clear();
    expect(harness.staged()).toEqual([]);
  });
});
