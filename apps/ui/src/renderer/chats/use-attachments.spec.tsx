// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import { AttachmentMediaType } from '../autogenerated';
import type { DecodedImage, ImageCodec } from './normalize-image';
import { type StagedAttachment, useAttachments } from './use-attachments';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

interface Harness {
  paste: (files: File[]) => void;
  staged: () => StagedAttachment[];
}

/**
 * Mount the hook behind a probe component and hand the spec its two verbs.
 *
 * `addFromClipboard` reads exactly one thing off the event — `data.files` — so
 * a plain object stands in for the `DataTransfer` jsdom does not implement.
 */
function mount(codec: ImageCodec): Harness {
  let latest: StagedAttachment[] = [];
  let add: (data: DataTransfer | null) => boolean = () => false;
  function Probe(): null {
    const { attachments, addFromClipboard } = useAttachments(codec);
    latest = attachments;
    add = addFromClipboard;
    return null;
  }
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(<Probe />);
  });
  return {
    paste: (files) => {
      act(() => {
        add({ files } as unknown as DataTransfer);
      });
    },
    staged: () => latest,
  };
}

/** A codec that reports a decoded size and renders to a stated media type. */
function codecOf(
  width: number,
  height: number,
  rendered: 'image/png' | 'image/jpeg',
): ImageCodec & { encodes: number } {
  const state = { encodes: 0 };
  const decoded: DecodedImage = {
    width,
    height,
    source: 'bitmap',
    close: () => {},
  };
  return {
    get encodes() {
      return state.encodes;
    },
    decode: () => Promise.resolve(decoded),
    encode: (_image, _w, _h, mediaType) => {
      state.encodes += 1;
      // Only the rung this codec is standing in for comes back small enough;
      // everything else is oversize, so the ladder walks on.
      return Promise.resolve(
        new Blob([new Uint8Array(mediaType === rendered ? 8 : 99_999_999)], {
          type: mediaType,
        }),
      );
    },
  };
}

const png = (name: string): File =>
  new File([new Uint8Array(64)], name, { type: 'image/png' });

/**
 * Let the staging finish. `FileReader.readAsDataURL` resolves on a TASK, not a
 * microtask, so draining the microtask queue alone leaves the list empty.
 */
async function settle(): Promise<void> {
  for (let tick = 0; tick < 8; tick += 1) {
    await act(async () => {
      await new Promise((resolve) => setTimeout(resolve, 0));
    });
  }
}

describe('useAttachments', () => {
  it('SHRINKS a paste the provider would refuse, and stages the shrunk bytes', async () => {
    // The reported defect: a 2094px retina screenshot went to the model at its
    // native size, over the 2000px ceiling a many-image conversation is served
    // under, and then failed every turn for as long as it stayed in history.
    // The hook is the one door images come through, so this is where it has to
    // be caught — pinning `normalizeImage` alone would stay green with the call
    // deleted from here.
    const codec = codecOf(2094, 968, 'image/png');
    const harness = mount(codec);

    harness.paste([png('shot.png')]);
    await settle();

    expect(codec.encodes).toBe(1);
    expect(harness.staged()).toHaveLength(1);
    // 8 bytes is the fake's rendering; the source file is 64. Asserting the
    // STAGED bytes rather than the call is what makes this fail if the hook
    // encodes and then sends the original anyway.
    expect(atob(harness.staged()[0]!.data)).toHaveLength(8);
  });

  it('leaves an in-bounds paste alone', async () => {
    const codec = codecOf(1200, 800, 'image/png');
    const harness = mount(codec);

    harness.paste([png('small.png')]);
    await settle();

    expect(codec.encodes).toBe(0);
    expect(atob(harness.staged()[0]!.data)).toHaveLength(64);
  });

  it('records the media type the RESIZE produced, not the file’s', async () => {
    // A PNG too heavy even at 2000px comes back as JPEG. The thumbnail's data
    // URL and the daemon's stored extension are both read off this field, so a
    // stale `image/png` writes JPEG bytes to a `.png` and mislabels the block
    // the model is handed.
    const codec = codecOf(3000, 3000, 'image/jpeg');
    const harness = mount(codec);

    harness.paste([png('huge.png')]);
    await settle();

    const staged = harness.staged()[0]!;
    expect(staged.mediaType).toBe(AttachmentMediaType.ImageJpeg);
    expect(staged.preview.startsWith('data:image/jpeg;base64,')).toBe(true);
  });

  it('still stages the image when the codec is unusable', async () => {
    // A runtime with no image codec must not lose the ability to paste at all:
    // the fallback is the behaviour that shipped before any of this existed.
    const broken: ImageCodec = {
      decode: () => Promise.reject(new Error('no createImageBitmap here')),
      encode: () => Promise.reject(new Error('unreachable')),
    };
    const harness = mount(broken);

    harness.paste([png('shot.png')]);
    await settle();

    expect(harness.staged()).toHaveLength(1);
    expect(atob(harness.staged()[0]!.data)).toHaveLength(64);
  });
});
