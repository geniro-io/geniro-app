import { useCallback, useState } from 'react';

import {
  AttachmentMediaType,
  type SendMessageDtoImagesInner,
} from '../autogenerated';
import {
  browserImageCodec,
  type ImageCodec,
  normalizeImage,
} from './normalize-image';

/**
 * TWIN LIMIT: apps/daemon/src/v1/agents/chat.types.ts
 * MAX_ATTACHMENT_BYTES / MAX_ATTACHMENTS_PER_MESSAGE.
 *
 * The daemon enforces these for real. Repeating them here is what turns a
 * refusal into a message the user reads BEFORE composing a whole prompt around
 * an image that was never going to be accepted.
 */
export const MAX_ATTACHMENT_BYTES = 5 * 1024 * 1024;
export const MAX_ATTACHMENTS = 8;

const ACCEPTED: string[] = Object.values(AttachmentMediaType);

/** One image staged in the composer, not yet sent. */
export interface StagedAttachment {
  /** Local-only id — the daemon mints the durable one when the message lands. */
  key: string;
  mediaType: AttachmentMediaType;
  /** base64 bytes, ready for the send body. */
  data: string;
  /** `data:` URL for the thumbnail. */
  preview: string;
  name: string;
  /**
   * Which part of a MULTI-PART field this image was pasted into, or null for a
   * field that has only one.
   *
   * The composer passes nothing and is unchanged. It exists for the question
   * card, whose tabs are several answers being written at once into one card:
   * an image pasted on the third tab belongs to the third question, and without
   * an owner every tab showed every image and the answer text could only say
   * that a picture was coming, never which question it was about.
   *
   * Deliberately just a tag, not a partition: the bytes still leave as ONE
   * follow-up message, because that is what the delivery path does. What the
   * owner decides is which thumbnails a part shows and which answer line
   * announces them.
   */
  owner: number | null;
}

const readAsBase64 = (file: Blob): Promise<string> =>
  new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = () => reject(new Error('could not read the image'));
    reader.onload = () => {
      const result = String(reader.result);
      // A data URL is `data:<media-type>;base64,<payload>` — the wire wants
      // only the payload.
      resolve(result.slice(result.indexOf(',') + 1));
    };
    reader.readAsDataURL(file);
  });

/**
 * Shrink an image the model would refuse, then read it.
 *
 * See {@link normalizeImage}: the provider serves a many-image conversation
 * under a 2000px per-image ceiling, the CLI caps its OWN images at exactly
 * that, and geniro's attachments bypass that code entirely — which is what put
 * eight `API Error: an image in the conversation could not be processed and was
 * removed` rows in a real thread, one per turn, for as long as the offending
 * screenshot stayed in the history.
 *
 * A normalization that FAILS falls back to the original bytes rather than
 * refusing the paste. The image may then be refused by the provider, which is
 * exactly the behaviour that shipped before this existed — so the worst case of
 * having the feature is the status quo, where refusing would make pasting stop
 * working outright on any runtime whose codec is missing.
 */
async function readNormalized(
  file: File,
  mediaType: AttachmentMediaType,
  codec: ImageCodec,
): Promise<{ mediaType: AttachmentMediaType; data: string }> {
  try {
    const normalized = await normalizeImage(
      file,
      mediaType,
      MAX_ATTACHMENT_BYTES,
      codec,
    );
    return {
      mediaType: normalized.mediaType,
      data: await readAsBase64(normalized.blob),
    };
  } catch {
    return { mediaType, data: await readAsBase64(file) };
  }
}

/**
 * Images staged on the composer.
 *
 * A pasted screenshot arrives as a `File` on the clipboard event; it is read
 * to base64 once, here, so the send path is a plain object and the thumbnail
 * needs no object-URL lifecycle to leak.
 *
 * It is also SHRUNK here if it is too big for the model to accept — see
 * {@link readNormalized}. This is the one door every attachment comes through
 * (the composer and the question card share it), and it is the only process in
 * the app that can decode an image at all, which is what makes it the place.
 */
export function useAttachments(
  /**
   * The decode/encode pair used to bring an oversize paste within the model's
   * pixel ceiling. A parameter only so a spec can drive the resize ladder:
   * Chromium's own `createImageBitmap`/`OffscreenCanvas` exist in neither jsdom
   * nor node, so the default is the only thing that ever runs in the app.
   */
  codec: ImageCodec = browserImageCodec,
): {
  attachments: StagedAttachment[];
  error: string | null;
  /**
   * Returns true when the event carried images (so the caller can
   * preventDefault). `owner` tags them — see {@link StagedAttachment.owner}.
   */
  addFromClipboard: (data: DataTransfer | null, owner?: number) => boolean;
  remove: (key: string) => void;
  clear: () => void;
  /**
   * Put a previously staged list back, unchanged.
   *
   * For per-thread drafts: switching threads saves whatever was staged and
   * restores the incoming thread's own, so an image pasted into one
   * conversation cannot be sent from another. Takes the staged shape rather
   * than raw files because the base64 conversion has already happened — a
   * restore must not redo work, and re-reading a `File` the clipboard no longer
   * holds would fail anyway.
   */
  restore: (staged: StagedAttachment[]) => void;
  clearError: () => void;
  /** The send-body projection. */
  toWire: () => SendMessageDtoImagesInner[];
} {
  const [attachments, setAttachments] = useState<StagedAttachment[]>([]);
  const [error, setError] = useState<string | null>(null);

  const addFromClipboard = useCallback(
    (data: DataTransfer | null, owner?: number): boolean => {
      const files = [...(data?.files ?? [])].filter((file) =>
        file.type.startsWith('image/'),
      );
      if (files.length === 0) {
        return false;
      }
      setError(null);
      for (const file of files) {
        if (!ACCEPTED.includes(file.type)) {
          setError(`${file.type} images are not supported`);
          continue;
        }
        if (file.size > MAX_ATTACHMENT_BYTES) {
          setError(
            `${file.name || 'image'} is larger than ${Math.floor(MAX_ATTACHMENT_BYTES / 1024 / 1024)}MB`,
          );
          continue;
        }
        void readNormalized(file, file.type as AttachmentMediaType, codec)
          .then(({ mediaType, data: base64 }) => {
            setAttachments((current) => {
              if (current.length >= MAX_ATTACHMENTS) {
                setError(`at most ${MAX_ATTACHMENTS} images per message`);
                return current;
              }
              return [
                ...current,
                {
                  // A pasted screenshot has no name and two pastes of the same
                  // image are indistinguishable by content, so the key is
                  // positional + random rather than derived from the file.
                  key: `${Date.now()}-${current.length}-${Math.random().toString(36).slice(2, 8)}`,
                  // The NORMALIZED type, not the file's: a resize that had to
                  // fall back to JPEG changes what these bytes are, and the
                  // thumbnail below and the daemon's own extension mapping are
                  // both read off this field.
                  mediaType,
                  data: base64,
                  preview: `data:${mediaType};base64,${base64}`,
                  name: file.name || 'pasted image',
                  // Captured at PASTE time, not read at render time: the read
                  // above is async, and the user is free to change tabs while
                  // it runs — an owner resolved later would land the image on
                  // whichever tab they had moved to.
                  owner: owner ?? null,
                },
              ];
            });
          })
          .catch((err: unknown) => {
            setError(
              err instanceof Error ? err.message : 'could not read image',
            );
          });
      }
      return true;
    },
    [codec],
  );

  const remove = useCallback((key: string): void => {
    setAttachments((current) => current.filter((item) => item.key !== key));
  }, []);

  const clear = useCallback((): void => {
    setAttachments([]);
    setError(null);
  }, []);

  const restore = useCallback((staged: StagedAttachment[]): void => {
    setAttachments(staged);
  }, []);

  const clearError = useCallback((): void => setError(null), []);

  const toWire = useCallback(
    (): SendMessageDtoImagesInner[] =>
      attachments.map(({ mediaType, data }) => ({ mediaType, data })),
    [attachments],
  );

  return {
    attachments,
    error,
    addFromClipboard,
    remove,
    clear,
    restore,
    clearError,
    toWire,
  };
}
