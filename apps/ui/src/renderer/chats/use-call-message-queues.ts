import { useCallback, useMemo, useRef, useState } from 'react';

import type { SendMessageDtoImagesInner } from '../autogenerated';
import { daemonErrorCode, daemonErrorDetail } from '../daemon-api';
import type { QueuedStripMessage } from './queued-strip';

/** Which call a message is addressed to. */
export interface CallTarget {
  runId: string;
  nodeId: string;
  callId: string;
  /**
   * The call block's own id (its `call_started` row). Call ids are numbered
   * per pass of a run, so only this tells one pass's `call-1` from the next.
   */
  blockId: string;
}

export interface QueuedCallMessage extends QueuedStripMessage {
  images: SendMessageDtoImagesInner[];
}

/** One call's outgoing messages and where their delivery has got to. */
export interface CallQueueState {
  /** Waiting to go out, in order. */
  messages: readonly QueuedCallMessage[];
  /**
   * The message whose POST is in flight — out of `messages`, so it cannot be
   * edited or removed after it has already been handed to the daemon.
   */
  inFlight: QueuedCallMessage | null;
  /** Nothing leaves the queue until a message is sent by hand. */
  paused: boolean;
  /** The daemon's refusal that stopped the queue, until the next attempt. */
  error: string | null;
}

export const EMPTY_CALL_QUEUE: CallQueueState = {
  messages: [],
  inFlight: null,
  paused: false,
  error: null,
};

/**
 * The backoff for `CALL_MESSAGE_REFUSED`, the one refusal that can clear on
 * its own (the callee's CLI was between steps). Anything else — the call has
 * ended, the run is archived — stops the queue with the daemon's sentence.
 */
const REFUSED_RETRY_MS = [300, 600, 1200, 2400];

export type CallMessageSend = (
  target: CallTarget,
  text: string,
  images: SendMessageDtoImagesInner[],
) => Promise<void>;

export interface CallMessageQueues {
  queueOf: (target: CallTarget) => CallQueueState;
  enqueue: (
    target: CallTarget,
    text: string,
    images: SendMessageDtoImagesInner[],
  ) => void;
  /** Deliver in order until the queue is empty, paused, or refused for good. */
  drain: (target: CallTarget) => Promise<void>;
  /** Move one message to the front and deliver it, pause or not. */
  sendNow: (target: CallTarget, id: string) => Promise<void>;
  edit: (target: CallTarget, id: string, text: string) => void;
  remove: (target: CallTarget, id: string) => void;
  reorder: (target: CallTarget, id: string, overId: string) => void;
  togglePause: (target: CallTarget) => void;
}

const keyOf = ({ runId, blockId }: CallTarget): string =>
  JSON.stringify([runId, blockId]);

/**
 * Per-call queues for messages written straight to a callee.
 *
 * Unlike the composer's queue, messages are not held until a turn ends — a
 * callee's only turn IS the call, so holding them would deliver nothing. The
 * queue is what keeps them in order and on screen: one POST at a time, a
 * refusal that may clear retried, and a refusal that cannot left visible
 * beside the messages it stopped. It lives above the call block so folding
 * the card does not lose what is waiting.
 */
export function useCallMessageQueues(send: CallMessageSend): CallMessageQueues {
  const [queues, setQueues] = useState<Record<string, CallQueueState>>({});
  // Read synchronously by `run`, which re-reads the head after every await.
  const queuesRef = useRef(queues);
  const draining = useRef(new Set<string>());
  // A Send-now pressed while a drain is already running, for that drain to
  // honour at its next step rather than being dropped. Bound to the MESSAGE:
  // on a paused queue a press releases that one message and nothing else.
  const forceRequested = useRef(new Map<string, string>());

  const update = useCallback(
    (target: CallTarget, change: (state: CallQueueState) => CallQueueState) => {
      const key = keyOf(target);
      const next = {
        ...queuesRef.current,
        [key]: change(queuesRef.current[key] ?? EMPTY_CALL_QUEUE),
      };
      queuesRef.current = next;
      setQueues(next);
    },
    [],
  );

  const run = useCallback(
    async (target: CallTarget, forceId: string | null): Promise<void> => {
      const key = keyOf(target);
      if (draining.current.has(key)) {
        if (forceId !== null) {
          forceRequested.current.set(key, forceId);
        }
        return;
      }
      draining.current.add(key);
      try {
        let attempt = 0;
        let forcedId = forceId;
        for (;;) {
          forcedId = forceRequested.current.get(key) ?? forcedId;
          forceRequested.current.delete(key);
          const state = queuesRef.current[key] ?? EMPTY_CALL_QUEUE;
          const head = state.messages[0];
          if (head === undefined || (state.paused && head.id !== forcedId)) {
            return;
          }
          update(target, (s) => ({
            ...s,
            messages: s.messages.filter((m) => m.id !== head.id),
            inFlight: head,
            error: null,
          }));
          try {
            await send(target, head.text, head.images);
            attempt = 0;
            if (head.id === forcedId) {
              forcedId = null;
            }
            update(target, (s) => ({ ...s, inFlight: null }));
          } catch (err) {
            const wait =
              daemonErrorCode(err) === 'CALL_MESSAGE_REFUSED'
                ? REFUSED_RETRY_MS[attempt]
                : undefined;
            const reason = daemonErrorDetail(err) ?? String(err);
            // Back at the front either way: undelivered, and the user's to
            // edit or remove while it waits.
            update(target, (s) => ({
              ...s,
              inFlight: null,
              messages: [head, ...s.messages],
              error: wait === undefined ? reason : null,
            }));
            if (wait === undefined) {
              return;
            }
            attempt += 1;
            await new Promise((resolve) => setTimeout(resolve, wait));
          }
        }
      } finally {
        draining.current.delete(key);
        forceRequested.current.delete(key);
      }
    },
    [send, update],
  );

  const queueOf = useCallback(
    (target: CallTarget): CallQueueState =>
      queues[keyOf(target)] ?? EMPTY_CALL_QUEUE,
    [queues],
  );

  const enqueue = useCallback(
    (target: CallTarget, text: string, images: SendMessageDtoImagesInner[]) => {
      update(target, (s) => ({
        ...s,
        error: null,
        messages: [...s.messages, { id: crypto.randomUUID(), text, images }],
      }));
    },
    [update],
  );

  const drain = useCallback((target: CallTarget) => run(target, null), [run]);

  const sendNow = useCallback(
    (target: CallTarget, id: string) => {
      update(target, (s) => {
        const picked = s.messages.find((m) => m.id === id);
        return picked === undefined
          ? s
          : {
              ...s,
              messages: [picked, ...s.messages.filter((m) => m.id !== id)],
            };
      });
      return run(target, id);
    },
    [run, update],
  );

  const edit = useCallback(
    (target: CallTarget, id: string, text: string) => {
      update(target, (s) => ({
        ...s,
        messages: s.messages.map((m) => (m.id === id ? { ...m, text } : m)),
      }));
    },
    [update],
  );

  const remove = useCallback(
    (target: CallTarget, id: string) => {
      update(target, (s) => {
        const messages = s.messages.filter((m) => m.id !== id);
        return {
          ...s,
          messages,
          error: messages.length === 0 ? null : s.error,
        };
      });
    },
    [update],
  );

  const reorder = useCallback(
    (target: CallTarget, id: string, overId: string) => {
      update(target, (s) => {
        const from = s.messages.findIndex((m) => m.id === id);
        const to = s.messages.findIndex((m) => m.id === overId);
        if (from < 0 || to < 0 || from === to) {
          return s;
        }
        const messages = [...s.messages];
        const [moved] = messages.splice(from, 1);
        messages.splice(to, 0, moved!);
        return { ...s, messages };
      });
    },
    [update],
  );

  const togglePause = useCallback(
    (target: CallTarget) => {
      update(target, (s) => ({ ...s, paused: !s.paused }));
    },
    [update],
  );

  // One identity per queue change, so a call block's context does not move
  // on every render of the screen that owns it.
  return useMemo(
    () => ({
      queueOf,
      enqueue,
      drain,
      sendNow,
      edit,
      remove,
      reorder,
      togglePause,
    }),
    [queueOf, enqueue, drain, sendNow, edit, remove, reorder, togglePause],
  );
}
