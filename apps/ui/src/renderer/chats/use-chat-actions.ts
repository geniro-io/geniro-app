import { createContext, useEffect, useMemo, useRef, useState } from 'react';

import type {
  ChatsApi,
  LiveAction,
  RunStateDto,
  WorkflowsApi,
} from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import {
  daemonErrorCode,
  describeDaemonError,
  isRunBusyError,
} from '../daemon-api';
import { randomId } from '../random-id';

/** How a press stands on this device, over the daemon's own `pending`. */
export type ActionPressPhase =
  /** The request is out. */
  | { kind: 'pressing' }
  /** The chat answered RUN_BUSY; the same press goes again once its turn settles. */
  | { kind: 'waiting'; clientMessageId: string }
  | { kind: 'error'; message: string }
  /** A reusable button just pressed: a brief check, then back to normal. */
  | { kind: 'done' };

/** How often a press refused RUN_BUSY with no turn open (a compaction) asks again. */
export const ACTION_RETRY_MS = 2000;

/** How long a reusable button shows its check after a press. */
export const ACTION_DONE_MS = 1500;

export interface ChatActions {
  /** The run's live buttons, newest first — the daemon's set, never a fold of the window. */
  actions: LiveAction[];
  /**
   * The newest seq the live set was read through: a publish past it is one the
   * set cannot speak for yet, rather than one that is no longer live.
   */
  throughSeq: number;
  /** This device's press state, by publish seq. */
  phases: ReadonlyMap<number, ActionPressPhase>;
  /**
   * A command's press only opens its confirmation (`confirming`); nothing is
   * sent until `confirmCommand`. Every other kind sends at once.
   */
  press: (action: LiveAction) => void;
  dismiss: (action: LiveAction) => void;
  /** The command awaiting the user's "Run command", or null. */
  confirming: LiveAction | null;
  confirmCommand: () => void;
  cancelCommand: () => void;
  /**
   * Open a call's card and bring it into view, paging the window to it first
   * when it is not drawn — where a callee's button card links to the thread
   * that published it. Absent where no call can be opened.
   */
  openCall?: (callId: string) => void;
}

/**
 * The open chat's buttons for a surface drawn deep in the transcript (the
 * action card). Null where nothing can be pressed — the card then draws its
 * record without a button.
 */
export const ChatActionsContext = createContext<ChatActions | null>(null);

/** What a surface does around a press, the way it does around a typed send. */
export interface PressHooks {
  /**
   * Run before every press reaches the daemon, a retry included — the builder
   * dock's canvas flush, and its working flag for a press that starts a turn
   * ({@link pressStartsTurn}).
   */
  beforePress?: (action: LiveAction) => Promise<unknown>;
  /**
   * How a press ended: `true` when the daemon accepted it, `false` for
   * anything else — a refusal, a RUN_BUSY the hook will retry, a flush that
   * threw.
   */
  onPressSettled?: (taken: boolean, action: LiveAction) => void;
}

/**
 * Where a run's buttons are pressed: a chat's route, or a workflow's, which
 * delivers to the agents the run's trigger feeds. The chat route refuses a
 * workflow run, so the caller hands over the one matching the open run.
 */
export type ActionApi =
  | Pick<ChatsApi, 'pressChatAction' | 'dismissChatAction'>
  | Pick<WorkflowsApi, 'pressWorkflowAction' | 'dismissWorkflowAction'>;

function pressVia(
  api: ActionApi,
  runId: string,
  seq: number,
  clientMessageId: string,
): Promise<unknown> {
  const request = { runId, seq, pressActionDto: { clientMessageId } };
  return 'pressWorkflowAction' in api
    ? api.pressWorkflowAction(request)
    : api.pressChatAction(request);
}

function dismissVia(
  api: ActionApi,
  runId: string,
  seq: number,
): Promise<unknown> {
  return 'dismissWorkflowAction' in api
    ? api.dismissWorkflowAction({ runId, seq })
    : api.dismissChatAction({ runId, seq });
}

/**
 * Whether a press starts a turn of the agent, as a typed send does: a message
 * press only. A stop or a command runs beside the conversation, and a surface
 * that raised its working flag for one would have nothing to lower it.
 */
export function pressStartsTurn(action: LiveAction): boolean {
  return action.spec.kind === 'message';
}

/** Whether a button can be pressed now — what every surface drawing one asks. */
export function isActionBusy(
  action: LiveAction,
  phase: ActionPressPhase | undefined,
): boolean {
  return (
    action.pending || phase?.kind === 'pressing' || phase?.kind === 'waiting'
  );
}

/**
 * The open chat's agent-published buttons and the two things a person does
 * with one. A press the chat refuses as busy is kept on this device and sent
 * again — the same seq, the same `clientMessageId`, so the message is sent at
 * most once — when the run's turn settles. It never goes through the
 * composer's queue: that drains as a plain message, which would send the text
 * without the press ever being recorded, and leave a one-shot button live.
 *
 * A workflow run opens no turn on run state, so a press it refused as busy —
 * still starting, compacting, a root finishing its turn — is asked again on
 * the same timer a compaction's is.
 */
export function useChatActions(
  api: ActionApi | null,
  runId: string | null,
  state: Pick<RunStateDto, 'actions' | 'turnStartedAt' | 'throughSeq'>,
  refresh: () => void,
  hooks: PressHooks = {},
): ChatActions {
  // Read through a ref: callers pass inline functions, and a new one is not a
  // reason to rebuild `press`.
  const hooksRef = useRef(hooks);
  useEffect(() => {
    hooksRef.current = hooks;
  }, [hooks]);
  const [phases, setPhases] = useState<ReadonlyMap<number, ActionPressPhase>>(
    () => new Map(),
  );
  // Which run an answer may still land on: one for a thread since left is dropped.
  const runRef = useRef(runId);
  const [confirming, setConfirming] = useState<LiveAction | null>(null);
  useEffect(() => {
    runRef.current = runId;
    setPhases(new Map());
    setConfirming(null);
  }, [runId]);

  const setPhase = useLatestCallback(
    (seq: number, phase: ActionPressPhase | null): void => {
      setPhases((current) => {
        const next = new Map(current);
        if (phase === null) {
          next.delete(seq);
        } else {
          next.set(seq, phase);
        }
        return next;
      });
    },
    [],
  );

  const send = useLatestCallback(
    (action: LiveAction, clientMessageId: string): void => {
      if (api === null || runId === null) {
        return;
      }
      setPhase(action.seq, { kind: 'pressing' });
      Promise.resolve(hooksRef.current.beforePress?.(action))
        .then(() => pressVia(api, runId, action.seq, clientMessageId))
        .then(
          () => {
            hooksRef.current.onPressSettled?.(true, action);
            if (runRef.current === runId) {
              // A one-shot leaves with the re-read; a reusable one stays and says it went.
              setPhase(action.seq, action.once ? null : { kind: 'done' });
              if (!action.once) {
                // Each check clears on its own clock; another button's phase
                // changing must not hold it up.
                setTimeout(() => {
                  setPhases((current) =>
                    current.get(action.seq)?.kind === 'done'
                      ? new Map(
                          [...current].filter(([seq]) => seq !== action.seq),
                        )
                      : current,
                  );
                }, ACTION_DONE_MS);
              }
              refresh();
            }
          },
          (err: unknown) => {
            hooksRef.current.onPressSettled?.(false, action);
            if (runRef.current !== runId) {
              return;
            }
            if (isRunBusyError(err)) {
              setPhase(action.seq, { kind: 'waiting', clientMessageId });
              return;
            }
            setPhase(action.seq, {
              kind: 'error',
              message: describeDaemonError(err),
            });
            const code = daemonErrorCode(err);
            if (code === 'ACTION_CHANGED' || code === 'ACTION_GONE') {
              refresh();
            }
          },
        );
    },
    [api, runId, refresh, setPhase],
  );

  const press = useLatestCallback(
    (action: LiveAction): void => {
      if (isActionBusy(action, phases.get(action.seq))) {
        return;
      }
      if (action.spec.kind === 'command') {
        setConfirming(action);
        return;
      }
      send(action, randomId());
    },
    [phases, send],
  );

  const confirmCommand = useLatestCallback((): void => {
    if (confirming === null) {
      return;
    }
    setConfirming(null);
    send(confirming, randomId());
  }, [confirming, send]);

  const cancelCommand = useLatestCallback((): void => setConfirming(null), []);

  const dismiss = useLatestCallback(
    (action: LiveAction): void => {
      if (api === null || runId === null) {
        return;
      }
      dismissVia(api, runId, action.seq).then(
        () => {
          if (runRef.current === runId) {
            setPhase(action.seq, null);
            refresh();
          }
        },
        (err: unknown) => {
          if (runRef.current === runId) {
            setPhase(action.seq, {
              kind: 'error',
              message: describeDaemonError(err),
            });
          }
        },
      );
    },
    [api, runId, refresh, setPhase],
  );

  // Re-press what the chat refused as busy once no turn is open. A refusal
  // with no turn open (a compaction, a resume) is asked again on a timer.
  const turnOpen = state.turnStartedAt !== null;
  useEffect(() => {
    if (turnOpen) {
      return;
    }
    const waiting = [...phases].filter(
      (
        entry,
      ): entry is [number, Extract<ActionPressPhase, { kind: 'waiting' }>] =>
        entry[1].kind === 'waiting',
    );
    if (waiting.length === 0) {
      return;
    }
    const timer = setTimeout(() => {
      for (const [seq, phase] of waiting) {
        const action = state.actions.find((entry) => entry.seq === seq);
        if (action === undefined) {
          setPhase(seq, null);
        } else {
          send(action, phase.clientMessageId);
        }
      }
    }, ACTION_RETRY_MS);
    return () => clearTimeout(timer);
  }, [turnOpen, phases, state.actions, send, setPhase]);

  // A phase outlives nothing: a button the daemon no longer lists has none.
  useEffect(() => {
    const live = new Set(state.actions.map((action) => action.seq));
    if ([...phases.keys()].some((seq) => !live.has(seq))) {
      setPhases(
        (current) => new Map([...current].filter(([seq]) => live.has(seq))),
      );
    }
  }, [state.actions, phases]);

  // Memoised: it is a context value, and the screen re-renders per streamed row.
  return useMemo(
    () => ({
      actions: state.actions,
      throughSeq: state.throughSeq,
      phases,
      press,
      dismiss,
      confirming,
      confirmCommand,
      cancelCommand,
    }),
    [
      state.actions,
      state.throughSeq,
      phases,
      press,
      dismiss,
      confirming,
      confirmCommand,
      cancelCommand,
    ],
  );
}
