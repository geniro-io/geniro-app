interface Harness {
  state: () => ChatRunState;
  swapDraft: ReturnType<typeof vi.fn>;
  resetSteerStatus: ReturnType<typeof vi.fn>;
  drain: ReturnType<typeof vi.fn>;
  /** What the hook reported of "not sent" rows arriving live. */
  liveUnsent: ReturnType<typeof vi.fn>;
  /** Which runs the composer is holding follow-ups for. */
  queued: Set<string>;
  unmount: () => void;
}

/** Drive the hook alone, through a probe component that renders nothing. */
async function mount(
  client: DaemonClient,
  historyPageSize?: number,
): Promise<Harness> {
  let latest: ChatRunState | null = null;
  const swapDraft = vi.fn();
  const resetSteerStatus = vi.fn();
  const drain = vi.fn();
  const queued = new Set<string>();
  const drainQueueRef = { current: drain };
  const liveUnsent = vi.fn();
  const onLiveUnsentRef = { current: liveUnsent };
  function Probe(): null {
    latest = useChatRun({
      client,
      chatApi: pagedChatApi as unknown as ChatsApi,
      workflowApi: workflowApi as unknown as WorkflowsApi,
      swapDraft,
      resetSteerStatus,
      hasQueuedMessages: (runId) => queued.has(runId),
      drainQueueRef,
      onLiveUnsentRef,
      historyPageSize,
    });
    return null;
  }
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root?.render(<Probe />);
  });
  return {
    state: () => {
      if (latest === null) {
        throw new Error('the hook has not rendered');
      }
      return latest;
    },
    swapDraft,
    resetSteerStatus,
    drain,
    liveUnsent,
    queued,
    unmount: () => {
      act(() => {
        root?.unmount();
      });
      root = null;
    },
  };
}

/** Open a thread and let its join + history replay settle. */
async function open(harness: Harness, runId: string): Promise<void> {
  await act(async () => {
    await harness.state().activateRun(runId);
  });
}

