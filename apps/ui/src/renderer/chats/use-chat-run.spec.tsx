function msg(
  runId: string,
  seq: number,
  role: 'user' | 'assistant',
  text: string,
): ChatItem {
  return {
    id: `${runId}-i${seq}`,
    runId,
    nodeId: null,
    seq,
    kind: 'message',
    role,
    payload: { text },
    createdAt: 'now',
  };
}

/** A run-level turn end — what settles the working state and releases a queue. */
function turnEnd(
  runId: string,
  seq: number,
  kind: 'turn_complete' | 'turn_cancelled' = 'turn_complete',
): ChatItem {
  return {
    id: `${runId}-t${seq}`,
    runId,
    nodeId: null,
    seq,
    kind,
    role: null,
    payload: {},
    createdAt: 'now',
  };
}

/** A fake DaemonClient whose listeners the test fires by hand. */
function makeClient(): {
  client: DaemonClient;
  joinRun: ReturnType<typeof vi.fn>;
  leaveRun: ReturnType<typeof vi.fn>;
  emitItem: (item: ChatItem) => void;
  emitRunStatus: (event: RunStatusEvent) => void;
  emitLiveText: (event: LiveTextEvent) => void;
  fireDisconnect: () => void;
  fireReconnect: (error?: Error) => void;
  fireVerdictAck: (ack: VerdictAck) => void;
  listenerCount: () => number;
} {
  let itemListener: ((item: ChatItem) => void) | null = null;
  let runStatusListener: ((event: RunStatusEvent) => void) | null = null;
  let disconnectListener: (() => void) | null = null;
  let reconnectListener: ((error?: Error) => void) | null = null;
  let verdictAckListener: ((ack: VerdictAck) => void) | null = null;
  let liveTextSubscribed = false;
  let liveTextListener: ((event: LiveTextEvent) => void) | null = null;
  const joinRun = vi.fn(async () => {});
  const leaveRun = vi.fn();
  const client = {
    onItem: (l: (item: ChatItem) => void) => {
      itemListener = l;
      return () => {
        itemListener = null;
      };
    },
    onRunStatus: (l: (event: RunStatusEvent) => void) => {
      runStatusListener = l;
      return () => {
        runStatusListener = null;
      };
    },
    onDisconnect: (l: () => void) => {
      disconnectListener = l;
      return () => {
        disconnectListener = null;
      };
    },
    onReconnect: (l: (error?: Error) => void) => {
      reconnectListener = l;
      return () => {
        reconnectListener = null;
      };
    },
    onVerdictAck: (l: (ack: VerdictAck) => void) => {
      verdictAckListener = l;
      return () => {
        verdictAckListener = null;
      };
    },
    onLiveText: (l: (event: LiveTextEvent) => void) => {
      liveTextSubscribed = true;
      liveTextListener = l;
      return () => {
        liveTextSubscribed = false;
        liveTextListener = null;
      };
    },
    joinRun,
    leaveRun,
  } as unknown as DaemonClient;
  return {
    client,
    joinRun,
    leaveRun,
    emitItem: (item) => itemListener?.(item),
    emitRunStatus: (event) => runStatusListener?.(event),
    emitLiveText: (event) => liveTextListener?.(event),
    fireDisconnect: () => disconnectListener?.(),
    fireReconnect: (error) => reconnectListener?.(error),
    fireVerdictAck: (ack) => verdictAckListener?.(ack),
    listenerCount: () =>
      [
        itemListener,
        runStatusListener,
        disconnectListener,
        reconnectListener,
        verdictAckListener,
        liveTextSubscribed ? true : null,
      ].filter(Boolean).length,
  };
}

