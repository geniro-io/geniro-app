const EMPTY_NAMING: ReadonlySet<string> = new Set();

/**
 * How many transcript items one fetch brings back.
 *
 * REPORTED as "иногда у нас разрастается чат с очень большим количеством
 * сообщений … мы должны максимум загружать где-то 1,000 сообщений … чтобы
 * интерфейс не лагал". Measured on the author's own longest thread: 7,814 items
 * are 18.9MB of payload, whose newest 1,000 are 0.63MB — so opening that chat
 * moved thirty times the bytes anybody was going to look at, parsed them, held
 * them, folded them eight times over and rendered every row.
 *
 * The window is the END of the conversation, never its start: a chat opens on
 * what was last said, and every reading the app takes off the transcript that
 * is not the transcript itself (is a turn open, is a card unanswered, what is
 * the agent doing) is about its tail.
 */
export const HISTORY_PAGE = 1000;

/**
 * May a REPLAYED transcript release this run's queue?
 *
 * The one rule, in one place. A replay carries every past turn's terminal item,
 * so no individual row may fire the drain — but a replay is also the only
 * signal that a turn ended while this client was not listening (another chat
 * was open, or the socket was down), and a queue owed its send must not wait
 * forever for a live event that already happened.
 *
 * `endedOnTerminal` may only AUTHORIZE, and the daemon's own status may only
 * authorize — but an UNKNOWN run authorizes nothing. `run?.status !== 'running'`
 * alone reads `undefined` as idle, which would send into a run this client
 * knows nothing about; erring toward not sending costs a delay the next
 * activation clears, while erring the other way delivers into a live turn.
 *
 * The status row alone cannot decide it either: three writers touch it and it
 * demonstrably lags, so on reopen the transcript's tail is the fresher witness.
 * That is why a terminal tail authorizes even while the row still says running.
 *
 * A CANCELLED turn authorizes nothing, from either witness. Stop is the user
 * asking the thread to stop, and a queue released by it starts a fresh turn in
 * answer — which is the same defect the live path has, just deferred to the
 * next time the chat is opened.
 */
function queueMayDrainAfterReplay(
  run: ChatRun | undefined,
  lastItem: ChatItem | undefined,
): boolean {
  if (run === undefined) {
    return false;
  }
  const tailSettledAs =
    lastItem === undefined ? null : settledRunStatus(lastItem);
  if (tailSettledAs === 'cancelled' || run.status === 'cancelled') {
    return false;
  }
  const endedOnTerminal =
    lastItem !== undefined &&
    TERMINAL_KINDS.has(lastItem.kind) &&
    lastItem.nodeId === null;
  // A HELD run counts as drainable even though its status is `running` and its
  // transcript has no terminal row — the daemon is DEFERRING that row until the
  // last delegate reports, which is why neither of the other two readings can
  // see it. The turn itself is over; see the live announce's own hold drain for
  // why that means the queue is owed its send. Without this the two replay
  // paths (opening the chat, and the delta after a reconnect) were the one
  // remaining way a queue could be released — and both refused a held run.
  return endedOnTerminal || run.holdingFor > 0 || run.status !== 'running';
}

/** What the run lifecycle needs from the surfaces it does not own. */
export interface ChatRunScope {
  client: DaemonClient;
  chatApi: ChatsApi;
  workflowApi: WorkflowsApi;
  /**
   * Park the composer's contents under `from` and put `to`'s back — `null` for
   * the landing card, which has no run id of its own. Owned by the composer;
   * called here because opening or closing a thread is when it has to happen.
   */
  swapDraft: (from: string | null, to: string | null) => void;
  /** The steer outcome belongs to the run the user pressed it in. */
  resetSteerStatus: () => void;
  /** Does this run hold follow-ups the drain still owes it? */
  hasQueuedMessages: (runId: string) => boolean;
  /**
   * Ref indirection: the stable `addItem` fires the drain on a turn's terminal
   * item, but the drain itself needs the current chatApi closure.
   */
  drainQueueRef: RefObject<(runId: string) => void>;
}

/** The sidebar's run list, the open transcript, and the live plane over both. */
export interface ChatRunState {
  runs: ChatRun[];
  setRuns: Dispatch<SetStateAction<ChatRun[]>>;
  /** First list fetch settled (either way) — gates the "No chats yet" claim. */
  runsLoaded: boolean;
  /**
   * Mirror of {@link ChatRunState.runs}, so the stable `activateRun` can read
   * the active run's current status without being re-created on every list
   * change.
   */
  runsRef: RefObject<ChatRun[]>;
  activeRunId: string | null;
  /**
   * The same id in a ref, so the long-lived onItem subscription always filters
   * against the current run without re-subscribing.
   */
  activeRunIdRef: RefObject<string | null>;
  items: ChatItem[];
  /** The loaded window does not reach the start of the conversation. */
  hasOlder: boolean;
  /** A page of older items is in flight. */
  loadingOlder: boolean;
  /**
   * Load the page before the oldest item on screen. Resolves true when rows
   * were prepended, so the caller can hold the reader's scroll position.
   */
  loadOlder: () => Promise<boolean>;
  /**
   * The runs whose NAME the daemon is working out right now.
   *
   * Not a field on the run row, because it is not a column of the run — it is a
   * fact about an attempt in flight, true for a few seconds and true of no run
   * after a reload. Held here so the sidebar row and the header can shimmer the
   * title while the name is coming, which is what was asked for once the wait
   * became visible ("while it's happening can we change thread title with some
   * small animation").
   */
  namingRunIds: ReadonlySet<string>;
  /**
   * Record that the USER named this run, so the naming announce cannot
   * overwrite it — see `renamedRuns`.
   */
  markRenamed: (runId: string) => void;
  liveText: ReadonlyMap<string, LiveState>;
  streaming: boolean;
  setStreaming: Dispatch<SetStateAction<boolean>>;
  error: string | null;
  setError: Dispatch<SetStateAction<string | null>>;
  activities: ReadonlyMap<string, string>;
  holding: ReadonlyMap<string, number>;
  /**
   * The runs that still have a DETACHED command out, whether or not their
   * thread is open.
   *
   * A set rather than a map: nothing measures how long a command has been
   * running, unlike a hold, whose start the header's worked figure subtracts.
   *
   * It exists because the same question used to be answered from the OPEN
   * thread's transcript, which can only ever answer it about one run — so a
   * settled chat with a command still out badged itself `working` while
   * selected and `completed` the moment it was not. Seeded from the run list
   * and kept current by the announce, so every row reads the same fact.
   */
  shellsOut: ReadonlySet<string>;
  settleSummaries: ReadonlyMap<string, string | null>;
  quietSettles: ReadonlySet<string>;
  /**
   * Requests the daemon reported as already settled — invalid answers remain
   * retryable, while expired cards stop retrying forever.
   */
  deadRequestKeys: Set<string>;
  /**
   * Set when a run is opened, cleared by the first render that has its items.
   * Opening a run must land on the NEWEST message, and the at-bottom gate
   * cannot decide that: activateRun empties the transcript first, which clamps
   * the scroller to 0, so when the history renders the gate correctly reads
   * "not at bottom" and would suppress the scroll — leaving the user at the
   * oldest message of every chat they open.
   */
  pendingScrollRef: RefObject<boolean>;
  /**
   * True once a terminal item has been seen for the active run since the last
   * activateRun. Guards the post-replay streaming derive from re-arming Stop on
   * a turn that already ended — e.g. a terminal WS item that lands during the
   * history fetch while the cached run.status is still 'running' and the
   * history snapshot predates that terminal item.
   */
  sawTerminalRef: RefObject<boolean>;
  /**
   * Append one item to the open transcript. `live` says it arrived on the wire
   * as it happened, rather than out of a history replay — see the callback's
   * own doc for why it has no default.
   */
  addItem: (item: ChatItem, live: boolean) => void;
  /**
   * File a context reading against this client's copy of the run row — the
   * middle source `chatContext` ranks between the live plane and the
   * transcript.
   *
   * Exposed for the ONE reader outside the live plane that holds a fresher
   * figure than either: the context panel's own ask, which reaches the CLI's
   * accounting directly. Its guards belong to the callback, so a caller states
   * a reading and never decides whether it counts.
   */
  rememberRunContext: (
    runId: string,
    tokens: number | null,
    window: number | null,
  ) => void;
  refreshRuns: () => void;
  /** How much of the archive the sidebar is showing. */
  chatScope: ChatListScope;
  /** Switch what the sidebar covers and refetch. */
  showScope: (next: ChatListScope) => void;
  /** Prepend a freshly created run, leaving the archive if that is what is up. */
  addRun: (run: ChatRun) => void;
  /**
   * Re-file a run whose ARCHIVED state just changed: update its row where the
   * current scope still holds it, take the row off where it does not.
   */
  placeRun: (run: ChatRun, closeOpen: () => void) => void;
  /** Drop a run's row; `closeOpen` runs instead when that run is the open one. */
  dropRun: (runId: string, closeOpen: () => void) => void;
  activateRun: (runId: string) => Promise<void>;
  /** Stable id-keyed activation for the memoized ChatListItem rows. */
  handleActivateRun: (runId: string) => void;
  /** Close the open thread: leave its room and empty the transcript plane. */
  deactivateRun: () => void;
}

/**
 * One chat screen's RUN lifecycle: which thread is open, what the daemon has
 * said about every thread, and the websocket that keeps both current.
 *
 * The join and the leave are BOTH here, and that is the point rather than a
 * tidiness: a `leaveRun` written anywhere else is a room the transcript goes on
 * rendering items from, or one the next thread never receives any in.
 */
export function useChatRun(scope: ChatRunScope): ChatRunState {
  const {
    client,
    chatApi,
    workflowApi,
    swapDraft,
    resetSteerStatus,
    hasQueuedMessages,
    drainQueueRef,
  } = scope;

  const [runs, setRuns] = useState<ChatRun[]>([]);
  /**
   * How much of the archive the sidebar is showing.
   *
   * Mirrored into a ref because `refreshRuns` is called from places that
   * cannot pass it — the mount effect, the reconnect handler, `newChat` — and
   * reading it off state there would rebuild `refreshRuns` on every switch,
   * re-arming the socket effect that depends on its identity.
   */
  const [chatScope, setChatScope] = useState<ChatListScope>('active');
  const chatScopeRef = useRef<ChatListScope>('active');
  /**
   * Which `refreshRuns` call the list on screen belongs to.
   *
   * Last to RESOLVE is not last to be asked for — the same rule
   * `use-pull-requests` states for its per-folder reads. It bites harder here
   * because `active` and `archived` are DISJOINT: the active fetch runs the
   * pull-request capture pass over every run, so it can still be in flight
   * when the user reaches the archive, and landing it there would fill the
   * archive with rows offering Unarchive and a permanent delete that do not
   * apply to them.
   */
  const refreshGenerationRef = useRef(0);
  const [activeRunId, setActiveRunId] = useState<string | null>(null);
  const [items, setItems] = useState<ChatItem[]>([]);
  /**
   * The loaded window may not reach the start of the conversation.
   *
   * False on a thread whose whole history is on screen, which is nearly all of
   * them — see {@link HISTORY_PAGE}. The transcript reads it to decide whether
   * scrolling up should fetch, and to say so while it does.
   */
  const [hasOlder, setHasOlder] = useState(false);
  const [loadingOlder, setLoadingOlder] = useState(false);
  /**
   * Mirror of {@link items}, so the stable `loadOlder` can read the oldest row
   * on screen without being re-created on every streamed item — which would
   * re-arm the transcript's scroll listener several times a second.
   */
  const itemsRef = useRef<ChatItem[]>([]);
  useEffect(() => {
    itemsRef.current = items;
  }, [items]);
  /**
   * A page fetch is in flight — a REF, not the state above, because the scroll
   * handler fires many times a second and reads this to decide whether to ask
   * again. State is one commit behind, which is several more identical
   * requests.
   */
  const loadingOlderRef = useRef(false);
  // The agent's not-yet-durable words, per agent. Ephemeral: never persisted,
  // never replayed, and cleared whenever the durable transcript is refetched.
  const [liveText, setLiveText] =
    useState<ReadonlyMap<string, LiveState>>(EMPTY_LIVE_TEXT);
  // Ephemeral like the plane above, and for the same reason: a naming in flight
  // is a fact about the next few seconds, not a column of the run.
  const [namingRunIds, setNamingRunIds] =
    useState<ReadonlySet<string>>(EMPTY_NAMING);
  /**
   * Runs this window has renamed, so a naming announce still in flight cannot
   * put the generated title back over the user's own.
   *
   * A ref rather than state: nothing re-renders when a run joins it, and the
   * set is read inside the announce handler that is already running. It is
   * never cleared — a name the user typed outranks the agent's for the life of
   * the chat, which is the same rule the daemon enforces in SQL.
   */
  const renamedRuns = useRef(new Set<string>());
  const [streaming, setStreaming] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const activeRunIdRef = useRef<string | null>(null);
  const pendingScrollRef = useRef(false);
  // Highest seq rendered for the active run — the replay cursor used to fetch
  // only the items missed during a disconnect.
  const lastSeqRef = useRef(-1);
  const reconnectAfterSeqRef = useRef(-1);
  const runsRef = useRef<ChatRun[]>([]);
  // A boolean rather than Graphs' `| null` sentinel deliberately: `runs` has
  // a dozen array-op call sites (map/filter/find/setRuns updaters) that a
  // null union would force to re-guard.
  const [runsLoaded, setRunsLoaded] = useState(false);
  useEffect(() => {
    runsRef.current = runs;
  }, [runs]);
  const sawTerminalRef = useRef(false);
  /**
   * The same thing, but LIVE items only.
   *
   * `sawTerminalRef` answers "has any turn ended since this run was activated",
   * which a fail-fast run needs (its terminal item is in the replayed history).
   * It cannot answer the question the activation below actually has — "did a
   * turn end while I was fetching" — because every chat past its first turn
   * replays a `turn_complete` and would set it. That made re-opening a working
   * multi-turn chat show Send instead of Stop, which is the opposite of what
   * that code promises.
   */
  const sawLiveTerminalRef = useRef(false);

  /**
   * What each running run is DOING right now, keyed by run id — "running
   * Bash", "waiting for your answer". Ephemeral: it describes the moment, so
   * it is never fetched, only pushed, and an unknown run simply has no entry.
   */
  const [activities, setActivities] = useState<ReadonlyMap<string, string>>(
    new Map(),
  );
  /**
   * Runs whose turn is HELD — the agent has finished and the process is alive
   * only until the delegates it launched report back.
   *
   * It is deliberately not folded into `activities`: that map holds a sentence
   * to display, and this is a fact the composer ACTS on. While a run is held
   * the CLI is idle, so a message typed then goes straight out instead of into
   * the queue — reported as "if claude is running agents in background it's
   * like it stopped to work until it gets a notification from them… we should
   * not send the message to the queue while it's just waiting for listeners".
   */
  /*
   * A MAP, keyed run → when the hold was first seen, and the timestamp earns
   * its place: the header's worked figure is not a wall clock, and a hold is
   * exactly the kind of stretch it exists to exclude. `OpenTurn.openSince`
   * already does this for a turn parked on an approval — "a turn parked
   * overnight would otherwise report eight hours of work nobody did" — and an
   * agent that stopped talking twenty minutes ago is the same claim from the
   * other side. Measured on the reported screenshot: `44m 45s · worked 44m
   * 45s`, of which the last twenty minutes were a dev server the turn was
   * waiting on rather than any work.
   *
   * First SEEN, not first begun: a window opened mid-hold cannot know when it
   * started, and dating it from now leaves the part it did not witness counted
   * as work. That errs toward overstating the work, which is the direction that
   * cannot invent a pause the agent never took.
   */
  const [holding, setHolding] = useState<ReadonlyMap<string, number>>(
    new Map(),
  );
  /**
   * {@link holding} as the announce handler reads it — the hold has to be
   * compared to its PREVIOUS value to spot the moment it begins, and that
   * comparison decides whether to fire the drain. A `setHolding` updater cannot
   * be where that happens: React invokes an updater twice under StrictMode and
   * may discard the result of a render it throws away, so a send fired from
   * inside one is a send fired an arbitrary number of times.
   */
  const holdingRef = useRef<ReadonlyMap<string, number>>(holding);
  useEffect(() => {
    holdingRef.current = holding;
  }, [holding]);
  /**
   * The runs holding a DETACHED command that has not reported — see
   * {@link ChatRunState.shellsOut}.
   *
   * A SET, and no ref beside it: unlike the hold, nothing fires off the moment
   * it begins (a shell releases no queue and starts no clock), so there is no
   * previous value anything has to be compared against.
   */
  const [shellsOut, setShellsOut] = useState<ReadonlySet<string>>(
    () => new Set(),
  );
  /**
   * What each run SAID as it last settled — the agent's closing words, or the
   * failure's message, as the daemon announced them.
   *
   * Its own map beside {@link ChatRunState.activities} rather than a field on
   * the run row: it describes a MOMENT (this settle) and not the row's current
   * state, and it arrives on the same push channel — a background thread's row
   * is only as fresh as the last list fetch, so writing it there would mix a
   * live fact into stale ones. Read by the notification rules, which is the one
   * place that has to tell the user what happened without opening the chat.
   */
  const [settleSummaries, setSettleSummaries] = useState<
    ReadonlyMap<string, string | null>
  >(new Map());
  /**
   * The runs whose LAST settle is not worth interrupting the user for.
   *
   * Two daemon flags feed it and they are different statements: `housekeeping`
   * says the turn produced nothing but the CLI's own compaction, `restored`
   * says the status is being handed BACK — a delegate lease expiring over a run
   * that had already settled, which crosses non-terminal→terminal a second time
   * for a turn that ended minutes ago. Both would otherwise earn a banner and a
   * sidebar mark for an ending the user has already seen.
   *
   * A set beside the summaries and updated from the same announce, because it
   * describes the same moment: whether that ending was worth interrupting the
   * user for. Both notification surfaces read it, so the banner and the sidebar
   * mark cannot disagree about one turn.
   */
  const [quietSettles, setQuietSettles] = useState<ReadonlySet<string>>(
    new Set(),
  );

  /**
   * A replay's one reading of the sidebar row — the run's status, taken from
   * the LAST item it replayed (the only terminal item that can describe the
   * present), and the preview line, taken from the last `message` row in the
   * same batch.
   *
   * It exists because the alternative (letting each replayed row mirror itself)
   * writes a past turn's ending over a run that is working right now; see the
   * `live` gate in `addItem`. Applied only when the row still says `running`,
   * so a replay can settle a stale row but never contradict a fresher
   * `run_status` broadcast that arrived while the fetch was in flight.
   *
   * The PREVIEW is here for the same reason and against a symptom of its own:
   * mirrored per row, every replayed message wrote itself into the sidebar's
   * one preview line, so the line's final owner was decided by whatever the
   * batch happened to end on rather than by any rule. It picks by
   * {@link previewMessageOf} — the same rule the daemon's run list uses, so the
   * two sources cannot write different owners into one line — takes the WHOLE
   * batch rather than its tail (which is routinely a `turn_complete`), and
   * writes nothing at all when the batch holds no message it should preview: a
   * reconnect delta carrying only tool rows must not blank a preview the run
   * list already has right.
   */
  const reconcileFromTail = useCallback(
    (runId: string, replayed: readonly ChatItem[]): void => {
      // Every row must BELONG to the run being reconciled. The two arrive from
      // different places — the id from the activation, the rows from a fetch
      // that may have been in flight across a run switch — and applying one
      // run's ending to another's row is the same class of cross-contamination
      // `activateRun`'s own stale-fetch guard exists for.
      const own = replayed.filter((item) => item.runId === runId);
      const lastItem = own.at(-1);
      if (lastItem === undefined) {
        return;
      }
      const settled = settledRunStatus(lastItem);
      const lastMessage = previewMessageOf(own);
      const previewText =
        lastMessage === undefined
          ? null
          : payloadString(lastMessage.payload, 'text');
      if (settled === null && previewText === null) {
        return;
      }
      setRuns((prev) =>
        prev.map((run) => {
          if (run.id !== runId) {
            return run;
          }
          const next = { ...run };
          if (settled !== null && run.status === 'running') {
            next.status = settled;
          }
          if (previewText !== null) {
            next.lastMessage = previewText;
          }
          // `updatedAt` is deliberately NOT touched here, though the rows in
          // hand are newer than it: this runs on ACTIVATION, so a time invented
          // from them moves the thread in the list at the exact moment the user
          // clicks it — which is the whole of the reported jump. The row's time
          // is the daemon's, kept current for every thread alike by
          // `RunStatusEvent.at`.
          return next;
        }),
      );
    },
    [],
  );

  /**
   * `live` says this item arrived on the wire as it happened, rather than out
   * of a history replay.
   *
   * REQUIRED, with no default — and that is the guard, not the prose. A default
   * made the dangerous call the natural one: `forEach(addItem)` passes the
   * ARRAY INDEX as the flag, falsy for the first item and truthy for every one
   * after, which is exactly the replayed-drain bug this parameter exists to
   * prevent. Requiring it moves the rule from a comment a reader may skip to an
   * error the compiler raises.
   */
  const addItem = useCallback((item: ChatItem, live: boolean): void => {
    if (item.runId !== activeRunIdRef.current) {
      return;
    }
    setItems((prev) => {
      const last = prev[prev.length - 1];
      // Fast path: items carry a monotonic seq and are emitted persist-first,
      // so a strictly-newer item just appends. `items` stays seq-sorted, so a
      // full copy+resort per stream item (O(N² log N) to build a run) is only
      // needed on the rare out-of-order case below.
      if (last === undefined || item.seq > last.seq) {
        return [...prev, item];
      }
      // The replay/live seam (or a reconnect delta) can re-deliver an item:
      // de-dupe, then insert in seq order.
      //
      // BY ID, never by seq. Identity is what `id` means and what the seam
      // actually re-delivers — the same row twice — while `seq` is only the
      // ORDER. Treating a repeated seq as a repeated item made this the second
      // half of the duplicate-seq defect: the daemon issued one value to two
      // different rows, and this silently dropped whichever arrived second,
      // which was reliably the agent's reply ("it deletes its last message").
      // The daemon can no longer issue one twice (`ItemSeqAllocator`), but a
      // transcript written before that fix still holds such a pair, and an
      // ordering number is the wrong thing to establish identity with in any
      // case: this way those rows come back on the next replay instead of
      // staying invisible forever.
      if (prev.some((existing) => existing.id === item.id)) {
        return prev;
      }
      // A stable sort keeps two rows that DO share a seq in arrival order,
      // rather than letting their relative position flip between renders.
      return [...prev, item].sort((a, b) => a.seq - b.seq);
    });
    if (item.seq > lastSeqRef.current) {
      lastSeqRef.current = item.seq;
    }
    // Mirror a streamed message into the sidebar row's preview line, so the
    // list stays live without a refetch.
    //
    // LIVE items only, for exactly the reason the terminal-item mirror below is
    // gated: a replay carries EVERY message the thread has ever held, and each
    // one writing itself here left the line's owner decided by where the batch
    // ended. A replay takes ONE reading, in `reconcileFromTail`.
    //
    // The PREVIEW alone. This used to write the row's `updatedAt` too — the
    // sidebar's ORDER — and that was the one field it had no business
    // inventing: items reach this window for the OPEN chat only, so the thread
    // being read crept up the list on every message while the threads working
    // in the background stood still. The row's time is the daemon's, and it now
    // arrives for every thread alike on `RunStatusEvent.at`.
    if (live && item.kind === 'message') {
      // Every message previews now, whoever said it — the rule is "the newest
      // message" (see {@link previewMessageOf}), and a lone message row IS the
      // newest of the batch it arrived in. The role test that used to stand
      // here is what kept the user's own last message off the row.
      const preview = payloadString(item.payload, 'text');
      if (preview !== null) {
        setRuns((prev) =>
          prev.map((run) =>
            run.id === item.runId ? { ...run, lastMessage: preview } : run,
          ),
        );
      }
    }
    // A compaction geniro performed ITSELF discards the CLI's conversation, so
    // every figure measured on it now describes a conversation that is gone —
    // including the two this window holds. The daemon clears its own column and
    // the transcript fold resets at this row, but neither reaches these: the
    // live plane outlives the turn it was filled in (it is dropped on a run
    // switch, never on a settle), and the run row's copy here is only ever
    // WRITTEN by that plane. Reported as "после компакта кружочек не
    // обновляется. Он все еще так же заполнен с контекстом".
    //
    // …and so does a CLI's OWN compaction that did not say what it left behind.
    //
    // This used to be geniro's compaction ALONE, on the reasoning that "a CLI
    // that compacts for itself REPORTS what it left behind, and that reading
    // arrives around its own marker row rather than safely after it — clearing
    // on one of those would wipe the very figure the ring is waiting for". That
    // holds for a compaction that reported, and claude reports only SOMETIMES
    // (`CompactionFacts.postTokens`: "Claude reports this less often than
    // pre"). On the silent ones there is no figure to wipe and none coming:
    // the daemon clears its own column (`forgetContext`, on that same
    // `postTokens === null` test) and the transcript fold resets at this row,
    // while the live plane — which OUTRANKS both in `chatContext` — went on
    // holding the pre-compaction number for the rest of the window.
    //
    // REPORTED as "after compact the context circle will not be updated, unless
    // i will hover on it". Hovering is the tell rather than a workaround: it
    // opens the readout, which asks the CLI directly and mirrors the answer back
    // onto the row, so the only thing that could correct the ring was the user
    // going to look at it.
    //
    // The condition is the DAEMON's, restated: a compaction that named a post
    // figure keeps every reading, exactly as before. Reading `postTokens` alone
    // is enough — `compactionFacts` already normalises a non-positive figure to
    // null, which is the same "not a measurement" the daemon's `<= 0` arm means.
    //
    // The WINDOW is kept: it belongs to the model, which a compaction does not
    // change.
    // The `system` guard is the twin's (`endsContextHistory` in
    // `compaction-payload.ts`), and the pair only holds if BOTH sides apply it:
    // the key is written onto a system row alone, so a future item kind
    // carrying it would empty the ring in one reader and not the other — one
    // compaction, two answers about whether the readings above it still stand.
    const compactedSilently =
      item.kind === 'system' &&
      compactionFacts(item.payload)?.postTokens === null;
    if (
      item.kind === 'system' &&
      (conversationReplaced(item.payload) || compactedSilently)
    ) {
      setLiveText((prev) => {
        const next = new Map(prev);
        for (const [key, state] of next) {
          next.set(key, { ...state, contextTokens: null });
        }
        return next;
      });
      setRuns((prev) =>
        prev.map((run) =>
          run.id === item.runId ? { ...run, contextTokens: null } : run,
        ),
      );
    }
    // Only a RUN-level terminal item ends the working state — a workflow's
    // per-node turn_complete/error (nodeId set) must not re-enable the composer
    // while sibling branches are still running.
    const settledStatus = settledRunStatus(item);
    if (settledStatus !== null) {
      sawTerminalRef.current = true;
      if (live) {
        sawLiveTerminalRef.current = true;
      }
      // LIVE items only — for the status and the working state alike, and for
      // the same reason the drain below is gated: a replayed transcript carries
      // EVERY past turn's terminal item, and the last of those is routinely not
      // the run's current state. Mirroring one wrote `completed` onto a run whose
      // next turn was in flight, and the write outlived the visit: the row stayed
      // wrong in `runs`, so the next activation read it as settled, left
      // `streaming` false, and the transcript's live row disappeared with it.
      // Measured on the real app — a chat with a blocked tool call read
      // `running · Working… 3m 39s`, and after switching to another chat and back
      // read `completed` with no live row, while the daemon still said `running`.
      //
      // A replay's own reading is taken ONCE by the caller, from the LAST item
      // (see `activateRun` and the reconnect delta), which is the only terminal
      // item that can describe the present.
      if (live) {
        setStreaming(false);
        // Mirror the daemon's settle write into the sidebar list — without this
        // a finished run keeps its stale 'running' badge until an app restart.
        // The STATUS only: the same settle announces `RunStatusEvent.at`, which
        // is where the row's time comes from for every thread rather than for
        // whichever one this window happens to have open.
        setRuns((prev) =>
          prev.map((run) =>
            run.id === item.runId ? { ...run, status: settledStatus } : run,
          ),
        );
      }
      // The turn ended — fire the next queued message into this chat (the
      // early return above guarantees item.runId IS the active run).
      //
      // LIVE items only. A replayed transcript carries every past turn's
      // terminal item, so re-opening a chat that is still working used to
      // drain the queue straight into the turn in flight — and claude accepts
      // a mid-turn follow-up, so it genuinely went. That is the exact
      // behaviour the queue exists to prevent, and Steer is the only sanctioned
      // way to reach a running turn. A replay's own drain decision is made once
      // by the caller, from the run's settled status.
      //
      // …and NEVER on a CANCEL. Stop is the user asking for the thread to stop,
      // and the drain answered it by starting a fresh turn on the spot — the
      // reported "I stopped the thread, but see it continue working", with the
      // `cancelled` row and the new turn's `Working…` one under it in the same
      // transcript. The message stays at the head of the queue, where Send-now,
      // Edit and Remove all still reach it; what it no longer does is let itself
      // out through the door the user just closed.
      if (
        live &&
        settledStatus !== 'cancelled' &&
        hasQueuedMessages(item.runId)
      ) {
        drainQueueRef.current(item.runId);
      }
    }
  }, []);

  /** Reload the sidebar's run list from the daemon (statuses included) —
   *  live items only reach the ACTIVE run's room, so other runs' settles are
   *  picked up by refetching at natural moments (mount, pressing +). */
  /**
   * Keep the run ROW's context reading current from the live plane.
   *
   * `chatContext` ranks the row ABOVE the transcript because the row is the
   * daemon's running total and the transcript can only carry a figure per
   * SETTLED turn. That ranking was only ever true of the daemon's row — the
   * copy HERE is whatever `GET /v1/chats` returned when the list was last
   * fetched, and nothing refreshed it: `run_status` carries status, activity,
   * `updatedAt`, the preview and the title, and no reading. So the copy froze
   * at the moment the window opened while the daemon's row went on moving.
   *
   * REPORTED as "у меня только что прыгнул кружочек с контекстом. Он показывал
   * 50%. Как только я на него навёл, он начал показывать правильную цифру:
   * 70%" — the ring on a frozen copy, the readout asking the live CLI. Measured
   * on the reporter's own `geniro.db` at that moment: the daemon's row held
   * 740,515 of 1,000,000 (74%) for that chat.
   *
   * The live plane is dropped when a turn settles (a context figure alone
   * keeps the entry, but a settle clears the figure too), which is what made
   * this show up BETWEEN turns rather than during one. Mirroring here means
   * the copy holds the newest reading this client has actually seen, so the
   * fallback the settle drops into is that reading rather than an old one.
   *
   * Guarded on the value CHANGING: this fires many times a second during a
   * turn, and an unconditional `setRuns` would re-render the whole sidebar on
   * every delta to store a number that had not moved.
   */
  const rememberRunContext = useCallback(
    (runId: string, tokens: number | null, window: number | null): void => {
      // A non-positive count is not a measurement — the same rule the live
      // plane and the transcript fold already apply, so a turn that reports
      // nothing cannot erase a real figure.
      if (tokens === null || tokens <= 0) {
        return;
      }
      const nextWindow = window !== null && window > 0 ? window : null;
      setRuns((prev) => {
        const run = prev.find((candidate) => candidate.id === runId);
        if (
          run === undefined ||
          (run.contextTokens === tokens &&
            (nextWindow === null || run.contextWindowTokens === nextWindow))
        ) {
          return prev;
        }
        return prev.map((candidate) =>
          candidate.id === runId
            ? {
                ...candidate,
                contextTokens: tokens,
                // A turn that reports no window has said nothing about one;
                // overwriting with its silence is what leaves a bare count
                // where the ring was.
                ...(nextWindow === null
                  ? {}
                  : { contextWindowTokens: nextWindow }),
              }
            : candidate,
        );
      });
    },
    [],
  );

  const markRenamed = useCallback((runId: string): void => {
    renamedRuns.current.add(runId);
  }, []);

  const refreshRuns = useCallback((): void => {
    const scope = chatScopeRef.current;
    const generation = ++refreshGenerationRef.current;
    void Promise.all([
      // The param is omitted for the default rather than sent as `'active'`,
      // so the common request is the one the daemon reads with no query at all.
      chatApi.listChats(scope === 'active' ? {} : { scope }),
      // ARCHIVED holds chats and nothing else — workflow runs have no archive,
      // so listing them there would put rows in a view whose own controls
      // (unarchive, delete permanently) cannot act on them. Under `all` they
      // belong: that scope widens the archive, not the run kind.
      scope === 'archived'
        ? Promise.resolve([])
        : workflowApi.listWorkflowRuns(),
    ])
      .then(([chats, workflowRuns]) => {
        if (generation !== refreshGenerationRef.current) {
          return;
        }
        const all = [...chats, ...workflowRuns].sort((a, b) =>
          b.createdAt.localeCompare(a.createdAt),
        );
        setRuns(all);
        // Seeded from the SNAPSHOT, not only from the live announce. The hold
        // starts with one broadcast and then lasts as long as the delegates do,
        // so a window opened after it — or one that just reconnected — would
        // otherwise read a held run as a working agent and queue the user's
        // message behind delegates that have minutes left to run.
        setHolding(
          new Map(
            all
              .filter((r) => r.holdingFor > 0)
              .map((r) => [r.id, Date.now()] as const),
          ),
        );
        // Seeded from the SNAPSHOT for a sharper version of the reason above: a
        // detached command routinely outlives the turn that launched it, so a
        // window opened afterwards sees no turn and no announce for it at all —
        // the row is the only place the fact exists for that window.
        setShellsOut(
          new Set(all.filter((r) => r.shellsOpen > 0).map((r) => r.id)),
        );
      })
      .catch((err: unknown) => {
        // Superseded on both arms, not only the happy one: a failed fetch of
        // the side the user has already left must not put its error on screen
        // over a listing that loaded fine.
        if (generation === refreshGenerationRef.current) {
          setError(String(err));
        }
      })
      // Either way the first fetch settled — "No chats yet" is reserved for a
      // resolved-but-empty list, never shown while the fetch is in flight.
      .finally(() => {
        if (generation === refreshGenerationRef.current) {
          setRunsLoaded(true);
        }
      });
  }, [chatApi, workflowApi]);

  /**
   * Switch what the sidebar covers, and refetch.
   *
   * The ref is written BEFORE the refetch, not by the effect that mirrors the
   * state: `refreshRuns` reads it synchronously, so a switch that only called
   * `setChatScope` would refetch the scope the user just left.
   */
  const showScope = useCallback(
    (next: ChatListScope): void => {
      chatScopeRef.current = next;
      setChatScope(next);
      // The rows on screen deliberately STAY until the fetch lands. Blanking
      // them was right while the two listings were disjoint and the row's
      // actions came from the VIEW; now a row draws its own from its own
      // `archivedAt`, so a row the new scope will drop is still drawn
      // correctly for the moment it survives. What blanking cost is not a
      // flicker: the active listing runs the pull-request capture pass, which
      // is seconds on its first sweep, and an empty sidebar under "Loading
      // chats…" for that long is the worse of the two.
      refreshRuns();
    },
    [refreshRuns],
  );

  /**
   * Put a freshly created run at the top of the list.
   *
   * A new run is never archived, so it belongs under `active` and under `all`
   * alike — only `archived` is the wrong place for it, and prepending it there
   * would put a row in the shelf offering Unarchive and a permanent delete
   * that do not apply to it. That case leaves the shelf instead; the switch
   * refetches and the new run arrives in that listing.
   */
  const addRun = useCallback(
    (run: ChatRun): void => {
      if (chatScopeRef.current === 'archived') {
        showScope('active');
        return;
      }
      setRuns((prev) => [run, ...prev]);
    },
    [showScope],
  );

  /**
   * Re-file a run whose archived state just changed.
   *
   * Under `all` the row STAYS and only its actions change, which is the whole
   * point of that scope — dropping it there was the disjoint-listing
   * assumption reaching one scope too far, and it would make a thread vanish
   * from a list that is meant to hide nothing. Under `active` and `archived` a
   * flipped run has left the listing, so the row goes; when it is the thread on
   * screen the window is handed back rather than left on a row nothing lists.
   */
  const placeRun = useCallback((run: ChatRun, closeOpen: () => void): void => {
    const scope = chatScopeRef.current;
    const belongs =
      scope === 'all' || (run.archivedAt != null) === (scope === 'archived');
    if (belongs) {
      setRuns((prev) => prev.map((row) => (row.id === run.id ? run : row)));
      return;
    }
    if (activeRunIdRef.current === run.id) {
      closeOpen();
      return;
    }
    setRuns((prev) => prev.filter((row) => row.id !== run.id));
  }, []);

  /**
   * Take a run's row off whichever list is showing, handing the window back to
   * the composer when that run is the one open.
   *
   * For a run that no longer EXISTS — the permanent delete. A run that merely
   * moved between sides of the archive goes through {@link placeRun}, which
   * can keep it.
   */
  const dropRun = useCallback((runId: string, closeOpen: () => void): void => {
    if (activeRunIdRef.current === runId) {
      closeOpen();
      return;
    }
    setRuns((prev) => prev.filter((run) => run.id !== runId));
  }, []);

  const activateRun = useCallback(
    async (runId: string): Promise<void> => {
      const previous = activeRunIdRef.current;
      if (previous && previous !== runId) {
        client.leaveRun(previous);
      }
      // Only on a genuine CHANGE of thread. `activateRun` is also called to
      // re-open the thread already showing (a refresh, a re-select), and
      // swapping a draft out and back through that path would hand the
      // composer whatever the map held rather than what is on screen.
      if (previous !== runId) {
        swapDraft(previous, runId);
      }
      resetSteerStatus();
      activeRunIdRef.current = runId;
      lastSeqRef.current = -1;
      sawTerminalRef.current = false;
      sawLiveTerminalRef.current = false;
      pendingScrollRef.current = true;
      setActiveRunId(runId);
      setItems([]);
      // Both belong to the thread being left. `hasOlder` is answered by the
      // fetch below; clearing it first stops the incoming thread from offering
      // to page through a conversation it has not read yet.
      setHasOlder(false);
      setLoadingOlder(false);
      loadingOlderRef.current = false;
      setLiveText(EMPTY_LIVE_TEXT);
      setStreaming(false);
      setError(null);
      // Join FIRST so any live item published during the history fetch is
      // buffered through addItem; the seq de-dupe reconciles the overlap.
      try {
        await client.joinRun(runId);
        const history = await chatApi.listRunItems({
          runId,
          limit: HISTORY_PAGE,
        });
        // A FULL page may have more behind it; a short one is the whole
        // conversation. Asking for one more item than the page would be the
        // other way to know, and this one costs no extra row — the worst case
        // is one page-load that comes back empty on a thread of exactly 1,000.
        setHasOlder(history.length === HISTORY_PAGE);
        // The user may have switched runs while this fetch was in flight —
        // a stale completion must not replay items or re-arm Stop/streaming
        // (and cross-contaminate errors) for the CURRENTLY active run.
        if (activeRunIdRef.current !== runId) {
          return;
        }
        history.forEach((item) => addItem(item, false));
        // Reconnecting/switching to an in-flight run must show the working state
        // (Stop), not an enabled Send that a second message would race into a
        // RUN_BUSY. Derive it from the run's status + whether the replayed
        // transcript already ended on a terminal item.
        const run = runsRef.current.find((r) => r.id === runId);
        const last = history.at(-1);
        const endedOnTerminal =
          last !== undefined && settledRunStatus(last) !== null;
        // The replay's ONE reading of its own tail — only the LAST item can say
        // what the run is now, which is why no individual replayed row is allowed
        // to (see `addItem`). It covers the turn that ended while the user was
        // looking at another chat, where the row they are carrying still says
        // running and nothing else will correct it.
        reconcileFromTail(runId, history);
        if (
          run?.status === 'running' &&
          !sawLiveTerminalRef.current &&
          !endedOnTerminal
        ) {
          setStreaming(true);
        }
        // NOT an `else` to the branch above, and the one case where the two
        // both fire is exactly what that costs: a HELD run is still `running`
        // with no terminal row, so it takes the live-row branch AND is owed its
        // drain. Every other run answers only one of them — a settled run
        // cannot enter the first, and a genuinely working one is refused by
        // `queueMayDrainAfterReplay`.
        if (queueMayDrainAfterReplay(run, last) && hasQueuedMessages(runId)) {
          // The ONE drain decision a replay is allowed to make, and it is taken
          // from the daemon's own run status rather than from any transcript
          // row: the turn this chat was on finished while the user was looking
          // at another one, so the queue is owed its send. While the run is
          // still `running` and not HELD nothing is sent — Steer is the only
          // way into a live turn.
          drainQueueRef.current(runId);
        }
      } catch (err) {
        if (activeRunIdRef.current === runId) {
          setError(String(err));
        }
      }
    },
    [client, chatApi, addItem],
  );

  const handleActivateRun = useCallback(
    (runId: string): void => void activateRun(runId),
    [activateRun],
  );

  /**
   * The other half of the join/leave pair, and it lives here for that reason
   * alone: the room a thread was opened into is left by the same owner that
   * joined it, so no other file can close a transcript and leave its room open.
   */
  const deactivateRun = useCallback((): void => {
    const previous = activeRunIdRef.current;
    if (previous) {
      client.leaveRun(previous);
    }
    swapDraft(previous, null);
    activeRunIdRef.current = null;
    setActiveRunId(null);
    setItems([]);
    setLiveText(EMPTY_LIVE_TEXT);
    setStreaming(false);
    setError(null);
  }, [client]);

  useEffect(() => {
    refreshRuns();
    // Wrapped, not passed bare: this is the one site that means LIVE, and an
    // arrow pins the arity so a future emitter argument cannot land on the
    // `live` flag.
    const unsubscribeItem = client.onItem((item) => addItem(item, true));
    const unsubscribeLiveText = client.onLiveText((event) => {
      // Throwaway by design — only ever shown for the run on screen, and
      // dropped wholesale on a run switch or a disconnect.
      if (event.runId !== activeRunIdRef.current) {
        return;
      }
      setLiveText((prev) => applyLiveText(prev, event));
      rememberRunContext(
        event.runId,
        event.contextTokens,
        event.contextWindowTokens,
      );
    });
    const unsubscribeDisconnect = client.onDisconnect(() => {
      reconnectAfterSeqRef.current = lastSeqRef.current;
      // The daemon kept streaming while we were away and the tail we hold is
      // now arbitrarily stale; the durable replay below is complete on its own.
      setLiveText(EMPTY_LIVE_TEXT);
    });
    // On reconnect the WS missed any items streamed while offline (the room
    // buffers nothing for an absent member); fetch just the delta past the last
    // seq we rendered. addItem de-dupes, so an overlap with re-joined live items
    // is harmless.
    const unsubscribeReconnect = client.onReconnect((joinError) => {
      const active = activeRunIdRef.current;
      if (!active) {
        return;
      }
      if (joinError) {
        setError(joinError.message);
        return;
      }
      void chatApi
        .listRunItems({ runId: active, afterSeq: reconnectAfterSeqRef.current })
        // A replay, not live: no individual row here may fire the drain, or a
        // transcript several turns long would send into the turn in flight.
        //
        // But this delta is ALSO the only place a turn that ended while the
        // socket was down is ever seen, so the same single decision the
        // activation replay takes has to be taken here too. An earlier version
        // of this comment claimed the queue would go out "on the next live
        // terminal item, or on the next activation" — neither fires when the
        // turn already ended offline, so the queue simply stopped forever, and
        // on cursor there is not even a Steer control to release it by hand.
        .then((items) => {
          items.forEach((item) => addItem(item, false));
          // Same single reading the activation replay takes, and needed here for
          // the same reason it is needed there: these rows are historical to the
          // renderer (no individual one may mirror its status) but they are the
          // only sighting of a turn that ended while the socket was down.
          reconcileFromTail(active, items);
          const run = runsRef.current.find((r) => r.id === active);
          if (
            queueMayDrainAfterReplay(run, items.at(-1)) &&
            hasQueuedMessages(active)
          ) {
            drainQueueRef.current(active);
          }
        })
        // Same stale-run guard as activateRun's catch: if the user switched
        // runs while this delta-fetch was in flight, A's error must not paint
        // over B (addItem is already run-scoped by item.runId; setError is not).
        .catch((err: unknown) => {
          if (activeRunIdRef.current === active) {
            setError(String(err));
          }
        });
    });
    // Broadcast to every client, for every run — this is what keeps the badge
    // of a chat the user is NOT looking at honest. Live items only reach the
    // focused run's room, so before this a background run's settle was
    // invisible until the next refetch.
    const unsubscribeRunStatus = client.onRunStatus((event) => {
      const status = event.status;
      // An activity-only announce carries no status and must not touch the
      // badge. It fires on every tool call without reading the run, so while
      // it asserted `running` one straggler after a cancel flipped the row
      // back to running and nothing announced again to correct it.
      // `awaiting` rides the SAME row as the status rather than a map of its
      // own, because the snapshot already carries it: `GET /v1/chats` answers
      // it per run, so a window that reconnects after the transition learns it
      // from the row it just loaded, and this event only has to keep that row
      // current. A parallel map would need seeding from the snapshot anyway,
      // and would then be a second place for the same fact to go stale.
      //
      // `undefined` means the announce said nothing about waiting — the field
      // is left exactly as it was, which is what lets a tool-call announce
      // fire during a parked turn without unparking it.
      const parked = event.awaiting;
      // Recorded BEFORE the row update below, so the notification rules — which
      // run off that row changing — already have the sentence when they fire.
      if (event.summary !== undefined) {
        const said = event.summary;
        setSettleSummaries((prev) => new Map(prev).set(event.runId, said));
      }
      // Recorded on the same terms and for the same reason: only a SETTLE says
      // anything about this, and every settle says it — so an absent field is
      // an activity announce and must leave the reading alone, while a settle
      // that did real work clears the flag its predecessor may have set.
      if (event.status !== null && isSettledRunStatus(event.status)) {
        const quiet = event.housekeeping === true || event.restored === true;
        setQuietSettles((prev) => {
          if (prev.has(event.runId) === quiet) {
            return prev;
          }
          const next = new Set(prev);
          if (quiet) {
            next.add(event.runId);
          } else {
            next.delete(event.runId);
          }
          return next;
        });
      }
      // The moment the daemon wrote the row, and the ONE thing that moves this
      // list's order — see `RunStatusEvent.at`. Without it a thread working in
      // the background kept the `updatedAt` it was loaded with for the whole
      // session, and the first thing that corrected it was the user opening the
      // thread: the reported "as soon as I click a thread it jumps to the top".
      // Present only on an announce that really wrote the row, so this cannot
      // run ahead of what the next refetch will say.
      const at = event.at;
      // The title the daemon gave this run once its first turn ended. It rides
      // the same row update as the status because it is the same kind of fact —
      // a column of the run the sidebar is already showing — and it arrives
      // while the user is typically looking somewhere else, which is why it is
      // a broadcast rather than a message to the run's room.
      const named = event.title;
      // Absent asserts nothing, exactly like every other three-state field on
      // this event: an ordinary activity announce must not lower a shimmer.
      if (event.titlePending !== undefined) {
        const naming = event.titlePending;
        setNamingRunIds((prev) => {
          if (prev.has(event.runId) === naming) {
            // Same identity when nothing moved: this event fires many times a
            // second, and a fresh Set would re-render the whole sidebar on each.
            return prev;
          }
          const next = new Set(prev);
          if (naming) {
            next.add(event.runId);
          } else {
            next.delete(event.runId);
          }
          return next.size === 0 ? EMPTY_NAMING : next;
        });
      }
      /**
       * What the thread last SAID, onto the row's preview line.
       *
       * REPORTED as "i see last chat message will not be updated (if AI wrote
       * new message) untill i will open this thread". The preview was written
       * from `addItem`, which returns early on any run but the OPEN one — items
       * are delivered to a single room and a client joins one at a time — so a
       * background thread's line kept the message it was loaded with, and the
       * first thing that corrected it was the user clicking the thread. The
       * same shape, and the same fix, as `at` two fields up.
       *
       * `summary` is already the right sentence and is already on the wire: the
       * daemon put it there precisely BECAUSE the row's `lastMessage` is
       * enriched by the list endpoints alone and is therefore stale for exactly
       * these runs (see `RunStatusEvent.summary`). Nothing new is sent; the
       * sentence that was reaching the notification is now also reaching the
       * line the notification is about.
       *
       * Only a non-empty string writes. `undefined` asserts nothing, as ever —
       * but `null` differs here from what it means to the notification: there
       * it CLEARS, because a wordless settle must not re-announce the previous
       * turn's words, while a preview is the thread's last message and a turn
       * that said nothing (a `/compact`) did not remove it. Blanking the row
       * would lose a line the daemon still holds and would put back on the next
       * refetch.
       */
      const spoke =
        typeof event.summary === 'string' && event.summary.trim() !== ''
          ? event.summary
          : undefined;
      /**
       * The same line, pushed while the turn is still RUNNING.
       *
       * The fix above moves the preview when a turn ENDS, which left the
       * reported "still i see here outdated last llm message. As soon as i
       * click on thread - it will be updated to actual one" — that screenshot
       * is a thread mid-turn, where the settle is minutes away and the line
       * shows the sentence the turn opened from.
       *
       * `preview` outranks `summary` where an announce carries both, which
       * nothing does today: they are produced by different call sites, and if
       * one ever did, the message-level field is the later fact.
       */
      const previewLine =
        typeof event.preview === 'string' && event.preview.trim() !== ''
          ? event.preview
          : spoke;
      if (
        status !== null ||
        parked !== undefined ||
        at !== undefined ||
        named !== undefined ||
        previewLine !== undefined
      ) {
        setRuns((prev) =>
          prev.map((run) =>
            run.id === event.runId
              ? {
                  ...run,
                  ...(status !== null ? { status } : {}),
                  ...(parked !== undefined ? { awaiting: parked } : {}),
                  ...(at === undefined ? {} : { updatedAt: at }),
                  ...(previewLine === undefined
                    ? {}
                    : { lastMessage: previewLine }),
                  // Applied whatever the row currently says, EXCEPT to a run
                  // this window renamed.
                  //
                  // It used to require `run.title === null`, which silently
                  // discarded the announcement this event exists for: naming
                  // happens in two steps, and the second REPLACES the derived
                  // opening line with the agent's own name — so the only title
                  // that ever reached a row live was the first one, and the
                  // upgrade appeared solely on the next full list refetch.
                  // REPORTED as "still title wasn't generated. I saw some
                  // animation, but after it finished title wasn't changed",
                  // over a run whose row in the database already read
                  // `Chat startup or greeting` while the sidebar still showed
                  // `heyyy hiiii`.
                  //
                  // A rename is still safe without that test, and the daemon is
                  // what makes it so: `RunDao.retitle` writes only when the
                  // title it read is still there, so a rename that landed first
                  // makes the naming lose and publish nothing at all. What the
                  // old test was really protecting against is the ORDER — a
                  // rename committed here while the announce was already in
                  // flight — and that is what `renamedRuns` answers, precisely,
                  // instead of blocking every upgrade to protect one race.
                  ...(named !== undefined &&
                  !renamedRuns.current.has(event.runId)
                    ? { title: named }
                    : {}),
                }
              : run,
          ),
        );
      }
      // A queue in a thread the user is NOT looking at is released HERE, and
      // nowhere else. Live items are delivered to the run's own room and the
      // client joins one room at a time, so `addItem` — which fires the drain
      // for the open chat — never sees a background turn end at all. Until
      // this, such a queue waited for the user to OPEN that chat again: the
      // reported "after compacting it will not send message that was in queue
      // — only after i will choose thread", where the compaction ran for two
      // minutes and the user read another thread while it did. Reproduced
      // without any compaction: queue a follow-up, switch chats, and the turn
      // that ends 20 seconds later leaves the message undelivered.
      //
      // The ACTIVE run is deliberately left to its terminal ITEM. This
      // broadcast and that item race, and one drain per settle is the whole
      // contract — the item is the finer-grained witness (it carries the
      // stopReason a workflow's roll-up rides), so it stays the authority
      // wherever it is available.
      //
      // `cancelled` is refused on the same grounds as the live path: Stop is
      // the user closing the door, not a cue to open a fresh turn behind it.
      if (
        status !== null &&
        status !== 'cancelled' &&
        isSettledRunStatus(status) &&
        event.runId !== activeRunIdRef.current &&
        hasQueuedMessages(event.runId)
      ) {
        drainQueueRef.current(event.runId);
      }
      setActivities((prev) => {
        // An announce carrying no activity key at all says nothing about it —
        // the naming announce is the first such producer — and must leave the
        // phrase standing, or it blanks the badge and the transcript's live row
        // of a turn that is running. A terminal status still clears, since a
        // stopped run is doing nothing whatever the announce carried.
        const stopped = status !== null && status !== 'running';
        if (event.activity === undefined && !stopped) {
          return prev;
        }
        const next = new Map(prev);
        // A run that is no longer RUNNING has no current activity, whatever
        // the announce carried. A null activity was the only thing that ever
        // cleared this map, so a terminal status arriving alongside a non-null
        // one left the entry behind — and the badge went on naming a tool that
        // finished, for as long as the row lived.
        if (!event.activity || stopped) {
          next.delete(event.runId);
        } else {
          next.set(event.runId, event.activity);
        }
        return next;
      });
      // A real STATUS transition ends whatever hold was in effect — a turn
      // that settled is not held, and a new turn starting has no hold yet.
      // An activity-only announce carrying no `holdingFor` says nothing and
      // must leave the reading alone.
      const wasHeld = holdingRef.current.has(event.runId);
      const held =
        event.holdingFor !== undefined
          ? event.holdingFor > 0
          : status !== null
            ? false
            : wasHeld;
      // Unchanged means unchanged, and that is what preserves the START: a
      // hold re-announces on every unit that reports, so rewriting the entry
      // each time would restamp it and the parked stretch would never grow.
      if (held !== wasHeld) {
        const next = new Map(holdingRef.current);
        if (held) {
          next.set(event.runId, Date.now());
        } else {
          next.delete(event.runId);
        }
        // Written here as well as by the effect that mirrors the state: two
        // announces can land in one tick, and the second must not compare
        // itself against the reading the first already replaced.
        holdingRef.current = next;
        setHolding(next);
      }
      // Only an explicit count moves this, and a STATUS transition deliberately
      // does not — which is the one place it parts company with the hold above.
      // A turn settling is exactly when a detached command is still out, so
      // clearing on a settle would take the badge down at the moment it becomes
      // the only thing saying the work is not over.
      if (event.shellsOpen !== undefined) {
        const out = event.shellsOpen > 0;
        setShellsOut((prev) => {
          if (out === prev.has(event.runId)) {
            return prev;
          }
          const next = new Set(prev);
          if (out) {
            next.add(event.runId);
          } else {
            next.delete(event.runId);
          }
          return next;
        });
      }
      // The run row's own context reading, carried by every status broadcast
      // rather than only by the live deltas of the room this client happens to
      // be in. Without it a thread that worked while the user was on another
      // chat left this copy of the row frozen at whatever the run list said
      // when the window opened — the reported hour-old ring that only a hover
      // corrected.
      //
      // A POSITIVE count only, which is what routes it through
      // `rememberRunContext`'s existing guards rather than a second reading of
      // the same rules. `null` — a compaction — is deliberately ignored here:
      // the compaction ROW is what clears the count, on every plane at once,
      // and a second clearer would be a second answer to when the ring empties.
      if (event.contextTokens !== undefined && event.contextTokens !== null) {
        rememberRunContext(
          event.runId,
          event.contextTokens,
          event.contextWindowTokens ?? null,
        );
      }
      // The hold BEGINNING releases the queue, and it is the second half of a
      // rule the composer already applies to a message being typed: a held turn
      // is not a working agent. Its CLI printed its turn-end line and is sitting
      // on an idle stdin so the delegates it launched have somewhere to report.
      //
      // Without this the queue waited for the hold to END, which is the whole
      // of the reported "i can see conversation compacted, but still see some
      // background job — so new messages from queue wasnt taken": three
      // follow-ups sat in the strip while the turn they were queued behind had
      // been over for minutes. The composer refused to queue a message typed in
      // that window (`Chats.tsx`, the `holdingRef` gate on the send path) and
      // that is exactly the judgement owed to messages queued BEFORE it.
      //
      // Once per transition, never per announce: a hold re-announces on every
      // unit that reports, and a drain per report would fire the whole queue
      // into one turn. `drainQueue` sends the head alone and the turn it starts
      // fires the next one, so the queue still leaves in order.
      if (held && !wasHeld && hasQueuedMessages(event.runId)) {
        drainQueueRef.current(event.runId);
      }
    });
    const selectedRun = activeRunIdRef.current;
    if (selectedRun) {
      void activateRun(selectedRun);
    }
    return () => {
      unsubscribeItem();
      unsubscribeLiveText();
      unsubscribeDisconnect();
      unsubscribeReconnect();
      unsubscribeRunStatus();
      const active = activeRunIdRef.current;
      if (active) {
        client.leaveRun(active);
      }
    };
  }, [client, chatApi, addItem, activateRun, refreshRuns]);

  const [deadRequestKeys, setDeadRequestKeys] = useState<Set<string>>(
    new Set(),
  );
  useEffect(
    () =>
      client.onVerdictAck((ack) => {
        if (
          ack.status === 'expired' &&
          ack.runId === activeRunIdRef.current &&
          ack.requestId
        ) {
          const requestKey = `${ack.runId}:${ack.requestId}`;
          setDeadRequestKeys((prev) => new Set(prev).add(requestKey));
        }
      }),
    [client],
  );

  /**
   * Fetch the page BEFORE the oldest item on screen and prepend it.
   *
   * Guarded by a ref rather than by the loading state: the transcript calls
   * this from a scroll handler, which fires many times a second, and state is
   * one commit behind — several identical pages would already be in flight.
   *
   * Answers whether it changed anything, so the caller can restore the scroll
   * position only when rows were actually inserted above the viewport.
   */
  const loadOlder = useCallback(async (): Promise<boolean> => {
    const runId = activeRunIdRef.current;
    if (runId === null || loadingOlderRef.current) {
      return false;
    }
    const oldest = itemsRef.current[0];
    if (oldest === undefined) {
      return false;
    }
    loadingOlderRef.current = true;
    setLoadingOlder(true);
    try {
      const page = await chatApi.listRunItems({
        runId,
        limit: HISTORY_PAGE,
        beforeSeq: oldest.seq,
      });
      // The user may have switched threads while this was in flight; a stale
      // page must not be spliced into somebody else's conversation.
      if (activeRunIdRef.current !== runId) {
        return false;
      }
      setHasOlder(page.length === HISTORY_PAGE);
      if (page.length === 0) {
        return false;
      }
      // Prepended WHOLE rather than through `addItem`: that path is written for
      // the newest row and would re-sort the entire transcript once per item.
      // These are older than everything held, already in seq order, and cannot
      // collide — they were selected strictly below the oldest seq on screen.
      setItems((prev) => [...page, ...prev]);
      return true;
    } catch {
      // A page that will not load is a transcript that stops growing upward,
      // never an error banner over a conversation the user is reading. The next
      // scroll asks again.
      return false;
    } finally {
      loadingOlderRef.current = false;
      setLoadingOlder(false);
    }
  }, [chatApi]);

  return {
    runs,
    setRuns,
    runsLoaded,
    runsRef,
    activeRunId,
    activeRunIdRef,
    items,
    hasOlder,
    loadingOlder,
    loadOlder,
    namingRunIds,
    markRenamed,
    liveText,
    streaming,
    setStreaming,
    error,
    setError,
    activities,
    holding,
    shellsOut,
    settleSummaries,
    quietSettles,
    deadRequestKeys,
    pendingScrollRef,
    sawTerminalRef,
    addItem,
    rememberRunContext,
    refreshRuns,
    chatScope,
    showScope,
    addRun,
    placeRun,
    dropRun,
    activateRun,
    handleActivateRun,
    deactivateRun,
  };
}
