/**
 * A WORKFLOW run that is `running` while every agent a message goes to has
 * ended its turn — the run is carried by calls those agents started. A
 * message is taken at once there, so nothing may hold it in the queue.
 */
export function workflowRootsIdle(run: ChatRun): boolean {
  return (
    run.workflowId !== null &&
    run.status === 'running' &&
    run.rootsWorking === 0
  );
}

/**
 * The listing, with every row this window holds that the daemon wrote LATER
 * than the listing read it kept in place of the listed copy.
 *
 * The chat listing reads its rows and then runs the pull-request capture pass,
 * which takes seconds, so a status the daemon announced in between — a turn
 * settling, a hold ending — was applied here and then overwritten by the older
 * copy the listing carried. Each of those is announced once, on its
 * transition, so the row stayed wrong: `running` over a finished thread, or a
 * stale hold that let the composer send straight into a live turn. Compared on
 * `updatedAt`, which is the daemon's own write time on both sides.
 *
 * Except for the row's ARRANGEMENT — its pin, its group, its archive stamp, its colour —
 * which the LISTING always decides. The daemon writes those without moving
 * `updatedAt` (they are not activity in the thread), so the comparison above
 * says nothing about them: a held copy dated later by any status announce
 * kept a pin position the daemon had since renumbered, beside rows the
 * listing did renumber, and two pinned threads came to share a slot.
 */
function keepFresherRows(
  listed: readonly ChatRun[],
  held: readonly ChatRun[],
): ChatRun[] {
  const heldById = new Map(held.map((run) => [run.id, run] as const));
  return listed.map((row) => {
    const mine = heldById.get(row.id);
    return mine !== undefined &&
      Date.parse(mine.updatedAt) > Date.parse(row.updatedAt)
      ? {
          ...mine,
          pinnedPosition: row.pinnedPosition,
          groupId: row.groupId,
          archivedAt: row.archivedAt,
          color: row.color,
        }
      : row;
  });
}

/**
 * May a REPLAYED transcript release this run's queue?
 *
 * The one rule, in one place. A replay carries every past turn's terminal item,
 * so no individual row may fire the drain — but a replay is also the only
 * signal that a turn ended while this client was not listening (another chat
 * was open, or the socket was down), and a queue owed its send must not wait
 * forever for a live event that already happened.
 *
 * `endedOnTerminal` may only AUTHORIZE, and the daemon's own status may only
 * authorize — but an UNKNOWN run authorizes nothing. `run?.status !== 'running'`
 * alone reads `undefined` as idle, which would send into a run this client
 * knows nothing about; erring toward not sending costs a delay the next
 * activation clears, while erring the other way delivers into a live turn.
 *
 * The status row alone cannot decide it either: three writers touch it and it
 * demonstrably lags, so on reopen the transcript's tail is the fresher witness.
 * That is why a terminal tail authorizes even while the row still says running.
 *
 * A CANCELLED turn authorizes nothing, from either witness. Stop is the user
 * asking the thread to stop, and a queue released by it starts a fresh turn in
 * answer — which is the same defect the live path has, just deferred to the
 * next time the chat is opened.
 */
function queueMayDrainAfterReplay(
  run: ChatRun | undefined,
  lastItem: ChatItem | undefined,
): boolean {
  if (run === undefined) {
    return false;
  }
  const tailSettledAs =
    lastItem === undefined ? null : settledRunStatus(lastItem);
  if (tailSettledAs === 'cancelled' || run.status === 'cancelled') {
    return false;
  }
  const endedOnTerminal = tailSettledAs !== null;
  // A HELD run counts as drainable even though its status is `running` and its
  // transcript has no terminal row — the daemon is DEFERRING that row until the
  // last delegate reports, which is why neither of the other two readings can
  // see it. The turn itself is over; see the live announce's own hold drain for
  // why that means the queue is owed its send. Without this the two replay
  // paths (opening the chat, and the delta after a reconnect) were the one
  // remaining way a queue could be released — and both refused a held run.
  // A run whose manager is parked in a wait on its own callees counts for the
  // hold's reason exactly: the turn is `running` and has no terminal row, and
  // the agent is producing nothing until a callee it started does. Opening such
  // a thread, or reconnecting to it, is the one moment its queue can be
  // released — the wait's own announce may have landed before this window
  // existed.
  // Background work the run is merely CARRYING counts on the same terms, and
  // for the same reason one more step on: sub-agents still out and a detached
  // command still up each leave a run `running` with no turn to be redirected,
  // so a queue opened in that state has nothing to wait for. The composer's own
  // send path reads the same facts — see `Chats.tsx`'s
  // `activeRunHeld`, which is where they are justified.
  return (
    endedOnTerminal ||
    run.holdingFor > 0 ||
    run.awaitingCalls > 0 ||
    workflowRootsIdle(run) ||
    run.subagentsOut > 0 ||
    run.shellsOpen > 0 ||
    run.status !== 'running'
  );
}

/** What the run lifecycle needs from the surfaces it does not own. */
export interface ChatRunScope {
  client: DaemonClient;
  chatApi: ChatsApi;
  workflowApi: WorkflowsApi;
  /**
   * Park the composer's contents under `from` and put `to`'s back — `null` for
   * the landing card, which has no run id of its own. Owned by the composer;
   * called here because opening or closing a thread is when it has to happen.
   */
  swapDraft: (from: string | null, to: string | null) => void;
  /** The steer outcome belongs to the run the user pressed it in. */
  resetSteerStatus: () => void;
  /** Does this run hold follow-ups the drain still owes it? */
  hasQueuedMessages: (runId: string) => boolean;
  /**
   * Ref indirection: the stable `addItem` fires the drain on a turn's terminal
   * item, but the drain itself needs the current chatApi closure.
   */
  drainQueueRef: RefObject<(runId: string) => void>;
  /**
   * How many items one fetch brings back (`Settings.historyPageSize`); absent
   * means {@link HISTORY_PAGE}. Only the transcript's own rows depend on it —
   * every readout beside them is read from the daemon over the whole run.
   */
  historyPageSize?: number;
}

