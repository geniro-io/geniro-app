// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { ChatsApi } from '../autogenerated';
import { type ChatSearchState, useChatSearch } from './use-chat-search';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const hit = (seq: number, snippet: string): Record<string, unknown> => ({
  seq,
  kind: 'message',
  role: 'assistant',
  snippet,
  createdAt: 'now',
});

let root: Root | null = null;
let container: HTMLDivElement | null = null;
let state: ChatSearchState | null = null;

function mount(searchChat: ReturnType<typeof vi.fn>): void {
  const api = { searchChat } as unknown as ChatsApi;
  function Probe(): null {
    state = useChatSearch('r1', api);
    return null;
  }
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(<Probe />);
  });
}

/** Type, then run past the debounce and let the reply land. */
async function type(query: string): Promise<void> {
  act(() => {
    state!.setQuery(query);
  });
  await act(async () => {
    await vi.advanceTimersByTimeAsync(400);
  });
}

beforeEach(() => {
  vi.useFakeTimers({ shouldAdvanceTime: true });
});

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  state = null;
  vi.useRealTimers();
});

describe('useChatSearch', () => {
  it('asks the daemon once for a word typed a letter at a time', async () => {
    // The debounce is the whole reason it exists: without it, `bloom` is five
    // queries, four of which are about a prefix nobody meant.
    const searchChat = vi.fn().mockResolvedValue({
      hits: [hit(12, 'sizing the bloom filter')],
      partialReason: null,
    });
    mount(searchChat);

    act(() => {
      state!.setQuery('bl');
      state!.setQuery('blo');
      state!.setQuery('bloom');
    });
    await act(async () => {
      await vi.advanceTimersByTimeAsync(400);
    });

    expect(searchChat).toHaveBeenCalledTimes(1);
    expect(searchChat).toHaveBeenCalledWith({ runId: 'r1', query: 'bloom' });
    expect(state!.hits).toHaveLength(1);
  });

  it('does not ask about a single character, and says why the list is empty', async () => {
    // One character matches most rows of most conversations and the daemon caps
    // what it returns, so the answer would be a slice of an unstated whole.
    const searchChat = vi.fn().mockResolvedValue({
      hits: [],
      partialReason: null,
    });
    mount(searchChat);

    await type('b');

    expect(searchChat).not.toHaveBeenCalled();
    expect(state!.tooShort).toBe(true);
    // Not an error: the query is being typed, not failing.
    expect(state!.error).toBeNull();
  });

  it('drops a reply that a newer query has already superseded', async () => {
    // Nothing orders two in-flight fetches. A slow answer to `bloom` landing
    // after a fast one to `bloom filter` would put the wrong list under a field
    // the user is still typing in.
    const slow = new Promise((resolve) =>
      setTimeout(
        () =>
          resolve({ hits: [hit(1, 'the stale answer')], partialReason: null }),
        1_000,
      ),
    );
    const searchChat = vi
      .fn()
      .mockReturnValueOnce(slow)
      .mockResolvedValue({
        hits: [hit(2, 'the current answer')],
        partialReason: null,
      });
    mount(searchChat);

    await type('bloom');
    await type('bloom filter');
    // Long enough for the FIRST reply to arrive, well after the second landed.
    await act(async () => {
      await vi.advanceTimersByTimeAsync(2_000);
    });

    expect(state!.hits).toHaveLength(1);
    expect(state!.hits[0]!.snippet).toBe('the current answer');
  });

  it('carries the daemon’s own sentence when the list is incomplete', async () => {
    // The list is real and short, which reads as "that is all there is" unless
    // something says otherwise — the whole point of searching on the daemon
    // being to find what the client could not see.
    const searchChat = vi.fn().mockResolvedValue({
      hits: [hit(12, 'sizing the bloom filter')],
      partialReason: 'showing the newest 50 matches',
    });
    mount(searchChat);

    await type('bloom');

    expect(state!.partialReason).toBe('showing the newest 50 matches');
  });

  it('reports a failed search instead of an empty conversation', async () => {
    const searchChat = vi.fn().mockRejectedValue(new Error('daemon went away'));
    mount(searchChat);

    await type('bloom');

    expect(state!.error).not.toBeNull();
    expect(state!.hits).toEqual([]);
    expect(state!.loading).toBe(false);
  });

  it('forgets the query and its answer on reset', async () => {
    // A search is scoped to ONE conversation, so a surface that closes and
    // reopens must not come back showing the previous thread's hits.
    const searchChat = vi.fn().mockResolvedValue({
      hits: [hit(12, 'sizing the bloom filter')],
      partialReason: 'showing the newest 50 matches',
    });
    mount(searchChat);
    await type('bloom');
    expect(state!.hits).toHaveLength(1);

    act(() => {
      state!.reset();
    });

    expect(state!.query).toBe('');
    expect(state!.hits).toEqual([]);
    expect(state!.partialReason).toBeNull();
  });
});
