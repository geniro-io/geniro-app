import { useEffect, useMemo, useRef, useState } from 'react';

import type { ChatsApi, ChatSearchHit } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { daemonErrorDetail } from '../daemon-api';

/**
 * Below this the answer says nothing. One character matches most rows of most
 * conversations and the daemon caps what it returns, so the reply would be the
 * newest fifty of several thousand — a list that looks like an answer and is a
 * slice of an unstated whole.
 */
export const MIN_QUERY_CHARS = 2;

/**
 * Long enough that typing a word costs one query rather than five, short enough
 * that the list feels attached to the field. Shorter than the session picker's
 * budget on purpose: that one reads session files off disk and spawns a CLI,
 * where this is one indexed statement against one run.
 */
const SEARCH_DEBOUNCE_MS = 250;

/** What a daemon search route answers: the hits, and why they may be partial. */
export interface DaemonSearchResult<THit> {
  hits: readonly THit[];
  partialReason: string | null;
}

export interface DaemonSearchState<THit> {
  query: string;
  setQuery: (query: string) => void;
  hits: readonly THit[];
  /** Why the list is real but incomplete — the daemon's own sentence. */
  partialReason: string | null;
  loading: boolean;
  error: string | null;
  /** The query is too short to have been asked — no result, and no failure. */
  tooShort: boolean;
  /** Forget the query and its answer, for a surface that closes and reopens. */
  reset: () => void;
}

export type ChatSearchState = DaemonSearchState<ChatSearchHit>;

/**
 * Search ONE conversation, on the daemon.
 *
 * The search has to be the daemon's because the client holds at most
 * `HISTORY_PAGE` items — filtering those would answer only about the window
 * already on screen, which is the part of the conversation the user can already
 * read. That is the whole reason this route exists, and it is why a hit can name
 * a `seq` the caller does not hold: jumping to one is `loadAround`'s job.
 *
 * A reply is dropped when a newer query has been issued since it went out
 * (`generation`), because nothing orders two in-flight fetches — a slow answer
 * to `bloom` landing after a fast one to `bloom filter` would put the wrong list
 * under the field the user is still typing in.
 */
export function useChatSearch(
  runId: string | null,
  chatApi: ChatsApi | null,
): ChatSearchState {
  const ask = useMemo(
    () =>
      runId === null || chatApi === null
        ? null
        : (term: string) => chatApi.searchChat({ runId, query: term }),
    [runId, chatApi],
  );
  return useDaemonSearch(ask, 'The search failed.');
}

/**
 * The typing loop every daemon-backed search field shares: a debounced ask,
 * a too-short query left unasked, and the reply to a superseded query dropped.
 * `ask` is null while there is nothing to search, which clears the answer;
 * pass a stable function (memoize it), since a new one asks again.
 */
export function useDaemonSearch<THit>(
  ask: ((term: string) => Promise<DaemonSearchResult<THit>>) | null,
  failure: string,
): DaemonSearchState<THit> {
  const [query, setQuery] = useState('');
  const [hits, setHits] = useState<readonly THit[]>([]);
  const [partialReason, setPartialReason] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const generation = useRef(0);

  const reset = useLatestCallback((): void => {
    // The generation moves so an answer already in flight cannot land into the
    // cleared state and refill the list.
    generation.current += 1;
    setQuery('');
    setHits([]);
    setPartialReason(null);
    setLoading(false);
    setError(null);
  }, []);

  const term = query.trim();
  const tooShort = term.length > 0 && term.length < MIN_QUERY_CHARS;

  useEffect(() => {
    if (ask === null || term.length < MIN_QUERY_CHARS) {
      // Not an error state: an empty field is the surface's resting state, and a
      // one-character one is a query still being typed. The generation moves
      // here too — deleting back to one character while a longer query is in
      // flight would otherwise let that answer land under a field that no longer
      // asks it.
      generation.current += 1;
      setHits([]);
      setPartialReason(null);
      setLoading(false);
      setError(null);
      return;
    }
    const asked = ++generation.current;
    setLoading(true);
    const timer = setTimeout(() => {
      void ask(term)
        .then((result) => {
          if (generation.current !== asked) {
            return;
          }
          setHits(result.hits);
          setPartialReason(result.partialReason);
          setError(null);
        })
        .catch((err: unknown) => {
          if (generation.current !== asked) {
            return;
          }
          setHits([]);
          setPartialReason(null);
          setError(daemonErrorDetail(err) ?? failure);
        })
        .finally(() => {
          if (generation.current === asked) {
            setLoading(false);
          }
        });
    }, SEARCH_DEBOUNCE_MS);
    return () => clearTimeout(timer);
  }, [ask, failure, term]);

  return {
    query,
    setQuery,
    hits,
    partialReason,
    loading,
    error,
    tooShort,
    reset,
  };
}
