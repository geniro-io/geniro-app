// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type {
  ChatsApi,
  ChatTimelineDto,
  ChatTimelineMarker,
} from '../autogenerated';
import { type ChatTimelineState, useChatTimeline } from './use-chat-timeline';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const marker = (seq: number, preview: string): ChatTimelineMarker =>
  ({
    seq,
    createdAt: '2026-09-07T12:00:00.000Z',
    preview,
    segment: {
      aiMessages: 1,
      elapsedMs: 1000,
      totals: {
        turns: 1,
        costedTurns: 1,
        costUsd: 0.1,
        inputTokens: 10,
        outputTokens: 5,
        cacheReadTokens: null,
        cacheCreationTokens: null,
        thinkingTokens: null,
        workedMs: 900,
      },
    },
  }) as ChatTimelineMarker;

/** A whole reply, so a mock can never be missing a field the hook reads. */
const rail = (...markers: ChatTimelineMarker[]): ChatTimelineDto => ({
  markers,
  partialReason: null,
});

interface Props {
  runId: string | null;
  settledTurns: number;
  latestUserSeq: number;
}

let root: Root | null = null;
let container: HTMLDivElement | null = null;
let seen: ChatTimelineState | null = null;

const previews = (): string[] => (seen?.markers ?? []).map((m) => m.preview);

function mount(
  readChatTimeline: ReturnType<typeof vi.fn>,
  initial: Props,
): (next: Props) => void {
  const api = { readChatTimeline } as unknown as ChatsApi;
  function Probe({ runId, settledTurns, latestUserSeq }: Props): null {
    seen = useChatTimeline(api, runId, settledTurns, latestUserSeq);
    return null;
  }
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(<Probe {...initial} />);
  });
  return (next: Props) => {
    act(() => {
      root!.render(<Probe {...next} />);
    });
  };
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  seen = null;
});

const BASE: Props = { runId: 'r1', settledTurns: 0, latestUserSeq: 0 };

describe('useChatTimeline', () => {
  it('reads the rail for the open run', async () => {
    const read = vi.fn(() => Promise.resolve(rail(marker(1, 'first ask'))));
    mount(read, BASE);
    await act(async () => {});

    expect(read).toHaveBeenCalledWith({ runId: 'r1' });
    expect(previews()).toEqual(['first ask']);
  });

  it('re-reads when a turn SETTLES, because the segment figures moved', async () => {
    const read = vi.fn(() => Promise.resolve(rail()));
    const rerender = mount(read, BASE);
    await act(async () => {});
    expect(read).toHaveBeenCalledTimes(1);

    rerender({ ...BASE, settledTurns: 1 });
    await act(async () => {});

    expect(read).toHaveBeenCalledTimes(2);
  });

  it('re-reads when a message is SENT, so the rail is not a turn behind', async () => {
    // The trigger that `settledTurns` cannot cover: a marker appears the moment
    // the user sends, and waiting for the turn to end would leave the message
    // currently being answered off the rail for the whole of it — which is
    // exactly when someone looks at it.
    const read = vi.fn(() => Promise.resolve(rail()));
    const rerender = mount(read, BASE);
    await act(async () => {});
    expect(read).toHaveBeenCalledTimes(1);

    rerender({ ...BASE, latestUserSeq: 7 });
    await act(async () => {});

    expect(read).toHaveBeenCalledTimes(2);
  });

  it('does NOT re-read on a render that changed neither trigger', async () => {
    // Older history paging in moves neither, so scrolling up costs no fetch.
    const read = vi.fn(() => Promise.resolve(rail()));
    const rerender = mount(read, BASE);
    await act(async () => {});

    rerender({ ...BASE });
    await act(async () => {});

    expect(read).toHaveBeenCalledTimes(1);
  });

  it("carries the daemon's own partial sentence through", async () => {
    // A capped rail has to be able to SAY so — one wording, the daemon's, so a
    // second copy here cannot drift from it.
    const read = vi.fn(() =>
      Promise.resolve({
        markers: [marker(1, 'an ask')],
        partialReason: 'showing the newest 200 messages',
      }),
    );
    mount(read, BASE);
    await act(async () => {});

    expect(seen?.partialReason).toBe('showing the newest 200 messages');
  });

  it('drops the rail on a failed read rather than surfacing an error', async () => {
    // A rail that could not be read is a chat without a rail — the transcript
    // under it is what the user opened the thread for and is unaffected.
    const read = vi
      .fn()
      .mockResolvedValueOnce(rail(marker(1, 'first ask')))
      .mockRejectedValueOnce(new Error('daemon GET failed'));
    const rerender = mount(read, BASE);
    await act(async () => {});
    expect(seen?.markers).toHaveLength(1);

    rerender({ ...BASE, settledTurns: 1 });
    await act(async () => {});

    expect(seen?.markers).toEqual([]);
    // The partial sentence goes with them: a failed read makes no claim about
    // how much of the conversation it was showing.
    expect(seen?.partialReason).toBeNull();
  });

  it('never draws the previous run rail under the new run name', async () => {
    // The effect runs after the render that switched threads, so without the
    // run stamp the new thread shows the old conversation's markers for a
    // frame — and a settled thread, whose rail never moves again, keeps them.
    let release: ((value: ChatTimelineDto) => void) | null = null;
    const read = vi
      .fn()
      .mockResolvedValueOnce(rail(marker(1, 'run one ask')))
      .mockImplementationOnce(
        () =>
          new Promise<ChatTimelineDto>((resolve) => {
            release = resolve;
          }),
      );
    const rerender = mount(read, BASE);
    await act(async () => {});
    expect(previews()).toEqual(['run one ask']);

    rerender({ ...BASE, runId: 'r2' });

    expect(previews()).toEqual([]);

    await act(async () => {
      release?.(rail(marker(4, 'run two ask')));
    });
    expect(previews()).toEqual(['run two ask']);
  });

  it('drops a read whose effect was already cleaned up, so a slow one cannot win', async () => {
    // The run stamp cannot cover this: a `settledTurns` bump leaves runId
    // unchanged, so an earlier read resolving LAST would overwrite the fresh
    // markers with stale ones. Deleting the cancelled flag as "redundant with
    // the run stamp" is what this goes red on.
    let releaseFirst: ((v: ChatTimelineDto) => void) | null = null;
    let releaseSecond: ((v: ChatTimelineDto) => void) | null = null;
    const read = vi
      .fn()
      .mockImplementationOnce(
        () =>
          new Promise<ChatTimelineDto>((resolve) => {
            releaseFirst = resolve;
          }),
      )
      .mockImplementationOnce(
        () =>
          new Promise<ChatTimelineDto>((resolve) => {
            releaseSecond = resolve;
          }),
      );
    const rerender = mount(read, BASE);

    // A second read supersedes the first while it is still in flight.
    rerender({ ...BASE, settledTurns: 1 });
    await act(async () => {
      releaseSecond?.(rail(marker(9, 'the current rail')));
    });
    expect(previews()).toEqual(['the current rail']);

    // The superseded read lands LAST and must change nothing.
    await act(async () => {
      releaseFirst?.(rail(marker(1, 'the stale rail')));
    });

    expect(previews()).toEqual(['the current rail']);
  });

  it('holds no rail for a run that is not open', async () => {
    const read = vi.fn(() => Promise.resolve(rail()));
    mount(read, { ...BASE, runId: null });
    await act(async () => {});

    expect(read).not.toHaveBeenCalled();
    expect(previews()).toEqual([]);
  });
});
