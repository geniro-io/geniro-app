import { useEffect, useState } from 'react';

import type {
  ChatsApi,
  ChatTimelineEvent,
  ChatTimelineMarker,
} from '../autogenerated';

export interface ChatTimelineState {
  /** Which chat this was read from — see the guard below for why. */
  runId: string | null;
  /** `idle` while nothing asked for it, `error` when the read failed. */
  status: 'idle' | 'loading' | 'ready' | 'error';
  markers: readonly ChatTimelineMarker[];
  /** Why the rail is real but incomplete — the daemon's own sentence. */
  partialReason: string | null;
  /** What happened on the thread, newest first. */
  events: readonly ChatTimelineEvent[];
  eventsPartialReason: string | null;
}

const NO_MARKERS: readonly ChatTimelineMarker[] = [];
const NO_EVENTS: readonly ChatTimelineEvent[] = [];

function nothing(
  runId: string | null,
  status: ChatTimelineState['status'],
): ChatTimelineState {
  return {
    runId,
    status,
    markers: NO_MARKERS,
    partialReason: null,
    events: NO_EVENTS,
    eventsPartialReason: null,
  };
}

/**
 * The open thread's user messages and what happened on it, read from the
 * DAEMON: the transcript holds a window, and a timeline folded from it would
 * describe the window and present it as the thread.
 *
 * Read only while `enabled` — while the Progress window shows its Timeline —
 * since each read walks a dozen kinds of row. While it shows, it follows the
 * thread: `settledTurns` (a turn ending), `latestUserSeq` (a message sent),
 * `latestAgentSeq` (the agent writing, which keeps the open stretch live) and
 * `latestEventSeq` (a row the timeline draws an event from). All are monotonic
 * within a thread and none moves when older history pages in.
 */
export function useChatTimeline(
  api: Pick<ChatsApi, 'readChatTimeline'> | null,
  runId: string | null,
  enabled: boolean,
  settledTurns: number,
  latestUserSeq: number,
  latestAgentSeq: number,
  latestEventSeq: number,
): ChatTimelineState {
  const [state, setState] = useState<ChatTimelineState>(() =>
    nothing(runId, 'idle'),
  );

  useEffect(() => {
    if (api === null || runId === null || !enabled) {
      return;
    }
    let cancelled = false;
    setState((was) =>
      was.runId === runId && was.status === 'ready'
        ? was
        : nothing(runId, 'loading'),
    );
    void api
      .readChatTimeline({ runId })
      .then((answer) => {
        if (!cancelled) {
          setState({
            runId,
            status: 'ready',
            markers: answer.markers,
            partialReason: answer.partialReason,
            events: answer.events,
            eventsPartialReason: answer.eventsPartialReason,
          });
        }
      })
      .catch(() => {
        if (!cancelled) {
          setState((was) =>
            was.runId === runId && was.status === 'ready'
              ? was
              : nothing(runId, 'error'),
          );
        }
      });
    return () => {
      cancelled = true;
    };
  }, [
    api,
    runId,
    enabled,
    settledTurns,
    latestUserSeq,
    latestAgentSeq,
    latestEventSeq,
  ]);

  // A thread switch renders once before the effect can replace the reading, so
  // without this guard the new thread would draw the previous one's timeline.
  return state.runId === runId ? state : nothing(runId, 'idle');
}
