import { useEffect, useState } from 'react';

import type { ChatsApi, ChatTimelineMarker } from '../autogenerated';

export interface ChatTimelineState {
  /** Which chat these markers were read from — see the guard below for why. */
  runId: string | null;
  markers: readonly ChatTimelineMarker[];
  /** Why the rail is real but incomplete — the daemon's own sentence. */
  partialReason: string | null;
}

const NO_MARKERS: readonly ChatTimelineMarker[] = [];

/** No rail, and no claim about why — the resting state and the failure state. */
const NOTHING: ChatTimelineState = {
  runId: null,
  markers: NO_MARKERS,
  partialReason: null,
};

/**
 * The open thread's user messages, as a rail to navigate by.
 *
 * Read from the DAEMON rather than folded from the transcript this component
 * already holds, for `useChatTotals`' reason and one sharper: a long thread
 * opens on its newest `HISTORY_PAGE` items, so a local fold would draw a rail
 * of the last few exchanges and present it as the whole conversation — shorter,
 * cheaper, and indistinguishable from a genuinely short thread.
 *
 * TWO refresh triggers, because two different things move the rail and neither
 * covers the other. `settledTurns` covers a turn ENDING, which is when a
 * segment's message count, elapsed time and spend stop changing. `latestUserSeq`
 * covers a message being SENT, which adds a marker immediately — without it the
 * message currently being answered is missing from the rail for the whole of
 * the turn, which is exactly when someone looks. Both are monotonic within a
 * thread and neither moves when older history pages in, so scrolling up costs
 * no fetch.
 */
export function useChatTimeline(
  api: Pick<ChatsApi, 'readChatTimeline'> | null,
  runId: string | null,
  settledTurns: number,
  latestUserSeq: number,
): ChatTimelineState {
  const [state, setState] = useState<ChatTimelineState>(() => ({
    ...NOTHING,
    runId,
  }));

  useEffect(() => {
    if (api === null || runId === null) {
      setState({ ...NOTHING, runId });
      return;
    }
    let cancelled = false;
    void api
      .readChatTimeline({ runId })
      .then((answer) => {
        if (!cancelled) {
          setState({
            runId,
            markers: answer.markers,
            partialReason: answer.partialReason,
          });
        }
      })
      // A rail that could not be read is a chat without a rail, never an error
      // banner over a working conversation — the transcript below it is what
      // the user opened the thread for, and it is unaffected. Same reading
      // `useChatTotals` takes for the header's spend.
      .catch(() => {
        if (!cancelled) {
          setState({ ...NOTHING, runId });
        }
      });
    return () => {
      cancelled = true;
    };
  }, [api, runId, settledTurns, latestUserSeq]);

  // The markers belong to the run they were read from. A thread switch renders
  // once before the effect above can replace them, so without this guard the
  // new thread's rail draws the previous conversation's messages — under the
  // new thread's name, which is the one place it cannot be recognised as stale.
  return state.runId === runId ? state : { ...NOTHING, runId };
}
