// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, type Mock, vi } from 'vitest';

import type { ChatsApi } from '../autogenerated';
import { useChatTotals } from './use-chat-totals';

/** The one field the header reads, rendered so a test can read it back. */
function Probe({
  api,
  runId,
  settledTurns,
}: {
  api: Parameters<typeof useChatTotals>[0];
  runId: string | null;
  settledTurns: number;
}): React.JSX.Element {
  const { costUsd, costedTurns } = useChatTotals(api, runId, settledTurns);
  return (
    <>
      <span data-slot="spend">{costUsd === null ? 'none' : costUsd}</span>
      <span data-slot="costed">
        {costedTurns === null ? 'unknown' : costedTurns}
      </span>
    </>
  );
}

let root: Root | null = null;
let host: HTMLDivElement | null = null;

function mount(props: Parameters<typeof Probe>[0]): HTMLElement {
  host = document.createElement('div');
  document.body.appendChild(host);
  root = createRoot(host);
  act(() => {
    root!.render(<Probe {...props} />);
  });
  return host;
}

function rerender(props: Parameters<typeof Probe>[0]): void {
  act(() => {
    root!.render(<Probe {...props} />);
  });
}

/** Let the fetch promise and the state it sets flush. */
async function settle(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
  });
}

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
});

/**
 * A client answering with one figure. Typed off the GENERATED method rather
 * than as a loose mock, so a spec cannot go on passing a shape the real client
 * stopped accepting.
 */
function apiReturning(
  costUsd: number | null,
  costedTurns = costUsd === null ? 0 : 1,
): {
  readChatTotals: Mock<ChatsApi['readChatTotals']>;
} {
  return {
    readChatTotals: vi.fn<ChatsApi['readChatTotals']>().mockResolvedValue({
      totals: { costUsd, costedTurns },
    } as Awaited<ReturnType<ChatsApi['readChatTotals']>>),
  };
}

describe('useChatTotals', () => {
  it('asks once per thread and reports what the daemon summed', async () => {
    const api = apiReturning(1.25);

    const el = mount({ api, runId: 'run-1', settledTurns: 0 });
    await settle();

    expect(api.readChatTotals).toHaveBeenCalledTimes(1);
    expect(api.readChatTotals).toHaveBeenCalledWith({ runId: 'run-1' });
    expect(el.querySelector('[data-slot="spend"]')?.textContent).toBe('1.25');
  });

  it('does NOT re-ask on a re-render that changed nothing', async () => {
    // The header re-renders once a second while a turn runs (the worked clock
    // ticks), and the total cannot move between two turns — so a dependency
    // that changed per render would be a request per second per open thread.
    const api = apiReturning(1.25);
    mount({ api, runId: 'run-1', settledTurns: 2 });
    await settle();

    rerender({ api, runId: 'run-1', settledTurns: 2 });
    await settle();

    expect(api.readChatTotals).toHaveBeenCalledTimes(1);
  });

  it('re-asks when a turn SETTLES, which is the only thing that moves the total', async () => {
    const api = apiReturning(1.25);
    mount({ api, runId: 'run-1', settledTurns: 2 });
    await settle();

    rerender({ api, runId: 'run-1', settledTurns: 3 });
    await settle();

    expect(api.readChatTotals).toHaveBeenCalledTimes(2);
  });

  it('shows no spend rather than the previous thread’s while switching', async () => {
    // The figure is per-thread, and a stale one under a new title is worse than
    // none: it is wrong and it looks authoritative.
    const api = apiReturning(1.25);
    const el = mount({ api, runId: 'run-1', settledTurns: 0 });
    await settle();

    rerender({ api, runId: null, settledTurns: 0 });

    expect(el.querySelector('[data-slot="spend"]')?.textContent).toBe('none');
  });

  it('answers a failed read with no spend, never an error', async () => {
    // Nothing here is what the user opened the thread to do — a readout that
    // could not be fetched must not take the conversation down with it.
    const api = {
      readChatTotals: vi
        .fn<ChatsApi['readChatTotals']>()
        .mockRejectedValue(new Error('daemon gone')),
    };

    const el = mount({ api, runId: 'run-1', settledTurns: 0 });
    await settle();

    expect(el.querySelector('[data-slot="spend"]')?.textContent).toBe('none');
  });

  it('drops the PRICED-turn count too when a later read fails', async () => {
    // Otherwise a thread that was once summed keeps its old count beside a
    // cleared cost — which is exactly the shape the header reads as "every
    // turn was summed and none was priced" and marks with a dash. A read that
    // failed knows nothing about this thread's turns, so it must say so.
    const el = mount({
      api: apiReturning(1.25, 4),
      runId: 'run-1',
      settledTurns: 0,
    });
    await settle();
    expect(el.querySelector('[data-slot="costed"]')?.textContent).toBe('4');

    rerender({
      api: {
        readChatTotals: vi
          .fn<ChatsApi['readChatTotals']>()
          .mockRejectedValue(new Error('daemon gone')),
      },
      runId: 'run-1',
      settledTurns: 0,
    });
    await settle();

    expect(el.querySelector('[data-slot="costed"]')?.textContent).toBe(
      'unknown',
    );
  });

  it('reports a thread whose turns carried no price as ZERO, not unknown', async () => {
    // The reading behind the header's dash. cursor-agent prices nothing —
    // probed on 2026.08.11-e8db854, a completed turn sends no `usage_update`
    // at all — so its threads come back summed with a null cost, which is a
    // different fact from a total nobody has fetched.
    const api = apiReturning(null, 0);

    const el = mount({ api, runId: 'run-1', settledTurns: 0 });
    await settle();

    expect(el.querySelector('[data-slot="spend"]')?.textContent).toBe('none');
    expect(el.querySelector('[data-slot="costed"]')?.textContent).toBe('0');
  });
});
