import { useCallback, useEffect, useState } from 'react';

import type { ChatsApi } from '../autogenerated';
import type { DaemonClient } from '../daemon-client';

/** Every figure this hook reports, absent. */
const NO_TOTALS = {
  costUsd: null,
  costedTurns: null,
  turns: null,
  workedMs: null,
} as const;

interface ChatTotalsState {
  /** Which chat these figures were read from — see the state below for why. */
  runId: string | null;
  costUsd: number | null;
  costedTurns: number | null;
  turns: number | null;
  workedMs: number | null;
}

interface SpendMark {
  runId: string | null;
  at: number;
}

/**
 * What the open thread has spent, for the header.
 *
 * Its own route (`GET /v1/chats/:runId/totals`) and not the metrics one the
 * context readout uses: that answer includes a breakdown ASKED of the live CLI,
 * measured at 1.2–3.3s, which is why the readout is opened rather than polled.
 * The header carries its figure on every thread the user opens, so it must not
 * cost a CLI round trip to switch chats.
 *
 * Summed on the DAEMON rather than folded from the transcript this component
 * already holds. The renderer's own copy is complete TODAY — the history fetch
 * takes no cursor — but history is paged behind an `afterSeq` cursor by design,
 * and the day anything starts using it a local fold would total part of a long
 * conversation and say so with a smaller number, which looks exactly like a
 * cheaper thread rather than like a bug.
 *
 * `settledTurns` is the refresh trigger, and it is a COUNT rather than a
 * timestamp or a boolean: the total only moves when a turn ends, so counting
 * the thread's finished turns re-asks exactly then — once per turn, never on a
 * stream of deltas, and correctly for a turn that ended while this component
 * was mounted on another thread.
 *
 * `client` is the SECOND trigger, and it exists because that reasoning holds
 * for every CLI but one. cursor reports no cost on its wire and records none on
 * this machine, so the daemon FETCHES it from Cursor on a cadence of its own —
 * one this hook cannot see and that has no reason to line up with a turn
 * ending. Whatever a poll found therefore reached the screen only when the next
 * turn settled, or when the chat was reopened: REPORTED as "i still dont see
 * any costs for cursor chat", against a running conversation Cursor had already
 * billed $4.89 for. The daemon now announces a run whose fetched spend CHANGED
 * (`RunStatusEvent.spendUpdatedAt`), and this re-asks on it — for the figure
 * itself, which stays the totals route's to state; the announce carries none.
 * Optional, so the harness and the specs that predate it pass nothing.
 */
export function useChatTotals(
  api: Pick<ChatsApi, 'readChatTotals'> | null,
  runId: string | null,
  settledTurns: number,
  client: Pick<DaemonClient, 'onRunStatus'> | null = null,
): {
  costUsd: number | null;
  /**
   * How many of {@link turns} carried a PRICE — the daemon's own count, and the
   * only thing that can tell an unpriced thread from an unanswered read.
   *
   * A null spend has two causes that look identical on screen and are not:
   * nothing has been summed yet, or every turn was summed and none of them was
   * priced. cursor-agent is the second — probed on 2026.08.11-e8db854, a
   * completed turn sends no `usage_update` at all, so no cost ever reaches the
   * ledger (confirmed against a real install: 1,642 claude turns all priced,
   * 28 cursor turns with every usage column null). REPORTED as "I dont see how
   * much i spend for thread - i should see it", about a header that was
   * correctly printing nothing.
   */
  costedTurns: number | null;
  turns: number | null;
  workedMs: number | null;
} {
  /**
   * The four figures, STAMPED with the thread they were read from.
   *
   * One piece of state rather than four, and the stamp is what makes them
   * answerable: figures held in separate hooks can only be discarded one at a
   * time, so nothing could say "these four belong to that conversation". The
   * fetch effect runs AFTER the render that switched threads, so without the
   * stamp the new thread's header draws the previous one's spend for a frame —
   * and a settled thread, whose figures never move again, keeps it. Mirrors
   * `context-meter.tsx`'s own runId stamp, down to the render-time guard below.
   *
   * `turns` and `workedMs` are the DAEMON's counts, over every `turn_complete`
   * row the run has ever written. The header used to fold both out of the
   * transcript this component holds, which was complete until the history
   * became a WINDOW: a long thread now opens on its newest 1,000 items, so that
   * fold would report a conversation's last few turns as the whole of it — a
   * smaller number that reads as a shorter thread rather than as a partial one.
   */
  const [state, setState] = useState<ChatTotalsState>(() => ({
    runId,
    ...NO_TOTALS,
  }));
  /**
   * The newest `spendUpdatedAt` this thread has been told about — a trigger,
   * never a figure. It is the announce's own stamp rather than a counter, so
   * two announces about one poll (which cannot happen today, and would the
   * moment a second producer appears) cost one fetch.
   *
   * Stamped with its run for a reason the figures do not share: the mark only
   * ever moves FORWARD, so one left behind by a busy thread would swallow the
   * next thread's announce outright — its poll stamp being older — and that
   * thread would then show a spend that never updated until it was reopened.
   */
  const [spendMark, setSpendMark] = useState<SpendMark>(() => ({
    runId,
    at: 0,
  }));
  useEffect(() => {
    if (client === null || runId === null) {
      return;
    }
    return client.onRunStatus((event) => {
      const at = event.spendUpdatedAt;
      if (event.runId !== runId || at === undefined) {
        return;
      }
      // Never BACKWARDS within a thread: announces are not ordered against each
      // other, and a late one carrying an older stamp says nothing new. Across
      // threads there is no ordering to keep — a different run's mark is not a
      // later reading of this one.
      setSpendMark((known) =>
        known.runId !== runId || at > known.at ? { runId, at } : known,
      );
    });
  }, [client, runId]);

  /** Drop every figure at once — see the catch below for why all four. */
  const forget = useCallback((): void => {
    setState({ runId, ...NO_TOTALS });
  }, [runId]);

  useEffect(() => {
    if (api === null || runId === null) {
      forget();
      return;
    }
    let cancelled = false;
    void api
      .readChatTotals({ runId })
      .then((answer) => {
        if (!cancelled) {
          setState({
            runId,
            costUsd: answer.totals.costUsd,
            costedTurns: answer.totals.costedTurns,
            turns: answer.totals.turns,
            workedMs: answer.totals.workedMs,
          });
        }
      })
      // A spend the header cannot read is a header without a spend, never an
      // error banner over a working conversation: nothing here is what the user
      // opened the thread to do.
      //
      // EVERY figure is dropped, not just the spend, and that is what keeps the
      // "no turn was priced" reading honest: it is `costedTurns === 0` beside a
      // non-zero `turns`, so a failed read that left either of them standing
      // would state, about a thread it knows nothing of, that its turns carried
      // no price. Dropping them also hands the worked figure back to the
      // transcript fold `Chats` already falls back to.
      .catch(() => {
        if (!cancelled) {
          forget();
        }
      });
    return () => {
      cancelled = true;
    };
  }, [api, forget, runId, settledTurns, spendMark]);

  // The figures belong to the run they were read from. A thread switch renders
  // once before the effect above can replace them, so without this guard the
  // new thread's header states the previous conversation's spend — under the
  // new thread's name, which is the one place it cannot be recognised as stale.
  const current = state.runId === runId ? state : { runId, ...NO_TOTALS };
  return {
    costUsd: current.costUsd,
    costedTurns: current.costedTurns,
    turns: current.turns,
    workedMs: current.workedMs,
  };
}
