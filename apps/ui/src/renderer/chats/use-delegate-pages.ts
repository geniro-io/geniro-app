import {
  createContext,
  type RefObject,
  useMemo,
  useRef,
  useState,
} from 'react';

import type { ChatsApi, ItemDto as ChatItem } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import type { CallConversationState } from './call-conversation';
import { mergeAnchorRows } from './history-anchors';

/** Where reading one sub-agent's own rows stands, keyed by its launching call. */
export interface DelegateConversationLoader {
  /** The delegate's newest page, once — or, with `older`, the page before the oldest held. */
  load(delegateId: string, older: boolean): void;
  /** Ask again for a delegate whose read failed. */
  retry(delegateId: string): void;
  /** Null before the delegate was first asked for. */
  stateOf(delegateId: string): CallConversationState | null;
}

/** Null where the transcript holds every row itself. */
export const DelegateConversationContext =
  createContext<DelegateConversationLoader | null>(null);

/**
 * Reads one sub-agent's rows page by page into the transcript's rows, the same
 * way {@link useCallPages} reads a call card's conversation: the page's rows and
 * anchors are merged into what the transcript folds, so the card's steps and its
 * summary are built by the same fold as the rows already on screen.
 */
export function useDelegatePages({
  runIdRef,
  api,
  pageSizeRef,
  commitRows,
}: {
  runIdRef: RefObject<string | null>;
  api: Pick<ChatsApi, 'listRunItems'>;
  /** Read at request time; a page is judged full by the size it was asked for. */
  pageSizeRef: RefObject<number>;
  commitRows: (update: (prev: ChatItem[]) => ChatItem[]) => void;
}): {
  delegateConversations: DelegateConversationLoader;
  /** Forget what was read, at every place the rows go — see `useCallPages`. */
  forgetDelegatePages: () => void;
} {
  const [delegatePages, setDelegatePages] = useState<
    ReadonlyMap<string, CallConversationState>
  >(() => new Map());
  const delegatePagesRef = useRef(delegatePages);
  const writeDelegatePages = useLatestCallback(
    (
      update: (
        prev: ReadonlyMap<string, CallConversationState>,
      ) => ReadonlyMap<string, CallConversationState>,
    ): void => {
      const next = update(delegatePagesRef.current);
      delegatePagesRef.current = next;
      setDelegatePages(next);
    },
    [],
  );
  const generationRef = useRef(0);
  const forgetDelegatePages = useLatestCallback((): void => {
    generationRef.current += 1;
    writeDelegatePages(() => new Map());
  }, [writeDelegatePages]);

  const readsRef = useRef(new Map<string, Promise<void>>());
  const loadDelegate = useLatestCallback(
    (delegateId: string, older: boolean): Promise<void> => {
      const runId = runIdRef.current;
      const held = delegatePagesRef.current.get(delegateId);
      if (held?.loading === true) {
        return readsRef.current.get(delegateId) ?? Promise.resolve();
      }
      if (
        runId === null ||
        (older ? held?.hasOlder !== true : held !== undefined)
      ) {
        return Promise.resolve();
      }
      const beforeSeq = older ? held?.oldestSeq : null;
      const generation = generationRef.current;
      const current = (): boolean =>
        runIdRef.current === runId && generationRef.current === generation;
      const settle = (next: CallConversationState): void => {
        writeDelegatePages((prev) => new Map(prev).set(delegateId, next));
      };
      settle({
        loading: true,
        failed: false,
        hasOlder: held?.hasOlder ?? false,
        oldestSeq: held?.oldestSeq ?? null,
      });
      const pageSize = pageSizeRef.current;
      const read = api
        .listRunItems({
          runId,
          limit: pageSize,
          delegate: delegateId,
          ...(beforeSeq === null || beforeSeq === undefined
            ? {}
            : { beforeSeq }),
        })
        .then(({ items: page, anchors: pageAnchors }) => {
          if (!current()) {
            return;
          }
          commitRows((prev) =>
            mergeAnchorRows(prev, [...page, ...pageAnchors]),
          );
          settle({
            loading: false,
            failed: false,
            hasOlder: page.length === pageSize,
            oldestSeq: page[0]?.seq ?? held?.oldestSeq ?? null,
          });
        })
        .catch(() => {
          if (!current()) {
            return;
          }
          settle(
            older && held !== undefined
              ? held
              : {
                  loading: false,
                  failed: true,
                  hasOlder: false,
                  oldestSeq: null,
                },
          );
        })
        .finally(() => {
          if (readsRef.current.get(delegateId) === read) {
            readsRef.current.delete(delegateId);
          }
        });
      readsRef.current.set(delegateId, read);
      return read;
    },
    [api, commitRows, pageSizeRef, runIdRef, writeDelegatePages],
  );

  const load = useLatestCallback(
    (delegateId: string, older: boolean): void => {
      void loadDelegate(delegateId, older);
    },
    [loadDelegate],
  );
  const retry = useLatestCallback(
    (delegateId: string): void => {
      writeDelegatePages((prev) => {
        const next = new Map(prev);
        next.delete(delegateId);
        return next;
      });
      void loadDelegate(delegateId, false);
    },
    [loadDelegate, writeDelegatePages],
  );
  const stateOf = useLatestCallback(
    (delegateId: string): CallConversationState | null =>
      delegatePagesRef.current.get(delegateId) ?? null,
    [],
  );
  const delegateConversations = useMemo<DelegateConversationLoader>(
    () => ({ load, retry, stateOf }),
    [load, retry, stateOf, delegatePages],
  );

  return { delegateConversations, forgetDelegatePages };
}
