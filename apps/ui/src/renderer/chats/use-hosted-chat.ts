import { EMPTY_LIVE_TEXT, useRunStream } from './use-run-stream';

/**
 * How much of the conversation a hosted chat loads.
 *
 * Far below the chat screen's own page: these are a dock a few centimetres
 * tall and a popup, used to ask for something and watch it land, and a
 * long-running conversation should not pay a thousand-row fetch to show the
 * last exchange.
 */
export const HOSTED_CHAT_PAGE = 120;

/**
 * What one run_status announce sets on a hosted chat's copy of the run row: the
 * fields the header, the context ring and the delegate blocks read, and only
 * those the announce carries. The fields the chat screen's `patchRow` sets the
 * same way are `runStatusRowFields`; the rest here are this hook's own readings
 * of the shell and sub-agent counts and of the context, which the chat screen
 * applies through handlers of its own (use-chat-run.ts).
 */
function runRowPatch(event: RunStatusEvent): Partial<RunDto> {
  const patch: Partial<RunDto> = runStatusRowFields(event);
  if (event.shellsOpen !== undefined) {
    patch.shellsOpen = event.shellsOpen;
  }
  if (event.subagentsOut !== undefined) {
    patch.subagentsOut = event.subagentsOut;
  }
  // A reported 0 is not a measurement, so only a positive reading is kept.
  if (typeof event.contextTokens === 'number' && event.contextTokens > 0) {
    patch.contextTokens = event.contextTokens;
  }
  if (
    typeof event.contextWindowTokens === 'number' &&
    event.contextWindowTokens > 0
  ) {
    patch.contextWindowTokens = event.contextWindowTokens;
  }
  return patch;
}

/**
 * Whether a run status means a turn is IN FLIGHT.
 *
 * `pending` is not one, and reading it as one is a mistake with teeth: a chat
 * is created `pending` and stays there until its first turn starts, so treating
 * it as working disables the composer on a conversation that has never run —
 * the first message can then never be sent, and the surface offers Stop for a
 * turn that does not exist. Found by driving the real app.
 */
function isTurnRunning(status: RunDto['status']): boolean {
  return status === 'running';
}

export interface HostedChatState {
  /** The socket the conversation streams over — what run-state readouts listen on. */
  client: DaemonClient | null;
  /** Bumped on every socket reconnect — what run-state readouts re-read on. */
  reconnectNonce: number;
  /** For a turn started other than by `post` (an action press): raise or lower `working` as `post` does. */
  markWorking: (working: boolean) => void;
  /** The conversation, or null while it is being opened / the surface is shut. */
  run: RunDto | null;
  /**
   * The "not sent" rows that arrived LIVE — the turn just ended before taking
   * messages the user sent into it — oldest first. Never one replayed on open.
   */
  liveUnsent: readonly { rowId: string; deliveryIds: string[] }[];
  items: ChatItem[];
  /**
   * Rows outside {@link items} that rows inside it belong to — see
   * `chats/history-anchors.ts`. Structure for the fold, never rows to draw.
   */
  anchors: ChatItem[];
  /**
   * What the agent is writing right now, keyed as the chat screen keys it —
   * folded into the transcript by `withLiveText`, exactly as there.
   */
  liveText: ReadonlyMap<string, LiveState>;
  /** The conversation is being opened — its transcript has not arrived yet. */
  loading: boolean;
  /** Why the surface could not open or send, in the daemon's own words. */
  error: string | null;
  /** A turn is in flight (the builder's dock: the agent may be writing the file). */
  working: boolean;
  /**
   * The phrase the agent's current work is named by, as the chat screen names
   * it (`running Bash`). Null while the run is idle or the daemon named nothing.
   */
  activity: string | null;
  /**
   * Bumped once each time a turn of this chat SETTLES.
   *
   * The builder reloads the workflow off this rather than watching the file:
   * nothing in either app watches one, and a turn ending is the moment the
   * agent's edits are finished being made. A message queued behind a turn is
   * sent off it too.
   */
  settledTurns: number;
  /**
   * How the turn last counted in {@link settledTurns} ended — `cancelled` for a
   * Stop — or null before any has. Set in the same render as the count, so a
   * reader of one sees the other: the message queue drains on a settle unless it
   * was a Stop (`settleReleasesQueue`).
   */
  settledAs: RunDto['status'] | null;
  send: (
    text: string,
    images?: SendMessageDtoImagesInner[],
  ) => Promise<boolean>;
  /** {@link send} that throws the daemon's refusal instead of showing it. */
  post: (
    text: string,
    images?: SendMessageDtoImagesInner[],
    clientMessageId?: string,
  ) => Promise<void>;
  /**
   * Change an OPEN conversation's model, effort, approval and the rest — the
   * same route the chat screen's own chips patch through.
   *
   * The create settings cannot serve for this: they are read once, and a chip
   * moved afterwards would silently change nothing. `agentKind` is absent from
   * the patch because it is fixed for a run's life — changing the agent means
   * {@link HostedChatState.discard} and a fresh conversation.
   */
  patchSettings: (patch: UpdateChatSettingsDto) => Promise<boolean>;
  /**
   * File a context reading the run's own metrics route answered with, so the ring
   * agrees with the readout it was opened from until the next announce. A zero is
   * not a measurement, on the rule `runRowPatch` applies to announces.
   */
  rememberContext: (
    runId: string,
    tokens: number | null,
    windowTokens: number | null,
  ) => void;
  /** Answer an approval or question card this chat raised. */
  respond: (
    requestId: string,
    allow: boolean,
    answer?: string,
    optionId?: string,
  ) => void;
  /** Stop the turn in flight. */
  cancel: () => Promise<void>;
  /**
   * Throw the conversation away; the next open starts a fresh one. A no-op
   * for a surface that was given no way to (see {@link useHostedChat}).
   */
  discard: () => Promise<void>;
  /**
   * The requests whose verdict the daemon refused as expired: their turn ended
   * before an answer arrived, so nothing is waiting on them. The chat screen keeps
   * the same set (`deadRequestKeys` in `use-chat-run.ts`), and a hosted chat counts a
   * request the same way it does.
   */
  deadRequestIds: ReadonlySet<string>;
}

/** A hosted chat never pages: it is always at the tail of its own short window. */
const ALWAYS_AT_TAIL = (): boolean => true;

/**
 * ONE conversation shown outside the chat screen, on a surface of its own: the
 * workflow builder's chat dock (`useWorkflowChat`) and a thread's analysis
 * popup. The sidebar never lists either.
 *
 * The rows, the anchors, the live plane, the request expiry and the socket's
 * replay are the chat screen's own (`useRunStream`, shared with
 * `useChatRun`). What is left here is what a surface does with a run and
 * nothing else: open it, count its turn endings, re-read its row after a
 * reconnect, and send, patch, answer, cancel or discard it.
 *
 * It follows the run's room through the same `DaemonClient` the chat screen
 * uses, which is why that client tracks joined rooms as a SET: both surfaces
 * are live at once.
 */
export function useHostedChat({
  subject,
  apis,
  client,
  open,
  discard: discardConversation,
}: {
  /**
   * What the conversation is about — a workflow slug, a thread id — or null
   * while the surface is closed. A change opens that subject's conversation.
   */
  subject: string | null;
  apis: DaemonApis | null;
  client: DaemonClient | null;
  /**
   * Answers the subject's conversation as it reads NOW, creating it where the
   * surface does that. Read through a ref: a new function is not a reopen.
   */
  open: () => Promise<RunDto>;
  /** Throws the conversation away on the daemon; absent where nothing does. */
  discard?: () => Promise<void>;
}): HostedChatState {
  const [run, setRun] = useState<RunDto | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [working, setWorking] = useState(false);
  const [activity, setActivity] = useState<string | null>(null);
  const [settledTurns, setSettledTurns] = useState(0);
  const [liveUnsent, setLiveUnsent] = useState<HostedChatState['liveUnsent']>(
    [],
  );
  const [reconnectNonce, setReconnectNonce] = useState(0);
  const [settledAs, setSettledAs] = useState<RunDto['status'] | null>(null);
  /** Count one turn ending, and how it ended. */
  const settle = useCallback((status: RunDto['status']): void => {
    setWorking(false);
    setSettledAs(status);
    setSettledTurns((count) => count + 1);
  }, []);
  // Bumped by `discard`, which is the one thing that ends a conversation
  // without the surface closing — the subject has not changed, so nothing
  // else would re-run the open effect and the surface would sit empty until
  // the user closed and reopened it.
  const [reopenNonce, setReopenNonce] = useState(0);

  // Read through refs, so the effect stays keyed on the subject alone: the
  // builder's opener closes over its chips, and a reopen per keystroke in a
  // model picker would tear the room down and join it again.
  const openRef = useRef(open);
  openRef.current = open;
  const discardRef = useRef(discardConversation);
  discardRef.current = discardConversation;
  const subjectRef = useRef(subject);
  subjectRef.current = subject;
  const runIdRef = useRef<string | null>(null);
  runIdRef.current = run?.id ?? null;
  const pageSizeRef = useRef(HOSTED_CHAT_PAGE);
  const workingRef = useRef(working);
  workingRef.current = working;
  // The row patches of announces that landed while a reconnect re-read was in
  // flight, one list per read. An announce names only the fields it carries, and
  // some carry no `at` (a count, a task list), so the answer cannot be ordered
  // against one by its clock. Each announce is laid over the answer instead. A
  // Set, because two reconnects can overlap.
  const landedDuringReads = useRef(new Set<Partial<RunDto>[]>());
  /**
   * The terminal rows already counted as a turn ending. The socket and the
   * reconnect replay can both deliver one, and a second count would re-read
   * the builder's canvas for a turn that ended once.
   */
  const countedEndsRef = useRef(new Set<string>());
  /**
   * Whether the newest live row ended the turn — see `liveTurnEndedRef` in
   * use-chat-run.ts, which this mirrors: a settle arriving after the turn's
   * terminal row lowers a `working` that a stray `running` raised in between.
   */
  const liveTurnEndedRef = useRef(false);
  const countTurnEnd = useCallback(
    (row: ChatItem, status: RunDto['status']): void => {
      if (countedEndsRef.current.has(row.id)) {
        return;
      }
      countedEndsRef.current.add(row.id);
      settle(status);
    },
    [settle],
  );

  /** File a reading onto the run row, on the positive-only rule of `runRowPatch`. */
  const rememberContext = useCallback(
    (
      readRunId: string,
      tokens: number | null,
      windowTokens: number | null,
    ): void => {
      const patch: Partial<RunDto> = {};
      if (typeof tokens === 'number' && tokens > 0) {
        patch.contextTokens = tokens;
      }
      if (typeof windowTokens === 'number' && windowTokens > 0) {
        patch.contextWindowTokens = windowTokens;
      }
      if (Object.keys(patch).length === 0) {
        return;
      }
      setRun((current) => {
        if (current === null || current.id !== readRunId) {
          return current;
        }
        const unchanged =
          (patch.contextTokens === undefined ||
            patch.contextTokens === current.contextTokens) &&
          (patch.contextWindowTokens === undefined ||
            patch.contextWindowTokens === current.contextWindowTokens);
        return unchanged ? current : { ...current, ...patch };
      });
    },
    [],
  );

  /** Whether `id` is still the conversation on screen — a switch or a discard ends a read. */
  const isCurrent = useCallback(
    (id: string): boolean =>
      runIdRef.current === id && subjectRef.current !== null,
    [],
  );

  /**
   * What the socket missed while it was down, read as the run's own row.
   *
   * The rows were merged by the stream; this reads the daemon's current row
   * whole, because the socket missed whatever it carried, so every field the
   * surface reads is read again. A settle with no terminal row (a lease running
   * out, a failed send) was announced only on the socket, which is why the run
   * is re-read as well as the rows.
   */
  const reread = useCallback(
    (replayedRunId: string, ended: boolean): void => {
      if (apis === null || subjectRef.current === null) {
        return;
      }
      const landed: Partial<RunDto>[] = [];
      landedDuringReads.current.add(landed);
      void (async () => {
        try {
          const opened = await openRef.current().finally(() => {
            landedDuringReads.current.delete(landed);
          });
          if (!isCurrent(replayedRunId)) {
            return;
          }
          // The chat was discarded while the socket was down, and opening made a
          // new one: open it the ordinary way, joining its room.
          if (opened.id !== replayedRunId) {
            setReopenNonce((nonce) => nonce + 1);
            return;
          }
          const current = landed.reduce<RunDto>(
            (row, patch) => ({ ...row, ...patch }),
            opened,
          );
          setRun((previous) =>
            previous === null || previous.id !== opened.id ? previous : current,
          );
          if (isTurnRunning(current.status)) {
            setWorking(true);
          } else {
            // Nothing is current on a run that is not running, as on the chat
            // screen, where the activity clears when its run settles.
            setActivity(null);
            if (
              !ended &&
              workingRef.current &&
              isSettledRunStatus(current.status)
            ) {
              settle(current.status);
            }
          }
        } catch (err) {
          if (isCurrent(replayedRunId)) {
            setError(describeDaemonError(err));
          }
        }
      })();
    },
    [apis, isCurrent, settle],
  );

  const stream = useRunStream({
    client,
    chatApi: apis?.chats ?? null,
    runIdRef,
    pageSizeRef,
    atTail: ALWAYS_AT_TAIL,
    onRow: (item, live) => {
      // The replayed rows are history: only a row that arrived on the wire as it
      // happened may end a turn or clear the ring the surface's readout shows.
      if (!live) {
        return;
      }
      if (item.kind === 'system') {
        const deliveryIds = unsentMessageIds(item.payload);
        if (deliveryIds.length > 0) {
          setLiveUnsent((pending) =>
            pending.some((entry) => entry.rowId === item.id)
              ? pending
              : [...pending, { rowId: item.id, deliveryIds }],
          );
        }
      }
      if (discardsContextReading(item)) {
        setRun((current) =>
          current ? { ...current, contextTokens: null } : current,
        );
      }
      const settledStatus = settledRunStatus(item);
      if (settledStatus !== null) {
        liveTurnEndedRef.current = true;
        countTurnEnd(item, settledStatus);
      } else if (!isAfterTurnBookkeeping(item)) {
        liveTurnEndedRef.current = false;
      }
    },
    onReconnect: () => setReconnectNonce((n) => n + 1),
    onLiveEvent: (event) => {
      rememberContext(
        event.runId,
        event.contextTokens,
        event.contextWindowTokens,
      );
    },
    onMissed: (replayedRunId, rows) => {
      const last = replayTail(rows);
      const settledStatus = last === undefined ? null : settledRunStatus(last);
      const ended = settledStatus !== null;
      // What the replay ended on stands in for the live rows it replaced.
      if (last !== undefined && isCurrent(replayedRunId)) {
        liveTurnEndedRef.current = ended;
      }
      if (last !== undefined && settledStatus !== null) {
        countTurnEnd(last, settledStatus);
      }
      reread(replayedRunId, ended);
    },
    onReplayFailed: (replayedRunId, err) => {
      if (isCurrent(replayedRunId)) {
        setError(describeDaemonError(err));
      }
      // A failed replay must not skip the re-read: a turn that ended while the
      // socket was down would then stay `working` for good (the builder's
      // autosave paused with it).
      reread(replayedRunId, false);
    },
  });
  const {
    items,
    structure: anchors,
    liveText,
    setLiveText,
    ingest,
    lastSeqRef,
    reconnectAfterSeqRef,
    commitItems,
    commitAnchors,
    commitCallRows,
    forgetAnchorAsks,
  } = stream;

  // Everything this hook holds for one conversation, cleared. Used when no
  // subject is open and when the chat is discarded: both must leave none of the
  // previous run behind — the live plane and the replay cursors included, which
  // the chat screen clears on the same moments.
  const resetConversation = useCallback((): void => {
    setRun(null);
    commitItems([]);
    commitAnchors([]);
    commitCallRows([]);
    setLiveText(EMPTY_LIVE_TEXT);
    lastSeqRef.current = -1;
    reconnectAfterSeqRef.current = -1;
    setActivity(null);
    forgetAnchorAsks();
    liveTurnEndedRef.current = false;
    setWorking(false);
    setError(null);
  }, [
    commitItems,
    commitAnchors,
    forgetAnchorAsks,
    setLiveText,
    lastSeqRef,
    reconnectAfterSeqRef,
  ]);

  useEffect(() => {
    if (subject === null || apis === null || client === null) {
      resetConversation();
      return;
    }
    let cancelled = false;
    let joinedRunId: string | null = null;
    setLoading(true);
    setError(null);
    void (async () => {
      try {
        const opened = await openRef.current();
        if (cancelled) {
          return;
        }
        // The room is joined BEFORE the history is read, so an item produced
        // between the two arrives on the socket rather than falling into the
        // gap between the fetch and the subscription. An unanswered join does
        // not stop the read: the room stays joined for the reconnect to restore.
        joinedRunId = opened.id;
        await client.joinRun(opened.id).catch(() => undefined);
        const history = await apis.chats.listRunItems({
          runId: opened.id,
          limit: HOSTED_CHAT_PAGE,
        });
        if (cancelled) {
          return;
        }
        // The stream holds rows for the run on screen alone, so the ref is set
        // here, ahead of the render that would set it — the same order the chat
        // screen takes in `activateRun`.
        runIdRef.current = opened.id;
        commitItems([]);
        commitCallRows([]);
        // A new conversation starts its cursor over, as `activateRun` does: the
        // previous run's seq would otherwise hold the replay cursor past rows
        // this one never had.
        lastSeqRef.current = -1;
        reconnectAfterSeqRef.current = -1;
        liveTurnEndedRef.current = false;
        for (const row of history.items) {
          ingest(row, false);
        }
        // The window is loaded through its newest row, so a socket that drops
        // from here replays what came after it — as `activateRun` takes it.
        reconnectAfterSeqRef.current = lastSeqRef.current;
        commitAnchors(history.anchors);
        setLiveText(EMPTY_LIVE_TEXT);
        setRun(opened);
        setActivity(null);
        forgetAnchorAsks();
        setWorking(isTurnRunning(opened.status));
      } catch (err) {
        if (!cancelled) {
          setError(describeDaemonError(err));
        }
      } finally {
        if (!cancelled) {
          setLoading(false);
        }
      }
    })();
    return () => {
      cancelled = true;
      if (joinedRunId !== null) {
        client.leaveRun(joinedRunId);
      }
    };
  }, [
    subject,
    apis,
    client,
    reopenNonce,
    resetConversation,
    commitItems,
    commitAnchors,
    forgetAnchorAsks,
    ingest,
    setLiveText,
    lastSeqRef,
    reconnectAfterSeqRef,
  ]);

  const runId = run?.id ?? null;

  useEffect(() => {
    if (client === null || runId === null) {
      return;
    }
    return client.onRunStatus((event) => {
      if (event.runId !== runId) {
        return;
      }
      const status = event.status;
      // The phrase the live row names the work with, under the chat screen's own
      // rule (`activityAfterAnnounce`).
      const phrase = activityAfterAnnounce(event);
      if (phrase !== undefined) {
        setActivity(phrase);
      }
      // The row's copy of the fields the header, the context ring and the
      // delegate blocks read — see `runRowPatch`. A count-only announce sets its
      // count and no other field of the row.
      const patch = runRowPatch(event);
      for (const landed of landedDuringReads.current) {
        landed.push(patch);
      }
      if (Object.keys(patch).length > 0) {
        setRun((current) => (current ? { ...current, ...patch } : current));
      }
      // Only ever raised here. A turn is lowered by its own terminal ITEM, so
      // a status announce that arrives first cannot report the turn as over
      // while the rows that ended it are still being written.
      if (status !== null && isTurnRunning(status)) {
        setWorking(true);
      }
      // A settle after the turn's terminal row already landed — that row
      // counted the turn end, so only `working` comes down here.
      if (
        liveTurnEndedRef.current &&
        status !== null &&
        isSettledRunStatus(status)
      ) {
        setWorking(false);
      }
      // Except a settle no terminal row stands behind — a lease running out,
      // the CLI session closing under an off-turn run. Nothing else will ever
      // arrive to lower it, and a raised flag keeps autosave paused.
      if (
        event.noTerminalItem === true &&
        status !== null &&
        isSettledRunStatus(status)
      ) {
        settle(status);
      }
    });
  }, [client, runId, settle]);

  /** This conversation's own view of the shared expiry set: only its requests. */
  const deadRequestIds = useMemo((): ReadonlySet<string> => {
    const ids = new Set<string>();
    if (runId === null) {
      return ids;
    }
    const prefix = `${runId}:`;
    for (const key of stream.deadRequestKeys) {
      if (key.startsWith(prefix)) {
        ids.add(key.slice(prefix.length));
      }
    }
    return ids;
  }, [stream.deadRequestKeys, runId]);

  /**
   * Hands one message to the run, and throws what the daemon refused with — the
   * message queue retries a RUN_BUSY, so it needs the refusal itself.
   */
  const post = useCallback(
    async (
      text: string,
      images?: SendMessageDtoImagesInner[],
      clientMessageId = randomId(),
    ): Promise<void> => {
      if (apis === null || runId === null) {
        throw new Error('no conversation to send to');
      }
      setError(null);
      // Raised BEFORE the request, so the builder's autosave is suspended
      // before the agent can possibly touch the file, and an Apply sent from
      // the analysis popup shows the turn at once.
      setWorking(true);
      try {
        await apis.chats.sendChatMessage({
          runId,
          sendMessageDto: {
            text,
            clientMessageId,
            ...(images?.length ? { images } : {}),
          },
        });
      } catch (err) {
        setWorking(false);
        throw err;
      }
    },
    [apis, runId],
  );

  const send = useCallback(
    async (
      text: string,
      images?: SendMessageDtoImagesInner[],
    ): Promise<boolean> => {
      if (apis === null || runId === null) {
        return false;
      }
      try {
        await post(text, images);
        return true;
      } catch (err) {
        setError(describeDaemonError(err));
        return false;
      }
    },
    [apis, runId, post],
  );

  /**
   * Saves a change to the run's settings. Resolves to whether the daemon took it:
   * a refusal is shown here, and the caller puts its own control back.
   */
  const patchSettings = useCallback(
    async (patch: UpdateChatSettingsDto): Promise<boolean> => {
      if (apis === null || runId === null) {
        return false;
      }
      try {
        const updated = await apis.chats.updateChatSettings({
          runId,
          updateChatSettingsDto: patch,
        });
        setRun(updated);
        return true;
      } catch (err) {
        setError(describeDaemonError(err));
        return false;
      }
    },
    [apis, runId],
  );

  const respond = useCallback(
    (
      requestId: string,
      allow: boolean,
      answer?: string,
      optionId?: string,
    ): void => {
      if (client === null || runId === null) {
        return;
      }
      // Arity-preserving: a one-time verdict keeps the call it always made.
      if (optionId === undefined) {
        client.sendVerdict(runId, requestId, allow, answer);
      } else {
        client.sendVerdict(runId, requestId, allow, answer, optionId);
      }
    },
    [client, runId],
  );

  const cancel = useCallback(async (): Promise<void> => {
    if (apis === null || runId === null) {
      return;
    }
    try {
      await apis.chats.cancelChat({ runId });
    } catch (err) {
      setError(describeDaemonError(err));
    }
  }, [apis, runId]);

  const discard = useCallback(async (): Promise<void> => {
    const throwAway = discardRef.current;
    if (apis === null || subject === null || throwAway === undefined) {
      return;
    }
    try {
      await throwAway();
      resetConversation();
      // The room is left by the open effect's own cleanup, which this re-runs:
      // leaving it here as well would leave the room twice and, worse, leave
      // the room the NEXT conversation is about to join.
      setReopenNonce((nonce) => nonce + 1);
    } catch (err) {
      setError(describeDaemonError(err));
    }
  }, [apis, subject, resetConversation]);

  return {
    client,
    reconnectNonce,
    markWorking: setWorking,
    run,
    items,
    anchors,
    liveText,
    loading,
    error,
    working,
    activity,
    settledTurns,
    liveUnsent,
    settledAs,
    send,
    post,
    patchSettings,
    rememberContext,
    deadRequestIds,
    respond,
    cancel,
    discard,
  };
}
