import { useEffect, useState } from 'react';

import type { LessonSegment } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

/** Every status a stretch can be in, for a reader that draws an offer through to its end. */
export const ALL_SEGMENT_STATUSES =
  'offered,dismissed,failed,reflecting,reflected,empty';

/**
 * Lesson stretches as the daemon holds them, re-read whenever a
 * `lessons_changed` broadcast names the thread (or names none). `runId` null
 * reads every thread's; `statuses` is the daemon's comma-separated filter,
 * omitted = the ones waiting in Not reflected yet (offered, failed). Null
 * until the first answer.
 */
export function useLessonSegments({
  lessonsApi,
  client,
  runId,
  statuses,
}: {
  lessonsApi: DaemonApis['lessons'] | null;
  client: DaemonClient | null;
  runId: string | null;
  statuses?: string;
}): { segments: LessonSegment[] | null; reload: () => void } {
  const [segments, setSegments] = useState<LessonSegment[] | null>(null);
  const [generation, setGeneration] = useState(0);

  useEffect(() => {
    if (client === null) {
      return;
    }
    return client.onLessonsChanged((event) => {
      if (runId === null || event.runId === null || event.runId === runId) {
        setGeneration((count) => count + 1);
      }
    });
  }, [client, runId]);

  useEffect(() => {
    if (lessonsApi === null) {
      return;
    }
    let live = true;
    void lessonsApi
      .listLessonSegments({
        ...(runId === null ? {} : { runId }),
        ...(statuses === undefined ? {} : { status: statuses }),
      })
      .then((answer) => {
        if (live) {
          setSegments(answer.segments);
        }
      })
      .catch(() => {
        if (live) {
          setSegments([]);
        }
      });
    return () => {
      live = false;
    };
  }, [lessonsApi, runId, statuses, generation]);

  return {
    segments,
    reload: () => setGeneration((count) => count + 1),
  };
}
