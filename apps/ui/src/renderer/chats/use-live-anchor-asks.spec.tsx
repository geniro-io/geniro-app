// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  ANCHOR_ASK_DELAY_MS,
  type LiveAnchorAsks,
  useLiveAnchorAsks,
} from './use-live-anchor-asks';

(
  globalThis as unknown as { IS_REACT_ACT_ENVIRONMENT: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const NONE: ChatItem[] = [];

const calleeRow = (runId: string, seq: number, callId: string): ChatItem => ({
  id: `${runId}-${seq}`,
  runId,
  nodeId: 'qa',
  seq,
  kind: 'message',
  role: null,
  payload: { text: 'x', callId },
  createdAt: 'now',
});

let root: Root | null = null;
beforeEach(() => {
  vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] });
});
afterEach(() => {
  act(() => root?.unmount());
  root = null;
  vi.useRealTimers();
});

async function mount(): Promise<{
  asks: () => LiveAnchorAsks;
  listRunItems: ReturnType<typeof vi.fn>;
}> {
  const listRunItems = vi.fn(() => Promise.resolve({ items: [], anchors: [] }));
  let latest: LiveAnchorAsks | null = null;
  function Probe(): null {
    latest = useLiveAnchorAsks({
      api: { listRunItems },
      items: NONE,
      anchors: NONE,
      isCurrentRun: () => true,
      onAnchors: () => undefined,
    });
    return null;
  }
  root = createRoot(document.createElement('div'));
  await act(async () => root!.render(<Probe />));
  return { asks: () => latest!, listRunItems };
}

describe('useLiveAnchorAsks', () => {
  it('drops a pending batch for another run rather than asking about both', async () => {
    // Its answer would be dropped on landing anyway: the run on screen moved.
    const { asks, listRunItems } = await mount();

    await act(async () => {
      asks().ask(calleeRow('r1', 10, 'call-1'));
      asks().ask(calleeRow('r2', 20, 'call-2'));
      await vi.advanceTimersByTimeAsync(ANCHOR_ASK_DELAY_MS);
    });

    expect(listRunItems).toHaveBeenCalledTimes(1);
    expect(listRunItems).toHaveBeenCalledWith(
      expect.objectContaining({ runId: 'r2', afterSeq: 19 }),
    );
  });

  it('asks nothing once the surface that gathered the batch is gone', async () => {
    const { asks, listRunItems } = await mount();

    await act(async () => {
      asks().ask(calleeRow('r1', 10, 'call-1'));
    });
    act(() => root?.unmount());
    root = null;
    await vi.advanceTimersByTimeAsync(ANCHOR_ASK_DELAY_MS);

    expect(listRunItems).not.toHaveBeenCalled();
  });
});
