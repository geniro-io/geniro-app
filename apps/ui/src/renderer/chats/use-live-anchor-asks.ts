import { useCallback, useEffect, useRef } from 'react';

import {
  type ChatsApi,
  type ItemDto as ChatItem,
  ListRunItemsTakeEnum,
} from '../autogenerated';
import { structureIndexOf, unplacedStructureOf } from './history-anchors';
import { payloadString } from './transcript-payload';

/** How long live rows naming unplaced structure are gathered before one ask. */
export const ANCHOR_ASK_DELAY_MS = 250;

/**
 * The most rows one anchor ask may span.
 *
 * TWIN: the daemon's own `limit` ceiling, `historyQuerySchema` in
 * apps/daemon/src/v1/agents/dto/chat.dto.ts — a larger ask is refused.
 */
const ANCHOR_ASK_MAX_ROWS = 5000;

export interface LiveAnchorAsks {
  /** Check one live row, and ask the daemon for its anchors when it needs some. */
  ask: (item: ChatItem) => void;
  /** Drop everything asked so far — call it wherever the anchors are REPLACED. */
  forget: () => void;
}

/**
 * A live row naming structure that started ABOVE the window — a call that went
 * quiet and has just spoken again, a delegate launched before the page — asks
 * the daemon for that row's anchors, exactly as a page would have brought them.
 * Batched over a short wait, because such a row is rarely alone: a woken call
 * streams a burst.
 *
 * Shared by every surface that holds a transcript WINDOW and appends live rows
 * to it (the chat screen, the workflow builder's dock), so the two cannot come
 * to disagree about which live rows need anchors.
 */
export function useLiveAnchorAsks({
  api,
  items,
  anchors,
  isCurrentRun,
  onAnchors,
}: {
  /** Null while there is no daemon to ask; live rows then ask nothing. */
  api: Pick<ChatsApi, 'listRunItems'> | null;
  items: readonly ChatItem[];
  anchors: readonly ChatItem[];
  /** Whether `runId` is still the run on screen when an answer lands. */
  isCurrentRun: (runId: string) => boolean;
  /** Merge an answer's anchors into the held ones. */
  onAnchors: (rows: ChatItem[]) => void;
}): LiveAnchorAsks {
  // What the window and its anchors can already place. Rebuilt when either
  // list moves, and topped up by a live row that opens structure itself, since
  // the next live row can name it before React has committed the first.
  const structureRef = useRef(structureIndexOf());
  useEffect(() => {
    structureRef.current = structureIndexOf(items, anchors);
  }, [items, anchors]);
  const isCurrentRunRef = useRef(isCurrentRun);
  const onAnchorsRef = useRef(onAnchors);
  useEffect(() => {
    isCurrentRunRef.current = isCurrentRun;
    onAnchorsRef.current = onAnchors;
  });
  // Structure already asked about, so one the daemon has no anchor for — a
  // delegate never launched by a tool call — is asked once, not per row.
  const askedRef = useRef(new Set<string>());
  const pendingRef = useRef<{
    runId: string;
    seqs: number[];
    timer: ReturnType<typeof setTimeout>;
  } | null>(null);
  // Bumped by every reset, so an answer still in flight when the window was
  // replaced is not merged into the new one.
  const generationRef = useRef(0);

  const forget = useCallback((): void => {
    if (pendingRef.current !== null) {
      clearTimeout(pendingRef.current.timer);
      pendingRef.current = null;
    }
    askedRef.current = new Set();
    generationRef.current += 1;
  }, []);
  // A batch still gathering when the surface goes would ask about a screen
  // nobody is looking at.
  useEffect(() => forget, [forget]);

  const ask = useCallback(
    (item: ChatItem): void => {
      if (api === null) {
        return;
      }
      const index = structureRef.current;
      const opened =
        item.kind === 'call_started' || item.kind === 'tool_call'
          ? payloadString(
              item.payload,
              item.kind === 'call_started' ? 'callId' : 'id',
            )
          : null;
      if (opened !== null) {
        (item.kind === 'call_started' ? index.callStarts : index.toolCalls).add(
          opened,
        );
      }
      const asked = askedRef.current;
      const keys = unplacedStructureOf(item, index).filter(
        (key) => !asked.has(key),
      );
      if (keys.length === 0) {
        return;
      }
      keys.forEach((key) => asked.add(key));
      const pending = pendingRef.current;
      if (pending !== null && pending.runId === item.runId) {
        pending.seqs.push(item.seq);
        return;
      }
      if (pending !== null) {
        // Another run's batch: its answer would be dropped anyway.
        clearTimeout(pending.timer);
      }
      const runId = item.runId;
      const seqs = [item.seq];
      pendingRef.current = {
        runId,
        seqs,
        timer: setTimeout(() => {
          pendingRef.current = null;
          const generation = generationRef.current;
          const from = Math.min(...seqs);
          const to = Math.max(...seqs);
          void api
            .listRunItems({
              runId,
              afterSeq: from - 1,
              beforeSeq: to + 1,
              limit: Math.min(to - from + 1, ANCHOR_ASK_MAX_ROWS),
              take: ListRunItemsTakeEnum.Oldest,
            })
            .then((page) => {
              if (
                isCurrentRunRef.current(runId) &&
                generationRef.current === generation
              ) {
                onAnchorsRef.current(page.anchors);
              }
            })
            // Best effort: the next page or reopening the thread brings them.
            .catch(() => undefined);
        }, ANCHOR_ASK_DELAY_MS),
      };
    },
    [api],
  );

  return { ask, forget };
}
