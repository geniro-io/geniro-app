import { createContext, useContext, useEffect, useState } from 'react';

import type { TaskDto } from '../autogenerated';
import { daemonErrorStatus } from '../daemon-api';

/**
 * How a transcript row reads one board card and hears it change. Provided by
 * `Chats`, which holds the daemon handle and the socket; null draws a card from
 * the transcript alone, with no live state.
 */
export interface TaskReader {
  read: (taskId: string) => Promise<TaskDto>;
  /** Calls `listener` with each changed card's id; answers the unsubscribe. */
  onChanged: (listener: (taskId: string) => void) => () => void;
  onReconnect: (listener: () => void) => () => void;
}

export const TaskReaderContext = createContext<TaskReader | null>(null);

export type LiveTask =
  | { kind: 'unread' }
  | { kind: 'loading' }
  | { kind: 'found'; task: TaskDto }
  | { kind: 'gone' }
  | { kind: 'unreadable' };

/**
 * One board card as the daemon has it now: read when `taskId` is first known,
 * again on every `task_changed` naming it and after a reconnect. An answer to
 * an older read never replaces a newer one.
 */
export function useLiveTask(taskId: string | null): LiveTask {
  const reader = useContext(TaskReaderContext);
  const [state, setState] = useState<LiveTask>({ kind: 'unread' });
  useEffect(() => {
    if (reader === null || taskId === null) {
      setState({ kind: 'unread' });
      return;
    }
    let live = true;
    let latest = 0;
    const load = (): void => {
      const ask = ++latest;
      reader.read(taskId).then(
        (task) => {
          if (live && ask === latest) {
            setState({ kind: 'found', task });
          }
        },
        (error: unknown) => {
          if (live && ask === latest) {
            setState({
              kind: daemonErrorStatus(error) === 404 ? 'gone' : 'unreadable',
            });
          }
        },
      );
    };
    setState({ kind: 'loading' });
    load();
    const offChanged = reader.onChanged((changed) => {
      if (changed === taskId) {
        load();
      }
    });
    const offReconnect = reader.onReconnect(load);
    return () => {
      live = false;
      offChanged();
      offReconnect();
    };
  }, [reader, taskId]);
  return state;
}
