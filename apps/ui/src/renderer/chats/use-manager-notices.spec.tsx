// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { SettingsNotice, SettingsNoticesDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { type ManagerNotices, useManagerNotices } from './use-manager-notices';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function notice(
  id: string,
  overrides: Partial<SettingsNotice> = {},
): SettingsNotice {
  return {
    id,
    kind: 'app-update',
    key: 'app-update',
    items: ['1.0.0'],
    label: null,
    openedAt: '2026-11-27T10:00:00.000Z',
    resolvedAt: null,
    dismissedAt: null,
    ...overrides,
  };
}

let root: Root;
let container: HTMLDivElement;
let list: SettingsNoticesDto;
let listCommandCenterNotices: ReturnType<typeof vi.fn>;
let dismissCommandCenterNotice: ReturnType<typeof vi.fn>;
let dismissCommandCenterThreadDone: ReturnType<typeof vi.fn>;
let changed: (event: { runIds: string[]; reason: string }) => void;
let reconnected: () => void;
let seen: ManagerNotices | null;

const client = {
  onCommandCenterChanged: (
    listener: (event: { runIds: string[]; reason: string }) => void,
  ) => {
    changed = listener;
    return () => undefined;
  },
  onReconnect: (listener: () => void) => {
    reconnected = listener;
    return () => undefined;
  },
} as unknown as DaemonClient;

function Probe({ apis }: { apis: DaemonApis }): null {
  seen = useManagerNotices(apis, client);
  return null;
}

async function mount(): Promise<void> {
  const apis = {
    commandCenter: {
      listCommandCenterNotices,
      dismissCommandCenterNotice,
      dismissCommandCenterThreadDone,
    },
  } as unknown as DaemonApis;
  await act(async () => {
    root.render(<Probe apis={apis} />);
  });
}

beforeEach(() => {
  seen = null;
  list = { notices: [], doneDismissals: [] };
  listCommandCenterNotices = vi.fn(() =>
    Promise.resolve(structuredClone(list)),
  );
  dismissCommandCenterNotice = vi.fn(({ noticeId }: { noticeId: string }) =>
    Promise.resolve(
      notice(noticeId, { dismissedAt: '2026-11-27T11:00:00.000Z' }),
    ),
  );
  dismissCommandCenterThreadDone = vi.fn(
    ({
      runId,
      dismissThreadDoneDto,
    }: {
      runId: string;
      dismissThreadDoneDto: { seq: number };
    }) =>
      Promise.resolve({
        notices: list.notices,
        doneDismissals: [{ runId, throughSeq: dismissThreadDoneDto.seq }],
      }),
  );
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('useManagerNotices', () => {
  it('counts only the notices still waiting: open and not dismissed', async () => {
    list.notices = [
      notice('open'),
      notice('dismissed', { dismissedAt: '2026-11-27T11:00:00.000Z' }),
      notice('resolved', { resolvedAt: '2026-11-27T11:00:00.000Z' }),
      notice('also-open', {
        kind: 'memory-conflicts',
        key: 'memory-conflicts',
      }),
    ];
    await mount();

    expect(seen?.unresolved).toBe(2);
  });

  it('follows a new notice, a resolution and a dismissal made on another device', async () => {
    await mount();
    expect(seen?.unresolved).toBe(0);

    list.notices = [notice('n1')];
    await act(async () => {
      changed({ runIds: ['manager'], reason: 'notices' });
    });
    expect(seen?.unresolved).toBe(1);

    list.notices = [notice('n1', { dismissedAt: '2026-11-27T11:00:00.000Z' })];
    await act(async () => {
      changed({ runIds: ['manager'], reason: 'roster' });
    });
    expect(seen?.unresolved).toBe(1);
    await act(async () => {
      reconnected();
    });
    expect(seen?.unresolved).toBe(0);
  });

  it('drops a notice from the count once the daemon confirms its Dismiss', async () => {
    list.notices = [notice('n1')];
    await mount();

    await act(async () => {
      seen!.dismiss('n1');
    });

    expect(dismissCommandCenterNotice).toHaveBeenCalledWith({ noticeId: 'n1' });
    expect(seen?.unresolved).toBe(0);
  });

  it("keeps a Done card's dismissal the daemon records, at once and after a re-read", async () => {
    await mount();

    act(() => {
      seen!.dismissDone('thread-a', 7);
    });
    expect(seen?.doneDismissedThrough.get('thread-a')).toBe(7);
    expect(dismissCommandCenterThreadDone).toHaveBeenCalledWith({
      runId: 'thread-a',
      dismissThreadDoneDto: { seq: 7 },
    });

    list.doneDismissals = [{ runId: 'thread-a', throughSeq: 7 }];
    await act(async () => {
      changed({ runIds: ['manager'], reason: 'notices' });
    });
    expect(seen?.doneDismissedThrough.get('thread-a')).toBe(7);
  });

  it('takes a refused Done dismissal back from the daemon list', async () => {
    dismissCommandCenterThreadDone = vi.fn(() =>
      Promise.reject(new Error('not found')),
    );
    await mount();

    await act(async () => {
      seen!.dismissDone('thread-a', 7);
    });

    expect(seen?.doneDismissedThrough.has('thread-a')).toBe(false);
  });
});
