import { useCallback, useEffect, useRef, useState } from 'react';

import type { SendMessageDtoImagesInner } from '../autogenerated';
import { isRunBusyError } from '../daemon-api';
import { randomId } from '../random-id';
import {
  type QueuedMessage,
  readStoredQueueState,
  type RestoredQueueState,
  writeStoredQueueState,
} from './queued-message-store';

/**
 * Backoff for a queued send that hits RUN_BUSY. The run's terminal item is
 * persisted-then-emitted while the CLI process is still tearing down, so the
 * daemon frees the turn slot a beat AFTER the renderer learns the turn ended —
 * a queued auto-send racing into that gap is retried briefly, not failed.
 */
const QUEUED_BUSY_RETRIES_MS = [300, 600, 1200, 2400];

/** What the queue needs from the surface it serves, read at the moment of use. */
export interface MessageQueueHandlers {
  /** The run whose queue the strip shows and the strip's controls address. */
  activeRunId: () => string | null;
  /** Hand one message to the run — the surface's own turn start. Throws on refusal. */
  send: (
    runId: string,
    text: string,
    images: SendMessageDtoImagesInner[],
  ) => Promise<unknown>;
  /** Whether a turn is running right now — read before a Send-now's POST. */
  isWorking: () => boolean;
  /**
   * A send that failed for a reason other than RUN_BUSY. `steer` is a
   * Send-now press; `wasWorking` is whether a turn was in flight before it.
   */
  onFailed: (
    runId: string,
    err: unknown,
    press: { steer: boolean; wasWorking: boolean },
  ) => void;
}

const NO_HANDLERS: MessageQueueHandlers = {
  activeRunId: () => null,
  send: () => Promise.reject(new Error('no queue handlers yet')),
  isWorking: () => false,
  onFailed: () => {},
};

const EMPTY_RESTORE: RestoredQueueState = { queues: {}, paused: new Set() };

export type SteerStatus = { id: string; state: 'sending' | 'held' } | null;

/**
 * Messages written while the agent was still working — sent automatically, one
 * per settled turn, in order (Claude Code / Cursor-style queueing). Keyed PER
 * RUN. A queued entry carries its attachments, not just its text: an image
 * dropped on the way through the queue would have the agent answer about a
 * screenshot it never received.
 *
 * The chat screen and the workflow builder's dock both queue through here, so
 * the order, the pause, Send-now and the RUN_BUSY backoff are one set of rules.
 * The surface fills {@link MessageQueueHandlers} through `handlersRef` once its
 * turn start exists, and fires `drain` on whatever tells it a turn ended.
 *
 * `persist` keeps the queues in the browser's storage beside memory: the
 * composer is cleared the moment a message is queued, so a reload before the
 * drain — routine on a phone, where iOS discards a background tab — lost it
 * outright (`queued-message-store.ts`). Only ONE surface may persist: the store
 * is one key, and two readers would each restore, and drain, the other's runs.
 */
export function useMessageQueue({ persist }: { persist: boolean }) {
  const handlersRef = useRef<MessageQueueHandlers>(NO_HANDLERS);
  // Read ONCE, for both halves below: the queues and which of them come back
  // paused (the user's pause, or a head that was mid-send when the page went).
  const [restored] = useState(() =>
    persist ? readStoredQueueState() : EMPTY_RESTORE,
  );
  const [queues, setQueues] = useState<Record<string, QueuedMessage[]>>(
    () => restored.queues,
  );
  const queuesRef = useRef<Record<string, QueuedMessage[]>>(queues);
  /**
   * The message each run's drain has IN FLIGHT, written to storage before its
   * POST goes out and cleared after — so a reload that lands between the two
   * restores that run paused rather than sending the message a second time.
   */
  const sendingRef = useRef<Record<string, string>>({});
  /**
   * Runs whose queue is PAUSED — held until the user releases each message by
   * hand, instead of the head going out on its own when a turn ends.
   *
   * ASKED FOR as "some toggle so queue of messages will not execute
   * automatically, but only on user click". PER RUN, and living exactly as long
   * as the queue: a flag that outlived the queue it was set on would silently
   * hold a thread's next follow-up weeks later. Mirrored into a ref because
   * `drain` reads it from callers that hold a stale closure.
   */
  const [pausedQueues, setPausedQueues] = useState<ReadonlySet<string>>(
    () => restored.paused,
  );
  const pausedRef = useRef<ReadonlySet<string>>(pausedQueues);
  useEffect(() => {
    pausedRef.current = pausedQueues;
  }, [pausedQueues]);
  const store = useCallback((): void => {
    if (!persist) {
      return;
    }
    writeStoredQueueState({
      queues: queuesRef.current,
      paused: pausedRef.current,
      sending: sendingRef.current,
    });
  }, [persist]);
  useEffect(() => {
    queuesRef.current = queues;
    store();
  }, [queues, pausedQueues, store]);
  /**
   * What became of the Send-now the user last pressed — rendered on the row by
   * `QueuedStrip`. One outstanding at a time: the answer belongs to the press,
   * and a second press supersedes the first. The caller clears it on a run
   * switch, so an outcome from one chat never surfaces against another's row.
   */
  const [steerStatus, setSteerStatus] = useState<SteerStatus>(null);
  /**
   * Retire this row's outcome — but only if a later press has not already
   * replaced it. A steer's POST outlives the press, so a slow one resolving
   * after the user moved to another row would otherwise wipe that row's state.
   */
  const clearSteerStatus = useCallback((id: string): void => {
    setSteerStatus((current) => (current?.id === id ? null : current));
  }, []);
  const resetSteerStatus = useCallback((): void => setSteerStatus(null), []);
  /**
   * The queued messages whose POST is out RIGHT NOW — the drain's head, or a
   * Send-now's row — rendered as on their way, with Edit and Remove withheld.
   * Only the POST itself is covered, never the RUN_BUSY backoff between two of
   * them: there the drain re-reads the entry before retrying, so both controls
   * still work.
   */
  const [postingIds, setPostingIds] = useState<ReadonlySet<string>>(
    () => new Set(),
  );
  const markPosting = useCallback((id: string, posting: boolean): void => {
    setPostingIds((current) => {
      if (current.has(id) === posting) {
        return current;
      }
      const next = new Set(current);
      if (posting) {
        next.add(id);
      } else {
        next.delete(id);
      }
      return next;
    });
  }, []);
  // Minted HERE so no caller can enqueue a message without an id.
  const enqueue = useCallback(
    (runId: string, message: Omit<QueuedMessage, 'id'>): void => {
      const entry = { ...message, id: randomId() };
      // The REF is written here too, not left to the effect that mirrors the
      // state — a caller may kick the drain in the same tick, and the drain reads
      // this ref to find its head. Through the effect alone that kick saw the
      // PRE-enqueue map and found nothing to send.
      queuesRef.current = {
        ...queuesRef.current,
        [runId]: [...(queuesRef.current[runId] ?? []), entry],
      };
      setQueues((prev) => ({
        ...prev,
        [runId]: [...(prev[runId] ?? []), entry],
      }));
    },
    [],
  );
  // One drain at a time PER RUN. A history REPLAY of a multi-turn transcript
  // fires the terminal-item trigger once per past turn in one synchronous sweep;
  // without this gate those calls all read the same stale head and double-send
  // it. Per run, so one busy chat's backoff does not hold every other queue.
  const drainingRef = useRef<Set<string>>(new Set());
  /**
   * Is the surface still on screen? The RUN_BUSY backoff runs for seconds, so
   * without this a retry keeps firing after the component is gone. Assigned in
   * the effect BODY so a StrictMode remount does not leave it stuck false.
   */
  const mountedRef = useRef(true);
  useEffect(() => {
    mountedRef.current = true;
    return () => {
      mountedRef.current = false;
    };
  }, []);

  /** Send this run's next queued message after a settled turn. One message per
   *  settled turn, in order; RUN_BUSY is retried per {@link QUEUED_BUSY_RETRIES_MS}. */
  const drain = useCallback(
    async (runId: string): Promise<void> => {
      if (drainingRef.current.has(runId)) {
        return;
      }
      const next = (queuesRef.current[runId] ?? [])[0];
      if (next === undefined) {
        return;
      }
      // The pause, gated HERE rather than at every place a drain is fired from —
      // a gate per caller is one missed edit away from a paused queue that
      // empties itself on reconnect. Send-now does not come through here: that
      // press IS the release.
      if (pausedRef.current.has(runId)) {
        return;
      }
      drainingRef.current.add(runId);
      // The head STAYS in the queue until the send resolves, so it stays visible
      // and removable while in flight. Dropped on success only.
      const dropHead = (): void =>
        setQueues((prev) => ({
          ...prev,
          [runId]: (prev[runId] ?? []).filter(
            (queued) => queued.id !== next.id,
          ),
        }));
      try {
        for (let attempt = 0; ; attempt += 1) {
          if (!mountedRef.current) {
            return;
          }
          // Re-READ the entry; never just check that it is still there. The
          // backoff can hold this loop for seconds and the head keeps live Edit
          // and Remove controls throughout — an edit keeps the id, so a presence
          // check would deliver the text the user replaced, and a missing entry
          // is a removal the user was already told about.
          const current = (queuesRef.current[runId] ?? []).find(
            (queued) => queued.id === next.id,
          );
          if (current === undefined) {
            return;
          }
          try {
            sendingRef.current = { ...sendingRef.current, [runId]: current.id };
            store();
            markPosting(current.id, true);
            try {
              await handlersRef.current.send(
                runId,
                current.text,
                current.images,
              );
            } finally {
              markPosting(current.id, false);
            }
            dropHead();
            return;
          } catch (err) {
            const delay = QUEUED_BUSY_RETRIES_MS[attempt];
            if (!isRunBusyError(err)) {
              // A real failure: the message is still at the head for the user to
              // edit or remove, because it was never taken out.
              handlersRef.current.onFailed(runId, err, {
                steer: false,
                wasWorking: false,
              });
              return;
            }
            if (delay === undefined) {
              // Still busy after the last backoff, which is NOT a failure: a turn
              // is still running and its terminal item fires this drain again.
              return;
            }
            await new Promise((resolve) => setTimeout(resolve, delay));
            // Not abandoned when the user switches away mid-retry: queueing IS
            // the instruction to send it when the turn ends.
          }
        }
      } finally {
        sendingRef.current = Object.fromEntries(
          Object.entries(sendingRef.current).filter(
            ([sendingRun]) => sendingRun !== runId,
          ),
        );
        store();
        drainingRef.current.delete(runId);
        // A Send-now press on the head this drain already owned was answered
        // `sending` with no POST of its own; this drain is the only thing that
        // knows how it ended.
        clearSteerStatus(next.id);
      }
    },
    [clearSteerStatus, store, markPosting],
  );

  /** Rewrite a queued message before it goes out. Text only — an attachment
   *  cannot be re-pasted into a one-line field. */
  const edit = useCallback((id: string, text: string): void => {
    const runId = handlersRef.current.activeRunId();
    if (!runId) {
      return;
    }
    setQueues((prev) => ({
      ...prev,
      [runId]: (prev[runId] ?? []).map((message) =>
        message.id === id ? { ...message, text } : message,
      ),
    }));
  }, []);

  /**
   * Hold the open run's queue, or let it flow again. RESUMING kicks the drain:
   * the automatic drain fires on a turn ENDING, which is usually already in the
   * past by the time the user reaches this control.
   */
  const togglePause = useCallback((): void => {
    const runId = handlersRef.current.activeRunId();
    if (!runId) {
      return;
    }
    const next = new Set(pausedRef.current);
    const resuming = next.delete(runId);
    if (!resuming) {
      next.add(runId);
    }
    pausedRef.current = next;
    setPausedQueues(next);
    if (resuming) {
      void drain(runId);
    }
  }, [drain]);

  const remove = useCallback((id: string): void => {
    const runId = handlersRef.current.activeRunId();
    if (!runId) {
      return;
    }
    setQueues((prev) => ({
      ...prev,
      [runId]: (prev[runId] ?? []).filter((message) => message.id !== id),
    }));
  }, []);

  /**
   * Move one queued message to where another currently sits — the strip's drag
   * and its ↑/↓ keys. REPORTED as wanting to drag the queue "чтобы
   * контролировать, какое сообщение следующим отправится первым". Both ends are
   * ids and both are re-checked, because the queue drains on its own.
   */
  const reorder = useCallback((id: string, overId: string): void => {
    const runId = handlersRef.current.activeRunId();
    if (!runId || id === overId) {
      return;
    }
    setQueues((prev) => {
      const queue = prev[runId] ?? [];
      const from = queue.findIndex((message) => message.id === id);
      const to = queue.findIndex((message) => message.id === overId);
      if (from === -1 || to === -1) {
        return prev;
      }
      const next = [...queue];
      next.splice(to, 0, next.splice(from, 1)[0]!);
      return { ...prev, [runId]: next };
    });
  }, []);

  /**
   * Send one queued message now — into the turn already running, where the CLI
   * has a mid-turn channel, or as the next turn when none is running. A RUN_BUSY
   * is not a failure: the message stays queued and goes out when the turn ends,
   * and the row says `held`.
   */
  const steer = useCallback(
    async (id: string): Promise<void> => {
      const runId = handlersRef.current.activeRunId();
      if (!runId) {
        return;
      }
      const queue = queuesRef.current[runId] ?? [];
      const message = queue.find((queued) => queued.id === id);
      if (!message) {
        return;
      }
      // The drain may already be sending this exact message — the head stays in
      // the queue while in flight — so a press would POST it twice.
      if (drainingRef.current.has(runId) && queue[0]?.id === id) {
        setSteerStatus({ id, state: 'sending' });
        return;
      }
      setSteerStatus({ id, state: 'sending' });
      const wasWorking = handlersRef.current.isWorking();
      try {
        markPosting(id, true);
        try {
          await handlersRef.current.send(runId, message.text, message.images);
        } finally {
          markPosting(id, false);
        }
        // Dropped by ID: the drain can shift the queue and an edit replaces the
        // object while this POST is in flight.
        setQueues((prev) => ({
          ...prev,
          [runId]: (prev[runId] ?? []).filter((queued) => queued.id !== id),
        }));
        clearSteerStatus(id);
      } catch (err) {
        if (isRunBusyError(err)) {
          // Guarded like `clearSteerStatus`: an older steer's refusal must not
          // replace a different row's `sending`.
          setSteerStatus((current) =>
            current === null || current.id === id
              ? { id, state: 'held' }
              : current,
          );
          return;
        }
        clearSteerStatus(id);
        handlersRef.current.onFailed(runId, err, { steer: true, wasWorking });
      }
    },
    [clearSteerStatus, markPosting],
  );

  /** Whether this run holds messages the drain still owes it — read off the ref. */
  const hasQueued = useCallback(
    (runId: string): boolean => (queuesRef.current[runId]?.length ?? 0) > 0,
    [],
  );

  return {
    handlersRef,
    queues,
    pausedQueues,
    postingIds,
    steerStatus,
    enqueue,
    drain,
    edit,
    remove,
    reorder,
    togglePause,
    steer,
    hasQueued,
    resetSteerStatus,
  };
}
