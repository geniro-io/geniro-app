// @vitest-environment jsdom
import { act, createElement } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ModelPrice, ModelPriceAnswerDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { AgentsApiContext } from './agents-api-context';
import {
  MODEL_PRICE_TTL_MS,
  requestModelPrice,
  useModelPrice,
} from './use-model-price';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const PRICE: ModelPrice = {
  input: 4,
  output: 20,
  cacheRead: 0.4,
  cacheWrite: null,
  tiers: [],
};

function agentsApi(
  answer: (query: {
    agent: string;
    model: string;
    configDir?: string;
  }) => Promise<ModelPriceAnswerDto>,
) {
  const getModelPrice = vi.fn(answer);
  return {
    getModelPrice,
    api: { getModelPrice } as unknown as DaemonApis['agents'],
  };
}

describe('requestModelPrice', () => {
  it('asks once per model, account and client within the TTL, and again after it', async () => {
    const { api, getModelPrice } = agentsApi(() =>
      Promise.resolve({ pricedAs: 'claude-opus-5-5', price: PRICE }),
    );

    await expect(
      requestModelPrice(api, 'claude', 'opus', '/profiles/work', 1_000),
    ).resolves.toEqual(PRICE);
    await requestModelPrice(
      api,
      'claude',
      'opus',
      '/profiles/work',
      1_000 + MODEL_PRICE_TTL_MS - 1,
    );
    expect(getModelPrice).toHaveBeenCalledTimes(1);
    expect(getModelPrice).toHaveBeenCalledWith({
      agent: 'claude',
      model: 'opus',
      configDir: '/profiles/work',
    });

    await requestModelPrice(
      api,
      'claude',
      'opus',
      '/profiles/work',
      1_000 + MODEL_PRICE_TTL_MS,
    );
    expect(getModelPrice).toHaveBeenCalledTimes(2);
  });

  it('shares a request still in flight', async () => {
    let release: (answer: ModelPriceAnswerDto) => void = () => {};
    const { api, getModelPrice } = agentsApi(
      () =>
        new Promise((resolve) => {
          release = resolve;
        }),
    );

    const first = requestModelPrice(api, 'codex', 'gpt-6.1-sol', null, 0);
    const second = requestModelPrice(api, 'codex', 'gpt-6.1-sol', null, 1);
    release({ pricedAs: 'gpt-6.1-sol', price: PRICE });

    await expect(Promise.all([first, second])).resolves.toEqual([PRICE, PRICE]);
    expect(getModelPrice).toHaveBeenCalledTimes(1);
    expect(getModelPrice).toHaveBeenCalledWith({
      agent: 'codex',
      model: 'gpt-6.1-sol',
    });
  });

  it('keeps two agents, or two accounts, of one model id apart', async () => {
    const { api, getModelPrice } = agentsApi(() =>
      Promise.resolve({ pricedAs: null, price: null }),
    );

    await requestModelPrice(api, 'claude', 'claude-haiku-5-5', null, 0);
    await requestModelPrice(api, 'cursor-agent', 'claude-haiku-5-5', null, 0);
    await requestModelPrice(api, 'claude', 'claude-haiku-5-5', '/p/two', 0);

    expect(getModelPrice).toHaveBeenCalledTimes(3);
  });

  it('reads a failed request as no price and asks again next time', async () => {
    let fail = true;
    const { api, getModelPrice } = agentsApi(() =>
      fail
        ? Promise.reject(new Error('daemon GET failed (503)'))
        : Promise.resolve({ pricedAs: 'gpt-6-astra', price: PRICE }),
    );

    await expect(
      requestModelPrice(api, 'codex', 'gpt-6-astra', null, 0),
    ).resolves.toBeNull();
    fail = false;
    await expect(
      requestModelPrice(api, 'codex', 'gpt-6-astra', null, 1),
    ).resolves.toEqual(PRICE);
    expect(getModelPrice).toHaveBeenCalledTimes(2);
  });
});

describe('useModelPrice', () => {
  let root: Root | null = null;

  afterEach(() => {
    act(() => root?.unmount());
    root = null;
    document.body.innerHTML = '';
  });

  it('shows the price of the model now named, never an answer for the one before', async () => {
    const pending = new Map<string, (answer: ModelPriceAnswerDto) => void>();
    const { api } = agentsApi(
      ({ model }) =>
        new Promise((resolve) => {
          pending.set(model, resolve);
        }),
    );
    const seen: (ModelPrice | null)[] = [];
    function Probe({ model }: { model: string }): null {
      seen.push(useModelPrice('claude', model, '/stale-guard'));
      return null;
    }
    const container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    const draw = (model: string): void => {
      act(() =>
        root!.render(
          createElement(
            AgentsApiContext.Provider,
            { value: api },
            createElement(Probe, { model }),
          ),
        ),
      );
    };

    draw('stale-guard-a');
    draw('stale-guard-b');
    await act(async () => {
      pending.get('stale-guard-b')?.({ pricedAs: 'b', price: PRICE });
      pending.get('stale-guard-a')?.({
        pricedAs: 'a',
        price: { ...PRICE, input: 99 },
      });
      await Promise.resolve();
    });

    expect(seen.at(-1)).toEqual(PRICE);
    expect(seen.some((price) => price?.input === 99)).toBe(false);
  });

  it('draws no price for a newly named model until its own answer lands', async () => {
    const pending = new Map<string, (answer: ModelPriceAnswerDto) => void>();
    const { api } = agentsApi(
      ({ model }) =>
        new Promise((resolve) => {
          pending.set(model, resolve);
        }),
    );
    const seen: (ModelPrice | null)[] = [];
    function Probe({ model }: { model: string }): null {
      seen.push(useModelPrice('claude', model, '/switch-guard'));
      return null;
    }
    const container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    const draw = (model: string): void => {
      act(() =>
        root!.render(
          createElement(
            AgentsApiContext.Provider,
            { value: api },
            createElement(Probe, { model }),
          ),
        ),
      );
    };

    draw('switch-guard-a');
    await act(async () => {
      pending.get('switch-guard-a')?.({
        pricedAs: 'a',
        price: { ...PRICE, input: 99 },
      });
      await Promise.resolve();
    });
    expect(seen.at(-1)?.input).toBe(99);

    draw('switch-guard-b');
    expect(seen.at(-1)).toBeNull();
  });
});
