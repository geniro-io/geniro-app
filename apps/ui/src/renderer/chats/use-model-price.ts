import { useContext, useEffect, useState } from 'react';

import type { CliKind } from '../../shared/contracts';
import type { ModelPrice } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { AgentsApiContext } from './agents-api-context';

/**
 * How long an answer is reused. Short: the daemon answers from memory, and its
 * own copy of the catalog is what refreshes hourly.
 */
export const MODEL_PRICE_TTL_MS = 5 * 60_000;

interface CachedPrice {
  at: number;
  price: Promise<ModelPrice | null>;
}

/** Per client, so a restarted daemon's answers are asked of it afresh. */
const cache = new WeakMap<DaemonApis['agents'], Map<string, CachedPrice>>();

/**
 * One model's list price (`GET /v1/agents/model-price`), shared by every
 * surface that shows the same model under the same account, a request in
 * flight included. A failed read is forgotten at once, so the next surface
 * asks again, and reads as no price meanwhile.
 */
export function requestModelPrice(
  agentsApi: DaemonApis['agents'],
  agent: CliKind,
  model: string,
  configDir: string | null,
  now: number = Date.now(),
): Promise<ModelPrice | null> {
  let byModel = cache.get(agentsApi);
  if (byModel === undefined) {
    byModel = new Map();
    cache.set(agentsApi, byModel);
  }
  const key = priceKey(agent, model, configDir);
  const held = byModel.get(key);
  if (held !== undefined && now - held.at < MODEL_PRICE_TTL_MS) {
    return held.price;
  }
  const entry: CachedPrice = {
    at: now,
    price: agentsApi
      .getModelPrice({ agent, model, ...(configDir ? { configDir } : {}) })
      .then(
        (answer) => answer.price,
        () => {
          if (byModel.get(key) === entry) {
            byModel.delete(key);
          }
          return null;
        },
      ),
  };
  byModel.set(key, entry);
  return entry.price;
}

/** One model a surface shows, under the CLI and account that run it. */
export interface ModelPriceQuery {
  agent: CliKind | null;
  model: string | null;
  configDir?: string | null;
}

/**
 * The list prices of several models at once, in the order asked, read through
 * `AgentsApiContext` — null for one still unknown or unpriced. An answer is
 * kept under its own question, so a model newly named never shows the price
 * of the one before it.
 */
export function useModelPrices(
  queries: readonly ModelPriceQuery[],
): (ModelPrice | null)[] {
  const agentsApi = useContext(AgentsApiContext);
  const keys = queries.map((query) =>
    query.agent !== null && query.model
      ? priceKey(query.agent, query.model, query.configDir ?? null)
      : null,
  );
  const asked = keys.filter((key): key is string => key !== null).join(SEP);
  const [answers, setAnswers] = useState<
    ReadonlyMap<string, ModelPrice | null>
  >(() => new Map());
  useEffect(() => {
    if (agentsApi === null || asked === '') {
      return undefined;
    }
    let current = true;
    for (const key of new Set(asked.split(SEP))) {
      const [agent, model, configDir] = key.split(PART) as [
        CliKind,
        string,
        string,
      ];
      void requestModelPrice(agentsApi, agent, model, configDir || null).then(
        (price) => {
          if (current) {
            setAnswers((held) => new Map(held).set(key, price));
          }
        },
      );
    }
    return () => {
      current = false;
    };
  }, [agentsApi, asked]);
  return keys.map((key) => (key === null ? null : (answers.get(key) ?? null)));
}

/** The list price of the model an agent runs under its account. */
export function useModelPrice(
  agent: CliKind | null,
  model: string | null,
  configDir: string | null = null,
): ModelPrice | null {
  return useModelPrices([{ agent, model, configDir }])[0] ?? null;
}

/** Neither a CLI name, a model id nor a path can contain these two. */
const PART = '\u0000';
const SEP = '\u0001';

function priceKey(
  agent: CliKind,
  model: string,
  configDir: string | null,
): string {
  return `${agent}${PART}${model}${PART}${configDir ?? ''}`;
}
