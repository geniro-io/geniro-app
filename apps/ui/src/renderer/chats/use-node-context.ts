import { useEffect, useState } from 'react';

import type { NodeStateDto, WorkflowsApi } from '../autogenerated';
import type { DaemonClient } from '../daemon-client';

/**
 * One workflow node's durable readings: its last context figure, the same per
 * CALL, and the totals it has accumulated — worked time and tool count.
 *
 * DERIVED from the wire DTO rather than restated, and that is what keeps the
 * mapper below honest: this file narrows the route's answer through an object
 * literal, so a field added to the schema and forgotten here would never reach
 * the ring and would raise no type error. Picking the fields makes the omission
 * a compile error instead.
 */
export type NodeDurableReading = Pick<
  NodeStateDto,
  | 'contextTokens'
  | 'contextWindowTokens'
  | 'calls'
  | 'workedMs'
  | 'toolCalls'
  // The node's own status and when its running turn began: what the transcript
  // window loses on a long run — see `withDurableNodeStatus`.
  | 'status'
  | 'startedAt'
  // What the node, and its own conversation, spent over the WHOLE run — the
  // figures a loaded window cannot sum.
  | 'totals'
  | 'mainTotals'
>;

const EMPTY: ReadonlyMap<string, NodeDurableReading> = new Map();

interface NodeContextState {
  /** Which run these readings were fetched for — see the guard on the return. */
  runId: string | null;
  readings: ReadonlyMap<string, NodeDurableReading>;
}

/**
 * Every workflow node's last context reading, read off the DAEMON's own rows.
 *
 * The daemon files a reading on `node_state` from every `context_progress` and
 * again from the `turn_complete` that carries the window — the per-node twin of
 * `Run.contextTokens`, and for the same reason: the live plane is EPHEMERAL, so
 * a window that reloads, reconnects, or opens the run for the first time has
 * nothing to draw a ring from, and a node parked in `await_agent` emits nothing
 * for minutes on end. Until this hook existed those columns were written on the
 * run's serialized persist chain and read by NOBODY — `listWorkflowRunNodes`
 * had no caller outside the generated client.
 *
 * Fetched on run OPEN, on RECONNECT, and each time a turn SETTLES
 * (`settledTurns`): the context figures move with live deltas, which outrank
 * this, but the SPEND totals only ever change when a turn completes and have
 * no live twin — without that trigger an agent's cost froze at the moment the
 * run was opened. The readings are the LAST source the
 * node ring consults for exactly that reason — fresher than the transcript's
 * settled turn, older than the delta being streamed now.
 *
 * A chat run has no nodes, so it is not asked. A failure is silence: the ring
 * falls back to what it already had, and a missing figure is a state the meter
 * already draws honestly.
 */
export function useNodeDurableReadings(
  runId: string | null,
  isWorkflowRun: boolean,
  workflowApi: WorkflowsApi,
  reconnectNonce: number,
  settledTurns = 0,
  client: Pick<DaemonClient, 'onRunStatus'> | null = null,
): ReadonlyMap<string, NodeDurableReading> {
  const [state, setState] = useState<NodeContextState>(() => ({
    runId,
    readings: EMPTY,
  }));
  /**
   * The newest cursor price the daemon announced for this run
   * (`spendUpdatedAt`). A cursor node's bill is polled onto its row up to a
   * minute after its turn settles, so no settled turn follows it — after a
   * run's last turn the card would never have shown it. Stamped with its run
   * for `useChatTotals`' reason: a mark only moves forward, so one left by
   * another run would swallow this run's announce.
   */
  const [spendMark, setSpendMark] = useState<{
    runId: string | null;
    at: number;
  }>(() => ({ runId, at: 0 }));
  useEffect(() => {
    if (client === null || runId === null) {
      return;
    }
    return client.onRunStatus((event) => {
      const at = event.spendUpdatedAt;
      if (event.runId !== runId || at === undefined) {
        return;
      }
      setSpendMark((known) =>
        known.runId !== runId || at > known.at ? { runId, at } : known,
      );
    });
  }, [client, runId]);
  const spendAt = spendMark.runId === runId ? spendMark.at : 0;

  useEffect(() => {
    // Cleared FIRST on a run→run switch, which is what forces it:
    // two runs of one workflow share node ids, so the previous run's map left
    // mounted while the new fetch is in flight resolves every ring against the
    // wrong run's row. That is the same defect `apps/ui/CLAUDE.md` states the
    // rule for on the metrics panel — a reading is carried with the run it was
    // taken from, and a mismatch reads as empty.
    //
    // A re-read of the SAME run keeps what it has until the answer lands, so a
    // turn settling does not blank every ring for the length of a round trip.
    setState((current) =>
      current.runId === runId ? current : { runId, readings: EMPTY },
    );
    if (runId === null || !isWorkflowRun) {
      return;
    }
    let cancelled = false;
    void workflowApi
      .listWorkflowRunNodes({ runId })
      .then((nodes) => {
        if (cancelled) {
          return;
        }
        setState({
          runId,
          readings: new Map(
            nodes.map((node) => [
              node.nodeId,
              {
                contextTokens: node.contextTokens,
                contextWindowTokens: node.contextWindowTokens,
                calls: node.calls,
                workedMs: node.workedMs,
                toolCalls: node.toolCalls,
                status: node.status,
                startedAt: node.startedAt,
                totals: node.totals,
                mainTotals: node.mainTotals,
              },
            ]),
          ),
        });
      })
      .catch(() => {
        // Silent by design — this is a fallback under two fresher sources, and
        // an error strip about a ring is louder than the thing it is about. It
        // leaves the map EMPTY rather than keeping what an earlier read said: a
        // failed re-read costs this run's rings their durable source and never
        // leaves an older reading standing in for a request that did not answer.
        if (!cancelled) {
          setState({ runId, readings: EMPTY });
        }
      });
    return () => {
      cancelled = true;
    };
  }, [
    runId,
    isWorkflowRun,
    workflowApi,
    reconnectNonce,
    settledTurns,
    spendAt,
  ]);

  // The readings belong to the run they were fetched for. The effect clears on
  // entry, but it runs AFTER the render that changed `runId` — and since two
  // runs of one workflow share node ids, that one render resolves every ring
  // against the previous run's row instead of drawing none. Same guard, and the
  // same reason, as the one on `use-chat-totals.ts`.
  return state.runId === runId ? state.readings : EMPTY;
}
