// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { PluginBlock, PluginsApi } from '../autogenerated';
import { type PluginBlocksEvents, usePluginBlocks } from './use-plugin-blocks';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

type ListPluginBlocks = PluginsApi['listPluginBlocksForRun'];

const block = (slug: string): PluginBlock => ({
  slug,
  name: slug,
  state: 'approved',
  folder: '/repo',
  view: [],
  refreshMinutes: 5,
  buttons: [],
  result: null,
});

const apiWith = (listPluginBlocksForRun: ListPluginBlocks): PluginsApi =>
  ({ listPluginBlocksForRun }) as unknown as PluginsApi;

function listenerBoard() {
  const listeners: { changed?: () => void; reconnect?: () => void } = {};
  const offChanged = vi.fn();
  const offReconnect = vi.fn();
  const events: PluginBlocksEvents = {
    onPluginsChanged: (listener) => {
      listeners.changed = listener;
      return offChanged;
    },
    onReconnect: (listener) => {
      listeners.reconnect = listener;
      return offReconnect;
    },
  };
  return { events, listeners, offChanged, offReconnect };
}

const tick = (): Promise<void> =>
  new Promise((resolve) => {
    setTimeout(resolve, 0);
  });

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

async function mount(
  api: PluginsApi | null,
  events: PluginBlocksEvents | null,
  runId: string | null,
): Promise<() => readonly PluginBlock[]> {
  let latest: readonly PluginBlock[] | null = null;
  function Probe(): null {
    latest = usePluginBlocks(api, events, runId);
    return null;
  }
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  await act(async () => {
    root?.render(<Probe />);
    await tick();
  });
  return () => {
    if (latest === null) {
      throw new Error('the hook never rendered');
    }
    return latest;
  };
}

async function fire(listener: (() => void) | undefined): Promise<void> {
  if (listener === undefined) {
    throw new Error('the hook never subscribed to this event');
  }
  await act(async () => {
    listener();
    await tick();
  });
}

describe('usePluginBlocks', () => {
  it('reads the blocks of the open run on mount and returns them', async () => {
    const list = vi
      .fn<ListPluginBlocks>()
      .mockResolvedValue({ blocks: [block('deploys')] });
    const latest = await mount(apiWith(list), listenerBoard().events, 'run-1');
    expect(list).toHaveBeenCalledExactlyOnceWith({ runId: 'run-1' });
    expect(latest().map((b) => b.slug)).toEqual(['deploys']);
  });

  it('reads the list again on plugins_changed and returns the new one', async () => {
    const list = vi
      .fn<ListPluginBlocks>()
      .mockResolvedValueOnce({ blocks: [block('deploys')] })
      .mockResolvedValueOnce({ blocks: [block('deploys'), block('lint')] });
    const board = listenerBoard();
    const latest = await mount(apiWith(list), board.events, 'run-1');
    await fire(board.listeners.changed);
    expect(list).toHaveBeenCalledTimes(2);
    expect(latest().map((b) => b.slug)).toEqual(['deploys', 'lint']);
  });

  it('reads the list again after a reconnect', async () => {
    const list = vi
      .fn<ListPluginBlocks>()
      .mockResolvedValueOnce({ blocks: [block('deploys')] })
      .mockResolvedValueOnce({ blocks: [block('lint')] });
    const board = listenerBoard();
    const latest = await mount(apiWith(list), board.events, 'run-1');
    await fire(board.listeners.reconnect);
    expect(list).toHaveBeenCalledTimes(2);
    expect(latest().map((b) => b.slug)).toEqual(['lint']);
  });

  it('draws no blocks when the list cannot be read', async () => {
    const list = vi
      .fn<ListPluginBlocks>()
      .mockRejectedValue(new Error('daemon unreachable'));
    const latest = await mount(apiWith(list), listenerBoard().events, 'run-1');
    expect(latest()).toEqual([]);
  });

  it('draws no blocks once a re-read of a list it had drawn fails', async () => {
    const list = vi
      .fn<ListPluginBlocks>()
      .mockResolvedValueOnce({ blocks: [block('deploys')] })
      .mockRejectedValueOnce(new Error('daemon unreachable'));
    const board = listenerBoard();
    const latest = await mount(apiWith(list), board.events, 'run-1');
    expect(latest().map((b) => b.slug)).toEqual(['deploys']);
    await fire(board.listeners.changed);
    expect(latest()).toEqual([]);
  });

  it('unsubscribes from both events when it unmounts', async () => {
    const board = listenerBoard();
    const list = vi
      .fn<ListPluginBlocks>()
      .mockResolvedValue({ blocks: [block('deploys')] });
    await mount(apiWith(list), board.events, 'run-1');
    act(() => {
      root?.unmount();
    });
    root = null;
    expect(board.offChanged).toHaveBeenCalledTimes(1);
    expect(board.offReconnect).toHaveBeenCalledTimes(1);
  });
});
