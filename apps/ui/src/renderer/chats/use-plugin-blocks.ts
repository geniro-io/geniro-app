import { useEffect, useState } from 'react';

import type { PluginBlock, PluginsApi } from '../autogenerated';
import { useRunDaemonRead } from './use-run-daemon-read';

type Api = Pick<PluginsApi, 'listPluginBlocksForRun'>;

/** The two client events that move the list: a plugin file written, and a reconnect. */
export interface PluginBlocksEvents {
  onPluginsChanged: (listener: () => void) => () => void;
  onReconnect: (listener: () => void) => () => void;
}

const NONE: readonly PluginBlock[] = [];

const readBlocks = async (
  api: Api,
  runId: string,
): Promise<readonly PluginBlock[]> =>
  (await api.listPluginBlocksForRun({ runId })).blocks;

/**
 * The plugins whose folders take in the open thread's folder, read from the
 * daemon on open, on every `plugins_changed` and after a reconnect. A list
 * that cannot be read draws no blocks.
 */
export function usePluginBlocks(
  api: Api | null,
  events: PluginBlocksEvents | null,
  runId: string | null,
): readonly PluginBlock[] {
  const [trigger, setTrigger] = useState(0);
  useEffect(() => {
    if (events === null) {
      return;
    }
    const bump = (): void => setTrigger((current) => current + 1);
    const offChanged = events.onPluginsChanged(bump);
    const offReconnect = events.onReconnect(bump);
    return () => {
      offChanged();
      offReconnect();
    };
  }, [events]);
  return useRunDaemonRead(api, runId, trigger, readBlocks, NONE).value;
}
