import { useEffect, useRef, useState } from 'react';

import type { ChatsApi, ItemDto as ChatItem } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonClient } from '../daemon-client';
import { mergeAnchorRows } from './history-anchors';
import { payloadString } from './transcript-payload';

/** How many of a callee's newest messages its row on the card shows. */
export const RECENT_CALL_MESSAGES = 3;

/**
 * TWIN PARSER: what `ChatHistoryService.callMessages` keeps for the daemon's
 * read of these messages: the callee's own words, never a delegate's or a
 * person's, and never a row with no text.
 */
function isCalleeMessage(
  item: ChatItem,
  runId: string,
  callIds: readonly string[],
): boolean {
  return (
    item.runId === runId &&
    item.kind === 'message' &&
    item.role !== 'user' &&
    typeof item.inCall === 'string' &&
    callIds.includes(item.inCall) &&
    payloadString(item.payload, 'parentToolUseId') === null &&
    (payloadString(item.payload, 'text') ?? '').trim() !== ''
  );
}

export interface RecentCallMessages {
  messages: readonly ChatItem[];
  hasOlder: boolean;
  loading: boolean;
  failed: boolean;
  retry: () => void;
}

interface HeldMessages {
  messages: readonly ChatItem[];
  hasOlder: boolean;
}

function withMessages(
  held: HeldMessages,
  rows: readonly ChatItem[],
  older: boolean,
): HeldMessages {
  const merged = mergeAnchorRows(held.messages, rows);
  return {
    messages: merged.slice(-RECENT_CALL_MESSAGES),
    hasOlder: held.hasOlder || older || merged.length > RECENT_CALL_MESSAGES,
  };
}

/**
 * A conversation's newest messages, read from the daemon when the row opens and
 * kept up to date by the socket directly: the stream behind the transcript
 * stops taking rows while the reader is away from the tail.
 */
export function useRecentCallMessages({
  api,
  client,
  runId,
  callId,
  callIds,
}: {
  api: Pick<ChatsApi, 'listCallMessages'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
  runId: string;
  callId: string;
  callIds: readonly string[];
}): RecentCallMessages {
  const [held, setHeld] = useState<HeldMessages>({
    messages: [],
    hasOlder: false,
  });
  const [loading, setLoading] = useState(true);
  const [failed, setFailed] = useState(false);
  const generationRef = useRef(0);
  const callIdsRef = useRef(callIds);
  callIdsRef.current = callIds;
  const read = useLatestCallback((): void => {
    generationRef.current += 1;
    const generation = generationRef.current;
    setLoading(true);
    setFailed(false);
    api
      .listCallMessages({ runId, callId, limit: RECENT_CALL_MESSAGES })
      .then((page) => {
        if (generationRef.current === generation) {
          setHeld((prev) => withMessages(prev, page.messages, page.hasOlder));
          setLoading(false);
        }
      })
      .catch(() => {
        if (generationRef.current === generation) {
          setFailed(true);
          setLoading(false);
        }
      });
  }, [api, runId, callId]);
  useEffect(() => {
    read();
    const offItem = client.onItem((item) => {
      if (isCalleeMessage(item, runId, callIdsRef.current)) {
        setHeld((prev) => withMessages(prev, [item], false));
      }
    });
    const offReconnect = client.onReconnect(() => read());
    return () => {
      generationRef.current += 1;
      offItem();
      offReconnect();
    };
  }, [client, runId, read]);
  return { ...held, loading, failed, retry: read };
}
