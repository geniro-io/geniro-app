import { useEffect, useRef, useState } from 'react';

import type {
  ChatsApi,
  ReviewComment as ReviewCommentDto,
  TeamsApi,
} from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { describeDaemonError, isRunBusyError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { randomId } from '../random-id';
import { ACTION_RETRY_MS } from './use-chat-actions';
import { useRunDaemonRead } from './use-run-daemon-read';

export type ReviewComment = ReviewCommentDto;

export interface ReviewCommentInput {
  folder: string;
  path: string;
  side: ReviewComment['side'];
  startLine: number | null;
  endLine: number | null;
  quote: string;
  body: string;
}

export type ReviewSending = 'idle' | 'waiting' | 'sending';

export interface ReviewController {
  comments: ReviewComment[];
  error: string | null;
  add: (input: ReviewCommentInput) => Promise<void>;
  edit: (id: string, body: string) => Promise<void>;
  remove: (id: string) => Promise<void>;
  setStatus: (id: string, status: 'resolved' | 'sent') => Promise<void>;
  send: (note: string | null) => Promise<void>;
  sending: ReviewSending;
  cancelWaiting: () => void;
}

type Api = Pick<
  ChatsApi,
  | 'listReviewComments'
  | 'addReviewComment'
  | 'editReviewComment'
  | 'deleteReviewComment'
  | 'sendChatReview'
>;
type TeamApi = Pick<TeamsApi, 'sendTeamReview'>;
type Events = Pick<DaemonClient, 'onReviewCommentsChanged' | 'onReconnect'>;

interface PendingSend {
  clientMessageId: string;
  note: string | null;
}

const NONE: ReviewComment[] = [];

const readComments = async (
  api: Api,
  runId: string,
): Promise<ReviewComment[]> =>
  (await api.listReviewComments({ runId })).comments;

/**
 * The open thread's review comments, read from the daemon and re-read when it
 * announces a change. A review sent while the agent works waits for the turn
 * to end and goes out as its own turn; a `RUN_BUSY` is retried with the same
 * `clientMessageId`, which the daemon replays rather than sending twice.
 */
export function useReviewComments({
  api,
  teamApi,
  client,
  runId,
  agentWorking,
}: {
  api: Api | null;
  teamApi: TeamApi | null;
  client: Events | null;
  runId: string | null;
  agentWorking: boolean;
}): ReviewController {
  const [bump, setBump] = useState(0);
  const [error, setError] = useState<string | null>(null);
  const [sending, setSending] = useState<ReviewSending>('idle');
  const pending = useRef<PendingSend | null>(null);
  const refused = useRef(false);

  useEffect(() => {
    if (client === null || runId === null) {
      return;
    }
    const offChange = client.onReviewCommentsChanged((event) => {
      if (event.runId === runId) {
        setBump((n) => n + 1);
      }
    });
    const offReconnect = client.onReconnect(() => setBump((n) => n + 1));
    return () => {
      offChange();
      offReconnect();
    };
  }, [client, runId]);

  useEffect(() => {
    pending.current = null;
    refused.current = false;
    setSending('idle');
    setError(null);
  }, [runId]);

  const read = useRunDaemonRead(api, runId, bump, readComments, NONE);

  const write = useLatestCallback(
    async (action: (api: Api, runId: string) => Promise<unknown>) => {
      if (api === null || runId === null) {
        return;
      }
      try {
        await action(api, runId);
        setError(null);
      } catch (err) {
        setError(describeDaemonError(err));
        throw err;
      } finally {
        setBump((n) => n + 1);
      }
    },
    [api, runId],
  );

  const add = useLatestCallback(
    (input: ReviewCommentInput) =>
      write((client, id) =>
        client.addReviewComment({
          runId: id,
          createReviewCommentDto: input,
        }),
      ),
    [write],
  );
  const edit = useLatestCallback(
    (commentId: string, body: string) =>
      write((client, id) =>
        client.editReviewComment({
          runId: id,
          commentId,
          editReviewCommentDto: { body },
        }),
      ),
    [write],
  );
  const setStatus = useLatestCallback(
    (commentId: string, status: 'resolved' | 'sent') =>
      write((client, id) =>
        client.editReviewComment({
          runId: id,
          commentId,
          editReviewCommentDto: { status },
        }),
      ),
    [write],
  );
  const remove = useLatestCallback(
    (commentId: string) =>
      write((client, id) =>
        client.deleteReviewComment({ runId: id, commentId }),
      ),
    [write],
  );

  const deliver = useLatestCallback(
    async (request: PendingSend): Promise<void> => {
      if (api === null || runId === null) {
        return;
      }
      setSending('sending');
      const sendReviewDto = {
        clientMessageId: request.clientMessageId,
        note: request.note,
      };
      try {
        await (teamApi === null
          ? api.sendChatReview({ runId, sendReviewDto })
          : teamApi.sendTeamReview({ runId, sendReviewDto }));
        pending.current = null;
        refused.current = false;
        setSending('idle');
        setError(null);
      } catch (err) {
        if (isRunBusyError(err)) {
          refused.current = true;
          pending.current = request;
          setSending('waiting');
          return;
        }
        pending.current = null;
        setSending('idle');
        setError(describeDaemonError(err));
      } finally {
        setBump((n) => n + 1);
      }
    },
    [api, teamApi, runId],
  );

  const send = useLatestCallback(
    async (note: string | null): Promise<void> => {
      const request = { clientMessageId: randomId(), note };
      if (agentWorking) {
        pending.current = request;
        setSending('waiting');
        return;
      }
      await deliver(request);
    },
    [agentWorking, deliver],
  );

  const cancelWaiting = useLatestCallback((): void => {
    pending.current = null;
    refused.current = false;
    setSending('idle');
  }, []);

  const isTeam = teamApi !== null;
  useEffect(() => {
    if (sending !== 'waiting' || agentWorking) {
      return;
    }
    const timer = setTimeout(
      () => {
        if (pending.current !== null) {
          void deliver(pending.current);
        }
      },
      isTeam || refused.current ? ACTION_RETRY_MS : 0,
    );
    return () => clearTimeout(timer);
  }, [sending, agentWorking, isTeam, deliver]);

  return {
    comments: read.value,
    error,
    add,
    edit,
    remove,
    setStatus,
    send,
    sending,
    cancelWaiting,
  };
}
