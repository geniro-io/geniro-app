import { useEffect, useState } from 'react';

import type { ChatsApi, RunArtifact } from '../autogenerated';

export interface RunArtifactsState {
  /** Which chat these were read from — see the guard below for why. */
  runId: string | null;
  artifacts: readonly RunArtifact[];
}

const NONE: readonly RunArtifact[] = [];

/** No pages, and no claim about why — the resting state and the failure state. */
const NOTHING: RunArtifactsState = { runId: null, artifacts: NONE };

/**
 * The pages the open thread has published, newest first.
 *
 * Read from the DAEMON rather than folded from the transcript this component
 * already holds, for {@link useChatTimeline}'s reason: a long thread opens on
 * its newest `HISTORY_PAGE` items, so a local fold would silently drop an
 * artifact published earlier — indistinguishable from a thread that published
 * none, and the panel is the page's only stable entry point once its card has
 * scrolled away.
 *
 * ONE refresh trigger where the timeline needs three, and the difference is
 * what the list is OF. A marker is written per user message and a segment's
 * figures move while a turn runs; an artifact row is written when an agent
 * publishes, and nothing about an already-published page changes until it is
 * republished — which writes another row. So the newest artifact `seq` covers
 * every way this list can move, and it is monotonic within a thread and does
 * not move when older history pages in, so scrolling up costs no fetch.
 */
export function useRunArtifacts(
  api: Pick<ChatsApi, 'readRunArtifacts'> | null,
  runId: string | null,
  latestArtifactSeq: number,
): RunArtifactsState {
  const [state, setState] = useState<RunArtifactsState>(() => ({
    ...NOTHING,
    runId,
  }));

  useEffect(() => {
    if (api === null || runId === null) {
      setState({ ...NOTHING, runId });
      return;
    }
    let cancelled = false;
    void api
      .readRunArtifacts({ runId })
      .then((answer) => {
        if (!cancelled) {
          setState({ runId, artifacts: answer.artifacts });
        }
      })
      // A list that could not be read is a thread with no panel section, never
      // an error banner over a working conversation — the transcript still
      // holds every card, which is where the pages actually are.
      .catch(() => {
        if (!cancelled) {
          setState({ ...NOTHING, runId });
        }
      });
    return () => {
      cancelled = true;
    };
  }, [api, runId, latestArtifactSeq]);

  // They belong to the run they were read from. A thread switch renders once
  // before the effect above can replace them, so without this guard the new
  // thread's panel lists the previous conversation's pages — under the new
  // thread's name, which is the one place it cannot be recognised as stale.
  return state.runId === runId ? state : { ...NOTHING, runId };
}
