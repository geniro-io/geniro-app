// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ChatsApi, RunPullRequestOutcomes } from '../autogenerated';
import { type RunOutcomesState, useRunOutcomes } from './use-run-outcomes';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function pullRequest(number: number): RunPullRequestOutcomes {
  return {
    owner: 'acme',
    repo: 'platform',
    number,
    url: `https://github.com/acme/platform/pull/${number}`,
    changesRequestedRounds: 0,
    msToAccepted: null,
    outcomes: [],
  };
}

type Api = Pick<ChatsApi, 'readRunOutcomes'>;
type Read = Api['readRunOutcomes'];

/** One api object per read function, as `Chats` holds one per launch. */
const apis = new WeakMap<Read, Api>();
function apiOf(read: Read): Api {
  let api = apis.get(read);
  if (api === undefined) {
    api = { readRunOutcomes: read };
    apis.set(read, api);
  }
  return api;
}

let root: Root | null = null;
let seen: RunOutcomesState | null = null;

function Probe({
  read,
  runId,
  seq,
}: {
  read: Read;
  runId: string | null;
  seq: number;
}): null {
  seen = useRunOutcomes(apiOf(read), runId, seq);
  return null;
}

async function render(
  read: Read,
  runId: string | null,
  seq: number,
): Promise<void> {
  if (root === null) {
    root = createRoot(document.createElement('div'));
  }
  await act(async () => {
    root!.render(<Probe read={read} runId={runId} seq={seq} />);
  });
}

const numbers = (): number[] =>
  (seen?.pullRequests ?? []).map((pr) => pr.number);

afterEach(() => {
  act(() => root?.unmount());
  root = null;
  seen = null;
});

describe('useRunOutcomes', () => {
  it('re-reads when a newer outcome is announced, and not when nothing moved', async () => {
    const lists = [[pullRequest(87)], [pullRequest(90), pullRequest(87)]];
    const read = vi.fn(async () => ({ pullRequests: lists.shift() ?? [] }));

    await render(read as unknown as Read, 'run-1', 5);
    expect(numbers()).toEqual([87]);

    await render(read as unknown as Read, 'run-1', 5);
    expect(read).toHaveBeenCalledTimes(1);

    await render(read as unknown as Read, 'run-1', 9);
    expect(numbers()).toEqual([90, 87]);
    expect(read).toHaveBeenCalledTimes(2);
  });

  it('drops the previous thread’s outcomes on a switch, before the new read answers', async () => {
    let answerSecond: (value: {
      pullRequests: RunPullRequestOutcomes[];
    }) => void = () => {};
    const read = vi.fn(({ runId }: { runId: string }) =>
      runId === 'run-1'
        ? Promise.resolve({ pullRequests: [pullRequest(87)] })
        : new Promise<{ pullRequests: RunPullRequestOutcomes[] }>((resolve) => {
            answerSecond = resolve;
          }),
    );

    await render(read as unknown as Read, 'run-1', 0);
    expect(numbers()).toEqual([87]);

    await render(read as unknown as Read, 'run-2', 0);
    expect(numbers()).toEqual([]);

    await act(async () => {
      answerSecond({ pullRequests: [pullRequest(12)] });
    });
    expect(numbers()).toEqual([12]);
  });

  it('reads nothing without a run, and a failed re-read drops what it held', async () => {
    let fail = false;
    const read = vi.fn(async () => {
      if (fail) {
        throw new Error('daemon GET failed (500)');
      }
      return { pullRequests: [pullRequest(87)] };
    });

    await render(read as unknown as Read, null, 0);
    expect(read).not.toHaveBeenCalled();
    expect(seen?.loaded).toBe(false);

    await render(read as unknown as Read, 'run-1', 5);
    expect(numbers()).toEqual([87]);

    fail = true;
    await render(read as unknown as Read, 'run-1', 9);
    expect(numbers()).toEqual([]);
    expect(seen?.loaded).toBe(true);
  });
});
