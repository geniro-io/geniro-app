import type { ChatsApi, RunPullRequestOutcomes } from '../autogenerated';
import { useRunDaemonRead } from './use-run-daemon-read';

export interface RunOutcomesState {
  runId: string | null;
  pullRequests: readonly RunPullRequestOutcomes[];
  loaded: boolean;
}

type Api = Pick<ChatsApi, 'readRunOutcomes'>;

const NONE: readonly RunPullRequestOutcomes[] = [];

const readOutcomes = async (
  api: Api,
  runId: string,
): Promise<readonly RunPullRequestOutcomes[]> =>
  (await api.readRunOutcomes({ runId })).pullRequests;

/**
 * Every pull request outcome the open team run recorded, per pull request
 * with its whole history. Re-read on the newest outcome seq the run's
 * pull-request list carries, which every `record_outcome` that wrote a row
 * announces.
 */
export function useRunOutcomes(
  api: Api | null,
  runId: string | null,
  latestOutcomeSeq: number,
): RunOutcomesState {
  const read = useRunDaemonRead(
    api,
    runId,
    latestOutcomeSeq,
    readOutcomes,
    NONE,
  );
  return { runId: read.runId, pullRequests: read.value, loaded: read.loaded };
}
