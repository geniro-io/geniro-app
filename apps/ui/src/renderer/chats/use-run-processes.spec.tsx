// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { RunProcessesDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import {
  PROCESS_POLL_MS,
  type RunProcessesState,
  useRunProcesses,
} from './use-run-processes';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function dto(processes: number): RunProcessesDto {
  return {
    sampledAt: '2026-10-04T12:00:00.000Z',
    trees: [],
    processes,
    cpuPercent: 0,
    rssBytes: 0,
    unavailableReason: null,
  };
}

let root: Root | null = null;
let host: HTMLDivElement | null = null;
let seen: RunProcessesState | null = null;

function Probe({
  apis,
  runId,
  enabled,
}: {
  apis: DaemonApis;
  runId: string | null;
  enabled: boolean;
}): null {
  seen = useRunProcesses(apis, runId, enabled);
  return null;
}

function render(
  apis: DaemonApis,
  runId: string | null,
  enabled: boolean,
): void {
  if (root === null) {
    host = document.createElement('div');
    document.body.append(host);
    root = createRoot(host);
  }
  act(() => {
    root?.render(<Probe apis={apis} runId={runId} enabled={enabled} />);
  });
}

/** Let the read's promise chain — then/catch/finally — run to the end. */
async function flush(): Promise<void> {
  await act(async () => {
    for (let i = 0; i < 5; i += 1) {
      await Promise.resolve();
    }
  });
}

beforeEach(() => {
  vi.useFakeTimers();
});

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
  seen = null;
  vi.useRealTimers();
});

describe('useRunProcesses', () => {
  it('asks nothing while the panel is folded', () => {
    const read = vi.fn(() => Promise.resolve(dto(1)));
    render(
      { chats: { readRunProcesses: read } } as unknown as DaemonApis,
      'r',
      false,
    );
    expect(read).not.toHaveBeenCalled();
  });

  it('polls once the last reading has answered, and stops when the panel folds', async () => {
    let n = 0;
    const read = vi.fn(() => Promise.resolve(dto((n += 1))));
    const apis = { chats: { readRunProcesses: read } } as unknown as DaemonApis;
    render(apis, 'r', true);
    await flush();
    expect(seen?.data?.processes).toBe(1);

    await act(async () => {
      vi.advanceTimersByTime(PROCESS_POLL_MS);
    });
    await flush();
    expect(read).toHaveBeenCalledTimes(2);
    expect(seen?.data?.processes).toBe(2);

    render(apis, 'r', false);
    await act(async () => {
      vi.advanceTimersByTime(PROCESS_POLL_MS * 3);
    });
    expect(read).toHaveBeenCalledTimes(2);
  });

  it('keeps the last good reading on screen when one poll fails', async () => {
    const read = vi
      .fn()
      .mockResolvedValueOnce(dto(4))
      .mockRejectedValueOnce(new Error('daemon away'));
    const apis = { chats: { readRunProcesses: read } } as unknown as DaemonApis;
    render(apis, 'r', true);
    await flush();
    await act(async () => {
      vi.advanceTimersByTime(PROCESS_POLL_MS);
    });
    await flush();

    expect(seen?.data?.processes).toBe(4);
    expect(seen?.error).toMatch(/daemon away/);
  });

  it('drops the previous run’s reading on a switch', async () => {
    const read = vi.fn(() => new Promise<RunProcessesDto>(() => {}));
    read.mockImplementationOnce(() => Promise.resolve(dto(9)));
    const apis = { chats: { readRunProcesses: read } } as unknown as DaemonApis;
    render(apis, 'a', true);
    await flush();
    expect(seen?.data?.processes).toBe(9);

    render(apis, 'b', true);
    expect(seen?.data).toBeNull();
  });
});
