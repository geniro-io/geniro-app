import { useEffect, useState } from 'react';

import { FetchError, type RunProcessesDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';

export interface RunProcessesState {
  data: RunProcessesDto | null;
  loading: boolean;
  error: string | null;
}

/**
 * How often the reading is taken while it is on screen. CPU and memory move
 * second to second, and a `ps` of the whole machine costs the daemon a few
 * milliseconds — three seconds keeps the figures live without the panel
 * becoming the busiest thing it measures.
 */
export const PROCESS_POLL_MS = 3_000;

const READ_FAILURE = 'could not read this thread’s processes';

/** See `use-run-waterfall.ts`'s twin: the generated runtime hides the cause. */
function readFailure(err: unknown): string {
  const root = err instanceof FetchError ? err.cause : err;
  const detail = root instanceof Error ? root.message.trim() : '';
  return detail ? `${READ_FAILURE} — ${detail}` : READ_FAILURE;
}

/**
 * What this run has running right now, polled while `enabled`.
 *
 * Gated on `enabled` like the waterfall: a panel nobody unfolded must not have
 * the daemon reading the process table every few seconds. Each poll is
 * scheduled only once the previous one has answered, so a slow daemon cannot
 * pile requests up behind itself. A failed poll keeps the last good reading on
 * screen beside the error rather than blanking it — one dropped request is not
 * news that every process vanished.
 */
export function useRunProcesses(
  apis: DaemonApis | null,
  runId: string | null,
  enabled: boolean,
): RunProcessesState {
  const [data, setData] = useState<RunProcessesDto | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!apis || runId === null || !enabled) {
      return;
    }
    let cancelled = false;
    let timer: ReturnType<typeof setTimeout> | null = null;
    const poll = (): void => {
      apis.chats
        .readRunProcesses({ runId })
        .then((result) => {
          if (cancelled) {
            return;
          }
          setData(result);
          setError(null);
          setLoading(false);
        })
        .catch((err: unknown) => {
          if (cancelled) {
            return;
          }
          setError(readFailure(err));
          setLoading(false);
        })
        .finally(() => {
          if (!cancelled) {
            timer = setTimeout(poll, PROCESS_POLL_MS);
          }
        });
    };
    setLoading(true);
    poll();
    return () => {
      cancelled = true;
      if (timer !== null) {
        clearTimeout(timer);
      }
    };
  }, [apis, runId, enabled]);

  // After the poll effect, on the waterfall's rule: a switched-away run must
  // not leave its processes on screen under the next run's name.
  useEffect(() => {
    setData(null);
    setError(null);
  }, [runId]);

  return { data, loading, error };
}
