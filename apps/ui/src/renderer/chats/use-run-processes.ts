import { useCallback, useState } from 'react';

import type { RunProcessesDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { type PolledReadState, usePolledRead } from '../use-polled-read';

export { PROCESS_POLL_MS } from '../use-polled-read';

export type RunProcessesState = PolledReadState<RunProcessesDto> & {
  runId?: string | null;
  stopDetached?: (pids: number[], monitorIds?: string[]) => Promise<void>;
};

/**
 * What this run has running right now, polled while `enabled`.
 *
 * Gated on `enabled` like the waterfall: a panel nobody unfolded must not have
 * the daemon reading the process table every few seconds.
 */
export function useRunProcesses(
  apis: DaemonApis | null,
  runId: string | null,
  enabled: boolean,
): RunProcessesState {
  const [revision, setRevision] = useState(0);
  const stopDetached = useCallback(
    async (pids: number[], monitorIds: string[] = []): Promise<void> => {
      if (apis === null || runId === null) {
        throw new Error('no thread is open');
      }
      const result = await apis.chats.stopDetachedProcesses({
        runId,
        stopDetachedProcessesDto: {
          ...(pids.length > 0 ? { pids } : {}),
          ...(monitorIds.length > 0 ? { monitorIds } : {}),
        },
      });
      setRevision((value) => value + 1);
      if (
        pids.some((pid) => !result.stoppedPids.includes(pid)) ||
        monitorIds.some((id) => !result.stoppedMonitorIds.includes(id))
      ) {
        throw new Error(
          'Some selected processes could not be confirmed or stopped. Refresh and try again.',
        );
      }
    },
    [apis, runId],
  );
  const read = useCallback(
    (): Promise<RunProcessesDto> =>
      apis && runId !== null
        ? apis.chats.readRunProcesses({ runId })
        : Promise.reject(new Error('no thread is open')),
    [apis, runId, revision],
  );
  const state = usePolledRead(
    apis && runId !== null && enabled ? read : null,
    runId,
    'could not read this thread’s processes',
  );
  return { ...state, runId, stopDetached };
}
