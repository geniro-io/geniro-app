import { useCallback, useEffect, useState } from 'react';

import type { ChatsApi, OpenShell } from '../autogenerated';

const NONE: readonly OpenShell[] = [];

interface RunShellsState {
  /** Which run these were read from — see the guard below. */
  runId: string | null;
  shells: readonly OpenShell[];
}

const NOTHING: RunShellsState = { runId: null, shells: NONE };

/**
 * Every command the open run still has RUNNING, over the whole conversation.
 *
 * `shell-activity.ts` folds the same list from the loaded transcript, which is
 * the right shape for the rows it draws beside — and the wrong shape for the
 * question the shelf asks, because a chat opens on its newest `HISTORY_PAGE`
 * items and a command detached before that has no row there to fold. The run
 * row kept counting it, so the badge read `working` over an empty shelf.
 *
 * REPORTED as "я вижу, что в этом трейде у меня показывается статус `working`,
 * но нет ни одного терминала", and then, on being offered a chip that merely
 * ADMITTED the gap: "we simply need to show current shells and everything else
 * for entire conversation, not last 1000". So the list is read from the daemon,
 * which can fold what the client has not loaded — the same move
 * `useChatTimeline` makes, for the same reason.
 *
 * Refetched when the RUN's own count moves, which is the one signal that says
 * a command started or ended anywhere in the conversation — including in the
 * part nobody has loaded. Scrolling costs no fetch, and neither does a turn.
 *
 * It also hands back a `refresh`, for the one thing that count cannot see: a
 * command the USER stopped. A kill on a LIVE run does move it (the daemon takes
 * the shell out of the run's live tally), but the case this list exists for is
 * precisely the other one — a command left over from a conversation whose CLI
 * is long gone, where the run's count is already zero and the row is known only
 * to the daemon's own fold. Nothing there would ever change, so the press has
 * to ask again itself.
 */
export function useRunShells(
  api: Pick<ChatsApi, 'readChatShells'> | null,
  runId: string | null,
  shellsOpen: number,
): { shells: readonly OpenShell[]; refresh: () => void } {
  const [state, setState] = useState<RunShellsState>(() => ({
    ...NOTHING,
    runId,
  }));
  // Bumped by `refresh`, and in the dependency list below, so an explicit
  // re-read runs the same effect the count's own change does — one fetch path,
  // one place the guard against a stale answer lives.
  const [nonce, setNonce] = useState(0);
  const refresh = useCallback(() => setNonce((n) => n + 1), []);

  useEffect(() => {
    if (api === null || runId === null) {
      setState({ ...NOTHING, runId });
      return;
    }
    let cancelled = false;
    void api
      .readChatShells({ runId })
      .then((answer) => {
        if (!cancelled) {
          setState({ runId, shells: answer.shells });
        }
      })
      // A list that could not be read leaves the local fold standing, never an
      // error over a working conversation — `useChatTimeline`'s reading.
      .catch(() => {
        if (!cancelled) {
          setState({ ...NOTHING, runId });
        }
      });
    return () => {
      cancelled = true;
    };
  }, [api, runId, shellsOpen, nonce]);

  // Belongs to the run it was read from: a thread switch renders once before
  // the effect can replace it, and the previous conversation's commands under
  // the new thread's name is the one place they cannot be recognised as stale.
  return { shells: state.runId === runId ? state.shells : NONE, refresh };
}
