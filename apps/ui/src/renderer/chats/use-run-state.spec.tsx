// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { ItemDto as ChatItem, RunStateDto } from '../autogenerated';
import type { DaemonClient, RunStatusEvent } from '../daemon-client';
import { REREAD_DELAY_MS, useRunState } from './use-run-state';

(
  globalThis as unknown as { IS_REACT_ACT_ENVIRONMENT: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const state = (calls: number): RunStateDto => ({
  openRequests: [],
  calls: Array.from({ length: calls }, (_, index) => ({
    callId: `call-${index}`,
    callerNodeId: null,
    calleeNodeId: null,
    title: null,
    brief: null,
    mode: null,
    thread: null,
    startSeq: index,
    startedAt: 'now',
    endedAt: null,
    status: 'running' as const,
    member: null,
  })),
  delegates: [],
  workflowRows: [],
  artifactRows: [],
  shells: [],
  turnStartedAt: null,
});

let root: Root | null = null;
// The re-read batch is a timer; drive it rather than wait it out.
beforeEach(() => {
  vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] });
});
afterEach(() => {
  act(() => root?.unmount());
  root = null;
  vi.useRealTimers();
});

function harness(runId: string) {
  const items = new Set<(item: ChatItem) => void>();
  const statuses = new Set<(event: RunStatusEvent) => void>();
  const client = {
    onItem: (l: (item: ChatItem) => void) => {
      items.add(l);
      return () => items.delete(l);
    },
    onRunStatus: (l: (event: RunStatusEvent) => void) => {
      statuses.add(l);
      return () => statuses.delete(l);
    },
  } as unknown as DaemonClient;
  const api = {
    readRunState: vi.fn((_args: { runId: string }): Promise<RunStateDto> =>
      Promise.resolve(state(1)),
    ),
  };
  let latest: RunStateDto | null = null;
  function Probe({ id, nonce }: { id: string | null; nonce: number }): null {
    latest = useRunState(api, client, id, nonce).state;
    return null;
  }
  const container = document.createElement('div');
  root = createRoot(container);
  return {
    api,
    render: async (id: string | null, nonce = 0) => {
      await act(async () => root!.render(<Probe id={id} nonce={nonce} />));
    },
    state: () => latest!,
    emitItem: (item: Partial<ChatItem>) =>
      items.forEach((l) => l({ runId, ...item } as ChatItem)),
    emitStatus: (event: Partial<RunStatusEvent>) =>
      statuses.forEach((l) => l({ runId, status: null, ...event })),
  };
}

const settle = () =>
  act(async () => {
    await vi.advanceTimersByTimeAsync(REREAD_DELAY_MS);
  });

describe('useRunState', () => {
  it('reads the open run’s state', async () => {
    const h = harness('r1');
    await h.render('r1');
    expect(h.state().calls).toHaveLength(1);
    expect(h.api.readRunState).toHaveBeenCalledWith({ runId: 'r1' });
  });

  it('re-reads after a structural row, once per burst — and never for an activity announce', async () => {
    const h = harness('r1');
    await h.render('r1');
    const before = h.api.readRunState.mock.calls.length;

    // Socket rows arrive as separate tasks; the timer is what makes them one.
    await act(async () => {
      h.emitItem({ kind: 'call_result' });
      await vi.advanceTimersByTimeAsync(REREAD_DELAY_MS - 1);
    });
    await act(async () => {
      h.emitItem({ kind: 'subagent_info' });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before + 1);

    await act(async () => {
      h.emitStatus({ activity: 'running Bash' });
      h.emitItem({ kind: 'message' });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before + 1);

    await act(async () => {
      h.emitStatus({ status: 'completed' });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before + 2);
  });

  it('re-reads when a delegate is launched — a sync one declares nothing', async () => {
    const h = harness('r1');
    await h.render('r1');
    const before = h.api.readRunState.mock.calls.length;

    await act(async () => {
      h.emitItem({ kind: 'tool_call', payload: { id: 't1', name: 'Bash' } });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before);

    await act(async () => {
      h.emitItem({ kind: 'tool_call', payload: { id: 't2', name: 'Task' } });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before + 1);
  });

  it('re-reads on an artifact publish, and on the reply to a delegate it lists', async () => {
    const h = harness('r1');
    h.api.readRunState.mockResolvedValue({
      ...state(0),
      delegates: [
        {
          id: 'toolu_d',
          nodeId: null,
          callId: null,
          label: null,
          kind: null,
          status: 'running',
          launchSeq: 1,
          startedAt: 'now',
        },
      ],
    });
    await h.render('r1');
    const before = h.api.readRunState.mock.calls.length;

    await act(async () => {
      h.emitItem({ kind: 'tool_result', payload: { id: 'toolu_other' } });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before);

    await act(async () => {
      h.emitItem({ kind: 'tool_result', payload: { id: 'toolu_d' } });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before + 1);

    await act(async () => {
      h.emitItem({
        kind: 'tool_call',
        payload: { id: 'a1', name: 'Artifact' },
      });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before + 2);
  });

  it('re-reads on the reply to an artifact or a workflow it lists — the reply is what carries the URL', async () => {
    const listedRow = (id: string, name: string): ChatItem => ({
      id: `row-${id}`,
      runId: 'r1',
      nodeId: null,
      seq: 1,
      kind: 'tool_call',
      role: null,
      payload: { id, name },
      createdAt: 'now',
    });
    const h = harness('r1');
    h.api.readRunState.mockResolvedValue({
      ...state(0),
      artifactRows: [listedRow('a1', 'Artifact')],
      workflowRows: [listedRow('wf1', 'Workflow')],
    });
    await h.render('r1');
    const before = h.api.readRunState.mock.calls.length;

    await act(async () => {
      h.emitItem({ kind: 'tool_result', payload: { id: 'a1' } });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before + 1);

    await act(async () => {
      h.emitItem({ kind: 'tool_result', payload: { id: 'wf1' } });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before + 2);
  });

  it('re-reads when a reply lands while the read that first lists its call is still out', async () => {
    // A sync delegate can answer within the re-read's own round trip: the read
    // then lists it running, and its reply came before anything listed it.
    const h = harness('r1');
    await h.render('r1');
    const before = h.api.readRunState.mock.calls.length;
    // Every later read still lists the delegate, as the daemon's does (it
    // lists every delegate), so only the reset on asking ends the re-reads.
    const delegate = {
      id: 'toolu_d',
      nodeId: null,
      callId: null,
      label: null,
      kind: null,
      status: 'completed' as const,
      launchSeq: 1,
      startedAt: 'now',
    };
    h.api.readRunState.mockResolvedValue({
      ...state(0),
      delegates: [delegate],
    });
    let land: (state: RunStateDto) => void = () => undefined;
    h.api.readRunState.mockImplementationOnce(
      () =>
        new Promise<RunStateDto>((resolve) => {
          land = resolve;
        }),
    );

    await act(async () => {
      h.emitItem({
        kind: 'tool_call',
        payload: { id: 'toolu_d', name: 'Task' },
      });
    });
    await settle();
    expect(h.api.readRunState.mock.calls.length).toBe(before + 1);

    await act(async () => {
      h.emitItem({ kind: 'tool_result', payload: { id: 'toolu_d' } });
    });
    await act(async () => {
      land({
        ...state(0),
        delegates: [
          {
            id: 'toolu_d',
            nodeId: null,
            callId: null,
            label: null,
            kind: null,
            status: 'running',
            launchSeq: 1,
            startedAt: 'now',
          },
        ],
      });
    });
    await settle();

    expect(h.api.readRunState.mock.calls.length).toBe(before + 2);
  });

  it('re-reads on a reconnect — a socket that dropped missed every trigger', async () => {
    const h = harness('r1');
    await h.render('r1', 0);
    const before = h.api.readRunState.mock.calls.length;

    await h.render('r1', 1);

    expect(h.api.readRunState.mock.calls.length).toBe(before + 1);
  });

  it('answers empty for a newly opened run until its own read lands', async () => {
    const h = harness('r1');
    await h.render('r1');
    expect(h.state().calls).toHaveLength(1);
    h.api.readRunState.mockImplementation(() => new Promise(() => undefined));

    await h.render('r2');

    expect(h.state().calls).toEqual([]);
  });

  it('ignores a structural row from another run', async () => {
    const h = harness('r1');
    await h.render('r1');
    const before = h.api.readRunState.mock.calls.length;

    await act(async () => {
      h.emitItem({ runId: 'r9', kind: 'call_result' });
    });
    await settle();

    expect(h.api.readRunState.mock.calls.length).toBe(before);
  });
});
