// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ChatsApi, TeamNote } from '../autogenerated';
import { type RunTeamNotesState, useRunTeamNotes } from './use-run-team-notes';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function note(seq: number, text: string): TeamNote {
  return {
    seq,
    kind: 'fact',
    text,
    nodeId: 'engineer',
    conversationId: null,
    callId: null,
    createdAt: '2026-10-26T09:00:00.000Z',
    supersedes: null,
    supersededBy: null,
  };
}

type Api = Pick<ChatsApi, 'readRunTeamNotes'>;
type Read = Api['readRunTeamNotes'];

/** One api object per read function, as `Chats` holds one per launch. */
const apis = new WeakMap<Read, Api>();
function apiOf(read: Read): Api {
  let api = apis.get(read);
  if (api === undefined) {
    api = { readRunTeamNotes: read };
    apis.set(read, api);
  }
  return api;
}

let root: Root | null = null;
let container: HTMLDivElement | null = null;
let seen: RunTeamNotesState | null = null;

function Probe({
  read,
  runId,
  seq,
}: {
  read: Read;
  runId: string | null;
  seq: number;
}): null {
  seen = useRunTeamNotes(apiOf(read), runId, seq);
  return null;
}

async function render(
  read: Read,
  runId: string | null,
  seq: number,
): Promise<void> {
  if (root === null) {
    container = document.createElement('div');
    root = createRoot(container);
  }
  await act(async () => {
    root!.render(<Probe read={read} runId={runId} seq={seq} />);
  });
}

const texts = (): string[] => (seen?.notes ?? []).map((n) => n.text);

afterEach(() => {
  act(() => root?.unmount());
  root = null;
  container = null;
  seen = null;
});

describe('useRunTeamNotes', () => {
  it('re-reads when a newer note row arrives, and not when nothing moved', async () => {
    const lists = [[note(5, 'first')], [note(9, 'second'), note(5, 'first')]];
    const read = vi.fn(async () => ({ notes: lists.shift() ?? [] }));

    await render(read as unknown as Read, 'run-1', 5);
    expect(texts()).toEqual(['first']);

    await render(read as unknown as Read, 'run-1', 5);
    expect(read).toHaveBeenCalledTimes(1);

    await render(read as unknown as Read, 'run-1', 9);
    expect(texts()).toEqual(['second', 'first']);
    expect(read).toHaveBeenCalledTimes(2);
  });

  it('drops the previous thread’s notes on a switch, before the new read answers', async () => {
    let answerSecond: (value: { notes: TeamNote[] }) => void = () => {};
    const read = vi.fn(({ runId }: { runId: string }) =>
      runId === 'run-1'
        ? Promise.resolve({ notes: [note(5, 'from run 1')] })
        : new Promise<{ notes: TeamNote[] }>((resolve) => {
            answerSecond = resolve;
          }),
    );

    await render(read as unknown as Read, 'run-1', 0);
    expect(texts()).toEqual(['from run 1']);

    await render(read as unknown as Read, 'run-2', 0);
    expect(texts()).toEqual([]);

    await act(async () => {
      answerSecond({ notes: [note(3, 'from run 2')] });
    });
    expect(texts()).toEqual(['from run 2']);
  });

  it('reads nothing without a run, and a failed re-read drops the notes it held', async () => {
    let fail = false;
    const read = vi.fn(async () => {
      if (fail) {
        throw new Error('daemon GET failed (500)');
      }
      return { notes: [note(5, 'held')] };
    });

    await render(read as unknown as Read, null, 0);
    expect(read).not.toHaveBeenCalled();
    expect(seen?.loaded).toBe(false);

    await render(read as unknown as Read, 'run-1', 5);
    expect(texts()).toEqual(['held']);
    expect(seen?.loaded).toBe(true);

    fail = true;
    await render(read as unknown as Read, 'run-1', 9);
    expect(texts()).toEqual([]);
    expect(seen?.loaded).toBe(true);
  });
});
