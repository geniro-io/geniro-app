import type { ChatsApi, TeamNote } from '../autogenerated';
import { useRunDaemonRead } from './use-run-daemon-read';

export interface RunTeamNotesState {
  /** Which run these were read from. */
  runId: string | null;
  notes: readonly TeamNote[];
  /**
   * Whether a read of this run has answered (a failed one included) — what
   * tells the notes a thread opened with from notes arriving while it is open.
   */
  loaded: boolean;
}

type Api = Pick<ChatsApi, 'readRunTeamNotes'>;

const NONE: readonly TeamNote[] = [];

const readNotes = async (
  api: Api,
  runId: string,
): Promise<readonly TeamNote[]> =>
  (await api.readRunTeamNotes({ runId })).notes;

/**
 * Every team note of the open team run, newest first, superseded ones
 * marked. Re-read on the newest `team_note` seq the window and the open call
 * cards hold: a note is append-only, so a new row is the only way the list
 * moves.
 */
export function useRunTeamNotes(
  api: Api | null,
  runId: string | null,
  latestTeamNoteSeq: number,
): RunTeamNotesState {
  const read = useRunDaemonRead(api, runId, latestTeamNoteSeq, readNotes, NONE);
  return { runId: read.runId, notes: read.value, loaded: read.loaded };
}
