import { useEffect, useState } from 'react';

import type { ChatsApi, TeamNote } from '../autogenerated';

export interface RunTeamNotesState {
  /** Which run these were read from — see the guard below. */
  runId: string | null;
  notes: readonly TeamNote[];
  /**
   * Whether a read of this run has answered (a failed one included) — what
   * tells the notes a thread opened with from notes arriving while it is open.
   */
  loaded: boolean;
}

const NONE: readonly TeamNote[] = [];

/** No notes, and no read answered yet — the resting state. */
const NOTHING: RunTeamNotesState = { runId: null, notes: NONE, loaded: false };

/**
 * Every team note of the open workflow run, newest first, superseded ones
 * marked.
 *
 * Read from the DAEMON, on {@link useRunArtifacts}' reason: the window holds
 * one page of the transcript, and a note written early in a long run would
 * silently drop out of a local fold. Its one refresh trigger is the newest
 * `team_note` seq the window and the open call cards hold: a note is
 * append-only, so a new row is the only way the list moves.
 */
export function useRunTeamNotes(
  api: Pick<ChatsApi, 'readRunTeamNotes'> | null,
  runId: string | null,
  latestTeamNoteSeq: number,
): RunTeamNotesState {
  const [state, setState] = useState<RunTeamNotesState>(() => ({
    ...NOTHING,
    runId,
  }));

  useEffect(() => {
    if (api === null || runId === null) {
      setState({ ...NOTHING, runId });
      return;
    }
    let cancelled = false;
    void api
      .readRunTeamNotes({ runId })
      .then((answer) => {
        if (!cancelled) {
          setState({ runId, notes: answer.notes, loaded: true });
        }
      })
      // A list that could not be read draws no section, never an error over
      // a working run: the transcript still holds every note row.
      .catch(() => {
        if (!cancelled) {
          setState({ runId, notes: NONE, loaded: true });
        }
      });
    return () => {
      cancelled = true;
    };
  }, [api, runId, latestTeamNoteSeq]);

  // A thread switch renders once before the effect replaces the list, so
  // without this the new thread would show the previous run's notes.
  return state.runId === runId ? state : { ...NOTHING, runId };
}
