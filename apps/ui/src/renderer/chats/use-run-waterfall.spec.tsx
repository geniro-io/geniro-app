// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { FetchError, type RunWaterfallDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { type RunWaterfallState, useRunWaterfall } from './use-run-waterfall';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function dto(from: string): RunWaterfallDto {
  return {
    from,
    to: from,
    lanes: [],
    toolUse: [],
    turns: [],
    calls: [],
    waits: [],
    delegates: [],
    totals: {
      turns: 0,
      costedTurns: 0,
      costUsd: null,
      inputTokens: null,
      outputTokens: null,
      cacheReadTokens: null,
      cacheCreationTokens: null,
      thinkingTokens: null,
      workedMs: null,
    },
    waitedOnUserMs: null,
    partialReason: null,
  };
}

let root: Root | null = null;
let host: HTMLDivElement | null = null;
/** The newest state the hook produced — what a consumer would be rendering. */
let seen: RunWaterfallState | null = null;

function Probe({
  apis,
  runId,
  enabled,
}: {
  apis: DaemonApis | null;
  runId: string | null;
  enabled: boolean;
}): null {
  seen = useRunWaterfall(apis, runId, enabled);
  return null;
}

function mount(
  apis: DaemonApis | null,
  runId: string | null,
  enabled: boolean,
): void {
  host = document.createElement('div');
  document.body.append(host);
  root = createRoot(host);
  act(() => {
    root?.render(<Probe apis={apis} runId={runId} enabled={enabled} />);
  });
}

function rerender(
  apis: DaemonApis | null,
  runId: string | null,
  enabled: boolean,
): void {
  act(() => {
    root?.render(<Probe apis={apis} runId={runId} enabled={enabled} />);
  });
}

/**
 * A client whose reads this test settles by hand.
 *
 * One pending pair PER CALL, not one shared pair: the switch-away race needs
 * the FIRST read resolved while a second is already in flight, and a single
 * pair silently resolves the newest instead — which passes while proving
 * nothing.
 */
function client(): {
  apis: DaemonApis;
  read: ReturnType<typeof vi.fn>;
  settle: (value: RunWaterfallDto, at?: number) => Promise<void>;
  fail: (err: unknown, at?: number) => Promise<void>;
} {
  const pending: {
    resolve: (value: RunWaterfallDto) => void;
    reject: (err: unknown) => void;
  }[] = [];
  const read = vi.fn(
    () =>
      new Promise<RunWaterfallDto>((resolve, reject) => {
        pending.push({ resolve, reject });
      }),
  );
  return {
    apis: { chats: { readRunWaterfall: read } } as unknown as DaemonApis,
    read,
    settle: async (value, at = pending.length - 1) => {
      await act(async () => {
        pending[at]?.resolve(value);
        await Promise.resolve();
      });
    },
    fail: async (err, at = pending.length - 1) => {
      await act(async () => {
        pending[at]?.reject(err);
        await Promise.resolve();
      });
    },
  };
}

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
  seen = null;
});

describe('useRunWaterfall', () => {
  it('asks nothing while the card that draws it is not on screen', async () => {
    // The whole reason the gate exists: the daemon walks the run's entire spine
    // to answer, so a folded panel must cost nothing.
    const { apis, read } = client();
    mount(apis, 'run-a', false);

    expect(read).not.toHaveBeenCalled();
    expect(seen?.loading).toBe(false);
  });

  it('reads once the card is on screen, and reports the figures', async () => {
    const { apis, read, settle } = client();
    mount(apis, 'run-a', true);
    expect(read).toHaveBeenCalledWith({ runId: 'run-a' });
    expect(seen?.loading).toBe(true);

    await settle(dto('2026-09-07T12:00:00.000Z'));

    expect(seen?.data?.from).toBe('2026-09-07T12:00:00.000Z');
    expect(seen?.loading).toBe(false);
  });

  it('never leaves one run’s figures standing under another run’s name', async () => {
    const { apis, settle } = client();
    mount(apis, 'run-a', true);
    await settle(dto('2026-09-07T12:00:00.000Z'));
    expect(seen?.data).not.toBeNull();

    rerender(apis, 'run-b', true);

    // Cleared the moment the run changes — before run-b's own read resolves.
    expect(seen?.data).toBeNull();
  });

  it('drops a read that resolves after its run was switched away from', async () => {
    // The slow-answer race: without the latch the previous run's figures land
    // on top of the new run's.
    const { apis, settle } = client();
    mount(apis, 'run-a', true);
    rerender(apis, 'run-b', true);

    // run-a's own read, answering late while run-b's is still out.
    await settle(dto('2026-01-01T00:00:00.000Z'), 0);

    expect(seen?.data).toBeNull();
  });

  it('says what actually failed, not the generated runtime’s boilerplate', async () => {
    // A `FetchError` carries a sentence about interceptors; the cause is the
    // part a reader can act on.
    const { apis, fail } = client();
    mount(apis, 'run-a', true);

    await fail(
      new FetchError(
        new Error('The user aborted a request.'),
        'The request failed and the interceptors did not return an alternative response',
      ),
    );

    expect(seen?.error).toContain('The user aborted a request.');
    expect(seen?.error).not.toContain('interceptors');
    expect(seen?.loading).toBe(false);
  });

  it('still says something when the failure carries no message', async () => {
    const { apis, fail } = client();
    mount(apis, 'run-a', true);

    await fail('not an error at all');

    expect(seen?.error).toBe('could not read this run');
  });
});
