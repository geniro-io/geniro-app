import { useEffect, useState } from 'react';

import { FetchError, type RunWaterfallDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';

export interface RunWaterfallState {
  data: RunWaterfallDto | null;
  loading: boolean;
  error: string | null;
}

/** Shown when the read failed with nothing more useful to say. */
const READ_FAILURE = 'could not read this run';

/**
 * Why the read failed, in words a reader can act on.
 *
 * The generated runtime wraps a transport failure in a `FetchError` whose own
 * message is boilerplate about interceptors, so the cause has to be unwrapped
 * before it is shown — the same unwrap `use-agent-mcp.ts` documents for the
 * same reason.
 */
function readFailure(err: unknown): string {
  const root = err instanceof FetchError ? err.cause : err;
  const detail = root instanceof Error ? root.message.trim() : '';
  return detail ? `${READ_FAILURE} — ${detail}` : READ_FAILURE;
}

/**
 * One run folded into money, order and timing — read on demand.
 *
 * Gated on `enabled` like `use-agent-mcp`, and for the same kind of reason: the
 * daemon walks the run's whole spine to answer, so a card nobody has on screen
 * must not pay for it. The read is not live either — a waterfall is a picture
 * of what a run DID, and re-folding it on every streamed token would cost the
 * run's full spine per token.
 */
export function useRunWaterfall(
  apis: DaemonApis | null,
  runId: string | null,
  enabled: boolean,
): RunWaterfallState {
  const [data, setData] = useState<RunWaterfallDto | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!apis || runId === null || !enabled) {
      return;
    }
    let cancelled = false;
    setLoading(true);
    setError(null);
    apis.chats
      .readRunWaterfall({ runId })
      .then((result) => {
        if (!cancelled) {
          setData(result);
          setLoading(false);
        }
      })
      .catch((err: unknown) => {
        if (cancelled) {
          return;
        }
        setError(readFailure(err));
        setLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [apis, runId, enabled]);

  // Declared AFTER the read effect so it runs after it in the same commit: a
  // run the user switched away from must not leave its predecessor's figures on
  // screen under the new run's name while the next read is in flight.
  useEffect(() => {
    setData(null);
    setError(null);
  }, [runId]);

  return { data, loading, error };
}
