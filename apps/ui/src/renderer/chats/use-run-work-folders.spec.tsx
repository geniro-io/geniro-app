// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ChatsApi } from '../autogenerated';
import { useRunWorkFolders } from './use-run-work-folders';

const REPO = '/repo';
const OWN = '/repo/.claude/worktrees/cw-1256-padding';
const SIBLING = '/repo/.claude/worktrees/cw-1257-copy';
const STARTED_AT = '2026-10-15T10:00:00.000Z';

type Api = Pick<ChatsApi, 'readRunNamedPaths'>;

let root: Root | null = null;
let container: HTMLDivElement | null = null;
let latest: readonly string[] = [];

afterEach(() => {
  act(() => root?.unmount());
  container?.remove();
  root = null;
  container = null;
  vi.unstubAllGlobals();
});

function Probe(props: { api: Api; runId: string; streaming: boolean }): null {
  latest = useRunWorkFolders(
    props.api,
    props.runId,
    REPO,
    STARTED_AT,
    props.streaming,
  );
  return null;
}

/** Render (or re-render) and let every pending read settle. */
async function show(props: Parameters<typeof Probe>[0]): Promise<void> {
  if (root === null) {
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
  }
  await act(async () => {
    root?.render(<Probe {...props} />);
  });
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
  });
}

const namedBy = (named: string[][]) => {
  const answers = [...named];
  return vi.fn<Api['readRunNamedPaths']>(async () => ({
    named: answers.shift() ?? [],
  }));
};

describe('useRunWorkFolders', () => {
  it('asks the daemon about the worktrees main lists and keeps only the ones the run names', async () => {
    vi.stubGlobal('geniro', { listWorktrees: async () => [OWN, SIBLING] });
    const readRunNamedPaths = namedBy([[OWN]]);

    await show({
      api: { readRunNamedPaths },
      runId: 'run-a',
      streaming: false,
    });

    expect(readRunNamedPaths).toHaveBeenCalledWith({
      runId: 'run-a',
      namedPathsDto: { paths: [OWN, SIBLING] },
    });
    expect(latest).toEqual([OWN]);
  });

  it('asks main only for worktrees made since the thread started', async () => {
    // A worktree older than the thread belongs to another thread or task,
    // however often this one mentions it.
    const listWorktrees = vi.fn(async () => [OWN]);
    vi.stubGlobal('geniro', { listWorktrees });

    await show({
      api: { readRunNamedPaths: namedBy([[OWN]]) },
      runId: 'run-a',
      streaming: false,
    });

    expect(listWorktrees).toHaveBeenCalledWith(REPO, Date.parse(STARTED_AT));
  });

  it('asks once when a thread is opened mid-turn, then again as the turn ends', async () => {
    // An earlier turn may already have made a worktree, so a running thread is
    // asked on open; the turn ending is the next moment one can have appeared.
    const listWorktrees = vi.fn(async () => [OWN]);
    vi.stubGlobal('geniro', { listWorktrees });
    const readRunNamedPaths = namedBy([[OWN]]);
    const api = { readRunNamedPaths };

    await show({ api, runId: 'run-a', streaming: true });
    expect(listWorktrees).toHaveBeenCalledTimes(1);
    expect(latest).toEqual([OWN]);

    await show({ api, runId: 'run-b', streaming: true });
    await show({ api, runId: 'run-a', streaming: true });
    expect(listWorktrees).toHaveBeenCalledTimes(3);

    await show({ api, runId: 'run-a', streaming: false });
    expect(listWorktrees).toHaveBeenCalledTimes(4);
  });

  it('adds a folder found later to the ones it holds, and asks only about the rest', async () => {
    vi.stubGlobal('geniro', { listWorktrees: async () => [OWN, SIBLING] });
    const readRunNamedPaths = namedBy([[OWN], [SIBLING]]);
    const api = { readRunNamedPaths };

    await show({ api, runId: 'run-a', streaming: false });
    await show({ api, runId: 'run-a', streaming: true });
    await show({ api, runId: 'run-a', streaming: false });

    expect(readRunNamedPaths).toHaveBeenLastCalledWith({
      runId: 'run-a',
      namedPathsDto: { paths: [SIBLING] },
    });
    expect(latest).toEqual([OWN, SIBLING]);
  });

  it('keeps the thread on screen from taking a slower answer about the one before it', async () => {
    vi.stubGlobal('geniro', { listWorktrees: async () => [OWN, SIBLING] });
    let releaseRunA: (named: string[]) => void = () => {};
    const readRunNamedPaths = vi.fn<Api['readRunNamedPaths']>(
      async ({ runId }) =>
        runId === 'run-a'
          ? new Promise((resolve) => {
              releaseRunA = (named) => resolve({ named });
            })
          : { named: [SIBLING] },
    );
    const api = { readRunNamedPaths };

    await show({ api, runId: 'run-a', streaming: false });
    await show({ api, runId: 'run-b', streaming: false });
    await act(async () => {
      releaseRunA([OWN]);
      await Promise.resolve();
    });

    expect(latest).toEqual([SIBLING]);
  });

  it('asks about more worktrees than one question carries in turns, dropping none', async () => {
    const many = Array.from({ length: 70 }, (_, at) => `/repo/wt/${at}`);
    vi.stubGlobal('geniro', { listWorktrees: async () => many });
    const readRunNamedPaths = vi.fn<Api['readRunNamedPaths']>(
      async ({ namedPathsDto }) => ({
        named: namedPathsDto.paths.filter((path) => path === many[69]),
      }),
    );

    await show({
      api: { readRunNamedPaths },
      runId: 'run-a',
      streaming: false,
    });
    await act(async () => {
      await Promise.resolve();
    });

    expect(
      readRunNamedPaths.mock.calls.map(
        ([ask]) => ask.namedPathsDto.paths.length,
      ),
    ).toEqual([64, 6]);
    expect(latest).toEqual([many[69]]);
  });

  it('starts another thread with none of the previous thread’s folders', async () => {
    vi.stubGlobal('geniro', { listWorktrees: async () => [OWN, SIBLING] });
    const readRunNamedPaths = namedBy([[OWN], [SIBLING]]);
    const api = { readRunNamedPaths };

    await show({ api, runId: 'run-a', streaming: false });
    await show({ api, runId: 'run-b', streaming: false });

    expect(latest).toEqual([SIBLING]);
  });

  it('answers none when the daemon cannot be asked', async () => {
    vi.stubGlobal('geniro', { listWorktrees: async () => [OWN] });
    const readRunNamedPaths = vi.fn<Api['readRunNamedPaths']>(async () => {
      throw new Error('daemon GET failed (503)');
    });

    await show({
      api: { readRunNamedPaths },
      runId: 'run-a',
      streaming: false,
    });

    expect(latest).toEqual([]);
  });
});
