import { useEffect, useRef, useState } from 'react';

import type { ChatsApi } from '../autogenerated';

const NONE: readonly string[] = [];

/** TWIN: the daemon's `MAX_NAMED_PATHS_PER_ASK` (`dto/chat.dto.ts`); more go in turns. */
const CANDIDATES_PER_ASK = 64;

/**
 * The other folders this thread's agents worked in — worktrees of the run
 * folder's repository that the run's own tool calls name.
 *
 * Read when the thread opens and whenever a turn ends, which is when an agent
 * can have made one. Only ever ADDS: a folder this thread worked in stays its
 * folder, and a worktree removed later drops out of the changes read instead.
 */
export function useRunWorkFolders(
  api: Pick<ChatsApi, 'readRunNamedPaths'> | null,
  runId: string | null,
  cwd: string | null,
  /** When the thread started (ISO) — a worktree made before it is not its own. */
  startedAt: string | null,
  streaming: boolean,
): readonly string[] {
  const [found, setFound] = useState<{
    runId: string | null;
    folders: readonly string[];
  }>({ runId: null, folders: NONE });
  const generation = useRef(0);
  // Read inside the effect without being one of its triggers: a folder found
  // is never asked about again.
  const foundRef = useRef(found);
  useEffect(() => {
    foundRef.current = found;
  }, [found]);

  // The run asked about last: a thread opened mid-turn is asked once on open,
  // then again only as each turn ends.
  const askedFor = useRef<string | null>(null);

  useEffect(() => {
    const startedAtMs = startedAt === null ? Number.NaN : Date.parse(startedAt);
    if (
      api === null ||
      runId === null ||
      cwd === null ||
      Number.isNaN(startedAtMs) ||
      (streaming && askedFor.current === runId)
    ) {
      return;
    }
    askedFor.current = runId;
    const mine = (generation.current += 1);
    void (async () => {
      const held =
        foundRef.current.runId === runId ? foundRef.current.folders : NONE;
      const candidates = (
        await window.geniro.listWorktrees(cwd, startedAtMs)
      ).filter((folder) => !held.includes(folder));
      const named: string[] = [];
      for (let at = 0; at < candidates.length; at += CANDIDATES_PER_ASK) {
        const answer = await api.readRunNamedPaths({
          runId,
          namedPathsDto: {
            paths: candidates.slice(at, at + CANDIDATES_PER_ASK),
          },
        });
        named.push(...answer.named);
      }
      if (generation.current !== mine || named.length === 0) {
        return;
      }
      setFound((prev) => {
        const held = prev.runId === runId ? prev.folders : NONE;
        const added = named.filter((folder) => !held.includes(folder));
        return added.length === 0 && prev.runId === runId
          ? prev
          : { runId, folders: [...held, ...added] };
      });
    })().catch(() => {
      // Fail toward the folder alone: the chip then states the run folder's
      // own changes, which is what it showed before work folders existed.
    });
  }, [api, runId, cwd, startedAt, streaming]);

  return found.runId === runId ? found.folders : NONE;
}
