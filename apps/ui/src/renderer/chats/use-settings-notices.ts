import { useEffect, useMemo, useRef, useState } from 'react';

import type { SettingsNotice } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { isRemoteRuntime } from '../remote/remote-session';
import { useCliAttention } from '../settings/use-cli-attention';
import { useUpdateState } from '../updates/use-update-state';
import { useCliLogin } from '../use-cli-login';
import {
  ON_SHARES,
  readMemoryFindings,
  readWaitingShares,
  reportedNoticeReadings,
  shareWaitsByPlace,
  useConfigProfiles,
} from './settings-attention';
import type { SettingsNoticesStore } from './settings-notices-context';
import { ON_MEMORY, useWaitingSet } from './use-waiting-items';

/** The manager's notices by id while `active`, re-read on their change announce and after a reconnect. */
function useNoticeList(
  apis: DaemonApis,
  client: DaemonClient | null,
  active: boolean,
): {
  notices: ReadonlyMap<string, SettingsNotice> | null;
  adopt: (notice: SettingsNotice) => void;
} {
  const [notices, setNotices] = useState<ReadonlyMap<
    string,
    SettingsNotice
  > | null>(null);
  const generation = useRef(0);

  const reload = useLatestCallback(() => {
    const mine = ++generation.current;
    void apis.commandCenter.listCommandCenterNotices().then(
      ({ notices: list }) => {
        if (mine === generation.current) {
          setNotices(new Map(list.map((notice) => [notice.id, notice])));
        }
      },
      () => undefined,
    );
  }, [apis]);

  const adopt = useLatestCallback((notice: SettingsNotice) => {
    setNotices((known) => new Map(known ?? []).set(notice.id, notice));
  }, []);

  useEffect(() => {
    if (!active) {
      generation.current += 1;
      return;
    }
    reload();
    if (client === null) {
      return;
    }
    const offChanged = client.onCommandCenterChanged((event) => {
      if (event.reason === 'notices') {
        reload();
      }
    });
    const offConnected = client.onReconnect(reload);
    return () => {
      generation.current += 1;
      offChanged();
      offConnected();
    };
  }, [active, client, reload]);

  return { notices, adopt };
}

/**
 * Everything the manager chat's Settings notice rows draw from: the notices
 * the daemon keeps, and the same live readings Settings draws. The desktop
 * window also reports what Electron main reads — the Geniro update and the
 * agent CLIs — so the daemon opens and closes their notices.
 */
export function useSettingsNotices({
  apis,
  client,
  active,
  onOpenMemoryConflicts,
  remote = isRemoteRuntime(),
}: {
  apis: DaemonApis;
  client: DaemonClient | null;
  active: boolean;
  onOpenMemoryConflicts: (() => void) | null;
  remote?: boolean;
}): SettingsNoticesStore {
  const cli = useCliAttention();
  const { refresh } = cli;
  useEffect(() => {
    if (active) {
      refresh(false);
    }
  }, [active, refresh]);
  const login = useCliLogin(apis, () => refresh(true));
  const update = useUpdateState();
  const profiles = useConfigProfiles();
  const shares = useWaitingSet(
    apis,
    client,
    active && !remote,
    readWaitingShares,
    ON_SHARES,
  );
  const findings = useWaitingSet(
    apis,
    client,
    active,
    readMemoryFindings,
    ON_MEMORY,
  );
  const { notices, adopt } = useNoticeList(apis, client, active);

  const readings = reportedNoticeReadings(cli.detections, update.state);
  const readingsKey = JSON.stringify(readings);
  const report = useLatestCallback(() => {
    void apis.commandCenter
      .reportCommandCenterNoticeReadings({
        settingsNoticeReadingsDto: { readings },
      })
      .catch(() => undefined);
  }, [apis, readings]);
  useEffect(() => {
    if (active && !remote && readingsKey !== '[]') {
      report();
    }
  }, [active, remote, readingsKey, report]);

  const dismiss = useLatestCallback(
    (noticeId: string) => {
      void apis.commandCenter
        .dismissCommandCenterNotice({ noticeId })
        .then(adopt, () => undefined);
    },
    [apis, adopt],
  );

  const shareWaits = useMemo(
    () =>
      shares.items === null ? [] : shareWaitsByPlace(shares.items.values()),
    [shares.items],
  );
  const conflictIds = useMemo(
    () => (findings.items === null ? [] : [...findings.items.keys()]),
    [findings.items],
  );
  return useMemo(
    () => ({
      apis,
      notices,
      dismiss,
      detections: cli.detections,
      cliUpdates: cli.updates,
      login,
      update,
      profiles,
      shareWaits,
      conflictIds,
      onOpenMemoryConflicts,
      remote,
    }),
    [
      apis,
      notices,
      dismiss,
      cli.detections,
      cli.updates,
      login,
      update,
      profiles,
      shareWaits,
      conflictIds,
      onOpenMemoryConflicts,
      remote,
    ],
  );
}
