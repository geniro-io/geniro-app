import { createContext, useEffect, useRef, useState } from 'react';

import type { ChatsApi, SurfaceDto, TeamsApi } from '../autogenerated';
import { useDebouncedPersist } from '../components/use-debounced-persist';
import { useLatestCallback } from '../components/use-latest-callback';
import {
  daemonErrorCode,
  describeDaemonError,
  isRunBusyError,
} from '../daemon-api';
import { randomId } from '../random-id';
import { overlayDrafts } from './a2ui-model';
import { ACTION_RETRY_MS } from './use-chat-actions';

export type SurfaceApi = Pick<
  ChatsApi,
  'readSurface' | 'saveSurfaceDrafts' | 'readSurfaceMedia' | 'pressChatSurface'
>;

/** What a card drawn deep in the transcript reaches for, provided by `Chats`. */
export interface SurfaceHost {
  runId: string;
  api: SurfaceApi;
  /** A team run presses through its own route; null for a chat. */
  teamPress: Pick<TeamsApi, 'pressTeamSurface'> | null;
  /** The newest version the daemon's run state names for each card. */
  versions: ReadonlyMap<string, number>;
  /** A chat's turn is open: a press refused RUN_BUSY goes again once it is not. */
  turnOpen: boolean;
  /** A hosted surface's own step before a press starts a turn, and its word on how it ended. */
  beforePress: (() => Promise<unknown>) | null;
  pressSettled: ((taken: boolean) => void) | null;
}

export const SurfaceHostContext = createContext<SurfaceHost | null>(null);

export type SurfacePressPhase =
  | { kind: 'idle' }
  | { kind: 'pressing'; componentId: string }
  | { kind: 'waiting'; componentId: string }
  | { kind: 'sent'; componentId: string }
  | { kind: 'error'; componentId: string; message: string };

interface PendingPress {
  componentId: string;
  userMessage: string | null;
  context: Record<string, unknown>;
  clientMessageId: string;
}

export interface SurfaceState {
  surface: SurfaceDto | null;
  error: string | null;
  /** The data model as drawn: the agent's, then saved values, then what is typed now. */
  model: unknown;
  /** Pointers the agent wrote over a value the user had entered. */
  highlighted: ReadonlySet<string>;
  phase: SurfacePressPhase;
  setValue: (pointer: string, value: unknown, secret: boolean) => void;
  press: (
    componentId: string,
    userMessage: string | null,
    context: Record<string, unknown>,
  ) => void;
  readMedia: (file: string) => Promise<{ mediaType: string; data: string }>;
}

function covers(outer: string, inner: string): boolean {
  return inner === outer || inner.startsWith(`${outer === '/' ? '' : outer}/`);
}

function withoutWritten(
  values: Record<string, unknown>,
  written: readonly string[],
): Record<string, unknown> {
  return Object.fromEntries(
    Object.entries(values).filter(
      ([pointer]) => !written.some((outer) => covers(outer, pointer)),
    ),
  );
}

export function useSurface(host: SurfaceHost, surfaceId: string): SurfaceState {
  const [surface, setSurface] = useState<SurfaceDto | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [edits, setEdits] = useState<Record<string, unknown>>({});
  const [secrets, setSecrets] = useState<ReadonlySet<string>>(new Set());
  const [phase, setPhase] = useState<SurfacePressPhase>({ kind: 'idle' });
  const pending = useRef<PendingPress | null>(null);
  const surfaceRef = useRef<SurfaceDto | null>(null);
  surfaceRef.current = surface;
  const { runId, api } = host;

  const adopt = useLatestCallback((next: SurfaceDto): void => {
    const previous = surfaceRef.current;
    surfaceRef.current = next;
    setSurface(next);
    if (previous !== null && next.version > previous.version) {
      setEdits((current) => withoutWritten(current, next.agentWrites));
    }
  }, []);

  const reread = useLatestCallback(async (): Promise<SurfaceDto | null> => {
    try {
      const next = await api.readSurface({ runId, surfaceId });
      adopt(next);
      setError(null);
      return next;
    } catch (err) {
      setError(describeDaemonError(err));
      return null;
    }
  }, []);

  const known = host.versions.get(surfaceId) ?? 0;
  useEffect(() => {
    if (surfaceRef.current === null || known > surfaceRef.current.version) {
      void reread();
    }
  }, [known, reread, runId, surfaceId]);

  const save = useLatestCallback(
    async (changes: Record<string, unknown>): Promise<void> => {
      const current = surfaceRef.current;
      if (current === null || Object.keys(changes).length === 0) {
        return;
      }
      try {
        adopt(
          await api.saveSurfaceDrafts({
            runId,
            surfaceId,
            saveSurfaceDraftsDto: { version: current.version, changes },
          }),
        );
      } catch (err) {
        if (daemonErrorCode(err) !== 'UI_SURFACE_CHANGED') {
          throw err;
        }
        const fresh = await reread();
        if (fresh === null) {
          return;
        }
        const kept = withoutWritten(changes, fresh.agentWrites);
        if (Object.keys(kept).length > 0) {
          adopt(
            await api.saveSurfaceDrafts({
              runId,
              surfaceId,
              saveSurfaceDraftsDto: { version: fresh.version, changes: kept },
            }),
          );
        }
      }
    },
    [],
  );
  const persist = useDebouncedPersist(save);

  const setValue = useLatestCallback(
    (pointer: string, value: unknown, secret: boolean): void => {
      const next = { ...edits, [pointer]: value };
      setEdits(next);
      if (secret) {
        setSecrets((current) => new Set([...current, pointer]));
        return;
      }
      persist.schedule(
        Object.fromEntries(
          Object.entries(next).filter(([key]) => !secrets.has(key)),
        ),
      );
    },
    [],
  );

  const send = useLatestCallback(async (press: PendingPress): Promise<void> => {
    setPhase({ kind: 'pressing', componentId: press.componentId });
    const body = {
      sourceComponentId: press.componentId,
      changes: edits,
      userMessage: press.userMessage,
      context: press.context,
      clientMessageId: press.clientMessageId,
    };
    try {
      await host.beforePress?.();
      const next =
        host.teamPress === null
          ? await api.pressChatSurface({
              runId,
              surfaceId,
              pressSurfaceDto: body,
            })
          : await host.teamPress.pressTeamSurface({
              runId,
              surfaceId,
              pressSurfaceDto: body,
            });
      pending.current = null;
      adopt(next);
      setEdits((current) =>
        Object.fromEntries(
          Object.entries(current).filter(([pointer]) => !secrets.has(pointer)),
        ),
      );
      setPhase({ kind: 'sent', componentId: press.componentId });
      host.pressSettled?.(true);
    } catch (err) {
      if (isRunBusyError(err)) {
        pending.current = press;
        setPhase({ kind: 'waiting', componentId: press.componentId });
        return;
      }
      pending.current = null;
      host.pressSettled?.(false);
      if (daemonErrorCode(err) === 'UI_ALREADY_PRESSED') {
        void reread();
      }
      setPhase({
        kind: 'error',
        componentId: press.componentId,
        message: describeDaemonError(err),
      });
    }
  }, []);

  const press = useLatestCallback(
    (
      componentId: string,
      userMessage: string | null,
      context: Record<string, unknown>,
    ): void => {
      void send({
        componentId,
        userMessage,
        context,
        clientMessageId: randomId(),
      });
    },
    [],
  );

  const isTeam = host.teamPress !== null;
  useEffect(() => {
    if (phase.kind !== 'waiting') {
      return;
    }
    if (!isTeam && host.turnOpen) {
      return;
    }
    const timer = setTimeout(
      () => {
        if (pending.current !== null) {
          void send(pending.current);
        }
      },
      isTeam ? ACTION_RETRY_MS : 0,
    );
    return () => clearTimeout(timer);
  }, [phase, isTeam, host.turnOpen, send]);

  const readMedia = useLatestCallback(async (file: string) => {
    const read = await api.readSurfaceMedia({ runId, file });
    return { mediaType: read.mediaType, data: read.data };
  }, []);

  const model =
    surface === null
      ? {}
      : overlayDrafts(overlayDrafts(surface.dataModel, surface.drafts), edits);
  return {
    surface,
    error,
    model,
    highlighted: new Set(surface?.overriddenDrafts ?? []),
    phase,
    setValue,
    press,
    readMedia,
  };
}
