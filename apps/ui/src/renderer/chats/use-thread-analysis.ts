import { useEffect, useState } from 'react';

import type { RunDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { runStatusRowFields } from './run-status-row';

/**
 * What a thread's Analyze button says about its analysis: none yet, one that
 * is idle, one working, or one waiting on the user (a question or an approval
 * — `save_workflow_change` asks).
 */
export type ThreadAnalysisMark = 'none' | 'idle' | 'working' | 'waiting';

type Reading = Pick<RunDto, 'id' | 'status' | 'awaiting'> | null;

/**
 * Whether a run is itself an analysis — of a thread, or of a workflow across
 * its runs. An analysis is never analysed in turn.
 */
export function isAnalysisRun(
  run: Pick<RunDto, 'analysisSourceRunId' | 'analysisWorkflowSlug'>,
): boolean {
  return run.analysisSourceRunId != null || run.analysisWorkflowSlug != null;
}

/** The mark one reading of the analysis row makes. */
export function analysisMarkOf(reading: Reading): ThreadAnalysisMark {
  if (reading === null) {
    return 'none';
  }
  if (reading.awaiting != null) {
    return 'waiting';
  }
  return reading.status === 'running' ? 'working' : 'idle';
}

/**
 * The open thread's analysis, as its Analyze button marks it.
 *
 * The analysis is never on the sidebar, so nothing else would say that one is
 * working or waiting once its popup is closed. Read when the thread opens and
 * whenever `refreshKey` moves (the popup closing, an analysis starting), then
 * kept current from the analysis run's own status announces.
 */
export function useThreadAnalysis({
  chatApi,
  client,
  sourceRunId,
  refreshKey,
}: {
  chatApi: DaemonApis['chats'] | null;
  client: DaemonClient | null;
  /** The thread on screen, or null when none is (or it is itself an analysis). */
  sourceRunId: string | null;
  refreshKey: number;
}): ThreadAnalysisMark {
  const [reading, setReading] = useState<{
    source: string;
    row: Reading;
  } | null>(null);

  useEffect(() => {
    if (chatApi === null || sourceRunId === null) {
      return;
    }
    let live = true;
    void chatApi
      .getThreadAnalysis({ runId: sourceRunId })
      .then(({ analysis }) => {
        if (live) {
          setReading({ source: sourceRunId, row: analysis ?? null });
        }
      })
      // A thread that cannot be asked about shows no mark; the button still
      // opens the setup dialog, which says what is wrong.
      .catch(() => {
        if (live) {
          setReading({ source: sourceRunId, row: null });
        }
      });
    return () => {
      live = false;
    };
  }, [chatApi, sourceRunId, refreshKey]);

  const analysisId = reading?.row?.id ?? null;
  useEffect(() => {
    if (client === null || analysisId === null) {
      return;
    }
    return client.onRunStatus((event) => {
      if (event.runId !== analysisId) {
        return;
      }
      const fields = runStatusRowFields(event);
      setReading((current) =>
        current === null || current.row === null
          ? current
          : {
              ...current,
              row: {
                ...current.row,
                ...(fields.status === undefined
                  ? {}
                  : { status: fields.status }),
                ...(fields.awaiting === undefined
                  ? {}
                  : { awaiting: fields.awaiting }),
              },
            },
      );
    });
  }, [client, analysisId]);

  // A reading taken for another thread says nothing about this one.
  return analysisMarkOf(
    reading !== null && reading.source === sourceRunId ? reading.row : null,
  );
}
