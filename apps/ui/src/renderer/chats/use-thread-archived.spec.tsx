// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { RunDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import type { ThreadArchived } from './thread-done-context';
import { useThreadArchived } from './use-thread-archived';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;
let latest: ThreadArchived | null;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  latest = null;
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function Probe({
  apis,
  client,
  runIds,
}: {
  apis: DaemonApis | null;
  client: DaemonClient;
  runIds: readonly string[] | null;
}): null {
  latest = useThreadArchived(apis, client, runIds);
  return null;
}

function fakeClient() {
  const changed = new Set<(runs: RunDto[]) => void>();
  const reconnect = new Set<() => void>();
  const client = {
    onRunsChanged: (listener: (runs: RunDto[]) => void) => {
      changed.add(listener);
      return () => changed.delete(listener);
    },
    onReconnect: (listener: () => void) => {
      reconnect.add(listener);
      return () => reconnect.delete(listener);
    },
  } as unknown as DaemonClient;
  return {
    client,
    announce: (runs: Partial<RunDto>[]) =>
      changed.forEach((listener) => listener(runs as RunDto[])),
    reconnect: () => reconnect.forEach((listener) => listener()),
  };
}

type Answer = Promise<RunDto[]>;

function fakeApis(archivedAt: Record<string, string | null>) {
  const listChats = vi.fn(async ({ runId }: { runId: string }): Answer =>
    runId in archivedAt
      ? [{ id: runId, archivedAt: archivedAt[runId] } as RunDto]
      : [],
  );
  const listTeamRuns = vi.fn(async (): Answer => []);
  const apis = {
    chats: { listChats },
    teams: { listTeamRuns },
  } as unknown as DaemonApis;
  return { apis, listChats, listTeamRuns };
}

async function render(
  apis: DaemonApis | null,
  client: DaemonClient,
  runIds: readonly string[] | null,
): Promise<void> {
  await act(async () => {
    root.render(<Probe apis={apis} client={client} runIds={runIds} />);
  });
}

describe('useThreadArchived', () => {
  it('reads each named run once, in the all scope, and answers every archivedAt together', async () => {
    const { apis, listChats } = fakeApis({
      a: '2026-11-20T10:00:00Z',
      b: null,
    });
    const { client } = fakeClient();
    await render(apis, client, ['a', 'b']);

    expect(latest?.get('a')).toBe('2026-11-20T10:00:00Z');
    expect(latest?.get('b')).toBeNull();
    expect(listChats).toHaveBeenCalledTimes(2);
    expect(listChats).toHaveBeenCalledWith({ scope: 'all', runId: 'a' });

    await render(apis, client, ['b', 'a']);
    expect(listChats).toHaveBeenCalledTimes(2);
  });

  it('reads only the runs it has not read when a new one is named', async () => {
    const { apis, listChats } = fakeApis({
      a: null,
      c: '2026-11-21T00:00:00Z',
    });
    const { client } = fakeClient();
    await render(apis, client, ['a']);
    await render(apis, client, ['a', 'c']);

    expect(listChats).toHaveBeenCalledTimes(2);
    expect(latest?.get('c')).toBe('2026-11-21T00:00:00Z');
  });

  it('reads nothing and answers null with no run ids or no daemon', async () => {
    const { apis, listChats } = fakeApis({});
    const { client } = fakeClient();
    await render(apis, client, null);
    expect(latest).toBeNull();
    await render(null, client, ['a']);
    expect(latest).toBeNull();
    expect(listChats).not.toHaveBeenCalled();
  });

  it('follows the archive and unarchive announce of a named run, and ignores other runs', async () => {
    const { apis } = fakeApis({ a: null });
    const { client, announce } = fakeClient();
    await render(apis, client, ['a']);

    await act(async () => {
      announce([
        { id: 'a', archivedAt: '2026-11-22T00:00:00Z' },
        { id: 'zzz', archivedAt: '2026-11-22T00:00:00Z' },
      ]);
    });
    expect(latest?.get('a')).toBe('2026-11-22T00:00:00Z');
    expect(latest?.has('zzz')).toBe(false);

    await act(async () => {
      announce([{ id: 'a', archivedAt: null }]);
    });
    expect(latest?.get('a')).toBeNull();
  });

  it('reads every run again after a reconnect', async () => {
    const archivedAt: Record<string, string | null> = { a: null };
    const { apis, listChats } = fakeApis(archivedAt);
    const { client, reconnect } = fakeClient();
    await render(apis, client, ['a']);

    archivedAt.a = '2026-11-23T00:00:00Z';
    await act(async () => reconnect());

    expect(listChats).toHaveBeenCalledTimes(2);
    expect(latest?.get('a')).toBe('2026-11-23T00:00:00Z');
  });

  it('drops a read that was asked before a newer announce of the same run', async () => {
    let release: (runs: RunDto[]) => void = () => undefined;
    const listChats = vi.fn(
      () =>
        new Promise<RunDto[]>((resolve) => {
          release = resolve;
        }),
    );
    const apis = {
      chats: { listChats },
      teams: { listTeamRuns: vi.fn(async () => []) },
    } as unknown as DaemonApis;
    const { client, announce } = fakeClient();
    await render(apis, client, ['a']);

    await act(async () => {
      announce([{ id: 'a', archivedAt: '2026-11-24T00:00:00Z' }]);
    });
    await act(async () => {
      release([{ id: 'a', archivedAt: null } as RunDto]);
    });

    expect(latest?.get('a')).toBe('2026-11-24T00:00:00Z');
  });
});
