import { useEffect, useRef, useState } from 'react';

import type { RunDto } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { readRunById } from './read-run';
import type { ThreadArchived } from './thread-done-context';

/**
 * When each of `runIds` was archived, read from the daemon (the run lists have
 * no read of several ids, so each id is read once and the answers land
 * together) and kept in step with the daemon's `runs_changed` announce, which
 * carries the re-filed rows. Everything is read again after a reconnect. An
 * answer that was asked before a newer announce of its run is dropped.
 */
export function useThreadArchived(
  apis: DaemonApis | null,
  client: DaemonClient | null,
  runIds: readonly string[] | null,
): ThreadArchived | null {
  const [archived, setArchived] = useState<ThreadArchived>(new Map());
  const announces = useRef(new Map<string, number>());
  const clock = useRef(0);
  const known = useRef(new Set<string>());
  const wanted = useRef<ReadonlySet<string>>(new Set());
  wanted.current = new Set(runIds ?? []);
  const active = apis !== null && runIds !== null;
  const key = runIds === null ? null : [...runIds].sort().join('\n');

  const read = useLatestCallback(
    (ids: readonly string[]): void => {
      if (apis === null || ids.length === 0) {
        return;
      }
      const startedAt = ++clock.current;
      void Promise.all(
        ids.map(async (id): Promise<[string, string | null] | null> => {
          try {
            const run = await readRunById(apis.chats, apis.teams, id);
            return [id, run?.archivedAt ?? null];
          } catch {
            return null;
          }
        }),
      ).then((answers) => {
        const fresh = answers.filter(
          (answer): answer is [string, string | null] =>
            answer !== null &&
            (announces.current.get(answer[0]) ?? 0) < startedAt,
        );
        if (fresh.length === 0) {
          return;
        }
        for (const [id] of fresh) {
          known.current.add(id);
        }
        setArchived((prev) => new Map([...prev, ...fresh]));
      });
    },
    [apis],
  );

  useEffect(() => {
    if (!active) {
      return;
    }
    read([...wanted.current].filter((id) => !known.current.has(id)));
  }, [active, key, read]);

  useEffect(() => {
    if (client === null || !active) {
      return;
    }
    const offChanged = client.onRunsChanged((runs: RunDto[]) => {
      const mine = runs.filter((run) => wanted.current.has(run.id));
      if (mine.length === 0) {
        return;
      }
      const at = ++clock.current;
      for (const run of mine) {
        announces.current.set(run.id, at);
        known.current.add(run.id);
      }
      setArchived(
        (prev) =>
          new Map([
            ...prev,
            ...mine.map((run) => [run.id, run.archivedAt] as const),
          ]),
      );
    });
    const offConnected = client.onReconnect(() => read([...wanted.current]));
    return () => {
      offChanged();
      offConnected();
    };
  }, [client, active, read]);

  return active ? archived : null;
}
