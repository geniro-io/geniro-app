// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type {
  PullRequestInfo,
  PullRequestRefResult,
} from '../../shared/contracts';
import type { DisplayedPullRequest, RunPullRequest } from '../autogenerated';
import { ThreadPullRequestChips } from './composer-shelf';
import {
  AGENTS_PANEL_COLLAPSED_FLAG,
  THREAD_PULL_REQUESTS_SETTLED_FLAG,
} from './panel-flags';
import { readThreadFlag, ThreadUiMemoryContext } from './thread-ui-memory';
import {
  changesPullRequestsOf,
  currentThreadPullRequest,
  refOf,
  rowPullRequestOf,
  threadPullRequestsOf,
} from './use-thread-pull-requests';

const row = (repo: string, number: number, seq: number): RunPullRequest => ({
  owner: 'acme',
  repo,
  number,
  url: `https://github.com/acme/${repo}/pull/${number}`,
  seq,
});

describe('changesPullRequestsOf', () => {
  const info: PullRequestInfo = {
    number: 7,
    title: 'Stacked',
    state: 'open',
    isDraft: false,
    headRefName: 'feature/top',
    headRefOid: 'a'.repeat(40),
    baseRefName: 'feature/stack',
    isCrossRepository: false,
    headRepositoryOwner: 'acme',
    author: 'someone',
    url: 'https://github.com/acme/platform/pull/7',
    updatedAt: '2026-11-06T00:00:00Z',
    added: null,
    removed: null,
    changedFiles: null,
  };
  const result = (
    pullRequest: PullRequestInfo | null,
  ): PullRequestRefResult => ({
    ref: refOf(row('platform', 7, 1)),
    pullRequest,
  });

  it('keeps what a read needs of an open pull request', () => {
    expect(changesPullRequestsOf([result(info)])).toEqual([
      {
        repository: 'acme/platform',
        headRefName: 'feature/top',
        headRefOid: 'a'.repeat(40),
        baseRefName: 'feature/stack',
      },
    ]);
  });

  it('leaves out what cannot set a folder’s base', () => {
    const { baseRefName: _unread, ...noBase } = info;

    expect(
      changesPullRequestsOf([
        result(null),
        result(noBase),
        result({ ...info, state: 'merged' }),
        result({ ...info, state: 'closed' }),
        result({ ...info, isCrossRepository: true }),
      ]),
    ).toEqual([]);
  });
});

describe('threadPullRequestsOf', () => {
  it('reads newest FIRST, though the row stores them oldest first', () => {
    // The row is a capture log ordered by when the thread opened them; a panel
    // is read top-down and the last thing a thread did is what its author came
    // looking for.
    const run = {
      pullRequests: [row('platform', 74, 1), row('platform', 87, 9)],
    };
    expect(
      threadPullRequestsOf(run, new Map()).map((r) => r.ref.number),
    ).toEqual([87, 74]);
  });

  it('still yields the pull request when GitHub answered nothing about it', () => {
    // The thread demonstrably opened it. A list built only from resolved
    // answers would make it vanish on a machine with no `gh` — which is the
    // failure the whole capture path exists to end, arrived at from the UI.
    const run = { pullRequests: [row('platform', 87, 1)] };
    const [only] = threadPullRequestsOf(run, new Map());
    expect(only?.pullRequest).toBeNull();
    expect(only?.ref.url).toBe('https://github.com/acme/platform/pull/87');
  });

  it('drops the transcript seq on its way to the Electron channel', () => {
    // A MAPPING, not a cast: `seq` is a transcript position and means nothing
    // outside the daemon.
    expect(refOf(row('platform', 87, 12))).toEqual({
      owner: 'acme',
      repo: 'platform',
      number: 87,
      url: 'https://github.com/acme/platform/pull/87',
    });
  });

  it('answers empty for a run row that carries no pull requests at all', () => {
    // Reached with rows from `run_status` broadcasts and hand-built fixtures,
    // where the field can be absent; throwing here takes the chat pane down.
    expect(threadPullRequestsOf({}, new Map())).toEqual([]);
    expect(threadPullRequestsOf(null, new Map())).toEqual([]);
  });
});

describe('ThreadPullRequestChips', () => {
  let container: HTMLElement;
  let root: Root;

  const render = (results: PullRequestRefResult[]): void => {
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
    act(() => {
      root.render(
        <ThreadUiMemoryContext.Provider value="run-1">
          <ThreadPullRequestChips results={results} />
        </ThreadUiMemoryContext.Provider>,
      );
    });
  };

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    localStorage.clear();
  });

  const result = (
    repo: string,
    number: number,
    state: PullRequestInfo['state'] | null = null,
  ): PullRequestRefResult => ({
    ref: refOf(row(repo, number, number)),
    pullRequest:
      state === null
        ? null
        : ({
            number,
            title: `work on ${repo}`,
            url: `https://github.com/acme/${repo}/pull/${number}`,
            state,
            isDraft: false,
            headRefName: 'feat/x',
            isCrossRepository: false,
            headRepositoryOwner: 'acme',
            author: 'someone',
            updatedAt: '2026-08-01T00:00:00Z',
            added: null,
            removed: null,
            changedFiles: null,
          } satisfies PullRequestInfo),
  });

  const trigger = (): HTMLButtonElement | null =>
    container.querySelector<HTMLButtonElement>(
      '[data-slot="thread-pull-requests"] button',
    );
  const listed = (): string[] =>
    [
      ...container.querySelectorAll(
        '[data-slot="thread-pull-request-list"] [data-slot="pull-request-list-detail"]',
      ),
    ].map((detail) => detail.textContent ?? '');

  it('draws a lone pull request as its own chip, linking to it', () => {
    render([result('platform', 87, 'open')]);

    const chips = [
      ...container.querySelectorAll<HTMLAnchorElement>(
        '[data-slot="pull-request-chip"]',
      ),
    ];
    expect(chips).toHaveLength(1);
    expect(chips[0]?.textContent).toContain('#87');
    expect(chips[0]?.href).toBe('https://github.com/acme/platform/pull/87');
    expect(chips[0]?.textContent).not.toContain('work on platform');
    expect(trigger()).toBeNull();
  });

  it('collapses several pull requests into ONE chip with their count', () => {
    render([
      result('platform', 90, 'open'),
      result('platform', 87, 'merged'),
      result('platform', 80, 'open'),
    ]);

    expect(
      container.querySelectorAll('[data-slot="pull-request-chip"]'),
    ).toHaveLength(0);
    expect(trigger()?.textContent).toBe('PR3');
    expect(trigger()?.title).toBe('Pull requests · 2 open of 3');
  });

  it('lists every pull request behind the chip, the open ones first', () => {
    render([
      result('platform', 90, 'open'),
      result('platform', 87, 'merged'),
      result('platform', 80, 'open'),
    ]);

    act(() => trigger()?.click());

    expect(listed()).toEqual([
      expect.stringContaining('#90'),
      expect.stringContaining('#80'),
      expect.stringContaining('#87'),
    ]);
  });

  it('hands the list to the PANEL from inside it', () => {
    render([1, 2, 3, 4, 5].map((n) => result('platform', n, 'merged')));

    act(() => trigger()?.click());
    const toPanel = [...container.querySelectorAll('button')].find(
      (button) => button.textContent === 'Show in the panel',
    );
    act(() => toPanel?.click());

    // Written for THIS thread — the panel it opens is the one beside it.
    expect(readThreadFlag('run-1', AGENTS_PANEL_COLLAPSED_FLAG)).toBe(false);
    expect(readThreadFlag('run-1', THREAD_PULL_REQUESTS_SETTLED_FLAG)).toBe(
      true,
    );
    expect(readThreadFlag('run-2', AGENTS_PANEL_COLLAPSED_FLAG)).toBeNull();
  });

  it('draws nothing for a thread with no pull request', () => {
    render([]);
    expect(container.textContent).toBe('');
  });

  it('names the repository only when the thread spans more than one', () => {
    // `#3` is unambiguous inside one repository and meaningless across six —
    // the thread this was built for opened `#3` in two of them.
    render([result('platform', 87)]);
    expect(container.textContent).toContain('#87');
    expect(container.textContent).not.toContain('platform#87');
  });

  it('names the repository in the list once a second one is there', () => {
    render([result('platform', 3, 'open'), result('ux-mockup', 3, 'open')]);
    act(() => trigger()?.click());
    expect(listed()).toEqual([
      expect.stringContaining('platform#3'),
      expect.stringContaining('ux-mockup#3'),
    ]);
  });
});

describe('currentThreadPullRequest', () => {
  it('is null for a thread that opened none', () => {
    expect(currentThreadPullRequest([])).toBeNull();
  });

  it('takes the newest when nothing is open', () => {
    // Newest FIRST is the order `threadPullRequestsOf` hands over.
    const rows = [
      { ref: refOf(row('platform', 9, 9)), pullRequest: null },
      { ref: refOf(row('platform', 1, 1)), pullRequest: null },
    ];
    expect(currentThreadPullRequest(rows)?.ref.number).toBe(9);
  });
});

describe('rowPullRequestOf', () => {
  const shown = (
    number: number,
    seq: number,
    opened: boolean,
  ): DisplayedPullRequest => ({ ...row('platform', number, seq), opened });
  /** What `gh` answered, keyed as the hook keys it: `number` resolved, as merged. */
  const resolved = (
    ...numbers: number[]
  ): ReadonlyMap<string, PullRequestRefResult> =>
    new Map(
      numbers.map((number) => [
        `acme/platform#${number}`,
        {
          ref: refOf(row('platform', number, number)),
          pullRequest: {
            number,
            title: `work ${number}`,
            url: `https://github.com/acme/platform/pull/${number}`,
            state: 'merged',
            isDraft: false,
            headRefName: 'feat/x',
            isCrossRepository: false,
            headRepositoryOwner: 'acme',
            author: 'someone',
            updatedAt: '2026-08-01T00:00:00Z',
            added: null,
            removed: null,
            changedFiles: null,
          },
        },
      ]),
    );

  it('names the newest pull request the thread opened over a newer one it only touched', () => {
    const run = {
      pullRequests: [
        shown(7169, 1, true),
        shown(7209, 2, true),
        shown(7207, 3, false),
      ],
    };
    expect(rowPullRequestOf(run, resolved(7169, 7209, 7207))?.number).toBe(
      7209,
    );
  });

  it('names only an opened one while the thread has any, however their answers stand', () => {
    const run = {
      pullRequests: [shown(7201, 1, true), shown(7207, 2, false)],
    };
    // Not asked yet.
    expect(rowPullRequestOf(run, resolved(7207))).toBeNull();
    // Asked, and no answer — a cap or a failed `gh` reads the same as a gone repository.
    const store = new Map(resolved(7207));
    store.set('acme/platform#7201', {
      ref: refOf(row('platform', 7201, 1)),
      pullRequest: null,
    });
    expect(rowPullRequestOf(run, store)).toBeNull();
  });

  it('names the newest touched one for a thread that opened none', () => {
    const run = {
      pullRequests: [shown(6287, 1, false), shown(6288, 2, false)],
    };
    expect(rowPullRequestOf(run, resolved(6287, 6288))?.number).toBe(6288);
    expect(rowPullRequestOf({}, resolved(6287))).toBeNull();
  });
});
