// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type {
  PullRequestInfo,
  PullRequestRefResult,
} from '../../shared/contracts';
import type { RunPullRequest } from '../autogenerated';
import { ThreadPullRequestChips } from './composer-shelf';
import {
  currentThreadPullRequest,
  refOf,
  threadPullRequestsOf,
} from './use-thread-pull-requests';

const row = (repo: string, number: number, seq: number): RunPullRequest => ({
  owner: 'acme',
  repo,
  number,
  url: `https://github.com/acme/${repo}/pull/${number}`,
  seq,
});

describe('threadPullRequestsOf', () => {
  it('reads newest FIRST, though the row stores them oldest first', () => {
    // The row is a capture log ordered by when the thread opened them; a panel
    // is read top-down and the last thing a thread did is what its author came
    // looking for.
    const run = {
      pullRequests: [row('platform', 74, 1), row('platform', 87, 9)],
    };
    expect(
      threadPullRequestsOf(run, new Map()).map((r) => r.ref.number),
    ).toEqual([87, 74]);
  });

  it('still yields the pull request when GitHub answered nothing about it', () => {
    // The thread demonstrably opened it. A list built only from resolved
    // answers would make it vanish on a machine with no `gh` — which is the
    // failure the whole capture path exists to end, arrived at from the UI.
    const run = { pullRequests: [row('platform', 87, 1)] };
    const [only] = threadPullRequestsOf(run, new Map());
    expect(only?.pullRequest).toBeNull();
    expect(only?.ref.url).toBe('https://github.com/acme/platform/pull/87');
  });

  it('drops the transcript seq on its way to the Electron channel', () => {
    // A MAPPING, not a cast: `seq` is a transcript position and means nothing
    // outside the daemon.
    expect(refOf(row('platform', 87, 12))).toEqual({
      owner: 'acme',
      repo: 'platform',
      number: 87,
      url: 'https://github.com/acme/platform/pull/87',
    });
  });

  it('answers empty for a run row that carries no pull requests at all', () => {
    // Reached with rows from `run_status` broadcasts and hand-built fixtures,
    // where the field can be absent; throwing here takes the chat pane down.
    expect(threadPullRequestsOf({}, new Map())).toEqual([]);
    expect(threadPullRequestsOf(null, new Map())).toEqual([]);
  });
});

describe('ThreadPullRequestChips', () => {
  let container: HTMLElement;
  let root: Root;

  const render = (results: PullRequestRefResult[]): void => {
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
    act(() => {
      root.render(<ThreadPullRequestChips results={results} />);
    });
  };

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    localStorage.clear();
  });

  const result = (
    repo: string,
    number: number,
    state: PullRequestInfo['state'] | null = null,
  ): PullRequestRefResult => ({
    ref: refOf(row(repo, number, number)),
    pullRequest:
      state === null
        ? null
        : ({
            number,
            title: `work on ${repo}`,
            url: `https://github.com/acme/${repo}/pull/${number}`,
            state,
            isDraft: false,
            headRefName: 'feat/x',
            isCrossRepository: false,
            headRepositoryOwner: 'acme',
            author: 'someone',
            updatedAt: '2026-08-01T00:00:00Z',
          } satisfies PullRequestInfo),
  });

  it('shows ONE chip however many the thread opened', () => {
    // The shelf is one line above the composer: thirty-one chips pushed the
    // textarea most of the way up the pane, which is what this replaced.
    render([1, 2, 3, 4, 5].map((n) => result('platform', n)));

    expect(
      container.querySelectorAll('[data-slot="pull-request-chip"]'),
    ).toHaveLength(1);
  });

  it('names the one still OPEN, not merely the newest', () => {
    render([
      result('platform', 90, 'merged'),
      result('platform', 87, 'open'),
      result('platform', 80, 'merged'),
    ]);

    const chip = container.querySelector('[data-slot="pull-request-chip"]');
    expect(chip?.textContent).toContain('#87');
  });

  it('hands the whole list to the PANEL rather than opening it in place', () => {
    // The press must not grow the shelf — that is the thing being fixed — and
    // it has to reach a panel that may be folded shut AND whose settled group
    // is shut by default, or "All 5" answers with an empty section.
    render([1, 2, 3, 4, 5].map((n) => result('platform', n, 'merged')));

    const all = container.querySelector('button');
    expect(all?.textContent).toBe('All 5');

    act(() => all?.click());

    expect(
      container.querySelectorAll('[data-slot="pull-request-chip"]'),
    ).toHaveLength(1);
    expect(localStorage.getItem('chats.agentsPanelCollapsed')).toBe('0');
    expect(localStorage.getItem('chats.threadPullRequestsSettledOpen')).toBe(
      '1',
    );
  });

  it('offers no button when the one chip IS the whole list', () => {
    render([result('platform', 87)]);
    expect(container.querySelector('button')).toBeNull();
  });

  it('names the repository only when the thread spans more than one', () => {
    // `#3` is unambiguous inside one repository and meaningless across six —
    // the thread this was built for opened `#3` in two of them.
    render([result('platform', 87)]);
    expect(container.textContent).toContain('#87');
    expect(container.textContent).not.toContain('platform#87');
  });

  it('names the repository once a second one is on the shelf', () => {
    render([result('platform', 3), result('ux-mockup', 3)]);
    expect(container.textContent).toContain('platform#3');
  });
});

describe('currentThreadPullRequest', () => {
  it('is null for a thread that opened none', () => {
    expect(currentThreadPullRequest([])).toBeNull();
  });

  it('takes the newest when nothing is open', () => {
    // Newest FIRST is the order `threadPullRequestsOf` hands over.
    const rows = [
      { ref: refOf(row('platform', 9, 9)), pullRequest: null },
      { ref: refOf(row('platform', 1, 1)), pullRequest: null },
    ];
    expect(currentThreadPullRequest(rows)?.ref.number).toBe(9);
  });
});
