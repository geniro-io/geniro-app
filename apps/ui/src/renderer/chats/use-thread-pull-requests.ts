import { useCallback, useEffect, useMemo, useRef, useState } from 'react';

import type {
  PullRequestRef,
  PullRequestRefResult,
} from '../../shared/contracts';
import type { RunPullRequest } from '../autogenerated';

/**
 * Live state for the pull requests each THREAD opened.
 *
 * The refs come from the daemon on the run row — it read them out of the
 * agent's own `gh pr create` output — and only GitHub knows what they currently
 * are, so this hook is the join between the two. It is the counterpart of
 * {@link usePullRequests}, which answers the OTHER question: what is open on
 * the branch a folder happens to have checked out.
 *
 * ONE batched call for every thread on screen, not one per thread. The resolve
 * groups by repository, so a sidebar of forty conversations across three
 * repositories costs three `gh` queries — where a per-thread call would cost
 * forty.
 */
const REFRESH_TTL_MS = 5 * 60_000;

/** How a resolved pull request is keyed, on both sides of the call. */
function keyOf(ref: { owner: string; repo: string; number: number }): string {
  return `${ref.owner}/${ref.repo}#${ref.number}`;
}

/**
 * The wire row as the Electron channel takes it.
 *
 * A MAPPING rather than a cast: `RunPullRequest` carries a transcript `seq`
 * that means nothing outside the daemon, and the IPC shape must stay free to
 * diverge from a generated type.
 */
export function refOf(pullRequest: RunPullRequest): PullRequestRef {
  return {
    owner: pullRequest.owner,
    repo: pullRequest.repo,
    number: pullRequest.number,
    url: pullRequest.url,
  };
}

/**
 * A captured pull-request URL, read back into its parts.
 *
 * The URL is the whole address — owner, repository and number are all in it —
 * which is what lets the memo below depend on nothing but the sorted list of
 * URLs. Anything that does not parse is DROPPED rather than guessed at: the
 * daemon only ever writes this shape, so a URL that is not it is a row from
 * somewhere else.
 */
const REF_URL = /^https:\/\/github\.com\/([^/]+)\/([^/]+)\/pull\/(\d+)$/u;

function parseRefUrl(url: string): PullRequestRef | null {
  const match = REF_URL.exec(url);
  if (match === null) {
    return null;
  }
  const [, owner, repo, number] = match;
  if (owner === undefined || repo === undefined || number === undefined) {
    return null;
  }
  return { owner, repo, number: Number(number), url };
}

export interface ThreadPullRequestStore {
  /**
   * What GitHub said about each pull request, keyed by `owner/repo#number`.
   *
   * A ref MISSING from this map is one whose answer has not arrived yet; a ref
   * present with a null `pullRequest` is one GitHub could not be asked about.
   * The two render differently — pending is quiet, unanswerable still links —
   * so they must stay distinguishable.
   */
  byKey: ReadonlyMap<string, PullRequestRefResult>;
  /** Re-ask now: a thread has just opened one, or the user pressed refresh. */
  refresh: () => void;
}

export function useThreadPullRequests(
  // Optional on the parameter, though the wire type has it: this reads run rows
  // that also arrive from `run_status` broadcasts and from hand-built fixtures,
  // and a hook that throws on a row missing one field takes the whole chat pane
  // down with it.
  runs: readonly { pullRequests?: RunPullRequest[] }[],
): ThreadPullRequestStore {
  const [byKey, setByKey] = useState<ReadonlyMap<string, PullRequestRefResult>>(
    new Map(),
  );
  /** The newest read asked for, so a slower earlier reply cannot land last. */
  const issued = useRef(0);
  /** When the last read answered, for {@link REFRESH_TTL_MS}. */
  const readAt = useRef(0);

  // Keyed on CONTENT: `runs` is a fresh array on every render of the owner, so
  // an effect keyed on the array itself would re-ask on every keystroke in the
  // composer.
  const key = useMemo(
    () =>
      [
        ...new Set(
          runs.flatMap((run) => (run.pullRequests ?? []).map((row) => row.url)),
        ),
      ]
        .sort()
        .join('\n'),
    [runs],
  );
  // Built back out of `key` rather than out of `runs`, and that is what makes
  // the memo honest: the array's identity changes on every render of the owner
  // while its content rarely does, so depending on `runs` would re-ask GitHub
  // on every keystroke in the composer — and a hook that depends on `key` while
  // reading `runs` is the same bug with the compiler no longer able to see it.
  // The URL carries all four fields, so nothing is lost by going through it.
  const refs = useMemo(
    () =>
      key === ''
        ? []
        : key
            .split('\n')
            .map(parseRefUrl)
            .filter((ref): ref is PullRequestRef => ref !== null),
    [key],
  );

  const read = useCallback(async (wanted: PullRequestRef[]): Promise<void> => {
    if (wanted.length === 0) {
      return;
    }
    const generation = issued.current + 1;
    issued.current = generation;
    try {
      const results = await window.geniro.getPullRequestsByRef(wanted);
      // Last to RESOLVE is not last to be asked for: a refresh fired while a
      // slower read is in flight must not have the older answer land second.
      if (issued.current !== generation) {
        return;
      }
      readAt.current = Date.now();
      setByKey((previous) => {
        const next = new Map(previous);
        for (const result of results) {
          next.set(keyOf(result.ref), result);
        }
        return next;
      });
    } catch {
      // One failed resolve costs this pass and nothing else — the next focus,
      // or the next thread to open a pull request, asks again.
    }
  }, []);

  useEffect(() => {
    void read(refs);
  }, [refs, read]);

  useEffect(() => {
    // Returning to the window is when the answer may have changed: a pull
    // request is merged or closed on GitHub, which is somewhere else by
    // definition.
    const onFocus = (): void => {
      if (Date.now() - readAt.current < REFRESH_TTL_MS) {
        return;
      }
      void read(refs);
    };
    window.addEventListener('focus', onFocus);
    return () => window.removeEventListener('focus', onFocus);
  }, [refs, read]);

  const refresh = useCallback(() => {
    readAt.current = 0;
    void read(refs);
  }, [refs, read]);

  return { byKey, refresh };
}

/**
 * One thread's pull requests, newest first, with whatever is known about each.
 *
 * Newest FIRST here, and oldest first on the daemon's row: the row is a
 * capture log, where order is when the thread opened them; a panel is read
 * top-down and the last thing a thread did is what its author is looking for.
 */
export function threadPullRequestsOf(
  run: { pullRequests?: RunPullRequest[] } | null | undefined,
  store: ReadonlyMap<string, PullRequestRefResult>,
): PullRequestRefResult[] {
  if (run?.pullRequests == null) {
    return [];
  }
  return [...run.pullRequests]
    .reverse()
    .map(
      (row) => store.get(keyOf(row)) ?? { ref: refOf(row), pullRequest: null },
    );
}

/**
 * The ONE of them the thread is currently on — what the shelf above the
 * composer names.
 *
 * An OPEN one outranks a settled one, and among open ones the newest wins: a
 * thread that opened six pull requests over a week is working on the one still
 * in review, not on the first one it merged. An unresolved row can still be the
 * answer — the thread demonstrably opened it, and `gh` having nothing to say is
 * not a state.
 */
export function currentThreadPullRequest(
  results: readonly PullRequestRefResult[],
): PullRequestRefResult | null {
  return (
    results.find((row) => row.pullRequest?.state === 'open') ??
    results[0] ??
    null
  );
}

/**
 * How many pull requests the shelf may name at once.
 *
 * THREE, and the number is about the LINE rather than about pull requests: the
 * shelf never wraps, so every chip drawn takes width from the ones beside it
 * and from the running-terminals chip, which does not shrink. Three chips still
 * leave each of them enough room to show a number and the front of a title;
 * four is where a title stops being readable at all and the row becomes a
 * column of bare numbers.
 */
export const MAX_SHELF_PULL_REQUESTS = 3;

/**
 * Which of them the shelf NAMES — every one the thread has open, capped, and
 * the newest single one when it has none.
 *
 * ASKED FOR as "we should show last PR. But in case if we have few opened PRS -
 * all of them, but maximum 3". The shelf named exactly one before this, which
 * is right for a thread whose work is one branch and wrong for the case it was
 * reported against: a thread with several reviews open at once could reach only
 * the newest of them from here, and the others were behind the panel.
 *
 * OPEN is what earns a chip, because an open pull request is the only kind that
 * is still work — a merged one is history and has its row in the panel. So the
 * cases collapse rather than branching: zero or one open gives back exactly
 * what {@link currentThreadPullRequest} gave, several give all of them, and a
 * thread whose pull requests have all settled still names its newest, since
 * "this thread produced this" is worth a chip even when nothing is left to do.
 *
 * Newest first throughout — `results` already arrives that way — so the chip
 * nearest the composer is the one the thread is most likely on.
 */
export function shelfThreadPullRequests(
  results: readonly PullRequestRefResult[],
  limit: number = MAX_SHELF_PULL_REQUESTS,
): PullRequestRefResult[] {
  const open = results.filter((row) => row.pullRequest?.state === 'open');
  if (open.length > 0) {
    return open.slice(0, limit);
  }
  const current = currentThreadPullRequest(results);
  return current === null ? [] : [current];
}
