import { useEffect, useMemo, useRef, useState } from 'react';

import type {
  KnowledgeRevisionHead,
  LessonProposal,
  MemoryEntry,
} from '../autogenerated';
import type { MemoryTeamOption } from '../components/memory-form';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { WAITING_LESSON_STATUSES } from './lessons-api-context';
import type { WaitingItemsStore } from './waiting-items-context';

const MEMORY_PAGE = 200;
const KNOWLEDGE_PAGE = 50;

async function readPendingMemories({
  memories: api,
}: DaemonApis): Promise<MemoryEntry[]> {
  const entries: MemoryEntry[] = [];
  let cursor: { beforeUpdatedAt: string; beforeId: string } | null = null;
  do {
    const page = await api.listMemories({
      status: 'pending',
      limit: MEMORY_PAGE,
      ...(cursor ?? {}),
    });
    entries.push(...page.memories);
    cursor = page.next;
  } while (cursor !== null);
  return entries;
}

async function readWaitingLessons({
  lessons,
}: DaemonApis): Promise<LessonProposal[]> {
  const { proposals } = await lessons.listLessonProposals({
    status: WAITING_LESSON_STATUSES,
  });
  return proposals;
}

async function readPendingRevisions({
  knowledge: api,
}: DaemonApis): Promise<KnowledgeRevisionHead[]> {
  const ids: string[] = [];
  let cursor: string | null = null;
  do {
    const page = await api.listKnowledge({
      status: 'waiting',
      limit: KNOWLEDGE_PAGE,
      cursor: cursor ?? undefined,
    });
    ids.push(...page.documents.map((document) => document.id));
    cursor = page.next;
  } while (cursor !== null);
  const lists = await Promise.all(
    ids.map((id) => api.listKnowledgeRevisions({ id })),
  );
  return lists.flatMap(({ revisions }) =>
    revisions.filter((revision) => revision.status === 'pending'),
  );
}

type Subscribe = (client: DaemonClient, reload: () => void) => () => void;

const ON_MEMORY: Subscribe = (client, reload) => client.onMemoryChanged(reload);
const ON_LESSONS: Subscribe = (client, reload) =>
  client.onLessonsChanged(reload);
const ON_KNOWLEDGE: Subscribe = (client, reload) =>
  client.onKnowledgeChanged(reload);

function useWaitingSet<T extends { id: string }>(
  apis: DaemonApis | null,
  client: DaemonClient | null,
  active: boolean,
  read: (apis: DaemonApis) => Promise<readonly T[]>,
  subscribe: Subscribe,
): { items: ReadonlyMap<string, T> | null; reload: () => void } {
  const [items, setItems] = useState<ReadonlyMap<string, T> | null>(null);
  const generation = useRef(0);

  const reload = useLatestCallback(() => {
    if (!active || apis === null) {
      return;
    }
    const mine = ++generation.current;
    void read(apis).then(
      (list) => {
        if (mine === generation.current) {
          setItems(new Map(list.map((item) => [item.id, item])));
        }
      },
      () => undefined,
    );
  }, [active, apis, read]);

  useEffect(() => {
    if (!active) {
      generation.current += 1;
      setItems(null);
      return;
    }
    reload();
    if (client === null) {
      return;
    }
    const offChanged = subscribe(client, reload);
    const offConnected = client.onReconnect(reload);
    return () => {
      generation.current += 1;
      offChanged();
      offConnected();
    };
  }, [active, client, reload, subscribe]);

  return { items, reload };
}

/**
 * Everything waiting on the user's review, by id, while `enabled`: the pending
 * memory entries, the lessons waiting and the pending knowledge revisions, each
 * re-read on its own change announce and all of them after a reconnect —
 * with the projects and library teams an entry's scope may name.
 */
export function useWaitingItems(
  apis: DaemonApis | null,
  client: DaemonClient | null,
  enabled: boolean,
  projects: readonly { id: string; name: string }[],
  libraryTeams: readonly MemoryTeamOption[],
): WaitingItemsStore | null {
  const teams = useMemo(
    () => libraryTeams.map(({ slug, name }) => ({ slug, name })),
    [libraryTeams],
  );
  const active = enabled && apis !== null;
  const memories = useWaitingSet(
    apis,
    client,
    active,
    readPendingMemories,
    ON_MEMORY,
  );
  const lessons = useWaitingSet(
    apis,
    client,
    active,
    readWaitingLessons,
    ON_LESSONS,
  );
  const knowledge = useWaitingSet(
    apis,
    client,
    active,
    readPendingRevisions,
    ON_KNOWLEDGE,
  );
  if (!active || apis === null) {
    return null;
  }
  return {
    apis,
    memories: memories.items,
    lessons: lessons.items,
    knowledge: knowledge.items,
    projects,
    teams,
    reloadMemories: memories.reload,
    reloadLessons: lessons.reload,
    reloadKnowledge: knowledge.reload,
  };
}
