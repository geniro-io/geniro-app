// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ChatsApi, WaitingMessageDto } from '../autogenerated';
import type {
  DaemonClient,
  ThreadMessagesChangedEvent,
} from '../daemon-client';
import {
  useWaitingMessages,
  type WaitingMessagesState,
} from './use-waiting-messages';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

type Api = Pick<ChatsApi, 'listWaitingMessages' | 'removeWaitingMessage'>;
type Events = Pick<DaemonClient, 'onThreadMessagesChanged' | 'onReconnect'>;

function waiting(id: string): WaitingMessageDto {
  return {
    id,
    fromRunId: 'r-pelican',
    fromTitle: 'Pelican',
    fromMember: null,
    text: `text of ${id}`,
    reason: 'stopped',
    createdAt: '2026-11-06T10:00:00Z',
  };
}

/** One list per read, in order; the last one repeats once they run out. */
function apiReturning(lists: WaitingMessageDto[][]): Api {
  let last: WaitingMessageDto[] = [];
  return {
    listWaitingMessages: vi.fn(async () => {
      last = lists.shift() ?? last;
      return last;
    }),
    removeWaitingMessage: vi.fn(async () => undefined),
  };
}

function fakeEvents(): {
  events: Events;
  announce: (runId: string) => void;
  reconnect: () => void;
} {
  const changed = new Set<(event: ThreadMessagesChangedEvent) => void>();
  const reconnected = new Set<() => void>();
  return {
    events: {
      onThreadMessagesChanged(listener) {
        changed.add(listener);
        return () => changed.delete(listener);
      },
      onReconnect(listener) {
        reconnected.add(listener);
        return () => reconnected.delete(listener);
      },
    },
    announce: (runId) => {
      for (const listener of changed) {
        listener({ runId });
      }
    },
    reconnect: () => {
      for (const listener of reconnected) {
        listener();
      }
    },
  };
}

let root: Root | null = null;
let seen: WaitingMessagesState | null = null;

function Probe({
  api,
  events,
  runId,
}: {
  api: Api | null;
  events: Events | null;
  runId: string | null;
}): null {
  seen = useWaitingMessages(api, events, runId);
  return null;
}

async function render(
  api: Api | null,
  events: Events | null,
  runId: string | null,
): Promise<void> {
  if (root === null) {
    root = createRoot(document.createElement('div'));
  }
  await act(async () => {
    root!.render(<Probe api={api} events={events} runId={runId} />);
  });
}

const ids = (): string[] => (seen?.messages ?? []).map((message) => message.id);

afterEach(() => {
  act(() => root?.unmount());
  root = null;
  seen = null;
});

describe('useWaitingMessages', () => {
  it('reads the waiting messages of the open thread', async () => {
    const api = apiReturning([[waiting('w1')]]);
    await render(api, fakeEvents().events, 'r-otter');
    expect(ids()).toEqual(['w1']);
    expect(seen?.loaded).toBe(true);
    expect(api.listWaitingMessages).toHaveBeenCalledWith({ runId: 'r-otter' });
  });

  it('re-reads when the daemon announces a change to its own thread, and not to another', async () => {
    const events = fakeEvents();
    const api = apiReturning([[waiting('w1')], [waiting('w1'), waiting('w2')]]);
    await render(api, events.events, 'r-otter');

    await act(async () => events.announce('r-pelican'));
    expect(api.listWaitingMessages).toHaveBeenCalledTimes(1);

    await act(async () => events.announce('r-otter'));
    expect(ids()).toEqual(['w1', 'w2']);
    expect(api.listWaitingMessages).toHaveBeenCalledTimes(2);
  });

  it('re-reads after a reconnect, which may have missed a change', async () => {
    const events = fakeEvents();
    const api = apiReturning([[waiting('w1')], []]);
    await render(api, events.events, 'r-otter');

    await act(async () => events.reconnect());
    expect(api.listWaitingMessages).toHaveBeenCalledTimes(2);
    expect(ids()).toEqual([]);
  });

  it('takes a message away and re-reads the list without it', async () => {
    const api = apiReturning([[waiting('w1'), waiting('w2')], [waiting('w2')]]);
    await render(api, fakeEvents().events, 'r-otter');

    await act(async () => {
      await seen!.remove('w1');
    });
    expect(api.removeWaitingMessage).toHaveBeenCalledWith({
      runId: 'r-otter',
      messageId: 'w1',
    });
    expect(ids()).toEqual(['w2']);
  });

  it('reads nothing while no thread is open', async () => {
    const api = apiReturning([[waiting('w1')]]);
    await render(api, fakeEvents().events, null);
    expect(ids()).toEqual([]);
    expect(api.listWaitingMessages).not.toHaveBeenCalled();
  });
});
