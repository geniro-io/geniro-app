import { useEffect, useState } from 'react';

import type {
  ChatsApi,
  DeliveredWaitingMessageDto,
  WaitingMessageDto,
} from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonClient } from '../daemon-client';
import { useRunDaemonRead } from './use-run-daemon-read';

type Api = Pick<
  ChatsApi,
  'listWaitingMessages' | 'removeWaitingMessage' | 'deliverWaitingMessage'
>;
type Events = Pick<DaemonClient, 'onThreadMessagesChanged' | 'onReconnect'>;

export interface WaitingMessagesState {
  runId: string | null;
  messages: readonly WaitingMessageDto[];
  loaded: boolean;
  /** Take one waiting message away; the list re-reads once the daemon has done it. */
  remove: (messageId: string) => Promise<void>;
  /** Deliver one now, waking the thread if it must; the list re-reads after. */
  deliver: (messageId: string) => Promise<DeliveredWaitingMessageDto>;
}

const NONE: readonly WaitingMessageDto[] = [];

const readWaiting = (
  api: Api,
  runId: string,
): Promise<readonly WaitingMessageDto[]> => api.listWaitingMessages({ runId });

/**
 * The messages other threads sent this one that still wait, read from the
 * daemon. Re-read when the daemon announces a change to this thread's waiting
 * list, and after a reconnect, which may have missed one.
 */
export function useWaitingMessages(
  api: Api | null,
  client: Events | null,
  runId: string | null,
): WaitingMessagesState {
  const [bump, setBump] = useState(0);

  useEffect(() => {
    if (client === null || runId === null) {
      return;
    }
    const unsubscribeChange = client.onThreadMessagesChanged((event) => {
      if (event.runId === runId) {
        setBump((n) => n + 1);
      }
    });
    const unsubscribeReconnect = client.onReconnect(() =>
      setBump((n) => n + 1),
    );
    return () => {
      unsubscribeChange();
      unsubscribeReconnect();
    };
  }, [client, runId]);

  const read = useRunDaemonRead(api, runId, bump, readWaiting, NONE);

  const remove = useLatestCallback(
    async (messageId: string): Promise<void> => {
      if (api === null || runId === null) {
        throw new Error('No thread is open to take the message from');
      }
      await api.removeWaitingMessage({ runId, messageId });
      setBump((n) => n + 1);
    },
    [api, runId],
  );

  const deliver = useLatestCallback(
    async (messageId: string): Promise<DeliveredWaitingMessageDto> => {
      if (api === null || runId === null) {
        throw new Error('No thread is open to deliver the message in');
      }
      const answer = await api.deliverWaitingMessage({ runId, messageId });
      setBump((n) => n + 1);
      return answer;
    },
    [api, runId],
  );

  return {
    runId: read.runId,
    messages: read.value,
    loaded: read.loaded,
    remove,
    deliver,
  };
}
