import {
  WaitingItemsContext,
  type WaitingItemsStore,
} from './waiting-items-context';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function pendingEntry(id: string, title: string, updatedAt: string) {
  return memoryEntry({
    id,
    handle: id,
    title,
    status: 'pending',
    updatedAt,
    source: {
      actor: 'agent',
      agentKind: 'claude',
      model: null,
      runId: null,
      importedFrom: null,
    },
  });
}

function proposal(id: string): LessonProposal {
  return {
    id,
    sourceRunId: 'run-1',
    sourceTitle: 'Release thread',
    reflectionRunId: 'reflection-1',
    projectId: 'proj-1',
    teamSlug: null,
    title: 'WHEN testing → use pnpm test:unit',
    rule: 'Run tests through pnpm test:unit.',
    why: 'Plain vitest skips Electron.',
    signalKind: 'user_correction',
    evidence: { seq: 3, quote: 'no vitest' },
    target: { kind: 'memory', scope: 'project', type: 'feedback' },
    dedup: { verdict: 'new', handle: null },
    status: 'proposed',
    rejectReason: null,
    checkVerdict: null,
    checkReason: null,
    memoryHandle: null,
    resultRef: null,
    places: PROJECT_PLACES,
    moveUp: null,
    undoable: false,
    memoryPending: false,
    sourceExists: true,
    createdAt: '2026-11-15T10:00:00Z',
    decidedAt: null,
  };
}

function storeOf(patch: Partial<WaitingItemsStore> = {}) {
  const updateMemory = vi.fn().mockResolvedValue({});
  const createMemory = vi.fn().mockResolvedValue({});
  const readMemory = vi.fn().mockResolvedValue({ status: 'active' });
  const rejectLesson = vi.fn().mockResolvedValue({});
  const listLessonProposals = vi.fn().mockResolvedValue({ proposals: [] });
  const readKnowledgeRevision = vi.fn();
  const approveKnowledgeRevision = vi.fn().mockResolvedValue({});
  const rejectKnowledgeRevision = vi.fn().mockResolvedValue({});
  const store: WaitingItemsStore = {
    apis: {
      memories: { updateMemory, readMemory, createMemory },
      lessons: { rejectLesson, listLessonProposals },
      knowledge: {
        readKnowledgeRevision,
        approveKnowledgeRevision,
        rejectKnowledgeRevision,
      },
    } as unknown as DaemonApis,
    memories: new Map(),
    lessons: new Map(),
    knowledge: new Map(),
    projects: [{ id: 'proj-1', name: 'Billing' }],
    teams: [{ slug: 'dev-team', name: 'Dev Team' }],
    reloadMemories: vi.fn(),
    reloadLessons: vi.fn(),
    reloadKnowledge: vi.fn(),
    ...patch,
  };
  return {
    store,
    updateMemory,
    readMemory,
    rejectLesson,
    listLessonProposals,
    readKnowledgeRevision,
    approveKnowledgeRevision,
    rejectKnowledgeRevision,
  };
}

function draw(
  store: WaitingItemsStore | null,
  row: Parameters<typeof WaitingItemsCard>[0]['row'],
  open: ((handle: string) => void) | null = null,
): void {
  act(() =>
    root.render(
      <MemoryOpenContext.Provider value={open}>
        <KnowledgeOpenContext.Provider value={null}>
          <WaitingItemsContext.Provider value={store}>
            <WaitingItemsCard row={row} />
          </WaitingItemsContext.Provider>
        </KnowledgeOpenContext.Provider>
      </MemoryOpenContext.Provider>,
    ),
  );
}

const buttonIn = (
  within: ParentNode,
  name: string,
): HTMLButtonElement | undefined =>
  [...within.querySelectorAll('button')].find(
    (button) => button.textContent?.trim() === name,
  );

const buttonNamed = (name: string): HTMLButtonElement | undefined =>
  buttonIn(container, name);

const resolvedLines = (): (string | null)[] =>
  [...container.querySelectorAll('[data-slot="waiting-items-resolved"]')].map(
    (line) => line.textContent,
  );

const decidedCard = (): HTMLElement | null =>
  container.querySelector<HTMLElement>(
    '[data-slot="waiting-items-card"][data-decided]',
  );

function typeInto(input: HTMLInputElement, value: string): void {
  act(() => {
    Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )!.set!.call(input, value);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

describe('WaitingItemsCard', () => {
  it('approves a memory entry through the API, then stays as a reviewed card saying it was approved', async () => {
    const entry = pendingEntry('m1', 'Never edit a sent invoice', '2026-11-01');
    const { store, updateMemory } = storeOf({
      memories: new Map<string, MemoryEntry>([[entry.id, entry]]),
    });
    const row = {
      kind: 'memory' as const,
      items: [{ id: 'm1', title: 'Never edit a sent invoice' }],
    };
    draw(store, row);

    expect(container.textContent).toContain('Waiting for your review');
    await act(async () => {
      buttonNamed('Approve')?.click();
    });
    expect(updateMemory).toHaveBeenCalledWith({
      memoryId: 'm1',
      updateMemoryDto: { status: 'active' },
    });
    expect(store.reloadMemories).toHaveBeenCalled();

    draw({ ...store, memories: new Map() }, row);
    await act(async () => undefined);
    expect(decidedCard()?.textContent).toContain('Reviewed');
    expect(resolvedLines()).toEqual(['Never edit a sent invoice — approved']);
    expect(container.textContent).not.toContain('Waiting for your review');
    expect(container.querySelector('button')).toBeNull();
  });

  it("names the entry's project and team the way Settings does", () => {
    const entry = {
      ...pendingEntry('m1', 'Never edit a sent invoice', '2026-11-01'),
      projectId: 'proj-1',
    };
    const { store } = storeOf({ memories: new Map([[entry.id, entry]]) });
    draw(store, { kind: 'memory', items: [{ id: 'm1', title: entry.title }] });

    expect(container.textContent).toContain('Billing');
    expect(container.textContent).not.toContain('a removed project');
  });

  it('offers Edit and Forget beside Approve, and saves an edit at the read rev', async () => {
    const entry = pendingEntry('m1', 'Never edit a sent invoice', '2026-11-01');
    const { store, updateMemory } = storeOf({
      memories: new Map([[entry.id, entry]]),
    });
    draw(store, { kind: 'memory', items: [{ id: 'm1', title: entry.title }] });
    const row = container.querySelector<HTMLElement>(
      '[data-slot="memory-row"]',
    )!;

    expect(buttonNamed('Approve')).toBeDefined();
    expect(await memoryRowActions(row)).toEqual(['Edit', 'Forget…']);

    await pressMemoryRowAction(row, 'Edit');
    const form = container.querySelector<HTMLElement>(
      '[data-slot="memory-form"]',
    )!;
    typeInto(
      form.querySelector<HTMLInputElement>('[data-slot="input"]')!,
      'Never edit a sent invoice; issue a credit note',
    );
    await act(async () => {
      buttonIn(form, 'Save')!.click();
    });

    expect(updateMemory).toHaveBeenCalledWith({
      memoryId: 'm1',
      updateMemoryDto: {
        title: 'Never edit a sent invoice; issue a credit note',
        body: entry.body,
        type: entry.type,
        projectId: null,
        teamSlug: null,
        rev: entry.rev,
        notDuplicateOf: undefined,
      },
    });
    expect(store.reloadMemories).toHaveBeenCalled();
    expect(container.querySelector('[data-slot="memory-form"]')).toBeNull();
  });

  it('offers Open in Settings → Memory only where something can take the reader there', () => {
    const entry = pendingEntry('m1', 'Never edit a sent invoice', '2026-11-01');
    const { store } = storeOf({ memories: new Map([[entry.id, entry]]) });
    const row = { kind: 'memory' as const, items: [{ id: 'm1', title: 'x' }] };
    draw(store, row);
    expect(buttonNamed('Open in Settings → Memory')).toBeUndefined();

    const open = vi.fn();
    draw(store, row, open);
    act(() => buttonNamed('Open in Settings → Memory')?.click());
    expect(open).toHaveBeenCalledWith('m1');
  });

  it('rejects a waiting lesson with the exact API call and reloads the lessons', async () => {
    const { store, rejectLesson } = storeOf({
      lessons: new Map([['p1', proposal('p1')]]),
    });
    draw(store, { kind: 'lesson', items: [{ id: 'p1', title: 'a lesson' }] });

    expect(container.textContent).toContain('Release thread');
    await act(async () => {
      buttonNamed('Reject')!.click();
    });
    await act(async () => {
      buttonNamed('Reject')!.click();
    });
    expect(rejectLesson).toHaveBeenCalledTimes(1);
    expect(rejectLesson).toHaveBeenCalledWith({
      proposalId: 'p1',
      rejectLessonDto: {},
    });
    expect(store.reloadLessons).toHaveBeenCalled();
  });

  it('forgets a waiting memory entry through updateMemory with status forgotten', async () => {
    const entry = pendingEntry('m1', 'Never edit a sent invoice', '2026-11-01');
    const { store, updateMemory } = storeOf({
      memories: new Map([[entry.id, entry]]),
    });
    draw(store, { kind: 'memory', items: [{ id: 'm1', title: entry.title }] });

    await pressMemoryRowAction(
      container.querySelector<HTMLElement>('[data-slot="memory-row"]')!,
      'Forget…',
    );
    await act(async () => {
      confirmInDialog('Forget').click();
    });
    expect(updateMemory).toHaveBeenCalledWith({
      memoryId: 'm1',
      updateMemoryDto: { status: 'forgotten' },
    });
    expect(store.reloadMemories).toHaveBeenCalled();
  });

  describe('a knowledge change', () => {
    const head = {
      id: 'rev-1',
      documentId: 'doc-1',
      title: 'Release checklist',
      status: 'pending',
      source: { actor: 'agent', agentKind: 'claude', model: null },
      createdAt: '2026-11-15T10:00:00Z',
    } as unknown as KnowledgeRevisionHead;
    const row = {
      kind: 'knowledge' as const,
      items: [{ id: 'rev-1', title: 'Release checklist' }],
    };

    const dialogOf = (): HTMLElement =>
      [...document.querySelectorAll<HTMLElement>('[role="dialog"]')].at(-1)!;

    async function openReview() {
      const made = storeOf({ knowledge: new Map([[head.id, head]]) });
      made.readKnowledgeRevision.mockResolvedValue(
        aKnowledgeRevision({ id: 'rev-1', documentId: 'doc-1' }),
      );
      draw(made.store, row);
      await act(async () => {
        buttonNamed('Review')!.click();
      });
      return made;
    }

    it('opens the review dialog on Review, reading that revision', async () => {
      const made = await openReview();
      expect(made.readKnowledgeRevision).toHaveBeenCalledWith({
        revisionId: 'rev-1',
      });
      expect(document.body.textContent).toContain('Waiting for review');
    });

    it('approves the revision by id and reloads the knowledge', async () => {
      const made = await openReview();
      await act(async () => {
        buttonIn(dialogOf(), 'Approve')!.click();
      });
      await act(async () => {
        confirmInDialog('Approve').click();
      });
      expect(made.approveKnowledgeRevision).toHaveBeenCalledWith({
        revisionId: 'rev-1',
      });
      expect(made.rejectKnowledgeRevision).not.toHaveBeenCalled();
      expect(made.store.reloadKnowledge).toHaveBeenCalled();
    });

    it('rejects the revision by id', async () => {
      const made = await openReview();
      await act(async () => {
        buttonIn(dialogOf(), 'Reject')!.click();
      });
      await act(async () => {
        confirmInDialog('Reject').click();
      });
      expect(made.rejectKnowledgeRevision).toHaveBeenCalledWith({
        revisionId: 'rev-1',
      });
      expect(made.approveKnowledgeRevision).not.toHaveBeenCalled();
    });

    it('reads as approved or rejected once the revision left the pending set', async () => {
      const made = storeOf({ knowledge: new Map() });
      made.readKnowledgeRevision.mockResolvedValue({ status: 'rejected' });
      await act(async () => {
        draw(made.store, row);
      });
      expect(decidedCard()).not.toBeNull();
      expect(resolvedLines()).toEqual(['Release checklist — rejected']);
      expect(made.readKnowledgeRevision).toHaveBeenCalledWith({
        revisionId: 'rev-1',
      });
    });
  });

  it('reads a resolved lesson as its decided status', async () => {
    const made = storeOf();
    made.listLessonProposals.mockResolvedValue({
      proposals: [{ ...proposal('p1'), status: 'saved' }],
    });
    await act(async () => {
      draw(made.store, {
        kind: 'lesson',
        items: [{ id: 'p1', title: 'a lesson' }],
      });
    });
    expect(made.listLessonProposals).toHaveBeenCalledWith({
      status: 'saved,rejected,undone',
    });
    expect(decidedCard()).not.toBeNull();
    expect(resolvedLines()).toEqual(['a lesson — saved']);
  });

  it('reads a forgotten memory entry as forgotten', async () => {
    const made = storeOf();
    made.readMemory.mockResolvedValue({ status: 'forgotten' });
    await act(async () => {
      draw(made.store, {
        kind: 'memory',
        items: [{ id: 'm1', title: 'Old note' }],
      });
    });
    expect(decidedCard()).not.toBeNull();
    expect(resolvedLines()).toEqual(['Old note — forgotten']);
  });

  it('falls back to no longer waiting when the outcome cannot be read', async () => {
    const made = storeOf();
    made.readMemory.mockRejectedValue(new Error('gone'));
    await act(async () => {
      draw(made.store, {
        kind: 'memory',
        items: [{ id: 'm1', title: 'Old note' }],
      });
    });
    expect(resolvedLines()).toEqual(['Old note — no longer waiting']);
  });

  it('counts only the items still waiting in a summary, newest first', () => {
    const old = pendingEntry('m1', 'Old note', '2026-10-01');
    const fresh = pendingEntry('m2', 'Fresh note', '2026-11-20');
    const { store } = storeOf({
      memories: new Map([
        [old.id, old],
        [fresh.id, fresh],
      ]),
    });
    draw(store, {
      kind: 'memory',
      items: [
        { id: 'm1', title: 'Old note' },
        { id: 'm2', title: 'Fresh note' },
        { id: 'm3', title: 'Already approved' },
      ],
    });

    expect(
      container.querySelector('[data-slot="waiting-items-count"]')?.textContent,
    ).toBe('2 memory entries waiting for your review');
    const titles = [
      ...container.querySelectorAll('[data-slot="memory-row"]'),
    ].map((row) => row.getAttribute('data-memory-id'));
    expect(titles).toEqual(['m2', 'm1']);
    expect(
      container.querySelector('[data-slot="waiting-items-decided"]')
        ?.textContent,
    ).toContain('Already approved');
  });

  it('shows three of a long summary and the rest behind Show all', () => {
    const entries = ['a', 'b', 'c', 'd', 'e'].map((id, index) =>
      pendingEntry(id, `Note ${id}`, `2026-11-0${index + 1}`),
    );
    const { store } = storeOf({
      memories: new Map(entries.map((entry) => [entry.id, entry])),
    });
    draw(store, {
      kind: 'memory',
      items: entries.map((entry) => ({ id: entry.id, title: entry.title })),
    });

    expect(container.querySelectorAll('[data-slot="memory-row"]')).toHaveLength(
      3,
    );
    act(() => buttonNamed('Show all 5 memory entries')?.click());
    expect(container.querySelectorAll('[data-slot="memory-row"]')).toHaveLength(
      5,
    );
  });

  it('stays a reviewed card once nothing waits, listing each item with its outcome', async () => {
    const made = storeOf();
    made.listLessonProposals.mockResolvedValue({
      proposals: [
        { ...proposal('p1'), status: 'saved' },
        { ...proposal('p2'), status: 'rejected' },
      ],
    });
    await act(async () => {
      draw(made.store, {
        kind: 'lesson',
        items: [
          { id: 'p1', title: 'one' },
          { id: 'p2', title: 'two' },
        ],
      });
    });

    expect(decidedCard()?.textContent).toContain('Reviewed');
    expect(container.textContent).toContain('2 decided');
    expect(resolvedLines()).toEqual(['one — saved', 'two — rejected']);
    expect(buttonNamed('Approve')).toBeUndefined();
  });

  it('shows the first outcomes of a long reviewed summary and the rest behind Show all', async () => {
    const ids = ['a', 'b', 'c', 'd', 'e', 'f', 'g'];
    const made = storeOf();
    await act(async () => {
      draw(made.store, {
        kind: 'memory',
        items: ids.map((id) => ({ id, title: `Note ${id}` })),
      });
    });

    expect(decidedCard()?.textContent).toContain('7 memory entries');
    expect(resolvedLines()).toEqual([
      'Note a — approved',
      'Note b — approved',
      'Note c — approved',
    ]);
    act(() => buttonNamed('Show all 7 memory entries')?.click());
    expect(resolvedLines()).toHaveLength(7);
  });

  it('offers every entry of a summary the same actions as Settings', async () => {
    const entries = ['a', 'b'].map((id, index) =>
      pendingEntry(id, `Note ${id}`, `2026-11-0${index + 1}`),
    );
    const { store } = storeOf({
      memories: new Map(entries.map((entry) => [entry.id, entry])),
    });
    draw(store, {
      kind: 'memory',
      items: entries.map((entry) => ({ id: entry.id, title: entry.title })),
    });

    const rows = [
      ...container.querySelectorAll<HTMLElement>('[data-slot="memory-row"]'),
    ];
    expect(rows).toHaveLength(2);
    for (const row of rows) {
      expect(buttonIn(row, 'Approve')).toBeDefined();
      expect(await memoryRowActions(row)).toEqual(['Edit', 'Forget…']);
    }
  });

  it('keeps the waiting items and adds an N decided line to a summary', async () => {
    const fresh = pendingEntry('m2', 'Fresh note', '2026-11-20');
    const made = storeOf({ memories: new Map([[fresh.id, fresh]]) });
    await act(async () => {
      draw(made.store, {
        kind: 'memory',
        items: [
          { id: 'm2', title: 'Fresh note' },
          { id: 'm3', title: 'Already approved' },
        ],
      });
    });

    expect(
      container.querySelector('[data-slot="waiting-items-count"]')?.textContent,
    ).toBe('1 memory entry waiting for your review');
    expect(
      container.querySelector('[data-slot="waiting-items-decided"]')
        ?.textContent,
    ).toContain('1 decided');
    expect(made.readMemory).toHaveBeenCalledTimes(1);
    expect(made.readMemory).toHaveBeenCalledWith({ memoryId: 'm3' });
  });

  it('draws the title alone before a kind has loaded', () => {
    const { store } = storeOf({ memories: null });
    draw(store, {
      kind: 'memory',
      items: [{ id: 'm1', title: 'Never edit a sent invoice' }],
    });

    expect(container.textContent).toContain('Never edit a sent invoice');
    expect(container.querySelector('button')).toBeNull();
  });

  it('draws titles alone, read-only, without a store', () => {
    draw(null, {
      kind: 'knowledge',
      items: [
        { id: 'r1', title: 'Release checklist' },
        { id: 'r2', title: 'Style guide' },
      ],
    });

    expect(container.textContent).toContain('Release checklist');
    expect(container.textContent).toContain('Style guide');
    expect(container.querySelector('button')).toBeNull();
  });
});
