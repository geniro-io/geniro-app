type Kind = WaitingItemsRowView['kind'];
type Item = WaitingItemsRowView['items'][number];

interface Resolution {
  outcome: string | null;
  /** The item's live title, where it can be read: the one its waiting card showed. */
  title: string | null;
}

const SUMMARY_SHOWN = 3;
const DECIDED_LESSON_STATUSES = 'saved,rejected,undone';
const DECIDED_WORDS: Record<string, string> = {
  saved: 'saved',
  rejected: 'rejected',
  undone: 'undone',
};

const KIND_WORDS: Record<Kind, { one: string; many: string }> = {
  memory: { one: 'memory entry', many: 'memory entries' },
  lesson: { one: 'lesson', many: 'lessons' },
  knowledge: { one: 'knowledge change', many: 'knowledge changes' },
};

function stampOf(store: WaitingItemsStore, kind: Kind, id: string): string {
  switch (kind) {
    case 'memory':
      return store.memories?.get(id)?.updatedAt ?? '';
    case 'lesson':
      return store.lessons?.get(id)?.createdAt ?? '';
    case 'knowledge':
      return store.knowledge?.get(id)?.createdAt ?? '';
  }
}

function stillWaiting(
  store: WaitingItemsStore,
  kind: Kind,
  items: readonly Item[],
): { waiting: Item[]; resolved: Item[] } | null {
  const held = heldOf(store, kind);
  if (held === null) {
    return null;
  }
  return {
    waiting: items
      .filter((item) => held.has(item.id))
      .sort((a, b) =>
        stampOf(store, kind, b.id).localeCompare(stampOf(store, kind, a.id)),
      ),
    resolved: items.filter((item) => !held.has(item.id)),
  };
}

const NO_LONGER_WAITING = 'no longer waiting';

function heldOf(
  store: WaitingItemsStore,
  kind: Kind,
): ReadonlyMap<string, unknown> | null {
  return kind === 'memory'
    ? store.memories
    : kind === 'lesson'
      ? store.lessons
      : store.knowledge;
}

async function readOutcomes(
  { apis }: WaitingItemsStore,
  kind: Kind,
  ids: readonly string[],
): Promise<ReadonlyMap<string, Resolution>> {
  const found = new Map<string, Resolution>();
  switch (kind) {
    case 'memory':
      await Promise.all(
        ids.map(async (id) => {
          const entry = await apis.memories
            .readMemory({ memoryId: id })
            .catch(() => null);
          if (entry === null) {
            return;
          }
          found.set(id, {
            outcome:
              entry.status === 'active'
                ? 'approved'
                : entry.status === 'forgotten'
                  ? 'forgotten'
                  : null,
            title: entry.title,
          });
        }),
      );
      return found;
    case 'lesson': {
      const { proposals } = await apis.lessons.listLessonProposals({
        status: DECIDED_LESSON_STATUSES,
      });
      const wanted = new Set(ids);
      for (const proposal of proposals) {
        if (wanted.has(proposal.id)) {
          found.set(proposal.id, {
            outcome: proposal.status,
            title: proposal.title,
          });
        }
      }
      return found;
    }
    case 'knowledge':
      await Promise.all(
        ids.map(async (id) => {
          const revision = await apis.knowledge
            .readKnowledgeRevision({ revisionId: id })
            .catch(() => null);
          if (revision?.status === 'applied') {
            found.set(id, { outcome: 'approved', title: null });
          } else if (revision?.status === 'rejected') {
            found.set(id, { outcome: 'rejected', title: null });
          }
        }),
      );
      return found;
  }
}

function useResolvedOutcomes(
  store: WaitingItemsStore | null,
  kind: Kind,
  resolved: readonly Item[],
): ReadonlyMap<string, Resolution> {
  const [outcomes, setOutcomes] = useState<ReadonlyMap<string, Resolution>>(
    new Map(),
  );
  const key = resolved.map((item) => item.id).join('\n');
  const held = store === null ? null : heldOf(store, kind);
  const apis = store?.apis ?? null;
  useEffect(() => {
    if (store === null || key === '') {
      return;
    }
    let live = true;
    readOutcomes(store, kind, key.split('\n')).then(
      (read) => {
        if (live) {
          setOutcomes(read);
        }
      },
      () => undefined,
    );
    return () => {
      live = false;
    };
  }, [apis, kind, key, held]);
  return outcomes;
}

function resolvedText(
  outcomes: ReadonlyMap<string, Resolution>,
  item: Item,
): string {
  const read = outcomes.get(item.id);
  const outcome = read?.outcome ?? null;
  const words =
    outcome === null ? NO_LONGER_WAITING : (DECIDED_WORDS[outcome] ?? outcome);
  return `${read?.title ?? item.title} — ${words}`;
}

function ResolvedLine({ text }: { text: string }): React.JSX.Element {
  return (
    <p
      data-slot="waiting-items-resolved"
      className="m-0 text-sm break-words text-foreground/80">
      {text}
    </p>
  );
}

function ResolvedList({
  items,
  outcomes,
  noun,
  nounOne,
}: {
  items: readonly Item[];
  outcomes: ReadonlyMap<string, Resolution>;
  noun: string;
  nounOne: string;
}): React.JSX.Element {
  const { shown, expanded, setExpanded } = useShowAll(items, SUMMARY_SHOWN);
  return (
    <div data-slot="waiting-items-decided" className="flex flex-col gap-1">
      <p className="m-0 text-xs text-muted-foreground">
        {items.length} decided
      </p>
      {shown.length === 0 ? null : (
        <ul className="m-0 flex list-none flex-col gap-1 p-0">
          {shown.map((item) => (
            <li key={item.id} className="min-w-0">
              <ResolvedLine text={resolvedText(outcomes, item)} />
            </li>
          ))}
        </ul>
      )}
      <ShowAllButton
        total={items.length}
        limit={SUMMARY_SHOWN}
        expanded={expanded}
        noun={noun}
        nounOne={nounOne}
        onToggle={() => setExpanded(!expanded)}
      />
    </div>
  );
}

function Frame({
  kind,
  heading,
  decided = false,
  children,
}: {
  kind: Kind;
  heading: string;
  /** Nothing in it waits any more: it says it was reviewed, and what became of each item. */
  decided?: boolean;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <div
      data-slot="waiting-items-card"
      data-kind={kind}
      data-decided={decided ? '' : undefined}
      className={cn(
        'flex min-w-0 flex-col gap-2 rounded-card border border-border border-l-2 bg-card px-3 py-2',
        decided ? 'border-l-success/50 opacity-80' : 'border-l-warning/50',
      )}>
      <EventLine
        icon={decided ? CircleCheck : Inbox}
        tone={decided ? 'success' : 'warning'}
        label={decided ? 'Reviewed' : 'Waiting for your review'}
        slot="waiting-items"
        member={heading}
      />
      {children}
    </div>
  );
}

function OpenLink({
  label,
  onOpen,
}: {
  label: string;
  onOpen: () => void;
}): React.JSX.Element {
  return (
    <Button
      type="button"
      variant="link"
      size="sm"
      className="h-auto self-start p-0 text-xs"
      onClick={onOpen}>
      {label}
    </Button>
  );
}

function MemoryItem({
  store,
  id,
}: {
  store: WaitingItemsStore;
  id: string;
}): React.JSX.Element | null {
  const openMemory = useContext(MemoryOpenContext);
  const [error, setError] = useState<string | null>(null);
  const editor = useMemoryEditor(store.apis.memories, {
    onSaved: store.reloadMemories,
    onStatusError: setError,
  });
  const entry = store.memories?.get(id);
  if (entry === undefined) {
    return null;
  }
  const editing =
    editor.editing?.kind === 'edit' && editor.editing.entry.id === entry.id
      ? editor.editing
      : null;
  const projectName =
    entry.projectId === null
      ? null
      : (store.projects.find((project) => project.id === entry.projectId)
          ?.name ?? null);
  const teamName =
    entry.teamSlug === null
      ? null
      : (store.teams.find((team) => team.slug === entry.teamSlug)?.name ??
        entry.teamSlug);
  return (
    <div className="flex min-w-0 flex-col gap-1">
      {editing === null ? (
        <MemoryRow
          entry={entry}
          projectName={projectName}
          teamName={teamName}
          showStatus={false}
          busy={editor.busy === entry.id}
          onEdit={() => {
            editor.setFormError(null);
            editor.setEditing(editingOf(entry));
          }}
          onForget={() => editor.setStatus(entry, 'forgotten')}
          onApprove={
            awaitsApproval(entry)
              ? () => void editor.setStatus(entry, 'active')
              : undefined
          }
        />
      ) : (
        <MemoryForm
          value={editing.value}
          projects={store.projects}
          teams={store.teams}
          saving={editor.saving}
          error={editor.formError}
          submitLabel="Save"
          onChange={(value) =>
            editor.setEditing({ ...editing, value, vouched: [] })
          }
          onSubmit={() => void editor.submit()}
          onCancel={editor.close}
        />
      )}
      {error === null ? null : (
        <p
          role="alert"
          data-slot="waiting-items-error"
          className="m-0 px-2 text-xs text-destructive">
          {error}
        </p>
      )}
      {openMemory === null || editing !== null ? null : (
        <div className="px-2">
          <OpenLink
            label="Open in Settings → Memory"
            onOpen={() => openMemory(entry.handle)}
          />
        </div>
      )}
    </div>
  );
}

function LessonItem({
  store,
  id,
}: {
  store: WaitingItemsStore;
  id: string;
}): React.JSX.Element | null {
  const proposal = store.lessons?.get(id);
  if (proposal === undefined) {
    return null;
  }
  return (
    <LessonProposalRow
      proposal={proposal}
      lessonsApi={store.apis.lessons}
      readDocuments={documentsReaderOf(store.apis.knowledge)}
      onChanged={store.reloadLessons}
    />
  );
}

function KnowledgeReviewDialog({
  store,
  revision: head,
  onClose,
}: {
  store: WaitingItemsStore;
  revision: KnowledgeRevisionHead;
  onClose: () => void;
}): React.JSX.Element {
  const openKnowledge = useContext(KnowledgeOpenContext);
  const [detail, setDetail] = useState<KnowledgeRevisionDetailDto | null>(null);
  const [error, setError] = useState<string | null>(null);
  const { knowledge } = store.apis;

  useEffect(() => {
    let live = true;
    knowledge.readKnowledgeRevision({ revisionId: head.id }).then(
      (read) => {
        if (live) {
          setDetail(read);
        }
      },
      (err: unknown) => {
        if (live) {
          setError(describeDaemonError(err));
        }
      },
    );
    return () => {
      live = false;
    };
  }, [knowledge, head.id]);

  const decide = async (kind: 'approve' | 'reject'): Promise<void> => {
    try {
      if (kind === 'approve') {
        await knowledge.approveKnowledgeRevision({ revisionId: head.id });
      } else {
        await knowledge.rejectKnowledgeRevision({ revisionId: head.id });
      }
      store.reloadKnowledge();
      onClose();
    } catch (err: unknown) {
      if (daemonErrorCode(err) === 'PROPOSAL_STALE') {
        setDetail(
          await knowledge.readKnowledgeRevision({ revisionId: head.id }),
        );
        return;
      }
      setError(describeDaemonError(err));
    }
  };

  return (
    <Dialog open onClose={onClose} title="Waiting for review">
      {detail === null ? (
        <p className="m-0 text-sm text-muted-foreground">
          {error ?? 'Loading…'}
        </p>
      ) : (
        <div className="flex min-w-0 flex-col gap-3">
          <KnowledgeReview
            revision={detail}
            onBack={onClose}
            onApprove={() => decide('approve')}
            onReject={() => decide('reject')}
            onOpenDocument={() => {
              onClose();
              openKnowledge?.({ documentId: detail.documentId });
            }}
          />
          {error === null ? null : (
            <p role="alert" className="m-0 text-xs text-destructive">
              {error}
            </p>
          )}
        </div>
      )}
    </Dialog>
  );
}

function KnowledgeItem({
  store,
  id,
}: {
  store: WaitingItemsStore;
  id: string;
}): React.JSX.Element | null {
  const openKnowledge = useContext(KnowledgeOpenContext);
  const [reviewing, setReviewing] = useState(false);
  const revision = store.knowledge?.get(id);
  if (revision === undefined) {
    return null;
  }
  return (
    <div
      data-slot="waiting-knowledge"
      className="flex min-w-0 flex-col gap-1.5 px-2 py-1">
      <span className="text-sm font-medium break-words">{revision.title}</span>
      <span className="text-xs text-muted-foreground">
        Proposed by {byLine(revision.source)}
      </span>
      <div className="flex flex-wrap items-center gap-3">
        <Button
          type="button"
          size="sm"
          variant="outline"
          className="h-7 rounded-control px-2.5 text-xs"
          onClick={() => setReviewing(true)}>
          Review
        </Button>
        {openKnowledge === null ? null : (
          <OpenLink
            label="Open in Knowledge"
            onOpen={() => openKnowledge({ documentId: revision.documentId })}
          />
        )}
      </div>
      {reviewing ? (
        <KnowledgeReviewDialog
          store={store}
          revision={revision}
          onClose={() => setReviewing(false)}
        />
      ) : null}
    </div>
  );
}

function ItemBody({
  store,
  kind,
  id,
}: {
  store: WaitingItemsStore;
  kind: Kind;
  id: string;
}): React.JSX.Element | null {
  switch (kind) {
    case 'memory':
      return <MemoryItem store={store} id={id} />;
    case 'lesson':
      return <LessonItem store={store} id={id} />;
    case 'knowledge':
      return <KnowledgeItem store={store} id={id} />;
  }
}

function Summary({
  store,
  kind,
  waiting,
  resolved,
  outcomes,
}: {
  store: WaitingItemsStore;
  kind: Kind;
  waiting: readonly Item[];
  resolved: readonly Item[];
  outcomes: ReadonlyMap<string, Resolution>;
}): React.JSX.Element {
  const { shown, expanded, setExpanded } = useShowAll(waiting, SUMMARY_SHOWN);
  const words = KIND_WORDS[kind];
  return (
    <Frame
      kind={kind}
      heading={`${waiting.length} ${waiting.length === 1 ? words.one : words.many}`}>
      <p data-slot="waiting-items-count" className="m-0 text-sm">
        {waiting.length} {waiting.length === 1 ? words.one : words.many} waiting
        for your review
      </p>
      <ul className="m-0 flex list-none flex-col divide-y divide-border p-0">
        {shown.map((item) => (
          <li
            key={item.id}
            data-slot="waiting-items-item"
            className="min-w-0 py-2 first:pt-0 last:pb-0">
            <ItemBody store={store} kind={kind} id={item.id} />
          </li>
        ))}
      </ul>
      <ShowAllButton
        total={waiting.length}
        limit={SUMMARY_SHOWN}
        expanded={expanded}
        noun={words.many}
        nounOne={words.one}
        onToggle={() => setExpanded(!expanded)}
      />
      {resolved.length === 0 ? null : (
        <ResolvedList
          items={resolved}
          outcomes={outcomes}
          noun={words.many}
          nounOne={words.one}
        />
      )}
    </Frame>
  );
}

function TitlesOnly({
  row,
  items,
}: {
  row: WaitingItemsRowView;
  items: readonly Item[];
}): React.JSX.Element {
  const words = KIND_WORDS[row.kind];
  return (
    <Frame
      kind={row.kind}
      heading={
        items.length === 1 ? words.one : `${items.length} ${words.many}`
      }>
      <ul
        data-slot="waiting-items-titles"
        className="m-0 flex list-none flex-col gap-1 p-0">
        {items.map((item) => (
          <li key={item.id} className="min-w-0 text-sm break-words">
            {item.title}
          </li>
        ))}
      </ul>
    </Frame>
  );
}

/**
 * The manager's announce of items waiting for the user's review: one item as
 * its Settings row with the same actions, several as a count of those still
 * waiting; once nothing waits, a reviewed card saying what became of each.
 * Outside the manager's chat, or before the lists load, only titles.
 */
export function WaitingItemsCard({
  row,
}: {
  row: WaitingItemsRowView;
}): React.JSX.Element {
  const store = useContext(WaitingItemsContext);
  const split =
    store === null ? null : stillWaiting(store, row.kind, row.items);
  const outcomes = useResolvedOutcomes(store, row.kind, split?.resolved ?? []);
  const words = KIND_WORDS[row.kind];
  if (store === null || split === null) {
    return <TitlesOnly row={row} items={row.items} />;
  }
  const { waiting, resolved } = split;
  const [only] = row.items;
  if (row.items.length === 1 && only !== undefined) {
    return waiting.length === 0 ? (
      <Frame kind={row.kind} heading={words.one} decided>
        <ResolvedLine text={resolvedText(outcomes, only)} />
      </Frame>
    ) : (
      <Frame kind={row.kind} heading={words.one}>
        <ItemBody store={store} kind={row.kind} id={waiting[0]?.id ?? ''} />
      </Frame>
    );
  }
  if (waiting.length === 0) {
    return (
      <Frame
        kind={row.kind}
        heading={`${resolved.length} ${resolved.length === 1 ? words.one : words.many}`}
        decided>
        <ResolvedList
          items={resolved}
          outcomes={outcomes}
          noun={words.many}
          nounOne={words.one}
        />
      </Frame>
    );
  }
  return (
    <Summary
      store={store}
      kind={row.kind}
      waiting={waiting}
      resolved={resolved}
      outcomes={outcomes}
    />
  );
}
