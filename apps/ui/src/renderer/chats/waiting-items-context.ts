import { createContext } from 'react';

import type {
  KnowledgeRevisionHead,
  LessonProposal,
  MemoryEntry,
} from '../autogenerated';
import type { MemoryTeamOption } from '../components/memory-form';
import type { DaemonApis } from '../daemon-api';

export interface WaitingItemsStore {
  apis: DaemonApis;
  /** Pending memory entries by id; null until the first read answers. */
  memories: ReadonlyMap<string, MemoryEntry> | null;
  /** Lesson proposals waiting on the user by id; null until the first read answers. */
  lessons: ReadonlyMap<string, LessonProposal> | null;
  /** Pending knowledge revisions by revision id; null until the first read answers. */
  knowledge: ReadonlyMap<string, KnowledgeRevisionHead> | null;
  /** The projects an entry may name, for its scope line and its edit form. */
  projects: readonly { id: string; name: string }[];
  /** The library teams an entry may name, for its scope line and its edit form. */
  teams: readonly MemoryTeamOption[];
  reloadMemories: () => void;
  reloadLessons: () => void;
  reloadKnowledge: () => void;
}

/** Null outside the command center manager's chat, where a waiting card is read-only. */
export const WaitingItemsContext = createContext<WaitingItemsStore | null>(
  null,
);
