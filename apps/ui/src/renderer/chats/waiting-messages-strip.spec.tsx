// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type {
  DeliveredWaitingMessageDto,
  WaitingMessageDto,
} from '../autogenerated';
import {
  WAITING_STRIP_ROWS,
  WaitingMessagesStrip,
} from './waiting-messages-strip';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function waiting(
  id: string,
  reason: WaitingMessageDto['reason'] = 'sender_opted_out',
): WaitingMessageDto {
  return {
    id,
    fromRunId: 'r-pelican',
    fromTitle: 'Pelican',
    fromMember: null,
    text: `text of ${id}`,
    reason,
    createdAt: '2026-11-11T10:00:00Z',
  };
}

let root: Root | null = null;
let container: HTMLDivElement | null = null;

async function render(
  messages: WaitingMessageDto[],
  onDeliver: (
    id: string,
  ) => Promise<DeliveredWaitingMessageDto> = async () => ({
    outcome: 'woken',
    reason: null,
  }),
  onRemove: (id: string) => Promise<void> = async () => undefined,
): Promise<HTMLDivElement> {
  container = document.createElement('div');
  root = createRoot(container);
  await act(async () => {
    root!.render(
      <WaitingMessagesStrip
        messages={messages}
        onDeliver={onDeliver}
        onRemove={onRemove}
      />,
    );
  });
  return container;
}

function buttons(name: string): HTMLButtonElement[] {
  return [...(container?.querySelectorAll('button') ?? [])].filter(
    (button) => button.textContent === name,
  );
}

afterEach(() => {
  act(() => root?.unmount());
  root = null;
  container = null;
});

describe('WaitingMessagesStrip', () => {
  it('draws nothing while no message waits', async () => {
    const view = await render([]);
    expect(view.innerHTML).toBe('');
  });

  it('shows who sent each message, why it waits and its text', async () => {
    const view = await render([waiting('w1')]);
    const text = view.textContent ?? '';
    expect(text).toContain('Message from');
    expect(text).toContain('Pelican');
    expect(text).toContain('the sender did not wake this thread');
    expect(text).toContain('text of w1');
  });

  it('offers Deliver now only where a turn opening is all the message waits for', async () => {
    await render([
      waiting('quiet', 'sender_opted_out'),
      waiting('cold', 'cold_and_large'),
      waiting('stopped', 'stopped'),
    ]);
    expect(buttons('Deliver now')).toHaveLength(2);
    expect(buttons('Remove')).toHaveLength(3);
  });

  it('delivers on a press and says why when the daemon left it waiting', async () => {
    const onDeliver = vi.fn(async (): Promise<DeliveredWaitingMessageDto> => ({
      outcome: 'waiting',
      reason: 'question',
    }));
    const view = await render([waiting('w1')], onDeliver);

    await act(async () => buttons('Deliver now')[0]!.click());

    expect(onDeliver).toHaveBeenCalledWith('w1');
    expect(view.textContent).toContain(
      'Not delivered: Goes out once you have answered',
    );
  });

  it('holds the buttons once a turn was opened for it', async () => {
    await render([waiting('w1')]);

    await act(async () => buttons('Deliver now')[0]!.click());

    expect(buttons('Delivering…')[0]?.disabled).toBe(true);
    expect(buttons('Remove')[0]?.disabled).toBe(true);
  });

  it('shows the refusal when a removal fails', async () => {
    const view = await render([waiting('w1')], undefined, async () => {
      throw new Error('a turn starting now has already read this message');
    });

    await act(async () => buttons('Remove')[0]!.click());

    expect(view.textContent).toContain('already read this message');
  });

  it('draws the oldest few and counts the rest', async () => {
    const many = Array.from({ length: WAITING_STRIP_ROWS + 2 }, (_, index) =>
      waiting(`w${index}`),
    );
    const view = await render(many);

    expect(
      view.querySelectorAll('[data-slot="waiting-message-strip-row"]'),
    ).toHaveLength(WAITING_STRIP_ROWS);
    expect(view.textContent).toContain('2 more waiting');
  });
});
