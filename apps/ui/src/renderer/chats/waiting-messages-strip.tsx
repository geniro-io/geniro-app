import { Mail } from 'lucide-react';
import { useState } from 'react';

import type {
  DeliveredWaitingMessageDto,
  WaitingMessageDto,
} from '../autogenerated';
import { ClampedText } from '../components/clamped-text';
import { ErrorText } from '../components/error-text';
import { Button } from '../components/ui/button';
import { describeDaemonError } from '../daemon-api';
import { ThreadTitle } from './thread-message-card';
import {
  type ThreadMessageReason,
  waitingMessageReasonWords,
} from './thread-message-payload';

/** Rows drawn above the composer; the rest stay one press away in the shelf's chip. */
export const WAITING_STRIP_ROWS = 3;

/** Reasons only a turn opening would end, which the user's press opens. */
const DELIVERABLE: ReadonlySet<ThreadMessageReason> = new Set([
  'sender_opted_out',
  'cold_and_large',
  'wake_limit',
]);

/**
 * The messages other threads sent this one that still wait for its next turn,
 * above the composer: who sent each, why it waits, its first lines, and
 * Deliver now where a turn opening is all it waits for.
 */
export function WaitingMessagesStrip({
  messages,
  onDeliver,
  onRemove,
}: {
  /** Oldest first, as the daemon lists them. */
  messages: readonly WaitingMessageDto[];
  onDeliver: (messageId: string) => Promise<DeliveredWaitingMessageDto>;
  onRemove: (messageId: string) => Promise<void>;
}): React.JSX.Element | null {
  if (messages.length === 0) {
    return null;
  }
  const shown = messages.slice(0, WAITING_STRIP_ROWS);
  const more = messages.length - shown.length;
  return (
    <div
      role="group"
      aria-label="Messages from other threads"
      data-slot="waiting-messages-strip"
      className="flex flex-col gap-1">
      {shown.map((message) => (
        <WaitingMessageStripRow
          key={message.id}
          message={message}
          onDeliver={onDeliver}
          onRemove={onRemove}
        />
      ))}
      {more > 0 ? (
        <span className="px-2 text-xs text-muted-foreground">
          {more} more waiting — listed under the shelf&apos;s mail counter
        </span>
      ) : null}
    </div>
  );
}

type RowPhase =
  | { kind: 'idle' }
  | { kind: 'busy' }
  | { kind: 'sent' }
  | { kind: 'refused'; text: string };

function WaitingMessageStripRow({
  message,
  onDeliver,
  onRemove,
}: {
  message: WaitingMessageDto;
  onDeliver: (messageId: string) => Promise<DeliveredWaitingMessageDto>;
  onRemove: (messageId: string) => Promise<void>;
}): React.JSX.Element {
  const [phase, setPhase] = useState<RowPhase>({ kind: 'idle' });
  const deliverable =
    message.reason !== null && DELIVERABLE.has(message.reason);
  const deliver = async (): Promise<void> => {
    setPhase({ kind: 'busy' });
    try {
      const answer = await onDeliver(message.id);
      setPhase(
        answer.outcome === 'waiting'
          ? {
              kind: 'refused',
              text:
                answer.reason === null
                  ? 'Not delivered yet.'
                  : `Not delivered: ${waitingMessageReasonWords(answer.reason)}.`,
            }
          : { kind: 'sent' },
      );
    } catch (err) {
      setPhase({ kind: 'refused', text: describeDaemonError(err) });
    }
  };
  const remove = async (): Promise<void> => {
    setPhase({ kind: 'busy' });
    try {
      await onRemove(message.id);
    } catch (err) {
      setPhase({ kind: 'refused', text: describeDaemonError(err) });
    }
  };
  const busy = phase.kind === 'busy' || phase.kind === 'sent';
  return (
    <div
      data-slot="waiting-message-strip-row"
      className="flex min-w-0 flex-col gap-0.5 rounded-md bg-muted/50 px-2 py-1.5 text-xs">
      <div className="flex min-w-0 items-center gap-1.5">
        <Mail
          aria-hidden="true"
          className="size-3 shrink-0 text-muted-foreground"
        />
        <span className="flex min-w-0 flex-1 flex-wrap items-center gap-x-1 text-muted-foreground">
          <span>Message from</span>
          <ThreadTitle runId={message.fromRunId} title={message.fromTitle} />
          {message.fromMember === null ? null : (
            <span>· {message.fromMember}</span>
          )}
        </span>
        {deliverable ? (
          <Button
            type="button"
            variant="ghost"
            size="sm"
            className="h-6 shrink-0 px-1.5 text-xs"
            disabled={busy}
            title="Open a turn in this thread now; the agent reads this message"
            onClick={() => void deliver()}>
            {phase.kind === 'sent' ? 'Delivering…' : 'Deliver now'}
          </Button>
        ) : null}
        <Button
          type="button"
          variant="ghost"
          size="sm"
          className="h-6 shrink-0 px-1.5 text-xs"
          disabled={busy}
          onClick={() => void remove()}>
          Remove
        </Button>
      </div>
      {message.reason === null ? null : (
        <span className="min-w-0 break-words text-muted-foreground">
          {waitingMessageReasonWords(message.reason)}
        </span>
      )}
      <ClampedText
        text={message.text}
        lines={2}
        slot="waiting-message-strip-text"
        className="text-foreground"
      />
      {phase.kind === 'refused' ? (
        <ErrorText className="text-xs">{phase.text}</ErrorText>
      ) : null}
    </div>
  );
}
