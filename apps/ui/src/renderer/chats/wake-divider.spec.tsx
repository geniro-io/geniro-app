// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import { RevealCallContext } from './call-block';
import { TranscriptItem } from './transcript-item';
import { readWakeNotice } from './wake-payload';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;

afterEach(() => {
  act(() => root?.unmount());
  root = null;
  document.body.innerHTML = '';
});

function mount(element: React.ReactElement): HTMLElement {
  const container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  act(() => {
    root!.render(element);
  });
  return container;
}

const wakeRow = (payload: Record<string, unknown>): ChatItem => ({
  id: 'i1',
  runId: 'r1',
  nodeId: 'manager',
  seq: 1,
  kind: 'system',
  role: null,
  payload,
  createdAt: '2026-09-23T12:00:00Z',
});

const WAKE = {
  severity: 'info',
  message: 'Picked back up — Researcher finished call-7.',
  wake: [{ callId: 'call-7', callee: 'Researcher', reason: 'finished' }],
};

describe('readWakeNotice', () => {
  it('reads the calls a wake was about, and nothing else', () => {
    expect(readWakeNotice(WAKE)).toEqual([
      { callId: 'call-7', callee: 'Researcher', reason: 'finished' },
    ]);
    expect(readWakeNotice({ message: 'plain notice' })).toBeNull();
    expect(
      readWakeNotice({
        wake: [{ callId: 'call-7', callee: 'Researcher', reason: 'slept' }],
      }),
    ).toBeNull();
  });
});

describe('the wake divider', () => {
  it('replaces the engine sentence with who picked back up, and why', () => {
    const el = mount(
      <TranscriptItem
        item={wakeRow(WAKE)}
        nodes={new Map([['manager', { name: 'Manager', kind: 'agent' }]])}
      />,
    );
    const divider = el.querySelector('[data-slot="wake-divider"]');
    expect(divider?.textContent).toContain(
      'Manager picked back up — Researcher finished call-7',
    );
    // The divider, not the daemon's plain sentence drawn as a note.
    expect(el.textContent).not.toContain('Picked back up');
  });

  it('opens the call’s card when the call is pressed', () => {
    const revealed: string[] = [];
    const el = mount(
      <RevealCallContext.Provider
        value={(callId) => () => {
          revealed.push(callId);
        }}>
        <TranscriptItem item={wakeRow(WAKE)} />
      </RevealCallContext.Provider>,
    );
    act(() => {
      el.querySelector<HTMLButtonElement>(
        '[data-slot="wake-divider-call"]',
      )!.click();
    });
    expect(revealed).toEqual(['call-7']);
  });

  it('draws plain text when the call’s card is not loaded', () => {
    const el = mount(
      <RevealCallContext.Provider value={() => null}>
        <TranscriptItem item={wakeRow(WAKE)} />
      </RevealCallContext.Provider>,
    );
    expect(el.querySelector('[data-slot="wake-divider-call"]')).toBeNull();
    expect(el.textContent).toContain('Researcher finished call-7');
  });

  it('draws plain text, not a dead control, with no way to reveal', () => {
    const el = mount(<TranscriptItem item={wakeRow(WAKE)} />);
    expect(el.querySelector('[data-slot="wake-divider-call"]')).toBeNull();
    expect(el.textContent).toContain('Researcher finished call-7');
  });
});
