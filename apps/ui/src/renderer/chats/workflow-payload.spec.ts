import { describe, expect, it } from 'vitest';

import type { ItemDto as ChatItem } from '../autogenerated';
import {
  mergeWorkflowDeclarations,
  readWorkflowDeclaration,
  workflowTally,
} from './workflow-payload';

let seq = 0;
function row(payload: unknown): ChatItem {
  seq += 1;
  return {
    id: `i-${seq}`,
    runId: 'run-1',
    nodeId: null,
    seq,
    kind: 'workflow_info',
    role: null,
    payload,
    createdAt: 'now',
  };
}

const agent = (index: number, over: Record<string, unknown> = {}) => ({
  index,
  label: `probe-${index}`,
  phase: 'Probe',
  state: 'done',
  model: 'claude-haiku-4-5-20251001',
  tokens: 13779,
  toolCalls: 0,
  durationMs: 1303,
  error: null,
  ...over,
});

describe('readWorkflowDeclaration', () => {
  it('refuses a row that names no launching call', () => {
    // The id is what joins the row to the tool call it describes; without one
    // the card has nothing to replace and nowhere to sit.
    expect(readWorkflowDeclaration(row({ name: 'probe-run' }))).toBeNull();
    expect(readWorkflowDeclaration(row(null))).toBeNull();
  });

  it('tells a MISSING roster from an empty one', () => {
    // Not a nicety: the CLI omits the roster from most progress lines, and the
    // merge below prefers the last non-null field. An absent roster read as `[]`
    // would empty the card every time a snapshot was throttled away.
    expect(readWorkflowDeclaration(row({ id: 'c1' }))?.agents).toBeNull();
    expect(
      readWorkflowDeclaration(row({ id: 'c1', agents: [] }))?.agents,
    ).toEqual([]);
  });

  it('keeps a zero and refuses a NaN', () => {
    // Zero is the first reading every workflow reports and a real one; a NaN
    // crossing JSON would render as `NaN tokens` on the header.
    const zero = readWorkflowDeclaration(row({ id: 'c1', tokens: 0 }));
    expect(zero?.tokens).toBe(0);
    const nan = readWorkflowDeclaration(
      row({ id: 'c1', tokens: Number.NaN, toolUses: '4' }),
    );
    expect(nan?.tokens).toBeNull();
    expect(nan?.toolUses).toBeNull();
  });

  it('drops a roster entry with no index and narrows an unknown state', () => {
    const read = readWorkflowDeclaration(
      row({
        id: 'c1',
        agents: [
          { label: 'nameless' },
          agent(2, { state: 'quantum-superposed' }),
        ],
      }),
    );
    // A state this renderer does not know would otherwise reach the roster as
    // a row with no glyph and no place in the tally.
    expect(read?.agents).toEqual([
      expect.objectContaining({ index: 2, state: 'running' }),
    ]);
  });
});

describe('mergeWorkflowDeclarations', () => {
  it('keeps the name the ANCHOR gave when a progress row carries none', () => {
    // Only the launch line ever states the workflow's name; every row after it
    // reports the description instead. Without the merge the card would lose
    // its identity on the first progress row.
    const anchor = readWorkflowDeclaration(
      row({ id: 'c1', name: 'probe-run', title: 'Two trivial agents' }),
    );
    const progress = readWorkflowDeclaration(
      row({ id: 'c1', title: 'Two trivial agents', tokens: 13779 }),
    );
    expect(anchor && progress).not.toBeNull();
    const merged = mergeWorkflowDeclarations(anchor!, progress!);
    expect(merged.name).toBe('probe-run');
    expect(merged.tokens).toBe(13779);
  });

  it('takes the newer roster WHOLE, never merging it into the older one', () => {
    // The CLI re-sends the entire roster every time it sends one. Index-merging
    // two snapshots would resurrect an agent a later one had dropped, and a
    // roster that only ever grows is the wrong reading for a workflow whose
    // phases retire their agents.
    const first = readWorkflowDeclaration(
      row({ id: 'c1', agents: [agent(1), agent(2)] }),
    );
    const second = readWorkflowDeclaration(
      row({ id: 'c1', agents: [agent(3)] }),
    );
    expect(
      mergeWorkflowDeclarations(first!, second!).agents?.map((a) => a.index),
    ).toEqual([3]);
  });

  it('lets a roster-less row leave the last roster standing', () => {
    const withRoster = readWorkflowDeclaration(
      row({ id: 'c1', agents: [agent(1)] }),
    );
    const without = readWorkflowDeclaration(row({ id: 'c1', tokens: 27559 }));
    const merged = mergeWorkflowDeclarations(withRoster!, without!);
    expect(merged.agents).toHaveLength(1);
    expect(merged.tokens).toBe(27559);
  });
});

describe('workflowTally', () => {
  it('counts the roster by state, which no single CLI figure answers', () => {
    // The CLI's own `agentCount` is a high-water mark it only ever raises. A
    // user watching thirty agents wants to know how many are still out.
    const read = readWorkflowDeclaration(
      row({
        id: 'c1',
        agents: [
          agent(1),
          agent(2, { state: 'running' }),
          agent(3, { state: 'running' }),
          agent(4, { state: 'failed' }),
        ],
      }),
    );
    expect(workflowTally(read?.agents ?? null)).toEqual({
      total: 4,
      running: 2,
      done: 1,
      failed: 1,
    });
  });

  it('answers zeroes for a workflow that has reported no roster yet', () => {
    // Reached on every workflow's first second — the anchor row carries none.
    expect(workflowTally(null)).toEqual({
      total: 0,
      running: 0,
      done: 0,
      failed: 0,
    });
  });
});
