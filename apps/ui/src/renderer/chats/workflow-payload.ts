import type { ItemDto as ChatItem } from '../autogenerated';

/**
 * How ONE agent inside a dynamic workflow is doing.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/adapters/adapter.types.ts` declares
 * the same three as `WorkflowAgentState`, and each CLI's adapter translates its
 * own vocabulary into them. An item payload is `z.unknown()` on the wire BY
 * DESIGN — every item kind carries a different shape — so no generated type
 * spans the two sides and this is an independent reading of one shape: add a
 * word there and it must be added here, or the new word reads as
 * {@link isAgentState} rejecting it.
 */
export type WorkflowAgentState = 'running' | 'done' | 'failed';

const AGENT_STATES: ReadonlySet<string> = new Set<WorkflowAgentState>([
  'running',
  'done',
  'failed',
]);

function isAgentState(value: unknown): value is WorkflowAgentState {
  return typeof value === 'string' && AGENT_STATES.has(value);
}

/** One row of the workflow's agent roster, as of the snapshot carrying it. */
export interface WorkflowAgentRow {
  index: number;
  label: string | null;
  phase: string | null;
  state: WorkflowAgentState;
  model: string | null;
  tokens: number | null;
  toolCalls: number | null;
  durationMs: number | null;
  error: string | null;
}

/**
 * What a `workflow_info` row says about one dynamic workflow.
 *
 * TWIN PARSER: `apps/daemon/src/v1/agents/utils/event-to-item.ts` writes these
 * keys, on the same footing as `subagent_info` beside it — the payload is
 * `z.unknown()` on the wire BY DESIGN, so this is an independent reading of one
 * shape and a rename on either side must be a rename on both.
 *
 * `id` is the LAUNCHING TOOL CALL's id, not the workflow's own: it is what joins
 * this declaration to the row that started it. Deliberately NOT
 * `parentToolUseId` — that key means "the workflow produced this row", and the
 * main thread produced every one of these ABOUT the workflow.
 */
export interface WorkflowDeclaration {
  id: string;
  /** The workflow's own name — its script's `meta.name`. */
  name: string | null;
  /** Its one-line description. */
  title: string | null;
  /** What it is doing right now, as the CLI phrases it: `Phase: label`. */
  activity: string | null;
  /** Every token its agents have spent, and every tool call they have made. */
  tokens: number | null;
  toolUses: number | null;
  durationMs: number | null;
  /**
   * The whole roster as of this row, or null when the row carried none.
   *
   * A SNAPSHOT, never a delta — see {@link mergeWorkflowDeclarations} for why
   * that distinction decides how two rows combine.
   */
  agents: WorkflowAgentRow[] | null;
}

function str(value: unknown): string | null {
  return typeof value === 'string' && value !== '' ? value : null;
}

/**
 * A figure, or null for anything that is not one.
 *
 * `Number.isFinite` and not a bare `typeof`, on `subagent-payload`'s rule: the
 * payload crosses JSON, where a `NaN` that got in would render as `NaN tokens`
 * on the card. Zero IS kept — a workflow whose agents have spent nothing yet is
 * a real reading, and it is the first one every workflow reports.
 */
function num(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

function readAgents(value: unknown): WorkflowAgentRow[] | null {
  if (!Array.isArray(value)) {
    return null;
  }
  const rows: WorkflowAgentRow[] = [];
  for (const entry of value as unknown[]) {
    if (typeof entry !== 'object' || entry === null) {
      continue;
    }
    const record = entry as Record<string, unknown>;
    const index = num(record.index);
    if (index === null) {
      continue;
    }
    rows.push({
      index,
      label: str(record.label),
      phase: str(record.phase),
      // Narrowed against the vocabulary, never cast: this is another process's
      // payload, and a word this renderer does not know would otherwise reach
      // the roster as a state with no glyph and no tally.
      state: isAgentState(record.state) ? record.state : 'running',
      model: str(record.model),
      tokens: num(record.tokens),
      toolCalls: num(record.toolCalls),
      durationMs: num(record.durationMs),
      error: str(record.error),
    });
  }
  return rows;
}

/** Read one `workflow_info` row, or null when it names no call to anchor to. */
export function readWorkflowDeclaration(
  item: ChatItem,
): WorkflowDeclaration | null {
  // `unknown`, not the generated field's own type: the payload is untyped on
  // the wire, so the generator gives it `any` and every read off it would
  // otherwise be unchecked.
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const record = payload as Record<string, unknown>;
  const id = str(record.id);
  if (id === null) {
    return null;
  }
  return {
    id,
    name: str(record.name),
    title: str(record.title),
    activity: str(record.activity),
    tokens: num(record.tokens),
    toolUses: num(record.toolUses),
    durationMs: num(record.durationMs),
    agents: readAgents(record.agents),
  };
}

/**
 * Later non-null fields win; the id is the same by construction.
 *
 * {@link WorkflowDeclaration.agents} follows the same last-non-null rule and
 * that is deliberate rather than incidental: the CLI re-sends the ENTIRE roster
 * every time it sends one, so a later snapshot replaces an earlier one whole.
 * Concatenating or index-merging them would resurrect an agent a later snapshot
 * had dropped, and a roster that only ever grows is exactly the wrong reading
 * for a workflow whose phases retire their agents.
 */
export function mergeWorkflowDeclarations(
  base: WorkflowDeclaration,
  next: WorkflowDeclaration,
): WorkflowDeclaration {
  return {
    id: base.id,
    name: next.name ?? base.name,
    title: next.title ?? base.title,
    activity: next.activity ?? base.activity,
    tokens: next.tokens ?? base.tokens,
    toolUses: next.toolUses ?? base.toolUses,
    durationMs: next.durationMs ?? base.durationMs,
    agents: next.agents ?? base.agents,
  };
}

/** How many agents a workflow has out, finished, and lost. */
export interface WorkflowTally {
  total: number;
  running: number;
  done: number;
  failed: number;
}

/**
 * The roster counted by state — the headline the card is opened for.
 *
 * Derived from the roster rather than read off a field, because the CLI's own
 * `agentCount` is a HIGH-WATER MARK (it is only ever raised, by the highest
 * index it has seen start) and never a breakdown. A user watching thirty agents
 * wants to know how many are still out, which no single number answers.
 */
export function workflowTally(
  agents: readonly WorkflowAgentRow[] | null,
): WorkflowTally {
  const tally: WorkflowTally = { total: 0, running: 0, done: 0, failed: 0 };
  for (const agent of agents ?? []) {
    tally.total += 1;
    tally[agent.state] += 1;
  }
  return tally;
}
