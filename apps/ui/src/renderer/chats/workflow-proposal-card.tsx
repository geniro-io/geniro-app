const WorkflowPreview = lazy(() => import('../workflows/workflow-preview'));

const APPROVAL_LABEL: Record<ApprovalMode, string> = {
  ask: 'Asks first',
  acceptEdits: 'Accepts edits, asks for the rest',
  auto: RUNS_UNASKED_LABEL,
};

function plural(count: number, one: string, many: string): string {
  return `${count} ${count === 1 ? one : many}`;
}

/** Why an approval wrote nothing, in the user's terms. */
function notSavedText(
  cause: NotSavedCause | null,
  proposal: ParsedWorkflowProposal,
): string {
  const name = proposal.replacesName ?? proposal.workflow.name;
  switch (cause) {
    case 'changed':
      return `“${name}” changed after this was proposed, so nothing was overwritten.`;
    case 'exists':
      return `A workflow was saved as “${proposal.slug}” after this was proposed, so nothing was written.`;
    case 'gone':
      return `“${name}” was deleted after this was proposed, and was not re-created.`;
    case 'not-closed':
      return 'The card could not be closed, so nothing was written.';
    case 'write-failed':
      return 'The workflow file could not be written.';
    case null:
      return 'Nothing was written.';
  }
}

function agentLine(
  identities: readonly AgentIdentityCapability[],
  fields: Pick<WorkflowAgentNode, 'agent' | 'model' | 'effort'>,
): string {
  return [agentShortName(identities, fields.agent), fields.model, fields.effort]
    .filter(Boolean)
    .join(' · ');
}

function ApprovalText({ mode }: { mode: ApprovalMode }): React.JSX.Element {
  return mode === 'auto' ? (
    <span className="inline-flex items-center gap-1 font-medium text-warning">
      <ShieldAlert aria-hidden="true" className="size-3 shrink-0" />
      {APPROVAL_LABEL.auto}
    </span>
  ) : (
    <span>{APPROVAL_LABEL[mode]}</span>
  );
}

const MARK_LABEL: Record<PreviewMark, string> = {
  added: 'New',
  changed: 'Changed',
};

/**
 * The proposal's agents, one row each: who it is, what runs it (every pool
 * member too) and whether it asks, then its role and the instruction blocks
 * wired into it. The run settings wrap as chips, so a long role never
 * squeezes them.
 */
function Roster({
  rows,
  marks,
}: {
  rows: readonly RosterRow[];
  marks: ReadonlyMap<string, PreviewMark>;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  return (
    <ul
      aria-label="Agents in this workflow"
      data-slot="workflow-roster"
      className="m-0 flex list-none flex-col p-0 text-xs">
      {rows.map(({ node, instructions }) => {
        const mark = marks.get(node.id);
        return (
          <li
            key={node.id}
            data-agent={node.id}
            className="flex min-w-0 flex-col gap-1 border-t border-border/60 py-2 first:border-t-0 first:pt-0">
            <div className="flex flex-wrap items-center gap-x-2 gap-y-1">
              <span className="min-w-0 font-medium break-words">
                {node.name ?? node.id}
              </span>
              {mark === undefined ? null : <MarkBadge mark={mark} />}
              <span className="ml-auto flex flex-col items-end gap-0.5 text-right">
                <ApprovalText mode={node.approval} />
                {(node.pool ?? []).map((member, index) =>
                  (member.approval ?? node.approval) ===
                  node.approval ? null : (
                    <span key={index}>
                      member {index + 2}:{' '}
                      <ApprovalText mode={member.approval ?? node.approval} />
                    </span>
                  ),
                )}
              </span>
            </div>
            <div className="flex min-w-0 flex-wrap gap-1">
              <Chip>{agentLine(identities, node)}</Chip>
              {(node.pool ?? []).map((member, index) => (
                <Chip key={index}>
                  member {index + 2}: {agentLine(identities, member)}
                </Chip>
              ))}
            </div>
            {node.role ? (
              <p className="m-0 line-clamp-2 break-words text-muted-foreground">
                {node.role}
              </p>
            ) : null}
            {instructions.length > 0 ? (
              <p className="m-0 break-words text-muted-foreground">
                <span className="text-foreground">Instructions:</span>{' '}
                {instructions.join(', ')}
              </p>
            ) : null}
          </li>
        );
      })}
    </ul>
  );
}

function Chip({ children }: { children: React.ReactNode }): React.JSX.Element {
  return (
    <span className="max-w-full rounded-sm bg-muted px-1.5 py-0.5 break-words text-muted-foreground">
      {children}
    </span>
  );
}

/**
 * A section of the card, folded by default: folded, it still shows `changed`
 * (what the proposal adds or changes in it) and says how much is behind the
 * fold; open, it shows `all`.
 */
function Fold({
  noun,
  total,
  replacing,
  open,
  onToggle,
  slot,
  changed,
  all,
}: {
  noun: [one: string, many: string];
  total: number;
  /** A replacement: nothing changed in it is worth saying. */
  replacing: boolean;
  open: boolean;
  onToggle: () => void;
  slot: string;
  changed: { count: number; content: React.ReactNode };
  all: React.ReactNode;
}): React.JSX.Element {
  const hidden = total - changed.count;
  const label = open
    ? plural(total, ...noun)
    : changed.count === 0
      ? `${plural(total, ...noun)}${replacing ? ', unchanged' : ''}`
      : hidden === 0
        ? plural(total, ...noun)
        : `${plural(total, ...noun)} · ${changed.count} changed, ${hidden} more`;
  return (
    <div data-slot={slot} className="flex flex-col gap-1.5">
      <Button
        type="button"
        variant="ghost"
        size="sm"
        className="h-auto gap-1 self-start px-0 py-0 text-xs font-medium hover:bg-transparent max-sm:min-h-11"
        aria-expanded={open}
        onClick={onToggle}>
        <ChevronRight
          aria-hidden="true"
          className={cn('size-3.5 transition-transform', open && 'rotate-90')}
        />
        {label}
      </Button>
      {open ? all : changed.count > 0 ? changed.content : null}
    </div>
  );
}

function MarkBadge({ mark }: { mark: PreviewMark }): React.JSX.Element {
  return (
    <Badge variant="outline" className="px-1.5 py-0 font-normal">
      {MARK_LABEL[mark]}
    </Badge>
  );
}

function StageList({
  stages,
  marks,
}: {
  stages: readonly WorkflowStage[];
  marks: ReadonlyMap<string, PreviewMark>;
}): React.JSX.Element {
  return (
    <ol
      data-slot="workflow-proposal-stage-text"
      className="m-0 flex max-h-72 list-none flex-col gap-2 overflow-auto p-0 text-xs">
      {stages.map((stage) => {
        const mark = marks.get(stage.id);
        return (
          <li key={stage.id} data-stage={stage.id} className="break-words">
            <span className="font-medium">{stage.title}</span>
            {mark === undefined ? null : (
              <>
                {' '}
                <MarkBadge mark={mark} />
              </>
            )}
            {stage.instructions?.trim() ? (
              <p className="m-0 whitespace-pre-line text-muted-foreground">
                {stage.instructions}
              </p>
            ) : null}
            <p className="m-0 text-muted-foreground">
              <span className="text-foreground">Done when</span>{' '}
              {stage.doneWhen}
            </p>
          </li>
        );
      })}
    </ol>
  );
}

function GraphSkeleton(): React.JSX.Element {
  return (
    <span
      aria-hidden="true"
      className="skeleton-pulse block h-full w-full rounded-md bg-muted-foreground/10"
    />
  );
}

/**
 * A whole workflow an agent proposes for the library — `propose_workflow`'s
 * card. Approve writes it (the daemon does, never the agent); Decline writes
 * nothing; a note typed beside either reaches the agent with the verdict.
 *
 * It shows what an approval commits to: the graph, every agent and whether it
 * asks before running tools — any that would not are named in a strip above
 * all else — and, for a replacement, what changes against the saved file.
 * Once answered it keeps the roster and the changes, the graph folded away,
 * and says what became of an approval: saved (with a way to open it) or not.
 */
export function WorkflowProposalCard({
  proposal,
  verdict,
  note = null,
  outcome = null,
  expired,
  memoryKey,
  onRespond,
  onOpenWorkflow,
}: {
  proposal: ParsedWorkflowProposal;
  /** null while pending; the user's decision once the verdict item arrived. */
  verdict: boolean | null;
  /** The note that decision carried, read back from the same verdict item. */
  note?: string | null;
  /** What the daemon did with an approval, from the same verdict item. */
  outcome?: ProposalOutcome | null;
  /** A newer proposal or the chat's archiving took the card down. */
  expired: boolean;
  /** The approval request's id: folds are remembered per thread under it. */
  memoryKey?: string;
  onRespond: (allow: boolean, answer?: string) => void;
  /** Open the saved workflow on its canvas; absent, nothing offers to. */
  onOpenWorkflow?: (slug: string) => void;
}): React.JSX.Element {
  const { workflow, autoAgents, diff } = proposal;
  const stages = workflow.stages ?? [];
  const { sending, respond } = useOneShotVerdict(verdict, expired, onRespond);
  const narrow = useNarrowViewport();
  const settled = verdict !== null || expired;
  const remembered = (name: string) =>
    memoryKey === undefined ? undefined : `${name}:${memoryKey}`;
  const [graphShown, setGraphShown] = useThreadFlag(
    remembered('workflow-graph'),
    !narrow && !settled,
  );
  const [stageTextShown, setStageTextShown] = useThreadFlag(
    remembered('workflow-stage-text'),
    false,
  );
  const [rosterShown, setRosterShown] = useThreadFlag(
    remembered('workflow-roster'),
    false,
  );
  const [enlarged, setEnlarged] = useState(false);
  const { draft, setDraft, tooLong, send } = useVerdictNote(respond);
  const titleId = useId();

  const roster = useMemo(() => rosterOf(workflow), [workflow]);
  const marks = useMemo(() => previewMarks(diff), [diff]);
  const stageMarks = useMemo(() => stageMarksOf(diff), [diff]);
  const changedAgents = roster.filter((row) => marks.has(row.node.id));
  const changedStages = stages.filter((stage) => stageMarks.has(stage.id));
  const changes = useMemo(
    () => (diff === null ? null : diffRows(diff, workflow)),
    [diff, workflow],
  );
  const scanText = useMemo(() => proposalScanText(proposal), [proposal]);
  const gate = useHazardGate(scanText);
  const graphSummary = `Graph: ${
    workflow.edges.length === 0
      ? 'no connections'
      : workflow.edges.map((edge) => `${edge.from} → ${edge.to}`).join(', ')
  }.`;

  return (
    <Card
      role="group"
      aria-labelledby={titleId}
      data-slot="workflow-proposal-card"
      className="flex min-w-0 flex-col gap-3 border-primary/40 p-3">
      <div className="flex flex-wrap items-center gap-x-2 gap-y-1">
        <WorkflowIcon
          aria-hidden="true"
          className="size-4 shrink-0 text-primary"
        />
        <span id={titleId} className="min-w-0 text-sm font-medium break-words">
          {workflow.name}
        </span>
        {proposal.mode === 'create' ? (
          <Badge variant="outline">New</Badge>
        ) : (
          <Badge variant="secondary" className="max-w-full truncate">
            Replaces {proposal.replacesName}
          </Badge>
        )}
        <span className="text-xs text-muted-foreground">
          {plural(roster.length, 'agent', 'agents')} ·{' '}
          {plural(workflow.edges.length, 'connection', 'connections')}
          {stages.length > 0
            ? ` · ${plural(stages.length, 'stage', 'stages')}`
            : null}
        </span>
      </div>
      {proposal.summary !== null || proposal.reason !== null ? (
        <div className="flex flex-col gap-1.5">
          {proposal.summary !== null ? (
            <p
              data-slot="workflow-proposal-summary"
              className="m-0 text-sm break-words">
              {proposal.summary}
            </p>
          ) : null}
          {proposal.reason !== null ? (
            <p
              data-slot="workflow-proposal-reason"
              className="m-0 text-xs break-words whitespace-pre-line">
              <span className="font-medium">Why: </span>
              <span className="text-muted-foreground">{proposal.reason}</span>
            </p>
          ) : null}
        </div>
      ) : null}
      {autoAgents.length > 0 ? (
        <div
          role="note"
          data-slot="workflow-auto-strip"
          className="flex items-start gap-2 rounded-md border border-warning/30 bg-warning/10 px-2.5 py-2 text-xs text-warning">
          <ShieldAlert aria-hidden="true" className="mt-px size-3.5 shrink-0" />
          <span className="break-words">
            {plural(autoAgents.length, 'agent runs', 'agents run')} without
            asking permission: {autoAgents.join(', ')}
          </span>
        </div>
      ) : null}
      <HazardWarning hazards={gate.hazards} subject="this proposal" />
      {changes !== null ? (
        <WorkflowDiffList
          rows={changes}
          memoryKey={remembered('workflow-diff')}
        />
      ) : null}
      {narrow || settled || !graphShown ? (
        <Button
          type="button"
          variant="link"
          className="h-auto self-start p-0 text-xs max-sm:min-h-11"
          aria-expanded={graphShown}
          onClick={() => setGraphShown((current) => !current)}>
          {graphShown ? 'Hide graph' : 'Show graph'}
        </Button>
      ) : null}
      {graphShown ? (
        <div
          data-slot="workflow-proposal-graph"
          className={cn(
            'relative w-full overflow-hidden rounded-md border border-border',
            narrow ? 'h-[300px]' : 'h-[360px]',
          )}>
          <p className="sr-only">{graphSummary}</p>
          <Suspense fallback={<GraphSkeleton />}>
            <WorkflowPreview
              workflow={workflow}
              marks={marks}
              interaction={narrow ? 'full' : 'embedded'}
              onExpand={narrow ? undefined : () => setEnlarged(true)}
              expandLabel={`Open a larger view of ${workflow.name}. ${graphSummary}`}
            />
          </Suspense>
        </div>
      ) : null}
      <Dialog
        open={enlarged}
        onClose={() => setEnlarged(false)}
        title={workflow.name}
        className="w-[min(1400px,95vw)]">
        <div className="h-[80vh]">
          <Suspense fallback={<GraphSkeleton />}>
            <WorkflowPreview
              workflow={workflow}
              marks={marks}
              interaction="full"
            />
          </Suspense>
        </div>
      </Dialog>
      {stages.length > 0 ? (
        <div
          data-slot="workflow-proposal-stages"
          className="flex flex-col gap-1.5 rounded-md border border-border p-2">
          <span className="text-xs font-medium">Stages every run walks</span>
          <StageGraph stages={stages} />
          <Fold
            slot="workflow-proposal-stage-fold"
            noun={['stage', 'stages']}
            total={stages.length}
            replacing={proposal.mode === 'replace'}
            open={stageTextShown}
            onToggle={() => setStageTextShown((current) => !current)}
            changed={{
              count: changedStages.length,
              content: <StageList stages={changedStages} marks={stageMarks} />,
            }}
            all={<StageList stages={stages} marks={stageMarks} />}
          />
        </div>
      ) : null}
      <Fold
        slot="workflow-proposal-agents"
        noun={['agent', 'agents']}
        total={roster.length}
        replacing={proposal.mode === 'replace'}
        open={rosterShown}
        onToggle={() => setRosterShown((current) => !current)}
        changed={{
          count: changedAgents.length,
          content: <Roster rows={changedAgents} marks={marks} />,
        }}
        all={<Roster rows={roster} marks={marks} />}
      />
      {expired && verdict === null ? (
        <p className="m-0 text-xs text-muted-foreground">
          ⏱ expired — a newer proposal replaced it, or the chat was archived
        </p>
      ) : sending ? (
        <p className="m-0 text-xs text-muted-foreground">Sending…</p>
      ) : verdict === null ? (
        <div className="flex flex-col gap-2">
          {proposal.mode === 'replace' ? (
            <p className="m-0 text-xs text-muted-foreground">
              Approving overwrites {proposal.replacesName}; the current file is
              backed up first.
            </p>
          ) : null}
          <VerdictNoteField
            draft={draft}
            onChange={setDraft}
            tooLong={tooLong}
            placeholder="Optional — what to change, or why not"
          />
          {gate.hazards.gates ? (
            <HazardAck
              id={gate.ackId}
              checked={gate.acknowledged}
              onCheckedChange={gate.setAcknowledged}
            />
          ) : null}
          <div className="flex gap-2">
            <Button
              type="button"
              className="max-sm:min-h-11"
              onClick={() => send(true)}
              disabled={tooLong || gate.blocksApprove}>
              Approve
            </Button>
            <Button
              type="button"
              variant="outline"
              className="max-sm:min-h-11"
              onClick={() => send(false)}
              disabled={tooLong}>
              Decline
            </Button>
          </div>
        </div>
      ) : (
        <div aria-live="polite" className="flex flex-col gap-1.5">
          {!verdict ? (
            <p className="m-0 text-xs text-destructive">✗ Declined</p>
          ) : outcome?.kind === 'saved' ? (
            <div className="flex flex-wrap items-center gap-2">
              <p className="m-0 text-xs text-success">
                ✓ Saved as “{outcome.slug}”
              </p>
              {onOpenWorkflow ? (
                <Button
                  type="button"
                  variant="outline"
                  size="sm"
                  className="max-sm:min-h-11"
                  onClick={() => onOpenWorkflow(outcome.slug)}>
                  Open in canvas
                </Button>
              ) : null}
            </div>
          ) : outcome?.kind === 'not-saved' ? (
            <>
              <p className="m-0 text-xs text-destructive">✗ Not saved</p>
              <p
                data-slot="workflow-not-saved"
                className="m-0 rounded-md border border-destructive/30 bg-destructive/10 px-2.5 py-1.5 text-xs text-destructive">
                {notSavedText(outcome.cause, proposal)}
              </p>
            </>
          ) : (
            <p className="m-0 text-xs text-success">✓ Approved</p>
          )}
          <VerdictNoteEcho note={note} />
        </div>
      )}
    </Card>
  );
}
