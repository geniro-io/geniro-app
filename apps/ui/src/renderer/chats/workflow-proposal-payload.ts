import {
  AgentKind,
  ApprovalMode,
  EdgeKind,
  TriggerKind,
  type Workflow,
  type WorkflowAgentNode,
} from '../autogenerated';
import type { PreviewMark } from '../workflows/graph-preview-context';
import { memberRunsUnasked, runsUnasked } from '../workflows/node-schema';

/**
 * The `propose_workflow` card's payload: the `input` of its `approval_request`
 * row, and the `outcome` its verdict row carries once approved.
 *
 * TWIN PARSER: `WorkflowProposalSchema` (`apps/daemon/src/v1/graphs/graphs.types.ts`),
 * `WorkflowDiff` (`apps/daemon/src/v1/graphs/utils/workflow-diff.ts`) and
 * `WorkflowProposalOutcome` (`apps/daemon/src/v1/agents/chat.types.ts`). The
 * daemon checked the workflow strictly before raising the card, so anything
 * here that does not read is version skew — the card then falls back to the
 * permission body rather than drawing half a proposal.
 */

export interface ProposalDiffField {
  field: string;
  /** JSON of the old value, quoted and capped by the daemon. */
  before: string;
  after: string;
}

export interface ProposalDiff {
  identical: boolean;
  workflowFields: string[];
  addedNodes: string[];
  removedNodes: string[];
  changedNodes: { id: string; fields: ProposalDiffField[] }[];
  addedEdges: string[];
  removedEdges: string[];
}

export interface ParsedWorkflowProposal {
  mode: 'create' | 'replace';
  workflow: Workflow;
  /** The library file an approval writes, fixed when the card was raised. */
  slug: string;
  /** The agent's own line, never trusted as a description of the change. */
  summary: string | null;
  /** The agent's own account of why, never trusted either. */
  reason: string | null;
  /** Every agent that runs tools without asking, as the daemon names them. */
  autoAgents: string[];
  /** Replace only: the name of the workflow being overwritten. */
  replacesName: string | null;
  /** Replace only; null on a new workflow. */
  diff: ProposalDiff | null;
}

const NOT_SAVED_CAUSES = [
  'changed',
  'exists',
  'gone',
  'not-closed',
  'write-failed',
] as const;

export type NotSavedCause = (typeof NOT_SAVED_CAUSES)[number];

export type ProposalOutcome =
  | { kind: 'saved'; slug: string }
  /** `cause` null: a cause this build does not know. */
  | { kind: 'not-saved'; cause: NotSavedCause | null };

function isNotSavedCause(value: unknown): value is NotSavedCause {
  return (NOT_SAVED_CAUSES as readonly unknown[]).includes(value);
}

type Fields = Record<string, unknown>;

function record(value: unknown): Fields | null {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
    ? (value as Fields)
    : null;
}

function isString(value: unknown): value is string {
  return typeof value === 'string';
}

function stringList(value: unknown): string[] | null {
  return Array.isArray(value) && value.every(isString) ? value : null;
}

function oneOf<T extends string>(
  values: Readonly<Record<string, T>>,
  value: unknown,
): value is T {
  return (Object.values(values) as unknown[]).includes(value);
}

function optionalString(value: unknown): boolean {
  return value === undefined || isString(value);
}

function readAgentFields(fields: Fields): boolean {
  return (
    oneOf(AgentKind, fields.agent) &&
    optionalString(fields.model) &&
    optionalString(fields.effort)
  );
}

function isNode(value: unknown): boolean {
  const node = record(value);
  if (node === null || !isString(node.id) || !optionalString(node.name)) {
    return false;
  }
  switch (node.kind) {
    case 'trigger':
      return oneOf(TriggerKind, node.trigger);
    case 'instruction':
      return isString(node.instructions);
    case 'agent': {
      if (
        !readAgentFields(node) ||
        !oneOf(ApprovalMode, node.approval) ||
        !optionalString(node.role) ||
        !optionalString(node.description)
      ) {
        return false;
      }
      if (node.pool === undefined) {
        return true;
      }
      return (
        Array.isArray(node.pool) &&
        node.pool.every((entry) => {
          const member = record(entry);
          return (
            member !== null &&
            readAgentFields(member) &&
            (member.approval === undefined ||
              oneOf(ApprovalMode, member.approval))
          );
        })
      );
    }
    default:
      return false;
  }
}

function isEdge(value: unknown): boolean {
  const edge = record(value);
  return (
    edge !== null &&
    isString(edge.from) &&
    isString(edge.to) &&
    oneOf(EdgeKind, edge.kind)
  );
}

function readWorkflow(value: unknown): Workflow | null {
  const workflow = record(value);
  if (
    workflow === null ||
    !isString(workflow.name) ||
    !optionalString(workflow.description) ||
    !Array.isArray(workflow.nodes) ||
    !Array.isArray(workflow.edges) ||
    !workflow.nodes.every(isNode) ||
    !workflow.edges.every(isEdge)
  ) {
    return null;
  }
  return workflow as unknown as Workflow;
}

function readDiff(value: unknown): ProposalDiff | null {
  const diff = record(value);
  if (diff === null || typeof diff.identical !== 'boolean') {
    return null;
  }
  const lists = {
    workflowFields: stringList(diff.workflowFields),
    addedNodes: stringList(diff.addedNodes),
    removedNodes: stringList(diff.removedNodes),
    addedEdges: stringList(diff.addedEdges),
    removedEdges: stringList(diff.removedEdges),
  };
  if (Object.values(lists).some((list) => list === null)) {
    return null;
  }
  if (!Array.isArray(diff.changedNodes)) {
    return null;
  }
  const changedNodes: ProposalDiff['changedNodes'] = [];
  for (const entry of diff.changedNodes) {
    const node = record(entry);
    if (node === null || !isString(node.id) || !Array.isArray(node.fields)) {
      return null;
    }
    const fields: ProposalDiffField[] = [];
    for (const raw of node.fields) {
      const field = record(raw);
      if (
        field === null ||
        !isString(field.field) ||
        !isString(field.before) ||
        !isString(field.after)
      ) {
        return null;
      }
      fields.push({
        field: field.field,
        before: field.before,
        after: field.after,
      });
    }
    changedNodes.push({ id: node.id, fields });
  }
  return {
    identical: diff.identical,
    workflowFields: lists.workflowFields!,
    addedNodes: lists.addedNodes!,
    removedNodes: lists.removedNodes!,
    changedNodes,
    addedEdges: lists.addedEdges!,
    removedEdges: lists.removedEdges!,
  };
}

function trimmedText(value: unknown): string | null {
  return isString(value) && value.trim() !== '' ? value.trim() : null;
}

/** The proposal on a card, or null to draw the permission body instead. */
export function readWorkflowProposal(
  input: unknown,
): ParsedWorkflowProposal | null {
  const proposal = record(input);
  if (proposal === null || !isString(proposal.slug)) {
    return null;
  }
  const workflow = readWorkflow(proposal.workflow);
  const autoAgents = stringList(proposal.autoAgents);
  if (workflow === null || autoAgents === null) {
    return null;
  }
  const summary = trimmedText(proposal.summary);
  const reason = trimmedText(proposal.reason);
  if (proposal.mode === 'create') {
    return {
      mode: 'create',
      workflow,
      slug: proposal.slug,
      summary,
      reason,
      autoAgents,
      replacesName: null,
      diff: null,
    };
  }
  if (proposal.mode !== 'replace' || !isString(proposal.replacesName)) {
    return null;
  }
  const diff = readDiff(proposal.diff);
  if (diff === null) {
    return null;
  }
  return {
    mode: 'replace',
    workflow,
    slug: proposal.slug,
    summary,
    reason,
    autoAgents,
    replacesName: proposal.replacesName,
    diff,
  };
}

/** What became of an approval, or null when the verdict row carries none. */
export function readProposalOutcome(raw: unknown): ProposalOutcome | null {
  const outcome = record(raw);
  if (outcome === null) {
    return null;
  }
  if (outcome.kind === 'saved' && isString(outcome.slug)) {
    return { kind: 'saved', slug: outcome.slug };
  }
  if (outcome.kind === 'not-saved') {
    return {
      kind: 'not-saved',
      cause: isNotSavedCause(outcome.cause) ? outcome.cause : null,
    };
  }
  return null;
}

function collectStrings(value: unknown, into: string[]): void {
  if (typeof value === 'string') {
    into.push(value);
  } else if (Array.isArray(value)) {
    for (const entry of value) {
      collectStrings(entry, into);
    }
  } else if (typeof value === 'object' && value !== null) {
    for (const [key, entry] of Object.entries(value)) {
      into.push(key);
      collectStrings(entry, into);
    }
  }
}

/**
 * Every string the card can draw, for the Approve gate's hazard scan: the
 * workflow, the diff — its old side and removed ids included, which the
 * proposed workflow does not carry — and the agent's own lines. Object keys
 * too: an agent writes those (`modelParameters`), and the scan is cheaper
 * whole than proven narrower.
 *
 * Raw, not JSON: `JSON.stringify` escapes the C0 controls the card draws
 * verbatim. Joined by spaces, with line breaks and tabs turned to spaces,
 * because each is itself `\p{Cc}` and would gate every multi-line role.
 */
export function proposalScanText(proposal: ParsedWorkflowProposal): string {
  const strings: string[] = [];
  collectStrings(
    [
      proposal.workflow,
      proposal.diff,
      proposal.summary,
      proposal.reason,
      proposal.replacesName,
      proposal.autoAgents,
    ],
    strings,
  );
  // A changed field's values arrive JSON-quoted and are drawn decoded
  // (`shown`), so the decoded form is scanned too: the quoted form hides a
  // control character behind its `\u` escape.
  for (const { fields } of proposal.diff?.changedNodes ?? []) {
    for (const { before, after } of fields) {
      strings.push(shown(before), shown(after));
    }
  }
  return strings.join(' ').replace(/[\n\t\r]/g, ' ');
}

/** Each node a replacement adds or changes, for the preview to mark. */
export function previewMarks(
  diff: ProposalDiff | null,
): ReadonlyMap<string, PreviewMark> {
  const marks = new Map<string, PreviewMark>();
  for (const { id } of diff?.changedNodes ?? []) {
    marks.set(id, 'changed');
  }
  for (const id of diff?.addedNodes ?? []) {
    marks.set(id, 'added');
  }
  return marks;
}

/** One agent of the proposal, as a roster row. */
export interface RosterRow {
  node: WorkflowAgentNode;
  /** The text of every instruction block wired into this agent. */
  instructions: string[];
}

/** The proposal's agents in workflow order, each with its instruction blocks. */
export function rosterOf(workflow: Workflow): RosterRow[] {
  const blocks = new Map<string, string>();
  for (const node of workflow.nodes) {
    if (node.kind === 'instruction') {
      blocks.set(node.id, node.instructions.trim() || (node.name ?? node.id));
    }
  }
  return workflow.nodes
    .filter((node): node is WorkflowAgentNode => node.kind === 'agent')
    .map((node) => ({
      node,
      instructions: workflow.edges
        .filter((edge) => edge.kind === 'instruction' && edge.to === node.id)
        .map((edge) => blocks.get(edge.from))
        .filter(isString),
    }));
}

export type DiffMarker = 'changed' | 'added' | 'removed';

/** One line of the change list. */
export interface DiffRow {
  key: string;
  marker: DiffMarker;
  /** What the subject names: the workflow's own field, a node, a wire. */
  scope: 'workflow' | 'node' | 'wire';
  /** A workflow field's name, a node id, or a wire as `from → to (kind)`. */
  subject: string;
  /** For a changed field: which one, and from what to what. */
  detail: { field: string; before: string; after: string } | null;
  /** The change makes an agent run tools without asking. */
  toAuto: boolean;
}

/** How the daemon quotes a field one side of the diff does not have. */
const UNSET = '(unset)';

/** A diff value as a reader sees it: a quoted string loses its quotes. */
function shown(json: string): string {
  try {
    const value: unknown = JSON.parse(json);
    return typeof value === 'string' ? value : json;
  } catch {
    return json;
  }
}

/**
 * Whether a node's OLD pool ran a member unasked under `approval` — the node's
 * new approval, so that only the pool edit is judged. Null when the old pool's
 * quote was cut short and cannot be read.
 */
function oldPoolRunsUnasked(approval: unknown, before: string): boolean | null {
  let pool: unknown;
  try {
    pool = before === UNSET ? [] : JSON.parse(before);
  } catch {
    return null;
  }
  if (!Array.isArray(pool)) {
    return null;
  }
  return pool.some((member) =>
    memberRunsUnasked(record(member)?.approval, approval),
  );
}

/**
 * The diff as rows, every change that makes an agent run unasked first — the
 * change a reader must not skim past — then the rest in the daemon's order.
 */
export function diffRows(diff: ProposalDiff, workflow: Workflow): DiffRow[] {
  const agents = new Map(
    workflow.nodes
      .filter((node): node is WorkflowAgentNode => node.kind === 'agent')
      .map((node) => [node.id, node]),
  );
  const unasked = new Set(
    [...agents.values()].filter(runsUnasked).map((node) => node.id),
  );
  // A pool row is flagged only when the POOL edit makes a member run unasked:
  // the old pool judged under the node's new approval, never the quoted new
  // pool, which the daemon cuts at 400 characters and in which a member that
  // inherits the node's `auto` never spells it. A node now `auto` itself is
  // flagged by its approval row or already ran so; an old pool cut short
  // counts as "did not", so a real switch is never missed.
  const poolToAuto = (id: string, before: string) => {
    const node = agents.get(id);
    return (
      node !== undefined &&
      node.approval !== 'auto' &&
      unasked.has(id) &&
      oldPoolRunsUnasked(node.approval, before) !== true
    );
  };
  const rows: DiffRow[] = [
    ...diff.workflowFields.map((field): DiffRow => ({
      key: `workflow:${field}`,
      marker: 'changed',
      scope: 'workflow',
      subject: field,
      detail: null,
      toAuto: false,
    })),
    ...diff.addedNodes.map((id): DiffRow => ({
      key: `added:${id}`,
      marker: 'added',
      scope: 'node',
      subject: id,
      detail: null,
      toAuto: unasked.has(id),
    })),
    ...diff.changedNodes.flatMap(({ id, fields }) =>
      fields.map(({ field, before, after }): DiffRow => ({
        key: `changed:${id}:${field}`,
        marker: 'changed',
        scope: 'node',
        subject: id,
        detail: { field, before: shown(before), after: shown(after) },
        toAuto:
          field === 'approval'
            ? shown(after) === 'auto'
            : field === 'pool' && poolToAuto(id, before),
      })),
    ),
    ...diff.removedNodes.map((id): DiffRow => ({
      key: `removed:${id}`,
      marker: 'removed',
      scope: 'node',
      subject: id,
      detail: null,
      toAuto: false,
    })),
    ...diff.addedEdges.map((edge): DiffRow => ({
      key: `added-edge:${edge}`,
      marker: 'added',
      scope: 'wire',
      subject: edge,
      detail: null,
      toAuto: false,
    })),
    ...diff.removedEdges.map((edge): DiffRow => ({
      key: `removed-edge:${edge}`,
      marker: 'removed',
      scope: 'wire',
      subject: edge,
      detail: null,
      toAuto: false,
    })),
  ];
  return [
    ...rows.filter((row) => row.toAuto),
    ...rows.filter((row) => !row.toAuto),
  ];
}
