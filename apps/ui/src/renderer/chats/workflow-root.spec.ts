import { describe, expect, it } from 'vitest';

import type { Workflow, WorkflowEdge, WorkflowNode } from '../autogenerated';
import { rootAgentOf } from './workflow-root';

const node = (
  id: string,
  kind: 'agent' | 'trigger' | 'instruction',
): WorkflowNode => ({ id, kind }) as unknown as WorkflowNode;

const edge = (from: string, to: string, kind?: string): WorkflowEdge =>
  ({
    from,
    to,
    ...(kind === undefined ? {} : { kind }),
  }) as unknown as WorkflowEdge;

const workflow = (nodes: WorkflowNode[], edges: WorkflowEdge[]): Workflow =>
  ({ nodes, edges }) as unknown as Workflow;

describe('rootAgentOf', () => {
  it('names the agent the trigger feeds', () => {
    expect(
      rootAgentOf(
        workflow(
          [
            node('t', 'trigger'),
            node('manager', 'agent'),
            node('eng', 'agent'),
          ],
          [edge('t', 'manager', 'data'), edge('manager', 'eng', 'call')],
        ),
      ),
    ).toBe('manager');
  });

  it('reads an edge with NO kind as data — the oldest graphs carry none', () => {
    // The same rule the canvas reads edges by (`flowEdgeKind`): every edge
    // persisted before the kind existed omits it, and a trigger edge is
    // exactly the kind of edge those graphs have.
    expect(
      rootAgentOf(
        workflow(
          [node('t', 'trigger'), node('manager', 'agent')],
          [edge('t', 'manager')],
        ),
      ),
    ).toBe('manager');
  });

  it('refuses to pick when the trigger fans out to TWO agents', () => {
    // The load-bearing half: dropping BOTH frames leaves two agents' words
    // interleaved at the top level with nothing saying which is which, which
    // is the failure the frames exist to prevent. One root is a conversation;
    // two are a graph, and a graph keeps its labels.
    expect(
      rootAgentOf(
        workflow(
          [node('t', 'trigger'), node('a', 'agent'), node('b', 'agent')],
          [edge('t', 'a', 'data'), edge('t', 'b', 'data')],
        ),
      ),
    ).toBeNull();
  });

  it('ignores call and instruction edges out of a trigger', () => {
    expect(
      rootAgentOf(
        workflow(
          [node('t', 'trigger'), node('a', 'agent')],
          [edge('t', 'a', 'call')],
        ),
      ),
    ).toBeNull();
  });

  it('answers null for a graph with no trigger, and for one whose edge names no agent', () => {
    expect(rootAgentOf(workflow([node('a', 'agent')], []))).toBeNull();
    expect(
      rootAgentOf(
        workflow(
          [node('t', 'trigger'), node('note', 'instruction')],
          [edge('t', 'note', 'instruction')],
        ),
      ),
    ).toBeNull();
  });
});
