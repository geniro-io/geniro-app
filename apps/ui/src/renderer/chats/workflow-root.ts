import type { Workflow } from '../autogenerated';

/**
 * The agent a workflow's TRIGGER feeds — the one the run is a conversation
 * WITH, rather than one the conversation is about.
 *
 * The transcript draws every agent in an avatar-framed block, which earns its
 * space the moment two of them share a flow. The root agent is the exception,
 * and it is the same exception a 1:1 chat already makes: the user writes to it,
 * it answers, and everything else in the run reaches the screen inside a card
 * that names its own agent (a call block, a sub-agent block). So framing it
 * asks the reader to keep telling one agent apart from nobody. Asked for in
 * those words — "let's make root agent … without its block, so it should look
 * like a normal root agent, same as if I run claude or cursor separately".
 *
 * Null when the graph has no such agent OR more than one, and the second half
 * is the load-bearing one: a trigger that fans out to two agents has two
 * conversations at the top level, and dropping BOTH frames would leave two
 * agents' words interleaved with nothing saying which is which — the exact
 * failure the frames exist to prevent. One root is a conversation; two are a
 * graph, and a graph keeps its labels.
 *
 * Purely presentational, so it is deliberately NOT the daemon's own entry-node
 * reading (`computeRunOrder`): a disagreement here costs a frame that should
 * not have been drawn, never a routing decision.
 */
export function rootAgentOf(workflow: Workflow): string | null {
  const triggers = new Set(
    workflow.nodes.filter((node) => node.kind === 'trigger').map((n) => n.id),
  );
  if (triggers.size === 0) {
    return null;
  }
  const agents = new Set(
    workflow.nodes.filter((node) => node.kind === 'agent').map((n) => n.id),
  );
  const roots = new Set(
    workflow.edges
      // An ABSENT kind reads as `data`, the same rule the canvas reads edges
      // by (`flowEdgeKind`): every edge persisted before the kind existed
      // carries none, and those are exactly the trigger edges of the oldest
      // graphs. A `call` or `instruction` edge is not a route into the run.
      .filter((edge) => (edge.kind ?? 'data') === 'data')
      .filter((edge) => triggers.has(edge.from) && agents.has(edge.to))
      .map((edge) => edge.to),
  );
  return roots.size === 1 ? [...roots][0]! : null;
}
