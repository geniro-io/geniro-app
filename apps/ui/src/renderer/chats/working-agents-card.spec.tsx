function doubles() {
  const listeners = new Set<(item: ItemDto) => void>();
  const reconnects = new Set<() => void>();
  const listCallMessages = vi.fn(async (): Promise<CallMessagesReply> => ({
    messages: [],
    hasOlder: false,
  }));
  const listRunItems = vi.fn(async (): Promise<RunItemsReply> => ({
    items: [],
    anchors: [],
  }));
  const api: Pick<ChatsApi, 'listCallMessages' | 'listRunItems'> = {
    listCallMessages,
    listRunItems,
  };
  const client: Pick<DaemonClient, 'onItem' | 'onReconnect'> = {
    onItem: (listener) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    onReconnect: (listener) => {
      const heard = (): void => listener();
      reconnects.add(heard);
      return () => reconnects.delete(heard);
    },
  };
  const emit = (item: ItemDto): void => {
    act(() => {
      for (const listener of listeners) {
        listener(item);
      }
    });
  };
  const reconnect = async (): Promise<void> => {
    await act(async () => {
      for (const listener of reconnects) {
        listener();
      }
    });
  };
  return { api, client, listCallMessages, listRunItems, emit, reconnect };
}

function mount(element: React.ReactElement): HTMLElement {
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  act(() => {
    root.render(element);
  });
  return container;
}

function renderSquare(
  rows: readonly WorkingAgentRow[],
  onShowInChat: (callId: string) => void = () => undefined,
) {
  const spies = doubles();
  const el = mount(
    <WorkingAgentsCard
      rows={rows}
      runId="run-1"
      api={spies.api}
      client={spies.client}
      onShowInChat={onShowInChat}
    />,
  );
  return { el, ...spies };
}

const settle = (): Promise<void> => act(async () => {});

type ReadMessages = ReturnType<typeof doubles>['listCallMessages'];

async function press(target: Element): Promise<void> {
  await act(async () => {
    target.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

async function pressOutside(): Promise<void> {
  await act(async () => {
    document.body.dispatchEvent(new MouseEvent('mousedown', { bubbles: true }));
  });
}

const slot = (el: Element, name: string): HTMLElement | null =>
  el.querySelector<HTMLElement>(`[data-slot="${name}"]`);

const toggleOf = (el: Element): HTMLElement =>
  el.querySelector<HTMLElement>('[data-slot="working-agents-toggle"] button')!;

const panelOf = (el: Element): HTMLElement | null => slot(el, 'popover-panel');

/** The square with its panel pinned open by a press, once the replies `prepare` lines up have landed. */
async function renderPinned(
  rows: readonly WorkingAgentRow[],
  prepare: (read: ReadMessages) => void = () => undefined,
  onShowInChat: (callId: string) => void = () => undefined,
) {
  const rendered = renderSquare(rows, onShowInChat);
  prepare(rendered.listCallMessages);
  await press(toggleOf(rendered.el));
  await settle();
  return rendered;
}

