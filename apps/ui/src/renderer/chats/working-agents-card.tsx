/** Enough to fill three clamped lines of this column, however long the message runs. */
const MESSAGE_PREVIEW_CHARS = 600;
const FOLDED_FACES = 3;
const UNFOLDS = 'grid transition-[grid-template-columns] duration-200 ease-out';
const STRIP_MAX_AGENTS = 4;
const STRIP_AGENT_WIDTH_PX = 88;
/** The card's own right margin, its padding, and room for `+N` and the failure mark. */
const STRIP_FIXED_WIDTH_PX = 88;
const LATEST_HALF_WIDTH_PX = 40;
/** Below this pane width the open card would reach the centred Latest button. */
const OPEN_CARD_CLEAR_OF_LATEST_PX = 720;
/** The open card's lift above Latest on a narrow pane, plus a margin under the pane's top. */
const LIFTED_CARD_CLEARANCE_PX = 56;

function failureSeenKey(row: WorkingAgentRow): string {
  return `working-agents:failure-seen:${row.callId}`;
}

/** Who is on the card, each member once: several conversations can share one face. */
function peopleOf(rows: readonly WorkingAgentRow[]): AvatarPerson[] {
  const people = new Map<string, AvatarPerson>();
  for (const row of rows) {
    if (!people.has(row.calleeKey)) {
      people.set(row.calleeKey, {
        key: row.calleeKey,
        name: row.callee,
        avatar: row.calleeAvatar,
      });
    }
  }
  return [...people.values()];
}

interface PaneSize {
  width: number;
  height: number;
}

/** The size of the pane just before `anchor`, which the card floats over. */
function usePaneSize(anchor: HTMLElement | null): PaneSize | null {
  const [size, setSize] = useState<PaneSize | null>(null);
  useLayoutEffect(() => {
    const pane = anchor?.previousElementSibling;
    if (!pane) {
      return;
    }
    const measure = (): void =>
      setSize({ width: pane.clientWidth, height: pane.clientHeight });
    measure();
    if (typeof ResizeObserver === 'undefined') {
      return;
    }
    const observer = new ResizeObserver(measure);
    observer.observe(pane);
    return () => observer.disconnect();
  }, [anchor]);
  return size;
}

type TileActivity = 'working' | 'waiting' | 'idle';

/** The folded card at rest: one readable face, how many more, and whether anyone works. */
function AgentsTile({
  lead,
  others,
  activity,
}: {
  lead: WorkingAgentRow;
  others: number;
  activity: TileActivity;
}): React.JSX.Element {
  return (
    <span
      data-slot="working-agents-tile"
      data-activity={activity}
      className={cn(
        'relative grid size-8',
        others > 0 ? 'place-items-start p-px' : 'place-items-center',
      )}>
      <span className="relative flex size-7 items-center justify-center">
        {activity === 'idle' ? null : (
          <span
            aria-hidden="true"
            data-slot="working-agents-tile-ring"
            className={cn(
              'absolute inset-0 rounded-full border-2',
              activity === 'working'
                ? 'animate-spin border-primary/25 border-t-primary motion-reduce:animate-none'
                : 'border-muted-foreground/40',
            )}
          />
        )}
        <MemberAvatar
          size={24}
          name={lead.callee}
          colorKey={lead.calleeKey}
          avatar={lead.calleeAvatar}
        />
      </span>
      {others > 0 ? (
        <span
          data-slot="working-agents-tile-more"
          className="absolute right-px bottom-px rounded-full bg-popover px-0.5 text-[9px] leading-[10px] font-medium text-foreground tabular-nums">
          +{others}
        </span>
      ) : null}
    </span>
  );
}

/** How many agents the strip can name and still stay clear of the centred Latest button. */
function stripCapacity(paneWidth: number | null): number {
  if (paneWidth === null) {
    return STRIP_MAX_AGENTS;
  }
  const room = paneWidth / 2 - LATEST_HALF_WIDTH_PX - STRIP_FIXED_WIDTH_PX;
  return Math.min(
    STRIP_MAX_AGENTS,
    Math.max(1, Math.floor(room / STRIP_AGENT_WIDTH_PX)),
  );
}

/** A message as one run of plain text, cut before the markdown is read. */
function compressedText(item: ChatItem): string {
  const text = payloadString(item.payload, 'text') ?? '';
  return plainPreview(text.slice(0, MESSAGE_PREVIEW_CHARS));
}

/** Mounted inside an open row only, which is what makes opening it the moment its messages are read. */
function RecentMessages({
  row,
  runId,
  api,
  client,
}: {
  row: WorkingAgentRow;
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
}): React.JSX.Element {
  const { messages, hasOlder, loading, failed, retry } = useRecentCallMessages({
    api,
    client,
    runId,
    callId: row.callId,
    callIds: row.callIds,
  });
  if (failed && messages.length === 0) {
    return (
      <div
        data-slot="working-agent-messages-failed"
        className="flex items-center gap-1.5 text-[11px] text-muted-foreground">
        Couldn’t load the messages.
        <Button
          type="button"
          variant="ghost"
          size="sm"
          className="h-6 px-2 text-xs"
          onClick={retry}>
          Retry
        </Button>
      </div>
    );
  }
  if (loading && messages.length === 0) {
    return (
      <div
        role="status"
        data-slot="working-agent-messages-loading"
        className="flex items-center gap-1.5 text-[11px] text-muted-foreground">
        <Spinner />
        Loading messages…
      </div>
    );
  }
  return (
    <div data-slot="working-agent-messages" className="flex flex-col gap-1">
      {hasOlder ? (
        <p
          data-slot="working-agent-older"
          className="m-0 text-[11px] text-muted-foreground">
          Earlier messages are above
        </p>
      ) : null}
      {messages.length === 0 ? (
        <p className="m-0 text-[11px] text-muted-foreground">
          No messages yet.
        </p>
      ) : null}
      {messages.map((item) => (
        <div
          key={item.id}
          data-slot="working-agent-message"
          className="flex flex-col gap-0.5 rounded-md bg-muted/60 px-2 py-1.5">
          <p className="m-0 line-clamp-3 text-xs break-words text-foreground/90">
            {compressedText(item)}
          </p>
          <span className="text-[10px] text-muted-foreground tabular-nums">
            {formatClockTime(item.createdAt)}
          </span>
        </div>
      ))}
    </div>
  );
}

function AgentRow({
  row,
  open,
  onToggle,
  onShowAll,
  onShowInChat,
  runId,
  api,
  client,
}: {
  row: WorkingAgentRow;
  open: boolean;
  onToggle: () => void;
  onShowAll: () => void;
  onShowInChat: () => void;
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
}): React.JSX.Element {
  return (
    <div className={cn('flex flex-col rounded-lg', open && 'bg-muted/40')}>
      <button
        type="button"
        data-slot="working-agent-row"
        data-conversation={row.conversationId}
        aria-expanded={open}
        title={`${row.callee} — ${open ? 'hide' : 'show'} the latest messages`}
        onClick={onToggle}
        className="flex w-full min-w-0 items-start gap-2 rounded-lg px-1.5 py-1.5 text-left font-normal hover:bg-muted">
        <WorkingAgentFaces row={row} />
        <WorkingAgentFacts row={row} />
      </button>
      {open ? (
        <div className="flex flex-col gap-1.5 px-1.5 pb-1.5">
          <RecentMessages row={row} runId={runId} api={api} client={client} />
          <div className="flex items-center gap-1">
            <Button
              type="button"
              size="sm"
              variant="outline"
              data-slot="working-agent-show-all"
              className="h-7 px-2 text-xs"
              onClick={onShowAll}>
              Show all
            </Button>
            <Button
              type="button"
              size="sm"
              variant="ghost"
              data-slot="working-agent-show-in-chat"
              className="h-7 px-2 text-xs font-normal text-muted-foreground"
              title={`Open ${row.callee}’s card in the conversation`}
              onClick={onShowInChat}>
              Show in chat
            </Button>
          </div>
        </div>
      ) : null}
    </div>
  );
}

/**
 * The agents this team run has started, on the right of its transcript: a press
 * on one shows its newest messages, and from there its whole conversation.
 *
 * It floats over the transcript rather than taking a column, so it appearing or
 * folding never reflows the text under the reader. The hanging row it sits in
 * lets every click but the card's own through.
 */
export function WorkingAgentsCard({
  rows,
  runId,
  api,
  client,
  onShowInChat,
  nodes,
  chatAgentName,
  delegateState,
  collapseToolSteps = false,
}: {
  rows: readonly WorkingAgentRow[];
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages' | 'listRunItems'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
  onShowInChat: (callId: string) => void;
  nodes?: ReadonlyMap<string, TranscriptNodeMeta>;
  chatAgentName?: string | null;
  delegateState?: Pick<RunStateDto, 'throughSeq' | 'delegates' | 'calls'>;
  collapseToolSteps?: boolean;
}): React.JSX.Element | null {
  const narrow = useNarrowViewport();
  const live = rows.filter(isWorkingAgentLive);
  const [pressed, setPressed] = useThreadOverride('working-agents:open');
  const [expanded, setExpanded] = useState<string | null>(null);
  const open = pressed === true;
  const [finishedOpen, setFinishedOpen] = useThreadFlag(
    'working-agents:finished',
    false,
  );
  const [dialogId, setDialogId] = useState<string | null>(null);
  const [anchor, setAnchor] = useState<HTMLDivElement | null>(null);
  const pane = usePaneSize(anchor);
  const memory = useThreadFlags();
  const failures = rows.filter((row) => row.state === 'failed');
  const unseenFailures = failures.filter(
    (row) => memory.get(failureSeenKey(row)) !== true,
  );
  useEffect(() => {
    if (open) {
      for (const row of unseenFailures) {
        memory.set(failureSeenKey(row), true);
      }
    }
  });
  if (rows.length === 0) {
    return null;
  }
  // A row being read stays where it is when its agent finishes, instead of
  // dropping into the fold under the reader.
  const onTop = rows.filter(
    (row) => isWorkingAgentLive(row) || row.conversationId === expanded,
  );
  const finished = rows.filter((row) => !onTop.includes(row));
  const summary = workingAgentsSummary(rows);
  const busy = rows.some(isWorkingAgentBusy);
  const failed = failures.length;
  const tile = leadWorkingAgent(rows, (row) => unseenFailures.includes(row));
  const anyoneWorking = rows.some((row) => row.state === 'working');
  const people = peopleOf(rows);
  const stripRows = live.slice(0, stripCapacity(pane?.width ?? null));
  const lifted =
    open && pane !== null && pane.width < OPEN_CARD_CLEAR_OF_LATEST_PX;
  const rowView = (row: WorkingAgentRow): React.JSX.Element => (
    <AgentRow
      key={row.conversationId}
      row={row}
      open={expanded === row.conversationId}
      onToggle={() =>
        setExpanded((held) =>
          held === row.conversationId ? null : row.conversationId,
        )
      }
      onShowAll={() => setDialogId(row.conversationId)}
      onShowInChat={() => {
        // Stepping aside: left open, it would stand over the card it revealed.
        setExpanded(null);
        if (narrow) {
          setPressed(false);
        }
        onShowInChat(row.callId);
      }}
      runId={runId}
      api={api}
      client={client}
    />
  );
  return (
    <>
      <div
        ref={setAnchor}
        className="pointer-events-none relative z-20 h-0 w-full overflow-visible">
        <section
          data-slot="working-agents-card"
          data-folded={!open}
          aria-label="Agents this run started"
          className={cn(
            popoverSurface,
            'pointer-events-auto right-4 z-20 flex max-w-[calc(100%-2rem)] flex-col',
            lifted ? 'bottom-12' : '-bottom-2',
            open && 'w-80',
            !open &&
              live.length === 0 &&
              unseenFailures.length === 0 &&
              'opacity-60 transition-opacity focus-within:opacity-100 hover:opacity-100',
          )}
          style={
            open && pane !== null
              ? {
                  maxHeight: lifted
                    ? pane.height - LIFTED_CARD_CLEARANCE_PX
                    : pane.height,
                }
              : undefined
          }>
          {open ? (
            <div className="flex max-h-[60vh] min-h-0 flex-col gap-0.5 overflow-y-auto overscroll-contain p-1">
              {onTop.map(rowView)}
              {finished.length > 0 ? (
                <button
                  type="button"
                  data-slot="working-agents-finished-toggle"
                  aria-expanded={finishedOpen}
                  onClick={() => setFinishedOpen((value) => !value)}
                  className="flex items-center gap-1.5 rounded-md px-1.5 py-1 text-left text-xs font-normal text-muted-foreground hover:text-foreground">
                  <ChevronRight
                    aria-hidden="true"
                    className={cn(
                      'size-3 shrink-0 transition-transform',
                      finishedOpen && 'rotate-90',
                    )}
                  />
                  {workingAgentsSummary(finished)}
                </button>
              ) : null}
              {finishedOpen ? finished.map(rowView) : null}
            </div>
          ) : null}
          <button
            type="button"
            data-slot="working-agents-toggle"
            aria-expanded={open}
            aria-label={
              open ? 'Fold the agents card' : 'Unfold the agents card'
            }
            title={`Agents · ${summary}`}
            onClick={() => setPressed(!open)}
            className={cn(
              'flex min-w-0 shrink-0 items-center rounded-xl text-left font-normal hover:bg-muted/60',
              open
                ? 'gap-2 rounded-t-none border-t border-border/60 px-2.5 py-1.5'
                : 'group relative',
            )}>
            {open ? (
              <>
                <CallGlyph
                  live={busy}
                  className={cn('size-3.5 shrink-0', busy && 'text-primary')}
                />
                <span className="shrink-0 text-sm font-semibold text-foreground">
                  Agents
                </span>
                <span
                  data-slot="working-agents-summary"
                  className="min-w-0 truncate text-xs text-muted-foreground">
                  {workingAgentsSummary(live)}
                </span>
                <ChevronDown
                  aria-hidden="true"
                  className="ml-auto size-3.5 shrink-0 text-muted-foreground"
                />
              </>
            ) : (
              <>
                <span
                  className={cn(
                    UNFOLDS,
                    'grid-cols-[0fr] group-hover:grid-cols-[1fr] group-focus-visible:grid-cols-[1fr]',
                  )}>
                  <span className="min-w-0 overflow-hidden">
                    <span
                      data-slot="working-agents-strip"
                      className="flex w-max items-center gap-2 px-1.5">
                      {live.length > 0 ? (
                        <>
                          {stripRows.map((row) => (
                            <WorkingAgentStripItem
                              key={row.conversationId}
                              row={row}
                            />
                          ))}
                          {live.length > stripRows.length ? (
                            <span
                              data-slot="working-agents-strip-more"
                              className="shrink-0 text-xs text-muted-foreground">
                              +{live.length - stripRows.length}
                            </span>
                          ) : null}
                        </>
                      ) : (
                        <>
                          {people.slice(0, FOLDED_FACES).map((person) => (
                            <MemberAvatar
                              key={person.key}
                              size={20}
                              name={person.name}
                              colorKey={person.key}
                              avatar={person.avatar}
                            />
                          ))}
                          <span
                            data-slot="working-agents-summary"
                            className="shrink-0 text-xs text-muted-foreground">
                            {workingAgentsShortCount(rows)}
                          </span>
                        </>
                      )}
                      {failed > 0 ? (
                        <span
                          data-slot="working-agents-failed"
                          className="flex shrink-0 items-center gap-0.5 text-xs text-destructive">
                          <CircleAlert aria-hidden="true" className="size-3" />
                          {failed}
                        </span>
                      ) : null}
                    </span>
                  </span>
                </span>
                <span
                  className={cn(
                    UNFOLDS,
                    'grid-cols-[1fr] group-hover:grid-cols-[0fr] group-focus-visible:grid-cols-[0fr]',
                  )}>
                  <span className="min-w-0 overflow-hidden">
                    {tile === null ? null : (
                      <AgentsTile
                        lead={tile.lead}
                        others={tile.others}
                        activity={
                          anyoneWorking
                            ? 'working'
                            : live.length > 0
                              ? 'waiting'
                              : 'idle'
                        }
                      />
                    )}
                  </span>
                </span>
                {unseenFailures.length > 0 ? (
                  <StatusDot
                    tone="bad"
                    className="absolute -top-0.5 -right-0.5 size-2 ring-2 ring-popover transition-opacity group-hover:opacity-0 group-focus-visible:opacity-0"
                  />
                ) : null}
              </>
            )}
          </button>
        </section>
      </div>
      <CallConversationDialog
        row={rows.find((row) => row.conversationId === dialogId) ?? null}
        onClose={() => setDialogId(null)}
        runId={runId}
        api={api}
        client={client}
        nodes={nodes}
        chatAgentName={chatAgentName}
        delegateState={delegateState}
        collapseToolSteps={collapseToolSteps}
      />
    </>
  );
}
