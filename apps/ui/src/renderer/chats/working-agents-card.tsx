/** Below this pane width the open card would reach the centred Latest button. */
const OPEN_CARD_CLEAR_OF_LATEST_PX = 720;
/** The open card's lift above Latest on a narrow pane, plus a margin under the pane's top. */
const LIFTED_CARD_CLEARANCE_PX = 56;

/**
 * A control of the card under the pointer: the menu's row tint, since `muted`
 * is one shade off this popover surface in the dark theme.
 */
const CONTROL_HOVER =
  'transition-colors duration-150 ease-out hover:bg-accent motion-reduce:transition-none';

function failureSeenKey(row: WorkingAgentRow): string {
  return `working-agents:failure-seen:${row.callId}`;
}

interface PaneSize {
  width: number;
  height: number;
}

/** The size of the pane just before `anchor`, which the card floats over. */
function usePaneSize(anchor: HTMLElement | null): PaneSize | null {
  const [size, setSize] = useState<PaneSize | null>(null);
  useLayoutEffect(() => {
    const pane = anchor?.previousElementSibling;
    if (!pane) {
      return;
    }
    const measure = (): void =>
      setSize({ width: pane.clientWidth, height: pane.clientHeight });
    measure();
    if (typeof ResizeObserver === 'undefined') {
      return;
    }
    const observer = new ResizeObserver(measure);
    observer.observe(pane);
    return () => observer.disconnect();
  }, [anchor]);
  return size;
}

type TileActivity = 'working' | 'waiting' | 'idle';

/** The folded card at rest: one readable face, how many more, and whether anyone works. */
function AgentsTile({
  lead,
  others,
  activity,
}: {
  lead: WorkingAgentRow;
  others: number;
  activity: TileActivity;
}): React.JSX.Element {
  return (
    <span
      data-slot="working-agents-tile"
      data-activity={activity}
      className={cn(
        'relative grid size-8',
        others > 0 ? 'place-items-start p-px' : 'place-items-center',
      )}>
      <span className="relative flex size-7 items-center justify-center">
        {activity === 'idle' ? null : (
          <span
            aria-hidden="true"
            data-slot="working-agents-tile-ring"
            className={cn(
              'absolute inset-0 rounded-full border-2',
              activity === 'working'
                ? 'animate-spin border-primary/25 border-t-primary motion-reduce:animate-none'
                : 'border-muted-foreground/40',
            )}
          />
        )}
        <MemberAvatar
          size={24}
          name={lead.callee}
          colorKey={lead.calleeKey}
          avatar={lead.calleeAvatar}
        />
      </span>
      {others > 0 ? (
        <span
          data-slot="working-agents-tile-more"
          className="absolute right-px bottom-px rounded-full bg-popover px-0.5 text-[9px] leading-[10px] font-medium text-foreground tabular-nums">
          +{others}
        </span>
      ) : null}
    </span>
  );
}

/** The folded card's hover: who is running what right now, a level below the card itself. */
function CurrentRunsPanel({
  rows,
  runId,
  api,
  client,
}: {
  rows: readonly WorkingAgentRow[];
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
}): React.JSX.Element {
  const agents = currentRunsPerAgent(rows);
  const busy = rows.some(isWorkingAgentBusy);
  const settled = rows.filter((row) => !isWorkingAgentLive(row));
  return (
    <div className="flex flex-col">
      <div className="flex min-w-0 items-center gap-2 px-3 py-2">
        <CallGlyph
          live={busy}
          className={cn('size-3.5 shrink-0', busy && 'text-primary')}
        />
        <span className="shrink-0 text-sm font-semibold text-foreground">
          Agents
        </span>
        <span
          data-slot="working-agents-panel-summary"
          className="min-w-0 truncate text-xs text-muted-foreground">
          {agents.length === 0
            ? 'No current runs'
            : workingAgentsSummary(rows.filter(isWorkingAgentLive))}
        </span>
      </div>
      {agents.length === 0 ? null : (
        <div className="flex flex-col gap-1.5 border-t border-border/60 p-1.5">
          {agents.map((agent) => (
            <div
              key={agent.key}
              data-slot="working-agents-current-agent"
              className="flex min-w-0 flex-col gap-2.5 rounded-lg bg-accent/40 p-2.5">
              <div className="flex min-w-0 items-center gap-2">
                <MemberAvatar
                  size={24}
                  name={agent.name}
                  colorKey={agent.key}
                  avatar={agent.avatar}
                />
                <span className="min-w-0 truncate text-[13px] font-semibold text-foreground">
                  {agent.name}
                </span>
                <span
                  data-slot="working-agents-current-agent-runs"
                  className="ml-auto shrink-0 rounded-full bg-accent px-1.5 py-px text-[10px] text-muted-foreground tabular-nums">
                  {agent.runs.length} {agent.runs.length === 1 ? 'run' : 'runs'}
                </span>
              </div>
              {agent.runs.map((run) => (
                <div
                  key={run.conversationId}
                  data-slot="working-agents-current-run"
                  className="flex min-w-0 flex-col gap-2">
                  <WorkingAgentRunFacts row={run} />
                  <div
                    className={cn(
                      'border-l-2 pl-3',
                      workingAgentRailClass(run.state),
                    )}>
                    <RecentMessages
                      row={run}
                      runId={runId}
                      api={api}
                      client={client}
                      showOlder={false}
                    />
                  </div>
                </div>
              ))}
            </div>
          ))}
        </div>
      )}
      {settled.length === 0 ? null : (
        <p
          data-slot="working-agents-panel-settled"
          className="m-0 border-t border-border/60 px-3 py-1.5 text-[11px] text-muted-foreground">
          {workingAgentsSummary(settled)}
        </p>
      )}
    </div>
  );
}

/** A message as plain text: its whole length, with its line breaks. */
function messageText(item: ChatItem): string {
  return plainMarkdownText(payloadString(item.payload, 'text') ?? '').trim();
}

/** Mounted only where it is on view, which is what makes that the moment its messages are read. */
function RecentMessages({
  row,
  runId,
  api,
  client,
  showOlder = true,
}: {
  row: WorkingAgentRow;
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
  showOlder?: boolean;
}): React.JSX.Element {
  const { messages, hasOlder, loading, failed, retry } = useRecentCallMessages({
    api,
    client,
    runId,
    callId: row.callId,
    callIds: row.callIds,
  });
  if (failed && messages.length === 0) {
    return (
      <div
        data-slot="working-agent-messages-failed"
        className="flex items-center gap-1.5 text-[11px] text-muted-foreground">
        Couldn’t load the messages.
        <Button
          type="button"
          variant="ghost"
          size="sm"
          className="h-6 px-2 text-xs"
          onClick={retry}>
          Retry
        </Button>
      </div>
    );
  }
  if (loading && messages.length === 0) {
    return (
      <div
        role="status"
        data-slot="working-agent-messages-loading"
        className="flex items-center gap-1.5 text-[11px] text-muted-foreground">
        <Spinner />
        Loading messages…
      </div>
    );
  }
  return (
    <div data-slot="working-agent-messages" className="flex flex-col gap-3">
      {showOlder && hasOlder ? (
        <p
          data-slot="working-agent-older"
          className="m-0 text-[11px] text-muted-foreground">
          Earlier messages are above
        </p>
      ) : null}
      {messages.length === 0 ? (
        <p className="m-0 text-[11px] text-muted-foreground">
          No messages yet.
        </p>
      ) : null}
      {messages.map((item, index) => {
        const latest = index === messages.length - 1;
        return (
          <div
            key={item.id}
            data-slot="working-agent-message"
            data-latest={latest ? 'true' : undefined}
            className="relative flex flex-col gap-0.5">
            {latest ? (
              <WorkingAgentStateDot
                state={row.state}
                className="absolute top-1 -left-[17px] size-2"
              />
            ) : (
              <StatusDot
                tone="unknown"
                className="absolute top-1 -left-[17px] size-2"
              />
            )}
            <span className="text-[10px] text-muted-foreground tabular-nums">
              {formatClockTime(item.createdAt)}
            </span>
            <p
              className={cn(
                'm-0 text-xs/relaxed break-words whitespace-pre-wrap',
                latest ? 'text-foreground' : 'text-muted-foreground',
              )}>
              {messageText(item)}
            </p>
          </div>
        );
      })}
    </div>
  );
}

function AgentRow({
  row,
  open,
  onToggle,
  onShowAll,
  onShowInChat,
  runId,
  api,
  client,
}: {
  row: WorkingAgentRow;
  open: boolean;
  onToggle: () => void;
  onShowAll: () => void;
  onShowInChat: () => void;
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
}): React.JSX.Element {
  return (
    <div
      data-slot="working-agent-block"
      className="flex flex-col rounded-lg bg-accent/40">
      <button
        type="button"
        data-slot="working-agent-row"
        data-conversation={row.conversationId}
        aria-expanded={open}
        title={`${row.callee} — ${open ? 'hide' : 'show'} the latest messages`}
        onClick={onToggle}
        className={cn(
          'flex w-full min-w-0 flex-col gap-2 rounded-lg p-2.5 text-left font-normal',
          CONTROL_HOVER,
        )}>
        <WorkingAgentHead row={row} />
        <WorkingAgentTitle row={row} />
      </button>
      {open ? (
        <div
          data-slot="working-agent-thread"
          className={cn(
            'mx-2.5 mb-2.5 flex flex-col gap-2.5 border-l-2 pl-3',
            workingAgentRailClass(row.state),
          )}>
          <RecentMessages row={row} runId={runId} api={api} client={client} />
          <div className="-ml-2 flex items-center gap-1">
            <Button
              type="button"
              size="sm"
              variant="ghost"
              data-slot="working-agent-show-all"
              className="h-7 px-2 text-xs font-normal text-foreground"
              onClick={onShowAll}>
              Show all
            </Button>
            <Button
              type="button"
              size="sm"
              variant="ghost"
              data-slot="working-agent-show-in-chat"
              className="h-7 px-2 text-xs font-normal text-muted-foreground"
              title={`Open ${row.callee}’s card in the conversation`}
              onClick={onShowInChat}>
              Show in chat
            </Button>
          </div>
        </div>
      ) : null}
    </div>
  );
}

/**
 * The agents this team run has started, on the right of its transcript: each one
 * working shows its newest messages, and from there its whole conversation.
 *
 * It floats over the transcript rather than taking a column, so it appearing or
 * folding never reflows the text under the reader. The hanging row it sits in
 * lets every click but the card's own through.
 */
export function WorkingAgentsCard({
  rows,
  runId,
  api,
  client,
  onShowInChat,
  nodes,
  chatAgentName,
  delegateState,
  collapseToolSteps = false,
}: {
  rows: readonly WorkingAgentRow[];
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages' | 'listRunItems'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
  onShowInChat: (callId: string) => void;
  nodes?: ReadonlyMap<string, TranscriptNodeMeta>;
  chatAgentName?: string | null;
  delegateState?: Pick<RunStateDto, 'throughSeq' | 'delegates' | 'calls'>;
  collapseToolSteps?: boolean;
}): React.JSX.Element | null {
  const narrow = useNarrowViewport();
  const live = rows.filter(isWorkingAgentLive);
  const [pressed, setPressed] = useThreadOverride('working-agents:open');
  const [rowPresses, setRowPresses] = useState<ReadonlyMap<string, boolean>>(
    new Map(),
  );
  const open = pressed === true;
  const [finishedOpen, setFinishedOpen] = useThreadFlag(
    'working-agents:finished',
    false,
  );
  const [dialogId, setDialogId] = useState<string | null>(null);
  const [anchor, setAnchor] = useState<HTMLDivElement | null>(null);
  const pane = usePaneSize(anchor);
  const memory = useThreadFlags();
  const failures = rows.filter((row) => row.state === 'failed');
  const unseenFailures = failures.filter(
    (row) => memory.get(failureSeenKey(row)) !== true,
  );
  useEffect(() => {
    if (open) {
      for (const row of unseenFailures) {
        memory.set(failureSeenKey(row), true);
      }
    }
  });
  if (rows.length === 0) {
    return null;
  }
  const pressRow = (row: WorkingAgentRow, rowOpen: boolean): void =>
    setRowPresses((held) => new Map(held).set(row.conversationId, rowOpen));
  const isRowOpen = (row: WorkingAgentRow): boolean =>
    rowPresses.get(row.conversationId) ?? isWorkingAgentLive(row);
  // A row pressed open stays where it is when its agent finishes, instead of
  // dropping into the fold under the reader.
  const onTop = rows.filter(
    (row) =>
      isWorkingAgentLive(row) || rowPresses.get(row.conversationId) === true,
  );
  const finished = rows.filter((row) => !onTop.includes(row));
  const summary = workingAgentsSummary(rows);
  const busy = rows.some(isWorkingAgentBusy);
  const tile = leadWorkingAgent(rows, (row) => unseenFailures.includes(row));
  const anyoneWorking = rows.some((row) => row.state === 'working');
  const lifted =
    open && pane !== null && pane.width < OPEN_CARD_CLEAR_OF_LATEST_PX;
  const rowView = (row: WorkingAgentRow): React.JSX.Element => (
    <AgentRow
      key={row.conversationId}
      row={row}
      open={isRowOpen(row)}
      onToggle={() => pressRow(row, !isRowOpen(row))}
      onShowAll={() => setDialogId(row.conversationId)}
      onShowInChat={() => {
        // Stepping aside: left open, it would stand over the card it revealed.
        pressRow(row, false);
        if (narrow) {
          setPressed(false);
        }
        onShowInChat(row.callId);
      }}
      runId={runId}
      api={api}
      client={client}
    />
  );
  return (
    <>
      <div
        ref={setAnchor}
        className="pointer-events-none relative z-20 h-0 w-full overflow-visible">
        <section
          data-slot="working-agents-card"
          data-folded={!open}
          aria-label="Agents this run started"
          className={cn(
            popoverSurface,
            'pointer-events-auto right-4 z-20 flex max-w-[calc(100%-2rem)] flex-col',
            lifted ? 'bottom-12' : '-bottom-2',
            open && 'w-80',
            !open &&
              live.length === 0 &&
              unseenFailures.length === 0 &&
              'opacity-60 transition-opacity focus-within:opacity-100 hover:opacity-100',
          )}
          style={
            open && pane !== null
              ? {
                  maxHeight: lifted
                    ? pane.height - LIFTED_CARD_CLEARANCE_PX
                    : pane.height,
                }
              : undefined
          }>
          {open ? (
            <div className="flex max-h-[60vh] min-h-0 flex-col gap-0.5 overflow-y-auto overscroll-contain p-1">
              {onTop.map(rowView)}
              {finished.length > 0 ? (
                <button
                  type="button"
                  data-slot="working-agents-finished-toggle"
                  aria-expanded={finishedOpen}
                  onClick={() => setFinishedOpen((value) => !value)}
                  className={cn(
                    'flex items-center gap-1.5 rounded-md px-1.5 py-1 text-left text-xs font-normal text-muted-foreground hover:text-foreground',
                    CONTROL_HOVER,
                  )}>
                  <ChevronRight
                    aria-hidden="true"
                    className={cn(
                      'size-3 shrink-0 transition-transform',
                      finishedOpen && 'rotate-90',
                    )}
                  />
                  {workingAgentsSummary(finished)}
                </button>
              ) : null}
              {finishedOpen ? finished.map(rowView) : null}
            </div>
          ) : null}
          <HoverPopover
            slot="working-agents-toggle"
            openOn={open ? 'click' : 'hover'}
            onPress={() => setPressed(!open)}
            label={
              open
                ? 'Fold the agents card'
                : `Unfold the agents card · ${summary}`
            }
            title={open ? `Agents · ${summary}` : undefined}
            panelLabel="Current runs of each agent"
            side="top"
            className="shrink-0"
            triggerClassName={cn(
              'group min-w-0 rounded-xl text-left font-normal',
              CONTROL_HOVER,
              open
                ? 'w-full gap-2 rounded-t-none border-t border-border/60 px-2.5 py-1.5'
                : 'relative',
            )}
            panelClassName="w-80 p-0"
            trigger={
              open ? (
                <>
                  <CallGlyph
                    live={busy}
                    className={cn('size-3.5 shrink-0', busy && 'text-primary')}
                  />
                  <span className="shrink-0 text-sm font-semibold text-foreground">
                    Agents
                  </span>
                  <span
                    data-slot="working-agents-summary"
                    className="min-w-0 truncate text-xs text-muted-foreground transition-colors group-hover:text-foreground motion-reduce:transition-none">
                    {workingAgentsSummary(live)}
                  </span>
                  <ChevronDown
                    aria-hidden="true"
                    className="ml-auto size-3.5 shrink-0 text-muted-foreground transition-colors group-hover:text-foreground motion-reduce:transition-none"
                  />
                </>
              ) : (
                <>
                  {tile === null ? null : (
                    <AgentsTile
                      lead={tile.lead}
                      others={tile.others}
                      activity={
                        anyoneWorking
                          ? 'working'
                          : live.length > 0
                            ? 'waiting'
                            : 'idle'
                      }
                    />
                  )}
                  {unseenFailures.length > 0 ? (
                    <StatusDot
                      tone="bad"
                      className="absolute -top-0.5 -right-0.5 size-2 ring-2 ring-popover"
                    />
                  ) : null}
                </>
              )
            }>
            <CurrentRunsPanel
              rows={rows}
              runId={runId}
              api={api}
              client={client}
            />
          </HoverPopover>
        </section>
      </div>
      <CallConversationDialog
        row={rows.find((row) => row.conversationId === dialogId) ?? null}
        onClose={() => setDialogId(null)}
        runId={runId}
        api={api}
        client={client}
        nodes={nodes}
        chatAgentName={chatAgentName}
        delegateState={delegateState}
        collapseToolSteps={collapseToolSteps}
      />
    </>
  );
}
