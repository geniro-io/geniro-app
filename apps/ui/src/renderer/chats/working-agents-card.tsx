/**
 * A control of the panel under the pointer: the menu's row tint, since `muted`
 * is one shade off this popover surface in the dark theme.
 */
const CONTROL_HOVER =
  'transition-colors duration-150 ease-out hover:bg-accent motion-reduce:transition-none';

function failureSeenKey(row: WorkingAgentRow): string {
  return `working-agents:failure-seen:${row.callId}`;
}

/** A press that lands on a control of its own inside an openable block. */
function pressedOwnControl(event: React.MouseEvent): boolean {
  const control =
    event.target instanceof Element ? event.target.closest('button, a') : null;
  return control !== null && control !== event.currentTarget;
}

type TileActivity = 'working' | 'waiting' | 'idle';

/** The folded card at rest: one readable face, how many more, and whether anyone works. */
function AgentsTile({
  lead,
  others,
  activity,
}: {
  lead: WorkingAgentRow;
  others: number;
  activity: TileActivity;
}): React.JSX.Element {
  return (
    <span
      data-slot="working-agents-tile"
      data-activity={activity}
      className={cn(
        'relative grid size-8',
        others > 0 ? 'place-items-start p-px' : 'place-items-center',
      )}>
      <span className="relative flex size-7 items-center justify-center">
        {activity === 'idle' ? null : (
          <span
            aria-hidden="true"
            data-slot="working-agents-tile-ring"
            className={cn(
              'absolute inset-0 rounded-full border-2',
              activity === 'working'
                ? 'animate-spin border-primary/25 border-t-primary motion-reduce:animate-none'
                : 'border-muted-foreground/40',
            )}
          />
        )}
        <MemberAvatar
          size={24}
          name={lead.callee}
          colorKey={lead.calleeKey}
          avatar={lead.calleeAvatar}
        />
      </span>
      {others > 0 ? (
        <span
          data-slot="working-agents-tile-more"
          className="absolute right-px bottom-px rounded-full bg-popover px-0.5 text-[9px] leading-[10px] font-medium text-foreground tabular-nums">
          +{others}
        </span>
      ) : null}
    </span>
  );
}

/** A settled conversation in the panel's fold: who, how it ended, and what for. */
function SettledRun({
  row,
  onOpen,
}: {
  row: WorkingAgentRow;
  onOpen: () => void;
}): React.JSX.Element {
  return (
    <button
      type="button"
      data-slot="working-agents-settled-run"
      data-conversation={row.conversationId}
      title={`Open ${row.callee}’s conversation`}
      onClick={onOpen}
      className={cn(
        'flex w-full min-w-0 flex-col gap-2 rounded-lg p-2.5 text-left font-normal',
        CARD_BUTTON_CLASS,
      )}>
      <WorkingAgentHead row={row} />
      <WorkingAgentTitle row={row} />
    </button>
  );
}

/** Who is running what right now, each run opening its conversation, over what has settled. */
function AgentsPanel({
  rows,
  runId,
  api,
  client,
  onOpen,
}: {
  rows: readonly WorkingAgentRow[];
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
  onOpen: (row: WorkingAgentRow) => void;
}): React.JSX.Element {
  const current = rows.filter(isWorkingAgentLive);
  const busy = rows.some(isWorkingAgentBusy);
  const settled = rows.filter((row) => !isWorkingAgentLive(row));
  const [settledOpen, setSettledOpen] = useThreadFlag(
    'working-agents:finished',
    false,
  );
  return (
    <div className="flex flex-col">
      <div className="flex min-w-0 items-center gap-2 px-3 py-2">
        <CallGlyph
          live={busy}
          className={cn('size-3.5 shrink-0', busy && 'text-primary')}
        />
        <span className="shrink-0 text-sm font-semibold text-foreground">
          Agents
        </span>
        <span
          data-slot="working-agents-panel-summary"
          className="min-w-0 truncate text-xs text-muted-foreground">
          {current.length === 0
            ? 'No current runs'
            : workingAgentsSummary(current)}
        </span>
      </div>
      {current.length === 0 ? null : (
        <div className="flex flex-col gap-1.5 border-t border-border/60 p-1.5">
          {current.map((run) => (
            <div
              key={run.conversationId}
              data-slot="working-agents-current-run"
              data-conversation={run.conversationId}
              onClick={(event) => {
                if (!pressedOwnControl(event)) {
                  onOpen(run);
                }
              }}
              className={cn(
                'flex min-w-0 cursor-pointer flex-col gap-2 rounded-lg bg-accent/40 p-2.5',
                CONTROL_HOVER,
              )}>
              <button
                type="button"
                data-slot="working-agents-open-run"
                title={`Open ${run.callee}’s conversation`}
                onClick={() => onOpen(run)}
                className="flex w-full min-w-0 flex-col gap-2 rounded-sm text-left font-normal outline-none focus-visible:ring-2 focus-visible:ring-ring">
                <span className="flex min-w-0 items-center gap-2">
                  <MemberAvatar
                    size={24}
                    name={run.callee}
                    colorKey={run.calleeKey}
                    avatar={run.calleeAvatar}
                  />
                  <span
                    data-slot="working-agents-current-run-callee"
                    className="min-w-0 truncate text-[13px] font-semibold text-foreground">
                    {run.callee}
                  </span>
                </span>
                <WorkingAgentRunFacts row={run} />
              </button>
              <div
                className={cn(
                  'border-l-2 pl-3',
                  workingAgentRailClass(run.state),
                )}>
                <RecentMessages
                  row={run}
                  runId={runId}
                  api={api}
                  client={client}
                />
              </div>
            </div>
          ))}
        </div>
      )}
      {settled.length === 0 ? null : (
        <div className="flex flex-col gap-0.5 border-t border-border/60 p-1">
          <button
            type="button"
            data-slot="working-agents-panel-settled"
            aria-expanded={settledOpen}
            onClick={() => setSettledOpen((value) => !value)}
            className={cn(
              'flex items-center gap-1.5 rounded-md px-1.5 py-1 text-left text-[11px] font-normal text-muted-foreground hover:text-foreground',
              CONTROL_HOVER,
            )}>
            <ChevronRight
              aria-hidden="true"
              className={cn(
                'size-3 shrink-0 transition-transform',
                settledOpen && 'rotate-90',
              )}
            />
            {workingAgentsSummary(settled)}
          </button>
          {settledOpen
            ? settled.map((row) => (
                <SettledRun
                  key={row.conversationId}
                  row={row}
                  onOpen={() => onOpen(row)}
                />
              ))
            : null}
        </div>
      )}
    </div>
  );
}

/** A message as plain text: its whole length, with its line breaks. */
function messageText(item: ChatItem): string {
  return plainMarkdownText(payloadString(item.payload, 'text') ?? '').trim();
}

/** Mounted only where it is on view, which is what makes that the moment its messages are read. */
function RecentMessages({
  row,
  runId,
  api,
  client,
}: {
  row: WorkingAgentRow;
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
}): React.JSX.Element {
  const { messages, loading, failed, retry } = useRecentCallMessages({
    api,
    client,
    runId,
    callId: row.callId,
    callIds: row.callIds,
  });
  if (failed && messages.length === 0) {
    return (
      <div
        data-slot="working-agent-messages-failed"
        className="flex items-center gap-1.5 text-[11px] text-muted-foreground">
        Couldn’t load the messages.
        <Button
          type="button"
          variant="ghost"
          size="sm"
          className="h-6 px-2 text-xs"
          onClick={retry}>
          Retry
        </Button>
      </div>
    );
  }
  if (loading && messages.length === 0) {
    return (
      <div
        role="status"
        data-slot="working-agent-messages-loading"
        className="flex items-center gap-1.5 text-[11px] text-muted-foreground">
        <Spinner />
        Loading messages…
      </div>
    );
  }
  return (
    <div data-slot="working-agent-messages" className="flex flex-col gap-3">
      {messages.length === 0 ? (
        <p className="m-0 text-[11px] text-muted-foreground">
          No messages yet.
        </p>
      ) : null}
      {messages.map((item, index) => {
        const latest = index === messages.length - 1;
        return (
          <div
            key={item.id}
            data-slot="working-agent-message"
            data-latest={latest ? 'true' : undefined}
            className="relative flex flex-col gap-0.5">
            {latest ? (
              <WorkingAgentStateDot
                state={row.state}
                className="absolute top-1 -left-[17px] size-2"
              />
            ) : (
              <StatusDot
                tone="unknown"
                className="absolute top-1 -left-[17px] size-2"
              />
            )}
            <span className="text-[10px] text-muted-foreground tabular-nums">
              {formatClockTime(item.createdAt)}
            </span>
            <p
              className={cn(
                'm-0 text-xs/relaxed break-words whitespace-pre-wrap',
                latest ? 'text-foreground' : 'text-muted-foreground',
              )}>
              {messageText(item)}
            </p>
          </div>
        );
      })}
    </div>
  );
}

/**
 * The agents this team run has started, on the right of its transcript: a
 * square whose panel — on hover, or pinned by a press — lists who runs what,
 * and a press on any of them opens that whole conversation.
 *
 * It floats over the transcript rather than taking a column, so it appearing
 * never reflows the text under the reader. The hanging row it sits in lets
 * every click but the card's own through.
 */
export function WorkingAgentsCard({
  rows,
  runId,
  api,
  client,
  onShowInChat,
  nodes,
  chatAgentName,
  delegateState,
  collapseToolSteps = false,
}: {
  rows: readonly WorkingAgentRow[];
  runId: string;
  api: Pick<ChatsApi, 'listCallMessages' | 'listRunItems'>;
  client: Pick<DaemonClient, 'onItem' | 'onReconnect'>;
  onShowInChat: (callId: string) => void;
  nodes?: ReadonlyMap<string, TranscriptNodeMeta>;
  chatAgentName?: string | null;
  delegateState?: Pick<RunStateDto, 'throughSeq' | 'delegates' | 'calls'>;
  collapseToolSteps?: boolean;
}): React.JSX.Element | null {
  const live = rows.filter(isWorkingAgentLive);
  const [panelOpen, setPanelOpen] = useState(false);
  const [dialogId, setDialogId] = useState<string | null>(null);
  const memory = useThreadFlags();
  const unseenFailures = rows.filter(
    (row) => row.state === 'failed' && memory.get(failureSeenKey(row)) !== true,
  );
  useEffect(() => {
    if (panelOpen) {
      for (const row of unseenFailures) {
        memory.set(failureSeenKey(row), true);
      }
    }
  });
  if (rows.length === 0) {
    return null;
  }
  const summary = workingAgentsSummary(rows);
  const tile = leadWorkingAgent(rows, (row) => unseenFailures.includes(row));
  const anyoneWorking = rows.some((row) => row.state === 'working');
  return (
    <>
      <div className="pointer-events-none relative z-20 h-0 w-full overflow-visible">
        <section
          data-slot="working-agents-card"
          aria-label="Agents this run started"
          className={cn(
            popoverSurface,
            'pointer-events-auto right-4 -bottom-2 z-20 flex flex-col',
            !panelOpen &&
              live.length === 0 &&
              unseenFailures.length === 0 &&
              'opacity-60 transition-opacity focus-within:opacity-100 hover:opacity-100',
          )}>
          <HoverPopover
            slot="working-agents-toggle"
            label={`Agents · ${summary}`}
            panelLabel="Agents this run started"
            side="top"
            onOpenChange={setPanelOpen}
            className="shrink-0"
            triggerClassName={cn(
              'group relative min-w-0 rounded-xl text-left font-normal',
              CONTROL_HOVER,
            )}
            panelClassName="w-80 p-0"
            trigger={
              <>
                {tile === null ? null : (
                  <AgentsTile
                    lead={tile.lead}
                    others={tile.others}
                    activity={
                      anyoneWorking
                        ? 'working'
                        : live.length > 0
                          ? 'waiting'
                          : 'idle'
                    }
                  />
                )}
                {unseenFailures.length > 0 ? (
                  <StatusDot
                    tone="bad"
                    className="absolute -top-0.5 -right-0.5 size-2 ring-2 ring-popover"
                  />
                ) : null}
              </>
            }>
            {(close) => (
              <AgentsPanel
                rows={rows}
                runId={runId}
                api={api}
                client={client}
                onOpen={(row) => {
                  close();
                  setDialogId(row.conversationId);
                }}
              />
            )}
          </HoverPopover>
        </section>
      </div>
      <CallConversationDialog
        row={rows.find((row) => row.conversationId === dialogId) ?? null}
        onClose={() => setDialogId(null)}
        runId={runId}
        api={api}
        client={client}
        nodes={nodes}
        chatAgentName={chatAgentName}
        delegateState={delegateState}
        collapseToolSteps={collapseToolSteps}
        onShowInChat={(callId) => {
          setDialogId(null);
          onShowInChat(callId);
        }}
      />
    </>
  );
}
