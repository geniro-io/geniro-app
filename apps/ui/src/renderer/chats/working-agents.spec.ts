import { describe, expect, it } from 'vitest';

import type { CallClock, RunCallState } from '../autogenerated';
import type { CallBlockEntry } from './transcript-groups';
import type { TranscriptNodeMeta } from './transcript-payload';
import {
  leadWorkingAgent,
  type WorkingAgentRow,
  workingAgentRows,
  workingAgentsSummary,
} from './working-agents';

const nodes = new Map<string, TranscriptNodeMeta>([
  ['manager', { name: 'Manager', kind: 'agent' }],
  ['engineer', { name: 'Engineer', kind: 'agent' }],
  ['researcher', { name: 'Researcher', kind: 'agent' }],
]);

const call = (over: Partial<RunCallState> = {}): RunCallState => ({
  callId: 'call-1',
  callerMemberId: 'manager',
  calleeMemberId: 'engineer',
  title: 'Fix the drop zone',
  brief: null,
  mode: null,
  thread: null,
  startSeq: 2,
  startedAt: '2026-11-08T12:00:00.000Z',
  endedAt: null,
  status: 'running',
  queued: false,
  member: null,
  ...over,
});

const block = (over: Partial<CallBlockEntry> = {}): CallBlockEntry =>
  ({
    type: 'call-block',
    id: 'call-1',
    createdAt: '2026-11-08T12:00:00.000Z',
    callId: 'call-1',
    callIds: ['call-1'],
    conversationCallIds: ['call-1'],
    calleeMemberId: 'engineer',
    callerMemberId: 'manager',
    mode: null,
    message: null,
    title: 'Fix the drop zone',
    status: 'running',
    result: null,
    stalled: false,
    ...over,
  }) as CallBlockEntry;

const clock = (over: Partial<CallClock> = {}): CallClock => ({
  closedMs: 0,
  runningSince: null,
  parkedMs: 0,
  parkedSince: null,
  openCards: [],
  throughSeq: 0,
  ...over,
});

const chainOf = (...callIds: string[]): [string, readonly string[]][] =>
  callIds.map((callId) => [callId, callIds]);

function rowsOf(
  input: Partial<Parameters<typeof workingAgentRows>[0]>,
): WorkingAgentRow[] {
  return workingAgentRows({
    calls: [],
    chains: new Map(),
    blocks: { open: [], drawn: new Set() },
    runSettled: false,
    nodes,
    clocks: new Map(),
    ...input,
  });
}

const stateOf = (
  rows: readonly WorkingAgentRow[],
  callId: string,
): WorkingAgentRow['state'] | undefined =>
  rows.find((row) => row.callId === callId)?.state;

describe('workingAgentRows', () => {
  it('folds a chain of two calls into one row: its first call as the conversation, its newest as the call', () => {
    const rows = rowsOf({
      calls: [
        call({
          callId: 'call-1',
          status: 'completed',
          endedAt: '2026-11-08T12:04:00.000Z',
        }),
        call({ callId: 'call-3', thread: 'call-1' }),
      ],
      chains: new Map(chainOf('call-1', 'call-3')),
    });

    expect(rows).toHaveLength(1);
    expect(rows[0]).toMatchObject({
      conversationId: 'call-1',
      callId: 'call-3',
      callIds: ['call-1', 'call-3'],
      state: 'working',
    });
  });

  it('reads a running call as working, and a running call waiting for room as queued', () => {
    const rows = rowsOf({
      calls: [
        call({ callId: 'call-1' }),
        call({ callId: 'call-2', calleeMemberId: 'researcher', queued: true }),
      ],
    });

    expect(stateOf(rows, 'call-1')).toBe('working');
    expect(stateOf(rows, 'call-2')).toBe('queued');
  });

  it('reads a completed call as finished, a failed one as failed and a cancelled one as stopped', () => {
    const rows = rowsOf({
      calls: [
        call({ callId: 'call-1', status: 'completed' }),
        call({ callId: 'call-2', status: 'failed' }),
        call({ callId: 'call-3', status: 'cancelled' }),
      ],
    });

    expect(stateOf(rows, 'call-1')).toBe('finished');
    expect(stateOf(rows, 'call-2')).toBe('failed');
    expect(stateOf(rows, 'call-3')).toBe('stopped');
  });

  it('reads a running call whose card is drawn and not open as finished', () => {
    const rows = rowsOf({
      calls: [call({ callId: 'call-1', status: 'running' })],
      blocks: { open: [], drawn: new Set(['call-1']) },
    });

    expect(stateOf(rows, 'call-1')).toBe('finished');
  });

  it('lists an open window block the daemon does not list yet as a live row', () => {
    const rows = rowsOf({
      blocks: {
        open: [
          block({
            id: 'call-9',
            callId: 'call-9',
            callIds: ['call-9'],
            conversationCallIds: ['call-9'],
            status: 'running',
          }),
        ],
        drawn: new Set(['call-9']),
      },
    });

    expect(rows).toHaveLength(1);
    expect(rows[0]).toMatchObject({
      conversationId: 'call-9',
      callId: 'call-9',
      state: 'working',
    });
  });

  it('finishes every row once the run has settled', () => {
    const rows = rowsOf({
      calls: [
        call({ callId: 'call-1' }),
        call({ callId: 'call-2', calleeMemberId: 'researcher', queued: true }),
      ],
      blocks: {
        open: [
          block({
            id: 'call-3',
            callId: 'call-3',
            callIds: ['call-3'],
            conversationCallIds: ['call-3'],
            status: 'running',
          }),
        ],
        drawn: new Set(),
      },
      runSettled: true,
    });

    expect(rows).toHaveLength(3);
    expect(rows.map((row) => row.state)).toEqual([
      'finished',
      'finished',
      'finished',
    ]);
  });

  it("gives a chain's row its newest call's title and start", () => {
    const rows = rowsOf({
      calls: [
        call({
          callId: 'call-1',
          title: 'Fix the drop zone',
          startedAt: '2026-11-08T12:00:00.000Z',
        }),
        call({
          callId: 'call-3',
          thread: 'call-1',
          title: 'Second pass',
          startedAt: '2026-11-08T12:05:00.000Z',
        }),
      ],
      chains: new Map(chainOf('call-1', 'call-3')),
    });

    expect(rows[0]).toMatchObject({
      title: 'Second pass',
      startedAt: Date.parse('2026-11-08T12:05:00.000Z'),
    });
  });

  it('names a row’s callee and caller as the transcript names their members', () => {
    const rows = rowsOf({
      calls: [
        call({
          callId: 'call-1',
          callerMemberId: 'manager',
          calleeMemberId: 'engineer',
        }),
        call({
          callId: 'call-2',
          callerMemberId: null,
          calleeMemberId: 'researcher',
        }),
      ],
    });

    expect(rows.find((row) => row.callId === 'call-1')).toMatchObject({
      callee: 'Engineer',
      calleeKey: 'engineer',
      caller: 'Manager',
      callerKey: 'manager',
    });
    expect(rows.find((row) => row.callId === 'call-2')).toMatchObject({
      callee: 'Researcher',
      calleeKey: 'researcher',
      caller: null,
      callerKey: null,
    });
  });

  it('reads an open block its daemon marked stalled as quiet', () => {
    const rows = rowsOf({
      calls: [call({ callId: 'call-1' })],
      blocks: {
        open: [block({ stalled: true })],
        drawn: new Set(['call-1']),
      },
    });

    expect(stateOf(rows, 'call-1')).toBe('quiet');
  });

  it('carries the clock of every call a chain folds into its row', () => {
    const first = clock({ closedMs: 40_000, throughSeq: 3 });
    const second = clock({ runningSince: 1, throughSeq: 9 });
    const rows = rowsOf({
      calls: [
        call({
          callId: 'call-1',
          status: 'completed',
          endedAt: '2026-11-08T12:04:00.000Z',
        }),
        call({ callId: 'call-3', thread: 'call-1' }),
      ],
      chains: new Map(chainOf('call-1', 'call-3')),
      clocks: new Map([
        ['call-1', first],
        ['call-3', second],
      ]),
    });

    expect(rows).toHaveLength(1);
    expect(rows[0]!.clocks).toHaveLength(2);
    expect(rows[0]!.clocks).toEqual(expect.arrayContaining([first, second]));
  });

  it('reads a queued call’s open card as queued, not working', () => {
    const rows = rowsOf({
      blocks: { open: [block({ queued: true })], drawn: new Set(['call-1']) },
    });

    expect(rows[0]?.state).toBe('queued');
  });

  it('lists the newest conversation first', () => {
    const rows = rowsOf({
      calls: [
        call({ callId: 'call-1', startSeq: 2 }),
        call({ callId: 'call-2', startSeq: 30 }),
        call({ callId: 'call-3', startSeq: 10 }),
      ],
    });

    expect(rows.map((row) => row.callId)).toEqual([
      'call-2',
      'call-3',
      'call-1',
    ]);
  });

  it('falls back on an earlier call’s title when the newest named none', () => {
    const rows = rowsOf({
      calls: [
        call({ callId: 'call-1', title: 'The first ask' }),
        call({ callId: 'call-3', thread: 'call-1', title: null }),
      ],
      chains: new Map(chainOf('call-1', 'call-3')),
    });

    expect(rows[0]?.title).toBe('The first ask');
  });

  it('reads the newest call the daemon knows when the chain’s last is not on its list yet', () => {
    const rows = rowsOf({
      calls: [call({ callId: 'call-1' })],
      chains: new Map(chainOf('call-1', 'call-3')),
    });

    expect(rows[0]).toMatchObject({
      conversationId: 'call-1',
      callId: 'call-1',
      callIds: ['call-1', 'call-3'],
    });
  });
});

describe('workingAgentsSummary', () => {
  const row = (state: WorkingAgentRow['state']): WorkingAgentRow =>
    ({ state }) as WorkingAgentRow;

  it.each<[readonly WorkingAgentRow['state'][], string]>([
    [['working', 'quiet', 'queued'], '2 working · 1 queued'],
    [['queued'], '1 queued'],
    [['finished', 'finished'], '2 finished'],
    [['finished', 'failed', 'stopped'], '1 finished · 1 failed · 1 stopped'],
    [['working', 'finished'], '1 working · 1 finished'],
  ])('%j reads %s', (states, expected) => {
    expect(workingAgentsSummary(states.map(row))).toBe(expected);
  });
});

describe('leadWorkingAgent', () => {
  const row = (
    callId: string,
    calleeKey: string,
    state: WorkingAgentRow['state'],
  ): WorkingAgentRow => ({ callId, calleeKey, state }) as WorkingAgentRow;
  const nothingUnseen = (): boolean => false;

  it('has no lead with no rows', () => {
    expect(leadWorkingAgent([], nothingUnseen)).toBeNull();
  });

  it('puts an unseen failure over someone working', () => {
    const failed = row('call-2', 'qa', 'failed');
    const rows = [row('call-1', 'engineer', 'working'), failed];

    expect(leadWorkingAgent(rows, (item) => item === failed)?.lead).toBe(
      failed,
    );
  });

  it('puts a seen failure behind everyone live', () => {
    const queued = row('call-1', 'engineer', 'queued');
    const rows = [row('call-2', 'qa', 'failed'), queued];

    expect(leadWorkingAgent(rows, nothingUnseen)?.lead).toBe(queued);
  });

  it('takes the newest of those working, over one queued ahead of it', () => {
    const newest = row('call-2', 'engineer', 'working');
    const rows = [
      row('call-3', 'qa', 'queued'),
      newest,
      row('call-1', 'researcher', 'working'),
    ];

    expect(leadWorkingAgent(rows, nothingUnseen)?.lead).toBe(newest);
  });

  it('counts every other live conversation, two of one agent as two, leaving out the settled', () => {
    const rows = [
      row('call-1', 'engineer', 'working'),
      row('call-2', 'engineer', 'queued'),
      row('call-3', 'qa', 'quiet'),
      row('call-4', 'qa', 'queued'),
      row('call-5', 'researcher', 'finished'),
    ];

    expect(leadWorkingAgent(rows, nothingUnseen)?.others).toBe(3);
  });

  it('counts the live conversations past a failure that leads', () => {
    const failed = row('call-1', 'qa', 'failed');
    const rows = [failed, row('call-2', 'engineer', 'working')];

    expect(leadWorkingAgent(rows, (item) => item === failed)?.others).toBe(1);
  });

  it('counts the run’s other conversations when nobody is live', () => {
    const rows = [
      row('call-1', 'engineer', 'finished'),
      row('call-2', 'qa', 'failed'),
      row('call-3', 'engineer', 'stopped'),
    ];

    expect(leadWorkingAgent(rows, nothingUnseen)?.others).toBe(2);
  });
});
