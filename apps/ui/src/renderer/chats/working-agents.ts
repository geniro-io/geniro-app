import type { CallClock, RunCallState } from '../autogenerated';
import type { AvatarLook } from '../components/member-avatar';
import { conversationClocks } from './call-context';
import type { CallBlockEntry } from './transcript-groups';
import type { TranscriptNodeMeta } from './transcript-payload';
import { parsedAt } from './turn-duration';

export type WorkingAgentState =
  'working' | 'queued' | 'quiet' | 'finished' | 'failed' | 'stopped';

/** One conversation a team member was called into, as the working-agents card lists it. */
export interface WorkingAgentRow {
  /** The chain's first call: the identity that stays put as it is continued. */
  conversationId: string;
  /** The chain's newest call, which names its card in the conversation. */
  callId: string;
  callIds: readonly string[];
  callee: string;
  calleeKey: string;
  calleeAvatar?: AvatarLook;
  caller: string | null;
  callerKey: string | null;
  callerAvatar?: AvatarLook;
  title: string | null;
  state: WorkingAgentState;
  /** When the newest call started, epoch ms, null when nothing recorded it. */
  startedAt: number | null;
  clocks: readonly CallClock[];
}

/** Whether the agent is still out: a queued call is out too, though nobody works on it. */
export function isWorkingAgentLive(row: WorkingAgentRow): boolean {
  return (
    row.state === 'working' || row.state === 'queued' || row.state === 'quiet'
  );
}

const SETTLED_STATE: Record<
  Exclude<RunCallState['status'], 'running'>,
  WorkingAgentState
> = {
  completed: 'finished',
  failed: 'failed',
  cancelled: 'stopped',
};

/**
 * The run's agents, one row per conversation, newest first.
 *
 * The daemon's list of calls says who ever ran, over the whole run. The window
 * only corrects what is still moving: its open cards may not be on the daemon's
 * list yet, and a card it drew shut may still read `running` there for the
 * moment until the list is read again.
 */
export function workingAgentRows({
  calls,
  chains,
  blocks,
  runSettled,
  nodes,
  clocks,
}: {
  calls: readonly RunCallState[];
  chains: ReadonlyMap<string, readonly string[]>;
  blocks: {
    open: readonly CallBlockEntry[];
    drawn: ReadonlySet<string>;
  };
  runSettled: boolean;
  nodes: ReadonlyMap<string, TranscriptNodeMeta>;
  clocks: ReadonlyMap<string, CallClock>;
}): WorkingAgentRow[] {
  const callsById = new Map(calls.map((call) => [call.callId, call] as const));
  const openBlockOf = new Map(
    blocks.open.flatMap((block) =>
      block.callIds.map((callId) => [callId, block] as const),
    ),
  );
  const faces = (
    calleeId: string | null,
    callerId: string | null,
  ): Pick<
    WorkingAgentRow,
    | 'callee'
    | 'calleeKey'
    | 'calleeAvatar'
    | 'caller'
    | 'callerKey'
    | 'callerAvatar'
  > => {
    const nameOf = (memberId: string): string =>
      nodes.get(memberId)?.name ?? memberId;
    const callee = calleeId === null ? 'a called agent' : nameOf(calleeId);
    return {
      callee,
      calleeKey: calleeId ?? callee,
      calleeAvatar: calleeId === null ? undefined : nodes.get(calleeId)?.avatar,
      caller: callerId === null ? null : nameOf(callerId),
      callerKey: callerId,
      callerAvatar: callerId === null ? undefined : nodes.get(callerId)?.avatar,
    };
  };
  const stateOf = (
    call: RunCallState | undefined,
    block: CallBlockEntry | undefined,
  ): WorkingAgentState => {
    const live: WorkingAgentState | null =
      block !== undefined
        ? block.queued === true
          ? 'queued'
          : block.stalled
            ? 'quiet'
            : 'working'
        : call === undefined ||
            call.status !== 'running' ||
            blocks.drawn.has(call.callId)
          ? null
          : call.queued
            ? 'queued'
            : 'working';
    if (live !== null) {
      return runSettled ? 'finished' : live;
    }
    return call === undefined || call.status === 'running'
      ? 'finished'
      : SETTLED_STATE[call.status];
  };

  const rows = new Map<string, { row: WorkingAgentRow; order: number }>();
  const add = (
    chain: readonly string[],
    build: (newest: string) => { row: WorkingAgentRow; order: number },
  ): void => {
    const conversationId = chain[0]!;
    if (!rows.has(conversationId)) {
      rows.set(conversationId, build(chain[chain.length - 1]!));
    }
  };

  for (const call of calls) {
    const chain = chains.get(call.callId) ?? [call.callId];
    add(chain, (head) => {
      const known = chain.filter((callId) => callsById.has(callId));
      const newest = callsById.get(head) ?? callsById.get(known.at(-1)!)!;
      const block = chain
        .map((callId) => openBlockOf.get(callId))
        .find((open) => open !== undefined);
      return {
        order: newest.startSeq,
        row: {
          conversationId: chain[0]!,
          callId: newest.callId,
          callIds: chain,
          ...faces(newest.calleeMemberId, newest.callerMemberId),
          title:
            [...known]
              .reverse()
              .map((callId) => callsById.get(callId)!.title)
              .find((title) => title !== null) ?? null,
          state: stateOf(newest, block),
          startedAt: parsedAt(newest.startedAt),
          clocks: conversationClocks(clocks, chain),
        },
      };
    });
  }
  for (const block of blocks.open) {
    const chain =
      block.callIds
        .map((callId) => chains.get(callId))
        .find((known) => known !== undefined) ?? block.callIds;
    add(chain, () => ({
      order: Number.MAX_SAFE_INTEGER,
      row: {
        conversationId: chain[0]!,
        callId: block.callId,
        callIds: chain,
        ...faces(block.calleeMemberId, block.callerMemberId),
        title: block.title,
        state: stateOf(undefined, block),
        startedAt: parsedAt(block.createdAt),
        clocks: conversationClocks(clocks, chain),
      },
    }));
  }
  return [...rows.values()]
    .sort((a, b) => b.order - a.order)
    .map(({ row }) => row);
}

/** Whether somebody is working on it now: a queued call is out, but nobody is. */
export function isWorkingAgentBusy(row: WorkingAgentRow): boolean {
  return row.state === 'working' || row.state === 'quiet';
}

/** "2 working · 1 queued · 3 finished · 1 failed", leaving out what there is none of. */
export function workingAgentsSummary(rows: readonly WorkingAgentRow[]): string {
  const count = (test: (row: WorkingAgentRow) => boolean): number =>
    rows.filter(test).length;
  return (
    [
      ['working', count(isWorkingAgentBusy)],
      ['queued', count((row) => row.state === 'queued')],
      ['finished', count((row) => row.state === 'finished')],
      ['failed', count((row) => row.state === 'failed')],
      ['stopped', count((row) => row.state === 'stopped')],
    ] as const
  )
    .filter(([, figure]) => figure > 0)
    .map(([word, figure]) => `${figure} ${word}`)
    .join(' · ');
}
