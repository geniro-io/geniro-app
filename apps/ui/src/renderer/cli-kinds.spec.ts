import { describe, expect, expectTypeOf, it } from 'vitest';

import { CLI_KINDS, type CliKind } from '../shared/contracts';
import { AgentKind } from './autogenerated';

describe('CLI_KINDS', () => {
  it('lists exactly the agent kinds the daemon publishes', () => {
    // `CliKind` is spelled by hand (`contracts.ts` holds no daemon shapes), so
    // the generated `AgentKind` is the only thing that can say when they drift.
    expectTypeOf<CliKind>().toEqualTypeOf<AgentKind>();
    // The line above is a compile-time check vitest never runs; this one fails
    // under vitest alone.
    expect([...CLI_KINDS].sort()).toEqual(Object.values(AgentKind).sort());
  });
});
