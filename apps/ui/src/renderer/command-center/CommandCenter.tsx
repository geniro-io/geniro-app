/** How often the idle marks and the graph's lit edges move on. */
const CLOCK_TICK_MS = 30_000;

type SidebarTab = 'needs' | 'timeline';

const CHAT_BUTTON_ROOM = 72;
const WINDOW_INSET = 16;

/** Where the manager's chat first opens: the page's bottom-right corner, above its chat button. */
export function managerWindowRect(bounds: WindowBounds): WindowRect {
  const width = Math.min(480, bounds.width - WINDOW_INSET * 2);
  const height = Math.min(680, bounds.height - WINDOW_INSET - CHAT_BUTTON_ROOM);
  return {
    x: bounds.width - width - WINDOW_INSET,
    y: bounds.height - height - CHAT_BUTTON_ROOM,
    width,
    height,
  };
}

function useClock(): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    const timer = setInterval(() => setNow(Date.now()), CLOCK_TICK_MS);
    return () => clearInterval(timer);
  }, []);
  return now;
}

/**
 * The command center: the live graph with the manager on top and every active
 * thread under it as a card, and the manager's chat in a window over it, one
 * press of the chat button away. The daemon folds everything; this page only
 * draws it and asks again when a card moves.
 */
export function CommandCenter({
  handle,
  client,
  active,
  onOpenThread,
}: {
  handle: DaemonHandle;
  client: DaemonClient | null;
  /**
   * Whether the page is on screen: the board and the timeline read nothing
   * while it is not.
   */
  active: boolean;
  onOpenThread: (runId: string) => void;
}): React.JSX.Element {
  const apis = useMemo(() => createDaemonApis(handle), [handle]);
  const contextReader = useMemo(
    () => threadContextReaderOf(apis.chats),
    [apis],
  );
  const identities = useContext(AgentIdentityContext);
  const narrow = useNarrowViewport();
  const [chatOpen, setChatOpen] = useState(false);
  const [front, setFront] = useState<'manager' | 'cards'>('manager');
  const cardOpeners = useRef(new Map<string, Element | null>());
  const [teamFaces, setTeamFaces] = useState<ReadonlyMap<string, TeamFace>>(
    () => new Map(),
  );
  const [projectFilter, setProjectFilter] = useState(ALL_PROJECTS);
  const sources = useRunConfigSources(apis);
  const { capabilities, loading: capabilitiesLoading } = useSharedCapabilities(
    apis.capabilities,
  );
  const managerChoice = useManagerChoice(sources.cliDetections);
  const board = useCommandCenterBoard(apis, client, active);
  const unknownTeams = [
    ...new Set(
      (board.cards ?? []).flatMap((card) =>
        card.run.teamId !== null &&
        card.run.teamId !== undefined &&
        !teamFaces.has(card.run.teamId)
          ? [card.run.teamId]
          : [],
      ),
    ),
  ]
    .sort()
    .join(',');
  useEffect(() => {
    let live = true;
    void apis.teams
      .listTeams()
      .then((teams) => {
        if (live) {
          setTeamFaces(teamFacesOf(teams));
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, [apis, unknownTeams]);
  const [sidebar, setSidebar] = useState<SidebarTab | null>(null);
  const cards = useOpenCards(narrow);
  const nodePositions = useNodePositions();
  const blockPlaces = useBlockPlaces();
  const blockOrders = useBlockOrders();
  const [focus, setFocus] = useState<GraphFocus | null>(null);
  const [offBoard, setOffBoard] = useState<string | null>(null);
  const [archived, setArchived] = useState<{
    runId: string;
    title: string;
  } | null>(null);
  const [undoError, setUndoError] = useState<string | null>(null);
  const timeline = useCommandCenterTimeline(
    apis,
    client,
    sidebar === 'timeline' && active,
  );
  const asking = useMemo(
    () =>
      (board.cards ?? []).flatMap((card): AskingThread[] =>
        card.run.awaiting === null || card.run.awaiting === undefined
          ? []
          : [
              {
                runId: card.run.id,
                title: card.run.title ?? 'Untitled thread',
                isTeam:
                  card.run.teamId !== null && card.run.teamId !== undefined,
                awaiting: card.run.awaiting,
                lastActivityAt: card.run.lastActivityAt ?? card.run.createdAt,
              },
            ],
      ),
    [board.cards],
  );
  const openRequests = useOpenRequests(
    apis,
    client,
    asking,
    board.markAnswered,
  );
  const askingByRun = useMemo(() => {
    const byRun = new Map<string, OpenRequest>();
    for (const request of openRequests.requests) {
      if (!byRun.has(request.runId)) {
        byRun.set(request.runId, request);
      }
    }
    return byRun;
  }, [openRequests.requests]);
  const askingKinds = useMemo(
    () =>
      new Map(
        [...askingByRun].map(([runId, request]) => [runId, askKindOf(request)]),
      ),
    [askingByRun],
  );
  const toggleSidebar = (tab: SidebarTab): void =>
    setSidebar((open) => (open === tab ? null : tab));
  const [answering, setAnswering] = useState<{
    runId: string;
    anchor: HTMLElement;
    title: string | null;
    from: 'graph' | 'timeline';
  } | null>(null);
  const answerFrom = (runId: string, anchor: HTMLElement): void =>
    setAnswering({ runId, anchor, title: null, from: 'graph' });
  const openItemIds = useMemo(
    () => new Set(openRequests.requests.map((request) => request.item.id)),
    [openRequests.requests],
  );
  const answeringRequests =
    answering === null
      ? []
      : openRequests.requests.filter(
          (request) => request.runId === answering.runId,
        );
  const answeredAll = answering !== null && answeringRequests.length === 0;
  const answeringHidden =
    answering !== null &&
    answering.from === 'timeline' &&
    sidebar !== 'timeline';
  useEffect(() => {
    if (answeredAll || answeringHidden) {
      setAnswering(null);
    }
  }, [answeredAll, answeringHidden]);
  const boardRunIds =
    board.cards === null
      ? null
      : board.cards
          .map((card) => card.run.id)
          .sort()
          .join(',');
  useEffect(() => {
    if (boardRunIds !== null) {
      const onBoard = new Set(boardRunIds === '' ? [] : boardRunIds.split(','));
      cards.keepOnly(onBoard);
      nodePositions.keepOnly(onBoard);
      blockOrders.keepOnly(onBoard);
    }
  }, [
    boardRunIds,
    cards.keepOnly,
    nodePositions.keepOnly,
    blockOrders.keepOnly,
  ]);
  const boardBlockIds =
    board.cards === null
      ? null
      : [
          ...new Set(
            board.cards.map((card) =>
              blockIdOf({ projectId: card.run.project?.id ?? null }),
            ),
          ),
        ]
          .sort()
          .join(',');
  useEffect(() => {
    if (boardBlockIds !== null) {
      blockPlaces.keepOnly(
        new Set(boardBlockIds === '' ? [] : boardBlockIds.split(',')),
      );
    }
  }, [boardBlockIds, blockPlaces.keepOnly]);
  const resetLayout = useLatestCallback((): void => {
    nodePositions.reset();
    blockPlaces.reset();
    blockOrders.reset();
  }, []);
  const { projects } = useProjects(apis, client);
  const pullRequests = useThreadPullRequests(
    (board.cards ?? []).map((card) => card.run),
  );
  const now = useClock();
  const managerRunId = board.manager?.id ?? null;

  const shown = useMemo(
    () =>
      (board.cards ?? []).filter(
        (card) =>
          projectFilter === ALL_PROJECTS ||
          card.run.project?.id === projectFilter,
      ),
    [board.cards, projectFilter],
  );
  const projectColors = useMemo(
    () => projectColorsOf((board.cards ?? []).map((card) => card.run.project)),
    [board.cards],
  );
  const colorOfProject = useMemo(
    () => new Map(projectColors.map((project) => [project.id, project.color])),
    [projectColors],
  );
  const shownProjects = projectColors.filter((project) =>
    shown.some((card) => card.run.project?.id === project.id),
  );
  const viewOf = (card: CommandCenterCard) =>
    threadCardViewOf(
      card,
      rowPullRequestOf(card.run, pullRequests.byKey),
      identities,
      teamFaces,
      now,
      colorOfProject,
    );
  const builtIdentities = useMemo(
    () =>
      threadIdentitiesOf(
        board.cards ?? [],
        board.manager,
        (card) => rowPullRequestOf(card.run, pullRequests.byKey),
        identities,
        teamFaces,
        Date.now(),
        colorOfProject,
      ),
    [
      board.cards,
      board.manager,
      pullRequests.byKey,
      identities,
      teamFaces,
      colorOfProject,
    ],
  );
  const [heldIdentities, setHeldIdentities] = useState({
    built: builtIdentities,
    kept: builtIdentities,
  });
  if (heldIdentities.built !== builtIdentities) {
    setHeldIdentities({
      built: builtIdentities,
      kept: sameThreadIdentities(builtIdentities, heldIdentities.kept)
        ? heldIdentities.kept
        : builtIdentities,
    });
  }
  const threadIdentities = heldIdentities.kept;

  const bandOf = (card: CommandCenterCard): CardBand => {
    const view = viewOf(card);
    return { attention: view.attention, lastAt: view.lastAt };
  };
  const toggleCard = (runId: string): void => {
    const card = board.cards?.find((entry) => entry.run.id === runId);
    if (card !== undefined) {
      cardOpeners.current.delete(runId);
      cards.toggle(runId, bandOf(card));
      setFront('cards');
    }
  };
  const closeCard = useLatestCallback((runId: string): void => {
    cards.close(runId);
    const opener = cardOpeners.current.get(runId);
    cardOpeners.current.delete(runId);
    if (opener instanceof HTMLElement && opener.isConnected) {
      opener.focus({ preventScroll: true });
    }
  }, []);
  const openThread = (runId: string, fromWindow: boolean): void => {
    if (board.cards === null) {
      return;
    }
    if (runId === managerRunId) {
      setChatOpen(true);
      setFront('manager');
      return;
    }
    const card = board.cards.find((entry) => entry.run.id === runId);
    if (card === undefined) {
      setOffBoard(runId);
      return;
    }
    setOffBoard(null);
    if (narrow) {
      setSidebar(null);
      setChatOpen(false);
    }
    if (
      projectFilter !== ALL_PROJECTS &&
      card.run.project?.id !== projectFilter
    ) {
      setProjectFilter(card.run.project?.id ?? ALL_PROJECTS);
    }
    if (!cards.cards.some((open) => open.runId === runId)) {
      cardOpeners.current.set(runId, document.activeElement);
    }
    cards.open(runId, bandOf(card), fromWindow);
    if (!fromWindow) {
      setFront('cards');
    }
    setFocus((last) => ({ runId, seq: (last?.seq ?? 0) + 1 }));
  };
  const showThread = useLatestCallback(
    (runId: string): void => openThread(runId, false),
    [],
  );
  const showThreadFromWindow = useLatestCallback(
    (runId: string): void => openThread(runId, true),
    [],
  );
  const replyFrom = (
    runId: string,
    anchor: HTMLElement,
    title: string | null,
  ): void => {
    if (narrow) {
      showThread(runId);
      return;
    }
    const row = anchor.closest('li') ?? anchor;
    setAnswering((last) =>
      last?.anchor === row
        ? null
        : { runId, anchor: row, title, from: 'timeline' },
    );
  };
  const renderCardChat = useLatestCallback(
    (runId: string): React.ReactNode =>
      client === null ? null : (
        <ThreadCardChat
          runId={runId}
          apis={apis}
          handle={handle}
          client={client}
          active={active}
          onOpenThread={showThread}
          threadIdentities={threadIdentities}
        />
      ),
    [],
  );

  const archiveFlow = useArchiveThread({
    lessonsApi: apis.lessons,
    agentsApi: apis.agents,
    teamsApi: apis.teams,
    archive: async (target, lessons) => {
      await apis.chats.archiveChat({ runId: target.id, lessons });
      setOffBoard(null);
      setUndoError(null);
      setArchived({ runId: target.id, title: target.label });
      board.reload();
    },
  });
  const archiveOf = useMemo<ThreadArchiveOf>(() => {
    const byRun = new Map(
      (board.cards ?? []).map((card) => [card.run.id, card] as const),
    );
    return (runId) => {
      const card = byRun.get(runId);
      if (card === undefined) {
        return null;
      }
      return () =>
        archiveFlow.ask({
          id: runId,
          label:
            threadIdentities.get(runId)?.title ??
            card.run.title ??
            'Untitled thread',
          work: archiveWorkOf(card.run),
          isTeam: card.run.teamId !== null && card.run.teamId !== undefined,
        });
    };
  }, [board.cards, threadIdentities, archiveFlow.ask]);
  const undoArchive = useLatestCallback((runId: string): void => {
    void apis.chats
      .unarchiveChat({ runId })
      .then(() => {
        setArchived(null);
        board.reload();
      })
      .catch((err: unknown) => setUndoError(String(err)));
  }, []);

  const workingThreads = (board.cards ?? []).flatMap((card) => {
    if (card.column !== 'working' && card.column !== 'waiting') {
      return [];
    }
    const view = viewOf(card);
    return [
      {
        runId: card.run.id,
        identity:
          threadIdentities.get(card.run.id) ?? bareThreadIdentity(view.title),
        status:
          card.column === 'working'
            ? ('working' as const)
            : ('waiting' as const),
        lastMessage: view.lastMessage,
        lastAt: view.lastAt,
        background: {
          held: (card.run.holdingFor ?? 0) > 0,
          subagents: card.run.subagentsOut ?? 0,
          commands: card.run.shellsOpen ?? 0,
          monitors: card.run.monitorsOpen ?? 0,
        },
      },
    ];
  });

  const graphThreads = shown.map((card) => {
    const view = viewOf(card);
    const ask = askingByRun.get(card.run.id);
    return {
      id: card.run.id,
      projectId: card.run.project?.id ?? null,
      createdAt: card.run.createdAt,
      view: ask === undefined ? view : { ...view, lastMessage: askLineOf(ask) },
    };
  });
  const contacts = Object.fromEntries(
    shown.map((card) => [
      card.run.id,
      {
        lastAt: card.contact.lastAt ?? null,
        awaitingReply: card.contact.awaitingReply,
      },
    ]),
  );
  const pulses = board.pulses.map((pulse) => ({
    id: pulse.messageId,
    threadId:
      pulse.fromRunId === managerRunId ? pulse.toRunId : pulse.fromRunId,
    at: pulse.at,
    direction:
      pulse.fromRunId === managerRunId ? ('out' as const) : ('in' as const),
  }));
  const manager =
    board.manager === null
      ? null
      : {
          agentLabel: managerIdentityOf(board.manager, identities).agentLabel,
          model: board.manager.model ?? null,
          working: board.manager.status === 'running',
          lastActivityAt: board.manager.lastActivityAt ?? null,
        };

  const projectGroups = [
    {
      items: [
        { value: ALL_PROJECTS, label: 'All projects' },
        ...(projects ?? []).map((project) => ({
          value: project.id,
          label: project.name,
        })),
      ],
    },
  ];
  const needsCount = openRequests.requests.length;

  const graph = (
    <main
      data-slot="command-center-graph-pane"
      className="relative flex min-h-0 min-w-0 flex-1 flex-col bg-sidebar/40">
      {board.cards === null ? (
        <p className="p-6 text-sm text-muted-foreground">Loading threads…</p>
      ) : shown.length === 0 ? (
        <EmptyState className="m-auto">
          No active threads. Open the manager’s chat and ask it to start one.
        </EmptyState>
      ) : (
        <Suspense
          fallback={
            <p className="p-6 text-sm text-muted-foreground">Loading graph…</p>
          }>
          <GraphView
            className="min-h-0 flex-1"
            manager={manager}
            pendingStarts={board.pendingStarts}
            threads={graphThreads}
            contacts={contacts}
            pulses={pulses}
            now={now}
            narrow={narrow}
            active={active}
            onOpenInChats={onOpenThread}
            onToggleCard={toggleCard}
            openCards={cards.cards.map((card) => ({
              ...card,
              size: cards.sizeOf(card.runId),
            }))}
            onCloseCard={closeCard}
            onResizeCard={cards.resize}
            positions={nodePositions.offsets}
            onPlaceNode={nodePositions.place}
            onUnplaceNode={nodePositions.forget}
            blockPlaces={blockPlaces.places}
            onPlaceBlock={blockPlaces.place}
            blockOrders={blockOrders.orders}
            onOrderBlock={blockOrders.order}
            onResetLayout={resetLayout}
            renderCardChat={renderCardChat}
            cardsInFront={front === 'cards'}
            onActivateCards={() => setFront('cards')}
            focus={focus}
            onFocused={(seq) =>
              setFocus((last) => (last?.seq === seq ? null : last))
            }
            projects={shownProjects}
            asking={askingKinds}
            onAnswer={answerFrom}
            onViewportMove={() => setAnswering(null)}
          />
        </Suspense>
      )}
    </main>
  );

  const chatToggleHidden = narrow && (chatOpen || cards.cards.length > 0);

  return (
    <ThreadContextReaderContext.Provider value={contextReader}>
      <ThreadArchiveContext.Provider value={archiveOf}>
        <div className="relative flex h-full min-h-0 flex-col">
          <header className="flex items-center justify-between gap-2 border-b border-border px-4 py-2">
            <div className="flex min-w-0 items-center gap-2">
              <h1 className="truncate text-sm font-semibold max-sm:hidden">
                Command center
              </h1>
              <Select
                aria-label="Project"
                variant="ghost"
                side="bottom"
                groups={projectGroups}
                value={projectFilter}
                onValueChange={setProjectFilter}
              />
            </div>
            <div className="flex min-w-0 items-center justify-end gap-1">
              <Button
                type="button"
                variant={sidebar === 'needs' ? 'secondary' : 'ghost'}
                size="sm"
                className="h-7 gap-1.5 px-2 text-xs"
                data-slot="command-center-needs-toggle"
                aria-pressed={sidebar === 'needs'}
                title="Questions and approvals your threads wait on — answer them here"
                onClick={() => toggleSidebar('needs')}>
                <MessageCircleQuestion
                  aria-hidden="true"
                  className="size-3.5"
                />
                <span className="max-sm:sr-only">Needs you</span>
                {needsCount === 0 ? null : (
                  <Badge
                    variant="warning"
                    data-slot="command-center-needs-count"
                    className="px-1.5 py-0 tabular-nums">
                    {needsCount}
                  </Badge>
                )}
              </Button>
              <Button
                type="button"
                variant={sidebar === 'timeline' ? 'secondary' : 'ghost'}
                size="sm"
                className="h-7 gap-1.5 px-2 text-xs"
                data-slot="command-center-timeline-toggle"
                aria-pressed={sidebar === 'timeline'}
                title="Everything the manager and its threads did, newest first"
                onClick={() => toggleSidebar('timeline')}>
                <History aria-hidden="true" className="size-3.5" />
                <span className="max-sm:sr-only">Timeline</span>
              </Button>
            </div>
          </header>
          {board.error === null ? null : (
            <ErrorBanner
              message={board.error}
              onDismiss={board.reload}
              action={
                <Button
                  type="button"
                  size="sm"
                  variant="outline"
                  onClick={board.reload}>
                  Retry
                </Button>
              }
            />
          )}
          <div className="relative flex min-h-0 flex-1">
            <div
              {...{ [WORKING_THREADS_CEILING]: '' }}
              className="relative flex min-h-0 min-w-0 flex-1 flex-col">
              {graph}
              {chatToggleHidden ? null : (
                <Button
                  type="button"
                  size="icon"
                  data-slot="command-center-chat-toggle"
                  aria-label={
                    chatOpen
                      ? 'Close the manager’s chat'
                      : 'Open the manager’s chat'
                  }
                  aria-pressed={chatOpen}
                  title={chatOpen ? 'Close the chat' : 'Chat with the manager'}
                  className="absolute right-4 bottom-4 z-20 size-11 rounded-full shadow-panel-md"
                  onClick={() => {
                    setChatOpen((open) => !open);
                    setFront('manager');
                  }}>
                  <MessageSquare aria-hidden="true" className="size-5" />
                  {manager?.working === true ? (
                    <span
                      aria-hidden="true"
                      data-slot="command-center-chat-working"
                      className="absolute -top-0.5 -right-0.5 size-3 animate-pulse rounded-full bg-success ring-2 ring-background motion-reduce:animate-none"
                    />
                  ) : null}
                </Button>
              )}
              {chatToggleHidden || workingThreads.length === 0 ? null : (
                <div className="pointer-events-none absolute right-17 bottom-4 z-20 flex h-11 items-center">
                  <WorkingThreadsCard
                    threads={workingThreads}
                    onOpenThread={showThread}
                    onOpenHere={showThread}
                  />
                </div>
              )}
              <FloatingWindow
                slot="command-center-chat"
                label="Manager chat"
                title="Manager"
                open={chatOpen}
                phone={narrow}
                initialRect={managerWindowRect}
                onActivate={() => setFront('manager')}
                onClose={() => setChatOpen(false)}>
                {managerRunId === null ? (
                  managerChoice.choice === null ? null : (
                    <ManagerStart
                      apis={apis}
                      choice={managerChoice.choice}
                      onPick={managerChoice.pick}
                      cliDetections={sources.cliDetections}
                      capabilities={capabilities}
                      capabilitiesLoading={capabilitiesLoading}
                      approvalCapabilityFor={sources.approvalCapabilityFor}
                      recentConfigDirs={sources.recentConfigDirs}
                      configProfiles={sources.configProfiles}
                      onOpened={board.reload}
                    />
                  )
                ) : client === null || managerChoice.choice === null ? null : (
                  <ManagerDock
                    apis={apis}
                    handle={handle}
                    client={client}
                    choice={managerChoice.choice}
                    hidden={!chatOpen}
                    active={active}
                    threadIdentities={threadIdentities}
                    onOpenThread={showThreadFromWindow}
                    onTurnSettled={board.reload}
                    onDiscarded={board.reload}
                  />
                )}
              </FloatingWindow>
              {answering !== null && !answeringHidden ? (
                <AnswerPopover
                  anchor={answering.anchor}
                  title={
                    threadIdentities.get(answering.runId)?.title ??
                    answering.title ??
                    'Thread'
                  }
                  projectColor={
                    threadIdentities.get(answering.runId)?.projectColor ?? null
                  }
                  requests={answeringRequests}
                  error={openRequests.error}
                  onAnswer={openRequests.answer}
                  onShowThread={() => {
                    showThread(answering.runId);
                    setAnswering(null);
                  }}
                  onClose={() => setAnswering(null)}
                />
              ) : null}
            </div>
            {sidebar === null ? null : (
              <aside
                aria-label="Command center sidebar"
                data-slot="command-center-sidebar"
                className={cn(
                  'flex min-h-0 flex-col border-l border-border bg-card',
                  narrow ? 'absolute inset-0 z-30' : 'w-[400px] shrink-0',
                )}>
                <div className="flex h-11 shrink-0 items-center gap-2 border-b border-border px-4">
                  <h2 className="min-w-0 flex-1 truncate text-sm font-semibold">
                    {sidebar === 'needs'
                      ? needsCount === 0
                        ? 'Needs you'
                        : `Needs you · ${needsCount}`
                      : 'Timeline'}
                  </h2>
                  <Button
                    type="button"
                    variant="ghost"
                    size="icon"
                    className="size-7"
                    aria-label="Close the sidebar"
                    title="Close"
                    onClick={() => setSidebar(null)}>
                    <X aria-hidden="true" className="size-4" />
                  </Button>
                </div>
                {sidebar === 'needs' ? (
                  <NeedsYouPanel
                    requests={openRequests.requests}
                    error={openRequests.error}
                    focusRunId={null}
                    onAnswer={openRequests.answer}
                    onOpenThread={showThread}
                  />
                ) : (
                  <TimelinePanel
                    events={timeline.events}
                    loading={timeline.loading}
                    error={timeline.error}
                    hasMore={timeline.hasMore}
                    onLoadOlder={timeline.loadOlder}
                    onShowThread={showThread}
                    onReply={replyFrom}
                    openItemIds={openItemIds}
                    now={now}
                  />
                )}
              </aside>
            )}
          </div>
          {offBoard === null ? null : (
            <ActionNotice
              key={offBoard}
              className="absolute bottom-4 left-1/2 z-40 w-[min(34rem,calc(100%-2rem))] -translate-x-1/2"
              icon={<Archive className="size-4" />}
              title="This thread is no longer on the board"
              detail="It was archived or removed; Chats still has it."
              action={{
                label: 'Open in Chats',
                onAction: () => {
                  setOffBoard(null);
                  onOpenThread(offBoard);
                },
              }}
              onDismiss={() => setOffBoard(null)}
            />
          )}
          {archived === null ? null : (
            <ActionNotice
              key={archived.runId}
              className="absolute bottom-4 left-1/2 z-40 w-[min(34rem,calc(100%-2rem))] -translate-x-1/2"
              icon={<Archive className="size-4" />}
              title={`Archived ${archived.title}`}
              detail={
                undoError ??
                'It left the board; Undo puts it back where it was.'
              }
              action={{
                label: 'Undo',
                onAction: () => undoArchive(archived.runId),
              }}
              onDismiss={() => {
                setArchived(null);
                setUndoError(null);
              }}
            />
          )}
          {archiveFlow.dialog}
        </div>
      </ThreadArchiveContext.Provider>
    </ThreadContextReaderContext.Provider>
  );
}
