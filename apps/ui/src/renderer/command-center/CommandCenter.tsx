import { MessageSquare, Network } from 'lucide-react';
import {
  lazy,
  Suspense,
  useContext,
  useEffect,
  useMemo,
  useState,
} from 'react';

import type { DaemonHandle } from '../../shared/contracts';
import { CLI_KINDS } from '../../shared/contracts';
import { AgentIdentityContext, agentShortName } from '../agent-identity';
import type { AgentKind, CommandCenterCard } from '../autogenerated';
import {
  rowPullRequestOf,
  useThreadPullRequests,
} from '../chats/use-thread-pull-requests';
import { EmptyState } from '../components/empty-state';
import { ErrorBanner } from '../components/error-banner';
import { Button } from '../components/ui/button';
import { Select } from '../components/ui/select';
import { useNarrowViewport } from '../components/use-narrow-viewport';
import { createDaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { useProjects } from '../projects/use-projects';
import { threadCardViewOf } from './card-view';
import { ManagerDock } from './manager-dock';
import { useCommandCenterBoard } from './use-command-center-board';

const GraphView = lazy(() =>
  import('./graph-view').then((m) => ({ default: m.GraphView })),
);

const ALL_PROJECTS = '__all__';

/** How often the idle marks and the graph's lit edges move on. */
const CLOCK_TICK_MS = 30_000;

type CommandCenterView = 'chat' | 'graph';

function useClock(): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    const timer = setInterval(() => setNow(Date.now()), CLOCK_TICK_MS);
    return () => clearInterval(timer);
  }, []);
  return now;
}

/**
 * The command center: the manager's chat across the whole page, and — one
 * press in the header away — the live graph with the manager on top and every
 * active thread under it as a card. The daemon folds everything; this page
 * only draws it and asks again when a card moves.
 */
export function CommandCenter({
  handle,
  client,
  onOpenThread,
}: {
  handle: DaemonHandle;
  client: DaemonClient | null;
  onOpenThread: (runId: string) => void;
}): React.JSX.Element {
  const apis = useMemo(() => createDaemonApis(handle), [handle]);
  const identities = useContext(AgentIdentityContext);
  const narrow = useNarrowViewport();
  const [view, setView] = useState<CommandCenterView>('chat');
  const [projectFilter, setProjectFilter] = useState(ALL_PROJECTS);
  const [managerAgent, setManagerAgent] = useState<AgentKind>(
    () => (identities[0]?.agent ?? CLI_KINDS[0]!) as AgentKind,
  );
  const board = useCommandCenterBoard(apis, client);
  const { projects } = useProjects(apis, client);
  const pullRequests = useThreadPullRequests(
    (board.cards ?? []).map((card) => card.run),
  );
  const now = useClock();
  const managerRunId = board.manager?.id ?? null;

  const shown = useMemo(
    () =>
      (board.cards ?? []).filter(
        (card) =>
          projectFilter === ALL_PROJECTS ||
          card.run.project?.id === projectFilter,
      ),
    [board.cards, projectFilter],
  );
  const viewOf = (card: CommandCenterCard) =>
    threadCardViewOf(
      card,
      rowPullRequestOf(card.run, pullRequests.byKey),
      identities,
      now,
    );

  const graphThreads = shown.map((card) => ({
    id: card.run.id,
    createdAt: card.run.createdAt,
    view: viewOf(card),
  }));
  const contacts = Object.fromEntries(
    shown.map((card) => [
      card.run.id,
      {
        lastAt: card.contact.lastAt ?? null,
        awaitingReply: card.contact.awaitingReply,
      },
    ]),
  );
  const pulses = board.pulses.map((pulse) => ({
    id: pulse.messageId,
    threadId:
      pulse.fromRunId === managerRunId ? pulse.toRunId : pulse.fromRunId,
    at: pulse.at,
    direction:
      pulse.fromRunId === managerRunId ? ('out' as const) : ('in' as const),
  }));
  const manager =
    board.manager === null
      ? null
      : {
          agentLabel:
            board.manager.agentKind == null
              ? null
              : agentShortName(identities, board.manager.agentKind),
          model: board.manager.model ?? null,
          working: board.manager.status === 'running',
          lastActivityAt: board.manager.lastActivityAt ?? null,
        };

  const projectGroups = [
    {
      items: [
        { value: ALL_PROJECTS, label: 'All projects' },
        ...(projects ?? []).map((project) => ({
          value: project.id,
          label: project.name,
        })),
      ],
    },
  ];
  const graphShown = view === 'graph';

  return (
    <div className="flex h-full min-h-0 flex-col">
      <header className="flex items-center gap-2 border-b border-border px-4 py-2">
        <h1 className="mr-2 truncate text-sm font-semibold">
          {graphShown ? 'Threads' : 'Manager'}
        </h1>
        {graphShown ? (
          <Select
            aria-label="Project"
            variant="ghost"
            side="bottom"
            groups={projectGroups}
            value={projectFilter}
            onValueChange={setProjectFilter}
          />
        ) : null}
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className="ml-auto size-8"
          data-slot="command-center-view-toggle"
          aria-pressed={graphShown}
          aria-label={graphShown ? 'Show the manager chat' : 'Show the graph'}
          title={graphShown ? 'Show the manager chat' : 'Show the graph'}
          onClick={() => setView(graphShown ? 'chat' : 'graph')}>
          {graphShown ? (
            <MessageSquare aria-hidden="true" />
          ) : (
            <Network aria-hidden="true" />
          )}
        </Button>
      </header>
      {board.error === null ? null : (
        <ErrorBanner
          message={board.error}
          onDismiss={board.reload}
          action={
            <Button
              type="button"
              size="sm"
              variant="outline"
              onClick={board.reload}>
              Retry
            </Button>
          }
        />
      )}
      {graphShown ? (
        <main className="flex min-h-0 flex-1 flex-col bg-sidebar/40">
          {board.cards === null ? (
            <p className="p-6 text-sm text-muted-foreground">
              Loading threads…
            </p>
          ) : shown.length === 0 ? (
            <EmptyState className="m-auto">
              No active threads. Ask the manager to start one.
            </EmptyState>
          ) : (
            <Suspense
              fallback={
                <p className="p-6 text-sm text-muted-foreground">
                  Loading graph…
                </p>
              }>
              <GraphView
                className="min-h-[18rem] flex-1"
                manager={manager}
                pendingStarts={board.pendingStarts}
                threads={graphThreads}
                contacts={contacts}
                pulses={pulses}
                now={now}
                narrow={narrow}
                onOpen={onOpenThread}
                onManager={() => setView('chat')}
              />
            </Suspense>
          )}
        </main>
      ) : null}
      {!graphShown && managerRunId === null ? (
        <section
          aria-label="Open the manager"
          className="m-auto flex max-w-md flex-col items-center gap-3 p-6 text-center text-sm">
          <p className="text-muted-foreground">
            The manager watches and messages every thread for you, and starts
            new ones when you ask. Run it on
          </p>
          <div className="flex items-center gap-2">
            <Select
              aria-label="Manager agent"
              variant="ghost"
              side="bottom"
              groups={[
                {
                  items: identities.map((identity) => ({
                    value: identity.agent,
                    label: identity.displayName,
                  })),
                },
              ]}
              value={managerAgent}
              onValueChange={(value) => setManagerAgent(value as AgentKind)}
            />
            <Button
              type="button"
              size="sm"
              onClick={() => {
                void apis.commandCenter
                  .openCommandCenterChat({
                    startCommandCenterChatDto: { agentKind: managerAgent },
                  })
                  .then(board.reload);
              }}>
              Open the manager
            </Button>
          </div>
        </section>
      ) : null}
      {managerRunId !== null && client !== null ? (
        <ManagerDock
          apis={apis}
          handle={handle}
          client={client}
          agentKind={managerAgent}
          hidden={graphShown}
          onTurnSettled={board.reload}
        />
      ) : null}
    </div>
  );
}
