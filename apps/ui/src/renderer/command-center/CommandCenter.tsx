const GraphView = lazy(() =>
  import('./graph-view').then((m) => ({ default: m.GraphView })),
);

const ALL_PROJECTS = '__all__';

/** How often the idle marks and the graph's lit edges move on. */
const CLOCK_TICK_MS = 30_000;

export type CommandCenterView = 'chat' | 'both' | 'graph';

const VIEW_KEY = 'commandCenter.view';

type SidebarTab = 'needs' | 'timeline';

/** The room the chat keeps under the graph in the split: its header, a few lines and the composer. */
const CHAT_MIN_HEIGHT = 320;
const PAGE_CHROME_HEIGHT = 96;

/** The tallest the graph may grow in the split, so the chat's composer never leaves the window. */
function maxGraphHeight(): number {
  return typeof window === 'undefined'
    ? 1600
    : Math.max(240, window.innerHeight - PAGE_CHROME_HEIGHT - CHAT_MIN_HEIGHT);
}

/** The graph's height in the split before the viewer drags it: about half of the page under the header. */
function defaultGraphHeight(): number {
  return typeof window === 'undefined'
    ? 420
    : Math.max(240, Math.round((window.innerHeight - PAGE_CHROME_HEIGHT) / 2));
}
const VIEWS: readonly CommandCenterView[] = ['chat', 'both', 'graph'];

/** The view the viewer last picked, or the split when they never did. */
export function readStoredView(): CommandCenterView {
  try {
    const stored = localStorage.getItem(VIEW_KEY);
    return VIEWS.find((view) => view === stored) ?? 'both';
  } catch {
    return 'both';
  }
}

function storeView(view: CommandCenterView): void {
  try {
    localStorage.setItem(VIEW_KEY, view);
  } catch {
    return;
  }
}

const VIEW_OPTIONS = [
  {
    id: 'chat' as const,
    label: 'Chat',
    icon: <MessageSquare aria-hidden="true" />,
  },
  { id: 'both' as const, label: 'Both', icon: <Rows2 aria-hidden="true" /> },
  {
    id: 'graph' as const,
    label: 'Graph',
    icon: <Network aria-hidden="true" />,
  },
];

function useClock(): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    const timer = setInterval(() => setNow(Date.now()), CLOCK_TICK_MS);
    return () => clearInterval(timer);
  }, []);
  return now;
}

/**
 * The command center: the manager's chat across the whole page, and — one
 * press in the header away — the live graph with the manager on top and every
 * active thread under it as a card. The daemon folds everything; this page
 * only draws it and asks again when a card moves.
 */
export function CommandCenter({
  handle,
  client,
  active,
  onOpenThread,
}: {
  handle: DaemonHandle;
  client: DaemonClient | null;
  /**
   * Whether the page is on screen: the board and the timeline read nothing
   * while it is not.
   */
  active: boolean;
  onOpenThread: (runId: string) => void;
}): React.JSX.Element {
  const apis = useMemo(() => createDaemonApis(handle), [handle]);
  const identities = useContext(AgentIdentityContext);
  const narrow = useNarrowViewport();
  const [storedView, setStoredView] = useState(readStoredView);
  const view: CommandCenterView =
    narrow && storedView === 'both' ? 'chat' : storedView;
  const pickView = (next: CommandCenterView): void => {
    setStoredView(next);
    storeView(next);
  };
  const graphHeight = usePanelWidth({
    storageKey: 'commandCenter.graphHeight',
    defaultWidth: defaultGraphHeight(),
    minWidth: 200,
    maxWidth: maxGraphHeight(),
    handleEdge: 'bottom',
  });
  const [teamFaces, setTeamFaces] = useState<ReadonlyMap<string, TeamFace>>(
    () => new Map(),
  );
  const [projectFilter, setProjectFilter] = useState(ALL_PROJECTS);
  const sources = useRunConfigSources(apis);
  const { capabilities, loading: capabilitiesLoading } = useSharedCapabilities(
    apis.capabilities,
  );
  const managerChoice = useManagerChoice(sources.cliDetections);
  const board = useCommandCenterBoard(apis, client, active);
  const unknownTeams = [
    ...new Set(
      (board.cards ?? []).flatMap((card) =>
        card.run.teamId != null && !teamFaces.has(card.run.teamId)
          ? [card.run.teamId]
          : [],
      ),
    ),
  ]
    .sort()
    .join(',');
  useEffect(() => {
    let live = true;
    void apis.teams
      .listTeams()
      .then((teams) => {
        if (live) {
          setTeamFaces(teamFacesOf(teams));
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, [apis, unknownTeams]);
  const [sidebar, setSidebar] = useState<SidebarTab | null>(null);
  const windows = useThreadWindows(narrow);
  const [measureWindowArea, windowArea] = useElementSize();
  const timeline = useCommandCenterTimeline(
    apis,
    client,
    sidebar === 'timeline' && active,
  );
  const asking = useMemo(
    () =>
      (board.cards ?? []).flatMap((card): AskingThread[] =>
        card.run.awaiting == null
          ? []
          : [
              {
                runId: card.run.id,
                title: card.run.title ?? 'Untitled thread',
                isTeam: card.run.teamId != null,
                awaiting: card.run.awaiting,
                lastActivityAt: card.run.lastActivityAt ?? card.run.createdAt,
              },
            ],
      ),
    [board.cards],
  );
  const openRequests = useOpenRequests(apis, client, asking);
  const askingByRun = useMemo(() => {
    const byRun = new Map<string, OpenRequest>();
    for (const request of openRequests.requests) {
      if (!byRun.has(request.runId)) {
        byRun.set(request.runId, request);
      }
    }
    return byRun;
  }, [openRequests.requests]);
  const askingKinds = useMemo(
    () =>
      new Map(
        [...askingByRun].map(([runId, request]) => [runId, askKindOf(request)]),
      ),
    [askingByRun],
  );
  const toggleSidebar = (tab: SidebarTab): void =>
    setSidebar((open) => (open === tab ? null : tab));
  const [answering, setAnswering] = useState<{
    runId: string;
    anchor: HTMLElement;
  } | null>(null);
  const answerFrom = (runId: string, anchor: HTMLElement): void =>
    setAnswering({ runId, anchor });
  const openHere = (runId: string): void => windows.open(runId, windowArea);
  const answeringRequests =
    answering === null
      ? []
      : openRequests.requests.filter(
          (request) => request.runId === answering.runId,
        );
  const answeredAll = answering !== null && answeringRequests.length === 0;
  useEffect(() => {
    if (answeredAll) {
      setAnswering(null);
    }
  }, [answeredAll]);
  const boardRunIds =
    board.cards === null
      ? null
      : board.cards
          .map((card) => card.run.id)
          .sort()
          .join(',');
  useEffect(() => {
    if (boardRunIds !== null) {
      windows.keepOnly(
        new Set(boardRunIds === '' ? [] : boardRunIds.split(',')),
      );
    }
  }, [boardRunIds, windows.keepOnly]);
  const { projects } = useProjects(apis, client);
  const pullRequests = useThreadPullRequests(
    (board.cards ?? []).map((card) => card.run),
  );
  const now = useClock();
  const managerRunId = board.manager?.id ?? null;

  const shown = useMemo(
    () =>
      (board.cards ?? []).filter(
        (card) =>
          projectFilter === ALL_PROJECTS ||
          card.run.project?.id === projectFilter,
      ),
    [board.cards, projectFilter],
  );
  const projectColors = useMemo(
    () => projectColorsOf((board.cards ?? []).map((card) => card.run.project)),
    [board.cards],
  );
  const colorOfProject = useMemo(
    () => new Map(projectColors.map((project) => [project.id, project.color])),
    [projectColors],
  );
  const shownProjects = projectColors.filter((project) =>
    shown.some((card) => card.run.project?.id === project.id),
  );
  const viewOf = (card: CommandCenterCard) =>
    threadCardViewOf(
      card,
      rowPullRequestOf(card.run, pullRequests.byKey),
      identities,
      teamFaces,
      now,
      colorOfProject,
    );
  const threadIdentities = useMemo(
    () =>
      threadIdentitiesOf(
        board.cards ?? [],
        board.manager,
        (card) => rowPullRequestOf(card.run, pullRequests.byKey),
        identities,
        teamFaces,
        Date.now(),
        colorOfProject,
      ),
    [
      board.cards,
      board.manager,
      pullRequests.byKey,
      identities,
      teamFaces,
      colorOfProject,
    ],
  );

  const workingThreads = (board.cards ?? []).flatMap((card) => {
    if (card.column !== 'working' && card.column !== 'waiting') {
      return [];
    }
    const view = viewOf(card);
    return [
      {
        runId: card.run.id,
        title: view.title,
        agentLabel: view.agentLabel,
        agentKind: card.run.agentKind ?? null,
        crew: view.crew,
        project: view.project,
        projectColor: view.projectColor ?? null,
        lastMessage: view.lastMessage,
        status:
          card.column === 'working'
            ? ('working' as const)
            : ('waiting' as const),
      },
    ];
  });

  const graphThreads = shown.map((card) => {
    const view = viewOf(card);
    const ask = askingByRun.get(card.run.id);
    return {
      id: card.run.id,
      createdAt: card.run.createdAt,
      view: ask === undefined ? view : { ...view, lastMessage: askLineOf(ask) },
    };
  });
  const contacts = Object.fromEntries(
    shown.map((card) => [
      card.run.id,
      {
        lastAt: card.contact.lastAt ?? null,
        awaitingReply: card.contact.awaitingReply,
      },
    ]),
  );
  const pulses = board.pulses.map((pulse) => ({
    id: pulse.messageId,
    threadId:
      pulse.fromRunId === managerRunId ? pulse.toRunId : pulse.fromRunId,
    at: pulse.at,
    direction:
      pulse.fromRunId === managerRunId ? ('out' as const) : ('in' as const),
  }));
  const manager =
    board.manager === null
      ? null
      : {
          agentLabel: managerIdentityOf(board.manager, identities).agentLabel,
          model: board.manager.model ?? null,
          working: board.manager.status === 'running',
          lastActivityAt: board.manager.lastActivityAt ?? null,
        };

  const projectGroups = [
    {
      items: [
        { value: ALL_PROJECTS, label: 'All projects' },
        ...(projects ?? []).map((project) => ({
          value: project.id,
          label: project.name,
        })),
      ],
    },
  ];
  const graphShown = view !== 'chat';
  const chatShown = view !== 'graph';
  const split = view === 'both';
  const needsCount = openRequests.requests.length;

  const graph = (
    <main
      data-slot="command-center-graph-pane"
      className={cn(
        'relative flex min-h-0 min-w-0 flex-col bg-sidebar/40',
        split ? 'shrink-0 border-b border-border' : 'flex-1',
      )}
      style={split ? { height: graphHeight.width } : undefined}>
      {board.cards === null ? (
        <p className="p-6 text-sm text-muted-foreground">Loading threads…</p>
      ) : shown.length === 0 ? (
        <EmptyState className="m-auto">
          No active threads. Ask the manager to start one.
        </EmptyState>
      ) : (
        <Suspense
          fallback={
            <p className="p-6 text-sm text-muted-foreground">Loading graph…</p>
          }>
          <GraphView
            className="min-h-0 flex-1"
            manager={manager}
            pendingStarts={board.pendingStarts}
            threads={graphThreads}
            contacts={contacts}
            pulses={pulses}
            now={now}
            narrow={narrow}
            onOpen={onOpenThread}
            onOpenHere={openHere}
            projects={shownProjects}
            asking={askingKinds}
            onAnswer={answerFrom}
            onViewportMove={() => setAnswering(null)}
          />
        </Suspense>
      )}
      {split ? (
        <PanelResizeHandle
          edge="bottom"
          label="Resize the graph"
          onMouseDown={graphHeight.startResize}
          value={graphHeight.width}
          min={graphHeight.minWidth}
          max={graphHeight.maxWidth}
          onResize={graphHeight.resizeTo}
        />
      ) : null}
    </main>
  );

  return (
    <div className="flex h-full min-h-0 flex-col">
      <header className="grid grid-cols-[1fr_auto_1fr] items-center gap-2 border-b border-border px-4 py-2">
        <div className="flex min-w-0 items-center gap-2">
          <h1 className="truncate text-sm font-semibold max-sm:hidden">
            Command center
          </h1>
          {graphShown ? (
            <Select
              aria-label="Project"
              variant="ghost"
              side="bottom"
              groups={projectGroups}
              value={projectFilter}
              onValueChange={setProjectFilter}
            />
          ) : null}
        </div>
        <SegmentedControl
          ariaLabel="View"
          size="sm"
          options={
            narrow
              ? VIEW_OPTIONS.filter((option) => option.id !== 'both')
              : VIEW_OPTIONS
          }
          value={view}
          onSelect={pickView}
        />
        <div className="flex min-w-0 items-center justify-end gap-1">
          <Button
            type="button"
            variant={sidebar === 'needs' ? 'secondary' : 'ghost'}
            size="sm"
            className="h-7 gap-1.5 px-2 text-xs"
            data-slot="command-center-needs-toggle"
            aria-pressed={sidebar === 'needs'}
            title="Questions and approvals your threads wait on — answer them here"
            onClick={() => toggleSidebar('needs')}>
            <MessageCircleQuestion aria-hidden="true" className="size-3.5" />
            <span className="max-sm:sr-only">Needs you</span>
            {needsCount === 0 ? null : (
              <Badge
                variant="warning"
                data-slot="command-center-needs-count"
                className="px-1.5 py-0 tabular-nums">
                {needsCount}
              </Badge>
            )}
          </Button>
          <Button
            type="button"
            variant={sidebar === 'timeline' ? 'secondary' : 'ghost'}
            size="sm"
            className="h-7 gap-1.5 px-2 text-xs"
            data-slot="command-center-timeline-toggle"
            aria-pressed={sidebar === 'timeline'}
            title="Everything the manager and its threads did, newest first"
            onClick={() => toggleSidebar('timeline')}>
            <History aria-hidden="true" className="size-3.5" />
            <span className="max-sm:sr-only">Timeline</span>
          </Button>
        </div>
      </header>
      {board.error === null ? null : (
        <ErrorBanner
          message={board.error}
          onDismiss={board.reload}
          action={
            <Button
              type="button"
              size="sm"
              variant="outline"
              onClick={board.reload}>
              Retry
            </Button>
          }
        />
      )}
      <div className="relative flex min-h-0 flex-1">
        <div
          ref={measureWindowArea}
          className="relative flex min-h-0 min-w-0 flex-1 flex-col">
          {graphShown ? graph : null}
          <div
            hidden={!chatShown}
            data-slot="command-center-chat"
            className={cn(
              'relative min-h-0 min-w-0 flex-1 flex-col',
              chatShown && 'flex',
            )}>
            {managerRunId === null ? (
              managerChoice.choice === null ? null : (
                <ManagerStart
                  apis={apis}
                  choice={managerChoice.choice}
                  onPick={managerChoice.pick}
                  cliDetections={sources.cliDetections}
                  capabilities={capabilities}
                  capabilitiesLoading={capabilitiesLoading}
                  approvalCapabilityFor={sources.approvalCapabilityFor}
                  recentConfigDirs={sources.recentConfigDirs}
                  configProfiles={sources.configProfiles}
                  onOpened={board.reload}
                />
              )
            ) : client === null || managerChoice.choice === null ? null : (
              <ManagerDock
                apis={apis}
                handle={handle}
                client={client}
                choice={managerChoice.choice}
                hidden={!chatShown}
                active={active}
                workingThreads={workingThreads}
                threadIdentities={threadIdentities}
                onOpenThread={onOpenThread}
                onTurnSettled={board.reload}
                onDiscarded={board.reload}
              />
            )}
          </div>
          {graphShown && client !== null ? (
            <ThreadWindowsLayer
              windows={windows}
              bounds={windowArea}
              narrow={narrow}
              subjects={threadIdentities}
              onOpenThread={onOpenThread}
              apis={apis}
              handle={handle}
              client={client}
              active={active}
            />
          ) : null}
          {graphShown && answering !== null ? (
            <AnswerPopover
              anchor={answering.anchor}
              title={threadIdentities.get(answering.runId)?.title ?? 'Thread'}
              projectColor={
                threadIdentities.get(answering.runId)?.projectColor ?? null
              }
              requests={answeringRequests}
              error={openRequests.error}
              onAnswer={openRequests.answer}
              onOpenHere={() => {
                openHere(answering.runId);
                setAnswering(null);
              }}
              onOpenThread={() => onOpenThread(answering.runId)}
              onClose={() => setAnswering(null)}
            />
          ) : null}
        </div>
        {sidebar === null ? null : (
          <aside
            aria-label="Command center sidebar"
            data-slot="command-center-sidebar"
            className={cn(
              'flex min-h-0 flex-col border-l border-border bg-card',
              narrow ? 'absolute inset-0 z-30' : 'w-[400px] shrink-0',
            )}>
            <div className="flex h-11 shrink-0 items-center gap-2 border-b border-border px-4">
              <h2 className="min-w-0 flex-1 truncate text-sm font-semibold">
                {sidebar === 'needs'
                  ? needsCount === 0
                    ? 'Needs you'
                    : `Needs you · ${needsCount}`
                  : 'Timeline'}
              </h2>
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-7"
                aria-label="Close the sidebar"
                title="Close"
                onClick={() => setSidebar(null)}>
                <X aria-hidden="true" className="size-4" />
              </Button>
            </div>
            {sidebar === 'needs' ? (
              <NeedsYouPanel
                requests={openRequests.requests}
                error={openRequests.error}
                focusRunId={null}
                onAnswer={openRequests.answer}
                onOpenThread={onOpenThread}
              />
            ) : (
              <TimelinePanel
                events={timeline.events}
                loading={timeline.loading}
                error={timeline.error}
                hasMore={timeline.hasMore}
                onLoadOlder={timeline.loadOlder}
                onOpenThread={onOpenThread}
                now={now}
              />
            )}
          </aside>
        )}
      </div>
    </div>
  );
}
