import {
  lazy,
  Suspense,
  useContext,
  useEffect,
  useMemo,
  useState,
} from 'react';

import type { DaemonHandle } from '../../shared/contracts';
import { CLI_KINDS } from '../../shared/contracts';
import { AgentIdentityContext } from '../agent-identity';
import type {
  AgentKind,
  CommandCenterCard,
  CommandCenterWindow,
} from '../autogenerated';
import {
  rowPullRequestOf,
  useThreadPullRequests,
} from '../chats/use-thread-pull-requests';
import { EmptyState } from '../components/empty-state';
import { ErrorBanner } from '../components/error-banner';
import { Button } from '../components/ui/button';
import { SegmentedControl } from '../components/ui/segmented-control';
import { Select } from '../components/ui/select';
import { useNarrowViewport } from '../components/use-narrow-viewport';
import { createDaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { useProjects } from '../projects/use-projects';
import { threadCardViewOf } from './card-view';
import { ManagerDock } from './manager-dock';
import { NewThreadDialog } from './new-thread-dialog';
import { useCommandCenterBoard } from './use-command-center-board';

const GraphView = lazy(() =>
  import('./graph-view').then((m) => ({ default: m.GraphView })),
);

const ALL_PROJECTS = '__all__';

/** How often the strips' right edge and the graph's lit edges move on. */
const CLOCK_TICK_MS = 30_000;

function useClock(): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    const timer = setInterval(() => setNow(Date.now()), CLOCK_TICK_MS);
    return () => clearInterval(timer);
  }, []);
  return now;
}

/**
 * The command center: one live graph with the manager on top and every active
 * thread hanging under it as a card, each thread's board card folded beneath
 * it — with the manager docked underneath. The daemon folds everything; this
 * page only draws it and asks again when a card moves.
 */
export function CommandCenter({
  handle,
  client,
  onOpenThread,
}: {
  handle: DaemonHandle;
  client: DaemonClient | null;
  onOpenThread: (runId: string) => void;
}): React.JSX.Element {
  const apis = useMemo(() => createDaemonApis(handle), [handle]);
  const identities = useContext(AgentIdentityContext);
  const narrow = useNarrowViewport();
  const [window, setWindow] = useState<CommandCenterWindow>('24h');
  const [projectFilter, setProjectFilter] = useState(ALL_PROJECTS);
  const [newThreadOpen, setNewThreadOpen] = useState(false);
  const [managerShown, setManagerShown] = useState(!narrow);
  const [managerAgent, setManagerAgent] = useState<AgentKind>(
    () => (identities[0]?.agent ?? CLI_KINDS[0]!) as AgentKind,
  );
  const board = useCommandCenterBoard(apis, client, window);
  const { projects } = useProjects(apis, client);
  const pullRequests = useThreadPullRequests(
    (board.cards ?? []).map((card) => card.run),
  );
  const now = useClock();

  const shown = useMemo(
    () =>
      (board.cards ?? []).filter(
        (card) =>
          projectFilter === ALL_PROJECTS ||
          card.run.project?.id === projectFilter,
      ),
    [board.cards, projectFilter],
  );
  const stripEnd = new Date(now).toISOString();
  const stripStart =
    board.stripStart ?? new Date(now - 8 * 60 * 60_000).toISOString();
  const viewOf = (card: CommandCenterCard) =>
    threadCardViewOf(
      card,
      rowPullRequestOf(card.run, pullRequests.byKey),
      identities,
      { start: stripStart, end: stripEnd },
    );

  const graphThreads = shown.map((card) => ({
    id: card.run.id,
    createdAt: card.run.createdAt,
    view: viewOf(card),
  }));
  const contacts = Object.fromEntries(
    shown.map((card) => [
      card.run.id,
      {
        lastAt: card.contact.lastAt ?? null,
        awaitingReply: card.contact.awaitingReply,
      },
    ]),
  );
  const pulses = board.pulses.flatMap((pulse) => {
    const threadId =
      pulse.fromRunId === board.managerRunId ? pulse.toRunId : pulse.fromRunId;
    return [
      {
        id: pulse.messageId,
        threadId,
        at: pulse.at,
        direction:
          pulse.fromRunId === board.managerRunId
            ? ('out' as const)
            : ('in' as const),
      },
    ];
  });

  const projectGroups = [
    {
      items: [
        { value: ALL_PROJECTS, label: 'All projects' },
        ...(projects ?? []).map((project) => ({
          value: project.id,
          label: project.name,
        })),
      ],
    },
  ];

  return (
    <div className="flex h-full min-h-0 flex-col">
      <header className="flex flex-wrap items-center gap-2 border-b border-border px-4 py-2">
        <h1 className="mr-2 text-sm font-semibold">Command center</h1>
        <Select
          aria-label="Project"
          variant="ghost"
          groups={projectGroups}
          value={projectFilter}
          onValueChange={setProjectFilter}
        />
        <SegmentedControl
          ariaLabel="Active within"
          size="sm"
          options={[
            { id: '24h', label: '24 h' },
            { id: '7d', label: '7 days' },
          ]}
          value={window}
          onSelect={setWindow}
        />
        <div className="ml-auto flex items-center gap-2">
          <Button
            type="button"
            variant="outline"
            size="sm"
            aria-pressed={managerShown}
            onClick={() => setManagerShown((was) => !was)}>
            Manager
          </Button>
          <Button
            type="button"
            size="sm"
            disabled={(projects ?? []).length === 0}
            title={
              (projects ?? []).length === 0
                ? 'A thread starts in a project — add one first'
                : undefined
            }
            onClick={() => setNewThreadOpen(true)}>
            New thread
          </Button>
        </div>
      </header>
      {board.error === null ? null : (
        <ErrorBanner
          message={board.error}
          onDismiss={board.reload}
          action={
            <Button
              type="button"
              size="sm"
              variant="outline"
              onClick={board.reload}>
              Retry
            </Button>
          }
        />
      )}
      <main className="flex min-h-0 flex-1 flex-col bg-sidebar/40">
        {board.cards === null ? (
          <p className="p-6 text-sm text-muted-foreground">Loading threads…</p>
        ) : shown.length === 0 ? (
          <EmptyState className="m-auto">
            No active threads
            {window === '24h' ? ' in the last 24 hours' : ' in the last 7 days'}
            . Start one with New thread, or ask the manager.
          </EmptyState>
        ) : (
          <Suspense
            fallback={
              <p className="p-6 text-sm text-muted-foreground">
                Loading graph…
              </p>
            }>
            <GraphView
              className="min-h-[18rem] flex-1"
              managerStarted={board.managerRunId !== null}
              threads={graphThreads}
              contacts={contacts}
              pulses={pulses}
              now={now}
              narrow={narrow}
              onOpen={onOpenThread}
              onManager={() => setManagerShown((was) => !was)}
            />
          </Suspense>
        )}
      </main>
      {board.managerRunId === null && managerShown ? (
        <aside
          aria-label="Open the manager"
          className="flex flex-wrap items-center gap-2 border-t border-border bg-sidebar px-4 py-3 text-sm">
          <span className="text-muted-foreground">
            The manager watches and messages every thread for you. Run it on
          </span>
          <Select
            aria-label="Manager agent"
            variant="ghost"
            groups={[
              {
                items: identities.map((identity) => ({
                  value: identity.agent,
                  label: identity.displayName,
                })),
              },
            ]}
            value={managerAgent}
            onValueChange={(value) => setManagerAgent(value as AgentKind)}
          />
          <Button
            type="button"
            size="sm"
            onClick={() => {
              void apis.commandCenter
                .openCommandCenterChat({
                  startCommandCenterChatDto: { agentKind: managerAgent },
                })
                .then(board.reload);
            }}>
            Open the manager
          </Button>
        </aside>
      ) : null}
      {board.managerRunId !== null && client !== null ? (
        <ManagerDock
          apis={apis}
          handle={handle}
          client={client}
          agentKind={managerAgent}
          hidden={!managerShown}
          onClose={() => setManagerShown(false)}
          onTurnSettled={board.reload}
        />
      ) : null}
      {newThreadOpen ? (
        <NewThreadDialog
          open
          apis={apis}
          projects={projects ?? []}
          initialProjectId={
            projectFilter === ALL_PROJECTS ? null : projectFilter
          }
          onClose={() => setNewThreadOpen(false)}
          onStarted={() => {
            setNewThreadOpen(false);
            board.reload();
          }}
        />
      ) : null}
    </div>
  );
}
