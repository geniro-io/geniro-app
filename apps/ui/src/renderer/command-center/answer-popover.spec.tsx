// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { ItemDto } from '../autogenerated';
import { AnswerPopover, type AnswerPopoverProps } from './answer-popover';
import type { OpenRequest } from './use-open-requests';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function question(runId: string, requestId: string, text: string): OpenRequest {
  return {
    runId,
    title: `Thread ${runId}`,
    isTeam: false,
    requestId,
    item: {
      id: `item-${requestId}`,
      runId,
      kind: 'approval_request',
      payload: {
        id: requestId,
        toolName: 'AskUserQuestion',
        questions: [
          { question: text, options: [{ label: 'Retry' }, { label: 'Park' }] },
        ],
      },
    } as unknown as ItemDto,
  };
}

const RETRY = question('run-a', 'q-1', 'How should the webhook be retried?');

let root: Root;
let container: HTMLDivElement;
let anchor: HTMLButtonElement;

beforeEach(() => {
  anchor = document.createElement('button');
  anchor.textContent = 'Answer';
  document.body.appendChild(anchor);
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  anchor.remove();
});

function draw(over: Partial<AnswerPopoverProps> = {}): void {
  act(() => {
    root.render(
      <AnswerPopover
        anchor={anchor}
        title="Bank webhook retries"
        projectColor="blue"
        requests={[RETRY]}
        error={null}
        onAnswer={vi.fn()}
        onShowThread={vi.fn()}
        onClose={vi.fn()}
        {...over}
      />,
    );
  });
}

const panel = (): HTMLElement | null =>
  container.querySelector<HTMLElement>('[data-slot="popover-panel"]');

const buttonNamed = (text: string): HTMLButtonElement =>
  [...panel()!.querySelectorAll<HTMLButtonElement>('button')].find(
    (button) => button.textContent === text,
  )!;

describe('AnswerPopover', () => {
  it('hangs the thread’s own question from the pressed Answer button, under the thread’s name and project colour', () => {
    draw();

    expect(panel()!.getAttribute('aria-label')).toBe(
      'Answer Bank webhook retries',
    );
    expect(panel()!.style.position).toBe('fixed');
    expect(
      panel()!.querySelector('[data-slot="answer-popover-title"]')!.textContent,
    ).toBe('Bank webhook retries');
    expect(
      panel()!.querySelector('[data-color]')!.getAttribute('data-color'),
    ).toBe('blue');
    expect(panel()!.textContent).toContain(
      'How should the webhook be retried?',
    );
  });

  it('answers through the Needs you path with the option picked', () => {
    const onAnswer = vi.fn();
    draw({ onAnswer });

    act(() => buttonNamed('Retry').click());

    expect(onAnswer).toHaveBeenCalledTimes(1);
    expect(onAnswer.mock.calls[0]!.slice(0, 3)).toEqual([RETRY, true, 'Retry']);
  });

  it('draws nothing once the thread holds nothing to answer', () => {
    draw({ requests: [] });

    expect(panel()).toBeNull();
  });

  it('closes on a press outside it, and leaves a press on its own Answer button to that button', () => {
    const onClose = vi.fn();
    draw({ onClose });

    act(() => {
      anchor.dispatchEvent(new MouseEvent('mousedown', { bubbles: true }));
    });
    expect(onClose).not.toHaveBeenCalled();

    act(() => {
      document.body.dispatchEvent(
        new MouseEvent('mousedown', { bubbles: true }),
      );
    });
    expect(onClose).toHaveBeenCalledTimes(1);
  });

  it('shows the thread’s chat on the canvas from its one Show chat button, and offers no other way in', () => {
    const onShowThread = vi.fn();
    draw({ onShowThread });

    const buttons = panel()!.querySelectorAll<HTMLButtonElement>(
      '[data-slot="answer-popover-show-chat"]',
    );
    expect(buttons).toHaveLength(1);
    expect(
      panel()!.querySelector('[data-slot="answer-popover-open-here"]'),
    ).toBeNull();
    expect(
      panel()!.querySelector('[data-slot="answer-popover-go"]'),
    ).toBeNull();

    act(() => buttons[0]!.click());

    expect(onShowThread).toHaveBeenCalledTimes(1);
  });
});
