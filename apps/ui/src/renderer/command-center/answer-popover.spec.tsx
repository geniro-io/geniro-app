// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { stubThreadContextReader } from '../__fixtures__/thread-context-reader';
import type { ItemDto } from '../autogenerated';
import type { PublishedArtifact } from '../chats/published-artifact';
import {
  type ThreadContextMessage,
  type ThreadContextReader,
  ThreadContextReaderContext,
} from '../chats/thread-question-context';
import { AnswerPopover, type AnswerPopoverProps } from './answer-popover';
import type { OpenRequest } from './use-open-requests';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function question(runId: string, requestId: string, text: string): OpenRequest {
  return {
    runId,
    title: `Thread ${runId}`,
    isTeam: false,
    requestId,
    item: {
      id: `item-${requestId}`,
      runId,
      kind: 'approval_request',
      payload: {
        id: requestId,
        toolName: 'AskUserQuestion',
        questions: [
          { question: text, options: [{ label: 'Retry' }, { label: 'Park' }] },
        ],
      },
    } as unknown as ItemDto,
  };
}

const RETRY = question('run-a', 'q-1', 'How should the webhook be retried?');

const RETRY_PLAN: PublishedArtifact = {
  artifactId: 'retry-plan',
  version: 1,
  title: 'Retry plan',
  summary: null,
  key: 'a'.repeat(64),
};

let root: Root;
let container: HTMLDivElement;
let anchor: HTMLButtonElement;

beforeEach(() => {
  anchor = document.createElement('button');
  anchor.textContent = 'Answer';
  document.body.appendChild(anchor);
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  anchor.remove();
});

function draw(
  over: Partial<AnswerPopoverProps> & {
    readContext?: ThreadContextReader['read'];
    pages?: PublishedArtifact[];
  } = {},
): void {
  const {
    readContext = vi.fn().mockResolvedValue([]),
    pages = [],
    ...props
  } = over;
  act(() => {
    root.render(
      <ThreadContextReaderContext.Provider
        value={stubThreadContextReader(readContext, {
          artifacts: () => Promise.resolve(pages),
        })}>
        <AnswerPopover
          anchor={anchor}
          title="Bank webhook retries"
          projectColor="blue"
          requests={[RETRY]}
          error={null}
          onAnswer={vi.fn()}
          onShowThread={vi.fn()}
          onClose={vi.fn()}
          {...props}
        />
      </ThreadContextReaderContext.Provider>,
    );
  });
}

const panel = (): HTMLElement | null =>
  container.querySelector<HTMLElement>('[data-slot="popover-panel"]');

const buttonNamed = (text: string): HTMLButtonElement =>
  [...panel()!.querySelectorAll<HTMLButtonElement>('button')].find(
    (button) => button.textContent === text,
  )!;

describe('AnswerPopover', () => {
  it('hangs the thread’s own question from the pressed Answer button, under the thread’s name and project colour', () => {
    draw();

    expect(panel()!.getAttribute('aria-label')).toBe(
      'Answer Bank webhook retries',
    );
    expect(panel()!.style.position).toBe('fixed');
    expect(
      panel()!.querySelector('[data-slot="answer-popover-title"]')!.textContent,
    ).toBe('Bank webhook retries');
    expect(
      panel()!.querySelector('[data-color]')!.getAttribute('data-color'),
    ).toBe('blue');
    expect(panel()!.textContent).toContain(
      'How should the webhook be retried?',
    );
  });

  it('answers through the Needs you path with the option picked', () => {
    const onAnswer = vi.fn();
    draw({ onAnswer });

    act(() => buttonNamed('Retry').click());

    expect(onAnswer).toHaveBeenCalledTimes(1);
    expect(onAnswer.mock.calls[0]!.slice(0, 3)).toEqual([RETRY, true, 'Retry']);
  });

  it('shows the last messages the thread sent before its question, expanded, between its header and the question', async () => {
    const messages: ThreadContextMessage[] = [
      { seq: 3, role: 'user', text: 'Keep the shared cache' },
      { seq: 4, role: 'assistant', text: 'Two caches could be meant' },
    ];
    const readContext = vi.fn().mockResolvedValue(messages);
    draw({ readContext });
    await act(async () => {
      await Promise.resolve();
    });

    expect(readContext).toHaveBeenCalledWith('run-a', 'q-1');
    expect(
      panel()!.querySelector<HTMLElement>(
        '[data-slot="thread-question-context"]',
      )?.dataset.state,
    ).toBe('shown');
    const text = panel()!.textContent ?? '';
    expect(text.indexOf('Bank webhook retries')).toBeLessThan(
      text.indexOf('Two caches could be meant'),
    );
    expect(text.indexOf('Two caches could be meant')).toBeLessThan(
      text.indexOf('How should the webhook be retried?'),
    );
  });

  it('shows the page its question passed explicitly inside the popover, at the thread’s own run', async () => {
    const asked = question(
      'run-a',
      'q-1',
      'How should the webhook be retried?',
    );
    draw({
      requests: [
        {
          ...asked,
          item: {
            ...asked.item,
            payload: {
              ...(asked.item.payload as Record<string, unknown>),
              toolName: 'ask_user_question',
              attachments: [
                {
                  kind: 'artifact',
                  artifactId: 'retry-plan',
                  title: 'Retry plan',
                  version: 1,
                },
              ],
            },
          },
        },
      ],
      pages: [RETRY_PLAN],
    });
    await act(async () => {
      await Promise.resolve();
    });

    const page = panel()!.querySelector<HTMLIFrameElement>(
      '[data-slot="question-attachments"] iframe',
    );
    expect(page?.getAttribute('src')).toContain(
      '/v1/artifacts/run-a/retry-plan',
    );
  });

  it('shows no page for a question that passed none, even one stored by an earlier build', async () => {
    draw({
      requests: [
        {
          ...RETRY,
          item: {
            ...RETRY.item,
            payload: {
              ...(RETRY.item.payload as Record<string, unknown>),
              attachments: [
                {
                  kind: 'artifact',
                  artifactId: 'retry-plan',
                  title: 'Retry plan',
                  version: 1,
                },
              ],
            },
          },
        },
      ],
      pages: [RETRY_PLAN],
    });
    await act(async () => {
      await Promise.resolve();
    });

    expect(panel()!.querySelector('iframe')).toBeNull();
    expect(panel()!.textContent).not.toContain('Retry plan');
  });

  it('draws nothing once the thread holds nothing to answer', () => {
    draw({ requests: [] });

    expect(panel()).toBeNull();
  });

  it('closes on a press outside it, and leaves a press on its own Answer button to that button', () => {
    const onClose = vi.fn();
    draw({ onClose });

    act(() => {
      anchor.dispatchEvent(new MouseEvent('mousedown', { bubbles: true }));
    });
    expect(onClose).not.toHaveBeenCalled();

    act(() => {
      document.body.dispatchEvent(
        new MouseEvent('mousedown', { bubbles: true }),
      );
    });
    expect(onClose).toHaveBeenCalledTimes(1);
  });

  it('shows the thread’s chat on the canvas from its one Show chat button, and offers no other way in', () => {
    const onShowThread = vi.fn();
    draw({ onShowThread });

    const buttons = panel()!.querySelectorAll<HTMLButtonElement>(
      '[data-slot="answer-popover-show-chat"]',
    );
    expect(buttons).toHaveLength(1);
    expect(
      panel()!.querySelector('[data-slot="answer-popover-open-here"]'),
    ).toBeNull();
    expect(
      panel()!.querySelector('[data-slot="answer-popover-go"]'),
    ).toBeNull();

    act(() => buttons[0]!.click());

    expect(onShowThread).toHaveBeenCalledTimes(1);
  });
});
