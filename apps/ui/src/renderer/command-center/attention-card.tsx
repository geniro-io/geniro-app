import { MessageSquare } from 'lucide-react';
import { useContext } from 'react';

import type { CommandCenterCard } from '../autogenerated';
import { SettingsNoticeCard } from '../chats/settings-attention-cards';
import { ThreadEventCard } from '../chats/thread-event-card';
import { ThreadOpenContext, useThreadIdentity } from '../chats/thread-title';
import { WaitingReviewCard } from '../chats/waiting-items-card';
import { WaitingItemsContext } from '../chats/waiting-items-context';
import {
  ArchiveThreadButton,
  useThreadArchive,
} from '../components/thread-archive';
import {
  bareThreadIdentity,
  ThreadActionButton,
  ThreadFoot,
  ThreadHead,
} from '../components/thread-head';
import { GoToThreadButton } from '../components/thread-labels';
import { type AnswerRequest, RequestCard } from './request-card';
import type { AttentionCard } from './use-attention-cards';
import type { OpenRequest } from './use-open-requests';

const UNTITLED = 'Untitled thread';

function RequestBody({
  request,
  onAnswer,
}: {
  request: OpenRequest;
  onAnswer: AnswerRequest;
}): React.JSX.Element {
  const open = useContext(ThreadOpenContext);
  return (
    <div className="flex min-w-0 flex-col gap-2">
      <div className="flex min-w-0 items-center gap-2">
        <span
          title={request.title}
          className="min-w-0 flex-1 truncate text-sm font-semibold">
          {request.title}
        </span>
        {open === null ? null : (
          <GoToThreadButton onGo={() => open(request.runId)} />
        )}
      </div>
      <RequestCard request={request} onAnswer={onAnswer} />
    </div>
  );
}

function FailedBody({ card }: { card: CommandCenterCard }): React.JSX.Element {
  const runId = card.run.id;
  const title = card.run.title ?? UNTITLED;
  const identity = useThreadIdentity(runId) ?? bareThreadIdentity(title);
  const open = useContext(ThreadOpenContext);
  const archive = useThreadArchive(runId);
  return (
    <article
      data-slot="attention-failed"
      className="flex w-full min-w-0 flex-col gap-1.5 rounded-lg border border-border/70 bg-card px-3 py-2 text-sm">
      <ThreadHead
        identity={{ ...identity, status: null }}
        slot="attention-failed"
        onOpen={open === null ? undefined : () => open(runId)}
        wrap
      />
      <p
        data-slot="attention-failed-status"
        className="m-0 text-sm text-destructive">
        Failed{card.activity === null ? '' : ` — ${card.activity}`}
      </p>
      <ThreadFoot slot="attention-failed" at={card.run.lastActivityAt ?? null}>
        {open === null ? null : (
          <ThreadActionButton
            slot="attention-failed-open"
            label={`Open ${identity.title}`}
            title="Open this thread's chat"
            icon={<MessageSquare aria-hidden="true" />}
            onClick={() => open(runId)}>
            Open chat
          </ThreadActionButton>
        )}
        {archive === null ? null : (
          <ArchiveThreadButton
            slot="attention-failed-archive"
            title={identity.title}
            onArchive={archive}
          />
        )}
      </ThreadFoot>
    </article>
  );
}

function ReviewBody({
  card,
}: {
  card: Extract<AttentionCard, { kind: 'review' }>;
}): React.JSX.Element | null {
  const store = useContext(WaitingItemsContext);
  return store === null ? null : (
    <WaitingReviewCard store={store} kind={card.review} id={card.id} />
  );
}

/**
 * One gallery card, drawn by the very component the manager chat draws it
 * with, so it carries the same actions: a question or approval answered the way
 * its thread answers it, a finished thread's Done card, a failed thread with
 * Open chat and Archive, a review item with its Settings row, a Settings notice.
 */
export function AttentionCardBody({
  card,
  onAnswer,
}: {
  card: AttentionCard;
  onAnswer: AnswerRequest;
}): React.JSX.Element | null {
  switch (card.kind) {
    case 'question':
    case 'approval':
      return <RequestBody request={card.request} onAnswer={onAnswer} />;
    case 'failed':
      return <FailedBody card={card.card} />;
    case 'finished':
      return (
        <ThreadEventCard
          kind="done"
          runId={card.card.run.id}
          title={card.card.run.title ?? UNTITLED}
          handle={card.card.handle}
          text={card.card.report}
          pullRequest={
            card.card.run.pullRequests.find((pr) => pr.opened)?.number ?? null
          }
          at={card.card.run.lastActivityAt ?? null}
          memoryKey={`attention:${card.key}`}
        />
      );
    case 'review':
      return <ReviewBody card={card} />;
    case 'notice':
      return (
        <SettingsNoticeCard
          row={{
            noticeId: card.notice.id,
            kind: card.notice.kind,
            key: card.notice.key,
          }}
        />
      );
  }
}
