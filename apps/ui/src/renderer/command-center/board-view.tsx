import type { CommandCenterColumn } from '../autogenerated';
import { cn } from '../components/ui/utils';
import type { ThreadCardView } from './card-view';
import { ThreadCard } from './thread-card';

export const BOARD_COLUMNS: readonly {
  id: CommandCenterColumn;
  label: string;
  hint: string;
}[] = [
  {
    id: 'working',
    label: 'Working',
    hint: 'A turn is running now.',
  },
  {
    id: 'waiting',
    label: 'Waiting on you',
    hint: 'A question or an approval waits for you.',
  },
  {
    id: 'idle',
    label: 'Idle',
    hint: 'Nothing running, nothing waiting, no pull request yet.',
  },
  {
    id: 'in_review',
    label: 'In review',
    hint: 'Its card is In review, or it opened a pull request and nothing runs. A thread without a card is placed by its pull requests alone.',
  },
  {
    id: 'done',
    label: 'Done',
    hint: 'Its card is Done, or the thread recorded how it ended.',
  },
];

export interface BoardEntry {
  runId: string;
  column: CommandCenterColumn;
  view: ThreadCardView;
}

/**
 * The same threads as the cards, in five columns the daemon computed. Never
 * dragged: a column is a fact about the thread, not a place to put it.
 */
export function BoardView({
  entries,
  onOpen,
}: {
  entries: readonly BoardEntry[];
  onOpen: (runId: string) => void;
}): React.JSX.Element {
  return (
    <div className="flex min-h-0 flex-1 gap-3 overflow-x-auto p-4 max-[640px]:flex-col max-[640px]:overflow-x-visible">
      {BOARD_COLUMNS.map((column) => {
        const inColumn = entries.filter((entry) => entry.column === column.id);
        return (
          <section
            key={column.id}
            aria-label={column.label}
            className={cn(
              'flex w-72 shrink-0 flex-col gap-2 rounded-lg bg-muted/40 p-2',
              'max-[640px]:w-full',
            )}>
            <header
              className="flex items-baseline justify-between px-1 text-xs font-medium text-muted-foreground"
              title={column.hint}>
              <span>{column.label}</span>
              <span className="tabular-nums">{inColumn.length}</span>
            </header>
            {inColumn.length === 0 ? (
              <p className="px-1 py-3 text-xs text-muted-foreground">
                No threads
              </p>
            ) : (
              inColumn.map((entry) => (
                <ThreadCard
                  key={entry.runId}
                  {...entry.view}
                  onOpen={() => onOpen(entry.runId)}
                />
              ))
            )}
          </section>
        );
      })}
    </div>
  );
}
