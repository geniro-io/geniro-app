describe('threadIdentitiesOf', () => {
  const boardCard = (
    id: string,
    over: {
      project?: { id: string; name: string } | null;
      teamId?: string | null;
      agentKind?: string | null;
      title?: string | null;
    },
  ) =>
    ({
      run: {
        id,
        title: over.title === undefined ? `Thread ${id}` : over.title,
        status: 'completed',
        awaiting: null,
        lastActivityAt: new Date(NOW - HOUR).toISOString(),
        createdAt: new Date(NOW - DAY).toISOString(),
        project: over.project ?? null,
        teamId: over.teamId ?? null,
        agentKind: over.agentKind ?? null,
        pullRequests: [],
      },
      column: 'idle',
      contact: { lastAt: null, awaitingReply: false },
      task: null,
      note: null,
      activity: null,
    }) as unknown as Parameters<typeof threadCardViewOf>[0];

  it('heads each board thread with what its node on the graph shows: status, labels, pull request and face', () => {
    const cards = [
      boardCard('run-web', {
        project: { id: 'p-web', name: 'Web' },
        agentKind: 'claude',
      }),
      boardCard('run-api', {
        project: { id: 'p-api', name: 'Api' },
        teamId: 'dev-team',
      }),
      boardCard('run-loose', { title: null }),
    ];
    const people = [{ key: 'm1', name: 'Lead' }];
    const teams = new Map([
      ['dev-team', { name: 'Dev Team', people, total: 3 }],
    ]);
    const canvasColors = new Map(
      projectColorsOf(cards.map((card) => card.run.project)).map((p) => [
        p.id,
        p.color,
      ]),
    );
    const claude = {
      agent: 'claude',
      shortName: 'claude',
      icon: 'terminal',
    } as unknown as AgentIdentityCapability;
    const pr = {
      number: 12,
      state: 'merged',
      isDraft: false,
    } as unknown as PullRequestInfo;

    const identities = threadIdentitiesOf(
      cards,
      null,
      (card) => (card.run.id === 'run-web' ? pr : null),
      [claude],
      teams,
      NOW,
      canvasColors,
    );

    for (const card of cards) {
      const view = threadCardViewOf(
        card,
        card.run.id === 'run-web' ? pr : null,
        [claude],
        teams,
        NOW,
        canvasColors,
      );
      expect(identities.get(card.run.id)).toMatchObject({
        title: view.title,
        status: { attention: view.attention, text: view.statusText },
        pullRequest: view.pullRequest,
        boardCard: view.boardCard,
        project: view.project,
        projectColor: view.projectColor,
        agentLabel: view.agentLabel,
        isTeam: view.isTeam,
      });
    }
    expect(identities.get('run-web')?.pullRequest).toEqual({
      number: 12,
      state: 'merged',
    });
    expect(identities.get('run-web')?.face).toEqual({
      kind: 'agent',
      icon: 'terminal',
      name: 'claude',
    });
    expect(identities.get('run-api')?.face).toEqual({
      kind: 'team',
      people,
      total: 3,
    });
    expect(identities.get('run-loose')?.face).toEqual({ kind: 'unknown' });
    expect(identities.size).toBe(cards.length);
  });

  it('heads the manager as its node does — Manager, its mast, its state and agent, no project', () => {
    const codex = {
      agent: 'codex',
      shortName: 'codex-short',
    } as unknown as AgentIdentityCapability;
    const identities = threadIdentitiesOf(
      [boardCard('run-web', { agentKind: 'claude' })],
      { id: 'run-manager', agentKind: 'codex', status: 'running' },
      () => null,
      [codex],
      new Map(),
      NOW,
      new Map(),
    );

    expect(identities.get('run-manager')).toEqual({
      title: MANAGER_TITLE,
      face: { kind: 'manager' },
      pullRequest: null,
      status: { attention: 'working', text: 'Working' },
      agentLabel: 'codex-short',
      isTeam: false,
      boardCard: null,
      project: null,
      projectColor: null,
    });
    expect(identities.get('run-web')?.title).toBe('Thread run-web');
  });
});

describe('sameThreadIdentities', () => {
  const people = [{ key: 'm1', name: 'Lead' }];
  const identity = (title: string, face: ThreadIdentity['face']) => ({
    ...bareThreadIdentity(title),
    face,
  });

  it('holds two separately built sets that name every thread the same way the same', () => {
    expect(
      sameThreadIdentities(
        new Map([
          ['a', identity('A', { kind: 'team', people, total: 3 })],
          [
            'b',
            identity('B', { kind: 'agent', icon: 'terminal', name: 'claude' }),
          ],
        ]),
        new Map([
          ['a', identity('A', { kind: 'team', people, total: 3 })],
          [
            'b',
            identity('B', { kind: 'agent', icon: 'terminal', name: 'claude' }),
          ],
        ]),
      ),
    ).toBe(true);
  });

  it('tells sets apart by a title, a thread, or a team’s faces', () => {
    const base = new Map([['a', identity('A', { kind: 'unknown' })]]);
    expect(
      sameThreadIdentities(
        base,
        new Map([['a', identity('A2', { kind: 'unknown' })]]),
      ),
    ).toBe(false);
    expect(
      sameThreadIdentities(
        base,
        new Map([['b', identity('A', { kind: 'unknown' })]]),
      ),
    ).toBe(false);
    expect(
      sameThreadIdentities(
        new Map([['a', identity('A', { kind: 'team', people, total: 3 })]]),
        new Map([
          ['a', identity('A', { kind: 'team', people: [...people], total: 3 })],
        ]),
      ),
    ).toBe(false);
  });

  it('holds two member faces the same when their name, colour and avatar match', () => {
    const member = (
      face: Partial<Extract<ThreadIdentity['face'], { kind: 'member' }>> = {},
    ): ThreadIdentity =>
      identity('A', {
        kind: 'member',
        name: 'Lead',
        avatar: { kind: 'initials', value: 'LD' },
        colorKey: 'lead',
        ...face,
      });
    const same = (a: ThreadIdentity, b: ThreadIdentity) =>
      sameThreadIdentities(new Map([['a', a]]), new Map([['a', b]]));

    expect(same(member(), member())).toBe(true);
    expect(same(member(), member({ name: 'QA' }))).toBe(false);
    expect(same(member(), member({ colorKey: 'qa' }))).toBe(false);
    expect(same(member(), member({ avatar: null }))).toBe(false);
    expect(
      same(member(), member({ avatar: { kind: 'emoji', value: 'LD' } })),
    ).toBe(false);
    expect(
      same(member(), member({ avatar: { kind: 'initials', value: 'LE' } })),
    ).toBe(false);
    expect(
      same(
        member(),
        member({ avatar: { kind: 'initials', value: 'LD', tone: 'avatar-2' } }),
      ),
    ).toBe(false);
  });

  it('holds two monitor faces the same, and tells one apart from a plain thread', () => {
    const monitor = () => identity('A', { kind: 'monitor' });
    expect(
      sameThreadIdentities(
        new Map([['a', monitor()]]),
        new Map([['a', monitor()]]),
      ),
    ).toBe(true);
    expect(
      sameThreadIdentities(
        new Map([['a', monitor()]]),
        new Map([['a', identity('A', { kind: 'unknown' })]]),
      ),
    ).toBe(false);
  });
});

