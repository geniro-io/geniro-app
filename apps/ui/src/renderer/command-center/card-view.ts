import type { PullRequestInfo } from '../../shared/contracts';
import { agentShortName } from '../agent-identity';
import type {
  AgentIdentityCapability,
  CommandCenterCard,
  CommandCenterTaskRef,
} from '../autogenerated';
import type {
  TimelineMarker,
  TimelineStripProps,
} from '../components/timeline-strip';
import type { ThreadCardProps, ThreadCardStatus } from './thread-card';

/** What a thread's card shows, and the board card it works. */
export type ThreadCardView = Omit<
  ThreadCardProps,
  'onOpen' | 'task' | 'summary'
> & { task: CommandCenterTaskRef | null };

function statusOf(card: CommandCenterCard): ThreadCardStatus {
  if (card.column === 'waiting') {
    return 'waiting';
  }
  if (card.column === 'working') {
    return 'working';
  }
  if (card.run.status === 'failed') {
    return 'failed';
  }
  return card.column === 'done' ? 'done' : 'idle';
}

function pullRequestOf(
  card: CommandCenterCard,
  pullRequest: PullRequestInfo | null,
): ThreadCardView['pullRequest'] {
  if (pullRequest !== null) {
    return {
      number: pullRequest.number,
      state:
        pullRequest.state === 'open' && pullRequest.isDraft
          ? 'draft'
          : pullRequest.state,
    };
  }
  const opened = card.run.pullRequests.find((row) => row.opened);
  return opened === undefined ? null : { number: opened.number, state: 'open' };
}

/**
 * A board card as the thread card draws it. The merged marker is the one
 * moment the daemon cannot place — it stores no merge state — so it comes from
 * the pull request main's `gh` read already returned.
 */
export function threadCardViewOf(
  card: CommandCenterCard,
  pullRequest: PullRequestInfo | null,
  identities: readonly AgentIdentityCapability[],
  strip: { start: string; end: string },
): ThreadCardView {
  const merged: TimelineMarker[] =
    pullRequest?.mergedAt !== undefined &&
    pullRequest.mergedAt >= strip.start &&
    pullRequest.mergedAt <= strip.end
      ? [
          {
            kind: 'pr_merged',
            at: pullRequest.mergedAt,
            label: `PR ${pullRequest.number}`,
          },
        ]
      : [];
  const timeline: TimelineStripProps = {
    start: strip.start,
    end: strip.end,
    spans: card.strip.spans.map((span) => ({
      kind: span.kind,
      start: span.start,
      end: span.end ?? null,
    })),
    markers: [
      ...card.strip.markers.map((marker) => ({
        kind: marker.kind,
        at: marker.at,
        label: marker.label ?? null,
      })),
      ...merged,
    ].sort((a, b) => a.at.localeCompare(b.at)),
  };
  return {
    title: card.run.title ?? 'Untitled thread',
    status: statusOf(card),
    handle: card.handle ?? null,
    task: card.task ?? null,
    project: card.run.project?.name ?? null,
    agentLabel:
      card.run.teamId != null
        ? 'Team'
        : card.run.agentKind == null
          ? null
          : agentShortName(identities, card.run.agentKind),
    pullRequest: pullRequestOf(card, pullRequest),
    note: card.note ?? null,
    activity: card.activity ?? null,
    strip: timeline,
  };
}
