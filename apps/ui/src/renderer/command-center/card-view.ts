/** What a thread's card shows. */
export type ThreadCardView = Omit<
  ThreadCardProps,
  'onGo' | 'onOpenHere' | 'summary' | 'height'
>;

const DAY_MS = 24 * 60 * 60_000;

/** A thread nobody touched for this many whole days wears an idle mark. */
export const IDLE_AFTER_DAYS = 3;

/** A quiet thread untouched this long is greyed out and sinks to the bottom. */
export const INACTIVE_AFTER_MS = DAY_MS;

/** Top to bottom: what is blocked, what waits on a question, what works, what is quiet, what has gone still. */
export const ATTENTION_ORDER: readonly ThreadAttention[] = [
  'blocked',
  'question',
  'working',
  'quiet',
  'inactive',
];

/** Whole days since the thread last moved, once that reaches {@link IDLE_AFTER_DAYS}; else null. */
export function idleDaysOf(lastAt: string, now: number): number | null {
  const days = Math.floor((now - Date.parse(lastAt)) / DAY_MS);
  return days >= IDLE_AFTER_DAYS ? days : null;
}

/**
 * Where a thread stands for the user: blocked on a press (a failure, an
 * approval), waiting on the user's answer to its question, working (the
 * manager awaiting its reply counts as work), quiet, or untouched for a day
 * and more.
 */
export function attentionOf(
  card: Pick<CommandCenterCard, 'run' | 'column' | 'contact'>,
  now: number,
): ThreadAttention {
  if (card.run.status === 'failed' || card.run.awaiting === 'approval') {
    return 'blocked';
  }
  if (card.column === 'working') {
    return 'working';
  }
  if (card.run.awaiting === 'question') {
    return 'question';
  }
  if (card.contact.awaitingReply) {
    return 'working';
  }
  const lastAt = Date.parse(card.run.lastActivityAt ?? card.run.createdAt);
  return now - lastAt >= INACTIVE_AFTER_MS ? 'inactive' : 'quiet';
}

/** The status chip's words: why a blocked, questioned or awaited thread stands where it does, else its status. */
export function statusTextOf(
  card: Pick<CommandCenterCard, 'run' | 'contact'>,
  status: ThreadCardStatus,
  attention: ThreadAttention,
): string {
  if (attention === 'blocked') {
    return card.run.status === 'failed' ? 'Failed' : 'Needs approval';
  }
  if (attention === 'question') {
    return 'Question for you';
  }
  if (
    attention === 'working' &&
    status !== 'working' &&
    card.contact.awaitingReply
  ) {
    return 'Awaiting reply';
  }
  return THREAD_STATUS_TEXT[status];
}

function statusOf(card: CommandCenterCard): ThreadCardStatus {
  if (card.column === 'waiting') {
    return 'waiting';
  }
  if (card.column === 'working') {
    return 'working';
  }
  if (card.run.status === 'failed') {
    return 'failed';
  }
  return card.column === 'done' ? 'done' : 'idle';
}

function pullRequestOf(
  card: CommandCenterCard,
  pullRequest: PullRequestInfo | null,
): ThreadCardView['pullRequest'] {
  if (pullRequest !== null) {
    return {
      number: pullRequest.number,
      state:
        pullRequest.state === 'open' && pullRequest.isDraft
          ? 'draft'
          : pullRequest.state,
    };
  }
  const opened = card.run.pullRequests.find((row) => row.opened);
  return opened === undefined ? null : { number: opened.number, state: 'open' };
}

/** What the command center knows of a library team: its name and the faces of its members. */
export interface TeamFace {
  name: string;
  people: readonly AvatarPerson[];
  total: number;
}

/** Each library team by slug, as its card on the graph draws it. */
export function teamFacesOf(
  teams: readonly TeamSummaryDto[],
): Map<string, TeamFace> {
  return new Map(
    teams.map((team) => [
      team.slug,
      {
        name: team.name,
        people: team.portrait.map((member) => ({
          key: member.id,
          name: member.name,
          avatar: member.avatar,
        })),
        total: team.memberCount,
      },
    ]),
  );
}

function agentLabelOf(
  card: CommandCenterCard,
  identities: readonly AgentIdentityCapability[],
  teams: ReadonlyMap<string, TeamFace>,
): string | null {
  if (card.run.teamId != null) {
    return teams.get(card.run.teamId)?.name ?? card.run.teamId;
  }
  return card.run.agentKind == null
    ? null
    : agentShortName(identities, card.run.agentKind);
}

function threadNameOf(
  card: CommandCenterCard,
  identities: readonly AgentIdentityCapability[],
  teams: ReadonlyMap<string, TeamFace>,
  projectColors: ReadonlyMap<string, ProfileColor>,
): Pick<
  ThreadCardView,
  'title' | 'project' | 'projectColor' | 'agentLabel' | 'isTeam'
> {
  return {
    title: card.run.title ?? 'Untitled thread',
    project: card.run.project?.name ?? null,
    projectColor:
      card.run.project == null
        ? null
        : (projectColors.get(card.run.project.id) ?? null),
    agentLabel: agentLabelOf(card, identities, teams),
    isTeam: card.run.teamId != null,
  };
}

function faceOf(
  card: CommandCenterCard,
  identities: readonly AgentIdentityCapability[],
  teams: ReadonlyMap<string, TeamFace>,
): ThreadFaceLook {
  if (card.run.teamId != null) {
    const team = teams.get(card.run.teamId);
    return team === undefined || team.people.length === 0
      ? { kind: 'unknown' }
      : { kind: 'team', people: team.people, total: team.total };
  }
  return card.run.agentKind == null
    ? { kind: 'unknown' }
    : {
        kind: 'agent',
        icon: agentIconName(identities, card.run.agentKind),
        name: agentShortName(identities, card.run.agentKind),
      };
}

/** A thread as transcripts head it, from what its node on the graph shows. */
export function threadIdentityOfView(
  view: ThreadCardView,
  face: ThreadFaceLook,
): ThreadIdentity {
  return {
    title: view.title,
    face,
    pullRequest: view.pullRequest,
    status: { attention: view.attention, text: view.statusText },
    agentLabel: view.agentLabel,
    isTeam: view.isTeam,
    boardCard: view.boardCard,
    project: view.project,
    projectColor: view.projectColor ?? null,
  };
}

/** The name the graph's manager node and the transcripts give the command center manager. */
export const MANAGER_TITLE = 'Manager';

/** The command center manager as its node on the graph shows it. */
export function managerIdentityOf(
  manager: Pick<RunDto, 'agentKind' | 'status'>,
  identities: readonly AgentIdentityCapability[],
): ThreadIdentity {
  const working = manager.status === 'running';
  return {
    title: MANAGER_TITLE,
    face: { kind: 'manager' },
    pullRequest: null,
    status: {
      attention: working ? 'working' : 'quiet',
      text: working ? 'Working' : 'Idle',
    },
    agentLabel:
      manager.agentKind == null
        ? null
        : agentShortName(identities, manager.agentKind),
    isTeam: false,
    boardCard: null,
    project: null,
    projectColor: null,
  };
}

/** Every board thread, and the manager, as transcripts head them — the same face, status, labels and pull request as their nodes on the graph. */
export function threadIdentitiesOf(
  cards: readonly CommandCenterCard[],
  manager: Pick<RunDto, 'id' | 'agentKind' | 'status'> | null,
  pullRequestOf: (card: CommandCenterCard) => PullRequestInfo | null,
  identities: readonly AgentIdentityCapability[],
  teams: ReadonlyMap<string, TeamFace>,
  now: number,
  projectColors: ReadonlyMap<string, ProfileColor>,
): ReadonlyMap<string, ThreadIdentity> {
  const threads = cards.map((card): [string, ThreadIdentity] => [
    card.run.id,
    threadIdentityOfView(
      threadCardViewOf(
        card,
        pullRequestOf(card),
        identities,
        teams,
        now,
        projectColors,
      ),
      faceOf(card, identities, teams),
    ),
  ]);
  return new Map(
    manager === null
      ? threads
      : [[manager.id, managerIdentityOf(manager, identities)], ...threads],
  );
}

/**
 * A board entry as the thread card draws it. A pull request's state comes
 * from main's `gh` read when there is one — the daemon stores no merge state.
 */
export function threadCardViewOf(
  card: CommandCenterCard,
  pullRequest: PullRequestInfo | null,
  identities: readonly AgentIdentityCapability[],
  teams: ReadonlyMap<string, TeamFace>,
  now: number,
  projectColors: ReadonlyMap<string, ProfileColor> = new Map(),
): ThreadCardView {
  const team = card.run.teamId == null ? undefined : teams.get(card.run.teamId);
  const lastAt = card.run.lastActivityAt ?? card.run.createdAt;
  const status = statusOf(card);
  const attention = attentionOf(card, now);
  return {
    ...threadNameOf(card, identities, teams, projectColors),
    status,
    statusText: statusTextOf(card, status, attention),
    attention,
    boardCard:
      card.task == null
        ? null
        : {
            identifier: card.task.identifier ?? null,
            title: card.task.title,
            status: card.task.status,
          },
    idleDays: idleDaysOf(lastAt, now),
    lastAt,
    now,
    crew:
      team === undefined ? null : { people: team.people, total: team.total },
    pullRequest: pullRequestOf(card, pullRequest),
    note: card.note ?? null,
    lastMessage: card.activity ?? null,
  };
}

/**
 * The cards in the order they stand: by {@link ATTENTION_ORDER}, newest
 * activity first within each band, except working threads, which stand newest
 * started first — their activity moves with every item they stream.
 */
export function orderByAttention<
  T extends {
    id: string;
    createdAt: string;
    view: Pick<ThreadCardView, 'attention' | 'lastAt'>;
  },
>(threads: readonly T[]): T[] {
  return [...threads].sort(
    (a, b) =>
      ATTENTION_ORDER.indexOf(a.view.attention) -
        ATTENTION_ORDER.indexOf(b.view.attention) ||
      (a.view.attention === 'working'
        ? b.createdAt.localeCompare(a.createdAt) || a.id.localeCompare(b.id)
        : b.view.lastAt.localeCompare(a.view.lastAt)),
  );
}
