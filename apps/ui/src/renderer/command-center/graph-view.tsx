function LinkEdge({ id, data }: EdgeProps<LinkFlowEdge>): React.JSX.Element {
  const path = roundedPath(data!.route, 10);
  return (
    <path
      aria-hidden="true"
      data-slot="graph-link"
      data-edge={id}
      d={path}
      style={pathStyle(path)}
      className="fill-none stroke-border-strong transition-[d] duration-300 ease-out motion-reduce:transition-none"
      strokeWidth={1.25}
      strokeLinecap="round"
    />
  );
}

const NODE_TYPES = {
  manager: ManagerNode,
  thread: ThreadNode,
  task: TaskNode,
  more: MoreNode,
};
const EDGE_TYPES = { contact: ContactEdge, link: LinkEdge };

function handlesFor(width: number, height: number): NodeHandle[] {
  return [
    { id: 'in', type: 'target', position: Position.Top, x: width / 2, y: 0 },
    {
      id: 'out',
      type: 'source',
      position: Position.Bottom,
      x: width / 2,
      y: height,
    },
  ];
}

function agoWords(ms: number): string {
  const minutes = Math.floor(ms / 60_000);
  if (minutes < 1) {
    return 'just now';
  }
  if (minutes < 60) {
    return `${minutes} min ago`;
  }
  return `${Math.floor(minutes / 60)} h ago`;
}

function summaryOf(
  view: ThreadCardView,
  state: EdgeState,
  lastAt: string | null,
  now: number,
): string {
  return [
    view.title,
    THREAD_STATUS_TEXT[view.status],
    ...(state === 'awaiting' ? ['awaiting a reply'] : []),
    lastAt === null
      ? 'no contact yet'
      : `last contact ${agoWords(now - Date.parse(lastAt))}`,
  ].join(', ');
}

function threadHeight(view: ThreadCardView): number {
  return threadCardHeight({
    note: view.note !== null,
    activity: activityLine(view.activity) !== '',
    task: view.task !== null,
  });
}

const MANAGER_BOX: GraphBox = {
  id: MANAGER_ID,
  width: MANAGER_WIDTH,
  height: MANAGER_HEIGHT,
};

/** What hangs under the manager, in the order it stands: each thread with its card if unfolded, then "+N more". */
export function graphItems(
  shown: readonly GraphThread[],
  hidden: number,
  expanded: ReadonlySet<string>,
): GraphItem[] {
  return [
    ...shown.map((thread): GraphItem => ({
      box: {
        id: `thread:${thread.id}`,
        width: THREAD_CARD_WIDTH,
        height: threadHeight(thread.view),
      },
      child:
        thread.view.task !== null && expanded.has(thread.id)
          ? { id: `task:${thread.id}`, width: TASK_WIDTH, height: TASK_HEIGHT }
          : null,
    })),
    ...(hidden > 0
      ? [
          {
            box: { id: MORE_ID, width: MORE_WIDTH, height: MORE_HEIGHT },
            child: null,
          },
        ]
      : []),
  ];
}

function useElementSize(): [
  (el: HTMLDivElement | null) => void,
  { width: number; height: number },
] {
  const [element, setElement] = useState<HTMLDivElement | null>(null);
  const [size, setSize] = useState({ width: 0, height: 0 });
  useLayoutEffect(() => {
    if (element === null) {
      return;
    }
    setSize({ width: element.clientWidth, height: element.clientHeight });
    if (typeof ResizeObserver === 'undefined') {
      return;
    }
    const observer = new ResizeObserver((entries) => {
      const rect = entries.at(-1)?.contentRect;
      if (rect !== undefined) {
        setSize({ width: rect.width, height: rect.height });
      }
    });
    observer.observe(element);
    return () => observer.disconnect();
  }, [element]);
  return [setElement, size];
}

const PAN_ROOM = 160;

/** Nodes answer the pointer only when React Flow sees a handler on them; the cards handle their own presses. */
const POINTER_ON_NODES = (): void => undefined;

/** Which threads get a node: the newest by activity, then oldest first, so a node keeps its place. */
export function shownThreads(threads: readonly GraphThread[]): GraphThread[] {
  return threads
    .slice(0, MAX_THREAD_NODES)
    .sort((a, b) => a.createdAt.localeCompare(b.createdAt));
}

export function GraphView(props: GraphViewProps): React.JSX.Element {
  return (
    <ReactFlowProvider>
      <GraphCanvas {...props} />
    </ReactFlowProvider>
  );
}

/**
 * The view that shows the graph across the canvas's width from its top, never
 * zoomed past 1: a card stays readable and a tall graph scrolls down, where a
 * whole-graph fit would shrink a few rows of cards to nothing.
 */
export function widthFit(
  graph: { width: number },
  canvas: { width: number },
): { x: number; y: number; zoom: number } {
  const zoom = Math.max(
    MIN_ZOOM,
    Math.min(1, (canvas.width - FIT_MARGIN * 2) / Math.max(1, graph.width)),
  );
  return {
    x: Math.max(FIT_MARGIN, (canvas.width - graph.width * zoom) / 2),
    y: FIT_MARGIN,
    zoom,
  };
}

function ZoomControls({ onFit }: { onFit: () => void }): React.JSX.Element {
  const flow = useReactFlow();
  const reduced = usePrefersReducedMotion();
  const duration = reduced ? 0 : 200;
  return (
    <div
      role="group"
      aria-label="Zoom"
      className="absolute right-3 bottom-3 z-10 flex flex-col gap-1 rounded-control border border-border bg-card p-1 shadow-sm">
      <Button
        type="button"
        variant="ghost"
        size="icon"
        className="size-7"
        aria-label="Zoom in"
        onClick={() => void flow.zoomIn({ duration })}>
        <Plus aria-hidden="true" />
      </Button>
      <Button
        type="button"
        variant="ghost"
        size="icon"
        className="size-7"
        aria-label="Zoom out"
        onClick={() => void flow.zoomOut({ duration })}>
        <Minus aria-hidden="true" />
      </Button>
      <Button
        type="button"
        variant="ghost"
        size="icon"
        className="size-7"
        aria-label="Fit the graph"
        onClick={onFit}>
        <Maximize aria-hidden="true" />
      </Button>
    </div>
  );
}

function GraphCanvas({
  managerStarted,
  threads,
  contacts,
  pulses,
  now,
  narrow,
  onOpen,
  onManager,
  className,
}: GraphViewProps): React.JSX.Element {
  const flow = useReactFlow();
  const reduced = usePrefersReducedMotion();
  const [expanded, setExpanded] = useState<ReadonlySet<string>>(new Set());
  const [measure, size] = useElementSize();
  const fitted = useRef<string | null>(null);

  const shown = shownThreads(threads);
  const hidden = threads.length - shown.length;
  const items = graphItems(shown, hidden, expanded);
  const drawn: GraphGeometry = narrow
    ? layoutColumn(MANAGER_BOX, items)
    : layoutRows(
        MANAGER_BOX,
        items,
        columnsFor(size.width, THREAD_CARD_WIDTH, items.length),
      );

  const fit = useLatestCallback((animate: boolean) => {
    void flow.setViewport(widthFit(drawn, size), {
      duration: animate && !reduced ? FIT_MS : 0,
    });
  }, []);
  const structure = [...drawn.boxes.keys()].sort().join('|');
  const fitKey = `${structure}#${Math.round(size.width)}x${Math.round(size.height)}`;
  useLayoutEffect(() => {
    if (narrow || size.width === 0 || fitted.current === fitKey) {
      return;
    }
    const first = fitted.current === null;
    fitted.current = fitKey;
    fit(!first);
  }, [fitKey, narrow, size.width, fit]);

  const open = useLatestCallback(onOpen, []);
  const manager = useLatestCallback(onManager, []);
  const toggle = useLatestCallback((threadId: string) => {
    setExpanded((was) => {
      const next = new Set(was);
      if (!next.delete(threadId)) {
        next.add(threadId);
      }
      return next;
    });
  }, []);

  const states = new Map(
    shown.map((thread) => {
      const contact = contacts[thread.id];
      const threadPulses = pulses.filter(
        (pulse) => pulse.threadId === thread.id,
      );
      return [
        thread.id,
        {
          contact,
          pulses: threadPulses,
          state: edgeStateOf(contact, threadPulses, now),
        },
      ] as const;
    }),
  );
  const awaiting = [...states.values()].filter(
    (entry) => entry.state === 'awaiting',
  ).length;

  const nodes: GraphFlowNode[] = [];
  const contactEdges: ContactFlowEdge[] = [];
  const linkEdges: LinkFlowEdge[] = [];
  const base = (id: string) => {
    const box = drawn.boxes.get(id)!;
    return {
      id,
      position: { x: box.x, y: box.y },
      width: box.width,
      height: box.height,
      handles: handlesFor(box.width, box.height),
      className: NODE_CLASS,
      selectable: false,
      draggable: false,
      focusable: false,
    };
  };
  const link = (
    source: string,
    target: string,
    route: readonly Point[] | undefined,
  ): void => {
    if (route !== undefined) {
      linkEdges.push({
        id: `link:${target}`,
        type: 'link',
        source,
        sourceHandle: 'out',
        target,
        targetHandle: 'in',
        focusable: false,
        selectable: false,
        data: { route },
      });
    }
  };
  nodes.push({
    ...base(MANAGER_ID),
    type: 'manager',
    data: { started: managerStarted, threads: shown.length, awaiting },
  });
  for (const thread of shown) {
    const id = `thread:${thread.id}`;
    const entry = states.get(thread.id)!;
    nodes.push({
      ...base(id),
      type: 'thread',
      data: {
        thread,
        expanded: expanded.has(thread.id),
        summary: summaryOf(
          thread.view,
          entry.state,
          entry.contact?.lastAt ?? null,
          now,
        ),
      },
    });
    const wire = drawn.routes.get(id);
    if (wire !== undefined) {
      contactEdges.push({
        id: `contact:${thread.id}`,
        type: 'contact',
        source: MANAGER_ID,
        sourceHandle: 'out',
        target: id,
        targetHandle: 'in',
        focusable: false,
        selectable: false,
        data: { route: wire, state: entry.state, pulses: entry.pulses, now },
      });
    }
    const taskId = `task:${thread.id}`;
    const task = thread.view.task;
    if (task !== null && drawn.boxes.has(taskId)) {
      nodes.push({
        ...base(taskId),
        type: 'task',
        data: { threadId: thread.id, task },
      });
      link(id, taskId, drawn.routes.get(taskId));
    }
  }
  if (hidden > 0) {
    nodes.push({ ...base(MORE_ID), type: 'more', data: { count: hidden } });
    link(MANAGER_ID, MORE_ID, drawn.routes.get(MORE_ID));
  }
  const edges: (ContactFlowEdge | LinkFlowEdge)[] = [
    ...linkEdges,
    ...contactEdges.sort(
      (a, b) =>
        EDGE_PAINT_ORDER[a.data!.state] - EDGE_PAINT_ORDER[b.data!.state],
    ),
  ];

  const label = `Manager and ${shown.length} ${shown.length === 1 ? 'thread' : 'threads'}`;
  const flowProps = {
    nodes,
    edges,
    nodeTypes: NODE_TYPES,
    edgeTypes: EDGE_TYPES,
    onNodeClick: POINTER_ON_NODES,
    nodesDraggable: false,
    nodesConnectable: false,
    nodesFocusable: false,
    edgesFocusable: false,
    elementsSelectable: false,
    disableKeyboardA11y: true,
    deleteKeyCode: null,
    selectionKeyCode: null,
    multiSelectionKeyCode: null,
    panActivationKeyCode: null,
    zoomActivationKeyCode: null,
    proOptions: PRO_OPTIONS,
  };

  return (
    <GraphActionsContext.Provider value={{ open, toggle, manager }}>
      {narrow ? (
        <div
          role="group"
          aria-label={label}
          data-slot="command-center-graph"
          data-layout="column"
          className={cn('overflow-y-auto', className)}>
          <div
            className="mx-auto"
            style={{ width: drawn.width, height: drawn.height }}>
            <ReactFlow
              {...flowProps}
              defaultViewport={{ x: 0, y: 0, zoom: 1 }}
              panOnDrag={false}
              panOnScroll={false}
              zoomOnScroll={false}
              zoomOnPinch={false}
              zoomOnDoubleClick={false}
              preventScrolling={false}
            />
          </div>
        </div>
      ) : (
        <div
          ref={measure}
          role="group"
          aria-label={label}
          data-slot="command-center-graph"
          data-layout="rows"
          data-columns={columnsFor(size.width, THREAD_CARD_WIDTH, items.length)}
          className={cn('relative', className)}>
          {size.width === 0 ? null : (
            <>
              <ReactFlow
                {...flowProps}
                defaultViewport={widthFit(drawn, size)}
                minZoom={MIN_ZOOM}
                maxZoom={MAX_ZOOM}
                translateExtent={[
                  [-PAN_ROOM, -PAN_ROOM],
                  [drawn.width + PAN_ROOM, drawn.height + PAN_ROOM],
                ]}
                panOnDrag
                panOnScroll
                zoomOnScroll={false}
                zoomOnPinch
                zoomOnDoubleClick={false}
              />
              <ZoomControls onFit={() => fit(true)} />
            </>
          )}
        </div>
      )}
    </GraphActionsContext.Provider>
  );
}
