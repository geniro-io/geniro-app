export const MAX_THREAD_NODES = 24;

export interface GraphThread {
  id: string;
  createdAt: string;
  view: ThreadCardView;
}

export interface GraphViewProps {
  /** Whether the manager chat exists yet. */
  managerStarted: boolean;
  /** Newest activity first; the first {@link MAX_THREAD_NODES} are drawn. */
  threads: readonly GraphThread[];
  contacts: Readonly<Record<string, ContactState>>;
  pulses: readonly ContactPulse[];
  now: number;
  /** One column for a narrow screen, scrolled rather than panned. */
  narrow: boolean;
  onOpen: (threadId: string) => void;
  onManager: () => void;
  className?: string;
}

const MANAGER_ID = 'manager';
const MORE_ID = 'more';
const MANAGER_WIDTH = THREAD_CARD_WIDTH;
const MANAGER_HEIGHT = 64;
const TASK_WIDTH = 260;
const TASK_HEIGHT = 60;
const MORE_WIDTH = 160;
const MORE_HEIGHT = 32;
const MIN_ZOOM = 0.25;
const MAX_ZOOM = 1.5;
const FIT_VIEW_OPTIONS = { padding: 0.12, maxZoom: 1, minZoom: 0.25 };
const FIT_MS = 400;
const PRO_OPTIONS = { hideAttribution: true };

const NODE_CLASS =
  'transition-transform duration-300 ease-out motion-reduce:transition-none';

interface ManagerNodeData extends Record<string, unknown> {
  started: boolean;
  threads: number;
  awaiting: number;
}

interface ThreadNodeData extends Record<string, unknown> {
  thread: GraphThread;
  expanded: boolean;
  summary: string;
}

interface TaskNodeData extends Record<string, unknown> {
  threadId: string;
  task: CommandCenterTaskRef;
}

interface MoreNodeData extends Record<string, unknown> {
  count: number;
}

interface LinkEdgeData extends Record<string, unknown> {
  route: readonly Point[];
}

type ManagerFlowNode = Node<ManagerNodeData, 'manager'>;
type ThreadFlowNode = Node<ThreadNodeData, 'thread'>;
type TaskFlowNode = Node<TaskNodeData, 'task'>;
type MoreFlowNode = Node<MoreNodeData, 'more'>;
type GraphFlowNode =
  ManagerFlowNode | ThreadFlowNode | TaskFlowNode | MoreFlowNode;
type LinkFlowEdge = Edge<LinkEdgeData, 'link'>;

interface GraphActions {
  open: (threadId: string) => void;
  toggle: (threadId: string) => void;
  manager: () => void;
}

const GraphActionsContext = createContext<GraphActions>({
  open: () => undefined,
  toggle: () => undefined,
  manager: () => undefined,
});

const HIDDEN_HANDLE = { opacity: 0, pointerEvents: 'none' } as const;

/**
 * The node's two wire ends, in the DOM as well as on the node: once React Flow
 * measures a drawn node it reads its handles from here, and a node without
 * them loses every wire.
 */
function WireEnds(): React.JSX.Element {
  return (
    <>
      <Handle
        id="in"
        type="target"
        position={Position.Top}
        isConnectable={false}
        style={HIDDEN_HANDLE}
      />
      <Handle
        id="out"
        type="source"
        position={Position.Bottom}
        isConnectable={false}
        style={HIDDEN_HANDLE}
      />
    </>
  );
}

function ManagerNode({ data }: NodeProps<ManagerFlowNode>): React.JSX.Element {
  const { manager } = useContext(GraphActionsContext);
  const { started, threads, awaiting } = data;
  const line = started
    ? `Runs ${threads} ${threads === 1 ? 'thread' : 'threads'}`
    : 'Not started — open it to run your threads in plain words';
  return (
    <>
      <WireEnds />
      <button
        type="button"
        data-slot="graph-manager"
        data-started={started}
        aria-label={`Manager: ${line}${awaiting > 0 ? `, ${awaiting} awaiting a reply` : ''}`}
        onClick={manager}
        className="flex size-full items-center gap-3 rounded-card border border-primary/60 bg-card px-3 text-left shadow-md outline-none transition-[box-shadow,translate] duration-200 hover:-translate-y-px hover:shadow-lg focus-visible:ring-[3px] focus-visible:ring-ring/60 motion-reduce:transition-none motion-reduce:hover:translate-y-0">
        <span className="flex size-9 shrink-0 items-center justify-center rounded-full bg-primary/12 text-primary">
          <RadioTower aria-hidden="true" className="size-4.5" />
        </span>
        <span className="flex min-w-0 flex-1 flex-col">
          <span className="text-sm font-semibold">Manager</span>
          <span className="truncate text-xs text-muted-foreground">{line}</span>
        </span>
        {awaiting > 0 ? (
          <span
            data-slot="graph-manager-awaiting"
            className="shrink-0 rounded-pill bg-warning/15 px-2 py-0.5 text-xs font-medium text-warning tabular-nums">
            {awaiting} awaiting
          </span>
        ) : null}
      </button>
    </>
  );
}

function ThreadNode({ data }: NodeProps<ThreadFlowNode>): React.JSX.Element {
  const { open, toggle } = useContext(GraphActionsContext);
  const { thread, expanded, summary } = data;
  const { task, ...view } = thread.view;
  return (
    <div data-slot="graph-thread" data-thread-id={thread.id}>
      <WireEnds />
      <ThreadCard
        {...view}
        summary={summary}
        task={
          task === null ? null : { expanded, onToggle: () => toggle(thread.id) }
        }
        onOpen={() => open(thread.id)}
      />
    </div>
  );
}

function TaskNode({ data }: NodeProps<TaskFlowNode>): React.JSX.Element {
  const { open } = useContext(GraphActionsContext);
  const { threadId, task } = data;
  const meta = taskStatusMeta(task.status);
  const Icon = meta.icon;
  return (
    <>
      <WireEnds />
      <button
        type="button"
        data-slot="graph-task"
        data-task-id={task.id}
        aria-label={`Board card ${task.identifier ?? ''} ${task.title}, ${meta.label}`.replace(
          /\s+/g,
          ' ',
        )}
        onClick={() => open(threadId)}
        className="live-row-in flex size-full flex-col justify-center gap-1 rounded-card border border-border bg-muted/40 px-3 text-left outline-none transition-colors hover:border-primary/50 focus-visible:ring-[3px] focus-visible:ring-ring/60">
        <span className="flex min-w-0 items-center gap-2 text-xs">
          <span className="font-mono text-muted-foreground tabular-nums">
            {task.identifier ?? 'Board card'}
          </span>
          <span
            className={cn(
              'ml-auto flex shrink-0 items-center gap-1',
              meta.className,
            )}>
            <Icon aria-hidden="true" className="size-3.5" />
            {meta.label}
          </span>
        </span>
        <span title={task.title} className="truncate text-sm">
          {task.title}
        </span>
      </button>
    </>
  );
}

function MoreNode({ data }: NodeProps<MoreFlowNode>): React.JSX.Element {
  return (
    <>
      <WireEnds />
      <span
        data-slot="graph-more"
        className="flex size-full items-center justify-center rounded-pill border border-dashed border-border-strong bg-card text-xs text-muted-foreground">
        +{data.count} more {data.count === 1 ? 'thread' : 'threads'}
      </span>
    </>
  );
}

function LinkEdge({ id, data }: EdgeProps<LinkFlowEdge>): React.JSX.Element {
  const path = roundedPath(data!.route, 10);
  return (
    <path
      aria-hidden="true"
      data-slot="graph-link"
      data-edge={id}
      d={path}
      style={pathStyle(path)}
      className="fill-none stroke-border-strong transition-[d] duration-300 ease-out motion-reduce:transition-none"
      strokeWidth={1.25}
      strokeLinecap="round"
    />
  );
}

const NODE_TYPES = {
  manager: ManagerNode,
  thread: ThreadNode,
  task: TaskNode,
  more: MoreNode,
};
const EDGE_TYPES = { contact: ContactEdge, link: LinkEdge };

function handlesFor(width: number, height: number): NodeHandle[] {
  return [
    { id: 'in', type: 'target', position: Position.Top, x: width / 2, y: 0 },
    {
      id: 'out',
      type: 'source',
      position: Position.Bottom,
      x: width / 2,
      y: height,
    },
  ];
}

function agoWords(ms: number): string {
  const minutes = Math.floor(ms / 60_000);
  if (minutes < 1) {
    return 'just now';
  }
  if (minutes < 60) {
    return `${minutes} min ago`;
  }
  return `${Math.floor(minutes / 60)} h ago`;
}

function summaryOf(
  view: ThreadCardView,
  state: EdgeState,
  lastAt: string | null,
  now: number,
): string {
  return [
    view.title,
    THREAD_STATUS_TEXT[view.status],
    ...(state === 'awaiting' ? ['awaiting a reply'] : []),
    lastAt === null
      ? 'no contact yet'
      : `last contact ${agoWords(now - Date.parse(lastAt))}`,
  ].join(', ');
}

function threadHeight(view: ThreadCardView): number {
  return threadCardHeight({
    note: view.note !== null,
    activity: activityLine(view.activity) !== '',
    task: view.task !== null,
  });
}

/** The boxes of the tree, in the order they stand: manager, then each thread and its card. */
export function graphBoxes(
  shown: readonly GraphThread[],
  hidden: number,
  expanded: ReadonlySet<string>,
): TreeBox[] {
  return [
    {
      id: MANAGER_ID,
      width: MANAGER_WIDTH,
      height: MANAGER_HEIGHT,
      parent: null,
    },
    ...shown.flatMap((thread): TreeBox[] => [
      {
        id: `thread:${thread.id}`,
        width: THREAD_CARD_WIDTH,
        height: threadHeight(thread.view),
        parent: MANAGER_ID,
      },
      ...(thread.view.task !== null && expanded.has(thread.id)
        ? [
            {
              id: `task:${thread.id}`,
              width: TASK_WIDTH,
              height: TASK_HEIGHT,
              parent: `thread:${thread.id}`,
            },
          ]
        : []),
    ]),
    ...(hidden > 0
      ? [
          {
            id: MORE_ID,
            width: MORE_WIDTH,
            height: MORE_HEIGHT,
            parent: MANAGER_ID,
          },
        ]
      : []),
  ];
}

/** Which threads get a node: the newest by activity, then oldest first, so a node keeps its place. */
export function shownThreads(threads: readonly GraphThread[]): GraphThread[] {
  return threads
    .slice(0, MAX_THREAD_NODES)
    .sort((a, b) => a.createdAt.localeCompare(b.createdAt));
}

export function GraphView(props: GraphViewProps): React.JSX.Element {
  return (
    <ReactFlowProvider>
      <GraphCanvas {...props} />
    </ReactFlowProvider>
  );
}

function ZoomControls(): React.JSX.Element {
  const flow = useReactFlow();
  const reduced = usePrefersReducedMotion();
  const duration = reduced ? 0 : 200;
  return (
    <div
      role="group"
      aria-label="Zoom"
      className="absolute right-3 bottom-3 z-10 flex flex-col gap-1 rounded-control border border-border bg-card p-1 shadow-sm">
      <Button
        type="button"
        variant="ghost"
        size="icon"
        className="size-7"
        aria-label="Zoom in"
        onClick={() => void flow.zoomIn({ duration })}>
        <Plus aria-hidden="true" />
      </Button>
      <Button
        type="button"
        variant="ghost"
        size="icon"
        className="size-7"
        aria-label="Zoom out"
        onClick={() => void flow.zoomOut({ duration })}>
        <Minus aria-hidden="true" />
      </Button>
      <Button
        type="button"
        variant="ghost"
        size="icon"
        className="size-7"
        aria-label="Fit the graph"
        onClick={() =>
          void flow.fitView({
            ...FIT_VIEW_OPTIONS,
            duration: reduced ? 0 : FIT_MS,
          })
        }>
        <Maximize aria-hidden="true" />
      </Button>
    </div>
  );
}

function GraphCanvas({
  managerStarted,
  threads,
  contacts,
  pulses,
  now,
  narrow,
  onOpen,
  onManager,
  className,
}: GraphViewProps): React.JSX.Element {
  const flow = useReactFlow();
  const reduced = usePrefersReducedMotion();
  const [expanded, setExpanded] = useState<ReadonlySet<string>>(new Set());
  const [drawn, setDrawn] = useState<TreeGraphGeometry | null>(null);
  const [failed, setFailed] = useState(false);
  const fitted = useRef<string | null>(null);

  const shown = shownThreads(threads);
  const hidden = threads.length - shown.length;
  const boxes = graphBoxes(shown, hidden, expanded);
  const signature = JSON.stringify([
    narrow,
    boxes.map((box) => [box.id, box.height]),
  ]);

  const relayout = useLatestCallback((): (() => void) => {
    let cancelled = false;
    if (narrow) {
      setDrawn(layoutTreeColumn(boxes));
      setFailed(false);
      return () => undefined;
    }
    layoutTreeGraph(boxes).then(
      (geometry) => {
        if (!cancelled) {
          setDrawn(geometry);
          setFailed(false);
        }
      },
      (error: unknown) => {
        if (!cancelled) {
          console.error('Could not lay out the command center graph', error);
          setFailed(true);
        }
      },
    );
    return () => {
      cancelled = true;
    };
  }, []);
  useLayoutEffect(() => relayout(), [signature, relayout]);

  const structure =
    drawn === null ? null : [...drawn.boxes.keys()].sort().join('|');
  useEffect(() => {
    if (narrow || structure === null || fitted.current === structure) {
      return;
    }
    const first = fitted.current === null;
    fitted.current = structure;
    if (first) {
      return;
    }
    const timer = window.setTimeout(() => {
      void flow.fitView({
        ...FIT_VIEW_OPTIONS,
        duration: reduced ? 0 : FIT_MS,
      });
    }, 0);
    return () => window.clearTimeout(timer);
  }, [structure, narrow, flow, reduced]);

  const open = useLatestCallback(onOpen, []);
  const manager = useLatestCallback(onManager, []);
  const toggle = useLatestCallback((threadId: string) => {
    setExpanded((was) => {
      const next = new Set(was);
      if (!next.delete(threadId)) {
        next.add(threadId);
      }
      return next;
    });
  }, []);

  const states = new Map(
    shown.map((thread) => {
      const contact = contacts[thread.id];
      const threadPulses = pulses.filter(
        (pulse) => pulse.threadId === thread.id,
      );
      return [
        thread.id,
        {
          contact,
          pulses: threadPulses,
          state: edgeStateOf(contact, threadPulses, now),
        },
      ] as const;
    }),
  );
  const awaiting = [...states.values()].filter(
    (entry) => entry.state === 'awaiting',
  ).length;

  const nodes: GraphFlowNode[] = [];
  const edges: (ContactFlowEdge | LinkFlowEdge)[] = [];
  if (drawn !== null) {
    const place = (id: string) => drawn.boxes.get(id);
    const base = (id: string) => {
      const box = place(id)!;
      return {
        id,
        position: { x: box.x, y: box.y },
        width: box.width,
        height: box.height,
        handles: handlesFor(box.width, box.height),
        className: NODE_CLASS,
        selectable: false,
        draggable: false,
        focusable: false,
      };
    };
    const route = (id: string) => drawn.routes.get(id);
    if (place(MANAGER_ID) !== undefined) {
      nodes.push({
        ...base(MANAGER_ID),
        type: 'manager',
        data: { started: managerStarted, threads: shown.length, awaiting },
      });
    }
    for (const thread of shown) {
      const id = `thread:${thread.id}`;
      if (place(id) === undefined) {
        continue;
      }
      const entry = states.get(thread.id)!;
      nodes.push({
        ...base(id),
        type: 'thread',
        data: {
          thread,
          expanded: expanded.has(thread.id),
          summary: summaryOf(
            thread.view,
            entry.state,
            entry.contact?.lastAt ?? null,
            now,
          ),
        },
      });
      const wire = route(id);
      if (wire !== undefined) {
        edges.push({
          id: `contact:${thread.id}`,
          type: 'contact',
          source: MANAGER_ID,
          sourceHandle: 'out',
          target: id,
          targetHandle: 'in',
          focusable: false,
          selectable: false,
          data: {
            route: wire,
            state: entry.state,
            pulses: entry.pulses,
            now,
          },
        });
      }
      const taskId = `task:${thread.id}`;
      const task = thread.view.task;
      if (task !== null && place(taskId) !== undefined) {
        nodes.push({
          ...base(taskId),
          type: 'task',
          data: { threadId: thread.id, task },
        });
        const taskWire = route(taskId);
        if (taskWire !== undefined) {
          edges.push({
            id: `link:${taskId}`,
            type: 'link',
            source: id,
            sourceHandle: 'out',
            target: taskId,
            targetHandle: 'in',
            focusable: false,
            selectable: false,
            data: { route: taskWire },
          });
        }
      }
    }
    if (hidden > 0 && place(MORE_ID) !== undefined) {
      nodes.push({ ...base(MORE_ID), type: 'more', data: { count: hidden } });
      const moreWire = route(MORE_ID);
      if (moreWire !== undefined) {
        edges.push({
          id: `link:${MORE_ID}`,
          type: 'link',
          source: MANAGER_ID,
          sourceHandle: 'out',
          target: MORE_ID,
          targetHandle: 'in',
          focusable: false,
          selectable: false,
          data: { route: moreWire },
        });
      }
    }
  }

  const label = `Manager and ${shown.length} ${shown.length === 1 ? 'thread' : 'threads'}`;

  if (failed) {
    return (
      <p className="p-6 text-sm text-muted-foreground">
        Couldn’t draw the graph
      </p>
    );
  }
  if (drawn === null) {
    return (
      <p className="p-6 text-sm text-muted-foreground">Laying out threads…</p>
    );
  }

  const flowProps = {
    nodes,
    edges,
    nodeTypes: NODE_TYPES,
    edgeTypes: EDGE_TYPES,
    nodesDraggable: false,
    nodesConnectable: false,
    nodesFocusable: false,
    edgesFocusable: false,
    elementsSelectable: false,
    disableKeyboardA11y: true,
    deleteKeyCode: null,
    selectionKeyCode: null,
    multiSelectionKeyCode: null,
    panActivationKeyCode: null,
    zoomActivationKeyCode: null,
    proOptions: PRO_OPTIONS,
  };

  return (
    <GraphActionsContext.Provider value={{ open, toggle, manager }}>
      {narrow ? (
        <div
          role="group"
          aria-label={label}
          data-slot="command-center-graph"
          data-layout="column"
          className={cn('overflow-y-auto', className)}>
          <div
            className="mx-auto"
            style={{ width: drawn.width, height: drawn.height }}>
            <ReactFlow
              {...flowProps}
              defaultViewport={{ x: 0, y: 0, zoom: 1 }}
              panOnDrag={false}
              panOnScroll={false}
              zoomOnScroll={false}
              zoomOnPinch={false}
              zoomOnDoubleClick={false}
              preventScrolling={false}
            />
          </div>
        </div>
      ) : (
        <div
          role="group"
          aria-label={label}
          data-slot="command-center-graph"
          data-layout="tree"
          className={cn('relative', className)}>
          <ReactFlow
            {...flowProps}
            fitView
            fitViewOptions={FIT_VIEW_OPTIONS}
            minZoom={MIN_ZOOM}
            maxZoom={MAX_ZOOM}
            panOnDrag
            panOnScroll
            zoomOnScroll={false}
            zoomOnPinch
            zoomOnDoubleClick={false}
          />
          <ZoomControls />
        </div>
      )}
    </GraphActionsContext.Provider>
  );
}
