import type { ManagerConfig } from '../../shared/contracts';
import type { StartCommandCenterChatDto } from '../autogenerated';
import { isChatApprovalMode } from '../chats/composer-values';
import { currentRunSettings } from '../run-settings';
import { triageRequestSettings } from '../settings/memory-triage-settings';

/**
 * The request that starts the manager on `choice`: its agent, profile, model,
 * effort, context window and parameters, its approval mode and auto-compact
 * when set, and the user's instructions and reply language read at the moment
 * of the start. An unset approval or auto-compact is left out, so the daemon's
 * own default applies.
 */
export async function managerStartRequest(
  choice: ManagerConfig,
): Promise<StartCommandCenterChatDto> {
  return {
    ...(await currentRunSettings()),
    ...triageRequestSettings(choice),
    ...(isChatApprovalMode(choice.approval)
      ? { approval: choice.approval }
      : {}),
    ...(choice.autoCompactPercent === null
      ? {}
      : { autoCompactPercent: choice.autoCompactPercent }),
  };
}
