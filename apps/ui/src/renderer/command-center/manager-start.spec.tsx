// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  type CliDetection,
  type CliKind,
  DEFAULT_SETTINGS,
  type ManagerConfig,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { AgentApprovalCapability } from '../autogenerated';
import { MODE_LABELS } from '../chats/approval-mode-select';
import { autoCompactLabel } from '../chats/auto-compact';
import type { DaemonApis } from '../daemon-api';
import { ManagerStart } from './manager-start';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

const DETECTIONS = [
  { kind: 'claude', found: true },
  { kind: 'codex', found: true },
  { kind: 'cursor-agent', found: false },
] as unknown as CliDetection[];

const CHOICE: ManagerConfig = {
  agent: 'codex',
  configDir: '/Users/me/codex-work',
  model: 'gpt-5.4',
  effort: 'high',
  contextWindow: '272k',
  modelParameters: { fast: 'on' },
  approval: null,
  autoCompactPercent: null,
};

// Which modes each CLI offers; `plan` is offered but withheld from the picker.
const MODES: Record<string, string[]> = {
  claude: ['ask', 'auto', 'plan'],
  codex: ['ask'],
  'cursor-agent': [],
};

function approvalCapabilityFor(
  kind: CliKind,
): AgentApprovalCapability | undefined {
  return {
    agent: kind,
    modes: MODES[kind],
  } as unknown as AgentApprovalCapability;
}

function settle(): Promise<void> {
  return act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });
}

function picker(label: string): HTMLButtonElement | null {
  return container.querySelector<HTMLButtonElement>(
    `button[aria-label="${label}"]`,
  );
}

async function click(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
  await settle();
}

function button(text: string): HTMLButtonElement {
  return [...container.querySelectorAll<HTMLButtonElement>('button')].find(
    (candidate) => candidate.textContent?.trim() === text,
  )!;
}

/** An option of an open menu, by the text of its own label. */
function optionNamed(text: string): HTMLElement | undefined {
  return [...document.querySelectorAll<HTMLElement>('[role="option"]')].find(
    (option) => option.querySelector('span')?.textContent === text,
  );
}

function labelOf(mode: string): string {
  return MODE_LABELS.find((entry) => entry.value === mode)!.label;
}

function renderStart(
  choice: ManagerConfig,
  onPick: (next: ManagerConfig) => void,
  onOpened: () => void,
  openCommandCenterChat: ReturnType<typeof vi.fn>,
): Promise<void> {
  const apis = {
    agents: null,
    commandCenter: { openCommandCenterChat },
  } as unknown as DaemonApis;
  return act(async () => {
    root.render(
      <ManagerStart
        apis={apis}
        choice={choice}
        onPick={onPick}
        cliDetections={DETECTIONS}
        capabilities={null}
        capabilitiesLoading={false}
        approvalCapabilityFor={approvalCapabilityFor}
        recentConfigDirs={{}}
        configProfiles={[]}
        onOpened={onOpened}
      />,
    );
  });
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  window.geniro = createPreloadStub({
    getSettings: () =>
      Promise.resolve({
        ...DEFAULT_SETTINGS,
        customInstructions: 'Be brief.',
        replyLanguage: 'Russian',
      }),
  });
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('ManagerStart', () => {
  it('offers the agent picker and the full model settings menu, not a bare select', async () => {
    await renderStart(CHOICE, vi.fn(), vi.fn(), vi.fn());

    expect(picker('Manager agent')).not.toBeNull();
    expect(picker('Model and its settings')).not.toBeNull();
  });

  it('starts the manager with the picked agent, profile, model, effort, window and parameters', async () => {
    const openCommandCenterChat = vi.fn(async () => ({}));
    const onOpened = vi.fn();
    await renderStart(CHOICE, vi.fn(), onOpened, openCommandCenterChat);

    await click(button('Open the manager'));

    expect(openCommandCenterChat).toHaveBeenCalledTimes(1);
    expect(openCommandCenterChat).toHaveBeenCalledWith({
      startCommandCenterChatDto: {
        agentKind: 'codex',
        configDir: '/Users/me/codex-work',
        model: 'gpt-5.4',
        effort: 'high',
        contextWindow: '272k',
        modelParameters: { fast: 'on' },
        customInstructions: 'Be brief.',
        replyLanguage: 'Russian',
        agentOptions: {},
      },
    });
    expect(onOpened).toHaveBeenCalledTimes(1);
  });

  it('offers the approval mode without plan, and reports the pick', async () => {
    const onPick = vi.fn();
    await renderStart({ ...CHOICE, agent: 'claude' }, onPick, vi.fn(), vi.fn());

    await click(picker('Tool-approval mode of the manager')!);
    expect(optionNamed(labelOf('plan'))).toBeUndefined();
    await click(optionNamed(labelOf('auto'))!);

    expect(onPick).toHaveBeenLastCalledWith({
      ...CHOICE,
      agent: 'claude',
      approval: 'auto',
    });
  });

  it('offers the auto-compact axis in the model menu, and reports the pick', async () => {
    const onPick = vi.fn();
    await renderStart(CHOICE, onPick, vi.fn(), vi.fn());

    await click(picker('Model and its settings')!);
    await click(optionNamed('Auto-compact')!);
    await click(optionNamed(autoCompactLabel(60))!);

    expect(onPick).toHaveBeenLastCalledWith({
      ...CHOICE,
      autoCompactPercent: 60,
    });
  });

  it('switching CLI drops an approval the new CLI does not offer, and keeps the auto-compact', async () => {
    const onPick = vi.fn();
    await renderStart(
      { ...CHOICE, agent: 'claude', approval: 'auto', autoCompactPercent: 80 },
      onPick,
      vi.fn(),
      vi.fn(),
    );

    await click(picker('Manager agent')!);
    await click(
      document.querySelector<HTMLElement>('[role="option"][title="codex"]')!,
    );

    expect(onPick).toHaveBeenLastCalledWith({
      agent: 'codex',
      configDir: null,
      model: null,
      effort: null,
      contextWindow: null,
      modelParameters: {},
      approval: null,
      autoCompactPercent: 80,
    });
  });

  it('switching CLI keeps an approval the new CLI offers', async () => {
    const onPick = vi.fn();
    await renderStart(
      { ...CHOICE, agent: 'codex', approval: 'ask' },
      onPick,
      vi.fn(),
      vi.fn(),
    );

    await click(picker('Manager agent')!);
    await click(
      document.querySelector<HTMLElement>('[role="option"][title="claude"]')!,
    );

    expect(onPick).toHaveBeenLastCalledWith(
      expect.objectContaining({ agent: 'claude', approval: 'ask' }),
    );
  });
});
