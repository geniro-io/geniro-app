import { useState } from 'react';

import type {
  CliDetection,
  CliKind,
  ConfigProfile,
  ManagerConfig,
} from '../../shared/contracts';
import type {
  AgentApprovalCapability,
  CapabilitiesDto,
} from '../autogenerated';
import {
  ApprovalModeSelect,
  approvalOptions,
  PLAN_WITHHELD,
} from '../chats/approval-mode-select';
import {
  isChatApprovalMode,
  newChatApprovalOf,
} from '../chats/composer-values';
import { TargetSelect, type TargetTeam } from '../chats/target-select';
import { Button } from '../components/ui/button';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import {
  blankTriageChoiceFor,
  ChoiceModelSettings,
} from '../settings/memory-triage-settings';
import { managerStartRequest } from './manager-start-request';

const NO_TEAMS: readonly TargetTeam[] = [];

/**
 * The command center before its manager exists: the agent and model settings,
 * the approval mode and the auto-compact the manager will run with, and the
 * press that starts it on them.
 */
export function ManagerStart({
  apis,
  choice,
  onPick,
  cliDetections,
  capabilities,
  capabilitiesLoading,
  approvalCapabilityFor,
  recentConfigDirs,
  configProfiles,
  onOpened,
}: {
  apis: DaemonApis;
  choice: ManagerConfig;
  onPick: (next: ManagerConfig) => void;
  cliDetections: readonly CliDetection[] | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  approvalCapabilityFor: (kind: CliKind) => AgentApprovalCapability | undefined;
  recentConfigDirs: Partial<Record<CliKind, readonly string[]>>;
  configProfiles: readonly ConfigProfile[];
  onOpened: () => void;
}): React.JSX.Element {
  const [error, setError] = useState<string | null>(null);

  const capability = approvalCapabilityFor(choice.agent);
  const approval = isChatApprovalMode(choice.approval)
    ? choice.approval
    : newChatApprovalOf(capability?.modes ?? []);
  const approvalPickable =
    approvalOptions(capability, approval, PLAN_WITHHELD).length > 0;

  // A mode the new CLI does not offer is dropped; the auto-compact is one value
  // for every CLI, so it stays.
  const approvalOfferedBy = (kind: CliKind): ManagerConfig['approval'] => {
    const mode = choice.approval;
    const offered = approvalCapabilityFor(kind)?.modes ?? [];
    return mode !== null && offered.some((offer) => offer === mode)
      ? mode
      : null;
  };

  const open = (): void => {
    setError(null);
    void managerStartRequest(choice)
      .then((request) =>
        apis.commandCenter.openCommandCenterChat({
          startCommandCenterChatDto: request,
        }),
      )
      .then(onOpened)
      .catch((err: unknown) => setError(describeDaemonError(err)));
  };

  return (
    <section
      aria-label="Open the manager"
      className="m-auto flex max-w-md flex-col items-center gap-3 p-6 text-center text-sm">
      <p className="text-muted-foreground">
        The manager watches and messages every thread for you, and starts new
        ones when you ask. Run it on
      </p>
      <div className="flex min-w-0 flex-wrap items-center justify-center gap-1">
        <TargetSelect
          value={choice.agent}
          teams={NO_TEAMS}
          cliDetections={cliDetections}
          aria-label="Manager agent"
          onChange={(target) => {
            const next = blankTriageChoiceFor(target);
            if (next !== null && next.agent !== choice.agent) {
              onPick({
                ...next,
                approval: approvalOfferedBy(next.agent),
                autoCompactPercent: choice.autoCompactPercent,
              });
            }
          }}
        />
        <ChoiceModelSettings
          value={choice}
          onChange={onPick}
          agentsApi={apis.agents}
          capabilities={capabilities}
          capabilitiesLoading={capabilitiesLoading}
          recentConfigDirs={recentConfigDirs}
          configProfiles={configProfiles}
          autoCompactPercent={choice.autoCompactPercent}
          onAutoCompactChange={(percent) =>
            onPick({ ...choice, autoCompactPercent: percent })
          }
        />
        {approvalPickable ? (
          <ApprovalModeSelect
            capability={capability}
            value={approval}
            withheld={PLAN_WITHHELD}
            ariaLabel="Tool-approval mode of the manager"
            onChange={(mode) => onPick({ ...choice, approval: mode })}
          />
        ) : null}
      </div>
      <Button type="button" size="sm" onClick={open}>
        Open the manager
      </Button>
      {error === null ? null : (
        <p role="alert" className="text-destructive">
          {error}
        </p>
      )}
    </section>
  );
}
