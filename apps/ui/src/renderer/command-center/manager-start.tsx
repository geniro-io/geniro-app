import { useState } from 'react';

import type {
  CliDetection,
  CliKind,
  ConfigProfile,
  MemoryTriageConfig,
} from '../../shared/contracts';
import type { CapabilitiesDto } from '../autogenerated';
import { TargetSelect, type TargetTeam } from '../chats/target-select';
import { Button } from '../components/ui/button';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import {
  blankTriageChoiceFor,
  ChoiceModelSettings,
} from '../settings/memory-triage-settings';
import { managerStartRequest } from './manager-start-request';

const NO_TEAMS: readonly TargetTeam[] = [];

/**
 * The command center before its manager exists: the agent and model settings
 * the manager will run with, and the press that starts it on them.
 */
export function ManagerStart({
  apis,
  choice,
  onPick,
  cliDetections,
  capabilities,
  capabilitiesLoading,
  recentConfigDirs,
  configProfiles,
  onOpened,
}: {
  apis: DaemonApis;
  choice: MemoryTriageConfig;
  onPick: (next: MemoryTriageConfig) => void;
  cliDetections: readonly CliDetection[] | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  recentConfigDirs: Partial<Record<CliKind, readonly string[]>>;
  configProfiles: readonly ConfigProfile[];
  onOpened: () => void;
}): React.JSX.Element {
  const [error, setError] = useState<string | null>(null);

  const open = (): void => {
    setError(null);
    void managerStartRequest(choice)
      .then((request) =>
        apis.commandCenter.openCommandCenterChat({
          startCommandCenterChatDto: request,
        }),
      )
      .then(onOpened)
      .catch((err: unknown) => setError(describeDaemonError(err)));
  };

  return (
    <section
      aria-label="Open the manager"
      className="m-auto flex max-w-md flex-col items-center gap-3 p-6 text-center text-sm">
      <p className="text-muted-foreground">
        The manager watches and messages every thread for you, and starts new
        ones when you ask. Run it on
      </p>
      <div className="flex min-w-0 flex-wrap items-center justify-center gap-1">
        <TargetSelect
          value={choice.agent}
          teams={NO_TEAMS}
          cliDetections={cliDetections}
          aria-label="Manager agent"
          onChange={(target) => {
            const next = blankTriageChoiceFor(target);
            if (next !== null && next.agent !== choice.agent) {
              onPick(next);
            }
          }}
        />
        <ChoiceModelSettings
          value={choice}
          onChange={onPick}
          agentsApi={apis.agents}
          capabilities={capabilities}
          capabilitiesLoading={capabilitiesLoading}
          recentConfigDirs={recentConfigDirs}
          configProfiles={configProfiles}
        />
      </div>
      <Button type="button" size="sm" onClick={open}>
        Open the manager
      </Button>
      {error === null ? null : (
        <p role="alert" className="text-destructive">
          {error}
        </p>
      )}
    </section>
  );
}
