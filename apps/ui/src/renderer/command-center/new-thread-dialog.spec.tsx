// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { ProjectDto, TaskDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { NewThreadDialog } from './new-thread-dialog';

const run = vi.hoisted(() => ({ startTaskRun: vi.fn() }));
vi.mock('../tasks/start-task-run', () => ({
  startTaskRun: run.startTaskRun,
}));

vi.mock('../chats/target-select', () => ({
  TargetSelect: ({ onChange }: { onChange: (target: string) => void }) => (
    <button type="button" onClick={() => onChange('team:review')}>
      Pick review team
    </button>
  ),
}));

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const PROJECT = { id: 'p1', name: 'Geniro', folder: '/repo' } as ProjectDto;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

beforeEach(() => {
  window.geniro = createPreloadStub({ detectClis: vi.fn(async () => []) });
  run.startTaskRun.mockReset();
});

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

function mount(): { createTask: ReturnType<typeof vi.fn> } {
  const createTask = vi.fn(
    async ({ createTaskDto }: { createTaskDto: { title: string } }) =>
      ({
        id: 'task-1',
        projectId: 'p1',
        title: createTaskDto.title,
      }) as TaskDto,
  );
  const apis = {
    tasks: { createTask },
    teams: { listTeams: vi.fn(async () => []) },
  } as unknown as DaemonApis;
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <NewThreadDialog
        open
        apis={apis}
        projects={[PROJECT]}
        initialProjectId="p1"
        onClose={() => undefined}
        onStarted={() => undefined}
      />,
    );
  });
  return { createTask };
}

function typeTitle(text: string): void {
  const title = document.body.querySelector(
    '#new-thread-title',
  ) as HTMLInputElement;
  const setter = Object.getOwnPropertyDescriptor(
    HTMLInputElement.prototype,
    'value',
  )?.set;
  act(() => {
    setter?.call(title, text);
    title.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

function button(label: string): HTMLButtonElement {
  return [...document.body.querySelectorAll('button')].find(
    (node) => node.textContent === label,
  ) as HTMLButtonElement;
}

async function submit(): Promise<void> {
  await act(async () => {
    button('Start thread').click();
  });
}

describe('NewThreadDialog', () => {
  it('files the card on the agent or team picked, then starts it', async () => {
    run.startTaskRun.mockResolvedValue({ runId: 'run-1' });
    const { createTask } = mount();

    typeTitle('Fix the login redirect');
    act(() => {
      button('Pick review team').click();
    });
    await submit();

    expect(createTask).toHaveBeenCalledWith({
      createTaskDto: {
        projectId: 'p1',
        title: 'Fix the login redirect',
        teamSlug: 'review',
      },
    });
    expect(run.startTaskRun).toHaveBeenCalledTimes(1);
  });

  it('starts the card it already filed when a failed start is tried again', async () => {
    run.startTaskRun
      .mockRejectedValueOnce(new Error('worktree failed'))
      .mockResolvedValueOnce({ runId: 'run-1' });
    const { createTask } = mount();

    typeTitle('Fix the login redirect');
    await submit();

    expect(document.body.textContent).toContain(
      'The card "Fix the login redirect" stays in backlog',
    );

    await submit();

    expect(createTask).toHaveBeenCalledTimes(1);
    expect(run.startTaskRun).toHaveBeenCalledTimes(2);
    expect(run.startTaskRun.mock.calls[1]![0].task.id).toBe('task-1');
  });
});
