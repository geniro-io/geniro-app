import { useState } from 'react';

import type { ProjectDto, TaskDto } from '../autogenerated';
import { ErrorText } from '../components/error-text';
import { Field } from '../components/field';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { Select } from '../components/ui/select';
import { Textarea } from '../components/ui/textarea';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import { currentRunSettings } from '../run-settings';
import { startTaskRun } from '../tasks/start-task-run';

/**
 * Start a new thread from the command center: a card on the project's board
 * with its own worktree and branch, started at once — the press is the
 * approval. What runs it is the project's own default, as on the board.
 */
export function NewThreadDialog({
  open,
  apis,
  projects,
  initialProjectId,
  onClose,
  onStarted,
}: {
  open: boolean;
  apis: DaemonApis;
  projects: readonly ProjectDto[];
  initialProjectId: string | null;
  onClose: () => void;
  onStarted: (runId: string | null) => void;
}): React.JSX.Element {
  const [title, setTitle] = useState('');
  const [brief, setBrief] = useState('');
  const [projectId, setProjectId] = useState<string | null>(
    initialProjectId ?? projects[0]?.id ?? null,
  );
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [filed, setFiled] = useState<TaskDto | null>(null);
  const project = projects.find((row) => row.id === projectId) ?? null;

  const start = async (): Promise<void> => {
    if (project === null || title.trim() === '') {
      return;
    }
    setBusy(true);
    setError(null);
    let task = filed?.projectId === project.id ? filed : null;
    try {
      task ??= await apis.tasks.createTask({
        createTaskDto: {
          projectId: project.id,
          title: title.trim(),
          ...(brief.trim() === '' ? {} : { description: brief.trim() }),
        },
      });
      setFiled(task);
      const started = await startTaskRun({
        apis,
        bridge: window.geniro,
        readRunSettings: currentRunSettings,
        task,
        project,
      });
      setTitle('');
      setBrief('');
      setFiled(null);
      onStarted(started.runId ?? null);
    } catch (err: unknown) {
      setError(
        task === null
          ? describeDaemonError(err)
          : `${describeDaemonError(err)} The card "${task.title}" stays in backlog; Start thread tries it again.`,
      );
    } finally {
      setBusy(false);
    }
  };

  return (
    <Dialog
      open={open}
      onClose={busy ? () => undefined : onClose}
      title="New thread">
      <form
        className="flex flex-col gap-4"
        onSubmit={(event) => {
          event.preventDefault();
          void start();
        }}>
        <Field label="What should it do?" htmlFor="new-thread-title">
          <Input
            id="new-thread-title"
            value={title}
            placeholder="Fix the login redirect"
            onChange={(event) => setTitle(event.target.value)}
          />
        </Field>
        <Field
          label="Details"
          htmlFor="new-thread-brief"
          hint="Becomes the card's description — what the agent reads first.">
          <Textarea
            id="new-thread-brief"
            rows={4}
            value={brief}
            onChange={(event) => setBrief(event.target.value)}
          />
        </Field>
        <Field
          label="Project"
          hint="It runs on the project's own agent or team, in a worktree of its own.">
          <Select
            aria-label="Project"
            groups={[
              {
                items: projects.map((row) => ({
                  value: row.id,
                  label: row.name,
                })),
              },
            ]}
            value={projectId}
            placeholder="No projects yet"
            onValueChange={setProjectId}
          />
        </Field>
        {error === null ? null : <ErrorText>{error}</ErrorText>}
        <div className="flex justify-end gap-2">
          <Button
            type="button"
            variant="outline"
            disabled={busy}
            onClick={onClose}>
            Cancel
          </Button>
          <Button
            type="submit"
            disabled={busy || project === null || title.trim() === ''}>
            {busy ? 'Starting…' : 'Start thread'}
          </Button>
        </div>
      </form>
    </Dialog>
  );
}
