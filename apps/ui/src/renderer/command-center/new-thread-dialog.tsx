import { useEffect, useState } from 'react';

import type { CliDetection } from '../../shared/contracts';
import type { ProjectDto, TaskDto } from '../autogenerated';
import { TargetSelect, type TargetTeam } from '../chats/target-select';
import { ErrorText } from '../components/error-text';
import { Field } from '../components/field';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { Select } from '../components/ui/select';
import { Textarea } from '../components/ui/textarea';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import { currentRunSettings } from '../run-settings';
import { startTaskRun } from '../tasks/start-task-run';
import { targetLabel, targetPatch } from '../tasks/task-target';

/**
 * Start a new thread from the command center: a card on the project's board
 * with its own worktree and branch, started at once — the press is the
 * approval. It runs on the agent or team picked here, else the project's own.
 */
export function NewThreadDialog({
  open,
  apis,
  projects,
  initialProjectId,
  onClose,
  onStarted,
}: {
  open: boolean;
  apis: DaemonApis;
  projects: readonly ProjectDto[];
  initialProjectId: string | null;
  onClose: () => void;
  onStarted: (runId: string | null) => void;
}): React.JSX.Element {
  const [title, setTitle] = useState('');
  const [brief, setBrief] = useState('');
  const [projectId, setProjectId] = useState<string | null>(
    initialProjectId ?? projects[0]?.id ?? null,
  );
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [filed, setFiled] = useState<TaskDto | null>(null);
  const [target, setTarget] = useState<string | null>(null);
  const [teams, setTeams] = useState<TargetTeam[]>([]);
  const [cliDetections, setCliDetections] = useState<CliDetection[] | null>(
    null,
  );
  useEffect(() => {
    if (!open) {
      return;
    }
    void apis.teams
      .listTeams()
      .then(setTeams)
      .catch(() => setTeams([]));
    void window.geniro
      .detectClis()
      .then(setCliDetections)
      .catch(() => setCliDetections(null));
  }, [open, apis]);
  const project = projects.find((row) => row.id === projectId) ?? null;

  const start = async (): Promise<void> => {
    if (project === null || title.trim() === '') {
      return;
    }
    setBusy(true);
    setError(null);
    const runsOn = targetPatch(target);
    let task = filed?.projectId === project.id ? filed : null;
    try {
      task ??= await apis.tasks.createTask({
        createTaskDto: {
          projectId: project.id,
          title: title.trim(),
          ...(brief.trim() === '' ? {} : { description: brief.trim() }),
          ...(runsOn.agentKind === null ? {} : { agentKind: runsOn.agentKind }),
          ...(runsOn.teamSlug === null ? {} : { teamSlug: runsOn.teamSlug }),
        },
      });
      setFiled(task);
      const started = await startTaskRun({
        apis,
        bridge: window.geniro,
        readRunSettings: currentRunSettings,
        task,
        project,
      });
      setTitle('');
      setBrief('');
      setFiled(null);
      setTarget(null);
      onStarted(started.runId ?? null);
    } catch (err: unknown) {
      setError(
        task === null
          ? describeDaemonError(err)
          : `${describeDaemonError(err)} The card "${task.title}" stays in backlog; Start thread tries it again.`,
      );
    } finally {
      setBusy(false);
    }
  };

  return (
    <Dialog
      open={open}
      onClose={busy ? () => undefined : onClose}
      title="New thread">
      <form
        className="flex flex-col gap-4"
        onSubmit={(event) => {
          event.preventDefault();
          void start();
        }}>
        <Field label="What should it do?" htmlFor="new-thread-title">
          <Input
            id="new-thread-title"
            value={title}
            placeholder="Fix the login redirect"
            onChange={(event) => setTitle(event.target.value)}
          />
        </Field>
        <Field
          label="Details"
          htmlFor="new-thread-brief"
          hint="Becomes the card's description — what the agent reads first.">
          <Textarea
            id="new-thread-brief"
            rows={4}
            value={brief}
            onChange={(event) => setBrief(event.target.value)}
          />
        </Field>
        <Field
          label="Project"
          hint="It runs in a worktree of its own, on its own branch.">
          <Select
            aria-label="Project"
            groups={[
              {
                items: projects.map((row) => ({
                  value: row.id,
                  label: row.name,
                })),
              },
            ]}
            value={projectId}
            placeholder="No projects yet"
            onValueChange={setProjectId}
          />
        </Field>
        <Field
          label="Runs on"
          hint={
            target === null
              ? "The project's own agent or team, unless you pick one."
              : `Runs on ${targetLabel(target, teams) ?? target}, not the project's default.`
          }>
          <div className="flex items-center gap-2">
            <TargetSelect
              aria-label="Agent or team for the new thread"
              value={target ?? ''}
              teams={teams}
              cliDetections={cliDetections}
              triggerLabel="Project default"
              onChange={setTarget}
            />
            {target === null ? null : (
              <Button
                type="button"
                variant="ghost"
                size="sm"
                onClick={() => setTarget(null)}>
                Use project default
              </Button>
            )}
          </div>
        </Field>
        {error === null ? null : <ErrorText>{error}</ErrorText>}
        <div className="flex justify-end gap-2">
          <Button
            type="button"
            variant="outline"
            disabled={busy}
            onClick={onClose}>
            Cancel
          </Button>
          <Button
            type="submit"
            disabled={busy || project === null || title.trim() === ''}>
            {busy ? 'Starting…' : 'Start thread'}
          </Button>
        </div>
      </form>
    </Dialog>
  );
}
