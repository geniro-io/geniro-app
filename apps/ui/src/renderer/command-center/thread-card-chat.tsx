import { memo, useMemo } from 'react';

import type { DaemonHandle } from '../../shared/contracts';
import type { RunDto } from '../autogenerated';
import { Chats } from '../chats/Chats';
import type { HostedThread } from '../chats/hosted-thread';
import { readRunById } from '../chats/read-run';
import { REMOTE_HISTORY_PAGE } from '../chats/use-chat-run';
import type { ThreadIdentity } from '../components/thread-head';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

/** The existing run a thread's card hosts. */
export async function readRun(
  apis: Pick<DaemonApis, 'chats' | 'teams'>,
  runId: string,
): Promise<RunDto> {
  const run = await readRunById(apis.chats, apis.teams, runId);
  if (run === undefined) {
    throw new Error('This thread no longer exists.');
  }
  return run;
}

export interface ThreadCardChatProps {
  runId: string;
  apis: DaemonApis;
  handle: DaemonHandle;
  client: DaemonClient;
  active: boolean;
  onOpenThread: (runId: string) => void;
  threadIdentities: ReadonlyMap<string, ThreadIdentity>;
}

/**
 * The chat under a thread's card on the canvas: the chat screen itself,
 * hosting that existing run. Kept apart from the card so panning, zooming and
 * resizing the card never draw the chat again.
 */
export const ThreadCardChat = memo(function ThreadCardChat({
  runId,
  apis,
  handle,
  client,
  active,
  onOpenThread,
  threadIdentities,
}: ThreadCardChatProps): React.JSX.Element {
  const open = useLatestCallback(() => readRun(apis, runId), [apis, runId]);
  const hosted = useMemo(
    (): HostedThread => ({
      open,
      queueScope: `command-center-thread:${runId}`,
      hideHeader: true,
      emptyText: 'Nothing has been said in this thread yet.',
      composerLabel: 'Message this thread',
      composerPlaceholder: 'Write to this thread…',
      onOpenThread,
      threadIdentities,
    }),
    [open, runId, onOpenThread, threadIdentities],
  );
  return (
    <Chats
      client={client}
      handle={handle}
      active={active}
      hosted={hosted}
      transcriptPageCap={REMOTE_HISTORY_PAGE}
    />
  );
});
