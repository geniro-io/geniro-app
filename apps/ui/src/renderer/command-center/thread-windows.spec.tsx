const { hostedByScope } = vi.hoisted(() => ({
  hostedByScope: new Map<string, HostedThread>(),
}));
vi.mock('../chats/Chats', async () => {
  const { createElement } = await import('react');
  return {
    Chats: function ChatsStub({
      hosted,
    }: {
      hosted: HostedThread;
    }): React.JSX.Element {
      hostedByScope.set(hosted.queueScope, hosted);
      return createElement('div', {
        'data-slot': 'chats-stub',
        'data-scope': hosted.queueScope,
      });
    },
  };
});

const HANDLE = { host: '127.0.0.1', port: 1, token: 't' } as DaemonHandle;
const CLIENT = {} as DaemonClient;
const BOUNDS = { width: 1200, height: 800 };

const SUBJECTS = new Map<string, ThreadWindowSubject>([
  [
    'run-a',
    {
      title: 'Fix the login redirect',
      project: { name: 'Web', color: 'teal' },
    },
  ],
  ['run-b', { title: 'Rebase billing', project: null }],
]);

function request(runId: string, requestId: string): OpenRequest {
  return {
    runId,
    title: `Thread ${runId}`,
    isTeam: false,
    requestId,
    item: {
      id: `item-${requestId}`,
      runId,
      kind: 'approval_request',
      payload: {
        id: requestId,
        toolName: 'AskUserQuestion',
        questions: [
          {
            question: `Question from ${runId}?`,
            options: [{ label: 'Yes' }, { label: 'No' }],
          },
        ],
      },
    } as unknown as ItemDto,
  };
}

function apisWith(
  chats: Partial<RunDto>[],
  teamRuns: Partial<RunDto>[],
): DaemonApis {
  return {
    chats: { listChats: vi.fn(() => Promise.resolve(chats)) },
    teams: { listTeamRuns: vi.fn(() => Promise.resolve(teamRuns)) },
  } as unknown as DaemonApis;
}

let root: Root;
let container: HTMLDivElement;
let windows: ThreadWindows;

function Harness({
  narrow,
  requests,
  onOpenThread,
}: {
  narrow: boolean;
  requests: readonly OpenRequest[];
  onOpenThread: (runId: string) => void;
}): React.JSX.Element {
  windows = useThreadWindows(narrow);
  return (
    <div className="relative">
      <ThreadWindowsLayer
        windows={windows}
        bounds={BOUNDS}
        narrow={narrow}
        subjects={SUBJECTS}
        requests={requests}
        requestsError={null}
        onAnswer={() => undefined}
        onOpenThread={onOpenThread}
        apis={apisWith([{ id: 'run-a' }], [{ id: 'run-b' }])}
        handle={HANDLE}
        client={CLIENT}
      />
    </div>
  );
}

function draw(over: Partial<React.ComponentProps<typeof Harness>> = {}): void {
  act(() => {
    root.render(
      <Harness
        narrow={false}
        requests={[]}
        onOpenThread={() => undefined}
        {...over}
      />,
    );
  });
}

const windowEls = (): HTMLElement[] =>
  Array.from(
    container.querySelectorAll<HTMLElement>('[data-slot="floating-window"]'),
  );
const titleOf = (el: HTMLElement): string | undefined =>
  el.querySelector<HTMLElement>('[data-slot="thread-window-title"]')?.dataset
    .runId;

beforeAll(() => {
  Element.prototype.scrollIntoView = vi.fn();
});

beforeEach(() => {
  hostedByScope.clear();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('useThreadWindows', () => {
  it('opens several threads side by side, each once, the last opened in front', () => {
    draw();
    act(() => windows.open('run-a', 'thread', BOUNDS));
    act(() => windows.open('run-b', 'thread', BOUNDS));

    expect(windows.windows.map((entry) => entry.runId)).toEqual([
      'run-a',
      'run-b',
    ]);
    expect(windows.windows[0]!.rect).not.toEqual(windows.windows[1]!.rect);

    act(() => windows.open('run-a', 'thread', BOUNDS));
    expect(windows.windows.map((entry) => entry.runId)).toEqual([
      'run-a',
      'run-b',
    ]);
    expect(frontWindow(windows.windows)!.runId).toBe('run-a');
    expect(windowEls()).toHaveLength(2);
  });

  it('brings a window to the front when it is pressed, and drops it when closed', () => {
    draw();
    act(() => windows.open('run-a', 'thread', BOUNDS));
    act(() => windows.open('run-b', 'thread', BOUNDS));

    const [elA, elB] = windowEls();
    expect(Number(elB!.style.zIndex)).toBeGreaterThan(
      Number(elA!.style.zIndex),
    );

    act(() => windows.focus('run-a'));
    expect(frontWindow(windows.windows)!.runId).toBe('run-a');
    expect(windowEls()[0]).toBe(elA);
    expect(windowEls()[1]).toBe(elB);
    expect(Number(elA!.style.zIndex)).toBeGreaterThan(
      Number(elB!.style.zIndex),
    );

    act(() => windows.close('run-a'));
    expect(windows.windows.map((entry) => entry.runId)).toEqual(['run-b']);
  });

  it('closes the window of a thread that left the board, and keeps the rest', () => {
    draw();
    act(() => windows.open('run-a', 'thread', BOUNDS));
    act(() => windows.open('run-b', 'thread', BOUNDS));

    act(() => windows.keepOnly(new Set(['run-b'])));

    expect(windows.windows.map((entry) => entry.runId)).toEqual(['run-b']);
  });

  it('keeps one window on a phone, the one opened last, full screen', () => {
    draw({ narrow: true });
    act(() => windows.open('run-a', 'thread', BOUNDS));
    act(() => windows.open('run-b', 'answer', BOUNDS));

    expect(windows.windows.map((entry) => entry.runId)).toEqual(['run-b']);
    expect(windowEls()).toHaveLength(1);
    expect(
      windowEls()[0]!.querySelector('[data-slot="floating-window-resize"]'),
    ).toBeNull();
  });
});

describe('ThreadWindowsLayer', () => {
  it('hosts the existing run in a thread window, read by its id', async () => {
    draw();
    act(() => windows.open('run-a', 'thread', BOUNDS));

    const hosted = hostedByScope.get('command-center-thread:run-a')!;
    await expect(hosted.open()).resolves.toEqual({ id: 'run-a' });
  });

  it('draws a thread window as the chat screen itself, hosting the existing run under a queue of its own', () => {
    draw();
    act(() => windows.open('run-a', 'thread', BOUNDS));

    const stub = windowEls()[0]!.querySelector<HTMLElement>(
      '[data-slot="chats-stub"]',
    )!;
    expect(stub.dataset.scope).toBe('command-center-thread:run-a');
    expect(titleOf(windowEls()[0]!)).toBe('run-a');
    expect(
      windowEls()[0]!.querySelector('[data-slot="thread-window-title"]')!
        .textContent,
    ).toContain('Fix the login redirect');
    expect(
      windowEls()[0]!
        .querySelector('[data-slot="thread-window-title"] [data-color]')!
        .getAttribute('data-color'),
    ).toBe('teal');
  });

  it('answers a thread on the graph: its own waiting cards only, then the live thread on Show thread', () => {
    draw({ requests: [request('run-a', 'q-a'), request('run-b', 'q-b')] });
    act(() => windows.open('run-a', 'answer', BOUNDS));

    const panel = windowEls()[0]!;
    expect(
      Array.from(
        panel.querySelectorAll<HTMLElement>('[data-slot="needs-you-request"]'),
      ).map((entry) => entry.dataset.runId),
    ).toEqual(['run-a']);
    expect(panel.textContent).toContain('Question from run-a?');
    expect(panel.querySelector('[data-slot="chats-stub"]')).toBeNull();

    act(() =>
      panel
        .querySelector<HTMLButtonElement>(
          '[data-slot="thread-window-show-thread"]',
        )!
        .click(),
    );

    expect(windows.windows[0]!.mode).toBe('thread');
    expect(
      windowEls()[0]!.querySelector('[data-slot="chats-stub"]'),
    ).not.toBeNull();
    expect(
      windowEls()[0]!.querySelector('[data-slot="needs-you-request"]'),
    ).toBeNull();
  });

  it('shows the live thread once nothing is left to answer in it', () => {
    draw({ requests: [request('run-a', 'q-a')] });
    act(() => windows.open('run-a', 'answer', BOUNDS));
    expect(
      windowEls()[0]!.querySelector('[data-slot="needs-you-request"]'),
    ).not.toBeNull();

    draw({ requests: [] });

    expect(
      windowEls()[0]!.querySelector('[data-slot="chats-stub"]'),
    ).not.toBeNull();
    expect(
      windowEls()[0]!.querySelector('[data-slot="thread-window-show-thread"]'),
    ).toBeNull();
  });

  it('goes to the thread in Chats from the window’s header', () => {
    const onOpenThread = vi.fn();
    draw({ onOpenThread });
    act(() => windows.open('run-b', 'thread', BOUNDS));

    act(() =>
      windowEls()[0]!
        .querySelector<HTMLButtonElement>('[data-slot="thread-window-go"]')!
        .click(),
    );

    expect(onOpenThread).toHaveBeenCalledWith('run-b');
  });
});

describe('readRun', () => {
  it('reads a plain chat and a team run alike, by id, from the listings', async () => {
    const apis = apisWith(
      [{ id: 'chat-1' }],
      [{ id: 'team-1' }, { id: 'team-2' }],
    );

    await expect(readRun(apis, 'team-2')).resolves.toEqual({ id: 'team-2' });
    await expect(readRun(apis, 'chat-1')).resolves.toEqual({ id: 'chat-1' });
    expect(apis.chats.listChats).toHaveBeenCalledWith({
      scope: 'all',
      runId: 'team-2',
    });
    expect(apis.teams.listTeamRuns).toHaveBeenCalledWith({
      scope: 'all',
      runId: 'team-2',
    });
  });

  it('fails plainly for a thread that no longer exists', async () => {
    await expect(readRun(apisWith([], []), 'gone')).rejects.toThrow(
      'This thread no longer exists.',
    );
  });
});
