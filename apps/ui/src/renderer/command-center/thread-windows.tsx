export interface ThreadWindow {
  runId: string;
  rect: FloatingRect;
  /** Higher stands in front; the windows themselves keep the order they opened in. */
  layer: number;
}

export interface ThreadWindows {
  /** In the order they opened, which never changes, so raising one moves no DOM node. */
  windows: readonly ThreadWindow[];
  open: (runId: string, bounds: FloatingBounds) => void;
  close: (runId: string) => void;
  focus: (runId: string) => void;
  move: (runId: string, rect: FloatingRect) => void;
  /** Close every window whose thread is no longer on the board. */
  keepOnly: (runIds: ReadonlySet<string>) => void;
}

function topLayer(rows: readonly ThreadWindow[]): number {
  return rows.reduce((top, row) => Math.max(top, row.layer), 0);
}

/** The window standing in front, or null when none is open. */
export function frontWindow(
  rows: readonly ThreadWindow[],
): ThreadWindow | null {
  return rows.reduce<ThreadWindow | null>(
    (front, row) => (front === null || row.layer > front.layer ? row : front),
    null,
  );
}

function raise(
  rows: readonly ThreadWindow[],
  runId: string,
): readonly ThreadWindow[] {
  if (
    !rows.some((entry) => entry.runId === runId) ||
    frontWindow(rows)?.runId === runId
  ) {
    return rows;
  }
  const layer = topLayer(rows) + 1;
  return rows.map((entry) =>
    entry.runId === runId ? { ...entry, layer } : entry,
  );
}

/** The thread windows open over the command center's graph; on a phone only the one opened last. */
export function useThreadWindows(narrow: boolean): ThreadWindows {
  const [windows, setWindows] = useState<readonly ThreadWindow[]>([]);
  const open = useLatestCallback(
    (runId: string, bounds: FloatingBounds): void =>
      setWindows((rows) => {
        if (rows.some((entry) => entry.runId === runId)) {
          return raise(
            narrow ? rows.filter((entry) => entry.runId === runId) : rows,
            runId,
          );
        }
        const kept = narrow ? [] : rows;
        return [
          ...kept,
          {
            runId,
            rect: cascadeRect(kept.length, bounds),
            layer: topLayer(kept) + 1,
          },
        ];
      }),
    [narrow],
  );
  const close = useLatestCallback(
    (runId: string): void =>
      setWindows((rows) => rows.filter((entry) => entry.runId !== runId)),
    [],
  );
  const focus = useLatestCallback(
    (runId: string): void => setWindows((rows) => raise(rows, runId)),
    [],
  );
  const move = useLatestCallback(
    (runId: string, rect: FloatingRect): void =>
      setWindows((rows) =>
        rows.map((entry) =>
          entry.runId === runId ? { ...entry, rect } : entry,
        ),
      ),
    [],
  );
  const keepOnly = useLatestCallback(
    (runIds: ReadonlySet<string>): void =>
      setWindows((rows) =>
        rows.every((entry) => runIds.has(entry.runId))
          ? rows
          : rows.filter((entry) => runIds.has(entry.runId)),
      ),
    [],
  );
  return { windows, open, close, focus, move, keepOnly };
}

/** A thread as its window's header names it. */
export interface ThreadWindowSubject {
  title: string;
  project: { name: string; color: ProfileColor | null } | null;
}

const WINDOW_Z_BASE = 20;

/** The existing run a thread window hosts. */
export async function readRun(
  apis: Pick<DaemonApis, 'chats' | 'teams'>,
  runId: string,
): Promise<RunDto> {
  const run = await readRunById(apis.chats, apis.teams, runId);
  if (run === undefined) {
    throw new Error('This thread no longer exists.');
  }
  return run;
}

function ThreadWindowChat({
  runId,
  apis,
  handle,
  client,
  active,
  onOpenThread,
}: {
  runId: string;
  apis: DaemonApis;
  handle: DaemonHandle;
  client: DaemonClient;
  active: boolean;
  onOpenThread: (runId: string) => void;
}): React.JSX.Element {
  const open = useLatestCallback(() => readRun(apis, runId), [apis, runId]);
  const hosted = useMemo(
    (): HostedThread => ({
      open,
      queueScope: `command-center-thread:${runId}`,
      emptyText: 'Nothing has been said in this thread yet.',
      composerLabel: 'Message this thread',
      composerPlaceholder: 'Write to this thread…',
      onOpenThread,
    }),
    [open, runId, onOpenThread],
  );
  return (
    <Chats client={client} handle={handle} active={active} hosted={hosted} />
  );
}

export interface ThreadWindowsLayerProps {
  windows: ThreadWindows;
  bounds: FloatingBounds;
  narrow: boolean;
  subjects: ReadonlyMap<string, ThreadWindowSubject>;
  onOpenThread: (runId: string) => void;
  apis: DaemonApis;
  handle: DaemonHandle;
  client: DaemonClient;
  active: boolean;
}

/**
 * The windows over the command center's graph, each one a thread drawn by the
 * chat screen itself, so several threads are read and written to side by side
 * without leaving the graph.
 */
export function ThreadWindowsLayer({
  windows,
  bounds,
  narrow,
  subjects,
  onOpenThread,
  apis,
  handle,
  client,
  active,
}: ThreadWindowsLayerProps): React.JSX.Element | null {
  const front = frontWindow(windows.windows);
  const shown = narrow && front !== null ? [front] : windows.windows;
  if (shown.length === 0) {
    return null;
  }
  const stack = [...shown].sort((a, b) => a.layer - b.layer);
  return (
    <div
      data-slot="command-center-windows"
      className="pointer-events-none absolute inset-0 z-20 overflow-hidden">
      {shown.map((entry) => {
        const subject = subjects.get(entry.runId);
        const title = subject?.title ?? 'Thread';
        return (
          <FloatingWindow
            key={entry.runId}
            label={title}
            className="pointer-events-auto"
            rect={entry.rect}
            bounds={bounds}
            zIndex={WINDOW_Z_BASE + stack.indexOf(entry)}
            fullScreen={narrow}
            onFocus={() => windows.focus(entry.runId)}
            onRectChange={(rect) => windows.move(entry.runId, rect)}
            onClose={() => windows.close(entry.runId)}
            title={
              <span
                data-slot="thread-window-title"
                data-run-id={entry.runId}
                title={
                  subject?.project == null
                    ? title
                    : `${title} · Project ${subject.project.name}`
                }
                className="flex min-w-0 items-center gap-2">
                {subject?.project?.color == null ? null : (
                  <PaletteDot color={subject.project.color} size="md" />
                )}
                <span className="min-w-0 truncate text-sm font-semibold">
                  {title}
                </span>
              </span>
            }
            actions={
              <Button
                type="button"
                variant="ghost"
                size="icon"
                data-slot="thread-window-go"
                className="size-6"
                aria-label={`Go to ${title}`}
                title="Go to the thread in Chats"
                onClick={() => onOpenThread(entry.runId)}>
                <ArrowUpRight aria-hidden="true" className="size-3.5" />
              </Button>
            }>
            <ThreadWindowChat
              runId={entry.runId}
              apis={apis}
              handle={handle}
              client={client}
              active={active}
              onOpenThread={onOpenThread}
            />
          </FloatingWindow>
        );
      })}
    </div>
  );
}
