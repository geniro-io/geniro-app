export type TimelineEvent = CommandCenterTimelineEvent;
export type TimelineEventKind = CommandCenterTimelineKind;

const OUTCOME_FAILURE = /fail|error|cancel|abort/i;

type TimelineTone =
  'primary' | 'success' | 'warning' | 'destructive' | 'accent' | 'muted';

const timelineToneVariants = cva(
  'relative z-[1] flex size-6 shrink-0 items-center justify-center rounded-pill ring-4 ring-card',
  {
    variants: {
      tone: {
        primary: 'bg-primary/10 text-primary',
        success: 'bg-success/10 text-success',
        warning: 'bg-warning/10 text-warning',
        destructive: 'bg-destructive/10 text-destructive',
        accent: 'bg-accent text-accent-foreground',
        muted: 'bg-muted text-muted-foreground',
      } satisfies Record<TimelineTone, string>,
    },
  },
);

const KIND_META: Record<
  TimelineEventKind,
  { icon: LucideIcon; tone: TimelineTone }
> = {
  user_message: { icon: MessageSquare, tone: 'primary' },
  manager_message: { icon: Send, tone: 'primary' },
  thread_message: { icon: Inbox, tone: 'muted' },
  thread_started: { icon: Play, tone: 'success' },
  start_requested: { icon: Rocket, tone: 'accent' },
  pull_request: { icon: GitPullRequest, tone: 'success' },
  question: { icon: CircleHelp, tone: 'warning' },
  approval: { icon: ShieldAlert, tone: 'warning' },
  stage: { icon: Milestone, tone: 'muted' },
  outcome: { icon: Flag, tone: 'success' },
  failed: { icon: CircleX, tone: 'destructive' },
};

function toneOf(event: TimelineEvent): TimelineTone {
  if (event.kind === 'outcome') {
    return event.detail !== null && OUTCOME_FAILURE.test(event.detail)
      ? 'destructive'
      : 'success';
  }
  return KIND_META[event.kind].tone;
}

interface Sentence {
  before: string;
  named: boolean;
  after: string;
}

function sentenceOf(event: TimelineEvent): Sentence {
  switch (event.kind) {
    case 'user_message':
      return { before: 'You wrote', named: false, after: '' };
    case 'manager_message':
      return { before: 'Manager →', named: true, after: '' };
    case 'thread_message':
      return { before: '', named: true, after: 'replied' };
    case 'thread_started':
      return { before: '', named: true, after: 'started' };
    case 'start_requested':
      return { before: '', named: true, after: 'Start requested' };
    case 'pull_request':
      return {
        before: '',
        named: true,
        after:
          event.detail === null ? 'opened a PR' : `opened PR #${event.detail}`,
      };
    case 'question':
      return { before: '', named: true, after: 'asked a question' };
    case 'approval':
      return { before: '', named: true, after: 'needs approval' };
    case 'stage':
      return {
        before: '',
        named: true,
        after:
          event.detail === null ? 'stage changed' : `stage: ${event.detail}`,
      };
    case 'outcome':
      return {
        before: '',
        named: true,
        after:
          event.detail === null ? 'finished' : `finished · ${event.detail}`,
      };
    case 'failed':
      return { before: '', named: true, after: 'failed' };
  }
}

function dayStamp(date: Date): string {
  return `${date.getFullYear()}-${date.getMonth()}-${date.getDate()}`;
}

function dayLabel(day: Date, now: Date): string {
  const yesterday = new Date(now);
  yesterday.setDate(now.getDate() - 1);
  const stamp = dayStamp(day);
  if (stamp === dayStamp(now)) {
    return 'Today';
  }
  if (stamp === dayStamp(yesterday)) {
    return 'Yesterday';
  }
  return day.toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    ...(day.getFullYear() === now.getFullYear() ? {} : { year: 'numeric' }),
  });
}

export interface TimelineDay {
  key: string;
  label: string;
  events: TimelineEvent[];
}

export function groupTimelineDays(
  events: readonly TimelineEvent[],
  now: number,
): TimelineDay[] {
  const nowDate = new Date(now);
  const days = new Map<string, TimelineDay>();
  for (const event of events) {
    const at = new Date(event.at);
    const key = dayStamp(at);
    const day = days.get(key) ?? {
      key,
      label: dayLabel(at, nowDate),
      events: [],
    };
    day.events.push(event);
    days.set(key, day);
  }
  return [...days.values()];
}

export interface TimelinePanelProps {
  events: readonly TimelineEvent[];
  loading: boolean;
  error: string | null;
  hasMore: boolean;
  onLoadOlder: () => void;
  /** Open the row's thread as its card on the canvas. */
  onShowThread: (runId: string) => void;
  /** Answer the row's still-open question in a popover hung from its Reply button. */
  onReply: (runId: string, anchor: HTMLElement, title: string | null) => void;
  /** The item ids of the questions and approvals a thread still waits on. */
  openItemIds: ReadonlySet<string>;
  now: number;
  className?: string;
}

/** Whether the event is a question or approval its thread still waits on. */
export function isAnswerable(
  event: TimelineEvent,
  openItemIds: ReadonlySet<string>,
): boolean {
  return (
    (event.kind === 'question' || event.kind === 'approval') &&
    openItemIds.has(event.id.slice(event.kind.length + 1))
  );
}

function RowActions({
  event,
  answerable,
  onReply,
}: {
  event: TimelineEvent;
  answerable: boolean;
  onReply: TimelinePanelProps['onReply'];
}): React.JSX.Element | null {
  const runId = event.threadRunId;
  const archive = useThreadArchive(event.kind === 'outcome' ? runId : null);
  const title = event.threadTitle ?? 'Untitled thread';
  if (runId === null || (!answerable && archive === null)) {
    return null;
  }
  return (
    <span className="flex shrink-0 items-center">
      {answerable ? (
        <ThreadActionButton
          slot="timeline-event-reply"
          label={`Reply to ${title}`}
          title="Answer this here"
          icon={<Reply aria-hidden="true" />}
          onClick={(anchor) => onReply(runId, anchor, event.threadTitle)}>
          Reply
        </ThreadActionButton>
      ) : null}
      {archive === null ? null : (
        <ArchiveThreadButton
          slot="timeline-event-archive"
          title={title}
          onArchive={archive}
        />
      )}
    </span>
  );
}

function RowBody({
  event,
  actions,
}: {
  event: TimelineEvent;
  actions: React.ReactNode;
}): React.JSX.Element {
  const Icon = KIND_META[event.kind].icon;
  const sentence = sentenceOf(event);
  const awaiting = event.kind === 'manager_message' && event.awaitingReply;
  const title = event.threadTitle ?? 'Untitled thread';
  return (
    <>
      <span
        aria-hidden="true"
        className={timelineToneVariants({ tone: toneOf(event) })}>
        <Icon className="size-3.5" />
      </span>
      <div className="min-w-0 flex-1">
        <div className="flex min-w-0 items-center gap-2">
          <p className="flex min-w-0 flex-1 items-baseline gap-1.5 text-sm leading-6">
            {sentence.before === '' ? null : (
              <span className="shrink-0 whitespace-nowrap">
                {sentence.before}
              </span>
            )}
            {sentence.named ? (
              <span
                data-slot="timeline-thread-title"
                title={title}
                className="min-w-0 truncate font-medium">
                {title}
              </span>
            ) : null}
            {sentence.after === '' ? null : (
              <span className="shrink-0 whitespace-nowrap text-muted-foreground">
                {sentence.after}
              </span>
            )}
          </p>
          {awaiting ? (
            <Badge
              variant="warning"
              className="shrink-0 px-1.5 py-0 text-[11px] font-normal">
              awaiting reply
            </Badge>
          ) : null}
          <time
            dateTime={event.at}
            className="shrink-0 text-xs leading-6 tabular-nums text-muted-foreground">
            {formatClockTime(event.at)}
          </time>
        </div>
        {event.text === null ? null : (
          <p className="mt-0.5 line-clamp-2 text-sm leading-5 break-words text-muted-foreground">
            {event.text}
          </p>
        )}
        {actions}
      </div>
    </>
  );
}

const ROW_CLASS =
  'gap-3 rounded-md px-2 py-1.5 before:absolute before:top-0 before:bottom-0 before:left-5 before:w-px before:bg-border first:before:top-3 last:before:bottom-auto last:before:h-3';

function TimelineRow({
  event,
  answerable,
  onShowThread,
  onReply,
}: {
  event: TimelineEvent;
  answerable: boolean;
  onShowThread: (runId: string) => void;
  onReply: TimelinePanelProps['onReply'];
}): React.JSX.Element {
  const runId = event.threadRunId;
  const actions = (
    <RowActions event={event} answerable={answerable} onReply={onReply} />
  );
  if (runId === null) {
    return (
      <li
        data-slot="timeline-event"
        data-kind={event.kind}
        className={cn('relative flex items-start', ROW_CLASS)}>
        <RowBody event={event} actions={actions} />
      </li>
    );
  }
  return (
    <NavListItem
      active={false}
      activateLabel={`Show ${event.threadTitle ?? 'Untitled thread'} on the canvas`}
      onActivate={() => onShowThread(runId)}
      className={cn('flex-row items-start', ROW_CLASS)}
      contentClassName="flex-1 flex-row items-start gap-3"
      data={{ 'data-slot': 'timeline-event', 'data-kind': event.kind }}>
      <RowBody event={event} actions={actions} />
    </NavListItem>
  );
}

export function TimelinePanel({
  events,
  loading,
  error,
  hasMore,
  onLoadOlder,
  onShowThread,
  onReply,
  openItemIds,
  now,
  className,
}: TimelinePanelProps): React.JSX.Element {
  const days = useMemo(() => groupTimelineDays(events, now), [events, now]);
  const initialLoad = loading && events.length === 0;
  const showEmpty = days.length === 0 && !initialLoad && error === null;
  const showLoadOlder = hasMore && !initialLoad;

  return (
    <section
      aria-label="Timeline"
      data-slot="command-center-timeline"
      className={cn(
        'flex min-h-0 w-full flex-1 flex-col bg-card text-card-foreground',
        className,
      )}>
      {error === null ? null : (
        <ErrorText className="mx-4 mb-2 shrink-0 rounded-md bg-destructive/10 px-3 py-2 text-sm">
          {error}
        </ErrorText>
      )}
      <div className="min-h-0 flex-1 overflow-y-auto px-4 pt-3 pb-4">
        {initialLoad ? (
          <div className="flex items-center justify-center gap-2 py-12 text-sm text-muted-foreground">
            <Spinner className="size-4" />
            Loading the timeline
          </div>
        ) : null}
        {showEmpty ? (
          <EmptyState icon={<Clock />}>Nothing here yet</EmptyState>
        ) : null}
        {days.length === 0 ? null : (
          <ol data-slot="timeline-days" className="flex flex-col gap-5">
            {days.map((day) => (
              <li key={day.key} className="flex flex-col gap-3">
                <h3 className="sticky top-0 z-[2] -mx-4 bg-card/95 px-4 py-1 text-xs font-semibold tracking-wide text-muted-foreground uppercase backdrop-blur-sm">
                  {day.label}
                </h3>
                <ol className="-mx-2 flex flex-col">
                  {day.events.map((event) => (
                    <TimelineRow
                      key={event.id}
                      event={event}
                      answerable={isAnswerable(event, openItemIds)}
                      onShowThread={onShowThread}
                      onReply={onReply}
                    />
                  ))}
                </ol>
              </li>
            ))}
          </ol>
        )}
        {showLoadOlder ? (
          <div className="flex justify-center pt-3">
            <Button
              type="button"
              variant="ghost"
              size="sm"
              data-slot="timeline-load-older"
              disabled={loading}
              onClick={onLoadOlder}>
              {loading ? <Spinner /> : null}
              Load older
            </Button>
          </div>
        ) : null}
      </div>
    </section>
  );
}
