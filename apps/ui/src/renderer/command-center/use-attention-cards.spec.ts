import { describe, expect, it } from 'vitest';

import { boardCard } from '../__fixtures__/board-cards';
import {
  approvalRequest,
  questionRequest,
} from '../__fixtures__/open-requests';
import type { SettingsNotice } from '../autogenerated';
import type { SettingsNoticesStore } from '../chats/settings-notices-context';
import type { ThreadDoneDismissals } from '../chats/thread-done-context';
import type { WaitingItemsStore } from '../chats/waiting-items-context';
import {
  attentionCardsOf,
  attentionCountsOf,
  type AttentionSources,
  attentionSplitText,
} from './use-attention-cards';

function notice(
  id: string,
  over: Partial<SettingsNotice> = {},
): SettingsNotice {
  return {
    id,
    kind: 'agent-updates',
    key: 'agent-updates:claude',
    items: ['claude@1.5.0'],
    label: null,
    openedAt: '2026-11-27T09:00:00.000Z',
    resolvedAt: null,
    dismissedAt: null,
    ...over,
  };
}

const NOTICE = notice('n1');

/** The manager's notices with the live readings their cards draw from: claude has an update. */
function noticeStore(
  notices: readonly SettingsNotice[] | null,
  updateAvailable = true,
): SettingsNoticesStore {
  return {
    notices: notices === null ? null : new Map(notices.map((n) => [n.id, n])),
    login: { starting: null, login: null },
    detections: [
      {
        kind: 'claude',
        found: true,
        version: '1.4.0',
        update: { available: updateAvailable, latestVersion: '1.5.0' },
      },
    ],
  } as unknown as SettingsNoticesStore;
}

function doneDismissals(
  finishes: ReadonlyMap<string, string | null> = new Map(),
): ThreadDoneDismissals {
  return { through: new Map(), finishes, dismiss: () => undefined };
}

function waiting(memoryAt: string): WaitingItemsStore {
  return {
    memories: new Map([['m1', { id: 'm1', updatedAt: memoryAt }]]),
    lessons: new Map(),
    knowledge: new Map(),
  } as unknown as WaitingItemsStore;
}

function sources(over: Partial<AttentionSources> = {}): AttentionSources {
  return {
    requests: [],
    boardCards: [],
    waiting: null,
    notices: noticeStore([]),
    doneDismissals: doneDismissals(),
    ...over,
  };
}

const kinds = (s: AttentionSources): string[] =>
  attentionCardsOf(s).map((card) => card.kind);

describe('attentionCardsOf', () => {
  it('orders questions and approvals, failed, finished, reviews, then notices', () => {
    const cards = attentionCardsOf(
      sources({
        requests: [approvalRequest('a', 'a-1'), questionRequest('q', 'q-1')],
        boardCards: [
          boardCard('done', { column: 'done' }),
          boardCard('broken', { status: 'failed' }),
          boardCard('busy', { column: 'working' }),
        ],
        waiting: waiting('2026-11-27T08:00:00.000Z'),
        notices: noticeStore([NOTICE]),
      }),
    );

    expect(cards.map((card) => card.kind)).toEqual([
      'approval',
      'question',
      'failed',
      'finished',
      'review',
      'notice',
    ]);
  });

  it('puts the oldest first inside a group', () => {
    const cards = attentionCardsOf(
      sources({
        boardCards: [
          boardCard('newer', {
            column: 'done',
            lastActivityAt: '2026-11-27T12:00:00.000Z',
          }),
          boardCard('older', {
            column: 'done',
            lastActivityAt: '2026-11-27T08:00:00.000Z',
          }),
        ],
      }),
    );

    expect(cards.map((card) => card.key)).toEqual([
      'finished:older',
      'finished:newer',
    ]);
  });

  it("keeps a finished thread's card key when its finish is read again under a new key", () => {
    const keyOf = (finishKey: string): string | undefined =>
      attentionCardsOf(
        sources({
          boardCards: [boardCard('t1', { column: 'done', finishKey })],
        }),
      )[0]?.key;

    expect(keyOf('second')).toBe(keyOf('first'));
  });

  it('leaves out a finished thread whose finish was dismissed, and shows a new finish again', () => {
    const dismissed = doneDismissals(new Map([['t1', 'first']]));

    expect(
      kinds(
        sources({
          boardCards: [boardCard('t1', { column: 'done', finishKey: 'first' })],
          doneDismissals: dismissed,
        }),
      ),
    ).toEqual([]);
    expect(
      kinds(
        sources({
          boardCards: [
            boardCard('t1', { column: 'done', finishKey: 'second' }),
          ],
          doneDismissals: dismissed,
        }),
      ),
    ).toEqual(['finished']);
  });

  it('leaves out a notice dismissed or resolved on any device', () => {
    expect(
      kinds(
        sources({
          notices: noticeStore([
            notice('n1', { dismissedAt: '2026-11-27T11:00:00.000Z' }),
            notice('n2', { resolvedAt: '2026-11-27T11:00:00.000Z' }),
          ]),
        }),
      ),
    ).toEqual([]);
  });

  it('leaves out an open notice while its card would draw nothing: the live reading says nothing waits', () => {
    expect(kinds(sources({ notices: noticeStore([NOTICE], false) }))).toEqual(
      [],
    );
  });

  it('puts the oldest notice first, keyed by its notice', () => {
    const cards = attentionCardsOf(
      sources({
        notices: noticeStore([
          notice('newer', { openedAt: '2026-11-27T12:00:00.000Z' }),
          notice('older', { openedAt: '2026-11-27T08:00:00.000Z' }),
        ]),
      }),
    );

    expect(cards.map((card) => card.key)).toEqual([
      'notice:older',
      'notice:newer',
    ]);
  });

  it("shows no finished thread or notice before the manager's notices first answered", () => {
    expect(
      kinds(
        sources({
          boardCards: [boardCard('t1', { column: 'done' })],
          notices: noticeStore(null),
        }),
      ),
    ).toEqual([]);
  });

  it('draws a failed thread once, never also as finished', () => {
    const cards = attentionCardsOf(
      sources({
        boardCards: [boardCard('t1', { column: 'done', status: 'failed' })],
      }),
    );

    expect(cards).toHaveLength(1);
    expect(cards[0]!.kind).toBe('failed');
  });

  it('draws one card per open request, never a second for its thread', () => {
    expect(
      attentionCardsOf(
        sources({
          requests: [questionRequest('q', 'q-1'), questionRequest('q', 'q-2')],
        }),
      ).map((card) => card.key),
    ).toEqual(['request:q:q-1', 'request:q:q-2']);
  });
});

describe('attentionCountsOf', () => {
  it('splits the total into questions, finished, approvals and other', () => {
    const counts = attentionCountsOf(
      attentionCardsOf(
        sources({
          requests: [questionRequest('q', 'q-1'), approvalRequest('a', 'a-1')],
          boardCards: [
            boardCard('done', { column: 'done' }),
            boardCard('broken', { status: 'failed' }),
          ],
          waiting: waiting('2026-11-27T08:00:00.000Z'),
          notices: noticeStore([NOTICE]),
        }),
      ),
    );

    expect(counts).toEqual({
      total: 6,
      questions: 1,
      finished: 1,
      approvals: 2,
      other: 2,
    });
    expect(attentionSplitText(counts)).toBe(
      '1 question · 1 finished · 2 approvals · 2 other',
    );
  });

  it('names nothing when nothing waits', () => {
    expect(attentionSplitText(attentionCountsOf([]))).toBe('');
  });
});
