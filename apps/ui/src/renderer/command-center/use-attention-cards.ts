import { useMemo } from 'react';

import type { CommandCenterCard, SettingsNotice } from '../autogenerated';
import { settingsNoticeView } from '../chats/settings-attention-cards';
import type { SettingsNoticesStore } from '../chats/settings-notices-context';
import {
  isFinishDismissed,
  type ThreadDoneDismissals,
} from '../chats/thread-done-context';
import type { WaitingItemsStore } from '../chats/waiting-items-context';
import { askKindOf, type OpenRequest } from './use-open-requests';

export type ReviewKind = 'memory' | 'lesson' | 'knowledge';

interface CardBase {
  /** Stable across reads: the gallery keeps the card in view by it. */
  key: string;
  /** When it began to wait, oldest first within its group; null keeps the source's own order. */
  at: string | null;
}

export type AttentionCard =
  | (CardBase & { kind: 'question' | 'approval'; request: OpenRequest })
  | (CardBase & { kind: 'failed'; card: CommandCenterCard })
  | (CardBase & { kind: 'finished'; card: CommandCenterCard })
  | (CardBase & { kind: 'review'; review: ReviewKind; id: string })
  | (CardBase & { kind: 'notice'; notice: SettingsNotice });

export type AttentionKind = AttentionCard['kind'];

/** How many cards wait, split the way the header's tooltip and the gallery's head name them. */
export interface AttentionCounts {
  total: number;
  questions: number;
  finished: number;
  /** Tool approvals and memory, lesson and knowledge reviews. */
  approvals: number;
  /** Failed threads and Settings notices. */
  other: number;
}

const GROUP: Record<AttentionKind, number> = {
  question: 0,
  approval: 0,
  failed: 1,
  finished: 2,
  review: 3,
  notice: 4,
};

export interface AttentionSources {
  requests: readonly OpenRequest[];
  boardCards: readonly CommandCenterCard[] | null;
  waiting: WaitingItemsStore | null;
  /** The manager chat's notices with the live readings their cards draw from. */
  notices: SettingsNoticesStore;
  /** How far the user dismissed each thread's finish. */
  doneDismissals: ThreadDoneDismissals;
}

function threadAt(card: CommandCenterCard): string {
  return card.run.lastActivityAt ?? card.run.createdAt;
}

function reviewCards(waiting: WaitingItemsStore | null): AttentionCard[] {
  if (waiting === null) {
    return [];
  }
  return [
    ...[...(waiting.memories?.values() ?? [])].map((entry): AttentionCard => ({
      key: `review:memory:${entry.id}`,
      at: entry.updatedAt,
      kind: 'review',
      review: 'memory',
      id: entry.id,
    })),
    ...[...(waiting.lessons?.values() ?? [])].map((lesson): AttentionCard => ({
      key: `review:lesson:${lesson.id}`,
      at: lesson.createdAt,
      kind: 'review',
      review: 'lesson',
      id: lesson.id,
    })),
    ...[...(waiting.knowledge?.values() ?? [])].map(
      (revision): AttentionCard => ({
        key: `review:knowledge:${revision.id}`,
        at: revision.createdAt,
        kind: 'review',
        review: 'knowledge',
        id: revision.id,
      }),
    ),
  ];
}

function noticeRowOf(notice: SettingsNotice) {
  return { noticeId: notice.id, kind: notice.kind, key: notice.key };
}

/**
 * Every card that waits on the user, in the gallery's order: questions and tool
 * approvals, failed threads, finished threads, reviews, then Settings notices;
 * oldest first inside each group. A finish or a notice the user dismissed on
 * any device is left out, and both wait for the manager's notices to be first
 * read, so a dismissed card never flashes in; a notice whose card would draw
 * nothing right now is left out too.
 */
export function attentionCardsOf({
  requests,
  boardCards,
  waiting,
  notices,
  doneDismissals,
}: AttentionSources): AttentionCard[] {
  const dismissalsKnown = notices.notices !== null;
  const cards: AttentionCard[] = requests.map((request) => ({
    key: `request:${request.runId}:${request.requestId}`,
    at: request.item.createdAt,
    kind: askKindOf(request),
    request,
  }));
  for (const card of boardCards ?? []) {
    if (card.run.status === 'failed') {
      cards.push({
        key: `failed:${card.run.id}`,
        at: threadAt(card),
        kind: 'failed',
        card,
      });
      continue;
    }
    if (
      card.column !== 'done' ||
      card.finishKey === null ||
      card.finishKey === undefined ||
      !dismissalsKnown ||
      isFinishDismissed(doneDismissals, card.run.id, card.finishKey)
    ) {
      continue;
    }
    cards.push({
      key: `finished:${card.run.id}`,
      at: threadAt(card),
      kind: 'finished',
      card,
    });
  }
  cards.push(...reviewCards(waiting));
  for (const notice of notices.notices?.values() ?? []) {
    if (settingsNoticeView(notices, noticeRowOf(notice)) !== null) {
      cards.push({
        key: `notice:${notice.id}`,
        at: notice.openedAt,
        kind: 'notice',
        notice,
      });
    }
  }
  return cards
    .map((card, index) => ({ card, index }))
    .sort(
      (a, b) =>
        GROUP[a.card.kind] - GROUP[b.card.kind] ||
        (a.card.at ?? '').localeCompare(b.card.at ?? '') ||
        a.index - b.index,
    )
    .map(({ card }) => card);
}

export function attentionCountsOf(
  cards: readonly AttentionCard[],
): AttentionCounts {
  const counts: AttentionCounts = {
    total: cards.length,
    questions: 0,
    finished: 0,
    approvals: 0,
    other: 0,
  };
  for (const card of cards) {
    switch (card.kind) {
      case 'question':
        counts.questions += 1;
        break;
      case 'finished':
        counts.finished += 1;
        break;
      case 'approval':
      case 'review':
        counts.approvals += 1;
        break;
      case 'failed':
      case 'notice':
        counts.other += 1;
        break;
    }
  }
  return counts;
}

/** The split in words: "2 questions · 1 finished · 3 other", only the kinds that wait. */
export function attentionSplitText(counts: AttentionCounts): string {
  const parts: string[] = [];
  const add = (count: number, one: string, many: string): void => {
    if (count > 0) {
      parts.push(`${count} ${count === 1 ? one : many}`);
    }
  };
  add(counts.questions, 'question', 'questions');
  add(counts.finished, 'finished', 'finished');
  add(counts.approvals, 'approval', 'approvals');
  add(counts.other, 'other', 'other');
  return parts.join(' · ');
}

export function useAttentionCards(sources: AttentionSources): {
  cards: AttentionCard[];
  counts: AttentionCounts;
} {
  const { requests, boardCards, waiting, notices, doneDismissals } = sources;
  return useMemo(() => {
    const cards = attentionCardsOf({
      requests,
      boardCards,
      waiting,
      notices,
      doneDismissals,
    });
    return { cards, counts: attentionCountsOf(cards) };
  }, [requests, boardCards, waiting, notices, doneDismissals]);
}
