// @vitest-environment jsdom
import { act, createElement } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { CommandCenterCard, RunDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type {
  CommandCenterChangedEvent,
  DaemonClient,
  VerdictAck,
} from '../daemon-client';
import {
  ANSWERED_MARK_MS,
  type CommandCenterBoardState,
  useCommandCenterBoard,
} from './use-command-center-board';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const FIVE_MINUTES_MS = 5 * 60_000;

const BOARD = {
  cards: [] as CommandCenterCard[],
  manager: null as RunDto | null,
  pendingStarts: 0,
  generatedAt: '2026-11-18T10:00:00.000Z',
};

interface ProbeProps {
  apis: DaemonApis;
  client: DaemonClient;
  active: boolean;
}

function Probe(props: ProbeProps): null {
  useCommandCenterBoard(props.apis, props.client, props.active);
  return null;
}

function fakes() {
  const readCommandCenterBoard = vi.fn((_request: { runIds?: string }) =>
    Promise.resolve(BOARD),
  );
  const listeners: {
    changed: ((event: CommandCenterChangedEvent) => void) | null;
    reconnect: (() => void) | null;
    ack: ((ack: VerdictAck) => void) | null;
  } = { changed: null, reconnect: null, ack: null };
  const apis = {
    commandCenter: { readCommandCenterBoard },
  } as unknown as DaemonApis;
  const client = {
    onCommandCenterChanged: (
      listener: (event: CommandCenterChangedEvent) => void,
    ) => {
      listeners.changed = listener;
      return () => undefined;
    },
    onCommandCenterContact: () => () => undefined,
    onReconnect: (listener: () => void) => {
      listeners.reconnect = listener;
      return () => undefined;
    },
    onVerdictAck: (listener: (ack: VerdictAck) => void) => {
      listeners.ack = listener;
      return () => undefined;
    },
  } as unknown as DaemonClient;
  return {
    apis,
    client,
    readCommandCenterBoard,
    announce: (runIds: string[]) =>
      act(async () => {
        listeners.changed?.({ runIds } as CommandCenterChangedEvent);
      }),
    reconnect: () =>
      act(async () => {
        listeners.reconnect?.();
      }),
    ack: (status: VerdictAck['status']) =>
      act(async () => {
        listeners.ack?.({ runId: 'run-1', requestId: 'req-1', status });
      }),
  };
}

let root: Root | null = null;
let container: HTMLDivElement | null = null;

async function render(props: ProbeProps): Promise<void> {
  if (root === null) {
    container = document.createElement('div');
    root = createRoot(container);
  }
  await act(async () => {
    root!.render(createElement(Probe, props));
  });
}

afterEach(() => {
  act(() => root?.unmount());
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

describe('useCommandCenterBoard', () => {
  it('reads nothing while hidden, and reads the whole board once when shown again', async () => {
    vi.useFakeTimers();
    const { apis, client, readCommandCenterBoard, announce, reconnect } =
      fakes();

    await render({ apis, client, active: false });
    await announce(['run-1']);
    await reconnect();
    await act(async () => {
      vi.advanceTimersByTime(FIVE_MINUTES_MS);
    });
    expect(readCommandCenterBoard).not.toHaveBeenCalled();

    await render({ apis, client, active: true });
    expect(readCommandCenterBoard.mock.calls).toEqual([[{}]]);
  });

  it('reads the whole board again on every return, even when nothing was announced while hidden', async () => {
    const { apis, client, readCommandCenterBoard } = fakes();

    await render({ apis, client, active: true });
    await render({ apis, client, active: false });
    await render({ apis, client, active: true });

    expect(readCommandCenterBoard.mock.calls).toEqual([[{}], [{}]]);
  });

  it('re-reads only the named cards while shown', async () => {
    const { apis, client, readCommandCenterBoard, announce } = fakes();

    await render({ apis, client, active: true });
    expect(readCommandCenterBoard.mock.calls).toEqual([[{}]]);

    await announce(['run-1', 'run-2']);
    expect(readCommandCenterBoard.mock.calls).toEqual([
      [{}],
      [{ runIds: 'run-1,run-2' }],
    ]);
  });
});

describe('useCommandCenterBoard — a thread the user just answered', () => {
  const asking = {
    run: { id: 'run-1', awaiting: 'question', lastActivityAt: null },
    column: 'waiting',
  } as unknown as CommandCenterCard;
  let seen: CommandCenterBoardState | null = null;

  function Watch(props: ProbeProps): null {
    seen = useCommandCenterBoard(props.apis, props.client, props.active);
    return null;
  }

  async function shown(props: ProbeProps): Promise<void> {
    if (root === null) {
      container = document.createElement('div');
      root = createRoot(container);
    }
    await act(async () => {
      root!.render(createElement(Watch, props));
    });
  }

  function cardOf(): CommandCenterCard {
    return seen!.cards!.find((card) => card.run.id === 'run-1')!;
  }

  async function answeredBoard() {
    const fake = fakes();
    fake.readCommandCenterBoard.mockResolvedValue({
      ...BOARD,
      cards: [asking],
    });
    await shown({ apis: fake.apis, client: fake.client, active: true });
    expect(cardOf().run.awaiting).toBe('question');
    await act(async () => seen!.markAnswered('run-1'));
    return fake;
  }

  it('stops waiting on the user at once, back at work, before any board read', async () => {
    const { readCommandCenterBoard } = await answeredBoard();

    expect(cardOf().run.awaiting).toBeNull();
    expect(cardOf().column).toBe('working');
    expect(readCommandCenterBoard).toHaveBeenCalledTimes(1);
  });

  it('shows the daemon state again when the daemon refuses the answer', async () => {
    const { ack } = await answeredBoard();

    await ack('expired');

    expect(cardOf().run.awaiting).toBe('question');
    expect(cardOf().column).toBe('waiting');
  });

  it('keeps the answer over a read the daemon answered before applying it, and gives way to a read after', async () => {
    const { ack, announce } = await answeredBoard();

    await announce(['run-1']);
    expect(cardOf().run.awaiting).toBeNull();

    await ack('applied');
    await announce(['run-1']);

    expect(cardOf().run.awaiting).toBe('question');
  });

  it('gives way to the board after a while with no acknowledgment', async () => {
    vi.useFakeTimers();
    await answeredBoard();

    await act(async () => {
      vi.advanceTimersByTime(ANSWERED_MARK_MS);
    });

    expect(cardOf().run.awaiting).toBe('question');
  });
});

describe('useCommandCenterBoard — answers that arrive out of order', () => {
  let seen: CommandCenterBoardState | null = null;

  function Watch(props: ProbeProps): null {
    seen = useCommandCenterBoard(props.apis, props.client, props.active);
    return null;
  }

  function card(
    id: string,
    status: 'running' | 'completed',
  ): CommandCenterCard {
    return {
      run: {
        id,
        status,
        lastActivityAt: null,
        createdAt: '2026-11-18T10:00:00.000Z',
      },
      column: status === 'running' ? 'working' : 'done',
    } as unknown as CommandCenterCard;
  }

  function deferredReads() {
    const fake = fakes();
    const pending: ((board: typeof BOARD) => void)[] = [];
    fake.readCommandCenterBoard.mockImplementation(
      () =>
        new Promise((resolve) => {
          pending.push(resolve);
        }),
    );
    const answer = (
      index: number,
      cards: CommandCenterCard[],
      board: Partial<typeof BOARD> = {},
    ) =>
      act(async () => {
        pending[index]!({ ...BOARD, ...board, cards });
      });
    return { ...fake, answer };
  }

  async function shown(props: ProbeProps): Promise<void> {
    if (root === null) {
      container = document.createElement('div');
      root = createRoot(container);
    }
    await act(async () => {
      root!.render(createElement(Watch, props));
    });
  }

  function statusOf(id: string): string | undefined {
    return seen!.cards!.find((held) => held.run.id === id)?.run.status;
  }

  it('keeps a settled card when a whole read issued before the settle answers after it', async () => {
    const { apis, client, announce, reconnect, answer } = deferredReads();
    await shown({ apis, client, active: true });
    await answer(0, [card('run-1', 'running'), card('run-2', 'running')]);
    await reconnect();
    await announce(['run-1']);

    await answer(2, [card('run-1', 'completed')]);
    await answer(1, [card('run-1', 'running'), card('run-2', 'running')]);

    expect(statusOf('run-1')).toBe('completed');
    expect(statusOf('run-2')).toBe('running');
  });

  it('keeps the later of two reads of one run, whichever answers last', async () => {
    const { apis, client, announce, answer } = deferredReads();
    await shown({ apis, client, active: true });
    await answer(0, [card('run-1', 'running')]);
    await announce(['run-1']);
    await announce(['run-1']);

    await answer(2, [card('run-1', 'completed')]);
    await answer(1, [card('run-1', 'running')]);

    expect(statusOf('run-1')).toBe('completed');
  });

  it('lets an older whole read neither drop a card a newer read added nor bring back one it removed', async () => {
    const { apis, client, announce, reconnect, answer } = deferredReads();
    await shown({ apis, client, active: true });
    await answer(0, [card('run-gone', 'completed')]);
    await reconnect();
    await announce(['run-new', 'run-gone']);

    await answer(2, [card('run-new', 'running')]);
    await answer(1, [card('run-gone', 'completed')]);

    expect(statusOf('run-new')).toBe('running');
    expect(statusOf('run-gone')).toBeUndefined();
  });

  it('applies no subset answer before the first whole read has landed', async () => {
    const { apis, client, announce, answer } = deferredReads();
    await shown({ apis, client, active: true });
    await announce(['run-1']);

    await answer(1, [card('run-1', 'completed')]);
    expect(seen!.cards).toBeNull();

    await answer(0, [card('run-1', 'running')]);
    expect(statusOf('run-1')).toBe('running');
  });

  it('keeps the manager a newer read answered over an older whole read', async () => {
    const { apis, client, announce, reconnect, answer } = deferredReads();
    const manager = (status: string) =>
      ({ id: 'manager', status }) as unknown as RunDto;
    await shown({ apis, client, active: true });
    await answer(0, []);
    await reconnect();
    await announce(['run-1']);

    await answer(2, [card('run-1', 'completed')], {
      manager: manager('completed'),
    });
    await answer(1, [], { manager: manager('running') });

    expect(seen!.manager?.status).toBe('completed');
  });

  it('lets a whole read issued after a subset read replace what that read applied', async () => {
    const { apis, client, announce, reconnect, answer } = deferredReads();
    await shown({ apis, client, active: true });
    await answer(0, [card('run-1', 'running')]);
    await announce(['run-1']);
    await answer(1, [card('run-1', 'running')]);

    await reconnect();
    await answer(2, [card('run-1', 'completed')]);

    expect(statusOf('run-1')).toBe('completed');
  });
});
