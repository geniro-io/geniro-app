import { useEffect, useMemo, useRef, useState } from 'react';

import type { CommandCenterCard, RunDto } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import type { CommandCenterContactEvent, DaemonClient } from '../daemon-client';

/** How long a contact pulse is kept for the graph — a lit edge's own lifetime. */
const PULSE_KEEP_MS = 5 * 60_000;

/** How often the board is read whole, so the idle marks move on. */
const FULL_REFRESH_MS = 5 * 60_000;

/** The longest an answered thread reads as answered with no board read to confirm it. */
export const ANSWERED_MARK_MS = 15_000;

/** A thread the user just answered, until a board read taken after the daemon applied the answer stands in for it. */
interface AnsweredMark {
  /** The read counter when the daemon acknowledged the answer; null until then. */
  appliedAt: number | null;
}

/** The card as it stands once its question is answered: no longer waiting on the user, back at work. */
function answeredCard(card: CommandCenterCard): CommandCenterCard {
  return {
    ...card,
    column: card.column === 'waiting' ? 'working' : card.column,
    run: { ...card.run, awaiting: null },
  };
}

export interface CommandCenterBoardState {
  /** Null until the first answer. */
  cards: CommandCenterCard[] | null;
  /** The manager's own chat, or null while there is none. */
  manager: RunDto | null;
  /** Threads the manager asked to start that wait on the user's Start. */
  pendingStarts: number;
  generatedAt: string | null;
  error: string | null;
  /** Messages between the manager and a thread, newest last. */
  pulses: readonly CommandCenterContactEvent[];
  reload: () => void;
  /** The user answered the thread's card here: show it answered until the board confirms or the daemon refuses. */
  markAnswered: (runId: string) => void;
}

function byActivity(a: CommandCenterCard, b: CommandCenterCard): number {
  return (b.run.lastActivityAt ?? b.run.createdAt).localeCompare(
    a.run.lastActivityAt ?? a.run.createdAt,
  );
}

/**
 * The command center's board as the daemon folds it. Read whole on mount,
 * after a reconnect and every {@link FULL_REFRESH_MS}; on
 * `command_center_changed` only the named cards are read again, and a named
 * card the daemon no longer answers for has left the board. While `active` is
 * false nothing is read, and the whole board is read once each time the page
 * is shown again: not every change to a card is announced (a rename is not).
 */
export function useCommandCenterBoard(
  apis: DaemonApis | null,
  client: DaemonClient | null,
  active: boolean,
): CommandCenterBoardState {
  const [cards, setCards] = useState<CommandCenterCard[] | null>(null);
  const [manager, setManager] = useState<RunDto | null>(null);
  const [pendingStarts, setPendingStarts] = useState(0);
  const [generatedAt, setGeneratedAt] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [pulses, setPulses] = useState<CommandCenterContactEvent[]>([]);
  const generation = useRef(0);
  const stale = useRef(true);
  const reads = useRef(0);
  const [answered, setAnswered] = useState<ReadonlyMap<string, AnsweredMark>>(
    () => new Map(),
  );
  const confirmed = (issued: number, runIds: readonly string[] | null): void =>
    setAnswered((held) => {
      const next = new Map(held);
      for (const [runId, mark] of held) {
        if (
          mark.appliedAt !== null &&
          issued > mark.appliedAt &&
          (runIds === null || runIds.includes(runId))
        ) {
          next.delete(runId);
        }
      }
      return next.size === held.size ? held : next;
    });
  const unmark = useLatestCallback((runId: string) => {
    setAnswered((held) => {
      if (!held.has(runId)) {
        return held;
      }
      const next = new Map(held);
      next.delete(runId);
      return next;
    });
  }, []);
  const markAnswered = useLatestCallback(
    (runId: string) => {
      setAnswered((held) => new Map(held).set(runId, { appliedAt: null }));
      setTimeout(() => unmark(runId), ANSWERED_MARK_MS);
    },
    [unmark],
  );

  const readWhole = useLatestCallback(() => {
    if (apis === null) {
      return;
    }
    stale.current = false;
    const mine = ++generation.current;
    const issued = ++reads.current;
    void apis.commandCenter
      .readCommandCenterBoard({})
      .then((board) => {
        if (mine !== generation.current) {
          return;
        }
        setCards(board.cards);
        confirmed(issued, null);
        setManager(board.manager);
        setPendingStarts(board.pendingStarts);
        setGeneratedAt(board.generatedAt);
        setError(null);
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setError(describeDaemonError(err));
        }
      });
  }, [apis]);

  const rereadSome = useLatestCallback(
    (runIds: readonly string[]) => {
      if (apis === null || runIds.length === 0) {
        return;
      }
      const asked = generation.current;
      const issued = ++reads.current;
      void apis.commandCenter
        .readCommandCenterBoard({ runIds: runIds.join(',') })
        .then((board) => {
          if (asked !== generation.current) {
            return;
          }
          confirmed(issued, runIds);
          const named = new Set(runIds);
          setCards((held) => {
            if (held === null) {
              return held;
            }
            const kept = held.filter((card) => !named.has(card.run.id));
            return [...kept, ...board.cards].sort(byActivity);
          });
          setManager(board.manager);
          setPendingStarts(board.pendingStarts);
          setGeneratedAt(board.generatedAt);
        })
        .catch(() => {
          // One failed subset read costs only those cards' freshness; the next
          // change or the periodic whole read brings them back.
        });
    },
    [apis],
  );

  const reload = useLatestCallback(() => {
    if (active) {
      readWhole();
    }
  }, [readWhole]);

  const changed = useLatestCallback(
    (runIds: readonly string[]) => {
      if (active) {
        rereadSome(runIds);
      }
    },
    [rereadSome],
  );

  useEffect(() => {
    if (!active) {
      stale.current = true;
    } else if (stale.current) {
      readWhole();
    }
  }, [active, readWhole]);

  useEffect(() => {
    const timer = setInterval(reload, FULL_REFRESH_MS);
    return () => clearInterval(timer);
  }, [reload]);

  useEffect(() => {
    if (client === null) {
      return;
    }
    const offChanged = client.onCommandCenterChanged(({ runIds }) => {
      changed(runIds);
    });
    const offContact = client.onCommandCenterContact((contact) => {
      const cutoff = Date.parse(contact.at) - PULSE_KEEP_MS;
      setPulses((held) => [
        ...held.filter((pulse) => Date.parse(pulse.at) >= cutoff),
        contact,
      ]);
    });
    const offReconnect = client.onReconnect(() => reload());
    const offAck = client.onVerdictAck((ack) => {
      const runId = ack.runId;
      if (runId === null) {
        return;
      }
      if (ack.status !== 'applied') {
        unmark(runId);
        return;
      }
      setAnswered((held) =>
        held.has(runId)
          ? new Map(held).set(runId, { appliedAt: reads.current })
          : held,
      );
    });
    return () => {
      offChanged();
      offContact();
      offReconnect();
      offAck();
    };
  }, [client, reload, changed, unmark]);

  const shown = useMemo(
    () =>
      cards === null || answered.size === 0
        ? cards
        : cards.map((card) =>
            answered.has(card.run.id) ? answeredCard(card) : card,
          ),
    [cards, answered],
  );

  return {
    cards: shown,
    manager,
    pendingStarts,
    generatedAt,
    error,
    pulses,
    reload,
    markAnswered,
  };
}
