import { Loader2, LogIn, LogOut } from 'lucide-react';

import {
  CLI_KINDS,
  type CliDetection,
  type CliKind,
} from '../../shared/contracts';
import type { LoginSession } from '../autogenerated';
import { CliLoginProgress } from './cli-login-progress';
import { CollapsibleCard } from './collapsible-card';
import { Field } from './field';
import { StatusDot, type StatusTone } from './status-dot';
import { Button } from './ui/button';
import { Input } from './ui/input';
import { cn } from './ui/utils';

export type AgentStatus = { label: string; tone: StatusTone };

/**
 * Readiness of one agent. "Ready" (green) means the binary was detected AND,
 * for a CLI whose own status command was actually asked and answered, it did
 * not say signed-out.
 *
 * `loggedIn === false` is the ONLY thing that renders warn: a CLI that said so
 * itself. `null` — no status command to ask (claude today) or a probe that
 * failed — reads as ready, same as `true`. Treating it as signed-out would
 * tell an already-signed-in user to sign in again, for a fix that would not
 * even address a probe failure.
 */
export function statusFor(
  clis: CliDetection[] | null,
  kind: CliKind,
): AgentStatus {
  if (clis === null) {
    return { label: 'Checking…', tone: 'unknown' };
  }
  const detection = clis.find((c) => c.kind === kind) ?? null;
  if (!detection?.found) {
    return { label: 'not found on PATH', tone: 'bad' };
  }
  const version = detection.version ? ` · ${detection.version}` : '';
  if (detection.loggedIn === false) {
    return { label: `detected${version} · not signed in`, tone: 'warn' };
  }
  return { label: `ready${version}`, tone: 'ok' };
}

const STATUS_TEXT: Record<StatusTone, string> = {
  ok: 'text-sm text-success',
  warn: 'text-sm text-warning',
  bad: 'text-sm text-destructive',
  unknown: 'text-sm text-muted-foreground',
};

export interface AgentConfigListProps {
  /** Detection results (null while probing). */
  clis: CliDetection[] | null;
  /** Which agent cards are expanded. */
  open: Partial<Record<CliKind, boolean>>;
  onToggle: (kind: CliKind) => void;
  /** Per-agent binary path override (blank = auto-detect on PATH). */
  binaryPaths: Partial<Record<CliKind, string>>;
  onBinaryPathChange: (kind: CliKind, value: string) => void;
  onBrowse: (kind: CliKind) => void;
  /**
   * Sign one CLI itself back in, in the user's own terminal. Settings-only —
   * onboarding passes nothing, and a card renders no control without it: the
   * decided placement for this action is Settings, not first-run setup.
   */
  onSignIn?: (kind: CliKind) => void;
  /**
   * The CLI whose sign-in has been asked for and not yet answered, or null.
   *
   * The caller's, because the controller is: one sign-in runs at a time across
   * the screen, so a flag kept in here would let two cards each think they own
   * it.
   */
  signingIn?: CliKind | null;
  /**
   * The CLIs whose ACCOUNT is per-config-directory, so this card's row can say
   * which profile it is reporting on. From the daemon's `configDirs[]`
   * capability — see {@link accountRowText}. Absent (onboarding, or before
   * capabilities answer) means no qualifier anywhere, which is the honest
   * rendering rather than a guessed one.
   */
  profileScopedKinds?: ReadonlySet<string>;
  /**
   * Sign one CLI itself OUT, in the user's own terminal. Settings-only, for the
   * reason its sibling is.
   *
   * Separate handler rather than one `onAccountAction(kind, verb)`: the card
   * decides which of the two to OFFER from the detection state, and the two
   * resolve different daemon routes. A single handler would move that choice
   * into the parent, where the detection it depends on is not the parent's to
   * read.
   */
  onSignOut?: (kind: CliKind) => void;
  /**
   * That agent's OWN settings, drawn inside its card — whatever is true of one
   * CLI and of no other.
   *
   * REPORTED as "все специфические, именно к агентам специфичные настройки
   * должны быть там": cursor's Max Mode and claude's browser tools each had a
   * section of their own further down the page, so a reader looking for what
   * they could change about cursor found half of it in the card named cursor
   * and half two screens below, under a heading that named a topic instead.
   *
   * Passed IN rather than built here, which is the rule the daemon's adapters
   * follow as well: this component knows how to draw a card, not what is true
   * of claude. It also keeps onboarding — which shares this list — free of
   * settings that belong to a running app, by simply passing none.
   */
  agentSettings?: Partial<Record<CliKind, React.ReactNode>>;
  /**
   * A sign-in the daemon is running right now, rendered on the card it belongs
   * to. Absent on onboarding, and absent between attempts.
   *
   * The card takes this rather than owning it: polling a daemon route is not a
   * presentational concern, and this component is shared with a screen that has
   * no daemon handle at all.
   */
  login?: {
    kind: CliKind;
    session: LoginSession;
    error: string | null;
    onSubmitCode: (code: string) => void;
    onCancel: () => void;
    onDismiss: () => void;
  } | null;
}

/**
 * The ONE account action on an agent card — whichever of the two the card's
 * detection state makes true.
 *
 * This is the reported defect. The card used to offer Sign in to every detected
 * CLI, including one the probe had just confirmed signed in, and there was no
 * sign-out at all: an action the user cannot need, in the place they look to
 * find out whether setup is finished, reads as an unfinished step. Worse, the
 * one CLI that reported its state was the one being told to sign in again.
 *
 * `loggedIn === true` is the ONLY state that offers Sign out, and the asymmetry
 * with {@link statusFor} is deliberate: there, `null` reads as ready because
 * refusing to guess must not accuse a signed-in user; here, `null` offers Sign
 * in because that is the action which can only help. Signing IN when already
 * signed in costs the user a re-auth they can cancel; signing OUT when the
 * state is unknown could destroy a working session on a probe failure.
 *
 * A card whose parent passed no handler for the action its state calls for
 * renders NOTHING rather than the other one — offering the wrong verb because
 * the right one is unavailable is how a control becomes a lie. (Onboarding
 * passes neither, and the note beside it names Settings as where to go.)
 */
function AccountButton({
  kind,
  loggedIn,
  signingIn,
  onSignIn,
  onSignOut,
}: {
  kind: CliKind;
  loggedIn: boolean | null;
  /** True while this card's sign-in has been asked for and not yet answered. */
  signingIn: boolean;
  onSignIn?: (kind: CliKind) => void;
  onSignOut?: (kind: CliKind) => void;
}): React.JSX.Element | null {
  if (loggedIn === true) {
    return onSignOut ? (
      // GHOST, where its sign-in sibling is outlined. The weight tracks how
      // likely the user is to want it: signing out of a working CLI is rare and
      // mildly destructive, so it stays quiet and legible rather than competing
      // with the card's own controls.
      <Button
        type="button"
        variant="ghost"
        size="sm"
        className="shrink-0 text-muted-foreground"
        onClick={() => onSignOut(kind)}>
        <LogOut className="size-3.5" />
        Sign out
      </Button>
    ) : null;
  }
  return onSignIn ? (
    // The press is answered HERE. The panel below only appears once the daemon
    // has replied, and that reply is held until the CLI prints its URL —
    // measured at 4001ms — so without this the button sits unchanged while a
    // browser tab opens behind the window. Disabled as well as spinning: a
    // second press starts a second browser challenge that invalidates the
    // first, which is the same reason the panel withholds this button entirely
    // once it owns the flow.
    <Button
      type="button"
      variant="outline"
      size="sm"
      className="shrink-0"
      disabled={signingIn}
      onClick={() => onSignIn(kind)}>
      {signingIn ? (
        <Loader2 aria-hidden="true" className="size-3.5 animate-spin" />
      ) : (
        <LogIn className="size-3.5" />
      )}
      {signingIn ? 'Signing in…' : 'Sign in'}
    </Button>
  ) : null;
}

/**
 * What this card's account row is TALKING ABOUT, and the state it is in.
 *
 * The scope prefix is the fix for a real ambiguity: this row's probe and its
 * button both run with no config directory, so they are about the CLI's DEFAULT
 * profile — while a chat can run under a different one, on a different
 * subscription. Unqualified, the row claimed to speak for an account it had
 * never asked about: a user whose chats all run under `~/profiles/work` would
 * read "not signed in" beside runs that were working perfectly.
 *
 * `profileScoped` is per CLI and comes from the daemon's own
 * `configDirs[].unavailableReason`, never from a name: cursor-agent READS a
 * config directory but keeps the account outside it (probed — a fresh
 * `CURSOR_CONFIG_DIR` still reports the default account), so for that CLI there
 * is exactly one account and "Default profile" would invent a distinction it
 * does not have. Unknown — onboarding, or capabilities not yet answered — is
 * treated as NOT scoped: at first run there are no profiles to distinguish, and
 * a prefix is worse than none if it might be wrong.
 *
 * Composed from a scope and a clause rather than written out per combination:
 * three states times two scopes times "is there a handler" is an eight-arm
 * matrix, and the arms that had to agree are exactly the ones a reader would
 * skim past.
 */
function accountRowText({
  kind,
  loggedIn,
  profileScoped,
  canSignIn,
}: {
  kind: CliKind;
  loggedIn: boolean | null;
  profileScoped: boolean;
  canSignIn: boolean;
}): string {
  const clause =
    loggedIn === false
      ? // Signed out with no control is REACHABLE, not theoretical: the sign-in
        // lives on Settings only, and Onboarding — which auto-expands a card
        // that is not ready — passes no handler. Naming where the cure is keeps
        // that screen from being a dead end without moving the control.
        canSignIn
        ? 'not signed in'
        : 'not signed in — sign in from Settings once setup is done'
      : loggedIn === true
        ? `signed in through the ${kind} CLI`
        : // No answer yet, or a CLI that cannot be asked. Says the one thing a
          // user hunting for an API key field needs to know, which is why this
          // wording survives from the row's first version.
          `signs in through the ${kind} CLI itself — no key to enter here`;
  return profileScoped
    ? `Default profile · ${clause}`
    : clause.charAt(0).toUpperCase() + clause.slice(1);
}

/**
 * The list of per-agent configuration cards — the single implementation shared
 * by onboarding and Settings, so both surfaces show detection state and
 * binary-path overrides identically. Fully controlled: the parent owns all
 * state and decides how a change is persisted (completeOnboarding vs.
 * updateSettings).
 */
export function AgentConfigList({
  clis,
  open,
  onToggle,
  binaryPaths,
  onBinaryPathChange,
  onBrowse,
  onSignIn,
  onSignOut,
  signingIn = null,
  profileScopedKinds,
  login,
  agentSettings,
}: AgentConfigListProps): React.JSX.Element {
  return (
    <div className="flex flex-col gap-3">
      {CLI_KINDS.map((kind) => {
        const detection = clis?.find((c) => c.kind === kind) ?? null;
        const status = statusFor(clis, kind);
        const isOpen = Boolean(open[kind]);
        const pathId = `agent-path-${kind}`;
        const found = Boolean(detection?.found);
        // Only one sign-in runs at a time, so at most one card shows a panel.
        const cardLogin = login?.kind === kind ? login : null;
        return (
          <CollapsibleCard
            key={kind}
            open={isOpen}
            onToggle={() => onToggle(kind)}
            header={
              <>
                <StatusDot tone={status.tone} />
                <span className="font-medium">{kind}</span>
                <span className={STATUS_TEXT[status.tone]}>{status.label}</span>
              </>
            }>
            <Field
              label="Binary path"
              htmlFor={pathId}
              hint={
                found
                  ? 'Detected here — edit to pin a different binary.'
                  : `Set the full path to the ${kind} binary.`
              }>
              <div className="flex gap-2">
                <Input
                  id={pathId}
                  type="text"
                  placeholder="Auto-detect on PATH"
                  value={binaryPaths[kind] ?? ''}
                  onChange={(event) =>
                    onBinaryPathChange(kind, event.target.value)
                  }
                />
                <Button
                  type="button"
                  variant="outline"
                  onClick={() => onBrowse(kind)}>
                  Browse…
                </Button>
              </div>
            </Field>

            {/* This agent's own settings, between what identifies the binary
                and what says who is signed in — the card reads top-to-bottom
                as which binary, how it behaves, whose account. */}
            {agentSettings?.[kind] ?? null}

            {/* A card FOOTER, not a tinted panel. This used to be a `NoteBox`
                inside the card, which put a box in a box and set a bordered
                button on a filled ground — grey on grey, with the control's own
                fill fighting the panel's. The account state is a property of the
                whole card, so it reads as a band across its foot: the card's own
                background, one hairline rule, and the flat control weight this
                screen already uses for `Re-check`.

                `-mx-4 -mb-4` bleeds through the body's padding so the rule spans
                the full card width; `px-4` puts the content back on the body's
                own gutter. */}
            <div
              className={cn(
                '-mx-4 flex items-center justify-between gap-3 border-t border-border px-4 py-2.5',
                // The bottom bleed belongs to whichever band is LAST. With a
                // login panel open, that is the panel — keeping it here would
                // leave the panel outside the card's rounded corner.
                cardLogin === null && '-mb-4',
              )}>
              <span
                className={cn(
                  'text-sm',
                  // Signed out is the one state that asks something of the user,
                  // so it carries the same warn tone as the header's own dot
                  // rather than sitting in muted text beside it.
                  detection?.loggedIn === false
                    ? 'text-warning'
                    : 'text-muted-foreground',
                )}>
                {accountRowText({
                  kind,
                  loggedIn: detection?.loggedIn ?? null,
                  profileScoped: profileScopedKinds?.has(kind) === true,
                  canSignIn: onSignIn !== undefined,
                })}
              </span>
              {/* `found` matters as much as the handler: the daemon resolves an
                  account target from the bare CLI name without checking it
                  exists, so offering either of these on a card that already says
                  "not found on PATH" opens a terminal that answers `command not
                  found`, where no in-app error can reach the user. */}
              {/* Withheld while THIS card's sign-in is running: the panel below
                  owns the flow, and a live Sign in button beside it would start a
                  second browser challenge that invalidates the first. */}
              {found && cardLogin === null ? (
                <AccountButton
                  kind={kind}
                  loggedIn={detection?.loggedIn ?? null}
                  signingIn={signingIn === kind}
                  onSignIn={onSignIn}
                  onSignOut={onSignOut}
                />
              ) : null}
            </div>
            {cardLogin !== null ? (
              <div className="-mb-4">
                <CliLoginProgress
                  session={cardLogin.session}
                  error={cardLogin.error}
                  onSubmitCode={cardLogin.onSubmitCode}
                  onCancel={cardLogin.onCancel}
                  onDismiss={cardLogin.onDismiss}
                />
              </div>
            ) : null}
          </CollapsibleCard>
        );
      })}
    </div>
  );
}
