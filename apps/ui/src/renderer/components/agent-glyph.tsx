import { Bot, Code, SquareTerminal } from 'lucide-react';

import type { AgentIconName } from '../autogenerated';
import { cn } from './ui/utils';

/**
 * The lucide icon for each of the daemon's named agent glyphs
 * (`GET /v1/capabilities` `agents[].icon`).
 *
 * Exhaustive over `AgentIconName` rather than a fallback default, so a fourth
 * icon name the daemon starts sending is a compile error here instead of a
 * silently blank glyph.
 */
const AGENT_ICON_COMPONENTS: Record<
  AgentIconName,
  typeof Bot | typeof SquareTerminal | typeof Code
> = {
  bot: Bot,
  terminal: SquareTerminal,
  code: Code,
};

/**
 * One agent's icon, drawn from the daemon's own `AgentIconName` rather than a
 * per-CLI literal, so no surface keeps a `Record<CliKind, ReactNode>` of its
 * own — the branch-on-agent-name the daemon's adapters exist to avoid.
 */
export function AgentGlyph({
  icon,
  className,
}: {
  icon: AgentIconName;
  className?: string;
}): React.JSX.Element {
  const Icon = AGENT_ICON_COMPONENTS[icon];
  return <Icon aria-hidden="true" className={cn('size-4', className)} />;
}
