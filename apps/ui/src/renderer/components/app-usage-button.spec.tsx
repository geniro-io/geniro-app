// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { AppProcessesDto } from '../autogenerated';
import { AppUsageButton } from './app-usage-button';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const MB = 1024 * 1024;

const READING: AppProcessesDto = {
  sampledAt: '2026-10-04T12:00:00.000Z',
  threads: [
    {
      runId: 'run-1',
      title: 'Ship it',
      agentKinds: ['claude'],
      agents: 2,
      figures: { processes: 6, cpuPercent: 3, rssBytes: 600 * MB },
    },
    {
      runId: 'run-2',
      title: null,
      agentKinds: ['codex'],
      agents: 1,
      figures: { processes: 1, cpuPercent: 0, rssBytes: 100 * MB },
    },
  ],
  geniro: { processes: 4, cpuPercent: 1, rssBytes: 300 * MB },
  total: { processes: 11, cpuPercent: 4, rssBytes: 1_000 * MB },
  unavailableReason: null,
};

let root: Root | null = null;
let host: HTMLDivElement | null = null;

function mount(props: Partial<Parameters<typeof AppUsageButton>[0]>): {
  el: HTMLDivElement;
  onOpenChange: ReturnType<typeof vi.fn>;
  onOpenThread: ReturnType<typeof vi.fn>;
} {
  const onOpenChange = vi.fn();
  const onOpenThread = vi.fn();
  host = document.createElement('div');
  document.body.append(host);
  root = createRoot(host);
  act(() =>
    root?.render(
      <AppUsageButton
        open
        onOpenChange={onOpenChange}
        data={READING}
        loading={false}
        error={null}
        onOpenThread={onOpenThread}
        {...props}
      />,
    ),
  );
  return { el: host, onOpenChange, onOpenThread };
}

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
});

describe('AppUsageButton', () => {
  it('lists each thread with its share of the app’s memory, then geniro’s own', () => {
    mount({});
    const threads = [
      ...document.querySelectorAll('[data-slot="app-usage-thread"]'),
    ];
    expect(threads.map((row) => row.textContent)).toEqual([
      expect.stringContaining('Ship it'),
      expect.stringContaining('Untitled thread'),
    ]);
    expect(threads[0]?.textContent).toContain('2 agents · 6 processes');
    expect(
      [...document.querySelectorAll('[data-slot="share-bar"]')].map((bar) =>
        bar.getAttribute('aria-label'),
      ),
    ).toEqual([
      '60% of the app’s memory',
      '10% of the app’s memory',
      '30% of the app’s memory',
    ]);
    expect(
      document.querySelector('[data-slot="app-usage-geniro"]')?.textContent,
    ).toContain('300.0 MB');
    expect(
      document.querySelector('[data-slot="app-usage-total"]')?.textContent,
    ).toContain('1000.0 MB');
  });

  it('opens a thread on press, and closes itself', () => {
    const { onOpenChange, onOpenThread } = mount({});
    act(() =>
      document
        .querySelector<HTMLButtonElement>('[data-slot="app-usage-thread"]')
        ?.click(),
    );
    expect(onOpenThread).toHaveBeenCalledWith('run-1');
    expect(onOpenChange).toHaveBeenCalledWith(false);
  });

  it('says so when no agent is running, and still shows geniro', () => {
    mount({ data: { ...READING, threads: [] } });
    expect(document.body.textContent).toContain(
      'no agent is running right now',
    );
    expect(
      document.querySelector('[data-slot="app-usage-geniro"]'),
    ).not.toBeNull();
  });

  it('toggles from the title bar glyph', () => {
    const { el, onOpenChange } = mount({ open: false });
    act(() =>
      el
        .querySelector<HTMLButtonElement>('[data-slot="app-usage-trigger"]')
        ?.click(),
    );
    expect(onOpenChange).toHaveBeenCalledWith(true);
  });
});
