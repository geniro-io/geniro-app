import { Activity } from 'lucide-react';
import { useContext, useMemo, useRef, useState } from 'react';

import { AgentIdentityContext, agentShortName } from '../agent-identity';
import type {
  AppProcessesDto,
  AppProcessThread,
  ProcessFigures,
} from '../autogenerated';
import {
  formatCpu,
  formatMemory,
  formatShare,
  NEUTRAL_SEGMENT_CLASS,
  ProcessFigureCells,
  ProcessFigureHeader,
  segmentColorClass,
  ShareDot,
  type ShareSegment,
  ShareStack,
} from './process-figures';
import { Popover } from './ui/popover';
import { SegmentedControl } from './ui/segmented-control';
import { cn } from './ui/utils';

/** Which figure the division is drawn by. */
export type UsageMetric = 'memory' | 'cpu';

const METRIC_OPTIONS = [
  { id: 'memory', label: 'Memory' },
  { id: 'cpu', label: 'CPU' },
] as const;

function metricOf(figures: ProcessFigures, metric: UsageMetric): number {
  return metric === 'memory' ? figures.rssBytes : figures.cpuPercent;
}

/** What a thread's row says about who is doing the work. */
function threadMeta(
  thread: AppProcessThread,
  names: (kind: string) => string,
): string {
  const kinds = thread.agentKinds.map(names).join(', ');
  const agents = thread.agents > 1 ? `${thread.agents} agents` : '1 agent';
  const processes = `${thread.figures.processes} process${thread.figures.processes === 1 ? '' : 'es'}`;
  return [kinds, agents, processes].filter(Boolean).join(' · ');
}

/** One row of the division: a thread, or geniro itself. */
interface UsageRow {
  key: string;
  runId: string | null;
  title: string;
  meta: string;
  figures: ProcessFigures;
  colorClass: string;
}

/**
 * The title bar's usage readout: how the whole app's load DIVIDES across its
 * threads — every agent CLI and everything under it, folded into the
 * conversation it works for — with geniro's own share beside them. One bar is
 * the division (by memory or by CPU, the reader's pick), each row carries the
 * dot of its stretch and its share in words, and a thread row opens that
 * thread, where its own Processes section breaks it down further.
 *
 * The trigger is a glyph and nothing else: the bar is for the window's own
 * business, and a figure that moved every three seconds there would be the
 * loudest thing in it. The reading is taken only while the panel is open —
 * the OWNER polls, on `open`, so a closed panel costs the daemon nothing.
 */
export function AppUsageButton({
  open,
  onOpenChange,
  data,
  loading,
  error,
  onOpenThread,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  data: AppProcessesDto | null;
  loading: boolean;
  error: string | null;
  onOpenThread?: (runId: string) => void;
}): React.JSX.Element {
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const [metric, setMetric] = useState<UsageMetric>('memory');

  return (
    <>
      <button
        ref={triggerRef}
        type="button"
        data-slot="app-usage-trigger"
        aria-label="App usage"
        aria-expanded={open}
        title="How the app's CPU and memory divide across threads"
        onClick={() => onOpenChange(!open)}
        className={cn(
          'app-no-drag flex size-6 items-center justify-center rounded-md text-muted-foreground outline-none hover:bg-sidebar-accent hover:text-foreground focus-visible:ring-2 focus-visible:ring-sidebar-ring/50',
          open && 'bg-sidebar-accent text-foreground',
        )}>
        <Activity aria-hidden="true" className="size-3.5" />
      </button>
      <Popover
        open={open}
        onClose={() => onOpenChange(false)}
        triggerRef={triggerRef}
        anchor="viewport"
        side="bottom"
        align="end"
        label="App usage"
        className="app-no-drag w-[22rem] p-0">
        <div className="flex max-h-[min(34rem,72vh)] flex-col">
          <div className="flex items-baseline gap-2 border-b border-border px-3 py-2.5">
            <span className="text-sm font-medium text-foreground">Usage</span>
            {data !== null && data.geniro !== null ? (
              <span
                data-slot="app-usage-total"
                className="ml-auto text-xs text-muted-foreground tabular-nums">
                {data.total.processes} processes ·{' '}
                {formatCpu(data.total.cpuPercent)} ·{' '}
                <span className="font-medium text-foreground">
                  {formatMemory(data.total.rssBytes)}
                </span>
              </span>
            ) : null}
          </div>
          <div className="min-h-0 overflow-y-auto px-3 py-2.5">
            <AppUsageBody
              data={data}
              loading={loading}
              error={error}
              metric={metric}
              onMetricChange={setMetric}
              canOpen={onOpenThread !== undefined}
              onOpenThread={(runId) => {
                onOpenThread?.(runId);
                onOpenChange(false);
              }}
            />
          </div>
        </div>
      </Popover>
    </>
  );
}

function AppUsageBody({
  data,
  loading,
  error,
  metric,
  onMetricChange,
  canOpen,
  onOpenThread,
}: {
  data: AppProcessesDto | null;
  loading: boolean;
  error: string | null;
  metric: UsageMetric;
  onMetricChange: (metric: UsageMetric) => void;
  canOpen: boolean;
  onOpenThread: (runId: string) => void;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);

  // Colours follow the thread, not its rank: they are assigned in the order
  // the daemon lists threads (heaviest memory first), so switching the metric
  // re-sorts the rows without repainting a thread in its neighbour's colour.
  const rows = useMemo((): UsageRow[] => {
    if (data === null) {
      return [];
    }
    const threads = data.threads.map((thread, index) => ({
      key: thread.runId,
      runId: thread.runId,
      title: thread.title ?? 'Untitled thread',
      meta: threadMeta(thread, (kind) => agentShortName(identities, kind)),
      figures: thread.figures,
      colorClass: segmentColorClass(index),
    }));
    threads.sort(
      (a, b) => metricOf(b.figures, metric) - metricOf(a.figures, metric),
    );
    return data.geniro === null
      ? threads
      : [
          ...threads,
          {
            key: 'geniro',
            runId: null,
            title: 'Geniro',
            meta: `app, daemon and terminals · ${data.geniro.processes} processes`,
            figures: data.geniro,
            colorClass: NEUTRAL_SEGMENT_CLASS,
          },
        ];
  }, [data, identities, metric]);

  if (data === null) {
    return (
      <p className="py-2 text-xs text-muted-foreground">
        {error ?? (loading ? 'reading processes…' : 'not read yet')}
      </p>
    );
  }
  if (data.unavailableReason !== null) {
    return (
      <p className="py-2 text-xs text-muted-foreground">
        {data.unavailableReason}
      </p>
    );
  }

  const whole = metricOf(data.total, metric);
  const segments: ShareSegment[] = rows.map((row) => ({
    key: row.key,
    label: row.title,
    value: metricOf(row.figures, metric),
    colorClass: row.colorClass,
  }));
  const metricWord = metric === 'memory' ? 'memory' : 'CPU';

  return (
    <div className="flex flex-col gap-2.5">
      <div className="flex items-center gap-2">
        <span className="text-[11px] text-muted-foreground">
          Split by thread
        </span>
        <SegmentedControl
          ariaLabel="Divide by"
          size="sm"
          className="ml-auto"
          options={METRIC_OPTIONS}
          value={metric}
          onSelect={onMetricChange}
        />
      </div>
      <ShareStack segments={segments} label={`The app’s ${metricWord}`} />
      <ProcessFigureHeader label="threads" className="mt-1 px-1.5" />
      {data.threads.length === 0 ? (
        <p className="px-1.5 text-xs text-muted-foreground">
          no agent is running right now
        </p>
      ) : null}
      <ul
        aria-label="Threads"
        className="m-0 flex list-none flex-col gap-0.5 p-0">
        {rows.map((row) => {
          const fraction =
            whole > 0 ? metricOf(row.figures, metric) / whole : 0;
          const body = (
            <>
              <span className="flex w-full items-baseline gap-1.5 text-xs">
                <span className="flex min-w-0 flex-1 items-center gap-1.5">
                  <ShareDot colorClass={row.colorClass} />
                  <span className="min-w-0 truncate font-medium text-foreground">
                    {row.title}
                  </span>
                </span>
                <ProcessFigureCells
                  cpuPercent={row.figures.cpuPercent}
                  rssBytes={row.figures.rssBytes}
                  strong
                />
              </span>
              <span className="flex w-full items-baseline gap-1.5 pl-3.5 text-[11px] text-muted-foreground">
                <span className="min-w-0 flex-1 truncate">{row.meta}</span>
                <span
                  data-slot="app-usage-share"
                  className="shrink-0 tabular-nums">
                  {formatShare(fraction)} of {metricWord}
                </span>
              </span>
            </>
          );
          return (
            <li
              key={row.key}
              className={cn(
                row.runId === null && 'mt-1 border-t border-border pt-1',
              )}>
              {row.runId === null ? (
                <div
                  data-slot="app-usage-geniro"
                  title="The window, the daemon and the terminal panel’s shells"
                  className="flex flex-col gap-0.5 px-1.5 py-1.5">
                  {body}
                </div>
              ) : (
                <button
                  type="button"
                  data-slot="app-usage-thread"
                  disabled={!canOpen}
                  onClick={() => onOpenThread(row.runId as string)}
                  title={canOpen ? 'Open this thread' : undefined}
                  className="flex w-full flex-col gap-0.5 rounded-md px-1.5 py-1.5 text-left outline-none enabled:hover:bg-muted focus-visible:ring-2 focus-visible:ring-ring/50">
                  {body}
                </button>
              )}
            </li>
          );
        })}
      </ul>
      {error === null ? null : (
        <p className="text-[11px] text-muted-foreground">{error}</p>
      )}
    </div>
  );
}
