import { Activity } from 'lucide-react';
import { useContext, useRef } from 'react';

import { AgentIdentityContext, agentShortName } from '../agent-identity';
import type { AppProcessesDto, AppProcessThread } from '../autogenerated';
import {
  formatCpu,
  formatMemory,
  ProcessFigureCells,
  ProcessFigureHeader,
  ShareBar,
} from './process-figures';
import { Popover } from './ui/popover';
import { cn } from './ui/utils';

/** What a thread's row says about who is doing the work. */
function threadMeta(
  thread: AppProcessThread,
  names: (kind: string) => string,
): string {
  const kinds = thread.agentKinds.map(names).join(', ');
  const agents = thread.agents > 1 ? `${thread.agents} agents` : '1 agent';
  const processes = `${thread.figures.processes} process${thread.figures.processes === 1 ? '' : 'es'}`;
  return [kinds, agents, processes].filter(Boolean).join(' · ');
}

function share(part: number, whole: number): number {
  return whole > 0 ? part / whole : 0;
}

/**
 * The title bar's usage readout: what the whole app is running right now, by
 * THREAD — every agent CLI and everything under it, folded into the
 * conversation it works for — and geniro's own share beside it. A thread row
 * opens that thread, where its own Processes section lists each process.
 *
 * The trigger is a glyph and nothing else: the bar is for the window's own
 * business, and a figure that moved every three seconds there would be the
 * loudest thing in it. The reading is taken only while the panel is open —
 * the OWNER polls, on `open`, so a closed panel costs the daemon nothing.
 */
export function AppUsageButton({
  open,
  onOpenChange,
  data,
  loading,
  error,
  onOpenThread,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  data: AppProcessesDto | null;
  loading: boolean;
  error: string | null;
  onOpenThread?: (runId: string) => void;
}): React.JSX.Element {
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const identities = useContext(AgentIdentityContext);
  const names = (kind: string): string => agentShortName(identities, kind);

  return (
    <>
      <button
        ref={triggerRef}
        type="button"
        data-slot="app-usage-trigger"
        aria-label="App usage"
        aria-expanded={open}
        title="What each thread is running — CPU and memory"
        onClick={() => onOpenChange(!open)}
        className={cn(
          'app-no-drag flex size-6 items-center justify-center rounded-md text-muted-foreground outline-none hover:bg-sidebar-accent hover:text-foreground focus-visible:ring-2 focus-visible:ring-sidebar-ring/50',
          open && 'bg-sidebar-accent text-foreground',
        )}>
        <Activity aria-hidden="true" className="size-3.5" />
      </button>
      <Popover
        open={open}
        onClose={() => onOpenChange(false)}
        triggerRef={triggerRef}
        anchor="viewport"
        side="bottom"
        align="end"
        label="App usage"
        className="app-no-drag w-[22rem] p-0">
        <div className="flex max-h-[min(32rem,70vh)] flex-col">
          <div className="flex items-baseline gap-2 border-b border-border px-3 py-2.5">
            <span className="text-sm font-medium text-foreground">Usage</span>
            {data !== null && data.geniro !== null ? (
              <span
                data-slot="app-usage-total"
                className="ml-auto text-xs text-muted-foreground tabular-nums">
                {data.total.processes} processes ·{' '}
                {formatCpu(data.total.cpuPercent)} ·{' '}
                <span className="font-medium text-foreground">
                  {formatMemory(data.total.rssBytes)}
                </span>
              </span>
            ) : null}
          </div>
          <div className="min-h-0 overflow-y-auto px-3 py-2">
            <AppUsageBody
              data={data}
              loading={loading}
              error={error}
              names={names}
              onOpenThread={(runId) => {
                onOpenThread?.(runId);
                onOpenChange(false);
              }}
              canOpen={onOpenThread !== undefined}
            />
          </div>
        </div>
      </Popover>
    </>
  );
}

function AppUsageBody({
  data,
  loading,
  error,
  names,
  onOpenThread,
  canOpen,
}: {
  data: AppProcessesDto | null;
  loading: boolean;
  error: string | null;
  names: (kind: string) => string;
  onOpenThread: (runId: string) => void;
  canOpen: boolean;
}): React.JSX.Element {
  if (data === null) {
    return (
      <p className="py-2 text-xs text-muted-foreground">
        {error ?? (loading ? 'reading processes…' : 'not read yet')}
      </p>
    );
  }
  if (data.unavailableReason !== null) {
    return (
      <p className="py-2 text-xs text-muted-foreground">
        {data.unavailableReason}
      </p>
    );
  }
  const whole = data.total.rssBytes;
  return (
    <div className="flex flex-col gap-2">
      <ProcessFigureHeader label="threads" className="px-1.5" />
      {data.threads.length === 0 ? (
        <p className="text-xs text-muted-foreground">
          no agent is running right now
        </p>
      ) : (
        <ul
          aria-label="Threads"
          className="m-0 flex list-none flex-col gap-0.5 p-0">
          {data.threads.map((thread) => (
            <li key={thread.runId}>
              <button
                type="button"
                data-slot="app-usage-thread"
                disabled={!canOpen}
                onClick={() => onOpenThread(thread.runId)}
                title={canOpen ? 'Open this thread' : undefined}
                className="flex w-full flex-col gap-1 rounded-md px-1.5 py-1.5 text-left outline-none enabled:hover:bg-muted focus-visible:ring-2 focus-visible:ring-ring/50">
                <span className="flex w-full items-baseline gap-1.5 text-xs">
                  <span className="min-w-0 flex-1 truncate font-medium text-foreground">
                    {thread.title ?? 'Untitled thread'}
                  </span>
                  <ProcessFigureCells
                    cpuPercent={thread.figures.cpuPercent}
                    rssBytes={thread.figures.rssBytes}
                    strong
                  />
                </span>
                <span className="truncate text-[11px] text-muted-foreground">
                  {threadMeta(thread, names)}
                </span>
                <ShareBar
                  fraction={share(thread.figures.rssBytes, whole)}
                  label={`${Math.round(share(thread.figures.rssBytes, whole) * 100)}% of the app’s memory`}
                />
              </button>
            </li>
          ))}
        </ul>
      )}
      {data.geniro === null ? null : (
        <div
          data-slot="app-usage-geniro"
          title="The window, the daemon and the terminal panel’s shells"
          className="flex flex-col gap-1 border-t border-border px-1.5 pt-2">
          <span className="flex items-baseline gap-1.5 text-xs">
            <span className="min-w-0 flex-1 truncate font-medium text-foreground">
              Geniro
            </span>
            <ProcessFigureCells
              cpuPercent={data.geniro.cpuPercent}
              rssBytes={data.geniro.rssBytes}
              strong
            />
          </span>
          <span className="text-[11px] text-muted-foreground">
            app, daemon and terminals · {data.geniro.processes} processes
          </span>
          <ShareBar
            fraction={share(data.geniro.rssBytes, whole)}
            label={`${Math.round(share(data.geniro.rssBytes, whole) * 100)}% of the app’s memory`}
          />
        </div>
      )}
      {error === null ? null : (
        <p className="text-[11px] text-muted-foreground">{error}</p>
      )}
    </div>
  );
}
