// @vitest-environment jsdom
import { act, type ReactElement } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type {
  ArchiveChatLessonsEnum,
  ThreadLessonEstimateDto,
} from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import {
  archiveDialogCopy,
  type ArchiveTarget,
  ArchiveThreadDialog,
  useArchiveThread,
} from './archive-thread-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const SETTLED: ArchiveTarget = {
  id: 'run-1',
  label: 'Fix the login redirect',
  running: false,
  isTeam: false,
};

const LESSONS: ThreadLessonEstimateDto = {
  signals: 4,
  lessonsOn: true,
  estimate: {
    agentKind: 'claude',
    model: 'claude-haiku-5-5',
    tokens: 42_000,
    usd: 0.21,
  },
  typical: {
    runs: 14,
    usd: 0.13,
    durationMs: 134_000,
    model: 'claude-haiku-5-5',
    sameModel: true,
  },
  check: null,
  fromSeq: 1,
  toSeq: 120,
};

describe('archiveDialogCopy', () => {
  it('asks to archive a settled chat', () => {
    expect(archiveDialogCopy(SETTLED)).toEqual({
      title: 'Archive chat',
      confirmLabel: 'Archive',
    });
  });

  it('names the cancel when the chat is running', () => {
    expect(archiveDialogCopy({ ...SETTLED, running: true })).toEqual({
      title: 'Archive a running chat',
      confirmLabel: 'Cancel turn & archive',
    });
  });

  it('archives a settled team run as a run', () => {
    expect(archiveDialogCopy({ ...SETTLED, isTeam: true })).toEqual({
      title: 'Archive run',
      confirmLabel: 'Archive',
    });
  });

  it('stops a running team run as a run', () => {
    expect(
      archiveDialogCopy({ ...SETTLED, isTeam: true, running: true }),
    ).toEqual({
      title: 'Archive a run in progress',
      confirmLabel: 'Stop run & archive',
    });
  });

  it('falls back to the chat copy with no target', () => {
    expect(archiveDialogCopy(null)).toEqual({
      title: 'Archive chat',
      confirmLabel: 'Archive',
    });
  });
});

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function button(label: string): HTMLButtonElement {
  const found = [
    ...container.querySelectorAll<HTMLButtonElement>('button'),
  ].find((el) => el.textContent?.trim() === label);
  if (!found) {
    throw new Error(`no "${label}" button (saw: ${container.textContent})`);
  }
  return found;
}

function checkbox(): HTMLInputElement | null {
  return container.querySelector<HTMLInputElement>('input[type="checkbox"]');
}

function renderDialog({
  target = SETTLED,
  lessons = null,
  extractLessons = false,
  lessonModel = null,
  onExtractLessonsChange = vi.fn(),
}: {
  target?: ArchiveTarget | null;
  lessons?: ThreadLessonEstimateDto | null;
  extractLessons?: boolean;
  lessonModel?: string | null;
  onExtractLessonsChange?: (extract: boolean) => void;
} = {}): void {
  act(() => {
    root.render(
      <ArchiveThreadDialog
        target={target}
        busy={false}
        error={null}
        lessons={lessons}
        extractLessons={extractLessons}
        lessonModel={lessonModel}
        onExtractLessonsChange={onExtractLessonsChange}
        onCancel={vi.fn()}
        onConfirm={vi.fn()}
      />,
    );
  });
}

describe('ArchiveThreadDialog', () => {
  it('draws the destructive copy for a running chat', () => {
    renderDialog({ target: { ...SETTLED, running: true } });

    expect(container.textContent).toContain('Archive a running chat');
    expect(container.textContent).toContain(
      'stops the turn and closes its agent session first',
    );
    expect(button('Cancel turn & archive')).toBeTruthy();
  });

  it('draws the run copy for a running team run, every agent in it stopped', () => {
    renderDialog({ target: { ...SETTLED, running: true, isTeam: true } });

    expect(container.textContent).toContain('Archive a run in progress');
    expect(container.textContent).toContain(
      'stops the run and every agent still working in it first',
    );
    expect(container.textContent).not.toContain('stops the turn');
  });

  it('draws the plain copy for a settled chat, with nothing stopped', () => {
    renderDialog();

    expect(container.textContent).not.toContain('stops the turn');
    expect(button('Archive')).toBeTruthy();
  });

  it('offers the lessons choice only when the thread has learning signals', () => {
    renderDialog({ lessons: { ...LESSONS, signals: 0 } });
    expect(checkbox()).toBeNull();

    renderDialog({ lessons: null });
    expect(checkbox()).toBeNull();

    renderDialog({ lessons: LESSONS });
    expect(checkbox()).not.toBeNull();
    expect(container.textContent).toContain('Extract lessons from this thread');
  });

  it('says what extracting does and what finished runs typically cost and took', () => {
    renderDialog({ lessons: LESSONS, lessonModel: 'Haiku 5.5' });

    expect(container.textContent).toContain(
      'a background agent (Haiku 5.5) reads the thread and saves up to 3 lessons to memory',
    );
    expect(container.textContent).toContain('Progress shows in the top bar');
    expect(
      container.querySelector('[data-slot="archive-lessons-typical"]')
        ?.textContent,
    ).toBe('Usually ~$0.13 and ~2m — median of the last 14 runs on Haiku 5.5');
    expect(container.textContent).not.toContain('$0.21');
  });

  it('says the cost is not measured yet before any extraction finished', () => {
    renderDialog({ lessons: { ...LESSONS, typical: null } });

    expect(
      container.querySelector('[data-slot="archive-lessons-typical"]')
        ?.textContent,
    ).toBe('Cost not measured yet — no extraction has finished so far');
  });

  it('reports the lessons choice when its box is toggled', () => {
    const onExtractLessonsChange = vi.fn();
    renderDialog({
      lessons: LESSONS,
      extractLessons: true,
      onExtractLessonsChange,
    });

    act(() => {
      checkbox()?.click();
    });

    expect(onExtractLessonsChange).toHaveBeenCalledWith(false);
  });
});

type Archive = (
  target: ArchiveTarget,
  lessons: ArchiveChatLessonsEnum | undefined,
) => Promise<void>;

function Harness({
  lessonsApi,
  archive,
  target,
}: {
  lessonsApi: DaemonApis['lessons'];
  archive: Archive;
  target: ArchiveTarget;
}): ReactElement {
  const flow = useArchiveThread({ lessonsApi, agentsApi: null, archive });
  return (
    <>
      <button type="button" onClick={() => flow.ask(target)}>
        Open
      </button>
      {flow.dialog}
    </>
  );
}

function renderFlow({
  signals = LESSONS.signals,
  lessonsOn = LESSONS.lessonsOn,
  archive = vi.fn<Archive>(() => Promise.resolve()),
}: {
  signals?: number;
  lessonsOn?: boolean;
  archive?: Archive;
} = {}): {
  estimateLessons: ReturnType<typeof vi.fn>;
  archive: Archive;
} {
  const estimateLessons = vi.fn(() =>
    Promise.resolve({ ...LESSONS, signals, lessonsOn }),
  );
  const lessonsApi = { estimateLessons } as unknown as DaemonApis['lessons'];
  act(() => {
    root.render(
      <Harness lessonsApi={lessonsApi} archive={archive} target={SETTLED} />,
    );
  });
  return { estimateLessons, archive };
}

async function openDialog(): Promise<void> {
  await act(async () => {
    button('Open').click();
  });
}

async function press(label: string): Promise<void> {
  await act(async () => {
    button(label).click();
  });
}

describe('useArchiveThread', () => {
  it('asks for the lessons estimate of the thread it opens', async () => {
    const { estimateLessons } = renderFlow();

    await openDialog();

    expect(estimateLessons).toHaveBeenCalledWith({ runId: 'run-1' });
    expect(container.textContent).toContain('Archive chat');
  });

  it('archives with reflection when the thread has signals and the lessons box stays on', async () => {
    const { archive } = renderFlow();
    await openDialog();

    await press('Archive');

    expect(archive).toHaveBeenCalledWith(SETTLED, 'reflect');
    expect(container.querySelector('[role="dialog"]')).toBeNull();
  });

  it('archives with skip when the lessons box is unchecked', async () => {
    const { archive } = renderFlow();
    await openDialog();

    await act(async () => {
      checkbox()?.click();
    });
    await press('Archive');

    expect(archive).toHaveBeenCalledWith(SETTLED, 'skip');
  });

  it('archives with no lessons choice when the thread has no signals', async () => {
    const { archive } = renderFlow({ signals: 0 });
    await openDialog();

    await press('Archive');

    expect(archive).toHaveBeenCalledWith(SETTLED, undefined);
  });

  it('keeps the dialog up with the error when the archive fails', async () => {
    const archive = vi.fn<Archive>(() =>
      Promise.reject(new Error('the daemon is not reachable')),
    );
    renderFlow({ archive });
    await openDialog();

    await press('Archive');

    expect(container.querySelector('[role="dialog"]')).not.toBeNull();
    expect(container.textContent).toContain('the daemon is not reachable');
    expect(button('Archive')).toBeTruthy();
  });

  it('closes on Cancel without archiving', async () => {
    const { archive } = renderFlow();
    await openDialog();

    await press('Cancel');

    expect(archive).not.toHaveBeenCalled();
    expect(container.querySelector('[role="dialog"]')).toBeNull();
  });
});
