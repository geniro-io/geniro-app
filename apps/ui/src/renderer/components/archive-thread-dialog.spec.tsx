type Archive = (
  target: ArchiveTarget,
  lessons: ArchiveChatLessonsEnum | undefined,
) => Promise<void>;

function Harness({
  lessonsApi,
  teamsApi = null,
  chatsApi = null,
  archive,
  target,
}: {
  lessonsApi: DaemonApis['lessons'];
  teamsApi?: DaemonApis['teams'] | null;
  chatsApi?: DaemonApis['chats'] | null;
  archive: Archive;
  target: ArchiveTarget;
}): ReactElement {
  const flow = useArchiveThread({
    lessonsApi,
    agentsApi: null,
    teamsApi,
    chatsApi,
    archive,
  });
  return (
    <>
      <button type="button" onClick={() => flow.ask(target)}>
        Open
      </button>
      {flow.dialog}
    </>
  );
}

function renderFlow({
  signals = LESSONS.signals,
  lessonsOn = LESSONS.lessonsOn,
  archive = vi.fn<Archive>(() => Promise.resolve()),
}: {
  signals?: number;
  lessonsOn?: boolean;
  archive?: Archive;
} = {}): {
  estimateLessons: ReturnType<typeof vi.fn>;
  archive: Archive;
} {
  const estimateLessons = vi.fn(() =>
    Promise.resolve({ ...LESSONS, signals, lessonsOn }),
  );
  const lessonsApi = { estimateLessons } as unknown as DaemonApis['lessons'];
  act(() => {
    root.render(
      <Harness lessonsApi={lessonsApi} archive={archive} target={SETTLED} />,
    );
  });
  return { estimateLessons, archive };
}

async function openDialog(): Promise<void> {
  await act(async () => {
    button('Open').click();
  });
}

async function press(label: string): Promise<void> {
  await act(async () => {
    button(label).click();
  });
}

describe('useArchiveThread', () => {
  it('asks for the lessons estimate of the thread it opens', async () => {
    const { estimateLessons } = renderFlow();

    await openDialog();

    expect(estimateLessons).toHaveBeenCalledWith({ runId: 'run-1' });
    expect(container.textContent).toContain('Archive chat');
  });

  it('archives with reflection when the thread has signals and the lessons box stays on', async () => {
    const { archive } = renderFlow();
    await openDialog();

    await press('Archive');

    expect(archive).toHaveBeenCalledWith(SETTLED, 'reflect');
    expect(container.querySelector('[role="dialog"]')).toBeNull();
  });

  it('archives with skip when the lessons box is unchecked', async () => {
    const { archive } = renderFlow();
    await openDialog();

    await act(async () => {
      checkbox()?.click();
    });
    await press('Archive');

    expect(archive).toHaveBeenCalledWith(SETTLED, 'skip');
  });

  it('archives with no lessons choice when the thread has no signals', async () => {
    const { archive } = renderFlow({ signals: 0 });
    await openDialog();

    await press('Archive');

    expect(archive).toHaveBeenCalledWith(SETTLED, undefined);
  });

  it('keeps the dialog up with the error when the archive fails', async () => {
    const archive = vi.fn<Archive>(() =>
      Promise.reject(new Error('the daemon is not reachable')),
    );
    renderFlow({ archive });
    await openDialog();

    await press('Archive');

    expect(container.querySelector('[role="dialog"]')).not.toBeNull();
    expect(container.textContent).toContain('the daemon is not reachable');
    expect(button('Archive')).toBeTruthy();
  });

  it('closes on Cancel without archiving', async () => {
    const { archive } = renderFlow();
    await openDialog();

    await press('Cancel');

    expect(archive).not.toHaveBeenCalled();
    expect(container.querySelector('[role="dialog"]')).toBeNull();
  });
});

describe('useArchiveThread — a running team run', () => {
  function renderTeamFlow(
    teamsApi: DaemonApis['teams'],
    target: ArchiveTarget,
  ) {
    const lessonsApi = {
      estimateLessons: vi.fn(() => Promise.resolve({ ...LESSONS, signals: 0 })),
    } as unknown as DaemonApis['lessons'];
    act(() => {
      root.render(
        <Harness
          lessonsApi={lessonsApi}
          teamsApi={teamsApi}
          archive={vi.fn<Archive>(() => Promise.resolve())}
          target={target}
        />,
      );
    });
  }

  function items(): string[] {
    return [
      ...container.querySelectorAll('[data-slot="archive-still-running"] li'),
    ].map((item) => item.textContent ?? '');
  }

  function teamsApiOf(nodes: Promise<unknown>) {
    const listTeamRunNodes = vi.fn(() => nodes);
    const getTeamRunSnapshot = vi.fn(() =>
      Promise.resolve({
        team: {
          members: [
            { id: 'senior', name: 'Tony Stark' },
            { id: 'handyman', name: 'Groot' },
          ],
        },
      }),
    );
    return {
      api: {
        listTeamRunNodes,
        getTeamRunSnapshot,
      } as unknown as DaemonApis['teams'],
      listTeamRunNodes,
      getTeamRunSnapshot,
    };
  }

  it('names the members whose turn or call is running, read when it opens', async () => {
    const { api, listTeamRunNodes, getTeamRunSnapshot } = teamsApiOf(
      Promise.resolve([
        { memberId: 'senior', status: 'running' },
        { memberId: 'handyman', status: 'completed' },
      ]),
    );
    renderTeamFlow(api, RUNNING_TEAM);

    await openDialog();

    expect(listTeamRunNodes).toHaveBeenCalledWith({ runId: 'run-1' });
    expect(getTeamRunSnapshot).toHaveBeenCalledWith({ runId: 'run-1' });
    expect(items()).toEqual(['Working: Tony Stark']);
  });

  it('names a running member the snapshot does not list by its id', async () => {
    const { api } = teamsApiOf(
      Promise.resolve([{ memberId: 'reviewer', status: 'running' }]),
    );
    renderTeamFlow(api, RUNNING_TEAM);

    await openDialog();

    expect(items()).toEqual(['Working: reviewer']);
  });

  it('drops a members answer that lands after the dialog closed', async () => {
    let answerNodes: (nodes: unknown) => void = () => undefined;
    const { api, listTeamRunNodes } = teamsApiOf(new Promise(() => {}));
    listTeamRunNodes.mockReturnValueOnce(
      new Promise((resolve) => {
        answerNodes = resolve;
      }),
    );
    renderTeamFlow(api, RUNNING_TEAM);
    await openDialog();
    await press('Cancel');
    await openDialog();

    await act(async () => {
      answerNodes([{ memberId: 'senior', status: 'running' }]);
    });

    expect(items()).toEqual(['The run']);
  });

  it('still says the run is working when its members cannot be read', async () => {
    const { api } = teamsApiOf(Promise.reject(new Error('gone')));
    renderTeamFlow(api, RUNNING_TEAM);

    await openDialog();

    expect(items()).toEqual(['The run']);
    expect(button('Stop run & archive')).toBeTruthy();
  });

  it('reads no members for a team run that is not running', async () => {
    const { api, listTeamRunNodes } = teamsApiOf(Promise.resolve([]));
    renderTeamFlow(api, SETTLED_TEAM_WITH_BACKGROUND);

    await openDialog();

    expect(listTeamRunNodes).not.toHaveBeenCalled();
    expect(items()).toEqual(['1 background command', '2 monitors']);
  });
});

