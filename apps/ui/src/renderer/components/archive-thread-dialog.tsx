import { useEffect, useState } from 'react';

import type {
  ArchiveChatLessonsEnum,
  RunDto,
  ThreadLessonEstimateDto,
} from '../autogenerated';
import {
  lessonExtractionTitle,
  lessonTypicalLabel,
} from '../chats/lesson-labels';
import { useModelDisplayName } from '../chats/use-model-display-name';
import type { DaemonApis } from '../daemon-api';
import { memberLabels } from '../teams/member-pick';
import { ConfirmDialog } from './confirm-dialog';
import { useLatestCallback } from './use-latest-callback';

/** What a thread still has running, every part of which an archive stops. */
export interface ArchiveWork {
  /** Its turn (a chat) or its run (a team) is in flight. */
  running: boolean;
  subagents: number;
  commands: number;
  monitors: number;
}

/** The thread an archive asks about. */
export interface ArchiveTarget {
  id: string;
  /** What the dialog calls it: its title, its team's name, or its agent. */
  label: string;
  work: ArchiveWork;
  isTeam: boolean;
}

/** What a run still has running, as the daemon counts it on the run row. */
export function archiveWorkOf(
  run: Pick<RunDto, 'status' | 'subagentsOut' | 'shellsOpen' | 'monitorsOpen'>,
): ArchiveWork {
  return {
    running: run.status === 'running',
    subagents: run.subagentsOut,
    commands: run.shellsOpen,
    monitors: run.monitorsOpen,
  };
}

function backgroundOf(work: ArchiveWork): number {
  return work.subagents + work.commands + work.monitors;
}

/** Whether the archive stops anything on its way. */
export function archiveStopsWork(target: ArchiveTarget | null): boolean {
  return (
    target !== null && (target.work.running || backgroundOf(target.work) > 0)
  );
}

/**
 * The dialog's title and button for one archive. A team run is stopped as a
 * RUN, every agent in it, where a chat's cancel is one turn; it says `run`,
 * never `team`, because the library team is untouched.
 */
export function archiveDialogCopy(target: ArchiveTarget | null): {
  title: string;
  confirmLabel: string;
} {
  const running = target?.work.running === true;
  const stops = archiveStopsWork(target);
  if (target?.isTeam === true) {
    return {
      title: running ? 'Archive a run in progress' : 'Archive run',
      confirmLabel: running
        ? 'Stop run & archive'
        : stops
          ? 'Stop & archive'
          : 'Archive',
    };
  }
  return {
    title: running ? 'Archive a running chat' : 'Archive chat',
    confirmLabel: running
      ? 'Cancel turn & archive'
      : stops
        ? 'Stop & archive'
        : 'Archive',
  };
}

function counted(count: number, one: string, many: string): string {
  return `${count} ${count === 1 ? one : many}`;
}

/**
 * One line per part of the thread still running. `workers` names the team
 * members working in a running run; null while they are being read or when
 * they could not be read.
 */
export function stillRunningLines(
  target: ArchiveTarget,
  workers: readonly string[] | null,
): string[] {
  const { work } = target;
  const lines: string[] = [];
  if (work.running) {
    if (!target.isTeam) {
      lines.push('Its turn');
    } else if (workers === null || workers.length === 0) {
      lines.push('The run');
    } else {
      lines.push(`Working: ${workers.join(', ')}`);
    }
  }
  if (work.subagents > 0) {
    lines.push(
      counted(work.subagents, 'background sub-agent', 'background sub-agents'),
    );
  }
  if (work.commands > 0) {
    lines.push(
      counted(work.commands, 'background command', 'background commands'),
    );
  }
  if (work.monitors > 0) {
    lines.push(counted(work.monitors, 'monitor', 'monitors'));
  }
  return lines;
}

/**
 * The one confirm every archive asks. A settled thread is only filed away, so
 * it is told what that costs (the row) and what it does not (the
 * conversation); a thread with work in flight has that work stopped, the one
 * part of archiving that destroys something, and only it is drawn destructive.
 */
export function ArchiveThreadDialog({
  target,
  workers = null,
  busy,
  error,
  lessons,
  extractLessons,
  lessonModel,
  onExtractLessonsChange,
  onCancel,
  onConfirm,
}: {
  target: ArchiveTarget | null;
  /** The members working in a running team run, once read. */
  workers?: readonly string[] | null;
  busy: boolean;
  error: string | null;
  lessons: ThreadLessonEstimateDto | null;
  extractLessons: boolean;
  lessonModel: string | null;
  onExtractLessonsChange: (extract: boolean) => void;
  onCancel: () => void;
  onConfirm: () => void;
}): React.JSX.Element {
  const copy = archiveDialogCopy(target);
  const label = target?.label ?? '';
  const stops = archiveStopsWork(target);
  return (
    <ConfirmDialog
      open={target !== null}
      busy={busy}
      error={error}
      title={copy.title}
      confirmLabel={copy.confirmLabel}
      confirmVariant={stops ? 'destructive' : 'default'}
      busyLabel="Archiving…"
      onCancel={onCancel}
      onConfirm={onConfirm}>
      {target !== null && stops ? (
        <>
          Still running in <strong>{label}</strong>:
          <ul
            data-slot="archive-still-running"
            className="mt-1.5 mb-1.5 list-disc pl-5 text-foreground">
            {stillRunningLines(target, workers).map((line) => (
              <li key={line}>{line}</li>
            ))}
          </ul>
          Archiving stops all of it first — whatever is part-way through is
          lost. The transcript itself is kept, and you can unarchive it at any
          time.
        </>
      ) : (
        <>
          Archive <strong>{label}</strong>? It leaves the list and nothing is
          deleted — the transcript is kept, and you can unarchive it at any
          time.
        </>
      )}
      {lessons !== null && lessons.signals > 0 ? (
        <label
          data-slot="archive-extract-lessons"
          title={lessonExtractionTitle(lessons, lessonModel)}
          className="mt-3 grid grid-cols-[auto_1fr] items-center gap-x-2 gap-y-0.5 text-foreground">
          <input
            type="checkbox"
            className="size-4 accent-primary"
            checked={extractLessons}
            onChange={(event) => onExtractLessonsChange(event.target.checked)}
          />
          <span>Extract lessons from this thread</span>
          <span
            data-slot="archive-lessons-typical"
            className="col-start-2 text-xs text-muted-foreground">
            {lessonTypicalLabel(lessons.typical, lessonModel)}
          </span>
        </label>
      ) : null}
    </ConfirmDialog>
  );
}

/** What `useArchiveThread` hands its screen: the opener and the dialog to draw. */
export interface ArchiveThreadFlow {
  ask: (target: ArchiveTarget) => void;
  dialog: React.JSX.Element;
}

/**
 * Every archive asks first, through {@link ArchiveThreadDialog}: the screen
 * calls `ask`, draws `dialog`, and `archive` runs only on the confirm, with
 * the lessons choice when the thread offers one. A failed archive keeps the
 * dialog up with its error.
 */
export function useArchiveThread({
  lessonsApi,
  agentsApi,
  teamsApi = null,
  archive,
}: {
  lessonsApi: DaemonApis['lessons'] | null;
  agentsApi: DaemonApis['agents'] | null;
  /** Reads which members a running team run has working; null reads none. */
  teamsApi?: DaemonApis['teams'] | null;
  archive: (
    target: ArchiveTarget,
    lessons: ArchiveChatLessonsEnum | undefined,
  ) => Promise<void>;
}): ArchiveThreadFlow {
  const [target, setTarget] = useState<ArchiveTarget | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [lessons, setLessons] = useState<ThreadLessonEstimateDto | null>(null);
  const [extractChoice, setExtractChoice] = useState<boolean | null>(null);
  const [workers, setWorkers] = useState<readonly string[] | null>(null);
  const targetId = target?.id ?? null;
  const teamRunning = target !== null && target.isTeam && target.work.running;
  useEffect(() => {
    if (targetId === null || !teamRunning || teamsApi === null) {
      return;
    }
    let live = true;
    Promise.all([
      teamsApi.listTeamRunNodes({ runId: targetId }),
      teamsApi.getTeamRunSnapshot({ runId: targetId }),
    ])
      .then(([nodes, { team }]) => {
        if (!live) {
          return;
        }
        const labels = memberLabels(team.members);
        setWorkers(
          nodes
            .filter((node) => node.status === 'running')
            .map((node) => labels.get(node.memberId) ?? node.memberId),
        );
      })
      .catch(() => {
        if (live) {
          setWorkers(null);
        }
      });
    return () => {
      live = false;
    };
  }, [teamsApi, targetId, teamRunning]);
  useEffect(() => {
    if (targetId === null || lessonsApi === null) {
      return;
    }
    let live = true;
    lessonsApi
      .estimateLessons({ runId: targetId })
      .then((answer) => {
        if (live) {
          setLessons(answer);
        }
      })
      .catch(() => {
        if (live) {
          setLessons(null);
        }
      });
    return () => {
      live = false;
    };
  }, [lessonsApi, targetId]);
  const lessonModel = useModelDisplayName(
    agentsApi,
    lessons?.estimate.agentKind ?? null,
    lessons?.estimate.model ?? null,
  );
  const offersLessons = lessons !== null && lessons.signals > 0;
  const extractLessons = extractChoice ?? lessons?.lessonsOn ?? false;

  const ask = useLatestCallback((next: ArchiveTarget): void => {
    setError(null);
    setLessons(null);
    setExtractChoice(null);
    setWorkers(null);
    setTarget(next);
  }, []);

  const confirm = useLatestCallback(async (): Promise<void> => {
    if (target === null) {
      return;
    }
    setBusy(true);
    setError(null);
    try {
      await archive(
        target,
        offersLessons ? (extractLessons ? 'reflect' : 'skip') : undefined,
      );
      setTarget(null);
    } catch (err) {
      setError(String(err));
    } finally {
      setBusy(false);
    }
  }, [target, archive, offersLessons, extractLessons]);

  return {
    ask,
    dialog: (
      <ArchiveThreadDialog
        target={target}
        workers={workers}
        busy={busy}
        error={error}
        lessons={lessons}
        extractLessons={extractLessons}
        lessonModel={lessonModel}
        onExtractLessonsChange={setExtractChoice}
        onCancel={() => setTarget(null)}
        onConfirm={() => void confirm()}
      />
    ),
  };
}
