import type { BackgroundJob } from '../autogenerated';
import { formatUsd } from '../chats/agent-activity';
import { formatRelativeTime } from '../chats/relative-time';
import { formatDuration } from '../stats/stats-format';

const KIND_TITLES: Record<BackgroundJob['kind'], string> = {
  lessons: 'Extract lessons',
};

const PHASE_WORDS: Record<string, string> = {
  reflecting: 'Reading the thread…',
  checking: 'Checking the lessons it found…',
};

/** What kind of work a job is, in the user's words. */
export function backgroundJobTitle(job: BackgroundJob): string {
  return KIND_TITLES[job.kind];
}

/** The thread a job works for, or a stand-in for one with no title or gone. */
export function backgroundJobThread(job: BackgroundJob): string {
  return job.title?.trim() || 'Untitled thread';
}

/** A count with its noun: `1 lesson`, `2 lessons`. */
function lessons(count: number): string {
  return `${count} lesson${count === 1 ? '' : 's'}`;
}

/**
 * Where a job stands, or what it ended with: "Reading the thread…",
 * "2 lessons saved · 1 waiting for review", "No lessons found", or why it
 * failed.
 */
export function backgroundJobResult(job: BackgroundJob): string {
  switch (job.status) {
    case 'queued':
      return 'Waiting to start';
    case 'running':
      return (job.phase === null ? null : PHASE_WORDS[job.phase]) ?? 'Working…';
    case 'failed':
      return job.error?.trim() || 'Failed';
    default:
      break;
  }
  if (job.lessons === null) {
    return 'Done';
  }
  const { saved, waiting, dropped } = job.lessons;
  const parts = [
    saved > 0 ? `${lessons(saved)} saved` : null,
    waiting > 0 ? `${lessons(waiting)} waiting for review` : null,
    dropped > 0 ? `${lessons(dropped)} dropped` : null,
  ].filter((part): part is string => part !== null);
  return parts.length === 0 ? 'No lessons found' : parts.join(' · ');
}

/** Whether a job left something the user should look at in Settings → Memory. */
export function backgroundJobWaitsForReview(job: BackgroundJob): boolean {
  return (job.lessons?.waiting ?? 0) > 0;
}

/** Cost, time and when: `$0.28 · 34s · 5m ago`; a figure nothing reported is left out. */
export function backgroundJobMeta(
  job: BackgroundJob,
  now: number = Date.now(),
): string {
  const when = formatRelativeTime(job.endedAt ?? job.startedAt, now);
  return [
    job.costUsd === null ? null : formatUsd(job.costUsd),
    job.durationMs === null ? null : formatDuration(job.durationMs),
    /^\d+[mhd]$/.test(when) ? `${when} ago` : when,
  ]
    .filter((part): part is string => part !== null && part !== '')
    .join(' · ');
}
