import { CircleAlert, CircleCheck, Clock, Sparkles } from 'lucide-react';

import type { BackgroundJob } from '../autogenerated';
import {
  backgroundJobMeta,
  backgroundJobResult,
  backgroundJobThread,
  backgroundJobTitle,
  backgroundJobWaitsForReview,
} from './background-job-labels';
import { Spinner } from './ui/spinner';
import { cn } from './ui/utils';

function StatusGlyph({
  status,
}: {
  status: BackgroundJob['status'];
}): React.JSX.Element {
  switch (status) {
    case 'running':
      return <Spinner className="size-3.5" />;
    case 'queued':
      return (
        <Clock
          aria-hidden="true"
          className="size-3.5 shrink-0 text-muted-foreground"
        />
      );
    case 'failed':
      return (
        <CircleAlert
          aria-hidden="true"
          className="size-3.5 shrink-0 text-destructive"
        />
      );
    default:
      return (
        <CircleCheck
          aria-hidden="true"
          className="size-3.5 shrink-0 text-success"
        />
      );
  }
}

/**
 * One background job, the same in the title bar's panel and in the full
 * history: what it is, for which thread, where it stands or what it ended
 * with, and its cost, time and when. The row opens its thread; a result that
 * waits for review offers the way to it.
 */
export function BackgroundJobRow({
  job,
  now,
  onOpenThread,
  onReview,
}: {
  job: BackgroundJob;
  now?: number;
  onOpenThread?: (runId: string) => void;
  onReview?: () => void;
}): React.JSX.Element {
  const result = backgroundJobResult(job);
  const meta = backgroundJobMeta(job, now);
  const canOpen = onOpenThread !== undefined && job.runId !== null;
  const reviewable = onReview !== undefined && backgroundJobWaitsForReview(job);
  return (
    <div
      data-slot="background-job"
      data-status={job.status}
      className="flex items-start gap-2 rounded-md px-1.5 py-1.5 hover:bg-muted">
      <span className="mt-0.5 flex size-3.5 items-center justify-center">
        <StatusGlyph status={job.status} />
      </span>
      <div className="flex min-w-0 flex-1 flex-col gap-0.5 text-xs">
        <button
          type="button"
          disabled={!canOpen}
          title={canOpen ? 'Open this thread' : undefined}
          onClick={() => {
            if (job.runId !== null) {
              onOpenThread?.(job.runId);
            }
          }}
          className="flex min-w-0 items-center gap-1.5 rounded-sm text-left text-xs outline-none focus-visible:ring-2 focus-visible:ring-ring/50 enabled:hover:underline">
          <Sparkles
            aria-hidden="true"
            className="size-3 shrink-0 text-muted-foreground"
          />
          <span className="shrink-0 text-muted-foreground">
            {backgroundJobTitle(job)}
          </span>
          <span className="min-w-0 truncate font-medium text-foreground">
            {backgroundJobThread(job)}
          </span>
        </button>
        <span
          data-slot="background-job-result"
          title={result}
          className={cn(
            'line-clamp-2 break-words',
            job.status === 'failed'
              ? 'text-destructive'
              : 'text-muted-foreground',
          )}>
          {result}
        </span>
        <span className="flex items-center gap-2 text-[11px] text-muted-foreground tabular-nums">
          <span data-slot="background-job-meta" title={job.model ?? undefined}>
            {meta}
          </span>
          {reviewable ? (
            <button
              type="button"
              data-slot="background-job-review"
              onClick={onReview}
              className="ml-auto shrink-0 rounded-sm text-[11px] text-primary outline-none hover:underline focus-visible:ring-2 focus-visible:ring-ring/50">
              Review in Memory
            </button>
          ) : null}
        </span>
      </div>
    </div>
  );
}
