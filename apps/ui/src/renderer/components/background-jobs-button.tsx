import { Layers } from 'lucide-react';
import { useRef } from 'react';

import type { BackgroundJob, BackgroundJobListDto } from '../autogenerated';
import { BackgroundJobRow } from './background-job-row';
import { TITLE_BAR_CONTROL } from './title-bar';
import { Popover } from './ui/popover';
import { Spinner } from './ui/spinner';
import { cn } from './ui/utils';

/**
 * The title bar's background work: a quiet glyph while nothing runs, a spinner
 * and the count while something is queued or running. Its panel lists the
 * active jobs, then the newest finished ones with what each filed or why it
 * failed, and leads to the full history.
 */
export function BackgroundJobsButton({
  open,
  onOpenChange,
  data,
  error,
  now,
  onOpenThread,
  onReview,
  onShowHistory,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  data: BackgroundJobListDto | null;
  error: string | null;
  now?: number;
  onOpenThread?: (runId: string) => void;
  onReview?: () => void;
  onShowHistory?: () => void;
}): React.JSX.Element {
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const running = data?.running ?? 0;
  const close = (): void => onOpenChange(false);
  const label =
    running === 0
      ? 'Background work'
      : `Background work — ${running} running or queued`;

  return (
    <>
      <button
        ref={triggerRef}
        type="button"
        data-slot="background-jobs-trigger"
        aria-label={label}
        aria-expanded={open}
        title={label}
        onClick={() => onOpenChange(!open)}
        className={cn(
          TITLE_BAR_CONTROL,
          'flex h-6 min-w-6 items-center justify-center gap-1 px-1',
          open && 'bg-sidebar-accent text-foreground',
        )}>
        {running === 0 ? (
          <Layers aria-hidden="true" className="size-3.5" />
        ) : (
          <>
            <Spinner className="size-3.5" />
            <span
              data-slot="background-jobs-count"
              className="text-xs font-medium tabular-nums text-foreground">
              {running}
            </span>
          </>
        )}
      </button>
      <Popover
        open={open}
        onClose={close}
        triggerRef={triggerRef}
        anchor="viewport"
        side="bottom"
        align="end"
        label="Background work"
        className="app-no-drag w-[24rem] p-0">
        <div className="flex max-h-[min(34rem,72vh)] flex-col">
          <div className="flex items-baseline gap-2 border-b border-border px-3 py-2.5">
            <span className="text-sm font-medium text-foreground">
              Background work
            </span>
            <span className="ml-auto text-xs text-muted-foreground tabular-nums">
              {running === 0 ? 'nothing running' : `${running} running`}
            </span>
          </div>
          <div className="min-h-0 overflow-y-auto px-1.5 py-1.5">
            <BackgroundJobsBody
              data={data}
              error={error}
              now={now}
              onOpenThread={
                onOpenThread === undefined
                  ? undefined
                  : (runId) => {
                      onOpenThread(runId);
                      close();
                    }
              }
              onReview={
                onReview === undefined
                  ? undefined
                  : () => {
                      onReview();
                      close();
                    }
              }
            />
          </div>
          {onShowHistory === undefined ? null : (
            <div className="border-t border-border px-3 py-2">
              <button
                type="button"
                data-slot="background-jobs-history"
                onClick={() => {
                  onShowHistory();
                  close();
                }}
                className="rounded-sm text-xs text-primary outline-none hover:underline focus-visible:ring-2 focus-visible:ring-ring/50">
                All runs
              </button>
            </div>
          )}
        </div>
      </Popover>
    </>
  );
}

function BackgroundJobsBody({
  data,
  error,
  now,
  onOpenThread,
  onReview,
}: {
  data: BackgroundJobListDto | null;
  error: string | null;
  now?: number;
  onOpenThread?: (runId: string) => void;
  onReview?: () => void;
}): React.JSX.Element {
  if (data === null) {
    return (
      <p className="px-1.5 py-2 text-xs text-muted-foreground">
        {error ?? 'reading…'}
      </p>
    );
  }
  if (data.active.length === 0 && data.finished.length === 0) {
    return (
      <p className="px-1.5 py-2 text-xs text-muted-foreground">
        Nothing has run in the background yet. Lessons extracted when you
        archive a thread show up here.
      </p>
    );
  }
  return (
    <div className="flex flex-col gap-1">
      {data.active.length === 0 ? null : (
        <JobSection
          label="Now"
          jobs={data.active}
          now={now}
          onOpenThread={onOpenThread}
          onReview={onReview}
        />
      )}
      {data.finished.length === 0 ? null : (
        <JobSection
          label="Recent"
          jobs={data.finished}
          now={now}
          onOpenThread={onOpenThread}
          onReview={onReview}
        />
      )}
      {error === null ? null : (
        <p className="px-1.5 text-[11px] text-muted-foreground">{error}</p>
      )}
    </div>
  );
}

function JobSection({
  label,
  jobs,
  now,
  onOpenThread,
  onReview,
}: {
  label: string;
  jobs: BackgroundJob[];
  now?: number;
  onOpenThread?: (runId: string) => void;
  onReview?: () => void;
}): React.JSX.Element {
  return (
    <section aria-label={label} className="flex flex-col">
      <span className="px-1.5 pt-1 pb-0.5 text-[11px] font-medium text-muted-foreground uppercase">
        {label}
      </span>
      {jobs.map((job) => (
        <BackgroundJobRow
          key={job.id}
          job={job}
          now={now}
          onOpenThread={onOpenThread}
          onReview={onReview}
        />
      ))}
    </section>
  );
}
