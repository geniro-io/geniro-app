import type { BackgroundJob } from '../autogenerated';
import { BackgroundJobRow } from './background-job-row';
import { Button } from './ui/button';
import { Dialog } from './ui/dialog';

/**
 * Every background job geniro has run, newest first, a page at a time: the
 * title bar's "All runs". The same rows as its panel, so a run reads alike in
 * both places.
 */
export function BackgroundJobsHistoryDialog({
  open,
  onClose,
  jobs,
  hasMore,
  loading,
  error,
  now,
  onLoadMore,
  onOpenThread,
  onReview,
}: {
  open: boolean;
  onClose: () => void;
  jobs: BackgroundJob[];
  hasMore: boolean;
  loading: boolean;
  error: string | null;
  now?: number;
  onLoadMore: () => void;
  onOpenThread?: (runId: string) => void;
  onReview?: () => void;
}): React.JSX.Element {
  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Background work — all runs"
      className="w-[32rem] max-w-[calc(100vw-2rem)]">
      <div
        data-slot="background-jobs-history-list"
        className="-mx-1.5 flex max-h-[min(36rem,70vh)] flex-col gap-0.5 overflow-y-auto">
        {jobs.length === 0 ? (
          <p className="px-1.5 py-2 text-xs text-muted-foreground">
            {loading
              ? 'reading…'
              : (error ?? 'Nothing has run in the background yet.')}
          </p>
        ) : (
          jobs.map((job) => (
            <BackgroundJobRow
              key={job.id}
              job={job}
              now={now}
              onOpenThread={
                onOpenThread === undefined
                  ? undefined
                  : (runId) => {
                      onOpenThread(runId);
                      onClose();
                    }
              }
              onReview={
                onReview === undefined
                  ? undefined
                  : () => {
                      onReview();
                      onClose();
                    }
              }
            />
          ))
        )}
      </div>
      {jobs.length > 0 && error !== null ? (
        <p className="mt-2 text-[11px] text-muted-foreground">{error}</p>
      ) : null}
      {hasMore ? (
        <div className="mt-3 flex justify-center">
          <Button
            variant="outline"
            size="sm"
            disabled={loading}
            onClick={onLoadMore}>
            {loading ? 'Loading…' : 'Load more'}
          </Button>
        </div>
      ) : null}
    </Dialog>
  );
}
