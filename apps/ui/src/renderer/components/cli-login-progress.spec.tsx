// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { LoginSessionDto } from '../autogenerated';
import { CliLoginProgress } from './cli-login-progress';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function session(overrides: Partial<LoginSessionDto> = {}): LoginSessionDto {
  return {
    id: 'login-1',
    agent: 'claude',
    status: 'waiting',
    url: null,
    message: null,
    ...overrides,
  } as LoginSessionDto;
}

function render(el: React.ReactNode): void {
  act(() => root.render(el));
}

function buttons(): HTMLButtonElement[] {
  return [...container.querySelectorAll('button')];
}

function byText(text: string): HTMLButtonElement | undefined {
  return buttons().find((b) => b.textContent?.includes(text));
}

const noop = { onSubmitCode: vi.fn(), onCancel: vi.fn(), onDismiss: vi.fn() };

describe('CliLoginProgress', () => {
  it('shows no code field while the CLI is only waiting on the browser', () => {
    // cursor's whole flow, and claude's first seconds. A field here would be a
    // dead input in front of a CLI that wants nothing.
    render(
      <CliLoginProgress
        session={session({ url: 'https://x.test/a' })}
        error={null}
        {...noop}
      />,
    );

    expect(container.querySelector('input')).toBeNull();
    expect(container.textContent).toContain('Waiting for you to finish');
  });

  it('offers the link as a COPY, never as a second auto-opened tab', () => {
    // The CLI opened the browser itself. A second tab on the same challenge
    // invalidates the first, so this control must copy and not navigate — an
    // anchor with an href would be the regression.
    render(
      <CliLoginProgress
        session={session({ url: 'https://x.test/a?challenge=1' })}
        error={null}
        {...noop}
      />,
    );

    expect(container.querySelector('a[href]')).toBeNull();
    expect(
      buttons().some(
        (b) => b.getAttribute('aria-label') === 'Copy sign-in link',
      ),
    ).toBe(true);
  });

  it('shows the code field ONLY in needs_code, and submits what was typed', () => {
    const onSubmitCode = vi.fn();
    render(
      <CliLoginProgress
        session={session({ status: 'needs_code' })}
        error={null}
        {...noop}
        onSubmitCode={onSubmitCode}
      />,
    );

    const input = container.querySelector('input');
    expect(input).not.toBeNull();
    // Through the native value setter, the idiom the sibling specs use: React
    // tracks the last value it wrote, so a direct `.value =` is seen as no change
    // and the state never updates.
    act(() => {
      Object.getOwnPropertyDescriptor(
        HTMLInputElement.prototype,
        'value',
      )!.set!.call(input, 'code-123');
      input!.dispatchEvent(new Event('input', { bubbles: true }));
    });
    act(() => {
      container
        .querySelector('form')!
        .dispatchEvent(
          new Event('submit', { bubbles: true, cancelable: true }),
        );
    });

    expect(onSubmitCode).toHaveBeenCalledWith('code-123');
  });

  it('will not submit a blank code', () => {
    // The daemon rejects it too, but a round-trip to be told off is not feedback.
    const onSubmitCode = vi.fn();
    render(
      <CliLoginProgress
        session={session({ status: 'needs_code' })}
        error={null}
        {...noop}
        onSubmitCode={onSubmitCode}
      />,
    );

    act(() => {
      container
        .querySelector('form')!
        .dispatchEvent(
          new Event('submit', { bubbles: true, cancelable: true }),
        );
    });

    expect(onSubmitCode).not.toHaveBeenCalled();
    expect(byText('Submit')?.disabled).toBe(true);
  });

  it('on the Mac, says to finish in the browser — the code is only a fallback', () => {
    // claude prints its code prompt on EVERY sign-in, so `needs_code` is the
    // usual state while the browser completes by itself. Headlining "paste the
    // code" is what got reported: "it's just asking for code, but I don't have
    // one — it should be automatic".
    render(
      <CliLoginProgress
        session={session({ status: 'needs_code' })}
        error={null}
        remote={false}
        {...noop}
      />,
    );

    expect(container.textContent).toContain(
      'Finish signing in in your browser',
    );
    expect(container.textContent).not.toMatch(/paste the code your browser/i);
    expect(container.querySelector('input')?.placeholder).toBe(
      'Browser shows a code? Paste it here',
    );
  });

  it('on a phone, sends the user through the link and asks for its code', () => {
    // The CLI opened the MAC's browser and waits on the Mac's localhost, so from
    // a phone the link below is the only way in, and its page shows the code.
    render(
      <CliLoginProgress
        session={session({ status: 'needs_code' })}
        error={null}
        remote={true}
        {...noop}
      />,
    );

    expect(container.textContent).toContain(
      'Open the sign-in page, sign in, then paste the code it shows',
    );
    expect(byText('Open sign-in page')).not.toBeNull();
  });

  it('offers Cancel while running and Dismiss once over — never the wrong one', () => {
    // Cancel on a finished run would reap nothing and read as though the result
    // could still be undone; Dismiss on a live one would abandon a child while
    // telling the user it was closed.
    const onCancel = vi.fn();
    const onDismiss = vi.fn();
    render(
      <CliLoginProgress
        session={session()}
        error={null}
        {...noop}
        onCancel={onCancel}
        onDismiss={onDismiss}
      />,
    );
    expect(byText('Dismiss')).toBeUndefined();
    act(() => byText('Cancel')?.click());
    expect(onCancel).toHaveBeenCalled();

    render(
      <CliLoginProgress
        session={session({ status: 'succeeded' })}
        error={null}
        {...noop}
        onCancel={onCancel}
        onDismiss={onDismiss}
      />,
    );
    expect(byText('Cancel')).toBeUndefined();
    act(() => byText('Dismiss')?.click());
    expect(onDismiss).toHaveBeenCalled();
  });

  it('keeps a SERVER sign-in spinning while the daemon checks the connection', () => {
    // A server's CLI can exit before the user has authorized anything, so
    // the daemon reports `verifying` until it SEES the server connect — and
    // that state must not read as finished.
    render(
      <CliLoginProgress
        session={session({ status: 'verifying' })}
        error={null}
        {...noop}
        scope="server"
      />,
    );

    expect(container.textContent).toContain('checking the connection');
    expect(container.textContent).not.toContain('Signed in');
    expect(byText('Cancel')).toBeDefined();
  });

  it('calls a SERVER sign-in connected once the daemon has seen it connect', () => {
    render(
      <CliLoginProgress
        session={session({ status: 'succeeded' })}
        error={null}
        {...noop}
        scope="server"
      />,
    );

    expect(container.textContent).toContain('Signed in — connected');
  });

  it('still calls an ACCOUNT sign-in finished, which genuinely is', () => {
    // The other half of the same switch: an account sign-in ends here — the
    // CLI takes the pasted code, checks it and exits — so weakening its wording
    // too would trade one wrong sentence for another.
    render(
      <CliLoginProgress
        session={session({ status: 'succeeded' })}
        error={null}
        {...noop}
      />,
    );

    expect(container.textContent).toContain('Sign-in finished');
  });

  it('states a failure instead of leaving a spinner turning', () => {
    render(
      <CliLoginProgress
        session={session({ status: 'failed', message: 'OAuth failed' })}
        error={null}
        {...noop}
      />,
    );

    expect(container.textContent).toContain('Sign-in did not complete');
    expect(container.textContent).toContain('OAuth failed');
    expect(container.querySelector('.animate-spin')).toBeNull();
  });

  it('keeps an inline ending on one line: the CLI’s line beside the headline, and none that only repeats it', () => {
    render(
      <CliLoginProgress
        session={session({ status: 'failed', message: 'OAuth failed' })}
        variant="inline"
        error="daemon refused"
        {...noop}
      />,
    );

    const row = container.querySelector(
      '[data-slot="cli-login-progress"] > div',
    );
    expect(row?.textContent).toContain('Sign-in did not complete');
    expect(row?.textContent).toContain('— OAuth failed');
    expect(row?.textContent).toContain('daemon refused');
    expect(
      container.querySelector('[data-slot="cli-login-progress"] > p'),
    ).toBeNull();

    render(
      <CliLoginProgress
        session={{
          status: 'timed-out',
          url: null,
          message: 'Sign-in timed out.',
        }}
        scope="share"
        variant="inline"
        error={null}
        {...noop}
      />,
    );

    expect(container.textContent).toContain('Not shared — sign-in timed out');
    expect(container.textContent).not.toContain('Sign-in timed out.');
  });

  it.each([
    ['waiting', 'Waiting for you to finish in the browser…'],
    ['verifying', 'Signed in — sharing…'],
    ['succeeded', 'Signed in'],
    ['cancelled', 'Not shared — sign-in cancelled'],
    ['timed-out', 'Not shared — sign-in timed out'],
    ['failed', 'Not shared — sign-in did not complete'],
  ] as const)(
    'words a share destination’s %s sign-in for what it means to the share',
    (status, headline) => {
      render(
        <CliLoginProgress
          session={{ status, url: null, message: null }}
          scope="share"
          onSubmitCode={vi.fn()}
          onCancel={vi.fn()}
          onDismiss={vi.fn()}
          error={null}
        />,
      );

      expect(container.textContent).toContain(headline);
      expect(container.textContent).toContain(
        status === 'waiting' || status === 'verifying' ? 'Cancel' : 'Dismiss',
      );
    },
  );
});
