import type { Meta, StoryObj } from '@storybook/react-vite';

import type { LoginSessionDto } from '../autogenerated';
import { CliLoginProgress } from './cli-login-progress';

function session(overrides: Partial<LoginSessionDto>): LoginSessionDto {
  return {
    id: 'session-1',
    agent: 'claude',
    status: 'waiting',
    url: 'https://claude.ai/oauth/authorize?code=abc123',
    message: null,
    ...overrides,
  };
}

const meta = {
  title: 'Components/CliLoginProgress',
  component: CliLoginProgress,
  args: {
    session: session({}),
    error: null,
    onSubmitCode: () => undefined,
    onCancel: () => undefined,
    onDismiss: () => undefined,
  },
  decorators: [
    (story) => (
      <div className="w-[360px] rounded-lg border border-border">{story()}</div>
    ),
  ],
} satisfies Meta<typeof CliLoginProgress>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Playground: Story = {};

export const NeedsCode: Story = {
  args: { session: session({ status: 'needs_code' }) },
};

export const ServerHandoff: Story = {
  args: {
    session: session({
      status: 'succeeded',
      message:
        'The connector will be available the next time you start Claude Code.',
    }),
    scope: 'server',
  },
};

export const Failed: Story = {
  args: {
    session: session({ status: 'failed', url: null }),
    error: 'The CLI exited before the sign-in finished.',
  },
};

export const InlineVariant: Story = {
  args: { session: session({ status: 'needs_code' }), variant: 'inline' },
};
