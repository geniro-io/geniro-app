import { Check, Loader2, TriangleAlert } from 'lucide-react';
import { useState } from 'react';

import type { LoginSession } from '../autogenerated';
import { CopyButton } from './copy-button';
import { Button } from './ui/button';
import { Input } from './ui/input';
import { cn } from './ui/utils';

/**
 * A sign-in happening IN the app, on the agent card that started it.
 *
 * It exists because the sign-in stopped opening a terminal: the terminal window
 * was the progress display, and removing it without replacing it would leave a
 * button that appears to do nothing while a browser tab opens somewhere behind
 * the app. This is that display.
 *
 * Four states, and each earns its place:
 * - `waiting` — the CLI is up and the browser round-trip is unfinished. Carries
 *   the link as a COPYABLE fallback, never auto-opened again: the CLI already
 *   opened the browser itself, and a second tab on the same challenge is a
 *   reliable way to invalidate the first.
 * - `needs_code` — the CLI asked for a pasted code (claude does; cursor polls and
 *   never reaches this). The field appears only here, so it can never be a dead
 *   input in front of a CLI that wants nothing.
 * - `succeeded` / `failed` / `cancelled` — over. Says so briefly; the card's own
 *   status line is the authority on whether the user ended up signed in, because
 *   it comes from re-asking the CLI rather than from an exit code.
 */
export function CliLoginProgress({
  session,
  onSubmitCode,
  onCancel,
  onDismiss,
  error,
  variant = 'band',
}: {
  session: LoginSession;
  onSubmitCode: (code: string) => void;
  onCancel: () => void;
  onDismiss: () => void;
  error: string | null;
  /**
   * Where this is standing, which decides its EDGES and nothing else.
   *
   * `band` is the original and still the default: a full-bleed strip across
   * the foot of a card, which is what the agent card wants and why the
   * negative margin is there — it cancels the card's own `px-4` so the rule
   * reaches both edges.
   *
   * `inline` is a line sitting among rows, and the negative margin is exactly
   * wrong there: REPORTED as "I have broken UI" against the MCP dialog, where
   * this rendered inside a narrower container and pulled itself 16px past both
   * of its sides, taking the pasted-code field off the edge with it.
   *
   * It is also QUIETER, which is the second half of that report ("make it
   * smaller and without background"). It first landed here as a tinted,
   * bordered box at the band's own type size, and that made a status line
   * heavier than the servers it belongs to — a box drawn around one sentence,
   * in a panel whose content is a list of rows. Inline it is a row: the row's
   * own 12px, the row's own glyph size, no fill and no frame. Nothing about
   * WHAT it says changes with the variant — only its weight.
   */
  variant?: 'band' | 'inline';
}): React.JSX.Element {
  const [code, setCode] = useState('');
  const over =
    session.status === 'succeeded' ||
    session.status === 'failed' ||
    session.status === 'cancelled';

  const band = variant === 'band';
  // One place the two weights are decided, so a later edit cannot make the
  // glyph small and leave the words large.
  const glyph = band ? 'size-4 shrink-0' : 'size-3.5 shrink-0';
  const control = band ? undefined : 'h-5 px-1.5 text-[11px]';

  return (
    <div
      data-slot="cli-login-progress"
      className={cn(
        'flex flex-col',
        band
          ? '-mx-4 gap-2 border-t border-border bg-muted/40 px-4 py-3'
          : 'gap-1 px-1.5 py-1',
      )}>
      <div
        className={cn(
          'flex items-center',
          band ? 'gap-2 text-sm' : 'gap-1.5 text-xs',
        )}>
        {over ? (
          session.status === 'succeeded' ? (
            <Check aria-hidden="true" className={cn(glyph, 'text-success')} />
          ) : (
            <TriangleAlert
              aria-hidden="true"
              className={cn(glyph, 'text-warning')}
            />
          )
        ) : (
          <Loader2
            aria-hidden="true"
            className={cn(glyph, 'animate-spin text-muted-foreground')}
          />
        )}
        <span
          className={cn(
            session.status === 'succeeded'
              ? 'text-foreground'
              : 'text-muted-foreground',
          )}>
          {headline(session)}
        </span>
        <div className="ml-auto flex items-center gap-1">
          {session.url !== null && !over ? (
            <>
              {/* Opening it is the USER's press, never automatic. The CLI has
                  already opened a tab on this same challenge, and a second one
                  raised on their behalf is a reliable way to invalidate the
                  first — but a browser that did not open, or opened in the
                  wrong profile, leaves them with a copy control and no way to
                  act on it, which is the gap this closes. `window.open` is
                  routed to the OS browser by main's own scheme-checked
                  `setWindowOpenHandler`, so this needs no channel of its own. */}
              <Button
                type="button"
                variant="ghost"
                size="sm"
                className={cn('text-muted-foreground', control)}
                title="Open the sign-in page in your browser"
                onClick={() => window.open(session.url ?? '', '_blank')}>
                Open
              </Button>
              <CopyButton text={session.url} label="Copy sign-in link" />
            </>
          ) : null}
          <Button
            type="button"
            variant="ghost"
            size="sm"
            className={cn('text-muted-foreground', control)}
            onClick={over ? onDismiss : onCancel}>
            {over ? 'Dismiss' : 'Cancel'}
          </Button>
        </div>
      </div>

      {session.status === 'needs_code' ? (
        <form
          className="flex items-center gap-2"
          onSubmit={(event) => {
            event.preventDefault();
            if (code.trim() !== '') {
              onSubmitCode(code);
              setCode('');
            }
          }}>
          <Input
            type="text"
            // `aria-label` rather than a visible one: the headline above already
            // says what to paste, and a second label would repeat it.
            aria-label="Sign-in code from the browser"
            placeholder="Paste the code from your browser"
            className={cn(band ? undefined : 'h-7 text-xs')}
            value={code}
            onChange={(event) => setCode(event.target.value)}
            autoFocus
          />
          <Button
            type="submit"
            variant="outline"
            size="sm"
            className={cn('shrink-0', control)}
            disabled={code.trim() === ''}>
            Submit
          </Button>
        </form>
      ) : null}

      {/* The CLI's own last line, when it has one worth showing. Held back while
          a code is being asked for, where the headline is already the
          instruction and this would restate it. */}
      {session.message !== null && session.status !== 'needs_code' ? (
        <p
          className={cn(
            'text-muted-foreground',
            band ? 'text-xs' : 'text-[11px]',
          )}>
          {session.message}
        </p>
      ) : null}
      {error !== null ? (
        <p className={cn('text-destructive', band ? 'text-xs' : 'text-[11px]')}>
          {error}
        </p>
      ) : null}
    </div>
  );
}

function headline(session: LoginSession): string {
  switch (session.status) {
    case 'needs_code':
      return 'Paste the code your browser shows';
    case 'succeeded':
      return 'Sign-in finished';
    case 'failed':
      return 'Sign-in did not complete';
    case 'cancelled':
      return 'Sign-in cancelled';
    default:
      return 'Waiting for you to finish in the browser…';
  }
}
