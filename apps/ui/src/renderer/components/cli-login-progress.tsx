import { Check, Loader2, TriangleAlert } from 'lucide-react';
import { useState } from 'react';

import type { LoginSession } from '../autogenerated';
import { CopyButton } from './copy-button';
import { Button } from './ui/button';
import { Input } from './ui/input';
import { cn } from './ui/utils';

/**
 * A sign-in happening IN the app, on the agent card that started it.
 *
 * It exists because the sign-in stopped opening a terminal: the terminal window
 * was the progress display, and removing it without replacing it would leave a
 * button that appears to do nothing while a browser tab opens somewhere behind
 * the app. This is that display.
 *
 * Four states, and each earns its place:
 * - `waiting` — the CLI is up and the browser round-trip is unfinished. Carries
 *   the link as a COPYABLE fallback, never auto-opened again: the CLI already
 *   opened the browser itself, and a second tab on the same challenge is a
 *   reliable way to invalidate the first.
 * - `needs_code` — the CLI asked for a pasted code (claude does; cursor polls and
 *   never reaches this). The field appears only here, so it can never be a dead
 *   input in front of a CLI that wants nothing.
 * - `succeeded` / `failed` / `cancelled` — over. Says so briefly; the card's own
 *   status line is the authority on whether the user ended up signed in, because
 *   it comes from re-asking the CLI rather than from an exit code.
 */
export function CliLoginProgress({
  session,
  onSubmitCode,
  onCancel,
  onDismiss,
  error,
}: {
  session: LoginSession;
  onSubmitCode: (code: string) => void;
  onCancel: () => void;
  onDismiss: () => void;
  error: string | null;
}): React.JSX.Element {
  const [code, setCode] = useState('');
  const over =
    session.status === 'succeeded' ||
    session.status === 'failed' ||
    session.status === 'cancelled';

  return (
    <div
      data-slot="cli-login-progress"
      className="-mx-4 flex flex-col gap-2 border-t border-border bg-muted/40 px-4 py-3">
      <div className="flex items-center gap-2 text-sm">
        {over ? (
          session.status === 'succeeded' ? (
            <Check
              aria-hidden="true"
              className="size-4 shrink-0 text-success"
            />
          ) : (
            <TriangleAlert
              aria-hidden="true"
              className="size-4 shrink-0 text-warning"
            />
          )
        ) : (
          <Loader2
            aria-hidden="true"
            className="size-4 shrink-0 animate-spin text-muted-foreground"
          />
        )}
        <span
          className={cn(
            session.status === 'succeeded'
              ? 'text-foreground'
              : 'text-muted-foreground',
          )}>
          {headline(session)}
        </span>
        <div className="ml-auto flex items-center gap-1">
          {session.url !== null && !over ? (
            <CopyButton text={session.url} label="Copy sign-in link" />
          ) : null}
          <Button
            type="button"
            variant="ghost"
            size="sm"
            className="text-muted-foreground"
            onClick={over ? onDismiss : onCancel}>
            {over ? 'Dismiss' : 'Cancel'}
          </Button>
        </div>
      </div>

      {session.status === 'needs_code' ? (
        <form
          className="flex items-center gap-2"
          onSubmit={(event) => {
            event.preventDefault();
            if (code.trim() !== '') {
              onSubmitCode(code);
              setCode('');
            }
          }}>
          <Input
            type="text"
            // `aria-label` rather than a visible one: the headline above already
            // says what to paste, and a second label would repeat it.
            aria-label="Sign-in code from the browser"
            placeholder="Paste the code from your browser"
            value={code}
            onChange={(event) => setCode(event.target.value)}
            autoFocus
          />
          <Button
            type="submit"
            variant="outline"
            size="sm"
            className="shrink-0"
            disabled={code.trim() === ''}>
            Submit
          </Button>
        </form>
      ) : null}

      {/* The CLI's own last line, when it has one worth showing. Held back while
          a code is being asked for, where the headline is already the
          instruction and this would restate it. */}
      {session.message !== null && session.status !== 'needs_code' ? (
        <p className="text-xs text-muted-foreground">{session.message}</p>
      ) : null}
      {error !== null ? (
        <p className="text-xs text-destructive">{error}</p>
      ) : null}
    </div>
  );
}

function headline(session: LoginSession): string {
  switch (session.status) {
    case 'needs_code':
      return 'Paste the code your browser shows';
    case 'succeeded':
      return 'Sign-in finished';
    case 'failed':
      return 'Sign-in did not complete';
    case 'cancelled':
      return 'Sign-in cancelled';
    default:
      return 'Waiting for you to finish in the browser…';
  }
}
