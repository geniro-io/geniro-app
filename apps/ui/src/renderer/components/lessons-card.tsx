const SUMMARY_PARTS: readonly [LessonOutcomeStatus | 'proposed', string][] = [
  ['proposed', 'proposed'],
  ['saved', 'saved'],
  ['pending', 'waiting for review'],
  ['rejected', 'rejected'],
  ['undone', 'undone'],
  ['skipped_duplicate', 'already in memory'],
  ['dropped_by_check', 'dropped by the check'],
];

function scopeLabel(scope: LessonScope): string {
  return `Memory · ${scope}`;
}

function memberName(memberId: string, places: LessonPlaces): string {
  return (
    places.members.find((member) => member.id === memberId)?.name ?? memberId
  );
}

/** A target in words, as a lesson names where it goes. */
function targetWords(target: LessonTarget, places: LessonPlaces): string {
  switch (target.kind) {
    case 'memory':
      return scopeLabel(target.scope);
    case 'project_instructions':
      return 'Project instructions';
    case 'member_instructions':
      return `Instructions of ${memberName(target.memberId, places)}`;
    case 'knowledge':
      return target.handle === null
        ? 'Knowledge · new document'
        : `Knowledge · ${target.handle}`;
  }
}

function targetKey(target: LessonTarget): string {
  switch (target.kind) {
    case 'memory':
      return `memory:${target.scope}`;
    case 'project_instructions':
      return 'project_instructions';
    case 'member_instructions':
      return `member:${target.memberId}`;
    case 'knowledge':
      return target.handle === null
        ? 'knowledge:new'
        : `knowledge:doc:${target.handle}`;
  }
}

type TargetGroup = 'Memory' | 'Instructions' | 'Knowledge';

function targetGroupOf(target: LessonTarget): TargetGroup {
  switch (target.kind) {
    case 'memory':
      return 'Memory';
    case 'project_instructions':
    case 'member_instructions':
      return 'Instructions';
    case 'knowledge':
      return 'Knowledge';
  }
}

interface TargetChoice {
  key: string;
  label: string;
  group: TargetGroup;
  target: LessonTarget;
}

/**
 * The targets a lesson can be saved to, as its places allow: memory always
 * (global), this project's and this team's memory, the project's instructions,
 * each member's instructions and the project's knowledge. The lesson's own
 * target is always among them, so the picker can name it before a document
 * list has been read.
 */
function choicesFor(
  lesson: LessonView,
  places: LessonPlaces,
  documents: readonly LessonKnowledgeDocument[] | null,
): TargetChoice[] {
  const type =
    lesson.target.kind === 'memory' ? lesson.target.type : 'feedback';
  const targets: LessonTarget[] = [
    ...LESSON_SCOPES.filter((scope) => scope === 'global' || places[scope]).map(
      (scope): LessonTarget => ({ kind: 'memory', scope, type }),
    ),
    ...(places.project ? [{ kind: 'project_instructions' } as const] : []),
    ...places.members.map((member): LessonTarget => ({
      kind: 'member_instructions',
      memberId: member.id,
    })),
    ...(places.projectId === null
      ? []
      : [
          { kind: 'knowledge', handle: null } as const,
          ...(documents ?? []).map((document): LessonTarget => ({
            kind: 'knowledge',
            handle: document.handle,
          })),
        ]),
  ];
  const choices: TargetChoice[] = targets.map((target) => ({
    key: targetKey(target),
    label: targetWords(target, places),
    group: targetGroupOf(target),
    target,
  }));
  if (!choices.some((choice) => choice.key === targetKey(lesson.target))) {
    choices.push({
      key: targetKey(lesson.target),
      label: targetWords(lesson.target, places),
      group: targetGroupOf(lesson.target),
      target: lesson.target,
    });
  }
  return choices.map((choice) =>
    choice.target.kind === 'knowledge' && choice.target.handle !== null
      ? {
          ...choice,
          label: documentLabel(choice.target.handle, documents),
        }
      : choice,
  );
}

function documentLabel(
  handle: string,
  documents: readonly LessonKnowledgeDocument[] | null,
): string {
  const title = documents?.find(
    (document) => document.handle === handle,
  )?.title;
  return title === undefined ? handle : `${handle} · ${title}`;
}

function pickerGroups(choices: readonly TargetChoice[]): MenuGroup[] {
  const order: readonly TargetGroup[] = ['Memory', 'Instructions', 'Knowledge'];
  return order.flatMap((group) => {
    const items = choices
      .filter((choice) => choice.group === group)
      .map((choice) => ({ value: choice.key, label: choice.label }));
    return items.length === 0 ? [] : [{ label: group, items }];
  });
}

/**
 * Where "Move up" puts a rule broken again: the project's instructions when the
 * thread has a project, else the memory index. Twin of the daemon's `moveUpOf`.
 */
export function moveUpOf(
  lesson: LessonView,
  places: LessonPlaces,
): LessonMoveUpPlace | null {
  if (
    lesson.dedup.verdict !== 'broken_again' ||
    lesson.dedup.handle === null ||
    lesson.target.kind !== 'memory'
  ) {
    return null;
  }
  return places.projectId === null ? 'memory_index' : 'project_instructions';
}

function dedupLabel(dedup: LessonView['dedup']): string {
  switch (dedup.verdict) {
    case 'new':
      return 'New';
    case 'refines':
      return dedup.handle === null ? 'Refines' : `Refines ${dedup.handle}`;
    case 'broken_again':
      return dedup.handle === null
        ? 'Broken again'
        : `Broken again ${dedup.handle}`;
  }
}

function footerText(view: LessonsReflectionView, look: LessonsLook): string {
  const parts = [view.agent, view.model, view.effort].filter(
    (part): part is string => part !== null && part !== '',
  );
  if (view.figures !== null) {
    if (view.figures.working) {
      parts.push('working…');
    } else {
      if (view.figures.durationMs !== null) {
        parts.push(look.formatDuration(view.figures.durationMs));
      }
      parts.push(
        view.figures.costUsd === null
          ? 'cost not reported'
          : look.formatUsd(view.figures.costUsd),
      );
    }
  }
  return `${view.label}: ${parts.join(' · ')}`;
}

function countsOf(
  lessons: readonly LessonView[],
  outcomes: Readonly<Record<string, LessonOutcomeView>>,
): string {
  if (lessons.length === 0) {
    return '0 proposed';
  }
  return SUMMARY_PARTS.flatMap(([status, label]) => {
    const n = lessons.filter(
      (lesson) => (outcomes[lesson.id]?.status ?? 'proposed') === status,
    ).length;
    return n === 0 ? [] : [`${n} ${label}`];
  }).join(' · ');
}

function summaryOf(
  lessons: readonly LessonView[],
  outcomes: Readonly<Record<string, LessonOutcomeView>>,
): string {
  return `Lessons: ${countsOf(lessons, outcomes)}`;
}

function messageOf(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

export function LessonsCard({
  look,
  lessons,
  outcomes,
  reflection,
  check = null,
  places = EVERY_PLACE,
  readDocuments = null,
  onSave,
  onReject,
  onUpdateRule,
  onMoveUp,
  onUndo,
  onEdit,
  onApprove,
  onShowInThread,
}: LessonsCardProps): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const kept = lessons.filter(
    (lesson) => outcomes[lesson.id]?.status !== 'dropped_by_check',
  );
  const dropped = lessons.filter(
    (lesson) => outcomes[lesson.id]?.status === 'dropped_by_check',
  );
  // A lesson still open to a decision (undecided, saved, waiting) keeps the card open.
  const settled =
    kept.length > 0 &&
    kept.every((lesson) => {
      const status = outcomes[lesson.id]?.status;
      return (
        status === 'rejected' ||
        status === 'undone' ||
        status === 'skipped_duplicate'
      );
    });
  const undecided = kept.some((lesson) => outcomes[lesson.id] === undefined);
  const hint =
    lessons.length === 0
      ? 'No lessons from this stretch — nothing passed the bar.'
      : undecided
        ? "Nothing reaches agents' instructions until you save it."
        : null;

  const body = (
    <>
      <div className="flex min-w-0 flex-col gap-1">
        <p className="m-0 flex items-center gap-1.5 text-sm font-medium">
          <span aria-hidden>💡</span>
          {`Lessons from this thread · ${countsOf(lessons, outcomes)}`}
        </p>
        {hint === null ? null : (
          <p className="m-0 text-xs text-muted-foreground">{hint}</p>
        )}
      </div>
      {kept.map((lesson) => {
        const outcome = outcomes[lesson.id] ?? null;
        return outcome === null ? (
          <LessonRow
            key={lesson.id}
            lesson={lesson}
            places={places}
            moveUp={moveUpOf(lesson, places)}
            readDocuments={readDocuments}
            onSave={onSave}
            onReject={onReject}
            onUpdateRule={onUpdateRule}
            onMoveUp={onMoveUp}
            onShowInThread={onShowInThread}
          />
        ) : (
          <DecidedRow
            key={lesson.id}
            lesson={lesson}
            outcome={outcome}
            places={places}
            onUndo={onUndo}
            onEdit={onEdit}
            onApprove={onApprove}
          />
        );
      })}
      {dropped.length === 0 ? null : (
        <DroppedGroup lessons={dropped} outcomes={outcomes} />
      )}
      <div className="flex flex-col gap-1">
        <p className="m-0 text-[11px] text-muted-foreground">
          {footerText(reflection, look)}
        </p>
        {check === null ? null : (
          <p className="m-0 text-[11px] text-muted-foreground">
            {footerText(check, look)}
          </p>
        )}
      </div>
    </>
  );

  if (!settled) {
    return (
      <div
        data-slot="lessons-card"
        className="flex min-w-0 flex-col gap-3 rounded-lg border border-border p-3">
        {body}
      </div>
    );
  }
  return (
    <div
      data-slot="lessons-card"
      className="flex min-w-0 flex-col gap-3 rounded-lg border border-border p-3">
      <Disclosure
        label={summaryOf(lessons, outcomes)}
        open={open}
        onToggle={() => setOpen((value) => !value)}>
        <div className="flex min-w-0 flex-col gap-3">{body}</div>
      </Disclosure>
    </div>
  );
}

function DroppedGroup({
  lessons,
  outcomes,
}: {
  lessons: readonly LessonView[];
  outcomes: Readonly<Record<string, LessonOutcomeView>>;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  return (
    <div className="border-t border-border pt-3 first:border-t-0 first:pt-0">
      <Disclosure
        label={`${lessons.length} dropped by the check`}
        open={open}
        onToggle={() => setOpen((value) => !value)}>
        <ul className="m-0 flex list-none flex-col gap-2 p-0">
          {lessons.map((lesson) => {
            const reason = outcomes[lesson.id]?.reason ?? null;
            return (
              <li key={lesson.id} className="flex flex-col gap-0.5 text-xs">
                <span className="text-muted-foreground">{lesson.title}</span>
                {reason === null ? null : (
                  <span className="text-muted-foreground">{reason}</span>
                )}
              </li>
            );
          })}
        </ul>
      </Disclosure>
    </div>
  );
}

function DecidedRow({
  lesson,
  outcome,
  places,
  onUndo,
  onEdit,
  onApprove,
}: {
  lesson: LessonView;
  outcome: LessonOutcomeView;
  places: LessonPlaces;
  onUndo?: LessonsCardProps['onUndo'];
  onEdit?: LessonsCardProps['onEdit'];
  onApprove?: LessonsCardProps['onApprove'];
}): React.JSX.Element {
  const [editing, setEditing] = useState(false);
  const [edited, setEdited] = useState(false);
  const [title, setTitle] = useState(outcome.title);
  const [rule, setRule] = useState(outcome.rule ?? lesson.rule);
  const [request, setRequest] = useState<'undo' | 'edit' | 'approve' | null>(
    null,
  );
  const [error, setError] = useState<string | null>(null);

  const busy = request !== null;
  const draftValid = title.trim() !== '' && rule.trim() !== '';
  const ownEntry =
    outcome.target.kind === 'memory' &&
    outcome.memoryHandle !== lesson.dedup.handle;

  const run = (
    kind: 'undo' | 'edit' | 'approve',
    action: () => Promise<void>,
    done: () => void = () => undefined,
  ): void => {
    setRequest(kind);
    setError(null);
    action().then(
      () => {
        setRequest(null);
        done();
      },
      (err: unknown) => {
        setRequest(null);
        setError(messageOf(err));
      },
    );
  };

  const save = (): void => {
    if (onEdit === undefined) {
      return;
    }
    run(
      'edit',
      () => onEdit(lesson.id, { title: title.trim(), rule: rule.trim() }),
      () => {
        setEditing(false);
        setEdited(true);
      },
    );
  };

  const undo = (): void => {
    if (onUndo === undefined) {
      return;
    }
    run('undo', () => onUndo(lesson.id));
  };

  const approve = (): void => {
    if (onApprove === undefined) {
      return;
    }
    run('approve', () => onApprove(lesson.id));
  };

  const muted = outcome.status !== 'saved' && outcome.status !== 'pending';
  const statusText = decidedStatusText(outcome, edited, places, lesson);
  const undoDisabled = busy || onUndo === undefined;

  return (
    <div className="flex min-w-0 flex-col gap-2 border-t border-border pt-3 first:border-t-0 first:pt-0">
      {editing ? (
        <div className="flex min-w-0 flex-col gap-2">
          <Input
            aria-label="Lesson title"
            value={title}
            maxLength={TITLE_MAX_CHARS}
            disabled={busy}
            onChange={(event) => setTitle(event.target.value)}
          />
          <ExpandableTextarea
            title="Lesson rule"
            ariaLabel="Lesson rule"
            value={rule}
            maxLength={RULE_MAX_CHARS}
            rows={3}
            onChange={setRule}
          />
        </div>
      ) : (
        <p
          className={
            muted
              ? 'm-0 text-sm font-medium text-muted-foreground'
              : 'm-0 text-sm font-medium'
          }>
          {outcome.title}
        </p>
      )}
      <p className="m-0 text-xs text-muted-foreground">{statusText}</p>
      {editing ? (
        <div className="flex flex-wrap gap-2">
          <Button
            size="sm"
            disabled={busy || !draftValid || onEdit === undefined}
            onClick={save}>
            {request === 'edit' ? 'Saving…' : 'Save'}
          </Button>
          <Button
            size="sm"
            variant="ghost"
            disabled={busy}
            onClick={() => {
              setTitle(outcome.title);
              setRule(outcome.rule ?? lesson.rule);
              setEditing(false);
            }}>
            Cancel
          </Button>
        </div>
      ) : outcome.status === 'saved' && ownEntry ? (
        <div className="flex flex-wrap gap-2">
          <Button
            size="sm"
            variant="outline"
            disabled={undoDisabled}
            onClick={undo}>
            {request === 'undo' ? 'Undoing…' : 'Undo'}
          </Button>
          <Button
            size="sm"
            variant="outline"
            disabled={busy || onEdit === undefined}
            onClick={() => setEditing(true)}>
            Edit
          </Button>
        </div>
      ) : outcome.status === 'pending' ? (
        <div className="flex flex-wrap gap-2">
          <Button
            size="sm"
            disabled={busy || onApprove === undefined}
            onClick={approve}>
            {request === 'approve' ? 'Approving…' : 'Approve'}
          </Button>
          <Button
            size="sm"
            variant="outline"
            disabled={undoDisabled}
            onClick={undo}>
            {request === 'undo' ? 'Undoing…' : 'Undo'}
          </Button>
        </div>
      ) : null}
      {error === null ? null : (
        <ErrorBanner
          message={error}
          size="sm"
          onDismiss={() => setError(null)}
        />
      )}
    </div>
  );
}

function savedStatusText(
  outcome: LessonOutcomeView,
  edited: boolean,
  places: LessonPlaces,
  lesson: LessonView,
): string {
  const { target } = outcome;
  switch (target.kind) {
    case 'memory':
      if (
        outcome.memoryHandle !== null &&
        outcome.memoryHandle === lesson.dedup.handle
      ) {
        return lesson.dedup.verdict === 'broken_again'
          ? `${outcome.memoryHandle} moved into the memory index`
          : `Updated ${outcome.memoryHandle}`;
      }
      return outcome.by === 'auto' && !edited
        ? `Saved to memory · ${target.scope} · Searchable only`
        : `Saved to memory · ${target.scope}`;
    case 'project_instructions':
      return 'Saved to project instructions';
    case 'member_instructions':
      return `Saved to ${memberName(target.memberId, places)} instructions`;
    case 'knowledge':
      return outcome.resultRef === null
        ? 'Saved to knowledge'
        : `Saved to knowledge · ${outcome.resultRef}`;
  }
}

function decidedStatusText(
  outcome: LessonOutcomeView,
  edited: boolean,
  places: LessonPlaces,
  lesson: LessonView,
): string {
  switch (outcome.status) {
    case 'saved':
      return savedStatusText(outcome, edited, places, lesson);
    case 'pending':
      return 'Waiting for review';
    case 'undone':
      return 'Undone';
    case 'skipped_duplicate':
      return outcome.memoryHandle === null
        ? 'Already in memory'
        : `Already in memory as ${outcome.memoryHandle}`;
    case 'rejected':
      return outcome.reason === null
        ? '✗ Rejected'
        : `✗ Rejected — ${outcome.reason}`;
    case 'dropped_by_check':
      return 'Dropped by the check';
  }
}

function moveUpHint(place: LessonMoveUpPlace): string {
  return place === 'project_instructions'
    ? "into the project's instructions"
    : 'into the memory index';
}

/**
 * One lesson still waiting for the user, with its target picker and its
 * actions. The card and Settings → Memory → Lessons draw it the same way.
 */
export function LessonRow({
  lesson,
  places,
  moveUp,
  readDocuments = null,
  source = null,
  onSave,
  onReject,
  onUpdateRule,
  onMoveUp,
  onShowInThread,
}: {
  lesson: LessonView;
  places: LessonPlaces;
  moveUp: LessonMoveUpPlace | null;
  readDocuments?: LessonDocumentsReader | null;
  /** Drawn above the lesson's title, where a list names the thread it came from. */
  source?: React.ReactNode;
  onSave?: LessonsCardProps['onSave'];
  onReject?: LessonsCardProps['onReject'];
  onUpdateRule?: LessonsCardProps['onUpdateRule'];
  onMoveUp?: LessonsCardProps['onMoveUp'];
  onShowInThread?: LessonsCardProps['onShowInThread'];
}): React.JSX.Element {
  const [targetKeyValue, setTargetKeyValue] = useState(() =>
    targetKey(lesson.target),
  );
  const [documents, setDocuments] = useState<
    readonly LessonKnowledgeDocument[] | null
  >(null);
  const [loadingDocuments, setLoadingDocuments] = useState(false);
  const [editing, setEditing] = useState(false);
  const [title, setTitle] = useState(lesson.title);
  const [rule, setRule] = useState(lesson.rule);
  const [rejecting, setRejecting] = useState(false);
  const [reason, setReason] = useState('');
  const [evidenceOpen, setEvidenceOpen] = useState(false);
  const [request, setRequest] = useState<
    'save' | 'update' | 'moveUp' | 'reject' | null
  >(null);
  const [error, setError] = useState<string | null>(null);

  const choices = choicesFor(lesson, places, documents);
  const selected =
    choices.find((choice) => choice.key === targetKeyValue) ?? choices[0];
  const refines =
    lesson.dedup.verdict === 'refines' && lesson.target.kind === 'memory';
  const busy = request !== null;
  const saveDisabled = onSave === undefined || busy;
  const rejectDisabled = onReject === undefined || busy;
  const draftValid = title.trim() !== '' && rule.trim() !== '';
  const updateLabel =
    lesson.dedup.handle === null
      ? 'Update rule'
      : `Update ${lesson.dedup.handle}`;

  const loadDocuments = (): void => {
    if (
      readDocuments === null ||
      places.projectId === null ||
      documents !== null ||
      loadingDocuments
    ) {
      return;
    }
    setLoadingDocuments(true);
    void readDocuments(places.projectId).then(
      (next) => {
        setDocuments(next);
        setLoadingDocuments(false);
      },
      (err: unknown) => {
        setLoadingDocuments(false);
        setError(messageOf(err));
      },
    );
  };

  const save = (): void => {
    if (onSave === undefined || selected === undefined) {
      return;
    }
    setRequest('save');
    setError(null);
    onSave(lesson.id, {
      target: selected.target,
      ...(editing ? { title: title.trim(), rule: rule.trim() } : {}),
    }).then(
      () => setRequest(null),
      (err: unknown) => {
        setRequest(null);
        setError(messageOf(err));
      },
    );
  };

  const updateRule = (): void => {
    if (onUpdateRule === undefined) {
      return;
    }
    setRequest('update');
    setError(null);
    onUpdateRule(
      lesson.id,
      editing ? { title: title.trim(), rule: rule.trim() } : {},
    ).then(
      () => setRequest(null),
      (err: unknown) => {
        setRequest(null);
        setError(messageOf(err));
      },
    );
  };

  const moveUpRule = (): void => {
    if (onMoveUp === undefined) {
      return;
    }
    setRequest('moveUp');
    setError(null);
    onMoveUp(lesson.id).then(
      () => setRequest(null),
      (err: unknown) => {
        setRequest(null);
        setError(messageOf(err));
      },
    );
  };

  const reject = (): void => {
    if (onReject === undefined) {
      return;
    }
    const trimmed = reason.trim();
    setRequest('reject');
    setError(null);
    onReject(lesson.id, trimmed === '' ? null : trimmed).then(
      () => setRequest(null),
      (err: unknown) => {
        setRequest(null);
        setError(messageOf(err));
      },
    );
  };

  const primary = editing ? (
    refines ? (
      <Button
        size="sm"
        disabled={busy || !draftValid || onUpdateRule === undefined}
        onClick={updateRule}>
        {request === 'update' ? 'Updating…' : updateLabel}
      </Button>
    ) : (
      <Button size="sm" disabled={saveDisabled || !draftValid} onClick={save}>
        {request === 'save' ? 'Saving…' : 'Save'}
      </Button>
    )
  ) : refines ? (
    <Button
      size="sm"
      disabled={busy || onUpdateRule === undefined}
      onClick={updateRule}>
      {request === 'update' ? 'Updating…' : updateLabel}
    </Button>
  ) : moveUp !== null ? (
    <Button
      size="sm"
      disabled={busy || onMoveUp === undefined}
      onClick={moveUpRule}>
      {request === 'moveUp' ? 'Moving…' : 'Move up'}
    </Button>
  ) : (
    <Button size="sm" disabled={saveDisabled} onClick={save}>
      {request === 'save' ? 'Saving…' : 'Save'}
    </Button>
  );

  return (
    <div className="flex min-w-0 flex-col gap-2 border-t border-border pt-3 first:border-t-0 first:pt-0">
      {source}
      {editing ? (
        <div className="flex min-w-0 flex-col gap-2">
          <Input
            aria-label="Lesson title"
            value={title}
            maxLength={TITLE_MAX_CHARS}
            disabled={busy}
            onChange={(event) => setTitle(event.target.value)}
          />
          <ExpandableTextarea
            title="Lesson rule"
            ariaLabel="Lesson rule"
            value={rule}
            maxLength={RULE_MAX_CHARS}
            rows={3}
            onChange={setRule}
          />
        </div>
      ) : (
        <>
          <p className="m-0 text-sm font-medium">{lesson.title}</p>
          {lesson.rule.trim() === lesson.title.trim() ? null : (
            <p className="m-0 text-xs">{lesson.rule}</p>
          )}
          <p className="m-0 text-xs text-muted-foreground">{lesson.why}</p>
        </>
      )}
      <div className="flex flex-wrap items-center gap-1.5">
        <Badge variant="outline">{SIGNAL_LABELS[lesson.signalKind]}</Badge>
        <Badge variant="secondary">{dedupLabel(lesson.dedup)}</Badge>
        <Chip>{`→ ${targetWords(selected?.target ?? lesson.target, places)}`}</Chip>
      </div>
      <Disclosure
        label={`Evidence · message #${lesson.evidence.seq}`}
        open={evidenceOpen}
        onToggle={() => setEvidenceOpen((value) => !value)}>
        <p className="m-0 text-xs text-muted-foreground">
          {`“${lesson.evidence.quote}”`}
          {onShowInThread === undefined ? null : (
            <>
              {' '}
              <Button
                size="sm"
                variant="link"
                className="h-auto p-0 text-xs"
                onClick={() => onShowInThread(lesson.evidence.seq)}>
                Show in thread
              </Button>
            </>
          )}
        </p>
      </Disclosure>
      <div
        className="flex min-w-0 items-center gap-2"
        onPointerDown={loadDocuments}
        onFocus={loadDocuments}>
        <span className="shrink-0 text-xs text-muted-foreground">Save to</span>
        <Select
          aria-label="Save to"
          groups={pickerGroups(choices)}
          value={selected?.key ?? null}
          disabled={saveDisabled}
          onValueChange={setTargetKeyValue}
        />
      </div>
      {moveUp === null || editing ? null : (
        <p className="m-0 text-xs text-muted-foreground">
          {`Moves the rule ${moveUpHint(moveUp)}.`}
        </p>
      )}
      {rejecting ? (
        <div className="flex min-w-0 flex-col gap-2">
          <Input
            aria-label="Reject reason"
            placeholder="Reason (optional)"
            value={reason}
            maxLength={REJECT_REASON_MAX_CHARS}
            disabled={rejectDisabled}
            onChange={(event) => setReason(event.target.value)}
          />
          <div className="flex flex-wrap gap-2">
            <Button
              size="sm"
              variant="outline"
              disabled={rejectDisabled}
              onClick={reject}>
              {request === 'reject' ? 'Rejecting…' : 'Reject'}
            </Button>
            <Button
              size="sm"
              variant="ghost"
              disabled={busy}
              onClick={() => setRejecting(false)}>
              Cancel
            </Button>
          </div>
        </div>
      ) : editing ? (
        <div className="flex flex-wrap gap-2">
          {primary}
          <Button
            size="sm"
            variant="ghost"
            disabled={busy}
            onClick={() => {
              setTitle(lesson.title);
              setRule(lesson.rule);
              setEditing(false);
            }}>
            Cancel
          </Button>
        </div>
      ) : (
        <div className="flex flex-wrap gap-2">
          {primary}
          {refines ? (
            <Button size="sm" disabled={saveDisabled} onClick={save}>
              {request === 'save' ? 'Saving…' : 'Save as new'}
            </Button>
          ) : moveUp === null ? null : (
            <Button size="sm" disabled={saveDisabled} onClick={save}>
              {request === 'save' ? 'Saving…' : 'Save'}
            </Button>
          )}
          <Button
            size="sm"
            variant="outline"
            disabled={saveDisabled}
            onClick={() => setEditing(true)}>
            Edit
          </Button>
          <Button
            size="sm"
            variant="outline"
            disabled={rejectDisabled}
            onClick={() => setRejecting(true)}>
            Reject
          </Button>
        </div>
      )}
      {error === null ? null : (
        <ErrorBanner
          message={error}
          size="sm"
          onDismiss={() => setError(null)}
        />
      )}
    </div>
  );
}
