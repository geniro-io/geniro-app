import { useState } from 'react';

import type {
  LessonDedup,
  LessonMemoryTarget,
  LessonSignalKind,
} from '../autogenerated';
import { ErrorBanner } from './error-banner';
import { ExpandableTextarea } from './expandable-textarea';
import { Disclosure } from './recommendations-figures';
import { Badge } from './ui/badge';
import { Button } from './ui/button';
import { Chip } from './ui/chip';
import { Input } from './ui/input';
import type { MenuGroup } from './ui/menu';
import { Select } from './ui/select';

export type LessonScope = LessonMemoryTarget['scope'];
export type LessonDedupVerdict = LessonDedup['verdict'];

/** One proposed lesson as the card draws it. */
export interface LessonView {
  id: string;
  title: string;
  rule: string;
  why: string;
  signalKind: LessonSignalKind;
  evidence: { seq: number; quote: string };
  target: LessonMemoryTarget;
  dedup: { verdict: LessonDedupVerdict; handle: string | null };
}

/** The user's decision on one lesson, as its `lesson_outcome` row states it. */
export interface LessonOutcomeView {
  proposalId: string;
  status: 'saved' | 'rejected';
  target: LessonMemoryTarget;
  memoryHandle: string | null;
  reason: string | null;
}

export interface LessonSaveRequest {
  target: LessonMemoryTarget;
  title?: string;
  rule?: string;
}

/** The reflection's footer, from the lessons row and its figures. */
export interface LessonsReflectionView {
  agent: string;
  model: string | null;
  working: boolean;
  durationMs: number | null;
  costUsd: number | null;
  tokens: number | null;
}

export interface LessonsLook {
  formatDuration: (ms: number) => string;
  formatUsd: (usd: number) => string;
}

export interface LessonsCardProps {
  look: LessonsLook;
  lessons: readonly LessonView[];
  outcomes: Readonly<Record<string, LessonOutcomeView>>;
  reflection: LessonsReflectionView;
  onSave?: (proposalId: string, request: LessonSaveRequest) => Promise<void>;
  onReject?: (proposalId: string, reason: string | null) => Promise<void>;
  /** Scroll the transcript to the evidence's row; absent draws no link. */
  onShowInThread?: (seq: number) => void;
}

const SIGNAL_LABELS: Record<LessonSignalKind, string> = {
  user_correction: 'User correction',
  approval_refused: 'Approval declined',
  error_then_success: 'Failing step, then fixed',
  outcome_failed: 'Outcome failed',
  stage_reopened: 'Stage reopened',
  review_finding: 'Review finding',
};

const LESSON_SCOPES: readonly LessonScope[] = ['project', 'team', 'global'];

const SCOPE_GROUPS: MenuGroup[] = [
  {
    items: LESSON_SCOPES.map((scope) => ({
      value: scope,
      label: scopeLabel(scope),
    })),
  },
];

const TITLE_MAX_CHARS = 120;
const RULE_MAX_CHARS = 300;
const REJECT_REASON_MAX_CHARS = 300;

function scopeLabel(scope: LessonScope): string {
  return `Memory · ${scope}`;
}

function isScope(value: string): value is LessonScope {
  return (LESSON_SCOPES as readonly string[]).includes(value);
}

function dedupLabel(dedup: LessonView['dedup']): string {
  switch (dedup.verdict) {
    case 'new':
      return 'New';
    case 'refines':
      return dedup.handle === null ? 'Refines' : `Refines ${dedup.handle}`;
    case 'broken_again':
      return dedup.handle === null
        ? 'Broken again'
        : `Broken again ${dedup.handle}`;
  }
}

function verdictText(outcome: LessonOutcomeView): string {
  if (outcome.status === 'rejected') {
    return outcome.reason === null
      ? '✗ Rejected'
      : `✗ Rejected — ${outcome.reason}`;
  }
  const where = `Saved to memory · ${outcome.target.scope}`;
  return outcome.memoryHandle === null
    ? `✓ ${where}`
    : `✓ ${where} as ${outcome.memoryHandle}`;
}

function reflectionText(
  reflection: LessonsReflectionView,
  look: LessonsLook,
): string {
  const who = [reflection.agent, reflection.model].filter(
    (part): part is string => part !== null && part !== '',
  );
  if (reflection.working) {
    return `Reflection: ${who.join(' · ')} · working…`;
  }
  const parts = [...who];
  if (reflection.durationMs !== null) {
    parts.push(look.formatDuration(reflection.durationMs));
  }
  if (reflection.costUsd !== null) {
    parts.push(look.formatUsd(reflection.costUsd));
  } else if (reflection.tokens !== null) {
    parts.push(`≈${reflection.tokens} tokens`);
  }
  return `Reflection: ${parts.join(' · ')}`;
}

function messageOf(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

export function LessonsCard({
  look,
  lessons,
  outcomes,
  reflection,
  onSave,
  onReject,
  onShowInThread,
}: LessonsCardProps): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const saved = lessons.filter(
    (lesson) => outcomes[lesson.id]?.status === 'saved',
  ).length;
  const rejected = lessons.filter(
    (lesson) => outcomes[lesson.id]?.status === 'rejected',
  ).length;
  const allHandled = lessons.length > 0 && saved + rejected === lessons.length;

  const body = (
    <>
      <div className="flex min-w-0 flex-col gap-1">
        <p className="m-0 flex items-center gap-1.5 text-sm font-medium">
          <span aria-hidden>💡</span>
          {`Lessons from this thread · ${lessons.length} proposed`}
        </p>
        <p className="m-0 text-xs text-muted-foreground">
          {lessons.length === 0
            ? 'No lessons from this stretch — nothing passed the bar.'
            : "Nothing reaches agents' instructions until you save it."}
        </p>
      </div>
      {lessons.map((lesson) => (
        <LessonRow
          key={lesson.id}
          lesson={lesson}
          outcome={outcomes[lesson.id] ?? null}
          onSave={onSave}
          onReject={onReject}
          onShowInThread={onShowInThread}
        />
      ))}
      <p className="m-0 text-[11px] text-muted-foreground">
        {reflectionText(reflection, look)}
      </p>
    </>
  );

  if (!allHandled) {
    return (
      <div
        data-slot="lessons-card"
        className="flex min-w-0 flex-col gap-3 rounded-lg border border-border p-3">
        {body}
      </div>
    );
  }
  return (
    <div
      data-slot="lessons-card"
      className="flex min-w-0 flex-col gap-3 rounded-lg border border-border p-3">
      <Disclosure
        label={`Lessons: ${saved} saved · ${rejected} rejected`}
        open={open}
        onToggle={() => setOpen((value) => !value)}>
        <div className="flex min-w-0 flex-col gap-3">{body}</div>
      </Disclosure>
    </div>
  );
}

function LessonRow({
  lesson,
  outcome,
  onSave,
  onReject,
  onShowInThread,
}: {
  lesson: LessonView;
  outcome: LessonOutcomeView | null;
  onSave?: LessonsCardProps['onSave'];
  onReject?: LessonsCardProps['onReject'];
  onShowInThread?: LessonsCardProps['onShowInThread'];
}): React.JSX.Element {
  const [scope, setScope] = useState<LessonScope>(lesson.target.scope);
  const [editing, setEditing] = useState(false);
  const [title, setTitle] = useState(lesson.title);
  const [rule, setRule] = useState(lesson.rule);
  const [rejecting, setRejecting] = useState(false);
  const [reason, setReason] = useState('');
  const [evidenceOpen, setEvidenceOpen] = useState(false);
  const [request, setRequest] = useState<'save' | 'reject' | null>(null);
  const [error, setError] = useState<string | null>(null);

  if (outcome !== null) {
    return (
      <p className="m-0 border-t border-border pt-3 text-xs text-muted-foreground first:border-t-0 first:pt-0">
        {verdictText(outcome)}
      </p>
    );
  }

  const busy = request !== null;
  const saveDisabled = onSave === undefined || busy;
  const rejectDisabled = onReject === undefined || busy;
  const draftValid = title.trim() !== '' && rule.trim() !== '';

  const save = (): void => {
    if (onSave === undefined) {
      return;
    }
    setRequest('save');
    setError(null);
    onSave(lesson.id, {
      target: { ...lesson.target, scope },
      ...(editing ? { title: title.trim(), rule: rule.trim() } : {}),
    }).catch((err: unknown) => {
      setRequest(null);
      setError(messageOf(err));
    });
  };

  const reject = (): void => {
    if (onReject === undefined) {
      return;
    }
    const trimmed = reason.trim();
    setRequest('reject');
    setError(null);
    onReject(lesson.id, trimmed === '' ? null : trimmed).catch(
      (err: unknown) => {
        setRequest(null);
        setError(messageOf(err));
      },
    );
  };

  return (
    <div className="flex min-w-0 flex-col gap-2 border-t border-border pt-3 first:border-t-0 first:pt-0">
      {editing ? (
        <div className="flex min-w-0 flex-col gap-2">
          <Input
            aria-label="Lesson title"
            value={title}
            maxLength={TITLE_MAX_CHARS}
            disabled={busy}
            onChange={(event) => setTitle(event.target.value)}
          />
          <ExpandableTextarea
            title="Lesson rule"
            ariaLabel="Lesson rule"
            value={rule}
            maxLength={RULE_MAX_CHARS}
            rows={3}
            onChange={setRule}
          />
        </div>
      ) : (
        <>
          <p className="m-0 text-sm font-medium">{lesson.title}</p>
          {lesson.rule.trim() === lesson.title.trim() ? null : (
            <p className="m-0 text-xs">{lesson.rule}</p>
          )}
          <p className="m-0 text-xs text-muted-foreground">{lesson.why}</p>
        </>
      )}
      <div className="flex flex-wrap items-center gap-1.5">
        <Badge variant="outline">{SIGNAL_LABELS[lesson.signalKind]}</Badge>
        <Badge variant="secondary">{dedupLabel(lesson.dedup)}</Badge>
        <Chip>{`→ ${scopeLabel(scope)}`}</Chip>
      </div>
      <Disclosure
        label={`Evidence · message #${lesson.evidence.seq}`}
        open={evidenceOpen}
        onToggle={() => setEvidenceOpen((value) => !value)}>
        <p className="m-0 text-xs text-muted-foreground">
          {`“${lesson.evidence.quote}”`}
          {onShowInThread === undefined ? null : (
            <>
              {' '}
              <Button
                size="sm"
                variant="link"
                className="h-auto p-0 text-xs"
                onClick={() => onShowInThread(lesson.evidence.seq)}>
                Show in thread
              </Button>
            </>
          )}
        </p>
      </Disclosure>
      <div className="flex min-w-0 items-center gap-2">
        <span className="shrink-0 text-xs text-muted-foreground">Save to</span>
        <Select
          aria-label="Save to"
          groups={SCOPE_GROUPS}
          value={scope}
          disabled={saveDisabled}
          onValueChange={(value) => {
            if (isScope(value)) {
              setScope(value);
            }
          }}
        />
      </div>
      {rejecting ? (
        <div className="flex min-w-0 flex-col gap-2">
          <Input
            aria-label="Reject reason"
            placeholder="Reason (optional)"
            value={reason}
            maxLength={REJECT_REASON_MAX_CHARS}
            disabled={rejectDisabled}
            onChange={(event) => setReason(event.target.value)}
          />
          <div className="flex flex-wrap gap-2">
            <Button
              size="sm"
              variant="outline"
              disabled={rejectDisabled}
              onClick={reject}>
              {request === 'reject' ? 'Rejecting…' : 'Reject'}
            </Button>
            <Button
              size="sm"
              variant="ghost"
              disabled={busy}
              onClick={() => setRejecting(false)}>
              Cancel
            </Button>
          </div>
        </div>
      ) : editing ? (
        <div className="flex flex-wrap gap-2">
          <Button
            size="sm"
            disabled={saveDisabled || !draftValid}
            onClick={save}>
            {request === 'save' ? 'Saving…' : 'Save'}
          </Button>
          <Button
            size="sm"
            variant="ghost"
            disabled={busy}
            onClick={() => {
              setTitle(lesson.title);
              setRule(lesson.rule);
              setEditing(false);
            }}>
            Cancel
          </Button>
        </div>
      ) : (
        <div className="flex flex-wrap gap-2">
          <Button size="sm" disabled={saveDisabled} onClick={save}>
            {request === 'save' ? 'Saving…' : 'Save'}
          </Button>
          <Button
            size="sm"
            variant="outline"
            disabled={saveDisabled}
            onClick={() => setEditing(true)}>
            Edit
          </Button>
          <Button
            size="sm"
            variant="outline"
            disabled={rejectDisabled}
            onClick={() => setRejecting(true)}>
            Reject
          </Button>
        </div>
      )}
      {error === null ? null : (
        <ErrorBanner
          message={error}
          size="sm"
          onDismiss={() => setError(null)}
        />
      )}
    </div>
  );
}
