// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { AgentMcpConfigDto } from '../autogenerated';
import { McpAddDialog, type McpConfigActions } from './mcp-add-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const DOC: AgentMcpConfigDto = {
  servers: { linear: { url: 'https://mcp.linear.app/mcp' } },
  path: '/Users/me/.claude.json',
  version: 'sha256:v1',
  unavailableReason: null,
};

function actions(overrides: Partial<McpConfigActions> = {}): McpConfigActions {
  return {
    read: vi.fn(() => Promise.resolve(DOC)),
    write: vi.fn(() => Promise.resolve(DOC)),
    add: vi.fn(() => Promise.resolve(DOC)),
    ...overrides,
  };
}

function render(element: React.ReactElement): void {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(element);
  });
}

async function settle(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
  });
}

function type(el: HTMLInputElement | HTMLTextAreaElement, value: string): void {
  const proto =
    el instanceof HTMLTextAreaElement
      ? HTMLTextAreaElement.prototype
      : HTMLInputElement.prototype;
  act(() => {
    Object.getOwnPropertyDescriptor(proto, 'value')!.set!.call(el, value);
    el.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

function click(el: Element): void {
  act(() => {
    el.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

const byLabel = <T extends HTMLElement>(label: string): T => {
  const node = [...document.querySelectorAll('label')].find(
    (candidate) => candidate.textContent === label,
  );
  return document.getElementById(node!.htmlFor) as T;
};
const button = (text: string): HTMLButtonElement =>
  [...document.querySelectorAll('button')].find(
    (candidate) => candidate.textContent?.trim() === text,
  ) as HTMLButtonElement;

describe('McpAddDialog — Add a server', () => {
  it('keeps Add disabled until the form names a server and its command', () => {
    render(
      <McpAddDialog
        open
        onClose={() => undefined}
        title="t"
        actions={actions()}
        onChanged={() => undefined}
      />,
    );
    expect(button('Add server').disabled).toBe(true);
    type(byLabel<HTMLInputElement>('Name'), 'acme');
    expect(button('Add server').disabled).toBe(true);
    expect(
      document.querySelector('[data-slot="mcp-add-hint"]')?.textContent,
    ).toMatch(/command/);
    type(byLabel<HTMLInputElement>('Command'), 'npx');
    expect(button('Add server').disabled).toBe(false);
  });

  it('sends the server the form states, one argument per line and env as KEY=value', async () => {
    const onChanged = vi.fn();
    const onClose = vi.fn();
    const act$ = actions();
    render(
      <McpAddDialog
        open
        onClose={onClose}
        title="t"
        actions={act$}
        onChanged={onChanged}
      />,
    );
    type(byLabel<HTMLInputElement>('Name'), 'acme');
    type(byLabel<HTMLInputElement>('Command'), 'npx');
    type(byLabel<HTMLTextAreaElement>('Arguments'), '-y\n@acme/mcp server');
    type(byLabel<HTMLTextAreaElement>('Environment'), 'ACME_TOKEN=t=1');
    click(button('Add server'));
    await settle();
    expect(act$.add).toHaveBeenCalledWith({
      name: 'acme',
      transport: 'stdio',
      command: 'npx',
      args: ['-y', '@acme/mcp server'],
      env: { ACME_TOKEN: 't=1' },
    });
    // The listing beneath is re-read, and the dialog gets out of its way.
    expect(onChanged).toHaveBeenCalledTimes(1);
    expect(onClose).toHaveBeenCalledTimes(1);
  });

  it('shows the daemon’s refusal and stays open', async () => {
    const onClose = vi.fn();
    render(
      <McpAddDialog
        open
        onClose={onClose}
        title="t"
        actions={actions({
          add: () =>
            Promise.reject(new Error('a server named "acme" already exists')),
        })}
        onChanged={() => undefined}
      />,
    );
    type(byLabel<HTMLInputElement>('Name'), 'acme');
    type(byLabel<HTMLInputElement>('Command'), 'npx');
    click(button('Add server'));
    await settle();
    expect(
      document.querySelector('[data-slot="mcp-add-error"]')?.textContent,
    ).toBe('a server named "acme" already exists');
    expect(onClose).not.toHaveBeenCalled();
  });

  it('switches to a URL and headers for an http server', async () => {
    const act$ = actions();
    render(
      <McpAddDialog
        open
        onClose={() => undefined}
        title="t"
        actions={act$}
        onChanged={() => undefined}
      />,
    );
    click(button('URL (http)'));
    type(byLabel<HTMLInputElement>('Name'), 'acme');
    type(byLabel<HTMLInputElement>('URL'), 'https://acme.example/mcp');
    type(byLabel<HTMLTextAreaElement>('Headers'), 'X-Api-Key: k:1');
    click(button('Add server'));
    await settle();
    expect(act$.add).toHaveBeenCalledWith({
      name: 'acme',
      transport: 'http',
      url: 'https://acme.example/mcp',
      headers: { 'X-Api-Key': 'k:1' },
    });
  });
});

describe('McpAddDialog — Edit JSON', () => {
  it('opens the profile’s servers, refuses invalid JSON, and saves at the version it read', async () => {
    const act$ = actions();
    const onChanged = vi.fn();
    render(
      <McpAddDialog
        open
        onClose={() => undefined}
        title="t"
        actions={act$}
        onChanged={onChanged}
        initialMode="json"
      />,
    );
    await settle();
    const editor = byLabel<HTMLTextAreaElement>('MCP servers');
    expect(JSON.parse(editor.value)).toEqual(DOC.servers);
    expect(document.body.textContent).toContain('/Users/me/.claude.json');
    // Unchanged: nothing to save.
    expect(button('Save').disabled).toBe(true);

    type(editor, '{ "linear": ');
    expect(button('Save').disabled).toBe(true);
    expect(
      document.querySelector('[data-slot="mcp-json-error"]')?.textContent,
    ).toMatch(/Not valid JSON/);

    type(editor, '{ "linear": { "args": [] } }');
    expect(
      document.querySelector('[data-slot="mcp-json-error"]')?.textContent,
    ).toMatch(/needs a "command"/);

    type(editor, '{ "other": { "command": "true" } }');
    expect(button('Save').disabled).toBe(false);
    click(button('Save'));
    await settle();
    expect(act$.write).toHaveBeenCalledWith(
      { other: { command: 'true' } },
      'sha256:v1',
    );
    expect(onChanged).toHaveBeenCalledTimes(1);
  });

  it('says why a document cannot be edited instead of offering an empty editor', async () => {
    render(
      <McpAddDialog
        open
        onClose={() => undefined}
        title="t"
        actions={actions({
          read: () =>
            Promise.resolve({
              servers: null,
              path: '/x',
              version: null,
              unavailableReason:
                '/x is not valid JSON, so geniro will not rewrite it',
            }),
        })}
        onChanged={() => undefined}
        initialMode="json"
      />,
    );
    await settle();
    expect(
      document.querySelector('[data-slot="mcp-json-unavailable"]')?.textContent,
    ).toBe('/x is not valid JSON, so geniro will not rewrite it');
    expect(button('Save')).toBeUndefined();
  });

  it('shows a refused save — a document that moved — and keeps the edit', async () => {
    render(
      <McpAddDialog
        open
        onClose={() => undefined}
        title="t"
        actions={actions({
          write: () =>
            Promise.reject(
              new Error('the MCP servers changed since the editor opened them'),
            ),
        })}
        onChanged={() => undefined}
        initialMode="json"
      />,
    );
    await settle();
    const editor = byLabel<HTMLTextAreaElement>('MCP servers');
    type(editor, '{ "other": { "url": "https://x" } }');
    click(button('Save'));
    await settle();
    expect(
      document.querySelector('[data-slot="mcp-json-error"]')?.textContent,
    ).toMatch(/changed since/);
    expect(editor.value).toBe('{ "other": { "url": "https://x" } }');
  });

  it('does not re-read and reset the edit when the caller re-renders with fresh actions', async () => {
    const read = vi.fn(() => Promise.resolve(DOC));
    const element = (): React.ReactElement => (
      <McpAddDialog
        open
        onClose={() => undefined}
        title="t"
        // A new object every render, as every caller binds it inline.
        actions={actions({ read })}
        onChanged={() => undefined}
        initialMode="json"
      />
    );
    render(element());
    await settle();
    const editor = byLabel<HTMLTextAreaElement>('MCP servers');
    type(editor, '{}');
    act(() => {
      root!.render(element());
    });
    await settle();
    expect(read).toHaveBeenCalledTimes(1);
    expect(byLabel<HTMLTextAreaElement>('MCP servers').value).toBe('{}');
  });
});
