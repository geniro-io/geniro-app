import type { Meta, StoryObj } from '@storybook/react-vite';
import { useState } from 'react';

import type { AgentMcpConfigDto } from '../autogenerated';
import { McpAddDialog, type McpConfigActions } from './mcp-add-dialog';

const DOCUMENT: AgentMcpConfigDto = {
  servers: {
    linear: { type: 'http', url: 'https://mcp.linear.app/mcp' },
    codegraph: { type: 'stdio', command: 'codegraph', args: ['mcp', 'start'] },
  },
  path: '/Users/me/.claude.json',
  version: 'sha256:demo',
  unavailableReason: null,
};

/** Answers after a beat, as the daemon does; nothing leaves the catalog. */
const later = <T,>(value: T): Promise<T> =>
  new Promise((resolve) => setTimeout(() => resolve(value), 500));

const ACTIONS: McpConfigActions = {
  read: () => later(DOCUMENT),
  write: (servers) => later({ ...DOCUMENT, servers }),
  add: () => later(DOCUMENT),
};

const meta = {
  title: 'Components/McpAddDialog',
  component: McpAddDialog,
  // A modal fills whatever box the docs preview gives it; sized to its form.
  decorators: [(story) => <div className="h-[640px]">{story()}</div>],
  args: {
    open: true,
    onClose: () => undefined,
    title: 'MCP servers — claude · add or edit',
    actions: ACTIONS,
    onChanged: () => undefined,
  },
  render: (args) => {
    const [open, setOpen] = useState(true);
    return (
      <McpAddDialog {...args} open={open} onClose={() => setOpen(false)} />
    );
  },
} satisfies Meta<typeof McpAddDialog>;

export default meta;
type Story = StoryObj<typeof meta>;

export const AddAServer: Story = {};

export const EditJson: Story = {
  args: { initialMode: 'json' },
};

export const AddRefused: Story = {
  args: {
    actions: {
      ...ACTIONS,
      add: () =>
        Promise.reject(
          new Error(
            'could not add linear for claude: a server named "linear" already exists in this profile — edit it in the JSON editor, or pick another name',
          ),
        ),
    },
  },
};

export const DocumentUnavailable: Story = {
  args: {
    initialMode: 'json',
    actions: {
      ...ACTIONS,
      read: () =>
        later({
          servers: null,
          path: '/Users/me/.claude.json',
          version: null,
          unavailableReason:
            '/Users/me/.claude.json is not valid JSON, so geniro will not rewrite it',
        }),
    },
  },
};
