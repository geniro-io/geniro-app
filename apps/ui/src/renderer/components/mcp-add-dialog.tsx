import { Loader2 } from 'lucide-react';
import { useEffect, useId, useRef, useState } from 'react';

import type { AgentMcpConfigDto } from '../autogenerated';
import { ErrorText } from './error-text';
import { Field } from './field';
import {
  EMPTY_MCP_SERVER_FORM,
  formatMcpServersJson,
  type McpServerDefinitions,
  type McpServerDraft,
  type McpServerFormValues,
  type McpTransport,
  readMcpServerForm,
  readMcpServersJson,
} from './mcp-server-form';
import { Button } from './ui/button';
import { Dialog } from './ui/dialog';
import { Input } from './ui/input';
import { SegmentedControl } from './ui/segmented-control';
import { Textarea } from './ui/textarea';

/**
 * What the dialog can do to ONE agent profile's MCP servers — bound by the
 * caller to a CLI and a config directory, so nothing here learns either.
 *
 * Each method rejects with the sentence to show (the daemon's own, where it
 * gave one); the dialog renders it as is and never composes a reason itself.
 */
export interface McpConfigActions {
  /** The profile's user-scope servers as the CLI's own document states them. */
  read: () => Promise<AgentMcpConfigDto>;
  /** Replace the whole map, at the version the editor opened. */
  write: (
    servers: McpServerDefinitions,
    version: string | null,
  ) => Promise<AgentMcpConfigDto>;
  /** Add one server through the CLI's own mechanism. */
  add: (server: McpServerDraft) => Promise<AgentMcpConfigDto>;
}

type Mode = 'add' | 'json';

const MODES: readonly { id: Mode; label: string }[] = [
  { id: 'add', label: 'Add a server' },
  { id: 'json', label: 'Edit JSON' },
];

const TRANSPORTS: readonly { id: McpTransport; label: string }[] = [
  { id: 'stdio', label: 'Command (stdio)' },
  { id: 'http', label: 'URL (http)' },
];

/**
 * Add an MCP server to one agent profile, or edit all of its servers as JSON.
 *
 * Two modes because they answer two different users. **Add** is the CLI's
 * own `mcp add` behind a form — a name, a command or a URL, its env or
 * headers — for someone who has a server's install line and wants it to work.
 * **Edit JSON** opens the profile's whole server map as the CLI keeps it
 * (claude's `mcpServers`, cursor's `mcp.json`, codex's `[mcp_servers]` table
 * read as JSON) for someone who wants to change what is already there; it
 * shows the user their own file, credentials included, and keeps no copy.
 *
 * Both write at USER scope — the profile, never a folder — which is what the
 * listing beneath it reads. A server that needs signing in shows up there with
 * the ordinary Sign in once the dialog closes.
 *
 * A save is refused, not merged, when the document moved since it was opened
 * (the daemon checks the version it was read at): the reader is shown the
 * daemon's sentence and reopens the editor on the current file.
 */
export function McpAddDialog({
  open,
  onClose,
  title,
  actions,
  onChanged,
  initialMode = 'add',
}: {
  open: boolean;
  onClose: () => void;
  title: string;
  actions: McpConfigActions;
  /** Called after a write landed, so the listing beneath can be re-read. */
  onChanged: () => void;
  initialMode?: Mode;
}): React.JSX.Element | null {
  const [mode, setMode] = useState<Mode>(initialMode);
  // A fresh dialog every time it opens: a half-typed form from an earlier
  // open belongs to a press the user abandoned.
  useEffect(() => {
    if (open) {
      setMode(initialMode);
    }
  }, [open, initialMode]);
  return (
    <Dialog open={open} onClose={onClose} title={title} className="max-w-xl">
      <div className="flex flex-col gap-3">
        <SegmentedControl
          ariaLabel="How to change the MCP servers"
          size="sm"
          options={MODES}
          value={mode}
          onSelect={setMode}
        />
        {!open ? null : mode === 'add' ? (
          <AddServerForm
            actions={actions}
            onDone={() => {
              onChanged();
              onClose();
            }}
          />
        ) : (
          <JsonEditor
            actions={actions}
            onDone={() => {
              onChanged();
              onClose();
            }}
          />
        )}
      </div>
    </Dialog>
  );
}

function AddServerForm({
  actions,
  onDone,
}: {
  actions: McpConfigActions;
  onDone: () => void;
}): React.JSX.Element {
  const id = useId();
  const [values, setValues] = useState<McpServerFormValues>(
    EMPTY_MCP_SERVER_FORM,
  );
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const checked = readMcpServerForm(values);
  const edited =
    values.name !== '' ||
    values.command !== '' ||
    values.url !== '' ||
    values.args !== '' ||
    values.env !== '' ||
    values.headers !== '';
  const set = (patch: Partial<McpServerFormValues>): void => {
    setValues((prev) => ({ ...prev, ...patch }));
    setError(null);
  };
  const submit = async (): Promise<void> => {
    if (!checked.ok || busy) {
      return;
    }
    setBusy(true);
    setError(null);
    try {
      await actions.add(checked.server);
      onDone();
    } catch (err: unknown) {
      setError(err instanceof Error ? err.message : String(err));
    } finally {
      setBusy(false);
    }
  };
  return (
    <form
      className="flex flex-col gap-3"
      onSubmit={(event) => {
        event.preventDefault();
        void submit();
      }}>
      <Field label="Name" htmlFor={`${id}-name`}>
        <Input
          id={`${id}-name`}
          value={values.name}
          placeholder="e.g. linear"
          autoComplete="off"
          spellCheck={false}
          onChange={(event) => set({ name: event.target.value })}
        />
      </Field>
      <SegmentedControl
        ariaLabel="Transport"
        size="sm"
        options={TRANSPORTS}
        value={values.transport}
        onSelect={(transport) => set({ transport })}
      />
      {values.transport === 'stdio' ? (
        <>
          <Field label="Command" htmlFor={`${id}-command`}>
            <Input
              id={`${id}-command`}
              className="font-mono"
              value={values.command}
              placeholder="npx"
              autoComplete="off"
              spellCheck={false}
              onChange={(event) => set({ command: event.target.value })}
            />
          </Field>
          <Field
            label="Arguments"
            htmlFor={`${id}-args`}
            hint="One per line, each passed exactly as written.">
            <Textarea
              id={`${id}-args`}
              className="min-h-14 font-mono text-xs"
              value={values.args}
              placeholder={'-y\n@acme/mcp-server'}
              spellCheck={false}
              onChange={(event) => set({ args: event.target.value })}
            />
          </Field>
          <Field
            label="Environment"
            htmlFor={`${id}-env`}
            hint="KEY=value, one per line.">
            <Textarea
              id={`${id}-env`}
              className="min-h-14 font-mono text-xs"
              value={values.env}
              placeholder="API_KEY=…"
              spellCheck={false}
              onChange={(event) => set({ env: event.target.value })}
            />
          </Field>
        </>
      ) : (
        <>
          <Field label="URL" htmlFor={`${id}-url`}>
            <Input
              id={`${id}-url`}
              className="font-mono"
              value={values.url}
              placeholder="https://mcp.example.com/mcp"
              autoComplete="off"
              spellCheck={false}
              onChange={(event) => set({ url: event.target.value })}
            />
          </Field>
          <Field
            label="Headers"
            htmlFor={`${id}-headers`}
            hint="Name: value, one per line. Leave empty for a server you sign in to.">
            <Textarea
              id={`${id}-headers`}
              className="min-h-14 font-mono text-xs"
              value={values.headers}
              placeholder="Authorization: Bearer …"
              spellCheck={false}
              onChange={(event) => set({ headers: event.target.value })}
            />
          </Field>
        </>
      )}
      {error !== null ? (
        <ErrorText data-slot="mcp-add-error" className="text-xs break-words">
          {error}
        </ErrorText>
      ) : !checked.ok && edited ? (
        <p
          data-slot="mcp-add-hint"
          className="m-0 text-xs text-muted-foreground">
          {checked.reason}
        </p>
      ) : null}
      <div className="flex items-center justify-end gap-2">
        <Button type="submit" size="sm" disabled={!checked.ok || busy}>
          {busy ? (
            <Loader2 aria-hidden="true" className="size-3.5 animate-spin" />
          ) : null}
          {busy ? 'Adding…' : 'Add server'}
        </Button>
      </div>
    </form>
  );
}

function JsonEditor({
  actions,
  onDone,
}: {
  actions: McpConfigActions;
  onDone: () => void;
}): React.JSX.Element {
  const id = useId();
  const [doc, setDoc] = useState<AgentMcpConfigDto | null>(null);
  const [readError, setReadError] = useState<string | null>(null);
  const [text, setText] = useState('');
  const [busy, setBusy] = useState(false);
  const [saveError, setSaveError] = useState<string | null>(null);
  // Read through a ref: callers bind the actions inline, so the object is
  // new on every render, and an effect keyed on it would re-read — and reset
  // the user's edit — each time anything above re-rendered.
  const actionsRef = useRef(actions);
  actionsRef.current = actions;
  // Read on MOUNT, which is every time the mode is entered: the file is the
  // user's and the CLI writes it too, so a copy from an earlier open is the
  // one thing this editor must not show.
  useEffect(() => {
    let live = true;
    actionsRef.current.read().then(
      (read) => {
        if (!live) {
          return;
        }
        setDoc(read);
        setText(
          read.servers === null ? '' : formatMcpServersJson(read.servers),
        );
      },
      (err: unknown) => {
        if (live) {
          setReadError(err instanceof Error ? err.message : String(err));
        }
      },
    );
    return () => {
      live = false;
    };
  }, []);
  if (readError !== null) {
    return <ErrorText className="text-xs break-words">{readError}</ErrorText>;
  }
  if (doc === null) {
    return (
      <p className="m-0 flex items-center gap-1.5 text-xs text-muted-foreground">
        <Loader2 aria-hidden="true" className="size-3 animate-spin" />
        Reading the profile’s MCP servers…
      </p>
    );
  }
  if (doc.servers === null) {
    return (
      <p
        data-slot="mcp-json-unavailable"
        className="m-0 text-xs break-words text-muted-foreground">
        {doc.unavailableReason}
      </p>
    );
  }
  const original = doc.servers;
  const checked = readMcpServersJson(text);
  const unchanged =
    checked.ok && JSON.stringify(checked.servers) === JSON.stringify(original);
  const save = async (): Promise<void> => {
    if (!checked.ok || busy) {
      return;
    }
    setBusy(true);
    setSaveError(null);
    try {
      await actions.write(checked.servers, doc.version);
      onDone();
    } catch (err: unknown) {
      setSaveError(err instanceof Error ? err.message : String(err));
    } finally {
      setBusy(false);
    }
  };
  return (
    <div className="flex flex-col gap-2">
      <Field
        label="MCP servers"
        htmlFor={`${id}-json`}
        hint={
          doc.path ? (
            <>
              Saved to <span className="font-mono break-all">{doc.path}</span> —
              this profile’s own servers, not a folder’s.
            </>
          ) : undefined
        }>
        <Textarea
          id={`${id}-json`}
          aria-invalid={!checked.ok}
          className="min-h-72 font-mono text-xs"
          value={text}
          spellCheck={false}
          onChange={(event) => {
            setText(event.target.value);
            setSaveError(null);
          }}
        />
      </Field>
      {saveError !== null ? (
        <ErrorText data-slot="mcp-json-error" className="text-xs break-words">
          {saveError}
        </ErrorText>
      ) : !checked.ok ? (
        <ErrorText data-slot="mcp-json-error" className="text-xs break-words">
          {checked.reason}
        </ErrorText>
      ) : null}
      <div className="flex items-center justify-end gap-2">
        <Button
          type="button"
          size="sm"
          disabled={!checked.ok || unchanged || busy}
          onClick={() => void save()}>
          {busy ? (
            <Loader2 aria-hidden="true" className="size-3.5 animate-spin" />
          ) : null}
          {busy ? 'Saving…' : 'Save'}
        </Button>
      </div>
    </div>
  );
}
