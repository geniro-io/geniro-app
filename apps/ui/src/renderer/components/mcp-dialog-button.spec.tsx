// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { AgentMcpListingDto as AgentMcpListing } from '../autogenerated';
import { McpDialogButton } from './mcp-dialog-button';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function render(element: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(element);
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const listing = (names: string[]): AgentMcpListing => ({
  servers: names.map((name) => ({
    name,
    status: 'connected',
    target: '',
    detail: null,
    disabled: false,
    transport: null,
    scope: 'unknown',
    toggleUnavailableReason: null,
    signInUnavailableReason: null,
    approveUnavailableReason: null,
    shadowsUser: false,
  })),
  unavailableReason: null,
  interactiveOnlyNote: null,
  pending: false,
});

const trigger = (el: HTMLDivElement): HTMLButtonElement =>
  el.querySelector<HTMLButtonElement>('[aria-label="MCP servers"]')!;

describe('McpDialogButton', () => {
  it('keeps the list behind the press — nothing of it is on screen closed', () => {
    // The reported defect on the builder's inspector: the listing stood open in
    // the panel, so a node with ten servers pushed its own wiring off the
    // bottom before anyone asked to see them.
    const el = render(
      <McpDialogButton
        title="MCP servers — reviewer"
        open={false}
        onOpenChange={() => {}}
        listing={listing(['github', 'linear'])}
        loading={false}
      />,
    );

    expect(el.textContent).not.toContain('github');
    expect(el.textContent).not.toContain('linear');
    expect(trigger(el).getAttribute('aria-expanded')).toBe('false');
  });

  it('opens the listing under the name of what it was opened from', () => {
    // Two agents' dialogs are identical but for this line, and the panel opens
    // them one at a time from rows that look alike.
    const el = render(
      <McpDialogButton
        title="MCP servers — reviewer"
        open
        onOpenChange={() => {}}
        listing={listing(['github'])}
        loading={false}
      />,
    );

    const dialog = el.querySelector('[role="dialog"]');
    expect(dialog?.textContent).toContain('MCP servers — reviewer');
    expect(dialog?.textContent).toContain('github');
  });

  it('asks the OWNER to open it, and stops the press reaching the row', () => {
    // The trigger sits inside rows that are (or may become) activatable, and
    // the open state is the owner's — the Agents panel keeps one open at a time
    // across every card, which a self-owned flag could not express.
    const onOpenChange = vi.fn();
    const onRowClick = vi.fn();
    const el = render(
      <div onClick={onRowClick}>
        <McpDialogButton
          title="MCP servers — reviewer"
          open={false}
          onOpenChange={onOpenChange}
          listing={undefined}
          loading={false}
        />
      </div>,
    );

    act(() => trigger(el).click());

    expect(onOpenChange).toHaveBeenCalledWith(true);
    expect(onRowClick).not.toHaveBeenCalled();
  });

  it('counts the servers on the chip, and only says so to a reader on the icon', () => {
    // The chip stands among other chips where a bare plug says nothing; the
    // icon sits in a control row with no room for a word, so its count is for
    // assistive tech alone.
    const chip = render(
      <McpDialogButton
        title="t"
        variant="chip"
        open={false}
        onOpenChange={() => {}}
        listing={listing(['a', 'b', 'c'])}
        loading={false}
      />,
    );
    expect(trigger(chip).textContent).toBe('MCP· 3');

    act(() => root?.unmount());
    container?.remove();

    const icon = render(
      <McpDialogButton
        title="t"
        open={false}
        onOpenChange={() => {}}
        listing={listing(['a', 'b', 'c'])}
        loading={false}
      />,
    );
    expect(trigger(icon).querySelector('.sr-only')?.textContent).toBe(
      '3 servers',
    );
  });

  it('offers no switch and no sign-in when the caller passed no way to do either', () => {
    // The builder's case: its listing is taken in no folder at all, so a switch
    // there would move and change nothing.
    const el = render(
      <McpDialogButton
        title="t"
        open
        onOpenChange={() => {}}
        listing={listing(['github'])}
        loading={false}
      />,
    );

    expect(el.querySelector('[role="switch"]')).toBeNull();
    expect(el.querySelector('[aria-label="Refresh MCP servers"]')).toBeNull();
  });
});
