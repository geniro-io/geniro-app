import type { Meta, StoryObj } from '@storybook/react-vite';
import { useState } from 'react';

import type {
  AgentMcpListingDto as AgentMcpListing,
  AgentMcpServer,
} from '../autogenerated';
import { McpDialogButton } from './mcp-dialog-button';

function server(
  overrides: Partial<AgentMcpServer> & Pick<AgentMcpServer, 'name' | 'status'>,
): AgentMcpServer {
  return {
    target: null,
    transport: 'stdio',
    detail: null,
    scope: 'workspace',
    shadowsUser: false,
    disabled: false,
    toggleUnavailableReason: null,
    signInUnavailableReason: null,
    approveUnavailableReason: null,
    ...overrides,
  };
}

const LISTING: AgentMcpListing = {
  servers: [
    server({
      name: 'codegraph',
      status: 'connected',
      target: 'codegraph mcp start',
    }),
    server({
      name: 'linear',
      status: 'failed',
      detail: 'connect ECONNREFUSED 127.0.0.1:9821 — is the server running?',
    }),
    server({ name: 'ticktick', status: 'needs_auth' }),
  ],
  unavailableReason: null,
  pending: false,
  interactiveOnlyNote: null,
};

const meta = {
  title: 'Components/McpDialogButton',
  component: McpDialogButton,
  args: {
    // open/onOpenChange are dummy defaults satisfying the required-args
    // type — the render below owns real open state and ignores these.
    open: true,
    onOpenChange: () => undefined,
    title: 'MCP servers',
    listing: LISTING,
    loading: false,
    onSetEnabled: () => undefined,
    onSignIn: () => undefined,
    onRefresh: () => undefined,
  },
  // The dialog is the whole point of the control, so the demo starts it open
  // rather than showing only the closed trigger.
  render: (args) => {
    const [open, setOpen] = useState(true);
    return <McpDialogButton {...args} open={open} onOpenChange={setOpen} />;
  },
} satisfies Meta<typeof McpDialogButton>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Playground: Story = {};

export const ChipVariant: Story = {
  args: { variant: 'chip' },
};

export const ChipInLabelledRow: Story = {
  args: { variant: 'chip', chipNamesItself: false },
};

export const SigningIn: Story = {
  args: {
    signingIn: 'ticktick',
    loginServer: 'ticktick',
    loginPanel: (
      <div className="rounded-md border border-border bg-muted px-2.5 py-2 text-xs text-muted-foreground">
        Waiting for the browser sign-in to finish…
      </div>
    ),
  },
};
