import { Plug } from 'lucide-react';

import type { AgentMcpListingDto as AgentMcpListing } from '../autogenerated';
import { McpSection } from './mcp-section';
import { Button } from './ui/button';
import { chipVariants } from './ui/chip';
import { Dialog } from './ui/dialog';
import { cn } from './ui/utils';

/**
 * The MCP control: one press opens a listing in a MODAL DIALOG.
 *
 * A dialog and not a popover, which is the third placement this list has had
 * and the first one sized for what it actually holds. It was a full-width band
 * across its surface, which pushed everything else off the bottom whenever it
 * was open; then a popover anchored to a 24px trigger inside a 280px panel —
 * ten server rows, each able to carry a paragraph of connection-failure text,
 * do not fit in one, and it closed on the first pointer press that landed
 * anywhere else. Toggling a server on and off is deliberate work, so it gets
 * the surface deliberate work gets: a centered card with room, a backdrop,
 * Escape, and focus that stays put until it is dismissed.
 *
 * Shared by the chat Agents panel (an icon beside the terminal one, on a card
 * with no room for a word) and the graph builder's node inspector (a chip in
 * the node's settings row, where its neighbours are all chips). The trigger is
 * the only thing that differs, and it is a {@link variant} rather than two
 * components: what a press opens, what the dialog is titled and which of the
 * section's write paths are offered are the parts that must not drift.
 */
export function McpDialogButton({
  title,
  variant = 'icon',
  chipNamesItself = true,
  open,
  onOpenChange,
  listing,
  loading,
  hint,
  onRefresh,
  onSetEnabled,
  onSignIn,
  signingIn,
  loginServer,
  loginPanel,
  className,
}: {
  /** Names the dialog, so several openable ones stay tellable apart. */
  title: string;
  /** `icon` for a control row, `chip` beside other chips. */
  variant?: 'icon' | 'chip';
  /**
   * Whether the `chip` names ITSELF — `MCP · 10` rather than `10 servers`.
   *
   * True beside other chips, which is where a control has to say what it is.
   * False in a LABELLED ROW, where the row's own label already says `MCP` and
   * repeating it stutters (`MCP    MCP · 10`); the chip then spends its width
   * on the only thing left to say, which is the count. It still reads as a
   * control rather than as text, because the plug glyph and the chip's own
   * hover fill are unchanged.
   */
  chipNamesItself?: boolean;
  open: boolean;
  onOpenChange: (open: boolean) => void;
  listing: AgentMcpListing | undefined;
  loading: boolean;
  /** What this particular listing covers, when it is not simply "a folder". */
  hint?: string;
  /** Re-dial each server. Absent hides the control. */
  onRefresh?: () => void;
  /**
   * Switch one server on or off. Absent renders every row read-only — the
   * builder's case, whose listing is taken in no folder at all.
   */
  onSetEnabled?: (server: string, enabled: boolean) => void;
  /** Sign one server in. Absent hides the action, on the same rule. */
  onSignIn?: (server: string) => void;
  /**
   * The server whose sign-in has been asked for and not yet answered.
   *
   * Threaded rather than derived from {@link loginPanel}: that panel only
   * exists once the daemon has ANSWERED, and the four seconds before it does
   * are exactly the window this covers.
   */
  signingIn?: string | null;
  /**
   * Which server {@link loginPanel} is about — null when nothing is signing in.
   */
  loginServer?: string | null;
  /**
   * A sign-in in flight, rendered UNDER THE ROW that started it. The CLI's own
   * browser tab opens behind the app, so without this the Sign in control
   * reads as a button that did nothing.
   *
   * It used to be a sibling of the whole listing, pinned to the dialog's foot,
   * and that is the reported "I have broken UI - i wanna this status line from
   * down to b under item where we actually clicked sign in": on a listing with
   * three signed-out rows the strip named no server and could have been about
   * any of them.
   */
  loginPanel?: React.ReactNode;
  className?: string;
}): React.JSX.Element {
  const count = listing?.servers?.length ?? 0;
  const toggle = (event: React.MouseEvent): void => {
    // The trigger sits inside rows that a later change could make activatable
    // (the Agents panel's list item, the inspector's settings band), and a
    // stray activation is not something a reader would trace back here.
    event.stopPropagation();
    onOpenChange(!open);
  };
  return (
    <>
      {variant === 'chip' ? (
        <button
          type="button"
          aria-expanded={open}
          aria-label="MCP servers"
          title="MCP servers this agent loads"
          className={cn(
            chipVariants({ interactive: true, tone: 'active' }),
            className,
          )}
          onClick={toggle}>
          <Plug aria-hidden="true" />
          {chipNamesItself ? (
            <>
              <span className="truncate">MCP</span>
              {count > 0 ? (
                <span className="text-muted-foreground">· {count}</span>
              ) : null}
            </>
          ) : (
            // Spelled out rather than a bare number: `10` alone beside a `MCP`
            // label reads as a setting whose VALUE is ten, and `0` reads as a
            // broken listing rather than as a folder with no servers.
            <span className="truncate">
              {count === 0
                ? 'No servers'
                : `${count} server${count === 1 ? '' : 's'}`}
            </span>
          )}
        </button>
      ) : (
        <Button
          type="button"
          variant="ghost"
          size="icon"
          aria-expanded={open}
          aria-label="MCP servers"
          title="MCP servers this agent loads here"
          className={cn('size-6 shrink-0 text-muted-foreground', className)}
          onClick={toggle}>
          <Plug aria-hidden="true" className="size-3.5 shrink-0" />
          {count > 0 ? <span className="sr-only">{count} servers</span> : null}
        </Button>
      )}
      <Dialog
        open={open}
        onClose={() => onOpenChange(false)}
        title={title}
        className="max-w-lg">
        <McpSection
          listing={listing}
          loading={loading}
          hint={hint}
          onRefresh={onRefresh}
          onSetEnabled={onSetEnabled}
          onSignIn={onSignIn}
          signingIn={signingIn}
          // Handed DOWN rather than rendered after the section, which is where
          // it used to sit: only the section knows what the rows are, so only
          // it can put the panel under the one the sign-in was started from.
          loginServer={loginServer}
          loginPanel={loginPanel}
          // The dialog IS the section's chrome here, so the card-band edges (a
          // top rule, the card's own padding) would draw a stray line across a
          // panel that is already bounded.
          className="border-t-0"
        />
      </Dialog>
    </>
  );
}
