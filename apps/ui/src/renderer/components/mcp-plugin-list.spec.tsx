// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { AgentMcpPlugin } from '../autogenerated';
import { type AddPluginServer, McpPluginList } from './mcp-plugin-list';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

function render(
  plugins: AgentMcpPlugin[],
  onAdd?: AddPluginServer,
): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root?.render(<McpPluginList plugins={plugins} onAdd={onAdd} />);
  });
  return container;
}

function plugin(overrides: Partial<AgentMcpPlugin> = {}): AgentMcpPlugin {
  return {
    name: 'datadog',
    enabledHere: true,
    servers: [
      {
        name: 'datadog',
        id: 'plugin-datadog-datadog',
        transport: 'http',
        target: 'https://${DD_MCP_DOMAIN:-not-setup}/v1/mcp',
        copiedAs: null,
      },
    ],
    variables: [],
    ...overrides,
  };
}

const DOMAIN = {
  name: 'DD_MCP_DOMAIN',
  title: 'Datadog Domain',
  description: 'Pick your [site](https://docs.datadoghq.com/)',
  options: ['mcp.datadoghq.com', 'mcp.datadoghq.eu'],
  required: true,
  defaultValue: null,
};

function button(root: HTMLElement, label: string): HTMLButtonElement {
  const found = [...root.querySelectorAll('button')].find(
    (candidate) => candidate.textContent?.trim() === label,
  );
  if (!found) {
    throw new Error(`no button "${label}"`);
  }
  return found;
}

async function flush(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
  });
}

describe('McpPluginList', () => {
  it('names each plugin with where it is enabled, and a copied server by its entry', () => {
    const view = render(
      [
        plugin(),
        plugin({
          name: 'linear',
          enabledHere: null,
          servers: [
            {
              name: 'linear',
              id: 'plugin-linear-linear',
              transport: 'http',
              target: 'https://mcp.linear.app/mcp',
              copiedAs: 'linear',
            },
          ],
        }),
      ],
      vi.fn(),
    );

    expect(view.textContent).toContain('datadog· enabled in this folder');
    expect(view.textContent).toContain('linear· installed');
    expect(view.textContent).toContain('in config as linear');
    // Only the server not yet in the config offers Add.
    expect(
      [...view.querySelectorAll('button')].filter(
        (b) => b.textContent?.trim() === 'Add',
      ),
    ).toHaveLength(1);
  });

  it('copies a server that needs nothing filled in on the first press', async () => {
    const onAdd = vi.fn<AddPluginServer>(() => Promise.resolve(null));
    const view = render([plugin()], onAdd);

    act(() => button(view, 'Add').click());
    await flush();

    expect(onAdd).toHaveBeenCalledWith('datadog', 'datadog', {});
  });

  it('asks for the plugin’s variables first, holding Add until a required one is chosen', async () => {
    const onAdd = vi.fn<AddPluginServer>(() => Promise.resolve(null));
    const view = render([plugin({ variables: [DOMAIN] })], onAdd);

    act(() => button(view, 'Add').click());
    expect(onAdd).not.toHaveBeenCalled();
    const form = view.querySelector('form');
    expect(form?.textContent).toContain('Datadog Domain');
    // The manifest's markdown link reads as its text.
    expect(form?.textContent).toContain('Pick your site');
    const submit = form?.querySelector<HTMLButtonElement>(
      'button[type="submit"]',
    );
    expect(submit?.disabled).toBe(true);

    act(() => form?.querySelector<HTMLElement>('[data-menu-trigger]')?.click());
    const option = [
      ...document.querySelectorAll<HTMLElement>('[role="option"]'),
    ].find((candidate) => candidate.textContent?.includes('mcp.datadoghq.eu'));
    act(() => option?.click());
    expect(submit?.disabled).toBe(false);
    act(() => submit?.click());
    await flush();

    expect(onAdd).toHaveBeenCalledWith('datadog', 'datadog', {
      DD_MCP_DOMAIN: 'mcp.datadoghq.eu',
    });
    // Accepted: the form closes.
    expect(view.querySelector('form')).toBeNull();
  });

  it('keeps the form and shows the daemon’s refusal beside it', async () => {
    const onAdd = vi.fn<AddPluginServer>(() =>
      Promise.resolve('mcp.json already has a server named datadog'),
    );
    const view = render(
      [
        plugin({
          variables: [{ ...DOMAIN, defaultValue: 'mcp.datadoghq.com' }],
        }),
      ],
      onAdd,
    );

    act(() => button(view, 'Add').click());
    act(() =>
      view.querySelector<HTMLButtonElement>('button[type="submit"]')?.click(),
    );
    await flush();

    expect(view.querySelector('form')).not.toBeNull();
    expect(view.textContent).toContain(
      'mcp.json already has a server named datadog',
    );
  });

  it('offers no Add on a surface with nowhere to add from', () => {
    const view = render([plugin()]);

    expect(view.textContent).toContain('datadog');
    expect(
      [...view.querySelectorAll('button')].some(
        (b) => b.textContent?.trim() === 'Add',
      ),
    ).toBe(false);
  });
});
