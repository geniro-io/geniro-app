import { Check, Loader2, Puzzle } from 'lucide-react';
import { useState } from 'react';

import type {
  AgentMcpPlugin,
  AgentMcpPluginServer,
  AgentMcpPluginVariable,
} from '../autogenerated';
import { ErrorText } from './error-text';
import { Button } from './ui/button';
import { Input } from './ui/input';
import { Label } from './ui/label';
import { Select } from './ui/select';

/**
 * Copy one plugin server into the agent's own config. Answers the daemon's
 * refusal as a sentence, or null once the server is in the config.
 */
export type AddPluginServer = (
  plugin: string,
  server: string,
  variables: Record<string, string>,
) => Promise<string | null>;

function enabledLabel(enabledHere: boolean | null): string {
  if (enabledHere === null) {
    return 'installed';
  }
  return enabledHere ? 'enabled in this folder' : 'turned off in this folder';
}

/** A manifest description is markdown; its links read better as their text. */
function plainDescription(text: string): string {
  return text.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1');
}

/**
 * The plugins whose servers the agent's own app loads and geniro's sessions do
 * not, each server with a way to copy it into the config they DO read.
 *
 * Why the gap exists, and what Add writes, is the daemon's sentence and is
 * shown by the section around this list — nothing here names a CLI.
 */
export function McpPluginList({
  plugins,
  onAdd,
}: {
  plugins: AgentMcpPlugin[];
  /** Absent renders the list read-only — a surface with no folder to add from. */
  onAdd?: AddPluginServer;
}): React.JSX.Element {
  // One form open at a time: two half-filled forms on one short list read as
  // one, and the second press would be about whichever the eye landed on.
  const [openKey, setOpenKey] = useState<string | null>(null);
  return (
    <ul className="m-0 flex list-none flex-col gap-2 p-0">
      {plugins.map((plugin) => (
        <li key={plugin.name} className="flex flex-col gap-1">
          <span className="flex items-center gap-1.5 text-xs">
            <Puzzle
              aria-hidden="true"
              className="size-3 shrink-0 text-muted-foreground"
            />
            <span className="font-medium">{plugin.name}</span>
            <span className="text-muted-foreground">
              · {enabledLabel(plugin.enabledHere)}
            </span>
          </span>
          <ul className="m-0 flex list-none flex-col gap-1 p-0 pl-4">
            {plugin.servers.map((server) => {
              const key = `${plugin.name}\u0000${server.name}`;
              return (
                <PluginServerRow
                  key={key}
                  plugin={plugin}
                  server={server}
                  onAdd={onAdd}
                  formOpen={openKey === key}
                  onFormOpenChange={(open) => setOpenKey(open ? key : null)}
                />
              );
            })}
          </ul>
        </li>
      ))}
    </ul>
  );
}

function PluginServerRow({
  plugin,
  server,
  onAdd,
  formOpen,
  onFormOpenChange,
}: {
  plugin: AgentMcpPlugin;
  server: AgentMcpPluginServer;
  onAdd?: AddPluginServer;
  formOpen: boolean;
  onFormOpenChange: (open: boolean) => void;
}): React.JSX.Element {
  const [adding, setAdding] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const submit = async (variables: Record<string, string>): Promise<void> => {
    if (!onAdd) {
      return;
    }
    setAdding(true);
    setError(null);
    const refused = await onAdd(plugin.name, server.name, variables);
    setAdding(false);
    if (refused === null) {
      onFormOpenChange(false);
    } else {
      setError(refused);
    }
  };
  return (
    <li className="flex flex-col gap-1" data-slot="mcp-plugin-server">
      <div className="flex min-w-0 items-center gap-2 text-xs">
        <span className="shrink-0 font-medium">{server.name}</span>
        {server.target ? (
          <span
            className="min-w-0 truncate text-muted-foreground"
            title={server.target}>
            {server.target}
          </span>
        ) : null}
        <span className="ml-auto shrink-0">
          {server.copiedAs !== null ? (
            <span
              className="flex items-center gap-1 text-muted-foreground"
              title="geniro's sessions load it from the agent's own MCP config">
              <Check aria-hidden="true" className="size-3" />
              in config as {server.copiedAs}
            </span>
          ) : onAdd && !formOpen ? (
            <Button
              type="button"
              variant="outline"
              size="sm"
              className="h-5 gap-1 px-1.5 text-[11px]"
              disabled={adding}
              title="Copy this server into the agent's own MCP config so geniro's sessions load it"
              onClick={() =>
                plugin.variables.length === 0
                  ? void submit({})
                  : onFormOpenChange(true)
              }>
              {adding ? (
                <Loader2 aria-hidden="true" className="animate-spin" />
              ) : null}
              Add
            </Button>
          ) : null}
        </span>
      </div>
      {formOpen ? (
        <PluginVariablesForm
          variables={plugin.variables}
          busy={adding}
          onSubmit={(values) => void submit(values)}
          onCancel={() => {
            setError(null);
            onFormOpenChange(false);
          }}
        />
      ) : null}
      {error !== null ? <ErrorText>{error}</ErrorText> : null}
    </li>
  );
}

function PluginVariablesForm({
  variables,
  busy,
  onSubmit,
  onCancel,
}: {
  variables: AgentMcpPluginVariable[];
  busy: boolean;
  onSubmit: (values: Record<string, string>) => void;
  onCancel: () => void;
}): React.JSX.Element {
  const [values, setValues] = useState<Record<string, string>>(() =>
    Object.fromEntries(
      variables.map((variable) => [variable.name, variable.defaultValue ?? '']),
    ),
  );
  const missing = variables.some(
    (variable) =>
      variable.required && (values[variable.name] ?? '').trim() === '',
  );
  return (
    <form
      className="flex flex-col gap-2 rounded-md border border-border p-2"
      onSubmit={(event) => {
        event.preventDefault();
        if (!missing) {
          onSubmit(values);
        }
      }}>
      {variables.map((variable) => {
        const id = `mcp-plugin-var-${variable.name}`;
        const set = (value: string): void =>
          setValues((prev) => ({ ...prev, [variable.name]: value }));
        return (
          <div key={variable.name} className="flex flex-col gap-1">
            <Label htmlFor={id} className="text-xs">
              {variable.title ?? variable.name}
              {variable.required ? null : (
                <span className="font-normal text-muted-foreground">
                  {' '}
                  (optional)
                </span>
              )}
            </Label>
            {variable.options !== null ? (
              <Select
                id={id}
                groups={[
                  {
                    items: variable.options.map((option) => ({
                      value: option,
                      label: option,
                    })),
                  },
                ]}
                value={values[variable.name] || null}
                placeholder="Choose…"
                onValueChange={set}
              />
            ) : (
              <Input
                id={id}
                className="h-8 text-xs"
                value={values[variable.name] ?? ''}
                onChange={(event) => set(event.target.value)}
              />
            )}
            {variable.description ? (
              <span className="text-xs text-muted-foreground">
                {plainDescription(variable.description)}
              </span>
            ) : null}
          </div>
        );
      })}
      <div className="flex justify-end gap-1.5">
        <Button
          type="button"
          variant="ghost"
          size="sm"
          className="h-7"
          onClick={onCancel}>
          Cancel
        </Button>
        <Button
          type="submit"
          size="sm"
          className="h-7"
          disabled={missing || busy}>
          {busy ? (
            <Loader2 aria-hidden="true" className="animate-spin" />
          ) : null}
          Add
        </Button>
      </div>
    </form>
  );
}
