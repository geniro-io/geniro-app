// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type {
  AgentMcpListingDto as AgentMcpListing,
  AgentMcpServer,
} from '../autogenerated';
import { McpSection } from './mcp-section';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

function listing(
  ...servers: {
    name: string;
    toggleUnavailableReason?: string | null;
    signInUnavailableReason?: string | null;
    target?: string | null;
    detail?: string | null;
    status?: AgentMcpServer['status'];
    disabled?: boolean;
  }[]
): AgentMcpListing {
  return {
    servers: servers.map((s) => ({
      name: s.name,
      target: s.target === undefined ? `node ${s.name}.js` : s.target,
      transport: 'stdio',
      status: s.status ?? 'connected',
      detail: s.detail ?? null,
      scope: 'project',
      disabled: s.disabled ?? false,
      toggleUnavailableReason: s.toggleUnavailableReason ?? null,
      signInUnavailableReason: s.signInUnavailableReason ?? null,
    })),
    unavailableReason: null,
  } as unknown as AgentMcpListing;
}

function render(props: Parameters<typeof McpSection>[0]): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(<McpSection {...props} />);
  });
  return container;
}

describe('McpSection — what the CLI loads only for itself', () => {
  const NOTE =
    'claude also loads claude-in-chrome and computer-use in its own interactive session.';

  it('shows the daemon’s note under the rows, verbatim', () => {
    // The panel is COMPLETE for the turns geniro runs, but the user compares
    // it against their terminal's `/mcp`, which lists more. Without this line
    // the only available reading is that rows went missing.
    const el = render({
      listing: {
        ...listing({ name: 'srv' }),
        interactiveOnlyNote: NOTE,
      },
      loading: false,
    });

    expect(el.textContent).toContain(NOTE);
  });

  it('shows it on an EMPTY folder too, where the question is loudest', () => {
    const el = render({
      listing: { ...listing(), interactiveOnlyNote: NOTE },
      loading: false,
    });

    expect(el.textContent).toContain('No servers');
    expect(el.textContent).toContain(NOTE);
    // The settled-empty half of the loading/empty pair: `servers: []` with
    // `loading: false` is the only state that may claim the folder has none.
    expect(el.textContent).not.toContain('Loading…');
  });

  it('renders nothing extra for a CLI that declares no such gap', () => {
    // cursor-agent's `interactiveOnlyNote` is null, and a paragraph of empty
    // space under its rows would be the tell that the section invented one.
    const el = render({
      listing: { ...listing({ name: 'srv' }), interactiveOnlyNote: null },
      loading: false,
    });

    expect(el.textContent).not.toContain('interactive session');
  });
});

describe('McpSection', () => {
  it('offers a switch on a surface that has a write path', () => {
    const el = render({
      listing: listing({ name: 'srv' }),
      loading: false,
      onSetEnabled: vi.fn(),
    });

    expect(el.querySelector('[aria-label="Load srv"]')).not.toBeNull();
  });

  it('shows the daemon’s reason instead of a switch it could not honour', () => {
    const el = render({
      listing: listing({
        name: 'srv',
        toggleUnavailableReason: 'not a project server',
      }),
      loading: false,
      onSetEnabled: vi.fn(),
    });

    expect(el.querySelector('[aria-label="Load srv"]')).toBeNull();
    expect(
      el.querySelector('[aria-label="not a project server"]'),
    ).not.toBeNull();
  });

  it('renders NEITHER switch nor lock on a read-only surface', () => {
    // The graph inspector's arm, and the reason this component was promoted
    // out of the chat panel. Its rows come from a listing taken in a folder
    // geniro owns, so every one of them carries a folder-scoped
    // `toggleUnavailableReason` — rendering that padlock would explain why a
    // control is unavailable on a surface where no control was ever going to
    // appear, citing a folder the workflow does not yet have.
    const el = render({
      listing: listing({
        name: 'srv',
        toggleUnavailableReason: 'not a project server',
      }),
      loading: false,
    });

    expect(el.querySelector('[aria-label="Load srv"]')).toBeNull();
    expect(el.querySelector('[aria-label="not a project server"]')).toBeNull();
    // ...but the server itself is still listed.
    expect(el.textContent).toContain('srv');
  });

  it('renders the hint when one is given, and nothing when not', () => {
    const withHint = render({
      listing: listing({ name: 'srv' }),
      loading: false,
      hint: 'Global servers only.',
    });
    expect(withHint.textContent).toContain('Global servers only.');

    act(() => {
      root!.unmount();
    });
    container!.remove();
    const without = render({
      listing: listing({ name: 'srv' }),
      loading: false,
    });
    expect(without.textContent).not.toContain('Global servers only.');
  });

  it('carries NO tooltip for a server whose CLI reported neither a target nor a detail', () => {
    // cursor prints `<name>: ready` and nothing else, so both fields are null.
    // What this catches is a `?? ''` fallback, which renders an empty tooltip
    // that follows the pointer around saying nothing. It does NOT pin the
    // trailing `?? undefined` — React omits a null attribute anyway, so that
    // half exists only to satisfy `title?: string`.
    const el = render({
      listing: listing({ name: 'srv', target: null }),
      loading: false,
    });

    const row = el.querySelector('li');
    expect(row).not.toBeNull();
    expect(row?.hasAttribute('title')).toBe(false);
    // ...and the server is still listed, health badge and all.
    expect(row?.textContent).toContain('srv');
  });

  it('carries no tooltip for an EMPTY target either, not just a null one', () => {
    // Absent is not only null: claude's parser yields `target: ''` for a row
    // whose command column is blank, and `??` would let that through as
    // `title=""` — an empty tooltip that follows the pointer saying nothing.
    const el = render({
      listing: listing({ name: 'srv', target: '', detail: null }),
      loading: false,
    });

    expect(el.querySelector('li > span')?.hasAttribute('title')).toBe(false);
  });

  it('carries NO tooltip for a target the CLI left blank', () => {
    // The `||` vs `??` distinction, actually driven. claude's parser yields
    // `target: ''` for a row whose command column is blank, and `??` would pass
    // that straight through as `title=""` — a tooltip that follows the pointer
    // saying nothing. Every other case here uses a non-empty target, which both
    // operators handle identically, so this is the only one that can fail.
    const el = render({
      listing: listing({ name: 'srv', target: '' }),
      loading: false,
    });

    expect(el.querySelector('li > span')?.hasAttribute('title')).toBe(false);
  });

  it('keeps the command line in the tooltip, where wanting it is optional', () => {
    // The command line is context, not an instruction. Rewriting the tooltip
    // as `title={server.target ?? undefined}` would pass claude's blank column
    // through as `title=""` — a tooltip that follows the pointer saying
    // nothing — which is what the `||` guards.
    const el = render({
      listing: listing({ name: 'srv' }),
      loading: false,
    });

    expect(el.querySelector('li > span')?.getAttribute('title')).toBe(
      'node srv.js',
    );
  });

  it('renders a FAILURE reason as text, not only as a tooltip', () => {
    // The reason is the only actionable part of a failure — fix a path, start
    // a service, sign in — and it used to live solely in a `title` on a
    // non-focusable `li`. A keyboard user could see the badge go red and never
    // reach the sentence explaining it.
    const el = render({
      listing: listing({
        name: 'srv',
        status: 'failed',
        detail: 'HTTP 502: dial failed',
      }),
      loading: false,
    });

    expect(el.textContent).toContain('HTTP 502: dial failed');
    // And it is NOT hidden behind the pointer any more.
    expect(el.querySelector('li > span')?.getAttribute('title')).toBe(
      'node srv.js',
    );
  });

  it('folds a LONG failure reason, and unfolds it on request', () => {
    // The reported symptom: a JSON-RPC 404 body is hundreds of characters of
    // protocol envelope around one useful sentence, and several at once turned
    // the panel into a wall of red. It is still all there — one press away —
    // rather than truncated, because the tail is sometimes the actionable part.
    const long = `HTTP 404: Streamable HTTP error: Error POSTing to endpoint: ${'{"type":"error"}'.repeat(20)}`;
    const el = render({
      listing: listing({ name: 'srv', status: 'failed', detail: long }),
      loading: false,
    });

    const reason = el.querySelector('.text-destructive')!;
    expect(reason.className).toContain('line-clamp-2');
    const toggle = [...el.querySelectorAll('button')].find(
      (button) => button.textContent === 'Show more',
    );
    expect(toggle).toBeDefined();
    // Smaller than the reason it folds. At the row's own size it read as the
    // loudest thing in the panel and drew the eye ahead of the failure it
    // belongs to — this is a disclosure control, not a peer of the message.
    expect(toggle!.className).toContain('text-[11px]');
    expect(reason.className).not.toContain('text-[11px]');

    act(() => {
      toggle!.click();
    });
    expect(el.querySelector('.text-destructive')!.className).not.toContain(
      'line-clamp-2',
    );
    expect(
      [...el.querySelectorAll('button')].some(
        (button) => button.textContent === 'Show less',
      ),
    ).toBe(true);
  });

  it('leaves a SHORT failure reason unfolded, with no toggle to press', () => {
    // Folding a one-line reason would add a control that reveals nothing.
    const el = render({
      listing: listing({
        name: 'srv',
        status: 'failed',
        detail: 'HTTP 502: dial failed',
      }),
      loading: false,
    });

    expect(el.querySelector('.text-destructive')!.className).not.toContain(
      'line-clamp-2',
    );
    expect(
      [...el.querySelectorAll('button')].some((button) =>
        button.textContent?.startsWith('Show '),
      ),
    ).toBe(false);
  });

  it('wraps an unbroken failure reason instead of overflowing the panel', () => {
    // These strings are routinely one unbroken token — a URL, or a serialized
    // error object with no spaces. Without a wrap rule the text does not widen
    // the panel, it runs out past its edge and is simply unreadable.
    const el = render({
      listing: listing({
        name: 'srv',
        status: 'failed',
        detail: `https://example.invalid/${'a'.repeat(300)}`,
      }),
      loading: false,
    });

    // All THREE, because `break-words` alone does not stop the overflow: the
    // text is a flex child, and a flex child's min-width defaults to its
    // content — so without `min-w-0` on both the text and the column that
    // holds it, the box refuses to shrink and the wrap rule never gets to
    // apply. Asserting only the wrap class certified the wrong half.
    const reason = el.querySelector('.text-destructive')!;
    expect(reason.className).toContain('break-words');
    expect(reason.className).toContain('min-w-0');
    expect(reason.parentElement!.className).toContain('min-w-0');
  });

  it('does not print a detail for a server that did not fail', () => {
    // A healthy list stays one line per server. Dropping the status guard puts
    // an explanatory sentence under rows with nothing to explain.
    const el = render({
      listing: listing({ name: 'srv', detail: 'connected in 12ms' }),
      loading: false,
    });

    expect(el.textContent).not.toContain('connected in 12ms');
  });

  it('renders a CLI-reported disabled server struck through, and never as broken', () => {
    // cursor's `mcp disable` state. It is a stated choice rather than a
    // failure, so it must not wear the destructive tone — and the row still
    // has to be visible: before this status existed the row vanished entirely.
    // The fixture is named `srv-x`, NOT `off-srv`: with that name
    // `toContain('off')` was satisfied by the server's own name, so the badge
    // assertion passed with the badge deleted. (The pre-diff version asserted
    // `toContain('disabled')`, which discriminated; the label rename to `off`
    // is what made it tautological.)
    const el = render({
      listing: listing({ name: 'srv-x', status: 'disabled', disabled: true }),
      loading: false,
    });

    const row = el.querySelector('li');
    expect(row?.textContent).toContain('srv-x');
    expect(row?.textContent).toContain('off');
    expect(row?.querySelector('.line-through')).not.toBeNull();
    expect(row?.querySelector('.bg-destructive')).toBeNull();
  });

  it('shows the adapter’s own sentence rather than an empty list', () => {
    const el = render({
      listing: {
        servers: [],
        unavailableReason: 'cursor-agent cannot list MCP servers',
      } as unknown as AgentMcpListing,
      loading: false,
    });

    expect(el.textContent).toContain('cursor-agent cannot list MCP servers');
    expect(el.textContent).not.toContain('No servers');
  });

  it('offers a re-dial only where the surface asked for one', () => {
    // The Agents panel puts its control in the PANEL header, because it shows
    // one listing per CLI and a per-section button would be the same action
    // offered several times. A surface that shows exactly one listing has
    // nowhere else to put it.
    const withoutRefresh = render({
      listing: listing({ name: 'srv' }),
      loading: false,
    });
    expect(
      withoutRefresh.querySelector('[aria-label="Refresh MCP servers"]'),
    ).toBeNull();

    act(() => {
      root?.unmount();
    });
    container?.remove();

    const onRefresh = vi.fn();
    const el = render({
      listing: listing({ name: 'srv' }),
      loading: false,
      onRefresh,
    });
    const button = el.querySelector<HTMLButtonElement>(
      '[aria-label="Refresh MCP servers"]',
    );
    expect(button).not.toBeNull();

    act(() => {
      button!.click();
    });
    expect(onRefresh).toHaveBeenCalledTimes(1);
  });

  it('does not let a second re-dial be asked for while one is running', () => {
    // The read health-checks — it launches the user's own MCP servers — so a
    // click-happy user must not be able to stack them.
    const onRefresh = vi.fn();
    const el = render({
      listing: listing({ name: 'srv' }),
      loading: true,
      onRefresh,
    });

    const button = el.querySelector<HTMLButtonElement>(
      '[aria-label="Refresh MCP servers"]',
    );
    expect(button?.disabled).toBe(true);
    act(() => {
      button!.click();
    });
    expect(onRefresh).not.toHaveBeenCalled();
  });
});

describe('McpSection — an empty listing that is still being dialled', () => {
  // `servers: []` is what a cold read in progress and a folder with none BOTH
  // look like on the wire: the daemon answers early with empty rows and
  // `pending: true` because dialling every server takes seconds. `loading` is
  // the only thing separating them, so these two cases hold the listing fixed
  // and vary that alone.
  it('says the read is in flight rather than claiming the folder has none', () => {
    const el = render({ listing: listing(), loading: true });

    expect(el.textContent).toContain('Loading…');
    expect(el.textContent).not.toContain('No servers');
  });
});

describe('McpSection — servers that need signing in', () => {
  /** The disclosure that folds them away. */
  function group(el: Element): HTMLButtonElement | null {
    return el.querySelector<HTMLButtonElement>('[aria-expanded]');
  }

  it('folds them away, and still says how many there are', () => {
    // The whole point of the group: a folder with several signed-out servers
    // buried the ones actually running. Folded, the count is the standing
    // statement that they exist — so the number must be on screen while the
    // rows are not.
    const el = render({
      listing: listing(
        { name: 'working' },
        { name: 'linear', status: 'needs_auth' },
        { name: 'notion', status: 'needs_auth' },
      ),
      loading: false,
    });

    expect(group(el)?.getAttribute('aria-expanded')).toBe('false');
    expect(group(el)?.textContent).toContain('2');
    // Present in the count, absent from the DOM until asked for.
    expect(el.textContent).toContain('working');
    expect(el.textContent).not.toContain('linear');
  });

  it('still shows the group, at zero, when every server is signed in', () => {
    // Reported as "I don't see the unauthorized MCP section" — on a folder
    // where the CLI reported no signed-out server at all. Hidden at zero, the
    // section's absence says nothing about WHY it is absent, so "none here"
    // and "this build has no such section" look identical and the only way to
    // tell them apart is to read the source.
    const el = render({
      listing: listing({ name: 'working' }, { name: 'also-working' }),
      loading: false,
    });

    const zero = [...el.querySelectorAll('button')].find((b) =>
      b.textContent?.includes('Needs sign-in'),
    );
    expect(zero).toBeDefined();
    expect(zero!.textContent).toContain('0');
    // Inert, not merely empty: a disclosure that opens onto nothing is a
    // worse lie than no disclosure. It also claims no expanded state, so
    // nothing announces a collapsed region that does not exist.
    expect(zero!.disabled).toBe(true);
    expect(zero!.getAttribute('aria-expanded')).toBeNull();
  });

  it('reveals them when the group is opened', () => {
    const el = render({
      listing: listing({ name: 'linear', status: 'needs_auth' }),
      loading: false,
    });

    act(() => {
      group(el)!.click();
    });

    expect(group(el)?.getAttribute('aria-expanded')).toBe('true');
    expect(el.querySelector('li')?.textContent).toContain('linear');
    // The row carries no status word of its own: the group heading above it and
    // the button beside it already say "sign in", and a third copy is what this
    // redesign exists to remove.
    expect(el.querySelector('li')?.textContent).not.toContain('sign-in');
  });

  it('never folds a server that is merely broken', () => {
    // A failure is not a sign-in, and hiding one behind a disclosure would put
    // the reason a user needs a level further from them than it is today.
    const el = render({
      listing: listing({
        name: 'broken',
        status: 'failed',
        detail: 'ENOENT',
      }),
      loading: false,
    });

    expect(group(el)).toBeNull();
    expect(el.textContent).toContain('broken');
  });

  it('asks its owner to sign in, naming the server and nothing else', () => {
    const onSignIn = vi.fn();
    const el = render({
      listing: listing({ name: 'linear', status: 'needs_auth' }),
      loading: false,
      onSignIn,
    });
    act(() => {
      group(el)!.click();
    });

    const button = [...el.querySelectorAll('button')].find((b) =>
      b.textContent?.includes('Sign in'),
    );
    act(() => {
      button!.click();
    });

    // A NAME, not an invocation: which agent and which folder belong to the
    // caller, and resolving the command belongs to the daemon.
    expect(onSignIn).toHaveBeenCalledWith('linear');
  });

  it('offers no sign-in on a surface with no write path', () => {
    // The graph inspector's case — the same rule the toggle follows.
    const el = render({
      listing: listing({ name: 'linear', status: 'needs_auth' }),
      loading: false,
    });
    act(() => {
      group(el)!.click();
    });

    expect(
      [...el.querySelectorAll('button')].some((b) =>
        b.textContent?.includes('Sign in'),
      ),
    ).toBe(false);
  });

  it('states the daemon’s reason instead of a button that would do nothing', () => {
    // A CLI with no `mcp login` still lists the row — the server is real and
    // its state is true — but pressing a button there would open a terminal
    // running a subcommand the binary does not have.
    const onSignIn = vi.fn();
    const el = render({
      listing: listing({
        name: 'linear',
        status: 'needs_auth',
        signInUnavailableReason: 'cursor-agent cannot sign in from here',
      }),
      loading: false,
      onSignIn,
    });
    act(() => {
      group(el)!.click();
    });

    expect(
      [...el.querySelectorAll('button')].some((b) =>
        b.textContent?.includes('Sign in'),
      ),
    ).toBe(false);
    expect(
      el.querySelector('[title="cursor-agent cannot sign in from here"]'),
    ).not.toBeNull();
  });
});
