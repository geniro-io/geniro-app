function server(
  overrides: Partial<AgentMcpServer> & Pick<AgentMcpServer, 'name' | 'status'>,
): AgentMcpServer {
  return {
    target: null,
    transport: 'stdio',
    detail: null,
    scope: 'workspace',
    shadowsUser: false,
    disabled: false,
    toggleUnavailableReason: null,
    signInUnavailableReason: null,
    approveUnavailableReason: null,
    ...overrides,
  };
}

