import { Lock, Plug } from 'lucide-react';

import type {
  AgentMcpListingDto as AgentMcpListing,
  AgentMcpServer,
} from '../autogenerated';
import { Badge } from './ui/badge';
import { Switch } from './ui/switch';
import { cn } from './ui/utils';

/**
 * How each reported health reads. `unknown` is what a CLI whose wording the
 * parser did not recognise degrades to — the server is still real, so it is
 * listed with its health unstated rather than dropped or called broken.
 */
type McpStatusTone = 'success' | 'destructive' | 'muted' | 'outline';

const MCP_STATUS_TONE: Record<AgentMcpServer['status'], McpStatusTone> = {
  connected: 'success',
  failed: 'destructive',
  pending: 'muted',
  unknown: 'outline',
};

/**
 * One MCP server listing, rendered as rows.
 *
 * Shared by the chat Agents panel (per CLI, per folder, with the toggle) and
 * the graph builder's node inspector (per node's plugin directory, read-only)
 * — the two surfaces show the same rows and must not drift, so this lives
 * here rather than inside either one.
 *
 * An agent whose CLI cannot be asked at all gets a sentence saying so rather
 * than an empty list — "no servers here" and "this CLI cannot tell us" are
 * different facts, and only one of them is about the user's configuration.
 */
export function McpSection({
  listing,
  loading,
  hint,
  onSetEnabled,
}: {
  listing: AgentMcpListing | undefined;
  loading: boolean;
  /** What this particular listing covers, when it is not simply "a folder". */
  hint?: string;
  /** Absent when the surface offers no write path — the inspector's case. */
  onSetEnabled?: (server: string, enabled: boolean) => void;
}): React.JSX.Element {
  const servers = listing?.servers;
  return (
    <div className="flex flex-col gap-1 border-t border-border px-2.5 py-1.5">
      <span className="flex items-center gap-1.5 text-xs text-muted-foreground">
        <Plug aria-hidden="true" className="size-3 shrink-0" />
        <span className="font-medium">MCP</span>
        {servers && servers.length > 0 ? <span>· {servers.length}</span> : null}
      </span>
      {hint ? (
        <span className="text-xs text-muted-foreground">{hint}</span>
      ) : null}
      {listing && listing.unavailableReason !== null ? (
        // The adapter's own sentence, shown verbatim. The panel never composes
        // this, and never asks which CLI it is looking at.
        <span className="text-xs text-muted-foreground">
          {listing.unavailableReason}
        </span>
      ) : servers === undefined ? (
        // Nothing has answered for this agent — which is NOT the same as it
        // having no servers. A run can carry no folder at all (`Run.cwd` is
        // nullable), and there is nothing to ask about then.
        <span className="text-xs text-muted-foreground">
          {loading ? 'Loading…' : 'Not checked'}
        </span>
      ) : servers.length === 0 ? (
        <span className="text-xs text-muted-foreground">No servers</span>
      ) : (
        <ul className="m-0 flex list-none flex-col gap-0.5 p-0">
          {servers.map((server) => (
            <li
              key={server.name}
              className="flex items-center gap-1.5 text-xs"
              // The failure reason is the only actionable part of a failure,
              // and it is far too long for the row.
              title={server.detail ?? server.target}>
              <span
                className={cn(
                  'min-w-0 flex-1 truncate',
                  server.disabled && 'text-muted-foreground line-through',
                )}>
                {server.name}
              </span>
              {/* Defaulted, not indexed blindly: the wire enum is gated by the
                  response schema today, but a widened status must degrade to a
                  neutral badge rather than crash the panel. */}
              <Badge variant={MCP_STATUS_TONE[server.status] ?? 'outline'}>
                {server.status}
              </Badge>
              {server.toggleUnavailableReason !== null ? (
                // No control at all, and the daemon's own sentence saying why.
                // A switch here would move and change nothing: the CLI has no
                // key that disables this server, or the user disabled it in
                // their own config, which geniro cannot undo.
                <span
                  aria-label={server.toggleUnavailableReason}
                  className="shrink-0 text-muted-foreground"
                  role="img"
                  title={server.toggleUnavailableReason}>
                  <Lock aria-hidden="true" className="size-3" />
                </span>
              ) : onSetEnabled ? (
                <Switch
                  aria-label={`Load ${server.name}`}
                  checked={!server.disabled}
                  className="h-4 w-7 shrink-0"
                  disabled={loading}
                  onCheckedChange={(next) => onSetEnabled(server.name, next)}
                />
              ) : null}
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
