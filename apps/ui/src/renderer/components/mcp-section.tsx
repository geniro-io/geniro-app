import {
  ChevronRight,
  Loader2,
  Lock,
  LogIn,
  Plug,
  RefreshCw,
  ShieldCheck,
} from 'lucide-react';
import { Fragment, useState } from 'react';

import type {
  AgentMcpListingDto as AgentMcpListing,
  AgentMcpServer,
} from '../autogenerated';
import { StatusDot, type StatusTone } from './status-dot';
import { Button } from './ui/button';
import { Switch } from './ui/switch';
import { cn } from './ui/utils';

/**
 * How each reported health reads: a tone for the dot, and the word beside it.
 *
 * A `null` label is deliberate and only `connected` has one. It is the common
 * case — a healthy folder is ten rows of it — and repeating "connected" ten
 * times is what made the list read as a wall of badges rather than as a list of
 * servers. The dot carries it, and every row that is NOT simply working keeps
 * its word, so the ones worth reading are the ones that say something.
 *
 * `unknown` is what a CLI whose wording the parser did not recognise degrades
 * to: the server is real, so it is listed with its health unstated rather than
 * dropped or called broken.
 */
const MCP_STATUS: Record<
  AgentMcpServer['status'],
  { tone: StatusTone; label: string | null }
> = {
  connected: { tone: 'ok', label: null },
  failed: { tone: 'bad', label: 'failed' },
  // A warning, never a failure: nothing is broken and one command fixes it.
  //
  // Label-less for the second reason `connected` is: these rows only ever
  // render inside the group headed "Needs sign-in", beside a button reading
  // "Sign in". A third copy of the same three words on the row itself is what
  // the redesign is meant to remove, not add.
  needs_auth: { tone: 'warn', label: null },
  // Label-less for the reason `needs_auth` is, and it is the reported defect:
  // `pending approval` was two words on a row whose switch already read ON,
  // with nothing saying what was pending, who approves, or how — the question
  // asked verbatim was "what is this and why is it written there". The row now
  // sits under a "Needs approval" heading that states it, above a caption that
  // explains it, beside a button that does it.
  pending: { tone: 'warn', label: null },
  // A MOMENT, not a state: the CLI was still dialling this server when it
  // answered, and the next read settles it either way. Worth its own word
  // because without one it arrived as `unknown`, which says the opposite —
  // that the CLI's wording is something this app could not read.
  loading: { tone: 'unknown', label: 'connecting…' },
  // Switched off in the CLI's own config — a stated choice, not a problem.
  disabled: { tone: 'unknown', label: 'off' },
  unknown: { tone: 'unknown', label: 'unknown' },
};

/** The neutral reading for a status the wire widened past what this knows. */
const UNKNOWN_STATUS = { tone: 'unknown' as StatusTone, label: 'unknown' };

/**
 * How each scope reads on a row, and `unknown` reads as nothing.
 *
 * The words are the CLI's own — cursor's picker says User and Workspace — so a
 * reader comparing the two panels is matching the same vocabulary rather than
 * translating. `unknown` is silence rather than a word, because it is a fact
 * about what geniro could read and not about the server; a CLI whose scopes are
 * not placed yet would otherwise carry a meaningless badge on every row.
 */
const MCP_SCOPE: Record<AgentMcpServer['scope'], string | null> = {
  user: 'user',
  workspace: 'workspace',
  unknown: null,
};

/**
 * Beyond this many characters a failure reason is folded until asked for.
 *
 * A JSON-RPC failure body is routinely hundreds of characters of protocol
 * envelope wrapping one useful sentence, and several of them at once turned
 * the panel into a wall. Past this length the reason is clamped to two lines
 * and the rest is one press away.
 *
 * A character count is a PROXY for the question actually being asked ("does
 * this overflow two lines?"), which only layout can answer — so a 119-char
 * unbroken URL can still wrap past two lines and render unfolded. Accepted
 * deliberately: measuring would cost a ref and a layout read on every row of
 * every listing, and the failure mode of the proxy is a slightly tall row,
 * not a wrong or hidden reason.
 */
const DETAIL_FOLD_AT = 120;

/**
 * A failure reason: wrapped, folded when long, expandable.
 *
 * Serves both the per-server `detail` and the whole listing's
 * `unavailableReason`, because they are the same kind of text with the same
 * failure mode.
 *
 * The wrapping is not cosmetic. These strings are frequently one unbroken
 * token — a URL, or a serialized error object with no spaces in it — and an
 * unwrapped one does not widen the panel, it overflows it: the text ran out
 * past the panel's edge and was simply unreadable, which is the reported
 * "a lot of errors for mcp" symptom as much as the count was.
 */
function FoldedReason({
  detail,
  className,
}: {
  detail: string;
  className?: string;
}): React.JSX.Element {
  const [expanded, setExpanded] = useState(false);
  const foldable = detail.length > DETAIL_FOLD_AT;
  return (
    <span className="flex min-w-0 flex-col items-start gap-0.5 text-xs">
      <span
        className={cn(
          'min-w-0 max-w-full break-words',
          className,
          foldable && !expanded && 'line-clamp-2',
        )}>
        {detail}
      </span>
      {foldable ? (
        // Smaller than the reason it folds, and deliberately so. This is a
        // disclosure control, not a peer of the failure text — at the row's
        // own size it read as the loudest thing in a panel whose actual
        // content is the server list, and it drew the eye ahead of the error
        // it belongs to. `text-[11px]` matches the other in-row controls (the
        // Sign in button), and dropping the underline to a hover affordance
        // leaves the row quiet until pointed at.
        <button
          type="button"
          className="shrink-0 text-[11px] leading-4 text-muted-foreground underline-offset-2 hover:text-foreground hover:underline"
          onClick={() => setExpanded((value) => !value)}>
          {expanded ? 'Show less' : 'Show more'}
        </button>
      ) : null}
    </span>
  );
}

/**
 * One server. A row, not a badge shelf: a dot for health, the name, the word
 * only when it is worth reading, then whatever can be done about it.
 *
 * The hover fill is the whole reason the row has padding of its own — it is
 * what makes a list of ten feel like something you point at rather than a
 * paragraph of statuses.
 */
function McpRow({
  server,
  loading,
  signingIn,
  onSetEnabled,
  onSignIn,
}: {
  server: AgentMcpServer;
  loading: boolean;
  /** True while this row's sign-in has been asked for and not yet answered. */
  signingIn: boolean;
  onSetEnabled?: (server: string, enabled: boolean) => void;
  onSignIn?: (server: string) => void;
}): React.JSX.Element {
  const { tone, label } = MCP_STATUS[server.status] ?? UNKNOWN_STATUS;
  const scopeLabel = MCP_SCOPE[server.scope] ?? null;
  return (
    <li className="flex flex-col gap-0.5 rounded-md px-1.5 py-1 text-xs transition-colors hover:bg-accent/40">
      <span
        className="flex items-center gap-2"
        // The COMMAND LINE only. It is context, not an instruction — wanting it
        // is a deliberate act, and a tooltip is a fine place for something
        // nobody is required to read. The failure reason used to live here too
        // and does not any more: see below.
        //
        // `||`, not `??`: absent is not only null here. claude's parser yields
        // `target: ''` for a row whose command column is blank, and `??` would
        // pass that straight through as `title=""`.
        title={server.target || undefined}>
        <StatusDot tone={tone} className="shrink-0" />
        <span
          className={cn(
            'min-w-0 flex-1 truncate',
            server.disabled && 'text-muted-foreground line-through',
          )}>
          {server.name}
        </span>
        {/* WHERE the server was defined, in the CLI's own vocabulary.
            `unknown` draws nothing: a row whose origin could not be read is
            the ordinary case for a CLI whose scopes geniro cannot place yet,
            and a badge reading "unknown" beside every one of them would be
            noise about geniro rather than a fact about the server. */}
        {scopeLabel ? (
          <span className="shrink-0 text-[11px] text-muted-foreground/80">
            {scopeLabel}
          </span>
        ) : null}
        {label ? (
          <span className="shrink-0 text-muted-foreground">{label}</span>
        ) : null}
        {/* Offered only where the row can act on it AND the CLI has the
            command. A `needs_auth` row on a CLI with no sign-in gets the
            daemon's own sentence instead of a button that would do nothing —
            the same shape the toggle uses one line down, for the same reason. */}
        {onSignIn === undefined ||
        server.status !==
          'needs_auth' ? null : server.signInUnavailableReason !== null ? (
          <span
            className="shrink-0 text-muted-foreground"
            title={server.signInUnavailableReason}>
            no sign-in
          </span>
        ) : (
          // The press is answered HERE, not when the daemon replies. That
          // request is held open until the CLI prints its URL — measured at
          // 4001ms in the running app — and for all of it a browser tab opens
          // behind the window while this button sits unchanged, which is the
          // reported "no loader, nothing". The spinner and the word are the
          // whole of the answer; `disabled` is the other half, since a second
          // press starts a second browser challenge that invalidates the first.
          <Button
            type="button"
            variant="outline"
            size="sm"
            className="h-5 shrink-0 gap-1 px-1.5 text-[11px]"
            title={`Sign in to ${server.name}`}
            disabled={signingIn}
            onClick={() => onSignIn(server.name)}>
            {signingIn ? (
              <Loader2
                aria-hidden="true"
                className="size-3 shrink-0 animate-spin"
              />
            ) : (
              <LogIn aria-hidden="true" className="size-3 shrink-0" />
            )}
            {signingIn ? 'Signing in…' : 'Sign in'}
          </Button>
        )}
        {/* Approving is the SAME write as switching on — `cursor-agent mcp
            enable <name>` answers "Enabled and approved" — so it rides
            `onSetEnabled` rather than a prop of its own. That is deliberate:
            a second callback is one a surface with a write path could forget
            to wire, and the button would then be missing on exactly the panel
            that can act. What it does NOT ride is the toggle's own
            availability: `approveUnavailableReason` is answered per row by the
            adapter, because claude's switch works and approves nothing (its
            `/mcp` screen does), and enabling an unapproved claude row would
            move a control and change nothing. */}
        {onSetEnabled === undefined ||
        server.status !== 'pending' ? null : server.approveUnavailableReason !==
          null ? (
          <span
            className="shrink-0 text-muted-foreground"
            title={server.approveUnavailableReason}>
            no approve
          </span>
        ) : (
          <Button
            type="button"
            variant="outline"
            size="sm"
            className="h-5 shrink-0 gap-1 px-1.5 text-[11px]"
            title={`Approve ${server.name} for this folder so ${server.name} is loaded`}
            disabled={loading}
            onClick={() => onSetEnabled(server.name, true)}>
            <ShieldCheck aria-hidden="true" className="size-3 shrink-0" />
            Approve
          </Button>
        )}
        {/* Both arms belong to a surface that HAS a write path. A read-only one
            (the graph inspector) shows neither switch nor lock: its rows come
            from a listing taken in a folder geniro owns, so every one of them
            carries a folder-scoped reason — and explaining why a control is
            unavailable, where no control was ever going to appear, only raises
            a question about a folder the workflow does not yet have. */}
        {onSetEnabled === undefined ? null : server.toggleUnavailableReason !==
          null ? (
          // No control, and the daemon's own sentence saying why. A switch here
          // would move and change nothing: the CLI has no key that disables
          // this server, or the user disabled it in their own config, which
          // geniro cannot undo.
          <span
            aria-label={server.toggleUnavailableReason}
            className="shrink-0 text-muted-foreground"
            role="img"
            title={server.toggleUnavailableReason}>
            <Lock aria-hidden="true" className="size-3" />
          </span>
        ) : (
          <Switch
            aria-label={`Load ${server.name}`}
            checked={!server.disabled}
            size="sm"
            disabled={loading}
            onCheckedChange={(next) => onSetEnabled(server.name, next)}
          />
        )}
      </span>
      {/* On its own line, not in the row's tooltip.
          The reason is the only ACTIONABLE part of a failure — it is what says
          whether to fix a path, start a service, or sign in — and a tooltip on
          a non-focusable `li` is reachable by pointer alone: a keyboard user
          could see the dot go red and never reach the sentence explaining it.
          Rendered only for a failure, so a healthy list stays one line per
          server. */}
      {server.status === 'failed' && server.detail ? (
        <FoldedReason className="text-destructive" detail={server.detail} />
      ) : null}
      {/* The one line that explains a contradiction rather than reporting a
          state, which is why it is here and not a badge. A CLI merges its
          scopes BY NAME, so a folder that redefines `codegraph` gets ONE row —
          and if the folder's copy is unapproved or broken, the panel says a
          server is not working that the reader knows perfectly well IS working
          everywhere else. Nothing on the row could have told them the two are
          different servers. Muted rather than a warning: neither definition is
          wrong, and only one of them can win. */}
      {server.shadowsUser ? (
        <span className="text-xs text-muted-foreground">
          This folder defines its own {server.name}, so your user-level one is
          not what runs here.
        </span>
      ) : null}
    </li>
  );
}

/**
 * A disclosure for one group of rows, collapsed by default.
 *
 * Local to this file rather than reaching for `CollapsibleCard`: that one is a
 * Card with its own border and 16px padding, built for onboarding and settings
 * blocks, and nesting it inside a panel that is already a bounded card drew a
 * second frame around four rows. This is the same disclosure wiring at list
 * weight. It becomes a shared component the moment a second surface wants it.
 */
function McpGroup({
  title,
  count,
  note,
  forceOpen = false,
  children,
}: {
  title: string;
  count: number;
  /**
   * Hold the group open regardless of the user's fold — for content inside it
   * that must not be hideable, which today is a sign-in in flight.
   *
   * It does not WRITE the fold: when it goes false the group returns to
   * whatever the user last chose, rather than to whatever this forced.
   */
  forceOpen?: boolean;
  /**
   * One sentence saying what this group IS, shown above its rows when open.
   *
   * For a group whose heading is self-explanatory ("Needs sign-in", beside
   * buttons reading "Sign in") there is nothing to add and none is passed.
   * "Needs approval" is the opposite case — the heading names a state nobody
   * outside the CLI's own documentation has met, which is what got it
   * reported — so the group carries the explanation rather than repeating it
   * on every row.
   */
  note?: string;
  /** Absent when {@link count} is 0 — there is nothing to disclose. */
  children?: React.ReactNode;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  // An EMPTY group is still a statement, and that is why it renders. Hidden at
  // zero, "no servers need signing in here" and "this build has no such
  // section" look identical — which is exactly how the section was reported
  // missing on a folder where every server happened to be signed in. Shown
  // with its count, the answer is on screen either way. It is inert rather
  // than merely empty: a disclosure that opens onto nothing is a worse lie
  // than no disclosure at all.
  const disclosable = count > 0;
  const shown = (open || forceOpen) && disclosable;
  return (
    <div className="flex flex-col">
      <button
        type="button"
        aria-expanded={disclosable ? shown : undefined}
        disabled={!disclosable}
        onClick={() => setOpen((value) => !value)}
        className={cn(
          'flex items-center gap-1 rounded-md px-1.5 py-1 text-xs text-muted-foreground transition-colors outline-none focus-visible:ring-2 focus-visible:ring-ring/50',
          disclosable && 'hover:bg-accent/40 hover:text-foreground',
          // Not `disabled:opacity-50`: at 50% this text drops below AA on the
          // card, and the row is the one thing the reader came to check.
          !disclosable && 'cursor-default opacity-70',
        )}>
        <ChevronRight
          aria-hidden="true"
          className={cn(
            'size-3 shrink-0 transition-transform',
            shown && 'rotate-90',
            !disclosable && 'invisible',
          )}
        />
        <span className="font-medium">{title}</span>
        <span>· {count}</span>
      </button>
      {shown ? (
        <>
          {note ? (
            <span className="px-1.5 pb-1 text-xs text-muted-foreground">
              {note}
            </span>
          ) : null}
          <ul className="m-0 flex list-none flex-col p-0">{children}</ul>
        </>
      ) : null}
    </div>
  );
}

/**
 * What the panel says while a read is running and it has NOTHING to show.
 *
 * A bare "Loading…" is what got the wait reported: reading this list is not a
 * fetch, it is the CLI STARTING every server the folder defines to see which
 * answer, so it is measured in seconds and one hanging server takes it to
 * tens of them. That is worth saying once, in the one state where the user is
 * looking at an empty panel with no idea what is being waited on. A folder
 * already read keeps its rows through the re-read and never reaches this.
 */
const FIRST_READ_LABEL = 'Starting each server to see which answer…';

/**
 * One MCP server listing, rendered as rows.
 *
 * Shared by the chat Agents panel (per CLI, per folder, with the toggle) and
 * the graph builder's node inspector (per node's config directory, read-only)
 * — the two surfaces show the same rows and must not drift, so this lives
 * here rather than inside either one.
 *
 * An agent whose CLI cannot be asked at all gets a sentence saying so rather
 * than an empty list — "no servers here" and "this CLI cannot tell us" are
 * different facts, and only one of them is about the user's configuration.
 *
 * Servers that need signing in are listed, but BELOW and folded. They are the
 * ones a reader can do something about, which is exactly why they must not sit
 * among the working ones: unfolded, a folder with several of them buried the
 * servers that are actually running. Folded, the group's own count is the
 * standing statement of how many there are — INCLUDING none, which is why the
 * group renders at zero too. Hidden at zero it took a folder with no
 * signed-out server to make the whole feature look absent.
 *
 * Servers awaiting APPROVAL are the second such group, on the same rule and
 * for a reported defect: they used to sit among the working rows carrying the
 * words `pending approval` and a switch already in the ON position, which said
 * neither what was pending nor how to grant it. See the group's own note.
 */
export function McpSection({
  listing,
  loading,
  hint,
  onSetEnabled,
  onSignIn,
  signingIn = null,
  loginServer = null,
  loginPanel,
  onRefresh,
  className,
}: {
  listing: AgentMcpListing | undefined;
  loading: boolean;
  /** What this particular listing covers, when it is not simply "a folder". */
  hint?: string;
  /** Absent when the surface offers no write path — the inspector's case. */
  onSetEnabled?: (server: string, enabled: boolean) => void;
  /**
   * Open a terminal signed in to one server. Absent hides the action entirely,
   * on the same rule as `onSetEnabled`.
   *
   * It hands back a SERVER NAME and nothing else: the caller owns which agent
   * and which folder, and resolving the invocation is the daemon's. Nothing
   * here knows that the answer is a terminal at all.
   */
  onSignIn?: (server: string) => void;
  /**
   * The server whose sign-in has been asked for and not yet answered, or null.
   *
   * Owned by the caller because the CONTROLLER is: one sign-in runs at a time
   * across the whole screen, so a flag kept per section would let two panels
   * each believe they own it.
   */
  signingIn?: string | null;
  /**
   * Which server {@link loginPanel} belongs to — null when no sign-in is in
   * flight.
   *
   * Threaded as a NAME rather than the panel carrying its own: the panel is
   * built by the screen that owns the sign-in controller, and matching it to a
   * row is this component's business, since only this one knows what the rows
   * are.
   */
  loginServer?: string | null;
  /**
   * A sign-in in flight, rendered directly under the row it was started from.
   *
   * See the placement itself for what it replaced. It is a `ReactNode` rather
   * than props for a login session because the controller, its four states and
   * the code field belong to `CliLoginProgress` and to the screen holding it —
   * this section only decides WHERE it goes.
   */
  loginPanel?: React.ReactNode;
  /**
   * Re-dial this listing's servers. Rendered in the section's own header.
   *
   * Every surface showing ONE listing at a time — the builder's inspector, and
   * now the Agents panel, whose listings moved into per-agent popovers. While
   * they were stacked bands of one panel the control lived in the panel header
   * instead, because the intent there was "re-check everything" and a
   * per-section button was the same action offered several times over.
   */
  onRefresh?: () => void;
  /**
   * Overrides the CARD chrome (`border-t`, the card's own horizontal padding),
   * which belongs to the Agents panel where every section is one band of a
   * stacked card. The builder's inspector is a field stack with its own
   * rhythm, and inheriting a card's edges there reads as a stray rule across
   * the panel.
   */
  className?: string;
}): React.JSX.Element {
  const servers = listing?.servers;
  // Split, never filtered: every server the CLI reported is on screen, one
  // group or the other. The user asked to see all of them, including the ones
  // they could sign in to.
  const signedOut =
    servers?.filter((server) => server.status === 'needs_auth') ?? [];
  // The second group, and it exists for the same reason the first does: an
  // unapproved server is not broken and not working either — it is one press
  // from being loaded — and among the healthy rows it read as a badge nobody
  // could act on. Split rather than filtered, as above.
  const unapproved =
    servers?.filter((server) => server.status === 'pending') ?? [];
  const rest =
    servers?.filter(
      (server) => server.status !== 'needs_auth' && server.status !== 'pending',
    ) ?? [];
  // Whose sign-in {@link loginPanel} is about, matched against the rows so the
  // panel lands under the one the user pressed.
  const loginRow =
    loginPanel !== undefined && loginServer !== null ? loginServer : null;
  const row = (server: AgentMcpServer): React.JSX.Element => (
    // A Fragment rather than a wrapper element: these are `<li>` children of
    // the group's `<ul>`, and anything between the two would be invalid there.
    <Fragment key={server.name}>
      <McpRow
        server={server}
        loading={loading}
        signingIn={signingIn === server.name}
        onSetEnabled={onSetEnabled}
        onSignIn={onSignIn}
      />
      {loginRow === server.name ? (
        // REPORTED as "I have broken UI - i wanna this status line from down
        // to b under item where we actually clicked sign in". It used to be a
        // sibling of this whole section, pinned to the dialog's foot — so on a
        // listing of fifteen servers the answer to "what happened when I
        // pressed Sign in on ticktick" was a strip at the bottom of the panel
        // naming no server at all, with three signed-out rows above it that it
        // could equally have been about.
        <li data-slot="mcp-login-slot">{loginPanel}</li>
      ) : null}
    </Fragment>
  );
  return (
    <div
      className={cn(
        'flex flex-col gap-1 border-t border-border px-2.5 py-1.5',
        className,
      )}>
      <span className="flex items-center gap-1.5 text-xs text-muted-foreground">
        <Plug aria-hidden="true" className="size-3 shrink-0" />
        <span className="font-medium">MCP</span>
        {servers && servers.length > 0 ? <span>· {servers.length}</span> : null}
        {onRefresh ? (
          <Button
            type="button"
            variant="ghost"
            size="icon"
            className="ml-auto size-5 shrink-0"
            aria-label="Refresh MCP servers"
            // Named for what it DOES to a broken server, because that is what
            // the user comes here wanting: the read re-dials each server, so
            // this is the reconnect. The CLI has no reconnect subcommand of
            // its own (`claude mcp` offers add/remove/login/logout/get/list,
            // probe-verified), so re-dialling is the whole mechanism there is.
            title="Reconnect — re-dial each server and re-check its health"
            disabled={loading}
            onClick={onRefresh}>
            <RefreshCw
              className={cn('size-3 shrink-0', loading && 'animate-spin')}
            />
          </Button>
        ) : null}
      </span>
      {hint ? (
        <span className="text-xs text-muted-foreground">{hint}</span>
      ) : null}
      {listing && listing.unavailableReason !== null ? (
        // The adapter's own sentence, shown verbatim. This section never
        // composes this, and never asks which CLI it is looking at.
        //
        // Folded on the same rule as a per-server failure, because it is the
        // SAME kind of text and routinely the longest of it: a transport
        // failure carries the daemon's route and query string, so this is the
        // one line that reliably ran off the panel's edge unreadably.
        <FoldedReason
          className="text-muted-foreground"
          detail={listing.unavailableReason}
        />
      ) : servers === undefined ? (
        // Nothing has answered for this agent — which is NOT the same as it
        // having no servers. A run can carry no folder at all (`Run.cwd` is
        // nullable), and there is nothing to ask about then.
        <span className="text-xs text-muted-foreground">
          {loading ? FIRST_READ_LABEL : 'Not checked'}
        </span>
      ) : servers.length === 0 ? (
        // Empty rows are the daemon's placeholder for a cold read still
        // dialling (`pending: true`), not a settled "this folder has none" —
        // the same distinction the `servers === undefined` branch above
        // already draws, just reached from the other side of it.
        <span className="text-xs text-muted-foreground">
          {loading ? FIRST_READ_LABEL : 'No servers'}
        </span>
      ) : (
        <>
          {rest.length > 0 ? (
            <ul className="m-0 flex list-none flex-col p-0">{rest.map(row)}</ul>
          ) : null}
          {/* Hidden at zero, which is the ONE place this panel departs from
              the empty-group rule its neighbour states — so it is worth saying
              why rather than leaving the asymmetry to read as an oversight.
              The sign-in group renders at zero because a user LOOKS for it:
              signed-out servers are the majority of a real listing, and the
              section was reported missing on the one folder that happened to
              have none. Nobody looks for an approval section, because only a
              project-scoped server can ever need one — most folders have no
              `.cursor/mcp.json` at all — so a permanent "Needs approval · 0"
              would be a standing line about a state that will never occur
              there, in a panel already criticised for saying too much. */}
          {unapproved.length > 0 ? (
            <McpGroup
              title="Needs approval"
              count={unapproved.length}
              // Says the two things the badge did not: what is waiting, and
              // that it is a choice rather than a fault. Deliberately about
              // the STATUS and not about one CLI — every CLI that reports this
              // reports the same fact, and a per-CLI sentence would be an
              // adapter field carrying prose no adapter has anything unique to
              // say in.
              note="These are configured for this folder but the agent will not load them until you approve them here — nothing is broken.">
              {unapproved.map(row)}
            </McpGroup>
          ) : null}
          {/* Rendered UNCONDITIONALLY once a listing exists, empty included —
              see {@link McpGroup}. The condition here is that we have an
              answer at all, not that the answer is non-zero. */}
          <McpGroup
            title="Needs sign-in"
            count={signedOut.length}
            // A group the user collapses while a sign-in is running would take
            // the progress panel — and the pasted-code field the CLI is
            // waiting on — off screen with it, which is a worse dead end than
            // the misplaced strip this fix replaced. The fold is theirs again
            // the moment the sign-in settles.
            forceOpen={
              loginRow !== null &&
              signedOut.some((server) => server.name === loginRow)
            }>
            {signedOut.map(row)}
          </McpGroup>
        </>
      )}
      {/* What the CLI loads only in its OWN interactive session, in its own
          words. Shown BELOW the rows and after every other branch — including
          "No servers" and a refusal — because it is the answer to a question
          the list itself provokes: the user compares this panel against their
          terminal's `/mcp`, sees fewer entries here, and has no way to tell a
          complete list from a broken one. The servers it names are genuinely
          not loaded in a headless turn, so listing them as rows would promise
          the agent tools it will not have.

          Which CLI has such a gap, and what to say about it, is the daemon's
          answer (`AdapterConfig.mcp.interactiveOnlyNote`) — this section never
          learns an agent's name. */}
      {listing?.interactiveOnlyNote ? (
        <p className="m-0 text-xs text-muted-foreground">
          {listing.interactiveOnlyNote}
        </p>
      ) : null}
    </div>
  );
}
