import { Lock, Plug, RefreshCw } from 'lucide-react';

import type {
  AgentMcpListingDto as AgentMcpListing,
  AgentMcpServer,
} from '../autogenerated';
import { Badge } from './ui/badge';
import { Button } from './ui/button';
import { Switch } from './ui/switch';
import { cn } from './ui/utils';

/**
 * How each reported health reads. `unknown` is what a CLI whose wording the
 * parser did not recognise degrades to — the server is still real, so it is
 * listed with its health unstated rather than dropped or called broken.
 */
type McpStatusTone = 'success' | 'destructive' | 'muted' | 'outline';

const MCP_STATUS_TONE: Record<AgentMcpServer['status'], McpStatusTone> = {
  connected: 'success',
  failed: 'destructive',
  pending: 'muted',
  // Switched off in the CLI's own config — a stated choice, not a problem, so
  // it reads like `pending` rather than like a failure. The row is also struck
  // through, because `disabled` on the wire follows this status.
  disabled: 'muted',
  unknown: 'outline',
};

/**
 * One MCP server listing, rendered as rows.
 *
 * Shared by the chat Agents panel (per CLI, per folder, with the toggle) and
 * the graph builder's node inspector (per node's plugin directory, read-only)
 * — the two surfaces show the same rows and must not drift, so this lives
 * here rather than inside either one.
 *
 * An agent whose CLI cannot be asked at all gets a sentence saying so rather
 * than an empty list — "no servers here" and "this CLI cannot tell us" are
 * different facts, and only one of them is about the user's configuration.
 */
export function McpSection({
  listing,
  loading,
  hint,
  onSetEnabled,
  onRefresh,
  className,
}: {
  listing: AgentMcpListing | undefined;
  loading: boolean;
  /** What this particular listing covers, when it is not simply "a folder". */
  hint?: string;
  /** Absent when the surface offers no write path — the inspector's case. */
  onSetEnabled?: (server: string, enabled: boolean) => void;
  /**
   * Re-dial this listing's servers. Rendered in the section's own header.
   *
   * For a surface showing ONE listing — the builder's inspector. The Agents
   * panel shows one per CLI and puts its control in the panel header instead,
   * because there the intent is "re-check everything" and a per-section button
   * would be the same action offered several times.
   */
  onRefresh?: () => void;
  /**
   * Overrides the CARD chrome (`border-t`, the card's own horizontal padding),
   * which belongs to the Agents panel where every section is one band of a
   * stacked card. The builder's inspector is a field stack with its own
   * rhythm, and inheriting a card's edges there reads as a stray rule across
   * the panel.
   */
  className?: string;
}): React.JSX.Element {
  const servers = listing?.servers;
  return (
    <div
      className={cn(
        'flex flex-col gap-1 border-t border-border px-2.5 py-1.5',
        className,
      )}>
      <span className="flex items-center gap-1.5 text-xs text-muted-foreground">
        <Plug aria-hidden="true" className="size-3 shrink-0" />
        <span className="font-medium">MCP</span>
        {servers && servers.length > 0 ? <span>· {servers.length}</span> : null}
        {onRefresh ? (
          <Button
            type="button"
            variant="ghost"
            size="icon"
            className="ml-auto size-5 shrink-0"
            aria-label="Refresh MCP servers"
            title="Re-check MCP server health"
            disabled={loading}
            onClick={onRefresh}>
            <RefreshCw
              className={cn('size-3 shrink-0', loading && 'animate-spin')}
            />
          </Button>
        ) : null}
      </span>
      {hint ? (
        <span className="text-xs text-muted-foreground">{hint}</span>
      ) : null}
      {listing && listing.unavailableReason !== null ? (
        // The adapter's own sentence, shown verbatim. This section never composes
        // this, and never asks which CLI it is looking at.
        <span className="text-xs text-muted-foreground">
          {listing.unavailableReason}
        </span>
      ) : servers === undefined ? (
        // Nothing has answered for this agent — which is NOT the same as it
        // having no servers. A run can carry no folder at all (`Run.cwd` is
        // nullable), and there is nothing to ask about then.
        <span className="text-xs text-muted-foreground">
          {loading ? 'Loading…' : 'Not checked'}
        </span>
      ) : servers.length === 0 ? (
        <span className="text-xs text-muted-foreground">No servers</span>
      ) : (
        <ul className="m-0 flex list-none flex-col gap-0.5 p-0">
          {servers.map((server) => (
            <li key={server.name} className="flex flex-col gap-0.5 text-xs">
              <span
                className="flex items-center gap-1.5"
                // The COMMAND LINE only. It is context, not an instruction —
                // wanting it is a deliberate act, and a tooltip is a fine place
                // for something nobody is required to read. The failure reason
                // used to live here too and does not any more: see below.
                //
                // `||`, not `??`: absent is not only null here. claude's parser
                // yields `target: ''` for a row whose command column is blank,
                // and `??` would pass that straight through as `title=""`.
                title={server.target || undefined}>
                <span
                  className={cn(
                    'min-w-0 flex-1 truncate',
                    server.disabled && 'text-muted-foreground line-through',
                  )}>
                  {server.name}
                </span>
                {/* Defaulted, not indexed blindly: the wire enum is gated by the
                  response schema today, but a widened status must degrade to a
                  neutral badge rather than crash the surface. */}
                <Badge variant={MCP_STATUS_TONE[server.status] ?? 'outline'}>
                  {server.status}
                </Badge>
                {/* Both arms belong to a surface that HAS a write path. A
                  read-only one (the graph inspector) shows neither switch nor
                  lock: its rows come from a listing taken in a folder geniro
                  owns, so every one of them carries a folder-scoped reason —
                  and explaining why a control is unavailable, where no control
                  was ever going to appear, only raises a question about a
                  folder the workflow does not yet have. */}
                {onSetEnabled ===
                undefined ? null : server.toggleUnavailableReason !== null ? (
                  // No control, and the daemon's own sentence saying why. A
                  // switch here would move and change nothing: the CLI has no
                  // key that disables this server, or the user disabled it in
                  // their own config, which geniro cannot undo.
                  <span
                    aria-label={server.toggleUnavailableReason}
                    className="shrink-0 text-muted-foreground"
                    role="img"
                    title={server.toggleUnavailableReason}>
                    <Lock aria-hidden="true" className="size-3" />
                  </span>
                ) : (
                  <Switch
                    aria-label={`Load ${server.name}`}
                    checked={!server.disabled}
                    className="h-4 w-7 shrink-0"
                    disabled={loading}
                    onCheckedChange={(next) => onSetEnabled(server.name, next)}
                  />
                )}
              </span>
              {/* On its own line, not in the row's tooltip.
                  The reason is the only ACTIONABLE part of a failure — it is
                  what says whether to fix a path, start a service, or sign in
                  — and a tooltip on a non-focusable `li` is reachable by
                  pointer alone: a keyboard user could see the badge go red and
                  never reach the sentence explaining it. Rendered only for a
                  failure, so a healthy list stays one line per server. */}
              {server.status === 'failed' && server.detail ? (
                <span className="text-destructive">{server.detail}</span>
              ) : null}
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
