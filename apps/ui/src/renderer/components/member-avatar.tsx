import { cva } from 'class-variance-authority';
import { User } from 'lucide-react';
import { useState } from 'react';

import type { MemberAvatar as AvatarLook } from '../autogenerated';
import { useAvatarImage } from './avatar-images';
import { cn } from './ui/utils';

export type { AvatarLook };

export const AVATAR_TONES = [
  'avatar-1',
  'avatar-2',
  'avatar-3',
  'avatar-4',
  'avatar-5',
  'avatar-6',
  'avatar-7',
  'avatar-8',
] as const;
export type AvatarTone = (typeof AVATAR_TONES)[number];

const TONE_CLASS: Record<AvatarTone, string> = {
  'avatar-1': 'bg-avatar-1',
  'avatar-2': 'bg-avatar-2',
  'avatar-3': 'bg-avatar-3',
  'avatar-4': 'bg-avatar-4',
  'avatar-5': 'bg-avatar-5',
  'avatar-6': 'bg-avatar-6',
  'avatar-7': 'bg-avatar-7',
  'avatar-8': 'bg-avatar-8',
};

export const AVATAR_SIZES = [20, 24, 40, 48, 64, 96] as const;
export type AvatarSize = (typeof AVATAR_SIZES)[number];

const avatarVariants = cva(
  'relative flex shrink-0 items-center justify-center overflow-hidden rounded-full leading-none font-semibold uppercase select-none',
  {
    variants: {
      size: {
        20: 'size-5 text-[9px]',
        24: 'size-6 text-[10px]',
        40: 'size-10 text-sm',
        48: 'size-12 text-base',
        64: 'size-16 text-xl',
        96: 'size-24 text-3xl',
      },
      look: {
        initials: 'text-primary-foreground',
        emoji: 'text-foreground',
        picture: 'bg-muted',
        user: 'bg-avatar-user text-primary-foreground',
      },
    },
  },
);

const emojiVariants = cva('normal-case', {
  variants: {
    size: {
      20: 'text-[11px]',
      24: 'text-sm',
      40: 'text-xl',
      48: 'text-2xl',
      64: 'text-3xl',
      96: 'text-5xl',
    },
  },
});

function hashKey(key: string): number {
  let hash = 0;
  for (let i = 0; i < key.length; i++) {
    hash = (hash * 31 + key.charCodeAt(i)) | 0;
  }
  return Math.abs(hash);
}

function isTone(value: string | undefined): value is AvatarTone {
  return (AVATAR_TONES as readonly string[]).includes(value ?? '');
}

/** The tone an avatar is drawn in: the member's own pick, else one hashed from `colorKey`. */
export function avatarToneOf(colorKey: string, look?: AvatarLook): AvatarTone {
  return isTone(look?.tone)
    ? look.tone
    : AVATAR_TONES[hashKey(colorKey) % AVATAR_TONES.length]!;
}

/** The background class for a tone — avatar pairs and pickers share it. */
export function toneClass(tone: AvatarTone): string {
  return TONE_CLASS[tone];
}

/**
 * Initials for a display name: the first letter of the first two words
 * ("Flaky (cursor)" → "FC"); one word keeps one letter ("Poet" → "P").
 */
export function initialsOf(name: string): string {
  const words = name
    .split(/[^\p{L}\p{N}]+/u)
    .filter((word) => word.length > 0)
    .slice(0, 2);
  if (words.length === 0) {
    return '?';
  }
  return words.map((word) => word[0]!.toUpperCase()).join('');
}

/** What an avatar shows, after its picture has loaded or failed. */
function shownKind(
  look: AvatarLook | undefined,
  pictureSrc: string | null,
): 'initials' | 'emoji' | 'picture' {
  if (look?.kind === 'picture') {
    return pictureSrc === null ? 'initials' : 'picture';
  }
  if (look?.kind === 'emoji' && look.value) {
    return 'emoji';
  }
  return 'initials';
}

/**
 * A team member's face, wherever it is drawn: their picture, their emoji on a
 * tone, or their initials on a tone. A picture that cannot be read falls back
 * to the initials, so a deleted file never leaves an empty circle. `solid` is
 * the user's own neutral avatar.
 */
export function MemberAvatar({
  name,
  avatar,
  colorKey,
  size = 24,
  solid = false,
  labelled = false,
  className,
}: {
  name: string;
  avatar?: AvatarLook | null;
  /** Drives the default tone (a member id); defaults to `name`. */
  colorKey?: string;
  size?: AvatarSize;
  solid?: boolean;
  /** Announce the name — only where no visible name stands beside it. */
  labelled?: boolean;
  className?: string;
}): React.JSX.Element {
  const look = avatar ?? undefined;
  const picture = useAvatarImage(
    look?.kind === 'picture' && look.value ? look.value : null,
  );
  const [brokenSrc, setBrokenSrc] = useState<string | null>(null);
  const pictureSrc =
    picture.status === 'ready' && picture.src !== brokenSrc
      ? picture.src
      : null;
  const kind = solid ? 'user' : shownKind(look, pictureSrc);
  const tone = avatarToneOf(colorKey ?? name, look);
  const initials =
    look?.kind === 'initials' && look.value?.trim()
      ? look.value.trim().slice(0, 3).toUpperCase()
      : initialsOf(name);
  return (
    <span
      data-slot="avatar"
      data-avatar-kind={kind}
      role={labelled ? 'img' : undefined}
      aria-label={labelled ? name : undefined}
      aria-hidden={labelled ? undefined : true}
      title={name}
      className={cn(
        avatarVariants({ size, look: kind }),
        (kind === 'initials' || kind === 'emoji') && toneClass(tone),
        className,
      )}>
      {kind === 'user' ? (
        <User aria-hidden="true" className="size-[55%]" strokeWidth={2.5} />
      ) : kind === 'picture' ? (
        <img
          src={pictureSrc ?? undefined}
          alt=""
          draggable={false}
          className="size-full object-cover"
          onError={() => setBrokenSrc(pictureSrc)}
        />
      ) : kind === 'emoji' ? (
        <span className={emojiVariants({ size })}>{look?.value}</span>
      ) : (
        initials
      )}
    </span>
  );
}

export interface AvatarPerson {
  key: string;
  name: string;
  avatar?: AvatarLook | null;
}

const stackVariants = cva('flex items-center', {
  variants: {
    size: {
      20: '-space-x-1.5',
      24: '-space-x-1.5',
      40: '-space-x-2.5',
      48: '-space-x-3',
      64: '-space-x-4',
      96: '-space-x-5',
    },
  },
});

const overflowVariants = cva(
  'relative flex shrink-0 items-center justify-center rounded-full bg-muted font-medium text-muted-foreground tabular-nums ring-2 ring-background',
  {
    variants: {
      size: {
        20: 'size-5 text-[9px]',
        24: 'size-6 text-[10px]',
        40: 'size-10 text-xs',
        48: 'size-12 text-sm',
        64: 'size-16 text-base',
        96: 'size-24 text-xl',
      },
    },
  },
);

/**
 * Overlapping faces — a team's portrait or a stage's responsible members —
 * each ringed in the surface it sits on, then `+N` for the rest.
 */
export function AvatarStack({
  people,
  total,
  max = 5,
  size = 24,
  ringClassName = 'ring-background',
  className,
}: {
  people: readonly AvatarPerson[];
  /** How many there are in all, when `people` is only the first few. */
  total?: number;
  max?: number;
  size?: AvatarSize;
  /** The ring colour — the surface the stack sits on. */
  ringClassName?: string;
  className?: string;
}): React.JSX.Element {
  const shown = people.slice(0, max);
  const rest = Math.max((total ?? people.length) - shown.length, 0);
  return (
    <span
      data-slot="avatar-stack"
      className={cn(stackVariants({ size }), className)}>
      {shown.map((person) => (
        <MemberAvatar
          key={person.key}
          name={person.name}
          avatar={person.avatar}
          colorKey={person.key}
          size={size}
          className={cn('ring-2', ringClassName)}
        />
      ))}
      {rest > 0 ? (
        <span
          data-slot="avatar-stack-rest"
          className={cn(overflowVariants({ size }), ringClassName)}>
          +{rest}
        </span>
      ) : null}
    </span>
  );
}
