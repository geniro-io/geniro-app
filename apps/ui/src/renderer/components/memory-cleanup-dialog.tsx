import type {
  MemoryEntry,
  MemoryForgetBatch,
  MemoryReviewRow,
  MemoryReviewRowWarningEnum,
} from '../autogenerated';
import { formatRelativeTime } from '../chats/relative-time';
import { ConfirmActionButton } from './confirm-action-button';
import { EmptyState } from './empty-state';
import { ErrorText } from './error-text';
import { MemoryRow } from './memory-row';
import { Badge } from './ui/badge';
import { Button } from './ui/button';
import { Dialog } from './ui/dialog';
import { OptionIndicator } from './ui/option-list';
import { SegmentedControl } from './ui/segmented-control';
import { Select, type SelectGroup } from './ui/select';
import { Spinner } from './ui/spinner';

export type MemoryCleanupTab = 'cold' | 'checks' | 'kept' | 'forgotten';

export const MEMORY_CLEANUP_SORTS = [
  'leastUsed',
  'oldestSaved',
  'largest',
  'longestSinceRead',
] as const;
export type MemoryCleanupSort = (typeof MEMORY_CLEANUP_SORTS)[number];

export const MEMORY_CLEANUP_WARNINGS = ['any', 'hide', 'only'] as const;
export type MemoryCleanupWarnings = (typeof MEMORY_CLEANUP_WARNINGS)[number];

/** What Least used is narrowed and ordered by; the daemon applies it over every row. */
export interface MemoryCleanupFilters {
  sort: MemoryCleanupSort;
  /** Days an entry must be old; 0 shows every age. */
  minAgeDays: number;
  /** `all`, `global`, a project id, or a team's scope value. */
  scope: string;
  /** `any` or a memory type. */
  type: string;
  warnings: MemoryCleanupWarnings;
  referenceGone: boolean;
}

/** The line a cleanup's result or its undo leaves in the dialog. */
export interface MemoryCleanupNotice {
  text: string;
  /** The batch the notice's Undo restores; null when there is nothing to undo. */
  batchId: string | null;
}

const SORT_ITEMS: { value: MemoryCleanupSort; label: string }[] = [
  { value: 'leastUsed', label: 'Least used' },
  { value: 'oldestSaved', label: 'Oldest saved' },
  { value: 'largest', label: 'Largest' },
  { value: 'longestSinceRead', label: 'Longest since read' },
];

const AGE_ITEMS = [
  { value: '0', label: 'Any age' },
  { value: '7', label: '7+ days' },
  { value: '14', label: '14+ days' },
  { value: '30', label: '30+ days' },
  { value: '90', label: '90+ days' },
];

const TYPE_ITEMS = [
  { value: 'any', label: 'Any type' },
  { value: 'project', label: 'Project' },
  { value: 'reference', label: 'Reference' },
  { value: 'feedback', label: 'Feedback' },
  { value: 'user', label: 'User' },
];

const WARNING_ITEMS: { value: MemoryCleanupWarnings; label: string }[] = [
  { value: 'any', label: 'With warnings' },
  { value: 'hide', label: 'Hide warnings' },
  { value: 'only', label: 'Only warnings' },
];

const WARNING_LABEL: Record<MemoryReviewRowWarningEnum, string> = {
  feedback: 'Looks like a rule: a correction you gave',
  user: 'Looks like a rule: about you',
  writtenByYou: 'Looks like a rule: written by you',
  statesLimit: 'Looks like a rule: states a limit',
  notChecked: 'Looks like a rule: not checked yet',
};

function count(n: number, one: string, many: string): string {
  return `${n.toLocaleString('en-US')} ${n === 1 ? one : many}`;
}

function entries(n: number): string {
  return count(n, 'entry', 'entries');
}

function since(iso: string): string {
  const relative = formatRelativeTime(iso);
  return /^\d+[mhd]$/.test(relative) ? `${relative} ago` : relative;
}

function dayLabel(day: string): string {
  return new Date(`${day}T00:00:00Z`).toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    timeZone: 'UTC',
  });
}

/** A cleanup batch in one line: how many it forgot and when. */
export function batchLabel(batch: MemoryForgetBatch): string {
  const forgot = `Forgot ${entries(batch.count)} · ${since(batch.forgottenAt)}`;
  return batch.automatic ? `Automatic cleanup · ${forgot}` : forgot;
}

/** The Forget question's text: what happens, and how many look like a rule. */
export function forgetDescription(total: number, warned: number): string {
  const them = total === 1 ? 'it' : 'them';
  const base = `Agents no longer see ${them}; new runs drop ${them} from their index. Undo brings ${them} back at any time.`;
  if (warned === 0) {
    return base;
  }
  if (total === 1) {
    return `${base} It looks like a rule.`;
  }
  return `${base} ${warned.toLocaleString('en-US')} of them ${warned === 1 ? 'looks' : 'look'} like a rule.`;
}

function UsageLine({ row }: { row: MemoryReviewRow }): React.JSX.Element {
  const { usage } = row;
  return (
    <p
      data-slot="memory-cleanup-usage"
      className="m-0 flex flex-wrap gap-x-3 gap-y-0.5 text-xs text-muted-foreground tabular-nums">
      <span>
        Read <span className="text-foreground">{usage.reads}</span>
      </span>
      <span>
        last read{' '}
        {usage.lastReadAt === null ? 'never' : dayLabel(usage.lastReadAt)}
      </span>
      <span>{count(usage.searchHits, 'search hit', 'search hits')}</span>
      <span>in {count(usage.indexShows, 'index', 'indexes')}</span>
    </p>
  );
}

function Reasons({
  row,
  tab,
}: {
  row: MemoryReviewRow;
  tab: MemoryCleanupTab;
}): React.JSX.Element | null {
  const marks: React.ReactNode[] = [];
  if (tab === 'cold') {
    marks.push(
      <Badge key="read" variant="muted">
        {row.usage.lastReadAt === null ? 'Never read' : 'Not read in 90 days'}
      </Badge>,
    );
    if (row.usage.lastReadAt === null && row.usage.searchHits > 0) {
      marks.push(
        <Badge key="hits" variant="muted">
          {count(row.usage.searchHits, 'search hit', 'search hits')}, not opened
        </Badge>,
      );
    }
  }
  if (tab === 'kept') {
    marks.push(
      <Badge key="kept" variant="success">
        You kept it
      </Badge>,
    );
  }
  if (tab === 'forgotten') {
    marks.push(
      <Badge key="forgotten" variant="muted">
        {row.forgetBatchId === null ? 'Forgotten' : 'Forgotten in a cleanup'}
        {row.forgottenAt === null ? '' : ` · ${since(row.forgottenAt)}`}
      </Badge>,
    );
  }
  for (const path of row.referencesGone.slice(0, 2)) {
    marks.push(
      <Badge
        key={`gone-${path}`}
        variant="outline"
        className="max-w-full truncate"
        title={path}>
        Reference gone: {path}
      </Badge>,
    );
  }
  if (row.warning !== null && tab !== 'forgotten') {
    marks.push(
      <Badge key="warning" variant="warning">
        {WARNING_LABEL[row.warning]}
      </Badge>,
    );
  }
  return marks.length === 0 ? null : (
    <div
      data-slot="memory-cleanup-reasons"
      className="flex min-w-0 flex-wrap gap-1">
      {marks}
    </div>
  );
}

/**
 * The cleanup list over the shared memory: the least used entries to forget
 * in batches, the duplicates and contradictions a check found, the kept ones,
 * and the forgotten ones with their recent cleanups and Undo. Every list,
 * figure and filter comes from the daemon, counted over every row; the dialog
 * only draws and reports presses.
 */
export function MemoryCleanupDialog({
  open,
  onOpenChange,
  tab,
  onTab,
  counts,
  filters,
  onFilters,
  scopeGroups,
  rows,
  total,
  younger,
  next,
  loading,
  error,
  countedSince,
  counting,
  selected,
  warnedSelected,
  tickSkipped,
  ticking,
  onToggle,
  onTickShown,
  onUntickAll,
  onForget,
  onKeep,
  onUnkeep,
  onRestore,
  onPurge,
  onUndo,
  onLoadMore,
  batches,
  notice,
  busyId,
  projectName,
  teamName,
  checkPanel = null,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  tab: MemoryCleanupTab;
  onTab: (tab: MemoryCleanupTab) => void;
  /** Each tab's count; null while it is not known yet. */
  counts: Record<MemoryCleanupTab, number | null>;
  filters: MemoryCleanupFilters;
  onFilters: (filters: MemoryCleanupFilters) => void;
  scopeGroups: SelectGroup[];
  rows: readonly MemoryReviewRow[];
  total: number;
  /** Least used: how many entries the age filter alone keeps out. */
  younger: number | null;
  next: string | null;
  loading: boolean;
  error: string | null;
  countedSince: string | null;
  counting: boolean;
  selected: ReadonlySet<string>;
  /** How many ticked entries carry a warning. */
  warnedSelected: number;
  /** How many entries with a warning the last Tick shown left unticked. */
  tickSkipped: number | null;
  ticking: boolean;
  onToggle: (row: MemoryReviewRow) => void;
  onTickShown: () => void;
  onUntickAll: () => void;
  onForget: (ids: readonly string[]) => Promise<void>;
  onKeep: (entry: MemoryEntry) => void;
  onUnkeep: (entry: MemoryEntry) => void;
  onRestore: (entry: MemoryEntry) => void;
  /** Forgotten only: delete for good, behind a confirm; absent on a paired device. */
  onPurge?: (entry: MemoryEntry) => Promise<void>;
  onUndo: (batchId: string) => void;
  onLoadMore: () => void;
  batches: readonly MemoryForgetBatch[];
  notice: MemoryCleanupNotice | null;
  busyId: string | null;
  projectName: (projectId: string | null) => string | null;
  teamName: (slug: string | null) => string | null;
  checkPanel?: React.ReactNode;
}): React.JSX.Element {
  const tabLabel = (label: string, n: number | null) =>
    n === null ? (
      label
    ) : (
      <span className="flex flex-col items-center leading-tight sm:flex-row sm:gap-1">
        <span>{label}</span> <span>({n.toLocaleString('en-US')})</span>
      </span>
    );
  const set = (patch: Partial<MemoryCleanupFilters>) =>
    onFilters({ ...filters, ...patch });
  const picked = selected.size;

  const row = (item: MemoryReviewRow) => {
    const { entry } = item;
    const ticked = selected.has(entry.id);
    const busy = busyId === entry.id;
    return (
      <li key={entry.id} data-slot="memory-cleanup-row">
        <MemoryRow
          entry={entry}
          projectName={projectName(entry.projectId)}
          teamName={teamName(entry.teamSlug)}
          busy={busy}
          leading={
            tab === 'cold' ? (
              <button
                type="button"
                aria-pressed={ticked}
                aria-label={`Pick ${entry.handle}`}
                className="mt-0.5 flex h-fit cursor-pointer rounded-md outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50"
                onClick={() => onToggle(item)}>
                <OptionIndicator arity="many" chosen={ticked} />
              </button>
            ) : undefined
          }
          details={
            <>
              <UsageLine row={item} />
              <Reasons row={item} tab={tab} />
            </>
          }
          onForget={
            tab === 'forgotten' ? undefined : () => onForget([entry.id])
          }
          forgetDescription={forgetDescription(
            1,
            item.warning === null ? 0 : 1,
          )}
          onRestore={tab === 'forgotten' ? () => onRestore(entry) : undefined}
          actions={
            tab === 'cold' ? (
              <Button
                type="button"
                variant="outline"
                size="sm"
                disabled={busy}
                onClick={() => onKeep(entry)}>
                Keep
              </Button>
            ) : tab === 'kept' ? (
              <Button
                type="button"
                variant="outline"
                size="sm"
                disabled={busy}
                onClick={() => onUnkeep(entry)}>
                Stop keeping
              </Button>
            ) : onPurge ? (
              <ConfirmActionButton
                disabled={busy}
                question={`Delete ${entry.handle} permanently?`}
                description="Its text, its forget reason and any finding that quotes it are erased for good. This cannot be undone. Its number is not reused and its usage figures stay. Past chats keep what they showed."
                confirmLabel="Delete permanently"
                busyLabel="Deleting…"
                confirmVariant="destructive"
                onConfirm={() => onPurge(entry)}>
                Delete permanently…
              </ConfirmActionButton>
            ) : undefined
          }
        />
      </li>
    );
  };

  const empty = (): React.ReactNode => {
    if (tab === 'kept') {
      return 'Nothing kept yet. Press Keep on an entry to keep it out of Least used.';
    }
    if (tab === 'forgotten') {
      return 'Nothing forgotten.';
    }
    if (younger !== null && younger > 0 && filters.minAgeDays > 0) {
      return (
        <div className="flex flex-col items-center gap-2">
          <span>
            Nothing older than {filters.minAgeDays} days is cold.{' '}
            {younger === 1
              ? '1 younger entry is cold too.'
              : `${younger.toLocaleString('en-US')} younger entries are cold too.`}
          </span>
          <Button
            type="button"
            size="sm"
            variant="outline"
            onClick={() => set({ minAgeDays: 0 })}>
            Show them
          </Button>
        </div>
      );
    }
    return 'Nothing to clean up. Every entry here was read in the last 90 days or is kept.';
  };

  return (
    <Dialog
      open={open}
      onClose={() => onOpenChange(false)}
      title="Clean up memory"
      className="max-w-3xl">
      <div data-slot="memory-cleanup" className="flex min-w-0 flex-col gap-3">
        <SegmentedControl
          ariaLabel="Review"
          value={tab}
          onSelect={onTab}
          options={[
            { id: 'cold', label: tabLabel('Least used', counts.cold) },
            { id: 'checks', label: tabLabel('Conflicts', counts.checks) },
            { id: 'kept', label: tabLabel('Kept', counts.kept) },
            { id: 'forgotten', label: tabLabel('Forgotten', counts.forgotten) },
          ]}
        />
        {notice === null ? null : (
          <div
            role="status"
            data-slot="memory-cleanup-notice"
            className="flex min-w-0 items-center justify-between gap-2 rounded-md border border-border bg-muted/60 px-3 py-2 text-sm">
            <span className="min-w-0">{notice.text}</span>
            {notice.batchId === null ? null : (
              <Button
                type="button"
                size="sm"
                variant="outline"
                onClick={() => onUndo(notice.batchId ?? '')}>
                Undo
              </Button>
            )}
          </div>
        )}
        {tab === 'cold' ? (
          <div
            data-slot="memory-cleanup-filters"
            className="flex min-w-0 flex-wrap items-center gap-1">
            <Select
              variant="ghost"
              aria-label="Sort"
              groups={[{ label: 'Sort', items: SORT_ITEMS }]}
              value={filters.sort}
              onValueChange={(value) =>
                set({
                  sort:
                    MEMORY_CLEANUP_SORTS.find((sort) => sort === value) ??
                    'leastUsed',
                })
              }
            />
            <Select
              variant="ghost"
              aria-label="Age"
              groups={[{ label: 'Age', items: AGE_ITEMS }]}
              value={String(filters.minAgeDays)}
              onValueChange={(value) => set({ minAgeDays: Number(value) })}
            />
            <Select
              variant="ghost"
              flexible
              aria-label="Review scope"
              groups={scopeGroups}
              value={filters.scope}
              onValueChange={(scope) => set({ scope })}
            />
            <Select
              variant="ghost"
              aria-label="Review type"
              groups={[{ label: 'Type', items: TYPE_ITEMS }]}
              value={filters.type}
              onValueChange={(type) => set({ type })}
            />
            <Select
              variant="ghost"
              aria-label="Warnings"
              groups={[{ label: 'Warnings', items: WARNING_ITEMS }]}
              value={filters.warnings}
              onValueChange={(value) =>
                set({
                  warnings:
                    MEMORY_CLEANUP_WARNINGS.find(
                      (warnings) => warnings === value,
                    ) ?? 'any',
                })
              }
            />
            <Button
              type="button"
              size="sm"
              variant="ghost"
              aria-pressed={filters.referenceGone}
              onClick={() => set({ referenceGone: !filters.referenceGone })}>
              <OptionIndicator arity="many" chosen={filters.referenceGone} />
              Reference gone
            </Button>
          </div>
        ) : null}
        {tab === 'forgotten' && batches.length > 0 ? (
          <section
            aria-label="Recent cleanups"
            data-slot="memory-cleanup-batches"
            className="flex min-w-0 flex-col gap-1 rounded-lg border border-border p-3">
            <span className="text-sm font-medium">Recent cleanups</span>
            <ul className="m-0 flex list-none flex-col gap-1 p-0">
              {batches.map((batch) => (
                <li
                  key={batch.batchId}
                  className="flex min-w-0 items-center justify-between gap-2 text-sm">
                  <span className="min-w-0 text-muted-foreground">
                    {batchLabel(batch)}
                  </span>
                  <Button
                    type="button"
                    size="sm"
                    variant="outline"
                    onClick={() => onUndo(batch.batchId)}>
                    Undo
                  </Button>
                </li>
              ))}
            </ul>
          </section>
        ) : null}
        {tab === 'checks' ? checkPanel : null}
        {error === null || tab === 'checks' ? null : (
          <ErrorText>{error}</ErrorText>
        )}
        {tab === 'cold' && countedSince !== null ? (
          <p className="m-0 text-xs text-muted-foreground">
            Counted over every entry; reads counted since{' '}
            {dayLabel(countedSince)}
            {counting ? ', earlier chats still being counted' : ''}.
          </p>
        ) : null}
        {tab === 'checks' ? null : loading && rows.length === 0 ? (
          <p
            role="status"
            className="m-0 flex items-center gap-2 text-sm text-muted-foreground">
            <Spinner />
            Loading…
          </p>
        ) : rows.length === 0 ? (
          error === null ? (
            <EmptyState data-slot="memory-cleanup-empty">{empty()}</EmptyState>
          ) : null
        ) : (
          <>
            <ul className="m-0 flex list-none flex-col gap-1 divide-y divide-border p-0">
              {rows.map(row)}
            </ul>
            {next !== null ? (
              <Button
                type="button"
                size="sm"
                variant="outline"
                className="self-start"
                disabled={loading}
                onClick={onLoadMore}>
                Show more ({(total - rows.length).toLocaleString('en-US')} left)
              </Button>
            ) : null}
          </>
        )}
        {tab === 'cold' && total > 0 ? (
          <div className="sticky -bottom-4 -mx-5 -mb-4 flex flex-wrap items-center justify-between gap-2 border-t border-border bg-card px-5 py-3">
            <div className="flex min-w-0 flex-wrap items-center gap-2">
              <Button
                type="button"
                size="sm"
                variant="ghost"
                disabled={ticking}
                onClick={onTickShown}>
                Tick shown
              </Button>
              <Button
                type="button"
                size="sm"
                variant="ghost"
                disabled={picked === 0}
                onClick={onUntickAll}>
                Untick all
              </Button>
              <span
                data-slot="memory-cleanup-picked"
                className="text-xs text-muted-foreground">
                {picked.toLocaleString('en-US')} selected
                {tickSkipped !== null && tickSkipped > 0
                  ? ` · Tick shown skipped ${entries(tickSkipped)} with a warning`
                  : ''}
              </span>
            </div>
            <ConfirmActionButton
              variant="default"
              disabled={picked === 0}
              question={`Forget ${entries(picked)}?`}
              description={forgetDescription(picked, warnedSelected)}
              confirmLabel={`Forget ${picked.toLocaleString('en-US')}`}
              busyLabel="Forgetting…"
              onConfirm={() => onForget([...selected])}>
              Forget {picked.toLocaleString('en-US')}…
            </ConfirmActionButton>
          </div>
        ) : null}
      </div>
    </Dialog>
  );
}
