export type MemoryCleanupTab = 'cold' | 'checks' | 'kept' | 'forgotten';

const CLEANUP_TABS_ID = 'memory-cleanup';

export const MEMORY_CLEANUP_SORTS = [
  'leastUsed',
  'oldestSaved',
  'largest',
  'longestSinceRead',
] as const;
export type MemoryCleanupSort = (typeof MEMORY_CLEANUP_SORTS)[number];

export const MEMORY_CLEANUP_WARNINGS = ['any', 'hide', 'only'] as const;
export type MemoryCleanupWarnings = (typeof MEMORY_CLEANUP_WARNINGS)[number];

/** What Least used is narrowed and ordered by; the daemon applies it over every row. */
export interface MemoryCleanupFilters {
  sort: MemoryCleanupSort;
  /** Days an entry must be old; 0 shows every age. */
  minAgeDays: number;
  /** `all`, `global`, a project id, or a team's scope value. */
  scope: string;
  /** `any` or a memory type. */
  type: string;
  warnings: MemoryCleanupWarnings;
  referenceGone: boolean;
}

/** The line a cleanup's result or its undo leaves in the dialog. */
export interface MemoryCleanupNotice {
  text: string;
  /** The batch the notice's Undo restores; null when there is nothing to undo. */
  batchId: string | null;
}

const WARNING_LABEL: Record<MemoryReviewRowWarningEnum, string> = {
  feedback: 'It reads like a correction you gave.',
  user: 'It says something about you.',
  writtenByYou: 'You wrote it yourself.',
  statesLimit: 'It states a limit.',
  notChecked: 'Not checked yet.',
};

const SUGGESTIONS_SHOWN = 6;

function count(n: number, one: string, many: string): string {
  return `${n.toLocaleString('en-US')} ${n === 1 ? one : many}`;
}

function entries(n: number): string {
  return count(n, 'entry', 'entries');
}

function since(iso: string): string {
  const relative = formatRelativeTime(iso);
  return /^\d+[mhd]$/.test(relative) ? `${relative} ago` : relative;
}

/** A cleanup batch in one line: what it forgot, when, and when it is deleted for good. */
export function batchLabel(batch: MemoryForgetBatch): string {
  const headline = batchHeadline(batch);
  return batch.purgeAt === null
    ? headline
    : `${headline} · ${deletedForGood(batch.purgeAt)}`;
}

function batchHeadline(batch: MemoryForgetBatch): string {
  const forgot = `Forgot ${entries(batch.count)} · ${since(batch.forgottenAt)}`;
  switch (batch.kind) {
    case 'marks':
      return `Forgotten by agents' marks — ${batch.title ?? entries(batch.count)}`;
    case 'expired_lesson':
      return `Auto lessons nobody confirmed in 90 days · ${entries(batch.count)} · ${since(batch.forgottenAt)}`;
    case 'automatic':
      return `Automatic cleanup · ${forgot}`;
    case 'manual':
      return forgot;
  }
}

/** A cleanup batch as the Recent cleanups list and the Last cleanup row draw it: its line, then its reason. */
export function BatchSummary({
  batch,
}: {
  batch: MemoryForgetBatch;
}): React.JSX.Element {
  return (
    <div className="flex min-w-0 flex-col gap-0.5">
      <span className="min-w-0 text-muted-foreground">{batchLabel(batch)}</span>
      {batch.reason === null || batch.kind === 'expired_lesson' ? null : (
        <ClampedText
          text={batch.reason}
          lines={2}
          slot="memory-batch-reason"
          className="text-xs text-muted-foreground"
        />
      )}
    </div>
  );
}

function countOf(
  batches: readonly MemoryForgetBatch[],
  kind: MemoryForgetBatch['kind'],
): number {
  return batches.reduce(
    (sum, batch) => (batch.kind === kind ? sum + batch.count : sum),
    0,
  );
}

/** A cleanup pass in one line: its total and when, who forgot its entries, and when they are deleted for good. */
export function passLabel(batches: readonly MemoryForgetBatch[]): string {
  const [newest] = batches;
  if (newest === undefined) {
    return '';
  }
  const total = batches.reduce((sum, batch) => sum + batch.count, 0);
  const byMarks = countOf(batches, 'marks');
  const byAutomatic = countOf(batches, 'automatic');
  const lessons = countOf(batches, 'expired_lesson');
  const purgeAt = batches.every((batch) => batch.purgeAt === newest.purgeAt)
    ? newest.purgeAt
    : null;
  return [
    `Forgot ${entries(total)} in one pass`,
    since(newest.forgottenAt),
    byMarks === 0
      ? null
      : `${byMarks.toLocaleString('en-US')} by agents' marks`,
    byAutomatic === 0
      ? null
      : `${byAutomatic.toLocaleString('en-US')} by the automatic cleanup`,
    lessons === 0
      ? null
      : count(
          lessons,
          'auto lesson nobody confirmed',
          'auto lessons nobody confirmed',
        ),
    purgeAt === null ? null : deletedForGood(purgeAt),
  ]
    .filter((part): part is string => part !== null)
    .join(' · ');
}

/** A cleanup pass's batch titles, in the order the batches are listed; an untitled batch reads as its entry count. */
export function passTitles(batches: readonly MemoryForgetBatch[]): string {
  return batches
    .map((batch) => batch.title ?? entries(batch.count))
    .join(' · ');
}

/** A cleanup pass of several batches as the Last cleanup row draws it: its line, then the titles it forgot. */
export function PassSummary({
  batches,
}: {
  batches: readonly MemoryForgetBatch[];
}): React.JSX.Element {
  return (
    <div className="flex min-w-0 flex-col gap-0.5">
      <span className="min-w-0 text-muted-foreground">
        {passLabel(batches)}
      </span>
      <ClampedText
        text={passTitles(batches)}
        lines={2}
        slot="memory-pass-titles"
        className="text-xs text-muted-foreground"
      />
    </div>
  );
}

/** The Forget question's text: what happens, and how many look like a rule. */
export function forgetDescription(total: number, warned: number): string {
  const them = total === 1 ? 'it' : 'them';
  const base = `Agents no longer see ${them}; new runs drop ${them} from their index. Undo brings ${them} back at any time.`;
  if (warned === 0) {
    return base;
  }
  if (total === 1) {
    return `${base} It looks like a rule.`;
  }
  return `${base} ${warned.toLocaleString('en-US')} of them ${warned === 1 ? 'looks' : 'look'} like a rule.`;
}

function whyListed(row: MemoryReviewRow, tab: MemoryCleanupTab): string[] {
  const parts: string[] = [];
  if (tab === 'cold') {
    parts.push(
      row.usage.lastReadAt === null ? 'Never read' : 'Not read in 90 days',
    );
  }
  if (tab === 'kept') {
    parts.push('You kept it');
  }
  if (tab === 'forgotten') {
    parts.push(
      row.forgottenAt === null
        ? 'Forgotten'
        : `Forgotten ${since(row.forgottenAt)}`,
    );
  }
  if (row.referencesGone.length > 0) {
    parts.push('Mentions a file that no longer exists');
  }
  return parts;
}

function RuleBadge({
  warning,
}: {
  warning: MemoryReviewRowWarningEnum;
}): React.JSX.Element {
  return (
    <Badge variant="warning" title={WARNING_LABEL[warning]}>
      Looks like a rule
    </Badge>
  );
}

function Why({
  row,
  tab,
}: {
  row: MemoryReviewRow;
  tab: MemoryCleanupTab;
}): React.JSX.Element | null {
  const parts = whyListed(row, tab);
  const warning = tab === 'forgotten' ? null : row.warning;
  if (parts.length === 0 && warning === null) {
    return null;
  }
  return (
    <div
      data-slot="memory-cleanup-why"
      className="flex min-w-0 flex-wrap items-center gap-2 text-xs text-muted-foreground"
      title={
        row.referencesGone.length === 0
          ? undefined
          : row.referencesGone.join('\n')
      }>
      {parts.length === 0 ? null : <span>{parts.join(' · ')}</span>}
      {warning === null ? null : <RuleBadge warning={warning} />}
    </div>
  );
}

/** What the AI sort said: how many entries it read, and the ones it would forget. */
export interface MemoryCleanupRecommendation {
  sorted: number;
  forget: readonly MemoryReviewRow[];
}

function Suggestions({
  recommendation,
  verdicts,
  overrides,
  onOverrides,
  forgetting,
  onForget,
}: {
  recommendation: MemoryCleanupRecommendation;
  verdicts: ReadonlyMap<string, MemorySortVerdict> | undefined;
  overrides: ReadonlyMap<string, boolean>;
  onOverrides: (next: ReadonlyMap<string, boolean>) => void;
  forgetting: boolean;
  onForget: (ids: readonly string[]) => void;
}): React.JSX.Element {
  const { forget, sorted } = recommendation;
  const { shown, expanded, setExpanded } = useShowAll(
    forget,
    SUGGESTIONS_SHOWN,
  );
  const chosen = (row: MemoryReviewRow): boolean =>
    overrides.get(row.entry.id) ?? row.warning === null;
  const picked = forget.filter(chosen).map((row) => row.entry.id);
  const toggle = (row: MemoryReviewRow): void => {
    onOverrides(new Map(overrides).set(row.entry.id, !chosen(row)));
  };

  return (
    <section
      aria-label="AI suggestions"
      data-slot="memory-cleanup-suggestions"
      className="flex min-w-0 flex-col gap-3 rounded-lg border border-border bg-muted/40 p-4">
      <div className="flex min-w-0 flex-wrap items-start justify-between gap-3">
        <div className="flex min-w-0 flex-col gap-0.5">
          <span
            data-slot="memory-cleanup-suggestions-title"
            className="text-sm font-medium">
            {forget.length === 0
              ? `AI suggests keeping all ${entries(sorted)} — nothing to forget.`
              : `AI suggests forgetting ${forget.length.toLocaleString('en-US')} of ${entries(sorted)}`}
          </span>
          {forget.length === 0 ? null : (
            <span className="text-xs text-muted-foreground">
              The ticked ones are forgotten when you press Forget. You can undo
              it.
            </span>
          )}
        </div>
        {forget.length === 0 ? null : (
          <Button
            type="button"
            size="sm"
            disabled={picked.length === 0 || forgetting}
            onClick={() => onForget(picked)}>
            {forgetting
              ? 'Forgetting…'
              : `Forget ${picked.length.toLocaleString('en-US')}`}
          </Button>
        )}
      </div>
      {forget.length === 0 ? null : (
        <ul className="m-0 flex list-none flex-col gap-2 p-0">
          {shown.map((row) => {
            const reason = verdicts?.get(row.entry.id)?.reason ?? '';
            return (
              <li
                key={row.entry.id}
                data-slot="memory-cleanup-suggestion"
                className="flex min-w-0 items-start gap-2.5">
                <button
                  type="button"
                  aria-pressed={chosen(row)}
                  aria-label={`Forget ${row.entry.handle}`}
                  className="mt-0.5 flex h-fit cursor-pointer rounded-md outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50"
                  onClick={() => toggle(row)}>
                  <OptionIndicator arity="many" chosen={chosen(row)} />
                </button>
                <div className="flex min-w-0 flex-col gap-0.5">
                  <span className="min-w-0 truncate text-sm">
                    {row.entry.title}
                  </span>
                  <span className="flex min-w-0 flex-wrap items-center gap-2 text-xs text-muted-foreground">
                    {reason === '' ? null : (
                      <span className="min-w-0 break-words">{reason}</span>
                    )}
                    {row.warning === null ? null : (
                      <RuleBadge warning={row.warning} />
                    )}
                  </span>
                </div>
              </li>
            );
          })}
        </ul>
      )}
      <ShowAllButton
        total={forget.length}
        limit={SUGGESTIONS_SHOWN}
        expanded={expanded}
        onToggle={() => setExpanded(!expanded)}
        noun="suggestions"
        nounOne="suggestion"
      />
    </section>
  );
}

/**
 * The cleanup list over the shared memory: the least used entries, the
 * duplicates and contradictions a check found, the kept ones, and the
 * forgotten ones with their recent cleanups and Undo. Least used leads with
 * the AI's suggestion of what to forget, when it was asked. Every list and
 * figure comes from the daemon, counted over every row; the dialog only draws
 * and reports presses.
 */
export function MemoryCleanupDialog({
  open,
  onOpenChange,
  tab,
  onTab,
  counts,
  filters,
  onFilters,
  rows,
  total,
  younger,
  next,
  loading,
  error,
  selected,
  tickSkipped,
  ticking,
  forgetting,
  onToggle,
  onSelectAll,
  onClearPicks,
  onForget,
  onForgetNow,
  onKeep,
  onUnkeep,
  onRestore,
  onPurge,
  onUndo,
  onLoadMore,
  batches,
  notice,
  busyId,
  projectName,
  teamName,
  checkPanel = null,
  sortPanel = null,
  recommendation = null,
  verdicts,
}: {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  tab: MemoryCleanupTab;
  onTab: (tab: MemoryCleanupTab) => void;
  /** Each tab's count; null while it is not known yet. */
  counts: Record<MemoryCleanupTab, number | null>;
  filters: MemoryCleanupFilters;
  onFilters: (filters: MemoryCleanupFilters) => void;
  rows: readonly MemoryReviewRow[];
  total: number;
  /** Least used: how many entries the age filter alone keeps out. */
  younger: number | null;
  next: string | null;
  loading: boolean;
  error: string | null;
  selected: ReadonlySet<string>;
  /** How many entries that look like a rule the last Select all left out. */
  tickSkipped: number | null;
  ticking: boolean;
  forgetting: boolean;
  onToggle: (row: MemoryReviewRow) => void;
  onSelectAll: () => void;
  onClearPicks: () => void;
  /** One entry's Forget, asked first by its row; rejects with the reason. */
  onForget: (ids: readonly string[]) => Promise<void>;
  /** Forget several at once; undone from the notice. */
  onForgetNow: (ids: readonly string[]) => void;
  onKeep: (entry: MemoryEntry) => void;
  onUnkeep: (entry: MemoryEntry) => void;
  onRestore: (entry: MemoryEntry) => void;
  /** Forgotten only: delete for good, behind a confirm; absent on a paired device. */
  onPurge?: (entry: MemoryEntry) => Promise<void>;
  onUndo: (batchId: string) => void;
  onLoadMore: () => void;
  batches: readonly MemoryForgetBatch[];
  notice: MemoryCleanupNotice | null;
  busyId: string | null;
  projectName: (projectId: string | null) => string | null;
  teamName: (slug: string | null) => string | null;
  checkPanel?: React.ReactNode;
  /** Least used: the box that asks AI what to forget, absent on a paired device. */
  sortPanel?: React.ReactNode;
  /** Least used: what the AI suggests forgetting, once it was asked. */
  recommendation?: MemoryCleanupRecommendation | null;
  /** Least used: what the AI said of each entry, by entry id. */
  verdicts?: ReadonlyMap<string, MemorySortVerdict>;
}): React.JSX.Element {
  const picked = selected.size;
  const [overrides, setOverrides] = useState<ReadonlyMap<string, boolean>>(
    new Map(),
  );

  const row = (item: MemoryReviewRow) => {
    const { entry } = item;
    const ticked = selected.has(entry.id);
    const busy = busyId === entry.id;
    return (
      <li key={entry.id} data-slot="memory-cleanup-row" className="py-2">
        <MemoryRow
          entry={entry}
          projectName={projectName(entry.projectId)}
          teamName={teamName(entry.teamSlug)}
          busy={busy}
          showStatus={false}
          leading={
            tab === 'cold' ? (
              <button
                type="button"
                aria-pressed={ticked}
                aria-label={`Pick ${entry.handle}`}
                className="mt-0.5 flex h-fit cursor-pointer rounded-md outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50"
                onClick={() => onToggle(item)}>
                <OptionIndicator arity="many" chosen={ticked} />
              </button>
            ) : undefined
          }
          details={<Why row={item} tab={tab} />}
          onForget={
            tab === 'forgotten' ? undefined : () => onForget([entry.id])
          }
          forgetDescription={forgetDescription(
            1,
            item.warning === null ? 0 : 1,
          )}
          onRestore={tab === 'forgotten' ? () => onRestore(entry) : undefined}
          actions={
            tab === 'cold'
              ? [{ value: 'keep', label: 'Keep', run: () => onKeep(entry) }]
              : tab === 'kept'
                ? [
                    {
                      value: 'unkeep',
                      label: 'Stop keeping',
                      run: () => onUnkeep(entry),
                    },
                  ]
                : onPurge
                  ? [
                      {
                        value: 'purge',
                        label: 'Delete permanently…',
                        tone: 'destructive',
                        run: () => onPurge(entry),
                        confirm: {
                          question: `Delete ${entry.handle} permanently?`,
                          description:
                            'Its text, its forget reason and any finding that quotes it are erased for good. This cannot be undone. Its number is not reused and its usage figures stay. Past chats keep what they showed.',
                          confirmLabel: 'Delete permanently',
                          busyLabel: 'Deleting…',
                        },
                      },
                    ]
                  : []
          }
        />
      </li>
    );
  };

  const empty = (): React.ReactNode => {
    if (tab === 'kept') {
      return 'Nothing kept yet. Press Keep on an entry to keep it out of Least used.';
    }
    if (tab === 'forgotten') {
      return 'Nothing forgotten.';
    }
    if (younger !== null && younger > 0 && filters.minAgeDays > 0) {
      return (
        <div className="flex flex-col items-center gap-2">
          <span>
            Nothing older than {filters.minAgeDays} days is cold.{' '}
            {younger === 1
              ? '1 younger entry is cold too.'
              : `${younger.toLocaleString('en-US')} younger entries are cold too.`}
          </span>
          <Button
            type="button"
            size="sm"
            variant="outline"
            onClick={() => onFilters({ ...filters, minAgeDays: 0 })}>
            Show them
          </Button>
        </div>
      );
    }
    return 'Nothing to clean up. Every entry here was read in the last 90 days or is kept.';
  };

  return (
    <Dialog
      open={open}
      onClose={() => onOpenChange(false)}
      title="Clean up memory"
      className="max-w-3xl">
      <div data-slot="memory-cleanup" className="flex min-w-0 flex-col gap-4">
        <div className="border-b border-border">
          <TabStrip
            label="Review"
            idPrefix={CLEANUP_TABS_ID}
            value={tab}
            onSelect={onTab}
            tabs={[
              { id: 'cold', label: 'Least used', count: counts.cold },
              { id: 'checks', label: 'Conflicts', count: counts.checks },
              { id: 'kept', label: 'Kept', count: counts.kept },
              { id: 'forgotten', label: 'Forgotten', count: counts.forgotten },
            ]}
          />
        </div>
        <div
          role="tabpanel"
          id={tabPanelId(CLEANUP_TABS_ID, tab)}
          aria-labelledby={tabId(CLEANUP_TABS_ID, tab)}
          className="flex min-w-0 flex-col gap-4">
          {notice === null ? null : (
            <div
              role="status"
              data-slot="memory-cleanup-notice"
              className="flex min-w-0 items-center justify-between gap-2 rounded-md border border-border bg-muted/60 px-3 py-2 text-sm">
              <span className="min-w-0">{notice.text}</span>
              {notice.batchId === null ? null : (
                <Button
                  type="button"
                  size="sm"
                  variant="outline"
                  onClick={() => onUndo(notice.batchId ?? '')}>
                  Undo
                </Button>
              )}
            </div>
          )}
          {tab === 'cold' ? sortPanel : null}
          {tab === 'cold' && recommendation !== null ? (
            <Suggestions
              recommendation={recommendation}
              verdicts={verdicts}
              overrides={overrides}
              onOverrides={setOverrides}
              forgetting={forgetting}
              onForget={onForgetNow}
            />
          ) : null}
          {tab === 'forgotten' && batches.length > 0 ? (
            <section
              aria-label="Recent cleanups"
              data-slot="memory-cleanup-batches"
              className="flex min-w-0 flex-col gap-1 rounded-lg border border-border p-3">
              <span className="text-sm font-medium">Recent cleanups</span>
              <ul className="m-0 flex list-none flex-col gap-1 p-0">
                {batches.map((batch) => (
                  <li
                    key={batch.batchId}
                    className="flex min-w-0 items-center justify-between gap-2 text-sm">
                    <BatchSummary batch={batch} />
                    <Button
                      type="button"
                      size="sm"
                      variant="outline"
                      onClick={() => onUndo(batch.batchId)}>
                      Undo
                    </Button>
                  </li>
                ))}
              </ul>
            </section>
          ) : null}
          {tab === 'checks' ? checkPanel : null}
          {error === null || tab === 'checks' ? null : (
            <ErrorText>{error}</ErrorText>
          )}
          {tab === 'checks' ? null : loading && rows.length === 0 ? (
            <p
              role="status"
              className="m-0 flex items-center gap-2 text-sm text-muted-foreground">
              <Spinner />
              Loading…
            </p>
          ) : rows.length === 0 ? (
            error === null ? (
              <EmptyState data-slot="memory-cleanup-empty">
                {empty()}
              </EmptyState>
            ) : null
          ) : (
            <div className="flex min-w-0 flex-col gap-1">
              {tab === 'cold' ? (
                <div className="flex min-w-0 items-center justify-between gap-2">
                  <span
                    data-slot="memory-cleanup-list-head"
                    className="text-xs text-muted-foreground">
                    {total === 1
                      ? '1 entry nobody has read lately'
                      : `${total.toLocaleString('en-US')} entries nobody has read lately`}
                    {tickSkipped !== null && tickSkipped > 0
                      ? ` · Select all left out ${tickSkipped.toLocaleString('en-US')} that ${tickSkipped === 1 ? 'looks' : 'look'} like a rule`
                      : ''}
                  </span>
                  <Button
                    type="button"
                    size="sm"
                    variant="ghost"
                    title="Tick every entry in this list, except the ones that look like a rule."
                    disabled={ticking}
                    onClick={onSelectAll}>
                    Select all
                  </Button>
                </div>
              ) : null}
              <ul className="m-0 flex list-none flex-col divide-y divide-border p-0">
                {rows.map(row)}
              </ul>
              {next !== null ? (
                <Button
                  type="button"
                  size="sm"
                  variant="outline"
                  className="self-start"
                  disabled={loading}
                  onClick={onLoadMore}>
                  Show more ({(total - rows.length).toLocaleString('en-US')}{' '}
                  left)
                </Button>
              ) : null}
            </div>
          )}
          {tab === 'cold' && picked > 0 ? (
            <div className="sticky -bottom-4 -mx-5 -mb-4 flex flex-wrap items-center justify-between gap-2 border-t border-border bg-card px-5 py-3">
              <div className="flex min-w-0 flex-wrap items-center gap-2">
                <span
                  data-slot="memory-cleanup-picked"
                  className="text-sm text-muted-foreground">
                  {picked.toLocaleString('en-US')} selected
                </span>
                <Button
                  type="button"
                  size="sm"
                  variant="ghost"
                  onClick={onClearPicks}>
                  Clear
                </Button>
              </div>
              <Button
                type="button"
                size="sm"
                disabled={forgetting}
                onClick={() => onForgetNow([...selected])}>
                {forgetting
                  ? 'Forgetting…'
                  : `Forget ${picked.toLocaleString('en-US')}`}
              </Button>
            </div>
          ) : null}
        </div>
      </div>
    </Dialog>
  );
}
