import { useId } from 'react';

import { type MemoryEntry, MemoryEntryTypeEnum } from '../autogenerated';
import { ErrorText } from './error-text';
import { ExpandableTextarea } from './expandable-textarea';
import { Field } from './field';
import { Button } from './ui/button';
import { Input } from './ui/input';
import { Select, type SelectGroup } from './ui/select';
import { cn } from './ui/utils';

export interface MemoryFormValue {
  title: string;
  body: string;
  type: MemoryEntry['type'];
  projectId: string | null;
}

// TWIN: MEMORY_TITLE_MAX_CHARS and MEMORY_BODY_MAX_BYTES in apps/daemon/src/v1/memory/memory.types.ts
export const MEMORY_TITLE_MAX_CHARS = 120;
export const MEMORY_BODY_MAX_BYTES = 8192;

const GLOBAL_SCOPE = '';

const TYPE_LABELS: Record<MemoryEntry['type'], string> = {
  user: 'User',
  feedback: 'Feedback',
  project: 'Project',
  reference: 'Reference',
};

export const MEMORY_TYPE_GROUPS: SelectGroup[] = [
  {
    items: Object.values(MemoryEntryTypeEnum).map((type) => ({
      value: type,
      label: TYPE_LABELS[type],
    })),
  },
];

export function memoryScopeGroups(
  projects: readonly { id: string; name: string }[],
): SelectGroup[] {
  return [
    {
      items: [
        { value: GLOBAL_SCOPE, label: 'Global' },
        ...projects.map((project) => ({
          value: project.id,
          label: project.name,
        })),
      ],
    },
  ];
}

export function scopeSelectValue(projectId: string | null): string {
  return projectId ?? GLOBAL_SCOPE;
}

export function projectIdOfScope(value: string): string | null {
  return value === GLOBAL_SCOPE ? null : value;
}

export function memoryTypeOf(value: string): MemoryEntry['type'] {
  return (
    Object.values(MemoryEntryTypeEnum).find((type) => type === value) ??
    MemoryEntryTypeEnum.User
  );
}

const encoder = new TextEncoder();

export function memoryBodyBytes(body: string): number {
  return encoder.encode(body).length;
}

export function MemoryForm({
  value,
  projects,
  saving,
  error,
  submitLabel,
  onChange,
  onSubmit,
  onCancel,
}: {
  value: MemoryFormValue;
  projects: readonly { id: string; name: string }[];
  saving: boolean;
  error: string | null;
  submitLabel: string;
  onChange: (next: MemoryFormValue) => void;
  onSubmit: () => void;
  onCancel: () => void;
}): React.JSX.Element {
  const id = useId();
  const bytes = memoryBodyBytes(value.body);
  const titleTooLong = value.title.length > MEMORY_TITLE_MAX_CHARS;
  const bodyTooLong = bytes > MEMORY_BODY_MAX_BYTES;
  const canSubmit =
    !saving &&
    value.title.trim() !== '' &&
    value.body.trim() !== '' &&
    !titleTooLong &&
    !bodyTooLong;

  return (
    <div
      data-slot="memory-form"
      className="flex min-w-0 flex-col gap-3"
      onKeyDown={(event) => {
        if (
          event.key === 'Escape' &&
          !event.defaultPrevented &&
          event.currentTarget.contains(event.target as Node)
        ) {
          event.preventDefault();
          onCancel();
        }
      }}>
      <Field
        label="Title"
        htmlFor={`${id}-title`}
        hint={
          titleTooLong
            ? `${value.title.length} / ${MEMORY_TITLE_MAX_CHARS} characters`
            : undefined
        }>
        <Input
          id={`${id}-title`}
          value={value.title}
          aria-invalid={titleTooLong}
          autoFocus
          onChange={(event) =>
            onChange({ ...value, title: event.target.value })
          }
          onKeyDown={(event) => {
            if (
              event.key === 'Enter' &&
              !event.nativeEvent.isComposing &&
              canSubmit
            ) {
              event.preventDefault();
              onSubmit();
            }
          }}
        />
      </Field>
      <Field
        label="Note"
        htmlFor={`${id}-body`}
        hint={
          <span
            data-slot="memory-body-bytes"
            className={cn(bodyTooLong && 'text-destructive')}>
            {bytes} / {MEMORY_BODY_MAX_BYTES} bytes
          </span>
        }>
        <ExpandableTextarea
          id={`${id}-body`}
          title="Memory note"
          value={value.body}
          invalid={bodyTooLong}
          rows={5}
          maxRows={12}
          onChange={(body) => onChange({ ...value, body })}
        />
      </Field>
      <div className="grid gap-3 sm:grid-cols-2">
        <Field label="Type" htmlFor={`${id}-type`}>
          <Select
            id={`${id}-type`}
            groups={MEMORY_TYPE_GROUPS}
            value={value.type}
            onValueChange={(type) =>
              onChange({ ...value, type: memoryTypeOf(type) })
            }
          />
        </Field>
        <Field label="Scope" htmlFor={`${id}-scope`}>
          <Select
            id={`${id}-scope`}
            groups={memoryScopeGroups(projects)}
            value={scopeSelectValue(value.projectId)}
            onValueChange={(scope) =>
              onChange({ ...value, projectId: projectIdOfScope(scope) })
            }
          />
        </Field>
      </div>
      {error === null ? null : <ErrorText>{error}</ErrorText>}
      <div className="flex justify-end gap-2">
        <Button type="button" variant="ghost" size="sm" onClick={onCancel}>
          Cancel
        </Button>
        <Button
          type="button"
          size="sm"
          disabled={!canSubmit}
          onClick={onSubmit}>
          {submitLabel}
        </Button>
      </div>
    </div>
  );
}
