// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import {
  MEMORY_IMPORT_PREVIEW,
  MEMORY_PROJECTS,
  memoryImportRow,
} from '../__fixtures__/memories';
import { PUBLISHED_IDENTITIES } from '../__tests__/agent-identities';
import { AgentIdentityContext } from '../agent-identity';
import type { MemoryImportPreviewDto } from '../autogenerated';
import {
  IMPORT_PAGE_SIZE,
  MemoryImportDialog,
  type MemoryImportTriage,
} from './memory-import-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

type Props = Partial<Parameters<typeof MemoryImportDialog>[0]>;

function element(props: Props): React.ReactElement {
  return (
    <AgentIdentityContext.Provider value={PUBLISHED_IDENTITIES}>
      <MemoryImportDialog
        open
        onOpenChange={() => undefined}
        preview={MEMORY_IMPORT_PREVIEW}
        loading={false}
        error={null}
        importing={false}
        projects={MEMORY_PROJECTS}
        onImport={() => undefined}
        {...props}
      />
    </AgentIdentityContext.Provider>
  );
}

function render(props: Props = {}): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(element(props));
  });
  return container;
}

function rerender(props: Props): void {
  act(() => {
    root!.render(element(props));
  });
}

const rowOf = (el: HTMLElement, key: string): HTMLElement =>
  el.querySelector<HTMLElement>(
    `[data-slot="memory-import-row"][data-key="${key}"]`,
  )!;

const tick = (el: HTMLElement, key: string): HTMLButtonElement =>
  rowOf(el, key).querySelector<HTMLButtonElement>('button[aria-pressed]')!;

const tickedKeys = (el: HTMLElement): string[] =>
  [...el.querySelectorAll<HTMLElement>('[data-slot="memory-import-row"]')]
    .filter(
      (row) =>
        row
          .querySelector('button[aria-pressed]')!
          .getAttribute('aria-pressed') === 'true',
    )
    .map((row) => row.getAttribute('data-key')!);

const button = (el: HTMLElement, name: string): HTMLButtonElement =>
  [...el.querySelectorAll('button')].find(
    (candidate) => candidate.textContent === name,
  )!;

const importButton = (el: HTMLElement): HTMLButtonElement =>
  [...el.querySelectorAll('button')].find((candidate) =>
    /^Import( \d+|ing…)$/.test(candidate.textContent ?? ''),
  )!;

function pick(
  el: HTMLElement,
  key: string,
  trigger: 0 | 1,
  label: string,
): void {
  act(() => {
    rowOf(el, key)
      .querySelectorAll<HTMLElement>('[data-menu-trigger]')
      [trigger]!.click();
  });
  const option = [
    ...rowOf(el, key).querySelectorAll<HTMLElement>('[role="option"]'),
  ].find((candidate) => candidate.textContent?.includes(label));
  act(() => {
    option!.click();
  });
}

describe('MemoryImportDialog', () => {
  it('ticks by default only the notes that are new, similar to nothing and importable', () => {
    const el = render();
    expect(tickedKeys(el)).toEqual(['row-1', 'row-5', 'row-2']);
    expect(importButton(el).textContent).toBe('Import 3');
    expect(
      el.querySelector('[data-slot="memory-import-summary"]')!.textContent,
    ).toBe('6 notes found · 3 ticked');
  });

  it('leaves a second copy of one note unticked and says so', () => {
    const el = render({
      preview: {
        rows: [
          memoryImportRow({ key: 'first', title: 'Same' }),
          memoryImportRow({ key: 'copy', title: 'Same', sameAs: 'first' }),
        ],
        sources: [],
        triageAgents: [],
      },
    });

    expect(tickedKeys(el)).toEqual(['first']);
    expect(rowOf(el, 'copy').textContent).toContain(
      'The same note as another row here',
    );
  });

  it('disables the row that has a problem and shows the reason', () => {
    const el = render();
    expect(tick(el, 'row-6').disabled).toBe(true);
    expect(tick(el, 'row-1').disabled).toBe(false);
    expect(rowOf(el, 'row-6').textContent).toContain(
      'The file is larger than 8192 bytes',
    );
  });

  it('marks similar, already imported and ambiguous notes', () => {
    const el = render();
    expect(rowOf(el, 'row-3').textContent).toContain(
      'Similar entry exists: m7 Keep pull requests small',
    );
    expect(rowOf(el, 'row-4').textContent).toContain('Already imported');
    expect(rowOf(el, 'row-5').textContent).toContain(
      'Several projects share this folder — filed as Global',
    );
    expect(rowOf(el, 'row-1').textContent).not.toContain('Already imported');
  });

  it('groups notes under the folder they were written for, naming the agent and its profile, and keeps the file in the title', () => {
    const el = render();
    const groups = [
      ...el.querySelectorAll<HTMLElement>('[data-slot="memory-import-group"]'),
    ];
    expect(
      groups.map(
        (group) =>
          group.querySelector('[data-slot="memory-import-group-name"]')!
            .textContent,
      ),
    ).toEqual(['billing', 'No folder']);
    expect(
      groups[0]!.querySelector('[data-slot="memory-import-group-origin"]')!
        .textContent,
    ).toBe('~/code/billing — Claude · ~/.claude');
    expect(
      groups[1]!.querySelector('[data-slot="memory-import-group-origin"]')!
        .textContent,
    ).toBe('Codex · ~/.codex/memories/MEMORY.md');
    expect(groups[0]!.textContent).toContain('2 of 5 notes');
    expect(tick(el, 'row-2').getAttribute('title')).toBe(
      '/Users/me/.codex/memories/MEMORY.md',
    );
  });

  it('ticks and unticks a whole group from its header', () => {
    const el = render();
    const header = el.querySelector<HTMLButtonElement>(
      '[data-slot="memory-import-group"] button[aria-pressed]',
    )!;
    expect(header.getAttribute('aria-pressed')).toBe('false');
    act(() => header.click());
    expect(tickedKeys(el)).toEqual([
      'row-1',
      'row-3',
      'row-4',
      'row-5',
      'row-2',
    ]);
    expect(header.getAttribute('aria-pressed')).toBe('true');
    act(() => header.click());
    expect(tickedKeys(el)).toEqual(['row-2']);
  });

  it('toggles a note with its checkbox and updates the count', () => {
    const el = render();
    act(() => tick(el, 'row-3').click());
    expect(tickedKeys(el)).toContain('row-3');
    expect(importButton(el).textContent).toBe('Import 4');
    act(() => tick(el, 'row-1').click());
    expect(tickedKeys(el)).not.toContain('row-1');
    expect(importButton(el).textContent).toBe('Import 3');
  });

  it('Tick all ticks every note except the one with a problem, Untick all clears them', () => {
    const el = render();
    act(() => button(el, 'Tick all').click());
    expect(tickedKeys(el)).toEqual([
      'row-1',
      'row-3',
      'row-4',
      'row-5',
      'row-2',
    ]);
    act(() => button(el, 'Untick all').click());
    expect(tickedKeys(el)).toEqual([]);
    expect(importButton(el).disabled).toBe(true);
  });

  it('imports only the ticked notes with the type and scope chosen for each', () => {
    const onImport = vi.fn();
    const el = render({ onImport });
    pick(el, 'row-1', 0, 'User');
    pick(el, 'row-1', 1, 'Website');
    act(() => tick(el, 'row-2').click());
    act(() => importButton(el).click());
    expect(onImport).toHaveBeenCalledWith([
      { key: 'row-1', type: 'user', projectId: 'project-website' },
      { key: 'row-5', type: 'feedback', projectId: null },
    ]);
  });

  it('starts each note from the type and project the preview proposed', () => {
    const onImport = vi.fn();
    const el = render({ onImport });
    act(() => importButton(el).click());
    expect(onImport).toHaveBeenCalledWith([
      { key: 'row-1', type: 'feedback', projectId: null },
      { key: 'row-2', type: 'project', projectId: 'project-website' },
      { key: 'row-5', type: 'feedback', projectId: null },
    ]);
  });

  it('resets ticks and choices when a new preview arrives', () => {
    const el = render();
    pick(el, 'row-1', 0, 'User');
    act(() => button(el, 'Untick all').click());
    const next: MemoryImportPreviewDto = {
      rows: [
        memoryImportRow({ key: 'row-1' }),
        memoryImportRow({ key: 'row-9' }),
      ],
      sources: [],
      triageAgents: [],
    };
    const onImport = vi.fn();
    rerender({ preview: next, onImport });
    expect(tickedKeys(el)).toEqual(['row-1', 'row-9']);
    act(() => importButton(el).click());
    expect(onImport).toHaveBeenCalledWith([
      { key: 'row-1', type: 'feedback', projectId: null },
      { key: 'row-9', type: 'feedback', projectId: null },
    ]);
  });

  it('says nothing was found and lists where it looked', () => {
    const el = render({
      preview: {
        rows: [],
        sources: MEMORY_IMPORT_PREVIEW.sources,
        triageAgents: [],
      },
    });
    expect(el.textContent).toContain('Nothing found');
    expect(
      [...el.querySelectorAll('[data-slot="memory-import-sources"] li')].map(
        (item) => item.textContent,
      ),
    ).toEqual([
      'Claude · /Users/me/.claude/projects · 4 notes',
      'Codex · /Users/me/.codex/memories/MEMORY.md · 2 notes',
    ]);
    expect(importButton(el).disabled).toBe(true);
  });

  it('shows a spinner and not Nothing found while loading', () => {
    const el = render({ preview: null, loading: true });
    expect(el.querySelector('[role="status"]')!.textContent).toContain(
      'Looking for notes',
    );
    expect(el.textContent).not.toContain('Nothing found');
  });

  it('shows the error it is given', () => {
    const el = render({ preview: null, error: 'Could not read the folders' });
    expect(el.querySelector('[role="alert"]')!.textContent).toBe(
      'Could not read the folders',
    );
  });

  it('disables Import while importing and closes from Cancel', () => {
    const onOpenChange = vi.fn();
    const el = render({ importing: true, onOpenChange });
    expect(importButton(el).disabled).toBe(true);
    act(() => button(el, 'Cancel').click());
    expect(onOpenChange).toHaveBeenCalledWith(false);
  });

  function triageWith(
    over: Partial<MemoryImportTriage> = {},
  ): MemoryImportTriage {
    return {
      verdicts: new Map(),
      running: false,
      done: 0,
      total: 0,
      error: null,
      start: vi.fn(),
      cancel: vi.fn(),
      ...over,
    };
  }

  function chooseFilter(el: HTMLElement, label: string): void {
    act(() => {
      el.querySelector<HTMLElement>(
        '[data-menu-trigger][aria-label="Show"]',
      )!.click();
    });
    const option = [
      ...document.querySelectorAll<HTMLElement>('[role="option"]'),
    ].find((candidate) => candidate.textContent?.startsWith(label));
    act(() => option!.click());
  }

  function type(el: HTMLElement, text: string): void {
    const input = el.querySelector<HTMLInputElement>(
      'input[aria-label="Search notes"]',
    )!;
    act(() => {
      const setter = Object.getOwnPropertyDescriptor(
        HTMLInputElement.prototype,
        'value',
      )!.set!;
      setter.call(input, text);
      input.dispatchEvent(new Event('input', { bubbles: true }));
    });
  }

  const shownKeys = (el: HTMLElement): string[] =>
    [
      ...el.querySelectorAll<HTMLElement>('[data-slot="memory-import-row"]'),
    ].map((row) => row.getAttribute('data-key')!);

  it('pages a long list, and Tick shown reaches every note the search matched, not just the page', () => {
    const rows = Array.from({ length: IMPORT_PAGE_SIZE + 5 }, (_, n) =>
      memoryImportRow({ key: `k${n}`, title: `Note ${n}` }),
    );
    const onImport = vi.fn();
    const el = render({
      preview: { rows, sources: [], triageAgents: [] },
      onImport,
    });
    expect(shownKeys(el)).toHaveLength(IMPORT_PAGE_SIZE);
    const pager = el.querySelector('[data-slot="memory-import-pager"]')!;
    expect(pager.textContent).toContain(`1–${IMPORT_PAGE_SIZE} of 35`);
    act(() =>
      el.querySelector<HTMLButtonElement>('[aria-label="Next page"]')!.click(),
    );
    expect(shownKeys(el)).toEqual(['k30', 'k31', 'k32', 'k33', 'k34']);

    type(el, 'note 3');
    expect(shownKeys(el)).toEqual(['k3', 'k30', 'k31', 'k32', 'k33', 'k34']);
    expect(el.querySelector('[data-slot="memory-import-pager"]')).toBeNull();
    act(() => button(el, 'Untick shown').click());
    expect(importButton(el).textContent).toBe(`Import ${35 - 6}`);
  });

  it('says so when nothing matches the search', () => {
    const el = render();
    type(el, 'no such note');
    expect(shownKeys(el)).toEqual([]);
    expect(el.textContent).toContain('No notes match.');
  });

  it('filters to the ticked notes and to those it cannot import', () => {
    const el = render();
    chooseFilter(el, 'Ticked');
    expect(shownKeys(el)).toEqual(['row-1', 'row-5', 'row-2']);
    chooseFilter(el, 'Can’t import');
    expect(shownKeys(el)).toEqual(['row-6']);
  });

  it('unticks what the AI left out, shows each verdict, and lets a tick by hand win', () => {
    const triage = triageWith({
      verdicts: new Map([
        ['row-1', { keep: false, reason: 'one task’s status' }],
        ['row-5', { keep: true, reason: 'a lasting convention' }],
        ['row-3', { keep: true, reason: 'durable' }],
      ]),
    });
    const el = render({ triage });

    expect(tickedKeys(el)).toEqual(['row-5', 'row-2']);
    expect(
      rowOf(el, 'row-1').querySelector('[data-slot="memory-import-verdict"]')!
        .textContent,
    ).toBe('AI: skip — one task’s status');
    expect(
      el.querySelector('[data-slot="memory-import-triage-summary"]')!
        .textContent,
    ).toContain('2 worth keeping·1 left out');

    act(() => tick(el, 'row-1').click());
    expect(tickedKeys(el)).toEqual(['row-1', 'row-5', 'row-2']);
    chooseFilter(el, 'AI: skip');
    expect(shownKeys(el)).toEqual(['row-1']);
  });

  it('sorts only the default-ticked notes not judged yet, with the first agent offered', () => {
    const triage = triageWith({
      verdicts: new Map([['row-1', { keep: true, reason: '' }]]),
    });
    const el = render({ triage });
    const sort = button(el, 'Sort 2 notes');
    act(() => sort.click());
    expect(triage.start).toHaveBeenCalledWith('claude', [
      expect.objectContaining({ key: 'row-2' }),
      expect.objectContaining({ key: 'row-5' }),
    ]);
  });

  it('shows progress and Stop while sorting, and the error a sort ended on', () => {
    const triage = triageWith({ running: true, done: 100, total: 300 });
    const el = render({ triage });
    expect(
      el.querySelector('[data-slot="memory-import-triage"] [role="status"]')!
        .textContent,
    ).toBe('100 / 300');
    act(() => button(el, 'Stop').click());
    expect(triage.cancel).toHaveBeenCalled();

    rerender({ triage: triageWith({ error: 'claude did not answer' }) });
    expect(
      el.querySelector('[data-slot="memory-import-triage"] [role="alert"]')!
        .textContent,
    ).toBe('claude did not answer');
  });

  it('offers no AI sort when no agent can do it', () => {
    const el = render({
      triage: triageWith(),
      preview: { ...MEMORY_IMPORT_PREVIEW, triageAgents: [] },
    });
    expect(el.querySelector('[data-slot="memory-import-triage"]')).toBeNull();
  });
});
