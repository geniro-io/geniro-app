function triage(over: Partial<MemoryImportTriage> = {}): MemoryImportTriage {
  return {
    verdicts: new Map(),
    running: false,
    done: 0,
    total: 0,
    error: null,
    start: () => undefined,
    cancel: () => undefined,
    ...over,
  };
}

const meta = {
  title: 'Components/MemoryImportDialog',
  component: MemoryImportDialog,
  decorators: [
    (story) => (
      <AgentIdentityContext.Provider value={PUBLISHED_IDENTITIES}>
        <div className="h-[760px]">{story()}</div>
      </AgentIdentityContext.Provider>
    ),
  ],
  args: {
    open: true,
    onOpenChange: () => undefined,
    preview: MEMORY_IMPORT_PREVIEW,
    loading: false,
    error: null,
    importing: false,
    projects: MEMORY_PROJECTS,
    onImport: () => undefined,
    triage: triage(),
  },
  render: (args) => {
    const [open, setOpen] = useState(true);
    return <MemoryImportDialog {...args} open={open} onOpenChange={setOpen} />;
  },
} satisfies Meta<typeof MemoryImportDialog>;

export default meta;
