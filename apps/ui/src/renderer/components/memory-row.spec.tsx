// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { memoryEntry } from '../__fixtures__/memories';
import type { MemoryEntry } from '../autogenerated';
import { MemoryRow } from './memory-row';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.restoreAllMocks();
});

function render(node: React.ReactNode): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(node);
  });
  return container;
}

const noop = (): void => undefined;

function labels(el: HTMLElement): string[] {
  return [...el.querySelectorAll('button')].map(
    (button) => button.textContent ?? '',
  );
}

function row(
  status: MemoryEntry['status'],
  handlers: Partial<Parameters<typeof MemoryRow>[0]> = {},
): HTMLDivElement {
  return render(
    <MemoryRow
      entry={memoryEntry({ status })}
      projectName={null}
      onEdit={noop}
      onForget={noop}
      onRestore={noop}
      onApprove={noop}
      {...handlers}
    />,
  );
}

function setHeights(scrollHeight: number, clientHeight: number): void {
  vi.spyOn(HTMLElement.prototype, 'scrollHeight', 'get').mockReturnValue(
    scrollHeight,
  );
  vi.spyOn(HTMLElement.prototype, 'clientHeight', 'get').mockReturnValue(
    clientHeight,
  );
}

describe('MemoryRow', () => {
  it('carries the entry id and handle for the pane to find it', () => {
    const el = row('active');
    const block = el.querySelector('[data-slot="memory-row"]')!;
    expect(block.getAttribute('data-memory-id')).toBe('memory-1');
    expect(block.getAttribute('data-memory-handle')).toBe('m1');
  });

  it('offers Edit and Forget on an active note, and Approve only when the pane asks for it', () => {
    expect(labels(row('active', { onApprove: undefined }))).toEqual([
      'Edit',
      'Forget',
    ]);
    expect(labels(row('active'))).toEqual(['Approve', 'Edit', 'Forget']);
  });

  it('offers Approve, Edit and Forget on a pending note and badges it', () => {
    const el = row('pending');
    expect(labels(el)).toEqual(['Approve', 'Edit', 'Forget']);
    expect(el.textContent).toContain('Waiting for review');
  });

  it('offers only Restore on a forgotten note and badges it', () => {
    const el = row('forgotten');
    expect(labels(el)).toEqual(['Restore']);
    expect(el.textContent).toContain('Forgotten');
  });

  it('draws only the actions it was given a callback for', () => {
    expect(
      labels(row('pending', { onApprove: undefined, onEdit: undefined })),
    ).toEqual(['Forget']);
  });

  it('calls the matching callback for each action', () => {
    const onEdit = vi.fn();
    const onApprove = vi.fn();
    const el = row('pending', { onEdit, onApprove });
    const find = (name: string): HTMLButtonElement =>
      [...el.querySelectorAll('button')].find(
        (button) => button.textContent === name,
      )!;
    act(() => find('Approve').click());
    act(() => find('Edit').click());
    expect(onApprove).toHaveBeenCalledTimes(1);
    expect(onEdit).toHaveBeenCalledTimes(1);
  });

  it('asks twice before forgetting', () => {
    const onForget = vi.fn();
    const el = row('active', { onForget });
    const forget = (): HTMLButtonElement =>
      [...el.querySelectorAll('button')].find(
        (button) =>
          button.textContent === 'Forget' || button.textContent === 'Forget?',
      )!;
    act(() => forget().click());
    expect(onForget).not.toHaveBeenCalled();
    expect(forget().textContent).toBe('Forget?');
    act(() => forget().click());
    expect(onForget).toHaveBeenCalledTimes(1);
  });

  it('disables every action while busy', () => {
    const el = row('pending', { busy: true });
    const buttons = [...el.querySelectorAll('button')];
    expect(buttons).toHaveLength(3);
    expect(buttons.every((button) => button.disabled)).toBe(true);
  });

  it('shows no toggle for a body that fits in three lines', () => {
    setHeights(60, 60);
    expect(labels(row('active'))).not.toContain('Show more');
  });

  it('clamps a long body behind a Show more toggle that expands and collapses it', () => {
    setHeights(200, 60);
    const el = row('active', {
      entry: memoryEntry({ body: 'first\n  indented\nthird\nfourth' }),
    });
    const body = el.querySelector('[data-slot="memory-body"]')!;
    const toggle = (): HTMLButtonElement =>
      [...el.querySelectorAll('button')].find((button) =>
        button.textContent?.startsWith('Show'),
      )!;
    expect(body.className).toContain('line-clamp-3');
    expect(body.className).toContain('whitespace-pre-wrap');
    expect(toggle().textContent).toBe('Show more');
    act(() => toggle().click());
    expect(body.className).not.toContain('line-clamp-3');
    expect(toggle().textContent).toBe('Show less');
    act(() => toggle().click());
    expect(body.className).toContain('line-clamp-3');
  });

  it('scrolls itself to the middle when it becomes focused', () => {
    const scrollIntoView = vi.fn();
    Element.prototype.scrollIntoView = scrollIntoView;
    const entry = memoryEntry();
    const props = { entry, projectName: null };
    const el = render(<MemoryRow {...props} />);
    expect(scrollIntoView).not.toHaveBeenCalled();
    act(() => {
      root!.render(<MemoryRow {...props} focused />);
    });
    expect(scrollIntoView).toHaveBeenCalledWith({ block: 'center' });
    expect(
      el
        .querySelector('[data-slot="memory-row"]')!
        .hasAttribute('data-focused'),
    ).toBe(true);
  });
});
