import { cva } from 'class-variance-authority';
import { useEffect, useLayoutEffect, useRef, useState } from 'react';

import type { MemoryEntry } from '../autogenerated';
import { ConfirmButton } from './confirm-button';
import { MemoryStatusBadge } from './memory-status-badge';
import { ProvenanceLine } from './provenance-line';
import { Button } from './ui/button';
import { cn } from './ui/utils';

const clampedVariants = cva('m-0 text-sm whitespace-pre-wrap break-words', {
  variants: {
    clamp: {
      2: 'line-clamp-2',
      3: 'line-clamp-3',
      none: '',
    },
  },
});

export function ClampedBody({
  text,
  lines,
}: {
  text: string;
  lines: 2 | 3;
}): React.JSX.Element {
  const bodyRef = useRef<HTMLParagraphElement | null>(null);
  const [expanded, setExpanded] = useState(false);
  const [overflowing, setOverflowing] = useState(false);

  useLayoutEffect(() => {
    if (expanded) {
      return;
    }
    const measure = (): void => {
      const body = bodyRef.current;
      if (body !== null) {
        setOverflowing(body.scrollHeight > body.clientHeight);
      }
    };
    measure();
    const body = bodyRef.current;
    if (body === null || typeof ResizeObserver === 'undefined') {
      return;
    }
    const observer = new ResizeObserver(measure);
    observer.observe(body);
    return () => observer.disconnect();
  }, [expanded, text]);

  return (
    <div className="flex min-w-0 flex-col gap-1">
      <p
        ref={bodyRef}
        data-slot="memory-body"
        className={clampedVariants({ clamp: expanded ? 'none' : lines })}>
        {text}
      </p>
      {overflowing || expanded ? (
        <button
          type="button"
          aria-expanded={expanded}
          onClick={() => setExpanded((current) => !current)}
          className="self-start rounded-md text-xs font-medium text-muted-foreground hover:text-foreground">
          {expanded ? 'Show less' : 'Show more'}
        </button>
      ) : null}
    </div>
  );
}

export function MemoryRow({
  entry,
  projectName,
  focused = false,
  busy = false,
  onEdit,
  onForget,
  onRestore,
  onApprove,
}: {
  entry: MemoryEntry;
  projectName: string | null;
  focused?: boolean;
  busy?: boolean;
  onEdit?: () => void;
  onForget?: () => void;
  onRestore?: () => void;
  onApprove?: () => void;
}): React.JSX.Element {
  const rowRef = useRef<HTMLDivElement | null>(null);

  useEffect(() => {
    if (focused) {
      rowRef.current?.scrollIntoView({ block: 'center' });
    }
  }, [focused]);

  const isActive = entry.status === 'active';
  const isPending = entry.status === 'pending';
  const isForgotten = entry.status === 'forgotten';

  return (
    <div
      ref={rowRef}
      data-slot="memory-row"
      data-memory-id={entry.id}
      data-memory-handle={entry.handle}
      data-focused={focused ? '' : undefined}
      className={cn(
        'flex min-w-0 flex-col gap-1.5 rounded-md px-2 py-2 transition-shadow',
        focused && 'bg-accent/40 ring-2 ring-ring/60',
      )}>
      <div className="flex min-w-0 flex-wrap items-center gap-2">
        <span className="min-w-0 text-sm font-medium break-words">
          {entry.title}
        </span>
        <MemoryStatusBadge status={entry.status} />
      </div>
      <ClampedBody text={entry.body} lines={3} />
      <ProvenanceLine entry={entry} projectName={projectName} />
      <div className="flex flex-wrap items-center gap-2">
        {(isActive || isPending) && onApprove !== undefined ? (
          <Button type="button" size="sm" disabled={busy} onClick={onApprove}>
            Approve
          </Button>
        ) : null}
        {(isActive || isPending) && onEdit !== undefined ? (
          <Button
            type="button"
            variant="outline"
            size="sm"
            disabled={busy}
            onClick={onEdit}>
            Edit
          </Button>
        ) : null}
        {(isActive || isPending) && onForget !== undefined ? (
          <ConfirmButton
            size="sm"
            confirmLabel="Forget?"
            disabled={busy}
            onConfirm={onForget}>
            Forget
          </ConfirmButton>
        ) : null}
        {isForgotten && onRestore !== undefined ? (
          <Button
            type="button"
            variant="outline"
            size="sm"
            disabled={busy}
            onClick={onRestore}>
            Restore
          </Button>
        ) : null}
      </div>
    </div>
  );
}
