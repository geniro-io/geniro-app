// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type { MemoryEntry } from '../autogenerated';
import { MemoryStatusBadge } from './memory-status-badge';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

function render(status: MemoryEntry['status']): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(<MemoryStatusBadge status={status} />);
  });
  return container;
}

describe('MemoryStatusBadge', () => {
  it('says a pending note is waiting for review', () => {
    expect(render('pending').textContent).toBe('Waiting for review');
  });

  it('says a forgotten note is forgotten', () => {
    expect(render('forgotten').textContent).toBe('Forgotten');
  });

  it('draws nothing for an active note', () => {
    expect(render('active').innerHTML).toBe('');
  });
});
