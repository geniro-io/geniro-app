import type { MemoryEntry } from '../autogenerated';
import { Badge } from './ui/badge';

export function MemoryStatusBadge({
  status,
}: {
  status: MemoryEntry['status'];
}): React.JSX.Element | null {
  switch (status) {
    case 'pending':
      return <Badge variant="warning">Waiting for review</Badge>;
    case 'forgotten':
      return <Badge variant="muted">Forgotten</Badge>;
    case 'active':
      return null;
  }
}
