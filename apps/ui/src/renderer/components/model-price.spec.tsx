// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type { ModelPrice as ModelPriceRates } from '../autogenerated';
import { ModelPrice, modelPriceText, modelPriceTitle } from './model-price';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;

afterEach(() => {
  act(() => root?.unmount());
  root = null;
  document.body.innerHTML = '';
});

function mount(
  price: ModelPriceRates | null | undefined,
  compact = false,
): HTMLElement {
  const container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => root!.render(<ModelPrice price={price} compact={compact} />));
  return container;
}

const SOL: ModelPriceRates = {
  input: 2,
  output: 10,
  cacheRead: 0.1,
  cacheWrite: null,
  tiers: [
    {
      aboveContextTokens: 272_000,
      input: 4,
      output: 15,
      cacheRead: 0.2,
      cacheWrite: null,
    },
  ],
};

describe('ModelPrice', () => {
  it('reads input then output per million tokens, every other rate in its tooltip', () => {
    const tag = mount(SOL).querySelector('[data-slot="model-price"]');

    expect(tag?.textContent).toBe('$2 / $10 per 1M');
    expect(tag?.getAttribute('title')).toBe(
      [
        'List price per 1M tokens (models.dev)',
        'input $2',
        'output $10',
        'cache read $0.10',
        'Prompts over 272k: input $4, output $15, cache read $0.20',
      ].join('\n'),
    );
  });

  it('drops the unit when compact, keeping it in the tooltip', () => {
    const tag = mount(SOL, true).querySelector('[data-slot="model-price"]');

    expect(tag?.textContent).toBe('$2 / $10');
    expect(tag?.getAttribute('title')).toContain('per 1M tokens');
  });

  it('draws nothing for a model nothing priced', () => {
    expect(mount(null).innerHTML).toBe('');
    act(() => root?.unmount());
    expect(mount(undefined).innerHTML).toBe('');
  });

  it('keeps a cache write the catalog states, and the vendor’s digits', () => {
    const haiku: ModelPriceRates = {
      input: 0.1,
      output: 0.5,
      cacheRead: 0.01,
      cacheWrite: 0.125,
      tiers: [],
    };
    expect(modelPriceText(haiku)).toBe('$0.10 / $0.50 per 1M');
    expect(modelPriceTitle(haiku)).toContain('cache write $0.125');
  });
});
