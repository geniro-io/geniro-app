import type { ModelPrice as ModelPriceRates } from '../autogenerated';
import { formatTokens, formatUsdRate } from '../chats/agent-activity';
import { cn } from './ui/utils';

/**
 * `$4 / $20 per 1M` — input, then output, per million tokens; `$4 / $20`
 * compact, where the tooltip carries the unit.
 */
export function modelPriceText(
  price: ModelPriceRates,
  compact = false,
): string {
  const rates = `${formatUsdRate(price.input)} / ${formatUsdRate(price.output)}`;
  return compact ? rates : `${rates} per 1M`;
}

/** Every rate the catalog states, for the tooltip over {@link modelPriceText}. */
export function modelPriceTitle(price: ModelPriceRates): string {
  const lines = [
    'List price per 1M tokens (models.dev)',
    ...rateLines(price),
    ...price.tiers.map(
      (tier) =>
        `Prompts over ${formatTokens(tier.aboveContextTokens)}: ${rateLines(tier).join(', ')}`,
    ),
  ];
  return lines.join('\n');
}

function rateLines(rates: Omit<ModelPriceRates, 'tiers'>): string[] {
  return [
    `input ${formatUsdRate(rates.input)}`,
    `output ${formatUsdRate(rates.output)}`,
    ...(rates.cacheRead === null
      ? []
      : [`cache read ${formatUsdRate(rates.cacheRead)}`]),
    ...(rates.cacheWrite === null
      ? []
      : [`cache write ${formatUsdRate(rates.cacheWrite)}`]),
  ];
}

/**
 * A model's list price beside its name: input and output per million tokens,
 * every other rate in its tooltip. Nothing at all for a model nothing priced —
 * never `$0`. `compact` drops the unit for a row too narrow to keep the model's
 * own name readable beside it.
 */
export function ModelPrice({
  price,
  compact = false,
  className,
}: {
  price: ModelPriceRates | null | undefined;
  compact?: boolean;
  className?: string;
}): React.JSX.Element | null {
  if (price == null) {
    return null;
  }
  return (
    <span
      data-slot="model-price"
      title={modelPriceTitle(price)}
      className={cn(
        'shrink-0 text-[11px] whitespace-nowrap text-muted-foreground tabular-nums',
        className,
      )}>
      {modelPriceText(price, compact)}
    </span>
  );
}
