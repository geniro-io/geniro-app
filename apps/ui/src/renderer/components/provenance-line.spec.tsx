// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { memoryEntry } from '../__fixtures__/memories';
import { PUBLISHED_IDENTITIES } from '../__tests__/agent-identities';
import { AgentIdentityContext } from '../agent-identity';
import type { MemoryEntry } from '../autogenerated';
import { ProvenanceLine } from './provenance-line';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

beforeEach(() => {
  vi.useFakeTimers({ toFake: ['Date'] });
  vi.setSystemTime(new Date('2026-10-20T12:00:00.000Z'));
});

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

function render(
  entry: MemoryEntry,
  projectName: string | null = null,
): HTMLElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <AgentIdentityContext.Provider value={PUBLISHED_IDENTITIES}>
        <ProvenanceLine entry={entry} projectName={projectName} />
      </AgentIdentityContext.Provider>,
    );
  });
  return container.querySelector('[data-slot="provenance-line"]')!;
}

function source(over: Partial<MemoryEntry['source']>): MemoryEntry['source'] {
  return { ...memoryEntry().source, ...over };
}

describe('ProvenanceLine', () => {
  it('reads handle, type, scope, author and change time in that order', () => {
    const line = render(memoryEntry({ updatedAt: '2026-10-20T09:00:00.000Z' }));
    expect(line.textContent).toBe(
      'm1 · feedback · Global · Written by you · changed 3h ago',
    );
  });

  it('names the project the note belongs to, or says it was removed', () => {
    const entry = memoryEntry({ projectId: 'project-billing' });
    expect(render(entry, 'Billing').textContent).toContain(' · Billing · ');
    act(() => root!.unmount());
    container!.remove();
    expect(render(entry, null).textContent).toContain(
      ' · a removed project · ',
    );
  });

  it('names the agent by its published short name and adds the model', () => {
    const line = render(
      memoryEntry({
        source: source({
          actor: 'agent',
          agentKind: 'cursor-agent',
          model: 'gpt-5',
        }),
      }),
    );
    expect(line.textContent).toContain('Saved by Cursor (gpt-5)');
  });

  it('leaves the model out when the agent did not report one', () => {
    const line = render(
      memoryEntry({
        source: source({ actor: 'agent', agentKind: 'claude', model: null }),
      }),
    );
    expect(line.textContent).toContain('Saved by Claude · ');
  });

  it('says an analysis saved it and which agent ran the analysis', () => {
    const line = render(
      memoryEntry({
        source: source({ actor: 'analysis', agentKind: 'codex' }),
      }),
    );
    expect(line.textContent).toContain('Saved by an analysis (Codex)');
  });

  it('shows only the file name of an import and keeps the full path in the title', () => {
    const path = '/Users/me/.cursor/projects/website/memory/deploys.md';
    const line = render(
      memoryEntry({
        source: source({ actor: 'import', importedFrom: path }),
      }),
    );
    const imported = line.querySelector(`[title="${path}"]`)!;
    expect(imported.textContent).toBe('Imported from deploys.md');
  });

  it('pins the change time to an absolute moment in the title', () => {
    const line = render(memoryEntry({ updatedAt: '2026-10-20T09:00:00.000Z' }));
    const changed = [...line.querySelectorAll('span')].find((span) =>
      span.textContent?.startsWith('changed'),
    )!;
    expect(changed.getAttribute('title')).toMatch(/^Oct 20, 2026, \d\d:\d\d$/);
  });

  it('adds approved only once the note has been approved', () => {
    expect(render(memoryEntry()).textContent).not.toContain('approved');
    act(() => root!.unmount());
    container!.remove();
    expect(
      render(memoryEntry({ approvedAt: '2026-10-20T10:00:00.000Z' }))
        .textContent,
    ).toMatch(/ · approved$/);
  });
});
