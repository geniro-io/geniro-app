import { Fragment, useContext } from 'react';

import { AgentIdentityContext, agentShortName } from '../agent-identity';
import type { MemoryEntry } from '../autogenerated';
import { formatDateTime, formatRelativeTime } from '../chats/relative-time';

function basename(path: string): string {
  return path.split(/[\\/]/).findLast((part) => part !== '') ?? path;
}

function changedLabel(iso: string): string {
  const relative = formatRelativeTime(iso);
  return /^\d+[mhd]$/.test(relative)
    ? `changed ${relative} ago`
    : `changed ${relative}`;
}

function Who({ entry }: { entry: MemoryEntry }): React.ReactNode {
  const identities = useContext(AgentIdentityContext);
  const { actor, agentKind, model, importedFrom } = entry.source;
  const agent =
    agentKind === null ? null : agentShortName(identities, agentKind);
  switch (actor) {
    case 'user':
      return 'Written by you';
    case 'agent':
      return `Saved by ${agent ?? 'an agent'}${model === null ? '' : ` (${model})`}`;
    case 'analysis':
      return agent === null
        ? 'Saved by an analysis'
        : `Saved by an analysis (${agent})`;
    case 'import':
      return importedFrom === null ? (
        'Imported'
      ) : (
        <span title={importedFrom}>Imported from {basename(importedFrom)}</span>
      );
  }
}

export function ProvenanceLine({
  entry,
  projectName,
}: {
  entry: MemoryEntry;
  projectName: string | null;
}): React.JSX.Element {
  const scope =
    entry.projectId === null ? 'Global' : (projectName ?? 'a removed project');
  const parts: React.ReactNode[] = [
    entry.handle,
    entry.type,
    scope,
    <Who key="who" entry={entry} />,
    <span key="changed" title={formatDateTime(entry.updatedAt)}>
      {changedLabel(entry.updatedAt)}
    </span>,
  ];
  if (entry.approvedAt !== null) {
    parts.push('approved');
  }
  return (
    <p
      data-slot="provenance-line"
      className="m-0 text-xs text-muted-foreground">
      {parts.map((part, index) => (
        <Fragment key={index}>
          {index === 0 ? null : ' · '}
          {part}
        </Fragment>
      ))}
    </p>
  );
}
