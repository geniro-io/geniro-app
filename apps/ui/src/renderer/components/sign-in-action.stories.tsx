import type { Meta, StoryObj } from '@storybook/react-vite';

import type { ShareSignInSessionDto } from '../autogenerated';
import type { ShareSignInClient } from '../use-share-sign-in';
import { SignInAction } from './sign-in-action';
import { Card } from './ui/card';

function session(
  overrides: Partial<ShareSignInSessionDto>,
): ShareSignInSessionDto {
  return {
    id: 'sign-in-1',
    destinationId: 'company',
    label: 'Google Cloud',
    cli: 'gcloud',
    status: 'waiting',
    lines: ['Your browser has been opened to visit:'],
    url: 'https://accounts.google.com/o/oauth2/auth?response_type=code',
    message: null,
    retried: [],
    ...overrides,
  };
}

/** A daemon whose sign-in stays where `answer` leaves it. */
function client(answer: ShareSignInSessionDto): ShareSignInClient {
  return {
    startShareSignIn: () => Promise.resolve(answer),
    readShareSignIn: () => Promise.resolve(answer),
    cancelShareSignIn: () =>
      Promise.resolve({
        ...answer,
        status: 'cancelled',
        message: 'Sign-in cancelled.',
      }),
  } as unknown as ShareSignInClient;
}

const meta = {
  title: 'Components/SignInAction',
  component: SignInAction,
  args: {
    api: client(session({})),
    destinationId: 'company',
    label: 'Google Cloud',
    className: 'w-full',
  },
  decorators: [
    (story) => (
      <Card className="w-80 gap-2 p-3">
        <p className="m-0 text-xs text-muted-foreground">
          Sign-in required (gcloud)
        </p>
        {story()}
      </Card>
    ),
  ],
} satisfies Meta<typeof SignInAction>;

export default meta;
type Story = StoryObj<typeof meta>;

/** Press it: the sign-in runs with Cancel and the link as a fallback. */
export const Playground: Story = {};

/** Press it: the CLI refuses to start. */
export const Fails: Story = {
  args: {
    api: client(
      session({
        status: 'failed',
        url: null,
        message:
          'gcloud could not be started (spawn gcloud ENOENT) — is it installed?',
      }),
    ),
  },
};

export const Aws: Story = {
  args: {
    label: 'AWS',
    api: client(
      session({
        label: 'AWS',
        cli: 'aws',
        lines: ['Then enter the code:', 'WDDD-HRQV'],
        url: 'https://device.sso.eu-west-1.amazonaws.com/',
      }),
    ),
  },
};
