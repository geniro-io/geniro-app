import { useEffect, useRef } from 'react';

import type { ShareSignInSessionDto } from '../autogenerated';
import {
  isShareSignInOver,
  type ShareSignInClient,
  useShareSignIn,
} from '../use-share-sign-in';
import { CliLoginProgress } from './cli-login-progress';
import { ErrorText } from './error-text';
import { Button } from './ui/button';
import { cn } from './ui/utils';

/**
 * "Sign in to <label>" for a share destination whose CLI is signed out, and
 * the sign-in it starts, drawn in place: the CLI's own browser round-trip in
 * {@link CliLoginProgress} with Cancel, then how it ended. The daemon runs the
 * login and, once it succeeds, shares what was waiting — nothing here
 * retries, and a cancelled or failed sign-in leaves the share unshared.
 *
 * Focus moves to Cancel when the sign-in starts and back to the button when
 * its ending is dismissed.
 */
export function SignInAction({
  api,
  destinationId,
  label,
  onSettled,
  variant = 'inline',
  compact = false,
  className,
}: {
  api: ShareSignInClient | null;
  destinationId: string;
  /** What the button names: "Sign in to Google Cloud". */
  label: string;
  onSettled?: (session: ShareSignInSessionDto) => void;
  variant?: 'band' | 'inline';
  /**
   * One text line tall — the button and the sign-in's progress alike — so it
   * sits in a one-line strip (the warning under an artifact card) without
   * making the row taller than its message.
   */
  compact?: boolean;
  /** For the button, e.g. `w-full` in a narrow panel. */
  className?: string;
}): React.JSX.Element {
  const signIn = useShareSignIn(api, onSettled);
  const buttonRef = useRef<HTMLButtonElement | null>(null);
  const cancelRef = useRef<HTMLButtonElement | null>(null);
  const session =
    signIn.session?.destinationId === destinationId ? signIn.session : null;
  const sessionId = session?.id ?? null;
  const shown = useRef<string | null>(null);

  useEffect(() => {
    if (sessionId !== null) {
      shown.current = sessionId;
      cancelRef.current?.focus();
    } else if (shown.current !== null) {
      shown.current = null;
      buttonRef.current?.focus();
    }
  }, [sessionId]);

  if (session !== null) {
    const running = !isShareSignInOver(session.status);
    return (
      <div
        role="status"
        aria-live="polite"
        data-slot="sign-in-action"
        // Takes back the inline progress's own vertical padding.
        className={cn(compact && '-my-1.5')}>
        <CliLoginProgress
          session={{
            status: session.status,
            url: session.url,
            // While it runs, the CLI's last line (a device code); once over,
            // how it ended.
            message: running ? (session.lines.at(-1) ?? null) : session.message,
          }}
          scope="share"
          variant={variant}
          error={signIn.error}
          cancelRef={cancelRef}
          onCancel={signIn.cancel}
          onDismiss={signIn.dismiss}
          onSubmitCode={() => undefined}
        />
      </div>
    );
  }
  return (
    // The error sits beside the button, wrapping under it only where the row
    // has no room (a full-width button in a narrow panel).
    <div
      className="flex min-w-0 flex-wrap items-center gap-x-2 gap-y-1"
      data-slot="sign-in-action">
      <Button
        ref={buttonRef}
        type="button"
        size="sm"
        className={cn(compact && '-my-0.5 h-5 px-2 text-xs', className)}
        disabled={api === null || signIn.starting}
        onClick={() => signIn.start(destinationId)}>
        {signIn.starting ? 'Starting sign-in…' : `Sign in to ${label}`}
      </Button>
      {signIn.error !== null && (
        <ErrorText className="min-w-0 truncate text-xs" title={signIn.error}>
          {signIn.error}
        </ErrorText>
      )}
    </div>
  );
}
