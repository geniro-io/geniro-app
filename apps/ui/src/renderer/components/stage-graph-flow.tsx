const PAD_X = 11;
const ICON_SIZE = 12;
const ICON_GAP = 4;
const BORDER = 1;
const MIN_PILL_WIDTH = 44;
const MAX_TITLE_PX = 200;
const PRO_OPTIONS = { hideAttribution: true };
const VIEWPORT = { x: 0, y: 0, zoom: 1 };

type PillTone =
  | 'plain'
  | 'selected'
  | 'error'
  | 'selectedError'
  | Exclude<StageStatus, 'pending'>;

type Highlight = 'none' | 'on' | 'dim';

type EdgeTone = 'plain' | 'walked' | 'untaken' | 'active' | 'loop';

const pillVariants = cva(
  'flex h-full w-full items-center justify-center gap-1 rounded-full border text-xs transition-[background-color,border-color,box-shadow,opacity] duration-150 outline-none',
  {
    variants: {
      tone: {
        plain: 'border-border-strong/50 bg-muted text-foreground',
        selected: 'border-primary bg-primary/12 font-semibold text-primary',
        error: 'border-destructive bg-muted text-foreground',
        selectedError:
          'border-destructive bg-primary/12 font-semibold text-primary',
        done: 'border-success/60 bg-success/12 text-foreground',
        current: 'border-primary bg-primary/15 font-semibold text-foreground',
        skipped: 'border-border-strong/50 bg-muted text-muted-foreground',
        not_taken:
          'border-dashed border-border-strong bg-transparent text-muted-foreground',
      } satisfies Record<PillTone, string>,
      ring: {
        none: '',
        current: 'ring-[3px] ring-primary/20',
        failed: 'ring-[3px] ring-destructive/25',
      },
      highlight: { none: '', on: '', dim: 'opacity-35' },
      untaken: { true: 'opacity-60', false: '' },
      interactive: {
        true: 'cursor-pointer focus-visible:ring-[3px] focus-visible:ring-ring/60',
        false: '',
      },
      hoverable: { true: 'hover:border-primary/60', false: '' },
    },
    compoundVariants: [
      { untaken: true, highlight: 'dim', class: 'opacity-25' },
    ],
  },
);

const pillIconVariants = cva('size-3 shrink-0', {
  variants: {
    tone: {
      done: 'text-success',
      current: 'text-primary',
      skipped: 'text-muted-foreground',
      not_taken: 'text-muted-foreground',
      error: 'text-destructive',
    },
  },
});

const edgeVariants = cva('fill-none transition-[opacity,stroke] duration-150', {
  variants: {
    tone: {
      plain: 'stroke-border-strong/70',
      walked: 'stroke-success/70',
      untaken: 'stroke-border-strong/40',
      active: 'stroke-primary',
      loop: 'stroke-destructive',
    } satisfies Record<EdgeTone, string>,
    highlight: { none: '', on: '', dim: 'opacity-20' },
  },
});

const FINISHED: ReadonlySet<StageStatus | undefined> = new Set([
  'done',
  'skipped',
]);

const BOLD_TONES: ReadonlySet<PillTone> = new Set([
  'selected',
  'selectedError',
  'current',
]);

interface Pill {
  stage: StageGraphStage;
  tone: PillTone;
  icon: 'error' | Exclude<StageStatus, 'pending'> | null;
  failed: boolean;
}

interface StagePillData extends Record<string, unknown> {
  pill: Pill;
  column: number;
  cut: boolean;
  selected: boolean;
  highlight: Highlight;
}

interface StageEdgeData extends Record<string, unknown> {
  route: readonly Point[];
  tone: EdgeTone;
  highlight: Highlight;
  loop: boolean;
}

type StageFlowNode = Node<StagePillData, 'stage'>;
type StageFlowEdge = Edge<StageEdgeData, 'stage'>;

interface StageGraphActions {
  select: ((stageId: string) => void) | null;
  hover: (stageId: string | null) => void;
}

const StageGraphActionsContext = createContext<StageGraphActions>({
  select: null,
  hover: () => undefined,
});

function pillTone(
  status: StageStatus | undefined,
  selected: boolean,
  failed: boolean,
): PillTone {
  if (failed) {
    return selected ? 'selectedError' : 'error';
  }
  if (selected) {
    return 'selected';
  }
  return status === undefined || status === 'pending' ? 'plain' : status;
}

function pillLabel(pill: Pill): string {
  const status =
    pill.stage.status === undefined
      ? ''
      : `, ${STAGE_STATUS_VIEW[pill.stage.status].word}`;
  return `${pill.stage.title}${status}${pill.failed ? ', has an error' : ''}`;
}

function StagePill({ data }: NodeProps<StageFlowNode>): React.JSX.Element {
  const { select, hover } = useContext(StageGraphActionsContext);
  const { pill, selected, highlight, column, cut } = data;
  const { stage, tone, icon, failed } = pill;
  const interactive = select !== null;
  const Icon =
    icon === null
      ? null
      : icon === 'error'
        ? TriangleAlert
        : STAGE_STATUS_VIEW[icon].Icon;
  return (
    <>
      <Handle
        id="in"
        type="target"
        position={Position.Left}
        isConnectable={false}
        style={{ opacity: 0 }}
      />
      <div
        data-slot="stage-pill"
        data-stage-id={stage.id}
        data-column={column}
        data-status={stage.status}
        data-error={failed || undefined}
        data-highlight={highlight}
        data-cut={cut || undefined}
        data-ring={
          stage.status === 'current' || failed
            ? failed
              ? 'failed'
              : 'current'
            : undefined
        }
        role={interactive ? 'button' : 'img'}
        aria-label={pillLabel(pill)}
        title={stage.title}
        aria-current={selected ? 'true' : undefined}
        tabIndex={interactive ? 0 : undefined}
        className={pillVariants({
          tone,
          ring: failed
            ? 'failed'
            : stage.status === 'current'
              ? 'current'
              : 'none',
          highlight,
          untaken: stage.status === 'not_taken',
          interactive,
          hoverable: interactive && !selected,
        })}
        style={{ paddingInline: PAD_X }}
        {...(interactive
          ? {
              onKeyDown: (event: React.KeyboardEvent) => {
                if (event.key === 'Enter' || event.key === ' ') {
                  event.preventDefault();
                  select(stage.id);
                }
              },
              onFocus: () => hover(stage.id),
              onBlur: () => hover(null),
            }
          : {})}>
        {Icon === null ? null : (
          <Icon
            aria-hidden="true"
            data-slot="stage-pill-icon"
            data-icon={icon}
            strokeWidth={2.25}
            className={pillIconVariants({ tone: icon ?? undefined })}
          />
        )}
        <span data-slot="stage-pill-title" className="min-w-0 truncate">
          {stage.title}
        </span>
      </div>
      <Handle
        id="out"
        type="source"
        position={Position.Right}
        isConnectable={false}
        style={{ opacity: 0 }}
      />
    </>
  );
}

function StageEdge({ id, data }: EdgeProps<StageFlowEdge>): React.JSX.Element {
  const { route, tone, highlight, loop } = data!;
  const className = edgeVariants({ tone, highlight });
  const width = highlight === 'on' ? 1.75 : 1.25;
  return (
    <>
      <path
        aria-hidden="true"
        data-slot="stage-edge"
        data-edge={id}
        data-tone={tone}
        data-highlight={highlight}
        data-loop={loop || undefined}
        d={roundedPath(route)}
        className={className}
        strokeWidth={width}
        strokeDasharray={loop ? '4 3' : undefined}
        strokeLinecap="round"
      />
      <path
        aria-hidden="true"
        data-slot="stage-edge-arrow"
        d={arrowHeadPath(route)}
        className={className}
        strokeWidth={width}
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </>
  );
}

const NODE_TYPES = { stage: StagePill };
const EDGE_TYPES = { stage: StageEdge };

function handlesFor(width: number): NodeHandle[] {
  return [
    {
      id: 'in',
      type: 'target',
      position: Position.Left,
      x: 0,
      y: PILL_HEIGHT / 2,
    },
    {
      id: 'out',
      type: 'source',
      position: Position.Right,
      x: width,
      y: PILL_HEIGHT / 2,
    },
  ];
}

function naturalWidth(pill: Pill, textWidth: number): number {
  const chrome =
    PAD_X * 2 + BORDER * 2 + (pill.icon === null ? 0 : ICON_SIZE + ICON_GAP);
  return Math.max(
    MIN_PILL_WIDTH,
    Math.ceil(Math.min(textWidth, MAX_TITLE_PX) + chrome + 1),
  );
}

/** Lazy behind `StageGraph`: `@xyflow/react` and `elkjs` stay out of the chat bundle. */
export default function StageGraphFlow<S extends StageGraphStage>(
  props: StageGraphProps<S>,
): React.JSX.Element {
  return (
    <ReactFlowProvider>
      <StageGraphCanvas {...props} />
    </ReactFlowProvider>
  );
}

function StageGraphCanvas<S extends StageGraphStage>({
  stages,
  selectedId = null,
  errorIds,
  onSelect,
  fitWidth,
  className,
}: StageGraphProps<S>): React.JSX.Element {
  const [hovered, setHovered] = useState<string | null>(null);
  const [measure, measured] = useElementWidth();
  const room = Math.round(fitWidth ?? measured);
  const probe = useRef<HTMLDivElement>(null);
  const [drawn, setDrawn] = useState<{
    geometry: StageGraphGeometry;
    overlong: ReadonlySet<string>;
  } | null>(null);
  const [failed, setFailed] = useState(false);

  const layout = stageLayout(stages);
  const pills: Pill[] = layout.columns.flat().map((stage) => {
    const failing = errorIds?.has(stage.id) ?? false;
    const tone = pillTone(stage.status, stage.id === selectedId, failing);
    return {
      stage,
      tone,
      failed: failing,
      icon: failing
        ? 'error'
        : stage.status === undefined || stage.status === 'pending'
          ? null
          : stage.status,
    };
  });
  const known = new Set(pills.map((pill) => pill.stage.id));
  const links: StageLink[] = pills.flatMap(({ stage }) =>
    [...new Set(stage.next ?? [])]
      .filter((to) => known.has(to))
      .map((to) => ({ key: stageEdgeKey(stage.id, to), from: stage.id, to })),
  );
  const signature = JSON.stringify([
    pills.map((pill) => [
      pill.stage.id,
      pill.stage.title,
      BOLD_TONES.has(pill.tone),
      pill.icon !== null,
    ]),
    links.map((link) => link.key),
    room,
  ]);

  const relayout = useLatestCallback((): (() => void) => {
    const spans = new Map(
      [
        ...(probe.current?.querySelectorAll<HTMLElement>('[data-measure-id]') ??
          []),
      ].map((span) => [
        span.dataset.measureId,
        span.getBoundingClientRect().width,
      ]),
    );
    const overlong = new Set<string>();
    const boxes = pills.map((pill) => {
      const measuredText = spans.get(pill.stage.id) ?? 0;
      const text =
        measuredText > 0
          ? measuredText
          : estimateTextWidth(pill.stage.title, BOLD_TONES.has(pill.tone));
      if (text > MAX_TITLE_PX) {
        overlong.add(pill.stage.id);
      }
      return { id: pill.stage.id, width: naturalWidth(pill, text) };
    });
    let cancelled = false;
    layoutStageGraph(boxes, links, room).then(
      (next) => {
        if (!cancelled) {
          setDrawn({ geometry: next, overlong });
          setFailed(false);
        }
      },
      (error: unknown) => {
        if (!cancelled) {
          console.error('Could not lay out the stage graph', error);
          setFailed(true);
        }
      },
    );
    return () => {
      cancelled = true;
    };
  }, []);
  useLayoutEffect(() => relayout(), [signature, relayout]);

  const hover = useLatestCallback((stageId: string | null) => {
    setHovered(stageId);
  }, []);
  const select = useLatestCallback((stageId: string) => {
    onSelect?.(stageId);
  }, []);
  const interactive = onSelect !== undefined;

  const lit = new Set<string>();
  if (hovered !== null) {
    lit.add(hovered);
    for (const link of links) {
      if (link.from === hovered || link.to === hovered) {
        lit.add(link.from);
        lit.add(link.to);
      }
    }
  }
  const statusOf = new Map(pills.map((pill) => [pill.stage.id, pill.stage]));
  const edgeTone = (link: StageLink, highlight: Highlight): EdgeTone => {
    if (layout.loopEdges.has(link.key)) {
      return 'loop';
    }
    if (highlight === 'on') {
      return 'active';
    }
    const from = statusOf.get(link.from)?.status;
    const to = statusOf.get(link.to)?.status;
    if (from === 'not_taken' || to === 'not_taken') {
      return 'untaken';
    }
    return FINISHED.has(from) && (to === 'current' || FINISHED.has(to))
      ? 'walked'
      : 'plain';
  };

  const nodes: StageFlowNode[] =
    drawn === null
      ? []
      : pills.flatMap((pill) => {
          const box = drawn.geometry.boxes.get(pill.stage.id);
          if (box === undefined) {
            return [];
          }
          return [
            {
              id: pill.stage.id,
              type: 'stage',
              position: { x: box.x, y: box.y },
              width: box.width,
              height: PILL_HEIGHT,
              handles: handlesFor(box.width),
              draggable: false,
              selectable: false,
              focusable: false,
              data: {
                pill,
                column: box.column,
                cut: box.cut || drawn.overlong.has(pill.stage.id),
                selected: pill.stage.id === selectedId,
                highlight:
                  hovered === null
                    ? 'none'
                    : lit.has(pill.stage.id)
                      ? 'on'
                      : 'dim',
              },
            },
          ];
        });
  const edges: StageFlowEdge[] =
    drawn === null
      ? []
      : links.flatMap((link) => {
          const route = drawn.geometry.routes.get(link.key);
          if (route === undefined) {
            return [];
          }
          const highlight: Highlight =
            hovered === null
              ? 'none'
              : link.from === hovered || link.to === hovered
                ? 'on'
                : 'dim';
          return [
            {
              id: link.key,
              source: link.from,
              target: link.to,
              sourceHandle: 'out',
              targetHandle: 'in',
              type: 'stage',
              focusable: false,
              selectable: false,
              data: {
                route,
                tone: edgeTone(link, highlight),
                highlight,
                loop: layout.loopEdges.has(link.key),
              },
            },
          ];
        });

  return (
    <div
      data-slot="stage-graph"
      className={cn('relative max-w-full overflow-x-auto', className)}>
      <div
        ref={probe}
        aria-hidden="true"
        className="pointer-events-none invisible absolute top-0 left-0 h-0 overflow-hidden whitespace-nowrap">
        {pills.map((pill) => (
          <span
            key={pill.stage.id}
            data-measure-id={pill.stage.id}
            className={cn(
              'text-xs',
              BOLD_TONES.has(pill.tone) && 'font-semibold',
            )}>
            {pill.stage.title}
          </span>
        ))}
      </div>
      <div ref={measure} data-slot="stage-graph-room" className="w-full">
        {failed ? (
          <p className="text-xs text-muted-foreground">
            Couldn’t draw the stage graph
          </p>
        ) : drawn === null ? (
          <StageGraphPending />
        ) : (
          <StageGraphActionsContext.Provider
            value={{ select: interactive ? select : null, hover }}>
            <div
              role="group"
              aria-label={graphLabel(layout)}
              data-slot="stage-graph-canvas"
              className="mx-auto"
              style={{
                width: drawn.geometry.width,
                height: drawn.geometry.height,
              }}>
              <ReactFlow
                nodes={nodes}
                edges={edges}
                nodeTypes={NODE_TYPES}
                edgeTypes={EDGE_TYPES}
                defaultViewport={VIEWPORT}
                onNodeMouseEnter={(_, node) => hover(node.id)}
                onNodeMouseLeave={() => hover(null)}
                {...(interactive
                  ? { onNodeClick: (_, node: StageFlowNode) => select(node.id) }
                  : {})}
                nodesDraggable={false}
                nodesConnectable={false}
                nodesFocusable={false}
                edgesFocusable={false}
                elementsSelectable={false}
                disableKeyboardA11y
                deleteKeyCode={null}
                selectionKeyCode={null}
                multiSelectionKeyCode={null}
                panActivationKeyCode={null}
                zoomActivationKeyCode={null}
                panOnDrag={false}
                panOnScroll={false}
                zoomOnScroll={false}
                zoomOnPinch={false}
                zoomOnDoubleClick={false}
                preventScrolling={false}
                proOptions={PRO_OPTIONS}
              />
            </div>
          </StageGraphActionsContext.Provider>
        )}
      </div>
    </div>
  );
}
