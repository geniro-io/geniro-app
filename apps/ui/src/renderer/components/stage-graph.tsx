export interface StageGraphStage {
  id: string;
  title: string;
  next?: readonly string[] | undefined;
  status?: StageStatus | undefined;
}

export const PILL_HEIGHT = 24;

export function stageEdgeKey(from: string, to: string): string {
  return `${from}>${to}`;
}

export interface StageLayout<S extends StageGraphStage> {
  columns: S[][];
  backEdges: ReadonlySet<string>;
  loopEdges: ReadonlySet<string>;
}

export function stageLayout<S extends StageGraphStage>(
  stages: readonly S[],
): StageLayout<S> {
  const unique = stages.filter(
    (stage, index) => stages.findIndex((s) => s.id === stage.id) === index,
  );
  const indexOf = new Map(unique.map((stage, index) => [stage.id, index]));
  const nextsOf = unique.map((stage) =>
    [...new Set(stage.next ?? [])].flatMap((id) => {
      const index = indexOf.get(id);
      return index === undefined ? [] : [index];
    }),
  );
  const edgeKey = (from: number, to: number): string =>
    stageEdgeKey(unique[from]!.id, unique[to]!.id);

  const reaches = (from: number, to: number): boolean => {
    const seen = new Set([from]);
    const queue = [from];
    for (let head = 0; head < queue.length; head += 1) {
      const current = queue[head]!;
      if (current === to) {
        return true;
      }
      for (const next of nextsOf[current]!) {
        if (!seen.has(next)) {
          seen.add(next);
          queue.push(next);
        }
      }
    }
    return false;
  };
  const loopEdges = new Set<string>();
  nextsOf.forEach((nexts, from) => {
    for (const to of nexts) {
      if (reaches(to, from)) {
        loopEdges.add(edgeKey(from, to));
      }
    }
  });

  const named = new Set(nextsOf.flat());
  const order = [...unique.keys()].sort(
    (a, b) => Number(named.has(a)) - Number(named.has(b)),
  );
  const backEdges = new Set<string>();
  const state = unique.map(() => 'new' as 'new' | 'walking' | 'done');
  const walk = (from: number): void => {
    state[from] = 'walking';
    for (const to of nextsOf[from]!) {
      if (state[to] === 'walking') {
        backEdges.add(edgeKey(from, to));
      } else if (state[to] === 'new') {
        walk(to);
      }
    }
    state[from] = 'done';
  };
  for (const index of order) {
    if (state[index] === 'new') {
      walk(index);
    }
  }

  const forward = nextsOf.map((nexts, from) =>
    nexts.filter((to) => !backEdges.has(edgeKey(from, to))),
  );
  const waiting = unique.map(() => 0);
  for (const nexts of forward) {
    for (const to of nexts) {
      waiting[to] = waiting[to]! + 1;
    }
  }
  const depth = unique.map(() => 0);
  const queue = waiting.flatMap((count, index) => (count === 0 ? [index] : []));
  for (let head = 0; head < queue.length; head += 1) {
    const current = queue[head]!;
    for (const to of forward[current]!) {
      depth[to] = Math.max(depth[to]!, depth[current]! + 1);
      waiting[to] = waiting[to]! - 1;
      if (waiting[to] === 0) {
        queue.push(to);
      }
    }
  }
  const columns: S[][] = [];
  unique.forEach((stage, index) => {
    (columns[depth[index]!] ??= []).push(stage);
  });
  return { columns, backEdges, loopEdges };
}

export function useElementWidth(): [
  (el: HTMLDivElement | null) => void,
  number,
] {
  const [element, setElement] = useState<HTMLDivElement | null>(null);
  const [width, setWidth] = useState(0);
  useLayoutEffect(() => {
    if (element === null) {
      return;
    }
    setWidth(element.clientWidth);
    if (typeof ResizeObserver === 'undefined') {
      return;
    }
    const observer = new ResizeObserver((entries) => {
      const entry = entries.at(-1);
      if (entry !== undefined) {
        setWidth(entry.contentRect.width);
      }
    });
    observer.observe(element);
    return () => observer.disconnect();
  }, [element]);
  return [setElement, width];
}

export function graphLabel<S extends StageGraphStage>(
  layout: StageLayout<S>,
): string {
  if (layout.loopEdges.size > 0) {
    return `Stages, which loop back on themselves: ${layout.columns
      .flat()
      .map((stage) => stage.title)
      .join(', ')}`;
  }
  return `Stages: ${layout.columns
    .map((column) => column.map((stage) => stage.title).join(' or '))
    .join(' → ')}`;
}

export interface StageGraphProps<S extends StageGraphStage> {
  stages: readonly S[];
  selectedId?: string | null;
  errorIds?: ReadonlySet<string>;
  onSelect?: (stageId: string) => void;
  /**
   * The room to fit into, for a container that sizes itself to the graph:
   * measuring such a container would only ever read the graph's own width.
   */
  fitWidth?: number;
  className?: string;
}

export function StageGraphPending({
  className,
}: {
  className?: string;
}): React.JSX.Element {
  return (
    <span
      aria-hidden="true"
      data-slot="stage-graph-pending"
      className={cn(
        'skeleton-pulse mx-auto block w-40 max-w-full rounded-md bg-muted-foreground/10',
        className,
      )}
      style={{ height: PILL_HEIGHT + 10 }}
    />
  );
}

const StageGraphFlow = lazy(() => import('./stage-graph-flow'));

export function StageGraph<S extends StageGraphStage>(
  props: StageGraphProps<S>,
): React.JSX.Element | null {
  if (props.stages.length === 0) {
    return null;
  }
  return (
    <Suspense fallback={<StageGraphPending className={props.className} />}>
      <StageGraphFlow {...props} />
    </Suspense>
  );
}
