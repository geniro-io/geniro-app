export const STAGE_STATUS_VIEW: Record<
  StageStatus,
  { word: string; Icon: LucideIcon }
> = {
  done: { word: 'done', Icon: CircleCheck },
  current: { word: 'current', Icon: CircleDot },
  pending: { word: 'pending', Icon: Circle },
  skipped: { word: 'skipped', Icon: SkipForward },
  not_taken: { word: 'not taken', Icon: CircleSlash },
};

export interface StageGraphStage {
  id: string;
  title: string;
  next?: readonly string[] | undefined;
  status?: StageStatus | undefined;
}

export function stageEdgeKey(from: string, to: string): string {
  return `${from}>${to}`;
}

export interface StageLayout<S extends StageGraphStage> {
  columns: S[][];
  backEdges: ReadonlySet<string>;
  loopEdges: ReadonlySet<string>;
}

export function stageLayout<S extends StageGraphStage>(
  stages: readonly S[],
): StageLayout<S> {
  const unique = stages.filter(
    (stage, index) => stages.findIndex((s) => s.id === stage.id) === index,
  );
  const indexOf = new Map(unique.map((stage, index) => [stage.id, index]));
  const nextsOf = unique.map((stage) =>
    [...new Set(stage.next ?? [])].flatMap((id) => {
      const index = indexOf.get(id);
      return index === undefined ? [] : [index];
    }),
  );
  const edgeKey = (from: number, to: number): string =>
    stageEdgeKey(unique[from]!.id, unique[to]!.id);

  const reaches = (from: number, to: number): boolean => {
    const seen = new Set([from]);
    const queue = [from];
    for (let head = 0; head < queue.length; head += 1) {
      const current = queue[head]!;
      if (current === to) {
        return true;
      }
      for (const next of nextsOf[current]!) {
        if (!seen.has(next)) {
          seen.add(next);
          queue.push(next);
        }
      }
    }
    return false;
  };
  const loopEdges = new Set<string>();
  nextsOf.forEach((nexts, from) => {
    for (const to of nexts) {
      if (reaches(to, from)) {
        loopEdges.add(edgeKey(from, to));
      }
    }
  });

  const named = new Set(nextsOf.flat());
  const order = [...unique.keys()].sort(
    (a, b) => Number(named.has(a)) - Number(named.has(b)),
  );
  const backEdges = new Set<string>();
  const state = unique.map(() => 'new' as 'new' | 'walking' | 'done');
  const walk = (from: number): void => {
    state[from] = 'walking';
    for (const to of nextsOf[from]!) {
      if (state[to] === 'walking') {
        backEdges.add(edgeKey(from, to));
      } else if (state[to] === 'new') {
        walk(to);
      }
    }
    state[from] = 'done';
  };
  for (const index of order) {
    if (state[index] === 'new') {
      walk(index);
    }
  }

  const forward = nextsOf.map((nexts, from) =>
    nexts.filter((to) => !backEdges.has(edgeKey(from, to))),
  );
  const waiting = unique.map(() => 0);
  for (const nexts of forward) {
    for (const to of nexts) {
      waiting[to] = waiting[to]! + 1;
    }
  }
  const depth = unique.map(() => 0);
  const queue = waiting.flatMap((count, index) => (count === 0 ? [index] : []));
  for (let head = 0; head < queue.length; head += 1) {
    const current = queue[head]!;
    for (const to of forward[current]!) {
      depth[to] = Math.max(depth[to]!, depth[current]! + 1);
      waiting[to] = waiting[to]! - 1;
      if (waiting[to] === 0) {
        queue.push(to);
      }
    }
  }
  const columns: S[][] = [];
  unique.forEach((stage, index) => {
    (columns[depth[index]!] ??= []).push(stage);
  });
  return { columns, backEdges, loopEdges };
}

const PILL_HEIGHT = 24;
const PAD_X = 11;
const ICON_SIZE = 12;
const ICON_GAP = 4;
const MIN_PILL_WIDTH = 44;
const COLUMN_GAP = 30;
const ROW_GAP = 10;
const MARGIN = 5;
const LOOP_ROOM = 16;
const MAX_TITLE = 26;
export const STAGE_GRAPH_MIN_SCALE = 0.65;

function textWidth(text: string, bold: boolean): number {
  let width = 0;
  for (const char of text) {
    if (/[iljtf.,:;'|!() ]/.test(char)) {
      width += 3.6;
    } else if (/[mwMW]/.test(char)) {
      width += 10;
    } else if (/[A-Z0-9]/.test(char)) {
      width += 7.8;
    } else {
      width += 6.6;
    }
  }
  return width * (bold ? 1.06 : 1);
}

function shortTitle(title: string): string {
  return title.length > MAX_TITLE
    ? `${title.slice(0, MAX_TITLE - 1).trimEnd()}…`
    : title;
}

type PillTone =
  | 'plain'
  | 'selected'
  | 'error'
  | 'selectedError'
  | Exclude<StageStatus, 'pending'>;

const pillVariants = cva('transition-[fill,stroke] duration-150', {
  variants: {
    tone: {
      plain: 'fill-muted stroke-border-strong/50',
      selected: 'fill-primary/12 stroke-primary',
      error: 'fill-muted stroke-destructive',
      selectedError: 'fill-primary/12 stroke-destructive',
      done: 'fill-success/12 stroke-success/60',
      current: 'fill-primary/15 stroke-primary',
      skipped: 'fill-muted stroke-border-strong/50',
      not_taken: 'fill-transparent stroke-border-strong',
    } satisfies Record<PillTone, string>,
  },
});

const pillTextVariants = cva('text-xs', {
  variants: {
    tone: {
      plain: 'fill-foreground',
      selected: 'fill-primary font-semibold',
      error: 'fill-foreground',
      selectedError: 'fill-primary font-semibold',
      done: 'fill-foreground',
      current: 'fill-foreground font-semibold',
      skipped: 'fill-muted-foreground',
      not_taken: 'fill-muted-foreground',
    } satisfies Record<PillTone, string>,
  },
});

const pillIconVariants = cva('', {
  variants: {
    tone: {
      done: 'text-success',
      current: 'text-primary',
      skipped: 'text-muted-foreground',
      not_taken: 'text-muted-foreground',
      error: 'text-destructive',
    },
  },
});

type Highlight = 'none' | 'on' | 'dim';

const pillGroupVariants = cva('outline-none transition-opacity duration-150', {
  variants: {
    highlight: { none: '', on: '', dim: 'opacity-35' },
    untaken: { true: 'opacity-60', false: '' },
    interactive: { true: 'group/pill cursor-pointer', false: '' },
  },
  compoundVariants: [{ untaken: true, highlight: 'dim', class: 'opacity-25' }],
});

const edgeVariants = cva('fill-none transition-[opacity,stroke] duration-150', {
  variants: {
    tone: {
      plain: 'stroke-border-strong/70',
      walked: 'stroke-success/70',
      untaken: 'stroke-border-strong/40',
      active: 'stroke-primary',
      loop: 'stroke-destructive',
    },
    highlight: { none: '', on: '', dim: 'opacity-20' },
  },
});

interface Placed<S> {
  stage: S;
  column: number;
  x: number;
  y: number;
  width: number;
  title: string;
  tone: PillTone;
  icon: 'error' | Exclude<StageStatus, 'pending'> | null;
}

interface Edge {
  key: string;
  from: string;
  to: string;
  d: string;
  loop: boolean;
}

const FINISHED: ReadonlySet<StageStatus | undefined> = new Set([
  'done',
  'skipped',
]);

function pillTone(
  status: StageStatus | undefined,
  selected: boolean,
  failed: boolean,
): PillTone {
  if (failed) {
    return selected ? 'selectedError' : 'error';
  }
  if (selected) {
    return 'selected';
  }
  return status === undefined || status === 'pending' ? 'plain' : status;
}

function graphLabel<S extends StageGraphStage>(layout: StageLayout<S>): string {
  if (layout.loopEdges.size > 0) {
    return `Stages, which loop back on themselves: ${layout.columns
      .flat()
      .map((stage) => stage.title)
      .join(', ')}`;
  }
  return `Stages: ${layout.columns
    .map((column) => column.map((stage) => stage.title).join(' or '))
    .join(' → ')}`;
}

export function StageGraph<S extends StageGraphStage>({
  stages,
  selectedId = null,
  errorIds,
  onSelect,
  className,
}: {
  stages: readonly S[];
  selectedId?: string | null;
  errorIds?: ReadonlySet<string>;
  onSelect?: (stageId: string) => void;
  className?: string;
}): React.JSX.Element | null {
  const [hovered, setHovered] = useState<string | null>(null);
  if (stages.length === 0) {
    return null;
  }

  const layout = stageLayout(stages);
  const { columns, backEdges, loopEdges } = layout;
  const interactive = onSelect !== undefined;

  const placedOf = new Map<string, Placed<S>>();
  const rows = Math.max(...columns.map((column) => column.length));
  const pillsHeight = rows * PILL_HEIGHT + (rows - 1) * ROW_GAP;
  let left = MARGIN;
  columns.forEach((column, columnIndex) => {
    const drawn = column.map((stage) => {
      const failed = errorIds?.has(stage.id) ?? false;
      const tone = pillTone(stage.status, stage.id === selectedId, failed);
      const icon: Placed<S>['icon'] = failed
        ? 'error'
        : stage.status === undefined || stage.status === 'pending'
          ? null
          : stage.status;
      const title = shortTitle(stage.title);
      const bold =
        tone === 'selected' || tone === 'selectedError' || tone === 'current';
      const width =
        PAD_X * 2 +
        textWidth(title, bold) +
        (icon === null ? 0 : ICON_SIZE + ICON_GAP);
      return { stage, tone, icon, title, width };
    });
    const columnWidth = Math.max(
      MIN_PILL_WIDTH,
      ...drawn.map((pill) => pill.width),
    );
    const columnHeight =
      column.length * PILL_HEIGHT + (column.length - 1) * ROW_GAP;
    const top = MARGIN + (pillsHeight - columnHeight) / 2;
    drawn.forEach((pill, rowIndex) => {
      placedOf.set(pill.stage.id, {
        ...pill,
        column: columnIndex,
        x: left,
        y: top + rowIndex * (PILL_HEIGHT + ROW_GAP),
        width: columnWidth,
      });
    });
    left += columnWidth + COLUMN_GAP;
  });
  const width = left - COLUMN_GAP + MARGIN;
  const height =
    MARGIN * 2 + pillsHeight + (backEdges.size > 0 ? LOOP_ROOM : 0);

  const edges: Edge[] = [...placedOf.values()].flatMap(({ stage }) =>
    [...new Set(stage.next ?? [])]
      .filter((to) => placedOf.has(to))
      .map((to): Edge => {
        const key = stageEdgeKey(stage.id, to);
        const a = placedOf.get(stage.id)!;
        const b = placedOf.get(to)!;
        const loop = loopEdges.has(key);
        if (backEdges.has(key)) {
          const x1 = a.x + a.width * 0.7;
          const x2 = b.x + b.width * 0.3;
          const low = MARGIN + pillsHeight + LOOP_ROOM;
          return {
            key,
            from: stage.id,
            to,
            loop,
            d: `M ${x1} ${a.y + PILL_HEIGHT} C ${x1} ${low}, ${x2} ${low}, ${x2} ${b.y + PILL_HEIGHT}`,
          };
        }
        const x1 = a.x + a.width;
        const y1 = a.y + PILL_HEIGHT / 2;
        const x2 = b.x;
        const y2 = b.y + PILL_HEIGHT / 2;
        const bend = (x2 - x1) / 2;
        return {
          key,
          from: stage.id,
          to,
          loop,
          d: `M ${x1} ${y1} C ${x1 + bend} ${y1}, ${x2 - bend} ${y2}, ${x2} ${y2}`,
        };
      }),
  );

  const lit = new Set<string>();
  if (hovered !== null) {
    lit.add(hovered);
    for (const edge of edges) {
      if (edge.from === hovered || edge.to === hovered) {
        lit.add(edge.from);
        lit.add(edge.to);
      }
    }
  }
  const edgeHighlight = (edge: Edge): Highlight =>
    hovered === null
      ? 'none'
      : edge.from === hovered || edge.to === hovered
        ? 'on'
        : 'dim';
  const pillHighlight = (id: string): Highlight =>
    hovered === null ? 'none' : lit.has(id) ? 'on' : 'dim';
  const edgeTone = (
    edge: Edge,
    highlight: Highlight,
  ): 'plain' | 'walked' | 'untaken' | 'active' | 'loop' => {
    if (edge.loop) {
      return 'loop';
    }
    if (highlight === 'on') {
      return 'active';
    }
    const from = placedOf.get(edge.from)!.stage.status;
    const to = placedOf.get(edge.to)!.stage.status;
    if (from === 'not_taken' || to === 'not_taken') {
      return 'untaken';
    }
    return FINISHED.has(from) && (to === 'current' || FINISHED.has(to))
      ? 'walked'
      : 'plain';
  };

  return (
    <div
      data-slot="stage-graph"
      className={cn('max-w-full overflow-x-auto', className)}>
      <svg
        role="group"
        aria-label={graphLabel(layout)}
        viewBox={`0 0 ${width} ${height}`}
        width="100%"
        style={{ maxWidth: width, minWidth: width * STAGE_GRAPH_MIN_SCALE }}
        className="mx-auto block h-auto overflow-visible">
        {edges.map((edge) => {
          const highlight = edgeHighlight(edge);
          const tone = edgeTone(edge, highlight);
          return (
            <path
              key={edge.key}
              aria-hidden="true"
              data-slot="stage-edge"
              data-edge={edge.key}
              data-tone={tone}
              data-highlight={highlight}
              data-loop={edge.loop || undefined}
              d={edge.d}
              className={edgeVariants({ tone, highlight })}
              strokeWidth={highlight === 'on' ? 1.75 : 1.25}
              strokeDasharray={edge.loop ? '4 3' : undefined}
              strokeLinecap="round"
            />
          );
        })}
        {[...placedOf.values()].map((pill) => {
          const { stage } = pill;
          const highlight = pillHighlight(stage.id);
          const selected = stage.id === selectedId;
          const failed = pill.tone === 'error' || pill.tone === 'selectedError';
          const status =
            stage.status === undefined
              ? ''
              : `, ${STAGE_STATUS_VIEW[stage.status].word}`;
          const label = `${stage.title}${status}${failed ? ', has an error' : ''}`;
          const center = pill.y + PILL_HEIGHT / 2;
          const iconLeft = pill.x + PAD_X - 2;
          const textLeft =
            pill.icon === null
              ? pill.x + PAD_X
              : iconLeft + ICON_SIZE + ICON_GAP;
          const textRight = pill.x + pill.width - PAD_X;
          const Icon =
            pill.icon === null
              ? null
              : pill.icon === 'error'
                ? TriangleAlert
                : STAGE_STATUS_VIEW[pill.icon].Icon;
          const select = (): void => onSelect?.(stage.id);
          return (
            <g
              key={stage.id}
              data-slot="stage-pill"
              data-stage-id={stage.id}
              data-column={pill.column}
              data-status={stage.status}
              data-error={failed || undefined}
              data-highlight={highlight}
              role={interactive ? 'button' : 'img'}
              aria-label={label}
              aria-current={selected ? 'true' : undefined}
              tabIndex={interactive ? 0 : undefined}
              className={pillGroupVariants({
                highlight,
                untaken: stage.status === 'not_taken',
                interactive,
              })}
              onPointerEnter={() => setHovered(stage.id)}
              onPointerLeave={() => setHovered(null)}
              {...(interactive
                ? {
                    onClick: select,
                    onKeyDown: (event: React.KeyboardEvent) => {
                      if (event.key === 'Enter' || event.key === ' ') {
                        event.preventDefault();
                        select();
                      }
                    },
                    onFocus: () => setHovered(stage.id),
                    onBlur: () => setHovered(null),
                  }
                : {})}>
              <title>{stage.title}</title>
              {stage.status === 'current' || failed ? (
                <rect
                  aria-hidden="true"
                  data-slot="stage-pill-ring"
                  x={pill.x - 3}
                  y={pill.y - 3}
                  width={pill.width + 6}
                  height={PILL_HEIGHT + 6}
                  rx={(PILL_HEIGHT + 6) / 2}
                  className={
                    failed
                      ? 'fill-none stroke-destructive/25'
                      : 'fill-none stroke-primary/20'
                  }
                  strokeWidth={3}
                />
              ) : null}
              {interactive ? (
                <rect
                  aria-hidden="true"
                  x={pill.x - 3}
                  y={pill.y - 3}
                  width={pill.width + 6}
                  height={PILL_HEIGHT + 6}
                  rx={(PILL_HEIGHT + 6) / 2}
                  className="fill-none stroke-ring/60 opacity-0 group-focus-visible/pill:opacity-100"
                  strokeWidth={3}
                />
              ) : null}
              <rect
                data-slot="stage-pill-shape"
                x={pill.x}
                y={pill.y}
                width={pill.width}
                height={PILL_HEIGHT}
                rx={PILL_HEIGHT / 2}
                className={cn(
                  pillVariants({ tone: pill.tone }),
                  interactive &&
                    !selected &&
                    'group-hover/pill:stroke-primary/60',
                )}
                strokeWidth={1}
                strokeDasharray={
                  stage.status === 'not_taken' ? '3 2' : undefined
                }
              />
              {Icon === null ? null : (
                <Icon
                  aria-hidden="true"
                  data-slot="stage-pill-icon"
                  data-icon={pill.icon}
                  x={iconLeft}
                  y={center - ICON_SIZE / 2}
                  width={ICON_SIZE}
                  height={ICON_SIZE}
                  strokeWidth={2.25}
                  className={pillIconVariants({
                    tone: pill.icon === null ? undefined : pill.icon,
                  })}
                />
              )}
              <text
                aria-hidden="true"
                x={(textLeft + textRight) / 2}
                y={center}
                textAnchor="middle"
                dominantBaseline="central"
                className={pillTextVariants({ tone: pill.tone })}>
                {pill.title}
              </text>
            </g>
          );
        })}
      </svg>
    </div>
  );
}
