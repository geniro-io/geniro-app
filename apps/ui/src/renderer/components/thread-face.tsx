import { cva } from 'class-variance-authority';
import { Activity, MessagesSquare, RadioTower } from 'lucide-react';

import type { AgentIconName } from '../autogenerated';
import { AgentGlyph } from './agent-glyph';
import {
  type AvatarLook,
  type AvatarPerson,
  type AvatarSize,
  AvatarStack,
  MemberAvatar,
} from './member-avatar';
import { cn } from './ui/utils';

/** Who works a thread, as its face shows them. */
export type ThreadFaceLook =
  | { kind: 'manager' }
  | { kind: 'team'; people: readonly AvatarPerson[]; total: number }
  | {
      kind: 'member';
      name: string;
      avatar: AvatarLook | null;
      colorKey: string;
    }
  | { kind: 'agent'; icon: AgentIconName; name: string }
  | { kind: 'monitor' }
  | { kind: 'unknown' };

/** md is the command center's face; sm is the 24px face a transcript card heads its line with. */
export type ThreadFaceSize = 'md' | 'sm';

const faceVariants = cva(
  'flex shrink-0 items-center justify-center rounded-full',
  {
    variants: {
      size: {
        md: 'size-8',
        sm: 'size-6',
      },
    },
    defaultVariants: { size: 'md' },
  },
);

const glyphVariants = cva('', {
  variants: {
    size: {
      md: 'size-4',
      sm: 'size-3.5',
    },
  },
  defaultVariants: { size: 'md' },
});

const memberAvatarVariants = cva('', {
  variants: {
    size: {
      md: 'size-8 text-xs',
      sm: 'size-6 text-[10px]',
    },
  },
  defaultVariants: { size: 'md' },
});

const teamVariants = cva('flex shrink-0 items-center', {
  variants: {
    size: {
      md: 'h-8',
      sm: 'h-6',
    },
  },
  defaultVariants: { size: 'md' },
});

const STACK_SIZE: Record<ThreadFaceSize, AvatarSize> = { md: 24, sm: 20 };

/**
 * A thread's face: the command center manager's mast, a team's members, the
 * agent's own glyph, or a plain thread glyph where the view does not know who
 * works it.
 */
export function ThreadFace({
  look,
  slot,
  ringClassName = 'ring-card',
  size = 'md',
}: {
  look: ThreadFaceLook;
  slot: string;
  /** The surface the crew's faces stand on, so their rings cut them apart. */
  ringClassName?: string;
  size?: ThreadFaceSize;
}): React.JSX.Element {
  const glyph = glyphVariants({ size });
  switch (look.kind) {
    case 'manager':
      return (
        <span
          data-slot={slot}
          data-face="manager"
          data-size={size}
          className={cn(faceVariants({ size }), 'bg-primary/15 text-primary')}>
          <RadioTower aria-hidden="true" className={glyph} />
        </span>
      );
    case 'team':
      return (
        <span
          data-slot={slot}
          data-face="team"
          data-size={size}
          aria-label={`${look.total} members`}
          className={teamVariants({ size })}>
          <AvatarStack
            size={STACK_SIZE[size]}
            max={3}
            total={look.total}
            people={look.people}
            ringClassName={ringClassName}
          />
        </span>
      );
    case 'member':
      return (
        <span
          data-slot={slot}
          data-face="member"
          data-size={size}
          title={look.name}
          className={faceVariants({ size })}>
          <MemberAvatar
            name={look.name}
            avatar={look.avatar}
            colorKey={look.colorKey}
            size={24}
            className={memberAvatarVariants({ size })}
          />
        </span>
      );
    case 'agent':
      return (
        <span
          data-slot={slot}
          data-face="agent"
          data-size={size}
          title={look.name}
          className={cn(faceVariants({ size }), 'bg-accent text-foreground')}>
          <AgentGlyph icon={look.icon} />
        </span>
      );
    case 'monitor':
      return (
        <span
          data-slot={slot}
          data-face="monitor"
          data-size={size}
          className={cn(
            faceVariants({ size }),
            'bg-muted text-muted-foreground',
          )}>
          <Activity aria-hidden="true" className={glyph} />
        </span>
      );
    case 'unknown':
      return (
        <span
          data-slot={slot}
          data-face="unknown"
          data-size={size}
          className={cn(
            faceVariants({ size }),
            'bg-muted text-muted-foreground',
          )}>
          <MessagesSquare aria-hidden="true" className={glyph} />
        </span>
      );
  }
}
