import { Activity, MessagesSquare, RadioTower } from 'lucide-react';

import type { AgentIconName } from '../autogenerated';
import { AgentGlyph } from './agent-glyph';
import {
  type AvatarLook,
  type AvatarPerson,
  AvatarStack,
  MemberAvatar,
} from './member-avatar';
import { cn } from './ui/utils';

/** Who works a thread, as its face shows them. */
export type ThreadFaceLook =
  | { kind: 'manager' }
  | { kind: 'team'; people: readonly AvatarPerson[]; total: number }
  | {
      kind: 'member';
      name: string;
      avatar: AvatarLook | null;
      colorKey: string;
    }
  | { kind: 'agent'; icon: AgentIconName; name: string }
  | { kind: 'monitor' }
  | { kind: 'unknown' };

const CIRCLE_CLASS =
  'flex size-8 shrink-0 items-center justify-center rounded-full';

/**
 * A thread's face: the command center manager's mast, a team's members, the
 * agent's own glyph, or a plain thread glyph where the view does not know who
 * works it.
 */
export function ThreadFace({
  look,
  slot,
  ringClassName = 'ring-card',
}: {
  look: ThreadFaceLook;
  slot: string;
  /** The surface the crew's faces stand on, so their rings cut them apart. */
  ringClassName?: string;
}): React.JSX.Element {
  switch (look.kind) {
    case 'manager':
      return (
        <span
          data-slot={slot}
          data-face="manager"
          className={cn(CIRCLE_CLASS, 'bg-primary/15 text-primary')}>
          <RadioTower aria-hidden="true" className="size-4" />
        </span>
      );
    case 'team':
      return (
        <span
          data-slot={slot}
          data-face="team"
          aria-label={`${look.total} members`}
          className="flex h-8 shrink-0 items-center">
          <AvatarStack
            size={24}
            max={3}
            total={look.total}
            people={look.people}
            ringClassName={ringClassName}
          />
        </span>
      );
    case 'member':
      return (
        <span
          data-slot={slot}
          data-face="member"
          title={look.name}
          className={CIRCLE_CLASS}>
          <MemberAvatar
            name={look.name}
            avatar={look.avatar}
            colorKey={look.colorKey}
            size={24}
            className="size-8 text-xs"
          />
        </span>
      );
    case 'agent':
      return (
        <span
          data-slot={slot}
          data-face="agent"
          title={look.name}
          className={cn(CIRCLE_CLASS, 'bg-accent text-foreground')}>
          <AgentGlyph icon={look.icon} />
        </span>
      );
    case 'monitor':
      return (
        <span
          data-slot={slot}
          data-face="monitor"
          className={cn(CIRCLE_CLASS, 'bg-muted text-muted-foreground')}>
          <Activity aria-hidden="true" className="size-4" />
        </span>
      );
    case 'unknown':
      return (
        <span
          data-slot={slot}
          data-face="unknown"
          className={cn(CIRCLE_CLASS, 'bg-muted text-muted-foreground')}>
          <MessagesSquare aria-hidden="true" className="size-4" />
        </span>
      );
  }
}
