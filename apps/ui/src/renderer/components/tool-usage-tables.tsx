import type { McpServerUse, ToolUse } from '../autogenerated';
import {
  formatCount,
  formatDuration,
  NOT_MEASURED,
} from '../stats/stats-format';
import { type FigureColumn, FigureTable } from './figure-table';

/** Rows a table shows; the rest are counted under it. */
export const TOOL_ROWS = 12;

const TOOL_COLUMNS: readonly FigureColumn<ToolUse>[] = [
  {
    header: 'Tool',
    cell: (row) => (
      <span className="block max-w-72 truncate">
        {row.tool}
        {row.mcpServer === null ? null : (
          <span className="text-muted-foreground"> · {row.mcpServer}</span>
        )}
      </span>
    ),
    title: (row) =>
      row.mcpServer === null ? row.tool : `${row.tool} (${row.mcpServer})`,
  },
  { header: 'Calls', align: 'end', cell: (row) => formatCount(row.calls) },
  { header: 'Errors', align: 'end', cell: (row) => formatCount(row.errors) },
  {
    header: 'Avg time',
    align: 'end',
    cell: (row) =>
      row.avgMs === null ? NOT_MEASURED : formatDuration(row.avgMs),
  },
];

const SERVER_COLUMNS: readonly FigureColumn<McpServerUse>[] = [
  {
    header: 'MCP server',
    cell: (row) => (
      <span className="block max-w-72 truncate">{row.server}</span>
    ),
    title: (row) => row.server,
  },
  { header: 'Calls', align: 'end', cell: (row) => formatCount(row.calls) },
  { header: 'Errors', align: 'end', cell: (row) => formatCount(row.errors) },
  { header: 'Tools', align: 'end', cell: (row) => formatCount(row.tools) },
];

/**
 * The tools and MCP servers a set of runs called, from the daemon's tool ledger:
 * calls, errors and mean time per tool, and per server over all its tools.
 */
export function ToolUsageTables({
  tools,
  mcpServers,
  emptyLabel,
}: {
  tools: readonly ToolUse[];
  mcpServers: readonly McpServerUse[];
  emptyLabel: string;
}): React.JSX.Element {
  const shown = tools.slice(0, TOOL_ROWS);
  return (
    <div data-slot="tool-usage" className="grid gap-6 lg:grid-cols-[3fr_2fr]">
      <div className="flex min-w-0 flex-col gap-1">
        <FigureTable
          ariaLabel="Tools"
          columns={TOOL_COLUMNS}
          rows={shown}
          rowKey={(row) => `${row.mcpServer ?? ''}:${row.tool}`}
          emptyLabel={emptyLabel}
        />
        {tools.length > shown.length ? (
          <p className="px-2 text-xs text-muted-foreground">
            +{formatCount(tools.length - shown.length)} more tools
          </p>
        ) : null}
      </div>
      <FigureTable
        ariaLabel="MCP servers"
        columns={SERVER_COLUMNS}
        rows={mcpServers}
        rowKey={(row) => row.server}
        emptyLabel="No MCP server was called."
      />
    </div>
  );
}
