import { useState } from 'react';

import type { MemoriesApi, MemoryEntry } from '../autogenerated';
import {
  daemonErrorCode,
  daemonErrorDetail,
  describeDaemonError,
} from '../daemon-api';
import type { MemoryFormValue } from './memory-form';

/** The entry form that is open: a new entry, or one being edited at its rev. */
export type MemoryEditing =
  | { kind: 'new'; value: MemoryFormValue; vouched: string[] }
  | {
      kind: 'edit';
      entry: MemoryEntry;
      value: MemoryFormValue;
      vouched: string[];
    };

/** Whether only the user's approval admits this entry to the memory index. */
export function awaitsApproval(entry: MemoryEntry): boolean {
  const byAgent =
    entry.source.actor === 'agent' || entry.source.actor === 'analysis';
  return (
    entry.status === 'pending' ||
    (entry.status === 'active' && byAgent && entry.approvedAt === null)
  );
}

/**
 * The handles a near-duplicate refusal names, so a "Save anyway" vouches past
 * exactly those; null for any other refusal.
 *
 * TWIN PARSER: `NEAR_DUPLICATE_PREFIX` in
 * `apps/daemon/src/v1/memory/utils/memory-outcome.ts`.
 */
export function nearDuplicateHandles(err: unknown): string[] | null {
  if (daemonErrorCode(err) !== 'MEMORY_NEAR_DUPLICATE') {
    return null;
  }
  const detail = daemonErrorDetail(err) ?? '';
  const prefix = 'similar entries exist: ';
  if (!detail.startsWith(prefix)) {
    return null;
  }
  return detail
    .slice(prefix.length)
    .split(',')
    .map((handle) => handle.trim())
    .filter((handle) => /^m\d+$/.test(handle));
}

export interface MemoryEditor {
  editing: MemoryEditing | null;
  setEditing: (editing: MemoryEditing | null) => void;
  formError: string | null;
  setFormError: (error: string | null) => void;
  saving: boolean;
  /** The id of the entry whose status write is out, or null. */
  busy: string | null;
  /** Approve or restore (`active`), or forget, one entry, then re-read. */
  setStatus: (
    entry: MemoryEntry,
    status: 'active' | 'forgotten',
  ) => Promise<void>;
  /**
   * Save the open form: create or update at the read rev. A near-duplicate
   * refusal keeps the form open, vouching past exactly the handles it named
   * on the next save.
   */
  submit: () => Promise<void>;
  /** Close the form, dropping what it said. */
  close: () => void;
}

/**
 * The user's add and edit form for shared-memory entries, one home for
 * Settings → Memory and a team's Memory tab. `filed` sets where a save files
 * the entry (a team's tab pins it to that team); `onSaved` re-reads the list.
 */
export function useMemoryEditor(
  api: Pick<MemoriesApi, 'createMemory' | 'updateMemory'> | null,
  {
    onSaved,
    onStatusError,
    filed = (value) => value,
  }: {
    onSaved: () => void;
    /** Where a refused status write is said; null clears it as a write starts. */
    onStatusError: (message: string | null) => void;
    filed?: (value: MemoryFormValue) => MemoryFormValue;
  },
): MemoryEditor {
  const [editing, setEditing] = useState<MemoryEditing | null>(null);
  const [formError, setFormError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);
  const [busy, setBusy] = useState<string | null>(null);

  const setStatus = async (
    entry: MemoryEntry,
    status: 'active' | 'forgotten',
  ): Promise<void> => {
    if (api === null) {
      return;
    }
    setBusy(entry.id);
    onStatusError(null);
    try {
      await api.updateMemory({
        memoryId: entry.id,
        updateMemoryDto: { status },
      });
    } catch (err: unknown) {
      onStatusError(describeDaemonError(err));
    } finally {
      setBusy(null);
      onSaved();
    }
  };

  const close = (): void => {
    setEditing(null);
    setFormError(null);
  };

  const submit = async (): Promise<void> => {
    if (api === null || editing === null) {
      return;
    }
    setSaving(true);
    setFormError(null);
    const value = filed(editing.value);
    const notDuplicateOf =
      editing.vouched.length > 0 ? editing.vouched : undefined;
    try {
      if (editing.kind === 'new') {
        await api.createMemory({
          createMemoryDto: { ...value, notDuplicateOf },
        });
      } else {
        await api.updateMemory({
          memoryId: editing.entry.id,
          updateMemoryDto: { ...value, rev: editing.entry.rev, notDuplicateOf },
        });
      }
      setEditing(null);
      onSaved();
    } catch (err: unknown) {
      const similar = nearDuplicateHandles(err);
      if (similar !== null && similar.length > 0) {
        setEditing({ ...editing, vouched: similar });
        setFormError(
          `Similar entries exist: ${similar.join(', ')}. Save again to keep this one anyway.`,
        );
      } else {
        setFormError(describeDaemonError(err));
      }
    } finally {
      setSaving(false);
    }
  };

  return {
    editing,
    setEditing,
    formError,
    setFormError,
    saving,
    busy,
    setStatus,
    submit,
    close,
  };
}
