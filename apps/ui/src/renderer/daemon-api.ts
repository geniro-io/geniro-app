import type { DaemonHandle } from '../shared/contracts';
import {
  AgentsApi,
  CapabilitiesApi,
  ChatsApi,
  Configuration,
  type Middleware,
  TerminalsApi,
  WorkflowsApi,
} from './autogenerated';

/**
 * Ceiling on every loopback request. The daemon is local — a healthy route
 * answers in milliseconds — so a request still pending after this long means
 * a wedged daemon, and without a bound the awaiting renderer action (a send
 * button, a run start) hangs forever with no feedback.
 *
 * It must stay ABOVE the daemon's own slowest bounded route, or the client
 * aborts first and throws away the daemon's own explanation. Every route
 * except the MCP ones clears that comfortably; the MCP routes do not, and they
 * carry {@link MCP_ROUTE_TIMEOUT_MS} instead.
 */
export const REQUEST_TIMEOUT_MS = 30_000;

/**
 * The budget for the MCP routes, which are the one exception to the ceiling
 * above.
 *
 * Reading a folder's MCP servers is not a lookup: the CLI HEALTH-CHECKS,
 * dialling every configured server — which means STARTING it. A `docker run`
 * or a `uvx` server that has to fetch first routinely takes tens of seconds,
 * so the daemon allows `CLAUDE_MCP_LIST_TIMEOUT_MS` (45s) for it. Against the
 * flat 30s above the CLIENT aborted first: the daemon's own sentence about
 * what went wrong never arrived, and the panel showed a bare transport failure
 * for a folder whose servers were merely slow.
 *
 * Deliberately ABOVE that daemon deadline, so the daemon always gives up first
 * and the reason the user reads is the specific one it produced. It belongs
 * HERE rather than at a call site because three call sites reach these routes
 * — the chat panel's listing, the builder's, and the enable/disable write,
 * whose handler re-dials on a lapsed cache — and giving only one of them the
 * budget leaves the other two reproducing the defect. No test spans the two
 * packages, so this note is the link.
 */
export const MCP_ROUTE_TIMEOUT_MS = 60_000;

/** `/v1/chats/r1/items?afterSeq=3` — what the uniform error names. */
const routeOf = (url: string): string => {
  try {
    const parsed = new URL(url);
    return `${parsed.pathname}${parsed.search}`;
  } catch {
    return url;
  }
};

/**
 * Translate a non-2xx response into the renderer's uniform error BEFORE the
 * generated runtime raises its own generic `ResponseError`. The exact text is
 * load-bearing: it is surfaced to the user verbatim and `Chats` parses the
 * `(status)` segment to tell a deleted run from a real failure.
 */
const uniformErrors: Middleware = {
  async post({ url, init, response }) {
    if (response.ok) {
      return response;
    }
    const detail = await response.text().catch(() => '');
    throw new Error(
      `daemon ${init.method ?? 'GET'} ${routeOf(url)} failed (${response.status})` +
        `${detail ? `: ${detail}` : ''}`,
    );
  },
};

/**
 * The `(status)` segment of the message {@link uniformErrors} produces, or null
 * for anything else (a timeout, an abort, a thrown non-Error). Lives HERE, next
 * to the only code that writes that text, so a caller that needs to tell a
 * 404 from a real failure cannot drift from the format it is parsing.
 */
export function daemonErrorStatus(err: unknown): number | null {
  const message = err instanceof Error ? err.message : String(err);
  const match = /^daemon .* failed \((\d{3})\)/.exec(message);
  return match ? Number(match[1]) : null;
}

/** The generated API clients, all bound to one daemon launch. */
export interface DaemonApis {
  chats: ChatsApi;
  agents: AgentsApi;
  workflows: WorkflowsApi;
  capabilities: CapabilitiesApi;
  terminals: TerminalsApi;
}

/**
 * Build the daemon clients for one launch handle.
 *
 * The route methods and every wire type come from `./autogenerated`, generated
 * off the daemon's own OpenAPI document by `pnpm generate:api` — the renderer
 * no longer hand-mirrors the daemon's shapes. This module owns the three things
 * the generator cannot know: the loopback base URL (host and port are
 * negotiated per launch and read from the pidfile), the per-launch bearer token
 * every non-public route requires, and the request timeout + uniform error
 * shape the UI is written against.
 */
export function createDaemonApis(handle: DaemonHandle): DaemonApis {
  const config = new Configuration({
    basePath: `http://${handle.host}:${handle.port}`,
    accessToken: handle.token,
    middleware: [uniformErrors],
    // The generated runtime never sets a signal, so this is the one place a
    // bound can be applied; an explicit per-call override still wins.
    fetchApi: (input, init) =>
      fetch(input, {
        ...init,
        signal: init?.signal ?? AbortSignal.timeout(REQUEST_TIMEOUT_MS),
      }),
  });

  return {
    chats: new ChatsApi(config),
    agents: new AgentsApi(config),
    workflows: new WorkflowsApi(config),
    capabilities: new CapabilitiesApi(config),
    terminals: new TerminalsApi(config),
  };
}
