/**
 * Ceiling on every loopback request. The daemon is local — a healthy route
 * answers in milliseconds — so a request still pending after this long means
 * a wedged daemon, and without a bound the awaiting renderer action (a send
 * button, a run start) hangs forever with no feedback.
 *
 * It must stay ABOVE the daemon's own slowest bounded route, or the client
 * aborts first and throws away the daemon's own explanation. Every route
 * except the MCP ones clears that comfortably; the MCP routes do not, and they
 * carry {@link MCP_ROUTE_TIMEOUT_MS} instead.
 */
export const REQUEST_TIMEOUT_MS = 30_000;

/**
 * The budget for the MCP routes, which are the one exception to the ceiling
 * above.
 *
 * Reading a folder's MCP servers is not a lookup: the CLI HEALTH-CHECKS,
 * dialling every configured server — which means STARTING it. A `docker run`
 * or a `uvx` server that has to fetch first routinely takes tens of seconds,
 * so the daemon allows `CLAUDE_MCP_LIST_TIMEOUT_MS` (45s) for it. Against the
 * flat 30s above the CLIENT aborted first: the daemon's own sentence about
 * what went wrong never arrived, and the panel showed a bare transport failure
 * for a folder whose servers were merely slow.
 *
 * Deliberately ABOVE that daemon deadline, so the daemon always gives up first
 * and the reason the user reads is the specific one it produced. It belongs
 * HERE rather than at a call site because three call sites reach these routes
 * — the chat panel's listing, the builder's, and the enable/disable write,
 * whose handler re-dials on a lapsed cache — and giving only one of them the
 * budget leaves the other two reproducing the defect. No test spans the two
 * packages, so this note is the link.
 */
export const MCP_ROUTE_TIMEOUT_MS = 60_000;

/** `/v1/chats/r1/items?afterSeq=3` — what the uniform error names. */
const routeOf = (url: string): string => {
  try {
    const parsed = new URL(url);
    return `${parsed.pathname}${parsed.search}`;
  } catch {
    return url;
  }
};

/**
 * Translate a non-2xx response into the renderer's uniform error BEFORE the
 * generated runtime raises its own generic `ResponseError`. The exact text is
 * load-bearing: it is surfaced to the user verbatim and `Chats` parses the
 * `(status)` segment to tell a deleted run from a real failure.
 */
const uniformErrors: Middleware = {
  async post({ url, init, response }) {
    if (response.ok) {
      return response;
    }
    const detail = await response.text().catch(() => '');
    throw new Error(
      `daemon ${init.method ?? 'GET'} ${routeOf(url)} failed (${response.status})` +
        `${detail ? `: ${detail}` : ''}`,
    );
  },
};

/**
 * The `(status)` segment of the message {@link uniformErrors} produces, or null
 * for anything else (a timeout, an abort, a thrown non-Error). Lives HERE, next
 * to the only code that writes that text, so a caller that needs to tell a
 * 404 from a real failure cannot drift from the format it is parsing.
 */
export function daemonErrorStatus(err: unknown): number | null {
  const message = err instanceof Error ? err.message : String(err);
  const match = /^daemon .* failed \((\d{3})\)/.exec(message);
  return match ? Number(match[1]) : null;
}

/**
 * The daemon's `code` field, read out of the body {@link uniformErrors} appended
 * after the `(status)` segment.
 *
 * Lives here for the same reason {@link daemonErrorStatus} does: this module is
 * the only writer of that text, so the only parser of it belongs beside the
 * writer. Callers ask for a NAMED code rather than substring-matching the
 * message — `String(err).includes('RUN_BUSY')` also matches a run whose id or
 * cwd happens to contain the word, and says nothing about the status.
 *
 * Returns null when the body is absent or is not the daemon's JSON error shape
 * (a proxy's HTML page, a truncated body), so a caller can never mistake
 * "we could not tell" for "some other code".
 */
export function daemonErrorCode(err: unknown): string | null {
  return errorEnvelopeField(err, 'code');
}

/**
 * The daemon's own SENTENCE for a refusal, or null when it did not write one.
 *
 * Sibling of {@link daemonErrorCode} and deliberately shaped like it: the code
 * is what a caller branches on, this is what it shows a person. The daemon
 * writes real explanations next to its codes ("this turn is running without a
 * permission gate, so its approval mode cannot be changed until it settles"),
 * and a renderer that falls back to `String(err)` throws that away and prints
 * the whole `daemon PATCH /v1/… failed (409): {"code":…}` envelope instead.
 *
 * Null — never a guess — when the body is absent, is not the daemon's JSON
 * shape, or carries no message, so a caller can tell "nothing to show" from a
 * refusal that explained itself.
 */
export function daemonErrorDetail(err: unknown): string | null {
  const detail = errorEnvelopeField(err, 'message');
  // Present but blank is still nothing to show the user.
  return detail !== null && detail.trim() !== '' ? detail : null;
}

/**
 * One string field of the daemon's JSON error envelope, or null.
 *
 * The uniform error shape (`daemon <METHOD> <path> failed (<status>): <body>`)
 * is parsed HERE and nowhere else, so its two readers cannot come to disagree
 * about it — the format is a contract with `createDaemonApis` below, and it had
 * already grown a third independent copy of this regex.
 *
 * Null — never a guess — when the body is absent or is not that JSON shape (a
 * proxy's HTML page, a truncated body), so a caller can never mistake "we could
 * not tell" for a value the daemon sent.
 */
function errorEnvelopeField(err: unknown, field: string): string | null {
  const message = err instanceof Error ? err.message : String(err);
  const body = /^daemon .*? failed \(\d{3}\): (.*)$/s.exec(message)?.[1];
  if (body === undefined) {
    return null;
  }
  try {
    const parsed: unknown = JSON.parse(body);
    if (typeof parsed === 'object' && parsed !== null && field in parsed) {
      const value = (parsed as Record<string, unknown>)[field];
      return typeof value === 'string' ? value : null;
    }
  } catch {
    // Not JSON — the daemon did not answer, something in front of it did.
  }
  return null;
}

/**
 * Whether the daemon refused a send because a turn is already in flight.
 *
 * The ONE question the follow-up composer asks, named once. It is answered by
 * the SERVER (409 + `RUN_BUSY`) and never by the renderer's own belief about
 * whether a turn is running: the two disagree in practice — a run row that has
 * not loaded yet, or a turn the daemon still holds — and when they did, the
 * documented queue fallback was skipped and the raw JSON body was rendered as a
 * red banner instead.
 */
export function isRunBusyError(err: unknown): boolean {
  // The STATUS is the strict half, and it is what makes this safe: 409 is the
  // daemon's one "a turn is already in flight" answer, so no 404, 500 or
  // transport failure can be mistaken for a reason to queue.
  if (daemonErrorStatus(err) !== 409) {
    return false;
  }
  // The BODY is the tolerant half. A parsed `code` is the precise reading, but
  // a 409 that names RUN_BUSY in any other envelope still means the same thing,
  // and being brittle here has a bad failure mode in exactly one direction:
  // an unrecognised body drops the user's message into a red banner instead of
  // the queue. A 409 carrying some OTHER code is still rejected, because the
  // parsed reading wins whenever there is one.
  const code = daemonErrorCode(err);
  if (code !== null) {
    return code === 'RUN_BUSY';
  }
  const message = err instanceof Error ? err.message : String(err);
  return /\bRUN_BUSY\b/.test(message);
}

/** The generated API clients, all bound to one daemon launch. */
export interface DaemonApis {
  chats: ChatsApi;
  agents: AgentsApi;
  workflows: WorkflowsApi;
  capabilities: CapabilitiesApi;
  handoff: HandoffApi;
  /**
   * Signing a CLI in and out in place (`/v1/auth`), as opposed to `handoff`,
   * which only resolves what the user would type. Separate client for the same
   * reason they are separate controllers: one runs commands, the other never does.
   */
  cliAuth: CliAuthApi;
  diagnostics: DiagnosticsApi;
}

/**
 * Build the daemon clients for one launch handle.
 *
 * The route methods and every wire type come from `./autogenerated`, generated
 * off the daemon's own OpenAPI document by `pnpm generate:api` — the renderer
 * no longer hand-mirrors the daemon's shapes. This module owns the three things
 * the generator cannot know: the loopback base URL (host and port are
 * negotiated per launch and read from the pidfile), the per-launch bearer token
 * every non-public route requires, and the request timeout + uniform error
 * shape the UI is written against.
 */
export function createDaemonApis(handle: DaemonHandle): DaemonApis {
  const config = new Configuration({
    basePath: `http://${handle.host}:${handle.port}`,
    accessToken: handle.token,
    middleware: [uniformErrors],
    // The generated runtime never sets a signal, so this is the one place a
    // bound can be applied; an explicit per-call override still wins.
    fetchApi: (input, init) =>
      fetch(input, {
        ...init,
        signal: init?.signal ?? AbortSignal.timeout(REQUEST_TIMEOUT_MS),
      }),
  });

  return {
    chats: new ChatsApi(config),
    agents: new AgentsApi(config),
    workflows: new WorkflowsApi(config),
    capabilities: new CapabilitiesApi(config),
    handoff: new HandoffApi(config),
    cliAuth: new CliAuthApi(config),
    diagnostics: new DiagnosticsApi(config),
  };
}
