import { beforeEach, describe, expect, it, vi } from 'vitest';

import type { DaemonHandle } from '../shared/contracts';
import type { ItemDto as ChatItem } from './autogenerated';
import {
  DaemonClient,
  parseDeletedRunId,
  parseRunStatus,
  parseTaskChanged,
} from './daemon-client';

// A fake Socket.IO socket whose 'connect' handler and onAny dispatcher the test
// can drive directly. vi.hoisted so the vi.mock factory can close over it.
const mocks = vi.hoisted(() => {
  const handlers: Record<string, (...args: unknown[]) => void> = {};
  const ref: { any: ((event: string, data: unknown) => void) | null } = {
    any: null,
  };
  const emit = vi.fn();
  const close = vi.fn();
  const engineClose = vi.fn();
  const socket = {
    connected: false,
    io: { engine: { close: engineClose } },
    on: (event: string, h: (...args: unknown[]) => void) => {
      handlers[event] = h;
    },
    onAny: (h: (event: string, data: unknown) => void) => {
      ref.any = h;
    },
    emit,
    close,
  };
  return {
    handlers,
    ref,
    emit,
    close,
    engineClose,
    socket,
    io: vi.fn(() => socket),
  };
});

vi.mock('socket.io-client', () => ({ io: mocks.io }));

const handle: DaemonHandle = {
  host: '127.0.0.1',
  port: 8123,
  token: 'tok',
  version: '1',
  startedAt: '2026-01-01T00:00:00.000Z',
};

function fireConnect(): void {
  mocks.socket.connected = true;
  mocks.handlers.connect?.();
}

function fireJoined(runId: string): void {
  mocks.ref.any?.('joined', { runId });
}

/** Let every pending microtask run — a macrotask drains the whole queue. */
function flushMicrotasks(): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, 0));
}

beforeEach(() => {
  mocks.emit.mockClear();
  mocks.close.mockClear();
  mocks.engineClose.mockClear();
  mocks.io.mockClear();
  mocks.socket.connected = false;
  mocks.ref.any = null;
  for (const key of Object.keys(mocks.handlers)) {
    delete mocks.handlers[key];
  }
});

describe('DaemonClient', () => {
  it('fires onReconnect only after the active room is re-joined', async () => {
    const client = new DaemonClient(handle, {});
    const reconnects: number[] = [];
    client.onReconnect(() => reconnects.push(1));
    client.connect();
    const initialJoin = client.joinRun('r1');

    // First connect is NOT a reconnect: no onReconnect, but the active room is
    // (re-)joined so live items resume.
    mocks.emit.mockClear();
    fireConnect();
    expect(reconnects).toHaveLength(0);
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    fireJoined('r1');
    await initialJoin;

    // Second connect IS a reconnect, but replay is held until the joined event.
    mocks.emit.mockClear();
    fireConnect();
    expect(reconnects).toHaveLength(0);
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    fireJoined('r1');
    // A macrotask, so every pending microtask has run: the assertion above —
    // still zero with the join event withheld — is what pins the HOLD, and
    // counting ticks here only pins how many promises the re-join is built
    // from.
    await flushMicrotasks();
    expect(reconnects).toHaveLength(1);
  });

  // Two surfaces can each be following a run — the chat screen stays mounted
  // while the workflow builder's chat panel is open — and a reconnect that
  // re-joined one of them left the other live and permanently silent.
  it('re-joins EVERY joined room after a reconnect, and waits for all of them', async () => {
    const client = new DaemonClient(handle, {});
    const reconnects: number[] = [];
    client.onReconnect(() => reconnects.push(1));
    client.connect();
    const first = client.joinRun('r1');
    const second = client.joinRun('r2');
    fireConnect();
    fireJoined('r1');
    fireJoined('r2');
    await Promise.all([first, second]);

    mocks.emit.mockClear();
    fireConnect();
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r2' });

    fireJoined('r1');
    await flushMicrotasks();
    expect(reconnects).toHaveLength(0);

    fireJoined('r2');
    await flushMicrotasks();
    expect(reconnects).toHaveLength(1);
  });

  it('stops re-joining a room that was left', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    const joining = client.joinRun('r1');
    fireConnect();
    fireJoined('r1');
    await joining;
    client.leaveRun('r1');

    mocks.emit.mockClear();
    fireConnect();

    expect(mocks.emit).not.toHaveBeenCalledWith('join', { runId: 'r1' });
  });

  it('routes only `item` events from onAny to onItem subscribers', () => {
    const client = new DaemonClient(handle, {});
    const items: ChatItem[] = [];
    client.onItem((i) => items.push(i));
    client.connect();

    const item: ChatItem = {
      id: 'i0',
      runId: 'r1',
      nodeId: null,
      seq: 0,
      kind: 'message',
      role: 'assistant',
      payload: { text: 'hi' },
      createdAt: 'now',
    };
    mocks.ref.any?.('item', item);
    mocks.ref.any?.('other', { x: 1 });

    expect(items).toEqual([item]);
  });

  it('forwards a question answer in the exact verdict payload', () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    fireConnect();

    client.sendVerdict('r1', 'req-1', true, 'Blue');

    expect(mocks.emit).toHaveBeenCalledWith('verdict', {
      runId: 'r1',
      requestId: 'req-1',
      allow: true,
      answer: 'Blue',
    });
  });

  it('reports a failed connection ATTEMPT, with the reason', () => {
    // Socket.IO retries forever and reports nothing else, so without this the
    // renderer cannot tell "still connecting" from "will never connect" — and
    // a daemon that is down produced no signal in the UI at all.
    const onError = vi.fn();
    const client = new DaemonClient(handle, { onError });
    client.connect();

    mocks.handlers.connect_error?.(
      new Error('xhr poll error: connect ECONNREFUSED 127.0.0.1:8123'),
    );

    expect(onError).toHaveBeenCalledWith(
      'xhr poll error: connect ECONNREFUSED 127.0.0.1:8123 (127.0.0.1:8123)',
    );
  });

  it('names the endpoint, because Socket.IO’s own wording does not', () => {
    // Observed against a dead port: the whole reason reaching the UI was
    // "websocket error". True, and useless for the one thing the user can
    // act on — which port are we dialling, and is anything on it. Host and
    // port are negotiated per launch, so this client is the only place that
    // knows them.
    const onError = vi.fn();
    const client = new DaemonClient(handle, { onError });
    client.connect();

    mocks.handlers.connect_error?.(new Error('websocket error'));

    expect(onError).toHaveBeenCalledWith('websocket error (127.0.0.1:8123)');
  });

  it('never hands the renderer an empty reason to render', () => {
    // A transport error with a blank message would put an empty sentence on
    // the connection strip, which reads as a broken UI rather than a failure.
    const onError = vi.fn();
    const client = new DaemonClient(handle, { onError });
    client.connect();

    mocks.handlers.connect_error?.(new Error(''));

    expect(onError).toHaveBeenCalledWith(
      'could not reach the daemon (127.0.0.1:8123)',
    );
  });

  it('passes the disconnect REASON on, rather than just the fact', () => {
    // "transport close" (the daemon exited) and "io server disconnect" (it
    // rejected us) are different problems with different fixes.
    const onClose = vi.fn();
    const client = new DaemonClient(handle, { onClose });
    client.connect();
    fireConnect();

    mocks.handlers.disconnect?.('transport close');

    expect(onClose).toHaveBeenCalledWith('transport close');
  });

  // A phone's browser cuts a backgrounded page's connection without a close
  // frame, so the socket still reads `connected` while every join goes into
  // the void until Socket.IO's own ping timeout. REPORTED as `timed out
  // joining run` through a tunnel.
  it('drops a transport that leaves a join unanswered, so the room is restored', async () => {
    vi.useFakeTimers();
    try {
      const client = new DaemonClient(handle, {});
      client.connect();
      fireConnect();

      const joining = client.joinRun('r1');
      const settled = joining.catch((err: unknown) => err);
      await vi.advanceTimersByTimeAsync(5_000);

      expect(await settled).toEqual(new Error('timed out joining run r1'));
      // The ENGINE, so the manager reconnects under its own backoff — a
      // `disconnect()` would switch reconnection off.
      expect(mocks.engineClose).toHaveBeenCalledTimes(1);
      expect(mocks.close).not.toHaveBeenCalled();

      // …and the reconnect puts the room back, since the timeout did not
      // forget it.
      mocks.emit.mockClear();
      fireConnect();
      expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    } finally {
      vi.useRealTimers();
    }
  });

  it('leaves a transport that is already down to its own reconnection', async () => {
    vi.useFakeTimers();
    try {
      const client = new DaemonClient(handle, {});
      client.connect();

      const settled = client.joinRun('r1').catch((err: unknown) => err);
      await vi.advanceTimersByTimeAsync(5_000);

      expect(await settled).toBeInstanceOf(Error);
      expect(mocks.engineClose).not.toHaveBeenCalled();
    } finally {
      vi.useRealTimers();
    }
  });

  it('leaveRun clears the active room so a later reconnect does not rejoin it', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    fireConnect();
    const joined = client.joinRun('r1');
    fireJoined('r1');
    await joined;
    client.leaveRun('r1');

    mocks.emit.mockClear();
    fireConnect();
    expect(mocks.emit).not.toHaveBeenCalledWith('join', { runId: 'r1' });
  });
});

describe('parseRunStatus — the run_status twin', () => {
  it('reads an activity-only announce as carrying NO status', () => {
    // The daemon's activity announce fires on every tool call and never reads
    // the run, so it sends `status: null`. Read as a status, it would write a
    // guess onto the row — which is how a cancelled run went back to running.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: 'running Bash' }),
    ).toEqual({ runId: 'r1', status: null, activity: 'running Bash' });
  });

  it('reads a MISSING status the same way', () => {
    expect(parseRunStatus({ runId: 'r1', activity: 'running Bash' })).toEqual({
      runId: 'r1',
      status: null,
      activity: 'running Bash',
    });
  });

  it('keeps whether a task group was stated whole, reading anything but true as patched', () => {
    const event = parseRunStatus({
      runId: 'r1',
      status: null,
      activity: null,
      taskList: [
        {
          nodeId: 'eng',
          callId: 'call-1',
          tasks: [{ id: '1' }],
          snapshot: true,
        },
        { nodeId: 'eng', callId: 'call-2', tasks: [{ id: '1' }], snapshot: 1 },
        { nodeId: 'eng', callId: 'call-3', tasks: [{ id: '1' }] },
      ],
    });
    expect(event?.taskList?.map((group) => group.snapshot)).toEqual([
      true,
      false,
      false,
    ]);
  });

  it('keeps the write moment a status announce carries, and only a real date', () => {
    // The sidebar's ORDER rides this field and compares the strings lexically,
    // so a value that is merely non-empty would not degrade to "no reorder" —
    // it would sort, wrongly, and stay there until the next refetch.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'running',
        activity: null,
        at: '2026-03-01T00:00:00.000Z',
      }),
    ).toEqual({
      runId: 'r1',
      status: 'running',
      activity: null,
      at: '2026-03-01T00:00:00.000Z',
    });
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'running',
        activity: null,
        at: 'soon',
      }),
    ).toEqual({ runId: 'r1', status: 'running', activity: null });
  });

  it('still rejects an UNRECOGNISED status outright', () => {
    // Version skew must degrade to no update at all. Folding it in as "no
    // status" would silently downgrade a real status change into an activity
    // update, which is worse than dropping the frame.
    expect(
      parseRunStatus({ runId: 'r1', status: 'zombie', activity: null }),
    ).toBeNull();
  });

  it('still reads a real status change', () => {
    expect(
      parseRunStatus({ runId: 'r1', status: 'completed', activity: null }),
    ).toEqual({ runId: 'r1', status: 'completed', activity: null });
  });

  it('keeps a settle’s NULL summary, so a wordless turn clears the last one', () => {
    // Three states, and the middle one is the whole fix: the client holds the
    // last sentence it was given, so a settle that said nothing has to say so
    // out loud. Dropped, a `/compact` turn — which produces no assistant
    // message at all — notified with the answer from the turn before it.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: null,
      }),
    ).toEqual({
      runId: 'r1',
      status: 'completed',
      activity: null,
      summary: null,
    });
    // …while an ABSENT one still asserts nothing, which is what lets an
    // activity announce fire mid-turn without erasing the last settle's words.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: 'running Bash' }),
    ).not.toHaveProperty('summary');
  });

  it('reads the housekeeping marker, and only when it is true', () => {
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: null,
        housekeeping: true,
      }),
    ).toMatchObject({ housekeeping: true });
    // A settle that did real work says nothing here rather than `false`, and a
    // daemon that predates the field is the same case — both must read as "not
    // housekeeping" without the key appearing.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: 'done',
      }),
    ).not.toHaveProperty('housekeeping');
  });

  it('reads the restored marker, and only when it is true', () => {
    // A delegate lease expiring hands an already-settled status back. It has to
    // arrive distinguishable from a fresh ending, or the client fires a second
    // `turn ended` banner for a turn that ended minutes ago.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        restored: true,
      }),
    ).toMatchObject({ restored: true });
    // A real settle says nothing here rather than `false`, and a daemon that
    // predates the field is the same case.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: 'done',
      }),
    ).not.toHaveProperty('restored');
  });

  it('leaves activity ABSENT when the announce carried none', () => {
    // The middle link of the naming-does-not-wipe-activity chain: the renderer
    // test asserts on a hand-built event, so without this the parser is free to
    // fold an absent key back into `null` and restore the bug.
    const parsed = parseRunStatus({ runId: 'r1', status: null, title: 'X' });

    expect(parsed).not.toHaveProperty('activity');
  });

  it('still clears on an explicit null activity', () => {
    // The other arm: a producer that DID read the run and found it idle has to
    // be able to say so.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: null }),
    ).toMatchObject({ activity: null });
  });

  it('reads the title a naming announce carries', () => {
    // `ChatTitleService` names a chat once its first turn ends, and sends it as
    // an activity-only announce — a null status, so the badge is left alone.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: null,
        activity: null,
        title: 'Fix Conflicts Worktree',
      }),
    ).toEqual({
      runId: 'r1',
      status: null,
      activity: null,
      title: 'Fix Conflicts Worktree',
    });
  });

  it('says nothing about the title on every other announce', () => {
    // Absent stays absent, like `awaiting` and `summary` beside it: an ordinary
    // settle must not be read as renaming the run to undefined.
    expect(
      parseRunStatus({ runId: 'r1', status: 'completed', activity: null }),
    ).not.toHaveProperty('title');
  });

  it('drops a blank or non-string title rather than clearing the name', () => {
    // A run is never UNnamed by this event, so an empty string is a skew to
    // ignore — applied, it would blank the sidebar row.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: null, title: '' }),
    ).not.toHaveProperty('title');
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: null, title: 42 }),
    ).not.toHaveProperty('title');
  });
});

describe('parseDeletedRunId — the run_deleted twin', () => {
  it('reads a real runId out of the envelope', () => {
    expect(parseDeletedRunId({ runId: 'r1' })).toBe('r1');
  });

  it('rejects a payload with no object shape at all', () => {
    // The whole reason this has its own reader rather than reusing
    // parseRunStatus: that one requires a status shape this event never
    // carries, so reusing it would refuse every deletion outright.
    expect(parseDeletedRunId(null)).toBeNull();
  });

  it('rejects an object carrying no runId', () => {
    expect(parseDeletedRunId({})).toBeNull();
  });

  it('rejects an empty runId rather than deleting every row', () => {
    // A blank string is not a run identity; degrading to null here means "no
    // ghost row gets cleared" rather than "clear every run in the sidebar".
    expect(parseDeletedRunId({ runId: '' })).toBeNull();
  });
});

describe('parseTaskChanged — the task_changed reader', () => {
  it('reads a whole event', () => {
    expect(
      parseTaskChanged({ taskId: 't1', projectId: 'p1', status: 'todo' }),
    ).toEqual({ taskId: 't1', projectId: 'p1', status: 'todo' });
  });

  it('refuses a payload that is not an object', () => {
    expect(parseTaskChanged(null)).toBeNull();
    expect(parseTaskChanged('task_changed')).toBeNull();
    expect(parseTaskChanged(7)).toBeNull();
  });

  it('refuses an event missing any of the three fields', () => {
    expect(parseTaskChanged({ projectId: 'p1', status: 'todo' })).toBeNull();
    expect(parseTaskChanged({ taskId: 't1', status: 'todo' })).toBeNull();
    expect(parseTaskChanged({ taskId: 't1', projectId: 'p1' })).toBeNull();
  });

  it('refuses a field of the wrong type rather than passing it through', () => {
    // The board keys a lookup on `status` and filters columns by it, so a
    // non-string here would reach that lookup as an object.
    expect(
      parseTaskChanged({ taskId: 't1', projectId: 'p1', status: { a: 1 } }),
    ).toBeNull();
    expect(
      parseTaskChanged({ taskId: 1, projectId: 'p1', status: 'todo' }),
    ).toBeNull();
  });

  it('passes a status string this build does not know', () => {
    // Deliberate: the daemon owns the vocabulary and a newer build of it may
    // send a status this renderer has never heard of. Dropping the event would
    // leave the card in a column it has left; the board renders an unknown
    // status as its own raw label instead.
    expect(
      parseTaskChanged({ taskId: 't1', projectId: 'p1', status: 'blocked' }),
    ).toEqual({ taskId: 't1', projectId: 'p1', status: 'blocked' });
  });
});
