import { beforeEach, describe, expect, it, vi } from 'vitest';

import type { DaemonHandle } from '../shared/contracts';
import type { ItemDto as ChatItem } from './autogenerated';
import { DaemonClient, parseRunStatus } from './daemon-client';

// A fake Socket.IO socket whose 'connect' handler and onAny dispatcher the test
// can drive directly. vi.hoisted so the vi.mock factory can close over it.
const mocks = vi.hoisted(() => {
  const handlers: Record<string, (...args: unknown[]) => void> = {};
  const ref: { any: ((event: string, data: unknown) => void) | null } = {
    any: null,
  };
  const emit = vi.fn();
  const close = vi.fn();
  const socket = {
    connected: false,
    on: (event: string, h: (...args: unknown[]) => void) => {
      handlers[event] = h;
    },
    onAny: (h: (event: string, data: unknown) => void) => {
      ref.any = h;
    },
    emit,
    close,
  };
  return { handlers, ref, emit, close, socket, io: vi.fn(() => socket) };
});

vi.mock('socket.io-client', () => ({ io: mocks.io }));

const handle: DaemonHandle = {
  host: '127.0.0.1',
  port: 8123,
  token: 'tok',
  version: '1',
};

function fireConnect(): void {
  mocks.socket.connected = true;
  mocks.handlers.connect?.();
}

function fireJoined(runId: string): void {
  mocks.ref.any?.('joined', { runId });
}

beforeEach(() => {
  mocks.emit.mockClear();
  mocks.close.mockClear();
  mocks.io.mockClear();
  mocks.socket.connected = false;
  mocks.ref.any = null;
  for (const key of Object.keys(mocks.handlers)) {
    delete mocks.handlers[key];
  }
});

describe('DaemonClient', () => {
  it('fires onReconnect only after the active room is re-joined', async () => {
    const client = new DaemonClient(handle, {});
    const reconnects: number[] = [];
    client.onReconnect(() => reconnects.push(1));
    client.connect();
    const initialJoin = client.joinRun('r1');

    // First connect is NOT a reconnect: no onReconnect, but the active room is
    // (re-)joined so live items resume.
    mocks.emit.mockClear();
    fireConnect();
    expect(reconnects).toHaveLength(0);
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    fireJoined('r1');
    await initialJoin;

    // Second connect IS a reconnect, but replay is held until the joined event.
    mocks.emit.mockClear();
    fireConnect();
    expect(reconnects).toHaveLength(0);
    expect(mocks.emit).toHaveBeenCalledWith('join', { runId: 'r1' });
    fireJoined('r1');
    await Promise.resolve();
    expect(reconnects).toHaveLength(1);
  });

  it('routes only `item` events from onAny to onItem subscribers', () => {
    const client = new DaemonClient(handle, {});
    const items: ChatItem[] = [];
    client.onItem((i) => items.push(i));
    client.connect();

    const item: ChatItem = {
      id: 'i0',
      runId: 'r1',
      nodeId: null,
      seq: 0,
      kind: 'message',
      role: 'assistant',
      payload: { text: 'hi' },
      createdAt: 'now',
    };
    mocks.ref.any?.('item', item);
    mocks.ref.any?.('other', { x: 1 });

    expect(items).toEqual([item]);
  });

  it('forwards a question answer in the exact verdict payload', () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    fireConnect();

    client.sendVerdict('r1', 'req-1', true, 'Blue');

    expect(mocks.emit).toHaveBeenCalledWith('verdict', {
      runId: 'r1',
      requestId: 'req-1',
      allow: true,
      answer: 'Blue',
    });
  });

  it('reports a failed connection ATTEMPT, with the reason', () => {
    // Socket.IO retries forever and reports nothing else, so without this the
    // renderer cannot tell "still connecting" from "will never connect" — and
    // a daemon that is down produced no signal in the UI at all.
    const onError = vi.fn();
    const client = new DaemonClient(handle, { onError });
    client.connect();

    mocks.handlers.connect_error?.(
      new Error('xhr poll error: connect ECONNREFUSED 127.0.0.1:8123'),
    );

    expect(onError).toHaveBeenCalledWith(
      'xhr poll error: connect ECONNREFUSED 127.0.0.1:8123 (127.0.0.1:8123)',
    );
  });

  it('names the endpoint, because Socket.IO’s own wording does not', () => {
    // Observed against a dead port: the whole reason reaching the UI was
    // "websocket error". True, and useless for the one thing the user can
    // act on — which port are we dialling, and is anything on it. Host and
    // port are negotiated per launch, so this client is the only place that
    // knows them.
    const onError = vi.fn();
    const client = new DaemonClient(handle, { onError });
    client.connect();

    mocks.handlers.connect_error?.(new Error('websocket error'));

    expect(onError).toHaveBeenCalledWith('websocket error (127.0.0.1:8123)');
  });

  it('never hands the renderer an empty reason to render', () => {
    // A transport error with a blank message would put an empty sentence on
    // the connection strip, which reads as a broken UI rather than a failure.
    const onError = vi.fn();
    const client = new DaemonClient(handle, { onError });
    client.connect();

    mocks.handlers.connect_error?.(new Error(''));

    expect(onError).toHaveBeenCalledWith(
      'could not reach the daemon (127.0.0.1:8123)',
    );
  });

  it('passes the disconnect REASON on, rather than just the fact', () => {
    // "transport close" (the daemon exited) and "io server disconnect" (it
    // rejected us) are different problems with different fixes.
    const onClose = vi.fn();
    const client = new DaemonClient(handle, { onClose });
    client.connect();
    fireConnect();

    mocks.handlers.disconnect?.('transport close');

    expect(onClose).toHaveBeenCalledWith('transport close');
  });

  it('leaveRun clears the active room so a later reconnect does not rejoin it', async () => {
    const client = new DaemonClient(handle, {});
    client.connect();
    fireConnect();
    const joined = client.joinRun('r1');
    fireJoined('r1');
    await joined;
    client.leaveRun('r1');

    mocks.emit.mockClear();
    fireConnect();
    expect(mocks.emit).not.toHaveBeenCalledWith('join', { runId: 'r1' });
  });
});

describe('parseRunStatus — the run_status twin', () => {
  it('reads an activity-only announce as carrying NO status', () => {
    // The daemon's activity announce fires on every tool call and never reads
    // the run, so it sends `status: null`. Read as a status, it would write a
    // guess onto the row — which is how a cancelled run went back to running.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: 'running Bash' }),
    ).toEqual({ runId: 'r1', status: null, activity: 'running Bash' });
  });

  it('reads a MISSING status the same way', () => {
    expect(parseRunStatus({ runId: 'r1', activity: 'running Bash' })).toEqual({
      runId: 'r1',
      status: null,
      activity: 'running Bash',
    });
  });

  it('keeps the write moment a status announce carries, and only a real date', () => {
    // The sidebar's ORDER rides this field and compares the strings lexically,
    // so a value that is merely non-empty would not degrade to "no reorder" —
    // it would sort, wrongly, and stay there until the next refetch.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'running',
        activity: null,
        at: '2026-03-01T00:00:00.000Z',
      }),
    ).toEqual({
      runId: 'r1',
      status: 'running',
      activity: null,
      at: '2026-03-01T00:00:00.000Z',
    });
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'running',
        activity: null,
        at: 'soon',
      }),
    ).toEqual({ runId: 'r1', status: 'running', activity: null });
  });

  it('still rejects an UNRECOGNISED status outright', () => {
    // Version skew must degrade to no update at all. Folding it in as "no
    // status" would silently downgrade a real status change into an activity
    // update, which is worse than dropping the frame.
    expect(
      parseRunStatus({ runId: 'r1', status: 'zombie', activity: null }),
    ).toBeNull();
  });

  it('still reads a real status change', () => {
    expect(
      parseRunStatus({ runId: 'r1', status: 'completed', activity: null }),
    ).toEqual({ runId: 'r1', status: 'completed', activity: null });
  });

  it('keeps a settle’s NULL summary, so a wordless turn clears the last one', () => {
    // Three states, and the middle one is the whole fix: the client holds the
    // last sentence it was given, so a settle that said nothing has to say so
    // out loud. Dropped, a `/compact` turn — which produces no assistant
    // message at all — notified with the answer from the turn before it.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: null,
      }),
    ).toEqual({
      runId: 'r1',
      status: 'completed',
      activity: null,
      summary: null,
    });
    // …while an ABSENT one still asserts nothing, which is what lets an
    // activity announce fire mid-turn without erasing the last settle's words.
    expect(
      parseRunStatus({ runId: 'r1', status: null, activity: 'running Bash' }),
    ).not.toHaveProperty('summary');
  });

  it('reads the housekeeping marker, and only when it is true', () => {
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: null,
        housekeeping: true,
      }),
    ).toMatchObject({ housekeeping: true });
    // A settle that did real work says nothing here rather than `false`, and a
    // daemon that predates the field is the same case — both must read as "not
    // housekeeping" without the key appearing.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: 'done',
      }),
    ).not.toHaveProperty('housekeeping');
  });

  it('reads the restored marker, and only when it is true', () => {
    // A delegate lease expiring hands an already-settled status back. It has to
    // arrive distinguishable from a fresh ending, or the client fires a second
    // `turn ended` banner for a turn that ended minutes ago.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        restored: true,
      }),
    ).toMatchObject({ restored: true });
    // A real settle says nothing here rather than `false`, and a daemon that
    // predates the field is the same case.
    expect(
      parseRunStatus({
        runId: 'r1',
        status: 'completed',
        activity: null,
        summary: 'done',
      }),
    ).not.toHaveProperty('restored');
  });
});
