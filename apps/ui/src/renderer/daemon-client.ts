import { io, type Socket } from 'socket.io-client';

import { type DaemonHandle } from '../shared/contracts';
import { type ItemDto as ChatItem, RunStatus } from './autogenerated';
import { type LiveTextEvent, parseLiveText } from './chats/live-text';

export interface DaemonClientEvents {
  onOpen?: () => void;
  onMessage?: (event: string, data: unknown) => void;
  /** `reason` is Socket.IO's own word for why the socket dropped. */
  onClose?: (reason: string) => void;
  /**
   * A connection ATTEMPT failed — the daemon is not answering, or it refused
   * the handshake token.
   *
   * Separate from `onClose` because the two are different facts and only this
   * one is actionable: a close is a live connection ending (often the daemon
   * restarting, and Socket.IO reconnects on its own), while this fires on
   * every retry of a connection that was never made. Without it a daemon that
   * is down produces no signal at all beyond a status dot changing colour —
   * which is the reported "if we have a problem with the api/connection we
   * should see it in the UI".
   */
  onError?: (message: string) => void;
}

/**
 * TWIN PARSER: mirrors the `verdict_ack` reply shape produced by the daemon's
 * `NotificationsGateway.verdict`
 * (apps/daemon/src/v1/notifications/gateways/notifications.gateway.ts) — no
 * daemon↔renderer shared package exists, so a shape change there must be
 * mirrored here, and vice versa.
 */
export interface VerdictAck {
  runId: string | null;
  requestId: string | null;
  status: 'applied' | 'expired' | 'invalid';
}

/**
 * TWIN PARSER: mirrors the daemon's `RunStatusEvent`
 * (apps/daemon/src/v1/agents/chat.types.ts), broadcast on `run_status`.
 * Outside the generated HTTP contract, so a shape change on either side MUST
 * be mirrored on the other.
 *
 * Broadcast to every client rather than to a run's room: the sidebar shows
 * runs the user is not looking at, and only the focused run's room delivers
 * items — so without this a background badge stayed stale until a refetch.
 */
export interface RunStatusEvent {
  runId: string;
  status: RunStatus;
  /** What the run is doing right now, or null when it is not doing anything. */
  activity: string | null;
}

/**
 * Read a `run_status` payload, or null when it is not one. Defensive because
 * the shape has no generated type behind it: a version skew must degrade to
 * "no live badge update", never to a crashed sidebar.
 */
export function parseRunStatus(data: unknown): RunStatusEvent | null {
  if (typeof data !== 'object' || data === null) {
    return null;
  }
  const { runId, status, activity } = data as Record<string, unknown>;
  if (typeof runId !== 'string' || runId.length === 0) {
    return null;
  }
  if (!RUN_STATUS_VALUES.has(status as RunStatus)) {
    return null;
  }
  return {
    runId,
    status: status as RunStatus,
    activity: typeof activity === 'string' && activity ? activity : null,
  };
}

/** The generated enum as a lookup, so an unknown status is rejected. */
const RUN_STATUS_VALUES: ReadonlySet<RunStatus> = new Set(
  Object.values(RunStatus),
);

const JOIN_TIMEOUT_MS = 5_000;

interface JoinWaiter {
  resolve: () => void;
  reject: (error: Error) => void;
  timer: ReturnType<typeof setTimeout>;
}

/**
 * Thin Socket.IO client to the loopback daemon. Authenticates with the
 * per-launch token via the handshake `auth` payload (browsers can't set WS
 * headers) and lets Socket.IO own reconnection. Forces the `websocket`
 * transport — no HTTP long-polling fallback is needed on loopback. M2 grows it
 * from the M1 hello/echo proof into the live run-event channel: `join`/`leave`
 * a run's room and receive its persisted `item` events.
 *
 * Socket.IO rooms are per-socket and server-side, so a transient
 * disconnect/reconnect lands a fresh socket id in NO rooms. The client tracks
 * the active run and re-emits `join` on every (re)connect, and fires
 * `onReconnect` so the renderer can fetch the items it missed while offline
 * (the room buffers nothing for an absent member).
 */
export class DaemonClient {
  private socket: Socket | null = null;
  private readonly itemListeners = new Set<(item: ChatItem) => void>();
  private readonly liveTextListeners = new Set<
    (event: LiveTextEvent) => void
  >();
  private readonly reconnectListeners = new Set<(error?: Error) => void>();
  private readonly disconnectListeners = new Set<() => void>();
  private readonly verdictAckListeners = new Set<(ack: VerdictAck) => void>();
  private readonly runStatusListeners = new Set<
    (event: RunStatusEvent) => void
  >();
  private readonly joinWaiters = new Map<string, Set<JoinWaiter>>();
  private activeRunId: string | null = null;
  private hasConnected = false;

  constructor(
    private readonly handle: DaemonHandle,
    private readonly events: DaemonClientEvents,
  ) {}

  connect(): void {
    const socket = io(`http://${this.handle.host}:${this.handle.port}`, {
      path: '/ws',
      transports: ['websocket'],
      auth: { token: this.handle.token },
    });
    this.socket = socket;

    socket.on('connect', () => {
      const isReconnect = this.hasConnected;
      this.hasConnected = true;
      // Re-join the active run's room so live items resume after a reconnect.
      let joined: Promise<void> | null = null;
      if (this.activeRunId) {
        if (isReconnect) {
          joined = this.waitForJoin(this.activeRunId);
        }
        socket.emit('join', { runId: this.activeRunId });
      }
      this.events.onOpen?.();
      if (isReconnect) {
        void (joined ?? Promise.resolve())
          .then(() => {
            for (const listener of this.reconnectListeners) {
              listener();
            }
          })
          .catch((err: unknown) => {
            const error = err instanceof Error ? err : new Error(String(err));
            for (const listener of this.reconnectListeners) {
              listener(error);
            }
          });
      }
    });
    socket.on('disconnect', (reason: string) => {
      this.rejectAllJoins('socket disconnected before joining run');
      for (const listener of this.disconnectListeners) {
        listener();
      }
      this.events.onClose?.(reason);
    });
    // Every failed ATTEMPT, including each automatic retry. Socket.IO keeps
    // retrying forever and reports nothing else, so this is the only place the
    // renderer can learn that the daemon is unreachable or rejecting the
    // token — the difference between "still connecting" and "will never
    // connect", which the UI otherwise had no way to tell the user about.
    socket.on('connect_error', (err: Error) => {
      // The ADDRESS is included because Socket.IO's own wording for a refused
      // loopback connection is the bare "websocket error" — true, and useless
      // for the one question the user can act on: which port are we dialling,
      // and is anything listening on it. The client is the only place that
      // knows, since host and port are negotiated per launch.
      const endpoint = `${this.handle.host}:${this.handle.port}`;
      const reason = err.message || 'could not reach the daemon';
      this.events.onError?.(`${reason} (${endpoint})`);
    });
    socket.onAny((event: string, data: unknown) => {
      this.events.onMessage?.(event, data);
      if (event === 'joined') {
        this.resolveJoined(data);
      }
      if (event === 'item') {
        const item = data as ChatItem;
        for (const listener of this.itemListeners) {
          listener(item);
        }
      }
      if (event === 'agent_delta') {
        // The EPHEMERAL live-text plane (see chats/live-text.ts, the twin of
        // the daemon's RunDeltaEvent). Nothing here is persisted, so a dropped
        // event costs nothing: the next one carries the whole tail again.
        const live = parseLiveText(data);
        if (live) {
          for (const listener of this.liveTextListeners) {
            listener(live);
          }
        }
      }
      if (event === 'run_status') {
        const status = parseRunStatus(data);
        if (status) {
          for (const listener of this.runStatusListeners) {
            listener(status);
          }
        }
      }
      if (event === 'verdict_ack') {
        const ack = data as VerdictAck;
        for (const listener of this.verdictAckListeners) {
          listener(ack);
        }
      }
    });
  }

  /** Subscribe to live assistant text (the non-durable growing bubble). */
  onLiveText(listener: (event: LiveTextEvent) => void): () => void {
    this.liveTextListeners.add(listener);
    return () => {
      this.liveTextListeners.delete(listener);
    };
  }

  /**
   * Subscribe to verdict acknowledgments. Only `expired` means the request
   * already settled; `invalid` remains retryable.
   */
  onVerdictAck(listener: (ack: VerdictAck) => void): () => void {
    this.verdictAckListeners.add(listener);
    return () => {
      this.verdictAckListeners.delete(listener);
    };
  }

  /**
   * Subscribe to run-status changes for EVERY run, not just the focused one —
   * this is what keeps a background chat's badge honest.
   */
  onRunStatus(listener: (event: RunStatusEvent) => void): () => void {
    this.runStatusListeners.add(listener);
    return () => {
      this.runStatusListeners.delete(listener);
    };
  }

  /** Subscribe to streamed run items; returns an unsubscribe function. */
  onItem(listener: (item: ChatItem) => void): () => void {
    this.itemListeners.add(listener);
    return () => {
      this.itemListeners.delete(listener);
    };
  }

  /**
   * Subscribe to reconnects (not the first connect); returns an unsubscribe
   * function. The renderer uses this to fetch items missed while offline.
   */
  onReconnect(listener: (error?: Error) => void): () => void {
    this.reconnectListeners.add(listener);
    return () => {
      this.reconnectListeners.delete(listener);
    };
  }

  onDisconnect(listener: () => void): () => void {
    this.disconnectListeners.add(listener);
    return () => {
      this.disconnectListeners.delete(listener);
    };
  }

  /** Join a run's room to start receiving its `item` events. */
  joinRun(runId: string): Promise<void> {
    this.activeRunId = runId;
    const joined = this.waitForJoin(runId);
    if (this.socket?.connected) {
      this.socket.emit('join', { runId });
    }
    return joined;
  }

  /** Leave a run's room. */
  leaveRun(runId: string): void {
    if (this.activeRunId === runId) {
      this.activeRunId = null;
    }
    this.rejectJoins(runId, 'run room was left before joining');
    this.socket?.emit('leave', { runId });
  }

  /**
   * Answer an `ask`-node's approval card. The durable acknowledgment is the
   * `approval_verdict` item the daemon persists-then-emits back to the room;
   * the immediate `verdict_ack` reply only reports routing (`expired` means
   * already settled; `invalid` remains retryable).
   * `answer` carries the user's picked option / typed text for a question
   * card (AskUserQuestion) — omitted for plain tool approvals.
   *
   * TWIN PARSER: the daemon parses this `verdict` envelope in
   * `extractVerdict`
   * (apps/daemon/src/v1/notifications/gateways/notifications.gateway.ts) —
   * `{runId, requestId, allow, answer?}`, `answer` honored only as a
   * non-empty string ≤ MAX_ANSWER_LENGTH. A shape change here must be
   * mirrored there, and vice versa.
   */
  sendVerdict(
    runId: string,
    requestId: string,
    allow: boolean,
    answer?: string,
  ): void {
    this.socket?.emit('verdict', {
      runId,
      requestId,
      allow,
      ...(answer !== undefined ? { answer } : {}),
    });
  }

  close(): void {
    this.rejectAllJoins('socket closed before joining run');
    this.socket?.close();
    this.socket = null;
  }

  private waitForJoin(runId: string): Promise<void> {
    return new Promise((resolve, reject) => {
      const waiter: JoinWaiter = {
        resolve,
        reject,
        timer: setTimeout(() => {
          this.removeJoinWaiter(runId, waiter);
          reject(new Error(`timed out joining run ${runId}`));
        }, JOIN_TIMEOUT_MS),
      };
      const waiters = this.joinWaiters.get(runId) ?? new Set<JoinWaiter>();
      waiters.add(waiter);
      this.joinWaiters.set(runId, waiters);
    });
  }

  private resolveJoined(data: unknown): void {
    const runId =
      typeof data === 'object' &&
      data !== null &&
      typeof (data as { runId?: unknown }).runId === 'string'
        ? (data as { runId: string }).runId
        : null;
    if (!runId) {
      return;
    }
    const waiters = this.joinWaiters.get(runId);
    if (!waiters) {
      return;
    }
    this.joinWaiters.delete(runId);
    for (const waiter of waiters) {
      clearTimeout(waiter.timer);
      waiter.resolve();
    }
  }

  private rejectJoins(runId: string, message: string): void {
    const waiters = this.joinWaiters.get(runId);
    if (!waiters) {
      return;
    }
    this.joinWaiters.delete(runId);
    for (const waiter of waiters) {
      clearTimeout(waiter.timer);
      waiter.reject(new Error(message));
    }
  }

  private rejectAllJoins(message: string): void {
    for (const runId of [...this.joinWaiters.keys()]) {
      this.rejectJoins(runId, message);
    }
  }

  private removeJoinWaiter(runId: string, waiter: JoinWaiter): void {
    const waiters = this.joinWaiters.get(runId);
    if (!waiters) {
      return;
    }
    waiters.delete(waiter);
    if (waiters.size === 0) {
      this.joinWaiters.delete(runId);
    }
  }
}
