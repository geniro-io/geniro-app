/** The three statuses a task row may carry; anything else reads as unknown. */
const TASK_STATUSES = new Set(['pending', 'in_progress', 'completed']);

/**
 * The task groups in a socket payload, keeping only the readable rows.
 *
 * Defensive for the reason {@link readPullRequestRefs} is: this is one of the
 * two shapes that arrive untyped, the generated client covering every other
 * route. An unreadable ROW is dropped rather than the group, because the chip
 * states `done/total` — losing one row shifts a count by one, while dropping the
 * group blanks a list the agent is visibly working through. Only `id` is
 * required: a patch legitimately carries no title, which is exactly why the
 * daemon's fold exists.
 */
function readTaskGroups(groups: readonly unknown[]): RunTaskGroup[] {
  const out: RunTaskGroup[] = [];
  for (const group of groups) {
    if (group === null || typeof group !== 'object') {
      continue;
    }
    const { nodeId, tasks } = group as Record<string, unknown>;
    if (!Array.isArray(tasks)) {
      continue;
    }
    const rows: RunTaskRow[] = [];
    for (const task of tasks) {
      if (task === null || typeof task !== 'object') {
        continue;
      }
      const { id, title, status, activeForm } = task as Record<string, unknown>;
      if (typeof id !== 'string' || id === '') {
        continue;
      }
      rows.push({
        id,
        title: typeof title === 'string' && title !== '' ? title : null,
        status:
          typeof status === 'string' && TASK_STATUSES.has(status)
            ? (status as RunTaskRow['status'])
            : null,
        activeForm:
          typeof activeForm === 'string' && activeForm !== ''
            ? activeForm
            : null,
      });
    }
    out.push({
      nodeId: typeof nodeId === 'string' ? nodeId : null,
      tasks: rows,
    });
  }
  return out;
}

/**
 * The pull-request refs in a socket payload, keeping only the whole ones.
 *
 * A REF is four fields and each is load-bearing downstream: the URL is what
 * `gh pr view` is addressed with, and the owner/repo/number are what a row is
 * named from. Anything short of all four is dropped rather than patched, since
 * a half-ref renders as a chip pointing nowhere — and this is the one place the
 * shapes arrive untyped, the generated client covering every other route.
 */
function readPullRequestRefs(rows: readonly unknown[]): RunPullRequest[] {
  const refs: RunPullRequest[] = [];
  for (const row of rows) {
    if (row === null || typeof row !== 'object') {
      continue;
    }
    const { owner, repo, number, url, seq } = row as Record<string, unknown>;
    if (
      typeof owner === 'string' &&
      owner !== '' &&
      typeof repo === 'string' &&
      repo !== '' &&
      typeof number === 'number' &&
      Number.isFinite(number) &&
      typeof url === 'string' &&
      url !== ''
    ) {
      // `seq` is the transcript position the capture recorded, and it only
      // orders them — the POSITION in the array already says the same thing,
      // so a payload that omits it falls back to that rather than losing the
      // ref over a field no surface reads.
      refs.push({
        owner,
        repo,
        number,
        url,
        seq:
          typeof seq === 'number' && Number.isFinite(seq) ? seq : refs.length,
      });
    }
  }
  return refs;
}

export interface DaemonClientEvents {
  onOpen?: () => void;
  onMessage?: (event: string, data: unknown) => void;
  /** `reason` is Socket.IO's own word for why the socket dropped. */
  onClose?: (reason: string) => void;
  /**
   * A connection ATTEMPT failed — the daemon is not answering, or it refused
   * the handshake token.
   *
   * Separate from `onClose` because the two are different facts and only this
   * one is actionable: a close is a live connection ending (often the daemon
   * restarting, and Socket.IO reconnects on its own), while this fires on
   * every retry of a connection that was never made. Without it a daemon that
   * is down produces no signal at all beyond a status dot changing colour —
   * which is the reported "if we have a problem with the api/connection we
   * should see it in the UI".
   */
  onError?: (message: string) => void;
}

