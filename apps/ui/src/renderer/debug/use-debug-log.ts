import { useCallback, useEffect, useRef, useState } from 'react';

import type { DebugChannel } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient, DebugLogEntry } from '../daemon-client';

/**
 * How many entries the panel keeps.
 *
 * Smaller than the daemon's own ring on purpose: this list re-renders, and a
 * panel holding tens of thousands of rows would make the app it is meant to
 * diagnose the slow one. The FILE is the place with no ceiling, which is why
 * the panel says where it is.
 */
export const PANEL_CAPACITY = 3_000;

export interface DebugLogState {
  entries: DebugLogEntry[];
  channels: DebugChannel[];
  /** Absolute path of the daemon's log file, once it has told us. */
  filePath: string | null;
  /** Entries the daemon's ring dropped before we could read them. */
  dropped: number;
  /** Live streaming is paused — the list holds still while you read it. */
  paused: boolean;
  error: string | null;
  loading: boolean;
}

/**
 * The debug panel's data: a REST backfill for what already happened, then the
 * live WS stream for what happens next.
 *
 * The two halves are the same shape the transcript uses, for the same reason —
 * a panel opened mid-incident must show the lines that led up to it, not only
 * the ones after someone thought to look. They are stitched on `seq`, which is
 * monotonic per daemon launch and (unlike the transcript's, before it was
 * fixed) has exactly one writer.
 *
 * Nothing is fetched and nothing is streamed until `active` — the daemon only
 * sends the debug room to sockets that asked, and asking is the act of opening
 * the panel.
 */
export function useDebugLog(
  apis: DaemonApis,
  client: DaemonClient,
  active: boolean,
): DebugLogState & {
  setChannels: (channels: DebugChannel[]) => void;
  setPaused: (paused: boolean) => void;
  clear: () => void;
  refresh: () => void;
} {
  const [entries, setEntries] = useState<DebugLogEntry[]>([]);
  const [channels, setChannelsState] = useState<DebugChannel[]>([]);
  const [filePath, setFilePath] = useState<string | null>(null);
  const [dropped, setDropped] = useState(0);
  const [paused, setPaused] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const lastSeqRef = useRef(-1);
  // Read by the socket callback, which is registered once — state would be
  // captured stale there, and a paused panel would keep growing.
  const pausedRef = useRef(paused);
  pausedRef.current = paused;

  const append = useCallback((incoming: DebugLogEntry[]): void => {
    if (incoming.length === 0) {
      return;
    }
    setEntries((prev) => {
      // De-duped by SEQ here, unlike the transcript — and that is sound for
      // exactly the reason it was not there: this stream has ONE writer (the
      // sink allocates every seq itself), so a repeated seq can only be the
      // same line arriving twice across the backfill/live seam.
      const seen = new Set(prev.map((entry) => entry.seq));
      const fresh = incoming.filter((entry) => !seen.has(entry.seq));
      if (fresh.length === 0) {
        return prev;
      }
      const next = [...prev, ...fresh].sort((a, b) => a.seq - b.seq);
      return next.length > PANEL_CAPACITY
        ? next.slice(next.length - PANEL_CAPACITY)
        : next;
    });
  }, []);

  const refresh = useCallback((): void => {
    setLoading(true);
    void apis.diagnostics
      .readDebugLog({ afterSeq: lastSeqRef.current })
      .then((page) => {
        setChannelsState(page.channels as DebugChannel[]);
        setFilePath(page.filePath ?? null);
        setDropped((prev) => prev + page.dropped);
        lastSeqRef.current = page.lastSeq;
        append(page.entries as DebugLogEntry[]);
        setError(null);
      })
      .catch((err: unknown) => setError(String(err)))
      .finally(() => setLoading(false));
  }, [apis, append]);

  // Backfill + live, gated on the panel being open.
  useEffect(() => {
    if (!active) {
      // Tell the daemon to stop sending. Without this the socket keeps
      // receiving every agent-stdio line for the rest of the session because
      // the panel was open once.
      client.setDebugStream(false);
      return;
    }
    refresh();
    client.setDebugStream(true);
    const off = client.onDebugEntry((entry) => {
      if (pausedRef.current) {
        // Dropped, not buffered. A pause that silently accumulated would
        // dump thousands of lines the moment it was released — and the point
        // of pausing is to stop the list moving, not to defer the movement.
        return;
      }
      lastSeqRef.current = Math.max(lastSeqRef.current, entry.seq);
      append([entry]);
    });
    return () => {
      off();
      client.setDebugStream(false);
    };
  }, [active, client, refresh, append]);

  // A RESUMED panel re-reads: while paused the live entries were discarded, so
  // the daemon's ring is the only place that gap still exists.
  //
  // Gated on the paused→running TRANSITION, not on `!paused`. Without the
  // previous value this effect also fires on mount, where the effect above has
  // already fetched — two identical reads per open, and every `dropped` count
  // added to the total twice.
  const wasPaused = useRef(paused);
  useEffect(() => {
    const resumed = wasPaused.current && !paused;
    wasPaused.current = paused;
    if (active && resumed) {
      refresh();
    }
  }, [active, paused, refresh]);

  const setChannels = useCallback(
    (next: DebugChannel[]): void => {
      // Optimistic, then corrected by the daemon's own echo: the switch is a
      // toggle the user is holding, and waiting a round-trip to move it reads
      // as a control that does not work.
      setChannelsState(next);
      void apis.diagnostics
        .setDebugChannels({ debugSettingsDto: { channels: next } })
        .then((result) => setChannelsState(result.channels as DebugChannel[]))
        .catch((err: unknown) => setError(String(err)));
    },
    [apis],
  );

  const clear = useCallback((): void => {
    // The PANEL's view only — the daemon's ring and the file are untouched,
    // and they are the record. This is "stop showing me what I have read".
    setEntries([]);
    setDropped(0);
  }, []);

  return {
    entries,
    channels,
    filePath,
    dropped,
    paused,
    error,
    loading,
    setChannels,
    setPaused,
    clear,
    refresh,
  };
}
