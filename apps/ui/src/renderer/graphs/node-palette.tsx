const INSTRUCTION_META: TileMeta = {
  label: 'Instructions',
  blurb: 'A block of instructions you wire to the agents it applies to.',
  details: [
    'Its text is appended to the turn of every agent you connect it to.',
    'Ranks after your global custom instructions and before that node’s own role.',
    'Runs nothing and is never a step — it has no status and cannot fail.',
    'Wire one block to several agents, or several blocks to one agent.',
  ],
  icon: <ScrollText aria-hidden="true" className="size-4" />,
};

function metaOf(item: PaletteItem): TileMeta {
  if (item.kind === 'agent') {
    return AGENT_META[item.agent];
  }
  if (item.kind === 'trigger') {
    return TRIGGER_META[item.trigger];
  }
  return INSTRUCTION_META;
}

/** Concrete node types matching a connection rule's kind (partner chips). */
function partnersOf(kind: NodeKind): string[] {
  if (kind === 'agent') {
    return CLI_KINDS.map((k) => AGENT_META[k].label);
  }
  if (kind === 'trigger') {
    return TRIGGER_KINDS.map((k) => TRIGGER_META[k].label);
  }
  return [INSTRUCTION_META.label];
}

// Persisted panel state (survives tab switches / reloads; the builder unmounts
// on every nav change so component state alone would reset the width + fold).
const LS_WIDTH = 'geniro.builder.paletteWidth';
const LS_COLLAPSED = 'geniro.builder.paletteCollapsed';
// There were three more keys here, one per category fold. The folds are gone
// (see `Category`), so the keys are too — including the pair of generations of
// them this file had already accumulated. Nothing migrates: a remembered fold
// is not the user's data, and the categories no longer have a state to restore.

/**
 * One connection rule row in the info dialog: the port dot (input/output
 * colored like the canvas handles), the accepted node kind with its
 * single/multiple arity, the rule description, and the concrete node types
 * matching the rule.
 */
function RuleRow({
  rule,
  direction,
}: {
  rule: ConnectionRule;
  direction: 'input' | 'output';
}): React.JSX.Element {
  return (
    <div className="flex items-start gap-2 px-3 py-2">
      <span
        aria-hidden="true"
        className={cn(
          'mt-1 size-2 shrink-0 rounded-full',
          // Call rules mirror their amber canvas handles; every other rule
          // keeps the input/output tones its handle is painted in.
          rule.edge === 'call'
            ? 'bg-warning'
            : direction === 'input'
              ? 'bg-primary'
              : 'bg-success',
        )}
      />
      <div className="flex min-w-0 flex-col gap-1">
        <span className="flex flex-wrap items-center gap-1.5">
          <code className="text-xs font-semibold">{rule.kind}</code>
          {/* Data flow is the unmarked case; every other wire names itself. */}
          {rule.edge !== 'data' ? (
            <Badge variant="muted">{rule.edge}</Badge>
          ) : null}
          <Badge variant="muted">{rule.multiple ? 'multiple' : 'single'}</Badge>
          {rule.required ? <Badge variant="secondary">required</Badge> : null}
          {partnersOf(rule.kind).map((label) => (
            <Badge key={label} variant="outline">
              {label}
            </Badge>
          ))}
        </span>
        <span className="text-xs text-muted-foreground">
          {rule.description}
        </span>
      </div>
    </div>
  );
}

/**
 * One draggable palette tile. Drag it onto the canvas to add a node; click it
 * to open its info dialog (never adds on click).
 */
function PaletteTile({
  item,
  onInfo,
}: {
  item: PaletteItem;
  onInfo: (item: PaletteItem) => void;
}): React.JSX.Element {
  const meta = metaOf(item);
  return (
    <button
      type="button"
      draggable
      onDragStart={(event) => {
        event.dataTransfer.setData(NODE_DND_MIME, JSON.stringify(item));
        event.dataTransfer.effectAllowed = 'move';
      }}
      onClick={() => onInfo(item)}
      className="flex cursor-grab items-start gap-2.5 rounded-lg border border-border bg-card px-3 py-2.5 text-left transition-all hover:border-primary/40 hover:shadow-panel-sm active:cursor-grabbing">
      <span
        className={cn(
          'mt-0.5 flex size-7 shrink-0 items-center justify-center rounded-full',
          item.kind === 'trigger'
            ? 'bg-success/15 text-success'
            : 'bg-primary/15 text-primary',
        )}>
        {meta.icon}
      </span>
      <span className="min-w-0">
        <span className="block text-sm font-medium">{meta.label}</span>
        {/* No `block` beside the clamp. `line-clamp-2` works by setting
            `display: -webkit-box`, so a `display: block` utility on the same
            element silently cancels it — measured here as three-line blurbs in
            a 240px column under a class that promised two. The clamp is
            block-level by construction, so nothing is lost by dropping it. */}
        <span className="mt-0.5 line-clamp-2 text-xs leading-relaxed text-muted-foreground">
          {meta.blurb}
        </span>
      </span>
    </button>
  );
}

/**
 * One category of the drawer — a caption and its tiles. It does NOT fold.
 *
 * It used to, and that was three accordions guarding FOUR tiles in total: one
 * trigger, two agents, one instruction block. Collapsed by default, so the
 * whole drawer opened as three closed rows in a 330px column with some 900px of
 * dead space under them, and reaching any single item cost a click that could
 * only ever reveal one or two. A fold earns its keep on a list that outgrows the
 * column; this one is bounded by how many CLIs the app supports.
 *
 * Going with it: three persisted localStorage flags, three pieces of state, and
 * a bare numeral beside each title — `TRIGGER_KINDS.length`, how many TYPES the
 * drawer offers, sitting a few centimetres from a canvas holding a different
 * number of the same noun (`Agents 2` beside four agent nodes). A count with no
 * noun next to a graph is read as a count OF the graph.
 */
function Category({
  title,
  children,
}: {
  title: string;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <section className="flex flex-col gap-1.5">
      <h3 className="px-1 text-[11px] font-medium uppercase tracking-wide text-muted-foreground">
        {title}
      </h3>
      <div className="flex flex-col gap-1">{children}</div>
    </section>
  );
}

/**
 * The builder's left palette: every node type the app can drop, under a caption
 * per category, plus a fold control that shrinks the whole panel to a slim rail
 * and a drag-to-resize right edge. Panel width and the rail fold persist in
 * localStorage; the categories themselves no longer fold — see {@link Category}.
 * Nodes are added by dragging a tile onto the canvas OR from the tile's info
 * dialog ("Add to canvas" — the keyboard path); clicking a tile opens that
 * dialog.
 */
export function NodePalette({
  onAdd,
}: {
  /** Position-less add (the canvas stacks it to the right) — the keyboard path. */
  onAdd?: (item: PaletteItem) => void;
}): React.JSX.Element {
  const [collapsed, setCollapsed] = usePersistedFlag(LS_COLLAPSED, false);
  const { width, minWidth, maxWidth, startResize, resizeTo } = usePanelWidth({
    storageKey: LS_WIDTH,
    defaultWidth: 240,
    minWidth: 180,
    maxWidth: 400,
    handleEdge: 'right',
  });
  const [infoItem, setInfoItem] = useState<PaletteItem | null>(null);

  const closeInfo = useCallback(() => setInfoItem(null), []);

  const infoMeta = infoItem ? metaOf(infoItem) : null;
  const infoRules = infoItem ? NODE_CONNECTION_RULES[infoItem.kind] : null;
  const infoDialog = (
    <Dialog
      open={infoItem !== null}
      onClose={closeInfo}
      title={infoMeta?.label}
      className="max-w-lg">
      {infoItem && infoMeta && infoRules ? (
        <div className="flex flex-col gap-4">
          <div className="flex items-center gap-2.5">
            <span
              className={cn(
                'flex size-9 shrink-0 items-center justify-center rounded-full',
                infoItem.kind === 'trigger'
                  ? 'bg-success/15 text-success'
                  : 'bg-primary/15 text-primary',
              )}>
              {infoMeta.icon}
            </span>
            <div className="min-w-0">
              <p className="text-sm text-muted-foreground">{infoMeta.blurb}</p>
              {infoMeta.command ? (
                <p className="mt-0.5 text-xs text-muted-foreground">
                  CLI:{' '}
                  <code className="rounded bg-muted px-1 py-0.5">
                    {infoMeta.command}
                  </code>
                </p>
              ) : null}
            </div>
          </div>
          <ul className="flex flex-col gap-1.5">
            {infoMeta.details.map((detail) => (
              <li
                key={detail}
                className="flex gap-2 text-sm text-muted-foreground">
                <span aria-hidden="true" className="text-primary">
                  •
                </span>
                <span>{detail}</span>
              </li>
            ))}
          </ul>

          <section className="flex flex-col gap-1.5">
            <h3 className="text-xs font-semibold tracking-wide text-muted-foreground uppercase">
              Node schema
            </h3>
            <p className="text-xs text-muted-foreground">
              Every {infoItem.kind} node shares this same schema.
            </p>
            <ul
              aria-label="Node schema"
              className="flex flex-col divide-y divide-border overflow-hidden rounded-md border border-border">
              {NODE_TYPE_SCHEMAS[infoItem.kind].map((field) => (
                <li key={field.key} className="flex flex-col gap-0.5 px-3 py-2">
                  <span className="flex items-center gap-2">
                    <code className="text-xs font-semibold">{field.key}</code>
                    <span className="text-xs text-muted-foreground">
                      {field.type}
                    </span>
                    <Badge
                      variant={field.required ? 'secondary' : 'muted'}
                      className="ml-auto">
                      {field.required ? 'required' : 'optional'}
                    </Badge>
                  </span>
                  <span className="text-xs text-muted-foreground">
                    {field.description}
                  </span>
                </li>
              ))}
            </ul>
          </section>

          <section className="flex flex-col gap-1.5">
            <h3 className="text-xs font-semibold tracking-wide text-muted-foreground uppercase">
              Connections
            </h3>
            <p className="text-xs text-muted-foreground">
              Typed per node kind — only listed pairs can be wired on the
              canvas.
            </p>
            <div
              aria-label="Connection rules"
              className="flex flex-col divide-y divide-border overflow-hidden rounded-md border border-border">
              <div>
                <p className="px-3 pt-2 text-xs font-medium">Inputs</p>
                {infoRules.inputs.length === 0 ? (
                  <p className="px-3 pt-1 pb-2 text-xs text-muted-foreground">
                    {/* A block has no inputs for a different reason than a
                        trigger does: it is not an entry point, it simply
                        cannot be fed. */}
                    {infoItem.kind === 'instruction'
                      ? 'None — nothing feeds a block; it only hands its text to the agents you wire it to.'
                      : `None — nothing can feed a ${infoItem.kind} node; it is an entry point.`}
                  </p>
                ) : (
                  infoRules.inputs.map((rule) => (
                    <RuleRow
                      key={`in-${rule.edge}-${rule.kind}`}
                      rule={rule}
                      direction="input"
                    />
                  ))
                )}
              </div>
              <div>
                <p className="px-3 pt-2 text-xs font-medium">Outputs</p>
                {infoRules.outputs.map((rule) => (
                  <RuleRow
                    key={`out-${rule.edge}-${rule.kind}`}
                    rule={rule}
                    direction="output"
                  />
                ))}
              </div>
            </div>
          </section>

          <div className="flex items-center justify-between gap-3 rounded-md bg-muted px-3 py-2">
            <p className="m-0 text-xs text-muted-foreground">
              Drag this {infoItem.kind} onto the canvas — or add it directly.
            </p>
            {onAdd ? (
              <Button
                type="button"
                size="sm"
                onClick={() => {
                  onAdd(infoItem);
                  closeInfo();
                }}>
                Add to canvas
              </Button>
            ) : null}
          </div>
        </div>
      ) : null}
    </Dialog>
  );

  if (collapsed) {
    return (
      <aside className="flex w-9 shrink-0 flex-col items-center gap-2 border-r border-border bg-muted/40 py-3">
        <Button
          type="button"
          variant="ghost"
          size="icon"
          aria-label="Expand palette"
          onClick={() => setCollapsed(false)}
          className="size-7 text-muted-foreground">
          <ChevronRight className="size-4" />
        </Button>
        <span className="mt-1 rotate-180 text-xs font-medium text-muted-foreground [writing-mode:vertical-rl]">
          Palette
        </span>
      </aside>
    );
  }

  return (
    <aside
      style={{ width }}
      className="relative flex min-h-0 shrink-0 flex-col border-r border-border bg-muted/40">
      <div className="flex-shrink-0 border-b border-border bg-card px-3 py-2.5">
        <div className="flex items-center justify-between">
          <span className="text-sm font-semibold">Palette</span>
          <Button
            type="button"
            variant="ghost"
            size="icon"
            aria-label="Collapse palette"
            onClick={() => setCollapsed(true)}
            className="size-6 text-muted-foreground">
            <ChevronLeft className="size-4" />
          </Button>
        </div>
        <p className="mt-0.5 text-xs text-muted-foreground">
          Drag onto the canvas; click for details.
        </p>
      </div>

      <div className="flex min-h-0 flex-1 flex-col gap-4 overflow-y-auto p-2">
        <Category title="Triggers">
          {TRIGGER_KINDS.map((trigger) => (
            <PaletteTile
              key={trigger}
              item={{ kind: 'trigger', trigger }}
              onInfo={setInfoItem}
            />
          ))}
        </Category>

        <Category title="Agents">
          {CLI_KINDS.map((agent) => (
            <PaletteTile
              key={agent}
              item={{ kind: 'agent', agent }}
              onInfo={setInfoItem}
            />
          ))}
        </Category>

        <Category title="Instructions">
          <PaletteTile item={{ kind: 'instruction' }} onInfo={setInfoItem} />
        </Category>
      </div>

      <PanelResizeHandle
        edge="right"
        label="Resize palette"
        onMouseDown={startResize}
        value={width}
        min={minWidth}
        max={maxWidth}
        onResize={resizeTo}
      />

      {infoDialog}
    </aside>
  );
}
