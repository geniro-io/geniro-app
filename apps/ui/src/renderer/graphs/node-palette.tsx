/**
 * Drag payload MIME for dropping a palette entry onto the canvas. The value
 * is a JSON `PaletteItem`; `Graphs`' canvas `onDrop` reads it back and adds
 * the node at the drop position. Clicking a tile opens its info dialog — it
 * does NOT add a node (matches geniro: drag to add, click for details).
 */
export const NODE_DND_MIME = 'application/geniro-node';

/**
 * One draggable palette entry — a node kind plus its concrete variant, where
 * the kind HAS variants. An instruction block has none: what distinguishes two
 * blocks is the text somebody writes into them afterwards.
 */
export type PaletteItem =
  | { kind: 'agent'; agent: CliKind }
  | { kind: 'trigger'; trigger: TriggerKind }
  | { kind: 'instruction' };

/** Parse a DnD payload back into a PaletteItem (null on garbage). */
export function parsePaletteItem(payload: string): PaletteItem | null {
  try {
    const item = JSON.parse(payload) as PaletteItem;
    if (item.kind === 'agent' && CLI_KINDS.includes(item.agent)) {
      return item;
    }
    if (item.kind === 'trigger' && TRIGGER_KINDS.includes(item.trigger)) {
      return item;
    }
    if (item.kind === 'instruction') {
      return item;
    }
    return null;
  } catch {
    return null;
  }
}

/**
 * The workflow node a palette tile drops onto the canvas.
 *
 * A block is created EMPTY on purpose — it is dropped before it is written,
 * which is the whole reason the schema admits `''` — and the card and the
 * inspector both say the text is still missing.
 */
export function paletteNode(item: PaletteItem, id: string): WorkflowNode {
  if (item.kind === 'trigger') {
    return { id, kind: 'trigger', trigger: item.trigger };
  }
  if (item.kind === 'instruction') {
    return { id, kind: 'instruction', instructions: '' };
  }
  return { id, kind: 'agent', agent: item.agent, approval: 'auto' };
}

interface TileMeta {
  label: string;
  blurb: string;
  details: string[];
  icon: React.ReactNode;
  /** The `CLI:` line for agents; omitted for triggers. */
  command?: string;
}

