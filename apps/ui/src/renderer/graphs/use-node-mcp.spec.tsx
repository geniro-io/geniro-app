// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { CliKind } from '../../shared/contracts';
import type { AgentMcpListingDto as AgentMcpListing } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { type NodeMcpState, useNodeMcp } from './use-node-mcp';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

function listing(...names: string[]): AgentMcpListing {
  return {
    servers: names.map((name) => ({
      name,
      target: `node ${name}.js`,
      transport: 'stdio',
      status: 'connected',
      detail: null,
      scope: 'other',
      disabled: false,
      toggleUnavailableReason: 'not a project server',
    })),
    unavailableReason: null,
  } as unknown as AgentMcpListing;
}

/** Drive the hook and expose its latest value, plus a way to re-render it. */
function mount(
  agentsApi: DaemonApis['agents'],
  agent: CliKind | null,
  pluginDir: string | null,
): {
  latest: () => NodeMcpState;
  rerender: (agent: CliKind | null, pluginDir: string | null) => void;
} {
  let latest!: NodeMcpState;
  function Probe(props: {
    agent: CliKind | null;
    pluginDir: string | null;
  }): null {
    latest = useNodeMcp(agentsApi, props.agent, props.pluginDir);
    return null;
  }
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(<Probe agent={agent} pluginDir={pluginDir} />);
  });
  return {
    latest: () => latest,
    rerender: (nextAgent, nextPluginDir) => {
      act(() => {
        root!.render(<Probe agent={nextAgent} pluginDir={nextPluginDir} />);
      });
    },
  };
}

describe('useNodeMcp', () => {
  it('asks WITHOUT a cwd, and passes the node’s plugin directory', async () => {
    // The builder has no folder. Sending one would make the inspector state
    // some unrelated folder's project servers as this node's.
    const seen: Record<string, unknown>[] = [];
    const listAgentMcpServers = vi.fn((req: Record<string, unknown>) => {
      seen.push(req);
      return Promise.resolve(listing('a'));
    });
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    const { latest } = mount(api, 'claude', '/opt/plugins/reviewer');
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(listAgentMcpServers).toHaveBeenCalledTimes(1);
    const arg = seen[0]!;
    expect(arg).toEqual({
      agent: 'claude',
      pluginDir: '/opt/plugins/reviewer',
    });
    expect('cwd' in arg).toBe(false);
    expect(latest().listing?.servers.map((s) => s.name)).toEqual(['a']);
  });

  it('omits pluginDir entirely when the node names none', async () => {
    const listAgentMcpServers = vi.fn(() => Promise.resolve(listing()));
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    mount(api, 'claude', null);
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(listAgentMcpServers).toHaveBeenCalledWith(
      { agent: 'claude' },
      expect.objectContaining({ signal: expect.anything() }),
    );
  });

  it('never asks while there is no agent selected', async () => {
    const listAgentMcpServers = vi.fn(() => Promise.resolve(listing()));
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    const { latest } = mount(api, null, null);
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(listAgentMcpServers).not.toHaveBeenCalled();
    expect(latest().listing).toBeUndefined();
    expect(latest().loading).toBe(false);
  });

  it('does NOT show one node’s servers under another node', async () => {
    // The answer for plugin A resolves AFTER the user has clicked to the node
    // using plugin B. Without the scope pairing the inspector would sit there
    // naming A's servers as B's — wrong, not merely stale.
    let resolveA: ((value: AgentMcpListing) => void) | undefined;
    const listAgentMcpServers = vi.fn((req: { pluginDir?: string }) =>
      req.pluginDir === '/plugin-a'
        ? new Promise<AgentMcpListing>((resolve) => {
            resolveA = resolve;
          })
        : Promise.resolve(listing('from-b')),
    );
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    const { latest, rerender } = mount(api, 'claude', '/plugin-a');
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });
    rerender('claude', '/plugin-b');
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });
    // A's answer lands late, after the user moved on.
    await act(async () => {
      resolveA?.(listing('from-a'));
      await Promise.resolve();
    });

    expect(latest().listing?.servers.map((s) => s.name)).toEqual(['from-b']);
  });

  it('shows NOTHING for the new node while its own answer is still in flight', async () => {
    // The `stale` flag alone cannot carry this one: B's read has not resolved,
    // so nothing overwrote A's stored answer — only the scope COMPARISON at
    // the return keeps A's rows off B's inspector during the debounce+fetch
    // window. Break that comparison and this is the assertion that fails.
    let resolveB: ((value: AgentMcpListing) => void) | undefined;
    const listAgentMcpServers = vi.fn((req: { pluginDir?: string }) =>
      req.pluginDir === '/plugin-a'
        ? Promise.resolve(listing('from-a'))
        : new Promise<AgentMcpListing>((resolve) => {
            resolveB = resolve;
          }),
    );
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    const { latest, rerender } = mount(api, 'claude', '/plugin-a');
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });
    // A's rows are on screen and correct for A.
    expect(latest().listing?.servers.map((s) => s.name)).toEqual(['from-a']);

    rerender('claude', '/plugin-b');
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    // B has not answered yet — and A's rows must NOT be standing in for it.
    expect(latest().listing).toBeUndefined();

    await act(async () => {
      resolveB?.(listing('from-b'));
      await Promise.resolve();
    });
    expect(latest().listing?.servers.map((s) => s.name)).toEqual(['from-b']);
  });

  it('shows the daemon’s refusal rather than swallowing it', async () => {
    // The refusal is the ONLY thing that can tell the user their path is wrong
    // — the CLI ignores an unusable --plugin-dir silently. A catch that
    // discarded it would render a typo as "Not checked".
    const listAgentMcpServers = vi.fn(() =>
      Promise.reject(
        new Error(
          'daemon GET /v1/agents/mcp failed (400): Plugin directory does not exist: /nope',
        ),
      ),
    );
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    const { latest } = mount(api, 'claude', '/nope');
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(latest().listing?.unavailableReason).toContain(
      'Plugin directory does not exist',
    );
    expect(latest().listing?.servers).toEqual([]);
    expect(latest().loading).toBe(false);
  });

  it('coalesces a typed path into ONE read, not one per keystroke', async () => {
    // The listing health-checks — it launches the user's own MCP servers — so
    // a read per keystroke would launch them once per character. Intermediate
    // paths can be real directories too, so validity alone would not bound it.
    const listAgentMcpServers = vi.fn(() => Promise.resolve(listing()));
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    const { rerender } = mount(api, 'claude', '/o');
    for (const partial of ['/op', '/opt', '/opt/p', '/opt/plugins']) {
      rerender('claude', partial);
    }
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(listAgentMcpServers).toHaveBeenCalledTimes(1);
    expect(listAgentMcpServers).toHaveBeenCalledWith(
      {
        agent: 'claude',
        pluginDir: '/opt/plugins',
      },
      expect.objectContaining({ signal: expect.anything() }),
    );
  });

  it('treats a daemon REFUSAL of the path as a field error', async () => {
    // The daemon rejects an unusable --plugin-dir with a 4xx, and that is the
    // only signal the user gets: the CLI itself ignores such a directory
    // silently. It has to reach the FIELD, not just the servers list.
    const api = {
      listAgentMcpServers: vi.fn(() =>
        Promise.reject(
          new Error(
            'daemon GET /v1/agents/mcp failed (400): plugin directory does not exist',
          ),
        ),
      ),
    } as unknown as DaemonApis['agents'];

    const { latest } = mount(api, 'claude', '/nope');
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(latest().invalidPluginDir).toContain('does not exist');
  });

  it('does NOT blame the path for a dead CLI or an unreachable daemon', async () => {
    // The same catch sees both. Rendering a 5xx or a transport failure under
    // the field puts a red validation error on a perfectly valid path and
    // hides the section explaining the real cause — so the reason still
    // reaches the listing, but the field stays clean.
    const api = {
      listAgentMcpServers: vi.fn(() =>
        Promise.reject(
          new Error('daemon GET /v1/agents/mcp failed (500): claude not found'),
        ),
      ),
    } as unknown as DaemonApis['agents'];

    const { latest } = mount(api, 'claude', '/opt/plugins');
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(latest().invalidPluginDir).toBeNull();
    expect(latest().listing?.unavailableReason).toContain('claude not found');
  });

  it('never blames a path the node does not name', async () => {
    // A refusal with no pluginDir in play cannot be about one.
    const api = {
      listAgentMcpServers: vi.fn(() =>
        Promise.reject(new Error('daemon GET /v1/agents/mcp failed (400): no')),
      ),
    } as unknown as DaemonApis['agents'];

    const { latest } = mount(api, 'claude', null);
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(latest().invalidPluginDir).toBeNull();
  });

  it('reads through the daemon’s cache until the user asks for a re-dial', async () => {
    // The automatic read exists to POPULATE the section. Sending refresh=true
    // on it would re-launch the user's own MCP servers every time a node is
    // selected or a path character typed — which is what makes re-dialling an
    // explicit act rather than a side effect of clicking around.
    const seen: Record<string, unknown>[] = [];
    const listAgentMcpServers = vi.fn((req: Record<string, unknown>) => {
      seen.push(req);
      return Promise.resolve(listing('a'));
    });
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    const { latest } = mount(api, 'claude', '/opt/plugins');
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });
    expect(seen[0]).not.toHaveProperty('refresh');

    // Two acts, not one: the state update must be flushed — and the effect it
    // re-runs scheduled — before the wait, or nothing has been asked yet when
    // the wait expires.
    act(() => {
      latest().refresh();
    });
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(listAgentMcpServers).toHaveBeenCalledTimes(2);
    expect(seen[1]).toMatchObject({ refresh: 'true' });
  });

  it('does NOT debounce a refresh', async () => {
    // The delay exists to collapse keystrokes. A click is not a keystroke, and
    // making the user wait half a second for the one control that re-dials
    // reads as a dead button.
    const listAgentMcpServers = vi.fn(() => Promise.resolve(listing('a')));
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    const { latest } = mount(api, 'claude', null);
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });
    expect(listAgentMcpServers).toHaveBeenCalledTimes(1);

    act(() => {
      latest().refresh();
    });
    await act(async () => {
      // A tenth of LISTING_DEBOUNCE_MS. A debounced refresh has not fired at
      // this point, so this assertion fails the moment the delay is applied
      // to one.
      await new Promise((r) => setTimeout(r, 50));
    });

    expect(listAgentMcpServers).toHaveBeenCalledTimes(2);
  });

  it('spends a refresh raised with no node selected instead of banking it', async () => {
    // A latched token would make the NEXT node the user clicks re-dial their
    // servers — a read nobody asked to refresh, and then every one after it.
    const seen: Record<string, unknown>[] = [];
    const listAgentMcpServers = vi.fn((req: Record<string, unknown>) => {
      seen.push(req);
      return Promise.resolve(listing('a'));
    });
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    const { latest, rerender } = mount(api, null, null);
    act(() => {
      latest().refresh();
    });
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });
    expect(listAgentMcpServers).not.toHaveBeenCalled();

    rerender('claude', null);
    await act(async () => {
      await new Promise((r) => setTimeout(r, 600));
    });

    expect(listAgentMcpServers).toHaveBeenCalledTimes(1);
    expect(seen[0]).not.toHaveProperty('refresh');
  });

  it('keeps asking while the daemon says the read is still running', async () => {
    // The daemon answers a cold read at once with empty rows under `pending`
    // and finishes the dial behind it. That dial STARTS the user's own MCP
    // servers, so it routinely outlasts several of these windows — the
    // inspector has to keep asking until the listing settles, or it renders the
    // daemon's placeholder as "no servers" for a node that has them.
    const stillReading = {
      servers: [],
      unavailableReason: null,
      pending: true,
    } as unknown as AgentMcpListing;
    const settled = { ...listing('memory'), pending: false };
    const listAgentMcpServers = vi
      .fn<() => Promise<AgentMcpListing>>()
      .mockResolvedValueOnce(stillReading)
      .mockResolvedValueOnce(stillReading)
      .mockResolvedValue(settled);
    const api = { listAgentMcpServers } as unknown as DaemonApis['agents'];

    vi.useFakeTimers();
    const { latest } = mount(api, 'claude', null);
    // The first read clears its 500ms debounce; each later one costs a 1000ms
    // retry window plus that same debounce.
    await act(async () => {
      await vi.advanceTimersByTimeAsync(600);
    });
    // One advance per poll CYCLE, and there are three answers to collect.
    // React flushes the retry effect after `advanceTimersByTimeAsync` returns,
    // so the timer it arms and the read that timer triggers land in the next
    // advance — two iterations would stop one answer short of the settled one.
    for (let poll = 0; poll < 4; poll += 1) {
      await act(async () => {
        await vi.advanceTimersByTimeAsync(1600);
      });
    }

    expect(latest().listing?.servers.map((s) => s.name)).toEqual(['memory']);
    expect(latest().loading).toBe(false);
  });
});
