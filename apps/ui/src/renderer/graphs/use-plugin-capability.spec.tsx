// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { CapabilitiesDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import {
  type PluginCapabilityState,
  usePluginCapability,
} from './use-plugin-capability';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

function capabilitiesApi(
  getCapabilities: () => Promise<CapabilitiesDto>,
): DaemonApis['capabilities'] {
  return { getCapabilities } as unknown as DaemonApis['capabilities'];
}

function caps(
  plugins: { agent: string; unavailableReason: string | null }[],
): CapabilitiesDto {
  return {
    claudeModes: {
      acceptEdits: 'pass',
      plan: 'pass',
      version: 'claude 2',
      probedAt: 1,
      reason: null,
    },
    plugins,
  } as unknown as CapabilitiesDto;
}

async function mount(
  api: DaemonApis['capabilities'] | null,
): Promise<() => PluginCapabilityState> {
  let latest!: PluginCapabilityState;
  function Probe(): null {
    latest = usePluginCapability(api);
    return null;
  }
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<Probe />);
  });
  return () => latest;
}

describe('usePluginCapability', () => {
  it('reports each CLI’s own reason, so the builder stops allowlisting a name', async () => {
    const latest = await mount(
      capabilitiesApi(() =>
        Promise.resolve(
          caps([
            { agent: 'claude', unavailableReason: null },
            {
              agent: 'cursor-agent',
              unavailableReason: 'cursor-agent has no plugin mechanism',
            },
          ]),
        ),
      ),
    );

    expect(latest().unavailableReasonFor('claude')).toBeNull();
    expect(latest().unavailableReasonFor('cursor-agent')).toBe(
      'cursor-agent has no plugin mechanism',
    );
    expect(latest().loading).toBe(false);
  });

  it('answers UNDEFINED for a CLI the daemon did not mention', async () => {
    // Not `null`, which the inspector reads as "this CLI supports it" and
    // would render an input for. An agent missing from the answer is one we
    // have no answer for, and the honest rendering is nothing at all.
    const latest = await mount(
      capabilitiesApi(() =>
        Promise.resolve(caps([{ agent: 'claude', unavailableReason: null }])),
      ),
    );

    expect(latest().unavailableReasonFor('cursor-agent')).toBeUndefined();
  });

  it('stays UNKNOWN when the read fails, never falling back to "cannot"', async () => {
    // A failed capabilities read is not evidence about any CLI. Treating it as
    // a refusal would hide the field from the agent that does support one, and
    // the user would have no way to tell a broken daemon from a CLI limit.
    const latest = await mount(
      capabilitiesApi(() => Promise.reject(new Error('daemon down'))),
    );

    expect(latest().unavailableReasonFor('claude')).toBeUndefined();
  });

  it('is not loading, and asks nothing, before a daemon handle exists', async () => {
    const getCapabilities = vi.fn();
    const latest = await mount(null);

    expect(latest().loading).toBe(false);
    expect(latest().unavailableReasonFor('claude')).toBeUndefined();
    expect(getCapabilities).not.toHaveBeenCalled();
  });
});
