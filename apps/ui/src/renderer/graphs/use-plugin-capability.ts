import { useEffect, useState } from 'react';

import type { AgentKind } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';

/**
 * Whether each CLI can load a plugin directory, as the DAEMON reports it.
 *
 * The builder used to answer this itself, with `agent === 'claude'` written
 * into the inspector. That was a second copy of a rule the daemon already
 * owned (`AdapterConfig.plugin.unavailableReason`), and the copies had already
 * diverged: the executor silently dropped a `pluginDir` it could not honour
 * while the listing route refused one with a 400, and a workflow imported from
 * YAML could carry one on a CLI that ignores it — with the field hidden, so
 * the user could not even see what to remove.
 *
 * Undefined while unknown. Callers must NOT read that as "cannot": the honest
 * rendering before the answer lands is nothing at all, the same way the panel
 * shows no MCP rows before its own read returns.
 */
export interface PluginCapabilityState {
  /** Why this CLI cannot load a plugin directory, `null` when it can. */
  unavailableReasonFor: (agent: AgentKind) => string | null | undefined;
  loading: boolean;
}

export function usePluginCapability(
  capabilitiesApi: DaemonApis['capabilities'] | null,
): PluginCapabilityState {
  const [byAgent, setByAgent] = useState<ReadonlyMap<
    AgentKind,
    string | null
  > | null>(null);

  useEffect(() => {
    if (capabilitiesApi === null) {
      setByAgent(null);
      return;
    }
    let stale = false;
    void capabilitiesApi
      .getCapabilities()
      .then((caps) => {
        if (!stale) {
          setByAgent(
            new Map(caps.plugins.map((p) => [p.agent, p.unavailableReason])),
          );
        }
      })
      .catch(() => {
        // Left unknown rather than assumed. A failed read is not evidence that
        // a CLI lacks the mechanism, and treating it as one would hide the
        // field from the agent that does have it.
        if (!stale) {
          setByAgent(null);
        }
      });
    return () => {
      stale = true;
    };
  }, [capabilitiesApi]);

  return {
    unavailableReasonFor: (agent) => byAgent?.get(agent),
    loading: byAgent === null && capabilitiesApi !== null,
  };
}
