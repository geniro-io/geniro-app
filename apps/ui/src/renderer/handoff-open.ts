import type { HandoffTargetDto } from './autogenerated';

/**
 * The whole handoff contract, once: ask the daemon for an invocation, and either
 * open it in the user's terminal or say why there isn't one.
 *
 * Four callers now resolve different things — a thread's conversation, an MCP
 * server's sign-in, a CLI's own sign-in from the chat surface, and the same
 * sign-in from Settings — and every one of them shares this shape. It lives
 * here, in a plain `.ts` module rather than beside any one screen, because the
 * fourth caller is on a DIFFERENT screen: hand-copied, a later fix (surfacing a
 * rejected `openInTerminal`, or offering `target.display` to paste) would have
 * to be made in two files that no longer sit next to each other, with nothing
 * catching a miss.
 *
 * A refusal is the ANSWER, not a failure — cursor-agent genuinely cannot reopen
 * one of its conversations — so the daemon's own sentence is what the user
 * reads, and `fallback` covers only the case where it sent none.
 */
export async function openResolvedTarget(
  resolve: () => Promise<HandoffTargetDto>,
  fallback: string,
  setError: (message: string | null) => void,
): Promise<void> {
  try {
    setError(null);
    const target = await resolve();
    if (target.kind !== 'command' || !target.command || !target.cwd) {
      setError(target.unavailableReason ?? fallback);
      return;
    }
    await window.geniro.openInTerminal({
      command: target.command,
      args: target.args,
      cwd: target.cwd,
      // Carried, never composed here: a resume that dropped it would open the
      // DEFAULT profile, where this session id does not exist, and the CLI
      // would show an unrelated conversation instead of an error.
      env: target.env,
    });
  } catch (err) {
    setError(err instanceof Error ? err.message : String(err));
  }
}
