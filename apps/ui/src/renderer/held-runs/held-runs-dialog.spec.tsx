// @vitest-environment jsdom
import { act, type ComponentProps } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { HeldRun } from '../autogenerated';
import { HeldRunsDialog } from './held-runs-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const RUNS: HeldRun[] = [
  { runId: 'run-a', title: 'Ship the login flow', cause: 'crash' },
  { runId: 'run-b', title: null, cause: 'crash' },
  { runId: 'run-c', title: 'Triage the inbox', cause: 'crash' },
];

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function renderDialog(
  overrides: Partial<ComponentProps<typeof HeldRunsDialog>> = {},
): void {
  act(() => {
    root.render(
      <HeldRunsDialog
        open
        runs={RUNS}
        answering={false}
        error={null}
        onAnswer={vi.fn()}
        {...overrides}
      />,
    );
  });
}

function button(label: string): HTMLButtonElement | undefined {
  return [...container.querySelectorAll('button')].find(
    (node) => node.textContent === label,
  );
}

function checkboxes(): HTMLButtonElement[] {
  return [
    ...container.querySelectorAll<HTMLButtonElement>('[role="checkbox"]'),
  ];
}

describe('HeldRunsDialog', () => {
  it('shows nothing while closed', () => {
    renderDialog({ open: false });

    expect(container.querySelector('[role="dialog"]')).toBeNull();
  });

  it('titles the dialog for one run and for several', () => {
    renderDialog({ runs: RUNS.slice(0, 1) });
    expect(
      container.querySelector('[data-slot="dialog-title"]')?.textContent,
    ).toBe('1 team run was interrupted by a crash');

    renderDialog();
    expect(
      container.querySelector('[data-slot="dialog-title"]')?.textContent,
    ).toBe('3 team runs were interrupted by a crash');
  });

  it('offers no corner ✕, so only its buttons close it', () => {
    renderDialog();

    expect(container.querySelector('[aria-label="Close"]')).toBeNull();
  });

  it('lists each run by its title, and an untitled one as Untitled run', () => {
    renderDialog();

    expect(
      [...container.querySelectorAll('li')].map((item) => item.textContent),
    ).toEqual(['Ship the login flow', 'Untitled run', 'Triage the inbox']);
  });

  it('opens with Continue all focused, so Enter never declines', () => {
    renderDialog();

    expect(document.activeElement).toBe(button('Continue all'));
  });

  it('Continue all answers every run as continued', () => {
    const onAnswer = vi.fn();
    renderDialog({ onAnswer });

    act(() => button('Continue all')!.click());

    expect(onAnswer).toHaveBeenCalledWith(['run-a', 'run-b', 'run-c'], []);
  });

  it("Don't continue answers every run as declined", () => {
    const onAnswer = vi.fn();
    renderDialog({ onAnswer });

    act(() => button("Don't continue")!.click());

    expect(onAnswer).toHaveBeenCalledWith([], ['run-a', 'run-b', 'run-c']);
  });

  it('Choose… ticks every run first, and continues only the ticked ones', () => {
    const onAnswer = vi.fn();
    renderDialog({ onAnswer });

    act(() => button('Choose…')!.click());
    expect(checkboxes().map((box) => box.getAttribute('aria-checked'))).toEqual(
      ['true', 'true', 'true'],
    );

    act(() => checkboxes()[0]!.click());
    act(() => checkboxes()[1]!.click());
    act(() => button('Continue selected (1)')!.click());

    expect(onAnswer).toHaveBeenCalledWith(['run-c'], ['run-a', 'run-b']);
  });

  it('Back returns to the default buttons', () => {
    renderDialog();

    act(() => button('Choose…')!.click());
    act(() => button('Back')!.click());

    expect(checkboxes()).toHaveLength(0);
    expect(button('Continue all')).toBeDefined();
  });

  it('puts the focus back on Continue all after Back, so Enter never declines', () => {
    renderDialog();

    act(() => button('Choose…')!.click());
    act(() => button('Back')!.click());

    expect(document.activeElement).toBe(button('Continue all'));
  });

  it('disables Continue selected while no run is ticked', () => {
    renderDialog();

    act(() => button('Choose…')!.click());
    checkboxes().forEach((box) => act(() => box.click()));

    expect(button('Continue selected (0)')!.disabled).toBe(true);
  });

  it('disables every button while an answer is being sent', () => {
    renderDialog({ answering: true });

    for (const label of ["Don't continue", 'Choose…', 'Continue all']) {
      expect(button(label)!.disabled).toBe(true);
    }
  });

  it('shows the error under the list', () => {
    renderDialog({ error: 'Could not reach Geniro — try again.' });

    expect(container.querySelector('[role="alert"]')?.textContent).toBe(
      'Could not reach Geniro — try again.',
    );
  });
});
