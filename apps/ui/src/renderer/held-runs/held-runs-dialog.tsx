import * as React from 'react';

import type { HeldRun } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Checkbox } from '../components/ui/checkbox';
import { Dialog } from '../components/ui/dialog';

function titleFor(count: number): string {
  return count === 1
    ? '1 team run was interrupted by a crash'
    : `${count} team runs were interrupted by a crash`;
}

export function HeldRunsDialog({
  open,
  runs,
  answering,
  error,
  onAnswer,
}: {
  open: boolean;
  runs: readonly HeldRun[];
  answering: boolean;
  error: string | null;
  onAnswer: (continueRunIds: string[], declineRunIds: string[]) => void;
}): React.JSX.Element | null {
  const continueAllRef = React.useRef<HTMLButtonElement>(null);
  return (
    <Dialog
      open={open}
      onClose={() => undefined}
      dismissible={false}
      initialFocus={continueAllRef}
      title={titleFor(runs.length)}>
      <HeldRunsChoice
        continueAllRef={continueAllRef}
        runs={runs}
        answering={answering}
        error={error}
        onAnswer={onAnswer}
      />
    </Dialog>
  );
}

function HeldRunsChoice({
  continueAllRef,
  runs,
  answering,
  error,
  onAnswer,
}: {
  continueAllRef: React.RefObject<HTMLButtonElement | null>;
  runs: readonly HeldRun[];
  answering: boolean;
  error: string | null;
  onAnswer: (continueRunIds: string[], declineRunIds: string[]) => void;
}): React.JSX.Element {
  const [choosing, setChoosing] = React.useState(false);
  const leftChoosing = React.useRef(false);
  React.useEffect(() => {
    if (!choosing && leftChoosing.current) {
      continueAllRef.current?.focus();
    }
    leftChoosing.current = choosing;
  }, [choosing, continueAllRef]);
  const [unticked, setUnticked] = React.useState<ReadonlySet<string>>(
    () => new Set(),
  );
  const allIds = runs.map((run) => run.runId);
  const continueIds = allIds.filter((id) => !unticked.has(id));
  const declineIds = allIds.filter((id) => unticked.has(id));

  const setTicked = (runId: string, ticked: boolean): void => {
    setUnticked((current) => {
      const next = new Set(current);
      if (ticked) {
        next.delete(runId);
      } else {
        next.add(runId);
      }
      return next;
    });
  };

  return (
    <div className="flex flex-col gap-4">
      <p className="m-0 text-sm text-muted-foreground">
        Geniro stopped unexpectedly while these runs were working. Continue them
        from where they stopped, or leave them stopped — you can still continue
        one later by writing in its thread.
      </p>
      <ul className="m-0 flex list-none flex-col gap-2 p-0">
        {runs.map((run) => {
          const name = run.title ?? 'Untitled run';
          return (
            <li key={run.runId} className="text-sm">
              {choosing ? (
                <Checkbox
                  checked={!unticked.has(run.runId)}
                  onCheckedChange={(next) => setTicked(run.runId, next)}
                  label={name}
                  disabled={answering}
                />
              ) : (
                name
              )}
            </li>
          );
        })}
      </ul>
      {error !== null ? (
        <p role="alert" className="m-0 text-sm text-destructive">
          {error}
        </p>
      ) : null}
      <div className="flex flex-wrap justify-end gap-2">
        {choosing ? (
          <>
            <Button
              variant="outline"
              disabled={answering}
              onClick={() => setChoosing(false)}>
              Back
            </Button>
            <Button
              disabled={answering || continueIds.length === 0}
              onClick={() => onAnswer(continueIds, declineIds)}>
              Continue selected ({continueIds.length})
            </Button>
          </>
        ) : (
          <>
            <Button
              variant="outline"
              disabled={answering}
              onClick={() => onAnswer([], allIds)}>
              Don't continue
            </Button>
            <Button
              variant="outline"
              disabled={answering}
              onClick={() => setChoosing(true)}>
              Choose…
            </Button>
            <Button
              ref={continueAllRef}
              disabled={answering}
              onClick={() => onAnswer(allIds, [])}>
              Continue all
            </Button>
          </>
        )}
      </div>
    </div>
  );
}
