// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type {
  HeldRun,
  HeldRunsAnsweredDto,
  HeldRunsDto,
} from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import {
  HELD_RUNS_ANSWER_ERROR,
  type HeldRunsController,
  useHeldRuns,
} from './use-held-runs';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const RUN: HeldRun = {
  runId: 'run-a',
  title: 'Ship the login flow',
  cause: 'crash',
};
const OTHER_RUN: HeldRun = { runId: 'run-z', title: 'Other', cause: 'crash' };

let container: HTMLDivElement;
let root: Root;
let latest: HeldRunsController | null;

type StatusListener = (event: { runId: string }) => void;

function fakeClient() {
  const listeners = new Set<StatusListener>();
  return {
    onRunStatus: (listener: StatusListener) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    emit: (runId: string) => {
      for (const listener of listeners) {
        listener({ runId });
      }
    },
  };
}

function Probe({
  apis,
  client = null,
}: {
  apis: DaemonApis | null;
  client?: ReturnType<typeof fakeClient> | null;
}): null {
  latest = useHeldRuns(apis, client as Parameters<typeof useHeldRuns>[1]);
  return null;
}

function fakeDaemon(list: () => Promise<HeldRunsDto>) {
  const teams = {
    listHeldRuns: vi.fn(list),
    answerHeldRuns: vi.fn((): Promise<HeldRunsAnsweredDto> =>
      Promise.resolve({ continued: [], declined: [] }),
    ),
  };
  return { apis: { teams } as unknown as DaemonApis, teams };
}

function listing(runs: HeldRun[]): () => Promise<HeldRunsDto> {
  return () => Promise.resolve({ runs });
}

function deferred<T>(): { promise: Promise<T>; resolve: (value: T) => void } {
  let resolve!: (value: T) => void;
  const promise = new Promise<T>((done) => {
    resolve = done;
  });
  return { promise, resolve };
}

async function mount(apis: DaemonApis | null): Promise<void> {
  await act(async () => {
    root.render(<Probe apis={apis} />);
  });
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  latest = null;
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('useHeldRuns', () => {
  it('lists the held runs once a daemon is attached, and opens only with runs', async () => {
    const { apis, teams } = fakeDaemon(listing([RUN]));

    await mount(null);
    expect(teams.listHeldRuns).not.toHaveBeenCalled();
    expect(latest?.open).toBe(false);

    await mount(apis);
    expect(teams.listHeldRuns).toHaveBeenCalledTimes(1);
    expect(latest?.open).toBe(true);
    expect(latest?.runs).toEqual([RUN]);
    expect([...(latest?.runIds ?? [])]).toEqual([RUN.runId]);

    await mount(apis);
    expect(teams.listHeldRuns).toHaveBeenCalledTimes(1);
  });

  it('stays shut when the daemon holds no runs', async () => {
    const { apis } = fakeDaemon(listing([]));

    await mount(apis);

    expect(latest?.open).toBe(false);
    expect(latest?.runs).toEqual([]);
  });

  it('shows nothing when the list cannot be read', async () => {
    const { apis } = fakeDaemon(() => Promise.reject(new Error('down')));

    await mount(apis);

    expect(latest?.open).toBe(false);
    expect(latest?.error).toBeNull();
  });

  it('shows nothing from the old daemon while the new one is still being asked', async () => {
    const first = fakeDaemon(listing([RUN]));
    const second = deferred<HeldRunsDto>();
    const next = fakeDaemon(() => second.promise);
    await mount(first.apis);
    expect(latest?.open).toBe(true);

    await mount(next.apis);
    expect(latest?.open).toBe(false);

    await act(async () => {
      second.resolve({ runs: [OTHER_RUN] });
    });
    expect(latest?.runs).toEqual([OTHER_RUN]);
  });

  it('ignores a list that arrives after its daemon was replaced', async () => {
    const first = deferred<HeldRunsDto>();
    const old = fakeDaemon(() => first.promise);
    const next = fakeDaemon(listing([OTHER_RUN]));
    await mount(old.apis);
    await mount(next.apis);

    await act(async () => {
      first.resolve({ runs: [RUN] });
    });

    expect(latest?.runs).toEqual([OTHER_RUN]);
  });

  it('drops a run continued elsewhere once its status changes, and closes with the last one', async () => {
    let held = [RUN, OTHER_RUN];
    const { apis, teams } = fakeDaemon(() => Promise.resolve({ runs: held }));
    const client = fakeClient();
    await act(async () => {
      root.render(<Probe apis={apis} client={client} />);
    });
    expect(latest?.runs).toEqual([RUN, OTHER_RUN]);

    held = [OTHER_RUN];
    await act(async () => {
      client.emit('not-held');
    });
    expect(teams.listHeldRuns).toHaveBeenCalledTimes(1);

    await act(async () => {
      client.emit(RUN.runId);
    });
    expect(latest?.runs).toEqual([OTHER_RUN]);
    expect(latest?.runIds.has(RUN.runId)).toBe(false);

    held = [];
    await act(async () => {
      client.emit(OTHER_RUN.runId);
    });
    expect(latest?.open).toBe(false);
  });

  it('answer posts the ids and closes the dialog', async () => {
    const { apis, teams } = fakeDaemon(listing([RUN]));
    await mount(apis);

    await act(async () => {
      latest?.answer(['run-a'], []);
    });

    expect(teams.answerHeldRuns).toHaveBeenCalledWith({
      answerHeldRunsDto: { continueRunIds: ['run-a'], declineRunIds: [] },
    });
    expect(latest?.open).toBe(false);
    expect(latest?.error).toBeNull();
  });

  it('reports answering while the answer is in flight', async () => {
    const reply = deferred<HeldRunsAnsweredDto>();
    const { apis, teams } = fakeDaemon(listing([RUN]));
    teams.answerHeldRuns.mockImplementation(() => reply.promise);
    await mount(apis);

    await act(async () => {
      latest?.answer([], ['run-a']);
    });
    expect(latest?.answering).toBe(true);
    expect(latest?.open).toBe(true);

    await act(async () => {
      reply.resolve({ continued: [], declined: ['run-a'] });
    });
    expect(latest?.open).toBe(false);
    expect(latest?.answering).toBe(false);
  });

  it('keeps the dialog open with an error when the answer fails', async () => {
    const { apis, teams } = fakeDaemon(listing([RUN]));
    teams.answerHeldRuns.mockImplementation(() =>
      Promise.reject(new Error('down')),
    );
    await mount(apis);

    await act(async () => {
      latest?.answer(['run-a'], []);
    });

    expect(latest?.open).toBe(true);
    expect(latest?.answering).toBe(false);
    expect(latest?.error).toBe(HELD_RUNS_ANSWER_ERROR);
    expect(latest?.error).toBe('Could not reach Geniro — try again.');
  });
});
