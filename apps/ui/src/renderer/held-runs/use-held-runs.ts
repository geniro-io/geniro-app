import { useEffect, useState } from 'react';

import type { HeldRun } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';

export const HELD_RUNS_ANSWER_ERROR = 'Could not reach Geniro — try again.';

export interface HeldRunsController {
  runs: readonly HeldRun[];
  open: boolean;
  answering: boolean;
  error: string | null;
  answer: (continueRunIds: string[], declineRunIds: string[]) => void;
}

interface HeldRunsSession {
  apis: DaemonApis;
  runs: readonly HeldRun[];
  answering: boolean;
  error: string | null;
}

/**
 * The list belongs to the daemon that gave it: after a respawn the old answer
 * cannot close the new daemon's list.
 */
export function useHeldRuns(apis: DaemonApis | null): HeldRunsController {
  const [session, setSession] = useState<HeldRunsSession | null>(null);

  useEffect(() => {
    if (apis === null) {
      return;
    }
    let stale = false;
    void apis.teams.listHeldRuns().then(
      ({ runs }) => {
        if (!stale) {
          setSession({ apis, runs, answering: false, error: null });
        }
      },
      () => undefined,
    );
    return () => {
      stale = true;
    };
  }, [apis]);

  const current = session !== null && session.apis === apis ? session : null;

  const answer = (continueRunIds: string[], declineRunIds: string[]): void => {
    if (apis === null || current === null || current.answering) {
      return;
    }
    setSession({ ...current, answering: true, error: null });
    void apis.teams
      .answerHeldRuns({ answerHeldRunsDto: { continueRunIds, declineRunIds } })
      .then(
        () => setSession((latest) => (latest?.apis === apis ? null : latest)),
        () =>
          setSession((latest) =>
            latest?.apis === apis
              ? { ...latest, answering: false, error: HELD_RUNS_ANSWER_ERROR }
              : latest,
          ),
      );
  };

  return {
    runs: current?.runs ?? [],
    open: (current?.runs.length ?? 0) > 0,
    answering: current?.answering ?? false,
    error: current?.error ?? null,
    answer,
  };
}
