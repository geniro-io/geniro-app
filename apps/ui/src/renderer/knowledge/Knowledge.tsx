import { BookOpen, Check, ChevronDown, Plus, Search } from 'lucide-react';
import { useEffect, useMemo, useRef, useState } from 'react';

import type { DaemonHandle } from '../../shared/contracts';
import type {
  KnowledgeDocumentDetailDto,
  KnowledgeHead,
  KnowledgeRevisionDetailDto,
} from '../autogenerated';
import { BackLink } from '../components/back-link';
import { EmptyState } from '../components/empty-state';
import { ErrorBanner } from '../components/error-banner';
import { LibraryHeader } from '../components/library-header';
import { Badge } from '../components/ui/badge';
import { Button } from '../components/ui/button';
import { Input } from '../components/ui/input';
import { Menu } from '../components/ui/menu';
import { Select, type SelectGroup } from '../components/ui/select';
import { useLatestCallback } from '../components/use-latest-callback';
import {
  createDaemonApis,
  daemonErrorCode,
  describeDaemonError,
} from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { isRemoteRuntime } from '../remote/remote-session';
import { KnowledgeDocumentView } from './knowledge-document-view';
import {
  type KnowledgeFieldErrors,
  KnowledgeForm,
  type KnowledgeFormValue,
  placeGroups,
} from './knowledge-form';
import { KnowledgeHistory } from './knowledge-history';
import { KnowledgeNote } from './knowledge-note';
import { KnowledgeReview } from './knowledge-review';
import { KnowledgeRow } from './knowledge-row';
import { currentOf, GLOBAL_PLACE, placeLabel } from './knowledge-text';
import {
  type KnowledgeStatusFilter,
  useKnowledgeCounts,
  useKnowledgeList,
} from './use-knowledge';
import { useKnowledgePlaces } from './use-knowledge-places';

const ALL_PLACES = 'all';

const STATUS_LABEL: Record<KnowledgeStatusFilter, string> = {
  active: 'Active',
  waiting: 'Waiting for review',
  archived: 'Archived',
};

/** What another screen asked this one to show. */
export interface KnowledgeRequest {
  /** Pick this place in the list. */
  place?: string;
  /** Open this document. */
  documentId?: string;
  /** Open a document a transcript named by its handle. */
  handle?: string;
  /** Whose places `handle` is looked up in. */
  runId?: string;
}

type Screen =
  | { kind: 'list' }
  | { kind: 'document'; id: string }
  | { kind: 'edit'; id: string }
  | { kind: 'new' }
  | { kind: 'history'; id: string }
  | { kind: 'review'; revisionId: string };

const EMPTY_FORM: KnowledgeFormValue = {
  title: '',
  whenToRead: '',
  handle: '',
  body: '',
  place: GLOBAL_PLACE,
};

/**
 * Documents agents read when a task calls for them: a list over every place,
 * one document with its history, a form, and the review of what agents propose.
 */
export function Knowledge({
  handle,
  client,
  place,
  onPlaceChange,
  request,
  onRequestHandled,
  onDocumentShown,
  remote = isRemoteRuntime(),
}: {
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  /** Null is every place; the shell holds it so a revisit keeps it. */
  place: string | null;
  onPlaceChange: (place: string | null) => void;
  /** Taken once, then handed back through `onRequestHandled`. */
  request: KnowledgeRequest | null;
  onRequestHandled: () => void;
  /** The document on show, for the address bar. */
  onDocumentShown: (documentId: string | null) => void;
  remote?: boolean;
}): React.JSX.Element {
  const apis = useMemo(
    () => (handle ? createDaemonApis(handle) : null),
    [handle],
  );
  const { places, loaded: placesLoaded } = useKnowledgePlaces(apis, client);
  const counts = useKnowledgeCounts(apis, client);
  const [status, setStatus] = useState<KnowledgeStatusFilter>('active');
  const [q, setQ] = useState('');
  const [filterOpen, setFilterOpen] = useState(false);
  const list = useKnowledgeList(apis, client, { place, status, q });
  const [screen, setScreen] = useState<Screen>({ kind: 'list' });
  const [document, setDocument] = useState<KnowledgeDocumentDetailDto | null>(
    null,
  );
  const [revision, setRevision] = useState<KnowledgeRevisionDetailDto | null>(
    null,
  );
  const [form, setForm] = useState<KnowledgeFormValue>(EMPTY_FORM);
  const [formErrors, setFormErrors] = useState<KnowledgeFieldErrors>({});
  const [stale, setStale] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [agentsOff, setAgentsOff] = useState(false);
  const editing = useRef(false);

  const fail = useLatestCallback((err: unknown) => {
    setError(describeDaemonError(err));
  }, []);

  const openReview = useLatestCallback(
    async (documentId: string) => {
      if (apis === null) {
        return;
      }
      setNotice(null);
      try {
        const { revisions } = await apis.knowledge.listKnowledgeRevisions({
          id: documentId,
        });
        const pending = revisions.find((row) => row.status === 'pending');
        if (!pending) {
          setDocument(await apis.knowledge.readKnowledge({ id: documentId }));
          setScreen({ kind: 'document', id: documentId });
          return;
        }
        setRevision(
          await apis.knowledge.readKnowledgeRevision({
            revisionId: pending.id,
          }),
        );
        setScreen({ kind: 'review', revisionId: pending.id });
      } catch (err: unknown) {
        fail(err);
      }
    },
    [apis, fail],
  );

  const openDocument = useLatestCallback(
    async (id: string) => {
      if (apis === null) {
        return;
      }
      setNotice(null);
      try {
        const read = await apis.knowledge.readKnowledge({ id });
        if (read.status === 'proposed') {
          await openReview(id);
          return;
        }
        setDocument(read);
        setScreen({ kind: 'document', id });
      } catch (err: unknown) {
        fail(err);
      }
    },
    [apis, fail, openReview],
  );

  const openRow = useLatestCallback(
    (head: KnowledgeHead) => {
      if (status === 'waiting' || head.status === 'proposed') {
        void openReview(head.id);
      } else {
        void openDocument(head.id);
      }
    },
    [status, openReview, openDocument],
  );

  useEffect(() => {
    if (request === null || apis === null) {
      return;
    }
    if (request.place !== undefined) {
      onPlaceChange(request.place);
      setScreen({ kind: 'list' });
    }
    if (request.documentId !== undefined) {
      void openDocument(request.documentId);
    }
    if (request.handle !== undefined) {
      void apis.knowledge
        .listKnowledge({ handle: request.handle, runId: request.runId })
        .then(({ documents }) => {
          const found = currentOf(documents);
          if (found) {
            void openDocument(found.id);
          } else {
            setNotice(`Nothing is filed as ${request.handle} any more.`);
            setScreen({ kind: 'list' });
          }
        })
        .catch(fail);
    }
    onRequestHandled();
  }, [request, apis, onPlaceChange, openDocument, onRequestHandled, fail]);

  useEffect(() => {
    onDocumentShown(screen.kind === 'document' ? screen.id : null);
  }, [screen, onDocumentShown]);

  useEffect(() => {
    if (
      placesLoaded &&
      place !== null &&
      !places.some((row) => row.key === place)
    ) {
      onPlaceChange(null);
    }
  }, [placesLoaded, places, place, onPlaceChange]);

  useEffect(() => {
    void window.geniro
      .getSettings()
      .then((settings) => setAgentsOff(!settings.knowledge.enabled))
      .catch(() => undefined);
  }, []);

  useEffect(() => {
    if (client === null) {
      return;
    }
    return client.onKnowledgeChanged((event) => {
      if (
        document !== null &&
        event.documentId === document.id &&
        !editing.current
      ) {
        void apis?.knowledge
          .readKnowledge({ id: document.id })
          .then(setDocument)
          .catch(() => setDocument(null));
      }
    });
  }, [client, apis, document]);

  const toList = (): void => {
    setRevision(null);
    setStale(false);
    setFormErrors({});
    editing.current = false;
    setScreen({ kind: 'list' });
  };

  const startNew = (): void => {
    setNotice(null);
    setForm({
      ...EMPTY_FORM,
      place: place ?? places[0]?.key ?? GLOBAL_PLACE,
    });
    setFormErrors({});
    editing.current = true;
    setScreen({ kind: 'new' });
  };

  const startEdit = (open: KnowledgeDocumentDetailDto): void => {
    setNotice(null);
    setForm({
      title: open.title,
      whenToRead: open.whenToRead,
      handle: open.handle,
      body: open.body,
      place: open.place,
    });
    setFormErrors({});
    setStale(false);
    editing.current = true;
    setScreen({ kind: 'edit', id: open.id });
  };

  const refuseField = (err: unknown): void => {
    const code = daemonErrorCode(err);
    if (code === 'HANDLE_TAKEN') {
      setFormErrors({ handle: 'This handle is taken in this place.' });
    } else if (code === 'KNOWLEDGE_STALE') {
      setStale(true);
    } else {
      fail(err);
    }
  };

  const create = async (): Promise<void> => {
    if (apis === null) {
      return;
    }
    setBusy(true);
    try {
      const made = await apis.knowledge.createKnowledge({
        createKnowledgeDto: {
          place: form.place,
          title: form.title,
          whenToRead: form.whenToRead,
          body: form.body,
          handle: form.handle.trim().length > 0 ? form.handle : undefined,
        },
      });
      editing.current = false;
      setNotice('Created');
      setDocument(made);
      setScreen({ kind: 'document', id: made.id });
    } catch (err: unknown) {
      refuseField(err);
    } finally {
      setBusy(false);
    }
  };

  const save = async (): Promise<void> => {
    if (apis === null || document === null) {
      return;
    }
    setBusy(true);
    try {
      const saved = await apis.knowledge.updateKnowledge({
        id: document.id,
        updateKnowledgeDto: {
          rev: document.rev,
          title: form.title,
          whenToRead: form.whenToRead,
          body: form.body,
          handle: form.handle,
        },
      });
      editing.current = false;
      setNotice(`Saved as rev ${saved.rev}`);
      setDocument(saved);
      setScreen({ kind: 'document', id: saved.id });
    } catch (err: unknown) {
      refuseField(err);
    } finally {
      setBusy(false);
    }
  };

  const reloadStale = async (): Promise<void> => {
    if (apis === null || document === null) {
      return;
    }
    try {
      const fresh = await apis.knowledge.readKnowledge({ id: document.id });
      setDocument(fresh);
      startEdit(fresh);
    } catch (err: unknown) {
      fail(err);
    }
  };

  const decide = async (kind: 'approve' | 'reject'): Promise<void> => {
    if (apis === null || revision === null) {
      return;
    }
    const revisionId = revision.id;
    const title = revision.title;
    try {
      if (kind === 'approve') {
        const done = await apis.knowledge.approveKnowledgeRevision({
          revisionId,
        });
        setNotice(`Approved. ${done.handle} is now rev ${done.rev}.`);
      } else {
        await apis.knowledge.rejectKnowledgeRevision({ revisionId });
        setNotice(`Rejected ${title}.`);
      }
      toList();
    } catch (err: unknown) {
      if (daemonErrorCode(err) === 'PROPOSAL_STALE') {
        setRevision(await apis.knowledge.readKnowledgeRevision({ revisionId }));
        return;
      }
      fail(err);
    }
  };

  const setStatusOf = async (next: 'archive' | 'restore'): Promise<void> => {
    if (apis === null || document === null) {
      return;
    }
    try {
      const { id } = document;
      if (next === 'archive') {
        await apis.knowledge.archiveKnowledge({ id });
      } else {
        await apis.knowledge.restoreKnowledge({ id });
      }
      await openDocument(id);
    } catch (err: unknown) {
      fail(err);
    }
  };

  const deleteForGood = async (): Promise<void> => {
    if (apis === null || document === null) {
      return;
    }
    await apis.knowledge.deleteKnowledge({ id: document.id });
    setNotice(`Deleted ${document.title}.`);
    toList();
  };

  const exportOne = async (): Promise<void> => {
    if (apis === null || document === null) {
      return;
    }
    try {
      const { markdown, name } = await apis.knowledge.exportKnowledge({
        id: document.id,
      });
      await window.geniro.saveKnowledgeExport({
        markdown,
        suggestedName: name,
      });
    } catch (err: unknown) {
      fail(err);
    }
  };

  const restoreRevision = async (revisionId: string): Promise<void> => {
    if (apis === null || document === null) {
      return;
    }
    const restored = await apis.knowledge.restoreKnowledgeRevision({
      revisionId,
      restoreKnowledgeRevisionDto: { rev: document.rev },
    });
    setNotice(`Saved as rev ${restored.rev}`);
    setDocument(restored);
    setScreen({ kind: 'document', id: restored.id });
  };

  const nameOf = (key: string): string => placeLabel(key, places);
  const waiting = counts?.waiting ?? 0;
  const pickerGroups: SelectGroup[] = [
    { items: [{ value: ALL_PLACES, label: 'All places' }] },
    ...placeGroups(places),
  ];
  const banners = (
    <>
      {error === null ? null : (
        <ErrorBanner message={error} onDismiss={() => setError(null)} />
      )}
      {notice === null ? null : (
        <p
          role="status"
          className="flex items-center gap-2 text-sm text-muted-foreground">
          <Check aria-hidden="true" className="size-4 shrink-0" />
          {notice}
        </p>
      )}
    </>
  );

  let body: React.ReactNode;
  if (screen.kind === 'new' || screen.kind === 'edit') {
    const isNew = screen.kind === 'new';
    const cancelForm =
      isNew || document === null
        ? toList
        : (): void => {
            editing.current = false;
            setStale(false);
            setScreen({ kind: 'document', id: document.id });
          };
    body = (
      <div className="flex min-w-0 flex-col gap-4">
        <div>
          <BackLink
            label={isNew ? 'Knowledge' : (document?.title ?? 'Knowledge')}
            onClick={cancelForm}
          />
        </div>
        <h2 className="text-title font-semibold">
          {isNew ? 'New document' : `Edit ${document?.title ?? ''}`}
        </h2>
        {stale ? (
          <KnowledgeNote
            action={
              <Button
                type="button"
                size="sm"
                variant="outline"
                onClick={() => void reloadStale()}>
                Reload
              </Button>
            }>
            This document changed while you were editing. Your text is kept
            here.
          </KnowledgeNote>
        ) : null}
        <KnowledgeForm
          value={form}
          places={places}
          isNew={isNew}
          busy={busy}
          errors={formErrors}
          submitLabel={isNew ? 'Create' : 'Save'}
          onChange={(value) => {
            setFormErrors({});
            setForm(value);
          }}
          onCancel={cancelForm}
          onSubmit={() => void (isNew ? create() : save())}
        />
      </div>
    );
  } else if (screen.kind === 'review' && revision !== null) {
    body = (
      <KnowledgeReview
        revision={revision}
        onBack={toList}
        onApprove={() => decide('approve')}
        onReject={() => decide('reject')}
        onOpenDocument={() => void openDocument(revision.documentId)}
      />
    );
  } else if (screen.kind === 'history' && document !== null && apis !== null) {
    body = (
      <KnowledgeHistory
        apis={apis}
        document={document}
        onBack={() => setScreen({ kind: 'document', id: document.id })}
        onRestore={restoreRevision}
      />
    );
  } else if (screen.kind === 'document' && document !== null) {
    body = (
      <KnowledgeDocumentView
        document={document}
        placeName={nameOf(document.place)}
        canExport={!remote}
        onBack={toList}
        onEdit={() => startEdit(document)}
        onHistory={() => setScreen({ kind: 'history', id: document.id })}
        onExport={() => void exportOne()}
        onArchive={() => void setStatusOf('archive')}
        onRestore={() => void setStatusOf('restore')}
        onDelete={deleteForGood}
        onReview={(head) => void openReview(head.id)}
      />
    );
  } else {
    body = (
      <>
        <LibraryHeader
          title="Knowledge"
          count={list.documents === null ? null : list.documents.length}
          subtitle="Documents agents read when a task calls for them."
          actions={
            <Button
              type="button"
              className="h-8 gap-2 rounded-control"
              disabled={apis === null}
              onClick={startNew}>
              <Plus aria-hidden="true" className="shrink-0" /> New document
            </Button>
          }
        />
        <div className="flex min-w-0 flex-wrap items-center gap-2">
          <div className="min-w-0 shrink">
            <Select
              aria-label="Place"
              variant="ghost"
              groups={pickerGroups}
              value={place ?? ALL_PLACES}
              onValueChange={(next) =>
                onPlaceChange(next === ALL_PLACES ? null : next)
              }
            />
          </div>
          <label className="relative min-w-[10rem] flex-1">
            <Search
              aria-hidden="true"
              className="absolute top-1/2 left-2.5 size-4 -translate-y-1/2 text-muted-foreground"
            />
            <Input
              aria-label="Search documents"
              placeholder="Search"
              className="pl-8"
              value={q}
              onChange={(event) => setQ(event.target.value)}
            />
          </label>
          <span className="relative">
            <Button
              type="button"
              variant="ghost"
              size="sm"
              aria-haspopup="menu"
              aria-expanded={filterOpen}
              aria-label="Status"
              onClick={() => setFilterOpen(true)}>
              {STATUS_LABEL[status]}
              <ChevronDown aria-hidden="true" />
            </Button>
            <Menu
              open={filterOpen}
              align="end"
              side="bottom"
              value={status}
              groups={[
                {
                  items: Object.entries(STATUS_LABEL).map(([value, label]) => ({
                    value,
                    label,
                  })),
                },
              ]}
              onSelect={(value) => {
                setFilterOpen(false);
                setStatus(value as KnowledgeStatusFilter);
              }}
              onClose={() => setFilterOpen(false)}
            />
          </span>
          {waiting > 0 && status === 'active' ? (
            <button type="button" onClick={() => setStatus('waiting')}>
              <Badge variant="warning">{waiting} waiting</Badge>
            </button>
          ) : null}
        </div>
        {agentsOff ? (
          <KnowledgeNote>
            Agents do not read knowledge right now. Turn it on in Settings →
            Knowledge. The documents below stay here to edit.
          </KnowledgeNote>
        ) : null}
        {list.error === null ? null : (
          <KnowledgeNote
            action={
              <Button
                type="button"
                size="sm"
                variant="outline"
                onClick={list.reload}>
                Retry
              </Button>
            }>
            {list.error}
          </KnowledgeNote>
        )}
        {list.documents === null ? (
          list.error === null ? (
            <p className="text-sm text-muted-foreground">Loading documents…</p>
          ) : null
        ) : list.documents.length === 0 ? (
          q.length > 0 || status !== 'active' ? (
            <EmptyState className="h-auto py-10">
              Nothing matches. Try other words, or clear the filters.
            </EmptyState>
          ) : (
            <EmptyState
              className="h-auto py-10"
              icon={<BookOpen aria-hidden="true" />}
              actions={
                <Button
                  type="button"
                  disabled={apis === null}
                  onClick={startNew}>
                  <Plus aria-hidden="true" /> New document
                </Button>
              }>
              No documents here yet. Put a long guide here instead of in the
              instructions, and agents read it when it helps.
            </EmptyState>
          )
        ) : (
          <ul className="flex min-w-0 flex-col gap-2">
            {list.documents.map((row) => (
              <li key={row.id} className="min-w-0">
                <KnowledgeRow
                  document={row}
                  placeName={nameOf(row.place)}
                  onOpen={openRow}
                />
              </li>
            ))}
          </ul>
        )}
        {list.hasMore ? (
          <div className="flex justify-center">
            <Button
              type="button"
              variant="outline"
              size="sm"
              onClick={list.loadMore}>
              Load more
            </Button>
          </div>
        ) : null}
      </>
    );
  }

  return (
    <div className="h-full min-h-0 overflow-y-auto">
      <div className="mx-auto flex max-w-[860px] min-w-0 flex-col gap-6 px-4 py-8 sm:px-6">
        {banners}
        {body}
      </div>
    </div>
  );
}
