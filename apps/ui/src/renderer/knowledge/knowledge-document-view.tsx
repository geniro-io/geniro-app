import { History, MoreHorizontal, Pencil } from 'lucide-react';
import { useState } from 'react';

import type {
  KnowledgeDocumentDetailDto,
  KnowledgeHead,
} from '../autogenerated';
import { MarkdownContent } from '../chats/markdown-content';
import { BackLink } from '../components/back-link';
import { ConfirmActionButton } from '../components/confirm-action-button';
import { CopyButton } from '../components/copy-button';
import { Badge } from '../components/ui/badge';
import { Button } from '../components/ui/button';
import { Menu } from '../components/ui/menu';
import { formatBytes } from '../format-bytes';
import { KnowledgeNote } from './knowledge-note';
import { KnowledgeRawText } from './knowledge-raw-text';
import { byLine, referenceOf, shortDate } from './knowledge-text';

/** One document: its when-to-read line, its text, and what can be done to it. */
export function KnowledgeDocumentView({
  document,
  placeName,
  canExport,
  onBack,
  onEdit,
  onHistory,
  onExport,
  onArchive,
  onRestore,
  onDelete,
  onReview,
}: {
  document: KnowledgeDocumentDetailDto;
  placeName: string;
  /** False on a paired phone, which has no file dialog. */
  canExport: boolean;
  onBack: () => void;
  onEdit: () => void;
  onHistory: () => void;
  onExport: () => void;
  onArchive: () => void;
  onRestore: () => void;
  onDelete: () => Promise<void>;
  onReview: (head: KnowledgeHead) => void;
}): React.JSX.Element {
  const [moreOpen, setMoreOpen] = useState(false);
  const archived = document.status === 'archived';
  return (
    <div className="flex min-w-0 flex-col gap-4">
      <div>
        <BackLink label="Knowledge" onClick={onBack} />
      </div>
      {archived ? (
        <KnowledgeNote
          action={
            <span className="flex gap-2">
              <Button
                type="button"
                size="sm"
                variant="outline"
                onClick={onRestore}>
                Restore
              </Button>
              <ConfirmActionButton
                question={`Delete ${document.title} for good?`}
                description="Its text and every version go. This cannot be undone."
                confirmLabel="Delete"
                busyLabel="Deleting…"
                confirmVariant="destructive"
                onConfirm={onDelete}>
                Delete
              </ConfirmActionButton>
            </span>
          }>
          Archived. Agents no longer see this document.
        </KnowledgeNote>
      ) : null}
      {document.pending > 0 && !archived ? (
        <KnowledgeNote
          action={
            <Button
              type="button"
              size="sm"
              variant="outline"
              onClick={() => onReview(document)}>
              Review
            </Button>
          }>
          {document.pending === 1
            ? 'An agent proposed a change to this document.'
            : `Agents proposed ${document.pending} changes to this document.`}
        </KnowledgeNote>
      ) : null}
      {document.status === 'active' && document.approvedAt === null ? (
        <KnowledgeNote>
          An agent saved this and you have not reviewed it. Agents read it
          marked unreviewed, and it stays out of the index.
        </KnowledgeNote>
      ) : null}
      <header className="flex flex-wrap items-start gap-3">
        <h2 className="flex min-w-0 flex-1 flex-wrap items-center gap-2 text-title font-semibold break-words">
          {document.title}
          <Badge variant="muted">{placeName}</Badge>
        </h2>
        <div className="flex items-center gap-2">
          {archived ? null : (
            <Button type="button" variant="outline" size="sm" onClick={onEdit}>
              <Pencil aria-hidden="true" /> Edit
            </Button>
          )}
          <span className="relative">
            <Button
              type="button"
              variant="outline"
              size="sm"
              aria-label="More"
              aria-haspopup="menu"
              aria-expanded={moreOpen}
              onClick={() => setMoreOpen(true)}>
              <MoreHorizontal aria-hidden="true" />
            </Button>
            <Menu
              open={moreOpen}
              align="end"
              side="bottom"
              groups={[
                {
                  items: [
                    {
                      value: 'history',
                      label: 'History',
                      icon: <History className="size-4" aria-hidden />,
                    },
                    ...(canExport
                      ? [{ value: 'export', label: 'Export as Markdown' }]
                      : []),
                    ...(archived
                      ? []
                      : [{ value: 'archive', label: 'Archive' }]),
                  ],
                },
              ]}
              onSelect={(value) => {
                setMoreOpen(false);
                if (value === 'history') {
                  onHistory();
                } else if (value === 'export') {
                  onExport();
                } else if (value === 'archive') {
                  onArchive();
                }
              }}
              onClose={() => setMoreOpen(false)}
            />
          </span>
        </div>
      </header>
      <div className="flex flex-wrap items-center gap-2 text-sm">
        <code className="rounded-control bg-muted px-2 py-0.5 break-all">
          {document.handle}
        </code>
        <CopyButton
          text={referenceOf(document.handle)}
          label="Copy reference"
          showLabel
        />
        <span className="text-xs text-muted-foreground">Stored in Geniro</span>
      </div>
      <section className="rounded-card bg-card p-4 ring-1 ring-border">
        <h3 className="text-sm font-medium">When to read</h3>
        <p className="text-sm text-muted-foreground break-words">
          {document.whenToRead}
        </p>
      </section>
      {document.approvedAt === null ? (
        <KnowledgeRawText text={document.body} />
      ) : (
        <MarkdownContent content={document.body} />
      )}
      <p className="text-xs text-muted-foreground">
        rev {document.rev} · {formatBytes(document.bodyBytes)} ·{' '}
        {shortDate(document.updatedAt)} · {byLine(document.source)}
      </p>
    </div>
  );
}
