import { useEffect, useState } from 'react';

import type { DeleteProjectKnowledgeEnum } from '../autogenerated';
import { type FateOption, FateOptions } from '../components/fate-options';
import type { DaemonApis } from '../daemon-api';

export type KnowledgeFate = DeleteProjectKnowledgeEnum;

const FATES: readonly FateOption<KnowledgeFate>[] = [
  {
    fate: 'global',
    label: 'Move them to Global',
    detail: 'Every run reads them from now on.',
  },
  {
    fate: 'delete',
    label: 'Delete them too',
    detail: 'Their text and every version go. This cannot be undone.',
  },
];

const FATES_OF_ONE: readonly FateOption<KnowledgeFate>[] = [
  {
    fate: 'global',
    label: 'Move it to Global',
    detail: 'Every run reads it from now on.',
  },
  {
    fate: 'delete',
    label: 'Delete it too',
    detail: 'Its text and every version go. This cannot be undone.',
  },
];

/** What a place holds, counted when its delete dialog opens. */
export interface KnowledgeHeld {
  /** Null when the count failed, or for a closed dialog. */
  count: number | null;
  /** False until the count has answered: the delete waits for it. */
  settled: boolean;
}

/**
 * How many documents `place` holds, read when it is named. A delete must not go
 * ahead on the default fate before the user could see the question.
 */
export function useKnowledgeHeld(
  apis: DaemonApis | null,
  place: string | null,
): KnowledgeHeld {
  const knowledgeApi = apis?.knowledge ?? null;
  const [read, setRead] = useState<{
    place: string;
    count: number | null;
  } | null>(null);

  useEffect(() => {
    if (knowledgeApi === null || place === null) {
      return;
    }
    let live = true;
    knowledgeApi
      .knowledgeCounts()
      .then(
        (counts) =>
          counts.places.find((row) => row.place === place)?.documents ?? 0,
        () => null,
      )
      .then((count) => {
        if (live) {
          setRead({ place, count });
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, [knowledgeApi, place]);

  return read !== null && read.place === place
    ? { count: read.count, settled: true }
    : { count: null, settled: knowledgeApi === null };
}

/**
 * What deleting a project or team does with the documents filed under it,
 * asked in the delete dialog. Draws nothing while the place holds none; a count
 * that failed says what the default does.
 */
export function KnowledgeFatePick({
  held,
  value,
  onChange,
}: {
  held: KnowledgeHeld;
  value: KnowledgeFate;
  onChange: (fate: KnowledgeFate) => void;
}): React.JSX.Element | null {
  if (!held.settled || held.count === 0) {
    return null;
  }
  if (held.count === null) {
    return (
      <p>
        Its knowledge documents could not be counted. Any it holds move to
        Global.
      </p>
    );
  }
  return (
    <div data-slot="knowledge-fate" className="flex flex-col gap-2">
      <p>
        Its{' '}
        {held.count === 1
          ? 'knowledge document'
          : `${held.count} knowledge documents`}
        :
      </p>
      <FateOptions
        label="Knowledge documents"
        fates={held.count === 1 ? FATES_OF_ONE : FATES}
        value={value}
        onChange={onChange}
      />
    </div>
  );
}
