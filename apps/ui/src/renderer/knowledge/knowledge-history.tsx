import { useEffect, useState } from 'react';

import type {
  KnowledgeDocumentDetailDto,
  KnowledgeRevisionDetailDto,
  KnowledgeRevisionHead,
} from '../autogenerated';
import { UnifiedDiff } from '../chats/diff-view';
import { BackLink } from '../components/back-link';
import { ConfirmActionButton } from '../components/confirm-action-button';
import { ErrorBanner } from '../components/error-banner';
import { Badge } from '../components/ui/badge';
import { cn } from '../components/ui/utils';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import { byLine, revisionLabel, shortDate } from './knowledge-text';

/** Every kept version, its diff from the one before, and a way back to it. */
export function KnowledgeHistory({
  apis,
  document,
  onBack,
  onRestore,
}: {
  apis: DaemonApis;
  document: KnowledgeDocumentDetailDto;
  onBack: () => void;
  onRestore: (revisionId: string) => Promise<void>;
}): React.JSX.Element {
  const [revisions, setRevisions] = useState<KnowledgeRevisionHead[] | null>(
    null,
  );
  const [selected, setSelected] = useState<string | null>(null);
  const [detail, setDetail] = useState<KnowledgeRevisionDetailDto | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let live = true;
    void apis.knowledge
      .listKnowledgeRevisions({ id: document.id })
      .then((list) => {
        if (live) {
          const applied = list.revisions.filter(
            (revision) => revision.status === 'applied',
          );
          setRevisions(applied);
          setSelected(applied[0]?.id ?? null);
        }
      })
      .catch((err: unknown) => {
        if (live) {
          setError(describeDaemonError(err));
        }
      });
    return () => {
      live = false;
    };
  }, [apis, document.id, document.rev]);

  useEffect(() => {
    if (selected === null) {
      return;
    }
    let live = true;
    void apis.knowledge
      .readKnowledgeRevision({ revisionId: selected })
      .then((read) => {
        if (live) {
          setDetail(read);
        }
      })
      .catch((err: unknown) => {
        if (live) {
          setError(describeDaemonError(err));
        }
      });
    return () => {
      live = false;
    };
  }, [apis, selected]);

  const current = detail?.rev === document.rev;
  return (
    <div className="flex min-w-0 flex-col gap-4">
      <BackLink label={document.title} onClick={onBack} />
      <h2 className="text-title font-semibold">History</h2>
      {error === null ? null : (
        <ErrorBanner message={error} onDismiss={() => setError(null)} />
      )}
      <div className="grid min-w-0 gap-4 md:grid-cols-[minmax(0,18rem)_minmax(0,1fr)]">
        <ul className="flex min-w-0 flex-col gap-1">
          {(revisions ?? []).map((revision) => (
            <li key={revision.id}>
              <button
                type="button"
                aria-pressed={revision.id === selected}
                onClick={() => setSelected(revision.id)}
                className={cn(
                  'flex w-full min-w-0 flex-col gap-0.5 rounded-control p-2 text-left text-sm hover:bg-accent',
                  revision.id === selected && 'bg-accent',
                )}>
                <span className="flex items-center gap-2 font-medium">
                  rev {revision.rev}
                  {revision.rev === document.rev ? (
                    <Badge variant="muted">Current</Badge>
                  ) : null}
                </span>
                <span className="text-muted-foreground break-words">
                  {revisionLabel(revision)}
                </span>
                <span className="text-xs text-muted-foreground">
                  {shortDate(revision.createdAt)} · {byLine(revision.source)}
                </span>
              </button>
            </li>
          ))}
        </ul>
        <div className="flex min-w-0 flex-col gap-3">
          {detail === null ? null : detail.diff.length > 0 ? (
            <div className="min-w-0 overflow-x-auto rounded-card ring-1 ring-border">
              <UnifiedDiff diff={detail.diff} />
            </div>
          ) : (
            <p className="text-sm text-muted-foreground">
              {detail.baseKept
                ? 'There is no line-by-line diff for this version.'
                : 'The version before this one is no longer kept.'}
            </p>
          )}
          {detail === null ? null : current ? (
            <p className="text-sm text-muted-foreground">
              This is the current text.
            </p>
          ) : (
            <div className="flex justify-end">
              <ConfirmActionButton
                variant="default"
                question={`Restore rev ${detail.rev}?`}
                description={`Its text becomes rev ${document.rev + 1}; rev ${document.rev} stays in the history.`}
                confirmLabel="Restore this version"
                busyLabel="Restoring…"
                confirmVariant="default"
                onConfirm={() => onRestore(detail.id)}>
                Restore this version
              </ConfirmActionButton>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
