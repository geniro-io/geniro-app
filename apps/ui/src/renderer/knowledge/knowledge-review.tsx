import type { KnowledgeRevisionDetailDto } from '../autogenerated';
import { UnifiedDiff } from '../chats/diff-view';
import { BackLink } from '../components/back-link';
import { ConfirmActionButton } from '../components/confirm-action-button';
import { CopyButton } from '../components/copy-button';
import { Button } from '../components/ui/button';
import { KnowledgeNote } from './knowledge-note';
import { KnowledgeRawText } from './knowledge-raw-text';
import { byLine } from './knowledge-text';

/**
 * One proposal against what it changes. A change whose document moved on
 * cannot be approved: it would overwrite newer text unseen, so its text is
 * offered to merge by hand instead.
 */
export function KnowledgeReview({
  revision,
  onBack,
  onApprove,
  onReject,
  onOpenDocument,
}: {
  revision: KnowledgeRevisionDetailDto;
  onBack: () => void;
  onApprove: () => Promise<void>;
  onReject: () => Promise<void>;
  onOpenDocument: () => void;
}): React.JSX.Element {
  const isNew = revision.baseRev === 0;
  const unseenBase = !isNew && revision.document.approvedAt === null;
  return (
    <div className="flex min-w-0 flex-col gap-4">
      <div>
        <BackLink label="Waiting for review" onClick={onBack} />
      </div>
      <header className="flex min-w-0 flex-col gap-1">
        <h2 className="text-title font-semibold break-words">
          {revision.title}
        </h2>
        <p className="text-sm break-words">
          <span className="text-muted-foreground">When to read: </span>
          {revision.whenToRead}
        </p>
        <p className="text-sm text-muted-foreground">
          {isNew ? 'New document' : `On rev ${revision.baseRev}`}, proposed by{' '}
          {byLine(revision.source)}
          {revision.source.memberId ? ` (${revision.source.memberId})` : ''}
        </p>
        {revision.reason ? (
          <p className="text-sm break-words">{revision.reason}</p>
        ) : null}
      </header>
      {revision.stale ? (
        <KnowledgeNote
          action={
            <CopyButton text={revision.body} label="Copy proposed text" />
          }>
          The document moved on to rev {revision.document.rev}, so this proposal
          cannot be approved. Copy its text to merge it by hand.
        </KnowledgeNote>
      ) : null}
      {unseenBase ? (
        <KnowledgeNote>
          You never reviewed this document, so approving this change approves
          its whole text, shown below.
        </KnowledgeNote>
      ) : null}
      {revision.diff.length > 0 && !unseenBase ? (
        <div className="min-w-0 overflow-x-auto rounded-card ring-1 ring-border">
          <UnifiedDiff diff={revision.diff} />
        </div>
      ) : (
        <>
          {isNew || unseenBase ? null : (
            <KnowledgeNote>
              There is no line-by-line diff for this change. This is the
              proposed text.
            </KnowledgeNote>
          )}
          <KnowledgeRawText text={revision.body} />
        </>
      )}
      <div className="flex flex-wrap justify-end gap-2">
        {revision.stale ? (
          <Button type="button" variant="link" onClick={onOpenDocument}>
            Open the document
          </Button>
        ) : null}
        <ConfirmActionButton
          question={`Reject this ${isNew ? 'document' : 'change'}?`}
          description={
            isNew
              ? 'It is deleted and its handle is free again.'
              : 'The document stays as it is.'
          }
          confirmLabel="Reject"
          busyLabel="Rejecting…"
          confirmVariant="destructive"
          onConfirm={onReject}>
          Reject
        </ConfirmActionButton>
        {revision.stale ? null : (
          <ConfirmActionButton
            variant="default"
            question={`Approve this ${isNew ? 'document' : 'change'}?`}
            description="The next read returns this text. A run already going keeps its index until it ends."
            confirmLabel="Approve"
            busyLabel="Approving…"
            confirmVariant="default"
            onConfirm={onApprove}>
            Approve
          </ConfirmActionButton>
        )}
      </div>
    </div>
  );
}
