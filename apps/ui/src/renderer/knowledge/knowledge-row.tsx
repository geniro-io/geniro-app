import type { KnowledgeHead } from '../autogenerated';
import { CARD_BUTTON_CLASS } from '../components/card-hover';
import { Badge } from '../components/ui/badge';
import { cn } from '../components/ui/utils';
import { metaLine } from './knowledge-text';

/** One document in the list; the text it shows never includes the body. */
export function KnowledgeRow({
  document,
  placeName,
  onOpen,
}: {
  document: KnowledgeHead;
  placeName: string;
  onOpen: (document: KnowledgeHead) => void;
}): React.JSX.Element {
  return (
    <button
      type="button"
      onClick={() => onOpen(document)}
      className={cn(
        'flex w-full min-w-0 flex-col gap-1 rounded-card bg-card p-4 text-left ring-1 ring-border',
        CARD_BUTTON_CLASS,
      )}>
      <span className="flex min-w-0 flex-wrap items-center gap-2">
        <span className="min-w-0 font-medium break-words">
          {document.title}
        </span>
        <Badge variant="muted">{placeName}</Badge>
        {document.status === 'proposed' ? (
          <Badge variant="warning">New · waiting for review</Badge>
        ) : document.pending > 0 ? (
          <Badge variant="warning">Change · waiting for review</Badge>
        ) : null}
        {document.status === 'archived' ? (
          <Badge variant="muted">Archived</Badge>
        ) : null}
        {document.status === 'active' && document.approvedAt === null ? (
          <Badge variant="warning">Unreviewed</Badge>
        ) : null}
      </span>
      <span className="text-sm text-muted-foreground break-words">
        {document.whenToRead}
      </span>
      <span className="text-xs text-muted-foreground break-all">
        {metaLine(document)}
      </span>
    </button>
  );
}
