import type { KnowledgeHead, KnowledgeRevisionHead } from '../autogenerated';
import { formatBytes } from '../format-bytes';

/** TWIN: `KNOWLEDGE_TITLE_MAX_CHARS` and friends in `apps/daemon/src/v1/knowledge/knowledge.types.ts`. */
export const KNOWLEDGE_TITLE_MAX_CHARS = 200;
export const KNOWLEDGE_WHEN_MAX_CHARS = 300;
export const KNOWLEDGE_HANDLE_MAX_CHARS = 80;

export const GLOBAL_PLACE = 'global';

/** Of a run's rows for one handle, nearest first: a live one before an archived one. */
export function currentOf(
  documents: KnowledgeHead[],
): KnowledgeHead | undefined {
  return documents.find((row) => row.status !== 'archived') ?? documents[0];
}

/** TWIN: `placeKeyOf` in `apps/daemon/src/v1/knowledge/utils/knowledge-text.ts`. */
export function projectPlace(projectId: string): string {
  return `project:${projectId}`;
}

/** TWIN: `placeKeyOf` in `apps/daemon/src/v1/knowledge/utils/knowledge-text.ts`. */
export function teamPlace(slug: string): string {
  return `team:${slug}`;
}

/** A place as the picker and a badge name it. */
export interface KnowledgePlace {
  key: string;
  label: string;
  /** The project's folder name, which tells two checkouts apart. */
  hint?: string;
  kind: 'project' | 'team' | 'global';
}

export function placeLabel(
  key: string,
  places: readonly KnowledgePlace[],
): string {
  const known = places.find((place) => place.key === key);
  if (known) {
    return known.label;
  }
  if (key === GLOBAL_PLACE) {
    return 'Global';
  }
  return key.slice(key.indexOf(':') + 1);
}

/** TWIN: `handleFromTitle` in `apps/daemon/src/v1/knowledge/utils/knowledge-text.ts`. */
export function handleFromTitle(title: string): string {
  return title
    .trim()
    .toLowerCase()
    .replace(/[^\p{Ll}\p{Lm}\p{Lo}\p{M}\p{N}]+/gu, '-')
    .slice(0, KNOWLEDGE_HANDLE_MAX_CHARS)
    .replace(/^-+|-+$/g, '');
}

export function shortDate(iso: string): string {
  return new Date(iso).toLocaleDateString(undefined, {
    month: 'short',
    day: 'numeric',
  });
}

/** Who wrote a document or revision. */
export function byLine(source: KnowledgeHead['source']): string {
  if (source.actor === 'user') {
    return 'You';
  }
  const agent = source.agentKind ?? 'agent';
  return source.model ? `${agent} · ${source.model}` : `${agent} · agent`;
}

/** What a row or a header says about a document. */
export function metaLine(document: KnowledgeHead): string {
  return [
    document.handle,
    formatBytes(document.bodyBytes),
    shortDate(document.updatedAt),
    byLine(document.source),
  ].join(' · ');
}

/** The sentence instructions cite a document by. */
export function referenceOf(handle: string): string {
  return `read the knowledge document ${handle}`;
}

/** What a delete moved to Global under a new name, or null. */
export function renamedNotice(
  renamed: readonly { from: string; to: string }[],
): string | null {
  return renamed.length === 0
    ? null
    : `Moved to Global under new handles, so instructions naming the old ones stop finding them: ${renamed
        .map(({ from, to }) => `${from} → ${to}`)
        .join(', ')}.`;
}

export function revisionLabel(revision: KnowledgeRevisionHead): string {
  return revision.reason ?? `Saved by ${byLine(revision.source)}`;
}
