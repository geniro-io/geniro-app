import { useEffect, useRef, useState } from 'react';

import type {
  KnowledgeCountsDto,
  KnowledgeHead,
  ListKnowledgeStatusEnum,
} from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

export type KnowledgeStatusFilter = ListKnowledgeStatusEnum;

export interface KnowledgeQuery {
  /** Null is every place. */
  place: string | null;
  status: KnowledgeStatusFilter;
  q: string;
}

export interface KnowledgeListState {
  /** Null until the first answer. */
  documents: KnowledgeHead[] | null;
  error: string | null;
  hasMore: boolean;
  loadMore: () => void;
  reload: () => void;
}

const PAGE = 50;

/** A search waits for a pause in the typing. */
const SEARCH_DELAY_MS = 250;

/**
 * One page of documents and on, read again whenever a knowledge write lands
 * anywhere and after a reconnect, which may have missed one.
 */
export function useKnowledgeList(
  apis: DaemonApis | null,
  client: DaemonClient | null,
  { place, status, q }: KnowledgeQuery,
): KnowledgeListState {
  const [documents, setDocuments] = useState<KnowledgeHead[] | null>(null);
  const [next, setNext] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const generation = useRef(0);

  const read = useLatestCallback(
    (cursor: string | null) => {
      if (apis === null) {
        return;
      }
      const mine = ++generation.current;
      void apis.knowledge
        .listKnowledge({
          place: place ?? undefined,
          status,
          q: q.trim().length > 0 ? q.trim() : undefined,
          limit: PAGE,
          cursor: cursor ?? undefined,
        })
        .then((page) => {
          if (mine !== generation.current) {
            return;
          }
          setDocuments((held) =>
            cursor === null
              ? page.documents
              : [...(held ?? []), ...page.documents],
          );
          setNext(page.next);
          setError(null);
        })
        .catch((err: unknown) => {
          if (mine === generation.current) {
            setError(describeDaemonError(err));
          }
        });
    },
    [apis, place, status, q],
  );

  useEffect(() => {
    const timer = setTimeout(() => read(null), q === '' ? 0 : SEARCH_DELAY_MS);
    return () => clearTimeout(timer);
  }, [read, apis, place, status, q]);

  useEffect(() => {
    if (client === null) {
      return;
    }
    const offChanged = client.onKnowledgeChanged(() => read(null));
    const offConnected = client.onReconnect(() => read(null));
    return () => {
      offChanged();
      offConnected();
    };
  }, [client, read]);

  return {
    documents,
    error,
    hasMore: next !== null,
    loadMore: () => read(next),
    reload: () => read(null),
  };
}

/** The store's counts, read again on every knowledge write. */
export function useKnowledgeCounts(
  apis: DaemonApis | null,
  client: DaemonClient | null,
): KnowledgeCountsDto | null {
  const [counts, setCounts] = useState<KnowledgeCountsDto | null>(null);
  const read = useLatestCallback(() => {
    void apis?.knowledge
      .knowledgeCounts()
      .then(setCounts)
      .catch(() => undefined);
  }, [apis]);

  useEffect(() => {
    read();
    if (client === null) {
      return;
    }
    const offChanged = client.onKnowledgeChanged(read);
    const offConnected = client.onReconnect(read);
    return () => {
      offChanged();
      offConnected();
    };
  }, [apis, client, read]);

  return counts;
}
