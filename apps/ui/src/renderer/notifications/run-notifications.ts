import type { RunNotificationKind } from '../../shared/contracts';
import type { RunAwaiting } from '../autogenerated';
import type { RunStatusKind } from '../chats/run-status';
import { awaitingPhrase, isSettledRunStatus } from '../chats/run-status';

/**
 * When a thread is worth interrupting the user for, and what the banner says.
 *
 * This is the renderer's half of the notifications module (`main/notifications/`
 * is the other): it decides WHEN, and main decides WHETHER. The split is not
 * arbitrary — the daemon knows a turn settled, but only this side knows whether
 * anyone is looking at it, and "the user is watching this exact chat" is the
 * one case where a banner is pure noise.
 *
 * Everything here is pure, so the rules can be pinned without a DOM or a
 * notification permission; {@link import('./use-run-notifications')} is the
 * thin React binding over it.
 */

/** One run that just crossed into a state worth interrupting the user for. */
export interface RunNotificationTrigger {
  runId: string;
  kind: RunNotificationKind;
  /** The status it landed in — what the body is worded from. */
  status: RunStatusKind;
}

/**
 * Which runs crossed into a notifiable state between two readings.
 *
 * The readings are DISPLAY statuses — the same ones the sidebar badges show,
 * never the daemon's row. A notification that fired while the badge said
 * something else would be the two surfaces disagreeing about one run, and the
 * badge is what the user checks when they get there.
 *
 * Four rules, each of which is a defect if dropped:
 *
 * 1. **A run seen for the first time never notifies.** The chat list loads with
 *    every past thread already in its final state, so a first reading that
 *    notified would open the app with a banner per finished conversation in the
 *    user's history.
 * 2. **`cancelled` is not an ending worth announcing.** It is the outcome of the
 *    user pressing Stop — they are at the keyboard by definition, and telling
 *    them what they just did is the notification everybody switches the feature
 *    off over. `failed` IS announced: nobody asked for it.
 * 3. **A question outranks a settle.** Both can be true of one reading, and the
 *    question is the one that will not advance without the user.
 * 4. **A turn that did nothing but HOUSEKEEPING is not an ending either.** A
 *    `/compact` is an ordinary turn on the wire, so it settled the run and
 *    earned a banner reporting a piece of context management the user asked
 *    for and can see the result of — reported as "no notification needed when
 *    compact fires". The daemon says which settles are not news:
 *    `RunStatusEvent.housekeeping` (the turn was only a compaction) and
 *    `RunStatusEvent.restored` (a delegate lease handing an already-settled
 *    status back). A question is still raised either way, because a turn parked
 *    on the user is news whatever else it did.
 */
export function diffRunNotifications(
  previous: ReadonlyMap<string, RunStatusKind>,
  current: ReadonlyMap<string, RunStatusKind>,
  /**
   * Runs whose most recent settle the daemon marked as not news — rule 4.
   * Either `RunStatusEvent.housekeeping` (the turn was only a compaction) or
   * `RunStatusEvent.restored` (a lease handing a settled status back).
   *
   * A set of ids rather than a flag on the status map, because it answers a
   * different question: the map says what a run IS, this says what the turn
   * that got it there was. Empty by default, so a caller that has no such
   * reading behaves exactly as before.
   */
  quiet: ReadonlySet<string> = new Set(),
): RunNotificationTrigger[] {
  const triggers: RunNotificationTrigger[] = [];
  for (const [runId, status] of current) {
    const before = previous.get(runId);
    // Rule 1 — never seen, so there is no transition, only a starting point.
    if (before === undefined || before === status) {
      continue;
    }
    if (status === 'needs-input') {
      triggers.push({ runId, kind: 'question', status });
      continue;
    }
    // Rule 2 — `cancelled` is deliberately absent from this condition even
    // though `isSettledRunStatus` includes it. Rule 4 sits beside it as a
    // second kind of ending nobody asked to hear about.
    if (
      status !== 'cancelled' &&
      !quiet.has(runId) &&
      isSettledRunStatus(status) &&
      !isSettledRunStatus(before)
    ) {
      triggers.push({ runId, kind: 'turn-end', status });
    }
  }
  return triggers;
}

/**
 * How recently the newest still-running command must have been LAUNCHED for a
 * turn's ending to be held back instead of announced.
 *
 * REPORTED as "он сам 2 или 3 раза остановился, потому что просто ждет
 * завершения каких-то процессов… и в каждом из этих случаев он мне отправляет
 * false positive-нотификацию". An agent routinely ends its turn WAITING on a
 * command it just backgrounded — a test run, a build — and the CLI opens a new
 * turn of its own the moment that command reports. Nothing on the wire says
 * which kind of ending a turn is (claude's `result` line carries no word about
 * background work), so the answer is read off WHEN the command started.
 *
 * Measured on the reporter's own `geniro.db` (2026-09-14), over every turn end
 * that left a detached command running. Of 275 whose command was launched in
 * that very turn, the agent carried on by itself after 150 — and in 141 of
 * those the command had been launched at most two minutes before the turn
 * ended (117 within thirty seconds). A launch older than that is the dev
 * server left up: the agent carried on after 9 of 64 of them, and after only
 * 61 of the 699 endings whose commands all came from earlier turns.
 */
export const RECENT_LAUNCH_MS = 2 * 60_000;

/**
 * How long a held ending waits after one of its commands has ENDED before it
 * is announced after all.
 *
 * The CLI learns a command finished from the command itself, so a carried-on
 * turn speaks almost at once: measured, the agent's first row came within 10s
 * of the close in 126 of 148 cases and within 30s in 141. Speaking retracts the
 * banner, so this only ever delays a turn that really is over.
 */
export const AFTER_CLOSE_GRACE_MS = 30_000;

/**
 * The longest an ending is held while its commands are still running.
 *
 * The other end of the stick: a server launched right before the turn ended
 * never exits, and that agent IS done. Ten minutes covers 123 of the 150
 * measured commands the agent was waiting on, so a longer wait is announced
 * with a banner that may yet be followed by more work, and a server-launching
 * turn is announced ten minutes late rather than never.
 */
export const HOLD_CEILING_MS = 10 * 60_000;

/**
 * Whether a turn's ending should be held back rather than announced — a
 * command is still running, and the newest launch is recent enough that the
 * agent is most likely waiting on it. See {@link RECENT_LAUNCH_MS}.
 *
 * Everything else is announced at once. That includes a run whose commands all
 * predate the turn, which the old blanket ten-second wait delayed for nothing.
 */
export function holdsEnding({
  shellsOpen,
  launchedAt,
  now,
}: {
  /** How many detached commands the run has out right now. */
  shellsOpen: number;
  /** When a launch was last seen, or undefined if none was seen this session. */
  launchedAt: number | undefined;
  now: number;
}): boolean {
  return (
    shellsOpen > 0 &&
    launchedAt !== undefined &&
    now - launchedAt <= RECENT_LAUNCH_MS
  );
}

/**
 * The line under the thread's name.
 *
 * Worded from the kind and the status it landed in, so a failure does not
 * announce itself as a completion. The question wording reuses
 * {@link awaitingPhrase}, which is what the sidebar row says under the same
 * badge — the banner and the row it sends you to must not describe one parked
 * turn in two different ways.
 */
export function notificationBody(
  trigger: RunNotificationTrigger,
  awaiting: RunAwaiting | null,
  /**
   * What the run SAID as it settled — the agent's closing words, or the
   * failure's own message, as the daemon announced them. Null when nothing was
   * said, or on a client that predates the field.
   */
  summary: string | null = null,
): string {
  if (trigger.kind === 'question') {
    const phrase =
      awaiting === null ? 'waiting for you' : awaitingPhrase(awaiting);
    // Capitalized: this is a sentence in a banner, not a fragment trailing a
    // status word in a 260px sidebar row.
    return `${phrase.charAt(0).toUpperCase()}${phrase.slice(1)}.`;
  }
  // What actually happened, in the agent's own words, whenever there are any.
  // "The turn finished." is true of every turn that ever finished and so tells
  // the reader nothing they did not know from the banner existing — the whole
  // complaint being a notification with no content in it. A failure's message
  // matters even more: it is the one case where the user has to decide whether
  // to go and look.
  const said = oneLine(summary);
  if (said !== null) {
    return trigger.status === 'failed' ? `Failed: ${said}` : said;
  }
  return trigger.status === 'failed'
    ? 'The turn failed.'
    : 'The turn finished.';
}

/**
 * How much of a message a banner may carry.
 *
 * macOS shows two or three lines and elides the rest itself, so this is not
 * about fitting — it is about not handing the notification centre a
 * multi-kilobyte answer to store. Cut on a word where one is near the end, so
 * the ellipsis lands after a word rather than mid-syllable.
 */
const BODY_LIMIT = 220;

/**
 * One line of an agent's answer: markdown headings, code fences and blank
 * lines collapsed away, trimmed, truncated.
 *
 * The first NON-EMPTY line rather than the first: an answer routinely opens
 * with a heading or a fenced block, and a banner reading "```ts" says less than
 * no banner at all. Returns null for text with nothing readable in it, which
 * falls back to the plain sentence.
 */
function oneLine(text: string | null): string | null {
  if (text === null) {
    return null;
  }
  const line = text
    .split('\n')
    .map((row) => row.replace(/^\s*[#>*-]+\s*/, '').trim())
    .find((row) => row !== '' && !row.startsWith('```'));
  if (line === undefined || line === '') {
    return null;
  }
  if (line.length <= BODY_LIMIT) {
    return line;
  }
  const cut = line.slice(0, BODY_LIMIT);
  const lastSpace = cut.lastIndexOf(' ');
  return `${(lastSpace > BODY_LIMIT - 40 ? cut.slice(0, lastSpace) : cut).trimEnd()}…`;
}
