import { useEffect, useRef } from 'react';

import type { RunAwaiting } from '../autogenerated';
import type { RunStatusKind } from '../chats/run-status';
import { isSettledRunStatus } from '../chats/run-status';
import { diffRunNotifications, notificationBody } from './run-notifications';

/**
 * How long an ENDING waits while a detached command is still out.
 *
 * Ten seconds, and the number is borrowed rather than guessed: the daemon faced
 * this exact shape for DELEGATES and answered it with `HELD_TERMINAL_GRACE_MS`,
 * measured across 22 real releases — the agent was producing again within 4s of
 * eighteen of them and within 8.3s of twenty. A turn that resumes does so almost
 * at once, so the wait costs a few seconds on a genuine ending and removes the
 * false ones entirely.
 */
const ENDING_GRACE_MS = 10_000;

/**
 * Report every notifiable transition to main, for as long as this is mounted.
 *
 * The React binding over {@link diffRunNotifications} and nothing more — the
 * rules live next door, pure. Mounted from `Chats`, which the app shell keeps
 * mounted (hidden) across nav switches, so a thread that finishes while the
 * user is in Settings still reports. It follows EVERY run, not just the focused
 * one: a background thread nobody is watching is the entire point.
 */
export function useRunNotifications<TRun extends { id: string }>({
  runs,
  statusOf,
  labelOf,
  awaitingOf,
  summaryOf,
  quiet,
  deferEnding,
  activeRunId,
}: {
  runs: readonly TRun[];
  /** The badge reading for a run — pass the sidebar's own, never the row. */
  statusOf: (run: TRun) => RunStatusKind;
  /** The thread's name, which is what the banner is titled with. */
  labelOf: (run: TRun) => string;
  /** What a parked run is waiting for, for the wording. */
  awaitingOf: (run: TRun) => RunAwaiting | null;
  /**
   * What the run said as it settled — the agent's closing words or the
   * failure's message. Optional: without it the banner falls back to the plain
   * "the turn finished" sentence, which is what it always said.
   */
  summaryOf?: (run: TRun) => string | null;
  /**
   * Runs whose latest settle is not news — a compaction-only turn, or a
   * delegate lease handing an already-settled status back. Neither is something
   * the user asked to be told about. Rule 4 of {@link diffRunNotifications}.
   */
  quiet?: ReadonlySet<string>;
  /**
   * Whether this run's ENDING might still be undone — true while it has a
   * detached command outstanding.
   *
   * REPORTED as an agent that waits on a terminal, gets announced as done the
   * moment that terminal exits, and carries straight on a second later: "our
   * application thinks that after its execution the agent finished, although
   * actually a second later it continues". The turn really did end, so nothing
   * upstream is wrong — what is wrong is ANNOUNCING it, because a banner is a
   * one-shot assertion delivered outside the app and cannot be taken back.
   *
   * Claude Code's own UI has the identical event (a finished background task is
   * a `task-notification` that wakes the agent in the same session) and no such
   * defect, for one reason: it never makes the claim. Its "done" is the prompt
   * returning, which costs nothing to be wrong about because more output simply
   * follows. This is the closest geniro can get while keeping a feature whose
   * whole point is the user NOT looking: hold the claim briefly, and drop it if
   * the agent speaks again.
   *
   * Optional — a caller that cannot know announces immediately, exactly as
   * before.
   */
  deferEnding?: (run: TRun) => boolean;
  /** The chat on screen — suppressed while the window has focus. */
  activeRunId: string | null;
}): void {
  const seenRef = useRef<ReadonlyMap<string, RunStatusKind>>(new Map());
  /** Endings waiting out {@link ENDING_GRACE_MS}, by run. */
  const pendingRef = useRef<Map<string, ReturnType<typeof setTimeout>>>(
    new Map(),
  );
  // Every pending claim is dropped with the screen. A timer that fired after
  // unmount would announce a thread whose reading nothing is watching any more.
  useEffect(() => {
    const pending = pendingRef.current;
    return () => {
      for (const timer of pending.values()) {
        clearTimeout(timer);
      }
      pending.clear();
    };
  }, []);
  // Read at FIRE time, not captured: the effect below re-runs on every list
  // change, and a stale active id would suppress a banner for the wrong chat.
  const activeRunIdRef = useRef(activeRunId);
  activeRunIdRef.current = activeRunId;

  useEffect(() => {
    const current = new Map(runs.map((run) => [run.id, statusOf(run)]));
    const triggers = diffRunNotifications(seenRef.current, current, quiet);
    // Recorded BEFORE the posts, so a throw from one cannot leave the same
    // transition to fire again on the next reading.
    seenRef.current = current;
    // RETRACT a deferred ending the moment its agent speaks again. This runs
    // ahead of the triggers and on EVERY reading, not only ones that produced
    // one, because the whole point is the reading where nothing was triggered:
    // the run simply went back to working.
    for (const [runId, timer] of pendingRef.current) {
      const status = current.get(runId);
      if (status === undefined || !isSettledRunStatus(status)) {
        clearTimeout(timer);
        pendingRef.current.delete(runId);
      }
    }
    if (triggers.length === 0) {
      return;
    }
    const byId = new Map(runs.map((run) => [run.id, run]));
    for (const trigger of triggers) {
      const run = byId.get(trigger.runId);
      if (!run) {
        continue;
      }
      // The one case a banner is noise: the user is looking at this very chat.
      // Both halves are needed — a focused window on ANOTHER chat still earns
      // one, and so does this chat while the window is in the background.
      if (trigger.runId === activeRunIdRef.current && document.hasFocus()) {
        continue;
      }
      const post = (): void => {
        pendingRef.current.delete(trigger.runId);
        void window.geniro
          .notify({
            kind: trigger.kind,
            runId: trigger.runId,
            title: labelOf(run),
            body: notificationBody(
              trigger,
              awaitingOf(run),
              summaryOf?.(run) ?? null,
            ),
          })
          .catch((err: unknown) => {
            // A banner is never worth a broken chat list.
            console.error('failed to post a notification', err);
          });
      };
      // An ENDING a command might still undo waits; everything else goes at
      // once. A question is never deferred — it is the one state that cannot
      // advance without the user, so delaying it is the opposite of the point.
      if (trigger.kind === 'turn-end' && deferEnding?.(run) === true) {
        const timer = setTimeout(post, ENDING_GRACE_MS);
        pendingRef.current.set(trigger.runId, timer);
        continue;
      }
      post();
    }
    // `summaryOf` rides the deps with the rest: the settle that changes a run's
    // status and the sentence explaining it arrive in ONE event, so the two
    // land in the same render and the banner is worded from the settle it is
    // about rather than from the previous one.
  }, [runs, statusOf, labelOf, awaitingOf, summaryOf, quiet, deferEnding]);
}
