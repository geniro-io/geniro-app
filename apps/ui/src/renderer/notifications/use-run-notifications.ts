import { useEffect, useRef } from 'react';

import type { GeniroApi } from '../../shared/contracts';
import type { RunAwaiting } from '../autogenerated';
import type { RunStatusKind } from '../chats/run-status';
import { isSettledRunStatus } from '../chats/run-status';
import {
  type AgentNotice,
  agentNoticeBody,
  diffRunNotifications,
  endingIsProvisional,
  notificationBody,
} from './run-notifications';

/** Post one banner. A banner is never worth a broken chat list. */
function post(payload: Parameters<GeniroApi['notify']>[0]): void {
  void window.geniro.notify(payload).catch((err: unknown) => {
    console.error('failed to post a notification', err);
  });
}

/** Withdraw a run's provisional banner — the same failure policy as a post. */
function retract(runId: string): void {
  void window.geniro.retractNotification(runId).catch((err: unknown) => {
    console.error('failed to withdraw a notification', err);
  });
}

/**
 * Report every notifiable transition to main, for as long as this is mounted.
 *
 * The React binding over {@link diffRunNotifications} and nothing more — the
 * rules live next door, pure. Mounted from `Chats`, which the app shell keeps
 * mounted (hidden) across nav switches, so a thread that finishes while the
 * user is in Settings still reports. It follows EVERY run, not just the focused
 * one: a background thread nobody is watching is the entire point.
 *
 * Nothing here waits: a banner is posted in the reading it belongs to, or not
 * at all.
 */
export function useRunNotifications<TRun extends { id: string }>({
  runs,
  statusOf,
  labelOf,
  awaitingOf,
  summaryOf,
  quiet,
  shellsOpenOf,
  notices,
  activeRunId,
}: {
  runs: readonly TRun[];
  /** The badge reading for a run — pass the sidebar's own, never the row. */
  statusOf: (run: TRun) => RunStatusKind;
  /** The thread's name, which is what the banner is titled with. */
  labelOf: (run: TRun) => string;
  /** What a parked run is waiting for, for the wording. */
  awaitingOf: (run: TRun) => RunAwaiting | null;
  /**
   * What the run said as it settled — the agent's closing words or the
   * failure's message. Optional: without it the banner falls back to the plain
   * "the turn finished" sentence, which is what it always said.
   */
  summaryOf?: (run: TRun) => string | null;
  /**
   * Runs whose latest settle is not news — a compaction-only turn, or a
   * delegate lease handing an already-settled status back. Neither is something
   * the user asked to be told about. Rule 4 of {@link diffRunNotifications}.
   */
  quiet?: ReadonlySet<string>;
  /**
   * How many DETACHED commands this run has out. A turn that finishes with any
   * is announced PROVISIONALLY ({@link endingIsProvisional}) — its banner is
   * withdrawn if the run goes back to work. Optional — a caller that cannot
   * know announces every ending as final.
   */
  shellsOpenOf?: (run: TRun) => number;
  /**
   * Notifications the AGENT asked for (`notify_user`), oldest first. Each is
   * posted once, and the ending of the turn that sent one is not announced a
   * second time.
   */
  notices?: readonly AgentNotice[];
  /** The chat on screen — suppressed while the window has focus. */
  activeRunId: string | null;
}): void {
  const seenRef = useRef<ReadonlyMap<string, RunStatusKind>>(new Map());
  /** The newest notice already handled — they arrive in id order. */
  const handledNoticeRef = useRef(0);
  /** Runs whose agent sent a notice during the turn now under way. */
  const noticedRef = useRef<Set<string>>(new Set());
  /** Runs whose last ending was posted provisionally and is still standing. */
  const provisionalRef = useRef<Set<string>>(new Set());
  // Read at post time, not captured: the effects below re-run on every list
  // change, and a stale active id would suppress a banner for the wrong chat.
  const activeRunIdRef = useRef(activeRunId);
  activeRunIdRef.current = activeRunId;

  /** The one case a banner is noise: the user is looking at this very chat. */
  const watching = (runId: string): boolean =>
    runId === activeRunIdRef.current && document.hasFocus();

  // Declared BEFORE the status effect, so a notice and the ending it precedes
  // are handled in that order when both land in one render.
  useEffect(() => {
    if (notices === undefined) {
      return;
    }
    for (const notice of notices) {
      if (notice.id <= handledNoticeRef.current) {
        continue;
      }
      handledNoticeRef.current = notice.id;
      // Marked whether or not a banner goes out: the user watching the chat
      // has seen the agent say it, which is just as much a reason not to
      // announce the same ending again.
      noticedRef.current.add(notice.runId);
      const run = runs.find((candidate) => candidate.id === notice.runId);
      if (run === undefined || watching(notice.runId)) {
        continue;
      }
      post({
        kind: 'turn-end',
        runId: notice.runId,
        title: labelOf(run),
        body: agentNoticeBody(notice.message),
      });
    }
    // `runs` and `labelOf` are read for the title only; the id guard is what
    // keeps a re-render from posting a notice twice.
  }, [notices, runs, labelOf]);

  useEffect(() => {
    const current = new Map(runs.map((run) => [run.id, statusOf(run)]));
    const triggers = diffRunNotifications(seenRef.current, current, quiet);
    // A run going back to WORK starts a new turn, so a notice from the last one
    // no longer speaks for its ending — and a provisional banner that called the
    // last one finished was wrong: the agent was waiting, so it is withdrawn.
    // Whatever reopened the run (the command reporting back, or the user's own
    // message) the banner no longer describes it.
    for (const [runId, status] of current) {
      const before = seenRef.current.get(runId);
      if (
        before !== undefined &&
        isSettledRunStatus(before) &&
        !isSettledRunStatus(status)
      ) {
        noticedRef.current.delete(runId);
        if (provisionalRef.current.delete(runId)) {
          retract(runId);
        }
      }
    }
    // Recorded BEFORE the posts, so a throw from one cannot leave the same
    // transition to fire again on the next reading.
    seenRef.current = current;
    if (triggers.length === 0) {
      return;
    }
    const byId = new Map(runs.map((run) => [run.id, run]));
    for (const trigger of triggers) {
      const run = byId.get(trigger.runId);
      if (!run) {
        continue;
      }
      let stillRunning = 0;
      if (trigger.kind === 'turn-end' && trigger.status === 'completed') {
        // The agent already said it was done, in its own words — that banner is
        // the announcement. A failure is exempt: nobody asked for it.
        if (noticedRef.current.delete(trigger.runId)) {
          continue;
        }
        stillRunning = shellsOpenOf?.(run) ?? 0;
      }
      if (watching(trigger.runId)) {
        continue;
      }
      const provisional = endingIsProvisional(stillRunning);
      post({
        kind: trigger.kind,
        runId: trigger.runId,
        title: labelOf(run),
        body: notificationBody(
          trigger,
          awaitingOf(run),
          summaryOf?.(run) ?? null,
          stillRunning,
        ),
        ...(provisional ? { retractable: true } : {}),
      });
      if (provisional) {
        provisionalRef.current.add(trigger.runId);
      }
    }
    // `summaryOf` rides the deps with the rest: the settle that changes a run's
    // status and the sentence explaining it arrive in ONE event, so the two
    // land in the same render and the banner is worded from the settle it is
    // about rather than from the previous one.
  }, [runs, statusOf, labelOf, awaitingOf, summaryOf, quiet, shellsOpenOf]);
}
