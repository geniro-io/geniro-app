import { useEffect, useRef } from 'react';

import type { RunAwaiting } from '../autogenerated';
import type { RunStatusKind } from '../chats/run-status';
import { diffRunNotifications, notificationBody } from './run-notifications';

/**
 * Report every notifiable transition to main, for as long as this is mounted.
 *
 * The React binding over {@link diffRunNotifications} and nothing more — the
 * rules live next door, pure. Mounted from `Chats`, which the app shell keeps
 * mounted (hidden) across nav switches, so a thread that finishes while the
 * user is in Settings still reports. It follows EVERY run, not just the focused
 * one: a background thread nobody is watching is the entire point.
 */
export function useRunNotifications<TRun extends { id: string }>({
  runs,
  statusOf,
  labelOf,
  awaitingOf,
  summaryOf,
  activeRunId,
}: {
  runs: readonly TRun[];
  /** The badge reading for a run — pass the sidebar's own, never the row. */
  statusOf: (run: TRun) => RunStatusKind;
  /** The thread's name, which is what the banner is titled with. */
  labelOf: (run: TRun) => string;
  /** What a parked run is waiting for, for the wording. */
  awaitingOf: (run: TRun) => RunAwaiting | null;
  /**
   * What the run said as it settled — the agent's closing words or the
   * failure's message. Optional: without it the banner falls back to the plain
   * "the turn finished" sentence, which is what it always said.
   */
  summaryOf?: (run: TRun) => string | null;
  /** The chat on screen — suppressed while the window has focus. */
  activeRunId: string | null;
}): void {
  const seenRef = useRef<ReadonlyMap<string, RunStatusKind>>(new Map());
  // Read at FIRE time, not captured: the effect below re-runs on every list
  // change, and a stale active id would suppress a banner for the wrong chat.
  const activeRunIdRef = useRef(activeRunId);
  activeRunIdRef.current = activeRunId;

  useEffect(() => {
    const current = new Map(runs.map((run) => [run.id, statusOf(run)]));
    const triggers = diffRunNotifications(seenRef.current, current);
    // Recorded BEFORE the posts, so a throw from one cannot leave the same
    // transition to fire again on the next reading.
    seenRef.current = current;
    if (triggers.length === 0) {
      return;
    }
    const byId = new Map(runs.map((run) => [run.id, run]));
    for (const trigger of triggers) {
      const run = byId.get(trigger.runId);
      if (!run) {
        continue;
      }
      // The one case a banner is noise: the user is looking at this very chat.
      // Both halves are needed — a focused window on ANOTHER chat still earns
      // one, and so does this chat while the window is in the background.
      if (trigger.runId === activeRunIdRef.current && document.hasFocus()) {
        continue;
      }
      void window.geniro
        .notify({
          kind: trigger.kind,
          runId: trigger.runId,
          title: labelOf(run),
          body: notificationBody(
            trigger,
            awaitingOf(run),
            summaryOf?.(run) ?? null,
          ),
        })
        .catch((err: unknown) => {
          // A banner is never worth a broken chat list.
          console.error('failed to post a notification', err);
        });
    }
    // `summaryOf` rides the deps with the rest: the settle that changes a run's
    // status and the sentence explaining it arrive in ONE event, so the two
    // land in the same render and the banner is worded from the settle it is
    // about rather than from the previous one.
  }, [runs, statusOf, labelOf, awaitingOf, summaryOf]);
}
