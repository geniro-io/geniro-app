import { useEffect, useRef } from 'react';

import type { RunAwaiting } from '../autogenerated';
import type { RunStatusKind } from '../chats/run-status';
import { isSettledRunStatus } from '../chats/run-status';
import {
  AFTER_CLOSE_GRACE_MS,
  diffRunNotifications,
  HOLD_CEILING_MS,
  holdsEnding,
  notificationBody,
} from './run-notifications';

/** An ending held back while a command its agent just launched runs on. */
interface HeldEnding {
  timer: ReturnType<typeof setTimeout>;
  /** How many commands the run had out when the ending was held. */
  shellsAtHold: number;
  /** One of them has ended, and {@link AFTER_CLOSE_GRACE_MS} is running. */
  closing: boolean;
  post: () => void;
}

/**
 * Report every notifiable transition to main, for as long as this is mounted.
 *
 * The React binding over {@link diffRunNotifications} and nothing more — the
 * rules live next door, pure. Mounted from `Chats`, which the app shell keeps
 * mounted (hidden) across nav switches, so a thread that finishes while the
 * user is in Settings still reports. It follows EVERY run, not just the focused
 * one: a background thread nobody is watching is the entire point.
 */
export function useRunNotifications<TRun extends { id: string }>({
  runs,
  statusOf,
  labelOf,
  awaitingOf,
  summaryOf,
  quiet,
  shellsOpenOf,
  activeRunId,
}: {
  runs: readonly TRun[];
  /** The badge reading for a run — pass the sidebar's own, never the row. */
  statusOf: (run: TRun) => RunStatusKind;
  /** The thread's name, which is what the banner is titled with. */
  labelOf: (run: TRun) => string;
  /** What a parked run is waiting for, for the wording. */
  awaitingOf: (run: TRun) => RunAwaiting | null;
  /**
   * What the run said as it settled — the agent's closing words or the
   * failure's message. Optional: without it the banner falls back to the plain
   * "the turn finished" sentence, which is what it always said.
   */
  summaryOf?: (run: TRun) => string | null;
  /**
   * Runs whose latest settle is not news — a compaction-only turn, or a
   * delegate lease handing an already-settled status back. Neither is something
   * the user asked to be told about. Rule 4 of {@link diffRunNotifications}.
   */
  quiet?: ReadonlySet<string>;
  /**
   * How many DETACHED commands this run has out — what decides whether its
   * ENDING might still be undone.
   *
   * A banner is a one-shot claim delivered outside the app and cannot be taken
   * back, while an agent routinely ends its turn waiting on a command and
   * carries on the moment it reports. Claude Code's own UI has the same event
   * and no such defect only because it never makes the claim. So an ending is
   * HELD while a command launched moments before it is still running
   * ({@link holdsEnding}), dropped if the agent speaks again, and announced once
   * the command has ended and the agent stayed quiet — or once
   * {@link HOLD_CEILING_MS} has passed, for a server that never exits.
   *
   * The launch time is read off the count RISING between two readings, since a
   * run row carries a count and nothing more. Optional — a caller that cannot
   * know announces every ending immediately.
   */
  shellsOpenOf?: (run: TRun) => number;
  /** The chat on screen — suppressed while the window has focus. */
  activeRunId: string | null;
}): void {
  const seenRef = useRef<ReadonlyMap<string, RunStatusKind>>(new Map());
  /** Each run's command count at the previous reading. */
  const shellsRef = useRef<ReadonlyMap<string, number>>(new Map());
  /** When each run's count last rose — its newest launch this session. */
  const launchedAtRef = useRef<Map<string, number>>(new Map());
  const heldRef = useRef<Map<string, HeldEnding>>(new Map());
  // Every held claim is dropped with the screen. A timer that fired after
  // unmount would announce a thread whose reading nothing is watching any more.
  useEffect(() => {
    const held = heldRef.current;
    return () => {
      for (const ending of held.values()) {
        clearTimeout(ending.timer);
      }
      held.clear();
    };
  }, []);
  // Read at FIRE time, not captured: the effect below re-runs on every list
  // change, and a stale active id would suppress a banner for the wrong chat.
  const activeRunIdRef = useRef(activeRunId);
  activeRunIdRef.current = activeRunId;

  useEffect(() => {
    const now = Date.now();
    const shells = new Map<string, number>();
    for (const run of runs) {
      const count = shellsOpenOf?.(run) ?? 0;
      const before = shellsRef.current.get(run.id);
      // A run's FIRST reading is a starting point, exactly as its status is:
      // commands already out when the list loaded were not launched just now.
      if (before !== undefined && count > before) {
        launchedAtRef.current.set(run.id, now);
      }
      shells.set(run.id, count);
    }
    shellsRef.current = shells;
    for (const runId of launchedAtRef.current.keys()) {
      if (!shells.has(runId)) {
        launchedAtRef.current.delete(runId);
      }
    }

    const current = new Map(runs.map((run) => [run.id, statusOf(run)]));
    const triggers = diffRunNotifications(seenRef.current, current, quiet);
    // Recorded BEFORE the posts, so a throw from one cannot leave the same
    // transition to fire again on the next reading.
    seenRef.current = current;
    for (const [runId, held] of heldRef.current) {
      // RETRACT the moment its agent speaks again. This runs on EVERY reading,
      // not only ones that produced a trigger, because the reading that matters
      // is the one where nothing was triggered: the run simply went back to
      // working.
      const status = current.get(runId);
      if (status === undefined || !isSettledRunStatus(status)) {
        clearTimeout(held.timer);
        heldRef.current.delete(runId);
        continue;
      }
      // A command ended. If it was the one the agent waited on, the CLI is
      // about to open a turn of its own — give it the grace to do so.
      if (!held.closing && (shells.get(runId) ?? 0) < held.shellsAtHold) {
        clearTimeout(held.timer);
        held.closing = true;
        held.timer = setTimeout(held.post, AFTER_CLOSE_GRACE_MS);
      }
    }
    if (triggers.length === 0) {
      return;
    }
    const byId = new Map(runs.map((run) => [run.id, run]));
    for (const trigger of triggers) {
      const run = byId.get(trigger.runId);
      if (!run) {
        continue;
      }
      const post = (): void => {
        heldRef.current.delete(trigger.runId);
        // The one case a banner is noise: the user is looking at this very
        // chat. Both halves are needed — a focused window on ANOTHER chat still
        // earns one, and so does this chat while the window is in the
        // background. Asked when the banner GOES, not when the ending landed:
        // a held ending can wait minutes, and the user may have opened the chat
        // in the meantime.
        if (trigger.runId === activeRunIdRef.current && document.hasFocus()) {
          return;
        }
        void window.geniro
          .notify({
            kind: trigger.kind,
            runId: trigger.runId,
            title: labelOf(run),
            body: notificationBody(
              trigger,
              awaitingOf(run),
              summaryOf?.(run) ?? null,
            ),
          })
          .catch((err: unknown) => {
            // A banner is never worth a broken chat list.
            console.error('failed to post a notification', err);
          });
      };
      // Only an ENDING is ever held. A question is the one state that cannot
      // advance without the user, so delaying it is the opposite of the point.
      const shellsOpen = shells.get(trigger.runId) ?? 0;
      if (
        trigger.kind === 'turn-end' &&
        holdsEnding({
          shellsOpen,
          launchedAt: launchedAtRef.current.get(trigger.runId),
          now,
        })
      ) {
        heldRef.current.set(trigger.runId, {
          timer: setTimeout(post, HOLD_CEILING_MS),
          shellsAtHold: shellsOpen,
          closing: false,
          post,
        });
        continue;
      }
      post();
    }
    // `summaryOf` rides the deps with the rest: the settle that changes a run's
    // status and the sentence explaining it arrive in ONE event, so the two
    // land in the same render and the banner is worded from the settle it is
    // about rather than from the previous one.
  }, [runs, statusOf, labelOf, awaitingOf, summaryOf, quiet, shellsOpenOf]);
}
