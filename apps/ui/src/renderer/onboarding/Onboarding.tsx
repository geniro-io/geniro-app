import {
  ArrowRight,
  Check,
  GitBranch,
  MessageSquare,
  SlidersHorizontal,
  Sparkles,
} from 'lucide-react';
import {
  createElement,
  useCallback,
  useEffect,
  useMemo,
  useRef,
  useState,
} from 'react';

import {
  CLI_KINDS,
  type CliDetection,
  type CliKind,
  type ConfigProfile,
  type DaemonHandle,
  type OnboardingProgress,
} from '../../shared/contracts';
import { AgentIdentityContext, agentShortName } from '../agent-identity';
import type { AgentIdentityCapability } from '../autogenerated';
import { AgentConfigList, statusFor } from '../components/agent-config-list';
import { CliLoginProgress } from '../components/cli-login-progress';
import { ErrorText } from '../components/error-text';
import { Logo } from '../components/logo';
import { Button } from '../components/ui/button';
import { Textarea } from '../components/ui/textarea';
import { cn } from '../components/ui/utils';
import { createDaemonApis } from '../daemon-api';
import { ConfigProfileList } from '../settings/config-profiles';
import { useSharedCapabilities } from '../use-capabilities';
import { signInAfterInstall, useCliInstall } from '../use-cli-install';
import { isLoginOver, useCliLogin } from '../use-cli-login';
import { configDirCapabilityFrom } from '../workflows/use-config-dir-capability';
import type { FirstLaunch } from './first-launch';

const STEPS = ['How it works', 'Agents', 'Profiles', 'First launch'] as const;
const INITIAL: OnboardingProgress = {
  step: 0,
  agent: null,
  route: 'chat',
  teamMethod: 'ai',
  brief: '',
};
const METHODS = [
  {
    value: 'ai',
    title: 'Build with AI',
    detail: 'Describe the team. An agent helps you assemble its graph.',
  },
  {
    value: 'example',
    title: 'Start with an example',
    detail: 'Planner → Builder → Reviewer. Edit each role to fit your work.',
  },
  {
    value: 'graph',
    title: 'Draw a graph',
    detail: 'Start with an empty canvas and connect the agents yourself.',
  },
  {
    value: 'import',
    title: 'Import YAML',
    detail: 'Bring an existing team into the graph editor.',
  },
] as const;

export function Onboarding({
  onDone,
  identities,
  onClose,
}: {
  onDone: (destination: FirstLaunch) => void;
  identities: readonly AgentIdentityCapability[];
  onClose?: () => void;
}): React.JSX.Element {
  const [progress, setProgress] = useState<OnboardingProgress>(INITIAL);
  const [loaded, setLoaded] = useState(false);
  const [clis, setClis] = useState<CliDetection[] | null>(null);
  const [open, setOpen] = useState<Partial<Record<CliKind, boolean>>>({});
  const [binaryPaths, setBinaryPaths] = useState<
    Partial<Record<CliKind, string>>
  >({});
  const [profiles, setProfiles] = useState<ConfigProfile[]>([]);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const didAutoOpenRef = useRef(false);
  const saves = useRef<Promise<unknown>>(Promise.resolve());
  const saveTimer = useRef<number | undefined>(undefined);
  const heading = useRef<HTMLHeadingElement>(null);
  const scroller = useRef<HTMLDivElement>(null);

  const loadSettings = useCallback(async (): Promise<void> => {
    try {
      const settings = await window.geniro.getSettings();
      setProgress(settings.onboardingProgress ?? INITIAL);
      setBinaryPaths(settings.cliPaths ?? {});
      setProfiles(settings.configProfiles);
      setLoaded(true);
      setError(null);
    } catch (err) {
      setError(String(err));
    }
  }, []);
  useEffect(() => {
    void loadSettings();
  }, [loadSettings]);

  const save = useCallback(
    (
      patch: Parameters<typeof window.geniro.updateSettings>[0],
    ): Promise<unknown> => {
      const pending = saves.current
        .catch(() => undefined)
        .then(() => window.geniro.updateSettings(patch));
      saves.current = pending;
      return pending;
    },
    [],
  );
  useEffect(() => {
    if (!loaded) {
      return;
    }
    saveTimer.current = window.setTimeout(() => {
      void save({
        onboardingProgress: progress,
        cliPaths: Object.fromEntries(
          Object.entries(binaryPaths)
            .filter(([, path]) => path?.trim().startsWith('/'))
            .map(([kind, path]) => [kind, path.trim()]),
        ),
      }).catch((err: unknown) => setError(String(err)));
    }, 350);
    return () => window.clearTimeout(saveTimer.current);
  }, [loaded, progress, binaryPaths, save]);
  useEffect(() => {
    scroller.current?.scrollTo?.({ top: 0 });
    heading.current?.focus();
  }, [progress.step]);

  const refreshClis = useCallback(async (): Promise<void> => {
    setClis(null);
    try {
      setClis(await window.geniro.detectClis());
    } catch (err) {
      setError(String(err));
    }
  }, []);
  useEffect(() => {
    void refreshClis();
  }, [refreshClis]);
  useEffect(() => {
    if (!clis || !loaded) {
      return;
    }
    setBinaryPaths((prev) => {
      const next = { ...prev };
      for (const d of clis) {
        if (d.found && d.path && !next[d.kind]) {
          next[d.kind] = d.path;
        }
      }
      return next;
    });
    if (!didAutoOpenRef.current) {
      didAutoOpenRef.current = true;
      setOpen((prev) => ({
        ...Object.fromEntries(
          CLI_KINDS.filter((kind) => statusFor(clis, kind).tone !== 'ok').map(
            (kind) => [kind, true],
          ),
        ),
        ...prev,
      }));
    }
    setProgress((prev) =>
      prev.agent !== null
        ? prev
        : {
            ...prev,
            agent:
              clis.find((cli) => cli.found && cli.loggedIn !== false)?.kind ??
              null,
          },
    );
  }, [clis, loaded]);

  const [handle, setHandle] = useState<DaemonHandle | null>(null);
  useEffect(() => {
    let cancelled = false;
    const unsubscribe = window.geniro.onDaemonRestarted((next) => {
      if (!cancelled) {
        setHandle(next);
      }
    });
    void window.geniro
      .getDaemonHandle()
      .then((current) => {
        if (!cancelled && current) {
          setHandle((prev) => prev ?? current);
        }
      })
      .catch((err: unknown) => setError(String(err)));
    return () => {
      cancelled = true;
      unsubscribe();
    };
  }, []);
  const apis = useMemo(
    () => (handle ? createDaemonApis(handle) : null),
    [handle],
  );
  const { capabilities, loading } = useSharedCapabilities(
    apis?.capabilities ?? null,
  );
  const configDirCapability = configDirCapabilityFrom(capabilities, loading);
  const profileScopedKinds = new Set(
    CLI_KINDS.filter(
      (kind) => configDirCapability.unavailableReasonFor(kind) === null,
    ),
  );
  const login = useCliLogin(apis, () => {
    void refreshClis();
  });
  const cliInstall = useCliInstall(async (result) => {
    const detected = await window.geniro.detectClis();
    setClis(detected);
    if (signInAfterInstall(result, detected, login)) {
      await login.start(result.kind, null);
    }
  });
  const settingUp =
    cliInstall.installing.size > 0 ||
    login.starting !== null ||
    (login.login !== null && !isLoginOver(login.login.session));
  const ready =
    clis?.some(
      (cli) =>
        cli.kind === progress.agent && cli.found && cli.loggedIn !== false,
    ) ?? false;
  const blocked = busy || settingUp || !loaded;
  const nameOf = (kind: CliKind): string => agentShortName(identities, kind);
  const move = (step: OnboardingProgress['step']): void => {
    setProgress((prev) => ({ ...prev, step }));
  };
  const browse = async (kind: CliKind): Promise<void> => {
    try {
      const chosen = await window.geniro.pickAgentBinary();
      if (chosen) {
        setBinaryPaths((prev) => ({ ...prev, [kind]: chosen }));
      }
    } catch (err) {
      setError(String(err));
    }
  };
  const recheck = async (): Promise<void> => {
    try {
      await save({
        cliPaths: Object.fromEntries(
          Object.entries(binaryPaths)
            .filter(([, path]) => path?.trim().startsWith('/'))
            .map(([kind, path]) => [kind, path.trim()]),
        ),
      });
      await refreshClis();
    } catch (err) {
      setError(String(err));
    }
  };
  const changeProfiles = (kind: CliKind, next: ConfigProfile[]): void => {
    const merged = [
      ...profiles.filter((profile) => profile.agent !== kind),
      ...next,
    ];
    const before = profiles;
    setProfiles(merged);
    void save({ configProfiles: merged })
      .then(() => refreshClis())
      .catch((err: unknown) => {
        setProfiles(before);
        setError(String(err));
      });
  };
  const finish = async (): Promise<void> => {
    if (blocked || (progress.route !== 'explore' && !ready)) {
      return;
    }
    setBusy(true);
    setError(null);
    window.clearTimeout(saveTimer.current);
    try {
      await saves.current;
      const cliPaths: Partial<Record<CliKind, string>> = {};
      for (const kind of CLI_KINDS) {
        const path = binaryPaths[kind]?.trim();
        if (path) {
          cliPaths[kind] = path;
        }
      }
      await window.geniro.completeOnboarding({
        cliPaths,
        ...(progress.agent === null ? {} : { lastChatTarget: progress.agent }),
      });
      const { step: _step, ...destination } = progress;
      onDone(destination);
    } catch (err) {
      setError(String(err));
    } finally {
      setBusy(false);
    }
  };
  const finishLabel =
    progress.route === 'chat'
      ? 'Open chat'
      : progress.route === 'team'
        ? progress.teamMethod === 'import'
          ? 'Choose YAML file'
          : 'Create team'
        : 'Explore Geniro';

  return (
    <AgentIdentityContext.Provider value={identities}>
      <div className="flex h-full min-h-0 bg-background text-foreground">
        <aside className="flex w-64 shrink-0 flex-col border-r border-border bg-card p-6 max-md:hidden">
          <div className="flex items-center gap-3">
            <Logo className="size-8" />
            <span className="text-lg font-semibold">Geniro</span>
          </div>
          <p className="mt-2 text-sm text-muted-foreground">
            A little setup. A lot you can build.
          </p>
          <nav aria-label="Setup steps" className="mt-12 flex flex-col gap-3">
            {STEPS.map((label, index) => (
              <Button
                key={label}
                variant={progress.step === index ? 'secondary' : 'ghost'}
                className="h-auto justify-start gap-3 px-3 py-3 text-left"
                disabled={blocked}
                aria-current={progress.step === index ? 'step' : undefined}
                onClick={() => move(index as OnboardingProgress['step'])}>
                <span
                  className={cn(
                    'flex size-6 items-center justify-center rounded-full border border-border text-xs',
                    progress.step === index &&
                      'border-primary bg-primary text-primary-foreground',
                  )}>
                  {index < progress.step ? (
                    <Check className="size-3" />
                  ) : (
                    index + 1
                  )}
                </span>
                {label}
              </Button>
            ))}
          </nav>
          <p className="mt-auto pt-8 text-xs leading-relaxed text-muted-foreground">
            Your agents run locally. You choose when a conversation or team
            starts working.
          </p>
        </aside>
        <div
          ref={scroller}
          className="min-h-0 flex-1 overflow-y-auto [scrollbar-gutter:stable]">
          <div className="mx-auto flex min-h-full max-w-3xl flex-col px-6 py-8 sm:px-10 sm:py-12">
            <div className="mb-8 flex items-center justify-between gap-4">
              <p className="text-xs font-medium uppercase tracking-widest text-muted-foreground">
                Step {progress.step + 1} of 4 · {STEPS[progress.step]}
              </p>
              {onClose ? (
                <Button
                  variant="ghost"
                  size="sm"
                  disabled={blocked}
                  onClick={() => {
                    window.clearTimeout(saveTimer.current);
                    setBusy(true);
                    void save({ onboardingProgress: progress })
                      .then(() => onClose())
                      .catch((err: unknown) => setError(String(err)))
                      .finally(() => setBusy(false));
                  }}>
                  Close guide
                </Button>
              ) : (
                <Logo className="size-6 md:hidden" />
              )}
            </div>
            <h1
              ref={heading}
              tabIndex={-1}
              className="text-3xl font-semibold tracking-tight outline-none sm:text-4xl">
              {
                [
                  'Your agents. One place to build.',
                  'Connect your agents',
                  'Make room for different profiles',
                  'What would you like to do first?',
                ][progress.step]
              }
            </h1>
            <p className="mt-3 text-sm leading-relaxed text-muted-foreground">
              {
                [
                  'Chat with a coding agent, or bring several agents together into a team. Let’s get you ready.',
                  'Use the coding agents you already know. Connect one to get started, or set up all three.',
                  'Optional: keep personal and work accounts, instructions, and tools in separate agent configurations.',
                  'Start small with a chat, assemble a team, or take a look around. Nothing runs until you send a task.',
                ][progress.step]
              }
            </p>
            <div className="my-8">
              {progress.step === 0 ? (
                <>
                  <div className="grid gap-4 sm:grid-cols-3">
                    {[
                      {
                        Icon: MessageSquare,
                        title: 'Agent',
                        description:
                          'A coding CLI that does the work. Geniro connects to it on your computer.',
                      },
                      {
                        Icon: SlidersHorizontal,
                        title: 'Profile',
                        description:
                          'An agent’s configuration: its account, instructions, and tools. You can have several.',
                      },
                      {
                        Icon: GitBranch,
                        title: 'Team',
                        description:
                          'A graph of agents with different roles. Connections tell them how to pass work along.',
                      },
                    ].map(({ Icon: icon, title, description }) => (
                      <div
                        key={title}
                        className="rounded-xl border border-border bg-card p-5">
                        {createElement(icon, {
                          className: 'mb-5 size-6 text-primary',
                          'aria-hidden': true,
                        })}
                        <h2 className="font-semibold">{title}</h2>
                        <p className="mt-2 text-sm leading-relaxed text-muted-foreground">
                          {description}
                        </p>
                      </div>
                    ))}
                  </div>
                  <div className="mt-6 rounded-xl bg-secondary p-5">
                    <p className="text-sm font-medium">
                      One task, a few clear roles
                    </p>
                    <p className="mt-2 text-sm text-muted-foreground">
                      Plan <span aria-hidden="true">→</span> Build{' '}
                      <span aria-hidden="true">→</span> Review
                    </p>
                    <p className="mt-3 text-sm text-muted-foreground">
                      Start with one agent. Add a team whenever it helps.
                    </p>
                  </div>
                </>
              ) : null}
              {progress.step === 1 ? (
                <>
                  <AgentConfigList
                    clis={clis}
                    open={open}
                    onToggle={(kind) =>
                      setOpen((prev) => ({ ...prev, [kind]: !prev[kind] }))
                    }
                    binaryPaths={binaryPaths}
                    onBinaryPathChange={(kind, path) =>
                      setBinaryPaths((prev) => ({ ...prev, [kind]: path }))
                    }
                    onBrowse={(kind) => void browse(kind)}
                    onInstall={(kind) => void cliInstall.install(kind)}
                    installing={cliInstall.installing}
                    installResults={cliInstall.results}
                    onSignIn={
                      apis ? (kind) => void login.start(kind, null) : undefined
                    }
                    signingIn={login.starting?.kind ?? null}
                    profileScopedKinds={profileScopedKinds}
                    login={
                      login.login
                        ? {
                            kind: login.login.kind,
                            session: login.login.session,
                            error: login.error,
                            onSubmitCode: (code) => void login.submitCode(code),
                            onCancel: () => void login.cancel(),
                            onDismiss: login.dismiss,
                          }
                        : undefined
                    }
                  />
                  <div className="mt-5 flex items-center justify-between">
                    <p className="text-xs text-muted-foreground">
                      Already installed? Geniro detects it automatically.
                    </p>
                    <Button
                      variant="ghost"
                      size="sm"
                      disabled={blocked || clis === null}
                      onClick={() => void recheck()}>
                      Re-check
                    </Button>
                  </div>
                  {clis?.some((cli) => cli.found && cli.loggedIn !== false) ? (
                    <fieldset className="mt-5">
                      <legend className="mb-2 text-sm font-medium">
                        Use for your first launch
                      </legend>
                      <div className="flex flex-wrap gap-2">
                        {clis
                          .filter((cli) => cli.found && cli.loggedIn !== false)
                          .map((cli) => (
                            <Button
                              key={cli.kind}
                              variant={
                                progress.agent === cli.kind
                                  ? 'secondary'
                                  : 'outline'
                              }
                              aria-pressed={progress.agent === cli.kind}
                              disabled={blocked}
                              onClick={() =>
                                setProgress((prev) => ({
                                  ...prev,
                                  agent: cli.kind,
                                }))
                              }>
                              {nameOf(cli.kind)}
                              {progress.agent === cli.kind ? (
                                <Check className="size-3" />
                              ) : null}
                            </Button>
                          ))}
                      </div>
                    </fieldset>
                  ) : null}
                </>
              ) : null}
              {progress.step === 2 ? (
                <>
                  <div className="mb-5 rounded-xl bg-secondary p-5 text-sm leading-relaxed text-muted-foreground">
                    A profile points to the agent’s configuration directory. It
                    keeps that agent’s account and setup separate. Add a folder
                    for each profile, give it a name, then sign in to that
                    profile. You can manage these later in Settings → Agents.
                  </div>
                  <div className="flex flex-col gap-4">
                    {CLI_KINDS.map((kind) => {
                      const reason =
                        configDirCapability.unavailableReasonFor(kind);
                      return (
                        <section
                          key={kind}
                          className="rounded-xl border border-border bg-card p-5">
                          <h2 className="mb-3 text-sm font-semibold">
                            {nameOf(kind)}
                          </h2>
                          {reason === null ? (
                            <ConfigProfileList
                              agent={kind}
                              profiles={profiles.filter(
                                (profile) => profile.agent === kind,
                              )}
                              onChange={(next) => changeProfiles(kind, next)}
                              onPickDirectory={() =>
                                window.geniro.pickProjectFolder()
                              }
                              onSignIn={
                                apis
                                  ? (dir) => void login.start(kind, dir)
                                  : undefined
                              }
                              signingIn={
                                login.starting?.kind === kind
                                  ? login.starting.configDir
                                  : null
                              }
                              busy={blocked}
                              logins={
                                clis?.find((cli) => cli.kind === kind)
                                  ?.profileLogins ?? {}
                              }
                            />
                          ) : (
                            <p className="text-sm text-muted-foreground">
                              {reason ??
                                (loading
                                  ? 'Checking profile support…'
                                  : 'Profile support is unavailable. You can configure profiles later in Settings.')}
                            </p>
                          )}
                          {login.login?.kind === kind ? (
                            <CliLoginProgress
                              variant="inline"
                              session={login.login.session}
                              error={login.error}
                              onSubmitCode={(code) =>
                                void login.submitCode(code)
                              }
                              onCancel={() => void login.cancel()}
                              onDismiss={login.dismiss}
                            />
                          ) : null}
                        </section>
                      );
                    })}
                  </div>
                </>
              ) : null}
              {progress.step === 3 ? (
                <>
                  <div className="grid gap-3 sm:grid-cols-3">
                    {[
                      {
                        value: 'chat',
                        Icon: MessageSquare,
                        title: 'Start a chat',
                        detail: 'Give one agent a task.',
                      },
                      {
                        value: 'team',
                        Icon: GitBranch,
                        title: 'Create a team',
                        detail: 'Connect agents and roles.',
                      },
                      {
                        value: 'explore',
                        Icon: Sparkles,
                        title: 'Explore Geniro',
                        detail: 'Set things up later.',
                      },
                    ].map(({ value, Icon: icon, title, detail }) => (
                      <Button
                        key={value}
                        variant="outline"
                        disabled={blocked}
                        aria-pressed={progress.route === value}
                        className={cn(
                          'h-auto flex-col items-start whitespace-normal p-5 text-left',
                          progress.route === value &&
                            'border-primary bg-secondary',
                        )}
                        onClick={() =>
                          setProgress((prev) => ({
                            ...prev,
                            route: value as OnboardingProgress['route'],
                          }))
                        }>
                        {createElement(icon, {
                          className: 'mb-2 size-5 text-primary',
                          'aria-hidden': true,
                        })}
                        <span>{title}</span>
                        <span className="text-xs font-normal text-muted-foreground">
                          {detail}
                        </span>
                      </Button>
                    ))}
                  </div>
                  {progress.route === 'team' ? (
                    <div className="mt-6">
                      <h2 className="mb-3 text-sm font-semibold">
                        How would you like to build it?
                      </h2>
                      <div className="grid gap-3 sm:grid-cols-2">
                        {METHODS.map((method) => (
                          <Button
                            key={method.value}
                            variant="outline"
                            disabled={blocked}
                            aria-pressed={progress.teamMethod === method.value}
                            className={cn(
                              'h-auto flex-col items-start whitespace-normal p-4 text-left',
                              progress.teamMethod === method.value &&
                                'border-primary bg-secondary',
                            )}
                            onClick={() =>
                              setProgress((prev) => ({
                                ...prev,
                                teamMethod: method.value,
                              }))
                            }>
                            <span>{method.title}</span>
                            <span className="text-xs font-normal leading-relaxed text-muted-foreground">
                              {method.detail}
                            </span>
                          </Button>
                        ))}
                      </div>
                      {progress.teamMethod === 'ai' ? (
                        <div className="mt-4">
                          <label
                            htmlFor="team-brief"
                            className="mb-2 block text-sm font-medium">
                            What should your team do?{' '}
                            <span className="font-normal text-muted-foreground">
                              (optional)
                            </span>
                          </label>
                          <Textarea
                            id="team-brief"
                            rows={3}
                            maxLength={4000}
                            disabled={blocked}
                            placeholder="For example: plan a feature, implement it, then review the changes."
                            value={progress.brief}
                            onChange={(event) =>
                              setProgress((prev) => ({
                                ...prev,
                                brief: event.target.value,
                              }))
                            }
                          />
                          <p className="mt-2 text-xs text-muted-foreground">
                            Your description opens as a draft in the team’s AI
                            chat. Review it and send when you’re ready.
                          </p>
                        </div>
                      ) : null}
                    </div>
                  ) : null}
                  {progress.route !== 'explore' ? (
                    <p className="mt-5 text-sm text-muted-foreground">
                      {ready && progress.agent
                        ? `First agent: ${nameOf(progress.agent)}. You can change it later.`
                        : 'Connect an agent in step 2 to start a chat or create a team, or choose Explore Geniro.'}
                    </p>
                  ) : null}
                </>
              ) : null}
            </div>
            {error ? (
              <div role="alert" className="mb-4">
                <ErrorText>{error}</ErrorText>
                {!loaded ? (
                  <Button
                    variant="outline"
                    size="sm"
                    onClick={() => void loadSettings()}>
                    Retry setup
                  </Button>
                ) : null}
              </div>
            ) : null}
            <footer className="mt-auto flex flex-wrap items-center justify-between gap-3 border-t border-border pt-6">
              <Button
                variant="ghost"
                disabled={blocked || progress.step === 0}
                onClick={() =>
                  move((progress.step - 1) as OnboardingProgress['step'])
                }>
                Back
              </Button>
              <div className="flex items-center gap-2">
                {progress.step === 1 ? (
                  <Button
                    variant="ghost"
                    disabled={blocked}
                    onClick={() =>
                      setProgress((prev) => ({
                        ...prev,
                        step: 2,
                        route: ready ? prev.route : 'explore',
                      }))
                    }>
                    Set up later
                  </Button>
                ) : null}
                {progress.step === 2 ? (
                  <Button
                    variant="ghost"
                    disabled={blocked}
                    onClick={() => move(3)}>
                    Skip for now
                  </Button>
                ) : null}
                {progress.step < 3 ? (
                  <Button
                    disabled={blocked || (progress.step === 1 && !ready)}
                    onClick={() =>
                      move((progress.step + 1) as OnboardingProgress['step'])
                    }>
                    Continue
                    <ArrowRight className="size-4" />
                  </Button>
                ) : (
                  <Button
                    disabled={
                      blocked || (progress.route !== 'explore' && !ready)
                    }
                    onClick={() => void finish()}>
                    {busy ? 'Finishing…' : finishLabel}
                    <ArrowRight className="size-4" />
                  </Button>
                )}
              </div>
            </footer>
          </div>
        </div>
      </div>
    </AgentIdentityContext.Provider>
  );
}
