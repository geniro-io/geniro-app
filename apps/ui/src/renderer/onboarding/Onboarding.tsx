import {
  ArrowRight,
  Check,
  ChevronLeft,
  GitBranch,
  Info,
  MessageSquare,
  RefreshCw,
  ShieldCheck,
  Sparkles,
} from 'lucide-react';
import {
  createElement,
  useCallback,
  useEffect,
  useMemo,
  useRef,
  useState,
} from 'react';

import {
  CLI_KINDS,
  type CliDetection,
  type CliKind,
  type ConfigProfile,
  type DaemonHandle,
  type OnboardingProgress,
} from '../../shared/contracts';
import {
  agentIconName,
  AgentIdentityContext,
  agentShortName,
} from '../agent-identity';
import type { AgentIdentityCapability } from '../autogenerated';
import { AgentConfigList, statusFor } from '../components/agent-config-list';
import { AgentGlyph } from '../components/agent-glyph';
import { CliLoginProgress } from '../components/cli-login-progress';
import { ErrorBanner } from '../components/error-banner';
import { Logo } from '../components/logo';
import { Badge } from '../components/ui/badge';
import { Button } from '../components/ui/button';
import { Card } from '../components/ui/card';
import { OptionIndicator, OptionList } from '../components/ui/option-list';
import { ProgressBar } from '../components/ui/progress-bar';
import { Select } from '../components/ui/select';
import { Textarea } from '../components/ui/textarea';
import { cn } from '../components/ui/utils';
import { createDaemonApis } from '../daemon-api';
import { ConfigProfileList } from '../settings/config-profiles';
import { useSharedCapabilities } from '../use-capabilities';
import { signInAfterInstall, useCliInstall } from '../use-cli-install';
import { isLoginOver, useCliLogin } from '../use-cli-login';
import { configDirCapabilityFrom } from '../workflows/use-config-dir-capability';
import type { FirstLaunch } from './first-launch';
import { OnboardingOverview } from './onboarding-overview';

const STEPS = ['How it works', 'Agents', 'Profiles', 'First launch'] as const;
const STEP_DETAILS = [
  'A quick introduction',
  'Connect a coding agent',
  'Optional · separate setups',
  'Choose where to begin',
] as const;
const INITIAL: OnboardingProgress = {
  step: 0,
  agent: null,
  route: 'chat',
  teamMethod: 'ai',
  brief: '',
};
const ROUTES = [
  {
    value: 'chat',
    Icon: MessageSquare,
    title: 'Start a chat',
    detail: 'Give one agent a task and watch it work.',
  },
  {
    value: 'team',
    Icon: GitBranch,
    title: 'Create a team',
    detail: 'Connect agents with clear roles in a graph.',
  },
  {
    value: 'explore',
    Icon: Sparkles,
    title: 'Explore Geniro',
    detail: 'Look around first and set things up later.',
  },
] as const;
const METHODS = [
  {
    value: 'ai',
    title: 'Build with AI',
    detail: 'Describe the team. An agent helps you assemble its graph.',
  },
  {
    value: 'example',
    title: 'Start with an example',
    detail: 'Planner → Builder → Reviewer. Edit each role to fit your work.',
  },
  {
    value: 'graph',
    title: 'Draw a graph',
    detail: 'Start with an empty canvas and connect the agents yourself.',
  },
  {
    value: 'import',
    title: 'Import YAML',
    detail: 'Bring an existing team into the graph editor.',
  },
] as const;

export function Onboarding({
  onDone,
  identities,
  onClose,
}: {
  onDone: (destination: FirstLaunch) => void;
  identities: readonly AgentIdentityCapability[];
  onClose?: () => void;
}): React.JSX.Element {
  const [progress, setProgress] = useState<OnboardingProgress>(INITIAL);
  const [loaded, setLoaded] = useState(false);
  const [clis, setClis] = useState<CliDetection[] | null>(null);
  const [open, setOpen] = useState<Partial<Record<CliKind, boolean>>>({});
  const [binaryPaths, setBinaryPaths] = useState<
    Partial<Record<CliKind, string>>
  >({});
  const [profiles, setProfiles] = useState<ConfigProfile[]>([]);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const didAutoOpenRef = useRef(false);
  const savedBinaryPaths = useRef<Partial<Record<CliKind, string>>>({});
  const saves = useRef<Promise<unknown>>(Promise.resolve());
  const saveTimer = useRef<number | undefined>(undefined);
  const heading = useRef<HTMLHeadingElement>(null);
  const scroller = useRef<HTMLDivElement>(null);

  const loadSettings = useCallback(async (): Promise<void> => {
    try {
      const settings = await window.geniro.getSettings();
      setProgress(settings.onboardingProgress ?? INITIAL);
      savedBinaryPaths.current = settings.cliPaths ?? {};
      setBinaryPaths(settings.cliPaths ?? {});
      setProfiles(settings.configProfiles);
      setLoaded(true);
      setError(null);
    } catch (err) {
      setError(String(err));
    }
  }, []);
  useEffect(() => {
    void loadSettings();
  }, [loadSettings]);

  const save = useCallback(
    (
      patch: Parameters<typeof window.geniro.updateSettings>[0],
    ): Promise<unknown> => {
      const pending = saves.current
        .catch(() => undefined)
        .then(() => window.geniro.updateSettings(patch));
      saves.current = pending;
      return pending;
    },
    [],
  );
  useEffect(() => {
    if (!loaded) {
      return;
    }
    saveTimer.current = window.setTimeout(() => {
      const paths = Object.fromEntries(
        Object.entries(binaryPaths)
          .filter(([, path]) => path?.trim().startsWith('/'))
          .map(([kind, path]) => [kind, path.trim()]),
      );
      const changed = CLI_KINDS.some(
        (kind) =>
          (paths[kind] ?? '') !== (savedBinaryPaths.current[kind] ?? ''),
      );
      void save({
        onboardingProgress: progress,
        ...(changed ? { cliPaths: paths } : {}),
      })
        .then(() => {
          if (changed) {
            savedBinaryPaths.current = paths;
          }
        })
        .catch((err: unknown) => setError(String(err)));
    }, 350);
    return () => window.clearTimeout(saveTimer.current);
  }, [loaded, progress, binaryPaths, save]);
  useEffect(() => {
    scroller.current?.scrollTo?.({ top: 0 });
    heading.current?.focus();
  }, [progress.step]);

  const refreshClis = useCallback(async (): Promise<void> => {
    setClis(null);
    try {
      setClis(await window.geniro.detectClis());
    } catch (err) {
      setError(String(err));
    }
  }, []);
  useEffect(() => {
    void refreshClis();
  }, [refreshClis]);
  useEffect(() => {
    if (!clis || !loaded) {
      return;
    }
    setBinaryPaths((prev) => {
      const next = { ...prev };
      for (const d of clis) {
        if (d.found && d.path && !next[d.kind]) {
          next[d.kind] = d.path;
        }
      }
      return next;
    });
    if (!didAutoOpenRef.current) {
      didAutoOpenRef.current = true;
      setOpen((prev) => ({
        ...Object.fromEntries(
          CLI_KINDS.filter((kind) => statusFor(clis, kind).tone !== 'ok').map(
            (kind) => [kind, true],
          ),
        ),
        ...prev,
      }));
    }
    setProgress((prev) =>
      prev.agent !== null
        ? prev
        : {
            ...prev,
            agent:
              clis.find((cli) => cli.found && cli.loggedIn !== false)?.kind ??
              null,
          },
    );
  }, [clis, loaded]);

  const [handle, setHandle] = useState<DaemonHandle | null>(null);
  useEffect(() => {
    let cancelled = false;
    const unsubscribe = window.geniro.onDaemonRestarted((next) => {
      if (!cancelled) {
        setHandle(next);
      }
    });
    void window.geniro
      .getDaemonHandle()
      .then((current) => {
        if (!cancelled && current) {
          setHandle((prev) => prev ?? current);
        }
      })
      .catch((err: unknown) => setError(String(err)));
    return () => {
      cancelled = true;
      unsubscribe();
    };
  }, []);
  const apis = useMemo(
    () => (handle ? createDaemonApis(handle) : null),
    [handle],
  );
  const { capabilities, loading } = useSharedCapabilities(
    apis?.capabilities ?? null,
  );
  const configDirCapability = configDirCapabilityFrom(capabilities, loading);
  const profileScopedKinds = new Set(
    CLI_KINDS.filter(
      (kind) => configDirCapability.unavailableReasonFor(kind) === null,
    ),
  );
  const login = useCliLogin(apis, () => {
    void refreshClis();
  });
  const cliInstall = useCliInstall(async (result) => {
    const detected = await window.geniro.detectClis();
    setClis(detected);
    if (signInAfterInstall(result, detected, login)) {
      await login.start(result.kind, null);
    }
  });
  const settingUp =
    cliInstall.installing.size > 0 ||
    login.starting !== null ||
    (login.login !== null && !isLoginOver(login.login.session));
  const ready =
    clis?.some(
      (cli) =>
        cli.kind === progress.agent && cli.found && cli.loggedIn !== false,
    ) ?? false;
  const readyAgents =
    clis?.filter((cli) => cli.found && cli.loggedIn !== false) ?? [];
  const blocked = busy || settingUp || !loaded;
  const nameOf = (kind: CliKind): string => agentShortName(identities, kind);
  const move = (step: OnboardingProgress['step']): void => {
    setProgress((prev) => ({ ...prev, step }));
  };
  const browse = async (kind: CliKind): Promise<void> => {
    try {
      const chosen = await window.geniro.pickAgentBinary();
      if (chosen) {
        setBinaryPaths((prev) => ({ ...prev, [kind]: chosen }));
      }
    } catch (err) {
      setError(String(err));
    }
  };
  const recheck = async (): Promise<void> => {
    try {
      await save({
        cliPaths: Object.fromEntries(
          Object.entries(binaryPaths)
            .filter(([, path]) => path?.trim().startsWith('/'))
            .map(([kind, path]) => [kind, path.trim()]),
        ),
      });
      await refreshClis();
    } catch (err) {
      setError(String(err));
    }
  };
  const changeProfiles = (kind: CliKind, next: ConfigProfile[]): void => {
    const merged = [
      ...profiles.filter((profile) => profile.agent !== kind),
      ...next,
    ];
    const before = profiles;
    setProfiles(merged);
    void save({ configProfiles: merged })
      .then(() => refreshClis())
      .catch((err: unknown) => {
        setProfiles(before);
        setError(String(err));
      });
  };
  const finish = async (): Promise<void> => {
    if (blocked || (progress.route !== 'explore' && !ready)) {
      return;
    }
    setBusy(true);
    setError(null);
    window.clearTimeout(saveTimer.current);
    try {
      await saves.current;
      const cliPaths: Partial<Record<CliKind, string>> = {};
      for (const kind of CLI_KINDS) {
        const path = binaryPaths[kind]?.trim();
        if (path) {
          cliPaths[kind] = path;
        }
      }
      await window.geniro.completeOnboarding({
        cliPaths,
        ...(progress.agent === null ? {} : { lastChatTarget: progress.agent }),
      });
      const { step: _step, ...destination } = progress;
      onDone(destination);
    } catch (err) {
      setError(String(err));
    } finally {
      setBusy(false);
    }
  };
  const finishLabel =
    progress.route === 'chat'
      ? 'Open chat'
      : progress.route === 'team'
        ? progress.teamMethod === 'import'
          ? 'Choose YAML file'
          : 'Create team'
        : 'Explore Geniro';

  return (
    <AgentIdentityContext.Provider value={identities}>
      <div
        data-slot="onboarding"
        className="flex h-full min-h-0 flex-col bg-background pt-11 text-foreground md:flex-row">
        <aside className="flex shrink-0 flex-col border-b border-border bg-card px-4 py-3 md:w-72 md:border-r md:border-b-0 md:px-5 md:py-6">
          <div className="hidden px-3 md:block">
            <Logo size="hero" className="-ml-1.5 max-w-full" />
            <p className="mt-2 text-sm leading-relaxed text-muted-foreground">
              A little setup.
              <br />A lot you can build.
            </p>
          </div>
          <nav
            aria-label="Setup steps"
            className="flex gap-2 md:mt-8 md:flex-col md:gap-1">
            {STEPS.map((label, index) => (
              <Button
                key={label}
                variant={progress.step === index ? 'secondary' : 'ghost'}
                className="h-auto min-w-0 flex-1 justify-start gap-2 whitespace-normal px-2 py-2 text-left md:flex-none md:gap-3 md:px-3 md:py-2.5"
                disabled={blocked}
                aria-current={progress.step === index ? 'step' : undefined}
                onClick={() => move(index as OnboardingProgress['step'])}>
                <span
                  className={cn(
                    'flex size-6 shrink-0 items-center justify-center rounded-full border border-border text-xs',
                    progress.step === index &&
                      'border-primary bg-primary text-primary-foreground',
                    index < progress.step &&
                      'border-primary/20 bg-primary/10 text-primary',
                  )}>
                  {index < progress.step ? (
                    <Check className="size-3.5" />
                  ) : (
                    index + 1
                  )}
                </span>
                <span className="min-w-0">
                  <span className="block truncate text-xs md:text-sm">
                    {label}
                  </span>
                  <span className="mt-0.5 hidden truncate text-xs font-normal text-muted-foreground md:block">
                    {STEP_DETAILS[index]}
                  </span>
                </span>
              </Button>
            ))}
          </nav>
          <div className="mt-auto hidden px-3 pt-8 md:block">
            <p className="flex items-start gap-2 text-xs font-medium leading-relaxed">
              <ShieldCheck className="mt-0.5 size-4 shrink-0 text-primary" />
              <span>
                On your computer.
                <br />
                In your control.
              </span>
            </p>
            <p className="mt-1.5 pl-6 text-xs leading-relaxed text-muted-foreground">
              Nothing starts working until you send a task.
            </p>
          </div>
        </aside>
        <main
          aria-label="Onboarding guide"
          className="flex min-h-0 min-w-0 flex-1 flex-col">
          <div
            ref={scroller}
            className="min-h-0 flex-1 overflow-y-auto [scrollbar-gutter:stable]">
            <div className="mx-auto flex min-h-full w-full max-w-4xl flex-col justify-center px-6 py-7 lg:px-12 lg:py-10">
              <div className="mb-7 flex items-center justify-between gap-4">
                <div className="space-y-2.5">
                  <p className="text-xs font-medium uppercase tracking-widest text-muted-foreground">
                    Step {progress.step + 1} of 4 · {STEPS[progress.step]}
                  </p>
                  <ProgressBar
                    fraction={(progress.step + 1) / STEPS.length}
                    label="Setup progress"
                    className="max-w-40"
                  />
                </div>
                {onClose ? (
                  <Button
                    variant="ghost"
                    size="sm"
                    disabled={blocked}
                    onClick={() => {
                      window.clearTimeout(saveTimer.current);
                      setBusy(true);
                      void save({ onboardingProgress: progress })
                        .then(() => onClose())
                        .catch((err: unknown) => setError(String(err)))
                        .finally(() => setBusy(false));
                    }}>
                    Close guide
                  </Button>
                ) : (
                  <Logo size="nav" className="md:hidden" />
                )}
              </div>
              <h1
                ref={heading}
                tabIndex={-1}
                className="max-w-2xl text-3xl font-semibold leading-tight tracking-tight outline-none lg:text-4xl">
                {
                  [
                    'Your agents. One place to build.',
                    'Connect your agents',
                    'A setup for every side of your work',
                    'What would you like to do first?',
                  ][progress.step]
                }
              </h1>
              <p className="mt-3 text-sm leading-relaxed text-muted-foreground">
                {
                  [
                    'Chat with a coding agent, or bring several agents together into a team. Let’s get you ready.',
                    'Use the coding agents you already know. Connect one to get started, or add more later.',
                    'Use each agent’s default setup, or add profiles to keep accounts, instructions, and tools separate.',
                    'Start small with a chat, assemble a team, or take a look around. Nothing runs until you send a task.',
                  ][progress.step]
                }
              </p>
              <div className="mt-7">
                {progress.step === 0 ? <OnboardingOverview /> : null}
                {progress.step === 1 ? (
                  <>
                    <AgentConfigList
                      clis={clis}
                      open={open}
                      onToggle={(kind) =>
                        setOpen((prev) => ({ ...prev, [kind]: !prev[kind] }))
                      }
                      binaryPaths={binaryPaths}
                      onBinaryPathChange={(kind, path) =>
                        setBinaryPaths((prev) => ({ ...prev, [kind]: path }))
                      }
                      onBrowse={(kind) => void browse(kind)}
                      onInstall={(kind) => void cliInstall.install(kind)}
                      installing={cliInstall.installing}
                      installResults={cliInstall.results}
                      onSignIn={
                        apis
                          ? (kind) => void login.start(kind, null)
                          : undefined
                      }
                      signingIn={login.starting?.kind ?? null}
                      profileScopedKinds={profileScopedKinds}
                      login={
                        login.login
                          ? {
                              kind: login.login.kind,
                              session: login.login.session,
                              error: login.error,
                              onSubmitCode: (code) =>
                                void login.submitCode(code),
                              onCancel: () => void login.cancel(),
                              onDismiss: login.dismiss,
                            }
                          : undefined
                      }
                    />
                    <div className="mt-3 flex flex-wrap items-center justify-between gap-2 pl-1">
                      <p className="text-xs text-muted-foreground">
                        Installed one just now? Geniro finds it on its own.
                      </p>
                      <Button
                        variant="ghost"
                        size="sm"
                        className="-mr-2"
                        disabled={blocked || clis === null}
                        onClick={() => void recheck()}>
                        <RefreshCw className="size-3.5" />
                        Re-check
                      </Button>
                    </div>
                  </>
                ) : null}
                {progress.step === 2 ? (
                  <>
                    <Card className="divide-y divide-border p-0 shadow-none">
                      {CLI_KINDS.map((kind) => {
                        const reason =
                          configDirCapability.unavailableReasonFor(kind);
                        const own = profiles.filter(
                          (profile) => profile.agent === kind,
                        );
                        const list =
                          reason === null ? (
                            <ConfigProfileList
                              compact
                              agent={kind}
                              profiles={own}
                              onChange={(next) => changeProfiles(kind, next)}
                              onPickDirectory={() =>
                                window.geniro.pickProjectFolder()
                              }
                              onSignIn={
                                apis
                                  ? (dir) => void login.start(kind, dir)
                                  : undefined
                              }
                              signingIn={
                                login.starting?.kind === kind
                                  ? login.starting.configDir
                                  : null
                              }
                              busy={blocked}
                              logins={
                                clis?.find((cli) => cli.kind === kind)
                                  ?.profileLogins ?? {}
                              }
                            />
                          ) : null;
                        return (
                          <div key={kind} className="px-5 py-4">
                            <div className="flex items-center gap-3">
                              <span className="flex size-8 shrink-0 items-center justify-center rounded-lg bg-secondary text-secondary-foreground">
                                <AgentGlyph
                                  icon={agentIconName(identities, kind)}
                                />
                              </span>
                              <div className="min-w-0 flex-1">
                                <h2 className="text-sm font-medium">
                                  {nameOf(kind)}
                                </h2>
                                <p
                                  className="truncate text-xs text-muted-foreground"
                                  title={reason ?? undefined}>
                                  {reason !== null
                                    ? 'Profiles aren’t available for this agent'
                                    : loading
                                      ? 'Checking profile support…'
                                      : own.length === 0
                                        ? 'Default setup'
                                        : `Default setup + ${own.length} ${own.length === 1 ? 'profile' : 'profiles'}`}
                                </p>
                              </div>
                              {reason !== null ? (
                                <Badge
                                  variant="muted"
                                  className="rounded-full"
                                  title={reason}>
                                  Not available
                                </Badge>
                              ) : own.length === 0 ? (
                                list
                              ) : null}
                            </div>
                            {own.length > 0 ? (
                              <div className="mt-3 pl-11">{list}</div>
                            ) : null}
                            {login.login?.kind === kind ? (
                              <div className="mt-3 pl-11">
                                <CliLoginProgress
                                  variant="inline"
                                  session={login.login.session}
                                  error={login.error}
                                  onSubmitCode={(code) =>
                                    void login.submitCode(code)
                                  }
                                  onCancel={() => void login.cancel()}
                                  onDismiss={login.dismiss}
                                />
                              </div>
                            ) : null}
                          </div>
                        );
                      })}
                    </Card>
                    <p className="mt-3 flex items-center gap-2 pl-1 text-xs text-muted-foreground">
                      <Info aria-hidden="true" className="size-3.5 shrink-0" />
                      Using one account per agent? Skip this step — profiles
                      live in Settings → Agents too.
                    </p>
                  </>
                ) : null}
                {progress.step === 3 ? (
                  <Card className="divide-y divide-border overflow-hidden p-0 shadow-none">
                    {ROUTES.map(({ value, Icon: icon, title, detail }) => {
                      const chosen = progress.route === value;
                      return (
                        <div
                          key={value}
                          className={cn(chosen && 'bg-primary/5')}>
                          <Button
                            variant="ghost"
                            disabled={blocked}
                            aria-pressed={chosen}
                            className={cn(
                              'h-auto w-full justify-start gap-4 whitespace-normal rounded-none px-5 py-4 text-left font-normal',
                              chosen && 'hover:bg-transparent',
                            )}
                            onClick={() =>
                              setProgress((prev) => ({ ...prev, route: value }))
                            }>
                            <span
                              className={cn(
                                'flex size-9 shrink-0 items-center justify-center rounded-lg bg-muted text-muted-foreground transition-colors',
                                chosen && 'bg-primary/15 text-primary',
                              )}>
                              {createElement(icon, {
                                className: 'size-4',
                                'aria-hidden': true,
                              })}
                            </span>
                            <span className="flex min-w-0 flex-1 flex-col gap-0.5">
                              <span className="text-sm font-medium">
                                {title}
                              </span>
                              <span className="text-xs text-muted-foreground">
                                {detail}
                              </span>
                            </span>
                            <OptionIndicator arity="one" chosen={chosen} />
                          </Button>
                          {chosen && value !== 'explore' ? (
                            <div className="flex flex-col gap-5 pr-5 pb-5 pl-[72px]">
                              {value === 'team' ? (
                                <>
                                  <div className="flex flex-col gap-2">
                                    <p className="text-sm font-medium">
                                      How would you like to build it?
                                    </p>
                                    <OptionList
                                      label="How to build the team"
                                      arity="one"
                                      className="-ml-2"
                                      disabled={blocked}
                                      options={METHODS.map((m) => m.title)}
                                      details={METHODS.map((m) => m.detail)}
                                      selected={METHODS.filter(
                                        (m) => m.value === progress.teamMethod,
                                      ).map((m) => m.title)}
                                      onPick={(picked) => {
                                        const method = METHODS.find(
                                          (m) => m.title === picked,
                                        );
                                        if (method) {
                                          setProgress((prev) => ({
                                            ...prev,
                                            teamMethod: method.value,
                                          }));
                                        }
                                      }}
                                    />
                                  </div>
                                  {progress.teamMethod === 'ai' ? (
                                    <div className="flex flex-col gap-2">
                                      <label
                                        htmlFor="team-brief"
                                        className="text-sm font-medium">
                                        What should your team do?{' '}
                                        <span className="font-normal text-muted-foreground">
                                          (optional)
                                        </span>
                                      </label>
                                      <Textarea
                                        id="team-brief"
                                        rows={3}
                                        maxLength={4000}
                                        disabled={blocked}
                                        placeholder="For example: plan a feature, implement it, then review the changes."
                                        value={progress.brief}
                                        onChange={(event) =>
                                          setProgress((prev) => ({
                                            ...prev,
                                            brief: event.target.value,
                                          }))
                                        }
                                      />
                                      <p className="text-xs text-muted-foreground">
                                        Your description opens as a draft in the
                                        team’s AI chat. Review it and send when
                                        you’re ready.
                                      </p>
                                    </div>
                                  ) : null}
                                </>
                              ) : null}
                              {readyAgents.length > 1 ? (
                                <div className="flex flex-col items-start gap-2">
                                  <label
                                    htmlFor="first-agent"
                                    className="text-sm font-medium">
                                    Agent
                                  </label>
                                  <Select
                                    id="first-agent"
                                    className="w-52"
                                    disabled={blocked}
                                    leadingIcon={
                                      progress.agent ? (
                                        <AgentGlyph
                                          icon={agentIconName(
                                            identities,
                                            progress.agent,
                                          )}
                                        />
                                      ) : undefined
                                    }
                                    groups={[
                                      {
                                        items: readyAgents.map((cli) => ({
                                          value: cli.kind,
                                          label: nameOf(cli.kind),
                                          icon: (
                                            <AgentGlyph
                                              icon={agentIconName(
                                                identities,
                                                cli.kind,
                                              )}
                                            />
                                          ),
                                        })),
                                      },
                                    ]}
                                    value={progress.agent}
                                    placeholder="Choose an agent"
                                    onValueChange={(next) =>
                                      setProgress((prev) => ({
                                        ...prev,
                                        agent: next as CliKind,
                                      }))
                                    }
                                  />
                                  <span className="text-xs text-muted-foreground">
                                    You can switch agents any time.
                                  </span>
                                </div>
                              ) : (
                                <p className="text-sm text-muted-foreground">
                                  {ready && progress.agent
                                    ? `Your agent: ${nameOf(progress.agent)}. You can switch agents any time.`
                                    : 'Connect an agent in step 2 first, or choose Explore Geniro.'}
                                </p>
                              )}
                            </div>
                          ) : null}
                        </div>
                      );
                    })}
                  </Card>
                ) : null}
              </div>
              {error ? (
                <div className="mt-6 space-y-2">
                  <ErrorBanner
                    message="We couldn’t complete that setup action. Your choices are still here."
                    onDismiss={() => setError(null)}
                    action={
                      <Button
                        variant="ghost"
                        size="sm"
                        disabled={busy}
                        onClick={() => {
                          setBusy(true);
                          setError(null);
                          void window.geniro
                            .ensureDaemon()
                            .then((next) => {
                              setHandle(next);
                              return loaded ? recheck() : loadSettings();
                            })
                            .catch((err: unknown) => setError(String(err)))
                            .finally(() => setBusy(false));
                        }}>
                        Retry setup
                      </Button>
                    }
                  />
                  <details className="text-xs text-muted-foreground">
                    <summary className="cursor-pointer">
                      Technical details
                    </summary>
                    <p className="mt-2 break-words">{error}</p>
                  </details>
                </div>
              ) : null}
            </div>
          </div>
          <footer className="shrink-0 border-t border-border bg-background">
            <div className="mx-auto flex w-full max-w-4xl flex-wrap items-center justify-between gap-3 px-6 py-4 lg:px-12">
              <Button
                variant="ghost"
                disabled={blocked || progress.step === 0}
                onClick={() =>
                  move((progress.step - 1) as OnboardingProgress['step'])
                }>
                <ChevronLeft className="size-4" />
                Back
              </Button>
              <div className="flex items-center gap-2">
                {progress.step === 1 ? (
                  <Button
                    variant="ghost"
                    disabled={blocked}
                    onClick={() =>
                      setProgress((prev) => ({
                        ...prev,
                        step: 2,
                        route: ready ? prev.route : 'explore',
                      }))
                    }>
                    Set up later
                  </Button>
                ) : null}
                {progress.step === 2 ? (
                  <Button
                    variant="ghost"
                    disabled={blocked}
                    onClick={() => move(3)}>
                    Skip for now
                  </Button>
                ) : null}
                {progress.step < 3 ? (
                  <Button
                    disabled={blocked || (progress.step === 1 && !ready)}
                    onClick={() =>
                      move((progress.step + 1) as OnboardingProgress['step'])
                    }>
                    Continue
                    <ArrowRight className="size-4" />
                  </Button>
                ) : (
                  <Button
                    disabled={
                      blocked || (progress.route !== 'explore' && !ready)
                    }
                    onClick={() => void finish()}>
                    {busy ? 'Finishing…' : finishLabel}
                    <ArrowRight className="size-4" />
                  </Button>
                )}
              </div>
            </div>
          </footer>
        </main>
      </div>
    </AgentIdentityContext.Provider>
  );
}
