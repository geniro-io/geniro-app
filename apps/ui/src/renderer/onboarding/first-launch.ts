import type { CliKind, OnboardingProgress } from '../../shared/contracts';
import type { Team } from '../autogenerated';

export type FirstLaunch = Omit<OnboardingProgress, 'step'>;
export type TeamLaunch = FirstLaunch & { agent: CliKind };

/**
 * The example team: one lead that takes the first message and runs the job,
 * calling a planner and a reviewer when it wants them.
 */
export function starterTeam(agent: CliKind): Team {
  return {
    name: 'Plan, build, review',
    description:
      'A small team that plans a task, implements it, and reviews the result.',
    mode: 'lead',
    members: [
      {
        id: 'lead',
        name: 'Builder',
        agent,
        approval: 'auto',
        role: 'Leads the task: implements it and verifies the result.',
        instructions:
          'Ask the Planner for a plan before changing files, implement it, then ask the Reviewer to review the change and address what it reports.',
      },
      {
        id: 'planner',
        name: 'Planner',
        agent,
        approval: 'auto',
        role: 'Reads a task and the relevant code and returns a concrete implementation plan. Changes no files.',
      },
      {
        id: 'reviewer',
        name: 'Reviewer',
        agent,
        approval: 'auto',
        role: 'Reviews a change against its task and reports concrete bugs, risks and missing checks. Changes no files.',
      },
    ],
    triggers: [{ kind: 'first-message', member: 'lead' }],
    instructionBlocks: [],
  };
}
