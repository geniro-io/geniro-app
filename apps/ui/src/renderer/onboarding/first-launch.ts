import type { CliKind, OnboardingProgress } from '../../shared/contracts';
import type { Workflow } from '../autogenerated';

export type FirstLaunch = Omit<OnboardingProgress, 'step'>;
export type TeamLaunch = FirstLaunch & { agent: CliKind };

export function starterTeam(agent: CliKind): Workflow {
  return {
    name: 'Plan, build, review',
    description:
      'A small team that plans a task, implements it, and reviews the result.',
    nodes: [
      { id: 'start', kind: 'trigger', trigger: 'manual', name: 'Start' },
      {
        id: 'plan',
        kind: 'agent',
        agent,
        approval: 'auto',
        name: 'Planner',
        role: 'Read the task and relevant code. Produce a concrete implementation plan for the next agent. Do not change files.',
      },
      {
        id: 'build',
        kind: 'agent',
        agent,
        approval: 'auto',
        name: 'Builder',
        role: 'Implement the task using the plan from the previous agent. Verify the changes and describe the result.',
      },
      {
        id: 'review',
        kind: 'agent',
        agent,
        approval: 'auto',
        name: 'Reviewer',
        role: 'Review the implementation against the original task. Report concrete bugs, risks, and missing checks. Do not change files.',
      },
    ],
    edges: [
      { from: 'start', to: 'plan', kind: 'data' },
      { from: 'plan', to: 'build', kind: 'data' },
      { from: 'build', to: 'review', kind: 'data' },
    ],
    layout: {
      start: { x: 0, y: 80 },
      plan: { x: 260, y: 80 },
      build: { x: 520, y: 80 },
      review: { x: 780, y: 80 },
    },
  };
}
