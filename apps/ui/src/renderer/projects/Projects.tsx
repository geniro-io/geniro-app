import { useEffect, useMemo, useState } from 'react';

import type { DaemonHandle, RunConfig } from '../../shared/contracts';
import type { CreateProjectDto, ProjectDto } from '../autogenerated';
import { BackLink } from '../components/back-link';
import { EmptyState } from '../components/empty-state';
import { ErrorBanner } from '../components/error-banner';
import { useLatestCallback } from '../components/use-latest-callback';
import { useNarrowViewport } from '../components/use-narrow-viewport';
import { usePhoneBackEntry } from '../components/use-phone-back-entry';
import { createDaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { NewProjectDialog } from '../tasks/new-project-dialog';
import { ProjectDetail } from './project-detail';
import { ProjectPageSlotsContext } from './project-page-slots';
import { LIST_UNREAD, ProjectsLibrary } from './projects-library';
import { UnboundRunConfigs } from './unbound-run-configs';
import { useBindRunConfigsByFolder } from './use-bind-run-configs';
import { useProjectQueues } from './use-project-queues';
import { useProjects } from './use-projects';
import { useRunConfigSources } from './use-run-config-sources';

const NO_IDS: ReadonlySet<string> = new Set();

/** What a link or another screen asked the Projects screen to show: one project, or the gallery (null). */
export interface ProjectsRequest {
  projectId: string | null;
}

/**
 * Every project — a folder, its board and its standing instructions — as a
 * gallery of cards; a card opens that project's page.
 */
export function Projects({
  handle,
  client,
  request,
  onRequestHandled,
  onProjectShown,
  onOpenBoard,
  onOpenTeam,
}: {
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  /** Taken once, then handed back through `onRequestHandled`. */
  request: ProjectsRequest | null;
  onRequestHandled: () => void;
  /** The project on show (null for the gallery), for the address bar. */
  onProjectShown: (projectId: string | null) => void;
  onOpenBoard: (projectId: string) => void;
  /** Open a library team on its own page — the shared team. */
  onOpenTeam: (slug: string) => void;
}): React.JSX.Element {
  const apis = useMemo(
    () => (handle ? createDaemonApis(handle) : null),
    [handle],
  );
  const listed = useProjects(apis, client);
  const sources = useRunConfigSources(apis);
  const narrow = useNarrowViewport();

  const [openId, setOpenId] = useState<string | null>(
    request?.projectId ?? null,
  );
  const [created, setCreated] = useState<ProjectDto | null>(null);
  const [sheetSlot, setSheetSlot] = useState<HTMLElement | null>(null);
  const [dockSlot, setDockSlot] = useState<HTMLElement | null>(null);
  const slots = useMemo(
    () => ({ sheet: sheetSlot, dock: dockSlot }),
    [sheetSlot, dockSlot],
  );
  const [gone, setGone] = useState<ReadonlySet<string>>(NO_IDS);
  const [creating, setCreating] = useState(false);
  const [actionError, setActionError] = useState<string | null>(null);
  const [dismissedListError, setDismissedListError] = useState<string | null>(
    null,
  );

  const requestHandled = useLatestCallback(() => onRequestHandled(), []);
  useEffect(() => {
    if (request === null) {
      return;
    }
    setOpenId(request.projectId);
    requestHandled();
  }, [request, requestHandled]);

  const projects = useMemo(() => {
    if (listed.projects === null) {
      return null;
    }
    const kept = listed.projects.filter((project) => !gone.has(project.id));
    return created !== null &&
      !gone.has(created.id) &&
      !kept.some((project) => project.id === created.id)
      ? [...kept, created]
      : kept;
  }, [listed.projects, created, gone]);

  useEffect(() => {
    if (
      created !== null &&
      listed.projects?.some((project) => project.id === created.id)
    ) {
      setCreated(null);
    }
  }, [created, listed.projects]);

  useBindRunConfigsByFolder(
    apis,
    listed.projects !== null,
    sources,
    setActionError,
  );

  const writeConfigs = useLatestCallback(
    (edit: (current: readonly RunConfig[]) => RunConfig[]): void => {
      sources
        .writeRunConfigs(edit)
        .catch((err: unknown) => setActionError(String(err)));
    },
    [sources.writeRunConfigs],
  );

  const queuedIds = useMemo(
    () =>
      openId !== null
        ? [openId]
        : (projects?.map((project) => project.id) ?? []),
    [openId, projects],
  );
  const queues = useProjectQueues(apis, client, queuedIds);

  const configCounts = useMemo(() => {
    const counts = new Map<string, number>();
    for (const config of sources.runConfigs) {
      if (config.projectId) {
        counts.set(config.projectId, (counts.get(config.projectId) ?? 0) + 1);
      }
    }
    return counts;
  }, [sources.runConfigs]);

  const shown =
    openId === null
      ? null
      : (projects?.find((project) => project.id === openId) ?? null);

  const reportShown = useLatestCallback(
    (projectId: string | null) => onProjectShown(projectId),
    [],
  );
  useEffect(() => {
    reportShown(openId);
  }, [openId, reportShown]);

  const closeForPhone = usePhoneBackEntry(
    'projects',
    narrow && openId !== null,
    () => setOpenId(null),
  );
  const back = narrow ? closeForPhone : () => setOpenId(null);

  const create = useLatestCallback(
    async (input: CreateProjectDto): Promise<void> => {
      if (apis === null) {
        return;
      }
      try {
        const project = await apis.projects.createProject({
          createProjectDto: input,
        });
        setCreated(project);
        setOpenId(project.id);
        listed.reload();
      } catch (err: unknown) {
        setActionError(describeDaemonError(err));
      }
    },
    [apis, listed.reload],
  );

  const deleted = useLatestCallback(
    (projectId: string): void => {
      setGone((current) => new Set([...current, projectId]));
      back();
      listed.reload();
    },
    [back, listed.reload],
  );

  const listError =
    listed.error !== null && listed.error !== dismissedListError
      ? listed.error
      : null;

  const banner =
    listError !== null || actionError !== null ? (
      <div className="flex flex-col gap-2">
        {listError === null ? null : (
          <ErrorBanner
            message={listError}
            onDismiss={() => setDismissedListError(listError)}
          />
        )}
        {actionError === null ? null : (
          <ErrorBanner
            message={actionError}
            onDismiss={() => setActionError(null)}
          />
        )}
      </div>
    ) : null;

  return (
    <div className="h-full min-h-0">
      {openId === null ? (
        <ProjectsLibrary
          projects={projects}
          banner={banner}
          failed={listed.error !== null}
          teams={sources.teams}
          configCounts={configCounts}
          queues={queues}
          onOpen={setOpenId}
          onNew={() => setCreating(true)}
          footer={
            projects === null || projects.length === 0 ? null : (
              <UnboundRunConfigs
                configs={sources.runConfigs}
                projects={projects}
                onMove={(configId, projectId) =>
                  writeConfigs((current) =>
                    current.map((config) =>
                      config.id === configId
                        ? { ...config, projectId }
                        : config,
                    ),
                  )
                }
                onDelete={(configId) =>
                  writeConfigs((current) =>
                    current.filter((config) => config.id !== configId),
                  )
                }
              />
            )
          }
        />
      ) : (
        <ProjectPageSlotsContext.Provider value={slots}>
          <div className="flex h-full min-h-0">
            <div className="flex min-w-0 flex-1 flex-col">
              <div
                data-slot="project-page"
                className="min-h-0 flex-1 overflow-y-auto"
                style={{ scrollbarGutter: 'stable' }}>
                <div className="mx-auto flex max-w-[1080px] flex-col gap-5 px-4 pt-3 pb-16 sm:px-6">
                  <div className="flex items-center">
                    <BackLink label="Projects" onClick={back} />
                  </div>
                  {banner}
                  {projects === null ? (
                    <EmptyState>
                      {listed.error === null
                        ? 'Loading projects…'
                        : LIST_UNREAD}
                    </EmptyState>
                  ) : shown === null ? (
                    <EmptyState>This project no longer exists</EmptyState>
                  ) : (
                    <ProjectDetail
                      key={shown.id}
                      project={shown}
                      projects={projects}
                      apis={apis}
                      handle={handle}
                      client={client}
                      sources={sources}
                      queue={queues.get(shown.id) ?? null}
                      onChanged={listed.reload}
                      onError={setActionError}
                      onOpenBoard={onOpenBoard}
                      onOpenTeam={onOpenTeam}
                      onDeleted={deleted}
                    />
                  )}
                </div>
              </div>
              <div
                ref={setDockSlot}
                data-slot="project-page-dock"
                className="contents"
              />
            </div>
            <div
              ref={setSheetSlot}
              data-slot="project-page-sheet"
              className="contents"
            />
          </div>
        </ProjectPageSlotsContext.Provider>
      )}

      <NewProjectDialog
        open={creating}
        teams={sources.teams}
        cliDetections={sources.cliDetections}
        agentsApi={apis?.agents ?? null}
        capabilitiesApi={apis?.capabilities ?? null}
        recentConfigDirs={sources.recentConfigDirs}
        configProfiles={sources.configProfiles}
        onClose={() => setCreating(false)}
        onCreate={(input) => {
          setCreating(false);
          void create(input);
        }}
      />
    </div>
  );
}
