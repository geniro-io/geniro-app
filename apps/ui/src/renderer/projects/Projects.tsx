import { ChevronLeft, FolderGit2, Plus } from 'lucide-react';
import { useEffect, useMemo, useState } from 'react';

import type { DaemonHandle } from '../../shared/contracts';
import type { CreateProjectDto, ProjectDto } from '../autogenerated';
import { shortenPath } from '../chats/directory-select';
import { AutopilotMark } from '../components/autopilot-mark';
import { EmptyState } from '../components/empty-state';
import { ErrorBanner } from '../components/error-banner';
import { MobileBarButton } from '../components/mobile-bar-button';
import { NavListItem } from '../components/nav-list-item';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import { useLatestCallback } from '../components/use-latest-callback';
import { useNarrowViewport } from '../components/use-narrow-viewport';
import { usePhoneBackEntry } from '../components/use-phone-back-entry';
import { createDaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { NewProjectDialog } from '../tasks/new-project-dialog';
import { ProjectDetail } from './project-detail';
import { useProjects } from './use-projects';
import { useRunConfigSources } from './use-run-config-sources';

const NO_IDS: ReadonlySet<string> = new Set();

/**
 * Every project — a folder, its board and its standing instructions — as a
 * list beside the selected one's page.
 */
export function Projects({
  handle,
  client,
  requestedProjectId,
  fallbackProjectId,
  onRequestHandled,
  onProjectShown,
  onOpenBoard,
}: {
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  /** A project a link or another screen asked for; it wins over everything. */
  requestedProjectId: string | null;
  /** The board's current project, shown when nothing else was asked for. */
  fallbackProjectId: string | null;
  onRequestHandled: () => void;
  /** The project on show, for the address bar. */
  onProjectShown: (projectId: string | null) => void;
  onOpenBoard: (projectId: string) => void;
}): React.JSX.Element {
  const apis = useMemo(
    () => (handle ? createDaemonApis(handle) : null),
    [handle],
  );
  const listed = useProjects(apis, client);
  const sources = useRunConfigSources(apis);
  const narrow = useNarrowViewport();

  const [chosen, setChosen] = useState<string | null>(requestedProjectId);
  const [detailOpen, setDetailOpen] = useState(requestedProjectId !== null);
  const [created, setCreated] = useState<ProjectDto | null>(null);
  const [gone, setGone] = useState<ReadonlySet<string>>(NO_IDS);
  const [creating, setCreating] = useState(false);
  const [actionError, setActionError] = useState<string | null>(null);
  const [dismissedListError, setDismissedListError] = useState<string | null>(
    null,
  );

  const requestHandled = useLatestCallback(() => onRequestHandled(), []);
  useEffect(() => {
    if (requestedProjectId === null) {
      return;
    }
    setChosen(requestedProjectId);
    setDetailOpen(true);
    requestHandled();
  }, [requestedProjectId, requestHandled]);

  const projects = useMemo(() => {
    if (listed.projects === null) {
      return null;
    }
    const kept = listed.projects.filter((project) => !gone.has(project.id));
    return created !== null &&
      !gone.has(created.id) &&
      !kept.some((project) => project.id === created.id)
      ? [...kept, created]
      : kept;
  }, [listed.projects, created, gone]);

  useEffect(() => {
    if (
      created !== null &&
      listed.projects?.some((project) => project.id === created.id)
    ) {
      setCreated(null);
    }
  }, [created, listed.projects]);

  const shownId =
    chosen ??
    (projects === null
      ? null
      : fallbackProjectId !== null &&
          projects.some((project) => project.id === fallbackProjectId)
        ? fallbackProjectId
        : (projects[0]?.id ?? null));
  const shown =
    shownId === null
      ? null
      : (projects?.find((project) => project.id === shownId) ?? null);

  const reportShown = useLatestCallback(
    (projectId: string | null) => onProjectShown(projectId),
    [],
  );
  useEffect(() => {
    reportShown(shownId);
  }, [shownId, reportShown]);

  const back = usePhoneBackEntry('projects', narrow && detailOpen, () =>
    setDetailOpen(false),
  );

  const select = (projectId: string): void => {
    setChosen(projectId);
    setDetailOpen(true);
  };

  const create = useLatestCallback(
    async (input: CreateProjectDto): Promise<void> => {
      if (apis === null) {
        return;
      }
      try {
        const project = await apis.projects.createProject({
          createProjectDto: input,
        });
        setCreated(project);
        select(project.id);
        listed.reload();
      } catch (err: unknown) {
        setActionError(describeDaemonError(err));
      }
    },
    [apis, listed.reload],
  );

  const deleted = useLatestCallback(
    (projectId: string): void => {
      setGone((current) => new Set([...current, projectId]));
      setChosen(null);
      back();
      listed.reload();
    },
    [back, listed.reload],
  );

  const listError =
    listed.error !== null && listed.error !== dismissedListError
      ? listed.error
      : null;

  const newProject = (
    <Button
      type="button"
      className="h-8 gap-2 rounded-control active:scale-[.97] motion-reduce:active:scale-100"
      onClick={() => setCreating(true)}>
      <Plus aria-hidden="true" className="shrink-0" /> New project
    </Button>
  );

  return (
    <div className="flex h-full min-h-0 flex-col">
      <header
        className={cn(
          'flex shrink-0 flex-wrap items-end gap-x-4 gap-y-3 border-b border-border px-6 py-5 max-sm:px-4',
          detailOpen && 'max-sm:hidden',
        )}>
        <div className="flex min-w-0 flex-col gap-1">
          <h2 className="flex items-baseline gap-2 text-title font-semibold">
            Projects
            {projects === null ? null : (
              <span className="text-base font-normal text-muted-foreground tabular-nums">
                {projects.length}
              </span>
            )}
          </h2>
          <p className="text-sm text-muted-foreground">
            One folder, one board, one set of standing instructions.
          </p>
        </div>
        <div className="ml-auto flex items-center gap-2">{newProject}</div>
      </header>

      {listError !== null || actionError !== null ? (
        <div className="flex shrink-0 flex-col gap-2 px-6 pt-3 max-sm:px-4">
          {listError === null ? null : (
            <ErrorBanner
              message={listError}
              onDismiss={() => setDismissedListError(listError)}
            />
          )}
          {actionError === null ? null : (
            <ErrorBanner
              message={actionError}
              onDismiss={() => setActionError(null)}
            />
          )}
        </div>
      ) : null}

      {projects === null ? (
        listed.error === null ? (
          <EmptyState>Loading projects…</EmptyState>
        ) : null
      ) : projects.length === 0 ? (
        <EmptyState
          icon={<FolderGit2 aria-hidden="true" />}
          actions={newProject}>
          No projects yet — a project binds a folder; its tasks become that
          folder&rsquo;s board, and its instructions go to every agent run in it
        </EmptyState>
      ) : (
        <div className="flex min-h-0 flex-1">
          <nav
            aria-label="Projects"
            className={cn(
              'w-64 shrink-0 overflow-y-auto border-r border-border p-3 max-sm:w-full max-sm:border-r-0',
              detailOpen && 'max-sm:hidden',
            )}>
            <ul className="flex flex-col gap-0.5">
              {projects.map((project) => (
                <NavListItem
                  key={project.id}
                  active={project.id === shownId}
                  activateLabel={project.name}
                  onActivate={() => select(project.id)}>
                  <span className="flex min-w-0 items-center gap-1.5">
                    <span className="truncate text-sm font-medium">
                      {project.name}
                    </span>
                    <AutopilotMark project={project} showArmed={false} />
                    <span className="ml-auto shrink-0 pl-2 font-mono text-xs text-muted-foreground">
                      {project.taskKey}
                    </span>
                  </span>
                  <span
                    className="truncate text-xs text-muted-foreground"
                    title={project.folder}>
                    {shortenPath(project.folder)}
                  </span>
                </NavListItem>
              ))}
            </ul>
          </nav>
          <div
            data-slot="project-pane"
            className={cn(
              'h-full min-w-0 flex-1 overflow-y-auto',
              !detailOpen && 'max-sm:hidden',
            )}
            style={{ scrollbarGutter: 'stable' }}>
            <div className="mx-auto flex w-full max-w-2xl flex-col gap-6 px-6 py-8 max-sm:gap-5 max-sm:px-4 max-sm:py-5">
              {shown === null ? (
                <EmptyState>This project no longer exists</EmptyState>
              ) : (
                <ProjectDetail
                  key={shown.id}
                  project={shown}
                  projects={projects}
                  apis={apis}
                  sources={sources}
                  onChanged={listed.reload}
                  onError={setActionError}
                  onOpenBoard={onOpenBoard}
                  onDeleted={deleted}
                />
              )}
            </div>
          </div>
        </div>
      )}

      {narrow && detailOpen ? (
        <MobileBarButton
          label="Back to projects"
          onClick={back}
          className="left-2">
          <ChevronLeft aria-hidden="true" />
        </MobileBarButton>
      ) : null}

      <NewProjectDialog
        open={creating}
        teams={sources.teams}
        cliDetections={sources.cliDetections}
        onClose={() => setCreating(false)}
        onCreate={(input) => {
          setCreating(false);
          void create(input);
        }}
      />
    </div>
  );
}
