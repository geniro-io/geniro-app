// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { aProject } from '../__fixtures__/projects';
import { type ProjectQueueDto, TaskStatus } from '../autogenerated';
import { ProjectCard, runsAsLabel } from './project-card';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => root?.unmount());
  container?.remove();
  root = null;
  container = null;
});

const queue = (running: number, waiting: number): ProjectQueueDto => ({
  projectId: 'p1',
  enabled: false,
  intakeStatus: TaskStatus.Todo,
  cap: 1,
  running,
  waiting,
  breakerOpen: false,
  failureStreak: 0,
  eligible: [],
  blocked: [],
  active: [],
});

function render(
  props: Partial<React.ComponentProps<typeof ProjectCard>> = {},
): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <ul>
        <ProjectCard
          project={aProject({
            name: 'Geniro',
            taskKey: 'GEN',
            folder: '/Users/me/code/geniro',
          })}
          teams={[]}
          configCount={0}
          queue={null}
          onOpen={vi.fn()}
          {...props}
        />
      </ul>,
    );
  });
  return container;
}

describe('ProjectCard', () => {
  it('shows the key, name, folder and what the project gives a run', () => {
    const el = render({
      project: aProject({
        name: 'Geniro',
        taskKey: 'GEN',
        folder: '/Users/me/code/geniro',
        description: 'The desktop app.',
        instructions: 'Use pnpm.',
        agentKind: 'claude',
        model: 'opus',
      }),
      configCount: 2,
      queue: queue(1, 3),
    });

    expect(
      el.querySelector('[data-slot="project-monogram"]')?.textContent,
    ).toBe('GEN');
    expect(el.textContent).toContain('Geniro');
    expect(el.querySelector('[title="/Users/me/code/geniro"]')).not.toBeNull();
    expect(el.textContent).toContain('The desktop app.');
    expect(el.textContent).toContain('Standing instructions');
    expect(el.textContent).toContain('2 configurations');
    expect(el.textContent).toContain('claude · opus');
    expect(
      el.querySelector('[data-slot="project-card-queue"]')?.textContent,
    ).toBe('1 running · 3 waiting');
  });

  it('says what a fresh project lacks, and draws no queue it has not read', () => {
    const el = render();
    expect(el.textContent).toContain('No description');
    expect(el.textContent).toContain('No instructions yet');
    expect(el.textContent).toContain('0 configurations');
    expect(el.querySelector('[data-slot="project-card-queue"]')).toBeNull();
    expect(el.querySelector('[data-slot="autopilot-pill"]')).toBeNull();
  });

  it('marks an armed autopilot, and a stopped one as stopped', () => {
    const armed = render({
      project: aProject({ autopilotEnabled: true }),
    });
    expect(
      armed.querySelector('[data-slot="autopilot-pill"]')?.textContent,
    ).toContain('Autopilot');
    act(() => root?.unmount());

    const stopped = render({
      project: aProject({ autopilotEnabled: true, autopilotFailureStreak: 3 }),
    });
    expect(
      stopped.querySelector('[data-slot="autopilot-pill"]')?.textContent,
    ).toContain('Stopped');
    act(() => root?.unmount());

    const waiting = render({
      project: aProject({
        autopilotEnabled: true,
        autopilotLimitUntil: '2099-11-08T11:01:00.000Z',
      }),
    });
    expect(
      waiting.querySelector('[data-slot="autopilot-pill"]')?.textContent,
    ).toContain('Waiting');
  });

  it('shows a project from before card keys by its name’s initials', () => {
    const el = render({
      project: aProject({ name: 'billing service', taskKey: null }),
    });
    expect(
      el.querySelector('[data-slot="project-monogram"]')?.textContent,
    ).toBe('BS');
  });

  it('names a team by its library name, else the agent and its model, else says no agent is set', () => {
    const teams = [{ slug: 'ship-it', name: 'Ship it' }];
    expect(runsAsLabel(aProject({ teamSlug: 'ship-it' }), teams)).toBe(
      'Ship it',
    );
    expect(
      runsAsLabel(
        aProject({ teamSlug: 'ship-it', agentKind: 'claude', model: 'opus' }),
        teams,
      ),
    ).toBe('Ship it');
    expect(runsAsLabel(aProject({ teamSlug: 'gone' }), teams)).toBe('gone');
    expect(
      runsAsLabel(aProject({ agentKind: 'claude', model: 'opus' }), teams),
    ).toBe('claude · opus');
    expect(runsAsLabel(aProject({ agentKind: 'codex' }), teams)).toBe('codex');
    expect(runsAsLabel(aProject(), teams)).toBe('No agent');
  });
});
