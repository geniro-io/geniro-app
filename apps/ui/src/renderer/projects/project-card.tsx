import { cva } from 'class-variance-authority';
import {
  Bot,
  FileText,
  Play,
  SlidersHorizontal,
  Workflow as TeamIcon,
} from 'lucide-react';

import type { ProjectDto } from '../autogenerated';
import { teamSlugOf } from '../chats/composer-values';
import { shortenPath } from '../chats/directory-select';
import { plural } from '../chats/run-outcome';
import type { TargetTeam } from '../chats/target-select';
import { AutopilotMark } from '../components/autopilot-mark';
import { LIFT_CARD_CLASS } from '../components/lift-card';
import { initialsOf } from '../components/member-avatar';
import { NavListItem } from '../components/nav-list-item';
import { cn } from '../components/ui/utils';
import { isBreakerOpen } from '../tasks/autopilot-control';
import { targetLabel, targetOf } from '../tasks/task-target';
import type { ProjectQueueReading } from './use-project-queues';

const monogramVariants = cva(
  'inline-flex shrink-0 items-center justify-center rounded-control bg-primary/10 font-mono font-semibold tracking-tight text-primary ring-1 ring-primary/20',
  {
    variants: {
      size: { md: 'size-10 text-xs', lg: 'size-14 text-base' },
    },
    defaultVariants: { size: 'md' },
  },
);

/**
 * A project's card key on a tinted tile — the project's face on its card and
 * its page; a project from before card keys shows its name's initials.
 */
export function ProjectMonogram({
  project,
  size = 'md',
}: {
  project: Pick<ProjectDto, 'taskKey' | 'name'>;
  size?: 'md' | 'lg';
}): React.JSX.Element {
  return (
    <span
      aria-hidden="true"
      data-slot="project-monogram"
      className={monogramVariants({ size })}>
      {project.taskKey ?? initialsOf(project.name)}
    </span>
  );
}

/** Whether the project's autopilot is armed or stopped by its breaker, as a pill; nothing when it is off. */
export function AutopilotPill({
  project,
}: {
  project: ProjectDto;
}): React.JSX.Element | null {
  if (!project.autopilotEnabled) {
    return null;
  }
  const stopped = isBreakerOpen(project);
  return (
    <span
      data-slot="autopilot-pill"
      className={cn(
        'inline-flex h-6 shrink-0 items-center gap-1 rounded-pill px-2 text-xs font-medium',
        stopped ? 'bg-warning/15 text-warning' : 'bg-primary/10 text-primary',
      )}>
      <AutopilotMark project={project} />
      {stopped ? 'Stopped' : 'Autopilot'}
    </span>
  );
}

/**
 * Who a project's board runs its cards with, in a few words: a team by its
 * name where the library holds it, else an agent and its model.
 */
export function runsAsLabel(
  project: ProjectDto,
  teams: readonly TargetTeam[],
): string {
  const target = targetOf(project);
  const label = targetLabel(target, teams);
  if (target === null || label === null) {
    return 'No agent';
  }
  return teamSlugOf(target) !== null || project.model === null
    ? label
    : `${label} · ${project.model}`;
}

/** {@link runsAsLabel} behind the board's own icon for a team or an agent. */
export function RunsAs({
  project,
  teams,
}: {
  project: ProjectDto;
  teams: readonly TargetTeam[];
}): React.JSX.Element {
  const target = targetOf(project);
  const Icon = target !== null && teamSlugOf(target) !== null ? TeamIcon : Bot;
  return (
    <>
      <Icon aria-hidden="true" className="size-3.5 shrink-0" />
      <span className="truncate">{runsAsLabel(project, teams)}</span>
    </>
  );
}

/**
 * One project in the gallery: its key, name, folder and what it is for, then
 * what it gives a run — its instructions, its bound configurations, who runs
 * its board — and its queue. The whole card opens the project.
 */
export function ProjectCard({
  project,
  teams,
  configCount,
  queue,
  onOpen,
}: {
  project: ProjectDto;
  teams: readonly TargetTeam[];
  configCount: number;
  /** The daemon's count of the board's live and waiting tasks; null until read. */
  queue: ProjectQueueReading | null;
  onOpen: () => void;
}): React.JSX.Element {
  return (
    <NavListItem
      active={false}
      activateLabel={`Open ${project.name}`}
      onActivate={onOpen}
      className={cn('p-5', LIFT_CARD_CLASS)}>
      <div data-slot="project-card" className="flex flex-col gap-4">
        <div className="flex items-start justify-between gap-3">
          <ProjectMonogram project={project} />
          <AutopilotPill project={project} />
        </div>
        <div className="flex min-w-0 flex-col gap-1">
          <h3 className="min-w-0 truncate text-base font-semibold">
            {project.name}
          </h3>
          <p
            className="truncate font-mono text-xs text-muted-foreground"
            title={project.folder}>
            {shortenPath(project.folder)}
          </p>
          <p className="mt-1 line-clamp-2 min-h-10 text-sm text-muted-foreground">
            {project.description ?? 'No description'}
          </p>
        </div>
        <div className="flex flex-col gap-1.5 border-t border-border pt-3 text-xs text-muted-foreground tabular-nums">
          <span className="flex min-w-0 items-center gap-1.5">
            <FileText aria-hidden="true" className="size-3.5 shrink-0" />
            <span
              className={cn(
                'truncate',
                project.instructions !== null && 'text-foreground',
              )}>
              {project.instructions === null
                ? 'No instructions yet'
                : 'Standing instructions'}
            </span>
            <span aria-hidden="true">·</span>
            <SlidersHorizontal
              aria-hidden="true"
              className="size-3.5 shrink-0"
            />
            <span className="shrink-0">
              {plural(configCount, 'configuration', 'configurations')}
            </span>
          </span>
          <span className="flex min-w-0 items-center gap-1.5">
            <RunsAs project={project} teams={teams} />
            {queue === null ? null : (
              <>
                <span aria-hidden="true">·</span>
                <Play aria-hidden="true" className="size-3.5 shrink-0" />
                <span data-slot="project-card-queue" className="shrink-0">
                  {queue.running} running · {queue.waiting} waiting
                </span>
              </>
            )}
          </span>
        </div>
      </div>
    </NavListItem>
  );
}
