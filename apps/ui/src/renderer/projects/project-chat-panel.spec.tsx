// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  type DaemonHandle,
  DEFAULT_SETTINGS,
  type GeniroApi,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import { stubResizeObserver } from '../__tests__/stub-resize-observer';
import type { RunDto } from '../autogenerated';
import type { HostedThread } from '../chats/hosted-thread';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { ProjectChatPanel } from './project-chat-panel';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const { drawn } = vi.hoisted(() => ({
  drawn: { hosted: null as HostedThread | null },
}));
vi.mock('../chats/Chats', () => ({
  Chats: function ChatsStub({ hosted }: { hosted: HostedThread }): null {
    drawn.hosted = hosted;
    return null;
  },
}));

const openProjectChat = vi.fn();
const APIS = {
  projects: { openProjectChat, discardProjectChat: vi.fn() },
} as unknown as DaemonApis;

let container: HTMLDivElement;
let root: Root;
const updateSettings = vi.fn<GeniroApi['updateSettings']>();

beforeEach(async () => {
  stubResizeObserver();
  updateSettings.mockReset().mockResolvedValue(DEFAULT_SETTINGS);
  window.geniro = createPreloadStub({
    getSettings: () =>
      Promise.resolve({
        ...DEFAULT_SETTINGS,
        lastAnalysisConfig: {
          agent: 'claude',
          configDir: '/profiles/work',
          model: 'opus',
          effort: 'xhigh',
          contextWindow: null,
          autoCompactPercent: null,
          modelParameters: {},
          approval: 'auto',
        },
      }),
    updateSettings,
  });
  drawn.hosted = null;
  openProjectChat.mockReset().mockResolvedValue({ id: 'run-1' });
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root.render(
      <ProjectChatPanel
        projectId="p1"
        projectName="Billing"
        runsTeam={false}
        apis={APIS}
        handle={{ host: '127.0.0.1', port: 1, token: 't' } as DaemonHandle}
        client={{} as DaemonClient}
        onClose={() => undefined}
        onBeforeSend={() => Promise.resolve()}
        onWorkingChange={() => undefined}
        onTurnSettled={() => undefined}
      />,
    );
  });
});

afterEach(() => {
  act(() => {
    root.unmount();
  });
  container.remove();
});

describe('ProjectChatPanel', () => {
  it('opens a new chat on the setup last used', async () => {
    await drawn.hosted!.open();

    expect(openProjectChat).toHaveBeenCalledWith({
      projectId: 'p1',
      startProjectChatDto: {
        agentKind: 'claude',
        approval: 'acceptEdits',
        agentOptions: {},
        configDir: '/profiles/work',
        model: 'opus',
        effort: 'xhigh',
      },
    });
  });

  it('remembers a setup changed in the chat', async () => {
    await drawn.hosted!.onRunSettingsChanged!({
      id: 'run-1',
      agentKind: 'claude',
      configDir: null,
      model: 'sonnet',
      effort: 'low',
      contextWindow: null,
      autoCompactPercent: null,
      modelParameters: {},
      approval: 'ask',
    } as RunDto);

    expect(updateSettings).toHaveBeenCalledWith(
      expect.objectContaining({
        lastChangeChatApproval: 'ask',
        lastAnalysisConfig: expect.objectContaining({
          model: 'sonnet',
          effort: 'low',
          approval: 'auto',
        }),
      }),
    );
  });
});
