import type { DaemonHandle } from '../../shared/contracts';
import type { RunAwaiting, RunDto } from '../autogenerated';
import { HostedChatDock } from '../chats/hosted-chat-dock';
import {
  openChangeChat,
  rememberChangeChatSetup,
} from '../chats/improvement-chat-setup';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

/**
 * The chat docked under a project's page: the user asks for a change to the
 * project's instructions, or to how its default team works in it, and the
 * agent puts it on a card. The page reads the project back once a turn ends.
 */
export function ProjectChatPanel({
  projectId,
  projectName,
  runsTeam,
  apis,
  handle,
  client,
  hidden = false,
  onClose,
  onBeforeSend,
  onWorkingChange,
  onAwaitingChange,
  onTurnSettled,
}: {
  projectId: string;
  projectName: string;
  /** Whether the project defaults to a team, which the empty chat then offers to change here. */
  runsTeam: boolean;
  apis: DaemonApis;
  handle: DaemonHandle;
  client: DaemonClient;
  /** Closed by the user but still following its conversation. */
  hidden?: boolean;
  onClose: () => void;
  /** Writes what the page holds unsaved before a message reaches the daemon. */
  onBeforeSend: () => Promise<unknown>;
  onWorkingChange: (working: boolean) => void;
  onAwaitingChange?: (awaiting: RunAwaiting | null) => void;
  /** A turn ended — the page reads back what the agent's card may have changed. */
  onTurnSettled: () => void | Promise<void>;
}): React.JSX.Element {
  const open = useLatestCallback(
    (): Promise<RunDto> =>
      openChangeChat((startProjectChatDto) =>
        apis.projects.openProjectChat({ projectId, startProjectChatDto }),
      ),
    [apis, projectId],
  );
  const discard = useLatestCallback(async (): Promise<void> => {
    await apis.projects.discardProjectChat({ projectId });
  }, [apis, projectId]);

  return (
    <HostedChatDock
      label={`Change ${projectName} with chat`}
      panelName="project chat panel"
      storageKey="projectChat.panelHeight"
      handle={handle}
      client={client}
      hidden={hidden}
      onClose={onClose}
      thread={{
        open,
        discard,
        queueScope: `project-chat:${projectId}`,
        emptyText: runsTeam
          ? `Ask for a change to ${projectName}’s instructions, or to how its team works here — a member’s model, effort or profile, its fallback agents, extra instructions. Other projects and any team are in reach too. The agent puts each change on a card; nothing changes until you approve.`
          : `Ask for a change to ${projectName}’s instructions. Other projects and any team are in reach too. The agent puts each change on a card; nothing changes until you approve.`,
        composerLabel: 'Ask for a project change',
        composerPlaceholder: 'Describe the change…',
        onBeforeSend,
        onWorkingChange,
        onAwaitingChange,
        onTurnSettled,
        onRunSettingsChanged: rememberChangeChatSetup,
      }}
    />
  );
}
