import { CLI_KINDS } from '../../shared/contracts';
import type { ProjectDto } from '../autogenerated';
import { isChatApprovalMode, targetAgentKind } from '../chats/composer-values';
import type { AppliedRunConfig } from '../chats/run-config';
import { targetOf } from '../tasks/task-target';

/** What of a project the new-chat composer reads to preselect its target. */
export type ProjectTargetFields = Pick<
  ProjectDto,
  | 'agentKind'
  | 'teamSlug'
  | 'model'
  | 'effort'
  | 'contextWindow'
  | 'modelParameters'
  | 'approval'
  | 'configDir'
>;

/** The composer choices a project's default target resolves to. */
export type ProjectTargetSeed = Pick<
  AppliedRunConfig,
  | 'target'
  | 'agentKind'
  | 'isTeam'
  | 'configDir'
  | 'model'
  | 'effort'
  | 'contextWindow'
  | 'modelParameters'
  | 'approval'
>;

/**
 * The composer state a project's default target names — a team, or an agent
 * with the CLI settings the project carries — or null when it names none this
 * build can run, in which case the composer keeps its own target.
 */
export function projectTargetSeed(
  project: ProjectTargetFields,
): ProjectTargetSeed | null {
  const target = targetOf(project);
  if (target === null) {
    return null;
  }
  if (project.teamSlug != null && project.teamSlug !== '') {
    return {
      target,
      agentKind: targetAgentKind(target),
      isTeam: true,
      configDir: null,
      model: null,
      effort: null,
      contextWindow: null,
      modelParameters: {},
      approval: null,
    };
  }
  if (!(CLI_KINDS as readonly string[]).includes(target)) {
    return null;
  }
  return {
    target,
    agentKind: targetAgentKind(target),
    isTeam: false,
    configDir: project.configDir,
    model: project.model,
    effort: project.effort,
    contextWindow: project.contextWindow,
    modelParameters: project.modelParameters,
    approval: isChatApprovalMode(project.approval) ? project.approval : null,
  };
}
