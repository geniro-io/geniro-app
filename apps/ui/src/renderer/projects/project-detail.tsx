// TWIN: PROJECT_NAME_MAX in apps/daemon/src/v1/projects/projects.types.ts.
const NAME_MAX = 120;

const SAVED_FLASH_MS = 1500;

const HERO_CHIP_CLASS =
  'inline-flex h-6 min-w-0 items-center gap-1 rounded-pill bg-muted px-2 text-muted-foreground';

/** One figure of the board's queue, as the daemon counted it. */
function QueueFigure({
  label,
  value,
  live = false,
}: {
  label: string;
  value: number | null;
  live?: boolean;
}): React.JSX.Element {
  const active = live && value !== null && value > 0;
  return (
    <div
      data-slot="project-queue-figure"
      className="flex min-w-0 flex-col gap-1 rounded-control bg-muted/60 px-3 py-2.5">
      <span className="flex min-w-0 items-center gap-1.5 text-xs text-muted-foreground">
        {live ? (
          <StatusDot
            tone={active ? 'ok' : 'unknown'}
            className={cn('shrink-0', active && 'animate-pulse')}
          />
        ) : null}
        <span className="truncate">{label}</span>
      </span>
      <span
        className={cn(
          'text-xl leading-none font-semibold tabular-nums',
          value === null || value === 0 ? 'text-muted-foreground' : null,
        )}>
        {value ?? '—'}
      </span>
    </div>
  );
}

/**
 * One project's page: a hero with its key, name, folder and who runs it,
 * then its instructions, its board and its bound run configurations as cards.
 */
export function ProjectDetail({
  project,
  projects,
  apis,
  handle,
  client,
  sources,
  queue,
  onChanged,
  onError,
  onOpenBoard,
  onOpenTeam,
  onOpenKnowledge,
  onDeleted,
}: {
  project: ProjectDto;
  projects: readonly ProjectDto[];
  apis: DaemonApis | null;
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  sources: RunConfigSources;
  /** The daemon's count of the board's live and waiting tasks; null until read. */
  queue: ProjectQueueReading | null;
  /**
   * A write to the project's name, run settings or autopilot landed: the list
   * is read again, so the controls drawn from it do not wait on the event.
   */
  onChanged: () => void;
  onError: (message: string) => void;
  onOpenBoard: (projectId: string) => void;
  onOpenTeam: (slug: string) => void;
  /** Open Knowledge with this project picked. */
  onOpenKnowledge: (projectId: string) => void;
  onDeleted: (projectId: string) => void;
}): React.JSX.Element {
  const [savedFlash, setSavedFlash] = useState(false);
  const flashTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const mounted = useRef(true);
  useEffect(() => {
    mounted.current = true;
    return () => {
      mounted.current = false;
      if (flashTimer.current !== null) {
        clearTimeout(flashTimer.current);
        flashTimer.current = null;
      }
    };
  }, []);

  const saved = useLatestCallback((): void => {
    if (!mounted.current) {
      return;
    }
    setSavedFlash(true);
    if (flashTimer.current !== null) {
      clearTimeout(flashTimer.current);
    }
    flashTimer.current = setTimeout(() => {
      flashTimer.current = null;
      setSavedFlash(false);
    }, SAVED_FLASH_MS);
  }, []);

  const patchProject = useLatestCallback(
    async (patch: UpdateProjectDto): Promise<void> => {
      if (apis === null) {
        return;
      }
      try {
        await apis.projects.updateProject({
          projectId: project.id,
          updateProjectDto: patch,
        });
        saved();
        onChanged();
      } catch (err: unknown) {
        onError(describeDaemonError(err));
      }
    },
    [apis, project.id, saved, onChanged, onError],
  );

  const rearm = useLatestCallback(async (): Promise<void> => {
    if (apis === null) {
      return;
    }
    try {
      await apis.projects.rearmProjectAutopilot({ projectId: project.id });
      saved();
      onChanged();
    } catch (err: unknown) {
      onError(describeDaemonError(err));
    }
  }, [apis, project.id, saved, onChanged, onError]);

  const [renaming, setRenaming] = useState(false);
  const commitName = (draft: string): void => {
    setRenaming(false);
    const name = draft.trim();
    if (name !== '') {
      void patchProject({ name });
    }
  };

  const [runConfigOpen, setRunConfigOpen] = useState(false);
  const instructionSizes = useProjectInstructionSizes(
    apis?.projects ?? null,
    project.id,
    `${project.name}\u0000${project.instructionsRevision}`,
  );

  const teamSlug =
    project.teamSlug === null || project.teamSlug === ''
      ? null
      : project.teamSlug;

  const slots = useContext(ProjectPageSlotsContext);
  const [chatOpen, setChatOpen] = useState(false);
  const [chatMounted, setChatMounted] = useState(false);
  const [chatWorking, setChatWorking] = useState(false);
  const [chatAwaiting, setChatAwaiting] = useState<RunAwaiting | null>(null);
  const [chatTurns, setChatTurns] = useState(0);
  const instructionsFlush = useRef<(() => Promise<unknown>) | null>(null);
  const overlayFlush = useRef<(() => Promise<unknown>) | null>(null);
  const beforeChatSend = useLatestCallback(
    (): Promise<unknown> =>
      Promise.all([instructionsFlush.current?.(), overlayFlush.current?.()]),
    [],
  );
  const afterChatTurn = useLatestCallback((): void => {
    setChatTurns((turns) => turns + 1);
    onChanged();
  }, [onChanged]);
  const chatWaits = chatAwaiting !== null && !chatOpen;

  const [confirming, setConfirming] = useState(false);
  const [deleting, setDeleting] = useState(false);
  const [deleteError, setDeleteError] = useState<string | null>(null);
  const [knowledgeFate, setKnowledgeFate] = useState<KnowledgeFate>('global');
  const knowledgeCounts = useKnowledgeCounts(apis, client);
  const placed = knowledgeCounts?.places.find(
    (row) => row.place === projectPlace(project.id),
  );
  const knowledgeHeld = useKnowledgeHeld(
    apis,
    confirming ? projectPlace(project.id) : null,
  );
  const linkedCount = sources.runConfigs.filter(
    (config) => config.projectId === project.id,
  ).length;

  const confirmDelete = useLatestCallback(async (): Promise<void> => {
    if (apis === null) {
      return;
    }
    const projectId = project.id;
    setDeleting(true);
    setDeleteError(null);
    try {
      const { knowledgeRenamed } = await apis.projects.deleteProject({
        projectId,
        knowledge: knowledgeFate,
      });
      const renamed = renamedNotice(knowledgeRenamed);
      if (renamed !== null) {
        onError(renamed);
      }
    } catch (err: unknown) {
      setDeleteError(describeDaemonError(err));
      setDeleting(false);
      return;
    }
    try {
      await sources.writeRunConfigs((current) =>
        current.map((config) =>
          config.projectId === projectId
            ? { ...config, projectId: null }
            : config,
        ),
      );
    } catch (err: unknown) {
      onError(String(err));
    }
    setDeleting(false);
    setConfirming(false);
    onDeleted(projectId);
  }, [apis, project.id, sources, onError, onDeleted, knowledgeFate]);

  return (
    <>
      <section
        data-slot="project-hero"
        aria-label={project.name}
        className="relative overflow-hidden rounded-card bg-card p-6 ring-1 ring-border max-sm:p-4">
        <div
          aria-hidden="true"
          className="pointer-events-none absolute inset-0 bg-gradient-to-br from-primary/10 via-transparent to-transparent"
        />
        <div className="relative flex gap-5 max-sm:flex-col max-sm:gap-4">
          <ProjectMonogram project={project} size="lg" />
          <div className="flex min-w-0 flex-1 flex-col gap-2">
            <div className="flex min-h-10 flex-wrap items-center gap-x-2 gap-y-1">
              {renaming ? (
                <InlineRenameInput
                  value={project.name}
                  maxLength={NAME_MAX}
                  ariaLabel="Project name"
                  className="h-10 max-w-md px-3 text-lg font-semibold"
                  onCommit={commitName}
                  onCancel={() => setRenaming(false)}
                />
              ) : (
                <>
                  <h1 className="min-w-0 text-title font-semibold break-words">
                    {project.name}
                  </h1>
                  <Button
                    type="button"
                    variant="ghost"
                    size="icon"
                    aria-label="Rename project"
                    title="Rename"
                    className="size-8 shrink-0 rounded-control text-muted-foreground"
                    onClick={() => setRenaming(true)}>
                    <Pencil className="size-4" aria-hidden />
                  </Button>
                </>
              )}
              <span
                role="status"
                className="flex shrink-0 items-center gap-1 text-sm text-success">
                {savedFlash ? (
                  <>
                    Saved
                    <Check className="size-4" aria-hidden />
                  </>
                ) : null}
              </span>
            </div>
            <div className="flex min-w-0 items-center gap-1.5 text-sm text-muted-foreground">
              <Folder aria-hidden="true" className="size-4 shrink-0" />
              <span
                className="min-w-0 truncate font-mono"
                title={project.folder}>
                {project.folder}
              </span>
              <CopyButton text={project.folder} label="Copy folder path" />
            </div>
            <div className="flex flex-wrap items-center gap-2 pt-1 text-xs">
              {project.taskKey === null ? null : (
                <span className={HERO_CHIP_CLASS}>
                  Card key
                  <span className="font-mono font-semibold text-foreground">
                    {project.taskKey}
                  </span>
                </span>
              )}
              <span className={HERO_CHIP_CLASS}>
                <RunsAs project={project} teams={sources.teams} />
              </span>
              <AutopilotPill project={project} />
            </div>
          </div>
          <div className="flex shrink-0 items-start gap-1">
            {apis === null || handle === null || client === null ? null : (
              <Button
                type="button"
                variant={chatOpen ? 'secondary' : 'outline'}
                size="sm"
                className="relative rounded-control"
                aria-pressed={chatOpen}
                aria-label={
                  chatWaits
                    ? 'Change with chat — the agent is waiting for your answer'
                    : 'Change with chat'
                }
                title={
                  chatWaits
                    ? 'The agent is waiting for your answer'
                    : 'Describe a change to this project and let an agent propose it'
                }
                onClick={() => {
                  setChatMounted(true);
                  setChatOpen((open) => !open);
                }}>
                <MessagesSquare className="size-4" aria-hidden />
                <span className="max-sm:sr-only">Change with chat</span>
                {chatWaits ? (
                  <span
                    data-slot="chat-awaiting-mark"
                    aria-hidden="true"
                    className="absolute top-1 right-1 size-2 rounded-pill bg-warning"
                  />
                ) : null}
              </Button>
            )}
            <Button
              type="button"
              variant="outline"
              size="sm"
              className="rounded-control"
              onClick={() => onOpenBoard(project.id)}>
              <KanbanSquare className="size-4" aria-hidden />
              Open board
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="icon"
              className="size-8 rounded-control text-muted-foreground hover:bg-destructive/10 hover:text-destructive"
              aria-label={`Delete ${project.name}`}
              title={`Delete ${project.name} and its tasks`}
              onClick={() => {
                setDeleteError(null);
                setKnowledgeFate('global');
                setConfirming(true);
              }}>
              <Trash2 className="size-4" aria-hidden />
            </Button>
          </div>
        </div>
      </section>

      <div className="grid items-start gap-4 lg:grid-cols-[minmax(0,1fr)_22rem]">
        <ProjectSection
          slot="project-instructions"
          icon={<FileText />}
          title="Description and instructions"
          hint="What this project is, and what every agent run in it is told.">
          <ProjectInstructionsForm
            project={project}
            api={apis?.projects ?? null}
            blockSizes={instructionSizes.blocks}
            flushRef={instructionsFlush}
            onSaved={saved}
            onError={onError}
          />
        </ProjectSection>

        <div className="flex min-w-0 flex-col gap-4">
          <ProjectSection
            slot="project-default-target"
            icon={<Bot />}
            title="Default agent or team"
            hint="Who a new chat, a card and the autopilot start with here.">
            <div className="-mt-1 -mb-2 flex flex-col">
              <SettingRow width="split" label="Default agent or team">
                <ProjectRunConfig
                  project={project}
                  teams={sources.teams}
                  cliDetections={sources.cliDetections}
                  agentsApi={apis?.agents ?? null}
                  capabilitiesApi={apis?.capabilities ?? null}
                  recentConfigDirs={sources.recentConfigDirs}
                  configProfiles={sources.configProfiles}
                  open={runConfigOpen}
                  onOpenChange={setRunConfigOpen}
                  onUpdate={(patch) => void patchProject(patch)}
                />
              </SettingRow>
            </div>
          </ProjectSection>

          <KnowledgeProjectSection
            active={knowledgeCounts === null ? null : (placed?.active ?? 0)}
            waiting={placed?.waiting ?? 0}
            onOpen={() => onOpenKnowledge(project.id)}
          />

          <ProjectSection
            slot="project-board"
            icon={<KanbanSquare />}
            title="Task board"
            hint="How this project's cards are worked.">
            <div className="grid grid-cols-2 gap-2">
              <QueueFigure
                label="Running"
                value={queue?.running ?? null}
                live
              />
              <QueueFigure
                label={
                  queue === null
                    ? 'Waiting'
                    : `Waiting in ${taskStatusMeta(queue.intakeStatus).label}`
                }
                value={queue?.waiting ?? null}
              />
            </div>
            <div className="-mt-1 -mb-2 flex flex-col divide-y divide-border">
              <SettingRow width="split" label="Autopilot">
                <AutopilotControl
                  project={project}
                  onUpdate={(patch) => void patchProject(patch)}
                  onRearm={() => void rearm()}
                />
              </SettingRow>
            </div>
          </ProjectSection>

          <ProjectInstructionSizes
            agents={instructionSizes.agents}
            loading={instructionSizes.loading}
            error={instructionSizes.error}
          />

          <ProjectRunConfigs
            project={project}
            projects={projects}
            agentsApi={apis?.agents ?? null}
            sources={sources}
            onSaved={saved}
            onError={onError}
          />
        </div>
      </div>

      {apis === null ? null : (
        <>
          {teamSlug === null ? null : (
            <ProjectTeamOverrides
              key={teamSlug}
              projectId={project.id}
              projectName={project.name}
              slug={teamSlug}
              apis={apis}
              chatWorking={chatWorking}
              reloadKey={chatTurns}
              flushRef={overlayFlush}
              onOpenTeam={onOpenTeam}
            />
          )}
          <ProjectKeptOverlays
            apis={apis}
            projectId={project.id}
            projectName={project.name}
            defaultTeamSlug={teamSlug}
          />
        </>
      )}

      {chatMounted &&
      apis !== null &&
      handle !== null &&
      client !== null &&
      slots.dock !== null
        ? createPortal(
            <ProjectChatPanel
              projectId={project.id}
              projectName={project.name}
              runsTeam={teamSlug !== null}
              apis={apis}
              handle={handle}
              client={client}
              hidden={!chatOpen}
              onClose={() => setChatOpen(false)}
              onBeforeSend={beforeChatSend}
              onWorkingChange={setChatWorking}
              onAwaitingChange={setChatAwaiting}
              onTurnSettled={afterChatTurn}
            />,
            slots.dock,
          )
        : null}

      <ConfirmDialog
        open={confirming}
        busy={deleting}
        error={deleteError}
        confirmDisabled={!knowledgeHeld.settled}
        title={`Delete ${project.name}?`}
        confirmLabel="Delete project"
        busyLabel="Deleting…"
        onCancel={() => setConfirming(false)}
        onConfirm={() => void confirmDelete()}>
        Its tasks are deleted with it. This cannot be undone — there is no
        trash, and nothing in the app can bring them back.
        {linkedCount > 0
          ? ` Its ${linkedCount} run ${linkedCount === 1 ? 'configuration is' : 'configurations are'} kept on the Projects page, waiting for another project.`
          : null}
        <KnowledgeFatePick
          held={knowledgeHeld}
          value={knowledgeFate}
          onChange={setKnowledgeFate}
        />
      </ConfirmDialog>
    </>
  );
}
