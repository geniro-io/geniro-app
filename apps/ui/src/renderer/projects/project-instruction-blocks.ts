import { hasControlCharacters } from '../../shared/contracts';
import type { ProjectInstructionBlock } from '../autogenerated';
import type { InstructionBlockIssue } from '../components/instruction-blocks';
import { randomId } from '../random-id';

/**
 * TWIN: PROJECT_BLOCK_TITLE_MAX, PROJECT_INSTRUCTIONS_MAX and
 * MAX_PROJECT_INSTRUCTION_BLOCKS in apps/daemon/src/v1/projects/projects.types.ts.
 */
export const PROJECT_BLOCK_TITLE_MAX = 80;
export const PROJECT_INSTRUCTIONS_MAX = 20_000;
export const MAX_PROJECT_INSTRUCTION_BLOCKS = 40;

/** A block just added: no title, no text, an id of its own. */
export function newProjectBlock(): ProjectInstructionBlock {
  return { id: `block-${randomId()}`, title: '', text: '' };
}

/** What the daemon would refuse in each block, by block id. */
export function projectBlockIssues(
  blocks: readonly ProjectInstructionBlock[],
): Map<string, InstructionBlockIssue[]> {
  const issues = new Map<string, InstructionBlockIssue[]>();
  const add = (id: string, issue: InstructionBlockIssue): void => {
    issues.set(id, [...(issues.get(id) ?? []), issue]);
  };
  for (const block of blocks) {
    if (block.title.length > PROJECT_BLOCK_TITLE_MAX) {
      add(block.id, {
        field: 'title',
        message: `A title may have at most ${PROJECT_BLOCK_TITLE_MAX} characters; this one has ${block.title.length}.`,
      });
    }
    if (hasControlCharacters(block.title)) {
      add(block.id, {
        field: 'title',
        message: 'The title contains invisible control characters.',
      });
    }
    if (hasControlCharacters(block.text)) {
      add(block.id, {
        field: 'text',
        message:
          'Contains invisible control characters. Pasting from a word processor or a terminal can add them.',
      });
    }
  }
  const total = blocks
    .map((block) => block.text.trim())
    .filter(Boolean)
    .join('\n\n').length;
  const last = blocks.at(-1);
  if (total > PROJECT_INSTRUCTIONS_MAX && last !== undefined) {
    add(last.id, {
      field: 'text',
      message: `The instructions may hold at most ${PROJECT_INSTRUCTIONS_MAX.toLocaleString('en-US')} characters in all; these hold ${total.toLocaleString('en-US')}.`,
    });
  }
  return issues;
}
