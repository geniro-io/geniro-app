import { ChevronDown, Ruler } from 'lucide-react';
import { useContext, useState } from 'react';

import {
  agentDisplayName,
  agentIconName,
  AgentIdentityContext,
} from '../agent-identity';
import type { AgentInstructionSize } from '../autogenerated';
import { formatTokens } from '../chats/agent-activity';
import { AgentGlyph } from '../components/agent-glyph';
import { Spinner } from '../components/ui/spinner';
import { cn } from '../components/ui/utils';
import { InstructionSizeCard } from '../teams/instruction-size-card';
import { ProjectSection } from './project-section';

/**
 * What every run in the project carries before its prompt, one row per CLI
 * with its total, opening into what that total is made of.
 */
export function ProjectInstructionSizes({
  agents,
  loading,
  error,
}: {
  agents: readonly AgentInstructionSize[] | null;
  loading: boolean;
  error: string | null;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  const [open, setOpen] = useState<string | null>(null);
  return (
    <ProjectSection
      slot="project-instruction-sizes"
      icon={<Ruler />}
      title="Instruction size"
      hint="What every turn here carries before its prompt. A team adds its own on top.">
      {agents === null ? (
        <p className="flex items-center gap-1.5 text-sm text-muted-foreground">
          {loading ? (
            <>
              <Spinner /> Measuring…
            </>
          ) : (
            (error ?? 'Not measured yet.')
          )}
        </p>
      ) : (
        <ul
          aria-label="Instruction size per agent"
          className="-mt-1 -mb-2 flex flex-col">
          {agents.map((entry) => {
            const expanded = open === entry.agent;
            const name = agentDisplayName(identities, entry.agent);
            return (
              <li
                key={entry.agent}
                data-slot="project-instruction-size"
                data-agent={entry.agent}
                className="border-b border-border last:border-b-0">
                <button
                  type="button"
                  aria-expanded={expanded}
                  className="-mx-2 my-1 flex w-[calc(100%+1rem)] items-center gap-2.5 rounded-control px-2 py-1.5 text-left text-sm transition-colors outline-none hover:bg-accent focus-visible:ring-2 focus-visible:ring-ring"
                  onClick={() => setOpen(expanded ? null : entry.agent)}>
                  <AgentGlyph
                    icon={agentIconName(identities, entry.agent)}
                    className="shrink-0 text-muted-foreground"
                  />
                  <span className="min-w-0 flex-1 truncate font-medium">
                    {name}
                  </span>
                  <span className="shrink-0 text-muted-foreground tabular-nums">
                    ~{formatTokens(entry.approxTokens)} tokens
                  </span>
                  <ChevronDown
                    aria-hidden="true"
                    className={cn(
                      'size-4 shrink-0 text-muted-foreground transition-transform motion-reduce:transition-none',
                      expanded && 'rotate-180',
                    )}
                  />
                </button>
                {expanded ? (
                  <div className="pb-3">
                    <InstructionSizeCard
                      size={entry}
                      loading={loading}
                      error={error}
                      blockName={(blockId) => blockId}
                    />
                  </div>
                ) : null}
              </li>
            );
          })}
        </ul>
      )}
      {agents !== null && error !== null ? (
        <p className="text-xs text-muted-foreground">{error}</p>
      ) : null}
    </ProjectSection>
  );
}
