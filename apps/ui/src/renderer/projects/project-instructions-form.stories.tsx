import type { Meta, StoryObj } from '@storybook/react-vite';

import { aProject } from '../__fixtures__/projects';
import type { ProjectsApi } from '../autogenerated';
import { ProjectInstructionsForm } from './project-instructions-form';

const BILLING = aProject({
  id: 'p-billing',
  name: 'Billing',
  folder: '/Users/me/code/billing',
  description: 'The invoicing service and its admin screens.',
  instructions: 'Use pnpm. Run pnpm test:unit before you push.',
  instructionsRevision: 3,
});

/** Saves land at once, each one revision on. */
function fakeApi(): ProjectsApi {
  let revision = BILLING.instructionsRevision;
  return {
    updateProject: async ({ updateProjectDto }) => {
      revision += 1;
      return {
        ...BILLING,
        ...updateProjectDto,
        instructionsRevision: revision,
      };
    },
    readProject: async () => ({ ...BILLING, instructionsRevision: revision }),
  } as Partial<ProjectsApi> as ProjectsApi;
}

const meta = {
  title: 'Projects/ProjectInstructionsForm',
  component: ProjectInstructionsForm,
  args: {
    project: BILLING,
    api: fakeApi(),
    onSaved: () => {},
    onError: () => {},
  },
  decorators: [
    (story) => (
      <div className="w-[640px] bg-background p-3 text-foreground">
        {story()}
      </div>
    ),
  ],
} satisfies Meta<typeof ProjectInstructionsForm>;

export default meta;
type Story = StoryObj<typeof meta>;

