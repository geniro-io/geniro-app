import { useEffect, useRef, useState } from 'react';

import type { ProjectDto } from '../autogenerated';
import { ErrorBanner } from '../components/error-banner';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Button } from '../components/ui/button';
import { Label } from '../components/ui/label';
import { useDebouncedPersist } from '../components/use-debounced-persist';
import { useLatestCallback } from '../components/use-latest-callback';
import {
  type DaemonApis,
  daemonErrorCode,
  daemonErrorStatus,
  describeDaemonError,
} from '../daemon-api';

// TWIN: PROJECT_DESCRIPTION_MAX and PROJECT_INSTRUCTIONS_MAX in apps/daemon/src/v1/projects/projects.types.ts.
const DESCRIPTION_MAX = 2000;
const INSTRUCTIONS_MAX = 20_000;

interface Texts {
  description: string;
  instructions: string;
}

const blankToNull = (text: string): string | null => text.trim() || null;

const textsOf = (project: ProjectDto): Texts => ({
  description: project.description ?? '',
  instructions: project.instructions ?? '',
});

const sameTexts = (a: Texts, b: Texts): boolean =>
  a.description === b.description && a.instructions === b.instructions;

function isDrift(err: unknown): boolean {
  return (
    daemonErrorStatus(err) === 409 &&
    daemonErrorCode(err) === 'PROJECT_INSTRUCTIONS_DRIFT'
  );
}

/**
 * A project's description and instructions, saved as they are typed. Every
 * write quotes the revision the text was read or last saved at, so a change
 * made elsewhere in the meantime is refused rather than overwritten. Key it by
 * project: leaving it flushes the pending write to the project it was typed for.
 */
export function ProjectInstructionsForm({
  project,
  api,
  onSaved,
  onError,
}: {
  /** The daemon's latest copy, adopted whenever no edit is waiting on it. */
  project: ProjectDto;
  api: DaemonApis['projects'] | null;
  onSaved: () => void;
  onError: (message: string) => void;
}): React.JSX.Element {
  const [texts, setTexts] = useState<Texts>(() => textsOf(project));
  const [drift, setDrift] = useState(false);
  const textsRef = useRef(texts);
  textsRef.current = texts;
  const savedRef = useRef<Texts>(textsOf(project));
  const revisionRef = useRef(project.instructionsRevision);
  const driftRef = useRef(false);
  const writes = useRef<Promise<unknown>>(Promise.resolve());

  const markDrift = (next: boolean): void => {
    driftRef.current = next;
    setDrift(next);
  };

  const write = useLatestCallback(
    (value: Texts): Promise<void> => {
      const projectId = project.id;
      const run = writes.current.then(async () => {
        if (
          api === null ||
          driftRef.current ||
          sameTexts(value, savedRef.current)
        ) {
          return;
        }
        try {
          const saved = await api.updateProject({
            projectId,
            updateProjectDto: {
              description: blankToNull(value.description),
              instructions: blankToNull(value.instructions),
              expectedInstructionsRevision: revisionRef.current,
            },
          });
          revisionRef.current = saved.instructionsRevision;
          savedRef.current = value;
          onSaved();
        } catch (err: unknown) {
          if (isDrift(err)) {
            markDrift(true);
            return;
          }
          onError(describeDaemonError(err));
          throw err;
        }
      });
      writes.current = run.catch(() => undefined);
      return run;
    },
    [api, project.id, onSaved, onError],
  );
  const persist = useDebouncedPersist(write, () => !driftRef.current);

  const edit = (patch: Partial<Texts>): void => {
    const next = { ...textsRef.current, ...patch };
    setTexts(next);
    persist.schedule(next);
  };

  const adopt = useLatestCallback((server: Texts, revision: number): void => {
    revisionRef.current = revision;
    savedRef.current = server;
    setTexts(server);
    if (persist.dirtyRef.current) {
      persist.schedule(server);
    }
  }, []);

  useEffect(() => {
    if (project.instructionsRevision <= revisionRef.current) {
      return;
    }
    const local = textsRef.current;
    const saved = savedRef.current;
    const server = textsOf(project);
    const descriptionClean = local.description === saved.description;
    const instructionsClean = local.instructions === saved.instructions;
    if (descriptionClean && instructionsClean) {
      adopt(server, project.instructionsRevision);
      return;
    }
    savedRef.current = {
      description: descriptionClean ? server.description : saved.description,
      instructions: instructionsClean
        ? server.instructions
        : saved.instructions,
    };
    setTexts({
      description: descriptionClean ? server.description : local.description,
      instructions: instructionsClean
        ? server.instructions
        : local.instructions,
    });
  }, [project, adopt]);

  const reload = useLatestCallback(async (): Promise<void> => {
    if (api === null) {
      return;
    }
    try {
      const fresh = await api.readProject({ projectId: project.id });
      adopt(textsOf(fresh), fresh.instructionsRevision);
      markDrift(false);
    } catch (err: unknown) {
      onError(describeDaemonError(err));
    }
  }, [api, project.id, onError]);

  return (
    <div className="flex flex-col gap-3">
      {drift ? (
        <ErrorBanner
          tone="warning"
          message="Changed elsewhere — reload to see the latest"
          action={
            <Button
              type="button"
              size="sm"
              variant="outline"
              onClick={() => void reload()}>
              Reload
            </Button>
          }
          onDismiss={() => markDrift(false)}
        />
      ) : null}
      <div className="flex flex-col gap-1.5">
        <Label htmlFor="project-description">Description</Label>
        <p className="m-0 text-xs text-muted-foreground">
          What this project is.
        </p>
        <ExpandableTextarea
          id="project-description"
          title="Project description"
          rows={3}
          maxLength={DESCRIPTION_MAX}
          value={texts.description}
          onChange={(description) => edit({ description })}
        />
      </div>
      <div className="flex flex-col gap-1.5">
        <Label htmlFor="project-instructions">Instructions</Label>
        <p className="m-0 text-xs text-muted-foreground">
          Every chat and team started in this project&rsquo;s folder, on one of
          its cards, or bound to it by a run configuration or the composer,
          receives these after your own custom instructions.
        </p>
        <ExpandableTextarea
          id="project-instructions"
          title="Project instructions"
          maxLength={INSTRUCTIONS_MAX}
          value={texts.instructions}
          onChange={(instructions) => edit({ instructions })}
        />
      </div>
      <p className="m-0 text-xs text-muted-foreground">
        A chat keeps what it started with.
      </p>
    </div>
  );
}
