import { useEffect, useRef, useState } from 'react';

import type {
  InstructionBlockSize,
  ProjectDto,
  ProjectInstructionBlock,
} from '../autogenerated';
import { ErrorBanner } from '../components/error-banner';
import { ExpandableTextarea } from '../components/expandable-textarea';
import {
  InstructionBlockCard,
  InstructionBlockList,
} from '../components/instruction-blocks';
import { Button } from '../components/ui/button';
import { Label } from '../components/ui/label';
import { useDebouncedPersist } from '../components/use-debounced-persist';
import { useLatestCallback } from '../components/use-latest-callback';
import {
  type DaemonApis,
  daemonErrorCode,
  daemonErrorStatus,
  describeDaemonError,
} from '../daemon-api';
import {
  MAX_PROJECT_INSTRUCTION_BLOCKS,
  newProjectBlock,
  projectBlockIssues,
} from './project-instruction-blocks';

// TWIN: PROJECT_DESCRIPTION_MAX in apps/daemon/src/v1/projects/projects.types.ts.
const DESCRIPTION_MAX = 2000;

interface Texts {
  description: string;
  blocks: ProjectInstructionBlock[];
}

const blankToNull = (text: string): string | null => text.trim() || null;

const textsOf = (project: ProjectDto): Texts => ({
  description: project.description ?? '',
  blocks: project.instructionBlocks,
});

const sameBlocks = (
  a: readonly ProjectInstructionBlock[],
  b: readonly ProjectInstructionBlock[],
): boolean => JSON.stringify(a) === JSON.stringify(b);

const sameTexts = (a: Texts, b: Texts): boolean =>
  a.description === b.description && sameBlocks(a.blocks, b.blocks);

function isDrift(err: unknown): boolean {
  return (
    daemonErrorStatus(err) === 409 &&
    daemonErrorCode(err) === 'PROJECT_INSTRUCTIONS_DRIFT'
  );
}

/**
 * A project's description and instruction blocks, saved as they are typed.
 * Every write quotes the revision the text was read or last saved at, so a
 * change made elsewhere in the meantime is refused rather than overwritten, and
 * nothing is written while a block holds something the daemon would refuse.
 * Key it by project: leaving it flushes the pending write to the project it
 * was typed for.
 */
export function ProjectInstructionsForm({
  project,
  api,
  blockSizes = null,
  flushRef,
  onSaved,
  onError,
}: {
  /** The daemon's latest copy, adopted whenever no edit is waiting on it. */
  project: ProjectDto;
  api: DaemonApis['projects'] | null;
  /** Each saved block's measured size, by block id; null before a measurement lands. */
  blockSizes?: ReadonlyMap<string, InstructionBlockSize> | null;
  /** Set to a write of whatever is typed and not yet saved, for the page's chat to run before it sends. */
  flushRef?: React.RefObject<(() => Promise<unknown>) | null>;
  onSaved: () => void;
  onError: (message: string) => void;
}): React.JSX.Element {
  const [texts, setTexts] = useState<Texts>(() => textsOf(project));
  const [drift, setDrift] = useState(false);
  const textsRef = useRef(texts);
  textsRef.current = texts;
  const savedRef = useRef<Texts>(textsOf(project));
  const revisionRef = useRef(project.instructionsRevision);
  const driftRef = useRef(false);
  const writes = useRef<Promise<unknown>>(Promise.resolve());

  const markDrift = (next: boolean): void => {
    driftRef.current = next;
    setDrift(next);
  };

  const write = useLatestCallback(
    (value: Texts): Promise<void> => {
      const projectId = project.id;
      const run = writes.current.then(async () => {
        if (
          api === null ||
          driftRef.current ||
          projectBlockIssues(value.blocks).size > 0 ||
          sameTexts(value, savedRef.current)
        ) {
          return;
        }
        try {
          const saved = await api.updateProject({
            projectId,
            updateProjectDto: {
              description: blankToNull(value.description),
              instructionBlocks: value.blocks,
              expectedInstructionsRevision: revisionRef.current,
            },
          });
          revisionRef.current = saved.instructionsRevision;
          savedRef.current = value;
          onSaved();
        } catch (err: unknown) {
          if (isDrift(err)) {
            markDrift(true);
            return;
          }
          onError(describeDaemonError(err));
          throw err;
        }
      });
      writes.current = run.catch(() => undefined);
      return run;
    },
    [api, project.id, onSaved, onError],
  );
  const persist = useDebouncedPersist(write, () => !driftRef.current);
  useEffect(() => {
    if (flushRef === undefined) {
      return undefined;
    }
    flushRef.current = async () => {
      await persist.flush().catch(() => undefined);
      await writes.current;
    };
    return () => {
      flushRef.current = null;
    };
  }, [flushRef, persist]);

  const edit = (patch: Partial<Texts>): void => {
    const next = { ...textsRef.current, ...patch };
    setTexts(next);
    persist.schedule(next);
  };

  const editBlocks = (blocks: ProjectInstructionBlock[]): void =>
    edit({ blocks });
  const editBlock = (
    blockId: string,
    patch: Partial<Omit<ProjectInstructionBlock, 'id'>>,
  ): void =>
    editBlocks(
      textsRef.current.blocks.map((block) =>
        block.id === blockId ? { ...block, ...patch } : block,
      ),
    );
  const issues = projectBlockIssues(texts.blocks);

  const adopt = useLatestCallback((server: Texts, revision: number): void => {
    revisionRef.current = revision;
    savedRef.current = server;
    setTexts(server);
    if (persist.dirtyRef.current) {
      persist.schedule(server);
    }
  }, []);

  useEffect(() => {
    if (project.instructionsRevision <= revisionRef.current) {
      return;
    }
    const local = textsRef.current;
    const saved = savedRef.current;
    const server = textsOf(project);
    const descriptionClean = local.description === saved.description;
    const blocksClean = sameBlocks(local.blocks, saved.blocks);
    if (descriptionClean && blocksClean) {
      adopt(server, project.instructionsRevision);
      return;
    }
    savedRef.current = {
      description: descriptionClean ? server.description : saved.description,
      blocks: blocksClean ? server.blocks : saved.blocks,
    };
    setTexts({
      description: descriptionClean ? server.description : local.description,
      blocks: blocksClean ? server.blocks : local.blocks,
    });
  }, [project, adopt]);

  const reload = useLatestCallback(async (): Promise<void> => {
    if (api === null) {
      return;
    }
    try {
      const fresh = await api.readProject({ projectId: project.id });
      adopt(textsOf(fresh), fresh.instructionsRevision);
      markDrift(false);
    } catch (err: unknown) {
      onError(describeDaemonError(err));
    }
  }, [api, project.id, onError]);

  return (
    <div className="flex flex-col gap-3">
      {drift ? (
        <ErrorBanner
          tone="warning"
          message="Changed elsewhere — reload to see the latest"
          action={
            <Button
              type="button"
              size="sm"
              variant="outline"
              onClick={() => void reload()}>
              Reload
            </Button>
          }
          onDismiss={() => markDrift(false)}
        />
      ) : null}
      <div className="flex flex-col gap-1.5">
        <Label htmlFor="project-description">Description</Label>
        <p className="m-0 text-xs text-muted-foreground">
          What this project is.
        </p>
        <ExpandableTextarea
          id="project-description"
          title="Project description"
          rows={3}
          maxLength={DESCRIPTION_MAX}
          value={texts.description}
          onChange={(description) => edit({ description })}
        />
      </div>
      <div className="flex flex-col gap-1.5">
        <Label>Instructions</Label>
        <p className="m-0 text-xs text-muted-foreground">
          Every chat and team started in this project&rsquo;s folder, on one of
          its cards, or bound to it by a run configuration or the composer,
          receives these blocks&rsquo; text in order, after your own custom
          instructions. Titles are for you; they are not sent.
        </p>
        <InstructionBlockList
          empty={texts.blocks.length === 0}
          emptyLabel="No project instructions yet."
          onAdd={() => {
            if (texts.blocks.length < MAX_PROJECT_INSTRUCTION_BLOCKS) {
              editBlocks([...texts.blocks, newProjectBlock()]);
            }
          }}>
          {texts.blocks.map((block) => {
            const size = blockSizes?.get(block.id);
            return (
              <InstructionBlockCard
                key={block.id}
                id={block.id}
                title={block.title}
                text={block.text}
                issues={issues.get(block.id) ?? []}
                size={size}
                sizeTitle={
                  size === undefined
                    ? undefined
                    : `${size.chars.toLocaleString('en-US')} characters, carried by every run in this project`
                }
                onTitleChange={(title) => editBlock(block.id, { title })}
                onTextChange={(text) => editBlock(block.id, { text })}
                onRemove={() =>
                  editBlocks(
                    texts.blocks.filter((entry) => entry.id !== block.id),
                  )
                }
              />
            );
          })}
        </InstructionBlockList>
      </div>
      <p className="m-0 text-xs text-muted-foreground">
        A chat keeps what it started with.
      </p>
    </div>
  );
}
