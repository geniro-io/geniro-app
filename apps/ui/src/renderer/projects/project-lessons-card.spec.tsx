// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { LessonsMode } from '../../shared/contracts';
import type { ProjectDto, UpdateProjectDto } from '../autogenerated';
import { ProjectLessonsCard } from './project-lessons-card';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

function projectWith(lessons: 'on' | 'off' | null): ProjectDto {
  return { id: 'p1', name: 'Demo', lessons } as unknown as ProjectDto;
}

function render(
  lessons: 'on' | 'off' | null,
  appMode: LessonsMode | null,
  onUpdate: (patch: UpdateProjectDto) => void,
): void {
  act(() => {
    root.render(
      <ProjectLessonsCard
        project={projectWith(lessons)}
        appMode={appMode}
        onUpdate={onUpdate}
      />,
    );
  });
}

function option(label: string): HTMLButtonElement {
  const found = [
    ...container.querySelectorAll<HTMLButtonElement>(
      '[data-slot="segmented-control"] button',
    ),
  ].find((button) => button.textContent === label);
  if (found === undefined) {
    throw new Error(`no option ${label}`);
  }
  return found;
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('ProjectLessonsCard', () => {
  it('presses Inherit when the project has no choice of its own', () => {
    render(null, 'offer', () => undefined);

    expect(option('Inherit').getAttribute('aria-pressed')).toBe('true');
    expect(option('On').getAttribute('aria-pressed')).toBe('false');
  });

  it('presses the project’s own value when it has one', () => {
    render('off', 'offer', () => undefined);

    expect(option('Off').getAttribute('aria-pressed')).toBe('true');
    expect(option('Inherit').getAttribute('aria-pressed')).toBe('false');
  });

  it('saves On as the project’s lessons value', () => {
    const onUpdate = vi.fn();
    render(null, 'offer', onUpdate);

    act(() => option('On').click());

    expect(onUpdate).toHaveBeenCalledTimes(1);
    expect(onUpdate).toHaveBeenCalledWith({ lessons: 'on' });
  });

  it('saves Off as the project’s lessons value', () => {
    const onUpdate = vi.fn();
    render('on', 'offer', onUpdate);

    act(() => option('Off').click());

    expect(onUpdate).toHaveBeenCalledWith({ lessons: 'off' });
  });

  it('saves Inherit as null, so the project follows the app again', () => {
    const onUpdate = vi.fn();
    render('on', 'offer', onUpdate);

    act(() => option('Inherit').click());

    expect(onUpdate).toHaveBeenCalledWith({ lessons: null });
  });

  it('says what inherit resolves to from the app setting while it is On', () => {
    render(null, 'offer', () => undefined);

    expect(container.textContent).toContain('Inherit (On — app setting)');
  });

  it('says why the choice is locked, in place of the inherit line, while the app setting is Off', () => {
    render(null, 'off', () => undefined);

    expect(container.textContent).not.toContain('Inherit (Off — app setting)');
    expect(container.textContent).toContain(
      'Off in Settings → Memory — turn it on there first',
    );
  });

  it('locks the choice and saves nothing while the app setting is Off', () => {
    const onUpdate = vi.fn();
    render('on', 'off', onUpdate);

    expect(option('Off').disabled).toBe(true);
    act(() => option('Off').click());
    expect(onUpdate).not.toHaveBeenCalled();
    expect(container.textContent).toContain(
      'Off in Settings → Memory — turn it on there first',
    );
  });
});
