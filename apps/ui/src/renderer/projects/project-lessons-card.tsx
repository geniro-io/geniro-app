import { Lightbulb } from 'lucide-react';

import type { LessonsMode } from '../../shared/contracts';
import type { ProjectDto, UpdateProjectDto } from '../autogenerated';
import {
  LESSONS_APP_OFF_REASON,
  type LessonsChoice,
  LessonsOverrideControl,
} from '../components/lessons-override-control';
import { ProjectSection } from './project-section';

function inheritedLabel(appMode: LessonsMode | null): string {
  if (appMode === null) {
    return 'Inherit (app setting)';
  }
  return appMode === 'offer'
    ? 'Inherit (On — app setting)'
    : 'Inherit (Off — app setting)';
}

export function ProjectLessonsCard({
  project,
  appMode,
  onUpdate,
}: {
  project: ProjectDto;
  /** The app's lessons mode from Settings; null until it is read. */
  appMode: LessonsMode | null;
  onUpdate: (patch: UpdateProjectDto) => void;
}): React.JSX.Element {
  const off = appMode === 'off';
  const choice: LessonsChoice = project.lessons ?? 'inherit';
  return (
    <ProjectSection
      slot="project-lessons"
      icon={<Lightbulb />}
      title="Lessons from threads"
      hint="Whether this project's threads are offered a reflection on what went wrong in them.">
      <div className="-mt-1 -mb-2 flex flex-col">
        <LessonsOverrideControl
          value={choice}
          onChange={(next) =>
            onUpdate({ lessons: next === 'inherit' ? null : next })
          }
          inheritedLabel={inheritedLabel(appMode)}
          disabled={off}
          disabledReason={off ? LESSONS_APP_OFF_REASON : undefined}
        />
      </div>
    </ProjectSection>
  );
}
