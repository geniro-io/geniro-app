import { Plus } from 'lucide-react';
import { useState } from 'react';

import type { RunConfig } from '../../shared/contracts';
import type { ProjectDto } from '../autogenerated';
import {
  blankRunConfigDraft,
  type RunConfigDraft,
  runConfigRefusal,
  upsertRunConfig,
} from '../chats/run-config';
import { RunConfigEditor, RunConfigSummary } from '../chats/run-config-picker';
import { EmptyState } from '../components/empty-state';
import { ErrorText } from '../components/error-text';
import { SettingsList, SettingsPanel } from '../components/settings-panel';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import type { DaemonApis } from '../daemon-api';
import type { RunConfigSources } from './use-run-config-sources';

interface Editing {
  id: string | null;
  draft: RunConfigDraft;
}

/** The saved run configurations bound to one project, edited and unlinked in place. */
export function ProjectRunConfigs({
  project,
  projects,
  agentsApi,
  sources,
  onSaved,
  onError,
}: {
  project: ProjectDto;
  projects: readonly ProjectDto[];
  agentsApi: DaemonApis['agents'] | null;
  sources: RunConfigSources;
  onSaved: () => void;
  onError: (message: string) => void;
}): React.JSX.Element {
  const [editing, setEditing] = useState<Editing | null>(null);
  const [refusal, setRefusal] = useState<string | null>(null);
  const linked = sources.runConfigs.filter(
    (config) => config.projectId === project.id,
  );

  const write = (
    edit: (current: readonly RunConfig[]) => RunConfig[],
  ): void => {
    sources.writeRunConfigs(edit).then(onSaved, (err: unknown) => {
      onError(String(err));
    });
  };

  const open = (next: Editing): void => {
    setRefusal(null);
    setEditing(next);
  };

  const commit = (): void => {
    if (editing === null) {
      return;
    }
    const why = runConfigRefusal(
      editing.draft,
      editing.id === null,
      sources.runConfigs.length,
    );
    if (why !== null) {
      setRefusal(why);
      return;
    }
    const { id, draft } = editing;
    write((current) => upsertRunConfig(current, draft, id));
    setEditing(null);
  };

  return (
    <section className="flex flex-col gap-3">
      <div className="flex items-center justify-between gap-3">
        <h2 className="text-lg font-medium">Run configurations</h2>
        <Button
          type="button"
          variant="outline"
          size="sm"
          onClick={() =>
            open({
              id: null,
              draft: blankRunConfigDraft({
                cwd: project.folder,
                projectId: project.id,
              }),
            })
          }>
          <Plus className="size-4" aria-hidden />
          New configuration
        </Button>
      </div>
      {linked.length === 0 ? (
        <SettingsPanel>
          <EmptyState className="py-6">
            No run configurations linked. Pick this project in a
            configuration&rsquo;s Project field, or create one here.
          </EmptyState>
        </SettingsPanel>
      ) : (
        <SettingsList
          className="overflow-hidden"
          aria-label="Run configurations">
          {linked.map((config) => (
            <li
              key={config.id}
              className="flex items-center gap-1 py-2 pr-2 pl-4">
              <div className="flex min-w-0 flex-1 flex-col gap-0.5">
                <span className="truncate text-sm text-foreground">
                  {config.name}
                </span>
                <RunConfigSummary config={config} projectName={null} />
              </div>
              <Button
                type="button"
                variant="ghost"
                size="sm"
                className="shrink-0"
                aria-label={`Edit ${config.name}`}
                onClick={() => {
                  const { id, ...draft } = config;
                  open({ id, draft });
                }}>
                Edit
              </Button>
              <Button
                type="button"
                variant="ghost"
                size="sm"
                className="shrink-0"
                aria-label={`Unlink ${config.name}`}
                title="Keep the configuration, bound to no project"
                onClick={() =>
                  write((current) =>
                    current.map((entry) =>
                      entry.id === config.id
                        ? { ...entry, projectId: null }
                        : entry,
                    ),
                  )
                }>
                Unlink
              </Button>
            </li>
          ))}
        </SettingsList>
      )}
      <Dialog
        open={editing !== null}
        onClose={() => setEditing(null)}
        title={
          editing?.id === null ? 'New configuration' : 'Edit configuration'
        }
        className="w-[min(48rem,calc(100vw-3rem))] max-w-none">
        {editing === null ? null : (
          <div className="flex flex-col gap-3">
            {refusal ? <ErrorText>{refusal}</ErrorText> : null}
            <RunConfigEditor
              draft={editing.draft}
              isNew={editing.id === null}
              open
              agentsApi={agentsApi}
              teams={sources.teams}
              projects={projects}
              cliDetections={sources.cliDetections}
              recentFolders={sources.recentFolders}
              recentConfigDirsFor={sources.recentConfigDirsFor}
              configProfilesFor={sources.configProfilesFor}
              approvalCapabilityFor={sources.approvalCapabilityFor}
              configDirReasonFor={sources.configDirReasonFor}
              onChange={(draft) => setEditing({ id: editing.id, draft })}
              onCancel={() => setEditing(null)}
              onCommit={commit}
            />
          </div>
        )}
      </Dialog>
    </section>
  );
}
