import { Pencil, Plus, SlidersHorizontal, Unlink } from 'lucide-react';
import { useState } from 'react';

import type { RunConfig } from '../../shared/contracts';
import type { ProjectDto } from '../autogenerated';
import {
  blankRunConfigDraft,
  type RunConfigDraft,
  runConfigRefusal,
  upsertRunConfig,
} from '../chats/run-config';
import { RunConfigEditor, RunConfigSummary } from '../chats/run-config-picker';
import { ErrorText } from '../components/error-text';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import type { DaemonApis } from '../daemon-api';
import { ProjectSection } from './project-section';
import type { RunConfigSources } from './use-run-config-sources';

interface Editing {
  id: string | null;
  draft: RunConfigDraft;
}

/** The saved run configurations bound to one project, edited and unlinked in place. */
export function ProjectRunConfigs({
  project,
  projects,
  agentsApi,
  sources,
  onSaved,
  onError,
}: {
  project: ProjectDto;
  projects: readonly ProjectDto[];
  agentsApi: DaemonApis['agents'] | null;
  sources: RunConfigSources;
  onSaved: () => void;
  onError: (message: string) => void;
}): React.JSX.Element {
  const [editing, setEditing] = useState<Editing | null>(null);
  const [refusal, setRefusal] = useState<string | null>(null);
  const linked = sources.runConfigs.filter(
    (config) => config.projectId === project.id,
  );

  const write = (
    edit: (current: readonly RunConfig[]) => RunConfig[],
  ): void => {
    sources.writeRunConfigs(edit).then(onSaved, (err: unknown) => {
      onError(String(err));
    });
  };

  const open = (next: Editing): void => {
    setRefusal(null);
    setEditing(next);
  };

  const commit = (): void => {
    if (editing === null) {
      return;
    }
    const why = runConfigRefusal(
      editing.draft,
      editing.id === null,
      sources.runConfigs.length,
    );
    if (why !== null) {
      setRefusal(why);
      return;
    }
    const { id, draft } = editing;
    write((current) => upsertRunConfig(current, draft, id));
    setEditing(null);
  };

  return (
    <ProjectSection
      slot="project-run-configs"
      icon={<SlidersHorizontal />}
      title="Run configurations"
      hint="Saved setups whose runs belong to this project."
      action={
        <Button
          type="button"
          variant="outline"
          size="sm"
          className="shrink-0 rounded-control"
          aria-label="New configuration"
          title="New configuration"
          onClick={() =>
            open({
              id: null,
              draft: blankRunConfigDraft({
                cwd: project.folder,
                projectId: project.id,
              }),
            })
          }>
          <Plus className="size-4" aria-hidden />
          New
        </Button>
      }>
      {linked.length === 0 ? (
        <p className="rounded-control border border-dashed border-border px-3 py-4 text-center text-sm text-muted-foreground">
          None linked yet. Pick this project in a configuration&rsquo;s Project
          field, or create one here.
        </p>
      ) : (
        <ul aria-label="Run configurations" className="flex flex-col gap-2">
          {linked.map((config) => (
            <li
              key={config.id}
              data-slot="project-run-config"
              className="flex items-start gap-1 rounded-control bg-muted/50 py-2 pr-1 pl-3 ring-1 ring-border/60">
              <div className="flex min-w-0 flex-1 flex-col gap-0.5 py-0.5">
                <span className="truncate text-sm font-medium text-foreground">
                  {config.name}
                </span>
                <RunConfigSummary config={config} projectName={null} />
              </div>
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-7 shrink-0 rounded-control text-muted-foreground"
                aria-label={`Edit ${config.name}`}
                title="Edit"
                onClick={() => {
                  const { id, ...draft } = config;
                  open({ id, draft });
                }}>
                <Pencil className="size-3.5" aria-hidden />
              </Button>
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-7 shrink-0 rounded-control text-muted-foreground"
                aria-label={`Unlink ${config.name}`}
                title="Unlink — keep the configuration, bound to no project"
                onClick={() =>
                  write((current) =>
                    current.map((entry) =>
                      entry.id === config.id
                        ? { ...entry, projectId: null }
                        : entry,
                    ),
                  )
                }>
                <Unlink className="size-3.5" aria-hidden />
              </Button>
            </li>
          ))}
        </ul>
      )}
      <Dialog
        open={editing !== null}
        onClose={() => setEditing(null)}
        title={
          editing?.id === null ? 'New configuration' : 'Edit configuration'
        }
        className="w-[min(48rem,calc(100vw-3rem))] max-w-none">
        {editing === null ? null : (
          <div className="flex flex-col gap-3">
            {refusal ? <ErrorText>{refusal}</ErrorText> : null}
            <RunConfigEditor
              draft={editing.draft}
              isNew={editing.id === null}
              open
              agentsApi={agentsApi}
              teams={sources.teams}
              projects={projects}
              cliDetections={sources.cliDetections}
              recentFolders={sources.recentFolders}
              recentConfigDirsFor={sources.recentConfigDirsFor}
              configProfilesFor={sources.configProfilesFor}
              approvalCapabilityFor={sources.approvalCapabilityFor}
              configDirReasonFor={sources.configDirReasonFor}
              onChange={(draft) => setEditing({ id: editing.id, draft })}
              onCancel={() => setEditing(null)}
              onCommit={commit}
            />
          </div>
        )}
      </Dialog>
    </ProjectSection>
  );
}
