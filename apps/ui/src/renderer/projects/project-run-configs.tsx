import { SlidersHorizontal } from 'lucide-react';

import type { RunConfig } from '../../shared/contracts';
import type { ProjectDto } from '../autogenerated';
import {
  blankRunConfigDraft,
  type RunConfigDraft,
  upsertRunConfig,
  withSubsetOrder,
} from '../chats/run-config';
import { RunConfigPicker } from '../chats/run-config-picker';
import type { DaemonApis } from '../daemon-api';
import { ProjectSection } from './project-section';
import type { RunConfigSources } from './use-run-config-sources';

/** The project's own run configurations: created, edited, ordered and deleted here. */
export function ProjectRunConfigs({
  project,
  projects,
  agentsApi,
  sources,
  onSaved,
  onError,
}: {
  project: ProjectDto;
  projects: readonly ProjectDto[];
  agentsApi: DaemonApis['agents'] | null;
  sources: RunConfigSources;
  onSaved: () => void;
  onError: (message: string) => void;
}): React.JSX.Element {
  const own = sources.runConfigs.filter(
    (config) => config.projectId === project.id,
  );

  const write = (
    edit: (current: readonly RunConfig[]) => RunConfig[],
  ): void => {
    sources.writeRunConfigs(edit).then(onSaved, (err: unknown) => {
      onError(String(err));
    });
  };

  return (
    <ProjectSection
      slot="project-run-configs"
      icon={<SlidersHorizontal />}
      title="Run configurations"
      hint="Saved new-chat setups of this project — start one from the + above the chat list.">
      <RunConfigPicker
        asDialog={false}
        open
        configs={own}
        totalCount={sources.runConfigs.length}
        showProject={false}
        emptyNote="A configuration names the folder, branch, agent and its options a new chat of this project starts with."
        agentsApi={agentsApi}
        teams={sources.teams}
        projects={projects}
        cliDetections={sources.cliDetections}
        recentFolders={sources.recentFolders}
        recentConfigDirsFor={sources.recentConfigDirsFor}
        configProfilesFor={sources.configProfilesFor}
        approvalCapabilityFor={sources.approvalCapabilityFor}
        configDirReasonFor={sources.configDirReasonFor}
        captureCurrent={(name): RunConfigDraft =>
          blankRunConfigDraft({
            name,
            cwd: project.folder,
            projectId: project.id,
          })
        }
        onSave={(draft, id) =>
          write((current) => upsertRunConfig(current, draft, id))
        }
        onDelete={(id) =>
          write((current) => current.filter((config) => config.id !== id))
        }
        onReorder={(next) => write((current) => withSubsetOrder(current, next))}
      />
    </ProjectSection>
  );
}
