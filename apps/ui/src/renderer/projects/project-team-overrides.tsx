type MemberPatch = Partial<Omit<TeamMember, 'id'>>;

const NO_ISSUES = (): string[] => [];
const NO_MEMBERS: readonly TeamMember[] = [];

function orphanWords(orphan: string): string {
  if (orphan.startsWith('members.')) {
    return `Overrides for member “${orphan.slice('members.'.length)}”, who is no longer on the team, are ignored.`;
  }
  if (orphan.startsWith('stages.')) {
    return `An addendum for stage “${orphan.slice('stages.'.length)}”, which the team no longer has, is ignored.`;
  }
  return `${orphan} names a member the team no longer has.`;
}

/** A sub-heading inside the Team section, with an optional line under it. */
function Part({
  title,
  hint,
  action,
  children,
}: {
  title: string;
  hint?: string;
  action?: React.ReactNode;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <section aria-label={title} className="flex flex-col gap-3">
      <div className="flex flex-wrap items-end gap-x-3 gap-y-1">
        <div className="flex min-w-0 flex-1 flex-col gap-0.5">
          <h3 className="text-sm font-semibold">{title}</h3>
          {hint === undefined ? null : (
            <p className="m-0 text-sm text-muted-foreground">{hint}</p>
          )}
        </div>
        {action}
      </div>
      {children}
    </section>
  );
}

/**
 * The project's own copy of its default team: the team's members, blocks and
 * stages as this project runs them, each Model setting and pool overridable
 * here, plus the blocks, extra instructions and stage addenda only this
 * project adds. Nothing here writes the team itself — every edit autosaves to
 * the project's overlay of it. The member sheet and the chat dock are drawn
 * beside and under the page.
 */
export function ProjectTeamOverrides({
  projectId,
  projectName,
  slug,
  apis,
  handle,
  client,
  onOpenTeam,
}: {
  projectId: string;
  projectName: string;
  slug: string;
  apis: DaemonApis;
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  onOpenTeam: (slug: string) => void;
}): React.JSX.Element {
  const slots = useContext(ProjectPageSlotsContext);
  const narrow = useNarrowViewport();
  const { capabilities, loading: capabilitiesLoading } = useSharedCapabilities(
    apis.capabilities,
  );
  const profileSources = useMemberProfileSources(true);

  const [team, setTeam] = useState<Team | null>(null);
  const [teamError, setTeamError] = useState<string | null>(null);
  const readTeam = useLatestCallback(async (): Promise<void> => {
    try {
      const { team: loaded } = await apis.teams.getTeam({ slug });
      setTeam(loaded);
      setTeamError(null);
    } catch (err) {
      setTeamError(describeDaemonError(err));
    }
  }, [apis, slug]);
  useEffect(() => {
    setTeam(null);
    void readTeam();
  }, [slug, readTeam]);

  const [chatOpen, setChatOpen] = useState(false);
  const [chatMounted, setChatMounted] = useState(false);
  const [chatWorking, setChatWorking] = useState(false);
  const overlayState = useTeamOverlay(
    apis.teams,
    slug,
    projectId,
    !chatWorking,
  );
  const overlay = overlayState.overlay;
  // Leaving the page (another project, another screen, a new default team)
  // unmounts this section: what is typed but not yet autosaved goes out first.
  const flushOverlay = useRef(overlayState.flush);
  flushOverlay.current = overlayState.flush;
  useEffect(
    () => () => {
      void flushOverlay.current();
    },
    [],
  );
  const health = useTeamHealth(apis, slug, { probe: false, projectId });

  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [openedOverrides, setOpenedOverrides] = useState<ReadonlySet<string>>(
    () => new Set(),
  );
  const [addendaOpen, setAddendaOpen] = useState(false);

  const members = team?.members ?? NO_MEMBERS;
  const agentLabelOf = (agent: string): string =>
    capabilities?.agents.find((entry) => entry.agent === agent)?.displayName ??
    agent;
  const selected =
    selectedId === null
      ? null
      : (members.find((member) => member.id === selectedId) ?? null);
  const shown =
    selected === null || overlay === null
      ? selected
      : effectiveMemberOf(selected, overlay);

  const instructionSizes = useInstructionSizes(
    apis.teams,
    slug,
    team === null ? '' : teamSnapshot(team),
    team !== null && overlay !== null,
    overlay === null
      ? null
      : { projectId, overlaySnapshot: JSON.stringify(overlay) },
  );

  const patchModel = useLatestCallback(
    (patch: MemberPatch): void => {
      if (selected === null) {
        return;
      }
      const settings = Object.fromEntries(
        Object.entries(patch).filter(
          ([field]) =>
            field === 'agent' ||
            (OVERLAY_MODEL_FIELDS as readonly string[]).includes(field),
        ),
      ) as Parameters<typeof withMemberSettings>[2];
      overlayState.edit((current) =>
        withMemberSettings(current, selected.id, settings),
      );
    },
    [selected, overlayState],
  );

  const rowScope = (
    fields: OverlaySettingsField[],
    teamValue: string,
  ): RowScope => {
    const memberId = selected?.id ?? '';
    const key = (field: OverlaySettingsField): string => `${memberId}:${field}`;
    return {
      projectName,
      overridden: fields.some(
        (field) =>
          (overlay !== null && isOverridden(overlay, memberId, field)) ||
          openedOverrides.has(key(field)),
      ),
      teamValue,
      onOverride: () => {
        if (selected === null) {
          return;
        }
        overlayState.edit((current) =>
          overrideFields(current, selected, fields),
        );
        setOpenedOverrides(
          (previous) => new Set([...previous, ...fields.map(key)]),
        );
      },
      onReset: () => {
        overlayState.edit((current) => resetFields(current, memberId, fields));
        setOpenedOverrides(
          (previous) =>
            new Set(
              [...previous].filter((entry) =>
                fields.includes('agent')
                  ? !entry.startsWith(`${memberId}:`)
                  : !fields.some((field) => entry === key(field)),
              ),
            ),
        );
      },
    };
  };

  const browseConfigDir = useLatestCallback(async (): Promise<void> => {
    if (selected === null || shown === null) {
      return;
    }
    const { id } = selected;
    const chosen = await profileSources.browse(shown.agent);
    if (chosen !== null) {
      overlayState.edit((current) =>
        withMemberSettings(current, id, { configDir: chosen }),
      );
    }
  }, [selected, shown, profileSources, overlayState]);

  const configDirCapability = configDirCapabilityFrom(
    capabilities,
    capabilitiesLoading,
  );

  const problemsOf = (memberId: string) =>
    memberProblemsOf(
      memberId,
      health.health?.members.find((entry) => entry.memberId === memberId),
      [],
    );

  const beforeChatSend = useLatestCallback(
    (): Promise<boolean> => overlayState.flush(),
    [overlayState],
  );
  const afterChatTurn = useLatestCallback(async (): Promise<void> => {
    await Promise.all([readTeam(), overlayState.refresh()]);
    health.reload();
  }, [readTeam, overlayState, health]);

  const addBlock = (): void =>
    overlayState.edit((current) => {
      const blocks = current.instructionBlocks ?? [];
      return withOverlayBlocks(current, [
        ...blocks,
        { id: nextBlockId(blocks), title: '', text: '', audience: 'everyone' },
      ]);
    });
  const patchBlock = (
    blockId: string,
    patch: Partial<Omit<InstructionBlock, 'id'>>,
  ): void =>
    overlayState.edit((current) =>
      withOverlayBlocks(
        current,
        (current.instructionBlocks ?? []).map((block) =>
          block.id === blockId ? { ...block, ...patch } : block,
        ),
      ),
    );
  const removeBlock = (blockId: string): void =>
    overlayState.edit((current) =>
      withOverlayBlocks(
        current,
        (current.instructionBlocks ?? []).filter(
          (block) => block.id !== blockId,
        ),
      ),
    );

  const stages = team?.stages ?? [];
  const addenda = Object.values(overlay?.stages ?? {}).filter(
    (stage) => (stage.howToWorkAddendum ?? '').trim() !== '',
  ).length;
  const handlerId = team === null ? null : triggerMemberOf(team);

  const sheet =
    selected === null || shown === null || overlay === null ? null : (
      <MenuAnchorContext.Provider value="viewport">
        <MemberSheet
          key={selected.id}
          member={selected}
          subtitle={
            selected.id === handlerId
              ? `${agentLabelOf(shown.agent)} · handles the first message`
              : agentLabelOf(shown.agent)
          }
          issuesFor={NO_ISSUES}
          problems={problemsOf(selected.id).map((problem) => ({
            key: problem.key,
            message: problem.message,
            level: problem.level,
          }))}
          fullScreen={narrow}
          active
          modelGroup={
            <MemberModelGroup
              agentsApi={apis.agents}
              capabilities={capabilities}
              capabilitiesLoading={capabilitiesLoading}
              member={shown}
              teamMember={selected}
              scopeOf={rowScope}
              sources={profileSources}
              onBrowseConfigDir={() => void browseConfigDir()}
              onPatch={patchModel}
            />
          }
          toolsGroup={
            <p className="m-0 text-sm text-muted-foreground">
              A member’s MCP switches are the same in every project — change
              them on the team’s page.
            </p>
          }
          poolGroup={
            <ScopedGroup
              label="Fallback members"
              bare
              scope={{
                projectName,
                overridden: overlay.members?.[selected.id]?.pool !== undefined,
                teamValue: `${selected.pool?.length ?? 0} member${selected.pool?.length === 1 ? '' : 's'}`,
                onOverride: () =>
                  overlayState.edit((current) =>
                    withMemberPool(current, selected.id, shown.pool ?? []),
                  ),
                onReset: () =>
                  overlayState.edit((current) =>
                    withMemberPool(current, selected.id, undefined),
                  ),
              }}>
              <AgentPoolEditor
                key={selected.id}
                members={shown.pool ?? []}
                agents={capabilities?.agents ?? []}
                agentsApi={apis.agents}
                defaultAgent={shown.agent}
                configDirAvailable={(agent) =>
                  configDirCapability.unavailableReasonFor(agent) === null
                }
                approvals={capabilities?.approvals ?? []}
                nodeApproval={shown.approval}
                nodeAutoCompactPercent={shown.autoCompactPercent}
                recentConfigDirs={profileSources.recentConfigDirs}
                configProfiles={profileSources.configProfiles}
                pickFolder={() => window.geniro.pickProjectFolder()}
                onChange={(pool) =>
                  overlayState.edit((current) =>
                    withMemberPool(current, selected.id, pool ?? []),
                  )
                }
              />
            </ScopedGroup>
          }
          sizeLine={
            <div data-slot="member-instruction-size">
              <InstructionSizeCard
                size={instructionSizes.sizes?.get(selected.id) ?? null}
                loading={instructionSizes.loading}
                error={instructionSizes.error}
                blockName={(blockId) => {
                  const block = [
                    ...(team?.instructionBlocks ?? []),
                    ...(overlay.instructionBlocks ?? []).map((entry) => ({
                      ...entry,
                      id: `project:${projectId}:${entry.id}`,
                    })),
                  ].find((entry) => entry.id === blockId);
                  return block?.title.trim() || blockId;
                }}
              />
            </div>
          }
          performance={null}
          removeWarning={null}
          canRemove={false}
          place={{
            index: members.findIndex((member) => member.id === selected.id),
            of: members.length,
          }}
          uploadAvatar={() => Promise.reject(new Error('read-only here'))}
          project={{
            name: projectName,
            extraInstructions:
              overlay.members?.[selected.id]?.extraInstructions ?? '',
            onExtraInstructions: (text) =>
              overlayState.edit((current) =>
                withExtraInstructions(current, selected.id, text),
              ),
          }}
          onPatch={() => undefined}
          onMove={() => undefined}
          onRemove={() => undefined}
          onClose={() => setSelectedId(null)}
        />
      </MenuAnchorContext.Provider>
    );

  const dock =
    chatMounted && handle !== null && client !== null && team !== null ? (
      <TeamChatPanel
        key={`${slug}:${projectId}`}
        slug={slug}
        teamName={team.name}
        projectId={projectId}
        projectName={projectName}
        apis={apis}
        handle={handle}
        client={client}
        hidden={!chatOpen}
        onClose={() => setChatOpen(false)}
        onBeforeSend={beforeChatSend}
        onWorkingChange={setChatWorking}
        onTurnSettled={afterChatTurn}
      />
    ) : null;

  return (
    <ProjectSection
      slot="project-team"
      icon={<UsersRound />}
      title={team === null ? 'Team' : `Team · ${team.name}`}
      hint={`How this team works in ${projectName}. What you change here applies to ${projectName}’s runs only; the team itself stays as it is.`}
      action={
        <div className="flex shrink-0 flex-wrap items-center gap-1">
          {handle === null || client === null ? null : (
            <Button
              type="button"
              variant="outline"
              size="sm"
              className="rounded-control"
              aria-pressed={chatOpen}
              onClick={() => {
                setChatMounted(true);
                setChatOpen((open) => !open);
              }}>
              <MessagesSquare className="size-4" aria-hidden />
              Change with chat
            </Button>
          )}
          <Button
            type="button"
            variant="ghost"
            size="sm"
            className="rounded-control"
            onClick={() => {
              void overlayState.flush().then(() => onOpenTeam(slug));
            }}>
            Open team
          </Button>
        </div>
      }>
      {teamError === null ? null : (
        <NoteBox className="text-destructive">{teamError}</NoteBox>
      )}
      {overlayState.stale ? (
        <NoteBox className="flex flex-wrap items-center gap-2 text-warning">
          <span className="flex-1">
            Changed elsewhere — reload. Your edits here are kept until you do.
          </span>
          <Button
            type="button"
            variant="outline"
            size="sm"
            className="h-8 rounded-control"
            onClick={() => void overlayState.reload()}>
            Reload
          </Button>
        </NoteBox>
      ) : null}
      {overlayState.error === null ? null : (
        <NoteBox className="text-destructive">{overlayState.error}</NoteBox>
      )}
      {overlayState.orphans.map((orphan) => (
        <NoteBox
          key={orphan}
          data-slot="overlay-orphan"
          className="flex flex-wrap items-center gap-2 text-warning">
          <span className="flex-1">{orphanWords(orphan)}</span>
          {orphan.startsWith('members.') || orphan.startsWith('stages.') ? (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              className="h-7 rounded-control"
              onClick={() =>
                overlayState.edit((current) => withoutOrphan(current, orphan))
              }>
              Remove
            </Button>
          ) : null}
        </NoteBox>
      ))}

      {team === null || overlay === null ? (
        <p className="m-0 text-sm text-muted-foreground">
          {teamError === null ? 'Reading the team…' : null}
        </p>
      ) : (
        <MenuAnchorContext.Provider value="viewport">
          <div className="flex flex-col gap-8">
            <Part
              title="Members"
              hint={`Open one to override its model, profile or fallback members, or to give it extra instructions for ${projectName}.`}>
              <ul className="grid grid-cols-1 gap-3 sm:grid-cols-2 xl:grid-cols-3">
                {members.map((member) => {
                  const setup = problemsOf(member.id);
                  return (
                    <MemberCard
                      key={member.id}
                      member={effectiveMemberOf(member, overlay)}
                      agentLabel={agentLabelOf(
                        effectiveMemberOf(member, overlay).agent,
                      )}
                      health={memberStatusOf(
                        health.health?.members.find(
                          (entry) => entry.memberId === member.id,
                        ),
                        setup,
                      )}
                      problems={setup.map((problem) => ({
                        key: problem.key,
                        message: problem.message,
                        level: problem.level,
                      }))}
                      stageTitles={stages
                        .filter((stage) =>
                          stage.responsible?.includes(member.id),
                        )
                        .map(stageTitle)}
                      handlesFirstMessage={member.id === handlerId}
                      selected={selectedId === member.id}
                      overlayBadges={memberOverlayBadges(overlay, member.id)}
                      onOpen={() => setSelectedId(member.id)}
                    />
                  );
                })}
              </ul>
            </Part>

            <Part
              title="Team instructions"
              hint={`The team’s own blocks, then the ones only ${projectName}’s runs of it carry.`}>
              <ProjectScopeInstructions
                projectName={projectName}
                sharedBlocks={team.instructionBlocks}
                overlayBlocks={overlay.instructionBlocks ?? []}
                members={members}
                overlaySizeOf={(blockId) =>
                  instructionSizes.blocks?.get(
                    `project:${projectId}:${blockId}`,
                  )
                }
                onAdd={addBlock}
                onChange={patchBlock}
                onRemove={removeBlock}
              />
            </Part>

            {stages.length === 0 ? null : (
              <Part
                title="Stages"
                hint={`Text added to a stage’s how-to-work in ${projectName}’s runs.`}
                action={
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    className="h-8 rounded-control"
                    onClick={() => setAddendaOpen(true)}>
                    Edit stage addenda
                  </Button>
                }>
                <p
                  data-slot="project-stage-addenda"
                  className="m-0 text-sm text-muted-foreground">
                  {addenda === 0
                    ? `No stage has an addendum for ${projectName}.`
                    : `${addenda} of ${stages.length} stage${stages.length === 1 ? '' : 's'} carry an addendum for ${projectName}.`}
                </p>
              </Part>
            )}
          </div>
        </MenuAnchorContext.Provider>
      )}

      {overlay === null ? null : (
        <StageAddendaDialog
          open={addendaOpen}
          projectName={projectName}
          stages={stages}
          overlay={overlay}
          onClose={() => setAddendaOpen(false)}
          onSave={(next) => {
            overlayState.edit((current) =>
              Object.entries(next).reduce(
                (doc, [stageId, text]) =>
                  withStageAddendum(doc, stageId, text.trim()),
                current,
              ),
            );
            setAddendaOpen(false);
          }}
        />
      )}
      {sheet === null || slots.sheet === null
        ? null
        : createPortal(sheet, slots.sheet)}
      {dock === null || slots.dock === null
        ? null
        : createPortal(dock, slots.dock)}
    </ProjectSection>
  );
}

/**
 * Overrides this project kept of teams it no longer defaults to: inactive
 * until it defaults to that team again, each removable.
 */
export function ProjectKeptOverlays({
  apis,
  projectId,
  projectName,
  defaultTeamSlug,
}: {
  apis: DaemonApis;
  projectId: string;
  projectName: string;
  defaultTeamSlug: string | null;
}): React.JSX.Element | null {
  const [overlays, setOverlays] = useState<ProjectTeamOverlay[]>([]);
  const [failed, setFailed] = useState(false);
  const read = useLatestCallback(async (): Promise<void> => {
    try {
      const listed = await apis.teams.listProjectTeamOverlays({ projectId });
      setOverlays(listed.overlays);
      setFailed(false);
    } catch {
      setOverlays([]);
      setFailed(true);
    }
  }, [apis, projectId]);
  useEffect(() => {
    void read();
  }, [defaultTeamSlug, read]);
  const kept = overlays.filter((entry) => !entry.active && entry.hasOverlay);
  if (failed) {
    return (
      <p
        data-slot="project-kept-overlays"
        className="m-0 text-sm text-muted-foreground">
        Could not read which teams {projectName} keeps overrides of.
      </p>
    );
  }
  if (kept.length === 0) {
    return null;
  }
  return (
    <div data-slot="project-kept-overlays" className="flex flex-col gap-2">
      {kept.map((entry) => (
        <NoteBox
          key={entry.slug}
          className="flex flex-wrap items-center gap-2 text-sm">
          <span className="min-w-0 flex-1">
            {projectName} keeps its overrides of{' '}
            <span className="font-medium text-foreground">
              {entry.teamName}
            </span>
            , unused while it defaults to {entry.defaultTeamName ?? 'an agent'}.
            They apply again if {entry.teamName} becomes its default.
          </span>
          <ConfirmActionButton
            variant="ghost"
            className="h-7 rounded-control"
            question={`Remove ${projectName}’s overrides of ${entry.teamName}?`}
            description="The overlay file is backed up, then removed."
            confirmLabel="Remove"
            busyLabel="Removing…"
            confirmVariant="destructive"
            onConfirm={async () => {
              await apis.teams.deleteTeamOverlay({
                slug: entry.slug,
                projectId,
              });
              await read();
            }}>
            Remove
          </ConfirmActionButton>
        </NoteBox>
      ))}
    </div>
  );
}
