import { FolderGit2, Plus } from 'lucide-react';

import type { ProjectDto } from '../autogenerated';
import type { TargetTeam } from '../chats/target-select';
import { EmptyState } from '../components/empty-state';
import { LibraryHeader } from '../components/library-header';
import { Button } from '../components/ui/button';
import { ProjectCard } from './project-card';
import type { ProjectQueueReading } from './use-project-queues';

export const LIST_UNREAD = 'The projects could not be read.';

/**
 * Every project as a gallery of cards under a header that creates one.
 * `projects` is null until the first read lands; `banner` carries any error.
 */
export function ProjectsLibrary({
  projects,
  banner = null,
  failed = false,
  teams,
  configCounts,
  queues,
  onOpen,
  onNew,
  footer = null,
}: {
  projects: readonly ProjectDto[] | null;
  banner?: React.ReactNode;
  /** The list could not be read: said in place of the loading line, since the banner can be dismissed. */
  failed?: boolean;
  teams: readonly TargetTeam[];
  /** Run configurations bound to each project, by project id. */
  configCounts: ReadonlyMap<string, number>;
  queues: ReadonlyMap<string, ProjectQueueReading>;
  onOpen: (projectId: string) => void;
  onNew: () => void;
  /** Drawn under the gallery once the list has been read. */
  footer?: React.ReactNode;
}): React.JSX.Element {
  const newProject = (
    <Button
      type="button"
      className="h-8 gap-2 rounded-control active:scale-[.97] motion-reduce:active:scale-100"
      onClick={onNew}>
      <Plus aria-hidden="true" className="shrink-0" /> New project
    </Button>
  );
  return (
    <div className="h-full min-h-0 overflow-y-auto">
      <div className="mx-auto flex max-w-[1080px] flex-col gap-8 px-4 py-8 sm:px-6">
        <LibraryHeader
          title="Projects"
          count={projects === null ? null : projects.length}
          subtitle="One folder, one board, one set of standing instructions."
          actions={newProject}
        />

        {banner}

        {projects === null ? (
          <p className="text-sm text-muted-foreground">
            {failed ? LIST_UNREAD : 'Loading projects…'}
          </p>
        ) : projects.length === 0 ? (
          <EmptyState
            icon={<FolderGit2 aria-hidden="true" />}
            actions={newProject}>
            No projects yet — a project binds a folder; its tasks become that
            folder&rsquo;s board, and its instructions go to every agent run in
            it
          </EmptyState>
        ) : (
          <ul
            aria-label="Projects"
            data-slot="project-library"
            className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
            {projects.map((project) => (
              <ProjectCard
                key={project.id}
                project={project}
                teams={teams}
                configCount={configCounts.get(project.id) ?? 0}
                queue={queues.get(project.id) ?? null}
                onOpen={() => onOpen(project.id)}
              />
            ))}
          </ul>
        )}
        {projects === null ? null : footer}
      </div>
    </div>
  );
}
