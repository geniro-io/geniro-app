const rows = (el: HTMLElement): HTMLLIElement[] => [
  ...el.querySelectorAll<HTMLLIElement>('ul[aria-label="Projects"] > li'),
];

/** Let the instructions' debounce run out and its write land. */
async function afterDebounce(): Promise<void> {
  await act(async () => {
    await vi.advanceTimersByTimeAsync(600);
  });
  await settle();
}

