import { useEffect } from 'react';

import type { ProjectDto } from '../autogenerated';

const READ_SLACK_MS = 1_000;
const MAX_TIMER_MS = 2 ** 31 - 1;

/**
 * Re-read the project list once the soonest usage-limit wait on it has lapsed:
 * the daemon just stops holding the project, and nothing announces it. Re-armed
 * on every answer, so a read landing just early schedules the next one.
 */
export function useAutopilotLimitLapse(
  projects: readonly ProjectDto[] | null,
  reread: () => void,
): void {
  useEffect(() => {
    const now = Date.now();
    const waits = (projects ?? []).flatMap((project) => {
      const until = project.autopilotLimitUntil;
      const left = until ? Date.parse(until) - now : Number.NaN;
      return left > 0 ? [left] : [];
    });
    if (waits.length === 0) {
      return;
    }
    const timer = setTimeout(
      reread,
      Math.min(Math.min(...waits) + READ_SLACK_MS, MAX_TIMER_MS),
    );
    return () => {
      clearTimeout(timer);
    };
  }, [projects, reread]);
}
