import { useEffect, useState } from 'react';

import type {
  AgentInstructionSize,
  InstructionBlockSize,
} from '../autogenerated';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import { currentRunSettings } from '../run-settings';

export interface ProjectInstructionSizesState {
  /** One measurement per CLI, from the last answer; null before one. */
  agents: readonly AgentInstructionSize[] | null;
  /** Each saved block's own size, by block id; null before an answer. */
  blocks: ReadonlyMap<string, InstructionBlockSize> | null;
  loading: boolean;
  error: string | null;
}

/**
 * What a run in the project carries before its prompt, per CLI, measured by
 * the daemon from the project as saved, the memory index a run there would
 * read, and the user's custom instructions and reply language as a run start
 * reads them. Measured again when `revision` moves (a saved edit of what the
 * project says) and when main announces a settings write.
 */
export function useProjectInstructionSizes(
  api: DaemonApis['projects'] | null,
  projectId: string,
  revision: string,
): ProjectInstructionSizesState {
  const [state, setState] = useState<ProjectInstructionSizesState>({
    agents: null,
    blocks: null,
    loading: false,
    error: null,
  });
  const [settingsWrites, setSettingsWrites] = useState(0);

  useEffect(
    () =>
      window.geniro.onSettingsChanged(() =>
        setSettingsWrites((count) => count + 1),
      ),
    [],
  );

  useEffect(() => {
    if (api === null) {
      return;
    }
    let stale = false;
    setState((prev) => ({ ...prev, loading: true }));
    void (async () => {
      try {
        const settings = await currentRunSettings();
        const answer = await api.measureProjectInstructionSizes({
          projectId,
          measureProjectInstructionSizesDto: {
            ...(settings.customInstructions
              ? { customInstructions: settings.customInstructions }
              : {}),
            ...(settings.replyLanguage
              ? { replyLanguage: settings.replyLanguage }
              : {}),
          },
        });
        if (!stale) {
          setState({
            agents: answer.agents,
            blocks: new Map(
              answer.blocks.map((block) => [block.blockId, block]),
            ),
            loading: false,
            error: null,
          });
        }
      } catch (err) {
        if (!stale) {
          setState((prev) => ({
            ...prev,
            loading: false,
            error: `Not measured: ${describeDaemonError(err)}`,
          }));
        }
      }
    })();
    return () => {
      stale = true;
    };
  }, [api, projectId, revision, settingsWrites]);

  return state;
}
