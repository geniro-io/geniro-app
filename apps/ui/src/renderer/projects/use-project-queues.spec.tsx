// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { type ProjectQueueDto, TaskStatus } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type {
  DaemonClient,
  ProjectsChangedEvent,
  TaskChangedEvent,
} from '../daemon-client';
import {
  type ProjectQueueReading,
  QUEUE_REREAD_MS,
  useProjectQueues,
} from './use-project-queues';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const queue = (
  projectId: string,
  over: Partial<ProjectQueueDto> = {},
): ProjectQueueDto => ({
  projectId,
  enabled: false,
  intakeStatus: TaskStatus.Todo,
  cap: 1,
  running: 0,
  waiting: 0,
  breakerOpen: false,
  failureStreak: 0,
  eligible: [],
  blocked: [],
  active: [],
  ...over,
});

let root: Root | null = null;
let container: HTMLDivElement | null = null;
let readProjectQueue: ReturnType<typeof vi.fn>;
let taskListeners: ((event: TaskChangedEvent) => void)[];
let projectListeners: ((event: ProjectsChangedEvent) => void)[];
let reconnectListeners: (() => void)[];
let held: ReadonlyMap<string, ProjectQueueReading>[];
let apis: DaemonApis;
let client: DaemonClient;

const makeApis = (): DaemonApis =>
  ({ projects: { readProjectQueue } }) as unknown as DaemonApis;

const makeClient = (): DaemonClient =>
  ({
    onTaskChanged: (listener: (event: TaskChangedEvent) => void) => {
      taskListeners.push(listener);
      return () => undefined;
    },
    onProjectsChanged: (listener: (event: ProjectsChangedEvent) => void) => {
      projectListeners.push(listener);
      return () => undefined;
    },
    onReconnect: (listener: () => void) => {
      reconnectListeners.push(listener);
      return () => undefined;
    },
  }) as unknown as DaemonClient;

function Figures({ ids }: { ids: string[] }): React.JSX.Element {
  const queues = useProjectQueues(apis, client, ids);
  held.push(queues);
  return (
    <p>
      {ids
        .map((id) => {
          const read = queues.get(id);
          return read === undefined
            ? `${id}:-`
            : `${id}:${read.running}/${read.waiting}`;
        })
        .join(' ')}
    </p>
  );
}

async function settle(): Promise<void> {
  await act(async () => {
    for (let tick = 0; tick < 10; tick += 1) {
      await Promise.resolve();
    }
  });
}

beforeEach(() => {
  vi.useFakeTimers();
  taskListeners = [];
  projectListeners = [];
  reconnectListeners = [];
  held = [];
  readProjectQueue = vi.fn(async ({ projectId }: { projectId: string }) =>
    projectId === 'p-gone'
      ? Promise.reject(new Error('gone'))
      : queue(projectId, { running: 1, waiting: 3 }),
  );
  apis = makeApis();
  client = makeClient();
});

afterEach(() => {
  act(() => root?.unmount());
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

const taskChanged = (projectId: string): TaskChangedEvent => ({
  taskId: 't1',
  projectId,
  status: TaskStatus.InProgress,
});

async function afterReread(): Promise<void> {
  await act(async () => {
    await vi.advanceTimersByTimeAsync(QUEUE_REREAD_MS);
  });
  await settle();
}

async function mount(ids: string[]): Promise<HTMLDivElement> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<Figures ids={ids} />);
  });
  await settle();
  return container;
}

describe('useProjectQueues', () => {
  it('reads each project’s queue and leaves out one that cannot be read', async () => {
    const el = await mount(['p-app', 'p-gone']);
    expect(el.textContent).toBe('p-app:1/3 p-gone:-');
  });

  it('reads again once after a burst of one project’s task changes, that project only, and not for a text edit', async () => {
    await mount(['p-app', 'p-docs']);
    readProjectQueue.mockClear();

    act(() => {
      for (const listener of taskListeners) {
        listener(taskChanged('p-app'));
        listener(taskChanged('p-app'));
      }
      for (const listener of projectListeners) {
        listener({ projectId: 'p-docs', textsOnly: true });
      }
    });
    await afterReread();
    expect(readProjectQueue.mock.calls).toEqual([[{ projectId: 'p-app' }]]);
  });

  it('reads a project again after a change to it that is not a text edit', async () => {
    await mount(['p-app', 'p-docs']);
    readProjectQueue.mockClear();

    act(() => {
      for (const listener of projectListeners) {
        listener({ projectId: 'p-docs', textsOnly: false });
      }
    });
    await afterReread();
    expect(readProjectQueue.mock.calls).toEqual([[{ projectId: 'p-docs' }]]);
  });

  it('keeps the newer figures when an older read lands after them', async () => {
    const answers: ((read: ProjectQueueDto) => void)[] = [];
    const el = await mount(['p-app']);
    readProjectQueue.mockImplementation(
      () =>
        new Promise<ProjectQueueDto>((resolve) => {
          answers.push(resolve);
        }),
    );

    act(() => {
      for (const listener of taskListeners) {
        listener(taskChanged('p-app'));
      }
    });
    await afterReread();
    act(() => {
      for (const listener of reconnectListeners) {
        listener();
      }
    });
    expect(answers).toHaveLength(2);

    await act(async () => {
      answers[1]!(queue('p-app', { running: 2, waiting: 0 }));
    });
    await settle();
    await act(async () => {
      answers[0]!(queue('p-app', { running: 0, waiting: 9 }));
    });
    await settle();

    expect(el.textContent).toBe('p-app:2/0');
  });

  it('keeps the same map when a read brings the same figures', async () => {
    await mount(['p-app']);
    const before = held.at(-1);

    act(() => {
      for (const listener of taskListeners) {
        listener(taskChanged('p-app'));
      }
    });
    await afterReread();

    expect(readProjectQueue).toHaveBeenCalledTimes(2);
    expect(before?.get('p-app')?.running).toBe(1);
    expect(held.at(-1)).toBe(before);
  });

  it('reads every project again at once after a reconnect', async () => {
    await mount(['p-app', 'p-docs']);
    readProjectQueue.mockClear();
    act(() => {
      for (const listener of reconnectListeners) {
        listener();
      }
    });
    await settle();
    expect(readProjectQueue.mock.calls).toEqual([
      [{ projectId: 'p-app' }],
      [{ projectId: 'p-docs' }],
    ]);
  });
});
