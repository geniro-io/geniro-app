import { useEffect, useRef, useState } from 'react';

import type { ProjectQueueDto } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

/** A burst of changes to one project is read once, this long after its last change. */
export const QUEUE_REREAD_MS = 400;

/**
 * The part of a queue read this hook keeps fresh: a read that changes none of
 * it keeps the previous object, so nothing else of the read may be relied on.
 */
export type ProjectQueueReading = Pick<
  ProjectQueueDto,
  'running' | 'waiting' | 'intakeStatus'
>;

const NO_QUEUES: ReadonlyMap<string, ProjectQueueReading> = new Map();

function readsTheSame(a: ProjectQueueReading, b: ProjectQueueReading): boolean {
  return (
    a.running === b.running &&
    a.waiting === b.waiting &&
    a.intakeStatus === b.intakeStatus
  );
}

/**
 * Each listed project's queue as the daemon counts it — tasks with a live run,
 * tasks waiting in its intake column — by project id. A project is read again
 * after its own task changes (the daemon announces a card whose own run starts
 * or settles, too) and after any change to it but a text edit; every project
 * after a reconnect. A queue that cannot be read is left out rather than shown
 * as zero.
 */
export function useProjectQueues(
  apis: DaemonApis | null,
  client: DaemonClient | null,
  projectIds: readonly string[],
): ReadonlyMap<string, ProjectQueueReading> {
  const [queues, setQueues] =
    useState<ReadonlyMap<string, ProjectQueueReading>>(NO_QUEUES);
  const generations = useRef(new Map<string, number>());
  const key = projectIds.join('\n');

  const read = useLatestCallback(
    (ids: readonly string[] | 'all'): void => {
      if (apis === null || key === '') {
        return;
      }
      const listed = key.split('\n');
      const wanted =
        ids === 'all' ? listed : ids.filter((id) => listed.includes(id));
      const marks = wanted.map((projectId) => {
        const mark = (generations.current.get(projectId) ?? 0) + 1;
        generations.current.set(projectId, mark);
        return { projectId, mark };
      });
      void Promise.all(
        marks.map(({ projectId }) =>
          apis.projects.readProjectQueue({ projectId }).catch(() => null),
        ),
      ).then((reads) => {
        setQueues((current) => {
          let next: Map<string, ProjectQueueReading> | null = null;
          const edit = (): Map<string, ProjectQueueReading> =>
            (next ??= new Map(current));
          marks.forEach(({ projectId, mark }, index) => {
            if (generations.current.get(projectId) !== mark) {
              return;
            }
            const fresh = reads[index] ?? null;
            const held = current.get(projectId);
            if (fresh === null) {
              if (held !== undefined) {
                edit().delete(projectId);
              }
            } else if (held === undefined || !readsTheSame(held, fresh)) {
              edit().set(projectId, fresh);
            }
          });
          return next ?? current;
        });
      });
    },
    [apis, key],
  );

  useEffect(() => {
    read('all');
  }, [read]);

  useEffect(() => {
    if (client === null) {
      return undefined;
    }
    const pending = new Set<string>();
    let timer: ReturnType<typeof setTimeout> | null = null;
    const soon = (projectId: string): void => {
      pending.add(projectId);
      if (timer !== null) {
        clearTimeout(timer);
      }
      timer = setTimeout(() => {
        timer = null;
        const ids = [...pending];
        pending.clear();
        read(ids);
      }, QUEUE_REREAD_MS);
    };
    const stops = [
      client.onTaskChanged((event) => soon(event.projectId)),
      client.onProjectsChanged((event) => {
        if (!event.textsOnly) {
          soon(event.projectId);
        }
      }),
      client.onReconnect(() => read('all')),
    ];
    return () => {
      if (timer !== null) {
        clearTimeout(timer);
      }
      for (const stop of stops) {
        stop();
      }
    };
  }, [client, read]);

  return queues;
}
