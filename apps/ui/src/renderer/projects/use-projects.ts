import { useEffect, useRef, useState } from 'react';

import type { ProjectDto } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient, ProjectsChangedEvent } from '../daemon-client';
import type { ProjectTargetFields } from './project-composer-target';
import { useAutopilotLimitLapse } from './use-autopilot-limit-lapse';

export interface ProjectsList {
  /** Null until the first answer. */
  projects: ProjectDto[] | null;
  error: string | null;
  reload: () => void;
}

/** What a picker needs of a project. */
export type ProjectRef = Pick<ProjectDto, 'id' | 'name' | 'folder'>;

/** A {@link ProjectRef} with the default target a new chat there starts from. */
export type ProjectTargetRef = ProjectRef & ProjectTargetFields;

/**
 * Every project as the daemon lists them, narrowed by `read`, read again on
 * every `projects_changed` and after a reconnect, which may have missed one.
 * A read `same` finds equal to the one held keeps the held value, so nothing
 * re-renders for it.
 */
function useProjectList<T>(
  apis: DaemonApis | null,
  client: DaemonClient | null,
  read: (list: ProjectDto[]) => T,
  same: (held: T, next: T) => boolean,
  ignores: (event: ProjectsChangedEvent) => boolean,
): { value: T | null; error: string | null; reload: () => void } {
  const [value, setValue] = useState<T | null>(null);
  const [error, setError] = useState<string | null>(null);
  const generation = useRef(0);

  const reload = useLatestCallback(() => {
    if (apis === null) {
      return;
    }
    const mine = ++generation.current;
    void apis.projects
      .listProjects()
      .then((list) => {
        if (mine === generation.current) {
          const next = read(list);
          setValue((held) => (held !== null && same(held, next) ? held : next));
          setError(null);
        }
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setError(describeDaemonError(err));
        }
      });
  }, [apis, read, same]);

  useEffect(() => {
    reload();
  }, [reload]);

  useEffect(
    () =>
      client?.onProjectsChanged((event) => {
        if (!ignores(event)) {
          reload();
        }
      }),
    [client, reload, ignores],
  );
  useEffect(() => client?.onReconnect(() => reload()), [client, reload]);

  return { value, error, reload };
}

const wholeList = (list: ProjectDto[]): ProjectDto[] => list;
const neverSame = (): boolean => false;
const noEvent = (): boolean => false;
const textEdit = (event: ProjectsChangedEvent): boolean => event.textsOnly;

/** Every project, as the daemon lists them — the list never folds or edits its copy. */
export function useProjects(
  apis: DaemonApis | null,
  client: DaemonClient | null,
): ProjectsList {
  const { value, error, reload } = useProjectList(
    apis,
    client,
    wholeList,
    neverSame,
    noEvent,
  );
  useAutopilotLimitLapse(value, reload);
  return { projects: value, error, reload };
}

const refsOf = (list: ProjectDto[]): ProjectTargetRef[] =>
  list.map(
    ({
      id,
      name,
      folder,
      agentKind,
      teamSlug,
      model,
      effort,
      contextWindow,
      modelParameters,
      approval,
      configDir,
    }) => ({
      id,
      name,
      folder,
      agentKind,
      teamSlug,
      model,
      effort,
      contextWindow,
      modelParameters,
      approval,
      configDir,
    }),
  );
const sameParameters = (
  held: Readonly<Record<string, string>>,
  next: Readonly<Record<string, string>>,
): boolean => {
  const keys = Object.keys(held);
  return (
    keys.length === Object.keys(next).length &&
    keys.every((key) => held[key] === next[key])
  );
};
const sameRefs = (
  held: readonly ProjectTargetRef[],
  next: readonly ProjectTargetRef[],
): boolean =>
  held.length === next.length &&
  held.every((ref, index) => {
    const other = next[index]!;
    return (
      ref.id === other.id &&
      ref.name === other.name &&
      ref.folder === other.folder &&
      ref.agentKind === other.agentKind &&
      ref.teamSlug === other.teamSlug &&
      ref.model === other.model &&
      ref.effort === other.effort &&
      ref.contextWindow === other.contextWindow &&
      ref.approval === other.approval &&
      ref.configDir === other.configDir &&
      sameParameters(ref.modelParameters, other.modelParameters)
    );
  });

/**
 * Each project's id, name, folder and default target, unchanged while those
 * are — so a screen that only picks a project neither re-reads nor re-renders
 * for an edit of a project's texts. Null until the first answer.
 */
export function useProjectRefs(
  apis: DaemonApis | null,
  client: DaemonClient | null,
): ProjectTargetRef[] | null {
  return useProjectList(apis, client, refsOf, sameRefs, textEdit).value;
}
