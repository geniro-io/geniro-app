import { useEffect, useRef, useState } from 'react';

import type { ProjectDto } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient, ProjectsChangedEvent } from '../daemon-client';

export interface ProjectsList {
  /** Null until the first answer. */
  projects: ProjectDto[] | null;
  error: string | null;
  reload: () => void;
}

/** What a picker needs of a project. */
export type ProjectRef = Pick<ProjectDto, 'id' | 'name' | 'folder'>;

/**
 * Every project as the daemon lists them, narrowed by `read`, read again on
 * every `projects_changed` and after a reconnect, which may have missed one.
 * A read `same` finds equal to the one held keeps the held value, so nothing
 * re-renders for it.
 */
function useProjectList<T>(
  apis: DaemonApis | null,
  client: DaemonClient | null,
  read: (list: ProjectDto[]) => T,
  same: (held: T, next: T) => boolean,
  ignores: (event: ProjectsChangedEvent) => boolean,
): { value: T | null; error: string | null; reload: () => void } {
  const [value, setValue] = useState<T | null>(null);
  const [error, setError] = useState<string | null>(null);
  const generation = useRef(0);

  const reload = useLatestCallback(() => {
    if (apis === null) {
      return;
    }
    const mine = ++generation.current;
    void apis.projects
      .listProjects()
      .then((list) => {
        if (mine === generation.current) {
          const next = read(list);
          setValue((held) => (held !== null && same(held, next) ? held : next));
          setError(null);
        }
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setError(describeDaemonError(err));
        }
      });
  }, [apis, read, same]);

  useEffect(() => {
    reload();
  }, [reload]);

  useEffect(
    () =>
      client?.onProjectsChanged((event) => {
        if (!ignores(event)) {
          reload();
        }
      }),
    [client, reload, ignores],
  );
  useEffect(() => client?.onReconnect(() => reload()), [client, reload]);

  return { value, error, reload };
}

const wholeList = (list: ProjectDto[]): ProjectDto[] => list;
const neverSame = (): boolean => false;
const noEvent = (): boolean => false;
const textEdit = (event: ProjectsChangedEvent): boolean => event.textsOnly;

/** Every project, as the daemon lists them — the list never folds or edits its copy. */
export function useProjects(
  apis: DaemonApis | null,
  client: DaemonClient | null,
): ProjectsList {
  const { value, error, reload } = useProjectList(
    apis,
    client,
    wholeList,
    neverSame,
    noEvent,
  );
  return { projects: value, error, reload };
}

const refsOf = (list: ProjectDto[]): ProjectRef[] =>
  list.map(({ id, name, folder }) => ({ id, name, folder }));
const sameRefs = (
  held: readonly ProjectRef[],
  next: readonly ProjectRef[],
): boolean =>
  held.length === next.length &&
  held.every(
    (ref, index) =>
      ref.id === next[index]!.id &&
      ref.name === next[index]!.name &&
      ref.folder === next[index]!.folder,
  );

/**
 * Each project's id, name and folder, unchanged while those are — so a screen
 * that only picks a project neither re-reads nor re-renders for an edit of a
 * project's texts. Null until the first answer.
 */
export function useProjectRefs(
  apis: DaemonApis | null,
  client: DaemonClient | null,
): ProjectRef[] | null {
  return useProjectList(apis, client, refsOf, sameRefs, textEdit).value;
}
