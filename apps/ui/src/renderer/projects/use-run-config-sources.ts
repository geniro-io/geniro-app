import { useEffect, useMemo, useRef, useState } from 'react';

import type {
  CliDetection,
  CliKind,
  ConfigProfile,
  RunConfig,
} from '../../shared/contracts';
import type { AgentApprovalCapability } from '../autogenerated';
import type { TargetTeam } from '../chats/target-select';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import { configDirCapabilityFrom } from '../teams/use-config-dir-capability';
import { useSharedCapabilities } from '../use-capabilities';

export interface RunConfigSources {
  runConfigs: readonly RunConfig[];
  /**
   * Rewrite `Settings.runConfigs` from the list as it stands in settings.json
   * at the moment of writing, one write at a time.
   */
  writeRunConfigs: (
    edit: (current: readonly RunConfig[]) => RunConfig[],
  ) => Promise<void>;
  teams: readonly TargetTeam[];
  cliDetections: readonly CliDetection[] | null;
  recentFolders: string[];
  recentConfigDirs: Partial<Record<CliKind, readonly string[]>>;
  configProfiles: readonly ConfigProfile[];
  recentConfigDirsFor: (kind: CliKind) => readonly string[];
  configProfilesFor: (kind: CliKind) => readonly ConfigProfile[];
  approvalCapabilityFor: (kind: CliKind) => AgentApprovalCapability | undefined;
  configDirReasonFor: (kind: CliKind) => string | null | undefined;
}

/**
 * The saved run configurations and everything their editor draws from: the
 * settings lists, the CLIs this machine has, the team library and the
 * per-CLI capability lookups.
 */
export function useRunConfigSources(apis: DaemonApis | null): RunConfigSources {
  const [runConfigs, setRunConfigs] = useState<readonly RunConfig[]>([]);
  const [recentFolders, setRecentFolders] = useState<string[]>([]);
  const [recentConfigDirs, setRecentConfigDirs] = useState<
    Partial<Record<CliKind, readonly string[]>>
  >({});
  const [configProfiles, setConfigProfiles] = useState<
    readonly ConfigProfile[]
  >([]);
  const [teams, setTeams] = useState<TargetTeam[]>([]);
  const [cliDetections, setCliDetections] = useState<CliDetection[] | null>(
    null,
  );

  const readSettings = useLatestCallback((): void => {
    void window.geniro
      .getSettings()
      .then((settings) => {
        setRunConfigs(settings.runConfigs ?? []);
        setRecentFolders(settings.recentFolders ?? []);
        setRecentConfigDirs(settings.recentConfigDirs ?? {});
        setConfigProfiles(settings.configProfiles ?? []);
      })
      .catch(() => undefined);
  }, []);

  useEffect(() => {
    readSettings();
    return window.geniro.onSettingsChanged(readSettings);
  }, [readSettings]);

  useEffect(() => {
    void window.geniro
      .detectClis()
      .then(setCliDetections)
      .catch(() => setCliDetections(null));
  }, []);

  useEffect(() => {
    if (apis === null) {
      return;
    }
    void apis.teams
      .listTeams()
      .then(setTeams)
      .catch(() => setTeams([]));
  }, [apis]);

  const writes = useRef<Promise<unknown>>(Promise.resolve());
  const writeRunConfigs = useLatestCallback(
    (edit: (current: readonly RunConfig[]) => RunConfig[]): Promise<void> => {
      const write = writes.current.then(async () => {
        const current = (await window.geniro.getSettings()).runConfigs ?? [];
        const next = edit(current);
        await window.geniro.updateSettings({ runConfigs: next });
        setRunConfigs(next);
      });
      writes.current = write.catch(() => undefined);
      return write;
    },
    [],
  );

  const { capabilities, loading } = useSharedCapabilities(
    apis?.capabilities ?? null,
  );
  const approvalByAgent = useMemo(
    () =>
      new Map((capabilities?.approvals ?? []).map((row) => [row.agent, row])),
    [capabilities],
  );
  const approvalCapabilityFor = useLatestCallback(
    (kind: CliKind): AgentApprovalCapability | undefined =>
      approvalByAgent.get(kind),
    [approvalByAgent],
  );
  const configDirReasonFor = configDirCapabilityFrom(
    capabilities,
    loading,
  ).unavailableReasonFor;
  const recentConfigDirsFor = useLatestCallback(
    (kind: CliKind): readonly string[] => recentConfigDirs[kind] ?? [],
    [recentConfigDirs],
  );
  const configProfilesFor = useLatestCallback(
    (kind: CliKind): readonly ConfigProfile[] =>
      configProfiles.filter((profile) => profile.agent === kind),
    [configProfiles],
  );

  return {
    runConfigs,
    writeRunConfigs,
    teams,
    cliDetections,
    recentFolders,
    recentConfigDirs,
    configProfiles,
    recentConfigDirsFor,
    configProfilesFor,
    approvalCapabilityFor,
    configDirReasonFor,
  };
}
