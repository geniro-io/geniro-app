// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { ResourceAlert } from '../autogenerated';
import { ResourceAlertStrip } from './resource-alert-strip';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const GIB = 1024 ** 3;

function alert(
  id: string,
  overrides: Partial<ResourceAlert> = {},
): ResourceAlert {
  return {
    id,
    kind: 'thread-memory',
    raisedAt: '2026-11-11T10:00:00.000Z',
    runId: 'r1',
    title: 'CI-1033',
    agentKind: 'claude',
    memberId: null,
    command: { pid: 7, name: 'node', label: 'node -e grow()', rssBytes: GIB },
    threadRssBytes: 9 * GIB,
    growthBytesPerMinute: null,
    freeDiskBytes: null,
    minFreeDiskBytes: null,
    stoppable: false,
    ...overrides,
  };
}

describe('ResourceAlertStrip', () => {
  let container: HTMLDivElement;
  let root: Root;
  const onOpenProcesses = vi.fn();
  const onStop = vi.fn();
  const onDismiss = vi.fn();

  function render(
    alerts: ResourceAlert[],
    stoppingId: string | null = null,
    error: string | null = null,
  ): void {
    act(() =>
      root.render(
        <ResourceAlertStrip
          alerts={alerts}
          agentName={(kind) => kind}
          stoppingId={stoppingId}
          error={error}
          onOpenProcesses={onOpenProcesses}
          onStop={onStop}
          onDismiss={onDismiss}
        />,
      ),
    );
  }

  const button = (name: string): HTMLButtonElement | undefined =>
    [...container.querySelectorAll('button')].find(
      (b) =>
        b.textContent?.includes(name) || b.getAttribute('aria-label') === name,
    );

  beforeEach(() => {
    vi.clearAllMocks();
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
  });

  it('draws nothing with no alert', () => {
    render([]);
    expect(container.innerHTML).toBe('');
  });

  it('offers Stop command only for a command the daemon may stop', () => {
    render([alert('a1', { stoppable: false })]);
    expect(button('Stop command')).toBeUndefined();

    render([alert('a1', { stoppable: true })]);
    act(() => button('Stop command')?.click());
    expect(onStop).toHaveBeenCalledWith('a1');
  });

  it('opens the blamed thread’s processes', () => {
    render([alert('a1')]);
    act(() => button('Open processes')?.click());
    expect(onOpenProcesses).toHaveBeenCalledWith('r1');
  });

  it('shows low disk as free space and its line alone', () => {
    render([
      alert('a1', {
        kind: 'low-disk',
        runId: null,
        title: null,
        agentKind: null,
        memberId: null,
        command: null,
        threadRssBytes: null,
        freeDiskBytes: 1.5 * GIB,
        minFreeDiskBytes: 10 * GIB,
        stoppable: false,
      }),
    ]);
    expect(button('Open processes')).toBeUndefined();
    expect(button('Stop command')).toBeUndefined();
    expect(container.textContent).toContain(
      'Only 1.5 GB free on the disk (warning below 10 GB).',
    );
    expect(container.textContent).not.toMatch(/CI-1033|runs|node/);
  });

  it('holds every Stop while one is under way', () => {
    render(
      [
        alert('a1', { stoppable: true }),
        alert('a2', { stoppable: true, runId: 'r2' }),
      ],
      'a1',
    );
    const stops = [...container.querySelectorAll('button')].filter((b) =>
      /Stop/.test(b.textContent ?? ''),
    );
    expect(stops.map((b) => [b.textContent, b.disabled])).toEqual([
      ['Stopping…', true],
      ['Stop command', true],
    ]);
  });

  it('dismisses one alert', () => {
    render([alert('a1')]);
    act(() => button('Dismiss warning')?.click());
    expect(onDismiss).toHaveBeenCalledWith('a1');
  });
});

describe('ResourceAlertStrip — its text', () => {
  it('shows the command line in the app, after who runs it', () => {
    const container = document.createElement('div');
    document.body.appendChild(container);
    const root = createRoot(container);
    act(() =>
      root.render(
        <ResourceAlertStrip
          alerts={[alert('a1')]}
          agentName={(kind) => kind}
          stoppingId={null}
          error="Could not stop the command: gone"
          onOpenProcesses={vi.fn()}
          onStop={vi.fn()}
          onDismiss={vi.fn()}
        />,
      ),
    );

    expect(container.textContent).toContain(
      '“CI-1033” is using 9.0 GB. claude runs node (1.0 GB): node -e grow()',
    );
    expect(container.textContent).toContain('Could not stop the command: gone');
    act(() => root.unmount());
    container.remove();
  });
});
