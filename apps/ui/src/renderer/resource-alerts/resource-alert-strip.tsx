import { Cpu, HardDrive, MemoryStick, Square } from 'lucide-react';

import type { ResourceAlert } from '../autogenerated';
import { ErrorBanner } from '../components/error-banner';
import { ErrorText } from '../components/error-text';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import {
  resourceAlertCulprit,
  resourceAlertHeadline,
} from './resource-alert-text';

function message(
  alert: ResourceAlert,
  agentName: (kind: string) => string,
): string {
  const culprit = resourceAlertCulprit(alert, agentName);
  const headline = `${resourceAlertHeadline(alert)}.`;
  return culprit === null || alert.command === null
    ? headline
    : `${headline} ${culprit}: ${alert.command.label}`;
}

/**
 * The app-wide strip for the daemon's resource alerts: which thread, agent
 * and command, with the thread's processes one press away and, when the
 * daemon may stop it, the command itself. A growth alert put away here is put
 * away on the daemon too, so it does not come back; any other alert stays
 * away in this window only.
 */
export function ResourceAlertStrip({
  alerts,
  agentName,
  stoppingId,
  error,
  onOpenProcesses,
  onStop,
  onDismiss,
  className,
}: {
  alerts: readonly ResourceAlert[];
  agentName: (kind: string) => string;
  stoppingId: string | null;
  error: string | null;
  onOpenProcesses: (runId: string) => void;
  onStop: (alertId: string) => void;
  onDismiss: (alertId: string) => void;
  className?: string;
}): React.JSX.Element | null {
  if (alerts.length === 0 && error === null) {
    return null;
  }
  return (
    <div
      data-slot="resource-alert-strip"
      className={cn(
        'flex flex-col gap-1 border-b border-warning/30 px-2 py-1.5',
        className,
      )}>
      {alerts.map((alert) => {
        const Icon = alert.kind === 'low-disk' ? HardDrive : MemoryStick;
        const runId = alert.runId;
        return (
          <ErrorBanner
            key={alert.id}
            data-alert-kind={alert.kind}
            tone="warning"
            size="sm"
            announce="status"
            icon={<Icon />}
            message={message(alert, agentName)}
            onDismiss={() => onDismiss(alert.id)}
            action={
              <>
                {runId === null ? null : (
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    className="h-6 shrink-0 px-2 text-xs"
                    onClick={() => onOpenProcesses(runId)}>
                    <Cpu aria-hidden="true" className="size-3" />
                    Open processes
                  </Button>
                )}
                {alert.stoppable ? (
                  <Button
                    type="button"
                    variant="destructive"
                    size="sm"
                    className="h-6 shrink-0 px-2 text-xs"
                    disabled={stoppingId !== null}
                    onClick={() => onStop(alert.id)}>
                    <Square aria-hidden="true" className="size-3" />
                    {stoppingId === alert.id ? 'Stopping…' : 'Stop command'}
                  </Button>
                ) : null}
              </>
            }
          />
        );
      })}
      {error === null ? null : (
        <ErrorText className="px-2 text-xs">{error}</ErrorText>
      )}
    </div>
  );
}
