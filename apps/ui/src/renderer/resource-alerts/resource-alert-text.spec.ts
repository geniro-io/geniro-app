import { describe, expect, it } from 'vitest';

import type { ResourceAlert } from '../autogenerated';
import {
  resourceAlertCulprit,
  resourceAlertHeadline,
  resourceAlertNotice,
} from './resource-alert-text';

const GIB = 1024 ** 3;

function alert(overrides: Partial<ResourceAlert> = {}): ResourceAlert {
  return {
    id: 'ra1',
    kind: 'thread-memory',
    raisedAt: '2026-11-11T10:00:00.000Z',
    runId: 'r1',
    title: 'CI-1033',
    agentKind: 'claude',
    memberId: 'middle',
    command: {
      pid: 7,
      name: 'python3',
      label: 'python3 x.py',
      rssBytes: 8 * GIB,
    },
    threadRssBytes: 9 * GIB,
    growthBytesPerMinute: 1.5 * GIB,
    freeDiskBytes: 1.5 * GIB,
    minFreeDiskBytes: null,
    stoppable: true,
    ...overrides,
  };
}

const name = (kind: string): string => kind.toUpperCase();

describe('resource alert text', () => {
  it('words each kind', () => {
    expect(resourceAlertHeadline(alert())).toBe('“CI-1033” is using 9.0 GB');
    expect(resourceAlertHeadline(alert({ kind: 'thread-growth' }))).toBe(
      '“CI-1033” is growing 1.5 GB/min (9.0 GB now)',
    );
    expect(resourceAlertHeadline(alert({ kind: 'memory-pressure' }))).toBe(
      'This Mac is running out of memory',
    );
    expect(
      resourceAlertHeadline(
        alert({ kind: 'low-disk', minFreeDiskBytes: 10 * GIB }),
      ),
    ).toBe('Only 1.5 GB free on the disk (warning below 10 GB)');
    expect(resourceAlertHeadline(alert({ kind: 'low-disk' }))).toBe(
      'Only 1.5 GB free on the disk',
    );
  });

  it('names the agent, member and command, and the thread for a system alert', () => {
    expect(resourceAlertCulprit(alert(), name)).toBe(
      'CLAUDE · middle runs python3 (8.0 GB)',
    );
    expect(resourceAlertCulprit(alert({ kind: 'memory-pressure' }), name)).toBe(
      'CLAUDE · middle in “CI-1033” runs python3 (8.0 GB)',
    );
    expect(
      resourceAlertCulprit(alert({ agentKind: null, memberId: null }), name),
    ).toBe('An agent runs python3 (8.0 GB)');
    expect(resourceAlertCulprit(alert({ command: null }), name)).toBeNull();
  });

  it('names no thread, agent or command for low disk', () => {
    expect(resourceAlertCulprit(alert({ kind: 'low-disk' }), name)).toBeNull();
    expect(resourceAlertNotice(alert({ kind: 'low-disk' }), name).body).toBe(
      'Only 1.5 GB free on the disk.',
    );
  });

  it('keeps the command line out of the system banner', () => {
    expect(resourceAlertNotice(alert(), name).body).toBe(
      '“CI-1033” is using 9.0 GB. CLAUDE · middle runs python3 (8.0 GB).',
    );
  });

  it('builds a notification that fits the system banner', () => {
    const notice = resourceAlertNotice(
      alert({
        title: 'T'.repeat(200),
        command: {
          pid: 7,
          name: 'n'.repeat(400),
          label: 'node',
          rssBytes: GIB,
        },
      }),
      name,
    );
    expect(notice.kind).toBe('resource-alert');
    expect(notice.title).toHaveLength(120);
    expect(notice.body).toHaveLength(240);
  });

  it('opens no thread from a notification that blames none', () => {
    const notice = resourceAlertNotice(
      alert({
        kind: 'low-disk',
        runId: null,
        title: null,
        agentKind: null,
        memberId: null,
        command: null,
        threadRssBytes: null,
        growthBytesPerMinute: null,
        minFreeDiskBytes: 10 * GIB,
        stoppable: false,
      }),
      name,
    );
    expect(notice).toEqual({
      kind: 'resource-alert',
      runId: '',
      title: 'Geniro',
      body: 'Only 1.5 GB free on the disk (warning below 10 GB).',
    });
  });
});
