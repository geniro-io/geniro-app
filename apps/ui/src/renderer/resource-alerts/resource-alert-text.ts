import type { RunNotification } from '../../shared/contracts';
import type { ResourceAlert } from '../autogenerated';
import { formatBytes } from '../format-bytes';

const MAX_TITLE_CHARS = 120;
const MAX_BODY_CHARS = 240;

function clip(text: string, max: number): string {
  const flat = text.replace(/\s+/g, ' ').trim();
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
}

function threadName(alert: ResourceAlert): string {
  return `“${alert.title ?? 'Untitled thread'}”`;
}

/** What the alert says happened, in one short sentence without a full stop. */
export function resourceAlertHeadline(alert: ResourceAlert): string {
  const rss = formatBytes(alert.threadRssBytes) ?? 'a lot of memory';
  switch (alert.kind) {
    case 'thread-memory':
      return `${threadName(alert)} is using ${rss}`;
    case 'thread-growth':
      return `${threadName(alert)} is growing ${formatBytes(alert.growthBytesPerMinute) ?? 'fast'}/min (${rss} now)`;
    case 'memory-pressure':
      return 'This Mac is running out of memory';
    case 'low-disk':
      return `Only ${formatBytes(alert.freeDiskBytes) ?? 'a little'} free on the disk`;
  }
}

/**
 * Who holds the blamed command and what it is called: `claude · middle runs
 * python3 (9.4 GB)`. Null when no command was named. The command line itself is
 * {@link ResourceAlert.command}'s label, shown only inside the app: an argv can
 * carry a credential no one typed, and a system banner outlives the screen.
 */
export function resourceAlertCulprit(
  alert: ResourceAlert,
  agentName: (kind: string) => string,
): string | null {
  const command = alert.command;
  if (command === null) {
    return null;
  }
  const who = [
    alert.agentKind === null ? null : agentName(alert.agentKind),
    alert.memberId,
  ]
    .filter((part): part is string => part !== null)
    .join(' · ');
  const system = alert.kind === 'memory-pressure' || alert.kind === 'low-disk';
  const where =
    system && alert.runId !== null ? `in ${threadName(alert)} ` : '';
  const size = formatBytes(command.rssBytes) ?? '';
  return `${who === '' ? 'An agent' : who} ${where}runs ${command.name} (${size})`;
}

/** The system notification for one newly raised alert. */
export function resourceAlertNotice(
  alert: ResourceAlert,
  agentName: (kind: string) => string,
): RunNotification {
  const culprit = resourceAlertCulprit(alert, agentName);
  return {
    kind: 'resource-alert',
    runId: alert.runId ?? '',
    title: clip(alert.title ?? 'Geniro', MAX_TITLE_CHARS),
    body: clip(
      culprit === null
        ? `${resourceAlertHeadline(alert)}.`
        : `${resourceAlertHeadline(alert)}. ${culprit}.`,
      MAX_BODY_CHARS,
    ),
  };
}
