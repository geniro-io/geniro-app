// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { GeniroApi } from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { ResourceAlert } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import {
  type ResourceAlertsState,
  useResourceAlerts,
} from './use-resource-alerts';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const GIB = 1024 ** 3;

function alert(
  id: string,
  overrides: Partial<ResourceAlert> = {},
): ResourceAlert {
  return {
    id,
    kind: 'thread-memory',
    raisedAt: '2026-11-11T10:00:00.000Z',
    runId: 'r1',
    title: 'CI-1033 — content visibility',
    agentKind: 'claude',
    memberId: 'middle',
    command: {
      pid: 4242,
      name: 'python3',
      label: 'python3 read_log.py api.log',
      rssBytes: 9 * GIB,
    },
    threadRssBytes: 9 * GIB,
    growthBytesPerMinute: null,
    freeDiskBytes: null,
    minFreeDiskBytes: null,
    stoppable: true,
    ...overrides,
  };
}

const agentName = (kind: string): string => `cli:${kind}`;

describe('useResourceAlerts', () => {
  let container: HTMLDivElement;
  let root: Root;
  let listed: ResourceAlert[];
  let changed: Set<() => void>;
  let reconnected: Set<() => void>;
  let state: ResourceAlertsState | null;
  const notify = vi.fn<GeniroApi['notify']>(async () => {});
  const listResourceAlerts = vi.fn(async () => ({ alerts: listed }));
  const stopResourceAlertCommand = vi.fn(async () => ({ stoppedPids: [4242] }));
  const apis = {
    chats: { listResourceAlerts, stopResourceAlertCommand },
  } as unknown as Pick<DaemonApis, 'chats'>;
  const client = {
    onResourceAlertsChanged: (listener: () => void) => {
      changed.add(listener);
      return () => changed.delete(listener);
    },
    onReconnect: (listener: () => void) => {
      reconnected.add(listener);
      return () => reconnected.delete(listener);
    },
  };

  function Probe({
    daemon = apis,
  }: {
    daemon?: Pick<DaemonApis, 'chats'>;
  }): null {
    state = useResourceAlerts({ apis: daemon, client, agentName });
    return null;
  }

  const flush = async (): Promise<void> => {
    await act(async () => {
      await Promise.resolve();
      await Promise.resolve();
    });
  };

  const announce = async (): Promise<void> => {
    act(() => {
      for (const listener of changed) {
        listener();
      }
    });
    await flush();
  };

  beforeEach(() => {
    notify.mockClear();
    listResourceAlerts.mockClear();
    stopResourceAlertCommand.mockClear();
    listed = [];
    changed = new Set();
    reconnected = new Set();
    state = null;
    window.geniro = createPreloadStub({ notify });
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
  });

  it('shows what the first read finds without announcing it', async () => {
    listed = [alert('ra1')];
    act(() => root.render(<Probe />));
    await flush();

    expect(state?.alerts.map((a) => a.id)).toEqual(['ra1']);
    expect(notify).not.toHaveBeenCalled();
  });

  it('announces an alert raised later, once, naming thread, agent and command', async () => {
    act(() => root.render(<Probe />));
    await flush();

    listed = [alert('ra1')];
    await announce();
    await announce();

    expect(notify).toHaveBeenCalledTimes(1);
    expect(notify).toHaveBeenCalledWith({
      kind: 'resource-alert',
      runId: 'r1',
      title: 'CI-1033 — content visibility',
      body: '“CI-1033 — content visibility” is using 9.0 GB. cli:claude · middle runs python3 (9.0 GB).',
    });
  });

  it('reads the list again after a reconnect, announcing what was raised meanwhile', async () => {
    act(() => root.render(<Probe />));
    await flush();

    listed = [alert('ra1')];
    act(() => {
      for (const listener of reconnected) {
        listener();
      }
    });
    await flush();

    expect(state?.alerts.map((a) => a.id)).toEqual(['ra1']);
    expect(notify).toHaveBeenCalledTimes(1);
  });

  it('drops an alert the daemon cleared', async () => {
    listed = [alert('ra1')];
    act(() => root.render(<Probe />));
    await flush();

    listed = [];
    await announce();

    expect(state?.alerts).toEqual([]);
  });

  it('hides a dismissed alert in this window only', async () => {
    listed = [alert('ra1'), alert('ra2', { kind: 'low-disk', runId: null })];
    act(() => root.render(<Probe />));
    await flush();

    act(() => state?.dismiss('ra1'));

    expect(state?.alerts.map((a) => a.id)).toEqual(['ra2']);
  });

  it('forgets what was dismissed once it talks to another daemon', async () => {
    listed = [alert('ra1')];
    act(() => root.render(<Probe />));
    await flush();
    act(() => state?.dismiss('ra1'));

    act(() => root.render(<Probe daemon={{ chats: apis.chats }} />));
    await flush();

    expect(state?.alerts.map((a) => a.id)).toEqual(['ra1']);
  });

  it('stops the command through the daemon and reads the list again', async () => {
    listed = [alert('ra1')];
    act(() => root.render(<Probe />));
    await flush();
    listResourceAlerts.mockClear();
    listed = [];

    await act(async () => {
      await state?.stop('ra1');
    });

    expect(stopResourceAlertCommand).toHaveBeenCalledWith({ alertId: 'ra1' });
    expect(listResourceAlerts).toHaveBeenCalledTimes(1);
    expect(state?.alerts).toEqual([]);
    expect(state?.error).toBeNull();
  });

  it('says why a stop was refused', async () => {
    listed = [alert('ra1')];
    stopResourceAlertCommand.mockRejectedValueOnce(
      new Error('pid 4242 is no longer a process this thread may stop'),
    );
    act(() => root.render(<Probe />));
    await flush();

    await act(async () => {
      await state?.stop('ra1');
    });

    expect(state?.error).toBe(
      'Could not stop the command: pid 4242 is no longer a process this thread may stop',
    );
  });
});
