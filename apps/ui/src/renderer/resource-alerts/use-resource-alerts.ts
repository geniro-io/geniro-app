import { useEffect, useRef, useState } from 'react';

import type { ResourceAlert } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { resourceAlertNotice } from './resource-alert-text';

export interface ResourceAlertsState {
  alerts: ResourceAlert[];
  stoppingId: string | null;
  error: string | null;
  dismiss: (id: string) => void;
  stop: (id: string) => Promise<void>;
}

function errorText(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

/**
 * The daemon's resource alerts, kept current from `resource_alerts_changed`,
 * with a system notification for each one raised while this is mounted. What
 * the first read finds was raised before this window was watching, so it is
 * shown but not announced again. `dismiss` puts a thread growth alert away on
 * the daemon, which starts that thread's quiet period; any other alert is put
 * away in this window only.
 */
export function useResourceAlerts({
  apis,
  client,
  agentName,
}: {
  apis: Pick<DaemonApis, 'chats'> | null;
  client: Pick<DaemonClient, 'onResourceAlertsChanged' | 'onReconnect'> | null;
  agentName: (kind: string) => string;
}): ResourceAlertsState {
  const [alerts, setAlerts] = useState<ResourceAlert[]>([]);
  const [dismissed, setDismissed] = useState<ReadonlySet<string>>(
    () => new Set(),
  );
  const [stoppingId, setStoppingId] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const known = useRef<Set<string> | null>(null);

  const refresh = useLatestCallback(async (): Promise<void> => {
    if (apis === null) {
      return;
    }
    let listed: ResourceAlert[];
    try {
      listed = (await apis.chats.listResourceAlerts()).alerts;
    } catch (err) {
      console.error('could not read the resource alerts', err);
      return;
    }
    const seen = known.current;
    if (seen !== null) {
      for (const alert of listed) {
        if (!seen.has(alert.id)) {
          void window.geniro
            .notify(resourceAlertNotice(alert, agentName))
            .catch((err: unknown) => {
              console.error('failed to post a notification', err);
            });
        }
      }
    }
    known.current = new Set([...(seen ?? []), ...listed.map((a) => a.id)]);
    setAlerts(listed);
  }, [apis]);

  useEffect(() => {
    known.current = null;
    setDismissed(new Set());
    void refresh();
  }, [apis, refresh]);

  useEffect(() => {
    if (client === null) {
      return;
    }
    const offChanged = client.onResourceAlertsChanged(() => void refresh());
    const offReconnect = client.onReconnect(() => void refresh());
    return () => {
      offChanged();
      offReconnect();
    };
  }, [client, refresh]);

  const dismissOnDaemon = useLatestCallback(
    async (id: string): Promise<void> => {
      if (apis === null) {
        return;
      }
      try {
        await apis.chats.dismissResourceAlert({ alertId: id });
      } catch (err) {
        setError(`Could not dismiss the alert: ${errorText(err)}`);
        setDismissed((prev) => new Set([...prev, id]));
      }
      await refresh();
    },
    [apis, refresh],
  );

  const dismiss = useLatestCallback((id: string): void => {
    const kind = alerts.find((alert) => alert.id === id)?.kind;
    if (kind === 'thread-growth' && apis !== null) {
      void dismissOnDaemon(id);
      return;
    }
    setDismissed((prev) => new Set([...prev, id]));
  }, []);

  const stop = useLatestCallback(
    async (id: string): Promise<void> => {
      if (apis === null) {
        return;
      }
      setStoppingId(id);
      setError(null);
      try {
        await apis.chats.stopResourceAlertCommand({ alertId: id });
      } catch (err) {
        setError(`Could not stop the command: ${errorText(err)}`);
      } finally {
        setStoppingId(null);
      }
      await refresh();
    },
    [apis, refresh],
  );

  return {
    alerts: alerts.filter((alert) => !dismissed.has(alert.id)),
    stoppingId,
    error,
    dismiss,
    stop,
  };
}
