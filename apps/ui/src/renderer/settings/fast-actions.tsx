/**
 * Fast actions — the user's own buttons for starting a chat.
 *
 * One action is a whole new-chat setup (folder, branch, agent and its options)
 * plus, optionally, the MESSAGE to send on start: press it on the new-chat
 * screen and a chat is already working on the thing you always ask for.
 *
 * Managing them lives HERE and nowhere else. It used to be a dialog hanging off
 * the sidebar's `+`, on the reasoning that a setup is edited in the moment you
 * notice it is wrong — but a fast action is a thing you SET UP once and press
 * many times, so it belongs on a screen of its own, which is what was asked
 * for. What that old note got right stands: ONE surface over the data, never
 * two free to disagree.
 *
 * The editor COMPOSES the composer's own chips rather than re-implementing
 * pickers, so an action can only ever hold values the composer itself could
 * produce. Its vocabulary is asked about the ACTION's agent, never the last one
 * the user chatted with — answering the second with the first is the session
 * picker's old bug, which sent a claude profile to cursor.
 */
/** A draft for an action with no folder yet — the folder chip asks for one. */
const EMPTY_DRAFT: RunConfigDraft = {
  name: '',
  firstMessage: null,
  cwd: '',
  branch: null,
  target: 'claude',
  model: null,
  effort: null,
  contextWindow: null,
  modelParameters: {},
  approval: null,
  configDir: null,
};

export function FastActionsPane({
  configs,
  agentsApi,
  workflows,
  cliDetections,
  recentFolders,
  recentConfigDirs,
  approvalModesFor,
  configDirReasonFor,
  planSupported,
  seed,
  onSave,
  onDelete,
}: {
  configs: readonly RunConfig[];
  agentsApi: DaemonApis['agents'] | null;
  workflows: readonly TargetWorkflow[];
  cliDetections: readonly CliDetection[] | null;
  recentFolders: string[];
  recentConfigDirs: string[];
  /** Modes one CLI honours, or null until the capability report lands. */
  approvalModesFor: (kind: CliKind) => readonly ChatApprovalMode[] | null;
  /** Why one CLI takes no config directory — null when it can, undefined while unknown. */
  configDirReasonFor: (kind: CliKind) => string | null | undefined;
  planSupported: boolean;
  /**
   * What a NEW action starts from — the choices the composer itself opens on,
   * read out of settings.json.
   *
   * The dialog this replaced seeded from live composer state, which a settings
   * screen has no access to. Reading the same remembered values gets the same
   * ergonomics with no coupling: a new action is a naming step rather than six
   * pickers, and it starts where the user actually works.
   */
  seed: RunConfigDraft | null;
  /** Create when the id is new, replace when it matches an existing entry. */
  onSave: (draft: RunConfigDraft, id: string | null) => void;
  onDelete: (id: string) => void;
}): React.JSX.Element {
  /**
   * `null` is the list; anything else is the editor, carrying the id it will
   * save back to (`null` for an action that does not exist yet).
   */
  const [editing, setEditing] = React.useState<{
    id: string | null;
    draft: RunConfigDraft;
  } | null>(null);
  /** The row whose Delete has been pressed once — the second press commits. */
  const [confirmingDelete, setConfirmingDelete] = React.useState<string | null>(
    null,
  );
  const [error, setError] = React.useState<string | null>(null);

  const startNew = React.useCallback((): void => {
    setError(null);
    setEditing({ id: null, draft: seed ?? EMPTY_DRAFT });
  }, [seed]);

  const commit = React.useCallback((): void => {
    if (!editing) {
      return;
    }
    const name = editing.draft.name.trim();
    if (name === '') {
      setError('Give the action a name.');
      return;
    }
    if (editing.draft.cwd === '') {
      setError('Choose the folder this action opens in.');
      return;
    }
    // Refuse here what the IPC schema would refuse anyway. That boundary
    // rejects the WHOLE settings patch by throwing, so without these guards an
    // over-long name or a 51st entry closes the editor, shows the row from
    // React state, and writes nothing.
    if (name.length > MAX_RUN_CONFIG_NAME) {
      setError(
        `That name is ${name.length} characters — keep it to ${MAX_RUN_CONFIG_NAME}.`,
      );
      return;
    }
    const message = editing.draft.firstMessage?.trim() ?? '';
    if (message.length > MAX_RUN_CONFIG_MESSAGE) {
      setError(
        `That message is ${message.length} characters — keep it to ${MAX_RUN_CONFIG_MESSAGE}.`,
      );
      return;
    }
    if (editing.id === null && configs.length >= MAX_RUN_CONFIGS) {
      setError(
        `You already have ${MAX_RUN_CONFIGS} actions — delete one before adding another.`,
      );
      return;
    }
    // Clear the refusal this save just resolved. The message renders above the
    // LIST as well as the editor, so a stale one sits over the row that proves
    // it wrong — the user is told to name an action that is on screen carrying
    // its name.
    setError(null);
    onSave(
      { ...editing.draft, name, firstMessage: message === '' ? null : message },
      editing.id,
    );
    setEditing(null);
  }, [editing, configs.length, onSave]);

  return (
    // NO heading of its own: the screen's header already names the section it
    // is showing, and the pane repeating it printed `Fast actions` twice, one
    // line apart. The same goes for the sentence under it — the header carries
    // the one description.
    <section className="flex flex-col gap-3" aria-label="Fast actions">
      {editing ? null : (
        <div className="flex items-center justify-end">
          <Button type="button" variant="outline" size="sm" onClick={startNew}>
            <Plus className="size-4" />
            New action
          </Button>
        </div>
      )}
      {error ? <ErrorText>{error}</ErrorText> : null}
      {editing ? (
        <FastActionEditor
          draft={editing.draft}
          isNew={editing.id === null}
          agentsApi={agentsApi}
          open
          workflows={workflows}
          cliDetections={cliDetections}
          recentFolders={recentFolders}
          recentConfigDirs={recentConfigDirs}
          approvalModesFor={approvalModesFor}
          configDirReasonFor={configDirReasonFor}
          planSupported={planSupported}
          onChange={(draft) => setEditing({ id: editing.id, draft })}
          onCancel={() => {
            setError(null);
            setEditing(null);
          }}
          onCommit={commit}
        />
      ) : (
        <div className="flex min-h-0 flex-col gap-3">
          {configs.length === 0 ? (
            <EmptyState className="flex-col gap-1">
              <span className="text-foreground">No fast actions yet</span>
              <span>
                A new one starts from the setup your next chat would open with —
                change whichever chips you like, and give it a name.
              </span>
            </EmptyState>
          ) : (
            <ul className="m-0 flex list-none flex-col gap-1 p-0">
              {configs.map((config) => (
                <FastActionRow
                  key={config.id}
                  config={config}
                  confirmingDelete={confirmingDelete === config.id}
                  onEdit={() => {
                    setError(null);
                    setConfirmingDelete(null);
                    const { id: _id, ...draft } = config;
                    setEditing({ id: config.id, draft });
                  }}
                  onDeletePress={() => setConfirmingDelete(config.id)}
                  onDeleteCancel={() => setConfirmingDelete(null)}
                  onDeleteConfirm={() => {
                    setConfirmingDelete(null);
                    onDelete(config.id);
                  }}
                />
              ))}
            </ul>
          )}
        </div>
      )}
    </section>
  );
}

/** One fast action: what it opens, and the two things you can do to it. */
function FastActionRow({
  config,
  confirmingDelete,
  onEdit,
  onDeletePress,
  onDeleteCancel,
  onDeleteConfirm,
}: {
  config: RunConfig;
  confirmingDelete: boolean;
  onEdit: () => void;
  onDeletePress: () => void;
  onDeleteCancel: () => void;
  onDeleteConfirm: () => void;
}): React.JSX.Element {
  const workflow = workflowSlugOf(config.target);
  return (
    <li className="flex items-center gap-1 rounded-md hover:bg-sidebar-accent">
      <button
        type="button"
        onClick={onEdit}
        // Named explicitly: the row's own text is a folder path and a model
        // alias read out as one run-on string.
        aria-label={`Edit the fast action “${config.name}”`}
        title={`Edit “${config.name}”`}
        className="flex min-w-0 flex-1 flex-col items-start gap-0.5 rounded-md px-3 py-2 text-left outline-none focus-visible:bg-sidebar-accent">
        <span className="w-full truncate text-sm text-foreground">
          {config.name}
        </span>
        <span className="flex w-full items-center gap-1.5 text-xs text-muted-foreground">
          <Folder className="size-3 shrink-0" aria-hidden="true" />
          {/* Elided from the FRONT — CSS truncation eats the tail, which for a
              path is the only end that says which project it is. */}
          <span className="truncate" title={config.cwd}>
            {shortenPath(config.cwd)}
          </span>
          {config.branch === null ? null : (
            <>
              <span aria-hidden="true">·</span>
              <GitBranch className="size-3 shrink-0" aria-hidden="true" />
              <span className="shrink-0 truncate">{config.branch}</span>
            </>
          )}
          <span aria-hidden="true">·</span>
          <span className="shrink-0">{workflow ?? config.target}</span>
          {config.model === null ? null : (
            <>
              <span aria-hidden="true">·</span>
              <span className="shrink-0 truncate">{config.model}</span>
            </>
          )}
        </span>
      </button>
      {confirmingDelete ? (
        // Two presses rather than a nested dialog, which would fight this one
        // for the focus trap. Cancel is not decoration: the confirm button
        // replaces the delete button under the pointer, so a double-click would
        // otherwise land straight on it.
        <>
          <Button
            type="button"
            variant="ghost"
            size="sm"
            className="shrink-0 text-muted-foreground"
            aria-label={`Keep ${config.name}`}
            onClick={onDeleteCancel}>
            Cancel
          </Button>
          <Button
            type="button"
            variant="destructive"
            size="sm"
            className="mr-1 shrink-0"
            aria-label={`Confirm delete ${config.name}`}
            onClick={onDeleteConfirm}>
            Delete?
          </Button>
        </>
      ) : (
        <>
          <Button
            type="button"
            variant="ghost"
            size="icon"
            className="size-7 shrink-0 text-muted-foreground"
            aria-label={`Edit ${config.name}`}
            title="Edit"
            onClick={onEdit}>
            <Pencil className="size-4" />
          </Button>
          <Button
            type="button"
            variant="ghost"
            size="icon"
            className="mr-1 size-7 shrink-0 text-muted-foreground"
            aria-label={`Delete ${config.name}`}
            title="Delete"
            onClick={onDeletePress}>
            <Trash2 className="size-4" />
          </Button>
        </>
      )}
    </li>
  );
}

/**
 * The editor, built from the composer's own chips.
 *
 * Its model and effort lists are fetched for the DRAFT's agent and only while
 * the dialog is open — a cursor model probe spawns a real `cursor-agent acp`,
 * so a closed dialog must not be paying for one.
 */
function FastActionEditor({
  draft,
  isNew,
  open,
  agentsApi,
  workflows,
  cliDetections,
  recentFolders,
  recentConfigDirs,
  approvalModesFor,
  configDirReasonFor,
  planSupported,
  onChange,
  onCancel,
  onCommit,
}: {
  draft: RunConfigDraft;
  isNew: boolean;
  open: boolean;
  agentsApi: DaemonApis['agents'] | null;
  workflows: readonly TargetWorkflow[];
  cliDetections: readonly CliDetection[] | null;
  recentFolders: string[];
  recentConfigDirs: string[];
  approvalModesFor: (kind: CliKind) => readonly ChatApprovalMode[] | null;
  configDirReasonFor: (kind: CliKind) => string | null | undefined;
  planSupported: boolean;
  onChange: (draft: RunConfigDraft) => void;
  onCancel: () => void;
  onCommit: () => void;
}): React.JSX.Element {
  const workflow = workflowSlugOf(draft.target) !== null;
  const kind = targetAgentKind(draft.target);
  // Null while closed, so neither list is fetched for a dialog nobody opened.
  const vocabularyKind = open && !workflow ? kind : null;
  // Every listing below is asked about the CONFIGURATION's own profile, since
  // each is an ACCOUNT fact — a saved configuration naming a profile has to be
  // edited against that account's models and levels, not the composer's.
  const vocabularyConfigDir = open && !workflow ? draft.configDir : null;
  const { models, loading: modelsLoading } = useAgentModels(
    agentsApi,
    vocabularyKind,
    vocabularyConfigDir,
  );
  const efforts = useAgentEfforts(
    agentsApi,
    vocabularyKind,
    null,
    vocabularyConfigDir,
  );
  // Asked WITH the draft's model, unlike the effort listing above: a window
  // size belongs to the model outright, so there is no CLI-wide list to fall
  // back on — asked without one the daemon answers "pick a model first", which
  // is exactly what the chip then says.
  const contextWindows = useAgentContextWindows(
    agentsApi,
    vocabularyKind,
    draft.model,
    vocabularyConfigDir,
  );
  // Asked about the CONFIGURATION's agent and model like its two neighbours —
  // here it decides which rows exist at all, not only what they contain.
  const modelParameters = useAgentModelParameters(
    agentsApi,
    vocabularyKind,
    draft.model,
    vocabularyConfigDir,
  );
  // Branches of the folder the DRAFT points at, not the composer's.
  const git = useGitInfo(draft.cwd === '' ? null : draft.cwd);
  const approvalModes = approvalModesFor(kind);

  const set = React.useCallback(
    (patch: Partial<RunConfigDraft>): void => onChange({ ...draft, ...patch }),
    [draft, onChange],
  );

  const browseFolder = React.useCallback((): void => {
    void window.geniro.pickProjectFolder().then((chosen) => {
      if (chosen) {
        // A new folder is a new repository, so a branch recorded against the
        // old one would name a ref this one may not have.
        onChange({ ...draft, cwd: chosen, branch: null });
      }
    });
  }, [draft, onChange]);

  const browseConfigDir = React.useCallback((): void => {
    void window.geniro.pickProjectFolder().then((chosen) => {
      if (chosen) {
        onChange({ ...draft, configDir: chosen });
      }
    });
  }, [draft, onChange]);

  return (
    <div className="flex min-h-0 flex-col gap-4">
      <label className="flex flex-col gap-1.5">
        <span className="text-sm font-medium">Name</span>
        <Input
          value={draft.name}
          placeholder="Geniro app · main"
          aria-label="Fast action name"
          maxLength={MAX_RUN_CONFIG_NAME}
          onChange={(event) => set({ name: event.target.value })}
        />
      </label>

      {/* The field that makes this a BUTTON rather than a bookmark. Optional on
          purpose: an action with no message seeds the composer and stops, which
          is what these have always done and is still wanted for the setups a
          user starts differently every time.

          `ExpandableTextarea` rather than a bare one — this is a whole brief,
          and the corner ⤢ opens it in the markdown editor. Safe here in a way
          the queued strip is not: nothing can send this row out from under the
          editor, so the component's own modal owns its lifetime. */}
      <label className="flex flex-col gap-1.5">
        <span className="text-sm font-medium">First message</span>
        <ExpandableTextarea
          value={draft.firstMessage ?? ''}
          rows={3}
          title="First message"
          placeholder="Review what changed on this branch and report findings."
          onChange={(value) =>
            set({
              // Capped where it is TYPED as well as where it is saved: the
              // commit refuses an over-long message, and a user who pasted
              // 6000 characters would otherwise learn that only on Save.
              firstMessage: value.slice(0, MAX_RUN_CONFIG_MESSAGE) || null,
            })
          }
        />
        <span className="text-xs text-muted-foreground">
          Sent the moment the action is pressed. Leave it empty to fill in the
          chips and write the message yourself.
        </span>
      </label>

      <div className="flex flex-col gap-1.5">
        <span className="text-sm font-medium">Opens with</span>
        <div className="flex flex-col divide-y divide-border rounded-md border border-border">
          <SettingRow label="Agent">
            <TargetSelect
              value={draft.target}
              workflows={workflows}
              cliDetections={cliDetections}
              aria-label="Agent or workflow this configuration starts"
              onChange={(target) =>
                // Switching to a workflow drops the CLI-only choices rather than
                // keeping them invisibly: their rows disappear, and a value the
                // user can neither see nor edit would still be saved.
                workflowSlugOf(target) !== null
                  ? set({
                      target,
                      model: null,
                      effort: null,
                      contextWindow: null,
                      modelParameters: {},
                      approval: null,
                      configDir: null,
                    })
                  : set({ target })
              }
            />
          </SettingRow>
          <SettingRow label="Folder">
            <FolderSelect
              folder={draft.cwd === '' ? null : draft.cwd}
              recentFolders={recentFolders}
              onChoose={(cwd) => onChange({ ...draft, cwd, branch: null })}
              onBrowse={browseFolder}
            />
          </SettingRow>
          {git.info.isRepo ? (
            <SettingRow
              label="Branch"
              hint="Switched before the chat starts; refused over a dirty tree, and the rest still applies.">
              <BranchValueSelect
                info={git.info}
                value={draft.branch}
                onChange={(branch) => set({ branch })}
              />
            </SettingRow>
          ) : null}
          {workflow ? null : (
            <>
              {configDirReasonFor(kind) === null ? (
                <SettingRow label="Profile">
                  <ConfigDirSelect
                    configDir={draft.configDir}
                    recentConfigDirs={recentConfigDirs}
                    unavailableReason={configDirReasonFor(kind)}
                    onChange={(configDir) => set({ configDir })}
                    onBrowse={browseConfigDir}
                  />
                </SettingRow>
              ) : null}
              <SettingRow label="Approvals">
                <ApprovalModeSelect
                  supportedModes={approvalModes}
                  value={
                    isChatApprovalMode(draft.approval) &&
                    approvalModes?.includes(draft.approval)
                      ? draft.approval
                      : null
                  }
                  planSupported={planSupported}
                  onChange={(approval) => set({ approval })}
                />
              </SettingRow>
              <SettingRow label="Model">
                <ModelSelect
                  agentKind={kind}
                  models={models}
                  loading={modelsLoading}
                  value={draft.model}
                  // The window and the other parameters belong to the model
                  // that offered them, so a model change clears both rather
                  // than carrying values the new model may not have — the same
                  // rule the daemon's settings patch holds for an open chat.
                  onChange={(model) =>
                    set({ model, contextWindow: null, modelParameters: {} })
                  }
                />
              </SettingRow>
              {/* The ROW goes with the control, here and below. Both chips
                  render nothing when the model offers no choice, and a labelled
                  row around nothing is a label with a hole in it — which in a
                  fixed label column is louder than the chip ever was. */}
              {efforts.efforts.length === 0 ? null : (
                <SettingRow label="Effort">
                  <EffortSelect
                    efforts={efforts.efforts}
                    value={draft.effort}
                    onChange={(effort) => set({ effort })}
                  />
                </SettingRow>
              )}
              {contextWindows.windows.length === 0 ? null : (
                <SettingRow label="Context window">
                  <ContextWindowSelect
                    windows={contextWindows.windows}
                    value={draft.contextWindow}
                    onChange={(contextWindow) => set({ contextWindow })}
                  />
                </SettingRow>
              )}
              {/* One labelled row per OTHER setting this model enumerates. A row
                  per parameter rather than one row of chips, because the
                  editor's whole shape is a fixed label column — a setting with
                  no address of its own is the wrapping chip row this screen was
                  built to replace. */}
              {modelParameters.parameters.map((parameter) => (
                <SettingRow key={parameter.id} label={parameter.label}>
                  <ModelParameterSelect
                    parameter={parameter}
                    // The row's label column already names it.
                    showAxisName={false}
                    value={draft.modelParameters[parameter.id] ?? null}
                    onChange={(next) =>
                      set({
                        modelParameters: withModelParameter(
                          draft.modelParameters,
                          parameter.id,
                          next,
                        ),
                      })
                    }
                  />
                </SettingRow>
              ))}
            </>
          )}
        </div>
        <p className="text-xs text-muted-foreground">
          A row left on its default means “let the CLI decide”.
        </p>
      </div>

      <div className="flex items-center justify-end gap-2 border-t border-border pt-3">
        <Button type="button" variant="ghost" size="sm" onClick={onCancel}>
          Cancel
        </Button>
        <Button type="button" size="sm" onClick={onCommit}>
          {isNew ? 'Create' : 'Save'}
        </Button>
      </div>
    </div>
  );
}
