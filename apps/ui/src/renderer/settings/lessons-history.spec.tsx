    title: 'WHEN a check fails → change what it exercises before rerunning',
    rule: 'Rerun a failing check only after changing what it exercises.',
    why: 'The same check was retried three times unchanged.',
    signalKind: 'error_then_success',
    evidence: { seq: 7, quote: 'опять тот же тест' },
    target: { kind: 'memory', scope: 'project', type: 'feedback' },
    dedup: { verdict: 'new', handle: null },
    status: 'saved',
    rejectReason: null,
    checkVerdict: null,
    checkReason: null,
    memoryHandle: null,
    resultRef: null,
    places: { project: true, team: false, projectId: 'proj-1', members: [] },
    moveUp: null,
    undoable: false,
    memoryPending: false,
    sourceExists: true,
    createdAt: '2026-11-20T10:00:00.000Z',
    decidedAt: null,
