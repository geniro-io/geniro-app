import { useEffect, useRef, useState } from 'react';

import type { LessonHistoryCounts, LessonProposal } from '../autogenerated';
import { documentsReaderOf } from '../chats/lessons-api-context';
import { ErrorBanner } from '../components/error-banner';
import { SettingsPanelRow } from '../components/settings-panel';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { LessonProposalRow } from './waiting-lessons';

const HISTORY_PAGE = 20;

type Lessons = DaemonApis['lessons'];

interface HistoryPages {
  proposals: readonly LessonProposal[];
  nextBefore: string | null;
}

export interface LessonHistoryState {
  /** Null until the daemon has answered. */
  counts: LessonHistoryCounts | null;
  /** Null until the dialog has read its first page. */
  pages: HistoryPages | null;
  loading: boolean;
  error: string | null;
  loadMore: () => void;
  reload: () => void;
}

function messageOf(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

/**
 * The counts of every lesson ever filed, and, while the dialog is open, its
 * pages newest first. A lessons change or a decision re-reads from the top
 * down to the depth already read.
 */
export function useLessonHistory({
  lessonsApi,
  client,
  open,
}: {
  lessonsApi: Lessons | null;
  client: Pick<DaemonClient, 'onLessonsChanged'> | null;
  open: boolean;
}): LessonHistoryState {
  const [counts, setCounts] = useState<LessonHistoryCounts | null>(null);
  const [pages, setPages] = useState<HistoryPages | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [generation, setGeneration] = useState(0);
  const read = useRef(0);
  const depth = useRef(0);

  const reload = useLatestCallback(
    () => setGeneration((value) => value + 1),
    [],
  );

  useEffect(() => {
    if (!open) {
      depth.current = 0;
      setPages(null);
    }
  }, [open]);

  useEffect(() => {
    if (lessonsApi === null) {
      return;
    }
    const ticket = ++read.current;
    const want = open ? depth.current : 0;
    const readTop = async (): Promise<void> => {
      let page = await lessonsApi.listLessonHistory({
        limit: open ? HISTORY_PAGE : 1,
      });
      const proposals = [...page.proposals];
      while (
        open &&
        proposals.length < want &&
        page.nextBefore !== null &&
        ticket === read.current
      ) {
        page = await lessonsApi.listLessonHistory({
          limit: HISTORY_PAGE,
          before: page.nextBefore,
        });
        proposals.push(...page.proposals);
      }
      if (ticket !== read.current) {
        return;
      }
      setCounts(page.counts);
      setPages(open ? { proposals, nextBefore: page.nextBefore } : null);
      setError(null);
    };
    setLoading(open);
    readTop().then(
      () => {
        if (ticket === read.current) {
          setLoading(false);
        }
      },
      (err: unknown) => {
        if (ticket === read.current) {
          setLoading(false);
          setError(messageOf(err));
        }
      },
    );
  }, [lessonsApi, open, generation]);

  useEffect(() => client?.onLessonsChanged(reload), [client, reload]);

  const loadMore = useLatestCallback((): void => {
    const before = pages?.nextBefore ?? null;
    if (lessonsApi === null || before === null || loading) {
      return;
    }
    const ticket = ++read.current;
    setLoading(true);
    lessonsApi.listLessonHistory({ limit: HISTORY_PAGE, before }).then(
      (page) => {
        if (ticket !== read.current) {
          return;
        }
        setCounts(page.counts);
        setPages((prev) => {
          const proposals = [...(prev?.proposals ?? []), ...page.proposals];
          depth.current = proposals.length;
          return { proposals, nextBefore: page.nextBefore };
        });
        setLoading(false);
        setError(null);
      },
      (err: unknown) => {
        if (ticket === read.current) {
          setLoading(false);
          setError(messageOf(err));
        }
      },
    );
  }, [lessonsApi, pages, loading]);

  return { counts, pages, loading, error, loadMore, reload };
}

export function historySummary(counts: LessonHistoryCounts): string {
  if (counts.total === 0) {
    return 'No lessons yet.';
  }
  return [
    `${counts.total.toLocaleString('en-US')} ${counts.total === 1 ? 'lesson' : 'lessons'}`,
    counts.saved > 0 ? `${counts.saved.toLocaleString('en-US')} saved` : null,
    counts.waiting > 0
      ? `${counts.waiting.toLocaleString('en-US')} waiting for review`
      : null,
    counts.checking > 0
      ? `${counts.checking.toLocaleString('en-US')} being checked`
      : null,
    counts.notSaved > 0
      ? `${counts.notSaved.toLocaleString('en-US')} not saved`
      : null,
  ]
    .filter((part): part is string => part !== null)
    .join(' · ');
}

/**
 * Settings → Memory → Lessons → History: the counts of every lesson a
 * reflection ever found, and Open…, a dialog listing each one newest first
 * with what became of it, a page at a time.
 */
export function LessonsHistory({
  lessonsApi,
  knowledgeApi,
  client,
}: {
  lessonsApi: Lessons | null;
  knowledgeApi: DaemonApis['knowledge'] | null;
  client: Pick<DaemonClient, 'onLessonsChanged'> | null;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const history = useLessonHistory({ lessonsApi, client, open });
  const { counts, pages } = history;
  const readDocuments = documentsReaderOf(knowledgeApi);
  const proposals = pages?.proposals ?? [];

  return (
    <>
      <SettingsPanelRow
        label="History"
        hint="Every lesson a reflection has found, newest first: which chat it came from, the rule, why it was proposed, and what became of it — saved to memory, to project or member instructions or to knowledge, still waiting for you, or not saved and why."
        description={
          counts === null
            ? 'Every lesson found so far, and what became of it.'
            : historySummary(counts)
        }>
        {counts === null || counts.total === 0 ? null : (
          <Button
            size="sm"
            variant="outline"
            title="List every lesson found so far and what became of it."
            onClick={() => setOpen(true)}>
            Open…
          </Button>
        )}
      </SettingsPanelRow>
      <Dialog
        open={open}
        onClose={() => setOpen(false)}
        title="Lessons history"
        className="w-[40rem] max-w-[calc(100vw-2rem)]">
        <div className="flex min-w-0 flex-col gap-3">
          {counts === null ? null : (
            <p
              data-slot="lessons-history-summary"
              className="m-0 text-xs text-muted-foreground">
              {historySummary(counts)}
            </p>
          )}
          {history.error === null ? null : (
            <ErrorBanner
              message={history.error}
              size="sm"
              onDismiss={history.reload}
            />
          )}
          <div className="-mx-1 max-h-[min(40rem,70vh)] overflow-y-auto px-1">
            {proposals.length === 0 ? (
              <p className="m-0 py-2 text-xs text-muted-foreground">
                {history.loading ? 'Reading…' : 'No lessons yet.'}
              </p>
            ) : (
              <ul
                data-slot="lessons-history"
                className="m-0 flex list-none flex-col divide-y divide-border p-0">
                {proposals.map((proposal) => (
                  <li
                    key={proposal.id}
                    data-slot="lessons-history-item"
                    className="min-w-0 py-3 first:pt-0 last:pb-0">
                    <LessonProposalRow
                      proposal={proposal}
                      lessonsApi={lessonsApi}
                      readDocuments={readDocuments}
                      detailed
                      onChanged={history.reload}
                    />
                  </li>
                ))}
              </ul>
            )}
            {pages?.nextBefore === null || pages === null ? null : (
              <div className="mt-3 flex justify-center">
                <Button
                  size="sm"
                  variant="outline"
                  title="Read the next older lessons."
                  disabled={history.loading}
                  onClick={history.loadMore}>
                  {history.loading ? 'Loading…' : 'Show more'}
                </Button>
              </div>
            )}
          </div>
        </div>
      </Dialog>
    </>
  );
}
