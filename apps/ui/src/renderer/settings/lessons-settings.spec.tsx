// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import {
  DEFAULT_SETTINGS,
  type LessonsSettings,
  type Settings,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { CapabilitiesDto } from '../autogenerated';
import { LessonsSettingsPanel } from './lessons-settings';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;
let writes: Partial<Settings>[];

const CAPABILITIES = {
  agents: [
    { agent: 'claude', displayName: 'Claude Code', shortName: 'Claude' },
    { agent: 'codex', displayName: 'Codex', shortName: 'Codex' },
  ],
} as unknown as CapabilitiesDto;

function install(lessons: LessonsSettings): void {
  writes = [];
  let stored: Settings = { ...DEFAULT_SETTINGS, lessons };
  window.geniro = createPreloadStub({
    getSettings: () => Promise.resolve(stored),
    updateSettings: (patch) => {
      writes.push(patch);
      stored = { ...stored, ...patch };
      return Promise.resolve(stored);
    },
  });
}

async function settle(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });
}

async function render(remote = false): Promise<void> {
  await act(async () => {
    root.render(
      <LessonsSettingsPanel
        agentsApi={null}
        capabilities={CAPABILITIES}
        remote={remote}
      />,
    );
  });
  await settle();
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
  await settle();
}

function modeOf(): HTMLButtonElement {
  return container.querySelector<HTMLButtonElement>('#settings-lessons-mode')!;
}

function agentOf(): HTMLButtonElement {
  return container.querySelector<HTMLButtonElement>('#settings-lessons-agent')!;
}

function option(label: string): HTMLElement {
  return [...document.querySelectorAll<HTMLElement>('[role="option"]')].find(
    (node) => node.textContent?.trim() === label,
  )!;
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('Lessons settings', () => {
  it('offers Off and Offer me, run when I press, and saves the pick alone', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render();

    await press(modeOf());
    expect(
      [...document.querySelectorAll<HTMLElement>('[role="option"]')].map(
        (node) => node.textContent?.trim(),
      ),
    ).toEqual(['Offer me, run when I press', 'Off']);
    await press(option('Off'));

    expect(writes).toEqual([
      { lessons: { ...DEFAULT_SETTINGS.lessons, mode: 'off' } },
    ]);
  });

  it('a new agent pick clears the model and effort picked for the last one', async () => {
    install({
      mode: 'offer',
      agentKind: 'claude',
      model: 'opus',
      effort: 'high',
    });
    await render();

    await press(agentOf());
    await press(option('codex'));

    expect(writes).toEqual([
      {
        lessons: {
          mode: 'offer',
          agentKind: 'codex',
          model: null,
          effort: null,
        },
      },
    ]);
  });

  it('stacks the reflection agent’s pickers under its label, so they cannot squeeze its description', async () => {
    install({ mode: 'offer', agentKind: 'claude', model: null, effort: null });
    await render();

    const row = agentOf().closest<HTMLElement>(
      '[data-slot="settings-panel-row"]',
    )!;
    expect(row.textContent).toContain('Which CLI, model and effort');
    expect(row.className).not.toContain('@[26rem]:flex-row');
    expect(row.querySelector('[aria-label="Reflection model"]')).not.toBeNull();
  });

  it('names the thread’s own CLI while no agent is picked', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render();

    expect(agentOf().textContent).toContain('Same CLI as the thread');
  });

  it('is read-only on a paired device, which may not choose what a reflection spends', async () => {
    install(DEFAULT_SETTINGS.lessons);
    await render(true);

    expect(modeOf().disabled).toBe(true);
    expect(agentOf().disabled).toBe(true);
  });
});
