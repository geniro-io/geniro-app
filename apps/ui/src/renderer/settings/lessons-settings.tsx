import { useContext, useEffect, useState } from 'react';

import {
  DEFAULT_LESSONS,
  type LessonsMode,
  type LessonsSettings,
} from '../../shared/contracts';
import { AgentIdentityContext, agentShortName } from '../agent-identity';
import type { AgentKind, CapabilitiesDto } from '../autogenerated';
import { useAgentEfforts } from '../chats/use-agent-efforts';
import { useAgentModels } from '../chats/use-agent-models';
import { ErrorBanner } from '../components/error-banner';
import { SettingsPanel, SettingsPanelRow } from '../components/settings-panel';
import { Select } from '../components/ui/select';
import type { DaemonApis } from '../daemon-api';

const THREAD_CLI = '__thread__';
const CLI_DEFAULT = '__default__';

const MODES: { value: LessonsMode; label: string }[] = [
  { value: 'offer', label: 'Offer me, run when I press' },
  { value: 'off', label: 'Off' },
];

/**
 * Settings → Memory → Lessons: whether threads are offered a reflection, and
 * the agent, model and effort one runs as. Desktop only — the choice decides
 * what a reflection spends — so a paired device sees it read-only.
 */
export function LessonsSettingsPanel({
  agentsApi,
  capabilities,
  remote,
}: {
  agentsApi: DaemonApis['agents'] | null;
  capabilities: CapabilitiesDto | null;
  remote: boolean;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  const [lessons, setLessons] = useState<LessonsSettings | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    void window.geniro
      .getSettings()
      .then((settings) => setLessons(settings.lessons))
      .catch((err: unknown) => setError(String(err)));
  }, []);

  const current = lessons ?? DEFAULT_LESSONS;
  const agentKind = (current.agentKind as AgentKind | null) ?? null;
  const models = useAgentModels(agentsApi, agentKind, null, current.model);
  const efforts = useAgentEfforts(agentsApi, agentKind, current.model, null);
  const disabled = lessons === null || remote;

  const save = (next: LessonsSettings): void => {
    const before = lessons;
    setLessons(next);
    setError(null);
    void window.geniro
      .updateSettings({ lessons: next })
      .catch((err: unknown) => {
        setLessons(before);
        setError(String(err));
      });
  };

  const agents = capabilities?.agents ?? [];

  return (
    <SettingsPanel>
      <SettingsPanelRow
        layout="block"
        label="Lessons"
        description="Reflect now on a thread proposes at most three lessons from what went wrong in it. Nothing reaches agents until you save a lesson.">
        {error === null ? null : (
          <ErrorBanner
            message={error}
            size="sm"
            onDismiss={() => setError(null)}
          />
        )}
      </SettingsPanelRow>
      <SettingsPanelRow
        label="Reflections"
        htmlFor="settings-lessons-mode"
        description="Reflect now works either way; Off keeps reflections from being offered.">
        <Select
          id="settings-lessons-mode"
          aria-label="Reflections"
          className="w-56"
          value={current.mode}
          disabled={disabled}
          groups={[{ label: 'Reflections', items: MODES }]}
          onValueChange={(value) =>
            save({ ...current, mode: value as LessonsMode })
          }
        />
      </SettingsPanelRow>
      <SettingsPanelRow
        layout="block"
        label="Reflection agent"
        htmlFor="settings-lessons-agent"
        description="Which CLI, model and effort a reflection runs as. A reflection's cost shows on its lessons card and under Lessons in Stats.">
        <div className="flex min-w-0 flex-wrap items-center justify-start gap-1">
          <Select
            id="settings-lessons-agent"
            aria-label="Reflection agent"
            className="w-48"
            value={agentKind ?? THREAD_CLI}
            disabled={disabled}
            groups={[
              {
                items: [
                  { value: THREAD_CLI, label: 'Same CLI as the thread' },
                  ...agents.map((agent) => ({
                    value: agent.agent,
                    label: agentShortName(identities, agent.agent),
                  })),
                ],
              },
            ]}
            onValueChange={(value) =>
              save({
                ...current,
                agentKind: value === THREAD_CLI ? null : value,
                model: null,
                effort: null,
              })
            }
          />
          {agentKind === null ? null : (
            <>
              <Select
                aria-label="Reflection model"
                className="w-48"
                value={current.model ?? CLI_DEFAULT}
                disabled={disabled || models.loading}
                groups={[
                  {
                    items: [
                      { value: CLI_DEFAULT, label: "The CLI's default model" },
                      ...models.models.map((model) => ({
                        value: model.id,
                        label: model.label,
                      })),
                    ],
                  },
                ]}
                onValueChange={(value) =>
                  save({
                    ...current,
                    model: value === CLI_DEFAULT ? null : value,
                    effort: null,
                  })
                }
              />
              {efforts.efforts.length === 0 ? null : (
                <Select
                  aria-label="Reflection effort"
                  className="w-36"
                  value={current.effort ?? CLI_DEFAULT}
                  disabled={disabled}
                  groups={[
                    {
                      items: [
                        { value: CLI_DEFAULT, label: 'Default effort' },
                        ...efforts.efforts.map((effort) => ({
                          value: effort.id,
                          label: effort.label,
                        })),
                      ],
                    },
                  ]}
                  onValueChange={(value) =>
                    save({
                      ...current,
                      effort: value === CLI_DEFAULT ? null : value,
                    })
                  }
                />
              )}
            </>
          )}
        </div>
      </SettingsPanelRow>
    </SettingsPanel>
  );
}
