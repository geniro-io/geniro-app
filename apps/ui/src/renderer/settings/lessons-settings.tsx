import { useEffect, useState } from 'react';

import {
  DEFAULT_LESSONS,
  type LessonsMode,
  type LessonsQuietWindowHours,
  type LessonsSettings,
} from '../../shared/contracts';
import type { AgentKind, CapabilitiesDto } from '../autogenerated';
import {
  CLI_DEFAULT_VALUE,
  LessonModelPicker,
} from '../chats/lesson-model-picker';
import { useAgentEfforts } from '../chats/use-agent-efforts';
import { ErrorBanner } from '../components/error-banner';
import { SettingsPanel, SettingsPanelRow } from '../components/settings-panel';
import { Select } from '../components/ui/select';
import type { DaemonApis } from '../daemon-api';

const MODES: { value: LessonsMode; label: string }[] = [
  { value: 'offer', label: 'Offer me, run when I press' },
  { value: 'off', label: 'Off' },
];

const QUIET_WINDOWS: { hours: LessonsQuietWindowHours; label: string }[] = [
  { hours: 1, label: '1 h' },
  { hours: 3, label: '3 h' },
  { hours: 6, label: '6 h' },
];

/**
 * Settings → Memory → Lessons: whether threads are offered a reflection, the
 * agent, model and effort one runs as, and how long a thread left open must
 * stay quiet before it is offered. Desktop only — the choice decides what a
 * reflection spends — so a paired device sees it read-only.
 */
export function LessonsSettingsPanel({
  agentsApi,
  capabilities,
  remote,
}: {
  agentsApi: DaemonApis['agents'] | null;
  capabilities: CapabilitiesDto | null;
  remote: boolean;
}): React.JSX.Element {
  const [lessons, setLessons] = useState<LessonsSettings | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    void window.geniro
      .getSettings()
      .then((settings) => setLessons(settings.lessons))
      .catch((err: unknown) => setError(String(err)));
  }, []);

  const current = lessons ?? DEFAULT_LESSONS;
  const agentKind = (current.agentKind as AgentKind | null) ?? null;
  const efforts = useAgentEfforts(agentsApi, agentKind, current.model, null);
  const disabled = lessons === null || remote;

  const save = (next: LessonsSettings): void => {
    const before = lessons;
    setLessons(next);
    setError(null);
    void window.geniro
      .updateSettings({ lessons: next })
      .catch((err: unknown) => {
        setLessons(before);
        setError(String(err));
      });
  };

  return (
    <SettingsPanel>
      <SettingsPanelRow
        layout="block"
        label="Lessons"
        description="Reflect now on a thread proposes at most three lessons from what went wrong in it. Nothing reaches agents until you save a lesson.">
        {error === null ? null : (
          <ErrorBanner
            message={error}
            size="sm"
            onDismiss={() => setError(null)}
          />
        )}
      </SettingsPanelRow>
      <SettingsPanelRow
        label="Reflections"
        htmlFor="settings-lessons-mode"
        description="Reflect now works either way; Off keeps reflections from being offered.">
        <Select
          id="settings-lessons-mode"
          aria-label="Reflections"
          className="w-56"
          value={current.mode}
          disabled={disabled}
          groups={[{ label: 'Reflections', items: MODES }]}
          onValueChange={(value) =>
            save({ ...current, mode: value as LessonsMode })
          }
        />
      </SettingsPanelRow>
      <SettingsPanelRow
        label="Left-open quiet window"
        htmlFor="settings-lessons-quiet"
        description="How long a thread left open must sit quiet before its lessons are offered.">
        <Select
          id="settings-lessons-quiet"
          aria-label="Left-open quiet window"
          className="w-56"
          value={String(current.quietWindowHours)}
          disabled={disabled}
          groups={[
            {
              items: QUIET_WINDOWS.map((window) => ({
                value: String(window.hours),
                label: window.label,
              })),
            },
          ]}
          onValueChange={(value) => {
            const picked = QUIET_WINDOWS.find(
              (window) => String(window.hours) === value,
            );
            if (picked) {
              save({ ...current, quietWindowHours: picked.hours });
            }
          }}
        />
      </SettingsPanelRow>
      <SettingsPanelRow
        layout="block"
        label="Reflection agent"
        htmlFor="settings-lessons-agent"
        description="Which CLI, model and effort a reflection runs as. A reflection's cost shows on its lessons card and under Lessons in Stats.">
        <div className="flex min-w-0 flex-wrap items-center justify-start gap-1">
          <LessonModelPicker
            idPrefix="settings-lessons"
            value={{ agentKind, model: current.model }}
            agentsApi={agentsApi}
            capabilities={capabilities}
            disabled={disabled}
            onChange={(choice) => save({ ...current, ...choice, effort: null })}
          />
          {agentKind === null || efforts.efforts.length === 0 ? null : (
            <Select
              aria-label="Reflection effort"
              className="w-36"
              value={current.effort ?? CLI_DEFAULT_VALUE}
              disabled={disabled}
              groups={[
                {
                  items: [
                    { value: CLI_DEFAULT_VALUE, label: 'Default effort' },
                    ...efforts.efforts.map((effort) => ({
                      value: effort.id,
                      label: effort.label,
                    })),
                  ],
                },
              ]}
              onValueChange={(value) =>
                save({
                  ...current,
                  effort: value === CLI_DEFAULT_VALUE ? null : value,
                })
              }
            />
          )}
        </div>
      </SettingsPanelRow>
    </SettingsPanel>
  );
}
