import { useContext } from 'react';

import type { CliKind, ConfigProfile } from '../../shared/contracts';
import { AgentIdentityContext, agentShortName } from '../agent-identity';
import type { AgentKind, CapabilitiesDto } from '../autogenerated';
import { withModelParameter } from '../chats/model-parameter-select';
import { ModelSettingsSelect } from '../chats/model-settings-select';
import { useAgentContextWindows } from '../chats/use-agent-context-windows';
import { useAgentEfforts } from '../chats/use-agent-efforts';
import { useAgentModelParameters } from '../chats/use-agent-model-parameters';
import { useAgentModels } from '../chats/use-agent-models';
import { Select } from '../components/ui/select';
import type { DaemonApis } from '../daemon-api';
import { configDirCapabilityFrom } from '../workflows/use-config-dir-capability';

/** The agent that sorts the import and everything it runs with, as a chat. */
export interface MemoryTriageChoice {
  agentKind: AgentKind;
  model: string | null;
  effort: string | null;
  contextWindow: string | null;
  modelParameters: Record<string, string>;
  configDir: string | null;
}

const NO_RECENTS: readonly string[] = [];

export function blankTriageChoice(agentKind: AgentKind): MemoryTriageChoice {
  return {
    agentKind,
    model: null,
    effort: null,
    contextWindow: null,
    modelParameters: {},
    configDir: null,
  };
}

/** The choice to run with: the one made, unless its agent cannot sort. */
export function triageChoiceFor(
  agents: readonly AgentKind[],
  choice: MemoryTriageChoice | null,
): MemoryTriageChoice | null {
  if (choice !== null && agents.includes(choice.agentKind)) {
    return choice;
  }
  return agents.length === 0 ? null : blankTriageChoice(agents[0]!);
}

export function MemoryTriageSettings({
  agents,
  value,
  onChange,
  agentsApi,
  capabilities,
  capabilitiesLoading,
  recentConfigDirs,
  configProfiles,
}: {
  agents: readonly AgentKind[];
  value: MemoryTriageChoice;
  onChange: (next: MemoryTriageChoice) => void;
  agentsApi: DaemonApis['agents'] | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  recentConfigDirs: Partial<Record<CliKind, readonly string[]>>;
  configProfiles: readonly ConfigProfile[];
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  const { agentKind, model, configDir } = value;
  const models = useAgentModels(agentsApi, agentKind, configDir, model);
  const efforts = useAgentEfforts(agentsApi, agentKind, model, configDir);
  const windows = useAgentContextWindows(
    agentsApi,
    agentKind,
    model,
    configDir,
  );
  const parameters = useAgentModelParameters(
    agentsApi,
    agentKind,
    model,
    configDir,
  );
  const configDirCapability = configDirCapabilityFrom(
    capabilities,
    capabilitiesLoading,
  );
  const patch = (next: Partial<MemoryTriageChoice>): void =>
    onChange({ ...value, ...next });
  const pickConfigDir = async (): Promise<void> => {
    const chosen = await window.geniro.pickProjectFolder();
    if (chosen) {
      patch({ configDir: chosen });
    }
  };

  return (
    <div
      data-slot="memory-triage-settings"
      className="flex min-w-0 flex-wrap items-center gap-1">
      {agents.length > 1 ? (
        <Select
          variant="ghost"
          aria-label="Agent that sorts"
          groups={[
            {
              items: agents.map((kind) => ({
                value: kind,
                label: agentShortName(identities, kind),
              })),
            },
          ]}
          value={agentKind}
          onValueChange={(next) => {
            const kind = agents.find((candidate) => candidate === next);
            if (kind !== undefined && kind !== agentKind) {
              onChange(blankTriageChoice(kind));
            }
          }}
        />
      ) : (
        <span className="text-xs text-muted-foreground">
          with {agentShortName(identities, agentKind)}
        </span>
      )}
      <ModelSettingsSelect
        agentKind={agentKind}
        models={models.models}
        model={model}
        onModelChange={(next) =>
          patch({ model: next, contextWindow: null, modelParameters: {} })
        }
        efforts={efforts.efforts}
        effort={value.effort}
        onEffortChange={(next) => patch({ effort: next })}
        approvalCapability={undefined}
        approval={null}
        onApprovalChange={() => undefined}
        windows={windows.windows}
        contextWindow={value.contextWindow}
        onContextWindowChange={(next) => patch({ contextWindow: next })}
        parameters={parameters.parameters}
        parameterValues={value.modelParameters}
        onParameterChange={(parameterId, next) =>
          patch({
            modelParameters: withModelParameter(
              value.modelParameters,
              parameterId,
              next,
            ),
          })
        }
        configDir={configDir}
        recentConfigDirs={recentConfigDirs[agentKind] ?? NO_RECENTS}
        configProfiles={configProfiles.filter(
          (profile) => profile.agent === agentKind,
        )}
        configDirUnavailableReason={configDirCapability.unavailableReasonFor(
          agentKind,
        )}
        onConfigDirChange={(next) => patch({ configDir: next })}
        onBrowseConfigDir={() => void pickConfigDir()}
        loading={models.loading}
        settingsLoading={
          efforts.loading || windows.loading || parameters.loading
        }
      />
    </div>
  );
}
