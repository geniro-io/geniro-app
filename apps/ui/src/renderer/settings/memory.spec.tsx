describe('importProfiles', () => {
  it('collects every profile settings names, per CLI kind, each once', () => {
    expect(
      importProfiles({
        configDirs: { claude: '/p/work' },
        recentConfigDirs: { claude: ['/p/work', '/p/old'], codex: ['/c/x'] },
        configProfiles: [
          { id: 'a', name: 'A', agent: 'claude', dir: '/p/old', color: 'blue' },
          {
            id: 'b',
            name: 'B',
            agent: 'codex',
            dir: 'relative',
            color: 'blue',
          },
        ],
      }),
    ).toEqual([
      { agentKind: 'claude', dir: '/p/work' },
      { agentKind: 'claude', dir: '/p/old' },
      { agentKind: 'codex', dir: '/c/x' },
    ]);
  });

  it('adds every team agent’s and pool member’s profile after the settings ones', () => {
    const team = {
      members: [
        {
          id: 'a',
          name: 'A',
          agent: 'claude',
          configDir: '/p/work',
          pool: [{ agent: 'codex', configDir: '/c/pool' }, { agent: 'codex' }],
        },
      ],
    } as unknown as Team;

    expect(
      importProfiles(
        {
          configDirs: { claude: '/p/work' },
          recentConfigDirs: {},
          configProfiles: [],
        },
        [team],
      ),
    ).toEqual([
      { agentKind: 'claude', dir: '/p/work' },
      { agentKind: 'codex', dir: '/c/pool' },
    ]);
  });
});

