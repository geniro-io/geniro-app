function fakeClient() {
  const listeners = new Set<(event: MemoryChangedEvent) => void>();
  return {
    onMemoryChanged: (listener: (event: MemoryChangedEvent) => void) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    announce: (event: MemoryChangedEvent) =>
      listeners.forEach((listener) => listener(event)),
  };
}

async function settle(ms = 0): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, ms));
  });
}

async function render(
  props: Partial<React.ComponentProps<typeof Memory>> = {},
): Promise<ReturnType<typeof fakeApi>> {
  const api = (props.api as ReturnType<typeof fakeApi>) ?? fakeApi();
  await act(async () => {
    root.render(
      <Memory
        api={api}
        client={null}
        projects={MEMORY_PROJECTS}
        remote={false}
        {...props}
      />,
    );
  });
  await settle();
  return api;
}

function rowOf(handle: string): HTMLElement {
  const row = container.querySelector<HTMLElement>(
    `[data-memory-handle="${handle}"]`,
  );
  if (!row) {
    throw new Error(`no row ${handle}`);
  }
  return row;
}

function button(scope: ParentNode, label: string): HTMLButtonElement {
  const found = [...scope.querySelectorAll('button')].find(
    (candidate) => candidate.textContent?.trim() === label,
  );
  if (!found) {
    throw new Error(`no button "${label}"`);
  }
  return found;
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
  await settle();
}

async function type(input: HTMLInputElement, value: string): Promise<void> {
  const setter = Object.getOwnPropertyDescriptor(
    HTMLInputElement.prototype,
    'value',
  )?.set;
  await act(async () => {
    setter?.call(input, value);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

async function choose(label: string, option: string): Promise<void> {
  const trigger = container.querySelector<HTMLElement>(
    `[data-menu-trigger][aria-label="${label}"]`,
  );
  if (!trigger) {
    throw new Error(`no select ${label}`);
  }
  await press(trigger);
  const item = [
    ...document.querySelectorAll<HTMLElement>('[role="option"]'),
  ].find((candidate) => candidate.textContent?.trim() === option);
  if (!item) {
    throw new Error(`no option ${option}`);
  }
  await press(item);
}

