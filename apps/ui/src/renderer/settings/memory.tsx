/**
 * The handles a near-duplicate refusal names, so a "Save anyway" vouches past
 * exactly those; null for any other refusal.
 *
 * TWIN PARSER: `NEAR_DUPLICATE_PREFIX` in
 * `apps/daemon/src/v1/memory/utils/memory-outcome.ts`.
 */
export function nearDuplicateHandles(err: unknown): string[] | null {
  if (daemonErrorCode(err) !== 'MEMORY_NEAR_DUPLICATE') {
    return null;
  }
  const detail = daemonErrorDetail(err) ?? '';
  const prefix = 'similar entries exist: ';
  if (!detail.startsWith(prefix)) {
    return null;
  }
  return detail
    .slice(prefix.length)
    .split(',')
    .map((handle) => handle.trim())
    .filter((handle) => /^m\d+$/.test(handle));
}

/**
 * Every CLI profile settings.json names, then every profile a library
 * team's agent or pool member runs on, for the import to read beside each
 * CLI's default one. The daemon decides which CLI keeps memory there.
 */
export function importProfiles(
  settings: Pick<
    AppSettings,
    'configDirs' | 'recentConfigDirs' | 'configProfiles'
  >,
  teams: readonly Team[] = [],
): ImportProfile[] {
  const seen = new Set<string>();
  const out: ImportProfile[] = [];
  const add = (
    agentKind: ImportProfile['agentKind'],
    dir: string | undefined,
  ) => {
    if (!dir?.startsWith('/') || seen.has(`${agentKind}\n${dir}`)) {
      return;
    }
    seen.add(`${agentKind}\n${dir}`);
    out.push({ agentKind, dir });
  };
  for (const kind of CLI_KINDS) {
    add(kind, settings.configDirs[kind]);
    for (const dir of settings.recentConfigDirs[kind] ?? []) {
      add(kind, dir);
    }
  }
  for (const profile of settings.configProfiles) {
    add(profile.agent, profile.dir);
  }
  for (const team of teams) {
    for (const node of team.nodes) {
      if (node.kind !== 'agent') {
        continue;
      }
      add(node.agent, node.configDir);
      for (const member of node.pool ?? []) {
        add(member.agent, member.configDir);
      }
    }
  }
  return out.slice(0, IMPORT_PROFILES_MAX);
}

async function libraryTeams(teams: TeamsClient | null): Promise<Team[]> {
  if (teams === null) {
    return [];
  }
  const summaries = await teams.listTeams().catch(() => []);
  const files = await Promise.allSettled(
    summaries.map((summary) => teams.getTeam({ slug: summary.slug })),
  );
  return files.flatMap((file) =>
    file.status === 'fulfilled' ? [file.value.team] : [],
  );
}

function plural(count: number, one: string, many: string): string {
  return `${count} ${count === 1 ? one : many}`;
}

/** What an import did, in one line: what landed, what was left out, and the switch it flipped. */
export function importNote({
  imported,
  skipped,
  unimportable,
  switchedNativeOff,
}: {
  imported: number;
  skipped: readonly MemoryImportResultDto['skipped'][number][];
  unimportable: number;
  switchedNativeOff: boolean;
}): string {
  const parts = [`Imported ${plural(imported, 'note', 'notes')}`];
  if (skipped.length > 0) {
    parts.push(
      `${skipped.length} skipped (${skipped
        .map((skip) => skip.reason)
        .slice(0, 3)
        .join('; ')})`,
    );
  }
  if (unimportable > 0) {
    parts.push(
      `${plural(unimportable, 'note', 'notes')} could not be imported`,
    );
  }
  const line = `${parts.join('; ')}.`;
  return switchedNativeOff
    ? `${line} Each CLI's own memory is now off for new chats, so they use only this one.`
    : line;
}

function listRequest(
  filters: Filters,
  focus: string | null,
): MemoriesApiListMemoriesRequest {
  if (focus !== null) {
    return { handle: focus };
  }
  const q = filters.q.trim();
  const status = statusOf(filters.status);
  const type = typeOf(filters.type);
  return {
    ...(status === undefined ? {} : { status }),
    ...(filters.scope === ALL_SCOPES
      ? {}
      : filters.scope === GLOBAL_SCOPE
        ? { scope: 'global' }
        : { scope: 'project', projectId: filters.scope }),
    ...(type === undefined ? {} : { type }),
    ...(q === '' ? {} : { q }),
  };
}

function emptyValue(projectId: string | null): MemoryFormValue {
  return { title: '', body: '', type: 'project', projectId };
}

/**
 * Settings → Memory: the one memory every agent shares — whether agents get
 * it, whether their writes wait for review, and every entry with its edit,
 * forget, restore and approve. Readable and editable from a paired phone; the
 * import and the export file are the Mac's.
 */
export function Memory({
  api,
  client,
  teams = null,
  projects,
  focus = null,
  onFocusDone,
  remote = isRemoteRuntime(),
  agentsApi = null,
  capabilities = null,
  capabilitiesLoading = false,
}: {
  api: MemoriesClient | null;
  client: Pick<DaemonClient, 'onMemoryChanged'> | null;
  /** The team library, whose agents' profiles the import reads too. */
  teams?: TeamsClient | null;
  projects: readonly ProjectOption[];
  /** An entry's handle (`m12`) to show alone, as a transcript row asks. */
  focus?: string | null;
  onFocusDone?: () => void;
  remote?: boolean;
  /** What the AI sort's model settings are listed from, as a chat's are. */
  agentsApi?: DaemonApis['agents'] | null;
  capabilities?: CapabilitiesDto | null;
  capabilitiesLoading?: boolean;
}): React.JSX.Element {
  const [memory, setMemory] = useState<MemorySettings | null>(null);
  const [profiles, setProfiles] = useState<ImportProfile[]>([]);
  const [filters, setFilters] = useState<Filters>(NO_FILTERS);
  const [entries, setEntries] = useState<MemoryEntry[]>([]);
  const [next, setNext] = useState<{
    beforeUpdatedAt: string;
    beforeId: string;
  } | null>(null);
  const [pending, setPending] = useState<MemoryEntry[]>([]);
  const [pendingCut, setPendingCut] = useState(false);
  const [loaded, setLoaded] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [editing, setEditing] = useState<Editing | null>(null);
  const [formError, setFormError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);
  const [busy, setBusy] = useState<string | null>(null);
  const [importOpen, setImportOpen] = useState(false);
  const [preview, setPreview] = useState<MemoryImportPreviewDto | null>(null);
  const [previewing, setPreviewing] = useState(false);
  const [importError, setImportError] = useState<string | null>(null);
  const [importing, setImporting] = useState(false);
  const [note, setNote] = useState<string | null>(null);
  const [triagePick, setTriagePick] = useState<MemoryTriageConfig | null>(null);
  const [triageProfiles, setTriageProfiles] = useState<
    Pick<AppSettings, 'recentConfigDirs' | 'configProfiles'>
  >({ recentConfigDirs: {}, configProfiles: [] });
  const triageAgents = preview?.triageAgents ?? NO_TRIAGE_AGENTS;
  const triageChoice = triageChoiceFor(triageAgents, triagePick);
  const triage = useMemoryTriage(api, triageChoice);

  const projectName = useLatestCallback(
    (projectId: string | null) =>
      projectId === null
        ? null
        : (projects.find((project) => project.id === projectId)?.name ?? null),
    [projects],
  );

  const generation = useRef(0);
  const cursorGeneration = useRef(0);
  const depth = useRef(0);
  const [loadingMore, setLoadingMore] = useState(false);
  const read = useLatestCallback(() => {
    if (api === null) {
      return;
    }
    const mine = ++generation.current;
    const limit = Math.min(
      Math.max(depth.current, MEMORY_PAGE),
      MEMORY_PAGE_MAX,
    );
    const lists = Promise.all([
      api.listMemories({ ...listRequest(filters, focus), limit }),
      focus === null
        ? api.listMemories({ status: 'pending', limit: PENDING_LIMIT })
        : Promise.resolve(null),
    ]);
    void lists
      .then(([page, waiting]) => {
        if (mine !== generation.current) {
          return;
        }
        setEntries(page.memories);
        depth.current = page.memories.length;
        cursorGeneration.current = mine;
        setNext(page.next);
        setPending(waiting?.memories ?? []);
        setPendingCut(waiting !== null && waiting.next !== null);
        setLoaded(true);
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setError(describeDaemonError(err));
        }
      });
  }, [api, filters, focus]);

  useEffect(() => {
    depth.current = 0;
    const timer = setTimeout(read, filters.q === '' ? 0 : REFRESH_DELAY_MS);
    return () => clearTimeout(timer);
  }, [read, filters.q]);

  useEffect(() => {
    if (client === null) {
      return;
    }
    let timer: ReturnType<typeof setTimeout> | null = null;
    const off = client.onMemoryChanged(() => {
      if (timer !== null) {
        clearTimeout(timer);
      }
      timer = setTimeout(read, REFRESH_DELAY_MS);
    });
    return () => {
      off();
      if (timer !== null) {
        clearTimeout(timer);
      }
    };
  }, [client, read]);

  useEffect(() => {
    void window.geniro
      .getSettings()
      .then((settings) => setMemory(settings.memory))
      .catch((err: unknown) => setError(String(err)));
  }, []);

  const current = memory ?? DEFAULT_MEMORY;

  const saveSettings = (nextMemory: MemorySettings): void => {
    const before = memory;
    setMemory(nextMemory);
    setError(null);
    void window.geniro
      .updateSettings({ memory: nextMemory })
      .catch((err: unknown) => {
        setMemory(before);
        setError(String(err));
      });
  };

  const pickTriage = (next: MemoryTriageConfig): void => {
    setTriagePick(next);
    void window.geniro
      .updateSettings({ lastMemoryTriage: next })
      .catch(() => undefined);
  };

  const loadMore = (): void => {
    if (api === null || next === null) {
      return;
    }
    const mine = cursorGeneration.current;
    setLoadingMore(true);
    void api
      .listMemories({ ...listRequest(filters, focus), ...next })
      .then((page) => {
        if (mine !== generation.current) {
          return;
        }
        setEntries((all) => {
          const more = [...all, ...page.memories];
          depth.current = more.length;
          return more;
        });
        setNext(page.next);
      })
      .catch((err: unknown) => setError(describeDaemonError(err)))
      .finally(() => setLoadingMore(false));
  };

  const act = async (id: string, work: () => Promise<unknown>) => {
    setBusy(id);
    setError(null);
    try {
      await work();
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    } finally {
      setBusy(null);
      read();
    }
  };

  const setStatus = (entry: MemoryEntry, status: 'active' | 'forgotten') =>
    act(entry.id, () =>
      api!.updateMemory({ memoryId: entry.id, updateMemoryDto: { status } }),
    );

  const submit = async (): Promise<void> => {
    if (api === null || editing === null) {
      return;
    }
    setSaving(true);
    setFormError(null);
    const { value, vouched } = editing;
    const notDuplicateOf = vouched.length > 0 ? vouched : undefined;
    try {
      if (editing.kind === 'new') {
        await api.createMemory({
          createMemoryDto: { ...value, notDuplicateOf },
        });
      } else {
        await api.updateMemory({
          memoryId: editing.entry.id,
          updateMemoryDto: { ...value, rev: editing.entry.rev, notDuplicateOf },
        });
      }
      setEditing(null);
      read();
    } catch (err: unknown) {
      const similar = nearDuplicateHandles(err);
      if (similar !== null && similar.length > 0) {
        setEditing({ ...editing, vouched: similar });
        setFormError(
          `Similar entries exist: ${similar.join(', ')}. Save again to keep this one anyway.`,
        );
      } else {
        setFormError(describeDaemonError(err));
      }
    } finally {
      setSaving(false);
    }
  };

  const forgetAll = async (): Promise<void> => {
    if (api === null) {
      return;
    }
    try {
      const { forgotten } = await api.forgetAllMemories();
      setNote(
        `Forgot ${forgotten} ${forgotten === 1 ? 'entry' : 'entries'} — each can be restored from Forgotten.`,
      );
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    }
    read();
  };

  const exportAll = async (): Promise<void> => {
    if (api === null) {
      return;
    }
    try {
      const { markdown } = await api.exportMemories();
      const saved = await window.geniro.saveMemoryExport(markdown);
      if (saved.saved) {
        setNote(`Saved to ${saved.path}`);
      }
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    }
  };

  const openImport = (): void => {
    if (api === null) {
      return;
    }
    setImportOpen(true);
    setPreview(null);
    setImportError(null);
    setPreviewing(true);
    void Promise.all([window.geniro.getSettings(), libraryTeams(teams)])
      .then(([settings, library]) => {
        const found = importProfiles(settings, library);
        setProfiles(found);
        setTriageProfiles({
          recentConfigDirs: settings.recentConfigDirs,
          configProfiles: settings.configProfiles,
        });
        setTriagePick((current) => current ?? settings.lastMemoryTriage);
        return api.previewMemoryImport({
          memoryImportPreviewRequestDto: { profiles: found },
        });
      })
      .then(setPreview)
      .catch((err: unknown) => setImportError(describeDaemonError(err)))
      .finally(() => setPreviewing(false));
  };

  const switchNativeMemoryOff = async (): Promise<boolean> => {
    try {
      const fresh = (await window.geniro.getSettings()).memory;
      if (fresh.nativeMemoryOff) {
        setMemory(fresh);
        return false;
      }
      const flipped = { ...fresh, nativeMemoryOff: true };
      await window.geniro.updateSettings({ memory: flipped });
      setMemory(flipped);
      return true;
    } catch (err: unknown) {
      setError(String(err));
      return false;
    }
  };

  const runImport = async (rows: MemoryImportChoice[]): Promise<void> => {
    if (api === null) {
      return;
    }
    setImporting(true);
    setImportError(null);
    const results: MemoryImportResultDto[] = [];
    let failure: string | null = null;
    try {
      for (let at = 0; at < rows.length; at += IMPORT_BATCH) {
        results.push(
          await api.importMemories({
            importMemoriesDto: {
              profiles,
              rows: rows.slice(at, at + IMPORT_BATCH),
            },
          }),
        );
      }
    } catch (err: unknown) {
      failure = describeDaemonError(err);
    }
    const imported = results.reduce((sum, r) => sum + r.imported, 0);
    if (results.length > 0) {
      const switchedNativeOff = imported > 0 && (await switchNativeMemoryOff());
      setNote(
        importNote({
          imported,
          skipped: results.flatMap((r) => r.skipped),
          unimportable:
            preview?.rows.filter((row) => row.problem !== null).length ?? 0,
          switchedNativeOff,
        }),
      );
      read();
    }
    if (failure === null) {
      setImportOpen(false);
    } else {
      setImportError(
        results.length > 0
          ? `${failure} — the notes sent before it were imported.`
          : failure,
      );
    }
    setImporting(false);
  };

  const waitingShown =
    focus === null && filters.status === LIVE && pending.length > 0;
  const shown = waitingShown
    ? entries.filter((entry) => entry.status !== 'pending')
    : entries;

  const scopeGroups = [
    {
      label: 'Scope',
      items: [
        { value: ALL_SCOPES, label: 'Every scope' },
        { value: GLOBAL_SCOPE, label: 'Global' },
        ...projects.map((project) => ({
          value: project.id,
          label: project.name,
        })),
      ],
    },
  ];

  const row = (entry: MemoryEntry) =>
    editing?.kind === 'edit' && editing.entry.id === entry.id ? (
      <MemoryForm
        value={editing.value}
        projects={projects}
        saving={saving}
        error={formError}
        submitLabel="Save"
        onChange={(value) => setEditing({ ...editing, value, vouched: [] })}
        onSubmit={() => void submit()}
        onCancel={() => {
          setEditing(null);
          setFormError(null);
        }}
      />
    ) : (
      <MemoryRow
        entry={entry}
        projectName={projectName(entry.projectId)}
        focused={focus !== null && entry.handle === focus}
        busy={busy === entry.id}
        onEdit={
          entry.status === 'forgotten'
            ? undefined
            : () => {
                setFormError(null);
                setEditing({
                  kind: 'edit',
                  entry,
                  vouched: [],
                  value: {
                    title: entry.title,
                    body: entry.body,
                    type: entry.type,
                    projectId: entry.projectId,
                  },
                });
              }
        }
        onForget={
          entry.status === 'forgotten'
            ? undefined
            : () => void setStatus(entry, 'forgotten')
        }
        onRestore={
          entry.status === 'forgotten'
            ? () => void setStatus(entry, 'active')
            : undefined
        }
        onApprove={
          awaitsApproval(entry)
            ? () => void setStatus(entry, 'active')
            : undefined
        }
      />
    );

  return (
    <div data-slot="memory" className="flex flex-col gap-3">
      {error !== null && (
        <ErrorBanner message={error} onDismiss={() => setError(null)} />
      )}
      {note !== null && (
        <p className="text-xs text-muted-foreground" role="status">
          {note}
        </p>
      )}

      <SettingsPanel>
        <SettingsPanelRow
          label="Shared memory"
          htmlFor="settings-memory-enabled"
          description="Agents read and save notes in one memory, whatever their CLI. Off, agents get no memory tools — the entries below stay here to edit.">
          <Switch
            id="settings-memory-enabled"
            checked={current.enabled}
            disabled={memory === null}
            onCheckedChange={(on) => saveSettings({ ...current, enabled: on })}
          />
        </SettingsPanelRow>
        <SettingsPanelRow
          label="Agent notes"
          htmlFor="settings-memory-agent-writes"
          description="Whether an agent's new note is used at once or waits below for you.">
          <Select
            id="settings-memory-agent-writes"
            aria-label="What happens to an agent's note"
            className="w-48"
            value={current.agentWrites}
            disabled={memory === null}
            groups={[{ label: 'Agent notes', items: AGENT_WRITES }]}
            onValueChange={(value) =>
              saveSettings({
                ...current,
                agentWrites: value as MemorySettings['agentWrites'],
              })
            }
          />
        </SettingsPanelRow>
        <SettingsPanelRow
          label="Each CLI's own memory off"
          htmlFor="settings-memory-native-off"
          description="New chats use only this memory, not the notes each CLI keeps itself. Import those first; a successful import turns this on.">
          <Switch
            id="settings-memory-native-off"
            checked={current.nativeMemoryOff}
            disabled={memory === null || !current.enabled}
            onCheckedChange={(on) =>
              saveSettings({ ...current, nativeMemoryOff: on })
            }
          />
        </SettingsPanelRow>
      </SettingsPanel>

      {waitingShown ? (
        <SettingsPanel>
          <SettingsPanelRow
            layout="block"
            label={`Waiting for review (${pending.length}${pendingCut ? '+' : ''})`}>
            <p className="text-xs text-muted-foreground">
              Agents saved these while their notes wait for you. Only what you
              approve goes into every new chat's memory index.
            </p>
            <ul className="mt-2 flex flex-col gap-2">
              {pending.map((entry) => (
                <li key={entry.id}>{row(entry)}</li>
              ))}
            </ul>
            {pendingCut ? (
              <Button
                type="button"
                size="sm"
                variant="outline"
                className="mt-2 self-start"
                onClick={() => setFilters({ ...filters, status: 'pending' })}>
                Show every waiting entry
              </Button>
            ) : null}
          </SettingsPanelRow>
        </SettingsPanel>
      ) : null}

      <SettingsPanel>
        <SettingsPanelRow layout="block" label="Entries">
          {focus !== null ? (
            <div className="flex items-center gap-2 text-xs text-muted-foreground">
              <span>Showing {focus} only.</span>
              <Button
                type="button"
                size="sm"
                variant="outline"
                onClick={() => onFocusDone?.()}>
                Show all
              </Button>
            </div>
          ) : (
            <div className="flex flex-wrap items-center gap-2">
              <Input
                aria-label="Search memory"
                placeholder="Search"
                className="min-w-40 flex-1"
                value={filters.q}
                onChange={(event) =>
                  setFilters({ ...filters, q: event.target.value })
                }
              />
              <div className="w-44">
                <Select
                  aria-label="Status"
                  value={filters.status}
                  groups={[{ label: 'Status', items: STATUS_FILTERS }]}
                  onValueChange={(status) => setFilters({ ...filters, status })}
                />
              </div>
              <div className="w-40">
                <Select
                  aria-label="Scope"
                  value={filters.scope}
                  groups={scopeGroups}
                  onValueChange={(scope) => setFilters({ ...filters, scope })}
                />
              </div>
              <div className="w-36">
                <Select
                  aria-label="Type"
                  value={filters.type}
                  groups={[{ label: 'Type', items: TYPE_FILTERS }]}
                  onValueChange={(type) => setFilters({ ...filters, type })}
                />
              </div>
              {editing?.kind === 'new' ? null : (
                <Button
                  type="button"
                  size="sm"
                  disabled={api === null}
                  onClick={() => {
                    setFormError(null);
                    setEditing({
                      kind: 'new',
                      vouched: [],
                      value: emptyValue(null),
                    });
                  }}>
                  Add an entry
                </Button>
              )}
            </div>
          )}
          {editing?.kind === 'new' ? (
            <div className="mt-2">
              <MemoryForm
                value={editing.value}
                projects={projects}
                saving={saving}
                error={formError}
                submitLabel="Add"
                onChange={(value) =>
                  setEditing({ ...editing, value, vouched: [] })
                }
                onSubmit={() => void submit()}
                onCancel={() => {
                  setEditing(null);
                  setFormError(null);
                }}
              />
            </div>
          ) : null}
          {loaded && shown.length === 0 ? (
            <p className="mt-2 text-sm text-muted-foreground">
              {focus !== null
                ? `No entry ${focus}.`
                : sameFilters(filters, NO_FILTERS)
                  ? 'Nothing saved yet. Agents add notes as they work, or add one here.'
                  : 'No entry matches.'}
            </p>
          ) : (
            <ul className="mt-2 flex flex-col gap-2">
              {shown.map((entry) => (
                <li key={entry.id}>{row(entry)}</li>
              ))}
            </ul>
          )}
          {next !== null ? (
            <Button
              type="button"
              size="sm"
              variant="outline"
              className="mt-2 self-start"
              disabled={loadingMore}
              onClick={loadMore}>
              Show more
            </Button>
          ) : null}
        </SettingsPanelRow>
      </SettingsPanel>

      <SettingsPanel>
        {remote ? null : (
          <SettingsPanelRow
            label="Import"
            description="Bring the notes each CLI kept in its own memory into this one. You pick which; the CLIs' files are only read.">
            <Button
              type="button"
              size="sm"
              variant="outline"
              disabled={api === null}
              onClick={openImport}>
              Import…
            </Button>
          </SettingsPanelRow>
        )}
        {remote ? null : (
          <SettingsPanelRow
            label="Export"
            description="Every active and waiting entry as one Markdown file.">
            <Button
              type="button"
              size="sm"
              variant="outline"
              disabled={api === null}
              onClick={() => void exportAll()}>
              Export…
            </Button>
          </SettingsPanelRow>
        )}
        <SettingsPanelRow
          label="Forget all"
          description="Hide every entry from every agent. Each stays restorable under Forgotten.">
          <ConfirmButton
            size="sm"
            confirmLabel="Forget every entry?"
            disabled={api === null}
            onConfirm={() => forgetAll()}>
            Forget all
          </ConfirmButton>
        </SettingsPanelRow>
      </SettingsPanel>

      {remote ? null : (
        <MemoryImportDialog
          open={importOpen}
          onOpenChange={setImportOpen}
          preview={preview}
          loading={previewing}
          error={importError}
          importing={importing}
          projects={projects}
          onImport={(rows) => void runImport(rows)}
          triage={triage}
          triageSettings={
            triageChoice === null ? null : (
              <MemoryTriageSettings
                agents={triageAgents}
                value={triageChoice}
                onChange={pickTriage}
                agentsApi={agentsApi}
                capabilities={capabilities}
                capabilitiesLoading={capabilitiesLoading}
                recentConfigDirs={triageProfiles.recentConfigDirs}
                configProfiles={triageProfiles.configProfiles}
              />
            )
          }
        />
      )}
    </div>
  );
}
