function statusOf(value: string): MemoryEntryStatusEnum | undefined {
  return Object.values(MemoryEntryStatusEnum).find(
    (status) => status === value,
  );
}

function typeOf(value: string): MemoryEntryTypeEnum | undefined {
  return Object.values(MemoryEntryTypeEnum).find((type) => type === value);
}

function sameFilters(a: Filters, b: Filters): boolean {
  return (
    a.status === b.status &&
    a.scope === b.scope &&
    a.type === b.type &&
    a.q.trim() === b.q.trim()
  );
}

/** Whether only the user's approval admits this entry to the memory index. */
function awaitsApproval(entry: MemoryEntry): boolean {
  const byAgent =
    entry.source.actor === 'agent' || entry.source.actor === 'analysis';
  return (
    entry.status === 'pending' ||
    (entry.status === 'active' && byAgent && entry.approvedAt === null)
  );
}

