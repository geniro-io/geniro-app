// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { LessonSegment } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { NotReflectedPanel } from './not-reflected-panel';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

function segment(overrides: Partial<LessonSegment> = {}): LessonSegment {
  return {
    id: 'seg-1',
    runId: 'run-1',
    sourceTitle: 'Refactor the parser',
    archived: true,
    fromSeq: 1,
    toSeq: 40,
    closedBy: 'archive',
    closedAt: '2026-11-13T10:00:00.000Z',
    signals: [{ kind: 'user_correction', seq: 12 }],
    status: 'offered',
    reflectionRunId: null,
    estimate: {
      agentKind: 'claude',
      model: 'claude-haiku-5-5',
      tokens: 1200,
      usd: 0.5,
    },
    ...overrides,
  } as LessonSegment;
}

function fakeLessons(segments: LessonSegment[]) {
  const api = {
    listLessonSegments: vi.fn(() => Promise.resolve({ segments })),
    reflectLessons: vi.fn(() => Promise.resolve({})),
    dismissLessonSegment: vi.fn(() => Promise.resolve({})),
    reflectAllLessonSegments: vi.fn(() =>
      Promise.resolve({ started: 1, refused: 0 }),
    ),
  };
  return api;
}

async function render(
  lessons: ReturnType<typeof fakeLessons>,
  remote = false,
): Promise<void> {
  await act(async () => {
    root.render(
      <NotReflectedPanel
        lessonsApi={lessons as unknown as DaemonApis['lessons']}
        client={null}
        remote={remote}
      />,
    );
  });
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });
}

function buttonNamed(label: string): HTMLButtonElement | undefined {
  return [...container.querySelectorAll<HTMLButtonElement>('button')].find(
    (button) => button.textContent?.trim() === label,
  );
}

async function press(button: HTMLButtonElement | undefined): Promise<void> {
  await act(async () => {
    button?.click();
  });
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('NotReflectedPanel', () => {
  it('says nothing is waiting when no thread holds a stretch', async () => {
    await render(fakeLessons([]));

    expect(container.textContent).toContain('Nothing waiting');
    expect(container.querySelectorAll('button')).toHaveLength(0);
  });

  it('names each waiting thread with why it closed, its signals, and what its reflection would run and spend', async () => {
    await render(fakeLessons([segment()]));

    const row = container.querySelector('li')!;
    expect(row.textContent).toContain('Refactor the parser');
    expect(row.textContent).toContain('Archived');
    expect(row.textContent).toContain('1 signal');
    expect(row.textContent).toContain(
      'claude · claude-haiku-5-5 · ≈$0.50 (≈1.2k tokens)',
    );
  });

  it('shows the tokens alone when the model has no list price', async () => {
    await render(
      fakeLessons([
        segment({
          estimate: {
            agentKind: 'codex',
            model: null,
            tokens: 900,
            usd: null,
          },
        }),
      ]),
    );

    const row = container.querySelector('li')!;
    expect(row.textContent).toContain('≈900 tokens');
    expect(row.textContent).not.toContain('$');
  });

  it('sums the prices of every waiting thread in Extract all, and adds the tokens of any unpriced one', async () => {
    await render(
      fakeLessons([
        segment({
          id: 'a',
          estimate: { agentKind: 'claude', model: null, tokens: 100, usd: 0.5 },
        }),
        segment({
          id: 'b',
          estimate: {
            agentKind: 'claude',
            model: null,
            tokens: 300,
            usd: 0.25,
          },
        }),
        segment({
          id: 'c',
          estimate: { agentKind: 'codex', model: null, tokens: 400, usd: null },
        }),
      ]),
    );

    expect(buttonNamed('Extract all · ≈$0.75 + ≈400 tokens')).toBeDefined();
  });

  it('Extract starts the reflection of that stretch, and Extract all starts every waiting one', async () => {
    const lessons = fakeLessons([segment({ id: 'seg-1', runId: 'run-9' })]);
    await render(lessons);

    await press(buttonNamed('Extract'));
    expect(lessons.reflectLessons).toHaveBeenCalledWith({
      runId: 'run-9',
      reflectLessonsDto: { segmentId: 'seg-1' },
    });

    await press(buttonNamed('Extract all · ≈$0.50'));
    expect(lessons.reflectAllLessonSegments).toHaveBeenCalledTimes(1);
    expect(container.textContent).not.toContain('not started');
  });

  it('Extract all says how many waiting threads the daemon did not start', async () => {
    const lessons = fakeLessons([segment({ id: 'seg-1' })]);
    lessons.reflectAllLessonSegments.mockResolvedValueOnce({
      started: 0,
      refused: 1,
    });
    await render(lessons);

    await press(buttonNamed('Extract all · ≈$0.50'));
    await act(async () => {
      await new Promise((resolve) => setTimeout(resolve, 0));
    });

    expect(container.textContent).toContain('1 not started');
    expect(container.querySelectorAll('li')).toHaveLength(1);
  });

  it('Dismiss sets an offered stretch aside, and a dismissed one offers no Dismiss', async () => {
    const lessons = fakeLessons([
      segment({ id: 'offered-1', status: 'offered' }),
      segment({
        id: 'dismissed-1',
        status: 'dismissed',
        sourceTitle: 'Old thread',
      }),
    ]);
    await render(lessons);

    expect(container.querySelectorAll('li')).toHaveLength(2);
    const dismissButtons = [
      ...container.querySelectorAll<HTMLButtonElement>('button'),
    ].filter((button) => button.textContent?.trim() === 'Dismiss');
    expect(dismissButtons).toHaveLength(1);
    expect(container.textContent).toContain('Dismissed');

    await press(dismissButtons[0]);
    expect(lessons.dismissLessonSegment).toHaveBeenCalledWith({
      segmentId: 'offered-1',
    });
  });

  it('a failed reflection says so and asks to try again', async () => {
    await render(fakeLessons([segment({ status: 'failed' })]));

    expect(container.textContent).toContain('Reflection failed — try again');
  });

  it('a paired device sees the list without any action to start one', async () => {
    await render(fakeLessons([segment()]), true);

    expect(container.querySelectorAll('li')).toHaveLength(1);
    expect(container.querySelectorAll('button')).toHaveLength(0);
  });
});
