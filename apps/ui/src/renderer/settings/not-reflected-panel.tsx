import { useContext, useState } from 'react';

import { AgentIdentityContext } from '../agent-identity';
import type { LessonSegment, LessonSegmentCloser } from '../autogenerated';
import { formatUsd } from '../chats/agent-activity';
import { lessonRunLabel } from '../chats/lesson-model-picker';
import { useLessonSegments } from '../chats/use-lesson-segments';
import { ErrorBanner } from '../components/error-banner';
import { SettingsPanel, SettingsPanelRow } from '../components/settings-panel';
import { Button } from '../components/ui/button';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

const CLOSED_BY: Record<LessonSegmentCloser, string> = {
  manual: 'Ended by you',
  archive: 'Archived',
  done: 'Marked done',
  idle: 'Left idle',
  delete: 'Deleted',
};

const ALL_ACTION = 'all';

function titleOf(segment: LessonSegment): string {
  const title = segment.sourceTitle?.trim();
  return title ? title : 'Untitled thread';
}

function totalLabel(rows: readonly LessonSegment[]): string {
  const priced = rows.reduce((sum, row) => sum + (row.estimate.usd ?? 0), 0);
  const pricedRows = rows.filter((row) => row.estimate.usd !== null).length;
  const unpricedTokens = rows.reduce(
    (sum, row) => (row.estimate.usd === null ? sum + row.estimate.tokens : sum),
    0,
  );
  if (pricedRows === 0) {
    return `Extract all · ≈${unpricedTokens} tokens`;
  }
  const usdText = formatUsd(priced);
  const usd = `Extract all · ${usdText.startsWith('<') ? usdText : `≈${usdText}`}`;
  return unpricedTokens === 0 ? usd : `${usd} + ≈${unpricedTokens} tokens`;
}

export function NotReflectedPanel({
  lessonsApi,
  client,
  remote,
}: {
  lessonsApi: DaemonApis['lessons'] | null;
  client: DaemonClient | null;
  remote: boolean;
}): React.JSX.Element {
  const identities = useContext(AgentIdentityContext);
  const { segments, reload } = useLessonSegments({
    lessonsApi,
    client,
    runId: null,
  });
  const [busy, setBusy] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const rows = segments ?? [];
  const actable = lessonsApi !== null && !remote && busy === null;

  const run = async (
    key: string,
    action: () => Promise<unknown>,
  ): Promise<void> => {
    setBusy(key);
    setError(null);
    try {
      await action();
    } catch (err) {
      setError(String(err));
    } finally {
      setBusy(null);
      reload();
    }
  };

  const reflectAll = (): void => {
    if (lessonsApi === null) {
      return;
    }
    void run(ALL_ACTION, () => lessonsApi.reflectAllLessonSegments());
  };

  const reflect = (row: LessonSegment): void => {
    if (lessonsApi === null) {
      return;
    }
    void run(row.id, () =>
      lessonsApi.reflectLessons({
        runId: row.runId,
        reflectLessonsDto: { segmentId: row.id },
      }),
    );
  };

  const dismiss = (row: LessonSegment): void => {
    if (lessonsApi === null) {
      return;
    }
    void run(row.id, () =>
      lessonsApi.dismissLessonSegment({ segmentId: row.id }),
    );
  };

  return (
    <SettingsPanel>
      <SettingsPanelRow
        layout="block"
        label="Not reflected yet"
        description="Threads whose lessons are waiting for you. Nothing runs until you press.">
        {error === null ? null : (
          <ErrorBanner
            message={error}
            size="sm"
            onDismiss={() => setError(null)}
          />
        )}
        {rows.length === 0 || remote ? null : (
          <div className="mt-2">
            <Button
              type="button"
              variant="outline"
              size="sm"
              disabled={!actable}
              onClick={reflectAll}>
              {totalLabel(rows)}
            </Button>
          </div>
        )}
        {segments === null ? null : rows.length === 0 ? (
          <p className="mt-2 text-sm text-muted-foreground">Nothing waiting</p>
        ) : (
          <ul className="mt-2 flex flex-col gap-2">
            {rows.map((row) => (
              <li
                key={row.id}
                className="flex flex-col gap-1 rounded-md border border-border px-3 py-2">
                <div className="flex min-w-0 items-start gap-2">
                  <span className="min-w-0 flex-1 break-words text-sm font-medium">
                    {titleOf(row)}
                  </span>
                  {remote ? null : (
                    <div className="flex shrink-0 gap-1">
                      <Button
                        type="button"
                        size="sm"
                        disabled={!actable}
                        onClick={() => reflect(row)}>
                        Extract
                      </Button>
                      {row.status === 'offered' ? (
                        <Button
                          type="button"
                          variant="ghost"
                          size="sm"
                          disabled={!actable}
                          onClick={() => dismiss(row)}>
                          Dismiss
                        </Button>
                      ) : null}
                    </div>
                  )}
                </div>
                <p className="text-xs text-muted-foreground">
                  {CLOSED_BY[row.closedBy]} · {row.signals.length}{' '}
                  {row.signals.length === 1 ? 'signal' : 'signals'} ·{' '}
                  {lessonRunLabel(identities, row.estimate)}
                </p>
                {row.status === 'failed' ? (
                  <p className="text-xs text-destructive">
                    Reflection failed — try again
                  </p>
                ) : row.status === 'dismissed' ? (
                  <p className="text-xs text-muted-foreground">Dismissed</p>
                ) : null}
              </li>
            ))}
          </ul>
        )}
      </SettingsPanelRow>
    </SettingsPanel>
  );
}
