// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { PluginSummary } from '../autogenerated';
import type { DaemonClient } from '../daemon-client';
import { PluginsSettings } from './plugins-settings';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function makeApi() {
  return {
    listPlugins: vi.fn(),
    updatePlugin: vi.fn(),
    deletePlugin: vi.fn(),
  };
}

type ChangedListener = (event: { slug: string | null }) => void;

let api = makeApi();
let changedListeners: ChangedListener[] = [];
let reconnectListeners: (() => void)[] = [];
let root: Root | null = null;
let container: HTMLDivElement | null = null;

const client = {
  onPluginsChanged: (listener: ChangedListener) => {
    changedListeners.push(listener);
    return () => {
      changedListeners = changedListeners.filter((item) => item !== listener);
    };
  },
  onReconnect: (listener: () => void) => {
    reconnectListeners.push(listener);
    return () => {
      reconnectListeners = reconnectListeners.filter(
        (item) => item !== listener,
      );
    };
  },
} as unknown as DaemonClient;

function aPlugin(overrides: Partial<PluginSummary> = {}): PluginSummary {
  return {
    slug: 'deploys',
    name: 'Prod deploys',
    enabled: true,
    folders: [],
    refreshMinutes: 5,
    command: 'gh run list --limit 5',
    buttons: [],
    state: 'approved',
    error: null,
    hash: 'h1',
    path: '/Users/me/Library/Application Support/Geniro/plugins/deploys.plugin.yaml',
    lastRunAt: null,
    ...overrides,
  };
}

async function settle(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => {
      setTimeout(resolve, 0);
    });
  });
}

async function mount(
  props: Partial<React.ComponentProps<typeof PluginsSettings>> = {},
): Promise<HTMLDivElement> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(
      <PluginsSettings api={api} client={client} remote={false} {...props} />,
    );
  });
  await settle();
  return container;
}

function row(slug: string): HTMLElement {
  const found = container?.querySelector<HTMLElement>(
    `[data-plugin-slug="${slug}"]`,
  );
  if (!found) {
    throw new Error(`no row for ${slug}`);
  }
  return found;
}

async function openMenu(name: string): Promise<void> {
  await act(async () => {
    container
      ?.querySelector<HTMLButtonElement>(
        `button[aria-label="Actions for ${name}"]`,
      )
      ?.click();
  });
  await settle();
}

function optionLabels(): string[] {
  return [...document.querySelectorAll<HTMLElement>('[role="option"]')].map(
    (node) => node.textContent?.trim() ?? '',
  );
}

async function pressOption(label: string): Promise<void> {
  const option = [
    ...document.querySelectorAll<HTMLElement>('[role="option"]'),
  ].find((node) => node.textContent?.trim() === label);
  if (!option) {
    throw new Error(`no menu item "${label}"`);
  }
  await act(async () => {
    option.click();
  });
  await settle();
}

async function pressDialogButton(label: string): Promise<void> {
  const button = [
    ...document.querySelectorAll<HTMLButtonElement>('[role="dialog"] button'),
  ].find((node) => node.textContent?.trim() === label);
  if (!button) {
    throw new Error(`no dialog button "${label}"`);
  }
  await act(async () => {
    button.click();
  });
  await settle();
}

beforeEach(() => {
  api = makeApi();
  changedListeners = [];
  reconnectListeners = [];
});

afterEach(async () => {
  if (root !== null) {
    await act(async () => {
      root?.unmount();
    });
  }
  container?.remove();
  root = null;
  container = null;
});

describe('PluginsSettings', () => {
  it('renders each plugin with its name and folders, and "Every folder" for an empty list', async () => {
    api.listPlugins.mockResolvedValue({
      plugins: [
        aPlugin({ slug: 'deploys', name: 'Prod deploys', folders: [] }),
        aPlugin({
          slug: 'queue',
          name: 'Queue depth',
          folders: ['/Users/me/Projects/geniro-app/apps/daemon'],
        }),
      ],
    });
    await mount();

    expect(row('deploys').textContent).toContain('Prod deploys');
    expect(row('deploys').textContent).toContain('Every folder');
    expect(row('queue').textContent).toContain('Queue depth');
    expect(row('queue').textContent).toContain('…/geniro-app/apps/daemon');
    expect(row('queue').textContent).not.toContain('Every folder');
  });

  it('turns a plugin off through updatePlugin with its row hash', async () => {
    api.listPlugins.mockResolvedValue({ plugins: [aPlugin({ hash: 'h1' })] });
    api.updatePlugin.mockResolvedValue(aPlugin({ enabled: false, hash: 'h2' }));
    await mount();

    await act(async () => {
      row('deploys')
        .querySelector<HTMLButtonElement>('[role="switch"]')
        ?.click();
    });
    await settle();

    expect(api.updatePlugin).toHaveBeenCalledWith({
      slug: 'deploys',
      pluginPatchRequestDto: { enabled: false, baseHash: 'h1' },
    });
  });

  it('deletes a plugin only after the user confirms the dialog', async () => {
    api.listPlugins.mockResolvedValue({ plugins: [aPlugin()] });
    api.deletePlugin.mockResolvedValue({ removed: true });
    await mount();

    await openMenu('Prod deploys');
    await pressOption('Delete');

    expect(document.querySelector('[role="dialog"]')?.textContent).toContain(
      'Delete plugin Prod deploys?',
    );
    expect(api.deletePlugin).not.toHaveBeenCalled();

    await pressDialogButton('Delete');

    expect(api.deletePlugin).toHaveBeenCalledWith({ slug: 'deploys' });
  });

  it('shows the empty state when no plugin exists yet', async () => {
    api.listPlugins.mockResolvedValue({ plugins: [] });
    const el = await mount();

    expect(el.textContent).toContain(
      'No plugins yet. Ask an agent in a chat to make one — for example, “make a plugin that shows the last prod deploys”.',
    );
  });

  it('shows an invalid plugin as invalid with its error and its slug', async () => {
    api.listPlugins.mockResolvedValue({
      plugins: [
        aPlugin({
          slug: 'broken',
          name: null,
          state: 'invalid',
          error: 'command: must be one line',
        }),
      ],
    });
    await mount();

    expect(row('broken').textContent).toContain('Invalid file');
    expect(row('broken').textContent).toContain('command: must be one line');
    expect(row('broken').textContent).toContain('broken');
  });

  it('reads the list again when a plugins_changed event arrives', async () => {
    api.listPlugins.mockResolvedValue({ plugins: [aPlugin()] });
    await mount();
    expect(api.listPlugins).toHaveBeenCalledTimes(1);

    await act(async () => {
      for (const listener of changedListeners) {
        listener({ slug: 'deploys' });
      }
    });
    await settle();

    expect(api.listPlugins).toHaveBeenCalledTimes(2);
  });

  it('saves the folders left after a removal through updatePlugin', async () => {
    api.listPlugins.mockResolvedValue({
      plugins: [aPlugin({ folders: ['/Users/me/Projects/a'] })],
    });
    api.updatePlugin.mockResolvedValue(aPlugin({ folders: [], hash: 'h2' }));
    await mount();

    await openMenu('Prod deploys');
    await pressOption('Edit folders');
    await act(async () => {
      document
        .querySelector<HTMLButtonElement>(
          '[role="dialog"] button[aria-label="Remove /Users/me/Projects/a"]',
        )
        ?.click();
    });
    await settle();
    await pressDialogButton('Save');

    expect(api.updatePlugin).toHaveBeenCalledWith({
      slug: 'deploys',
      pluginPatchRequestDto: { folders: [], baseHash: 'h1' },
    });
  });

  it('shows the daemon message on a conflicting save and reads the list again', async () => {
    api.listPlugins.mockResolvedValue({ plugins: [aPlugin()] });
    api.updatePlugin.mockRejectedValue(
      new Error(
        'daemon PATCH /v1/plugins/deploys failed (409): {"code":"PLUGIN_CHANGED","message":"the plugin changed since you read it"}',
      ),
    );
    await mount();

    await act(async () => {
      row('deploys')
        .querySelector<HTMLButtonElement>('[role="switch"]')
        ?.click();
    });
    await settle();

    expect(document.body.textContent).toContain(
      'the plugin changed since you read it',
    );
    expect(api.listPlugins).toHaveBeenCalledTimes(2);
  });

  it('leaves Show file in Finder out of the menu on a paired device', async () => {
    api.listPlugins.mockResolvedValue({ plugins: [aPlugin()] });
    await mount({ remote: true });

    await openMenu('Prod deploys');

    expect(optionLabels()).toEqual(['Edit folders', 'Delete']);
  });

  it('offers Show file in Finder on the Mac', async () => {
    api.listPlugins.mockResolvedValue({ plugins: [aPlugin()] });
    await mount({ remote: false });

    await openMenu('Prod deploys');

    expect(optionLabels()).toContain('Show file in Finder');
  });
});
