type PluginsClient = Pick<
  PluginsApi,
  'listPlugins' | 'updatePlugin' | 'deletePlugin' | 'runPluginInFolder'
>;

interface PluginPatch {
  enabled?: boolean;
  folders?: string[];
}

const NOT_CONNECTED = 'Geniro is not connected to its daemon.';
const RUN_DATA_SHOWN_MAX = 4000;

function foldersLabel(folders: string[]): string {
  return folders.length === 0
    ? 'Every folder'
    : folders.map((folder) => shortenPath(folder)).join(', ');
}

function lastRunLabel(plugin: PluginSummary): string {
  return plugin.lastRunAt === null
    ? 'Not run yet'
    : `Last run ${formatRelativeTime(plugin.lastRunAt)}`;
}

export function PluginsSettings({
  api,
  client = null,
  remote = isRemoteRuntime(),
}: {
  api: PluginsClient | null;
  client?: DaemonClient | null;
  remote?: boolean;
}): React.JSX.Element {
  const [plugins, setPlugins] = useState<PluginSummary[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [editing, setEditing] = useState<PluginSummary | null>(null);
  const [running, setRunning] = useState<PluginSummary | null>(null);
  const [recentFolders, setRecentFolders] = useState<string[]>([]);
  const [asking, setAsking] = useState<PluginSummary | null>(null);
  const [askError, setAskError] = useState<string | null>(null);
  const [deleting, setDeleting] = useState(false);
  const finder = useShowInFinder();

  const read = useLatestCallback((): void => {
    if (api === null) {
      return;
    }
    void api
      .listPlugins()
      .then(({ plugins: next }) => setPlugins(next))
      .catch((err: unknown) => setError(describeDaemonError(err)));
  }, [api]);

  useEffect(() => {
    const readRecents = (): void => {
      void window.geniro
        .getSettings()
        .then((settings) => setRecentFolders(settings.recentFolders ?? []))
        .catch(() => undefined);
    };
    readRecents();
    return window.geniro.onSettingsChanged(readRecents);
  }, []);

  useEffect(() => {
    read();
    if (client === null) {
      return;
    }
    const offChanged = client.onPluginsChanged(read);
    const offConnected = client.onReconnect(read);
    return () => {
      offChanged();
      offConnected();
    };
  }, [client, read]);

  const apply = (
    plugin: PluginSummary,
    patch: PluginPatch,
  ): Promise<string | null> => {
    if (api === null) {
      return Promise.resolve(NOT_CONNECTED);
    }
    return api
      .updatePlugin({
        slug: plugin.slug,
        pluginPatchRequestDto: { ...patch, baseHash: plugin.hash },
      })
      .then((updated) => {
        setPlugins(
          (held) =>
            held?.map((row) => (row.slug === updated.slug ? updated : row)) ??
            null,
        );
        return null;
      })
      .catch((err: unknown) => {
        read();
        return describeDaemonError(err);
      });
  };

  const reportFailure = (message: string | null): void => {
    if (message !== null) {
      setError(message);
    }
  };

  const confirmDelete = async (plugin: PluginSummary): Promise<void> => {
    if (api === null) {
      return;
    }
    setDeleting(true);
    setAskError(null);
    try {
      await api.deletePlugin({ slug: plugin.slug });
      setAsking(null);
      read();
    } catch (err: unknown) {
      setAskError(describeDaemonError(err));
    } finally {
      setDeleting(false);
    }
  };

  return (
    <SettingsGroups>
      {error === null ? null : (
        <ErrorBanner message={error} onDismiss={() => setError(null)} />
      )}
      {finder.failure === null ? null : (
        <ErrorBanner message={finder.failure} onDismiss={finder.clearFailure} />
      )}

      <SettingsGroup
        icon={<Puzzle />}
        title="Plugins"
        description="Panels that show a command’s result beside a chat."
        hint="An agent makes a plugin when you ask for one in a chat. Its command runs only once you approve it in that chat’s Plugins block, and only in the folders you pick.">
        <SettingsPanel>
          {plugins === null ? null : plugins.length === 0 ? (
            <p className="px-2 py-3 text-sm text-muted-foreground">
              No plugins yet. Ask an agent in a chat to make one — for example,
              “make a plugin that shows the last prod deploys”.
            </p>
          ) : (
            <SettingsList aria-label="Plugins">
              {plugins.map((plugin) => (
                <PluginRow
                  key={plugin.slug}
                  plugin={plugin}
                  remote={remote}
                  onToggle={(enabled) =>
                    void apply(plugin, { enabled }).then(reportFailure)
                  }
                  onFolders={() => setEditing(plugin)}
                  onRun={() => setRunning(plugin)}
                  onFinder={() => finder.show(plugin.path)}
                  onDelete={() => {
                    setAskError(null);
                    setAsking(plugin);
                  }}
                />
              ))}
            </SettingsList>
          )}
        </SettingsPanel>
      </SettingsGroup>

      {editing === null ? null : (
        <FoldersDialog
          plugin={editing}
          onSave={(folders) => apply(editing, { folders })}
          onClose={() => setEditing(null)}
        />
      )}

      {running === null ? null : (
        <RunNowDialog
          plugin={running}
          recentFolders={recentFolders}
          onRun={(folder) => {
            if (api === null) {
              return Promise.reject(new Error(NOT_CONNECTED));
            }
            return api
              .runPluginInFolder({
                slug: running.slug,
                pluginFolderRunRequestDto: { folder, force: true },
              })
              .finally(read);
          }}
          onClose={() => setRunning(null)}
        />
      )}

      {asking === null ? null : (
        <ConfirmDialog
          open
          busy={deleting}
          error={askError}
          title={`Delete plugin ${asking.name ?? asking.slug}?`}
          confirmLabel="Delete"
          busyLabel="Deleting…"
          onCancel={() => setAsking(null)}
          onConfirm={() => void confirmDelete(asking)}>
          Its block leaves every chat. A backup of the file is kept.
        </ConfirmDialog>
      )}
    </SettingsGroups>
  );
}

function PluginRow({
  plugin,
  remote,
  onToggle,
  onFolders,
  onRun,
  onFinder,
  onDelete,
}: {
  plugin: PluginSummary;
  remote: boolean;
  onToggle: (enabled: boolean) => void;
  onFolders: () => void;
  onRun: () => void;
  onFinder: () => void;
  onDelete: () => void;
}): React.JSX.Element {
  const [menuOpen, setMenuOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement>(null);
  const name = plugin.name ?? plugin.slug;
  const runBlocker = !plugin.enabled
    ? 'Off'
    : plugin.state !== 'approved'
      ? 'Not approved'
      : undefined;

  const items: MenuItem[] = [
    ...(remote
      ? []
      : [{ value: 'finder', label: 'Show file in Finder', action: true }]),
    {
      value: 'run',
      label: 'Run now in a folder…',
      action: true,
      disabled: runBlocker !== undefined,
      hint: runBlocker,
    },
    { value: 'folders', label: 'Edit folders', action: true },
    { value: 'delete', label: 'Delete', tone: 'destructive', action: true },
  ];

  const pick = (value: string): void => {
    setMenuOpen(false);
    switch (value) {
      case 'finder':
        onFinder();
        return;
      case 'run':
        onRun();
        return;
      case 'folders':
        onFolders();
        return;
      case 'delete':
        onDelete();
        return;
    }
  };

  return (
    <li
      data-slot="plugin-row"
      data-plugin-slug={plugin.slug}
      className="group/plugin-row flex min-w-0 items-start gap-3 px-2 py-2.5">
      <div className="flex min-w-0 flex-1 flex-col gap-1">
        <div className="flex min-w-0 flex-wrap items-center gap-2">
          <span
            className={cn(
              'min-w-0 break-words text-sm font-medium',
              plugin.name === null && 'text-muted-foreground',
            )}>
            {name}
          </span>
          {plugin.state === 'changed' ? (
            <Badge variant="secondary">Changed since approved</Badge>
          ) : null}
          {plugin.state === 'invalid' ? (
            <Badge variant="destructive">Invalid file</Badge>
          ) : null}
        </div>
        <span
          className="text-xs text-muted-foreground"
          title={plugin.folders.join('\n') || undefined}>
          {foldersLabel(plugin.folders)}
        </span>
        <span className="text-xs text-muted-foreground">
          {lastRunLabel(plugin)}
        </span>
        {plugin.state === 'changed' ? (
          <span className="text-xs text-muted-foreground">
            Review it in a chat’s Plugins block.
          </span>
        ) : null}
        {plugin.error === null ? null : <ErrorText>{plugin.error}</ErrorText>}
      </div>
      <Switch
        aria-label={`Enable ${name}`}
        checked={plugin.enabled}
        onCheckedChange={onToggle}
      />
      <Button
        ref={triggerRef}
        type="button"
        variant="ghost"
        size="icon"
        aria-label={`Actions for ${name}`}
        aria-haspopup="menu"
        aria-expanded={menuOpen}
        title="More actions for this plugin"
        className="-my-1 size-7 shrink-0 rounded-control text-muted-foreground opacity-0 transition-opacity group-hover/plugin-row:opacity-100 group-focus-within/plugin-row:opacity-100 focus-visible:opacity-100 aria-expanded:opacity-100 pointer-coarse:opacity-100 max-sm:opacity-100 [&_svg]:size-4"
        onClick={() => setMenuOpen((open) => !open)}>
        <MoreHorizontal aria-hidden="true" />
      </Button>
      <Menu
        open={menuOpen}
        align="end"
        side="bottom"
        anchor="viewport"
        triggerRef={triggerRef}
        className="w-56 min-w-0"
        groups={[{ items }]}
        onSelect={pick}
        onClose={() => setMenuOpen(false)}
      />
    </li>
  );
}

function FoldersDialog({
  plugin,
  onSave,
  onClose,
}: {
  plugin: PluginSummary;
  onSave: (folders: string[]) => Promise<string | null>;
  onClose: () => void;
}): React.JSX.Element {
  const [folders, setFolders] = useState(plugin.folders);
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const addFolder = (folder: string): void => {
    setFolders((held) => (held.includes(folder) ? held : [...held, folder]));
  };

  const browse = (): void => {
    void window.geniro.pickProjectFolder().then((chosen) => {
      if (chosen) {
        addFolder(chosen);
      }
    });
  };

  const save = (): void => {
    setSaving(true);
    setError(null);
    void onSave(folders).then((message) => {
      setSaving(false);
      if (message === null) {
        onClose();
      } else {
        setError(message);
      }
    });
  };

  return (
    <Dialog
      open
      onClose={saving ? () => undefined : onClose}
      title={`Folders for ${plugin.name ?? plugin.slug}`}>
      <div className="flex flex-col gap-4">
        {folders.length === 0 ? (
          <p className="text-sm text-muted-foreground">
            Every folder: the block shows in every chat.
          </p>
        ) : (
          <ul className="flex flex-col gap-1">
            {folders.map((folder) => (
              <li
                key={folder}
                className="flex items-center justify-between gap-2 text-sm">
                <span className="min-w-0 truncate" title={folder}>
                  {shortenPath(folder)}
                </span>
                <Button
                  type="button"
                  variant="ghost"
                  size="icon"
                  aria-label={`Remove ${folder}`}
                  title="Remove this folder"
                  onClick={() =>
                    setFolders((held) => held.filter((item) => item !== folder))
                  }>
                  <X aria-hidden="true" />
                </Button>
              </li>
            ))}
          </ul>
        )}
        <DirectorySelect
          value={null}
          recents={[]}
          placeholder="Add folder"
          searchPlaceholder="Search folders"
          browseLabel="Choose a folder…"
          icon={<FolderOpen />}
          onChange={(directory) => {
            if (directory !== null) {
              addFolder(directory);
            }
          }}
          onBrowse={browse}
          aria-label="Add folder"
          title="Add a folder this plugin shows in"
        />
        {error === null ? null : <ErrorText>{error}</ErrorText>}
        <div className="flex justify-end gap-2">
          <Button
            type="button"
            variant="outline"
            disabled={saving}
            onClick={onClose}>
            Cancel
          </Button>
          <Button type="button" disabled={saving} onClick={save}>
            {saving ? 'Saving…' : 'Save'}
          </Button>
        </div>
      </div>
    </Dialog>
  );
}

function runDataText(data: unknown): string {
  const text = JSON.stringify(data, null, 2) ?? 'null';
  return text.length > RUN_DATA_SHOWN_MAX
    ? `${text.slice(0, RUN_DATA_SHOWN_MAX)}…`
    : text;
}

function RunNowDialog({
  plugin,
  recentFolders,
  onRun,
  onClose,
}: {
  plugin: PluginSummary;
  recentFolders: string[];
  onRun: (folder: string) => Promise<PluginRunResult>;
  onClose: () => void;
}): React.JSX.Element {
  const choices = [...new Set([...plugin.folders, ...recentFolders])];
  const [folder, setFolder] = useState<string | null>(choices[0] ?? null);
  const [running, setRunning] = useState(false);
  const [result, setResult] = useState<PluginRunResult | null>(null);
  const [error, setError] = useState<string | null>(null);
  const name = plugin.name ?? plugin.slug;

  const choose = (next: string): void => {
    setFolder(next);
    setResult(null);
    setError(null);
  };

  const browse = (): void => {
    void window.geniro.pickProjectFolder().then((chosen) => {
      if (chosen) {
        choose(chosen);
      }
    });
  };

  const run = (): void => {
    if (folder === null) {
      return;
    }
    setRunning(true);
    setError(null);
    setResult(null);
    void onRun(folder)
      .then(setResult)
      .catch((err: unknown) => setError(describeDaemonError(err)))
      .finally(() => setRunning(false));
  };

  return (
    <Dialog
      open
      onClose={running ? () => undefined : onClose}
      title={`Run ${name} now`}>
      <div className="flex flex-col gap-4">
        <p className="text-sm text-muted-foreground">
          Runs the plugin’s command in the folder you choose. Chats in that
          folder show the result.
        </p>
        <DirectorySelect
          value={folder}
          recents={choices}
          placeholder="Choose folder…"
          searchPlaceholder="Search folders"
          browseLabel="Choose a folder…"
          icon={<Folder />}
          disabled={running}
          onChange={(next) => {
            if (next !== null) {
              choose(next);
            }
          }}
          onBrowse={browse}
          aria-label="Folder to run in"
          title={folder ?? 'Choose the folder to run the plugin in'}
        />
        {error === null ? null : <ErrorText>{error}</ErrorText>}
        {result === null ? null : (
          <div data-slot="plugin-run-result" className="flex flex-col gap-2">
            <span className="text-xs text-muted-foreground">
              {`Ran ${formatRelativeTime(result.at)}`}
            </span>
            {result.error === null ? (
              <pre className="m-0 max-h-64 overflow-auto rounded-md bg-muted p-2 text-xs whitespace-pre-wrap">
                {runDataText(result.data)}
              </pre>
            ) : (
              <>
                <ErrorText>{result.error}</ErrorText>
                {result.stderrTail === '' ? null : (
                  <pre className="m-0 max-h-48 overflow-auto rounded-md bg-muted p-2 text-xs whitespace-pre-wrap">
                    {result.stderrTail}
                  </pre>
                )}
              </>
            )}
          </div>
        )}
        <div className="flex justify-end gap-2">
          <Button
            type="button"
            variant="outline"
            disabled={running}
            onClick={onClose}>
            Close
          </Button>
          <Button
            type="button"
            disabled={running || folder === null}
            onClick={run}>
            {running ? 'Running…' : result === null ? 'Run' : 'Run again'}
          </Button>
        </div>
      </div>
    </Dialog>
  );
}
