import { useState } from 'react';

import type { ProjectDto, UpdateProjectDto } from '../autogenerated';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Label } from '../components/ui/label';

// TWIN: PROJECT_DESCRIPTION_MAX and PROJECT_INSTRUCTIONS_MAX in apps/daemon/src/v1/projects/projects.types.ts.
const DESCRIPTION_MAX = 2000;
const INSTRUCTIONS_MAX = 20_000;

const blankToNull = (text: string): string | null => text.trim() || null;

function ProjectInstructionsForm({
  project,
  onSave,
  onCancel,
}: {
  project: ProjectDto;
  onSave: (patch: UpdateProjectDto) => void;
  onCancel: () => void;
}): React.JSX.Element {
  const [description, setDescription] = useState(project.description ?? '');
  const [instructions, setInstructions] = useState(project.instructions ?? '');
  return (
    <div className="flex flex-col gap-3">
      <div className="flex flex-col gap-1.5">
        <Label htmlFor="project-description">Description</Label>
        <p className="m-0 text-xs text-muted-foreground">
          What this project is.
        </p>
        <ExpandableTextarea
          id="project-description"
          title="Project description"
          rows={3}
          maxLength={DESCRIPTION_MAX}
          value={description}
          onChange={setDescription}
        />
      </div>
      <div className="flex flex-col gap-1.5">
        <Label htmlFor="project-instructions">Instructions</Label>
        <p className="m-0 text-xs text-muted-foreground">
          Every chat and workflow started in this project&rsquo;s folder, or on
          one of its cards, receives these after your own custom instructions. A
          chat keeps what it started with.
        </p>
        <ExpandableTextarea
          id="project-instructions"
          title="Project instructions"
          maxLength={INSTRUCTIONS_MAX}
          value={instructions}
          onChange={setInstructions}
        />
      </div>
      <div className="flex justify-end gap-2">
        <Button variant="ghost" size="sm" onClick={onCancel}>
          Cancel
        </Button>
        <Button
          size="sm"
          onClick={() => {
            onSave({
              description: blankToNull(description),
              instructions: blankToNull(instructions),
            });
          }}>
          Save
        </Button>
      </div>
    </div>
  );
}

/**
 * A project's description and instructions: the standing text every run in the
 * project's folder is given, after the user's own custom instructions. Open for
 * the project it is handed; closed for null.
 */
export function ProjectInstructionsDialog({
  project,
  onSave,
  onClose,
}: {
  project: ProjectDto | null;
  onSave: (projectId: string, patch: UpdateProjectDto) => void;
  onClose: () => void;
}): React.JSX.Element {
  return (
    <Dialog
      open={project !== null}
      onClose={onClose}
      title={project === null ? '' : `${project.name} instructions`}
      className="max-w-xl">
      {project === null ? null : (
        <ProjectInstructionsForm
          key={project.id}
          project={project}
          onCancel={onClose}
          onSave={(patch) => {
            onSave(project.id, patch);
            onClose();
          }}
        />
      )}
    </Dialog>
  );
}
