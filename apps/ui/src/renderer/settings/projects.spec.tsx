// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { ProjectDto } from '../autogenerated';
import { ProjectsPane } from './projects';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

function pane(
  projects: ProjectDto[],
  onDelete = vi.fn(),
): { el: HTMLDivElement; onDelete: ReturnType<typeof vi.fn> } {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(<ProjectsPane projects={projects} onDelete={onDelete} />);
  });
  return { el: container, onDelete };
}

const project = (over: Partial<ProjectDto> = {}): ProjectDto =>
  ({
    id: 'p1',
    name: 'Geniro',
    folder: '/Users/me/code/geniro',
    ...over,
  }) as ProjectDto;

describe('ProjectsPane', () => {
  it('says where projects come from when there are none', () => {
    // The pane is reachable before Tasks has ever been opened, so an empty
    // list has to point at the screen that fills it.
    expect(pane([]).el.textContent).toContain('Tasks screen');
  });

  it('names the project in the delete control rather than saying only "Delete"', () => {
    // Deleting takes the tasks with it and there is no trash, so a row of
    // identical "Delete" buttons is a press with no subject.
    const { el } = pane([project()]);

    const button = el.querySelector('button');
    expect(button?.getAttribute('aria-label')).toBe('Delete Geniro');
    expect(button?.getAttribute('title')).toContain('and its tasks');
  });

  it('asks before deleting, and names what goes', () => {
    // Deleting a project destroys its whole board and there is no trash. This
    // app confirms DELETE GROUP, which keeps every chat in it — so the
    // strictly more destructive action confirms too.
    const { el, onDelete } = pane([project({ id: 'p2', name: 'Other' })]);

    act(() => {
      (el.querySelector('button') as HTMLButtonElement).click();
    });

    expect(onDelete).not.toHaveBeenCalled();
    expect(document.body.textContent).toContain('cannot be undone');
  });

  it('deletes the project the row belongs to once confirmed', () => {
    const { el, onDelete } = pane([project({ id: 'p2', name: 'Other' })]);
    act(() => {
      (el.querySelector('button') as HTMLButtonElement).click();
    });

    const confirm = [...document.body.querySelectorAll('button')].find(
      (node) => node.textContent === 'Delete project',
    ) as HTMLButtonElement;
    act(() => {
      confirm.click();
    });

    expect(onDelete).toHaveBeenCalledWith('p2');
  });
});
