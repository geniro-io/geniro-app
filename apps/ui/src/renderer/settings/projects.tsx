import { Pencil, Plus, Trash2 } from 'lucide-react';
import { useState } from 'react';

import type { CliDetection } from '../../shared/contracts';
import type {
  CreateProjectDto,
  ProjectDto,
  UpdateProjectDto,
} from '../autogenerated';
import { shortenPath } from '../chats/directory-select';
import type { TargetWorkflow } from '../chats/target-select';
import { ConfirmDialog } from '../components/confirm-dialog';
import { ErrorBanner } from '../components/error-banner';
import { Button } from '../components/ui/button';
import { Card } from '../components/ui/card';
import { NewProjectDialog } from '../tasks/new-project-dialog';
import { ProjectInstructionsDialog } from './project-instructions-dialog';

export function ProjectsPane({
  projects,
  error,
  onCreate,
  onUpdate,
  onDelete,
  onDismissError,
  workflows = [],
  cliDetections = null,
}: {
  projects: ProjectDto[];
  /** The last failed create, update or delete, in the daemon's own words. */
  error?: string | null;
  onCreate: (input: CreateProjectDto) => void;
  onUpdate: (projectId: string, patch: UpdateProjectDto) => void;
  onDelete: (projectId: string) => void;
  onDismissError?: () => void;
  /** What the new-project dialog's target picker offers. */
  workflows?: readonly TargetWorkflow[];
  cliDetections?: readonly CliDetection[] | null;
}): React.JSX.Element {
  // Deleting takes the project's whole board with it and there is no trash, so
  // it asks first. This app already confirms DELETE GROUP, which keeps every
  // chat in it - a strictly less destructive action than this one.
  const [confirming, setConfirming] = useState<ProjectDto | null>(null);
  // The pane is the screen that LISTS projects, so it is where one is added
  // too. It used to say "create one from the Tasks screen", which sent a user
  // looking at the list somewhere else to grow it — reported as "i cant add
  // projects". The dialog is the board's own, so the two cannot drift.
  const [creating, setCreating] = useState(false);
  const [editing, setEditing] = useState<ProjectDto | null>(null);
  return (
    <div className="flex flex-col gap-2">
      {error ? (
        <ErrorBanner
          message={error}
          onDismiss={onDismissError ?? (() => undefined)}
        />
      ) : null}
      <div className="flex flex-row items-center justify-between gap-3">
        {projects.length === 0 ? (
          <p className="text-sm text-muted-foreground">
            No projects yet — a project binds a folder, and its tasks become
            that folder&rsquo;s board.
          </p>
        ) : (
          <span />
        )}
        <Button
          variant="outline"
          size="sm"
          className="shrink-0"
          onClick={() => {
            setCreating(true);
          }}>
          <Plus className="size-4" aria-hidden />
          New project
        </Button>
      </div>
      {projects.map((project) => (
        <Card key={project.id} className="flex flex-col gap-3 p-3">
          <div className="flex flex-row items-center justify-between gap-3">
            <div className="flex min-w-0 flex-col">
              <span className="truncate text-sm font-medium">
                {project.name}
              </span>
              <span
                className="truncate font-mono text-xs text-muted-foreground"
                title={project.folder}>
                {shortenPath(project.folder)}
              </span>
              {project.description ? (
                <span
                  className="truncate text-xs text-muted-foreground"
                  title={project.description}>
                  {project.description}
                </span>
              ) : null}
            </div>
            <div className="flex shrink-0 flex-row items-center">
              <Button
                variant="ghost"
                size="sm"
                aria-label={`Edit instructions for ${project.name}`}
                title={`Edit ${project.name}’s description and instructions`}
                onClick={() => {
                  setEditing(project);
                }}>
                <Pencil className="size-4" aria-hidden />
              </Button>
              <Button
                variant="ghost"
                size="sm"
                aria-label={`Delete ${project.name}`}
                // Deleting a project deletes its tasks with it, and there is no
                // trash — so the label names the project rather than saying
                // "Delete", which in a list is a press with no subject.
                title={`Delete ${project.name} and its tasks`}
                onClick={() => {
                  setConfirming(project);
                }}>
                <Trash2 className="size-4" aria-hidden />
              </Button>
            </div>
          </div>
        </Card>
      ))}
      <NewProjectDialog
        open={creating}
        workflows={workflows}
        cliDetections={cliDetections}
        onClose={() => {
          setCreating(false);
        }}
        onCreate={(input) => {
          setCreating(false);
          onCreate(input);
        }}
      />
      <ProjectInstructionsDialog
        project={editing}
        onSave={onUpdate}
        onClose={() => {
          setEditing(null);
        }}
      />
      <ConfirmDialog
        open={confirming !== null}
        title={`Delete ${confirming?.name ?? ''}?`}
        confirmLabel="Delete project"
        busyLabel="Deleting…"
        onCancel={() => {
          setConfirming(null);
        }}
        onConfirm={() => {
          const target = confirming;
          setConfirming(null);
          if (target) {
            onDelete(target.id);
          }
        }}>
        Its tasks are deleted with it. This cannot be undone — there is no
        trash, and nothing in the app can bring them back.
      </ConfirmDialog>
    </div>
  );
}
