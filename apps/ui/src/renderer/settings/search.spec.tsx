const TOTAL = 346_396_233;

function state(overrides: Partial<SearchModelState> = {}): SearchModelState {
  return {
    phase: 'off',
    receivedBytes: 0,
    totalBytes: TOTAL,
    reason: null,
    systemVersion: null,
    modelBytes: 0,
    ...overrides,
  };
}

function status(
  overrides: Partial<EmbeddingStatusDto> = {},
): EmbeddingStatusDto {
  return {
    state: 'ready',
    model: {
      id: 'embeddinggemma-2',
      revision: 'daa72c51243991dfcaf9f9137d2c573d8f7790c0',
    },
    pendingModel: null,
    counts: {
      memory: { indexed: 12, total: 12 },
      knowledge: { indexed: 3, total: 4 },
      chats: { indexed: 400, total: 900, paused: null },
    },
    indexBytes: 12_000_000,
    failure: null,
    ...overrides,
  };
}

interface Harness {
  api: SearchApi & {
    getEmbeddingStatus: ReturnType<typeof vi.fn>;
    deleteEmbeddingIndex: ReturnType<typeof vi.fn>;
  };
  events: SearchEvents & { emit(event: EmbeddingsChangedEvent): void };
  geniro: {
    setSearchByMeaning: ReturnType<typeof vi.fn>;
    cancelSearchModelDownload: ReturnType<typeof vi.fn>;
    retrySearchModelDownload: ReturnType<typeof vi.fn>;
    updateSearchModel: ReturnType<typeof vi.fn>;
    deleteSearchModel: ReturnType<typeof vi.fn>;
    notifySearchModelFailed: ReturnType<typeof vi.fn>;
    emitState(next: SearchModelState): void;
  };
}

function harness(
  current: SearchModelState,
  currentStatus: EmbeddingStatusDto | null = status(),
): Harness {
  let emitStateListener: (next: SearchModelState) => void = () => undefined;
  let emitEventListener: (event: EmbeddingsChangedEvent) => void = () =>
    undefined;
  const spies = {
    setSearchByMeaning: vi.fn((on: boolean) =>
      Promise.resolve(state({ phase: on ? 'downloading' : 'off' })),
    ),
    cancelSearchModelDownload: vi.fn(() => Promise.resolve(state())),
    retrySearchModelDownload: vi.fn(() =>
      Promise.resolve(state({ phase: 'downloading' })),
    ),
    updateSearchModel: vi.fn(() =>
      Promise.resolve(state({ phase: 'updating' })),
    ),
    deleteSearchModel: vi.fn(() => Promise.resolve(state())),
    notifySearchModelFailed: vi.fn(() => Promise.resolve()),
  };
  window.geniro = createPreloadStub({
    ...spies,
    getSearchModelState: () => Promise.resolve(current),
    onSearchModelState: (listener) => {
      emitStateListener = listener;
      return () => undefined;
    },
  });
  const api = {
    getEmbeddingStatus: vi.fn(() =>
      currentStatus === null
        ? Promise.reject(new Error('the daemon is not answering'))
        : Promise.resolve(currentStatus),
    ),
    deleteEmbeddingIndex: vi.fn(() => Promise.resolve()),
  };
  const events = {
    onEmbeddingsChanged: (
      listener: (event: EmbeddingsChangedEvent) => void,
    ) => {
      emitEventListener = listener;
      return () => undefined;
    },
    emit: (event: EmbeddingsChangedEvent) => emitEventListener(event),
  };
  return {
    api,
    events,
    geniro: {
      ...spies,
      emitState: (next) => emitStateListener(next),
    },
  };
}

let root: Root | null = null;
let container: HTMLDivElement | null = null;

async function settle(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });
}

async function mount(ui: ReactElement): Promise<void> {
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  await act(async () => {
    root?.render(ui);
  });
  await settle();
}

function textOf(): string {
  return `${container?.textContent ?? ''}${document.body.textContent ?? ''}`;
}

function switchEl(): HTMLButtonElement {
  const el = container?.querySelector<HTMLButtonElement>('[role="switch"]');
  if (!el) {
    throw new Error('no switch on the page');
  }
  return el;
}

function buttonNamed(text: string): HTMLButtonElement {
  const found = [...(container?.querySelectorAll('button') ?? [])].find(
    (button) => button.textContent?.trim() === text,
  );
  if (!found) {
    throw new Error(`no button "${text}"`);
  }
  return found;
}

function dialogButton(text: string): HTMLButtonElement {
  const found = [
    ...document.querySelectorAll<HTMLButtonElement>('[role="dialog"] button'),
  ].find((button) => button.textContent?.trim() === text);
  if (!found) {
    throw new Error(`no dialog button "${text}"`);
  }
  return found;
}

function progressOf(label: string): HTMLElement | null {
  return (
    container?.querySelector<HTMLElement>(
      `[role="progressbar"][aria-label="${label}"]`,
    ) ?? null
  );
}

async function press(el: HTMLElement): Promise<void> {
  await act(async () => {
    el.click();
  });
  await settle();
}

describe('SearchSettings', () => {
  beforeEach(() => {
    vi.mocked(isRemoteRuntime).mockReturnValue(false);
  });

  afterEach(() => {
    if (root !== null) {
      act(() => root?.unmount());
    }
    container?.remove();
    root = null;
    container = null;
    document.body.innerHTML = '';
    vi.useRealTimers();
  });

  it('shows the switch off with the download size from the pinned model', async () => {
    const h = harness(state({ phase: 'off' }));
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(switchEl().getAttribute('aria-checked')).toBe('false');
    expect(textOf()).toContain(
      'A one-time download of the 346 MB search model from Geniro’s releases.',
    );
  });

  it('disables the switch on macOS 13 and says which version this Mac runs', async () => {
    const h = harness(state({ phase: 'unsupported', systemVersion: '13.6.1' }));
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(switchEl().disabled).toBe(true);
    expect(textOf()).toContain(
      'Needs macOS 14 or later. This Mac runs macOS 13.6.1 — search keeps matching words.',
    );
  });

  it('turning the switch on asks main to switch search by meaning on', async () => {
    const h = harness(state({ phase: 'off' }));
    await mount(<SearchSettings api={h.api} events={h.events} />);

    await press(switchEl());

    expect(h.geniro.setSearchByMeaning).toHaveBeenCalledWith(true);
  });

  it('shows a download as its megabytes and a bar, and Cancel stops it', async () => {
    const h = harness(
      state({ phase: 'downloading', receivedBytes: 138_000_000 }),
      null,
    );
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(textOf()).toContain('138 of 346 MB');
    expect(
      progressOf('Downloading the search model')?.getAttribute('aria-valuenow'),
    ).toBe('40');

    await press(buttonNamed('Cancel'));

    expect(h.geniro.cancelSearchModelDownload).toHaveBeenCalledTimes(1);
  });

  it('shows the checking step as an indeterminate bar', async () => {
    const h = harness(state({ phase: 'checking', receivedBytes: TOTAL }), null);
    await mount(<SearchSettings api={h.api} events={h.events} />);

    const bar = progressOf('Checking the download');
    expect(bar).not.toBeNull();
    expect(bar?.hasAttribute('aria-valuenow')).toBe(false);
  });

  it('a failed download says why in plain words, keeps the switch off, and Try again resumes it', async () => {
    const h = harness(state({ phase: 'failed', reason: 'network' }), null);
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(textOf()).toContain(
      'The network connection failed. Search keeps matching words.',
    );
    expect(switchEl().getAttribute('aria-checked')).toBe('false');

    await press(buttonNamed('Try again'));

    expect(h.geniro.retrySearchModelDownload).toHaveBeenCalledTimes(1);
  });

  it('a ready model shows each source’s count, the chats paused on battery, and the size line', async () => {
    const h = harness(
      state({ phase: 'ready', modelBytes: TOTAL }),
      status({
        counts: {
          memory: { indexed: 12, total: 12 },
          knowledge: { indexed: 3, total: 4 },
          chats: { indexed: 400, total: 900, paused: 'battery' },
        },
      }),
    );
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(textOf()).toContain('Memory notes');
    expect(textOf()).toContain('12 of 12');
    expect(textOf()).toContain('Knowledge documents');
    expect(textOf()).toContain('3 of 4');
    expect(textOf()).toContain('400 of 900 · paused — on battery');
    expect(textOf()).toContain('EmbeddingGemma 2 · model 346 MB · index 12 MB');
  });

  it('a newer model waits for Update model, which downloads it', async () => {
    const h = harness(state({ phase: 'update-available', modelBytes: TOTAL }));
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(textOf()).toContain('A newer search model is available');

    await press(buttonNamed('Update model'));

    expect(h.geniro.updateSearchModel).toHaveBeenCalledTimes(1);
  });

  it('an update that did not finish says why, and Search keeps using the current model', async () => {
    const h = harness(
      state({
        phase: 'update-available',
        modelBytes: TOTAL,
        reason: 'network',
      }),
    );
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(textOf()).toContain(
      'The update did not finish: The network connection failed. Search keeps using the current model.',
    );
    expect(textOf()).not.toContain('the old model is deleted');
  });

  it('the daemon’s failure reason shows when the index stopped', async () => {
    const h = harness(
      state({ phase: 'ready', modelBytes: TOTAL }),
      status({
        state: 'failed',
        failure: 'The index file is locked by another process.',
      }),
    );
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(textOf()).toContain('The index stopped');
    expect(textOf()).toContain('The index file is locked by another process.');
  });

  it('off keeps the files on disk and says turning it on again is instant', async () => {
    const h = harness(state({ phase: 'off', modelBytes: TOTAL }), null);
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(textOf()).toContain(
      'The model and index are kept on this Mac (346 MB). Turn this on again to use them at once.',
    );
  });

  it('Delete model and index asks first, then deletes the model and the index', async () => {
    const h = harness(state({ phase: 'ready', modelBytes: TOTAL }));
    await mount(<SearchSettings api={h.api} events={h.events} />);

    await press(buttonNamed('Delete model and index…'));
    expect(document.querySelector('[role="dialog"]')).not.toBeNull();
    expect(h.geniro.deleteSearchModel).not.toHaveBeenCalled();

    await press(dialogButton('Delete'));

    expect(h.geniro.deleteSearchModel).toHaveBeenCalledTimes(1);
    expect(h.api.deleteEmbeddingIndex).toHaveBeenCalledTimes(1);
    expect(storage.forgetStorageReading).toHaveBeenCalled();
  });

  it('re-reads the index status at most once a second while its changes keep arriving', async () => {
    const h = harness(state({ phase: 'ready', modelBytes: TOTAL }));
    await mount(<SearchSettings api={h.api} events={h.events} />);
    expect(h.api.getEmbeddingStatus).toHaveBeenCalledTimes(1);

    await act(async () => {
      h.events.emit({ reason: 'progress' });
      h.events.emit({ reason: 'progress' });
      h.events.emit({ reason: 'state' });
    });
    expect(h.api.getEmbeddingStatus).toHaveBeenCalledTimes(1);

    await act(async () => {
      await new Promise((resolve) => setTimeout(resolve, 1100));
    });
    expect(h.api.getEmbeddingStatus).toHaveBeenCalledTimes(2);
  });

  it('on a paired device the status shows and nothing can be changed', async () => {
    vi.mocked(isRemoteRuntime).mockReturnValue(true);
    const h = harness(state({ phase: 'off' }));
    await mount(<SearchSettings api={h.api} events={h.events} />);

    expect(switchEl().disabled).toBe(true);
    expect(textOf()).toContain('Turned on or off on the Mac that runs Geniro.');
  });
});

function FailureProbe({ showing }: { showing: boolean }): null {
  useSearchModelFailureNotice(showing);
  return null;
}

describe('useSearchModelFailureNotice', () => {
  beforeEach(() => {
    vi.spyOn(document, 'hasFocus').mockReturnValue(true);
  });

  afterEach(() => {
    if (root !== null) {
      act(() => root?.unmount());
    }
    container?.remove();
    root = null;
    container = null;
    document.body.innerHTML = '';
    vi.restoreAllMocks();
  });

  it('posts a failure while the Search page is not showing', async () => {
    const h = harness(state({ phase: 'off' }));
    await mount(<FailureProbe showing={false} />);

    h.geniro.emitState(state({ phase: 'failed', reason: 'disk-full' }));

    expect(h.geniro.notifySearchModelFailed).toHaveBeenCalledWith('disk-full');
  });

  it('posts a failure while the window is not focused, even on the Search page', async () => {
    vi.mocked(document.hasFocus).mockReturnValue(false);
    const h = harness(state({ phase: 'off' }));
    await mount(<FailureProbe showing={true} />);

    h.geniro.emitState(state({ phase: 'failed', reason: 'checksum' }));

    expect(h.geniro.notifySearchModelFailed).toHaveBeenCalledWith('checksum');
  });

  it('never posts while the Search page is showing and the window is focused', async () => {
    const h = harness(state({ phase: 'off' }));
    await mount(<FailureProbe showing={true} />);

    h.geniro.emitState(state({ phase: 'failed', reason: 'network' }));

    expect(h.geniro.notifySearchModelFailed).not.toHaveBeenCalled();
  });

  it('posts once for a failure, not again for every state event that repeats it', async () => {
    const h = harness(state({ phase: 'off' }));
    await mount(<FailureProbe showing={false} />);

    h.geniro.emitState(state({ phase: 'failed', reason: 'network' }));
    h.geniro.emitState(state({ phase: 'failed', reason: 'network' }));

    expect(h.geniro.notifySearchModelFailed).toHaveBeenCalledTimes(1);
  });
});
