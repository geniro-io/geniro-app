export type SearchApi = Pick<
  EmbeddingsApi,
  'getEmbeddingStatus' | 'deleteEmbeddingIndex'
>;

export type SearchEvents = Pick<DaemonClient, 'onEmbeddingsChanged'>;

type Chats = EmbeddingStatusDto['counts']['chats'];

/** How long a burst of index changes waits before the status is read again. */
const STATUS_READ_GAP_MS = 1000;

/** Megabytes as the copy says them: decimal, as the release page does. */
export function megabytes(bytes: number): number {
  return Math.round(bytes / 1_000_000);
}

/** A size on disk as the copy says it: never "0 MB" for something that is there. */
function sizeOnDisk(bytes: number): string {
  return bytes < 1_000_000 ? 'under 1 MB' : `${megabytes(bytes)} MB`;
}

/** What the "Model and index" row names: only the parts that are on this Mac. */
function onDiskParts(modelBytes: number, indexBytes: number): string {
  return [
    'EmbeddingGemma 2',
    ...(modelBytes > 0 ? [`model ${sizeOnDisk(modelBytes)}`] : []),
    ...(indexBytes > 0 ? [`index ${sizeOnDisk(indexBytes)}`] : []),
  ].join(' · ');
}

function messageOf(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

/** Whether the switch reads as on: a download, its check, a ready model, or an update in progress. */
function switchReadsOn(phase: SearchModelState['phase']): boolean {
  return (
    phase === 'downloading' ||
    phase === 'checking' ||
    phase === 'ready' ||
    phase === 'update-available' ||
    phase === 'updating'
  );
}

function chatsWord(chats: Chats): string {
  if (chats.paused === 'battery') {
    return 'paused — on battery';
  }
  return chats.indexed >= chats.total ? 'done' : 'in the background';
}

const ALL_TIME = 'all';
const CUSTOM_WINDOW = 'custom';
const WINDOW_PRESET_DAYS: readonly number[] = [7, 30, 90];

const CHAT_WINDOW_OPTIONS: SelectGroup[] = [
  {
    items: [
      { value: ALL_TIME, label: 'All time' },
      { value: '7', label: 'Last 7 days' },
      { value: '30', label: 'Last 30 days' },
      { value: '90', label: 'Last 90 days' },
      { value: CUSTOM_WINDOW, label: 'Custom…' },
    ],
  },
];

function windowValueOf(days: number | null): string {
  if (days === null) {
    return ALL_TIME;
  }
  return WINDOW_PRESET_DAYS.includes(days) ? String(days) : CUSTOM_WINDOW;
}

function windowNoteOf(days: number | null): string | null {
  if (days === null) {
    return null;
  }
  return `last ${days} ${days === 1 ? 'day' : 'days'}`;
}

function parseWindowDays(text: string): number | null {
  const trimmed = text.trim();
  if (!/^\d+$/.test(trimmed)) {
    return null;
  }
  const days = Number(trimmed);
  return days >= SEMANTIC_SEARCH_WINDOW_MIN_DAYS &&
    days <= SEMANTIC_SEARCH_WINDOW_MAX_DAYS
    ? days
    : null;
}

export function useSearchModelState(): {
  state: SearchModelState | null;
  setState: (next: SearchModelState) => void;
  readError: string | null;
} {
  const [state, setState] = useState<SearchModelState | null>(null);
  const [readError, setReadError] = useState<string | null>(null);
  useEffect(() => {
    let mounted = true;
    window.geniro.getSearchModelState().then(
      (next) => {
        if (mounted) {
          setState(next);
        }
      },
      (err: unknown) => {
        if (mounted) {
          setReadError(messageOf(err));
        }
      },
    );
    const off = window.geniro.onSearchModelState((next) => {
      if (mounted) {
        setState(next);
      }
    });
    return () => {
      mounted = false;
      off();
    };
  }, []);
  return { state, setState, readError };
}

/**
 * The daemon's index status, read now and again at most once per
 * {@link STATUS_READ_GAP_MS} while its changes keep arriving.
 */
export function useEmbeddingStatus(
  api: SearchApi | null,
  events: SearchEvents | null,
): {
  status: EmbeddingStatusDto | null;
  readError: string | null;
  readNow: () => Promise<void>;
} {
  const [status, setStatus] = useState<EmbeddingStatusDto | null>(null);
  const [readError, setReadError] = useState<string | null>(null);
  const lastRead = useRef(0);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);

  const readNow = useLatestCallback(async (): Promise<void> => {
    if (api === null) {
      return;
    }
    lastRead.current = Date.now();
    try {
      setStatus(await api.getEmbeddingStatus());
      setReadError(null);
    } catch (err) {
      setReadError(messageOf(err));
    }
  }, []);

  const readSoon = useLatestCallback((): void => {
    if (timer.current !== null) {
      return;
    }
    const wait = Math.max(
      0,
      STATUS_READ_GAP_MS - (Date.now() - lastRead.current),
    );
    timer.current = setTimeout(() => {
      timer.current = null;
      void readNow();
    }, wait);
  }, []);

  useEffect(() => {
    void readNow();
  }, [api, readNow]);

  useEffect(() => {
    if (events === null) {
      return undefined;
    }
    const off = events.onEmbeddingsChanged(() => readSoon());
    return () => {
      off();
      if (timer.current !== null) {
        clearTimeout(timer.current);
        timer.current = null;
      }
    };
  }, [events, readSoon]);

  return { status, readError, readNow };
}

/**
 * The failure banner, posted from the always-mounted shell: it fires when the
 * download turns `failed` while the Search page is not on screen or the window
 * is not focused, and never when the user is looking at it.
 */
export function useSearchModelFailureNotice(showing: boolean): void {
  const showingRef = useRef(showing);
  useEffect(() => {
    showingRef.current = showing;
  }, [showing]);

  useEffect(() => {
    let previous: SearchModelState['phase'] | null = null;
    let mounted = true;
    window.geniro.getSearchModelState().then(
      (next) => {
        if (mounted) {
          previous = next.phase;
        }
      },
      (): void => undefined,
    );
    const off = window.geniro.onSearchModelState((next) => {
      const failedNow = previous !== 'failed' && next.phase === 'failed';
      previous = next.phase;
      if (!failedNow || next.reason === null) {
        return;
      }
      if (showingRef.current && document.hasFocus()) {
        return;
      }
      void window.geniro.notifySearchModelFailed(next.reason);
    });
    return () => {
      mounted = false;
      off();
    };
  }, []);
}

export function SearchSettings({
  api,
  events,
}: {
  api: SearchApi | null;
  events: SearchEvents | null;
}): React.JSX.Element {
  const remote = isRemoteRuntime();
  const { state, setState, readError: stateReadError } = useSearchModelState();
  const {
    status,
    readError: statusReadError,
    readNow,
  } = useEmbeddingStatus(api, events);
  const [actionError, setActionError] = useState<string | null>(null);
  const [semantic, setSemantic] = useState<SemanticSearchSettings | null>(null);
  const [scopeError, setScopeError] = useState<string | null>(null);
  const [customText, setCustomText] = useState<string | null>(null);
  const [windowError, setWindowError] = useState<string | null>(null);
  const scopeSaves = useRef(0);

  useEffect(() => {
    let mounted = true;
    window.geniro.getSettings().then(
      (settings) => {
        if (mounted) {
          setSemantic(settings.semanticSearch);
        }
      },
      (err: unknown) => {
        if (mounted) {
          setScopeError(messageOf(err));
        }
      },
    );
    return () => {
      mounted = false;
    };
  }, []);

  const saveScope = (
    change: Partial<Pick<SemanticSearchSettings, 'sources' | 'chatWindowDays'>>,
  ): Promise<boolean> => {
    const before = semantic;
    const mine = ++scopeSaves.current;
    setSemantic(before === null ? null : { ...before, ...change });
    setScopeError(null);
    return window.geniro
      .getSettings()
      .then((settings) =>
        window.geniro.updateSettings({
          semanticSearch: { ...settings.semanticSearch, ...change },
        }),
      )
      .then((saved) => {
        if (mine === scopeSaves.current) {
          setSemantic(saved.semanticSearch);
        }
        return true;
      })
      .catch((err: unknown) => {
        if (mine === scopeSaves.current) {
          setSemantic(before);
          setScopeError(messageOf(err));
        }
        return false;
      });
  };

  const act = (action: () => Promise<SearchModelState>): void => {
    setActionError(null);
    action().then(
      (next) => {
        setState(next);
      },
      (err: unknown) => setActionError(messageOf(err)),
    );
  };

  const deleteModelAndIndex = async (): Promise<void> => {
    const next = await window.geniro.deleteSearchModel();
    setState(next);
    if (api !== null) {
      await api.deleteEmbeddingIndex();
    }
    forgetStorageReading();
    await readNow();
  };

  const sources = semantic?.sources ?? DEFAULT_SEMANTIC_SEARCH.sources;
  const chatWindowDays = semantic?.chatWindowDays ?? null;
  const scopeOff =
    state === null ||
    !switchReadsOn(state.phase) ||
    remote ||
    semantic === null;
  const windowValue =
    customText === null ? windowValueOf(chatWindowDays) : CUSTOM_WINDOW;
  const daysText =
    customText ?? (chatWindowDays === null ? '' : String(chatWindowDays));

  const setSource = (
    source: keyof SemanticSearchSources,
    on: boolean,
  ): void => {
    void saveScope({ sources: { ...sources, [source]: on } });
  };

  const pickWindow = (value: string): void => {
    setWindowError(null);
    if (value === CUSTOM_WINDOW) {
      setCustomText(
        windowValueOf(chatWindowDays) === CUSTOM_WINDOW
          ? String(chatWindowDays)
          : '',
      );
      return;
    }
    setCustomText(null);
    void saveScope({
      chatWindowDays: value === ALL_TIME ? null : Number(value),
    });
  };

  const commitDays = (): void => {
    if (customText === null) {
      return;
    }
    if (customText.trim() === '') {
      setCustomText(null);
      setWindowError(null);
      return;
    }
    const days = parseWindowDays(customText);
    if (days === null) {
      setWindowError(
        `Enter a whole number of days from ${SEMANTIC_SEARCH_WINDOW_MIN_DAYS} to ${SEMANTIC_SEARCH_WINDOW_MAX_DAYS}.`,
      );
      return;
    }
    setWindowError(null);
    if (days === chatWindowDays) {
      setCustomText(null);
      return;
    }
    void saveScope({ chatWindowDays: days }).then((saved) => {
      if (saved) {
        setCustomText(null);
      }
    });
  };

  const phase = state?.phase ?? 'off';
  const unsupported = phase === 'unsupported';
  const modelMegabytes =
    state === null ? '' : `${megabytes(state.totalBytes)} MB`;
  const actionsOff = remote;

  const switchDescription = (): string => {
    if (state === null) {
      return '';
    }
    if (unsupported) {
      return `Needs macOS 14 or later. This Mac runs macOS ${state.systemVersion ?? ''} — search keeps matching words.`;
    }
    if (remote) {
      return 'Turned on or off on the Mac that runs Geniro.';
    }
    return `A one-time download of the ${modelMegabytes} search model from Geniro’s releases. It runs on this Mac.`;
  };

  const showStatus =
    api !== null &&
    status !== null &&
    (phase === 'ready' ||
      phase === 'update-available' ||
      phase === 'updating') &&
    status.state !== 'off';

  const stateRows: ReactNode[] = [];
  if (state !== null) {
    if (phase === 'downloading') {
      stateRows.push(
        <SettingsPanelRow
          key="downloading"
          label="Downloading the search model"
          description={`${megabytes(state.receivedBytes)} of ${megabytes(state.totalBytes)} MB`}>
          <ProgressBar
            fraction={
              state.totalBytes > 0
                ? state.receivedBytes / state.totalBytes
                : null
            }
            label="Downloading the search model"
          />
          <Button
            variant="outline"
            size="sm"
            disabled={actionsOff}
            title="Stop the download and delete the part that arrived"
            onClick={() =>
              act(() => window.geniro.cancelSearchModelDownload())
            }>
            Cancel
          </Button>
        </SettingsPanelRow>,
      );
    }
    if (phase === 'checking') {
      stateRows.push(
        <SettingsPanelRow
          key="checking"
          label="Checking the download"
          description="The files are checked against their checksums before the model is used.">
          <ProgressBar fraction={null} label="Checking the download" />
        </SettingsPanelRow>,
      );
    }
    if (phase === 'failed') {
      stateRows.push(
        <SettingsPanelRow
          key="failed"
          label="The download did not finish"
          description={
            <span className="flex items-center gap-1.5 text-destructive">
              <TriangleAlert aria-hidden="true" className="size-4 shrink-0" />
              {state.reason === null
                ? 'Search keeps matching words.'
                : `${SEARCH_MODEL_FAILURE_SENTENCES[state.reason]} Search keeps matching words.`}
            </span>
          }>
          <Button
            variant="default"
            size="sm"
            disabled={actionsOff}
            title="Resume the download where it stopped"
            onClick={() => act(() => window.geniro.retrySearchModelDownload())}>
            Try again
          </Button>
        </SettingsPanelRow>,
      );
    }
    if (phase === 'update-available') {
      stateRows.push(
        <SettingsPanelRow
          key="update"
          label="A newer search model is available"
          description={
            state.reason === null
              ? `Search keeps using the current model until the new one is downloaded and indexed. The download is ${modelMegabytes}; the old model is deleted once the new index is complete.`
              : `The update did not finish: ${SEARCH_MODEL_FAILURE_SENTENCES[state.reason]} Search keeps using the current model.`
          }>
          <Button
            variant="default"
            size="sm"
            disabled={actionsOff}
            title="Download the newer model; search keeps using the current one meanwhile"
            onClick={() => act(() => window.geniro.updateSearchModel())}>
            Update model
          </Button>
        </SettingsPanelRow>,
      );
    }
    if (phase === 'updating') {
      stateRows.push(
        <SettingsPanelRow
          key="updating"
          label="Downloading the newer model"
          description={`${megabytes(state.receivedBytes)} of ${megabytes(state.totalBytes)} MB`}>
          <ProgressBar
            fraction={
              state.totalBytes > 0
                ? state.receivedBytes / state.totalBytes
                : null
            }
            label="Downloading the newer model"
          />
        </SettingsPanelRow>,
      );
    }
  }

  const statusRows: ReactNode[] = [];
  if (showStatus && status !== null) {
    const { memory, knowledge, chats } = status.counts;
    const rowFor = (
      key: string,
      label: string,
      on: boolean,
      indexed: number,
      total: number,
      note: string | null = null,
    ): ReactNode => (
      <SettingsPanelRow
        key={key}
        label={label}
        description={
          on
            ? `${indexed} of ${total}${note === null ? '' : ` · ${note}`}`
            : 'Off'
        }>
        {on && indexed < total ? (
          <ProgressBar
            fraction={total > 0 ? indexed / total : null}
            label={`${label} indexed`}
          />
        ) : null}
      </SettingsPanelRow>
    );
    const chatNote = [chatsWord(chats), windowNoteOf(chatWindowDays)]
      .filter((part): part is string => part !== null)
      .join(' · ');
    statusRows.push(
      rowFor(
        'memory',
        'Memory notes',
        sources.memory,
        memory.indexed,
        memory.total,
      ),
      rowFor(
        'knowledge',
        'Knowledge documents',
        sources.knowledge,
        knowledge.indexed,
        knowledge.total,
      ),
      rowFor(
        'chats',
        'Chat messages',
        sources.chats,
        chats.indexed,
        chats.total,
        chatNote,
      ),
    );
    if (status.state === 'loading') {
      statusRows.push(
        <SettingsPanelRow key="loading" label="Loading the search model">
          <ProgressBar fraction={null} label="Loading the search model" />
        </SettingsPanelRow>,
      );
    }
    if (status.state === 'failed') {
      statusRows.push(
        <SettingsPanelRow
          key="index-failed"
          label="The index stopped"
          description={
            <span className="flex items-center gap-1.5 text-destructive">
              <TriangleAlert aria-hidden="true" className="size-4 shrink-0" />
              {status.failure ?? 'The index stopped without a reason.'}
            </span>
          }>
          {null}
        </SettingsPanelRow>,
      );
    }
  }

  const modelOnDisk = state !== null && state.modelBytes > 0;
  const indexBytes = status?.indexBytes ?? 0;
  const onDisk = modelOnDisk || indexBytes > 0;
  const onDiskText =
    state === null
      ? ''
      : phase === 'off'
        ? `The model and index are kept on this Mac (${sizeOnDisk(state.modelBytes + indexBytes)}). Turn this on again to use them at once.`
        : onDiskParts(state.modelBytes, indexBytes);

  return (
    <SettingsGroups>
      <SettingsGroup
        icon={<Sparkles />}
        title="Search by meaning"
        description="Also find notes, documents and chats by what they mean, not only by their words."
        hint="Word search keeps working whether or not this is on. Turning it on downloads the search model once, from Geniro's releases, and it runs on this Mac. Chats are indexed in the background at low priority, about four hours of CPU for your current history and then about ten minutes a day; the index grows about 150 MB a month, and chats pause while the Mac runs on battery.">
        <SettingsPanel>
          <SettingsPanelRow
            label="Search by meaning"
            htmlFor="settings-search-enabled"
            description={switchDescription()}
            hint="Off: agents and the app search by words only, exactly as before. On: a note, document or chat that means the same thing is found too.">
            <Switch
              id="settings-search-enabled"
              checked={state !== null && switchReadsOn(state.phase)}
              disabled={state === null || unsupported || remote}
              onCheckedChange={(on) =>
                act(() => window.geniro.setSearchByMeaning(on))
              }
            />
          </SettingsPanelRow>
          <SettingsPanelRow
            label="Memory"
            htmlFor="settings-search-source-memory"
            description="Find notes that mean the same thing, not only the same words."
            hint="Turning this off leaves your notes in place; word search keeps finding them.">
            <Switch
              id="settings-search-source-memory"
              checked={sources.memory}
              disabled={scopeOff}
              onCheckedChange={(on) => setSource('memory', on)}
            />
          </SettingsPanelRow>
          <SettingsPanelRow
            label="Knowledge"
            htmlFor="settings-search-source-knowledge"
            description="Find documents that mean the same thing, not only the same words."
            hint="Turning this off leaves the documents in place; word search keeps finding them.">
            <Switch
              id="settings-search-source-knowledge"
              checked={sources.knowledge}
              disabled={scopeOff}
              onCheckedChange={(on) => setSource('knowledge', on)}
            />
          </SettingsPanelRow>
          <SettingsPanelRow
            label="Chats"
            htmlFor="settings-search-source-chats"
            description="Indexing chats takes the most CPU and disk."
            hint="Chats outside the window below leave the meaning index; word search still finds them.">
            <Switch
              id="settings-search-source-chats"
              checked={sources.chats}
              disabled={scopeOff}
              onCheckedChange={(on) => setSource('chats', on)}
            />
          </SettingsPanelRow>
          <SettingsPanelRow
            label="Index chats from"
            htmlFor="settings-search-chat-window"
            description="Older chats leave the meaning index; word search still finds them."
            hint="Pick a period, or Custom for any number of whole days.">
            <Select
              id="settings-search-chat-window"
              aria-label="Index chats from"
              className="w-44"
              groups={CHAT_WINDOW_OPTIONS}
              value={windowValue}
              disabled={scopeOff || !sources.chats}
              onValueChange={pickWindow}
            />
          </SettingsPanelRow>
          {windowValue === CUSTOM_WINDOW ? (
            <SettingsPanelRow
              label="Number of days"
              htmlFor="settings-search-chat-days"
              description="Saves when you press Enter or leave the field."
              hint="Whole days, from 1 to 3650.">
              <Input
                id="settings-search-chat-days"
                type="number"
                inputMode="numeric"
                min={SEMANTIC_SEARCH_WINDOW_MIN_DAYS}
                max={SEMANTIC_SEARCH_WINDOW_MAX_DAYS}
                className="w-24"
                value={daysText}
                disabled={scopeOff || !sources.chats}
                onChange={(event) => {
                  setCustomText(event.target.value);
                  setWindowError(null);
                }}
                onBlur={commitDays}
                onKeyDown={(event) => {
                  if (event.key === 'Enter') {
                    commitDays();
                  }
                }}
              />
            </SettingsPanelRow>
          ) : null}
          {stateRows}
          {statusRows}
          {onDisk && state !== null ? (
            <SettingsPanelRow label="Model and index" description={onDiskText}>
              <ConfirmActionButton
                variant="outline"
                size="sm"
                disabled={actionsOff}
                title="Delete the search model and its index from this Mac"
                question="Delete the search model and index?"
                description="The model is removed from this Mac and search by meaning turns off. The index is deleted too. Turning search back on downloads the model and rebuilds the index."
                confirmLabel="Delete"
                busyLabel="Deleting…"
                onConfirm={deleteModelAndIndex}>
                Delete model and index…
              </ConfirmActionButton>
            </SettingsPanelRow>
          ) : null}
        </SettingsPanel>
        {actionError === null ? null : <ErrorText>{actionError}</ErrorText>}
        {scopeError === null ? null : <ErrorText>{scopeError}</ErrorText>}
        {windowError === null ? null : <ErrorText>{windowError}</ErrorText>}
        {stateReadError === null && statusReadError === null ? null : (
          <ErrorText>
            {`Could not read the search status: ${stateReadError ?? statusReadError ?? ''}`}
          </ErrorText>
        )}
      </SettingsGroup>
    </SettingsGroups>
  );
}
