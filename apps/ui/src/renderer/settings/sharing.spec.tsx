// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  DEFAULT_SETTINGS,
  type Settings,
  type SharingSettings,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type {
  Share,
  ShareCheckResultDto,
  ShareSignInSessionDto,
} from '../autogenerated';
import { Sharing } from './sharing';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const GCS = {
  kind: 'gcs' as const,
  id: 'company',
  name: 'Company',
  linkBase: 'https://artifacts.example.com',
  bucket: 'company-share',
};

const SHARED: Share = {
  id: 'share-1',
  runId: 'run-1',
  artifactId: 'report',
  title: 'Delivery report',
  destinationId: 'company',
  destinationName: 'Company',
  sharedVersion: 3,
  sharedBy: 'agent',
  status: 'live',
  lastError: null,
  signIn: { cli: 'gcloud', label: 'Google Cloud' },
  askedByAgent: false,
  createdAt: '2026-10-15T00:00:00.000Z',
  updatedAt: '2026-10-15T00:00:00.000Z',
};

let container: HTMLDivElement;
let root: Root;
let writes: Partial<Settings>[];

function install(sharing: SharingSettings): void {
  writes = [];
  window.geniro = createPreloadStub({
    getSettings: () => Promise.resolve({ ...DEFAULT_SETTINGS, sharing }),
    updateSettings: (patch) => {
      writes.push(patch);
      return Promise.resolve({ ...DEFAULT_SETTINGS, ...patch });
    },
  });
}

const SIGN_IN: ShareSignInSessionDto = {
  id: 'sign-in-1',
  destinationId: 'company',
  label: 'Google Cloud',
  cli: 'gcloud',
  status: 'succeeded',
  lines: [],
  url: null,
  message: null,
  retried: ['share-1'],
};

function fakeApi(
  shares: Share[] = [],
  checked: ShareCheckResultDto = {
    state: 'signed-in',
    detail: 'Reached Company.',
    signIn: { cli: 'gcloud', label: 'Google Cloud' },
  },
) {
  return {
    listShares: vi.fn(() =>
      Promise.resolve({ shares, configReceivedAt: '2026-10-15T00:00:00Z' }),
    ),
    checkShareDestination: vi.fn(() => Promise.resolve(checked)),
    startShareSignIn: vi.fn(() => Promise.resolve(SIGN_IN)),
    readShareSignIn: vi.fn(() => Promise.resolve(SIGN_IN)),
    cancelShareSignIn: vi.fn(() => Promise.resolve(SIGN_IN)),
    readShareLink: vi.fn(() => Promise.resolve({ url: 'https://x#k=K' })),
    revokeShare: vi.fn(() => Promise.resolve({ status: 'revoked' as const })),
  };
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

async function render(
  api: ReturnType<typeof fakeApi> | null,
  remote = false,
): Promise<void> {
  await act(async () => {
    root.render(<Sharing api={api} remote={remote} />);
  });
}

function button(text: string): HTMLButtonElement {
  const found = [...container.querySelectorAll('button')].find(
    (b) => b.textContent?.trim() === text,
  );
  if (!found) {
    throw new Error(`no button "${text}"`);
  }
  return found;
}

async function press(element: HTMLElement): Promise<void> {
  await act(async () => {
    element.click();
  });
}

/** The control a visible `<label>` reading exactly `text` points at. */
function labelled(text: string): HTMLInputElement | null {
  const label = Array.from(container.querySelectorAll('label')).find(
    (candidate) => candidate.textContent === text,
  );
  const control = label?.htmlFor
    ? document.getElementById(label.htmlFor)
    : null;
  return control instanceof HTMLInputElement ? control : null;
}

async function type(label: string, value: string): Promise<void> {
  const input = labelled(label);
  if (!input) {
    throw new Error(`no field "${label}"`);
  }
  await act(async () => {
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )?.set;
    setter?.call(input, value);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

describe('Settings → Sharing', () => {
  it('turns agent sharing on with one switch, keeping the places as they are', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: false,
    });
    await render(fakeApi());

    await press(
      container.querySelector<HTMLButtonElement>('#settings-agents-share')!,
    );

    expect(writes).toEqual([
      {
        sharing: {
          destinations: [GCS],
          defaultDestinationId: 'company',
          agentsMayShare: true,
        },
      },
    ]);
  });

  it('adds a bucket and makes the first place the default', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
    });
    await render(fakeApi());

    await press(button('Add a place'));
    await type('Name', 'Company');
    await type('Link address', 'https://artifacts.example.com');
    await type('Bucket', 'company-share');
    await type('Folder in the bucket', 'geniro');
    await press(button('Save place'));

    const saved = writes[0]?.sharing;
    expect(saved?.destinations).toEqual([
      expect.objectContaining({
        kind: 'gcs',
        name: 'Company',
        linkBase: 'https://artifacts.example.com',
        bucket: 'company-share',
        prefix: 'geniro',
      }),
    ]);
    expect(saved?.defaultDestinationId).toBe(saved?.destinations[0]?.id);
  });

  it('labels every field visibly, so a filled-in form still says which is which', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
    });
    await render(fakeApi());
    await press(button('Add a place'));

    for (const text of [
      'Kind of place',
      'Name',
      'Link address',
      'Bucket',
      'Folder in the bucket',
    ]) {
      const label = Array.from(container.querySelectorAll('label')).find(
        (candidate) => candidate.textContent === text,
      );
      expect(label?.htmlFor, text).toBeTruthy();
      expect(
        document.getElementById(label?.htmlFor ?? ''),
        text,
      ).not.toBeNull();
    }
  });

  it('refuses a link address that is not https, writing nothing', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
    });
    await render(fakeApi());

    await press(button('Add a place'));
    await type('Name', 'Plain');
    await type('Link address', 'http://insecure.example.com');
    await type('Bucket', 'b-u-c');
    await press(button('Save place'));

    expect(writes).toEqual([]);
    expect(container.textContent).toContain('must start with https://');
  });

  it('keeps what was typed when main refuses the place, so it can be corrected', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
    });
    window.geniro = {
      ...window.geniro,
      updateSettings: () => Promise.reject(new Error('Invalid prefix')),
    };
    await render(fakeApi());

    await press(button('Add a place'));
    await type('Name', 'Company');
    await type('Link address', 'https://artifacts.example.com');
    await type('Bucket', 'company-share');
    await press(button('Save place'));

    expect(container.textContent).toContain('Invalid prefix');
    expect(labelled('Name')?.value).toBe('Company');
    expect(button('Save place').disabled).toBe(false);
  });

  it('saves a place once however often Save is pressed while the write is pending', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
    });
    let finish: () => void = () => undefined;
    const pending: Partial<Settings>[] = [];
    window.geniro = {
      ...window.geniro,
      updateSettings: (patch) => {
        pending.push(patch);
        return new Promise((resolve) => {
          finish = () => resolve({ ...DEFAULT_SETTINGS, ...patch });
        });
      },
    };
    await render(fakeApi());

    await press(button('Add a place'));
    await type('Name', 'Company');
    await type('Link address', 'https://artifacts.example.com');
    await type('Bucket', 'company-share');
    await press(button('Save place'));
    await press(button('Save place'));

    expect(pending).toHaveLength(1);
    await act(async () => finish());
    expect(container.querySelector('[data-slot="sharing-form"]')).toBeNull();
  });

  it('checks nothing on open, then checks a place through the daemon on Check', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: false,
    });
    const api = fakeApi();
    await render(api);
    expect(api.checkShareDestination).not.toHaveBeenCalled();
    expect(container.textContent).toContain('Not checked');

    await press(button('Check'));

    expect(api.checkShareDestination).toHaveBeenCalledWith({
      checkShareDestinationDto: { destination: GCS },
    });
    expect(container.textContent).toContain('Signed in');
    expect(container.textContent).not.toContain('Sign in to');
  });

  it('offers Sign in when the check says sign-in is required, then rechecks and retries what waited', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: false,
    });
    const api = fakeApi([], {
      state: 'sign-in-required',
      detail: 'does not have any valid credentials',
      signIn: { cli: 'gcloud', label: 'Google Cloud' },
    });
    await render(api);
    await press(button('Check'));
    expect(container.textContent).toContain('Sign-in required');
    const listsBefore = api.listShares.mock.calls.length;

    await press(button('Sign in to Google Cloud'));

    expect(api.startShareSignIn).toHaveBeenCalledWith({
      startShareSignInDto: { destinationId: 'company' },
    });
    await vi.waitFor(() =>
      expect(container.textContent).toContain('Retrying 1 waiting share…'),
    );
    expect(api.checkShareDestination).toHaveBeenCalledTimes(2);
    expect(api.listShares.mock.calls.length).toBeGreaterThan(listsBefore);
  });

  it('says a failed check without offering a sign-in that could not help', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: false,
    });
    const api = fakeApi([], {
      state: 'check-failed',
      detail: 'gs://company-share not found: 404.',
      signIn: { cli: 'gcloud', label: 'Google Cloud' },
    });
    await render(api);

    await press(button('Check'));

    expect(container.textContent).toContain('Check failed');
    expect(container.textContent).toContain('not found: 404.');
    expect(container.textContent).not.toContain('Sign in to');
  });

  it('saves a custom place’s optional sign-in, one token or phrase per line', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
    });
    await render(fakeApi());
    await press(button('Add a place'));
    const form = container.querySelector('[data-slot="sharing-form"]');
    const kindTrigger = form?.querySelector<HTMLElement>('[data-menu-trigger]');
    await press(kindTrigger!);
    const ownCommand = [...document.querySelectorAll('[role="option"]')].find(
      (option) => option.textContent === 'Your own command',
    ) as HTMLElement;
    await press(ownCommand);
    await type('Name', 'Own');
    await type('Link address', 'https://pages.example.com');
    const area = (label: string, value: string) => {
      const field = [...container.querySelectorAll('label')].find(
        (candidate) => candidate.textContent === label,
      );
      const textarea = document.getElementById(field?.htmlFor ?? '');
      if (!(textarea instanceof HTMLTextAreaElement)) {
        throw new Error(`no field "${label}"`);
      }
      Object.getOwnPropertyDescriptor(
        HTMLTextAreaElement.prototype,
        'value',
      )?.set?.call(textarea, value);
      textarea.dispatchEvent(new Event('input', { bubbles: true }));
    };
    await act(async () => {
      area('Upload command', '/usr/local/bin/put\n{file}\n{object}');
      area('Remove command', '/usr/local/bin/del\n{object}');
      area('Login command', '/usr/local/bin/put\nlogin');
      area('Sign-in required when output contains', 'session expired\n');
    });

    await press(button('Save place'));

    expect(writes[0]?.sharing?.destinations).toEqual([
      expect.objectContaining({
        kind: 'command',
        signIn: {
          login: ['/usr/local/bin/put', 'login'],
          patterns: ['session expired'],
        },
      }),
    ]);
  });

  it('lists every shared page, who shared it, and revokes after confirming', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
    });
    const api = fakeApi([SHARED]);
    await render(api);

    expect(container.textContent).toContain('Delivery report');
    expect(container.textContent).toContain('by an agent');
    expect(button('Get link')).toBeTruthy();

    await press(button('Revoke'));
    await press(button('Revoke link?'));

    expect(api.revokeShare).toHaveBeenCalledWith({ shareId: 'share-1' });
  });

  it('lists a share waiting on sign-in without a link to get', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
    });
    await render(
      fakeApi([{ ...SHARED, status: 'awaiting-sign-in', sharedVersion: 0 }]),
    );

    expect(container.textContent).toContain('waiting on sign-in');
    expect(container.textContent).not.toContain('v0');
    expect(
      [...container.querySelectorAll('button')].some(
        (b) => b.textContent === 'Get link',
      ),
    ).toBe(false);
  });

  it('on a paired phone says sharing is set up on the Mac and offers nothing to change', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
    });
    const api = fakeApi([SHARED]);
    await render(api, true);

    expect(container.textContent).toContain('Sharing is set up on the Mac.');
    expect(container.querySelector('#settings-agents-share')).toBeNull();
    expect(api.listShares).not.toHaveBeenCalled();
  });
});
