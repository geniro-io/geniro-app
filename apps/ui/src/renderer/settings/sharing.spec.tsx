// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  DEFAULT_SETTINGS,
  type Settings,
  type SharingSettings,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { RevokeAllSharesDto, Share } from '../autogenerated';
import { Sharing } from './sharing';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const GCS = {
  kind: 'gcs' as const,
  id: 'company',
  name: 'Company',
  linkBase: 'https://artifacts.example.com',
  bucket: 'company-share',
};

const SHARED: Share = {
  id: 'share-1',
  runId: 'run-1',
  artifactId: 'report',
  title: 'Delivery report',
  destinationId: 'company',
  destinationName: 'Company',
  sharedVersion: 3,
  sharedBy: 'agent',
  status: 'live',
  lastError: null,
  createdAt: '2026-10-15T00:00:00.000Z',
  updatedAt: '2026-10-15T00:00:00.000Z',
};

let container: HTMLDivElement;
let root: Root;
let writes: Partial<Settings>[];

function install(sharing: SharingSettings): void {
  writes = [];
  window.geniro = createPreloadStub({
    getSettings: () => Promise.resolve({ ...DEFAULT_SETTINGS, sharing }),
    updateSettings: (patch) => {
      writes.push(patch);
      return Promise.resolve({ ...DEFAULT_SETTINGS, ...patch });
    },
  });
}

function fakeApi(shares: Share[] = []) {
  return {
    listShares: vi.fn(() =>
      Promise.resolve({ shares, configReceivedAt: '2026-10-15T00:00:00Z' }),
    ),
    probeShareDestination: vi.fn(() =>
      Promise.resolve({ ok: true, detail: 'Reached Company.' }),
    ),
    readShareLink: vi.fn(() => Promise.resolve({ url: 'https://x#k=K' })),
    revokeShare: vi.fn(() => Promise.resolve({ status: 'revoked' as const })),
    revokeAllShares: vi.fn(
      (
        _request: { revokeSharesDto: { shareIds: string[] } },
        _init?: RequestInit,
      ): Promise<RevokeAllSharesDto> =>
        Promise.resolve({ revoked: shares.length, failed: 0, detail: null }),
    ),
  };
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

async function render(
  api: ReturnType<typeof fakeApi> | null,
  remote = false,
): Promise<void> {
  await act(async () => {
    root.render(<Sharing api={api} remote={remote} />);
  });
}

function button(text: string): HTMLButtonElement {
  const found = [...container.querySelectorAll('button')].find(
    (b) => b.textContent?.trim() === text,
  );
  if (!found) {
    throw new Error(`no button "${text}"`);
  }
  return found;
}

async function press(element: HTMLElement): Promise<void> {
  await act(async () => {
    element.click();
  });
}

/** The control a visible `<label>` reading exactly `text` points at. */
function labelled(text: string): HTMLInputElement | null {
  const label = Array.from(container.querySelectorAll('label')).find(
    (candidate) => candidate.textContent === text,
  );
  const control = label?.htmlFor
    ? document.getElementById(label.htmlFor)
    : null;
  return control instanceof HTMLInputElement ? control : null;
}

function optionNamed(label: string): HTMLElement {
  const option = [
    ...document.querySelectorAll<HTMLElement>('[role="option"]'),
  ].find((candidate) => (candidate.textContent ?? '').trim() === label);
  if (!option) {
    throw new Error(`no "${label}" option`);
  }
  return option;
}

async function type(label: string, value: string): Promise<void> {
  const input = labelled(label);
  if (!input) {
    throw new Error(`no field "${label}"`);
  }
  await act(async () => {
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )?.set;
    setter?.call(input, value);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

describe('Settings → Sharing', () => {
  it('turns agent sharing on with one switch, keeping the places as they are', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: false,
      autoRevokeAfterDays: null,
    });
    await render(fakeApi());

    await press(
      container.querySelector<HTMLButtonElement>('#settings-agents-share')!,
    );

    expect(writes).toEqual([
      {
        sharing: {
          destinations: [GCS],
          defaultDestinationId: 'company',
          agentsMayShare: true,
          autoRevokeAfterDays: null,
        },
      },
    ]);
  });

  it('adds a bucket and makes the first place the default', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
      autoRevokeAfterDays: null,
    });
    await render(fakeApi());

    await press(button('Add a place'));
    await type('Name', 'Company');
    await type('Link address', 'https://artifacts.example.com');
    await type('Bucket', 'company-share');
    await type('Folder in the bucket', 'geniro');
    await press(button('Save place'));

    const saved = writes[0]?.sharing;
    expect(saved?.destinations).toEqual([
      expect.objectContaining({
        kind: 'gcs',
        name: 'Company',
        linkBase: 'https://artifacts.example.com',
        bucket: 'company-share',
        prefix: 'geniro',
      }),
    ]);
    expect(saved?.defaultDestinationId).toBe(saved?.destinations[0]?.id);
  });

  it('labels every field visibly, so a filled-in form still says which is which', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
      autoRevokeAfterDays: null,
    });
    await render(fakeApi());
    await press(button('Add a place'));

    for (const text of [
      'Kind of place',
      'Name',
      'Link address',
      'Bucket',
      'Folder in the bucket',
    ]) {
      const label = Array.from(container.querySelectorAll('label')).find(
        (candidate) => candidate.textContent === text,
      );
      expect(label?.htmlFor, text).toBeTruthy();
      expect(
        document.getElementById(label?.htmlFor ?? ''),
        text,
      ).not.toBeNull();
    }
  });

  it('refuses a link address that is not https, writing nothing', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
      autoRevokeAfterDays: null,
    });
    await render(fakeApi());

    await press(button('Add a place'));
    await type('Name', 'Plain');
    await type('Link address', 'http://insecure.example.com');
    await type('Bucket', 'b-u-c');
    await press(button('Save place'));

    expect(writes).toEqual([]);
    expect(container.textContent).toContain('must start with https://');
  });

  it('keeps what was typed when main refuses the place, so it can be corrected', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
      autoRevokeAfterDays: null,
    });
    window.geniro = {
      ...window.geniro,
      updateSettings: () => Promise.reject(new Error('Invalid prefix')),
    };
    await render(fakeApi());

    await press(button('Add a place'));
    await type('Name', 'Company');
    await type('Link address', 'https://artifacts.example.com');
    await type('Bucket', 'company-share');
    await press(button('Save place'));

    expect(container.textContent).toContain('Invalid prefix');
    expect(labelled('Name')?.value).toBe('Company');
    expect(button('Save place').disabled).toBe(false);
  });

  it('saves a place once however often Save is pressed while the write is pending', async () => {
    install({
      destinations: [],
      defaultDestinationId: null,
      agentsMayShare: false,
      autoRevokeAfterDays: null,
    });
    let finish: () => void = () => undefined;
    const pending: Partial<Settings>[] = [];
    window.geniro = {
      ...window.geniro,
      updateSettings: (patch) => {
        pending.push(patch);
        return new Promise((resolve) => {
          finish = () => resolve({ ...DEFAULT_SETTINGS, ...patch });
        });
      },
    };
    await render(fakeApi());

    await press(button('Add a place'));
    await type('Name', 'Company');
    await type('Link address', 'https://artifacts.example.com');
    await type('Bucket', 'company-share');
    await press(button('Save place'));
    await press(button('Save place'));

    expect(pending).toHaveLength(1);
    await act(async () => finish());
    expect(container.querySelector('[data-slot="sharing-form"]')).toBeNull();
  });

  it('tests a place through the daemon and shows what it said', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: false,
      autoRevokeAfterDays: null,
    });
    const api = fakeApi();
    await render(api);

    await press(button('Test'));

    expect(api.probeShareDestination).toHaveBeenCalledWith({
      probeShareDestinationDto: { destination: GCS },
    });
    expect(container.textContent).toContain('Reached Company.');
  });

  it('lists every shared page, who shared it, and revokes after confirming', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
      autoRevokeAfterDays: null,
    });
    const api = fakeApi([SHARED]);
    await render(api);

    expect(container.textContent).toContain('Delivery report');
    expect(container.textContent).toContain('by an agent');

    await press(button('Revoke'));
    await press(button('Revoke link?'));

    expect(api.revokeShare).toHaveBeenCalledWith({ shareId: 'share-1' });
  });

  it('shows the date each page was first shared', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
      autoRevokeAfterDays: null,
    });
    await render(
      fakeApi([{ ...SHARED, updatedAt: '2026-10-20T00:00:00.000Z' }]),
    );

    const time = container.querySelector('time');
    expect(time?.dateTime).toBe('2026-10-15T00:00:00.000Z');
    expect(time?.textContent).toMatch(/^Oct 1[45], 2026, \d\d:\d\d$/);
  });

  it('revokes exactly the listed pages after confirming, then lists what is left', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
      autoRevokeAfterDays: null,
    });
    const api = fakeApi([SHARED, { ...SHARED, id: 'share-2' }]);
    await render(api);
    const survivor = { ...SHARED, id: 'share-3', title: 'Shared meanwhile' };
    api.listShares.mockResolvedValue({
      shares: [survivor],
      configReceivedAt: '2026-10-15T00:00:00Z',
    });

    await press(button('Revoke all'));
    expect(api.revokeAllShares).not.toHaveBeenCalled();
    await press(button('Revoke all 2?'));

    expect(api.revokeAllShares).toHaveBeenCalledWith(
      { revokeSharesDto: { shareIds: ['share-1', 'share-2'] } },
      expect.objectContaining({ signal: expect.any(AbortSignal) }),
    );
    expect(api.revokeShare).not.toHaveBeenCalled();
    expect(container.textContent).toContain('Shared meanwhile');
    expect(container.textContent).not.toContain('Delivery report');
  });

  it('shows the daemon’s refusal of a Revoke all and reads the list again', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
      autoRevokeAfterDays: null,
    });
    const api = fakeApi([SHARED]);
    api.revokeAllShares.mockRejectedValue(new Error('daemon unreachable'));
    await render(api);

    await press(button('Revoke all'));
    await press(button('Revoke all 1?'));

    expect(container.textContent).toContain('daemon unreachable');
    expect(api.listShares).toHaveBeenCalledTimes(2);
  });

  it('says how many links survived a Revoke all, and why', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
      autoRevokeAfterDays: null,
    });
    const api = fakeApi([SHARED, { ...SHARED, id: 'share-2' }]);
    api.revokeAllShares.mockResolvedValue({
      revoked: 1,
      failed: 1,
      detail: 'ERROR: permission denied',
    });
    await render(api);

    await press(button('Revoke all'));
    await press(button('Revoke all 2?'));

    expect(container.textContent).toContain(
      '1 of 2 links could not be removed: ERROR: permission denied',
    );
  });

  it('offers no Revoke all while nothing is shared', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
      autoRevokeAfterDays: null,
    });
    await render(fakeApi());

    expect(() => button('Revoke all')).toThrow();
  });

  it('saves an auto-revoke window as a number of days, and Never as null', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: false,
      autoRevokeAfterDays: null,
    });
    await render(fakeApi());
    const picker = container.querySelector<HTMLButtonElement>(
      '#settings-share-auto-revoke',
    )!;
    expect(picker.textContent).toContain('Never');

    await press(picker);
    await press(optionNamed('After 30 days'));
    await press(picker);
    await press(optionNamed('Never'));

    expect(writes.map((w) => w.sharing?.autoRevokeAfterDays)).toEqual([
      30,
      null,
    ]);
    expect(writes[0]?.sharing).toEqual({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: false,
      autoRevokeAfterDays: 30,
    });
  });

  it('on a paired phone says sharing is set up on the Mac and offers nothing to change', async () => {
    install({
      destinations: [GCS],
      defaultDestinationId: 'company',
      agentsMayShare: true,
      autoRevokeAfterDays: null,
    });
    const api = fakeApi([SHARED]);
    await render(api, true);

    expect(container.textContent).toContain('Sharing is set up on the Mac.');
    expect(container.querySelector('#settings-agents-share')).toBeNull();
    expect(api.listShares).not.toHaveBeenCalled();
  });
});
