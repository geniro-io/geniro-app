type SharesClient = Pick<
  SharesApi,
  'listShares' | 'probeShareDestination' | 'readShareLink' | 'revokeShare'
>;

type Kind = ShareDestination['kind'];

const KIND_LABEL: Record<Kind, string> = {
  gcs: 'Google Cloud Storage (gcloud)',
  s3: 'Amazon S3 (aws)',
  command: 'Your own command',
};

/** The add-a-destination form, as typed — turned into a destination on save. */
interface Draft {
  kind: Kind;
  name: string;
  linkBase: string;
  bucket: string;
  prefix: string;
  profile: string;
  region: string;
  /** One argv token per line. */
  upload: string;
  remove: string;
}

const EMPTY_DRAFT: Draft = {
  kind: 'gcs',
  name: '',
  linkBase: '',
  bucket: '',
  prefix: '',
  profile: '',
  region: '',
  upload: '',
  remove: '',
};

const lines = (text: string): string[] =>
  text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

/** The draft as a destination, or the reason it is not one yet. */
function destinationFrom(draft: Draft): ShareDestination | string {
  const name = draft.name.trim();
  const linkBase = draft.linkBase.trim();
  if (name === '') {
    return 'Give it a name.';
  }
  if (!linkBase.startsWith('https://')) {
    return 'The link address must start with https://.';
  }
  const base = { id: randomId(), name, linkBase };
  const optional = (value: string): string | undefined =>
    value.trim() === '' ? undefined : value.trim();
  if (draft.kind === 'command') {
    const upload = lines(draft.upload);
    const remove = lines(draft.remove);
    if (upload.length === 0 || remove.length === 0) {
      return 'Both commands need at least the program, one token per line.';
    }
    return { kind: 'command', ...base, upload, remove };
  }
  if (draft.bucket.trim() === '') {
    return 'Name the bucket.';
  }
  const prefix = optional(draft.prefix);
  if (draft.kind === 'gcs') {
    return {
      kind: 'gcs',
      ...base,
      bucket: draft.bucket.trim(),
      ...(prefix === undefined ? {} : { prefix }),
    };
  }
  const profile = optional(draft.profile);
  const region = optional(draft.region);
  return {
    kind: 's3',
    ...base,
    bucket: draft.bucket.trim(),
    ...(prefix === undefined ? {} : { prefix }),
    ...(profile === undefined ? {} : { profile }),
    ...(region === undefined ? {} : { region }),
  };
}

function summaryOf(destination: ShareDestination): string {
  switch (destination.kind) {
    case 'gcs':
      return `gs://${destination.bucket}/${destination.prefix ?? ''}`;
    case 's3':
      return `s3://${destination.bucket}/${destination.prefix ?? ''}`;
    case 'command':
      return destination.upload.join(' ');
  }
}

/**
 * Settings → Sharing: where encrypted page links are uploaded, whether agents
 * may share, and every page shared so far with its revoke.
 *
 * The places are kept in settings.json and handed to the daemon by main; each
 * upload runs through the user's own CLI and login, so nothing here holds a
 * credential. Desktop only — a paired phone may read this page but not change
 * it.
 */
export function Sharing({
  api,
  remote = isRemoteRuntime(),
}: {
  api: SharesClient | null;
  remote?: boolean;
}): React.JSX.Element {
  const [sharing, setSharing] = useState<SharingSettings | null>(null);
  const [shares, setShares] = useState<Share[]>([]);
  const [received, setReceived] = useState<string | null>(null);
  const [draft, setDraft] = useState<Draft | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [probes, setProbes] = useState<Record<string, string>>({});
  const [links, setLinks] = useState<Record<string, string>>({});
  const [savingPlace, setSavingPlace] = useState(false);

  const readShares = useCallback(() => {
    if (api === null || remote) {
      return;
    }
    void api
      .listShares({})
      .then((answer) => {
        setShares(answer.shares);
        setReceived(answer.configReceivedAt);
      })
      .catch((err: unknown) => setError(describeDaemonError(err)));
  }, [api, remote]);

  useEffect(() => {
    void window.geniro
      .getSettings()
      .then((settings) => setSharing(settings.sharing))
      .catch((err: unknown) => setError(String(err)));
    readShares();
  }, [readShares]);

  // Main hands a saved value to the daemon as it writes the file, and that
  // push is not awaited by the save, so the "has these settings" line is
  // re-read a moment later rather than at once.
  const reread = useRef<ReturnType<typeof setTimeout> | null>(null);
  useEffect(
    () => () => {
      if (reread.current !== null) {
        clearTimeout(reread.current);
      }
    },
    [],
  );

  /** Resolves true once the file holds `next`; on refusal the screen goes back. */
  const save = (next: SharingSettings): Promise<boolean> => {
    setError(null);
    const before = sharing;
    setSharing(next);
    return window.geniro
      .updateSettings({ sharing: next })
      .then(() => {
        if (reread.current !== null) {
          clearTimeout(reread.current);
        }
        reread.current = setTimeout(readShares, 500);
        return true;
      })
      .catch((err: unknown) => {
        setSharing(before);
        setError(String(err));
        return false;
      });
  };

  if (remote) {
    return (
      <SettingsPanel>
        <SettingsPanelRow layout="block">
          <p className="text-sm text-muted-foreground">
            Sharing is set up on the Mac.
          </p>
        </SettingsPanelRow>
      </SettingsPanel>
    );
  }

  const current = sharing ?? DEFAULT_SHARING;

  const addDestination = (): void => {
    if (draft === null) {
      return;
    }
    const made = destinationFrom(draft);
    if (typeof made === 'string') {
      setError(made);
      return;
    }
    // The form stays filled until the write lands, so a refusal (a value
    // main's schema rejects) leaves what the user typed to correct.
    setSavingPlace(true);
    void save({
      ...current,
      destinations: [...current.destinations, made],
      defaultDestinationId: current.defaultDestinationId ?? made.id,
    }).then((saved) => {
      setSavingPlace(false);
      if (saved) {
        setDraft(null);
      }
    });
  };

  const removeDestination = async (id: string): Promise<void> => {
    await save({
      ...current,
      destinations: current.destinations.filter((d) => d.id !== id),
      defaultDestinationId:
        current.defaultDestinationId === id
          ? null
          : current.defaultDestinationId,
    });
  };

  const probe = (destination: ShareDestination): void => {
    if (api === null) {
      return;
    }
    setProbes((all) => ({ ...all, [destination.id]: 'Testing…' }));
    void api
      .probeShareDestination({ probeShareDestinationDto: { destination } })
      .then((result) =>
        setProbes((all) => ({ ...all, [destination.id]: result.detail })),
      )
      .catch((err: unknown) =>
        setProbes((all) => ({
          ...all,
          [destination.id]: describeDaemonError(err),
        })),
      );
  };

  // A link's key lives in the Keychain, so it is read on demand and then
  // handed to the shared copy control.
  const showLink = (id: string): void => {
    if (api === null) {
      return;
    }
    void api
      .readShareLink({ shareId: id })
      .then((answer) => setLinks((all) => ({ ...all, [id]: answer.url })))
      .catch((err: unknown) => setError(describeDaemonError(err)));
  };

  const revoke = async (id: string): Promise<void> => {
    if (api === null) {
      return;
    }
    try {
      const outcome = await api.revokeShare({ shareId: id });
      if (outcome.status === 'revoke-failed') {
        setError(revokeFailedMessage(outcome.detail));
      }
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    }
    readShares();
  };

  return (
    <div data-slot="sharing" className="flex flex-col gap-3">
      {error !== null && (
        <ErrorBanner message={error} onDismiss={() => setError(null)} />
      )}

      <SettingsPanel>
        <SettingsPanelRow
          label="Let agents share pages"
          htmlFor="settings-agents-share"
          description="An agent asked to share a page uploads it to the default place below and gets its link.">
          <Switch
            id="settings-agents-share"
            checked={current.agentsMayShare}
            disabled={sharing === null}
            onCheckedChange={(on) => save({ ...current, agentsMayShare: on })}
          />
        </SettingsPanelRow>
        <SettingsPanelRow
          label="Share to"
          description="Where a Share press and an agent upload.">
          <Select
            aria-label="Default place to share to"
            value={current.defaultDestinationId}
            placeholder="Nowhere yet"
            groups={[
              {
                label: 'Places',
                items: current.destinations.map((d) => ({
                  value: d.id,
                  label: d.name,
                })),
              },
            ]}
            onValueChange={(id) =>
              save({ ...current, defaultDestinationId: id })
            }
          />
        </SettingsPanelRow>
        <SettingsPanelRow layout="block">
          <p className="text-xs text-muted-foreground">
            {received === null
              ? 'Not yet handed to the daemon — sharing is off until it is.'
              : 'The daemon has these settings.'}{' '}
            Pages are encrypted on this Mac; only ciphertext is uploaded, and
            the key travels in the link after #.
          </p>
        </SettingsPanelRow>
      </SettingsPanel>

      <SettingsPanel>
        <SettingsPanelRow layout="block" label="Places to share to">
          <ul className="flex flex-col gap-2">
            {current.destinations.map((destination) => (
              <li
                key={destination.id}
                className="flex min-w-0 flex-col gap-1 rounded-md border border-border p-2">
                <div className="flex min-w-0 items-center gap-2">
                  <span className="shrink-0 font-medium">
                    {destination.name}
                  </span>
                  <span className="min-w-0 flex-1 truncate text-xs text-muted-foreground">
                    {summaryOf(destination)}
                  </span>
                  <span className="ml-auto flex shrink-0 gap-1">
                    {destination.kind !== 'command' && (
                      <Button
                        type="button"
                        size="sm"
                        variant="outline"
                        onClick={() => probe(destination)}>
                        Test
                      </Button>
                    )}
                    <ConfirmButton
                      size="sm"
                      confirmLabel="Remove?"
                      onConfirm={() => removeDestination(destination.id)}>
                      Remove
                    </ConfirmButton>
                  </span>
                </div>
                {probes[destination.id] !== undefined && (
                  <p className="text-xs text-muted-foreground">
                    {probes[destination.id]}
                  </p>
                )}
              </li>
            ))}
          </ul>
          {draft === null ? (
            <Button
              type="button"
              size="sm"
              variant="outline"
              className="mt-2 self-start"
              disabled={sharing === null}
              onClick={() => setDraft(EMPTY_DRAFT)}>
              Add a place
            </Button>
          ) : (
            <DestinationForm
              draft={draft}
              onChange={setDraft}
              onCancel={() => setDraft(null)}
              onSave={addDestination}
              saving={savingPlace}
            />
          )}
        </SettingsPanelRow>
      </SettingsPanel>

      <SettingsPanel>
        <SettingsPanelRow layout="block" label="Shared pages">
          {shares.length === 0 ? (
            <p className="text-sm text-muted-foreground">Nothing shared yet.</p>
          ) : (
            <ul className="flex flex-col gap-1">
              {shares.map((share) => (
                <li
                  key={share.id}
                  className="flex min-w-0 items-center gap-2 text-sm">
                  <span className="truncate">{share.title}</span>
                  <span className="shrink-0 text-xs text-muted-foreground">
                    v{share.sharedVersion} ·{' '}
                    {share.sharedBy === 'agent' ? 'by an agent' : 'by you'} ·{' '}
                    {share.destinationName}
                    {share.status === 'revoke-failed' ? ' · revoke failed' : ''}
                  </span>
                  <span className="ml-auto flex shrink-0 gap-1">
                    {links[share.id] === undefined ? (
                      <Button
                        type="button"
                        size="sm"
                        variant="ghost"
                        onClick={() => showLink(share.id)}>
                        Get link
                      </Button>
                    ) : (
                      <CopyButton
                        text={links[share.id] ?? ''}
                        label="Copy link"
                      />
                    )}
                    <ConfirmButton
                      size="sm"
                      confirmLabel="Revoke link?"
                      onConfirm={() => revoke(share.id)}>
                      Revoke
                    </ConfirmButton>
                  </span>
                </li>
              ))}
            </ul>
          )}
        </SettingsPanelRow>
      </SettingsPanel>
    </div>
  );
}

function DestinationForm({
  draft,
  onChange,
  onCancel,
  onSave,
  saving,
}: {
  draft: Draft;
  onChange: (next: Draft) => void;
  onCancel: () => void;
  onSave: () => void;
  saving: boolean;
}): React.JSX.Element {
  const field = (
    key: Exclude<keyof Draft, 'kind'>,
    label: string,
    placeholder: string,
  ): React.JSX.Element => (
    <Input
      aria-label={label}
      placeholder={placeholder}
      value={draft[key]}
      onChange={(event) => onChange({ ...draft, [key]: event.target.value })}
    />
  );
  return (
    <div className="mt-2 flex flex-col gap-2" data-slot="sharing-form">
      <Select
        aria-label="Kind of place"
        value={draft.kind}
        groups={[
          {
            label: 'Upload with',
            items: (Object.keys(KIND_LABEL) as Kind[]).map((kind) => ({
              value: kind,
              label: KIND_LABEL[kind],
            })),
          },
        ]}
        onValueChange={(kind) => onChange({ ...draft, kind: kind as Kind })}
      />
      {field('name', 'Name', 'Company artifacts')}
      {field('linkBase', 'Link address', 'https://artifacts.example.com')}
      <p className="text-xs text-muted-foreground">
        Use a domain of your own. A shared one (storage.googleapis.com,
        s3.amazonaws.com) lets any other page on it read the key from a link.
      </p>
      {draft.kind === 'command' ? (
        <>
          <Textarea
            aria-label="Upload command"
            placeholder={'/usr/local/bin/upload\n--src={file}\n{object}'}
            value={draft.upload}
            onChange={(event) =>
              onChange({ ...draft, upload: event.target.value })
            }
          />
          <Textarea
            aria-label="Remove command"
            placeholder={'/usr/local/bin/delete\n{object}'}
            value={draft.remove}
            onChange={(event) =>
              onChange({ ...draft, remove: event.target.value })
            }
          />
          <p className="text-xs text-muted-foreground">
            One argument per line; run directly, never through a shell.
            {' {file}'} is the encrypted page, {'{object}'} where it goes.
          </p>
        </>
      ) : (
        <>
          {field('bucket', 'Bucket', 'company-share')}
          {field('prefix', 'Folder in the bucket', 'geniro (optional)')}
          {draft.kind === 's3' && (
            <>
              {field('profile', 'AWS profile', 'default (optional)')}
              {field('region', 'AWS region', 'eu-west-1 (optional)')}
            </>
          )}
        </>
      )}
      <div className="flex gap-2">
        <Button type="button" size="sm" disabled={saving} onClick={onSave}>
          Save place
        </Button>
        <Button
          type="button"
          size="sm"
          variant="ghost"
          disabled={saving}
          onClick={onCancel}>
          Cancel
        </Button>
      </div>
    </div>
  );
}
