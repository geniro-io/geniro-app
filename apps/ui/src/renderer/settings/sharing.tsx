import {
  DEFAULT_SHARING,
  type ShareDestination,
  type SharingSettings,
} from '../../shared/contracts';
import type { Share, SharesApi } from '../autogenerated';
import { revokeFailedMessage } from '../chats/use-artifact-sharing';
import { ConfirmButton } from '../components/confirm-button';
