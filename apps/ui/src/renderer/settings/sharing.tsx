/** What a destination's row says about its CLI's sign-in. */
type CheckState =
  | { kind: 'checking' }
  | { kind: 'answered'; result: ShareCheckResultDto }
  | { kind: 'error'; detail: string };

type Kind = ShareDestination['kind'];

const KIND_LABEL: Record<Kind, string> = {
  gcs: 'Google Cloud Storage (gcloud)',
  s3: 'Amazon S3 (aws)',
  command: 'Your own command',
};

/** The add-a-destination form, as typed — turned into a destination on save. */
interface Draft {
  kind: Kind;
  name: string;
  linkBase: string;
  bucket: string;
  prefix: string;
  profile: string;
  region: string;
  /** One argv token per line. */
  upload: string;
  remove: string;
  /** Custom only: the login argv, one token per line. */
  login: string;
  /** Custom only: output that means signed out, one per line. */
  patterns: string;
}

const EMPTY_DRAFT: Draft = {
  kind: 'gcs',
  name: '',
  linkBase: '',
  bucket: '',
  prefix: '',
  profile: '',
  region: '',
  upload: '',
  remove: '',
  login: '',
  patterns: '',
};

/** The select's spelling of `autoRevokeAfterDays: null`. */
const NEVER_REVOKE = 'never';

/**
 * Discrete rows rather than a number field: this arms revokes on a clock
 * nobody watches, so only windows somebody chose are reachable. `Never` leads
 * as the default and the only row that revokes nothing.
 */
const AUTO_REVOKE_OPTIONS: SelectGroup[] = [
  {
    items: [
      { value: NEVER_REVOKE, label: 'Never' },
      { value: '7', label: 'After 7 days' },
      { value: '30', label: 'After 30 days' },
      { value: '90', label: 'After 90 days' },
      { value: '180', label: 'After 180 days' },
      { value: '365', label: 'After a year' },
    ],
  },
];

const lines = (text: string): string[] =>
  text
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.length > 0);

/** The draft as a destination, or the reason it is not one yet. */
function destinationFrom(draft: Draft): ShareDestination | string {
  const name = draft.name.trim();
  const linkBase = draft.linkBase.trim();
  if (name === '') {
    return 'Give it a name.';
  }
  if (!linkBase.startsWith('https://')) {
    return 'The link address must start with https://.';
  }
  const base = { id: randomId(), name, linkBase };
  const optional = (value: string): string | undefined =>
    value.trim() === '' ? undefined : value.trim();
  if (draft.kind === 'command') {
    const upload = lines(draft.upload);
    const remove = lines(draft.remove);
    if (upload.length === 0 || remove.length === 0) {
      return 'Both commands need at least the program, one token per line.';
    }
    const login = lines(draft.login);
    const patterns = lines(draft.patterns);
    const signIn = {
      ...(login.length === 0 ? {} : { login }),
      ...(patterns.length === 0 ? {} : { patterns }),
    };
    return {
      kind: 'command',
      ...base,
      upload,
      remove,
      ...(Object.keys(signIn).length === 0 ? {} : { signIn }),
    };
  }
  if (draft.bucket.trim() === '') {
    return 'Name the bucket.';
  }
  const prefix = optional(draft.prefix);
  if (draft.kind === 'gcs') {
    return {
      kind: 'gcs',
      ...base,
      bucket: draft.bucket.trim(),
      ...(prefix === undefined ? {} : { prefix }),
    };
  }
  const profile = optional(draft.profile);
  const region = optional(draft.region);
  return {
    kind: 's3',
    ...base,
    bucket: draft.bucket.trim(),
    ...(prefix === undefined ? {} : { prefix }),
    ...(profile === undefined ? {} : { profile }),
    ...(region === undefined ? {} : { region }),
  };
}

function summaryOf(destination: ShareDestination): string {
  switch (destination.kind) {
    case 'gcs':
      return `gs://${destination.bucket}/${destination.prefix ?? ''}`;
    case 's3':
      return `s3://${destination.bucket}/${destination.prefix ?? ''}`;
    case 'command':
      return destination.upload.join(' ');
  }
}

/**
 * Settings → Sharing: where encrypted page links are uploaded, whether agents
 * may share, and every page shared so far with its revoke.
 *
 * The places are kept in settings.json and handed to the daemon by main; each
 * upload runs through the user's own CLI and login, so nothing here holds a
 * credential. Desktop only — a paired phone may read this page but not change
 * it.
 */
export function Sharing({
  api,
  remote = isRemoteRuntime(),
}: {
  api: SharesClient | null;
  remote?: boolean;
}): React.JSX.Element {
  const [sharing, setSharing] = useState<SharingSettings | null>(null);
  const [shares, setShares] = useState<Share[]>([]);
  const [received, setReceived] = useState<string | null>(null);
  const [draft, setDraft] = useState<Draft | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [checks, setChecks] = useState<Record<string, CheckState>>({});
  const [retryNotes, setRetryNotes] = useState<Record<string, string>>({});
  const [links, setLinks] = useState<Record<string, string>>({});
  const [savingPlace, setSavingPlace] = useState(false);

  const readShares = useLatestCallback(() => {
    if (api === null || remote) {
      return;
    }
    void api
      .listShares({})
      .then((answer) => {
        setShares(answer.shares);
        setReceived(answer.configReceivedAt);
      })
      .catch((err: unknown) => setError(describeDaemonError(err)));
  }, [api, remote]);

  useEffect(() => {
    void window.geniro
      .getSettings()
      .then((settings) => setSharing(settings.sharing))
      .catch((err: unknown) => setError(String(err)));
    readShares();
  }, [readShares]);

  // Main hands a saved value to the daemon as it writes the file, and that
  // push is not awaited by the save, so the "has these settings" line is
  // re-read a moment later rather than at once.
  const reread = useRef<ReturnType<typeof setTimeout> | null>(null);
  useEffect(
    () => () => {
      if (reread.current !== null) {
        clearTimeout(reread.current);
      }
    },
    [],
  );

  /** Resolves true once the file holds `next`; on refusal the screen goes back. */
  const save = (next: SharingSettings): Promise<boolean> => {
    setError(null);
    const before = sharing;
    setSharing(next);
    return window.geniro
      .updateSettings({ sharing: next })
      .then(() => {
        if (reread.current !== null) {
          clearTimeout(reread.current);
        }
        reread.current = setTimeout(readShares, 500);
        return true;
      })
      .catch((err: unknown) => {
        setSharing(before);
        setError(String(err));
        return false;
      });
  };

  if (remote) {
    return (
      <SettingsPanel>
        <SettingsPanelRow layout="block">
          <p className="text-sm text-muted-foreground">
            Sharing is set up on the Mac.
          </p>
        </SettingsPanelRow>
      </SettingsPanel>
    );
  }

  const current = sharing ?? DEFAULT_SHARING;

  const addDestination = (): void => {
    if (draft === null) {
      return;
    }
    const made = destinationFrom(draft);
    if (typeof made === 'string') {
      setError(made);
      return;
    }
    // The form stays filled until the write lands, so a refusal (a value
    // main's schema rejects) leaves what the user typed to correct.
    setSavingPlace(true);
    void save({
      ...current,
      destinations: [...current.destinations, made],
      defaultDestinationId: current.defaultDestinationId ?? made.id,
    }).then((saved) => {
      setSavingPlace(false);
      if (saved) {
        setDraft(null);
      }
    });
  };

  const removeDestination = async (id: string): Promise<void> => {
    await save({
      ...current,
      destinations: current.destinations.filter((d) => d.id !== id),
      defaultDestinationId:
        current.defaultDestinationId === id
          ? null
          : current.defaultDestinationId,
    });
  };

  const check = (destination: ShareDestination): void => {
    if (api === null) {
      return;
    }
    setChecks((all) => ({ ...all, [destination.id]: { kind: 'checking' } }));
    void api
      .checkShareDestination({ checkShareDestinationDto: { destination } })
      .then((result) =>
        setChecks((all) => ({
          ...all,
          [destination.id]: { kind: 'answered', result },
        })),
      )
      .catch((err: unknown) =>
        setChecks((all) => ({
          ...all,
          [destination.id]: { kind: 'error', detail: describeDaemonError(err) },
        })),
      );
  };

  // A sign-in that succeeded has had the daemon retry what was waiting on it.
  const signedIn = (
    destination: ShareDestination,
    session: ShareSignInSessionDto,
  ): void => {
    if (session.status !== 'succeeded') {
      return;
    }
    const n = session.retried.length;
    setRetryNotes((all) => ({
      ...all,
      [destination.id]:
        n === 0 ? '' : `Retrying ${n} waiting share${n === 1 ? '' : 's'}…`,
    }));
    check(destination);
    readShares();
  };

  // A link's key lives in the Keychain, so it is read on demand and then
  // handed to the shared copy control.
  const showLink = (id: string): void => {
    if (api === null) {
      return;
    }
    void api
      .readShareLink({ shareId: id })
      .then((answer) => setLinks((all) => ({ ...all, [id]: answer.url })))
      .catch((err: unknown) => setError(describeDaemonError(err)));
  };

  const revoke = async (id: string): Promise<void> => {
    if (api === null) {
      return;
    }
    try {
      const outcome = await api.revokeShare({ shareId: id });
      if (outcome.status === 'revoke-failed') {
        setError(revokeFailedMessage(outcome.detail));
      }
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    }
    readShares();
  };

  // The pages on screen, not whatever is shared by the time the press lands:
  // the user confirmed this count.
  const revokeAll = async (): Promise<void> => {
    if (api === null || shares.length === 0) {
      return;
    }
    try {
      const outcome = await api.revokeAllShares(
        { revokeSharesDto: { shareIds: shares.map((share) => share.id) } },
        { signal: AbortSignal.timeout(BULK_REVOKE_TIMEOUT_MS) },
      );
      if (outcome.failed > 0) {
        setError(
          revokeManyFailedMessage(
            outcome.failed,
            outcome.revoked + outcome.failed,
            outcome.detail,
          ),
        );
      }
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    }
    readShares();
  };

  const setAutoRevoke = (value: string): void => {
    const days = value === NEVER_REVOKE ? null : Number(value);
    if (days !== null && !Number.isInteger(days)) {
      return;
    }
    void save({ ...current, autoRevokeAfterDays: days });
  };

  return (
    <div data-slot="sharing" className="flex flex-col gap-3">
      {error !== null && (
        <ErrorBanner message={error} onDismiss={() => setError(null)} />
      )}

      <SettingsPanel>
        <SettingsPanelRow
          label="Let agents share pages"
          htmlFor="settings-agents-share"
          description="An agent asked to share a page uploads it to the default place below and gets its link.">
          <Switch
            id="settings-agents-share"
            checked={current.agentsMayShare}
            disabled={sharing === null}
            onCheckedChange={(on) => save({ ...current, agentsMayShare: on })}
          />
        </SettingsPanelRow>
        <SettingsPanelRow
          label="Share to"
          description="Where a Share press and an agent upload.">
          <Select
            aria-label="Default place to share to"
            value={current.defaultDestinationId}
            placeholder="Nowhere yet"
            groups={[
              {
                label: 'Places',
                items: current.destinations.map((d) => ({
                  value: d.id,
                  label: d.name,
                })),
              },
            ]}
            onValueChange={(id) =>
              save({ ...current, defaultDestinationId: id })
            }
          />
        </SettingsPanelRow>
        <SettingsPanelRow layout="block">
          <p className="text-xs text-muted-foreground">
            {received === null
              ? 'Not yet handed to the daemon — sharing is off until it is.'
              : 'The daemon has these settings.'}{' '}
            Pages are encrypted on this Mac; only ciphertext is uploaded, and
            the key travels in the link after #.
          </p>
        </SettingsPanelRow>
      </SettingsPanel>

      <SettingsPanel>
        <SettingsPanelRow layout="block" label="Places to share to">
          <ul className="flex flex-col gap-2">
            {current.destinations.map((destination) => (
              <li
                key={destination.id}
                className="flex min-w-0 flex-col gap-1 rounded-md border border-border p-2">
                <div className="flex min-w-0 items-center gap-2">
                  <span className="shrink-0 font-medium">
                    {destination.name}
                  </span>
                  <span className="min-w-0 flex-1 truncate text-xs text-muted-foreground">
                    {summaryOf(destination)}
                  </span>
                  <span className="ml-auto flex shrink-0 gap-1">
                    <Button
                      type="button"
                      size="sm"
                      variant="outline"
                      disabled={checks[destination.id]?.kind === 'checking'}
                      onClick={() => check(destination)}>
                      Check
                    </Button>
                    <ConfirmButton
                      size="sm"
                      confirmLabel="Remove?"
                      onConfirm={() => removeDestination(destination.id)}>
                      Remove
                    </ConfirmButton>
                  </span>
                </div>
                <SignInStatus
                  destination={destination}
                  state={checks[destination.id]}
                  api={api}
                  onSettled={(session) => signedIn(destination, session)}
                />
                {retryNotes[destination.id] ? (
                  <p className="text-xs text-muted-foreground">
                    {retryNotes[destination.id]}
                  </p>
                ) : null}
              </li>
            ))}
          </ul>
          {draft === null ? (
            <Button
              type="button"
              size="sm"
              variant="outline"
              className="mt-2 self-start"
              disabled={sharing === null}
              onClick={() => setDraft(EMPTY_DRAFT)}>
              Add a place
            </Button>
          ) : (
            <DestinationForm
              draft={draft}
              onChange={setDraft}
              onCancel={() => setDraft(null)}
              onSave={addDestination}
              saving={savingPlace}
            />
          )}
        </SettingsPanelRow>
      </SettingsPanel>

      <SettingsPanel>
        <SettingsPanelRow
          label="Revoke shared pages"
          htmlFor="settings-share-auto-revoke"
          description="Counted from when a page was first shared. Its link stops working; checked every few hours while Geniro runs.">
          <Select
            id="settings-share-auto-revoke"
            className="w-44"
            aria-label="When to revoke shared pages"
            groups={AUTO_REVOKE_OPTIONS}
            value={
              current.autoRevokeAfterDays === null
                ? NEVER_REVOKE
                : String(current.autoRevokeAfterDays)
            }
            disabled={sharing === null}
            onValueChange={setAutoRevoke}
          />
        </SettingsPanelRow>
        <SettingsPanelRow layout="block" label="Shared pages">
          {shares.length === 0 ? (
            <p className="text-sm text-muted-foreground">Nothing shared yet.</p>
          ) : (
            <ul className="flex flex-col gap-2">
              {shares.map((share) => (
                <li
                  key={share.id}
                  className="flex min-w-0 items-center gap-2 text-sm">
                  <span className="flex min-w-0 flex-1 flex-col">
                    <span className="truncate">{share.title}</span>
                    <span className="truncate text-xs text-muted-foreground">
                      Shared{' '}
                      <time dateTime={share.createdAt}>
                        {formatDateTime(share.createdAt)}
                      </time>{' '}
                      ·{' '}
                      {share.sharedVersion > 0
                        ? `v${share.sharedVersion} · `
                        : ''}
                      {share.sharedBy === 'agent' ? 'by an agent' : 'by you'} ·{' '}
                      {share.destinationName}
                      {SHARE_STATUS_NOTE[share.status] ?? ''}
                    </span>
                  </span>
                  <span className="flex shrink-0 gap-1">
                    {share.sharedVersion === 0 ? null : links[share.id] ===
                      undefined ? (
                      <Button
                        type="button"
                        size="sm"
                        variant="ghost"
                        onClick={() => showLink(share.id)}>
                        Get link
                      </Button>
                    ) : (
                      <CopyButton
                        text={links[share.id] ?? ''}
                        label="Copy link"
                      />
                    )}
                    <ConfirmButton
                      size="sm"
                      confirmLabel="Revoke link?"
                      onConfirm={() => revoke(share.id)}>
                      Revoke
                    </ConfirmButton>
                  </span>
                </li>
              ))}
            </ul>
          )}
          {shares.length > 0 && (
            <ConfirmButton
              size="sm"
              className="mt-2 self-start"
              confirmLabel={`Revoke all ${shares.length}?`}
              onConfirm={revokeAll}>
              Revoke all
            </ConfirmButton>
          )}
        </SettingsPanelRow>
      </SettingsPanel>
    </div>
  );
}

/** The tail a shared page's line gets for a status other than live. */
const SHARE_STATUS_NOTE: Partial<Record<Share['status'], string>> = {
  'revoke-failed': ' · revoke failed',
  'awaiting-sign-in': ' · waiting on sign-in',
  failed: ' · not shared',
};

interface Chip {
  tone: 'success' | 'warning' | 'muted';
  icon: 'check' | 'alert' | 'spin' | 'none';
  text: string;
}

const NOT_CHECKED: Chip = { tone: 'muted', icon: 'none', text: 'Not checked' };
const CHECKING: Chip = { tone: 'muted', icon: 'spin', text: 'Checking…' };
const CHECK_CHIP: Record<ShareCheckResultDto['state'], Chip> = {
  'signed-in': { tone: 'success', icon: 'check', text: 'Signed in' },
  'sign-in-required': {
    tone: 'warning',
    icon: 'alert',
    text: 'Sign-in required',
  },
  'check-failed': { tone: 'warning', icon: 'alert', text: 'Check failed' },
  'not-set-up': { tone: 'muted', icon: 'none', text: 'Sign-in not set up' },
};

/**
 * One destination's sign-in, as its row shows it: a chip saying whether its
 * CLI is signed in — only once Check is pressed, since opening the page runs
 * nothing — and "Sign in to …" when it is not.
 */
function SignInStatus({
  destination,
  state,
  api,
  onSettled,
}: {
  destination: ShareDestination;
  state: CheckState | undefined;
  api: SharesClient | null;
  onSettled: (session: ShareSignInSessionDto) => void;
}): React.JSX.Element {
  const result = state?.kind === 'answered' ? state.result : null;
  const chip: Chip =
    state === undefined
      ? NOT_CHECKED
      : state.kind === 'checking'
        ? CHECKING
        : state.kind === 'error'
          ? CHECK_CHIP['check-failed']
          : // A state a newer daemon added reads as a failed check.
            (CHECK_CHIP[state.result.state] ?? CHECK_CHIP['check-failed']);
  const detail =
    state?.kind === 'error' ? state.detail : (result?.detail ?? null);
  const label = result?.signIn?.label ?? destination.name;
  return (
    <div className="flex flex-col gap-1">
      <p
        role="status"
        className={cn(
          'flex items-center gap-1.5 text-xs',
          chip.tone === 'success' && 'text-success',
          chip.tone === 'warning' && 'text-warning',
          chip.tone === 'muted' && 'text-muted-foreground',
        )}>
        {chip.icon === 'check' && (
          <Check aria-hidden="true" className="size-3.5 shrink-0" />
        )}
        {chip.icon === 'alert' && (
          <TriangleAlert aria-hidden="true" className="size-3.5 shrink-0" />
        )}
        {chip.icon === 'spin' && (
          <Loader2
            aria-hidden="true"
            className="size-3.5 shrink-0 animate-spin"
          />
        )}
        {chip.icon === 'none' && (
          <CircleDashed aria-hidden="true" className="size-3.5 shrink-0" />
        )}
        <span className="shrink-0 whitespace-nowrap">{chip.text}</span>
        {detail !== null && result?.state !== 'signed-in' && (
          <span
            className="min-w-0 truncate text-muted-foreground"
            title={detail}>
            — {detail}
          </span>
        )}
      </p>
      {result?.state === 'sign-in-required' && (
        <SignInAction
          api={api}
          destinationId={destination.id}
          label={label}
          onSettled={onSettled}
        />
      )}
    </div>
  );
}

function DestinationForm({
  draft,
  onChange,
  onCancel,
  onSave,
  saving,
}: {
  draft: Draft;
  onChange: (next: Draft) => void;
  onCancel: () => void;
  onSave: () => void;
  saving: boolean;
}): React.JSX.Element {
  const id = useId();
  const field = (
    key: Exclude<keyof Draft, 'kind'>,
    label: string,
    placeholder: string,
    hint?: React.ReactNode,
  ): React.JSX.Element => (
    <Field label={label} htmlFor={`${id}-${key}`} hint={hint}>
      <Input
        id={`${id}-${key}`}
        placeholder={placeholder}
        value={draft[key]}
        onChange={(event) => onChange({ ...draft, [key]: event.target.value })}
      />
    </Field>
  );
  return (
    <div className="mt-2 flex flex-col gap-3" data-slot="sharing-form">
      <Field label="Kind of place" htmlFor={`${id}-kind`}>
        <Select
          id={`${id}-kind`}
          value={draft.kind}
          groups={[
            {
              label: 'Upload with',
              items: (Object.keys(KIND_LABEL) as Kind[]).map((kind) => ({
                value: kind,
                label: KIND_LABEL[kind],
              })),
            },
          ]}
          onValueChange={(kind) => onChange({ ...draft, kind: kind as Kind })}
        />
      </Field>
      {field('name', 'Name', 'Company artifacts')}
      {field(
        'linkBase',
        'Link address',
        'https://artifacts.example.com',
        'Use a domain of your own. A shared one (storage.googleapis.com, s3.amazonaws.com) lets any other page on it read the key from a link.',
      )}
      {draft.kind === 'command' ? (
        <>
          <Field label="Upload command" htmlFor={`${id}-upload`}>
            <Textarea
              id={`${id}-upload`}
              placeholder={'/usr/local/bin/upload\n--src={file}\n{object}'}
              value={draft.upload}
              onChange={(event) =>
                onChange({ ...draft, upload: event.target.value })
              }
            />
          </Field>
          <Field
            label="Remove command"
            htmlFor={`${id}-remove`}
            hint={
              <>
                One argument per line; run directly, never through a shell.
                {' {file}'} is the encrypted page, {'{object}'} where it goes.
              </>
            }>
            <Textarea
              id={`${id}-remove`}
              placeholder={'/usr/local/bin/delete\n{object}'}
              value={draft.remove}
              onChange={(event) =>
                onChange({ ...draft, remove: event.target.value })
              }
            />
          </Field>
          <p className="text-xs font-medium">Sign-in (optional)</p>
          <Field
            label="Login command"
            htmlFor={`${id}-login`}
            hint="One argument per line, never a shell. Without it a program named gcloud or aws signs in as that CLI does.">
            <Textarea
              id={`${id}-login`}
              placeholder={'/usr/local/bin/upload\nlogin'}
              value={draft.login}
              onChange={(event) =>
                onChange({ ...draft, login: event.target.value })
              }
            />
          </Field>
          <Field
            label="Sign-in required when output contains"
            htmlFor={`${id}-patterns`}
            hint="One phrase per line, any case. A failed upload whose output contains one offers Sign in instead of failing.">
            <Textarea
              id={`${id}-patterns`}
              placeholder={'session expired\nnot logged in'}
              value={draft.patterns}
              onChange={(event) =>
                onChange({ ...draft, patterns: event.target.value })
              }
            />
          </Field>
        </>
      ) : (
        <>
          {field('bucket', 'Bucket', 'company-share')}
          {field('prefix', 'Folder in the bucket', 'reports (optional)')}
          {draft.kind === 's3' && (
            <>
              {field('profile', 'AWS profile', 'default (optional)')}
              {field('region', 'AWS region', 'eu-west-1 (optional)')}
            </>
          )}
        </>
      )}
      <div className="flex gap-2">
        <Button type="button" size="sm" disabled={saving} onClick={onSave}>
          Save place
        </Button>
        <Button
          type="button"
          size="sm"
          variant="ghost"
          disabled={saving}
          onClick={onCancel}>
          Cancel
        </Button>
      </div>
    </div>
  );
}
