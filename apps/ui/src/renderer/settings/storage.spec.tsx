// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { AppStorageUsage, WorktreeRemoval } from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { StorageJob, StorageUsageDto } from '../autogenerated';
import { jobOutcome, Storage, STORAGE_JOB_POLL_MS } from './storage';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const GB = 1024 ** 3;

function usage(job: StorageJob | null = null): StorageUsageDto {
  return {
    root: '/Users/me/Library/Application Support/Geniro',
    scannedAt: '2026-10-31T12:00:00.000Z',
    groups: [
      {
        id: 'database',
        bytes: 9 * GB,
        entries: [{ name: 'geniro.db', bytes: 9 * GB }],
        clean: [
          { target: 'archivedChats', count: 778, bytes: null },
          { target: 'compactDatabase', count: 0, bytes: 2 * GB },
        ],
      },
      {
        id: 'workflowBackups',
        bytes: 5 * 1024 * 1024,
        entries: [{ name: 'workflows/.backups', bytes: 5 * 1024 * 1024 }],
        clean: [
          { target: 'workflowBackups', count: 20, bytes: 5 * 1024 * 1024 },
        ],
      },
    ],
    chats: { active: 19, archived: 778 },
    unclaimed: ['Cache', 'worktrees'],
    job,
  };
}

const APP: AppStorageUsage = {
  worktrees: [
    {
      name: 'task-1',
      bytes: 1.4 * GB,
      kind: 'worktree',
      taskId: 'task-1',
      branch: 'feat/thing',
      cardFinished: true,
    },
  ],
  browserCache: [{ name: 'Cache', bytes: 1.2 * GB }],
  appData: [],
};

let container: HTMLDivElement;
let root: Root;
let getAppStorage: ReturnType<
  typeof vi.fn<(unclaimed: string[]) => Promise<AppStorageUsage>>
>;
let removeStorageWorktree: ReturnType<
  typeof vi.fn<(name: string) => Promise<WorktreeRemoval>>
>;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  getAppStorage = vi.fn((_unclaimed: string[]) => Promise.resolve(APP));
  removeStorageWorktree = vi.fn((_name: string) =>
    Promise.resolve({
      removed: false,
      reason: 'it holds unsaved changes — commit or discard them first',
    }),
  );
  window.geniro = createPreloadStub({ getAppStorage, removeStorageWorktree });
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  vi.useRealTimers();
});

async function flush(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
  });
}

function buttonNamed(text: string): HTMLButtonElement {
  const button = [...container.querySelectorAll('button')].find((b) =>
    b.textContent?.includes(text),
  );
  if (!button) {
    throw new Error(`no button "${text}"`);
  }
  return button;
}

async function pressTwice(text: string): Promise<void> {
  await act(async () => buttonNamed(text).click());
  await act(async () => buttonNamed('Delete?').click());
}

describe('Storage', () => {
  it("measures the desktop app's share from the names the daemon did not claim", async () => {
    const api = {
      getStorageUsage: vi.fn(() => Promise.resolve(usage())),
      getStorageJob: vi.fn(() => Promise.resolve({ job: null })),
      cleanStorage: vi.fn(),
    };
    await act(async () => root.render(<Storage api={api} remote={false} />));
    await flush();

    expect(getAppStorage).toHaveBeenCalledWith(['Cache', 'worktrees']);
    expect(container.textContent).toContain('Database — 9.0 GB');
    expect(container.textContent).toContain('19 chats, 778 archived.');
    expect(container.textContent).toContain('feat/thing');
    expect(container.textContent).toContain('Window cache — 1.2 GB');
    expect(buttonNamed('Delete 778 archived chats')).toBeTruthy();
    expect(buttonNamed('Compact · 2.0 GB')).toBeTruthy();
  });

  it('starts a clean-up only on the confirming press, then reports it once done', async () => {
    vi.useFakeTimers({ shouldAdvanceTime: true });
    const running: StorageJob = {
      target: 'archivedChats',
      state: 'running',
      startedAt: '2026-10-31T12:00:00.000Z',
      finishedAt: null,
      removed: 0,
      freedBytes: null,
      error: null,
    };
    const done: StorageJob = {
      ...running,
      state: 'done',
      removed: 778,
      finishedAt: '2026-10-31T12:01:00.000Z',
    };
    const api = {
      getStorageUsage: vi.fn(() => Promise.resolve(usage())),
      getStorageJob: vi.fn(() =>
        Promise.resolve({ job: null as StorageJob | null }),
      ),
      cleanStorage: vi.fn(() => Promise.resolve(running)),
    };
    await act(async () => root.render(<Storage api={api} remote={false} />));
    await flush();

    await act(async () => buttonNamed('Delete 778 archived chats').click());
    expect(api.cleanStorage).not.toHaveBeenCalled();
    await act(async () => buttonNamed('Delete?').click());
    await flush();

    expect(api.cleanStorage).toHaveBeenCalledWith({
      storageCleanDto: { target: 'archivedChats' },
    });
    expect(container.textContent).toContain('Deleting the archived chats…');

    api.getStorageJob.mockImplementation(() =>
      Promise.resolve({ job: done as StorageJob | null }),
    );
    await act(async () => {
      await vi.advanceTimersByTimeAsync(STORAGE_JOB_POLL_MS);
    });
    await flush();

    expect(container.textContent).toContain('Deleted 778 archived chats.');
    expect(container.textContent).not.toContain('Deleting the archived chats…');
    expect(api.getStorageUsage).toHaveBeenCalledTimes(2);
  });

  it('clears the window cache on the confirming press and says what it freed', async () => {
    const clearBrowserCache = vi.fn(() =>
      Promise.resolve({ freedBytes: 1.2 * GB }),
    );
    window.geniro = createPreloadStub({
      getAppStorage,
      removeStorageWorktree,
      clearBrowserCache,
    });
    const api = {
      getStorageUsage: vi.fn(() => Promise.resolve(usage())),
      getStorageJob: vi.fn(() => Promise.resolve({ job: null })),
      cleanStorage: vi.fn(),
    };
    await act(async () => root.render(<Storage api={api} remote={false} />));
    await flush();

    await act(async () => buttonNamed('Clear cache').click());
    expect(clearBrowserCache).not.toHaveBeenCalled();
    await act(async () => buttonNamed('Clear?').click());
    await flush();

    expect(clearBrowserCache).toHaveBeenCalledTimes(1);
    expect(container.textContent).toContain(
      'The window cache is cleared — 1.2 GB freed.',
    );
  });

  it('schedules a compaction, restarts the daemon, then says what it freed', async () => {
    const restartDaemon = vi.fn(() => Promise.resolve());
    window.geniro = createPreloadStub({
      getAppStorage,
      removeStorageWorktree,
      restartDaemon,
    });
    const scheduled: StorageJob = {
      target: 'compactDatabase',
      state: 'scheduled',
      startedAt: '2026-10-31T12:00:00.000Z',
      finishedAt: null,
      removed: 0,
      freedBytes: null,
      error: null,
    };
    const api = {
      getStorageUsage: vi.fn(() => Promise.resolve(usage())),
      getStorageJob: vi.fn(() => Promise.resolve({ job: null })),
      cleanStorage: vi.fn(() => Promise.resolve(scheduled)),
    };
    await act(async () => root.render(<Storage api={api} remote={false} />));
    await flush();

    await act(async () => buttonNamed('Compact').click());
    expect(api.cleanStorage).not.toHaveBeenCalled();
    await act(async () => buttonNamed('Restart & compact?').click());
    await flush();

    expect(api.cleanStorage).toHaveBeenCalledWith({
      storageCleanDto: { target: 'compactDatabase' },
    });
    expect(restartDaemon).toHaveBeenCalledTimes(1);

    const restarted = {
      getStorageUsage: vi.fn(() =>
        Promise.resolve(
          usage({
            ...scheduled,
            state: 'done',
            freedBytes: 8 * GB,
            finishedAt: '2026-10-31T12:00:09.000Z',
          }),
        ),
      ),
      getStorageJob: vi.fn(() => Promise.resolve({ job: null })),
      cleanStorage: vi.fn(),
    };
    await act(async () =>
      root.render(<Storage api={restarted} remote={false} />),
    );
    await flush();

    expect(container.textContent).toContain(
      'The database is compacted — 8.0 GB freed.',
    );
  });

  it('shows a clean-up that failed as an error', async () => {
    vi.useFakeTimers({ shouldAdvanceTime: true });
    const running: StorageJob = {
      target: 'workflowBackups',
      state: 'running',
      startedAt: '2026-10-31T12:00:00.000Z',
      finishedAt: null,
      removed: 0,
      freedBytes: null,
      error: null,
    };
    const api = {
      getStorageUsage: vi.fn(() => Promise.resolve(usage())),
      getStorageJob: vi.fn(() =>
        Promise.resolve({
          job: {
            ...running,
            state: 'failed',
            error: 'permission denied',
          } as StorageJob | null,
        }),
      ),
      cleanStorage: vi.fn(() => Promise.resolve(running)),
    };
    await act(async () => root.render(<Storage api={api} remote={false} />));
    await flush();

    await pressTwice('Delete 20 backups');
    await flush();
    await act(async () => {
      await vi.advanceTimersByTimeAsync(STORAGE_JOB_POLL_MS);
    });
    await flush();

    expect(container.textContent).toContain(
      'The clean-up failed: permission denied',
    );
  });

  it('says why a worktree was kept', async () => {
    const api = {
      getStorageUsage: vi.fn(() => Promise.resolve(usage())),
      getStorageJob: vi.fn(() => Promise.resolve({ job: null })),
      cleanStorage: vi.fn(),
    };
    await act(async () => root.render(<Storage api={api} remote={false} />));
    await flush();

    await act(async () => buttonNamed('Remove').click());
    await act(async () => buttonNamed('Remove?').click());
    await flush();

    expect(removeStorageWorktree).toHaveBeenCalledWith('task-1');
    expect(container.textContent).toContain(
      'Kept: it holds unsaved changes — commit or discard them first',
    );
  });

  it('shows the failure of a clean-up the daemon refused', async () => {
    const api = {
      getStorageUsage: vi.fn(() => Promise.resolve(usage())),
      getStorageJob: vi.fn(() => Promise.resolve({ job: null })),
      cleanStorage: vi.fn(() =>
        Promise.reject(new Error('an agent is working')),
      ),
    };
    await act(async () => root.render(<Storage api={api} remote={false} />));
    await flush();

    await pressTwice('Delete 20 backups');
    await flush();

    expect(container.textContent).toContain('an agent is working');
  });

  it('reads nothing and deletes nothing from a paired phone', async () => {
    const api = {
      getStorageUsage: vi.fn(() => Promise.resolve(usage())),
      getStorageJob: vi.fn(() => Promise.resolve({ job: null })),
      cleanStorage: vi.fn(),
    };
    await act(async () => root.render(<Storage api={api} remote />));
    await flush();

    expect(api.getStorageUsage).not.toHaveBeenCalled();
    expect(container.textContent).toContain('Storage is managed on the Mac.');
  });
});

describe('jobOutcome', () => {
  it('names what a compaction gave back', () => {
    expect(
      jobOutcome({
        target: 'compactDatabase',
        state: 'done',
        startedAt: '',
        finishedAt: '',
        removed: 0,
        freedBytes: 8 * GB,
        error: null,
      }),
    ).toBe('The database is compacted — 8.0 GB freed.');
  });
});
