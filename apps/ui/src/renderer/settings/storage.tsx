function cleanLabel(option: StorageCleanOption): string {
  const size = option.bytes === null ? '' : ` · ${formatBytes(option.bytes)}`;
  switch (option.target) {
    case StorageCleanTarget.ArchivedChats:
      return `Delete ${chatCount(option.count)}`;
    case StorageCleanTarget.CompactDatabase:
      return `Compact${size}`;
    case StorageCleanTarget.OrphanChatFiles:
    case StorageCleanTarget.OrphanTaskFiles:
      return `Delete ${option.count} orphaned folder${option.count === 1 ? '' : 's'}${size}`;
    case StorageCleanTarget.TeamBackups:
      return `Delete ${option.count} backup${option.count === 1 ? '' : 's'}${size}`;
    case StorageCleanTarget.Logs:
      return `Delete ${option.count} old log${option.count === 1 ? '' : 's'}${size}`;
    case StorageCleanTarget.Leftovers:
    case StorageCleanTarget.SettingsCopies:
      return `Delete${size}`;
  }
}

function confirmOf(option: StorageCleanOption): {
  question: string;
  description: string;
  confirmLabel: string;
  busyLabel: string;
} {
  if (option.target === StorageCleanTarget.CompactDatabase) {
    return {
      question: 'Compact the database?',
      description:
        'Geniro’s background service restarts and compacts the database before it serves anything again. Chats are not changed.',
      confirmLabel: 'Restart & compact',
      busyLabel: 'Restarting…',
    };
  }
  return {
    question: `${cleanLabel(option)}?`,
    description: 'They are deleted for good. This cannot be undone.',
    confirmLabel: 'Delete',
    busyLabel: 'Deleting…',
  };
}

const ALL_ARCHIVED = 'all';
const DEFAULT_ARCHIVED_PERIOD = '30';

function periodKey(period: StorageArchivedPeriod): string {
  return period.days === null ? ALL_ARCHIVED : String(period.days);
}

function periodLabel(period: StorageArchivedPeriod): string {
  return period.days === null
    ? 'All archived'
    : `Archived in the last ${period.days} days`;
}

function chatCount(count: number): string {
  return `${count} chat${count === 1 ? '' : 's'}`;
}

/** What deleting a period's chats takes, and what it leaves. */
function archivedConfirmOf(period: StorageArchivedPeriod): {
  question: string;
  description: string;
} {
  if (period.window.from === null) {
    return {
      question:
        period.count === 1
          ? 'Delete the 1 chat in the archive?'
          : `Delete all ${period.count} chats in the archive?`,
      description:
        'Every archived chat and everything it holds are deleted for good. Chats that are not archived stay. This cannot be undone.',
    };
  }
  const since = new Date(period.window.from).toLocaleDateString('en-US', {
    dateStyle: 'medium',
  });
  return {
    question: `Delete ${chatCount(period.count)} archived in the last ${period.days} days?`,
    description: `Only chats you archived since ${since} are deleted, with everything they hold. Chats archived before then, and chats that are not archived, stay. This cannot be undone.`,
  };
}

/**
 * Whether this window asked for a compaction whose outcome it has not shown.
 * Module-level: the daemon restart that runs the compaction hands Settings a
 * new client, and the page that pressed may be mounted afresh.
 */
let compactionAwaited = false;

/** One line on what a clean-up that finished did. */
export function jobOutcome(job: StorageJob): string {
  if (job.target === StorageCleanTarget.ArchivedChats) {
    return `Deleted ${job.removed} archived chat${job.removed === 1 ? '' : 's'}. Compact the database to give the space back to the disk.`;
  }
  const freed = formatBytes(job.freedBytes ?? 0) ?? '0 B';
  return job.target === StorageCleanTarget.CompactDatabase
    ? `The database is compacted — ${freed} freed.`
    : `Deleted ${job.removed} item${job.removed === 1 ? '' : 's'} — ${freed} freed.`;
}

const RUNNING_TEXT: Record<StorageCleanTarget, string> = {
  [StorageCleanTarget.ArchivedChats]: 'Deleting the archived chats…',
  [StorageCleanTarget.CompactDatabase]: 'Compacting the database…',
  [StorageCleanTarget.OrphanChatFiles]: 'Deleting orphaned chat files…',
  [StorageCleanTarget.OrphanTaskFiles]: 'Deleting orphaned task files…',
  [StorageCleanTarget.TeamBackups]: 'Deleting the team backups…',
  [StorageCleanTarget.Logs]: 'Deleting old logs…',
  [StorageCleanTarget.Leftovers]: 'Deleting leftovers…',
  [StorageCleanTarget.SettingsCopies]: 'Deleting the settings copies…',
};

function sum(entries: readonly { bytes: number }[]): number {
  return entries.reduce((total, entry) => total + entry.bytes, 0);
}

/** What a row keeps folded: what it is, then each thing it counts. */
function StorageDetails({
  about,
  note,
  entries,
}: {
  about: React.ReactNode;
  note?: React.ReactNode;
  entries?: readonly { name: string; bytes: number }[];
}): React.JSX.Element {
  return (
    <>
      <p>{about}</p>
      {note === undefined ? null : <p>{note}</p>}
      {entries === undefined ? null : (
        <ul className="flex flex-col gap-0.5">
          {entries.map((entry) => (
            <li key={entry.name} className="flex justify-between gap-3">
              <span className="min-w-0 break-all">{entry.name}</span>
              <span className="shrink-0">{formatBytes(entry.bytes)}</span>
            </li>
          ))}
        </ul>
      )}
    </>
  );
}

/**
 * Settings → Storage: everything Geniro keeps in its data folder, measured,
 * with the clean-ups that are safe. Desktop only — a phone may not delete the
 * Mac's files.
 */
export function Storage({
  api,
  remote = isRemoteRuntime(),
}: {
  api: StorageClient | null;
  remote?: boolean;
}): React.JSX.Element {
  const [reading, setReading] = useState<Reading | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [worktreeNotes, setWorktreeNotes] = useState<Record<string, string>>(
    {},
  );
  const generation = useRef(0);

  const measure = useLatestCallback(async (): Promise<void> => {
    if (api === null || remote) {
      return;
    }
    const mine = ++generation.current;
    setLoading(true);
    try {
      const daemon = await api.getStorageUsage();
      const app = await window.geniro
        .getAppStorage(daemon.unclaimed)
        .catch((err: unknown) => {
          setError(String(err));
          return null;
        });
      if (mine === generation.current) {
        setReading({ daemon, app });
        const finished = daemon.job;
        if (
          compactionAwaited &&
          finished?.target === StorageCleanTarget.CompactDatabase &&
          (finished.state === 'done' || finished.state === 'failed')
        ) {
          compactionAwaited = false;
          if (finished.state === 'failed') {
            setError(
              `The compaction failed: ${finished.error ?? 'no reason given'}`,
            );
          } else {
            setNotice(jobOutcome(finished));
          }
        }
      }
    } catch (err) {
      if (mine === generation.current) {
        setError(describeDaemonError(err));
      }
    } finally {
      if (mine === generation.current) {
        setLoading(false);
      }
    }
  }, [api, remote]);

  useEffect(() => {
    void measure();
  }, [measure]);

  const job = reading?.daemon.job ?? null;
  const running = job?.state === 'running';
  const busy = running || job?.state === 'scheduled';

  useEffect(() => {
    if (!running || api === null) {
      return;
    }
    let timer: ReturnType<typeof setTimeout> | null = null;
    let stopped = false;
    const poll = (): void => {
      timer = setTimeout(() => {
        void api
          .getStorageJob()
          .then(({ job: latest }) => {
            if (stopped) {
              return;
            }
            if (latest?.state === 'running') {
              poll();
              return;
            }
            if (latest?.state === 'failed') {
              setError(
                `The clean-up failed: ${latest.error ?? 'no reason given'}`,
              );
            } else if (latest !== null && latest !== undefined) {
              setNotice(jobOutcome(latest));
            }
            void measure();
          })
          .catch((err: unknown) => {
            if (!stopped) {
              setError(describeDaemonError(err));
              poll();
            }
          });
      }, STORAGE_JOB_POLL_MS);
    };
    poll();
    return () => {
      stopped = true;
      if (timer !== null) {
        clearTimeout(timer);
      }
    };
  }, [running, api, measure]);

  if (remote) {
    return (
      <SettingsPanel>
        <SettingsPanelRow layout="block">
          <p className="text-sm text-muted-foreground">
            Storage is managed on the Mac.
          </p>
        </SettingsPanelRow>
      </SettingsPanel>
    );
  }

  const clean = async (
    target: StorageCleanTarget,
    archivedWindow?: StorageArchivedWindow,
  ): Promise<void> => {
    if (api === null) {
      return;
    }
    setError(null);
    setNotice(null);
    try {
      const started = await api.cleanStorage({
        storageCleanDto: { target, archivedWindow },
      });
      setReading((current) =>
        current === null
          ? current
          : { ...current, daemon: { ...current.daemon, job: started } },
      );
      if (started.state === 'scheduled') {
        compactionAwaited = true;
        setNotice('Restarting Geniro’s background service to compact…');
        await window.geniro.restartDaemon();
      }
    } catch (err) {
      compactionAwaited = false;
      setError(describeDaemonError(err));
    }
  };

  const clearBrowserCache = async (): Promise<void> => {
    setError(null);
    try {
      const { freedBytes } = await window.geniro.clearBrowserCache();
      setNotice(
        `The window cache is cleared — ${formatBytes(freedBytes)} freed.`,
      );
      await measure();
    } catch (err) {
      setError(String(err));
    }
  };

  const removeWorktree = async (name: string): Promise<void> => {
    setError(null);
    try {
      const outcome = await window.geniro.removeStorageWorktree(name);
      setWorktreeNotes((notes) => ({
        ...notes,
        [name]: outcome.removed ? 'Removed.' : `Kept: ${outcome.reason ?? ''}`,
      }));
      if (outcome.removed) {
        await measure();
      }
    } catch (err) {
      setError(String(err));
    }
  };

  if (reading === null) {
    return (
      <SettingsPanel>
        <SettingsPanelRow layout="block">
          {error === null ? (
            <span className="flex items-center gap-2 text-sm text-muted-foreground">
              <Spinner /> Measuring the data folder…
            </span>
          ) : (
            <ErrorBanner message={error} onDismiss={() => setError(null)} />
          )}
        </SettingsPanelRow>
      </SettingsPanel>
    );
  }

  const { daemon, app } = reading;
  const groupOf = (id: StorageGroupIdEnum): StorageGroup | undefined =>
    daemon.groups.find((group) => group.id === id);
  const worktrees = app?.worktrees ?? [];
  const browserCache = app?.browserCache ?? [];
  const appData = app?.appData ?? [];

  const overview: { key: string; label: string; bytes: number }[] = [
    ...daemon.groups.map((group) => ({
      key: group.id,
      label: GROUP_TEXT[group.id].title,
      bytes: group.bytes,
    })),
    { key: 'worktrees', label: 'Task worktrees', bytes: sum(worktrees) },
    { key: 'browserCache', label: 'Window cache', bytes: sum(browserCache) },
    { key: 'appData', label: 'Window data', bytes: sum(appData) },
  ]
    .filter((row) => row.bytes > 0)
    .sort((a, b) => b.bytes - a.bytes);
  const total = sum(overview);
  const segments: BreakdownSegment[] = overview.map((row, index) => ({
    key: row.key,
    label: row.label,
    value: row.bytes,
    colorClass: contextCategoryColor(index),
    figures: [formatBytes(row.bytes)],
  }));

  const cleanButtons = (options: readonly StorageCleanOption[]) =>
    options.map((option) => (
      <ConfirmActionButton
        key={option.target}
        disabled={busy}
        {...confirmOf(option)}
        onConfirm={() => clean(option.target)}>
        {cleanLabel(option)}
      </ConfirmActionButton>
    ));

  const groupRow = (id: StorageGroupIdEnum, note?: React.ReactNode) => {
    const group = groupOf(id);
    if (group === undefined) {
      return null;
    }
    const text = GROUP_TEXT[id];
    return (
      <SettingsPanelRow
        key={id}
        label={`${text.title} — ${formatBytes(group.bytes)}`}
        details={
          <StorageDetails
            about={text.about}
            note={note}
            entries={group.entries}
          />
        }>
        {group.clean.length === 0 ? null : cleanButtons(group.clean)}
      </SettingsPanelRow>
    );
  };

  return (
    <div className="flex flex-col gap-4">
      {error === null ? null : (
        <ErrorBanner message={error} onDismiss={() => setError(null)} />
      )}
      {notice === null ? null : (
        <p className="text-sm text-muted-foreground" role="status">
          {notice}
        </p>
      )}

      <SettingsPanel>
        <SettingsPanelRow
          label={`In use — ${formatBytes(total)}`}
          details={
            <span className="flex items-center gap-1">
              <span className="min-w-0 break-all">{daemon.root}</span>
              <CopyButton text={daemon.root} label="Copy the folder path" />
            </span>
          }>
          <Button
            size="sm"
            variant="outline"
            disabled={loading}
            onClick={() => void measure()}>
            {loading ? <Spinner /> : <RefreshCw />} Measure again
          </Button>
        </SettingsPanelRow>
        <SettingsPanelRow layout="block">
          <SegmentBreakdown segments={segments} denominator={total} />
        </SettingsPanelRow>
        {running && job !== null ? (
          <SettingsPanelRow layout="block">
            <span className="text-sm">{RUNNING_TEXT[job.target]}</span>
            <ProgressBar fraction={null} label={RUNNING_TEXT[job.target]} />
          </SettingsPanelRow>
        ) : null}
      </SettingsPanel>

      <SettingsPanel>
        {groupRow(
          StorageGroupIdEnum.Database,
          `${daemon.chats.active} chats, ${daemon.chats.archived} archived.`,
        )}
        {daemon.chats.archived === 0 ? null : (
          <ArchivedChatsRow
            total={daemon.chats.archived}
            periods={daemon.chats.archivedPeriods}
            disabled={busy}
            onDelete={(window) =>
              clean(StorageCleanTarget.ArchivedChats, window)
            }
          />
        )}
        {groupRow(StorageGroupIdEnum.AgentSessions)}
        {groupRow(StorageGroupIdEnum.ChatFiles)}
        {groupRow(StorageGroupIdEnum.TaskFiles)}
      </SettingsPanel>

      {worktrees.length === 0 ? null : (
        <SettingsPanel>
          <SettingsPanelRow
            label={`Task worktrees — ${formatBytes(sum(worktrees))}`}
            details={
              <>
                <p>
                  Checkouts the board&apos;s cards worked in. Removing one keeps
                  its branch; one holding unsaved work, or whose card is still
                  open, is kept.
                </p>
                <ul className="flex flex-col divide-y divide-border text-foreground">
                  {worktrees.map((worktree) => (
                    <WorktreeItem
                      key={worktree.name}
                      worktree={worktree}
                      note={worktreeNotes[worktree.name] ?? null}
                      onRemove={() => removeWorktree(worktree.name)}
                    />
                  ))}
                </ul>
              </>
            }
          />
        </SettingsPanel>
      )}

      <SettingsPanel>
        {groupRow(StorageGroupIdEnum.TeamBackups)}
        {groupRow(StorageGroupIdEnum.Teams)}
        {groupRow(StorageGroupIdEnum.Logs)}
        {groupRow(StorageGroupIdEnum.Leftovers)}
        {groupRow(StorageGroupIdEnum.SettingsCopies)}
        {groupRow(StorageGroupIdEnum.Caches)}
        {groupRow(StorageGroupIdEnum.AppState)}
      </SettingsPanel>

      {app === null ? null : (
        <SettingsPanel>
          {browserCache.length === 0 ? null : (
            <SettingsPanelRow
              label={`Window cache — ${formatBytes(sum(browserCache))}`}
              details={
                <StorageDetails
                  about="What the app window caches to load faster. Clearing empties its web and script caches; they refill as you work."
                  entries={browserCache}
                />
              }>
              <ConfirmActionButton
                question="Clear the window cache?"
                description="Its web and script caches are emptied; they refill as you work."
                confirmLabel="Clear cache"
                busyLabel="Clearing…"
                confirmVariant="default"
                onConfirm={clearBrowserCache}>
                Clear cache
              </ConfirmActionButton>
            </SettingsPanelRow>
          )}
          {appData.length === 0 ? null : (
            <SettingsPanelRow
              label={`Window data — ${formatBytes(sum(appData))}`}
              details={
                <StorageDetails
                  about="The window’s own storage, settings and pairings. Kept."
                  entries={appData}
                />
              }
            />
          )}
        </SettingsPanel>
      )}
    </div>
  );
}

/**
 * The archive's one delete: pick a period, read how many chats it holds, press.
 * Each period carries the window the daemon counted, posted back as it came, so
 * what is deleted is what was counted, whatever is archived after this reading.
 */
function ArchivedChatsRow({
  total,
  periods,
  disabled,
  onDelete,
}: {
  total: number;
  periods: readonly StorageArchivedPeriod[];
  disabled: boolean;
  onDelete: (window: StorageArchivedWindow) => Promise<void>;
}): React.JSX.Element | null {
  const [chosen, setChosen] = useState(DEFAULT_ARCHIVED_PERIOD);
  const period =
    periods.find((candidate) => periodKey(candidate) === chosen) ?? periods[0];
  if (period === undefined) {
    return null;
  }
  return (
    <SettingsPanelRow
      label={`Archived chats — ${total}`}
      details={
        <StorageDetails about="A chat deleted here loses its transcript, its files and its agent conversation for good. Periods count from when a chat was archived, not when it was last used. Compact the database afterwards to give the space back to the disk." />
      }>
      <div className="w-60 shrink-0">
        <Select
          aria-label="Which archived chats to delete"
          value={chosen}
          triggerLabel={periodLabel(period)}
          disabled={disabled}
          groups={[
            {
              label: 'Delete chats',
              items: periods.map((candidate) => ({
                value: periodKey(candidate),
                label: `${periodLabel(candidate)} · ${candidate.count}`,
              })),
            },
          ]}
          onValueChange={setChosen}
        />
      </div>
      <ConfirmActionButton
        disabled={disabled || period.count === 0}
        {...archivedConfirmOf(period)}
        confirmLabel="Delete"
        busyLabel="Deleting…"
        onConfirm={() => onDelete(period.window)}>
        {cleanLabel({
          target: StorageCleanTarget.ArchivedChats,
          count: period.count,
          bytes: null,
        })}
      </ConfirmActionButton>
    </SettingsPanelRow>
  );
}

function worktreeState(worktree: StorageWorktree): string {
  if (worktree.kind === 'file') {
    return 'a loose file';
  }
  if (worktree.kind === 'folder') {
    return 'not a git worktree';
  }
  if (worktree.taskId === null) {
    return 'not tracked by the board';
  }
  return worktree.cardFinished === true
    ? 'card finished'
    : worktree.cardFinished === false
      ? 'card still open'
      : 'card state unknown';
}

function WorktreeItem({
  worktree,
  note,
  onRemove,
}: {
  worktree: StorageWorktree;
  note: string | null;
  onRemove: () => Promise<void>;
}): React.JSX.Element {
  return (
    <li className="flex items-center gap-3 py-2 first:pt-0 last:pb-0">
      <div className="flex min-w-0 flex-1 flex-col">
        <span className="truncate text-sm" title={worktree.name}>
          {worktree.branch ?? worktree.name}
        </span>
        <span className="truncate text-xs text-muted-foreground">
          {formatBytes(worktree.bytes)} · {worktreeState(worktree)}
          {note === null ? null : ` · ${note}`}
        </span>
      </div>
      {worktree.kind === 'worktree' ? (
        <ConfirmActionButton
          question={`Remove ${worktree.branch ?? worktree.name}?`}
          description={
            <>
              The checkout is deleted and its branch is kept. One holding
              unsaved work, or whose card is still open, is kept instead.
            </>
          }
          confirmLabel="Remove"
          busyLabel="Removing…"
          onConfirm={onRemove}>
          Remove
        </ConfirmActionButton>
      ) : null}
    </li>
  );
}
