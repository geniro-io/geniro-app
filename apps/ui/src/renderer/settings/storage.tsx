export type StorageClient = Pick<
  StorageApi,
  'getStorageUsage' | 'getStorageJob' | 'cleanStorage'
>;

/** How often a running clean-up's progress is asked for. */
export const STORAGE_JOB_POLL_MS = 1500;

interface Reading {
  daemon: StorageUsageDto;
  app: AppStorageUsage | null;
}

