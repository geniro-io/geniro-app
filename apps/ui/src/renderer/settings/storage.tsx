/**
 * Settings → Storage: everything Geniro keeps in its data folder, measured,
 * with the clean-ups that are safe. Desktop only — a phone may not delete the
 * Mac's files.
 */
export function Storage({
  api,
  remote = isRemoteRuntime(),
}: {
  api: StorageClient | null;
  remote?: boolean;
}): React.JSX.Element {
  const [reading, setReading] = useState<Reading | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [worktreeNotes, setWorktreeNotes] = useState<Record<string, string>>(
    {},
  );
  const generation = useRef(0);

  const measure = useLatestCallback(async (): Promise<void> => {
    if (api === null || remote) {
      return;
    }
    const mine = ++generation.current;
    setLoading(true);
    try {
      const daemon = await api.getStorageUsage();
      const app = await window.geniro
        .getAppStorage(daemon.unclaimed)
        .catch((err: unknown) => {
          setError(String(err));
          return null;
        });
      if (mine === generation.current) {
        setReading({ daemon, app });
        const finished = daemon.job;
        if (
          compactionAwaited &&
          finished?.target === StorageCleanTarget.CompactDatabase &&
          (finished.state === 'done' || finished.state === 'failed')
        ) {
          compactionAwaited = false;
          if (finished.state === 'failed') {
            setError(
              `The compaction failed: ${finished.error ?? 'no reason given'}`,
            );
          } else {
            setNotice(jobOutcome(finished));
          }
        }
      }
    } catch (err) {
      if (mine === generation.current) {
        setError(describeDaemonError(err));
      }
    } finally {
      if (mine === generation.current) {
        setLoading(false);
      }
    }
  }, [api, remote]);

  useEffect(() => {
    void measure();
  }, [measure]);

  const job = reading?.daemon.job ?? null;
  const running = job?.state === 'running';
  const busy = running || job?.state === 'scheduled';

  useEffect(() => {
    if (!running || api === null) {
      return;
    }
    let timer: ReturnType<typeof setTimeout> | null = null;
    let stopped = false;
    const poll = (): void => {
      timer = setTimeout(() => {
        void api
          .getStorageJob()
          .then(({ job: latest }) => {
            if (stopped) {
              return;
            }
            if (latest?.state === 'running') {
              poll();
              return;
            }
            if (latest?.state === 'failed') {
              setError(
                `The clean-up failed: ${latest.error ?? 'no reason given'}`,
              );
            } else if (latest !== null && latest !== undefined) {
              setNotice(jobOutcome(latest));
            }
            void measure();
          })
          .catch((err: unknown) => {
            if (!stopped) {
              setError(describeDaemonError(err));
              poll();
            }
          });
      }, STORAGE_JOB_POLL_MS);
    };
    poll();
    return () => {
      stopped = true;
      if (timer !== null) {
        clearTimeout(timer);
      }
    };
  }, [running, api, measure]);

  if (remote) {
    return (
      <SettingsPanel>
        <SettingsPanelRow layout="block">
          <p className="text-sm text-muted-foreground">
            Storage is managed on the Mac.
          </p>
        </SettingsPanelRow>
      </SettingsPanel>
    );
  }

  const clean = async (
    target: StorageCleanTarget,
    archivedBefore?: string,
  ): Promise<void> => {
    if (api === null) {
      return;
    }
    setError(null);
    setNotice(null);
    try {
      const started = await api.cleanStorage({
        storageCleanDto: { target, archivedBefore },
      });
      setReading((current) =>
        current === null
          ? current
          : { ...current, daemon: { ...current.daemon, job: started } },
      );
      if (started.state === 'scheduled') {
        compactionAwaited = true;
        setNotice('Restarting Geniro’s background service to compact…');
        await window.geniro.restartDaemon();
      }
    } catch (err) {
      compactionAwaited = false;
      setError(describeDaemonError(err));
    }
  };

  const clearBrowserCache = async (): Promise<void> => {
    setError(null);
    try {
      const { freedBytes } = await window.geniro.clearBrowserCache();
      setNotice(
        `The window cache is cleared — ${formatBytes(freedBytes)} freed.`,
      );
      await measure();
    } catch (err) {
      setError(String(err));
    }
  };

  const removeWorktree = async (name: string): Promise<void> => {
    setError(null);
    try {
      const outcome = await window.geniro.removeStorageWorktree(name);
      setWorktreeNotes((notes) => ({
        ...notes,
        [name]: outcome.removed ? 'Removed.' : `Kept: ${outcome.reason ?? ''}`,
      }));
      if (outcome.removed) {
        await measure();
      }
    } catch (err) {
      setError(String(err));
    }
  };

  if (reading === null) {
    return (
      <SettingsPanel>
        <SettingsPanelRow layout="block">
          {error === null ? (
            <span className="flex items-center gap-2 text-sm text-muted-foreground">
              <Spinner /> Measuring the data folder…
            </span>
          ) : (
            <ErrorBanner message={error} onDismiss={() => setError(null)} />
          )}
        </SettingsPanelRow>
      </SettingsPanel>
    );
  }

  const { daemon, app } = reading;
  const groupOf = (id: StorageGroupIdEnum): StorageGroup | undefined =>
    daemon.groups.find((group) => group.id === id);
  const worktrees = app?.worktrees ?? [];
  const browserCache = app?.browserCache ?? [];
  const appData = app?.appData ?? [];

  const overview: { key: string; label: string; bytes: number }[] = [
    ...daemon.groups.map((group) => ({
      key: group.id,
      label: GROUP_TEXT[group.id].title,
      bytes: group.bytes,
    })),
    { key: 'worktrees', label: 'Task worktrees', bytes: sum(worktrees) },
    { key: 'browserCache', label: 'Window cache', bytes: sum(browserCache) },
    { key: 'appData', label: 'Window data', bytes: sum(appData) },
  ]
    .filter((row) => row.bytes > 0)
    .sort((a, b) => b.bytes - a.bytes);
  const total = sum(overview);
  const segments: BreakdownSegment[] = overview.map((row, index) => ({
    key: row.key,
    label: row.label,
    value: row.bytes,
    colorClass:
      index < COLOURED_PARTS && row.bytes / total >= COLOURED_PART_MIN_SHARE
        ? contextCategoryColor(index)
        : UNCOLOURED_PART,
    figures: [formatBytes(row.bytes), formatPercent((row.bytes / total) * 100)],
  }));
  const dotOf = (key: string): string =>
    segments.find((segment) => segment.key === key)?.colorClass ?? 'bg-muted';

  const cleanButtons = (options: readonly StorageCleanOption[]) =>
    options.map((option) => (
      <ConfirmActionButton
        key={option.target}
        variant="ghost"
        className={
          option.target === StorageCleanTarget.CompactDatabase
            ? KEEPS_DATA_CLASS
            : DELETES_DATA_CLASS
        }
        disabled={busy}
        {...confirmOf(option)}
        onConfirm={() => clean(option.target)}>
        {cleanButtonLabel(option)}
      </ConfirmActionButton>
    ));

  const groupRow = (id: StorageGroupIdEnum, note?: React.ReactNode) => {
    const group = groupOf(id);
    if (group === undefined) {
      return null;
    }
    const text = GROUP_TEXT[id];
    return (
      <StorageRow
        key={id}
        name={text.title}
        figure={formatBytes(group.bytes) ?? '0 B'}
        dot={dotOf(id)}
        quiet={group.bytes === 0 && group.clean.length === 0}
        details={
          <StorageDetails
            about={text.about}
            note={note}
            entries={group.entries}
          />
        }>
        {group.clean.length === 0 ? null : cleanButtons(group.clean)}
      </StorageRow>
    );
  };

  const taskRows = [
    worktrees.length === 0 ? null : (
      <StorageRow
        key="worktrees"
        name="Task worktrees"
        figure={formatBytes(sum(worktrees)) ?? '0 B'}
        dot={dotOf('worktrees')}
        details={
          <>
            <p>
              Checkouts the board&apos;s cards worked in. Removing one keeps its
              branch; one holding unsaved work, or whose card is still open, is
              kept.
            </p>
            <ul className="flex flex-col divide-y divide-border text-foreground">
              {worktrees.map((worktree) => (
                <WorktreeItem
                  key={worktree.name}
                  worktree={worktree}
                  note={worktreeNotes[worktree.name] ?? null}
                  onRemove={() => removeWorktree(worktree.name)}
                />
              ))}
            </ul>
          </>
        }
      />
    ),
    groupRow(StorageGroupIdEnum.TaskFiles),
  ].filter((row) => row !== null);

  const appRows = [
    ...[
      StorageGroupIdEnum.Teams,
      StorageGroupIdEnum.TeamBackups,
      StorageGroupIdEnum.Logs,
      StorageGroupIdEnum.Leftovers,
      StorageGroupIdEnum.SettingsCopies,
      StorageGroupIdEnum.Caches,
      StorageGroupIdEnum.AppState,
    ].map((id) => ({ bytes: groupOf(id)?.bytes ?? 0, row: groupRow(id) })),
    {
      bytes: sum(browserCache),
      row:
        browserCache.length === 0 ? null : (
          <StorageRow
            key="browserCache"
            name="Window cache"
            figure={formatBytes(sum(browserCache)) ?? '0 B'}
            dot={dotOf('browserCache')}
            details={
              <StorageDetails
                about="What the app window caches to load faster. Clearing empties its web and script caches; they refill as you work."
                entries={browserCache}
              />
            }>
            <ConfirmActionButton
              variant="ghost"
              className={KEEPS_DATA_CLASS}
              question="Clear the window cache?"
              description="Its web and script caches are emptied; they refill as you work."
              confirmLabel="Clear cache"
              busyLabel="Clearing…"
              confirmVariant="default"
              onConfirm={clearBrowserCache}>
              Clear cache
            </ConfirmActionButton>
          </StorageRow>
        ),
    },
    {
      bytes: sum(appData),
      row:
        appData.length === 0 ? null : (
          <StorageRow
            key="appData"
            name="Window data"
            figure={formatBytes(sum(appData)) ?? '0 B'}
            dot={dotOf('appData')}
            details={
              <StorageDetails
                about="The window’s own storage, settings and pairings. Kept."
                entries={appData}
              />
            }
          />
        ),
    },
  ]
    .filter(({ row }) => row !== null)
    .sort((a, b) => b.bytes - a.bytes);

  return (
    <div className="flex flex-col gap-6">
      {error === null ? null : (
        <ErrorBanner message={error} onDismiss={() => setError(null)} />
      )}
      {notice === null ? null : (
        <p className="text-sm text-muted-foreground" role="status">
          {notice}
        </p>
      )}

      <InUseCard
        total={total}
        segments={segments}
        folder={daemon.root}
        loading={loading}
        onMeasure={() => void measure()}
        runningText={running && job !== null ? RUNNING_TEXT[job.target] : null}
      />

      <StorageSection title="Chats">
        {groupRow(
          StorageGroupIdEnum.Database,
          `${daemon.chats.active} chats, ${daemon.chats.archived} archived.`,
        )}
        {daemon.chats.archived === 0 ? null : (
          <ArchivedChatsRow
            total={daemon.chats.archived}
            periods={daemon.chats.archivedPeriods}
            disabled={busy}
            onDelete={(archivedBefore) =>
              clean(StorageCleanTarget.ArchivedChats, archivedBefore)
            }
          />
        )}
        {groupRow(StorageGroupIdEnum.AgentSessions)}
        {groupRow(StorageGroupIdEnum.ChatFiles)}
      </StorageSection>

      {taskRows.length === 0 ? null : (
        <StorageSection title="Tasks">{taskRows}</StorageSection>
      )}

      {appRows.length === 0 ? null : (
        <StorageSection title="Teams and app">
          {appRows.map(({ row }) => row)}
        </StorageSection>
      )}
    </div>
  );
}

/** A named run of rows. */
function StorageSection({
  title,
  children,
}: {
  title: string;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <section className="flex flex-col gap-2">
      <h2 className="px-1 text-xs font-medium text-muted-foreground">
        {title}
      </h2>
      <SettingsPanel>{children}</SettingsPanel>
    </section>
  );
}

/**
 * The one number the page is for, and the bar of what makes it up. The rows
 * below carry the bar's colours, so the list and the sizes behind Breakdown are
 * for whoever wants them in one sorted column, with the folder they measure.
 */
function InUseCard({
  total,
  segments,
  folder,
  loading,
  onMeasure,
  runningText,
}: {
  total: number;
  segments: readonly BreakdownSegment[];
  folder: string;
  loading: boolean;
  onMeasure: () => void;
  runningText: string | null;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const detailsId = useId();
  const [amount, unit] = (formatBytes(total) ?? '0 B').split(' ');
  const coloured = segments.filter(
    (segment) => segment.colorClass !== UNCOLOURED_PART,
  );
  const rest = sum(
    segments
      .filter((segment) => segment.colorClass === UNCOLOURED_PART)
      .map((segment) => ({ bytes: segment.value })),
  );
  return (
    <SettingsPanel>
      <div className="flex flex-col gap-4 p-4">
        <div className="flex items-start justify-between gap-3">
          <div className="flex min-w-0 flex-col gap-2">
            <span className="text-xs font-medium text-muted-foreground">
              In use
            </span>
            <span
              data-slot="storage-total"
              className="text-4xl leading-none font-semibold tracking-tight tabular-nums">
              {amount}
              <span className="text-lg font-medium tracking-normal text-muted-foreground">
                {' '}
                {unit}
              </span>
            </span>
          </div>
          <Button
            size="sm"
            variant="ghost"
            className={cn('-mt-1 -mr-2.5', KEEPS_DATA_CLASS)}
            disabled={loading}
            onClick={onMeasure}>
            {loading ? <Spinner /> : <RefreshCw />} Measure again
          </Button>
        </div>
        <SegmentBar
          segments={[
            ...coloured,
            ...(rest > 0
              ? [{ key: 'rest', value: rest, colorClass: UNCOLOURED_PART }]
              : []),
          ]}
          denominator={total}
          className="h-2 gap-px"
        />
        <button
          type="button"
          aria-expanded={open}
          aria-controls={open ? detailsId : undefined}
          onClick={() => setOpen((current) => !current)}
          className="-my-1 flex w-fit cursor-pointer items-center gap-1 rounded-sm py-1 text-xs text-muted-foreground outline-none select-none hover:text-foreground focus-visible:ring-2 focus-visible:ring-ring/50">
          Breakdown
          <ChevronRight
            aria-hidden="true"
            className={cn('size-3 transition-transform', open && 'rotate-90')}
          />
        </button>
        {open ? (
          <div
            id={detailsId}
            className="flex flex-col gap-2 text-xs text-muted-foreground">
            <SegmentLegend segments={segments} />
            <span className="flex items-center gap-1">
              <span className="min-w-0 break-all">{folder}</span>
              <CopyButton text={folder} label="Copy the folder path" />
            </span>
          </div>
        ) : null}
      </div>
      {runningText === null ? null : (
        <SettingsPanelRow layout="block">
          <span className="text-sm">{runningText}</span>
          <ProgressBar fraction={null} label={runningText} />
        </SettingsPanelRow>
      )}
    </SettingsPanel>
  );
}

/**
 * The archive's one delete: pick a period, read how many chats it holds, press.
 * Each period carries the window the daemon counted, posted back as it came, so
 * what is deleted is what was counted, whatever is archived after this reading.
 */
function ArchivedChatsRow({
  total,
  periods,
  disabled,
  onDelete,
}: {
  total: number;
  periods: readonly StorageArchivedPeriod[];
  disabled: boolean;
  onDelete: (archivedBefore: string) => Promise<void>;
}): React.JSX.Element | null {
  const [chosen, setChosen] = useState(DEFAULT_ARCHIVED_PERIOD);
  const period =
    periods.find((candidate) => periodKey(candidate) === chosen) ?? periods[0];
  if (period === undefined) {
    return null;
  }
  return (
    <StorageRow
      name="Archived chats"
      figure={chatCount(total)}
      dot={null}
      details={
        <StorageDetails about="A chat deleted here loses its transcript, its files and its agent conversation for good. Age counts from when a chat was archived, not when it was last used; chats archived more recently than the period you pick stay. Compact the database afterwards to give the space back to the disk." />
      }>
      <Select
        variant="ghost"
        className="ml-1 @[36rem]:ml-0"
        aria-label="Which archived chats to delete"
        value={chosen}
        triggerLabel={periodLabel(period)}
        disabled={disabled}
        groups={[
          {
            label: 'Delete archived chats',
            items: periods.map((candidate) => ({
              value: periodKey(candidate),
              label: `${periodLabel(candidate)} · ${candidate.count}`,
            })),
          },
        ]}
        onValueChange={setChosen}
      />
      <ConfirmActionButton
        variant="ghost"
        className={DELETES_DATA_CLASS}
        disabled={disabled || period.count === 0}
        {...archivedConfirmOf(period)}
        confirmLabel="Delete"
        busyLabel="Deleting…"
        onConfirm={() => onDelete(period.archivedBefore)}>
        {cleanLabel({
          target: StorageCleanTarget.ArchivedChats,
          count: period.count,
          bytes: null,
        })}
      </ConfirmActionButton>
    </StorageRow>
  );
}

function worktreeState(worktree: StorageWorktree): string {
  if (worktree.kind === 'file') {
    return 'a loose file';
  }
  if (worktree.kind === 'folder') {
    return 'not a git worktree';
  }
  if (worktree.taskId === null) {
    return 'not tracked by the board';
  }
  return worktree.cardFinished === true
    ? 'card finished'
    : worktree.cardFinished === false
      ? 'card still open'
      : 'card state unknown';
}

function WorktreeItem({
  worktree,
  note,
  onRemove,
}: {
  worktree: StorageWorktree;
  note: string | null;
  onRemove: () => Promise<void>;
}): React.JSX.Element {
  return (
    <li className="flex items-center gap-3 py-2 first:pt-0 last:pb-0">
      <div className="flex min-w-0 flex-1 flex-col">
        <span className="truncate text-sm" title={worktree.name}>
          {worktree.branch ?? worktree.name}
        </span>
        <span className="truncate text-xs text-muted-foreground">
          {formatBytes(worktree.bytes)} · {worktreeState(worktree)}
          {note === null ? null : ` · ${note}`}
        </span>
      </div>
      {worktree.kind === 'worktree' ? (
        <ConfirmActionButton
          variant="ghost"
          className={DELETES_DATA_CLASS}
          question={`Remove ${worktree.branch ?? worktree.name}?`}
          description={
            <>
              The checkout is deleted and its branch is kept. One holding
              unsaved work, or whose card is still open, is kept instead.
            </>
          }
          confirmLabel="Remove"
          busyLabel="Removing…"
          onConfirm={onRemove}>
          Remove
        </ConfirmActionButton>
      ) : null}
    </li>
  );
}
