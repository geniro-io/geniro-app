function cleanLabel(option: StorageCleanOption): string {
  const size = option.bytes === null ? '' : ` · ${formatBytes(option.bytes)}`;
  switch (option.target) {
    case StorageCleanTarget.ArchivedChats:
      return `Delete ${chatCount(option.count)}`;
    case StorageCleanTarget.CompactDatabase:
      return `Compact${size}`;
    case StorageCleanTarget.OrphanChatFiles:
    case StorageCleanTarget.OrphanTaskFiles:
      return `Delete ${option.count} orphaned folder${option.count === 1 ? '' : 's'}${size}`;
    case StorageCleanTarget.TeamBackups:
      return `Delete ${option.count} backup${option.count === 1 ? '' : 's'}${size}`;
    case StorageCleanTarget.Logs:
      return `Delete ${option.count} old log${option.count === 1 ? '' : 's'}${size}`;
    case StorageCleanTarget.Leftovers:
    case StorageCleanTarget.SettingsCopies:
      return `Delete${size}`;
  }
}

function confirmOf(option: StorageCleanOption): {
  question: string;
  description: string;
  confirmLabel: string;
  busyLabel: string;
} {
  if (option.target === StorageCleanTarget.CompactDatabase) {
    return {
      question: 'Compact the database?',
      description:
        'Geniro’s background service restarts and compacts the database before it serves anything again. Chats are not changed.',
      confirmLabel: 'Restart & compact',
      busyLabel: 'Restarting…',
    };
  }
  return {
    question: `${cleanLabel(option)}?`,
    description: 'They are deleted for good. This cannot be undone.',
    confirmLabel: 'Delete',
    busyLabel: 'Deleting…',
  };
}

/** A quiet button that destroys something: the only red on the page. */
