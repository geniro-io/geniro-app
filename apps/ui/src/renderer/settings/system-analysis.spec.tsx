import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  type AnalysisConfig,
  DEFAULT_SETTINGS,
  type Settings,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import { withVocabulary } from '../__tests__/agent-vocabulary-api';
import {
  type AgentFlagRunKind,
  type CommandCenterCardRun,
  type DigestThread,
  FetchError,
  type RunDto,
  type StartSystemAnalysisDto,
  type SystemAnalysisListDto,
  type SystemAnalysisRow,
  type SystemAnalysisScopeDto,
} from '../autogenerated';
import { type DaemonApis, SYSTEM_ANALYSIS_TIMEOUT_MS } from '../daemon-api';
import type { SystemAnalysesChangedEvent } from '../daemon-client';
import {
  SystemAnalysisPage,
  type SystemAnalysisPageProps,
} from './system-analysis';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;
let writes: Partial<Settings>[];
let stored: Settings;

const REMEMBERED: AnalysisConfig = {
  agent: 'claude',
  configDir: null,
  model: 'opus',
  effort: null,
  contextWindow: null,
  autoCompactPercent: null,
  modelParameters: {},
  approval: null,
};

const PERIOD = {
  from: '2026-11-15T00:00:00.000Z',
  to: '2026-11-22T00:00:00.000Z',
};

function install(settings: Partial<Settings> = {}): void {
  writes = [];
  stored = { ...DEFAULT_SETTINGS, ...settings };
  window.geniro = createPreloadStub({
    getSettings: () => Promise.resolve(stored),
    updateSettings: (patch) => {
      writes.push(patch);
      stored = { ...stored, ...patch };
      return Promise.resolve(stored);
    },
  });
}

function scopeOf(
  days: number,
  threadsWithSignals: number,
  threads: DigestThread[] = [],
): SystemAnalysisScopeDto {
  return {
    period: { ...PERIOD, days },
    totals: {
      threadsWithSignals,
      flags: 3,
      failedToolCalls: 4,
      systemThreads: 1,
    },
    threads,
  };
}

function digestThread(
  runId: string,
  title: string,
  kind: AgentFlagRunKind,
  over: Partial<DigestThread['signals']> = {},
): DigestThread {
  return {
    runId,
    title,
    kind,
    teamSlug: null,
    projectId: null,
    archived: false,
    lastActivityAt: '2026-11-21T10:00:00.000Z',
    score: 5,
    signals: {
      workFlags: 0,
      disagreementFlags: 0,
      outcome: null,
      unmetGoals: 0,
      refusedApprovals: 0,
      corrections: 0,
      analysisRefusals: 0,
      failedToolCalls: 0,
      ...over,
    },
    failedTools: [],
    snapshotSeq: 1,
  };
}

function runOf(id: string, createdAt: string): CommandCenterCardRun {
  return { id, createdAt, title: id } as unknown as CommandCenterCardRun;
}

function analysisRow(
  id: string,
  createdAt: string,
  over: Partial<SystemAnalysisRow> = {},
): SystemAnalysisRow {
  return {
    run: runOf(id, createdAt),
    period: { ...PERIOD, days: 7 },
    threadsRead: 2,
    proposals: 1,
    status: 'filed',
    filed: 1,
    started: 0,
    failed: 0,
    ...over,
  };
}

const ROWS_NEWEST_FIRST = [
  analysisRow('a', '2026-11-22T09:00:00.000Z'),
  analysisRow('b', '2026-11-20T09:00:00.000Z', {
    status: 'waiting',
    proposals: 2,
  }),
  analysisRow('c', '2026-11-18T09:00:00.000Z', { status: 'kept' }),
];

const OLDER_ROW = analysisRow('d', '2026-11-10T09:00:00.000Z', {
  status: 'failed',
  period: null,
});

function fakeApi(
  scopeFor: (days: number) => SystemAnalysisScopeDto = (days) =>
    scopeOf(days, days === 3 ? 5 : 2),
  list: (before: string | undefined) => SystemAnalysisListDto = (before) =>
    before === undefined
      ? { analyses: ROWS_NEWEST_FIRST, next: 'cursor-1' }
      : { analyses: [OLDER_ROW], next: null },
) {
  return {
    readSystemAnalysisScope: vi.fn(
      (
        request: { days: number },
        _init?: RequestInit,
      ): Promise<SystemAnalysisScopeDto> =>
        Promise.resolve(scopeFor(request.days)),
    ),
    listSystemAnalyses: vi.fn(
      (request: { limit?: number; before?: string } = {}) =>
        Promise.resolve(list(request.before)),
    ),
    startSystemAnalysis: vi.fn(
      (
        _request: { startSystemAnalysisDto: StartSystemAnalysisDto },
        _init?: RequestInit,
      ) =>
        Promise.resolve<RunDto>({
          id: 'run-new',
        } as unknown as RunDto),
    ),
  };
}

function asApi(api: ReturnType<typeof fakeApi>): DaemonApis['systemAnalyses'] {
  return api as unknown as DaemonApis['systemAnalyses'];
}

function agentsApiStub(): DaemonApis['agents'] {
  return Object.assign(
    withVocabulary({
      listAgentModels: vi.fn(async () => [
        { id: 'opus', label: 'Opus', source: 'cli' as const },
        { id: 'sonnet', label: 'Sonnet', source: 'cli' as const },
      ]),
    }),
    {
      getModelPrice: vi.fn(async () => ({ price: null })),
    },
  ) as unknown as DaemonApis['agents'];
}

async function settle(ms = 0): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => {
      setTimeout(resolve, ms);
    });
  });
}

async function renderPage(
  props: Partial<SystemAnalysisPageProps> = {},
): Promise<void> {
  await act(async () => {
    root.render(
      <SystemAnalysisPage
        api={asApi(fakeApi())}
        client={null}
        agentsApi={agentsApiStub()}
        cliDetections={null}
        capabilities={null}
        capabilitiesLoading={false}
        onOpenReport={vi.fn()}
        remote={false}
        {...props}
      />,
    );
  });
  await settle();
  await settle();
}

function button(scope: ParentNode, label: string): HTMLButtonElement {
  const found = [...scope.querySelectorAll('button')].find(
    (candidate) => candidate.textContent?.trim() === label,
  );
  if (!found) {
    throw new Error(`no button "${label}"`);
  }
  return found;
}

function findButton(label: string): HTMLButtonElement | undefined {
  return [...container.querySelectorAll('button')].find(
    (candidate) => candidate.textContent?.trim() === label,
  );
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
  await settle();
}

async function choose(
  label: string,
  option: string,
  scope: ParentNode = container,
): Promise<void> {
  const trigger = scope.querySelector<HTMLElement>(
    `[data-menu-trigger][aria-label="${label}"]`,
  );
  if (!trigger) {
    throw new Error(`no select ${label}`);
  }
  await press(trigger);
  const item = [
    ...document.querySelectorAll<HTMLElement>('[role="option"]'),
  ].find((candidate) => candidate.textContent?.trim() === option);
  if (!item) {
    throw new Error(`no option ${option}`);
  }
  await press(item);
}

function totalsText(): string | null | undefined {
  return container.querySelector('[data-slot="system-analysis-totals"]')
    ?.textContent;
}

function pastRowIds(): string[] {
  return [
    ...container.querySelectorAll<HTMLElement>(
      '[data-slot="system-analysis-row"]',
    ),
  ].map((row) => row.dataset.runId ?? '');
}

beforeEach(() => {
  Element.prototype.scrollIntoView = vi.fn();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  install({ lastAnalysisConfig: REMEMBERED });
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('SystemAnalysisPage', () => {
  it('shows the threads of the period picked, and reads the period again when it changes', async () => {
    const api = fakeApi();
    await renderPage({ api: asApi(api) });

    expect(api.readSystemAnalysisScope).toHaveBeenLastCalledWith(
      { days: 7 },
      expect.objectContaining({ signal: expect.any(AbortSignal) }),
    );
    expect(totalsText()).toContain('2 threads with signals');

    await choose('Period of the threads to analyse', 'Last 3 days');

    expect(api.readSystemAnalysisScope).toHaveBeenLastCalledWith(
      { days: 3 },
      expect.objectContaining({ signal: expect.any(AbortSignal) }),
    );
    expect(totalsText()).toContain('5 threads with signals');
  });

  it('starts with the remembered agent and model for the period picked, saves them, and opens the report it returns', async () => {
    const api = fakeApi();
    const onOpenReport = vi.fn();
    await renderPage({ api: asApi(api), onOpenReport });

    await choose('Period of the threads to analyse', 'Last 3 days');
    await press(button(container, 'Start analysis'));

    expect(api.startSystemAnalysis).toHaveBeenCalledWith(
      {
        startSystemAnalysisDto: { agentKind: 'claude', model: 'opus', days: 3 },
      },
      expect.objectContaining({ signal: expect.any(AbortSignal) }),
    );
    expect(onOpenReport).toHaveBeenCalledWith(
      expect.objectContaining({ id: 'run-new' }),
    );
    expect(writes.at(-1)).toMatchObject({
      lastAnalysisConfig: { agent: 'claude', model: 'opus' },
    });
  });

  it('drops the model of the old agent when the agent is changed, so Start names only the new one', async () => {
    const api = fakeApi();
    await renderPage({ api: asApi(api) });

    await choose('Agent that runs the analysis', 'codex');
    await press(button(container, 'Start analysis'));

    expect(api.startSystemAnalysis).toHaveBeenCalledWith(
      { startSystemAnalysisDto: { agentKind: 'codex', days: 7 } },
      expect.objectContaining({ signal: expect.any(AbortSignal) }),
    );
  });

  it('hides Start on a paired device and says the analysis starts on the Mac', async () => {
    const api = fakeApi();
    await renderPage({ api: asApi(api), remote: true });

    expect(findButton('Start analysis')).toBeUndefined();
    expect(container.textContent).toContain(
      'Start the analysis from your Mac.',
    );
    expect(api.listSystemAnalyses).toHaveBeenCalled();
  });

  it('disables Start, and says so, when no thread in the period has signals', async () => {
    await renderPage({
      api: asApi(fakeApi(() => scopeOf(7, 0))),
    });

    expect(button(container, 'Start analysis').disabled).toBe(true);
    expect(container.textContent).toContain(
      'No thread in this period has anything to analyse.',
    );
  });

  it('lists the past analyses in the order the daemon gives them, and Show all loads the next page', async () => {
    const api = fakeApi();
    await renderPage({ api: asApi(api) });

    expect(pastRowIds()).toEqual(['a', 'b', 'c']);
    expect(api.listSystemAnalyses).toHaveBeenLastCalledWith({ limit: 3 });

    await press(button(container, 'Show all'));

    expect(api.listSystemAnalyses).toHaveBeenLastCalledWith({
      limit: 3,
      before: 'cursor-1',
    });
    expect(pastRowIds()).toEqual(['a', 'b', 'c', 'd']);
    expect(findButton('Show all')).toBeUndefined();
  });

  it('reads the past analyses again when a system analysis changes, and stops once unmounted', async () => {
    let rows = ROWS_NEWEST_FIRST;
    const api = fakeApi(undefined, () => ({ analyses: rows, next: null }));
    const listeners = new Set<(event: SystemAnalysesChangedEvent) => void>();
    const client = {
      onSystemAnalysesChanged: (
        listener: (event: SystemAnalysesChangedEvent) => void,
      ) => {
        listeners.add(listener);
        return () => {
          listeners.delete(listener);
        };
      },
    };
    await renderPage({ api: asApi(api), client });
    const rowB = (): string | null | undefined =>
      container.querySelector('[data-run-id="b"]')?.textContent;
    expect(rowB()).toContain('Waiting for you');

    rows = ROWS_NEWEST_FIRST.map((row) =>
      row.run.id === 'b' ? { ...row, status: 'filed', filed: 2 } : row,
    );
    await act(async () => {
      for (const listener of listeners) {
        listener({ runId: 'b' });
      }
    });
    await settle();

    expect(rowB()).not.toContain('Waiting for you');
    expect(rowB()).toContain('2 cards filed');

    act(() => root.unmount());
    expect(listeners.size).toBe(0);
    root = createRoot(container);
  });

  it('opens the report of the past analysis whose row is pressed', async () => {
    const onOpenReport = vi.fn();
    await renderPage({ api: asApi(fakeApi()), onOpenReport });

    await press(container.querySelector<HTMLElement>('[data-run-id="b"]')!);

    expect(onOpenReport).toHaveBeenCalledWith(
      expect.objectContaining({ id: 'b' }),
    );
  });

  it('gives the scope read and the start the system-analysis budget, not the 30 s default', async () => {
    const timeout = vi.spyOn(AbortSignal, 'timeout');
    try {
      const api = fakeApi();
      await renderPage({ api: asApi(api) });
      await press(button(container, 'Start analysis'));

      const budgetSignals = timeout.mock.calls.flatMap(
        ([ms], index): unknown[] =>
          ms === SYSTEM_ANALYSIS_TIMEOUT_MS
            ? [timeout.mock.results[index]?.value]
            : [],
      );
      expect(budgetSignals).toHaveLength(2);
      expect(api.readSystemAnalysisScope.mock.calls[0]?.[1]?.signal).toBe(
        budgetSignals[0],
      );
      expect(api.startSystemAnalysis.mock.calls[0]?.[1]?.signal).toBe(
        budgetSignals[1],
      );
    } finally {
      timeout.mockRestore();
    }
  });

  it('says in plain words that a start the client gave up on was not answered in time', async () => {
    const api = fakeApi();
    api.startSystemAnalysis.mockRejectedValueOnce(
      new FetchError(
        new DOMException('signal timed out', 'TimeoutError'),
        'The request failed and the interceptors did not return an alternative response',
      ),
    );
    const onOpenReport = vi.fn();
    await renderPage({ api: asApi(api), onOpenReport });

    await press(button(container, 'Start analysis'));

    expect(container.textContent).toContain(
      'The daemon did not answer in time',
    );
    expect(container.textContent).not.toContain('interceptors');
    expect(onOpenReport).not.toHaveBeenCalled();
  });

  it('shows the nothing-to-analyse refusal as its text and opens no report', async () => {
    const api = fakeApi();
    api.startSystemAnalysis.mockRejectedValueOnce(
      new Error(
        'daemon POST /v1/system-analyses failed (409): {"code":"SYSTEM_ANALYSIS_NOTHING","message":"Nothing to analyse."}',
      ),
    );
    const onOpenReport = vi.fn();
    await renderPage({ api: asApi(api), onOpenReport });

    await press(button(container, 'Start analysis'));

    expect(container.textContent).toContain(
      'No thread in this period has anything to analyse.',
    );
    expect(onOpenReport).not.toHaveBeenCalled();
  });

  it('lists the threads of the period with their signals in words, and filters them by kind', async () => {
    const threads = [
      digestThread('t1', 'Fix the parser', 'chat', { corrections: 2 }),
      digestThread('t2', 'Reflect on the build', 'lessons', {
        failedToolCalls: 4,
      }),
    ];
    await renderPage({
      api: asApi(fakeApi((days) => scopeOf(days, 2, threads))),
    });

    await press(button(container, 'Show threads'));
    const dialog = (): HTMLElement => document.body;
    expect(dialog().textContent).toContain('Fix the parser');
    expect(dialog().textContent).toContain('2 corrections');

    await choose('Kind of thread', 'Lessons', dialog());

    const listed = [
      ...dialog().querySelectorAll<HTMLElement>(
        '[data-slot="system-analysis-thread"]',
      ),
    ];
    expect(listed).toHaveLength(1);
    expect(listed[0]!.textContent).toContain('Reflect on the build');
    expect(listed[0]!.textContent).toContain('4 failed tool calls');
  });
});
