const DEFAULT_DAYS = 7;

const PERIODS = [1, 3, 7, 30];

const NOTHING_TO_ANALYSE = 'No thread in this period has anything to analyse.';

const KIND_LABEL: Record<AgentFlagRunKind, string> = {
  chat: 'Chat',
  team: 'Team',
  thread_analysis: 'Thread analysis',
  team_analysis: 'Team analysis',
  lessons: 'Lessons',
  lessons_check: 'Lessons check',
  system_analysis: 'System analysis',
  builder: 'Builder',
  project: 'Project',
  command_center: 'Command center',
};

const STATUS_TEXT: Record<
  SystemAnalysisStatus,
  (row: SystemAnalysisRow) => string
> = {
  running: () => 'Working',
  waiting: () => 'Waiting for you',
  filed: (row) => plural(row.filed, 'card filed', 'cards filed'),
  started: (row) => `${row.started.toLocaleString('en-US')} started`,
  kept: () => 'Report kept',
  failed: () => 'Failed',
};

const AGENT_BLANK = {
  model: null,
  effort: null,
  contextWindow: null,
  modelParameters: {},
  configDir: null,
} satisfies Partial<AnalysisConfig>;

function formatWhen(iso: string): string {
  return new Date(iso).toLocaleString('en-US', {
    month: 'short',
    day: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  });
}

function totalsText(totals: SystemDigestTotals): string {
  return [
    plural(
      totals.threadsWithSignals,
      'thread with signals',
      'threads with signals',
    ),
    plural(totals.flags, 'flag', 'flags'),
    plural(totals.failedToolCalls, 'failed tool call', 'failed tool calls'),
    plural(totals.systemThreads, 'system thread', 'system threads'),
  ].join(' · ');
}

function signalWords(signals: DigestSignals): string[] {
  const counted: [number, string, string][] = [
    [signals.workFlags, 'work flag', 'work flags'],
    [signals.disagreementFlags, 'disagreement flag', 'disagreement flags'],
    [signals.unmetGoals, 'unmet goal', 'unmet goals'],
    [signals.refusedApprovals, 'refused approval', 'refused approvals'],
    [signals.corrections, 'correction', 'corrections'],
    [signals.analysisRefusals, 'refused analysis', 'refused analyses'],
    [signals.failedToolCalls, 'failed tool call', 'failed tool calls'],
  ];
  const words = counted
    .filter(([count]) => count > 0)
    .map(([count, one, many]) => plural(count, one, many));
  return signals.outcome === null
    ? words
    : [`outcome ${signals.outcome}`, ...words];
}

export interface SystemAnalysisPageProps {
  /** The daemon's system-analysis routes; null until the daemon is reached. */
  api: DaemonApis['systemAnalyses'] | null;
  /** Announces each start, Apply and card start, so the past analyses re-read. */
  client: Pick<DaemonClient, 'onSystemAnalysesChanged'> | null;
  agentsApi: DaemonApis['agents'] | null;
  cliDetections: readonly CliDetection[] | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  /** Opens a run's report in the analysis popup. */
  onOpenReport: (run: CommandCenterCardRun) => void;
  /** A paired device reads the history but starts nothing: the analysis runs on the Mac. */
  remote?: boolean;
}

export function SystemAnalysisPage({
  api,
  client,
  agentsApi,
  cliDetections,
  capabilities,
  capabilitiesLoading,
  onOpenReport,
  remote = isRemoteRuntime(),
}: SystemAnalysisPageProps): React.JSX.Element {
  const [days, setDays] = useState(DEFAULT_DAYS);
  const [threadsOpen, setThreadsOpen] = useState(false);
  const [starting, setStarting] = useState(false);
  const [startError, setStartError] = useState<string | null>(null);
  const { config, setConfig, profiles } = useAnalysisSetup();
  const state = useSystemAnalysis(api, client, days);
  const { scope } = state;
  const canStart =
    !remote &&
    api !== null &&
    config !== null &&
    scope !== null &&
    scope.totals.threadsWithSignals > 0 &&
    !starting;
  const running =
    state.analyses?.find((row) => row.status === 'running') ?? null;

  const start = async (): Promise<void> => {
    if (config === null) {
      return;
    }
    setStarting(true);
    setStartError(null);
    try {
      const run = await state.start({
        agentKind: config.agent,
        ...setupFieldsOf(config),
        days,
      });
      saveAnalysisSetup(config);
      onOpenReport(run);
    } catch (err) {
      setStartError(
        daemonErrorCode(err) === 'SYSTEM_ANALYSIS_NOTHING'
          ? NOTHING_TO_ANALYSE
          : describeDaemonError(err),
      );
    } finally {
      setStarting(false);
    }
  };

  return (
    <SettingsGroups>
      <SettingsGroup
        icon={<Sparkles />}
        title="Run an analysis"
        description="Reads the threads of a period that have something to learn from, and writes one report."
        hint="The analysis reads the threads where agents raised a flag, a tool failed, a goal was left unmet, or you corrected an agent, and the threads geniro itself analysed or reflected on. It runs in a hidden chat, and its report opens in a window when it starts.">
        {running === null ? null : (
          <RunningAnalysis row={running} onOpen={onOpenReport} />
        )}
        <SettingsPanel>
          <SettingsPanelRow
            label="Period"
            hint="The threads whose last activity falls in this period are read.">
            <Select
              variant="ghost"
              aria-label="Period of the threads to analyse"
              leadingIcon={<CalendarDays />}
              value={String(days)}
              groups={[
                {
                  items: PERIODS.map((period) => ({
                    value: String(period),
                    label: periodLabel(period),
                  })),
                },
              ]}
              onValueChange={(next) => setDays(Number(next))}
            />
          </SettingsPanelRow>
          <SettingsPanelRow
            label="Threads"
            hint="Threads with a signal in the period. Start needs at least one.">
            <div className="flex min-w-0 flex-wrap items-center gap-2">
              <ThreadTotals scope={scope} error={state.scopeError} />
              <Button
                type="button"
                size="sm"
                variant="outline"
                title="List the threads this analysis would read, with what they show."
                disabled={scope === null}
                onClick={() => setThreadsOpen(true)}>
                Show threads
              </Button>
            </div>
          </SettingsPanelRow>
          {remote || config === null || profiles === null ? null : (
            <ModelRows
              config={config}
              setConfig={setConfig}
              recentConfigDirs={profiles.recentConfigDirs}
              configProfiles={profiles.configProfiles}
              agentsApi={agentsApi}
              cliDetections={cliDetections}
              capabilities={capabilities}
              capabilitiesLoading={capabilitiesLoading}
            />
          )}
        </SettingsPanel>
        {remote ? (
          <p
            data-slot="system-analysis-remote"
            className="m-0 text-sm text-muted-foreground">
            Start the analysis from your Mac.
          </p>
        ) : (
          <div className="flex min-w-0 flex-wrap items-center justify-between gap-2">
            <span className="text-xs text-muted-foreground">
              {scope !== null && scope.totals.threadsWithSignals === 0
                ? NOTHING_TO_ANALYSE
                : null}
            </span>
            <Button
              type="button"
              size="sm"
              title="Start the analysis of the threads in this period, with the agent and model picked above."
              disabled={!canStart}
              onClick={() => void start()}>
              {starting ? 'Starting…' : 'Start analysis'}
            </Button>
          </div>
        )}
        {startError === null ? null : <ErrorText>{startError}</ErrorText>}
      </SettingsGroup>

      <SettingsGroup
        icon={<History />}
        title="Past analyses"
        description="The reports of earlier analyses, newest first."
        hint="A row opens its report.">
        <PastAnalyses
          rows={state.analyses}
          hasMore={state.hasMore}
          loadingMore={state.loadingMore}
          error={state.listError}
          onOpen={onOpenReport}
          onMore={state.loadMore}
        />
      </SettingsGroup>

      {threadsOpen && scope !== null ? (
        <ThreadsDialog
          threads={scope.threads}
          onClose={() => setThreadsOpen(false)}
        />
      ) : null}
    </SettingsGroups>
  );
}

function ThreadTotals({
  scope,
  error,
}: {
  scope: SystemAnalysisScopeDto | null;
  error: string | null;
}): React.JSX.Element {
  if (error !== null) {
    return <ErrorText>{error}</ErrorText>;
  }
  if (scope === null) {
    return (
      <span className="inline-flex items-center gap-1 text-xs text-muted-foreground">
        <Spinner /> Reading the period…
      </span>
    );
  }
  return (
    <span data-slot="system-analysis-totals" className="text-sm tabular-nums">
      {totalsText(scope.totals)}
    </span>
  );
}

function ModelRows({
  config,
  setConfig,
  recentConfigDirs,
  configProfiles,
  agentsApi,
  cliDetections,
  capabilities,
  capabilitiesLoading,
}: {
  config: AnalysisConfig;
  setConfig: (next: AnalysisConfig) => void;
  recentConfigDirs: Partial<Record<CliKind, readonly string[]>>;
  configProfiles: readonly ConfigProfile[];
  agentsApi: DaemonApis['agents'] | null;
  cliDetections: readonly CliDetection[] | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
}): React.JSX.Element {
  const price = useModelPriceOf(
    agentsApi,
    config.agent,
    config.model,
    config.configDir,
  );
  return (
    <>
      <SettingsPanelRow
        label="Agent"
        hint="The CLI that reads the threads and writes the report, with the model and its settings picked beside it.">
        <span className="flex min-w-0 flex-wrap items-center gap-1">
          <TargetSelect
            value={config.agent}
            teams={[]}
            cliDetections={cliDetections}
            aria-label="Agent that runs the analysis"
            onChange={(target) =>
              setConfig({
                ...config,
                ...AGENT_BLANK,
                agent: targetAgentKind(target),
              })
            }
          />
          <ChoiceModelSettings
            value={config}
            onChange={setConfig}
            agentsApi={agentsApi}
            capabilities={capabilities}
            capabilitiesLoading={capabilitiesLoading}
            recentConfigDirs={recentConfigDirs}
            configProfiles={configProfiles}
          />
        </span>
      </SettingsPanelRow>
      <SettingsPanelRow
        label="List price"
        hint="What the picked model costs per million tokens, from the published price list.">
        <PriceText price={price} />
      </SettingsPanelRow>
    </>
  );
}

function PriceText({
  price,
}: {
  price: ModelPrice | null | undefined;
}): React.JSX.Element | null {
  if (price === undefined) {
    return null;
  }
  if (price === null) {
    return (
      <span className="text-xs text-muted-foreground">
        cost not measured for this model
      </span>
    );
  }
  return <ModelPriceText price={price} />;
}

function ThreadsDialog({
  threads,
  onClose,
}: {
  threads: readonly DigestThread[];
  onClose: () => void;
}): React.JSX.Element {
  const [kind, setKind] = useState<AgentFlagRunKind | 'all'>('all');
  const kinds = [...new Set(threads.map((thread) => thread.kind))];
  const listed =
    kind === 'all' ? threads : threads.filter((thread) => thread.kind === kind);
  return (
    <Dialog
      open
      onClose={onClose}
      title="Threads in this period"
      className="max-w-2xl">
      <div
        data-slot="system-analysis-threads"
        className="flex min-w-0 flex-col gap-3">
        <Select
          variant="ghost"
          aria-label="Kind of thread"
          groups={[
            {
              items: [
                { value: 'all', label: 'All kinds' },
                ...kinds.map((item) => ({
                  value: item,
                  label: KIND_LABEL[item],
                })),
              ],
            },
          ]}
          value={kind}
          onValueChange={(next) =>
            setKind(kinds.find((item) => item === next) ?? 'all')
          }
        />
        {listed.length === 0 ? (
          <EmptyState>No thread of this kind in the period.</EmptyState>
        ) : (
          <ul className="m-0 flex list-none flex-col divide-y divide-border p-0">
            {listed.map((thread) => (
              <li
                key={thread.runId}
                data-slot="system-analysis-thread"
                className="flex min-w-0 flex-col gap-1 py-2">
                <div className="flex min-w-0 flex-wrap items-center gap-2">
                  <span className="min-w-0 truncate text-sm font-medium">
                    {thread.title ?? 'Untitled thread'}
                  </span>
                  <Badge variant="secondary">{KIND_LABEL[thread.kind]}</Badge>
                  <span
                    className="ml-auto text-xs text-muted-foreground tabular-nums"
                    title="How strongly its signals point at it">
                    score {thread.score}
                  </span>
                </div>
                <span className="text-xs text-muted-foreground">
                  {signalWords(thread.signals).join(' · ')}
                </span>
              </li>
            ))}
          </ul>
        )}
      </div>
    </Dialog>
  );
}

function RunningAnalysis({
  row,
  onOpen,
}: {
  row: SystemAnalysisRow;
  onOpen: (run: CommandCenterCardRun) => void;
}): React.JSX.Element {
  return (
    <div
      data-slot="system-analysis-running"
      className="flex min-w-0 flex-wrap items-center justify-between gap-2 rounded-md border border-border px-3 py-2">
      <span className="text-sm">
        {row.period === null
          ? 'An analysis is working.'
          : `An analysis of the last ${row.period.days} days is working.`}
      </span>
      <Button
        type="button"
        size="sm"
        variant="outline"
        title="Open the report of the analysis that is working."
        onClick={() => onOpen(row.run)}>
        Open
      </Button>
    </div>
  );
}

function PastAnalyses({
  rows,
  hasMore,
  loadingMore,
  error,
  onOpen,
  onMore,
}: {
  rows: readonly SystemAnalysisRow[] | null;
  hasMore: boolean;
  loadingMore: boolean;
  error: string | null;
  onOpen: (run: CommandCenterCardRun) => void;
  onMore: () => void;
}): React.JSX.Element {
  return (
    <div
      data-slot="system-analysis-past"
      className="flex min-w-0 flex-col gap-2">
      {error === null ? null : <ErrorText>{error}</ErrorText>}
      {rows === null ? (
        error === null ? (
          <span className="inline-flex items-center gap-1 text-sm text-muted-foreground">
            <Spinner /> Loading…
          </span>
        ) : null
      ) : rows.length === 0 ? (
        <EmptyState>No analysis yet.</EmptyState>
      ) : (
        <ul className="m-0 flex list-none flex-col divide-y divide-border p-0">
          {rows.map((row) => (
            <li key={row.run.id}>
              <button
                type="button"
                data-slot="system-analysis-row"
                data-run-id={row.run.id}
                title="Open this analysis's report"
                onClick={() => onOpen(row.run)}
                className={cn(
                  'flex w-full min-w-0 flex-wrap items-center gap-x-3 gap-y-1 rounded-md px-3 py-2 text-left text-sm',
                  CARD_BUTTON_CLASS,
                )}>
                <span className="font-medium tabular-nums">
                  {formatWhen(row.run.createdAt)}
                </span>
                <span className="text-muted-foreground">
                  {row.period === null
                    ? 'No period'
                    : periodLabel(row.period.days)}
                </span>
                <span className="text-muted-foreground">
                  {plural(row.threadsRead, 'thread read', 'threads read')}
                </span>
                <span className="text-muted-foreground">
                  {plural(row.proposals, 'proposal', 'proposals')}
                </span>
                <span className="ml-auto font-medium">
                  {STATUS_TEXT[row.status](row)}
                </span>
              </button>
            </li>
          ))}
        </ul>
      )}
      {hasMore ? (
        <Button
          type="button"
          size="sm"
          variant="ghost"
          className="self-start"
          title={`Read the next ${SYSTEM_ANALYSIS_PAGE_SIZE} older analyses.`}
          disabled={loadingMore}
          onClick={onMore}>
          {loadingMore ? 'Loading…' : 'Show all'}
        </Button>
      ) : null}
    </div>
  );
}
