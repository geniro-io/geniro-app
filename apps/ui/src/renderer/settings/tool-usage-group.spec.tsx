// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { DEFAULT_SETTINGS, type Settings } from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type {
  ToolUsageListDto,
  ToolUsageRow,
  ToolUsageSubjectDto,
} from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { ToolUsageGroup } from './tool-usage-group';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;
let writes: Partial<Settings>[];

function row(
  subject: string,
  calls: number,
  extra: Partial<ToolUsageRow> = {},
): ToolUsageRow {
  return {
    subjectKind: 'tool',
    subject,
    source: '',
    calls,
    subagentCalls: 0,
    errors: 0,
    refused: 0,
    avgDurationMs: null,
    avgResultChars: null,
    firstAt: '2026-11-01T10:00:00.000Z',
    lastAt: '2026-11-20T10:00:00.000Z',
    firstKnownAt: null,
    offeredSessions: null,
    removalEligible: false,
    ...extra,
  };
}

const TEN_ROWS = Array.from({ length: 10 }, (_, index) =>
  row(`tool${index}`, 100 - index),
);

function listOf(overrides: Partial<ToolUsageListDto> = {}): ToolUsageListDto {
  return {
    countingSince: '2026-10-15T12:00:00.000Z',
    liveSince: '2026-11-01T00:00:00.000Z',
    rows: TEN_ROWS,
    neverCalled: [],
    ...overrides,
  };
}

function statsApi(
  list: () => Promise<ToolUsageListDto>,
  subject?: ToolUsageSubjectDto,
): DaemonApis['stats'] & {
  readToolUsage: ReturnType<typeof vi.fn>;
  readToolUsageSubject: ReturnType<typeof vi.fn>;
} {
  return {
    readToolUsage: vi.fn(list),
    readToolUsageSubject: vi.fn(async () => subject),
  } as never;
}

async function settle(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => {
      setTimeout(resolve, 0);
    });
  });
}

async function renderGroup(
  api: DaemonApis['stats'] | null,
  remote = false,
  client: { onReconnect: (listener: () => void) => () => void } | null = null,
): Promise<void> {
  await act(async () => {
    root.render(<ToolUsageGroup api={api} client={client} remote={remote} />);
  });
  await settle();
  await settle();
}

async function press(target: HTMLElement | null | undefined): Promise<void> {
  if (!target) {
    throw new Error('nothing to press');
  }
  await act(async () => {
    target.click();
  });
  await settle();
}

function button(
  label: string,
  scope: ParentNode = document,
): HTMLButtonElement {
  const found = [...scope.querySelectorAll('button')].find(
    (candidate) => candidate.textContent?.trim() === label,
  );
  if (!found) {
    throw new Error(`no button "${label}"`);
  }
  return found;
}

async function choose(label: string, option: string): Promise<void> {
  await press(
    document.querySelector<HTMLElement>(
      `[data-menu-trigger][aria-label="${label}"]`,
    ),
  );
  await press(
    [...document.querySelectorAll<HTMLElement>('[role="option"]')].find(
      (candidate) => candidate.textContent?.trim() === option,
    ),
  );
}

function names(scope: ParentNode): string[] {
  return [...scope.querySelectorAll('[data-slot="tool-usage-row"]')].map(
    (node) => node.querySelector('span')?.textContent ?? '',
  );
}

beforeEach(() => {
  Element.prototype.scrollIntoView = vi.fn();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  writes = [];
  window.geniro = createPreloadStub({
    getSettings: () =>
      Promise.resolve({ ...DEFAULT_SETTINGS, toolCallLogRetentionDays: 90 }),
    updateSettings: (patch) => {
      writes.push(patch);
      return Promise.resolve({ ...DEFAULT_SETTINGS, ...patch });
    },
  });
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  document.body.innerHTML = '';
});

describe('ToolUsageGroup', () => {
  it('lists the eight most called rows and counts the rest', async () => {
    await renderGroup(statsApi(async () => listOf()));
    expect(names(container)).toEqual(
      TEN_ROWS.slice(0, 8).map((item) => item.subject),
    );
    expect(
      container.querySelector('[data-slot="tool-usage-more"]')?.textContent,
    ).toBe('+2 more');
    expect(container.textContent).toContain('Oct 15, 2026');
  });

  it('reorders the rows when another column header is pressed', async () => {
    const rows = [
      row('alpha', 50, { errors: 0 }),
      row('beta', 40, { errors: 9 }),
    ];
    await renderGroup(statsApi(async () => listOf({ rows })));
    expect(names(container)).toEqual(['alpha', 'beta']);
    await press(button('Errors', container));
    expect(names(container)).toEqual(['beta', 'alpha']);
  });

  it('labels a row by its kind and shows its MCP server', async () => {
    const rows = [
      row('Bash', 5),
      row('show_ui', 4, { source: 'geniro' }),
      row('search', 3, { source: 'github' }),
      row('plan', 2, { subjectKind: 'skill' }),
    ];
    await renderGroup(statsApi(async () => listOf({ rows })));
    const text = container.textContent ?? '';
    for (const label of ['CLI tool', 'Geniro tool', 'MCP tool', 'Skill']) {
      expect(text).toContain(label);
    }
    expect(text).toContain('github');
  });

  it('opens the dialog from Show all and filters it by search and by kind', async () => {
    const rows = [
      row('Bash', 5),
      row('show_ui', 4, { source: 'geniro' }),
      row('plan', 2, { subjectKind: 'skill' }),
    ];
    await renderGroup(statsApi(async () => listOf({ rows })));
    await press(button('Show all'));
    const dialog = document.querySelector<HTMLElement>(
      '[data-slot="tool-usage-all"]',
    )!;
    expect(names(dialog)).toEqual(['Bash', 'show_ui', 'plan']);

    await choose('Kind of tool or capability', 'Skills');
    expect(names(dialog)).toEqual(['plan']);
    await choose('Kind of tool or capability', 'All kinds');

    const search = dialog.querySelector<HTMLInputElement>('input')!;
    await act(async () => {
      Object.getOwnPropertyDescriptor(
        HTMLInputElement.prototype,
        'value',
      )!.set!.call(search, 'show');
      search.dispatchEvent(new Event('input', { bubbles: true }));
    });
    expect(names(dialog)).toEqual(['show_ui']);
  });

  it('opens the dialog already on the never called subjects, with a 0 count', async () => {
    const never = row('old_tool', 0, {
      source: 'geniro',
      firstAt: null,
      lastAt: null,
    });
    await renderGroup(statsApi(async () => listOf({ neverCalled: [never] })));
    expect(container.textContent).toContain('Never called');
    await press(button('Show', container));
    const dialog = document.querySelector<HTMLElement>(
      '[data-slot="tool-usage-all"]',
    )!;
    expect(names(dialog)).toEqual(['old_tool']);
    const cells = [...dialog.querySelectorAll('tbody td')].map((cell) =>
      cell.textContent?.trim(),
    );
    expect(cells).toContain('0');
  });

  it('says so when nothing was counted yet', async () => {
    await renderGroup(statsApi(async () => listOf({ rows: [] })));
    expect(
      container.querySelector('[data-slot="tool-usage-empty"]'),
    ).not.toBeNull();
    expect(names(container)).toEqual([]);
  });

  it('shows loading while the read is pending', async () => {
    await renderGroup(
      statsApi(
        () =>
          new Promise<ToolUsageListDto>(() => {
            // never settles
          }),
      ),
    );
    expect(
      container.querySelector('[data-slot="tool-usage-loading"]'),
    ).not.toBeNull();
  });

  it('shows the error and reads again on Retry', async () => {
    const api = statsApi(async () => listOf());
    api.readToolUsage.mockRejectedValueOnce(new Error('daemon down'));
    await renderGroup(api);
    expect(
      container.querySelector('[data-slot="tool-usage-error"]'),
    ).not.toBeNull();
    await press(button('Retry', container));
    expect(api.readToolUsage).toHaveBeenCalledTimes(2);
    expect(
      container.querySelector('[data-slot="tool-usage-error"]'),
    ).toBeNull();
    expect(names(container).length).toBe(8);
  });

  it('reads again after the daemon client reconnects', async () => {
    const listeners = new Set<() => void>();
    const api = statsApi(async () => listOf());
    await renderGroup(api, false, {
      onReconnect: (listener) => {
        listeners.add(listener);
        return () => listeners.delete(listener);
      },
    });
    await act(async () => {
      listeners.forEach((listener) => listener());
    });
    await settle();
    expect(api.readToolUsage).toHaveBeenCalledTimes(2);
  });

  it("opens a row's card with the subject's split", async () => {
    const subject = row('Bash', 20, {
      subagentCalls: 5,
      errors: 4,
      refused: 1,
      avgDurationMs: 1500,
      avgResultChars: 2048,
    });
    const api = statsApi(async () => listOf({ rows: [subject] }), {
      row: subject,
      byAgent: [{ agentKind: 'claude', calls: 20, errors: 4 }],
      byOrigin: [
        { origin: 'direct', calls: 15, errors: 3 },
        { origin: 'subagent', calls: 5, errors: 1 },
      ],
      byProject: [
        { projectId: 'p1', name: 'Alpha', calls: 12, errors: 1 },
        { projectId: null, name: null, calls: 8, errors: 3 },
      ],
    });
    await renderGroup(api);
    await press(container.querySelector('[data-slot="tool-usage-row"]'));
    expect(api.readToolUsageSubject).toHaveBeenCalledWith({
      subjectKind: 'tool',
      subject: 'Bash',
      source: '',
    });
    const card = document.querySelector<HTMLElement>(
      '[data-slot="tool-card"]',
    )!;
    const text = card.textContent ?? '';
    expect(text).toContain('20 (5 sub-agent)');
    expect(text).toContain('3 (1 refused)');
    expect(text).toContain('16 ok · 3 error · 1 refused');
    expect(text).toContain('2s');
    expect(text).toContain('2,048 chars');
    expect(text).toContain('claude');
    expect(text).toContain('Alpha');
    expect(text).toContain('No project');
    expect(text).toContain('Sub-agent');
    expect(text).not.toContain('Offered in sessions');
  });

  it('hides the retention row on a paired device', async () => {
    await renderGroup(
      statsApi(async () => listOf()),
      true,
    );
    expect(
      document.querySelector(
        '[aria-label="How long to keep the detailed tool log"]',
      ),
    ).toBeNull();
    expect(container.textContent).not.toContain('Detailed tool log');
  });

  it('writes the retention setting when it changes', async () => {
    await renderGroup(statsApi(async () => listOf()));
    const trigger = document.querySelector(
      '[data-menu-trigger][aria-label="How long to keep the detailed tool log"]',
    );
    expect(trigger?.textContent).toContain('90 days');
    await choose('How long to keep the detailed tool log', 'Keep forever');
    expect(writes).toEqual([{ toolCallLogRetentionDays: null }]);
    await choose('How long to keep the detailed tool log', '1 year');
    expect(writes.at(-1)).toEqual({ toolCallLogRetentionDays: 365 });
  });
});
