import type { Meta, StoryObj } from '@storybook/react-vite';

import { DEFAULT_SETTINGS } from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { ToolUsageRow } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { ToolUsageGroup } from './tool-usage-group';

function row(
  subject: string,
  calls: number,
  extra: Partial<ToolUsageRow> = {},
): ToolUsageRow {
  return {
    subjectKind: 'tool',
    subject,
    source: '',
    calls,
    subagentCalls: Math.floor(calls / 4),
    agents: ['claude'],
    errors: Math.floor(calls / 20),
    refused: 0,
    avgDurationMs: 1200,
    avgResultChars: 3400,
    firstAt: '2026-10-02T09:00:00.000Z',
    lastAt: '2026-11-26T16:30:00.000Z',
    firstKnownAt: null,
    offeredSessions: null,
    removalEligible: false,
    ...extra,
  };
}

const ROWS: ToolUsageRow[] = [
  row('Bash', 4120),
  row('Read', 3800),
  row('Edit', 1900),
  row('show_ui', 240, { source: 'geniro', offeredSessions: 310 }),
  row('search_issues', 64, { source: 'github' }),
  row('Subagents', 51, { subjectKind: 'capability' }),
  row('review', 30, { subjectKind: 'skill' }),
  row('/compact', 22, { subjectKind: 'command' }),
  row('Grep', 18, { agents: ['claude', 'codex'] }),
  row('WebFetch', 9),
];

const LONG_NAME_ROWS: ToolUsageRow[] = [
  row(`mcp_tool_${'with_a_very_long_name_'.repeat(5)}`, 5000, {
    source: 'a-server-with-a-long-name',
  }),
  ...ROWS,
];

const stats = (rows: ToolUsageRow[], fail = false): DaemonApis['stats'] =>
  ({
    readToolUsage: () =>
      fail
        ? Promise.reject(new Error('daemon unreachable'))
        : Promise.resolve({
            countingSince: '2026-10-01T00:00:00.000Z',
            liveSince: '2026-11-01T00:00:00.000Z',
            rows,
            neverCalled: [
              row('save_plugin', 0, { source: 'geniro', firstAt: null }),
            ],
          }),
    readToolUsageSubject: (request: { subject: string }) =>
      Promise.resolve({
        row: rows.find((item) => item.subject === request.subject) ?? rows[0],
        byAgent: [{ agentKind: 'claude', calls: 100, errors: 4 }],
        byOrigin: [
          { origin: 'direct', calls: 80, errors: 3 },
          { origin: 'subagent', calls: 20, errors: 1 },
        ],
        byProject: [
          { projectId: 'p', name: 'geniro-app', calls: 90, errors: 4 },
          { projectId: null, name: null, calls: 10, errors: 0 },
        ],
      }),
  }) as unknown as DaemonApis['stats'];

const meta = {
  title: 'Settings/ToolUsageGroup',
  component: ToolUsageGroup,
  args: { api: stats(ROWS), client: null, remote: false },
  decorators: [
    (story) => {
      window.geniro = createPreloadStub({
        getSettings: () =>
          Promise.resolve({
            ...DEFAULT_SETTINGS,
            toolCallLogRetentionDays: 90,
          }),
      });
      return <div className="max-w-6xl">{story()}</div>;
    },
  ],
} satisfies Meta<typeof ToolUsageGroup>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Default: Story = {};

export const Empty: Story = { args: { api: stats([]) } };

export const LoadFailed: Story = { args: { api: stats([], true) } };

export const PairedDevice: Story = { args: { remote: true } };

export const NarrowWithLongName: Story = {
  args: { api: stats(LONG_NAME_ROWS) },
  decorators: [(story) => <div className="w-80">{story()}</div>],
};
