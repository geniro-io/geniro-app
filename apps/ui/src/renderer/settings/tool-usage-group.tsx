const TOP_ROWS = 8;
const KEEP_FOREVER = 'forever';
const HIGH_ERROR_SHARE = 0.08;

type RowKind = 'geniro' | 'cli' | 'mcp' | 'capability' | 'skill' | 'command';
type KindFilter = RowKind | 'all' | 'never';
type SortKey = 'name' | 'calls' | 'subagent' | 'last' | 'errors' | 'first';

const KIND_LABEL: Record<RowKind, string> = {
  geniro: 'Geniro tool',
  cli: 'CLI tool',
  mcp: 'MCP tool',
  capability: 'Capability',
  skill: 'Skill',
  command: 'Command',
};

const KIND_FILTERS: { value: KindFilter; label: string }[] = [
  { value: 'all', label: 'All kinds' },
  { value: 'geniro', label: 'Geniro tools' },
  { value: 'cli', label: 'CLI tools' },
  { value: 'mcp', label: 'MCP tools' },
  { value: 'capability', label: 'Capabilities' },
  { value: 'skill', label: 'Skills' },
  { value: 'command', label: 'Commands' },
  { value: 'never', label: 'Never called' },
];

const SORT_KEYS: readonly SortKey[] = [
  'name',
  'calls',
  'subagent',
  'last',
  'errors',
  'first',
];

function isSortKey(key: string): key is SortKey {
  return (SORT_KEYS as readonly string[]).includes(key);
}

const RETENTION_LABEL = (days: number | null): string => {
  if (days === null) {
    return 'Keep forever';
  }
  return days === 365 ? '1 year' : `${days} days`;
};

function kindOf(row: ToolUsageRow): RowKind {
  if (row.subjectKind !== 'tool') {
    return row.subjectKind;
  }
  if (row.source === 'geniro') {
    return 'geniro';
  }
  return row.source === '' ? 'cli' : 'mcp';
}

function keyOf(row: ToolUsageRow): string {
  return [row.subjectKind, row.source, row.subject].join('\u0000');
}

function formatDate(iso: string | null): string {
  return iso === null ? NOT_MEASURED : formatDayStamp(iso);
}

function formatWhen(iso: string | null): string {
  return iso === null ? NOT_MEASURED : formatRelativeTime(iso);
}

function formatFirstSeen(iso: string | null): string {
  return iso === null ? NOT_MEASURED : formatShortDate(iso);
}

function agentNames(
  row: ToolUsageRow,
  identities: readonly AgentIdentityCapability[],
): string {
  return row.agents
    .map((agent) => agentDisplayName(identities, agent))
    .join(' · ');
}

/** Where a row's calls come from, under its name: the CLIs, the MCP server, or Geniro itself. */
function sourceLine(
  row: ToolUsageRow,
  identities: readonly AgentIdentityCapability[],
): string {
  const agents = agentNames(row, identities);
  switch (kindOf(row)) {
    case 'geniro':
      return 'Geniro';
    case 'mcp':
      return `MCP · ${row.source}`;
    case 'capability':
      return KIND_LABEL.capability;
    case 'cli':
      return agents === '' ? KIND_LABEL.cli : agents;
    case 'skill':
    case 'command':
      return [KIND_LABEL[kindOf(row)], agents].filter(Boolean).join(' · ');
  }
}

/** Every call that ended in an error, refused ones included, split for a hover. */
function outcomeOf(row: ToolUsageRow): {
  ok: number;
  failed: number;
  refused: number;
} {
  const refused = Math.min(row.refused, row.errors);
  return {
    ok: Math.max(0, row.calls - row.errors),
    failed: row.errors - refused,
    refused,
  };
}

function outcomeText(row: ToolUsageRow): string {
  const { ok, failed, refused } = outcomeOf(row);
  return `${formatCount(ok)} ok · ${formatCount(failed)} failed · ${formatCount(refused)} refused`;
}

function errorShare(row: ToolUsageRow): number | null {
  return row.calls === 0 ? null : row.errors / row.calls;
}

function formatErrorShare(share: number): string {
  if (share > 0 && share < 0.001) {
    return '<0.1%';
  }
  return `${Math.round(share * 1000) / 10}%`;
}

function compareAt(a: string | null, b: string | null): number {
  if (a === b) {
    return 0;
  }
  if (a === null) {
    return 1;
  }
  if (b === null) {
    return -1;
  }
  return b.localeCompare(a);
}

function sortRows(
  rows: readonly ToolUsageRow[],
  sort: SortKey,
): ToolUsageRow[] {
  const compare = (a: ToolUsageRow, b: ToolUsageRow): number => {
    switch (sort) {
      case 'name':
        return a.subject.localeCompare(b.subject);
      case 'calls':
        return b.calls - a.calls;
      case 'subagent':
        return b.subagentCalls - a.subagentCalls;
      case 'errors':
        return (errorShare(b) ?? -1) - (errorShare(a) ?? -1);
      case 'last':
        return compareAt(a.lastAt, b.lastAt);
      case 'first':
        return compareAt(a.firstAt, b.firstAt);
    }
  };
  return [...rows].sort(compare);
}

function matchesFilter(row: ToolUsageRow, filter: KindFilter): boolean {
  return filter === 'all' || filter === 'never' || kindOf(row) === filter;
}

export function ToolUsageGroup({
  api,
  client,
  remote,
}: {
  api: DaemonApis['stats'] | null;
  client: ToolUsageClient | null;
  remote: boolean;
}): React.JSX.Element {
  const { data, error, reload } = useToolUsage(api, client);
  const [listFilter, setListFilter] = useState<KindFilter | null>(null);
  const [selected, setSelected] = useState<ToolUsageRow | null>(null);
  const retention = useToolCallLogRetention();

  return (
    <SettingsGroup
      icon={<Wrench />}
      title="Tools and capabilities"
      description="How often agents use each tool and Geniro feature, counted by Geniro itself."
      hint="Geniro counts every tool call, and the capabilities, skills and slash commands agents used. Use it to see what is worth keeping and what nobody calls.">
      {error !== null ? (
        <div
          data-slot="tool-usage-error"
          className="flex min-w-0 flex-wrap items-center gap-2">
          <ErrorText>{error}</ErrorText>
          <Button type="button" size="sm" variant="outline" onClick={reload}>
            Retry
          </Button>
        </div>
      ) : data === null ? (
        <span
          data-slot="tool-usage-loading"
          className="inline-flex items-center gap-1 text-sm text-muted-foreground">
          <Spinner /> Loading…
        </span>
      ) : (
        <>
          <SettingsPanel>
            <SettingsPanelRow
              label="Counted since"
              hint={
                data.liveSince === null
                  ? 'Counters only add up; tools start with what the call log already holds.'
                  : `Counters only add up; tools start with what the call log already holds. Capabilities, sub-agent calls and offers are counted from ${formatDate(data.liveSince)}.`
              }>
              <span
                data-slot="tool-usage-since"
                className="text-sm tabular-nums">
                {formatDate(data.countingSince)} ·{' '}
                {formatCount(data.rows.length + data.neverCalled.length)} tools
                and capabilities
              </span>
            </SettingsPanelRow>
            <SettingsPanelRow
              label="Never called"
              hint="Geniro tools and capabilities with no call since counting began.">
              <span className="text-sm tabular-nums">
                {formatCount(data.neverCalled.length)}
              </span>
              <Button
                type="button"
                size="sm"
                variant="outline"
                disabled={data.neverCalled.length === 0}
                onClick={() => setListFilter('never')}>
                Show
              </Button>
            </SettingsPanelRow>
          </SettingsPanel>
          {data.rows.length === 0 ? (
            <EmptyState data-slot="tool-usage-empty">
              No tool call has been counted yet.
            </EmptyState>
          ) : (
            <div className="flex min-w-0 flex-col gap-2">
              <UsageTable
                rows={data.rows.slice(0, TOP_ROWS)}
                ariaLabel="Most called tools and capabilities"
                emptyLabel="Nothing was called."
                onOpen={setSelected}
              />
              <div className="flex min-w-0 items-center justify-between gap-2">
                <span
                  data-slot="tool-usage-more"
                  className="text-xs text-muted-foreground">
                  {data.rows.length > TOP_ROWS
                    ? `+${formatCount(data.rows.length - TOP_ROWS)} more`
                    : null}
                </span>
                <Button
                  type="button"
                  size="sm"
                  variant="outline"
                  onClick={() => setListFilter('all')}>
                  Show all {formatCount(data.rows.length)}
                </Button>
              </div>
            </div>
          )}
        </>
      )}
      <SettingsPanel>
        {remote ? null : (
          <SettingsPanelRow
            label="Detailed tool log"
            hint="One row per call, used by team stats and thread failures. Rows older than this are deleted for good, so the tool tables on the Stats page and in team stats cover only this period.">
            <Select
              className="w-40"
              aria-label="How long to keep the detailed tool log"
              placeholder="Loading…"
              value={
                retention.days === undefined
                  ? null
                  : retention.days === null
                    ? KEEP_FOREVER
                    : String(retention.days)
              }
              groups={[
                {
                  items: TOOL_CALL_LOG_RETENTION_CHOICES.map((days) => ({
                    value: days === null ? KEEP_FOREVER : String(days),
                    label: RETENTION_LABEL(days),
                  })),
                },
              ]}
              onValueChange={(next) =>
                retention.setDays(next === KEEP_FOREVER ? null : Number(next))
              }
            />
          </SettingsPanelRow>
        )}
        <SettingsPanelRow
          label="Counters"
          hint="What the table and the analysis read.">
          <span data-slot="tool-usage-counters" className="text-sm">
            Kept for good · one row per tool
          </span>
        </SettingsPanelRow>
      </SettingsPanel>
      {listFilter !== null && data !== null ? (
        <ShowAllDialog
          rows={data.rows}
          neverCalled={data.neverCalled}
          initialFilter={listFilter}
          onOpen={setSelected}
          onClose={() => setListFilter(null)}
        />
      ) : null}
      {selected === null ? null : (
        <ToolCardDialog
          api={api}
          row={selected}
          onClose={() => setSelected(null)}
        />
      )}
    </SettingsGroup>
  );
}

function UsageTable({
  rows,
  ariaLabel,
  emptyLabel,
  onOpen,
}: {
  rows: readonly ToolUsageRow[];
  ariaLabel: string;
  emptyLabel: string;
  onOpen: (row: ToolUsageRow) => void;
}): React.JSX.Element {
  const [sort, setSort] = useState<SortKey>('calls');
  const identities = useContext(AgentIdentityContext);
  const columns: FigureColumn<ToolUsageRow>[] = [
    {
      header: 'Tool or capability',
      sortKey: 'name',
      fill: true,
      truncate: true,
      title: (row) => `${row.subject} · ${sourceLine(row, identities)}`,
      cell: (row) => (
        <button
          type="button"
          data-slot="tool-usage-row"
          aria-label={`Open the card of ${row.subject}`}
          onClick={() => onOpen(row)}
          className="group flex w-full min-w-0 flex-col rounded-sm text-left outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50">
          <span className="truncate font-mono text-sm group-hover:underline">
            {row.subject}
          </span>
          <span className="truncate text-xs text-muted-foreground">
            {sourceLine(row, identities)}
          </span>
        </button>
      ),
    },
    {
      header: 'Calls',
      sortKey: 'calls',
      align: 'end',
      cell: (row) => formatCount(row.calls),
    },
    {
      header: 'Sub-agent',
      sortKey: 'subagent',
      align: 'end',
      hideBelow: '32rem',
      cell: (row) => formatCount(row.subagentCalls),
    },
    {
      header: 'Last call',
      sortKey: 'last',
      align: 'end',
      hideBelow: '26rem',
      title: (row) =>
        row.lastAt === null ? undefined : formatDateTime(row.lastAt),
      cell: (row) => formatWhen(row.lastAt),
    },
    {
      header: 'Errors',
      sortKey: 'errors',
      align: 'end',
      title: (row) => (row.calls === 0 ? undefined : outcomeText(row)),
      cell: (row) => {
        const share = errorShare(row);
        return share === null ? (
          NOT_MEASURED
        ) : (
          <span
            data-slot="tool-usage-errors"
            className={cn(share >= HIGH_ERROR_SHARE && 'text-destructive')}>
            {formatErrorShare(share)}
          </span>
        );
      },
    },
    {
      header: 'First seen',
      sortKey: 'first',
      align: 'end',
      hideBelow: '26rem',
      title: (row) =>
        row.firstAt === null ? undefined : formatDate(row.firstAt),
      cell: (row) => formatFirstSeen(row.firstAt),
    },
  ];
  return (
    <FigureTable
      columns={columns}
      rows={sortRows(rows, sort)}
      rowKey={keyOf}
      emptyLabel={emptyLabel}
      ariaLabel={ariaLabel}
      sort={{
        key: sort,
        onSort: (key) => setSort(isSortKey(key) ? key : 'calls'),
      }}
    />
  );
}

function ShowAllDialog({
  rows,
  neverCalled,
  initialFilter,
  onOpen,
  onClose,
}: {
  rows: readonly ToolUsageRow[];
  neverCalled: readonly ToolUsageRow[];
  initialFilter: KindFilter;
  onOpen: (row: ToolUsageRow) => void;
  onClose: () => void;
}): React.JSX.Element {
  const [filter, setFilter] = useState<KindFilter>(initialFilter);
  const [query, setQuery] = useState('');
  const identities = useContext(AgentIdentityContext);
  const needle = query.trim().toLowerCase();
  const listed = (filter === 'never' ? neverCalled : rows)
    .filter((row) => matchesFilter(row, filter))
    .filter(
      (row) =>
        needle === '' ||
        `${row.subject} ${sourceLine(row, identities)}`
          .toLowerCase()
          .includes(needle),
    );
  return (
    <Dialog
      open
      onClose={onClose}
      title="All tools and capabilities"
      className="max-w-4xl">
      <div data-slot="tool-usage-all" className="flex min-w-0 flex-col gap-3">
        <div className="flex min-w-0 flex-wrap items-center gap-2">
          <Input
            type="search"
            aria-label="Search tools and capabilities"
            placeholder="Search"
            className="max-w-xs"
            value={query}
            onChange={(event) => setQuery(event.target.value)}
          />
          <Select
            variant="ghost"
            aria-label="Kind of tool or capability"
            value={filter}
            groups={[{ items: KIND_FILTERS }]}
            onValueChange={(next) =>
              setFilter(
                KIND_FILTERS.find((item) => item.value === next)?.value ??
                  'all',
              )
            }
          />
        </div>
        <UsageTable
          rows={listed}
          ariaLabel="All tools and capabilities"
          emptyLabel="Nothing matches."
          onOpen={onOpen}
        />
      </div>
    </Dialog>
  );
}

function Figure({
  label,
  children,
}: {
  label: string;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <div className="flex min-w-0 flex-col gap-0.5">
      <dt className="text-xs text-muted-foreground">{label}</dt>
      <dd className="m-0 text-sm tabular-nums">{children}</dd>
    </div>
  );
}

function SplitList({
  title,
  items,
}: {
  title: string;
  items: { key: string; label: string; calls: number; errors: number }[];
}): React.JSX.Element {
  return (
    <section className="flex min-w-0 flex-col gap-1">
      <h3 className="text-xs font-medium text-muted-foreground">{title}</h3>
      <ul className="m-0 flex list-none flex-col divide-y divide-border p-0 text-sm">
        {items.map((item) => (
          <li
            key={item.key}
            className="flex min-w-0 items-baseline justify-between gap-3 py-1">
            <span className="min-w-0 truncate">{item.label}</span>
            <span className="shrink-0 text-xs text-muted-foreground tabular-nums">
              {formatCount(item.calls)} calls · {formatCount(item.errors)}{' '}
              errors
            </span>
          </li>
        ))}
      </ul>
    </section>
  );
}

function ToolCardDialog({
  api,
  row: listed,
  onClose,
}: {
  api: DaemonApis['stats'] | null;
  row: ToolUsageRow;
  onClose: () => void;
}): React.JSX.Element {
  const { data, error, retry } = useToolUsageSubject(api, listed);
  const identities = useContext(AgentIdentityContext);
  const row = data?.row ?? listed;
  const { refused } = outcomeOf(row);
  const heading = [
    KIND_LABEL[kindOf(row)],
    kindOf(row) === 'mcp' ? row.source : '',
    agentNames(row, identities),
  ].filter(Boolean);
  return (
    <Dialog open onClose={onClose} title={row.subject} className="max-w-2xl">
      <div data-slot="tool-card" className="flex min-w-0 flex-col gap-4">
        <p
          data-slot="tool-card-kind"
          className="m-0 min-w-0 truncate text-sm text-muted-foreground">
          {heading.join(' · ')}
        </p>
        <dl className="m-0 grid grid-cols-2 gap-x-4 gap-y-3 sm:grid-cols-3">
          <Figure label="Calls">
            {formatCount(row.calls)} ({formatCount(row.subagentCalls)}{' '}
            sub-agent)
          </Figure>
          <Figure label="Errors">
            {formatCount(row.errors)} ({formatCount(refused)} refused)
          </Figure>
          <Figure label="Last call">{formatWhen(row.lastAt)}</Figure>
          <Figure label="First seen">{formatDate(row.firstAt)}</Figure>
          {row.offeredSessions === null ? null : (
            <Figure label="Offered in sessions">
              {formatCount(row.offeredSessions)}
            </Figure>
          )}
          <Figure label="Avg time">
            {row.avgDurationMs === null
              ? NOT_MEASURED
              : formatDuration(row.avgDurationMs)}
          </Figure>
          <Figure label="Avg result size">
            {row.avgResultChars === null
              ? NOT_MEASURED
              : `${formatCount(Math.round(row.avgResultChars))} chars`}
          </Figure>
          <Figure label="Outcome">{outcomeText(row)}</Figure>
        </dl>
        {error !== null ? (
          <div className="flex min-w-0 flex-wrap items-center gap-2">
            <ErrorText>{error}</ErrorText>
            <Button type="button" size="sm" variant="outline" onClick={retry}>
              Retry
            </Button>
          </div>
        ) : data === null ? (
          <span className="inline-flex items-center gap-1 text-sm text-muted-foreground">
            <Spinner /> Loading…
          </span>
        ) : (
          <>
            <SplitList
              title="Who called"
              items={data.byOrigin.map((item) => ({
                key: item.origin,
                label: item.origin === 'direct' ? 'Direct' : 'Sub-agent',
                calls: item.calls,
                errors: item.errors,
              }))}
            />
            <SplitList
              title="By CLI"
              items={data.byAgent.map((item) => ({
                key: item.agentKind ?? '',
                label:
                  item.agentKind === null
                    ? 'Unknown'
                    : agentDisplayName(identities, item.agentKind),
                calls: item.calls,
                errors: item.errors,
              }))}
            />
            <SplitList
              title="Projects"
              items={data.byProject.map((item) => ({
                key: item.projectId ?? '',
                label: item.name ?? 'No project',
                calls: item.calls,
                errors: item.errors,
              }))}
            />
          </>
        )}
      </div>
    </Dialog>
  );
}
