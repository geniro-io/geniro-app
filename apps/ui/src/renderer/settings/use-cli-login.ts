import { useCallback, useEffect, useRef, useState } from 'react';

import type { CliKind } from '../../shared/contracts';
import type { AgentKind, LoginSession } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';

/** How often to re-ask where a sign-in has got to. */
const POLL_MS = 1_200;

/**
 * One in-flight sign-in, as the Settings card needs to render it.
 *
 * `kind` is here so the caller can tell WHICH card owns the panel: only one
 * sign-in runs at a time, deliberately — two concurrent browser challenges for
 * two CLIs would be indistinguishable in the browser, and the second would look
 * like the first had failed.
 */
export interface CliLoginState {
  kind: CliKind;
  session: LoginSession;
}

export interface CliLoginController {
  login: CliLoginState | null;
  /** Start one. Resolves when the daemon has answered, not when it finishes. */
  start: (kind: CliKind) => Promise<void>;
  submitCode: (code: string) => Promise<void>;
  cancel: () => Promise<void>;
  /** Dismiss a finished panel without cancelling anything. */
  dismiss: () => void;
  error: string | null;
}

/**
 * Drives a sign-in the DAEMON is running, so no terminal window opens.
 *
 * The polling shape is deliberate over a WS room. This is one short-lived
 * question asked by one open screen, and a room would mean a gateway, a
 * subscription and a reconnect policy for a flow that lasts under a minute —
 * whereas a poll that stops the moment the status is terminal cannot leak a
 * listener. It also degrades correctly: a missed tick costs a second, not the
 * flow.
 *
 * `onSettled` fires once when the CLI exits, whatever the outcome. That is where
 * the caller re-probes detection — the daemon's `succeeded` means only "the
 * command completed cleanly", and whether the user is actually signed in is a
 * question only the CLI's own status command answers.
 */
export function useCliLogin(
  apis: DaemonApis | null,
  onSettled: () => void,
): CliLoginController {
  const [login, setLogin] = useState<CliLoginState | null>(null);
  const [error, setError] = useState<string | null>(null);
  // Read inside the interval, so a re-rendered caller passing a fresh closure
  // does not restart the poll — and the poll always calls the current one.
  const settledRef = useRef(onSettled);
  settledRef.current = onSettled;

  const isOver = (session: LoginSession): boolean =>
    session.status === 'succeeded' ||
    session.status === 'failed' ||
    session.status === 'cancelled';

  useEffect(() => {
    if (!apis || login === null || isOver(login.session)) {
      return;
    }
    const id = login.session.id;
    const kind = login.kind;
    let stopped = false;
    const timer = setInterval(() => {
      void apis.cliAuth
        .getCliLogin({ id })
        .then((session) => {
          if (stopped) {
            return;
          }
          setLogin({ kind, session });
          if (isOver(session)) {
            settledRef.current();
          }
        })
        .catch((err: unknown) => {
          if (!stopped) {
            setError(String(err));
          }
        });
    }, POLL_MS);
    return () => {
      stopped = true;
      clearInterval(timer);
    };
    // Keyed on the sign-in's IDENTITY and whether it is over — not on the whole
    // session. Re-keying on every field would tear down and rebuild the interval
    // on each progress line, which is how a poll ends up never firing: each new
    // interval starts its wait from zero.
  }, [apis, login?.session.id, login === null || isOver(login.session)]);

  const start = useCallback(
    async (kind: CliKind): Promise<void> => {
      if (!apis) {
        return;
      }
      setError(null);
      try {
        const session = await apis.cliAuth.startCliLogin({
          agent: kind as AgentKind,
        });
        setLogin({ kind, session });
        if (isOver(session)) {
          settledRef.current();
        }
      } catch (err) {
        setError(String(err));
      }
    },
    [apis],
  );

  const submitCode = useCallback(
    async (code: string): Promise<void> => {
      if (!apis || login === null) {
        return;
      }
      setError(null);
      try {
        const session = await apis.cliAuth.submitCliLoginCode({
          id: login.session.id,
          loginCodeBodyDto: { code },
        });
        setLogin({ kind: login.kind, session });
      } catch (err) {
        setError(String(err));
      }
    },
    [apis, login],
  );

  const cancel = useCallback(async (): Promise<void> => {
    if (!apis || login === null) {
      return;
    }
    try {
      // The panel closes on the CANCEL answer rather than optimistically: until
      // the daemon has reaped the group, the CLI may still complete, and a panel
      // that vanished first would leave the user with a sign-in they cannot see.
      const session = await apis.cliAuth.cancelCliLogin({
        id: login.session.id,
      });
      setLogin({ kind: login.kind, session });
      settledRef.current();
    } catch (err) {
      setError(String(err));
    }
  }, [apis, login]);

  const dismiss = useCallback((): void => {
    setLogin(null);
    setError(null);
  }, []);

  return { login, start, submitCode, cancel, dismiss, error };
}
