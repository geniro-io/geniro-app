import { useEffect, useRef, useState } from 'react';

import type { MemoryTriageConfig } from '../../shared/contracts';
import type {
  MemoriesApi,
  MemoryFinding,
  MemoryPair,
  MemoryReviewPairsDto,
} from '../autogenerated';
import type { MemoryCleanupNotice } from '../components/memory-cleanup-dialog';
import { useLatestCallback } from '../components/use-latest-callback';
import { describeDaemonError, MEMORY_TRIAGE_TIMEOUT_MS } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

/** TWIN: `MEMORY_CHECK_PAIRS_MAX` in `apps/daemon/src/v1/memory/memory.types.ts`. */
export const CHECK_BATCH = 20;
const REFRESH_DELAY_MS = 250;

export type CheckClient = Pick<
  MemoriesApi,
  | 'listMemoryReviewPairs'
  | 'checkMemoryReviewPairs'
  | 'listMemoryFindings'
  | 'dismissMemoryFinding'
  | 'mergeMemories'
  | 'forgetMemoryBatch'
>;

/** The text a merge saves, as the user edited it. */
export interface MemoryMergeText {
  title: string;
  body: string;
}

function choiceSettings(choice: MemoryTriageConfig) {
  return {
    agentKind: choice.agent,
    ...(choice.model === null ? {} : { model: choice.model }),
    ...(choice.effort === null ? {} : { effort: choice.effort }),
    ...(choice.contextWindow === null
      ? {}
      : { contextWindow: choice.contextWindow }),
    ...(Object.keys(choice.modelParameters).length === 0
      ? {}
      : { modelParameters: choice.modelParameters }),
    ...(choice.configDir === null ? {} : { configDir: choice.configDir }),
  };
}

/**
 * The cleanup's check for duplicates and contradictions: the stored findings,
 * the pairs still to check and what checking them would take, and a queue
 * that asks the chosen CLI one batch at a time. Stop ends the queue; the batch
 * already asked still finishes, and is billed. Every decision on a finding is
 * a press of the user's, and a forget or a merge leaves an Undo.
 */
export function useMemoryCheck(
  api: CheckClient | null,
  client: Pick<DaemonClient, 'onMemoryChanged'> | null,
  {
    open,
    active,
    remote,
    choice,
    onNotice,
  }: {
    /** The cleanup dialog is open: findings are read. */
    open: boolean;
    /** Its Duplicates & contradictions tab is shown: pairs are looked for. */
    active: boolean;
    remote: boolean;
    choice: MemoryTriageConfig | null;
    onNotice: (notice: MemoryCleanupNotice) => void;
  },
) {
  const [findings, setFindings] = useState<MemoryFinding[]>([]);
  const [pairs, setPairs] = useState<MemoryReviewPairsDto | null>(null);
  const [pairsLoading, setPairsLoading] = useState(false);
  const [running, setRunning] = useState(false);
  const [stopping, setStopping] = useState(false);
  const [checked, setChecked] = useState(0);
  const [queued, setQueued] = useState(0);
  const [error, setError] = useState<string | null>(null);
  const [failed, setFailed] = useState(false);
  const [busyId, setBusyId] = useState<string | null>(null);
  const [later, setLater] = useState<ReadonlySet<string>>(new Set());
  const stopRef = useRef(false);
  const runningRef = useRef(false);
  const pairsGeneration = useRef(0);

  const readFindings = useLatestCallback(() => {
    if (api === null || !open) {
      return;
    }
    void api
      .listMemoryFindings()
      .then(({ findings: stored }) => setFindings(stored))
      .catch((err: unknown) => setError(describeDaemonError(err)));
  }, [api, open]);

  const priceAgent = choice?.agent ?? null;
  const priceModel = choice?.model ?? null;
  const readPairs = useLatestCallback(() => {
    if (api === null || !open || !active || remote || runningRef.current) {
      return;
    }
    const mine = ++pairsGeneration.current;
    setPairsLoading(true);
    void api
      .listMemoryReviewPairs({
        ...(priceAgent === null ? {} : { agentKind: priceAgent }),
        ...(priceModel === null ? {} : { model: priceModel }),
      })
      .then((listed) => {
        if (mine === pairsGeneration.current) {
          setPairs(listed);
        }
      })
      .catch((err: unknown) => {
        if (mine === pairsGeneration.current) {
          setError(describeDaemonError(err));
        }
      })
      .finally(() => {
        if (mine === pairsGeneration.current) {
          setPairsLoading(false);
        }
      });
  }, [api, open, active, remote, priceAgent, priceModel]);

  useEffect(() => {
    readFindings();
  }, [readFindings]);

  useEffect(() => {
    readPairs();
  }, [readPairs]);

  useEffect(() => {
    if (client === null) {
      return;
    }
    let timer: ReturnType<typeof setTimeout> | null = null;
    const off = client.onMemoryChanged(() => {
      if (timer !== null) {
        clearTimeout(timer);
      }
      timer = setTimeout(readFindings, REFRESH_DELAY_MS);
    });
    return () => {
      off();
      if (timer !== null) {
        clearTimeout(timer);
      }
    };
  }, [client, readFindings]);

  const start = useLatestCallback(() => {
    if (
      api === null ||
      choice === null ||
      remote ||
      runningRef.current ||
      pairs === null ||
      pairs.pairs.length === 0
    ) {
      return;
    }
    const queue: MemoryPair[][] = [];
    for (let at = 0; at < pairs.pairs.length; at += CHECK_BATCH) {
      queue.push(pairs.pairs.slice(at, at + CHECK_BATCH));
    }
    const settings = choiceSettings(choice);
    runningRef.current = true;
    stopRef.current = false;
    setRunning(true);
    setStopping(false);
    setFailed(false);
    setError(null);
    setChecked(0);
    setQueued(pairs.pairs.length);
    void (async () => {
      try {
        for (const batch of queue) {
          if (stopRef.current) {
            break;
          }
          const result = await api.checkMemoryReviewPairs(
            {
              memoryReviewCheckRequestDto: { ...settings, pairs: batch },
            },
            { signal: AbortSignal.timeout(MEMORY_TRIAGE_TIMEOUT_MS) },
          );
          setChecked((count) => count + batch.length);
          if (result.findings.length > 0) {
            setFindings((current) => {
              const landed = new Set(result.findings.map((found) => found.id));
              return [
                ...result.findings,
                ...current.filter((found) => !landed.has(found.id)),
              ];
            });
          }
        }
      } catch (err: unknown) {
        setFailed(true);
        setError(describeDaemonError(err));
      } finally {
        runningRef.current = false;
        setRunning(false);
        setStopping(false);
        readPairs();
        readFindings();
      }
    })();
  }, [api, choice, remote, pairs, readPairs, readFindings]);

  const stop = (): void => {
    if (runningRef.current) {
      stopRef.current = true;
      setStopping(true);
    }
  };

  const decide = (
    finding: MemoryFinding,
    run: () => Promise<MemoryCleanupNotice | null>,
  ): Promise<string | null> => {
    setBusyId(finding.id);
    return run()
      .then((notice) => {
        if (notice !== null) {
          onNotice(notice);
        }
        return null;
      })
      .catch((err: unknown) => describeDaemonError(err))
      .finally(() => {
        setBusyId(null);
        readFindings();
      });
  };

  const keepOne = (finding: MemoryFinding, side: 'a' | 'b'): void => {
    if (api === null) {
      return;
    }
    const kept = side === 'a' ? finding.a : finding.b;
    const dropped = side === 'a' ? finding.b : finding.a;
    void decide(finding, async () => {
      const result = await api.forgetMemoryBatch({
        forgetMemoryBatchDto: { ids: [dropped.id] },
      });
      return {
        text:
          result.forgotten === 0
            ? `${dropped.handle} changed meanwhile and stayed as it was.`
            : `Kept ${kept.handle} and forgot ${dropped.handle}.`,
        batchId: result.batchId,
      };
    }).then((failure) => {
      if (failure !== null) {
        setError(failure);
      }
    });
  };

  const merge = (
    finding: MemoryFinding,
    text: MemoryMergeText,
  ): Promise<string | null> => {
    if (api === null) {
      return Promise.resolve(null);
    }
    return decide(finding, async () => {
      const result = await api.mergeMemories({
        mergeMemoriesDto: {
          sourceIds: [finding.a.id, finding.b.id],
          title: text.title,
          body: text.body,
          type: finding.a.type,
          projectId: finding.a.projectId,
          teamSlug: finding.a.teamSlug,
        },
      });
      return {
        text: `Saved ${result.entry.handle} and forgot ${result.forgotten.join(' and ')}.`,
        batchId: result.batchId,
      };
    });
  };

  const bothTrue = (finding: MemoryFinding): void => {
    if (api === null) {
      return;
    }
    setBusyId(finding.id);
    void api
      .dismissMemoryFinding({ findingId: finding.id })
      .then(({ findings: stored }) => setFindings(stored))
      .catch((err: unknown) => setError(describeDaemonError(err)))
      .finally(() => setBusyId(null));
  };

  const decideLater = (finding: MemoryFinding): void => {
    setLater((before) => new Set([...before, finding.id]));
  };

  const showLater = (): void => setLater(new Set());

  const shown = findings.filter((found) => !later.has(found.id));

  return {
    findings: shown,
    total: findings.length,
    setAside: findings.length - shown.length,
    pairs,
    pairsLoading,
    running,
    stopping,
    checked,
    queued,
    error,
    failed,
    busyId,
    start,
    stop,
    keepOne,
    merge,
    bothTrue,
    decideLater,
    showLater,
  };
}

export type MemoryCheck = ReturnType<typeof useMemoryCheck>;
