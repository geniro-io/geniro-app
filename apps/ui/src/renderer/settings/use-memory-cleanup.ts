import { useEffect, useRef, useState } from 'react';

import type {
  ListMemoryReviewTypeEnum,
  MemoriesApi,
  MemoriesApiListMemoryReviewRequest,
  MemoryEntry,
  MemoryForgetBatch,
  MemoryReviewRow,
  MemoryReviewSummaryDto,
} from '../autogenerated';
import type {
  MemoryCleanupFilters,
  MemoryCleanupNotice,
  MemoryCleanupTab,
} from '../components/memory-cleanup-dialog';
import { teamSlugOfScope } from '../components/memory-form';
import { useLatestCallback } from '../components/use-latest-callback';
import { describeDaemonError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import type { AutoForgetFigure } from './memory-auto-forget';

export type CleanupClient = Pick<
  MemoriesApi,
  | 'memoryReviewSummary'
  | 'listMemoryReview'
  | 'listMemoryReviewIds'
  | 'forgetMemoryBatch'
  | 'listMemoryBatches'
  | 'restoreMemoryBatch'
  | 'keepMemory'
  | 'unkeepMemory'
  | 'updateMemory'
  | 'purgeMemory'
>;

/** TWIN: `MEMORY_REVIEW_MIN_AGE_DAYS` in `apps/daemon/src/v1/memory/memory.types.ts`. */
export const CLEANUP_MIN_AGE_DAYS = 14;
const CLEANUP_PAGE = 30;
/** TWIN: `MEMORY_REVIEW_LIMIT_MAX` in `apps/daemon/src/v1/memory/memory.types.ts`. */
const CLEANUP_PAGE_MAX = 100;
const REFRESH_DELAY_MS = 250;

export const DEFAULT_CLEANUP_FILTERS: MemoryCleanupFilters = {
  sort: 'leastUsed',
  minAgeDays: CLEANUP_MIN_AGE_DAYS,
  scope: 'all',
  type: 'any',
  warnings: 'any',
  referenceGone: false,
};

const TYPES: readonly ListMemoryReviewTypeEnum[] = [
  'user',
  'feedback',
  'project',
  'reference',
];

export function entries(n: number): string {
  return `${n.toLocaleString('en-US')} ${n === 1 ? 'entry' : 'entries'}`;
}

function figureOf(summary: MemoryReviewSummaryDto): AutoForgetFigure | null {
  return summary.autoForget === null
    ? null
    : {
        forget: summary.autoForget.forget,
        warned: summary.autoForget.warned,
        provisional: summary.counting,
      };
}

/** The review query a tab and its filters ask the daemon for. */
export function reviewRequest(
  tab: Exclude<MemoryCleanupTab, 'checks'>,
  filters: MemoryCleanupFilters,
): MemoriesApiListMemoryReviewRequest {
  if (tab !== 'cold') {
    return { tab };
  }
  const teamSlug = teamSlugOfScope(filters.scope);
  const type = TYPES.find((candidate) => candidate === filters.type);
  return {
    tab,
    sort: filters.sort,
    minAgeDays: filters.minAgeDays,
    warnings: filters.warnings,
    ...(filters.referenceGone ? { referenceGone: 'true' } : {}),
    ...(type === undefined ? {} : { type }),
    ...(filters.scope === 'all'
      ? {}
      : filters.scope === 'global'
        ? { scope: 'global' }
        : teamSlug !== null
          ? { scope: 'team', teamSlug }
          : { scope: 'project', projectId: filters.scope }),
  };
}

/**
 * The Clean up panel's figures and the review dialog's state: which tab and
 * filters, the rows loaded so far, what is ticked, and every press — keep,
 * forget a batch, undo, restore, delete for good. Figures and lists are
 * refreshed whenever the memory changes, wherever the change was made; with
 * an armed `autoForgetDays` the figures carry what that sweep would take now.
 */
export function useMemoryCleanup(
  api: CleanupClient | null,
  client: Pick<DaemonClient, 'onMemoryChanged'> | null,
  autoForgetDays: number | null = null,
) {
  const [summary, setSummary] = useState<MemoryReviewSummaryDto | null>(null);
  const [open, setOpen] = useState(false);
  const [tab, setTabState] = useState<MemoryCleanupTab>('cold');
  const [filters, setFiltersState] = useState(DEFAULT_CLEANUP_FILTERS);
  const [rows, setRows] = useState<MemoryReviewRow[]>([]);
  const [total, setTotal] = useState(0);
  const [younger, setYounger] = useState<number | null>(null);
  const [next, setNext] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [selected, setSelected] = useState<ReadonlySet<string>>(new Set());
  const [warned, setWarned] = useState<ReadonlySet<string>>(new Set());
  const [tickSkipped, setTickSkipped] = useState<number | null>(null);
  const [ticking, setTicking] = useState(false);
  const [batches, setBatches] = useState<MemoryForgetBatch[]>([]);
  const [notice, setNotice] = useState<MemoryCleanupNotice | null>(null);
  const [busyId, setBusyId] = useState<string | null>(null);
  const generation = useRef(0);
  const picks = useRef(0);
  const depth = useRef(0);

  const readSummary = useLatestCallback(() => {
    if (api === null) {
      return;
    }
    void api
      .memoryReviewSummary(autoForgetDays === null ? {} : { autoForgetDays })
      .then(setSummary)
      .catch(() => undefined);
  }, [api, autoForgetDays]);

  const readPage = useLatestCallback(() => {
    if (api === null || !open || tab === 'checks') {
      return;
    }
    const listed = tab;
    const mine = ++generation.current;
    const limit = Math.min(
      Math.max(depth.current, CLEANUP_PAGE),
      CLEANUP_PAGE_MAX,
    );
    setLoading(true);
    void Promise.all([
      api.listMemoryReview({ ...reviewRequest(listed, filters), limit }),
      listed === 'forgotten' ? api.listMemoryBatches() : Promise.resolve(null),
    ])
      .then(([page, recent]) => {
        if (mine !== generation.current) {
          return;
        }
        setRows(page.rows);
        depth.current = page.rows.length;
        setTotal(page.total);
        setYounger(page.younger);
        setNext(page.next);
        if (recent !== null) {
          setBatches(recent.batches);
        }
        setError(null);
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setError(describeDaemonError(err));
        }
      })
      .finally(() => {
        if (mine === generation.current) {
          setLoading(false);
        }
      });
  }, [api, open, tab, filters]);

  const refresh = useLatestCallback(() => {
    readSummary();
    readPage();
  }, [readSummary, readPage]);

  useEffect(() => {
    readSummary();
  }, [readSummary]);

  useEffect(() => {
    depth.current = 0;
    readPage();
  }, [readPage]);

  useEffect(() => {
    if (client === null) {
      return;
    }
    let timer: ReturnType<typeof setTimeout> | null = null;
    const off = client.onMemoryChanged(() => {
      if (timer !== null) {
        clearTimeout(timer);
      }
      timer = setTimeout(refresh, REFRESH_DELAY_MS);
    });
    return () => {
      off();
      if (timer !== null) {
        clearTimeout(timer);
      }
    };
  }, [client, refresh]);

  const clearPicks = (): void => {
    picks.current += 1;
    setSelected(new Set());
    setWarned(new Set());
    setTickSkipped(null);
  };

  const setTab = (nextTab: MemoryCleanupTab): void => {
    if (nextTab === tab) {
      return;
    }
    setTabState(nextTab);
    setNotice(null);
    setRows([]);
    clearPicks();
  };

  const setFilters = (nextFilters: MemoryCleanupFilters): void => {
    setFiltersState(nextFilters);
    setRows([]);
    clearPicks();
  };

  const openDialog = (): void => {
    setOpen(true);
    setNotice(null);
  };

  const closeDialog = (): void => {
    setOpen(false);
    clearPicks();
  };

  const loadMore = (): void => {
    if (api === null || next === null || tab === 'checks') {
      return;
    }
    const mine = generation.current;
    setLoading(true);
    void api
      .listMemoryReview({
        ...reviewRequest(tab, filters),
        limit: CLEANUP_PAGE,
        cursor: next,
      })
      .then((page) => {
        if (mine !== generation.current) {
          return;
        }
        setRows((all) => {
          const more = [...all, ...page.rows];
          depth.current = more.length;
          return more;
        });
        setTotal(page.total);
        setNext(page.next);
      })
      .catch((err: unknown) => setError(describeDaemonError(err)))
      .finally(() => setLoading(false));
  };

  const toggle = (row: MemoryReviewRow): void => {
    const id = row.entry.id;
    const on = !selected.has(id);
    setSelected((before) => {
      const after = new Set(before);
      if (on) {
        after.add(id);
      } else {
        after.delete(id);
      }
      return after;
    });
    setWarned((before) => {
      const after = new Set(before);
      if (on && row.warning !== null) {
        after.add(id);
      } else {
        after.delete(id);
      }
      return after;
    });
  };

  const tickShown = (): void => {
    if (api === null || tab === 'checks') {
      return;
    }
    setTicking(true);
    const mine = picks.current;
    void api
      .listMemoryReviewIds(reviewRequest(tab, filters))
      .then(({ ids, warnedSkipped }) => {
        if (mine !== picks.current) {
          return;
        }
        setSelected((before) => new Set([...before, ...ids]));
        setTickSkipped(warnedSkipped);
      })
      .catch((err: unknown) => setError(describeDaemonError(err)))
      .finally(() => setTicking(false));
  };

  const forget = async (ids: readonly string[]): Promise<void> => {
    if (api === null || ids.length === 0) {
      return;
    }
    const result = await api.forgetMemoryBatch({
      forgetMemoryBatchDto: { ids: [...ids] },
    });
    const skipped =
      result.skipped.length === 0
        ? ''
        : ` ${entries(result.skipped.length)} changed meanwhile and stayed as ${result.skipped.length === 1 ? 'it was' : 'they were'}.`;
    setNotice({
      text: `Forgot ${entries(result.forgotten)}.${skipped}`,
      batchId: result.batchId,
    });
    setSelected((before) => {
      const after = new Set(before);
      for (const id of ids) {
        after.delete(id);
      }
      return after;
    });
    setWarned((before) => {
      const after = new Set(before);
      for (const id of ids) {
        after.delete(id);
      }
      return after;
    });
    refresh();
  };

  const undo = (batchId: string): void => {
    if (api === null) {
      return;
    }
    void api
      .restoreMemoryBatch({ batchId })
      .then(({ restored }) =>
        setNotice({
          text:
            restored === 0
              ? 'Nothing to restore: every entry of that cleanup was changed since.'
              : `Restored ${entries(restored)}. Each is back as it was.`,
          batchId: null,
        }),
      )
      .catch((err: unknown) => setError(describeDaemonError(err)))
      .finally(refresh);
  };

  const act = (
    entry: MemoryEntry,
    run: () => Promise<unknown>,
    text: string,
  ): void => {
    setBusyId(entry.id);
    void run()
      .then(() => setNotice({ text, batchId: null }))
      .catch((err: unknown) => setError(describeDaemonError(err)))
      .finally(() => {
        setBusyId(null);
        refresh();
      });
  };

  const keep = (entry: MemoryEntry): void => {
    if (api === null) {
      return;
    }
    act(
      entry,
      () => api.keepMemory({ memoryId: entry.id }),
      `Kept ${entry.handle}. It moved to Kept.`,
    );
  };

  const unkeep = (entry: MemoryEntry): void => {
    if (api === null) {
      return;
    }
    act(
      entry,
      () => api.unkeepMemory({ memoryId: entry.id }),
      `${entry.handle} is no longer kept.`,
    );
  };

  const restore = (entry: MemoryEntry): void => {
    if (api === null) {
      return;
    }
    act(
      entry,
      () =>
        api.updateMemory({
          memoryId: entry.id,
          updateMemoryDto: { status: 'active' },
        }),
      `Restored ${entry.handle}.`,
    );
  };

  const purge = async (entry: MemoryEntry): Promise<void> => {
    if (api === null) {
      return;
    }
    try {
      await api.purgeMemory({ memoryId: entry.id });
    } catch (err: unknown) {
      throw new Error(describeDaemonError(err), { cause: err });
    }
    setNotice({
      text: `Deleted ${entry.handle} permanently.`,
      batchId: null,
    });
    refresh();
  };

  const autoForgetFigure = async (
    days: number,
  ): Promise<AutoForgetFigure | null> => {
    if (api === null) {
      return null;
    }
    return figureOf(await api.memoryReviewSummary({ autoForgetDays: days }));
  };

  return {
    summary,
    autoForget: summary === null ? null : figureOf(summary),
    open,
    openDialog,
    closeDialog,
    tab,
    setTab,
    filters,
    setFilters,
    rows,
    total,
    younger,
    next,
    loading,
    error,
    selected,
    warnedSelected: warned.size,
    tickSkipped:
      tickSkipped === null ? null : Math.max(0, tickSkipped - warned.size),
    ticking,
    toggle,
    tickShown,
    untickAll: clearPicks,
    forget,
    undo,
    keep,
    unkeep,
    restore,
    purge,
    autoForgetFigure,
    loadMore,
    batches,
    notice,
    announce: setNotice,
    busyId,
  };
}
