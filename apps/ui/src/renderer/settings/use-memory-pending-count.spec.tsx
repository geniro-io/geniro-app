// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { MemoryReviewSummaryDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { useMemoryPendingCount } from './use-memory-pending-count';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function summaryOf(pending: number): MemoryReviewSummaryDto {
  return {
    active: 0,
    pending,
    read: 0,
    neverRead: 0,
    proposed: 0,
    proposedWithWarning: 0,
    younger: 0,
    kept: 0,
    forgotten: 0,
    minAgeDays: 14,
    countedSince: null,
    counting: false,
    lastBatch: null,
    autoForget: null,
  };
}

function Probe({
  apis,
  client,
}: {
  apis: DaemonApis;
  client: DaemonClient;
}): React.JSX.Element {
  const pending = useMemoryPendingCount(apis, client);
  return (
    <output data-slot="pending">{pending === null ? 'none' : pending}</output>
  );
}

let container: HTMLDivElement;
let root: Root;
let memoryChanged: (() => void)[];
let reconnected: (() => void)[];
let offMemoryChanged: ReturnType<typeof vi.fn>;
let offReconnected: ReturnType<typeof vi.fn>;
let memoryReviewSummary: ReturnType<typeof vi.fn>;
let apis: DaemonApis;
let client: DaemonClient;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  memoryChanged = [];
  reconnected = [];
  offMemoryChanged = vi.fn();
  offReconnected = vi.fn();
  memoryReviewSummary = vi.fn(() => Promise.resolve(summaryOf(4)));
  apis = {
    memories: { memoryReviewSummary },
  } as unknown as DaemonApis;
  client = {
    onMemoryChanged: vi.fn((listener: () => void) => {
      memoryChanged.push(listener);
      return offMemoryChanged;
    }),
    onReconnect: vi.fn((listener: () => void) => {
      reconnected.push(listener);
      return offReconnected;
    }),
  } as unknown as DaemonClient;
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

const drawn = (): string | null | undefined =>
  container.querySelector('[data-slot="pending"]')?.textContent;

async function render(shown: boolean): Promise<void> {
  await act(async () => {
    root.render(shown ? <Probe apis={apis} client={client} /> : null);
  });
}

async function fire(listeners: (() => void)[]): Promise<void> {
  await act(async () => {
    for (const listener of listeners) {
      listener();
    }
  });
}

describe('useMemoryPendingCount', () => {
  it('draws no count before the first answer, then the pending entries', async () => {
    let answer: (summary: MemoryReviewSummaryDto) => void = () => undefined;
    memoryReviewSummary.mockReturnValueOnce(
      new Promise<MemoryReviewSummaryDto>((resolve) => {
        answer = resolve;
      }),
    );
    await render(true);
    expect(drawn()).toBe('none');

    await act(async () => {
      answer(summaryOf(4));
    });
    expect(drawn()).toBe('4');
  });

  it('reads again on every memory write and after a reconnect', async () => {
    await render(true);
    expect(drawn()).toBe('4');

    memoryReviewSummary.mockResolvedValueOnce(summaryOf(5));
    await fire(memoryChanged);
    expect(drawn()).toBe('5');

    memoryReviewSummary.mockResolvedValueOnce(summaryOf(0));
    await fire(reconnected);
    expect(drawn()).toBe('0');
    expect(memoryReviewSummary).toHaveBeenCalledTimes(3);
  });

  it('draws no count when a read fails, rather than the last one it had', async () => {
    await render(true);
    expect(drawn()).toBe('4');

    memoryReviewSummary.mockRejectedValueOnce(new Error('daemon down'));
    await fire(memoryChanged);
    expect(drawn()).toBe('none');
  });

  it('stops listening once it leaves the screen', async () => {
    await render(true);
    await render(false);
    expect(offMemoryChanged).toHaveBeenCalledTimes(1);
    expect(offReconnected).toHaveBeenCalledTimes(1);
  });
});
