// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { memoryImportRow } from '../__fixtures__/memories';
import type {
  MemoriesApi,
  MemoriesApiTriageMemoryImportRequest,
  MemoryImportTriageDto,
} from '../autogenerated';
import type { MemoryImportTriage } from '../components/memory-import-dialog';
import { TRIAGE_BATCH, useMemoryTriage } from './use-memory-triage';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

type Triage = (
  request: MemoriesApiTriageMemoryImportRequest,
  init?: RequestInit,
) => Promise<MemoryImportTriageDto>;

function mount(triage: Triage): () => MemoryImportTriage {
  let latest: MemoryImportTriage | null = null;
  const api = {
    triageMemoryImport: triage,
  } as unknown as Pick<MemoriesApi, 'triageMemoryImport'>;
  function Probe(): null {
    latest = useMemoryTriage(api);
    return null;
  }
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  act(() => root!.render(<Probe />));
  return () => latest!;
}

const keepAll: Triage = (request) =>
  Promise.resolve({
    verdicts: request.memoryImportTriageRequestDto.notes.map((note) => ({
      key: note.key,
      keep: true,
      reason: 'useful',
    })),
  });

async function flush(): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, 0));
  });
}

const rows = (count: number) =>
  Array.from({ length: count }, (_, n) =>
    memoryImportRow({ key: `k${n}`, folder: `/f${n}` }),
  );

describe('useMemoryTriage', () => {
  it('asks in batches, sending each note’s text and folder, and gathers every verdict', async () => {
    const triage = vi.fn(keepAll);
    const latest = mount(triage);

    act(() => latest().start('codex', rows(TRIAGE_BATCH + 1)));
    expect(latest().running).toBe(true);
    expect(latest().total).toBe(TRIAGE_BATCH + 1);
    await flush();

    expect(triage).toHaveBeenCalledTimes(2);
    const first = triage.mock.calls[0]![0].memoryImportTriageRequestDto;
    expect(first.agentKind).toBe('codex');
    expect(first.notes).toHaveLength(TRIAGE_BATCH);
    expect(first.notes[0]).toEqual({
      key: 'k0',
      title: memoryImportRow().title,
      body: memoryImportRow().body,
      folder: '/f0',
    });
    expect(latest().running).toBe(false);
    expect(latest().done).toBe(TRIAGE_BATCH + 1);
    expect(latest().verdicts.get(`k${TRIAGE_BATCH}`)).toEqual({
      keep: true,
      reason: 'useful',
    });
  });

  it('asks again only about notes it has no verdict for', async () => {
    const triage = vi.fn(keepAll);
    const latest = mount(triage);
    act(() => latest().start('claude', rows(2)));
    await flush();

    act(() => latest().start('claude', rows(3)));
    await flush();

    expect(
      triage.mock.calls[1]![0].memoryImportTriageRequestDto.notes.map(
        (note) => note.key,
      ),
    ).toEqual(['k2']);
  });

  it('stops on the first failure and says why', async () => {
    const triage = vi.fn<Triage>(() =>
      Promise.reject(new Error('not signed in')),
    );
    const latest = mount(triage);
    act(() => latest().start('claude', rows(1)));
    await flush();

    expect(latest().running).toBe(false);
    expect(latest().error).toContain('not signed in');
  });

  it('a Stop aborts the request in flight, keeps no error and drops its answer', async () => {
    let signal: AbortSignal | undefined;
    let answer: (value: MemoryImportTriageDto) => void = () => undefined;
    const triage = vi.fn<Triage>((_request, init) => {
      signal = init?.signal ?? undefined;
      return new Promise((resolve, reject) => {
        answer = resolve;
        signal?.addEventListener('abort', () => reject(new Error('aborted')));
      });
    });
    const latest = mount(triage);
    act(() => latest().start('claude', rows(1)));

    act(() => latest().cancel());
    answer({ verdicts: [{ key: 'k0', keep: true, reason: '' }] });
    await flush();

    expect(signal?.aborted).toBe(true);
    expect(latest().running).toBe(false);
    expect(latest().error).toBeNull();
    expect(latest().verdicts.size).toBe(0);
  });
});
