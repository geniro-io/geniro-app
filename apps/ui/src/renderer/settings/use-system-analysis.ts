import { useEffect, useRef, useState } from 'react';

import {
  type AnalysisConfig,
  CLI_KINDS,
  type CliKind,
  type Settings,
} from '../../shared/contracts';
import type {
  ModelPrice,
  RunDto,
  StartSystemAnalysisDto,
  SystemAnalysisRow,
  SystemAnalysisScopeDto,
} from '../autogenerated';
import { requestModelPrice } from '../chats/use-model-price';
import { useLatestCallback } from '../components/use-latest-callback';
import { type DaemonApis, describeDaemonError } from '../daemon-api';

export const SYSTEM_ANALYSIS_PAGE_SIZE = 3;

/** How often the past analyses are re-read while one of them still works. */
export const SYSTEM_ANALYSIS_POLL_MS = 10_000;

type SystemAnalysisApi = DaemonApis['systemAnalyses'];

interface ListPage {
  rows: readonly SystemAnalysisRow[];
  next: string | null;
}

export interface SystemAnalysisState {
  /** The scope of the period asked for; null while it is read. */
  scope: SystemAnalysisScopeDto | null;
  scopeError: string | null;
  /** The past analyses, newest first; null until the first page answers. */
  analyses: readonly SystemAnalysisRow[] | null;
  listError: string | null;
  hasMore: boolean;
  loadingMore: boolean;
  /** Appends the next page of older analyses. */
  loadMore: () => void;
  /** Starts an analysis and re-reads the list; rejects with the daemon's refusal. */
  start: (dto: StartSystemAnalysisDto) => Promise<RunDto>;
}

export function useSystemAnalysis(
  api: SystemAnalysisApi | null,
  days: number,
): SystemAnalysisState {
  const [scope, setScope] = useState<{
    days: number;
    value: SystemAnalysisScopeDto;
  } | null>(null);
  const [scopeError, setScopeError] = useState<string | null>(null);
  const [page, setPage] = useState<ListPage | null>(null);
  const [listError, setListError] = useState<string | null>(null);
  const [loadingMore, setLoadingMore] = useState(false);
  const generation = useRef(0);
  const shown = useRef(0);
  shown.current = page?.rows.length ?? 0;

  useEffect(() => {
    if (api === null) {
      return undefined;
    }
    let live = true;
    setScopeError(null);
    api
      .readSystemAnalysisScope({ days })
      .then((value) => {
        if (live) {
          setScope({ days, value });
        }
      })
      .catch((err: unknown) => {
        if (live) {
          setScopeError(describeDaemonError(err));
        }
      });
    return () => {
      live = false;
    };
  }, [api, days]);

  const reload = useLatestCallback(async (): Promise<void> => {
    if (api === null) {
      return;
    }
    const mine = ++generation.current;
    setLoadingMore(false);
    try {
      const answer = await api.listSystemAnalyses({
        limit: Math.max(SYSTEM_ANALYSIS_PAGE_SIZE, shown.current),
      });
      if (mine === generation.current) {
        setPage({ rows: answer.analyses, next: answer.next });
        setListError(null);
      }
    } catch (err) {
      if (mine === generation.current) {
        setListError(describeDaemonError(err));
      }
    }
  }, [api]);

  useEffect(() => {
    void reload();
  }, [reload]);

  const loadMore = useLatestCallback((): void => {
    if (api === null || page === null || page.next === null || loadingMore) {
      return;
    }
    const mine = generation.current;
    setLoadingMore(true);
    api
      .listSystemAnalyses({
        limit: SYSTEM_ANALYSIS_PAGE_SIZE,
        before: page.next,
      })
      .then((answer) => {
        if (mine === generation.current) {
          setPage((held) => ({
            rows: [...(held?.rows ?? []), ...answer.analyses],
            next: answer.next,
          }));
        }
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setListError(describeDaemonError(err));
        }
      })
      .finally(() => {
        if (mine === generation.current) {
          setLoadingMore(false);
        }
      });
  }, [api, page, loadingMore]);

  const start = useLatestCallback(
    async (dto: StartSystemAnalysisDto): Promise<RunDto> => {
      if (api === null) {
        throw new Error('The daemon is not connected.');
      }
      const run = await api.startSystemAnalysis({
        startSystemAnalysisDto: dto,
      });
      void reload();
      return run;
    },
    [api, reload],
  );

  const running = page?.rows.some((row) => row.status === 'running') ?? false;
  useEffect(() => {
    if (!running) {
      return undefined;
    }
    const timer = window.setInterval(
      () => void reload(),
      SYSTEM_ANALYSIS_POLL_MS,
    );
    return () => window.clearInterval(timer);
  }, [running, reload]);

  return {
    scope: scope?.days === days ? scope.value : null,
    scopeError,
    analyses: page?.rows ?? null,
    listError,
    hasMore: page !== null && page.next !== null,
    loadingMore,
    loadMore,
    start,
  };
}

export function defaultAnalysisConfig(): AnalysisConfig {
  return {
    agent: CLI_KINDS[0]!,
    configDir: null,
    model: null,
    effort: null,
    contextWindow: null,
    autoCompactPercent: null,
    modelParameters: {},
    approval: null,
  };
}

export interface AnalysisSetup {
  /** The setup last used, or the default; null until the settings are read. */
  config: AnalysisConfig | null;
  setConfig: (next: AnalysisConfig) => void;
  /** The profiles a CLI's model settings offer; null until the settings are read. */
  profiles: Pick<Settings, 'recentConfigDirs' | 'configProfiles'> | null;
}

export function useAnalysisSetup(): AnalysisSetup {
  const [config, setConfig] = useState<AnalysisConfig | null>(null);
  const [profiles, setProfiles] = useState<AnalysisSetup['profiles']>(null);
  useEffect(() => {
    let live = true;
    window.geniro
      .getSettings()
      .then((settings) => {
        if (live) {
          setConfig(
            (held) =>
              held ?? settings.lastAnalysisConfig ?? defaultAnalysisConfig(),
          );
          setProfiles({
            recentConfigDirs: settings.recentConfigDirs,
            configProfiles: settings.configProfiles,
          });
        }
      })
      .catch(() => {
        if (live) {
          setConfig((held) => held ?? defaultAnalysisConfig());
          setProfiles({ recentConfigDirs: {}, configProfiles: [] });
        }
      });
    return () => {
      live = false;
    };
  }, []);
  return { config, setConfig, profiles };
}

/** A failed remembering costs only the next default, so it is not reported. */
export function saveAnalysisSetup(config: AnalysisConfig): void {
  void window.geniro
    .updateSettings({ lastAnalysisConfig: config })
    .catch(() => undefined);
}

/**
 * The list price of a model under its account: undefined while it is read,
 * null when the model has none, or when no model is picked.
 */
export function useModelPriceOf(
  agentsApi: DaemonApis['agents'] | null,
  agent: CliKind,
  model: string | null,
  configDir: string | null,
): ModelPrice | null | undefined {
  const [answer, setAnswer] = useState<{
    agent: CliKind;
    model: string;
    configDir: string | null;
    price: ModelPrice | null;
  } | null>(null);
  useEffect(() => {
    if (agentsApi === null || model === null) {
      return undefined;
    }
    let live = true;
    void requestModelPrice(agentsApi, agent, model, configDir).then((price) => {
      if (live) {
        setAnswer({ agent, model, configDir, price });
      }
    });
    return () => {
      live = false;
    };
  }, [agentsApi, agent, model, configDir]);
  if (model === null) {
    return null;
  }
  if (
    answer === null ||
    answer.agent !== agent ||
    answer.model !== model ||
    answer.configDir !== configDir
  ) {
    return undefined;
  }
  return answer.price;
}
