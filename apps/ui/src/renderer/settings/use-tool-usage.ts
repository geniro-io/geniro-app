import { useEffect, useState } from 'react';

import type {
  ToolUsageListDto,
  ToolUsageRow,
  ToolUsageSubjectDto,
} from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

type StatsApi = DaemonApis['stats'];
export type ToolUsageClient = Pick<DaemonClient, 'onReconnect'>;

export interface ToolUsageState {
  data: ToolUsageListDto | null;
  error: string | null;
  reload: () => void;
}

export function useToolUsage(
  api: StatsApi | null,
  client: ToolUsageClient | null,
): ToolUsageState {
  const [data, setData] = useState<ToolUsageListDto | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [generation, setGeneration] = useState(0);

  useEffect(() => {
    if (api === null) {
      return undefined;
    }
    let live = true;
    api
      .readToolUsage()
      .then((answer) => {
        if (live) {
          setData(answer);
          setError(null);
        }
      })
      .catch((err: unknown) => {
        if (live) {
          setError(describeDaemonError(err));
        }
      });
    return () => {
      live = false;
    };
  }, [api, generation]);

  const reload = useLatestCallback((): void => {
    setError(null);
    setGeneration((held) => held + 1);
  }, []);

  useEffect(() => {
    if (client === null) {
      return undefined;
    }
    return client.onReconnect(() => reload());
  }, [client, reload]);

  return { data, error, reload };
}

export interface ToolUsageSubjectState {
  data: ToolUsageSubjectDto | null;
  error: string | null;
  retry: () => void;
}

export function useToolUsageSubject(
  api: StatsApi | null,
  row: ToolUsageRow,
): ToolUsageSubjectState {
  const [data, setData] = useState<ToolUsageSubjectDto | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [attempt, setAttempt] = useState(0);
  const { subjectKind, subject, source } = row;

  useEffect(() => {
    if (api === null) {
      return undefined;
    }
    let live = true;
    api
      .readToolUsageSubject({ subjectKind, subject, source })
      .then((answer) => {
        if (live) {
          setData(answer);
          setError(null);
        }
      })
      .catch((err: unknown) => {
        if (live) {
          setError(describeDaemonError(err));
        }
      });
    return () => {
      live = false;
    };
  }, [api, subjectKind, subject, source, attempt]);

  const retry = useLatestCallback((): void => {
    setError(null);
    setAttempt((held) => held + 1);
  }, []);

  return { data, error, retry };
}

export interface ToolCallLogRetention {
  /** undefined until the settings are read. */
  days: number | null | undefined;
  setDays: (next: number | null) => void;
}

export function useToolCallLogRetention(): ToolCallLogRetention {
  const [days, setDaysState] = useState<number | null | undefined>(undefined);
  useEffect(() => {
    let live = true;
    window.geniro
      .getSettings()
      .then((settings) => {
        if (live) {
          setDaysState(settings.toolCallLogRetentionDays);
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, []);
  const setDays = (next: number | null): void => {
    setDaysState(next);
    void window.geniro
      .updateSettings({ toolCallLogRetentionDays: next })
      .catch(() => undefined);
  };
  return { days, setDays };
}
