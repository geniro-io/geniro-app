// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { DaemonHandle } from '../../shared/contracts';
import type { ChatTotals, UsageStatsDto } from '../autogenerated';

const mocks = vi.hoisted(() => ({
  readUsageStats: vi.fn(),
}));

vi.mock('../daemon-api', () => ({
  createDaemonApis: () => ({ stats: { readUsageStats: mocks.readUsageStats } }),
}));

const { Stats } = await import('./Stats');

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const HANDLE = {
  host: '127.0.0.1',
  port: 1,
  token: 't',
} as unknown as DaemonHandle;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

async function render(element: React.ReactElement): Promise<HTMLDivElement> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(element);
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.clearAllMocks();
});

function totals(overrides: Partial<ChatTotals> = {}): ChatTotals {
  return {
    turns: 4,
    costedTurns: 4,
    costUsd: 2.5,
    inputTokens: 1_000,
    outputTokens: 200,
    cacheReadTokens: 3_000,
    cacheCreationTokens: 100,
    thinkingTokens: 50,
    workedMs: 3_600_000,
    ...overrides,
  };
}

function stats(overrides: Partial<UsageStatsDto> = {}): UsageStatsDto {
  return {
    from: '2026-08-10T00:00:00.000Z',
    to: '2026-08-12T00:00:00.000Z',
    totals: totals(),
    days: [
      { date: '2026-08-10', totals: totals({ turns: 2, costUsd: 1.5 }) },
      { date: '2026-08-11', totals: totals({ turns: 2, costUsd: 1 }) },
    ],
    byAgent: [{ key: 'claude', totals: totals() }],
    byModel: [{ key: 'claude-opus-5', totals: totals() }],
    byProject: [{ key: '/Users/me/work/geniro-app', totals: totals() }],
    ...overrides,
  } as UsageStatsDto;
}

/**
 * Every stat on the page, as `label → value` — the hero, its supporting
 * figures, and the metric grid alike.
 *
 * Read off the `stat` / `stat-label` / `stat-value` slots rather than by
 * counting spans, which is what the previous helper did: it silently matched
 * only cards with exactly two spans, so adding an icon to a card would have
 * dropped it out of the map and every assertion about it with it.
 */
function cards(el: HTMLElement): Record<string, string> {
  const entries: Record<string, string> = {};
  for (const stat of el.querySelectorAll('[data-slot="stat"]')) {
    const label = stat.querySelector('[data-slot="stat-label"]')?.textContent;
    const value = stat.querySelector('[data-slot="stat-value"]')?.textContent;
    if (label !== null && label !== undefined) {
      entries[label] = value ?? '';
    }
  }
  return entries;
}

const buttonNamed = (el: HTMLElement, label: string): HTMLButtonElement =>
  [...el.querySelectorAll('button')].find(
    (node) => node.textContent === label,
  ) as HTMLButtonElement;

describe('Stats', () => {
  beforeEach(() => {
    mocks.readUsageStats.mockResolvedValue(stats());
  });

  it('shows the period’s headline figures', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    expect(cards(el)).toMatchObject({
      Spent: '$2.50',
      Turns: '4',
      'Tokens in': '1k',
      'Agent time': '1h 0m',
    });
  });

  it('renders an unreported figure as not-measured, never as zero', async () => {
    // The cursor-agent shape. A "$0.00" here would be a false statement about
    // money, and it is the single thing this page must never say.
    mocks.readUsageStats.mockResolvedValue(
      stats({ totals: totals({ costUsd: null, workedMs: null }) }),
    );

    const el = await render(<Stats handle={HANDLE} />);

    expect(cards(el).Spent).toBe('—');
    expect(cards(el)['Agent time']).toBe('—');
    expect(cards(el)['Cost per turn']).toBe('—');
  });

  it('averages cost over the turns that were priced, not over all of them', async () => {
    mocks.readUsageStats.mockResolvedValue(
      stats({
        totals: totals({ turns: 10, costedTurns: 4, costUsd: 8 }),
      }),
    );

    const el = await render(<Stats handle={HANDLE} />);

    // $2.00 (8/4), not $0.80 (8/10): the six turns that reported no cost
    // contributed nothing to the numerator, so counting them below the line
    // would understate what a priced turn actually costs.
    expect(cards(el)['Cost per turn']).toBe('$2.00');
  });

  it('derives the cache hit rate from what was reported', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    // 3000 cached against 1000 fresh.
    expect(cards(el)['Cache hit rate']).toBe('75%');
  });

  it('asks the daemon again when the period changes', async () => {
    const el = await render(<Stats handle={HANDLE} />);
    expect(mocks.readUsageStats).toHaveBeenCalledTimes(1);

    await act(async () => {
      buttonNamed(el, '7 days').click();
    });

    expect(mocks.readUsageStats).toHaveBeenCalledTimes(2);
    // "All time" is the only period that names no lower bound, so a 7-day pick
    // must carry one.
    expect(mocks.readUsageStats.mock.calls[1]![0]).toHaveProperty('from');
  });

  it('asks for the whole history when All time is picked', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    await act(async () => {
      buttonNamed(el, 'All time').click();
    });

    expect(mocks.readUsageStats.mock.calls[1]![0].from).toBeUndefined();
  });

  it('re-plots the daily chart without refetching when the metric changes', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    await act(async () => {
      buttonNamed(el, 'Tokens').click();
    });

    // Same period, different projection of data already in hand — a refetch
    // here would cost a round trip for a value the client already holds.
    expect(mocks.readUsageStats).toHaveBeenCalledTimes(1);
    // The toggle moved, which is what "re-plots" means from here. The plotted
    // series itself is asserted in `chart-data.spec.ts`: Recharts measures its
    // container to lay out, and jsdom reports every box as 0×0, so a chart
    // never paints under this environment. Asserting on the SVG here would pin
    // nothing — it is absent whether or not the metric switch works.
    expect(buttonNamed(el, 'Tokens').getAttribute('aria-pressed')).toBe('true');
    expect(buttonNamed(el, 'Spend').getAttribute('aria-pressed')).toBe('false');
  });

  it('shortens a project path in the breakdown', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    expect(el.textContent).toContain('…/work/geniro-app');
  });

  it('surfaces a failed read instead of an empty page', async () => {
    mocks.readUsageStats.mockRejectedValue(
      new Error('daemon GET failed (500)'),
    );

    const el = await render(<Stats handle={HANDLE} />);

    expect(el.textContent).toContain('daemon GET failed (500)');
  });

  it('lets a failed read be dismissed, not only retried', async () => {
    mocks.readUsageStats.mockRejectedValue(
      new Error('daemon GET failed (500)'),
    );
    const el = await render(<Stats handle={HANDLE} />);

    const dismiss = [...el.querySelectorAll('button')].find(
      (node) => node.getAttribute('aria-label') === 'Dismiss error',
    ) as HTMLButtonElement;
    await act(async () => {
      dismiss.click();
    });
    // Flush whatever the click set in motion, so "the strip is still there"
    // is an observation rather than a race.
    await act(async () => {});

    // The strip's close control is the only way off a failure nothing the user
    // can type will clear (`ErrorBanner`) — and this screen already offers a
    // Retry beside it. Wired to the retry as well, the daemon being down means
    // the banner cannot be dismissed at all.
    expect(el.textContent).not.toContain('daemon GET failed (500)');
  });

  it('shows the period the daemon actually reported on', async () => {
    const el = await render(<Stats handle={HANDLE} />);

    // The daemon clamps a request to what its ledger can answer for, so the
    // page must show the RESOLVED span — otherwise a short history under a long
    // period reads as a quiet quarter.
    expect(el.textContent).toContain('2026');
    expect(el.textContent).not.toContain('What your agents have used');
  });

  it('ignores a superseded response that lands after a newer one', async () => {
    // Two overlapping reads: the slow 30-day request must not overwrite the
    // 7-day figures the user is now looking at, and its failure must not raise
    // a banner for a period they already left. Nothing entered that guard
    // before, so deleting it left the suite green.
    let settleFirst: (value: UsageStatsDto) => void = () => undefined;
    let failFirst: (err: Error) => void = () => undefined;
    mocks.readUsageStats.mockReturnValueOnce(
      new Promise<UsageStatsDto>((resolve, reject) => {
        settleFirst = resolve;
        failFirst = reject;
      }),
    );
    mocks.readUsageStats.mockResolvedValueOnce(
      stats({ totals: totals({ turns: 99, costUsd: 7 }) }),
    );

    const el = await render(<Stats handle={HANDLE} />);
    await act(async () => {
      buttonNamed(el, '7 days').click();
    });

    // The newer read resolved; now let the superseded one land, both ways.
    await act(async () => {
      settleFirst(stats({ totals: totals({ turns: 1, costUsd: 0.01 }) }));
      failFirst(new Error('superseded failure'));
      await Promise.resolve();
    });

    expect(cards(el).Turns).toBe('99');
    expect(cards(el).Spent).toBe('$7.00');
    expect(el.textContent).not.toContain('superseded failure');
  });

  it('says it is connecting when there is no daemon handle yet', async () => {
    const el = await render(<Stats handle={null} />);

    expect(el.textContent).toContain('Connecting to the daemon');
    expect(mocks.readUsageStats).not.toHaveBeenCalled();
  });
});
