import { useMemo, useState } from 'react';

import type { DaemonHandle } from '../../shared/contracts';
import type { ChatTotals } from '../autogenerated';
import { formatTokens, formatUsd } from '../chats/agent-activity';
import { shortenPath } from '../chats/directory-select';
import { EmptyState } from '../components/empty-state';
import { ErrorBanner } from '../components/error-banner';
import { BarChart, type BarChartPoint } from '../components/ui/bar-chart';
import { Button } from '../components/ui/button';
import { Card, CardContent } from '../components/ui/card';
import { cn } from '../components/ui/utils';
import { createDaemonApis } from '../daemon-api';
import { BreakdownCard } from './breakdown-card';
import {
  cacheHitRate,
  formatDayLabel,
  formatDayTitle,
  formatDuration,
  NOT_MEASURED,
  NOT_MEASURED_TITLE,
} from './stats-format';
import { STATS_PERIODS, type StatsPeriodId, useStats } from './use-stats';

/** Which figure the per-day chart plots. */
const DAILY_METRICS = [
  { id: 'cost', label: 'Spend' },
  { id: 'tokens', label: 'Tokens' },
] as const;

type DailyMetricId = (typeof DAILY_METRICS)[number]['id'];

/**
 * What the app has cost, and where it went.
 *
 * Every figure is summed on the DAEMON from its usage ledger — a table that
 * deliberately outlives the runs it accounts for, so tidying a chat away does
 * not quietly shrink the lifetime total.
 *
 * The page's one recurring rule: a figure nobody reported reads as
 * {@link NOT_MEASURED}, never as zero. cursor-agent reports no cost unless its
 * currency is USD and no cache, thinking or timing figures at all, so a page
 * that defaulted them would be making claims about money that no CLI ever made.
 */
export function Stats({
  handle,
}: {
  handle: DaemonHandle | null;
}): React.JSX.Element {
  const apis = useMemo(
    () => (handle ? createDaemonApis(handle) : null),
    [handle],
  );
  const [period, setPeriod] = useState<StatsPeriodId>('30d');
  const [metric, setMetric] = useState<DailyMetricId>('cost');
  const { data, loading, error, reload, dismiss } = useStats(apis, period);

  const points = useMemo<BarChartPoint[]>(
    () => (data ? data.days.map((day) => dailyPoint(day, metric)) : []),
    [data, metric],
  );

  if (!handle) {
    return <EmptyState>Connecting to the daemon…</EmptyState>;
  }

  return (
    <div className="flex h-full min-h-0 flex-col overflow-y-auto">
      <div className="flex flex-col gap-6 p-6">
        <header className="flex flex-wrap items-center justify-between gap-3">
          <div>
            <h2 className="text-lg font-semibold">Stats</h2>
            <p className="text-sm text-muted-foreground">
              {data
                ? // The RESOLVED span, not the requested one. The daemon clamps
                  // a request to what the ledger can answer for, so a profile
                  // with three days of history that picks "90 days" gets three
                  // columns — indistinguishable from a quiet quarter unless the
                  // real period is on screen.
                  `${formatDayTitle(data.from.slice(0, 10))} – ${formatDayTitle(
                    data.to.slice(0, 10),
                  )}`
                : 'What your agents have used, and what it cost.'}
            </p>
          </div>
          <SegmentedControl
            ariaLabel="Period"
            options={STATS_PERIODS}
            value={period}
            onSelect={setPeriod}
          />
        </header>

        {error ? (
          <ErrorBanner
            message={error}
            onDismiss={dismiss}
            action={
              <Button
                type="button"
                variant="ghost"
                size="sm"
                className="shrink-0"
                onClick={reload}>
                Retry
              </Button>
            }
          />
        ) : null}

        {loading && !data ? (
          <EmptyState>Loading…</EmptyState>
        ) : data ? (
          <>
            <section className="grid grid-cols-2 gap-3 md:grid-cols-4">
              <StatCard
                label="Spent"
                value={formatOrDash(data.totals.costUsd, formatUsd)}
              />
              <StatCard label="Turns" value={String(data.totals.turns)} />
              <StatCard
                label="Tokens in"
                value={formatOrDash(data.totals.inputTokens, formatTokens)}
              />
              <StatCard
                label="Tokens out"
                value={formatOrDash(data.totals.outputTokens, formatTokens)}
              />
              <StatCard
                label="Cache read"
                value={formatOrDash(data.totals.cacheReadTokens, formatTokens)}
              />
              <StatCard
                label="Cache written"
                value={formatOrDash(
                  data.totals.cacheCreationTokens,
                  formatTokens,
                )}
              />
              <StatCard
                label="Thinking"
                value={formatOrDash(data.totals.thinkingTokens, formatTokens)}
              />
              <StatCard
                label="Agent time"
                value={formatOrDash(data.totals.workedMs, formatDuration)}
              />
              <StatCard
                label="Cache hit rate"
                value={formatOrDash(
                  cacheHitRate(
                    data.totals.cacheReadTokens,
                    data.totals.inputTokens,
                  ),
                  (rate) => `${Math.round(rate)}%`,
                )}
                hint="Share of prompt tokens served from cache — the difference between a cheap session and an expensive one."
              />
              <StatCard
                label="Cost per turn"
                value={formatOrDash(
                  // Divided by the turns that actually REPORTED a cost, not by
                  // every turn: a period mixing a CLI that prices its turns
                  // with one that does not would otherwise report roughly half
                  // the true average.
                  data.totals.costedTurns > 0 && data.totals.costUsd !== null
                    ? data.totals.costUsd / data.totals.costedTurns
                    : null,
                  formatUsd,
                )}
              />
            </section>

            <Card>
              <CardContent className="flex flex-col gap-4 p-5">
                <div className="flex flex-wrap items-center justify-between gap-3">
                  <h3 className="text-sm font-medium">Per day</h3>
                  <SegmentedControl
                    ariaLabel="Daily metric"
                    options={DAILY_METRICS}
                    value={metric}
                    onSelect={setMetric}
                  />
                </div>
                <BarChart
                  points={points}
                  ariaLabel={`${
                    metric === 'cost' ? 'Spend' : 'Tokens'
                  } per day over the selected period`}
                />
              </CardContent>
            </Card>

            <section className="flex flex-col gap-3 lg:flex-row">
              <BreakdownCard
                title="By agent"
                groups={data.byAgent}
                labelOf={(key) => key ?? 'Unattributed'}
                emptyLabel="No agent activity in this period."
              />
              <BreakdownCard
                title="By model"
                groups={data.byModel}
                labelOf={(key) => key ?? 'CLI default'}
                emptyLabel="No model activity in this period."
              />
              <BreakdownCard
                title="By project"
                groups={data.byProject}
                labelOf={(key) =>
                  key === null ? 'Unknown folder' : shortenPath(key, 2)
                }
                emptyLabel="No project activity in this period."
              />
            </section>
          </>
        ) : null}
      </div>
    </div>
  );
}

/** One day's column — the plotted value plus the sentence shown on hover. */
function dailyPoint(
  day: { date: string; totals: ChatTotals },
  metric: DailyMetricId,
): BarChartPoint {
  const value =
    metric === 'cost'
      ? day.totals.costUsd
      : sumTokens(day.totals.inputTokens, day.totals.outputTokens);
  const title = `${formatDayTitle(day.date)} — ${
    day.totals.turns === 0
      ? 'no turns'
      : `${day.totals.turns} turn${day.totals.turns === 1 ? '' : 's'}, ${
          value === null
            ? 'not measured'
            : metric === 'cost'
              ? formatUsd(value)
              : `${formatTokens(value)} tokens`
        }`
  }`;
  return { key: day.date, label: formatDayLabel(day.date), value, title };
}

/**
 * Input + output where either was reported, null where neither was.
 *
 * A plain `(a ?? 0) + (b ?? 0)` would turn a day nobody measured into a
 * measured zero, which is the one substitution this page exists not to make.
 */
function sumTokens(input: number | null, output: number | null): number | null {
  if (input === null && output === null) {
    return null;
  }
  return (input ?? 0) + (output ?? 0);
}

/** A measured figure, or the not-measured mark. */
function formatOrDash(
  value: number | null,
  format: (value: number) => string,
): string {
  return value === null ? NOT_MEASURED : format(value);
}

function StatCard({
  label,
  value,
  hint,
}: {
  label: string;
  value: string;
  hint?: string;
}): React.JSX.Element {
  return (
    <Card>
      <CardContent
        className="flex flex-col gap-1 p-4"
        title={value === NOT_MEASURED ? NOT_MEASURED_TITLE : hint}>
        <span className="text-xs text-muted-foreground">{label}</span>
        <span
          className={cn(
            'text-xl font-semibold tabular-nums',
            value === NOT_MEASURED && 'text-muted-foreground',
          )}>
          {value}
        </span>
      </CardContent>
    </Card>
  );
}

/**
 * A small run of mutually exclusive options.
 *
 * Not `select`: there are two to four choices, they are always worth showing,
 * and switching between them is the main thing a reader does on this page — a
 * dropdown would hide them behind a click each time. Kept local to this screen
 * rather than promoted to `components/`, since nothing else uses one yet.
 */
function SegmentedControl<T extends string>({
  ariaLabel,
  options,
  value,
  onSelect,
}: {
  ariaLabel: string;
  options: readonly { id: T; label: string }[];
  value: T;
  onSelect: (id: T) => void;
}): React.JSX.Element {
  return (
    <div
      role="group"
      aria-label={ariaLabel}
      className="flex items-center gap-1 rounded-md border border-border bg-muted p-1">
      {options.map((option) => (
        <button
          key={option.id}
          type="button"
          aria-pressed={option.id === value}
          onClick={() => onSelect(option.id)}
          className={cn(
            'rounded-sm px-3 py-1 text-sm font-medium outline-none transition-colors',
            'focus-visible:ring-2 focus-visible:ring-ring/50',
            option.id === value
              ? 'bg-card text-foreground shadow-panel-sm'
              : 'text-muted-foreground hover:text-foreground',
          )}>
          {option.label}
        </button>
      ))}
    </div>
  );
}
