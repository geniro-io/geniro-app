import { useState } from 'react';

import type { UsageGroup } from '../autogenerated';
import { formatTokens, formatUsd } from '../chats/agent-activity';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { cn } from '../components/ui/utils';
import { isCosted, type RankedRow, toRankedRows } from './chart-data';

/**
 * How many rows a column shows before the rest go behind "Show all".
 *
 * REPORTED as "there are too many items in the panel — show the top 5, then
 * all of them in a separate popup": By project ran to sixty-six rows on a real
 * ledger, the four columns are one surface, so the longest one set the height
 * of all four and pushed the charts below it a dozen screens down.
 */
export const TOP_ROWS = 5;

/**
 * How faint the bar at each rank is drawn, as a Tailwind opacity class.
 *
 * ONE hue, stepped by RANK — never the categorical ramp this used to reach for.
 * A ranked row already carries its own label on its own line, so colour
 * identifies nothing here; what it did instead was mislead. Each of the four
 * breakdowns restarted the ramp at index 0, so "the second bar is teal" held in
 * three cards about three unrelated dimensions at once, and a reader is right
 * to try to correlate a colour that repeats across columns of one table.
 * Stepping one hue encodes the only thing these rows actually share — their
 * order — and it is the ordering the card is sorted by.
 *
 * It floors at a strength that is still legible rather than fading toward
 * nothing, and the floor is high because it compounds with the WIDTH floor
 * below: the faintest rank is routinely also the 2%-wide one, so a ramp that
 * ended near transparent would draw the minimum-visible mark invisibly —
 * undoing, by opacity, the guarantee that a row which spent money can be seen
 * to have spent it.
 */
const RANK_OPACITY = [
  'bg-primary',
  'bg-primary/75',
  'bg-primary/60',
  'bg-primary/50',
] as const;

function rankClass(index: number): string {
  return RANK_OPACITY[index] ?? 'bg-primary/45';
}

/**
 * A breakdown as a ranked list of bars — who spent what, dearest first.
 *
 * Bars rather than the ring this replaced. A ring compares angles, which the eye
 * does badly past three slices and cannot do at all for the long tail; and its
 * legend had to sit beside it, so a model name like
 * `claude-opus-5[thinking=true,context=300k,…]` was truncated to a few
 * characters. A bar row gives the label the full width of the card and ranks by
 * length, which is the comparison actually being made.
 *
 * The column shows the top {@link TOP_ROWS} and hands the rest to a dialog
 * ("Show all N") rather than growing: the columns share one surface, so one
 * long column made every column that tall. The dialog's rows are the SAME rows,
 * sized against the same largest one, so a bar means the same thing in both.
 *
 * A COLUMN of one ruled surface rather than a `Card` of its own, and that is
 * what fixed the shape of this row: four cards in a grid are stretched to the
 * tallest, so a workflow breakdown holding ONE row was a 345px box with 300px
 * of nothing in it, three times over. One surface has the same air in it and
 * does not draw three empty boxes around it.
 */
export function BreakdownColumn({
  title,
  groups,
  labelOf,
  titleOf,
  emptyLabel,
}: {
  title: string;
  groups: readonly UsageGroup[];
  /** How a group reads for THIS dimension — "unknown model", "no folder". */
  labelOf: (key: string | null, group: UsageGroup) => string;
  /** The row's hover text, where the key is not it — see `toRankedRows`. */
  titleOf?: (group: UsageGroup) => string;
  emptyLabel: string;
}): React.JSX.Element {
  const [showAll, setShowAll] = useState(false);
  const costed = isCosted(groups);
  const rows = toRankedRows(
    groups,
    labelOf,
    // WHAT IT COST and WHAT IT MOVED — never the turn count.
    //
    // It used to read `formatUsd` where the whole card was costed and
    // `formatTurns` otherwise, and `isCosted` demands that EVERY group carry a
    // cost — so one agent reporting none took the dollars off every row. On a
    // real ledger that is exactly what happened: claude had spent $32,581.96
    // and the agent column read `3359 turns`, because cursor-agent's cost was
    // null. REPORTED as "я не могу увидеть, сколько я потратил by agent в
    // долларах. Я могу видеть тёрнс, но тёрнс мне вообще ничего не дает".
    //
    // Each figure is drawn only where something measured it, so a group with
    // neither says so rather than showing a zero of either.
    (row) =>
      [
        row.costUsd === null ? null : formatUsd(row.costUsd),
        row.tokens === null ? null : `${formatTokens(row.tokens)} tokens`,
      ]
        .filter((part): part is string => part !== null)
        .join(' · ') || 'not measured',
    costed,
    titleOf,
  );

  return (
    <div
      data-slot="breakdown"
      className="flex min-w-0 flex-col gap-3 bg-card px-4 py-4">
      <h3 className="text-xs font-medium uppercase tracking-wide text-muted-foreground">
        {title}
      </h3>
      {rows.length === 0 ? (
        <p className="text-sm text-muted-foreground">{emptyLabel}</p>
      ) : (
        <>
          <BreakdownRows rows={rows.slice(0, TOP_ROWS)} />
          {rows.length > TOP_ROWS ? (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              data-slot="breakdown-show-all"
              className="-ml-2 self-start text-muted-foreground"
              onClick={() => setShowAll(true)}>
              Show all {rows.length}
            </Button>
          ) : null}
          <Dialog
            open={showAll}
            onClose={() => setShowAll(false)}
            title={`${title} · ${rows.length}`}
            className="max-w-xl">
            <BreakdownRows rows={rows} />
          </Dialog>
        </>
      )}
    </div>
  );
}

/** Ranked rows as label, figure and bar — the column's and the dialog's. */
function BreakdownRows({
  rows,
}: {
  rows: readonly RankedRow[];
}): React.JSX.Element {
  return (
    <ul className="flex flex-col gap-2.5">
      {rows.map((row, index) => (
        <li key={row.id} className="flex flex-col gap-1.5">
          <div className="flex min-w-0 items-baseline gap-2 text-sm">
            <span className="min-w-0 flex-1 truncate" title={row.title}>
              {row.label}
            </span>
            <span className="shrink-0 tabular-nums text-muted-foreground">
              {row.display}
            </span>
          </div>
          <div className="h-1.5 w-full overflow-hidden rounded-full bg-muted">
            <div
              className={cn('h-full rounded-full', rankClass(index))}
              style={{
                // A floor, so a real but tiny share is still a visible
                // mark rather than rounding away to nothing — the same
                // reason the old ring kept a minimum wedge.
                width: `${Math.max(row.fraction * 100, 2)}%`,
              }}
            />
          </div>
        </li>
      ))}
    </ul>
  );
}
