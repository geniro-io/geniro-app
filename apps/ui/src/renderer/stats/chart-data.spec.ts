import { describe, expect, it } from 'vitest';

import type { ChatTotals, UsageGroup } from '../autogenerated';
import { isCosted, sumMeasured, toDayPoints, toRankedRows } from './chart-data';

function totals(overrides: Partial<ChatTotals> = {}): ChatTotals {
  return {
    turns: 2,
    costedTurns: 2,
    costUsd: 1,
    inputTokens: 100,
    outputTokens: 20,
    cacheReadTokens: null,
    cacheCreationTokens: null,
    thinkingTokens: null,
    workedMs: null,
    ...overrides,
  };
}

const day = (date: string, overrides: Partial<ChatTotals> = {}) => ({
  date,
  totals: totals(overrides),
});

describe('toDayPoints', () => {
  it('carries an unreported figure through as null, never as zero', () => {
    // The one substitution this page exists not to make. It matters especially
    // HERE: Recharts draws a null as a gap and a 0 as a point sitting on the
    // axis, so coalescing on the way in would draw a day nobody measured as a
    // day that cost nothing.
    const [point] = toDayPoints([
      day('2026-08-10', {
        costUsd: null,
        inputTokens: null,
        outputTokens: null,
      }),
    ]);

    expect(point!.costUsd).toBeNull();
    expect(point!.inputTokens).toBeNull();
    expect(point!.totalTokens).toBeNull();
  });

  it('still sums the half that WAS reported', () => {
    const [point] = toDayPoints([day('2026-08-10', { outputTokens: null })]);

    // Only one side was missing, so the day is not unmeasured — it is a day
    // with 100 prompt tokens, and saying "not measured" would lose that.
    expect(point!.totalTokens).toBe(100);
  });

  it('accumulates spend across the period', () => {
    const points = toDayPoints([
      day('2026-08-10', { costUsd: 1.5 }),
      day('2026-08-11', { costUsd: 1 }),
      day('2026-08-12', { costUsd: 0.5 }),
    ]);

    expect(points.map((point) => point.cumulativeUsd)).toEqual([1.5, 2.5, 3]);
  });

  it('holds the running total flat across a day nobody costed', () => {
    // Deliberately NOT null. A cumulative line is a claim about the days so far,
    // and a break in it would read as "the total is unknown from here on" —
    // whereas what actually happened is that this day added nothing to it.
    const points = toDayPoints([
      day('2026-08-10', { costUsd: 2 }),
      day('2026-08-11', { costUsd: null }),
      day('2026-08-12', { costUsd: 1 }),
    ]);

    expect(points.map((point) => point.cumulativeUsd)).toEqual([2, 2, 3]);
    // …while the day's OWN figure stays unmeasured, so the two charts disagree
    // about nothing: the daily series breaks where the cumulative one flattens.
    expect(points[1]!.costUsd).toBeNull();
  });

  it('labels and dates every day for the axis and the tooltip', () => {
    const [point] = toDayPoints([day('2026-08-10')]);

    expect(point!.label).toContain('Aug');
    expect(point!.title).toContain('2026');
    expect(point!.turns).toBe(2);
  });
});

describe('sumMeasured', () => {
  it('is null only when NEITHER side was reported', () => {
    expect(sumMeasured(null, null)).toBeNull();
    expect(sumMeasured(null, 5)).toBe(5);
    expect(sumMeasured(5, null)).toBe(5);
    expect(sumMeasured(2, 3)).toBe(5);
  });

  it('keeps a measured zero as zero', () => {
    // 0 is a figure somebody took; it must not fall through to "not measured".
    expect(sumMeasured(0, 0)).toBe(0);
  });
});

const group = (key: string | null, overrides: Partial<ChatTotals> = {}) =>
  ({ key, totals: totals(overrides) }) as UsageGroup;

describe('isCosted', () => {
  it('is false when any group reported no cost', () => {
    // The mixed-CLI period. Sizing the bars on cost here would give the cursor
    // group a zero-width bar and erase its turns from the one card about them.
    expect(
      isCosted([
        group('claude', { costUsd: 5 }),
        group('cursor-agent', { costUsd: null }),
      ]),
    ).toBe(false);
  });

  it('is false when a group reported a measured zero', () => {
    // A subscription-priced profile reports real tokens against `costUsd: 0`.
    // Same disappearance as a null, reached by a different route.
    expect(
      isCosted([group('claude', { costUsd: 5 }), group('sub', { costUsd: 0 })]),
    ).toBe(false);
  });

  it('is false for an empty breakdown', () => {
    expect(isCosted([])).toBe(false);
  });

  it('is true only when every group has a positive cost', () => {
    expect(
      isCosted([group('a', { costUsd: 5 }), group('b', { costUsd: 0.01 })]),
    ).toBe(true);
  });
});

describe('toRankedRows', () => {
  const label = (key: string | null) => key ?? 'Unattributed';
  const display = (row: { turns: number }) => `${row.turns}`;

  it('sizes every bar against the LARGEST row, not the total', () => {
    const rows = toRankedRows(
      [
        group('a', { turns: 10 }),
        group('b', { turns: 5 }),
        group('c', { turns: 1 }),
      ],
      label,
      display,
      false,
    );

    // Share-of-largest: the leader fills the track and the rest read against it.
    // Share-of-total would leave every bar short in a breakdown with many small
    // groups, which is exactly when the comparison matters most.
    expect(rows.map((row) => row.fraction)).toEqual([1, 0.5, 0.1]);
  });

  it('falls the whole card back to turns when the breakdown is not costed', () => {
    const groups = [
      group('claude', { turns: 3, costUsd: 5 }),
      group('cursor-agent', { turns: 40, costUsd: null }),
    ];
    const rows = toRankedRows(groups, label, display, isCosted(groups));

    // Sized by TURNS, so the 40-turn group is the long bar — under cost sizing
    // it would have been a zero and vanished.
    expect(rows[1]!.value).toBe(40);
    expect(rows[1]!.fraction).toBe(1);
    expect(rows[0]!.fraction).toBeCloseTo(3 / 40);
  });

  it('survives a breakdown in which everything is zero', () => {
    // No peak to divide by. Every fraction is 0 rather than NaN, which would
    // reach the DOM as `width: NaN%` and collapse the whole list.
    const rows = toRankedRows(
      [group('a', { turns: 0 })],
      label,
      display,
      false,
    );

    expect(rows[0]!.fraction).toBe(0);
    expect(Number.isNaN(rows[0]!.fraction)).toBe(false);
  });

  it('keeps the untruncated key as the row title', () => {
    // The label is truncated by CSS; the title is what a hover recovers, and a
    // long model descriptor is precisely the case the ring could not show.
    const rows = toRankedRows(
      [group('claude-opus-5[thinking=true,context=300k]')],
      (key) => (key ?? '').slice(0, 6),
      display,
      false,
    );

    expect(rows[0]!.label).toBe('claude');
    expect(rows[0]!.title).toBe('claude-opus-5[thinking=true,context=300k]');
  });
});
