import type { ChatTotals, UsageGroup } from '../autogenerated';
import { formatDayLabel, formatDayTitle } from './stats-format';

/**
 * One day, shaped for the charts.
 *
 * Every measured figure stays `number | null`. Recharts draws a null as a GAP
 * and a 0 as a point on the axis, which is exactly the distinction this page is
 * built to keep — so the nulls are carried all the way to the chart rather than
 * being coalesced on the way in.
 */
export interface DayPoint {
  /** `2026-08-10` — stable identity, and what the tooltip dates itself from. */
  date: string;
  /** `Aug 10` — the x-axis tick. */
  label: string;
  /** `Monday, 10 August 2026` — the tooltip heading. */
  title: string;
  turns: number;
  costUsd: number | null;
  inputTokens: number | null;
  outputTokens: number | null;
  /** Input + output, null only when NEITHER was reported. */
  totalTokens: number | null;
  /**
   * Spend accumulated from the start of the period through this day.
   *
   * Never null: a running total is a statement about the days SO FAR, and every
   * day so far contributed whatever it reported. A day nobody costed adds
   * nothing and the line stays flat — which is true — rather than breaking, which
   * would read as "the total is unknown from here on".
   */
  cumulativeUsd: number;
}

/**
 * The daily series, in order, with the running total folded in.
 *
 * One pass rather than a `map` per chart: all three time charts read the same
 * days, and deriving the cumulative separately invites the two to disagree about
 * which days were included.
 */
export function toDayPoints(
  days: readonly { date: string; totals: ChatTotals }[],
): DayPoint[] {
  let running = 0;
  return days.map(({ date, totals }) => {
    running += totals.costUsd ?? 0;
    // A day on which NOTHING RAN is a measured zero, not a hole. The daemon
    // reports every figure as null for such a day simply because it had no
    // events to sum, and reading that as "not measured" broke the line across
    // every quiet weekend — drawing an idle day as an unknown one.
    //
    // The two are genuinely different claims and only the turn count can tell
    // them apart: zero turns means nothing ran, so nothing was spent. A day
    // WITH turns whose cost nobody reported is still unmeasured, still a gap,
    // and that is the case the whole null rule exists for.
    const idle = totals.turns === 0;
    const measured = (value: number | null): number | null =>
      idle ? (value ?? 0) : value;
    return {
      date,
      label: formatDayLabel(date),
      title: formatDayTitle(date),
      turns: totals.turns,
      costUsd: measured(totals.costUsd),
      inputTokens: measured(totals.inputTokens),
      outputTokens: measured(totals.outputTokens),
      totalTokens: idle
        ? 0
        : sumMeasured(totals.inputTokens, totals.outputTokens),
      cumulativeUsd: running,
    };
  });
}

/**
 * Two figures added where either was reported, null where neither was.
 *
 * A plain `(a ?? 0) + (b ?? 0)` turns a day nobody measured into a measured
 * zero, which is the one substitution this page exists not to make.
 */
export function sumMeasured(
  first: number | null,
  second: number | null,
): number | null {
  if (first === null && second === null) {
    return null;
  }
  return (first ?? 0) + (second ?? 0);
}

/** One row of a ranked breakdown — a bar plus everything its label needs. */
/**
 * Input + output, or null when NEITHER was measured.
 *
 * Null is not zero here: cursor-agent reports no token figures at all, and a
 * `0` beside its row would claim a measurement nobody took — the same rule the
 * daemon's own totals follow.
 */
function sumTokens(
  input: number | null | undefined,
  output: number | null | undefined,
): number | null {
  if (input == null && output == null) {
    return null;
  }
  return (input ?? 0) + (output ?? 0);
}

export interface RankedRow {
  /** The group's own key, or `__none__` for the unattributed group. */
  id: string;
  label: string;
  /** The full, untruncated label — the row's hover text. */
  title: string;
  /** What the bar is sized by: spend where every group has one, else turns. */
  value: number;
  /** `value` as a share of the largest row, 0-1. Drives the bar width. */
  fraction: number;
  /** The rendered figure beside the bar. */
  display: string;
  turns: number;
  costUsd: number | null;
  /**
   * Input + output for this group, or null when nothing measured either.
   *
   * The two figures every CLI that reports any reports both, and the two that
   * cannot overlap — `thinkingTokens` is left out because some providers count
   * reasoning inside the output figure, so adding it would double some groups
   * and not others. Same rule the conversation timeline's segments follow.
   */
  tokens: number | null;
}

/**
 * Rank a breakdown's groups, sizing on spend whenever ANY group reported some.
 *
 * The rows arrive ranked by spend (the daemon's own order), so the bars must be
 * sized by spend too: sizing on turns whenever one group lacked a cost — the
 * rule this replaced — drew a $5,900 thread with a sliver of a bar under a
 * $2,400 one at full width, because one unpriced thread anywhere in the column
 * switched the whole column to turn counts. A group with no cost still keeps
 * its row, its token figure and the width floor, so it stays visible as a
 * thread that spent nothing anybody measured. Only a column where NOTHING was
 * priced falls back to turns, since it has no money to rank by at all.
 */
export function toRankedRows(
  groups: readonly UsageGroup[],
  labelOf: (key: string | null, group: UsageGroup) => string,
  formatValue: (row: {
    costUsd: number | null;
    turns: number;
    tokens: number | null;
  }) => string,
  costed: boolean,
  /**
   * The row's hover text. The KEY by default — the full path behind a
   * shortened folder — and the label where the key is an id nobody reads
   * (a thread's run id).
   */
  titleOf: (group: UsageGroup) => string = (group) =>
    group.key ?? labelOf(group.key, group),
): RankedRow[] {
  const rows = groups.map((group) => ({
    id: group.key ?? '__none__',
    label: labelOf(group.key, group),
    title: titleOf(group),
    value: costed ? (group.totals.costUsd ?? 0) : group.totals.turns,
    turns: group.totals.turns,
    costUsd: group.totals.costUsd,
    tokens: sumTokens(group.totals.inputTokens, group.totals.outputTokens),
  }));
  // The largest row, not the SUM: these are bars, and a bar reads against the
  // longest one beside it. Sizing by share-of-total would leave every bar short
  // in a breakdown with many small groups.
  const peak = rows.reduce((max, row) => Math.max(max, row.value), 0);
  return rows.map((row) => ({
    ...row,
    fraction: peak > 0 ? row.value / peak : 0,
    display: formatValue(row),
  }));
}

/** Whether a breakdown can be sized by money at all — see {@link toRankedRows}. */
export function isCosted(groups: readonly UsageGroup[]): boolean {
  return groups.some((group) => (group.totals.costUsd ?? 0) > 0);
}
