import type { ChatTotals, UsageGroup } from '../autogenerated';
import { formatDayLabel, formatDayTitle } from './stats-format';

/**
 * One day, shaped for the charts.
 *
 * Every measured figure stays `number | null`. Recharts draws a null as a GAP
 * and a 0 as a point on the axis, which is exactly the distinction this page is
 * built to keep — so the nulls are carried all the way to the chart rather than
 * being coalesced on the way in.
 */
export interface DayPoint {
  /** `2026-08-10` — stable identity, and what the tooltip dates itself from. */
  date: string;
  /** `Aug 10` — the x-axis tick. */
  label: string;
  /** `Monday, 10 August 2026` — the tooltip heading. */
  title: string;
  turns: number;
  costUsd: number | null;
  inputTokens: number | null;
  outputTokens: number | null;
  /** Input + output, null only when NEITHER was reported. */
  totalTokens: number | null;
  /**
   * Spend accumulated from the start of the period through this day.
   *
   * Never null: a running total is a statement about the days SO FAR, and every
   * day so far contributed whatever it reported. A day nobody costed adds
   * nothing and the line stays flat — which is true — rather than breaking, which
   * would read as "the total is unknown from here on".
   */
  cumulativeUsd: number;
}

/**
 * The daily series, in order, with the running total folded in.
 *
 * One pass rather than a `map` per chart: all three time charts read the same
 * days, and deriving the cumulative separately invites the two to disagree about
 * which days were included.
 */
export function toDayPoints(
  days: readonly { date: string; totals: ChatTotals }[],
): DayPoint[] {
  let running = 0;
  return days.map(({ date, totals }) => {
    running += totals.costUsd ?? 0;
    return {
      date,
      label: formatDayLabel(date),
      title: formatDayTitle(date),
      turns: totals.turns,
      costUsd: totals.costUsd,
      inputTokens: totals.inputTokens,
      outputTokens: totals.outputTokens,
      totalTokens: sumMeasured(totals.inputTokens, totals.outputTokens),
      cumulativeUsd: running,
    };
  });
}

/**
 * Two figures added where either was reported, null where neither was.
 *
 * A plain `(a ?? 0) + (b ?? 0)` turns a day nobody measured into a measured
 * zero, which is the one substitution this page exists not to make.
 */
export function sumMeasured(
  first: number | null,
  second: number | null,
): number | null {
  if (first === null && second === null) {
    return null;
  }
  return (first ?? 0) + (second ?? 0);
}

/** One row of a ranked breakdown — a bar plus everything its label needs. */
export interface RankedRow {
  /** The group's own key, or `__none__` for the unattributed group. */
  id: string;
  label: string;
  /** The full, untruncated label — the row's hover text. */
  title: string;
  /** What the bar is sized by: spend where every group has one, else turns. */
  value: number;
  /** `value` as a share of the largest row, 0-1. Drives the bar width. */
  fraction: number;
  /** The rendered figure beside the bar. */
  display: string;
  turns: number;
  costUsd: number | null;
}

/**
 * Rank a breakdown's groups, sizing on spend only when EVERY group reported
 * some.
 *
 * Sizing on cost whenever ANY group had one erases the others: a null becomes 0,
 * a zero-width bar reads as nothing happening, and in a mixed claude + cursor
 * period the cursor group's turns vanish from the one card that is about them.
 * A group reporting a measured `costUsd: 0` (a subscription-priced profile) does
 * the same thing by a different route, so the test is "> 0 for all", not "some".
 */
export function toRankedRows(
  groups: readonly UsageGroup[],
  labelOf: (key: string | null) => string,
  formatValue: (row: { costUsd: number | null; turns: number }) => string,
  costed: boolean,
): RankedRow[] {
  const rows = groups.map((group) => ({
    id: group.key ?? '__none__',
    label: labelOf(group.key),
    title: group.key ?? labelOf(group.key),
    value: costed ? (group.totals.costUsd ?? 0) : group.totals.turns,
    turns: group.totals.turns,
    costUsd: group.totals.costUsd,
  }));
  // The largest row, not the SUM: these are bars, and a bar reads against the
  // longest one beside it. Sizing by share-of-total would leave every bar short
  // in a breakdown with many small groups.
  const peak = rows.reduce((max, row) => Math.max(max, row.value), 0);
  return rows.map((row) => ({
    ...row,
    fraction: peak > 0 ? row.value / peak : 0,
    display: formatValue(row),
  }));
}

/** Whether a breakdown can be sized by money at all — see {@link toRankedRows}. */
export function isCosted(groups: readonly UsageGroup[]): boolean {
  return (
    groups.length > 0 &&
    groups.every((group) => (group.totals.costUsd ?? 0) > 0)
  );
}
