import type { UsageGroup } from '../autogenerated';
import { formatTokens, formatUsd, markEstimate } from '../chats/agent-activity';

/**
 * The period's spend on lessons reflections, as the daemon summed it
 * (`byPurpose`), or nothing when none ran. Kept out of the breakdowns above,
 * which read the user's own work.
 */
export function LessonsSpendLine({
  groups,
}: {
  groups: readonly UsageGroup[];
}): React.JSX.Element | null {
  const lessons = groups.find((group) => group.key === 'lessons');
  if (lessons === undefined) {
    return null;
  }
  const { costUsd, estimatedCostUsd, turns, inputTokens, outputTokens } =
    lessons.totals;
  const tokens =
    inputTokens === null && outputTokens === null
      ? null
      : (inputTokens ?? 0) + (outputTokens ?? 0);
  const spend = [
    costUsd === null ? null : markEstimate(formatUsd(costUsd), estimatedCostUsd),
    tokens === null ? null : `${formatTokens(tokens)} tokens`,
    `${turns} ${turns === 1 ? 'turn' : 'turns'}`,
  ].filter((part): part is string => part !== null);
  return (
    <p
      data-slot="lessons-spend"
      className="px-1 text-xs text-muted-foreground">
      <span className="font-medium text-foreground">Lessons</span> —
      reflections spent {spend.join(' · ')} in this period.
    </p>
  );
}
