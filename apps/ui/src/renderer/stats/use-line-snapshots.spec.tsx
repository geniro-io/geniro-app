// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type {
  ChangesBaseUnreachable,
  ChangesTotals,
  GitHead,
} from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { RunDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type {
  DaemonClient,
  RunStatusEvent,
  UsageRecordedEvent,
} from '../daemon-client';
import { answerLineFlush } from './line-flush';
import { MEASURE_DEBOUNCE_MS, useLineSnapshots } from './use-line-snapshots';

const mocks = vi.hoisted(() => ({
  remote: { on: false },
  report: vi.fn(),
}));

vi.mock('../remote/remote-session', () => ({
  isRemoteRuntime: () => mocks.remote.on,
}));

vi.mock('../debug/report-ui-errors', () => ({
  reportRendererIssue: mocks.report,
}));

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

type Thread = Pick<RunDto, 'id' | 'cwd'>;

/** The folder's baseline, which every thread in it is measured against. */
const SHA = 'a'.repeat(40);
const THREAD: Thread = { id: 'run-a', cwd: '/work/app' };

const getChangesTotals =
  vi.fn<
    (
      dir: string,
      sha: string,
    ) => Promise<ChangesTotals | ChangesBaseUnreachable | null>
  >();
const getGitHead = vi.fn<(dir: string) => Promise<GitHead | null>>();
/** The repository the thread's folder belongs to. */
const REPO = '/work';
const recordLineSnapshot = vi.fn(
  async (_request: { lineSnapshotDto: unknown }) => ({ recorded: true }),
);
const resolveLineBaseline = vi.fn(
  async (_request: {
    lineBaselineRequestDto: {
      runId: string;
      root: string;
      branch: string | null;
      staleBaseSha?: string;
    };
  }): Promise<{ baseSha: string | null }> => ({ baseSha: SHA }),
);

let listener: ((event: UsageRecordedEvent) => void) | null = null;
const onUsageRecorded = vi.fn((next: (event: UsageRecordedEvent) => void) => {
  listener = next;
  return () => {
    listener = null;
  };
});
let statusListener: ((event: RunStatusEvent) => void) | null = null;
const onRunStatus = vi.fn((next: (event: RunStatusEvent) => void) => {
  statusListener = next;
  return () => {
    statusListener = null;
  };
});
const client = { onUsageRecorded, onRunStatus } as unknown as DaemonClient;
const apis = {
  stats: { recordLineSnapshot, resolveLineBaseline },
} as unknown as DaemonApis;

/** Every preload channel the hook reads, with the ones a test overrides. */
function preload(
  overrides: Parameters<typeof createPreloadStub>[0] = {},
): ReturnType<typeof createPreloadStub> {
  return createPreloadStub({ getChangesTotals, getGitHead, ...overrides });
}

let root: Root | null = null;
let container: HTMLDivElement | null = null;

/** The component the hook is mounted in — it renders nothing. */
function Probe({ runs }: { runs: readonly Thread[] }): null {
  useLineSnapshots({ apis, client, runs });
  return null;
}

async function mount(runs: readonly Thread[]): Promise<void> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<Probe runs={runs} />);
  });
}

/** A turn of `runId` finishing — the daemon's `usage_recorded`. */
async function turnEnds(runId: string): Promise<void> {
  await act(async () => {
    listener?.({
      runId,
      nodeId: null,
      occurredAt: new Date().toISOString(),
      turn: true,
    });
  });
}

/** Let the clock run, and every promise a timer released, settle. */
async function elapse(ms: number): Promise<void> {
  await act(async () => {
    await vi.advanceTimersByTimeAsync(ms);
  });
}

/** The `lineSnapshotDto` of every post, in the order the daemon received them. */
function postedBodies(): unknown[] {
  return recordLineSnapshot.mock.calls.map(
    ([request]) => request.lineSnapshotDto,
  );
}

beforeEach(() => {
  vi.useFakeTimers();
  mocks.remote.on = false;
  mocks.report.mockReset();
  getChangesTotals.mockReset();
  getGitHead.mockReset();
  getGitHead.mockResolvedValue({ root: REPO, branch: 'main' });
  recordLineSnapshot.mockClear();
  resolveLineBaseline.mockClear();
  resolveLineBaseline.mockImplementation(async () => ({ baseSha: SHA }));
  onUsageRecorded.mockClear();
  onRunStatus.mockClear();
  window.geniro = preload();
});

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

describe('useLineSnapshots', () => {
  it('posts a measurement still waiting out its settle window when the quit asks, and answers only after the post', async () => {
    // The quit stops the daemon once every window has answered, so an answer that came before the post
    // would let the post reach a daemon already gone.
    const order: string[] = [];
    const release: { posted?: () => void } = {};
    window.geniro = preload({
      lineMeasurementsFlushed: async (requestId: string) => {
        order.push(`answered ${requestId}`);
      },
    });
    getChangesTotals.mockResolvedValue({
      linesAdded: 4,
      linesRemoved: 1,
      partial: false,
    });
    recordLineSnapshot.mockImplementationOnce(
      () =>
        new Promise((resolve) => {
          release.posted = () => {
            order.push('posted');
            resolve({ recorded: true });
          };
        }),
    );
    await mount([THREAD]);
    await turnEnds('run-a');
    expect(getChangesTotals).not.toHaveBeenCalled();

    await act(async () => {
      answerLineFlush('quit-1');
    });
    await elapse(0);
    // The post is still out, so the answer waits for it.
    expect(getChangesTotals).toHaveBeenCalledWith('/work/app', SHA);
    expect(order).toEqual([]);

    await act(async () => {
      release.posted?.();
    });
    await elapse(0);
    expect(order).toEqual(['posted', 'answered quit-1']);
    // The measurement the quit took is not taken again when its settle window would have closed.
    await elapse(MEASURE_DEBOUNCE_MS * 2);
    expect(getChangesTotals).toHaveBeenCalledTimes(1);
  });

  it('answers a quit only after a read that the settle window had already handed off has posted', async () => {
    const order: string[] = [];
    const release: {
      totals?: (value: ChangesTotals | ChangesBaseUnreachable | null) => void;
    } = {};
    window.geniro = preload({
      lineMeasurementsFlushed: async (requestId: string) => {
        order.push(`answered ${requestId}`);
      },
    });
    getChangesTotals.mockImplementationOnce(
      () =>
        new Promise<ChangesTotals | ChangesBaseUnreachable | null>(
          (resolve) => {
            release.totals = resolve;
          },
        ),
    );
    recordLineSnapshot.mockImplementationOnce(async () => {
      order.push('posted');
      return { recorded: true };
    });
    await mount([THREAD]);
    await turnEnds('run-a');
    // The settle window closes with the read still in flight: the timer is gone, the read is not.
    await elapse(MEASURE_DEBOUNCE_MS);
    expect(getChangesTotals).toHaveBeenCalledTimes(1);

    await act(async () => {
      answerLineFlush('quit-2');
    });
    await elapse(0);
    expect(order).toEqual([]);

    await act(async () => {
      release.totals?.({ linesAdded: 4, linesRemoved: 1, partial: false });
    });
    await elapse(0);
    expect(order).toEqual(['posted', 'answered quit-2']);
  });

  it("posts the folder's totals once a thread's turn is recorded, measured against the folder's baseline", async () => {
    getChangesTotals.mockResolvedValue({
      linesAdded: 12,
      linesRemoved: 3,
      partial: false,
    });
    await mount([THREAD]);

    const turnAt = Date.now();
    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(resolveLineBaseline).toHaveBeenCalledWith({
      lineBaselineRequestDto: { runId: 'run-a', root: REPO, branch: 'main' },
    });
    expect(getChangesTotals).toHaveBeenCalledWith('/work/app', SHA);
    expect(recordLineSnapshot).toHaveBeenCalledWith({
      lineSnapshotDto: {
        runId: 'run-a',
        baseSha: SHA,
        branch: 'main',
        root: REPO,
        linesAdded: 12,
        linesRemoved: 3,
        partial: false,
        occurredAt: new Date(turnAt + MEASURE_DEBOUNCE_MS).toISOString(),
      },
    });
  });

  it('stamps a total with the moment its read started, not the moment it was posted', async () => {
    // The daemon orders totals by this stamp. A read that takes half a second must not
    // move its total later than the read it started after.
    getChangesTotals.mockImplementation(
      () =>
        new Promise((resolve) =>
          setTimeout(
            () => resolve({ linesAdded: 1, linesRemoved: 0, partial: false }),
            500,
          ),
        ),
    );
    await mount([THREAD]);

    const turnAt = Date.now();
    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS + 500);

    expect(postedBodies()).toEqual([
      expect.objectContaining({
        occurredAt: new Date(turnAt + MEASURE_DEBOUNCE_MS).toISOString(),
      }),
    ]);
  });

  it('orders two reads of one thread by when they started, even when the older finishes last', async () => {
    // The first read is still in flight when the second turn's read starts and finishes.
    // Posting the older total last must not make it the latest: its stamp is earlier.
    let finishFirst: (totals: ChangesTotals) => void = () => undefined;
    getChangesTotals
      .mockReturnValueOnce(
        new Promise<ChangesTotals>((resolve) => {
          finishFirst = resolve;
        }),
      )
      .mockResolvedValueOnce({
        linesAdded: 110,
        linesRemoved: 0,
        partial: false,
      });
    await mount([THREAD]);

    const firstStartedAt = Date.now() + MEASURE_DEBOUNCE_MS;
    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);
    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);
    await act(async () => {
      finishFirst({ linesAdded: 100, linesRemoved: 0, partial: false });
      await vi.advanceTimersByTimeAsync(0);
    });

    expect(postedBodies()).toEqual([
      expect.objectContaining({
        linesAdded: 110,
        occurredAt: new Date(
          firstStartedAt + MEASURE_DEBOUNCE_MS,
        ).toISOString(),
      }),
      expect.objectContaining({
        linesAdded: 100,
        occurredAt: new Date(firstStartedAt).toISOString(),
      }),
    ]);
  });

  it('posts nothing again while the totals are unchanged, and posts a change as a total', async () => {
    // The post itself writes a usage event, which comes back here. Without this
    // check every post would measure and post again, forever.
    getChangesTotals.mockResolvedValue({
      linesAdded: 12,
      linesRemoved: 3,
      partial: false,
    });
    await mount([THREAD]);
    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);

    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);
    expect(recordLineSnapshot).toHaveBeenCalledTimes(1);

    getChangesTotals.mockResolvedValue({
      linesAdded: 20,
      linesRemoved: 3,
      partial: false,
    });
    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);
    expect(recordLineSnapshot).toHaveBeenCalledTimes(2);
    expect(recordLineSnapshot).toHaveBeenLastCalledWith({
      lineSnapshotDto: {
        runId: 'run-a',
        baseSha: SHA,
        branch: 'main',
        root: REPO,
        linesAdded: 20,
        linesRemoved: 3,
        partial: false,
        occurredAt: expect.any(String),
      },
    });
  });

  it('waits for a burst of turns to settle, then reads the thread once', async () => {
    getChangesTotals.mockResolvedValue({
      linesAdded: 1,
      linesRemoved: 0,
      partial: false,
    });
    await mount([THREAD]);

    // A workflow ends a turn per node, a second apart. Each turn restarts the
    // settle window, so none of the three is measured on its own.
    await turnEnds('run-a');
    await elapse(1_000);
    await turnEnds('run-a');
    await elapse(1_000);
    await turnEnds('run-a');
    await elapse(1_000);
    expect(getChangesTotals).not.toHaveBeenCalled();

    await elapse(MEASURE_DEBOUNCE_MS);
    expect(getChangesTotals).toHaveBeenCalledTimes(1);
  });

  it('measures a turn still waiting out its settle window when the window closes', async () => {
    // Dropping it would leave that turn's lines out for good: a thread's totals only
    // move when a later turn measures them again.
    getChangesTotals.mockResolvedValue({
      linesAdded: 7,
      linesRemoved: 2,
      partial: false,
    });
    await mount([THREAD]);
    await turnEnds('run-a');

    act(() => {
      root?.unmount();
    });
    root = null;
    await act(async () => {
      await vi.advanceTimersByTimeAsync(0);
    });

    expect(getChangesTotals).toHaveBeenCalledWith('/work/app', SHA);
    expect(recordLineSnapshot).toHaveBeenCalledTimes(1);
  });

  it('skips a thread with no folder, a folder with no commit, and one the daemon has no baseline for', async () => {
    getGitHead.mockImplementation(async (dir) =>
      dir === '/plain' ? null : { root: REPO, branch: 'main' },
    );
    resolveLineBaseline.mockImplementation(async () => ({ baseSha: null }));
    await mount([
      { id: 'run-bare', cwd: null },
      { id: 'run-plain', cwd: '/plain' },
      { id: 'run-unbased', cwd: '/work/app' },
    ]);

    await turnEnds('run-bare');
    await turnEnds('run-plain');
    await turnEnds('run-unbased');
    await elapse(MEASURE_DEBOUNCE_MS);

    // A plain folder never asks for a baseline; the folder with no baseline asks and stops.
    expect(resolveLineBaseline).toHaveBeenCalledTimes(1);
    expect(getChangesTotals).not.toHaveBeenCalled();
    expect(recordLineSnapshot).not.toHaveBeenCalled();
  });

  it('reports a baseline the folder has left as stale once, and measures against its replacement', async () => {
    const NEXT = 'b'.repeat(40);
    resolveLineBaseline
      .mockImplementationOnce(async () => ({ baseSha: SHA }))
      .mockImplementationOnce(async () => ({ baseSha: NEXT }));
    getChangesTotals
      .mockResolvedValueOnce({ baseUnreachable: true })
      .mockResolvedValueOnce({
        linesAdded: 3,
        linesRemoved: 0,
        partial: false,
      });
    await mount([THREAD]);

    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(resolveLineBaseline).toHaveBeenLastCalledWith({
      lineBaselineRequestDto: {
        runId: 'run-a',
        root: REPO,
        branch: 'main',
        staleBaseSha: SHA,
      },
    });
    expect(getChangesTotals).toHaveBeenLastCalledWith('/work/app', NEXT);
    expect(postedBodies()).toEqual([
      expect.objectContaining({ baseSha: NEXT, linesAdded: 3 }),
    ]);
  });

  it('posts nothing when even the replacement baseline cannot be measured from', async () => {
    getChangesTotals.mockResolvedValue({ baseUnreachable: true });
    await mount([THREAD]);

    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(resolveLineBaseline).toHaveBeenCalledTimes(2);
    expect(recordLineSnapshot).not.toHaveBeenCalled();
  });

  it('posts a folder total once when two of its threads measure the same figures', async () => {
    getChangesTotals.mockResolvedValue({
      linesAdded: 9,
      linesRemoved: 1,
      partial: false,
    });
    await mount([THREAD, { id: 'run-b', cwd: '/work/app' }]);

    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);
    await turnEnds('run-b');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(getChangesTotals).toHaveBeenCalledTimes(2);
    expect(recordLineSnapshot).toHaveBeenCalledTimes(1);
  });

  it('posts one total for a repository whose threads work in different folders of it', async () => {
    // Both folders read the same repository root, so the second read is the same series
    // and an unchanged total is not posted again.
    getChangesTotals.mockResolvedValue({
      linesAdded: 9,
      linesRemoved: 1,
      partial: false,
    });
    await mount([THREAD, { id: 'run-b', cwd: '/work/lib' }]);

    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);
    await turnEnds('run-b');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(getChangesTotals).toHaveBeenCalledTimes(2);
    expect(postedBodies()).toEqual([
      expect.objectContaining({ runId: 'run-a', root: REPO }),
    ]);
  });

  it('measures a folder once when several of its threads finish together', async () => {
    getChangesTotals.mockResolvedValue({
      linesAdded: 9,
      linesRemoved: 1,
      partial: false,
    });
    await mount([THREAD, { id: 'run-b', cwd: '/work/app' }]);

    await turnEnds('run-a');
    await turnEnds('run-b');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(getGitHead).toHaveBeenCalledTimes(1);
    expect(getChangesTotals).toHaveBeenCalledTimes(1);
    // Measured for the thread whose turn ended last.
    expect(postedBodies()).toEqual([
      expect.objectContaining({ runId: 'run-b' }),
    ]);
  });

  it('asks the folder’s other threads for a baseline when the newest cannot set one', async () => {
    // A thread with no start commit cannot set a baseline. Its turn ending last must not
    // leave the other thread's work unposted until that thread's next turn.
    resolveLineBaseline.mockImplementation(async (request) => ({
      baseSha: request.lineBaselineRequestDto.runId === 'run-b' ? null : SHA,
    }));
    getChangesTotals.mockResolvedValue({
      linesAdded: 4,
      linesRemoved: 0,
      partial: false,
    });
    await mount([THREAD, { id: 'run-b', cwd: '/work/app' }]);

    await turnEnds('run-a');
    await turnEnds('run-b');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(postedBodies()).toEqual([
      expect.objectContaining({ runId: 'run-a', linesAdded: 4 }),
    ]);
  });

  it('asks the next thread when the newest one is refused, as a thread deleted inside the window is', async () => {
    resolveLineBaseline.mockImplementation(async (request) => {
      if (request.lineBaselineRequestDto.runId === 'run-b') {
        throw new Error('daemon GET failed (404): no thread has that run id');
      }
      return { baseSha: SHA };
    });
    getChangesTotals.mockResolvedValue({
      linesAdded: 6,
      linesRemoved: 0,
      partial: false,
    });
    await mount([THREAD, { id: 'run-b', cwd: '/work/app' }]);

    await turnEnds('run-a');
    await turnEnds('run-b');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(postedBodies()).toEqual([
      expect.objectContaining({ runId: 'run-a', linesAdded: 6 }),
    ]);
    expect(mocks.report).not.toHaveBeenCalled();
  });

  it('measures a run that settles, since a stopped or failed turn records no usage', async () => {
    getChangesTotals.mockResolvedValue({
      linesAdded: 2,
      linesRemoved: 0,
      partial: false,
    });
    await mount([THREAD]);

    await act(async () => {
      // An activity announce says nothing about whether the run is still going, and a run
      // still working has not finished changing the folder.
      statusListener?.({ runId: 'run-a', status: null } as RunStatusEvent);
      statusListener?.({
        runId: 'run-a',
        status: 'running',
      } as RunStatusEvent);
    });
    await elapse(MEASURE_DEBOUNCE_MS);
    expect(getChangesTotals).not.toHaveBeenCalled();

    await act(async () => {
      statusListener?.({
        runId: 'run-a',
        status: 'cancelled',
      } as RunStatusEvent);
    });
    await elapse(MEASURE_DEBOUNCE_MS);
    expect(recordLineSnapshot).toHaveBeenCalledTimes(1);
  });

  it('posts nothing when the totals cannot be read, never a zero', async () => {
    // Null is "could not be measured" — the commit is gone, the folder moved.
    // Posting it as zero would say the thread changed nothing.
    getChangesTotals.mockResolvedValue(null);
    await mount([THREAD]);

    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(getChangesTotals).toHaveBeenCalledTimes(1);
    expect(recordLineSnapshot).not.toHaveBeenCalled();
  });

  it('reports a read that throws to the daemon log, and posts nothing for it', async () => {
    getChangesTotals.mockRejectedValueOnce(new Error('git failed'));
    await mount([THREAD]);

    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(mocks.report).toHaveBeenCalledWith('could not measure a thread', {
      runId: 'run-a',
      error: 'git failed',
    });
    expect(recordLineSnapshot).not.toHaveBeenCalled();
  });

  it('does not measure again on a snapshot’s own announcement, which is not a turn', async () => {
    getChangesTotals.mockResolvedValue({
      linesAdded: 12,
      linesRemoved: 3,
      partial: false,
    });
    await mount([THREAD]);

    await act(async () => {
      listener?.({
        runId: 'run-a',
        nodeId: null,
        occurredAt: new Date().toISOString(),
        turn: false,
      });
    });
    await elapse(MEASURE_DEBOUNCE_MS * 2);

    expect(getChangesTotals).not.toHaveBeenCalled();
    expect(recordLineSnapshot).not.toHaveBeenCalled();
  });

  it('measures nothing from a remote device, where the Mac’s own window does', async () => {
    mocks.remote.on = true;
    await mount([THREAD]);

    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(onUsageRecorded).not.toHaveBeenCalled();
    expect(getChangesTotals).not.toHaveBeenCalled();
  });

  it('reports a failed post to the daemon log', async () => {
    // Nothing reaches the user: a banner about a background measurement would ask
    // them to act on nothing, and the Stats figure catches up on the next turn.
    getChangesTotals.mockResolvedValue({
      linesAdded: 4,
      linesRemoved: 1,
      partial: false,
    });
    recordLineSnapshot.mockRejectedValueOnce(
      new Error('daemon POST failed (500)'),
    );
    await mount([THREAD]);

    await turnEnds('run-a');
    await elapse(MEASURE_DEBOUNCE_MS);

    expect(mocks.report).toHaveBeenCalledWith(
      'could not post line totals for a thread',
      { runId: 'run-a', error: 'daemon POST failed (500)' },
    );
  });
});
