import { useEffect, useRef } from 'react';

import type {
  ChangesBaseUnreachable,
  ChangesTotals,
} from '../../shared/contracts';
import type { RunDto } from '../autogenerated';
import { isSettledRunStatus } from '../chats/run-status';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { reportRendererIssue } from '../debug/report-ui-errors';
import { isRemoteRuntime } from '../remote/remote-session';
import { registerLineFlush } from './line-flush';

/**
 * How long a burst of finished turns is allowed to settle before its thread is
 * measured. A workflow writes a ledger row per node as the nodes' turns end, so
 * the measurement belongs after the last of them, not after each.
 */
export const MEASURE_DEBOUNCE_MS = 2_000;

function isUnreachable(
  reading: ChangesTotals | ChangesBaseUnreachable | null,
): reading is ChangesBaseUnreachable {
  return reading !== null && 'baseUnreachable' in reading;
}

/**
 * Keeps each folder's line totals on the daemon current — one measurement per
 * finished turn of any thread working in it.
 *
 * The daemon cannot count lines: every git call belongs to the Electron process,
 * so this window measures the folder and posts the TOTAL, never a delta. It
 * measures against the BASELINE of the folder's repository and branch
 * (`resolveLineBaseline`), the one commit every thread there is measured
 * against — keyed by the repository root, since the totals cover the whole
 * repository and a thread in a subfolder measures the same changes — so work two
 * threads share is one series and is counted once. A baseline the folder has
 * left behind (a rewritten history, a checkout that no longer descends from it)
 * is reported stale once, and the daemon replaces it with this thread's start.
 * A missed event moves when a change is counted, not how many there were.
 *
 * Mounted from `Chats`, not the shell, because a thread's folder is on the run
 * rows that screen holds. Silent on a remote device: the Mac's own window
 * measures the Mac's folders, and a phone measuring them too would post the same
 * totals twice and run git twice.
 *
 * A post writes a usage event of its own, which comes back here as a non-turn
 * event and is ignored. A run SETTLING is measured too, because a turn that was
 * stopped or failed writes no usage row and still changed the folder.
 *
 * Several threads finishing in one folder together measure it once: the settle
 * window is per folder, not per thread.
 *
 * A quit asks each window to post what it still holds before the daemon stops
 * (`answerLineFlush`). The flush is registered here, so it waits for every
 * measurement this hook has started, whether a settle window handed it off or
 * the quit asked for it.
 */
export function useLineSnapshots({
  apis,
  client,
  runs,
}: {
  apis: DaemonApis | null;
  client: DaemonClient | null;
  /** The thread rows this window holds — the folder comes from them. */
  runs: readonly Pick<RunDto, 'id' | 'cwd'>[];
}): void {
  // Read through a ref so a run list that refreshes on every sidebar update does
  // not re-subscribe the listener, and the measurement always sees the latest row.
  const runsRef = useRef(runs);
  runsRef.current = runs;

  useEffect(() => {
    if (!client || !apis || isRemoteRuntime()) {
      return;
    }
    // Captured here, past the guard, so the measurement below does not have to
    // re-narrow a parameter that a closure is free to see as null.
    const { stats } = apis;
    // The last total posted per series (folder, branch and baseline), so a turn that
    // changed nothing posts nothing, whichever of the folder's threads it was.
    const posted = new Map<string, ChangesTotals>();
    // Per folder: the threads whose turns ended in the window, newest last, and the window.
    const timers = new Map<
      string,
      { runIds: string[]; timer: ReturnType<typeof setTimeout> }
    >();
    // Every measurement under way, so a quit can wait on each one rather than on
    // the timers alone: a read a settle window already handed off is in neither.
    const inFlight = new Set<Promise<void>>();

    /**
     * Measures the folder `cwd` on behalf of one of `runIds`, the threads whose turns ended
     * there. The newest is asked for the baseline first; a thread that cannot set one (it has
     * no start commit) hands the question to the next, so the others' work is not left
     * waiting for their next turn.
     */
    async function measure(
      cwd: string,
      runIds: readonly string[],
    ): Promise<void> {
      let runId = runIds[runIds.length - 1] ?? '';
      // Stamped when the read STARTS, and sent with the total. Two reads of one folder
      // can finish out of order, and the daemon orders totals by this time rather than
      // by when they arrive, so the older read stays the older total.
      const measuredAt = new Date().toISOString();
      let root: string;
      let branch: string | null;
      let baseSha: string | null;
      let reading: ChangesTotals | ChangesBaseUnreachable | null;
      try {
        const head = await window.geniro.getGitHead(cwd);
        // Not a repository, or one with no commit: nothing to measure against.
        if (head === null) {
          return;
        }
        ({ root, branch } = head);
        baseSha = null;
        // A thread deleted inside the window is refused by the daemon; the next one is
        // asked rather than the folder going unmeasured.
        let refused: unknown = null;
        for (const candidate of [...runIds].reverse()) {
          runId = candidate;
          try {
            baseSha = (
              await stats.resolveLineBaseline({
                lineBaselineRequestDto: { runId, root, branch },
              })
            ).baseSha;
          } catch (error) {
            refused = error;
            continue;
          }
          if (baseSha !== null) {
            break;
          }
        }
        if (baseSha === null) {
          if (refused !== null) {
            throw refused;
          }
          return;
        }
        reading = await window.geniro.getChangesTotals(cwd, baseSha);
        if (isUnreachable(reading)) {
          baseSha = (
            await stats.resolveLineBaseline({
              lineBaselineRequestDto: {
                runId,
                root,
                branch,
                staleBaseSha: baseSha,
              },
            })
          ).baseSha;
          if (baseSha === null) {
            return;
          }
          reading = await window.geniro.getChangesTotals(cwd, baseSha);
        }
      } catch (error) {
        reportLineFailure('could not measure a thread', runId, error);
        return;
      }
      // A null is a measurement that could not be taken — git failed, the folder
      // moved — and an unmeasured total is never posted as zero.
      if (reading === null || isUnreachable(reading)) {
        return;
      }
      const series = JSON.stringify([root, branch, baseSha]);
      const last = posted.get(series);
      if (
        last &&
        last.linesAdded === reading.linesAdded &&
        last.linesRemoved === reading.linesRemoved &&
        last.partial === reading.partial
      ) {
        return;
      }
      try {
        await stats.recordLineSnapshot({
          lineSnapshotDto: {
            runId,
            baseSha,
            branch,
            root,
            linesAdded: reading.linesAdded,
            linesRemoved: reading.linesRemoved,
            partial: reading.partial,
            occurredAt: measuredAt,
          },
        });
        posted.set(series, reading);
      } catch (error) {
        reportLineFailure(
          'could not post line totals for a thread',
          runId,
          error,
        );
      }
    }

    /** Starts a measurement nothing waits on, and keeps it tracked until it has finished. */
    function start(cwd: string, runIds: readonly string[]): void {
      const pending = measure(cwd, runIds);
      inFlight.add(pending);
      void pending.finally(() => {
        inFlight.delete(pending);
      });
    }

    /**
     * Trailing debounce per FOLDER: the last event of a burst is the one worth measuring,
     * since the total is the same whichever one it is read after — and the same whichever of
     * the folder's threads it is read for, so several threads ending together measure once.
     */
    function schedule(runId: string): void {
      const cwd = runsRef.current.find(
        (candidate) => candidate.id === runId,
      )?.cwd;
      if (!cwd) {
        return;
      }
      const pending = timers.get(cwd);
      if (pending !== undefined) {
        clearTimeout(pending.timer);
      }
      const runIds = [
        ...(pending?.runIds ?? []).filter((id) => id !== runId),
        runId,
      ];
      timers.set(cwd, {
        runIds,
        timer: setTimeout(() => {
          timers.delete(cwd);
          start(cwd, runIds);
        }, MEASURE_DEBOUNCE_MS),
      });
    }

    /**
     * Measures every thread a finished turn is still waiting on, now, and waits until every measurement
     * under way has posted — the ones the settle windows handed off as well. The quit asks for this before
     * it stops the daemon (see `answerLineFlush`), so a turn that ended a moment before the quit is counted.
     */
    async function flushPending(): Promise<void> {
      const waiting = [...timers.entries()];
      timers.clear();
      for (const [cwd, { runIds, timer }] of waiting) {
        clearTimeout(timer);
        start(cwd, runIds);
      }
      while (inFlight.size > 0) {
        await Promise.all(inFlight);
      }
    }

    const unsubscribeUsage = client.onUsageRecorded((event) => {
      // A snapshot's own announcement is not a turn. Measuring after it would re-read the folder
      // for the total it just wrote, and a folder that keeps changing would keep writing a row per
      // debounce window.
      if (event.turn) {
        schedule(event.runId);
      }
    });
    const unsubscribeStatus = client.onRunStatus((event) => {
      // A turn that was stopped or failed records no usage, and may still have edited files.
      if (event.status !== null && isSettledRunStatus(event.status)) {
        schedule(event.runId);
      }
    });

    const unregisterFlush = registerLineFlush(flushPending);

    return () => {
      unsubscribeUsage();
      unsubscribeStatus();
      unregisterFlush();
      // A turn still waiting out its settle window is measured now, not dropped: a
      // folder's totals move only when a later turn measures them again, so a dropped
      // last turn would leave its lines out until then.
      for (const [cwd, { runIds, timer }] of timers) {
        clearTimeout(timer);
        start(cwd, runIds);
      }
      timers.clear();
    };
  }, [apis, client]);
}

/**
 * A line-total failure goes to the daemon's log beside everything else the window
 * reports, and never to a banner: the Stats page's own figure is simply one
 * measurement behind until the next turn, and a banner about a background
 * measurement would ask the user to act on nothing.
 */
function reportLineFailure(
  message: string,
  runId: string,
  error: unknown,
): void {
  reportRendererIssue(message, {
    runId,
    error: error instanceof Error ? error.message : String(error),
  });
}
