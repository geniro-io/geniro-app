import { useEffect, useRef } from 'react';

import type { ChangesTotals } from '../../shared/contracts';
import type { RunDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { reportRendererIssue } from '../debug/report-ui-errors';
import { isRemoteRuntime } from '../remote/remote-session';
import { registerLineFlush } from './line-flush';

/**
 * How long a burst of finished turns is allowed to settle before its thread is
 * measured. A workflow writes a ledger row per node as the nodes' turns end, so
 * the measurement belongs after the last of them, not after each.
 */
export const MEASURE_DEBOUNCE_MS = 2_000;

/**
 * Keeps each thread's line totals on the daemon current — one measurement per
 * finished turn.
 *
 * The daemon cannot count lines: every git call belongs to the Electron process,
 * so this window measures a thread's own changes against its start commit and
 * posts the TOTAL. Never a delta. A missed event moves when a change is counted,
 * not how many there were, which is why an unmeasured turn costs timing and
 * nothing else.
 *
 * Mounted from `Chats`, not the shell, because a thread's folder and start commit
 * are on the run rows that screen holds. Silent on a remote device: the Mac's own
 * window measures the Mac's folders, and a phone measuring them too would post
 * the same totals twice and run git twice.
 *
 * The post writes a usage event of its own, which comes back here and reads the
 * same total again. The unchanged check is what absorbs that echo, so it costs one
 * measurement and never a second row.
 *
 * A quit asks each window to post what it still holds before the daemon stops
 * (`answerLineFlush`). The flush is registered here, so it waits for every
 * measurement this hook has started, whether a settle window handed it off or
 * the quit asked for it.
 */
export function useLineSnapshots({
  apis,
  client,
  runs,
}: {
  apis: DaemonApis | null;
  client: DaemonClient | null;
  /** The thread rows this window holds — the folder and start commit come from them. */
  runs: readonly Pick<RunDto, 'id' | 'cwd' | 'startSha'>[];
}): void {
  // Read through a ref so a run list that refreshes on every sidebar update does
  // not re-subscribe the listener, and the measurement always sees the latest row.
  const runsRef = useRef(runs);
  runsRef.current = runs;

  useEffect(() => {
    if (!client || !apis || isRemoteRuntime()) {
      return;
    }
    // Captured here, past the guard, so the measurement below does not have to
    // re-narrow a parameter that a closure is free to see as null.
    const { stats } = apis;
    const posted = new Map<string, ChangesTotals>();
    const timers = new Map<string, ReturnType<typeof setTimeout>>();
    // Every measurement under way, so a quit can wait on each one rather than on
    // the timers alone: a read a settle window already handed off is in neither.
    const inFlight = new Set<Promise<void>>();

    async function measure(runId: string): Promise<void> {
      const run = runsRef.current.find((candidate) => candidate.id === runId);
      // A thread with no folder, or no start commit, has no baseline to measure
      // its changes against — nothing to post, and nothing wrong about that.
      if (!run?.cwd || !run.startSha) {
        return;
      }
      // Stamped when the read STARTS, and sent with the total. Two reads of one thread
      // can finish out of order, and the daemon orders totals by this time rather than
      // by when they arrive, so the older read stays the older total.
      const measuredAt = new Date().toISOString();
      let totals: ChangesTotals | null;
      try {
        totals = await window.geniro.getChangesTotals(run.cwd, run.startSha);
      } catch (error) {
        reportLineFailure('could not measure a thread', runId, error);
        return;
      }
      // A null is a measurement that could not be taken — the commit is gone, the
      // folder moved — and an unmeasured total is never posted as zero.
      if (totals === null) {
        return;
      }
      const last = posted.get(runId);
      if (
        last &&
        last.linesAdded === totals.linesAdded &&
        last.linesRemoved === totals.linesRemoved &&
        last.partial === totals.partial
      ) {
        return;
      }
      try {
        await stats.recordLineSnapshot({
          lineSnapshotDto: {
            runId,
            linesAdded: totals.linesAdded,
            linesRemoved: totals.linesRemoved,
            partial: totals.partial,
            occurredAt: measuredAt,
          },
        });
        posted.set(runId, totals);
      } catch (error) {
        reportLineFailure(
          'could not post line totals for a thread',
          runId,
          error,
        );
      }
    }

    /** Starts a measurement nothing waits on, and keeps it tracked until it has finished. */
    function start(runId: string): void {
      const pending = measure(runId);
      inFlight.add(pending);
      void pending.finally(() => {
        inFlight.delete(pending);
      });
    }

    /**
     * Measures every thread a finished turn is still waiting on, now, and waits until every measurement
     * under way has posted — the ones the settle windows handed off as well. The quit asks for this before
     * it stops the daemon (see `answerLineFlush`), so a turn that ended a moment before the quit is counted.
     */
    async function flushPending(): Promise<void> {
      const waiting = [...timers.keys()];
      for (const timer of timers.values()) {
        clearTimeout(timer);
      }
      timers.clear();
      for (const runId of waiting) {
        start(runId);
      }
      while (inFlight.size > 0) {
        await Promise.all(inFlight);
      }
    }

    const unsubscribe = client.onUsageRecorded((event) => {
      // A snapshot's own announcement is not a turn. Measuring after it would re-read the folder
      // for the total it just wrote, and a folder that keeps changing would keep writing a row per
      // debounce window.
      if (!event.turn) {
        return;
      }
      // Trailing debounce per thread: the last turn of a burst is the one worth
      // measuring, since the total is the same whichever turn it is read after.
      const pending = timers.get(event.runId);
      if (pending !== undefined) {
        clearTimeout(pending);
      }
      timers.set(
        event.runId,
        setTimeout(() => {
          timers.delete(event.runId);
          start(event.runId);
        }, MEASURE_DEBOUNCE_MS),
      );
    });

    const unregisterFlush = registerLineFlush(flushPending);

    return () => {
      unsubscribe();
      unregisterFlush();
      // A turn still waiting out its settle window is measured now, not dropped: a
      // thread's totals move only when a later turn measures them again, so a dropped
      // last turn would leave its lines out for good.
      for (const [runId, timer] of timers) {
        clearTimeout(timer);
        start(runId);
      }
      timers.clear();
    };
  }, [apis, client]);
}

/**
 * A line-total failure goes to the daemon's log beside everything else the window
 * reports, and never to a banner: the Stats page's own figure is simply one
 * measurement behind until the next turn, and a banner about a background
 * measurement would ask the user to act on nothing.
 */
function reportLineFailure(
  message: string,
  runId: string,
  error: unknown,
): void {
  reportRendererIssue(message, {
    runId,
    error: error instanceof Error ? error.message : String(error),
  });
}
