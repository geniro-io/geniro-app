import { useCallback, useEffect, useState } from 'react';

import type { UsageStatsDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';

/** The periods the page offers, and how far back each one reaches. */
export const STATS_PERIODS = [
  { id: '7d', label: '7 days', days: 7 },
  { id: '30d', label: '30 days', days: 30 },
  { id: '90d', label: '90 days', days: 90 },
  { id: 'all', label: 'All time', days: null },
] as const;

export type StatsPeriodId = (typeof STATS_PERIODS)[number]['id'];

/**
 * The half-open range a period covers, in the machine's own timezone.
 *
 * The lower bound is a local MIDNIGHT rather than "now minus N×24h": the daemon
 * buckets by calendar day, so a range starting mid-afternoon would make the
 * oldest column a part-day and draw a short bar that means nothing. "All time"
 * names no lower bound at all and lets the daemon answer from its own first
 * recorded turn.
 */
export function periodRange(
  period: StatsPeriodId,
  now: Date,
): {
  from?: string;
  to: string;
} {
  const spec = STATS_PERIODS.find((entry) => entry.id === period);
  const to = new Date(now);
  if (!spec?.days) {
    return { to: to.toISOString() };
  }
  const from = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  // N days INCLUDING today, so "7 days" is a week of columns rather than eight.
  from.setDate(from.getDate() - (spec.days - 1));
  return { from: from.toISOString(), to: to.toISOString() };
}

export interface StatsState {
  data: UsageStatsDto | null;
  /** True only while the FIRST load of a period is in flight. */
  loading: boolean;
  error: string | null;
  /** Fetch this period again — what a Retry control does. */
  reload: () => void;
  /**
   * Clear the error WITHOUT refetching.
   *
   * Separate from {@link reload} because the banner's close control has to be
   * able to close it: wiring the X to a refetch left the strip unclearable for
   * as long as the daemon stayed down, which is the failure the close control
   * exists to prevent.
   */
  dismiss: () => void;
}

/**
 * One period's usage statistics.
 *
 * The previous period's figures stay on screen while a new one loads, so
 * switching from 30 days to 90 does not blank the page and reflow every card —
 * `loading` is only true when there is nothing to show yet.
 */
export function useStats(
  apis: DaemonApis | null,
  period: StatsPeriodId,
): StatsState {
  const [data, setData] = useState<UsageStatsDto | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [nonce, setNonce] = useState(0);

  const reload = useCallback(() => setNonce((value) => value + 1), []);
  const dismiss = useCallback(() => setError(null), []);

  useEffect(() => {
    if (!apis) {
      return;
    }
    let cancelled = false;
    setError(null);
    // The range is computed at REQUEST time, not at render time: a window left
    // open overnight would otherwise keep asking for yesterday's period.
    const range = periodRange(period, new Date());
    apis.stats
      .readUsageStats(range)
      .then((stats) => {
        if (!cancelled) {
          setData(stats);
          setLoading(false);
        }
      })
      .catch((err: unknown) => {
        if (cancelled) {
          return;
        }
        setError(err instanceof Error ? err.message : String(err));
        setLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [apis, period, nonce]);

  return { data, loading, error, reload, dismiss };
}
