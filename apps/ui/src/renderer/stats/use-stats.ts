import { useCallback, useEffect, useRef, useState } from 'react';

import type { UsageStatsDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

/** The periods the page offers, and how far back each one reaches. */
export const STATS_PERIODS = [
  { id: '7d', label: '7 days', days: 7 },
  { id: '30d', label: '30 days', days: 30 },
  { id: '90d', label: '90 days', days: 90 },
  { id: 'all', label: 'All time', days: null },
] as const;

export type StatsPeriodId = (typeof STATS_PERIODS)[number]['id'];

/**
 * The half-open range a period covers, in the machine's own timezone.
 *
 * The lower bound is a local MIDNIGHT rather than "now minus N×24h": the daemon
 * buckets by calendar day, so a range starting mid-afternoon would make the
 * oldest column a part-day and draw a short bar that means nothing. "All time"
 * names no lower bound at all and lets the daemon answer from its own first
 * recorded turn.
 */
export function periodRange(
  period: StatsPeriodId,
  now: Date,
): {
  from?: string;
  to: string;
} {
  const spec = STATS_PERIODS.find((entry) => entry.id === period);
  const to = new Date(now);
  if (!spec?.days) {
    return { to: to.toISOString() };
  }
  const from = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  // N days INCLUDING today, so "7 days" is a week of columns rather than eight.
  from.setDate(from.getDate() - (spec.days - 1));
  return { from: from.toISOString(), to: to.toISOString() };
}

/**
 * How long a burst of finished turns is allowed to accumulate before the page
 * re-reads. A workflow settles its nodes within a second or two of each other,
 * and each one writes a ledger row — without this the fan-out's last node would
 * be the fifth refetch of the same period.
 */
const LIVE_REFRESH_DEBOUNCE_MS = 750;

export interface StatsState {
  data: UsageStatsDto | null;
  /** True only while the FIRST load of a period is in flight. */
  loading: boolean;
  error: string | null;
  /** Fetch this period again — what a Retry control does. */
  reload: () => void;
  /**
   * Clear the error WITHOUT refetching.
   *
   * Separate from {@link reload} because the banner's close control has to be
   * able to close it: wiring the X to a refetch left the strip unclearable for
   * as long as the daemon stayed down, which is the failure the close control
   * exists to prevent.
   */
  dismiss: () => void;
}

/**
 * One period's usage statistics, kept CURRENT while the page is open.
 *
 * The previous period's figures stay on screen while a new one loads, so
 * switching from 30 days to 90 does not blank the page and reflow every card —
 * `loading` is only true when there is nothing to show yet.
 *
 * **Live, and pushed rather than polled.** The daemon announces each turn it
 * writes to the ledger (`usage_recorded`), and this re-reads the period a beat
 * later. A poll was the alternative and is worse in both directions: on an idle
 * machine it asks a question whose answer cannot have changed, and on a busy one
 * it is still up to an interval stale — while the page was, before this, stale
 * for as long as it stayed open, which is precisely how a screen about spending
 * comes to sit at a number the user has already moved past.
 *
 * The refetch is a refetch and not a patch: the figures are sums the DAEMON
 * computes (see `StatsService`), so adding a pushed row to them client-side
 * would keep a second set of books that any dropped event silently corrupts.
 */
export function useStats(
  apis: DaemonApis | null,
  period: StatsPeriodId,
  /**
   * The live channel. Optional — without one the page still works, it simply
   * shows the reading it was opened on.
   */
  client?: DaemonClient | null,
): StatsState {
  const [data, setData] = useState<UsageStatsDto | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [nonce, setNonce] = useState(0);

  const reload = useCallback(() => setNonce((value) => value + 1), []);
  const dismiss = useCallback(() => setError(null), []);

  useEffect(() => {
    if (!apis) {
      return;
    }
    let cancelled = false;
    setError(null);
    // The range is computed at REQUEST time, not at render time: a window left
    // open overnight would otherwise keep asking for yesterday's period.
    const range = periodRange(period, new Date());
    apis.stats
      .readUsageStats(range)
      .then((stats) => {
        if (!cancelled) {
          setData(stats);
          setLoading(false);
        }
      })
      .catch((err: unknown) => {
        if (cancelled) {
          return;
        }
        setError(err instanceof Error ? err.message : String(err));
        setLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [apis, period, nonce]);

  // A `reload` that is stable for the effect below, so re-subscribing does not
  // depend on the render that produced the callback.
  const reloadRef = useRef(reload);
  reloadRef.current = reload;

  useEffect(() => {
    if (!client) {
      return;
    }
    let timer: ReturnType<typeof setTimeout> | null = null;
    const unsubscribe = client.onUsageRecorded(() => {
      // Trailing debounce: the LAST event of a burst is the one worth reading
      // after, since the read is of the whole period either way.
      if (timer !== null) {
        clearTimeout(timer);
      }
      timer = setTimeout(() => {
        timer = null;
        reloadRef.current();
      }, LIVE_REFRESH_DEBOUNCE_MS);
    });
    return () => {
      unsubscribe();
      if (timer !== null) {
        // Cleared on unmount, or a page the user has navigated away from
        // refetches once more into state nothing is rendering.
        clearTimeout(timer);
      }
    };
  }, [client]);

  return { data, loading, error, reload, dismiss };
}
