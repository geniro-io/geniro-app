async function board(): Promise<HTMLDivElement> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<Tasks handle={handle} client={null} active />);
  });
  return container;
}

const cardNode = (el: HTMLElement): HTMLButtonElement =>
  el.querySelector('[data-task-id="t1"]') as HTMLButtonElement;

const columnNamed = (el: HTMLElement, name: string): HTMLElement =>
  [...el.querySelectorAll('[role="group"]')].find((node) =>
    (node.getAttribute('aria-label') ?? '').startsWith(name),
  ) as HTMLElement;

const headerTrigger = (el: HTMLElement): HTMLButtonElement =>
  el.querySelector<HTMLButtonElement>('[data-menu-trigger]')!;

const options = (el: HTMLElement): HTMLElement[] => [
  ...el.querySelectorAll<HTMLElement>('[role="option"]'),
];

describe('Tasks board', () => {
  it('renders a column per status the daemon defines', async () => {
    const el = await board();

    // Keyed off the daemon's own vocabulary rather than a literal 6: a status
    // added there must grow a column, and a hardcoded count would keep passing
    // while the board silently stopped being able to show some of its cards.
    expect(el.querySelectorAll('[role="group"]').length).toBe(
      Object.keys(TaskStatus).length,
    );
  });

  it('moves a card on drop, telling the daemon which column it left', async () => {
    const el = await board();
    const dt = { setData: vi.fn(), dropEffect: '', effectAllowed: '' };

    await act(async () => {
      cardNode(el).dispatchEvent(
        Object.assign(new Event('dragstart', { bubbles: true }), {
          dataTransfer: dt,
        }),
      );
    });
    const target = columnNamed(el, 'In progress');
    await act(async () => {
      target.dispatchEvent(
        Object.assign(new Event('dragover', { bubbles: true }), {
          dataTransfer: dt,
        }),
      );
      target.dispatchEvent(
        Object.assign(new Event('drop', { bubbles: true }), {
          dataTransfer: dt,
        }),
      );
    });

    expect(mocks.moveTaskStatus).toHaveBeenCalledWith({
      taskId: 't1',
      moveTaskStatusDto: { from: 'todo', to: 'in_progress' },
    });
  });

  it('moves a focused card with alt and an arrow, and keeps focus on it', async () => {
    // The board must never be drag-only. The move re-parents the card into
    // another column's subtree, so without the refocus the node that had focus
    // is unmounted and the next arrow press goes nowhere.
    const el = await board();
    cardNode(el).focus();

    await act(async () => {
      cardNode(el).dispatchEvent(
        new KeyboardEvent('keydown', {
          key: 'ArrowRight',
          altKey: true,
          bubbles: true,
        }),
      );
    });

    expect(mocks.moveTaskStatus).toHaveBeenCalledWith({
      taskId: 't1',
      moveTaskStatusDto: { from: 'todo', to: 'in_progress' },
    });
    expect(document.activeElement).toBe(cardNode(el));
  });

  it('re-seeds the detail panel when a different card is opened', async () => {
    // The panel seeds its title and description drafts from props at MOUNT.
    // Rendered unkeyed it is one reused instance, so opening B after A left
    // A's text in the field — and blur wrote A's title onto B, cross-card data
    // loss with no undo. The header naming B while the input held A was the
    // only tell.
    mocks.reconcileTasks.mockResolvedValue([
      card({ id: 'a', title: 'Alpha' }),
      card({ id: 'b', title: 'Bravo', status: 'done' }),
    ]);
    const el = await board();

    const open = async (id: string): Promise<void> => {
      const node = el.querySelector(
        `[data-task-id="${id}"]`,
      ) as HTMLButtonElement;
      await act(async () => {
        node.click();
      });
    };
    await open('a');
    // Put the panel into edit mode on A, so a reused instance would carry it.
    const titleButton = (): HTMLButtonElement =>
      [...(el.querySelector('aside')?.querySelectorAll('button') ?? [])].find(
        (node) => (node.textContent ?? '').length > 0,
      ) as HTMLButtonElement;
    await act(async () => {
      titleButton().click();
    });
    await open('b');

    const aside = el.querySelector('aside');
    expect(aside?.getAttribute('aria-label')).toContain('Bravo');
    // No stray input holding Alpha's title.
    const input = aside?.querySelector('input');
    expect(input?.value ?? '').not.toContain('Alpha');
  });

  it('leaves the card alone on a bare arrow, which still has to move focus through the cards', async () => {
    const el = await board();

    await act(async () => {
      cardNode(el).dispatchEvent(
        new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }),
      );
    });

    expect(mocks.moveTaskStatus).not.toHaveBeenCalled();
  });

  it('puts the card back and shows the reason when the move is refused', async () => {
    mocks.moveTaskStatus.mockRejectedValue(
      new Error(
        'task t1 is in done, not todo — it moved since you last read it',
      ),
    );
    const el = await board();
    cardNode(el).focus();

    await act(async () => {
      cardNode(el).dispatchEvent(
        new KeyboardEvent('keydown', {
          key: 'ArrowRight',
          altKey: true,
          bubbles: true,
        }),
      );
    });

    // Back in its own column, and the reason on screen — never a silent
    // snap-back, which reads as the app losing the move.
    expect(columnNamed(el, 'To do').contains(cardNode(el))).toBe(true);
    expect(el.textContent).toContain('it moved since you last read it');
  });
});

describe('the drop target', () => {
  it('accepts the drag by preventing the default, and lights up', async () => {
    // A dragover that does not preventDefault is one the browser reads as "not
    // a drop target" — the drop never fires and the card animates home. The
    // earlier test only proved the move happened; this proves the mechanism.
    const el = await board();
    const dt = { setData: vi.fn(), dropEffect: '', effectAllowed: '' };
    await act(async () => {
      cardNode(el).dispatchEvent(
        Object.assign(new Event('dragstart', { bubbles: true }), {
          dataTransfer: dt,
        }),
      );
    });

    const target = columnNamed(el, 'In progress');
    const over = Object.assign(
      new Event('dragover', { bubbles: true, cancelable: true }),
      { dataTransfer: dt },
    );
    await act(async () => {
      target.dispatchEvent(over);
    });

    expect(over.defaultPrevented).toBe(true);
    expect(dt.dropEffect).toBe('move');
  });

  it('does not accept a drag this board did not start', async () => {
    // The foreign-drag guard returns BEFORE preventDefault, so a file dragged
    // in from the desktop is not silently swallowed by a column.
    const el = await board();
    const target = columnNamed(el, 'In progress');
    const over = Object.assign(
      new Event('dragover', { bubbles: true, cancelable: true }),
      { dataTransfer: { setData: vi.fn(), dropEffect: '' } },
    );

    await act(async () => {
      target.dispatchEvent(over);
    });

    expect(over.defaultPrevented).toBe(false);
  });
});

describe('the column surface', () => {
  it('files a task into the column whose + was pressed', async () => {
    // The whole point of a per-column add: pressing In review means a task
    // that STARTS there, not one that starts in Backlog and has to be dragged.
    const el = await board();

    const add = [...el.querySelectorAll('button')].find(
      (node) => node.getAttribute('aria-label') === 'Add a task to In review',
    ) as HTMLButtonElement;
    await act(async () => {
      add.click();
    });
    const title = document.body.querySelector(
      '#new-task-title',
    ) as HTMLInputElement;
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )?.set;
    await act(async () => {
      setter?.call(title, 'Needs review');
      title.dispatchEvent(new Event('input', { bubbles: true }));
    });
    const submit = [...document.body.querySelectorAll('button')].find(
      (node) => node.textContent === 'Add task',
    ) as HTMLButtonElement;
    await act(async () => {
      submit.click();
    });

    expect(mocks.createTask).toHaveBeenCalledWith({
      createTaskDto: expect.objectContaining({
        title: 'Needs review',
        status: 'in_review',
      }),
    });
  });

  it('leaves the status unstated when the board-level New task is used', async () => {
    // Absent, not null: the daemon defaults an unstated status to `backlog`,
    // and sending one explicitly would make the board own a default the
    // daemon already owns.
    const el = await board();

    const add = [...el.querySelectorAll('button')].find((node) =>
      (node.textContent ?? '').includes('New task'),
    ) as HTMLButtonElement;
    await act(async () => {
      add.click();
    });
    const title = document.body.querySelector(
      '#new-task-title',
    ) as HTMLInputElement;
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )?.set;
    await act(async () => {
      setter?.call(title, 'Anywhere');
      title.dispatchEvent(new Event('input', { bubbles: true }));
    });
    const submit = [...document.body.querySelectorAll('button')].find(
      (node) => node.textContent === 'Add task',
    ) as HTMLButtonElement;
    await act(async () => {
      submit.click();
    });

    const sent = mocks.createTask.mock.calls[0]?.[0] as {
      createTaskDto: Record<string, unknown>;
    };
    expect('status' in sent.createTaskDto).toBe(false);
  });

  it('says where to drop while a card is over the column', async () => {
    // An empty column reads "No tasks" until a drag arrives, and then has to
    // say it is a target — with the dashed placeholder border gone, the words
    // and the surface tint are what remain.
    const el = await board();
    const dt = { setData: vi.fn(), dropEffect: '', effectAllowed: '' };
    await act(async () => {
      cardNode(el).dispatchEvent(
        Object.assign(new Event('dragstart', { bubbles: true }), {
          dataTransfer: dt,
        }),
      );
    });

    const target = columnNamed(el, 'In progress');
    await act(async () => {
      target.dispatchEvent(
        Object.assign(
          new Event('dragover', { bubbles: true, cancelable: true }),
          { dataTransfer: dt },
        ),
      );
    });

    expect(target.textContent).toContain('Drop here');
  });

  it('switches the board from the header picker', async () => {
    const other = aProject({ id: 'p2', name: 'Other', folder: '/tmp/other' });
    mocks.listProjects.mockResolvedValue([project, other]);
    const el = await board();

    await act(async () => {
      headerTrigger(el).click();
    });
    const row = options(el).find((node) => node.textContent?.includes('Other'));
    expect(row).toBeDefined();
    await act(async () => {
      row!.click();
    });

    expect(mocks.reconcileTasks).toHaveBeenCalledWith({
      reconcileTasksDto: { projectId: 'p2' },
    });
  });

  // The rail carried `New project` along its bottom edge. Deleting the rail
  // without rehoming it would leave a user with no projects unable to make one
  // from this screen at all, and nothing about the board would look broken.
  it('opens the new-project dialog from the picker', async () => {
    const el = await board();

    await act(async () => {
      headerTrigger(el).click();
    });
    const row = options(el).find((node) =>
      node.textContent?.includes('New project'),
    );
    expect(row).toBeDefined();
    await act(async () => {
      row!.click();
    });

    expect(
      [...document.querySelectorAll('label')].some((node) =>
        node.textContent?.includes('Folder'),
      ),
    ).toBe(true);
  });

  it('still offers a new project, and refuses a new task, with none at all', async () => {
    mocks.listProjects.mockResolvedValue([]);
    const el = await board();

    await act(async () => {
      headerTrigger(el).click();
    });
    expect(options(el).map((node) => node.textContent?.trim())).toStrictEqual([
      'New project…',
    ]);

    const add = [...el.querySelectorAll('button')].find((node) =>
      node.textContent?.includes('New task'),
    );
    expect(add?.disabled).toBe(true);
  });

  // Every other picker in the app sits near the FOOT of the window, so `Menu`
  // defaults to opening upward — and it clamps rather than flips, with the
  // clamp floored, so a trigger at the top of the window simply runs its rows
  // off the edge. Measured in the running app before the fix: three rows open
  // in the DOM with a sliver of the panel on screen. jsdom computes no layout,
  // so the emitted class is the observable — and it IS the mechanism here,
  // not a proxy for it.
  it('opens the project menu downward, away from the top of the window', async () => {
    const el = await board();

    await act(async () => {
      headerTrigger(el).click();
    });

    const panel = el.querySelector('[data-slot="menu-panel"]');
    expect(panel).not.toBeNull();
    expect(panel!.className).toContain('top-full');
    expect(panel!.className).not.toContain('bottom-full');
  });

  // The folder used to sit beside the control as its own muted span, which
  // said the same fact twice — the project is named after the folder. It now
  // rides inside the trigger, in a quieter treatment, and appears ONCE.
  it('names the folder inside the trigger, and only there', async () => {
    // A distinctive leaf: the default fixture's is `/w`, one letter, and
    // "New task" contains it — a substring check against that passes on the
    // button beside the picker and proves nothing.
    mocks.listProjects.mockResolvedValue([
      aProject({ folder: '/tmp/board-fixture' }),
    ]);
    const el = await board();

    const trigger = headerTrigger(el);
    expect(trigger.textContent).toContain('One');
    expect(trigger.textContent).toContain('board-fixture');

    const header = el.querySelector('header')!;
    const outside = [...header.children].filter(
      (node) => !node.contains(trigger),
    );
    expect(
      outside.some((node) =>
        (node.textContent ?? '').includes('board-fixture'),
      ),
    ).toBe(false);
  });

  // `items-center` centres BOXES, and a descender-free label sits high in its
  // own line box, so a square glyph beside it lands visibly low — measured on
  // the running app at 5.5 device px for the picker and 5.0 for the button.
  // jsdom computes no layout, so the class IS the correction, not a proxy.
  it('lifts the header glyphs off the box centre', async () => {
    const el = await board();

    const icons = [...el.querySelectorAll('header svg')];
    expect(icons.length).toBeGreaterThan(0);
    // The chevron is the menu's own affordance and centres on the box, not on
    // the label — only the two LEADING glyphs are corrected.
    const lifted = icons.filter((node) =>
      (node.getAttribute('class') ?? '').includes('-translate-y-'),
    );
    // ONE, not two: the picker's glyph sits beside a two-line block and
    // centres on it, so only the button's plus — beside a single
    // descender-free baseline — needs the correction.
    expect(lifted.length).toBe(1);
  });

  // Side by side, a long pair truncated BOTH halves —
  // `Harn… geniro-claude-har…` — losing the half that identifies the project.
  // Stacked, each line gets the control's full width. jsdom lays nothing out,
  // so the flex direction is the observable and it IS the rule.
  it('stacks the folder under the project name', async () => {
    mocks.listProjects.mockResolvedValue([
      aProject({ name: 'Harness', folder: '/home/user/geniro-claude-harness' }),
    ]);
    const el = await board();

    const trigger = headerTrigger(el);
    const name = [...trigger.querySelectorAll('span')].find(
      (node) => node.textContent === 'Harness',
    );
    const folder = [...trigger.querySelectorAll('span')].find(
      (node) => node.textContent === 'geniro-claude-harness',
    );
    expect(name).toBeDefined();
    expect(folder).toBeDefined();
    expect(name!.parentElement).toBe(folder!.parentElement);
    expect(name!.parentElement!.className).toContain('flex-col');
    // The name leads: a reader takes the identity before the qualifier.
    expect(
      name!.compareDocumentPosition(folder!) & Node.DOCUMENT_POSITION_FOLLOWING,
    ).toBeTruthy();
  });
  const openDetail = async (el: HTMLElement): Promise<void> => {
    await act(async () => {
      cardNode(el).click();
    });
  };

  // Matches the control whatever it currently SAYS — its label carries the
  // state (`Run task` / `Starting…` / `Running`), so keying on one spelling
  // would silently stop finding it in exactly the states worth asserting on.
  const runButton = (el: HTMLElement): HTMLButtonElement =>
    [...el.querySelectorAll('button')].find((node) =>
      /^(Run task|Starting…|Running)$/.test((node.textContent ?? '').trim()),
    ) as HTMLButtonElement;

  it('runs a task: worktree first, then the agent inside it', async () => {
    const el = await board();
    await openDetail(el);

    await act(async () => {
      runButton(el).click();
    });

    // The worktree must exist before the daemon is asked to run in it — the
    // daemon runs no git and cannot make one for itself.
    expect(window.geniro.prepareTaskWorktree).toHaveBeenCalledWith({
      taskId: 't1',
      folder: '/w',
    });
    expect(mocks.startTaskRun).toHaveBeenCalledWith(
      expect.objectContaining({
        taskId: 't1',
        startTaskRunDto: expect.objectContaining({
          cwd: '/tmp/geniro-worktrees/t1',
          branch: 'geniro/task-t1',
          // What THIS board believed the card was in, so a start against a
          // card someone else already moved is refused rather than applied.
          from: TaskStatus.Todo,
        }),
      }),
    );
  });

  it('removes the worktree it just made when the run cannot be started', async () => {
    mocks.startTaskRun.mockRejectedValueOnce(new Error('daemon said no'));
    const el = await board();
    await openDetail(el);

    await act(async () => {
      runButton(el).click();
    });

    // Otherwise every failed press leaves a checkout on disk that nothing
    // collects: the boot reaper only ever sees what a previous SESSION left.
    expect(window.geniro.pruneTaskWorktree).toHaveBeenCalledWith('t1');
    expect(el.textContent).toContain('daemon said no');
  });

  it('does not start a run when the worktree could not be made', async () => {
    window.geniro = createPreloadStub();
    window.geniro.prepareTaskWorktree = vi.fn(() =>
      Promise.resolve({
        ok: false,
        path: null,
        branch: null,
        error: 'fatal: not a git repository',
      }),
    );
    const el = await board();
    await openDetail(el);

    await act(async () => {
      runButton(el).click();
    });

    expect(mocks.startTaskRun).not.toHaveBeenCalled();
    expect(el.textContent).toContain('fatal: not a git repository');
  });

  it('refuses to start a card an agent is already working', async () => {
    mocks.reconcileTasks.mockResolvedValue([
      card({ status: TaskStatus.InProgress, runId: 'run-1' }),
    ]);
    const el = await board();
    await openDetail(el);

    expect(runButton(el).disabled).toBe(true);
    // The reason is VISIBLE text, not a title: a disabled button carries
    // `pointer-events-none`, so a tooltip on it can never be hovered.
    expect(el.textContent).toContain('An agent is working this task');
  });

  it('offers Run again once the card has come back for review', async () => {
    // It still names the run that did the work — that is its history, not a
    // claim on it, so a reviewed card must be startable again.
    mocks.reconcileTasks.mockResolvedValue([
      card({ status: TaskStatus.InReview, runId: 'run-1' }),
    ]);
    const el = await board();
    await openDetail(el);

    expect(runButton(el).disabled).toBe(false);
  });
});
