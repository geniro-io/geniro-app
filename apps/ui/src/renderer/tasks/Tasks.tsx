/**
 * Which card of a column a drag over it would land ahead of — the first card
 * whose vertical midpoint is below the pointer — or null for the column's end.
 */
function dropSlotBefore(
  event: React.DragEvent<HTMLElement>,
  columnIds: readonly string[],
): string | null {
  const cards = [
    ...event.currentTarget.querySelectorAll<HTMLElement>('[data-task-id]'),
  ];
  for (const card of cards) {
    const id = card.dataset.taskId;
    if (id === undefined || !columnIds.includes(id)) {
      continue;
    }
    const rect = card.getBoundingClientRect();
    if (event.clientY < rect.top + rect.height / 2) {
      return id;
    }
  }
  return null;
}

export function Tasks({
  handle,
  client,
  active,
  onOpenThread,
}: {
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  /**
   * Take the app to a card's own conversation. Absent in a harness, which is
   * why the call sites are optional — the board owns no route of its own, the
   * nav rail being `App`'s.
   */
  onOpenThread?: (runId: string) => void;
  /**
   * Whether this screen is the one on show. The board is latch-mounted and
   * never remounts, so becoming visible again is the only moment it can
   * notice a project deleted from Settings while it was hidden.
   */
  active: boolean;
}): React.JSX.Element {
  const [apis, setApis] = useState<DaemonApis | null>(null);
  useEffect(() => {
    setApis(handle ? createDaemonApis(handle) : null);
  }, [handle]);

  const board = useBoard(apis, client);
  const refreshProjects = board.refreshProjects;
  useEffect(() => {
    if (active) {
      refreshProjects();
    }
  }, [active, refreshProjects]);

  /**
   * The workflow library, for the two target pickers (the project chip, and a
   * card's own Agent row).
   *
   * Re-read on the `active` transition rather than once at mount: this screen
   * is latch-mounted and the library is editable on the Workflows page while
   * it stays mounted, so a mount-only read would go on offering yesterday's
   * workflows for the life of the window. A failed read is the EMPTY list and
   * never an error on this screen — a board is perfectly usable while the
   * pickers offer less than they could.
   */
  const [workflows, setWorkflows] = useState<TargetWorkflow[]>([]);
  const [cliDetections, setCliDetections] = useState<CliDetection[] | null>(
    null,
  );
  useEffect(() => {
    if (!active || apis === null) {
      return;
    }
    void apis.workflows
      .listWorkflows()
      .then(setWorkflows)
      .catch(() => {
        setWorkflows([]);
      });
  }, [active, apis]);
  /**
   * Which CLIs this machine has, read ONCE — mount-only, the shape `Chats`
   * itself uses for its own copy of this same probe. Keying it to `active`
   * would spawn five child processes and two authenticated network calls on
   * every Chats→Tasks visit, for a list consumed only inside pickers the user
   * has not opened yet. This board is latch-mounted for the life of the window
   * (see `App.tsx`), so "once" here already covers a fresh launch; a CLI
   * installed mid-session is picked up the next time the app is opened.
   */
  useEffect(() => {
    void window.geniro
      .detectClis()
      .then(setCliDetections)
      .catch(() => {
        setCliDetections(null);
      });
  }, []);
  /**
   * The user's NAMED agent profiles, and the config directories they have
   * reached for before — read once, on the same terms as the probe above.
   *
   * Both run-config panels draw their Profile row from these. Without them the
   * picker offers the native chooser and nothing else, so a board could only
   * ever name a profile by walking to its directory again — while the composer,
   * over the same control, lists them by name and colour.
   */
  const [configProfiles, setConfigProfiles] = useState<
    readonly ConfigProfile[]
  >([]);
  const [recentConfigDirs, setRecentConfigDirs] = useState<readonly string[]>(
    [],
  );
  useEffect(() => {
    void window.geniro
      .getSettings()
      .then((settings) => {
        setConfigProfiles(settings.configProfiles ?? []);
        setRecentConfigDirs(settings.recentConfigDirs ?? []);
      })
      .catch(() => {
        // The empty defaults ARE the degrade: the picker keeps its native
        // chooser, so a profile is still reachable by path. Nothing here can
        // act on the failure, and the settings read is the debug log's own.
        setConfigProfiles([]);
        setRecentConfigDirs([]);
      });
  }, []);
  const [draggingTaskId, setDraggingTaskId] = useState<string | null>(null);
  const [dropTarget, setDropTarget] = useState<string | null>(null);
  /** The card a drag would land ahead of in `dropTarget`; null = its end. */
  const [dropBeforeTaskId, setDropBeforeTaskId] = useState<string | null>(null);
  const [openTaskId, setOpenTaskId] = useState<string | null>(null);
  const [newProjectOpen, setNewProjectOpen] = useState(false);
  /**
   * The board's run settings, held HERE because two controls open them: the
   * header chip they belong to, and the intake column's explanation of why
   * nothing can start — which is where a user with an agent-less board
   * actually is when they need them.
   */
  const [runConfigOpen, setRunConfigOpen] = useState(false);
  /**
   * The card whose Run was pressed, while the dialog asks what to add.
   *
   * A press no longer starts the agent on its own: every run may carry a
   * sentence of its own, and a card that has been worked before is continued
   * rather than restarted — so the press opens the dialog and the dialog
   * starts the run. The autopilot is untouched by this; it starts runs from
   * the main process and has nobody to ask.
   */
  const [runTaskId, setRunTaskId] = useState<string | null>(null);
  const [newTaskOpen, setNewTaskOpen] = useState(false);
  /**
   * Which column the new-task dialog files into.
   *
   * Held here rather than inside the dialog because the column's own `+` sets
   * it: pressing the one on In review means a task that starts there, not one
   * that starts in Backlog and has to be dragged.
   */
  const [newTaskStatus, setNewTaskStatus] = useState<string | null>(null);

  // A keyboard move re-parents the card into another column's subtree, so the
  // node that had focus is unmounted and focus falls to <body>. Re-claim it on
  // the card's new node, or the next arrow press goes nowhere.
  const refocusTaskId = useRef<string | null>(null);
  useEffect(() => {
    const id = refocusTaskId.current;
    if (id === null) {
      return;
    }
    refocusTaskId.current = null;
    // Scanned rather than interpolated into a selector: the id is daemon
    // data, so a selector built from it would need escaping to be correct.
    const node = [
      ...document.querySelectorAll<HTMLElement>('[data-task-id]'),
    ].find((el) => el.dataset.taskId === id);
    node?.focus();
  }, [board.tasks]);

  const onCardKeyDown = useCallback(
    (event: React.KeyboardEvent<HTMLButtonElement>, taskId: string) => {
      // Alt rather than a bare arrow: the cards are buttons in a scrolling
      // pane, and a bare arrow has to stay available for moving THROUGH them.
      if (!event.altKey) {
        return;
      }
      const task = board.tasks.find((row) => row.id === taskId);
      if (task === undefined) {
        return;
      }
      if (event.key === 'ArrowUp' || event.key === 'ArrowDown') {
        const column = board.tasks
          .filter((row) => row.status === task.status)
          .map((row) => row.id);
        const at = column.indexOf(taskId);
        const target = event.key === 'ArrowUp' ? at - 1 : at + 1;
        if (target < 0 || target >= column.length) {
          return;
        }
        event.preventDefault();
        refocusTaskId.current = taskId;
        // Down lands ahead of the card after the neighbour, or at the end.
        const before =
          event.key === 'ArrowUp'
            ? (column[target] ?? null)
            : (column[target + 1] ?? null);
        void board.placeTask(taskId, task.status, before);
        return;
      }
      const step =
        event.key === 'ArrowLeft' ? -1 : event.key === 'ArrowRight' ? 1 : 0;
      if (step === 0) {
        return;
      }
      const from = BOARD_COLUMNS.indexOf(task.status);
      // -1 is a status this build does not know, and `-1 + 1` indexes the FIRST
      // column — a nudge rightwards would silently reclassify the card as
      // Backlog and tell the daemon it came from a column it was never in.
      if (from === -1) {
        return;
      }
      const next = BOARD_COLUMNS[from + step];
      if (next === undefined) {
        return;
      }
      event.preventDefault();
      refocusTaskId.current = taskId;
      void board.moveTask(taskId, next);
    },
    [board],
  );

  const projectId = board.selectedProjectId;
  const openTask = board.tasks.find((row) => row.id === openTaskId) ?? null;

  const [labelsOpen, setLabelsOpen] = useState(false);
  /**
   * Labels that carry instructions, and the project each is scoped to (null =
   * every project), so a card's editor offers them even before any card uses
   * one — pinning such a label is how its instructions attach.
   */
  const [instructionLabels, setInstructionLabels] = useState<
    { label: string; projectId: string | null }[]
  >([]);
  const [labelsNonce, setLabelsNonce] = useState(0);
  useEffect(() => {
    if (!active || apis === null) {
      return;
    }
    // A slower earlier read must not overwrite the answer to a later one.
    let cancelled = false;
    // This board's rows plus the global ones; every project's on the
    // every-project board, whose cards come from all of them.
    void apis.labelInstructions
      .listLabelInstructions(projectId === null ? {} : { projectId })
      .then((rows) => {
        if (!cancelled) {
          setInstructionLabels(
            rows.map((row) => ({ label: row.label, projectId: row.projectId })),
          );
        }
      })
      .catch(() => {
        // Only suggestions ride on this read; the dialog reports its own
        // failures, so an empty list is the whole of the degrade here.
        if (!cancelled) {
          setInstructionLabels([]);
        }
      });
    return () => {
      cancelled = true;
    };
  }, [active, apis, labelsNonce, projectId]);

  /**
   * Every label in use on this board, plus those carrying instructions that
   * would attach in `scope` — a global row, or one scoped to that project; with
   * no scope, every row. Sorted so the offered order does not depend on which
   * card happens to sit first in a column.
   *
   * The scope rule mirrors the daemon's `LabelInstructionDao.matching`
   * (apps/daemon/src/v1/tasks/dao/label-instruction.dao.ts), which decides
   * what actually attaches; a change there is mirrored here.
   */
  const labelsFor = useCallback(
    (scope: string | null): string[] =>
      [
        ...new Set([
          ...board.tasks.flatMap((row) => row.labels),
          ...instructionLabels
            .filter(
              (row) =>
                scope === null ||
                row.projectId === null ||
                row.projectId === scope,
            )
            .map((row) => row.label),
        ]),
      ].sort((a, b) => a.localeCompare(b)),
    [board.tasks, instructionLabels],
  );
  const knownLabels = useMemo(
    () => labelsFor(projectId),
    [labelsFor, projectId],
  );
  // On the every-project board an open card is offered only the instruction
  // labels that would attach to IT, not another project's.
  const openTaskLabels = useMemo(
    () => labelsFor(openTask?.projectId ?? projectId),
    [labelsFor, openTask?.projectId, projectId],
  );

  const openProject =
    board.projects.find((row) => row.id === board.selectedProjectId) ?? null;

  /** Every card's own project — the board may be showing all of them. */
  const projectsById = useMemo(
    () => new Map(board.projects.map((row) => [row.id, row])),
    [board.projects],
  );
  const openTaskProject =
    openTask === null ? null : (projectsById.get(openTask.projectId) ?? null);
  const runTask = board.tasks.find((row) => row.id === runTaskId) ?? null;

  /**
   * Which cards have an agent working them, by task id.
   *
   * From the daemon's queue and not from the columns: `Task.runId` outlives
   * the run it names — a settled card still points at the thread it came from
   * — so a card in `in_review` would otherwise draw a spinner for ever.
   */
  const activeByTask = useMemo(
    () => new Map(board.activeTasks.map((row) => [row.id, row])),
    [board.activeTasks],
  );

  if (!handle) {
    return <EmptyState>Connecting to the daemon…</EmptyState>;
  }

  return (
    <div className="flex h-full min-h-0">
      <div className="flex min-w-0 flex-1 flex-col">
        {/* Everything that acts on the BOARD AS A WHOLE lives on this one row:
            which project is open, and adding to it. The project list was a rail
            down the left edge and the row held a single button, so the board
            paid 224px of its width for a choice made rarely and still read as
            having an empty line above it. */}
        <header className="flex items-center gap-2 border-b border-border px-4 py-4">
          <ProjectPicker
            projects={board.projects}
            selectedProjectId={board.selectedProjectId}
            onSelect={board.selectProject}
            onNewProject={() => {
              setNewProjectOpen(true);
            }}
          />
          {openProject !== null ? (
            <>
              {/* BEFORE the autopilot chip: what the board runs as has to be
                  answered before arming it is worth anything, and an unset
                  one is why an armed project starts nothing. */}
              <ProjectRunConfig
                project={openProject}
                workflows={workflows}
                cliDetections={cliDetections}
                agentsApi={apis?.agents ?? null}
                capabilitiesApi={apis?.capabilities ?? null}
                recentConfigDirs={recentConfigDirs}
                configProfiles={configProfiles}
                open={runConfigOpen}
                onOpenChange={setRunConfigOpen}
                onUpdate={(patch) => {
                  void board.updateProject(patch);
                }}
              />
              <AutopilotControl
                project={openProject}
                blocked={board.queue?.blocked ?? []}
                onUpdate={(patch) => {
                  void board.updateAutopilot(patch);
                }}
                onRearm={() => {
                  void board.rearmAutopilot();
                }}
              />
              {/* Beside the autopilot chip rather than on the intake column's
                  band, where it was counting cards that had already left that
                  column. It is its own readout because it is not the
                  autopilot's figure — a run started by hand from a card is in
                  it too. */}
              <RunningTasks running={board.queue?.running ?? null} />
            </>
          ) : null}
          {/* OMITTED, never disabled, while there is no board to add to. It
              shipped disabled on the reading that the empty state below
              explains it — and it was reported straight back: with no project,
              the only action on screen was a greyed one for the thing that
              cannot be done, while the thing that CAN be done had no control at
              all. A control drawn to be refused states that a feature exists
              and is broken; the truth is that this board has nothing to add to
              yet, which is the empty state's own sentence and now its own
              button. The same rule the chat header's actions follow. */}
          {board.projects.length === 0 ? null : (
            <div className="ml-auto flex shrink-0 items-center gap-2">
              <Button
                variant="ghost"
                size="sm"
                className="text-foreground"
                onClick={() => {
                  setLabelsOpen(true);
                }}>
                <Tag className="size-3.5" aria-hidden />
                Labels
              </Button>
              {/* GHOST, and the panel's Run task is the pattern being matched
                  — ASKED FOR on those terms ("make it same as Run task button
                  design"). It was the filled amber `default`, which made the
                  quietest row on the screen carry the loudest thing on it: a
                  block of brand colour beside a project picker and an autopilot
                  chip that are both flat, over a board whose own cards are
                  where the eye is meant to be. Quiet and beside the other
                  header controls it reads as one of them, which is what it is,
                  while the glyph keeps it findable at a glance — the same
                  trade, in the same words, the Run task button already made. */}
              {/* Withheld on the every-project board: a card is filed into one project. */}
              {projectId === null ? null : (
                <Button
                  variant="ghost"
                  size="sm"
                  className="text-foreground"
                  onClick={() => {
                    setNewTaskStatus(null);
                    setNewTaskOpen(true);
                  }}>
                  {/* NOT lifted. Measured in the running app: the glyph
                      already lands on the button's own centre, and the label's
                      ink sits 0.9px above it — a font's own asymmetry, since
                      "New task" has no descender. A 2px lift therefore
                      overshot by more than the gap it was closing and took the
                      glyph 1.1px ABOVE the label, which is what the whole
                      content reading high actually was. */}
                  <Plus className="size-3.5" aria-hidden />
                  New task
                </Button>
              )}
            </div>
          )}
        </header>

        {board.error !== null ? (
          <ErrorBanner
            message={board.error}
            onDismiss={board.dismissError}
            className="m-3"
          />
        ) : null}

        {/* The empty state CARRIES the one thing to do here. It was a sentence
            alone, which named the next step and then left the user to find the
            control for it inside a picker labelled `No projects yet` — the
            board's own screen offering no way onto it. Keyed on the PROJECT
            LIST rather than on the selection, because that is the fact the
            words state; the two cannot disagree, since `useBoard` fills an
            empty selection from the list in the same write that sets it. */}
        {board.projects.length === 0 ? (
          <EmptyState>
            <div className="flex max-w-sm flex-col items-center gap-4">
              <p>
                No projects yet. A project is a board of tasks, with a default
                folder its agents work in — each task can name its own.
              </p>
              <Button
                size="sm"
                onClick={() => {
                  setNewProjectOpen(true);
                }}>
                <Plus className="size-4" aria-hidden />
                New project
              </Button>
            </div>
          </EmptyState>
        ) : (
          <>
            {board.loading && board.tasks.length === 0 ? (
              <EmptyState>Loading the board…</EmptyState>
            ) : null}
            {/* The COLUMNS scroll horizontally and each scrolls its own cards;
              the page itself never scrolls. */}
            <div className="flex min-h-0 flex-1 gap-3 overflow-x-auto p-3">
              {boardColumns(board.tasks).map((status) => (
                <BoardColumn
                  key={status}
                  status={status}
                  // Only on the column the open project actually picks work up
                  // from, and only while it is armed: everywhere else "work
                  // leaves here on its own" is not a fact about what the user
                  // is looking at.
                  autopilot={
                    openProject?.autopilotEnabled === true &&
                    openProject.autopilotIntakeStatus === status
                      ? {
                          breakerOpen: isBreakerOpen(openProject),
                          waiting: board.queue?.waiting ?? null,
                          // Every blocked card is in the intake column by
                          // construction — the daemon only ever considers that
                          // column — and this banner is drawn on that column
                          // alone, so the queue's whole list belongs here.
                          blocked: board.queue?.blocked ?? [],
                          onStop: () => {
                            void board.stopAutopilot();
                          },
                          // The board's run settings are where most blocked
                          // cards are answered, so the explanation offers them
                          // rather than naming the chip they live behind.
                          onFixBlocked: () => {
                            setRunConfigOpen(true);
                          },
                        }
                      : undefined
                  }
                  tasks={board.tasks.filter((row) => row.status === status)}
                  taskKeyOf={(task) =>
                    projectsById.get(task.projectId)?.taskKey ?? null
                  }
                  {...(projectId === null
                    ? {
                        projectNameOf: (task: TaskDto) =>
                          projectsById.get(task.projectId)?.name ?? null,
                      }
                    : {})}
                  activeByTask={activeByTask}
                  selectedTaskId={openTaskId}
                  draggingTaskId={draggingTaskId}
                  isDropTarget={dropTarget === status}
                  {...(dropTarget === status ? { dropBeforeTaskId } : {})}
                  onOpenTask={setOpenTaskId}
                  onDragStartTask={setDraggingTaskId}
                  onDragEndTask={() => {
                    setDraggingTaskId(null);
                    setDropTarget(null);
                    setDropBeforeTaskId(null);
                  }}
                  onTaskKeyDown={onCardKeyDown}
                  {...(openProject === null
                    ? {}
                    : {
                        onAddTask: (into: string) => {
                          setNewTaskStatus(into);
                          setNewTaskOpen(true);
                        },
                      })}
                  onDragOver={(event) => {
                    if (draggingTaskId === null) {
                      return;
                    }
                    // After the foreign-drag guard above and before anything
                    // else. A dragover that returns without calling this is a
                    // dragover the browser reads as "not a drop target", and
                    // the card animates back to where it started.
                    event.preventDefault();
                    event.dataTransfer.dropEffect = 'move';
                    setDropTarget(status);
                    setDropBeforeTaskId(
                      dropSlotBefore(
                        event,
                        board.tasks
                          .filter((row) => row.status === status)
                          .map((row) => row.id),
                      ),
                    );
                  }}
                  onDragLeave={() => {
                    setDropTarget((current) =>
                      current === status ? null : current,
                    );
                  }}
                  onDrop={(event) => {
                    event.preventDefault();
                    const taskId = draggingTaskId;
                    const before = dropBeforeTaskId;
                    setDraggingTaskId(null);
                    setDropTarget(null);
                    setDropBeforeTaskId(null);
                    if (taskId !== null) {
                      void board.placeTask(taskId, status, before);
                    }
                  }}
                />
              ))}
            </div>
          </>
        )}
      </div>

      {openTask !== null ? (
        <TaskDetail
          // Keyed so a task switch REMOUNTS: the panel seeds its title and
          // description drafts from props at mount only, so a reused instance
          // carries the previous card's text and blur writes it onto this one.
          key={openTask.id}
          task={openTask}
          projectName={openTaskProject?.name ?? null}
          projectTaskKey={openTaskProject?.taskKey ?? null}
          projectFolder={openTaskProject?.folder ?? null}
          projectTarget={
            openTaskProject === null ? null : targetOf(openTaskProject)
          }
          projectRunConfig={
            openTaskProject === null
              ? null
              : {
                  model: openTaskProject.model,
                  effort: openTaskProject.effort,
                  approval: openTaskProject.approval,
                }
          }
          knownLabels={openTaskLabels}
          workflows={workflows}
          cliDetections={cliDetections}
          recentConfigDirs={recentConfigDirs}
          configProfiles={configProfiles}
          agentsApi={apis?.agents ?? null}
          capabilitiesApi={apis?.capabilities ?? null}
          tasksApi={apis?.tasks ?? null}
          onClose={() => {
            setOpenTaskId(null);
          }}
          onSave={(patch) => {
            void board.updateTask(openTask.id, patch);
          }}
          onMove={(to) => {
            void board.moveTask(openTask.id, to);
          }}
          starting={board.startingTaskId === openTask.id}
          onRun={() => {
            setRunTaskId(openTask.id);
          }}
          // Straight to the run, with no dialog in the way: the box the user
          // just typed into IS the dialog's own question.
          // The PROMISE is returned, not discarded: `TaskFollowUp` clears its
          // box only once the start is confirmed, so a swallowed rejection
          // would leave that protection unreachable and the user's words lost
          // on every refusal.
          onFollowUp={(text) => board.runTask(openTask.id, text)}
          {...(onOpenThread === undefined ? {} : { onOpenThread })}
          onAttachFiles={(paths) => {
            void board.attachFiles(openTask.id, paths);
          }}
          onDetachFile={(attachmentId) => {
            void board.detachFile(openTask.id, attachmentId);
          }}
          onDelete={async () => {
            if (await board.deleteTask(openTask.id)) {
              setOpenTaskId(null);
            }
          }}
        />
      ) : null}

      <RunTaskDialog
        open={runTaskId !== null}
        task={runTask}
        taskKey={
          runTask === null
            ? null
            : (projectsById.get(runTask.projectId)?.taskKey ?? null)
        }
        starting={board.startingTaskId === runTaskId}
        onClose={() => {
          setRunTaskId(null);
        }}
        onRun={(prompt) => {
          const taskId = runTaskId;
          setRunTaskId(null);
          if (taskId !== null) {
            void board.runTask(taskId, prompt);
          }
        }}
      />

      <LabelInstructionsDialog
        open={labelsOpen}
        onClose={() => {
          setLabelsOpen(false);
        }}
        api={apis?.labelInstructions ?? null}
        projects={board.projects}
        selectedProjectId={projectId}
        knownLabels={knownLabels}
        onChanged={() => {
          setLabelsNonce((n) => n + 1);
        }}
      />

      <NewProjectDialog
        open={newProjectOpen}
        workflows={workflows}
        cliDetections={cliDetections}
        onClose={() => {
          setNewProjectOpen(false);
        }}
        onCreate={(input) => {
          setNewProjectOpen(false);
          void board.createProject(input);
        }}
      />
      {projectId !== null && openProject !== null ? (
        <NewTaskDialog
          open={newTaskOpen}
          // The pressed column when there was one; otherwise the dialog's own
          // default, which is the `backlog` the daemon would have defaulted to
          // — a Status row on screen has to state the answer it is creating.
          {...(newTaskStatus === null ? {} : { status: newTaskStatus })}
          projectName={openProject.name}
          knownLabels={knownLabels}
          context={{
            project: {
              target: targetOf(openProject),
              runConfig: {
                model: openProject.model,
                effort: openProject.effort,
                approval: openProject.approval,
              },
              folder: openProject.folder,
            },
            workflows,
            cliDetections,
            agentsApi: apis?.agents ?? null,
            capabilitiesApi: apis?.capabilities ?? null,
          }}
          onClose={() => {
            setNewTaskOpen(false);
          }}
          onCreate={(input, staged) => {
            setNewTaskOpen(false);
            void board.createTask({ projectId, ...input }, staged);
          }}
        />
      ) : null}
    </div>
  );
}
