// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { type ProjectDto, TaskStatus } from '../autogenerated';
import {
  AutopilotControl,
  FAILURE_BREAKER_THRESHOLD,
} from './autopilot-control';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const project = (over: Partial<ProjectDto> = {}): ProjectDto =>
  ({
    id: 'p1',
    name: 'geniro-app',
    folder: '/repo/geniro-app',
    groupId: null,
    agentKind: null,
    model: null,
    effort: null,
    approval: null,
    configDir: null,
    workflowSlug: null,
    autopilotEnabled: false,
    autopilotIntakeStatus: TaskStatus.Todo,
    autopilotMaxConcurrent: 1,
    autopilotFailureStreak: 0,
    provider: 'geniro',
    createdAt: '2026-09-07T12:00:00.000Z',
    updatedAt: '2026-09-07T12:00:00.000Z',
    ...over,
  }) as ProjectDto;

function control(
  over: Partial<ProjectDto> = {},
  handlers: { onUpdate?: () => void; onRearm?: () => void } = {},
): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <AutopilotControl
        project={project(over)}
        onUpdate={handlers.onUpdate ?? vi.fn()}
        onRearm={handlers.onRearm ?? vi.fn()}
      />,
    );
  });
  return container;
}

const trigger = (el: HTMLElement): HTMLElement =>
  el.querySelector('[aria-label="Autopilot settings"]') as HTMLElement;

const openPanel = (el: HTMLElement): void => {
  act(() => {
    trigger(el).click();
  });
};

/** The panel is portalled, so it is not under the container. */
const panelText = (): string => document.body.textContent ?? '';

const byLabel = (label: string): HTMLElement | null =>
  document.body.querySelector(`[aria-label="${label}"]`);

describe('AutopilotControl', () => {
  // The chip carries the STATE. One reading only "Autopilot" would make the
  // reader open it to learn the single thing they wanted.
  it('states off, the intake column, or stopped, on the chip itself', () => {
    expect(trigger(control()).textContent).toContain('Autopilot off');

    expect(trigger(control({ autopilotEnabled: true })).textContent).toContain(
      'Autopilot · To do',
    );

    expect(
      trigger(
        control({
          autopilotEnabled: true,
          autopilotFailureStreak: FAILURE_BREAKER_THRESHOLD,
        }),
      ).textContent,
    ).toContain('Autopilot stopped');
  });

  // The chip is named for what it OPENS, the switch for what it IS — one
  // accessible name each, so navigating by name reaches the intended control.
  it('arms the project from the switch inside the panel', () => {
    const onUpdate = vi.fn();
    const el = control({}, { onUpdate });

    openPanel(el);
    act(() => {
      (byLabel('Autopilot') as HTMLElement | null)?.click();
    });

    expect(onUpdate).toHaveBeenCalledWith({ autopilotEnabled: true });
  });

  it('shows the column and the cap only once the project is armed', () => {
    openPanel(control());
    expect(byLabel('Intake column')).toBeNull();
    expect(byLabel('Runs at once')).toBeNull();

    openPanel(control({ autopilotEnabled: true }));
    expect(byLabel('Intake column')).not.toBeNull();
    expect(byLabel('Runs at once')).not.toBeNull();
  });

  // The daemon REFUSES an over-ceiling cap rather than clamping it, so a value
  // it would reject is never sent.
  it('does not send a cap the daemon would refuse', () => {
    const onUpdate = vi.fn();
    openPanel(control({ autopilotEnabled: true }, { onUpdate }));
    const field = byLabel('Runs at once') as HTMLInputElement;

    act(() => {
      set(field, '9');
    });
    expect(onUpdate).not.toHaveBeenCalled();

    act(() => {
      set(field, '3');
    });
    expect(onUpdate).toHaveBeenCalledWith({ autopilotMaxConcurrent: 3 });
  });

  // The whole point of the rewrite: the first wording said only "Stopped after
  // 3 failed runs in a row", which names no subject and was reported as an
  // error the reader could not account for.
  it('explains a stopped autopilot — what stopped, why, and what is safe', () => {
    openPanel(
      control({
        autopilotEnabled: true,
        autopilotFailureStreak: FAILURE_BREAKER_THRESHOLD,
      }),
    );

    const text = panelText();
    expect(text).toContain('Autopilot stopped itself');
    expect(text).toContain(`${FAILURE_BREAKER_THRESHOLD} runs failed`);
    expect(text).toContain('Your tasks are untouched');
  });

  it('restarts a stopped autopilot from the panel', () => {
    const onRearm = vi.fn();
    openPanel(
      control(
        {
          autopilotEnabled: true,
          autopilotFailureStreak: FAILURE_BREAKER_THRESHOLD,
        },
        { onRearm },
      ),
    );

    const button = [...document.body.querySelectorAll('button')].find((node) =>
      (node.textContent ?? '').includes('Start it again'),
    );
    act(() => {
      button?.click();
    });

    expect(onRearm).toHaveBeenCalledTimes(1);
  });

  it('offers no restart while nothing has stopped', () => {
    openPanel(control({ autopilotEnabled: true }));

    expect(panelText()).not.toContain('Start it again');
  });
});

/** Set a controlled input's value the way React's own listener sees it. */
function set(input: HTMLInputElement, value: string): void {
  const setter = Object.getOwnPropertyDescriptor(
    HTMLInputElement.prototype,
    'value',
  )?.set;
  setter?.call(input, value);
  input.dispatchEvent(new Event('input', { bubbles: true }));
}
