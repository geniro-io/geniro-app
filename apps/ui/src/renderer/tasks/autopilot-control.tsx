import { CirclePause, Zap } from 'lucide-react';
import { useRef, useState } from 'react';

import {
  type BlockedTask,
  type ProjectDto,
  TaskStatus,
} from '../autogenerated';
import { Button } from '../components/ui/button';
import { Chip, ChipChevron } from '../components/ui/chip';
import { Popover } from '../components/ui/popover';
import { Select } from '../components/ui/select';
import { Stepper } from '../components/ui/stepper';
import { Switch } from '../components/ui/switch';
import { cn } from '../components/ui/utils';
import { TASK_STATUS_META, taskStatusMeta } from './task-status';

/**
 * When the breaker has tripped, mirroring the daemon's own threshold.
 *
 * The board already holds the project row carrying the streak, so a poll
 * purely to be told a comparison it can make itself would put a request on a
 * timer for nothing. The daemon still ENFORCES it; this only decides which
 * sentence is shown.
 */
export const FAILURE_BREAKER_THRESHOLD = 3;

/** The daemon REFUSES a cap above this rather than clamping it. */
export const MAX_CONCURRENT_CEILING = 5;

/**
 * How many blocked cards the panel names before it counts the rest.
 *
 * They share ONE reason in every case this can produce today, so listing forty
 * of them would be the same sentence forty times in a 20rem popover; the count
 * says how big the problem is and the board says which cards.
 */
const MAX_BLOCKED_SHOWN = 4;

export interface AutopilotPatch {
  autopilotEnabled?: boolean;
  autopilotIntakeStatus?: TaskStatus;
  autopilotMaxConcurrent?: number;
}

export function isBreakerOpen(project: ProjectDto): boolean {
  return project.autopilotFailureStreak >= FAILURE_BREAKER_THRESHOLD;
}

/**
 * The open project's autopilot, on the board's own header.
 *
 * It lives here rather than in Settings because this is where the thing it
 * governs is: the intake column it picks work up from is on this screen, and
 * so is the queue behind it. A per-project switch filed under Settings makes
 * the user leave the board to answer a question about the board.
 *
 * A chip opening a popover rather than three controls in the header: the
 * header is the row for acting on the board as a whole, and a switch, a column
 * picker and a number field spread across it would push the one control most
 * presses go to — New task — off the end.
 */
export function AutopilotControl({
  project,
  blocked = [],
  onUpdate,
  onRearm,
}: {
  project: ProjectDto;
  /**
   * Cards in the intake column the daemon will not hand out, with its own
   * sentence for each. Empty is the healthy case and draws nothing.
   */
  blocked?: readonly BlockedTask[];
  onUpdate: (patch: AutopilotPatch) => void;
  onRearm: () => void;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const stopped = isBreakerOpen(project);
  const armed = project.autopilotEnabled;

  return (
    <div className="relative">
      <Chip
        asChild
        interactive
        tone={armed ? 'active' : 'muted'}
        data-menu-trigger>
        <button
          type="button"
          ref={triggerRef}
          // NOT "Autopilot": the switch inside this panel is the autopilot,
          // and two controls in one view answering to the same accessible
          // name is a real ambiguity for anyone navigating by name — the
          // spec below found it by clicking the wrong one. This chip OPENS
          // the settings; the switch is the setting.
          aria-label="Autopilot settings"
          aria-expanded={open}
          onClick={() => {
            setOpen((current) => !current);
          }}>
          {stopped ? (
            <CirclePause className="text-warning" aria-hidden />
          ) : (
            <Zap aria-hidden />
          )}
          {/* The STATE, not the word alone: a chip reading only "Autopilot"
              makes the reader open it to learn the one thing they wanted. */}
          {stopped
            ? 'Autopilot stopped'
            : armed
              ? `Autopilot · ${taskStatusMeta(project.autopilotIntakeStatus).label}`
              : 'Autopilot off'}
          <ChipChevron />
        </button>
      </Chip>
      <Popover
        open={open}
        onClose={() => {
          setOpen(false);
        }}
        triggerRef={triggerRef}
        side="bottom"
        align="start"
        anchor="viewport"
        // The PANEL's own name, distinct from the switch inside it: the
        // popover renders this as an `aria-label`, so reusing "Autopilot"
        // here put a third control of that name in one view.
        label="Autopilot settings"
        className="w-80 p-3">
        <div className="flex flex-col gap-3">
          <div className="flex items-start justify-between gap-3">
            <div className="flex min-w-0 flex-col">
              <span className="text-sm font-medium">Autopilot</span>
              <span className="text-xs text-muted-foreground">
                {/* What arming AUTHORISES, not just what it does. An
                    unattended run has to be given a mode that cannot stop and
                    ask, so the daemon answers permission requests for it —
                    shell commands included. Saying so here is the only place
                    the person turning it on can read it. */}
                {armed
                  ? 'Starts tasks from the intake column on its own. Agents run unattended and approve their own commands — including shell commands, which the task’s worktree does not confine.'
                  : 'Tasks on this board are started by hand.'}
              </span>
            </div>
            <Switch
              checked={armed}
              aria-label="Autopilot"
              onCheckedChange={(next) => {
                onUpdate({ autopilotEnabled: next });
              }}
            />
          </div>

          {armed ? (
            <div className="flex flex-col gap-2 border-t border-border pt-3">
              <label className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
                Picks work up from
                <Select
                  aria-label="Intake column"
                  variant="ghost"
                  side="bottom"
                  value={project.autopilotIntakeStatus}
                  groups={[
                    {
                      items: Object.values(TaskStatus).map((status) => ({
                        value: status,
                        label: TASK_STATUS_META[status].label,
                      })),
                    },
                  ]}
                  onValueChange={(next) => {
                    onUpdate({ autopilotIntakeStatus: next as TaskStatus });
                  }}
                />
              </label>
              {/* A `div` rather than a `label`: the control is a spinbutton
                  carrying its own accessible name, and a label wrapping it
                  would put a second one on the same element. */}
              <div className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
                Runs at once
                {/* A stepper, not a number field — the range is 1..5, so the
                    bound is enforced by the control having nowhere further to
                    go rather than by refusing what was typed. That drops the
                    validation this used to need: a value the daemon would
                    reject is now unreachable. */}
                <Stepper
                  value={project.autopilotMaxConcurrent}
                  min={1}
                  max={MAX_CONCURRENT_CEILING}
                  aria-label="Runs at once"
                  onChange={(next) => {
                    onUpdate({ autopilotMaxConcurrent: next });
                  }}
                />
              </div>
              <p className="text-xs text-muted-foreground">
                Each run works on its own branch, in its own worktree.
              </p>
            </div>
          ) : null}

          {stopped ? (
            <div
              className={cn(
                'flex flex-col gap-2 rounded-lg p-2.5 text-xs',
                'bg-warning/10 text-warning',
              )}>
              {/* Says WHAT stopped, WHY, and what happens now. The first
                  wording said only "Stopped after 3 failed runs in a row",
                  which names no subject — reported as an error the reader
                  could not account for. */}
              <p>
                Autopilot stopped itself: {project.autopilotFailureStreak} runs
                failed one after another, so it is no longer starting anything
                here. Your tasks are untouched.
              </p>
              <Button
                size="sm"
                variant="outline"
                className="self-start"
                onClick={onRearm}>
                Start it again
              </Button>
            </div>
          ) : null}

          {/* Cards the daemon will not hand out, and why.
              Without this the autopilot could sit on `1 waiting` forever with
              the only record a status code in the debug log: it prepared a
              worktree and was refused every twenty seconds, and the breaker
              could not end it because a run that never started never failed.
              The daemon now keeps such a card out of `eligible` — which stops
              the churn — and names it here, which is what lets `waiting` be
              read honestly. */}
          {blocked.length > 0 ? (
            <div className="flex flex-col gap-1.5 border-t border-border pt-3">
              <span className="text-xs font-medium text-warning">
                {blocked.length === 1
                  ? '1 task cannot start'
                  : `${blocked.length} tasks cannot start`}
              </span>
              <ul className="flex flex-col gap-1">
                {blocked.slice(0, MAX_BLOCKED_SHOWN).map((task) => (
                  <li key={task.id} className="flex min-w-0 flex-col">
                    <span className="truncate text-xs" title={task.title}>
                      {task.title}
                    </span>
                    <span className="text-xs text-muted-foreground">
                      {task.reason}
                    </span>
                  </li>
                ))}
              </ul>
              {blocked.length > MAX_BLOCKED_SHOWN ? (
                <span className="text-xs text-muted-foreground">
                  and {blocked.length - MAX_BLOCKED_SHOWN} more
                </span>
              ) : null}
            </div>
          ) : null}
        </div>
      </Popover>
    </div>
  );
}
