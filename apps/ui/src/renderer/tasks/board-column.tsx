import { CircleAlert, Plus, Zap } from 'lucide-react';
import { useRef, useState } from 'react';

import type { ActiveTask, BlockedTask, TaskDto } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Chip } from '../components/ui/chip';
import { Popover } from '../components/ui/popover';
import { cn } from '../components/ui/utils';
import { TaskCard } from './task-card';
import { taskStatusMeta } from './task-status';

export function BoardColumn({
  status,
  tasks,
  taskKey,
  activeByTask,
  selectedTaskId,
  draggingTaskId,
  isDropTarget,
  onOpenTask,
  onDragStartTask,
  onDragEndTask,
  onDragOver,
  onDragLeave,
  onDrop,
  onTaskKeyDown,
  onAddTask,
  autopilot,
}: {
  status: string;
  tasks: TaskDto[];
  /** The board's own prefix, for each card's identifier. */
  taskKey?: string | null;
  /**
   * Which cards have an agent working them, keyed by task id — the daemon's
   * own answer, since `Task.runId` outlives the run it names.
   */
  activeByTask?: ReadonlyMap<string, ActiveTask>;
  selectedTaskId: string | null;
  draggingTaskId: string | null;
  isDropTarget: boolean;
  onOpenTask: (taskId: string) => void;
  onDragStartTask: (taskId: string) => void;
  onDragEndTask: () => void;
  onDragOver: (event: React.DragEvent<HTMLElement>) => void;
  onDragLeave: () => void;
  onDrop: (event: React.DragEvent<HTMLElement>) => void;
  onTaskKeyDown?: (
    event: React.KeyboardEvent<HTMLButtonElement>,
    taskId: string,
  ) => void;
  onAddTask: (status: string) => void;
  /**
   * Present only on the column the project's autopilot picks work up from.
   *
   * The banner and the Stop belong to THAT column and to no other, because
   * that is the only place on the board where "work leaves here on its own" is
   * a fact about what the user is looking at.
   */
  autopilot?: {
    breakerOpen: boolean;
    /**
     * How many cards in THIS column are queued — from the daemon's queue and
     * not from the column, since a card's column is written optimistically on
     * a drag. Null while unread.
     *
     * There is deliberately no RUNNING count here any more. A started card
     * leaves this column for `in_progress`, so counting it on the intake
     * column's band put a number over an empty column — REPORTED against a
     * board reading `2 running` under `To do 0` while both cards sat in the
     * next column along. What is running belongs to the board, so it is said
     * once, on the header's autopilot chip.
     */
    waiting: number | null;
    /**
     * The cards in THIS column the daemon will not hand out, with its own
     * reason for each.
     *
     * It is on the banner rather than only in the autopilot popover because
     * the popover is a click away and this band is not: `2 waiting` beside a
     * Stop button, with nothing ever starting, is exactly the sentence that
     * was reported as a lie. See {@link queueLine}.
     */
    blocked: readonly BlockedTask[];
    onStop: () => void;
    /** Opens the board's run settings — the answer to most blocked cards. */
    onFixBlocked?: () => void;
  };
}): React.JSX.Element {
  const meta = taskStatusMeta(status);
  return (
    <section
      role="group"
      aria-label={`${meta.label}, ${tasks.length} task${tasks.length === 1 ? '' : 's'}`}
      onDragOver={onDragOver}
      onDragLeave={onDragLeave}
      onDrop={onDrop}
      className={cn(
        // The column is a SURFACE the cards sit on, which is what was missing:
        // without it the cards floated on the page and the board read as one
        // list with gaps rather than as columns.
        //
        // `muted/40` and not `muted` outright, because the flat token inverts
        // between themes — it is darker than the page in light and LIGHTER than
        // `card` in dark, which would sink every card into its own column. The
        // blend keeps one order in both: page, then column, then card on top.
        // Grows to share the width when the columns FIT, and falls back to
        // scrolling when they do not. A fixed `w-72` put the fifth column off
        // the right edge behind a horizontal scroll on a window wide enough
        // to hold all of them with room to spare.
        'flex min-w-64 flex-1 basis-72 flex-col gap-2 rounded-xl bg-muted/40 p-2',
        // The EDGE carries the definition, not the fill. `muted` cannot simply
        // be deepened: in dark it converges on `card` around 50%, and past that
        // the cards stop reading as raised out of their own column. A ring is
        // legible at any tint and behaves the same in both themes.
        'ring-1 transition-[background-color,box-shadow]',
        isDropTarget ? 'bg-accent/60 ring-primary' : 'ring-border',
      )}>
      {/* Quiet chrome, not a card: the columns are the page's structure, so a
        filled badge per header read as six competing buttons. The status glyph
        carries the only colour here. */}
      <header className="flex items-center gap-2 px-1">
        <meta.icon
          className={cn('size-3.5 shrink-0', meta.className)}
          aria-hidden
        />
        <span className="text-sm font-medium">{meta.label}</span>
        <span className="text-xs tabular-nums text-muted-foreground">
          {tasks.length}
        </span>
        <button
          type="button"
          // Visible rather than revealed on hover: a pointer-only affordance is
          // undiscoverable by keyboard and invisible in a screenshot, and this
          // app already prefers a quiet always-there control to a hidden one.
          aria-label={`Add a task to ${meta.label}`}
          title={`Add a task to ${meta.label}`}
          onClick={() => {
            onAddTask(status);
          }}
          className="ml-auto rounded p-1 text-muted-foreground hover:bg-accent hover:text-foreground focus-visible:outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50">
          <Plus className="size-3.5" aria-hidden />
        </button>
      </header>
      {autopilot ? (
        <AutopilotBanner {...autopilot} onOpenTask={onOpenTask} />
      ) : null}
      <div className="flex min-h-24 flex-1 flex-col gap-2 overflow-y-auto">
        {tasks.map((task) => (
          <TaskCardRow
            key={task.id}
            task={task}
            taskKey={taskKey ?? null}
            active={activeByTask?.get(task.id)}
            selected={task.id === selectedTaskId}
            dragging={task.id === draggingTaskId}
            onOpen={onOpenTask}
            onDragStart={onDragStartTask}
            onDragEnd={onDragEndTask}
            onKeyDown={onTaskKeyDown}
          />
        ))}
        {/* Nothing at rest. An empty column already LOOKS empty, and on a
            fresh board "No tasks" was written four times across a screen whose
            own emptiness said it once. The drop hint stays: that one is a
            state the column is in, not a restatement of what it holds. */}
        {tasks.length === 0 && isDropTarget ? (
          <p className="px-1 py-3 text-xs text-muted-foreground">Drop here</p>
        ) : null}
      </div>
    </section>
  );
}

/**
 * That the autopilot reads this column, and the way to stop it.
 *
 * Deliberately thin. The SETTING lives on the board header, where the switch,
 * the intake column and the cap are; what belongs here is only the fact that
 * this particular column is the one work leaves from, and the one press worth
 * having within reach of it.
 *
 * Stop is always visible and never behind a confirm: it is what a user reaches
 * for when something is going wrong, and a dialog in the way is the wrong
 * thing to meet at that moment. It is also cheap to undo — the header switch
 * arms the project again — which is what makes no-confirm right here and wrong
 * for the project delete elsewhere.
 *
 * It disarms INTAKE and deliberately does not touch a task already running:
 * stopping a working agent is a different act with a different cost and has
 * its own control on the run. The title says so, because a Stop that silently
 * left an agent working would be read as broken.
 */
function AutopilotBanner({
  breakerOpen,
  waiting,
  blocked,
  onStop,
  onFixBlocked,
  onOpenTask,
}: {
  breakerOpen: boolean;
  waiting: number | null;
  blocked: readonly BlockedTask[];
  onStop: () => void;
  onFixBlocked?: () => void;
  onOpenTask: (taskId: string) => void;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const lineRef = useRef<HTMLButtonElement | null>(null);
  const stuck = !breakerOpen && blocked.length > 0;
  const line = breakerOpen
    ? 'Autopilot is stopped.'
    : (queueLine(waiting, blocked.length) ?? 'Autopilot starts tasks here.');
  return (
    <div
      data-slot="autopilot-banner"
      className={cn(
        // NO `text-xs` on the wrapper. A type-setting wrapper does not reach
        // a native `<button>` inside it — `global.css` gives every bare button
        // an explicit size as a direct rule, which beats an inherited one — so
        // the Stop chip would render larger than the sentence beside it. Each
        // child states its own size instead, which `Chip` already does.
        'flex items-center gap-1.5 rounded-lg px-2 py-1',
        // Ambient state, from tokens already in use — never a new colour.
        // A banner competing with the cards would read as an alert on every
        // board that merely has autopilot switched on. A board where nothing
        // CAN start is the exception, and it wears the breaker's own tone:
        // that is a state the user has to act on, not one to sit under.
        breakerOpen || stuck
          ? 'bg-warning/10 text-warning'
          : 'bg-accent/50 text-muted-foreground',
      )}>
      {/* NOT a warning triangle. The card beside it draws one for the URGENT
          priority, in the same corner of the same board, and two identical
          glyphs meaning unrelated things is what was reported: "у меня есть
          иконка с восклицательным знаком в треугольничке напротив таски… Я не
          понимаю, что она значит". The tone still carries the alarm. */}
      {stuck ? (
        <CircleAlert className="size-3.5 shrink-0" aria-hidden />
      ) : (
        <Zap className="size-3.5 shrink-0" aria-hidden />
      )}
      {/* The line OPENS the explanation when there is one to open. A `title`
          was the whole of it before, and a tooltip is not an answer to "почему?
          … Сейчас это очень странно выглядит": it is invisible until hovered,
          it names one card of several, and it holds no way to act. The column
          is NOT named again — this sits directly under a header that says it. */}
      {stuck ? (
        <button
          type="button"
          ref={lineRef}
          aria-expanded={open}
          aria-label={`${line} — why, and what to do`}
          onClick={() => {
            setOpen((current) => !current);
          }}
          className="min-w-0 flex-1 truncate text-left text-xs underline decoration-dotted underline-offset-4 hover:decoration-solid focus-visible:outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50">
          {line}
        </button>
      ) : (
        <span className="min-w-0 flex-1 truncate text-xs">{line}</span>
      )}
      {stuck ? (
        <BlockedPanel
          open={open}
          triggerRef={lineRef}
          blocked={blocked}
          onClose={() => {
            setOpen(false);
          }}
          onOpenTask={(taskId) => {
            setOpen(false);
            onOpenTask(taskId);
          }}
          {...(onFixBlocked === undefined
            ? {}
            : {
                onFix: () => {
                  setOpen(false);
                  onFixBlocked();
                },
              })}
        />
      ) : null}
      {breakerOpen ? null : (
        <Chip asChild interactive>
          <button
            type="button"
            aria-label="Stop the autopilot"
            title="Stops picking up new work. A task already running is left alone."
            onClick={onStop}
            // `h-6 px-1.5` over the chip's own `h-8`: this sits inside a band
            // one line tall, and a chip at its default height makes the band
            // taller than the cards under it.
            className="h-6 shrink-0 px-1.5">
            Stop
          </button>
        </Chip>
      )}
    </div>
  );
}

/**
 * WHY the autopilot will not take these cards, and what to do about it.
 *
 * The band it opens from is one line in a 300px column, so it can hold a count
 * and nothing else. Everything a stuck board actually needs is here: which
 * cards, the daemon's own sentence for each, and the two places the answer can
 * be set — the board's run settings, and the card itself.
 *
 * Both are OFFERED rather than described. "set one on this task, or a default
 * for the project" is the daemon telling the truth about its own precedence
 * and is still no help to somebody who has not found either control; a row
 * that opens the card and a button that opens the board's settings are the
 * same two answers, pressable.
 */
function BlockedPanel({
  open,
  triggerRef,
  blocked,
  onClose,
  onOpenTask,
  onFix,
}: {
  open: boolean;
  triggerRef: React.RefObject<HTMLButtonElement | null>;
  blocked: readonly BlockedTask[];
  onClose: () => void;
  onOpenTask: (taskId: string) => void;
  onFix?: () => void;
}): React.JSX.Element {
  return (
    <Popover
      open={open}
      onClose={onClose}
      triggerRef={triggerRef}
      side="bottom"
      align="start"
      // The board scrolls horizontally and each column scrolls its own cards,
      // so an absolutely-placed panel would be cut by whichever of the two the
      // band happens to sit inside.
      anchor="viewport"
      label="Why these tasks cannot start"
      className="w-80 p-3">
      <div className="flex flex-col gap-3">
        <div className="flex min-w-0 flex-col">
          <span className="text-sm font-medium">
            {blocked.length === 1
              ? 'This task cannot start'
              : `${blocked.length} tasks cannot start`}
          </span>
          <span className="text-xs text-muted-foreground">
            Autopilot is armed and reaching them — the daemon refuses each one
            for the reason below.
          </span>
        </div>
        <ul className="flex flex-col gap-1">
          {blocked.map((task) => (
            <li key={task.id} className="flex min-w-0">
              <button
                type="button"
                onClick={() => {
                  onOpenTask(task.id);
                }}
                className="flex min-w-0 flex-1 flex-col rounded-md px-1.5 py-1 text-left hover:bg-accent focus-visible:outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50">
                <span
                  className="truncate text-xs font-medium"
                  title={task.title}>
                  {task.title}
                </span>
                {/* The DAEMON's own sentence, verbatim. Restating it here
                    would be a second wording of one refusal, free to drift
                    from the one that is actually enforced. */}
                <span className="text-xs text-muted-foreground">
                  {task.reason}
                </span>
              </button>
            </li>
          ))}
        </ul>
        {onFix === undefined ? null : (
          <Button
            size="sm"
            variant="outline"
            className="self-start"
            onClick={onFix}>
            Set the board’s agent
          </Button>
        )}
      </div>
    </Popover>
  );
}

/**
 * What the autopilot is doing, in the fewest words that are still true.
 *
 * The count comes from the daemon's own queue rather than from the column on
 * screen: a card's column is written optimistically the moment it is dragged.
 *
 * Null while nothing has been read, and the caller falls back to the plain
 * sentence rather than drawing a zero it cannot stand behind.
 *
 * **`waiting` alone was a lie, and this is the correction.** A card the daemon
 * refuses is still sitting in the intake column, so it is counted in `waiting`
 * — which made a permanently stuck board read `2 waiting` beside a Stop
 * button, forever, with nothing on this band saying why. REPORTED against
 * exactly that: "я прямо сейчас вижу, что он waiting, но он ничего не делает".
 * The blocked cards are named in the autopilot popover too, but a popover is a
 * click away and this band is not — and the band is what the reader is already
 * looking at when they conclude the feature is broken.
 *
 * So a blocked card is SUBTRACTED from the waiting count rather than merely
 * mentioned beside it: `2 waiting · 2 cannot start` reads as four cards, and a
 * count that includes what it then contradicts is the same defect one step
 * quieter.
 */
function queueLine(waiting: number | null, blocked: number): string | null {
  if (waiting === null) {
    return null;
  }
  // Never negative, though it should not be: the daemon counts both off one
  // read of the same column, and a client that drew `-1 waiting` because the
  // two disagreed would be a worse bug than the one this fixes.
  const queued = Math.max(0, waiting - blocked);
  if (queued === 0 && blocked === 0) {
    return 'Autopilot starts tasks here.';
  }
  const parts: string[] = [];
  if (queued > 0) {
    parts.push(`${queued} waiting`);
  }
  if (blocked > 0) {
    // The COUNT and the reason, because the count alone is what was already on
    // screen. Singular is spelled rather than derived — `1 tasks` is the tell
    // that nobody read the string out loud.
    parts.push(
      blocked === 1 ? '1 task cannot start' : `${blocked} tasks cannot start`,
    );
  }
  return parts.join(' · ');
}

function TaskCardRow({
  task,
  taskKey,
  active,
  selected,
  dragging,
  onOpen,
  onDragStart,
  onDragEnd,
  onKeyDown,
}: {
  task: TaskDto;
  taskKey: string | null | undefined;
  active: ActiveTask | undefined;
  selected: boolean;
  dragging: boolean;
  onOpen: (taskId: string) => void;
  onDragStart: (taskId: string) => void;
  onDragEnd: () => void;
  onKeyDown?: (
    event: React.KeyboardEvent<HTMLButtonElement>,
    taskId: string,
  ) => void;
}): React.JSX.Element {
  return (
    <TaskCard
      task={task}
      taskKey={taskKey}
      {...(active === undefined ? {} : { active })}
      selected={selected}
      dragging={dragging}
      onOpen={() => {
        onOpen(task.id);
      }}
      onDragStart={() => {
        onDragStart(task.id);
      }}
      onDragEnd={onDragEnd}
      onKeyDown={
        onKeyDown === undefined
          ? undefined
          : (event) => {
              onKeyDown(event, task.id);
            }
      }
    />
  );
}
