import type { TaskDto, TaskStatus } from '../autogenerated';
import { Badge } from '../components/ui/badge';
import { cn } from '../components/ui/utils';
import { TaskCard } from './task-card';
import { TASK_STATUS_META } from './task-status';

export function BoardColumn({
  status,
  tasks,
  selectedTaskId,
  draggingTaskId,
  isDropTarget,
  onOpenTask,
  onDragStartTask,
  onDragEndTask,
  onDragOver,
  onDragLeave,
  onDrop,
  onTaskKeyDown,
  children,
}: {
  status: TaskStatus;
  tasks: TaskDto[];
  selectedTaskId: string | null;
  draggingTaskId: string | null;
  isDropTarget: boolean;
  onOpenTask: (taskId: string) => void;
  onDragStartTask: (taskId: string) => void;
  onDragEndTask: () => void;
  onDragOver: (event: React.DragEvent<HTMLElement>) => void;
  onDragLeave: () => void;
  onDrop: (event: React.DragEvent<HTMLElement>) => void;
  onTaskKeyDown?: (
    event: React.KeyboardEvent<HTMLButtonElement>,
    taskId: string,
  ) => void;
  children?: React.ReactNode;
}): React.JSX.Element {
  const meta = TASK_STATUS_META[status];
  return (
    <section
      role="group"
      aria-label={`${meta.label}, ${tasks.length} task${tasks.length === 1 ? '' : 's'}`}
      onDragOver={onDragOver}
      onDragLeave={onDragLeave}
      onDrop={onDrop}
      className="flex w-70 shrink-0 flex-col gap-2">
      <header className="flex items-center gap-2 px-1">
        <meta.icon
          className={cn('size-4 shrink-0', meta.className)}
          aria-hidden
        />
        <span className="text-sm font-medium">{meta.label}</span>
        <Badge variant="secondary">{tasks.length}</Badge>
        {children}
      </header>
      <div
        className={cn(
          // `min-h` rather than a fixed height: the padding is what gives an
          // empty column something to drop onto at all.
          'flex min-h-24 flex-1 flex-col gap-2 overflow-y-auto rounded-md border border-dashed p-2',
          isDropTarget ? 'border-primary bg-accent/40' : 'border-transparent',
        )}>
        {tasks.map((task) => (
          <TaskCardRow
            key={task.id}
            task={task}
            selected={task.id === selectedTaskId}
            dragging={task.id === draggingTaskId}
            onOpen={onOpenTask}
            onDragStart={onDragStartTask}
            onDragEnd={onDragEndTask}
            onKeyDown={onTaskKeyDown}
          />
        ))}
        {tasks.length === 0 ? (
          <p className="px-1 py-2 text-xs text-muted-foreground">No tasks</p>
        ) : null}
      </div>
    </section>
  );
}

function TaskCardRow({
  task,
  selected,
  dragging,
  onOpen,
  onDragStart,
  onDragEnd,
  onKeyDown,
}: {
  task: TaskDto;
  selected: boolean;
  dragging: boolean;
  onOpen: (taskId: string) => void;
  onDragStart: (taskId: string) => void;
  onDragEnd: () => void;
  onKeyDown?: (
    event: React.KeyboardEvent<HTMLButtonElement>,
    taskId: string,
  ) => void;
}): React.JSX.Element {
  return (
    <TaskCard
      task={task}
      selected={selected}
      dragging={dragging}
      onOpen={() => {
        onOpen(task.id);
      }}
      onDragStart={() => {
        onDragStart(task.id);
      }}
      onDragEnd={onDragEnd}
      onKeyDown={
        onKeyDown === undefined
          ? undefined
          : (event) => {
              onKeyDown(event, task.id);
            }
      }
    />
  );
}
