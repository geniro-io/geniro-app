// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type {
  LabelInstructionDto,
  LabelInstructionsApi,
} from '../autogenerated';
import { aProject } from './__tests__/fixtures';
import { LabelInstructionsDialog } from './label-instructions-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const row = (over: Partial<LabelInstructionDto> = {}): LabelInstructionDto => ({
  id: 'li1',
  projectId: null,
  label: 'bug',
  instructions: 'Write a failing test first.',
  createdAt: '2026-09-15T00:00:00.000Z',
  updatedAt: '2026-09-15T00:00:00.000Z',
  ...over,
});

function stubApi(rows: LabelInstructionDto[]): {
  api: LabelInstructionsApi;
  list: ReturnType<typeof vi.fn>;
  create: ReturnType<typeof vi.fn>;
  update: ReturnType<typeof vi.fn>;
  remove: ReturnType<typeof vi.fn>;
} {
  const list = vi.fn().mockResolvedValue(rows);
  const create = vi.fn().mockResolvedValue(row({ id: 'li2' }));
  const update = vi.fn().mockResolvedValue(row());
  const remove = vi.fn().mockResolvedValue({ deleted: true });
  const api = {
    listLabelInstructions: list,
    createLabelInstruction: create,
    updateLabelInstruction: update,
    deleteLabelInstruction: remove,
  } as unknown as LabelInstructionsApi;
  return { api, list, create, update, remove };
}

async function render(
  api: LabelInstructionsApi,
  selectedProjectId: string | null = null,
  onChanged?: () => void,
): Promise<void> {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(
      <LabelInstructionsDialog
        open
        onClose={vi.fn()}
        api={api}
        projects={[aProject({ id: 'p1', name: 'Geniro' })]}
        selectedProjectId={selectedProjectId}
        knownLabels={['frontend']}
        onChanged={onChanged}
      />,
    );
  });
}

const setValue = (
  node: HTMLInputElement | HTMLTextAreaElement,
  value: string,
): void => {
  const proto =
    node instanceof HTMLTextAreaElement
      ? HTMLTextAreaElement.prototype
      : HTMLInputElement.prototype;
  Object.getOwnPropertyDescriptor(proto, 'value')?.set?.call(node, value);
  node.dispatchEvent(new Event('input', { bubbles: true }));
};

const button = (text: string): HTMLButtonElement =>
  [...document.body.querySelectorAll('button')].find(
    (node) =>
      (node.textContent ?? '').trim() === text ||
      node.getAttribute('aria-label') === text,
  ) as HTMLButtonElement;

describe('LabelInstructionsDialog', () => {
  it('lists the board’s rows, naming each one’s scope', async () => {
    const { api, list } = stubApi([
      row(),
      row({ id: 'li3', projectId: 'p1', label: 'ui' }),
    ]);
    await render(api, 'p1');

    expect(list).toHaveBeenCalledWith({ projectId: 'p1' });
    const items = [
      ...document.body.querySelectorAll('[data-slot="label-instruction"]'),
    ];
    expect(items.map((node) => node.textContent)).toEqual([
      expect.stringContaining('All projects'),
      expect.stringContaining('Geniro'),
    ]);
  });

  it('creates instructions for a picked label, defaulting to the open project', async () => {
    const { api, create } = stubApi([]);
    const onChanged = vi.fn();
    await render(api, 'p1', onChanged);

    await act(async () => {
      button('Add instructions').click();
    });
    await act(async () => {
      button('Label').click();
    });
    await act(async () => {
      button('Add label frontend').click();
    });
    const text = document.body.querySelector(
      '#label-instructions-text',
    ) as HTMLTextAreaElement;
    await act(async () => {
      setValue(text, 'Check it in a narrow window.');
    });
    await act(async () => {
      button('Save').click();
    });

    expect(create).toHaveBeenCalledWith({
      createLabelInstructionDto: {
        label: 'frontend',
        projectId: 'p1',
        instructions: 'Check it in a narrow window.',
      },
    });
    // The board refetches its label suggestions off this.
    expect(onChanged).toHaveBeenCalledTimes(1);
  });

  it('edits an existing row through update, never create', async () => {
    const { api, create, update } = stubApi([row()]);
    await render(api);

    await act(async () => {
      button('Edit instructions for bug').click();
    });
    const text = document.body.querySelector(
      '#label-instructions-text',
    ) as HTMLTextAreaElement;
    await act(async () => {
      setValue(text, 'Reproduce it first.');
    });
    await act(async () => {
      button('Save').click();
    });

    expect(update).toHaveBeenCalledWith({
      instructionId: 'li1',
      updateLabelInstructionDto: {
        label: 'bug',
        projectId: null,
        instructions: 'Reproduce it first.',
      },
    });
    expect(create).not.toHaveBeenCalled();
  });

  it('saves only once both a label and instructions are given', async () => {
    const { api } = stubApi([]);
    await render(api);

    await act(async () => {
      button('Add instructions').click();
    });
    const text = document.body.querySelector(
      '#label-instructions-text',
    ) as HTMLTextAreaElement;
    await act(async () => {
      setValue(text, 'Check it in a narrow window.');
    });
    // Instructions alone are not enough…
    expect(button('Save').disabled).toBe(true);

    await act(async () => {
      button('Label').click();
    });
    await act(async () => {
      button('Add label frontend').click();
    });
    expect(button('Save').disabled).toBe(false);

    // …and neither is a label once the instructions are only whitespace.
    await act(async () => {
      setValue(text, '   ');
    });
    expect(button('Save').disabled).toBe(true);
  });

  it('tells the board after a delete so its label suggestions refresh', async () => {
    const { api } = stubApi([row()]);
    const onChanged = vi.fn();
    await render(api, null, onChanged);

    await act(async () => {
      button('Delete instructions for bug').click();
    });

    expect(onChanged).toHaveBeenCalledTimes(1);
  });

  it('deletes a row and takes it off the list', async () => {
    const { api, remove } = stubApi([row()]);
    await render(api);

    await act(async () => {
      button('Delete instructions for bug').click();
    });

    expect(remove).toHaveBeenCalledWith({ instructionId: 'li1' });
    expect(
      document.body.querySelectorAll('[data-slot="label-instruction"]').length,
    ).toBe(0);
  });
});
