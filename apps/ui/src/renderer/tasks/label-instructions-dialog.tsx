import { Pencil, Plus, Trash2 } from 'lucide-react';
import { useCallback, useEffect, useState } from 'react';

import type {
  LabelInstructionDto,
  LabelInstructionsApi,
  ProjectDto,
} from '../autogenerated';
import { ErrorBanner } from '../components/error-banner';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Label } from '../components/ui/label';
import { Select } from '../components/ui/select';
import { describeDaemonError } from '../daemon-api';
import { LabelEditor } from './label-editor';
import { TaskLabel } from './task-chip';

/** The scope row standing for "every project" — `projectId: null` on the wire. */
const GLOBAL_SCOPE = '__global__';

interface Draft {
  /** Null while creating. */
  id: string | null;
  label: string;
  projectId: string | null;
  instructions: string;
}

/**
 * Instructions attached to a task LABEL — for every project, or for one — which
 * a run on any card carrying that label receives beside the user's own.
 *
 * The label is picked from the ones already in use or typed new, through the
 * same editor a card uses, held to one label.
 */
export function LabelInstructionsDialog({
  open,
  onClose,
  api,
  projects,
  selectedProjectId,
  knownLabels,
  onChanged,
}: {
  open: boolean;
  onClose: () => void;
  api: LabelInstructionsApi | null;
  projects: readonly ProjectDto[];
  /** The board's open project: the list is narrowed to it, and new rows default to it. */
  selectedProjectId: string | null;
  knownLabels: readonly string[];
  /** Called after every successful write, so label suggestions can refresh. */
  onChanged?: () => void;
}): React.JSX.Element {
  const [rows, setRows] = useState<LabelInstructionDto[]>([]);
  const [draft, setDraft] = useState<Draft | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);

  const load = useCallback(async (): Promise<void> => {
    if (api === null) {
      return;
    }
    try {
      setRows(
        await api.listLabelInstructions(
          selectedProjectId === null ? {} : { projectId: selectedProjectId },
        ),
      );
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    }
  }, [api, selectedProjectId]);

  useEffect(() => {
    if (open) {
      setDraft(null);
      setError(null);
      void load();
    }
  }, [open, load]);

  const scopeName = (projectId: string | null): string =>
    projectId === null
      ? 'All projects'
      : (projects.find((row) => row.id === projectId)?.name ?? 'A project');

  const save = async (): Promise<void> => {
    if (api === null || draft === null) {
      return;
    }
    setSaving(true);
    try {
      const body = {
        label: draft.label,
        projectId: draft.projectId,
        instructions: draft.instructions,
      };
      if (draft.id === null) {
        await api.createLabelInstruction({ createLabelInstructionDto: body });
      } else {
        await api.updateLabelInstruction({
          instructionId: draft.id,
          updateLabelInstructionDto: body,
        });
      }
      setDraft(null);
      setError(null);
      onChanged?.();
      await load();
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    } finally {
      setSaving(false);
    }
  };

  const remove = async (row: LabelInstructionDto): Promise<void> => {
    if (api === null) {
      return;
    }
    try {
      await api.deleteLabelInstruction({ instructionId: row.id });
      setRows((current) =>
        current.filter((candidate) => candidate.id !== row.id),
      );
      onChanged?.();
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    }
  };

  const suggestions = [
    ...new Set([...knownLabels, ...rows.map((row) => row.label)]),
  ].sort((a, b) => a.localeCompare(b));
  const canSave =
    draft !== null &&
    draft.label.trim() !== '' &&
    draft.instructions.trim() !== '' &&
    !saving;

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Label instructions"
      className="max-w-xl">
      <div className="flex flex-col gap-3">
        <p className="m-0 text-xs text-muted-foreground">
          A task carrying one of these labels runs with its instructions added.
        </p>

        {error !== null ? (
          <ErrorBanner
            message={error}
            onDismiss={() => {
              setError(null);
            }}
          />
        ) : null}

        {rows.length === 0 && draft === null ? (
          <p className="m-0 text-sm text-muted-foreground">
            No label has instructions yet.
          </p>
        ) : null}

        <ul className="m-0 flex list-none flex-col gap-2 p-0">
          {rows.map((row) => (
            <li
              key={row.id}
              data-slot="label-instruction"
              className="flex min-w-0 items-start gap-2 rounded-lg border border-border p-2">
              <div className="flex min-w-0 flex-1 flex-col gap-1">
                <span className="flex min-w-0 items-center gap-2">
                  <TaskLabel label={row.label} />
                  <span className="truncate text-xs text-muted-foreground">
                    {scopeName(row.projectId)}
                  </span>
                </span>
                <span className="line-clamp-2 text-xs whitespace-pre-wrap">
                  {row.instructions}
                </span>
              </div>
              <Button
                variant="ghost"
                size="icon"
                className="size-7 shrink-0"
                aria-label={`Edit instructions for ${row.label}`}
                onClick={() => {
                  setDraft({
                    id: row.id,
                    label: row.label,
                    projectId: row.projectId,
                    instructions: row.instructions,
                  });
                }}>
                <Pencil className="size-3.5" aria-hidden />
              </Button>
              <Button
                variant="ghost"
                size="icon"
                className="size-7 shrink-0"
                aria-label={`Delete instructions for ${row.label}`}
                onClick={() => {
                  void remove(row);
                }}>
                <Trash2 className="size-3.5" aria-hidden />
              </Button>
            </li>
          ))}
        </ul>

        {draft === null ? (
          <Button
            variant="outline"
            size="sm"
            className="self-start"
            disabled={api === null}
            onClick={() => {
              setDraft({
                id: null,
                label: '',
                projectId: selectedProjectId,
                instructions: '',
              });
            }}>
            <Plus className="size-3.5" aria-hidden />
            Add instructions
          </Button>
        ) : (
          <div
            data-slot="label-instruction-editor"
            className="flex flex-col gap-3 rounded-lg border border-border p-3">
            <div className="flex flex-col gap-1.5">
              <Label>Label</Label>
              <LabelEditor
                labels={draft.label === '' ? [] : [draft.label]}
                suggestions={suggestions}
                onChange={(next) => {
                  setDraft({ ...draft, label: next.at(-1) ?? '' });
                }}
              />
            </div>
            <div className="flex flex-col gap-1.5">
              <Label>Applies to</Label>
              <Select
                aria-label="Applies to"
                groups={[
                  {
                    items: [
                      { value: GLOBAL_SCOPE, label: 'All projects' },
                      ...projects.map((project) => ({
                        value: project.id,
                        label: project.name,
                      })),
                    ],
                  },
                ]}
                value={draft.projectId ?? GLOBAL_SCOPE}
                onValueChange={(value) => {
                  setDraft({
                    ...draft,
                    projectId: value === GLOBAL_SCOPE ? null : value,
                  });
                }}
              />
            </div>
            <div className="flex flex-col gap-1.5">
              <Label htmlFor="label-instructions-text">Instructions</Label>
              <ExpandableTextarea
                id="label-instructions-text"
                title="Label instructions"
                value={draft.instructions}
                onChange={(next) => {
                  setDraft({ ...draft, instructions: next });
                }}
                placeholder="What an agent should do differently on a task with this label"
              />
            </div>
            <div className="flex justify-end gap-2">
              <Button
                variant="ghost"
                size="sm"
                onClick={() => {
                  setDraft(null);
                }}>
                Cancel
              </Button>
              <Button
                size="sm"
                disabled={!canSave}
                onClick={() => {
                  void save();
                }}>
                Save
              </Button>
            </div>
          </div>
        )}
      </div>
    </Dialog>
  );
}
