// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { createPreloadStub } from '../__fixtures__/preload-stub';
import { withVocabulary } from '../__tests__/agent-vocabulary-api';
import type { CapabilitiesDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { NewProjectDialog } from './new-project-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  window.geniro = createPreloadStub({
    pickProjectFolder: vi.fn(async () => null),
  });
});

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.restoreAllMocks();
});

async function flush(): Promise<void> {
  await act(async () => {
    for (let i = 0; i < 6; i += 1) {
      await Promise.resolve();
    }
  });
}

const agentsApi = withVocabulary({
  listAgentModels: vi.fn(async () => [
    { id: 'opus', label: 'Opus', source: 'cli' as const },
  ]),
  listAgentEfforts: vi.fn(async () => ({
    efforts: [{ id: 'high', label: 'High' }],
    unavailableReason: null,
  })),
}) as unknown as DaemonApis['agents'];

const capabilitiesApi = {
  getCapabilities: vi.fn(
    async () =>
      ({
        configDirs: [{ agent: 'claude', unavailableReason: null }],
        interactiveTerminals: [],
        approvals: [{ agent: 'claude', modes: ['ask', 'auto'], probe: null }],
        followUps: [],
      }) as unknown as CapabilitiesDto,
  ),
} as unknown as DaemonApis['capabilities'];

function mount(onCreate: (input: unknown) => void, onClose = vi.fn()): void {
  act(() => {
    root!.render(
      <NewProjectDialog
        open
        onClose={onClose}
        onCreate={onCreate}
        agentsApi={agentsApi}
        capabilitiesApi={capabilitiesApi}
      />,
    );
  });
}

function button(name: string): HTMLButtonElement {
  const found = [...document.querySelectorAll('button')].find(
    (b) =>
      b.getAttribute('aria-label') === name || b.textContent?.trim() === name,
  );
  if (!found) {
    throw new Error(`no button "${name}"`);
  }
  return found;
}

function option(text: string): HTMLElement {
  const found = [
    ...document.querySelectorAll<HTMLElement>('[role="option"]'),
  ].find((o) => o.textContent?.trim() === text);
  if (!found) {
    throw new Error(`no "${text}" option`);
  }
  return found;
}

function click(node: HTMLElement): void {
  act(() => {
    node.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

function type(id: string, value: string): void {
  const input = document.getElementById(id) as HTMLInputElement;
  act(() => {
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )!.set!;
    setter.call(input, value);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

describe('NewProjectDialog', () => {
  it('creates the project with the model and effort chosen in its run settings', async () => {
    const onCreate = vi.fn();
    mount(onCreate);
    await flush();

    type('new-project-name', 'Mobile');
    type('new-project-folder', '/Users/me/code/mobile');
    click(button('Project run settings'));
    await flush();
    click(button('Model'));
    click(option('Opus'));
    await flush();
    click(button('Reasoning effort'));
    click(option('High'));
    click(button('Create project'));

    expect(onCreate).toHaveBeenCalledWith({
      name: 'Mobile',
      folder: '/Users/me/code/mobile',
      agentKind: 'claude',
      model: 'opus',
      effort: 'high',
    });
  });

  it('closes its run settings on Escape and keeps the draft', async () => {
    const onClose = vi.fn();
    mount(vi.fn(), onClose);
    await flush();
    type('new-project-name', 'Mobile');
    click(button('Project run settings'));
    expect(
      document.querySelector(
        '[aria-label="Project run settings"][role="dialog"]',
      ),
    ).not.toBeNull();

    act(() => {
      document.dispatchEvent(
        new KeyboardEvent('keydown', {
          key: 'Escape',
          bubbles: true,
          cancelable: true,
        }),
      );
    });

    expect(
      document.querySelector(
        '[aria-label="Project run settings"][role="dialog"]',
      ),
    ).toBeNull();
    expect(onClose).not.toHaveBeenCalled();
    expect(
      (document.getElementById('new-project-name') as HTMLInputElement).value,
    ).toBe('Mobile');
  });
});
