import { useEffect, useRef, useState } from 'react';

import {
  CLI_KINDS,
  type CliDetection,
  type CliKind,
  type ConfigProfile,
} from '../../shared/contracts';
import type { CreateProjectDto } from '../autogenerated';
import type { TargetTeam } from '../chats/target-select';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { Label } from '../components/ui/label';
import type { DaemonApis } from '../daemon-api';
import {
  ProjectRunConfig,
  type ProjectRunDefaults,
} from './project-run-config';
import { targetPatch } from './task-target';

/** What a new project is pointed at before the user touches the picker. */
const FALLBACK_TARGET = CLI_KINDS[0]!;

function defaultsFor(target: string): ProjectRunDefaults {
  return {
    ...targetPatch(target),
    model: null,
    effort: null,
    contextWindow: null,
    modelParameters: {},
    approval: null,
    configDir: null,
  };
}

export function NewProjectDialog({
  open,
  onClose,
  onCreate,
  teams = [],
  cliDetections = null,
  agentsApi = null,
  capabilitiesApi = null,
  recentConfigDirs = {},
  configProfiles = [],
}: {
  open: boolean;
  onClose: () => void;
  onCreate: (input: CreateProjectDto) => void;
  teams?: readonly TargetTeam[];
  cliDetections?: readonly CliDetection[] | null;
  agentsApi?: DaemonApis['agents'] | null;
  capabilitiesApi?: DaemonApis['capabilities'] | null;
  recentConfigDirs?: Partial<Record<CliKind, readonly string[]>>;
  configProfiles?: readonly ConfigProfile[];
}): React.JSX.Element {
  const [name, setName] = useState('');
  const [folder, setFolder] = useState('');
  /**
   * Seeded from the composer's own remembered target, which is what makes this
   * field cost the user nothing: a project created without touching it runs as
   * whatever they last chose for a chat.
   *
   * It is a REQUIRED field with a good default rather than an optional one,
   * and that is the whole fix for the defect this dialog caused. The daemon
   * treats a null agent as "unset — fall back to whatever the composer would
   * have", but nothing implemented that fallback, so every project made here
   * named no agent and every task run on it was refused. Answering the question
   * once, at the moment the project is made, is what stops that recurring —
   * where a silent runtime default would pin an agent the user never chose.
   */
  const [runDefaults, setRunDefaults] = useState<ProjectRunDefaults>(() =>
    defaultsFor(FALLBACK_TARGET),
  );
  const [runConfigOpen, setRunConfigOpen] = useState(false);
  const runDefaultsTouched = useRef(false);
  useEffect(() => {
    if (!open) {
      return;
    }
    runDefaultsTouched.current = false;
    setRunDefaults(defaultsFor(FALLBACK_TARGET));
    void window.geniro
      .getSettings()
      .then((settings) => {
        if (!runDefaultsTouched.current) {
          setRunDefaults(
            defaultsFor(settings.lastChatTarget || FALLBACK_TARGET),
          );
        }
      })
      .catch(() => {
        // A settings read that failed is not worth an error on this dialog:
        // the fallback is a real answer and the picker is right there.
      });
  }, [open]);
  const ready = name.trim().length > 0 && folder.trim().length > 0;

  // The dialog is visibility-toggled rather than remounted, so a draft
  // abandoned with Cancel, Escape or the backdrop is still sitting there on the
  // next open unless every exit clears it.
  const close = (): void => {
    setName('');
    setFolder('');
    setRunConfigOpen(false);
    onClose();
  };

  return (
    <Dialog open={open} onClose={close} title="New project">
      <div className="flex flex-col gap-4">
        <div className="flex flex-col gap-1.5">
          <Label htmlFor="new-project-name">Name</Label>
          <Input
            id="new-project-name"
            value={name}
            onChange={(event) => {
              setName(event.target.value);
            }}
          />
        </div>
        {/* DEFAULT, not the law: a card may name a folder of its own, and one
            board routinely holds work across several checkouts. The label says
            so, since a field reading `Folder` on the project reads as the one
            place the answer is given. */}
        <div className="flex flex-col gap-1.5">
          <Label htmlFor="new-project-folder">Default folder</Label>
          <div className="flex gap-2">
            <Input
              id="new-project-folder"
              value={folder}
              placeholder="/path/to/repo"
              onChange={(event) => {
                setFolder(event.target.value);
              }}
            />
            <Button
              variant="outline"
              onClick={() => {
                void window.geniro.pickProjectFolder().then((chosen) => {
                  if (chosen) {
                    setFolder(chosen);
                  }
                });
              }}>
              Browse
            </Button>
          </div>
        </div>
        {/* DEFAULT again, on the folder's own terms — a card may name its own
            agent, and a board routinely mixes a team for the big jobs with
            a single agent for the small ones. The project page's own run
            settings panel, so a project starts with everything it can hold. */}
        <div className="flex flex-col gap-1.5">
          <Label>Default agent or team</Label>
          <div className="flex">
            <ProjectRunConfig
              project={runDefaults}
              teams={teams}
              cliDetections={cliDetections}
              agentsApi={agentsApi}
              capabilitiesApi={capabilitiesApi}
              recentConfigDirs={recentConfigDirs}
              configProfiles={configProfiles}
              open={runConfigOpen}
              onOpenChange={setRunConfigOpen}
              onUpdate={(patch) => {
                runDefaultsTouched.current = true;
                setRunDefaults((current) => ({
                  ...current,
                  ...patch,
                  modelParameters:
                    patch.modelParameters === undefined
                      ? current.modelParameters
                      : (patch.modelParameters ?? {}),
                }));
              }}
            />
          </div>
        </div>
        <div className="flex justify-end gap-2">
          <Button variant="ghost" onClick={close}>
            Cancel
          </Button>
          <Button
            disabled={!ready}
            // Disabled rather than validating on submit: the two fields ARE
            // the requirement. No `title` to explain it - `buttonVariants` sets
            // `disabled:pointer-events-none`, so a disabled button never
            // receives the hover its tooltip would need.
            onClick={() => {
              // CREATE takes non-nullable optionals, unlike the patch route, so
              // an unset default is dropped rather than sent as null.
              const {
                agentKind,
                teamSlug,
                model,
                effort,
                contextWindow,
                modelParameters,
                approval,
                configDir,
              } = runDefaults;
              onCreate({
                name: name.trim(),
                folder: folder.trim(),
                ...(agentKind === null ? {} : { agentKind }),
                ...(teamSlug === null ? {} : { teamSlug }),
                ...(model === null ? {} : { model }),
                ...(effort === null ? {} : { effort }),
                ...(contextWindow === null ? {} : { contextWindow }),
                ...(Object.keys(modelParameters).length === 0
                  ? {}
                  : { modelParameters }),
                ...(approval === null ? {} : { approval }),
                ...(configDir === null ? {} : { configDir }),
              });
              setName('');
              setFolder('');
              setRunConfigOpen(false);
            }}>
            Create project
          </Button>
        </div>
      </div>
    </Dialog>
  );
}
