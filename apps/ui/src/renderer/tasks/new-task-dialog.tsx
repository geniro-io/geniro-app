import { useEffect, useState } from 'react';

import { type CreateTaskDto, TaskPriority, TaskStatus } from '../autogenerated';
import { insertPastedFilePaths } from '../chats/paste-file-paths';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { Label } from '../components/ui/label';
import { cn } from '../components/ui/utils';
import {
  PropertyGroup,
  PropertyRow,
  TaskBasicRows,
  type TaskFieldsContext,
  type TaskFieldsValue,
  TaskRunConfigRows,
  VALUE_INSET,
} from './task-fields';

/** Everything the create route takes except the board it lands on. */
export type NewTaskInput = Omit<CreateTaskDto, 'projectId'>;

/**
 * A blank card, in the status of the column whose + was pressed.
 *
 * The cast is the board's own: a column id IS a daemon status, and the board
 * carries them as strings so a status this build has never heard of still
 * draws a column (`unknown-status.spec.tsx`).
 */
function blankDraft(status: string): TaskFieldsValue {
  return {
    status: status as TaskStatus,
    priority: TaskPriority.None,
    dueDate: null,
    labels: [],
    folder: null,
    agentKind: null,
    workflowSlug: null,
    model: null,
    effort: null,
    approval: null,
    configDir: null,
  };
}

/**
 * Writing a new card, on the SAME form the card is read and edited on.
 *
 * REPORTED as "let's make new task popup with same design as when we open task
 * — it should be same component". It was three stacked `Label` + `Input`
 * blocks: a title, a description and a folder path, in a narrow dialog that
 * looked nothing like the panel the card opens in a second later — and the
 * mismatch was not only visual. Every other property a card carries (its
 * status, its priority, its due date, its labels, the agent that works it and
 * everything that agent runs with) could be set ONLY by creating the card and
 * then opening it, so the dialog's real job was to get a title on screen.
 *
 * The rows are `task-fields.tsx`'s, rendered here exactly as the panel renders
 * them, so the two cannot drift. What differs is what a DRAFT can honestly
 * offer: it has no id yet, so there are no files, no branch, no run, no
 * identifier and no timestamps — those rows are simply not composed here,
 * rather than drawn disabled.
 */
export function NewTaskDialog({
  open,
  onClose,
  onCreate,
  status = TaskStatus.Backlog,
  projectName = null,
  knownLabels = [],
  context,
}: {
  open: boolean;
  onClose: () => void;
  onCreate: (input: NewTaskInput) => void;
  /** The column the + was pressed in — where this card starts. */
  status?: string;
  /** The board this card lands on, stated for the reason the panel states it. */
  projectName?: string | null;
  knownLabels?: readonly string[];
  /** The project's defaults and the vocabularies, as the panel builds them. */
  context: TaskFieldsContext;
}): React.JSX.Element {
  const [title, setTitle] = useState('');
  const [description, setDescription] = useState('');
  const [draft, setDraft] = useState<TaskFieldsValue>(() => blankDraft(status));
  const ready = title.trim().length > 0;

  /**
   * The dialog is visibility-toggled rather than remounted, so it is reset on
   * OPEN rather than in `close()`: Escape and a backdrop click are exits too,
   * and a draft abandoned through either would otherwise be sitting there next
   * time. Opening is also the only moment the pressed column is known.
   */
  useEffect(() => {
    if (open) {
      setTitle('');
      setDescription('');
      setDraft(blankDraft(status));
    }
  }, [open, status]);

  const patch = (next: Partial<TaskFieldsValue>): void => {
    setDraft((current) => ({ ...current, ...next }));
  };

  const submit = (): void => {
    const { folder, agentKind, workflowSlug, model, effort, approval } = draft;
    onCreate({
      title: title.trim(),
      status: draft.status,
      priority: draft.priority,
      labels: draft.labels,
      // Omitted rather than sent empty or null: create takes non-nullable
      // optionals, and an ABSENT field is what makes the card inherit the
      // project's answer — which is exactly what a null here means on screen.
      ...(description.trim() === '' ? {} : { description: description.trim() }),
      ...(draft.dueDate === null ? {} : { dueDate: draft.dueDate }),
      ...(folder === null ? {} : { folder }),
      ...(agentKind === null ? {} : { agentKind }),
      ...(workflowSlug === null ? {} : { workflowSlug }),
      ...(model === null ? {} : { model }),
      ...(effort === null ? {} : { effort }),
      ...(approval === null ? {} : { approval }),
    });
  };

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="New task"
      // The panel's popup width, and for its reason: this holds a form rather
      // than a sentence, and at the app's default `max-w-md` the property rows
      // would be a narrow column with a backdrop behind it.
      className="max-w-3xl">
      <div data-slot="new-task" className="flex flex-col gap-4">
        {/* The title leads, at the size the panel gives it — it is the one
            string a user quotes elsewhere, and on a blank card it is also the
            only required field. `Dialog` focuses the first control after its
            ✕, which is this. */}
        <Input
          id="new-task-title"
          aria-label="Task title"
          placeholder="Task title"
          // The panel's title, drawn as a field: same size and weight, no box
          // of its own at rest, the same hover tint the panel's title button
          // wears — and `Dialog` puts the caret here on open, so the one
          // required field on this form is where a user is already typing.
          className="h-auto border-transparent bg-transparent px-1 text-lg font-semibold leading-snug hover:bg-accent/50 md:text-lg"
          value={title}
          onChange={(event) => {
            setTitle(event.target.value);
          }}
        />

        <PropertyGroup name="Properties">
          {projectName === null ? null : (
            <PropertyRow name="Project">
              <span className={cn('truncate text-xs', VALUE_INSET)}>
                {projectName}
              </span>
            </PropertyRow>
          )}
          <TaskBasicRows
            value={draft}
            onChange={patch}
            onStatusChange={(next) => {
              patch({ status: next as TaskStatus });
            }}
            knownLabels={knownLabels}
          />
          {/* NO Files row: an attachment is bound to a card by id, and this
              card has none until it is created. It is one of the first things
              the panel offers on the card that opens next. */}
        </PropertyGroup>

        <PropertyGroup name="Run configuration">
          <TaskRunConfigRows value={draft} onChange={patch} context={context} />
        </PropertyGroup>

        <div className="flex flex-col gap-2 border-t border-border pt-3">
          {/* A `Label` rather than a heading, wearing the caption's styling:
              `ExpandableTextarea` forwards the id to a real `Textarea`, so
              `htmlFor` genuinely associates them and clicking the word focuses
              the field. */}
          <Label
            htmlFor="new-task-description"
            className="text-[10px] font-medium tracking-wider text-muted-foreground uppercase">
            Description
          </Label>
          <ExpandableTextarea
            id="new-task-description"
            value={description}
            title="Description"
            rows={5}
            maxRows={16}
            placeholder="What should the agent do? Paste a file to reference it."
            // The path half of the panel's paste, and only that half: a pasted
            // IMAGE is bytes the daemon writes under the card's own directory,
            // which needs an id this draft does not have yet. A file already on
            // disk is a path, and a path is what the agent opens.
            onPaste={(event) => {
              if (insertPastedFilePaths(event.clipboardData)) {
                event.preventDefault();
              }
            }}
            onChange={setDescription}
          />
        </div>

        <div className="flex justify-end gap-2">
          <Button variant="ghost" onClick={onClose}>
            Cancel
          </Button>
          <Button disabled={!ready} onClick={submit}>
            Add task
          </Button>
        </div>
      </div>
    </Dialog>
  );
}
