import { CirclePause, FolderGit2, Plus, Zap } from 'lucide-react';

import type { ProjectDto } from '../autogenerated';
import { folderName } from '../chats/directory-select';
import { Select, type SelectGroup } from '../components/ui/select';
import { cn } from '../components/ui/utils';

/**
 * The row that OPENS the new-project dialog instead of selecting a project.
 *
 * It shares the value space with the project ids, which is safe because the row
 * carries `action: true`: the menu never treats an action row as a choice, so
 * it can never become the picker's value or wear the checkmark, and `labelOf`
 * skips it when resolving what the trigger shows.
 */
const NEW_PROJECT = '__new-project__';

/** Past this many, finding a project by eye is slower than typing it. */
const SEARCHABLE_FROM = 8;

/** Mirrors the daemon's own threshold; see `Tasks.tsx`. */
const FAILURE_BREAKER_THRESHOLD = 3;

/**
 * The ambient state of one project's autopilot, or nothing at all.
 *
 * Nothing is the common case and has to LOOK like nothing: a project nobody
 * armed must not carry a marker saying so, or the glyph stops meaning
 * anything. Both tones come from tokens already in use — `muted-foreground`
 * for armed, `warning` for a tripped breaker — because a new colour under
 * `apps/ui/src/renderer` is an eslint error, and because this is a state worth
 * noticing rather than one worth interrupting for.
 */
function AutopilotMark({
  project,
}: {
  project: ProjectDto;
}): React.JSX.Element | null {
  if (!project.autopilotEnabled) {
    return null;
  }
  const stopped = project.autopilotFailureStreak >= FAILURE_BREAKER_THRESHOLD;
  const label = stopped
    ? `${project.name}: autopilot stopped after ${project.autopilotFailureStreak} failed runs`
    : `${project.name}: autopilot on`;
  const Icon = stopped ? CirclePause : Zap;
  return (
    <Icon
      // The accessible name rather than a `title`, and for this app's usual
      // reason: an aria-label wins the name computation, so a fact stated only
      // in a tooltip is silent to the reader that most needs it.
      role="img"
      aria-label={label}
      className={cn(
        'size-3.5 shrink-0',
        stopped ? 'text-warning' : 'text-muted-foreground',
      )}
    />
  );
}

/**
 * The board's project switcher, in the page header.
 *
 * It was a 224px nav rail down the left edge, and that was the wrong shape for
 * what it holds: a board has ONE project open, so a permanent column listing
 * the others spent the board's width on a choice that is made rarely, next to a
 * header that held a single button and otherwise read as an empty line. The
 * switcher belongs where the thing it names is identified.
 *
 * `New project…` moved in here with it. The rail carried that button along its
 * bottom edge, and deleting the rail without rehoming it would have left a user
 * with no projects unable to make one from this screen at all.
 */
export function ProjectPicker({
  projects,
  selectedProjectId,
  onSelect,
  onNewProject,
}: {
  projects: ProjectDto[];
  selectedProjectId: string | null;
  onSelect: (projectId: string) => void;
  onNewProject: () => void;
}): React.JSX.Element {
  const groups: SelectGroup[] = [
    ...(projects.length > 0
      ? [
          {
            items: projects.map((project) => ({
              value: project.id,
              label: project.name,
              // The folder is what tells two checkouts of one repo apart, so it
              // rides every row rather than only the tooltip.
              hint: folderName(project.folder),
              title: project.folder,
              // On EVERY row, not only the open one: which of your projects
              // are working unattended is a question about the list, and
              // answering it only for the one already on screen answers the
              // half you did not need to ask.
              icon: <AutopilotMark project={project} />,
            })),
          },
        ]
      : []),
    {
      items: [
        {
          value: NEW_PROJECT,
          label: 'New project…',
          icon: <Plus className="size-4" aria-hidden />,
          action: true,
        },
      ],
    },
  ];

  const selected = projects.find((row) => row.id === selectedProjectId) ?? null;

  return (
    <div className="min-w-0 shrink">
      <Select
        aria-label="Project"
        variant="ghost"
        groups={groups}
        value={selectedProjectId}
        placeholder="No projects yet"
        triggerLabel={
          selected === null ? undefined : (
            // ONE line, at the height of every other control on this row.
            //
            // It was two lines, name over folder, because side by side they
            // competed for a fixed 256px and a long pair truncated BOTH
            // halves — `Harn… geniro-claude-har…`, destroying the half that
            // identifies the project. Stacking fixed that at the cost of
            // making the picker the tallest thing in a header of 32px
            // controls, so the row read as one heavy box plus an afterthought.
            //
            // The cause was the fixed width and the even fight, not the shared
            // line: the control now sizes to its content, the NAME never
            // shrinks, and the folder is the half that gives way. So the
            // original defect cannot return — what truncates is the fact the
            // menu rows and the tooltip both still state in full.
            <span className="flex min-w-0 items-center gap-1.5">
              <span className="shrink-0">{selected.name}</span>
              <AutopilotMark project={selected} />
              <span className="min-w-0 truncate text-muted-foreground">
                {folderName(selected.folder)}
              </span>
            </span>
          )
        }
        title={selected?.folder}
        // Opens DOWNWARD, which every other picker in the app does not: the
        // default `top` grows a panel upward from the trigger, right for the
        // composer chips at the foot of the window and wrong for the first
        // control this app has put at the TOP of one. `Menu` clamps rather
        // than flips — only `Popover` flips — and the clamp is floored, so
        // the rows simply ran off the top edge. Measured in the running app:
        // three rows open in the DOM with a sliver of the panel on screen.
        side="bottom"
        leadingIcon={
          <FolderGit2 className="size-4 shrink-0 text-muted-foreground" />
        }
        searchPlaceholder={
          projects.length >= SEARCHABLE_FROM ? 'Find a project…' : undefined
        }
        onValueChange={(value) => {
          if (value === NEW_PROJECT) {
            onNewProject();
            return;
          }
          onSelect(value);
        }}
      />
    </div>
  );
}
