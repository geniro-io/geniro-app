import { Plus } from 'lucide-react';

import type { ProjectDto } from '../autogenerated';
import { folderName } from '../chats/directory-select';
import { NavListItem } from '../components/nav-list-item';
import { Button } from '../components/ui/button';

export function ProjectPicker({
  projects,
  selectedProjectId,
  onSelect,
  onNewProject,
}: {
  projects: ProjectDto[];
  selectedProjectId: string | null;
  onSelect: (projectId: string) => void;
  onNewProject: () => void;
}): React.JSX.Element {
  return (
    <nav
      aria-label="Projects"
      className="flex w-56 shrink-0 flex-col border-r border-border">
      <div className="flex min-h-0 flex-1 flex-col gap-1 overflow-y-auto p-2">
        {projects.map((project) => (
          <NavListItem
            key={project.id}
            active={project.id === selectedProjectId}
            title={project.name}
            subtitle={folderName(project.folder)}
            onActivate={() => {
              onSelect(project.id);
            }}
          />
        ))}
        {projects.length === 0 ? (
          <p className="p-2 text-xs text-muted-foreground">
            No projects yet. A project binds a folder, and its tasks become the
            board.
          </p>
        ) : null}
      </div>
      <div className="border-t border-border p-2">
        <Button
          variant="ghost"
          size="sm"
          className="w-full justify-start"
          onClick={onNewProject}>
          <Plus className="size-4" aria-hidden />
          New project
        </Button>
      </div>
    </nav>
  );
}
