// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { createPreloadStub } from '../__fixtures__/preload-stub';
import type {
  AgentEffort,
  AgentModelDto,
  CapabilitiesDto,
} from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { aProject } from './__tests__/fixtures';
import { ProjectRunConfig } from './project-run-config';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  window.geniro = createPreloadStub({
    pickProjectFolder: vi.fn(async () => null),
  });
});

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.restoreAllMocks();
});

/** Flush the microtask queue a resolved daemon-API promise settles on. */
async function flush(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
  });
}

function agentsApi(
  models: AgentModelDto[] = [],
  efforts: AgentEffort[] = [],
): DaemonApis['agents'] {
  return {
    listAgentModels: vi.fn(async () => models),
    listAgentEfforts: vi.fn(async () => ({ efforts, unavailableReason: null })),
  } as unknown as DaemonApis['agents'];
}

function capabilitiesApi(
  over: Partial<CapabilitiesDto> = {},
): DaemonApis['capabilities'] {
  const caps: CapabilitiesDto = {
    claudeModes: {
      acceptEdits: 'pass',
      plan: 'pass',
      version: 'claude 2',
      probedAt: 1,
      reason: null,
    },
    configDirs: [{ agent: 'claude', unavailableReason: null }],
    interactiveTerminals: [],
    approvals: [
      { agent: 'claude', modes: ['ask', 'acceptEdits', 'plan', 'auto'] },
    ],
    followUps: [],
    ...over,
  } as unknown as CapabilitiesDto;
  return {
    getCapabilities: vi.fn(async () => caps),
  } as unknown as DaemonApis['capabilities'];
}

function render(
  props: Partial<React.ComponentProps<typeof ProjectRunConfig>> = {},
): {
  onUpdate: ReturnType<typeof vi.fn>;
} {
  const onUpdate = vi.fn();
  act(() => {
    root!.render(
      <ProjectRunConfig
        project={aProject({ agentKind: 'claude' })}
        workflows={[]}
        cliDetections={null}
        agentsApi={null}
        capabilitiesApi={null}
        open
        onOpenChange={vi.fn()}
        onUpdate={onUpdate}
        {...props}
      />,
    );
  });
  return { onUpdate };
}

function el(): HTMLDivElement {
  if (container === null) {
    throw new Error('not mounted');
  }
  return container;
}

/** The one button whose accessible name matches, or a failure naming what was found. */
function button(name: string): HTMLButtonElement {
  const found = [...el().querySelectorAll('button')].find(
    (b) =>
      b.getAttribute('aria-label') === name || b.textContent?.trim() === name,
  );
  if (!found) {
    throw new Error(
      `no button "${name}" — found: ${[...el().querySelectorAll('button')]
        .map((b) => b.getAttribute('aria-label') ?? b.textContent?.trim())
        .join(' | ')}`,
    );
  }
  return found;
}

function click(node: HTMLElement): void {
  act(() => {
    node.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

/** Every option row currently open in a menu. */
function options(): HTMLElement[] {
  return [...el().querySelectorAll<HTMLElement>('[role="option"]')];
}

function optionNamed(text: string): HTMLElement {
  const found = options().find((o) => o.textContent?.trim() === text);
  if (!found) {
    throw new Error(
      `no "${text}" option — found: ${options()
        .map((o) => o.textContent?.trim())
        .join(' | ')}`,
    );
  }
  return found;
}

describe('ProjectRunConfig', () => {
  it('picking a workflow clears every per-CLI field along with the agent', () => {
    const { onUpdate } = render({
      project: aProject({ agentKind: 'claude', model: 'opus', effort: 'high' }),
      workflows: [{ slug: 'review-team', name: 'Review team' }],
    });

    click(button('Agent or workflow for this project'));
    click(optionNamed('Review team'));

    expect(onUpdate).toHaveBeenCalledWith({
      agentKind: null,
      workflowSlug: 'review-team',
      model: null,
      effort: null,
      approval: null,
      configDir: null,
    });
  });

  // Clearing on a workflow switch alone leaves a claude→cursor-agent switch
  // carrying the stale claude model into a cursor run — the exact bug
  // `resolveRunTarget` cannot see past, since it reads each field off
  // whichever level named it first. `approval` is in the patch for the same
  // reason and is the harder one to spot: `plan` is claude-only, and the
  // chip filters it out of the options, so a carried one is invisible while
  // refusing every start.
  it('picking a DIFFERENT agent clears every per-CLI field too', async () => {
    const { onUpdate } = render({
      project: aProject({ agentKind: 'claude', model: 'opus', effort: 'high' }),
      agentsApi: agentsApi(),
      capabilitiesApi: capabilitiesApi(),
    });
    await flush();

    click(button('Agent or workflow for this project'));
    click(optionNamed('cursor-agent'));

    expect(onUpdate).toHaveBeenCalledWith({
      agentKind: 'cursor-agent',
      workflowSlug: null,
      model: null,
      effort: null,
      approval: null,
      configDir: null,
    });
  });

  it('picking a model drops the effort level chosen under the old one', async () => {
    const { onUpdate } = render({
      project: aProject({ agentKind: 'claude' }),
      agentsApi: agentsApi([{ id: 'opus', label: 'Opus', source: 'cli' }]),
      capabilitiesApi: capabilitiesApi(),
    });
    await flush();

    click(button('Model'));
    click(optionNamed('Opus'));

    expect(onUpdate).toHaveBeenCalledWith({ model: 'opus', effort: null });
  });

  it('draws no Model row for a workflow target', () => {
    render({
      project: aProject({ agentKind: null, workflowSlug: 'review-team' }),
      workflows: [{ slug: 'review-team', name: 'Review team' }],
    });

    expect(el().querySelector('[aria-label="Model"]')).toBeNull();
  });

  it('withholds plan from the approval modes it offers', async () => {
    render({
      project: aProject({ agentKind: 'claude' }),
      agentsApi: agentsApi(),
      capabilitiesApi: capabilitiesApi(),
    });
    await flush();

    click(button('Tool-approval mode'));

    // `ask` and `auto-approve` are the CLI's honoured modes reaching the menu;
    // `plan` is honoured too (per the capabilities mock) and still must not
    // appear, since `planSupported` is hardcoded false for an unattended
    // board default.
    expect(options().some((o) => o.textContent?.trim() === 'ask')).toBe(true);
    expect(options().some((o) => o.textContent?.trim() === 'plan')).toBe(false);
  });

  it('offers a Profile row when the CLI supports a config directory', async () => {
    const { onUpdate } = render({
      project: aProject({
        agentKind: 'claude',
        configDir: '/repo/.claude-work',
      }),
      agentsApi: agentsApi(),
      capabilitiesApi: capabilitiesApi(),
    });
    await flush();

    click(button('Config directory for this project'));
    click(optionNamed('Default profile'));

    expect(onUpdate).toHaveBeenCalledWith({ configDir: null });
  });

  it('draws no Profile row for a CLI with no config-directory mechanism', async () => {
    render({
      project: aProject({ agentKind: 'claude' }),
      agentsApi: agentsApi(),
      capabilitiesApi: capabilitiesApi({
        configDirs: [
          {
            agent: 'claude',
            unavailableReason: 'this CLI has no such control',
          },
        ],
      }),
    });
    await flush();

    expect(
      el().querySelector('[aria-label="Config directory for this project"]'),
    ).toBeNull();
  });

  // The panel is mounted in the board header whenever a project is open,
  // well before its own chip is pressed — an ungated vocabulary read would pay
  // a real CLI handshake on every board visit for a popover nobody opened.
  it('asks the CLI nothing while the popover is shut', async () => {
    const models = vi.fn(async () => []);
    const efforts = vi.fn(async () => ({
      efforts: [],
      unavailableReason: null,
    }));
    render({
      project: aProject({ agentKind: 'claude' }),
      open: false,
      agentsApi: {
        listAgentModels: models,
        listAgentEfforts: efforts,
      } as unknown as DaemonApis['agents'],
      capabilitiesApi: null,
    });
    await flush();

    expect(models).not.toHaveBeenCalled();
    expect(efforts).not.toHaveBeenCalled();
  });
});
