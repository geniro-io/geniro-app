import { Bot, Workflow as WorkflowIcon } from 'lucide-react';
import { useRef } from 'react';

import type {
  CliDetection,
  CliKind,
  ConfigProfile,
} from '../../shared/contracts';
import type { ChatApprovalMode, ProjectDto } from '../autogenerated';
import { ApprovalModeSelect } from '../chats/approval-mode-select';
import { workflowSlugOf } from '../chats/composer-values';
import { ConfigDirSelect } from '../chats/config-dir-select';
import { EffortSelect } from '../chats/effort-select';
import { ModelSelect } from '../chats/model-select';
import { TargetSelect, type TargetWorkflow } from '../chats/target-select';
import { Chip, ChipChevron } from '../components/ui/chip';
import { LoadingChip } from '../components/ui/loading-chip';
import { Popover } from '../components/ui/popover';
import type { DaemonApis } from '../daemon-api';
import { targetLabel, targetOf, targetPatch } from './task-target';
import { useRunConfigVocabulary } from './use-run-config-vocabulary';

/** What this control may change about a project — its run defaults, only. */
export interface ProjectRunConfigPatch {
  agentKind?: ProjectDto['agentKind'];
  workflowSlug?: string | null;
  model?: string | null;
  effort?: string | null;
  approval?: ChatApprovalMode | null;
  configDir?: string | null;
}

/**
 * What every task on this board runs as, unless the card says otherwise.
 *
 * It lives on the board header beside the autopilot chip, and for that chip's
 * own recorded reason: this is where the thing it governs is. A per-project
 * run configuration filed under Settings makes the user leave the board to
 * answer a question about the board — and worse here, because the answer is
 * what decides whether the Run button on that board works at all.
 *
 * It exists because nothing in this app could set these columns. The daemon has
 * carried `agentKind` / `model` / `effort` / `workflowSlug` on a project since
 * the board shipped and accepted them on both DTOs; the new-project dialog
 * collected a name and a folder, and no other surface wrote them — so every
 * project made in the app named no agent, and `TaskRunsService` refused every
 * start with `TASK_RUN_NO_AGENT`, once by hand and once per autopilot tick.
 *
 * A chip opening a panel rather than three controls in the header, again on the
 * autopilot chip's reasoning: the header is the row for acting on the board as
 * a whole, and a third run of pickers across it would push New task off the
 * end.
 */
export function ProjectRunConfig({
  project,
  workflows,
  cliDetections,
  agentsApi,
  capabilitiesApi,
  recentConfigDirs = [],
  configProfiles = [],
  open,
  onOpenChange,
  onUpdate,
}: {
  project: ProjectDto;
  workflows: readonly TargetWorkflow[];
  cliDetections: readonly CliDetection[] | null;
  /** For the model and effort vocabularies, which the CLI itself reports. */
  agentsApi: DaemonApis['agents'] | null;
  /** For the approval modes, which each adapter declares. */
  capabilitiesApi: DaemonApis['capabilities'] | null;
  /** The user's recent config-directory picks, for the Profile row's picker. */
  recentConfigDirs?: readonly string[];
  /** The user's named config directories, so a chosen profile wears its colour. */
  configProfiles?: readonly ConfigProfile[];
  /**
   * CONTROLLED, because this panel is opened from somewhere else as well as
   * from its own chip: the intake column's `N tasks cannot start` explains a
   * board with no agent and then offers to fix it, and the fix is this panel.
   * A control that only its own trigger can open leaves that offer as prose
   * pointing at a chip.
   */
  open: boolean;
  onOpenChange: (open: boolean) => void;
  onUpdate: (patch: ProjectRunConfigPatch) => void;
}): React.JSX.Element {
  const triggerRef = useRef<HTMLButtonElement | null>(null);

  const target = targetOf(project);
  const workflowSlug = target === null ? null : workflowSlugOf(target);
  // A workflow's nodes each name their own model and effort in the YAML, so
  // there is nothing here for a run-level answer to apply to — the same
  // subtraction `resolveRunTarget` makes on the daemon side.
  //
  // Gated on `open` too, not merely on the workflow check: this component is
  // mounted in the board header whenever a project is open, well before its
  // chip is ever pressed, so an ungated agent here paid a real CLI vocabulary
  // handshake (models, efforts) on every board visit for a panel nobody
  // opened.
  const agentKind: CliKind | null =
    !open || workflowSlug !== null
      ? null
      : ((target as CliKind | null) ?? null);
  // The same three questions a CARD's own overrides ask — one hook, so the two
  // forms cannot come to disagree about what a CLI offers.
  const {
    models,
    modelsLoading,
    efforts,
    effortsLoading,
    approvalModes,
    approvalModesLoading,
    configDirUnavailableReason,
  } = useRunConfigVocabulary({
    agentsApi,
    capabilitiesApi,
    agentKind,
    model: project.model,
    configDir: project.configDir,
  });

  const label = targetLabel(target, workflows);

  return (
    <div className="relative">
      <Chip
        asChild
        interactive
        // MUTED when nothing is set, and that is the chip's most important
        // state rather than an edge case: it is the one thing on screen that
        // explains a board where every Run press is refused.
        tone={target === null ? 'muted' : 'active'}
        data-menu-trigger>
        <button
          type="button"
          ref={triggerRef}
          aria-label="Project run settings"
          aria-expanded={open}
          onClick={() => {
            onOpenChange(!open);
          }}>
          {workflowSlug !== null ? (
            <WorkflowIcon aria-hidden />
          ) : (
            <Bot aria-hidden />
          )}
          {/* The STATE, not the word alone — the autopilot chip's own rule. */}
          {label === null ? 'No agent' : `Agent · ${label}`}
          <ChipChevron />
        </button>
      </Chip>
      <Popover
        open={open}
        onClose={() => {
          onOpenChange(false);
        }}
        triggerRef={triggerRef}
        side="bottom"
        align="start"
        anchor="viewport"
        label="Project run settings"
        className="w-80 p-3">
        <div className="flex flex-col gap-3">
          <div className="flex min-w-0 flex-col">
            <span className="text-sm font-medium">Run settings</span>
            <span className="text-xs text-muted-foreground">
              What every task here runs as, unless the task says otherwise.
            </span>
          </div>

          <label className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
            Agent or workflow
            <TargetSelect
              value={target ?? ''}
              workflows={workflows}
              cliDetections={cliDetections}
              aria-label="Agent or workflow for this project"
              {...(target === null ? { triggerLabel: 'Choose an agent…' } : {})}
              onChange={(next) => {
                // A model, an effort level, an approval mode and a config
                // directory each belong to the CLI that offered them, so ANY
                // change of target clears all four — a switch to a workflow
                // (whose runs are graphs) AND a switch between two CLIs alike.
                //
                // The two that matter most are the two the screen cannot show
                // you. `configDir`'s row is withheld for a CLI that reads
                // none; `approval`'s options are filtered to the modes the
                // CLI supports, so a `plan` carried from claude to
                // cursor-agent is absent from the chip while still refusing
                // every start with `does not support the approval mode`.
                onUpdate({
                  ...targetPatch(next),
                  model: null,
                  effort: null,
                  approval: null,
                  configDir: null,
                });
              }}
            />
          </label>

          {/* Withheld for a workflow, and OMITTED rather than disabled — the
              rule the effort and context chips already follow: a control drawn
              to be refused says the feature is broken, where its absence says
              the question does not arise. */}
          {agentKind !== null ? (
            <>
              <label className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
                Model
                <ModelSelect
                  agentKind={agentKind}
                  models={models}
                  value={project.model}
                  loading={modelsLoading}
                  onChange={(model) => {
                    // A model belongs to the CLI that offered it, so changing
                    // it drops an effort level picked under the old one.
                    onUpdate({ model, effort: null });
                  }}
                />
              </label>
              <label className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
                Effort
                {/* The waiting state the CARD's own rows already draw. Without
                    it a cold daemon — one ACP handshake per listing — renders
                    an unanswered axis exactly like a CLI that offers none,
                    which is the confusion the hook's flags exist to remove. */}
                {effortsLoading ? (
                  <LoadingChip noun="effort levels" />
                ) : (
                  <EffortSelect
                    efforts={efforts}
                    value={project.effort}
                    onChange={(effort) => {
                      onUpdate({ effort });
                    }}
                  />
                )}
              </label>
              {/* REPORTED as missing: "у меня даже таких settings нет в модели,
                  типа proof mod agent на проекте" — the daemon has carried
                  `Project.approval` since the board shipped and nothing could
                  set it, so a board could only ever run at whatever the start
                  path chose.

                  `plan` is withheld (`planSupported={false}`): it makes an
                  agent write a plan and stop, which is not a thing to pin as a
                  whole board's default. A project already stored on it keeps
                  the option, since `approvalOptions` never hides the value it
                  is displaying. */}
              <label className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
                Approval
                {approvalModesLoading ? (
                  <LoadingChip noun="approval modes" />
                ) : (
                  <ApprovalModeSelect
                    supportedModes={approvalModes}
                    value={project.approval}
                    planSupported={false}
                    onChange={(approval) => {
                      onUpdate({ approval });
                    }}
                  />
                )}
              </label>
              {/* WITHHELD entirely (never disabled) for a CLI with no config-
                  directory mechanism, and left as no row at all while the
                  capability probe has not answered — `ConfigDirSelect`'s own
                  rule, the same one the row above already follows for a
                  workflow target. */}
              {configDirUnavailableReason === null ? (
                <label className="flex items-center justify-between gap-2 text-xs text-muted-foreground">
                  Profile
                  <ConfigDirSelect
                    configDir={project.configDir}
                    recentConfigDirs={[...recentConfigDirs]}
                    configProfiles={configProfiles}
                    unavailableReason={configDirUnavailableReason}
                    ariaLabel="Config directory for this project"
                    onChange={(configDir) => {
                      onUpdate({ configDir });
                    }}
                    onBrowse={() => {
                      void window.geniro.pickProjectFolder().then((chosen) => {
                        if (chosen) {
                          onUpdate({ configDir: chosen });
                        }
                      });
                    }}
                  />
                </label>
              ) : null}
              {/* Said HERE rather than left to be discovered, because this is
                  the one setting on the panel that an armed board overrides.
                  An unattended run cannot answer a permission card — nothing
                  expires it, so the run holds its slot and its worktree for
                  ever — which is why the daemon forces auto-approval for the
                  autopilot whatever stands on this row. */}
              <p className="text-xs text-muted-foreground">
                Autopilot always auto-approves — an unattended run has nobody to
                ask. This is what a Run press uses.
              </p>
            </>
          ) : null}
        </div>
      </Popover>
    </div>
  );
}
