import { Play } from 'lucide-react';
import { useEffect, useState } from 'react';

import type { TaskDto } from '../autogenerated';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Label } from '../components/ui/label';
import { taskIdentifier } from './task-identifier';

/**
 * The press of Run, with room for the one thing the card cannot say.
 *
 * ASKED FOR as "it should always ask for additional prompt optional" — and the
 * reason it is worth a dialog rather than a straight start is what a SECOND
 * press means. A card is run, reviewed, and sent back; the next press is never
 * "do the same thing again", it is "the tests still fail" or "do the other half
 * now". Without somewhere to say that, the only way to say it was to leave the
 * board, find the thread, and type it there.
 *
 * There is NO new-thread-or-continue choice, and that is the settled answer
 * rather than an omission: it was asked for and then withdrawn in the same
 * breath — "let's even not ask user to create new chat - let's always continue
 * in existing one". The daemon continues the card's own thread whenever there
 * is one to continue, so this dialog only has to say which of the two is about
 * to happen.
 */
export function RunTaskDialog({
  open,
  task,
  taskKey = null,
  starting = false,
  onClose,
  onRun,
}: {
  open: boolean;
  /** The card being run, or null while none is. */
  task: TaskDto | null;
  /** The board's prefix, for the card's identifier — `GEN` of `GEN-12`. */
  taskKey?: string | null;
  /** This card's run is being started right now. */
  starting?: boolean;
  onClose: () => void;
  /** Run it, with whatever the user added — the empty string for nothing. */
  onRun: (prompt: string) => void;
}): React.JSX.Element {
  const [prompt, setPrompt] = useState('');

  // Cleared on OPEN rather than on close, the new-task dialog's own rule: the
  // ✕, Escape and the backdrop are exits too, and a draft abandoned through
  // any of them would still be sitting there for the next card.
  useEffect(() => {
    if (open) {
      setPrompt('');
    }
  }, [open, task?.id]);

  const identifier = taskIdentifier(taskKey, task?.number ?? null);
  /**
   * Whether this press continues the thread the card already has.
   *
   * Read off the card's own `runId`, which is all the board holds. The daemon
   * makes the real decision and falls back to a new thread when that run has
   * since been deleted or archived — states this side cannot see, and rare
   * enough that stating the ordinary case is worth more than saying nothing.
   */
  const continues = task?.runId != null;

  return (
    <Dialog open={open} onClose={onClose} title="Run task">
      <div data-slot="run-task" className="flex flex-col gap-4">
        {task === null ? null : (
          <div className="flex flex-col gap-1">
            <p className="flex items-baseline gap-2 text-sm font-medium">
              {identifier === null ? null : (
                <span className="shrink-0 font-mono text-xs text-muted-foreground">
                  {identifier}
                </span>
              )}
              <span className="min-w-0 truncate">{task.title}</span>
            </p>
            <p className="text-xs text-muted-foreground">
              {continues
                ? 'Continues this task’s existing thread, so the agent still has everything said there.'
                : 'Starts a thread for this task, on the card’s own brief.'}
            </p>
          </div>
        )}

        <div className="flex flex-col gap-1.5">
          <Label htmlFor="run-task-prompt">Anything to add? (optional)</Label>
          <ExpandableTextarea
            id="run-task-prompt"
            value={prompt}
            title="Instructions for this run"
            rows={4}
            maxRows={14}
            placeholder={
              continues
                ? 'e.g. the tests still fail — start with the parser'
                : 'e.g. start with the parser'
            }
            onChange={setPrompt}
          />
          {/* Said only where it is TRUE. On a new thread the brief is sent
              whatever else happens, so there is nothing to warn about; on a
              continued one the card's own words are what fills the silence,
              and a user who expects "just carry on" should know that. */}
          {continues ? (
            <p className="text-xs text-muted-foreground">
              Left empty, the task’s brief is sent again — so an edited
              description or a newly attached file reaches the agent.
            </p>
          ) : null}
        </div>

        <div className="flex justify-end gap-2">
          <Button variant="ghost" onClick={onClose}>
            Cancel
          </Button>
          <Button
            disabled={task === null || starting}
            onClick={() => {
              onRun(prompt.trim());
            }}>
            <Play className="size-3.5" aria-hidden />
            {starting ? 'Starting…' : 'Run task'}
          </Button>
        </div>
      </div>
    </Dialog>
  );
}
