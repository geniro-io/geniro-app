// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { TaskFile } from '../autogenerated';
import { TaskAttachments } from './task-attachments';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const file = (over: Partial<TaskFile> = {}): TaskFile => ({
  id: 'a1',
  name: 'bundle.zip',
  path: '/u/downloads/bundle.zip',
  bytes: 2_411_724,
  ...over,
});

function render(
  props: Partial<React.ComponentProps<typeof TaskAttachments>> = {},
): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(<TaskAttachments files={[]} {...props} />);
  });
  return container;
}

const byLabel = (el: HTMLElement, label: string): HTMLElement | null =>
  el.querySelector(`[aria-label="${label}"]`);

/**
 * The files a user binds to a card.
 *
 * REPORTED as missing — "я всё ещё не могу прицеплять файлы, например
 * zip-архивы, то есть как attachments" — after images (which arrive as bytes
 * and are written to disk) already worked.
 */
describe('TaskAttachments', () => {
  it('lists a file by name, with its size', () => {
    const el = render({ files: [file()] });

    expect(el.textContent).toContain('bundle.zip');
    expect(el.textContent).toContain('2.3 MB');
  });

  it('puts the PATH on the row, which is what explains a broken link', () => {
    // The name is already on screen; the path is the fact that diagnoses a
    // file the user has since moved — geniro references rather than copies.
    const el = render({ files: [file()] });
    const row = el.querySelector('[title]');

    expect(row?.getAttribute('title')).toBe('/u/downloads/bundle.zip');
  });

  it('says nothing about a size it could not read', () => {
    expect(
      render({ files: [file({ bytes: null })] }).textContent,
    ).not.toContain('B');
  });

  it('offers REMOVAL in words that promise no delete', () => {
    // The one thing this control must never do is delete the user's own
    // archive, so the accessible name says what it does instead.
    const onDetach = vi.fn();
    const el = render({ files: [file()], onDetach });
    const remove = byLabel(el, 'Remove bundle.zip from this task');

    expect(remove?.getAttribute('title')).toContain('file itself is left');
    act(() => {
      remove?.click();
    });
    expect(onDetach).toHaveBeenCalledWith('a1');
  });

  it('attaches what the picker answered with', async () => {
    window.geniro = createPreloadStub({
      pickTaskFiles: () => Promise.resolve(['/u/a.zip', '/u/b.csv']),
    });
    const onAttach = vi.fn();
    const el = render({ onAttach });

    act(() => {
      [...el.querySelectorAll('button')]
        .find((node) => node.textContent?.includes('Attach'))
        ?.click();
    });
    await act(async () => {
      await Promise.resolve();
    });

    expect(onAttach).toHaveBeenCalledWith(['/u/a.zip', '/u/b.csv']);
  });

  it('attaches a DROPPED file by its real path', () => {
    // How somebody with a zip in a Finder window will actually try first.
    window.geniro = createPreloadStub({ filePath: () => '/u/dropped.zip' });
    const onAttach = vi.fn();
    const el = render({ onAttach });
    const zone = el.querySelector('[data-slot="task-attachments"]');

    act(() => {
      const event = new Event('drop', { bubbles: true });
      Object.defineProperty(event, 'dataTransfer', {
        value: { files: [new File([''], 'dropped.zip')] },
      });
      zone?.dispatchEvent(event);
    });

    expect(onAttach).toHaveBeenCalledWith(['/u/dropped.zip']);
  });

  it('accepts the drag, or the browser navigates away from the app', () => {
    // An un-prevented `dragover` means the drop opens the file, replacing the
    // whole window with a PDF and losing its state.
    const el = render({ onAttach: vi.fn() });
    const zone = el.querySelector('[data-slot="task-attachments"]');
    const event = new Event('dragover', { bubbles: true, cancelable: true });

    act(() => {
      zone?.dispatchEvent(event);
    });

    expect(event.defaultPrevented).toBe(true);
  });

  it('offers no controls where there is nothing to attach through', () => {
    // The harness, and any caller with no daemon — a control that cannot work
    // is worse than its absence.
    const el = render({ files: [file()] });

    expect(el.querySelector('button')).toBeNull();
  });
});
