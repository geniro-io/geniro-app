import { Paperclip, X } from 'lucide-react';
import { useRef, useState } from 'react';

import type { TaskFile } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Spinner } from '../components/ui/spinner';
import { cn } from '../components/ui/utils';
import { isRemoteRuntime } from '../remote/remote-session';

/** `1.2 MB`, or nothing at all for a size that could not be read. */
function formatBytes(bytes: number | null): string | null {
  if (bytes === null || bytes < 0) {
    return null;
  }
  if (bytes < 1024) {
    return `${bytes} B`;
  }
  const units = ['KB', 'MB', 'GB', 'TB'];
  let value = bytes / 1024;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  // One decimal below 10 and none above it: `9.4 MB` is worth the digit,
  // `847.3 MB` is three characters of noise on a row that has to fit a name.
  return `${value < 10 ? value.toFixed(1) : Math.round(value)} ${units[unit]}`;
}

/**
 * The files bound to a card — an archive, a spec, a spreadsheet.
 *
 * REPORTED as missing: "я всё ещё не могу прицеплять файлы, например
 * zip-архивы, то есть как attachments." Pasting had covered images and, for
 * anything else, wrote the file's PATH into the description — which works and
 * is invisible: a path buried in prose cannot be listed, counted or removed.
 *
 * Every row REFERENCES a file that stays where the user put it; geniro copies
 * nothing (the trade is argued daemon-side at `TaskFileSchema`). Two things
 * follow, and both are said on screen rather than left to be discovered: the
 * path is on each row's tooltip, so a link that breaks because the file moved
 * is diagnosable, and the remove control says it removes the REFERENCE.
 *
 * DROPPING is offered beside the picker because it is how somebody with a zip
 * in a Finder window will actually try first — and it costs one handler, the
 * path of a dropped file being exactly what `webUtils.getPathForFile` answers.
 */
export function TaskAttachments({
  files,
  onAttach,
  onDetach,
  onUpload,
  remote = isRemoteRuntime(),
}: {
  files: readonly TaskFile[];
  /** Absent where there is no daemon to attach through — the harness. */
  onAttach?: (paths: readonly string[]) => void;
  onDetach?: (attachmentId: string) => void;
  /**
   * Attach files by their BYTES — what a device with no path on the Mac has to
   * offer. On a phone the native picker belongs to the Mac and is refused, so
   * a path-only button would do nothing at all. There the button opens the
   * browser's own file picker and the files go up through this instead.
   *
   * A PROMISE says the files are going up now rather than being staged: each
   * is then listed with a spinner until it lands, and the button is withheld.
   */
  onUpload?: (files: readonly File[]) => void | Promise<void>;
  /** Whether this is a browser on another device. A prop for the specs. */
  remote?: boolean;
}): React.JSX.Element {
  const [over, setOver] = useState(false);
  const input = useRef<HTMLInputElement>(null);
  // What is on its way up. A phone sends the bytes one file after another over
  // the LAN, so until each lands the list and the button would look untouched
  // and invite a second tap that uploads everything twice. `baseline` is the
  // list's length when the first file was picked: the uploads land in order,
  // one row each, so the ones past it are the ones that arrived.
  const [uploading, setUploading] = useState<{
    names: readonly string[];
    baseline: number;
  } | null>(null);
  const uploadsInFlight = useRef(0);
  const upload = (picked: readonly File[]): void => {
    const pending = onUpload?.(picked);
    if (pending === undefined) {
      return;
    }
    uploadsInFlight.current += 1;
    setUploading((current) => ({
      names: [...(current?.names ?? []), ...picked.map((file) => file.name)],
      baseline: current?.baseline ?? files.length,
    }));
    void pending.finally(() => {
      uploadsInFlight.current -= 1;
      if (uploadsInFlight.current === 0) {
        setUploading(null);
      }
    });
  };
  const stillUploading =
    uploading === null
      ? []
      : uploading.names.slice(Math.max(0, files.length - uploading.baseline));
  // On a remote device a path is never available, so the upload route is the
  // only way in; without it there is nothing an Attach button could do.
  const canAttach = remote ? onUpload !== undefined : onAttach !== undefined;

  const dropped = (event: React.DragEvent<HTMLDivElement>): string[] =>
    [...event.dataTransfer.files]
      .map((file) => window.geniro.filePath(file))
      .filter((path): path is string => path !== null && path !== '');

  return (
    <div
      data-slot="task-attachments"
      onDragOver={(event) => {
        // Without this the browser navigates to the dropped file, which
        // replaces the whole app with a PDF and loses the window's state.
        event.preventDefault();
        setOver(true);
      }}
      onDragLeave={() => {
        setOver(false);
      }}
      onDrop={(event) => {
        event.preventDefault();
        setOver(false);
        if (remote) {
          const picked = [...event.dataTransfer.files];
          if (picked.length > 0) {
            upload(picked);
          }
          return;
        }
        const paths = dropped(event);
        if (paths.length > 0) {
          onAttach?.(paths);
        }
      }}
      className={cn(
        'flex flex-col gap-1 rounded-md transition-colors',
        over && 'bg-accent/40 ring-1 ring-primary',
      )}>
      {files.map((file) => (
        <div
          key={file.id}
          // `min-h-8` is the panel's own property-row height, and it is what
          // makes the `Files` name line up with this first row rather than
          // with the middle of the stack — see `PropertyRow`'s `align`.
          className="flex min-h-8 min-w-0 items-center gap-2 rounded-md px-2 hover:bg-accent/40">
          {/* The PATH on the tooltip, not the name: the name is on screen, and
              the path is the thing that explains a file that has since moved. */}
          <span className="min-w-0 flex-1 truncate text-xs" title={file.path}>
            {file.name}
          </span>
          {formatBytes(file.bytes) === null ? null : (
            <span className="shrink-0 text-[11px] tabular-nums text-muted-foreground">
              {formatBytes(file.bytes)}
            </span>
          )}
          {onDetach === undefined ? null : (
            <button
              type="button"
              // The wording is the whole guarantee: this is not a delete, and a
              // control that read `Delete bundle.zip` would be a promise this
              // app must never keep.
              aria-label={`Remove ${file.name} from this task`}
              title="Removes it from this task. The file itself is left alone."
              onClick={() => {
                onDetach(file.id);
              }}
              className="shrink-0 rounded p-0.5 text-muted-foreground hover:bg-accent hover:text-foreground focus-visible:outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50">
              <X className="size-3" aria-hidden />
            </button>
          )}
        </div>
      ))}
      {stillUploading.map((name, index) => (
        <div
          // By position: two picked files may share a name.
          key={`uploading-${index}`}
          data-slot="task-attachment-uploading"
          className="flex min-h-8 min-w-0 items-center gap-2 rounded-md px-2 text-muted-foreground">
          <Spinner />
          <span className="min-w-0 flex-1 truncate text-xs">{name}</span>
        </div>
      ))}
      {!canAttach ? null : (
        <>
          {remote ? (
            // Opened by the button below, synchronously inside its press —
            // the only way a mobile browser will show its picker.
            <input
              ref={input}
              type="file"
              multiple
              hidden
              data-slot="task-attachments-upload"
              onChange={(event) => {
                const picked = [...(event.target.files ?? [])];
                // Cleared so picking the SAME file again still fires `change`.
                event.target.value = '';
                if (picked.length > 0) {
                  upload(picked);
                }
              }}
            />
          ) : null}
          <Button
            variant="ghost"
            size="sm"
            className="h-8 w-fit px-2 text-[11px] text-muted-foreground"
            disabled={uploading !== null}
            onClick={() => {
              if (remote) {
                input.current?.click();
                return;
              }
              void window.geniro.pickTaskFiles().then((paths) => {
                if (paths.length > 0) {
                  onAttach?.(paths);
                }
              });
            }}>
            <Paperclip className="size-3.5" aria-hidden />
            {uploading !== null
              ? 'Uploading…'
              : files.length === 0
                ? 'Attach files'
                : 'Attach more'}
          </Button>
        </>
      )}
    </div>
  );
}
