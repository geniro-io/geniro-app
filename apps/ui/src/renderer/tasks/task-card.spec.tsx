// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { TaskDto } from '../autogenerated';
import { TaskCard } from './task-card';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const task = (over: Partial<TaskDto> = {}): TaskDto =>
  ({
    id: 't1',
    projectId: 'p1',
    title: 'Wire the board',
    description: null,
    status: 'in_progress',
    labels: [],
    source: 'manual',
    branch: null,
    position: 0,
    ...over,
  }) as TaskDto;

function render(node: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(node);
  });
  return container;
}

const card = (over: Partial<TaskDto> = {}, props = {}): HTMLButtonElement => {
  const el = render(
    <TaskCard
      task={task(over)}
      selected={false}
      dragging={false}
      onOpen={vi.fn()}
      onDragStart={vi.fn()}
      onDragEnd={vi.fn()}
      {...props}
    />,
  );
  return el.querySelector('button') as HTMLButtonElement;
};

describe('TaskCard', () => {
  it('announces its column and the keyboard move on the accessible name', () => {
    // On aria-label and not title: an aria-label wins the accessible-name
    // computation, so an affordance stated only in a tooltip is silent to the
    // screen reader that most needs it. The sibling queued-strip puts its
    // arrow hint on `title` and is the pattern NOT to copy here.
    const name = card().getAttribute('aria-label') ?? '';

    expect(name).toContain('In progress');
    expect(name.toLowerCase()).toContain('arrow');
  });

  it('is draggable and carries its id for the drop handler', () => {
    const el = card();

    expect(el.getAttribute('draggable')).toBe('true');
    expect(el.dataset.taskId).toBe('t1');
  });

  it('folds labels past the second into a count', () => {
    const el = card({ labels: ['a', 'b', 'c', 'd'] });

    expect(el.textContent).toContain('+2');
  });

  it('dims itself while it is the card being dragged', () => {
    const plain = card();
    const plainClass = plain.className;
    act(() => {
      root?.unmount();
    });
    container?.remove();

    const el = card({}, { dragging: true });

    expect(plainClass).not.toContain('opacity-40');
    expect(el.className).toContain('opacity-40');
  });
});
