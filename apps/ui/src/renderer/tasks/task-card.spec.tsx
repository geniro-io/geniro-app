// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { TaskDto } from '../autogenerated';
import { aTask } from './__tests__/fixtures';
import { TaskCard, VISIBLE_LABELS } from './task-card';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const task = (over: Partial<TaskDto> = {}): TaskDto =>
  aTask({ title: 'Wire the board', status: 'in_progress', ...over });

function render(node: React.ReactElement): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(node);
  });
  return container;
}

const card = (over: Partial<TaskDto> = {}, props = {}): HTMLButtonElement => {
  const el = render(
    <TaskCard
      task={task(over)}
      selected={false}
      dragging={false}
      onOpen={vi.fn()}
      onDragStart={vi.fn()}
      onDragEnd={vi.fn()}
      {...props}
    />,
  );
  return el.querySelector('button') as HTMLButtonElement;
};

describe('TaskCard', () => {
  it('announces its column and the keyboard move on the accessible name', () => {
    // On aria-label and not title: an aria-label wins the accessible-name
    // computation, so an affordance stated only in a tooltip is silent to the
    // screen reader that most needs it. The sibling queued-strip puts its
    // arrow hint on `title` and is the pattern NOT to copy here.
    const name = card().getAttribute('aria-label') ?? '';

    expect(name).toContain('In progress');
    expect(name.toLowerCase()).toContain('arrow');
  });

  it('is draggable and carries its id for the drop handler', () => {
    const el = card();

    expect(el.getAttribute('draggable')).toBe('true');
    expect(el.dataset.taskId).toBe('t1');
  });

  it('folds labels past the visible few into a count', () => {
    // Derived from the component's own constant rather than a literal, so
    // changing how many chips a card shows does not silently leave this test
    // asserting the old design.
    const extra = 2;
    const labels = Array.from(
      { length: VISIBLE_LABELS + extra },
      (_, i) => `label-${i}`,
    );

    const el = card({ labels });

    expect(el.textContent).toContain(`+${extra}`);
    expect(el.textContent).toContain(labels[0]);
    expect(el.textContent).not.toContain(labels[VISIBLE_LABELS]);
  });

  it('dims itself while it is the card being dragged', () => {
    const plain = card();
    const plainClass = plain.className;
    act(() => {
      root?.unmount();
    });
    container?.remove();

    const el = card({}, { dragging: true });

    expect(plainClass).not.toContain('opacity-40');
    expect(el.className).toContain('opacity-40');
  });
});

describe('the richer card', () => {
  it('does not repeat the status the column already states', () => {
    // A deliberate design decision, pinned because it is easy to undo by
    // accident: the card sits IN its status column, so printing "In progress"
    // on every card was noise. Screen readers still hear it — see below.
    const el = card({ status: 'in_progress' });

    expect(el.textContent).not.toContain('In progress');
  });

  it('still names the column in the accessible name', () => {
    // The other half of the decision. A sighted user reads the column header;
    // a screen-reader user has no column to look at, so dropping it from the
    // visible card must not drop it from the name.
    expect(
      card({ status: 'in_progress' }).getAttribute('aria-label'),
    ).toContain('In progress');
  });

  it('previews the description so a card says what the task is', () => {
    const el = card({ description: '## Context\n\nThe cards are too thin.' });

    expect(el.textContent).toContain('The cards are too thin.');
    expect(el.textContent).not.toContain('##');
  });

  it('shows when the task last moved', () => {
    const el = card({
      updatedAt: new Date(Date.now() - 7_200_000).toISOString(),
    });

    expect(el.querySelector('time')?.textContent).toBe('2h');
  });

  it('gives each label its own colour dot', () => {
    const el = card({ labels: ['design', 'infra'] });

    const dots = [...el.querySelectorAll('span')].filter((node) =>
      node.className.includes('bg-group-'),
    );
    expect(dots.length).toBe(2);
    // Different names, different swatches — the point of colouring them.
    expect(dots[0]?.className).not.toBe(dots[1]?.className);
  });
});
