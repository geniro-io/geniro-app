import { CalendarDays, GitBranch } from 'lucide-react';

import type { ActiveTask, TaskDto } from '../autogenerated';
import { shortAgentLabel } from '../chats/agent-label';
import { Spinner } from '../components/ui/spinner';
import { cn } from '../components/ui/utils';
import { dueDateView, shortDate } from './due-date';
import { TaskChip, TaskLabel } from './task-chip';
import { taskIdentifier } from './task-identifier';
import { descriptionPreview } from './task-labels';
import { priorityMeta } from './task-priority';
import { taskStatusMeta } from './task-status';

/** How many label chips a card shows before folding the rest into a +N. */
export const VISIBLE_LABELS = 3;

export function TaskCard({
  task,
  taskKey,
  active,
  selected,
  dragging,
  onOpen,
  onDragStart,
  onDragEnd,
  onKeyDown,
}: {
  task: TaskDto;
  /**
   * The board's own prefix, for this card's identifier — `GEN` of `GEN-12`.
   *
   * From the PROJECT row rather than the card, the two halves living apart:
   * see `taskIdentifier`.
   */
  taskKey?: string | null;
  /**
   * Set while an agent is actually working this card — the daemon's own
   * answer, from the project queue.
   *
   * It cannot be derived here: `task.runId` OUTLIVES the run it names, since a
   * settled card's report is read through exactly that id. Absent = at rest.
   */
  active?: ActiveTask;
  selected: boolean;
  dragging: boolean;
  onOpen: () => void;
  onDragStart: () => void;
  onDragEnd: () => void;
  onKeyDown?: (event: React.KeyboardEvent<HTMLButtonElement>) => void;
}): React.JSX.Element {
  const status = taskStatusMeta(task.status);
  const priority = priorityMeta(task.priority);
  const due = dueDateView(task.dueDate);
  const extra = task.labels.length - VISIBLE_LABELS;
  const preview = descriptionPreview(task.description);
  const showPriority = task.priority !== 'none';
  const agent =
    active === undefined
      ? null
      : (shortAgentLabel(active.agentKind) ?? 'workflow');
  const created = shortDate(task.createdAt);
  const identifier = taskIdentifier(taskKey, task.number);
  const hasChips =
    showPriority ||
    due !== null ||
    task.branch !== null ||
    task.labels.length > 0;

  return (
    <button
      type="button"
      data-task-id={task.id}
      draggable
      onDragStart={(event) => {
        // The id lives in component state; `dataTransfer` is set only because
        // a drag with no data is not required to be legal cross-browser.
        event.dataTransfer.setData('text/plain', task.id);
        event.dataTransfer.effectAllowed = 'move';
        onDragStart();
      }}
      onDragEnd={onDragEnd}
      onClick={onOpen}
      onKeyDown={onKeyDown}
      // The card does not SHOW its status — the column it sits in is the
      // status. The accessible name still states it, plus the priority and due
      // date, which are glyphs and an abbreviation on screen: a screen reader
      // has no column to look at and cannot read an icon.
      aria-label={[
        identifier,
        task.title,
        // AHEAD of the column, because it is the fact that changes what the
        // card is: the column says `In progress`, which is also true of a card
        // whose agent finished minutes ago and is waiting to be reviewed.
        agent === null ? null : `${agent} is working on it`,
        status.label,
        showPriority ? priority.label : null,
        due === null
          ? null
          : `due ${due.label}${due.overdue ? ', overdue' : ''}`,
        'Move between columns with Alt and the left or right arrow.',
      ]
        .filter((part) => part !== null)
        .join(' — ')}
      className={cn(
        // Roomier than it was, and that is Linear's card rather than a
        // preference: the pill row below needs air above and below it or the
        // three rows read as one block of noise.
        'group flex w-full flex-col gap-2 rounded-lg border border-border bg-card px-3 py-2.5 text-left',
        'shadow-panel-sm transition-[box-shadow,border-color] hover:border-border-strong hover:shadow-panel-md',
        'focus-visible:outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50',
        selected && 'border-primary',
        dragging && 'opacity-40',
      )}>
      {/* The IDENTIFIER row — Linear's own, and asked for as such ("нужно
          добавить номер, вот как в linear, то есть по первым буквам проекта и
          номер"). It is what a card is CALLED: `GEN-12` goes in a commit
          message, a chat, a message to somebody else, where a UUID cannot. The
          live agent shares this row because it is Linear's avatar slot — who
          is on it, beside what it is called.

          Drawn only when there is something to put in it: an older card the
          backfill has not reached has no identifier, and a card at rest has no
          agent. */}
      {identifier === null && agent === null ? null : (
        <span className="flex items-center gap-2 text-[11px]">
          <span className="font-mono text-muted-foreground">
            {identifier ?? ''}
          </span>
          {agent === null ? null : (
            <span className="ml-auto flex shrink-0 items-center gap-1 text-primary">
              <Spinner className="size-3" />
              {agent}
            </span>
          )}
        </span>
      )}

      {/* Title row. The priority glyph used to lead it and is now a pill in
          the row below with everything else — Linear's arrangement, and the
          end of a long-running confusion: a bare warning triangle beside a
          title reads as an alarm about that card, which is exactly how it was
          reported ("я не понимаю, что она значит"). In a row of tags it reads
          as a tag. */}
      <span className="flex items-start gap-2">
        <span className="line-clamp-2 min-w-0 flex-1 text-[13px] leading-snug font-medium">
          {task.title}
        </span>
      </span>

      {/* ONE line. Two lines of preview under two lines of title made the
        title stop being the thing the eye lands on, and the panel behind one
        click holds the whole description anyway. */}
      {preview !== null ? (
        <span className="line-clamp-1 text-xs leading-snug text-muted-foreground">
          {preview}
        </span>
      ) : null}

      {/* ONE row of TAGS, all of them the same object — Linear's card, and the
          reason its metadata reads at a glance while ours did not: a due date
          drawn as a small glyph plus muted text, beside a branch drawn as a
          small glyph plus muted text, beside labels drawn as a small dot plus
          muted text, is three different facts in one indistinguishable shape.
          They wrap; nothing here is more important than the title above. */}
      {hasChips ? (
        <span className="flex min-w-0 flex-wrap items-center gap-1">
          {/* FIRST, and icon-only with its name on hover — Linear's own
              priority pill. The word is on the accessible name already. */}
          {showPriority ? (
            <TaskChip title={`${priority.label} priority`}>
              <priority.icon
                className={cn('size-3 shrink-0', priority.className)}
                aria-hidden
              />
            </TaskChip>
          ) : null}
          {task.labels.slice(0, VISIBLE_LABELS).map((label) => (
            <TaskLabel key={label} label={label} className="max-w-32" />
          ))}
          {extra > 0 ? <TaskChip>{`+${extra}`}</TaskChip> : null}
          {due !== null ? (
            <TaskChip
              // Overdue is the one thing on a card that earns alarm colour;
              // due-today is merely soon, and colouring it the same would make
              // every board look on fire by Friday.
              {...(due.overdue ? { tone: 'alarm' as const } : {})}
              title={
                due.overdue ? `Overdue — due ${due.label}` : `Due ${due.label}`
              }>
              <CalendarDays className="size-3 shrink-0" aria-hidden />
              {due.label}
            </TaskChip>
          ) : null}
          {task.branch !== null ? (
            <TaskChip className="max-w-full" title={task.branch}>
              <GitBranch className="size-3 shrink-0" aria-hidden />
              <span className="truncate font-mono">{task.branch}</span>
            </TaskChip>
          ) : null}
        </span>
      ) : null}

      {/* The card's own footer, and the ONE thing on it that is not a tag.
          This REVERSES an earlier cut: the update time was removed for being a
          third metadata row holding a lone figure with no glyph, competing
          with the two above it. In this arrangement there is one metadata row,
          and a quiet dateline under it is what closes the card — which is what
          Linear's does. It is the CREATED date rather than the updated one: a
          card's age is a fact about the card, where "updated" moves every time
          anything touches it and says nothing a reader can act on. */}
      {created === null ? null : (
        <span className="text-[11px] text-muted-foreground/70">
          Created {created}
        </span>
      )}
    </button>
  );
}
