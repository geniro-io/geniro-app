import type { TaskDto } from '../autogenerated';
import { Badge } from '../components/ui/badge';
import { cn } from '../components/ui/utils';
import { TASK_STATUS_META } from './task-status';

/** How many label chips a card shows before folding the rest into a +N. */
const VISIBLE_LABELS = 2;

export function TaskCard({
  task,
  selected,
  dragging,
  onOpen,
  onDragStart,
  onDragEnd,
  onKeyDown,
}: {
  task: TaskDto;
  selected: boolean;
  dragging: boolean;
  onOpen: () => void;
  onDragStart: () => void;
  onDragEnd: () => void;
  onKeyDown?: (event: React.KeyboardEvent<HTMLButtonElement>) => void;
}): React.JSX.Element {
  const meta = TASK_STATUS_META[task.status];
  const extra = task.labels.length - VISIBLE_LABELS;
  return (
    <button
      type="button"
      data-task-id={task.id}
      draggable
      onDragStart={(event) => {
        // The id lives in component state; `dataTransfer` is set only because
        // a drag with no data is not required to be legal cross-browser.
        event.dataTransfer.setData('text/plain', task.id);
        event.dataTransfer.effectAllowed = 'move';
        onDragStart();
      }}
      onDragEnd={onDragEnd}
      onClick={onOpen}
      onKeyDown={onKeyDown}
      // Names the column so a screen reader hears where the card is, and the
      // move affordance so it is discoverable without a mouse. It goes on
      // `aria-label` and NOT on `title`: an aria-label wins the accessible-name
      // computation, so an affordance stated only in a tooltip is silent.
      aria-label={`${task.title} — ${meta.label}. Move between columns with Alt and the left or right arrow.`}
      className={cn(
        'flex w-full flex-col gap-2 rounded-md border border-border bg-card p-3 text-left',
        'shadow-panel-sm transition-shadow hover:shadow-panel-md',
        'focus-visible:outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50',
        selected && 'border-primary',
        dragging && 'opacity-40',
      )}>
      <span className="truncate text-sm font-medium" title={task.title}>
        {task.title}
      </span>
      {task.labels.length > 0 ? (
        <span className="flex flex-wrap gap-1">
          {task.labels.slice(0, VISIBLE_LABELS).map((label) => (
            <Badge key={label} variant="outline">
              {label}
            </Badge>
          ))}
          {extra > 0 ? <Badge variant="outline">{`+${extra}`}</Badge> : null}
        </span>
      ) : null}
      {task.branch !== null ? (
        <span className="truncate font-mono text-xs text-muted-foreground">
          {task.branch}
        </span>
      ) : null}
      <span className={cn('flex items-center gap-1 text-xs', meta.className)}>
        <meta.icon className="size-3 shrink-0" aria-hidden />
        {meta.label}
      </span>
    </button>
  );
}
