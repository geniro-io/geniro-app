import { GitBranch } from 'lucide-react';

import type { TaskDto } from '../autogenerated';
import { formatRelativeTime } from '../chats/relative-time';
import { cn } from '../components/ui/utils';
import { descriptionPreview, labelDotClass } from './task-labels';
import { taskStatusMeta } from './task-status';

/** How many label chips a card shows before folding the rest into a +N. */
export const VISIBLE_LABELS = 3;

export function TaskCard({
  task,
  selected,
  dragging,
  onOpen,
  onDragStart,
  onDragEnd,
  onKeyDown,
}: {
  task: TaskDto;
  selected: boolean;
  dragging: boolean;
  onOpen: () => void;
  onDragStart: () => void;
  onDragEnd: () => void;
  onKeyDown?: (event: React.KeyboardEvent<HTMLButtonElement>) => void;
}): React.JSX.Element {
  const meta = taskStatusMeta(task.status);
  const extra = task.labels.length - VISIBLE_LABELS;
  const preview = descriptionPreview(task.description);
  return (
    <button
      type="button"
      data-task-id={task.id}
      draggable
      onDragStart={(event) => {
        // The id lives in component state; `dataTransfer` is set only because
        // a drag with no data is not required to be legal cross-browser.
        event.dataTransfer.setData('text/plain', task.id);
        event.dataTransfer.effectAllowed = 'move';
        onDragStart();
      }}
      onDragEnd={onDragEnd}
      onClick={onOpen}
      onKeyDown={onKeyDown}
      // The card no longer SHOWS its status — the column it sits in is the
      // status, and repeating it on every card was noise. The accessible name
      // still states it, because a screen-reader user has no column to look at.
      // It goes on `aria-label` and NOT on `title`: an aria-label wins the
      // accessible-name computation, so an affordance stated only in a tooltip
      // is silent.
      aria-label={`${task.title} — ${meta.label}. Move between columns with Alt and the left or right arrow.`}
      className={cn(
        'group flex w-full flex-col gap-1.5 rounded-lg border border-border bg-card px-3 py-2.5 text-left',
        'shadow-panel-sm transition-[box-shadow,border-color] hover:border-border-strong hover:shadow-panel-md',
        'focus-visible:outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50',
        selected && 'border-primary',
        dragging && 'opacity-40',
      )}>
      {task.labels.length > 0 ? (
        <span className="flex flex-wrap items-center gap-x-2 gap-y-1">
          {task.labels.slice(0, VISIBLE_LABELS).map((label) => (
            <span
              key={label}
              className="flex items-center gap-1 text-xs text-muted-foreground">
              <span
                className={cn(
                  'size-2 shrink-0 rounded-full',
                  labelDotClass(label),
                )}
                aria-hidden
              />
              {label}
            </span>
          ))}
          {extra > 0 ? (
            <span className="text-xs text-muted-foreground">{`+${extra}`}</span>
          ) : null}
        </span>
      ) : null}

      <span className="line-clamp-2 text-sm leading-snug font-medium">
        {task.title}
      </span>

      {preview !== null ? (
        <span className="line-clamp-2 text-xs leading-snug text-muted-foreground">
          {preview}
        </span>
      ) : null}

      <span className="mt-0.5 flex items-center gap-2 text-xs text-muted-foreground">
        {task.branch !== null ? (
          <span className="flex min-w-0 items-center gap-1">
            <GitBranch className="size-3 shrink-0" aria-hidden />
            <span className="truncate font-mono">{task.branch}</span>
          </span>
        ) : null}
        <time className="ml-auto shrink-0" dateTime={task.updatedAt}>
          {formatRelativeTime(task.updatedAt)}
        </time>
      </span>
    </button>
  );
}
