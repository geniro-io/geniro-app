// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { TaskDto } from '../autogenerated';
import { aTask } from './__tests__/fixtures';
import { TaskDetail } from './task-detail';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const task = (over: Partial<TaskDto> = {}): TaskDto =>
  aTask({ title: 'Wire the board', status: 'in_review', ...over });

function detail(over: Partial<TaskDto> = {}): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <TaskDetail task={task(over)} onClose={vi.fn()} onSave={vi.fn()} />,
    );
  });
  return container;
}

const buttonNamed = (el: HTMLElement, text: string): HTMLButtonElement =>
  [...el.querySelectorAll('button')].find((node) =>
    (node.textContent ?? '').includes(text),
  ) as HTMLButtonElement;

describe('TaskDetail', () => {
  it('shows Run task disabled, with the reason on screen rather than in a tooltip', () => {
    // Disabled, never hidden: a control that vanishes teaches nothing, while
    // one visibly off says the capability exists and is not ready. The reason
    // cannot live in a `title` — `buttonVariants` sets
    // `disabled:pointer-events-none`, so a disabled button never receives the
    // hover its tooltip would need, and an earlier version of this test
    // asserted exactly that unreachable tooltip.
    const el = detail();
    const run = buttonNamed(el, 'Run task');

    expect(run.disabled).toBe(true);
    expect(el.textContent).toContain('not built yet');
  });

  it('invites a description rather than showing an empty pane', () => {
    expect(detail().textContent).toContain('No description yet');
  });

  it('renders an existing description as markdown, not as raw text', () => {
    // The existing markdown-content.tsx pipeline — the app must never grow a
    // second markdown renderer.
    // A heading would be the obvious probe and is the wrong one: that pipeline
    // deliberately renders `h1` as a bold paragraph, since a transcript has no
    // document outline. Emphasis keeps its own element, so it shows the
    // markdown was parsed rather than printed.
    const el = detail({ description: 'a **bold** word' });

    expect(el.querySelector('strong')?.textContent).toBe('bold');
    expect(el.textContent).not.toContain('**');
  });
});
