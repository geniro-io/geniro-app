// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { type ItemDto, type TaskDto, TaskStatus } from '../autogenerated';
import { aTask } from './__tests__/fixtures';
import { TaskDetail } from './task-detail';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const task = (over: Partial<TaskDto> = {}): TaskDto =>
  aTask({ title: 'Wire the board', status: 'in_review', ...over });

/**
 * `over` carries TASK fields; `props` carries panel props. Two bags rather
 * than one because a spec asserting on the Run control needs to say both
 * "this card holds a run" and "there is a way to start one", and those are
 * different objects.
 */
function detail(
  over: Partial<TaskDto> & {
    onRun?: () => void;
    task?: TaskDto;
    report?: ItemDto | null;
  } = {},
): HTMLDivElement {
  const { onRun, task: given, report, ...fields } = over;
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <TaskDetail
        task={given ?? task(fields)}
        onClose={vi.fn()}
        onSave={vi.fn()}
        onRun={onRun}
        report={report ?? null}
      />,
    );
  });
  return container;
}

/** The detail panel's own save signature, so a spy cannot drift from it. */
type SaveHandler = React.ComponentProps<typeof TaskDetail>['onSave'];
const saveSpy = (): ReturnType<typeof vi.fn<SaveHandler>> =>
  vi.fn<SaveHandler>();

function detailWith({
  onSave = saveSpy(),
  task: over = {},
}: {
  onSave?: ReturnType<typeof saveSpy>;
  task?: Partial<TaskDto>;
}): HTMLDivElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <TaskDetail task={task(over)} onClose={vi.fn()} onSave={onSave} />,
    );
  });
  return container;
}

const buttonNamed = (el: HTMLElement, text: string): HTMLButtonElement =>
  [...el.querySelectorAll('button')].find((node) =>
    (node.textContent ?? '').includes(text),
  ) as HTMLButtonElement;

describe('TaskDetail', () => {
  it('runs the task when there is a handler for it', () => {
    const onRun = vi.fn();
    const el = detail({ onRun });

    const run = buttonNamed(el, 'Run task');
    expect(run.disabled).toBe(false);
    run.click();

    expect(onRun).toHaveBeenCalledTimes(1);
  });

  it('is disabled with a VISIBLE reason when there is no way to run', () => {
    // Disabled, never hidden: a control that vanishes teaches nothing. The
    // reason must be VISIBLE text — `buttonVariants` sets
    // `disabled:pointer-events-none`, so a disabled button never receives the
    // hover a tooltip would need.
    const el = detail();

    expect(buttonNamed(el, 'Run task').disabled).toBe(true);
    expect(el.textContent).toContain('Open a project to run this task');
  });

  it('says an agent is already working, and refuses a second start', () => {
    const el = detail({
      onRun: vi.fn(),
      task: aTask({ status: TaskStatus.InProgress, runId: 'run-1' }),
    });

    expect(buttonNamed(el, 'Running').disabled).toBe(true);
    expect(el.textContent).toContain('An agent is working this task');
  });

  it('names the branch the agent is working on', () => {
    const el = detail({
      onRun: vi.fn(),
      task: aTask({ branch: 'geniro/task-t1' }),
    });

    expect(el.textContent).toContain('geniro/task-t1');
  });

  it('invites a description, and SAYS the region is editable', () => {
    const el = detail();

    expect(el.textContent).toContain('Add a description');
    // The affordance, not just the placeholder: the prose used to sit in a
    // transparent box whose only hint was a border on hover, and it was
    // reported as a description that could not be edited at all.
    expect(el.querySelector('[aria-label="Edit description"]')).not.toBeNull();
  });

  it('renders an existing description as markdown, not as raw text', () => {
    // The existing markdown-content.tsx pipeline — the app must never grow a
    // second markdown renderer.
    // A heading would be the obvious probe and is the wrong one: that pipeline
    // deliberately renders `h1` as a bold paragraph, since a transcript has no
    // document outline. Emphasis keeps its own element, so it shows the
    // markdown was parsed rather than printed.
    const el = detail({ description: 'a **bold** word' });

    expect(el.querySelector('strong')?.textContent).toBe('bold');
    expect(el.textContent).not.toContain('**');
  });
});

describe('priority and due date', () => {
  it('offers the priorities most-urgent first, with no-priority last', () => {
    // Untriaged is not the top of the scale — it is off it, so it sits at the
    // bottom of the list even though the daemon's own array leads with it.
    const el = detail();

    const trigger = el.querySelector(
      '[data-menu-trigger][aria-label="Priority"]',
    ) as HTMLButtonElement;
    act(() => {
      trigger.click();
    });

    const options = [...document.body.querySelectorAll('[role="option"]')].map(
      (node) => node.textContent,
    );
    expect(options).toEqual(['Urgent', 'High', 'Medium', 'Low', 'No priority']);
  });

  it('saves the priority the user picks', () => {
    const onSave = saveSpy();
    const el = detailWith({ onSave });

    act(() => {
      (
        el.querySelector(
          '[data-menu-trigger][aria-label="Priority"]',
        ) as HTMLButtonElement
      ).click();
    });
    const urgent = [...document.body.querySelectorAll('[role="option"]')].find(
      (node) => node.textContent === 'Urgent',
    ) as HTMLElement;
    act(() => {
      urgent.click();
    });

    expect(onSave).toHaveBeenCalledWith({ priority: 'urgent' });
  });

  it('shows the stored due date in the field', () => {
    const el = detail({ dueDate: '2026-09-30' });

    expect((el.querySelector('#task-due-date') as HTMLInputElement).value).toBe(
      '2026-09-30',
    );
  });

  it('clears the due date to null rather than an empty string', () => {
    // The daemon distinguishes `null` (drop it) from the field being absent.
    // An empty string would fail its `z.iso.date()` and land a red banner.
    const onSave = saveSpy();
    const el = detailWith({ onSave, task: { dueDate: '2026-09-30' } });

    const field = el.querySelector('#task-due-date') as HTMLInputElement;
    const setter = Object.getOwnPropertyDescriptor(
      HTMLInputElement.prototype,
      'value',
    )?.set;
    act(() => {
      setter?.call(field, '');
      field.dispatchEvent(new Event('change', { bubbles: true }));
    });

    expect(onSave).toHaveBeenCalledWith({ dueDate: null });
  });

  const anItem = (over: Partial<ItemDto>): ItemDto => ({
    id: 'i1',
    runId: 'run-1',
    nodeId: null,
    seq: 1,
    kind: 'message',
    role: 'assistant',
    payload: null,
    createdAt: '2026-01-01T00:00:00.000Z',
    ...over,
  });

  it('shows no report section for a card that has none', () => {
    expect(detail().textContent).not.toContain('Report');
  });

  it('renders a prose report through the transcript’s own markdown pipeline', () => {
    const el = detail({
      report: anItem({ payload: { text: 'Fixed the *cap*.' } }),
    });

    expect(el.textContent).toContain('Report');
    // The app must never grow a second markdown renderer: emphasis keeps its
    // own element, which is what shows the pipeline actually ran.
    expect(el.querySelector('em')?.textContent).toBe('cap');
  });

  it('renders a STRUCTURED report as the findings card, not as prose', () => {
    const el = detail({
      report: anItem({
        kind: 'report_findings',
        role: null,
        payload: {
          level: 'high',
          findings: [{ file: 'src/a.ts', summary: 'off by one' }],
        },
      }),
    });

    expect(el.querySelector('[data-slot="findings-card"]')).not.toBeNull();
    expect(el.textContent).toContain('off by one');
  });

  it('draws nothing for a row whose payload reads as neither', () => {
    const el = detail({ report: anItem({ payload: { nothing: true } }) });

    expect(el.querySelector('[data-slot="findings-card"]')).toBeNull();
    // Including the HEADING, which would otherwise promise a report the panel
    // has nothing to put under it.
    expect(el.textContent).not.toContain('Report');
  });
});

describe('status', () => {
  /** Mounts the panel with a move handler, which `detail` does not offer. */
  function withMove(
    onMove: (to: string) => void,
    over: Partial<TaskDto> = {},
  ): HTMLDivElement {
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    act(() => {
      root!.render(
        <TaskDetail
          task={task(over)}
          onClose={vi.fn()}
          onSave={vi.fn()}
          onMove={onMove}
        />,
      );
    });
    return container;
  }

  const statusTrigger = (el: HTMLElement): HTMLButtonElement =>
    el.querySelector(
      '[data-menu-trigger][aria-label="Status"]',
    ) as HTMLButtonElement;

  it('moves the card from the panel, which used to need a drag', () => {
    const onMove = vi.fn();
    const el = withMove(onMove, { status: 'todo' as TaskDto['status'] });

    act(() => {
      statusTrigger(el).click();
    });
    const done = [...document.body.querySelectorAll('[role="option"]')].find(
      (node) => node.textContent === 'Done',
    ) as HTMLElement;
    act(() => {
      done.click();
    });

    expect(onMove).toHaveBeenCalledWith('done');
  });

  it('does not move a card re-picked into the column it is already in', () => {
    // `moveTaskStatus` is a compare-and-set the daemon answers 400 to when
    // `from` equals `to`, so a no-op pick must never reach it.
    const onMove = vi.fn();
    const el = withMove(onMove, { status: 'todo' as TaskDto['status'] });

    act(() => {
      statusTrigger(el).click();
    });
    const same = [...document.body.querySelectorAll('[role="option"]')].find(
      (node) => node.textContent === 'To do',
    ) as HTMLElement;
    act(() => {
      same.click();
    });

    expect(onMove).not.toHaveBeenCalled();
  });

  it('locks the picker when the board cannot move the card', () => {
    // Same rule the Run button follows: shown-and-disabled, never withheld.
    expect(statusTrigger(detail()).disabled).toBe(true);
  });
});
