import { Pencil, Play, X } from 'lucide-react';
import { useState } from 'react';

import { type ItemDto, type TaskDto, TaskStatus } from '../autogenerated';
import { MarkdownContent } from '../chats/markdown-content';
import { formatRelativeTime } from '../chats/relative-time';
import { Button } from '../components/ui/button';
import { Input } from '../components/ui/input';
import { MdEditor } from '../components/ui/md-editor';
import { MenuAnchorContext } from '../components/ui/menu';
import { Select } from '../components/ui/select';
import { cn } from '../components/ui/utils';
import { LabelEditor } from './label-editor';
import { PRIORITY_META, PRIORITY_ORDER, priorityMeta } from './task-priority';
import { TaskReport } from './task-report';
import { TASK_STATUS_META, taskStatusMeta } from './task-status';

/** Height of the description editor, in px — `MdEditor` takes a number. */
const EDITOR_HEIGHT = 260;

/**
 * One property of the card: a muted name on the left, its control on the right.
 *
 * A fixed name column rather than `justify-between`, so every control on the
 * panel starts at the same x — with `justify-between` each row's control is
 * pushed by the width of its own label and the column reads as ragged.
 */
function PropertyRow({
  name,
  children,
}: {
  name: string;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <div className="flex min-h-8 items-center gap-2">
      <span className="w-20 shrink-0 text-xs text-muted-foreground">
        {name}
      </span>
      <div className="flex min-w-0 flex-1 flex-wrap items-center gap-1.5">
        {children}
      </div>
    </div>
  );
}

/**
 * What a card is, and everything about it the user can change.
 *
 * Ordered by what the reader came for rather than by what is cheapest to
 * render: the title and the DESCRIPTION first, because that is the card's
 * content, then the properties, then the action, and the timestamps last. The
 * previous arrangement put four bands of metadata between the title and the
 * description, so the one thing a task actually says was the seventh thing on
 * the panel.
 */
export function TaskDetail({
  task,
  onClose,
  onSave,
  onMove,
  onRun,
  starting = false,
  report = null,
  projectFolder = null,
}: {
  task: TaskDto;
  onClose: () => void;
  /** Move the card to another column, from the panel rather than by dragging. */
  onMove?: (to: string) => void;
  /** Start an agent on this card. */
  onRun?: () => void;
  /** This card's run is being started right now. */
  starting?: boolean;
  /** The transcript row holding the agent's closing report, if it wrote one. */
  report?: ItemDto | null;
  /**
   * The project's own folder — what this card's runs use while it names none.
   * Null only while no project is open, where the row states nothing rather
   * than guessing.
   */
  projectFolder?: string | null;
  onSave: (patch: {
    title?: string;
    description?: string;
    labels?: string[];
    priority?: TaskDto['priority'];
    dueDate?: string | null;
    folder?: string | null;
  }) => void;
}): React.JSX.Element {
  const [editingTitle, setEditingTitle] = useState(false);
  const [title, setTitle] = useState(task.title);
  const [editingBody, setEditingBody] = useState(false);
  const [body, setBody] = useState(task.description ?? '');
  const status = taskStatusMeta(task.status);
  // A card is being WORKED when it holds a run and sits in the column that
  // says so. `runId` alone is its history — a reviewed task keeps the run that
  // did the work and must still be startable again.
  const running = task.runId !== null && task.status === 'in_progress';
  const reason =
    onRun === undefined
      ? 'Open a project to run this task.'
      : running
        ? 'An agent is working this task. Open its chat to follow along.'
        : null;

  return (
    // The pane scrolls, so it CLIPS — and a box that scrolls vertically cannot
    // keep `overflow-x: visible`. Declaring the anchor here is the house rule:
    // every menu inside measures its trigger and places itself `fixed`.
    <MenuAnchorContext.Provider value="viewport">
      <aside
        aria-label={`Task: ${task.title}`}
        data-slot="task-detail"
        className="flex w-96 shrink-0 flex-col gap-4 overflow-y-auto border-l border-border p-4">
        <div className="flex items-center gap-2">
          {/* The status is a PICKER here, not the badge it was: the panel is
              where a card is worked on, and moving it was reachable only by
              dragging it across the board. */}
          <Select
            aria-label="Status"
            variant="ghost"
            // `bottom`, against the app's own `top` default: this trigger sits
            // in the panel's first row, and a menu growing upward from it has
            // nowhere to go. `menu.tsx` clamps rather than flips on that axis,
            // and the clamp is FLOORED — measured here at `top: -68.75` for a
            // six-row panel, with two of its rows off the top of the window.
            side="bottom"
            value={task.status}
            disabled={onMove === undefined}
            triggerLabel={
              <span className="inline-flex items-center gap-1.5">
                <status.icon
                  className={cn('size-3.5', status.className)}
                  aria-hidden
                />
                {status.label}
              </span>
            }
            groups={[
              {
                items: Object.values(TaskStatus).map((value) => {
                  const meta = TASK_STATUS_META[value];
                  return {
                    value,
                    label: meta.label,
                    icon: (
                      <meta.icon className={cn('size-4', meta.className)} />
                    ),
                  };
                }),
              },
            ]}
            onValueChange={(next) => {
              if (next !== task.status) {
                onMove?.(next);
              }
            }}
          />
          <Button
            variant="ghost"
            size="sm"
            className="ml-auto"
            onClick={onClose}
            aria-label="Close">
            <X className="size-4" aria-hidden />
          </Button>
        </div>

        {editingTitle ? (
          <Input
            autoFocus
            aria-label="Task title"
            value={title}
            onChange={(event) => {
              setTitle(event.target.value);
            }}
            onBlur={() => {
              setEditingTitle(false);
              if (title.trim() && title !== task.title) {
                onSave({ title: title.trim() });
              }
            }}
          />
        ) : (
          <button
            type="button"
            aria-label="Edit title"
            className="-mx-1 rounded-md px-1 text-left text-lg font-semibold leading-snug transition-colors hover:bg-accent/50"
            onClick={() => {
              setEditingTitle(true);
            }}>
            {task.title}
          </button>
        )}

        {editingBody ? (
          <div className="flex flex-col gap-2">
            {/* `edit`, not the primitive's default `live` split: this panel is
                384px wide, and the split halves that into two ~140px columns
                that wrap every sentence to three words each (measured in the
                running app). The toolbar's own preview toggles are still
                there for anyone who wants the other half. */}
            <MdEditor
              value={body}
              preview="edit"
              height={EDITOR_HEIGHT}
              onChange={(next) => {
                setBody(next);
              }}
            />
            <div className="flex justify-end gap-2">
              <Button
                variant="ghost"
                size="sm"
                onClick={() => {
                  setBody(task.description ?? '');
                  setEditingBody(false);
                }}>
                Cancel
              </Button>
              <Button
                size="sm"
                onClick={() => {
                  setEditingBody(false);
                  onSave({ description: body });
                }}>
                Save
              </Button>
            </div>
          </div>
        ) : (
          // A BORDER at rest and a pencil on hover, because the previous
          // rendering was prose in a transparent box and was reported as a
          // description that could not be edited at all. An affordance that
          // appears only on hover cannot answer "is this editable" for someone
          // who has not hovered it.
          <button
            type="button"
            aria-label="Edit description"
            className="group relative rounded-md border border-border/60 p-2.5 text-left transition-colors hover:border-border hover:bg-accent/30"
            onClick={() => {
              setEditingBody(true);
            }}>
            <Pencil
              className="absolute right-2.5 top-2.5 size-3.5 text-muted-foreground opacity-0 transition-opacity group-hover:opacity-100"
              aria-hidden
            />
            {task.description ? (
              <MarkdownContent content={task.description} />
            ) : (
              <span className="text-sm text-muted-foreground">
                Add a description…
              </span>
            )}
          </button>
        )}

        <div className="flex flex-col gap-1 border-t border-border pt-3">
          <PropertyRow name="Priority">
            <Select
              aria-label="Priority"
              variant="ghost"
              value={task.priority}
              triggerLabel={priorityMeta(task.priority).label}
              groups={[
                {
                  items: PRIORITY_ORDER.map((value) => {
                    const meta = PRIORITY_META[value];
                    return {
                      value,
                      label: meta.label,
                      icon: (
                        <meta.icon className={cn('size-4', meta.className)} />
                      ),
                    };
                  }),
                },
              ]}
              onValueChange={(next) => {
                onSave({ priority: next as TaskDto['priority'] });
              }}
            />
          </PropertyRow>

          <PropertyRow name="Due">
            {/* A native date input, which is the ONE place this app's
              no-native-control rule does not reach: `select.tsx` replaces the
              OS dropdown because its menu ignores every token and cannot be
              asserted on, while a date field has no such menu — and
              hand-rolling a calendar to avoid it would be a far larger surface
              than the rule is protecting. */}
            <Input
              id="task-due-date"
              aria-label="Due"
              type="date"
              className="h-8 w-auto border-transparent bg-transparent px-2 text-xs hover:bg-accent focus-visible:border-ring md:text-xs"
              value={task.dueDate ?? ''}
              onChange={(event) => {
                onSave({ dueDate: event.target.value || null });
              }}
            />
          </PropertyRow>

          <PropertyRow name="Labels">
            <LabelEditor
              labels={task.labels}
              onChange={(labels) => {
                onSave({ labels });
              }}
            />
          </PropertyRow>

          {/* WHERE this card is worked, which is the card's own answer and only
              DEFAULTS to the project's. A run is cut from it as a git
              worktree, so changing it here changes the next run and never the
              checkout an agent is already working in. The inherited value is
              shown rather than left blank — "no folder" is not a state a card
              can be in, and a reader deciding whether to override needs to see
              what they would be overriding. */}
          {task.folder !== null || projectFolder !== null ? (
            <PropertyRow name="Folder">
              <button
                type="button"
                data-slot="task-folder"
                className="min-w-0 cursor-pointer truncate rounded-md px-1.5 py-0.5 text-left font-mono text-xs text-muted-foreground hover:bg-accent focus-visible:ring-[3px] focus-visible:ring-ring/50 focus-visible:outline-none"
                title={
                  task.folder === null
                    ? `${projectFolder ?? ''}\nThe project's folder — this task names none of its own. Click to choose one.`
                    : `${task.folder}\nClick to choose another folder.`
                }
                onClick={() => {
                  void window.geniro.pickProjectFolder().then((chosen) => {
                    if (chosen) {
                      onSave({ folder: chosen });
                    }
                  });
                }}>
                {task.folder ?? projectFolder}
              </button>
              {task.folder === null ? (
                <span className="shrink-0 text-[10px] tracking-wide text-muted-foreground/70 uppercase">
                  project
                </span>
              ) : (
                <Button
                  variant="ghost"
                  size="sm"
                  className="h-6 px-1.5 text-[11px]"
                  onClick={() => {
                    onSave({ folder: null });
                  }}>
                  Use project folder
                </Button>
              )}
            </PropertyRow>
          ) : null}

          {task.branch !== null ? (
            <PropertyRow name="Branch">
              <span className="truncate font-mono text-xs text-muted-foreground">
                {task.branch}
              </span>
            </PropertyRow>
          ) : null}
        </div>

        {/* Disabled-never-hidden, and the reason sits BESIDE the button rather
          than in a `title`: `buttonVariants` carries
          `disabled:pointer-events-none`, so a disabled button receives no hover
          and its tooltip can never be read. */}
        <div className="flex flex-col gap-1 border-t border-border pt-3">
          <Button
            disabled={onRun === undefined || running || starting}
            className="self-start"
            onClick={onRun}>
            <Play className="size-4" aria-hidden />
            {starting ? 'Starting…' : running ? 'Running' : 'Run task'}
          </Button>
          {reason !== null ? (
            <span className="text-xs text-muted-foreground">{reason}</span>
          ) : null}
        </div>

        {report !== null ? <TaskReport item={report} /> : null}

        {/* Last, and one line: a timestamp is the least of what a reader opened
          this panel for, and it had a ruled block of its own between the
          properties and the description. */}
        <p className="mt-auto pt-2 text-xs text-muted-foreground">
          {task.source} · created{' '}
          <time dateTime={task.createdAt} title={task.createdAt}>
            {formatRelativeTime(task.createdAt)}
          </time>{' '}
          · updated{' '}
          <time dateTime={task.updatedAt} title={task.updatedAt}>
            {formatRelativeTime(task.updatedAt)}
          </time>
        </p>
      </aside>
    </MenuAnchorContext.Provider>
  );
}
