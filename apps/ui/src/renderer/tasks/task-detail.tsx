import { Play, X } from 'lucide-react';
import { useState } from 'react';

import type { TaskDto } from '../autogenerated';
import { MarkdownContent } from '../chats/markdown-content';
import { formatRelativeTime } from '../chats/relative-time';
import { Badge } from '../components/ui/badge';
import { Button } from '../components/ui/button';
import { Input } from '../components/ui/input';
import { MdEditor } from '../components/ui/md-editor';
import { MenuAnchorContext } from '../components/ui/menu';
import { cn } from '../components/ui/utils';
import { LabelEditor } from './label-editor';
import { taskStatusMeta } from './task-status';

/** Height of the description editor, in px — `MdEditor` takes a number. */
const EDITOR_HEIGHT = 320;

export function TaskDetail({
  task,
  onClose,
  onSave,
}: {
  task: TaskDto;
  onClose: () => void;
  onSave: (patch: {
    title?: string;
    description?: string;
    labels?: string[];
  }) => void;
}): React.JSX.Element {
  const [editingTitle, setEditingTitle] = useState(false);
  const [title, setTitle] = useState(task.title);
  const [editingBody, setEditingBody] = useState(false);
  const [body, setBody] = useState(task.description ?? '');
  const meta = taskStatusMeta(task.status);

  return (
    // The pane scrolls, so it CLIPS — and a box that scrolls vertically cannot
    // keep `overflow-x: visible`. Declaring the anchor here is the house rule:
    // every menu inside measures its trigger and places itself `fixed`.
    <MenuAnchorContext.Provider value="viewport">
      <aside
        aria-label={`Task: ${task.title}`}
        className="flex w-96 shrink-0 flex-col gap-3 overflow-y-auto border-l border-border p-4">
        <div className="flex items-start gap-2">
          {editingTitle ? (
            <Input
              autoFocus
              value={title}
              onChange={(event) => {
                setTitle(event.target.value);
              }}
              onBlur={() => {
                setEditingTitle(false);
                if (title.trim() && title !== task.title) {
                  onSave({ title: title.trim() });
                }
              }}
            />
          ) : (
            <button
              type="button"
              className="flex-1 text-left text-base font-medium"
              onClick={() => {
                setEditingTitle(true);
              }}>
              {task.title}
            </button>
          )}
          <Button
            variant="ghost"
            size="sm"
            onClick={onClose}
            aria-label="Close">
            <X className="size-4" aria-hidden />
          </Button>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <Badge variant="outline" className={cn(meta.className)}>
            {meta.label}
          </Badge>
          {/* Outline, not filled: every task in a project carries the same
            source today, so a solid badge made the least informative thing on
            the panel the loudest. It earns colour once a task can arrive from
            somewhere else. */}
          <Badge variant="outline" className="text-muted-foreground">
            {task.source}
          </Badge>
          {task.branch !== null ? (
            <Badge variant="outline" className="font-mono">
              {task.branch}
            </Badge>
          ) : null}
        </div>

        <LabelEditor
          labels={task.labels}
          onChange={(labels) => {
            onSave({ labels });
          }}
        />

        <dl className="flex flex-col gap-1 border-y border-border py-2 text-xs text-muted-foreground">
          <div className="flex justify-between gap-4">
            <dt>Created</dt>
            <dd>
              <time dateTime={task.createdAt} title={task.createdAt}>
                {formatRelativeTime(task.createdAt)}
              </time>
            </dd>
          </div>
          <div className="flex justify-between gap-4">
            <dt>Updated</dt>
            <dd>
              <time dateTime={task.updatedAt} title={task.updatedAt}>
                {formatRelativeTime(task.updatedAt)}
              </time>
            </dd>
          </div>
        </dl>

        {editingBody ? (
          <div className="flex flex-col gap-2">
            <MdEditor
              value={body}
              height={EDITOR_HEIGHT}
              onChange={(next) => {
                setBody(next);
              }}
            />
            <div className="flex justify-end gap-2">
              <Button
                variant="ghost"
                size="sm"
                onClick={() => {
                  setBody(task.description ?? '');
                  setEditingBody(false);
                }}>
                Cancel
              </Button>
              <Button
                size="sm"
                onClick={() => {
                  setEditingBody(false);
                  onSave({ description: body });
                }}>
                Save
              </Button>
            </div>
          </div>
        ) : (
          <button
            type="button"
            className="rounded-md border border-transparent p-1 text-left hover:border-border"
            onClick={() => {
              setEditingBody(true);
            }}>
            {task.description ? (
              <MarkdownContent content={task.description} />
            ) : (
              <span className="text-sm text-muted-foreground">
                No description yet — click to add one.
              </span>
            )}
          </button>
        )}

        {/* Present but disabled, per this app's disabled-never-hidden
          convention: a control that vanishes teaches nothing, while one that is
          visibly off says the capability exists and is not ready. The reason
          sits BESIDE it rather than in a `title`, because `buttonVariants`
          carries `disabled:pointer-events-none` — a disabled button receives no
          hover, so its tooltip can never be read. */}
        <div className="flex flex-col gap-1">
          <Button disabled className="self-start">
            <Play className="size-4" aria-hidden />
            Run task
          </Button>
          <span className="text-xs text-muted-foreground">
            Running a task from the board arrives in milestone 3.
          </span>
        </div>
      </aside>
    </MenuAnchorContext.Provider>
  );
}
