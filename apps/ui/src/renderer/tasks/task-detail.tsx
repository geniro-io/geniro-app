import { Play, X } from 'lucide-react';
import { useState } from 'react';

import type { TaskDto } from '../autogenerated';
import { MarkdownContent } from '../chats/markdown-content';
import { Badge } from '../components/ui/badge';
import { Button } from '../components/ui/button';
import { Input } from '../components/ui/input';
import { MdEditor } from '../components/ui/md-editor';
import { MenuAnchorContext } from '../components/ui/menu';
import { cn } from '../components/ui/utils';
import { TASK_STATUS_META } from './task-status';

/** Height of the description editor, in px — `MdEditor` takes a number. */
const EDITOR_HEIGHT = 320;

export function TaskDetail({
  task,
  onClose,
  onSave,
}: {
  task: TaskDto;
  onClose: () => void;
  onSave: (patch: { title?: string; description?: string }) => void;
}): React.JSX.Element {
  const [editingTitle, setEditingTitle] = useState(false);
  const [title, setTitle] = useState(task.title);
  const [editingBody, setEditingBody] = useState(false);
  const [body, setBody] = useState(task.description ?? '');
  const meta = TASK_STATUS_META[task.status];

  return (
    // The pane scrolls, so it CLIPS — and a box that scrolls vertically cannot
    // keep `overflow-x: visible`. Declaring the anchor here is the house rule:
    // every menu inside measures its trigger and places itself `fixed`.
    <MenuAnchorContext.Provider value="viewport">
      <aside
        aria-label={`Task: ${task.title}`}
        className="flex w-96 shrink-0 flex-col gap-3 overflow-y-auto border-l border-border p-4">
        <div className="flex items-start gap-2">
          {editingTitle ? (
            <Input
              autoFocus
              value={title}
              onChange={(event) => {
                setTitle(event.target.value);
              }}
              onBlur={() => {
                setEditingTitle(false);
                if (title.trim() && title !== task.title) {
                  onSave({ title: title.trim() });
                }
              }}
            />
          ) : (
            <button
              type="button"
              className="flex-1 text-left text-base font-medium"
              onClick={() => {
                setEditingTitle(true);
              }}>
              {task.title}
            </button>
          )}
          <Button
            variant="ghost"
            size="sm"
            onClick={onClose}
            aria-label="Close">
            <X className="size-4" aria-hidden />
          </Button>
        </div>

        <div className="flex flex-wrap items-center gap-2">
          <Badge variant="outline" className={cn(meta.className)}>
            {meta.label}
          </Badge>
          <Badge variant="secondary">{task.source}</Badge>
          {task.branch !== null ? (
            <Badge variant="outline" className="font-mono">
              {task.branch}
            </Badge>
          ) : null}
        </div>

        {editingBody ? (
          <div className="flex flex-col gap-2">
            <MdEditor
              value={body}
              height={EDITOR_HEIGHT}
              onChange={(next) => {
                setBody(next);
              }}
            />
            <div className="flex justify-end gap-2">
              <Button
                variant="ghost"
                size="sm"
                onClick={() => {
                  setBody(task.description ?? '');
                  setEditingBody(false);
                }}>
                Cancel
              </Button>
              <Button
                size="sm"
                onClick={() => {
                  setEditingBody(false);
                  onSave({ description: body });
                }}>
                Save
              </Button>
            </div>
          </div>
        ) : (
          <button
            type="button"
            className="rounded-md border border-transparent p-1 text-left hover:border-border"
            onClick={() => {
              setEditingBody(true);
            }}>
            {task.description ? (
              <MarkdownContent content={task.description} />
            ) : (
              <span className="text-sm text-muted-foreground">
                No description yet — click to add one.
              </span>
            )}
          </button>
        )}

        <Button
          disabled
          // Present but disabled, per this app's disabled-never-hidden
          // convention: a control that vanishes teaches nothing, while one that
          // is visibly off says the capability exists and is not ready.
          title="Running a task arrives in milestone 3"
          className="self-start">
          <Play className="size-4" aria-hidden />
          Run task
        </Button>
      </aside>
    </MenuAnchorContext.Provider>
  );
}
