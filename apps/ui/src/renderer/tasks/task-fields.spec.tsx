// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { createPreloadStub } from '../__fixtures__/preload-stub';
import type {
  AgentEffort,
  AgentModelDto,
  CapabilitiesDto,
} from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { aTask } from './__tests__/fixtures';
import {
  TaskBasicRows,
  type TaskFieldsContext,
  type TaskFieldsPatch,
  TaskRunConfigRows,
} from './task-fields';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  window.geniro = createPreloadStub({
    pickProjectFolder: vi.fn(async () => null),
  });
});

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.restoreAllMocks();
});

/** Flush the microtask queue a resolved daemon-API promise settles on. */
async function flush(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
  });
}

const noProject: TaskFieldsContext['project'] = {
  target: null,
  runConfig: null,
  folder: null,
};

function agentsApi(
  models: AgentModelDto[] = [],
  efforts: AgentEffort[] = [],
): DaemonApis['agents'] {
  return {
    listAgentModels: vi.fn(async () => models),
    listAgentEfforts: vi.fn(async () => ({ efforts, unavailableReason: null })),
  } as unknown as DaemonApis['agents'];
}

function capabilitiesApi(
  over: Partial<CapabilitiesDto> = {},
): DaemonApis['capabilities'] {
  const caps: CapabilitiesDto = {
    claudeModes: {
      acceptEdits: 'pass',
      plan: 'pass',
      version: 'claude 2',
      probedAt: 1,
      reason: null,
    },
    configDirs: [{ agent: 'claude', unavailableReason: null }],
    interactiveTerminals: [],
    approvals: [
      { agent: 'claude', modes: ['ask', 'acceptEdits', 'plan', 'auto'] },
    ],
    followUps: [],
    ...over,
  } as unknown as CapabilitiesDto;
  return {
    getCapabilities: vi.fn(async () => caps),
  } as unknown as DaemonApis['capabilities'];
}

function el(): HTMLDivElement {
  if (container === null) {
    throw new Error('not mounted');
  }
  return container;
}

function button(name: string): HTMLButtonElement {
  const found = [...el().querySelectorAll('button')].find(
    (b) =>
      b.getAttribute('aria-label') === name || b.textContent?.trim() === name,
  );
  if (!found) {
    throw new Error(
      `no button "${name}" — found: ${[...el().querySelectorAll('button')]
        .map((b) => b.getAttribute('aria-label') ?? b.textContent?.trim())
        .join(' | ')}`,
    );
  }
  return found;
}

function click(node: HTMLElement): void {
  act(() => {
    node.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

function options(): HTMLElement[] {
  return [...el().querySelectorAll<HTMLElement>('[role="option"]')];
}

function optionNamed(text: string): HTMLElement {
  const found = options().find((o) => o.textContent?.trim() === text);
  if (!found) {
    throw new Error(
      `no "${text}" option — found: ${options()
        .map((o) => o.textContent?.trim())
        .join(' | ')}`,
    );
  }
  return found;
}

function renderRunConfig(
  props: Partial<React.ComponentProps<typeof TaskRunConfigRows>> = {},
): { onChange: ReturnType<typeof vi.fn<(patch: TaskFieldsPatch) => void>> } {
  const onChange = vi.fn<(patch: TaskFieldsPatch) => void>();
  act(() => {
    root!.render(
      <TaskRunConfigRows
        value={aTask({ agentKind: 'claude' })}
        onChange={onChange}
        context={{
          project: noProject,
          agentsApi: null,
          capabilitiesApi: null,
        }}
        {...props}
      />,
    );
  });
  return { onChange };
}

describe('TaskRunConfigRows', () => {
  // A model and an effort level each belong to the CLI that offered
  // them, so switching a card straight from claude to cursor-agent must not
  // hand a claude model to a cursor run — `resolveRunTarget` reads whichever
  // level named a model first, and the card is the most specific level there
  // is.
  it('clears every per-CLI field when the target switches to a different agent', async () => {
    const { onChange } = renderRunConfig({
      value: aTask({ agentKind: 'claude', model: 'opus', effort: 'high' }),
      context: {
        project: noProject,
        agentsApi: agentsApi(),
        capabilitiesApi: capabilitiesApi(),
      },
    });
    await flush();

    click(button('Agent or workflow for this task'));
    click(optionNamed('cursor-agent'));

    expect(onChange).toHaveBeenCalledWith({
      agentKind: 'cursor-agent',
      workflowSlug: null,
      model: null,
      effort: null,
      approval: null,
      configDir: null,
    });
  });

  it('clears every per-CLI field when the target switches to a workflow', () => {
    const { onChange } = renderRunConfig({
      value: aTask({ agentKind: 'claude', model: 'opus', effort: 'high' }),
      context: {
        project: noProject,
        workflows: [{ slug: 'review-team', name: 'Review team' }],
        agentsApi: null,
        capabilitiesApi: null,
      },
    });

    click(button('Agent or workflow for this task'));
    click(optionNamed('Review team'));

    expect(onChange).toHaveBeenCalledWith({
      agentKind: null,
      workflowSlug: 'review-team',
      model: null,
      effort: null,
      approval: null,
      configDir: null,
    });
  });

  // An unread axis must not render like a CLI that genuinely offers none —
  // the composer's own rule (`model-settings-select.tsx`'s loading chip).
  it('shows a waiting placeholder for Effort while its vocabulary is unread', () => {
    // A pending agentsApi call, never resolved within this test — the exact
    // window the placeholder exists for.
    const pendingApi = {
      listAgentModels: vi.fn(
        () => new Promise<AgentModelDto[]>(() => undefined),
      ),
      listAgentEfforts: vi.fn(
        () =>
          new Promise<{ efforts: AgentEffort[]; unavailableReason: null }>(
            () => undefined,
          ),
      ),
    } as unknown as DaemonApis['agents'];
    renderRunConfig({
      value: aTask({ agentKind: 'claude' }),
      context: {
        project: noProject,
        agentsApi: pendingApi,
        capabilitiesApi: null,
      },
    });

    expect(
      el().querySelector('[aria-label="Loading effort levels"]'),
    ).not.toBeNull();
  });

  it('draws no Effort row once the CLI answers with none', async () => {
    renderRunConfig({
      value: aTask({ agentKind: 'claude' }),
      context: {
        project: noProject,
        agentsApi: agentsApi([], []),
        capabilitiesApi: null,
      },
    });
    await flush();

    expect(
      el().querySelector('[aria-label="Loading effort levels"]'),
    ).toBeNull();
    expect(el().querySelector('[aria-label="Reasoning effort"]')).toBeNull();
  });

  // The Config-directory row, reusing `ConfigDirSelect` rather than a
  // second picker.
  it('offers a Profile row when the CLI supports a config directory', async () => {
    const { onChange } = renderRunConfig({
      value: aTask({ agentKind: 'claude', configDir: '/repo/.claude-work' }),
      context: {
        project: noProject,
        agentsApi: agentsApi(),
        capabilitiesApi: capabilitiesApi(),
      },
    });
    await flush();

    click(button('Config directory for this task'));
    click(optionNamed('Default profile'));

    expect(onChange).toHaveBeenCalledWith({ configDir: null });
  });

  it('draws no Profile row for a CLI with no config-directory mechanism', async () => {
    renderRunConfig({
      value: aTask({ agentKind: 'claude' }),
      context: {
        project: noProject,
        agentsApi: agentsApi(),
        capabilitiesApi: capabilitiesApi({
          configDirs: [
            {
              agent: 'claude',
              unavailableReason: 'this CLI has no such control',
            },
          ],
        }),
      },
    });
    await flush();

    expect(
      el().querySelector('[aria-label="Config directory for this task"]'),
    ).toBeNull();
  });
});

describe('TaskBasicRows', () => {
  // A native date input has no clear control of its own.
  it('offers no Clear control when there is no due date', () => {
    act(() => {
      root!.render(
        <TaskBasicRows value={aTask({ dueDate: null })} onChange={vi.fn()} />,
      );
    });

    expect(
      [...el().querySelectorAll('button')].some(
        (b) => b.textContent?.trim() === 'Clear',
      ),
    ).toBe(false);
  });

  it('clears the due date through the Clear control', () => {
    const onChange = vi.fn<(patch: TaskFieldsPatch) => void>();
    act(() => {
      root!.render(
        <TaskBasicRows
          value={aTask({ dueDate: '2026-09-30' })}
          onChange={onChange}
        />,
      );
    });

    click(button('Clear'));

    expect(onChange).toHaveBeenCalledWith({ dueDate: null });
  });
});
