/**
 * A card's properties, drawn the SAME way wherever a card is being written.
 *
 * Two surfaces edit a task — the detail panel and the New task dialog — and
 * they were two unrelated forms: the panel a Linear-style column of labelled
 * property rows, the dialog three stacked `Label` + `Input` blocks that could
 * name a title, a description and a folder and nothing else. REPORTED as one
 * thing ("same design as when we open task — it should be same component"),
 * and it is the right reading twice over: a card made in the dialog and the
 * same card opened a second later looked like two different objects, and every
 * property the dialog could not name was one the user had to open the card
 * again to set.
 *
 * So the ROWS live here and both surfaces render them. Not a component with a
 * `mode` flag: what actually differs between the two is which rows exist at
 * all — a draft has no id, so it has no files, no branch, no run and no
 * timestamps — and that is expressed by the caller composing the rows it can
 * honour, rather than by a flag this file would have to interpret.
 */

/**
 * The horizontal inset a value's TEXT takes, so every row starts at one x.
 *
 * A ghost picker is a chip with `px-2`, so its label sits 8px inside its own
 * box while a bare string sits at 0 — which is half of why this column read as
 * ragged. The other half was the leading glyphs, dropped at their own call
 * sites below. Plain values wear this to join the line the chips already make.
 */
export const VALUE_INSET = 'px-2';

/**
 * One property of the card: a muted name on the left, its control on the right.
 *
 * A fixed name column rather than `justify-between`, so every control on the
 * panel starts at the same x — with `justify-between` each row's control is
 * pushed by the width of its own label and the column reads as ragged.
 *
 * `wrap` is off by default, and that is a correction: every row wrapped, so a
 * row whose value is one long string — the Folder path, and now the Agent —
 * broke onto a second line with its marker beneath it instead of truncating
 * beside it, and the panel read as two ragged columns. A wrapping flex item
 * does not shrink, so `truncate` on the value could never take effect. Only
 * the Labels row, which is genuinely a SET of chips and has to reflow, asks
 * for it back.
 */
export function PropertyRow({
  name,
  wrap = false,
  align = 'center',
  children,
}: {
  name: string;
  wrap?: boolean;
  /**
   * Where the NAME sits against a value taller than one row.
   *
   * `center` is right for every row whose value is one line — and for the
   * Labels row, whose chips reflow within a line box the name is centred in
   * the same 32px as.
   *
   * `top` is for a value that is a genuine STACK: the Files row draws a row
   * per file and then its own control, so centring put `Files` in the gap
   * between the file and the button, level with neither — REPORTED as "it's
   * not on same line". The name then takes a row box of its own height, and
   * the stack's first row takes the same, so the two line up by construction
   * rather than by an offset that has to be re-tuned whenever either changes.
   */
  align?: 'center' | 'top';
  children: React.ReactNode;
}): React.JSX.Element {
  const stacked = align === 'top';
  return (
    <div
      className={cn(
        'flex gap-2',
        stacked ? 'items-start' : 'min-h-8 items-center',
      )}>
      <span
        className={cn(
          'w-20 shrink-0 text-xs text-muted-foreground',
          stacked && 'flex min-h-8 items-center',
        )}>
        {name}
      </span>
      <div
        className={cn(
          'flex min-w-0 flex-1 gap-1.5',
          stacked ? 'flex-col' : 'items-center',
          wrap && 'flex-wrap',
        )}>
        {children}
      </div>
    </div>
  );
}

/**
 * A group of properties under its own small caption.
 *
 * Linear's issue panel is the reference here, and the grouping is the half of
 * it worth copying at this width: eleven rows in one undifferentiated column
 * read as a form to fill in, where `Properties` / `Run configuration` /
 * `Description` says which question each stretch answers — and the second of
 * those is the one a reader is looking for when a card will not start.
 */
export function PropertyGroup({
  name,
  children,
}: {
  name: string;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <section className="flex flex-col gap-0.5 border-t border-border pt-3">
      <h3 className="mb-1 text-[10px] font-medium tracking-wider text-muted-foreground/70 uppercase">
        {name}
      </h3>
      {children}
    </section>
  );
}

/**
 * The muted `project` tag beside an inherited value — one component, because
 * several rows now say it and they read as one column only while they agree.
 */
export function InheritedTag(): React.JSX.Element {
  return (
    <span className="shrink-0 text-[10px] tracking-wide text-muted-foreground/70 uppercase">
      project
    </span>
  );
}

/**
 * The card's own fields, exactly as the wire spells them.
 *
 * A `Pick` of the generated type rather than an interface of its own, so a
 * saved card satisfies it for free and a field the daemon renames cannot be
 * left behind here — which is the whole reason the DRAFT is held in this shape
 * too rather than in some dialog-local one.
 */
export type TaskFieldsValue = Pick<
  TaskDto,
  | 'status'
  | 'priority'
  | 'dueDate'
  | 'labels'
  | 'folder'
  | 'agentKind'
  | 'workflowSlug'
  | 'model'
  | 'effort'
  | 'approval'
  | 'configDir'
>;

/**
 * What one of these rows changes.
 *
 * STATUS is not in it: the panel moves a card through `onMove`, which is a
 * conditional move the daemon refuses when the board has shifted underneath —
 * so it cannot be one more key in a patch.
 */
export type TaskFieldsPatch = Partial<
  Pick<
    TaskFieldsValue,
    | 'priority'
    | 'dueDate'
    | 'labels'
    | 'folder'
    | 'agentKind'
    | 'workflowSlug'
    | 'model'
    | 'effort'
    | 'approval'
  >
>;

/** The project's own answers — what a card takes while it names none. */
export interface ProjectDefaults {
  /**
   * The project's own agent-or-workflow: what this card runs as while it names
   * none of its own. Null when the project names nothing either, which is a
   * real state and the one the Agent row has to say out loud — it is why
   * nothing on this board can start.
   */
  target: string | null;
  /**
   * The project's own model, effort and approval.
   *
   * Shown beside each row rather than left blank, on the Folder row's rule: a
   * reader deciding whether to override needs to see what they would be
   * overriding. It is only ever DISPLAYED when this card inherits the
   * project's agent, because that is the daemon's own rule — a level naming a
   * different agent contributes none of its trim fields, so a claude model
   * cannot reach a cursor run (`resolveRunTarget`).
   */
  runConfig: {
    model: string | null;
    effort: string | null;
    approval: TaskDto['approval'];
  } | null;
  /**
   * The project's folder — what this card's runs use while it names none.
   * Null only while no project is open, where the row states nothing rather
   * than guessing.
   */
  folder: string | null;
}

/** What both row groups need the daemon and the app to have answered. */
export interface TaskFieldsContext {
  project: ProjectDefaults;
  /** The workflow library, for the Agent picker. Empty until it is read. */
  workflows?: readonly TargetWorkflow[];
  /** Per-CLI detection, or null while the probe has not answered. */
  cliDetections?: readonly CliDetection[] | null;
  /** For the model and effort vocabularies, which the CLI itself reports. */
  agentsApi?: DaemonApis['agents'] | null;
  /** For the approval modes, which each adapter declares. */
  capabilitiesApi?: DaemonApis['capabilities'] | null;
}

/**
 * Status, priority, due date and labels — what the card IS.
 *
 * Status keeps its own handler rather than riding the patch, for the reason
 * `TaskFieldsPatch` gives; absent, the row is drawn and disabled, since a
 * status is a fact about the card whether or not this surface may change it.
 */
export function TaskBasicRows({
  value,
  onChange,
  onStatusChange,
  knownLabels = [],
}: {
  value: TaskFieldsValue;
  onChange: (patch: TaskFieldsPatch) => void;
  onStatusChange?: (to: string) => void;
  /**
   * Every label already in use on this board, offered while adding one so a
   * second card can be given a label by pressing it rather than by remembering
   * its spelling — which is how `bug` and `Bug` become two labels.
   */
  knownLabels?: readonly string[];
}): React.JSX.Element {
  const status = taskStatusMeta(value.status);
  return (
    <>
      {/* The status is a property of the card like every other, and it is the
          one most often changed. It stays a PICKER — moving a card was
          reachable only by dragging it across the board before this existed. */}
      <PropertyRow name="Status">
        <Select
          aria-label="Status"
          variant="ghost"
          value={value.status}
          disabled={onStatusChange === undefined}
          // The word alone. The glyph stays on the MENU rows, where it
          // helps a reader pick, and leaves the TRIGGER, where it was one of
          // the three left edges this column had: `Status` is already the
          // name beside it, so the mark says nothing the word does not.
          triggerLabel={status.label}
          groups={[
            {
              items: Object.values(TaskStatus).map((item) => {
                const meta = TASK_STATUS_META[item];
                return {
                  value: item,
                  label: meta.label,
                  icon: <meta.icon className={cn('size-4', meta.className)} />,
                };
              }),
            },
          ]}
          onValueChange={(next) => {
            if (next !== value.status) {
              onStatusChange?.(next);
            }
          }}
        />
      </PropertyRow>

      <PropertyRow name="Priority">
        <Select
          aria-label="Priority"
          variant="ghost"
          value={value.priority}
          triggerLabel={priorityMeta(value.priority).label}
          groups={[
            {
              items: PRIORITY_ORDER.map((item) => {
                const meta = PRIORITY_META[item];
                return {
                  value: item,
                  label: meta.label,
                  icon: <meta.icon className={cn('size-4', meta.className)} />,
                };
              }),
            },
          ]}
          onValueChange={(next) => {
            onChange({ priority: next as TaskDto['priority'] });
          }}
        />
      </PropertyRow>

      <PropertyRow name="Due">
        {/* A native date input, which is the ONE place this app's
            no-native-control rule does not reach: `select.tsx` replaces the
            OS dropdown because its menu ignores every token and cannot be
            asserted on, while a date field has no such menu — and
            hand-rolling a calendar to avoid it would be a far larger surface
            than the rule is protecting. */}
        <Input
          id="task-due-date"
          aria-label="Due"
          type="date"
          className="h-8 w-auto border-transparent bg-transparent px-2 text-xs hover:bg-accent focus-visible:border-ring md:text-xs"
          value={value.dueDate ?? ''}
          onChange={(event) => {
            onChange({ dueDate: event.target.value || null });
          }}
        />
      </PropertyRow>

      <PropertyRow name="Labels" wrap>
        <LabelEditor
          labels={value.labels}
          suggestions={knownLabels}
          onChange={(labels) => {
            onChange({ labels });
          }}
        />
      </PropertyRow>
    </>
  );
}

/**
 * Agent, model, effort, approval and folder — how the card gets WORKED.
 *
 * Every row inherits: the card's own answer if it has one, else the project's,
 * with the `project` tag saying which is being shown. REPORTED against the
 * panel as "для таска я могу выбрать агента, но не могу выбрать его
 * конфигурацию… там должна быть полная agent configuration, такая же, как у
 * нас при начале нового разговора" — and the dialog could not name even the
 * agent, so a card made there could only ever be a project-default card.
 */
export function TaskRunConfigRows({
  value,
  onChange,
  context,
}: {
  value: TaskFieldsValue;
  onChange: (patch: TaskFieldsPatch) => void;
  context: TaskFieldsContext;
}): React.JSX.Element {
  const {
    project,
    workflows = [],
    cliDetections = null,
    agentsApi = null,
    capabilitiesApi = null,
  } = context;
  // What this card runs as: its own answer, else the project's. Null from both
  // is the state that makes every start fail, and the row says so.
  const ownTarget = targetOf(value);
  const effectiveTarget = ownTarget ?? project.target;
  const inherited = inheritsProjectRunConfig(ownTarget, project.target)
    ? project.runConfig
    : null;
  // A workflow's nodes each name their own model and effort in the YAML, so
  // there is nothing here for a run-level answer to apply to.
  const agentKind: CliKind | null =
    effectiveTarget === null || workflowSlugOf(effectiveTarget) !== null
      ? null
      : (effectiveTarget as CliKind);
  const { models, modelsLoading, efforts, approvalModes } =
    useRunConfigVocabulary({
      agentsApi,
      capabilitiesApi,
      agentKind,
      model: value.model ?? inherited?.model ?? null,
      configDir: value.configDir,
    });

  return (
    <>
      {/* WHAT works this card — an agent or a whole workflow — on the
          Folder row's own inheritance: the card's answer if it has one,
          else the project's, and null from both is a real state rather
          than an empty control. That last case is why the row is drawn
          even when nothing is set: it is the ONLY thing on screen that can
          explain a board where every start is refused. */}
      <PropertyRow name="Agent">
        <TargetSelect
          value={effectiveTarget ?? ''}
          workflows={workflows}
          cliDetections={cliDetections}
          aria-label="Agent or workflow for this task"
          {...(effectiveTarget === null
            ? { triggerLabel: 'Choose an agent…' }
            : {})}
          onChange={(target) => {
            onChange(targetPatch(target));
          }}
        />
        {ownTarget === null && effectiveTarget !== null ? (
          <InheritedTag />
        ) : null}
        {ownTarget !== null ? (
          <Button
            variant="ghost"
            size="sm"
            className="h-6 shrink-0 px-1.5 text-[11px]"
            onClick={() => {
              onChange(targetPatch(null));
            }}>
            Use project agent
          </Button>
        ) : null}
      </PropertyRow>

      {/* WITHHELD for a workflow, and omitted rather than disabled — the
          rule the effort and context chips already follow: a control drawn
          to be refused says the feature is broken, where its absence says
          the question does not arise. A graph's nodes each name their own
          model in the YAML. */}
      {agentKind === null ? null : (
        <>
          <PropertyRow name="Model">
            <ModelSelect
              agentKind={agentKind}
              showIcon={false}
              models={models}
              value={value.model ?? inherited?.model ?? null}
              loading={modelsLoading}
              onChange={(model) => {
                // A model belongs to the CLI that offered it, so changing it
                // drops an effort level picked under the old one.
                onChange({ model, effort: null });
              }}
            />
            {value.model === null && inherited?.model != null ? (
              <InheritedTag />
            ) : null}
          </PropertyRow>

          {efforts.length === 0 ? null : (
            <PropertyRow name="Effort">
              <EffortSelect
                efforts={efforts}
                showIcon={false}
                value={value.effort ?? inherited?.effort ?? null}
                onChange={(effort) => {
                  onChange({ effort });
                }}
              />
              {value.effort === null && inherited?.effort != null ? (
                <InheritedTag />
              ) : null}
            </PropertyRow>
          )}

          {approvalModes === null || approvalModes.length === 0 ? null : (
            <PropertyRow name="Approval">
              <ApprovalModeSelect
                supportedModes={approvalModes}
                value={value.approval ?? inherited?.approval ?? null}
                // `plan` makes an agent write a plan and stop, which is not a
                // thing to pin on a card that exists to be worked. A card
                // already stored on it keeps the option, since
                // `approvalOptions` never hides the value it is displaying.
                planSupported={false}
                onChange={(approval) => {
                  onChange({ approval });
                }}
              />
              {value.approval === null && inherited?.approval != null ? (
                <InheritedTag />
              ) : null}
            </PropertyRow>
          )}
        </>
      )}

      {/* WHERE this card is worked, which is the card's own answer and only
          DEFAULTS to the project's. A run is cut from it as a git
          worktree, so changing it here changes the next run and never the
          checkout an agent is already working in. The inherited value is
          shown rather than left blank — "no folder" is not a state a card
          can be in, and a reader deciding whether to override needs to see
          what they would be overriding. */}
      {value.folder !== null || project.folder !== null ? (
        <PropertyRow name="Folder">
          <button
            type="button"
            data-slot="task-folder"
            className="min-w-0 cursor-pointer truncate rounded-md px-2 py-0.5 text-left font-mono text-xs text-muted-foreground hover:bg-accent focus-visible:ring-[3px] focus-visible:ring-ring/50 focus-visible:outline-none"
            title={
              value.folder === null
                ? `${project.folder ?? ''}\nThe project's folder — this task names none of its own. Click to choose one.`
                : `${value.folder}\nClick to choose another folder.`
            }
            onClick={() => {
              void window.geniro.pickProjectFolder().then((chosen) => {
                if (chosen) {
                  onChange({ folder: chosen });
                }
              });
            }}>
            {value.folder ?? project.folder}
          </button>
          {value.folder === null ? (
            <InheritedTag />
          ) : (
            <Button
              variant="ghost"
              size="sm"
              className="h-6 shrink-0 px-1.5 text-[11px]"
              onClick={() => {
                onChange({ folder: null });
              }}>
              Use project folder
            </Button>
          )}
        </PropertyRow>
      ) : null}
    </>
  );
}
