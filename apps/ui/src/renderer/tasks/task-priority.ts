import type { LucideIcon } from 'lucide-react';
import {
  Minus,
  SignalHigh,
  SignalLow,
  SignalMedium,
  TriangleAlert,
} from 'lucide-react';

import { TaskPriority } from '../autogenerated';

/**
 * How each priority presents itself, in the order a triage list wants: the most
 * urgent first, with `none` last because an untriaged task is not the top of
 * the scale — it is off it.
 *
 * The daemon's own array leads with `none` (it is the default a row is created
 * with); display order is the renderer's, which is why this is a separate list
 * rather than a re-export.
 */
export const PRIORITY_ORDER: readonly TaskPriority[] = [
  TaskPriority.Urgent,
  TaskPriority.High,
  TaskPriority.Medium,
  TaskPriority.Low,
  TaskPriority.None,
];

export const PRIORITY_META: Record<
  TaskPriority,
  { label: string; icon: LucideIcon; className: string }
> = {
  [TaskPriority.Urgent]: {
    label: 'Urgent',
    icon: TriangleAlert,
    className: 'text-destructive',
  },
  [TaskPriority.High]: {
    label: 'High',
    icon: SignalHigh,
    className: 'text-warning',
  },
  [TaskPriority.Medium]: {
    label: 'Medium',
    icon: SignalMedium,
    className: 'text-foreground',
  },
  [TaskPriority.Low]: {
    label: 'Low',
    icon: SignalLow,
    className: 'text-muted-foreground',
  },
  [TaskPriority.None]: {
    label: 'No priority',
    icon: Minus,
    className: 'text-muted-foreground',
  },
};

/**
 * The metadata for a priority, tolerating one this build has never heard of.
 *
 * Same rule the status map learned the hard way: the daemon owns the
 * vocabulary, so a bare `Record` index is a crash waiting for the next value
 * somebody adds there.
 */
export function priorityMeta(
  priority: string,
): (typeof PRIORITY_META)[TaskPriority] {
  return (
    PRIORITY_META[priority as TaskPriority] ?? {
      label: priority,
      icon: Minus,
      className: 'text-muted-foreground',
    }
  );
}
