import { CircleX, SendHorizontal } from 'lucide-react';
import { useState } from 'react';

import type { ItemDto } from '../autogenerated';
import { FindingsCard } from '../chats/findings-block';
import { readFindingsReport } from '../chats/findings-payload';
import { MarkdownContent } from '../chats/markdown-content';
import { formatRelativeTime } from '../chats/relative-time';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Button } from '../components/ui/button';
import { Spinner } from '../components/ui/spinner';
import { cn } from '../components/ui/utils';

/**
 * The agent's own words on a message row, or null when the payload does not
 * read as one.
 *
 * The generated `payload` is `any`, so it is narrowed here rather than
 * trusted — the same shape `readFindingsReport` takes to the same field.
 */
function messageText(item: ItemDto): string | null {
  const payload: unknown = item.payload;
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const text = (payload as { text?: unknown }).text;
  return typeof text === 'string' && text.trim() !== '' ? text : null;
}

/**
 * A section of the panel that is not a list of properties — the same rule the
 * Description block follows, restated here rather than imported, since the
 * report's caption carries a second thing on its right.
 */
function ReportSection({
  name,
  aside = null,
  tone = 'default',
  children,
}: {
  name: string;
  aside?: React.ReactNode;
  /**
   * `alarm` for a run that ENDED BADLY — the caption carries the state, since
   * it is the first thing read and the only part of this section that is
   * always the same shape whatever the agent left behind.
   */
  tone?: 'default' | 'alarm';
  children: React.ReactNode;
}): React.JSX.Element {
  const alarm = tone === 'alarm';
  return (
    <section className="flex flex-col gap-2 border-t border-border pt-3">
      <div className="flex items-baseline justify-between gap-2">
        <h3
          className={cn(
            'flex items-center gap-1.5 text-[10px] font-medium tracking-wider uppercase',
            alarm ? 'text-destructive' : 'text-muted-foreground/70',
          )}>
          {alarm ? (
            // Sized to the CAPTION rather than to a control: it is a mark on a
            // 10px word, and at `size-3.5` it out-weighed the words beside it.
            <CircleX className="size-3 shrink-0" aria-hidden />
          ) : null}
          {name}
        </h3>
        {aside}
      </div>
      {children}
    </section>
  );
}

/**
 * What the agent said when it finished a task.
 *
 * Both renderings are the transcript's OWN — `FindingsCard` for a structured
 * report and `MarkdownContent` for prose. Nothing here parses or draws a
 * message itself: a second transcript implementation is exactly what this
 * milestone is not allowed to grow, and the live view links to the chat.
 *
 * REDESIGNED on report, and the change is that it is now a SECTION like every
 * other stretch of this panel rather than a caption and some loose prose: a
 * bordered surface under a ruled heading, with WHEN it was written on the
 * heading's own line. The prose used to run straight off the bottom of the
 * panel with nothing enclosing it, so the one thing a reader opens a finished
 * card to read was the one thing on screen that did not look like a thing.
 *
 * The surface is the DESCRIPTION's, deliberately: those two are the card's
 * long text — one written by the person, one by the agent — and drawing them
 * alike is what makes the panel read as a document instead of a form with an
 * essay stapled to it. A structured report brings its own card and is left
 * alone, since a border around a bordered card is two boxes saying one thing.
 */
export function TaskReport({
  item,
  failed = false,
}: {
  /** The row holding the closing report, or null when the card has none. */
  item: ItemDto | null;
  /**
   * The card ended in FAILURE — its run died, was refused, or was cut off.
   *
   * REPORTED as "for report with error it should have design with some
   * problem, like to show w error and so on", over a card whose Status read
   * `Failed` while the section beneath it was headed `Report` and held the
   * agent's OPENING line ("I'll start by getting oriented…"). That is not a
   * report and never was: the settle path takes the newest assistant message
   * when no closing report was written (`TaskSettleService.findReport`), which
   * is exactly right for a run that finished and exactly wrong-looking for one
   * that did not — the last thing said by an agent that died on its first step
   * is its first sentence.
   *
   * Nothing about the underlying row changes here. What changes is the FRAME:
   * the section says the run failed, and the text is labelled as the last
   * thing the agent said rather than presented as its conclusion.
   */
  failed?: boolean;
}): React.JSX.Element | null {
  const report = item === null ? null : readFindingsReport(item);
  const text = report === null && item !== null ? messageText(item) : null;
  if (report === null && text === null && !failed) {
    // The heading belongs to this component rather than to the panel, so it
    // cannot outlive what it labels: gated outside, a row whose payload reads
    // as neither still printed "Report" over nothing.
    return null;
  }
  return (
    <ReportSection
      // A failed run has no report, so calling the section one is the whole of
      // what was wrong with it. The word is what a reader takes the contents
      // for, and `Report` over an opening line reads as an agent that did the
      // work and then described none of it.
      name={failed ? 'Run failed' : 'Report'}
      tone={failed ? 'alarm' : 'default'}
      aside={
        item === null ? null : (
          <time
            className="shrink-0 text-[11px] text-muted-foreground"
            dateTime={item.createdAt}
            title={item.createdAt}>
            {formatRelativeTime(item.createdAt)}
          </time>
        )
      }>
      {failed ? (
        <p className="text-xs text-muted-foreground">
          {text === null && report === null
            ? 'The agent stopped before it finished, and left nothing behind. Open its thread to see what happened.'
            : 'The agent stopped before it finished. The last thing it said:'}
        </p>
      ) : null}
      {report !== null ? (
        <FindingsCard report={report} />
      ) : text === null ? null : (
        // TINTED for a failure, and only the frame: the words are the agent's
        // and are drawn by the same markdown pipeline either way. A red wash
        // over the text itself would read as the agent shouting rather than as
        // this app saying the run went wrong.
        <div
          className={cn(
            'rounded-md border p-2.5',
            failed
              ? 'border-destructive/40 bg-destructive/5'
              : 'border-border/60',
          )}>
          <MarkdownContent content={text} />
        </div>
      )}
    </ReportSection>
  );
}

/**
 * Say the next thing to the agent, without leaving the card.
 *
 * ASKED FOR as "we should have ability there to add follow up message right
 * from task". Reading a report and having something to say about it is one
 * gesture; before this it was four — leave the board, find the thread among
 * every other conversation, open it, type. The card is where the reader
 * already is.
 *
 * It sends through the card's own RUN path rather than through the chat's, and
 * that is what keeps it a task rather than a chat message: the worktree is
 * prepared again, the card moves back to In progress, and the daemon continues
 * the thread this card already has (`TaskRunsService.resume`). So the board
 * keeps saying what is true — a card being worked sits in the column that says
 * so — which a message sent straight down the chat channel would quietly break.
 *
 * WITHHELD while the agent is working, rather than queued. The chat surface has
 * a queue and a strip that shows what is in it; this box has neither, so a
 * message accepted here would vanish into a run the card cannot show. The line
 * that replaces it says where the live conversation is.
 */
export function TaskFollowUp({
  running,
  starting = false,
  onSend,
}: {
  /** An agent is working this card right now. */
  running: boolean;
  /** A turn is being started for this card right now. */
  starting?: boolean;
  onSend: (text: string) => void;
}): React.JSX.Element {
  const [text, setText] = useState('');
  const ready = text.trim() !== '' && !running && !starting;

  return (
    <ReportSection name="Follow up">
      {running ? (
        <p className="flex items-center gap-2 text-xs text-muted-foreground">
          <Spinner className="size-3" />
          An agent is working this task. Open its thread to talk to it while it
          runs.
        </p>
      ) : (
        <>
          <ExpandableTextarea
            id="task-follow-up"
            value={text}
            title="Follow up"
            rows={3}
            maxRows={12}
            placeholder="Ask for a change, or say what to do next…"
            onChange={setText}
          />
          <div className="flex items-center justify-between gap-2">
            {/* The card MOVES, so the box says so before it is pressed rather
                than after: this is not a chat message, it is another run of
                the card, and a reader who expects the first will not expect
                the second. */}
            <span className="min-w-0 text-[11px] text-muted-foreground">
              Continues this task’s thread and moves the card back to In
              progress.
            </span>
            <Button
              size="sm"
              className="shrink-0"
              disabled={!ready}
              onClick={() => {
                onSend(text.trim());
                setText('');
              }}>
              {starting ? (
                <Spinner className="size-3.5" />
              ) : (
                <SendHorizontal className="size-3.5" aria-hidden />
              )}
              {starting ? 'Sending…' : 'Send'}
            </Button>
          </div>
        </>
      )}
    </ReportSection>
  );
}
