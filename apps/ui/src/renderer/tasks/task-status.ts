import type { LucideIcon } from 'lucide-react';
import {
  CircleCheck,
  CircleDot,
  CircleHelp,
  CircleX,
  Eye,
  Inbox,
  List,
} from 'lucide-react';

import { TaskStatus } from '../autogenerated';

/**
 * How each column of the board presents itself.
 *
 * A sibling of `chats/run-status.tsx`'s `RUN_STATUS_META` rather than a reuse of
 * it: that one is keyed by RUN status (pending/running/held/…), which is a
 * different vocabulary from a task's. A card grows a run footer in milestone 3
 * and takes its colours from that map then; these are the column's own.
 */
export const TASK_STATUS_META: Record<
  TaskStatus,
  { label: string; icon: LucideIcon; className: string }
> = {
  [TaskStatus.Backlog]: {
    label: 'Backlog',
    icon: Inbox,
    className: 'text-muted-foreground',
  },
  [TaskStatus.Todo]: {
    label: 'To do',
    icon: List,
    className: 'text-muted-foreground',
  },
  [TaskStatus.InProgress]: {
    label: 'In progress',
    icon: CircleDot,
    className: 'text-primary',
  },
  [TaskStatus.InReview]: {
    label: 'In review',
    icon: Eye,
    className: 'text-warning',
  },
  [TaskStatus.Done]: {
    label: 'Done',
    icon: CircleCheck,
    className: 'text-success',
  },
  [TaskStatus.Failed]: {
    label: 'Failed',
    icon: CircleX,
    className: 'text-destructive',
  },
};

/**
 * The presentation for a status, including one this build has never heard of.
 *
 * The daemon owns this vocabulary, so a newer daemon can send a value outside
 * the union — `parseTaskChanged` deliberately passes such an event through
 * rather than dropping it. A bare `TASK_STATUS_META[status]` index answers
 * `undefined` there and every reader of `.label` throws, taking the whole board
 * down over one unrecognised card. This degrades instead: the card shows the
 * raw status and stays inert.
 */
export function taskStatusMeta(status: string): {
  label: string;
  icon: LucideIcon;
  className: string;
} {
  return (
    TASK_STATUS_META[status as TaskStatus] ?? {
      label: status,
      icon: CircleHelp,
      className: 'text-muted-foreground',
    }
  );
}
