import type { AgentKind } from '../autogenerated';
import { teamSlugOf } from '../chats/composer-values';

/**
 * What a card or a project is pointed at, in the COMPOSER's own vocabulary.
 *
 * The daemon keeps two nullable columns — `agentKind` and `teamSlug` — one
 * of which is set; the composer has always spelled the same either/or as a
 * single string, a CLI kind or `team:<slug>`. This is the seam between them, and
 * it exists so the board can reuse `TargetSelect` rather than grow a second
 * picker that means the same thing.
 *
 * The daemon side stays two columns deliberately: `team:` is a renderer encoding
 * and the wire carries the daemon's own vocabulary, which is the rule the rest
 * of `settings.json` follows too.
 */
export interface RunTargetFields {
  agentKind?: AgentKind | null;
  teamSlug?: string | null;
}

/** The composer-style target these fields name, or null when they name none. */
export function targetOf(row: RunTargetFields): string | null {
  if (row.teamSlug != null && row.teamSlug !== '') {
    return `team:${row.teamSlug}`;
  }
  return row.agentKind ?? null;
}

/**
 * The patch that makes a row name `target`, or name nothing when it is null.
 *
 * BOTH fields are always written, and that is the whole point: a card moved
 * from a team to an agent must have its team cleared in the same patch,
 * or the daemon's resolution — which reads a team first — would go on
 * running the graph while the picker showed the agent. Explicit `null` is what
 * clears one; an omitted key means "leave alone" on that route.
 */
export function targetPatch(target: string | null): {
  agentKind: AgentKind | null;
  teamSlug: string | null;
} {
  if (target === null || target === '') {
    return { agentKind: null, teamSlug: null };
  }
  const slug = teamSlugOf(target);
  return slug === null
    ? { agentKind: target as AgentKind, teamSlug: null }
    : { agentKind: null, teamSlug: slug };
}

/**
 * How a target reads on a row that is not a picker — a team by NAME where
 * the library still holds it, else by its slug.
 *
 * A slug is what the wire carries and a name is what the user gave it, so a
 * team deleted out from under a card still says something rather than
 * rendering blank.
 */
export function targetLabel(
  target: string | null,
  teams: readonly { slug: string; name: string }[],
): string | null {
  if (target === null) {
    return null;
  }
  const slug = teamSlugOf(target);
  if (slug === null) {
    return target;
  }
  return teams.find((wf) => wf.slug === slug)?.name ?? slug;
}

/**
 * Whether the project's model, effort and approval reach this card.
 *
 * The DAEMON's rule, restated on the client so the panel can say what a card
 * would actually run with. `resolveRunTarget` reads the rungs
 * most-specific-first and a rung naming a DIFFERENT agent contributes nothing —
 * which is what stops a claude project's model being handed to a card pointed
 * at cursor. Naming the same agent, or naming none at all, inherits the lot.
 *
 * Its own function because the panel would otherwise state this inline three
 * times, once per inherited field, and a fourth field would make it four.
 */
export function inheritsProjectRunConfig(
  ownTarget: string | null,
  projectTarget: string | null,
): boolean {
  return ownTarget === null || ownTarget === projectTarget;
}
