// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { TaskWorktreeSettleResult } from '../../shared/contracts';
import { createPreloadStub } from '../__fixtures__/preload-stub';
import type { ProjectDto, TaskDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { aProject, aTask } from './__tests__/fixtures';
import { type BoardApi, useBoard } from './use-board';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

const project = (over: Partial<ProjectDto> = {}): ProjectDto => aProject(over);

const task = (over: Partial<TaskDto> = {}): TaskDto => aTask(over);

interface Stub {
  apis: DaemonApis;
  listTasks: ReturnType<typeof vi.fn>;
  reconcileTasks: ReturnType<typeof vi.fn>;
  moveTaskStatus: ReturnType<typeof vi.fn>;
  attachTaskFile: ReturnType<typeof vi.fn>;
  detachTaskFile: ReturnType<typeof vi.fn>;
}

function stubApis(
  over: {
    moveTaskStatus?: ReturnType<typeof vi.fn>;
    attachTaskFile?: ReturnType<typeof vi.fn>;
    detachTaskFile?: ReturnType<typeof vi.fn>;
  } = {},
): Stub {
  const listTasks = vi.fn().mockResolvedValue([task()]);
  // The board LOADS through reconcile: one call that also settles any run
  // which finished while no window was open.
  const reconcileTasks = vi.fn().mockResolvedValue([task()]);
  const moveTaskStatus =
    over.moveTaskStatus ??
    vi
      .fn()
      .mockImplementation(({ moveTaskStatusDto }) =>
        Promise.resolve(task({ status: moveTaskStatusDto.to })),
      );
  const attachTaskFile =
    over.attachTaskFile ?? vi.fn().mockResolvedValue(task());
  const detachTaskFile =
    over.detachTaskFile ?? vi.fn().mockResolvedValue(task());
  const apis = {
    projects: {
      listProjects: vi.fn().mockResolvedValue([project()]),
      // Read beside the board so the intake banner can count. Its failure is
      // swallowed by the hook, so a fake that omitted it would still pass —
      // which is why it answers real numbers here rather than nothing.
      readProjectQueue: vi
        .fn()
        .mockResolvedValue({ running: 0, waiting: 0, eligible: [] }),
    },
    tasks: {
      listTasks,
      moveTaskStatus,
      reconcileTasks,
      attachTaskFile,
      detachTaskFile,
    },
  } as unknown as DaemonApis;
  return {
    apis,
    listTasks,
    reconcileTasks,
    moveTaskStatus,
    attachTaskFile,
    detachTaskFile,
  };
}

/** Mount the hook and hand back a live handle to its latest return value. */
async function mount(
  apis: DaemonApis,
  client: DaemonClient | null = null,
): Promise<{ current: BoardApi }> {
  const handle = { current: null as unknown as BoardApi };
  function Probe(): null {
    handle.current = useBoard(apis, client);
    return null;
  }
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<Probe />);
  });
  return handle;
}

describe('useBoard', () => {
  it('moves the card before the write lands, and tells the daemon which column it came from', async () => {
    // The request is held open deliberately. Awaiting the whole call would
    // sample only the post-response state, which the stub also produces — so
    // the assertion would hold with the optimism deleted and this test would
    // pin nothing it claims to.
    let release: ((value: unknown) => void) | null = null;
    const held = new Promise((resolve) => {
      release = resolve;
    });
    const moveTaskStatus = vi
      .fn()
      .mockImplementation(() =>
        held.then(() => task({ status: 'in_progress' })),
      );
    const { apis } = stubApis({ moveTaskStatus });
    const board = await mount(apis);

    let pending: Promise<void> | null = null;
    await act(async () => {
      pending = board.current.moveTask('t1', 'in_progress');
    });

    // In flight: the card has already moved.
    expect(board.current.tasks[0]?.status).toBe('in_progress');

    await act(async () => {
      release?.(undefined);
      await pending;
    });

    expect(board.current.tasks[0]?.status).toBe('in_progress');
    // `from` is the status the board held BEFORE the move, not the one it is
    // moving to — that is the whole compare-and-set, and sending `to` for both
    // would make every stale move succeed.
    expect(moveTaskStatus).toHaveBeenCalledWith({
      taskId: 't1',
      moveTaskStatusDto: { from: 'todo', to: 'in_progress' },
    });
  });

  it('puts the card back and surfaces the reason when the write is refused', async () => {
    const { apis } = stubApis({
      moveTaskStatus: vi
        .fn()
        .mockRejectedValue(new Error('task t1 is in done, not todo')),
    });
    const board = await mount(apis);

    await act(async () => {
      await board.current.moveTask('t1', 'in_progress');
    });

    expect(board.current.tasks[0]?.status).toBe('todo');
    expect(board.current.error).toContain('not todo');
  });

  it('reloads when a task changes on the board being shown', async () => {
    let emit: ((event: unknown) => void) | null = null;
    const client = {
      onTaskChanged: (listener: (event: unknown) => void) => {
        emit = listener;
        return () => undefined;
      },
    } as unknown as DaemonClient;
    const { apis, reconcileTasks: listTasks } = stubApis();
    await mount(apis, client);
    const before = listTasks.mock.calls.length;

    await act(async () => {
      emit?.({ taskId: 't9', projectId: 'p1', status: 'done' });
    });

    expect(listTasks.mock.calls.length).toBeGreaterThan(before);
  });

  it('ignores a task change on a board it is not showing', async () => {
    // The broadcast is client-wide, so every other project's traffic arrives
    // here too; reloading on it would refetch this board on every keystroke
    // happening in another window.
    let emit: ((event: unknown) => void) | null = null;
    const client = {
      onTaskChanged: (listener: (event: unknown) => void) => {
        emit = listener;
        return () => undefined;
      },
    } as unknown as DaemonClient;
    const { apis, reconcileTasks: listTasks } = stubApis();
    await mount(apis, client);
    const before = listTasks.mock.calls.length;

    await act(async () => {
      emit?.({ taskId: 't9', projectId: 'OTHER', status: 'done' });
    });

    expect(listTasks.mock.calls.length).toBe(before);
  });

  describe('attaching files', () => {
    it('sends each attachment SEQUENTIALLY, in the order given', async () => {
      // The hook's own doc block states this as a correctness property — "a
      // batch sent in parallel would race past the daemon's cap" — so the
      // ORDERING is what has to be pinned, not merely the eventual call count,
      // which a `Promise.all` would satisfy just as well.
      const releases: ((value: TaskDto) => void)[] = [];
      const attachTaskFile = vi.fn().mockImplementation(
        () =>
          new Promise<TaskDto>((resolve) => {
            releases.push(resolve);
          }),
      );
      const { apis } = stubApis({ attachTaskFile });
      const board = await mount(apis);

      let pending: Promise<void> | null = null;
      await act(async () => {
        pending = board.current.attachFiles('t1', ['/a', '/b', '/c']);
      });

      // Only the FIRST call has gone out — a parallel fan-out would have
      // invoked all three synchronously by now.
      expect(attachTaskFile).toHaveBeenCalledTimes(1);
      expect(attachTaskFile).toHaveBeenNthCalledWith(1, {
        taskId: 't1',
        attachTaskFileDto: { path: '/a' },
      });

      await act(async () => {
        releases[0]?.(task());
        await Promise.resolve();
      });
      expect(attachTaskFile).toHaveBeenCalledTimes(2);
      expect(attachTaskFile).toHaveBeenNthCalledWith(2, {
        taskId: 't1',
        attachTaskFileDto: { path: '/b' },
      });

      await act(async () => {
        releases[1]?.(task());
        await Promise.resolve();
      });
      expect(attachTaskFile).toHaveBeenCalledTimes(3);
      expect(attachTaskFile).toHaveBeenNthCalledWith(3, {
        taskId: 't1',
        attachTaskFileDto: { path: '/c' },
      });

      await act(async () => {
        releases[2]?.(task());
        await pending;
      });
    });

    it('stops at the first refusal, having sent only what came before it', async () => {
      const attachTaskFile = vi
        .fn()
        .mockResolvedValueOnce(task())
        .mockRejectedValueOnce(new Error('daemon refused /b'));
      const { apis } = stubApis({ attachTaskFile });
      const board = await mount(apis);

      await act(async () => {
        await board.current.attachFiles('t1', ['/a', '/b', '/c']);
      });

      // The third file is never sent — a sequential loop that stops on error
      // does not press on past the one that failed.
      expect(attachTaskFile).toHaveBeenCalledTimes(2);
      expect(board.current.error).toContain('daemon refused /b');
    });
  });

  describe('collecting a settled run’s worktree', () => {
    let emit: ((event: unknown) => void) | null;
    type SettleWorktree = (taskId: string) => Promise<TaskWorktreeSettleResult>;
    let settle: ReturnType<typeof vi.fn<SettleWorktree>>;

    const mountWithClient = async () => {
      emit = null;
      const client = {
        onTaskChanged: (listener: (event: unknown) => void) => {
          emit = listener;
          return () => undefined;
        },
      } as unknown as DaemonClient;
      const { apis } = stubApis();
      await mount(apis, client);
    };

    beforeEach(() => {
      window.geniro = createPreloadStub();
      settle = vi.fn<SettleWorktree>(() =>
        Promise.resolve({ removed: true, committed: true }),
      );
      window.geniro.settleTaskWorktree = settle;
    });

    it('collects it when the DAEMON says the run settled', async () => {
      await mountWithClient();

      await act(async () => {
        emit?.({
          taskId: 't9',
          projectId: 'p1',
          status: 'in_review',
          reason: 'run-settled',
        });
      });

      expect(settle).toHaveBeenCalledWith('t9');
    });

    it('collects it for a board this window is not even showing', async () => {
      // A worktree belongs to the TASK, not to the project on screen. Scoping
      // this to the open board would leave every other project's checkouts on
      // disk for as long as this one is selected.
      await mountWithClient();

      await act(async () => {
        emit?.({
          taskId: 't9',
          projectId: 'OTHER',
          status: 'in_review',
          reason: 'run-settled',
        });
      });

      expect(settle).toHaveBeenCalledWith('t9');
    });

    it('does NOT collect it when the card merely moved', async () => {
      // A drag writes the column optimistically, before the daemon has
      // answered — so a card dropped in Done while its agent is still working
      // reaches this same broadcast. Acting on the column rather than on the
      // daemon's reason is what would remove a live agent's checkout.
      await mountWithClient();

      await act(async () => {
        emit?.({ taskId: 't9', projectId: 'p1', status: 'done' });
      });

      expect(settle).not.toHaveBeenCalled();
    });
  });
});

describe('useBoard error text and refresh scope', () => {
  it('shows the sentence the daemon wrote, not its whole error envelope', () => {
    // The refused move arrives as the transport's uniform envelope
    // (`daemon PATCH … failed (409): {…}`). Putting that in the banner shows
    // the user raw JSON; the daemon's own message is the readable half.
    const { apis } = stubApis({
      moveTaskStatus: vi
        .fn()
        .mockRejectedValue(
          new Error(
            'daemon PATCH /v1/tasks/t1/status failed (409): ' +
              '{"statusCode":409,"code":"TASK_STATUS_CONFLICT","message":"task t1 is in done, not todo — it moved since you last read it"}',
          ),
        ),
    });

    return mount(apis).then(async (board) => {
      await act(async () => {
        await board.current.moveTask('t1', 'in_progress');
      });

      expect(board.current.error).toBe(
        'task t1 is in done, not todo — it moved since you last read it',
      );
      expect(board.current.error).not.toContain('statusCode');
    });
  });

  it('drops a selection whose project has been deleted', async () => {
    // Settings can delete the project this board is showing, and the screen is
    // latch-mounted so it never remounts to notice. Holding the id would keep
    // a dead project's cards on screen and fail every write against them.
    const { apis } = stubApis();
    const listProjects = apis.projects.listProjects as ReturnType<typeof vi.fn>;
    const board = await mount(apis);
    expect(board.current.selectedProjectId).toBe('p1');

    listProjects.mockResolvedValue([aProject({ id: 'p2', name: 'Survivor' })]);
    await act(async () => {
      board.current.refreshProjects();
    });

    expect(board.current.selectedProjectId).toBe('p2');
  });

  it('does not re-read the project list when a task changes', async () => {
    // The broadcast echoes the board's own writes back to it. One counter for
    // both effects turned every card move into a `listProjects` too.
    let emit: ((event: unknown) => void) | null = null;
    const client = {
      onTaskChanged: (listener: (event: unknown) => void) => {
        emit = listener;
        return () => undefined;
      },
    } as unknown as DaemonClient;
    const { apis, reconcileTasks: listTasks } = stubApis();
    const listProjects = apis.projects.listProjects as ReturnType<typeof vi.fn>;
    await mount(apis, client);
    const projectReads = listProjects.mock.calls.length;
    const taskReads = listTasks.mock.calls.length;

    await act(async () => {
      emit?.({ taskId: 't1', projectId: 'p1', status: 'done' });
    });

    expect(listTasks.mock.calls.length).toBeGreaterThan(taskReads);
    expect(listProjects.mock.calls.length).toBe(projectReads);
  });
});
