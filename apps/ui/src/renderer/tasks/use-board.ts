const NOTHING_STAGED: NewTaskAttachments = {
  images: [],
  files: [],
  uploads: [],
};

/**
 * The board's columns, left to right.
 *
 * Read off the generated enum rather than restated, so the daemon's own
 * vocabulary and its declared order are the only source. A status added there
 * grows a column here with no edit; a hand-written list would instead render a
 * board that silently cannot show some of its own cards.
 */
export const BOARD_COLUMNS: readonly TaskStatus[] = Object.values(TaskStatus);

/**
 * The columns to draw for a given set of tasks: the known vocabulary, plus any
 * status present in the data that this build does not know, appended in the
 * order first seen.
 *
 * Without the second half a card whose status came from a newer daemon matches
 * no column and is silently absent from the board — worse than an unfamiliar
 * column, because nothing tells the user the card exists at all.
 */
export function boardColumns(tasks: TaskDto[]): string[] {
  const known = new Set<string>(BOARD_COLUMNS);
  const extra: string[] = [];
  for (const task of tasks) {
    if (!known.has(task.status) && !extra.includes(task.status)) {
      extra.push(task.status);
    }
  }
  return [...BOARD_COLUMNS, ...extra];
}

/**
 * The ids of column `status` once `taskId` is dropped into it ahead of
 * `beforeTaskId` (null = at the end), or null when the drop changes nothing.
 *
 * Read off the board's own array order, which is the order the columns draw.
 */
export function columnOrderAfterDrop(
  tasks: readonly TaskDto[],
  taskId: string,
  status: string,
  beforeTaskId: string | null,
): string[] | null {
  const moving = tasks.find((row) => row.id === taskId);
  if (moving === undefined || beforeTaskId === taskId) {
    return null;
  }
  const current = tasks
    .filter((row) => row.status === status)
    .map((row) => row.id);
  const ids = current.filter((id) => id !== taskId);
  const at = beforeTaskId === null ? -1 : ids.indexOf(beforeTaskId);
  ids.splice(at === -1 ? ids.length : at, 0, taskId);
  const unchanged =
    moving.status === status &&
    ids.length === current.length &&
    ids.every((id, index) => id === current[index]);
  return unchanged ? null : ids;
}

/**
 * The board with column `status` rearranged to `ids` and the moved card in it.
 * The column's cards go to the end of the array in their new order; other
 * columns keep their relative order, which is all the columns read.
 */
export function arrangeColumn(
  tasks: readonly TaskDto[],
  status: string,
  ids: readonly string[],
): TaskDto[] {
  const byId = new Map(tasks.map((row) => [row.id, row]));
  const placed = new Set(ids);
  const column = ids
    .map((id) => byId.get(id))
    .filter((row): row is TaskDto => row !== undefined)
    .map((row, position) => ({
      ...row,
      status: status as TaskStatus,
      position,
    }));
  return [...tasks.filter((row) => !placed.has(row.id)), ...column];
}

/** One card edit the daemon has not answered yet, numbered in sending order. */
interface EditInFlight {
  id: number;
  dto: UpdateTaskDto;
}

/**
 * The fields an edit NAMES, as card fields. An `undefined` in a DTO means "not
 * part of this edit", never "clear it" — clearing is an explicit null.
 */
function editedFields(dto: UpdateTaskDto): Partial<TaskDto> {
  return Object.fromEntries(
    Object.entries(dto).filter(([, value]) => value !== undefined),
  ) as Partial<TaskDto>;
}

/** A card with an edit laid over it — what the board shows before the answer. */
function withEdit(row: TaskDto, dto: UpdateTaskDto): TaskDto {
  return { ...row, ...editedFields(dto) };
}

/**
 * A card with every edit still in flight laid back over it, oldest first.
 *
 * Applied to every row the daemon hands the board while an edit is out: a
 * reload (each task write echoes a `task_changed`, and the reload it triggers
 * can answer from before the NEXT write landed) or another write's answer
 * would otherwise take an edit off the screen that the daemon is about to
 * make — and the next edit, built from what is on screen, would drop it.
 */
function withEditsInFlight(
  row: TaskDto,
  inFlight: ReadonlyMap<string, readonly EditInFlight[]>,
): TaskDto {
  return (inFlight.get(row.id) ?? []).reduce(
    (current, edit) => withEdit(current, edit.dto),
    row,
  );
}

/**
 * A card with a REFUSED edit taken back out: each field it named goes back to
 * what it was before — but only while the field still holds what that edit
 * wrote, so a later edit to the same field is not undone along with it.
 */
function withoutEdit(
  row: TaskDto,
  dto: UpdateTaskDto,
  before: TaskDto,
): TaskDto {
  const restored = Object.fromEntries(
    Object.entries(editedFields(dto))
      .filter(
        ([field, wrote]) =>
          JSON.stringify(row[field as keyof TaskDto]) === JSON.stringify(wrote),
      )
      .map(([field]) => [field, before[field as keyof TaskDto]]),
  ) as Partial<TaskDto>;
  return { ...row, ...restored };
}

/**
 * The daemon refusals that mean ANOTHER start of the same card holds it.
 *
 * TWIN: `apps/ui/src/main/autopilot-conductor.ts` `ANOTHER_START_HOLDS_IT`,
 * which names the daemon's throw sites. Spelled on each side because main and
 * the renderer share no module for it.
 */
const ANOTHER_START_HOLDS_IT: ReadonlySet<string> = new Set([
  'TASK_RUN_STARTING',
  'TASK_ALREADY_RUNNING',
]);

/**
 * Whether a worktree THIS press made may go back after its start was refused.
 *
 * Making it is not the same as being its only user. A task's worktree lives at
 * ONE path per task, so the autopilot starting the same card a moment later is
 * handed this very directory as `reused` — and when that start is the one the
 * daemon took, this refusal is the loser's, and pruning the clean tree takes
 * the cwd out from under the agent it just started. So the daemon is asked: a
 * refusal naming another start of the card keeps it outright (that start may
 * not have moved the card yet), and otherwise a card now `in_progress` is
 * being worked. A card that is GONE holds nothing; any other failure to read
 * it keeps the worktree — a stray costs disk, a wrong guess costs an agent its
 * working directory.
 *
 * TWIN: `apps/ui/src/main/autopilot-conductor.ts` `mayGiveBack`, the timer's
 * half of the same race.
 */
async function mayGiveBackWorktree(
  apis: DaemonApis,
  taskId: string,
  refusal: unknown,
): Promise<boolean> {
  const code = daemonErrorCode(refusal);
  if (code !== null && ANOTHER_START_HOLDS_IT.has(code)) {
    return false;
  }
  try {
    return (await apis.tasks.readTask({ taskId })).status !== 'in_progress';
  } catch (err: unknown) {
    return daemonErrorStatus(err) === 404;
  }
}

export interface BoardApi {
  projects: ProjectDto[];
  /** The open project, or null for every project's cards on one board. */
  selectedProjectId: string | null;
  tasks: TaskDto[];
  /**
   * Every card an agent is working, across the projects on screen — the
   * daemon's own answer, since `Task.runId` outlives the run it names.
   */
  activeTasks: ActiveTask[];
  loading: boolean;
  /** The last failure, in the daemon's own words, until it is dismissed. */
  error: string | null;
  selectProject: (projectId: string | null) => void;
  createProject: (dto: CreateProjectDto) => Promise<ProjectDto | null>;
  /**
   * Create a card, then write what the New task dialog STAGED for it — the
   * pictures pasted into its description and the files picked for it.
   */
  createTask: (
    dto: CreateTaskDto,
    staged?: NewTaskAttachments,
  ) => Promise<TaskDto | null>;
  updateTask: (taskId: string, dto: UpdateTaskDto) => Promise<TaskDto | null>;
  /** Bind files to a card by absolute path — the daemon copies nothing. */
  attachFiles: (taskId: string, paths: readonly string[]) => Promise<void>;
  /** Attach files by their bytes — a phone's way in (`TaskAttachments.onUpload`). */
  uploadFiles: (taskId: string, files: readonly File[]) => Promise<void>;
  /** Drop one reference. The FILE on disk is untouched. */
  detachFile: (taskId: string, attachmentId: string) => Promise<void>;
  moveTask: (taskId: string, to: string) => Promise<void>;
  /**
   * Drop a card into column `to` ahead of `beforeTaskId` (null = at the end) —
   * a status move when the column differs, then the column's new order.
   */
  placeTask: (
    taskId: string,
    to: string,
    beforeTaskId: string | null,
  ) => Promise<void>;
  /**
   * Delete a card from the board. Answers whether it went, so the panel that
   * asked closes only when it did.
   */
  deleteTask: (taskId: string) => Promise<boolean>;
  /**
   * Work a card: main makes the worktree, the daemon runs the agent inside it.
   *
   * `prompt` is what the user added to this one press. A card that has already
   * been worked is CONTINUED in the thread it already has, so a second press
   * is where "the tests still fail" belongs — see `TaskRunsService.resume`.
   */
  /**
   * Start (or continue) a card's run. Resolves TRUE when a run was actually
   * started and FALSE when the press was refused — the worktree could not be
   * made, or the daemon declined it.
   *
   * A boolean rather than a rejection: a refusal is an ordinary outcome here
   * (the card moved, the board is at its cap) and is already surfaced through
   * `error`, so throwing would make every fire-and-forget caller handle a
   * rejection to avoid an unhandled one. What the boolean buys is that the
   * follow-up box can keep what the user typed instead of clearing it into a
   * run that never began.
   */
  runTask: (taskId: string, prompt?: string) => Promise<boolean>;
  /** The card whose run is being started right now, or null. */
  startingTaskId: string | null;
  dismissError: () => void;
  /** Re-read the project list — the board calls this when it becomes visible. */
  refreshProjects: () => void;
  /**
   * Disarm the open project's autopilot.
   *
   * Intake only: a task already running is left working. Stopping one is a
   * different act with a different cost and has its own control on the run.
   */
  /**
   * What the open project's autopilot may start right now, as the DAEMON
   * counts it — or null while nothing has been read.
   *
   * Read rather than derived from `tasks`, and that is the whole point: a
   * card's column is written optimistically the moment it is dragged, and
   * "running" means a run that is still live, which a column cannot say. It
   * is fetched with the board and again on `task_changed`, so it moves with
   * the work rather than on a timer.
   */
  queue: ProjectQueueDto | null;
  stopAutopilot: () => Promise<void>;
  /** Write the open project's autopilot policy — switch, intake column, cap. */
  updateAutopilot: (patch: {
    autopilotEnabled?: boolean;
    autopilotIntakeStatus?: TaskDto['status'];
    autopilotMaxConcurrent?: number;
  }) => Promise<void>;
  /**
   * Write the open project's RUN defaults — the agent or workflow every task
   * on this board takes, and the model and effort under it.
   *
   * The same call as `updateAutopilot` under a name that says which question
   * is being answered; typed as the whole DTO rather than narrowed, because
   * these fields are nullable-optional and an explicit null is how one is
   * cleared.
   */
  updateProject: (patch: UpdateProjectDto) => Promise<void>;
  /** Close a tripped breaker so the autopilot resumes. */
  rearmAutopilot: () => Promise<void>;
}

export function useBoard(
  apis: DaemonApis | null,
  client: DaemonClient | null,
): BoardApi {
  const [queue, setQueue] = useState<ProjectQueueDto | null>(null);
  const [projects, setProjects] = useState<ProjectDto[]>([]);
  const [selectedProjectId, setSelectedProjectId] = useState<string | null>(
    null,
  );
  const [tasks, setTasks] = useState<TaskDto[]>([]);
  const [activeTasks, setActiveTasks] = useState<ActiveTask[]>([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  // TWO counters, not one. A task write echoes its own broadcast back, and a
  // single counter both effects keyed on turned every card move into a
  // `listProjects` as well as a `listTasks` of the whole board.
  const [startingTaskId, setStartingTaskId] = useState<string | null>(null);
  const [projectsNonce, setProjectsNonce] = useState(0);
  const [tasksNonce, setTasksNonce] = useState(0);
  /**
   * Card edits the daemon has not answered, per card, oldest first — laid back
   * over every row the board receives until each one lands (`withEditsInFlight`).
   * Refs rather than state: they change nothing on screen by themselves, and
   * they are read inside answers that arrive after the render that sent them.
   */
  const editsInFlight = useRef(new Map<string, EditInFlight[]>());
  const lastEditId = useRef(0);
  /** The newest edit per card whose ANSWER is on the board — see `updateTask`. */
  const answeredEdit = useRef(new Map<string, number>());

  const reload = useCallback(() => {
    setTasksNonce((n) => n + 1);
  }, []);

  const refreshProjects = useCallback(() => {
    setProjectsNonce((n) => n + 1);
  }, []);

  useEffect(() => {
    if (!apis) {
      return;
    }
    let cancelled = false;
    void apis.projects
      .listProjects()
      .then((rows) => {
        if (cancelled) {
          return;
        }
        setProjects(rows);
        // A selection pointing at a project that is no longer here has to GO:
        // Settings can delete the project this board is showing, and the
        // screen is latch-mounted so it never remounts to notice. Null is the
        // every-project board, which is also where the board opens.
        setSelectedProjectId((current) =>
          current !== null && !rows.some((row) => row.id === current)
            ? null
            : current,
        );
      })
      .catch((err: unknown) => {
        if (!cancelled) {
          setError(describeDaemonError(err));
        }
      });
    return () => {
      cancelled = true;
    };
  }, [apis, projectsNonce]);

  useEffect(() => {
    if (!apis) {
      setTasks([]);
      setQueue(null);
      setActiveTasks([]);
      return;
    }
    let cancelled = false;
    setLoading(true);
    // Beside the board rather than inside it, and its failure is SWALLOWED:
    // this only decides whether a banner can count, and a board that refused
    // to draw because a count could not be read would trade the whole screen
    // for a line of it. The every-project board has no single queue: it reads
    // only the projects holding a card with a run, once the board says which —
    // a run, not the In progress column, since a card continued after review
    // or dropped in Done can still have an agent at work.
    const readQueues = (projectIds: readonly string[]): void => {
      void Promise.all(
        projectIds.map((projectId) =>
          apis.projects.readProjectQueue({ projectId }).catch(() => null),
        ),
      ).then((reads) => {
        if (cancelled) {
          return;
        }
        setQueue(selectedProjectId === null ? null : (reads[0] ?? null));
        setActiveTasks(reads.flatMap((read) => read?.active ?? []));
      });
    };
    if (selectedProjectId !== null) {
      readQueues([selectedProjectId]);
    }
    // RECONCILE rather than list, and it answers with the board so this is
    // still one call. A run that settled while no window was open announced to
    // nobody, so without this the card it belongs to is still drawn as working
    // — which is exactly the force-quit case the milestone is asked to handle.
    void apis.tasks
      .reconcileTasks({
        reconcileTasksDto:
          selectedProjectId === null ? {} : { projectId: selectedProjectId },
      })
      .then((rows) => {
        if (cancelled) {
          return;
        }
        setTasks(
          rows.map((row) => withEditsInFlight(row, editsInFlight.current)),
        );
        if (selectedProjectId === null) {
          readQueues([
            ...new Set(
              rows
                .filter((row) => row.runId !== null)
                .map((row) => row.projectId),
            ),
          ]);
        }
      })
      .catch((err: unknown) => {
        if (!cancelled) {
          setError(describeDaemonError(err));
        }
      })
      .finally(() => {
        if (!cancelled) {
          setLoading(false);
        }
      });
    return () => {
      cancelled = true;
    };
  }, [apis, selectedProjectId, tasksNonce]);

  // Stable for the subscribe effect, so re-subscribing does not depend on the
  // render that produced the callback.
  const reloadRef = useRef(reload);
  reloadRef.current = reload;
  const selectedRef = useRef(selectedProjectId);
  selectedRef.current = selectedProjectId;
  /**
   * The runs this board's cards are holding, for the pull-request announce
   * below — a Set rather than a scan of `tasks`, since that event fires for
   * every chat in the app and this board is routinely not the subject.
   */
  const boardRunsRef = useRef<Set<string>>(new Set());
  boardRunsRef.current = new Set(
    tasks
      .map((task) => task.runId)
      .filter((runId): runId is string => runId !== null),
  );

  useEffect(() => {
    if (!client) {
      return;
    }
    return client.onTaskChanged((event) => {
      // The daemon has decided this card's work is FINISHED — it is Done and
      // no run is working in it — which is the one moment its worktree may go.
      // Main commits whatever the agent left onto the task's own branch and
      // then removes the directory.
      //
      // NOT when the card's run settles, which is what this keyed on before: a
      // task's run is a chat the user continues after review, Retry re-sends
      // into, and the CLI carries on by itself when a background command
      // reports — all of it in that directory. Collecting at the settle took a
      // live conversation's cwd out from under it, and every screenshot the
      // agent had shown in it.
      //
      // Keyed on the daemon's REASON rather than on the card's column, which
      // is written optimistically the moment a card is dragged: a card dropped
      // in Done while its agent is still working reaches this same broadcast.
      //
      // Deliberately NOT scoped to the open board. A worktree belongs to the
      // task, not to the project being looked at, and main answers with
      // `removed: false` for a task it never made one for — so the unscoped
      // call is a registry lookup, and scoping it would leave every other
      // project's worktrees uncollected for as long as this board is open.
      if (event.reason === 'work-finished') {
        void window.geniro.settleTaskWorktree(event.taskId);
      }
      // The broadcast is client-wide, so most events belong to a board this
      // one is not showing — unless it is showing every project.
      if (
        selectedRef.current === null ||
        event.projectId === selectedRef.current
      ) {
        reloadRef.current();
      }
    });
  }, [client]);

  useEffect(() => {
    if (!client) {
      return;
    }
    // A card's pull requests are the RUN's, captured from its transcript when
    // a turn ends — which is a different moment from the card settling, and
    // routinely the later of the two. Without this the result of the work
    // appears on the card only at the next listing, so a reader watching a
    // task finish sees the report land and the link not.
    //
    // The announce is client-wide and fires for every chat in the app, so it
    // is narrowed to a run this board is actually holding; the daemon is
    // already silent when a run's pull requests have not changed.
    return client.onRunStatus((event) => {
      if (event.pullRequests === undefined) {
        return;
      }
      if (boardRunsRef.current.has(event.runId)) {
        reloadRef.current();
      }
    });
  }, [client]);

  const createProject = useCallback(
    async (dto: CreateProjectDto): Promise<ProjectDto | null> => {
      if (!apis) {
        return null;
      }
      try {
        const project = await apis.projects.createProject({
          createProjectDto: dto,
        });
        setProjects((current) => [...current, project]);
        setSelectedProjectId(project.id);
        return project;
      } catch (err: unknown) {
        setError(describeDaemonError(err));
        return null;
      }
    },
    [apis],
  );

  /**
   * Create a card, then write what the dialog staged for it.
   *
   * Neither a picture nor a file can ride the create: the daemon keys both by
   * the card's id, which does not exist until this call returns. So the card
   * is created first — WITHOUT the staged references, so a card whose uploads
   * never happen holds no link to a file that does not exist — and each
   * picture is then written and its reference repointed at the saved path, in
   * the one description update that follows. A picture the user deleted from
   * the text before pressing Add is never uploaded.
   *
   * After the create, a failure costs one picture or one file, never the card:
   * it is reported, a picture's reference is taken out whole, and the rest
   * carries on. Files stop at the first refusal, as `attachFiles` does, since
   * the daemon's cap is the usual reason for one.
   */
  const createTask = useCallback(
    async (
      dto: CreateTaskDto,
      staged: NewTaskAttachments = NOTHING_STAGED,
    ): Promise<TaskDto | null> => {
      if (!apis) {
        return null;
      }
      const { description: typed = '', ...fields } = dto;
      const bare = stripStagedImages(typed).trim();
      let task: TaskDto;
      try {
        task = await apis.tasks.createTask({
          createTaskDto: {
            ...fields,
            ...(bare === '' ? {} : { description: bare }),
          },
        });
      } catch (err: unknown) {
        setError(describeDaemonError(err));
        return null;
      }
      const created = task;
      setTasks((current) => [...current, created]);
      // Pinned from the create: every call below answers with the whole card,
      // and none of them may be aimed by whatever the previous one answered.
      const taskId = created.id;

      const failures: string[] = [];
      let description = typed;
      for (const image of staged.images) {
        if (!referencesStagedImage(description, image.ref)) {
          continue;
        }
        try {
          const saved = await apis.tasks.addTaskAttachment({
            taskId,
            addTaskAttachmentDto: {
              mediaType: image.mediaType,
              data: await image.data,
              ...(image.name === null ? {} : { name: image.name }),
            },
          });
          description = resolveStagedImage(description, image.ref, saved.path);
        } catch (err: unknown) {
          description = resolveStagedImage(description, image.ref, null);
          failures.push(describeDaemonError(err));
        }
      }
      // Whatever is still staged references a picture nothing holds.
      description = stripStagedImages(description).trim();
      if (description !== bare) {
        try {
          task = await apis.tasks.updateTask({
            taskId,
            updateTaskDto: { description },
          });
        } catch (err: unknown) {
          failures.push(describeDaemonError(err));
        }
      }
      for (const path of staged.files) {
        try {
          task = await apis.tasks.attachTaskFile({
            taskId,
            attachTaskFileDto: { path },
          });
        } catch (err: unknown) {
          failures.push(describeDaemonError(err));
          break;
        }
      }
      // Files a phone picked go up by their BYTES once the card exists — it has
      // no path on this machine to bind (`TaskAttachments.onUpload`).
      for (const file of staged.uploads) {
        try {
          task = await apis.tasks.uploadTaskFile({
            taskId,
            uploadTaskFileDto: {
              name: file.name,
              data: await readAsBase64(file),
            },
          });
        } catch (err: unknown) {
          failures.push(describeDaemonError(err));
          break;
        }
      }

      const final = task;
      if (final !== created) {
        setTasks((current) =>
          current.map((row) => (row.id === final.id ? final : row)),
        );
      }
      if (failures.length > 0) {
        setError(
          `The task was created, but not everything staged for it could be attached: ${failures[0]}`,
        );
      }
      return final;
    },
    [apis],
  );

  /**
   * Edit a card — OPTIMISTICALLY, like a drag: the edit is on the card the
   * moment it is made, and the daemon's answer replaces it when it lands.
   *
   * It does not wait for that answer, because the task panel builds every edit
   * from the card it is handed — so a second edit inside one round trip would
   * be built from the card as it stood BEFORE the first, and write the first
   * one away: two quick label presses would keep only the second label, and a
   * date field controlled by the lagging card would reset mid-typing.
   *
   * Three rules keep the screen honest while edits are out. Until an edit is
   * answered it is laid back over every row the board receives
   * (`withEditsInFlight`). An answer is shown only if no NEWER edit's answer is
   * already on the board — an older one landing late describes a card from
   * before it. And a refused edit is taken back out field by field, only where
   * the field still holds what it wrote (`withoutEdit`), the rule `moveTask`
   * follows for the same reason.
   */
  const updateTask = useCallback(
    async (taskId: string, dto: UpdateTaskDto): Promise<TaskDto | null> => {
      if (!apis) {
        return null;
      }
      lastEditId.current += 1;
      const id = lastEditId.current;
      const inFlight = editsInFlight.current;
      inFlight.set(taskId, [...(inFlight.get(taskId) ?? []), { id, dto }]);
      const settle = (answered: (edit: EditInFlight) => boolean): void => {
        const left = (inFlight.get(taskId) ?? []).filter(
          (edit) => !answered(edit),
        );
        if (left.length === 0) {
          inFlight.delete(taskId);
        } else {
          inFlight.set(taskId, left);
        }
      };
      // The card as it stood just before THIS edit, for taking it back out.
      // Captured inside the updater, which is what sees earlier edits that
      // have not reached a render yet.
      const before: { row: TaskDto | null } = { row: null };
      setTasks((current) =>
        current.map((row) => {
          if (row.id !== taskId) {
            return row;
          }
          before.row = row;
          return withEdit(row, dto);
        }),
      );
      try {
        const task = await apis.tasks.updateTask({
          taskId,
          updateTaskDto: dto,
        });
        // Every edit sent before this one has been handled by the daemon too,
        // so none of them is laid over its answer any more.
        settle((edit) => edit.id <= id);
        if ((answeredEdit.current.get(taskId) ?? 0) < id) {
          answeredEdit.current.set(taskId, id);
          setTasks((current) =>
            current.map((row) =>
              row.id === taskId ? withEditsInFlight(task, inFlight) : row,
            ),
          );
        }
        return task;
      } catch (err: unknown) {
        settle((edit) => edit.id === id);
        // Read inside the updater: updaters run in the order they were queued,
        // so the optimistic one above has always run — and captured — by then,
        // even if no render has happened since.
        setTasks((current) =>
          current.map((row) =>
            row.id === taskId && before.row !== null
              ? withoutEdit(row, dto, before.row)
              : row,
          ),
        );
        setError(describeDaemonError(err));
        return null;
      }
    },
    [apis],
  );

  /**
   * Bind files to a card, one call each.
   *
   * SEQUENTIAL rather than fanned out, and the reason is the daemon's cap: the
   * list is bounded, so a batch sent in parallel would have several calls race
   * past the limit and land a set the route would have refused one at a time.
   * Each answers with the whole card, so the last one in is the list.
   *
   * A refusal stops the run and is reported — attaching six files and being
   * told about the third is more useful than six banners, and the ones already
   * bound are on screen.
   */
  const attachFiles = useCallback(
    async (taskId: string, paths: readonly string[]): Promise<void> => {
      if (!apis) {
        return;
      }
      try {
        for (const path of paths) {
          const task = await apis.tasks.attachTaskFile({
            taskId,
            attachTaskFileDto: { path },
          });
          setTasks((current) =>
            current.map((row) =>
              row.id === taskId
                ? withEditsInFlight(task, editsInFlight.current)
                : row,
            ),
          );
        }
      } catch (err: unknown) {
        setError(describeDaemonError(err));
      }
    },
    [apis],
  );

  /**
   * Attach files by their BYTES, for a device with no path on this machine —
   * a phone over the LAN gateway. Sequential for `attachFiles`' reason: the
   * daemon caps the list, and a parallel batch would race past it.
   */
  const uploadFiles = useCallback(
    async (taskId: string, files: readonly File[]): Promise<void> => {
      if (!apis) {
        return;
      }
      try {
        for (const file of files) {
          const task = await apis.tasks.uploadTaskFile({
            taskId,
            uploadTaskFileDto: {
              name: file.name,
              data: await readAsBase64(file),
            },
          });
          setTasks((current) =>
            current.map((row) =>
              row.id === taskId
                ? withEditsInFlight(task, editsInFlight.current)
                : row,
            ),
          );
        }
      } catch (err: unknown) {
        setError(describeDaemonError(err));
      }
    },
    [apis],
  );

  const detachFile = useCallback(
    async (taskId: string, attachmentId: string): Promise<void> => {
      if (!apis) {
        return;
      }
      try {
        const task = await apis.tasks.detachTaskFile({ taskId, attachmentId });
        setTasks((current) =>
          current.map((row) =>
            row.id === taskId
              ? withEditsInFlight(task, editsInFlight.current)
              : row,
          ),
        );
      } catch (err: unknown) {
        setError(describeDaemonError(err));
      }
    },
    [apis],
  );

  const moveTask = useCallback(
    async (taskId: string, to: string): Promise<void> => {
      const before = tasks.find((row) => row.id === taskId);
      if (!apis || before === undefined || before.status === to) {
        return;
      }
      // Optimistic: the card follows the pointer immediately, and the write
      // catches up. `from` carries the status this board believes the card is
      // in, which is what lets the daemon refuse a move made against a stale
      // read instead of overwriting whoever moved it first.
      setTasks((current) =>
        current.map((row) =>
          row.id === taskId ? { ...row, status: to as TaskStatus } : row,
        ),
      );
      try {
        const moved = await apis.tasks.moveTaskStatus({
          taskId,
          // The daemon owns the status vocabulary, so `to` is whatever the
          // column carries — including one this build does not know.
          moveTaskStatusDto: { from: before.status, to: to as TaskStatus },
        });
        setTasks((current) =>
          current.map((row) =>
            row.id === taskId
              ? withEditsInFlight(moved, editsInFlight.current)
              : row,
          ),
        );
      } catch (err: unknown) {
        // Put it back where the user took it from, and say so — a silent
        // snap-back reads as the app losing the drag. Restore ONLY if the row
        // still holds the value this call wrote: a refusal usually means
        // someone else moved the card, and a reload racing this request may
        // already have fetched their newer status. Overwriting that would
        // leave the board disagreeing with the daemon and every later move
        // refused for the same reason.
        setTasks((current) =>
          current.map((row) =>
            row.id === taskId && row.status === to ? before : row,
          ),
        );
        setError(describeDaemonError(err));
      }
    },
    [apis, tasks],
  );

  /**
   * Delete a card — the daemon's delete, then the worktree its runs were cut
   * from, which nothing else would ever collect once the card is gone.
   *
   * The worktree goes through `pruneTaskWorktree`, the path a failed start
   * already takes: it removes only a directory this app recorded creating and
   * keeps one holding unsaved work, and it never touches the BRANCH — so the
   * agent's commits outlive the card that asked for them.
   */
  const deleteTask = useCallback(
    async (taskId: string): Promise<boolean> => {
      if (!apis) {
        return false;
      }
      try {
        await apis.tasks.deleteTask({ taskId });
      } catch (err: unknown) {
        setError(describeDaemonError(err));
        return false;
      }
      setTasks((current) => current.filter((row) => row.id !== taskId));
      await window.geniro.pruneTaskWorktree(taskId).catch(() => false);
      return true;
    },
    [apis],
  );

  /**
   * Drop a card into a column ahead of another card, or at its end.
   *
   * Optimistic, like `moveTask`. A refusal of either write re-reads the board
   * rather than restoring a snapshot: the usual cause is someone else moving a
   * card, and the daemon's order is the only one worth showing then.
   */
  const placeTask = useCallback(
    async (
      taskId: string,
      to: string,
      beforeTaskId: string | null,
    ): Promise<void> => {
      const before = tasks.find((row) => row.id === taskId);
      const ids = columnOrderAfterDrop(tasks, taskId, to, beforeTaskId);
      if (!apis || before === undefined || ids === null) {
        return;
      }
      const status = to as TaskStatus;
      setTasks((current) => arrangeColumn(current, status, ids));
      try {
        if (before.status !== status) {
          await apis.tasks.moveTaskStatus({
            taskId,
            moveTaskStatusDto: { from: before.status, to: status },
          });
        }
        const saved = await apis.tasks.reorderTasks({
          reorderTasksDto: { status, ids },
        });
        const byId = new Map(saved.map((row) => [row.id, row]));
        // Re-arranged rather than merged in place: the move's own broadcast
        // can reload the board between the two writes, putting the card back
        // at the end of its new column, and a merge keeps that array order.
        // Only the cards the daemon placed: one that left the column meanwhile
        // was skipped there, and arranging it would pull it back.
        setTasks((current) =>
          arrangeColumn(
            current.map((row) => byId.get(row.id) ?? row),
            status,
            ids.filter((id) => byId.has(id)),
          ),
        );
      } catch (err: unknown) {
        setError(describeDaemonError(err));
        reload();
      }
    },
    [apis, tasks, reload],
  );

  const selectProject = useCallback((projectId: string | null) => {
    setSelectedProjectId(projectId);
  }, []);

  /**
   * Press Run: make the workspace, then start the agent in it.
   *
   * The ORDER is the whole safety of it. Main creates the worktree first,
   * because the daemon needs a real directory to run in and runs no git
   * itself; the daemon then starts the chat. If that second half fails, a
   * worktree THIS press made is removed in the failure path of the same
   * operation — otherwise every failed press leaves a checkout on disk for a
   * card whose work may never be finished, which is all the reaper collects.
   * One that was the task's own, still standing, is left where it is.
   */
  const runTask = useCallback(
    async (taskId: string, prompt = ''): Promise<boolean> => {
      const task = tasks.find((row) => row.id === taskId);
      const project = projects.find((row) => row.id === task?.projectId);
      if (!apis || task === undefined || project === undefined) {
        return false;
      }
      setStartingTaskId(taskId);
      try {
        const made = await window.geniro.prepareTaskWorktree({
          taskId,
          // The CARD's folder if it names one, else the project's — a project's
          // folder is the default for its board and not the law, since one
          // board routinely holds work across several checkouts. The same
          // resolution the daemon does for the autopilot's handout; here it is
          // one line because both rows are already in hand.
          folder: task.folder ?? project.folder,
        });
        if (!made.ok || made.path === null || made.branch === null) {
          setError(made.error ?? 'the worktree could not be created');
          return false;
        }
        try {
          // The client's own reading of the folder, taken now — the fixed
          // point the chat's diff view measures against, exactly as the
          // composer takes it when a chat is opened by hand.
          const stamp = await window.geniro.getGitStamp(made.path);
          const settings = await window.geniro.getSettings();
          const started = await apis.tasks.startTaskRun({
            taskId,
            startTaskRunDto: {
              cwd: made.path,
              branch: made.branch,
              // What THIS board believes the card is in, so a start computed
              // against a card someone else already moved is refused.
              from: task.status,
              startSha: stamp.sha ?? undefined,
              startDirty: stamp.dirty ?? undefined,
              customInstructions:
                settings.customInstructions.trim() === ''
                  ? undefined
                  : settings.customInstructions,
              // What the user added to THIS press. Omitted rather than sent
              // blank: absent is what the daemon reads as "the press said
              // nothing", and a card being continued then gets its own brief
              // again rather than an empty message.
              ...(prompt.trim() === '' ? {} : { prompt: prompt.trim() }),
            },
          });
          setTasks((current) =>
            current.map((row) => (row.id === taskId ? started : row)),
          );
          return true;
        } catch (err: unknown) {
          // Given back only when THIS press made it. A worktree that was the
          // task's own, still standing from an earlier run, stays: a refused
          // start may mean that run is working in it right now. And one this
          // press made stays too when another start of the card is using it —
          // see `mayGiveBackWorktree`.
          if (!made.reused && (await mayGiveBackWorktree(apis, taskId, err))) {
            await window.geniro.pruneTaskWorktree(taskId);
          }
          setError(describeDaemonError(err));
          return false;
        }
      } finally {
        setStartingTaskId(null);
      }
    },
    [apis, projects, tasks],
  );

  const dismissError = useCallback(() => {
    setError(null);
  }, []);

  /**
   * The open project's own row — its autopilot policy and its run defaults.
   *
   * The conductor reads that row on its next tick, so there is nothing to
   * tell it and no IPC channel between them — the board, Settings and the
   * timer all learn the same answer from the same place.
   *
   * ONE writer for both groups of fields, exported under two names because the
   * two controls are about different things: a second callback would be a
   * second copy of the optimistic replace below and of the error handling
   * around it.
   */
  const patchProject = useCallback(
    async (patch: UpdateProjectDto): Promise<void> => {
      const projectId = selectedRef.current;
      if (!apis || projectId === null) {
        return;
      }
      try {
        const saved = await apis.projects.updateProject({
          projectId,
          updateProjectDto: patch,
        });
        setProjects((current) =>
          current.map((row) => (row.id === saved.id ? saved : row)),
        );
      } catch (err: unknown) {
        setError(describeDaemonError(err));
      }
    },
    [apis],
  );

  const stopAutopilot = useCallback(
    () => patchProject({ autopilotEnabled: false }),
    [patchProject],
  );

  const rearmAutopilot = useCallback(async (): Promise<void> => {
    const projectId = selectedRef.current;
    if (!apis || projectId === null) {
      return;
    }
    try {
      const saved = await apis.projects.rearmProjectAutopilot({ projectId });
      setProjects((current) =>
        current.map((row) => (row.id === saved.id ? saved : row)),
      );
    } catch (err: unknown) {
      setError(describeDaemonError(err));
    }
  }, [apis]);

  return {
    projects,
    selectedProjectId,
    tasks,
    activeTasks,
    loading,
    error,
    selectProject,
    createProject,
    createTask,
    updateTask,
    attachFiles,
    uploadFiles,
    detachFile,
    moveTask,
    placeTask,
    deleteTask,
    runTask,
    startingTaskId,
    dismissError,
    refreshProjects,
    queue,
    stopAutopilot,
    updateAutopilot: patchProject,
    updateProject: patchProject,
    rearmAutopilot,
  };
}
