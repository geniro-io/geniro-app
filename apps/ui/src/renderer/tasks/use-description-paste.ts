import { useCallback, useRef, useState } from 'react';

import type { AttachmentMediaType } from '../autogenerated';
import { insertPastedFilePaths } from '../chats/paste-file-paths';
import type { DaemonApis } from '../daemon-api';

/** What the daemon will store; anything else keeps the browser's own paste. */
const IMAGE_TYPES = new Set([
  'image/png',
  'image/jpeg',
  'image/gif',
  'image/webp',
]);

/** The alt text a clipboard screenshot is referenced under. */
const PASTED_NAME = 'Pasted image';

/** Strip the `data:<type>;base64,` head a `FileReader` result carries. */
function base64Of(dataUrl: string): string {
  const comma = dataUrl.indexOf(',');
  return comma === -1 ? '' : dataUrl.slice(comma + 1);
}

function readAsBase64(file: File): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = () => {
      reject(new Error('could not read the pasted image'));
    };
    reader.onload = () => {
      resolve(base64Of(String(reader.result ?? '')));
    };
    reader.readAsDataURL(file);
  });
}

/**
 * Paste a screenshot or a file into a task's description and have it LAND.
 *
 * REPORTED as "я всё ещё не могу вставлять файлы или изображения. Например,
 * когда я делаю скриншот и нажимаю «Вставить», он должен автоматически
 * добавлять файл с description в Markdown. Сейчас ничего не происходит" — and
 * nothing was happening because nothing was listening: the composer has had
 * both halves of this for months and the description field had neither.
 *
 * Two kinds, and the split is the composer's own. An IMAGE is bytes with no
 * path, so it is written to disk by the daemon and referenced as
 * `![name](path)`. Anything ELSE the clipboard carries as a file already IS a
 * path, so `insertPastedFilePaths` writes that path verbatim — a `.pdf`, a
 * `.csv`, a source file — which is exactly what a description wants, since the
 * agent that reads it can open the thing.
 *
 * The reference is a PATH in both cases rather than an inline `data:` URL, and
 * that is the decision the rest follows from: a description is a brief an AGENT
 * works from, and an agent cannot read a base64 blob out of a prompt as a file.
 * See `TaskAttachmentService`.
 *
 * The insertion goes through `execCommand('insertText')` for
 * `insertPastedFilePaths`' three recorded reasons: it lands at the CARET, keeps
 * the field's own undo stack, and fires the `input` event a controlled value is
 * written from. A state update would do none of the three.
 */
export function useDescriptionPaste({
  taskId,
  tasksApi,
}: {
  taskId: string;
  tasksApi: DaemonApis['tasks'] | null;
}): {
  /** Attach to the textarea. Returns whether it swallowed the paste. */
  onPaste: (event: React.ClipboardEvent<HTMLTextAreaElement>) => void;
  /** An upload that failed, in the daemon's own words — null when all is well. */
  error: string | null;
  /** True while bytes are on their way to disk. */
  uploading: boolean;
  dismissError: () => void;
} {
  const [error, setError] = useState<string | null>(null);
  const [uploading, setUploading] = useState(false);

  const onPaste = useCallback(
    (event: React.ClipboardEvent<HTMLTextAreaElement>): void => {
      const data = event.clipboardData;
      const image = [...(data?.files ?? [])].find((file) =>
        IMAGE_TYPES.has(file.type),
      );
      if (image === undefined) {
        // Not an image: any other pasted file becomes its own absolute path,
        // and a paste carrying no file at all falls through to the browser.
        if (insertPastedFilePaths(data)) {
          event.preventDefault();
        }
        return;
      }
      if (tasksApi === null) {
        return;
      }
      // Swallowed BEFORE the await: the default paste of an image file inserts
      // its NAME, and letting that land first would leave the word `Screenshot
      // 2026-09-08.png` in the description beside the reference we then add.
      event.preventDefault();
      setError(null);
      setUploading(true);
      // Captured synchronously: `insertText` writes wherever the caret is, and
      // the field this paste came from may not be the one focused once the
      // upload lands — a title `Input` elsewhere on the card autosaves on blur,
      // so a misdirected insertion is not just a wrong link, it is persisted.
      const field = event.currentTarget;
      void readAsBase64(image)
        .then((data64) =>
          tasksApi.addTaskAttachment({
            taskId,
            addTaskAttachmentDto: {
              mediaType: image.type as 'image/png',
              data: data64,
              ...(image.name === '' ? {} : { name: image.name }),
            },
          }),
        )
        .then((saved) => {
          // Only insert while the paste's own field is still focused; a failed
          // or redirected insertion is reported rather than dropped or sent
          // elsewhere, since the file is already on disk and the user has no
          // other way to reference it.
          const written =
            document.activeElement === field &&
            document.execCommand(
              'insertText',
              false,
              `![${saved.name || PASTED_NAME}](${saved.path})`,
            );
          if (!written) {
            setError(
              `The image was saved to ${saved.path}, but could not be written into the description — click into it and paste again.`,
            );
          }
        })
        .catch((err: unknown) => {
          setError(err instanceof Error ? err.message : String(err));
        })
        .finally(() => {
          setUploading(false);
        });
    },
    [taskId, tasksApi],
  );

  const dismissError = useCallback(() => {
    setError(null);
  }, []);

  return { onPaste, error, uploading, dismissError };
}

/**
 * The scheme a STAGED picture's reference uses until its card exists.
 *
 * Not a URL anything can open, deliberately: a reference that somehow outlived
 * the create meant to resolve it draws as a broken image rather than pointing
 * an agent at some file.
 */
const STAGED_SCHEME = 'staged-image:';

/** One staged picture's WHOLE reference — `![alt](staged-image:<n>)`. */
const STAGED_REFERENCE = /!\[[^\]]*\]\(staged-image:\d+\)/g;

/** A picture pasted into a card that does not exist yet. */
export interface StagedImage {
  /** What stands in the description for it — `staged-image:<n>`. */
  ref: string;
  mediaType: AttachmentMediaType;
  /** The file's own name, when the clipboard carried one. */
  name: string | null;
  /**
   * Its bytes, base64 — read at PASTE time, as the panel's paste reads them,
   * and awaited when the card is created.
   */
  data: Promise<string>;
}

/** Whether a description still references one staged picture. */
export function referencesStagedImage(
  description: string,
  ref: string,
): boolean {
  return description.includes(`](${ref})`);
}

/**
 * Point a staged picture's reference at the path it was saved to — or, with a
 * null path, take the reference out WHOLE, alt text and all, so a picture that
 * could not be written leaves no dead image behind it.
 */
export function resolveStagedImage(
  description: string,
  ref: string,
  path: string | null,
): string {
  if (path !== null) {
    return description.split(`](${ref})`).join(`](${path})`);
  }
  return description.replace(STAGED_REFERENCE, (match) =>
    match.endsWith(`](${ref})`) ? '' : match,
  );
}

/** Take every staged reference out — what a card is CREATED with. */
export function stripStagedImages(description: string): string {
  return description.replace(STAGED_REFERENCE, '');
}

/**
 * The New task dialog's paste: the same two kinds as
 * {@link useDescriptionPaste}, for a card that has no id yet.
 *
 * REPORTED as "i cant add images to task when i just create task - only when
 * edit". The daemon writes a picture under its CARD's directory, so the dialog
 * took paths alone and a pasted screenshot did nothing. It now STAGES one: a
 * `![name](staged-image:<n>)` reference lands at the caret at once — so the
 * picture sits where the user put it in the prose, which is how a description
 * that interleaves sentences and screenshots is written — and the board writes
 * the bytes and repoints the reference once the card exists (`createTask`).
 */
export function useStagedDescriptionPaste(): {
  onPaste: (event: React.ClipboardEvent<HTMLTextAreaElement>) => void;
  /** Every picture staged since the last reset, referenced or not. */
  staged: readonly StagedImage[];
  error: string | null;
  dismissError: () => void;
  /** Forget everything staged — the dialog calls it on every open. */
  reset: () => void;
} {
  const [staged, setStaged] = useState<StagedImage[]>([]);
  const [error, setError] = useState<string | null>(null);
  // Never reset with the list: a reference left in a restored draft must not
  // come to mean a different picture.
  const nextRef = useRef(0);

  const onPaste = useCallback(
    (event: React.ClipboardEvent<HTMLTextAreaElement>): void => {
      const data = event.clipboardData;
      const image = [...(data?.files ?? [])].find((file) =>
        IMAGE_TYPES.has(file.type),
      );
      if (image === undefined) {
        if (insertPastedFilePaths(data)) {
          event.preventDefault();
        }
        return;
      }
      event.preventDefault();
      nextRef.current += 1;
      const ref = `${STAGED_SCHEME}${nextRef.current}`;
      // SYNCHRONOUS, unlike the panel's: nothing has to be written first, so
      // the reference lands while the field that took the paste has focus.
      const written = document.execCommand(
        'insertText',
        false,
        `![${image.name || PASTED_NAME}](${ref})`,
      );
      if (!written) {
        setError(
          'The picture could not be written into the description — click into it and paste again.',
        );
        return;
      }
      setError(null);
      const bytes = readAsBase64(image);
      // Marked handled now; the create awaits it and reports a failure there.
      bytes.catch(() => undefined);
      setStaged((current) => [
        ...current,
        {
          ref,
          mediaType: image.type as AttachmentMediaType,
          name: image.name === '' ? null : image.name,
          data: bytes,
        },
      ]);
    },
    [],
  );

  const dismissError = useCallback(() => {
    setError(null);
  }, []);

  const reset = useCallback(() => {
    setStaged([]);
    setError(null);
  }, []);

  return { onPaste, staged, error, dismissError, reset };
}
