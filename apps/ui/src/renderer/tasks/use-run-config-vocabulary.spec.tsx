// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { CapabilitiesDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import {
  type RunConfigVocabulary,
  useRunConfigVocabulary,
} from './use-run-config-vocabulary';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

// Constant identity across renders — `useAgentModels`/`useAgentEfforts` key
// their own effects on this reference, so a fresh object per render would
// refetch on every commit rather than exercising the thing under test.
const AGENTS_API = {
  listAgentModels: vi.fn(async () => []),
  listAgentEfforts: vi.fn(async () => ({
    efforts: [],
    unavailableReason: null,
  })),
} as unknown as DaemonApis['agents'];

function capabilitiesApi(
  getCapabilities: () => Promise<CapabilitiesDto>,
): DaemonApis['capabilities'] {
  return { getCapabilities } as unknown as DaemonApis['capabilities'];
}

function caps(): CapabilitiesDto {
  return {
    claudeModes: {
      acceptEdits: 'pass',
      plan: 'pass',
      version: 'claude 2',
      probedAt: 1,
      reason: null,
    },
    configDirs: [{ agent: 'claude', unavailableReason: null }],
    approvals: [{ agent: 'claude', modes: ['ask', 'auto'] }],
  } as unknown as CapabilitiesDto;
}

let latest: RunConfigVocabulary | null = null;

function Probe({
  capsApi,
}: {
  capsApi: DaemonApis['capabilities'] | null;
}): null {
  latest = useRunConfigVocabulary({
    agentsApi: AGENTS_API,
    capabilitiesApi: capsApi,
    agentKind: 'claude',
    model: null,
    configDir: null,
  });
  return null;
}

async function mount(
  capsApi: DaemonApis['capabilities'] | null,
): Promise<() => RunConfigVocabulary | null> {
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<Probe capsApi={capsApi} />);
  });
  return () => latest;
}

describe('useRunConfigVocabulary — approvalModesLoading', () => {
  it('is true while the capabilities read is genuinely outstanding', async () => {
    const read = await mount(capabilitiesApi(() => new Promise(() => {})));

    expect(read()?.approvalModesLoading).toBe(true);
    expect(read()?.approvalModes).toBeNull();
  });

  it('clears once the read lands with an answer', async () => {
    const read = await mount(capabilitiesApi(() => Promise.resolve(caps())));

    expect(read()?.approvalModesLoading).toBe(false);
    expect(read()?.approvalModes).toEqual(['ask', 'auto']);
  });

  it('clears on a FAILED read too — a refusal is not "still asking"', async () => {
    // Before this fix `approvalModesLoading` was derived from
    // `capabilities === null` alone, which a failed read never clears —
    // `useCapabilities` fails open to `null` and used to expose no settled
    // state, so the approval-mode chip spun for the life of the daemon
    // handle over a probe that had already given up.
    const read = await mount(
      capabilitiesApi(() => Promise.reject(new Error('daemon down'))),
    );

    expect(read()?.approvalModesLoading).toBe(false);
    expect(read()?.approvalModes).toBeNull();
  });

  it('is false with no daemon handle at all — nothing was ever asked', async () => {
    const read = await mount(null);

    expect(read()?.approvalModesLoading).toBe(false);
  });
});
