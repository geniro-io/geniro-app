import type { CliKind } from '../../shared/contracts';
import type {
  AgentApprovalCapability,
  ChatApprovalMode,
} from '../autogenerated';
import { useAgentEfforts } from '../chats/use-agent-efforts';
import { useAgentModels } from '../chats/use-agent-models';
import type { DaemonApis } from '../daemon-api';
import { useSharedCapabilities } from '../use-capabilities';

/** Everything a run-configuration form needs the daemon to answer. */
export interface RunConfigVocabulary {
  /** The models this CLI reports, and whether that read has landed. */
  models: ReturnType<typeof useAgentModels>['models'];
  modelsLoading: boolean;
  /** The effort levels this (CLI, model) pair reports. */
  efforts: ReturnType<typeof useAgentEfforts>['efforts'];
  /**
   * Whether the effort read is still in flight — `useAgentEfforts` already
   * carries this; it is surfaced here rather than dropped, on the same
   * "unread must not read as unavailable" rule `modelsLoading` follows.
   */
  effortsLoading: boolean;
  /**
   * The approval modes this CLI honours — null while capabilities are unread,
   * which the picker renders as nothing rather than as a guess.
   */
  approvalModes: readonly ChatApprovalMode[] | null;
  /**
   * Whether `approvalModes` is still unread rather than genuinely empty — the
   * capabilities probe has not answered yet for an agent one has been chosen.
   */
  approvalModesLoading: boolean;
  /**
   * This agent's full approval capability (modes plus any probe), for a
   * probe-driven `ApprovalModeSelect` — undefined on the same terms
   * `approvalModes` is null: no agent chosen, or capabilities unread.
   */
  approvalCapability: AgentApprovalCapability | undefined;
  /**
   * Why this CLI cannot be pointed at a config directory (`null` = it can), or
   * `undefined` while capabilities are unread — `ConfigDirSelect`'s own
   * vocabulary, read off the same capabilities probe as the approval modes.
   */
  configDirUnavailableReason: string | null | undefined;
}

/**
 * The three vocabularies a run configuration is built from, fetched once.
 *
 * TWO surfaces ask for exactly this set — the board header's project defaults
 * and a card's own overrides — and each of them is a form of the same shape
 * over the same generated pickers. What differs between them is inheritance
 * and layout; what is identical is the question put to the daemon, so that is
 * what is shared rather than a component with a flag.
 *
 * Every answer belongs to the CLI and is asked of the CLI: which models exist
 * is `GET /v1/agents/models`, which effort levels a MODEL offers is a second
 * question with the model in it, and which approval modes are honoured comes
 * off `GET /v1/capabilities` — composed from each adapter's own
 * `AdapterConfig.approval`. None of the three is ever decided here by agent
 * name, which is the rule `approval-mode-select.tsx` records the cost of.
 *
 * A null `agentKind` (nothing chosen, or a workflow, whose nodes each name
 * their own model) yields empty vocabularies, so every picker draws nothing —
 * the same subtraction `resolveRunTarget` makes on the daemon side.
 */
export function useRunConfigVocabulary({
  agentsApi,
  capabilitiesApi,
  agentKind,
  model,
  configDir,
}: {
  agentsApi: DaemonApis['agents'] | null;
  capabilitiesApi: DaemonApis['capabilities'] | null;
  agentKind: CliKind | null;
  model: string | null;
  configDir: string | null;
}): RunConfigVocabulary {
  const { models, loading: modelsLoading } = useAgentModels(
    agentsApi,
    agentKind,
    configDir,
  );
  const { efforts, loading: effortsLoading } = useAgentEfforts(
    agentsApi,
    agentKind,
    model,
    configDir,
  );
  const { capabilities, loading: capabilitiesLoading } =
    useSharedCapabilities(capabilitiesApi);
  const approvalCapability =
    capabilities === null || agentKind === null
      ? undefined
      : capabilities.approvals.find((row) => row.agent === agentKind);
  const approvalModes =
    capabilities === null || agentKind === null
      ? null
      : (approvalCapability?.modes ?? []);
  // True only while a read is genuinely outstanding. The capabilities read's
  // own `loading` tells "still asking" apart from "asked and got nothing", so a
  // FAILED read — fail-open to `capabilities: null` — clears it rather than
  // reading as a probe still in flight.
  //
  // `capabilitiesApi !== null` for a null api: the DEFAULT this hook is called
  // with (`TaskFieldsContext`, and `Tasks.tsx` for as long as `apis` is null).
  // Nothing is asked for this surface then, so it must not spin whatever the
  // app's own read is doing.
  const approvalModesLoading =
    capabilitiesApi !== null && agentKind !== null && capabilitiesLoading;
  const configDirUnavailableReason =
    capabilities === null
      ? undefined
      : capabilities.configDirs.find((row) => row.agent === agentKind)
          ?.unavailableReason;
  return {
    models,
    modelsLoading,
    efforts,
    effortsLoading,
    approvalModes,
    approvalModesLoading,
    approvalCapability,
    configDirUnavailableReason,
  };
}
