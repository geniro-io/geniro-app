/**
 * An analysis can save the team the builder has open. The builder's saves
 * quote the version they were made from, and one made from a stale copy is
 * refused rather than writing the old copy back over the applied change.
 */
describe('Teams — a save over a file changed outside the builder', () => {
  beforeEach(() => {
    client = fakeClient();
  });

  it('quotes its version, holds autosave on a refusal, and reloads on request', async () => {
    saveTeam.mockImplementation(async () => {
      throw new Error(
        'daemon PUT /v1/teams/dev-team failed (409): {"code":"TEAM_CHANGED","message":"changed since this copy was read"}',
      );
    });
    await openBuilder();

    await edit();
    await wait(900);

    expect(savedRequests()).toHaveLength(1);
    expect(savedRequests()[0]!.saveTeamDto.baseHash).toBe('loaded-1');
    expect(container.textContent).toContain(
      'This team changed outside the builder',
    );

    await edit();
    await wait(900);
    expect(savedRequests()).toHaveLength(1);

    const reads = getTeam.mock.calls.length;
    await press('Reload');
    expect(getTeam.mock.calls.length).toBe(reads + 1);
    expect(container.textContent).not.toContain(
      'This team changed outside the builder',
    );
  });

  it('quotes the version its own last save returned on the next save', async () => {
    await openBuilder();

    await edit();
    await wait(900);
    await edit();
    await wait(900);

    expect(savedRequests().map((r) => r.saveTeamDto.baseHash)).toEqual([
      'loaded-1',
      'saved-1',
    ]);
  });

  it('quotes the version the post-turn re-read found', async () => {
    openTeamChat.mockImplementation(async () => ({
      id: 'run-1',
      status: 'running',
    }));
    await openBuilder();
    await press('Change with chat');
    getTeam.mockImplementation(async ({ slug }: { slug: string }) => ({
      slug,
      team: EMPTY,
      hash: 'reread-2',
    }));

    await edit();
    await endTurn('done-1');
    await wait(900);

    expect(savedRequests().at(-1)!.saveTeamDto.baseHash).toBe('reread-2');
  });
});
