/** Let real time pass — the autosave debounce is 700ms. */
async function wait(ms: number): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, ms));
  });
}

/** Click a control by its accessible name. */
async function press(label: string): Promise<void> {
  const control = [
    ...document.body.querySelectorAll<HTMLButtonElement>('button'),
  ].find(
    (button) =>
      button.getAttribute('aria-label') === label ||
      button.textContent?.trim() === label,
  );
  if (control === undefined) {
    throw new Error(`no control named ${label}`);
  }
  await act(async () => {
    control.click();
  });
}

/** Add a node the keyboard way: its palette tile, then "Add to canvas". */
async function addFromPalette(tile: string): Promise<void> {
  const control = [
    ...document.body.querySelectorAll<HTMLButtonElement>('button'),
  ].find((button) => button.textContent?.includes(tile));
  if (control === undefined) {
    throw new Error(`no palette tile ${tile}`);
  }
  await act(async () => {
    control.click();
  });
  await press('Add to canvas');
}

/** Pick a row of the builder's overflow menu. */
async function menuRow(label: string): Promise<void> {
  await press('Team actions');
  const row = [
    ...document.body.querySelectorAll<HTMLElement>('[role="option"]'),
  ].find((option) => option.textContent?.trim() === label);
  if (row === undefined) {
    throw new Error(`no menu row ${label}`);
  }
  await act(async () => {
    row.click();
  });
}

