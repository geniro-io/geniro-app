// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { PUBLISHED_IDENTITIES } from '../__tests__/agent-identities';
import { AgentIdentityContext } from '../agent-identity';
import type { AgentIdentityCapability, TeamAgentNode } from '../autogenerated';

// The canvas card renders inside the shared NodeCard shell (React Flow store
// hooks); stub it to a plain wrapper so this spec exercises only the agent
// header — the approval chip in particular.
vi.mock('./node-card', () => ({
  NodeCard: ({
    children,
    className,
  }: {
    children: React.ReactNode;
    className?: string;
  }) => (
    <div data-testid="node-card" className={className}>
      {children}
    </div>
  ),
}));
vi.mock('./agent-avatar', () => ({
  AgentAvatar: () => <span data-testid="avatar" />,
}));

import { AgentNode } from './agent-node';
import { GraphPreviewContext } from './graph-preview-context';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function renderNode(
  approval: TeamAgentNode['approval'],
  patch: Partial<TeamAgentNode> = {},
  /** Default [] mirrors `AgentIdentityContext`'s own default — no Provider. */
  identities: readonly AgentIdentityCapability[] = [],
  /** Drawn inside a proposal's read-only preview rather than the canvas. */
  inPreview = false,
): HTMLDivElement {
  const node: TeamAgentNode = {
    id: 'a1',
    kind: 'agent',
    agent: 'claude',
    approval,
    ...patch,
  };
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  // Only `data.node` and `selected` are read; the rest of NodeProps is cast.
  const props = {
    id: 'a1',
    data: { node },
    selected: false,
  } as unknown as React.ComponentProps<typeof AgentNode>;
  act(() => {
    root!.render(
      <AgentIdentityContext.Provider value={identities}>
        <GraphPreviewContext.Provider
          value={inPreview ? { marks: new Map() } : null}>
          <AgentNode {...props} />
        </GraphPreviewContext.Provider>
      </AgentIdentityContext.Provider>,
    );
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

describe('AgentNode in a proposal preview', () => {
  const unaskedChip = (el: HTMLElement): Element | null =>
    [...el.querySelectorAll('[data-slot="badge"]')].find(
      (badge) => badge.textContent === 'Runs without asking',
    ) ?? null;

  it('names and rings an agent that runs tools without asking', () => {
    const el = renderNode('auto', {}, [], true);
    expect(unaskedChip(el)).not.toBeNull();
    expect(el.querySelector('[data-testid="node-card"]')?.className).toContain(
      'ring-warning/40',
    );
  });

  it('names one whose pool member runs unasked, though the node itself asks', () => {
    const el = renderNode(
      'ask',
      { pool: [{ agent: 'codex', approval: 'auto' }] },
      [],
      true,
    );
    expect(unaskedChip(el)).not.toBeNull();
  });

  it('leaves an agent that asks unmarked, and the canvas without the chip', () => {
    expect(unaskedChip(renderNode('ask', {}, [], true))).toBeNull();
    act(() => root?.unmount());
    expect(unaskedChip(renderNode('auto'))).toBeNull();
  });
});

describe('AgentNode approval chip', () => {
  it('shows no approval chip for an auto node', () => {
    const el = renderNode('auto');
    expect(
      el.querySelector('[aria-label="Asks before tool calls"]'),
    ).toBeNull();
    expect(
      el.querySelector('[aria-label="Auto-approves edits, asks for the rest"]'),
    ).toBeNull();
  });

  it('shows the ask chip for an ask node', () => {
    const el = renderNode('ask');
    expect(
      el.querySelector('[aria-label="Asks before tool calls"]'),
    ).not.toBeNull();
  });

  it('shows a distinct chip for the widened acceptEdits node — not indistinguishable from auto', () => {
    const el = renderNode('acceptEdits');
    expect(
      el.querySelector('[aria-label="Auto-approves edits, asks for the rest"]'),
    ).not.toBeNull();
  });
});

describe('AgentNode pool label', () => {
  it('names the node’s own CLI and counts the other members in one label', () => {
    const el = renderNode('auto', { pool: [{ agent: 'codex' }] });
    const label = el.querySelector('[data-slot="agent-pool-label"]')!;
    expect(label.querySelectorAll('[data-slot="badge"]')).toHaveLength(1);
    expect(
      label.querySelector('[data-slot="agent-pool-extra"]')?.textContent,
    ).toBe('+1');
    expect(el.textContent).not.toContain('pool of');
  });

  it('shows the plain CLI badge with no count for a node without a pool', () => {
    const el = renderNode('auto');
    const label = el.querySelector('[data-slot="agent-pool-label"]')!;
    expect(label.querySelector('[data-slot="agent-pool-extra"]')).toBeNull();
    expect(label.querySelector('button')).toBeNull();
  });
});

describe('AgentNode blurb', () => {
  it('prefers the description — it is written to say what the agent does', () => {
    const el = renderNode('auto', {
      description: 'Reviews a diff.',
      role: 'You are the Reviewer. Run the review skill…',
    });
    expect(el.textContent).toContain('Reviews a diff.');
    expect(el.textContent).not.toContain('You are the Reviewer.');
  });

  it('falls back to the role so a description-less node is not blank', () => {
    const el = renderNode('auto', { role: 'You are the Reviewer.' });
    expect(el.textContent).toContain('You are the Reviewer.');
  });

  it('shows no blurb when the node has neither', () => {
    expect(renderNode('auto').querySelector('p')).toBeNull();
  });
});

describe('AgentNode agent badge', () => {
  /** The badge naming the node's agent — first in the row, ahead of the model's. */
  const agentBadge = (el: HTMLElement): Element =>
    el.querySelector('[data-slot="badge"]')!;

  it.each([
    { agent: 'claude', name: 'Claude', glyph: 'lucide-bot' },
    { agent: 'cursor-agent', name: 'Cursor', glyph: 'lucide-square-terminal' },
    { agent: 'codex', name: 'Codex', glyph: 'lucide-code' },
  ] as const)(
    'names a $agent node by its published short name and glyph, not by its binary',
    ({ agent, name, glyph }) => {
      const badge = agentBadge(
        renderNode('auto', { agent }, PUBLISHED_IDENTITIES),
      );

      expect(badge.textContent).toBe(name);
      expect(badge.querySelector(`svg.${glyph}`)).not.toBeNull();
    },
  );

  it('falls back to the kind and the generic glyph before identities have loaded', () => {
    const badge = agentBadge(renderNode('auto', { agent: 'cursor-agent' }));

    expect(badge.textContent).toBe('cursor-agent');
    expect(badge.querySelector('svg.lucide-bot')).not.toBeNull();
  });
});
