import type { EdgeProps } from '@xyflow/react';
import type { ComponentType } from 'react';

import type { EdgeKind } from '../autogenerated';
import { AgentNode } from './agent-node';
import { CallEdge, DataEdge, InstructionEdge } from './graph-edge';
import { InstructionNode } from './instruction-node';
import { TriggerNode } from './trigger-node';

/**
 * The node and wire components a team graph is drawn with — the builder's
 * canvas and a proposal's read-only preview alike, so the two cannot draw one
 * graph two ways. Module-level, so React Flow sees stable identities.
 */
export const NODE_TYPES = {
  agent: AgentNode,
  trigger: TriggerNode,
  instruction: InstructionNode,
};
// EVERY kind is drawn by `graph-edge.tsx` — data solid and heaviest, the two
// annotation kinds dashed and coloured. Data used to be absent here and take
// React Flow's own default, which is how the wire that orders the run came to
// be the only thing on the canvas nobody had designed.
// Keyed by the whole `EdgeKind` union so a kind added there without a component
// here is a compile error rather than a wire that silently reverts to that
// default.
// `satisfies`, not an annotation: React Flow's own `EdgeTypes` index signature
// is narrower than `ComponentType<EdgeProps>`, so annotating would widen the
// value away from what `<ReactFlow edgeTypes>` accepts. This checks the KEYS
// and leaves the values inferred.
export const EDGE_TYPES = {
  data: DataEdge,
  call: CallEdge,
  instruction: InstructionEdge,
} satisfies Record<EdgeKind, ComponentType<EdgeProps>>;
