import { cva } from 'class-variance-authority';
import { CircleAlert, Plus, ScrollText, Trash2 } from 'lucide-react';

import type { InstructionBlock, TeamMember } from '../autogenerated';
import { ErrorText } from '../components/error-text';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Field } from '../components/field';
import { Button } from '../components/ui/button';
import { Input } from '../components/ui/input';
import { AudiencePick, memberLabels } from './member-pick';
import { audienceOf, type BlockAudience } from './member-schema';
import type { BlockIssue } from './member-validate';

const rowVariants = cva(
  'flex w-full min-w-0 items-center gap-2 rounded-md px-2 py-1.5 text-left outline-none transition-colors focus-visible:ring-[3px] focus-visible:ring-ring/50',
  {
    variants: {
      selected: {
        true: 'bg-accent text-accent-foreground',
        false: 'hover:bg-accent/50',
      },
    },
  },
);

/** Whom a block reaches, in words. */
export function audienceSummary(
  audience: BlockAudience,
  labels: ReadonlyMap<string, string>,
): string {
  if (audience === 'everyone') {
    return 'Everyone';
  }
  if (audience.length === 0) {
    return 'Nobody yet';
  }
  return audience.map((id) => labels.get(id) ?? id).join(', ');
}

/** The team's instruction blocks: press one to edit it. */
export function InstructionBlocksList({
  blocks,
  members,
  selectedId,
  problemIds,
  onSelect,
  onAdd,
}: {
  blocks: readonly InstructionBlock[];
  members: readonly Pick<TeamMember, 'id' | 'name'>[];
  selectedId: string | null;
  problemIds: ReadonlySet<string>;
  onSelect: (blockId: string) => void;
  onAdd: () => void;
}): React.JSX.Element {
  const labels = memberLabels(members);
  return (
    <div className="flex flex-col gap-1">
      {blocks.length === 0 ? (
        <p className="px-2 text-xs text-muted-foreground">
          None — text every member, or some of them, carries on every turn.
        </p>
      ) : (
        <ul
          aria-label="Instruction blocks"
          data-slot="blocks-list"
          className="flex flex-col gap-0.5">
          {blocks.map((block) => (
            <li key={block.id} data-slot="block-row" data-block-id={block.id}>
              <button
                type="button"
                aria-current={block.id === selectedId ? 'true' : undefined}
                className={rowVariants({ selected: block.id === selectedId })}
                onClick={() => onSelect(block.id)}>
                <ScrollText
                  aria-hidden="true"
                  className="size-4 shrink-0 text-muted-foreground"
                />
                <span className="flex min-w-0 flex-1 flex-col">
                  <span className="truncate text-sm font-medium">
                    {block.title.trim() || 'Untitled block'}
                  </span>
                  <span className="truncate text-xs text-muted-foreground">
                    {audienceSummary(audienceOf(block), labels)}
                  </span>
                </span>
                {problemIds.has(block.id) ? (
                  <CircleAlert
                    aria-label="Has a problem"
                    className="size-3.5 shrink-0 text-destructive"
                  />
                ) : null}
              </button>
            </li>
          ))}
        </ul>
      )}
      <Button
        type="button"
        variant="ghost"
        size="sm"
        className="justify-start gap-2 text-muted-foreground"
        onClick={onAdd}>
        <Plus aria-hidden="true" />
        Add instruction block
      </Button>
    </div>
  );
}

/** One instruction block's title, text and audience, edited in place. */
export function InstructionBlockEditor({
  block,
  members,
  issues,
  warnings,
  onChange,
  onRemove,
}: {
  block: InstructionBlock;
  members: readonly Pick<TeamMember, 'id' | 'name'>[];
  issues: readonly BlockIssue[];
  /** Advisory lines about this block (an audience naming no member). */
  warnings: readonly string[];
  onChange: (patch: Partial<Omit<InstructionBlock, 'id'>>) => void;
  onRemove: () => void;
}): React.JSX.Element {
  const at = (field: BlockIssue['field']): BlockIssue[] =>
    issues.filter((issue) => issue.field === field);
  return (
    <div data-slot="block-editor" className="flex flex-col gap-4">
      <div className="flex items-center gap-2">
        <ScrollText
          aria-hidden="true"
          className="size-4 shrink-0 text-muted-foreground"
        />
        <p className="min-w-0 flex-1 truncate text-sm font-semibold">
          {block.title.trim() || 'Untitled block'}
        </p>
        <Button
          type="button"
          variant="ghost"
          size="sm"
          className="gap-1.5 text-muted-foreground hover:text-destructive"
          onClick={onRemove}>
          <Trash2 aria-hidden="true" />
          Remove block
        </Button>
      </div>
      <Field label="Title" htmlFor={`block-${block.id}-title`}>
        <Input
          id={`block-${block.id}-title`}
          value={block.title}
          placeholder="House style"
          aria-invalid={at('title').length > 0 || undefined}
          onChange={(event) => onChange({ title: event.target.value })}
        />
        {at('title').map((issue) => (
          <ErrorText key={issue.message} className="text-xs">
            {issue.message}
          </ErrorText>
        ))}
      </Field>
      <Field
        label="Text"
        htmlFor={`block-${block.id}-text`}
        hint="Carried on every turn of the members it reaches, after your own custom instructions.">
        <ExpandableTextarea
          id={`block-${block.id}-text`}
          title="Text"
          value={block.text}
          rows={6}
          invalid={at('text').length > 0 || undefined}
          placeholder="Prefer short sentences. Cite the files you changed."
          onChange={(text) => onChange({ text })}
        />
        {at('text').map((issue) => (
          <ErrorText key={issue.message} className="text-xs">
            {issue.message}
          </ErrorText>
        ))}
        {block.text.trim() === '' ? (
          <p className="text-xs text-muted-foreground">
            No text yet — the block adds nothing until it has some.
          </p>
        ) : null}
      </Field>
      <Field label="Reaches">
        <AudiencePick
          members={members}
          audience={audienceOf(block)}
          onChange={(audience) => onChange({ audience })}
        />
        {warnings.map((warning) => (
          <p key={warning} className="text-xs text-warning">
            {warning}
          </p>
        ))}
      </Field>
    </div>
  );
}
