import type {
  InstructionSizePart,
  InstructionSizeSource,
  NodeInstructionSize,
} from '../autogenerated';
import { formatTokens } from '../chats/agent-activity';
import { contextCategoryColor } from '../chats/chat-metrics';
import { SegmentBreakdown } from '../components/segment-breakdown';
import { Spinner } from '../components/ui/spinner';
import { formatCount } from '../stats/stats-format';

/** What each part of the block is called on screen. */
const SOURCE_LABEL: Record<InstructionSizeSource, string> = {
  preamble: 'Geniro display preamble',
  backgroundWorkNote: 'Background-work note',
  replyLanguage: 'Reply language',
  customInstructions: 'Your custom instructions',
  projectInstructions: 'Project instructions',
  memoryIndex: 'Memory index',
  taskInstructions: 'Task card instructions',
  teamInstructions: 'Team builder brief',
  instructionBlocks: 'Instruction block',
  stageMap: 'Stage map',
  role: 'Role',
  answeringACall: 'Answering-a-call note',
  callSurface: 'Call block (May call)',
};

/**
 * How much text an agent node's every turn carries before the prompt: the
 * composed instruction block, its total and what it is made of.
 *
 * Every figure is the daemon's (`POST /v1/teams/instruction-sizes`), which
 * measures the block the node's own CLI is handed, so the total is exact and
 * the tokens are an estimate. Nothing here is a limit.
 */
export function InstructionSizeCard({
  size,
  loading,
  error,
  instructionName,
}: {
  /** This node's measurement, or null before one has landed. */
  size: NodeInstructionSize | null;
  /** A measurement is in flight; a shown one stays up meanwhile. */
  loading: boolean;
  /** Why the last measurement failed, when it did. */
  error: string | null;
  /** The name of an instruction node, for its block's row. */
  instructionName: (nodeId: string) => string;
}): React.JSX.Element {
  if (!size) {
    return (
      <p className="flex items-center gap-1.5 text-xs text-muted-foreground">
        {loading ? (
          <>
            <Spinner /> Measuring…
          </>
        ) : (
          (error ?? 'Not measured yet.')
        )}
      </p>
    );
  }
  const labelOf = (part: InstructionSizePart): string =>
    part.source === 'instructionBlocks' && part.instructionNodeId
      ? instructionName(part.instructionNodeId)
      : SOURCE_LABEL[part.source];
  return (
    <div
      data-slot="instruction-size"
      className="flex flex-col gap-2 text-xs"
      aria-busy={loading}>
      <div className="flex items-baseline gap-1.5">
        <span className="text-sm font-medium tabular-nums text-foreground">
          ~{formatTokens(size.approxTokens)} tokens
        </span>
        <span className="tabular-nums text-muted-foreground">
          {formatCount(size.totalChars)} characters
        </span>
        {loading ? <Spinner className="self-center" /> : null}
      </div>
      {size.turn === 'call' ? (
        <p className="text-muted-foreground">
          Measured for a turn answering a call — the only turn this agent runs.
        </p>
      ) : null}
      <SegmentBreakdown
        denominator={size.totalChars}
        segments={size.parts.map((part, index) => ({
          // By position: one instruction node wired twice yields two rows.
          key: `${index}:${part.source}`,
          label: labelOf(part),
          value: part.chars,
          colorClass: contextCategoryColor(index),
          figures: [
            formatCount(part.chars),
            `~${formatTokens(part.approxTokens)}`,
          ],
        }))}
        {...(size.separatorChars > 0
          ? {
              remainder: {
                label: 'Paragraph breaks',
                figures: [formatCount(size.separatorChars), ''],
              },
            }
          : {})}
      />
      {error ? <p className="text-muted-foreground">{error}</p> : null}
    </div>
  );
}
