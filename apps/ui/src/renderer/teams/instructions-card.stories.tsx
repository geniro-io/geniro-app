import type { Meta, StoryObj } from '@storybook/react-vite';
import { useState } from 'react';

import type { InstructionBlock } from '../autogenerated';
import { InstructionsCard } from './instructions-card';

const MEMBERS = [
  { id: 'ada', name: 'Ada' },
  { id: 'grace', name: 'Grace' },
  {
    id: 'linus',
    name: 'Linus',
    avatar: { kind: 'emoji' as const, value: '🐧' },
  },
  { id: 'margaret', name: 'Margaret Hamilton' },
];

const BLOCKS: InstructionBlock[] = [
  {
    id: 'block-1',
    title: 'House rules',
    text: 'Run pnpm full-check before you report done. Never push to main.',
    audience: 'everyone',
  },
  {
    id: 'block-2',
    title: 'Review style',
    text: 'Group findings by severity; quote the line you mean.',
    audience: ['grace', 'linus', 'margaret'],
  },
  {
    id: 'block-3',
    title: 'Release checklist',
    text: 'Tag the release and update the changelog.',
    audience: [],
  },
];

function Stateful({
  initial,
}: {
  initial: InstructionBlock[];
}): React.JSX.Element {
  const [blocks, setBlocks] = useState(initial);
  return (
    <InstructionsCard
      blocks={blocks}
      members={MEMBERS}
      issues={new Map()}
      warnings={new Map()}
      onAdd={() =>
        setBlocks((current) => [
          ...current,
          {
            id: `block-${current.length + 1}`,
            title: '',
            text: '',
            audience: 'everyone',
          },
        ])
      }
      onChange={(id, patch) =>
        setBlocks((current) =>
          current.map((block) =>
            block.id === id ? { ...block, ...patch } : block,
          ),
        )
      }
      onRemove={(id) =>
        setBlocks((current) => current.filter((block) => block.id !== id))
      }
    />
  );
}

const meta = {
  title: 'Teams/InstructionsCard',
  component: InstructionsCard,
  args: {
    blocks: BLOCKS,
    members: MEMBERS,
    issues: new Map(),
    warnings: new Map(),
    onAdd: () => {},
    onChange: () => {},
    onRemove: () => {},
  },
  decorators: [(story) => <div className="w-[720px] p-4">{story()}</div>],
} satisfies Meta<typeof InstructionsCard>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Blocks: Story = { render: () => <Stateful initial={BLOCKS} /> };

export const Empty: Story = { render: () => <Stateful initial={[]} /> };
