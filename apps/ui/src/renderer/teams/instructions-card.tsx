import type {
  InstructionBlock,
  InstructionBlockSize,
  TeamMember,
} from '../autogenerated';
import {
  InstructionBlockCard,
  InstructionBlockList,
} from '../components/instruction-blocks';
import { AudiencePick } from './member-pick';
import { audienceOf } from './member-schema';
import type { BlockIssue } from './member-validate';

type MemberRef = Pick<TeamMember, 'id' | 'name'> &
  Partial<Pick<TeamMember, 'avatar'>>;

function BlockCard({
  block,
  members,
  issues,
  warnings,
  size,
  onChange,
  onRemove,
}: {
  block: InstructionBlock;
  members: readonly MemberRef[];
  issues: readonly BlockIssue[];
  warnings: readonly string[];
  size: InstructionBlockSize | undefined;
  onChange: (patch: Partial<Omit<InstructionBlock, 'id'>>) => void;
  onRemove: () => void;
}): React.JSX.Element {
  return (
    <InstructionBlockCard
      id={block.id}
      title={block.title}
      text={block.text}
      issues={issues}
      size={size}
      sizeTitle={
        size === undefined
          ? undefined
          : `${size.chars.toLocaleString('en-US')} characters, carried by ${size.reaches} ${size.reaches === 1 ? 'member' : 'members'} on every turn`
      }
      headerExtra={
        <div className="flex max-w-[50%] min-w-0 shrink">
          <AudiencePick
            members={members}
            audience={audienceOf(block)}
            onChange={(next) => onChange({ audience: next })}
          />
        </div>
      }
      onTitleChange={(title) => onChange({ title })}
      onTextChange={(text) => onChange({ text })}
      onRemove={onRemove}>
      {warnings.map((warning) => (
        <p key={warning} className="text-sm text-warning">
          {warning}
        </p>
      ))}
    </InstructionBlockCard>
  );
}

/**
 * The team's own instructions: blocks of text, each reaching everyone or the
 * members it names, joined with the project's instructions at run time.
 */
export function InstructionsCard({
  blocks,
  members,
  issues,
  warnings,
  blockSizes = null,
  emptyLabel = 'No team instructions yet.',
  addLabel,
  onAdd,
  onChange,
  onRemove,
}: {
  blocks: readonly InstructionBlock[];
  members: readonly MemberRef[];
  issues: ReadonlyMap<string, readonly BlockIssue[]>;
  /** Advisory lines per block id (an audience naming no member). */
  warnings: ReadonlyMap<string, readonly string[]>;
  /** Each block's measured size, by block id; null before a measurement lands. */
  blockSizes?: ReadonlyMap<string, InstructionBlockSize> | null;
  emptyLabel?: string;
  addLabel?: string;
  onAdd: () => void;
  onChange: (
    blockId: string,
    patch: Partial<Omit<InstructionBlock, 'id'>>,
  ) => void;
  onRemove: (blockId: string) => void;
}): React.JSX.Element {
  return (
    <InstructionBlockList
      empty={blocks.length === 0}
      emptyLabel={emptyLabel}
      {...(addLabel === undefined ? {} : { addLabel })}
      onAdd={onAdd}>
      {blocks.map((block) => (
        <BlockCard
          key={block.id}
          block={block}
          members={members}
          issues={issues.get(block.id) ?? []}
          warnings={warnings.get(block.id) ?? []}
          size={blockSizes?.get(block.id)}
          onChange={(patch) => onChange(block.id, patch)}
          onRemove={() => onRemove(block.id)}
        />
      ))}
    </InstructionBlockList>
  );
}
