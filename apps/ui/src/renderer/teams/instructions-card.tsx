import { ChevronDown, Plus, Trash2 } from 'lucide-react';
import { useState } from 'react';

import type { InstructionBlock, TeamMember } from '../autogenerated';
import { ErrorText } from '../components/error-text';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Button } from '../components/ui/button';
import { Input } from '../components/ui/input';
import { cn } from '../components/ui/utils';
import { AudiencePick, memberLabels } from './member-pick';
import { audienceOf, type BlockAudience } from './member-schema';
import type { BlockIssue } from './member-validate';

type MemberRef = Pick<TeamMember, 'id' | 'name'>;

/** Whom a block reaches, in words. */
export function audienceSummary(
  audience: BlockAudience,
  labels: ReadonlyMap<string, string>,
): string {
  if (audience === 'everyone') {
    return 'Everyone';
  }
  if (audience.length === 0) {
    return 'Nobody yet';
  }
  return audience.map((id) => labels.get(id) ?? id).join(', ');
}

const FLAT_FIELD =
  'rounded-control border-transparent bg-muted/40 shadow-none hover:border-field-border focus-visible:border-field-border';

function BlockCard({
  block,
  members,
  labels,
  issues,
  warnings,
  onChange,
  onRemove,
}: {
  block: InstructionBlock;
  members: readonly MemberRef[];
  labels: ReadonlyMap<string, string>;
  issues: readonly BlockIssue[];
  warnings: readonly string[];
  onChange: (patch: Partial<Omit<InstructionBlock, 'id'>>) => void;
  onRemove: () => void;
}): React.JSX.Element {
  const [reachOpen, setReachOpen] = useState(false);
  const audience = audienceOf(block);
  const at = (field: BlockIssue['field']): BlockIssue[] =>
    issues.filter((issue) => issue.field === field);
  return (
    <li
      data-slot="block-card"
      data-block-id={block.id}
      className="flex flex-col gap-3 rounded-card bg-card p-5 ring-1 ring-border">
      <div className="flex items-center gap-2">
        <Input
          id={`block-${block.id}-title`}
          aria-label="Block title"
          value={block.title}
          placeholder="Untitled block"
          aria-invalid={at('title').length > 0 || undefined}
          className={cn('h-8 flex-1 text-base font-semibold', FLAT_FIELD)}
          onChange={(event) => onChange({ title: event.target.value })}
        />
        <Button
          type="button"
          variant="ghost"
          size="sm"
          aria-expanded={reachOpen}
          className="h-7 max-w-[45%] shrink gap-1 rounded-pill bg-muted px-2.5 text-sm font-normal text-muted-foreground"
          onClick={() => setReachOpen((open) => !open)}>
          <span className="truncate">
            Reaches {audienceSummary(audience, labels)}
          </span>
          <ChevronDown aria-hidden="true" className="size-3.5 shrink-0" />
        </Button>
        <Button
          type="button"
          variant="ghost"
          size="icon"
          aria-label={`Remove block ${block.title.trim() || block.id}`}
          title="Remove block"
          className="size-8 shrink-0 text-muted-foreground hover:bg-destructive/10 hover:text-destructive"
          onClick={onRemove}>
          <Trash2 />
        </Button>
      </div>
      {at('title').map((issue) => (
        <ErrorText key={issue.message} className="text-xs">
          {issue.message}
        </ErrorText>
      ))}
      {reachOpen ? (
        <AudiencePick
          members={members}
          audience={audience}
          onChange={(next) => onChange({ audience: next })}
        />
      ) : null}
      {warnings.map((warning) => (
        <p key={warning} className="text-sm text-warning">
          {warning}
        </p>
      ))}
      <div className="[&_textarea]:border-transparent [&_textarea]:bg-muted/40 [&_textarea]:shadow-none [&_textarea:focus-visible]:border-field-border [&_textarea:hover]:border-field-border">
        <ExpandableTextarea
          id={`block-${block.id}-text`}
          title={block.title.trim() || 'Instruction block'}
          ariaLabel="Block text"
          value={block.text}
          rows={4}
          invalid={at('text').length > 0 || undefined}
          placeholder="Prefer short sentences. Cite the files you changed."
          onChange={(text) => onChange({ text })}
        />
      </div>
      {at('text').map((issue) => (
        <ErrorText key={issue.message} className="text-xs">
          {issue.message}
        </ErrorText>
      ))}
    </li>
  );
}

/**
 * The team's own instructions: blocks of text, each reaching everyone or the
 * members it names, joined with the project's instructions at run time.
 */
export function InstructionsCard({
  blocks,
  members,
  issues,
  warnings,
  onAdd,
  onChange,
  onRemove,
}: {
  blocks: readonly InstructionBlock[];
  members: readonly MemberRef[];
  issues: ReadonlyMap<string, readonly BlockIssue[]>;
  /** Advisory lines per block id (an audience naming no member). */
  warnings: ReadonlyMap<string, readonly string[]>;
  onAdd: () => void;
  onChange: (
    blockId: string,
    patch: Partial<Omit<InstructionBlock, 'id'>>,
  ) => void;
  onRemove: (blockId: string) => void;
}): React.JSX.Element {
  const labels = memberLabels(members);
  return (
    <div data-slot="instructions-card" className="flex flex-col gap-3">
      {blocks.length === 0 ? (
        <p className="text-sm text-muted-foreground">
          No team instructions yet.
        </p>
      ) : (
        <ul className="flex flex-col gap-3">
          {blocks.map((block) => (
            <BlockCard
              key={block.id}
              block={block}
              members={members}
              labels={labels}
              issues={issues.get(block.id) ?? []}
              warnings={warnings.get(block.id) ?? []}
              onChange={(patch) => onChange(block.id, patch)}
              onRemove={() => onRemove(block.id)}
            />
          ))}
        </ul>
      )}
      <Button
        type="button"
        variant="ghost"
        className="h-8 self-start gap-2 rounded-control text-muted-foreground"
        onClick={onAdd}>
        <Plus aria-hidden="true" />
        Add instruction block
      </Button>
    </div>
  );
}
