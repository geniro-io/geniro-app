// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type {
  AgentMcpListingDto as AgentMcpListing,
  AgentMcpServer,
} from '../autogenerated';
import {
  ALLOW_LIST_NOTE,
  McpAllowListControl,
  type McpAllowListControlProps,
} from './mcp-allow-list-control';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

function row(
  name: string,
  patch: Partial<AgentMcpServer> = {},
): AgentMcpServer {
  return {
    name,
    target: null,
    transport: 'stdio',
    status: 'connected',
    detail: null,
    scope: 'user',
    shadowsUser: false,
    disabled: false,
    toggleUnavailableReason: null,
    signInUnavailableReason: null,
    approveUnavailableReason: null,
    turnToggleUnavailableReason: null,
    ...patch,
  };
}

const LISTING: AgentMcpListing = {
  servers: [row('codegraph'), row('linear'), row('claude.ai Gmail')],
  unavailableReason: null,
  pending: false,
  plugins: [],
  interactiveOnlyNote: null,
};

let root: Root | null = null;
let host: HTMLElement | null = null;

afterEach(() => {
  act(() => root?.unmount());
  host?.remove();
  root = null;
  host = null;
});

function render(props: Partial<McpAllowListControlProps> = {}) {
  const onChange = vi.fn();
  host = document.createElement('div');
  document.body.append(host);
  root = createRoot(host);
  act(() =>
    root!.render(
      <McpAllowListControl
        ariaLabel="Servers this member loads"
        allowed={undefined}
        listing={LISTING}
        disabled={undefined}
        capability={{
          unavailableReason: null,
          accountConnectorPrefix: 'claude.ai ',
        }}
        onChange={onChange}
        {...props}
      />,
    ),
  );
  return onChange;
}

const byText = (text: string): HTMLButtonElement | undefined =>
  [...document.body.querySelectorAll<HTMLButtonElement>('button')].find(
    (button) => button.textContent?.trim() === text,
  );
const box = (name: string): HTMLElement | null =>
  document.body.querySelector(`[aria-label="${name} in the list"]`);
const click = (el: HTMLElement | null | undefined): void =>
  act(() => el!.click());

describe('McpAllowListControl', () => {
  it('seeds the list with the servers that load now when "Only picked" is chosen', () => {
    const onChange = render({ disabled: ['linear'] });
    click(byText('Only picked'));
    expect(onChange).toHaveBeenCalledWith(['codegraph', 'claude.ai Gmail']);
  });

  it('removes the list on "All"', () => {
    const onChange = render({ allowed: ['codegraph'] });
    click(byText('All'));
    expect(onChange).toHaveBeenCalledWith(undefined);
  });

  it('draws no rows and no note while every server loads', () => {
    render();
    expect(box('codegraph')).toBeNull();
    expect(document.body.textContent).not.toContain(ALLOW_LIST_NOTE);
  });

  it('ticks a row on and off, keeping the rest of the list', () => {
    const onChange = render({ allowed: ['codegraph'] });
    expect(document.body.textContent).toContain(ALLOW_LIST_NOTE);
    expect(box('codegraph')?.getAttribute('aria-checked')).toBe('true');
    expect(box('linear')?.getAttribute('aria-checked')).toBe('false');
    click(box('linear'));
    expect(onChange).toHaveBeenLastCalledWith(['codegraph', 'linear']);
    click(box('codegraph'));
    expect(onChange).toHaveBeenLastCalledWith([]);
  });

  it('marks account connectors and leaves them all out with one press', () => {
    const onChange = render({
      allowed: ['codegraph', 'claude.ai Gmail', 'claude.ai Slack'],
    });
    expect(box('claude.ai Gmail')?.textContent).toContain(
      'claude.ai Gmail account connector',
    );
    click(byText('Leave out account connectors'));
    expect(onChange).toHaveBeenCalledWith(['codegraph']);
  });

  it('offers no connector action for a CLI without a connector prefix', () => {
    render({
      allowed: ['codegraph'],
      capability: { unavailableReason: null, accountConnectorPrefix: null },
    });
    expect(byText('Leave out account connectors')).toBeUndefined();
  });

  it('keeps a listed-no-more name as a row marked not found, so it can be removed', () => {
    const onChange = render({ allowed: ['codegraph', 'gone'] });
    expect(box('gone')?.textContent).toContain('gone not found');
    click(box('gone'));
    expect(onChange).toHaveBeenCalledWith(['codegraph']);
  });

  it('does not call a name missing while the listing is still being read', () => {
    render({
      allowed: ['codegraph'],
      listing: { ...LISTING, servers: [], pending: true },
    });
    expect(box('codegraph')?.textContent).not.toContain('not found');
  });

  it('is disabled with the capability’s reason when the CLI cannot apply a list', () => {
    const onChange = render({
      capability: {
        unavailableReason: 'This CLI cannot limit its servers.',
        accountConnectorPrefix: null,
      },
    });
    expect(document.body.textContent).toContain(
      'This CLI cannot limit its servers.',
    );
    expect(byText('Only picked')?.disabled).toBe(true);
    click(byText('Only picked'));
    expect(onChange).not.toHaveBeenCalled();
  });

  it('cannot start a list before the servers are read, which would write an empty one', () => {
    const onChange = render({ listing: undefined });
    expect(byText('Only picked')?.disabled).toBe(true);
    click(byText('Only picked'));
    expect(onChange).not.toHaveBeenCalled();
  });
});
