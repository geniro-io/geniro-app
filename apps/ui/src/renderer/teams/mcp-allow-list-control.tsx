import type {
  AgentMcpAllowListCapability,
  AgentMcpListingDto as AgentMcpListing,
} from '../autogenerated';
import { Button } from '../components/ui/button';
import { Checkbox } from '../components/ui/checkbox';
import { SegmentedControl } from '../components/ui/segmented-control';
import {
  isAccountConnector,
  loadingServerNames,
  nextMcpAllowed,
  withoutAccountConnectors,
} from './node-mcp-switches';
import { type RowScope, ScopedSettingRow } from './overridable-row';

type Mode = 'all' | 'only';

const MODES: readonly { id: Mode; label: string }[] = [
  { id: 'all', label: 'All' },
  { id: 'only', label: 'Only picked' },
];

export const ALLOW_LIST_NOTE =
  'Servers not on the list don’t load in this member’s turns, including account connectors added later. Geniro’s own server always loads.';

export interface McpAllowListControlProps {
  ariaLabel: string;
  allowed: readonly string[] | undefined;
  listing: AgentMcpListing | undefined;
  disabled: readonly string[] | undefined;
  capability: Pick<
    AgentMcpAllowListCapability,
    'unavailableReason' | 'accountConnectorPrefix'
  >;
  scope?: RowScope | null;
  onChange: (next: string[] | undefined) => void;
}

/**
 * A member's MCP allow list: every server loads, or only the ones ticked.
 * Choosing "only" starts from the servers that load now, so nothing changes
 * until one is unticked.
 */
export function McpAllowListControl({
  ariaLabel,
  allowed,
  listing,
  disabled,
  capability,
  scope = null,
  onChange,
}: McpAllowListControlProps): React.JSX.Element {
  const ready =
    listing !== undefined &&
    !listing.pending &&
    listing.unavailableReason === null;
  const mode: Mode = allowed === undefined ? 'all' : 'only';
  const prefix = capability.accountConnectorPrefix;
  const listed = ready ? listing.servers : [];
  const listedNames = new Set(listed.map((row) => row.name));
  const offByMember = new Set(disabled ?? []);
  const picked = allowed ?? [];
  const names = [
    ...listed.map((row) => row.name),
    ...picked.filter((name) => !listedNames.has(name)),
  ];
  const connectors = names.filter((name) => isAccountConnector(name, prefix));

  return (
    <>
      <ScopedSettingRow label="Loads" scope={scope}>
        <SegmentedControl
          ariaLabel={ariaLabel}
          size="sm"
          options={MODES}
          value={mode}
          disabled={
            capability.unavailableReason !== null || (mode === 'all' && !ready)
          }
          onSelect={(next) => {
            if (next === mode) {
              return;
            }
            onChange(
              next === 'all'
                ? undefined
                : loadingServerNames(listing, disabled),
            );
          }}
        />
      </ScopedSettingRow>
      {capability.unavailableReason !== null ? (
        <p
          data-slot="mcp-allow-list-unavailable"
          className="px-3 pb-2 text-xs text-muted-foreground">
          {capability.unavailableReason}
        </p>
      ) : null}
      {mode === 'only' ? (
        <div
          data-slot="mcp-allow-list"
          className="flex flex-col gap-2 px-3 pb-3">
          <p className="text-xs text-muted-foreground">{ALLOW_LIST_NOTE}</p>
          <div
            role="group"
            aria-label="Servers in the list"
            className="flex flex-col gap-1.5">
            {names.map((name) => {
              const missing = ready && !listedNames.has(name);
              return (
                <Checkbox
                  key={name}
                  aria-label={`${name} in the list`}
                  checked={picked.includes(name)}
                  onCheckedChange={(on) =>
                    onChange(nextMcpAllowed(picked, name, on))
                  }
                  label={
                    <span className="inline-flex flex-wrap items-baseline gap-x-1.5 [overflow-wrap:anywhere]">
                      <span>{name}</span>
                      {isAccountConnector(name, prefix) ? (
                        <>
                          {' '}
                          <span className="text-xs text-muted-foreground">
                            account connector
                          </span>
                        </>
                      ) : null}
                      {missing ? (
                        <>
                          {' '}
                          <span className="text-xs text-warning">
                            not found
                          </span>
                        </>
                      ) : null}
                      {offByMember.has(name) ? (
                        <>
                          {' '}
                          <span className="text-xs text-muted-foreground">
                            switched off
                          </span>
                        </>
                      ) : null}
                    </span>
                  }
                />
              );
            })}
          </div>
          {connectors.length > 0 ? (
            <Button
              type="button"
              variant="outline"
              size="sm"
              className="self-start"
              disabled={!connectors.some((name) => picked.includes(name))}
              onClick={() =>
                onChange(withoutAccountConnectors(picked, prefix))
              }>
              Leave out account connectors
            </Button>
          ) : null}
        </div>
      ) : null}
    </>
  );
}
