import { Plus, Zap } from 'lucide-react';

import type { TeamMember } from '../autogenerated';
import { MemberAvatar } from '../components/member-avatar';
import { NavListItem } from '../components/nav-list-item';
import { StatusDot, type StatusTone } from '../components/status-dot';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import { LIFT_CARD_CLASS } from './team-card';

/**
 * A member's setup health. `unchecked` covers everything past the editor's own
 * refusals until the daemon checks it.
 */
export type MemberHealth = 'ready' | 'warning' | 'error' | 'unchecked';

export const HEALTH_WORD: Record<MemberHealth, string> = {
  ready: 'ready',
  warning: 'needs setup',
  error: 'cannot run',
  unchecked: 'not checked',
};

const HEALTH_TONE: Record<MemberHealth, StatusTone> = {
  ready: 'ok',
  warning: 'warn',
  error: 'bad',
  unchecked: 'unknown',
};

export interface MemberCardFix {
  label: string;
  run: () => void;
}

const CHIP_CLASS =
  'inline-flex h-6 max-w-full items-center truncate rounded-pill bg-muted px-2.5 text-sm text-muted-foreground';

/**
 * One member as a profile: their face with a health dot, name, the role the
 * others see, their character, what they run on and the stages they own. The
 * whole card opens the member; a fix button, when there is a problem, sits
 * outside that activation area.
 */
export function MemberCard({
  member,
  agentLabel,
  health,
  reason = null,
  fix,
  stageTitles,
  handlesFirstMessage,
  selected,
  onOpen,
}: {
  member: TeamMember;
  agentLabel: string;
  health: MemberHealth;
  /** Why the member is not ready, in words; null when nothing is wrong. */
  reason?: string | null;
  fix?: MemberCardFix;
  stageTitles: readonly string[];
  handlesFirstMessage: boolean;
  selected: boolean;
  onOpen: () => void;
}): React.JSX.Element {
  const name = member.name.trim() || 'Unnamed member';
  const role = member.role?.trim();
  const label = [
    `Open ${name}`,
    ...(role ? [role.split('\n')[0]!] : []),
    ...(health === 'unchecked' ? [] : [HEALTH_WORD[health]]),
  ].join(', ');
  return (
    <NavListItem
      active={false}
      activateLabel={label}
      onActivate={onOpen}
      className={cn(
        'group p-5 hover:bg-card has-[>button:focus-visible]:ring-2 has-[>button:focus-visible]:ring-ring has-[>button:focus-visible]:ring-offset-2 has-[>button:focus-visible]:ring-offset-background',
        LIFT_CARD_CLASS,
        selected && 'ring-2 ring-primary hover:ring-primary',
      )}>
      <div className="flex flex-col gap-4">
        <div
          data-slot="member-card"
          data-member-id={member.id}
          data-selected={selected || undefined}
          className="flex items-start gap-4">
          <span className="relative shrink-0">
            <MemberAvatar
              name={name}
              avatar={member.avatar}
              colorKey={member.id}
              size={64}
            />
            <StatusDot
              tone={HEALTH_TONE[health]}
              label={HEALTH_WORD[health]}
              className="absolute right-0.5 bottom-0.5 size-3 ring-2 ring-card"
            />
          </span>
          <div className="flex min-w-0 flex-1 flex-col gap-1">
            <p className="flex min-w-0 items-center gap-1.5">
              <span className="truncate text-base font-semibold">{name}</span>
              {handlesFirstMessage ? (
                <Zap
                  role="img"
                  aria-label="handles the first message"
                  className="size-3.5 shrink-0 text-primary"
                />
              ) : null}
            </p>
            <p
              className={cn(
                'line-clamp-2 text-sm',
                role ? 'text-foreground/80' : 'text-muted-foreground',
              )}>
              {role || 'No role yet — the others will not know what to ask.'}
            </p>
          </div>
        </div>
        {member.character?.trim() ? (
          <p className="line-clamp-2 text-sm text-muted-foreground italic">
            “{member.character.trim()}”
          </p>
        ) : null}
        <div className="flex flex-wrap gap-1.5">
          <span className={CHIP_CLASS}>{agentLabel}</span>
          <span className={CHIP_CLASS}>{member.model ?? 'default model'}</span>
          {stageTitles.map((title) => (
            <span
              key={title}
              data-slot="member-stage-chip"
              className={cn(CHIP_CLASS, 'bg-primary/10 text-primary')}>
              {title}
            </span>
          ))}
        </div>
        {reason === null ? null : (
          <div className="flex items-center gap-2">
            <p
              className={cn(
                'min-w-0 flex-1 text-sm',
                health === 'error' ? 'text-destructive' : 'text-warning',
              )}>
              {reason}
            </p>
            {fix ? (
              <Button
                type="button"
                size="sm"
                variant="outline"
                className="h-7 shrink-0 rounded-control px-2.5 text-sm"
                onClick={fix.run}>
                {fix.label}
              </Button>
            ) : null}
          </div>
        )}
      </div>
    </NavListItem>
  );
}

/** The dashed card that adds a member. */
export function AddMemberCard({
  onAdd,
}: {
  onAdd: () => void;
}): React.JSX.Element {
  return (
    <li className="list-none">
      <button
        type="button"
        className="flex size-full min-h-40 flex-col items-center justify-center gap-2 rounded-card border border-dashed border-field-border text-base font-medium text-muted-foreground transition-colors outline-none hover:border-primary/60 hover:text-foreground focus-visible:ring-2 focus-visible:ring-ring active:scale-[.97] motion-reduce:active:scale-100"
        onClick={onAdd}>
        <Plus aria-hidden="true" className="size-5" />
        Add member
      </button>
    </li>
  );
}
