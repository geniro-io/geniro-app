import { cva } from 'class-variance-authority';
import { CircleAlert, Plus, TriangleAlert, Zap } from 'lucide-react';

import type { TeamMember } from '../autogenerated';
import { NAV_CARD_CLASS } from '../components/card-hover';
import { HoverPopover } from '../components/hover-popover';
import { MemberAvatar } from '../components/member-avatar';
import { NavListItem } from '../components/nav-list-item';
import { StatusDot, type StatusTone } from '../components/status-dot';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import type { HeldProblem } from './held-problems';
import type { MemberStatus } from './member-problems';

export const HEALTH_WORD: Record<MemberStatus, string> = {
  ready: 'ready',
  warning: 'needs setup',
  error: 'cannot run',
  checking: 'checking…',
  unchecked: 'not checked',
};

const HEALTH_TONE: Record<MemberStatus, StatusTone> = {
  ready: 'ok',
  warning: 'warn',
  error: 'bad',
  checking: 'unknown',
  unchecked: 'unknown',
};

const problemsBadgeVariants = cva(
  'flex size-7 items-center justify-center rounded-pill transition-colors',
  {
    variants: {
      level: {
        error: 'bg-destructive/15 text-destructive hover:bg-destructive/25',
        warning: 'bg-warning/15 text-warning hover:bg-warning/25',
      },
    },
  },
);

const problemIconVariants = cva('mt-0.5 size-4 shrink-0', {
  variants: {
    level: { error: 'text-destructive', warning: 'text-warning' },
  },
});

/**
 * The "!" in a member card's corner: what keeps the member from running well,
 * read on hover or focus, each problem with its fix.
 */
function MemberProblemsBadge({
  name,
  problems,
}: {
  name: string;
  problems: readonly HeldProblem[];
}): React.JSX.Element {
  const level = problems.some((problem) => problem.level === 'error')
    ? 'error'
    : 'warning';
  const heading =
    level === 'error' ? `${name} cannot run` : `${name} needs setup`;
  return (
    <HoverPopover
      slot="member-problems"
      label={`${heading}: ${problems.map((problem) => problem.message).join(' ')}`}
      panelLabel={heading}
      side="bottom"
      align="end"
      triggerClassName="rounded-pill"
      panelClassName="w-80 p-3"
      trigger={
        <span className={problemsBadgeVariants({ level })}>
          <CircleAlert aria-hidden="true" className="size-4" />
        </span>
      }>
      {(close) => (
        <div className="flex flex-col gap-2">
          <p className="m-0 text-sm font-medium">{heading}</p>
          <ul className="m-0 flex list-none flex-col gap-2 p-0">
            {problems.map((problem) => (
              <li
                key={problem.key}
                data-slot="member-problem"
                className="flex items-start gap-2">
                <TriangleAlert
                  aria-hidden="true"
                  className={problemIconVariants({ level: problem.level })}
                />
                <div className="flex min-w-0 flex-1 flex-col items-start gap-1.5">
                  <p className="m-0 text-sm">{problem.message}</p>
                  {problem.fix ? (
                    <Button
                      type="button"
                      size="sm"
                      variant="outline"
                      className="h-7 rounded-control px-2.5 text-sm"
                      onClick={() => {
                        close();
                        problem.fix?.run();
                      }}>
                      {problem.fix.label}
                    </Button>
                  ) : null}
                </div>
              </li>
            ))}
          </ul>
        </div>
      )}
    </HoverPopover>
  );
}

const CHIP_CLASS =
  'inline-flex h-6 max-w-full items-center truncate rounded-pill bg-muted px-2.5 text-sm text-muted-foreground';

/**
 * One member as a profile: their face with a health dot, name, the role the
 * others see, their character, what they run on and the stages they own. The
 * whole card opens the member; what needs fixing is a "!" in the corner,
 * outside that activation area.
 */
export function MemberCard({
  member,
  agentLabel,
  health,
  problems = [],
  stageTitles,
  handlesFirstMessage,
  selected,
  overlayBadges,
  onOpen,
}: {
  member: TeamMember;
  /** In a project's scope: what that project's overlay changes about this member. */
  overlayBadges?: { overrides: number; notes: boolean };
  agentLabel: string;
  health: MemberStatus;
  /** What keeps the member from running well, each with its fix. */
  problems?: readonly HeldProblem[];
  stageTitles: readonly string[];
  handlesFirstMessage: boolean;
  selected: boolean;
  onOpen: () => void;
}): React.JSX.Element {
  const name = member.name.trim() || 'Unnamed member';
  const role = member.role?.trim();
  const label = [
    `Open ${name}`,
    ...(role ? [role.split('\n')[0]!] : []),
    ...(health === 'unchecked' ? [] : [HEALTH_WORD[health]]),
  ].join(', ');
  return (
    <NavListItem
      active={false}
      activateLabel={label}
      onActivate={onOpen}
      className={cn(
        'group h-full p-5',
        NAV_CARD_CLASS,
        selected && 'ring-2 ring-primary',
      )}
      contentClassName="flex-1">
      {problems.length === 0 ? null : (
        <span className="absolute -top-2 -right-2">
          <MemberProblemsBadge name={name} problems={problems} />
        </span>
      )}
      <div className="flex h-full flex-col gap-3">
        <div
          data-slot="member-card"
          data-member-id={member.id}
          data-selected={selected || undefined}
          className="flex items-start gap-4">
          <span className="relative shrink-0">
            <MemberAvatar
              name={name}
              avatar={member.avatar}
              colorKey={member.id}
              size={64}
            />
            <StatusDot
              tone={HEALTH_TONE[health]}
              label={HEALTH_WORD[health]}
              className={cn(
                'absolute right-0.5 bottom-0.5 size-3 ring-2 ring-card',
                health === 'checking' &&
                  'animate-pulse motion-reduce:animate-none',
              )}
            />
          </span>
          <div
            className={cn(
              'flex min-w-0 flex-1 flex-col gap-1',
              problems.length > 0 && 'pr-7',
            )}>
            <p className="flex min-w-0 items-center gap-1.5">
              <span className="truncate text-base font-semibold">{name}</span>
              {handlesFirstMessage ? (
                <Zap
                  role="img"
                  aria-label="handles the first message"
                  className="size-3.5 shrink-0 text-primary"
                />
              ) : null}
            </p>
            <p
              className={cn(
                'line-clamp-2 min-h-[2lh] text-sm',
                role ? 'text-foreground/80' : 'text-muted-foreground',
              )}>
              {role || 'No role yet — the others will not know what to ask.'}
            </p>
          </div>
        </div>
        <div data-slot="member-setup" className="flex flex-wrap gap-1.5">
          <span className={CHIP_CLASS}>{agentLabel}</span>
          <span className={CHIP_CLASS}>{member.model ?? 'default model'}</span>
          {overlayBadges === undefined ||
          overlayBadges.overrides === 0 ? null : (
            <span
              data-slot="member-overrides"
              className={cn(CHIP_CLASS, 'bg-override/10 text-override')}>
              {overlayBadges.overrides} override
              {overlayBadges.overrides === 1 ? '' : 's'}
            </span>
          )}
          {overlayBadges?.notes ? (
            <span
              data-slot="member-project-notes"
              className={cn(CHIP_CLASS, 'bg-override/10 text-override')}>
              project notes
            </span>
          ) : null}
        </div>
        {stageTitles.length === 0 ? null : (
          <div data-slot="member-stages" className="flex flex-wrap gap-1.5">
            {stageTitles.map((title) => (
              <span
                key={title}
                data-slot="member-stage-chip"
                className={cn(CHIP_CLASS, 'bg-primary/10 text-primary')}>
                {title}
              </span>
            ))}
          </div>
        )}
        {member.character?.trim() ? (
          <p className="mt-auto line-clamp-2 text-sm text-muted-foreground italic">
            “{member.character.trim()}”
          </p>
        ) : null}
      </div>
    </NavListItem>
  );
}

/** The dashed card that adds a member. */
export function AddMemberCard({
  onAdd,
}: {
  onAdd: () => void;
}): React.JSX.Element {
  return (
    <li className="list-none">
      <button
        type="button"
        className="flex size-full min-h-40 flex-col items-center justify-center gap-2 rounded-card border border-dashed border-field-border text-base font-medium text-muted-foreground transition-colors outline-none hover:border-primary/60 hover:text-foreground focus-visible:ring-2 focus-visible:ring-ring active:scale-[.97] motion-reduce:active:scale-100"
        onClick={onAdd}>
        <Plus aria-hidden="true" className="size-5" />
        Add member
      </button>
    </li>
  );
}
