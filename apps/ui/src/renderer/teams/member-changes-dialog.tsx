import { ArrowDown, ArrowRight, ArrowUp } from 'lucide-react';

import type { MemberChange } from '../autogenerated';
import { formatUsd } from '../chats/agent-activity';
import { ClampedText } from '../components/clamped-text';
import { Badge } from '../components/ui/badge';
import { Dialog } from '../components/ui/dialog';
import { cn } from '../components/ui/utils';
import { formatDuration, formatPercent } from '../stats/stats-format';
import { formatUpdated } from './format-updated';

type Effect = MemberChange['effect'];
type MovedFigure = MemberChange['moved'][number];

const EFFECT_BADGE: Record<
  Effect,
  { label: string; variant: 'success' | 'destructive' | 'secondary' | 'muted' }
> = {
  better: { label: 'Better', variant: 'success' },
  worse: { label: 'Worse', variant: 'destructive' },
  mixed: { label: 'Mixed', variant: 'secondary' },
  'no-change': { label: 'No change', variant: 'muted' },
  'too-few-runs': { label: 'Too few runs', variant: 'muted' },
};

const EFFECT_ORDER: readonly Effect[] = [
  'better',
  'worse',
  'mixed',
  'no-change',
  'too-few-runs',
];

const KIND_LABEL: Record<MemberChange['kinds'][number], string> = {
  added: 'added',
  removed: 'removed',
  role: 'role',
  instructions: 'instructions',
  character: 'character',
  agent: 'agent',
  model: 'model',
  effort: 'effort',
  approval: 'approval',
  pool: 'pool',
  tools: 'tools',
  stages: 'stages',
  blocks: 'team instructions',
};

const SOURCE_LABEL: Record<string, string> = {
  analysis: 'by an analysis',
  builder: 'in the builder chat',
  chat: 'from a chat',
  restore: 'by a restore',
  migration: 'by a migration',
};

const EFFECT_TITLE =
  'Measured by Geniro over the runs of either version: a figure counts once it moved by a tenth or more';

function versionLabel(ref: MemberChange['from']): string {
  return ref.number === null ? 'unnumbered' : `v${ref.number}`;
}

function movedValue(unit: MovedFigure['unit'], value: number): string {
  if (unit === 'usd') {
    return formatUsd(value);
  }
  if (unit === 'ms') {
    return formatDuration(value);
  }
  return formatPercent(value * 100);
}

/** Where a figure stood on either side of the change. */
export function movedSpan(moved: MovedFigure): string {
  return `${movedValue(moved.unit, moved.from)} → ${movedValue(moved.unit, moved.to)}`;
}

/**
 * How far it moved: percentage points for a share, else the change relative to
 * where it stood, which its rounded ends can hide (`$0.01 → $0.02` for a tenth).
 */
export function movedDelta(moved: MovedFigure): string | null {
  const sign = moved.to > moved.from ? '+' : '−';
  if (moved.unit === 'share') {
    return `${sign}${Math.round(Math.abs(moved.to - moved.from) * 100)} pts`;
  }
  if (moved.from === 0) {
    return null;
  }
  const change = ((moved.to - moved.from) / Math.abs(moved.from)) * 100;
  return `${sign}${formatPercent(Math.abs(change))}`;
}

function sentenceCase(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

function changeMeta(change: MemberChange): string {
  return [
    formatUpdated(change.at),
    change.source === null
      ? 'edited by hand'
      : (SOURCE_LABEL[change.source] ?? change.source),
    change.recommendationIds.length === 0
      ? null
      : change.recommendationIds.join(', '),
  ]
    .filter((part): part is string => part !== null && part !== '')
    .join(' · ');
}

function MovedFigures({
  moved,
  judged,
}: {
  moved: readonly MovedFigure[];
  judged: boolean;
}): React.JSX.Element {
  return (
    <dl
      data-slot="member-change-figures"
      className="m-0 grid grid-cols-[minmax(0,1fr)_auto_auto] items-baseline gap-x-4 gap-y-1 text-xs tabular-nums">
      {moved.map((figure) => {
        const delta = movedDelta(figure);
        const Arrow = figure.to > figure.from ? ArrowUp : ArrowDown;
        return (
          <div
            key={figure.figure}
            data-slot="member-change-figure"
            data-figure={figure.figure}
            data-direction={figure.direction}
            className="contents">
            <dt className="min-w-0 truncate text-muted-foreground">
              {sentenceCase(figure.figure)}
            </dt>
            <dd
              data-slot="member-change-span"
              className="m-0 text-right whitespace-nowrap text-muted-foreground">
              {movedSpan(figure)}
            </dd>
            <dd
              data-slot="member-change-delta"
              className={cn(
                'm-0 inline-flex items-center justify-end gap-0.5 font-medium whitespace-nowrap',
                !judged
                  ? 'text-muted-foreground'
                  : figure.direction === 'better'
                    ? 'text-success'
                    : 'text-destructive',
              )}>
              <Arrow aria-hidden="true" className="size-3 shrink-0" />
              {delta ?? 'new'}
            </dd>
          </div>
        );
      })}
    </dl>
  );
}

/** One change that touched the member, and what its runs measured on either side. */
function ChangeCard({ change }: { change: MemberChange }): React.JSX.Element {
  const badge = EFFECT_BADGE[change.effect];
  const judged = change.effect !== 'too-few-runs';
  return (
    <li
      data-slot="member-change"
      data-effect={change.effect}
      className="flex min-w-0 flex-col gap-2.5 rounded-lg bg-muted/30 p-3 ring-1 ring-border/60">
      <div className="flex min-w-0 flex-wrap items-center gap-x-2 gap-y-1">
        <span
          data-slot="member-change-versions"
          className="inline-flex items-center gap-1 text-sm font-semibold tabular-nums">
          {versionLabel(change.from)}
          <ArrowRight
            aria-label="to"
            className="size-3.5 text-muted-foreground"
          />
          {versionLabel(change.to)}
        </span>
        {change.to.current ? <Badge variant="outline">current</Badge> : null}
        <span className="min-w-0 truncate text-xs text-muted-foreground">
          {changeMeta(change)}
        </span>
        <Badge
          data-slot="member-change-effect"
          variant={badge.variant}
          title={EFFECT_TITLE}
          className="ml-auto">
          {badge.label}
        </Badge>
      </div>
      <div
        data-slot="member-change-kinds"
        className="flex flex-wrap items-center gap-1">
        {change.kinds.map((kind) => (
          <Badge key={kind} variant="muted" className="font-normal">
            {KIND_LABEL[kind]}
          </Badge>
        ))}
      </div>
      {change.summary === null || change.summary.trim() === '' ? null : (
        <ClampedText
          text={change.summary}
          lines={2}
          slot="member-change-summary"
          className="text-xs text-foreground/80"
        />
      )}
      {change.moved.length === 0 ? (
        <p className="m-0 text-xs text-muted-foreground">
          No figure moved by a tenth or more.
        </p>
      ) : (
        <MovedFigures moved={change.moved} judged={judged} />
      )}
      {judged ? null : (
        <p className="m-0 text-xs text-muted-foreground">
          Under two runs on one side, so these figures are not judged.
        </p>
      )}
    </li>
  );
}

/** Every change that touched one member, newest first, each with the effect the daemon measured. */
export function MemberChangesDialog({
  open,
  onClose,
  changes,
}: {
  open: boolean;
  onClose: () => void;
  changes: readonly MemberChange[];
}): React.JSX.Element {
  const counts = EFFECT_ORDER.map((effect) => ({
    effect,
    count: changes.filter((change) => change.effect === effect).length,
  })).filter((entry) => entry.count > 0);
  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Changes and their effect"
      className="max-w-2xl">
      <div data-slot="member-changes" className="flex flex-col gap-4">
        <div className="flex flex-col gap-2">
          <p className="m-0 text-xs text-muted-foreground">
            How this member’s figures per run moved after each change to the
            team that touched it, measured over the runs of either version.
          </p>
          <div
            data-slot="member-changes-summary"
            className="flex flex-wrap items-center gap-1.5">
            {counts.map(({ effect, count }) => (
              <Badge key={effect} variant={EFFECT_BADGE[effect].variant}>
                {count} {EFFECT_BADGE[effect].label.toLowerCase()}
              </Badge>
            ))}
          </div>
        </div>
        <ul className="m-0 flex list-none flex-col gap-2.5 p-0">
          {changes.map((change) => (
            <ChangeCard
              key={`${change.from.number}:${change.to.number}:${change.at}`}
              change={change}
            />
          ))}
        </ul>
      </div>
    </Dialog>
  );
}
