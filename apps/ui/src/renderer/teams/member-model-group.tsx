import { useMemo } from 'react';

import type {
  AgentKind,
  ApprovalMode as TeamApproval,
  CapabilitiesDto,
  TeamMember,
} from '../autogenerated';
import {
  ApprovalModeSelect,
  PLAN_WITHHELD,
} from '../chats/approval-mode-select';
import { AutoCompactSelect } from '../chats/auto-compact-select';
import { ConfigDirSelect } from '../chats/config-dir-select';
import { ModelSelect } from '../chats/model-select';
import { useAgentContextWindows } from '../chats/use-agent-context-windows';
import { useAgentEfforts } from '../chats/use-agent-efforts';
import { useAgentModelParameters } from '../chats/use-agent-model-parameters';
import { useAgentModels } from '../chats/use-agent-models';
import { Select } from '../components/ui/select';
import type { DaemonApis } from '../daemon-api';
import { modelChangePatch } from './member-schema';
import { ModelSettingsRows } from './model-settings-rows';
import {
  type RowScope,
  ScopedGroup,
  ScopedSettingRow,
} from './overridable-row';
import { rememberMemberAgent } from './team-doc';
import type { OverlaySettingsField } from './team-overlay-doc';
import { configDirCapabilityFrom } from './use-config-dir-capability';
import type { MemberProfileSources } from './use-member-profile-sources';

type MemberPatch = Partial<Omit<TeamMember, 'id'>>;

/**
 * A member's Model group — CLI, profile, approval, model and its axes,
 * auto-compact — as the member sheet draws it. With `scopeOf`, each row is
 * one project's override of the team's value (TEAM / OVERRIDDEN, Override and
 * Reset); without, the plain rows of the shared team.
 */
export function MemberModelGroup({
  agentsApi,
  capabilities,
  capabilitiesLoading,
  member,
  teamMember,
  scopeOf = null,
  sources,
  onBrowseConfigDir,
  onPatch,
}: {
  agentsApi: DaemonApis['agents'] | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  /** The member as it runs here — the shared team's, or with the project's overrides applied. */
  member: TeamMember;
  /** The member as the shared team holds it, for the "Team: …" line. */
  teamMember: TeamMember;
  /** One project's override of `fields`; null draws the shared team's rows. */
  scopeOf?:
    ((fields: OverlaySettingsField[], teamValue: string) => RowScope) | null;
  sources: Pick<MemberProfileSources, 'recentConfigDirs' | 'configProfiles'>;
  onBrowseConfigDir: () => void;
  onPatch: (patch: MemberPatch) => void;
}): React.JSX.Element {
  const scope = (
    fields: OverlaySettingsField[],
    teamValue: string,
  ): RowScope | null => (scopeOf === null ? null : scopeOf(fields, teamValue));
  const configDir = member.configDir ?? null;
  // Each listing is an account fact: the member's CLI under its own profile.
  const { models, loading: modelsLoading } = useAgentModels(
    agentsApi,
    member.agent,
    configDir,
    member.model ?? null,
  );
  const efforts = useAgentEfforts(
    agentsApi,
    member.agent,
    member.model ?? null,
    configDir,
  );
  const windows = useAgentContextWindows(
    agentsApi,
    member.agent,
    member.model ?? null,
    configDir,
  );
  const parameters = useAgentModelParameters(
    agentsApi,
    member.agent,
    member.model ?? null,
    configDir,
  );
  const configDirCapability = configDirCapabilityFrom(
    capabilities,
    capabilitiesLoading,
  );
  // `plan` is withheld: it is a chat posture the team schema does not hold.
  const approvalCapability = useMemo(
    () => capabilities?.approvals.find((entry) => entry.agent === member.agent),
    [capabilities, member.agent],
  );

  const autoCompactRow = (
    <ScopedSettingRow
      label="Auto-compact"
      scope={scope(
        ['autoCompactPercent'],
        teamMember.autoCompactPercent === undefined
          ? 'never'
          : `${teamMember.autoCompactPercent}%`,
      )}>
      <AutoCompactSelect
        value={member.autoCompactPercent ?? null}
        onChange={(percent) =>
          onPatch({ autoCompactPercent: percent ?? undefined })
        }
      />
    </ScopedSettingRow>
  );

  return (
    <div className="@container flex flex-col divide-y divide-border rounded-card bg-card ring-1 ring-border">
      <ScopedSettingRow
        label="Agent"
        scope={scope(
          ['agent'],
          capabilities?.agents.find((entry) => entry.agent === teamMember.agent)
            ?.displayName ?? teamMember.agent,
        )}>
        <Select
          variant="ghost"
          aria-label="CLI for this member"
          value={member.agent}
          groups={[
            {
              items: (capabilities?.agents ?? []).map((identity) => ({
                value: identity.agent,
                label: identity.displayName,
              })),
            },
          ]}
          onValueChange={(next) => {
            const agent = next as AgentKind;
            if (agent === member.agent) {
              return;
            }
            rememberMemberAgent(agent);
            // Another CLI starts from its own defaults.
            onPatch({
              agent,
              model: undefined,
              effort: undefined,
              contextWindow: undefined,
              modelParameters: undefined,
              configDir: undefined,
              mcpDisabled: undefined,
            });
          }}
        />
      </ScopedSettingRow>
      {configDirCapability.unavailableReasonFor(member.agent) === null ? (
        <ScopedSettingRow
          label="Profile"
          scope={scope(
            ['configDir'],
            teamMember.configDir ?? 'Default profile',
          )}>
          <ConfigDirSelect
            configDir={configDir}
            recentConfigDirs={sources.recentConfigDirs[member.agent] ?? []}
            configProfiles={sources.configProfiles.filter(
              (profile) => profile.agent === member.agent,
            )}
            unavailableReason={null}
            ariaLabel="Agent config directory for this member"
            onChange={(next) => onPatch({ configDir: next ?? undefined })}
            onBrowse={onBrowseConfigDir}
          />
        </ScopedSettingRow>
      ) : null}
      <ScopedSettingRow
        label="Approval"
        scope={scope(['approval'], teamMember.approval)}>
        <ApprovalModeSelect
          capability={approvalCapability}
          withheld={PLAN_WITHHELD}
          value={member.approval}
          onChange={(approval) =>
            onPatch({ approval: approval as TeamApproval })
          }
        />
      </ScopedSettingRow>
      <ScopedSettingRow
        label="Model"
        scope={scope(['model'], teamMember.model ?? 'CLI default')}>
        <ModelSelect
          key={member.id}
          agentKind={member.agent}
          models={models}
          loading={modelsLoading}
          allowCustom
          value={member.model ?? null}
          onChange={(model) => onPatch(modelChangePatch(model))}
        />
      </ScopedSettingRow>
      <ScopedGroup
        label="Effort, context and parameters"
        scope={scope(
          ['effort', 'contextWindow', 'modelParameters'],
          [
            teamMember.effort ?? 'default effort',
            teamMember.contextWindow ?? 'default window',
          ].join(', '),
        )}>
        <ModelSettingsRows
          efforts={efforts.efforts}
          windows={windows.windows}
          parameters={parameters.parameters}
          loading={efforts.loading || windows.loading || parameters.loading}
          value={member}
          onPatch={onPatch}
          afterContext={scopeOf === null ? autoCompactRow : null}
        />
      </ScopedGroup>
      {scopeOf === null ? null : autoCompactRow}
    </div>
  );
}
