// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { vi } from 'vitest';

import {
  assessment,
  PLANNER,
  REVIEWER,
} from '../__fixtures__/member-performance';
import type { TeamStatsMember } from '../autogenerated';
import { assessmentCaption, MemberPerformance } from './member-performance';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function render(
  row: TeamStatsMember | null,
  loading = false,
  onVerdict?: Parameters<typeof MemberPerformance>[0]['onVerdict'],
): void {
  act(() => {
    root.render(
      <MemberPerformance row={row} loading={loading} onVerdict={onVerdict} />,
    );
  });
}

describe('MemberPerformance', () => {
  it('shows the newest assessment with what became of its items, and the earlier ones beneath it', () => {
    render(REVIEWER);

    const latest = container.querySelector('[data-slot="member-assessment"]')!;
    expect(latest.textContent).toContain('2 of its 6 approvals were reopened');
    expect(
      [
        ...latest.querySelectorAll(
          '[data-slot="member-assessment-item-status"]',
        ),
      ].map((badge) => badge.textContent),
    ).toEqual(['Applied']);
    expect(
      [
        ...container.querySelectorAll(
          '[data-slot="member-assessment-history"] [data-slot="member-verdict"]',
        ),
      ].map((badge) => badge.getAttribute('data-verdict')),
    ).toEqual(['reconfigure']);
    expect(latest.textContent).not.toContain('LGTM');

    act(() => {
      [...latest.querySelectorAll('button')]
        .find((button) => button.textContent?.includes('Evidence'))!
        .click();
    });

    expect(latest.textContent).toContain('LGTM — the change looks correct');
  });

  it("reads the member's work over its measured runs", () => {
    render(REVIEWER);

    const text = container.textContent ?? '';
    expect(text).toContain('Calls answered14 (1 failed)');
    expect(text).toContain('Tool errors9 of 212');
    expect(text).toContain('Own goals achieved75% (3 of 4)');
    expect(text).toContain('Reopened2 of 6');
    expect(text).toContain('over its 6 measured runs');
  });

  it('says what was not measured and that no analysis has judged it, never zeros', () => {
    render(PLANNER);

    const text = container.textContent ?? '';
    expect(text).toContain('Cost—');
    expect(text).not.toContain('Calls answered');
    expect(text).toContain(
      'counted only for runs started since Geniro began measuring',
    );
    expect(
      container.querySelector('[data-slot="member-performance-unassessed"]'),
    ).not.toBeNull();
  });

  it('says a member with no turn has none yet, and waits while loading', () => {
    render(null);
    expect(container.textContent).toBe('It has not taken a turn yet.');

    render(null, true);
    expect(container.textContent).toBe('Loading…');
  });
});

describe('assessmentCaption', () => {
  const now = Date.parse('2026-11-03T12:00:00.000Z');

  it('names the runs an analysis read and the versions they ran, one run for a thread analysis', () => {
    expect(
      assessmentCaption(
        assessment({ filedAt: '2026-11-01T12:00:00.000Z' }),
        now,
      ),
    ).toBe('2d ago · 6 runs of versions 3–4 (current)');
    expect(
      assessmentCaption(
        assessment({
          filedAt: '2026-11-03T11:00:00.000Z',
          chatKind: 'thread',
          runs: 1,
          versions: [{ number: 2, current: false }],
        }),
        now,
      ),
    ).toBe('1h ago · one run of version 2');
    expect(
      assessmentCaption(
        assessment({
          filedAt: '2026-11-03T11:00:00.000Z',
          runs: 2,
          versions: [],
        }),
        now,
      ),
    ).toBe('1h ago · 2 runs');
  });
});

describe('MemberPerformance — an unjudged mark', () => {
  it('draws a mark the analysis left unjudged as a dash, never a figure', () => {
    render({
      ...REVIEWER,
      assessments: [
        assessment({
          usefulness: null,
          quality: 4,
          verdict: 'keep',
          items: [],
        }),
      ],
    });

    const meters = [
      ...container.querySelectorAll(
        '[data-slot="member-assessment"] [data-slot="mark-meter"]',
      ),
    ];
    expect(meters.map((meter) => meter.getAttribute('aria-label'))).toEqual([
      'Usefulness not judged',
      'Quality 4 of 5',
    ]);
    expect(meters[0]!.textContent).toBe('Usefulness—');
  });
});

describe('MemberPerformance — reliability, changes, judges and verdicts', () => {
  it('reads its clean runs and the spread of its cost and time per run', () => {
    render(REVIEWER);

    const text = container.textContent ?? '';
    expect(text).toContain('Clean runs4 of 6');
    expect(text).toContain('Cost per run$0.30 ($0.18–$0.52)');
    expect(text).toContain('Time per run14m (10m–25m)');
  });

  it('lists each change that touched it with who made it, the measured effect and the figures that moved', () => {
    render(REVIEWER);

    const change = container.querySelector('[data-slot="member-change"]')!;
    expect(change.getAttribute('data-effect')).toBe('better');
    expect(change.textContent).toContain('v3 → v4 (current)');
    expect(change.textContent).toContain('instructions');
    expect(change.textContent).toContain('by an analysis · W-1');
    expect(change.textContent).toContain('cost per run −46% ($0.41 → $0.22)');
    expect(change.textContent).toContain('rework 50% → 0%');
  });

  it('says how far a per-run amount moved when its rounded ends would read as doubling', () => {
    const [change] = REVIEWER.changes;
    render({
      ...REVIEWER,
      changes: [
        {
          ...change!,
          effect: 'worse',
          moved: [
            {
              figure: 'cost per run',
              unit: 'usd',
              from: 0.0141,
              to: 0.0156,
              direction: 'worse',
            },
          ],
        },
      ],
    });

    expect(
      container.querySelector('[data-slot="member-change"]')!.textContent,
    ).toContain('cost per run +11% ($0.01 → $0.02)');
  });

  it('names the judge, warns when it shares the member’s vendor, and sends the verdict on its marks', async () => {
    const onVerdict = vi.fn().mockResolvedValue(undefined);
    render(
      {
        ...REVIEWER,
        assessments: [
          assessment({
            judge: { agent: 'claude', model: 'opus', sameVendor: true },
          }),
        ],
      },
      false,
      onVerdict,
    );

    const latest = container.querySelector('[data-slot="member-assessment"]')!;
    expect(latest.textContent).toContain('judged by claude · opus');
    expect(
      latest.querySelector('[data-slot="member-assessment-same-vendor"]'),
    ).not.toBeNull();

    await act(async () => {
      [...latest.querySelectorAll('button')]
        .find((button) => button.textContent?.includes('Agree'))!
        .click();
    });

    expect(onVerdict).toHaveBeenCalledWith(
      expect.objectContaining({ chatRunId: 'analysis-2', cardSeq: 40 }),
      { verdict: 'agree', note: null },
    );
  });
});
