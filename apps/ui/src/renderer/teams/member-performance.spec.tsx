// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import {
  assessment,
  PLANNER,
  REVIEWER,
} from '../__fixtures__/member-performance';
import type { TeamStatsMember } from '../autogenerated';
import { assessmentCaption, MemberPerformance } from './member-performance';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function render(row: TeamStatsMember | null, loading = false): void {
  act(() => {
    root.render(<MemberPerformance row={row} loading={loading} />);
  });
}

describe('MemberPerformance', () => {
  it('shows the newest assessment with what became of its items, and the earlier ones beneath it', () => {
    render(REVIEWER);

    const latest = container.querySelector('[data-slot="member-assessment"]')!;
    expect(latest.textContent).toContain('2 of its 6 approvals were reopened');
    expect(
      [
        ...latest.querySelectorAll(
          '[data-slot="member-assessment-item-status"]',
        ),
      ].map((badge) => badge.textContent),
    ).toEqual(['Applied']);
    expect(
      [
        ...container.querySelectorAll(
          '[data-slot="member-assessment-history"] [data-slot="member-verdict"]',
        ),
      ].map((badge) => badge.getAttribute('data-verdict')),
    ).toEqual(['reconfigure']);
    expect(latest.textContent).not.toContain('LGTM');

    act(() => {
      [...latest.querySelectorAll('button')]
        .find((button) => button.textContent?.includes('Evidence'))!
        .click();
    });

    expect(latest.textContent).toContain('LGTM — the change looks correct');
  });

  it("reads the member's work over its measured runs", () => {
    render(REVIEWER);

    const text = container.textContent ?? '';
    expect(text).toContain('Calls answered14 (1 failed)');
    expect(text).toContain('Tool errors9 of 212');
    expect(text).toContain('Goals achieved75% (3 of 4)');
    expect(text).toContain('Reopened2 of 6');
    expect(text).toContain('over its 6 measured runs');
  });

  it('says what was not measured and that no analysis has judged it, never zeros', () => {
    render(PLANNER);

    const text = container.textContent ?? '';
    expect(text).toContain('Cost—');
    expect(text).not.toContain('Calls answered');
    expect(text).toContain(
      'counted only for runs started since Geniro began measuring',
    );
    expect(
      container.querySelector('[data-slot="member-performance-unassessed"]'),
    ).not.toBeNull();
  });

  it('says a member with no turn has none yet, and waits while loading', () => {
    render(null);
    expect(container.textContent).toBe('It has not taken a turn yet.');

    render(null, true);
    expect(container.textContent).toBe('Loading…');
  });
});

describe('assessmentCaption', () => {
  const now = Date.parse('2026-11-03T12:00:00.000Z');

  it('names the version and the runs a team analysis read, and one run for a thread analysis', () => {
    expect(
      assessmentCaption(
        assessment({ filedAt: '2026-11-01T12:00:00.000Z' }),
        now,
      ),
    ).toBe('2d ago · version 4 (current) · 6 runs');
    expect(
      assessmentCaption(
        assessment({
          filedAt: '2026-11-03T11:00:00.000Z',
          chatKind: 'thread',
          runs: 1,
          version: null,
        }),
        now,
      ),
    ).toBe('1h ago · one run');
  });
});
