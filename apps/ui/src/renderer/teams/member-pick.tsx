import { ArrowDown, ArrowUp, UserCheck, Users, X } from 'lucide-react';
import { useRef, useState } from 'react';

import type { TeamMember } from '../autogenerated';
import { AvatarStack, MemberAvatar } from '../components/member-avatar';
import { Button } from '../components/ui/button';
import { ChipChevron, chipVariants } from '../components/ui/chip';
import { OptionIndicator } from '../components/ui/option-list';
