import type { BlockAudience } from './member-schema';

type MemberRef = Pick<TeamMember, 'id' | 'name'> &
  Partial<Pick<TeamMember, 'avatar'>>;

/**
 * One label per member, told apart: a name two members share carries the id,
 * since an option list and a picker identify their rows by label.
 */
export function memberLabels(
  members: readonly MemberRef[],
): ReadonlyMap<string, string> {
  const counts = new Map<string, number>();
  for (const member of members) {
    const name = member.name.trim() || member.id;
    counts.set(name, (counts.get(name) ?? 0) + 1);
  }
  return new Map(
    members.map((member) => {
      const name = member.name.trim() || member.id;
      return [
        member.id,
        (counts.get(name) ?? 0) > 1 ? `${name} (${member.id})` : name,
      ];
    }),
  );
}

/** Whom a block reaches, in words. */
export function audienceSummary(
  audience: BlockAudience,
  labels: ReadonlyMap<string, string>,
): string {
  if (audience === 'everyone') {
    return 'Everyone';
  }
  if (audience.length === 0) {
    return 'Nobody yet';
  }
  return audience.map((id) => labels.get(id) ?? id).join(', ');
}

type AudienceMode = 'everyone' | 'picked';

const AUDIENCE_MODES: readonly {
  id: AudienceMode;
  label: string;
  icon: React.ReactNode;
}[] = [
  { id: 'everyone', label: 'Everyone', icon: <Users /> },
  { id: 'picked', label: 'Picked members', icon: <UserCheck /> },
];

const audienceTriggerVariants = cva(
  'h-8 max-w-full gap-2 rounded-pill px-3 text-sm font-normal',
  {
    variants: {
      empty: {
        true: 'bg-warning/15 text-warning hover:bg-warning/20 hover:text-warning',
        false: 'bg-muted text-foreground',
      },
    },
  },
);

function AudienceMemberRow({
  label,
  avatar,
  colorKey,
  note,
  chosen,
  onToggle,
}: {
  label: string;
  avatar?: MemberRef['avatar'];
  colorKey: string;
  note?: string;
  chosen: boolean;
  onToggle: () => void;
}): React.JSX.Element {
  return (
    <li>
      <button
        type="button"
        role="checkbox"
        aria-checked={chosen}
        aria-label={label}
        className="flex w-full min-w-0 items-center gap-2.5 rounded-control px-2 py-1.5 text-left text-sm transition-colors outline-none hover:bg-accent focus-visible:ring-2 focus-visible:ring-ring/50"
        onClick={onToggle}>
        <OptionIndicator arity="many" chosen={chosen} />
        <MemberAvatar
          name={label}
          avatar={avatar}
          colorKey={colorKey}
          size={24}
        />
        <span className="min-w-0 flex-1 truncate">{label}</span>
        {note === undefined ? null : (
          <span className="shrink-0 text-xs text-warning">{note}</span>
        )}
      </button>
    </li>
  );
}

/**
 * Who an instruction block reaches: a chip naming them, opening a panel to
 * pick everyone or the members picked. Switching to picked members starts
 * from none picked; an id that names no member stays listed, marked, until it
 * is cleared.
 */
export function AudiencePick({
  members,
  audience,
  onChange,
}: {
  members: readonly MemberRef[];
  audience: BlockAudience;
  onChange: (audience: BlockAudience) => void;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const labels = memberLabels(members);
  const picked = audience === 'everyone' ? [] : audience;
  const unknown = picked.filter((id) => !labels.has(id));
  const summary = audienceSummary(audience, labels);
  const people = (
    audience === 'everyone'
      ? members
      : members.filter((member) => picked.includes(member.id))
  ).map((member) => ({
    key: member.id,
    name: labels.get(member.id)!,
    avatar: member.avatar,
  }));
  const toggle = (id: string): void =>
    onChange(
      picked.includes(id)
        ? picked.filter((other) => other !== id)
        : [...picked, id],
    );
  return (
    <span
      data-slot="audience-pick"
      className="relative flex min-w-0 shrink justify-end">
      <button
        ref={triggerRef}
        type="button"
        aria-label={`Reaches ${summary}`}
        aria-expanded={open}
        aria-haspopup="dialog"
        title={`Reaches ${summary}`}
        className={cn(
          chipVariants({ interactive: true }),
          audienceTriggerVariants({ empty: summary === 'Nobody yet' }),
        )}
        onClick={() => setOpen((was) => !was)}>
        <span className="shrink-0 text-muted-foreground">Reaches</span>
        {audience === 'everyone' ? (
          <Users className="size-4 shrink-0 text-muted-foreground" />
        ) : people.length > 0 ? (
          <AvatarStack
            people={people}
            max={3}
            size={20}
            ringClassName="ring-muted"
            className="shrink-0"
          />
        ) : null}
        <span className="min-w-0 truncate">{summary}</span>
        <ChipChevron />
      </button>
      <Popover
        open={open}
        onClose={() => setOpen(false)}
        triggerRef={triggerRef}
        side="bottom"
        align="end"
        anchor="viewport"
        label="Who this block reaches"
        className="flex w-80 max-w-[calc(100vw-2rem)] flex-col gap-3 p-3">
        <SegmentedControl
          ariaLabel="Who this block reaches"
          size="sm"
          options={AUDIENCE_MODES}
          value={audience === 'everyone' ? 'everyone' : 'picked'}
          onSelect={(mode) => {
            if (mode === 'everyone') {
              onChange('everyone');
            } else if (audience === 'everyone') {
              onChange([]);
            }
          }}
          className="w-full [&>button]:flex-1 [&>button]:justify-center"
        />
        {audience === 'everyone' ? (
          <div className="flex items-center gap-2.5 px-1 text-sm text-muted-foreground">
            {people.length > 0 ? (
              <AvatarStack
                people={people}
                max={5}
                size={24}
                ringClassName="ring-popover"
                className="shrink-0"
              />
            ) : null}
            <span>
              Every member carries this block, including members added later.
            </span>
          </div>
        ) : (
          <>
            <ul
              role="group"
              aria-label="Members this block reaches"
              className="-mx-1 flex max-h-72 flex-col gap-0.5 overflow-y-auto">
              {members.map((member) => (
                <AudienceMemberRow
                  key={member.id}
                  label={labels.get(member.id)!}
                  avatar={member.avatar}
                  colorKey={member.id}
                  chosen={picked.includes(member.id)}
                  onToggle={() => toggle(member.id)}
                />
              ))}
              {unknown.map((id) => (
                <AudienceMemberRow
                  key={id}
                  label={id}
                  colorKey={id}
                  note="not in this team"
                  chosen
                  onToggle={() => toggle(id)}
                />
              ))}
            </ul>
            <p
              className={cn(
                'px-1 text-xs',
                picked.length === 0 ? 'text-warning' : 'text-muted-foreground',
              )}>
              {picked.length === 0
                ? 'Pick at least one member, or the block reaches nobody.'
                : `${picked.length} of ${members.length} ${members.length === 1 ? 'member' : 'members'} carry this block.`}
            </p>
          </>
        )}
      </Popover>
    </span>
  );
}

/**
 * The members responsible for a stage, in order: the first one leads it. Each
 * can be moved or removed; the picker below adds the members not yet listed.
 * An id that names no member stays listed, marked, until it is removed.
 */
export function ResponsiblePick({
  id,
  members,
  responsible,
  onChange,
}: {
  id?: string;
  members: readonly MemberRef[];
  responsible: readonly string[];
  onChange: (responsible: string[]) => void;
}): React.JSX.Element {
  const labels = memberLabels(members);
  const left = members.filter((member) => !responsible.includes(member.id));
  const move = (index: number, by: -1 | 1): void => {
    const next = [...responsible];
    const [moved] = next.splice(index, 1);
    next.splice(index + by, 0, moved!);
    onChange(next);
  };
  return (
    <div data-slot="responsible-pick" className="flex flex-col gap-2">
      {responsible.length === 0 ? (
        <p className="text-sm text-muted-foreground">
          No one in particular — any member may take it.
        </p>
      ) : (
        <ol
          aria-label="Responsible members"
          className="flex flex-col gap-1 rounded-control bg-muted/40 p-1">
          {responsible.map((memberId, index) => {
            const label =
              labels.get(memberId) ?? `${memberId} (not in this team)`;
            return (
              <li
                key={memberId}
                data-slot="responsible-row"
                data-member-id={memberId}
                className="flex min-w-0 items-center gap-2 px-2 py-1 text-sm">
                <span className="w-4 shrink-0 text-xs text-muted-foreground tabular-nums">
                  {index + 1}
                </span>
                <MemberAvatar
                  name={label}
                  avatar={members.find((m) => m.id === memberId)?.avatar}
                  colorKey={memberId}
                  size={20}
                />
                <span className="min-w-0 flex-1 truncate">{label}</span>
                {index === 0 ? (
                  <span className="shrink-0 text-xs text-muted-foreground">
                    leads
                  </span>
                ) : null}
                <Button
                  type="button"
                  variant="ghost"
                  size="icon"
                  className="size-6"
                  disabled={index === 0}
                  aria-label={`Move ${label} up`}
                  title="Move up"
                  onClick={() => move(index, -1)}>
                  <ArrowUp className="size-3.5" />
                </Button>
                <Button
                  type="button"
                  variant="ghost"
                  size="icon"
                  className="size-6"
                  disabled={index === responsible.length - 1}
                  aria-label={`Move ${label} down`}
                  title="Move down"
                  onClick={() => move(index, 1)}>
                  <ArrowDown className="size-3.5" />
                </Button>
                <Button
                  type="button"
                  variant="ghost"
                  size="icon"
                  className="size-6"
                  aria-label={`Remove ${label}`}
                  title="Remove"
                  onClick={() =>
                    onChange(responsible.filter((other) => other !== memberId))
                  }>
                  <X className="size-3.5" />
                </Button>
              </li>
            );
          })}
        </ol>
      )}
      {left.length > 0 ? (
        <Select
          id={id}
          aria-label="Add a responsible member"
          placeholder="Add a member…"
          value={null}
          groups={[
            {
              items: left.map((member) => ({
                value: member.id,
                label: labels.get(member.id)!,
              })),
            },
          ]}
          onValueChange={(memberId) => onChange([...responsible, memberId])}
        />
      ) : null}
    </div>
  );
}
