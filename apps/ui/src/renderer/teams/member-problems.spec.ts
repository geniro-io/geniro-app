import { describe, expect, it } from 'vitest';

import type { HealthProblem, MemberHealth } from '../autogenerated';
import {
  memberProblemsOf,
  memberStatusOf,
  type SignInProblem,
} from './member-problems';

function problem(over: Partial<HealthProblem> = {}): HealthProblem {
  return {
    kind: 'mcp_failed',
    level: 'warning',
    message: 'The github server did not connect',
    agent: 'claude',
    poolMember: null,
    configDir: null,
    server: 'github',
    model: null,
    ...over,
  };
}

function reading(
  status: MemberHealth['status'],
  problems: HealthProblem[] = [],
): MemberHealth {
  return {
    memberId: 'ada',
    seats: [],
    status,
    checking: status === 'checking',
    problems,
    mcpCheckedAt: null,
  };
}

const SIGNED_OUT: SignInProblem = {
  kind: 'signed_out',
  message: 'Signed out of Claude',
  agent: 'claude',
  configDir: null,
  poolMember: null,
};

describe('memberProblemsOf', () => {
  it('puts the daemon errors first, then warnings, then sign-in findings', () => {
    const problems = memberProblemsOf(
      'ada',
      reading('error', [
        problem(),
        problem({ kind: 'cli_missing', level: 'error', server: null }),
      ]),
      [SIGNED_OUT],
    );
    expect(problems.map((entry) => entry.kind)).toEqual([
      'cli_missing',
      'mcp_failed',
      'signed_out',
    ]);
    expect(problems[2]).toMatchObject({ level: 'warning', memberId: 'ada' });
  });

  it('keeps the pool members of one member under different keys', () => {
    const problems = memberProblemsOf(
      'ada',
      reading('warning', [
        problem({ poolMember: null }),
        problem({ poolMember: 2 }),
        problem({ poolMember: 3 }),
      ]),
      [{ ...SIGNED_OUT, poolMember: 2 }, SIGNED_OUT],
    );
    expect(new Set(problems.map((entry) => entry.key)).size).toBe(
      problems.length,
    );
  });

  it('keeps even an exact repeat under its own key', () => {
    const problems = memberProblemsOf(
      'ada',
      reading('warning', [problem(), problem()]),
      [],
    );
    expect(problems[0]!.key).not.toBe(problems[1]!.key);
  });

  it('folds many servers with one finding into one row per seat', () => {
    const servers = ['a', 'b', 'c', 'd'];
    const problems = memberProblemsOf(
      'ada',
      reading('warning', [
        ...servers.map((server) => problem({ kind: 'mcp_needs_auth', server })),
        ...servers.map((server) =>
          problem({ kind: 'mcp_needs_auth', server, poolMember: 2 }),
        ),
        problem({ kind: 'mcp_failed', server: 'github' }),
      ]),
      [],
    );
    expect(problems.map((entry) => [entry.message, entry.server])).toEqual([
      ['4 MCP servers need signing in for this member.', null],
      ['4 MCP servers need signing in for pool agent 2.', null],
      ['The github server did not connect', 'github'],
    ]);
  });

  it('keeps a couple of servers with one finding as their own rows', () => {
    const problems = memberProblemsOf(
      'ada',
      reading('warning', [
        problem({ kind: 'mcp_needs_auth', server: 'a' }),
        problem({ kind: 'mcp_needs_auth', server: 'b' }),
      ]),
      [],
    );
    expect(problems.map((entry) => entry.server)).toEqual(['a', 'b']);
  });

  it('is empty without a reading and without sign-in findings', () => {
    expect(memberProblemsOf('ada', undefined, [])).toEqual([]);
  });
});

describe('memberStatusOf', () => {
  it('reads an unknown sign-in as a warning, never an error', () => {
    const problems = memberProblemsOf('ada', reading('ok'), [
      { ...SIGNED_OUT, kind: 'sign_in_unknown' },
    ]);
    expect(memberStatusOf(reading('ok'), problems)).toBe('warning');
  });

  it('ranks error above checking above warning above ready', () => {
    const warning = memberProblemsOf('ada', undefined, [SIGNED_OUT]);
    const error = memberProblemsOf(
      'ada',
      reading('error', [problem({ level: 'error' })]),
      [],
    );
    expect(memberStatusOf(reading('checking'), [...error, ...warning])).toBe(
      'error',
    );
    expect(memberStatusOf(reading('checking'), warning)).toBe('checking');
    expect(memberStatusOf(reading('warning'), warning)).toBe('warning');
    expect(memberStatusOf(reading('ok'), [])).toBe('ready');
  });

  it('is unchecked until a reading lands, unless the renderer found something', () => {
    expect(memberStatusOf(undefined, [])).toBe('unchecked');
    expect(
      memberStatusOf(
        undefined,
        memberProblemsOf('ada', undefined, [SIGNED_OUT]),
      ),
    ).toBe('warning');
  });
});
