import type { AgentKind, HealthProblem, MemberHealth } from '../autogenerated';

export type MemberProblemKind =
  HealthProblem['kind'] | 'signed_out' | 'sign_in_unknown';

/** How a member stands: `unchecked` is the state before any reading landed. */
export type MemberStatus =
  'ready' | 'warning' | 'error' | 'checking' | 'unchecked';

/** A sign-in finding, read in the renderer from Electron main's detection. */
export interface SignInProblem {
  kind: 'signed_out' | 'sign_in_unknown';
  message: string;
  agent: AgentKind;
  configDir: string | null;
  /** Null is the member itself; 2.. is the pool position. */
  poolMember: number | null;
}

/** One thing wrong with one member, whichever side found it. */
export interface MemberProblem {
  /** Unique within one member's list. */
  key: string;
  memberId: string;
  kind: MemberProblemKind;
  level: HealthProblem['level'];
  message: string;
  agent: AgentKind | null;
  configDir: string | null;
  server: string | null;
  /** Every MCP server the finding names: its own, or those a collapsed row stands for. */
  servers: readonly string[];
  poolMember: number | null;
}

export const SERVER_REPEATS_COLLAPSE_AT = 3;

export const SERVER_REPEAT_TEXT: Partial<Record<MemberProblemKind, string>> = {
  mcp_needs_auth: 'need signing in',
  mcp_failed: 'failed to connect',
  mcp_disconnected: 'are not connected',
};

function serverGroupOf(problem: Omit<MemberProblem, 'key'>): string | null {
  if (problem.server === null || !(problem.kind in SERVER_REPEAT_TEXT)) {
    return null;
  }
  return [
    problem.kind,
    problem.level,
    problem.poolMember ?? 'member',
    problem.agent ?? '',
    problem.configDir ?? '',
  ].join(':');
}

function collapseServerRepeats(
  problems: readonly Omit<MemberProblem, 'key'>[],
): Omit<MemberProblem, 'key'>[] {
  const groups = new Map<string, Omit<MemberProblem, 'key'>[]>();
  for (const problem of problems) {
    const group = serverGroupOf(problem);
    if (group !== null) {
      groups.set(group, [...(groups.get(group) ?? []), problem]);
    }
  }
  const emitted = new Set<string>();
  return problems.flatMap((problem) => {
    const group = serverGroupOf(problem);
    const members = group === null ? undefined : groups.get(group);
    if (
      group === null ||
      members === undefined ||
      members.length < SERVER_REPEATS_COLLAPSE_AT
    ) {
      return [problem];
    }
    if (emitted.has(group)) {
      return [];
    }
    emitted.add(group);
    const who =
      problem.poolMember === null
        ? 'this member'
        : `pool agent ${problem.poolMember}`;
    return [
      {
        ...problem,
        server: null,
        servers: members.flatMap((entry) => entry.servers),
        message: `${members.length} MCP servers ${SERVER_REPEAT_TEXT[problem.kind]} for ${who}.`,
      },
    ];
  });
}

function keyOf(memberId: string, problem: Omit<MemberProblem, 'key'>): string {
  return [
    memberId,
    problem.poolMember ?? 'member',
    problem.kind,
    problem.agent ?? '',
    problem.configDir ?? '',
    problem.server ?? '',
  ].join(':');
}

/**
 * A member's problems: the daemon's reading first, errors before warnings,
 * then what the renderer found itself about sign-in. Keys stay apart for the
 * pool members of one member, and for a repeat of one finding.
 */
export function memberProblemsOf(
  memberId: string,
  health: MemberHealth | undefined,
  signIn: readonly SignInProblem[],
): MemberProblem[] {
  const fromDaemon: Omit<MemberProblem, 'key'>[] = (health?.problems ?? [])
    .map((problem) => ({
      memberId,
      kind: problem.kind,
      level: problem.level,
      message: problem.message,
      agent: problem.agent,
      configDir: problem.configDir,
      server: problem.server,
      servers: problem.server === null ? [] : [problem.server],
      poolMember: problem.poolMember,
    }))
    .sort((a, b) => Number(b.level === 'error') - Number(a.level === 'error'));
  const fromSignIn: Omit<MemberProblem, 'key'>[] = signIn.map((problem) => ({
    memberId,
    kind: problem.kind,
    level: 'warning',
    message: problem.message,
    agent: problem.agent,
    configDir: problem.configDir,
    server: null,
    servers: [],
    poolMember: problem.poolMember,
  }));
  const seen = new Map<string, number>();
  return [...collapseServerRepeats(fromDaemon), ...fromSignIn].map(
    (problem) => {
      const base = keyOf(memberId, problem);
      const count = seen.get(base) ?? 0;
      seen.set(base, count + 1);
      return { ...problem, key: count === 0 ? base : `${base}#${count}` };
    },
  );
}

/**
 * Error beats checking beats warning beats ready. A member nobody has read yet
 * and that has no finding of its own is `unchecked`.
 */
export function memberStatusOf(
  health: MemberHealth | undefined,
  problems: readonly MemberProblem[],
): MemberStatus {
  if (
    health?.status === 'error' ||
    problems.some((problem) => problem.level === 'error')
  ) {
    return 'error';
  }
  if (health?.status === 'checking') {
    return 'checking';
  }
  if (health?.status === 'warning' || problems.length > 0) {
    return 'warning';
  }
  return health === undefined ? 'unchecked' : 'ready';
}
