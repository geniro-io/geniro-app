import type { TeamMember } from '../autogenerated';

/** What a member that runs tools without asking is called wherever it is shown. */
export const RUNS_UNASKED_LABEL = 'Runs without asking';

/** How a member stands against the saved team a proposal replaces. */
export type PreviewMark = 'added' | 'changed';

/**
 * Whether a member, or any member of its pool, runs tools without asking — a
 * pool member with no `approval` of its own takes the member's.
 *
 * TWIN PARSER: `agentsThatRunAuto` in `apps/daemon/src/v1/teams/utils/unattended.ts`.
 */
export function runsUnasked(member: TeamMember): boolean {
  return (
    member.approval === 'auto' ||
    (member.pool ?? []).some((entry) =>
      memberRunsUnasked(entry.approval, member.approval),
    )
  );
}

/** A pool member runs unasked when its own approval, else its member's, is `auto`. */
export function memberRunsUnasked(
  poolApproval: unknown,
  memberApproval: unknown,
): boolean {
  return (poolApproval ?? memberApproval) === 'auto';
}

/**
 * The fields a model change resets: a window size or parameter of one model
 * means nothing to another.
 */
export function modelChangePatch(model: string | null): {
  model: string | undefined;
  contextWindow: undefined;
  modelParameters: undefined;
} {
  return {
    model: model ?? undefined,
    contextWindow: undefined,
    modelParameters: undefined,
  };
}

/** A block's audience: everyone, or the ids of the members it reaches. */
export type BlockAudience = 'everyone' | string[];

/**
 * A block's audience as its union. The generated client cannot express
 * `'everyone' | string[]` and types it as an empty interface, so every read
 * narrows here; anything else reads as reaching nobody.
 */
export function audienceOf(block: { audience: unknown }): BlockAudience {
  const { audience } = block;
  if (audience === 'everyone') {
    return 'everyone';
  }
  return Array.isArray(audience)
    ? audience.filter((id): id is string => typeof id === 'string')
    : [];
}

/** Whether a block's audience reaches `memberId`. */
export function audienceReaches(
  block: { audience: unknown },
  memberId: string,
): boolean {
  const audience = audienceOf(block);
  return audience === 'everyone' || audience.includes(memberId);
}
