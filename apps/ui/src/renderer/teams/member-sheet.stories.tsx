import type { Meta, StoryObj } from '@storybook/react-vite';
import { useState } from 'react';

import type { TeamMember } from '../autogenerated';
import { SettingRow } from '../components/setting-row';
import { MemberSheet } from './member-sheet';

const ADA: TeamMember = {
  id: 'ada',
  name: 'Ada',
  agent: 'claude',
  approval: 'auto',
  role: 'Leads the task — breaks it down, keeps the plan and hands work to the others.',
  character: 'Calm and precise; asks one question at a time.',
};

const rows = (
  <div className="@container flex flex-col rounded-card bg-card ring-1 ring-border">
    <SettingRow width="compact" label="Agent">
      Claude
    </SettingRow>
    <SettingRow width="compact" label="Model">
      default model
    </SettingRow>
  </div>
);

function Stateful({
  initial,
  problems = [],
  fullScreen = false,
}: {
  initial: TeamMember;
  problems?: string[];
  fullScreen?: boolean;
}): React.JSX.Element {
  const [member, setMember] = useState(initial);
  return (
    <div className="flex h-[720px] justify-end bg-background">
      <MemberSheet
        member={member}
        subtitle="claude · handles the first message"
        issuesFor={(field) =>
          field === 'name' && member.name.trim() === ''
            ? ['A member needs a name']
            : []
        }
        problems={problems}
        fullScreen={fullScreen}
        active
        modelGroup={rows}
        toolsGroup={<p className="text-[13px]">MCP: 3 servers</p>}
        poolGroup={<p className="text-[13px]">No pool members</p>}
        sizeLine={
          <p className="text-[13px] text-muted-foreground">
            Always-on instructions: ~1.2k tokens
          </p>
        }
        removeWarning="Ada handles the first message; the entry becomes empty."
        canRemove
        place={{ index: 0, of: 4 }}
        onMove={() => {}}
        uploadAvatar={async () => 'stored.png'}
        onPatch={(patch) => setMember((current) => ({ ...current, ...patch }))}
        onRemove={() => {}}
        onClose={() => {}}
      />
    </div>
  );
}

const meta = {
  title: 'Teams/MemberSheet',
  component: MemberSheet,
  args: {
    member: ADA,
    subtitle: 'claude',
    issuesFor: () => [],
    problems: [],
    fullScreen: false,
    active: true,
    modelGroup: rows,
    toolsGroup: null,
    poolGroup: null,
    sizeLine: null,
    removeWarning: null,
    canRemove: true,
    place: { index: 0, of: 1 },
    onMove: () => {},
    uploadAvatar: async () => 'stored.png',
    onPatch: () => {},
    onRemove: () => {},
    onClose: () => {},
  },
} satisfies Meta<typeof MemberSheet>;

export default meta;
type Story = StoryObj<typeof meta>;

export const Default: Story = { render: () => <Stateful initial={ADA} /> };

export const WithProblems: Story = {
  render: () => (
    <Stateful
      initial={{ ...ADA, name: '' }}
      problems={['A member needs a name']}
    />
  ),
};

export const Phone: Story = {
  render: () => <Stateful initial={ADA} fullScreen />,
};
