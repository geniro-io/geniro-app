import { cva } from 'class-variance-authority';
import { ArrowDown, ArrowLeft, ArrowUp, Pencil, Trash2, X } from 'lucide-react';
import { useEffect, useRef, useState } from 'react';

import type { TeamMember } from '../autogenerated';
import { AvatarPicker } from '../components/avatar-picker';
import { ConfirmDialog } from '../components/confirm-dialog';
import { ErrorText } from '../components/error-text';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Field } from '../components/field';
import { type AvatarLook, MemberAvatar } from '../components/member-avatar';
import { PanelResizeHandle, usePanelWidth } from '../components/panel-resize';
import { Button } from '../components/ui/button';
import { Input } from '../components/ui/input';
import { Popover } from '../components/ui/popover';
import { useLatestCallback } from '../components/use-latest-callback';
import { HeldProblems } from './held-problems';
import type { MemberField } from './member-validate';

type MemberPatch = Partial<Omit<TeamMember, 'id'>>;

const sheetVariants = cva(
  'flex min-h-0 flex-col bg-surface-raised transition-[translate,opacity] duration-[175ms] ease-out motion-reduce:transition-none',
  {
    variants: {
      fullScreen: {
        true: 'fixed inset-0 z-40',
        false:
          'relative h-full shrink-0 rounded-l-card shadow-panel-lg ring-1 ring-border',
      },
      entered: {
        true: 'translate-x-0 opacity-100',
        false: 'translate-x-4 opacity-0',
      },
    },
  },
);

/** One group of the sheet: a heading, its warning dot, and its rows. */
function SheetGroup({
  title,
  warning = false,
  children,
}: {
  title: string;
  warning?: boolean;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <section className="flex flex-col gap-3" aria-label={title}>
      <h3 className="flex items-center gap-2 text-base font-semibold">
        {title}
        {warning ? (
          <span
            role="img"
            aria-label="needs attention"
            className="size-2 rounded-pill bg-warning"
          />
        ) : null}
      </h3>
      {children}
    </section>
  );
}

/**
 * Everything about one member, beside the page rather than over it: the
 * profile (face, name, character), what it does and how, the model it runs,
 * its tools and its pool. It is non-modal — another card switches it — and
 * on a phone it becomes a page of its own with a back arrow. Problems the
 * editor would refuse stay pinned at its top.
 */
export function MemberSheet({
  member,
  subtitle,
  issuesFor,
  problems,
  fullScreen,
  active,
  focusName = false,
  modelGroup,
  toolsGroup,
  poolGroup,
  sizeLine,
  removeWarning,
  canRemove,
  place,
  uploadAvatar,
  onPatch,
  onMove,
  onRemove,
  onClose,
}: {
  member: TeamMember;
  /** "claude · handles the first message" */
  subtitle: string;
  issuesFor: (field: MemberField) => string[];
  /** Problems to keep in view, in words. */
  problems: readonly string[];
  fullScreen: boolean;
  /** Whether the screen holding the sheet is on view; a hidden one hears no keys. */
  active: boolean;
  /** Put the cursor in Name as the sheet opens (a member just added). */
  focusName?: boolean;
  modelGroup: React.ReactNode;
  toolsGroup: React.ReactNode;
  poolGroup: React.ReactNode;
  sizeLine: React.ReactNode;
  /** What removing breaks (stages it owns, the first message), or null. */
  removeWarning: string | null;
  canRemove: boolean;
  /** Where the member stands in the team's order. */
  place: { index: number; of: number };
  uploadAvatar: (base64: string) => Promise<string>;
  onPatch: (patch: MemberPatch) => void;
  onMove: (by: -1 | 1) => void;
  onRemove: () => void;
  onClose: () => void;
}): React.JSX.Element {
  const { width, minWidth, maxWidth, startResize, resizeTo } = usePanelWidth({
    storageKey: 'teams.memberSheetWidth',
    defaultWidth: 460,
    minWidth: 400,
    maxWidth: 720,
    handleEdge: 'left',
  });
  const [entered, setEntered] = useState(false);
  const [pickerOpen, setPickerOpen] = useState(false);
  const [removeOpen, setRemoveOpen] = useState(false);
  const avatarRef = useRef<HTMLButtonElement | null>(null);
  const nameRef = useRef<HTMLInputElement | null>(null);
  const sheetRef = useRef<HTMLElement | null>(null);
  const name = member.name;

  useEffect(() => {
    const frame = window.requestAnimationFrame(() => setEntered(true));
    return () => window.cancelAnimationFrame(frame);
  }, []);

  useEffect(() => {
    if (focusName) {
      nameRef.current?.focus();
    }
  }, [member.id, focusName]);

  const close = useLatestCallback(() => onClose(), [onClose]);
  useEffect(() => {
    if (!active) {
      return;
    }
    const onKey = (event: KeyboardEvent): void => {
      // Escape belongs to an open picker or menu inside the sheet first.
      if (
        event.key === 'Escape' &&
        !event.defaultPrevented &&
        !sheetRef.current?.querySelector('[aria-expanded="true"]')
      ) {
        close();
      }
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [active, close]);

  const fieldErrors = (field: MemberField): React.ReactNode =>
    issuesFor(field).map((message) => (
      <ErrorText key={message} className="text-xs break-words">
        {message}
      </ErrorText>
    ));
  const hasIssues = (fields: readonly MemberField[]): boolean =>
    fields.some((field) => issuesFor(field).length > 0);

  return (
    <aside
      ref={sheetRef}
      data-slot="member-sheet"
      data-member-id={member.id}
      aria-label={`Member ${name || member.id}`}
      style={fullScreen ? undefined : { width }}
      className={sheetVariants({ fullScreen, entered })}>
      {fullScreen ? null : (
        <PanelResizeHandle
          edge="left"
          label="Resize the member panel"
          onMouseDown={startResize}
          value={width}
          min={minWidth}
          max={maxWidth}
          onResize={resizeTo}
        />
      )}
      <div className="flex shrink-0 items-center gap-2 px-4 pt-3">
        {fullScreen ? (
          <Button
            type="button"
            variant="ghost"
            size="icon"
            aria-label="Back to the team"
            className="size-8 rounded-control"
            onClick={onClose}>
            <ArrowLeft />
          </Button>
        ) : null}
        <span className="min-w-0 flex-1 truncate text-sm text-muted-foreground">
          {subtitle}
        </span>
        {fullScreen ? null : (
          <Button
            type="button"
            variant="ghost"
            size="icon"
            aria-label="Close member"
            className="size-8 rounded-control"
            onClick={onClose}>
            <X />
          </Button>
        )}
      </div>
      <HeldProblems
        problems={problems}
        slot="member-sheet-problems"
        role="status"
        className="mx-4 mt-2 shrink-0"
      />

      <div className="min-h-0 flex-1 overflow-y-auto">
        <div className="flex flex-col gap-8 px-6 pt-4 pb-8">
          <div className="flex flex-col items-center gap-3 text-center">
            <span className="relative">
              <button
                ref={avatarRef}
                type="button"
                data-menu-trigger
                aria-haspopup="dialog"
                aria-expanded={pickerOpen}
                aria-label={`Change ${name || 'this member'}’s avatar`}
                className="group/avatar relative rounded-pill outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 focus-visible:ring-offset-surface-raised"
                onClick={() => setPickerOpen((open) => !open)}>
                <MemberAvatar
                  name={name || member.id}
                  avatar={member.avatar}
                  colorKey={member.id}
                  size={96}
                />
                <span
                  aria-hidden="true"
                  className="absolute inset-0 flex items-center justify-center rounded-pill bg-foreground/40 text-background opacity-0 transition-opacity group-hover/avatar:opacity-100 group-focus-visible/avatar:opacity-100">
                  <Pencil className="size-5" />
                </span>
              </button>
              <Popover
                open={pickerOpen}
                onClose={() => setPickerOpen(false)}
                triggerRef={avatarRef}
                side="bottom"
                align="start"
                anchor="viewport"
                label="Avatar"
                className="p-4">
                <AvatarPicker
                  name={name || member.id}
                  colorKey={member.id}
                  value={member.avatar ?? undefined}
                  upload={uploadAvatar}
                  onChange={(avatar: AvatarLook | undefined) =>
                    onPatch({ avatar })
                  }
                />
              </Popover>
            </span>
            <Input
              ref={nameRef}
              id="member-name"
              aria-label="Name"
              value={name}
              placeholder="Name"
              aria-invalid={issuesFor('name').length > 0 || undefined}
              className="h-10 w-full max-w-sm border-transparent bg-transparent text-center text-xl font-semibold shadow-none hover:border-field-border focus-visible:border-field-border"
              onChange={(event) => onPatch({ name: event.target.value })}
            />
            {fieldErrors('name')}
          </div>

          <SheetGroup title="Identity" warning={hasIssues(['character'])}>
            <Field
              label="Character"
              htmlFor="member-character"
              hint="Optional — its manner and tone. Only its own turns carry it.">
              <ExpandableTextarea
                id="member-character"
                title="Character"
                value={member.character ?? ''}
                rows={2}
                placeholder="Terse and precise."
                onChange={(next) => onPatch({ character: next || undefined })}
              />
              {fieldErrors('character')}
            </Field>
          </SheetGroup>

          <SheetGroup
            title="Role & instructions"
            warning={hasIssues(['role', 'instructions'])}>
            <Field
              label="Role"
              htmlFor="member-role"
              hint="What it does — visible to the others, so they can hand it work.">
              <ExpandableTextarea
                id="member-role"
                title="Role"
                value={member.role ?? ''}
                rows={3}
                placeholder="Reviews a diff or branch and reports findings by severity."
                onChange={(next) => onPatch({ role: next || undefined })}
              />
              {fieldErrors('role')}
            </Field>
            <Field
              label="Instructions"
              htmlFor="member-instructions"
              hint="How it works — private: only its own turns carry it.">
              <ExpandableTextarea
                id="member-instructions"
                title="Instructions"
                value={member.instructions ?? ''}
                rows={5}
                onChange={(next) =>
                  onPatch({ instructions: next || undefined })
                }
              />
              {fieldErrors('instructions')}
            </Field>
            {sizeLine}
          </SheetGroup>

          <SheetGroup title="Model" warning={hasIssues(['settings'])}>
            {modelGroup}
            {fieldErrors('settings')}
          </SheetGroup>

          <SheetGroup title="Tools & MCP">
            {toolsGroup}
            <p className="text-sm text-muted-foreground">
              Every member can call every other member.
            </p>
          </SheetGroup>

          <SheetGroup title="Pool" warning={hasIssues(['pool'])}>
            {poolGroup}
            {fieldErrors('pool')}
          </SheetGroup>

          <div className="flex flex-wrap items-center gap-2">
            <span className="text-sm text-muted-foreground tabular-nums">
              {place.index + 1} of {place.of} in the team
            </span>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              className="h-8 gap-1.5 rounded-control"
              disabled={place.index === 0}
              onClick={() => onMove(-1)}>
              <ArrowUp aria-hidden="true" />
              Move earlier
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              className="h-8 gap-1.5 rounded-control"
              disabled={place.index >= place.of - 1}
              onClick={() => onMove(1)}>
              <ArrowDown aria-hidden="true" />
              Move later
            </Button>
          </div>

          {canRemove ? (
            <Button
              type="button"
              variant="ghost"
              className="self-start gap-2 rounded-control text-muted-foreground hover:bg-destructive/10 hover:text-destructive"
              onClick={() => setRemoveOpen(true)}>
              <Trash2 aria-hidden="true" />
              Remove member
            </Button>
          ) : (
            <p className="text-sm text-muted-foreground">
              A team keeps at least one member.
            </p>
          )}
        </div>
      </div>

      <ConfirmDialog
        open={removeOpen}
        title="Remove member"
        confirmLabel="Remove"
        busyLabel="Removing…"
        onCancel={() => setRemoveOpen(false)}
        onConfirm={() => {
          setRemoveOpen(false);
          onRemove();
        }}>
        <p>
          Remove{' '}
          <span className="font-medium text-foreground">
            {name || member.id}
          </span>{' '}
          from the team?
          {removeWarning === null ? null : ` ${removeWarning}`}
        </p>
      </ConfirmDialog>
    </aside>
  );
}
