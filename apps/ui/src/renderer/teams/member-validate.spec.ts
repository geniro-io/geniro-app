import { describe, expect, it } from 'vitest';

import type { InstructionBlock, TeamMember } from '../autogenerated';
import {
  MAX_MEMBER_CHARACTER_LENGTH,
  MAX_MEMBER_NAME_LENGTH,
  mcpServerNameProblem,
  validateInstructionBlock,
  validateMember,
} from './member-validate';

const MEMBER: TeamMember = {
  id: 'lead',
  name: 'Lead',
  agent: 'claude',
  approval: 'auto',
};

const block = (fields: Partial<InstructionBlock> = {}): InstructionBlock => ({
  id: 'b1',
  title: 'Style',
  text: 'Short sentences.',
  audience: 'everyone',
  ...fields,
});

describe('validateMember mirrors the daemon’s member schema', () => {
  it('accepts a plain member and one at every length limit', () => {
    expect(validateMember(MEMBER)).toEqual([]);
    expect(
      validateMember({
        ...MEMBER,
        name: 'n'.repeat(MAX_MEMBER_NAME_LENGTH),
        character: 'c'.repeat(MAX_MEMBER_CHARACTER_LENGTH),
      }),
    ).toEqual([]);
  });

  it('refuses a blank name and one past the limit, on the name field', () => {
    expect(validateMember({ ...MEMBER, name: '  ' })).toEqual([
      { field: 'name', message: 'A member needs a name.' },
    ]);
    expect(
      validateMember({
        ...MEMBER,
        name: 'n'.repeat(MAX_MEMBER_NAME_LENGTH + 1),
      }),
    ).toEqual([
      { field: 'name', message: expect.stringContaining('at most 80') },
    ]);
  });

  it('refuses a character past the limit', () => {
    expect(
      validateMember({
        ...MEMBER,
        character: 'c'.repeat(MAX_MEMBER_CHARACTER_LENGTH + 1),
      }),
    ).toEqual([
      { field: 'character', message: expect.stringContaining('at most 2000') },
    ]);
  });

  it.each([
    ['role', 'Role', 'role'],
    ['instructions', 'Instructions', 'instructions'],
    ['character', 'Character', 'character'],
    ['model', 'Model', 'settings'],
    ['effort', 'Effort', 'settings'],
    ['contextWindow', 'Context window', 'settings'],
    ['configDir', 'Config directory', 'settings'],
  ])('flags a NUL in `%s` under its field', (key, label, field) => {
    // The escape, never the raw byte — a NUL in a .ts file has no diff.
    expect(
      validateMember({ ...MEMBER, [key]: 'a\u0000b' } as TeamMember),
    ).toEqual([
      { field, message: `${label} contains an invisible NUL character.` },
    ]);
  });

  it('flags a NUL in a pool member’s field, naming the pool member', () => {
    expect(
      validateMember({
        ...MEMBER,
        pool: [{ agent: 'codex', configDir: '/p\u0000x' }],
      }),
    ).toEqual([
      {
        field: 'pool',
        message:
          'Pool member 2: Config directory contains an invisible NUL character.',
      },
    ]);
  });

  it('leaves an ESC, a form-feed and line breaks in a role alone', () => {
    expect(
      validateMember({ ...MEMBER, role: 'bold \u001b[1mx\u000c\n\tmore\r\n' }),
    ).toEqual([]);
  });

  it('flags a switched-off MCP list past the cap, and a bad name, naming whose', () => {
    expect(
      validateMember({
        ...MEMBER,
        mcpDisabled: Array.from({ length: 101 }, (_, i) => `s${i}`),
      }),
    ).toEqual([
      { field: 'settings', message: expect.stringContaining('at most 100') },
    ]);
    expect(
      validateMember({
        ...MEMBER,
        mcpDisabled: ['code\tgraph'],
        pool: [{ agent: 'codex', mcpDisabled: [''] }],
      }),
    ).toEqual([
      {
        field: 'settings',
        message: expect.stringContaining(
          'This member: the switched-off MCP server name',
        ),
      },
      {
        field: 'pool',
        message: expect.stringContaining('Pool member 2: the switched-off'),
      },
    ]);
  });
});

describe('mcpServerNameProblem', () => {
  it('names each refusal, and accepts an ordinary name', () => {
    expect(mcpServerNameProblem('claude.ai Gmail')).toBeNull();
    expect(mcpServerNameProblem('')).toBe('is empty');
    expect(mcpServerNameProblem('x'.repeat(257))).toBe(
      'is longer than 256 characters',
    );
    expect(mcpServerNameProblem('a\u007fb')).toBe(
      'contains invisible control characters',
    );
  });
});

describe('validateInstructionBlock', () => {
  it('accepts a block, an empty text included', () => {
    expect(validateInstructionBlock(block())).toEqual([]);
    expect(validateInstructionBlock(block({ text: '' }))).toEqual([]);
  });

  it('refuses a title past the limit, and a NUL in the title', () => {
    expect(validateInstructionBlock(block({ title: 't'.repeat(81) }))).toEqual([
      { field: 'title', message: expect.stringContaining('at most 80') },
    ]);
    expect(validateInstructionBlock(block({ title: 'a\u0000' }))).toEqual([
      { field: 'title', message: expect.stringContaining('NUL') },
    ]);
  });

  it('refuses control characters in the text but keeps tabs and line breaks', () => {
    expect(validateInstructionBlock(block({ text: 'a\u0007b' }))).toEqual([
      { field: 'text', message: expect.stringContaining('control characters') },
    ]);
    expect(validateInstructionBlock(block({ text: 'one\n\ttwo\r\n' }))).toEqual(
      [],
    );
  });
});
