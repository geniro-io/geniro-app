import { hasControlCharacters } from '../../shared/contracts';
import type { InstructionBlock, TeamMember } from '../autogenerated';

/**
 * The member and block field limits the daemon's schema refuses past.
 *
 * TWIN: `MAX_MEMBER_NAME_LENGTH`, `MAX_MEMBER_CHARACTER_LENGTH`,
 * `MAX_INSTRUCTION_BLOCK_TITLE_LENGTH` and `MAX_AVATAR_VALUE_LENGTH` in the
 * daemon's `v1/teams/teams.types.ts`. The builder autosaves the whole team in
 * one write, so a field refused there stops every later edit from saving.
 */
export const MAX_MEMBER_NAME_LENGTH = 80;
export const MAX_MEMBER_CHARACTER_LENGTH = 2000;
export const MAX_INSTRUCTION_BLOCK_TITLE_LENGTH = 80;
export const MAX_AVATAR_VALUE_LENGTH = 512;

/**
 * How many MCP servers one member or pool member may switch off, and how long
 * a name may be.
 *
 * TWIN: `MAX_MEMBER_MCP_DISABLED` / `MAX_MCP_SERVER_NAME_LENGTH` in the daemon's
 * `v1/teams/teams.types.ts`. Change one, change the other.
 */
export const MAX_MEMBER_MCP_DISABLED = 100;
export const MAX_MCP_SERVER_NAME_LENGTH = 256;

/** The member field an issue belongs to, so the inspector shows it there. */
export type MemberField =
  'name' | 'character' | 'role' | 'instructions' | 'settings' | 'pool';

export interface MemberIssue {
  field: MemberField;
  message: string;
}

export type BlockField = 'title' | 'text';

export interface BlockIssue {
  field: BlockField;
  message: string;
}

/**
 * The member fields the daemon refuses a NUL in, with the label the inspector
 * gives each — every one reaches a spawned CLI (argv or env) or a prompt.
 * A NUL and nothing wider: the daemon's schema also reads stored teams.
 *
 * TWIN: the `argvSafe` refinements on `TeamMemberSchema` in the daemon's
 * `v1/teams/teams.types.ts`. Add a field there, add it here.
 */
const ARGV_TEXT_FIELDS: readonly (readonly [
  keyof TeamMember,
  string,
  MemberField,
])[] = [
  ['id', 'Member id', 'settings'],
  ['name', 'Name', 'name'],
  ['character', 'Character', 'character'],
  ['role', 'Role', 'role'],
  ['instructions', 'Instructions', 'instructions'],
  ['model', 'Model', 'settings'],
  ['effort', 'Effort', 'settings'],
  ['contextWindow', 'Context window', 'settings'],
  ['configDir', 'Config directory', 'settings'],
];

/** The text fields of one agent-pool member — `TeamAgentPoolMemberSchema`'s twin. */
const POOL_MEMBER_TEXT_FIELDS: readonly (readonly [
  'model' | 'effort' | 'contextWindow' | 'configDir',
  string,
])[] = [
  ['model', 'Model'],
  ['effort', 'Effort'],
  ['contextWindow', 'Context window'],
  ['configDir', 'Config directory'],
];

const NUL = '\u0000';

/**
 * What the daemon would refuse about one switched-off server name, or null.
 * Every control character, tab and newline included — wider than the NUL rule,
 * because the name reaches a CLI as argv, a config key or a JSON file.
 *
 * TWIN: `mcpServerNameIsClean` and `McpDisabledSchema` in the daemon's
 * `v1/teams/teams.types.ts`.
 */
export function mcpServerNameProblem(name: string): string | null {
  if (name.length === 0) {
    return 'is empty';
  }
  if (name.length > MAX_MCP_SERVER_NAME_LENGTH) {
    return `is longer than ${MAX_MCP_SERVER_NAME_LENGTH} characters`;
  }
  for (let i = 0; i < name.length; i += 1) {
    const code = name.charCodeAt(i);
    if (code < 0x20 || code === 0x7f) {
      return 'contains invisible control characters';
    }
  }
  return null;
}

function mcpDisabledIssues(
  owner: string,
  field: MemberField,
  names: readonly string[] | undefined,
): MemberIssue[] {
  if (names === undefined) {
    return [];
  }
  const issues: MemberIssue[] = [];
  if (names.length > MAX_MEMBER_MCP_DISABLED) {
    issues.push({
      field,
      message: `${owner} switches off ${names.length} MCP servers — at most ${MAX_MEMBER_MCP_DISABLED} are allowed.`,
    });
  }
  for (const name of names) {
    const problem = mcpServerNameProblem(name);
    if (problem !== null) {
      issues.push({
        field,
        message: `${owner}: the switched-off MCP server name “${name}” ${problem}.`,
      });
    }
  }
  return issues;
}

/**
 * Every refusal the daemon's member schema would make about one member, each
 * filed under the inspector field it belongs to.
 */
export function validateMember(member: TeamMember): MemberIssue[] {
  const issues: MemberIssue[] = [];
  if (member.name.trim().length === 0) {
    issues.push({ field: 'name', message: 'A member needs a name.' });
  } else if (member.name.length > MAX_MEMBER_NAME_LENGTH) {
    issues.push({
      field: 'name',
      message: `A name may have at most ${MAX_MEMBER_NAME_LENGTH} characters; this one has ${member.name.length}.`,
    });
  }
  if ((member.character?.length ?? 0) > MAX_MEMBER_CHARACTER_LENGTH) {
    issues.push({
      field: 'character',
      message: `Character may have at most ${MAX_MEMBER_CHARACTER_LENGTH} characters; this has ${member.character?.length}.`,
    });
  }
  if ((member.avatar?.value?.length ?? 0) > MAX_AVATAR_VALUE_LENGTH) {
    issues.push({
      field: 'settings',
      message: `The avatar may have at most ${MAX_AVATAR_VALUE_LENGTH} characters.`,
    });
  }
  for (const [key, label, field] of ARGV_TEXT_FIELDS) {
    const value = member[key];
    if (typeof value === 'string' && value.includes(NUL)) {
      issues.push({
        field,
        message: `${label} contains an invisible NUL character.`,
      });
    }
  }
  issues.push(
    ...mcpDisabledIssues('This member', 'settings', member.mcpDisabled),
  );
  (member.pool ?? []).forEach((entry, index) => {
    const owner = `Pool member ${index + 2}`;
    issues.push(...mcpDisabledIssues(owner, 'pool', entry.mcpDisabled));
    for (const [key, label] of POOL_MEMBER_TEXT_FIELDS) {
      const value = entry[key];
      if (typeof value === 'string' && value.includes(NUL)) {
        issues.push({
          field: 'pool',
          message: `${owner}: ${label} contains an invisible NUL character.`,
        });
      }
    }
  });
  return issues;
}

/**
 * Every refusal the daemon's block schema would make about one instruction
 * block. Its text goes through the user's own custom-instructions rule (every
 * C0 control character but tab and line breaks); an empty text is admitted,
 * since a block just added is saved before it is written.
 */
export function validateInstructionBlock(
  block: InstructionBlock,
): BlockIssue[] {
  const issues: BlockIssue[] = [];
  if (block.title.length > MAX_INSTRUCTION_BLOCK_TITLE_LENGTH) {
    issues.push({
      field: 'title',
      message: `A title may have at most ${MAX_INSTRUCTION_BLOCK_TITLE_LENGTH} characters; this one has ${block.title.length}.`,
    });
  }
  if (block.title.includes(NUL) || block.id.includes(NUL)) {
    issues.push({
      field: 'title',
      message: 'The title contains an invisible NUL character.',
    });
  }
  if (hasControlCharacters(block.text)) {
    issues.push({
      field: 'text',
      message:
        'Contains invisible control characters. Pasting from a word processor or a terminal can add them.',
    });
  }
  return issues;
}
