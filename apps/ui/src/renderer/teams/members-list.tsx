import { cva } from 'class-variance-authority';
import {
  ArrowDown,
  ArrowUp,
  CircleAlert,
  MoreVertical,
  Plus,
  Trash2,
} from 'lucide-react';
import { useRef, useState } from 'react';

import type { TeamMember } from '../autogenerated';
import { Button } from '../components/ui/button';
import { Menu } from '../components/ui/menu';
import { AgentAvatar } from './agent-avatar';
import { memberLabels } from './member-pick';

const rowVariants = cva(
  'group/row flex min-w-0 items-center gap-1 rounded-md pr-1 transition-colors',
  {
    variants: {
      selected: {
        true: 'bg-accent text-accent-foreground',
        false: 'hover:bg-accent/50',
      },
    },
  },
);

/**
 * The team's members, in order: press one to edit it in the inspector; each
 * row's menu moves or removes it. The last member cannot be removed — a team
 * needs one, and the save would be refused.
 */
export function MembersList({
  members,
  selectedId,
  handlerId,
  problemIds,
  onSelect,
  onAdd,
  onMove,
  onRemove,
}: {
  members: readonly TeamMember[];
  selectedId: string | null;
  /** The member the first message goes to. */
  handlerId: string | null;
  /** Members with a problem that holds the save back. */
  problemIds: ReadonlySet<string>;
  onSelect: (memberId: string) => void;
  onAdd: () => void;
  onMove: (memberId: string, by: -1 | 1) => void;
  onRemove: (memberId: string) => void;
}): React.JSX.Element {
  const labels = memberLabels(members);
  return (
    <div className="flex flex-col gap-1">
      <ul
        aria-label="Members"
        data-slot="members-list"
        className="flex flex-col gap-0.5">
        {members.map((member, index) => (
          <MemberRow
            key={member.id}
            member={member}
            label={labels.get(member.id)!}
            selected={member.id === selectedId}
            handles={member.id === handlerId}
            problem={problemIds.has(member.id)}
            first={index === 0}
            last={index === members.length - 1}
            only={members.length === 1}
            onSelect={() => onSelect(member.id)}
            onMove={(by) => onMove(member.id, by)}
            onRemove={() => onRemove(member.id)}
          />
        ))}
      </ul>
      <Button
        type="button"
        variant="ghost"
        size="sm"
        className="justify-start gap-2 text-muted-foreground"
        onClick={onAdd}>
        <Plus aria-hidden="true" />
        Add member
      </Button>
    </div>
  );
}

function MemberRow({
  member,
  label,
  selected,
  handles,
  problem,
  first,
  last,
  only,
  onSelect,
  onMove,
  onRemove,
}: {
  member: TeamMember;
  label: string;
  selected: boolean;
  handles: boolean;
  problem: boolean;
  first: boolean;
  last: boolean;
  only: boolean;
  onSelect: () => void;
  onMove: (by: -1 | 1) => void;
  onRemove: () => void;
}): React.JSX.Element {
  const [menuOpen, setMenuOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  return (
    <li
      data-slot="member-row"
      data-member-id={member.id}
      className={rowVariants({ selected })}>
      <button
        type="button"
        aria-current={selected ? 'true' : undefined}
        className="flex min-w-0 flex-1 items-center gap-2 rounded-md px-2 py-1.5 text-left outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50"
        onClick={onSelect}>
        <AgentAvatar label={member.name || member.id} />
        <span className="flex min-w-0 flex-1 flex-col">
          <span className="truncate text-sm font-medium">{label}</span>
          <span className="truncate text-xs text-muted-foreground">
            {handles ? `${member.agent} · first message` : member.agent}
          </span>
        </span>
        {problem ? (
          <CircleAlert
            aria-label="Has a problem"
            className="size-3.5 shrink-0 text-destructive"
          />
        ) : null}
      </button>
      <span className="relative inline-flex shrink-0">
        <Button
          ref={triggerRef}
          type="button"
          variant="ghost"
          size="icon"
          data-menu-trigger
          className="size-6 text-muted-foreground"
          aria-haspopup="listbox"
          aria-expanded={menuOpen}
          aria-label={`Options for ${label}`}
          onClick={() => setMenuOpen((open) => !open)}>
          <MoreVertical className="size-3.5" aria-hidden="true" />
        </Button>
        <Menu
          open={menuOpen}
          side="bottom"
          align="end"
          anchor="viewport"
          triggerRef={triggerRef}
          className="min-w-44"
          groups={[
            {
              items: [
                {
                  value: 'up',
                  label: 'Move up',
                  icon: <ArrowUp className="size-4" />,
                  action: true,
                  disabled: first,
                },
                {
                  value: 'down',
                  label: 'Move down',
                  icon: <ArrowDown className="size-4" />,
                  action: true,
                  disabled: last,
                },
                {
                  value: 'remove',
                  label: 'Remove',
                  icon: <Trash2 className="size-4" />,
                  action: true,
                  tone: 'destructive',
                  disabled: only,
                  ...(only
                    ? { title: 'A team needs at least one member' }
                    : {}),
                },
              ],
            },
          ]}
          onSelect={(value) => {
            setMenuOpen(false);
            if (value === 'up') {
              onMove(-1);
            } else if (value === 'down') {
              onMove(1);
            } else {
              onRemove();
            }
          }}
          onClose={() => setMenuOpen(false)}
        />
      </span>
    </li>
  );
}
