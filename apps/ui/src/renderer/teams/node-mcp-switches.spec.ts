import { describe, expect, it } from 'vitest';

import type {
  AgentMcpListingDto as AgentMcpListing,
  AgentMcpServer,
} from '../autogenerated';
import {
  APPROVE_IN_A_CHAT,
  nextMcpDisabled,
  NOT_IN_PROFILE,
  OFF_IN_PROFILE,
  withNodeSwitches,
} from './node-mcp-switches';

function row(
  name: string,
  patch: Partial<AgentMcpServer> = {},
): AgentMcpServer {
  return {
    name,
    target: null,
    transport: 'stdio',
    status: 'connected',
    detail: null,
    scope: 'user',
    shadowsUser: false,
    disabled: false,
    // The FOLDER switch's reason — the builder has no folder, so it is never
    // what decides a node's switch.
    toggleUnavailableReason: 'a folder-scoped reason',
    signInUnavailableReason: null,
    approveUnavailableReason: null,
    turnToggleUnavailableReason: null,
    ...patch,
  };
}

function listing(
  servers: AgentMcpServer[],
  patch: Partial<AgentMcpListing> = {},
): AgentMcpListing {
  return {
    servers,
    unavailableReason: null,
    pending: false,
    interactiveOnlyNote: null,
    plugins: [],
    ...patch,
  };
}

describe('withNodeSwitches', () => {
  it('draws the node’s own list as the rows’ state, switchable unless the daemon says why not', () => {
    const out = withNodeSwitches(
      listing([
        row('codegraph'),
        row('linear'),
        row('cua_repl', { turnToggleUnavailableReason: 'a plugin’s server' }),
      ]),
      ['linear'],
    )!;
    expect(
      out.servers.map((server) => [
        server.name,
        server.disabled,
        server.toggleUnavailableReason,
      ]),
    ).toEqual([
      ['codegraph', false, null],
      ['linear', true, null],
      ['cua_repl', false, 'a plugin’s server'],
    ]);
    // Approving is a folder's choice, never a node's switch.
    expect(
      out.servers.every(
        (s) => s.approveUnavailableReason === APPROVE_IN_A_CHAT,
      ),
    ).toBe(true);
  });

  it('locks a server the profile itself has off — a node cannot switch it on', () => {
    const [server] = withNodeSwitches(
      listing([row('playwright-2', { status: 'disabled', disabled: true })]),
      [],
    )!.servers;
    expect(server).toMatchObject({
      disabled: true,
      toggleUnavailableReason: OFF_IN_PROFILE,
    });
  });

  it('keeps a switched-off name the profile does not list, so it can be switched back on', () => {
    const out = withNodeSwitches(listing([row('codegraph')]), ['old-server']);
    expect(out!.servers.map((server) => server.name)).toEqual([
      'codegraph',
      'old-server',
    ]);
    expect(out!.servers[1]).toMatchObject({
      disabled: true,
      toggleUnavailableReason: null,
      target: NOT_IN_PROFILE,
    });
  });

  it('adds no such rows while the listing is still dialling', () => {
    const out = withNodeSwitches(listing([], { pending: true }), ['codegraph']);
    expect(out!.servers).toEqual([]);
  });

  it('passes a listing that could not be read through untouched', () => {
    const failed = listing([], { unavailableReason: 'cannot list' });
    expect(withNodeSwitches(failed, ['x'])).toBe(failed);
  });
});

describe('nextMcpDisabled', () => {
  it('adds a server switched off and removes one switched back on', () => {
    expect(nextMcpDisabled(undefined, 'a', false)).toEqual(['a']);
    expect(nextMcpDisabled(['a'], 'b', false)).toEqual(['a', 'b']);
    expect(nextMcpDisabled(['a', 'b'], 'a', true)).toEqual(['b']);
    // Switching off twice does not list it twice.
    expect(nextMcpDisabled(['a'], 'a', false)).toEqual(['a']);
  });

  it('is undefined once nothing is off, so the YAML carries no empty key', () => {
    expect(nextMcpDisabled(['a'], 'a', true)).toBeUndefined();
  });
});
