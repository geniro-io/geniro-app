import type {
  AgentMcpAllowListCapability,
  AgentMcpListingDto as AgentMcpListing,
  AgentMcpServer,
} from '../autogenerated';

/**
 * A team member's own MCP switches, laid over the listing of the servers its
 * PROFILE loads.
 *
 * The listing is the CLI's answer about a profile; the switches are the member's
 * (`TeamMember.mcpDisabled`, or a pool member's), applied per turn by
 * the daemon and written into no config of the CLI's. So the overlay owns
 * exactly three things on a row and leaves the rest the CLI's:
 *
 * - `disabled` — whether THIS member runs without it;
 * - the lock — a row this member cannot switch says so in the daemon's own
 *   sentence (`turnToggleUnavailableReason`), and a row the profile ITSELF has
 *   off says that a member can only switch servers off, never on;
 * - approving — a per-FOLDER choice the builder has no folder for, so its
 *   button is replaced by that sentence rather than wired to a switch it is not.
 *
 * A name the member switched off that the profile does not list (a project
 * server of the run folder, a server removed from the profile since) is SHOWN
 * rather than dropped: the daemon still applies it to any server of that name
 * a run loads, and a list the reader cannot see is one they cannot clear. Not
 * while the listing is still dialling (`pending`), when every name would read
 * as missing.
 */
export function withNodeSwitches(
  listing: AgentMcpListing | undefined,
  disabled: readonly string[] | undefined,
): AgentMcpListing | undefined {
  if (listing === undefined || listing.unavailableReason !== null) {
    return listing;
  }
  const off = new Set(disabled ?? []);
  const servers: AgentMcpServer[] = listing.servers.map((row) => {
    const shared = {
      ...row,
      approveUnavailableReason: APPROVE_IN_A_CHAT,
    };
    if (row.disabled) {
      return {
        ...shared,
        disabled: true,
        toggleUnavailableReason: OFF_IN_PROFILE,
      };
    }
    return {
      ...shared,
      disabled: off.has(row.name),
      toggleUnavailableReason: row.turnToggleUnavailableReason ?? null,
    };
  });
  if (!listing.pending) {
    const listed = new Set(listing.servers.map((row) => row.name));
    for (const name of off) {
      if (!listed.has(name)) {
        servers.push(unlistedRow(name));
      }
    }
  }
  return { ...listing, servers };
}

/**
 * The member's list after one switch: a server switched OFF is added, one
 * switched back ON removed. Undefined once nothing is off, so the YAML carries
 * no empty key. Order is kept — it is the order the user switched them in.
 */
export function nextMcpDisabled(
  current: readonly string[] | undefined,
  server: string,
  enabled: boolean,
): string[] | undefined {
  const rest = (current ?? []).filter((name) => name !== server);
  const next = enabled ? rest : [...rest, server];
  return next.length === 0 ? undefined : next;
}

/** The servers a turn of this member loads now: the profile's own that are on and not switched off by the member. */
export function loadingServerNames(
  listing: AgentMcpListing | undefined,
  disabled: readonly string[] | undefined,
): string[] {
  const off = new Set(disabled ?? []);
  return (listing?.servers ?? [])
    .filter((row) => !row.disabled && !off.has(row.name))
    .map((row) => row.name);
}

/** The allow-list capability of one CLI out of `GET /v1/capabilities`. */
export function allowListCapabilityOf(
  lists: readonly AgentMcpAllowListCapability[] | undefined,
  agent: string,
): AgentMcpAllowListCapability | undefined {
  return lists?.find((entry) => entry.agent === agent);
}

/** One server put on the allow list or taken off it; order is the order the user picked them in. */
export function nextMcpAllowed(
  current: readonly string[],
  server: string,
  allowed: boolean,
): string[] {
  const rest = current.filter((name) => name !== server);
  return allowed ? [...rest, server] : rest;
}

export function isAccountConnector(
  name: string,
  prefix: string | null,
): boolean {
  return prefix !== null && name.startsWith(prefix);
}

/** The list with every account connector taken off it at once. */
export function withoutAccountConnectors(
  current: readonly string[],
  prefix: string | null,
): string[] {
  return current.filter((name) => !isAccountConnector(name, prefix));
}

/** A member's allow list in a few words, for the team value an overridden row names. */
export function mcpAllowedWords(
  allowed: readonly string[] | undefined,
): string {
  if (allowed === undefined) {
    return 'every server';
  }
  return allowed.length === 0
    ? 'Geniro’s own server only'
    : `only ${allowed.join(', ')}`;
}

/**
 * What the builder's MCP dialog says above a team member's (or a pool member's) rows:
 * whose servers these are, and what a switch here does and does NOT do — the
 * second half is the part nobody could guess, since the same switch in a chat
 * writes the CLI's own config.
 */
export function nodeMcpHint(subject: 'member', hasProfile: boolean): string {
  return `${whoseServers(subject, hasProfile)} A switch here applies only to this ${subject}'s turns — nothing in the CLI's own config changes. ${RUN_FOLDER_SERVERS}`;
}

/** The same dialog's words on a project's page, where a switch overrides the team's for that project. */
export function projectMemberMcpHint(hasProfile: boolean): string {
  return `${whoseServers('member', hasProfile)} A switch here applies only to this member's turns in this project — the team's own switches and the CLI's own config stay as they are. The project folder's own servers are listed too.`;
}

/** A member's switches in a few words, for the team value an overridden row names. */
export function mcpSwitchesWords(
  disabled: readonly string[] | undefined,
): string {
  return disabled === undefined || disabled.length === 0
    ? 'every server on'
    : `off: ${disabled.join(', ')}`;
}

const RUN_FOLDER_SERVERS =
  "The run folder's own project servers are added when it runs.";

function whoseServers(subject: 'member', hasProfile: boolean): string {
  return hasProfile
    ? `The servers in this ${subject}'s own config directory.`
    : 'Global servers.';
}

/** Why a row the profile itself switched off has no switch on a member. */
export const OFF_IN_PROFILE =
  'Off in this profile’s own config — a team member can only switch servers off, not back on.';

/** Why a builder row offers no Approve. */
export const APPROVE_IN_A_CHAT =
  'Approving a server is a per-folder choice, so it is made in a chat.';

/** Said on a row the member switched off that the profile does not list. */
export const NOT_IN_PROFILE =
  'Not among this profile’s servers — switched off for any server of this name a run loads (a run folder’s project server, say).';

function unlistedRow(name: string): AgentMcpServer {
  return {
    name,
    target: NOT_IN_PROFILE,
    transport: null,
    status: 'disabled',
    detail: null,
    scope: 'unknown',
    shadowsUser: false,
    disabled: true,
    toggleUnavailableReason: null,
    signInUnavailableReason: NOT_IN_PROFILE,
    approveUnavailableReason: APPROVE_IN_A_CHAT,
    turnToggleUnavailableReason: null,
  };
}
