import type { InstructionBlock, InstructionBlockSize } from '../autogenerated';
import { InstructionsCard } from './instructions-card';

type MemberRef = Parameters<typeof InstructionsCard>[0]['members'][number];

/**
 * The blocks a project's overlay of its team still carries. A project's own
 * text lives in its instructions, so nothing adds one here; what an overlay
 * already holds stays visible, editable and removable, since its runs carry it.
 */
export function ProjectScopeInstructions({
  overlayBlocks,
  members,
  overlaySizeOf,
  onChange,
  onRemove,
}: {
  overlayBlocks: readonly InstructionBlock[];
  members: readonly MemberRef[];
  overlaySizeOf: (blockId: string) => InstructionBlockSize | undefined;
  onChange: (
    blockId: string,
    patch: Partial<Omit<InstructionBlock, 'id'>>,
  ) => void;
  onRemove: (blockId: string) => void;
}): React.JSX.Element {
  const sizes = new Map<string, InstructionBlockSize>();
  for (const block of overlayBlocks) {
    const size = overlaySizeOf(block.id);
    if (size !== undefined) {
      sizes.set(block.id, size);
    }
  }
  return (
    <div data-slot="project-scope-instructions">
      <InstructionsCard
        blocks={overlayBlocks}
        members={members}
        issues={new Map()}
        warnings={new Map()}
        blockSizes={sizes}
        onChange={onChange}
        onRemove={onRemove}
      />
    </div>
  );
}
