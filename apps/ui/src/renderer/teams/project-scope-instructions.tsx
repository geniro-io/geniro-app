import type { InstructionBlock, InstructionBlockSize } from '../autogenerated';
import { InheritedTag } from '../components/inherited-tag';
import {
  InstructionBlockList,
  ReadOnlyInstructionBlockCard,
} from '../components/instruction-blocks';
import { InstructionsCard } from './instructions-card';

type MemberRef = Parameters<typeof InstructionsCard>[0]['members'][number];

/** Every audience as the card names it: everyone, or the members' names. */
function audienceLine(
  block: InstructionBlock,
  members: readonly MemberRef[],
): string {
  if (block.audience === 'everyone' || !Array.isArray(block.audience)) {
    return 'Everyone';
  }
  const names = new Map(members.map((member) => [member.id, member.name]));
  return (block.audience as string[])
    .map((id) => names.get(id) ?? id)
    .join(', ');
}

/**
 * A team's instructions as one project runs it: the shared team's blocks,
 * read-only here, then the blocks only this project's runs of the team carry,
 * edited here.
 */
export function ProjectScopeInstructions({
  projectName,
  sharedBlocks,
  overlayBlocks,
  members,
  overlaySizeOf,
  onAdd,
  onChange,
  onRemove,
}: {
  projectName: string;
  sharedBlocks: readonly InstructionBlock[];
  overlayBlocks: readonly InstructionBlock[];
  members: readonly MemberRef[];
  overlaySizeOf: (blockId: string) => InstructionBlockSize | undefined;
  onAdd: () => void;
  onChange: (
    blockId: string,
    patch: Partial<Omit<InstructionBlock, 'id'>>,
  ) => void;
  onRemove: (blockId: string) => void;
}): React.JSX.Element {
  const sizes = new Map<string, InstructionBlockSize>();
  for (const block of overlayBlocks) {
    const size = overlaySizeOf(block.id);
    if (size !== undefined) {
      sizes.set(block.id, size);
    }
  }
  return (
    <div data-slot="project-scope-instructions" className="flex flex-col gap-6">
      <div className="flex flex-col gap-2">
        <h4 className="text-sm font-medium">
          Shared — edit them on the team’s page
        </h4>
        <InstructionBlockList
          empty={sharedBlocks.length === 0}
          emptyLabel="The shared team has no instruction blocks.">
          {sharedBlocks.map((block) => (
            <ReadOnlyInstructionBlockCard
              key={block.id}
              id={block.id}
              title={block.title}
              text={block.text}
              tag={<InheritedTag variant="team" />}>
              <p className="m-0 text-xs text-muted-foreground">
                To: {audienceLine(block, members)}
              </p>
            </ReadOnlyInstructionBlockCard>
          ))}
        </InstructionBlockList>
      </div>
      <div className="flex flex-col gap-2">
        <h4 className="text-sm font-medium">Only in {projectName}</h4>
        <InstructionsCard
          blocks={overlayBlocks}
          members={members}
          issues={new Map()}
          warnings={new Map()}
          blockSizes={sizes}
          addLabel={`Add block for ${projectName}`}
          emptyLabel={`No blocks only ${projectName} carries yet.`}
          onAdd={onAdd}
          onChange={onChange}
          onRemove={onRemove}
        />
      </div>
    </div>
  );
}
