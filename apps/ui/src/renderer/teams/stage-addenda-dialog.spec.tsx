// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { TeamOverlay, TeamStage } from '../autogenerated';
import { StageAddendaDialog } from './stage-addenda-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const STAGES: TeamStage[] = [
  { id: 'plan', title: 'Planning', goal: 'A plan', howToWork: 'Plan first.' },
  { id: 'build', title: 'Build', goal: 'A change', howToWork: 'Build it.' },
];

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function render(
  overlay: TeamOverlay,
  onSave: (addenda: Record<string, string>) => void = vi.fn(),
): void {
  act(() => {
    root.render(
      <StageAddendaDialog
        open
        projectName="ManifestOS"
        stages={STAGES}
        overlay={overlay}
        onClose={vi.fn()}
        onSave={onSave}
      />,
    );
  });
}

const field = (id: string): HTMLTextAreaElement | null =>
  container.querySelector(`#addendum-${id}`);

describe('StageAddendaDialog', () => {
  it('shows a field only for a stage that has an addendum, and Add for the rest', () => {
    render({ stages: { build: { howToWorkAddendum: 'Run the e2e suite.' } } });

    expect(field('plan')).toBeNull();
    expect(field('build')!.value).toBe('Run the e2e suite.');
    expect(
      [...container.querySelectorAll('[data-slot="stage-addendum-add"]')].map(
        (button) => button.textContent,
      ),
    ).toEqual(['Add for ManifestOS']);
  });

  it('opens the field on Add and saves what was typed', () => {
    const onSave = vi.fn();
    render({}, onSave);

    act(() =>
      (
        container.querySelector(
          '[data-slot="stage-addendum-add"]',
        ) as HTMLButtonElement
      ).click(),
    );
    expect(field('plan')).not.toBeNull();
    expect(field('build')).toBeNull();

    act(() => {
      const textarea = field('plan')!;
      const setter = Object.getOwnPropertyDescriptor(
        HTMLTextAreaElement.prototype,
        'value',
      )!.set!;
      setter.call(textarea, 'Ask before planning.');
      textarea.dispatchEvent(new Event('input', { bubbles: true }));
    });
    act(() =>
      container
        .querySelector('form')!
        .dispatchEvent(
          new Event('submit', { bubbles: true, cancelable: true }),
        ),
    );

    expect(onSave).toHaveBeenCalledWith({
      plan: 'Ask before planning.',
      build: '',
    });
  });
});
