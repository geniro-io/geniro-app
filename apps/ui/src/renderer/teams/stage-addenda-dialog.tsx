import { useEffect, useState } from 'react';

import type { TeamOverlay, TeamStage } from '../autogenerated';
import { ExpandableTextarea } from '../components/expandable-textarea';
import { Field } from '../components/field';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';

const MAX_HOW_TO_WORK = 4000;

/**
 * A project's addendum to each stage's how-to-work text: the shared text
 * read-only, and what this project's runs add after it. The stages
 * themselves are shared and change in the shared scope only.
 */
export function StageAddendaDialog({
  open,
  projectName,
  stages,
  overlay,
  onClose,
  onSave,
}: {
  open: boolean;
  projectName: string;
  stages: readonly TeamStage[];
  overlay: TeamOverlay;
  onClose: () => void;
  onSave: (addenda: Record<string, string>) => void;
}): React.JSX.Element {
  const [draft, setDraft] = useState<Record<string, string>>({});
  useEffect(() => {
    if (open) {
      setDraft(
        Object.fromEntries(
          stages.map((stage) => [
            stage.id,
            overlay.stages?.[stage.id]?.howToWorkAddendum ?? '',
          ]),
        ),
      );
    }
  }, [open, stages, overlay]);
  const tooLong = stages.filter((stage) => {
    const extra = (draft[stage.id] ?? '').trim();
    const base = (stage.howToWork ?? '').trimEnd();
    return extra !== '' && base.length + extra.length + 2 > MAX_HOW_TO_WORK;
  });
  return (
    <Dialog
      open={open}
      onClose={onClose}
      title={`Stage addenda for ${projectName}`}>
      <form
        className="flex flex-col gap-5"
        onSubmit={(event) => {
          event.preventDefault();
          if (tooLong.length === 0) {
            onSave(draft);
          }
        }}>
        {stages.map((stage) => (
          <Field
            key={stage.id}
            label={stage.title}
            htmlFor={`addendum-${stage.id}`}
            hint={
              stage.howToWork?.trim()
                ? `Shared: ${stage.howToWork.trim()}`
                : 'The stage has no shared how-to-work text.'
            }>
            <ExpandableTextarea
              id={`addendum-${stage.id}`}
              title={`Addendum for ${projectName} — ${stage.title}`}
              ariaLabel={`Addendum for ${projectName} — ${stage.title}`}
              value={draft[stage.id] ?? ''}
              rows={3}
              invalid={tooLong.includes(stage) || undefined}
              placeholder={`What ${projectName}’s runs add to this stage`}
              onChange={(text) =>
                setDraft((current) => ({ ...current, [stage.id]: text }))
              }
            />
            {tooLong.includes(stage) ? (
              <span className="text-xs text-destructive">
                With the shared text this runs past {MAX_HOW_TO_WORK}{' '}
                characters.
              </span>
            ) : null}
          </Field>
        ))}
        <div className="flex justify-end gap-2">
          <Button type="button" variant="ghost" onClick={onClose}>
            Cancel
          </Button>
          <Button type="submit" disabled={tooLong.length > 0}>
            Save addenda
          </Button>
        </div>
      </form>
    </Dialog>
  );
}
