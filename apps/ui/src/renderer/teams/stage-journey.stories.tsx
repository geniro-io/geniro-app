function Stateful({
  stages,
  initialTrigger,
}: {
  stages: TeamStage[];
  initialTrigger: string | null;
}): React.JSX.Element {
  const [trigger, setTrigger] = useState(initialTrigger);
  return (
    <StageJourney
      stages={stages}
      members={MEMBERS}
      triggerMemberId={trigger}
      onPickTrigger={setTrigger}
      onOpenStage={() => {}}
      onAddStage={() => {}}
    />
  );
}

const meta = {
  title: 'Teams/StageJourney',
  component: StageJourney,
  args: {
    stages: STAGES,
    members: MEMBERS,
    triggerMemberId: 'ada',
    onPickTrigger: () => {},
    onOpenStage: () => {},
    onAddStage: () => {},
  },
  decorators: [(story) => <div className="w-[900px] p-4">{story()}</div>],
} satisfies Meta<typeof StageJourney>;

export default meta;
type Story = StoryObj<typeof meta>;

export const WithFork: Story = {
  render: () => <Stateful stages={STAGES} initialTrigger="ada" />,
};

export const NoStages: Story = {
  render: () => <Stateful stages={[]} initialTrigger="ada" />,
};

export const TriggerMissing: Story = {
  render: () => <Stateful stages={STAGES} initialTrigger={null} />,
};

export const Phone: Story = {
  parameters: { viewport: { defaultViewport: 'mobile1' } },
  decorators: [(story) => <div className="w-[360px]">{story()}</div>],
  render: () => <Stateful stages={STAGES} initialTrigger="ada" />,
};
