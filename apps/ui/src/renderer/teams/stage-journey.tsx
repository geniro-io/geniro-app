/** One stage: its number, title, what done means and who owns it. */
export function StageCard({
  placed,
  columnCount,
  members,
  hasWarning = false,
  hasError = false,
  compact = false,
  onOpen,
}: {
  placed: PlacedStage;
  columnCount: number;
  members: readonly JourneyMember[];
  hasWarning?: boolean;
  /** The stage holds something a save would refuse. */
  hasError?: boolean;
  compact?: boolean;
  onOpen: () => void;
}): React.JSX.Element {
  const { stage } = placed;
  const owners = responsibleOf(stage, members);
  return (
    <button
      type="button"
      data-slot="stage-card"
      data-stage-id={stage.id}
      data-error={hasError || undefined}
      aria-label={`${stagePlaceLabel(placed, columnCount)}: ${stageTitle(stage)}${hasError ? ', has an error' : ''}`}
      className={cn(stageCardVariants({ compact, error: hasError }))}
      onClick={onOpen}>
      <span className="flex items-center gap-2">
        <span className="flex h-6 min-w-6 shrink-0 items-center justify-center rounded-pill bg-primary/10 px-1.5 text-sm font-semibold text-primary tabular-nums">
          {shortNumber(placed)}
        </span>
        <span className="min-w-0 truncate text-base font-semibold">
          {stageTitle(stage)}
        </span>
      </span>
      <span className={goalVariants({ missing: !stage.goal.trim() })}>
        {stage.goal.trim() || 'No goal yet — say what done means'}
      </span>
      {owners.length > 0 ? (
        <AvatarStack
          size={24}
          max={4}
          ringClassName="ring-card"
          people={owners.map((owner) => ({
            key: owner.id,
            name: owner.name,
            avatar: owner.avatar,
          }))}
        />
      ) : (
        <span className="text-sm text-muted-foreground">No one assigned</span>
      )}
      {hasWarning ? (
        <span className="text-sm text-warning">
          A responsible member is no longer in the team
        </span>
      ) : null}
    </button>
  );
}

/**
 * Where a run begins: the member the first message goes to. Choosing one is
 * required; until then the card says so in words, framed as an error.
 */
export function EntryCard({
  members,
  memberId,
  onPick,
  disabled = false,
  compact = false,
}: {
  members: readonly JourneyMember[];
  memberId: string | null;
  onPick: (memberId: string) => void;
  disabled?: boolean;
  compact?: boolean;
}): React.JSX.Element {
  const errorId = useId();
  const [open, setOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const handler = members.find((member) => member.id === memberId) ?? null;
  return (
    <span className="relative inline-flex shrink-0">
      <button
        ref={triggerRef}
        type="button"
        data-slot="entry-card"
        data-menu-trigger
        aria-haspopup="listbox"
        aria-expanded={open}
        aria-label={
          handler === null
            ? 'First message: choose who receives it'
            : `First message goes to ${handler.name}`
        }
        aria-required="true"
        aria-invalid={handler === null || undefined}
        aria-describedby={handler === null ? errorId : undefined}
        disabled={disabled}
        className={entryCardVariants({ compact, missing: handler === null })}
        onClick={() => setOpen((wasOpen) => !wasOpen)}>
        <span className="flex items-center gap-1.5 text-sm font-medium text-muted-foreground">
          <Zap aria-hidden="true" className="size-3.5 text-primary" />
          First message
        </span>
        {handler === null ? (
          <>
            <span className="flex items-center gap-2">
              <span
                aria-hidden="true"
                className="flex size-6 items-center justify-center rounded-pill border border-dashed border-destructive text-destructive">
                <Plus className="size-3.5" />
              </span>
              <ChevronDown
                aria-hidden="true"
                className="size-3.5 text-muted-foreground"
              />
            </span>
            <span id={errorId} className="text-sm text-destructive">
              Choose who receives the first message
            </span>
          </>
        ) : (
          <span className="flex min-w-0 items-center gap-1.5 text-base">
            <span aria-hidden="true" className="text-muted-foreground">
              →
            </span>
            <MemberAvatar
              name={handler.name}
              avatar={handler.avatar}
              colorKey={handler.id}
              size={24}
            />
            <span className="min-w-0 truncate font-medium">{handler.name}</span>
            <ChevronDown
              aria-hidden="true"
              className="size-3.5 shrink-0 text-muted-foreground"
            />
          </span>
        )}
      </button>
      <Menu
        open={open}
        side="bottom"
        align="start"
        anchor="viewport"
        triggerRef={triggerRef}
        {...(memberId === null ? {} : { value: memberId })}
        groups={[
          {
            items: members.map((member) => ({
              value: member.id,
              label: member.name,
              icon: (
                <MemberAvatar
                  name={member.name}
                  avatar={member.avatar}
                  colorKey={member.id}
                  size={20}
                />
              ),
            })),
          },
        ]}
        onSelect={(picked) => {
          setOpen(false);
          onPick(picked);
        }}
        onClose={() => setOpen(false)}
      />
    </span>
  );
}

interface Wire {
  key: string;
  path: string;
}

/**
 * The orthogonal wires between the cards, measured from the cards themselves
 * so a card that grows keeps its wires attached. Drawn on the border token.
 */
function useWires(
  containerRef: React.RefObject<HTMLDivElement | null>,
  edges: readonly { from: string; to: string }[],
  layout: string,
): { wires: Wire[]; start: { x: number; y: number } | null } {
  const [state, setState] = useState<{
    wires: Wire[];
    start: { x: number; y: number } | null;
  }>({ wires: [], start: null });
  const edgeKey = edges.map((edge) => `${edge.from}>${edge.to}`).join('|');

  useLayoutEffect(() => {
    const container = containerRef.current;
    if (container === null || typeof ResizeObserver === 'undefined') {
      return;
    }
    const measure = (): void => {
      const origin = container.getBoundingClientRect();
      const box = (key: string): DOMRect | null =>
        container
          .querySelector<HTMLElement>(`[data-journey-node="${key}"]`)
          ?.getBoundingClientRect() ?? null;
      const wires: Wire[] = [];
      let start: { x: number; y: number } | null = null;
      for (const edge of edges) {
        const from = box(edge.from);
        const to = box(edge.to);
        if (from === null || to === null) {
          continue;
        }
        const x1 = from.right - origin.left;
        const y1 = from.top + from.height / 2 - origin.top;
        const x2 = to.left - origin.left;
        const y2 = to.top + to.height / 2 - origin.top;
        const mid = x1 + (x2 - x1) / 2;
        if (edge.from === 'entry') {
          start = { x: x1, y: y1 };
        }
        wires.push({
          key: `${edge.from}>${edge.to}`,
          path: `M ${x1} ${y1} H ${mid} V ${y2} H ${x2}`,
        });
      }
      setState({ wires, start });
    };
    measure();
    const observer = new ResizeObserver(measure);
    observer.observe(container);
    for (const child of container.querySelectorAll('[data-journey-node]')) {
      observer.observe(child);
    }
    return () => observer.disconnect();
  }, [containerRef, edgeKey, layout]);

  return state;
}

/**
 * The stages as a journey: the first-message card, then each stage left to
 * right, alternatives stacked and re-joining, ending in "Add stage". Below
 * `sm` the same journey reads as a vertical timeline on a dot-and-line rail,
 * alternatives indented under "or".
 */
export function StageJourney({
  stages,
  members,
  triggerMemberId,
  warningStageIds,
  errorStageIds,
  onPickTrigger,
  onOpenStage,
  onAddStage,
  triggerDisabled = false,
}: {
  stages: readonly TeamStage[];
  members: readonly JourneyMember[];
  triggerMemberId: string | null;
  warningStageIds?: ReadonlySet<string>;
  errorStageIds?: ReadonlySet<string>;
  onPickTrigger: (memberId: string) => void;
  onOpenStage: (stageId: string) => void;
  onAddStage: () => void;
  triggerDisabled?: boolean;
}): React.JSX.Element {
  const narrow = useNarrowViewport();
  const columns = layoutStages(stages);
  const containerRef = useRef<HTMLDivElement | null>(null);
  const edges = [
    ...(columns[0] ?? []).map((placed) => ({
      from: 'entry',
      to: placed.stage.id,
    })),
    ...stages.flatMap((stage) =>
      (stage.next ?? [])
        .filter((next) => stages.some((other) => other.id === next))
        .map((next) => ({ from: stage.id, to: next })),
    ),
  ];
  const { wires, start } = useWires(
    containerRef,
    edges,
    narrow ? 'timeline' : 'ribbon',
  );
  const entry = (compact: boolean): React.JSX.Element => (
    <EntryCard
      members={members}
      memberId={triggerMemberId}
      onPick={onPickTrigger}
      disabled={triggerDisabled}
      compact={compact}
    />
  );
  const card = (placed: PlacedStage, compact: boolean): React.JSX.Element => (
    <StageCard
      placed={placed}
      columnCount={columns.length}
      members={members}
      hasWarning={warningStageIds?.has(placed.stage.id) ?? false}
      hasError={errorStageIds?.has(placed.stage.id) ?? false}
      compact={compact}
      onOpen={() => onOpenStage(placed.stage.id)}
    />
  );
  const addStage = (
    <button
      type="button"
      className="flex h-10 shrink-0 items-center gap-2 self-center rounded-control px-3 text-base font-medium text-muted-foreground transition-colors outline-none hover:bg-accent hover:text-foreground focus-visible:ring-2 focus-visible:ring-ring active:scale-[.97] motion-reduce:active:scale-100"
      onClick={onAddStage}>
      <Plus aria-hidden="true" className="size-4" />
      Add stage
    </button>
  );

  if (narrow) {
    return (
      <div data-slot="stage-journey" data-layout="timeline">
        <ol
          aria-label="Stages"
          className="relative flex flex-col gap-4 pl-6 before:absolute before:top-3 before:bottom-3 before:left-2 before:w-px before:bg-field-border">
          <li className="relative before:absolute before:top-5 before:-left-[19px] before:size-2 before:rounded-pill before:bg-field-border">
            {entry(true)}
          </li>
          {columns.map((column, index) => (
            <li
              key={index}
              className="relative flex flex-col gap-2 before:absolute before:top-5 before:-left-[19px] before:size-2 before:rounded-pill before:bg-field-border">
              {column.map((placed, branch) => (
                <div
                  key={placed.stage.id}
                  className={cn('flex flex-col gap-1', branch > 0 && 'pl-4')}>
                  {branch > 0 ? (
                    <span className="text-sm text-muted-foreground">or</span>
                  ) : null}
                  {card(placed, true)}
                </div>
              ))}
            </li>
          ))}
          <li>{addStage}</li>
        </ol>
      </div>
    );
  }
  return (
    <div data-slot="stage-journey" data-layout="ribbon">
      <div className="overflow-x-auto [mask-image:linear-gradient(to_right,transparent,black_16px,black_calc(100%-16px),transparent)] [scrollbar-width:thin]">
        <div
          ref={containerRef}
          className="relative flex w-max items-center gap-12 px-4 py-4">
          <svg
            aria-hidden="true"
            className="pointer-events-none absolute inset-0 size-full overflow-visible text-field-border">
            {wires.map((wire) => (
              <path
                key={wire.key}
                d={wire.path}
                fill="none"
                stroke="currentColor"
                strokeWidth={1.5}
              />
            ))}
            {start === null ? null : (
              <circle cx={start.x} cy={start.y} r={3} fill="currentColor" />
            )}
          </svg>
          <div data-journey-node="entry" className="relative">
            {entry(false)}
          </div>
          {columns.map((column, index) => (
            <ol
              key={index}
              aria-label={`Stage ${index + 1}`}
              className="relative flex flex-col gap-4">
              {column.map((placed) => (
                <li key={placed.stage.id} data-journey-node={placed.stage.id}>
                  {card(placed, false)}
                </li>
              ))}
            </ol>
          ))}
          {addStage}
        </div>
      </div>
    </div>
  );
}
