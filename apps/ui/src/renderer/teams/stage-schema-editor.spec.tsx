// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { settleStageGraphs } from '../__tests__/settle-stage-graphs';
import { stubResizeObserver } from '../__tests__/stub-resize-observer';
import type { TeamStage } from '../autogenerated';
import { StageSchemaEditor } from './stage-schema-editor';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  vi.clearAllMocks();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

const onClose = vi.fn();
const onSave = vi.fn();

const LINE: TeamStage[] = [
  {
    id: 'investigate',
    title: 'Investigate',
    goal: 'Cause found',
    next: ['fix'],
  },
  { id: 'fix', title: 'Fix', goal: 'Fix merged' },
];

const MEMBERS = [
  { id: 'coder', name: 'Coder' },
  { id: 'reviewer', name: 'Reviewer' },
  { id: 'tester', name: 'Tester' },
];

function render(
  stages: TeamStage[] | undefined,
  members: { id: string; name: string }[] = MEMBERS,
): void {
  act(() => {
    root.render(
      <StageSchemaEditor
        open
        stages={stages}
        members={members}
        onClose={onClose}
        onSave={onSave}
      />,
    );
  });
}

function click(el: Element | null): void {
  expect(el).not.toBeNull();
  act(() => (el as HTMLElement).click());
}

function type(el: HTMLInputElement | HTMLTextAreaElement, value: string): void {
  act(() => {
    const proto =
      el instanceof HTMLTextAreaElement
        ? HTMLTextAreaElement.prototype
        : HTMLInputElement.prototype;
    Object.getOwnPropertyDescriptor(proto, 'value')!.set!.call(el, value);
    el.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

const button = (name: string): HTMLButtonElement | null =>
  [...container.querySelectorAll('button')].find(
    (b) => b.textContent?.trim() === name,
  ) ?? null;

const rows = (): HTMLElement[] => [
  ...container.querySelectorAll<HTMLElement>('[data-slot="stage-row"]'),
];
const rowTitles = (): (string | null | undefined)[] =>
  rows().map(
    (row) => row.querySelector('[data-slot="stage-row-title"]')?.textContent,
  );
const rowWords = (id: string): string | null | undefined =>
  rows()
    .find((row) => row.dataset.stageId === id)!
    .querySelector('[data-slot="stage-row-words"]')?.textContent;
const pill = (id: string): HTMLElement =>
  container.querySelector<HTMLElement>(
    `[data-slot="stage-graph"] [data-slot="stage-pill"][data-stage-id="${id}"]`,
  )!;
const fieldIssues = (tone: 'error' | 'warning'): string[] =>
  [
    ...container.querySelectorAll(
      `[data-slot="stage-field-issue"][data-tone="${tone}"]`,
    ),
  ].map((issue) => issue.textContent!);
const field = (label: string): HTMLInputElement | HTMLTextAreaElement => {
  const htmlFor = [...container.querySelectorAll('label')].find(
    (l) => l.textContent === label,
  )!.htmlFor;
  return document.getElementById(htmlFor) as
    HTMLInputElement | HTMLTextAreaElement;
};
const doneButton = (): HTMLButtonElement => button('Done')!;
const errorAlert = (): Element | null =>
  container.querySelector('[role="alert"]');

function pickRowMenuItem(rowIndex: number, label: string): void {
  click(rows()[rowIndex]!.querySelector('[data-menu-trigger]'));
  const option = [...document.querySelectorAll('[role="option"]')].find((o) =>
    o.textContent?.includes(label),
  );
  click(option ?? null);
}

function lastSaved(): TeamStage[] {
  return onSave.mock.calls.at(-1)![0] as TeamStage[];
}

describe('StageSchemaEditor', () => {
  it('adds stages one after another as a line, with stable ids minted from their titles', () => {
    render(undefined);
    expect(container.textContent).toContain('No stages yet');

    click(button('Add stage'));
    type(field('Title') as HTMLInputElement, 'Fix the Build');
    type(field('Goal') as HTMLInputElement, 'Build is green');
    click(button('Add stage'));
    type(field('Goal') as HTMLInputElement, 'Merged');
    expect(rowTitles()).toEqual(['Fix the Build', 'Stage 2']);

    click(doneButton());
    expect(lastSaved()).toEqual([
      {
        id: 'stage-1',
        title: 'Fix the Build',
        goal: 'Build is green',
        next: ['stage-2'],
      },
      { id: 'stage-2', title: 'Stage 2', goal: 'Merged' },
    ]);
  });

  it('edits the selected stage and writes trimmed text, dropping empty optional fields', () => {
    render(LINE);
    click(rows()[1]!.querySelector('button'));
    type(field('Title') as HTMLInputElement, '  Repair  ');
    type(field('How to work') as HTMLTextAreaElement, '   ');
    type(field('Goal') as HTMLInputElement, ' Repair merged ');
    click(doneButton());

    expect(lastSaved()[1]).toEqual({
      id: 'fix',
      title: 'Repair',
      goal: 'Repair merged',
    });
    expect(rowTitles()).toEqual(['Investigate', 'Repair']);
  });

  it('builds an ordered Responsible list whose first member leads, and clears it', () => {
    render(LINE);
    const addMember = (name: string): void => {
      click(
        container.querySelector<HTMLElement>(
          'button[aria-label="Add a responsible member"]',
        ),
      );
      click(
        [...document.querySelectorAll('[role="option"]')].find(
          (o) => o.textContent === name,
        ) ?? null,
      );
    };
    const listed = (): (string | undefined)[] =>
      [
        ...container.querySelectorAll<HTMLElement>(
          '[data-slot="responsible-row"]',
        ),
      ].map((row) => row.dataset.memberId);
    expect(container.textContent).toContain('No one in particular');

    addMember('Reviewer');
    addMember('Coder');
    expect(listed()).toEqual(['reviewer', 'coder']);
    expect(
      container.querySelector('[data-slot="responsible-row"]')!.textContent,
    ).toContain('leads');
    expect(rowWords('investigate')).toBe('start · Reviewer');

    click(container.querySelector('button[aria-label="Move Coder up"]'));
    expect(listed()).toEqual(['coder', 'reviewer']);
    expect(rowWords('investigate')).toBe('start · Coder');
    click(doneButton());
    expect(lastSaved()[0]!.responsible).toEqual(['coder', 'reviewer']);

    click(container.querySelector('button[aria-label="Remove Coder"]'));
    click(container.querySelector('button[aria-label="Remove Reviewer"]'));
    click(doneButton());
    expect('responsible' in lastSaved()[0]!).toBe(false);
  });

  it('offers only the members not already responsible', () => {
    render([{ ...LINE[0]!, responsible: ['coder'] }, LINE[1]!]);
    click(
      container.querySelector<HTMLElement>(
        'button[aria-label="Add a responsible member"]',
      ),
    );
    expect(
      [...document.querySelectorAll('[role="option"]')].map(
        (o) => o.textContent,
      ),
    ).toEqual(['Reviewer', 'Tester']);
  });

  it('moves a stage up and down from its menu, and offers neither past the ends', () => {
    render(LINE);
    pickRowMenuItem(0, 'Move down');
    expect(rowTitles()).toEqual(['Fix', 'Investigate']);

    click(rows()[0]!.querySelector('[data-menu-trigger]'));
    const up = [
      ...document.querySelectorAll<HTMLButtonElement>('[role="option"]'),
    ].find((o) => o.textContent?.includes('Move up'));
    expect(up!.disabled).toBe(true);
    click(document.querySelector('[role="option"]:not([disabled])'));
    expect(rowTitles()).toEqual(['Investigate', 'Fix']);
  });

  it('deletes a stage and takes it out of every next list', () => {
    render(
      [...LINE, { id: 'ship', title: 'Ship', goal: 'Shipped' }].map((s) =>
        s.id === 'fix' ? { ...s, next: ['ship'] } : s,
      ),
    );
    pickRowMenuItem(2, 'Delete');
    expect(rowTitles()).toEqual(['Investigate', 'Fix']);

    click(doneButton());
    expect(lastSaved()).toEqual([
      LINE[0],
      { id: 'fix', title: 'Fix', goal: 'Fix merged' },
    ]);
  });

  it('says in the hint line where the run goes: one stage, a fork, or the end', () => {
    render([
      { id: 'a', title: 'A', goal: 'a', next: ['b'] },
      { id: 'b', title: 'B', goal: 'b' },
      { id: 'c', title: 'C', goal: 'c' },
    ]);
    const hint = (): string =>
      container.querySelector('[data-slot="stage-next-hint"]')!.textContent!;
    expect(hint()).toBe('Then B');

    const next = (name: string): HTMLButtonElement =>
      [...container.querySelectorAll<HTMLButtonElement>('[aria-pressed]')].find(
        (b) => b.textContent === name,
      )!;
    expect(rowWords('a')).toBe('start');
    click(next('C'));
    expect(hint()).toBe('Fork — the run takes one of 2');
    expect(next('B').getAttribute('aria-pressed')).toBe('true');
    expect(next('C').getAttribute('aria-pressed')).toBe('true');
    expect(rowWords('a')).toBe('start · fork');

    click(next('B'));
    expect(hint()).toBe('Then C');
    click(next('C'));
    expect(hint()).toBe('Final stage — the run ends here');
    expect(rowWords('a')).toBe('start · final');
  });

  it('names a next stage that does not exist by its id', () => {
    render([{ id: 'a', title: 'A', goal: 'a', next: ['ghost'] }]);
    expect(
      container.querySelector('[data-slot="stage-next-hint"]')!.textContent,
    ).toBe('Then ghost');
    expect(errorAlert()).toBeNull();
    click(doneButton());
    expect(onSave).not.toHaveBeenCalled();
    expect(errorAlert()!.textContent).toContain('Error');
  });

  it('refuses Done while the stages loop back, and says why in words', async () => {
    stubResizeObserver();
    render([
      { id: 'a', title: 'A', goal: 'a', next: ['b'] },
      { id: 'b', title: 'B', goal: 'b', next: ['c'] },
      { id: 'c', title: 'C', goal: 'c', next: ['b'] },
    ]);
    expect(container.querySelector('[data-slot="stage-errors"]')).toBeNull();
    expect(rowWords('b')).toBeUndefined();
    click(doneButton());
    expect(onSave).not.toHaveBeenCalled();
    const alert = container.querySelector('[data-slot="stage-errors"]')!;
    expect(alert.getAttribute('role')).toBe('alert');
    expect(alert.textContent).toContain('Error');
    expect(alert.textContent).toContain('B: The stages loop back');
    expect(rowWords('b')).toBe('error');
    await settleStageGraphs(container);
    expect(pill('b').dataset.error).toBe('true');
    expect(pill('b').getAttribute('aria-label')).toBe('B, has an error');
    expect(
      [
        ...container.querySelectorAll<SVGPathElement>(
          '[data-slot="stage-edge"][stroke-dasharray]',
        ),
      ].map((edge) => edge.dataset.edge),
    ).toEqual(['b>c', 'c>b']);

    click(rows()[2]!.querySelector('button'));
    click(
      [
        ...container.querySelectorAll<HTMLButtonElement>(
          '[aria-pressed="true"]',
        ),
      ].find((b) => b.textContent === 'B') ?? null,
    );
    expect(container.querySelector('[data-slot="stage-errors"]')).toBeNull();
    click(doneButton());
    expect(lastSaved()).toHaveLength(3);
  });

  it('refuses Done for a stage without a title or a goal, and for a second start', () => {
    render([{ id: 'a', title: 'A', goal: 'a' }]);
    click(doneButton());
    expect(onSave).toHaveBeenCalledTimes(1);

    type(field('Title') as HTMLInputElement, '   ');
    expect(fieldIssues('error')).toEqual(['Error: A stage needs a title']);
    click(doneButton());
    expect(onSave).toHaveBeenCalledTimes(1);
    type(field('Title') as HTMLInputElement, 'A');
    expect(fieldIssues('error')).toEqual([]);

    type(field('Goal') as HTMLInputElement, '');
    expect(fieldIssues('error')).toEqual(['Error: A stage needs a goal']);
    click(doneButton());
    expect(onSave).toHaveBeenCalledTimes(1);
    type(field('Goal') as HTMLInputElement, 'a');

    click(button('Add stage'));
    type(field('Goal') as HTMLInputElement, 'b');
    click(rows()[0]!.querySelector('button'));
    click(
      [
        ...container.querySelectorAll<HTMLButtonElement>(
          '[aria-pressed="true"]',
        ),
      ].find((b) => b.textContent === 'Stage 2') ?? null,
    );
    click(doneButton());
    expect(onSave).toHaveBeenCalledTimes(1);
    expect(
      container.querySelector('[data-slot="stage-errors"]')!.textContent,
    ).toContain('Only one stage may start');
  });

  it('shows no error and no alert for a stage just added, however often', async () => {
    stubResizeObserver();
    render([{ id: 'a', title: 'A', goal: 'a' }]);
    click(button('Add stage'));
    click(button('Add stage'));
    expect(rows().length).toBe(3);
    expect(fieldIssues('error')).toEqual([]);
    expect(errorAlert()).toBeNull();
    expect(rowWords('stage-2')).toBeUndefined();
    await settleStageGraphs(container);
    expect(pill('stage-2').dataset.error).toBeUndefined();
  });

  it('shows a field’s error once the field is edited or left, and the rest only after Done is pressed', () => {
    render([{ id: 'a', title: 'A', goal: 'a' }]);
    click(button('Add stage'));
    const goal = field('Goal') as HTMLInputElement;
    expect(fieldIssues('error')).toEqual([]);

    act(() => goal.focus());
    act(() => goal.blur());
    expect(fieldIssues('error')).toEqual(['Error: A stage needs a goal']);
    expect(errorAlert()).toBeNull();
  });

  it('on Done with errors, shows every error with an alert, saves nothing and stays open', () => {
    render(LINE);
    click(button('Add stage'));
    click(button('Add stage'));
    expect(fieldIssues('error')).toEqual([]);

    click(doneButton());
    expect(onSave).not.toHaveBeenCalled();
    expect(onClose).not.toHaveBeenCalled();
    expect(fieldIssues('error')).toEqual(['Error: A stage needs a goal']);
    const alert = errorAlert()!;
    expect(alert).toBe(container.querySelector('[data-slot="stage-errors"]'));
    expect(alert.textContent).toContain('Stage 3');
    expect(rowWords('stage-3')).toContain('error');
    expect(rowWords('stage-4')).toContain('error');

    type(field('Goal') as HTMLInputElement, 'Shipped');
    click(rows()[2]!.querySelector('button'));
    type(field('Goal') as HTMLInputElement, 'Reviewed');
    expect(errorAlert()).toBeNull();
    click(doneButton());
    expect(lastSaved()).toHaveLength(4);
  });

  it('starts every open without the previous visit’s attempt', () => {
    render([{ id: 'a', title: 'A', goal: '' }]);
    click(doneButton());
    expect(errorAlert()).not.toBeNull();

    act(() =>
      root.render(
        <StageSchemaEditor
          open={false}
          stages={LINE}
          members={[]}
          onClose={onClose}
          onSave={onSave}
        />,
      ),
    );
    render([{ id: 'a', title: 'A', goal: '' }]);
    expect(errorAlert()).toBeNull();
    expect(fieldIssues('error')).toEqual([]);
  });

  it('writes how to work from the expandable field', () => {
    render(LINE);
    expect(
      container.querySelector('button[aria-label="Expand How to work"]'),
    ).not.toBeNull();
    type(field('How to work') as HTMLTextAreaElement, ' Find it ');
    click(doneButton());
    expect(lastSaved()[0]!.howToWork).toBe('Find it');
  });

  it('keeps the stored next as ids and tells apart stages that share a title', () => {
    render([
      { id: 'a', title: 'A', goal: 'a', next: ['twin-1'] },
      { id: 'twin-1', title: 'Twin', goal: 't' },
      { id: 'twin-2', title: 'Twin', goal: 't' },
    ]);
    const options = (): string[] =>
      [...container.querySelectorAll('[aria-pressed]')].map(
        (b) => b.textContent!,
      );
    expect(options()).toEqual(['Twin (twin-1)', 'Twin (twin-2)']);
    click(
      [...container.querySelectorAll<HTMLButtonElement>('[aria-pressed]')].find(
        (b) => b.textContent === 'Twin (twin-2)',
      ) ?? null,
    );
    click(doneButton());
    expect(lastSaved()[0]!.next).toEqual(['twin-1', 'twin-2']);
  });

  it('shows a responsible id the team lacks as a warning that does not block Done', () => {
    render([
      { id: 'a', title: 'A', goal: 'a', next: ['b'] },
      { id: 'b', title: 'B', goal: 'b', responsible: ['ghost'] },
    ]);
    const warning = container.querySelector('[data-slot="stage-warnings"]')!;
    expect(warning.textContent).toContain('Warning');
    expect(warning.textContent).toContain(
      "B: Stage 'b' names 'ghost' as responsible",
    );
    expect(rowWords('b')).toBe('warning · final · ghost');
    expect(fieldIssues('warning')).toEqual([]);

    click(rows()[1]!.querySelector('button'));
    expect(fieldIssues('warning')).toEqual([
      expect.stringContaining(
        "Warning: Stage 'b' names 'ghost' as responsible",
      ),
    ]);
    expect(
      container.querySelector('[data-slot="responsible-row"]')!.textContent,
    ).toContain('ghost (not in this team)');
    expect(container.querySelector('[data-slot="stage-warnings"]')).toBeNull();
    expect(container.querySelector('[data-slot="stage-errors"]')).toBeNull();
    click(doneButton());
    expect(lastSaved()[1]!.responsible).toEqual(['ghost']);
  });

  it('draws the draft as the stage graph: a pill per stage, a line per next', async () => {
    stubResizeObserver();
    render([
      { id: 'a', title: 'Investigation', goal: 'a', next: ['b', 'c'] },
      { id: 'b', title: 'Implementation', goal: 'b', next: ['d'] },
      { id: 'c', title: '  ', goal: 'c', next: ['d'] },
      { id: 'd', title: 'Review', goal: 'd' },
    ]);
    await settleStageGraphs(container);
    expect(
      ['a', 'b', 'c', 'd'].map(
        (id) =>
          pill(id).querySelector('[data-slot="stage-pill-title"]')!.textContent,
      ),
    ).toEqual(['Investigation', 'Implementation', 'Untitled stage', 'Review']);
    expect(
      [
        ...container.querySelectorAll<SVGPathElement>(
          '[data-slot="stage-graph"] [data-slot="stage-edge"]',
        ),
      ].map((edge) => edge.dataset.edge),
    ).toEqual(['a>b', 'a>c', 'b>d', 'c>d']);
  });

  it('selects a stage for editing when its pill in the preview is pressed', async () => {
    stubResizeObserver();
    render([
      { id: 'a', title: 'Investigation', goal: 'a', next: ['b', 'c'] },
      { id: 'b', title: 'Implementation', goal: 'b' },
      { id: 'c', title: 'Fix', goal: 'c' },
    ]);
    expect((field('Title') as HTMLInputElement).value).toBe('Investigation');
    await settleStageGraphs(container);
    expect(pill('a').getAttribute('aria-current')).toBe('true');

    act(() => {
      pill('c').dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    expect((field('Title') as HTMLInputElement).value).toBe('Fix');
    expect(pill('c').getAttribute('aria-current')).toBe('true');
    expect(pill('a').getAttribute('aria-current')).toBeNull();
    expect(
      rows()
        .find((row) => row.dataset.stageId === 'c')!
        .querySelector('[aria-current]'),
    ).not.toBeNull();
  });

  it('reorders by dragging a row’s handle, live under the pointer', () => {
    render([
      LINE[0]!,
      { ...LINE[1]!, next: ['ship'] },
      { id: 'ship', title: 'Ship', goal: 'Shipped' },
    ]);
    const rect = vi
      .spyOn(HTMLElement.prototype, 'getBoundingClientRect')
      .mockImplementation(function (this: HTMLElement) {
        const top = rows().indexOf(this) * 50;
        return { top, height: 50, bottom: top + 50 } as DOMRect;
      });
    const handle = rows()[0]!.querySelector('[data-slot="stage-drag-handle"]')!;
    act(() => {
      handle.dispatchEvent(
        new MouseEvent('pointerdown', { bubbles: true, clientY: 10 }),
      );
    });
    expect(rows()[0]!.dataset.dragging).toBe('true');
    act(() => {
      window.dispatchEvent(new MouseEvent('pointermove', { clientY: 80 }));
    });
    expect(rowTitles()).toEqual(['Fix', 'Investigate', 'Ship']);
    act(() => {
      window.dispatchEvent(new MouseEvent('pointermove', { clientY: 140 }));
    });
    expect(rowTitles()).toEqual(['Fix', 'Ship', 'Investigate']);
    act(() => {
      window.dispatchEvent(new MouseEvent('pointerup'));
    });
    expect(rows().some((row) => row.dataset.dragging)).toBe(false);

    act(() => {
      window.dispatchEvent(new MouseEvent('pointermove', { clientY: 0 }));
    });
    expect(rowTitles()).toEqual(['Fix', 'Ship', 'Investigate']);
    rect.mockRestore();

    click(doneButton());
    expect(lastSaved().map((stage) => stage.id)).toEqual([
      'fix',
      'ship',
      'investigate',
    ]);
  });

  it('ends a drag when the editor closes mid-drag, taking its window listeners with it', () => {
    const added = vi.spyOn(window, 'addEventListener');
    const removed = vi.spyOn(window, 'removeEventListener');
    render(LINE);
    const handle = rows()[0]!.querySelector('[data-slot="stage-drag-handle"]')!;
    act(() => {
      handle.dispatchEvent(
        new MouseEvent('pointerdown', { bubbles: true, clientY: 10 }),
      );
    });
    expect(rows()[0]!.dataset.dragging).toBe('true');
    const listener = (type: string): unknown =>
      added.mock.calls.find(([name]) => name === type)?.[1];
    const move = listener('pointermove');
    const up = listener('pointerup');
    expect(move).toBeTypeOf('function');
    expect(up).toBeTypeOf('function');
    const removedFor = (type: string): unknown[] =>
      removed.mock.calls.filter(([name]) => name === type).map(([, fn]) => fn);
    expect(removedFor('pointermove')).not.toContain(move);

    act(() =>
      root.render(
        <StageSchemaEditor
          open={false}
          stages={LINE}
          members={[]}
          onClose={onClose}
          onSave={onSave}
        />,
      ),
    );
    expect(removedFor('pointermove')).toContain(move);
    expect(removedFor('pointerup')).toContain(up);
    expect(removedFor('pointercancel')).toContain(listener('pointercancel'));
    expect(() =>
      act(() => {
        window.dispatchEvent(new MouseEvent('pointermove', { clientY: 500 }));
        window.dispatchEvent(new MouseEvent('pointerup'));
      }),
    ).not.toThrow();

    render(LINE);
    expect(rowTitles()).toEqual(['Investigate', 'Fix']);
    expect(rows().some((row) => row.dataset.dragging)).toBe(false);
  });

  it('starts every open from the saved stages, not from an abandoned draft', () => {
    render(LINE);
    click(button('Add stage'));
    expect(rows().length).toBe(3);

    render(LINE);
    expect(rows().length).toBe(3);
    act(() =>
      root.render(
        <StageSchemaEditor
          open={false}
          stages={LINE}
          members={[]}
          onClose={onClose}
          onSave={onSave}
        />,
      ),
    );
    render(LINE);
    expect(rows().length).toBe(2);
  });

  it('closes without saving on Cancel', () => {
    render(LINE);
    click(button('Cancel'));
    expect(onClose).toHaveBeenCalledOnce();
    expect(onSave).not.toHaveBeenCalled();
  });
});
