type MemberRef = Pick<TeamMember, 'id' | 'name'>;

function normalized(draft: readonly TeamStage[]): TeamStage[] {
  return draft.map((stage): TeamStage => {
    const howToWork = stage.howToWork?.trim();
    return {
      id: stage.id,
      title: stage.title.trim(),
      ...(howToWork ? { howToWork } : {}),
      goal: stage.goal.trim(),
      ...(stage.responsible && stage.responsible.length > 0
        ? { responsible: stage.responsible }
        : {}),
      ...(stage.next && stage.next.length > 0 ? { next: stage.next } : {}),
    };
  });
}

type StagePatch = { [K in keyof TeamStage]?: TeamStage[K] | undefined };

function patched(stage: TeamStage, patch: StagePatch): TeamStage {
  const merged: Record<string, unknown> = { ...stage, ...patch };
  for (const key of Object.keys(patch)) {
    if (merged[key] === undefined) {
      delete merged[key];
    }
  }
  return merged as unknown as TeamStage;
}

function stageIdsOf(issues: readonly StageIssue[]): Set<string> {
  return new Set(issues.flatMap((issue) => issue.stageId ?? []));
}

type FormField = 'id' | 'title' | 'howToWork' | 'goal' | 'responsible' | 'next';

const touchKey = (stageId: string, field: FormField): string =>
  `${stageId}:${field}`;

const ISSUE_FIELD: Record<StageIssue['code'], FormField | null> = {
  STAGE_TOO_MANY: null,
  STAGE_NO_START: null,
  STAGE_MULTIPLE_STARTS: null,
  STAGE_DUPLICATE_ID: 'id',
  STAGE_ID_INVALID: 'id',
  STAGE_TITLE_REQUIRED: 'title',
  STAGE_TITLE_TOO_LONG: 'title',
  STAGE_HOW_TO_WORK_TOO_LONG: 'howToWork',
  STAGE_GOAL_REQUIRED: 'goal',
  STAGE_GOAL_TOO_LONG: 'goal',
  STAGE_TEXT_NUL: null,
  STAGE_RESPONSIBLE_UNKNOWN: 'responsible',
  STAGE_NEXT_UNKNOWN: 'next',
  STAGE_NEXT_DUPLICATE: 'next',
  STAGE_CYCLE: 'next',
};

function kindWords(facts: StageFacts): string[] {
  return [
    ...(facts.start ? ['start'] : []),
    ...(facts.branches >= 2 ? ['fork'] : []),
    ...(facts.branches === 0 ? ['final'] : []),
  ];
}

export function StageSchemaEditor({
  open,
  stages,
  members,
  initialSelectedId = null,
  onClose,
  onSave,
}: {
  open: boolean;
  stages: readonly TeamStage[] | undefined;
  /** The team's members, whom a stage's Responsible list names. */
  members: readonly MemberRef[];
  /** The stage selected on opening; the first one when absent or unknown. */
  initialSelectedId?: string | null;
  onClose: () => void;
  onSave: (stages: TeamStage[]) => void;
}): React.JSX.Element {
  const formId = useId();
  const [draft, setDraft] = useState<TeamStage[]>([]);
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [draggingId, setDraggingId] = useState<string | null>(null);
  const [touched, setTouched] = useState<ReadonlySet<string>>(new Set());
  const [attempted, setAttempted] = useState(false);
  const listRef = useRef<HTMLOListElement | null>(null);
  const endDragRef = useRef<(() => void) | null>(null);

  useEffect(() => {
    if (open) {
      setDraft([...(stages ?? [])]);
      setSelectedId(
        stages?.some((stage) => stage.id === initialSelectedId)
          ? initialSelectedId
          : (stages?.[0]?.id ?? null),
      );
      setTouched(new Set());
      setAttempted(false);
    }
  }, [open]);

  // Escape mid-drag closes the dialog while this component stays mounted.
  useEffect(() => {
    if (!open) {
      endDragRef.current?.();
    }
  }, [open]);
  useEffect(() => () => endDragRef.current?.(), []);

  const validation = useMemo(() => {
    const shape = validateStages({ stages: draft, members });
    return {
      errors: [...validateStageFields(draft), ...shape.errors],
      warnings: shape.warnings,
    };
  }, [draft, members]);
  const facts = useMemo(() => stageFacts(draft), [draft]);
  const labels = useMemo(() => memberLabels(members), [members]);
  const revealedErrors = useMemo(
    () =>
      validation.errors.filter((issue) => {
        const field = ISSUE_FIELD[issue.code];
        return (
          attempted ||
          (issue.stageId !== undefined &&
            field !== null &&
            touched.has(touchKey(issue.stageId, field)))
        );
      }),
    [validation.errors, attempted, touched],
  );
  const errorIds = useMemo(() => stageIdsOf(revealedErrors), [revealedErrors]);
  const warningIds = useMemo(
    () => stageIdsOf(validation.warnings),
    [validation.warnings],
  );
  const graphStages = useMemo(
    () => draft.map((stage) => ({ ...stage, title: stageTitle(stage) })),
    [draft],
  );

  const selected = draft.find((stage) => stage.id === selectedId) ?? null;
  const shownInForm = (issue: StageIssue): boolean =>
    selected !== null &&
    issue.stageId === selected.id &&
    ISSUE_FIELD[issue.code] !== null;
  const titleOf = (id: string | undefined): string | null => {
    const stage = id === undefined ? undefined : draft.find((s) => s.id === id);
    return stage === undefined ? null : stageTitle(stage);
  };

  const touch = (stageId: string, field: FormField): void =>
    setTouched((current) => {
      const key = touchKey(stageId, field);
      return current.has(key) ? current : new Set(current).add(key);
    });

  const update = (id: string, patch: StagePatch): void =>
    setDraft((current) =>
      current.map((stage) => (stage.id === id ? patched(stage, patch) : stage)),
    );

  const addStage = (): void => {
    const title = `Stage ${draft.length + 1}`;
    const id = stageIdFor(title, new Set(draft.map((stage) => stage.id)));
    const last = draft[draft.length - 1];
    const follows = last !== undefined && (last.next?.length ?? 0) === 0;
    setDraft([
      ...draft.map((stage) =>
        follows && stage.id === last.id
          ? patched(stage, { next: [id] })
          : stage,
      ),
      { id, title, goal: '' },
    ]);
    setSelectedId(id);
  };

  const deleteStage = (id: string): void => {
    const index = draft.findIndex((stage) => stage.id === id);
    const rest = draft
      .filter((stage) => stage.id !== id)
      .map((stage): TeamStage => {
        if (!stage.next?.includes(id)) {
          return stage;
        }
        const next = stage.next.filter((nextId) => nextId !== id);
        return patched(stage, { next: next.length > 0 ? next : undefined });
      });
    setDraft(rest);
    setTouched(
      (current) =>
        new Set([...current].filter((key) => !key.startsWith(`${id}:`))),
    );
    if (selectedId === id) {
      setSelectedId((rest[index] ?? rest[index - 1])?.id ?? null);
    }
  };

  const moveStageTo = (id: string, to: number): void =>
    setDraft((current) => {
      const from = current.findIndex((stage) => stage.id === id);
      if (from === to) {
        return current;
      }
      const next = current.filter((_, index) => index !== from);
      next.splice(to, 0, current[from]!);
      return next;
    });

  const moveStage = (id: string, by: -1 | 1): void =>
    moveStageTo(id, draft.findIndex((stage) => stage.id === id) + by);

  const startDrag = (id: string, event: React.PointerEvent): void => {
    event.preventDefault();
    setDraggingId(id);
    setSelectedId(id);
    const move = (moved: PointerEvent): void => {
      const list = listRef.current;
      if (list === null) {
        return;
      }
      const others = [
        ...list.querySelectorAll<HTMLElement>('[data-slot="stage-row"]'),
      ].filter((row) => row.dataset.stageId !== id);
      const to = others.filter((row) => {
        const box = row.getBoundingClientRect();
        return box.top + box.height / 2 < moved.clientY;
      }).length;
      moveStageTo(id, to);
    };
    const end = (): void => {
      setDraggingId(null);
      window.removeEventListener('pointermove', move);
      window.removeEventListener('pointerup', end);
      window.removeEventListener('pointercancel', end);
      endDragRef.current = null;
    };
    window.addEventListener('pointermove', move);
    window.addEventListener('pointerup', end);
    window.addEventListener('pointercancel', end);
    endDragRef.current = end;
  };

  const toggleNext = (stage: TeamStage, nextId: string): void => {
    const current = stage.next ?? [];
    const next = current.includes(nextId)
      ? current.filter((id) => id !== nextId)
      : [...current, nextId];
    update(stage.id, { next: next.length > 0 ? next : undefined });
  };

  const blocked = validation.errors.length > 0;
  const tooMany = draft.length >= MAX_TEAM_STAGES;
  const elsewhereErrors = revealedErrors.filter((i) => !shownInForm(i));
  const confirm = (): void => {
    if (blocked) {
      setAttempted(true);
      return;
    }
    onSave(normalized(draft));
  };
  const elsewhereWarnings = validation.warnings.filter((i) => !shownInForm(i));

  return (
    <Dialog open={open} onClose={onClose} title="Stages" className="max-w-4xl">
      <div data-slot="stage-schema-editor" className="flex flex-col gap-5">
        <p className="text-sm text-muted-foreground">
          The steps every run of this team walks. Members see them and move the
          run from one to the next.
        </p>

        {attempted && blocked ? (
          <IssueSummary
            tone="error"
            heading={`Error — fix ${validation.errors.length === 1 ? 'this' : `these ${validation.errors.length}`} before saving`}
            issues={elsewhereErrors}
            titleOf={titleOf}
          />
        ) : null}
        {elsewhereWarnings.length > 0 ? (
          <IssueSummary
            tone="warning"
            heading="Warning — this does not block saving"
            issues={elsewhereWarnings}
            titleOf={titleOf}
          />
        ) : null}

        <div className="grid gap-5 sm:grid-cols-[18rem_minmax(0,1fr)]">
          <div className="flex min-w-0 flex-col gap-2">
            <p className="flex items-baseline justify-between px-1 text-xs text-muted-foreground">
              <span className="font-medium">Stages</span>
              <span className="tabular-nums">
                {draft.length} of {MAX_TEAM_STAGES}
              </span>
            </p>
            <div className="rounded-xl border border-border px-3 py-1">
              <ol
                ref={listRef}
                aria-label="Stages"
                data-slot="stage-list"
                className="flex flex-col">
                {draft.map((stage, index) => (
                  <StageRow
                    key={stage.id}
                    stage={stage}
                    lead={
                      stage.responsible?.[0] === undefined
                        ? null
                        : (labels.get(stage.responsible[0]) ??
                          stage.responsible[0])
                    }
                    title={stageTitle(stage)}
                    facts={facts.get(stage.id)!}
                    selected={stage.id === selectedId}
                    hasError={errorIds.has(stage.id)}
                    hasWarning={warningIds.has(stage.id)}
                    dragging={stage.id === draggingId}
                    first={index === 0}
                    last={index === draft.length - 1}
                    onSelect={() => setSelectedId(stage.id)}
                    onMove={(by) => moveStage(stage.id, by)}
                    onDelete={() => deleteStage(stage.id)}
                    onDragStart={(event) => startDrag(stage.id, event)}
                  />
                ))}
              </ol>
              {draft.length === 0 ? (
                <p className="py-2 text-sm text-muted-foreground">
                  No stages yet. Add the first one.
                </p>
              ) : null}
              <div
                className={cn(
                  'py-1',
                  draft.length > 0 && 'border-t border-border',
                )}>
                <Button
                  type="button"
                  variant="ghost"
                  disabled={tooMany}
                  className="h-auto w-full justify-start gap-2 rounded-md px-0.5 py-1 font-normal text-muted-foreground hover:bg-transparent hover:text-foreground"
                  onClick={addStage}>
                  <Plus className="size-3.5" aria-hidden="true" />
                  Add stage
                </Button>
              </div>
            </div>
            {tooMany ? (
              <p className="px-1 text-xs text-muted-foreground">
                A team may have at most {MAX_TEAM_STAGES} stages.
              </p>
            ) : null}
          </div>

          <div className="min-w-0 sm:border-l sm:border-border sm:pl-5">
            {selected === null ? (
              <p className="flex h-full min-h-32 items-center justify-center text-center text-sm text-muted-foreground">
                {draft.length === 0
                  ? 'A stage’s details appear here once there is one.'
                  : 'Pick a stage to edit it.'}
              </p>
            ) : (
              <StageForm
                key={selected.id}
                idPrefix={`${formId}-${selected.id}`}
                stage={selected}
                facts={facts.get(selected.id)!}
                stages={draft}
                members={members}
                errors={revealedErrors.filter(shownInForm)}
                warnings={validation.warnings.filter(shownInForm)}
                onChange={(patch) => update(selected.id, patch)}
                onTouch={(field) => touch(selected.id, field)}
                onToggleNext={(nextId) => {
                  toggleNext(selected, nextId);
                  touch(selected.id, 'next');
                }}
              />
            )}
          </div>
        </div>

        {draft.length > 0 ? (
          <section className="flex flex-col gap-2 border-t border-border pt-4">
            <div className="flex flex-wrap items-baseline justify-between gap-x-3 gap-y-1">
              <p className="text-sm font-medium">Preview</p>
              <p className="hidden text-xs text-muted-foreground sm:block">
                Point at a stage to trace its lines; click it to edit it.
              </p>
            </div>
            <StageGraph
              stages={graphStages}
              selectedId={selectedId}
              errorIds={errorIds}
              onSelect={setSelectedId}
              className="py-1"
            />
          </section>
        ) : null}

        <div className="flex justify-end gap-2">
          <Button type="button" variant="outline" onClick={onClose}>
            Cancel
          </Button>
          <Button type="button" onClick={confirm}>
            <Check aria-hidden="true" />
            Done
          </Button>
        </div>
      </div>
    </Dialog>
  );
}

const issueToneVariants = cva('', {
  variants: {
    tone: { error: 'text-destructive', warning: 'text-warning' },
  },
});

const ISSUE_ICON = { error: TriangleAlert, warning: CircleAlert } as const;

function IssueSummary({
  tone,
  heading,
  issues,
  titleOf,
}: {
  tone: 'error' | 'warning';
  heading: string;
  issues: readonly StageIssue[];
  titleOf: (id: string | undefined) => string | null;
}): React.JSX.Element {
  const Icon = ISSUE_ICON[tone];
  return (
    <div
      role={tone === 'error' ? 'alert' : undefined}
      data-slot={tone === 'error' ? 'stage-errors' : 'stage-warnings'}
      className="flex flex-col gap-1 text-sm">
      <p
        className={cn(
          'flex items-center gap-2 font-medium',
          issueToneVariants({ tone }),
        )}>
        <Icon className="size-4 shrink-0" aria-hidden="true" />
        {heading}
      </p>
      {issues.length > 0 ? (
        <ul className="flex flex-col gap-0.5 pl-6 text-muted-foreground">
          {issues.map((issue, index) => {
            const title = titleOf(issue.stageId);
            return (
              <li key={`${issue.code}-${index}`} className="list-disc">
                {title === null ? null : (
                  <span className="text-foreground">{title}: </span>
                )}
                {issue.message}
              </li>
            );
          })}
        </ul>
      ) : null}
    </div>
  );
}

const rowVariants = cva(
  'group/row relative flex items-center gap-1.5 border-b border-border transition-[background-color,box-shadow] last:border-b-0',
  {
    variants: {
      dragging: {
        true: 'z-10 -mx-1.5 rounded-md bg-card px-1.5 shadow-panel-md',
        false: '',
      },
    },
  },
);

const rowTitleVariants = cva('max-w-[65%] min-w-0 shrink-0 truncate', {
  variants: {
    selected: {
      true: 'font-semibold text-primary',
      false: 'text-foreground',
    },
  },
});

const wordToneVariants = cva('', {
  variants: {
    tone: {
      plain: '',
      error: 'text-destructive',
      warning: 'text-warning',
    },
  },
});

function StageRow({
  stage,
  lead,
  title,
  facts,
  selected,
  hasError,
  hasWarning,
  dragging,
  first,
  last,
  onSelect,
  onMove,
  onDelete,
  onDragStart,
}: {
  stage: TeamStage;
  /** The label of the member who leads the stage, when one is named. */
  lead: string | null;
  title: string;
  facts: StageFacts;
  selected: boolean;
  hasError: boolean;
  hasWarning: boolean;
  dragging: boolean;
  first: boolean;
  last: boolean;
  onSelect: () => void;
  onMove: (by: -1 | 1) => void;
  onDelete: () => void;
  onDragStart: (event: React.PointerEvent) => void;
}): React.JSX.Element {
  const [menuOpen, setMenuOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement | null>(null);
  const words: { text: string; tone: 'plain' | 'error' | 'warning' }[] = [
    ...(hasError ? [{ text: 'error', tone: 'error' as const }] : []),
    ...(hasWarning ? [{ text: 'warning', tone: 'warning' as const }] : []),
    ...kindWords(facts).map((text) => ({ text, tone: 'plain' as const })),
    ...(lead === null ? [] : [{ text: lead, tone: 'plain' as const }]),
  ];
  return (
    <li
      data-slot="stage-row"
      data-stage-id={stage.id}
      data-dragging={dragging || undefined}
      className={rowVariants({ dragging })}>
      <span
        data-slot="stage-drag-handle"
        aria-hidden="true"
        title="Drag to reorder"
        className="flex w-3.5 shrink-0 cursor-grab touch-none items-center justify-center self-stretch text-muted-foreground/60 transition-colors group-hover/row:text-muted-foreground group-data-[dragging]/row:cursor-grabbing"
        onPointerDown={onDragStart}>
        <GripVertical className="size-3.5" />
      </span>
      <button
        type="button"
        aria-current={selected ? 'true' : undefined}
        className="flex min-w-0 flex-1 cursor-pointer items-center gap-3 rounded-md py-2 text-left text-sm outline-none focus-visible:ring-[3px] focus-visible:ring-ring/50"
        onClick={onSelect}>
        <span
          data-slot="stage-row-title"
          className={rowTitleVariants({ selected })}>
          {title}
        </span>
        {words.length > 0 ? (
          <span
            data-slot="stage-row-words"
            className="ml-auto min-w-0 truncate text-right text-xs text-muted-foreground">
            {words.map((word, index) => (
              <span key={word.text}>
                {index > 0 ? ' · ' : null}
                <span className={wordToneVariants({ tone: word.tone })}>
                  {word.text}
                </span>
              </span>
            ))}
          </span>
        ) : null}
      </button>
      <span className="relative inline-flex shrink-0">
        <Button
          ref={triggerRef}
          type="button"
          variant="ghost"
          size="icon"
          data-menu-trigger
          className="size-6 text-muted-foreground transition-opacity aria-expanded:opacity-100 sm:opacity-0 sm:group-hover/row:opacity-100 sm:focus-visible:opacity-100 sm:group-has-[[aria-current]]/row:opacity-100"
          aria-haspopup="listbox"
          aria-expanded={menuOpen}
          aria-label={`Options for ${title}`}
          onClick={() => setMenuOpen((open) => !open)}>
          <MoreVertical className="size-3.5" aria-hidden="true" />
        </Button>
        <Menu
          open={menuOpen}
          side="bottom"
          align="end"
          triggerRef={triggerRef}
          className="min-w-44"
          groups={[
            {
              items: [
                {
                  value: 'up',
                  label: 'Move up',
                  icon: <ArrowUp className="size-4" />,
                  action: true,
                  disabled: first,
                },
                {
                  value: 'down',
                  label: 'Move down',
                  icon: <ArrowDown className="size-4" />,
                  action: true,
                  disabled: last,
                },
                {
                  value: 'delete',
                  label: 'Delete',
                  icon: <Trash2 className="size-4" />,
                  action: true,
                  tone: 'destructive',
                },
              ],
            },
          ]}
          onSelect={(value) => {
            if (value === 'up') {
              onMove(-1);
            } else if (value === 'down') {
              onMove(1);
            } else {
              onDelete();
            }
          }}
          onClose={() => {
            setMenuOpen(false);
            triggerRef.current?.focus();
          }}
        />
      </span>
    </li>
  );
}

function FieldIssues({
  errors,
  warnings,
}: {
  errors: readonly StageIssue[];
  warnings: readonly StageIssue[];
}): React.JSX.Element | null {
  const issues = [
    ...errors.map((issue) => ({ issue, tone: 'error' as const })),
    ...warnings.map((issue) => ({ issue, tone: 'warning' as const })),
  ];
  if (issues.length === 0) {
    return null;
  }
  return (
    <>
      {issues.map(({ issue, tone }, index) => {
        const Icon = ISSUE_ICON[tone];
        return (
          <p
            key={`${issue.code}-${index}`}
            data-slot="stage-field-issue"
            data-tone={tone}
            className={cn(
              'flex items-start gap-1.5 text-xs',
              issueToneVariants({ tone }),
            )}>
            <Icon className="mt-px size-3.5 shrink-0" aria-hidden="true" />
            <span>
              <span className="sr-only">
                {tone === 'error' ? 'Error: ' : 'Warning: '}
              </span>
              {issue.message}
            </span>
          </p>
        );
      })}
    </>
  );
}

function StageForm({
  idPrefix,
  stage,
  facts,
  stages,
  members,
  errors,
  warnings,
  onChange,
  onTouch,
  onToggleNext,
}: {
  idPrefix: string;
  stage: TeamStage;
  facts: StageFacts;
  stages: readonly TeamStage[];
  members: readonly MemberRef[];
  errors: readonly StageIssue[];
  warnings: readonly StageIssue[];
  onChange: (patch: StagePatch) => void;
  onTouch: (field: FormField) => void;
  onToggleNext: (nextId: string) => void;
}): React.JSX.Element {
  const others = stages.filter((other) => other.id !== stage.id);
  const next = stage.next ?? [];
  const at = (
    field: FormField,
  ): { errors: StageIssue[]; warnings: StageIssue[] } => ({
    errors: errors.filter((issue) => ISSUE_FIELD[issue.code] === field),
    warnings: warnings.filter((issue) => ISSUE_FIELD[issue.code] === field),
  });
  const invalid = (field: FormField): true | undefined =>
    at(field).errors.length > 0 || undefined;
  const nextLabels = distinctStageLabels(
    others.map((other) => ({ id: other.id, title: stageTitle(other) })),
  );
  const onlyNext = stages.find((other) => other.id === next[0]);
  const nextLine =
    next.length >= 2
      ? `Fork — the run takes one of ${next.length}`
      : next.length === 1
        ? `Then ${onlyNext ? stageTitle(onlyNext) : next[0]}`
        : 'Final stage — the run ends here';
  return (
    <div data-slot="stage-form" className="flex min-w-0 flex-col gap-4">
      <header className="flex flex-col gap-1.5">
        <div className="flex min-w-0 items-baseline gap-2">
          <p className="truncate text-sm font-semibold">{stageTitle(stage)}</p>
          <p className="min-w-0 truncate font-mono text-xs text-muted-foreground">
            {stage.id}
          </p>
          <p className="ml-auto shrink-0 text-xs text-muted-foreground">
            {kindWords(facts).join(' · ')}
          </p>
        </div>
        <FieldIssues {...at('id')} />
      </header>
      <Field
        label="Title"
        htmlFor={`${idPrefix}-title`}
        hint="A short name for this stage.">
        <Input
          id={`${idPrefix}-title`}
          value={stage.title}
          aria-invalid={invalid('title')}
          placeholder="Investigation"
          onChange={(event) => {
            onChange({ title: event.target.value });
            onTouch('title');
          }}
          onBlur={() => onTouch('title')}
        />
        <FieldIssues {...at('title')} />
      </Field>
      <Field
        label="How to work"
        htmlFor={`${idPrefix}-how-to-work`}
        hint="Optional — how to work in this stage, in plain language.">
        <ExpandableTextarea
          id={`${idPrefix}-how-to-work`}
          title="How to work"
          invalid={invalid('howToWork')}
          value={stage.howToWork ?? ''}
          rows={3}
          onChange={(next) => {
            onChange({ howToWork: next });
            onTouch('howToWork');
          }}
          onBlur={() => onTouch('howToWork')}
        />
        <FieldIssues {...at('howToWork')} />
      </Field>
      <Field
        label="Goal"
        htmlFor={`${idPrefix}-goal`}
        hint="The condition that makes this stage done.">
        <Input
          id={`${idPrefix}-goal`}
          value={stage.goal}
          aria-invalid={invalid('goal')}
          placeholder="The cause is written down"
          onChange={(event) => {
            onChange({ goal: event.target.value });
            onTouch('goal');
          }}
          onBlur={() => onTouch('goal')}
        />
        <FieldIssues {...at('goal')} />
      </Field>
      <Field
        label="Responsible"
        htmlFor={`${idPrefix}-responsible`}
        hint="The members who take this stage, in order — the first one leads it.">
        <ResponsiblePick
          id={`${idPrefix}-responsible`}
          members={members}
          responsible={stage.responsible ?? []}
          onChange={(responsible) => {
            onChange({
              responsible: responsible.length > 0 ? responsible : undefined,
            });
            onTouch('responsible');
          }}
        />
        <FieldIssues {...at('responsible')} />
      </Field>
      <Field
        label="Next stages"
        hint={
          <>
            <span data-slot="stage-next-hint">{nextLine}</span>
            {next.length < 2 && others.length > 1
              ? '. Pick two or more for a fork.'
              : null}
          </>
        }>
        {others.length === 0 ? (
          <p className="text-sm text-muted-foreground">
            Add another stage to choose what follows this one.
          </p>
        ) : (
          <OptionList
            arity="many"
            label="Next stages"
            options={others.map((other) => nextLabels.get(other.id)!)}
            selected={next.flatMap((id) => nextLabels.get(id) ?? [])}
            onPick={(label) => {
              const picked = others.find(
                (other) => nextLabels.get(other.id) === label,
              );
              if (picked) {
                onToggleNext(picked.id);
              }
            }}
          />
        )}
        <FieldIssues {...at('next')} />
      </Field>
    </div>
  );
}
