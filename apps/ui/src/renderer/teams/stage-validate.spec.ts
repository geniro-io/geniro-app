import { describe, expect, it } from 'vitest';

import type { TeamStage } from '../autogenerated';
import {
  stageFacts,
  stageIdFor,
  stageTitle,
  validateStageFields,
  validateStages,
} from './stage-validate';

const MEMBERS = [{ id: 'coder' }, { id: 'reviewer' }];

function stage(
  id: string,
  next?: string[],
  extra: Partial<TeamStage> = {},
): TeamStage {
  return {
    id,
    title: id.toUpperCase(),
    goal: `${id} is done`,
    ...(next ? { next } : {}),
    ...extra,
  };
}

const codes = (issues: { code: string }[]): string[] =>
  issues.map((issue) => issue.code);

describe('validateStages (twin of the daemon validator)', () => {
  it('has nothing to say about no stages or an empty list', () => {
    expect(validateStages({ members: MEMBERS })).toEqual({
      errors: [],
      warnings: [],
    });
    expect(validateStages({ stages: [], members: MEMBERS })).toEqual({
      errors: [],
      warnings: [],
    });
  });

  it('accepts a line and a one-of fork that rejoins', () => {
    const fork = [
      stage('investigate', ['implement', 'fix']),
      stage('implement', ['review']),
      stage('fix', ['review']),
      stage('review', ['done']),
      stage('done'),
    ];
    expect(validateStages({ stages: fork, members: MEMBERS })).toEqual({
      errors: [],
      warnings: [],
    });
  });

  it('refuses a stage graph that loops back', () => {
    const { errors } = validateStages({
      stages: [stage('a', ['b']), stage('b', ['c']), stage('c', ['b'])],
      members: MEMBERS,
    });
    expect(codes(errors)).toEqual(['STAGE_CYCLE']);
    expect(errors[0]!.message).toContain('b → c → b');
  });

  it('refuses a graph in which every stage is named as a next stage', () => {
    expect(
      codes(
        validateStages({
          stages: [stage('a', ['b']), stage('b', ['a'])],
          members: MEMBERS,
        }).errors,
      ),
    ).toEqual(['STAGE_NO_START']);
  });

  it('refuses more than one start, naming them', () => {
    const { errors } = validateStages({
      stages: [stage('a', ['c']), stage('b', ['c']), stage('c')],
      members: MEMBERS,
    });
    expect(codes(errors)).toEqual(['STAGE_MULTIPLE_STARTS']);
    expect(errors[0]!.message).toContain("'a', 'b'");
  });

  it('refuses a duplicate id, an unknown next and a next listed twice', () => {
    expect(
      codes(
        validateStages({
          stages: [stage('a', ['b']), stage('a')],
          members: MEMBERS,
        }).errors,
      ),
    ).toContain('STAGE_DUPLICATE_ID');
    expect(
      validateStages({ stages: [stage('a', ['ghost'])], members: MEMBERS })
        .errors,
    ).toEqual([
      expect.objectContaining({ code: 'STAGE_NEXT_UNKNOWN', stageId: 'a' }),
    ]);
    expect(
      codes(
        validateStages({
          stages: [stage('a', ['b', 'b']), stage('b')],
          members: MEMBERS,
        }).errors,
      ),
    ).toEqual(['STAGE_NEXT_DUPLICATE']);
  });

  it('refuses more than 20 stages', () => {
    const many = Array.from({ length: 21 }, (_, i) =>
      stage(`s${i}`, i < 20 ? [`s${i + 1}`] : undefined),
    );
    expect(
      codes(validateStages({ stages: many, members: MEMBERS }).errors),
    ).toEqual(['STAGE_TOO_MANY']);
  });

  it('warns, never refuses, about a responsible id that is no member of the team', () => {
    const result = validateStages({
      stages: [
        stage('a', ['b'], { responsible: ['coder', 'ghost'] }),
        stage('b', undefined, { responsible: ['brief'] }),
      ],
      members: MEMBERS,
    });
    expect(result.errors).toEqual([]);
    expect(result.warnings).toEqual([
      expect.objectContaining({
        code: 'STAGE_RESPONSIBLE_UNKNOWN',
        stageId: 'a',
        message: expect.stringContaining("'ghost'"),
      }),
      expect.objectContaining({
        code: 'STAGE_RESPONSIBLE_UNKNOWN',
        stageId: 'b',
      }),
    ]);
    expect(
      validateStages({
        stages: [stage('a', undefined, { responsible: ['coder', 'reviewer'] })],
        members: MEMBERS,
      }).warnings,
    ).toEqual([]);
  });
});

describe('validateStageFields', () => {
  it('accepts a stage at every limit', () => {
    expect(
      validateStageFields([
        stage('a', undefined, {
          title: 'x'.repeat(80),
          howToWork: 'y'.repeat(4000),
          goal: 'z'.repeat(300),
        }),
      ]),
    ).toEqual([]);
  });

  it('reports each broken field against its stage', () => {
    const issues = validateStageFields([
      stage('ok'),
      stage('bad', undefined, {
        title: '   ',
        goal: '',
      }),
      stage('long', undefined, {
        title: 'x'.repeat(81),
        howToWork: 'y'.repeat(4001),
        goal: 'z'.repeat(301),
      }),
      stage('123'),
      stage('Has Caps'),
    ]);
    expect(issues.map((i) => `${i.stageId}:${i.code}`)).toEqual([
      'bad:STAGE_TITLE_REQUIRED',
      'bad:STAGE_GOAL_REQUIRED',
      'long:STAGE_TITLE_TOO_LONG',
      'long:STAGE_HOW_TO_WORK_TOO_LONG',
      'long:STAGE_GOAL_TOO_LONG',
      '123:STAGE_ID_INVALID',
      'Has Caps:STAGE_ID_INVALID',
    ]);
  });

  it.each<[string, Partial<TeamStage>]>([
    ['title', { title: 'Re\u0000view' }],
    ['howToWork', { howToWork: 'Read\u0000 it' }],
    ['goal', { goal: 'It is\u0000 done' }],
    ['responsible', { responsible: ['cod\u0000er'] }],
  ])('reports a NUL in a stage’s %s as STAGE_TEXT_NUL', (_field, extra) => {
    expect(
      validateStageFields([stage('a'), stage('nul', undefined, extra)]),
    ).toEqual([
      expect.objectContaining({ code: 'STAGE_TEXT_NUL', stageId: 'nul' }),
    ]);
  });
});

describe('stageIdFor', () => {
  it('makes a lowercase slug and keeps it unique', () => {
    expect(stageIdFor('Fix the Build!', new Set())).toBe('fix-the-build');
    expect(stageIdFor('Review', new Set(['review']))).toBe('review-2');
    expect(stageIdFor('Review', new Set(['review', 'review-2']))).toBe(
      'review-3',
    );
  });

  it('never returns an all-digit or empty id, nor one over 40 characters', () => {
    expect(stageIdFor('2024', new Set())).toBe('stage-2024');
    expect(stageIdFor('???', new Set())).toBe('stage');
    const long = stageIdFor('word '.repeat(30), new Set());
    expect(long.length).toBeLessThanOrEqual(40);
    const next = stageIdFor('word '.repeat(30), new Set([long]));
    expect(next.length).toBeLessThanOrEqual(40);
    expect(next).not.toBe(long);
    for (const id of ['stage-2024', 'stage', long, next]) {
      expect(validateStageFields([stage(id)])).toEqual([]);
    }
  });
});

describe('stage facts', () => {
  it('marks the start, forks and finals, counting each next stage once', () => {
    const facts = stageFacts([
      stage('a', ['b', 'c', 'c']),
      stage('b', ['c']),
      stage('c'),
      stage('a', ['b']),
    ]);
    expect([...facts.entries()]).toEqual([
      ['a', { start: true, branches: 2 }],
      ['b', { start: false, branches: 1 }],
      ['c', { start: false, branches: 0 }],
    ]);
  });
});

describe('stageTitle', () => {
  it('trims a title and stands in for a blank one', () => {
    expect(stageTitle({ title: '  Fix  ' })).toBe('Fix');
    expect(stageTitle({ title: '   ' })).toBe('Untitled stage');
  });
});
