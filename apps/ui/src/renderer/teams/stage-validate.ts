import type { TeamMember, TeamStage } from '../autogenerated';

export const MAX_TEAM_STAGES = 20;
export const MAX_STAGE_TITLE_LENGTH = 80;
export const MAX_STAGE_INSTRUCTIONS_LENGTH = 4000;
export const MAX_STAGE_DONE_WHEN_LENGTH = 300;
export const STAGE_ID_PATTERN = /^(?![0-9]+$)[a-z0-9][a-z0-9-]{0,39}$/;

const MAX_STAGE_ID_LENGTH = 40;

export type StageIssueCode =
  | 'STAGE_TOO_MANY'
  | 'STAGE_DUPLICATE_ID'
  | 'STAGE_NEXT_UNKNOWN'
  | 'STAGE_NEXT_DUPLICATE'
  | 'STAGE_NO_START'
  | 'STAGE_MULTIPLE_STARTS'
  | 'STAGE_CYCLE'
  | 'STAGE_RESPONSIBLE_UNKNOWN';

export type StageFieldIssueCode =
  | 'STAGE_ID_INVALID'
  | 'STAGE_TITLE_REQUIRED'
  | 'STAGE_TITLE_TOO_LONG'
  | 'STAGE_HOW_TO_WORK_TOO_LONG'
  | 'STAGE_GOAL_REQUIRED'
  | 'STAGE_GOAL_TOO_LONG'
  | 'STAGE_TEXT_NUL';

export interface StageIssue {
  code: StageIssueCode | StageFieldIssueCode;
  message: string;
  stageId?: string;
}

export interface StageValidation {
  errors: StageIssue[];
  warnings: StageIssue[];
}

