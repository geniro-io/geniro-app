export function validateStages(team: {
  stages?: readonly TeamStage[] | undefined;
  members: readonly Pick<TeamMember, 'id'>[];
}): StageValidation {
  const errors: StageIssue[] = [];
  const warnings: StageIssue[] = [];
  const stages = team.stages;
  if (stages === undefined || stages.length === 0) {
    return { errors, warnings };
  }
  if (stages.length > MAX_TEAM_STAGES) {
    errors.push({
      code: 'STAGE_TOO_MANY',
      message: `A team may have at most ${MAX_TEAM_STAGES} stages; this one has ${stages.length}`,
    });
  }

  const ids = new Set<string>();
  for (const stage of stages) {
    if (ids.has(stage.id)) {
      errors.push({
        code: 'STAGE_DUPLICATE_ID',
        message: `Two stages share the id '${stage.id}'`,
        stageId: stage.id,
      });
    }
    ids.add(stage.id);
  }

  const memberIds = new Set(team.members.map((member) => member.id));
  const incoming = new Map<string, number>([...ids].map((id) => [id, 0]));
  for (const stage of stages) {
    const seen = new Set<string>();
    for (const next of stage.next ?? []) {
      if (seen.has(next)) {
        errors.push({
          code: 'STAGE_NEXT_DUPLICATE',
          message: `Stage '${stage.id}' lists '${next}' as a next stage twice`,
          stageId: stage.id,
        });
        continue;
      }
      seen.add(next);
      if (!ids.has(next)) {
        errors.push({
          code: 'STAGE_NEXT_UNKNOWN',
          message: `Stage '${stage.id}' names a next stage '${next}' that does not exist`,
          stageId: stage.id,
        });
        continue;
      }
      incoming.set(next, (incoming.get(next) ?? 0) + 1);
    }
    for (const responsible of stage.responsible ?? []) {
      if (!memberIds.has(responsible)) {
        warnings.push({
          code: 'STAGE_RESPONSIBLE_UNKNOWN',
          message: `Stage '${stage.id}' names '${responsible}' as responsible, which is not a member of this team; it is left out of what members are told`,
          stageId: stage.id,
        });
      }
    }
  }
  if (errors.length > 0) {
    return { errors, warnings };
  }

  const starts = stages.filter((s) => incoming.get(s.id) === 0);
  if (starts.length === 0) {
    errors.push({
      code: 'STAGE_NO_START',
      message:
        'Every stage is named as a next stage, so none can come first — one stage must start the walk',
    });
    return { errors, warnings };
  }
  if (starts.length > 1) {
    errors.push({
      code: 'STAGE_MULTIPLE_STARTS',
      message: `Only one stage may start the walk; ${starts.map((s) => `'${s.id}'`).join(', ')} are each named by no other stage`,
    });
    return { errors, warnings };
  }

  const cycle = cycleIn(stages);
  if (cycle !== null) {
    errors.push({
      code: 'STAGE_CYCLE',
      message: `The stages loop back on themselves: ${cycle.join(' → ')}`,
      stageId: cycle[0],
    });
  }

  return { errors, warnings };
}

function cycleIn(stages: readonly TeamStage[]): string[] | null {
  const byId = new Map(stages.map((s) => [s.id, s]));
  const done = new Set<string>();
  const path: string[] = [];
  const onPath = new Set<string>();
  const visit = (id: string): string[] | null => {
    if (onPath.has(id)) {
      return [...path.slice(path.indexOf(id)), id];
    }
    if (done.has(id)) {
      return null;
    }
    onPath.add(id);
    path.push(id);
    for (const next of byId.get(id)?.next ?? []) {
      const found = visit(next);
      if (found !== null) {
        return found;
      }
    }
    path.pop();
    onPath.delete(id);
    done.add(id);
    return null;
  };
  for (const stage of stages) {
    const found = visit(stage.id);
    if (found !== null) {
      return found;
    }
  }
  return null;
}

export function validateStageFields(
  stages: readonly TeamStage[] | undefined,
): StageIssue[] {
  const issues: StageIssue[] = [];
  for (const stage of stages ?? []) {
    const issue = (code: StageFieldIssueCode, message: string): number =>
      issues.push({ code, message, stageId: stage.id });
    if (!STAGE_ID_PATTERN.test(stage.id)) {
      issue(
        'STAGE_ID_INVALID',
        `Stage id '${stage.id}' must be lowercase letters, digits and '-', at most ${MAX_STAGE_ID_LENGTH} characters, and not all digits`,
      );
    }
    if (!/\S/.test(stage.title)) {
      issue('STAGE_TITLE_REQUIRED', 'A stage needs a title');
    } else if (stage.title.length > MAX_STAGE_TITLE_LENGTH) {
      issue(
        'STAGE_TITLE_TOO_LONG',
        `A stage title may have at most ${MAX_STAGE_TITLE_LENGTH} characters; this one has ${stage.title.length}`,
      );
    }
    if ((stage.howToWork?.length ?? 0) > MAX_STAGE_INSTRUCTIONS_LENGTH) {
      issue(
        'STAGE_HOW_TO_WORK_TOO_LONG',
        `How to work may have at most ${MAX_STAGE_INSTRUCTIONS_LENGTH} characters; this has ${stage.howToWork?.length}`,
      );
    }
    if (!/\S/.test(stage.goal)) {
      issue('STAGE_GOAL_REQUIRED', 'A stage needs a goal');
    } else if (stage.goal.length > MAX_STAGE_DONE_WHEN_LENGTH) {
      issue(
        'STAGE_GOAL_TOO_LONG',
        `A goal may have at most ${MAX_STAGE_DONE_WHEN_LENGTH} characters; this one has ${stage.goal.length}`,
      );
    }
    if (
      [
        stage.title,
        stage.howToWork,
        stage.goal,
        ...(stage.responsible ?? []),
      ].some((text) => text?.includes('\u0000'))
    ) {
      issue('STAGE_TEXT_NUL', 'Stage text must not contain a NUL character');
    }
  }
  return issues;
}

export function stageIdFor(title: string, taken: ReadonlySet<string>): string {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, MAX_STAGE_ID_LENGTH)
    .replace(/-+$/, '');
  const base = slug === '' || /^[0-9]+$/.test(slug) ? `stage-${slug}` : slug;
  let candidate = base.replace(/-+$/, '');
  for (let n = 2; taken.has(candidate); n += 1) {
    const suffix = `-${n}`;
    candidate = `${base.slice(0, MAX_STAGE_ID_LENGTH - suffix.length)}${suffix}`;
  }
  return candidate;
}

export interface StageFacts {
  start: boolean;
  branches: number;
}

export function stageFacts(
  stages: readonly TeamStage[],
): Map<string, StageFacts> {
  const named = new Set<string>();
  for (const stage of stages) {
    for (const next of stage.next ?? []) {
      named.add(next);
    }
  }
  const facts = new Map<string, StageFacts>();
  stages.forEach((stage) => {
    if (!facts.has(stage.id)) {
      facts.set(stage.id, {
        start: !named.has(stage.id),
        branches: new Set(stage.next ?? []).size,
      });
    }
  });
  return facts;
}

export function stageTitle(stage: Pick<TeamStage, 'title'>): string {
  return stage.title.trim() === '' ? 'Untitled stage' : stage.title.trim();
}
