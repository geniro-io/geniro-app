// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { TeamSummaryDto as TeamSummary } from '../autogenerated';
import { TeamCard } from './team-card';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const SUMMARY: TeamSummary = {
  slug: 'review-team',
  name: 'Review Team',
  description: 'Coder then reviewer',
  memberCount: 3,
  stageCount: 2,
  agentCounts: [
    { kind: 'claude', count: 2 },
    { kind: 'cursor-agent', count: 1 },
  ],
  portrait: [
    { id: 'coder', name: 'Coder' },
    {
      id: 'reviewer',
      name: 'Reviewer',
      avatar: { kind: 'emoji', value: '🦉' },
    },
    { id: 'tester', name: 'Tester' },
  ],
  updatedAt: new Date().toISOString(),
};

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  vi.restoreAllMocks();
});

function render(
  summary: TeamSummary,
  onOpen: () => void = vi.fn(),
  onDelete: () => void | Promise<void> = vi.fn(),
): HTMLElement {
  act(() => {
    root.render(
      <ul>
        <TeamCard summary={summary} onOpen={onOpen} onDelete={onDelete} />
      </ul>,
    );
  });
  const el = container.querySelector<HTMLElement>(
    `button[aria-label="Open ${summary.name}"]`,
  );
  if (!el) {
    throw new Error('TeamCard did not render a clickable element');
  }
  return el;
}

function deleteButton(): HTMLButtonElement {
  const el = container.querySelector<HTMLButtonElement>(
    `[aria-label="Delete ${SUMMARY.name}"]`,
  );
  if (!el) {
    throw new Error('TeamCard did not render a delete button');
  }
  return el;
}

/** One click on the card's delete control, as a user's would bubble. */
function clickDelete(): void {
  act(() => {
    deleteButton().dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

describe('TeamCard', () => {
  it('draws the team as a portrait of its members, then how many more', () => {
    render({ ...SUMMARY, memberCount: 9 });
    const faces = container.querySelectorAll('[data-slot="avatar"]');
    expect(faces.length).toBe(3);
    expect(faces[1]?.getAttribute('data-avatar-kind')).toBe('emoji');
    expect(
      container.querySelector('[data-slot="avatar-stack-rest"]')?.textContent,
    ).toBe('+6');
  });

  it('shows the name, description and member/stage counts — no node or edge counters', () => {
    render(SUMMARY);
    const text = container.textContent ?? '';
    expect(text).toContain('Review Team');
    expect(text).toContain('Coder then reviewer');
    expect(text).toContain('3 members · 2 stages');
    expect(text).not.toContain('claude ×2');
  });

  it('lets the description wrap to two lines rather than truncating to one', () => {
    render(SUMMARY);
    const description = [...container.querySelectorAll('p')].find(
      (p) => p.textContent === 'Coder then reviewer',
    );
    expect(description?.className).toContain('line-clamp-2');
    expect(description?.className).not.toContain('truncate');
  });

  it('marks open setup problems with a count, and a checked team with a word', () => {
    act(() =>
      root.render(
        <ul>
          <TeamCard
            summary={SUMMARY}
            warningCount={2}
            onOpen={vi.fn()}
            onDelete={vi.fn()}
          />
        </ul>,
      ),
    );
    expect(
      container.querySelector('[data-slot="team-card-warnings"]')?.textContent,
    ).toBe('2 need setup');
    act(() =>
      root.render(
        <ul>
          <TeamCard
            summary={SUMMARY}
            warningCount={0}
            onOpen={vi.fn()}
            onDelete={vi.fn()}
          />
        </ul>,
      ),
    );
    expect(container.querySelector('[aria-label="ready"]')).not.toBeNull();
  });

  it('pluralizes a single member/stage without a trailing "s"', () => {
    // Read the whole card, not `render`'s return: that is the ACTIVATION
    // button, which is layered under the content and holds no text of its own.
    render({ ...SUMMARY, memberCount: 1, stageCount: 1 });
    const text = container.textContent ?? '';
    expect(text).toContain('1 member');
    expect(text).not.toContain('1 members');
    expect(text).toContain('1 stage');
    expect(text).not.toContain('1 stages');
  });

  it('falls back to "No description" when there is none', () => {
    render({ ...SUMMARY, description: null });
    expect(container.textContent ?? '').toContain('No description');
  });

  it('activates from a REAL <button>, so the platform supplies Enter/Space', () => {
    // The row this replaced was, before it was a row, a div wearing
    // `role="button"` with a hand-rolled Enter/Space keydown handler and a
    // nested delete button — which ARIA forbids and needed an event dam to
    // survive. The card is `NavListItem`'s overlay button instead: keyboard
    // activation is the element's, not ours, and delete is its sibling.
    //
    // jsdom does not synthesize a click from a keydown, so a keyboard
    // assertion here could only ever re-test jsdom. What IS ours to pin is
    // the element type — revert to a role-bearing div and this fails.
    const onOpen = vi.fn();
    const el = render(SUMMARY, onOpen);

    expect(el.tagName).toBe('BUTTON');
    expect(el.getAttribute('role')).toBeNull();

    act(() => {
      el.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    expect(onOpen).toHaveBeenCalledTimes(1);
  });

  it('keeps the delete control OUTSIDE the activation surface', () => {
    // The structural half of the same fix: nothing interactive may be a
    // descendant of the activation button. Nesting them is what made the
    // event dam necessary in the first place.
    render(SUMMARY);
    const activate = container.querySelector('button[aria-label^="Open "]')!;
    expect(activate.querySelector('button')).toBeNull();
    expect(activate.contains(deleteButton())).toBe(false);
  });
});

describe('TeamCard — delete', () => {
  it('asks the page to delete — the card itself deletes nothing', () => {
    // The card only REQUESTS deletion; the page confirms in a modal. So one
    // click must reach onDelete (no in-card arming step swallowing it).
    const onDelete = vi.fn();
    render(SUMMARY, vi.fn(), onDelete);

    clickDelete();
    expect(onDelete).toHaveBeenCalledTimes(1);
  });

  it('never opens the team while deleting it', () => {
    // The whole card is a click target, so a delete click that found its way
    // to onOpen would drop the user into the builder of the very team
    // they are removing — behind the confirm dialog. Fails the moment the
    // card itself takes an onClick again instead of layering the overlay
    // button.
    const onOpen = vi.fn();
    render(SUMMARY, onOpen, vi.fn());

    clickDelete();
    expect(onOpen).not.toHaveBeenCalled();
  });

  it('names the team it deletes, so the grid stays unambiguous', () => {
    render(SUMMARY);
    expect(deleteButton().getAttribute('aria-label')).toBe(
      'Delete Review Team',
    );
  });
});

describe('TeamCard — delete held', () => {
  it('holds delete while a run of the team is live, saying why', () => {
    const onDelete = vi.fn();
    act(() =>
      root.render(
        <ul>
          <TeamCard
            summary={SUMMARY}
            deleteDisabledReason="A run of this team is working"
            onOpen={vi.fn()}
            onDelete={onDelete}
          />
        </ul>,
      ),
    );
    expect(deleteButton().disabled).toBe(true);
    expect(deleteButton().title).toBe('A run of this team is working');
  });
});

describe('TeamCard — warnings badge', () => {
  function badge(props: {
    warningsCheckedAt?: string | null;
    blocking?: boolean;
  }): HTMLElement {
    act(() =>
      root.render(
        <ul>
          <TeamCard
            summary={SUMMARY}
            warningCount={2}
            {...props}
            onOpen={vi.fn()}
            onDelete={vi.fn()}
          />
        </ul>,
      ),
    );
    return container.querySelector<HTMLElement>(
      '[data-slot="team-card-warnings"]',
    )!;
  }

  it('says how long ago the MCP servers were read', () => {
    const twoHoursAgo = new Date(Date.now() - 2 * 3_600_000).toISOString();
    expect(badge({ warningsCheckedAt: twoHoursAgo }).title).toBe(
      'MCP last checked 2h ago',
    );
  });

  it('says so when the MCP servers were never read', () => {
    expect(badge({ warningsCheckedAt: null }).title).toBe(
      'MCP not checked yet',
    );
  });

  it('is red when a problem stops a run and amber otherwise', () => {
    expect(badge({ blocking: true }).className).toContain('text-destructive');
    expect(badge({ blocking: false }).className).toContain('text-warning');
  });
});
