import { Trash2, TriangleAlert } from 'lucide-react';

import type { TeamSummaryDto as TeamSummary } from '../autogenerated';
import { plural } from '../chats/run-outcome';
import { LIFT_CARD_CLASS } from '../components/lift-card';
import { AvatarStack } from '../components/member-avatar';
import { NavListItem } from '../components/nav-list-item';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import { formatUpdated } from './format-updated';

/**
 * One team in the library: its people as a portrait, its name, what it is
 * for, and how big it is. The whole card opens the team (`NavListItem`'s
 * activation button); the delete control is its sibling, shown on hover or
 * focus and held while a run of the team is live.
 */
export function TeamCard({
  summary,
  warningCount = null,
  warningsCheckedAt = null,
  blocking = false,
  deleteDisabledReason = null,
  onOpen,
  onDelete,
}: {
  summary: TeamSummary;
  /** Open setup problems; null until the daemon has checked. */
  warningCount?: number | null;
  /** When the MCP servers were last read, for the badge's tooltip; null if never. */
  warningsCheckedAt?: string | null;
  /** A problem stands that stops a run: the badge is red instead of amber. */
  blocking?: boolean;
  /** Why the team cannot be deleted right now, or null. */
  deleteDisabledReason?: string | null;
  onOpen: () => void;
  /** Asks to delete this team — the page confirms in a modal first. */
  onDelete: () => void;
}): React.JSX.Element {
  return (
    <NavListItem
      active={false}
      activateLabel={`Open ${summary.name}`}
      onActivate={onOpen}
      className={cn('group p-5', LIFT_CARD_CLASS)}>
      <div className="flex flex-col gap-4">
        <div className="flex items-start justify-between gap-3">
          <AvatarStack
            size={40}
            max={5}
            total={summary.memberCount}
            people={summary.portrait.map((member) => ({
              key: member.id,
              name: member.name,
              avatar: member.avatar,
            }))}
            ringClassName="ring-card"
          />
          <Button
            type="button"
            variant="ghost"
            size="icon"
            aria-label={`Delete ${summary.name}`}
            title={deleteDisabledReason ?? 'Delete team'}
            disabled={deleteDisabledReason !== null}
            className="size-8 shrink-0 rounded-control text-muted-foreground opacity-0 transition-opacity group-hover:opacity-100 focus-visible:opacity-100 hover:bg-destructive/10 hover:text-destructive [&_svg]:size-4"
            onClick={onDelete}>
            <Trash2 />
          </Button>
        </div>
        <div className="flex min-w-0 flex-col gap-1.5">
          <div className="flex min-w-0 items-center gap-2">
            <h3 className="min-w-0 truncate text-base font-semibold">
              {summary.name}
            </h3>
            {warningCount === null ? null : warningCount > 0 ? (
              <span
                data-slot="team-card-warnings"
                data-blocking={blocking || undefined}
                title={
                  warningsCheckedAt === null
                    ? 'MCP not checked yet'
                    : `MCP last checked ${formatUpdated(warningsCheckedAt)}`
                }
                className={cn(
                  'inline-flex h-6 shrink-0 items-center gap-1 rounded-pill px-2 text-sm font-medium tabular-nums',
                  blocking
                    ? 'bg-destructive/15 text-destructive'
                    : 'bg-warning/15 text-warning',
                )}>
                <TriangleAlert aria-hidden="true" className="size-3" />
                {warningCount}
                <span className="sr-only"> need setup</span>
              </span>
            ) : (
              <span
                role="img"
                aria-label="ready"
                title="ready"
                className="size-2 shrink-0 rounded-pill bg-success"
              />
            )}
          </div>
          <p className="line-clamp-2 text-sm text-muted-foreground">
            {summary.description || 'No description'}
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-x-3 gap-y-1 text-sm text-muted-foreground tabular-nums">
          <span>
            {plural(summary.memberCount, 'member', 'members')} ·{' '}
            {plural(summary.stageCount, 'stage', 'stages')}
          </span>
          <span className="ml-auto">{formatUpdated(summary.updatedAt)}</span>
        </div>
      </div>
    </NavListItem>
  );
}
