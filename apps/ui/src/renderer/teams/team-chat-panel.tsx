import { ChevronDown, Trash2 } from 'lucide-react';

import type { CliKind, DaemonHandle } from '../../shared/contracts';
import { CLI_KINDS } from '../../shared/contracts';
import type { RunAwaiting, RunDto } from '../autogenerated';
import { Chats } from '../chats/Chats';
import type { HostedThread } from '../chats/hosted-thread';
import { PanelResizeHandle, usePanelWidth } from '../components/panel-resize';
import { Button } from '../components/ui/button';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { currentRunSettings } from '../run-settings';

/**
 * The chat docked under the team builder: the user describes a change and
 * an agent makes it in the team's own YAML file.
 *
 * It mirrors the terminal panel's dock — an `<aside>` with a resize handle —
 * so the app's two bottom panels are one thing to learn. What it holds is the
 * chat screen itself, drawing this one conversation (`Chats` with `hosted`).
 *
 * Once opened it stays MOUNTED while the builder holds that team and is
 * only HIDDEN when closed, like the terminal panel — not for a scrollback, but
 * for the two reports it owes the builder. Unmounted, a turn still running
 * when the dock was closed would take its `working` report and its settle
 * with it: the builder's autosave would stay suspended for good (every later
 * editor edit lost on leaving) and the agent's own edit would never be
 * reloaded, so the next editor save would write over it.
 */
export function TeamChatPanel({
  slug,
  teamName,
  projectId = null,
  projectName = null,
  apis,
  handle,
  client,
  hidden = false,
  initialAgent,
  initialDraft = '',
  active = true,
  onClose,
  onBeforeSend,
  onWorkingChange,
  onAwaitingChange,
  onTurnSettled,
}: {
  slug: string;
  teamName: string;
  /** The project scope the dock is opened in: its chat edits that project's overlay beside the shared team. */
  projectId?: string | null;
  projectName?: string | null;
  apis: DaemonApis;
  handle: DaemonHandle;
  client: DaemonClient;
  /** Closed by the user but still following its conversation — see above. */
  hidden?: boolean;
  /** The agent a NEW team chat starts with. */
  initialAgent?: CliKind;
  initialDraft?: string;
  /** Whether the builder is on screen. */
  active?: boolean;
  onClose: () => void;
  /**
   * Run before a message or a button press reaches the daemon — the builder
   * writes any pending editor edit first, so the agent reads the team the
   * user is looking at rather than the one last autosaved.
   */
  onBeforeSend: () => Promise<unknown>;
  /**
   * A turn started or ended. The builder suspends its autosave while one runs,
   * so the agent's write and the editor cannot overwrite each other.
   */
  onWorkingChange: (working: boolean) => void;
  /**
   * The agent is waiting on the user — a question or an approval card — or no
   * longer is. The dock can be HIDDEN while its turn waits, so the builder
   * marks its toggle from this; nothing else on screen would say so.
   */
  onAwaitingChange?: (awaiting: RunAwaiting | null) => void;
  /** A turn ended — the builder re-reads the team the agent may have edited. */
  onTurnSettled: () => void | Promise<void>;
}): React.JSX.Element {
  const {
    width: height,
    minWidth,
    maxWidth,
    startResize,
    resizeTo,
  } = usePanelWidth({
    storageKey: 'teamChat.panelHeight',
    defaultWidth: 420,
    minWidth: 240,
    maxWidth: 900,
    handleEdge: 'top',
  });

  // `acceptEdits`: the chat's saves are edits of the team file it was asked to
  // make, so the daemon approves a save as it would a file edit; `ask` would
  // put a card in front of every save. A CLI without the mode opens on its own
  // default — the daemon narrows it.
  const open = useLatestCallback(
    async (): Promise<RunDto> =>
      apis.teams.openTeamChat({
        slug,
        startTeamChatDto: {
          agentKind: initialAgent ?? CLI_KINDS[0]!,
          approval: 'acceptEdits',
          ...(await currentRunSettings()),
          projectId,
        },
      }),
    [apis, slug, initialAgent, projectId],
  );
  const discard = useLatestCallback(async (): Promise<void> => {
    await apis.teams.discardTeamChat({ slug });
  }, [apis, slug]);
  const headerActions = useLatestCallback(
    ({ discard: startOver }: { discard: (() => void) | null }) => (
      <>
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className="size-6"
          aria-label="Start a new conversation"
          title="Throw this conversation away and start a new one"
          disabled={startOver === null}
          onClick={() => startOver?.()}>
          <Trash2 className="size-3.5 shrink-0" />
        </Button>
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className="size-6"
          aria-label="Hide the team chat panel"
          title="Hide — the conversation is kept"
          onClick={onClose}>
          <ChevronDown className="size-3.5 shrink-0" />
        </Button>
      </>
    ),
    [onClose],
  );
  const thread: HostedThread = {
    open,
    discard,
    queueScope: `team-chat:${slug}`,
    emptyText:
      'Ask for a change — members, instruction blocks or the stages every run walks — or for an analysis of its latest runs. The agent edits this team’s file and the editor reloads when it is done.',
    composerLabel: 'Ask for a team change',
    composerPlaceholder:
      'Describe the change, or ask what its latest runs suggest…',
    initialDraft,
    onBeforeSend,
    onWorkingChange,
    onAwaitingChange,
    onTurnSettled,
    headerActions,
  };

  return (
    <aside
      hidden={hidden}
      className="relative flex shrink-0 flex-col border-t border-border bg-sidebar"
      style={{ height }}
      aria-label={
        projectName === null
          ? `Change ${teamName} with chat`
          : `Change with chat · ${teamName} + ${projectName}`
      }>
      <PanelResizeHandle
        edge="top"
        label="Resize the team chat panel"
        onMouseDown={startResize}
        value={height}
        min={minWidth}
        max={maxWidth}
        onResize={resizeTo}
      />
      <div className="min-h-0 flex-1">
        <Chats
          client={client}
          handle={handle}
          active={active && !hidden}
          hosted={thread}
        />
      </div>
    </aside>
  );
}
