// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { AgentIdentityCapability, Team } from '../autogenerated';
import { runsUnasked } from './member-schema';
import {
  defaultMemberAgent,
  newMember,
  normalizedTeam,
  rememberMemberAgent,
  teamFromMeta,
  teamSnapshot,
  withMember,
  withMemberMoved,
  withoutMember,
} from './team-doc';

const member = (id: string): Team['members'][number] => ({
  id,
  name: id,
  agent: 'claude',
  approval: 'auto',
});

function team(fields: Partial<Team> = {}): Team {
  return {
    name: 'T',
    mode: 'lead',
    members: [member('a'), member('b'), member('c')],
    triggers: [{ kind: 'first-message', member: 'b' }],
    instructionBlocks: [],
    ...fields,
  };
}

const identity = (agent: string): AgentIdentityCapability =>
  ({ agent, displayName: agent }) as AgentIdentityCapability;

describe('normalizedTeam / teamSnapshot', () => {
  it('trims the name and description, and leaves out a blank one and empty stages', () => {
    expect(
      normalizedTeam(team({ name: '  T  ', description: '  ', stages: [] })),
    ).toEqual(team());
    expect(normalizedTeam(team({ name: ' ' })).name).toBe('team');
  });

  it('serializes equal teams alike, whatever order their fields came in', () => {
    const { members, ...rest } = team({ description: 'd', maxActiveTurns: 2 });
    expect(teamSnapshot({ members, ...rest })).toBe(
      teamSnapshot({ ...rest, members }),
    );
  });

  it('reads a member edited in the editor and the same member read back from disk alike', () => {
    const edited = team({
      members: [{ ...member('a'), role: 'Reviews code.' }],
    });
    const fromDisk = team({
      members: [
        {
          id: 'a',
          name: 'a',
          role: 'Reviews code.',
          agent: 'claude',
          approval: 'auto',
        },
      ],
    });

    expect(teamSnapshot(edited)).toBe(teamSnapshot(fromDisk));
    expect(teamSnapshot(edited)).not.toBe(
      teamSnapshot(team({ members: [member('a')] })),
    );
  });
});

describe('withoutMember', () => {
  it('drops the member from every audience and responsible list', () => {
    const next = withoutMember(
      team({
        instructionBlocks: [
          { id: 'x', title: '', text: '', audience: ['a', 'c'] },
          { id: 'y', title: '', text: '', audience: 'everyone' },
        ],
        stages: [
          { id: 's', title: 'S', goal: 'g', responsible: ['c', 'a'] },
          { id: 't', title: 'T', goal: 'g', responsible: ['c'] },
        ],
      }),
      'c',
    );
    expect(next.members.map((m) => m.id)).toEqual(['a', 'b']);
    expect(next.instructionBlocks.map((b) => b.audience)).toEqual([
      ['a'],
      'everyone',
    ]);
    expect(next.stages).toEqual([
      { id: 's', title: 'S', goal: 'g', responsible: ['a'] },
      { id: 't', title: 'T', goal: 'g' },
    ]);
    expect(next.triggers).toEqual([{ kind: 'first-message', member: 'b' }]);
  });

  it('hands the first message to the first member left when its handler goes', () => {
    expect(withoutMember(team(), 'b').triggers).toEqual([
      { kind: 'first-message', member: 'a' },
    ]);
  });
});

describe('withMember', () => {
  it('leaves a working trigger alone', () => {
    const next = withMember(team(), member('d'));
    expect(next.members.map((m) => m.id)).toEqual(['a', 'b', 'c', 'd']);
    expect(next.triggers).toEqual([{ kind: 'first-message', member: 'b' }]);
  });

  it('hands the first message to the new member when no member had it', () => {
    expect(
      withMember(team({ members: [], triggers: [] }), member('d')).triggers,
    ).toEqual([{ kind: 'first-message', member: 'd' }]);
    expect(
      withMember(
        team({ triggers: [{ kind: 'first-message', member: 'ghost' }] }),
        member('d'),
      ).triggers,
    ).toEqual([{ kind: 'first-message', member: 'd' }]);
  });
});

describe('newMember', () => {
  it('takes a free id and is named after its place', () => {
    expect(newMember(team({ members: [member('member-1')] }), 'codex')).toEqual(
      {
        id: 'member-2',
        name: 'Member 2',
        agent: 'codex',
        approval: 'auto',
      },
    );
  });

  it('starts unattended, as the schema’s default does', () => {
    expect(runsUnasked(newMember(team(), 'claude'))).toBe(true);
  });
});

describe('withMemberMoved', () => {
  it('moves a member one place and stops at either end', () => {
    expect(withMemberMoved(team(), 'c', -1).members.map((m) => m.id)).toEqual([
      'a',
      'c',
      'b',
    ]);
    const unchanged = team();
    expect(withMemberMoved(unchanged, 'a', -1)).toBe(unchanged);
    expect(withMemberMoved(unchanged, 'c', 1)).toBe(unchanged);
  });
});

describe('teamFromMeta', () => {
  it('makes the smallest team a save accepts: one lead handling the first message', () => {
    expect(teamFromMeta({ name: 'New', description: 'd' }, 'codex')).toEqual({
      name: 'New',
      description: 'd',
      mode: 'lead',
      members: [
        { id: 'member-1', name: 'Lead', agent: 'codex', approval: 'auto' },
      ],
      triggers: [{ kind: 'first-message', member: 'member-1' }],
      instructionBlocks: [],
    });
  });
});

describe('defaultMemberAgent', () => {
  const AGENTS = [identity('claude'), identity('codex')];
  beforeEach(() => localStorage.clear());
  afterEach(() => vi.restoreAllMocks());

  it('starts on the first CLI the daemon lists when none was chosen', () => {
    expect(defaultMemberAgent(AGENTS)).toBe('claude');
  });

  it('starts on the CLI last chosen in the builder', () => {
    rememberMemberAgent('codex');
    expect(defaultMemberAgent(AGENTS)).toBe('codex');
  });

  it('falls back to the first listed CLI when the remembered one is no longer offered', () => {
    rememberMemberAgent('codex');
    expect(defaultMemberAgent([identity('claude')])).toBe('claude');
  });

  it('starts on the first listed CLI, and remembers nothing, when storage refuses', () => {
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => {
      throw new Error('blocked');
    });
    vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => {
      throw new Error('blocked');
    });
    expect(() => rememberMemberAgent('codex')).not.toThrow();
    expect(defaultMemberAgent(AGENTS)).toBe('claude');
  });
});
