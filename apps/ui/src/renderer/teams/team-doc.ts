import { CLI_KINDS, type CliKind } from '../../shared/contracts';
import type {
  AgentIdentityCapability,
  InstructionBlock,
  Team,
  TeamMember,
} from '../autogenerated';
import { audienceOf } from './member-schema';

/** The team-level fields the meta form edits, as a save writes them. */
export type TeamMeta = Pick<
  Team,
  'name' | 'description' | 'maxActiveTurns' | 'stages'
>;

/**
 * A team as a save writes it: the name trimmed (never empty), a blank
 * description and an empty stage list left out. Fields in a fixed order, so
 * two equal teams serialize alike whatever order their edits came in.
 */
export function normalizedTeam(team: Team): Team {
  const description = team.description?.trim();
  return {
    name: team.name.trim() || 'team',
    ...(description ? { description } : {}),
    ...(team.maxActiveTurns !== undefined
      ? { maxActiveTurns: team.maxActiveTurns }
      : {}),
    mode: team.mode,
    members: team.members,
    triggers: team.triggers,
    instructionBlocks: team.instructionBlocks,
    // A file must not flip between `stages: []` and no key on a save.
    ...(team.stages !== undefined && team.stages.length > 0
      ? { stages: team.stages }
      : {}),
  };
}

/**
 * The team as a save would write it, with object keys sorted at every depth —
 * the builder's dirty-check baseline (the snapshot taken at load/save against
 * the live editor). A team read back from disk arrives in schema key order and
 * an edit adds keys in its own, so only the content may decide; an edit undone
 * by hand reads clean again.
 */
export function teamSnapshot(team: Team): string {
  return JSON.stringify(sortedKeys(normalizedTeam(team)));
}

function sortedKeys(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(sortedKeys);
  }
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([, field]) => field !== undefined)
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([key, field]) => [key, sortedKeys(field)]),
    );
  }
  return value;
}

function nextId(existing: ReadonlySet<string>, prefix: string): string {
  let n = 1;
  while (existing.has(`${prefix}-${n}`)) {
    n += 1;
  }
  return `${prefix}-${n}`;
}

/** A fresh member id not colliding with the team's (`member-1`, …). */
export function nextMemberId(
  members: readonly Pick<TeamMember, 'id'>[],
): string {
  return nextId(new Set(members.map((member) => member.id)), 'member');
}

/** A fresh instruction block id not colliding with the team's (`block-1`, …). */
export function nextBlockId(
  blocks: readonly Pick<InstructionBlock, 'id'>[],
): string {
  return nextId(new Set(blocks.map((block) => block.id)), 'block');
}

/** The member the first message goes to, or null when the team names none. */
export function triggerMemberOf(team: Pick<Team, 'triggers'>): string | null {
  return team.triggers[0]?.member ?? null;
}

/** The team with its one trigger handed to `memberId`. */
export function withTriggerMember(team: Team, memberId: string): Team {
  return { ...team, triggers: [{ kind: 'first-message', member: memberId }] };
}

/**
 * A new member on `agent`, named after its place in the team. Its approval is
 * `auto`, the schema's own default for a member written without one.
 */
export function newMember(
  team: Pick<Team, 'members'>,
  agent: CliKind,
): TeamMember {
  const id = nextMemberId(team.members);
  return {
    id,
    name: `Member ${team.members.length + 1}`,
    agent,
    approval: 'auto',
  };
}

/**
 * The team with `member` appended. A team whose trigger names no member yet —
 * one with no members, or one read from a file without a trigger — hands the
 * first message to it, so the team it leaves is one a save accepts.
 */
export function withMember(team: Team, member: TeamMember): Team {
  const next = { ...team, members: [...team.members, member] };
  const handler = triggerMemberOf(team);
  return handler !== null &&
    team.triggers.length === 1 &&
    team.members.some((existing) => existing.id === handler)
    ? next
    : withTriggerMember(next, member.id);
}

/**
 * The team without member `memberId`, and without every reference to it: it
 * leaves each block's audience and each stage's responsible list, and when it
 * handled the first message the trigger moves to the first member left.
 */
export function withoutMember(team: Team, memberId: string): Team {
  const members = team.members.filter((member) => member.id !== memberId);
  const instructionBlocks = team.instructionBlocks.map((block) => {
    const audience = audienceOf(block);
    return audience === 'everyone' || !audience.includes(memberId)
      ? block
      : { ...block, audience: audience.filter((id) => id !== memberId) };
  });
  const stages = team.stages?.map((stage) => {
    if (!stage.responsible?.includes(memberId)) {
      return stage;
    }
    const { responsible, ...rest } = stage;
    const left = responsible.filter((id) => id !== memberId);
    return left.length > 0 ? { ...rest, responsible: left } : rest;
  });
  const next: Team = {
    ...team,
    members,
    instructionBlocks,
    ...(stages === undefined ? {} : { stages }),
  };
  if (triggerMemberOf(team) !== memberId) {
    return next;
  }
  const heir = members[0];
  return heir === undefined
    ? { ...next, triggers: [] }
    : withTriggerMember(next, heir.id);
}

/** The team with member `memberId` moved `by` places, clamped to the list. */
export function withMemberMoved(
  team: Team,
  memberId: string,
  by: -1 | 1,
): Team {
  const from = team.members.findIndex((member) => member.id === memberId);
  const to = from + by;
  if (from < 0 || to < 0 || to >= team.members.length) {
    return team;
  }
  const members = [...team.members];
  const [moved] = members.splice(from, 1);
  members.splice(to, 0, moved!);
  return { ...team, members };
}

/**
 * Where the builder remembers the CLI a member was last put on — a per-viewer
 * convenience, so it is browser storage and read defensively.
 */
const LS_LAST_AGENT = 'geniro.builder.lastAgent';

/** Remember the CLI the user just put a member on, for the next one added. */
export function rememberMemberAgent(agent: CliKind): void {
  try {
    localStorage.setItem(LS_LAST_AGENT, agent);
  } catch {
    // Storage unavailable: the next member starts on the first CLI instead.
  }
}

/**
 * The CLI a new member starts on: the one last chosen in the builder while
 * the daemon still offers it, else the first CLI the daemon lists.
 */
export function defaultMemberAgent(
  agents: readonly AgentIdentityCapability[],
): CliKind {
  let last: string | null = null;
  try {
    last = localStorage.getItem(LS_LAST_AGENT);
  } catch {
    last = null;
  }
  const offered = agents.find((identity) => identity.agent === last);
  return offered?.agent ?? agents[0]?.agent ?? CLI_KINDS[0]!;
}

/**
 * A new team from the meta form: one member on `agent`, handling the first
 * message — the smallest team a save accepts.
 */
export function teamFromMeta(meta: TeamMeta, agent: CliKind): Team {
  const empty: Team = {
    ...meta,
    mode: 'lead',
    members: [],
    triggers: [],
    instructionBlocks: [],
  };
  return normalizedTeam(
    withMember(empty, { ...newMember(empty, agent), name: 'Lead' }),
  );
}
