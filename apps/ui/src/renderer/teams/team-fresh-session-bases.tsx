import type {
  FreshSessionBase,
  FreshSessionContextReading,
  FreshSessionContextServer,
  TeamMember,
} from '../autogenerated';
import { formatTokens } from '../chats/agent-activity';
import { contextCategoryColor } from '../chats/chat-metrics';
import { MemberAvatar } from '../components/member-avatar';
import { SegmentBreakdown } from '../components/segment-breakdown';
import { Spinner } from '../components/ui/spinner';
import { dayRangeTitle, formatPercent } from '../stats/stats-format';

const UNMEASURED_PART_LABEL: Record<
  FreshSessionBase['notMeasured'][number]['part'],
  string
> = {
  plugins: 'Plugins',
  skills: 'Skills',
  builtInTools: 'Built-in tools',
};

interface ProjectGroup {
  key: string;
  name: string;
  entries: FreshSessionBase[];
}

/**
 * What each member's fresh CLI session started with in the team's newest runs,
 * per project, split into Geniro's instructions, the repository's instruction
 * files and what the CLI adds itself — the daemon's figures
 * (`POST /v1/teams/:slug/fresh-session-bases`). A part nobody measured says so.
 */
export function TeamFreshSessionBases({
  members,
  labels,
  bases,
  loading,
  error,
}: {
  members: readonly Pick<TeamMember, 'id' | 'avatar'>[];
  labels: ReadonlyMap<string, string>;
  bases: readonly FreshSessionBase[] | null;
  loading: boolean;
  error: string | null;
}): React.JSX.Element {
  if (bases === null || bases.length === 0) {
    return (
      <p className="flex items-center gap-1.5 text-sm text-muted-foreground">
        {loading ? (
          <>
            <Spinner /> Measuring…
          </>
        ) : (
          (error ?? 'Not measured yet.')
        )}
      </p>
    );
  }
  const avatarOf = new Map(members.map((member) => [member.id, member.avatar]));
  const labelOf = (memberId: string): string =>
    labels.get(memberId) ?? memberId;
  const unstarted = bases.filter((entry) => entry.baseTokens === null);
  return (
    <div
      data-slot="team-fresh-session-bases"
      aria-busy={loading}
      className="flex flex-col gap-4">
      {groupsOf(bases).map((group) => (
        <div key={group.key} className="flex flex-col gap-2">
          <h4 className="text-sm font-medium text-foreground">
            In {group.name}
          </h4>
          {group.entries.map((entry) => (
            <MemberBase
              key={`${entry.memberId}-${entry.poolMember ?? 1}`}
              entry={entry}
              label={labelOf(entry.memberId)}
              avatar={avatarOf.get(entry.memberId)}
            />
          ))}
        </div>
      ))}
      {unstarted.length > 0 ? (
        <p
          data-slot="fresh-session-unstarted"
          className="text-xs text-muted-foreground">
          No fresh session in the runs read, so not measured:{' '}
          {unstarted.map((entry) => labelOf(entry.memberId)).join(', ')}.
        </p>
      ) : null}
      {error ? <p className="text-xs text-muted-foreground">{error}</p> : null}
    </div>
  );
}

function MemberBase({
  entry,
  label,
  avatar,
}: {
  entry: FreshSessionBase;
  label: string;
  avatar: TeamMember['avatar'];
}): React.JSX.Element {
  const base = entry.baseTokens ?? 0;
  const parts = [
    {
      key: 'team',
      label: 'Geniro instructions',
      tokens: entry.teamBlockTokens,
      share: entry.teamBlockShare,
      unavailableReason: entry.teamBlockUnavailableReason,
    },
    {
      key: 'repo',
      label: 'Repository files',
      tokens: entry.repoFiles?.approxTokens ?? null,
      share: entry.repoFiles?.share ?? null,
      unavailableReason: null,
    },
    {
      key: 'cli',
      label:
        entry.repoFiles === null
          ? 'Added by the CLI, repository files included'
          : 'Added by the CLI',
      tokens: entry.cliRemainderTokens,
      share: entry.cliRemainderShare,
      unavailableReason: entry.cliRemainderUnavailableReason,
    },
  ];
  return (
    <div
      data-slot="fresh-session-base"
      className="flex flex-col gap-2 rounded-card bg-card p-5 text-xs ring-1 ring-border">
      <div className="flex flex-wrap items-center gap-x-1.5 gap-y-1">
        <MemberAvatar
          name={label}
          avatar={avatar}
          colorKey={entry.memberId}
          size={20}
        />
        <span className="font-medium text-foreground">{label}</span>
        {entry.poolMember !== null && entry.poolMember > 1 ? (
          <span className="text-muted-foreground">
            · pool member {entry.poolMember}
          </span>
        ) : null}
        {entry.model ? (
          <span className="text-muted-foreground">· {entry.model}</span>
        ) : null}
        <span
          data-slot="fresh-session-base-total"
          className="ml-auto text-sm font-medium text-foreground tabular-nums">
          ≈{formatTokens(base)} tokens
        </span>
      </div>
      <SegmentBreakdown
        denominator={base}
        segments={parts.flatMap((part, index) =>
          part.tokens === null
            ? []
            : [
                {
                  key: part.key,
                  label: part.label,
                  value: Math.max(part.tokens, 0),
                  colorClass: contextCategoryColor(index),
                  figures: [
                    `~${formatTokens(part.tokens)}`,
                    part.share === null ? '' : formatPercent(part.share * 100),
                  ],
                },
              ],
        )}
      />
      <ul className="flex flex-col gap-0.5 text-muted-foreground">
        <li>
          Approximate: the median of {entry.starts}{' '}
          {entry.starts === 1 ? 'fresh session' : 'fresh sessions'}
          {entry.firstStartAt && entry.lastStartAt
            ? `, ${dayRangeTitle(entry.firstStartAt, entry.lastStartAt)}`
            : ''}
          , read from the{' '}
          <span data-slot="fresh-session-base-source">
            {entry.baseSource === 'firstRequest'
              ? 'first request'
              : 'last request'}
          </span>{' '}
          of each session’s first turn
          {entry.medianRequests !== null
            ? ` (${entry.medianRequests} ${entry.medianRequests === 1 ? 'request' : 'requests'})`
            : ''}
          .
        </li>
        {parts.flatMap((part) =>
          part.tokens === null && part.unavailableReason !== null
            ? [
                <li key={part.key} data-slot="fresh-session-part-unmeasured">
                  {part.label}: not measured — {part.unavailableReason}.
                </li>,
              ]
            : [],
        )}
        <li>
          {entry.repoFiles === null
            ? `Repository files: not measured — ${entry.repoFilesUnavailableReason ?? 'unknown'}.`
            : `Repository files: ${entry.repoFiles.files.length} measured on disk now.`}
        </li>
        <li data-slot="fresh-session-mcp">
          {entry.mcpServers === null
            ? `MCP servers: not measured — ${entry.mcpServersUnavailableReason ?? 'unknown'}.`
            : `MCP servers as reported ${dayRangeTitle(entry.mcpServers.harvestedAt, entry.mcpServers.harvestedAt)}: ${entry.mcpServers.names.join(', ') || 'none'}.`}
        </li>
        {entry.notMeasured.map(({ part, reason }) => (
          <li key={part} data-slot="fresh-session-not-measured">
            {UNMEASURED_PART_LABEL[part]} — {reason}.
          </li>
        ))}
      </ul>
      {entry.contextReading !== null ? (
        <ContextReadingBlock reading={entry.contextReading} />
      ) : null}
    </div>
  );
}

function ContextReadingBlock({
  reading,
}: {
  reading: FreshSessionContextReading;
}): React.JSX.Element {
  const servers = [...reading.mcpServers].sort(
    (a, b) => (b.inWindowTokens ?? 0) - (a.inWindowTokens ?? 0),
  );
  const onUseServers = [...reading.mcpServers]
    .filter((server) => (server.onUseTokens ?? 0) > 0)
    .sort((a, b) => (b.onUseTokens ?? 0) - (a.onUseTokens ?? 0));
  const namesOnly = servers.some(
    (server) =>
      server.inWindowTokens !== null &&
      server.loadedToolCount < server.toolCount,
  );
  return (
    <details data-slot="fresh-session-reading">
      <summary className="cursor-pointer text-muted-foreground">
        The CLI’s own breakdown
      </summary>
      <div className="mt-2 flex flex-col gap-2 text-muted-foreground">
        <p>
          Measured {dayRangeTitle(reading.measuredAt, reading.measuredAt)} in
          the newest fresh session.
        </p>
        <ReadingList title="In the window" slot="fresh-session-categories">
          {reading.inWindow.map((part) => (
            <ReadingRow
              key={part.name}
              name={part.name}
              figure={`${formatTokens(part.tokens)} tokens`}
            />
          ))}
        </ReadingList>
        {reading.memoryFiles.length > 0 ? (
          <ReadingList title="Memory files" slot="fresh-session-memory-files">
            {reading.memoryFiles.map((file) => (
              <ReadingRow
                key={file.path}
                name={file.kind ? `${file.path} · ${file.kind}` : file.path}
                figure={
                  file.tokens === null
                    ? 'not counted'
                    : `${formatTokens(file.tokens)} tokens`
                }
              />
            ))}
          </ReadingList>
        ) : null}
        {servers.length > 0 ? (
          <ReadingList
            title="MCP servers in the window"
            slot="fresh-session-servers">
            {servers.map((server) => (
              <ReadingRow
                key={server.name}
                name={server.name}
                figure={inWindowFigure(server)}
              />
            ))}
            {namesOnly ? (
              <li data-slot="fresh-session-names-only">
                A tool known by name only adds just its name, which the CLI does
                not count; its schema loads when the tool is first used.
              </li>
            ) : null}
          </ReadingList>
        ) : null}
        {reading.onUse.length > 0 || onUseServers.length > 0 ? (
          <ReadingList
            title="Available on use, not in the window"
            slot="fresh-session-deferred">
            {reading.onUse.map((part) => (
              <ReadingRow
                key={part.name}
                name={part.name}
                figure={`${formatTokens(part.tokens)} tokens`}
              />
            ))}
            {onUseServers.map((server) => (
              <ReadingRow
                key={`server-${server.name}`}
                name={`${server.name} tool schemas`}
                figure={`${formatTokens(server.onUseTokens ?? 0)} tokens`}
              />
            ))}
          </ReadingList>
        ) : null}
        {reading.reserved.length > 0 ? (
          <ReadingList
            title="Held back by the CLI, not in the request"
            slot="fresh-session-reserved">
            {reading.reserved.map((part) => (
              <ReadingRow
                key={part.name}
                name={part.name}
                figure={`${formatTokens(part.tokens)} tokens`}
              />
            ))}
          </ReadingList>
        ) : null}
        <ul className="flex flex-col gap-0.5">
          {reading.firstRequestTokens !== null ? (
            <li data-slot="fresh-session-first-request">
              First request: {formatTokens(reading.firstRequestTokens)} tokens
            </li>
          ) : null}
          {reading.cliTotalTokens !== null ? (
            <li data-slot="fresh-session-cli-total">
              CLI total: {formatTokens(reading.cliTotalTokens)} tokens
            </li>
          ) : null}
          {reading.firstRequestLessCliTotalTokens !== null ? (
            <li data-slot="fresh-session-request-vs-total">
              {reading.firstRequestLessCliTotalTokens < 0
                ? `The CLI total is ${formatTokens(-reading.firstRequestLessCliTotalTokens)} tokens above the first request: its parts add up to more than the model received, so none of the request is left unitemised.`
                : `Not itemised by the CLI: ${formatTokens(reading.firstRequestLessCliTotalTokens)} tokens of the first request (tool names it does not count, fixed overhead).`}
            </li>
          ) : null}
        </ul>
      </div>
    </details>
  );
}

function inWindowFigure(server: FreshSessionContextServer): string {
  const tools = (count: number): string =>
    `${count} ${count === 1 ? 'tool' : 'tools'}`;
  if (server.inWindowTokens === null) {
    return `${tools(server.loadedToolCount)} loaded, not counted by the CLI`;
  }
  if (server.loadedToolCount === 0) {
    return `${tools(server.toolCount)} by name only`;
  }
  const loaded = `${formatTokens(server.inWindowTokens)} tokens · ${server.loadedToolCount} of ${tools(server.toolCount)} loaded`;
  return server.loadedToolCount < server.toolCount
    ? `${loaded}, the rest by name`
    : loaded;
}

function ReadingList({
  title,
  slot,
  children,
}: {
  title: string;
  slot: string;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <div data-slot={slot} className="flex flex-col gap-0.5">
      <h5 className="font-medium text-foreground">{title}</h5>
      <ul className="flex flex-col gap-0.5">{children}</ul>
    </div>
  );
}

function ReadingRow({
  name,
  figure,
}: {
  name: string;
  figure: string;
}): React.JSX.Element {
  return (
    <li className="flex justify-between gap-3">
      <span className="min-w-0 break-words">{name}</span>
      <span className="shrink-0 tabular-nums">{figure}</span>
    </li>
  );
}

function groupsOf(bases: readonly FreshSessionBase[]): ProjectGroup[] {
  const groups = new Map<string, ProjectGroup>();
  for (const entry of bases) {
    if (entry.baseTokens === null || entry.project === null) {
      continue;
    }
    const key = entry.project.projectId ?? `folder:${entry.project.name}`;
    const group = groups.get(key) ?? {
      key,
      name: entry.project.name,
      entries: [],
    };
    group.entries.push(entry);
    groups.set(key, group);
  }
  return [...groups.values()];
}
