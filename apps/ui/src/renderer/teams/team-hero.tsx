import {
  Clock,
  type LucideIcon,
  Milestone,
  Play,
  Users,
  Wallet,
} from 'lucide-react';

import type { TeamStatsDto } from '../autogenerated';
import { formatUsd } from '../chats/agent-activity';
import { ClampedText } from '../components/clamped-text';
import { type AvatarPerson, AvatarStack } from '../components/member-avatar';
import { formatCount, formatDuration } from '../stats/stats-format';

/**
 * What the team has done, as the daemon measured it. A figure nothing
 * measured is null and shows as a dash.
 */
export interface TeamFigures {
  runs: number | null;
  cost: string | null;
  worked: string | null;
}

export const UNMEASURED_FIGURES: TeamFigures = {
  runs: null,
  cost: null,
  worked: null,
};

/** The hero's figures from the daemon's readings; none yet is unmeasured. */
export function teamFiguresOf(stats: TeamStatsDto | null): TeamFigures {
  if (stats === null) {
    return UNMEASURED_FIGURES;
  }
  return {
    runs: stats.runs,
    cost: stats.costUsd === null ? null : formatUsd(stats.costUsd),
    worked: stats.workedMs === null ? null : formatDuration(stats.workedMs),
  };
}

function HeroFigure({
  icon,
  value,
  label,
}: {
  icon: LucideIcon;
  value: string | number | null;
  label: string;
}): React.JSX.Element {
  const Icon = icon;
  return (
    <span data-slot="team-figure" className="inline-flex items-center gap-1.5">
      <Icon aria-hidden="true" className="size-4 shrink-0" />
      <span className="font-medium text-foreground">
        {value === null ? '—' : value}
      </span>
      <span>{label}</span>
    </span>
  );
}

/**
 * The top of a team's page: its people, its name and purpose, how big it is
 * and what it has done, and anything it needs before it runs well.
 */
export function TeamHero({
  name,
  description,
  people,
  memberCount,
  stageCount,
  figures,
  warning,
}: {
  name: string;
  description: string | null | undefined;
  people: readonly AvatarPerson[];
  memberCount: number;
  stageCount: number;
  figures: TeamFigures;
  /** The setup-problems pill, or null. */
  warning?: React.ReactNode;
}): React.JSX.Element {
  return (
    <section
      data-slot="team-hero"
      aria-label={name}
      className="flex gap-5 max-sm:flex-col max-sm:gap-4">
      <AvatarStack
        people={people}
        total={memberCount}
        max={6}
        size={48}
        className="shrink-0 self-start pt-1"
      />
      <div className="flex min-w-0 flex-1 flex-col gap-2">
        <div className="flex flex-wrap items-center gap-x-3 gap-y-2">
          <h2 className="min-w-0 text-title font-semibold break-words">
            {name}
          </h2>
          {warning}
        </div>
        {description?.trim() ? (
          <ClampedText
            text={description}
            lines={3}
            slot="team-description"
            className="max-w-[72ch] text-base text-muted-foreground"
            toggleClassName="text-sm"
          />
        ) : null}
        <p
          data-slot="team-figures"
          className="flex flex-wrap items-center gap-x-4 gap-y-1.5 pt-1 text-sm text-muted-foreground tabular-nums">
          <HeroFigure
            icon={Users}
            value={memberCount}
            label={memberCount === 1 ? 'member' : 'members'}
          />
          <HeroFigure
            icon={Milestone}
            value={stageCount}
            label={stageCount === 1 ? 'stage' : 'stages'}
          />
          <span aria-hidden="true" className="h-4 w-px bg-border" />
          <HeroFigure
            icon={Play}
            value={figures.runs === null ? null : formatCount(figures.runs)}
            label={figures.runs === 1 ? 'run' : 'runs'}
          />
          <HeroFigure icon={Wallet} value={figures.cost} label="spent" />
          <HeroFigure icon={Clock} value={figures.worked} label="worked" />
        </p>
      </div>
    </section>
  );
}
