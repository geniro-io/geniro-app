// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import type { TeamStatsDto } from '../autogenerated';
import { TeamStatsTab } from './team-insights';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const NO_METRICS: TeamStatsDto['metrics'] = {
  goals: {
    recorded: 0,
    achieved: 0,
    notAchieved: 0,
    dropped: 0,
    open: 0,
    achievedShare: null,
    runsWithGoals: 0,
    measuredRuns: 0,
    coverage: null,
  },
  outcomes: {
    success: 0,
    partial: 0,
    failed: 0,
    abandoned: 0,
    recorded: 0,
    derived: 0,
  },
  handOffs: null,
  tools: [],
  mcpServers: [],
  stages: [],
  calls: [],
};

const NO_OUTCOMES = {
  total: 0,
  accepted: 0,
  changesRequested: 0,
  notYet: 0,
  notNeeded: 0,
};

const STATS: TeamStatsDto = {
  slug: 'dev-team',
  runs: 23,
  costUsd: 41.2,
  estimatedCostUsd: 6.4,
  turns: 312,
  workedMs: 50_400_000,
  outcomes: {
    total: 9,
    accepted: 6,
    changesRequested: 2,
    notYet: 1,
    notNeeded: 0,
  },
  days: [
    {
      day: '2026-10-30',
      runs: 3,
      costUsd: null,
      turns: 40,
      workedMs: null,
      outcomes: 0,
    },
    {
      day: '2026-10-31',
      runs: 10,
      costUsd: 25.3,
      turns: 147,
      workedMs: 32_400_000,
      outcomes: 6,
    },
  ],
  metrics: NO_METRICS,
  byMember: [
    {
      memberId: 'engineer',
      agentKind: 'claude',
      costUsd: 28.5,
      turns: 190,
      workedMs: 32_400_000,
    },
    {
      memberId: 'gone-member',
      agentKind: null,
      costUsd: null,
      turns: 7,
      workedMs: null,
    },
  ],
};

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function render(stats: TeamStatsDto | null): void {
  act(() => {
    root.render(
      <TeamStatsTab
        stats={stats}
        loading={false}
        error={null}
        memberOf={(memberId) =>
          memberId === 'engineer' ? { name: 'Engineer' } : null
        }
      />,
    );
  });
}

function tile(caption: string): HTMLElement {
  const found = [
    ...container.querySelectorAll<HTMLElement>('[data-slot="kpi-tile"]'),
  ].find((candidate) => candidate.textContent?.startsWith(caption));
  if (!found) {
    throw new Error(`no ${caption} tile`);
  }
  return found;
}

describe('TeamStatsTab', () => {
  it('shows the daemon figures and keeps unmeasured cost a dash', () => {
    render(STATS);

    expect(tile('Runs').textContent).toContain('23');
    expect(tile('Cost').textContent).toContain('$41.20');
    expect(tile('Cost').textContent).toContain('incl. $6.40 estimated');
    expect(tile('Turns').textContent).toContain('312');
    expect(tile('Worked time').textContent).toContain('14h 0m');
    expect(tile('Outcomes').textContent).toContain('6 of 9');

    render({
      ...STATS,
      costUsd: null,
      estimatedCostUsd: null,
      workedMs: null,
      outcomes: NO_OUTCOMES,
    });

    expect(tile('Cost').textContent).toBe('Cost—');
    expect(tile('Worked time').textContent).toBe('Worked time—');
    expect(tile('Outcomes').textContent).toBe('Outcomes—');
    expect(tile('Runs').textContent).toContain('23');
  });

  it('shows goals achieved, hand-offs, the call matrix, tools and stages from the daemon', () => {
    render({
      ...STATS,
      metrics: {
        ...NO_METRICS,
        goals: {
          ...NO_METRICS.goals,
          recorded: 3,
          achieved: 2,
          open: 1,
          achievedShare: 2 / 3,
          runsWithGoals: 1,
          measuredRuns: 1,
          coverage: 1,
        },
        handOffs: 4,
        tools: [
          { tool: 'Bash', mcpServer: null, calls: 9, errors: 1, avgMs: 1_000 },
          {
            tool: 'codegraph_explore',
            mcpServer: 'codegraph',
            calls: 2,
            errors: 0,
            avgMs: null,
          },
        ],
        mcpServers: [{ server: 'codegraph', calls: 2, errors: 0, tools: 1 }],
        stages: [
          {
            stageId: 'build',
            completed: 2,
            skipped: 0,
            reopened: 1,
            avgMs: 60_000,
          },
        ],
        calls: [
          {
            caller: 'engineer',
            callee: 'gone-member',
            calls: 3,
            failed: 1,
            turns: 6,
            costUsd: 1.5,
            avgMs: 2_000,
          },
        ],
      },
    });

    expect(tile('Goals achieved').textContent).toContain('67%');
    expect(tile('Goals achieved').textContent).toContain('2 of 3 goals');
    expect(tile('Hand-offs').textContent).toContain('4');
    const matrix = container.querySelector(
      'table[aria-label="Calls between members"]',
    );
    expect(matrix?.textContent).toContain('Engineer');
    expect(matrix?.textContent).toContain('gone-member (removed)');
    expect(matrix?.textContent).toContain('3 (1 failed)');
    const tools = container.querySelector('table[aria-label="Tools"]');
    expect(tools?.textContent).toContain('codegraph_explore · codegraph');
    expect(
      container.querySelector('table[aria-label="MCP servers"]')?.textContent,
    ).toContain('codegraph');
    expect(
      container.querySelector('table[aria-label="Stages"]')?.textContent,
    ).toContain('build');
  });

  it('keeps unmeasured goals and hand-offs a dash', () => {
    render(STATS);

    expect(tile('Goals achieved').textContent).toBe('Goals achieved—');
    expect(tile('Hand-offs').textContent).toBe('Hand-offs—');
  });

  it('lists each member by name, and a removed member by id', () => {
    render(STATS);

    const rows = [
      ...container.querySelectorAll<HTMLElement>(
        '[data-slot="member-breakdown-row"]',
      ),
    ];
    expect(rows).toHaveLength(2);
    expect(rows[0]?.textContent).toContain('Engineer');
    expect(rows[0]?.textContent).toContain('$28.50');
    expect(rows[1]?.textContent).toContain('gone-member (removed)');
    expect(rows[1]?.textContent).toContain('7');
  });

  it('says there are no runs when the team has none', () => {
    render({
      ...STATS,
      runs: 0,
      costUsd: null,
      estimatedCostUsd: null,
      turns: 0,
      workedMs: null,
      outcomes: NO_OUTCOMES,
      days: [],
      metrics: NO_METRICS,
      byMember: [],
    });

    expect(container.textContent).toContain('No runs yet.');
    expect(
      container.querySelector('[data-slot="member-breakdown-row"]'),
    ).toBeNull();
  });
});
