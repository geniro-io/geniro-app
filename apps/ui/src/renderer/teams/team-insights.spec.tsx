// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import type { TeamStatsDto } from '../autogenerated';
import { TeamStatsTab } from './team-insights';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const NO_OUTCOMES = {
  total: 0,
  accepted: 0,
  changesRequested: 0,
  notYet: 0,
  notNeeded: 0,
};

const STATS: TeamStatsDto = {
  slug: 'dev-team',
  runs: 23,
  costUsd: 41.2,
  estimatedCostUsd: 6.4,
  turns: 312,
  workedMs: 50_400_000,
  outcomes: {
    total: 9,
    accepted: 6,
    changesRequested: 2,
    notYet: 1,
    notNeeded: 0,
  },
  days: [
    {
      day: '2026-10-30',
      runs: 3,
      costUsd: null,
      turns: 40,
      workedMs: null,
      outcomes: 0,
    },
    {
      day: '2026-10-31',
      runs: 10,
      costUsd: 25.3,
      turns: 147,
      workedMs: 32_400_000,
      outcomes: 6,
    },
  ],
  byMember: [
    {
      memberId: 'engineer',
      agentKind: 'claude',
      costUsd: 28.5,
      turns: 190,
      workedMs: 32_400_000,
    },
    {
      memberId: 'gone-member',
      agentKind: null,
      costUsd: null,
      turns: 7,
      workedMs: null,
    },
  ],
};

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function render(stats: TeamStatsDto | null): void {
  act(() => {
    root.render(
      <TeamStatsTab
        stats={stats}
        loading={false}
        error={null}
        memberOf={(memberId) =>
          memberId === 'engineer' ? { name: 'Engineer' } : null
        }
      />,
    );
  });
}

function tile(caption: string): HTMLElement {
  const found = [
    ...container.querySelectorAll<HTMLElement>('[data-slot="kpi-tile"]'),
  ].find((candidate) => candidate.textContent?.startsWith(caption));
  if (!found) {
    throw new Error(`no ${caption} tile`);
  }
  return found;
}

describe('TeamStatsTab', () => {
  it('shows the daemon figures and keeps unmeasured cost a dash', () => {
    render(STATS);

    expect(tile('Runs').textContent).toContain('23');
    expect(tile('Cost').textContent).toContain('$41.20');
    expect(tile('Cost').textContent).toContain('incl. $6.40 estimated');
    expect(tile('Turns').textContent).toContain('312');
    expect(tile('Worked time').textContent).toContain('14h 0m');
    expect(tile('Outcomes').textContent).toContain('6 of 9');

    render({
      ...STATS,
      costUsd: null,
      estimatedCostUsd: null,
      workedMs: null,
      outcomes: NO_OUTCOMES,
    });

    expect(tile('Cost').textContent).toBe('Cost—');
    expect(tile('Worked time').textContent).toBe('Worked time—');
    expect(tile('Outcomes').textContent).toBe('Outcomes—');
    expect(tile('Runs').textContent).toContain('23');
  });

  it('lists each member by name, and a removed member by id', () => {
    render(STATS);

    const rows = [
      ...container.querySelectorAll<HTMLElement>(
        '[data-slot="member-breakdown-row"]',
      ),
    ];
    expect(rows).toHaveLength(2);
    expect(rows[0]?.textContent).toContain('Engineer');
    expect(rows[0]?.textContent).toContain('$28.50');
    expect(rows[1]?.textContent).toContain('gone-member (removed)');
    expect(rows[1]?.textContent).toContain('7');
  });

  it('says there are no runs when the team has none', () => {
    render({
      ...STATS,
      runs: 0,
      costUsd: null,
      estimatedCostUsd: null,
      turns: 0,
      workedMs: null,
      outcomes: NO_OUTCOMES,
      days: [],
      byMember: [],
    });

    expect(container.textContent).toContain('No runs yet.');
    expect(
      container.querySelector('[data-slot="member-breakdown-row"]'),
    ).toBeNull();
  });
});
