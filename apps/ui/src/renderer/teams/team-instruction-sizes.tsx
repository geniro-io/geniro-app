import type { MemberInstructionSize, TeamMember } from '../autogenerated';
import { formatTokens } from '../chats/agent-activity';
import { contextCategoryColor } from '../chats/chat-metrics';
import { MemberAvatar } from '../components/member-avatar';
import { SegmentBreakdown } from '../components/segment-breakdown';
import { Spinner } from '../components/ui/spinner';
import { formatCount } from '../stats/stats-format';

/**
 * How much instruction text each member's every turn carries before its
 * prompt, and the team's together — the daemon's figures
 * (`POST /v1/teams/instruction-sizes`); a member's own breakdown is on its sheet.
 */
export function TeamInstructionSizes({
  members,
  labels,
  sizes,
  loading,
  error,
}: {
  members: readonly Pick<TeamMember, 'id' | 'avatar'>[];
  labels: ReadonlyMap<string, string>;
  sizes: ReadonlyMap<string, MemberInstructionSize> | null;
  loading: boolean;
  error: string | null;
}): React.JSX.Element {
  const measured = members.flatMap((member) => {
    const size = sizes?.get(member.id);
    return size === undefined ? [] : [{ member, size }];
  });
  if (measured.length === 0) {
    return (
      <p className="flex items-center gap-1.5 text-sm text-muted-foreground">
        {loading ? (
          <>
            <Spinner /> Measuring…
          </>
        ) : (
          (error ?? 'Not measured yet.')
        )}
      </p>
    );
  }
  const totalTokens = measured.reduce(
    (sum, entry) => sum + entry.size.approxTokens,
    0,
  );
  const totalChars = measured.reduce(
    (sum, entry) => sum + entry.size.totalChars,
    0,
  );
  return (
    <div
      data-slot="team-instruction-sizes"
      aria-busy={loading}
      className="flex flex-col gap-2 rounded-card bg-card p-5 text-xs ring-1 ring-border">
      <div className="flex items-baseline gap-1.5">
        <span
          data-slot="team-instruction-total"
          className="text-sm font-medium text-foreground tabular-nums">
          ~{formatTokens(totalTokens)} tokens
        </span>
        <span className="text-muted-foreground tabular-nums">
          {formatCount(totalChars)} characters across{' '}
          {measured.length === 1 ? '1 member' : `${measured.length} members`}
        </span>
        {loading ? <Spinner className="self-center" /> : null}
      </div>
      <SegmentBreakdown
        denominator={totalTokens}
        segments={measured.map(({ member, size }, index) => ({
          key: member.id,
          label: (
            <span className="inline-flex min-w-0 items-center gap-1.5">
              <MemberAvatar
                name={labels.get(member.id) ?? member.id}
                avatar={member.avatar}
                colorKey={member.id}
                size={20}
              />
              <span className="truncate">
                {labels.get(member.id) ?? member.id}
              </span>
              {size.turn === 'call' ? (
                <span className="shrink-0 text-muted-foreground">
                  · answering a call
                </span>
              ) : null}
            </span>
          ),
          value: size.approxTokens,
          colorClass: contextCategoryColor(index),
          figures: [
            formatCount(size.totalChars),
            `~${formatTokens(size.approxTokens)}`,
          ],
        }))}
      />
      {error ? <p className="text-muted-foreground">{error}</p> : null}
    </div>
  );
}
