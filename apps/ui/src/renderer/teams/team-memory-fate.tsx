import { useEffect, useState } from 'react';

import type { DeleteTeamMemoriesEnum } from '../autogenerated';
import { FateOptions } from '../components/fate-options';
import type { DaemonApis } from '../daemon-api';

export type TeamMemoryFate = DeleteTeamMemoriesEnum;

const FATES: readonly {
  fate: TeamMemoryFate;
  label: string;
  detail: string;
}[] = [
  {
    fate: 'forget',
    label: 'Forget them',
    detail: 'They can be restored in Settings → Memory.',
  },
  {
    fate: 'keep',
    label: 'Keep them for this team name',
    detail: 'A team created later with the same name reads them.',
  },
  {
    fate: 'global',
    label: 'Move them to Global',
    detail: 'Every run reads them from now on.',
  },
];

/** The most entries one read counts before the dialog says "or more". */
const COUNT_LIMIT = 200;

/**
 * What deleting a team does with the memories filed under it, asked in the
 * delete dialog. Draws nothing while the team has none, or before its count
 * arrives, since there is then nothing to decide.
 */
export function TeamMemoryFatePick({
  apis,
  slug,
  value,
  onChange,
}: {
  apis: DaemonApis | null;
  slug: string | null;
  value: TeamMemoryFate;
  onChange: (fate: TeamMemoryFate) => void;
}): React.JSX.Element | null {
  const memoriesApi = apis?.memories ?? null;
  const [count, setCount] = useState<{ slug: string; total: string } | null>(
    null,
  );

  useEffect(() => {
    if (memoriesApi === null || slug === null) {
      return;
    }
    let live = true;
    void memoriesApi
      .listMemories({ scope: 'team', teamSlug: slug, limit: COUNT_LIMIT })
      .then((list) => {
        if (live) {
          setCount({
            slug,
            total:
              list.next === null
                ? String(list.memories.length)
                : `${list.memories.length} or more`,
          });
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, [memoriesApi, slug]);

  if (count === null || count.slug !== slug || count.total === '0') {
    return null;
  }
  return (
    <div data-slot="team-memory-fate" className="flex flex-col gap-2">
      <p>
        This team keeps {count.total} memor
        {count.total === '1' ? 'y' : 'ies'}. What happens to{' '}
        {count.total === '1' ? 'it' : 'them'}?
      </p>
      <FateOptions
        label="Team memories"
        fates={FATES}
        value={value}
        onChange={onChange}
      />
    </div>
  );
}
