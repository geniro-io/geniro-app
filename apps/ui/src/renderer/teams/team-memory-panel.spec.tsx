// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { memoryEntry } from '../__fixtures__/memories';
import { PUBLISHED_IDENTITIES } from '../__tests__/agent-identities';
import { confirmInDialog } from '../__tests__/confirm-in-dialog';
import { AgentIdentityContext } from '../agent-identity';
import type { MemoryEntry, MemoryListDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient, MemoryChangedEvent } from '../daemon-client';
import { TeamMemoryPanel } from './team-memory-panel';
import { useTeamMemories } from './use-team-memories';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

const NOTE = memoryEntry({
  id: 'e1',
  handle: 'm1',
  title: 'Review in pairs',
  teamSlug: 'review-crew',
});
const WAITING = memoryEntry({
  id: 'e2',
  handle: 'm2',
  title: 'Hand off with a brief',
  teamSlug: 'review-crew',
  status: 'pending',
  source: {
    actor: 'agent',
    agentKind: 'claude',
    model: 'opus',
    runId: 'r1',
    importedFrom: null,
  },
});

function fakeApis(listed: MemoryEntry[] = [NOTE, WAITING]) {
  const memories = {
    listMemories: vi.fn((_request: unknown) =>
      Promise.resolve<MemoryListDto>({ memories: listed, next: null }),
    ),
    createMemory: vi.fn((_request: unknown) => Promise.resolve(NOTE)),
    updateMemory: vi.fn((_request: unknown) => Promise.resolve(NOTE)),
  };
  return { memories, apis: { memories } as unknown as DaemonApis };
}

function fakeClient() {
  const listeners = new Set<(event: MemoryChangedEvent) => void>();
  return {
    client: {
      onMemoryChanged: (listener: (event: MemoryChangedEvent) => void) => {
        listeners.add(listener);
        return () => listeners.delete(listener);
      },
    } as unknown as DaemonClient,
    announce: (event: MemoryChangedEvent) =>
      listeners.forEach((listener) => listener(event)),
  };
}

function Harness({
  apis,
  client,
  query = '',
}: {
  apis: DaemonApis;
  client: DaemonClient | null;
  query?: string;
}): React.JSX.Element {
  const memories = useTeamMemories(apis, 'review-crew', query, client);
  return (
    <AgentIdentityContext.Provider value={PUBLISHED_IDENTITIES}>
      <TeamMemoryPanel
        apis={apis}
        slug="review-crew"
        teamName="Review crew"
        memories={memories}
      />
    </AgentIdentityContext.Provider>
  );
}

async function settle(ms = 0): Promise<void> {
  await act(async () => {
    await new Promise((resolve) => setTimeout(resolve, ms));
  });
}

async function render(
  apis: DaemonApis,
  client: DaemonClient | null = null,
  query = '',
): Promise<void> {
  await act(async () => {
    root.render(<Harness apis={apis} client={client} query={query} />);
  });
  await settle();
}

function button(scope: ParentNode, label: string): HTMLButtonElement {
  const found = [...scope.querySelectorAll('button')].find(
    (candidate) => candidate.textContent?.trim() === label,
  );
  if (!found) {
    throw new Error(`no button "${label}"`);
  }
  return found;
}

async function press(target: HTMLElement): Promise<void> {
  await act(async () => {
    target.click();
  });
  await settle();
}

function rowOf(handle: string): HTMLElement {
  return container.querySelector<HTMLElement>(
    `[data-memory-handle="${handle}"]`,
  )!;
}

function fill(field: HTMLInputElement | HTMLTextAreaElement, text: string) {
  const proto =
    field instanceof HTMLTextAreaElement
      ? HTMLTextAreaElement.prototype
      : HTMLInputElement.prototype;
  return act(async () => {
    Object.getOwnPropertyDescriptor(proto, 'value')!.set!.call(field, text);
    field.dispatchEvent(new Event('input', { bubbles: true }));
  });
}

beforeEach(() => {
  Element.prototype.scrollIntoView = vi.fn();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('TeamMemoryPanel', () => {
  it('draws the rows the daemon lists for this team’s scope, named for the team', async () => {
    const { apis, memories } = fakeApis();
    await render(apis);

    expect(memories.listMemories).toHaveBeenCalledWith({
      scope: 'team',
      teamSlug: 'review-crew',
      limit: 200,
    });
    expect(rowOf('m1').textContent).toContain('Review in pairs');
    expect(rowOf('m1').textContent).toContain(' · Review crew · ');
    expect(rowOf('m2').textContent).toContain('Hand off with a brief');
  });

  it('draws no rows while the team has none, leaving the tab’s own empty state', async () => {
    const { apis } = fakeApis([]);
    await render(apis);

    expect(container.querySelector('[data-memory-handle]')).toBeNull();
    expect(container.querySelector('ul')).toBeNull();
  });

  it('adds a memory filed under the team and no project', async () => {
    const { apis, memories } = fakeApis();
    await render(apis);

    await press(button(container, 'Add memory'));
    const form = container.querySelector<HTMLElement>(
      '[data-slot="memory-form"]',
    )!;
    await fill(form.querySelector<HTMLInputElement>('input')!, 'Pair up');
    await fill(
      form.querySelector<HTMLTextAreaElement>('textarea')!,
      'Two reviewers per change',
    );
    await press(button(form, 'Add'));

    expect(memories.createMemory).toHaveBeenCalledWith({
      createMemoryDto: {
        title: 'Pair up',
        body: 'Two reviewers per change',
        type: 'project',
        projectId: null,
        teamSlug: 'review-crew',
        notDuplicateOf: undefined,
      },
    });
    expect(container.querySelector('[data-slot="memory-form"]')).toBeNull();
  });

  it('offers a second press with the named handles after a near-duplicate refusal', async () => {
    const { apis, memories } = fakeApis();
    memories.createMemory.mockRejectedValueOnce(
      new Error(
        'daemon POST /v1/memories failed (409): {"code":"MEMORY_NEAR_DUPLICATE","message":"similar entries exist: m3, m7"}',
      ),
    );
    await render(apis);

    await press(button(container, 'Add memory'));
    const form = container.querySelector<HTMLElement>(
      '[data-slot="memory-form"]',
    )!;
    await fill(form.querySelector<HTMLInputElement>('input')!, 'Pair up');
    await fill(form.querySelector<HTMLTextAreaElement>('textarea')!, 'Pairs.');
    await press(button(form, 'Add'));
    expect(container.textContent).toContain('Similar entries exist: m3, m7');
    await press(button(form, 'Add'));

    expect(memories.createMemory).toHaveBeenLastCalledWith({
      createMemoryDto: expect.objectContaining({
        teamSlug: 'review-crew',
        notDuplicateOf: ['m3', 'm7'],
      }),
    });
  });

  it('edits an entry at its revision, still filed under the team', async () => {
    const { apis, memories } = fakeApis();
    await render(apis);

    await press(button(rowOf('m1'), 'Edit'));
    const form = container.querySelector<HTMLElement>(
      '[data-slot="memory-form"]',
    )!;
    await fill(form.querySelector<HTMLInputElement>('input')!, 'Review twice');
    await press(button(form, 'Save'));

    expect(memories.updateMemory).toHaveBeenCalledWith({
      memoryId: 'e1',
      updateMemoryDto: expect.objectContaining({
        title: 'Review twice',
        rev: 1,
        projectId: null,
        teamSlug: 'review-crew',
      }),
    });
  });

  it('forgets an entry after a confirming press', async () => {
    const { apis, memories } = fakeApis();
    await render(apis);

    await press(button(rowOf('m1'), 'Forget'));
    expect(memories.updateMemory).not.toHaveBeenCalled();
    await press(confirmInDialog('Forget'));

    expect(memories.updateMemory).toHaveBeenCalledWith({
      memoryId: 'e1',
      updateMemoryDto: { status: 'forgotten' },
    });
  });

  it('approves a waiting agent entry', async () => {
    const { apis, memories } = fakeApis();
    await render(apis);

    await press(button(rowOf('m2'), 'Approve'));

    expect(memories.updateMemory).toHaveBeenCalledWith({
      memoryId: 'e2',
      updateMemoryDto: { status: 'active' },
    });
  });

  it('re-reads the daemon’s list when memory changes', async () => {
    const { apis, memories } = fakeApis();
    const { client, announce } = fakeClient();
    await render(apis, client);
    const before = memories.listMemories.mock.calls.length;

    memories.listMemories.mockImplementationOnce(() =>
      Promise.resolve<MemoryListDto>({
        memories: [
          memoryEntry({ id: 'e9', handle: 'm9', teamSlug: 'review-crew' }),
        ],
        next: null,
      }),
    );
    announce({
      memoryId: 'e9',
      change: 'created',
      projectId: null,
      teamSlug: 'review-crew',
      batchId: null,
    });
    await settle(300);

    expect(memories.listMemories.mock.calls.length - before).toBe(1);
    expect(rowOf('m9')).not.toBeNull();
    expect(container.querySelector('[data-memory-handle="m1"]')).toBeNull();
  });

  it('searches with the trimmed query and leaves it out when blank', async () => {
    const { apis, memories } = fakeApis();
    await render(apis, null, '  pairs ');
    await settle(300);

    expect(memories.listMemories).toHaveBeenLastCalledWith({
      scope: 'team',
      teamSlug: 'review-crew',
      q: 'pairs',
      limit: 200,
    });
  });

  it('shows the daemon’s refusal with a Retry that reads again', async () => {
    const { apis, memories } = fakeApis();
    memories.listMemories.mockRejectedValueOnce(new Error('daemon is down'));
    await render(apis);

    expect(container.querySelector('[role="alert"]')!.textContent).toContain(
      'daemon is down',
    );
    await press(button(container, 'Retry'));

    expect(container.querySelector('[role="alert"]')).toBeNull();
    expect(rowOf('m1')).not.toBeNull();
  });
});
