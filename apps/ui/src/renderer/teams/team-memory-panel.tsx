import { Brain } from 'lucide-react';
import { useState } from 'react';

import type { LessonsMode } from '../../shared/contracts';
import type { LessonOverride, MemoryEntry } from '../autogenerated';
import { EmptyState } from '../components/empty-state';
import { ErrorBanner } from '../components/error-banner';
import {
  LESSONS_APP_OFF_REASON,
  LessonsOverrideControl,
} from '../components/lessons-override-control';
import { MemoryForm } from '../components/memory-form';
import { MemoryRow } from '../components/memory-row';
import { Button } from '../components/ui/button';
import { Spinner } from '../components/ui/spinner';
import {
  awaitsApproval,
  type MemoryEditing,
  useMemoryEditor,
} from '../components/use-memory-editor';
import type { DaemonApis } from '../daemon-api';
import type { TeamMemories } from './use-team-memories';

const NO_PROJECTS: readonly { id: string; name: string }[] = [];

/** The team's own lessons setting and what the app's Settings say about it. */
export interface TeamLessons {
  /** The team's own value; undefined inherits the project's, then the app's. */
  value: LessonOverride | undefined;
  /** The app's lessons mode from Settings; null until it is read. */
  appMode: LessonsMode | null;
  onChange: (value: LessonOverride | undefined) => void;
}

/**
 * The Memory tab's body: the team's own entries, each editable, forgettable
 * and approvable, and an Add memory form filed under the team. Entries are
 * always the daemon's list in `memories`; a write re-reads it. When `lessons`
 * is given, the team's lessons setting leads the tab.
 */
export function TeamMemoryPanel({
  apis,
  slug,
  teamName,
  memories,
  query = '',
  lessons,
}: {
  apis: DaemonApis | null;
  slug: string;
  teamName: string;
  memories: TeamMemories;
  /** The search the list was read with; it decides the empty state's words. */
  query?: string;
  lessons?: TeamLessons;
}): React.JSX.Element {
  const api = apis?.memories ?? null;
  const [actionError, setActionError] = useState<string | null>(null);
  const {
    editing,
    setEditing,
    formError,
    setFormError,
    saving,
    busy,
    setStatus,
    submit,
    close,
  } = useMemoryEditor(api, {
    onSaved: () => memories.reload(),
    onStatusError: setActionError,
    filed: (value) => ({ ...value, projectId: null, teamSlug: slug }),
  });
  const [dismissedRead, setDismissedRead] = useState<string | null>(null);

  const teams = [{ slug, name: teamName }];

  const form = (submitLabel: string, current: MemoryEditing) => (
    <MemoryForm
      value={current.value}
      projects={NO_PROJECTS}
      teams={teams}
      scopeLocked
      saving={saving}
      error={formError}
      submitLabel={submitLabel}
      onChange={(value) => setEditing({ ...current, value, vouched: [] })}
      onSubmit={() => void submit()}
      onCancel={close}
    />
  );

  const row = (entry: MemoryEntry) =>
    editing?.kind === 'edit' && editing.entry.id === entry.id ? (
      form('Save', editing)
    ) : (
      <MemoryRow
        entry={entry}
        projectName={null}
        teamName={teamName}
        busy={busy === entry.id}
        onEdit={() => {
          setFormError(null);
          setEditing({
            kind: 'edit',
            entry,
            vouched: [],
            value: {
              title: entry.title,
              body: entry.body,
              type: entry.type,
              projectId: null,
              teamSlug: slug,
            },
          });
        }}
        onForget={() => void setStatus(entry, 'forgotten')}
        onApprove={
          awaitsApproval(entry)
            ? () => void setStatus(entry, 'active')
            : undefined
        }
      />
    );

  const readError =
    memories.error !== null && memories.error !== dismissedRead
      ? memories.error
      : null;
  const entries = memories.entries ?? [];

  return (
    <div data-slot="team-memory-panel" className="flex flex-col gap-3">
      {lessons === undefined ? null : (
        <LessonsOverrideControl
          value={lessons.value ?? 'inherit'}
          onChange={(next) =>
            lessons.onChange(next === 'inherit' ? undefined : next)
          }
          inheritedLabel="Inherit (project, then app setting)"
          disabled={lessons.appMode === 'off'}
          disabledReason={
            lessons.appMode === 'off' ? LESSONS_APP_OFF_REASON : undefined
          }
        />
      )}
      {readError === null ? null : (
        <ErrorBanner
          message={readError}
          action={
            <Button
              type="button"
              size="sm"
              variant="outline"
              onClick={memories.reload}>
              Retry
            </Button>
          }
          onDismiss={() => setDismissedRead(readError)}
        />
      )}
      {actionError === null ? null : (
        <ErrorBanner
          message={actionError}
          onDismiss={() => setActionError(null)}
        />
      )}
      {editing?.kind === 'new' ? (
        form('Add', editing)
      ) : (
        <div className="flex justify-end">
          <Button
            type="button"
            size="sm"
            disabled={api === null}
            onClick={() => {
              setFormError(null);
              setEditing({
                kind: 'new',
                vouched: [],
                value: {
                  title: '',
                  body: '',
                  type: 'project',
                  projectId: null,
                  teamSlug: slug,
                },
              });
            }}>
            Add memory
          </Button>
        </div>
      )}
      {memories.loading ? (
        <EmptyState className="gap-2">
          <Spinner />
          Loading team memories…
        </EmptyState>
      ) : entries.length === 0 ? (
        readError === null ? (
          <EmptyState icon={<Brain aria-hidden="true" />}>
            {query.trim() === ''
              ? 'No team memories yet.'
              : 'No team memories match this search.'}
          </EmptyState>
        ) : null
      ) : (
        <ul className="flex flex-col gap-2">
          {entries.map((entry) => (
            <li key={entry.id}>{row(entry)}</li>
          ))}
        </ul>
      )}
      {memories.more ? (
        <p className="text-xs text-muted-foreground">
          Showing the newest entries. Search to narrow the list.
        </p>
      ) : null}
    </div>
  );
}
