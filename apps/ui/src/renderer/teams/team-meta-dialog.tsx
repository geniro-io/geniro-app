import { MessagesSquare, Pencil, Plus } from 'lucide-react';
import { useEffect, useState } from 'react';

import type { TeamStage } from '../autogenerated';
import { ErrorText } from '../components/error-text';
import { Field } from '../components/field';
import { StageGraph } from '../components/stage-graph';
import { Button } from '../components/ui/button';
import { Dialog } from '../components/ui/dialog';
import { Input } from '../components/ui/input';
import { Stepper } from '../components/ui/stepper';
import { Switch } from '../components/ui/switch';
import { Textarea } from '../components/ui/textarea';
import type { TeamMeta } from './graph-doc';
import { StageSchemaEditor } from './stage-schema-editor';
import { stageFacts } from './stage-validate';

/** Where a newly switched-on limit starts: low enough to mean something. */
const DEFAULT_MAX_ACTIVE_TURNS = 4;

export function stageCount(stages: readonly TeamStage[]): string {
  const forks = [...stageFacts(stages).values()].filter(
    (facts) => facts.branches >= 2,
  ).length;
  const count = `${stages.length} ${stages.length === 1 ? 'stage' : 'stages'}`;
  return forks === 0
    ? count
    : `${count} · ${forks} ${forks === 1 ? 'fork' : 'forks'}`;
}

/**
 * The one team-meta form (name, optional description, optional cap on
 * agent turns working at once), shared by BOTH meta flows so they stay
 * identical: "New team" (empty form; Create persists a fresh team) and
 * the builder's "Change team" (form prefilled from the open team; Save
 * persists the new meta). Submit hands the trimmed meta to the caller; Cancel
 * changes nothing.
 */
export function TeamMetaDialog({
  open,
  busy,
  error,
  title,
  submitLabel,
  busyLabel,
  initial,
  maxActiveTurnsCeiling,
  agentIds,
  onClose,
  onSubmit,
  onAskChat,
}: {
  open: boolean;
  busy: boolean;
  error?: string | null;
  title: string;
  submitLabel: string;
  busyLabel: string;
  /** Prefill for editing an existing team's meta; omit for a blank form. */
  initial?: TeamMeta;
  /**
   * This Mac's ceiling on agent turns working at once in one run
   * (`GET /v1/capabilities`) — what no limit means, and the most a limit can
   * be set to. Null until it is read.
   */
  maxActiveTurnsCeiling: number | null;
  agentIds: readonly string[];
  onClose: () => void;
  onSubmit: (meta: TeamMeta) => void;
  /** Absent where there is no chat (a team not created yet). */
  onAskChat?: (hasStages: boolean) => void;
}): React.JSX.Element {
  const [name, setName] = useState('');
  const [description, setDescription] = useState('');
  // Off = no limit of the team's own: the run goes up to the ceiling.
  const [limited, setLimited] = useState(false);
  const [maxActiveTurns, setMaxActiveTurns] = useState(
    DEFAULT_MAX_ACTIVE_TURNS,
  );
  const [stages, setStages] = useState<readonly TeamStage[] | undefined>(
    undefined,
  );
  const [stagesOpen, setStagesOpen] = useState(false);

  // A reopened dialog starts from `initial` (or blank) — never from the
  // previous visit's abandoned draft.
  useEffect(() => {
    if (open) {
      setName(initial?.name ?? '');
      setDescription(initial?.description ?? '');
      setLimited(initial?.maxActiveTurns !== undefined);
      setMaxActiveTurns(initial?.maxActiveTurns ?? DEFAULT_MAX_ACTIVE_TURNS);
    }
    // `initial` is compared by its fields: a rename dialog reopened for the
    // same team must reset even when the caller rebuilt the object.
  }, [open, initial?.name, initial?.description, initial?.maxActiveTurns]);

  // Compared by content: a re-read that rebuilt an equal list keeps the draft,
  // one that brought other stages replaces it like the other fields.
  const initialStagesKey = JSON.stringify(initial?.stages ?? null);
  useEffect(() => {
    if (open) {
      setStages(initial?.stages);
      setStagesOpen(false);
    }
  }, [open, initialStagesKey]);

  const canSubmit = name.trim().length > 0 && !busy;
  // The chat works on the saved file, and handing over closes the dialog.
  const unsaved =
    name !== (initial?.name ?? '') ||
    description !== (initial?.description ?? '') ||
    limited !== (initial?.maxActiveTurns !== undefined) ||
    (limited && maxActiveTurns !== initial?.maxActiveTurns) ||
    JSON.stringify(stages ?? null) !== initialStagesKey;
  const askChatTitle = unsaved
    ? 'Save or cancel your changes first — the chat changes the saved team'
    : undefined;

  return (
    <>
      <Dialog open={open} onClose={onClose} title={title}>
        <form
          className="flex flex-col gap-4"
          onSubmit={(event) => {
            event.preventDefault();
            if (!canSubmit) {
              return;
            }
            const trimmedDescription = description.trim();
            onSubmit({
              name: name.trim(),
              ...(trimmedDescription
                ? { description: trimmedDescription }
                : {}),
              ...(limited ? { maxActiveTurns } : {}),
              ...(stages && stages.length > 0 ? { stages: [...stages] } : {}),
            });
          }}>
          <Field label="Name" htmlFor="team-name">
            <Input
              id="team-name"
              value={name}
              placeholder="Review team"
              onChange={(event) => setName(event.target.value)}
            />
          </Field>
          <Field
            label="Description"
            htmlFor="team-description"
            hint="Optional — shown on the team's library card.">
            <Textarea
              id="team-description"
              value={description}
              rows={3}
              placeholder="What this agent team does…"
              onChange={(event) => setDescription(event.target.value)}
            />
          </Field>
          <Field
            label="Agents working at once"
            htmlFor="team-limit-turns"
            hint="How many agent calls of a run may work at the same time, at any depth; the rest wait their turn.">
            <div className="flex h-8 items-center justify-between gap-3">
              <label
                htmlFor="team-limit-turns"
                className="flex min-w-0 items-center gap-2 text-sm">
                <Switch
                  id="team-limit-turns"
                  checked={limited}
                  onCheckedChange={setLimited}
                />
                <span className="truncate">
                  {limited ? 'Limited to' : 'No limit of its own'}
                </span>
              </label>
              {limited ? (
                <Stepper
                  value={maxActiveTurns}
                  min={1}
                  // Until the ceiling is read, the value can go down but not up.
                  max={maxActiveTurnsCeiling ?? maxActiveTurns}
                  aria-label="Agents working at once"
                  onChange={setMaxActiveTurns}
                />
              ) : (
                <span
                  data-slot="max-active-turns-ceiling"
                  className="truncate text-sm text-muted-foreground tabular-nums">
                  {maxActiveTurnsCeiling === null
                    ? 'this Mac’s ceiling'
                    : `up to ${maxActiveTurnsCeiling}, this Mac’s ceiling`}
                </span>
              )}
            </div>
          </Field>
          <Field label="Stages">
            {stages && stages.length > 0 ? (
              <div
                data-slot="stages-panel"
                className="flex flex-col gap-2.5 rounded-xl border border-border bg-background p-3">
                <StageGraph stages={stages} />
                <div className="flex items-center justify-between gap-3">
                  <span
                    data-slot="stages-count"
                    className="text-xs text-muted-foreground tabular-nums">
                    {stageCount(stages)}
                  </span>
                  <div className="flex flex-wrap justify-end gap-2">
                    {onAskChat === undefined ? null : (
                      <Button
                        type="button"
                        variant="ghost"
                        size="sm"
                        aria-disabled={unsaved || undefined}
                        title={askChatTitle}
                        onClick={() => {
                          if (!unsaved) {
                            onAskChat(true);
                          }
                        }}>
                        <MessagesSquare aria-hidden="true" />
                        Change with chat
                      </Button>
                    )}
                    <Button
                      type="button"
                      variant="outline"
                      size="sm"
                      onClick={() => setStagesOpen(true)}>
                      <Pencil aria-hidden="true" />
                      Edit stages
                    </Button>
                  </div>
                </div>
              </div>
            ) : (
              <div
                data-slot="stages-panel"
                className="flex flex-wrap items-center justify-between gap-x-3 gap-y-2 rounded-xl border border-border px-3 py-2.5">
                <p
                  data-slot="stages-empty"
                  className="min-w-0 flex-[1_1_14rem] text-xs text-muted-foreground">
                  No stages yet — optional: the steps every run walks, which
                  agents move along.
                </p>
                <div className="ml-auto flex shrink-0 flex-wrap justify-end gap-2">
                  {onAskChat === undefined ? null : (
                    <Button
                      type="button"
                      variant="ghost"
                      size="sm"
                      aria-disabled={unsaved || undefined}
                      title={askChatTitle}
                      onClick={() => {
                        if (!unsaved) {
                          onAskChat(false);
                        }
                      }}>
                      <MessagesSquare aria-hidden="true" />
                      Add with chat
                    </Button>
                  )}
                  <Button
                    type="button"
                    variant="outline"
                    size="sm"
                    onClick={() => setStagesOpen(true)}>
                    <Plus aria-hidden="true" />
                    Add stages
                  </Button>
                </div>
              </div>
            )}
          </Field>
          {error ? <ErrorText>{error}</ErrorText> : null}
          <div className="flex justify-end gap-2">
            <Button type="button" variant="outline" onClick={onClose}>
              Cancel
            </Button>
            <Button type="submit" disabled={!canSubmit}>
              {busy ? busyLabel : submitLabel}
            </Button>
          </div>
        </form>
      </Dialog>
      {/* Outside the form: the editor's buttons must not submit this one. */}
      <StageSchemaEditor
        open={open && stagesOpen}
        stages={stages}
        agentIds={agentIds}
        onClose={() => setStagesOpen(false)}
        onSave={(saved) => {
          setStages(saved.length > 0 ? saved : undefined);
          setStagesOpen(false);
        }}
      />
    </>
  );
}
