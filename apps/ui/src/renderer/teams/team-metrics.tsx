import type { MemberCall, StageFigures } from '../autogenerated';
import { formatUsd } from '../chats/agent-activity';
import { type FigureColumn, FigureTable } from '../components/figure-table';
import {
  formatCount,
  formatDuration,
  NOT_MEASURED,
} from '../stats/stats-format';

/**
 * Who called whom across a team's runs: one row per caller, one column per callee,
 * each cell the calls between them with how many failed. Read from the daemon's
 * call ledger, never folded from a transcript.
 */
export function CallMatrix({
  calls,
  nameOf,
}: {
  calls: readonly MemberCall[];
  nameOf: (memberId: string) => string;
}): React.JSX.Element {
  const callers = [...new Set(calls.map((call) => call.caller))];
  const callees = [...new Set(calls.map((call) => call.callee))];
  const cell = (caller: string, callee: string): MemberCall | undefined =>
    calls.find((call) => call.caller === caller && call.callee === callee);
  const columns: FigureColumn<string>[] = [
    {
      header: 'Caller → callee',
      cell: (caller) => (
        <span className="block max-w-48 truncate">{nameOf(caller)}</span>
      ),
      title: nameOf,
    },
    ...callees.map((callee): FigureColumn<string> => ({
      header: nameOf(callee),
      align: 'end',
      cell: (caller) => {
        const pair = cell(caller, callee);
        if (pair === undefined) {
          return <span className="text-muted-foreground">·</span>;
        }
        return pair.failed > 0 ? (
          <span>
            {formatCount(pair.calls)}{' '}
            <span className="text-destructive">
              ({formatCount(pair.failed)} failed)
            </span>
          </span>
        ) : (
          formatCount(pair.calls)
        );
      },
      title: (caller) => {
        const pair = cell(caller, callee);
        if (pair === undefined) {
          return undefined;
        }
        const cost =
          pair.costUsd === null ? NOT_MEASURED : formatUsd(pair.costUsd);
        const time =
          pair.avgMs === null ? NOT_MEASURED : formatDuration(pair.avgMs);
        return `${formatCount(pair.turns)} callee turns · ${cost} · ${time} per call`;
      },
    })),
  ];
  return (
    <FigureTable
      ariaLabel="Calls between members"
      columns={columns}
      rows={callers}
      rowKey={(caller) => caller}
      emptyLabel="No member has called another yet."
    />
  );
}

/** Each stage's completions, skips and reopens, and how long it took when completed. */
export function StageFiguresTable({
  stages,
  titleOf,
}: {
  stages: readonly StageFigures[];
  titleOf: (stageId: string) => string;
}): React.JSX.Element {
  return (
    <FigureTable
      ariaLabel="Stages"
      columns={[
        {
          header: 'Stage',
          cell: (row) => (
            <span className="block max-w-56 truncate">
              {titleOf(row.stageId)}
            </span>
          ),
          title: (row) => titleOf(row.stageId),
        },
        {
          header: 'Completed',
          align: 'end',
          cell: (row) => formatCount(row.completed),
        },
        {
          header: 'Skipped',
          align: 'end',
          cell: (row) => formatCount(row.skipped),
        },
        {
          header: 'Reopened',
          align: 'end',
          cell: (row) => formatCount(row.reopened),
        },
        {
          header: 'Avg time',
          align: 'end',
          cell: (row) =>
            row.avgMs === null ? NOT_MEASURED : formatDuration(row.avgMs),
        },
      ]}
      rows={stages}
      rowKey={(row) => row.stageId}
      emptyLabel="No stage has moved yet."
    />
  );
}
