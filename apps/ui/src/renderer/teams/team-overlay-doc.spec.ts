import { describe, expect, it } from 'vitest';

import type { TeamMember, TeamOverlay } from '../autogenerated';
import {
  effectiveMemberOf,
  isOverridden,
  memberOverlayBadges,
  overrideFields,
  resetFields,
  withMemberPool,
  withMemberSettings,
  withTeamSettings,
} from './team-overlay-doc';

const LEAD: TeamMember = {
  id: 'lead',
  name: 'Lead',
  agent: 'claude',
  approval: 'ask',
  model: 'opus',
  effort: 'high',
  configDir: '/profiles/home',
  pool: [{ agent: 'claude', model: 'sonnet' }],
};

describe('effectiveMemberOf', () => {
  it('takes the member override over allMembers over the team', () => {
    const member = effectiveMemberOf(LEAD, {
      allMembers: { claude: { effort: 'low', model: 'haiku' } },
      members: { lead: { settings: { effort: 'max' } } },
    });

    expect(member).toMatchObject({
      effort: 'max',
      model: 'haiku',
      configDir: '/profiles/home',
    });
    expect(member.pool).toEqual([
      { agent: 'claude', model: 'haiku', effort: 'low' },
    ]);
  });

  it('starts the Model group over on an agent override and keeps an overridden pool as it is', () => {
    const member = effectiveMemberOf(LEAD, {
      allMembers: { claude: { configDir: '/profiles/work' } },
      members: {
        lead: { settings: { agent: 'codex' }, pool: [{ agent: 'claude' }] },
      },
    });

    expect(member).toMatchObject({ agent: 'codex', approval: 'ask' });
    expect(member.model).toBeUndefined();
    expect(member.configDir).toBeUndefined();
    expect(member.pool).toEqual([{ agent: 'claude' }]);
  });
});

describe('effectiveMemberOf picking another model', () => {
  it('drops the team’s window and parameters, as the editor does on a model change', () => {
    const member = effectiveMemberOf(
      { ...LEAD, contextWindow: '1m', modelParameters: { fast: 'on' } },
      { members: { lead: { settings: { model: 'haiku' } } } },
    );

    expect(member.model).toBe('haiku');
    expect(member.contextWindow).toBeUndefined();
    expect(member.modelParameters).toBeUndefined();
  });
});

describe('editing an overlay', () => {
  it('seeds an override with the team’s value, and resets it away', () => {
    const seeded = overrideFields({}, LEAD, ['effort']);
    expect(seeded).toEqual({
      members: { lead: { settings: { effort: 'high' } } },
    });
    expect(isOverridden(seeded, 'lead', 'effort')).toBe(true);
    expect(isOverridden(seeded, 'lead', 'model')).toBe(false);

    expect(resetFields(seeded, 'lead', ['effort'])).toEqual({ members: {} });
  });

  it('drops every CLI-bound override when the agent changes', () => {
    const before: TeamOverlay = {
      members: { lead: { settings: { model: 'opus', approval: 'auto' } } },
    };

    expect(withMemberSettings(before, 'lead', { agent: 'codex' })).toEqual({
      members: { lead: { settings: { agent: 'codex', approval: 'auto' } } },
    });
  });

  it('replaces and returns the pool, and counts it as one override', () => {
    const pooled = withMemberPool({}, 'lead', []);
    expect(pooled.members?.lead?.pool).toEqual([]);
    expect(memberOverlayBadges(pooled, 'lead')).toEqual({
      overrides: 1,
      notes: false,
    });
    expect(withMemberPool(pooled, 'lead', undefined)).toEqual({ members: {} });
  });

  it('restores every setting and the pool, keeping the extra instructions and other members', () => {
    const before: TeamOverlay = {
      members: {
        lead: {
          settings: { agent: 'codex', effort: 'low' },
          pool: [],
          extraInstructions: 'Use the staging DB.',
        },
        reviewer: { settings: { effort: 'max' } },
      },
    };

    expect(withTeamSettings(before, 'lead')).toEqual({
      members: {
        lead: { extraInstructions: 'Use the staging DB.' },
        reviewer: { settings: { effort: 'max' } },
      },
    });
    expect(
      withTeamSettings({ members: { lead: { pool: [] } } }, 'lead'),
    ).toEqual({ members: {} });
  });
});
