import type {
  InstructionBlock,
  TeamAgentPoolMember,
  TeamMember,
  TeamOverlay,
  TeamOverlayAgentDefaults,
  TeamOverlayMember,
  TeamOverlayMemberSettings,
} from '../autogenerated';

/** The Model-group fields a project may override on a member, `agent` aside. */
export const OVERLAY_MODEL_FIELDS = [
  'model',
  'effort',
  'contextWindow',
  'modelParameters',
  'autoCompactPercent',
  'approval',
  'configDir',
] as const satisfies readonly (keyof TeamOverlayAgentDefaults)[];

export type OverlayModelField = (typeof OVERLAY_MODEL_FIELDS)[number];
export type OverlaySettingsField = OverlayModelField | 'agent';

const CLI_BOUND_FIELDS: readonly OverlayModelField[] =
  OVERLAY_MODEL_FIELDS.filter((field) => field !== 'approval');

const MODEL_BOUND_FIELDS = ['contextWindow', 'modelParameters'] as const;

function forModel<T extends { model?: string }>(
  target: T,
  layers: readonly (TeamOverlayAgentDefaults | undefined)[],
): T {
  const model = layers.reduce<string | undefined>(
    (picked, layer) => layer?.model ?? picked,
    undefined,
  );
  if (model === undefined || model === target.model) {
    return target;
  }
  const out = { ...target };
  for (const field of MODEL_BOUND_FIELDS) {
    delete (out as Record<string, unknown>)[field];
  }
  return out;
}

function withDefaults<T extends object>(
  target: T,
  values: TeamOverlayAgentDefaults | undefined,
): T {
  if (!values) {
    return target;
  }
  const out = { ...target } as Record<string, unknown>;
  for (const field of OVERLAY_MODEL_FIELDS) {
    if (values[field] !== undefined) {
      out[field] = values[field];
    }
  }
  return out as T;
}

/**
 * The member a run in the project runs: member override, then `allMembers`
 * for its CLI, then the team's value; an agent override starts its Model group
 * over. Extra instructions are left apart, for the sheet to show on their own.
 *
 * TWIN PARSER: `applyTeamOverlay` (`effectiveMember`) in
 * `apps/daemon/src/v1/teams/utils/team-overlay.ts`.
 */
export function effectiveMemberOf(
  member: TeamMember,
  overlay: TeamOverlay,
): TeamMember {
  const own = overlay.members?.[member.id];
  const settings = own?.settings;
  const agent = settings?.agent ?? member.agent;
  let out: TeamMember = { ...member, agent };
  if (agent !== member.agent) {
    for (const field of CLI_BOUND_FIELDS) {
      delete out[field];
    }
  }
  out = forModel(out, [overlay.allMembers?.[agent]]);
  out = withDefaults(out, overlay.allMembers?.[agent]);
  if (settings) {
    out = forModel(out, [settings]);
    out = withDefaults(out, settings);
  }
  if (own?.pool !== undefined) {
    out.pool = own.pool;
  } else if (member.pool !== undefined) {
    out.pool = member.pool.map((entry): TeamAgentPoolMember =>
      withDefaults(
        forModel({ ...entry }, [overlay.allMembers?.[entry.agent]]),
        overlay.allMembers?.[entry.agent],
      ),
    );
  }
  return out;
}

function withOwn(
  overlay: TeamOverlay,
  memberId: string,
  next: (own: TeamOverlayMember) => TeamOverlayMember,
): TeamOverlay {
  const members = { ...overlay.members };
  const updated = next({ ...members[memberId] });
  if (
    updated.settings !== undefined &&
    Object.keys(updated.settings).length === 0
  ) {
    delete updated.settings;
  }
  if (updated.extraInstructions === '') {
    delete updated.extraInstructions;
  }
  if (Object.keys(updated).length === 0) {
    delete members[memberId];
  } else {
    members[memberId] = updated;
  }
  return { ...overlay, members };
}

/**
 * Write a sheet patch as the member's override. A changed agent replaces the
 * whole Model group, so every CLI-bound override goes with it.
 */
export function withMemberSettings(
  overlay: TeamOverlay,
  memberId: string,
  patch: Partial<Pick<TeamMember, OverlaySettingsField>>,
): TeamOverlay {
  return withOwn(overlay, memberId, (own) => {
    let settings: TeamOverlayMemberSettings = { ...own.settings };
    if (patch.agent !== undefined) {
      settings = { agent: patch.agent, approval: settings.approval };
      if (settings.approval === undefined) {
        delete settings.approval;
      }
    }
    for (const field of OVERLAY_MODEL_FIELDS) {
      if (field in patch) {
        const value = patch[field];
        if (value === undefined) {
          delete settings[field];
        } else {
          (settings as Record<string, unknown>)[field] = value;
        }
      }
    }
    return { ...own, settings };
  });
}

/**
 * Seed overrides of `fields` with the values the team (and `allMembers`)
 * gives the member now; a field the team leaves unset has nothing to seed.
 */
export function overrideFields(
  overlay: TeamOverlay,
  member: TeamMember,
  fields: readonly OverlaySettingsField[],
): TeamOverlay {
  const team = effectiveMemberOf(member, { ...overlay, members: {} });
  return withOwn(overlay, member.id, (own) => {
    const settings: Record<string, unknown> = { ...own.settings };
    for (const field of fields) {
      const value = team[field];
      if (value !== undefined) {
        settings[field] = value;
      }
    }
    return { ...own, settings: settings as TeamOverlayMemberSettings };
  });
}

/** Back to the team's value for `fields` (the whole Model group when `agent` is among them). */
export function resetFields(
  overlay: TeamOverlay,
  memberId: string,
  fields: readonly OverlaySettingsField[],
): TeamOverlay {
  return withOwn(overlay, memberId, (own) => {
    if (fields.includes('agent')) {
      return { ...own, settings: {} };
    }
    const settings = { ...own.settings };
    for (const field of fields) {
      delete settings[field];
    }
    return { ...own, settings };
  });
}

/** Whether the member's own override names `field` — set, or an agent switch that resets it. */
export function isOverridden(
  overlay: TeamOverlay,
  memberId: string,
  field: OverlaySettingsField,
): boolean {
  const settings = overlay.members?.[memberId]?.settings;
  if (settings === undefined) {
    return false;
  }
  return settings[field] !== undefined || settings.agent !== undefined;
}

/** Every Model setting and the pool back to the team's; the member's extra instructions stay. */
export function withTeamSettings(
  overlay: TeamOverlay,
  memberId: string,
): TeamOverlay {
  return withOwn(overlay, memberId, (own) => {
    const next = { ...own };
    delete next.settings;
    delete next.pool;
    return next;
  });
}

/** `pool` undefined goes back to the team's pool. */
export function withMemberPool(
  overlay: TeamOverlay,
  memberId: string,
  pool: TeamAgentPoolMember[] | undefined,
): TeamOverlay {
  return withOwn(overlay, memberId, (own) => {
    const next = { ...own };
    if (pool === undefined) {
      delete next.pool;
    } else {
      next.pool = pool;
    }
    return next;
  });
}

export function withExtraInstructions(
  overlay: TeamOverlay,
  memberId: string,
  text: string,
): TeamOverlay {
  return withOwn(overlay, memberId, (own) => ({
    ...own,
    extraInstructions: text,
  }));
}

export function withOverlayBlocks(
  overlay: TeamOverlay,
  instructionBlocks: InstructionBlock[],
): TeamOverlay {
  return { ...overlay, instructionBlocks };
}

/** What a member's card says it has in the project: "N overrides", project notes. */
export function memberOverlayBadges(
  overlay: TeamOverlay,
  memberId: string,
): { overrides: number; notes: boolean } {
  const own = overlay.members?.[memberId];
  return {
    overrides:
      Object.keys(own?.settings ?? {}).length +
      (own?.pool === undefined ? 0 : 1),
    notes: (own?.extraInstructions ?? '').trim() !== '',
  };
}

/** The overlay with one orphan entry (`members.<id>`) removed. */
export function withoutOrphan(
  overlay: TeamOverlay,
  orphan: string,
): TeamOverlay {
  const [section, ...rest] = orphan.split('.');
  const id = rest.join('.');
  if (section === 'members') {
    const members = { ...overlay.members };
    delete members[id];
    return { ...overlay, members };
  }
  return overlay;
}
