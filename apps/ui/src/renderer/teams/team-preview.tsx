import '@xyflow/react/dist/style.css';

import {
  ReactFlow,
  ReactFlowProvider,
  useNodesInitialized,
  useNodesState,
  useReactFlow,
} from '@xyflow/react';
import { Maximize2, Minus, Plus, Scan } from 'lucide-react';
import { useEffect, useMemo, useState } from 'react';

import type { Team } from '../autogenerated';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import { EDGE_TYPES, NODE_TYPES } from './flow-types';
import { autoLayout, type GraphFlowNode, toFlow } from './graph-doc';
import {
  type GraphPreview,
  GraphPreviewContext,
  type PreviewMark,
} from './graph-preview-context';

const PRO_OPTIONS = { hideAttribution: true };
/** Fit the whole graph, never magnified past 1:1 — a two-node team stays small. */
const FIT = { padding: 0.12, maxZoom: 1 };
const NO_MARKS: ReadonlyMap<string, PreviewMark> = new Map();
const ZOOM_STEP = { duration: 150 };

/**
 * How the graph answers the pointer: `none` not at all; `embedded` pans on a
 * drag and zooms on a pinch or the zoom buttons, leaving the wheel to the
 * page it sits in (a chat card); `full` also zooms on the wheel (a dialog).
 */
export type PreviewInteraction = 'none' | 'embedded' | 'full';

export interface TeamPreviewProps {
  team: Team;
  /** Each node's standing against the team a proposal replaces. */
  marks?: ReadonlyMap<string, PreviewMark>;
  interaction?: PreviewInteraction;
  /** Offered beside the zoom buttons: open the graph in a larger view. */
  onExpand?: () => void;
  /** The expand button's accessible name; it should say what the graph shows. */
  expandLabel?: string;
  className?: string;
}

/**
 * A team drawn read-only with the builder's own node and wire components:
 * nothing can be dragged, connected, selected or deleted.
 *
 * Laid out by ELK from what each card MEASURES (see `autoLayout`): the nodes
 * are drawn once unseen, measured, placed, and only then shown, so a tall card
 * never overlaps the one below. A skeleton stands in meanwhile.
 *
 * The default export, so a chat card can `lazy()` it: this module is what
 * pulls `@xyflow/react` and `elkjs` in, and neither belongs in the chat bundle.
 */
export default function TeamPreview(
  props: TeamPreviewProps,
): React.JSX.Element {
  return (
    <ReactFlowProvider>
      <PreviewCanvas {...props} />
    </ReactFlowProvider>
  );
}

function PreviewCanvas({
  team,
  marks = NO_MARKS,
  interaction = 'none',
  onExpand,
  expandLabel = 'Open a larger view',
  className,
}: TeamPreviewProps): React.JSX.Element {
  const flow = useMemo(() => toFlow(team), [team]);
  const [nodes, setNodes, onNodesChange] = useNodesState<GraphFlowNode>(
    flow.nodes,
  );
  // An empty graph has nothing to measure, and React Flow never reports it
  // measured, so it starts laid out.
  const [phase, setPhase] = useState<'measuring' | 'laid-out' | 'failed'>(() =>
    flow.nodes.length === 0 ? 'laid-out' : 'measuring',
  );
  const measured = useNodesInitialized();
  const { getNodes, fitView, zoomIn, zoomOut } = useReactFlow();
  const interactive = interaction !== 'none';
  const preview = useMemo<GraphPreview>(() => ({ marks }), [marks]);

  useEffect(() => {
    if (phase !== 'measuring' || !measured) {
      return;
    }
    let cancelled = false;
    const sizes = new Map(
      getNodes().map((node) => [
        node.id,
        node.measured?.width !== undefined && node.measured.height !== undefined
          ? { width: node.measured.width, height: node.measured.height }
          : undefined,
      ]),
    );
    autoLayout(team, sizes).then(
      (positions) => {
        if (cancelled) {
          return;
        }
        setNodes((current) =>
          current.map((node) => ({
            ...node,
            position: positions[node.id] ?? node.position,
          })),
        );
        setPhase('laid-out');
      },
      () => {
        if (!cancelled) {
          setPhase('failed');
        }
      },
    );
    return () => {
      cancelled = true;
    };
  }, [phase, measured, getNodes, team, setNodes]);

  // Fitted a frame after the new positions are applied, or it fits the
  // pre-layout pile.
  useEffect(() => {
    if (phase !== 'laid-out') {
      return;
    }
    const frame = requestAnimationFrame(() => {
      void fitView(FIT);
    });
    return () => cancelAnimationFrame(frame);
  }, [phase, fitView]);

  if (phase === 'failed') {
    return (
      <div
        className={cn(
          'flex h-full w-full items-center justify-center text-xs text-muted-foreground',
          className,
        )}>
        Couldn’t draw the preview
      </div>
    );
  }
  return (
    <div
      data-slot="team-preview"
      data-phase={phase}
      className={cn('relative h-full w-full', className)}>
      {phase === 'measuring' ? (
        <span
          aria-hidden="true"
          className="skeleton-pulse absolute inset-0 rounded-md bg-muted-foreground/10"
        />
      ) : null}
      <GraphPreviewContext.Provider value={preview}>
        <div aria-hidden="true" className="h-full w-full">
          <ReactFlow
            className={cn(phase === 'measuring' && 'opacity-0')}
            nodes={nodes}
            edges={flow.edges}
            nodeTypes={NODE_TYPES}
            edgeTypes={EDGE_TYPES}
            onNodesChange={onNodesChange}
            nodesDraggable={false}
            nodesConnectable={false}
            nodesFocusable={false}
            edgesFocusable={false}
            elementsSelectable={false}
            deleteKeyCode={null}
            panOnDrag={interactive}
            panOnScroll={false}
            zoomOnScroll={interaction === 'full'}
            zoomOnPinch={interactive}
            zoomOnDoubleClick={false}
            preventScrolling={interaction === 'full'}
            minZoom={0.1}
            maxZoom={2}
            proOptions={PRO_OPTIONS}
          />
        </div>
      </GraphPreviewContext.Provider>
      {interactive && phase === 'laid-out' ? (
        <div
          data-slot="team-preview-zoom"
          className="absolute right-2 bottom-2 flex gap-1">
          <Button
            type="button"
            variant="outline"
            size="icon"
            className="size-7"
            aria-label="Zoom out"
            title="Zoom out"
            onClick={() => void zoomOut(ZOOM_STEP)}>
            <Minus className="size-3.5" />
          </Button>
          <Button
            type="button"
            variant="outline"
            size="icon"
            className="size-7"
            aria-label="Zoom in"
            title="Zoom in"
            onClick={() => void zoomIn(ZOOM_STEP)}>
            <Plus className="size-3.5" />
          </Button>
          <Button
            type="button"
            variant="outline"
            size="icon"
            className="size-7"
            aria-label="Fit the whole graph"
            title="Fit the whole graph"
            onClick={() => void fitView({ ...FIT, ...ZOOM_STEP })}>
            <Scan className="size-3.5" />
          </Button>
          {onExpand === undefined ? null : (
            <Button
              type="button"
              variant="outline"
              size="sm"
              className="h-7 gap-1 px-2 text-xs has-[>svg]:px-2"
              aria-label={expandLabel}
              title="Open a larger view"
              onClick={onExpand}>
              <Maximize2 className="size-3.5" />
              Expand
            </Button>
          )}
        </div>
      ) : null}
    </div>
  );
}
