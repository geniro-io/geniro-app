import type { AgentKind } from '../autogenerated';
import { shortenPath } from '../chats/directory-select';
import type { MemberProblem } from './member-problems';
import { SERVER_REPEAT_TEXT } from './member-problems';
import type { TeamProblem, TeamProblemMember } from './warning-pill';

/** One member's finding, with whom it is about. */
export interface MemberFinding {
  member: TeamProblemMember;
  problem: MemberProblem;
}

interface Group {
  key: string;
  first: MemberProblem;
  members: TeamProblemMember[];
  servers: string[];
}

/**
 * The same finding about one CLI account is one problem, whoever it reaches:
 * the members sharing a profile see its MCP servers alike, so twenty servers
 * across five members are one row naming the five, not a hundred. A server
 * finding groups by its kind and account, every other by its words too.
 */
function groupKeyOf(problem: MemberProblem): string {
  const account = `${problem.agent ?? ''}:${problem.configDir ?? ''}`;
  return problem.kind in SERVER_REPEAT_TEXT && problem.servers.length > 0
    ? `servers:${problem.kind}:${problem.level}:${account}`
    : `${problem.kind}:${problem.level}:${account}:${problem.message}`;
}

/** "Claude Code · default profile", or the profile folder it uses. */
function accountOf(
  problem: MemberProblem,
  agentLabel: (agent: AgentKind) => string,
): string | undefined {
  if (problem.agent === null) {
    return undefined;
  }
  const profile =
    problem.configDir === null
      ? 'default profile'
      : shortenPath(problem.configDir);
  return `${agentLabel(problem.agent)} · ${profile}`;
}

function messageOf(group: Group): string {
  const { first, servers } = group;
  if (servers.length <= 1 || !(first.kind in SERVER_REPEAT_TEXT)) {
    return group.members.length > 1
      ? first.message.replace(/ for this member\.$/, '.')
      : first.message;
  }
  return `${servers.length} MCP servers ${SERVER_REPEAT_TEXT[first.kind]}.`;
}

/**
 * The members' findings as the rows the "need setup" pill lists: one per
 * distinct problem, naming every member it reaches, errors first.
 */
export function groupMemberFindings(
  findings: readonly MemberFinding[],
  agentLabel: (agent: AgentKind) => string,
  fixOf: (problem: MemberProblem) => TeamProblem['fix'],
): TeamProblem[] {
  const groups = new Map<string, Group>();
  for (const { member, problem } of findings) {
    const key = groupKeyOf(problem);
    const group = groups.get(key);
    if (group === undefined) {
      groups.set(key, {
        key,
        first: problem,
        members: [member],
        servers: [...problem.servers],
      });
      continue;
    }
    if (!group.members.some((entry) => entry.id === member.id)) {
      group.members.push(member);
    }
    for (const server of problem.servers) {
      if (!group.servers.includes(server)) {
        group.servers.push(server);
      }
    }
  }
  return [...groups.values()]
    .map((group): TeamProblem => {
      const many = group.servers.length > 1;
      const fix = fixOf(many ? { ...group.first, server: null } : group.first);
      return {
        key: group.key,
        members: group.members,
        message: messageOf(group),
        level: group.first.level,
        account: accountOf(group.first, agentLabel),
        details: many ? group.servers : undefined,
        ...(fix === undefined ? {} : { fix }),
      };
    })
    .sort((a, b) => Number(b.level === 'error') - Number(a.level === 'error'));
}
