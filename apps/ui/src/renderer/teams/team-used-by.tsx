import { useEffect, useState } from 'react';

import type { TeamOverlayScope, TeamsApi } from '../autogenerated';

/** The projects a team's overlay list names, read once per team. */
function useTeamScopes(
  api: TeamsApi | null,
  slug: string | null,
  readKey: unknown = null,
): { scopes: TeamOverlayScope[]; failed: boolean } {
  const [scopes, setScopes] = useState<TeamOverlayScope[]>([]);
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    setScopes([]);
    setFailed(false);
    if (api === null || slug === null) {
      return;
    }
    let stale = false;
    api
      .listTeamOverlays({ slug })
      .then(({ scopes: listed }) => {
        if (!stale) {
          setScopes(listed);
        }
      })
      .catch(() => {
        if (!stale) {
          setFailed(true);
        }
      });
    return () => {
      stale = true;
    };
  }, [api, slug, readKey]);
  return { scopes, failed };
}

/**
 * Which projects run this team by default — a change here reaches all of
 * them. Each opens its project's page, where that project's overrides of the
 * team live; nothing about a project is edited on the team's page.
 */
export function TeamUsedBy({
  api,
  slug,
  readKey,
  onOpenProject,
}: {
  api: TeamsApi | null;
  slug: string;
  /** Changes when the list should be read again — the screen coming back into view. */
  readKey?: unknown;
  onOpenProject?: (projectId: string) => void;
}): React.JSX.Element | null {
  const { scopes, failed } = useTeamScopes(api, slug, readKey);
  const active = scopes.filter((scope) => scope.active);
  if (failed) {
    return (
      <p data-slot="team-used-by" className="m-0 text-sm text-muted-foreground">
        Could not read which projects use this team.
      </p>
    );
  }
  if (active.length === 0) {
    return null;
  }
  return (
    <p
      data-slot="team-used-by"
      className="m-0 flex flex-wrap items-center gap-x-1.5 gap-y-1 text-sm text-muted-foreground">
      <span>Used by</span>
      {active.map((scope, index) => (
        <span key={scope.projectId} className="flex items-center">
          {onOpenProject === undefined ? (
            <span className="text-foreground">{scope.projectName}</span>
          ) : (
            <button
              type="button"
              className="rounded-control text-sm text-foreground underline-offset-2 hover:underline focus-visible:underline focus-visible:outline-none"
              title={`Open ${scope.projectName} — its overrides of this team are on its page`}
              onClick={() => onOpenProject(scope.projectId)}>
              {scope.projectName}
            </button>
          )}
          {index < active.length - 1 ? ',' : null}
        </span>
      ))}
    </p>
  );
}

/** In a team's delete confirm: the projects that default to it or keep overrides of it. */
export function TeamDeleteProjects({
  api,
  slug,
}: {
  api: TeamsApi | null;
  slug: string | null;
}): React.JSX.Element | null {
  const { scopes: listed, failed } = useTeamScopes(api, slug);
  const scopes = listed.filter((scope) => scope.active || scope.hasOverlay);
  if (failed) {
    return (
      <p data-slot="team-delete-projects">
        Could not read which projects use it: any project’s overrides of it are
        removed too (backed up first).
      </p>
    );
  }
  if (scopes.length === 0) {
    return null;
  }
  return (
    <p data-slot="team-delete-projects">
      Used by {scopes.map((scope) => scope.projectName).join(', ')}: their
      overrides of it are removed too (backed up first), and a project that
      defaults to it needs a new default.
    </p>
  );
}
