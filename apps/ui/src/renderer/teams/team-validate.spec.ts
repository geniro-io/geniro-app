import { describe, expect, it } from 'vitest';

import type { Team } from '../autogenerated';
import { validateTeam } from './team-validate';

const member = (id: string): Team['members'][number] => ({
  id,
  name: id.toUpperCase(),
  agent: 'claude',
  approval: 'auto',
});

function team(fields: Partial<Team> = {}): Team {
  return {
    name: 'T',
    mode: 'lead',
    members: [member('lead'), member('qa')],
    triggers: [{ kind: 'first-message', member: 'lead' }],
    instructionBlocks: [],
    ...fields,
  };
}

const codes = (issues: { code: string }[]): string[] =>
  issues.map((issue) => issue.code);

describe('validateTeam (twin of the daemon validator)', () => {
  it('accepts a team with members, one trigger on a member and unique ids', () => {
    expect(validateTeam(team())).toEqual({ errors: [], warnings: [] });
  });

  it('refuses a team with no members', () => {
    expect(
      codes(validateTeam(team({ members: [], triggers: [] })).errors),
    ).toEqual(['TEAM_NO_MEMBERS', 'TEAM_TRIGGER_COUNT']);
  });

  it('refuses two members sharing an id, naming it', () => {
    const result = validateTeam(
      team({ members: [member('lead'), member('lead')] }),
    );
    expect(result.errors).toEqual([
      expect.objectContaining({
        code: 'TEAM_DUPLICATE_MEMBER',
        message: expect.stringContaining('lead'),
      }),
    ]);
  });

  it('refuses no trigger, two triggers, and a trigger naming no member', () => {
    expect(codes(validateTeam(team({ triggers: [] })).errors)).toEqual([
      'TEAM_TRIGGER_COUNT',
    ]);
    expect(
      codes(
        validateTeam(
          team({
            triggers: [
              { kind: 'first-message', member: 'lead' },
              { kind: 'first-message', member: 'qa' },
            ],
          }),
        ).errors,
      ),
    ).toEqual(['TEAM_TRIGGER_COUNT']);
    expect(
      codes(
        validateTeam(
          team({ triggers: [{ kind: 'first-message', member: 'ghost' }] }),
        ).errors,
      ),
    ).toEqual(['TEAM_TRIGGER_UNKNOWN']);
  });

  it('refuses two blocks sharing an id', () => {
    const block = { id: 'b', title: 'B', text: '', audience: 'everyone' };
    expect(
      codes(validateTeam(team({ instructionBlocks: [block, block] })).errors),
    ).toEqual(['TEAM_DUPLICATE_BLOCK']);
  });

  it('warns, never refuses, about an audience id that is no member, naming the block', () => {
    const result = validateTeam(
      team({
        instructionBlocks: [
          { id: 'b1', title: 'Checks', text: '', audience: ['qa', 'ghost'] },
          { id: 'b2', title: '', text: '', audience: 'everyone' },
        ],
      }),
    );
    expect(result.errors).toEqual([]);
    expect(result.warnings).toEqual([
      expect.objectContaining({
        code: 'TEAM_AUDIENCE_UNKNOWN',
        blockId: 'b1',
        message: expect.stringContaining("'Checks' is addressed to 'ghost'"),
      }),
    ]);
  });

  it('carries the stage rules: a refusal and a responsible warning', () => {
    const result = validateTeam(
      team({
        stages: [
          { id: 'a', title: 'A', goal: 'a', next: ['b'], responsible: ['x'] },
          { id: 'b', title: 'B', goal: 'b', next: ['a'] },
        ],
      }),
    );
    expect(codes(result.errors)).toEqual(['STAGE_NO_START']);
    expect(codes(result.warnings)).toEqual(['STAGE_RESPONSIBLE_UNKNOWN']);
  });
});
