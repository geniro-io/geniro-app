// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  DEV_TEAM_VERSIONS,
  EDITED_SINCE_LAST_RUN,
  NEVER_RUN_VERSIONS,
} from '../__fixtures__/team-versions';
import type { TeamVersionsDto } from '../autogenerated';
import { TeamVersionsDialog } from './team-versions-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  document.body.innerHTML = '';
});

function render(
  props: Partial<Parameters<typeof TeamVersionsDialog>[0]> & {
    data: TeamVersionsDto | null;
  },
): {
  onClose: ReturnType<typeof vi.fn>;
  onRetry: ReturnType<typeof vi.fn>;
} {
  const onClose = vi.fn();
  const onRetry = vi.fn();
  act(() => {
    root.render(
      <TeamVersionsDialog
        open
        onClose={onClose}
        teamName="Dev Team"
        loading={false}
        error={null}
        onRetry={onRetry}
        {...props}
      />,
    );
  });
  return { onClose, onRetry };
}

function rows(slot: string): HTMLElement[] {
  return [
    ...document.body.querySelectorAll<HTMLElement>(`[data-slot="${slot}"]`),
  ];
}

function press(label: string): void {
  const button = [...document.body.querySelectorAll('button')].find(
    (candidate) =>
      candidate.getAttribute('aria-label') === label ||
      candidate.textContent === label,
  );
  if (!button) {
    throw new Error(`no button ${label}`);
  }
  act(() => button.click());
}

describe('TeamVersionsDialog', () => {
  it('draws one card per version with its runs, average cost and line counts, under the totals', () => {
    render({ data: DEV_TEAM_VERSIONS });

    const versionRows = rows('version-row');
    expect(versionRows.map((row) => row.textContent)).toEqual([
      expect.stringContaining('b7c1e09a'),
      expect.stringContaining('5d06e8b7'),
      expect.stringContaining('41aa90c3'),
      expect.stringContaining('No recorded graph'),
    ]);
    expect(versionRows[0]!.textContent).toContain('current');
    expect(versionRows[0]!.textContent).toContain('#2');
    expect(versionRows[0]!.textContent).toContain('2 runs');
    expect(versionRows[0]!.textContent).toContain('$6.20');
    expect(versionRows[0]!.textContent).toContain('+9−2');
    expect(versionRows[1]!.textContent).toContain('≈$3.00');
    const summary = rows('versions-summary')[0]!.textContent;
    expect(summary).toContain('Runs7');
    expect(summary).toContain('Versions3');
    expect(summary).toContain('≈$3.73');
  });

  it('says why a row has no diff or no cost, as text', () => {
    render({ data: DEV_TEAM_VERSIONS });

    const [, first, inferred, copyless] = rows('version-row');
    expect(first!.textContent).toContain('first recorded version');
    expect(inferred!.textContent).toContain('not numbered: graph copied later');
    expect(inferred!.textContent).toContain('no cost reported');
    expect(copyless!.textContent).toContain('these runs kept no graph copy');
  });

  it('shows a version’s git diff on a press, and goes back to the list', () => {
    render({ data: DEV_TEAM_VERSIONS });

    press('Show version b7c1e09a');

    const diff = document.body.querySelector('[data-slot="unified-diff"]');
    expect(diff?.textContent).toContain('--- a/dev-team.team.yaml');
    expect(diff?.textContent).toContain('+maxActiveTurns: 3');
    expect(rows('version-row')).toEqual([]);

    press('All versions');
    expect(rows('version-row')).toHaveLength(4);
  });

  it('opens the diff from a press anywhere on the card', () => {
    render({ data: DEV_TEAM_VERSIONS });

    const figures =
      rows('version-row')[0]!.querySelector<HTMLElement>('.tabular-nums');
    act(() => figures!.click());

    expect(
      document.body.querySelector('[data-slot="unified-diff"]'),
    ).not.toBeNull();
  });

  it('offers no press on a version whose graph was never recorded', () => {
    render({ data: DEV_TEAM_VERSIONS });

    const [, , inferred, copyless] = rows('version-row');
    for (const row of [inferred!, copyless!]) {
      expect(row.querySelector('button')).toBeNull();
      act(() => row.querySelector<HTMLElement>('span')!.click());
      expect(
        document.body.querySelector('[data-slot="version-view"]'),
      ).toBeNull();
    }
  });

  it('opens the first version too, saying there is nothing to compare it with', () => {
    render({ data: DEV_TEAM_VERSIONS });

    press('Show version 5d06e8b7');

    expect(
      document.body.querySelector('[data-slot="version-view"]')?.textContent,
    ).toContain('first recorded version: there is nothing to compare it with');
  });

  it('restores a version after a confirming second press, then returns to the table', async () => {
    const onRestore = vi.fn(async () => undefined);
    render({ data: DEV_TEAM_VERSIONS, onRestore });
    press('Show version 5d06e8b7');

    press('Restore this version');
    expect(onRestore).not.toHaveBeenCalled();
    await act(async () => {
      [...document.body.querySelectorAll('button')]
        .find((button) => button.textContent === 'Restore #1?')!
        .click();
    });

    expect(onRestore).toHaveBeenCalledWith(DEV_TEAM_VERSIONS.versions[1]);
    expect(rows('version-row')).toHaveLength(4);
  });

  it('shows why a restore failed and stays on the version', async () => {
    const onRestore = vi.fn(async () => {
      throw new Error('changed since this copy was read');
    });
    render({ data: DEV_TEAM_VERSIONS, onRestore });
    press('Show version 5d06e8b7');

    press('Restore this version');
    await act(async () => {
      [...document.body.querySelectorAll('button')]
        .find((button) => button.textContent === 'Restore #1?')!
        .click();
    });

    expect(document.body.querySelector('[role="alert"]')?.textContent).toBe(
      'changed since this copy was read',
    );
    expect(
      document.body.querySelector('[data-slot="version-view"]'),
    ).not.toBeNull();
  });

  it('offers no restore of the current version', () => {
    render({ data: DEV_TEAM_VERSIONS, onRestore: vi.fn() });

    press('Show version b7c1e09a');

    expect(document.body.textContent).not.toContain('Restore this version');
  });

  it('holds the restore back, saying why, while it cannot start', () => {
    render({
      data: DEV_TEAM_VERSIONS,
      onRestore: vi.fn(),
      restoreBlockedReason: 'The chat’s agent is working on this team.',
    });

    press('Show version 5d06e8b7');

    const restore = [...document.body.querySelectorAll('button')].find(
      (button) => button.textContent === 'Restore this version',
    );
    expect(restore?.disabled).toBe(true);
    expect(document.body.textContent).toContain(
      'The chat’s agent is working on this team.',
    );
  });

  it('forgets the open diff when the dialog closes', () => {
    const { onClose } = render({ data: DEV_TEAM_VERSIONS });
    press('Show version b7c1e09a');

    press('Close');
    expect(onClose).toHaveBeenCalledTimes(1);
    render({ data: DEV_TEAM_VERSIONS });

    expect(rows('version-row')).toHaveLength(4);
  });

  it('shows a graph edited since its last run as the current row, not run yet, with its diff and no restore', () => {
    render({ data: EDITED_SINCE_LAST_RUN, onRestore: vi.fn() });

    const edited = rows('version-row')[0]!;
    expect(edited.textContent).toContain('c3a9e1f0');
    expect(edited.textContent).toContain('current');
    expect(edited.textContent).toContain('not run yet');
    expect(edited.textContent).toContain('New version');
    expect(edited.textContent).toContain('+1−1');
    expect(rows('version-row')[1]!.textContent).not.toContain('current');

    press('Show version c3a9e1f0');
    expect(
      document.body.querySelector('[data-slot="unified-diff"]')?.textContent,
    ).toContain('+maxActiveTurns: 4');
    expect(document.body.textContent).not.toContain('Restore this version');
  });

  it('offers to restore the version that was current before the edit', () => {
    render({ data: EDITED_SINCE_LAST_RUN, onRestore: vi.fn() });

    press('Show version b7c1e09a');

    expect(document.body.textContent).toContain('Restore this version');
  });

  it('focuses the list on open, so no card wears a focus ring until Tab reaches it', () => {
    render({ data: DEV_TEAM_VERSIONS });

    expect(document.activeElement?.getAttribute('aria-label')).toBe(
      'Versions, newest first',
    );
  });

  it('says a team that never ran has no versions yet', () => {
    render({ data: NEVER_RUN_VERSIONS });

    expect(document.body.textContent).toContain(
      "This team hasn't run yet. Versions appear after its first run.",
    );
    expect(rows('version-row')).toEqual([]);
  });

  it('offers a retry when the read failed', () => {
    const { onRetry } = render({ data: null, error: 'boom' });

    const alert = document.body.querySelector('[role="alert"]');
    expect(alert?.textContent).toContain("Couldn't load versions");
    const retry = [...alert!.querySelectorAll('button')].find(
      (button) => button.textContent === 'Retry',
    );
    act(() => retry!.click());
    expect(onRetry).toHaveBeenCalledTimes(1);
  });

  it('marks the first load busy', () => {
    render({ data: null, loading: true });

    expect(document.body.querySelector('[aria-busy="true"]')).not.toBeNull();
  });
});
