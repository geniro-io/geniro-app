import { Plus, Upload, Users } from 'lucide-react';

import type { TeamSummaryDto as TeamSummary } from '../autogenerated';
import { EmptyState } from '../components/empty-state';
import { ErrorText } from '../components/error-text';
import { Button } from '../components/ui/button';
import { TeamCard } from './team-card';

/**
 * The library of teams: a grid of cards, one per `*.team.yaml`, under a header
 * that creates or imports one. `summaries` is null until the first read lands.
 */
export function TeamsLibrary({
  summaries,
  error,
  onOpen,
  onDelete,
  onNew,
  onImport,
}: {
  summaries: readonly TeamSummary[] | null;
  error: string | null;
  onOpen: (slug: string) => void;
  onDelete: (summary: TeamSummary) => void;
  onNew: () => void;
  onImport: () => void;
}): React.JSX.Element {
  return (
    <div className="h-full min-h-0 overflow-y-auto">
      <div className="mx-auto flex max-w-[880px] flex-col gap-8 px-4 py-8 sm:px-6">
        <header className="flex flex-wrap items-end gap-x-4 gap-y-3">
          <div className="flex min-w-0 flex-col gap-1">
            <h2 className="flex items-baseline gap-2 text-title font-semibold">
              Teams
              {summaries === null ? null : (
                <span className="text-base font-normal text-muted-foreground tabular-nums">
                  {summaries.length}
                </span>
              )}
            </h2>
            <p className="text-sm text-muted-foreground">
              Agents that work together. Runs start from the Chats page.
            </p>
          </div>
          <div className="ml-auto flex items-center gap-2">
            <Button
              type="button"
              variant="outline"
              className="h-8 gap-2 rounded-control active:scale-[.97] motion-reduce:active:scale-100"
              onClick={onImport}>
              <Upload aria-hidden="true" className="shrink-0" /> Import
            </Button>
            <Button
              type="button"
              className="h-8 gap-2 rounded-control active:scale-[.97] motion-reduce:active:scale-100"
              onClick={onNew}>
              <Plus aria-hidden="true" className="shrink-0" /> New team
            </Button>
          </div>
        </header>

        {error ? <ErrorText>{error}</ErrorText> : null}

        {summaries === null ? (
          <p className="text-sm text-muted-foreground">Loading teams…</p>
        ) : summaries.length === 0 ? (
          <EmptyState
            icon={<Users aria-hidden="true" />}
            actions={
              <>
                <Button
                  type="button"
                  className="h-8 gap-2 rounded-control"
                  onClick={onNew}>
                  <Plus aria-hidden="true" /> New team
                </Button>
                <Button
                  type="button"
                  variant="outline"
                  className="h-8 gap-2 rounded-control"
                  onClick={onImport}>
                  <Upload aria-hidden="true" /> Import
                </Button>
              </>
            }>
            No teams yet. Create one to start composing your agents.
          </EmptyState>
        ) : (
          <ul
            data-slot="team-library"
            className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-3">
            {summaries.map((summary) => (
              <TeamCard
                key={summary.slug}
                summary={summary}
                onOpen={() => onOpen(summary.slug)}
                onDelete={() => onDelete(summary)}
              />
            ))}
          </ul>
        )}
      </div>
    </div>
  );
}
