import { useEffect, useState } from 'react';

import type { FreshSessionBasesDto } from '../autogenerated';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import { currentRunSettings } from '../run-settings';

/** Long enough that passing through the Team tab on the way to another asks nothing. */
const MEASURE_DEBOUNCE_MS = 400;

export interface FreshSessionBasesState {
  /** The daemon's last answer for this team; null before one. */
  bases: FreshSessionBasesDto | null;
  loading: boolean;
  error: string | null;
}

/**
 * What each member's fresh CLI session started with in the saved team's newest
 * runs, measured by the daemon (`POST /v1/teams/:slug/fresh-session-bases`)
 * with the user's custom instructions and reply language read the way a run
 * start reads them. Asked only while `enabled`, again when it turns true and
 * on every settings write; an answer is shown only for the team it measured.
 */
export function useFreshSessionBases(
  api: DaemonApis['teams'] | null,
  slug: string | null,
  enabled: boolean,
): FreshSessionBasesState {
  const [state, setState] = useState<
    FreshSessionBasesState & { forSlug: string | null }
  >({ forSlug: slug, bases: null, loading: false, error: null });
  const [settingsWrites, setSettingsWrites] = useState(0);

  useEffect(() => {
    if (!enabled) {
      return;
    }
    return window.geniro.onSettingsChanged(() =>
      setSettingsWrites((count) => count + 1),
    );
  }, [enabled]);

  useEffect(() => {
    if (api === null || slug === null || !enabled) {
      return;
    }
    let stale = false;
    setState((prev) =>
      prev.forSlug === slug
        ? { ...prev, loading: true }
        : { forSlug: slug, bases: null, loading: true, error: null },
    );
    const timer = setTimeout(() => {
      void (async () => {
        try {
          const settings = await currentRunSettings();
          const bases = await api.measureFreshSessionBases({
            slug,
            measureFreshSessionBasesDto: {
              ...(settings.customInstructions
                ? { customInstructions: settings.customInstructions }
                : {}),
              ...(settings.replyLanguage
                ? { replyLanguage: settings.replyLanguage }
                : {}),
            },
          });
          if (!stale) {
            setState({ forSlug: slug, bases, loading: false, error: null });
          }
        } catch (err) {
          if (!stale) {
            setState((prev) => ({
              ...prev,
              loading: false,
              error: `Not measured: ${describeDaemonError(err)}`,
            }));
          }
        }
      })();
    }, MEASURE_DEBOUNCE_MS);
    return () => {
      stale = true;
      clearTimeout(timer);
    };
  }, [api, slug, enabled, settingsWrites]);

  return state.forSlug === slug
    ? { bases: state.bases, loading: state.loading, error: state.error }
    : { bases: null, loading: false, error: null };
}
