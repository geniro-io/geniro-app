import { useEffect, useState } from 'react';

import type { MemberInstructionSize, Team } from '../autogenerated';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import { currentRunSettings } from '../run-settings';

/** Long enough to collapse typing in the role box into one measurement. */
const MEASURE_DEBOUNCE_MS = 400;

export interface InstructionSizesState {
  /** Each member's measurement, from the last answer; null before one. */
  sizes: ReadonlyMap<string, MemberInstructionSize> | null;
  /** A measurement of the current draft is in flight. */
  loading: boolean;
  /** Why the last measurement failed, when it did. */
  error: string | null;
}

/**
 * The always-on instruction size of every member of the team, measured
 * by the daemon from the draft as it stands — saved or not — and the user's
 * custom instructions and reply language, read at each measurement the way a
 * run start reads them.
 *
 * `snapshot` is the team serialized as Save writes it (`teamSnapshot`), so
 * a selection or other no-op event measures nothing. `enabled` turning
 * true measures again — the builder passes it as "a member is selected and the
 * screen is on view" — and so does main announcing a settings write
 * (`onSettingsChanged`), from the Settings screen or a paired phone. While it
 * is false nothing is asked. An answer is shown only for the
 * team it measured (`teamKey`): member ids repeat across teams.
 */
export function useInstructionSizes(
  api: DaemonApis['teams'] | null,
  teamKey: string,
  snapshot: string,
  enabled: boolean,
): InstructionSizesState {
  const [state, setState] = useState<
    InstructionSizesState & { forKey: string }
  >({ forKey: teamKey, sizes: null, loading: false, error: null });
  const [settingsWrites, setSettingsWrites] = useState(0);

  useEffect(() => {
    if (!enabled) {
      return;
    }
    return window.geniro.onSettingsChanged(() =>
      setSettingsWrites((count) => count + 1),
    );
  }, [enabled]);

  useEffect(() => {
    if (api === null || !enabled) {
      return;
    }
    let stale = false;
    setState((prev) =>
      prev.forKey === teamKey
        ? { ...prev, loading: true }
        : { forKey: teamKey, sizes: null, loading: true, error: null },
    );
    const timer = setTimeout(() => {
      void (async () => {
        try {
          const settings = await currentRunSettings();
          const answer = await api.measureInstructionSizes({
            measureInstructionSizesDto: {
              team: JSON.parse(snapshot) as Team,
              ...(settings.customInstructions
                ? { customInstructions: settings.customInstructions }
                : {}),
              ...(settings.replyLanguage
                ? { replyLanguage: settings.replyLanguage }
                : {}),
            },
          });
          if (!stale) {
            setState({
              forKey: teamKey,
              sizes: new Map(
                answer.members.map((member) => [member.memberId, member]),
              ),
              loading: false,
              error: null,
            });
          }
        } catch (err) {
          if (!stale) {
            // A draft the daemon refuses (a field still being filled in) is
            // ordinary while editing: the last figures stay, marked unsure.
            setState((prev) => ({
              ...prev,
              loading: false,
              error: `Not measured: ${describeDaemonError(err)}`,
            }));
          }
        }
      })();
    }, MEASURE_DEBOUNCE_MS);
    return () => {
      stale = true;
      clearTimeout(timer);
    };
  }, [api, teamKey, snapshot, enabled, settingsWrites]);

  return state.forKey === teamKey
    ? { sizes: state.sizes, loading: state.loading, error: state.error }
    : { sizes: null, loading: false, error: null };
}
