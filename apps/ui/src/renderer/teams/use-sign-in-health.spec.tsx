// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { CliDetection } from '../../shared/contracts';
import type { TeamMember } from '../autogenerated';
import type { SignInProblem } from './member-problems';
import { useSignInHealth } from './use-sign-in-health';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;
const detectClis = vi.fn();

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  detectClis.mockReset();
  (window as unknown as { geniro: unknown }).geniro = { detectClis };
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

function detection(over: Partial<CliDetection>): CliDetection {
  return {
    kind: 'claude',
    found: true,
    path: '/bin/claude',
    version: '1',
    loggedIn: true,
    update: { available: null, latestVersion: null },
    ...over,
  } as CliDetection;
}

const ADA: TeamMember = {
  id: 'ada',
  name: 'Ada',
  agent: 'claude',
  approval: 'auto',
};

async function read(
  members: TeamMember[],
  detections: CliDetection[],
): Promise<Map<string, SignInProblem[]>> {
  detectClis.mockResolvedValue(detections);
  let latest!: Map<string, SignInProblem[]>;
  function Probe(): null {
    latest = useSignInHealth(members, {
      agentLabelOf: (agent) => `<${agent}>`,
    });
    return null;
  }
  await act(async () => {
    root.render(<Probe />);
  });
  return latest;
}

describe('useSignInHealth', () => {
  it('asks main for a reading no older than a minute', async () => {
    await read([ADA], [detection({})]);
    expect(detectClis).toHaveBeenCalledWith({ maxAgeMs: 60_000 });
  });

  it('asks main afresh once a sign-in finishes, so a fixed account clears at once', async () => {
    detectClis.mockResolvedValue([detection({ loggedIn: false })]);
    let latest!: Map<string, SignInProblem[]>;
    function Probe({ refreshKey }: { refreshKey: number }): null {
      latest = useSignInHealth([ADA], { refreshKey });
      return null;
    }
    await act(async () => {
      root.render(<Probe refreshKey={0} />);
    });
    expect(latest.get('ada')?.map((p) => p.kind)).toEqual(['signed_out']);

    detectClis.mockResolvedValue([detection({ loggedIn: true })]);
    await act(async () => {
      root.render(<Probe refreshKey={1} />);
    });

    expect(detectClis).toHaveBeenLastCalledWith(undefined);
    expect(latest.get('ada') ?? []).toEqual([]);
  });

  it('says signed out only for a CLI that answered false', async () => {
    const result = await read([ADA], [detection({ loggedIn: false })]);
    expect(result.get('ada')).toEqual([
      {
        kind: 'signed_out',
        message: 'Signed out of <claude>',
        agent: 'claude',
        configDir: null,
        poolMember: null,
      },
    ]);
  });

  it('says unknown, not signed out, when the answer is null', async () => {
    const result = await read([ADA], [detection({ loggedIn: null })]);
    expect(result.get('ada')?.[0]?.kind).toBe('sign_in_unknown');
  });

  it('says nothing for a CLI that is not found', async () => {
    const result = await read(
      [ADA],
      [detection({ found: false, loggedIn: null })],
    );
    expect(result.size).toBe(0);
  });

  it('reads a profile by its directory and a pool member by its position', async () => {
    const member: TeamMember = {
      ...ADA,
      configDir: '/p/work',
      pool: [{ agent: 'claude', configDir: '/p/spare' }] as TeamMember['pool'],
    };
    const result = await read(
      [member],
      [
        detection({
          loggedIn: false,
          profileLogins: { '/p/work': true, '/p/spare': null },
        }),
      ],
    );
    expect(result.get('ada')).toEqual([
      expect.objectContaining({
        kind: 'sign_in_unknown',
        configDir: '/p/spare',
        poolMember: 2,
      }),
    ]);
  });

  it('says nothing for a profile the detection never probed', async () => {
    const result = await read(
      [{ ...ADA, configDir: '/p/work' }],
      [detection({ loggedIn: false, profileLogins: {} })],
    );
    expect(result.size).toBe(0);
  });
});
