import { useEffect, useMemo, useState } from 'react';

import type { CliDetection } from '../../shared/contracts';
import type { AgentKind, MemberSeat, TeamMember } from '../autogenerated';
import type { SignInProblem } from './member-problems';

/** How old a detection main may answer from, so opening a page spawns no probe. */
export const DETECTION_MAX_AGE_MS = 60_000;

type Seat = MemberSeat;

function seatsOf(member: TeamMember): Seat[] {
  return [
    {
      agent: member.agent,
      configDir: member.configDir ?? null,
      poolMember: null,
    },
    ...(member.pool ?? []).map((entry, index) => ({
      agent: entry.agent,
      configDir: entry.configDir ?? null,
      poolMember: index + 2,
    })),
  ];
}

/** What main's detection says about one seat's sign-in, or null when nothing is wrong or known. */
export function signInOf(
  seat: Seat,
  detections: readonly CliDetection[],
  agentLabelOf: (agent: AgentKind) => string,
): SignInProblem | null {
  const detection = detections.find((entry) => entry.kind === seat.agent);
  if (detection === undefined || !detection.found) {
    return null;
  }
  let loggedIn: boolean | null | undefined;
  if (seat.configDir === null) {
    loggedIn = detection.loggedIn;
  } else if (
    detection.profileLogins !== undefined &&
    Object.hasOwn(detection.profileLogins, seat.configDir)
  ) {
    loggedIn = detection.profileLogins[seat.configDir];
  }
  if (loggedIn === undefined || loggedIn === true) {
    return null;
  }
  const label = agentLabelOf(seat.agent);
  return {
    kind: loggedIn === false ? 'signed_out' : 'sign_in_unknown',
    message:
      loggedIn === false
        ? `Signed out of ${label}`
        : `Cannot tell whether ${label} is signed in`,
    agent: seat.agent,
    configDir: seat.configDir,
    poolMember: seat.poolMember,
  };
}

/**
 * Which members (and pool members) run on a CLI that is signed out, from
 * Electron main's last detection. `null` is unknown and never read as signed
 * out; a CLI that is not found is the daemon's `cli_missing`, not ours.
 * Asks once per mount and again when the set of (agent, profile) pairs
 * changes; a changed `refreshKey` asks afresh, which is how a finished
 * sign-in is seen.
 */
export function useSignInHealth(
  members: readonly TeamMember[],
  options: {
    agentLabelOf?: (agent: AgentKind) => string;
    refreshKey?: number;
  } = {},
): Map<string, SignInProblem[]> {
  const { agentLabelOf = (agent) => agent, refreshKey = 0 } = options;
  const [detections, setDetections] = useState<CliDetection[] | null>(null);
  const pairs = [
    ...new Set(
      members
        .flatMap(seatsOf)
        .map((seat) => `${seat.agent}\u0000${seat.configDir ?? ''}`),
    ),
  ]
    .sort()
    .join('\u0001');

  useEffect(() => {
    if (pairs === '') {
      return;
    }
    let live = true;
    const fresh = refreshKey !== 0;
    window.geniro
      .detectClis(fresh ? undefined : { maxAgeMs: DETECTION_MAX_AGE_MS })
      .then((detected) => {
        if (live) {
          setDetections(detected);
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
  }, [pairs, refreshKey]);

  const seatKey = members
    .map(
      (member) =>
        `${member.id}\u0001${seatsOf(member)
          .map((seat) => `${seat.agent}\u0000${seat.configDir ?? ''}`)
          .join('\u0002')}`,
    )
    .join('\u0003');
  const labelKey = [...new Set(members.flatMap(seatsOf).map((s) => s.agent))]
    .map((agent) => agentLabelOf(agent))
    .join('\u0001');

  return useMemo(() => {
    const byMember = new Map<string, SignInProblem[]>();
    if (detections === null) {
      return byMember;
    }
    for (const member of members) {
      const problems = seatsOf(member)
        .map((seat) => signInOf(seat, detections, agentLabelOf))
        .filter((problem): problem is SignInProblem => problem !== null);
      if (problems.length > 0) {
        byMember.set(member.id, problems);
      }
    }
    return byMember;
    // Keyed on what the members hold and how their CLIs are worded, not on the
    // arrays and closure a caller builds anew each render.
  }, [detections, seatKey, labelKey]);
}
