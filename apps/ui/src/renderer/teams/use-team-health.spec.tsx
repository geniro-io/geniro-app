// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { CliDetection } from '../../shared/contracts';
import type { MemberHealth, TeamHealthDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import {
  type LibraryHealth,
  type TeamHealthState,
  useLibraryHealth,
  useTeamHealth,
} from './use-team-health';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;
const detectClis = vi.fn(async (): Promise<CliDetection[]> => []);

beforeEach(() => {
  vi.useFakeTimers();
  detectClis.mockReset().mockResolvedValue([]);
  (window as unknown as { geniro: unknown }).geniro = { detectClis };
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  vi.useRealTimers();
});

function member(
  status: MemberHealth['status'],
  over: Partial<MemberHealth> = {},
): MemberHealth {
  return {
    memberId: 'ada',
    seats: [],
    status,
    checking: status === 'checking',
    problems: [],
    mcpCheckedAt: null,
    ...over,
  };
}

function dto(
  members: MemberHealth[],
  over: Partial<TeamHealthDto> = {},
): TeamHealthDto {
  return {
    slug: 'dev',
    checkedAt: '2026-11-02T10:00:00.000Z',
    blocking: false,
    team: [],
    members,
    ...over,
  };
}

function apisWith(
  readTeamHealth: (req: {
    slug: string;
    probe?: string;
  }) => Promise<TeamHealthDto>,
): DaemonApis {
  return { teams: { readTeamHealth } } as unknown as DaemonApis;
}

async function flush(ms = 0): Promise<void> {
  await act(async () => {
    await vi.advanceTimersByTimeAsync(ms);
  });
}

describe('useTeamHealth', () => {
  function mount(
    apis: DaemonApis,
    slug: string | null,
    probe: boolean,
  ): () => TeamHealthState {
    let latest!: TeamHealthState;
    function Probe(): null {
      latest = useTeamHealth(apis, slug, { probe });
      return null;
    }
    act(() => root.render(<Probe />));
    return () => latest;
  }

  it('re-reads with probe=true only while a member is checking, then stops', async () => {
    const answers = [
      dto([member('checking')]),
      dto([member('checking')]),
      dto([member('ok')]),
    ];
    const read = vi.fn(() => Promise.resolve(answers.shift()!));
    const latest = mount(apisWith(read), 'dev', true);
    await flush();
    expect(read).toHaveBeenCalledTimes(1);
    expect(read).toHaveBeenLastCalledWith({ slug: 'dev', probe: 'true' });
    await flush(2_000);
    expect(read).toHaveBeenCalledTimes(2);
    await flush(2_000);
    expect(read).toHaveBeenCalledTimes(3);
    expect(latest().health?.members[0]?.status).toBe('ok');
    await flush(10_000);
    expect(read).toHaveBeenCalledTimes(3);
  });

  it('keeps polling for a red member whose MCP read is still running', async () => {
    const answers = [
      dto([member('error', { checking: true })]),
      dto([member('error', { checking: false })]),
    ];
    const read = vi.fn(() => Promise.resolve(answers.shift()!));
    mount(apisWith(read), 'dev', true);
    await flush();
    await flush(2_000);
    expect(read).toHaveBeenCalledTimes(2);
    await flush(10_000);
    expect(read).toHaveBeenCalledTimes(2);
  });

  it('gives up after about a minute of a member still checking', async () => {
    const read = vi.fn(() => Promise.resolve(dto([member('checking')])));
    mount(apisWith(read), 'dev', true);
    await flush();
    for (let poll = 0; poll < 40; poll += 1) {
      await flush(2_000);
    }

    expect(read).toHaveBeenCalledTimes(31);
  });

  it('never polls on the cheap path', async () => {
    const read = vi.fn(() => Promise.resolve(dto([member('checking')])));
    mount(apisWith(read), 'dev', false);
    await flush(10_000);
    expect(read).toHaveBeenCalledTimes(1);
    expect(read).toHaveBeenCalledWith({ slug: 'dev', probe: 'false' });
  });

  it('stops polling when the slug changes and does not show the old team', async () => {
    const read = vi.fn((req: { slug: string }) =>
      Promise.resolve(dto([member('checking')], { slug: req.slug })),
    );
    const apis = apisWith(read);
    let latest!: TeamHealthState;
    function Probe({ slug }: { slug: string | null }): null {
      latest = useTeamHealth(apis, slug, { probe: true });
      return null;
    }
    act(() => root.render(<Probe slug="dev" />));
    await flush();
    act(() => root.render(<Probe slug={null} />));
    expect(latest.health).toBeNull();
    await flush(10_000);
    expect(read).toHaveBeenCalledTimes(1);
  });

  it('reads again on reload', async () => {
    const read = vi.fn(() => Promise.resolve(dto([member('ok')])));
    const latest = mount(apisWith(read), 'dev', true);
    await flush();
    act(() => latest().reload());
    await flush();
    expect(read).toHaveBeenCalledTimes(2);
  });

  it('reports a failed read as an error', async () => {
    const read = vi.fn(() => Promise.reject(new Error('daemon down')));
    const latest = mount(apisWith(read), 'dev', true);
    await flush();
    expect(latest().error).toBe('daemon down');
    expect(latest().loading).toBe(false);
  });
});

describe('useLibraryHealth', () => {
  it('asks every team with probe=false and sums its problems', async () => {
    const problem = {
      kind: 'mcp_failed' as const,
      level: 'warning' as const,
      message: 'x',
      agent: null,
      poolMember: null,
      configDir: null,
      server: null,
      model: null,
    };
    const read = vi.fn((req: { slug: string }) =>
      Promise.resolve(
        req.slug === 'dev'
          ? dto(
              [
                member('warning', {
                  problems: [problem, problem],
                  mcpCheckedAt: '2026-11-02T09:00:00.000Z',
                }),
                member('ok', { mcpCheckedAt: '2026-11-02T08:00:00.000Z' }),
              ],
              { team: [{ ...problem, kind: 'no_trigger' }], blocking: true },
            )
          : dto([member('ok')]),
      ),
    );
    const apis = apisWith(read);
    let latest!: Map<string, LibraryHealth>;
    function Probe(): null {
      latest = useLibraryHealth(apis, ['dev', 'docs']);
      return null;
    }
    act(() => root.render(<Probe />));
    await flush();
    expect(read.mock.calls.map(([req]) => req)).toEqual([
      { slug: 'dev', probe: 'false' },
      { slug: 'docs', probe: 'false' },
    ]);
    expect(latest.get('dev')).toEqual({
      count: 3,
      blocking: true,
      mcpCheckedAt: '2026-11-02T08:00:00.000Z',
    });
    expect(latest.get('docs')).toEqual({
      count: 0,
      blocking: false,
      mcpCheckedAt: null,
    });
  });

  it('reads at most four teams at once, and every team in the end', async () => {
    let inFlight = 0;
    let most = 0;
    const read = vi.fn(async () => {
      inFlight += 1;
      most = Math.max(most, inFlight);
      await new Promise((resolve) => setTimeout(resolve, 10));
      inFlight -= 1;
      return dto([member('ok')]);
    });
    const slugs = ['a', 'b', 'c', 'd', 'e', 'f', 'g'];
    const apis = apisWith(read);
    let latest!: Map<string, LibraryHealth>;
    function Probe(): null {
      latest = useLibraryHealth(apis, slugs);
      return null;
    }
    act(() => root.render(<Probe />));
    await flush(100);

    expect(most).toBe(4);
    expect(read).toHaveBeenCalledTimes(7);
    expect([...latest.keys()].sort()).toEqual(slugs);
  });

  it('counts a member signed out of its CLI, by main’s last detection, never a fresh probe', async () => {
    detectClis.mockResolvedValue([
      {
        kind: 'claude',
        found: true,
        path: '/bin/claude',
        version: '1',
        loggedIn: false,
        profileLogins: { '/work': true },
        update: { available: null, latestVersion: null },
      } as unknown as CliDetection,
    ]);
    const read = vi.fn(async () =>
      dto([
        member('ok', {
          seats: [
            { agent: 'claude', configDir: null, poolMember: null },
            { agent: 'claude', configDir: '/work', poolMember: 2 },
          ],
        }),
      ]),
    );
    const apis = apisWith(read);
    let latest!: Map<string, LibraryHealth>;
    function Probe(): null {
      latest = useLibraryHealth(apis, LIBRARY_SLUGS);
      return null;
    }
    act(() => root.render(<Probe />));
    await flush();

    expect(detectClis).toHaveBeenCalledWith({ maxAgeMs: 60_000 });
    expect(latest.get('dev')?.count).toBe(1);
  });
});

const LIBRARY_SLUGS = ['dev'];
