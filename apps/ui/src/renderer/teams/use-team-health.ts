import { useEffect, useMemo, useState } from 'react';

import type { CliDetection } from '../../shared/contracts';
import { ReadTeamHealthProbeEnum, type TeamHealthDto } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import { DETECTION_MAX_AGE_MS, signInOf } from './use-sign-in-health';

/** How long to wait before asking again while a member's MCP is being read. */
const CHECKING_POLL_MS = 2_000;

/** About a minute of waiting; a listing that long is stuck, not slow. */
const MAX_CHECKING_POLLS = 30;

export interface TeamHealthState {
  health: TeamHealthDto | null;
  loading: boolean;
  error: string | null;
  reload: () => void;
}

/**
 * The daemon's reading of one team's setup. `probe: true` is the open team's
 * page only: it makes the daemon list each profile's MCP servers once, and
 * while a member still reads `checking` this asks again every couple of
 * seconds, a bounded number of times. `probe: false` never dials anything and
 * never polls. With `projectId`, the team is read as that project runs it.
 */
export function useTeamHealth(
  apis: DaemonApis | null,
  slug: string | null,
  options: { probe: boolean; projectId?: string | null },
): TeamHealthState {
  const teamsApi = apis?.teams ?? null;
  const { probe } = options;
  const projectId = options.projectId ?? null;
  const [answered, setAnswered] = useState<{
    slug: string;
    health: TeamHealthDto;
  } | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [reloadToken, setReloadToken] = useState(0);

  useEffect(() => {
    if (teamsApi === null || slug === null) {
      setAnswered(null);
      setLoading(false);
      setError(null);
      return;
    }
    let live = true;
    let timer: ReturnType<typeof setTimeout> | undefined;
    let polls = 0;
    setLoading(true);
    const read = (): void => {
      teamsApi
        .readTeamHealth({
          slug,
          ...(projectId === null ? {} : { projectId }),
          probe: probe
            ? ReadTeamHealthProbeEnum.True
            : ReadTeamHealthProbeEnum.False,
        })
        .then((health) => {
          if (!live) {
            return;
          }
          setAnswered({ slug, health });
          setError(null);
          setLoading(false);
          if (
            probe &&
            polls < MAX_CHECKING_POLLS &&
            health.members.some((member) => member.checking)
          ) {
            polls += 1;
            timer = setTimeout(read, CHECKING_POLL_MS);
          }
        })
        .catch((err: unknown) => {
          if (live) {
            setError(err instanceof Error ? err.message : String(err));
            setLoading(false);
          }
        });
    };
    read();
    return () => {
      live = false;
      clearTimeout(timer);
    };
  }, [teamsApi, slug, probe, projectId, reloadToken]);

  const reload = useLatestCallback(() => {
    setReloadToken((token) => token + 1);
  }, []);

  return {
    health:
      answered !== null && answered.slug === slug ? answered.health : null,
    loading,
    error,
    reload,
  };
}

/** How many teams' health the library reads at once. */
const LIBRARY_HEALTH_READERS = 4;

/** What the library card says about one team. */
export interface LibraryHealth {
  count: number;
  blocking: boolean;
  mcpCheckedAt: string | null;
}

/**
 * One cheap reading per team for the library's badges: never a probe, so
 * opening the library starts none of the user's MCP servers. Each member's
 * sign-in comes from Electron main's last detection, as on the team page. A
 * team whose read fails has no entry.
 */
export function useLibraryHealth(
  apis: DaemonApis | null,
  slugs: readonly string[],
): Map<string, LibraryHealth> {
  const teamsApi = apis?.teams ?? null;
  const [byTeam, setByTeam] = useState<Map<string, TeamHealthDto>>(new Map());
  const [detections, setDetections] = useState<CliDetection[] | null>(null);
  const slugKey = slugs.join('\u0000');

  useEffect(() => {
    if (slugs.length === 0) {
      return;
    }
    let live = true;
    window.geniro
      .detectClis({ maxAgeMs: DETECTION_MAX_AGE_MS })
      .then((detected) => {
        if (live) {
          setDetections(detected);
        }
      })
      .catch(() => undefined);
    return () => {
      live = false;
    };
    // slugKey is the content of `slugs`, which a caller rebuilds each render.
  }, [slugKey]);

  useEffect(() => {
    const wanted = new Set(slugs);
    setByTeam(
      (previous) => new Map([...previous].filter(([slug]) => wanted.has(slug))),
    );
    if (teamsApi === null) {
      return;
    }
    let live = true;
    const queue = [...wanted];
    const readNext = async (): Promise<void> => {
      for (let slug = queue.shift(); slug !== undefined; slug = queue.shift()) {
        if (!live) {
          return;
        }
        const health = await teamsApi
          .readTeamHealth({ slug, probe: ReadTeamHealthProbeEnum.False })
          .catch(() => null);
        if (!live || health === null) {
          continue;
        }
        const answered = slug;
        setByTeam((previous) => new Map(previous).set(answered, health));
      }
    };
    for (let reader = 0; reader < LIBRARY_HEALTH_READERS; reader += 1) {
      void readNext();
    }
    return () => {
      live = false;
    };
    // slugKey is the content of `slugs`, which a caller rebuilds each render.
  }, [teamsApi, slugKey]);

  return useMemo(() => {
    const summaries = new Map<string, LibraryHealth>();
    for (const [slug, health] of byTeam) {
      const checked = health.members
        .map((member) => member.mcpCheckedAt)
        .filter((at): at is string => at !== null)
        .sort();
      const signedOut =
        detections === null
          ? 0
          : health.members.reduce(
              (sum, member) =>
                sum +
                member.seats.filter(
                  (seat) =>
                    signInOf(seat, detections, (agent) => agent) !== null,
                ).length,
              0,
            );
      summaries.set(slug, {
        count:
          health.team.length +
          health.members.reduce(
            (sum, member) => sum + member.problems.length,
            0,
          ) +
          signedOut,
        blocking: health.blocking,
        mcpCheckedAt: checked[0] ?? null,
      });
    }
    return summaries;
  }, [byTeam, detections]);
}
