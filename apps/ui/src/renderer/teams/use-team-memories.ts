import { useEffect, useRef, useState } from 'react';

import type { MemoryEntry } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

/** TWIN: `MEMORY_LIST_LIMIT_MAX` in `apps/daemon/src/v1/memory/memory.types.ts`. */
const MEMORY_PAGE_MAX = 200;
const REFRESH_DELAY_MS = 250;

export interface TeamMemories {
  /** Null until the first answer for this team. */
  entries: MemoryEntry[] | null;
  /** The team has more entries than one page holds. */
  more: boolean;
  loading: boolean;
  error: string | null;
  reload: () => void;
}

interface Answer {
  slug: string;
  entries: MemoryEntry[];
  more: boolean;
}

/**
 * One team's shared-memory entries (active and waiting), searched by `query`
 * and re-read on every `memory_changed`. The list is the daemon's: it is never
 * folded or edited here, and another team's entries are never shown under this
 * one's name.
 */
export function useTeamMemories(
  apis: DaemonApis | null,
  slug: string | null,
  query: string,
  client?: DaemonClient | null,
): TeamMemories {
  const [answer, setAnswer] = useState<Answer | null>(null);
  const [failure, setFailure] = useState<{
    slug: string;
    message: string;
  } | null>(null);
  const generation = useRef(0);
  const q = query.trim();

  const read = useLatestCallback(() => {
    if (apis === null || slug === null) {
      return;
    }
    const mine = ++generation.current;
    void apis.memories
      .listMemories({
        scope: 'team',
        teamSlug: slug,
        ...(q === '' ? {} : { q }),
        limit: MEMORY_PAGE_MAX,
      })
      .then((page) => {
        if (mine === generation.current) {
          setAnswer({
            slug,
            entries: page.memories,
            more: page.next !== null,
          });
          setFailure(null);
        }
      })
      .catch((err: unknown) => {
        if (mine === generation.current) {
          setFailure({ slug, message: describeDaemonError(err) });
        }
      });
  }, [apis, slug, q]);

  useEffect(() => {
    const timer = setTimeout(read, q === '' ? 0 : REFRESH_DELAY_MS);
    return () => clearTimeout(timer);
  }, [read, q]);

  useEffect(() => {
    if (!client || slug === null) {
      return;
    }
    let timer: ReturnType<typeof setTimeout> | null = null;
    const off = client.onMemoryChanged(() => {
      if (timer !== null) {
        clearTimeout(timer);
      }
      timer = setTimeout(read, REFRESH_DELAY_MS);
    });
    return () => {
      off();
      if (timer !== null) {
        clearTimeout(timer);
      }
    };
  }, [client, slug, read]);

  const reload = useLatestCallback(() => {
    setFailure(null);
    read();
  }, [read]);

  const current = answer?.slug === slug ? answer : null;
  const error = failure?.slug === slug ? failure.message : null;
  return {
    entries: current?.entries ?? null,
    more: current?.more ?? false,
    loading:
      apis !== null && slug !== null && current === null && error === null,
    error,
    reload,
  };
}
