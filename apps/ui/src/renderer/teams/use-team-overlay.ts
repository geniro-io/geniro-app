import { useEffect, useRef, useState } from 'react';

import type { TeamOverlay, TeamsApi } from '../autogenerated';
import { useLatestCallback } from '../components/use-latest-callback';
import { daemonErrorCode, daemonErrorDetail } from '../daemon-api';
import { type AutosaveState, useAutosave } from './use-autosave';

export interface TeamOverlayState {
  /** The project's overlay as edited; null until read. */
  overlay: TeamOverlay | null;
  orphans: string[];
  loading: boolean;
  error: string | null;
  /** The file changed elsewhere since it was read: edits are kept, saving holds. */
  stale: boolean;
  save: AutosaveState;
  edit: (next: (current: TeamOverlay) => TeamOverlay) => void;
  flush: () => Promise<boolean>;
  reload: (keepEdits?: boolean) => Promise<void>;
  /** Re-read the file unless the copy here holds unsaved edits — after an agent may have written it. */
  refresh: () => Promise<void>;
}

function snapshotOf(overlay: TeamOverlay | null): string {
  return JSON.stringify(overlay ?? null);
}

/**
 * One project's overlay of its default team: read when the project's page
 * opens, autosaved like the team, every save quoting the hash it was read at
 * (`TEAM_OVERLAY_CHANGED` keeps the edits and holds saving until a reload).
 */
export function useTeamOverlay(
  api: TeamsApi | null,
  slug: string | null,
  projectId: string | null,
  enabled: boolean,
): TeamOverlayState {
  const [overlay, setOverlay] = useState<TeamOverlay | null>(null);
  const [orphans, setOrphans] = useState<string[]>([]);
  const [saved, setSaved] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [stale, setStale] = useState(false);
  const hashRef = useRef<string | null>(null);
  const keyRef = useRef<string | null>(null);
  const changesRef = useRef(0);

  const reload = useLatestCallback(
    async (keepEdits = false): Promise<void> => {
      const key =
        slug === null || projectId === null ? null : `${slug}/${projectId}`;
      keyRef.current = key;
      if (!api || slug === null || projectId === null) {
        setOverlay(null);
        setSaved(null);
        setOrphans([]);
        hashRef.current = null;
        return;
      }
      setLoading(true);
      const changesAtRead = changesRef.current;
      try {
        const wire = await api.getTeamOverlay({ slug, projectId });
        if (
          keyRef.current !== key ||
          (keepEdits && changesRef.current !== changesAtRead)
        ) {
          return;
        }
        hashRef.current = wire.hash;
        setOverlay(wire.overlay);
        setSaved(snapshotOf(wire.overlay));
        setOrphans(wire.orphans);
        setStale(false);
        setError(null);
      } catch (err) {
        if (keyRef.current === key) {
          setError(daemonErrorDetail(err) ?? String(err));
        }
      } finally {
        if (keyRef.current === key) {
          setLoading(false);
        }
      }
    },
    [api, slug, projectId],
  );

  useEffect(() => {
    void reload();
  }, [slug, projectId, reload]);

  const write = useLatestCallback(async (): Promise<boolean> => {
    if (!api || slug === null || projectId === null || overlay === null) {
      return false;
    }
    const key = `${slug}/${projectId}`;
    const sent = overlay;
    try {
      const wire = await api.saveTeamOverlay({
        slug,
        projectId,
        saveTeamOverlayDto: { overlay: sent, baseHash: hashRef.current },
      });
      if (keyRef.current !== key) {
        return true;
      }
      changesRef.current += 1;
      hashRef.current = wire.hash;
      setSaved(snapshotOf(sent));
      setOrphans(wire.orphans);
      setError(null);
      return true;
    } catch (err) {
      if (keyRef.current === key) {
        if (daemonErrorCode(err) === 'TEAM_OVERLAY_CHANGED') {
          setStale(true);
        } else {
          setError(daemonErrorDetail(err) ?? String(err));
        }
      }
      return false;
    }
  }, [api, slug, projectId, overlay]);

  const autosave = useAutosave({
    enabled: enabled && projectId !== null && !stale && overlay !== null,
    snapshot: snapshotOf(overlay),
    savedSnapshot: saved,
    save: write,
  });

  const edit = useLatestCallback(
    (next: (current: TeamOverlay) => TeamOverlay): void => {
      changesRef.current += 1;
      setOverlay((current) => (current === null ? current : next(current)));
    },
    [],
  );

  const refresh = useLatestCallback(async (): Promise<void> => {
    if (snapshotOf(overlay) === saved) {
      await reload(true);
    }
  }, [overlay, saved, reload]);

  return {
    overlay,
    orphans,
    loading,
    error,
    stale,
    save: autosave.state,
    edit,
    flush: autosave.flush,
    reload,
    refresh,
  };
}
