// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { DaemonHandle } from '../../shared/contracts';
import {
  TerminalKind,
  type TerminalSessionDto as TerminalSession,
} from '../autogenerated';
import { TerminalPanel } from './terminal-panel';

const mocks = vi.hoisted(() => {
  const term = {
    loadAddon: vi.fn(),
    open: vi.fn(),
    focus: vi.fn(),
    reset: vi.fn(),
    write: vi.fn(),
    dispose: vi.fn(),
    onData: vi.fn(() => ({ dispose: vi.fn() })),
    cols: 80,
    rows: 24,
  };
  interface ClientEvents {
    onSnapshot?: (s: string, status: string, code: number | null) => void;
    onData?: (d: string) => void;
    onExit?: (code: number | null) => void;
    onGone?: () => void;
  }
  const clients: {
    terminalId: string;
    events: ClientEvents;
    connect: ReturnType<typeof vi.fn>;
    input: ReturnType<typeof vi.fn>;
    resize: ReturnType<typeof vi.fn>;
    close: ReturnType<typeof vi.fn>;
  }[] = [];
  class FakeTerminalClient {
    connect = vi.fn();
    input = vi.fn();
    resize = vi.fn();
    close = vi.fn();
    constructor(
      _handle: unknown,
      public readonly terminalId: string,
      public readonly events: ClientEvents,
    ) {
      clients.push(this);
    }
  }
  // Captured so the read-only/EOL decisions can be asserted on the REAL
  // constructor argument rather than on a rendering of it.
  const termOptions: Record<string, unknown>[] = [];
  return { term, clients, termOptions, FakeTerminalClient };
});

vi.mock('@xterm/xterm', () => ({
  Terminal: function Terminal(options: Record<string, unknown>) {
    mocks.termOptions.push(options);
    return mocks.term;
  },
}));
vi.mock('@xterm/xterm/css/xterm.css', () => ({}));
vi.mock('@xterm/addon-fit', () => ({
  FitAddon: function FitAddon() {
    return { fit: () => {} };
  },
}));
vi.mock('../terminal-client', () => ({
  TerminalClient: mocks.FakeTerminalClient,
}));

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

class FakeResizeObserver {
  observe(): void {}
  disconnect(): void {}
}
(globalThis as { ResizeObserver?: unknown }).ResizeObserver =
  FakeResizeObserver;

const handle: DaemonHandle = {
  host: '127.0.0.1',
  port: 8123,
  token: 'tok',
  version: '1',
};

const session: TerminalSession = {
  id: 't-1',
  kind: TerminalKind.Interactive,
  runId: 'run-1',
  nodeId: null,
  resumeSessionId: null,
  cwd: '/tmp',
  status: 'running',
  exitCode: null,
  createdAt: 0,
};

const liveSession: TerminalSession = {
  ...session,
  id: 'live-1',
  kind: TerminalKind.Live,
};

let container: HTMLDivElement;
let root: Root;

function render(
  onClose = vi.fn(),
  opts: {
    session?: TerminalSession;
    onSwitchKind?: (k: TerminalKind) => void;
  } = {},
) {
  act(() => {
    root.render(
      <TerminalPanel
        handle={handle}
        session={opts.session ?? session}
        title="claude · demo"
        onClose={onClose}
        onSwitchKind={opts.onSwitchKind}
      />,
    );
  });
  return { onClose };
}

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  mocks.clients.length = 0;
  mocks.term.write.mockClear();
  mocks.term.reset.mockClear();
  mocks.term.dispose.mockClear();
  mocks.term.focus.mockClear();
  mocks.term.onData.mockClear();
  mocks.termOptions.length = 0;
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

describe('TerminalPanel', () => {
  it('connects a client for the session and replays the snapshot into xterm', () => {
    render();

    const client = mocks.clients[0];
    expect(client?.terminalId).toBe('t-1');
    expect(client?.connect).toHaveBeenCalled();

    act(() => client?.events.onSnapshot?.('history', 'running', null));
    expect(mocks.term.reset).toHaveBeenCalled();
    expect(mocks.term.write).toHaveBeenCalledWith('history');
    expect(client?.resize).toHaveBeenCalledWith(80, 24);
  });

  it('focuses the terminal on open and again on attach — keys route to the PTY, not the trigger button', () => {
    render();
    // xterm's open() does not focus; without the explicit call, keystrokes
    // stay on the background button under the modal (Space re-fires it).
    expect(mocks.term.focus).toHaveBeenCalled();

    mocks.term.focus.mockClear();
    const client = mocks.clients[0];
    act(() => client?.events.onSnapshot?.('history', 'running', null));
    expect(mocks.term.focus).toHaveBeenCalled();
  });

  it('shows a connecting state, then NO badge once the mirror is healthy', () => {
    render();

    expect(container.textContent).toContain('Connecting…');
    expect(container.textContent).toContain('connecting');

    const client = mocks.clients[0];
    act(() => client?.events.onSnapshot?.('history', 'running', null));

    // A healthy live mirror carries no badge at all (the old 'live' label
    // is deliberately gone) — only exceptional states get labeled.
    expect(container.textContent).not.toContain('Connecting…');
    expect(container.textContent).not.toContain('connecting');
    expect(container.querySelector('[data-slot="badge"]')).toBeNull();
    expect(container.textContent).not.toContain('live');
  });

  it('writes live data and shows the exited badge on exit', () => {
    render();
    const client = mocks.clients[0];

    act(() => client?.events.onData?.('output'));
    expect(mocks.term.write).toHaveBeenCalledWith('output');

    act(() => client?.events.onExit?.(0));
    expect(container.textContent).toContain('exited (0)');
  });

  it('drops the exited badge when a fresh running session replaces an exited one', () => {
    render();
    const first = mocks.clients[0];
    act(() => first?.events.onExit?.(1));
    expect(container.textContent).toContain('exited (1)');

    // Chats swaps the session prop in place (same element position, no key):
    // the user re-opens a terminal after the previous TUI exited. The panel
    // already supports the swap without a remount (its effect re-runs on
    // session.id and connects a new client), so the status badge must reflect
    // the NEW session, not the exit of the old one.
    act(() => {
      root.render(
        <TerminalPanel
          handle={handle}
          session={{ ...session, id: 't-2' }}
          title="claude · demo"
          onClose={vi.fn()}
        />,
      );
    });
    const second = mocks.clients[1];
    expect(second?.terminalId).toBe('t-2');
    act(() => second?.events.onSnapshot?.('', 'running', null));

    expect(container.textContent).not.toContain('exited');
  });

  it('shows the gone badge when the attach targets a reaped session', () => {
    render();
    const client = mocks.clients[0];

    act(() => client?.events.onGone?.());

    expect(container.textContent).toContain('gone');
  });

  it('detaches the client and disposes xterm on unmount', () => {
    render();
    const client = mocks.clients[0];

    act(() => root.unmount());

    expect(client?.close).toHaveBeenCalled();
    expect(mocks.term.dispose).toHaveBeenCalled();
  });

  it('closes via the standard ✕ icon — and offers NO End session control', () => {
    const { onClose } = render();

    // The one header action: the standard icon close (no text label).
    const close = container.querySelector<HTMLButtonElement>(
      'button[aria-label="Close terminal"]',
    )!;
    expect(close.textContent).toBe('');
    expect(close.querySelector('svg')).not.toBeNull();
    // Ending a session happens inside the TUI, never from the popup chrome.
    expect(container.textContent).not.toContain('End session');

    act(() => {
      close.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    expect(onClose).toHaveBeenCalledOnce();
  });

  it('is a modal popup: a backdrop click detaches, a click inside does not', () => {
    const { onClose } = render();
    expect(container.querySelector('[role="dialog"]')).not.toBeNull();

    act(() => {
      container
        .querySelector('header')
        ?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    expect(onClose).not.toHaveBeenCalled();

    act(() => {
      container
        .querySelector('[data-testid="terminal-backdrop"]')
        ?.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    expect(onClose).toHaveBeenCalledOnce();
  });
});

describe('TerminalPanel — the live mirror', () => {
  it('wires keystrokes for an interactive session and NOT for a live one', () => {
    // The whole read-only claim. `onData` is what carries a keystroke to the
    // daemon; a live session has no process behind it, so input would be
    // accepted, forwarded and silently dropped — a terminal that looks frozen
    // rather than one that is plainly read-only.
    render();
    expect(mocks.term.onData).toHaveBeenCalled();

    act(() => root.unmount());
    root = createRoot(container);
    mocks.term.onData.mockClear();

    render(vi.fn(), { session: liveSession });
    expect(mocks.term.onData).not.toHaveBeenCalled();
  });

  it('converts bare LF for the live plane ONLY — it is a pipe, not a PTY', () => {
    // A headless child writes '\\n' where a PTY emits '\\r\\n'; without this every
    // line after the first is indented by the previous line's width. It stays
    // OFF for the PTY kind, whose output already carries the CR and which is a
    // full-screen TUI that xterm's column-0-on-every-LF would disturb.
    render(vi.fn(), { session: liveSession });
    expect(mocks.termOptions[0]?.convertEol).toBe(true);
    expect(mocks.termOptions[0]?.cursorBlink).toBe(false);

    act(() => root.unmount());
    root = createRoot(container);
    mocks.termOptions.length = 0;

    render();
    expect(mocks.termOptions[0]?.convertEol).toBe(false);
    // The interactive session has a real prompt to type at.
    expect(mocks.termOptions[0]?.cursorBlink).toBe(true);
  });

  it('explains an empty live mirror instead of showing a blank screen', () => {
    render(vi.fn(), { session: liveSession });
    const client = mocks.clients[0];

    // Attached, healthy, and holding nothing: no turn has run for this node
    // since the daemon started. Indistinguishable from the reported bug unless
    // the panel says so.
    act(() => client?.events.onSnapshot?.('', 'running', null));
    expect(container.textContent).toContain('Nothing yet');

    act(() => client?.events.onData?.('{"type":"system"}'));
    expect(container.textContent).not.toContain('Nothing yet');
  });

  it('clears the empty-state hint again when a reconnect replays nothing', () => {
    // The flag follows the buffer rather than latching: a reconnect REPLACES
    // the terminal contents (the panel resets xterm first), so a session whose
    // buffer was dropped must go back to explaining itself.
    render(vi.fn(), { session: liveSession });
    const client = mocks.clients[0];

    act(() => client?.events.onSnapshot?.('some output', 'running', null));
    expect(container.textContent).not.toContain('Nothing yet');

    act(() => client?.events.onSnapshot?.('', 'running', null));
    expect(container.textContent).toContain('Nothing yet');
  });

  it('says "ended" rather than an exit code for a mirror that never had a process', () => {
    render(vi.fn(), { session: liveSession });
    const client = mocks.clients[0];

    act(() => client?.events.onExit?.(null));

    expect(container.textContent).toContain('ended');
    // "exited (0)" would claim a process outcome for a session that ran none.
    expect(container.textContent).not.toContain('exited');
  });

  it('offers the kind picker only when the owner can switch, and reports the pick', () => {
    render();
    expect(container.querySelector('[data-menu-trigger]')).toBeNull();

    act(() => root.unmount());
    root = createRoot(container);
    const onSwitchKind = vi.fn();
    render(vi.fn(), { session: liveSession, onSwitchKind });

    const trigger = container.querySelector<HTMLElement>(
      '[data-menu-trigger]',
    )!;
    act(() => {
      trigger.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    const options = [
      ...container.querySelectorAll<HTMLElement>('[role="option"]'),
    ];
    const interactive = options.find((o) =>
      o.textContent?.includes('Interactive session'),
    )!;
    act(() => {
      interactive.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });

    expect(onSwitchKind).toHaveBeenCalledWith(TerminalKind.Interactive);
  });
});
