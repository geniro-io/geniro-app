import '@xterm/xterm/css/xterm.css';

import { FitAddon } from '@xterm/addon-fit';
import { Terminal } from '@xterm/xterm';
import { X } from 'lucide-react';
import { useEffect, useRef, useState } from 'react';

import type { DaemonHandle } from '../../shared/contracts';
import {
  TerminalKind,
  type TerminalSessionDto as TerminalSession,
  type TerminalStatus,
} from '../autogenerated';
import { Badge } from '../components/ui/badge';
import { Button } from '../components/ui/button';
import { Select, type SelectGroup } from '../components/ui/select';
import { TerminalClient } from '../terminal-client';

/** Resolve a design token to the concrete colour value xterm can parse. */
function tokenColor(name: string): string | undefined {
  const value = getComputedStyle(document.documentElement)
    .getPropertyValue(name)
    .trim();
  return value.length > 0 ? value : undefined;
}

/**
 * The two mirrors, labelled by what the user GETS rather than by how either is
 * built. What the difference actually means is explained once, in the footer —
 * a picker row is not the place for two sentences of caveat.
 */
const KIND_GROUPS: SelectGroup[] = [
  {
    items: [
      { value: TerminalKind.Live, label: 'Live output' },
      { value: TerminalKind.Interactive, label: 'Interactive session' },
    ],
  },
];

/**
 * Modal popup showing one terminal mirror of a run, in an xterm.js view over a
 * dimmed backdrop. Colours come from the design tokens (resolved at mount —
 * xterm needs concrete values, not var() references).
 *
 * Two kinds, picked in the header:
 *
 * - `live` streams the raw output of the run's OWN turns as they happen. It is
 *   read-only — there is no second process to type into — and it follows the
 *   conversation across turns.
 * - `interactive` is a separate `--resume` CLI process on the same stored
 *   conversation: you can type at it, but being a different process it replays
 *   the transcript at startup and then cannot advance while the chat's own turn
 *   is running. That standstill is what `live` exists to fix, so `live` is what
 *   opens by default.
 *
 * Closing — the ✕ or a backdrop click — always DETACHES. An interactive session
 * keeps running for a later re-open (ending it happens inside the TUI, never
 * from this chrome); a live mirror is dropped, since its buffer lives on the
 * daemon and the next open replays it anyway. Escape deliberately does NOT
 * close: the key belongs to the TUI inside (claude uses it to interrupt).
 */
export function TerminalPanel({
  handle,
  session,
  title,
  onClose,
  onSwitchKind,
}: {
  handle: DaemonHandle;
  session: TerminalSession;
  /** Header label, e.g. "claude · run title" or the node id. */
  title: string;
  onClose: () => void;
  /**
   * Open the OTHER mirror of the same target. Absent = no picker, for a caller
   * that can only offer one kind.
   */
  onSwitchKind?: (kind: TerminalKind) => void;
}): React.JSX.Element {
  const containerRef = useRef<HTMLDivElement | null>(null);
  const [exitCode, setExitCode] = useState<number | null>(null);
  const [status, setStatus] = useState<TerminalStatus>(session.status);
  const [gone, setGone] = useState(false);
  // False until the attach delivers its first snapshot/data/exit — a blank
  // card under a "live" badge reads as broken, so surface "Connecting…".
  const [connected, setConnected] = useState(false);
  // Distinct from `connected`: a live mirror attaches instantly and correctly
  // with NOTHING buffered, when no turn has run for this node since the daemon
  // started. That is a blank screen with no error, which reads exactly like the
  // "shell not updating" bug this panel was rebuilt to fix — so it gets its own
  // sentence instead of being left to look broken.
  const [hasOutput, setHasOutput] = useState(false);
  const live = session.kind === TerminalKind.Live;

  useEffect(() => {
    const container = containerRef.current;
    if (!container) {
      return;
    }
    // A session swap re-runs this effect with a fresh client — back to
    // connecting until the new attach replies.
    //
    // `gone` is reset here, not only in `onSnapshot`: the flag describes the
    // session that WAS attached, and a swap can be the user's way out of a
    // reaped one. Clearing it only on a successful snapshot leaves the new
    // session wearing the old one's "gone" badge until the attach lands — and
    // permanently, if the new attach also fails.
    setConnected(false);
    setHasOutput(false);
    setGone(false);
    const term = new Terminal({
      // A live mirror has no prompt waiting on you, so a blinking cursor would
      // invite typing that goes nowhere.
      cursorBlink: !live,
      // The live plane is a PIPE, not a PTY: a headless child writes bare LF
      // where a terminal would emit CRLF, and without this every line after the
      // first starts where the previous one ended (the classic staircase).
      //
      // Gated on `live` rather than left on globally. xterm implements this by
      // forcing column 0 on EVERY LF, which is a real behaviour change for a
      // full-screen TUI that emits bare LFs deliberately — and the interactive
      // kind is a full-screen TUI whose output already carries the CR, so it
      // needs nothing here and must not be guessed at.
      convertEol: live,
      fontSize: 13,
      scrollback: 5000,
      theme: {
        background: tokenColor('--card'),
        foreground: tokenColor('--foreground'),
        cursor: tokenColor('--primary'),
        selectionBackground: tokenColor('--accent'),
      },
    });
    const fit = new FitAddon();
    term.loadAddon(fit);
    term.open(container);
    fit.fit();
    // xterm's open() does not focus. Without this, keystrokes stay on the
    // background trigger button under the modal (Space would re-fire it) and
    // typing does nothing until the user clicks inside the terminal.
    term.focus();

    const client = new TerminalClient(handle, session.id, {
      onSnapshot: (snapshot, snapshotStatus, code) => {
        setConnected(true);
        setGone(false);
        // Set, not OR'd: a reconnect replaces the buffer, so an empty replay
        // means there is genuinely nothing to show again.
        setHasOutput(snapshot.length > 0);
        // A reconnect replays the full buffer — reset so nothing doubles.
        term.reset();
        term.write(snapshot);
        // Set (not just flip) the badge from the snapshot's status: Chats can
        // swap the session prop in place, and a fresh running session must not
        // inherit the previous session's "exited" badge.
        setStatus(snapshotStatus);
        setExitCode(snapshotStatus === 'exited' ? code : null);
        client.resize(term.cols, term.rows);
        // (Re)attach lands the mirror live — keys must route to the PTY.
        term.focus();
      },
      onData: (data) => {
        setConnected(true);
        setHasOutput(true);
        term.write(data);
      },
      onExit: (code) => {
        setConnected(true);
        setStatus('exited');
        setExitCode(code);
      },
      // The session was disposed/reaped before this attach — flag it so the
      // header stops showing a "live" badge over an inert terminal.
      onGone: () => setGone(true),
    });
    client.connect();

    // Only an interactive session has somewhere for keystrokes to go. Leaving
    // this wired for a live mirror would send input the daemon silently drops,
    // which looks like a frozen terminal rather than a read-only one.
    const dataSub = live ? null : term.onData((data) => client.input(data));
    const observer = new ResizeObserver(() => {
      fit.fit();
      client.resize(term.cols, term.rows);
    });
    observer.observe(container);

    return () => {
      observer.disconnect();
      dataSub?.dispose();
      client.close();
      term.dispose();
    };
  }, [handle, session.id, live]);

  return (
    <div
      role="dialog"
      aria-modal="true"
      aria-label={title}
      className="fixed inset-0 z-50 flex items-center justify-center p-6">
      <div
        className="absolute inset-0 bg-foreground/30"
        aria-hidden="true"
        data-testid="terminal-backdrop"
        onClick={onClose}
      />
      <div className="relative z-10 flex h-[78vh] w-full max-w-5xl flex-col overflow-hidden rounded-xl border border-border bg-card shadow-panel-md">
        <header className="flex items-center gap-2 border-b border-border px-4 py-2">
          <span className="min-w-0 flex-1 truncate text-sm font-medium text-foreground">
            {title}
          </span>
          {/* A healthy live mirror needs no badge — only the exceptional
              states (still connecting, ended, reaped) get labeled. */}
          {gone ? (
            <Badge variant="secondary">gone</Badge>
          ) : !connected ? (
            <Badge variant="secondary">connecting</Badge>
          ) : status === 'exited' ? (
            <Badge variant="secondary">
              {/* A live mirror carries no exit code — nothing exited; its
                  source went away with the run. */}
              {live
                ? 'ended'
                : `exited${exitCode !== null ? ` (${exitCode})` : ''}`}
            </Badge>
          ) : status === 'closing' ? (
            <Badge variant="secondary">closing</Badge>
          ) : null}
          {onSwitchKind ? (
            <Select
              variant="ghost"
              aria-label="Terminal mirror"
              align="end"
              className="shrink-0"
              groups={KIND_GROUPS}
              value={session.kind}
              onValueChange={(next) => onSwitchKind(next as TerminalKind)}
            />
          ) : null}
          <Button
            type="button"
            variant="ghost"
            size="icon"
            className="size-7"
            onClick={onClose}
            aria-label="Close terminal"
            title="Close">
            <X className="size-4 shrink-0" />
          </Button>
        </header>
        <div className="relative min-h-0 flex-1">
          {!connected && !gone ? (
            <div className="absolute inset-0 z-10 flex items-center justify-center text-sm text-muted-foreground">
              Connecting…
            </div>
          ) : connected && !gone && live && !hasOutput ? (
            <div className="absolute inset-0 z-10 flex items-center justify-center px-8 text-center text-sm text-muted-foreground">
              Nothing yet. This mirrors the agent’s own output as it runs, and
              it only holds what this app has seen since it started — send a
              message and it fills in.
            </div>
          ) : null}
          <div ref={containerRef} className="h-full bg-card p-2" />
        </div>
        {/* What the mirror IS, said once rather than left to be inferred —
            because the two kinds fail in opposite ways when confused. The live
            one looks frozen if you expect a prompt; the interactive one looks
            stale if you expect it to follow the chat. */}
        <footer className="border-t border-border px-4 py-1.5 text-[11px] text-muted-foreground">
          {live
            ? 'The raw output of this agent’s own turns, as they run. Read-only — it is watching the conversation, not a second session you can type at.'
            : 'A separate interactive session on this run’s conversation — answer anything the CLI asks on startup and your messages appear. It does not follow a turn already running in the chat.'}
        </footer>
      </div>
    </div>
  );
}
