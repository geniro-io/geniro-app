import { describe, expect, it, vi } from 'vitest';

import type { ChatsApi, ThreadOverviewDto } from './autogenerated';
import { batchThreadReads } from './thread-read-batching';

const STATE = { marker: 'state' };
const TOTALS = { marker: 'totals' };
const TIMELINE = { marker: 'timeline' };
const ARTIFACTS = { artifacts: [] };
const ANALYSIS = { analysis: null };

function client(overview: Partial<ThreadOverviewDto> = {}) {
  const own = {
    readRunState: vi.fn(async () => ({ own: 'state' })),
    readChatTotals: vi.fn(async () => ({ own: 'totals' })),
    readChatTimeline: vi.fn(async () => ({ own: 'timeline' })),
    readRunArtifacts: vi.fn(async () => ({ own: 'artifacts' })),
    getThreadAnalysis: vi.fn(async () => ({ own: 'analysis' })),
  };
  const readThreadOverview = vi.fn(async () => ({
    state: STATE,
    totals: TOTALS,
    timeline: TIMELINE,
    artifacts: ARTIFACTS,
    analysis: ANALYSIS,
    ...overview,
  }));
  const api = batchThreadReads({
    ...own,
    readThreadOverview,
  } as unknown as ChatsApi);
  return { api, own, readThreadOverview };
}

describe('batchThreadReads', () => {
  it('sends a thread opening’s reads as ONE overview request and answers each its part', async () => {
    const c = client();

    const answers = await Promise.all([
      c.api.readRunState({ runId: 'run-1' }),
      c.api.readChatTotals({ runId: 'run-1' }),
      c.api.readChatTimeline({ runId: 'run-1' }),
      c.api.readRunArtifacts({ runId: 'run-1' }),
      c.api.getThreadAnalysis({ runId: 'run-1' }),
    ]);

    expect(c.readThreadOverview).toHaveBeenCalledTimes(1);
    expect(c.readThreadOverview).toHaveBeenCalledWith({
      runId: 'run-1',
      parts: 'state,totals,timeline,artifacts,analysis',
    });
    expect(answers).toEqual([STATE, TOTALS, TIMELINE, ARTIFACTS, ANALYSIS]);
    expect(c.own.readRunState).not.toHaveBeenCalled();
  });

  it('sends a read asked alone to its own route — a re-read costs one part', async () => {
    const c = client();

    await expect(c.api.readRunState({ runId: 'run-1' })).resolves.toEqual({
      own: 'state',
    });

    expect(c.own.readRunState).toHaveBeenCalledTimes(1);
    expect(c.readThreadOverview).not.toHaveBeenCalled();
  });

  it('fails only the caller whose part the daemon could not read', async () => {
    const c = client({ timeline: null });

    const [state, timeline] = await Promise.allSettled([
      c.api.readRunState({ runId: 'run-1' }),
      c.api.readChatTimeline({ runId: 'run-1' }),
    ]);

    expect(state).toEqual({ status: 'fulfilled', value: STATE });
    expect(timeline.status).toBe('rejected');
  });

  it('batches per thread, never across two', async () => {
    const c = client();

    await Promise.all([
      c.api.readRunState({ runId: 'run-1' }),
      c.api.readChatTotals({ runId: 'run-1' }),
      c.api.readRunState({ runId: 'run-2' }),
    ]);

    expect(c.readThreadOverview).toHaveBeenCalledTimes(1);
    expect(c.readThreadOverview).toHaveBeenCalledWith({
      runId: 'run-1',
      parts: 'state,totals',
    });
    // run-2 asked one part alone, so it went to its own route.
    expect(c.own.readRunState).toHaveBeenCalledWith({ runId: 'run-2' });
  });

  it('sends a call with its own request options alone, so no option is lost to a batch', async () => {
    const c = client();
    const options = { signal: new AbortController().signal };

    await Promise.all([
      c.api.readRunState({ runId: 'run-1' }, options),
      c.api.readChatTotals({ runId: 'run-1' }),
    ]);

    expect(c.own.readRunState).toHaveBeenCalledWith(
      { runId: 'run-1' },
      options,
    );
    expect(c.readThreadOverview).not.toHaveBeenCalled();
  });

  it('rejects every caller of a batch whose request failed', async () => {
    const c = client();
    c.readThreadOverview.mockRejectedValueOnce(
      new Error('daemon GET failed (404)'),
    );

    const settled = await Promise.allSettled([
      c.api.readRunState({ runId: 'gone' }),
      c.api.readChatTotals({ runId: 'gone' }),
    ]);

    expect(settled.map((s) => s.status)).toEqual(['rejected', 'rejected']);
  });
});
