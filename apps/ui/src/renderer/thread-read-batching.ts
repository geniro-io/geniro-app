import type { ChatsApi, ThreadOverviewDto } from './autogenerated';

/**
 * The reads `GET /v1/chats/:runId/overview` can answer together, by the
 * client method each is, mapped to the part name the route takes it under.
 *
 * TWIN: `THREAD_OVERVIEW_PARTS` in `apps/daemon/src/v1/agents/chat.types.ts`.
 */
const BATCHED = {
  readRunState: 'state',
  readChatTotals: 'totals',
  readChatTimeline: 'timeline',
  readRunArtifacts: 'artifacts',
  getThreadAnalysis: 'analysis',
} as const satisfies Record<string, keyof ThreadOverviewDto>;

type BatchedMethod = keyof typeof BATCHED;
type Part = (typeof BATCHED)[BatchedMethod];

/**
 * Compile-time proof that each part the overview answers IS what its own
 * route answers — the promise a caller is handed is typed by its own route,
 * and this is what makes resolving it with the overview's part sound. A part
 * that drifted on the daemon side fails here after `pnpm generate:api`.
 */
const SAME_SHAPE: {
  [M in BatchedMethod]: NonNullable<
    ThreadOverviewDto[(typeof BATCHED)[M]]
  > extends Awaited<ReturnType<ChatsApi[M]>>
    ? Awaited<ReturnType<ChatsApi[M]>> extends NonNullable<
        ThreadOverviewDto[(typeof BATCHED)[M]]
      >
      ? true
      : false
    : false;
} = {
  readRunState: true,
  readChatTotals: true,
  readChatTimeline: true,
  readRunArtifacts: true,
  getThreadAnalysis: true,
};
void SAME_SHAPE;

interface Waiting {
  part: Part;
  /** The read on its own route — what a batch of one is sent as. */
  alone: () => Promise<unknown>;
  resolve: (value: unknown) => void;
  reject: (reason: unknown) => void;
}

/**
 * `api` with a thread's opening reads sent together.
 *
 * Opening a thread fires five reads at once — its state, totals, timeline,
 * artifacts and analysis, each from its own hook — and over the LAN gateway or
 * a tunnel each is a real round trip, queued behind a browser's six
 * connections per host. Reads of ONE thread asked in the same tick are
 * collected here and, when there are two or more, sent as one
 * `readThreadOverview`; each caller gets exactly the part its own route
 * answers. A read asked alone — a reconnect re-reading the state, a new page
 * moving the artifacts — still goes to its own route, so a re-read costs one
 * part, and a press that reads alone keeps its own route's error.
 *
 * The hooks are untouched: they call the methods they always called. A call
 * that brings its own request options (a signal, a timeout) is sent alone, so
 * no option is lost to a batch.
 */
export function batchThreadReads(api: ChatsApi): ChatsApi {
  const waiting = new Map<string, Waiting[]>();

  const flush = (runId: string): void => {
    const batch = waiting.get(runId) ?? [];
    waiting.delete(runId);
    if (batch.length === 1) {
      const [only] = batch;
      only!.alone().then(only!.resolve, only!.reject);
      return;
    }
    const parts = [...new Set(batch.map((entry) => entry.part))];
    api.readThreadOverview({ runId, parts: parts.join(',') }).then(
      (answer) => {
        for (const entry of batch) {
          const value = answer[entry.part];
          if (value === null) {
            // That part alone could not be read: its caller fails the way its
            // own route's failure would have reached it, the rest are answered.
            entry.reject(
              new Error(
                `the daemon could not read this thread's ${entry.part}`,
              ),
            );
          } else {
            entry.resolve(value);
          }
        }
      },
      (reason: unknown) => {
        for (const entry of batch) {
          entry.reject(reason);
        }
      },
    );
  };

  const batched = <M extends BatchedMethod>(method: M): ChatsApi[M] => {
    const own = api[method].bind(api) as (
      ...args: Parameters<ChatsApi[M]>
    ) => ReturnType<ChatsApi[M]>;
    return ((...args: Parameters<ChatsApi[M]>) => {
      const [params, initOverrides] = args as [{ runId: string }, unknown?];
      if (initOverrides !== undefined) {
        return own(...args);
      }
      return new Promise<unknown>((resolve, reject) => {
        const batch = waiting.get(params.runId);
        const entry: Waiting = {
          part: BATCHED[method],
          alone: () => own(...args),
          resolve,
          reject,
        };
        if (batch === undefined) {
          waiting.set(params.runId, [entry]);
          // Every hook of a thread opening asks from an effect of the same
          // commit, all before the first microtask runs.
          queueMicrotask(() => flush(params.runId));
        } else {
          batch.push(entry);
        }
      });
    }) as ChatsApi[M];
  };

  for (const method of Object.keys(BATCHED) as BatchedMethod[]) {
    Object.assign(api, { [method]: batched(method) });
  }
  return api;
}
