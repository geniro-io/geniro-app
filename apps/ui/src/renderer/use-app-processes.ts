import { useCallback } from 'react';

import type { AppProcessesDto } from './autogenerated';
import type { DaemonApis } from './daemon-api';
import { type PolledReadState, usePolledRead } from './use-polled-read';

export type AppProcessesState = PolledReadState<AppProcessesDto>;

/**
 * What the whole app is running, by thread — polled only while the title
 * bar's usage panel is open. Closed, it costs nothing: the readout is a
 * question the user asks, not a figure the bar keeps current.
 */
export function useAppProcesses(
  apis: DaemonApis | null,
  enabled: boolean,
): AppProcessesState {
  const read = useCallback(
    (): Promise<AppProcessesDto> =>
      apis
        ? apis.chats.readAppProcesses()
        : Promise.reject(new Error('offline')),
    [apis],
  );
  return usePolledRead(
    apis && enabled ? read : null,
    null,
    'could not read the app’s processes',
  );
}
