// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { BACKGROUND_JOBS, backgroundJob } from './__fixtures__/background-jobs';
import type { BackgroundJobListDto } from './autogenerated';
import type { DaemonApis } from './daemon-api';
import type { DaemonClient } from './daemon-client';
import {
  BACKGROUND_JOBS_RECENT,
  type BackgroundJobHistory,
  useBackgroundJobHistory,
  useBackgroundJobs,
} from './use-background-jobs';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;
let changed: (() => void)[];
let reconnected: (() => void)[];
let listBackgroundJobs: ReturnType<typeof vi.fn>;
let apis: DaemonApis;
let client: DaemonClient;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  changed = [];
  reconnected = [];
  listBackgroundJobs = vi.fn(() => Promise.resolve(BACKGROUND_JOBS));
  apis = {
    backgroundJobs: { listBackgroundJobs },
  } as unknown as DaemonApis;
  client = {
    onBackgroundJobsChanged: (listener: () => void) => {
      changed.push(listener);
      return () => undefined;
    },
    onReconnect: (listener: () => void) => {
      reconnected.push(listener);
      return () => undefined;
    },
  } as unknown as DaemonClient;
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
});

async function flush(): Promise<void> {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
  });
}

describe('useBackgroundJobs', () => {
  let seen: { data: BackgroundJobListDto | null; error: string | null }[];

  function Probe(): null {
    seen.push(useBackgroundJobs(apis, client));
    return null;
  }

  beforeEach(() => {
    seen = [];
  });

  it('reads the active jobs and the newest finished ones on mount, on every change and after a reconnect', async () => {
    act(() => root.render(<Probe />));
    await flush();

    expect(listBackgroundJobs).toHaveBeenCalledWith({
      limit: BACKGROUND_JOBS_RECENT,
    });
    expect(seen.at(-1)?.data).toEqual(BACKGROUND_JOBS);

    changed.forEach((listener) => listener());
    reconnected.forEach((listener) => listener());
    await flush();

    expect(listBackgroundJobs).toHaveBeenCalledTimes(3);
  });

  it('keeps the last answer and says why a read failed', async () => {
    act(() => root.render(<Probe />));
    await flush();
    listBackgroundJobs.mockRejectedValueOnce(new Error('daemon down'));

    changed.forEach((listener) => listener());
    await flush();

    expect(seen.at(-1)).toEqual({
      data: BACKGROUND_JOBS,
      error: 'Error: daemon down',
    });
  });
});

describe('useBackgroundJobHistory', () => {
  let history: BackgroundJobHistory | null;

  function Probe({ open }: { open: boolean }): null {
    history = useBackgroundJobHistory(apis, client, open);
    return null;
  }

  beforeEach(() => {
    history = null;
  });

  it('reads nothing while closed', async () => {
    act(() => root.render(<Probe open={false} />));
    await flush();

    expect(listBackgroundJobs).not.toHaveBeenCalled();
  });

  it('pages the history from the cursor and starts over on a change', async () => {
    const older = backgroundJob({ id: 'lessons:old' });
    listBackgroundJobs
      .mockResolvedValueOnce({ ...BACKGROUND_JOBS, nextBefore: 'cursor-1' })
      .mockResolvedValueOnce({
        active: [],
        finished: [older],
        nextBefore: null,
        running: 0,
      });
    act(() => root.render(<Probe open />));
    await flush();

    expect(history?.jobs).toHaveLength(5);
    expect(history?.hasMore).toBe(true);

    act(() => history?.loadMore());
    await flush();

    expect(listBackgroundJobs).toHaveBeenLastCalledWith(
      expect.objectContaining({ before: 'cursor-1' }),
    );
    expect(history?.jobs.at(-1)?.id).toBe('lessons:old');
    expect(history?.hasMore).toBe(false);

    act(() => changed.forEach((listener) => listener()));
    await flush();

    expect(listBackgroundJobs).toHaveBeenLastCalledWith(
      expect.not.objectContaining({ before: expect.anything() }),
    );
    expect(history?.jobs).toHaveLength(5);
  });
});
