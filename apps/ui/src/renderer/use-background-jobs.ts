import { useEffect, useRef, useState } from 'react';

import type { BackgroundJob, BackgroundJobListDto } from './autogenerated';
import { useLatestCallback } from './components/use-latest-callback';
import type { DaemonApis } from './daemon-api';
import type { DaemonClient } from './daemon-client';

/** How many finished jobs the title bar's panel lists under the active ones. */
export const BACKGROUND_JOBS_RECENT = 8;
/** How many finished jobs one page of the full history reads. */
export const BACKGROUND_JOBS_HISTORY_PAGE = 20;

/**
 * The title bar's background work: every active job and the newest finished
 * ones, read on mount, on every `background_jobs_changed` and after a
 * reconnect. Nothing polls: a job's every move is announced. A failed read
 * keeps the last answer and says why.
 */
export function useBackgroundJobs(
  apis: DaemonApis | null,
  client: DaemonClient | null,
): { data: BackgroundJobListDto | null; error: string | null } {
  const [data, setData] = useState<BackgroundJobListDto | null>(null);
  const [error, setError] = useState<string | null>(null);
  const read = useLatestCallback(() => {
    if (apis === null) {
      return;
    }
    void apis.backgroundJobs
      .listBackgroundJobs({ limit: BACKGROUND_JOBS_RECENT })
      .then((answer) => {
        setData(answer);
        setError(null);
      })
      .catch((err: unknown) => setError(String(err)));
  }, [apis]);

  useEffect(() => {
    read();
    if (client === null) {
      return;
    }
    const offChanged = client.onBackgroundJobsChanged(read);
    const offReconnect = client.onReconnect(read);
    return () => {
      offChanged();
      offReconnect();
    };
  }, [apis, client, read]);

  return { data, error };
}

/** The full history, page by page, while its dialog is open. */
export interface BackgroundJobHistory {
  jobs: BackgroundJob[];
  hasMore: boolean;
  loading: boolean;
  error: string | null;
  loadMore: () => void;
}

/**
 * Every background job, newest first, read a page at a time while `open`.
 * A `background_jobs_changed` re-reads from the first page, so a job that
 * moved is never shown twice or in an old state.
 */
export function useBackgroundJobHistory(
  apis: DaemonApis | null,
  client: DaemonClient | null,
  open: boolean,
): BackgroundJobHistory {
  const [jobs, setJobs] = useState<BackgroundJob[]>([]);
  const [nextBefore, setNextBefore] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [generation, setGeneration] = useState(0);
  const generationRef = useRef(generation);
  generationRef.current = generation;

  const readPage = useLatestCallback(
    (before: string | null, from: number): void => {
      if (apis === null) {
        return;
      }
      setLoading(true);
      void apis.backgroundJobs
        .listBackgroundJobs({
          limit: BACKGROUND_JOBS_HISTORY_PAGE,
          ...(before === null ? {} : { before }),
        })
        .then((answer) => {
          if (from !== generationRef.current) {
            return;
          }
          setJobs((shown) =>
            before === null
              ? [...answer.active, ...answer.finished]
              : [...shown, ...answer.finished],
          );
          setNextBefore(answer.nextBefore);
          setError(null);
        })
        .catch((err: unknown) => {
          if (from === generationRef.current) {
            setError(String(err));
          }
        })
        .finally(() => {
          if (from === generationRef.current) {
            setLoading(false);
          }
        });
    },
    [apis],
  );
  useEffect(() => {
    if (!open) {
      return;
    }
    readPage(null, generation);
  }, [open, generation, readPage]);

  useEffect(() => {
    if (!open || client === null) {
      return;
    }
    const restart = (): void => setGeneration((count) => count + 1);
    const offChanged = client.onBackgroundJobsChanged(restart);
    const offReconnect = client.onReconnect(restart);
    return () => {
      offChanged();
      offReconnect();
    };
  }, [open, client]);

  return {
    jobs,
    hasMore: nextBefore !== null,
    loading,
    error,
    loadMore: () => {
      if (nextBefore !== null && !loading) {
        readPage(nextBefore, generation);
      }
    },
  };
}
