// @vitest-environment jsdom
import { act, useEffect } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { identity as sharedIdentity } from './__tests__/agent-identities';
import type { AgentIdentityCapability, CapabilitiesDto } from './autogenerated';
import type { DaemonApis } from './daemon-api';
import {
  CapabilitiesContext,
  type CapabilitiesState,
  useAgentIdentities,
  useCapabilities,
  useSharedCapabilities,
} from './use-capabilities';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
  vi.useRealTimers();
});

/**
 * One probed mode's status, as `capabilities.approvals[0].probe` would carry
 * it for claude — the one CLI with a `requiresPass` row today.
 */
function caps(
  acceptEdits: 'pass' | 'fail' | 'unknown',
  plan: 'pass' | 'fail' | 'unknown' = 'pass',
): CapabilitiesDto {
  return {
    approvals: [
      {
        agent: 'claude',
        modes: ['auto', 'ask', 'acceptEdits', 'plan'],
        probe: {
          modes: [
            { mode: 'acceptEdits', status: acceptEdits, requiresPass: false },
            { mode: 'plan', status: plan, requiresPass: true },
          ],
          version: 'claude 2',
          probedAt: 1,
          reason: null,
        },
      },
    ],
    configDirs: [{ agent: 'claude', unavailableReason: null }],
  } as unknown as CapabilitiesDto;
}

function api(
  getCapabilities: () => Promise<CapabilitiesDto>,
): DaemonApis['capabilities'] {
  return { getCapabilities } as unknown as DaemonApis['capabilities'];
}

/** The `acceptEdits` probe row's status off claude's approval capability. */
function acceptEditsStatus(state: CapabilitiesState | null): unknown {
  return state?.capabilities?.approvals[0]?.probe?.modes.find(
    (mode) => mode.mode === 'acceptEdits',
  )?.status;
}

async function mount(
  capabilitiesApi: DaemonApis['capabilities'] | null,
): Promise<() => CapabilitiesState | null> {
  let latest: CapabilitiesState | null = null;
  function Probe(): null {
    latest = useCapabilities(capabilitiesApi);
    return null;
  }
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<Probe />);
  });
  return () => latest;
}

/**
 * Mounts the hook and records what each COMMITTED render handed out. A render
 * React bails out of runs no effect, so the list's length is how many times the
 * app would actually have been redrawn — which a bare `latest` cannot say.
 */
async function mountRecording(
  capabilitiesApi: DaemonApis['capabilities'] | null,
): Promise<CapabilitiesState[]> {
  const committed: CapabilitiesState[] = [];
  function Probe(): null {
    const state = useCapabilities(capabilitiesApi);
    useEffect(() => {
      committed.push(state);
    });
    return null;
  }
  container = document.createElement('div');
  document.body.append(container);
  root = createRoot(container);
  await act(async () => {
    root!.render(<Probe />);
  });
  return committed;
}

describe('useCapabilities', () => {
  it('asks ONCE when the probe already answered', async () => {
    // The settled case is the common one. Re-asking a resolved verdict would
    // re-run this read on a timer for the life of the screen.
    const getCapabilities = vi.fn(() => Promise.resolve(caps('pass')));
    vi.useFakeTimers();
    const latest = await mount(api(getCapabilities));
    await act(async () => {
      await vi.advanceTimersByTimeAsync(30_000);
    });

    expect(acceptEditsStatus(latest())).toBe('pass');
    expect(getCapabilities).toHaveBeenCalledTimes(1);
  });

  it('re-asks while the probe is UNSETTLED, then stops once it lands', async () => {
    // Reading this endpoint is also what pre-warms the daemon's probe, so a
    // cold launch answers `unknown` through no fault of the request. Without
    // the re-ask the verdict only reaches the screen after a remount — which
    // is the bug that made the chat screen grow its own fetcher in the first
    // place.
    vi.useFakeTimers();
    const getCapabilities = vi
      .fn(() => Promise.resolve(caps('unknown')))
      .mockImplementationOnce(() => Promise.resolve(caps('unknown')))
      .mockImplementation(() => Promise.resolve(caps('pass')));

    const latest = await mount(api(getCapabilities));
    expect(acceptEditsStatus(latest())).toBe('unknown');

    await act(async () => {
      await vi.advanceTimersByTimeAsync(2_000);
    });
    expect(acceptEditsStatus(latest())).toBe('pass');

    const settledCalls = getCapabilities.mock.calls.length;
    await act(async () => {
      await vi.advanceTimersByTimeAsync(30_000);
    });
    // Stopped: a settled verdict is not re-asked.
    expect(getCapabilities).toHaveBeenCalledTimes(settledCalls);
  });

  it('keeps re-asking for as long as the approval probe can take', async () => {
    // This is the app's one read, so no screen opened later asks again: a
    // verdict that settles after the poll gave up would never reach the
    // screen. The probe runs its modes one after another, 30s each, so the
    // answer can be a minute away.
    vi.useFakeTimers();
    let calls = 0;
    const getCapabilities = vi.fn(() => {
      calls += 1;
      // Unsettled for the first minute of re-asks (one every 2s).
      return Promise.resolve(caps(calls <= 31 ? 'unknown' : 'pass'));
    });
    const latest = await mount(api(getCapabilities));
    await act(async () => {
      await vi.advanceTimersByTimeAsync(70_000);
    });

    expect(acceptEditsStatus(latest())).toBe('pass');
  });

  const neverSettles: [string, () => Promise<CapabilitiesDto>][] = [
    [
      'an answer whose probe never settles',
      () => Promise.resolve(caps('unknown')),
    ],
    ['a read that keeps failing', () => Promise.reject(new Error('down'))],
  ];

  it.each(neverSettles)(
    'gives up after a bounded number of tries on %s',
    async (_case, read) => {
      // Neither a probe that never settles nor a daemon that keeps refusing may
      // be polled forever — the two re-ask down different paths.
      vi.useFakeTimers();
      const getCapabilities = vi.fn(read);
      await mount(api(getCapabilities));
      await act(async () => {
        await vi.advanceTimersByTimeAsync(120_000);
      });
      expect(getCapabilities).toHaveBeenCalledTimes(41);

      await act(async () => {
        await vi.advanceTimersByTimeAsync(120_000);
      });
      // The initial read plus MAX_POLLS re-asks, and no more.
      expect(getCapabilities).toHaveBeenCalledTimes(41);
    },
  );

  it('keeps the held answer, and commits nothing, while re-asks come back unchanged', async () => {
    // A CLI that is not installed leaves its probe row `unknown` for the
    // daemon's whole life, so the answer never settles and every re-ask says
    // the same thing — each time as a NEW object, which React reads as a state
    // change.
    vi.useFakeTimers();
    const getCapabilities = vi.fn(() => Promise.resolve(caps('unknown')));
    const committed = await mountRecording(api(getCapabilities));
    expect(acceptEditsStatus(committed.at(-1) ?? null)).toBe('unknown');
    const held = committed.at(-1)?.capabilities;
    const commitsBefore = committed.length;

    // One poll per act, as they arrive in real time — inside a single act React
    // would fold ten committed reads into one and blur what is being counted.
    for (let poll = 0; poll < 10; poll += 1) {
      await act(async () => {
        await vi.advanceTimersByTimeAsync(2_000);
      });
    }

    // The reads went on...
    expect(getCapabilities).toHaveBeenCalledTimes(11);
    // ...and not one of them reached the screen.
    expect(committed).toHaveLength(commitsBefore);
    expect(committed.at(-1)?.capabilities).toBe(held);
  });

  it('replaces the held answer as soon as one differs, however deep the difference', async () => {
    // The guard above must not turn into "the first answer wins": compared as
    // content, a status three levels down still counts.
    vi.useFakeTimers();
    const getCapabilities = vi
      .fn(() => Promise.resolve(caps('pass')))
      .mockImplementationOnce(() => Promise.resolve(caps('unknown')))
      .mockImplementationOnce(() => Promise.resolve(caps('unknown')));
    const committed = await mountRecording(api(getCapabilities));
    const held = committed.at(-1)?.capabilities;
    const commitsBefore = committed.length;

    await act(async () => {
      await vi.advanceTimersByTimeAsync(2_000);
    });
    expect(committed).toHaveLength(commitsBefore);
    expect(committed.at(-1)?.capabilities).toBe(held);

    await act(async () => {
      await vi.advanceTimersByTimeAsync(2_000);
    });
    expect(committed).toHaveLength(commitsBefore + 1);
    expect(committed.at(-1)?.capabilities).not.toBe(held);
    expect(acceptEditsStatus(committed.at(-1) ?? null)).toBe('pass');
  });

  it('asks again after a failed read, and fills the answer in when it lands', async () => {
    // Nothing else asks: a transient refusal must not leave every screen
    // without an answer until the daemon is next restarted.
    vi.useFakeTimers();
    const getCapabilities = vi
      .fn(() => Promise.resolve(caps('pass')))
      .mockImplementationOnce(() => Promise.reject(new Error('busy')));
    const latest = await mount(api(getCapabilities));
    expect(latest()?.capabilities).toBeNull();
    expect(latest()?.loading).toBe(false);

    await act(async () => {
      await vi.advanceTimersByTimeAsync(2_000);
    });

    expect(acceptEditsStatus(latest())).toBe('pass');
    expect(getCapabilities).toHaveBeenCalledTimes(2);
  });

  it('keeps the answer already on screen when a RE-ask fails', async () => {
    // One refused request says nothing new about any CLI, so the screens go on
    // drawing what this daemon already said rather than falling back to "not
    // answered" until the next re-ask lands.
    vi.useFakeTimers();
    const getCapabilities = vi
      .fn(() => Promise.resolve(caps('pass')))
      .mockImplementationOnce(() => Promise.resolve(caps('unknown')))
      .mockImplementationOnce(() => Promise.reject(new Error('busy')));
    const latest = await mount(api(getCapabilities));
    expect(acceptEditsStatus(latest())).toBe('unknown');

    await act(async () => {
      await vi.advanceTimersByTimeAsync(2_000);
    });
    expect(acceptEditsStatus(latest())).toBe('unknown');

    await act(async () => {
      await vi.advanceTimersByTimeAsync(2_000);
    });
    expect(acceptEditsStatus(latest())).toBe('pass');
  });

  it('stops re-asking once unmounted', async () => {
    // A pending re-ask that outlives the unmount fires against a daemon handle
    // the app has already replaced.
    vi.useFakeTimers();
    const getCapabilities = vi.fn(() => Promise.resolve(caps('unknown')));
    await mount(api(getCapabilities));
    const beforeUnmount = getCapabilities.mock.calls.length;

    act(() => {
      root?.unmount();
      root = null;
    });
    await act(async () => {
      await vi.advanceTimersByTimeAsync(30_000);
    });

    expect(getCapabilities).toHaveBeenCalledTimes(beforeUnmount);
  });

  it('reports LOADING true until the first read settles, then clears it', async () => {
    // The distinction the whole widened return exists for: a caller must be
    // able to tell "still asking" from "asked and got an answer" without
    // reading `capabilities === null`, which is also true before anything was
    // asked at all.
    let resolveRead!: (value: CapabilitiesDto) => void;
    const getCapabilities = vi.fn(
      () =>
        new Promise<CapabilitiesDto>((resolve) => {
          resolveRead = resolve;
        }),
    );
    const latest = await mount(api(getCapabilities));

    expect(latest()?.loading).toBe(true);
    expect(latest()?.capabilities).toBeNull();

    await act(async () => {
      resolveRead(caps('pass'));
    });

    expect(latest()?.loading).toBe(false);
    expect(acceptEditsStatus(latest())).toBe('pass');
  });

  it('fails OPEN — a failed read is null, not a negative verdict — and ENDS the loading state', async () => {
    // An unreachable daemon is not evidence about any CLI. Callers read null
    // as "not answered" and render nothing rather than a refusal.
    //
    // The read still SETTLED, though: it just settled with nothing. A caller
    // reading `capabilities === null` alone cannot tell that apart from "still
    // asking", which is exactly the bug this field exists to fix — a
    // `LoadingChip` driven off that reading spun for the life of the daemon
    // handle over a probe that had already given up.
    const latest = await mount(api(() => Promise.reject(new Error('down'))));

    expect(latest()?.capabilities).toBeNull();
    expect(latest()?.loading).toBe(false);
  });

  it('treats an answer it cannot read as no answer, never as the one to keep', async () => {
    // A shape this hook cannot evaluate fails open like a refused read — held
    // on to, it would be handed to every screen, which then read fields it
    // does not have.
    const latest = await mount(
      api(() => Promise.resolve({} as unknown as CapabilitiesDto)),
    );

    expect(latest()?.capabilities).toBeNull();
    expect(latest()?.loading).toBe(false);
  });

  it('asks nothing at all before a daemon handle exists', async () => {
    const latest = await mount(null);

    expect(latest()?.capabilities).toBeNull();
    expect(latest()?.loading).toBe(false);
  });
});

describe('useSharedCapabilities', () => {
  async function mountShared(
    capabilitiesApi: DaemonApis['capabilities'] | null,
    provided: CapabilitiesState | null,
  ): Promise<() => CapabilitiesState | null> {
    let latest: CapabilitiesState | null = null;
    function Probe(): null {
      latest = useSharedCapabilities(capabilitiesApi);
      return null;
    }
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
    await act(async () => {
      root!.render(
        provided === null ? (
          <Probe />
        ) : (
          <CapabilitiesContext.Provider value={provided}>
            <Probe />
          </CapabilitiesContext.Provider>
        ),
      );
    });
    return () => latest;
  }

  it('reads the app’s answer and asks nothing of its own under a provider', async () => {
    // The point of the shared read: a screen inside the app cannot draw from
    // a second answer that settled differently from the one around it.
    const getCapabilities = vi.fn(() => Promise.resolve(caps('fail')));
    const latest = await mountShared(api(getCapabilities), {
      capabilities: caps('pass'),
      loading: false,
    });

    expect(acceptEditsStatus(latest())).toBe('pass');
    expect(getCapabilities).not.toHaveBeenCalled();
  });

  it('reads for itself when no provider is around it', async () => {
    // A screen rendered alone — a spec, the component catalog — still works.
    const getCapabilities = vi.fn(() => Promise.resolve(caps('pass')));
    const latest = await mountShared(api(getCapabilities), null);

    expect(acceptEditsStatus(latest())).toBe('pass');
    expect(getCapabilities).toHaveBeenCalledTimes(1);
  });
});

describe('useAgentIdentities', () => {
  function identity(displayName: string): AgentIdentityCapability {
    return { ...sharedIdentity('claude', 'claude', 'bot'), displayName };
  }

  /** A whole answer: the probe status and the identities are independent. */
  function answer(
    acceptEdits: 'pass' | 'unknown',
    displayName: string,
  ): CapabilitiesDto {
    return { ...caps(acceptEdits), agents: [identity(displayName)] };
  }

  async function mountIdentities(): Promise<
    (
      capabilities: CapabilitiesDto | null,
    ) => Promise<readonly AgentIdentityCapability[]>
  > {
    let latest: readonly AgentIdentityCapability[] = [];
    function Probe({
      capabilities,
    }: {
      capabilities: CapabilitiesDto | null;
    }): null {
      latest = useAgentIdentities(capabilities);
      return null;
    }
    container = document.createElement('div');
    document.body.append(container);
    root = createRoot(container);
    return async (capabilities) => {
      await act(async () => {
        root!.render(<Probe capabilities={capabilities} />);
      });
      return latest;
    };
  }

  it('keeps the same array while the identities are unchanged, whatever else the answer says', async () => {
    // A probe row settling hands `App` a whole new answer — new objects all the
    // way down — and the array under `AgentIdentityContext` must not follow it
    // into every memoized reader.
    const render = await mountIdentities();
    const first = await render(answer('unknown', 'Claude'));
    expect(first.map((agent) => agent.displayName)).toEqual(['Claude']);

    const settled = await render(answer('pass', 'Claude'));
    expect(settled).toBe(first);

    const renamed = await render(answer('pass', 'Claude Code'));
    expect(renamed).not.toBe(first);
    expect(renamed.map((agent) => agent.displayName)).toEqual(['Claude Code']);
  });

  it('keeps one empty array for as long as nothing has answered', async () => {
    // An unanswered read means "not answered yet", and every reader treats the
    // empty list that way — which is a new list per render unless held.
    const render = await mountIdentities();
    const none = await render(null);
    expect(none).toEqual([]);

    expect(await render(null)).toBe(none);
  });
});
