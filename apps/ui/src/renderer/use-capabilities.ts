import { createContext, useContext, useEffect, useMemo, useState } from 'react';

import type { CapabilitiesDto } from './autogenerated';
import type { DaemonApis } from './daemon-api';

/**
 * How often an unsettled or failed read is re-asked, and how many times.
 *
 * The budget outlasts the slowest thing that leaves an answer unsettled — the
 * daemon's approval probe, which runs a CLI's probed modes one after another
 * under a per-mode bound (claude's: two modes, 30s each). It has to: this is
 * the app's ONE read, so a screen opened after it gives up reads the same
 * answer rather than asking again, and nothing else would carry a verdict
 * that settled late to the screen.
 */
const POLL_INTERVAL_MS = 2_000;
const MAX_POLLS = 40;

/** What {@link useCapabilities} answers. */
export interface CapabilitiesState {
  /**
   * The daemon's answer, or `null` while unread — see the fail-open note
   * below for the other way this stays `null`.
   */
  capabilities: CapabilitiesDto | null;
  /**
   * Whether the FIRST read is still outstanding — cleared the moment it
   * settles, whichever way: a landed answer and a failed read both clear it,
   * so a caller can tell "still asking" from "asked and got nothing", which
   * `capabilities === null` alone cannot. The background re-asks that follow
   * (an unsettled probe, a failed read) do not reopen this — they refine or
   * retry an answer rather than gate whether one exists yet.
   */
  loading: boolean;
}

/**
 * `GET /v1/capabilities` — the machine's feature availability, read ONCE per
 * daemon handle by `App` and shared with every screen through
 * {@link CapabilitiesContext}.
 *
 * One read on purpose, not merely one fetcher: two reads can settle
 * differently — one answered while the other failed — and a screen drawing
 * from both would describe the same CLI two ways at once. Screens read the
 * shared answer through {@link useSharedCapabilities}.
 *
 * RE-ASKS WHILE UNSETTLED, which is the behaviour worth sharing. Reading this
 * endpoint is also what PRE-WARMS the daemon's per-mode approval probes (a
 * `requiresPass` row — claude's `plan` today), so on a cold launch the first
 * answer comes back `unknown` through no fault of the request. Re-asking, within
 * the budget above, is what lets the verdict reach the screen this session.
 *
 * Fails OPEN: a failed first read yields `capabilities: null`, and every caller
 * treats that as "not answered" rather than as a negative verdict — an
 * unreachable daemon is not evidence about any CLI. What the failure DOES
 * clear is `loading`: the read settled, it just settled with nothing, and a
 * caller that conflated the two spun a waiting chip for the life of the handle
 * over a probe that had already given up. A failed read is still ASKED AGAIN,
 * because nothing else will ask: a transient refusal must not leave every
 * screen without an answer until the daemon is next restarted. A failed
 * RE-ask keeps the answer this daemon already gave, since one refused request
 * says nothing new about any CLI.
 */
export function useCapabilities(
  capabilitiesApi: DaemonApis['capabilities'] | null,
): CapabilitiesState {
  const [capabilities, setCapabilities] = useState<CapabilitiesDto | null>(
    null,
  );
  const [loading, setLoading] = useState(capabilitiesApi !== null);

  useEffect(() => {
    if (capabilitiesApi === null) {
      setCapabilities(null);
      setLoading(false);
      return;
    }
    let cancelled = false;
    let attempts = 0;
    let answered = false;
    let timer: number | undefined;
    setLoading(true);
    const askAgain = (): void => {
      if (attempts < MAX_POLLS) {
        attempts += 1;
        timer = window.setTimeout(poll, POLL_INTERVAL_MS);
      }
    };
    const poll = (): void => {
      void capabilitiesApi
        .getCapabilities()
        .then((caps) => {
          if (cancelled) {
            return;
          }
          // Only a CLI's own approval probes are asynchronous daemon-side; the
          // config-dir answers are compile-time config and are settled on the
          // first read. Any agent's probe row still `unknown` means at least
          // one mode has not settled — the same reading `approvalOptions`
          // takes per row. Read BEFORE the answer is committed: one this
          // cannot read throws into the catch below as a failed read, rather
          // than becoming the answer every screen keeps.
          const unsettled = caps.approvals.some((agent) =>
            agent.probe?.modes.some((mode) => mode.status === 'unknown'),
          );
          answered = true;
          setCapabilities(caps);
          setLoading(false);
          if (unsettled) {
            askAgain();
          }
        })
        .catch(() => {
          if (cancelled) {
            return;
          }
          if (!answered) {
            setCapabilities(null);
          }
          setLoading(false);
          askAgain();
        });
    };
    poll();
    return () => {
      cancelled = true;
      // Without this a pending re-ask outlives the unmount and fires against a
      // daemon handle the app has already replaced.
      window.clearTimeout(timer);
    };
  }, [capabilitiesApi]);

  // Stable while nothing changed: `App` provides this object as a context
  // value, and a fresh one per render would re-render every screen reading it.
  return useMemo(() => ({ capabilities, loading }), [capabilities, loading]);
}

/**
 * The app's one capabilities read, provided by `App` around every view.
 *
 * `null` outside a provider — a spec or the component catalog rendering a
 * screen on its own — which {@link useSharedCapabilities} answers by reading
 * for itself.
 */
export const CapabilitiesContext = createContext<CapabilitiesState | null>(
  null,
);

/**
 * `GET /v1/capabilities` as a screen reads it: the app's shared answer when
 * `App` provides one, so nothing on screen can be drawn from a second read
 * that settled differently. Outside a provider it reads for itself through the
 * api it is handed, so a screen rendered alone behaves as it always did — the
 * rule `chats/thread-ui-memory.ts` follows for its own context.
 *
 * The hook is called with a null api under a provider rather than skipped,
 * because a hook cannot be called conditionally — a null api asks nothing.
 */
export function useSharedCapabilities(
  capabilitiesApi: DaemonApis['capabilities'] | null,
): CapabilitiesState {
  const shared = useContext(CapabilitiesContext);
  const own = useCapabilities(shared === null ? capabilitiesApi : null);
  return shared ?? own;
}
