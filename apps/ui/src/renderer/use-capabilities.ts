import { useEffect, useState } from 'react';

import type { CapabilitiesDto } from './autogenerated';
import type { DaemonApis } from './daemon-api';

/** How often an unsettled probe is re-asked, and how many times. */
const POLL_INTERVAL_MS = 2_000;
const MAX_POLLS = 5;

/**
 * `GET /v1/capabilities` — the machine's feature availability, read ONCE per
 * daemon handle and shared by every surface that needs it.
 *
 * One fetcher on purpose. Two screens read this endpoint (the chat composer,
 * for whether claude's `plan` mode is usable; the workflow builder, for whether
 * a CLI can load a plugin directory), and when each owned its own effect they
 * had different loading, retry and error policies for the same request — so a
 * fix to one silently did not reach the other.
 *
 * POLLS WHILE UNSETTLED, which is the behaviour worth sharing. Reading this
 * endpoint is also what PRE-WARMS the daemon's permission-mode probe, so on a
 * cold launch the first answer comes back `unknown` through no fault of the
 * request. Re-asking a bounded number of times is what lets the pre-warmed
 * verdict actually reach the screen this session rather than only after a
 * remount.
 *
 * Fails OPEN: a failed read yields `null`, and every caller treats that as
 * "not answered" rather than as a negative verdict — an unreachable daemon is
 * not evidence about any CLI.
 */
export function useCapabilities(
  capabilitiesApi: DaemonApis['capabilities'] | null,
): CapabilitiesDto | null {
  const [capabilities, setCapabilities] = useState<CapabilitiesDto | null>(
    null,
  );

  useEffect(() => {
    if (capabilitiesApi === null) {
      setCapabilities(null);
      return;
    }
    let cancelled = false;
    let attempts = 0;
    let timer: number | undefined;
    const poll = (): void => {
      void capabilitiesApi
        .getCapabilities()
        .then((caps) => {
          if (cancelled) {
            return;
          }
          setCapabilities(caps);
          // Only the claude mode probe is asynchronous daemon-side; the plugin
          // answers are compile-time config and are settled on the first read.
          const unsettled =
            caps.claudeModes.acceptEdits === 'unknown' ||
            caps.claudeModes.plan === 'unknown';
          if (unsettled && attempts < MAX_POLLS) {
            attempts += 1;
            timer = window.setTimeout(poll, POLL_INTERVAL_MS);
          }
        })
        .catch(() => {
          if (!cancelled) {
            setCapabilities(null);
          }
        });
    };
    poll();
    return () => {
      cancelled = true;
      // Without this a pending re-ask outlives the unmount and fires against a
      // daemon handle the app has already replaced.
      window.clearTimeout(timer);
    };
  }, [capabilitiesApi]);

  return capabilities;
}
