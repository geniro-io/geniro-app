import { describe, expect, it } from 'vitest';

import type { CliDetection, CliInstallResult } from '../shared/contracts';
import type { LoginSessionDto } from './autogenerated';
import { signInAfterInstall } from './use-cli-install';

const installed: CliInstallResult = {
  kind: 'codex',
  ok: true,
  version: 'codex-cli 0.162.0',
  path: '/home/u/.local/bin/codex',
  output: null,
  reason: null,
};

function detected(loggedIn: boolean | null): CliDetection[] {
  return [
    {
      kind: 'codex',
      found: true,
      path: '/home/u/.local/bin/codex',
      version: 'codex-cli 0.162.0',
      loggedIn,
      update: {
        available: null,
        latestVersion: null,
        checkUnavailableReason: null,
      },
    },
  ];
}

const idle = { login: null, starting: null };

function running(status: LoginSessionDto['status']) {
  return {
    starting: null,
    login: {
      kind: 'claude' as const,
      server: null,
      configDir: null,
      session: { id: 's1', status } as LoginSessionDto,
    },
  };
}

describe('signInAfterInstall', () => {
  it('signs in a fresh CLI that says it is signed out', () => {
    expect(signInAfterInstall(installed, detected(false), idle)).toBe(true);
  });

  it('does not sign in on a guess — signed in, or a probe that could not tell', () => {
    expect(signInAfterInstall(installed, detected(true), idle)).toBe(false);
    expect(signInAfterInstall(installed, detected(null), idle)).toBe(false);
  });

  it('does not sign in after a failed install', () => {
    expect(
      signInAfterInstall({ ...installed, ok: false }, detected(false), idle),
    ).toBe(false);
  });

  it('never starts over a sign-in already running or being started', () => {
    expect(
      signInAfterInstall(installed, detected(false), running('waiting')),
    ).toBe(false);
    expect(
      signInAfterInstall(installed, detected(false), {
        login: null,
        starting: { kind: 'claude', server: null, configDir: null },
      }),
    ).toBe(false);
    // A finished panel left on screen owns nothing.
    expect(
      signInAfterInstall(installed, detected(false), running('succeeded')),
    ).toBe(true);
  });
});
