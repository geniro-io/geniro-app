// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { LoginSessionDto } from './autogenerated';
import type { DaemonApis } from './daemon-api';
import {
  type CliLoginController,
  type CliLoginState,
  useCliLogin,
} from './use-cli-login';

const waiting: LoginSessionDto = {
  id: 'login-1',
  agent: 'claude',
  status: 'waiting',
  url: 'https://example.test/auth',
  message: null,
};

const notFound = (): Error =>
  new Error(
    'daemon GET /v1/auth/login/login-1 failed (404): {"code":"CLI_LOGIN_NOT_FOUND"}',
  );

function mount(cliAuth: Partial<DaemonApis['cliAuth']>): {
  controller: () => CliLoginController;
  settled: CliLoginState[];
} {
  const apis = { cliAuth } as unknown as DaemonApis;
  const settled: CliLoginState[] = [];
  let latest: CliLoginController | null = null;
  function Probe(): null {
    latest = useCliLogin(apis, (s) => settled.push(s));
    return null;
  }
  act(() => {
    root = createRoot(document.createElement('div'));
    root.render(<Probe />);
  });
  return {
    controller: () => {
      if (latest === null) {
        throw new Error('probe did not render');
      }
      return latest;
    },
    settled,
  };
}

let root: Root | null = null;

beforeEach(() => {
  (
    globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
  ).IS_REACT_ACT_ENVIRONMENT = true;
  vi.useFakeTimers();
});

afterEach(() => {
  act(() => root?.unmount());
  root = null;
  vi.useRealTimers();
});

describe('useCliLogin', () => {
  it('ends a sign-in the daemon has forgotten instead of polling it forever', async () => {
    // A restarted daemon answers 404 for every sign-in it was running; a poll
    // that set an error and asked again would do so every 1.2s for good,
    // under a panel whose only button is a Cancel that 404s too.
    const getCliLogin = vi.fn().mockRejectedValue(notFound());
    const { controller, settled } = mount({
      startCliLogin: vi.fn().mockResolvedValue(waiting),
      getCliLogin,
    });

    await act(async () => {
      await controller().start('claude');
    });
    await act(async () => {
      await vi.advanceTimersByTimeAsync(1_300);
    });

    expect(controller().login?.session.status).toBe('failed');
    expect(settled).toHaveLength(1);
    const calls = getCliLogin.mock.calls.length;
    await act(async () => {
      await vi.advanceTimersByTimeAsync(5_000);
    });
    expect(getCliLogin.mock.calls.length).toBe(calls);
  });

  it('lets Cancel close a sign-in the daemon has forgotten', async () => {
    const { controller, settled } = mount({
      startCliLogin: vi.fn().mockResolvedValue(waiting),
      getCliLogin: vi.fn().mockResolvedValue(waiting),
      cancelCliLogin: vi.fn().mockRejectedValue(notFound()),
    });

    await act(async () => {
      await controller().start('claude');
    });
    await act(async () => {
      await controller().cancel();
    });

    expect(controller().login?.session.status).toBe('failed');
    expect(controller().error).toBeNull();
    expect(settled).toHaveLength(1);
  });

  it('takes back a POLL error once a later poll is answered', async () => {
    const getCliLogin = vi
      .fn()
      .mockRejectedValueOnce(new Error('network down'))
      .mockResolvedValue(waiting);
    const { controller } = mount({
      startCliLogin: vi.fn().mockResolvedValue(waiting),
      getCliLogin,
    });

    await act(async () => {
      await controller().start('claude');
    });
    await act(async () => {
      await vi.advanceTimersByTimeAsync(1_300);
    });
    expect(controller().error).toContain('network down');

    await act(async () => {
      await vi.advanceTimersByTimeAsync(1_300);
    });
    expect(controller().error).toBeNull();
  });

  it('places a refused ACCOUNT sign-in on its own row, not an earlier server’s', async () => {
    const { controller } = mount({
      startMcpLogin: vi.fn().mockRejectedValue(new Error('mcp refused')),
      startCliLogin: vi.fn().mockRejectedValue(new Error('account refused')),
    });

    await act(async () => {
      await controller().startMcp({ kind: 'claude', server: 'linear' });
    });
    expect(controller().errorTarget?.server).toBe('linear');

    await act(async () => {
      await controller().start('claude');
    });
    expect(controller().error).toContain('account refused');
    expect(controller().errorTarget).toEqual({
      kind: 'claude',
      server: null,
      configDir: null,
    });
  });
});
