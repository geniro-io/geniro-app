import { useCallback, useEffect, useRef, useState } from 'react';

import type { CliKind } from '../shared/contracts';
import type { AgentKind, LoginSession } from './autogenerated';
import type { DaemonApis } from './daemon-api';

/** How often to re-ask where a sign-in has got to. */
const POLL_MS = 1_200;

/**
 * One in-flight sign-in, as the Settings card needs to render it.
 *
 * `kind` is here so the caller can tell WHICH card owns the panel: only one
 * sign-in runs at a time, deliberately — two concurrent browser challenges for
 * two CLIs would be indistinguishable in the browser, and the second would look
 * like the first had failed.
 */
export interface CliLoginState {
  kind: CliKind;
  session: LoginSession;
  /**
   * The MCP server this sign-in is for, or null for the CLI's own account.
   *
   * Carried so the panel can NAME what is being signed in to. Two sign-ins look
   * identical once a browser tab is open, and "signing in…" over a list of nine
   * servers is the one caption that answers nothing.
   */
  server: string | null;
}

/**
 * Which sign-in a press has ASKED for, before the daemon has answered.
 *
 * `server` is null for the CLI's own account, matching {@link CliLoginState} —
 * the two describe the same flow either side of the daemon's first reply, and a
 * caller telling rows apart uses the same field on both.
 */
export interface CliLoginTarget {
  kind: CliKind;
  server: string | null;
}

export interface CliLoginController {
  login: CliLoginState | null;
  /**
   * The sign-in a press has started and the daemon has not answered yet, or
   * null.
   *
   * THE REPORTED DEFECT lives in this window: `start` sets `login` only once
   * `POST /v1/auth/login` returns, and that request is held open by the daemon
   * until the CLI prints its URL — measured at 4001ms in the running app, which
   * is exactly the daemon's own `URL_WAIT_MS` ceiling. For those four seconds a
   * browser tab opens somewhere behind the window and nothing in the app moves:
   * the button still reads "Sign in", still enabled, with no panel anywhere.
   * Reported as "I press Sign In and there is no loader, nothing".
   *
   * Set SYNCHRONOUSLY, before the await, which is the whole point — anything
   * derived after it would land in the same window it exists to fill.
   */
  starting: CliLoginTarget | null;
  /**
   * Start one. Resolves when the daemon has answered, not when it finishes.
   *
   * `configDir` is the run's PROFILE, and it is the one thing about an account
   * that is not machine-wide: credentials live in that folder, so a chat pointed
   * at a second profile signed into the default one watches the same turn fail
   * again. Omitted where the caller is configuring the CLI itself (Settings),
   * which always means the default profile.
   */
  start: (kind: CliKind, configDir?: string | null) => Promise<void>;
  /**
   * Start a sign-in to ONE MCP server — the same flow, the same polling, the
   * same cancel, differing only in what the daemon spawns.
   *
   * Here rather than in a hook of its own precisely because the lifecycle is
   * identical: a second copy is where a cancel or a settle would come to be
   * handled two ways.
   *
   * `cwd` is where the CLI resolves the server NAME, so it must be the folder
   * the LISTING the user pressed was taken in. Omitted means the daemon's
   * folder-independent directory — the graph builder's case, whose node
   * inspector lists exactly the servers that do not depend on a folder.
   */
  startMcp: (input: {
    kind: CliKind;
    server: string;
    cwd?: string;
    configDir?: string | null;
  }) => Promise<void>;
  submitCode: (code: string) => Promise<void>;
  cancel: () => Promise<void>;
  /** Dismiss a finished panel without cancelling anything. */
  dismiss: () => void;
  error: string | null;
}

/**
 * Drives a sign-in the DAEMON is running, so no terminal window opens.
 *
 * The polling shape is deliberate over a WS room. This is one short-lived
 * question asked by one open screen, and a room would mean a gateway, a
 * subscription and a reconnect policy for a flow that lasts under a minute —
 * whereas a poll that stops the moment the status is terminal cannot leak a
 * listener. It also degrades correctly: a missed tick costs a second, not the
 * flow.
 *
 * `onSettled` fires once when the CLI exits, whatever the outcome. That is where
 * the caller re-probes detection — the daemon's `succeeded` means only "the
 * command completed cleanly", and whether the user is actually signed in is a
 * question only the CLI's own status command answers.
 *
 * It is handed the sign-in that settled, because ONE controller serves both
 * flows and they are re-probed by different reads: an MCP server's answer is in
 * the server LISTING, an account's is in CLI detection. A caller driving both
 * (the chat screen does) dispatches on `server`; one driving a single flow
 * ignores the argument.
 */
export function useCliLogin(
  apis: DaemonApis | null,
  onSettled: (settled: CliLoginState) => void,
): CliLoginController {
  const [login, setLogin] = useState<CliLoginState | null>(null);
  const [starting, setStarting] = useState<CliLoginTarget | null>(null);
  const [error, setError] = useState<string | null>(null);
  // Read inside the interval, so a re-rendered caller passing a fresh closure
  // does not restart the poll — and the poll always calls the current one.
  const settledRef = useRef(onSettled);
  settledRef.current = onSettled;

  const isOver = (session: LoginSession): boolean =>
    session.status === 'succeeded' ||
    session.status === 'failed' ||
    session.status === 'cancelled';

  useEffect(() => {
    if (!apis || login === null || isOver(login.session)) {
      return;
    }
    const id = login.session.id;
    const kind = login.kind;
    const server = login.server;
    let stopped = false;
    const timer = setInterval(() => {
      void apis.cliAuth
        .getCliLogin({ id })
        .then((session) => {
          if (stopped) {
            return;
          }
          setLogin({ kind, session, server });
          if (isOver(session)) {
            settledRef.current({ kind, session, server });
          }
        })
        .catch((err: unknown) => {
          if (!stopped) {
            setError(String(err));
          }
        });
    }, POLL_MS);
    return () => {
      stopped = true;
      clearInterval(timer);
    };
    // Keyed on the sign-in's IDENTITY and whether it is over — not on the whole
    // session. Re-keying on every field would tear down and rebuild the interval
    // on each progress line, which is how a poll ends up never firing: each new
    // interval starts its wait from zero.
  }, [apis, login?.session.id, login === null || isOver(login.session)]);

  const start = useCallback(
    async (kind: CliKind, configDir?: string | null): Promise<void> => {
      if (!apis) {
        return;
      }
      setError(null);
      // Before the await, never after: the wait IS the window the flag exists
      // to cover.
      setStarting({ kind, server: null });
      try {
        const session = await apis.cliAuth.startCliLogin({
          agent: kind as AgentKind,
          ...(configDir ? { configDir } : {}),
        });
        setLogin({ kind, session, server: null });
        if (isOver(session)) {
          settledRef.current({ kind, session, server: null });
        }
      } catch (err) {
        setError(String(err));
      } finally {
        // In a `finally` so a REFUSED start clears it too — otherwise a failed
        // press leaves a spinner running over a sign-in that never began.
        setStarting(null);
      }
    },
    [apis],
  );

  const startMcp = useCallback(
    async (input: {
      kind: CliKind;
      server: string;
      cwd?: string;
      configDir?: string | null;
    }): Promise<void> => {
      if (!apis) {
        return;
      }
      setError(null);
      setStarting({ kind: input.kind, server: input.server });
      try {
        const session = await apis.cliAuth.startMcpLogin({
          agent: input.kind as AgentKind,
          server: input.server,
          // Omitted rather than defaulted: the daemon reads an absent `cwd` as
          // its own folderless directory, which is a place, not a fallback.
          ...(input.cwd ? { cwd: input.cwd } : {}),
          ...(input.configDir ? { configDir: input.configDir } : {}),
        });
        setLogin({ kind: input.kind, session, server: input.server });
        if (isOver(session)) {
          settledRef.current({
            kind: input.kind,
            session,
            server: input.server,
          });
        }
      } catch (err) {
        setError(String(err));
      } finally {
        setStarting(null);
      }
    },
    [apis],
  );

  const submitCode = useCallback(
    async (code: string): Promise<void> => {
      if (!apis || login === null) {
        return;
      }
      setError(null);
      try {
        const session = await apis.cliAuth.submitCliLoginCode({
          id: login.session.id,
          loginCodeBodyDto: { code },
        });
        setLogin({ kind: login.kind, session, server: login.server });
      } catch (err) {
        setError(String(err));
      }
    },
    [apis, login],
  );

  const cancel = useCallback(async (): Promise<void> => {
    if (!apis || login === null) {
      return;
    }
    try {
      // The panel closes on the CANCEL answer rather than optimistically: until
      // the daemon has reaped the group, the CLI may still complete, and a panel
      // that vanished first would leave the user with a sign-in they cannot see.
      const session = await apis.cliAuth.cancelCliLogin({
        id: login.session.id,
      });
      setLogin({ kind: login.kind, session, server: login.server });
      settledRef.current({ kind: login.kind, session, server: login.server });
    } catch (err) {
      setError(String(err));
    }
  }, [apis, login]);

  const dismiss = useCallback((): void => {
    setLogin(null);
    setError(null);
  }, []);

  return {
    login,
    starting,
    start,
    startMcp,
    submitCode,
    cancel,
    dismiss,
    error,
  };
}
