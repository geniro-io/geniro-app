import { useEffect, useState } from 'react';

import { FetchError } from './autogenerated';

export interface PolledReadState<T> {
  data: T | null;
  loading: boolean;
  error: string | null;
}

/**
 * How often a live process reading is retaken while it is on screen. CPU and
 * memory move second to second, and a `ps` of the whole machine costs the
 * daemon a few milliseconds — three seconds keeps the figures live without the
 * readout becoming the busiest thing it measures.
 */
export const PROCESS_POLL_MS = 3_000;

/** See `use-run-waterfall.ts`'s twin: the generated runtime hides the cause. */
function readFailure(prefix: string, err: unknown): string {
  const root = err instanceof FetchError ? err.cause : err;
  const detail = root instanceof Error ? root.message.trim() : '';
  return detail ? `${prefix} — ${detail}` : prefix;
}

/**
 * A daemon read retaken every `intervalMs` while `read` is non-null.
 *
 * Each poll is scheduled only once the previous one has answered, so a slow
 * daemon cannot pile requests up behind itself. A failed poll keeps the last
 * good reading on screen beside the error rather than blanking it — one
 * dropped request is not news that the thing measured vanished. `resetKey`
 * names WHAT is being read: when it changes, the previous subject's reading is
 * dropped at once, so it is never shown under the next one's name.
 *
 * `read` must be stable for as long as the subject is (a `useCallback`), or
 * every render restarts the loop.
 */
export function usePolledRead<T>(
  read: (() => Promise<T>) | null,
  resetKey: string | null,
  failure: string,
  intervalMs: number = PROCESS_POLL_MS,
): PolledReadState<T> {
  const [data, setData] = useState<T | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (read === null) {
      return;
    }
    let cancelled = false;
    let timer: ReturnType<typeof setTimeout> | null = null;
    const poll = (): void => {
      read()
        .then((result) => {
          if (cancelled) {
            return;
          }
          setData(result);
          setError(null);
          setLoading(false);
        })
        .catch((err: unknown) => {
          if (cancelled) {
            return;
          }
          setError(readFailure(failure, err));
          setLoading(false);
        })
        .finally(() => {
          if (!cancelled) {
            timer = setTimeout(poll, intervalMs);
          }
        });
    };
    setLoading(true);
    poll();
    return () => {
      cancelled = true;
      if (timer !== null) {
        clearTimeout(timer);
      }
    };
  }, [read, failure, intervalMs]);

  // After the poll effect, on the waterfall's rule.
  useEffect(() => {
    setData(null);
    setError(null);
  }, [resetKey]);

  return { data, loading, error };
}
