import { useCallback, useEffect, useRef, useState } from 'react';

import type { SharesApi, ShareSignInSessionDto } from './autogenerated';
import { daemonErrorStatus, describeDaemonError } from './daemon-api';

/** How often a running sign-in is re-read — `use-cli-login.ts`'s own cadence. */
export const SHARE_SIGN_IN_POLL_MS = 1200;

export type ShareSignInClient = Pick<
  SharesApi,
  'startShareSignIn' | 'readShareSignIn' | 'cancelShareSignIn'
>;

export interface ShareSignInController {
  /** The sign-in on screen, running or just ended; null before a press or after Dismiss. */
  session: ShareSignInSessionDto | null;
  /** Set from the press until the daemon answers, so a second press cannot start another. */
  starting: boolean;
  /** Why the daemon refused the press, or why a read failed. */
  error: string | null;
  start: (destinationId: string) => void;
  cancel: () => void;
  dismiss: () => void;
}

export function isShareSignInOver(
  status: ShareSignInSessionDto['status'],
): boolean {
  return status !== 'waiting' && status !== 'verifying';
}

/**
 * The sign-in the daemon answered 404 about, as the FAILED session it now is:
 * sign-ins are held in memory, so a restarted daemon has forgotten it, and
 * polling it again — or pressing a Cancel that 404s too — would never end.
 */
function lostSession(
  session: ShareSignInSessionDto,
  err: unknown,
): ShareSignInSessionDto | null {
  return daemonErrorStatus(err) === 404
    ? {
        ...session,
        status: 'failed',
        message:
          'Geniro restarted before this sign-in finished — start it again.',
      }
    : null;
}

/**
 * Drives a share destination's sign-in that the DAEMON runs (`gcloud auth
 * login`, `aws sso login`, or a custom login command) — polled, like
 * `useCliLogin`, until it ends. Separate from it on purpose: that controller
 * belongs to the agent CLIs' own accounts and their wire.
 *
 * `onSettled` fires once when the sign-in ends, whatever the outcome; a
 * success has already had the daemon retry the waiting shares
 * (`session.retried`).
 */
export function useShareSignIn(
  api: ShareSignInClient | null,
  onSettled?: (session: ShareSignInSessionDto) => void,
): ShareSignInController {
  const [session, setSession] = useState<ShareSignInSessionDto | null>(null);
  const [starting, setStarting] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const settledRef = useRef(onSettled);
  settledRef.current = onSettled;
  const told = useRef<string | null>(null);

  const running = session !== null && !isShareSignInOver(session.status);
  const sessionId = session?.id ?? null;

  useEffect(() => {
    if (session === null || !isShareSignInOver(session.status)) {
      return;
    }
    if (told.current !== session.id) {
      told.current = session.id;
      settledRef.current?.(session);
    }
  }, [session]);

  useEffect(() => {
    if (api === null || sessionId === null || !running) {
      return;
    }
    const timer = setInterval(() => {
      void api
        .readShareSignIn({ signInId: sessionId })
        .then((next) => {
          setSession((current) => (current?.id === next.id ? next : current));
        })
        .catch((err: unknown) => {
          setSession((current) =>
            current?.id === sessionId
              ? (lostSession(current, err) ?? current)
              : current,
          );
          if (daemonErrorStatus(err) !== 404) {
            setError(describeDaemonError(err));
          }
        });
    }, SHARE_SIGN_IN_POLL_MS);
    return () => clearInterval(timer);
  }, [api, sessionId, running]);

  const start = useCallback(
    (destinationId: string) => {
      if (api === null || starting) {
        return;
      }
      setStarting(true);
      setError(null);
      void api
        .startShareSignIn({ startShareSignInDto: { destinationId } })
        .then(setSession)
        .catch((err: unknown) => setError(describeDaemonError(err)))
        .finally(() => setStarting(false));
    },
    [api, starting],
  );

  const cancel = useCallback(() => {
    if (api === null || sessionId === null) {
      return;
    }
    void api
      .cancelShareSignIn({ signInId: sessionId })
      .then((next) =>
        setSession((current) => (current?.id === next.id ? next : current)),
      )
      .catch((err: unknown) => {
        const lost = session === null ? null : lostSession(session, err);
        if (lost !== null) {
          setSession(lost);
          return;
        }
        setError(describeDaemonError(err));
      });
  }, [api, sessionId, session]);

  const dismiss = useCallback(() => {
    setSession(null);
    setError(null);
  }, []);

  return { session, starting, error, start, cancel, dismiss };
}
