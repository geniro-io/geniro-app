/** Deliver a row that ENDS a run-level turn, as the daemon's socket would. */
async function endTurn(id: string): Promise<void> {
  await act(async () => {
    for (const listener of [...itemListeners]) {
      listener({
        id,
        runId: 'run-1',
        seq: 1,
        kind: 'turn_complete',
        role: 'assistant',
        nodeId: null,
        payload: {},
        createdAt: '2026-09-01T00:00:00.000Z',
      } as ChatItem);
    }
  });
}

