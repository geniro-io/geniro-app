const NOTICE_TTL_MS = 6_000;

/**
 * The Workflows page: compose a DAG of agents on a React Flow canvas, backed
 * by the daemon's YAML library (`*.geniro.yaml` — the source of truth). The
 * canvas is a static builder (no live-run animation in M3); runs start from
 * the Chats page.
 */
export function Workflows({
  handle,
  client,
  active = true,
}: {
  handle: DaemonHandle | null;
  /**
   * The live daemon socket, for the builder's chat panel — it follows its
   * conversation's run room exactly as the chat screen follows its own.
   */
  client: DaemonClient | null;
  /** Whether this screen is the one on view — see the library refresh below. */
  active?: boolean;
}): React.JSX.Element {
  const apis = useMemo(
    () => (handle ? createDaemonApis(handle) : null),
    [handle],
  );
  const api = apis?.workflows ?? null;

  // null = not yet loaded (the Settings `clis` pattern) — the empty state is
  // an authoritative claim reserved for a resolved-but-empty library.
  const [summaries, setSummaries] = useState<WorkflowSummary[] | null>(null);
  const [activeSlug, setActiveSlug] = useState<string | null>(null);
  const [name, setName] = useState('');
  // Set in the create dialog / loaded with the workflow; carried through every
  // save so a described workflow never loses its description to the builder.
  const [description, setDescription] = useState('');
  const [createOpen, setCreateOpen] = useState(false);
  const [creating, setCreating] = useState(false);
  // The builder's "Change workflow" popup — the create meta form, prefilled.
  const [renameOpen, setRenameOpen] = useState(false);
  const [renaming, setRenaming] = useState(false);
  // A delete in flight — suspends autosave (see `remove`).
  const [deleting, setDeleting] = useState(false);
  // The library card awaiting its delete confirmation (null = dialog closed).
  const [pendingDelete, setPendingDelete] = useState<WorkflowSummary | null>(
    null,
  );
  // The builder header's overflow menu, and the delete confirmation it opens.
  //
  // A DIALOG here where the header used to arm a `ConfirmButton` in place: a
  // menu row cannot arm itself — it commits and the panel closes — so moving
  // the delete behind the menu without this would have made destroying a
  // workflow a single click. The library's own card has had the same dialog
  // all along.
  const [moreOpen, setMoreOpen] = useState(false);
  const moreRef = useRef<HTMLButtonElement | null>(null);
  const [removeOpen, setRemoveOpen] = useState(false);
  // The builder's chat dock: whether it is on screen, and whether its agent is
  // mid-turn — which is what suspends autosave, since the agent writes the same
  // file the canvas does.
  const [chatOpen, setChatOpen] = useState(false);
  const [chatWorking, setChatWorking] = useState(false);
  const [nodes, setNodes, onNodesChange] = useNodesState<GraphFlowNode>([]);
  const [edges, setEdges, onEdgesChange] = useEdgesState<Edge>([]);
  const [selectedNodeId, setSelectedNodeId] = useState<string | null>(null);
  const [started, setStarted] = useState(false);
  // The workflow as last loaded/saved (see canvasSnapshot) — compared against
  // the live canvas to decide whether leaving the builder discards work.
  const [savedSnapshot, setSavedSnapshot] = useState<string | null>(null);
  // Captured from ReactFlow's onInit so the canvas drop handler can map screen
  // coordinates to flow coordinates (screenToFlowPosition).
  const [rfInstance, setRfInstance] = useState<ReactFlowInstance<
    GraphFlowNode,
    Edge
  > | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  // The right inspector only exists while a node is selected; its width is
  // drag-resizable from its left edge and persists like the palette's.
  const inspector = usePanelWidth({
    storageKey: 'geniro.builder.inspectorWidth',
    defaultWidth: 300,
    minWidth: 240,
    maxWidth: 480,
    handleEdge: 'left',
  });

  const refreshList = useCallback(async (): Promise<void> => {
    if (!api) {
      return;
    }
    try {
      setSummaries(await api.listWorkflows());
    } catch (err) {
      setError(String(err));
    }
  }, [api]);

  /**
   * Re-read the library whenever this screen comes back into view.
   *
   * Workflows stays MOUNTED across nav switches — that is what keeps an unsaved
   * builder edit alive while the user glances at Chats — so a one-shot mount
   * read never runs again. The library is `*.geniro.yaml` on disk and those
   * files are the source of truth, so anything that writes one without going
   * through this screen stayed invisible until the app was restarted: an editor,
   * another window, a second checkout. Measured — a file dropped into the
   * workflows directory was served by `GET /v1/workflows` immediately and still
   * missing from this list after navigating away and back.
   *
   * The LIBRARY only. The builder's canvas is the user's unsaved work, and
   * refetching that on every nav switch is what staying mounted exists to avoid.
   */
  useEffect(() => {
    if (!active) {
      return;
    }
    void refreshList();
  }, [active, refreshList]);

  // Status-bar messages expire on their own (see NOTICE_TTL_MS).
  useEffect(() => {
    if (!notice) {
      return;
    }
    const timer = window.setTimeout(() => setNotice(null), NOTICE_TTL_MS);
    return () => window.clearTimeout(timer);
  }, [notice]);

  const openWorkflow = useCallback(
    async (slug: string): Promise<void> => {
      if (!api) {
        return;
      }
      setError(null);
      setNotice(null);
      try {
        const { workflow } = await api.getWorkflow({ slug });
        const flow = toFlow(workflow);
        setActiveSlug(slug);
        setName(workflow.name);
        setDescription(workflow.description ?? '');
        setNodes(flow.nodes);
        setEdges(flow.edges);
        setSelectedNodeId(null);
        setSavedSnapshot(
          canvasSnapshot(
            workflow.name,
            workflow.description ?? '',
            flow.nodes,
            flow.edges,
          ),
        );
        setStarted(true);
      } catch (err) {
        setError(String(err));
      }
    },
    [api, setNodes, setEdges],
  );

  /** "New workflow" opens the create dialog — nothing exists until Create. */
  const newWorkflow = useCallback((): void => {
    setError(null);
    setCreateOpen(true);
  }, []);

  /**
   * Create-dialog submit: persist a fresh EMPTY workflow (name + description
   * from the dialog, blank canvas — nodes come from the palette), then
   * redirect into the builder for it. On failure the dialog stays open
   * showing the error.
   */
  const createWorkflow = useCallback(
    async (meta: { name: string; description?: string }): Promise<void> => {
      if (!api) {
        return;
      }
      setCreating(true);
      setError(null);
      try {
        const saved = await api.createWorkflow({
          createWorkflowDto: { workflow: fromFlow(meta, [], []) },
        });
        setCreateOpen(false);
        await openWorkflow(saved.slug);
      } catch (err) {
        setError(String(err));
      } finally {
        setCreating(false);
      }
    },
    [api, openWorkflow],
  );

  /** Clear the builder and return to the library grid (refreshing the list so
   *  a just-saved workflow's card reflects its new node count / mtime). Callers
   *  flush pending autosave work first — see `leaveToLibrary`. */
  const backToLibrary = useCallback((): void => {
    setStarted(false);
    setActiveSlug(null);
    setSelectedNodeId(null);
    setName('');
    setDescription('');
    setNodes([]);
    setEdges([]);
    setError(null);
    setNotice(null);
    setSavedSnapshot(null);
    setChatOpen(false);
    setChatWorking(false);
    void refreshList();
  }, [refreshList, setNodes, setEdges]);

  /** The live canvas serialized as a write would store it — the autosave
   *  trigger (compared against `savedSnapshot`). */
  const liveSnapshot = useMemo(
    () => canvasSnapshot(name, description, nodes, edges),
    [name, description, nodes, edges],
  );

  /** Persist the canvas under the given meta; true on success. */
  const persist = useCallback(
    async (meta: { name: string; description?: string }): Promise<boolean> => {
      if (!api) {
        return false;
      }
      setError(null);
      try {
        const workflow = fromFlow(meta, nodes, edges);
        const saved = activeSlug
          ? await api.saveWorkflow({
              slug: activeSlug,
              saveWorkflowDto: { workflow },
            })
          : await api.createWorkflow({ createWorkflowDto: { workflow } });
        setActiveSlug(saved.slug);
        setSavedSnapshot(
          canvasSnapshot(meta.name, meta.description ?? '', nodes, edges),
        );
        await refreshList();
        return true;
      } catch (err) {
        setError(String(err));
        return false;
      }
    },
    [api, nodes, edges, activeSlug, refreshList],
  );

  /** One autosave write of the open workflow under its current meta. The
   *  normalization matches `canvasSnapshot`'s exactly — a mismatch would leave
   *  the canvas permanently "dirty" and autosave writing in a loop. */
  const saveNow = useCallback((): Promise<boolean> => {
    const trimmedDescription = description.trim();
    return persist({
      name: name.trim() || 'workflow',
      ...(trimmedDescription ? { description: trimmedDescription } : {}),
    });
  }, [persist, name, description]);

  // No Save button: edits persist on their own once the user pauses. Suspended
  // while a delete is in flight so a queued write can't resurrect the file.
  const autosave = useAutosave({
    // Suspended while the chat's agent is mid-turn, on the same reasoning the
    // delete uses: a queued write would land on top of the file the agent is
    // editing, and the two would overwrite each other silently.
    enabled: started && activeSlug !== null && !deleting && !chatWorking,
    snapshot: liveSnapshot,
    savedSnapshot,
    save: saveNow,
  });

  // Read inside `reloadAfterAgentEdit`, which must stay STABLE: the chat panel
  // holds it in an effect's dependencies, and a callback re-created on every
  // canvas keystroke would re-arm that effect for the life of the conversation.
  const liveSnapshotRef = useRef(liveSnapshot);
  liveSnapshotRef.current = liveSnapshot;
  const savedSnapshotRef = useRef(savedSnapshot);
  savedSnapshotRef.current = savedSnapshot;

  /**
   * Re-read the workflow once the chat's agent finishes a turn.
   *
   * This is the whole of how an agent's edit reaches the canvas: nothing in
   * either app watches a file, and a turn ending is the moment the agent's
   * writes are done being made. Re-seeding `savedSnapshot` with it is what
   * stops the next canvas edit from writing the pre-agent graph back over it.
   *
   * A turn that changed nothing on disk leaves the canvas ALONE — most turns
   * are questions and answers, and re-seeding on every one of them would drop
   * the user's own in-progress edits for no reason. When the file HAS moved and
   * the canvas had unsaved edits, they are gone, and the notice says so rather
   * than letting the graph change under the user unannounced.
   */
  const reloadAfterAgentEdit = useCallback(async (): Promise<void> => {
    if (!api || activeSlug === null) {
      return;
    }
    try {
      const { workflow } = await api.getWorkflow({ slug: activeSlug });
      const flow = toFlow(workflow);
      const onDisk = canvasSnapshot(
        workflow.name,
        workflow.description ?? '',
        flow.nodes,
        flow.edges,
      );
      if (onDisk === liveSnapshotRef.current) {
        // Nothing to do, and the canvas may hold edits made while it ran.
        setSavedSnapshot(onDisk);
        return;
      }
      const hadUnsaved =
        savedSnapshotRef.current !== null &&
        liveSnapshotRef.current !== savedSnapshotRef.current;
      setName(workflow.name);
      setDescription(workflow.description ?? '');
      setNodes(flow.nodes);
      setEdges(flow.edges);
      setSavedSnapshot(onDisk);
      setNotice(
        hadUnsaved
          ? 'Reloaded — the agent changed this workflow, replacing the canvas edits made while it worked'
          : 'Reloaded — the agent changed this workflow',
      );
      await refreshList();
    } catch (err) {
      setError(String(err));
    }
  }, [api, activeSlug, setNodes, setEdges, refreshList]);

  /** Leaving writes first — the debounce may still be pending, and clearing
   *  the canvas without flushing is exactly the silent data loss the old
   *  "Discard unsaved edits?" confirm existed to warn about. */
  const leaveToLibrary = useCallback(async (): Promise<void> => {
    await autosave.flush();
    backToLibrary();
  }, [autosave, backToLibrary]);

  /** Change-popup submit: adopt the new meta and persist it immediately —
   *  the popup only closes once the library file actually carries it. */
  const renameWorkflow = useCallback(
    async (meta: { name: string; description?: string }): Promise<void> => {
      setRenaming(true);
      try {
        if (await persist(meta)) {
          setName(meta.name);
          setDescription(meta.description ?? '');
          setRenameOpen(false);
        }
      } finally {
        setRenaming(false);
      }
    },
    [persist],
  );

  /** Delete one workflow from the library (its saved viewport goes with it);
   *  true on success. The ONE delete path — the library grid's per-card
   *  confirm and the builder's toolbar both go through it. */
  const deleteWorkflow = useCallback(
    async (slug: string): Promise<boolean> => {
      if (!api) {
        return false;
      }
      setError(null);
      try {
        await api.deleteWorkflow({ slug });
        clearViewport(slug);
        await refreshList();
        return true;
      } catch (err) {
        setError(String(err));
        return false;
      }
    },
    [api, refreshList],
  );

  /** The library grid's delete, once the modal is confirmed. A failure keeps
   *  the dialog open carrying the error rather than closing on a no-op. */
  const confirmDelete = useCallback(async (): Promise<void> => {
    if (!pendingDelete) {
      return;
    }
    setDeleting(true);
    try {
      if (await deleteWorkflow(pendingDelete.slug)) {
        setPendingDelete(null);
      }
    } finally {
      setDeleting(false);
    }
  }, [pendingDelete, deleteWorkflow]);

  /**
   * The builder's own delete: drop the open workflow, then clear the canvas.
   *
   * Answers whether it HAPPENED, which its confirmation dialog needs: a failed
   * delete must leave the dialog standing with the reason in it, exactly as the
   * library card's own `confirmDelete` does. It used to return void because its
   * caller was a two-step button that closed itself either way.
   */
  const remove = useCallback(async (): Promise<boolean> => {
    if (!activeSlug) {
      return false;
    }
    // Suspends autosave for the duration: a debounced write firing after the
    // DELETE would recreate the YAML the user just deleted.
    setDeleting(true);
    try {
      if (await deleteWorkflow(activeSlug)) {
        setActiveSlug(null);
        setNodes([]);
        setEdges([]);
        setName('');
        setDescription('');
        setStarted(false);
        return true;
      }
      return false;
    } finally {
      setDeleting(false);
    }
  }, [activeSlug, deleteWorkflow, setNodes, setEdges]);

  /**
   * The builder header's overflow rows — every command that has no state.
   *
   * In WORDS rather than as icons, which is the half of the redesign that is
   * easy to lose: collapsing five buttons into five glyphs would have made the
   * header smaller and every control harder to identify. A menu row can carry
   * its icon AND its name, so the row that got shorter is the header and not
   * the vocabulary.
   *
   * Auto-layout is offered whatever the canvas holds — it acts on the nodes on
   * screen, saved or not — while the other three name the workflow's own FILE
   * and appear only once there is one. Delete is a group of its own, which is
   * what draws the hairline above it: it is the one row here that destroys
   * something.
   */
  const builderActions = useMemo((): MenuGroup[] => {
    const commands: MenuGroup['items'] = [
      { value: 'layout', label: 'Auto-layout', icon: <Wand2 />, action: true },
    ];
    if (activeSlug) {
      commands.push(
        { value: 'export', label: 'Export…', icon: <Download />, action: true },
        {
          value: 'rename',
          label: 'Edit name and description',
          icon: <Pencil />,
          action: true,
        },
      );
    }
    return [
      { items: commands },
      ...(activeSlug
        ? [
            {
              items: [
                {
                  value: 'delete',
                  label: 'Delete workflow',
                  icon: <Trash2 />,
                  action: true,
                  tone: 'destructive' as const,
                },
              ],
            },
          ]
        : []),
    ];
  }, [activeSlug]);

  const importWorkflow = useCallback(async (): Promise<void> => {
    if (!api) {
      return;
    }
    setError(null);
    try {
      const path = await window.geniro.pickWorkflowImport();
      if (!path) {
        return;
      }
      const imported = await api.importWorkflow({
        importWorkflowDto: { path },
      });
      await refreshList();
      await openWorkflow(imported.slug);
    } catch (err) {
      setError(String(err));
    }
  }, [api, refreshList, openWorkflow]);

  const exportWorkflow = useCallback(async (): Promise<void> => {
    if (!api || !activeSlug) {
      return;
    }
    setError(null);
    try {
      const path = await window.geniro.pickWorkflowExport(
        `${activeSlug}.geniro.yaml`,
      );
      if (!path) {
        return;
      }
      await api.exportWorkflow({
        slug: activeSlug,
        exportWorkflowDto: { path },
      });
      setNotice(`Exported to ${path}`);
    } catch (err) {
      setError(String(err));
    }
  }, [api, activeSlug]);

  const addNode = useCallback(
    (item: PaletteItem, position?: { x: number; y: number }): void => {
      const id = nextNodeId(new Set(nodes.map((n) => n.id)), item.kind);
      const maxX = nodes.reduce((max, n) => Math.max(max, n.position.x), -260);
      // Toolbar adds stack to the right; a drop lands where it was dropped.
      const at = position ?? { x: maxX + 260, y: 40 };
      const node = flowNodeFor(paletteNode(item, id), at);
      setNodes((prev) => [...prev, node]);
      setSelectedNodeId(id);
      if (!position && rfInstance) {
        // A toolbar add lands 260px right of the rightmost node, which after a
        // few is past the edge of the canvas — five "Add to canvas" clicks put
        // four nodes off-screen and the builder looked like it had stopped
        // adding them. A DROP is exempt: it landed where the user aimed.
        // Panning, never zooming: the zoom is the user's.
        rfInstance.setCenter(at.x + NODE_WIDTH / 2, at.y + NODE_HEIGHT / 2, {
          zoom: rfInstance.getZoom(),
          duration: 200,
        });
      }
    },
    [nodes, setNodes, rfInstance],
  );

  const onCanvasDragOver = useCallback((event: React.DragEvent): void => {
    event.preventDefault();
    event.dataTransfer.dropEffect = 'move';
  }, []);

  const onCanvasDrop = useCallback(
    (event: React.DragEvent): void => {
      event.preventDefault();
      const item = parsePaletteItem(event.dataTransfer.getData(NODE_DND_MIME));
      if (!rfInstance || !item) {
        return;
      }
      const position = rfInstance.screenToFlowPosition({
        x: event.clientX,
        y: event.clientY,
      });
      addNode(item, position);
    },
    [rfInstance, addNode],
  );

  const layout = useCallback(async (): Promise<void> => {
    try {
      const workflow = fromFlow(
        { name: name.trim() || 'workflow' },
        nodes,
        edges,
      );
      // What each card MEASURES on this canvas, which only the canvas knows —
      // React Flow measures every node it has rendered. Without it ELK places
      // 128px boxes and the taller cards eat the gap between them (see
      // `autoLayout`); an unmeasured node simply falls back to the constant.
      const sizes = new Map(
        nodes.map((n) => [
          n.id,
          n.measured?.width !== undefined && n.measured.height !== undefined
            ? { width: n.measured.width, height: n.measured.height }
            : undefined,
        ]),
      );
      const positions = await autoLayout(workflow, sizes);
      setNodes((prev) =>
        prev.map((n) => ({ ...n, position: positions[n.id] ?? n.position })),
      );
    } catch (err) {
      setError(String(err));
    }
  }, [name, nodes, edges, setNodes]);

  const onConnect = useCallback(
    (connection: Connection): void => {
      if (!connection.source || !connection.target) {
        return;
      }
      if (connection.source === connection.target) {
        return; // self-loops are invalid (the daemon rejects them too)
      }
      // A drag that grabbed a call handle on either end wires a call edge;
      // everything else — the collapsed summary pills included — stays data
      // flow (call edges are drawn from the expanded ports block).
      const edgeKind = connectionEdgeKind(
        connection.sourceHandle,
        connection.targetHandle,
      );
      // Normalize to the canonical handle pair derived from the edge kind +
      // endpoint kinds (the same ids toFlow derives) — a drag may have
      // grabbed any of the stacked collapsed handles, but with one rule per
      // (side, edge kind, peer kind) there is exactly one correct pair.
      const kindOf = (id: string): NodeKind | undefined =>
        nodes.find((n) => n.id === id)?.data.node.kind;
      const sourceKind = kindOf(connection.source);
      const targetKind = kindOf(connection.target);
      setEdges((prev) => {
        const id = edgeId(connection.source, connection.target, edgeKind);
        // One edge per (pair, edge kind) — the daemon rejects duplicates on
        // save, so the canvas never creates one.
        if (prev.some((e) => e.id === id)) {
          return prev;
        }
        return addEdge(
          {
            ...connection,
            id,
            ...flowEdgeType(edgeKind),
            sourceHandle: targetKind
              ? makeHandleId('source', edgeKind, targetKind)
              : connection.sourceHandle,
            targetHandle: sourceKind
              ? makeHandleId('target', edgeKind, sourceKind)
              : connection.targetHandle,
          },
          prev,
        );
      });
    },
    [nodes, setEdges],
  );

  /**
   * Live drag predicate: an edge may only be wired when the connection rules
   * allow the (edge kind, source kind → target kind) triple — the same
   * registry the daemon enforces on save — and no edge of that kind already
   * joins the pair. Also refuses self-loops so the invalid wire never draws.
   */
  const isValidConnection = useCallback(
    (connection: Connection | Edge): boolean => {
      if (
        !connection.source ||
        !connection.target ||
        connection.source === connection.target
      ) {
        return false;
      }
      const kindOf = (id: string): string | undefined =>
        nodes.find((n) => n.id === id)?.data.node.kind;
      const sourceKind = kindOf(connection.source);
      const targetKind = kindOf(connection.target);
      const edgeKind = connectionEdgeKind(
        connection.sourceHandle,
        connection.targetHandle,
      );
      if (
        sourceKind === undefined ||
        targetKind === undefined ||
        !canConnect(edgeKind, sourceKind, targetKind) ||
        edges.some(
          (e) =>
            e.id === edgeId(connection.source, connection.target, edgeKind),
        )
      ) {
        return false;
      }
      // ARITY, which the compatibility check above cannot answer: it decides
      // whether this PAIR of kinds may be wired at all, while this decides
      // whether ANOTHER such wire may be added to the ones already here. That
      // divergence is not new with the single-trigger rule: the agent's own
      // `{ edge: 'data', kind: 'trigger' }` input has always been single-arity,
      // so two triggers into one agent already drew fine here.
      return arityAllowsConnection(
        edgeKind,
        { source: connection.source, target: connection.target },
        { kindOf, edges },
      );
    },
    [nodes, edges],
  );

  /**
   * Patch the selected node's workflow data (inspector edits). The inspector
   * only sends fields belonging to the selected node's own kind and never
   * `kind` itself, so the spread stays within the node's union branch — the
   * cast just tells TS what the per-kind field editors guarantee.
   */
  const patchSelected = useCallback(
    (
      patch: Partial<
        Omit<WorkflowAgentNode, 'kind'> &
          Omit<WorkflowTriggerNode, 'kind'> &
          Omit<WorkflowInstructionNode, 'kind'>
      >,
    ): void => {
      if (!selectedNodeId) {
        return;
      }
      setNodes((prev) =>
        prev.map((n) =>
          n.id === selectedNodeId
            ? ({
                ...n,
                data: { node: { ...n.data.node, ...patch } as WorkflowNode },
              } as GraphFlowNode)
            : n,
        ),
      );
    },
    [selectedNodeId, setNodes],
  );

  const selected =
    nodes.find((n) => n.id === selectedNodeId)?.data.node ?? null;

  // The inspector's model rows come from the selected node's CLI itself, the
  // same source the chat composer uses — one list, so the two cannot drift.
  // The NODE's own profile: each listing below is an account fact, and a
  // workflow's nodes routinely name different ones — so two nodes on one CLI
  // genuinely have two vocabularies, exactly as they have two MCP listings.
  const selectedConfigDir =
    selected?.kind === 'agent' ? (selected.configDir ?? null) : null;
  const { models: agentModels, loading: agentModelsLoading } = useAgentModels(
    apis?.agents ?? null,
    selected?.kind === 'agent' ? selected.agent : null,
    selectedConfigDir,
  );
  // Same source as the composer's chip, for the same reason the models are:
  // the levels are the CLI's own, so builder and chat cannot offer different
  // ones for the same agent.
  // …narrowed to the node's OWN model, for the same reason the composer's is:
  // the levels belong to the model, so a node on a cursor model with no `max`
  // must not be offered one. A node with no model asks for the CLI-wide union,
  // which is the honest answer for "whatever the CLI opens with".
  const agentEfforts = useAgentEfforts(
    apis?.agents ?? null,
    selected?.kind === 'agent' ? selected.agent : null,
    selected?.kind === 'agent' ? (selected.model ?? null) : null,
    selectedConfigDir,
  );
  // Same listing, same narrowing, and here the model is not an improvement but
  // the whole question: window sizes belong to the model, so a node with none
  // has nothing to choose from and the chip says so.
  const agentContextWindows = useAgentContextWindows(
    apis?.agents ?? null,
    selected?.kind === 'agent' ? selected.agent : null,
    selected?.kind === 'agent' ? (selected.model ?? null) : null,
    selectedConfigDir,
  );
  // And whatever those two do not cover — here the SET of chips is the model's
  // answer, so a node that changes model changes which controls it has.
  const agentModelParameters = useAgentModelParameters(
    apis?.agents ?? null,
    selected?.kind === 'agent' ? selected.agent : null,
    selected?.kind === 'agent' ? (selected.model ?? null) : null,
    selectedConfigDir,
  );

  // What this node would load regardless of where the run lands: the user's
  // global servers plus whatever its own config directory brings. The folder's
  // own project servers are added by the CLI at run time, so the builder —
  // which has no folder — neither knows nor claims them.
  const nodeMcp = useNodeMcp(
    apis?.agents ?? null,
    selected?.kind === 'agent' ? selected.agent : null,
    selected?.kind === 'agent' ? (selected.configDir ?? null) : null,
  );

  /**
   * Signing a node's MCP server in, from the builder.
   *
   * REPORTED as "когда я открываю список MCP-серверов, я не могу их настроить
   * … Здесь я тоже должен иметь возможность абсолютно так же настроить,
   * залогиниться" — the dialog listed servers, said which needed signing in,
   * and offered nothing to do about it, while the chat panel's identical
   * dialog did.
   *
   * The sign-in carries no `cwd`, which the daemon reads as its own
   * folder-independent directory — the very directory this listing was taken
   * in, so the row and the action name the same server. The controller is the
   * app's ONE sign-in (`useCliLogin`): one browser challenge at a time, since a
   * second invalidates the first.
   *
   * The on/off TOGGLE deliberately stays absent, and that is not the same
   * omission. Both CLIs store it per FOLDER (claude in
   * `projects[<cwd>].disabledMcpServers`), and the builder has no folder until
   * the workflow runs — so a switch here would write a decision about geniro's
   * scratch directory and change nothing about the run. `mcp-section` says so
   * on the rows rather than leaving the reader to wonder, which is the whole
   * lesson of this report.
   */
  const login = useCliLogin(apis, (settled) => {
    // Only the LISTING can say whether a sign-in landed — the CLI exits as soon
    // as it has handed the browser the challenge — so a settled server sign-in
    // re-reads this node's servers. An ACCOUNT sign-in cannot be started here.
    if (settled.server !== null) {
      nodeMcp.refresh();
    }
  });

  /**
   * Why the config directory the node names cannot be used, or null.
   *
   * On the FIELD rather than only inside the listing, because it is a path
   * the user has to fix — and the CLI itself says nothing, silently ignoring
   * a directory it cannot use, which is the whole reason the validation
   * exists. The hook narrows this to a daemon REFUSAL; a missing CLI or an
   * unreachable daemon stays in the section below, where it belongs.
   */
  const configDirError = nodeMcp.invalidConfigDir;

  // ONE read of `/v1/capabilities` for the whole screen — the inspector now
  // asks it two questions (can this CLI take a config directory, and which
  // approval modes does it honour), and `useCapabilities` holds its state per
  // CALL, so a second hook here would mount a second fetcher and a second retry
  // loop against one endpoint. Its `loading` is taken too and handed to
  // `configDirCapabilityFrom` below, which must not derive one of its own: only
  // the hook knows a read SETTLED, so a derived flag cannot clear on failure.
  const { capabilities, loading: capabilitiesLoading } = useCapabilities(
    apis?.capabilities ?? null,
  );

  // Whether the selected node's CLI can take a config directory at all, asked
  // of the daemon rather than decided here — the inspector used to allowlist
  // one agent by name, which is how this question came to have three
  // incompatible answers across the app.
  const configDirCapability = configDirCapabilityFrom(
    capabilities,
    capabilitiesLoading,
  );

  /**
   * The approval modes this node's CLI honours, narrowed to the ones a WORKFLOW
   * node can carry.
   *
   * Which modes a CLI honours is the daemon's answer (`approvals[]`, composed
   * from each adapter's own config), the same one the composer's chip reads —
   * the inspector used to offer a hardcoded three to every agent, which is how
   * a CLI gaining or losing a mode reached the chat and not the builder.
   *
   * `plan` is dropped rather than passed through: it is a CHAT posture
   * (`ChatApprovalMode`), and the workflow schema has no such value, so
   * offering it would build a node the daemon refuses on save.
   */
  const nodeApprovalModes = useMemo(() => {
    if (selected?.kind !== 'agent') {
      return null;
    }
    const modes = capabilities?.approvals.find(
      (entry) => entry.agent === selected.agent,
    )?.modes;
    return modes ? modes.filter((mode) => mode !== 'plan') : null;
  }, [capabilities, selected]);

  // Which node's MCP dialog is open, or null. Closed on every selection change:
  // the dialog is titled with the node it was opened from, so carrying it
  // across a click would leave it naming one node while listing another's.
  const [mcpOpen, setMcpOpen] = useState(false);
  useEffect(() => {
    setMcpOpen(false);
  }, [selectedNodeId]);

  /**
   * The config directories the user has picked recently — the SAME list the
   * composer's chip offers, read from `settings.json`.
   *
   * Shared deliberately: a profile is an account the user set up once, and
   * having to re-browse to it in the builder because the composer is where they
   * first chose it is the kind of split that makes two pickers of one control.
   */
  const [recentConfigDirs, setRecentConfigDirs] = useState<string[]>([]);
  useEffect(() => {
    void window.geniro
      .getSettings()
      .then((settings) => setRecentConfigDirs(settings.recentConfigDirs ?? []))
      // A settings read that fails costs the recents list and nothing else —
      // the picker still browses, and the builder is not a screen to fail.
      .catch(() => undefined);
  }, []);

  /**
   * Browse for this node's config directory.
   *
   * Writes back only `recentConfigDirs`, never the composer's own `configDir`
   * default: choosing a profile for a workflow node says nothing about which
   * account the user's next CHAT should run as.
   */
  const chooseNodeConfigDir = useCallback(async (): Promise<void> => {
    const chosen = await window.geniro.pickProjectFolder();
    if (chosen === null) {
      return;
    }
    patchSelected({ configDir: chosen });
    const next = [
      chosen,
      ...recentConfigDirs.filter((path) => path !== chosen),
    ].slice(0, RECENT_CONFIG_DIRS);
    setRecentConfigDirs(next);
    void window.geniro.updateSettings({ recentConfigDirs: next });
  }, [patchSelected, recentConfigDirs]);

  // Read-only "Agent calls" summary for the inspector: who this agent may
  // invoke and who may invoke it (the amber call edges touching the node),
  // plus a heads-up when it takes part in a call loop. Null when the node
  // has no call wiring — the section only appears once calls exist.
  const callInfo = useMemo(
    () =>
      selected?.kind === 'agent'
        ? agentCallInfo(
            selected.id,
            nodes.map((n) => ({
              id: n.id,
              name: n.data.node.name,
              // Only agent nodes carry one; a trigger is never a callee.
              description:
                n.data.node.kind === 'agent'
                  ? n.data.node.description
                  : undefined,
            })),
            edges,
          )
        : null,
    [selected, nodes, edges],
  );

  // The last pan/zoom of this workflow, restored on open. Only read when the
  // builder (re)mounts its ReactFlow — one instance per opened workflow.
  const savedViewport = useMemo(
    () => (activeSlug ? loadViewport(activeSlug) : null),
    [activeSlug],
  );

  const onSelectionChange = useCallback(
    ({ nodes: sel }: { nodes: GraphFlowNode[] }): void =>
      setSelectedNodeId(sel[0]?.id ?? null),
    [],
  );

  // Every finished pan/zoom gesture persists (per workflow).
  const onMoveEnd = useCallback(
    (_event: unknown, viewport: Viewport): void => {
      if (activeSlug) {
        saveViewport(activeSlug, viewport);
      }
    },
    [activeSlug],
  );

  if (!handle) {
    return <EmptyState>Connecting to the daemon…</EmptyState>;
  }

  // Library grid — the landing view: one card per workflow with its metadata.
  // Clicking a card (or "New workflow") opens the builder below.
  if (!started) {
    return (
      <div className="flex h-full min-h-0 flex-col">
        <header className="flex items-center gap-2 border-b border-border px-4 py-3">
          <div className="flex flex-col">
            <div className="flex items-baseline gap-2">
              {/* Matches the Stats header's scale — these are the two pages
                  that are a whole surface rather than a document. */}
              <h2 className="text-lg font-semibold">Workflows</h2>
              {/* A count only once one is known: `0` while the list is still
                  loading is a claim, and the empty state below is the one
                  place allowed to make it. */}
              {summaries === null ? null : (
                <span className="text-sm text-muted-foreground tabular-nums">
                  {summaries.length}
                </span>
              )}
            </div>
            <p className="text-xs text-muted-foreground">
              Compose a team of agents as a graph. Runs start from the Chats
              page.
            </p>
          </div>
          <div className="ml-auto flex items-center gap-2">
            <Button
              type="button"
              variant="outline"
              className="gap-2"
              onClick={() => void importWorkflow()}>
              <Upload className="shrink-0" /> Import YAML…
            </Button>
            <Button type="button" className="gap-2" onClick={newWorkflow}>
              <Plus className="shrink-0" /> New workflow
            </Button>
          </div>
        </header>

        {error ? (
          <ErrorText className="border-b border-border px-4 py-1.5">
            {error}
          </ErrorText>
        ) : null}

        {summaries === null ? (
          <p className="flex-1 p-4 text-sm text-muted-foreground">
            Loading workflows…
          </p>
        ) : summaries.length === 0 ? (
          <EmptyState className="flex-1">
            <div className="flex flex-col items-center gap-4">
              <WorkflowIcon
                aria-hidden="true"
                className="size-10 text-muted-foreground/50"
              />
              <p className="max-w-sm text-sm text-muted-foreground">
                No workflows yet. Create one to start composing your agent team,
                or import an existing <code>.geniro.yaml</code>.
              </p>
              <Button type="button" className="gap-2" onClick={newWorkflow}>
                <Plus className="shrink-0" /> New workflow
              </Button>
            </div>
          </EmptyState>
        ) : (
          <div className="min-h-0 flex-1 overflow-y-auto p-4">
            {/* See `WorkflowCard` for why two per line and `items-start`. */}
            <ul className="grid grid-cols-1 items-start gap-4 sm:grid-cols-2">
              {summaries.map((summary) => (
                <WorkflowCard
                  key={summary.slug}
                  summary={summary}
                  onOpen={() => void openWorkflow(summary.slug)}
                  onDelete={() => setPendingDelete(summary)}
                />
              ))}
            </ul>
          </div>
        )}

        <WorkflowMetaDialog
          open={createOpen}
          busy={creating}
          error={createOpen ? error : null}
          title="New workflow"
          submitLabel="Create"
          busyLabel="Creating…"
          onClose={() => setCreateOpen(false)}
          onSubmit={(meta) => void createWorkflow(meta)}
        />

        <ConfirmDialog
          open={pendingDelete !== null}
          busy={deleting}
          error={pendingDelete ? error : null}
          title="Delete workflow"
          confirmLabel="Delete"
          busyLabel="Deleting…"
          onCancel={() => setPendingDelete(null)}
          onConfirm={() => void confirmDelete()}>
          <p>
            Delete{' '}
            <span className="font-medium text-foreground">
              {pendingDelete?.name}
            </span>{' '}
            permanently? Its <code>{pendingDelete?.slug}.geniro.yaml</code> file
            is removed from the library. Past runs of it are kept.
          </p>
        </ConfirmDialog>
      </div>
    );
  }

  // Builder — a single workflow open on the canvas + node inspector.
  return (
    <section className="flex h-full min-h-0 flex-col">
      <div className="flex flex-wrap items-center gap-2 border-b border-border px-3 py-2">
        {/* No discard-confirm any more: leaving flushes pending edits
              instead of throwing them away. */}
        <Button
          type="button"
          variant="ghost"
          className="gap-1.5"
          aria-label="Back to library"
          onClick={() => void leaveToLibrary()}>
          <ArrowLeft className="shrink-0" /> Library
        </Button>
        <h2 className="min-w-0 truncate font-medium">{name}</h2>
        {/* TWO controls, where there were five. Reported as "они сейчас
            какие-то большие, их слишком много… сделать их какими-то отдельными
            иконками или более понятными": a row of labelled outline buttons —
            Auto-layout, Export, ✏️, Change with chat, 🗑 — took most of the
            header's width for four things pressed once a session and one
            pressed often. What stays visible is the TOGGLE, because it is the
            only one of the five that has a STATE the header has to show; the
            rest are commands, and a command with no state belongs behind the
            overflow, where it gets a full label in words instead of an icon
            the reader has to hover to decode. */}
        <div className="ml-auto flex items-center gap-1">
          {activeSlug ? (
            <Button
              type="button"
              variant={chatOpen ? 'secondary' : 'ghost'}
              size="icon"
              aria-label="Change with chat"
              title="Describe a change and let an agent make it"
              aria-pressed={chatOpen}
              onClick={() => setChatOpen((open) => !open)}>
              <MessagesSquare className="shrink-0" />
            </Button>
          ) : null}
          <span className="relative inline-flex">
            <Button
              ref={moreRef}
              type="button"
              variant="ghost"
              size="icon"
              data-menu-trigger
              aria-haspopup="listbox"
              aria-expanded={moreOpen}
              aria-label="Workflow actions"
              title="Workflow actions"
              onClick={() => setMoreOpen((wasOpen) => !wasOpen)}>
              <MoreHorizontal className="shrink-0" />
            </Button>
            <Menu
              open={moreOpen}
              side="bottom"
              align="end"
              anchor="viewport"
              triggerRef={moreRef}
              groups={builderActions}
              onSelect={(value) => {
                setMoreOpen(false);
                if (value === 'layout') {
                  void layout();
                } else if (value === 'export') {
                  void exportWorkflow();
                } else if (value === 'rename') {
                  setRenameOpen(true);
                } else if (value === 'delete') {
                  setRemoveOpen(true);
                }
              }}
              onClose={() => setMoreOpen(false)}
            />
          </span>
        </div>
      </div>

      {error ? (
        <ErrorText className="border-b border-border px-3 py-1.5">
          {error}
        </ErrorText>
      ) : null}

      <div className="flex min-h-0 flex-1">
        <NodePalette onAdd={addNode} />

        <div
          className="relative min-w-0 flex-1 [overscroll-behavior:none]"
          onDrop={onCanvasDrop}
          onDragOver={onCanvasDragOver}>
          {/* Figma-style navigation, mirroring geniro's GraphCanvas: two-finger
              scroll PANS (free, any direction), scroll never zooms — zoom is
              pinch or Cmd+scroll (React Flow's default zoomActivationKey). */}
          <ReactFlow
            nodes={nodes}
            edges={edges}
            nodeTypes={NODE_TYPES}
            edgeTypes={EDGE_TYPES}
            onInit={setRfInstance}
            onNodesChange={onNodesChange}
            onEdgesChange={onEdgesChange}
            onConnect={onConnect}
            isValidConnection={isValidConnection}
            onSelectionChange={onSelectionChange}
            // Reopen where the user left off; only a never-seen workflow gets
            // the automatic fit. Every finished pan/zoom gesture persists.
            {...(savedViewport
              ? { defaultViewport: savedViewport }
              : { fitView: true, fitViewOptions: INITIAL_FIT })}
            onMoveEnd={onMoveEnd}
            deleteKeyCode={DELETE_KEY_CODES}
            minZoom={0.1}
            maxZoom={4}
            panOnScroll
            panOnScrollMode={PanOnScrollMode.Free}
            zoomOnScroll={false}
            proOptions={PRO_OPTIONS}>
            <Background />
            <Controls />
          </ReactFlow>
        </div>

        {selected ? (
          <aside
            style={{ width: inspector.width }}
            className="relative flex min-h-0 shrink-0 flex-col border-l border-border bg-muted/30">
            <PanelResizeHandle
              edge="left"
              label="Resize inspector"
              onMouseDown={inspector.startResize}
              value={inspector.width}
              min={inspector.minWidth}
              max={inspector.maxWidth}
              onResize={inspector.resizeTo}
            />
            {/* The inspector body scrolls, so it CLIPS — and a box that
                scrolls vertically cannot keep `overflow-x: visible`. A picker
                panel wider than the 300px panel (a config directory is a whole
                path) was cut on its left edge, losing the start of every row.
                Declaring the container is the house rule: every menu inside
                measures its trigger and places itself `fixed`. */}
            <MenuAnchorContext.Provider value="viewport">
              <div className="flex min-h-0 flex-1 flex-col overflow-y-auto">
                <div className="flex items-center gap-2 border-b border-border bg-card px-4 py-3">
                  {selected.kind === 'trigger' ? (
                    <span className="flex size-7 shrink-0 items-center justify-center rounded-full bg-success/15 text-success">
                      <Zap aria-hidden="true" className="size-3.5" />
                    </span>
                  ) : selected.kind === 'instruction' ? (
                    <span className="flex size-7 shrink-0 items-center justify-center rounded-full bg-primary/15 text-primary">
                      <ScrollText aria-hidden="true" className="size-3.5" />
                    </span>
                  ) : (
                    <AgentAvatar
                      label={selected.name ?? selected.id}
                      className="size-7 text-xs"
                    />
                  )}
                  <div className="min-w-0">
                    <p className="truncate text-sm font-semibold">
                      {selected.name ?? selected.id}
                    </p>
                    <p className="text-xs text-muted-foreground">
                      {selected.kind === 'trigger'
                        ? `${selected.trigger} trigger`
                        : selected.kind === 'instruction'
                          ? 'Instruction block'
                          : selected.agent}
                    </p>
                  </div>
                </div>
                <div className="flex flex-col gap-4 p-4">
                  <Field label="Display name" htmlFor="node-name">
                    <Input
                      id="node-name"
                      value={selected.name ?? ''}
                      placeholder={selected.id}
                      onChange={(event) =>
                        patchSelected({
                          name: event.target.value || undefined,
                        })
                      }
                    />
                  </Field>
                  {selected.kind === 'trigger' ? (
                    <NoteBox>
                      Runs start here: firing this {selected.trigger} trigger
                      seeds every connected agent with the prompt you submit.
                    </NoteBox>
                  ) : selected.kind === 'instruction' ? (
                    // The field's own hint is the whole explanation this panel
                    // owes. A `NoteBox` under it repeated it — "never runs and
                    // has no status", "wire one block to several agents" — as a
                    // second paragraph about the same block, and was REPORTED
                    // as exactly that: "этот блок нужно убрать. Он бесполезен!".
                    // Neither sentence is about THIS block: they describe what
                    // an instruction node is, which the palette tile's own info
                    // dialog states once, where somebody is deciding whether to
                    // add one.
                    <Field
                      label="Instructions"
                      htmlFor="node-instructions"
                      hint="Appended to the turn of every agent you wire this block to — after your global custom instructions, before that node's own role.">
                      <ExpandableTextarea
                        id="node-instructions"
                        title="Instructions"
                        value={selected.instructions}
                        rows={8}
                        placeholder="Prefer short sentences. Cite the files you changed."
                        onChange={(next) =>
                          patchSelected({ instructions: next })
                        }
                      />
                    </Field>
                  ) : (
                    <>
                      {/* Every per-run setting as a LABELLED ROW, in one divided
                        card — a label column over the composer's own chips.

                        The controls are already right and stay untouched: an
                        earlier report ("effort select and model should be same
                        design as when we create chat … approval should be near
                        by … config directory should be the same setting")
                        replaced four `Field`s of three different kinds with the
                        composer's chips, and every one of them still names the
                        same thing the composer names.

                        What changed is the LAYOUT, and the reason is the same
                        one written on `SettingRow`. A wrapping chip row is
                        right under a message box, where it reads as a sentence
                        about the next turn. Here it is read rather than
                        written: an unlabelled `high` says nothing about which
                        axis it is, and the row REFLOWS as the model changes —
                        `claude-opus-5` through cursor draws eight chips over
                        four lines — so the same setting sat somewhere different
                        on every node you clicked. A fixed label column gives
                        each one an address, and the control's cell truncates
                        instead of wrapping.

                        `compact`, because this panel is draggable down to 240px
                        (`inspector`'s `minWidth`) where the dialog's 7rem label
                        column would leave the control ~100px.

                        ORDER is profile, approval, then the model and
                        everything the model offers — the same order the
                        composer's model-settings panel lists them in, so a
                        label column and a popover teach one order rather than
                        two. MCP is last because it is the one row that opens
                        something instead of setting a value. */}
                      <Field label="Agent settings">
                        {/* `@container`: the rows fit themselves to THIS card,
                          whose width comes from the panel's drag handle rather
                          than from the window — see `SettingRow`'s `compact`,
                          which stacks label over control once two columns can no
                          longer hold the longest value. */}
                        <div className="@container flex flex-col divide-y divide-border rounded-md border border-border bg-card">
                          {/* Absent — not disabled — for a CLI that reads no
                            config directory, and absent while the daemon has
                            not said either way. The chip decided that itself
                            from the reason it was handed; in a label column the
                            ROW has to go with it, or the panel carries a
                            `Profile` heading with a hole under it. */}
                          {configDirCapability.unavailableReasonFor(
                            selected.agent,
                          ) === null ? (
                            <SettingRow width="compact" label="Profile">
                              <ConfigDirSelect
                                configDir={selected.configDir ?? null}
                                recentConfigDirs={recentConfigDirs}
                                unavailableReason={null}
                                ariaLabel="Agent config directory for this node"
                                onChange={(configDir) =>
                                  patchSelected({
                                    configDir: configDir ?? undefined,
                                  })
                                }
                                onBrowse={() => void chooseNodeConfigDir()}
                              />
                            </SettingRow>
                          ) : null}
                          <SettingRow width="compact" label="Approval">
                            <ApprovalModeSelect
                              supportedModes={nodeApprovalModes}
                              // Never on a workflow node — see `nodeApprovalModes`.
                              planSupported={false}
                              value={selected.approval}
                              onChange={(approval) =>
                                patchSelected({
                                  approval: approval as WorkflowApproval,
                                })
                              }
                            />
                          </SettingRow>
                          <SettingRow width="compact" label="Model">
                            {/* `key` per node: the chip decides its free-text mode
                              once, and that decision is one node's. */}
                            <ModelSelect
                              key={selected.id}
                              agentKind={selected.agent}
                              models={agentModels}
                              loading={agentModelsLoading}
                              // The builder's own half of the chip — a full model
                              // id the CLI does not enumerate is worth a text
                              // field in a workflow that runs for months.
                              allowCustom
                              value={selected.model ?? null}
                              // Changing the model clears the window and the other
                              // parameters with it: both belong to the model that
                              // offered them, and a workflow keeping `1m` — or an
                              // `optimize_for` the new model never enumerated —
                              // would send `-32602` on every turn for months.
                              onChange={(model) =>
                                patchSelected({
                                  model: model ?? undefined,
                                  contextWindow: undefined,
                                  modelParameters: undefined,
                                })
                              }
                            />
                          </SettingRow>
                          {/* The ROW goes with the control, here and in the two
                            below. Each of these chips renders nothing when the
                            model offers no such axis, and a labelled row around
                            nothing is a label with a hole under it — louder in a
                            fixed column than the missing chip ever was. The
                            guard is the chip's own "renders nothing with
                            nothing to pick", asked one level out. */}
                          {agentEfforts.efforts.length === 0 ? null : (
                            <SettingRow width="compact" label="Effort">
                              <EffortSelect
                                efforts={agentEfforts.efforts}
                                levelsAreModelSpecific={
                                  selected.model !== undefined
                                }
                                value={selected.effort ?? null}
                                onChange={(effort) =>
                                  patchSelected({ effort: effort ?? undefined })
                                }
                              />
                            </SettingRow>
                          )}
                          {agentContextWindows.windows.length === 0 ? null : (
                            <SettingRow width="compact" label="Context">
                              <ContextWindowSelect
                                windows={agentContextWindows.windows}
                                value={selected.contextWindow ?? null}
                                onChange={(contextWindow) =>
                                  patchSelected({
                                    contextWindow: contextWindow ?? undefined,
                                  })
                                }
                              />
                            </SettingRow>
                          )}
                          {/* Always offered: a share of the window belongs to
                            no model, so there is no listing to wait for. */}
                          <SettingRow width="compact" label="Auto-compact">
                            <AutoCompactSelect
                              value={selected.autoCompactPercent ?? null}
                              onChange={(percent) =>
                                patchSelected({
                                  autoCompactPercent: percent ?? undefined,
                                })
                              }
                            />
                          </SettingRow>
                          {/* One labelled ROW per OTHER setting this node's model
                            enumerates — the same set the composer draws, over
                            the node's own stored map, and a row apiece for the
                            reason the editor gives: a setting with no address of
                            its own is the wrapping chip row this band replaced.
                            The label is the CLI's own word for the axis, which
                            is the only name this app has for it.

                            `undefined` rather than an empty object when the last
                            one is cleared, so the YAML loses the key instead of
                            carrying `{}`. */}
                          {agentModelParameters.parameters.map((parameter) => (
                            <SettingRow
                              key={parameter.id}
                              width="compact"
                              label={parameter.label}>
                              <ModelParameterSelect
                                parameter={parameter}
                                // The row names the axis now, so the chip must not
                                // name it too — `Optimize For    Optimize For ·
                                // Balance` is the stutter the label column exists
                                // to remove.
                                showAxisName={false}
                                value={
                                  selected.modelParameters?.[parameter.id] ??
                                  null
                                }
                                onChange={(next) => {
                                  const merged = withModelParameter(
                                    selected.modelParameters ?? {},
                                    parameter.id,
                                    next,
                                  );
                                  patchSelected({
                                    modelParameters:
                                      Object.keys(merged).length === 0
                                        ? undefined
                                        : merged,
                                  });
                                }}
                              />
                            </SettingRow>
                          ))}
                          {/* Reported as "we should have a button there to show
                            MCP, not just inline". It was a section standing
                            open in the panel — a header, a hint, up to ten
                            server rows and a paragraph of connection-failure
                            text under each broken one — between the node's
                            settings and its call wiring. Behind a chip it is
                            one press away and the panel is readable.

                            The READ still happens on selection rather than on
                            the press: it is what validates the config-directory
                            path below, and the CLI says nothing about a profile
                            it cannot use. Gating it would move that error
                            behind a button nobody opens.

                            Suppressed entirely while the path is refused: the
                            listing would restate the same sentence as if it
                            were a fact about the folder's servers, and there is
                            nothing behind it to show. */}
                          {configDirError === null ? (
                            <SettingRow width="compact" label="MCP">
                              <McpDialogButton
                                variant="chip"
                                // The row says `MCP`; the control says how many.
                                chipNamesItself={false}
                                title={`MCP servers — ${selected.name ?? selected.id}`}
                                open={mcpOpen}
                                onOpenChange={setMcpOpen}
                                listing={nodeMcp.listing}
                                loading={nodeMcp.loading}
                                hint={
                                  // The second sentence is why there are no
                                  // on/off switches here, said out loud: a
                                  // control that simply vanishes is what got
                                  // this dialog reported in the first place.
                                  // Signing in IS offered — credentials are not
                                  // folder-bound — so only the switch is named.
                                  selected.configDir
                                    ? "The servers configured in this node's own config directory. The run folder's own project servers are added when it runs. Switching one off is a per-folder choice, so it is made in a chat rather than here."
                                    : 'Global servers. The run folder’s own project servers are added when it runs. Switching one off is a per-folder choice, so it is made in a chat rather than here.'
                                }
                                onRefresh={nodeMcp.refresh}
                                onSignIn={(server) => {
                                  void login.startMcp({
                                    kind: selected.agent,
                                    server,
                                    // No cwd: the daemon signs in where it
                                    // TOOK this listing — its own folderless
                                    // directory — so the name resolves to the
                                    // server the row is about.
                                    configDir: selected.configDir ?? null,
                                  });
                                }}
                                // Busy for the whole flow, both windows: the
                                // daemon holds its first reply until the CLI
                                // prints a URL, and `mcp login` then EXITS
                                // while the user is still authorizing. A second
                                // press in either opens a second challenge and
                                // invalidates the first.
                                signingIn={
                                  login.starting?.server ??
                                  login.login?.server ??
                                  null
                                }
                                loginServer={login.login?.server ?? null}
                                loginPanel={
                                  login.login && login.login.server !== null ? (
                                    <CliLoginProgress
                                      session={login.login.session}
                                      onSubmitCode={(code) =>
                                        void login.submitCode(code)
                                      }
                                      onCancel={() => void login.cancel()}
                                      onDismiss={login.dismiss}
                                      error={login.error}
                                      variant="inline"
                                    />
                                  ) : null
                                }
                              />
                            </SettingRow>
                          ) : null}
                        </div>
                        {/* The daemon's refusal is the ONLY thing that can tell
                          the user their path is wrong — claude CREATES a
                          directory it cannot find and then reports "Not logged
                          in" about it. Folded into the listing's
                          `unavailableReason` it rendered in the same muted span
                          as "No servers", which reads as a fact about the
                          profile rather than a typo. */}
                        {/* `break-words` because this string is routinely ONE
                          unbroken token: the daemon's uniform error shape puts
                          the percent-encoded query string in it, and a 300px
                          panel cannot wrap that at a space it does not have —
                          unwrapped it did not widen the panel, it ran out past
                          its right edge and was unreadable from the URL on. */}
                        {configDirError ? (
                          <ErrorText
                            id="node-config-dir-error"
                            className="text-xs break-words">
                            {configDirError}
                          </ErrorText>
                        ) : null}
                        {/* A config directory this CLI will ignore. Only when the
                          node actually carries one — a workflow imported from
                          YAML can, and with the chip absent the user had no way
                          to see what to remove. */}
                        {selected.configDir &&
                        configDirCapability.unavailableReasonFor(
                          selected.agent,
                        ) ? (
                          <NoteBox
                            aria-label="Config directory"
                            className="text-xs">
                            <span className="block">
                              {configDirCapability.unavailableReasonFor(
                                selected.agent,
                              )}
                            </span>
                            <span className="block text-warning">
                              This node names {selected.configDir}, which will
                              be ignored when it runs.
                            </span>
                          </NoteBox>
                        ) : null}
                      </Field>
                      <Field
                        label="Description"
                        htmlFor="node-description"
                        hint="What this agent is for. Agents wired to call it see this — and nothing else about it — so they can route work here on their own.">
                        <ExpandableTextarea
                          id="node-description"
                          title="Description"
                          value={selected.description ?? ''}
                          rows={3}
                          placeholder="Reviews a diff or branch and reports findings by severity."
                          onChange={(next) =>
                            patchSelected({ description: next || undefined })
                          }
                        />
                      </Field>
                      <Field
                        label="Role / system prompt"
                        htmlFor="node-role"
                        hint="Prepended to this node's turn. Private — no other agent ever reads it.">
                        <ExpandableTextarea
                          id="node-role"
                          title="Role / system prompt"
                          value={selected.role ?? ''}
                          rows={5}
                          onChange={(next) =>
                            patchSelected({ role: next || undefined })
                          }
                        />
                      </Field>
                      {callInfo ? (
                        <Field
                          label="Agent calls"
                          hint="This agent routes by each callee's Description — never their Role.">
                          <AgentCallsCard
                            info={callInfo}
                            agentKind={selected.agent}
                          />
                        </Field>
                      ) : null}
                    </>
                  )}
                </div>
              </div>
            </MenuAnchorContext.Provider>
          </aside>
        ) : null}
      </div>

      {chatOpen && activeSlug !== null ? (
        <WorkflowChatPanel
          // Keyed by slug so opening another workflow's builder can never show
          // the previous one's conversation for a frame.
          key={activeSlug}
          slug={activeSlug}
          workflowName={name}
          apis={apis}
          client={client}
          capabilities={capabilities}
          capabilitiesLoading={capabilitiesLoading}
          recentConfigDirs={recentConfigDirs}
          onClose={() => setChatOpen(false)}
          onBeforeSend={autosave.flush}
          onWorkingChange={setChatWorking}
          onTurnSettled={reloadAfterAgentEdit}
        />
      ) : null}

      <BuilderStatusBar
        nodeCount={nodes.length}
        edgeCount={edges.length}
        message={error ? null : notice}
        saveState={autosave.state}
      />

      <WorkflowMetaDialog
        open={renameOpen}
        busy={renaming}
        error={renameOpen ? error : null}
        title="Change workflow"
        submitLabel="Save"
        busyLabel="Saving…"
        initial={{
          name,
          ...(description.trim() ? { description } : {}),
        }}
        onClose={() => setRenameOpen(false)}
        onSubmit={(meta) => void renameWorkflow(meta)}
      />

      <ConfirmDialog
        open={removeOpen}
        busy={deleting}
        error={removeOpen ? error : null}
        title="Delete workflow"
        confirmLabel="Delete"
        busyLabel="Deleting…"
        onCancel={() => setRemoveOpen(false)}
        onConfirm={() => {
          void remove().then((removed) => {
            if (removed) {
              setRemoveOpen(false);
            }
          });
        }}>
        <p>
          Delete <span className="font-medium text-foreground">{name}</span>{' '}
          permanently? Its <code>{activeSlug}.geniro.yaml</code> file is removed
          from the library. Past runs of it are kept.
        </p>
      </ConfirmDialog>
    </section>
  );
}
