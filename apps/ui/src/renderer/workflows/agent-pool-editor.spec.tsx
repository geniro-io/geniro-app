// @vitest-environment jsdom
import { act, useState } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type {
  AgentApprovalCapability,
  AgentIdentityCapability,
  WorkflowAgentPoolMember,
} from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import { AgentPoolEditor } from './agent-pool-editor';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(() => {
  act(() => root?.unmount());
  container?.remove();
  root = null;
  container = null;
});

const AGENTS = [
  { agent: 'claude', displayName: 'Claude Code', shortName: 'claude' },
  { agent: 'codex', displayName: 'Codex', shortName: 'codex' },
] as unknown as AgentIdentityCapability[];

// codex lacks `acceptEdits`, so the node's own mode below is one a codex
// member does not honour.
const APPROVALS = [
  { agent: 'claude', modes: ['auto', 'acceptEdits', 'ask'] },
  { agent: 'codex', modes: ['auto', 'ask'] },
] as unknown as AgentApprovalCapability[];

function renderEditor(
  members: WorkflowAgentPoolMember[],
  agentsApi: DaemonApis['agents'] | null = null,
  nodeAutoCompactPercent: number | undefined = undefined,
): ReturnType<typeof vi.fn> {
  const onChange = vi.fn();
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root?.render(
      <AgentPoolEditor
        members={members}
        agents={AGENTS}
        agentsApi={agentsApi}
        defaultAgent="claude"
        configDirAvailable={() => false}
        approvals={APPROVALS}
        nodeApproval="acceptEdits"
        nodeAutoCompactPercent={nodeAutoCompactPercent}
        recentConfigDirs={{}}
        configProfiles={[]}
        pickFolder={async () => null}
        onChange={onChange}
      />,
    );
  });
  return onChange;
}

function button(name: string): HTMLButtonElement {
  const found = [...document.querySelectorAll('button')].find(
    (b) =>
      b.getAttribute('aria-label') === name ||
      (b.textContent ?? '').trim() === name,
  );
  if (!found) {
    throw new Error(`no button named ${name}`);
  }
  return found;
}

function press(element: Element): void {
  act(() => {
    element.dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

/** Opens the picker labelled `label` and presses its option reading `text`. */
function choose(label: string, text: string): void {
  const trigger = document.querySelector(`[aria-label="${label}"]`);
  if (!trigger) {
    throw new Error(`no picker ${label}`);
  }
  press(trigger);
  const option = [...document.querySelectorAll('[role="option"]')].find(
    (candidate) => (candidate.textContent ?? '').trim() === text,
  );
  if (!option) {
    throw new Error(`no option ${text}`);
  }
  press(option);
}

describe('AgentPoolEditor', () => {
  it('adds a member on the node’s own CLI', () => {
    const onChange = renderEditor([]);
    press(button('Add pool member'));
    expect(onChange).toHaveBeenCalledWith([{ agent: 'claude' }]);
  });

  it('starts a new member at the node’s own auto-compact threshold', () => {
    const onChange = renderEditor([], null, 80);
    press(button('Add pool member'));
    expect(onChange).toHaveBeenCalledWith([
      { agent: 'claude', autoCompactPercent: 80 },
    ]);
  });

  it('sets a member’s own auto-compact threshold, and clears it with off', () => {
    const onChange = renderEditor([{ agent: 'codex', autoCompactPercent: 80 }]);
    choose('Auto-compact for member 2', 'at 60%');
    expect(onChange).toHaveBeenLastCalledWith([
      { agent: 'codex', autoCompactPercent: 60 },
    ]);
    choose('Auto-compact for member 2', 'off');
    expect(onChange).toHaveBeenLastCalledWith([
      { agent: 'codex', autoCompactPercent: undefined },
    ]);
  });

  it('sets a member’s own approval mode, showing the node’s until it does', () => {
    const onChange = renderEditor([{ agent: 'claude' }]);
    const trigger = document.querySelector(
      '[aria-label="Tool-approval mode for member 2"]',
    );
    expect(trigger?.textContent).toContain('accept edits');
    choose('Tool-approval mode for member 2', 'auto-approve');
    expect(onChange).toHaveBeenLastCalledWith([
      { agent: 'claude', approval: 'auto' },
    ]);
  });

  it('numbers existing members from 2 — the node itself is member 1', () => {
    renderEditor([{ agent: 'codex' }]);
    expect(container?.textContent).toContain('Member 2');
  });

  it('removing the last member clears the pool rather than leaving an empty list', () => {
    const onChange = renderEditor([{ agent: 'codex' }]);
    press(button('Remove member 2'));
    expect(onChange).toHaveBeenCalledWith(undefined);
  });

  it('moves a member down', () => {
    const onChange = renderEditor([
      { agent: 'codex' },
      { agent: 'claude', configDir: '/p' },
    ]);
    press(button('Move member 2 down'));
    expect(onChange).toHaveBeenCalledWith([
      { agent: 'claude', configDir: '/p' },
      { agent: 'codex' },
    ]);
  });

  it('moves a member’s ROW with it, not just its values', () => {
    // Keyed by position, the row left in place would be handed the other
    // member's settings — and with them its fetched lists and open picker.
    function Harness(): React.JSX.Element {
      const [members, setMembers] = useState<WorkflowAgentPoolMember[]>([
        { agent: 'codex' },
        { agent: 'claude', configDir: '/p' },
      ]);
      return (
        <AgentPoolEditor
          members={members}
          agents={AGENTS}
          agentsApi={null}
          defaultAgent="claude"
          configDirAvailable={() => false}
          approvals={APPROVALS}
          nodeApproval="auto"
          nodeAutoCompactPercent={undefined}
          recentConfigDirs={{}}
          configProfiles={[]}
          pickFolder={async () => null}
          onChange={(next) => setMembers(next ?? [])}
        />
      );
    }
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    act(() => root?.render(<Harness />));
    const rows = (): Element[] => [
      ...document.querySelectorAll('[data-slot="agent-pool-member"]'),
    ];
    const codexRow = rows()[0];

    press(button('Move member 2 down'));

    expect(rows()[1]).toBe(codexRow);
  });

  it('offers a member its model’s context window and other settings', async () => {
    const agentsApi = {
      listAgentModels: vi.fn(async () => []),
      listAgentEfforts: vi.fn(async () => ({
        efforts: [],
        unavailableReason: null,
      })),
      listAgentContextWindows: vi.fn(async () => ({
        windows: [{ id: '1m', label: '1M' }],
        unavailableReason: null,
        unavailableKind: null,
      })),
      listAgentModelParameters: vi.fn(async () => ({
        parameters: [
          {
            id: 'fast',
            label: 'Fast',
            values: [
              { id: 'true', label: 'On' },
              { id: 'false', label: 'Off' },
            ],
            current: null,
          },
        ],
        unavailableReason: null,
      })),
    } as unknown as DaemonApis['agents'];

    renderEditor([{ agent: 'claude', model: 'opus' }], agentsApi);
    await act(async () => {
      await new Promise((resolve) => setTimeout(resolve, 0));
    });

    expect(agentsApi.listAgentContextWindows).toHaveBeenCalledWith(
      expect.objectContaining({ agent: 'claude', model: 'opus' }),
    );
    const labels = [
      ...document.querySelectorAll('[data-slot="agent-pool-member"] *'),
    ].map((node) => (node.childElementCount === 0 ? node.textContent : ''));
    expect(labels).toContain('Context');
    expect(labels).toContain('Fast');
  });

  it('switching a member’s CLI drops the settings the old CLI offered, and keeps its threshold', () => {
    const onChange = renderEditor([
      {
        agent: 'claude',
        model: 'opus',
        effort: 'high',
        configDir: '/p',
        approval: 'acceptEdits',
        autoCompactPercent: 70,
      },
    ]);
    const trigger = document.querySelector('[aria-label="CLI for member 2"]');
    if (!trigger) {
      throw new Error('no CLI picker');
    }
    press(trigger);
    const codex = [...document.querySelectorAll('[role="option"]')].find(
      (option) => (option.textContent ?? '').includes('Codex'),
    );
    if (!codex) {
      throw new Error('no Codex option');
    }
    press(codex);
    expect(onChange).toHaveBeenCalledWith([
      { agent: 'codex', autoCompactPercent: 70 },
    ]);
  });

  it('offers no add control once the pool is full', () => {
    renderEditor(
      Array.from({ length: 7 }, () => ({ agent: 'codex' as const })),
    );
    expect(
      [...document.querySelectorAll('button')].some(
        (b) => (b.textContent ?? '').trim() === 'Add pool member',
      ),
    ).toBe(false);
  });

  it('warns on a member whose CLI does not offer the approval mode it runs', () => {
    renderEditor([
      { agent: 'codex' },
      { agent: 'claude' },
      { agent: 'codex', approval: 'auto' },
    ]);
    const notes = document.querySelectorAll(
      '[data-slot="agent-pool-approval-note"]',
    );
    expect(notes).toHaveLength(1);
    expect(notes[0]?.textContent).toContain('“accept edits”');
  });
});
