/**
 * Members a pool may hold BESIDES the node's own.
 *
 * TWIN: the daemon's `MAX_AGENT_POOL_EXTRA_MEMBERS` (`graphs.types.ts`), which
 * refuses a longer pool on save. Change one, change the other.
 */
const MAX_POOL_EXTRA_MEMBERS = 7;

/**
 * The node's AGENT POOL: further configurations a CALL to this node can run
 * under — another account, another model, another CLI.
 *
 * The node's own settings above are member 1, so this lists members 2, 3, …
 * and says so; the numbers are the ones a calling agent picks a member by.
 * Each row asks its OWN CLI for its models and efforts, under its own profile,
 * because a member is a different account as often as a different CLI.
 */
export function AgentPoolEditor({
  members,
  agents,
  agentsApi,
  defaultAgent,
  configDirAvailable,
  approvalOffered,
  recentConfigDirs,
  configProfiles,
  pickFolder,
  onChange,
}: {
  members: readonly WorkflowAgentPoolMember[];
  /** Every CLI the daemon can run, for the member's CLI picker. */
  agents: readonly AgentIdentityCapability[];
  agentsApi: DaemonApis['agents'] | null;
  /** The CLI a newly added member starts on — the node's own. */
  defaultAgent: AgentKind;
  /** Whether a CLI can be pointed at a config directory at all. */
  configDirAvailable: (agent: AgentKind) => boolean;
  /**
   * The node's approval mode, shared by every member, when a CLI does NOT
   * honour it — null when it does. A member on such a CLI runs the mode its
   * CLI falls back to, which can stop an unattended call to ask.
   */
  approvalOffered: (agent: AgentKind) => string | null;
  recentConfigDirs: Partial<Record<AgentKind, string[]>>;
  configProfiles: readonly ConfigProfile[];
  /** The native folder picker; null when the user cancelled. */
  pickFolder: () => Promise<string | null>;
  /** The whole list after an edit; undefined once the last member is removed. */
  onChange: (next: WorkflowAgentPoolMember[] | undefined) => void;
}): React.JSX.Element {
  // A row key per member, moved WITH it: a member has no id of its own, and
  // keyed by position a reorder hands each row the other's fetched lists and
  // open picker. Rebuilt only when the list arrives from elsewhere (another
  // node selected, the YAML replaced) at a different length.
  const keys = useRef<string[]>([]);
  if (keys.current.length !== members.length) {
    keys.current = members.map((_, i) => keys.current[i] ?? randomId());
  }
  const commit = (next: WorkflowAgentPoolMember[]): void => {
    onChange(next.length === 0 ? undefined : next);
  };
  const replace = (index: number, member: WorkflowAgentPoolMember): void => {
    commit(members.map((current, i) => (i === index ? member : current)));
  };
  const move = (index: number, by: -1 | 1): void => {
    const next = [...members];
    const [moved] = next.splice(index, 1);
    next.splice(index + by, 0, moved!);
    const [key] = keys.current.splice(index, 1);
    keys.current.splice(index + by, 0, key!);
    commit(next);
  };
  const remove = (index: number): void => {
    keys.current.splice(index, 1);
    commit(members.filter((_, i) => i !== index));
  };
  const add = (): void => {
    keys.current.push(randomId());
    commit([...members, { agent: defaultAgent }]);
  };

  return (
    <div data-slot="agent-pool" className="flex flex-col gap-2">
      <p className="text-xs text-muted-foreground">
        {members.length === 0
          ? 'Add further accounts, models or CLIs a call to this agent can run on. A new call takes the next member in turn, and one that hits a usage limit or a lapsed sign-in moves to the next member by itself.'
          : 'Member 1 is the settings above. A new call takes the next member in turn, and moves on when a member hits a usage limit or a lapsed sign-in; a calling agent can also pick a member by number.'}
      </p>
      {members.map((member, index) => (
        <PoolMemberRow
          key={keys.current[index]}
          number={index + 2}
          member={member}
          agents={agents}
          agentsApi={agentsApi}
          configDirAvailable={configDirAvailable(member.agent)}
          unofferedApproval={approvalOffered(member.agent)}
          recentConfigDirs={recentConfigDirs[member.agent] ?? []}
          configProfiles={configProfiles.filter(
            (profile) => profile.agent === member.agent,
          )}
          canMoveUp={index > 0}
          canMoveDown={index < members.length - 1}
          onChange={(next) => replace(index, next)}
          onBrowse={async () => {
            const chosen = await pickFolder();
            if (chosen !== null) {
              replace(index, { ...member, configDir: chosen });
            }
          }}
          onMove={(by) => move(index, by)}
          onRemove={() => remove(index)}
        />
      ))}
      {members.length < MAX_POOL_EXTRA_MEMBERS ? (
        <Button
          type="button"
          variant="outline"
          size="sm"
          className="self-start"
          onClick={add}>
          <Plus aria-hidden />
          Add pool member
        </Button>
      ) : null}
    </div>
  );
}

function PoolMemberRow({
  number,
  member,
  agents,
  agentsApi,
  configDirAvailable,
  unofferedApproval,
  recentConfigDirs,
  configProfiles,
  canMoveUp,
  canMoveDown,
  onChange,
  onBrowse,
  onMove,
  onRemove,
}: {
  number: number;
  member: WorkflowAgentPoolMember;
  agents: readonly AgentIdentityCapability[];
  agentsApi: DaemonApis['agents'] | null;
  configDirAvailable: boolean;
  unofferedApproval: string | null;
  recentConfigDirs: string[];
  configProfiles: readonly ConfigProfile[];
  canMoveUp: boolean;
  canMoveDown: boolean;
  onChange: (member: WorkflowAgentPoolMember) => void;
  onBrowse: () => Promise<void>;
  onMove: (by: -1 | 1) => void;
  onRemove: () => void;
}): React.JSX.Element {
  const configDir = member.configDir ?? null;
  const { models, loading } = useAgentModels(
    agentsApi,
    member.agent,
    configDir,
  );
  const { efforts } = useAgentEfforts(
    agentsApi,
    member.agent,
    member.model ?? null,
    configDir,
  );
  const { windows } = useAgentContextWindows(
    agentsApi,
    member.agent,
    member.model ?? null,
    configDir,
  );
  const { parameters } = useAgentModelParameters(
    agentsApi,
    member.agent,
    member.model ?? null,
    configDir,
  );

  return (
    <div
      data-slot="agent-pool-member"
      className="@container flex flex-col divide-y divide-border rounded-md border border-border bg-card">
      <div className="flex items-center gap-1 px-3 py-1.5">
        <span className="flex-1 text-xs font-medium text-foreground">
          Member {number}
        </span>
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className="size-7"
          aria-label={`Move member ${number} up`}
          disabled={!canMoveUp}
          onClick={() => onMove(-1)}>
          <ArrowUp aria-hidden />
        </Button>
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className="size-7"
          aria-label={`Move member ${number} down`}
          disabled={!canMoveDown}
          onClick={() => onMove(1)}>
          <ArrowDown aria-hidden />
        </Button>
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className="size-7"
          aria-label={`Remove member ${number}`}
          onClick={onRemove}>
          <Trash2 aria-hidden />
        </Button>
      </div>
      <SettingRow width="compact" label="Agent">
        <Select
          variant="ghost"
          aria-label={`CLI for member ${number}`}
          value={member.agent}
          groups={[
            {
              items: agents.map((agent) => ({
                value: agent.agent,
                label: agent.displayName,
              })),
            },
          ]}
          // Every CLI setting belongs to the CLI that offered it, so another
          // CLI starts the member from that CLI's defaults.
          onValueChange={(agent) => {
            if (agent !== member.agent) {
              onChange({ agent: agent as AgentKind });
            }
          }}
        />
      </SettingRow>
      {configDirAvailable ? (
        <SettingRow width="compact" label="Profile">
          <ConfigDirSelect
            configDir={configDir}
            recentConfigDirs={recentConfigDirs}
            configProfiles={configProfiles}
            unavailableReason={null}
            ariaLabel={`Agent config directory for member ${number}`}
            onChange={(next) =>
              onChange({ ...member, configDir: next ?? undefined })
            }
            onBrowse={() => void onBrowse()}
          />
        </SettingRow>
      ) : null}
      <SettingRow width="compact" label="Model">
        <ModelSelect
          key={member.agent}
          agentKind={member.agent}
          models={models}
          loading={loading}
          allowCustom
          value={member.model ?? null}
          // A window or a parameter belongs to the model that offered it.
          onChange={(model) =>
            onChange({ ...member, ...modelChangePatch(model) })
          }
        />
      </SettingRow>
      {unofferedApproval === null ? null : (
        <p
          data-slot="agent-pool-approval-note"
          className="px-3 py-1.5 text-xs text-warning">
          This CLI does not offer the “
          {MODE_LABELS.find((mode) => mode.value === unofferedApproval)
            ?.label ?? unofferedApproval}
          ” approval this agent uses — calls on this member may stop to ask.
        </p>
      )}
      <ModelSettingsRows
        efforts={efforts}
        windows={windows}
        parameters={parameters}
        value={member}
        onPatch={(patch) => onChange({ ...member, ...patch })}
      />
    </div>
  );
}
