/**
 * Members a pool may hold BESIDES the node's own.
 *
 * TWIN: the daemon's `MAX_AGENT_POOL_EXTRA_MEMBERS` (`graphs.types.ts`), which
 * refuses a longer pool on save. Change one, change the other.
 */
const MAX_POOL_EXTRA_MEMBERS = 7;

/**
 * The node's AGENT POOL: further configurations a CALL to this node can run
 * under — another account, another model, another CLI.
 *
 * The node's own settings above are member 1, so this lists members 2, 3, …
 * and says so; the numbers are the ones a calling agent picks a member by.
 * Each row asks its OWN CLI for its models, efforts and MCP servers, under its
 * own profile, because a member is a different account as often as a different
 * CLI. A row offers every setting the card above does: its own approval mode
 * (the node's until it picks one) and its own auto-compact threshold (never
 * until it picks one — a new member starts from the node's).
 */
/**
 * Signing a member's MCP server in — the builder's ONE sign-in controller
 * (`useCliLogin`), shared with the node's own MCP dialog: one browser
 * challenge at a time, since a second invalidates the first.
 */
export interface PoolMcpSignIn {
  /** Start signing `server` in under one member's CLI and profile. */
  start: (agent: AgentKind, server: string, configDir: string | null) => void;
  /** The CLI + profile the sign-in in flight was started for, or null. */
  scope: { agent: AgentKind; configDir: string | null } | null;
  signingIn: string | null;
  loginServer: string | null;
  loginPanel: React.ReactNode;
  /** Bumped each time a server sign-in settles — a member re-reads on it. */
  settledToken: number;
}

export function AgentPoolEditor({
  members,
  agents,
  agentsApi,
  defaultAgent,
  configDirAvailable,
  approvals,
  nodeApproval,
  nodeAutoCompactPercent,
  recentConfigDirs,
  configProfiles,
  pickFolder,
  mcpSignIn,
  onChange,
}: {
  members: readonly WorkflowAgentPoolMember[];
  /** Every CLI the daemon can run, for the member's CLI picker. */
  agents: readonly AgentIdentityCapability[];
  agentsApi: DaemonApis['agents'] | null;
  /** The CLI a newly added member starts on — the node's own. */
  defaultAgent: AgentKind;
  /** Whether a CLI can be pointed at a config directory at all. */
  configDirAvailable: (agent: AgentKind) => boolean;
  /** Every CLI's approval modes (`GET /v1/capabilities` `approvals[]`). */
  approvals: readonly AgentApprovalCapability[];
  /** The node's own mode — what a member that names none runs. */
  nodeApproval: WorkflowApproval;
  /** The node's own threshold, which a NEW member starts from. */
  nodeAutoCompactPercent: number | undefined;
  recentConfigDirs: Partial<Record<AgentKind, string[]>>;
  configProfiles: readonly ConfigProfile[];
  /** The native folder picker; null when the user cancelled. */
  pickFolder: () => Promise<string | null>;
  /** Absent leaves every member's MCP dialog without a Sign in. */
  mcpSignIn?: PoolMcpSignIn;
  /** The whole list after an edit; undefined once the last member is removed. */
  onChange: (next: WorkflowAgentPoolMember[] | undefined) => void;
}): React.JSX.Element {
  // A row key per member, moved WITH it: a member has no id of its own, and
  // keyed by position a reorder hands each row the other's fetched lists and
  // open picker. Rebuilt only when the list arrives from elsewhere (another
  // node selected, the YAML replaced) at a different length.
  const keys = useRef<string[]>([]);
  if (keys.current.length !== members.length) {
    keys.current = members.map((_, i) => keys.current[i] ?? randomId());
  }
  const commit = (next: WorkflowAgentPoolMember[]): void => {
    onChange(next.length === 0 ? undefined : next);
  };
  const replace = (index: number, member: WorkflowAgentPoolMember): void => {
    commit(members.map((current, i) => (i === index ? member : current)));
  };
  const move = (index: number, by: -1 | 1): void => {
    const next = [...members];
    const [moved] = next.splice(index, 1);
    next.splice(index + by, 0, moved!);
    const [key] = keys.current.splice(index, 1);
    keys.current.splice(index + by, 0, key!);
    commit(next);
  };
  const remove = (index: number): void => {
    keys.current.splice(index, 1);
    commit(members.filter((_, i) => i !== index));
  };
  const add = (): void => {
    keys.current.push(randomId());
    commit([
      ...members,
      {
        agent: defaultAgent,
        ...(nodeAutoCompactPercent !== undefined
          ? { autoCompactPercent: nodeAutoCompactPercent }
          : {}),
      },
    ]);
  };

  return (
    <div data-slot="agent-pool" className="flex flex-col gap-2">
      <p className="text-xs text-muted-foreground">
        {members.length === 0
          ? 'Add further accounts, models or CLIs a call to this agent can run on. A new call takes the next member in turn, and one that hits a usage limit or a lapsed sign-in moves to the next member by itself.'
          : 'Member 1 is the settings above. A new call takes the next member in turn, and moves on when a member hits a usage limit or a lapsed sign-in; a calling agent can also pick a member by number.'}
      </p>
      {members.map((member, index) => (
        <PoolMemberRow
          key={keys.current[index]}
          number={index + 2}
          member={member}
          agents={agents}
          agentsApi={agentsApi}
          configDirAvailable={configDirAvailable(member.agent)}
          approval={approvals.find((entry) => entry.agent === member.agent)}
          nodeApproval={nodeApproval}
          recentConfigDirs={recentConfigDirs[member.agent] ?? []}
          configProfiles={configProfiles.filter(
            (profile) => profile.agent === member.agent,
          )}
          canMoveUp={index > 0}
          canMoveDown={index < members.length - 1}
          onChange={(next) => replace(index, next)}
          onBrowse={async () => {
            const chosen = await pickFolder();
            if (chosen !== null) {
              replace(index, { ...member, configDir: chosen });
            }
          }}
          onMove={(by) => move(index, by)}
          onRemove={() => remove(index)}
          mcpSignIn={mcpSignIn}
        />
      ))}
      {members.length < MAX_POOL_EXTRA_MEMBERS ? (
        <Button
          type="button"
          variant="outline"
          size="sm"
          className="self-start"
          onClick={add}>
          <Plus aria-hidden />
          Add pool member
        </Button>
      ) : null}
    </div>
  );
}

function PoolMemberRow({
  number,
  member,
  agents,
  agentsApi,
  configDirAvailable,
  approval,
  nodeApproval,
  recentConfigDirs,
  configProfiles,
  canMoveUp,
  canMoveDown,
  onChange,
  onBrowse,
  onMove,
  onRemove,
  mcpSignIn,
}: {
  number: number;
  member: WorkflowAgentPoolMember;
  agents: readonly AgentIdentityCapability[];
  agentsApi: DaemonApis['agents'] | null;
  configDirAvailable: boolean;
  approval: AgentApprovalCapability | undefined;
  nodeApproval: WorkflowApproval;
  recentConfigDirs: string[];
  configProfiles: readonly ConfigProfile[];
  canMoveUp: boolean;
  canMoveDown: boolean;
  onChange: (member: WorkflowAgentPoolMember) => void;
  onBrowse: () => Promise<void>;
  onMove: (by: -1 | 1) => void;
  onRemove: () => void;
  mcpSignIn?: PoolMcpSignIn;
}): React.JSX.Element {
  const configDir = member.configDir ?? null;
  const { models, loading } = useAgentModels(
    agentsApi,
    member.agent,
    configDir,
  );
  const { efforts } = useAgentEfforts(
    agentsApi,
    member.agent,
    member.model ?? null,
    configDir,
  );
  const { windows } = useAgentContextWindows(
    agentsApi,
    member.agent,
    member.model ?? null,
    configDir,
  );
  const { parameters } = useAgentModelParameters(
    agentsApi,
    member.agent,
    member.model ?? null,
    configDir,
  );
  // Read on mount like the card above's, not on the press: the daemon's
  // refusal is the only thing that says this member's profile path is wrong.
  const mcp = useNodeMcp(agentsApi, member.agent, configDir);
  const [mcpOpen, setMcpOpen] = useState(false);
  // Whether the sign-in in flight is THIS member's: the panel and the busy row
  // belong to the dialog it was pressed in, and two members on one CLI share
  // server names.
  const ownsSignIn =
    mcpSignIn?.scope !== null &&
    mcpSignIn?.scope !== undefined &&
    mcpSignIn.scope.agent === member.agent &&
    mcpSignIn.scope.configDir === configDir;
  // Only the LISTING can say whether a sign-in landed, so a settled one makes
  // the member that started it read its servers again.
  const refreshMcp = mcp.refresh;
  const settledToken = mcpSignIn?.settledToken ?? 0;
  const seenToken = useRef(settledToken);
  useEffect(() => {
    if (settledToken !== seenToken.current) {
      seenToken.current = settledToken;
      if (ownsSignIn) {
        refreshMcp();
      }
    }
  }, [settledToken, ownsSignIn, refreshMcp]);
  const effectiveApproval = member.approval ?? nodeApproval;
  // A mode this CLI does not offer runs as whatever the CLI falls back to,
  // which can stop an unattended call to ask.
  const unofferedApproval =
    approval?.modes.includes(effectiveApproval) === false
      ? effectiveApproval
      : null;

  return (
    <div
      data-slot="agent-pool-member"
      className="@container flex flex-col divide-y divide-border rounded-md border border-border bg-card">
      <div className="flex items-center gap-1 px-3 py-1.5">
        <span className="flex-1 text-xs font-medium text-foreground">
          Member {number}
        </span>
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className="size-7"
          aria-label={`Move member ${number} up`}
          disabled={!canMoveUp}
          onClick={() => onMove(-1)}>
          <ArrowUp aria-hidden />
        </Button>
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className="size-7"
          aria-label={`Move member ${number} down`}
          disabled={!canMoveDown}
          onClick={() => onMove(1)}>
          <ArrowDown aria-hidden />
        </Button>
        <Button
          type="button"
          variant="ghost"
          size="icon"
          className="size-7"
          aria-label={`Remove member ${number}`}
          onClick={onRemove}>
          <Trash2 aria-hidden />
        </Button>
      </div>
      <SettingRow width="compact" label="Agent">
        <Select
          variant="ghost"
          aria-label={`CLI for member ${number}`}
          value={member.agent}
          groups={[
            {
              items: agents.map((agent) => ({
                value: agent.agent,
                label: agent.displayName,
              })),
            },
          ]}
          // Every CLI setting belongs to the CLI that offered it, so another
          // CLI starts the member from that CLI's defaults — the approval
          // included, whose modes differ per CLI, and the switched-off MCP
          // servers, which name that CLI's own servers. The threshold is a share of
          // the window, which means the same on any CLI, so it stays.
          onValueChange={(agent) => {
            if (agent !== member.agent) {
              onChange({
                agent: agent as AgentKind,
                ...(member.autoCompactPercent !== undefined
                  ? { autoCompactPercent: member.autoCompactPercent }
                  : {}),
              });
            }
          }}
        />
      </SettingRow>
      {configDirAvailable ? (
        <SettingRow width="compact" label="Profile">
          <ConfigDirSelect
            configDir={configDir}
            recentConfigDirs={recentConfigDirs}
            configProfiles={configProfiles}
            unavailableReason={null}
            ariaLabel={`Agent config directory for member ${number}`}
            onChange={(next) =>
              onChange({ ...member, configDir: next ?? undefined })
            }
            onBrowse={() => void onBrowse()}
          />
        </SettingRow>
      ) : null}
      <SettingRow width="compact" label="Approval">
        <ApprovalModeSelect
          capability={approval}
          withheld={PLAN_WITHHELD}
          value={effectiveApproval}
          ariaLabel={`Tool-approval mode for member ${number}`}
          onChange={(next) =>
            onChange({ ...member, approval: next as WorkflowApproval })
          }
        />
      </SettingRow>
      <SettingRow width="compact" label="Model">
        <ModelSelect
          key={member.agent}
          agentKind={member.agent}
          models={models}
          loading={loading}
          allowCustom
          value={member.model ?? null}
          // A window or a parameter belongs to the model that offered it.
          onChange={(model) =>
            onChange({ ...member, ...modelChangePatch(model) })
          }
        />
      </SettingRow>
      {unofferedApproval === null ? null : (
        <p
          data-slot="agent-pool-approval-note"
          className="px-3 py-1.5 text-xs text-warning">
          This CLI does not offer the “
          {MODE_LABELS.find((mode) => mode.value === unofferedApproval)
            ?.label ?? unofferedApproval}
          ” approval this member uses — calls on it may stop to ask.
        </p>
      )}
      <ModelSettingsRows
        efforts={efforts}
        windows={windows}
        parameters={parameters}
        value={member}
        onPatch={(patch) => onChange({ ...member, ...patch })}
        afterContext={
          <SettingRow width="compact" label="Auto-compact">
            <AutoCompactSelect
              ariaLabel={`Auto-compact for member ${number}`}
              value={member.autoCompactPercent ?? null}
              onChange={(percent) =>
                onChange({
                  ...member,
                  autoCompactPercent: percent ?? undefined,
                })
              }
            />
          </SettingRow>
        }
      />
      {mcp.invalidConfigDir === null ? (
        <SettingRow width="compact" label="MCP">
          <McpDialogButton
            variant="chip"
            chipNamesItself={false}
            title={`MCP servers — member ${number}`}
            open={mcpOpen}
            onOpenChange={setMcpOpen}
            // This member's OWN switches over its own profile's servers —
            // never member 1's, which name another profile's servers.
            listing={withNodeSwitches(mcp.listing, member.mcpDisabled)}
            loading={mcp.loading}
            hint={nodeMcpHint('member', configDir !== null)}
            onSetEnabled={(server, enabled) =>
              onChange({
                ...member,
                mcpDisabled: nextMcpDisabled(
                  member.mcpDisabled,
                  server,
                  enabled,
                ),
              })
            }
            onRefresh={mcp.refresh}
            onSignIn={
              mcpSignIn
                ? (server) => mcpSignIn.start(member.agent, server, configDir)
                : undefined
            }
            signingIn={ownsSignIn ? mcpSignIn!.signingIn : null}
            loginServer={ownsSignIn ? mcpSignIn!.loginServer : null}
            loginPanel={ownsSignIn ? mcpSignIn!.loginPanel : null}
            // This member's PROFILE, the file its own rows came from.
            configActions={
              agentsApi
                ? mcpConfigActions(agentsApi, {
                    agent: member.agent,
                    configDir,
                  })
                : undefined
            }
          />
        </SettingRow>
      ) : (
        <ErrorText className="px-3 py-1.5 text-xs break-words">
          {mcp.invalidConfigDir}
        </ErrorText>
      )}
    </div>
  );
}
