import { Panel } from '@xyflow/react';
import { ChevronDown, ChevronUp, MessagesSquare, Pencil } from 'lucide-react';

import type { WorkflowStage } from '../autogenerated';
import { StageGraph } from '../components/stage-graph';
import { Button } from '../components/ui/button';
import { popoverSurface } from '../components/ui/popover';
import { cn } from '../components/ui/utils';
import { usePersistedFlag } from '../components/use-persisted-flag';
import { stageCount } from './workflow-meta-dialog';

const LS_OPEN = 'geniro.builder.stagesOpen';

/** The workflow's stage graph over the canvas — a panel, never nodes: a stage names no node or wire. */
export function CanvasStages({
  stages,
  onEdit,
  onAskChat,
}: {
  stages: readonly WorkflowStage[];
  onEdit: () => void;
  /** Absent while there is no chat to ask (no saved workflow). */
  onAskChat?: () => void;
}): React.JSX.Element | null {
  const [open, setOpen] = usePersistedFlag(LS_OPEN, true);
  if (stages.length === 0) {
    return null;
  }
  return (
    <Panel
      position="top-center"
      data-slot="canvas-stages"
      className={cn(
        popoverSurface,
        'flex w-[min(720px,calc(100%-2rem))] flex-col gap-1.5 rounded-xl px-2.5 py-2',
      )}>
      <div className="flex items-center gap-2">
        <Button
          type="button"
          variant="ghost"
          size="sm"
          className="h-7 gap-1 px-1.5 text-xs font-medium has-[>svg]:px-1.5"
          aria-expanded={open}
          onClick={() => setOpen((current) => !current)}>
          Stages
          <span className="font-normal text-muted-foreground tabular-nums">
            {stageCount(stages)}
          </span>
          {open ? (
            <ChevronUp aria-hidden="true" className="size-3.5" />
          ) : (
            <ChevronDown aria-hidden="true" className="size-3.5" />
          )}
        </Button>
        <div className="ml-auto flex items-center gap-1">
          {onAskChat === undefined ? null : (
            <Button
              type="button"
              variant="ghost"
              size="sm"
              className="h-7 gap-1 px-2 text-xs has-[>svg]:px-2"
              title="Describe how the stages should change and let an agent make it"
              onClick={onAskChat}>
              <MessagesSquare aria-hidden="true" className="size-3.5" />
              Change with chat
            </Button>
          )}
          <Button
            type="button"
            variant="ghost"
            size="sm"
            className="h-7 gap-1 px-2 text-xs has-[>svg]:px-2"
            onClick={onEdit}>
            <Pencil aria-hidden="true" className="size-3.5" />
            Edit
          </Button>
        </div>
      </div>
      {open ? <StageGraph stages={stages} /> : null}
    </Panel>
  );
}
