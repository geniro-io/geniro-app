import { Panel } from '@xyflow/react';
import { ChevronDown, ChevronUp, Pencil, Route } from 'lucide-react';

import type { WorkflowStage } from '../autogenerated';
import { StageGraph, useElementWidth } from '../components/stage-graph';
import { Button } from '../components/ui/button';
import { popoverSurface } from '../components/ui/popover';
import { cn } from '../components/ui/utils';
import { usePersistedFlag } from '../components/use-persisted-flag';
import { stageCount } from './workflow-meta-dialog';

const LS_OPEN = 'geniro.builder.stagesOpen';
/** The graph section's padding and the card's border, left and right. */
const CARD_INSET_PX = 26;

/** The workflow's stage graph over the canvas — a panel, never nodes: a stage names no node or wire. */
export function CanvasStages({
  stages,
  onEdit,
}: {
  stages: readonly WorkflowStage[];
  /** Open the stage editor, on the pressed stage when one was. */
  onEdit: (stageId: string | null) => void;
}): React.JSX.Element | null {
  const [open, setOpen] = usePersistedFlag(LS_OPEN, true);
  // The card is as wide as its graph, so the graph is fitted to the canvas row
  // instead: measuring the card would read back the graph's own width.
  const [measureRow, room] = useElementWidth();
  if (stages.length === 0) {
    return null;
  }
  const foldLabel = open ? 'Hide the stage graph' : 'Show the stage graph';
  return (
    <Panel
      position="top-center"
      className="pointer-events-none w-[calc(100%-2rem)]">
      <div ref={measureRow} className="flex w-full justify-center">
        <div
          role="group"
          aria-label="Stages"
          data-slot="canvas-stages"
          className={cn(
            popoverSurface,
            'pointer-events-auto relative w-max max-w-full overflow-hidden bg-card',
          )}>
          <div className="flex items-center gap-2 py-1 pr-1 pl-3">
            <Route
              aria-hidden="true"
              className="size-3.5 shrink-0 text-primary"
            />
            <span className="text-xs font-medium">Stages</span>
            <span className="text-xs text-muted-foreground tabular-nums">
              {stageCount(stages)}
            </span>
            <div className="ml-auto flex items-center pl-4">
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-7 text-muted-foreground hover:text-foreground"
                aria-label="Edit stages"
                title="Edit stages"
                onClick={() => onEdit(null)}>
                <Pencil aria-hidden="true" className="size-3.5" />
              </Button>
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-7 text-muted-foreground hover:text-foreground"
                aria-expanded={open}
                aria-label={foldLabel}
                title={foldLabel}
                onClick={() => setOpen((current) => !current)}>
                {open ? (
                  <ChevronUp aria-hidden="true" className="size-3.5" />
                ) : (
                  <ChevronDown aria-hidden="true" className="size-3.5" />
                )}
              </Button>
            </div>
          </div>
          {open ? (
            <div className="border-t border-border/60 bg-muted/30 px-3 py-2">
              <StageGraph
                stages={stages}
                onSelect={onEdit}
                {...(room > 0 ? { fitWidth: room - CARD_INSET_PX } : {})}
              />
            </div>
          ) : null}
        </div>
      </div>
    </Panel>
  );
}
