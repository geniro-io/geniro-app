import { describe, expect, it } from 'vitest';

import type { Workflow } from '../autogenerated';
import {
  autoLayout,
  canvasSnapshot,
  edgeId,
  flowNodeFor,
  fromFlow,
  nextNodeId,
  toFlow,
} from './graph-doc';

const WF: Workflow = {
  name: 'team',
  nodes: [
    {
      id: 'coder',
      kind: 'agent',
      agent: 'claude',
      approval: 'auto',
      role: 'You code.',
    },
    { id: 'reviewer', kind: 'agent', agent: 'cursor-agent', approval: 'ask' },
  ],
  edges: [{ from: 'coder', to: 'reviewer', kind: 'data' }],
  layout: { coder: { x: 10, y: 20 } },
};

describe('toFlow / fromFlow', () => {
  it('round-trips a workflow through the canvas document', () => {
    const flow = toFlow(WF);
    expect(flow.nodes.map((n) => n.id)).toEqual(['coder', 'reviewer']);
    // Stored position wins; missing position falls back to the grid.
    expect(flow.nodes[0]!.position).toEqual({ x: 10, y: 20 });
    expect(flow.nodes[1]!.position).toEqual({ x: 260, y: 0 });
    expect(flow.edges).toEqual([
      {
        id: '["coder","reviewer","data"]',
        source: 'coder',
        target: 'reviewer',
        label: undefined,
        // A data edge NAMES its type like the annotation kinds, so it is drawn
        // by `graph-edge.tsx` rather than by React Flow's own default — which
        // is what left the graph's ordering wire the one thing on the canvas
        // nobody had designed. Not persisted: `fromFlow` reads it back to a
        // kind and drops it, along with the handles below.
        type: 'data',
        // Handles derive from the edge kind + endpoint kinds (both agents
        // here) and are never persisted — fromFlow drops them below.
        sourceHandle: 'source-data-agent',
        targetHandle: 'target-data-agent',
      },
    ]);

    const back = fromFlow({ name: WF.name }, flow.nodes, flow.edges);
    expect(back.nodes).toEqual(WF.nodes);
    expect(back.edges).toEqual([
      { from: 'coder', to: 'reviewer', kind: 'data' },
    ]);
    // Every node position (including the fallback) persists into the layout.
    expect(back.layout).toEqual({
      coder: { x: 10, y: 20 },
      reviewer: { x: 260, y: 0 },
    });
  });

  it('maps node kinds to their RF component types and round-trips a trigger', () => {
    const flow = toFlow({
      name: 'triggered',
      nodes: [{ id: 'start', kind: 'trigger', trigger: 'manual' }, ...WF.nodes],
      edges: [{ from: 'start', to: 'coder', kind: 'data' }, ...WF.edges],
    });
    expect(flow.nodes.map((n) => n.type)).toEqual([
      'trigger',
      'agent',
      'agent',
    ]);
    // A trigger→agent edge lands on the agent's trigger-typed input handle.
    expect(flow.edges[0]).toMatchObject({
      source: 'start',
      target: 'coder',
      sourceHandle: 'source-data-agent',
      targetHandle: 'target-data-trigger',
    });
    const back = fromFlow({ name: 'triggered' }, flow.nodes, flow.edges);
    expect(back.nodes[0]).toEqual({
      id: 'start',
      kind: 'trigger',
      trigger: 'manual',
    });
  });

  it('round-trips a call edge, coexisting with a data edge on the same pair', () => {
    const flow = toFlow({
      ...WF,
      edges: [
        { from: 'coder', to: 'reviewer', kind: 'data' },
        { from: 'coder', to: 'reviewer', kind: 'call' },
      ],
    });
    // Per-kind ids keep both edges alive on the canvas; each renders through
    // its OWN component in `graph-edge.tsx` and lands on its own handles. The
    // data edge names its type too — it used to be left blank for React Flow to
    // fill with the library default, which is the state that change ended.
    expect(flow.edges.map((e) => e.id)).toEqual([
      '["coder","reviewer","data"]',
      '["coder","reviewer","call"]',
    ]);
    expect(flow.edges[0]!.type).toBe('data');
    expect(flow.edges[1]).toMatchObject({
      type: 'call',
      sourceHandle: 'source-call-agent',
      targetHandle: 'target-call-agent',
    });
    const back = fromFlow({ name: WF.name }, flow.nodes, flow.edges);
    expect(back.edges).toEqual([
      { from: 'coder', to: 'reviewer', kind: 'data' },
      { from: 'coder', to: 'reviewer', kind: 'call' },
    ]);
  });

  it('gives distinct canvas ids to distinct edges even when node ids contain "->"', () => {
    // Node ids from a hand-written YAML file are free-form and may contain
    // '->' themselves; 'a' → 'b->c' and 'a->b' → 'c' are two different wires.
    // React Flow requires unique edge ids — sharing one id breaks rendering
    // and selection of one of the two edges.
    const agent = (id: string) =>
      ({ id, kind: 'agent', agent: 'claude', approval: 'auto' }) as const;
    const flow = toFlow({
      name: 'arrow ids',
      nodes: [agent('a'), agent('b->c'), agent('a->b'), agent('c')],
      edges: [
        { from: 'a', to: 'b->c', kind: 'data' },
        { from: 'a->b', to: 'c', kind: 'data' },
      ],
    });
    expect(new Set(flow.edges.map((e) => e.id)).size).toBe(2);
  });

  it('keeps edge labels when present', () => {
    const flow = toFlow({
      ...WF,
      edges: [{ from: 'coder', to: 'reviewer', kind: 'data', label: 'diff' }],
    });
    const back = fromFlow({ name: 'x' }, flow.nodes, flow.edges);
    expect(back.edges[0]).toEqual({
      from: 'coder',
      to: 'reviewer',
      kind: 'data',
      label: 'diff',
    });
  });
});

describe('canvasSnapshot (the builder dirty-check baseline)', () => {
  it('is stable across a load round-trip and selection, and flips on a real edit', () => {
    const flow = toFlow(WF);
    const baseline = canvasSnapshot('team', '', flow.nodes, flow.edges);

    // Re-serializing the untouched canvas reads clean.
    expect(canvasSnapshot('team', '', flow.nodes, flow.edges)).toBe(baseline);

    // Selecting a node is not an edit — it must never arm the discard guard.
    const selected = flow.nodes.map((n) =>
      n.id === 'coder' ? { ...n, selected: true } : n,
    );
    expect(canvasSnapshot('team', '', selected, flow.edges)).toBe(baseline);

    // Moving a node IS an edit (layout persists to the YAML).
    const moved = flow.nodes.map((n) =>
      n.id === 'coder' ? { ...n, position: { x: 99, y: 20 } } : n,
    );
    expect(canvasSnapshot('team', '', moved, flow.edges)).not.toBe(baseline);

    // Removing an edge IS an edit.
    expect(canvasSnapshot('team', '', flow.nodes, [])).not.toBe(baseline);
  });

  it('normalizes meta like Save does — whitespace and the empty-name fallback', () => {
    const flow = toFlow(WF);
    expect(canvasSnapshot(' team ', '  ', flow.nodes, flow.edges)).toBe(
      canvasSnapshot('team', '', flow.nodes, flow.edges),
    );
    expect(canvasSnapshot('', '', flow.nodes, flow.edges)).toBe(
      canvasSnapshot('workflow', '', flow.nodes, flow.edges),
    );
  });
});

describe('nextNodeId', () => {
  it('skips taken ids', () => {
    expect(nextNodeId(new Set(['agent-1', 'agent-2']))).toBe('agent-3');
    expect(nextNodeId(new Set())).toBe('agent-1');
  });

  it('prefixes by node kind', () => {
    expect(nextNodeId(new Set(['agent-1']), 'trigger')).toBe('trigger-1');
    expect(nextNodeId(new Set(['trigger-1']), 'trigger')).toBe('trigger-2');
  });
});

describe('edgeId', () => {
  it('is stable per (endpoint pair, edge kind) — kinds never collide', () => {
    expect(edgeId('a', 'b', 'data')).toBe('["a","b","data"]');
    expect(edgeId('a', 'b', 'call')).toBe('["a","b","call"]');
    expect(edgeId('a', 'b', 'data')).not.toBe(edgeId('a', 'b', 'call'));
  });
});

describe('autoLayout', () => {
  it('positions every node with producers left of consumers', async () => {
    const layout = await autoLayout(WF);
    expect(Object.keys(layout).sort()).toEqual(['coder', 'reviewer']);
    expect(layout.coder!.x).toBeLessThan(layout.reviewer!.x);
  });

  it('leaves a real gap between siblings as tall as they measure', async () => {
    // THE REPORTED DEFECT: ELK places boxes of the size it is TOLD, and every
    // node used to be declared NODE_HEIGHT (128) while a real agent card is
    // 173px — so the 48px gap between siblings came out as 3px on the canvas,
    // and a card past 176px overlapped the one below outright.
    //
    // Two siblings fanning out of one producer, so the layout stacks them.
    const FAN: Workflow = {
      name: 'fan',
      nodes: [
        { id: 'lead', kind: 'agent', agent: 'claude', approval: 'auto' },
        { id: 'a', kind: 'agent', agent: 'claude', approval: 'auto' },
        { id: 'b', kind: 'agent', agent: 'claude', approval: 'auto' },
      ],
      edges: [
        { from: 'lead', to: 'a', kind: 'data' },
        { from: 'lead', to: 'b', kind: 'data' },
      ],
    };
    const TALL = 231; // an agent card carrying a wiring warning, measured
    const sizes = new Map(
      ['lead', 'a', 'b'].map((id) => [id, { width: 240, height: TALL }]),
    );

    const layout = await autoLayout(FAN, sizes);
    const [upper, lower] = [layout.a!, layout.b!].sort((p, q) => p.y - q.y);

    // The gap is measured against what the cards ACTUALLY are, which is the
    // whole point: told 128, ELK would leave 176 between origins and the 231px
    // cards would overlap by 55.
    expect(lower!.y - upper!.y).toBeGreaterThanOrEqual(TALL);
  });
});

describe('instruction blocks on the canvas', () => {
  const NOTED: Workflow = {
    name: 'noted',
    nodes: [
      { id: 'writer', kind: 'agent', agent: 'claude', approval: 'auto' },
      { id: 'style', kind: 'instruction', instructions: 'Be terse.' },
    ],
    edges: [{ from: 'style', to: 'writer', kind: 'instruction' }],
  };

  it('maps a block to its own canvas type and back', () => {
    const flow = toFlow(NOTED);
    expect(flow.nodes.find((n) => n.id === 'style')?.type).toBe('instruction');
    // The React Flow `type` is what selects the instruction edge component AND
    // what `fromFlow` reads the kind back off. Left untyped it would be a DATA
    // edge — the one kind that orders the run — so the block would become a
    // producer of the agent it is only meant to instruct.
    expect(flow.edges[0]?.type).toBe('instruction');

    const back = fromFlow({ name: 'noted' }, flow.nodes, flow.edges);
    expect(back.nodes).toEqual(NOTED.nodes);
    expect(back.edges).toEqual(NOTED.edges);
  });

  it('mints block ids under their own prefix', () => {
    expect(nextNodeId(new Set(['instruction-1']), 'instruction')).toBe(
      'instruction-2',
    );
  });
});

describe('flowNodeFor', () => {
  // ONE kind -> React Flow `type` mapping, shared by `toFlow` and the builder's
  // add path. They used to carry a branch each, and the add path's copy is the
  // one a new kind is easiest to forget — a node typed `agent` by mistake
  // renders as an agent card over instruction data.
  it('maps every kind to its own canvas type', () => {
    const at = { x: 0, y: 0 };
    expect(
      flowNodeFor({ id: 't', kind: 'trigger', trigger: 'manual' }, at).type,
    ).toBe('trigger');
    expect(
      flowNodeFor({ id: 'i', kind: 'instruction', instructions: '' }, at).type,
    ).toBe('instruction');
    expect(
      flowNodeFor(
        { id: 'a', kind: 'agent', agent: 'claude', approval: 'auto' },
        at,
      ).type,
    ).toBe('agent');
  });

  it('carries the node through as its own data', () => {
    const node = {
      id: 'i',
      kind: 'instruction' as const,
      instructions: 'Be terse.',
    };
    expect(flowNodeFor(node, { x: 4, y: 5 })).toEqual({
      id: 'i',
      type: 'instruction',
      position: { x: 4, y: 5 },
      data: { node },
    });
  });
});
