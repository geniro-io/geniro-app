import type { Edge, Node } from '@xyflow/react';
import ELK from 'elkjs/lib/elk.bundled.js';

import type {
  EdgeKind,
  Workflow,
  WorkflowAgentNode,
  WorkflowEdge,
  WorkflowInstructionNode,
  WorkflowNode,
  WorkflowTriggerNode,
} from '../autogenerated';
import type { NodeKind } from './node-schema';
import { flowEdgeKind, flowEdgeType, makeHandleId } from './node-schema';

/**
 * Canvas position per node id. The generated client leaves this inline on
 * `Workflow` (an OpenAPI record has no name of its own), so the alias is read
 * back off the generated type rather than restated.
 */
export type WorkflowLayout = NonNullable<Workflow['layout']>;

/**
 * Pure Workflow ⇄ React Flow document conversion (no React, unit-testable).
 * The YAML `layout` block is the persisted source of canvas positions; nodes
 * without a stored position get a deterministic staggered-grid fallback so a
 * hand-written file still opens readably.
 */

/** React Flow nodes carrying their workflow node as data, typed per kind —
 *  the RF `type` string doubles as the node kind and selects the component. */
export type AgentFlowNode = Node<{ node: WorkflowAgentNode }, 'agent'>;
export type TriggerFlowNode = Node<{ node: WorkflowTriggerNode }, 'trigger'>;
export type InstructionFlowNode = Node<
  { node: WorkflowInstructionNode },
  'instruction'
>;
export type GraphFlowNode =
  AgentFlowNode | TriggerFlowNode | InstructionFlowNode;

const GRID_X = 260;
const GRID_Y = 120;

function fallbackPosition(index: number): { x: number; y: number } {
  return { x: (index % 3) * GRID_X, y: Math.floor(index / 3) * GRID_Y };
}

/**
 * Stable edge id per (from, to, edge kind) — the kind is part of the identity
 * because wires of different kinds may legally share the same endpoints.
 * JSON keeps the components unambiguous: node ids are free-form (hand-written
 * YAML may contain '->' or '#'), and React Flow needs distinct edges to never
 * share an id.
 */
export function edgeId(from: string, to: string, kind: EdgeKind): string {
  return JSON.stringify([from, to, kind]);
}

/**
 * One workflow node as a canvas node. Shared by {@link toFlow} and by the
 * builder's own add path, which used to carry its own copy of the kind → RF
 * `type` branch — two mappings for one fact, and the add path's copy is the
 * one a new kind is easiest to forget.
 */
export function flowNodeFor(
  node: WorkflowNode,
  position: { x: number; y: number },
): GraphFlowNode {
  if (node.kind === 'trigger') {
    return { id: node.id, type: 'trigger', position, data: { node } };
  }
  if (node.kind === 'instruction') {
    return { id: node.id, type: 'instruction', position, data: { node } };
  }
  return { id: node.id, type: 'agent', position, data: { node } };
}

/**
 * A workflow as a canvas document.
 *
 * `dropped` is every edge naming a node the workflow does not have, and those
 * are LEFT OUT of `edges` rather than carried along. The library's read checks
 * a file's shape and nothing about its graph, so a hand-written file — or one
 * the builder chat's agent wrote — can hold such a wire; React Flow draws
 * nothing for it, so it was invisible and undeletable, while the status bar
 * counted it and every save was refused (`GRAPH_EDGE_NOT_FOUND`) for a wire
 * the user could not see. Dropped here, the next save writes the file without
 * it; the caller says so, which is the only trace the wire leaves.
 */
export function toFlow(workflow: Workflow): {
  nodes: GraphFlowNode[];
  edges: Edge[];
  dropped: WorkflowEdge[];
} {
  const nodes = workflow.nodes.map((node, index): GraphFlowNode =>
    flowNodeFor(node, workflow.layout?.[node.id] ?? fallbackPosition(index)),
  );
  // Edges attach to the per-rule handles. The YAML never stores ports: with
  // at most one rule per (side, edge kind, peer kind) the canonical handle
  // pair is fully derived from the edge kind + endpoint kinds (makeHandleId).
  const kindOf = new Map(workflow.nodes.map((node) => [node.id, node.kind]));
  const dropped: WorkflowEdge[] = [];
  const edges: Edge[] = [];
  for (const edge of workflow.edges) {
    const sourceKind = kindOf.get(edge.from);
    const targetKind = kindOf.get(edge.to);
    if (sourceKind === undefined || targetKind === undefined) {
      dropped.push(edge);
      continue;
    }
    edges.push({
      id: edgeId(edge.from, edge.to, edge.kind),
      source: edge.from,
      target: edge.to,
      label: edge.label,
      ...flowEdgeType(edge.kind),
      sourceHandle: makeHandleId('source', edge.kind, targetKind),
      targetHandle: makeHandleId('target', edge.kind, sourceKind),
    });
  }
  return { nodes, edges, dropped };
}

/**
 * The sentence a load says about the wires {@link toFlow} left out, or null
 * when it left none. Names each one, since a count alone tells the reader a
 * file was changed and nothing about what to look for.
 */
export function droppedEdgesNotice(
  dropped: readonly WorkflowEdge[],
): string | null {
  if (dropped.length === 0) {
    return null;
  }
  const wires = dropped.map((edge) => `${edge.from} → ${edge.to}`).join(', ');
  return dropped.length === 1
    ? `Removed a wire to a node this workflow does not have (${wires}) — the next save writes the file without it.`
    : `Removed ${dropped.length} wires to nodes this workflow does not have (${wires}) — the next save writes the file without them.`;
}

export function fromFlow(
  meta: { name: string; description?: string },
  nodes: readonly GraphFlowNode[],
  edges: readonly Edge[],
): Workflow {
  const layout: WorkflowLayout = {};
  for (const node of nodes) {
    layout[node.id] = {
      x: Math.round(node.position.x),
      y: Math.round(node.position.y),
    };
  }
  return {
    name: meta.name,
    ...(meta.description ? { description: meta.description } : {}),
    nodes: nodes.map((n): WorkflowNode => n.data.node),
    edges: edges.map((e) => ({
      from: e.source,
      to: e.target,
      kind: flowEdgeKind(e),
      ...(typeof e.label === 'string' && e.label ? { label: e.label } : {}),
    })),
    layout,
  };
}

/**
 * The canvas serialized exactly as Save would write it — the builder's
 * dirty-check baseline (compare the snapshot taken at load/save against the
 * live canvas). Serialize-and-compare beats per-change tracking: selection
 * and other no-op canvas events cannot false-flag, and an edit undone by
 * hand reads clean again.
 */
export function canvasSnapshot(
  name: string,
  description: string,
  nodes: readonly GraphFlowNode[],
  edges: readonly Edge[],
): string {
  const trimmed = description.trim();
  return JSON.stringify(
    fromFlow(
      {
        name: name.trim() || 'workflow',
        ...(trimmed ? { description: trimmed } : {}),
      },
      nodes,
      edges,
    ),
  );
}

/** A fresh node id not colliding with the existing set — prefixed by kind
 *  (`agent-1`, `trigger-1`, …). */
export function nextNodeId(
  existing: ReadonlySet<string>,
  prefix: NodeKind = 'agent',
): string {
  let n = 1;
  while (existing.has(`${prefix}-${n}`)) {
    n += 1;
  }
  return `${prefix}-${n}`;
}

/**
 * What a node card measures, for the two callers that must place one before
 * React Flow has measured it: the auto-layout below, and the canvas centring on
 * a freshly added node.
 */
export const NODE_WIDTH = 240;
export const NODE_HEIGHT = 128;

/**
 * What one node card measures on the canvas right now, when React Flow has
 * measured it. Keyed by node id; a missing entry falls back to the constants
 * above.
 */
export type NodeSizes = ReadonlyMap<
  string,
  { width: number; height: number } | undefined
>;

/**
 * Auto-layout via ELK (layered, left→right — matches the producer→consumer
 * edge direction). Returns a fresh layout block; the caller applies it to the
 * canvas and it persists into the YAML on save.
 *
 * `sizes` is what each card ACTUALLY measures, and passing it is not an
 * optimisation — it is the difference between the spacing below meaning
 * anything and meaning nothing. ELK places boxes of the size it is told, so a
 * card taller than its declared box overruns the gap left after it. Every node
 * used to be declared {@link NODE_HEIGHT} (128) while a real agent card is
 * 173px with a description and 231px carrying a wiring warning — measured in
 * the running builder — so the 48px gap between siblings came out as **3px**,
 * and any card past 176px overlapped the one below outright. REPORTED as
 * "автолейаут работает некрасиво, то есть ноды вообще слишком близко находятся
 * друг к другу и перекрывают все!".
 *
 * The constants stay as the FALLBACK rather than being raised to fit the
 * tallest card: a node this canvas has not measured yet has no honest size,
 * and padding every layout for the worst case would leave a graph of short
 * nodes strewn across the screen. What a card measures is a fact only the
 * canvas holds, which is why it is an argument rather than a bigger guess here.
 */
export async function autoLayout(
  workflow: Workflow,
  sizes: NodeSizes = new Map(),
): Promise<WorkflowLayout> {
  const elk = new ELK();
  const graph = await elk.layout({
    id: 'root',
    layoutOptions: {
      'elk.algorithm': 'layered',
      'elk.direction': 'RIGHT',
      'elk.spacing.nodeNode': '48',
      'elk.layered.spacing.nodeNodeBetweenLayers': '96',
    },
    children: workflow.nodes.map((node) => ({
      id: node.id,
      width: sizes.get(node.id)?.width ?? NODE_WIDTH,
      height: sizes.get(node.id)?.height ?? NODE_HEIGHT,
    })),
    edges: workflow.edges.map((edge) => ({
      id: edgeId(edge.from, edge.to, edge.kind),
      sources: [edge.from],
      targets: [edge.to],
    })),
  });
  const layout: WorkflowLayout = {};
  for (const child of graph.children ?? []) {
    layout[child.id] = {
      x: Math.round(child.x ?? 0),
      y: Math.round(child.y ?? 0),
    };
  }
  return layout;
}
