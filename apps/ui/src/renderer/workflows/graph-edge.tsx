import {
  BaseEdge,
  EdgeLabelRenderer,
  type EdgeProps,
  getBezierPath,
} from '@xyflow/react';
import { useState } from 'react';

import type { EdgeKind } from '../autogenerated';
import { cn } from '../components/ui/utils';

/**
 * EVERY wire on the canvas — one component, one variant per edge kind.
 *
 * A data edge means "this runs after that": it orders the DAG. `call` and
 * `instruction` edges order nothing. So the drawing has to rank them, and it
 * used to rank them BACKWARDS: data edges kept React Flow's own default, an
 * unstyled hairline with no arrowhead, while the two kinds that order nothing
 * had custom tones, dashes, arrowheads and hover chips. REPORTED as "why do
 * arrows have different design? I see one gray arrow" — the grey one was the
 * spine of the graph, drawn by the library because nobody had drawn it.
 *
 * The ranking now matches what the wires mean. Data is SOLID, the heaviest
 * stroke, and neutral — structure rather than accent, so a graph reads as a
 * skeleton with commentary on it rather than as a bundle of amber dashes.
 * The annotations stay dashed, thinner and coloured, which is what makes them
 * legible AS annotations.
 *
 * ONE component with a variant rather than three files: the back-edge routing
 * below is the fiddly half and a second copy of it is how two kinds come to
 * disagree about where a wire goes.
 */
/** Back-edge loop geometry: horizontal reach past the handles, drop below
 *  the lower endpoint (clears the card bottom — handles sit near it), and
 *  the rounded-corner radius. */
const LOOP_EXT = 24;
const LOOP_DIP = 64;
const LOOP_RADIUS = 12;

/** What one edge kind looks like and calls itself. */
interface EdgeVariant {
  /** The midpoint chip's text — the wire's own name. */
  label: string;
  /** Stroke + arrowhead fill, always a token (a literal is an eslint error). */
  stroke: string;
  /**
   * Stroke alpha. The data wire is the only one that needs it: it is painted
   * in `--color-foreground`, which at full strength is the brightest thing on
   * a dark canvas and would out-shout the node cards it connects.
   */
  opacity: number;
  /** `strokeDasharray`, or undefined for a solid wire. */
  dash?: string;
  /** Resting stroke width; selection adds half a pixel. */
  width: number;
  /** Chip surface classes, the token pair matching {@link stroke}. */
  chip: string;
  /** Arrowhead marker id — per variant, since the fill differs. */
  markerId: string;
}

const VARIANTS = {
  // SOLID, heaviest, neutral. This is the wire that orders the run, so it is
  // the one a reader traces to answer "what happens after what" — and it is
  // the one that had no design at all. Neutral rather than the brand accent
  // deliberately: the annotations are already caramel and amber, and a third
  // warm line would leave the canvas a single hue with nothing ranked.
  data: {
    label: 'feeds',
    stroke: 'var(--color-foreground)',
    // Measured against the annotations on a real graph rather than picked: at
    // 0.5 the one solid wire still lost to seven full-chroma amber dashes, so
    // the spine was quieter than the commentary even after it had been drawn.
    // Not 1 either — `--color-foreground` is the page's text colour, and a
    // wire at full text weight out-shouts the node cards it connects.
    opacity: 0.7,
    width: 2,
    chip: 'bg-foreground text-background',
    markerId: 'geniro-data-arrow',
  },
  call: {
    label: 'call',
    stroke: 'var(--color-warning)',
    opacity: 1,
    dash: '6 4',
    width: 1.5,
    chip: 'bg-warning text-warning-foreground',
    markerId: 'geniro-call-arrow',
  },
  instruction: {
    label: 'instruction',
    stroke: 'var(--color-primary)',
    opacity: 1,
    dash: '6 4',
    width: 1.5,
    chip: 'bg-primary text-primary-foreground',
    markerId: 'geniro-instruction-arrow',
  },
  // Keyed by the kind union, not by `string`: `flowEdgeType` now emits a React
  // Flow `type` for EVERY kind, so one without a variant here (and a component
  // in `Workflows.tsx`'s EDGE_TYPES) would silently fall back to the library
  // default — which is exactly the state this file was written to end.
} as const satisfies Record<EdgeKind, EdgeVariant>;

/**
 * Path for a BACK edge (target left of the source — every mutual call pair
 * has one): the default bezier between a right-side source and a left-side
 * target at similar heights degenerates to a near-straight line that runs
 * BEHIND both node cards (edges render under nodes), leaving only orphaned
 * stubs visible at the handles. Route it the way node editors draw feedback
 * wires instead: out of the source, down just below the cards, straight
 * across, and up into the target — a tight rounded-orthogonal loop.
 */
function backEdgePath(
  sourceX: number,
  sourceY: number,
  targetX: number,
  targetY: number,
): [string, number, number] {
  const r = LOOP_RADIUS;
  const right = sourceX + LOOP_EXT;
  const left = targetX - LOOP_EXT;
  const dip = Math.max(sourceY, targetY) + LOOP_DIP;
  const path =
    `M ${sourceX},${sourceY} H ${right - r} Q ${right},${sourceY} ${right},${sourceY + r} ` +
    `V ${dip - r} Q ${right},${dip} ${right - r},${dip} ` +
    `H ${left + r} Q ${left},${dip} ${left},${dip - r} ` +
    `V ${targetY + r} Q ${left},${targetY} ${left + r},${targetY} H ${targetX}`;
  // Chip on the middle of the bottom run.
  return [path, (right + left) / 2, dip];
}

function makeGraphEdge(
  variant: EdgeVariant,
  displayName: string,
): (props: EdgeProps) => React.JSX.Element {
  function GraphEdge({
    id,
    sourceX,
    sourceY,
    targetX,
    targetY,
    sourcePosition,
    targetPosition,
    selected,
  }: EdgeProps): React.JSX.Element {
    const [hovered, setHovered] = useState(false);
    const [path, labelX, labelY] =
      targetX < sourceX
        ? backEdgePath(sourceX, sourceY, targetX, targetY)
        : getBezierPath({
            sourceX,
            sourceY,
            sourcePosition,
            targetX,
            targetY,
            targetPosition,
          });
    return (
      // The group wraps BaseEdge's visible path AND its wide invisible
      // interaction path, so the hover chip triggers from the whole hit area.
      <g
        onMouseEnter={() => setHovered(true)}
        onMouseLeave={() => setHovered(false)}>
        {/* Arrowhead pointing INTO the target — EVERY wire here is directional
            (an ordering, a call permission, an instruction handed one way), and
            without a marker they read as symmetric. The data edge had none at
            all, which is half of why it read as the library's line rather than
            as the graph's spine. Every edge of a kind re-declares the same def;
            browsers resolve the shared id to the first one, so the duplication
            is inert. */}
        <defs>
          <marker
            id={variant.markerId}
            viewBox="0 0 10 10"
            refX="9"
            refY="5"
            markerWidth="7"
            markerHeight="7"
            orient="auto-start-reverse">
            <path
              d="M 0 1.5 L 9 5 L 0 8.5 z"
              fill={variant.stroke}
              fillOpacity={variant.opacity}
            />
          </marker>
        </defs>
        <BaseEdge
          id={id}
          path={path}
          markerEnd={`url(#${variant.markerId})`}
          style={{
            stroke: variant.stroke,
            strokeOpacity: variant.opacity,
            strokeWidth: selected ? variant.width + 0.5 : variant.width,
            ...(variant.dash === undefined
              ? {}
              : { strokeDasharray: variant.dash }),
          }}
        />
        {selected || hovered ? (
          <EdgeLabelRenderer>
            <span
              style={{
                transform: `translate(-50%, -50%) translate(${labelX}px, ${labelY}px)`,
              }}
              className={cn(
                'pointer-events-none absolute rounded px-1.5 py-0.5 text-[10px] font-semibold',
                variant.chip,
              )}>
              {variant.label}
            </span>
          </EdgeLabelRenderer>
        ) : null}
      </g>
    );
  }
  GraphEdge.displayName = displayName;
  return GraphEdge;
}

/**
 * Registered as React Flow edge type `data` — "this runs after that, and its
 * final text feeds it". The graph's spine, and the only one of the three that
 * orders the run.
 */
export const DataEdge = makeGraphEdge(VARIANTS.data, 'DataEdge');

/** Registered as React Flow edge type `call` — "may invoke at runtime". */
export const CallEdge = makeGraphEdge(VARIANTS.call, 'CallEdge');

/**
 * Registered as React Flow edge type `instruction` — "this block's text is
 * appended to that agent's turn".
 */
export const InstructionEdge = makeGraphEdge(
  VARIANTS.instruction,
  'InstructionEdge',
);
