// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it, vi } from 'vitest';

import type { WorkflowInstructionNode } from '../autogenerated';

// The canvas card renders inside the shared NodeCard shell (React Flow store
// hooks); stub it to a plain wrapper so this spec exercises only the block's
// own header and preview.
vi.mock('./node-card', () => ({
  NodeCard: ({ children }: { children: React.ReactNode }) => (
    <div data-testid="node-card">{children}</div>
  ),
}));

import { InstructionNode } from './instruction-node';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

function renderNode(patch: Partial<WorkflowInstructionNode> = {}): HTMLElement {
  const node: WorkflowInstructionNode = {
    id: 'instruction-1',
    kind: 'instruction',
    instructions: 'Prefer short sentences.',
    ...patch,
  };
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  // Only `data.node` and `selected` are read; the rest of NodeProps is cast.
  const props = {
    id: node.id,
    data: { node },
    selected: false,
  } as unknown as React.ComponentProps<typeof InstructionNode>;
  act(() => {
    root!.render(<InstructionNode {...props} />);
  });
  return container;
}

afterEach(() => {
  act(() => {
    root?.unmount();
  });
  container?.remove();
  root = null;
  container = null;
});

describe('InstructionNode', () => {
  // The text IS the block, so the card shows it rather than only a title —
  // two blocks named `instruction-1` and `instruction-2` are otherwise
  // indistinguishable until one is selected.
  it('shows the instruction text on the card', () => {
    expect(renderNode().textContent).toContain('Prefer short sentences.');
  });

  it('falls back to the id when the block has no name, and shows the name when it has one', () => {
    expect(renderNode().textContent).toContain('instruction-1');
    expect(renderNode({ name: 'House style' }).textContent).toContain(
      'House style',
    );
  });

  // An empty block is legal (it is dropped on the canvas before it is
  // written) and must say so — a card with a title and blank space below it
  // reads as a rendering failure.
  it('says so when nothing has been written into the block yet', () => {
    const el = renderNode({ instructions: '   ' });
    expect(el.textContent).toContain('No instructions yet');
  });
});
