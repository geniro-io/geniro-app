// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, describe, expect, it } from 'vitest';

import type { NodeInstructionSize } from '../autogenerated';
import { InstructionSizeCard } from './instruction-size-card';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let root: Root | null = null;
let container: HTMLDivElement | null = null;

const MANAGER: NodeInstructionSize = {
  nodeId: 'manager',
  agent: 'claude',
  turn: 'own',
  totalChars: 151_234,
  approxTokens: 37_809,
  separatorChars: 10,
  parts: [
    { source: 'preamble', chars: 2_400, approxTokens: 600 },
    { source: 'customInstructions', chars: 324, approxTokens: 81 },
    {
      source: 'instructionBlocks',
      instructionNodeId: 'team-settings',
      chars: 45_000,
      approxTokens: 11_250,
    },
    {
      source: 'instructionBlocks',
      instructionNodeId: 'intent',
      chars: 3_500,
      approxTokens: 875,
    },
    { source: 'role', chars: 100_000, approxTokens: 25_000 },
  ],
};

const NAMES: Record<string, string> = {
  'team-settings': 'Team Settings',
  intent: 'Intent Review Standard',
};

function render(
  props: Partial<Parameters<typeof InstructionSizeCard>[0]> = {},
): HTMLElement {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
  act(() => {
    root!.render(
      <InstructionSizeCard
        size={MANAGER}
        loading={false}
        error={null}
        instructionName={(id) => NAMES[id] ?? id}
        {...props}
      />,
    );
  });
  return container;
}

function rows(host: HTMLElement): string[] {
  return [...host.querySelectorAll('li')].map((li) => li.textContent ?? '');
}

afterEach(() => {
  act(() => root?.unmount());
  container?.remove();
  root = null;
  container = null;
});

describe('InstructionSizeCard', () => {
  it('leads with the daemon’s total, in tokens and exact characters', () => {
    const text = render().textContent ?? '';

    expect(text).toContain('~37.8k tokens');
    expect(text).toContain('151,234 characters');
  });

  it('lists one row per part, a wired block under its instruction node’s name', () => {
    expect(rows(render())).toEqual([
      'Geniro display preamble2,400~600',
      'Your custom instructions324~81',
      'Team Settings45,000~11.3k',
      'Intent Review Standard3,500~875',
      'Role100,000~25k',
      'Paragraph breaks10',
    ]);
  });

  it('says when the measured turn is one answering a call', () => {
    expect(render().textContent).not.toContain('answering a call');
    expect(
      render({ size: { ...MANAGER, turn: 'call' } }).textContent,
    ).toContain('Measured for a turn answering a call');
  });

  it('keeps the last measurement up while the next one runs', () => {
    const host = render({ loading: true });

    expect(host.textContent).toContain('~37.8k tokens');
    expect(
      host
        .querySelector('[data-slot="instruction-size"]')
        ?.getAttribute('aria-busy'),
    ).toBe('true');
  });

  it('keeps the last figures up under the reason a new measurement failed', () => {
    const text =
      render({ error: 'Not measured: role is invalid.' }).textContent ?? '';

    expect(text).toContain('~37.8k tokens');
    expect(text).toContain('Not measured: role is invalid.');
  });

  it('says why there is no figure instead of showing a zero', () => {
    expect(render({ size: null, loading: true }).textContent).toContain(
      'Measuring…',
    );
    expect(
      render({ size: null, error: 'Not measured: fix the workflow first.' })
        .textContent,
    ).toBe('Not measured: fix the workflow first.');
  });
});
