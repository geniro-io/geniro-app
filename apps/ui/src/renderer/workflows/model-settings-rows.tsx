import type { ReactNode } from 'react';

import type {
  AgentContextWindow,
  AgentEffort,
  AgentModelParameter,
  WorkflowAgentPoolMember,
} from '../autogenerated';
import { ContextWindowSelect } from '../chats/context-window-select';
import { EffortSelect } from '../chats/effort-select';
import {
  ModelParameterSelect,
  withModelParameter,
} from '../chats/model-parameter-select';
import { SettingRow } from '../components/setting-row';

/** The per-model settings one configuration holds — the node's own or a pool member's. */
type ModelSettings = Pick<
  WorkflowAgentPoolMember,
  'model' | 'effort' | 'contextWindow' | 'modelParameters'
>;

/**
 * The labelled rows for whatever a configuration's MODEL offers: its effort,
 * its context window, and one row per other setting it enumerates. Shared by
 * the node's own settings card and each pool member, so a rule about when a
 * row shows is written once.
 *
 * The ROW goes with its control: each chip renders nothing when the model
 * offers no such axis, and a labelled row around nothing is a label with a
 * hole under it. A parameter row is labelled with the CLI's own word for the
 * axis, so the chip does not name it a second time.
 */
export function ModelSettingsRows({
  efforts,
  windows,
  parameters,
  value,
  onPatch,
  afterContext,
}: {
  efforts: AgentEffort[];
  windows: AgentContextWindow[];
  parameters: readonly AgentModelParameter[];
  value: ModelSettings;
  onPatch: (patch: Partial<ModelSettings>) => void;
  /** A row the caller places between the window and the parameters. */
  afterContext?: ReactNode;
}): React.JSX.Element {
  return (
    <>
      {efforts.length === 0 ? null : (
        <SettingRow width="compact" label="Effort">
          <EffortSelect
            efforts={efforts}
            levelsAreModelSpecific={value.model !== undefined}
            value={value.effort ?? null}
            onChange={(effort) => onPatch({ effort: effort ?? undefined })}
          />
        </SettingRow>
      )}
      {windows.length === 0 ? null : (
        <SettingRow width="compact" label="Context">
          <ContextWindowSelect
            windows={windows}
            value={value.contextWindow ?? null}
            onChange={(contextWindow) =>
              onPatch({ contextWindow: contextWindow ?? undefined })
            }
          />
        </SettingRow>
      )}
      {afterContext}
      {parameters.map((parameter) => (
        <SettingRow key={parameter.id} width="compact" label={parameter.label}>
          <ModelParameterSelect
            parameter={parameter}
            showAxisName={false}
            value={value.modelParameters?.[parameter.id] ?? null}
            onChange={(next) => {
              const merged = withModelParameter(
                value.modelParameters ?? {},
                parameter.id,
                next,
              );
              // `undefined` rather than `{}` once the last one is cleared, so
              // the YAML loses the key instead of carrying an empty map.
              onPatch({
                modelParameters:
                  Object.keys(merged).length === 0 ? undefined : merged,
              });
            }}
          />
        </SettingRow>
      ))}
    </>
  );
}
