import type {
  AgentMcpListingDto as AgentMcpListing,
  AgentMcpServer,
} from '../autogenerated';

/**
 * A workflow node's own MCP switches, laid over the listing of the servers its
 * PROFILE loads.
 *
 * The listing is the CLI's answer about a profile; the switches are the node's
 * (`WorkflowAgentNode.mcpDisabled`, or a pool member's), applied per turn by
 * the daemon and written into no config of the CLI's. So the overlay owns
 * exactly three things on a row and leaves the rest the CLI's:
 *
 * - `disabled` — whether THIS node runs without it;
 * - the lock — a row this node cannot switch says so in the daemon's own
 *   sentence (`turnToggleUnavailableReason`), and a row the profile ITSELF has
 *   off says that a node can only switch servers off, never on;
 * - approving — a per-FOLDER choice the builder has no folder for, so its
 *   button is replaced by that sentence rather than wired to a switch it is not.
 *
 * A name the node switched off that the profile does not list (a project
 * server of the run folder, a server removed from the profile since) is SHOWN
 * rather than dropped: the daemon still applies it to any server of that name
 * a run loads, and a list the reader cannot see is one they cannot clear. Not
 * while the listing is still dialling (`pending`), when every name would read
 * as missing.
 */
export function withNodeSwitches(
  listing: AgentMcpListing | undefined,
  disabled: readonly string[] | undefined,
): AgentMcpListing | undefined {
  if (listing === undefined || listing.unavailableReason !== null) {
    return listing;
  }
  const off = new Set(disabled ?? []);
  const servers: AgentMcpServer[] = listing.servers.map((row) => {
    const shared = {
      ...row,
      approveUnavailableReason: APPROVE_IN_A_CHAT,
    };
    if (row.disabled) {
      return {
        ...shared,
        disabled: true,
        toggleUnavailableReason: OFF_IN_PROFILE,
      };
    }
    return {
      ...shared,
      disabled: off.has(row.name),
      toggleUnavailableReason: row.turnToggleUnavailableReason ?? null,
    };
  });
  if (!listing.pending) {
    const listed = new Set(listing.servers.map((row) => row.name));
    for (const name of off) {
      if (!listed.has(name)) {
        servers.push(unlistedRow(name));
      }
    }
  }
  return { ...listing, servers };
}

/**
 * The node's list after one switch: a server switched OFF is added, one
 * switched back ON removed. Undefined once nothing is off, so the YAML carries
 * no empty key. Order is kept — it is the order the user switched them in.
 */
export function nextMcpDisabled(
  current: readonly string[] | undefined,
  server: string,
  enabled: boolean,
): string[] | undefined {
  const rest = (current ?? []).filter((name) => name !== server);
  const next = enabled ? rest : [...rest, server];
  return next.length === 0 ? undefined : next;
}

/**
 * What the builder's MCP dialog says above a node's (or a pool member's) rows:
 * whose servers these are, and what a switch here does and does NOT do — the
 * second half is the part nobody could guess, since the same switch in a chat
 * writes the CLI's own config.
 */
export function nodeMcpHint(
  subject: 'node' | 'member',
  hasProfile: boolean,
): string {
  const whose = hasProfile
    ? `The servers in this ${subject}'s own config directory.`
    : 'Global servers.';
  return `${whose} A switch here applies only to this ${subject}'s turns — nothing in the CLI's own config changes. The run folder's own project servers are added when it runs.`;
}

/** Why a row the profile itself switched off has no switch on a node. */
export const OFF_IN_PROFILE =
  'Off in this profile’s own config — a workflow node can only switch servers off, not back on.';

/** Why a builder row offers no Approve. */
export const APPROVE_IN_A_CHAT =
  'Approving a server is a per-folder choice, so it is made in a chat.';

/** Said on a row the node switched off that the profile does not list. */
export const NOT_IN_PROFILE =
  'Not among this profile’s servers — switched off for any server of this name a run loads (a run folder’s project server, say).';

function unlistedRow(name: string): AgentMcpServer {
  return {
    name,
    target: NOT_IN_PROFILE,
    transport: null,
    status: 'disabled',
    detail: null,
    scope: 'unknown',
    shadowsUser: false,
    disabled: true,
    toggleUnavailableReason: null,
    signInUnavailableReason: NOT_IN_PROFILE,
    approveUnavailableReason: APPROVE_IN_A_CHAT,
    turnToggleUnavailableReason: null,
  };
}
