function StageForm({
  idPrefix,
  stage,
  facts,
  stages,
  agentIds,
  errors,
  warnings,
  onChange,
  onToggleNext,
}: {
  idPrefix: string;
  stage: WorkflowStage;
  facts: StageFacts;
  stages: readonly WorkflowStage[];
  agentIds: readonly string[];
  errors: readonly StageIssue[];
  warnings: readonly StageIssue[];
  onChange: (patch: StagePatch) => void;
  onToggleNext: (nextId: string) => void;
}): React.JSX.Element {
  const others = stages.filter((other) => other.id !== stage.id);
  const next = stage.next ?? [];
  const owners = [
    {
      value: ANY_AGENT,
      label: 'Any agent',
      icon: <Users className="size-4" />,
    },
    ...agentIds.map((id) => ({
      value: id,
      label: id,
      icon: <Bot className="size-4" />,
    })),
    ...(stage.ownerHint && !agentIds.includes(stage.ownerHint)
      ? [
          {
            value: stage.ownerHint,
            label: `${stage.ownerHint} (not in this workflow)`,
            icon: <CircleAlert className="size-4" />,
          },
        ]
      : []),
  ];
  const at = (
    field: FormField,
  ): { errors: StageIssue[]; warnings: StageIssue[] } => ({
    errors: errors.filter((issue) => ISSUE_FIELD[issue.code] === field),
    warnings: warnings.filter((issue) => ISSUE_FIELD[issue.code] === field),
  });
  const invalid = (field: FormField): true | undefined =>
    at(field).errors.length > 0 || undefined;
  const onlyNext = stages.find((other) => other.id === next[0]);
  const nextLine =
    next.length >= 2
      ? `Fork — the run takes one of ${next.length}`
      : next.length === 1
        ? `Then ${onlyNext ? stageTitle(onlyNext) : next[0]}`
        : 'Final stage — the run ends here';
  return (
    <div data-slot="stage-form" className="flex min-w-0 flex-col gap-4">
      <header className="flex flex-col gap-1.5">
        <div className="flex min-w-0 items-baseline gap-2">
          <p className="truncate text-sm font-semibold">{stageTitle(stage)}</p>
          <p className="min-w-0 truncate font-mono text-xs text-muted-foreground">
            {stage.id}
          </p>
          <p className="ml-auto shrink-0 text-xs text-muted-foreground">
            {kindWords(facts).join(' · ')}
          </p>
        </div>
        <FieldIssues {...at('id')} />
      </header>
      <Field
        label="Title"
        htmlFor={`${idPrefix}-title`}
        hint="A short name for this stage.">
        <Input
          id={`${idPrefix}-title`}
          value={stage.title}
          aria-invalid={invalid('title')}
          placeholder="Investigation"
          onChange={(event) => onChange({ title: event.target.value })}
        />
        <FieldIssues {...at('title')} />
      </Field>
      <Field
        label="Instructions"
        htmlFor={`${idPrefix}-instructions`}
        hint="Optional — what to do in this stage, in plain language.">
        <Textarea
          id={`${idPrefix}-instructions`}
          value={stage.instructions ?? ''}
          rows={3}
          aria-invalid={invalid('instructions')}
          onChange={(event) => onChange({ instructions: event.target.value })}
        />
        <FieldIssues {...at('instructions')} />
      </Field>
      <Field
        label="Done when"
        htmlFor={`${idPrefix}-done-when`}
        hint="The condition that makes this stage finished.">
        <Input
          id={`${idPrefix}-done-when`}
          value={stage.doneWhen}
          aria-invalid={invalid('doneWhen')}
          placeholder="The cause is written down"
          onChange={(event) => onChange({ doneWhen: event.target.value })}
        />
        <FieldIssues {...at('doneWhen')} />
      </Field>
      <Field
        label="Usually done by"
        htmlFor={`${idPrefix}-owner`}
        hint="A hint for the agents, never a permission.">
        <Select
          id={`${idPrefix}-owner`}
          groups={[{ items: owners }]}
          value={stage.ownerHint ?? ANY_AGENT}
          onValueChange={(value) =>
            onChange({ ownerHint: value === ANY_AGENT ? undefined : value })
          }
        />
        <FieldIssues {...at('owner')} />
      </Field>
      <Field
        label="Next stages"
        hint={
          <>
            <span data-slot="stage-next-hint">{nextLine}</span>
            {next.length < 2 && others.length > 1
              ? '. Pick two or more for a fork.'
              : null}
          </>
        }>
        {others.length === 0 ? (
          <p className="text-sm text-muted-foreground">
            Add another stage to choose what follows this one.
          </p>
        ) : (
          <div
            role="group"
            aria-label="Next stages — pick as many as apply"
            className="flex flex-wrap gap-1.5">
            {others.map((other) => {
              const chosen = next.includes(other.id);
              return (
                <Chip
                  key={other.id}
                  asChild
                  interactive
                  className={nextChipVariants({ pressed: chosen })}>
                  <button
                    type="button"
                    aria-pressed={chosen}
                    onClick={() => onToggleNext(other.id)}>
                    {chosen ? (
                      <Check className="size-3" aria-hidden="true" />
                    ) : null}
                    <span className="truncate">{stageTitle(other)}</span>
                  </button>
                </Chip>
              );
            })}
          </div>
        )}
        <FieldIssues {...at('next')} />
      </Field>
    </div>
  );
}
