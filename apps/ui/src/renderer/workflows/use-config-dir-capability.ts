import type { AgentKind, CapabilitiesDto } from '../autogenerated';

/**
 * Whether each CLI can run under a config directory, as the DAEMON reports it.
 *
 * The daemon owns this answer (`AdapterConfig.configDir.unavailableReason`), so
 * the builder asks rather than deciding: a rule the renderer restates is one
 * that can disagree with the executor that enforces it, and a workflow
 * imported from YAML can name a config directory on a CLI that has none.
 *
 * A thin SELECTOR over the app's one capabilities read, not a fetch of its own
 * — the endpoint is read once so its loading and error policy cannot fork per
 * screen. What lives here is only the shape the inspector wants.
 *
 * Undefined while unknown. Callers must NOT read that as "cannot": the honest
 * rendering before the answer lands is nothing at all, the same way the panel
 * shows no MCP rows before its own read returns.
 */
export interface ConfigDirCapabilityState {
  /** Why this CLI cannot run under a config directory, `null` when it can. */
  unavailableReasonFor: (agent: AgentKind) => string | null | undefined;
  loading: boolean;
}

/**
 * The selector over a capabilities answer the caller already holds — every
 * caller reads the app's one shared answer (`useSharedCapabilities`), so
 * narrowing it needs no state and no hook of its own.
 */
export function configDirCapabilityFrom(
  capabilities: CapabilitiesDto | null,
  /**
   * `useCapabilities`'s own `loading`, passed in rather than derived here.
   *
   * The hook is the only thing that knows a read SETTLED: a failed read fails
   * open to `capabilities: null`, so a waiting state derived from the answer
   * alone would say "still asking" for the life of the daemon handle about a
   * read that had already given up.
   */
  loading: boolean,
): ConfigDirCapabilityState {
  const byAgent = capabilities
    ? new Map(
        capabilities.configDirs.map((p) => [p.agent, p.unavailableReason]),
      )
    : null;

  return {
    // `get` on an absent agent yields undefined, which is exactly the
    // "no answer for this CLI" the caller must not read as a refusal.
    unavailableReasonFor: (agent) => byAgent?.get(agent),
    loading,
  };
}
