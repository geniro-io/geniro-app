import type { AgentKind, CapabilitiesDto } from '../autogenerated';

/**
 * Whether each CLI can load a plugin directory, as the DAEMON reports it.
 *
 * The daemon owns this answer (`AdapterConfig.plugin.unavailableReason`), so
 * the builder asks rather than deciding: a rule the renderer restates is one
 * that can disagree with the executor that enforces it, and a workflow
 * imported from YAML can name a plugin directory on a CLI that ignores it.
 *
 * A thin SELECTOR over `useCapabilities`, not a fetch of its own — the
 * endpoint has one fetcher so its loading and error policy cannot fork per
 * screen. What lives here is only the shape the inspector wants.
 *
 * Undefined while unknown. Callers must NOT read that as "cannot": the honest
 * rendering before the answer lands is nothing at all, the same way the panel
 * shows no MCP rows before its own read returns.
 */
export interface ConfigDirCapabilityState {
  /** Why this CLI cannot load a plugin directory, `null` when it can. */
  unavailableReasonFor: (agent: AgentKind) => string | null | undefined;
  loading: boolean;
}

/**
 * The selector over a capabilities answer the caller already fetched.
 *
 * A PURE function rather than a hook, deliberately: `useCapabilities` holds its
 * state per CALL, so a hook wrapping the pair meant a screen needing two slices
 * of one answer (the builder wants this and the approval modes; Settings wants
 * this and the account row) mounted two fetchers and two retry loops for the
 * one endpoint whose doc says it exists to prevent exactly that. Every caller
 * reads `useCapabilities` once and narrows it here.
 */
export function configDirCapabilityFrom(
  capabilities: CapabilitiesDto | null,
  /** Whether a daemon is connected at all — `loading` is meaningless without one. */
  hasApi: boolean,
): ConfigDirCapabilityState {
  const byAgent = capabilities
    ? new Map(
        capabilities.configDirs.map((p) => [p.agent, p.unavailableReason]),
      )
    : null;

  return {
    // `get` on an absent agent yields undefined, which is exactly the
    // "no answer for this CLI" the caller must not read as a refusal.
    unavailableReasonFor: (agent) => byAgent?.get(agent),
    loading: byAgent === null && hasApi,
  };
}
