// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import { withHistoryPages } from '../__tests__/history-page';
import type { ItemDto as ChatItem, RunDto } from '../autogenerated';
import { CHAT_LIVE_KEY, type LiveTextEvent } from '../chats/live-text';
import { ANCHOR_ASK_DELAY_MS } from '../chats/use-live-anchor-asks';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient, RunStatusEvent } from '../daemon-client';
import {
  useWorkflowChat,
  type WorkflowChatSettings,
  type WorkflowChatState,
} from './use-workflow-chat';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const CHIPS: WorkflowChatSettings = { agentKind: 'claude' };

/** A live delta as the daemon's socket sends one — every figure unmeasured. */
function live(overrides: Partial<LiveTextEvent> = {}): LiveTextEvent {
  return {
    runId: 'run-1',
    nodeId: null,
    ownerKey: null,
    text: '',
    thinkingTokens: null,
    thinkingText: null,
    thinkingSince: null,
    thinkingStretch: null,
    contextTokens: null,
    contextWindowTokens: null,
    spentInputTokens: null,
    spentOutputTokens: null,
    spentCacheReadTokens: null,
    spentCostUsd: null,
    ...overrides,
  } as LiveTextEvent;
}

function runDto(overrides: Partial<RunDto> = {}): RunDto {
  return { id: 'run-1', status: 'pending', ...overrides } as RunDto;
}

function item(overrides: Partial<ChatItem> = {}): ChatItem {
  return {
    id: 'item-1',
    runId: 'run-1',
    seq: 1,
    kind: 'message',
    role: 'assistant',
    nodeId: null,
    payload: { text: 'hi' },
    createdAt: new Date().toISOString(),
    ...overrides,
  } as ChatItem;
}

/** A row `settledRunStatus` reads as a run-level turn ending. */
function turnComplete(id: string): ChatItem {
  return item({ id, kind: 'turn_complete', payload: {} });
}

describe('useWorkflowChat', () => {
  let container: HTMLDivElement | null = null;
  let root: Root | null = null;
  let latest: WorkflowChatState | null = null;

  let openWorkflowChat: ReturnType<typeof vi.fn>;
  let discardWorkflowChat: ReturnType<typeof vi.fn>;
  let listRunItems: ReturnType<typeof vi.fn>;
  let sendChatMessage: ReturnType<typeof vi.fn>;
  let cancelChat: ReturnType<typeof vi.fn>;
  let joinRun: ReturnType<typeof vi.fn>;
  let leaveRun: ReturnType<typeof vi.fn>;
  let sendVerdict: ReturnType<typeof vi.fn>;
  let itemListeners: ((row: ChatItem) => void)[];
  let statusListeners: ((event: RunStatusEvent) => void)[];
  let liveListeners: ((event: LiveTextEvent) => void)[];
  let reconnectListeners: ((error?: Error) => void)[];
  let disconnectListeners: (() => void)[];
  let apis: DaemonApis;
  let client: DaemonClient;

  function Probe({ slug }: { slug: string | null }): null {
    latest = useWorkflowChat({ slug, apis, client, settings: CHIPS });
    return null;
  }

  const state = (): WorkflowChatState => {
    if (latest === null) {
      throw new Error('the hook has not rendered');
    }
    return latest;
  };

  async function mount(slug: string | null = 'dev-team'): Promise<void> {
    container = document.createElement('div');
    document.body.appendChild(container);
    root = createRoot(container);
    await act(async () => {
      root?.render(<Probe slug={slug} />);
    });
  }

  const rerender = async (slug: string | null): Promise<void> => {
    await act(async () => {
      root?.render(<Probe slug={slug} />);
    });
  };

  const emitItem = async (row: ChatItem): Promise<void> => {
    await act(async () => {
      for (const listener of [...itemListeners]) {
        listener(row);
      }
    });
  };

  const emitStatus = async (event: RunStatusEvent): Promise<void> => {
    await act(async () => {
      for (const listener of [...statusListeners]) {
        listener(event);
      }
    });
  };

  const emitLive = async (event: LiveTextEvent): Promise<void> => {
    await act(async () => {
      for (const listener of [...liveListeners]) {
        listener(event);
      }
    });
  };

  beforeEach(() => {
    latest = null;
    itemListeners = [];
    statusListeners = [];
    liveListeners = [];
    reconnectListeners = [];
    disconnectListeners = [];
    openWorkflowChat = vi.fn().mockResolvedValue(runDto());
    discardWorkflowChat = vi.fn().mockResolvedValue({ deleted: 1 });
    listRunItems = vi.fn().mockResolvedValue([item()]);
    sendChatMessage = vi.fn().mockResolvedValue(item({ id: 'sent' }));
    cancelChat = vi.fn().mockResolvedValue({ cancelled: true });
    joinRun = vi.fn().mockResolvedValue(undefined);
    leaveRun = vi.fn();
    sendVerdict = vi.fn();
    apis = {
      workflows: { openWorkflowChat, discardWorkflowChat },
      chats: withHistoryPages({ listRunItems, sendChatMessage, cancelChat }),
    } as unknown as DaemonApis;
    client = {
      joinRun,
      leaveRun,
      sendVerdict,
      onItem: (listener: (row: ChatItem) => void) => {
        itemListeners.push(listener);
        return () => {
          itemListeners = itemListeners.filter((held) => held !== listener);
        };
      },
      onRunStatus: (listener: (event: RunStatusEvent) => void) => {
        statusListeners.push(listener);
        return () => {
          statusListeners = statusListeners.filter((held) => held !== listener);
        };
      },
      onLiveText: (listener: (event: LiveTextEvent) => void) => {
        liveListeners.push(listener);
        return () => {
          liveListeners = liveListeners.filter((held) => held !== listener);
        };
      },
      onDisconnect: (listener: () => void) => {
        disconnectListeners.push(listener);
        return () => {
          disconnectListeners = disconnectListeners.filter(
            (held) => held !== listener,
          );
        };
      },
      onReconnect: (listener: (error?: Error) => void) => {
        reconnectListeners.push(listener);
        return () => {
          reconnectListeners = reconnectListeners.filter(
            (held) => held !== listener,
          );
        };
      },
    } as unknown as DaemonClient;
  });

  afterEach(() => {
    act(() => {
      root?.unmount();
    });
    root = null;
    container?.remove();
    container = null;
    vi.useRealTimers();
  });

  it('opens the workflow chat and loads its transcript', async () => {
    await mount();

    expect(openWorkflowChat).toHaveBeenCalledWith({
      slug: 'dev-team',
      startWorkflowChatDto: CHIPS,
    });
    expect(state().run?.id).toBe('run-1');
    expect(state().items).toHaveLength(1);
    expect(joinRun).toHaveBeenCalledWith('run-1');
  });

  // A room joined after the history read drops anything produced in between;
  // a fetch that lands second cannot lose a row the socket already delivered.
  it('joins the run room before reading history', async () => {
    await mount();

    expect(joinRun.mock.invocationCallOrder[0] ?? 0).toBeLessThan(
      listRunItems.mock.invocationCallOrder[0] ?? 0,
    );
  });

  it('opens nothing while the panel is closed', async () => {
    await mount(null);

    expect(openWorkflowChat).not.toHaveBeenCalled();
    expect(state().run).toBeNull();
  });

  it('leaves the run room when the panel closes', async () => {
    await mount();

    await rerender(null);

    expect(leaveRun).toHaveBeenCalledWith('run-1');
  });

  it('appends a live item once, however often the socket delivers it', async () => {
    await mount();

    await emitItem(item({ id: 'live' }));
    await emitItem(item({ id: 'live' }));

    expect(state().items.filter((row) => row.id === 'live')).toHaveLength(1);
  });

  it('holds the opened page’s anchors apart from its rows', async () => {
    const start = item({
      id: 'start',
      seq: 1,
      kind: 'call_started',
      payload: { callId: 'call-7', calleeNodeId: 'qa' },
    });
    listRunItems.mockResolvedValueOnce({
      items: [item({ id: 'tail', seq: 400 })],
      anchors: [start],
    });

    await mount();

    expect(state().items.map((row) => row.id)).toEqual(['tail']);
    expect(state().anchors.map((row) => row.id)).toEqual(['start']);
  });

  it('merges a reconnect read-back’s anchors into the held ones, and drops another run’s', async () => {
    const held = item({
      id: 'held',
      seq: 1,
      kind: 'call_started',
      payload: { callId: 'call-1', calleeNodeId: 'qa' },
    });
    listRunItems.mockResolvedValueOnce({
      items: [item({ id: 'tail', seq: 400 })],
      anchors: [held],
    });
    await mount();
    const missedStart = item({
      id: 'missed-start',
      seq: 2,
      kind: 'call_started',
      payload: { callId: 'call-2', calleeNodeId: 'qa' },
    });
    listRunItems.mockResolvedValueOnce({
      items: [item({ id: 'offline', seq: 401 })],
      anchors: [missedStart, { ...missedStart, id: 'foreign', runId: 'run-9' }],
    });

    await reconnect();

    expect(state().anchors.map((row) => row.id)).toEqual([
      'held',
      'missed-start',
    ]);
  });

  it('asks for the anchors of a live row whose call started above its short window', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout'] });
    await mount();
    const start = item({
      id: 'start',
      seq: 2,
      kind: 'call_started',
      payload: { callId: 'call-7', calleeNodeId: 'qa' },
    });
    listRunItems.mockResolvedValueOnce({ items: [], anchors: [start] });

    await emitItem(
      item({
        id: 'callee',
        seq: 300,
        nodeId: 'qa',
        payload: { text: 'still at it', callId: 'call-7' },
      }),
    );
    await act(async () => {
      await vi.advanceTimersByTimeAsync(ANCHOR_ASK_DELAY_MS);
    });

    expect(listRunItems).toHaveBeenLastCalledWith(
      expect.objectContaining({ runId: 'run-1', afterSeq: 299 }),
    );
    expect(state().anchors.map((row) => row.id)).toEqual(['start']);
  });

  it('ignores an item belonging to another run', async () => {
    await mount();

    await emitItem(item({ id: 'other', runId: 'run-2' }));

    expect(state().items.some((row) => row.id === 'other')).toBe(false);
  });

  // This count is what the builder reloads its canvas on.
  it('counts a turn settling, and reports the agent as no longer working', async () => {
    await mount();
    await act(async () => {
      await state().send('rename the reviewer');
    });
    expect(state().working).toBe(true);

    await emitItem(turnComplete('done-1'));

    expect(state().settledTurns).toBe(1);
    expect(state().working).toBe(false);
  });

  it('reports the agent as working again on the next turn', async () => {
    await mount();
    await emitItem(turnComplete('done-1'));

    await emitStatus({ runId: 'run-1', status: 'running' } as RunStatusEvent);

    expect(state().working).toBe(true);
  });

  // A status announce that beats the rows ending the turn must not report the
  // turn as over while they are still being written.
  it('never lowers working from a status announce alone', async () => {
    await mount();
    await act(async () => {
      await state().send('go');
    });

    await emitStatus({ runId: 'run-1', status: 'completed' } as RunStatusEvent);

    expect(state().working).toBe(true);
  });

  it('lowers working on a settle no terminal row stands behind', async () => {
    // A lease running out, or the CLI session closing under an off-turn run,
    // settles with no row to lower the flag — and a raised flag keeps the
    // builder's autosave paused and the dock refusing to send.
    await mount();
    await emitStatus({ runId: 'run-1', status: 'running' } as RunStatusEvent);
    expect(state().working).toBe(true);

    await emitStatus({
      runId: 'run-1',
      status: 'completed',
      noTerminalItem: true,
    } as RunStatusEvent);

    expect(state().working).toBe(false);
    expect(state().settledTurns).toBe(1);
  });

  it('lowers working when the turn ended while the socket was down', async () => {
    // The room buffers nothing for an absent member, so the terminal row that
    // would have lowered the flag is only ever seen by reading it back.
    await mount();
    await act(async () => {
      await state().send('go');
    });
    expect(state().working).toBe(true);
    listRunItems.mockResolvedValueOnce([
      item({ id: 'offline-1', seq: 2 }),
      { ...turnComplete('offline-end'), seq: 3 },
    ]);

    await act(async () => {
      for (const listener of [...reconnectListeners]) {
        listener();
      }
    });

    expect(listRunItems).toHaveBeenLastCalledWith({
      runId: 'run-1',
      afterSeq: 1,
    });
    expect(state().items.map((row) => row.id)).toEqual([
      'item-1',
      'offline-1',
      'offline-end',
    ]);
    expect(state().working).toBe(false);
    expect(state().settledTurns).toBe(1);
  });

  const reconnect = async (error?: Error): Promise<void> => {
    await act(async () => {
      for (const listener of [...reconnectListeners]) {
        listener(error);
      }
    });
  };

  it('counts a turn ending once when the socket and the replay both deliver it', async () => {
    // Each count re-reads the builder's canvas.
    await mount();
    const end = { ...turnComplete('end-1'), seq: 2 };
    await emitItem(end);
    listRunItems.mockResolvedValueOnce([end]);

    await reconnect();

    expect(state().items.filter((row) => row.id === 'end-1')).toHaveLength(1);
    expect(state().settledTurns).toBe(1);
  });

  it('reads nothing back on a reconnect whose re-join was refused', async () => {
    // Another reconnect, and this replay with it, is already on its way.
    await mount();
    listRunItems.mockClear();

    await reconnect(new Error('join timed out'));

    expect(listRunItems).not.toHaveBeenCalled();
  });

  it('reads the newest page back when nothing was held before the drop', async () => {
    // Never `afterSeq: -1`, which the daemon reads as the whole transcript.
    listRunItems.mockResolvedValueOnce([]);
    await mount();

    await reconnect();

    const [args] = listRunItems.mock.calls.at(-1)!;
    expect(args).toEqual({ runId: 'run-1', limit: expect.any(Number) });
  });

  it('keeps working when the rows read back end mid-turn', async () => {
    await mount();
    await act(async () => {
      await state().send('go');
    });
    listRunItems.mockResolvedValueOnce([item({ id: 'mid-1', seq: 2 })]);
    openWorkflowChat.mockResolvedValue(runDto({ status: 'running' }));

    await reconnect();

    expect(state().items.some((row) => row.id === 'mid-1')).toBe(true);
    expect(state().working).toBe(true);
    expect(state().settledTurns).toBe(0);
  });

  it('reads back from where the socket dropped, not from a row that landed since', async () => {
    // The room is re-joined before the reconnect listeners run, so a live row
    // can arrive first; reading after it would skip what was missed.
    await mount();
    await act(async () => {
      for (const listener of [...disconnectListeners]) {
        listener();
      }
    });
    await emitItem(item({ id: 'live-5', seq: 5 }));

    await reconnect();

    expect(listRunItems).toHaveBeenLastCalledWith({
      runId: 'run-1',
      afterSeq: 1,
    });
  });

  it('lowers working when the run settled with no row while the socket was down', async () => {
    // A lease running out or a failed send writes no terminal row, and its
    // flagged announce went to a socket that was not there.
    await mount();
    await act(async () => {
      await state().send('go');
    });
    listRunItems.mockResolvedValueOnce([]);
    openWorkflowChat.mockResolvedValueOnce(runDto({ status: 'completed' }));

    await reconnect();

    expect(state().working).toBe(false);
    expect(state().settledTurns).toBe(1);
    expect(state().run?.status).toBe('completed');
  });

  it('opens the new chat when the old one was discarded while the socket was down', async () => {
    await mount();
    openWorkflowChat.mockResolvedValue(runDto({ id: 'run-2' }));

    await reconnect();

    expect(state().run?.id).toBe('run-2');
    expect(joinRun).toHaveBeenLastCalledWith('run-2');
  });

  // A chat is created `pending` and stays there until its first turn starts.
  // Read as working it disabled the composer on a conversation that had never
  // run, so the FIRST message could never be sent — found by driving the app.
  it('does not read a freshly created chat as working', async () => {
    openWorkflowChat.mockResolvedValue(runDto({ status: 'pending' }));

    await mount();

    expect(state().working).toBe(false);
  });

  it('does not read a pending announce as working either', async () => {
    await mount();

    await emitStatus({ runId: 'run-1', status: 'pending' } as RunStatusEvent);

    expect(state().working).toBe(false);
  });

  it('reads a run that is already running as working', async () => {
    openWorkflowChat.mockResolvedValue(runDto({ status: 'running' }));

    await mount();

    expect(state().working).toBe(true);
  });

  it('surfaces the daemon sentence when a send is refused', async () => {
    sendChatMessage.mockRejectedValue(new Error('daemon said no'));
    await mount();

    await act(async () => {
      await state().send('go');
    });

    expect(state().error).toBe('daemon said no');
    expect(state().working).toBe(false);
  });

  it('surfaces the daemon sentence when the chat cannot be opened', async () => {
    openWorkflowChat.mockRejectedValue(new Error('no such workflow'));

    await mount('gone');

    expect(state().error).toBe('no such workflow');
    expect(state().run).toBeNull();
  });

  it('routes an approval verdict to the open run', async () => {
    await mount();

    await act(async () => {
      state().respond('req-9', true, 'go ahead');
    });

    expect(sendVerdict).toHaveBeenCalledWith(
      'run-1',
      'req-9',
      true,
      'go ahead',
    );
  });

  // Discarding is the panel's start-over and the slug does not change, so
  // without the reopen the dock would sit empty until it was closed and opened.
  it('opens a fresh conversation after a discard', async () => {
    await mount();
    openWorkflowChat.mockResolvedValue(runDto({ id: 'run-2' }));

    await act(async () => {
      await state().discard();
    });

    expect(discardWorkflowChat).toHaveBeenCalledWith({ slug: 'dev-team' });
    expect(state().run?.id).toBe('run-2');
  });

  it('cancels the turn in flight', async () => {
    await mount();

    await act(async () => {
      await state().cancel();
    });

    expect(cancelChat).toHaveBeenCalledWith({ runId: 'run-1' });
  });

  // The LIVE plane — the words the agent is writing before they are a row.
  // Without it the panel showed nothing at all while a turn ran, which is the
  // reported "сейчас там нет ни иконки загрузки, ничего".
  it('collects the agent\u2019s live deltas', async () => {
    await mount();

    await emitLive(live({ text: 'adding the reviewer' }));

    expect(state().liveText.get(CHAT_LIVE_KEY)?.text).toBe(
      'adding the reviewer',
    );
  });

  it('ignores a delta belonging to another run', async () => {
    await mount();

    await emitLive(live({ runId: 'run-2', text: 'not ours' }));

    expect(state().liveText.size).toBe(0);
  });

  // Throwaway by construction: it describes an instant of one conversation, so
  // carrying it into the next would draw another workflow's half-written
  // sentence under this one's transcript.
  it('drops the plane when the panel closes', async () => {
    await mount();
    await emitLive(live({ text: 'adding the reviewer' }));
    expect(state().liveText.size).toBe(1);

    await rerender(null);

    expect(state().liveText.size).toBe(0);
  });
});
