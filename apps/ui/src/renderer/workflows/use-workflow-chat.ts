import { useCallback, useEffect, useRef, useState } from 'react';

import type {
  ItemDto as ChatItem,
  RunDto,
  StartWorkflowChatDto,
  UpdateChatSettingsDto,
} from '../autogenerated';
import { settledRunStatus } from '../chats/settled-status';
import { type DaemonApis, describeDaemonError } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';

/**
 * How much of the conversation the panel loads.
 *
 * Far below the chat screen's own page: this is a dock a few centimetres tall,
 * used to ask for a change and watch it land, and a builder open on a
 * long-running workflow chat should not pay a thousand-row fetch to show the
 * last exchange. Older history is read in the chat screen, where the thread is
 * an ordinary chat like any other.
 */
export const WORKFLOW_CHAT_PAGE = 120;

/** The composer chips a workflow chat is STARTED with. */
export type WorkflowChatSettings = StartWorkflowChatDto;

export interface WorkflowChatState {
  /** The conversation, or null while it is being opened / the panel is shut. */
  run: RunDto | null;
  items: ChatItem[];
  /** The conversation is being opened — its transcript has not arrived yet. */
  loading: boolean;
  /** Why the panel could not open or send, in the daemon's own words. */
  error: string | null;
  /** A turn is in flight, so the agent may be writing the workflow file. */
  working: boolean;
  /**
   * Bumped once each time a turn of this chat SETTLES.
   *
   * The builder reloads the workflow off this rather than watching the file:
   * nothing in either app watches one, and a turn ending is the moment the
   * agent's edits are finished being made.
   */
  settledTurns: number;
  send: (text: string) => Promise<void>;
  /**
   * Change an OPEN conversation's model, effort, approval and the rest — the
   * same route the chat screen's own chips patch through.
   *
   * The create settings cannot serve for this: they are read once, and a chip
   * moved afterwards would silently change nothing. `agentKind` is absent from
   * the patch because it is fixed for a run's life — changing the agent means
   * {@link WorkflowChatState.discard} and a fresh conversation.
   */
  patchSettings: (patch: UpdateChatSettingsDto) => Promise<void>;
  /** Answer an approval or question card this chat raised. */
  respond: (requestId: string, allow: boolean, answer?: string) => void;
  /** Stop the turn in flight. */
  cancel: () => Promise<void>;
  /** Throw the conversation away; the next open starts a fresh one. */
  discard: () => Promise<void>;
}

/**
 * The ONE conversation behind the workflow builder's chat panel.
 *
 * `useChatRun` is the chat SCREEN's hook — the run list, the scopes, the
 * paging, the draft swapping, the follow-up queue — and none of that has a
 * meaning in a dock bound to one workflow. What this needs is the subset that
 * is genuinely about a single run: open it, read its transcript, follow its
 * room, send into it, answer its cards. Widening `useChatRun` to serve both
 * would mean every one of its screen-wide concerns growing a "not on this
 * surface" arm.
 *
 * It follows the run's room through the same `DaemonClient` the chat screen
 * uses, which is why that client tracks joined rooms as a SET: both surfaces
 * are live at once whenever the builder is open.
 */
export function useWorkflowChat({
  slug,
  apis,
  client,
  settings,
}: {
  /** The workflow whose chat this is, or null while the panel is closed. */
  slug: string | null;
  apis: DaemonApis | null;
  client: DaemonClient | null;
  /** Read only when a chat is CREATED — an open one keeps what it started with. */
  settings: WorkflowChatSettings;
}): WorkflowChatState {
  const [run, setRun] = useState<RunDto | null>(null);
  const [items, setItems] = useState<ChatItem[]>([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [working, setWorking] = useState(false);
  const [settledTurns, setSettledTurns] = useState(0);
  // Bumped by `discard`, which is the one thing that ends a conversation
  // without the panel closing — the slug has not changed, so nothing else
  // would re-run the open effect and the panel would sit empty until the user
  // closed and reopened it.
  const [reopenNonce, setReopenNonce] = useState(0);

  // The chips are the CREATE arguments, so re-reading them must not reopen the
  // chat — a ref keeps the effect keyed on the workflow alone. Without it every
  // keystroke in a model picker would tear the room down and join it again.
  const settingsRef = useRef(settings);
  settingsRef.current = settings;

  useEffect(() => {
    if (slug === null || apis === null || client === null) {
      setRun(null);
      setItems([]);
      setError(null);
      setWorking(false);
      return;
    }
    let cancelled = false;
    let joinedRunId: string | null = null;
    setLoading(true);
    setError(null);
    void (async () => {
      try {
        const opened = await apis.workflows.openWorkflowChat({
          slug,
          startWorkflowChatDto: settingsRef.current,
        });
        if (cancelled) {
          return;
        }
        // The room is joined BEFORE the history is read, so an item produced
        // between the two arrives on the socket rather than falling into the
        // gap between the fetch and the subscription.
        joinedRunId = opened.id;
        await client.joinRun(opened.id);
        const history = await apis.chats.listRunItems({
          runId: opened.id,
          limit: WORKFLOW_CHAT_PAGE,
        });
        if (cancelled) {
          return;
        }
        setRun(opened);
        setItems(history);
        setWorking(opened.status === 'running' || opened.status === 'pending');
      } catch (err) {
        if (!cancelled) {
          setError(describeDaemonError(err));
        }
      } finally {
        if (!cancelled) {
          setLoading(false);
        }
      }
    })();
    return () => {
      cancelled = true;
      if (joinedRunId !== null) {
        client.leaveRun(joinedRunId);
      }
    };
  }, [slug, apis, client, reopenNonce]);

  const runId = run?.id ?? null;

  useEffect(() => {
    if (client === null || runId === null) {
      return;
    }
    return client.onItem((item) => {
      if (item.runId !== runId) {
        return;
      }
      // Keyed by id rather than appended blindly: the daemon persists then
      // emits, so an item can arrive over the socket that the history read
      // already returned.
      setItems((current) =>
        current.some((held) => held.id === item.id)
          ? current
          : [...current, item],
      );
      if (settledRunStatus(item) !== null) {
        setWorking(false);
        setSettledTurns((count) => count + 1);
      }
    });
  }, [client, runId]);

  useEffect(() => {
    if (client === null || runId === null) {
      return;
    }
    return client.onRunStatus((event) => {
      if (event.runId !== runId || event.status === null) {
        return;
      }
      const status = event.status;
      setRun((current) => (current ? { ...current, status } : current));
      // Only ever raised here. A turn is lowered by its own terminal ITEM, so
      // a status announce that arrives first cannot report the turn as over
      // while the rows that ended it are still being written.
      if (status === 'running' || status === 'pending') {
        setWorking(true);
      }
    });
  }, [client, runId]);

  const send = useCallback(
    async (text: string): Promise<void> => {
      if (apis === null || runId === null) {
        return;
      }
      setError(null);
      // Raised BEFORE the request, so the builder's autosave is suspended
      // before the agent can possibly touch the file.
      setWorking(true);
      try {
        await apis.chats.sendChatMessage({
          runId,
          sendMessageDto: { text },
        });
      } catch (err) {
        setWorking(false);
        setError(describeDaemonError(err));
      }
    },
    [apis, runId],
  );

  const patchSettings = useCallback(
    async (patch: UpdateChatSettingsDto): Promise<void> => {
      if (apis === null || runId === null) {
        return;
      }
      try {
        const updated = await apis.chats.updateChatSettings({
          runId,
          updateChatSettingsDto: patch,
        });
        setRun(updated);
      } catch (err) {
        setError(describeDaemonError(err));
      }
    },
    [apis, runId],
  );

  const respond = useCallback(
    (requestId: string, allow: boolean, answer?: string): void => {
      if (client === null || runId === null) {
        return;
      }
      client.sendVerdict(runId, requestId, allow, answer);
    },
    [client, runId],
  );

  const cancel = useCallback(async (): Promise<void> => {
    if (apis === null || runId === null) {
      return;
    }
    try {
      await apis.chats.cancelChat({ runId });
    } catch (err) {
      setError(describeDaemonError(err));
    }
  }, [apis, runId]);

  const discard = useCallback(async (): Promise<void> => {
    if (apis === null || slug === null) {
      return;
    }
    try {
      await apis.workflows.discardWorkflowChat({ slug });
      setRun(null);
      setItems([]);
      setWorking(false);
      setError(null);
      // The room is left by the open effect's own cleanup, which this re-runs:
      // leaving it here as well would leave the room twice and, worse, leave
      // the room the NEXT conversation is about to join.
      setReopenNonce((nonce) => nonce + 1);
    } catch (err) {
      setError(describeDaemonError(err));
    }
  }, [apis, slug]);

  return {
    run,
    items,
    loading,
    error,
    working,
    settledTurns,
    send,
    patchSettings,
    respond,
    cancel,
    discard,
  };
}
