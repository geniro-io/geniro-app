import { useRef } from 'react';

import type { RunDto, StartWorkflowChatDto } from '../autogenerated';
import { type HostedChatState, useHostedChat } from '../chats/use-hosted-chat';
import { useLatestCallback } from '../components/use-latest-callback';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { currentRunSettings } from '../run-settings';

/** The composer chips a workflow chat is STARTED with. */
export type WorkflowChatSettings = StartWorkflowChatDto;

export type WorkflowChatState = HostedChatState;

/**
 * The ONE conversation behind the workflow builder's chat panel — a hosted
 * chat (`useHostedChat`) whose subject is the workflow: opening it creates the
 * workflow's chat when there is none, and discarding it throws that chat away.
 */
export function useWorkflowChat({
  slug,
  apis,
  client,
  settings,
}: {
  /** The workflow whose chat this is, or null while the panel is closed. */
  slug: string | null;
  apis: DaemonApis | null;
  client: DaemonClient | null;
  /** Read only when a chat is CREATED — an open one keeps what it started with. */
  settings: WorkflowChatSettings;
}): WorkflowChatState {
  // The chips are the CREATE arguments, read when the chat is opened, never a
  // reason to reopen it.
  const settingsRef = useRef(settings);
  settingsRef.current = settings;
  const open = useLatestCallback(async (): Promise<RunDto> => {
    if (apis === null || slug === null) {
      throw new Error('no workflow chat to open');
    }
    return apis.workflows.openWorkflowChat({
      slug,
      startWorkflowChatDto: {
        ...settingsRef.current,
        ...(await currentRunSettings()),
      },
    });
  }, [apis, slug]);
  const discard = useLatestCallback(async (): Promise<void> => {
    if (apis !== null && slug !== null) {
      await apis.workflows.discardWorkflowChat({ slug });
    }
  }, [apis, slug]);
  return useHostedChat({ subject: slug, apis, client, open, discard });
}
