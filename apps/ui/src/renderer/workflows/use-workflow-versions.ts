import type { WorkflowVersionsDto } from '../autogenerated';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import {
  type LiveDaemonRead,
  useLiveDaemonRead,
} from '../use-live-daemon-read';

/**
 * One workflow's versions table, read only while `slug` is set (the dialog is open)
 * and kept current after each recorded turn. Another workflow's table is never shown
 * under this one's name.
 */
export function useWorkflowVersions(
  apis: DaemonApis | null,
  slug: string | null,
  client?: DaemonClient | null,
): LiveDaemonRead<WorkflowVersionsDto> {
  return useLiveDaemonRead(
    apis,
    slug,
    (source) => source.stats.readWorkflowVersions({ slug: slug ?? '' }),
    { client },
  );
}
