import { GitFork, Trash2, Workflow as WorkflowIcon } from 'lucide-react';

import type { WorkflowSummaryDto as WorkflowSummary } from '../autogenerated';
import { NavListItem } from '../components/nav-list-item';
import { Button } from '../components/ui/button';
import {
  Card,
  CardDescription,
  CardFooter,
  CardHeader,
  CardTitle,
} from '../components/ui/card';
import { cn } from '../components/ui/utils';
import { formatUpdated } from './format-updated';

/** `3 nodes` / `1 node` — count with its correctly-pluralized unit. */
function plural(count: number, unit: string): string {
  return `${count} ${unit}${count === 1 ? '' : 's'}`;
}

/**
 * One workflow in the library GRID: name and description in a `Card` body,
 * the per-agent-kind tally and the graph's shape in a footer row underneath.
 *
 * Two per line, so the description — the field that tells two workflows apart,
 * where the tally and counts are near-identical — has the width to wrap into
 * three lines rather than being cut to one.
 *
 * Built on `NavListItem` for its activation structure (a real `<button>`
 * layered under the content, so keyboard activation is the platform's and
 * the delete control is a sibling of it rather than a nested interactive
 * inside a `role="button"` div, which ARIA forbids) — see that component's
 * doc block. The visible surface is the actual `Card` primitive, nested
 * inside `NavListItem`'s content wrapper, rather than a second card look
 * hand-rolled from Card's own class list: `NavListItem`'s own `<li>` dress
 * is neutralized (`bg-transparent`, no padding) so `Card` is
 * the only thing painting a border/radius/shadow here.
 *
 * Row heights are NOT forced equal down a grid row (no `items-stretch` on
 * the library's grid) — a description is one line as often as three, and
 * stretching every card to its tallest neighbour would leave a footer
 * dangling in blank space under a one-line description.
 */
export function WorkflowCard({
  summary,
  onOpen,
  onDelete,
}: {
  summary: WorkflowSummary;
  onOpen: () => void;
  /** Asks to delete this workflow — the page confirms in a modal first. */
  onDelete: () => void;
}): React.JSX.Element {
  return (
    <NavListItem
      active={false}
      activateLabel={`Open ${summary.name}`}
      onActivate={onOpen}
      className="group rounded-xl bg-transparent px-0 py-0 hover:bg-transparent">
      <Card className="gap-4 transition-colors group-hover:bg-accent/20">
        <CardHeader className="gap-1">
          <CardTitle className="truncate text-sm font-medium">
            {summary.name}
          </CardTitle>
          {/* Up to three lines — the field this card exists to give room to. */}
          <CardDescription className="line-clamp-3 text-xs">
            {summary.description || 'No description'}
          </CardDescription>
        </CardHeader>

        <CardFooter
          className={cn(
            'flex flex-wrap items-center gap-x-3 gap-y-1.5',
            'text-xs text-muted-foreground',
          )}>
          {/* Which CLIs this team is made of — truncated rather than hidden
              below a breakpoint, since a card is narrower than the row it
              replaced but still wide enough for one line of this. */}
          <span className="min-w-0 flex-1 truncate">
            {summary.agentCounts
              .map((agent) => `${agent.kind} ×${agent.count}`)
              .join(' · ')}
          </span>

          <span className="inline-flex shrink-0 items-center gap-1 tabular-nums">
            <WorkflowIcon aria-hidden="true" className="size-3.5 shrink-0" />
            {plural(summary.nodeCount, 'node')}
          </span>
          <span className="inline-flex shrink-0 items-center gap-1 tabular-nums">
            <GitFork aria-hidden="true" className="size-3.5 shrink-0" />
            {plural(summary.edgeCount, 'edge')}
          </span>

          <span className="shrink-0 tabular-nums">
            {formatUpdated(summary.updatedAt)}
          </span>

          <Button
            type="button"
            variant="ghost"
            size="icon"
            aria-label={`Delete ${summary.name}`}
            title="Delete workflow"
            className="ml-auto size-7 shrink-0 text-muted-foreground opacity-0 transition-opacity hover:bg-destructive/10 hover:text-destructive focus-visible:opacity-100 group-hover:opacity-100 [&_svg]:size-3.5"
            onClick={onDelete}>
            <Trash2 />
          </Button>
        </CardFooter>
      </Card>
    </NavListItem>
  );
}
