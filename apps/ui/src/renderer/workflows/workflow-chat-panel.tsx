/** No workflow is ever a target here — this chat EDITS one. */
const NO_WORKFLOW_TARGETS = [] as const;

/**
 * The agent a workflow chat opens with when the user has picked none.
 *
 * Its edits are file edits it was asked to make, so `acceptEdits` is the mode
 * that matches what the panel is for — `ask` would put a card in front of every
 * write, and `auto` gives away more than the job needs. A CLI that does not
 * offer it opens on its own default instead; the daemon narrows it.
 */
const DEFAULT_APPROVAL: ChatApprovalMode = 'acceptEdits';

/** The chips a save can change, each named by the settings field it patches. */
const CHIP_KEYS = [
  'model',
  'effort',
  'contextWindow',
  'approval',
  'modelParameters',
  'configDir',
] as const;
type ChipKey = (typeof CHIP_KEYS)[number];

function isChipKey(key: string): key is ChipKey {
  return CHIP_KEYS.some((known) => known === key);
}

/** One chip's saves that have not answered yet — see `applySettings`. */
interface ChipSaves {
  pending: number;
  /** The newest save the daemon accepted, by the order the saves were sent. */
  newest: { seq: number; values: UpdateChatSettingsDto } | null;
}

/** A run row read in the shape a settings save uses, so a chip sets from either. */
function rowValues(row: RunDto): UpdateChatSettingsDto {
  return {
    model: row.model,
    effort: row.effort,
    contextWindow: row.contextWindow,
    approval: row.approval ?? undefined,
    modelParameters: row.modelParameters,
    configDir: row.configDir,
  };
}

/**
 * The chat docked under the workflow builder: the user describes a change and
 * an agent makes it in the workflow's own YAML file.
 *
 * It mirrors the terminal panel's dock — an `<aside>` with a resize handle, a
 * header and a collapse control — so the app's two bottom panels are one thing
 * to learn. What it holds is the chat screen's own parts: the transcript rows,
 * the approval card, the composer shell and its chips. Nothing here re-draws a
 * message or an option list; if a row looks wrong, it looks wrong in the chat
 * screen too.
 *
 * Once opened it stays MOUNTED while the builder holds that workflow and is
 * only HIDDEN when closed, like the terminal panel — not for a scrollback, but
 * for the two reports it owes the builder. Unmounted, a turn still running
 * when the dock was closed would take its `working` report and its settle
 * with it: the builder's autosave would stay suspended for good (every later
 * canvas edit lost on leaving) and the agent's own edit would never be
 * reloaded, so the next canvas save would write over it.
 */
export function WorkflowChatPanel({
  slug,
  workflowName,
  apis,
  handle,
  client,
  capabilities,
  capabilitiesLoading,
  recentConfigDirs,
  configProfiles,
  hidden = false,
  active = true,
  onClose,
  onBeforeSend,
  onWorkingChange,
  onAwaitingChange,
  onTurnSettled,
}: {
  slug: string;
  workflowName: string;
  apis: DaemonApis | null;
  /** This launch's daemon — what a published page's URL is built from. */
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  /** PER CLI: each keeps a different layout in its directory. */
  recentConfigDirs: Partial<Record<CliKind, readonly string[]>>;
  /** The user's named config directories — the WHOLE list; filtered to this panel's own agent below. */
  configProfiles: readonly ConfigProfile[];
  /** Closed by the user but still following its conversation — see above. */
  hidden?: boolean;
  /** Whether the builder is on screen. Its settings are read again when it is. */
  active?: boolean;
  onClose: () => void;
  /**
   * Run before a message is handed to the daemon — the builder writes any
   * pending canvas edit first, so the agent reads the graph the user is
   * looking at rather than the one last autosaved.
   */
  onBeforeSend: () => Promise<unknown>;
  /**
   * A turn started or ended. The builder suspends its autosave while one runs,
   * so the agent's write and the canvas cannot overwrite each other.
   */
  onWorkingChange: (working: boolean) => void;
  /**
   * The agent is waiting on the user — a question or an approval card — or no
   * longer is. The dock can be HIDDEN while its turn waits, so the builder
   * marks its toggle from this; nothing else on screen would say so.
   */
  onAwaitingChange?: (awaiting: RunAwaiting | null) => void;
  /** A turn ended — the builder re-reads the workflow the agent may have edited. */
  onTurnSettled: () => void | Promise<void>;
}): React.JSX.Element {
  const {
    width: height,
    minWidth,
    maxWidth,
    startResize,
    resizeTo,
  } = usePanelWidth({
    storageKey: 'workflowChat.panelHeight',
    defaultWidth: 320,
    minWidth: 180,
    maxWidth: 900,
    handleEdge: 'top',
  });

  // The chips, before a conversation exists. Once one does they describe the
  // run and every change is patched onto it — see `applySettings` below.
  const [agentKind, setAgentKind] = useState<AgentKind>(CLI_KINDS[0]!);
  const [model, setModel] = useState<string | null>(null);
  const [effort, setEffort] = useState<string | null>(null);
  const [contextWindow, setContextWindow] = useState<string | null>(null);
  const [approval, setApproval] = useState<ChatApprovalMode>(DEFAULT_APPROVAL);
  const [modelParameters, setModelParameters] = useState<
    Record<string, string>
  >({});
  const [configDir, setConfigDir] = useState<string | null>(null);
  const [collapseToolSteps, setCollapseToolSteps] = useState(false);
  const [draft, setDraft] = useState('');
  const [composeError, setComposeError] = useState<string | null>(null);
  const sendingRef = useRef(false);

  const settings = useMemo<WorkflowChatSettings>(
    () => ({
      agentKind,
      approval,
      ...(model === null ? {} : { model }),
      ...(effort === null ? {} : { effort }),
      ...(contextWindow === null ? {} : { contextWindow }),
      ...(configDir === null ? {} : { configDir }),
      ...(Object.keys(modelParameters).length === 0 ? {} : { modelParameters }),
    }),
    [
      agentKind,
      approval,
      model,
      effort,
      contextWindow,
      configDir,
      modelParameters,
    ],
  );

  const chat = useWorkflowChat({ slug, apis, client, settings });
  const runId = chat.run?.id ?? null;
  const ownerRef = useRef(runId ?? slug);
  ownerRef.current = runId ?? slug;
  const attachments = useAttachments(undefined, {
    current: () => ownerRef.current,
    // A discarded conversation cannot receive an image whose read finishes later.
    elsewhere: () => {},
  });
  const fileAttach = useFileAttach({
    remote: isRemoteRuntime(),
    stageImages: attachments.addFiles,
    resolvePath: (file) => window.geniro.filePath(file),
    upload: async (file) => {
      if (apis === null) {
        throw new Error('daemon unavailable');
      }
      return (
        await apis.chats.uploadChatFile(
          {
            uploadChatFileDto: {
              name: file.name,
              data: await readAsBase64(file),
            },
          },
          { signal: AbortSignal.timeout(CHAT_UPLOAD_TIMEOUT_MS) },
        )
      ).path;
    },
    currentOwner: () => ownerRef.current,
    deliver: (owner, paths) => {
      if (owner === ownerRef.current) {
        setDraft((text) => appendPaths(text, paths));
      }
    },
  });
  const clearAttachments = attachments.clear;
  useEffect(() => {
    setDraft('');
    setComposeError(null);
    clearAttachments();
  }, [slug, runId, clearAttachments]);
  const attachBusy = attachments.reading || fileAttach.uploading;
  const attachBusyTitle = attachments.reading
    ? 'Reading the image…'
    : 'Uploading the file…';
  const hasContent = draft.trim() !== '' || attachments.attachments.length > 0;
  const loadAttachment = useCallback(
    async (attachmentRunId: string, attachmentId: string): Promise<string> => {
      if (apis === null) {
        throw new Error('daemon unavailable');
      }
      return (
        await apis.chats.readChatAttachment({
          runId: attachmentRunId,
          attachmentId,
        })
      ).data;
    },
    [apis],
  );

  // A picture the agent referenced, read from this run's own folder: the route
  // the chat screen takes (`loadMarkdownImage` in Chats.tsx).
  const loadMarkdownImage = useCallback(
    async (path: string): Promise<string> => {
      if (apis === null || runId === null) {
        throw new Error('no run to resolve this image against');
      }
      return readLocalImageDataUrl(apis.chats, runId, path);
    },
    [apis, runId],
  );

  // The approvals the transcript already draws as cards, which its verdict rows
  // must not repeat — the chat screen computes the same set.
  const cardBacked = useMemo(
    () => cardBackedRequestIds(chat.items),
    [chat.items],
  );
  /** How a page this dock's agent published is addressed — see `Chats.tsx`. */
  const artifactUrl = useMemo<ArtifactUrlBuilder | null>(() => {
    if (handle === null || runId === null) {
      return null;
    }
    return artifactUrlBuilder(handle, runId);
  }, [handle, runId]);
  const { run, working, settledTurns, patchSettings, rememberContext } = chat;
  /**
   * The context readout's loader — the chat screen's own, read off the run's
   * metrics route. A run-level reading is written back to the row, so the ring
   * agrees with the panel it was opened from. A node's or a call's reading is a
   * window the row does not hold, so it is not written back.
   */
  const loadMetrics = useMemo<ChatMetricsLoader | undefined>(() => {
    if (apis === null) {
      return undefined;
    }
    return (readRunId, nodeId, callId, refresh) =>
      apis.chats
        .readChatMetrics({
          runId: readRunId,
          nodeId: nodeId ?? undefined,
          callId: callId ?? undefined,
          refresh: refresh ? 'true' : undefined,
        })
        .then((metrics) => {
          if (nodeId === null && callId === null) {
            rememberContext(
              readRunId,
              metrics.context?.totalTokens ?? null,
              metrics.context?.maxTokens ?? null,
            );
          }
          return metrics;
        });
  }, [apis, rememberContext]);
  // The chat screen folds and reads a run through these same functions, so the
  // transcript, the status and the composer's ring fold and read the same rows.
  const foldItems = useMemo(
    () => withAnchors(chat.items, chat.anchors),
    [chat.items, chat.anchors],
  );
  const anchorIds = useMemo(
    () => anchorOnlyIds(chat.items, chat.anchors),
    [chat.items, chat.anchors],
  );
  // The verdicts, and the requests a turn was taken down with, read as the card
  // reads them: a card that shows as answered never counts as waiting here.
  const verdicts = useMemo(() => collectVerdicts(chat.items), [chat.items]);
  const unanswerable = useMemo(
    () => unanswerableRequestIds(chat.items),
    [chat.items],
  );
  // A request row with neither — the chat screen's test for a card still waiting
  // on the user. The run row's own `awaiting` is the other half, OR'd in `status`.
  // A request whose verdict the daemon refused as expired is dropped too — the set
  // the hook keeps from the live acks, as the chat screen keeps its own.
  const openRequestOnScreen = useMemo(
    () =>
      foldItems.some((item) => {
        if (item.kind !== 'approval_request') {
          return false;
        }
        const id = payloadString(item.payload, 'id');
        return (
          id !== null &&
          !verdicts.has(id) &&
          !unanswerable.has(id) &&
          !chat.deadRequestIds.has(id)
        );
      }),
    [foldItems, verdicts, unanswerable, chat.deadRequestIds],
  );
  const durableEntries = useMemo(
    () =>
      foldDurableTranscript({
        items: chat.items,
        foldItems,
        anchorIds,
        runId,
        taskList: run?.taskList,
        collapseToolSteps,
      }),
    [chat.items, foldItems, anchorIds, runId, run?.taskList, collapseToolSteps],
  );
  const runStoppedAt =
    run !== null && isSettledRunStatus(run.status)
      ? settleMomentOf(run, chat.items)
      : null;
  const subagentRunning = useMemo(
    () =>
      anySubagentRunning(
        durableEntries,
        runStoppedAt,
        run?.subagentsOut ?? null,
      ),
    [durableEntries, runStoppedAt, run?.subagentsOut],
  );
  const status =
    run === null
      ? 'pending'
      : displayRunStatus({
          status: run.status,
          streaming: working,
          awaitingAnswer: run.awaiting != null || openRequestOnScreen,
          subagentRunning,
          heldForBackgroundWork: run.holdingFor > 0,
          shellsRunning: run.shellsOpen > 0,
          subagentsOut: run.subagentsOut > 0,
        });
  const runSettledAt =
    run !== null && isSettledRunStatus(status)
      ? settleMomentOf(run, chat.items)
      : null;
  const turnDurations = useMemo(
    () => scanTurns(chat.items).durations,
    [chat.items],
  );
  const { remember, recall, forget } = useContextReadings();
  const transcriptFigures = useMemo(
    () => computeAgentActivity(foldItems).get(CHAT_AGENT_KEY),
    [foldItems],
  );
  const ring = useMemo(
    () =>
      chatContextFigures({
        live: chat.liveText.get(CHAT_LIVE_KEY),
        run,
        transcript: transcriptFigures,
        itemsLoaded: chat.items.length > 0,
        recall: () => recall(runId),
      }),
    [chat.liveText, chat.items.length, recall, run, transcriptFigures],
  );
  useRememberedContextReading({
    runId,
    figures: ring,
    itemsLoaded: chat.items.length > 0,
    remember,
    forget,
  });
  const awaitingReading = chatContextAwaitingReading(ring.tokens, chat.items);

  // The run is the truth once it exists: a conversation carries the settings it
  // was created with, and the chips have to describe THAT rather than whatever
  // the panel was last set to for a different workflow. They are read when a run
  // is opened, and when a refused save leaves a chip with no save still answering
  // for it — not on every announce, which restates the row and would put back a
  // value a save is still carrying.
  const rowRef = useRef(run);
  useEffect(() => {
    rowRef.current = run;
  });
  // Set one chip from the values a save carried, or from the row read the same way.
  const applyChip = useCallback(
    (key: ChipKey, values: UpdateChatSettingsDto) => {
      switch (key) {
        case 'model':
          setModel(values.model ?? null);
          break;
        case 'effort':
          setEffort(values.effort ?? null);
          break;
        case 'contextWindow':
          setContextWindow(values.contextWindow ?? null);
          break;
        case 'approval':
          if (values.approval !== undefined) {
            setApproval(values.approval);
          }
          break;
        case 'modelParameters':
          setModelParameters(values.modelParameters ?? {});
          break;
        case 'configDir':
          setConfigDir(values.configDir ?? null);
          break;
      }
    },
    [],
  );
  const syncChips = useCallback(() => {
    const row = rowRef.current;
    if (row === null) {
      return;
    }
    setAgentKind((current) => row.agentKind ?? current);
    for (const key of CHIP_KEYS) {
      applyChip(key, rowValues(row));
    }
  }, [applyChip]);
  useEffect(() => {
    syncChips();
  }, [runId, syncChips]);
  // The saves in flight for each chip, and the newest one the daemon accepted —
  // see `applySettings`. Kept per run: the panel is keyed by slug, and a save
  // still answering for the run before must not write onto the one open now.
  const chipSaves = useRef(new Map<ChipKey, ChipSaves>());
  const saveSeq = useRef(0);
  const [chipsToResync, setChipsToResync] = useState<readonly ChipKey[]>([]);
  useEffect(() => {
    chipSaves.current = new Map();
  }, [runId]);
  // A refused save puts its chip back to the row once it has answered. This runs
  // after the commit that shows the row's latest value, so the row read is current.
  useEffect(() => {
    const row = rowRef.current;
    if (row === null) {
      return;
    }
    for (const key of chipsToResync) {
      applyChip(key, rowValues(row));
    }
  }, [chipsToResync, applyChip]);

  useEffect(() => {
    onWorkingChange(working);
  }, [working, onWorkingChange]);

  // The same setting the chat screen reads, so a tool step folds here as it does
  // in a thread. Read again on activation: the builder stays mounted while it is
  // not on screen, so a change made in Settings reaches the dock only this way.
  useEffect(() => {
    if (!active) {
      return;
    }
    void window.geniro.getSettings().then((s) => {
      setCollapseToolSteps(s.collapseToolSteps ?? false);
    });
  }, [active]);

  const awaiting = run?.awaiting ?? null;
  useEffect(() => {
    onAwaitingChange?.(awaiting);
  }, [awaiting, onAwaitingChange]);

  // Keyed on the COUNT rather than on a boolean: two turns in a row must reload
  // the canvas twice, and an effect on `working` going false cannot tell the
  // second settle from the first.
  const settledSeen = useRef(settledTurns);
  useEffect(() => {
    if (settledTurns !== settledSeen.current) {
      settledSeen.current = settledTurns;
      void onTurnSettled();
    }
  }, [settledTurns, onTurnSettled]);

  const agentApi = apis?.agents ?? null;
  const models = useAgentModels(agentApi, agentKind, configDir);
  const efforts = useAgentEfforts(agentApi, agentKind, model, configDir);
  const windows = useAgentContextWindows(agentApi, agentKind, model, configDir);
  const parameters = useAgentModelParameters(
    agentApi,
    agentKind,
    model,
    configDir,
  );
  const configDirCapability = configDirCapabilityFrom(
    capabilities,
    capabilitiesLoading,
  );
  const approvalCapability = useMemo(
    () => capabilities?.approvals.find((entry) => entry.agent === agentKind),
    [capabilities, agentKind],
  );

  /**
   * Apply one chip. Before a conversation exists this only seeds the create;
   * afterwards the run is patched, because a chip that moved and changed
   * nothing is worse than no chip at all.
   *
   * A save the daemon refuses leaves the run as it was, so its chip goes back to
   * the row — but only once no other save for that chip is still answering, since
   * a later save the user made is the newest choice. When the last save for a chip
   * answers, the chip takes the newest save the daemon ACCEPTED, in send order.
   */
  const applySettings = useCallback(
    (apply: () => void, patch: Parameters<typeof patchSettings>[0]) => {
      apply();
      if (run === null) {
        return;
      }
      saveSeq.current += 1;
      const seq = saveSeq.current;
      const sent = Object.keys(patch)
        .filter(isChipKey)
        .map((key) => {
          const batch: ChipSaves = chipSaves.current.get(key) ?? {
            pending: 0,
            newest: null,
          };
          batch.pending += 1;
          chipSaves.current.set(key, batch);
          return { key, batch };
        });
      void patchSettings(patch).then((saved) => {
        const refused: ChipKey[] = [];
        for (const { key, batch } of sent) {
          if (saved && (batch.newest === null || seq > batch.newest.seq)) {
            batch.newest = { seq, values: patch };
          }
          batch.pending -= 1;
          // A batch the panel no longer holds belongs to the run before this one.
          if (batch.pending > 0 || chipSaves.current.get(key) !== batch) {
            continue;
          }
          chipSaves.current.delete(key);
          if (batch.newest === null) {
            refused.push(key);
          } else {
            applyChip(key, batch.newest.values);
          }
        }
        if (refused.length > 0) {
          setChipsToResync(refused);
        }
      });
    },
    [run, patchSettings, applyChip],
  );
  const pickConfigDir = useCallback(async (): Promise<void> => {
    const chosen = await window.geniro.pickProjectFolder();
    if (chosen) {
      applySettings(() => setConfigDir(chosen), { configDir: chosen });
    }
  }, [applySettings]);

  /**
   * The transcript, folded EXACTLY as the chat screen folds it — tool groups,
   * turn blocks, sub-agent enclosures and call cards — with the live plane laid
   * over the top.
   *
   * It used to map `chat.items` one row per item, which is why this surface
   * looked nothing like the chat: every tool call was its own bare row, nothing
   * folded, and a running turn showed no streaming text and no spinner at all
   * (REPORTED as "сейчас там нет ни иконки загрузки, ничего"). Reusing the fold
   * rather than re-deriving one is also what keeps the two surfaces honest — a
   * row that looks wrong here looks wrong in the chat screen too.
   */
  const entries = useMemo<TranscriptEntry[]>(() => {
    // ONE agent, so the fallback that draws `Working… 12s` under a turn nobody
    // has streamed a word for is keyed by the chat sentinel — the same key the
    // daemon files a chat's own deltas under. An agent parked on an approval
    // card is waiting on the person, so no working row is drawn for it.
    const workingAgents =
      working && awaiting === null
        ? new Set([CHAT_LIVE_KEY])
        : new Set<string>();
    return withLiveText(durableEntries, chat.liveText, workingAgents, runId);
  }, [durableEntries, chat.liveText, working, awaiting, runId]);

  const transcriptRef = useRef<HTMLDivElement | null>(null);
  useEffect(() => {
    const box = transcriptRef.current;
    if (box !== null) {
      box.scrollTop = box.scrollHeight;
    }
    // The LIVE plane too, not only the durable rows: a streaming answer grows
    // the box without adding an item, and following only items left the tail
    // of what the agent was writing off the bottom of a 320px dock.
  }, [chat.items, chat.liveText]);

  const send = useCallback(async (): Promise<void> => {
    const text = draft.trim();
    const images = attachments.toWire();
    if (
      (text === '' && images.length === 0) ||
      working ||
      attachBusy ||
      runId === null ||
      sendingRef.current
    ) {
      return;
    }
    sendingRef.current = true;
    setComposeError(null);
    const owner = ownerRef.current;
    const sentKeys = attachments.attachments.map(
      (attachment) => attachment.key,
    );
    // The flush comes FIRST and is awaited: the agent reads the file, so a
    // canvas edit still sitting in the autosave debounce would be invisible to
    // the turn that is about to start — and would then be written on top of
    // whatever that turn produced.
    try {
      await onBeforeSend();
      if (owner !== ownerRef.current) {
        return;
      }
      const sent =
        images.length === 0
          ? await chat.send(text)
          : await chat.send(text, images);
      if (sent && owner === ownerRef.current) {
        setDraft((current) => (current === draft ? '' : current));
        attachments.clear(sentKeys);
      }
    } catch (err) {
      setComposeError(describeDaemonError(err));
    } finally {
      sendingRef.current = false;
    }
  }, [draft, attachments, working, attachBusy, runId, chat, onBeforeSend]);
  const error =
    composeError ?? chat.error ?? attachments.error ?? fileAttach.error;

  return (
    /* What a transcript row reaches for without being handed it — the SAME
       set the chat screen provides, so a row folded here reads and remembers
       exactly as it does there. `threadId` is answerable from this surface only
       for this conversation: a fold the reader presses here must not follow
       them into another workflow's. The sign-in, the retry and the direct line
       to a running call's callee have no meaning in a dock that runs one agent
       against one file, so they stay null. The sub-agent detail dialog and the
       call jumps need the chat screen's own transcript scroller and dialog, so
       they stay null here too.

       `artifactUrl` IS answerable, and has to be: this dock runs an ordinary
       chat, so the daemon offers its agent `show_artifact` like any other. A
       null here would let the agent spend a turn writing a page and hand the
       user a card saying it cannot be opened. */
    <ChatProviders
      threadId={runId}
      signIn={null}
      retry={null}
      callContext={null}
      callChannel={null}
      artifactUrl={artifactUrl}
      runSettledAt={runSettledAt}
      delegatesOut={run?.subagentsOut ?? null}
      collapseToolSteps={collapseToolSteps}
      runActivity={chat.activity}
      cardBacked={cardBacked}
      loadImage={loadMarkdownImage}
      loadMetrics={loadMetrics}
      turnDurations={turnDurations}
      revealCallBlock={null}
      revealCall={null}
      openSubagentDetail={null}
      loadAttachment={loadAttachment}>
      <aside
        hidden={hidden}
        className="relative flex shrink-0 flex-col border-t border-border bg-sidebar"
        style={{ height }}
        aria-label={`Change ${workflowName} with chat`}>
        <PanelResizeHandle
          edge="top"
          label="Resize the workflow chat panel"
          onMouseDown={startResize}
          value={height}
          min={minWidth}
          max={maxWidth}
          onResize={resizeTo}
        />
        <header className="flex items-center gap-2 px-3 pt-2 pb-1">
          <MessagesSquare className="size-3.5 shrink-0 text-muted-foreground" />
          <span className="truncate text-xs font-medium">Change with chat</span>
          <span className="truncate text-xs text-muted-foreground">
            {workflowName}
          </span>
          {run === null ? null : (
            <RunStatusBadge data-slot="workflow-chat-status" status={status} />
          )}
          {/* NO Stop here. It lives in the composer, where the chat screen keeps
            it and where the hand already is — REPORTED as "кнопочка «Стоп»
            должна быть в текстере, то есть те же самые компоненты, которые у
            нас есть уже". Two places to stop a turn is also two places for the
            two to disagree about whether there is one. */}
          <div className="ml-auto flex shrink-0 items-center gap-1">
            <Button
              type="button"
              variant="ghost"
              size="icon"
              className="size-6"
              aria-label="Start a new conversation"
              title="Throw this conversation away and start a new one"
              disabled={chat.run === null}
              onClick={() => void chat.discard()}>
              <Trash2 className="size-3.5 shrink-0" />
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="icon"
              className="size-6"
              aria-label="Hide the workflow chat panel"
              title="Hide — the conversation is kept"
              onClick={onClose}>
              <ChevronDown className="size-3.5 shrink-0" />
            </Button>
          </div>
        </header>

        <div
          ref={transcriptRef}
          data-slot="workflow-chat-transcript"
          className="min-h-0 flex-1 space-y-2 overflow-y-auto px-3 py-2">
          {chat.loading && chat.items.length === 0 ? (
            <p className="text-xs text-muted-foreground">Opening the chat…</p>
          ) : null}
          {/* Gated on the ENTRIES, not on the items: a turn that has started
              and streamed nothing durable yet still puts a working row on
              screen, and the invitation to ask for a change printed under it
              would be describing a conversation already in progress. */}
          {!chat.loading && entries.length === 0 ? (
            <p className="text-xs text-muted-foreground">
              Ask for a change — the agent edits this workflow&apos;s file and
              the canvas reloads when it is done.
            </p>
          ) : null}
          {/* An `approval_request` is intercepted here rather than left to the
            entry view, exactly as the chat screen intercepts it: the fold
            deliberately keeps that kind in the MAIN flow (a card folded into a
            collapsed block is a card nobody can see they must answer), and the
            row it draws is a CARD the panel has to wire its verdict channel
            into. Everything else goes through the shared renderer. */}
          {entries.map((entry) => (
            <TranscriptRow key={transcriptEntryKey(entry)}>
              {entry.type === 'item' &&
              entry.item.kind === 'approval_request' ? (
                <ApprovalRow
                  item={entry.item}
                  verdicts={verdicts}
                  unanswerable={unanswerable}
                  onRespond={chat.respond}
                />
              ) : (
                <TranscriptEntryView
                  entry={entry}
                  // ONE agent and no nodes, so its rows need no identity frame —
                  // the same exemption a 1:1 chat gets. The user's own messages
                  // keep theirs; the conversation still has two sides.
                  soloAgent
                  chatAgentName={chat.run?.agentKind ?? agentKind}
                />
              )}
            </TranscriptRow>
          ))}
        </div>

        <div className="space-y-1 px-3 pt-1 pb-2">
          {error === null ? null : <ErrorText>{error}</ErrorText>}
          <MessageComposer
            attachments={attachments.attachments}
            onRemoveAttachment={attachments.remove}
            onAttachFiles={fileAttach.attach}
            onPasteImages={attachments.addFromClipboard}
            textareaProps={{
              value: draft,
              rows: 2,
              disabled: chat.run === null,
              onChange: (event) => setDraft(event.target.value),
              onKeyDown: (event) => {
                if (isComposerSendKey(event)) {
                  event.preventDefault();
                  void send();
                }
              },
              'aria-label': 'Ask for a workflow change',
              placeholder:
                'Describe the change — add a reviewer, wire it to the coder…',
            }}
            actions={
              working ? (
                <Button
                  type="button"
                  variant="destructive"
                  size="icon"
                  className="size-8 rounded-full"
                  aria-label="Stop"
                  title="Stop the current turn"
                  onClick={() => void chat.cancel()}>
                  <Square className="size-3 shrink-0" />
                </Button>
              ) : (
                <Button
                  type="button"
                  size="icon"
                  className="size-8 rounded-full"
                  aria-label="Send"
                  title={attachBusy ? attachBusyTitle : 'Send'}
                  disabled={!hasContent || chat.run === null || attachBusy}
                  onClick={() => void send()}>
                  <ArrowUp className="size-3.5 shrink-0" />
                </Button>
              )
            }>
            {chat.run === null ? (
              <TargetSelect
                value={agentKind}
                workflows={NO_WORKFLOW_TARGETS}
                cliDetections={null}
                aria-label="Agent for this workflow chat"
                onChange={(target) => setAgentKind(target as AgentKind)}
              />
            ) : null}
            <ModelSettingsSelect
              agentKind={agentKind}
              models={models.models}
              model={model}
              onModelChange={(next) =>
                applySettings(
                  () => {
                    setModel(next);
                    // A window and the model's other parameters belong to the
                    // model that offered them, so they go with it.
                    setContextWindow(null);
                    setModelParameters({});
                  },
                  {
                    model: next,
                    contextWindow: null,
                    modelParameters: null,
                  },
                )
              }
              efforts={efforts.efforts}
              effort={effort}
              onEffortChange={(next) =>
                applySettings(() => setEffort(next), { effort: next })
              }
              approvalCapability={approvalCapability}
              approval={approval}
              withheld={PLAN_WITHHELD}
              onApprovalChange={(next) =>
                applySettings(() => setApproval(next), { approval: next })
              }
              windows={windows.windows}
              contextWindow={contextWindow}
              onContextWindowChange={(next) =>
                applySettings(() => setContextWindow(next), {
                  contextWindow: next,
                })
              }
              parameters={parameters.parameters}
              parameterValues={modelParameters}
              onParameterChange={(parameterId, value) => {
                const next = withModelParameter(
                  modelParameters,
                  parameterId,
                  value,
                );
                applySettings(() => setModelParameters(next), {
                  modelParameters: next,
                });
              }}
              configDir={configDir}
              recentConfigDirs={recentConfigDirs[agentKind] ?? []}
              configProfiles={configProfiles.filter(
                (profile) => profile.agent === agentKind,
              )}
              configDirUnavailableReason={configDirCapability.unavailableReasonFor(
                agentKind,
              )}
              onConfigDirChange={(next) =>
                applySettings(() => setConfigDir(next), { configDir: next })
              }
              settingsLoading={
                efforts.loading || windows.loading || parameters.loading
              }
              loading={models.loading}
              nextTurnOnly={working}
              windowTokens={ring.window}
              autoCompactPercent={run?.autoCompactPercent ?? null}
              onAutoCompactChange={
                run === null
                  ? undefined
                  : (percent) =>
                      void patchSettings({ autoCompactPercent: percent })
              }
              onBrowseConfigDir={() => void pickConfigDir()}
            />
            {run === null ? null : (
              <ContextMeter
                className="ml-1.5"
                runId={run.id}
                contextTokens={ring.tokens}
                contextWindowTokens={ring.window}
                awaitingReading={awaitingReading}
                live={isWorkingRunStatus(status)}
                side="top"
              />
            )}
          </MessageComposer>
        </div>
      </aside>
    </ChatProviders>
  );
}

/**
 * One approval or question card in the panel.
 *
 * The chat screen composes exactly this, and the three exclusions are read from
 * the same helpers it reads them from — a card that shows as answered must not
 * still be answerable, on either surface.
 */
function ApprovalRow({
  item,
  verdicts,
  unanswerable,
  onRespond,
}: {
  item: ChatItem;
  verdicts: ReturnType<typeof collectVerdicts>;
  unanswerable: ReadonlySet<string>;
  onRespond: (requestId: string, allow: boolean, answer?: string) => void;
}): React.JSX.Element | null {
  const requestId = payloadString(item.payload, 'id');
  if (requestId === null) {
    return null;
  }
  const settled = verdicts.get(requestId) ?? null;
  return (
    <ApprovalCard
      toolName={payloadString(item.payload, 'toolName') ?? 'tool'}
      input={(item.payload as { input?: unknown } | null)?.input ?? null}
      questions={(item.payload as { questions?: unknown } | null)?.questions}
      requestId={requestId}
      verdict={settled?.allow ?? null}
      answer={settled?.answer ?? null}
      expired={unanswerable.has(requestId)}
      onRespond={(allow, answer) => onRespond(requestId, allow, answer)}
    />
  );
}
