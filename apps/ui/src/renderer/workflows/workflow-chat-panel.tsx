import {
  useWorkflowChat,
  type WorkflowChatSettings,
} from './use-workflow-chat';

/** No workflow is ever a target here — this chat EDITS one. */
const NO_WORKFLOW_TARGETS = [] as const;

/**
 * The agent a workflow chat opens with when the user has picked none.
 *
 * Its edits are file edits it was asked to make, so `acceptEdits` is the mode
 * that matches what the panel is for — `ask` would put a card in front of every
 * write, and `auto` gives away more than the job needs.
 */
const DEFAULT_APPROVAL: ChatApprovalMode = 'acceptEdits';

/**
 * The chat docked under the workflow builder: the user describes a change and
 * an agent makes it in the workflow's own YAML file.
 *
 * It mirrors the terminal panel's dock — an `<aside>` with a resize handle, a
 * header and a collapse control — so the app's two bottom panels are one thing
 * to learn. What it holds is the chat screen's own parts: the transcript rows,
 * the approval card, the composer shell and its chips. Nothing here re-draws a
 * message or an option list; if a row looks wrong, it looks wrong in the chat
 * screen too.
 *
 * MOUNTED only while it is open, unlike the terminal panel — a shell has a
 * process and a scrollback to lose, and this has a conversation the daemon
 * holds and the hook reloads.
 */
export function WorkflowChatPanel({
  slug,
  workflowName,
  apis,
  handle,
  client,
  capabilities,
  capabilitiesLoading,
  recentConfigDirs,
  onClose,
  onBeforeSend,
  onWorkingChange,
  onTurnSettled,
}: {
  slug: string;
  workflowName: string;
  apis: DaemonApis | null;
  /** This launch's daemon — what a published page's URL is built from. */
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  recentConfigDirs: readonly string[];
  onClose: () => void;
  /**
   * Run before a message is handed to the daemon — the builder writes any
   * pending canvas edit first, so the agent reads the graph the user is
   * looking at rather than the one last autosaved.
   */
  onBeforeSend: () => Promise<void>;
  /**
   * A turn started or ended. The builder suspends its autosave while one runs,
   * so the agent's write and the canvas cannot overwrite each other.
   */
  onWorkingChange: (working: boolean) => void;
  /** A turn ended — the builder re-reads the workflow the agent may have edited. */
  onTurnSettled: () => void | Promise<void>;
}): React.JSX.Element {
  const {
    width: height,
    minWidth,
    maxWidth,
    startResize,
    resizeTo,
  } = usePanelWidth({
    storageKey: 'workflowChat.panelHeight',
    defaultWidth: 320,
    minWidth: 180,
    maxWidth: 900,
    handleEdge: 'top',
  });

  // The chips, before a conversation exists. Once one does they describe the
  // run and every change is patched onto it — see `applySettings` below.
  const [agentKind, setAgentKind] = useState<AgentKind>('claude');
  const [model, setModel] = useState<string | null>(null);
  const [effort, setEffort] = useState<string | null>(null);
  const [contextWindow, setContextWindow] = useState<string | null>(null);
  const [approval, setApproval] = useState<ChatApprovalMode>(DEFAULT_APPROVAL);
  const [modelParameters, setModelParameters] = useState<
    Record<string, string>
  >({});
  const [configDir, setConfigDir] = useState<string | null>(null);
  const [draft, setDraft] = useState('');

  const settings = useMemo<WorkflowChatSettings>(
    () => ({
      agentKind,
      approval,
      ...(model === null ? {} : { model }),
      ...(effort === null ? {} : { effort }),
      ...(contextWindow === null ? {} : { contextWindow }),
      ...(configDir === null ? {} : { configDir }),
      ...(Object.keys(modelParameters).length === 0 ? {} : { modelParameters }),
    }),
    [
      agentKind,
      approval,
      model,
      effort,
      contextWindow,
      configDir,
      modelParameters,
    ],
  );

  const chat = useWorkflowChat({ slug, apis, client, settings });
  const runId = chat.run?.id ?? null;
  /** How a page this dock's agent published is addressed — see `Chats.tsx`. */
  const artifactUrl = useMemo<ArtifactUrlBuilder | null>(() => {
    if (handle === null || runId === null) {
      return null;
    }
    return (artifact) => artifactPageUrl(handle, runId, artifact);
  }, [handle, runId]);
  const { run, working, settledTurns, patchSettings } = chat;

  // The run is the truth once it exists: a conversation carries the settings it
  // was created with, and the chips have to describe THAT rather than whatever
  // the panel was last set to for a different workflow.
  useEffect(() => {
    if (run === null) {
      return;
    }
    setAgentKind((current) => run.agentKind ?? current);
    setModel(run.model ?? null);
    setEffort(run.effort ?? null);
    setContextWindow(run.contextWindow ?? null);
    setApproval((current) => run.approval ?? current);
    setConfigDir(run.configDir ?? null);
  }, [run]);

  useEffect(() => {
    onWorkingChange(working);
  }, [working, onWorkingChange]);

  // Keyed on the COUNT rather than on a boolean: two turns in a row must reload
  // the canvas twice, and an effect on `working` going false cannot tell the
  // second settle from the first.
  const settledSeen = useRef(settledTurns);
  useEffect(() => {
    if (settledTurns !== settledSeen.current) {
      settledSeen.current = settledTurns;
      void onTurnSettled();
    }
  }, [settledTurns, onTurnSettled]);

  const agentApi = apis?.agents ?? null;
  const models = useAgentModels(agentApi, agentKind, configDir);
  const efforts = useAgentEfforts(agentApi, agentKind, model, configDir);
  const windows = useAgentContextWindows(agentApi, agentKind, model, configDir);
  const parameters = useAgentModelParameters(
    agentApi,
    agentKind,
    model,
    configDir,
  );
  const configDirCapability = configDirCapabilityFrom(
    capabilities,
    capabilitiesLoading,
  );
  const approvalModes = useMemo(
    () =>
      capabilities?.approvals.find((entry) => entry.agent === agentKind)
        ?.modes ?? null,
    [capabilities, agentKind],
  );

  /**
   * Apply one chip. Before a conversation exists this only seeds the create;
   * afterwards the run is patched, because a chip that moved and changed
   * nothing is worse than no chip at all.
   */
  const applySettings = useCallback(
    (apply: () => void, patch: Parameters<typeof patchSettings>[0]) => {
      apply();
      if (run !== null) {
        void patchSettings(patch);
      }
    },
    [run, patchSettings],
  );

  /**
   * The transcript, folded EXACTLY as the chat screen folds it — tool groups,
   * turn blocks, sub-agent enclosures and call cards — with the live plane laid
   * over the top.
   *
   * It used to map `chat.items` one row per item, which is why this surface
   * looked nothing like the chat: every tool call was its own bare row, nothing
   * folded, and a running turn showed no streaming text and no spinner at all
   * (REPORTED as "сейчас там нет ни иконки загрузки, ничего"). Reusing the fold
   * rather than re-deriving one is also what keeps the two surfaces honest — a
   * row that looks wrong here looks wrong in the chat screen too.
   */
  const entries = useMemo<TranscriptEntry[]>(() => {
    // ONE agent, so the fallback that draws `Working… 12s` under a turn nobody
    // has streamed a word for is keyed by the chat sentinel — the same key the
    // daemon files a chat's own deltas under.
    const workingAgents = working
      ? new Set([CHAT_LIVE_KEY])
      : new Set<string>();
    return withLiveText(
      groupTranscript(chat.items),
      chat.liveText,
      workingAgents,
    );
  }, [chat.items, chat.liveText, working]);

  const transcriptRef = useRef<HTMLDivElement | null>(null);
  useEffect(() => {
    const box = transcriptRef.current;
    if (box !== null) {
      box.scrollTop = box.scrollHeight;
    }
    // The LIVE plane too, not only the durable rows: a streaming answer grows
    // the box without adding an item, and following only items left the tail
    // of what the agent was writing off the bottom of a 320px dock.
  }, [chat.items, chat.liveText]);

  const verdicts = useMemo(() => collectVerdicts(chat.items), [chat.items]);
  const unanswerable = useMemo(
    () => unanswerableRequestIds(chat.items),
    [chat.items],
  );

  const send = useCallback(async (): Promise<void> => {
    const text = draft.trim();
    if (text === '' || working) {
      return;
    }
    setDraft('');
    // The flush comes FIRST and is awaited: the agent reads the file, so a
    // canvas edit still sitting in the autosave debounce would be invisible to
    // the turn that is about to start — and would then be written on top of
    // whatever that turn produced.
    await onBeforeSend();
    await chat.send(text);
  }, [draft, working, chat, onBeforeSend]);

  return (
    /* What a transcript row reaches for without being handed it — the SAME
       component the chat screen wraps its own tree in, so a row folded here
       reads and remembers exactly as it does there. Only `threadId` is
       answerable from this surface: a fold the reader presses in this dock is
       a fact about THIS conversation and must not follow them into another
       workflow's. The other three are the chat screen's own (sign-in, retry,
       and the direct line to a running call's callee) and have no meaning in a
       dock that runs one agent against one file.

       `artifactUrl` IS answerable, and has to be: this dock runs an ordinary
       chat, so the daemon offers its agent `show_artifact` like any other. A
       null here would let the agent spend a turn writing a page and hand the
       user a card saying it cannot be opened. */
    <ChatProviders
      threadId={chat.run?.id ?? null}
      signIn={null}
      retry={null}
      callContext={null}
      callChannel={null}
      artifactUrl={artifactUrl}>
      <aside
        className="relative flex shrink-0 flex-col border-t border-border bg-sidebar"
        style={{ height }}
        aria-label={`Change ${workflowName} with chat`}>
        <PanelResizeHandle
          edge="top"
          label="Resize the workflow chat panel"
          onMouseDown={startResize}
          value={height}
          min={minWidth}
          max={maxWidth}
          onResize={resizeTo}
        />
        <header className="flex items-center gap-2 px-3 pt-2 pb-1">
          <MessagesSquare className="size-3.5 shrink-0 text-muted-foreground" />
          <span className="truncate text-xs font-medium">Change with chat</span>
          <span className="truncate text-xs text-muted-foreground">
            {workflowName}
          </span>
          {/* NO Stop here. It lives in the composer, where the chat screen keeps
            it and where the hand already is — REPORTED as "кнопочка «Стоп»
            должна быть в текстере, то есть те же самые компоненты, которые у
            нас есть уже". Two places to stop a turn is also two places for the
            two to disagree about whether there is one. */}
          <div className="ml-auto flex shrink-0 items-center gap-1">
            <Button
              type="button"
              variant="ghost"
              size="icon"
              className="size-6"
              aria-label="Start a new conversation"
              title="Throw this conversation away and start a new one"
              disabled={chat.run === null}
              onClick={() => void chat.discard()}>
              <Trash2 className="size-3.5 shrink-0" />
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="icon"
              className="size-6"
              aria-label="Hide the workflow chat panel"
              title="Hide — the conversation is kept"
              onClick={onClose}>
              <ChevronDown className="size-3.5 shrink-0" />
            </Button>
          </div>
        </header>

        <div
          ref={transcriptRef}
          data-slot="workflow-chat-transcript"
          className="min-h-0 flex-1 space-y-2 overflow-y-auto px-3 py-2">
          {chat.loading && chat.items.length === 0 ? (
            <p className="text-xs text-muted-foreground">Opening the chat…</p>
          ) : null}
          {/* Gated on the ENTRIES, not on the items: a turn that has started
              and streamed nothing durable yet still puts a working row on
              screen, and the invitation to ask for a change printed under it
              would be describing a conversation already in progress. */}
          {!chat.loading && entries.length === 0 ? (
            <p className="text-xs text-muted-foreground">
              Ask for a change — the agent edits this workflow&apos;s file and
              the canvas reloads when it is done.
            </p>
          ) : null}
          {/* An `approval_request` is intercepted here rather than left to the
            entry view, exactly as the chat screen intercepts it: the fold
            deliberately keeps that kind in the MAIN flow (a card folded into a
            collapsed block is a card nobody can see they must answer), and the
            row it draws is a CARD the panel has to wire its verdict channel
            into. Everything else goes through the shared renderer. */}
          {entries.map((entry) =>
            entry.type === 'item' && entry.item.kind === 'approval_request' ? (
              <ApprovalRow
                key={entry.item.id}
                item={entry.item}
                verdicts={verdicts}
                unanswerable={unanswerable}
                onRespond={chat.respond}
              />
            ) : (
              <TranscriptEntryView
                key={transcriptEntryKey(entry)}
                entry={entry}
                // ONE agent and no nodes, so its rows need no identity frame —
                // the same exemption a 1:1 chat gets. The user's own messages
                // keep theirs; the conversation still has two sides.
                soloAgent
                chatAgentName={chat.run?.agentKind ?? agentKind}
              />
            ),
          )}
        </div>

        <div className="space-y-1 px-3 pt-1 pb-2">
          {chat.error === null ? null : <ErrorText>{chat.error}</ErrorText>}
          <ComposerCard>
            <Textarea
              value={draft}
              onChange={(event) => setDraft(event.target.value)}
              onKeyDown={(event) => {
                if (isComposerSendKey(event)) {
                  event.preventDefault();
                  void send();
                }
              }}
              aria-label="Ask for a workflow change"
              placeholder="Describe the change — add a reviewer, wire it to the coder…"
              className={cn(
                'resize-none border-0 bg-transparent px-3 py-2 text-sm shadow-none focus-visible:ring-0',
                COMPOSER_TEXTAREA_GROWTH,
              )}
            />
            <div className="flex flex-wrap items-center gap-1 px-2 pb-2">
              {chat.run === null ? (
                <TargetSelect
                  value={agentKind}
                  workflows={NO_WORKFLOW_TARGETS}
                  cliDetections={null}
                  aria-label="Agent for this workflow chat"
                  onChange={(target) => setAgentKind(target as AgentKind)}
                />
              ) : (
                <span className="px-2 text-xs text-muted-foreground">
                  {chat.run.agentKind ?? 'agent'}
                </span>
              )}
              <ModelSettingsSelect
                agentKind={agentKind}
                models={models.models}
                model={model}
                onModelChange={(next) =>
                  applySettings(
                    () => {
                      setModel(next);
                      // A window and the model's other parameters belong to the
                      // model that offered them, so they go with it.
                      setContextWindow(null);
                      setModelParameters({});
                    },
                    { model: next, contextWindow: null, modelParameters: null },
                  )
                }
                efforts={efforts.efforts}
                effort={effort}
                onEffortChange={(next) =>
                  applySettings(() => setEffort(next), { effort: next })
                }
                approvalModes={approvalModes}
                approval={approval}
                planSupported={false}
                onApprovalChange={(next) =>
                  applySettings(() => setApproval(next), { approval: next })
                }
                windows={windows.windows}
                contextWindow={contextWindow}
                onContextWindowChange={(next) =>
                  applySettings(() => setContextWindow(next), {
                    contextWindow: next,
                  })
                }
                parameters={parameters.parameters}
                parameterValues={modelParameters}
                onParameterChange={(parameterId, value) => {
                  const next = withModelParameter(
                    modelParameters,
                    parameterId,
                    value,
                  );
                  applySettings(() => setModelParameters(next), {
                    modelParameters: next,
                  });
                }}
                configDir={configDir}
                recentConfigDirs={recentConfigDirs}
                configDirUnavailableReason={configDirCapability.unavailableReasonFor(
                  agentKind,
                )}
                onConfigDirChange={(next) =>
                  applySettings(() => setConfigDir(next), { configDir: next })
                }
                settingsLoading={
                  efforts.loading || windows.loading || parameters.loading
                }
                loading={models.loading}
              />
              {/* Send and Stop are ONE slot, the chat screen's own arrangement:
                while a turn runs the only thing to do here is stop it, and the
                Stop is red because it is the one control in a composer that
                destroys work. Moved down from the panel header on report —
                "кнопочка «Стоп» должна быть в текстере". */}
              {working ? (
                <Button
                  type="button"
                  variant="destructive"
                  size="icon"
                  className="ml-auto size-7 rounded-full"
                  aria-label="Stop"
                  title="Stop the current turn"
                  onClick={() => void chat.cancel()}>
                  <Square className="size-3 shrink-0" />
                </Button>
              ) : (
                <Button
                  type="button"
                  size="icon"
                  className="ml-auto size-7 rounded-full"
                  aria-label="Send"
                  title="Send"
                  disabled={draft.trim() === '' || chat.run === null}
                  onClick={() => void send()}>
                  <ArrowUp className="size-3.5 shrink-0" />
                </Button>
              )}
            </div>
          </ComposerCard>
        </div>
      </aside>
    </ChatProviders>
  );
}

/**
 * One approval or question card in the panel.
 *
 * The chat screen composes exactly this, and the three exclusions are read from
 * the same helpers it reads them from — a card that shows as answered must not
 * still be answerable, on either surface.
 */
function ApprovalRow({
  item,
  verdicts,
  unanswerable,
  onRespond,
}: {
  item: ChatItem;
  verdicts: ReturnType<typeof collectVerdicts>;
  unanswerable: ReadonlySet<string>;
  onRespond: (requestId: string, allow: boolean, answer?: string) => void;
}): React.JSX.Element | null {
  const requestId = payloadString(item.payload, 'id');
  if (requestId === null) {
    return null;
  }
  const settled = verdicts.get(requestId) ?? null;
  return (
    <ApprovalCard
      toolName={payloadString(item.payload, 'toolName') ?? 'tool'}
      input={(item.payload as { input?: unknown } | null)?.input ?? null}
      verdict={settled?.allow ?? null}
      answer={settled?.answer ?? null}
      expired={unanswerable.has(requestId)}
      onRespond={(allow, answer) => onRespond(requestId, allow, answer)}
    />
  );
}
