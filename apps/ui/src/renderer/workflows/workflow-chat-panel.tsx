import { ChevronDown, MessagesSquare, Trash2 } from 'lucide-react';
import { useMemo, useState } from 'react';

import type {
  CliKind,
  ConfigProfile,
  DaemonHandle,
} from '../../shared/contracts';
import { CLI_KINDS } from '../../shared/contracts';
import type {
  CapabilitiesDto,
  RunAwaiting,
  StartWorkflowChatDto,
} from '../autogenerated';
import { type ChipValues, HostedChat } from '../chats/hosted-chat';
import { RunStatusBadge } from '../chats/run-status';
import { PanelResizeHandle, usePanelWidth } from '../components/panel-resize';
import { Button } from '../components/ui/button';
import type { DaemonApis } from '../daemon-api';
import type { DaemonClient } from '../daemon-client';
import { useWorkflowChat } from './use-workflow-chat';

/**
 * The agent a workflow chat opens with when the user has picked none, and the
 * approval: its saves are edits of the workflow file it was asked to make, so
 * `acceptEdits` is the mode that matches what the panel is for — the daemon
 * approves the save there as it would a file edit, `ask` would put a card in
 * front of every save, and `auto` gives away more than the job needs. A CLI
 * that does not offer it opens on its own default instead; the daemon narrows
 * it.
 */
const FIRST_CHIPS: ChipValues = {
  agentKind: CLI_KINDS[0]!,
  approval: 'acceptEdits',
  model: null,
  effort: null,
  contextWindow: null,
  modelParameters: {},
  configDir: null,
};

/** The create's settings, as the draft chips name them. */
function chipsAsSettings(chips: ChipValues): StartWorkflowChatDto {
  const {
    agentKind,
    approval,
    model,
    effort,
    contextWindow,
    configDir,
    modelParameters,
  } = chips;
  return {
    agentKind,
    approval,
    ...(model === null ? {} : { model }),
    ...(effort === null ? {} : { effort }),
    ...(contextWindow === null ? {} : { contextWindow }),
    ...(configDir === null ? {} : { configDir }),
    ...(Object.keys(modelParameters).length === 0 ? {} : { modelParameters }),
  };
}

/**
 * The chat docked under the workflow builder: the user describes a change and
 * an agent makes it in the workflow's own YAML file.
 *
 * It mirrors the terminal panel's dock — an `<aside>` with a resize handle, a
 * header and a collapse control — so the app's two bottom panels are one thing
 * to learn. What it holds is a hosted chat (`HostedChat`): the chat screen's
 * own transcript rows, approval card, composer shell and chips.
 *
 * Once opened it stays MOUNTED while the builder holds that workflow and is
 * only HIDDEN when closed, like the terminal panel — not for a scrollback, but
 * for the two reports it owes the builder. Unmounted, a turn still running
 * when the dock was closed would take its `working` report and its settle
 * with it: the builder's autosave would stay suspended for good (every later
 * canvas edit lost on leaving) and the agent's own edit would never be
 * reloaded, so the next canvas save would write over it.
 */
export function WorkflowChatPanel({
  slug,
  workflowName,
  apis,
  handle,
  client,
  capabilities,
  capabilitiesLoading,
  recentConfigDirs,
  configProfiles,
  hidden = false,
  initialAgent,
  initialDraft = '',
  active = true,
  onClose,
  onBeforeSend,
  onWorkingChange,
  onAwaitingChange,
  onTurnSettled,
}: {
  slug: string;
  workflowName: string;
  apis: DaemonApis | null;
  /** This launch's daemon — what a published page's URL is built from. */
  handle: DaemonHandle | null;
  client: DaemonClient | null;
  capabilities: CapabilitiesDto | null;
  capabilitiesLoading: boolean;
  /** PER CLI: each keeps a different layout in its directory. */
  recentConfigDirs: Partial<Record<CliKind, readonly string[]>>;
  /** The user's named config directories — the WHOLE list; filtered to this panel's own agent below. */
  configProfiles: readonly ConfigProfile[];
  /** Closed by the user but still following its conversation — see above. */
  hidden?: boolean;
  initialAgent?: CliKind;
  initialDraft?: string;
  /** Whether the builder is on screen. Its settings are read again when it is. */
  active?: boolean;
  onClose: () => void;
  /**
   * Run before a message is handed to the daemon — the builder writes any
   * pending canvas edit first, so the agent reads the graph the user is
   * looking at rather than the one last autosaved.
   */
  onBeforeSend: () => Promise<unknown>;
  /**
   * A turn started or ended. The builder suspends its autosave while one runs,
   * so the agent's write and the canvas cannot overwrite each other.
   */
  onWorkingChange: (working: boolean) => void;
  /**
   * The agent is waiting on the user — a question or an approval card — or no
   * longer is. The dock can be HIDDEN while its turn waits, so the builder
   * marks its toggle from this; nothing else on screen would say so.
   */
  onAwaitingChange?: (awaiting: RunAwaiting | null) => void;
  /** A turn ended — the builder re-reads the workflow the agent may have edited. */
  onTurnSettled: () => void | Promise<void>;
}): React.JSX.Element {
  const {
    width: height,
    minWidth,
    maxWidth,
    startResize,
    resizeTo,
  } = usePanelWidth({
    storageKey: 'workflowChat.panelHeight',
    defaultWidth: 320,
    minWidth: 180,
    maxWidth: 900,
    handleEdge: 'top',
  });

  // The chips' values before a conversation exists: what the create starts
  // with. Held here because the open reads them (`useWorkflowChat`).
  const [draftChips, setDraftChips] = useState<ChipValues>(() => ({
    ...FIRST_CHIPS,
    agentKind: initialAgent ?? FIRST_CHIPS.agentKind,
  }));
  const settings = useMemo(() => chipsAsSettings(draftChips), [draftChips]);
  const chat = useWorkflowChat({ slug, apis, client, settings });

  return (
    <aside
      hidden={hidden}
      className="relative flex shrink-0 flex-col border-t border-border bg-sidebar"
      style={{ height }}
      aria-label={`Change ${workflowName} with chat`}>
      <PanelResizeHandle
        edge="top"
        label="Resize the workflow chat panel"
        onMouseDown={startResize}
        value={height}
        min={minWidth}
        max={maxWidth}
        onResize={resizeTo}
      />
      <HostedChat
        chat={chat}
        ownerKey={slug}
        apis={apis}
        handle={handle}
        capabilities={capabilities}
        capabilitiesLoading={capabilitiesLoading}
        recentConfigDirs={recentConfigDirs}
        configProfiles={configProfiles}
        draftChips={draftChips}
        onDraftChipsChange={setDraftChips}
        initialDraft={initialDraft}
        active={active}
        transcriptSlot="workflow-chat-transcript"
        emptyText="Ask for a change — the agent edits this workflow's file and the canvas reloads when it is done."
        composerLabel="Ask for a workflow change"
        composerPlaceholder="Describe the change — add a reviewer, wire it to the coder…"
        onBeforeSend={onBeforeSend}
        onWorkingChange={onWorkingChange}
        onAwaitingChange={onAwaitingChange}
        onTurnSettled={onTurnSettled}
        header={({ run, status }) => (
          <header className="flex items-center gap-2 px-3 pt-2 pb-1">
            <MessagesSquare className="size-3.5 shrink-0 text-muted-foreground" />
            <span className="truncate text-xs font-medium">
              Change with chat
            </span>
            <span className="truncate text-xs text-muted-foreground">
              {workflowName}
            </span>
            {run === null ? null : (
              <RunStatusBadge
                data-slot="workflow-chat-status"
                status={status}
              />
            )}
            {/* NO Stop here. It lives in the composer, where the chat screen
              keeps it and where the hand already is — REPORTED as "кнопочка
              «Стоп» должна быть в текстере, то есть те же самые компоненты,
              которые у нас есть уже". Two places to stop a turn is also two
              places for the two to disagree about whether there is one. */}
            <div className="ml-auto flex shrink-0 items-center gap-1">
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-6"
                aria-label="Start a new conversation"
                title="Throw this conversation away and start a new one"
                disabled={run === null}
                onClick={() => void chat.discard()}>
                <Trash2 className="size-3.5 shrink-0" />
              </Button>
              <Button
                type="button"
                variant="ghost"
                size="icon"
                className="size-6"
                aria-label="Hide the workflow chat panel"
                title="Hide — the conversation is kept"
                onClick={onClose}>
                <ChevronDown className="size-3.5 shrink-0" />
              </Button>
            </div>
          </header>
        )}
      />
    </aside>
  );
}
