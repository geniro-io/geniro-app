// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import type { WorkflowSummaryDto as WorkflowSummary } from '../autogenerated';
import { WorkflowRow } from './workflow-row';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

const SUMMARY: WorkflowSummary = {
  slug: 'review-team',
  name: 'Review Team',
  description: 'Coder then reviewer',
  nodeCount: 3,
  edgeCount: 2,
  agentCounts: [
    { kind: 'claude', count: 2 },
    { kind: 'cursor-agent', count: 1 },
  ],
  updatedAt: new Date().toISOString(),
};

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  vi.restoreAllMocks();
});

function render(
  summary: WorkflowSummary,
  onOpen: () => void = vi.fn(),
  onDelete: () => void | Promise<void> = vi.fn(),
): HTMLElement {
  act(() => {
    root.render(
      <ul>
        <WorkflowRow summary={summary} onOpen={onOpen} onDelete={onDelete} />
      </ul>,
    );
  });
  const el = container.querySelector<HTMLElement>(
    `button[aria-label="Open ${summary.name}"]`,
  );
  if (!el) {
    throw new Error('WorkflowRow did not render a clickable element');
  }
  return el;
}

function deleteButton(): HTMLButtonElement {
  const el = container.querySelector<HTMLButtonElement>(
    `[aria-label="Delete ${SUMMARY.name}"]`,
  );
  if (!el) {
    throw new Error('WorkflowRow did not render a delete button');
  }
  return el;
}

/** One click on the card's delete control, as a user's would bubble. */
function clickDelete(): void {
  act(() => {
    deleteButton().dispatchEvent(new MouseEvent('click', { bubbles: true }));
  });
}

describe('WorkflowRow', () => {
  it('shows the name, description, agent breakdown, and node/edge counts', () => {
    render(SUMMARY);
    const text = container.textContent ?? '';
    expect(text).toContain('Review Team');
    expect(text).toContain('Coder then reviewer');
    // The agent breakdown is the "how many agents" signal — a real tally per
    // kind, not just the node count.
    expect(text).toContain('claude ×2');
    expect(text).toContain('cursor-agent ×1');
    expect(text).toContain('3 nodes');
    expect(text).toContain('2 edges');
  });

  it('pluralizes a single node/edge without a trailing "s"', () => {
    // Read the whole row, not `render`'s return: that is the ACTIVATION
    // button, which is layered under the content and holds no text of its own.
    render({ ...SUMMARY, nodeCount: 1, edgeCount: 1 });
    const text = container.textContent ?? '';
    expect(text).toContain('1 node');
    expect(text).not.toContain('1 nodes');
    expect(text).toContain('1 edge');
    expect(text).not.toContain('1 edges');
  });

  it('falls back to "No description" when there is none', () => {
    render({ ...SUMMARY, description: null });
    expect(container.textContent ?? '').toContain('No description');
  });

  it('activates from a REAL <button>, so the platform supplies Enter/Space', () => {
    // The tile this replaced was a div wearing `role="button"` with a
    // hand-rolled Enter/Space keydown handler — and a nested delete button
    // inside it, which ARIA forbids and which needed an event dam to survive.
    // The row is `NavListItem`'s overlay button instead: keyboard activation
    // is the element's, not ours, and delete is its sibling.
    //
    // jsdom does not synthesize a click from a keydown, so a keyboard
    // assertion here could only ever re-test jsdom. What IS ours to pin is
    // the element type — revert to a role-bearing div and this fails.
    const onOpen = vi.fn();
    const el = render(SUMMARY, onOpen);

    expect(el.tagName).toBe('BUTTON');
    expect(el.getAttribute('role')).toBeNull();

    act(() => {
      el.dispatchEvent(new MouseEvent('click', { bubbles: true }));
    });
    expect(onOpen).toHaveBeenCalledTimes(1);
  });

  it('keeps the delete control OUTSIDE the activation surface', () => {
    // The structural half of the same fix: nothing interactive may be a
    // descendant of the activation button. Nesting them is what made the
    // event dam necessary in the first place.
    render(SUMMARY);
    const activate = container.querySelector('button[aria-label^="Open "]')!;
    expect(activate.querySelector('button')).toBeNull();
    expect(activate.contains(deleteButton())).toBe(false);
  });
});

describe('WorkflowRow — delete', () => {
  it('asks the page to delete — the row itself deletes nothing', () => {
    // The row only REQUESTS deletion; the page confirms in a modal. So one
    // click must reach onDelete (no in-row arming step swallowing it).
    const onDelete = vi.fn();
    render(SUMMARY, vi.fn(), onDelete);

    clickDelete();
    expect(onDelete).toHaveBeenCalledTimes(1);
  });

  it('never opens the workflow while deleting it', () => {
    // The whole row is a click target, so a delete click that found its way to
    // onOpen would drop the user into the builder of the very workflow they
    // are removing — behind the confirm dialog. Fails the moment the row
    // itself takes an onClick again instead of layering the overlay button.
    const onOpen = vi.fn();
    render(SUMMARY, onOpen, vi.fn());

    clickDelete();
    expect(onOpen).not.toHaveBeenCalled();
  });

  it('names the workflow it deletes, so the list stays unambiguous', () => {
    render(SUMMARY);
    expect(deleteButton().getAttribute('aria-label')).toBe(
      'Delete Review Team',
    );
  });
});
