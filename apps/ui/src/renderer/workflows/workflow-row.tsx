import { GitFork, Trash2, Workflow as WorkflowIcon } from 'lucide-react';

import type { WorkflowSummaryDto as WorkflowSummary } from '../autogenerated';
import { NavListItem } from '../components/nav-list-item';
import { Button } from '../components/ui/button';
import { cn } from '../components/ui/utils';
import { formatUpdated } from './format-updated';

/** `3 nodes` / `1 node` — count with its correctly-pluralized unit. */
function plural(count: number, unit: string): string {
  return `${count} ${unit}${count === 1 ? '' : 's'}`;
}

/**
 * Column tracks for one library row, so the numbers on every row line up the
 * way a table's would without the row being one. Each `hidden` cell drops out
 * of grid placement entirely (`display: none` is not laid out), so the widths
 * a breakpoint declares are exactly the cells it also shows — get those two
 * out of step and the shape figures slide under the timestamp.
 *
 * name/description · agent tally · shape · updated · delete
 */
const ROW_TRACKS = cn(
  '[grid-template-columns:minmax(0,1fr)_136px_84px_auto]',
  'xl:[grid-template-columns:minmax(0,1fr)_176px_136px_84px_auto]',
);

/**
 * One workflow in the library list: name and description on the left, the
 * per-agent-kind tally and the graph's shape on the right.
 *
 * A ROW rather than a tile. The library grid put four 289px cards in a 1190px
 * page and clamped every description to two lines inside them, which is where
 * the one thing that tells `Review Team` from `Bugfix Squad` was being cut —
 * while `claude ×2 · 6 nodes · 8 edges`, near-identical across a library, took
 * the space. A full-width row hands the description the width and demotes the
 * rest to a right rail.
 *
 * Activation is `NavListItem`'s: a real `<button>` layered under the content,
 * so the platform supplies Enter/Space and the delete control is a sibling of
 * that button rather than a nested interactive inside a `role="button"` div —
 * which ARIA forbids, and which needed an event dam here to stop a delete
 * click from also opening the builder of the workflow being removed.
 */
export function WorkflowRow({
  summary,
  onOpen,
  onDelete,
}: {
  summary: WorkflowSummary;
  onOpen: () => void;
  /** Asks to delete this workflow — the page confirms in a modal first. */
  onDelete: () => void;
}): React.JSX.Element {
  return (
    <NavListItem
      active={false}
      activateLabel={`Open ${summary.name}`}
      onActivate={onOpen}
      className="group rounded-none bg-card px-4 py-2.5 hover:bg-accent/40">
      <div className={cn('grid w-full min-w-0 items-center gap-4', ROW_TRACKS)}>
        <div className="flex min-w-0 flex-col gap-0.5">
          <span className="truncate text-sm font-medium">{summary.name}</span>
          {/* One line, and the full width of the row to say it in — the tile
              this replaced reserved two clamped lines whether or not there
              were two, so a one-line blurb sat over its own blank line. */}
          <span className="truncate text-xs text-muted-foreground">
            {summary.description || 'No description'}
          </span>
        </div>

        {/* Which CLIs this team is made of. Last to appear: it is the most
            interesting field when it differs and pure noise when it doesn't,
            so it yields the width before the shape figures do.

            One line of text rather than a `Badge` each: badges are a card
            idiom, and at this track width two of them wrapped to a second line
            — which grew the row and pulled the name off the shape figures
            beside it. Truncated, so a fourth agent kind shortens the line
            instead of reflowing the row. */}
        <span className="hidden truncate text-right text-xs text-muted-foreground xl:block">
          {summary.agentCounts
            .map((agent) => `${agent.kind} ×${agent.count}`)
            .join(' · ')}
        </span>

        <span className="flex items-center justify-end gap-3 text-xs text-muted-foreground tabular-nums">
          <span className="inline-flex items-center gap-1">
            <WorkflowIcon aria-hidden="true" className="size-3.5 shrink-0" />
            {plural(summary.nodeCount, 'node')}
          </span>
          <span className="inline-flex items-center gap-1">
            <GitFork aria-hidden="true" className="size-3.5 shrink-0" />
            {plural(summary.edgeCount, 'edge')}
          </span>
        </span>

        <span className="text-right text-xs text-muted-foreground">
          {formatUpdated(summary.updatedAt)}
        </span>

        <Button
          type="button"
          variant="ghost"
          size="icon"
          aria-label={`Delete ${summary.name}`}
          title="Delete workflow"
          className="size-7 text-muted-foreground opacity-0 transition-opacity hover:bg-destructive/10 hover:text-destructive focus-visible:opacity-100 group-hover:opacity-100 [&_svg]:size-3.5"
          onClick={onDelete}>
          <Trash2 />
        </Button>
      </div>
    </NavListItem>
  );
}
