// @vitest-environment jsdom
import { act } from 'react';
import { createRoot, type Root } from 'react-dom/client';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

import {
  DEV_TEAM_VERSIONS,
  NEVER_RUN_VERSIONS,
} from '../__fixtures__/workflow-versions';
import type { WorkflowVersionsDto } from '../autogenerated';
import {
  changeSummary,
  WorkflowVersionsDialog,
} from './workflow-versions-dialog';

(
  globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }
).IS_REACT_ACT_ENVIRONMENT = true;

let container: HTMLDivElement;
let root: Root;

beforeEach(() => {
  container = document.createElement('div');
  document.body.appendChild(container);
  root = createRoot(container);
});

afterEach(() => {
  act(() => root.unmount());
  container.remove();
  document.body.innerHTML = '';
});

function render(
  props: Partial<Parameters<typeof WorkflowVersionsDialog>[0]> & {
    data: WorkflowVersionsDto | null;
  },
): {
  onClose: ReturnType<typeof vi.fn>;
  onOpenThread: ReturnType<typeof vi.fn>;
  onRetry: ReturnType<typeof vi.fn>;
} {
  const onClose = vi.fn();
  const onOpenThread = vi.fn();
  const onRetry = vi.fn();
  act(() => {
    root.render(
      <WorkflowVersionsDialog
        open
        onClose={onClose}
        workflowName="Dev Team"
        loading={false}
        error={null}
        onRetry={onRetry}
        onOpenThread={onOpenThread}
        {...props}
      />,
    );
  });
  return { onClose, onOpenThread, onRetry };
}

function rows(slot: string): HTMLElement[] {
  return [
    ...document.body.querySelectorAll<HTMLElement>(`[data-slot="${slot}"]`),
  ];
}

function expand(label: string): void {
  const button = [...document.body.querySelectorAll('button')].find(
    (candidate) => candidate.getAttribute('aria-label') === label,
  );
  if (!button) {
    throw new Error(`no button ${label}`);
  }
  act(() => button.click());
}

describe('WorkflowVersionsDialog', () => {
  it('draws one row per version, the copy-less runs’ row, and the totals', () => {
    render({ data: DEV_TEAM_VERSIONS });

    const versionRows = rows('version-row');
    expect(versionRows.map((row) => row.textContent)).toEqual([
      expect.stringContaining('b7c1e09a'),
      expect.stringContaining('41aa90c3'),
      expect.stringContaining('No recorded graph'),
    ]);
    expect(versionRows[0]!.textContent).toContain('current');
    expect(versionRows[1]!.textContent).toContain('inferred');
    expect(versionRows[1]!.textContent).toContain(
      'not numbered: graph copied later',
    );
    expect(rows('versions-total')[0]!.textContent).toContain('All versions');
    expect(rows('versions-total')[0]!.textContent).toContain('$15.50');
    expect(document.body.textContent).toContain('4 runs · 2 versions');
  });

  it('shows an unmeasured figure’s reason as text, not only on hover', () => {
    render({ data: DEV_TEAM_VERSIONS });

    const inferred = rows('version-row')[1]!;
    expect(inferred.textContent).toContain('—');
    expect(inferred.textContent).toContain('not measured');
    expect(inferred.textContent).toContain('partial: deleted runs not timed');
    expect(rows('version-row')[2]!.textContent).toContain(
      'these runs kept no graph copy',
    );
  });

  it('opens a live run’s thread and closes the dialog first', () => {
    const { onClose, onOpenThread } = render({ data: DEV_TEAM_VERSIONS });
    expand('Show runs of b7c1e09a');

    const live = [...document.body.querySelectorAll('button')].find(
      (button) =>
        button.getAttribute('aria-label') ===
        'Open thread: Ship the versions table, completed',
    );
    act(() => live!.click());

    expect(onClose).toHaveBeenCalledTimes(1);
    expect(onOpenThread).toHaveBeenCalledWith('run-live');
    expect(onClose.mock.invocationCallOrder[0]).toBeLessThan(
      onOpenThread.mock.invocationCallOrder[0]!,
    );
  });

  it('draws a deleted run as text, not as a button, and keeps its cost', () => {
    render({ data: DEV_TEAM_VERSIONS });
    expand('Show runs of b7c1e09a');

    const runs = rows('version-run');
    const deleted = runs.find((run) => run.textContent?.includes('deleted'));
    expect(deleted).toBeDefined();
    expect(deleted!.tagName).not.toBe('BUTTON');
    expect(deleted!.textContent).toContain('$4.30');
  });

  it('says a workflow that never ran has no versions yet', () => {
    render({ data: NEVER_RUN_VERSIONS });

    expect(document.body.textContent).toContain(
      "This workflow hasn't run yet. Versions appear after its first run.",
    );
    expect(rows('version-row')).toEqual([]);
  });

  it('offers a retry when the read failed', () => {
    const { onRetry } = render({ data: null, error: 'boom' });

    const alert = document.body.querySelector('[role="alert"]');
    expect(alert?.textContent).toContain("Couldn't load versions");
    const retry = [...alert!.querySelectorAll('button')].find(
      (button) => button.textContent === 'Retry',
    );
    act(() => retry!.click());
    expect(onRetry).toHaveBeenCalledTimes(1);
  });

  it('marks the first load busy', () => {
    render({ data: null, loading: true });

    expect(document.body.querySelector('[aria-busy="true"]')).not.toBeNull();
  });
});

describe('changeSummary', () => {
  it('names each kind of change once, in one line', () => {
    expect(changeSummary(DEV_TEAM_VERSIONS.versions[0]!.changes!)).toBe(
      '+1 node, 1 changed, +1 edge, agents at once 2 → 3',
    );
  });
});
