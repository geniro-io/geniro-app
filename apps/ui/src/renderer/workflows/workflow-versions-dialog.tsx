function Figure({
  label,
  children,
}: {
  label: string;
  children: React.ReactNode;
}): React.JSX.Element {
  return (
    <div className="flex flex-col gap-0.5">
      <span className="text-[10px] tracking-wide text-muted-foreground uppercase">
        {label}
      </span>
      <span className="tabular-nums">{children}</span>
    </div>
  );
}

function OutcomeFigures({
  outcomes,
}: {
  outcomes: VersionOutcomes;
}): React.JSX.Element {
  return (
    <div className="grid grid-cols-2 gap-3">
      <Figure label="Runs">
        {formatCount(outcomes.runs)}
        <StatusMix statuses={outcomes.statuses} />
      </Figure>
      <Figure label="Failed nodes">
        <FailedNodes outcomes={outcomes} />
      </Figure>
      <Figure label="Cost">
        <Cost outcomes={outcomes} />
      </Figure>
      <Figure label="Turns · PRs">
        {formatCount(outcomes.totals.turns)} ·{' '}
        {formatCount(outcomes.pullRequests)}
      </Figure>
      <Figure label="Lines">
        <Lines outcomes={outcomes} />
      </Figure>
      <Figure label="Work time">
        <WorkTime outcomes={outcomes} />
      </Figure>
    </div>
  );
}

function VersionCard({
  row,
  current,
  onOpenThread,
}: {
  row: WorkflowVersionRow;
  current: boolean;
  onOpenThread?: (runId: string) => void;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const changed = changedText(row);
  return (
    <section
      data-slot="version-card"
      className="flex flex-col gap-3 rounded-xl border border-border bg-card p-4 text-xs">
      <VersionLabel row={row} current={current} />
      {changed.reason === null ? (
        <p>{changed.text}</p>
      ) : (
        <Unmeasured reason={changed.reason} />
      )}
      <p className="text-muted-foreground">{dateRange(row)}</p>
      <OutcomeFigures outcomes={row.outcomes} />
      <Button
        type="button"
        variant="outline"
        className="min-h-11"
        aria-expanded={open}
        onClick={() => setOpen((was) => !was)}>
        {open ? 'Hide runs' : 'Show runs'}
      </Button>
      {open ? <RunList runs={row.runs} onOpenThread={onOpenThread} /> : null}
    </section>
  );
}

function VersionCards({
  data,
  onOpenThread,
}: {
  data: WorkflowVersionsDto;
  onOpenThread?: (runId: string) => void;
}): React.JSX.Element {
  return (
    <div className="flex flex-col gap-3">
      <section
        data-slot="versions-total-card"
        className="flex flex-col gap-3 rounded-xl border border-border bg-muted/30 p-4 text-xs">
        <span className="font-medium">All versions</span>
        <OutcomeFigures outcomes={data.totals} />
      </section>
      {[...data.versions, ...(data.unversioned ? [data.unversioned] : [])].map(
        (row) => (
          <VersionCard
            key={row.version ?? 'unversioned'}
            row={row}
            current={
              row.version !== null && row.version === data.currentVersion
            }
            onOpenThread={onOpenThread}
          />
        ),
      )}
    </div>
  );
}

function summaryLine(data: WorkflowVersionsDto): string {
  const parts = [
    plural(data.totals.runs, 'run'),
    plural(data.versions.length, 'version'),
  ];
  if (data.totals.totals.costUsd !== null) {
    parts.push(
      `${markEstimate(formatUsd(data.totals.totals.costUsd), data.totals.totals.estimatedCostUsd)} total`,
    );
  }
  return parts.join(' · ');
}

/**
 * The open workflow's runs by graph version: what each version changed and what its runs
 * came to. Every figure is the daemon's; the dialog only lays them out.
 */
export function WorkflowVersionsDialog({
  open,
  onClose,
  workflowName,
  data,
  loading,
  error,
  onRetry,
  onOpenThread,
}: {
  open: boolean;
  onClose: () => void;
  workflowName: string;
  data: WorkflowVersionsDto | null;
  loading: boolean;
  error: string | null;
  onRetry: () => void;
  /** Opens a run's thread in Chats; the dialog closes first. */
  onOpenThread?: (runId: string) => void;
}): React.JSX.Element | null {
  const narrow = useNarrowViewport();
  const openThread = onOpenThread
    ? (runId: string): void => {
        onClose();
        onOpenThread(runId);
      }
    : undefined;

  let body: React.ReactNode;
  if (error !== null && data === null) {
    body = (
      <div role="alert" className="flex flex-col items-start gap-2 text-sm">
        <p className="font-medium">Couldn't load versions</p>
        <p className="text-xs text-muted-foreground">{error}</p>
        <Button type="button" size="sm" variant="outline" onClick={onRetry}>
          Retry
        </Button>
      </div>
    );
  } else if (data === null || loading) {
    body = (
      <div aria-busy="true" className="flex flex-col gap-2">
        <div className="h-3 w-48 animate-pulse rounded bg-muted" />
        {Array.from({ length: 6 }, (_, index) => (
          <div
            key={index}
            className="h-9 animate-pulse rounded-md bg-muted/60"
          />
        ))}
      </div>
    );
  } else if (data.totals.runs === 0) {
    body = (
      <p className="text-sm text-muted-foreground">
        This workflow hasn't run yet. Versions appear after its first run.
      </p>
    );
  } else {
    body = (
      <div className="flex flex-col gap-3">
        <div className="flex flex-col gap-0.5">
          <p className="text-sm text-muted-foreground">{summaryLine(data)}</p>
          <p className="text-xs text-muted-foreground">
            Name, description and layout edits do not create a version.
          </p>
        </div>
        {narrow ? (
          <VersionCards data={data} onOpenThread={openThread} />
        ) : (
          <VersionsTable data={data} onOpenThread={openThread} />
        )}
      </div>
    );
  }

  return (
    <Dialog
      open={open}
      onClose={onClose}
      fullScreen={narrow}
      className={narrow ? undefined : 'max-h-[85vh] max-w-[80rem]'}
      title={`Versions of ${workflowName}`}>
      {body}
    </Dialog>
  );
}
