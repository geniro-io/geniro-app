const DATE = new Intl.DateTimeFormat('en-US', {
  month: 'short',
  day: 'numeric',
  year: 'numeric',
});

/** The statuses in the order a run mix is read: settled first, live last. */
const STATUS_ORDER: readonly VersionRunStatus[] = [
  'completed',
  'failed',
  'cancelled',
  'running',
  'pending',
  'unknown',
];

/**
 * A run status's tone and word: the shared vocabulary (`RUN_STATUS_META`) for the five
 * a run can hold, and a muted `status unknown` for a deleted run never stamped.
 */
function statusMeta(status: VersionRunStatus): {
  className: string;
  label: string;
} {
  return status === 'unknown'
    ? { className: 'text-muted-foreground', label: 'status unknown' }
    : RUN_STATUS_META[status];
}

function plural(count: number, noun: string): string {
  return `${count} ${noun}${count === 1 ? '' : 's'}`;
}

/** One line naming what a version changed against the one before it. */
export function changeSummary(changes: VersionChanges): string {
  const parts: string[] = [];
  if (changes.nodesAdded.length > 0) {
    parts.push(`+${plural(changes.nodesAdded.length, 'node')}`);
  }
  if (changes.nodesRemoved.length > 0) {
    parts.push(`−${plural(changes.nodesRemoved.length, 'node')}`);
  }
  if (changes.nodesChanged.length > 0) {
    parts.push(`${changes.nodesChanged.length} changed`);
  }
  if (changes.edgesAdded.length > 0) {
    parts.push(`+${plural(changes.edgesAdded.length, 'edge')}`);
  }
  if (changes.edgesRemoved.length > 0) {
    parts.push(`−${plural(changes.edgesRemoved.length, 'edge')}`);
  }
  if (changes.maxActiveTurns) {
    parts.push(
      `agents at once ${changes.maxActiveTurns.from ?? 'no cap'} → ${changes.maxActiveTurns.to ?? 'no cap'}`,
    );
  }
  return parts.length === 0 ? 'no graph change' : parts.join(', ');
}

/** Every change spelled out, for an expanded row. */
function changeLines(changes: VersionChanges): string[] {
  const name = (node: { id: string; name: string | null }): string =>
    node.name ?? node.id;
  return [
    ...changes.nodesAdded.map((node) => `Added ${name(node)}`),
    ...changes.nodesRemoved.map((node) => `Removed ${name(node)}`),
    ...changes.nodesChanged.map(
      (node) => `Changed ${name(node)}: ${node.fields.join(', ')}`,
    ),
    ...changes.edgesAdded.map(
      (edge) => `Added ${edge.kind} edge ${edge.from} → ${edge.to}`,
    ),
    ...changes.edgesRemoved.map(
      (edge) => `Removed ${edge.kind} edge ${edge.from} → ${edge.to}`,
    ),
    ...(changes.maxActiveTurns
      ? [
          `Agents at once: ${changes.maxActiveTurns.from ?? 'no cap'} → ${changes.maxActiveTurns.to ?? 'no cap'}`,
        ]
      : []),
  ];
}

function changedText(row: WorkflowVersionRow): {
  text: string;
  reason: string | null;
} {
  if (row.version === null) {
    return { text: NOT_MEASURED, reason: 'these runs kept no graph copy' };
  }
  if (row.changes) {
    return { text: changeSummary(row.changes), reason: null };
  }
  if (row.inferred) {
    return { text: NOT_MEASURED, reason: 'not numbered: graph copied later' };
  }
  return row.ordinal === 1
    ? { text: 'first recorded version', reason: null }
    : { text: NOT_MEASURED, reason: 'previous graph not recorded' };
}

function dateRange(row: WorkflowVersionRow): string {
  const first = DATE.format(new Date(row.firstRunAt));
  const last = DATE.format(new Date(row.lastRunAt));
  return first === last ? first : `${first} – ${last}`;
}

/** A dash with the reason beside it, never behind a hover. */
function Unmeasured({ reason }: { reason: string }): React.JSX.Element {
  return (
    <span className="flex flex-col">
      <span>{NOT_MEASURED}</span>
      <span className="text-[10px] text-muted-foreground">{reason}</span>
    </span>
  );
}

function StatusMix({
  statuses,
}: {
  statuses: VersionOutcomes['statuses'];
}): React.JSX.Element {
  const present = STATUS_ORDER.filter((status) => statuses[status] > 0);
  return (
    <span className="flex flex-wrap gap-x-2 gap-y-0.5 text-[10px] text-muted-foreground">
      {present.map((status) => (
        <span key={status} className="inline-flex items-center gap-1">
          <span
            aria-hidden="true"
            className={cn(
              'size-1.5 rounded-full bg-current',
              statusMeta(status).className,
            )}
          />
          {statuses[status]} {statusMeta(status).label}
        </span>
      ))}
    </span>
  );
}

function FailedNodes({
  outcomes,
}: {
  outcomes: VersionOutcomes;
}): React.JSX.Element {
  if (outcomes.failedNodes.length === 0) {
    return <span className="text-muted-foreground">none</span>;
  }
  return (
    <span className="flex flex-col">
      {outcomes.failedNodes.map((node) => (
        <span key={node.nodeId}>
          {node.name ?? node.nodeId} ×{node.count}
        </span>
      ))}
    </span>
  );
}

function Cost({ outcomes }: { outcomes: VersionOutcomes }): React.JSX.Element {
  return outcomes.totals.costUsd === null ? (
    <Unmeasured reason="no cost reported" />
  ) : (
    <>
      {markEstimate(
        formatUsd(outcomes.totals.costUsd),
        outcomes.totals.estimatedCostUsd,
      )}
    </>
  );
}

function Lines({ outcomes }: { outcomes: VersionOutcomes }): React.JSX.Element {
  return outcomes.lines === null ? (
    <Unmeasured reason="not measured" />
  ) : (
    <>
      {formatLineCount(outcomes.lines.added, 'added')} /{' '}
      {formatLineCount(outcomes.lines.removed, 'removed')}
    </>
  );
}

function WorkTime({
  outcomes,
}: {
  outcomes: VersionOutcomes;
}): React.JSX.Element {
  if (outcomes.workedMs === null) {
    return <Unmeasured reason="not measured" />;
  }
  return (
    <span className="flex flex-col">
      <span>{formatDuration(outcomes.workedMs)}</span>
      {outcomes.workedPartial ? (
        <span className="text-[10px] text-muted-foreground">
          partial: deleted runs not timed
        </span>
      ) : null}
    </span>
  );
}

function VersionLabel({
  row,
  current,
}: {
  row: WorkflowVersionRow;
  current: boolean;
}): React.JSX.Element {
  if (row.version === null) {
    return <span className="font-medium">No recorded graph</span>;
  }
  return (
    <span className="flex flex-col gap-0.5">
      <span className="flex flex-wrap items-center gap-1.5">
        <span className="font-mono">{row.version.slice(0, 8)}</span>
        {row.ordinal !== null ? (
          <span className="text-muted-foreground">#{row.ordinal}</span>
        ) : null}
        {current ? <Badge variant="success">current</Badge> : null}
        {row.inferred ? <Badge variant="outline">inferred</Badge> : null}
      </span>
      {row.inferred ? (
        <span className="text-[10px] text-muted-foreground">
          graph copied after these runs started
        </span>
      ) : null}
    </span>
  );
}

function RunList({
  runs,
  onOpenThread,
}: {
  runs: readonly VersionRun[];
  onOpenThread?: (runId: string) => void;
}): React.JSX.Element {
  return (
    <ul className="flex flex-col gap-1">
      {runs.map((run) => {
        const title = run.title ?? 'Untitled run';
        const body = (
          <>
            <span className="min-w-0 flex-1 truncate text-left">
              {run.deleted ? 'deleted' : title}
            </span>
            <span className="text-muted-foreground">
              {DATE.format(new Date(run.createdAt))}
            </span>
            {run.status === 'unknown' ? (
              <span className={statusMeta(run.status).className}>
                {statusMeta(run.status).label}
              </span>
            ) : (
              <RunStatusBadge status={run.status} />
            )}
            <span className="w-16 text-right tabular-nums">
              {run.costUsd === null
                ? NOT_MEASURED
                : markEstimate(
                    formatUsd(run.costUsd),
                    run.estimated ? run.costUsd : null,
                  )}
            </span>
          </>
        );
        return (
          <li key={run.runId}>
            {run.deleted || !onOpenThread ? (
              <div
                data-slot="version-run"
                className="flex items-center gap-2 px-2 py-1.5 text-xs">
                {body}
              </div>
            ) : (
              <button
                type="button"
                data-slot="version-run"
                aria-label={`Open thread: ${title}, ${statusMeta(run.status).label}`}
                className="flex min-h-11 w-full items-center gap-2 rounded-md px-2 py-1.5 text-xs hover:bg-muted/40 focus-visible:ring-2 focus-visible:ring-ring/50 focus-visible:outline-none sm:min-h-0"
                onClick={() => onOpenThread(run.runId)}>
                {body}
              </button>
            )}
          </li>
        );
      })}
    </ul>
  );
}

const COLUMNS = 10;

function VersionTableRow({
  row,
  current,
  onOpenThread,
}: {
  row: WorkflowVersionRow;
  current: boolean;
  onOpenThread?: (runId: string) => void;
}): React.JSX.Element {
  const [open, setOpen] = useState(false);
  const changed = changedText(row);
  const outcomes = row.outcomes;
  return (
    <>
      <TableRow data-slot="version-row">
        <TableCell>
          <span className="flex items-start gap-1">
            <Button
              type="button"
              variant="ghost"
              size="icon"
              className="size-6 shrink-0"
              aria-expanded={open}
              aria-label={`${open ? 'Hide' : 'Show'} runs of ${row.version?.slice(0, 8) ?? 'runs with no recorded graph'}`}
              onClick={() => setOpen((was) => !was)}>
              {open ? (
                <ChevronDown className="size-3.5" />
              ) : (
                <ChevronRight className="size-3.5" />
              )}
            </Button>
            <VersionLabel row={row} current={current} />
          </span>
        </TableCell>
        <TableCell className="max-w-64">
          {changed.reason === null ? (
            <span className="block truncate" title={changed.text}>
              {changed.text}
            </span>
          ) : (
            <Unmeasured reason={changed.reason} />
          )}
        </TableCell>
        <TableCell className="whitespace-nowrap">{dateRange(row)}</TableCell>
        <TableCell>
          <span className="flex flex-col">
            <span>{formatCount(outcomes.runs)}</span>
            <StatusMix statuses={outcomes.statuses} />
          </span>
        </TableCell>
        <TableCell>
          <FailedNodes outcomes={outcomes} />
        </TableCell>
        <TableCell align="right">
          <Cost outcomes={outcomes} />
        </TableCell>
        <TableCell align="right">
          {formatCount(outcomes.totals.turns)}
        </TableCell>
        <TableCell align="right">
          {formatCount(outcomes.pullRequests)}
        </TableCell>
        <TableCell align="right" className="whitespace-nowrap">
          <Lines outcomes={outcomes} />
        </TableCell>
        <TableCell align="right">
          <WorkTime outcomes={outcomes} />
        </TableCell>
      </TableRow>
      {open ? (
        <TableRow>
          <TableCell colSpan={COLUMNS} className="bg-muted/20">
            {row.changes ? (
              <ul className="mb-2 flex flex-col gap-0.5 text-muted-foreground">
                {changeLines(row.changes).map((line) => (
                  <li key={line}>{line}</li>
                ))}
              </ul>
            ) : null}
            <RunList runs={row.runs} onOpenThread={onOpenThread} />
          </TableCell>
        </TableRow>
      ) : null}
    </>
  );
}

