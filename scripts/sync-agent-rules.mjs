#!/usr/bin/env node
/**
 * Generate each agent's copy of the repository rules and guides:
 *
 * - `.cursor/rules/<name>.mdc` from each `.claude/rules/<name>.md`, for Cursor.
 * - `.agents/skills/rule-<name>/SKILL.md` from each rule, and
 *   `.agents/skills/guide-<dir>/SKILL.md` for each nested `AGENTS.md`, for
 *   Codex. Codex reads only the `AGENTS.md` files from the repository root
 *   down to where it started, so from the root it never meets a rule or a
 *   nested guide; it does list every skill under `.agents/skills/` by name,
 *   description and path, and reads one when its description fits the work.
 *
 *   node scripts/sync-agent-rules.mjs           write the files
 *   node scripts/sync-agent-rules.mjs --check   fail if one is missing, stale or extra
 *
 * Claude Code reads only `paths:` from a rule; Cursor ignores `paths:` and
 * types a rule by `alwaysApply`, then `globs`, then `description`, with a
 * line-based parser (one-line values, a list only under `globs:`). So each
 * rule is translated: `description` → `description`, `paths` → `globs: a, b`
 * plus `alwaysApply: false`, no `paths` → `alwaysApply: true`; the body is
 * copied verbatim. A Codex skill takes `name` and `description` only, so its
 * description names the paths the rule applies to. The source frontmatter may
 * hold only a one-line `description:` and a `paths:` block list with no brace
 * group (Cursor splits `globs` on commas); anything else fails, naming the
 * file.
 *
 * Every generated file carries the GENERATED line below. The script deletes
 * only files that carry it, and refuses one without it (or a symlink) rather
 * than overwrite it; a hand-written skill beside the generated ones is left
 * alone. The files are committed, not generated at install time, because
 * Cursor's cloud agents, Bugbot and Codex cloud read the repo tree.
 * Dependency-free but for `git`; CI's Build and Lint job and `pnpm full-check`
 * run `--check`.
 */
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const check = args.includes('--check');
if (args.some((a) => a !== '--check')) {
  console.error('usage: node scripts/sync-agent-rules.mjs [--check]');
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = '.claude/rules';
const CURSOR_DIR = '.cursor/rules';
const SKILLS_DIR = '.agents/skills';
const MARKER = '<!-- GENERATED by scripts/sync-agent-rules.mjs';
const marker = (source) =>
  `${MARKER} from ${source}. DO NOT EDIT: edit the source, then run \`pnpm sync:agent-rules\`. -->`;
const isGenerated = (text) =>
  text.split('\n').some((line) => line.startsWith(MARKER));

const errors = [];

/** One YAML scalar on one line: plain, "double-quoted" or 'single-quoted'. */
function scalar(raw) {
  if (raw.startsWith('"')) {
    try {
      return JSON.parse(raw);
    } catch {
      return undefined;
    }
  }
  if (raw.startsWith("'")) {
    return raw.length > 1 && raw.endsWith("'")
      ? raw.slice(1, -1).replaceAll("''", "'")
      : undefined;
  }
  return raw;
}

/** The rule's frontmatter fields and body, or undefined after recording why. */
function parseRule(file, text) {
  const fail = (why) => {
    errors.push(`${file}: ${why}`);
    return undefined;
  };
  const lines = text.split('\n');
  const fence = (line) => line.replace(/\r$/, '') === '---';
  const end = lines.findIndex((line, i) => i > 0 && fence(line));
  if (!fence(lines[0]) || end === -1) {
    return fail('no frontmatter; it needs a one-line `description:`');
  }
  let description;
  let paths;
  let key;
  for (const raw of lines.slice(1, end)) {
    const line = raw.replace(/\r$/, '');
    if (line.trim() === '' || line.trimStart().startsWith('#')) continue;
    const item = line.match(/^\s+-\s+(.*)$/);
    if (/^\s/.test(line)) {
      if (key === 'paths' && item) {
        const path = scalar(item[1].trim());
        if (path === undefined) return fail(`cannot read path ${item[1]}`);
        if (/[{}]/.test(path)) {
          return fail(
            `path "${path}" has a brace group; Cursor splits globs on commas, so list each pattern on its own line`,
          );
        }
        if (path.includes(',')) {
          return fail(
            `path "${path}" has a comma; Cursor splits globs on commas`,
          );
        }
        paths.push(path);
        continue;
      }
      if (key === 'description') {
        return fail('`description` spans more than one line');
      }
      return fail(`cannot read frontmatter line "${line}"`);
    }
    const field = line.match(/^([^:\s]+):\s*(.*)$/);
    if (!field) return fail(`cannot read frontmatter line "${line}"`);
    [, key] = field;
    const value = field[2].trim();
    if (key === 'description') {
      if (value === '' || /^[|>]/.test(value)) {
        return fail('`description` spans more than one line');
      }
      description = scalar(value);
      if (description === undefined || description.includes('\n')) {
        return fail('`description` spans more than one line');
      }
    } else if (key === 'paths') {
      if (value !== '') {
        return fail('write `paths` as a block list, one `- "pattern"` a line');
      }
      paths = [];
    } else {
      return fail(
        `unsupported key \`${key}\`; only \`description\` and \`paths\` are allowed`,
      );
    }
  }
  if (description === undefined || description.trim() === '') {
    return fail('`description` is missing');
  }
  if (paths?.length === 0) return fail('`paths` is empty');
  const body = lines.slice(end + 1).join('\n');
  return { description, paths: paths ?? [], body };
}

function cursorRule(name, rule) {
  const source = `${SOURCE_DIR}/${name}.md`;
  const frontmatter = [`description: ${rule.description}`];
  if (rule.paths.length > 0) {
    frontmatter.push(`globs: ${rule.paths.join(', ')}`, 'alwaysApply: false');
  } else {
    frontmatter.push('alwaysApply: true');
  }
  return `---\n${frontmatter.join('\n')}\n---\n${marker(source)}\n${rule.body}`;
}

function skill(name, description, source, body) {
  return `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n${marker(source)}\n${body}`;
}

function ruleSkill(name, rule) {
  const scope =
    rule.paths.length === 0
      ? 'A repository rule for every change; read it before you start.'
      : `A repository rule for ${rule.paths.join(', ')}; read it before editing a file there.`;
  return skill(
    `rule-${name}`,
    `${rule.description.replace(/\.?$/, '.')} ${scope}`,
    `${SOURCE_DIR}/${name}.md`,
    rule.body,
  );
}

function guideSkill(guide) {
  const dir = dirname(guide);
  return skill(
    `guide-${dir.replaceAll('/', '-').replace(/^apps-/, '')}`,
    `The ${dir}/ guide (${guide}): its invariants and conventions. Read it whole before working under ${dir}/.`,
    guide,
    `\nRead \`${guide}\` in full before changing anything under \`${dir}/\`. Codex started at the repository root does not load it on its own, and the root \`AGENTS.md\` holds only what is shared across the repository.\n`,
  );
}

/** Every `AGENTS.md` git tracks below the root. */
function nestedGuides() {
  return execFileSync('git', ['ls-files', '--', '*/AGENTS.md'], {
    cwd: root,
    encoding: 'utf8',
  })
    .split('\n')
    .filter((path) => path !== '' && !path.startsWith('packages/'))
    .sort();
}

// What the sources say each target should hold, keyed by path from the root.
const expected = new Map();
const sourceDir = join(root, SOURCE_DIR);
for (const file of readdirSync(sourceDir).sort()) {
  if (!file.endsWith('.md')) continue;
  const name = file.slice(0, -'.md'.length);
  const rule = parseRule(
    `${SOURCE_DIR}/${file}`,
    readFileSync(join(sourceDir, file), 'utf8'),
  );
  if (rule) {
    expected.set(`${CURSOR_DIR}/${name}.mdc`, cursorRule(name, rule));
    expected.set(`${SKILLS_DIR}/rule-${name}/SKILL.md`, ruleSkill(name, rule));
  }
}
for (const guide of nestedGuides()) {
  const text = guideSkill(guide);
  const name = text.match(/^name: (.*)$/m)[1];
  expected.set(`${SKILLS_DIR}/${name}/SKILL.md`, text);
}

// What the targets hold now: Cursor reads `.cursor/rules/**/*.mdc`, Codex
// `.agents/skills/*/SKILL.md`.
const present = new Map();
const extra = [];
function scan(dir, matches) {
  const full = join(root, dir);
  if (!existsSync(full)) return;
  for (const file of readdirSync(full, { recursive: true }).sort()) {
    if (!matches(file)) continue;
    const path = join(full, file);
    const shown = `${dir}/${file}`;
    if (lstatSync(path).isSymbolicLink()) {
      errors.push(
        `${shown}: a symlink, not a generated file; delete it and run \`pnpm sync:agent-rules\``,
      );
      continue;
    }
    if (!lstatSync(path).isFile()) continue;
    const text = readFileSync(path, 'utf8');
    if (!isGenerated(text)) {
      if (dir === CURSOR_DIR || expected.has(shown)) {
        errors.push(
          `${shown}: hand-written (no GENERATED line); move it into ${SOURCE_DIR}/ or delete it`,
        );
      }
      continue;
    }
    if (expected.has(shown)) present.set(shown, text);
    else extra.push(shown);
  }
}
scan(CURSOR_DIR, (file) => file.endsWith('.mdc'));
scan(SKILLS_DIR, (file) => /^[^/]+\/SKILL\.md$/.test(file));

const targets = `${CURSOR_DIR}/ and ${SKILLS_DIR}/`;
if (errors.length > 0) {
  console.error(`${targets} were not ${check ? 'checked' : 'written'}:`);
  for (const error of errors) console.error(`  - ${error}`);
  process.exit(1);
}

const missing = [...expected.keys()].filter((path) => !present.has(path));
const stale = [...present.keys()].filter(
  (path) => present.get(path) !== expected.get(path),
);

if (check) {
  if (missing.length + stale.length + extra.length > 0) {
    console.error(
      `${targets} have drifted from their sources; run \`pnpm sync:agent-rules\` and commit the result:`,
    );
    for (const path of missing) console.error(`  - ${path} is missing`);
    for (const path of stale) console.error(`  - ${path} is stale`);
    for (const path of extra) {
      console.error(`  - ${path} has no rule or guide behind it`);
    }
    process.exit(1);
  }
  console.log(`${targets}: ${expected.size} files, each up to date.`);
  process.exit(0);
}

for (const path of [...missing, ...stale]) {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), expected.get(path));
  console.log(`wrote   ${path}`);
}
for (const path of extra) {
  rmSync(join(root, path));
  const parent = dirname(join(root, path));
  if (path.startsWith(`${SKILLS_DIR}/`) && readdirSync(parent).length === 0) {
    rmSync(parent, { recursive: true });
  }
  console.log(`deleted ${path}`);
}
console.log(`${targets}: ${expected.size} files, each up to date.`);
