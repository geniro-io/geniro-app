#!/usr/bin/env node
/**
 * Generate `.cursor/rules/<name>.mdc` from each `.claude/rules/<name>.md`.
 *
 *   node scripts/sync-cursor-rules.mjs           write the files
 *   node scripts/sync-cursor-rules.mjs --check   fail if one is missing, stale or extra
 *
 * Claude Code reads only `paths:` from a rule; Cursor ignores `paths:` and
 * types a rule by `alwaysApply`, then `globs`, then `description`, with a
 * line-based parser (one-line values, a list only under `globs:`). So each
 * rule is translated: `description` → `description`, `paths` → `globs: a, b`
 * plus `alwaysApply: false`, no `paths` → `alwaysApply: true`; the body is
 * copied verbatim. The source frontmatter may hold only a one-line
 * `description:` and a `paths:` block list with no brace group (Cursor splits
 * `globs` on commas); anything else fails, naming the file.
 *
 * Every generated file carries the GENERATED line below. The script deletes
 * only `.mdc` files that carry it, and refuses one without it (or a symlink)
 * rather than overwrite it. The files are committed, not generated at install
 * time, because Cursor's cloud agents and Bugbot read the repo tree.
 * Dependency-free; CI's Build and Lint job and `pnpm full-check` run `--check`.
 */
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const check = args.includes('--check');
if (args.some((a) => a !== '--check')) {
  console.error('usage: node scripts/sync-cursor-rules.mjs [--check]');
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = '.claude/rules';
const TARGET_DIR = '.cursor/rules';
const MARKER = '<!-- GENERATED by scripts/sync-cursor-rules.mjs';
const marker = (source) =>
  `${MARKER} from ${source}. DO NOT EDIT: edit the source, then run \`pnpm sync:cursor-rules\`. -->`;
const isGenerated = (text) =>
  text.split('\n').some((line) => line.startsWith(MARKER));

const errors = [];

/** One YAML scalar on one line: plain, "double-quoted" or 'single-quoted'. */
function scalar(raw) {
  if (raw.startsWith('"')) {
    try {
      return JSON.parse(raw);
    } catch {
      return undefined;
    }
  }
  if (raw.startsWith("'")) {
    return raw.length > 1 && raw.endsWith("'")
      ? raw.slice(1, -1).replaceAll("''", "'")
      : undefined;
  }
  return raw;
}

/** The rule's frontmatter fields and body, or undefined after recording why. */
function parseRule(file, text) {
  const fail = (why) => {
    errors.push(`${file}: ${why}`);
    return undefined;
  };
  const lines = text.split('\n');
  const fence = (line) => line.replace(/\r$/, '') === '---';
  const end = lines.findIndex((line, i) => i > 0 && fence(line));
  if (!fence(lines[0]) || end === -1) {
    return fail('no frontmatter; it needs a one-line `description:`');
  }
  let description;
  let paths;
  let key;
  for (const raw of lines.slice(1, end)) {
    const line = raw.replace(/\r$/, '');
    if (line.trim() === '' || line.trimStart().startsWith('#')) continue;
    const item = line.match(/^\s+-\s+(.*)$/);
    if (/^\s/.test(line)) {
      if (key === 'paths' && item) {
        const path = scalar(item[1].trim());
        if (path === undefined) return fail(`cannot read path ${item[1]}`);
        if (/[{}]/.test(path)) {
          return fail(
            `path "${path}" has a brace group; Cursor splits globs on commas, so list each pattern on its own line`,
          );
        }
        if (path.includes(',')) {
          return fail(
            `path "${path}" has a comma; Cursor splits globs on commas`,
          );
        }
        paths.push(path);
        continue;
      }
      if (key === 'description') {
        return fail('`description` spans more than one line');
      }
      return fail(`cannot read frontmatter line "${line}"`);
    }
    const field = line.match(/^([^:\s]+):\s*(.*)$/);
    if (!field) return fail(`cannot read frontmatter line "${line}"`);
    [, key] = field;
    const value = field[2].trim();
    if (key === 'description') {
      if (value === '' || /^[|>]/.test(value)) {
        return fail('`description` spans more than one line');
      }
      description = scalar(value);
      if (description === undefined || description.includes('\n')) {
        return fail('`description` spans more than one line');
      }
    } else if (key === 'paths') {
      if (value !== '') {
        return fail('write `paths` as a block list, one `- "pattern"` a line');
      }
      paths = [];
    } else {
      return fail(
        `unsupported key \`${key}\`; only \`description\` and \`paths\` are allowed`,
      );
    }
  }
  if (description === undefined || description.trim() === '') {
    return fail('`description` is missing');
  }
  if (paths?.length === 0) return fail('`paths` is empty');
  const body = lines.slice(end + 1).join('\n');
  return { description, paths: paths ?? [], body };
}

function generate(name, rule) {
  const source = `${SOURCE_DIR}/${name}.md`;
  const frontmatter = [`description: ${rule.description}`];
  if (rule.paths.length > 0) {
    frontmatter.push(`globs: ${rule.paths.join(', ')}`, 'alwaysApply: false');
  } else {
    frontmatter.push('alwaysApply: true');
  }
  return `---\n${frontmatter.join('\n')}\n---\n${marker(source)}\n${rule.body}`;
}

// What .claude/rules/ says .cursor/rules/ should hold, keyed by relative path.
const expected = new Map();
const sourceDir = join(root, SOURCE_DIR);
for (const file of readdirSync(sourceDir).sort()) {
  if (!file.endsWith('.md')) continue;
  const name = file.slice(0, -'.md'.length);
  const rule = parseRule(
    `${SOURCE_DIR}/${file}`,
    readFileSync(join(sourceDir, file), 'utf8'),
  );
  if (rule) expected.set(`${name}.mdc`, generate(name, rule));
}

// What .cursor/rules/ holds now. Cursor reads `.cursor/rules/**/*.mdc`.
const targetDir = join(root, TARGET_DIR);
const present = new Map();
const extra = [];
if (existsSync(targetDir)) {
  for (const file of readdirSync(targetDir, { recursive: true }).sort()) {
    if (!file.endsWith('.mdc')) continue;
    const path = join(targetDir, file);
    const shown = `${TARGET_DIR}/${file}`;
    if (lstatSync(path).isSymbolicLink()) {
      errors.push(
        `${shown}: a symlink, not a generated file; delete it and run \`pnpm sync:cursor-rules\``,
      );
      continue;
    }
    if (!lstatSync(path).isFile()) continue;
    const text = readFileSync(path, 'utf8');
    if (!isGenerated(text)) {
      errors.push(
        `${shown}: hand-written (no GENERATED line); move it into ${SOURCE_DIR}/ or delete it`,
      );
      continue;
    }
    if (expected.has(file)) present.set(file, text);
    else extra.push(file);
  }
}

if (errors.length > 0) {
  console.error(`${TARGET_DIR}/ was not ${check ? 'checked' : 'written'}:`);
  for (const error of errors) console.error(`  - ${error}`);
  process.exit(1);
}

const missing = [...expected.keys()].filter((file) => !present.has(file));
const stale = [...present.keys()].filter(
  (file) => present.get(file) !== expected.get(file),
);

if (check) {
  if (missing.length + stale.length + extra.length > 0) {
    console.error(
      `${TARGET_DIR}/ has drifted from ${SOURCE_DIR}/; run \`pnpm sync:cursor-rules\` and commit the result:`,
    );
    for (const file of missing)
      console.error(`  - ${TARGET_DIR}/${file} is missing`);
    for (const file of stale)
      console.error(`  - ${TARGET_DIR}/${file} is stale`);
    for (const file of extra) {
      console.error(`  - ${TARGET_DIR}/${file} has no rule behind it`);
    }
    process.exit(1);
  }
  console.log(`${TARGET_DIR}/: ${expected.size} rules, each up to date.`);
  process.exit(0);
}

mkdirSync(targetDir, { recursive: true });
for (const file of [...missing, ...stale]) {
  writeFileSync(join(targetDir, file), expected.get(file));
  console.log(`wrote   ${TARGET_DIR}/${file}`);
}
for (const file of extra) {
  rmSync(join(targetDir, file));
  console.log(`deleted ${TARGET_DIR}/${file}`);
}
console.log(`${TARGET_DIR}/: ${expected.size} rules, each up to date.`);
